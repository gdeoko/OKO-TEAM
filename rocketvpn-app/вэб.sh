#!/bin/bash
# Одна команда на боевом веб-сервере Rocket VPN, через мост VPS.
#
# Путь до него в два прыжка, и это не прихоть: из облачной сессии хост
# 217.19.122.132 напрямую недоступен, а VPS до него ходит. Пароль живёт
# в мастер-хранилище на VPS и в этот файл НЕ попадает: репозиторий
# открытый, и однажды пароль тут уже лежал открытым текстом.
#
#   bash вэб.sh 'ls -la /var/www/rocketvpn'
set -u
V=/tmp/cab/v.sh
[ -x "$V" ] || { echo "нет моста $V"; exit 1; }
[ $# -ge 1 ] || { echo "нечего выполнять"; exit 1; }

# Команда уезжает в base64: внутри неё бывают кавычки, доллары и
# переводы строк, и каждый слой (мост, ssh, оболочка) норовит их
# развернуть по-своему. Base64 переживает все три слоя без потерь.
CMD_B64=$(printf '%s' "$1" | base64 -w0)

"$V" 'VAULT=/opt/oko-poster/cfg/OKO_MASTER_VAULT.md
PW=$(grep -m1 -E "^\| *Вход *\| *ubuntu */" "$VAULT" | sed -E "s#.*ubuntu */ *([^ (|]+).*#\1#")
[ -n "$PW" ] || { echo "пароль не найден в хранилище"; exit 1; }
sshpass -p "$PW" ssh -o StrictHostKeyChecking=no -o ConnectTimeout=20 ubuntu@217.19.122.132 "echo '"$CMD_B64"' | base64 -d | bash -s" 2>&1'
