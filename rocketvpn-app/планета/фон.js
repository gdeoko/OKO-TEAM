/* ЖИВОЙ ФОН: ВИДЕО ВМЕСТО НАРИСОВАННОГО МИРА

   Слово Даниэля: фон как на концептах, один в один, и живой. Кодом
   такой фотореализм на телефоне не нарисовать, поэтому фон это
   оживлённое видео (Veo 3.1, петля восемь секунд), а всё, чем человек
   пользуется, остаётся кодом поверх: стекло, кнопки, список, след по
   пингам.

   Звука у фона нет. Клиент послушал и сказал: «их лучше вообще убрать».

   ── ФОН ИДЁТ МЕДЛЕННЕЕ, ЧЕМ СНЯТ ──────────────────────────────────
   Второе слово клиента: «много динамики очень». Клип играет на ТЕМП от
   своей скорости: вода, облака и сияние остаются живыми, но дышат, а не
   бегут. Премиальный фон не отвлекает от кнопки, он её подсвечивает.

   У каждой темы два клипа, утро и вечер. Утро с 6:00 до 18:00 по часам
   телефона, вечер с 18:00 до 6:00. Смена идёт сама, плавным переходом.

   Модуль отвечает тем же именем МИР, что и прежний 3D-движок, и тем же
   набором вызовов: экран.js зовёт МИР.тема, МИР.сказать, МИР.источник и
   не знает, чем нарисован фон.

   ── ФОН ПРИБИТ К КНОПКЕ, А НЕ К ЭКРАНУ ─────────────────────────────
   В концепте солнце стоит за кнопкой, аврора обнимает её кольцом,
   гроза встаёт справа от неё. Экраны телефонов разной высоты, и при
   обычном «cover» эти пары расходятся: на высоком телефоне солнце
   уезжает из-за кнопки под логотип. Поэтому у каждого клипа записана
   точка кадра, которая обязана стоять в центре кнопки (якорь), и кадр
   двигается и масштабируется так, чтобы якорь сел туда, а края экрана
   остались закрыты. */
(function (g) {
  "use strict";

  var КОРЕНЬ = "ассеты/фон/";
  var ТЕМП = 0.55;
  /* Один формат на всех: H.264 в mp4 играет любой телефон и любой браузер,
     включая iPhone. Второй файл в webm удваивал вес папки ради сборок
     Chromium без закрытых кодеков, а таких у людей нет: на стенде вместо
     видео честно показывается постер, то есть первый кадр того же клипа. */

  /* Точки в долях кадра 9:16. якорь - что стоит в центре кнопки,
     исток - откуда в фоне выходит след замера (молния из грозы, вода
     из солнечной дорожки, огонь из факела). */
  var КЛИПЫ = {
    "океан-утро":  { якорь: [.50, .270], исток: [.50, .330] },
    "океан-вечер": { якорь: [.50, .268], исток: [.50, .372] },
    "космос-утро": { якорь: [.50, .190], исток: [.50, .318] },
    "космос-вечер":{ якорь: [.50, .300], исток: [.83, .300] },
    /* Солнце рассвета сидит на верхней кромке линзы. В её центре
       белый блик прямо под словом «Подключиться» съедал надпись. Исток
       следа там, где солнечная дорожка выходит из-под линзы. */
    "полёт-утро":  { якорь: [.50, .350], исток: [.50, .452] },
    "полёт-вечер": { якорь: [.50, .210], исток: [.83, .560] }
  };
  /* Имена тем в приложении прежние (планета, океан, ракета): под ними
     уже лежат выбор человека в памяти телефона, иконки и цвета. */
  var ТЕМА_В_КЛИП = { планета: "космос", океан: "океан", ракета: "полёт" };

  var МИР = g.МИР = {
    жив: false, готов: false, якоря: null,
    тема: тема, сказать: сказать, источник: источник,
    обновитьЯкоря: разложить, текущая: function () { return текущаяТема; },
    заморозить: заморозить, пора: пора, клип: function () { return текущийКлип; }
  };

  var телефон = null, слой = null, видео = [], активное = 0;
  var текущаяТема = null, текущийКлип = null, раскладка = null;
  var снимок = false, стоп = false;

  /* Утро с 6:00 до 17:59, вечер с 18:00 до 5:59. Для проверки можно
     прибить время суток адресом ?пора=утро или ?пора=вечер. */
  function пора() {
    var п = null;
    try { п = (decodeURIComponent(g.location.search).match(/[?&]пора=([^&]+)/) || [])[1]; } catch (о) {}
    if (п === "утро" || п === "вечер") return п;
    var ч = new Date().getHours();
    return ч >= 6 && ч < 18 ? "утро" : "вечер";
  }

  function имяКлипа(т) { return (ТЕМА_В_КЛИП[т] || "космос") + "-" + пора(); }

  function завести() {
    телефон = document.getElementById("телефон");
    if (!телефон) return false;
    слой = document.createElement("div");
    слой.className = "фон-видео";
    слой.setAttribute("aria-hidden", "true");
    for (var i = 0; i < 2; i++) {
      var в = document.createElement("video");
      в.muted = true; в.defaultMuted = true; в.loop = true;
      в.playsInline = true; в.setAttribute("playsinline", ""); в.setAttribute("webkit-playsinline", "");
      в.setAttribute("muted", ""); в.preload = "auto";
      в.className = "фон-клип";
      слой.appendChild(в);
      видео.push(в);
    }
    телефон.insertBefore(слой, телефон.firstChild);
    document.documentElement.classList.add("фон-живой");
    МИР.жив = true; МИР.готов = true;

    var тянуть = null;
    g.addEventListener("resize", function () { clearTimeout(тянуть); тянуть = setTimeout(разложить, 100); });
    /* Раз в минуту сверяем время суток: приложение открыто в 17:59 и
       не трогается, а в 18:00 фон уходит в вечер сам. */
    setInterval(function () { if (текущаяТема && имяКлипа(текущаяТема) !== текущийКлип) показать(имяКлипа(текущаяТема)); }, 60000);
    /* Свёрнутое приложение не должно крутить видео и греть телефон. */
    document.addEventListener("visibilitychange", function () {
      var в = видео[активное];
      if (document.hidden) в.pause();
      else if (!стоп && !снимок) играть(в);
    });
    return true;
  }

  /* Скорость ставится перед каждым запуском: после смены src браузер
     сбрасывает её на единицу, и клип вдруг бежал бы вдвое быстрее. */
  function играть(в) {
    в.defaultPlaybackRate = ТЕМП; в.playbackRate = ТЕМП;
    try { var п = в.play(); if (п && п.catch) п.catch(function () {}); } catch (о) {}
  }

  function тема(имя) {
    текущаяТема = имя;
    if (!слой && !завести()) return;
    показать(имяКлипа(имя));
  }

  /* Новый клип встаёт во второй видеослой и проявляется поверх старого,
     когда у него есть первый кадр. Резкая подмена дала бы чёрный кадр
     между клипами. Постер (первый кадр картинкой) показывается сразу. */
  function показать(клип) {
    if (клип === текущийКлип) return;
    текущийКлип = клип;
    document.documentElement.setAttribute("data-пора", /утро$/.test(клип) ? "утро" : "вечер");
    var след = 1 - активное, в = видео[след], было = видео[активное];
    в.poster = КОРЕНЬ + клип + ".webp";
    в.src = КОРЕНЬ + клип + ".mp4";
    в.setAttribute("data-клип", клип);
    разложить();
    var проявить = function () {
      в.removeEventListener("loadeddata", проявить);
      в.playbackRate = ТЕМП;
      в.classList.add("виден");
      было.classList.remove("виден");
      setTimeout(function () { if (!было.classList.contains("виден")) { было.pause(); } }, 1400);
    };
    /* Постер уже есть - проявляем сразу, видео догонит в том же слое. */
    в.classList.add("виден");
    было.classList.remove("виден");
    в.addEventListener("loadeddata", проявить);
    if (!снимок && !стоп) играть(в);
    активное = след;
  }
  /* «Движение» выключено - фон стоит первым кадром: человек, которому
     мешает движение, не должен получать его от фона. */
  МИР.движение = function (вкл) {
    стоп = !вкл;
    var в = видео[активное];
    if (!в) return;
    if (стоп) в.pause(); else if (!снимок) играть(в);
  };

  /* ── РАСКЛАДКА ────────────────────────────────────────────────────
     Кадр 1080x1920. Масштаб берётся наименьший из тех, при которых
     якорь садится в центр кнопки и экран закрыт целиком. */
  function разложить() {
    if (!слой || !текущийКлип) return;
    var т = телефон.getBoundingClientRect();
    var Ш = т.width, В = т.height;
    /* Центр кнопки считается по разметке, цепочкой offsetParent.
       getBoundingClientRect для этого не годится: он учитывает
       transform: пока раздел или кнопка в движении, центр выходил на
       несколько точек ниже настоящего, и весь фон вставал мимо якоря -
       солнце и аврора съезжали из-за линзы скачком. */
    var кн = document.querySelector("#пуск .ядро");
    var видна = !!(кн && кн.offsetWidth > 0);
    var цх = Ш / 2, цу = В * .157;
    if (видна) {
      var x = 0, y = 0;
      for (var у = кн; у && у !== телефон; у = у.offsetParent) { x += у.offsetLeft; y += у.offsetTop; }
      цх = x + кн.offsetWidth / 2;
      цу = y + кн.offsetHeight / 2;
    }
    /* Кнопки на экране нет (раздел «Серверы») - держим прежнюю
       раскладку: фон, прыгающий при смене раздела, читался бы поломкой. */
    if (!видна && раскладка) return применить();
    var к = КЛИПЫ[текущийКлип] || { якорь: [.5, .2] };
    var ах = к.якорь[0], ау = к.якорь[1];
    var вш = 1080, вв = 1920;
    var м = Math.max(Ш / вш, В / вв);
    /* якорь по вертикали: сверху не должно быть щели, снизу тоже */
    if (ау > 0) м = Math.max(м, цу / (ау * вв));
    if (ау < 1) м = Math.max(м, (В - цу) / ((1 - ау) * вв));
    if (ах > 0) м = Math.max(м, цх / (ах * вш));
    if (ах < 1) м = Math.max(м, (Ш - цх) / ((1 - ах) * вш));
    раскладка = { м: м, x: цх - ах * вш * м, y: цу - ау * вв * м, ш: вш * м, в: вв * м };
    применить();
    МИР.якоря = { ширина: Ш, высота: В, кнопка: { x: цх, y: цу, видна: !!видна }, фон: раскладка };
  }
  function применить() {
    var р = раскладка;
    видео.forEach(function (в) {
      в.style.width = р.ш + "px"; в.style.height = р.в + "px";
      в.style.transform = "translate3d(" + р.x.toFixed(2) + "px," + р.y.toFixed(2) + "px,0)";
    });
  }

  /* Точка в css-точках телефона, откуда выходит след замера. */
  function источник() {
    if (!раскладка || !текущийКлип) return null;
    var к = КЛИПЫ[текущийКлип];
    if (!к) return null;
    return { x: раскладка.x + к.исток[0] * раскладка.ш, y: раскладка.y + к.исток[1] * раскладка.в };
  }

  /* Отклик фона на интерфейс. Сам клип не меняется, свет отвечает
     один раз, на начале удара: исток следа коротко вспыхивает. Удар
     шлёт начало и конец, и прежде вспышка шла на оба, то есть дважды
     на каждый замер. Подключение фон больше не осветляет: светлая
     сцена под списком съедала контраст строк на всё время сессии, а
     подключение и так видно по зелёному ободу, слову и таймеру. */
  function сказать(событие, данные) {
    if (!слой) return;
    if (событие === "удар" && (!данные || данные.фаза === "начало")) {
      слой.classList.remove("вспышка"); void слой.offsetWidth; слой.classList.add("вспышка");
    }
  }

  /* Для сборщика кадров: встать на заданную секунду и не играть. */
  function заморозить(t) {
    снимок = true;
    var в = видео[активное];
    return new Promise(function (готово) {
      var встать = function () {
        в.pause();
        var д = в.duration || 10;
        var на = Math.max(0, Math.min(д - .05, t % д));
        var ок = function () { в.removeEventListener("seeked", ок); готово(true); };
        в.addEventListener("seeked", ок);
        в.currentTime = на;
        setTimeout(function () { готово(false); }, 4000);
      };
      if (в.readyState >= 1) встать();
      else {
        в.addEventListener("loadedmetadata", встать, { once: true });
        /* Видео нет (не доехало, не тот кодек) - на экране постер, его
           и снимаем, а не ждём вечно. */
        setTimeout(function () { готово(false); }, 3000);
      }
    });
  }
})(window);
