/* ЖИВОЙ ЭКРАН ТЕМЫ «ПЛАНЕТА»

   Здесь три вещи: разряд по колонке пингов, отклик на нажатия и
   пересборка геометрии при смене размера экрана.

   ── РАЗРЯД ИДЁТ ПО КОЛОНКЕ ПИНГОВ ────────────────────────────────
   Клиент прислал снимок чужого приложения, обвёл зелёным ИМЕННО
   столбец миллисекунд и спросил: «Это же пинги? И по ним молнию да?».
   Значит ствол идёт сверху вниз по этому столбцу, а не по краю экрана
   и не через названия стран. От ствола на каждой строке отходит
   короткая ветка влево, к полоскам сигнала: это и есть «прошило
   сервер».

   На том же снимке у Гонконга вместо числа стоит «н/д». Ровно для
   таких строк и нужен потухший серый след, о котором он просил.

   ── МОЛНИЯ ЖИВАЯ, А НЕ НАРИСОВАННАЯ ЛИНИЯ ────────────────────────
   Настоящий разряд не рисуется одним росчерком: он бьёт вниз ступенями,
   дрожит, ветвится и оставляет тающий след. Поэтому здесь нет готового
   пути, который просто проявляется. Ствол СТРОИТСЯ каждый кадр из
   точек, излом точек пересчитывается несколько раз в секунду, и от
   головы отлетают короткие отростки, которые тут же гаснут.

   ── ХОД СЧИТАЕТСЯ ПО ВРЕМЕНИ, А НЕ ПО КАДРАМ ────────────────────
   Телефоны рисуют от 60 до 120 кадров в секунду, а старые роняют до
   тридцати. Привяжи ход к кадрам, и на одном аппарате молния пройдёт
   за секунду, на другом за четыре. */

(function () {
  "use strict";

  var список = document.getElementById("список");
  var молния = document.getElementById("молния");
  var слойС  = document.getElementById("слой-ствол");
  var слойВ  = document.getElementById("слой-ветки");
  var голова = document.getElementById("голова");
  if (!список || !молния) return;

  var НС = "http://www.w3.org/2000/svg";
  var ряды = Array.prototype.slice.call(список.querySelectorAll(".ряд"));

  /* До восьмидесяти миллисекунд это хорошо, дальше средне. Порог
     назван числом здесь, а не рассыпан по разметке. */
  var СРЕДНЕ_ОТ = 80;
  ряды.forEach(function (р) {
    var п = parseInt(р.getAttribute("data-пинг"), 10);
    if (п && п >= СРЕДНЕ_ОТ) р.classList.add("середина");
  });

  var СПУСК_МС  = 880;    /* ствол доходит донизу */
  var ДРОЖЬ_МС  = 55;     /* как часто пересчитывается излом */
  var ДЕРЖИТ_МС = 260;    /* разряд стоит целиком и трещит */
  var ГАСНЕТ_МС = 520;    /* след тает */
  var СВЕТ_МС   = 760;    /* сколько строка держит вспышку */
  var ПАУЗА_МС  = 3200;

  var сост = null;

  function мера() {
    var к = список.getBoundingClientRect();
    if (!к.width || !к.height) return false;

    молния.setAttribute("viewBox", "0 0 " + к.width.toFixed(1) + " " + к.height.toFixed(1));

    /* ── ОСЬ РАЗРЯДА СТОИТ ВПЛОТНУЮ К ЧИСЛАМ, А НЕ НА НИХ ──────────
       Клиент обвёл зелёным столбец пингов, и первый сбор пустил ствол
       ровно по его середине. Кадр показал, во что это обходится:
       молния перечеркнула «28 мс», «42 мс» и все остальные значения.
       Число пинга это то, ради чего человек сюда смотрит, и закрывать
       его эффектом нельзя.

       Ось встаёт в просвет между числом и звездой: разряд идёт впритык
       к столбцу, задевает каждую строку и светит на цифры сбоку, ничего
       не закрывая. Место меряется у живых узлов, потому что ширина
       столбца зависит от самого длинного значения. */
    var первый = ряды[0];
    var чк = первый.querySelector(".пинг").getBoundingClientRect();
    var зк = первый.querySelector(".звезда").getBoundingClientRect();
    var ось = (чк.right + зк.left) / 2 - к.left;

    var узлы = ряды.map(function (р) {
      var рк = р.getBoundingClientRect();
      var сиг = р.querySelector(".заряд").getBoundingClientRect();
      return {
        узел: р,
        y: рк.top - к.top + рк.height / 2,
        полвысоты: рк.height / 2,
        доЗначка: сиг.left - к.left + сиг.width / 2,
        мёртвый: р.classList.contains("нет"),
        било: false
      };
    });

    сост = { ш: к.width, в: к.height, ось: ось, ряды: узлы };
    чисто();
    return true;
  }

  function чисто(сброситьЗаряд) {
    слойС.textContent = "";
    слойВ.textContent = "";
    if (голова) голова.style.opacity = 0;
    if (!сост) return;
    сост.ряды.forEach(function (р) {
      р.било = false;
      р.узел.classList.remove("бьёт");
      /* Заряд снимается только на НАЧАЛЕ нового замера. Снимать его в
         конце удара значило бы гасить то, что владелец просил оставить
         гореть. */
      if (сброситьЗаряд) р.узел.classList.remove("заряжен");
    });
  }

  /* ── ТОЧКИ СТВОЛА ────────────────────────────────────────────────
     Ступени идут вниз ровным шагом, вбок уходят случайно. Размах
     небольшой: разряд идёт ВДОЛЬ столбца, и широкий зигзаг увёл бы
     его на названия стран. */
  function точки(высота, размах) {
    var т = [], шаг = Math.max(9, высота / 26);
    for (var y = -12; y <= высота + 12; y += шаг) {
      т.push({ y: y, x: (Math.random() * 2 - 1) * размах });
    }
    return т;
  }

  function путь(т, до, ось) {
    var д = "";
    for (var i = 0; i < до && i < т.length; i++) {
      д += (i ? " L " : "M ") + (ось + т[i].x).toFixed(1) + " " + т[i].y.toFixed(1);
    }
    return д;
  }

  /* ── СВЕЧЕНИЕ СОБИРАЕТСЯ ОБВОДКАМИ, А НЕ РАЗМЫТИЕМ ──────────────
     Сначала широкая линия размывалась: сперва свойством CSS
     filter: blur(), потом своим фильтром SVG. Оба раза размытый слой
     уезжал влево почти на половину ширины списка, и в кадре посреди
     строк висело синее пятно. Замер рамок поймал это числом: жила
     стояла на x 296..368, а её же сияние с ТЕМ ЖЕ путём на 99..171.

     Размытие тут и не нужно. Свечение это пять обводок одного пути:
     самая широкая почти прозрачная, самая тонкая белая и плотная. Глаз
     читает такую стопку как сияние, рисуется она одинаково в любом
     браузере, и уезжать ей некуда - это обычная линия.

     Заодно это дешевле: размытие большой области на телефоне стоит
     кадров, а приложение ВПН открывают по десять раз на дню. */
  var СЛОИ = ["дым", "дальний", "средний", "ближний", "жила"];
  function тройка(родитель, клас) {
    var г = document.createElementNS(НС, "g");
    СЛОИ.forEach(function (и) {
      var п = document.createElementNS(НС, "path");
      п.setAttribute("class", "нить " + и + (клас ? " " + клас : ""));
      г.appendChild(п);
    });
    родитель.appendChild(г);
    return г;
  }

  function задатьТройке(г, д) {
    for (var i = 0; i < г.children.length; i++) г.children[i].setAttribute("d", д);
  }

  /* ── ВЕТКА ОБХОДИТ ЧИСЛО СНИЗУ ──────────────────────────────────
     Прямая ветка от ствола к полоскам сигнала шла через всю строку и
     перечёркивала само значение: на кадре «63 мс» и «78 мс» оказались
     зачёркнуты разрядом. Число пинга это то, ради чего человек сюда
     смотрит.

     Теперь ветка ныряет под строку, проходит под числом и поднимается
     к полоскам. Читается то же самое - ток дошёл до сервера и зажёг
     его отклик, - и ничего не закрыто. Мёртвая строка получает
     короткий огрызок: до полосок он не доходит и гаснет на полпути. */
  function веткаПуть(р) {
    var низ = р.y + р.полвысоты * 0.62;
    var от = сост.ось, до = р.доЗначка;
    if (р.мёртвый) до = от - (от - до) * 0.45;
    var т = [{ x: от, y: р.y }, { x: от - 4, y: низ }];
    var шаг = Math.max(8, (от - до) / 5);
    for (var x = от - 10; x > до + 6; x -= шаг) {
      т.push({ x: x, y: низ + (Math.random() * 2 - 1) * 1.8 });
    }
    т.push({ x: до, y: р.мёртвый ? низ : р.y });
    var д = "";
    т.forEach(function (п, i) { д += (i ? " L " : "M ") + п.x.toFixed(1) + " " + п.y.toFixed(1); });
    return д;
  }

  var номер = 0;
  var идёт = false;

  function удар() {
    if (!сост) return;
    номер += 1;
    var мой = номер;
    идёт = true;
    чисто(true);

    var размах = Math.min(сост.ш * 0.022, 9);
    var т = точки(сост.в, размах);
    var ствол = тройка(слойС, "");
    var начало = null, дрожало = 0;

    document.documentElement.classList.add("разряд");

    function кадр(время) {
      if (мой !== номер) return;
      if (начало === null) начало = время;
      var прошло = время - начало;
      var доля = Math.min(1, прошло / СПУСК_МС);

      /* Излом пересчитывается редко, а не каждый кадр: на ста двадцати
         кадрах в секунду ежекадровая дрожь читается шумом, а не
         электричеством. */
      if (прошло - дрожало > ДРОЖЬ_МС) {
        дрожало = прошло;
        for (var i = 0; i < т.length; i++) т[i].x = (Math.random() * 2 - 1) * размах;
      }

      var до = Math.max(2, Math.round(т.length * доля));
      задатьТройке(ствол, путь(т, до, сост.ось));

      var кон = т[Math.min(до, т.length) - 1];
      if (голова) {
        голова.setAttribute("cx", (сост.ось + кон.x).toFixed(1));
        голова.setAttribute("cy", кон.y.toFixed(1));
        голова.style.opacity = доля < 1 ? 1 : 0;
      }

      сост.ряды.forEach(function (р) {
        if (!р.било && кон.y >= р.y) {
          р.било = true;
          ударитьРяд(р, мой);
        }
      });

      if (прошло < СПУСК_МС + ДЕРЖИТ_МС) {
        requestAnimationFrame(кадр);
      } else {
        document.documentElement.classList.remove("разряд");
        ствол.classList.add("тает");
        setTimeout(function () {
          if (мой !== номер) return;
          идёт = false;
          чисто();
        }, ГАСНЕТ_МС);
      }
    }
    requestAnimationFrame(кадр);
  }

  /* ── УДАР ПО РЯДУ ────────────────────────────────────────────────
     Живой сервер отвечает: ветка добегает до полосок сигнала, число
     загорается, строка подсвечивается. Мёртвый не отвечает: ветка
     серая, короче и тает вдвое быстрее, строка не светится вовсе.
     Это и есть «где нету, молния потухшая, серый след». */
  function ударитьРяд(р, мой) {
    var г = тройка(слойВ, р.мёртвый ? "мёртвая" : "живая");
    задатьТройке(г, веткаПуть(р));

    р.узел.classList.add("бьёт");
    /* Заряд остаётся ПОСЛЕ вспышки и не снимается вместе с ней. Слово
       Даниэля: «гореть остаются иконки те, где пинг есть, ну цифры
       справа 112 мс и так далее». Мёртвой строке заряд не достаётся
       никогда: у неё нет отклика, и гореть нечему. */
    if (!р.мёртвый) р.узел.classList.add("заряжен");
    setTimeout(function () {
      if (мой !== номер) return;
      г.classList.add("тает");
      р.узел.classList.remove("бьёт");
    }, р.мёртвый ? СВЕТ_МС * 0.45 : СВЕТ_МС);
  }

  /* ── ОТКЛИК НА НАЖАТИЕ ───────────────────────────────────────────
     Слово Даниэля: «и анимации нажатий кнопок красиво». Круг от точки
     касания это то, что человек ждёт от нажатия на телефоне: палец
     попал сюда, и отсюда пошла волна. Круг живёт полсекунды и
     убирается за собой, чтобы в разметке не копились мёртвые узлы. */
  function волна(э, соб) {
    var к = э.getBoundingClientRect();
    var в = document.createElement("span");
    в.className = "волна";
    var d = Math.max(к.width, к.height) * 2.1;
    var x = (соб && соб.clientX ? соб.clientX : к.left + к.width / 2) - к.left;
    var y = (соб && соб.clientY ? соб.clientY : к.top + к.height / 2) - к.top;
    в.style.width = в.style.height = d + "px";
    в.style.left = (x - d / 2) + "px";
    в.style.top  = (y - d / 2) + "px";
    э.appendChild(в);
    setTimeout(function () { в.remove(); }, 620);
  }

  document.querySelectorAll(".пуск, .полоса, .плитка, .ряд, .вкладка, .кругляш").forEach(function (э) {
    if (getComputedStyle(э).position === "static") э.style.position = "relative";
    э.classList.add("нажимается");
    э.addEventListener("pointerdown", function (соб) { волна(э, соб); });
  });

  /* Тумблер переключается по-настоящему: неработающий тумблер на
     показе клиенту читается как недоделка. */
  document.querySelectorAll(".тумблер").forEach(function (т) {
    var род = т.closest(".плитка") || т;
    род.addEventListener("click", function () { т.classList.toggle("вкл"); });
  });

  /* Выбор страны переставляется по нажатию: то же самое, экран должен
     отвечать на палец. */
  ряды.forEach(function (р) {
    р.addEventListener("click", function () {
      ряды.forEach(function (д) { д.classList.remove("выбран"); });
      р.classList.add("выбран");
    });
  });

  /* Кнопка подключения: нажатие бьёт разрядом по всем серверам. Это и
     показ эффекта, и честный смысл - идёт замер связи. */
  var пуск = document.getElementById("пуск");
  if (пуск) {
    пуск.addEventListener("click", function () {
      пуск.classList.remove("толчок");
      void пуск.offsetWidth;
      пуск.classList.add("толчок");
      if (!идёт) удар();
    });
  }

  function поехали() {
    if (!мера()) { setTimeout(поехали, 120); return; }
    setTimeout(function повтор() {
      удар();
      setTimeout(повтор, СПУСК_МС + ДЕРЖИТ_МС + ГАСНЕТ_МС + ПАУЗА_МС);
    }, 900);
  }

  if (document.fonts && document.fonts.ready) document.fonts.ready.then(поехали);
  else поехали();

  var часы = null;
  window.addEventListener("resize", function () {
    clearTimeout(часы);
    часы = setTimeout(мера, 180);
  });

  /* ── СБОРЩИКУ КАДРОВ: ОСТАНОВКА НА ЗАДАННОЙ ДОЛЕ ────────────────
     Снимать живую молнию кадрами нельзя, и это выяснилось замером.
     Разряд идёт 880 миллисекунд, а один снимок экрана на тройной
     плотности с размытиями снимается дольше: четырнадцать кадров
     подряд поймали пустой список, хотя живая проба в тот же момент
     показывала четыре пробитых строки и четыре ветки.

     Поэтому у раскадровки свой путь: удар не запускается, а СТАВИТСЯ
     на заданную долю. Кадры выходят одинаковые от прогона к прогону, и
     сравнивать их между собой можно честно. */
  window.ЭКРАН_ГОТОВ  = function () { return !!сост; };
  window.УДАРИТЬ      = function () { номер += 1; идёт = false; удар(); };
  window.МОЛНИЯ_ИДЁТ  = function () { return идёт; };

  var стопТочки = null;
  window.СТОП_УДАР = function (доля) {
    if (!сост) return false;
    номер += 1;            /* глушим живой удар, если он шёл */
    идёт = true;
    чисто(true);
    var размах = Math.min(сост.ш * 0.022, 9);
    if (!стопТочки) стопТочки = точки(сост.в, размах);
    var ствол = тройка(слойС, "");
    var до = Math.max(2, Math.round(стопТочки.length * доля));
    задатьТройке(ствол, путь(стопТочки, до, сост.ось));
    var кон = стопТочки[Math.min(до, стопТочки.length) - 1];
    голова.setAttribute("cx", (сост.ось + кон.x).toFixed(1));
    голова.setAttribute("cy", кон.y.toFixed(1));
    голова.style.opacity = доля < 1 ? 1 : 0;
    document.documentElement.classList.add("разряд");
    /* В живом ударе строка держит вспышку меньше секунды и гаснет, а
       голова к тому времени ушла вниз. Стоп-кадр обязан показывать то
       же самое: зажечь ВСЕ пройденные строки значило бы нарисовать
       кадр, которого в анимации не бывает. Держим окно из четырёх
       последних строк, как и в живом ходе. */
    var ОКНО = 4;
    var прошло = сост.ряды.filter(function (р) { return кон.y >= р.y; });
    var порог = прошло.length > ОКНО ? прошло[прошло.length - ОКНО].y : -1e9;
    сост.ряды.forEach(function (р) {
      /* Заряд получает КАЖДАЯ пройденная строка, а вспышку только
         окно у головы: так стоп-кадр показывает ровно то, что видит
         человек в живом ходе. */
      if (кон.y >= р.y && !р.мёртвый) р.узел.classList.add("заряжен");
      if (кон.y >= р.y && р.y >= порог) {
        р.узел.classList.add("бьёт");
        if (!р.мёртвый) р.узел.classList.add("заряжен");
        /* Ветка строится ТОЙ ЖЕ функцией, что и в живом ударе. Своя
           копия расчёта здесь уже стояла, и правка формы ветки в одном
           месте не доезжала до другого: стоп-кадр показывал не то, что
           видит человек. */
        задатьТройке(тройка(слойВ, р.мёртвый ? "мёртвая" : "живая"), веткаПуть(р));
      }
    });
    return true;
  };
})();
