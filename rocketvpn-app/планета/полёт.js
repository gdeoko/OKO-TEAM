/* РАКЕТА ЛЕТАЕТ ПО ФОНУ (тема «Полёт»).

   Слово владельца: «чтобы ракета не на месте летела, а продумать,
   чтобы она летала по фону красиво в разных направлениях, не мешая
   работе». Видеоклип под это не годится: петля обязана вернуться в
   первый кадр, и ракета в ней либо стоит, либо улетает и пропадает.
   Поэтому фон темы это вращающаяся планета (видео), а ракета живёт
   отдельно, в коде: вырезанный снимок корабля, факел и шлейф из искр
   рисуются на холсте поверх клипа и ПОД стеклом интерфейса.

   Как летает. Маршруты записаны кривыми Безье в долях экрана и идут
   по кругу: подъём справа, дальний проход по диагонали, подъём слева,
   дальний проход обратно, разворот снизу. Близкие проходы крупнее и
   ярче, дальние мелкие: так у неба появляется глубина. Ни один
   маршрут не проходит за линзой и словом «Подключиться»: ракета
   обходит кнопку по краям экрана или идёт ниже, под стеклом карточек,
   где она видна размытой. Между проходами пауза в пару секунд, небо
   дышит само.

   Нос всегда смотрит по касательной к пути: ракета поворачивает
   вместе с кривой, а не едет боком. Факел мерцает по шуму, из сопла
   летят искры с затуханием, днём за ними тянется тёплый дымок.

   Где не летает. На внутренних разделах, при выключенных анимациях,
   в свёрнутом приложении и в других темах холст гаснет и цикл встаёт:
   батарея не тратится на то, чего не видно.

   Стенд (navigator.webdriver) получает один честный кадр: полёт
   прокручивается вперёд без отрисовки до середины первого маршрута,
   и снимок каждый раз одинаковый. */
(function (g) {
  "use strict";

  var СПРАЙТ = "ассеты/фон/ракета.webp?v=202609301400";

  /* Точки в долях экрана телефона: [x, y], y сверху. р - высота ракеты
     в долях высоты экрана, с - секунд на проход, я - яркость. */
  /* Открытое небо это верхняя треть экрана: ниже лежат плотные стеклянные
     карточки, и ракета под ними почти не видна. Поэтому каждый маршрут
     либо выходит из-под карточек в открытое небо, либо весь идёт в нём,
     обходя линзу (x .30-.70, y .08-.27) по бокам и поверху. */
  var МАРШРУТЫ = [
    { имя: "подъём справа",  т: [[.86, .62], [.97, .38], [.80, .20], [1.04, -.14]], р: .14, с: 6.5, я: 1 },
    { имя: "дальний поверху", т: [[1.12, .12], [.72, .045], [.30, .045], [-.12, .13]], р: .05, с: 9, я: .85 },
    { имя: "подъём слева",   т: [[.14, .62], [.03, .38], [.20, .20], [-.04, -.14]], р: .14, с: 6.5, я: 1 },
    { имя: "дальний слева",  т: [[-.12, .31], [.10, .25], [.19, .09], [.37, -.12]], р: .06, с: 8, я: .85 },
    { имя: "разворот справа", т: [[1.12, .31], [.84, .31], [.77, .12], [.92, -.14]], р: .11, с: 7, я: .95 }
  ];
  var ПАУЗА = [1.6, 3.2];

  /* Цвета факела по времени суток: днём золото, как неон темы утром,
     ночью оранжевый огонь. */
  var ЦВЕТ = {
    утро:  { внеш: [255, 168, 70], сред: [255, 214, 150], ядро: [255, 248, 232], дым: [255, 236, 214], дымЯ: .10 },
    вечер: { внеш: [255, 106, 36], сред: [255, 170, 90],  ядро: [255, 242, 220], дым: [120, 96, 88],   дымЯ: .07 }
  };

  var холст, кт, спрайт = null, готовСпрайт = false;
  var Ш = 0, В = 0, dpr = 1;
  var вкл = false, идти = false, пора = "утро";
  var номер = 0, t = 0, пауза = 0, частицы = [], последнееСопло = null;
  var кадрИд = 0, прошлое = 0;
  var стенд = !!(g.navigator && g.navigator.webdriver);

  function завести(слой) {
    холст = document.createElement("canvas");
    холст.className = "фон-полёт";
    холст.setAttribute("aria-hidden", "true");
    слой.appendChild(холст);
    кт = холст.getContext("2d");
    спрайт = new Image();
    спрайт.decoding = "async";
    спрайт.onload = function () { готовСпрайт = true; if (стенд) кадрСтенда(); };
    спрайт.src = СПРАЙТ;
    g.addEventListener("resize", мерить);
    мерить();
  }

  function мерить() {
    if (!холст) return;
    var р = холст.parentNode.getBoundingClientRect();
    Ш = р.width; В = р.height;
    dpr = Math.min(2, g.devicePixelRatio || 1);
    холст.width = Math.round(Ш * dpr); холст.height = Math.round(В * dpr);
    холст.style.width = Ш + "px"; холст.style.height = В + "px";
    if (стенд) кадрСтенда();
  }

  /* ── КРИВАЯ ─────────────────────────────────────────────────────── */
  function безье(т, u) {
    var a = 1 - u, b = a * a * a, c = 3 * a * a * u, d = 3 * a * u * u, e = u * u * u;
    return [b * т[0][0] + c * т[1][0] + d * т[2][0] + e * т[3][0],
            b * т[0][1] + c * т[1][1] + d * т[2][1] + e * т[3][1]];
  }
  /* Лёгкий разгон и торможение поверх ровного хода: чистая плавная
     ступень давала заметную остановку посреди экрана. */
  function ход(x) { return .72 * x + .28 * x * x * (3 - 2 * x); }

  function положение() {
    var м = МАРШРУТЫ[номер], u = ход(Math.min(1, t / м.с));
    var p = безье(м.т, u), q = безье(м.т, Math.min(1, u + .004));
    if (q[0] === p[0] && q[1] === p[1]) q = [p[0], p[1] - .001];
    var x = p[0] * Ш, y = p[1] * В;
    var угол = Math.atan2((q[1] - p[1]) * В, (q[0] - p[0]) * Ш) + Math.PI / 2;
    return { x: x, y: y, угол: угол, м: м };
  }

  /* ── ШУМ ДЛЯ МЕРЦАНИЯ ФАКЕЛА ────────────────────────────────────── */
  function шум(x) {
    return (Math.sin(x * 12.9) * .5 + Math.sin(x * 31.7 + 1.3) * .3 + Math.sin(x * 57.1 + 2.1) * .2);
  }

  /* ── ЧАСТИЦЫ ────────────────────────────────────────────────────── */
  var точка = null;
  function мягкаяТочка() {
    if (точка) return точка;
    точка = document.createElement("canvas");
    точка.width = точка.height = 64;
    var к = точка.getContext("2d"), гр = к.createRadialGradient(32, 32, 0, 32, 32, 32);
    гр.addColorStop(0, "rgba(255,255,255,1)");
    гр.addColorStop(.35, "rgba(255,255,255,.55)");
    гр.addColorStop(1, "rgba(255,255,255,0)");
    к.fillStyle = гр; к.fillRect(0, 0, 64, 64);
    return точка;
  }
  var цветныеТочки = {};
  function точкаЦвета(rgb) {
    var ключ = rgb.join(",");
    if (цветныеТочки[ключ]) return цветныеТочки[ключ];
    var к = document.createElement("canvas"); к.width = к.height = 64;
    var кк = к.getContext("2d");
    кк.drawImage(мягкаяТочка(), 0, 0);
    кк.globalCompositeOperation = "source-in";
    кк.fillStyle = "rgb(" + ключ + ")"; кк.fillRect(0, 0, 64, 64);
    return (цветныеТочки[ключ] = к);
  }

  function выпустить(п, dt) {
    var ц = ЦВЕТ[пора], м = п.м, h = м.р * В;
    var назад = [-Math.sin(п.угол), Math.cos(п.угол)];
    var поперёк = [Math.cos(п.угол), Math.sin(п.угол)];
    var сколько = Math.round(140 * dt * (м.р / .15) + Math.random());
    for (var i = 0; i < сколько; i++) {
      var сдвиг = (Math.random() - .5) * h * .09;
      var скор = h * (1.6 + Math.random() * 1.4);
      частицы.push({
        x: п.x + поперёк[0] * сдвиг, y: п.y + поперёк[1] * сдвиг,
        vx: назад[0] * скор + поперёк[0] * (Math.random() - .5) * h * .5,
        vy: назад[1] * скор + поперёк[1] * (Math.random() - .5) * h * .5,
        жизнь: 0, срок: .45 + Math.random() * .55, р: h * (.035 + Math.random() * .03), я: м.я, вид: "искра"
      });
    }
    if (Math.random() < 30 * dt) {
      частицы.push({
        x: п.x + назад[0] * h * .2, y: п.y + назад[1] * h * .2,
        vx: назад[0] * h * .5 + (Math.random() - .5) * h * .2, vy: назад[1] * h * .5 + (Math.random() - .5) * h * .2,
        жизнь: 0, срок: 1.6 + Math.random() * .8, р: h * (.08 + Math.random() * .05), я: м.я * ц.дымЯ * 10, вид: "дым"
      });
    }
    if (частицы.length > 420) частицы.splice(0, частицы.length - 420);
  }

  function шагЧастиц(dt) {
    for (var i = частицы.length - 1; i >= 0; i--) {
      var ч = частицы[i];
      ч.жизнь += dt;
      if (ч.жизнь >= ч.срок) { частицы.splice(i, 1); continue; }
      var тормоз = ч.вид === "дым" ? .55 : 2.2;
      ч.vx *= Math.exp(-тормоз * dt); ч.vy *= Math.exp(-тормоз * dt);
      ч.x += ч.vx * dt; ч.y += ч.vy * dt;
    }
  }

  /* ── ШАГ МИРА ───────────────────────────────────────────────────── */
  function шаг(dt) {
    if (пауза > 0) {
      пауза -= dt;
      if (пауза <= 0) { номер = (номер + 1) % МАРШРУТЫ.length; t = 0; }
      последнееСопло = null;
    } else {
      t += dt;
      var м = МАРШРУТЫ[номер];
      if (t >= м.с) {
        пауза = ПАУЗА[0] + Math.random() * (ПАУЗА[1] - ПАУЗА[0]);
        последнееСопло = null;
      } else {
        var п = положение();
        выпустить(п, dt);
        последнееСопло = п;
      }
    }
    шагЧастиц(dt);
  }

  /* ── ОТРИСОВКА ──────────────────────────────────────────────────── */
  function рисовать(время) {
    кт.setTransform(dpr, 0, 0, dpr, 0, 0);
    кт.clearRect(0, 0, Ш, В);
    var ц = ЦВЕТ[пора];

    /* дым под искрами, обычным наложением */
    кт.globalCompositeOperation = "source-over";
    var дым = точкаЦвета(ц.дым);
    частицы.forEach(function (ч) {
      if (ч.вид !== "дым") return;
      var k = ч.жизнь / ч.срок, р = ч.р * (1 + k * 2.2);
      кт.globalAlpha = Math.min(1, ч.я) * ц.дымЯ * Math.sin(Math.PI * Math.min(1, k * 1.4 + .05));
      кт.drawImage(дым, ч.x - р, ч.y - р, р * 2, р * 2);
    });

    /* искры светом */
    кт.globalCompositeOperation = "lighter";
    var горяч = точкаЦвета(ц.сред), внеш = точкаЦвета(ц.внеш);
    частицы.forEach(function (ч) {
      if (ч.вид !== "искра") return;
      var k = ч.жизнь / ч.срок, р = ч.р * (1 + k * 1.6);
      кт.globalAlpha = ч.я * (1 - k) * (1 - k) * .9;
      кт.drawImage(k < .3 ? горяч : внеш, ч.x - р, ч.y - р, р * 2, р * 2);
    });

    var п = последнееСопло;
    if (п && готовСпрайт) {
      var м = п.м, h = м.р * В, w = h * спрайт.naturalWidth / спрайт.naturalHeight;
      var мерц = 1 + .14 * шум(время * .9) ;
      кт.save();
      кт.translate(п.x, п.y); кт.rotate(п.угол);

      /* Факел: общий язык света и три струи по соплам снимка, в центре
         связка основной ступени, по бокам ускорители (±0.38 ширины).
         Каждая струя мерцает своим шумом, иначе три факела дышат одним
         движением и выглядят наклейкой. */
      кт.globalCompositeOperation = "lighter";
      var L = h * .95 * мерц, ядро = точкаЦвета(ц.ядро);
      факел(внеш, w * 1.5, L * 1.35, .75 * м.я, 0);
      [[0, 1, 0], [-.38, .72, 1.7], [.38, .72, 3.1]].forEach(function (с) {
        var к = 1 + .16 * шум(время * 1.3 + с[2]);
        факел(горяч, w * .5 * с[1], L * .85 * с[1] * к, .95 * м.я, с[0] * w);
        факел(ядро, w * .24 * с[1], L * .42 * с[1] * к, 1, с[0] * w);
      });
      /* ореол у сопла */
      кт.globalAlpha = .6 * м.я * мерц;
      кт.drawImage(внеш, -w * 1.1, -w * 1.1, w * 2.2, w * 2.2);

      /* корпус: сопло в начале координат, нос вверх */
      кт.globalCompositeOperation = "source-over";
      кт.globalAlpha = м.я;
      кт.drawImage(спрайт, -w / 2, -h, w, h);
      кт.restore();
    }
    кт.globalAlpha = 1;
    кт.globalCompositeOperation = "source-over";
  }

  /* Язык факела: мягкая точка, вытянутая назад от сопла. */
  function факел(т, ширина, длина, я, сдвиг) {
    кт.globalAlpha = я;
    кт.drawImage(т, сдвиг - ширина / 2, -длина * .08, ширина, длина);
  }

  /* ── ЦИКЛ ───────────────────────────────────────────────────────── */
  function кадр(сейчас) {
    кадрИд = 0;
    if (!идти) return;
    var dt = прошлое ? Math.min(.05, (сейчас - прошлое) / 1000) : 1 / 60;
    прошлое = сейчас;
    шаг(dt);
    рисовать(сейчас / 1000);
    кадрИд = g.requestAnimationFrame(кадр);
  }

  function пересмотреть(можно) {
    var надо = вкл && можно && !стенд;
    if (холст) холст.classList.toggle("виден", вкл && (можно || стенд));
    if (надо && !идти) { идти = true; прошлое = 0; if (!кадрИд) кадрИд = g.requestAnimationFrame(кадр); }
    if (!надо && идти) { идти = false; if (кадрИд) { g.cancelAnimationFrame(кадрИд); кадрИд = 0; } }
    if (стенд && вкл) кадрСтенда();
  }

  /* Стенд: середина первого маршрута, полторы секунды шлейфа за ней. */
  function кадрСтенда() {
    if (!холст || !готовСпрайт || !Ш) return;
    номер = 0; пауза = 0; частицы = [];
    var до = МАРШРУТЫ[0].с * .58;
    t = Math.max(0, до - 1.5);
    var старый = Math.random; var сид = 7;
    Math.random = function () { сид = (сид * 16807) % 2147483647; return (сид - 1) / 2147483646; };
    while (t < до) шаг(1 / 30);
    Math.random = старый;
    рисовать(до);
  }

  g.ПОЛЁТ = {
    завести: завести,
    мерить: мерить,
    /* тема «Полёт» включена или нет; можно - разрешено ли движение */
    тема: function (да, можно) { вкл = !!да; пересмотреть(можно); },
    пора: function (п) { пора = п === "вечер" ? "вечер" : "утро"; if (стенд) кадрСтенда(); },
    можно: function (можно) { пересмотреть(можно); },
    /* Сопло в css-точках телефона, когда ракета на экране. Отсюда
       выходит след замера: огонь идёт из её факела. */
    сопло: function () {
      var п = последнееСопло;
      if (!вкл || !п) return null;
      if (п.x < 12 || п.x > Ш - 12 || п.y < 12 || п.y > В - 12) return null;
      return { x: п.x, y: п.y };
    }
  };
})(window);
