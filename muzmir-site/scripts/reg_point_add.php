<?php
/**
 * scripts/reg_point_add.php — ДОПИСАТЬ ПУНКТ В ПОЛОЖЕНИЕ КОНКУРСА.
 *
 *   php scripts/reg_point_add.php --after=7.9 --no=7.10 --text="…" [--only-open] [--dry]
 *   php scripts/reg_point_add.php --after=7.9 --no=7.10 --text="…" --file=docs/polozheniya/etalon_2.docx
 *
 * ПРАВИШЬ ПОЛОЖЕНИЯ — ПРАВЬ И ЭТАЛОН (--file). Положение пересобирается из
 * эталона при каждом сохранении конкурса в админке, и дописанный пункт из
 * живого файла при этом пропадает.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ИНСТРУМЕНТ. Положение это .docx, подписанный генеральным
 * директором, и правка в нём не косметика: по этому тексту центр отвечает людям,
 * а с 13.10.2026 по нему же отвечает чат-бот (core/chat_regulation.php читает
 * пункты прямо из файла). Открывать документ руками в Word и править одиннадцать
 * файлов — это одиннадцать шансов разойтись формулировкой; здесь один текст
 * ложится во все выбранные файлы одинаково.
 *
 * КАК. Новый пункт не рисуется с нуля: берётся АБЗАЦ-ОБРАЗЕЦ (тот, что указан в
 * --after), копируется целиком со всем оформлением, и в копии подменяется только
 * текст. Поэтому шрифт, отступы и выключка у нового пункта те же, что у соседей.
 * Служебные метки абзаца (w14:paraId, w14:textId) из копии убираются:два абзаца
 * с одним идентификатором Word считает ошибкой разметки.
 *
 * ЗАКРЫТЫЕ КОНКУРСЫ ПО УМОЛЧАНИЮ НЕ ТРОГАЕМ (--only-open). Положение прошедшего
 * конкурса это документ о том, что уже состоялось, и дописывать в него правила
 * задним числом нельзя: участник подавал работу по другому тексту.
 *
 * Перед каждой правкой рядом с файлом кладётся копия .bak-<дата>.
 */
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { fwrite(STDERR, "CLI only\n"); exit(1); }

define('BASE_PATH', dirname(__DIR__));
$GLOBALS['CFG'] = require BASE_PATH . '/config.php';
require_once BASE_PATH . '/core/db.php';
require_once BASE_PATH . '/core/helpers.php';
require_once BASE_PATH . '/core/regulation_gen.php';   // reg_file_vladelec()

$opt   = getopt('', ['after::', 'no::', 'text::', 'file::', 'only-open', 'dry']);
$after = trim((string) ($opt['after'] ?? ''));
$no    = trim((string) ($opt['no'] ?? ''));
$text  = trim((string) ($opt['text'] ?? ''));
$dry   = isset($opt['dry']);
$onlyOpen = isset($opt['only-open']);

if ($after === '' || $no === '' || $text === '') {
    fwrite(STDERR, "нужны --after=<номер образца>, --no=<номер нового пункта>, --text=<текст>\n");
    exit(1);
}

/* --file=<путь[,путь]> — править ЭТАЛОН, а не положение живого конкурса.
 *
 * Зачем это нужно (разбор 14.10.2026): положение конкурса собирается заново из
 * эталона при КАЖДОМ сохранении конкурса в админке (regulation_generate), а
 * эталоны лежат в docs/polozheniya/ и про дописанные пункты не знают. Пункт
 * 7.10 про возврат взноса, продиктованный владельцем 13.10, был вписан в файлы
 * четырёх конкурсов — и первое же сохранение «Мирового акцента» стёрло его
 * начисто. Полтора месяца это не выстреливало только потому, что copy() падал
 * на правах файла, то есть пункт держала СЛУЧАЙНОСТЬ.
 *
 * Поэтому пункт кладётся в ДВА места: в живые положения (чтобы работал сейчас)
 * и в эталон (чтобы не терялся при перегенерации и достался конкурсам следующего
 * месяца — их заводят заново, правило 11).
 */
$files = trim((string) ($opt['file'] ?? ''));
if ($files !== '') {
    $comps = [];
    foreach (explode(',', $files) as $f) {
        $f = trim($f);
        if ($f === '') continue;
        if (!str_starts_with($f, '/')) $f = BASE_PATH . '/' . ltrim($f, '/');
        $comps[] = ['id' => 0, 'name' => basename($f), 'status' => 'эталон', 'regulation_pdf' => $f];
    }
    if (!$comps) { echo "Файлов не передано.\n"; exit(1); }
} else {
    $where = $onlyOpen ? "AND status = 'open' AND COALESCE(launched,0) = 1" : '';
    $comps = all("SELECT id, name, status, regulation_pdf FROM competitions
                   WHERE COALESCE(regulation_pdf,'') <> '' $where ORDER BY sort");
    if (!$comps) { echo "Положений не найдено.\n"; exit(0); }
}

$done = 0; $skip = 0;

foreach ($comps as $c) {
    $path = (string) $c['regulation_pdf'];
    $name = (string) $c['name'];
    if (!is_file($path)) { echo "  [нет файла] $name\n"; $skip++; continue; }

    /* ВСТАВКУ ДЕЛАЕТ ЕДИНЫЙ ИСТОЧНИК - `reg_point_vstavit()` в
       core/regulation_gen.php. Здесь она лежала своей копией, а той же механикой
       с 16.10.2026 пользуется и перегенерация положения (правило 72): две копии
       разошлись бы молча - грабля оплачена правилами 33, 35, 45, 47, 56а, 64. */
    $st = reg_point_vstavit($path, $after, $no, $text, $dry);
    if ($st === 'уже есть') { echo "  [уже есть п. $no] $name\n"; $skip++; continue; }
    if ($st !== '')         { echo "  [$st] $name\n"; $skip++; continue; }
    echo $dry
        ? "  [сухой прогон] $name ({$c['status']}): после п. $after встанет п. $no\n"
        : "  [готово] $name ({$c['status']}): п. $no на месте\n";
    $done++;
}

echo "Положений изменено: $done, пропущено: $skip" . ($dry ? ' (сухой прогон)' : '') . "\n";
if (!$dry && $done > 0) {
    // Кэш разбора у бота держится отпечатком файлов и пересоберётся сам,
    // но сбросим явно: иначе до следующего вопроса он отвечает по старому.
    set_setting('chat_reg_stamp', '');
    echo "Кэш пунктов у чат-бота сброшен — следующий ответ уже по новому тексту.\n";
}
