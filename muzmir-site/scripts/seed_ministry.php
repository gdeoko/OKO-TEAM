<?php
/**
 * scripts/seed_ministry.php — наполнение таблицы ministry_letters реальными
 * записями по субъектам РФ, упомянутым в источниках проекта.
 *
 * Что делает:
 *   Заводит записи «письмо/благодарность информационной поддержки» по регионам,
 *   которые фигурируют в конспектах КЦ «Музыкальный Мир» (география участников и
 *   документально зафиксированные обращения министерств). Для двух субъектов,
 *   прямо задокументированных в скриншотах старого сайта, указано точное
 *   ведомство: Республика Татарстан (Министерство образования и науки) и
 *   Ставропольский край (Министерство образования). Остальные субъекты внесены
 *   с нейтральным заголовком «характер поддержки», без выдуманных номеров,
 *   подписантов и дат.
 *
 * Важно:
 *   - image_path НАМЕРЕННО пустой — заверенных сканов у нас нет, их пришлёт
 *     Даниэль; страница показывает такие записи как «скан готовится».
 *   - Идемпотентно: ключ дедупликации — регион + заголовок. Повторный запуск
 *     не плодит дубли, только обновляет порядок сортировки.
 *
 * Запуск: php scripts/seed_ministry.php
 */
declare(strict_types=1);
define('BASE_PATH', dirname(__DIR__));
$GLOBALS['CFG'] = require BASE_PATH . '/config.php';
require_once BASE_PATH . '/core/db.php';
require_once BASE_PATH . '/core/helpers.php';

echo "=== Письма поддержки министерств (ministry_letters) ===\n\n";

/*
 * [region, title]
 * title = характер поддержки. Для документально подтверждённых субъектов —
 * точное название ведомства (без номеров/подписантов). Для остальных —
 * общий заголовок, регион служит идентификатором записи.
 */
$SUPPORT = 'Информационная поддержка международных и всероссийских конкурсов и фестивалей';

$letters = [
    // --- Документально зафиксированные обращения (см. 09_screens_site.md) ---
    ['Республика Татарстан',  'Министерство образования и науки Республики Татарстан'],
    ['Ставропольский край',   'Министерство образования Ставропольского края'],

    // --- Субъекты РФ из географии участников/поддержки (конспекты 02_knowledge, SOURCE_knowledge_base) ---
    // Южный ФО
    ['Краснодарский край',     $SUPPORT],
    ['Ростовская область',     $SUPPORT],
    ['Астраханская область',   $SUPPORT],
    // Центральный ФО
    ['Белгородская область',   $SUPPORT],
    ['Воронежская область',    $SUPPORT],
    ['Рязанская область',      $SUPPORT],
    ['Тульская область',       $SUPPORT],
    ['Владимирская область',   $SUPPORT],
    ['Брянская область',       $SUPPORT],
    // Приволжский ФО
    ['Республика Башкортостан', $SUPPORT],
    ['Нижегородская область',  $SUPPORT],
    ['Саратовская область',    $SUPPORT],
    ['Ульяновская область',    $SUPPORT],
    ['Пензенская область',     $SUPPORT],
    // Северо-Западный ФО
    ['Калининградская область', $SUPPORT],
    ['Республика Коми',        $SUPPORT],
    // Сибирский ФО
    ['Красноярский край',      $SUPPORT],
    ['Кемеровская область',    $SUPPORT],
    ['Республика Хакасия',     $SUPPORT],
    ['Омская область',         $SUPPORT],
    // Дальневосточный ФО
    ['Амурская область',       $SUPPORT],
];

$added = 0; $updated = 0;
foreach ($letters as $i => [$region, $title]) {
    $existing = one("SELECT id FROM ministry_letters WHERE region = ? AND title = ?", [$region, $title]);
    if ($existing) {
        // Скан не трогаем (мог быть загружен вручную); обновляем только порядок.
        update('ministry_letters', ['sort' => $i], 'id = :id', ['id' => $existing['id']]);
        $updated++;
        echo "  [=] $region — $title\n";
    } else {
        insert('ministry_letters', [
            'region'     => $region,
            'title'      => $title,
            'image_path' => '',   // сканов нет — пришлёт Даниэль
            'sort'       => $i,
        ]);
        $added++;
        echo "  [+] $region — $title\n";
    }
}

echo "\n=== Итог ===\n";
printf("Добавлено: %d, обновлено: %d\n", $added, $updated);
printf("Всего писем в базе: %d\n", (int) scalar("SELECT COUNT(*) FROM ministry_letters"));
printf("Со сканом: %d, без скана (готовятся): %d\n",
    (int) scalar("SELECT COUNT(*) FROM ministry_letters WHERE image_path <> ''"),
    (int) scalar("SELECT COUNT(*) FROM ministry_letters WHERE image_path = ''"));
echo "\nСканы — от Даниэля: заверенные письма кладём в public/ и проставляем image_path.\n";
echo "=== Готово ===\n";
