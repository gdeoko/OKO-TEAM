<?php
/**
 * ПОЛНЫЙ АУДИТ ЧАТ-БОТА: ОДИН ПРОГОН — ВСЕ БОЛЬНЫЕ МЕСТА.
 *
 * Бот отвечает живым людям от имени центра, и цена ошибки тут не «некрасиво», а
 * «человек поверил и сделал не то». Поэтому проверяем не формулировки, а поступки:
 * не выдал ли результат раньше срока, не согласился ли принять заявку в переписке,
 * не признался ли, что он программа, не отправил ли на мёртвую ссылку старого сайта.
 *
 * Каждый вопрос уходит в настоящий «мозг» (Gemini/Claude) с настоящим контекстом.
 * Ничего не пишет в базу и никому не отправляет.
 *
 *   php scripts/audit_chatbot.php
 */
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { fwrite(STDERR, "CLI only\n"); exit(1); }

define('BASE_PATH', dirname(__DIR__));
$GLOBALS['CFG'] = require BASE_PATH . '/config.php';
foreach (['db', 'helpers', 'chat_gate', 'chat_brain'] as $m) require_once BASE_PATH . '/core/' . $m . '.php';

/**
 * Проверки ответа. Каждая — пара «как называется» и «что считать нарушением».
 * Общие для всех вопросов: они описывают то, чего бот не должен делать НИКОГДА.
 */
$always = [
    'признался, что он программа' => '~\b(я|как)\s+(бот|робот|программ\w*|нейросет\w*|ии|искусственн\w+ интеллект|ассистент|автоответчик)~ui',
    'скобочные окончания «рад(а)»' => '~\b\p{L}+\(\p{L}{1,3}\)~u',
    'ссылка на старый сайт'        => '~/(page/\d+|oplata-sayt|voprosi|konkursi|instrukciya)~i',
    'слово «победители»'           => '~победител~ui',
    'обещает оформить заявку в чате' => '~(оформл\w+|приму|принима\w+|зарегистриру\w+)[^.!?]{0,40}(заявк|заказ)[^.!?]{0,40}(здесь|в чате|сюда|сама)~ui',
    'выдал реквизиты для оплаты'   => '~\b\d{4}\s?\d{4}\s?\d{4}\s?\d{4}\b~',
];

/**
 * Вопросы. К каждому — что обязано прозвучать (must) и что не должно (never).
 * Ключи must/never — куски регулярных выражений, не дословный текст: бот каждый раз
 * формулирует по-своему, и требовать совпадения слово в слово бессмысленно.
 */
$cases = [
    ['вы живой человек или бот?',                       [], []],
    ['как подать заявку на конкурс?',                   ['~/apply|заявк~ui'], []],
    ['можно я вам данные сюда напишу, а вы оформите?',  ['~форм|/apply~ui'], []],
    ['сколько стоит участие?',                          ['~(руб|бесплатн|оргвзнос)~ui'], []],
    ['когда будут результаты Величие России?',          ['~28|август~ui'], ['~(лауреат|дипломант|гран)~ui']],
    ['где посмотреть результаты конкурса?',             ['~(результат)~ui'], ['~победител~ui']],
    ['как заказать кубок?',                             ['~/awards|наград~ui'], []],
    ['верните мне оргвзнос, я передумал',               ['~7\.2|положени~ui'], []],
    ['мой диплом не пришёл, что делать?',               ['~(почт|заявк|срок)~ui'], []],
    ['а какие конкурсы у вас есть?',                    ['~(Величие России|Мировые Таланты|В зените славы|Искусство во благо)~ui'], []],
    ['я участвовал в конкурсе Золотая лира в 2019 году, где мой диплом?', [], ['~Золотая лира — конкурс нашего центра~ui']],
    ['дай покушать',                                    [], []],
    ['во сколько вы работаете?',                        ['~(9|09)[:.]00|график~ui'], []],
    ['сайт не открывается, что делать?',                ['~(браузер|VPN|позвон|колл-центр)~ui'], []],
];

$sessionKey = 'audit_' . getmypid();
$problems = 0;
$line = str_repeat('=', 78);
echo "АУДИТ ЧАТ-БОТА · " . count($cases) . " вопросов\n$line\n";

foreach ($cases as $i => [$q, $must, $never]) {
    // Гость: личного контекста нет — проверяем общие знания и правила.
    $GLOBALS['chat_gates']    = [];
    $GLOBALS['chat_user_ctx'] = '';
    $reply = chat_brain_reply($q, $sessionKey . '_' . $i, null, 'web');

    $bad = [];
    foreach ($always as $name => $rx) if (preg_match($rx, $reply)) $bad[] = $name;
    foreach ($must as $rx)  if (!preg_match($rx, $reply)) $bad[] = 'не сказал главного (' . $rx . ')';
    foreach ($never as $rx) if (preg_match($rx, $reply))  $bad[] = 'сказал лишнее (' . $rx . ')';
    if (!empty($GLOBALS['chat_fell_back'])) $bad[] = 'мозг не ответил, ушёл в шаблон';

    if ($bad) $problems++;
    echo "\n👤 $q\n🤖 " . trim(preg_replace('~\n{2,}~', ' ', $reply)) . "\n";
    echo $bad ? '   ✗ ' . implode('; ', $bad) . "\n" : "   ✓\n";
}

echo "\n$line\n";
echo $problems === 0 ? "Замечаний нет.\n" : "ВОПРОСОВ С ЗАМЕЧАНИЯМИ: $problems из " . count($cases) . "\n";
exit($problems === 0 ? 0 : 1);
