<?php
/**
 * НОРМАЛИЗАЦИЯ НАЗВАНИЙ УЧРЕЖДЕНИЙ.
 *
 * Названия собраны из выгрузки Минкультуры и из ВКонтакте, где их писали люди
 * в свободной форме. В базе оказалось полторы тысячи названий капслоком,
 * кавычки-ёлочки, набранные как «<<» и «>>», двойные пробелы и декоративные
 * символы из оформления групп. В обычном списке это мелочь, но название
 * подставляется в официальное письмо и в бланк с печатью — «МБУ ДО ДШИ № 12»
 * там уместно, а «ТВОРЧЕСКАЯ СТУДИЯ <<АКУЛËНОК>>» выглядит как ошибка отправителя.
 *
 * Капслок разбирается с оглядкой на аббревиатуры: «ДШИ», «МБУ», «ДО», «ЦКР»
 * должны остаться заглавными, иначе получится «Мбу до Дши». Поэтому короткие
 * слова не трогаем вовсе, а длинные приводим к строчным, поднимая первую букву
 * фразы и первую букву внутри кавычек.
 *
 * Записи, которые вообще не являются учреждением (описания групп ВК на двести
 * символов), помечаются непригодными — не удаляются.
 *
 * Запуск:
 *   php scripts/normalize_institutions.php         — показать, что изменится
 *   php scripts/normalize_institutions.php apply   — применить
 */

declare(strict_types=1);

define('BASE_PATH', dirname(__DIR__));
require_once BASE_PATH . '/config.php';
