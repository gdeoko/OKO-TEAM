/** Длина, после которой это уже не название, а описание группы. */
const IN_MAX_NAME = 160;

/**
 * Аббревиатуры организационных форм — остаются заглавными целиком.
 *
 * Короткие слова раскапслок и так не трогает, но формы вроде «ГБУДО» и «ФГБОУ»
 * длиннее порога и превратились бы в «Гбудо». Список закрытый: таких форм в
 * стране конечное число.
 */
const IN_ABBR = [
    'ГБУДО', 'МБУДО', 'МАУДО', 'МКУДО', 'ГАУДО', 'МБУДОД', 'МАУДОД', 'МБОУДО', 'МАОУДО',
    'МБУК', 'МАУК', 'ГБУК', 'МКУК', 'ГАУК', 'ОГБУК', 'ГБУКК', 'МБУКДО',
    'МБОУ', 'МАОУ', 'ГБОУ', 'МКОУ', 'ГАОУ', 'ФГБОУ', 'ФГАОУ', 'ГБПОУ', 'ГАПОУ', 'ОГБПОУ',
    'СПБГУ', 'МГИК', 'ГИТИС',
];

/**
 * Короткие слова, которые аббревиатурами НЕ являются.
 *
 * Раскапслок не трогает слова до четырёх букв — иначе «ДШИ» станет «Дши».
 * Но под тот же порог попадают обычные слова, и «ДОМ КУЛЬТУРЫ» превращался в
 * «ДОМ культуры». Список короткий, потому что коротких слов в названиях
 * учреждений немного.
 */
const IN_SHORT_WORDS = [
    'ДОМ', 'МИР', 'ЗАЛ', 'КЛУБ', 'ХОР', 'ЛУЧ', 'ЗВУК', 'СВЕТ', 'ДЕТИ', 'ГОД',
    'ПРИ', 'ДЛЯ', 'НАД', 'ПОД', 'ИЗ', 'ЗА', 'НА', 'ПО', 'ОТ', 'СЕЛА', 'СЕЛО',
];

/**
 * Приводит капслок к человеческому виду, сохраняя аббревиатуры.
 *
 * Короткие слова (до четырёх букв) не трогаем: там живут МБУ, ДО, ДШИ, ДК, ЦКР
 * и римские цифры. Длинные опускаем в строчные и поднимаем первую букву там,
 * где начинается фраза или закавыченное имя.
 */
function in_decaps(string $s): string {
    if ($s === '' || $s !== mb_strtoupper($s, 'UTF-8')) return $s;   // не капслок — не трогаем

    $out = preg_replace_callback('~\S+~u', static function (array $m): string {
        $w = $m[0];
        // Слово вместе с обрамляющими кавычками и скобками.
        if (preg_match('~^(\W*)(.+?)(\W*)$~u', $w, $p)) {
            [$pre, $core, $post] = [$p[1], $p[2], $p[3]];
        } else {
            [$pre, $core, $post] = ['', $w, ''];
        }
        // «ИМ.» — это «имени», а не аббревиатура, и в названии пишется строчными.
        if (mb_strtoupper($core, 'UTF-8') === 'ИМ') return $pre . 'им' . $post;
        // «№ 12», «XIX» и аббревиатуры вроде «МБУ», «ДШИ», «ГБУДО» — как есть.
        if (in_array(mb_strtoupper($core, 'UTF-8'), IN_SHORT_WORDS, true)) {
            return $pre . mb_strtolower($core, 'UTF-8') . $post;
        }
        if (mb_strlen($core) <= 4 || preg_match('~^[IVXLC]+$~u', $core)
            || in_array(mb_strtoupper($core, 'UTF-8'), IN_ABBR, true)) {
            return $w;
        }

        // Слитная запись через точки — «ИМ.А.Л.КОРЯГИНА». Инициалы обязаны
        // остаться заглавными, «ИМ» превращается в «им», фамилия — в Фамилию.
        if (mb_strpos($core, '.') !== false) {
            $parts = array_map(static function (string $seg): string {
                if ($seg === '') return $seg;
                if (mb_strtoupper($seg, 'UTF-8') === 'ИМ') return 'им';
                if (mb_strlen($seg) <= 2) return $seg;
                return mb_strtoupper(mb_substr($seg, 0, 1), 'UTF-8') . mb_strtolower(mb_substr($seg, 1), 'UTF-8');
            }, explode('.', $core));
            return $pre . implode('.', $parts) . $post;
        }
        return $pre . mb_strtolower($core, 'UTF-8') . $post;
    }, $s);

    // Первая буква названия и первая буква внутри кавычек — заглавная.
    $out = preg_replace_callback('~(^|[«"(\x{201C}]\s*)(\p{Ll})~u', static fn($m) => $m[1] . mb_strtoupper($m[2], 'UTF-8'), $out);
    // Фамилия после инициалов: «имени В.И. устинова» → «имени В.И. Устинова».
    $out = preg_replace_callback('~(\p{Lu}\.\s*(?:\p{Lu}\.\s*)?)(\p{Ll})~u',
        static fn($m) => $m[1] . mb_strtoupper($m[2], 'UTF-8'), $out);
    // Название населённого пункта: «ДК села луговое» → «ДК села Луговое».
    $out = preg_replace_callback(
        '~\b(сел[аоу]|город[ае]?|деревн[иию]|станиц[ыае]|посёлк[ае]|поселк[ае]|аул[аеу]?|пгт)\s+(\p{Ll})~u',
        static fn($m) => $m[1] . ' ' . mb_strtoupper($m[2], 'UTF-8'), $out);
    return $out;
}

/** Убирает мусор оформления и приводит кавычки к одному виду. */
function in_clean(string $s): string {
    $s = str_replace(["\xC2\xA0", "\t", "\r", "\n"], ' ', $s);
    $s = html_entity_decode($s, ENT_QUOTES | ENT_HTML5, 'UTF-8');
    // Угловые скобки здесь — это кавычки: «<<Название>>» и «<НАЗВАНИЕ>» так
    // набирают, когда ёлочек нет на клавиатуре. Разбираем их ДО strip_tags,
    // иначе тот примет «<АКУЛЁНОК>» за html-тег и вырежет вместе с названием.
    $s = str_replace(['<<', '>>', "''", '``'], ['«', '»', '«', '«'], $s);
    $s = preg_replace('~<([^<>]{2,60})>~u', '«$1»', $s);
    $s = strip_tags($s);
    // Прямые кавычки чередуются: нечётная открывает, чётная закрывает.
    $odd = true;
    $s = preg_replace_callback('~"~u', static function () use (&$odd): string {
        $q = $odd ? '«' : '»';
        $odd = !$odd;
        return $q;
    }, $s);
    // «МАУДО«Детская школа» — аббревиатура слиплась с названием, разделяем.
    $s = preg_replace('~(\p{L})«~u', '$1 «', $s);
    // Декор из групп ВКонтакте: звёздочки, блоки псевдографики, стрелки.
    $s = preg_replace('~[\x{2000}-\x{206F}\x{2190}-\x{27BF}\x{2580}-\x{259F}\x{25A0}-\x{25FF}\x{2B00}-\x{2BFF}\x{FE00}-\x{FE0F}\x{1F000}-\x{1FAFF}]~u', ' ', $s);
    $s = preg_replace('~\s+~u', ' ', $s);
    // Обрезка краёв ТОЛЬКО регулярным выражением: trim() с набором символов
    // режет по байтам, а у «–» и «—» второй байт совпадает с байтом буквы «р» —
    // «музыкальный театр» превращался в «теат».
    $s = preg_replace('~^[\s.,;:\-–—_|/\\\\]+|[\s.,;:\-–—_|/\\\\]+$~u', '', $s);
    return $s;
}

/** Итоговое название: чистка плюс раскапслок. Пустая строка — оставить как было. */
function in_fix_name(string $s): string {
    $out = in_decaps(in_clean($s));
    return mb_strlen($out) >= 3 ? $out : '';
}

/* ── Разбор ────────────────────────────────────────────────────────────── */

$apply = ($argv[1] ?? '') === 'apply';

$rows = all("SELECT id, name FROM institutions WHERE status <> 'invalid'");
$rename = [];
$junk   = [];

foreach ($rows as $r) {
    $id  = (int) $r['id'];
    $was = (string) $r['name'];

    if (mb_strlen($was) > IN_MAX_NAME) { $junk[$id] = 'описание вместо названия'; continue; }

    $now = in_fix_name($was);
    if ($now === '')  { $junk[$id] = 'пустое название после чистки'; continue; }
    if ($now !== $was) $rename[$id] = $now;
}

printf("Названий поправлено : %d\n", count($rename));
printf("Помечено непригодных: %d\n\n", count($junk));

if (!$apply) {
    echo "Сухой прогон. Примеры:\n";
    $i = 0;
    foreach ($rename as $id => $now) {
        $was = one("SELECT name FROM institutions WHERE id = ?", [$id]);
        echo "  было: ", $was['name'], "\n  стало: ", $now, "\n";
        if (++$i >= 10) break;
    }
    echo "\nПрименить: php scripts/normalize_institutions.php apply\n";
    exit(0);
}

$db = db();
$db->beginTransaction();
foreach ($rename as $id => $now) {
    q("UPDATE institutions SET name = ?, updated_at = datetime('now') WHERE id = ?", [$now, $id]);
}
foreach ($junk as $id => $why) {
    q("UPDATE institutions SET status = 'invalid', note = TRIM(COALESCE(note,'') || ' [' || ? || ']'),
              updated_at = datetime('now') WHERE id = ?", [$why, $id]);
}
$db->commit();

printf("Готово. Переименовано: %d, помечено непригодными: %d\n", count($rename), count($junk));
