<?php
/**
 * ОТВЕТ ABUSE-СЛУЖБЕ MAIL.RU ПО ЗАЯВКЕ О СНЯТИИ ОГРАНИЧЕНИЯ.
 *
 * 8 сентября служба ответила на обращение центра и попросила ровно одно:
 * полный текст отказа с Error code и Message ID — либо, если его нет, точный
 * адрес отправителя и получателя, дату и время проблемного письма.
 *
 * У центра есть и то, и другое: за один день накопилось три отказа с полными
 * заголовками, среди них — письмо на СОБСТВЕННЫЙ ящик центра на mail.ru. Это
 * лучший из возможных примеров: получатель наш, жалоб на нас он не подавал,
 * и никакой почтовой фильтрации на его стороне нет.
 *
 * Скрипт кладёт ответ в очередь на утро. НАРУЖУ НИЧЕГО НЕ УХОДИТ НОЧЬЮ —
 * письмо уйдёт в рабочее окно, как любое другое письмо центра.
 *
 * Тему менять НЕЛЬЗЯ: служба просила сохранять её вместе с номером заявки,
 * иначе ответ не приклеится к тикету и разбор начнётся сначала.
 *
 *   php scripts/mailru_ticket_reply.php --dry    — показать письмо
 *   php scripts/mailru_ticket_reply.php          — поставить в очередь на 09:05
 */
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { fwrite(STDERR, "CLI only\n"); exit(1); }

define('BASE_PATH', dirname(__DIR__));
$GLOBALS['CFG'] = require BASE_PATH . '/config.php';
require_once BASE_PATH . '/core/db.php';
require_once BASE_PATH . '/core/helpers.php';

$dry = in_array('--dry', array_slice($argv, 1), true);

const TICKET = '22770409S0637371360910665';
const SUBJ   = 'Re: [Ticket#' . TICKET . '] Просьба снять ограничение для домена музыкальный-мир.рф '
             . '(код 04596AAE73A74D5F1C2D4A681230C236667CFF232E7F46A89394563E85076A13)';

/* Берём отказы как есть, из входящих: пересказывать их своими словами нельзя —
 * служба просила ПОЛНЫЙ текст. */
$rows = all("SELECT received_at, body_text FROM inbox_messages
              WHERE received_at >= date('now','-3 days')
                AND (from_email LIKE 'mailer-daemon@%' OR subject LIKE '%едоставлен%')
              ORDER BY received_at DESC LIMIT 12");

$cases = [];
foreach ($rows as $r) {
    $b = (string) $r['body_text'];
    // Нас интересует только техническая часть — та, где адрес получателя,
    // ответ сервера, Error code и ID. Остальное письмо — вежливость Яндекса.
    if (!preg_match('~<([^>]+@[^>]+)>:\s*host\s+([^\s]+).*?Error code:\s*([0-9A-F]+)\.\s*ID:\s*([0-9A-F]+)~su', $b, $m)) continue;
    $tech = mb_substr(trim(mb_substr($b, (int) mb_strpos($b, '<' . $m[1] . '>'))), 0, 900);
    $cases[] = ['at' => (string) $r['received_at'], 'to' => $m[1], 'host' => $m[2],
                'code' => $m[3], 'id' => $m[4], 'tech' => $tech];
    if (count($cases) >= 3) break;
}

if (!$cases) { fwrite(STDERR, "не нашёл ни одного отказа с полными заголовками\n"); exit(1); }

$body = "Здравствуйте, Екатерина!\n\n"
      . "Высылаем полный текст отказов, как Вы просили. Отправитель во всех случаях —\n"
      . "kc@музыкальный-мир.рф (xn----7sbugdeiegh1b0a9hen.xn--p1ai), отправка через\n"
      . "SMTP Яндекс 360 (mail.yandex.net). Время московское.\n\n";

foreach ($cases as $i => $c) {
    $n = $i + 1;
    $body .= str_repeat('—', 60) . "\n"
           . "Случай $n\n"
           . "Отправитель: kc@музыкальный-мир.рф\n"
           . "Получатель:  {$c['to']}\n"
           . "Дата и время отправки: " . date('d.m.Y H:i', (int) strtotime($c['at'])) . " МСК\n"
           . "Error code: {$c['code']}\n"
           . "Message ID: {$c['id']}\n\n"
           . "Полный текст отказа:\n{$c['tech']}\n\n";
}

$body .= str_repeat('—', 60) . "\n\n"
       . "Обращаем внимание на первый случай: получатель kulturniy.centr.mir@mail.ru —\n"
       . "это собственный почтовый ящик нашего центра, он указан на наших бланках и\n"
       . "в справочниках. Жалоб на нас с этого адреса не поступало и поступить не могло.\n"
       . "Письмо на него отклоняется так же, как письма участникам, — то есть\n"
       . "ограничение действует на весь домен, независимо от получателя.\n\n"
       . "Дополнительно проверено 8 сентября: письмо с того же домена через сервис\n"
       . "рассылок Unisender Go (SPF, DKIM селектор gokey, DMARC настроены и проходят)\n"
       . "на тот же собственный ящик также не доставлено. Письмо с адреса\n"
       . "kulturniy.centr.mir@gmail.com на тот же ящик доставлено во «Входящие» —\n"
       . "то есть дело именно в репутации домена музыкальный-мир.рф.\n\n"
       . "Со своей стороны рассылку по вашим доменам мы остановили полностью и\n"
       . "возобновлять до снятия ограничения не будем. Готовы начать со ста писем в\n"
       . "сутки и только по своей базе участников — по адресам, которые люди оставили\n"
       . "нам сами при подаче заявки на конкурс.\n\n"
       . "Подскажите, пожалуйста, что ещё требуется с нашей стороны.\n\n"
       . "С уважением,\n"
       . "Ильясов Альберт Ильясович\n"
       . "Культурный центр «Музыкальный Мир»\n"
       . "kc@музыкальный-мир.рф · https://музыкальный-мир.рф\n";

if ($dry) {
    echo "КОМУ:  abuse@corp.mail.ru\n";
    echo "ТЕМА:  " . SUBJ . "\n";
    echo str_repeat('=', 70) . "\n" . $body;
    echo str_repeat('=', 70) . "\nЭто сухой прогон, письмо не поставлено в очередь.\n";
    exit(0);
}

// Уже стоит в очереди — второй раз не заводим: служба просила отвечать в тикет,
// а не заваливать его копиями.
$dup = (int) (scalar("SELECT COUNT(*) FROM mail_queue WHERE to_email='abuse@corp.mail.ru'
                       AND status IN ('queued','sent') AND created_at >= date('now','-1 day')") ?? 0);
if ($dup > 0) { echo "ответ по этой заявке уже в очереди или отправлен — второй раз не завожу\n"; exit(0); }

/* УТРО, А НЕ НОЧЬ. Правило центра: наружу ничего не уходит ночью и в
 * воскресенье. Ставим на ближайшее рабочее утро. */
$when = strtotime('tomorrow 09:05');
if ((int) date('N', $when) === 7) $when = strtotime('+1 day', $when);   // воскресенье пропускаем

$id = (int) insert('mail_queue', [
    'to_email'      => 'abuse@corp.mail.ru',
    'to_name'       => 'Abuse Team Mail.ru',
    'subject'       => SUBJ,
    'body'          => '<pre style="font:14px/1.5 monospace;white-space:pre-wrap">' . h($body) . '</pre>',
    'status'        => 'queued',
    /* PRIORITY У ОЧЕРЕДИ ЗНАЧИТ НЕ «ВАЖНОСТЬ», А «МАССОВОЕ».
     *
     * Ноль — личное письмо: подтверждение заявки, код входа, обращение в
     * ведомство. Больше нуля — массовая рассылка, и такие письма ждут пульта,
     * окна и суточных норм. Поставленная сгоряча единица отправила это письмо
     * в хвост двадцати двух тысяч застрявших писем на Mail.ru — оно и не ушло. */
    'priority'      => 0,
    'campaign_type' => 'official',
    'scheduled_at'  => date('Y-m-d H:i:s', $when),
    'created_at'    => date('Y-m-d H:i:s'),
]);

printf("ответ поставлен в очередь: письмо #%d, уйдёт %s\n", $id, date('d.m.Y H:i', $when));
printf("случаев в письме: %d\n", count($cases));
