function upsert_page(string $slug, string $title, string $body): void {
    $row = one("SELECT id FROM pages WHERE slug=?", [$slug]);
    if ($row) {
        update('pages', ['title' => $title, 'body' => $body, 'updated_at' => date('Y-m-d H:i:s')], 'id=:id', ['id' => (int) $row['id']]);
        echo "обновлено: $slug (" . mb_strlen($body) . " симв.)\n";
    } else {
        insert('pages', ['slug' => $slug, 'title' => $title, 'body' => $body]);
        echo "создано: $slug (" . mb_strlen($body) . " симв.)\n";
    }
}

