          . "придут на почту учреждения. Ответное письмо писать не нужно.\n"
          . $tail,
    ],
    6 => [
        'kind'  => 'club',
        'title' => 'КЛУБ УЧАСТНИКОВ',
        'text'  =>
            "Вступить в Клуб: {$site}/club\n"
          . "Все конкурсы: {$site}/konkursi\n\n"
          . "КЛУБ ПОСТОЯННЫХ УЧАСТНИКОВ Культурного центра «Музыкальный Мир» — для тех, кто участвует "
