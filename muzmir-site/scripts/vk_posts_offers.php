      . "👤 Личный кабинет: {$site}/cabinet\n"
      . "🤝 Партнёрам-учреждениям: {$site}/partner\n"
      . "🏆 Клуб участников: {$site}/club\n"
      . "🏛 Поддержка Министерства культуры: {$site}/ministry-support\n\n"
      . "💬 Мы на связи:\n"
      . "ВКонтакте: vk.ru/music_world.online\n"
      . "📞 Колл-центр: {$tel}\n\n"
      . "🕑 График (МСК): Пн–Пт 09:00–18:00, Сб 10:00–16:00, Вс — выходной.\n\n"
      . "🌍 С уважением, Оргкомитет Культурного центра «Музыкальный Мир» 🌍";

$OFFERS = [
    5 => [
        'kind'  => 'partner',
        'title' => 'ИНФОРМАЦИОННЫЙ ПАРТНЁР',
        'text'  =>
            "Стать информационным партнёром: {$site}/partner\n"
          . "Положения конкурсов: {$site}/konkursi\n\n"
          . "Культурный центр «Музыкальный Мир» приглашает школы искусств, музыкальные и художественные "
