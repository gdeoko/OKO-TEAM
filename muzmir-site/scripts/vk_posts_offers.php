echo "ЗАПИСИ ПАРТНЁРСТВА И КЛУБА\n$line\n";

foreach ($OFFERS as $slot => $o) {
    printf("\n--- слот %d · %s ---\n", $slot, $o['title']);

    if ($dry) {
        echo $o['text'] . "\n";
        printf("\n  символов: %d\n", mb_strlen($o['text']));
        continue;
    }

    // Афишу снимает scripts/make_offer_posters.php — страница /tests/offer-poster.php
    // в стиле нашего сертификата, всегда 1920×1080.
    $png = BASE_PATH . '/public/posters/offer_' . $o['kind'] . '_16x9.png';
    if (!is_file($png)) { echo "  афиши нет: сначала php scripts/make_offer_posters.php\n"; continue; }
    printf("  афиша: %s, %d КБ\n", basename($png), (int) round(filesize($png) / 1024));

    $exists = one("SELECT * FROM vk_posts WHERE slot=?", [$slot]);
    if ($exists && (int) $exists['source_post_id'] > 0) {
        q("UPDATE vk_posts SET title=:t, text=:x WHERE slot=:s",
          ['t' => $o['title'], 'x' => $o['text'], 's' => $slot]);
        echo "  запись уже опубликована ранее — обновлён только текст\n";
        continue;
    }

    // Публикуем у себя: по чужим сообществам должны расходиться настоящие записи
    // сообщества, а не заготовки, которых у нас самих нет.
    $att = vk_upload_wall_photo($png);
    if ($att === '') echo '  внимание: афишу загрузить не удалось (' . vk_upload_last_error() . ")\n";
    $r = vk_wall_post($o['text'], $att !== '' ? ['attachments' => $att] : []);
    if (isset($r['error'])) { echo '  публикация не удалась: ' . (string) ($r['error']['error_msg'] ?? '?') . "\n"; continue; }

    $pid = (int) ($r['response']['post_id'] ?? 0);
    $gid = (int) cfgv('vk_group_id', 211325055);
    printf("  опубликовано: vk.com/wall-%d_%d\n", $gid, $pid);

    q("INSERT INTO vk_posts (slot, kind, title, text, attachment, source_post_id, active)
       VALUES (:s,:k,:t,:x,:a,:p,1)
       ON CONFLICT(slot) DO UPDATE SET
         kind=excluded.kind, title=excluded.title, text=excluded.text,
         attachment=excluded.attachment, source_post_id=excluded.source_post_id, active=1",
      ['s' => $slot, 'k' => $o['kind'], 't' => $o['title'], 'x' => $o['text'],
       'a' => $att, 'p' => $pid]);
}

echo "\n$line\n  записей в наборе: " . (int) (scalar("SELECT COUNT(*) FROM vk_posts WHERE active=1") ?? 0) . "\n";
