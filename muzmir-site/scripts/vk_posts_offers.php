 * Повторный запуск не плодит записи: если слот уже занят записью со стены,
 * скрипт только обновит текст, а публиковать заново не станет.
 *
 *   php scripts/vk_posts_offers.php --dry     — показать тексты, ничего не делать
 *   php scripts/vk_posts_offers.php           — нарисовать, опубликовать, поставить в слоты
 */
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { fwrite(STDERR, "CLI only\n"); exit(1); }

define('BASE_PATH', dirname(__DIR__));
$GLOBALS['CFG'] = require BASE_PATH . '/config.php';
require_once BASE_PATH . '/core/db.php';
require_once BASE_PATH . '/core/helpers.php';
require_once BASE_PATH . '/core/outreach_window.php';
require_once BASE_PATH . '/core/vk_promo.php';


$dry  = in_array('--dry', $argv, true);
$line = str_repeat('=', 78);
$site = (string) cfgv('domain', 'музыкальный-мир.рф');
$tel  = (string) cfgv('org_phone', '');

if (!$dry && !outreach_window_guard(in_array('--force', $argv, true))) exit(0);

vkp_ensure();

/* Хвост записи — тот же, что у наших постов о конкурсах: человек привык
 * находить в нём ссылки и часы работы. */
$tail = "\n━━━━━━━━━━━━━━━━━━\n"
      . "🔗 РЕСУРСЫ И КОНТАКТЫ\n"
