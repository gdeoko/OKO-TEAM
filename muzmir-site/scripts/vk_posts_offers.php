          . "• Право использовать статус на сайте учреждения, в отчётности и информационных материалах.\n"
          . "• Персональную ссылку: заявки ваших учеников автоматически засчитываются учреждению.\n"
          . "• Кабинет партнёра на сайте: заявки, статистика участников, документы.\n"
          . "• С 5 заявок — благодарственные письма руководству и каждому педагогу-куратору, бесплатно.\n"
          . "• С 10 заявок — именной промокод на скидку 10% для участников учреждения.\n"
          . "• Приоритетную аттестацию: результаты и дипломы за 4 рабочих дня вместо пяти.\n\n"
