<?php
/**
 * РАЗБОР ВХОДЯЩИХ ПИСЕМ — НА ЖИВЫХ ФОРМУЛИРОВКАХ.
 *
 * От того, как понято письмо учреждения, зависит его судьба: «согласны» открывает
 * партнёрство и отправляет сертификат, «отказываемся» удаляет адрес навсегда.
 * До сих пор разборщик не видел ни одного настоящего ответа — партнёров ноль,
 * писем о согласии ноль. Значит, единственный способ убедиться, что он не
 * ошибётся на первом же живом письме, — прогнать его по тому, как люди пишут
 * на самом деле.
 *
 * Формулировки взяты не из головы: канцелярские обороты учреждений культуры и
 * ведомств, включая те, что уже приходили в ящик центра.
 *
 * ЦЕНА ОШИБКИ РАЗНАЯ, и проверка это учитывает:
 *   принять отказ за согласие  — учреждение получает сертификат, которого не
 *                                просило: стыдно, но поправимо;
 *   принять согласие за отказ  — адрес удаляется навсегда, партнёр потерян;
 *   не понять и отдать человеку — всегда допустимо.
 * Поэтому сомнительные формулировки обязаны уходить оператором, а не решаться
 * машиной.
 *
 *   php scripts/audit_inbox_classify.php
 */
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { fwrite(STDERR, "CLI only\n"); exit(1); }

define('BASE_PATH', dirname(__DIR__));
$GLOBALS['CFG'] = require BASE_PATH . '/config.php';
require_once BASE_PATH . '/core/db.php';
require_once BASE_PATH . '/core/helpers.php';
require_once BASE_PATH . '/core/inbox_reader.php';

$OK = 0; $BAD = 0;
$line = str_repeat('=', 78);

/**
 * @param string $box  ящик: novosti — учреждения, kc — ведомства
 * @param string $text текст письма
 * @param string $want ожидаемый разбор
 * @param string $note чем важен этот случай
 */
function want(string $box, string $text, string $want, string $note = ''): void {
    global $OK, $BAD;
    $got = inbox_classify($box, '', $text, false);
    $short = mb_substr(preg_replace('~\s+~u', ' ', $text) ?? '', 0, 62);
    if ($got === $want) { $OK++; printf("  [ок]   %-13s «%s…»\n", $got, $short); return; }
    $BAD++;
    printf("  [СБОЙ] ждали %-16s получили %-16s «%s…»%s\n", $want, $got, $short,
        $note !== '' ? "\n           ↳ " . $note : '');
}

echo "РАЗБОР ВХОДЯЩИХ ПИСЕМ\n$line\n";

/* ── Согласие учреждения ──────────────────────────────────────────────────── */
echo "\nСОГЛАСИЕ УЧРЕЖДЕНИЯ (открывает партнёрство)\n$line\n";
foreach ([
    'Здравствуйте! Мы согласны на участие в партнёрской программе.',
    'Добрый день. Подтверждаем согласие на сотрудничество с вашим центром.',
    'МБУ ДО «ДШИ №1» выражает согласие стать информационным партнёром.',
    'Готовы стать информационным партнёром, просим оформить статус.',
    'Принимаем ваше предложение о партнёрстве. Реквизиты во вложении.',
    'Мы заинтересованы в сотрудничестве, расскажите подробнее об условиях.',
    'Хотим стать информационным партнёром вашего центра.',
    'Согласны, направьте пожалуйста сертификат и доступ в кабинет.',
    'Информация доведена до сведения педагогического коллектива, согласны участвовать.',
] as $t) want('novosti', $t, 'partner_accept');

/* ── Отказ учреждения ─────────────────────────────────────────────────────── */
echo "\nОТКАЗ УЧРЕЖДЕНИЯ (адрес удаляется навсегда)\n$line\n";
foreach ([
    'Отказываемся от участия, спасибо за предложение.',
    'Мы не заинтересованы в подобных мероприятиях.',
    'Просим более не направлять письма на этот адрес.',
    'Исключите нас из рассылки, пожалуйста.',
    'В этом году участвовать не будем.',
    'Не планируем участие в конкурсах вашего центра.',
    'Отпишите нас от рассылки.',
] as $t) want('novosti', $t, 'partner_decline');

/* ── Вопрос: должен уходить человеку ──────────────────────────────────────── */
echo "\nВОПРОС ИЛИ НЕЯСНОЕ (уходит оператору)\n$line\n";
foreach ([
    ['Здравствуйте! Подскажите, какой размер оргвзноса и до какого числа приём?',
     'обычный вопрос об условиях'],
    ['Просим выслать положение конкурса в формате Word.', 'просьба о документе'],
    ['Ваше письмо получено, будет рассмотрено в установленном порядке.',
     'формальное подтверждение получения, решения тут нет'],
    ['Согласно положению о конкурсе, работы принимаются до 25 числа. Уточните, пожалуйста, порядок оплаты.',
     'СЛОВО «СОГЛАСНО» КАК ПРЕДЛОГ: принять его за согласие значит выдать сертификат тому, кто задал вопрос'],
    ['Нет, мы пока думаем.', 'слово «нет» само по себе не отказ'],
    ['Да, спасибо.', 'слово «да» само по себе не согласие'],
    ['Направляем заявку от нашего учреждения на конкурс «Величие России».', 'это заявка, а не ответ о партнёрстве'],
    ['Здравствуйте. Кто у вас руководитель? Хотим уточнить реквизиты для договора.', 'вопрос по реквизитам'],
] as [$t, $note]) want('novosti', $t, 'question', $note);

/* ── Ведомства ────────────────────────────────────────────────────────────── */
echo "\nВЕДОМСТВА (тот же разбор, но свои последствия)\n$line\n";
foreach ([
    ['Министерство культуры поддерживает проведение конкурса, информация направлена подведомственным учреждениям.',
     'ministry_approve'],
    ['Информация доведена до подведомственных учреждений культуры региона.', 'ministry_approve'],
    ['Оснований для информационной поддержки не имеется.', 'ministry_decline'],
    ['Не находим оснований для размещения информации на официальном сайте.', 'ministry_decline'],
    ['Не считаем возможным оказать поддержку данному мероприятию.', 'ministry_decline'],
    ['Ваше обращение зарегистрировано, вх. №89-23/01-06/1592 от 14.08.2026.', 'ministry_question'],
    ['Обращение перенаправлено по подведомственности в департамент культуры.', 'ministry_question'],
] as [$t, $want]) want('kc', $t, $want);

/* ── Служебные ────────────────────────────────────────────────────────────── */
echo "\nСЛУЖЕБНЫЕ\n$line\n";
want('novosti', 'Undelivered Mail Returned to Sender: user unknown', 'bounce');
want('novosti', 'Письмо не доставлено: почтовый ящик не существует', 'bounce');
$auto = inbox_classify('novosti', 'Автоответ', 'Я в отпуске до 30 августа.', true);
$auto === 'auto' ? printf("  [ок]   auto          автоответчик распознан\n") && $OK++
                 : printf("  [СБОЙ] автоответчик разобран как %s\n", $auto) && $BAD++;

/* ── Что дальше делает разбор ─────────────────────────────────────────────── */
echo "\nПОСЛЕДСТВИЯ РАЗБОРА\n$line\n";
$src = (string) @file_get_contents(BASE_PATH . '/cron/inbox_actions.php');
foreach ([
    'согласие ведёт к приёму в партнёры' => 'partner_accept(' . '$' . 'instId)',
    'после приёма уходит письмо с сертификатом' => 'partner_send_welcome(',
    'отказ действующего партнёра отдаётся человеку' => "=== 'accepted'",
    'согласие с неизвестного адреса не принимается вслепую' => 'нужен оператор',
    'название учреждения берётся из колонки name' => 'SELECT id, name, partner_status',
] as $what => $needle) {
    mb_strpos($src, $needle) !== false
        ? (printf("  [ок]   %s\n", $what) && $OK++)
        : (printf("  [СБОЙ] %s\n", $what) && $BAD++);
}

echo "\n$line\n";
printf("ПРОЙДЕНО: %d · СБОЕВ: %d\n", $OK, $BAD);
exit($BAD > 0 ? 1 : 0);
