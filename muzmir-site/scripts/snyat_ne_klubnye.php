<?php
/**
 * СНЯТЬ ЗАЯВКИ, ПОДАННЫЕ НЕ УЧАСТНИКАМИ КЛУБА В КОНКУРС «ТОЛЬКО ДЛЯ КЛУБА».
 *
 * Слово владельца 16.10.2026 (правила 72, 72а): приём заявок в платный конкурс
 * «Мировой акцент» идёт только от участников Элитного клуба. Признак
 * `competitions.club_entry_only` появился позже самих заявок, и четыре человека
 * успели подать до него - форма приняла, трое оплатили оргвзнос. Владелец
 * решил: заявки снять, написать людям с извинением за технический сбой,
 * предложить Клуб, а **возврат провести самому руками, в течение суток**.
 *
 * ДЕНЬГИ ЭТОТ ИНСТРУМЕНТ НЕ ДВИГАЕТ НИКОГДА (правило 8а). Обычная дверь
 * отклонения `grade_reject_application()` возвращает оргвзнос САМА, через кассу,
 * и своё письмо с причиной отправляет тоже сама - поэтому здесь дверь зовётся с
 * `без_возврата` и `без_письма`, а письмо собирает `core/club_entry_mail.php`.
 * Прямого UPDATE мимо двери тут нет намеренно: за отклонением тянется снятие
 * наградных материалов и возврат партнёрской скидки, и пропусти их - человек
 * останется с висящим дипломом.
 *
 * Ключи:
 *   --сухой            ничего не меняет и не отправляет, печатает письма словами
 *   --конкурс=<id>     только этот конкурс (по умолчанию все с признаком)
 *   --только=<номера>  через запятую, например MA-2026-00001,MA-2026-00004
 */
declare(strict_types=1);

require __DIR__ . '/../config.php';
require __DIR__ . '/../core/db.php';
require_once __DIR__ . '/../core/helpers.php';
require_once __DIR__ . '/../core/club.php';
require_once __DIR__ . '/../core/club_free.php';
require_once __DIR__ . '/../core/mailer.php';
require_once __DIR__ . '/../core/grade_apply.php';
require_once __DIR__ . '/../core/club_entry_mail.php';

$сухой   = in_array('--сухой', $argv, true) || in_array('--dry', $argv, true);
$конкурс = 0;
$только  = [];
foreach ($argv as $arg) {
    if (preg_match('~^--конкурс=(\d+)$~u', $arg, $m)) $конкурс = (int) $m[1];
    if (preg_match('~^--только=(.+)$~u', $arg, $m))   $только = array_filter(array_map('trim', explode(',', $m[1])));
}

/* ПРИЧИНА ПИШЕТСЯ В ЗАЯВКУ СЛОВАМИ И НЕ ОБЕЩАЕТ ВОЗВРАТА ТАМ, ГДЕ ДЕНЕГ НЕ БЫЛО.
   Первая сборка писала одну причину на все заявки, и у MA-2026-00004 в карточке
   стояло «оргвзнос возвращается вручную» при том, что обе попытки оплаты не
   завершились и центр не получил ничего: оператор прочитал бы это как долг. */
$ПРИЧИНА = static function (int $возврат): string {
    return 'Снято по решению оргкомитета: приём заявок на этот конкурс идёт только от '
         . 'участников Элитного клуба. Заявка принята формой сайта до появления проверки '
         . '(технический сбой). '
         . ($возврат > 0
             ? 'Оргвзнос ' . $возврат . ' ₽ возвращается оргкомитетом вручную, в течение суток.'
             : 'Оргвзнос в центр не поступал, возвращать нечего.');
};

$где = 'COALESCE(c.club_entry_only,0)=1';
$арг = [];
if ($конкурс > 0) { $где .= ' AND c.id=?'; $арг[] = $конкурс; }

$заявки = all("SELECT a.*, c.name comp FROM applications a
                JOIN competitions c ON c.id=a.competition_id
               WHERE $где AND COALESCE(a.status,'') <> 'rejected'
               ORDER BY a.id", $арг);

if ($только) {
    $заявки = array_values(array_filter($заявки, static fn(array $a): bool => in_array((string) $a['number'], $только, true)));
}

echo ($сухой ? "СУХОЙ ПРОГОН. " : "") . "Заявок к разбору: " . count($заявки) . "\n\n";

$снято = 0; $писем = 0; $кВозврату = 0;
foreach ($заявки as $a) {
    $id  = (int) $a['id'];
    $ном = (string) $a['number'];

    /* Участник Клуба заявку подал законно - его не трогаем. Членство живёт у
       номера пользователя, как и льгота на заявки без взноса. */
    $uid = (int) ($a['user_id'] ?? 0);
    if ($uid > 0 && function_exists('club_is_active') && club_is_active($uid)) {
        echo "  $ном - участник Клуба, заявка законна, не трогаем\n";
        continue;
    }

    /* Сумма к возврату - доля именно этой заявки. Берём `amount_paid`, а при
       нуле - удачный платёж по заявке: в `amount_paid` у старых заявок пусто,
       а у неоплаченных там лежит сумма ПОПЫТКИ (урок правила 66), поэтому
       решает `is_paid`. */
    $возврат = 0;
    if ((int) ($a['is_paid'] ?? 0) === 1) {
        $возврат = (int) ($a['amount_paid'] ?? 0);
        if ($возврат <= 0) {
            $возврат = (int) scalar("SELECT COALESCE(amount,0) FROM payments
                                      WHERE application_id=? AND status='succeeded'
                                      ORDER BY id DESC LIMIT 1", [$id]);
        }
    }

    $c = one("SELECT * FROM competitions WHERE id=?", [(int) $a['competition_id']]) ?: [];
    $м = club_entry_mail_html((array) $a, (array) $c, $возврат);

    echo "=== $ном  id=$id\n";
    echo "  кому: " . $м['email'] . ($м['name'] !== '' ? ' (' . $м['name'] . ')' : '') . "\n";
    echo "  к возврату: " . ($возврат > 0 ? $возврат . ' ₽ (владелец возвращает руками)' : 'нечего, денег не поступало') . "\n";
    echo "  тема: " . $м['subject'] . "\n";

    if ($сухой) {
        $t = preg_replace('~<(style|script)[^>]*>.*?</\1>~is', '', $м['html']);
        $t = preg_replace('~<(br|/p|/h1|/h2|/div|/tr|/table)[^>]*>~i', "\n", $t);
        $t = html_entity_decode(strip_tags($t), ENT_QUOTES | ENT_HTML5, 'UTF-8');
        $t = preg_replace('~[ \t]+~u', ' ', $t);
        $t = preg_replace('~\n\s*\n\s*\n+~u', "\n\n", trim($t));
        echo "  --- письмо словами ---\n" . $t . "\n  --- конец письма ---\n\n";
        $кВозврату += $возврат;
        continue;
    }

    /* Дверь одна, но без возврата и без её собственного письма. */
    $r = grade_reject_application($id, $ПРИЧИНА($возврат), 'jury', ['без_возврата' => true, 'без_письма' => true]);
    if (empty($r['ok'])) { echo "  НЕ СНЯТО: " . $r['msg'] . "\n\n"; continue; }
    $снято++;
    echo "  снято: " . $r['msg'] . "\n";

    $mid = club_entry_mail_send($id, $возврат);
    if ($mid > 0) { $писем++; echo "  письмо поставлено в очередь, id=$mid\n"; }
    else          { echo "  ВНИМАНИЕ: письмо не поставлено в очередь\n"; }
    $кВозврату += $возврат;
    echo "\n";
}

echo "Итог: " . ($сухой ? "сухой прогон, ничего не менялось" : "снято $снято, писем $писем")
   . ", к возврату вручную " . $кВозврату . " ₽\n";
