    ]);
    if ($stmt->rowCount() > 0) {
        $added++;
        printf("  [+] %-40s — %s\n", $a['slug'], $a['rubric']);
    } else {
        $skipped++;
        printf("  [=] %-40s — %s (уже есть, пропуск)\n", $a['slug'], $a['rubric']);
    }
}

