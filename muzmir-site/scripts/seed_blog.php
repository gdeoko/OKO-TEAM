    $meta = 'Рубрика: ' . $a['rubric'] . '. ' . $a['excerpt'];
    $stmt->execute([
        'slug'             => $a['slug'],
        'title'            => $a['title'],
        'body'             => trim($a['body']),
        'meta_description' => $meta,
        // updated_at задаём временем 12:00 — влияет и на порядок ленты, и на подпись «Обновлено».
