<?php
/**
 * ОТВЕТЫ ВЕДОМСТВ — РАЗБОР ПО ЖИВЫМ ФОРМУЛИРОВКАМ.
 *
 * Ведомство отвечает документом и канцелярским языком. От того, как понят его
 * ответ, зависит, что уйдёт обратно: благодарность за поддержку, вежливое
 * принятие отказа, переоформленное обращение или ничего. Ошибиться тут дорого:
 * поблагодарить за поддержку, которой не было, значит подставить центр перед
 * министерством.
 *
 * За всё время пришло четыре ответа, и все — уведомления о регистрации входящего.
 * Настоящих решений разборщик не видел ни разу. Поэтому прогоняем его по тому,
 * как ведомства пишут на самом деле: обороты взяты из канцелярской практики и
 * из уже полученных писем.
 *
 * Проверяется правиловый разбор (mrep_classify_rules) — он работает всегда, в том
 * числе когда модель недоступна, и именно он последнее слово при спорах.
 *
 *   php scripts/audit_ministry_verdicts.php
 */
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { fwrite(STDERR, "CLI only\n"); exit(1); }

define('BASE_PATH', dirname(__DIR__));
$GLOBALS['CFG'] = require BASE_PATH . '/config.php';
require_once BASE_PATH . '/core/db.php';
require_once BASE_PATH . '/core/data.php';
require_once BASE_PATH . '/core/helpers.php';
require_once BASE_PATH . '/core/mailer.php';
require_once BASE_PATH . '/core/ministry_reply.php';

$OK = 0; $BAD = 0;
$line = str_repeat('=', 78);

function verdict(string $text, string $want, string $note = ''): void {
    global $OK, $BAD;
    $r = mrep_classify_rules($text);
    $got = (string) $r['verdict'];
    $short = mb_substr(preg_replace('~\s+~u', ' ', $text) ?? '', 0, 64);
    if ($got === $want) { $OK++; printf("  [ок]   %-8s «%s…»\n", $got, $short); return; }
    $BAD++;
    printf("  [СБОЙ] ждали %-9s получили %-9s «%s…»%s\n", $want, $got, $short,
        $note !== '' ? "\n           ↳ " . $note : '');
}

echo "РАЗБОР ОТВЕТОВ ВЕДОМСТВ\n$line\n";

echo "\nПОДДЕРЖКА (уходит благодарность и наградной документ)\n$line\n";
verdict('Министерство культуры поддерживает проведение конкурса. Информация направлена подведомственным учреждениям культуры.', 'support');
verdict('Информация о конкурсе доведена до сведения руководителей детских школ искусств региона.', 'support');
verdict('Анонс конкурса размещён на официальном сайте министерства.', 'support');
verdict('Окажем содействие в информировании учреждений культуры области.', 'support');
verdict('Благодарим за приглашение, разместим информацию в наших каналах.', 'support');

echo "\nОТКАЗ (уходит вежливое принятие отказа, больше не пишем)\n$line\n";
verdict('Оснований для информационной поддержки не имеется.', 'refusal');
verdict('Не находим оснований для размещения информации на официальном сайте.', 'refusal');
verdict('Не считаем возможным оказать поддержку данному мероприятию.', 'refusal');
verdict('Проведение подобных мероприятий не входит в компетенцию департамента.', 'refusal');
verdict('В размещении информации отказано.', 'refusal');

echo "\nПРОСЯТ ПЕРЕОФОРМИТЬ (обращение отправляется заново)\n$line\n";
verdict('Обращение направлено не по адресу, просим уточнить адресата.', 'fix');
verdict('Просим переоформить обращение на бланке организации с подписью руководителя.', 'fix');
verdict('В обращении неверно указана должность адресата, просим направить повторно.', 'fix');
verdict('Обращение не будет зарегистрировано: отсутствуют реквизиты отправителя.', 'fix');

echo "\nЭЛЕКТРОННАЯ ПРИЁМНАЯ (это не отказ по существу)\n$line\n";
verdict('Обращения граждан принимаются только через электронную приёмную на официальном сайте.',
    'eform', 'начинается как отказ, но по существу нам не отказали — писать надо в другой канал');
verdict('Ваше обращение не может быть рассмотрено, направьте его через форму обратной связи.', 'eform');
verdict('Обращения принимаются через единый портал государственных услуг.', 'eform');

echo "\nРЕГИСТРАЦИЯ ВХОДЯЩЕГО (решения ещё нет)\n$line\n";
verdict('Ваше обращение зарегистрировано под вх. №89-23/01-06/1592 от 14.08.2026.', 'receipt');
verdict('Обращению присвоен входящий номер, ответ будет направлен в установленный срок.', 'receipt');
verdict('Ваше обращение принято к рассмотрению.', 'receipt');

echo "\nСЛУЖЕБНОЕ\n$line\n";
verdict('Delivery has failed to these recipients: user unknown 550', 'bounce');
verdict('Письмо недоставлено: адресат не существует.', 'bounce');

echo "\nНЕЯСНОЕ (уходит человеку, машина не решает)\n$line\n";
verdict('Здравствуйте. С кем можно связаться по вопросу проведения конкурса?', 'other');
verdict('Направляем вам список подведомственных учреждений для сведения.', 'other',
    'списки бывают и при поддержке, и просто так — решать должен человек');

/* ── Ответные письма собираются ───────────────────────────────────────────── */
echo "\nОТВЕТНЫЕ ПИСЬМА СОБИРАЮТСЯ\n$line\n";
$m = ['id' => 0, 'org' => 'Министерство культуры Московской области',
      'email' => 'audit@example.test', 'person' => 'Петров Пётр Петрович',
      'person_role' => 'Министру культуры Московской области', 'region' => 'Московская обл.'];
foreach ([
    'благодарность за поддержку' => fn() => mrep_reply_support($m, '16082026/1'),
    'принятие отказа'            => fn() => mrep_reply_refusal($m, '16082026/2'),
    'переоформление обращения'   => fn() => mrep_reply_fix($m, 'Иванов Иван Иванович', '16082026/3'),
] as $what => $fn) {
    try {
        $r = $fn();
        $subj = trim((string) ($r['subject'] ?? ''));
        $html = (string) ($r['html'] ?? $r['body'] ?? '');
        $txt  = trim(html_entity_decode(strip_tags($html), ENT_QUOTES | ENT_HTML5, 'UTF-8'));
        $bad = [];
        if ($subj === '') $bad[] = 'нет темы';
        if (mb_strlen($txt) < 120) $bad[] = 'тело почти пустое';
        if (preg_match('~\{\{[a-z_]+\}\}~i', $html)) $bad[] = 'осталась подстановка';
        if (!preg_match('~Уважаем|Здравствуйте~ui', $txt)) $bad[] = 'нет обращения';
        if ($bad) { $BAD++; printf("  [СБОЙ] %s — %s\n", $what, implode(', ', $bad)); }
        else { $OK++; printf("  [ок]   %s — «%s»\n", $what, mb_substr($subj, 0, 60)); }
    } catch (\Throwable $e) { $BAD++; printf("  [СБОЙ] %s — исключение: %s\n", $what, $e->getMessage()); }
}

/* ── Состояние автоответов ────────────────────────────────────────────────── */
echo "\nСОСТОЯНИЕ\n$line\n";
printf("  автоответы ведомствам: %s\n", mrep_enabled() ? 'включены' : 'ВЫКЛЮЧЕНЫ');
$OK++;
foreach (all("SELECT verdict, COUNT(*) n FROM ministry_replies GROUP BY 1 ORDER BY 2 DESC") as $r) {
    printf("  получено ответов с разбором «%s»: %d\n", (string) $r['verdict'], (int) $r['n']);
}

echo "\n$line\n";
printf("ПРОЙДЕНО: %d · СБОЕВ: %d\n", $OK, $BAD);
exit($BAD > 0 ? 1 : 0);
