/* ---------- Сборка ---------- */

if (!@copy($src, $dst)) { fwrite(STDERR, "Не удалось скопировать эталон\n"); exit(1); }
@chmod($dst, 0644);

$zip = new ZipArchive();
if ($zip->open($dst) !== true) { fwrite(STDERR, "Не открыть DOCX\n"); exit(1); }
$xml = (string) $zip->getFromName('word/document.xml');
if ($xml === '') { $zip->close(); fwrite(STDERR, "В DOCX нет document.xml\n"); exit(1); }

/** Все абзацы документа как есть. */
preg_match_all('~<w:p\b.*?</w:p>~su', $xml, $m);
$paras = $m[0];

/** Видимый текст абзаца. */
$plain = static function (string $p): string {
    $t = strip_tags(preg_replace('~<w:tab/>~', ' ', $p));
    return trim(html_entity_decode($t, ENT_QUOTES, 'UTF-8'));
};

/** Найти индекс первого абзаца, чей текст подходит под образец. */
$find = static function (array $paras, string $re, callable $plain, int $from = 0): int {
    foreach ($paras as $i => $p) {
        if ($i < $from) continue;
        if (preg_match($re, $plain($p))) return $i;
    }
    return -1;
};

/**
 * Новый абзац по образцу донора: сохраняем оформление, меняем только текст.
 *
 * Донор обязан быть ОДНОРУННЫМ по видимому тексту — иначе замена содержимого
 * первого <w:t> оставит хвост чужих слов. Поэтому в доноре гасим все прогоны
 * кроме первого, а в первый кладём нужный текст.
 */
$make = static function (string $donor, string $text): string {
    $out = $donor;
    $first = true;
    $out = preg_replace_callback('~<w:t(\s[^>]*)?>.*?</w:t>~su', function ($mm) use (&$first, $text) {
        if ($first) {
            $first = false;
            return '<w:t xml:space="preserve">' . htmlspecialchars($text, ENT_XML1 | ENT_QUOTES, 'UTF-8') . '</w:t>';
        }
        return '<w:t xml:space="preserve"></w:t>';
    }, $out);
    return $out;
};

$report = [];

/* 1. Блок про Клуб — под «Участие в конкурсе – бесплатное!» в ФИНАНСОВЫХ УСЛОВИЯХ. */
$iFin = $find($paras, '~^ФИНАНСОВЫЕ УСЛОВИЯ~u', $plain);
if ($iFin < 0) { $zip->close(); fwrite(STDERR, "Не найден раздел ФИНАНСОВЫЕ УСЛОВИЯ\n"); exit(1); }
$iFree = $find($paras, '~^Участие в конкурсе~u', $plain, $iFin);
if ($iFree < 0) { $zip->close(); fwrite(STDERR, "Не найдена строка про бесплатное участие\n"); exit(1); }

$donorFin = $paras[$iFree];
$blockFin = '';
foreach (CLUB_FINANCE as $line) $blockFin .= $make($donorFin, $line);
$xml = str_replace($paras[$iFree], $paras[$iFree] . $blockFin, $xml);
$report[] = 'ФИНАНСОВЫЕ УСЛОВИЯ: добавлено абзацев ' . count(CLUB_FINANCE);

/* 2. Пункт про фонд — после 4.4, перед «Пункт №5». */
$i44 = $find($paras, '~^4\.4\.~u', $plain);
if ($i44 < 0) { $zip->close(); fwrite(STDERR, "Не найден пункт 4.4\n"); exit(1); }

$donorFund = $paras[$i44];
$blockFund = '';
foreach (CLUB_FUND as $line) $blockFund .= $make($donorFund, $line);
$xml = str_replace($paras[$i44], $paras[$i44] . $blockFund, $xml);
$report[] = 'Пункт №4-А про призовой фонд: добавлено абзацев ' . count(CLUB_FUND);

$zip->addFromString('word/document.xml', $xml);
$zip->close();

echo "Собран: $dst\n";
foreach ($report as $r) echo "  · $r\n";

/* Проверка: документ открывается и новые строки в нём есть. */
$chk = new ZipArchive();
if ($chk->open($dst) !== true) { fwrite(STDERR, "ПРОВЕРКА: DOCX не открывается\n"); exit(1); }
$out = (string) $chk->getFromName('word/document.xml');
$chk->close();
$miss = 0;
foreach (array_merge(CLUB_FINANCE, CLUB_FUND) as $line) {
    $probe = mb_substr($line, 0, 40);
    if (mb_strpos(html_entity_decode(strip_tags($out), ENT_QUOTES, 'UTF-8'), $probe) === false) {
        echo "  ПРОПУЩЕНО: $probe…\n"; $miss++;
    }
}
echo $miss === 0 ? "ПРОВЕРКА: все строки на месте.\n" : "ПРОВЕРКА: не хватает строк — $miss\n";
exit($miss === 0 ? 0 : 1);
