foreach ($argv as $a) if (preg_match('~^--дни=(\d+)$~u', $a, $m)) $дни = max(1, (int) $m[1]);

/**
 * КОГДА ЗАСЛОНЫ ВСТАЛИ. Разделять прошлое и будущее здесь обязательно.
 *
 * Повторы, которые УЖЕ ушли людям, кодом не отменить: сообщение прочитано.
 * Если считать их провалом, проверка останется красной навсегда - а красное на
 * ровном месте и прячет настоящие отказы (правило 47). Поэтому сказанное до
 * этой черты печатается как известный и названный факт, а провалом считается
 * только то, что ушло ПОСЛЕ.
 *
 * Черта двигается ровно тогда, когда заслоны правятся, и ни для чего другого.
 */
const ЗАСЛОНЫ_С = '2026-10-14 21:00:00';

$ok = 0; $fail = 0;
function чек(string $имя, bool $усл, string $беда = ''): void {
    global $ok, $fail;
    if ($усл) { $ok++; echo "  ok   {$имя}\n"; }
    else { $fail++; echo "  FAIL {$имя}" . ($беда !== '' ? " - {$беда}" : '') . "\n"; }
}

echo "=== 1. ЗАСЛОНЫ НА МЕСТЕ И НЕ СЛЕПЫЕ\n";
foreach (['chat_dialogue_granica','chat_said_since_user','chat_closing_already',
          'chat_closing_short','chat_vk_kabinet_est','vk_import_outgoing',
          'chat_norm_text'] as $f) {
    чек("мерка {$f}() есть", function_exists($f));
}

/* Прощание собирается у чистого разговора и НЕ собирается там, где уже
   прощались. Ключи взяты заведомо несуществующие: проверка ничего не пишет. */
$чистый = 'audit_' . bin2hex(random_bytes(6));
$m = chat_closing_message('Иван', null, $чистый);
чек('у чистого разговора прощание собирается', trim($m) !== '', 'заслон ослеп, прощание не уйдёт никому');
чек('гостю в прощании есть приглашение', mb_strpos($m, 'Не забудьте пожалуйста зарегистрироваться') !== false);
$mu = chat_closing_message('Иван', 1, $чистый);
чек('участнику приглашения в прощании нет',
    mb_strpos($mu, 'Не забудьте пожалуйста зарегистрироваться') === false,
    'вошедшему предлагается завести кабинет, который у него есть (правило 38)');
чек('короткая строка не пустая и без ссылок',
    trim(chat_closing_short('Иван')) !== '' && mb_strpos(chat_closing_short('Иван'), 'http') === false);
чек('нормализация сводит \r\n и \n к одному виду',
    chat_norm_text("а\r\nб  в") === chat_norm_text("а\nб в"));

echo "\n=== 2. ЗАСЛОН СТОИТ В ИСТОЧНИКЕ, А НЕ В ОДНОМ ПУЛЬТЕ\n";
$brain = (string) file_get_contents(BASE_PATH . '/core/chat_brain.php');
чек('прощание само себя отбивает (внутри chat_closing_message)',
    (bool) preg_match('~chat_closing_already\(\$sk\)\s*\)\s*\{\s*return \'\';~u', $brain),
    'проверка только у вызывающих - четвёртая дверь откроется молча');
foreach ([['api/v1/chat.php','веб-чат сайта'],
          ['api/v1/webhook_vk.php','вебхук ВКонтакте'],
          ['cron/vk_bot_close.php','сторож закрытия']] as [$f, $что]) {
    $s = (string) file_get_contents(BASE_PATH . '/' . $f);
    чек("{$что} проверяет пустое прощание",
        (bool) preg_match('~trim\(\$(reply|msg)\)\s*===\s*\'\'~u', $s),
        "отправит пустоту или шаблон вторым разом ({$f})");
}
$wh = (string) file_get_contents(BASE_PATH . '/api/v1/webhook_vk.php');
чек('вебхук выравнивает историю по ВК до сборки ответа',
    mb_strpos($wh, 'vk_import_outgoing($peer, $sessionKey)') !== false,
    'ручные ответы оператора из ВК снова станут невидимы боту');
$cl = (string) file_get_contents(BASE_PATH . '/cron/vk_bot_close.php');
чек('сторож закрытия выравнивает историю по ВК', mb_strpos($cl, 'vk_import_outgoing($peer, $sk)') !== false);
чек('у сторожа закрытия стоят рабочие часы',
    mb_strpos($cl, 'chat_is_working_hours()') !== false,
    'прощания уйдут ночью и в воскресенье (правило 7)');
чек('сторож закрытия судит кабинет шире привязки',
    mb_strpos($cl, 'chat_vk_kabinet_est') !== false);
$ad = (string) file_get_contents(BASE_PATH . '/admin/chats.php');
чек('у операторского ответа есть антидубль по тексту',
    mb_strpos($ad, "-10 minutes") !== false,
    'двойное нажатие снова отправит участнику два одинаковых сообщения');
чек('заготовка прощания вторым разом из админки не уходит',
    mb_strpos($ad, 'chat_closing_already($sk)') !== false);

echo "\n=== 3. ГРАНИЦА РАЗГОВОРА СЧИТАЕТСЯ ОТ СЛОВА УЧАСТНИКА\n";
чек('память прощания не оглядывается на метку завершения',
    (bool) preg_match('~role=\'dialog_end\' AND id < \?~u', $brain),
    'метку ставит само прощание - по старой границе оно себя не видит');
чек('память судит и по времени, а не только по номеру',
    mb_strpos($brain, "COALESCE(created_at,'') >= ?") !== false,
    'подтянутый из ВК старый ответ выглядел бы свежим');
чек('приглашение зарегистрироваться считает по новой границе',
    (bool) preg_match('~function chat_signup_offered.{0,600}chat_said_since_user~su', $brain));
чек('«уже есть кабинет» считается приглашением',
    mb_strpos($brain, 'уже\s+есть\s+(?:личный\s+)?кабинет') !== false);

echo "\n=== 4. СРАВНЕНИЕ НОМЕРА СООБЩЕНИЯ ВК - БЕЗ COALESCE\n";
$ops = (string) file_get_contents(BASE_PATH . '/core/chat_ops.php');
чек('номер сверяется прямо по колонке',
    mb_strpos($ops, 'AND vk_msg_id = ?') !== false);
/* ПОЯСНЕНИЯ ВЫРЕЗАЕМ ПЕРЕД ПОИСКОМ. В самом chat_ops.php причина этой грабли
   написана словами и с примером `COALESCE(vk_msg_id,0)=?` - и проверка приняла
   бы разбор за код. Та же грабля, что у заслона «простое запрещено» (правило 40)
   и у проверки путей к бланкам (правило 48): мера краснеет на нашем же
   объяснении. */
$opsКод = (string) preg_replace(['~/\*.*?\*/~su', '~//[^\n]*~u'], '', $ops);
чек('COALESCE в сравнении номера нет',
    !preg_match('~COALESCE\(vk_msg_id,0\)\s*=\s*\?~u', $opsКод),
    'COALESCE снимает тип колонки, PDO отдаёт число строкой - равенства не бывает, и история копится дублями');
чек('ноль ищется явно', mb_strpos($ops, 'vk_msg_id IS NULL OR vk_msg_id = 0') !== false);
чек('колонка vk_msg_id заводится миграцией',
    mb_strpos((string) file_get_contents(BASE_PATH . '/core/db.php'), "'vk_msg_id'") !== false);
try {
    db()->query("SELECT vk_msg_id FROM chat_messages LIMIT 1")->fetchColumn();
    чек('колонка vk_msg_id есть в базе', true);
} catch (\Throwable $e) { чек('колонка vk_msg_id есть в базе', false, $e->getMessage()); }

echo "\n=== 5. ЖИВЫЕ РАЗГОВОРЫ: НЕТ ЛИ ПОВТОРОВ У ЛЮДЕЙ (за {$дни} дн.)\n";
/* Считаем ФАКТ по истории, а не доверяем заслонам на слово. */
$диалоги = all("SELECT DISTINCT session_key FROM chat_messages
                 WHERE created_at > datetime('now','localtime','-' || ? || ' days')
                   AND role='assistant'", [$дни]);
$бедаПрощание = []; $бедаПриглашение = []; $бедаДубль = [];
$прощаниеНовое = []; $приглашениеНовое = []; $дубльНовый = [];
foreach ($диалоги as $d) {
    $sk = (string) $d['session_key'];
    $rows = all("SELECT id, created_at, text FROM chat_messages
                  WHERE session_key=? AND role IN ('assistant','assistant_followup')
               ORDER BY id", [$sk]);
    $последнийВопрос = (string) (scalar("SELECT created_at FROM chat_messages
                                         WHERE session_key=? AND role='user'
                                           AND TRIM(COALESCE(text,''))<>''
                                      ORDER BY id DESC LIMIT 1", [$sk]) ?: '');
    $пр = 0; $пригл = 0; $виден = [];
    $прНовых = 0; $приглНовых = 0;      // то же, но после установки заслонов
    foreach ($rows as $r) {
        $t    = (string) $r['text'];
        $когда = (string) $r['created_at'];
        $новое = $когда >= ЗАСЛОНЫ_С;
        if ($последнийВопрос !== '' && $когда >= $последнийВопрос) {
            if (preg_match('~Благодарим Вас за обращение~ui', $t))               { $пр++;    if ($новое) $прНовых++; }
            if (preg_match('~Не забудьте пожалуйста зарегистрироваться~ui', $t)) { $пригл++; if ($новое) $приглНовых++; }
        }
        $k = mb_substr(chat_norm_text($t), 0, 120);
        if ($k !== '' && isset($виден[$k])) {
            $t1 = strtotime((string) $виден[$k]); $t2 = strtotime($когда);
            if ($t1 && $t2 && ($t2 - $t1) <= 600) {
                $бедаДубль[$sk] = ($бедаДубль[$sk] ?? 0) + 1;
                if ($новое) $дубльНовый[$sk] = ($дубльНовый[$sk] ?? 0) + 1;
            }
        }
        if ($k !== '') $виден[$k] = $когда;
    }
    if ($пр > 1)    $бедаПрощание[$sk] = $пр;
    if ($пригл > 1) $бедаПриглашение[$sk] = $пригл;
    if ($пр > 1 && $прНовых > 1)       $прощаниеНовое[$sk] = $прНовых;
    if ($пригл > 1 && $приглНовых > 1) $приглашениеНовое[$sk] = $приглНовых;
}
echo "  разговоров просмотрено: " . count($диалоги) . "\n";
$печать = static function (string $имя, array $m): void {
    foreach ($m as $sk => $n) echo "       {$sk}: {$n}\n";
};
echo "  ПРОШЛОЕ (до " . ЗАСЛОНЫ_С . ", кодом не отменить, печатается как факт):\n";
echo "       прощание повторялось в " . count($бедаПрощание) . " разговорах\n";
$печать('прощание', $бедаПрощание);
echo "       приглашение повторялось в " . count($бедаПриглашение) . " разговорах\n";
$печать('приглашение', $бедаПриглашение);
echo "       одинаковые подряд за 10 минут в " . count($бедаДубль) . " разговорах\n";
$печать('дубль', $бедаДубль);

echo "  ПОСЛЕ УСТАНОВКИ ЗАСЛОНОВ:\n";
чек('прощание после последнего слова участника не повторяется', count($прощаниеНовое) === 0,
    'повтор в ' . count($прощаниеНовое) . ' разговорах');
$печать('прощание', $прощаниеНовое);
чек('приглашение зарегистрироваться не повторяется', count($приглашениеНовое) === 0,
    'повтор в ' . count($приглашениеНовое) . ' разговорах');
$печать('приглашение', $приглашениеНовое);
чек('одинаковых сообщений подряд за 10 минут нет', count($дубльНовый) === 0,
    'дубли в ' . count($дубльНовый) . ' разговорах');
$печать('дубль', $дубльНовый);

echo "\n=== 6. ПРАВИЛО 45 В ОТВЕТАХ: ПОРЯДОК ЗАКАЗА\n";
$плохо = all("SELECT id, session_key, created_at FROM chat_messages
               WHERE role IN ('assistant','assistant_followup')
                 AND created_at > datetime('now','localtime','-' || ? || ' days')
                 AND (text LIKE '%как отдельно, так и вместе%'
                   OR text LIKE '%можно заказать отдельно от основного%'
                   OR text LIKE '%заказываются отдельно%')", [$дни]);
$живое = [];
foreach ($плохо as $p) {
    $t = (string) (scalar("SELECT text FROM chat_messages WHERE id=?", [(int) $p['id']]) ?: '');
    if (function_exists('chat_fix_dop_zakaz') && chat_fix_dop_zakaz($t) !== $t) $живое[] = $p;
}
$доЧерты = []; $послеЧерты = [];
foreach ($живое as $p) {
    if ((string) $p['created_at'] >= ЗАСЛОНЫ_С) $послеЧерты[] = $p; else $доЧерты[] = $p;
}
echo "  ПРОШЛОЕ: " . count($доЧерты) . " ответов до установки замка\n";
foreach ($доЧерты as $p) echo "       #{$p['id']} {$p['created_at']} {$p['session_key']}\n";
чек('после установки замка ложь про порядок заказа не уходила', count($послеЧерты) === 0,
    count($послеЧерты) . ' ответов уже с замком - значит замок не держит');
foreach ($послеЧерты as $p) echo "       #{$p['id']} {$p['created_at']} {$p['session_key']}\n";
чек('замок правит живую фразу из переписки 14.10',
    chat_fix_dop_zakaz('Вы можете заказать его как отдельно, так и вместе с основным дипломом.')
      !== 'Вы можете заказать его как отдельно, так и вместе с основным дипломом.');

echo "\nПРОВЕРОК: " . ($ok + $fail) . ", ok: {$ok}, FAIL: {$fail}\n";
exit($fail > 0 ? 1 : 0);
