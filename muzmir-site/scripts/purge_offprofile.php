/**
 * Поиск признака ПО НАЧАЛУ СЛОВА, а не по любому куску строки.
 *
 * Простой поиск подстроки едва не стоил нам полутора тысяч адресов: «Чебоксары»
 * содержат «бокс», и школа граффити из Чебоксар оказалась в списке на удаление
 * как боксёрская. Поэтому признак должен начинать слово: «бокс» найдётся в
 * «бокса» и «боксёрский», но не в «Чебоксарах».
 */
/**
 * Поиск признака КАК СЛОВА, а не как куска другого слова.
 *
 * Наивный поиск подстроки дважды едва не выкинул из базы настоящие школы
 * искусств: «Чебоксары» содержат «бокс», «Бокситогорская» — тоже. Поэтому
 * признак должен начинать слово и заканчиваться вместе с ним: после корня
 * допускается только короткое русское окончание. Звёздочка в конце признака
 * снимает ограничение там, где нужен именно префикс («татуировк*» ловит и
 * «татуировки», и «татуировкой»).
 */
$hit = static function (string $hay, array $words): string {
    foreach ($words as $w) {
        if ($w === '') continue;
        $loose = str_ends_with($w, '*');
        $core  = $loose ? mb_substr($w, 0, -1) : $w;
        $re = '~(?:^|[^а-яёa-z0-9])' . preg_quote($core, '~')
            . ($loose ? '' : '[а-яё]{0,3}(?![а-яёa-z])') . '~u';
        if (preg_match($re, $hay)) return $w;
    }
    return '';
};

echo "ЧИСТКА БАЗЫ ОТ ЧУЖОГО ПРОФИЛЯ\n$line\n";
printf("  учреждений в базе: %s\n", number_format((int) (scalar("SELECT COUNT(*) FROM institutions") ?? 0), 0, '.', ' '));

$rows = all("SELECT * FROM institutions
              WHERE COALESCE(partner_status,'') = ''
                AND COALESCE(replied_at,'') = ''
                AND id NOT IN (SELECT DISTINCT institution_id FROM applications WHERE institution_id<>0)");

$doomed = [];
foreach ($rows as $r) {
    $hay = ' ' . mb_strtolower((string) $r['name'] . ' ' . (string) $r['kind'] . ' ' . (string) $r['note']) . ' ';
    // Жёсткий признак решает сразу: «художественная татуировка» это татуировка.
    // Но творческое ядро сильнее его: студия танца остаётся студией танца,
    // сколько бы фитнеса ни было в названии.
    $hard = $hit($hay, HARD_OFF);
    if ($hard !== '' && $hit($hay, CORE_ART) === '') {
        $doomed[] = ['row' => $r, 'why' => $hard];
        continue;
    }
    if ($hard !== '') continue;
    if ($hit($hay, ON_PROFILE) !== '') continue;            // наш профиль — не трогаем
    $bad = $hit($hay, OFF_PROFILE);
    if ($bad === '') continue;
    $doomed[] = ['row' => $r, 'why' => $bad];
}

printf("  под чистку попадает: %s\n\n", number_format(count($doomed), 0, '.', ' '));
if (!$doomed) { echo "  чужого профиля не нашлось\n"; exit(0); }

/* Сводка по признакам: видно, что именно вычищается и не затесалась ли ошибка. */
$byWhy = [];
foreach ($doomed as $d) $byWhy[$d['why']] = ($byWhy[$d['why']] ?? 0) + 1;
arsort($byWhy);
echo "ПО ПРИЗНАКАМ\n$line\n";
foreach ($byWhy as $w => $c) printf("  %-24s %s\n", $w, number_format($c, 0, '.', ' '));

echo "\nПРИМЕРЫ\n$line\n";
foreach (array_slice($doomed, 0, 25) as $d) {
    printf("  %-52s [%s]\n", mb_substr((string) $d['row']['name'], 0, 52), $d['why']);
}
if (count($doomed) > 25) printf("  … и ещё %d\n", count($doomed) - 25);

/* Сколько писем этим адресатам ещё стоит в очереди. */
$queued = 0;
foreach ($doomed as $d) {
    $e = mb_strtolower(trim((string) $d['row']['email']));
    if ($e === '') continue;
    $queued += (int) (scalar("SELECT COUNT(*) FROM mail_queue WHERE status='queued' AND LOWER(to_email)=?", [$e]) ?? 0);
}
printf("\n  их писем ждёт отправки: %s\n", number_format($queued, 0, '.', ' '));

if ($dry) { echo "\n  сухой прогон: ничего не изменено\n"; exit(0); }

/* ── Чистка ── */
$moved = $unqueued = $vk = 0;
db()->beginTransaction();
try {
    foreach ($doomed as $d) {
        $r  = $d['row'];
        $id = (int) $r['id'];

        try { q("INSERT OR REPLACE INTO institutions_removed SELECT * FROM institutions WHERE id=?", [$id]); }
        catch (\Throwable $e) { /* архив не обязателен для самой чистки */ }

        $e = mb_strtolower(trim((string) $r['email']));
        if ($e !== '') {
            $st = q("UPDATE mail_queue SET status='cancelled', error='адресат не нашего профиля'
                      WHERE status='queued' AND LOWER(to_email)=?", [$e]);
            $unqueued += $st->rowCount();
        }

        $gid = (int) $r['vk_id'];
        if ($gid > 0) {
            try { q("DELETE FROM vk_targets WHERE group_id=?", [$gid]); $vk++; } catch (\Throwable $ex) {}
        }

        q("DELETE FROM institutions WHERE id=?", [$id]);
        $moved++;
    }
    db()->commit();
} catch (\Throwable $e) {
    db()->rollBack();
    echo "\n  ОШИБКА, ничего не изменено: " . $e->getMessage() . "\n";
    exit(1);
}

echo "\nСДЕЛАНО\n$line\n";
printf("  убрано из базы: %s (карточки лежат в institutions_removed)\n", number_format($moved, 0, '.', ' '));
printf("  снято с очереди писем: %s\n", number_format($unqueued, 0, '.', ' '));
printf("  убрано площадок ВКонтакте: %s\n", number_format($vk, 0, '.', ' '));
printf("\n  учреждений осталось: %s\n",
    number_format((int) (scalar("SELECT COUNT(*) FROM institutions") ?? 0), 0, '.', ' '));
