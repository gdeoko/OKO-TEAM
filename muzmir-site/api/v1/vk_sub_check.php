<?php
/**
 * «Я ПОДПИСАЛСЯ» — ПРОВЕРКА ПОДПИСКИ НА СООБЩЕСТВО ПО ПРОСЬБЕ ЧЕЛОВЕКА.
 *
 * Суточная сверка (cron/vk_subs_sync.php) рано или поздно увидит подписку сама,
 * но человек, который только что нажал «Подписаться» и вернулся за скидкой,
 * ждать до завтра не станет и решит, что бонус — обман. Поэтому здесь сверка
 * идёт немедленно и в обход кэша.
 *
 * Отвечаем честно в обе стороны: подписки нет — так и говорим, без «проверим
 * позже» и без обещаний. ВКонтакте не ответил — говорим и это: признак
 * остаётся прежним, человек ничего не теряет.
 *
 * POST, требует входа и привязанного ВКонтакте.
 */
declare(strict_types=1);
require __DIR__ . '/_boot.php';
require_post();

if (!csrf_check()) json_out(['ok' => false, 'error' => 'Сессия устарела, обновите страницу'], 403);

$u = current_user();
if (!$u) json_out(['ok' => false, 'error' => 'Требуется вход в кабинет'], 401);
$uid = (int) $u['id'];

require_once BASE_PATH . '/core/vk_subscriber.php';

$pct = vk_sub_bonus_pct();
if ($pct <= 0) json_out(['ok' => false, 'error' => 'Бонус за подписку сейчас не действует.'], 409);

if (trim((string) ($u['vk_id'] ?? '')) === '') {
    json_out([
        'ok'        => false,
        'need_bind' => true,
        'bind_url'  => url('/api/v1/oauth_vk?bind=1'),
        'error'     => 'Сначала свяжите аккаунт с ВКонтакте — иначе мы не узнаем Вас среди подписчиков.',
    ], 409);
}

$was = vk_sub_is($uid);
$now = vk_sub_check($uid, true);   // force: спрашиваем ВКонтакте прямо сейчас

json_out([
    'ok'         => true,
    'subscribed' => $now,
    'changed'    => $was !== $now,
    'percent'    => $now ? $pct : 0,
    'group_url'  => vk_sub_group_url(),
    'message'    => $now
        ? 'Спасибо, подписка есть! Скидка ' . $pct . '% на электронные наградные документы уже действует.'
        : 'Подписки пока не видим. Подпишитесь на сообщество и нажмите «Я подписался» ещё раз — проверим сразу.',
]);
