/**
 * Рубрика для конкретной заявки: сначала переопределение из админки, потом файл.
 * Возвращает и критерии, и уточнение по направлению, и текстовое описание для
 * модели — одно и то же знание в одном месте, чтобы не разъезжалось.
 */
function gr_rubric_for(string $nomination, string $subgroup = ''): array {
    $all = gr_rubrics();
    $key = trim($nomination);

    // Точное совпадение, иначе по началу строки (в заявках названия обрезаются),
    // иначе универсальная рубрика.
    $r = $all[$key] ?? null;
    if (!$r) {
        foreach ($all as $name => $row) {
            if ($name === '*') continue;
            if ($key !== '' && (mb_stripos($name, $key) === 0 || mb_stripos($key, $name) === 0)) { $r = $row; break; }
        }
    }
    if (!$r) $r = $all['*'];

    // Переопределение из админки, если владелец правил критерии руками.
    try {
        $db = one("SELECT payload FROM grading_rubrics WHERE nomination=? AND COALESCE(subgroup,'')=? LIMIT 1",
                  [$key, trim($subgroup)]);
        if ($db && trim((string) $db['payload']) !== '') {
            $j = json_decode((string) $db['payload'], true);
            if (is_array($j) && !empty($j['criteria'])) $r = $j;
        }
    } catch (\Throwable $e) { /* таблицы ещё нет — работаем по файлу */ }

    $sub = trim($subgroup);
    $r['sub_note'] = $sub !== '' ? (string) ($r['sub'][$sub] ?? '') : '';
    return $r;
}

/** Сумма весов рубрики — всегда должна давать 100, иначе балл поедет. */
function gr_weight_sum(array $rubric): int {
    $s = 0;
    foreach ((array) ($rubric['criteria'] ?? []) as $c) $s += (int) ($c['weight'] ?? 0);
    return $s;
}
