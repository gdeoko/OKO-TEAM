/**
 * ЗВАНИЕ ПО СУММЕ БАЛЛОВ (шкала 100).
 *
 * Границы взяты из практики конкурсов той же категории: Гран-при это не «лучший
 * из присланных», а работа безупречного уровня, поэтому 95 и выше, и в обычном
 * потоке таких единицы. Ниже 65 звания нет вовсе: участник получает диплом
 * участника, и это честнее, чем раздавать «дипломанта III» всем подряд.
 */
function gr_title_by_score(float $score): string {
    if ($score >= 95) return 'ГРАН-ПРИ';
    if ($score >= 90) return 'ЛАУРЕАТ I СТЕПЕНИ';
    if ($score >= 85) return 'ЛАУРЕАТ II СТЕПЕНИ';
    if ($score >= 80) return 'ЛАУРЕАТ III СТЕПЕНИ';
    if ($score >= 75) return 'ДИПЛОМАНТ I СТЕПЕНИ';
    if ($score >= 70) return 'ДИПЛОМАНТ II СТЕПЕНИ';
    if ($score >= 65) return 'ДИПЛОМАНТ III СТЕПЕНИ';
    return 'УЧАСТНИК КОНКУРСА';
}

/** Обратная граница: минимальный балл для звания (для проверок и отчётов). */
function gr_score_floor(string $title): float {
    $t = mb_strtoupper(trim($title));
    return match (true) {
        str_contains($t, 'ГРАН')                                  => 95.0,
        str_contains($t, 'ЛАУРЕАТ I ')  || str_contains($t, 'ЛАУРЕАТ I СТ') => 90.0,
        str_contains($t, 'ЛАУРЕАТ II ') || str_contains($t, 'ЛАУРЕАТ II С')  => 85.0,
        str_contains($t, 'ЛАУРЕАТ III')                            => 80.0,
        str_contains($t, 'ДИПЛОМАНТ I ') || str_contains($t, 'ДИПЛОМАНТ I С') => 75.0,
        str_contains($t, 'ДИПЛОМАНТ II ')|| str_contains($t, 'ДИПЛОМАНТ II С')=> 70.0,
        str_contains($t, 'ДИПЛОМАНТ III')                          => 65.0,
        default                                                    => 0.0,
    };
}

