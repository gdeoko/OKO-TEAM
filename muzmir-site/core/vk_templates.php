/**
 * ОСТАЛОСЬ 3 ДНЯ / ПОСЛЕДНИЙ ДЕНЬ — ОДИН сводный пост по всем открытым конкурсам.
 *
 * Заголовок считается ОТ ФАКТИЧЕСКОЙ ДАТЫ ПУБЛИКАЦИИ, а не от названия волны.
 * Волна, выпавшая на воскресенье, уходит в субботу (наружу в выходной не пишем),
 * и жёсткое «СЕГОДНЯ ПОСЛЕДНИЙ ДЕНЬ» в этот день было бы неправдой: приём идёт
 * ещё сутки, а в теле поста стоит настоящая дата окончания. Одно и то же
 * сообщение не должно спорить само с собой.
 */
function vkt_deadline(array $comps, bool $lastDay): string {
    $endTs = strtotime((string) ($comps[0]['end_date'] ?? ''));
    $left  = $endTs ? (int) floor((strtotime(date('Y-m-d', $endTs)) - strtotime(date('Y-m-d'))) / 86400) : ($lastDay ? 0 : 3);
    if ($lastDay) {
        $head = $left <= 0
            ? "❗️ВНИМАНИЕ! СЕГОДНЯ ПОСЛЕДНИЙ ДЕНЬ ПРИЁМА ЗАЯВОК❗️"
            : ($left === 1
                ? "❗️ВНИМАНИЕ! ЗАВТРА ПОСЛЕДНИЙ ДЕНЬ ПРИЁМА ЗАЯВОК❗️"
                : "❗️ВНИМАНИЕ! ОСТАЛОСЬ " . $left . " ДН.\nДО КОНЦА ПРИЁМА ЗАЯВОК❗️");
    } else {
        $head = $left > 0 && $left !== 3
            ? "❗️ВНИМАНИЕ! ОСТАЛОСЬ " . $left . " ДН.\nДО КОНЦА ПРИЁМА ЗАЯВОК❗️"
            : "❗️ВНИМАНИЕ! ОСТАЛОСЬ 3 ДНЯ\nДО КОНЦА ПРИЁМА ЗАЯВОК❗️";
    }
    $end = vkt_date_ru((string)($comps[0]['end_date'] ?? ''));
    return $head . "\n\n"
        . vkt_comp_lines($comps)
        . "\nПриём заявок завершается " . $end . " года (включительно до 18.00).\n\n"
        . "✅ Успейте подать заявку и пройти аттестацию компетентного жюри по профессионализму!\n\n"
        . vkt_contacts();
}

