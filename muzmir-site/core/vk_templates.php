/** Длинный конкурс (результаты публикуются пакетно датой) — по results_mode, НЕ по duration. */
function vkt_is_long(array $c): bool { return (string) ($c['results_mode'] ?? '') === 'list'; }

/** «Международный|Всероссийский» + падежи. */
function vkt_type(array $c, string $case = 'im'): string {
    $intl = ($c['type'] ?? '') === 'international';
    return match ($case) {
        'pr'    => $intl ? 'международном' : 'всероссийском',   // предложный
        'rod'   => $intl ? 'международного' : 'всероссийского', // родительный
        default => $intl ? 'Международный' : 'Всероссийский',
    };
}

function vkt_date_ru(?string $d): string {
    if (!$d) return '';
    $ts = strtotime($d);
    if (!$ts) return '';
    $m = [1=>'января',2=>'февраля',3=>'марта',4=>'апреля',5=>'мая',6=>'июня',
          7=>'июля',8=>'августа',9=>'сентября',10=>'октября',11=>'ноября',12=>'декабря'];
    return date('j', $ts) . ' ' . $m[(int)date('n', $ts)] . ' ' . date('Y', $ts);
}

