/** Длинный конкурс (результаты публикуются пакетно датой) — по results_mode, НЕ по duration. */
function vkt_is_long(array $c): bool { return (string) ($c['results_mode'] ?? '') === 'list'; }

/* СРОК АТТЕСТАЦИИ БЕРЁТСЯ У КОДА, А НЕ ВПИСЫВАЕТСЯ ЧИСЛОМ (правка владельца
   16.10.2026). У конкурса, который принимает заявки только от членов Клуба,
   срок три рабочих дня, а не общие пять (правила 72, 72г): все его участники
   клубные, а клубный срок короче. Число отдаёт единый источник
   `prioritet_dnei_konkursa()` - своя копия условия разошлась бы молча
   (правила 33, 35, 45, 47, 73). */
function vkt_srok_dnei(array $c): int {
    if (!function_exists('prioritet_dnei_konkursa') && defined('BASE_PATH')
        && is_file(BASE_PATH . '/core/prioritet.php')) {
        require_once BASE_PATH . '/core/prioritet.php';
    }
    return function_exists('prioritet_dnei_konkursa') ? (int) prioritet_dnei_konkursa($c) : 5;
}

/* В СВОДНОМ ПОСТЕ КОНКУРСОВ НЕСКОЛЬКО, И СРОК У НИХ БЫВАЕТ РАЗНЫЙ. Одно число
   можно назвать, только когда оно у всех коротких одно; иначе пост соврал бы
   половине читателей, и срок называет страница конкурса. */
function vkt_srok_korotkih(array $comps): string {
    $сроки = [];
    foreach ($comps as $c) { if (!vkt_is_long($c)) $сроки[vkt_srok_dnei($c)] = true; }
    $сроки = array_keys($сроки);
    sort($сроки);
    return count($сроки) === 1
        ? 'через ' . (function_exists('prioritet_dney') ? prioritet_dney((int) $сроки[0]) : (int) $сроки[0] . ' рабочих дней') . ' с даты подачи заявки'
        : 'в срок, указанный на странице каждого конкурса';
}

/** «Международный|Всероссийский» + падежи. */
function vkt_type(array $c, string $case = 'im'): string {
    $intl = ($c['type'] ?? '') === 'international';
    return match ($case) {
        'pr'    => $intl ? 'международном' : 'всероссийском',   // предложный
        'rod'   => $intl ? 'международного' : 'всероссийского', // родительный
        default => $intl ? 'Международный' : 'Всероссийский',
    };
}

function vkt_date_ru(?string $d): string {
    if (!$d) return '';
    $ts = strtotime($d);
    if (!$ts) return '';
    $m = [1=>'января',2=>'февраля',3=>'марта',4=>'апреля',5=>'мая',6=>'июня',
          7=>'июля',8=>'августа',9=>'сентября',10=>'октября',11=>'ноября',12=>'декабря'];
    return date('j', $ts) . ' ' . $m[(int)date('n', $ts)] . ' ' . date('Y', $ts);
}

