/** Блок «строка конкурса» для сводных постов (3 дня / последний день). */
function vkt_comp_lines(array $comps): string {
    $out = '';
    foreach ($comps as $c) {
        $flag = ($c['type'] ?? '') === 'international' ? '🌍' : '🇷🇺';
        $out .= $flag . ' ' . vkt_type($c) . ' многожанровый онлайн-конкурс культуры и искусства «'
            . mb_strtoupper(trim((string)$c['name'])) . "».\n"
            . '• Подать заявку: ' . VKT_SITE . '/konkurs-' . $c['slug'] . "\n"
            . '• Положение: ' . VKT_SITE . '/polozhenie-' . $c['slug'] . "\n";
    }
    return $out;
}

/** ЗАПУСК конкурса — отдельный пост на каждый конкурс (с афишей). Платный/бесплатный по-разному. */
function vkt_launch(array $c): string {
    $name   = mb_strtoupper(trim((string)$c['name']));
    $isPaid = (int)($c['is_paid'] ?? 0) === 1;
    $isLong = vkt_is_long($c);
    $fee    = $isPaid ? ('Оргвзнос за участие: ' . (int)$c['price'] . ' ₽.') : 'Участие БЕСПЛАТНОЕ.';
    // «в стоимость входит диплом» — ТОЛЬКО для платных.
    $incl   = $isPaid
        ? "В стоимость оргвзноса входит изготовление и отправка:\n1. Основной диплом (электронный).\n2. Дополнительный диплом (при наличии).\n\n"
        : '';
    // Результаты: длинный/бесплатный — датой публикации; платный короткий — 5 рабочих дней.
    $res = ($isLong && !empty($c['results_date']))
        ? 'Результаты конкурса будут опубликованы ' . vkt_date_ru((string)$c['results_date'])
          . ' на официальной странице сообщества ВКонтакте Культурного центра «Музыкальный Мир».'
        : 'Результаты конкурса приходят в течение 5 рабочих дней с даты подачи заявки на электронную почту, указанную в заявке.';

    return 'Подать заявку на конкурс: ' . VKT_SITE . '/konkurs-' . $c['slug'] . "\n"
        . 'Положение конкурса: ' . VKT_SITE . '/polozhenie-' . $c['slug'] . "\n"
        . 'Образцы наград: ' . VKT_SITE . '/obrazci-' . $c['slug'] . "\n\n"
        . 'Культурный центр «Музыкальный Мир» при информационной поддержке Министерства культуры'
        . ' и образования субъектов Российской Федерации и государственного портала «Про.Культура.РФ»'
        . ' приглашает принять участие в ' . vkt_type($c, 'pr') . ' многожанровом онлайн-конкурсе:' . "\n"
        . '«' . $name . '».' . "\n\n"
        . $fee . "\n\n"
        . $incl
        . "• Моментальный приём заявки.\n"
        . "• В дипломе не указывается, что конкурс проводится в формате онлайн.\n"
        . "• Без ограничений по возрасту, номинации, количеству заявок, количеству участников в номере и длительности конкурсного номера.\n"
        . "• Профессиональное компетентное жюри.\n"
        . "• Квалифицированная оценка членов жюри.\n\n"
        . 'Приём заявок до ' . vkt_date_ru((string)($c['end_date'] ?? '')) . " года (включительно).\n"
        . $res . "\n\n"
        . vkt_contacts();
}

/** ОСТАЛОСЬ 3 ДНЯ / ПОСЛЕДНИЙ ДЕНЬ — ОДИН сводный пост по всем открытым конкурсам. */
function vkt_deadline(array $comps, bool $lastDay): string {
    $head = $lastDay
        ? "❗️ВНИМАНИЕ! СЕГОДНЯ ПОСЛЕДНИЙ ДЕНЬ ПРИЁМА ЗАЯВОК❗️"
        : "❗️ВНИМАНИЕ! ОСТАЛОСЬ 3 ДНЯ\nДО КОНЦА ПРИЁМА ЗАЯВОК❗️";
    $end = vkt_date_ru((string)($comps[0]['end_date'] ?? ''));
    return $head . "\n\n"
        . vkt_comp_lines($comps)
        . "\nПриём заявок завершается " . $end . " года (включительно до 18.00).\n\n"
        . "✅ Успейте подать заявку и пройти аттестацию компетентного жюри по профессионализму!\n\n"
        . vkt_contacts();
}

/** ПРИЁМ ЗАКРЫТ — ОДИН сводный пост; для длинных с датой публикации результатов. */
function vkt_closed(array $comps): string {
    $lines = '';
    $longResults = '';
    foreach ($comps as $c) {
        $lines .= '- ' . vkt_type($c) . ' многожанровый онлайн-конкурс культуры и искусства «'
            . mb_strtoupper(trim((string)$c['name'])) . "»\n";
        if (vkt_is_long($c) && !empty($c['results_date'])) $longResults = vkt_date_ru((string)$c['results_date']);
    }
    $resBlock = $longResults !== ''
        ? "Аттестационные результаты длинных конкурсов будут опубликованы на официальной странице сообщества ВКонтакте Культурного центра «Музыкальный Мир» " . $longResults . " года.\nПо коротким конкурсам результаты приходят в течение 5 рабочих дней на почту из заявки.\n\n"
        : "Результаты по коротким конкурсам приходят в течение 5 рабочих дней с даты подачи заявки на почту, указанную в заявке.\n\n";
    return "❗ ВНИМАНИЕ ❗\nПриём заявок на участие:\n" . $lines
        . "❌ ОБЪЯВЛЯЕТСЯ ЗАКРЫТЫМ ❌\n\n"
        . $resBlock
        . "Благодарим всех конкурсантов за участие.\nЖелаем творческих успехов и новых побед.\n"
        . "Ждём вас на наших новых проектах и конкурсах.\n\n"
        . vkt_contacts();
}

