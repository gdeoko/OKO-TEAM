/** График работы центра. ЕДИНЫЙ, из настроек: вписанный руками устаревает молча. */
function vkt_hours(): string {
    $h = function_exists('cfgv') ? trim((string) cfgv('org_hours', '')) : '';
    if ($h === '') $h = 'Пн-Пт 09:00-18:00, Сб 10:00-16:00, Вс: (праздничные дни) ВЫХОДНОЙ (МСК)';
    // «(МСК)» в строке настроек уже есть, а подпись выше говорит «График (МСК)»:
    // второй раз не повторяем.
    $h = trim((string) preg_replace('~\s*\(МСК\)\s*$~u', '', $h));
    return rtrim($h, '. ') . '.';
}

