<?php
/**
 * ОБУЧЕНИЕ АССИСТЕНТА НА ЖИВЫХ ДИАЛОГАХ.
 *
 * Модель мы не дообучаем — это дорого и медленно. Растёт не модель, а то, что она
 * видит перед каждым ответом. Материал берётся из двух мест, и оба появляются сами
 * собой, пока люди работают:
 *
 *   ЭТАЛОНЫ СТИЛЯ. Когда оператор отвечает участнику из админки, это образец того,
 *   как в центре разговаривают на самом деле. Такие ответы помечаются и потом
 *   показываются модели как «вот так у нас принято».
 *
 *   УРОКИ. Когда оператор правит фразу бота, он молча говорит: «так — неправильно,
 *   а вот так — правильно». Обе версии сохраняются вместе с вопросом, и в следующий
 *   раз на похожий вопрос модель увидит исправленный вариант.
 *
 * Чем дольше работает центр, тем больше эталонов и уроков — и тем меньше ассистент
 * похож на робота, который отвечает шаблонами.
 */
declare(strict_types=1);

/** Колонка-метка и таблица уроков. Вызывается лениво, безопасно повторно. */
function chat_learn_migrate(): void {
    static $done = false;
    if ($done) return;
    $done = true;
    try { db()->exec("ALTER TABLE chat_messages ADD COLUMN by_operator INTEGER DEFAULT 0"); } catch (\Throwable $e) {}
    try {
        db()->exec("CREATE TABLE IF NOT EXISTS chat_lessons (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            question TEXT DEFAULT '',
            bad TEXT DEFAULT '',
            good TEXT DEFAULT '',
            session_key TEXT DEFAULT '',
            created_at TEXT DEFAULT (datetime('now','localtime'))
        )");
        db()->exec("CREATE INDEX IF NOT EXISTS idx_lessons_created ON chat_lessons(created_at DESC)");
    } catch (\Throwable $e) {}
}

/** Пометить сообщение как написанное живым оператором. */
function chat_learn_mark_operator(int $messageId): void {
    if ($messageId <= 0) return;
    chat_learn_migrate();
    try { q("UPDATE chat_messages SET by_operator=1 WHERE id=?", [$messageId]); } catch (\Throwable $e) {}
}

/** Вопрос участника, на который отвечало сообщение $messageId. */
function chat_learn_question_before(int $messageId): string {
    try {
        $r = one("SELECT session_key FROM chat_messages WHERE id=?", [$messageId]);
        if (!$r) return '';
        return trim((string) (scalar(
            "SELECT text FROM chat_messages
              WHERE session_key=? AND role='user' AND id<? AND text<>''
           ORDER BY id DESC LIMIT 1", [$r['session_key'], $messageId]) ?: ''));
    } catch (\Throwable $e) { return ''; }
}

/**
 * Записать урок: оператор исправил формулировку бота.
 * Пустые и косметические правки не сохраняем — учиться на них нечему.
 */
function chat_learn_lesson(int $messageId, string $before, string $after): void {
    chat_learn_migrate();
    $before = trim($before); $after = trim($after);
    if ($after === '' || $before === $after) return;
    if (mb_strlen($after) < 12) return;
    // Правка в пару символов — опечатка, а не урок.
    if (mb_strlen($before) > 0 && abs(mb_strlen($before) - mb_strlen($after)) < 6
        && mb_substr($before, 0, 20) === mb_substr($after, 0, 20)) return;
    $q = chat_learn_question_before($messageId);
    try {
        $sk = (string) (scalar("SELECT session_key FROM chat_messages WHERE id=?", [$messageId]) ?: '');
        insert('chat_lessons', ['question' => mb_substr($q, 0, 500), 'bad' => mb_substr($before, 0, 800),
                                'good' => mb_substr($after, 0, 800), 'session_key' => $sk]);
    } catch (\Throwable $e) {}
}

/**
 * Живые примеры стиля: пары «вопрос участника → ответ оператора».
 *
 * Берём последние ответы, написанные человеком, и к каждому — вопрос, на который он
 * отвечал. Короткие реплики вроде «да» или «спасибо» отбрасываем: стилю по ним не
 * научишься. Это и есть голос центра — не придуманный, а тот, которым здесь говорят.
 */
/**
 * ИМЯ В ЭТАЛОНАХ — СЕГОДНЯШНЕЕ, А НЕ ВЧЕРАШНЕЕ.
 *
 * Эталоны это настоящие ответы операторов, и в семи из них стоит «Меня зовут
 * Анастасия». Модель учится манере по ним и копирует имя буквально — сколько
 * ни пиши в правилах, что сегодня она Михаил. Поэтому в примерах имя
 * подменяется на то, которым помощник представляется этому человеку сегодня.
 *
 * Меняем ТОЛЬКО представление самого центра: после «Меня зовут» и после
 * «С уважением,». Имя участника в теле ответа («результаты для Нелиной
 * Анастасии») трогать нельзя — это чужое имя в чужом падеже, и подмена
 * превратила бы пример в бессмыслицу.
 */
function chat_learn_self_name(string $answer): string {
    if (!function_exists('chat_operator') || $answer === '') return $answer;
    $op  = chat_operator();
    $имя = (string) ($op['имя'] ?? '');
    if ($имя === '') return $answer;

    /* 1. ИМЯ. Меняем только представление самого центра: после «Меня зовут» и
          после «С уважением,». Имя участника в теле ответа («результаты для
          Нелиной Анастасии») трогать нельзя — это чужое имя в чужом падеже. */
    if (mb_strpos($answer, 'Анастасия') !== false) {
        $answer = preg_replace('~(Меня зовут\s+)Анастасия~u', '${1}' . $имя, $answer) ?? $answer;
        $answer = preg_replace('~(С уважением,\s*)Анастасия~u', '${1}' . $имя, $answer) ?? $answer;
    }

    if (!empty($op['она'])) return $answer;

    /* 2. РОД. Эталоны писала женщина, и рядом с её представлением стоит «рада
          помочь». Подставив мужское имя и оставив «рада», мы дали бы модели
          пример, который прямо спорит с правилом о роде, — а пример она слушает
          охотнее правила.
          СПИСОК ЗАКРЫТЫЙ, И ЭТО ВАЖНО. Слепая правка «всё женское в мужское»
          ломает ответ: в живом эталоне стоит «заявка ДОЛЖНА пройти через
          систему» и «наградная медаль», и «должен пройти» вышло бы ошибкой
          вместо исправления. Поэтому здесь только те слова, которыми оператор
          говорит о СЕБЕ и ни о чём другом (сверено по всем 208 эталонам).
          «готова» и «должна» в список НЕ входят намеренно: в этом корпусе они
          всегда про заявку или про наградной материал. */
    $себе = [
        'рада'            => 'рад',
        'могла'           => 'мог',
        'смогла'          => 'смог',
        'помогла'         => 'помог',
        'нашла'           => 'нашёл',
        'проверила'       => 'проверил',
        'перепроверила'   => 'перепроверил',
        'сверила'         => 'сверил',
        'посмотрела'      => 'посмотрел',
        'подсказала'      => 'подсказал',
        'продублировала'  => 'продублировал',
        'уточнила'        => 'уточнил',
        'оформила'        => 'оформил',
        'запросила'       => 'запросил',
        'подготовила'     => 'подготовил',
        'передала'        => 'передал',
        'связалась'       => 'связался',
    ];
    $из = $в = [];
    foreach ($себе as $ж => $м) {
        $из[] = '~\b' . $ж . '\b~u';                       $в[] = $м;
        $из[] = '~\b' . mb_strtoupper(mb_substr($ж, 0, 1)) . mb_substr($ж, 1) . '\b~u';
        $в[]  = mb_strtoupper(mb_substr($м, 0, 1)) . mb_substr($м, 1);
    }
    $out = preg_replace($из, $в, $answer);
    return is_string($out) ? $out : $answer;
}

/**
 * ОТВЕТ, ПРОТИВОРЕЧАЩИЙ ДЕЙСТВУЮЩЕМУ ПРАВИЛУ, В ОБУЧЕНИЕ НЕ ИДЁТ.
 *
 * Эталоны учат модель не только манере, но и содержанию: что сказано в примере,
 * то она и повторит. А правила центра меняются словом владельца, и вчерашний
 * верный ответ оператора сегодня становится неправдой.
 *
 * ЦЕНА ИЗВЕСТНА: 14.10.2026 бот написал Татьяне Волосатовой, что дополнительный
 * диплом «можно заказать как отдельно, так и вместе с основным». В правилах
 * бота обратное стоит дословно, но в эталонах лежал живой ответ оператора от
 * 03.09.2026: «Дипломы, Дополнительные Дипломы и Благодарственные письма
 * заказываются отдельно». Эталон перебил правило - та же грабля, что с именем
 * оператора (правило 34), только дороже: человеку назвали неверный порядок
 * заказа.
 *
 * Фильтр стоит в точке ПОДСТАНОВКИ, а не только при сборе: эталоны из истории
 * ВК пересобираются кроном каждую ночь заново (vk_style_learn --apply удаляет и
 * заливает снова), и правка одной записи руками вернулась бы к утру.
 *
 * Список узкий и проверяемый: каждый пункт - действующее жёсткое правило центра
 * со своим номером в памяти проекта. Общие рассуждения сюда не попадают, иначе
 * фильтр начнёт выбрасывать живые ответы.
 */
function chat_learn_obsolete(string $text): bool {
    $t = mb_strtolower($text);
    if (trim($t) === '') return false;

    /* Правило 45: дополнительный диплом, благодарность, кубок, статуэтка и медаль
       заказываются только вместе с основным или именным. «Заказываются отдельно»
       про эти позиции - устаревшая правда. Отличаем от честного «оплачиваются
       отдельно» (от участия): там нет связки с основным дипломом и нет слова
       «заказываются». */
    $предмет = '(дополнительн\w*\s+диплом|доп\.?\s*диплом|благодарственн|благодарност|кубок|статуэтк|медал)';
    if (!preg_match('~' . $предмет . '~u', $t)) return false;

    $оборот = [
        '~заказыва\w+\s+отдельно~u',
        '~как\s+отдельно,?\s*так\s+и\s+вместе~u',
        '~отдельно\s+от\s+основно~u',
        '~(?:можете|можно)\s+(?:его\s+)?заказать\s+отдельно~u',
    ];

    /* ОТРИЦАНИЕ ЭТО НЕ УТВЕРЖДЕНИЕ, И ЭТО ГЛАВНОЕ В ФИЛЬТРЕ.
     *
     * Та же грабля, что у заслона «простое запрещено» (правило 40): обороты
     * искались по всему тексту, и фильтр краснел на ответе, который как раз
     * ПРАВИЛЬНО называет правило словами — «отдельно от основного заявку на
     * изготовление подать нельзя». Замерено 14.10.2026 на письме-исправлении
     * для участницы: оно отбрасывалось целиком, то есть лучший учебный пример
     * по правилу 45 помощник не увидел бы никогда, а устаревшие остались бы.
     *
     * Поэтому судим по ПРЕДЛОЖЕНИЮ, в котором стоит оборот, и молчим, если в
     * нём же стоит запрет или прямое «это неверно»: так читается исправление,
     * а не устаревшая правда. */
    $запрет = '~нельзя|невозможн|не\s+получится|не\s+(?:может|могут|выда|оформ|заказ|удастся)'
            . '|только\s+вместе|неверн|ошибочн|это\s+не\s+так~u';

    foreach (preg_split('~(?<=[.!?])\s+~u', $t) as $фраза) {
        if (!preg_match('~' . $предмет . '~u', $фраза)) continue;
        if (preg_match($запрет, $фраза)) continue;
        foreach ($оборот as $re) if (preg_match($re, $фраза)) return true;
    }

    /* Предмет и оборот в РАЗНЫХ предложениях (так и вышло у бота 14.10:
       «Дополнительный диплом присуждается жюри… Вы можете заказать его как
       отдельно, так и вместе»). Тогда смотрим пару соседних предложений, и
       запрет в любой из них так же снимает подозрение. */
    $фразы = preg_split('~(?<=[.!?])\s+~u', $t);
    for ($i = 1; $i < count($фразы); $i++) {
        $окно = $фразы[$i - 1] . ' ' . $фразы[$i];
        if (!preg_match('~' . $предмет . '~u', $окно)) continue;
        if (preg_match($запрет, $окно)) continue;
        foreach ($оборот as $re) if (preg_match($re, $фразы[$i])) return true;
    }

    return false;
}

/**
 * ПОПРАВИМОЕ В ПРИМЕРЕ ПРАВИМ, А НЕ ВЫБРАСЫВАЕМ.
 *
 * Снятый телефон - не причина терять живой ответ оператора: прощание, в котором
 * он стоит, само по себе образцовое, негоден только номер. Выбросив такие
 * примеры целиком, помощник лишился бы пятнадцати уроков из ста двенадцати.
 *
 * ЗАМЕР 14.10.2026, И ЭТО ЖИВАЯ БЕДА: решение владельца от 12.10 оставило центру
 * ОДИН номер (+7 999 504-88-99), из положений и базы знаний снятый вычищен
 * (правило 33), но ОПЕРАТОР вручную копирует старый шаблон и отправляет людям
 * 89509459900 до сих пор - 110 ответов всего, 15 за последнюю неделю, последний
 * в тот же день в 12:21. Бот учится на ручных ответах оператора, значит без этой
 * подмены он перенял бы снятый номер прямо из свежих примеров.
 */
function chat_learn_fix_obsolete(string $text): string {
    if (trim($text) === '') return $text;
    $тел = trim((string) (function_exists('cfgv') ? cfgv('org_phone') : ''));
    if ($тел === '') return $text;
    /* Снятый номер пишут по-разному: слитно, через восьмёрку, с пробелами и
       дефисами. Перечисляем начертания, а не ловим любой телефон: чужие номера
       (трек-номера, номера заявок) трогать нельзя. */
    return (string) preg_replace(
        '~(?:\+7|8)?[\s\-]*\(?950\)?[\s\-]*945[\s\-]*99[\s\-]*00|(?:\+7|8)?[\s\-]*\(?950\)?[\s\-]*9459900~u',
        $тел, $text);
}

function chat_style_examples(int $limit = 8): string {
    chat_learn_migrate();
    $out = [];
    $seen = [];
    $topic = chat_topic_of((string) ($GLOBALS['chat_last_question'] ?? ''));

    $sameStart = 0;
    $add = static function (string $q, string $a) use (&$out, &$seen, &$sameStart, $limit): bool {
        if (count($out) >= $limit) return false;
        $q = trim($q); $a = chat_learn_self_name(chat_learn_strip_boiler($a));
        if (mb_strlen($q) < 10 || $a === '') return true;
        /* Устаревшее по действующим правилам в пример не берём: модель копирует
           содержание примера охотнее, чем слушает правило в промпте. */
        $a = chat_learn_fix_obsolete($a);
        if (chat_learn_obsolete($a)) return true;
        $key = mb_substr(mb_strtolower($a), 0, 60);
        if (isset($seen[$key])) return true;      // одна и та же фраза уже показана
        /* ОДНОТИПНЫХ ПРИМЕРОВ — НЕ БОЛЬШЕ ДВУХ.
         * У занятого оператора самый частый ответ — «подробную информацию узнаете
         * в положении по ссылке». Если показать модели пять таких примеров, она
         * решит, что это и есть работа помощника, и начнёт отсылать к документу
         * вместо ответа. Два примера показывают манеру, пять — портят помощника. */
        if (preg_match('~^(более подробн|подробн|ознакомьтесь)~ui', $a)) {
            if ($sameStart >= 2) return true;
            $sameStart++;
        }
        $seen[$key] = true;
        $out[] = 'Участник: ' . mb_substr($q, 0, 260) . "\nОтвет центра: " . mb_substr($a, 0, 420);
        return true;
    };

    /* СНАЧАЛА — ОТВЕТЫ ПО ЭТОЙ ЖЕ ТЕМЕ.
     *
     * Раньше брались просто последние операторские ответы, и на вопрос про диплом
     * модель видела три ответа про оргвзнос. Теперь сперва ищем, как в центре
     * отвечали на похожее, и только потом добираем свежими: манера у всех ответов
     * одна, а вот по делу учит только совпавший по теме. */
    try {
        $rows = all("SELECT id, session_key, text FROM chat_messages
                      WHERE by_operator=1 AND role='assistant' AND LENGTH(text)>60
                   ORDER BY id DESC LIMIT 200");
        $pool = [];
        foreach ($rows as $r) {
            $q = trim((string) (scalar(
                "SELECT text FROM chat_messages
                  WHERE session_key=? AND role='user' AND id<? AND text<>''
               ORDER BY id DESC LIMIT 1", [$r['session_key'], (int) $r['id']]) ?: ''));
            if ($q === '') continue;
            $pool[] = ['q' => $q, 'a' => (string) $r['text']];
        }
        if ($topic !== '') {
            foreach ($pool as $p) { if (chat_topic_of($p['q']) === $topic) $add($p['q'], $p['a']); }
        }
        foreach ($pool as $p) $add($p['q'], $p['a']);
    } catch (\Throwable $e) {}

    // ПЯТЬ ЛЕТ ПЕРЕПИСКИ СООБЩЕСТВА — тоже наши ответы, просто данные раньше.
    // Операторских ответов в новом чате пока десятки, а в сообществе их тысячи,
    // и именно там видно, как центр разговаривает: короткими репликами, без
    // канцелярита, с уточняющими вопросами вместо догадок. Образцы подбираются
    // под тему текущего вопроса (scripts/vk_style_learn.php раскладывает их по темам).
    if (count($out) < $limit) {
        try {
            $need = $limit - count($out);
            $rows = $topic !== ''
                ? all("SELECT question, answer FROM chat_style_samples WHERE topic=? ORDER BY RANDOM() LIMIT ?", [$topic, $need])
                : [];
            if (count($rows) < $need) {
                foreach (all("SELECT question, answer FROM chat_style_samples ORDER BY RANDOM() LIMIT ?",
                             [$need - count($rows)]) as $extra) $rows[] = $extra;
            }
            foreach ($rows as $r) $add((string) $r['question'], (string) $r['answer']);
        } catch (\Throwable $e) { /* образцов ещё нет — не беда */ }
    }

    if (!$out) return '';
    return "ТАК В ЦЕНТРЕ РАЗГОВАРИВАЮТ НА САМОМ ДЕЛЕ — живые ответы наших сотрудников из переписки "
         . "сообщества и чата. Держи эту интонацию, длину и манеру: коротко, по делу, без канцелярита, "
         . "с уточняющим вопросом вместо догадки. НЕ копируй дословно и НЕ повторяй чужую подпись — "
         . "говори так же, но своими словами:\n\n"
         . implode("\n\n", $out);
}

/**
 * КАНОН ЦЕНТРА — ОТВЕТЫ, КОТОРЫЕ ПОВТОРЯЮТ ПОЧТИ ДОСЛОВНО.
 *
 * Эталоны стиля учат манере: как здесь разговаривают. Но на десяток самых частых
 * вопросов у центра есть готовые формулировки, выверенные годами, и их владелец
 * правит у бота каждый раз, когда тот пересказывает их своими словами. «В случае
 * принятия Вами решения о необходимости наградного диплома (согласно
 * аттестационному результату)…» — это не стиль, это текст, который обязан
 * прозвучать так и не иначе.
 *
 * Поэтому канон отделён от эталонов: эталоны показывают, КАК говорить, канон —
 * ЧТО именно сказать по этим темам. Собирает его scripts/vk_style_learn.php из
 * повторов в переписке сообщества, ведёт владелец в админке.
 */
function chat_canon_migrate(): void {
    static $done = false;
    if ($done) return;
    $done = true;
    try {
        db()->exec("CREATE TABLE IF NOT EXISTS chat_canon (
            id         INTEGER PRIMARY KEY AUTOINCREMENT,
            topic      TEXT DEFAULT '',
            triggers   TEXT DEFAULT '',      -- примеры вопросов, по которым он подходит
            answer     TEXT NOT NULL,
            uses       INTEGER DEFAULT 0,    -- сколько раз так отвечали в переписке
            enabled    INTEGER DEFAULT 1,
            source     TEXT DEFAULT '',
            created_at TEXT DEFAULT '')");
    } catch (\Throwable $e) {}
}

/**
 * Блок канона для системного промпта — только по теме текущего вопроса.
 *
 * Весь канон разом в промпт не кладём: десяток готовых ответов перед глазами
 * превращает помощника в автомат, который выбирает ближайший шаблон вместо того,
 * чтобы читать вопрос. Показываем один-два по делу.
 */
function chat_canon_prompt(int $limit = 2): string {
    chat_canon_migrate();
    $q = (string) ($GLOBALS['chat_last_question'] ?? '');
    $topic = chat_topic_of($q);
    if ($topic === '') return '';

    /* КАНОН — ДЛЯ ВОПРОСА О СВОЁМ СЛУЧАЕ, А НЕ ДЛЯ СПРАВКИ.
     *
     * Самый частый канон центра — просьба назвать конкурс, ФИО и название номера.
     * Она к месту, когда человек спрашивает про СВОЮ заявку, оплату или награду:
     * «где мой диплом», «не пришёл результат». И она вредна, когда спрашивают
     * общее — «как подать заявку», «сколько стоит участие», «где положение»:
     * там ответ известен и без данных, а просьба их назвать выглядит как
     * отфутболивание. Проверка показала ровно это: на «Как подать заявку?» боту
     * подставлялось «Уточните ФИО конкурсанта».
     *
     * Признак личного случая — местоимение о себе или жалоба на то, что чего-то
     * нет. Признак справки — вопрос «как/сколько/где/можно ли» без них. */
    $l = mb_strtolower($q);
    $mine = (bool) preg_match('~\b(мо[йяёе]\w*|мне|меня|у меня|наш\w*|нам|нас|я\b)~u', $l)
         || (bool) preg_match('~не (пришл|получил|дошл|вижу|нашл|могу найти)|почему|куда дел|потерял~u', $l);
    $howto = (bool) preg_match('~^\s*(как|сколько|где|когда можно|что нужно|можно ли|какие|какой|есть ли)\b~u', $l);
    if ($howto && !$mine) return '';
    try {
        $rows = all("SELECT triggers, answer FROM chat_canon
                      WHERE enabled=1 AND topic=? ORDER BY uses DESC LIMIT ?", [$topic, $limit]);
    } catch (\Throwable $e) { return ''; }
    if (!$rows) return '';

    $out = [];
    foreach ($rows as $r) {
        $tr = trim((string) $r['triggers']);
        $out[] = ($tr !== '' ? 'Когда спрашивают: ' . mb_substr($tr, 0, 200) . "\n" : '')
               . 'Отвечай так: ' . trim((string) $r['answer']);
    }
    return "ГОТОВАЯ ФОРМУЛИРОВКА ЦЕНТРА ПО ЭТОЙ ТЕМЕ. Это выверенный текст, которым здесь отвечают "
         . "годами, — передай его смысл ПОЛНОСТЬЮ и теми же словами в главном (сроки, порядок действий, "
         . "ссылка, оговорки). Можно поправить обращение и убрать лишнее под вопрос человека, но не "
         . "пересказывай своими словами и ничего не добавляй от себя:\n\n" . implode("\n\n", $out);
}

/**
 * ОЧИСТКА ЭТАЛОНА ОТ ДЕЖУРНЫХ ФРАЗ.
 *
 * Оператор пишет короткими репликами: отдельно «Здравствуйте», отдельно суть,
 * в конце — «Благодарим Вас за обращение» с графиком работы и подписью. В базе
 * каждая реплика лежит отдельной строкой, и в эталоны стиля попадали именно
 * прощания: на вопрос «какой оргвзнос?» модель видела три примера, где центр
 * отвечает «рады были помочь», — и училась отвечать так же, ничего не сказав
 * по делу. Здесь дежурное отсекается: приветствие, прощание, справочный хвост
 * с телефоном и графиком. Остаётся то, ради чего человек и писал.
 *
 * Возвращает '' , если после чистки ничего содержательного не осталось.
 */
function chat_learn_strip_boiler(string $text): string {
    $t = trim($text);
    if ($t === '') return '';
    // Справочный хвост: всё от «В случае возникновения дополнительных вопросов»,
    // графика работы или подписи оргкомитета — это подпись, а не ответ.
    $cut = [
        'В случае возникновения дополнительных вопросов',
        'График работы',
        'С уважением, оргкомитет',
        'Ожидайте пожалуйста',
        'Ожидайте, пожалуйста',
        '🕑', '🌍',
    ];
    foreach ($cut as $marker) {
        $p = mb_strpos($t, $marker);
        if ($p !== false) $t = mb_substr($t, 0, $p);
    }
    /* ПРИВЕТСТВИЕ В НАЧАЛЕ — НЕ ЧАСТЬ ОТВЕТА.
     *
     * Оператор пишет «Здравствуйте Наталья.» отдельной строкой, а суть — со
     * следующей. Для эталона важна суть: приветствие мешает и разобрать пример,
     * и распознать отписку, спрятанную за ним. Убираем строку целиком и только
     * если она вся состоит из приветствия и имени — резать текст по словам
     * нельзя, так из «Здравствуйте. Информацию по заявке…» пропадало слово. */
    $lines = preg_split('~\R~u', trim($t)) ?: [];
    while ($lines && preg_match('~^(здравствуйте|добрый день|доброе утро|добрый вечер|доброго времени суток|приветствую)[\s,!.]*([А-ЯЁ][а-яё]+)?[\s,!.]*$~ui', trim((string) $lines[0]))) {
        array_shift($lines);
    }
    $t = trim(implode("\n", $lines));
    $t = trim($t);
    $plain = mb_strtolower(preg_replace('~[^\p{L}\d ]+~u', ' ', $t) ?? '');
    $plain = trim(preg_replace('~\s+~u', ' ', $plain) ?? '');
    $boiler = [
        '~^здравствуйте[а-яё ]*$~u',
        '~^благодарим вас за обращение~u',
        '~^рады были вам помочь~u',
        '~^доброго времени суток~u',
        '~^спасибо( вам)?( за обращение)?$~u',
        '~остались вопросы~u',
    ];
    foreach ($boiler as $re) if (preg_match($re, $plain)) return '';
    /* ОТСЫЛКА К ПОЛОЖЕНИЮ — НЕ ОБРАЗЕЦ ОТВЕТА.
     *
     * Занятой оператор часто отвечает одной фразой: «более подробную информацию
     * узнаете в положении по ссылке». Человеку так отвечать можно — он видит
     * собеседника и понимает, что тот спешит. Но как ЭТАЛОН для помощника это
     * яд: модель перенимает самое частое и начинает отправлять к документу
     * вместо ответа. Берём такие ответы в примеры только если после формулы
     * идёт что-то по существу — то есть текст заметно длиннее самой формулы. */
    if (preg_match('~^(более подробн|подробн|ознакомьтесь|ознакомиться)~ui', $t) && mb_strlen($t) < 260) return '';
    // Та же отписка, начатая с другого слова: «Информацию по срокам… Вы сможете
    // узнать, ознакомившись с положением…». Ловим по сути, а не по первому слову.
    if (preg_match('~(ознакомившись|ознакомьтесь|ознакомиться)[^.]{0,60}положени~ui', $t) && mb_strlen($t) < 320) return '';
    // После чистки должно остаться настоящее предложение, а не два слова.
    return mb_strlen($t) >= 40 ? $t : '';
}

/**
 * Тема вопроса — теми же словами, что и в разборе переписки.
 * Нужна, чтобы подсунуть образцы по делу: на вопрос о доставке показывать, как
 * центр отвечает про доставку, а не про оргвзнос.
 */
function chat_topic_of(string $q): string {
    $t = mb_strtolower(trim($q));
    if ($t === '') return '';
    $has = static fn(array $w): bool => (bool) array_filter($w, static fn($x) => mb_strpos($t, $x) !== false);
    if ($has(['возврат', 'вернуть деньги', 'верните']))                            return 'возврат';
    if ($has(['трек', 'посылк', 'почта росс', 'наложен', 'доставк', 'отправил']))  return 'доставка';
    if ($has(['благодарност', 'куратор', 'педагог', 'преподавател']))              return 'педагогу';
    if ($has(['партнёр', 'партнер', 'сотрудничеств']))                             return 'партнёрство';
    if ($has(['кубок', 'медал', 'статуэтк', 'оригинал', 'изготовлен']))            return 'заказ наград';
    if ($has(['диплом', 'наградн', 'результат', 'итог', 'звание', 'лауреат']))     return 'результаты';
    if ($has(['оплат', 'взнос', 'счёт', 'счет', 'квитанц', 'чек']))                return 'оплата';
    if ($has(['заявк', 'подать', 'участв', 'участие', 'номинац']))                 return 'заявка';
    if ($has(['положени', 'правил', 'требован', 'видео']))                         return 'положение';
    return '';
}

/**
 * Уроки, подходящие к текущему вопросу.
 *
 * Совпадение ищем по редким словам вопроса: короткие и служебные слова есть почти
 * везде и притянули бы случайные уроки. Если ничего похожего нет — отдаём несколько
 * свежих: даже общий урок полезнее пустоты.
 */
function chat_lessons_for(string $text, int $limit = 3): string {
    chat_learn_migrate();
    $words = [];
    foreach (preg_split('~[^\p{L}\d]+~u', mb_strtolower($text)) ?: [] as $w) {
        if (mb_strlen($w) >= 5) $words[] = $w;
    }
    $rows = [];
    try {
        if ($words) {
            $words = array_slice(array_unique($words), 0, 6);
            $cond = implode(' OR ', array_fill(0, count($words), 'LOWER(question) LIKE ?'));
            $args = array_map(fn($w) => '%' . $w . '%', $words);
            $args[] = $limit;
            $rows = all("SELECT question, bad, good FROM chat_lessons WHERE ($cond)
                      ORDER BY id DESC LIMIT ?", $args);
        }
        if (!$rows) $rows = all("SELECT question, bad, good FROM chat_lessons ORDER BY id DESC LIMIT ?", [$limit]);
        /* УРОК С УСТАРЕВШИМ ОТВЕТОМ УЧИТ НЕПРАВДЕ. В «good» лежит ответ, которым
           владелец заменил ответ бота, и он верен НА ТОТ ДЕНЬ: правила центра
           меняются его же словом. Поэтому урок проверяется тем же фильтром, что
           и эталоны (chat_learn_obsolete). */
        $rows = array_values(array_filter(array_map(static function (array $r): array {
            $r['good'] = chat_learn_fix_obsolete((string) ($r['good'] ?? ''));
            return $r;
        }, $rows), static function (array $r): bool {
            return !chat_learn_obsolete((string) ($r['good'] ?? ''));
        }));
    } catch (\Throwable $e) { return ''; }
    if (!$rows) return '';
    $out = [];
    foreach ($rows as $r) {
        $q = trim((string) $r['question']); $g = trim((string) $r['good']); $b = trim((string) $r['bad']);
        if ($g === '') continue;
        /* ПОКАЗЫВАЕМ КОНТРАСТ, А НЕ ТОЛЬКО ПРАВИЛЬНЫЙ ОТВЕТ.
         * Урок «правильный ответ такой» модель читает как ещё один эталон и
         * спокойно повторяет прежнюю ошибку рядом. Видно должно быть оба текста:
         * что написал бот и что вместо этого сказал старший оператор — тогда
         * заметна сама разница, ради которой урок и записан. */
        $line = ($q !== '' ? 'На вопрос «' . mb_substr($q, 0, 180) . '»:' : 'Случай:');
        if ($b !== '' && mb_substr(mb_strtolower($b), 0, 40) !== mb_substr(mb_strtolower($g), 0, 40)) {
            $line .= "\n  бот написал ТАК (неверно): " . mb_substr($b, 0, 260);
        }
        $line .= "\n  надо ТАК: " . mb_substr($g, 0, 400);
        $out[] = $line;
    }
    if (!$out) return '';
    return "РАНЬШЕ ЗДЕСЬ ОШИБАЛИСЬ, И СТАРШИЙ ОПЕРАТОР ПОПРАВИЛ. Не повторяй те ошибки:\n"
         . implode("\n", $out);
}

/**
 * Признаки машинного текста, которых быть не должно.
 *
 * Человека выдаёт не содержание, а обороты: канцелярит, дежурные «важно отметить»,
 * бесконечные тире и списки из трёх пунктов. Участник таких слов от девушки из
 * колл-центра не слышит — и как только они появляются, разговор начинает звучать
 * как переписка с автоответчиком.
 */
function chat_human_rules(): string {
    return 'ЖИВАЯ РЕЧЬ, А НЕ МАШИННАЯ. Запрещены обороты, по которым сразу узнают робота: '
         . '«важно отметить», «стоит подчеркнуть», «в современном мире», «играет важную роль», '
         . '«является ключевым», «не только… но и», «данный», «осуществляется», «необходимо отметить», '
         . '«в рамках», «с целью», «таким образом», «подводя итог». '
         . 'Не строй фразы из трёх однородных частей подряд — это машинный ритм. '
         . 'Не используй длинное тире как украшение и не разбивай короткий ответ на списки. '
         . 'Пиши простыми предложениями, как говоришь вслух: «Проверила — заявка принята, '
         . 'результат придёт на почту до пятницы». Обращайся на «Вы», но без канцелярита. '
         . 'Не начинай ответ с «Конечно!», «Отлично!», «Разумеется!» — живые люди так не пишут '
         . 'в каждой реплике. Лучше сразу к сути. '
         /* Правка владельца 13.10.2026: речь должна быть как у живого оператора. */
         . 'НЕ РАССКАЗЫВАЙ, А ОТВЕЧАЙ. Слова «расскажу», «расскажем», «рассказать» не употребляй: '
         . 'говори «отвечу на Ваши вопросы», «объясню», «поясню», «подскажу», «покажу, где посмотреть». '
         . 'Пиши так, как сказал бы живой оператор в трубку: обычными словами, без заготовленных '
         . 'формул и без пересказа вопроса перед ответом («Вы спрашиваете о сроках. Сроки такие…» — '
         . 'лишняя строка, человек свой вопрос помнит). Можно начать с глагола и ответить одной '
         . 'фразой: «Проверила, заявка принята», «Приём до 25 октября». Уместны живые связки '
         . '«смотрите», «если коротко», «тут просто»; неуместны «информируем Вас», «сообщаем, что», '
         . '«в соответствии с регламентом». Одно и то же слово два раза в соседних фразах не ставь.';
}
