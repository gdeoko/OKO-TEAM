<?php
/**
 * ПРИГЛАШЕНИЕ ЗАРЕГИСТРИРОВАТЬСЯ НА САЙТЕ ОТПРАВЛЯЕТСЯ ОДИН РАЗ ЗА ВСЮ ПЕРЕПИСКУ.
 *
 * Правило владельца от 20.10.2026, постоянное, для бота и для оператора.
 *
 * Блок «Не забудьте пожалуйста зарегистрироваться на нашем официальном сайте…»
 * с кабинетом, сообществом и клубом полезен ровно один раз: человек либо
 * зарегистрировался, либо решил не регистрироваться. На второй и третий раз это
 * читается как робот, который не помнит, что уже писал. К 20 октября блок ушёл
 * 108 раз в 71 разговор: пятнадцать человек получили его повторно, один —
 * восемь раз за пять дней.
 *
 * Почему он вообще повторяется. Текст не лежит шаблоном в коде — он въелся в
 * обучение: десять эталонов в chat_style_samples и одиннадцать уроков в
 * chat_lessons целиком состоят из него, поэтому модель считает его образцовым
 * ответом и подставляет к любому разговору. Операторы добавляли его руками
 * (88 отправок из 108). Чистка обучения одна не помогает: эталоны набираются
 * заново из переписки, а человек вставляет текст из своего буфера.
 *
 * Поэтому запрет стоит не в генерации, а на выходе — в точке, где ответ
 * ложится в chat_messages. Через неё проходит всё: сайт, ВКонтакте, ответ
 * оператора из админки, отложенная ночная очередь и прощание бота. Блок
 * вырезается из ответа, остальной текст доходит без изменений; если кроме
 * приглашения в сообщении ничего не было, не уходит ничего.
 */
declare(strict_types=1);

if (!defined('BASE_PATH')) define('BASE_PATH', dirname(__DIR__));

/**
 * Опознаёт блок приглашения.
 *
 * Текст у него плавающий: «VIP - Золотой клуб» и «ЭЛИТНЫЙ КЛУБ», с блоком
 * «ВНИМАНИЕ ВАЖНАЯ ИНФОРМАЦИЯ» и без него, с «кол. центр» и «оргкомитет» в
 * подписи — пять разных вариантов за два месяца. Общее у всех одно: призыв
 * зарегистрироваться на официальном сайте центра. По нему и опознаём.
 */
function chat_invite_present(string $text): bool {
    $t = mb_strtolower(preg_replace('~\s+~u', ' ', $text) ?? '');
    if ($t === '') return false;
    // «зарегистрироваться на нашем официальном сайте», «при регистрации на нашем
    // официальном сайте» — и то же самое без слова «нашем».
    if (preg_match('~(зарегистрироваться|регистраци[ияи]) на (нашем |вашем )?официальн~u', $t)) return true;
    // Запасной признак: призыв завести кабинет вместе со ссылкой на него.
    if (mb_strpos($t, 'не забудьте') !== false && mb_strpos($t, '/cabinet') !== false
        && preg_match('~регистр~u', $t)) return true;
    return false;
}

/**
 * Границы блока в разбитом по строкам тексте: [первая строка, последняя].
 *
 * Блок начинается призывом и кончается ссылкой на клуб — дальше идёт прощание
 * «Благодарим Вас за обращение», график работы и подпись, их трогать нельзя.
 * Если ссылки на клуб нет, останавливаемся на первой же строке прощания или
 * подписи, а без них — на конце текста.
 *
 * @return array{0:int,1:int}|null
 */
function chat_invite_bounds(array $lines): ?array {
    $from = -1;
    foreach ($lines as $i => $ln) {
        $l = mb_strtolower(trim($ln));
        if ($l === '') continue;
        if (preg_match('~(зарегистрироваться|регистраци[ияи]) на (нашем |вашем )?официальн~u', $l)
            || (mb_strpos($l, 'не забудьте') !== false && preg_match('~регистр~u', $l))) {
            $from = $i;
            break;
        }
    }
    if ($from < 0) return null;

    $to = count($lines) - 1;
    for ($i = $from; $i < count($lines); $i++) {
        $l = mb_strtolower(trim($lines[$i]));
        // Конец блока — ссылка на клуб: это последняя его строка.
        if (mb_strpos($l, '/club') !== false) { $to = $i; break; }
        // Начало прощания или подписи: блок кончился раньше, клуба в нём не было.
        if ($i > $from && (mb_strpos($l, 'благодарим вас за обращение') !== false
            || mb_strpos($l, 'с уважением') !== false
            || mb_strpos($l, 'рабочее время') !== false
            || mb_strpos($l, 'график работы') !== false)) { $to = $i - 1; break; }
    }
    return [$from, $to];
}

/** Вырезает блок приглашения, остальное оставляет как есть. */
function chat_invite_cut(string $text): string {
    $lines = preg_split('~\R~u', $text) ?: [];
    $b = chat_invite_bounds($lines);
    if (!$b) return $text;
    [$from, $to] = $b;
    for ($i = $from; $i <= $to; $i++) $lines[$i] = null;
    $out = implode("\n", array_filter($lines, static fn($l) => $l !== null));
    // Две и больше пустых строк подряд на месте выреза схлопываем в одну.
    $out = preg_replace('~\n{3,}~u', "\n\n", $out) ?? $out;
    return trim($out);
}

/**
 * Отправляли ли этому собеседнику приглашение РАНЬШЕ — за всю переписку.
 *
 * Ищем и по ключу разговора, и по аккаунту: у человека с сайта ключ меняется
 * при новой сессии, а user_id остаётся, и наоборот — у гостя ВКонтакте есть
 * только ключ vk_<id>. Канал не важен: бот это написал или оператор руками,
 * для получателя разницы нет.
 */
function chat_invite_sent_before(string $sessionKey, ?int $userId = null, int $exceptId = 0): bool {
    $sessionKey = trim($sessionKey);
    if ($sessionKey === '' && !$userId) return false;

    $where = [];
    $args  = [];
    if ($sessionKey !== '') { $where[] = 'session_key = ?'; $args[] = $sessionKey; }
    if ($userId)            { $where[] = 'user_id = ?';     $args[] = (int) $userId; }
    $who = '(' . implode(' OR ', $where) . ')';

    // Грубый отбор по базе, точное решение — chat_invite_present(): так
    // выборка остаётся короткой, а распознавание не зависит от формулировки.
    $sql = "SELECT text FROM chat_messages
             WHERE $who AND role IN ('assistant','operator')
               AND (text LIKE '%зарегистрироваться на наш%'
                 OR text LIKE '%регистрации на наш%'
                 OR text LIKE '%зарегистрироваться на официальн%')";
    if ($exceptId > 0) { $sql .= ' AND id <> ?'; $args[] = $exceptId; }
    $sql .= ' LIMIT 50';

    try { $rows = all($sql, $args); } catch (\Throwable $e) { return false; }
    foreach ($rows as $r) if (chat_invite_present((string) $r['text'])) return true;
    return false;
}

/**
 * Страж на выходе: пропускает ответ, но не даёт приглашению уйти дважды.
 *
 * @return array{text:string, cut:bool} text — что отправлять ('' = не отправлять ничего)
 */
function chat_invite_guard(string $text, string $sessionKey, ?int $userId = null): array {
    if (trim($text) === '' || !chat_invite_present($text)) return ['text' => $text, 'cut' => false];
    if (!chat_invite_sent_before($sessionKey, $userId)) return ['text' => $text, 'cut' => false];

    $clean = chat_invite_cut($text);
    // Вырезали, а текст не изменился — значит границы не нашлись (формулировка
    // новая). Лучше отдать как есть, чем промолчать: повтор приглашения хуже
    // немого бота, но немой бот хуже обоих.
    if ($clean === trim($text)) return ['text' => $text, 'cut' => false];
    return ['text' => $clean, 'cut' => true];
}
