/**
 * Спросить модель и получить JSON. Ключи и очередь моделей берём те же, что у
 * чат-бота: у пары ключей «Музыкального Мира» своя квота, и смешивать её с парой
 * ОКО нельзя — квота одного проекта не должна съедать другой.
 */
function smm_ask_json(string $prompt, int $timeout = 90): ?array {
    $keys = function_exists('chat_gemini_keys') ? chat_gemini_keys() : [];
    if (!$keys) {
        $raw = trim((string) (cfgv('gemini_api_keys') ?: cfgv('gemini_api_key') ?: ''));
        $keys = $raw !== '' ? preg_split('~[,\s]+~', $raw) ?: [] : [];
    }
    if (!$keys) return null;

    $models = array_values(array_filter(array_map('trim',
        preg_split('~[,\s]+~', (string) (cfgv('gemini_models') ?: '')) ?: [])));
    /* СНЯТАЯ МОДЕЛЬ СТОЯЛА ПЕРВОЙ, И КАЖДЫЙ ВОПРОС НАЧИНАЛСЯ С ОТКАЗА.
       gemini-2.5-flash отвечает 404 «no longer available to new users»: Google
       закрыл её для новых проектов. Перебор молча шёл дальше, но первый заход
       каждого ключа уходил впустую. Берём живые: latest-псевдонимы не протухают. */
    if (!$models) $models = ['gemini-flash-latest', 'gemini-3-flash-preview', 'gemini-flash-lite-latest'];

    $base = rtrim((string) (cfgv('gemini_base_url') ?: 'https://generativelanguage.googleapis.com'), '/');

    /* КЛЮЧ, КОТОРОМУ СКАЗАЛИ «ПРИХОДИ ЧЕРЕЗ ДВА ЧАСА», НЕ ДЁРГАЕМ ДВА ЧАСА.
     *
     * У бесплатного ключа дневная норма - ДВАДЦАТЬ запросов. Конвейер просыпается
     * каждый час и на каждый слот делает до шести заходов за темой, плюс проверка
     * факта и текст: норма сгорала к утру, и дальше сутки напролёт приходило 429.
     * Снаружи это выглядело как «тема не нашлась» - не как кончившаяся квота.
     * Теперь служба сама говорит, через сколько прийти («Please retry in 2h6m»),
     * и до этого часа ключ отдыхает. Отдых у каждого ключа свой: платный и
     * бесплатный упираются в разные стены. */
    $rest = json_decode((string) setting('smm_brain_rest', '{}'), true);
    if (!is_array($rest)) $rest = [];
    $now  = time();
    $live = [];
    foreach ($keys as $key) {
        $h = substr(md5((string) $key), 0, 8);
        if ((int) ($rest[$h] ?? 0) > $now) continue;
        $live[] = $key;
    }
    if (!$live) {
        /* Отдыхают все — повторять шесть заходов подряд незачем: ответ будет тот
           же. Ставим метку, по ней вызывающий прекращает перебор и пишет в
           журнал час, когда мозг снова заговорит. */
        $soon = min(array_map('intval', $rest ?: [0]));
        $GLOBALS['SMM_BRAIN_RESTING'] = $soon ?: $now;
        smm_log_brain('все ключи Gemini отдыхают до ' . date('H:i', $soon ?: $now));
        return smm_ask_json_fallback($prompt, $timeout);
    }
    $GLOBALS['SMM_BRAIN_RESTING'] = 0;

    foreach ($live as $key) {
        foreach ($models as $model) {
            $url = "{$base}/v1beta/models/{$model}:generateContent?key=" . urlencode($key);
            $body = json_encode([
                'contents' => [['role' => 'user', 'parts' => [['text' => $prompt]]]],
                'generationConfig' => [
                    'temperature'      => 1.0,   // темы обязаны быть разными — низкая температура даёт одно и то же
                    'maxOutputTokens'  => 4096,
                    'responseMimeType' => 'application/json',
                ],
            ], JSON_UNESCAPED_UNICODE);

            $ch = curl_init($url);
            curl_setopt_array($ch, [
                CURLOPT_POST => true,
                CURLOPT_POSTFIELDS => $body,
                CURLOPT_HTTPHEADER => ['Content-Type: application/json'],
                CURLOPT_RETURNTRANSFER => true,
                CURLOPT_TIMEOUT => $timeout,
            ]);
            $res  = curl_exec($ch);
            $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
            curl_close($ch);

            if ($code === 429) {
                /* Служба называет срок сама: «Please retry in 7583.1s» или
                   «in 2h6m23s». Берём его, а не выдумываем свой. */
                $wait = 0;
                if (is_string($res) && preg_match('~retry in ([0-9hms\.]+)~i', $res, $m)) {
                    if (preg_match('~^([0-9.]+)s?$~', $m[1], $mm)) $wait = (int) $mm[1];
                    else {
                        preg_match('~(\d+)h~', $m[1], $h1); preg_match('~(\d+)m~', $m[1], $m1);
                        $wait = ((int) ($h1[1] ?? 0)) * 3600 + ((int) ($m1[1] ?? 0)) * 60;
                    }
                }
                if ($wait <= 0) $wait = 1800;                      // молчит о сроке — полчаса
                $hk = substr(md5((string) $key), 0, 8);
                $rest[$hk] = $now + min($wait, 86400);
                set_setting('smm_brain_rest', json_encode($rest));
                smm_log_brain("ключ упёрся в квоту, отдыхает до " . date('H:i', $rest[$hk]));
                continue 2;                                        // другая модель тем же ключом не поможет
            }
            if ($code === 503) continue;                           // перегрузка — следующая модель
            if ($code !== 200 || !is_string($res)) continue;

            $j = json_decode($res, true);
            $txt = $j['candidates'][0]['content']['parts'][0]['text'] ?? '';
            if (!is_string($txt) || $txt === '') continue;

            $out = json_decode($txt, true);
            if (is_array($out)) return smm_json_unwrap($out);
            /* ОТВЕТ БЫВАЕТ ЗАВЁРНУТ В СТРОКУ, И ЭТО НЕ МОЛЧАНИЕ МОДЕЛИ.
               При responseMimeType=application/json служба иногда отдаёт не
               объект, а СТРОКУ с объектом внутри: json_decode даёт строку,
               is_array ложно, заход списывался в молчание и уходил впустую. */
            if (is_string($out) && $out !== '') {
                $вложенный = json_decode($out, true);
                if (is_array($вложенный)) return smm_json_unwrap($вложенный);
            }
        }
    }
    return smm_ask_json_fallback($prompt, $timeout);
}

/**
 * РАЗВЕРНУТЬ ОБЁРТКУ ВОКРУГ ОТВЕТА.
 *
 * Замер 13.10.2026: на вопрос про сцену плаката пришло
 * `{"value":"{\"scene\":\"The Great Hall …\"}"}` - нужный объект лежал
 * строкой под ключом «value», которого в задании не было вовсе. Снаружи это
 * выглядело как «мозг молчит»: вызывающий спрашивал $r['scene'], не находил и
 * бросал заход. Обёртку ставят и Gemini, и запасной мозг, и имя у неё разное,
 * поэтому разворачиваем в ОДНОМ месте - на выходе общей двери.
 */
function smm_json_unwrap(array $out): array {
    /* ИМЯ ОБЁРТКИ «input» СТОИЛО АФИШИ ЛЕРМОНТОВА.
       Замер ночи 15.10.2026: на вопрос о дате рождения пришло
       `{"input":{"новый_стиль":"15 октября","старый_стиль":"3 октября","знаю":true}}` -
       ответ ВЕРНЫЙ, но завёрнутый, и этого имени в списке не было. Заслон
       спрашивал $r['новый_стиль'], не находил и писал в журнал «мозг молчит»,
       хотя через минуту тот же мозг отвечал по шесть раз подряд. Повод чуть не
       ушёл на год.
       Имя не случайное: посредник превращает требование «только JSON» в вызов
       инструмента, а у вызова аргументы лежат под `input`/`arguments`. Поэтому
       добавлена вся эта семья. Список остаётся ЗАКРЫТЫМ по именам, а не по
       форме: разворачивать любой одиночный ключ нельзя - у праздника ответ и
       есть один ключ `{"дата":…}`, и его развернули бы в мусор. */
    $имена = ['value', 'json', 'result', 'data', 'output', 'response', 'content',
              'input', 'arguments', 'args', 'parameters', 'params', 'answer', 'payload'];
    for ($круг = 0; $круг < 3; $круг++) {
        if (count($out) !== 1) break;
        $ключ = (string) array_key_first($out);
        if (!in_array(mb_strtolower($ключ), $имена, true)) break;
        $в = $out[$ключ];
        if (is_array($в)) { $out = $в; continue; }
        if (is_string($в) && $в !== '') {
            $вложенный = json_decode(trim($в), true);
            if (is_array($вложенный)) { $out = $вложенный; continue; }
        }
        break;
    }
    return $out;
}

/** Короткая строка о состоянии мозга — в тот же журнал, что и крон. */
function smm_log_brain(string $msg): void {
    @file_put_contents(BASE_PATH . '/data/logs/cron.log',
        '[' . date('Y-m-d H:i:s') . "] [smm_brain] $msg\n", FILE_APPEND | LOCK_EX);
}

/**
 * ЗАПАСНОЙ МОЗГ: apimodels, тот же счёт, на котором живут картинки.
 *
 * Гасить ленту из-за чужой квоты неправильно, но и тратить деньги владельца молча
 * тоже нельзя. Поэтому запасной путь выключен по умолчанию: включается настройкой
 * smm_brain_fallback=1 в админке. Модель и цена видны там же; счёт apimodels у
 * центра уже оплачен и работает - на нём собираются картинки к постам.
 */
function smm_ask_json_fallback(string $prompt, int $timeout = 90): ?array {
    if ((int) setting('smm_brain_fallback', '0') !== 1) return null;
    $key = trim((string) (cfgv('apimodels_key') ?: ''));
    if ($key === '') return null;

    /* У ЗАПАСНОГО МОЗГА СВОЙ ДНЕВНОЙ ПРЕДЕЛ, КАК У КАРТИНОК.
     *
     * Он тратит деньги владельца, и опереться тут не на что: своей квоты, которая
     * сама скажет «хватит», у платного счёта нет. Один пост обходится примерно в
     * восемь вызовов (тема, проверка факта, текст, переписывания), два поста в
     * день - под двадцать. Предел по умолчанию шестьдесят: запас на переписывания
     * есть, а убежать в сотни вызовов из-за зацикленной проверки нельзя.
     * Счёт обнуляется с новой датой, видно его на пульте «Соцсети». */
    $day  = json_decode((string) setting('smm_brain_day', '{}'), true);
    if (!is_array($day) || ($day['date'] ?? '') !== date('Y-m-d')) {
        $day = ['date' => date('Y-m-d'), 'calls' => 0, 'in' => 0, 'out' => 0];
    }
    $limit = (int) setting('smm_brain_fallback_limit', '60');
    if ($limit > 0 && (int) $day['calls'] >= $limit) {
        smm_log_brain("дневной предел запасного мозга исчерпан ({$limit} вызовов)");
        return null;
    }

    $model = (string) setting('smm_brain_fallback_model', 'claude-haiku-5-5');
    $base  = rtrim((string) (cfgv('apimodels_base') ?: 'https://api.apimodels.app/v1'), '/');
    /* «ОТВЕЧАЙ JSON» НАДО СКАЗАТЬ ОТДЕЛЬНОЙ СТРОКОЙ, А НЕ ТОЛЬКО ФЛАГОМ.
     *
     * Флаг `response_format: json_object` посредник до модели не доносит: на тот же
     * запрос приходило то чистое тело, то «I'm Claude, an AI assistant… I'll
     * create a topic for you:» с JSON где-то в середине. Конвейер такой ответ
     * считал молчанием модели и терял заход. Поэтому требование стоит системным
     * сообщением, а разбор ниже умеет достать тело из обёртки. */
    $body  = json_encode([
        'model'    => $model,
        'messages' => [
            ['role' => 'system', 'content' => 'Отвечай ТОЛЬКО одним валидным объектом JSON. '
                . 'Без приветствий, без пояснений, без markdown-ограды, без текста до или после. '
                . 'Первый символ ответа — «{», последний — «}».'],
            ['role' => 'user', 'content' => $prompt],
        ],
        'response_format' => ['type' => 'json_object'],
    ], JSON_UNESCAPED_UNICODE);

    $ch = curl_init($base . '/chat/completions');
    curl_setopt_array($ch, [
        CURLOPT_POST => true,
        CURLOPT_POSTFIELDS => $body,
        CURLOPT_HTTPHEADER => ['Content-Type: application/json', 'Authorization: Bearer ' . $key],
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_TIMEOUT => $timeout,
    ]);
    $res  = curl_exec($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);
    if ($code !== 200 || !is_string($res)) { smm_log_brain("запасной мозг ответил {$code}"); return null; }

    $j   = json_decode($res, true);
    $day['calls']++;
    $day['in']  += (int) ($j['usage']['prompt_tokens'] ?? 0);
    $day['out'] += (int) ($j['usage']['completion_tokens'] ?? 0);
    set_setting('smm_brain_day', json_encode($day));

    $txt = (string) ($j['choices'][0]['message']['content'] ?? '');
    if ($txt === '') return null;
    /* Модель охотно оборачивает JSON в ```json … ``` — снимаем забор. */
    $txt = trim(preg_replace('~^```[a-z]*|```$~m', '', $txt) ?? $txt);
    $out = json_decode($txt, true);
    /* А если вокруг тела всё-таки оказалась болтовня — вынимаем первый полный
       объект от «{» до парной «}». Считаем скобки, а не берём жадным регулярным
       выражением: в тексте поста фигурные скобки не встречаются, но вложенные
       объекты в ответе бывают. */
    if (!is_array($out)) {
        $i = mb_strpos($txt, '{');
        if ($i !== false) {
            $depth = 0; $start = $i; $len = mb_strlen($txt);
            for ($k = $i; $k < $len; $k++) {
                $ch2 = mb_substr($txt, $k, 1);
                if ($ch2 === '{') $depth++;
                elseif ($ch2 === '}') {
                    $depth--;
                    if ($depth === 0) { $out = json_decode(mb_substr($txt, $start, $k - $start + 1), true); break; }
                }
            }
        }
    }
    if (!is_array($out)) {
        /* Сырой текст отдаём вызывающему: иногда модель отказывается от формата
           («I'm unable to respond to your request in the format specified»), но
           сам ответ по существу в тексте есть. Сверка даты повода умеет достать
           из него дату, и повод не теряется из-за капризов формата. */
        $GLOBALS['smm_brain_raw'] = $txt;
        smm_log_brain('запасной мозг ответил не JSON: ' . mb_substr(preg_replace('~\s+~u', ' ', $txt) ?? '', 0, 90));
        return null;
    }
    $GLOBALS['smm_brain_raw'] = '';

    /* МОЗГ ЗАГОВОРИЛ - ЗНАЧИТ ОН НЕ ОТДЫХАЕТ.
     *
     * Метку «все ключи отдыхают» ставит основной путь, и по ней smm_make_topic
     * прекращает перебор: ответ всё равно будет один и тот же. Но когда запасной
     * мозг включён и отвечает, метка лжёт - и первый же неполный ответ модели
     * («не вернула topic») обрывал весь заход со словами «мозг отдыхает по
     * квоте», хотя мозг работал. Снимаем метку на каждом удачном ответе. */
    $GLOBALS['SMM_BRAIN_RESTING'] = 0;
    smm_log_brain("ответил запасной мозг ({$model})");
    return smm_json_unwrap($out);
}

