 * Промпт картинки — ОДНА ГЕНЕРАЦИЯ НА ВСЁ.
 *
 * Требование владельца: кадр, заголовок и логотип рождаются вместе, в одном
 * вызове. Ничего не доклеивается после.
 *
 * Почему именно так, а не наложением. Наложенный поверх логотип и подписанный
 * сверху заголовок всегда читаются как наклейка на фотографии: у них свой свет,
 * своя резкость, своя геометрия, и кадр распадается на картинку и стикер.
 * Когда же надпись и эмблема описаны внутри сцены — краска на бетонной стене
 * коридора, латунная табличка у двери репетиционной, буквы на белёной стене
 * студии, — на них ложится тот же свет, та же пыль и та же перспектива, и кадр
 * остаётся единым. Образцы владельца сделаны именно так.
 *
 * Логотип при этом идёт в генерацию референсом (image_urls) и описывается как
 * предмет, который в сцене уже существует: его не перерисовывают заново, его
 * вешают на стену.
 *
 * С 13.10.2026 ПРОМПТ СОБИРАЕТСЯ ПО КЛЮЧ-АРТУ ЗАВОДА (слово владельца:
 * «Генерацию всех картинок необходимо выполнять по структуре ключ арт завода
 * oko»). Мозгу остаётся ОДНА работа - назвать сцену; формат, монтаж,
 * типографику титула, цветовой ключ, знак, запреты и отделку кладёт код
 * (core/smm_keyart.php), три оси с памятью на четыре. Раньше весь промпт писала
 * модель по длинному описанию, и длина плавала от 1800 до 4000 знаков, а
 * разнообразие держалось на её настроении.
 */
/**
 * Месяц повода по-английски из ключа слота «ГГГГ-ММ-ДД_Ч».
 *
 * Нужен афише: сезон в задании сцены называется словом, иначе модель ставит
 * приметы чужого времени года (новогоднюю ёлку на октябрьском поздравлении).
 * Ключ не разобрался - отдаём пустое «the season of the date», а не выдуманный
 * месяц: назвать не тот месяц хуже, чем не назвать никакого.
 */
function smm_mesyac_en(string $ключСлота): string {
    if (preg_match('~^(\d{4})-(\d{2})-(\d{2})~', trim($ключСлота), $m)) {
        $ts = mktime(12, 0, 0, (int) $m[2], (int) $m[3], (int) $m[1]);
        if ($ts) return date('F', $ts);
    }
    return 'the season of the date';
}

function smm_make_image_prompt(array $topic, string $ratio, string $title = '',
                               string $subtitle = '', string $age = '', string $чем = '',
                               string $персона = '', string $вид = 'совет',
                               string $сюжет = '', string $человек = ''): ?string {
    $title    = trim($title);
    $subtitle = trim($subtitle);
    $герой    = (string) (SMM_AGES[$age]['кадр'] ?? '');
    $персона  = trim($персона);
    /* $персона — человек, ПОРТРЕТ которого нашёлся (лицо по референсу);
       $человек — герой рассказа вообще, с портретом или без. Раньше эпоху
       определял только портрет: у Шуберта 22.10.2026 его не нашлось, и пост про
       Вену 1822 года получил кадр «студенты в современном классе». */
    $человек  = trim($человек) !== '' ? trim($человек) : trim((string) ($topic['person'] ?? ''));
    if ($человек === '') $человек = $персона;

    /* ШАГ 1. СЦЕНУ НАЗЫВАЕТ МОЗГ, И ТОЛЬКО ЕЁ.
       Остальное - формат, монтаж, типографика, цвет, знак, запреты - собирает
       код по ключ-арту: так промпт держится в коридоре и не зависит от того,
       насколько щедра сегодня модель. */
    /* СЦЕНА ПРИНАДЛЕЖИТ ЭПОХЕ РАССКАЗА, А НЕ ВСЕГДА СЕГОДНЯШНЕМУ ДНЮ.
     *
     * Правка владельца 15.10.2026 требует современных, светлых, молодёжных
     * мест (правила 70, 70а), и до 16.10 это требование стояло безусловно. На
     * посте #21 про премьеру «Весны священной» в Париже 1913 года оно победило
     * второе наше же правило - «по кадру должен быть узнаваем предмет поста»:
     * в задание ушло «a sunlit modern rehearsal studio in Moscow» и «2020s
     * athleisure», и лист вышел про сегодняшних пенсионеров у рояля. Про Париж
     * и 1913 год по кадру было не догадаться.
     *
     * Поэтому современность просим там, где рассказ про сегодня, а у истории
     * про прошлое и у афиши с портретом место и приметы берутся у ЭПОХИ.
     * Яркость, свет и живость остаются в обоих случаях: они про качество
     * кадра, а не про век. */
    $факт = trim((string) ($topic['fact'] ?? ''));
    $историческое = $персона !== '' || $человек !== ''
        || in_array($сюжет, ['деятель', 'мир-музыки-прошлое'], true)
        /* История с датой прошлого века и раньше — тоже про прошлое, даже без героя. */
        || ($вид === 'история' && preg_match('~\b(1[0-8]\d\d|19[0-8]\d)\b~', $факт . ' ' . (string) ($topic['topic'] ?? '')));
    $безПортрета = $историческое && $персона === '';

    $__место = $историческое
        ? ("- the place and every object must belong to the ERA AND COUNTRY OF THE STORY above, "
         . "not to today: the hall, the theatre, the street, the instruments, the furniture and "
         . "the clothes of that time, researched and specific. Never a modern studio, never "
         . "today's clothes, never a phone, a laptop or a LED screen;
")
        : ("- a real, modern Russian setting, bright and well kept, chosen to fit the topic and NOT "
         . "the same place every time: a sunlit rehearsal studio with big windows, a dance studio "
         . "with mirrors, a music school with colourful acoustic panels, a modern stage under clean "
         . "LED light, a glass foyer, a rooftop over the city, a bright courtyard or park, a wall "
         . "with street art, a light home studio with a ring light, a modern cafe. Never a glossy "
         . "empty studio, never a shabby, dusty or dated interior;\n");

    $__настрой = $историческое
        ? ("- bright, clear light and vivid colour; a living moment, not a monument: faces busy, "
         . "hands working, something happening. Period-true clothes, hair and objects.\n")
        : ("- bright daylight or clean modern lighting; vivid colour; a cheerful, energetic mood - "
         . "smiles, movement, people glad to be there; contemporary 2020s clothes, haircuts, "
         . "instruments and furniture, in fashion today.\n");

    $q = "You are the art director of a Russian cultural centre that runs online arts "
        . "competitions in eight fields: singing, dance, instrumental music, spoken word, "
        . "theatre, drawing and painting, crafts, circus.\n\n"
        . "Post topic: " . (string) ($topic['topic'] ?? '') . "\n"
        . "Angle: " . (string) ($topic['angle'] ?? '') . "\n"
        /* ФАКТ ПОСТА — В ЗАДАНИЕ СЦЕНЫ. Мозг видел только тему и сочинял свою
           историю: к посту о «Неоконченной» вышли друзья, которые «доиграют её до
           конца». Сцена обязана показывать то, о чём рассказывает текст. */
        . ($факт !== '' ? ("What the post actually tells (the scene must show THIS): " . mb_substr($факт, 0, 600) . "\n") : '')
        . ($title !== '' ? ("Headline of the post: " . $title . ($subtitle !== '' ? ' - ' . $subtitle : '') . "\n") : '')
        . "Aspect ratio of the sheet: " . $ratio . "\n"
        . ($безПортрета && $человек !== ''
            ? ("The story is about a real person of the past: " . $человек . ". Show THEIR place, THEIR time "
             . "and THEIR work from the story - the room, the hall, the manuscript, the instrument, the people "
             . "around them in that era. We have NO portrait, so the person is seen only from behind, in "
             . "silhouette or far away, never a clear face. Never today's people re-enacting the story.\n")
            : '')
        . ($персона !== ''
            ? ("The frame is about a real person: " . $персона . ". Name the place and the era "
             . "around them - their room, their stage, their instrument, their time - and do NOT "
             . "describe their face: a real portrait of them is supplied as a reference.\n")
            : ((!$историческое && $герой !== '') ? ("People who must be in the frame: " . $герой . ".\n") : ''))
        /* АФИША ЭТО ПОЗДРАВЛЕНИЕ, А НЕ ПАМЯТНАЯ ДОСКА.
           Куплено живым кадром в ночь на 15.10.2026: на афише к 212-летию
           Лермонтова мозг положил на стол ДУЭЛЬНЫЙ ПИСТОЛЕТ в открытом футляре
           и повторил его крупно в ленте кадров. Поэт погиб на дуэли, и оружие
           на поздравлении читается как напоминание о гибели. Модель брала его
           честно - как примету эпохи и биографии, - поэтому запрет назван
           словами, а не оставлен на её вкус. */
        . ($вид === 'афиша'
            ? ("\nTHIS SHEET IS A BIRTHDAY GREETING from the centre, warm and alive. Show the "
             . "person at their craft, at work, among people and their everyday things. NEVER "
             . "any weapon, duel, duelling case, grave, funeral, mourning ribbon or memorial "
             . "candle, and nothing else that hints at how they died: a greeting is about a life, "
             . "not about its end.\n"
             /* СЕЗОН НАЗЫВАЕМ ВСЛУХ. На афише 15.10 модель поставила в ленту
                кадров новогоднюю ёлку со свечами: повод октябрьский, а примета
                зимняя. Месяц она сама не знает - в задании его не было. */
             . "The occasion falls in " . smm_mesyac_en($чем) . ": every small scene must belong "
             . "to that season. No New Year tree, fairy lights, baubles, snow or holiday candles "
             . "unless the occasion itself is that winter holiday.\n")
            : '')
        . "\nName THE SCENE for a poster key visual: WHAT is happening and WHERE, in ENGLISH, "
        . "2 or 3 short sentences, 200 to 330 characters: the sheet has no room for more.\n"
        /* СЦЕНА ОБЯЗАНА БЫТЬ ПРО ТЕМУ ПОСТА, И ЭТО СЛОВО ВЛАДЕЛЬЦА 15.10.2026:
           «чтобы они соответствовали той информации, которая публикуется в посте».
           Прежняя формулировка просила «момент этой темы» - этого мало: по кадру
           тему было не назвать. */
        . "- the scene must be recognisably ABOUT THE TOPIC above: a stranger who sees only the "
        . "sheet should be able to say what the post is about;\n"
        . "- a specific moment of it, something happening and about to change;\n"
        /* СТАРОМОДНЫМ КАДР ДЕЛАЛО САМО ЗАДАНИЕ: здесь дословно просили «an OLD
           music school hall» и «a village club». Правка владельца 15.10.2026
           («старомодно, блекло, тускло, скучно») - значит зовём в современные,
           светлые, обжитые места. «Не глянцевая пустая студия» остаётся: кадру
           нужен монтаж из живых планов, а не фон. */
        /* МЕСТ СТАЛО БОЛЬШЕ И ОНИ МОЛОДЁЖНЫЕ - второе слово владельца 15.10.2026
           («что бы использовались современные молодёжные фоны на фото»). Прежний
           список был из пяти залов, и лента получалась про один и тот же зал. */
        . $__место
        . "- name two or three further small scenes of the same story that can stand around the "
        . "main one, so the sheet can be built as a montage;\n"
        /* ЖИЗНЕРАДОСТНОСТЬ НАЗВАНА СЛОВАМИ, А НЕ ОСТАВЛЕНА НА ВКУС МОДЕЛИ. */
        . $__настрой
        /* ЖЁСТКАЯ ЦЕНЗУРА НАЗВАНА САМОМУ МОЗГУ, А НЕ ОСТАВЛЕНА ЗАСЛОНУ.
           Слово владельца 19.10.2026. Это бесплатно: сцену пишет мозг, в коридор
           промпта задание не входит, а не названный запрет мозг нарушает честно -
           16.10 он сам написал в сцену «stands barefoot on a worn wooden stage». */
        . "- EVERY person is fully and modestly dressed and WEARS SHOES: never barefoot, bare-chested, "
        . "in underwear, swimwear or revealing clothing, never undressed or half-dressed, never a "
        . "suggestive pose;\n"
        . "- nothing that may not be published in Russia: no alcohol, tobacco, vaping, drugs, weapon, "
        . "blood, violence, gambling, no political, military or extremist symbol;\n"
        . "Do NOT describe the colour grade, the typography, the logo, the format or the camera: "
        . "the layout adds all of that. Do NOT put any words or lettering into the scene.\n"
        . "Return strictly JSON: {\"scene\":\"...\"}";

    $r = smm_ask_json($q, 90);
    $сцена = is_array($r) ? trim((string) ($r['scene'] ?? '')) : '';
    if ($сцена === '') return null;

    /* ШАГ 2. ТРОЙКА ОСЕЙ С ПАМЯТЬЮ НА ЧЕТЫРЕ. Ключ слота, а не темы: при
       повторном заходе того же слота плакат тот же и деньги не тратятся дважды. */
    /* Портрет в кадре снимает монтажи, вырезающие героя (SMM_KA_MONTAGES_NO_FACE):
       иначе лист получает фигуру без лица - см. разбор афиши Лермонтова. */
    $оси = smm_ka_triple($чем !== '' ? $чем : (string) ($topic['topic'] ?? ''),
                         trim((string) $персона) !== '');

    /* ШАГ 3. ПЛАКАТ СОБИРАЕТ КОД. */
    $пл = smm_ka_prompt(
        $сцена,
        $герой,
        $оси,
        (string) setting('smm_ka_tag', 'МУЗЫКАЛЬНЫЙ МИР'),
        $title,
        $subtitle,
        $персона,
        // История без портрета: в кадре люди той эпохи, а не возрастная группа поста.
        $безПортрета ? ($человек !== '' ? $человек : '-') : ''
    );
    if (empty($пл['ок'])) {
        $GLOBALS['SMM_KA_ALARM'] = (string) ($пл['почему'] ?? 'плакат не собрался');
        return null;
    }

    /* ШАГ 4. ЗАСЛОН: ПРОСТОЕ ЗАПРЕЩЕНО. Судим промпт даром и ДО траты. */
    $беды = smm_ka_simple((string) $пл['промпт']);
    if ($беды) {
        $GLOBALS['SMM_KA_ALARM'] = 'заслон ключ-арта: ' . implode('; ', $беды);
        return null;
    }

    $GLOBALS['SMM_KA_LAST'] = [
        'монтаж'      => (string) $пл['монтаж'],
        'типографика' => (string) $пл['типографика'],
        'цвет'        => (string) $пл['цвет'],
        'приём'       => (string) ($пл['приём'] ?? ''),
        'знаков'      => (int) $пл['знаков'],
        'вне_коридора'=> (string) ($пл['вне_коридора'] ?? ''),
    ];
    return (string) $пл['промпт'];
}

/** Размер холста под формат. */
function smm_ratio_size(string $ratio): array {
    return match ($ratio) {
        '1:1' => [2048, 2048],
        '4:3' => [2304, 1728],
        default => [2560, 1440],
    };
}

/**
 * Сгенерировать картинку. Платно, поэтому расход сначала спрашивается у бюджета.
 * Логотип центра передаётся референсом: правило владельца — логотип только
 * настоящий, нарисованных подобий быть не должно.
 */
/* РЕФЕРЕНСЫ ПЕРЕДАЮТСЯ ПАРАМЕТРОМ, А НЕ ВПИСАНЫ НАВСЕГДА.
   У поста знак центра обязан быть в кадре (правило владельца про настоящее
   лого), а у АФИШИ конкурса знака в промпте нет вовсе: лист собирается целиком
   по своим девяти строкам, и лишняя картинка в референсах просится моделью в
   кадр наклейкой. Поэтому $ссылки = [] значит «без референсов», null - прежнее
   поведение поста. Второй копии разговора с apimodels в проекте быть не должно
   (правила 33, 35, 45, 47, 56а, 64). */
function smm_make_image(string $prompt, string $ratio, string $saveTo,
                        string $портрет = '', ?array $ссылки = null): array {
    $key = trim((string) (cfgv('apimodels_key') ?: ''));
    if ($key === '') return [false, 'нет ключа apimodels', 0.0];

    $cost = (float) setting('smm_image_cost', '0.04');
    /* Афиша тратит из СВОЕГО кошелька (см. scripts/afisha_make.php --api): её
       расход не ложится в smm_posts, и общий предел ленты она не ест. */
    if ($ссылки === null && !smm_budget_ok($cost)) {
        return [false, 'дневной предел расхода на картинки исчерпан', 0.0];
    }

    /* Логотип идёт референсом в ту же генерацию: кадр, надпись и эмблема
       рождаются вместе и живут в одном свете. Ничего не доклеивается после. */
    $logo = (string) (cfgv('smm_logo_url')
        ?: 'https://xn----7sbugdeiegh1b0a9hen.xn--p1ai/assets/img/logo_muzmir_main.png');

    $body = json_encode([
        'model'        => (string) (cfgv('apimodels_model') ?: 'gemini-3-pro-image'),
        'prompt'       => $prompt,
        'aspect_ratio' => $ratio,
        'resolution'   => '2k',
        'quality'      => 'high',
        /* ВТОРЫМ РЕФЕРЕНСОМ - НАСТОЯЩИЙ ПОРТРЕТ, когда пост о человеке. Знак
           остаётся ПЕРВЫМ: порядок референсов назван в самом промпте. */
        'image_urls'   => $ссылки !== null
            ? array_values($ссылки)
            : ($портрет !== '' ? [$logo, $портрет] : [$logo]),
    ], JSON_UNESCAPED_UNICODE);

    $base = rtrim((string) (cfgv('apimodels_base') ?: 'https://api.apimodels.app/v1'), '/');
    $ch = curl_init($base . '/images/generations');
    curl_setopt_array($ch, [
        CURLOPT_POST => true,
        CURLOPT_POSTFIELDS => $body,
        CURLOPT_HTTPHEADER => ['Content-Type: application/json', 'Authorization: Bearer ' . $key],
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_TIMEOUT => 120,
    ]);
    $res  = curl_exec($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);
    /* ОТВЕТ СЛУЖБЫ ПЕРЕСКАЗЫВАЕМ ЕЁ ЖЕ СЛОВАМИ.
     *
     * Раньше в журнал и в админку попадал голый номер: «apimodels ответил 401».
     * По нему нельзя отличить протухший ключ от кончившихся денег и от запрета
     * на модель, а служба сама пишет это прямым текстом в поле msg. Три дня в
     * октябре конвейер стоял с таким номером в графе ошибки, и чтобы узнать
     * причину, пришлось повторять его запрос руками. */
    if ($code !== 200 || !is_string($res)) {
        $why = '';
        if (is_string($res)) {
            $j = json_decode($res, true);
            $why = trim((string) ($j['msg'] ?? $j['message'] ?? $j['error']['message'] ?? ''));
            if ($why === '') $why = trim(mb_substr(strip_tags($res), 0, 120));
        }
        return [false, "apimodels ответил {$code}" . ($why !== '' ? ": {$why}" : ''), 0.0];
    }

    $j = json_decode($res, true);
    /* ГРАБЛИ: идентификатор задачи лежит в data.taskId, а результат — в
       data.resultUrls, не в data.output.image_urls, как подсказывает здравый смысл. */
    $taskId = (string) ($j['data']['taskId'] ?? $j['taskId'] ?? '');
    if ($taskId === '') return [false, 'apimodels не вернул taskId', 0.0];

    /* ГРАБЛИ: готовность спрашивается НЕ путём /images/generations/<id> (на него
       приходит 404 с нотацией про base_url, сбивающей с толку), а тем же путём с
       параметром ?task_id=. Именно task_id со знаком подчёркивания: taskId,
       которым API сам назвал поле в ответе, здесь даёт «task_id is required». */
    $url = '';
    for ($i = 0; $i < 60; $i++) {
        sleep(5);
        $ch = curl_init($base . '/images/generations?task_id=' . rawurlencode($taskId));
        curl_setopt_array($ch, [
            CURLOPT_HTTPHEADER => ['Authorization: Bearer ' . $key],
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_TIMEOUT => 30,
        ]);
        $r2 = curl_exec($ch);
        curl_close($ch);
        if (!is_string($r2)) continue;
        $d = json_decode($r2, true);
        $state = (string) ($d['data']['state'] ?? $d['data']['status'] ?? '');
        if ($state === 'completed' || $state === 'success') {
            $url = (string) ($d['data']['resultUrls'][0] ?? '');
            break;
        }
        if ($state === 'failed' || $state === 'error') return [false, 'генерация не удалась', 0.0];
    }
    if ($url === '') return [false, 'картинка не дождалась готовности', 0.0];

    /* ГРАБЛИ: хранилище r2.apimodels.app отдаёт 403 на запрос без обычных
       браузерных заголовков — скачиваем curl'ом с User-Agent. */
    $ch = curl_init($url);
    curl_setopt_array($ch, [
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_TIMEOUT => 120,
        CURLOPT_FOLLOWLOCATION => true,
        CURLOPT_USERAGENT => 'Mozilla/5.0',
    ]);
    $img  = curl_exec($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);
    if ($code !== 200 || !is_string($img) || strlen($img) < 10000) return [false, 'картинка не скачалась', 0.0];

    @mkdir(dirname($saveTo), 0775, true);
    if (file_put_contents($saveTo, $img) === false) return [false, 'картинка не сохранилась', 0.0];

    return [true, '', $cost];
}

/* ------------------------------------------------------------------ *
 *  Hooppy: публикация
 * ------------------------------------------------------------------ */

function smm_hooppy_call(string $path, string $method = 'GET', ?array $payload = null, ?string $filePath = null): ?array {
    $token = trim((string) (cfgv('hooppy_token') ?: ''));
    if ($token === '') return null;
    $base = rtrim((string) (cfgv('hooppy_base') ?: 'https://api.hooppy.ru/api'), '/');

    $ch = curl_init($base . '/' . ltrim($path, '/'));
    $headers = ['Accept: application/json', 'Authorization: Bearer ' . $token];
    $opts = [CURLOPT_RETURNTRANSFER => true, CURLOPT_TIMEOUT => 180];

    if ($filePath !== null) {
        $opts[CURLOPT_POST] = true;
        $opts[CURLOPT_POSTFIELDS] = [
            'file'    => new CURLFile($filePath, mime_content_type($filePath) ?: 'image/jpeg', basename($filePath)),
            'file_id' => $payload['file_id'] ?? bin2hex(random_bytes(16)),
        ];
    } elseif ($method === 'POST') {
        $opts[CURLOPT_POST] = true;
        $opts[CURLOPT_POSTFIELDS] = json_encode($payload ?: [], JSON_UNESCAPED_UNICODE);
        $headers[] = 'Content-Type: application/json';
    }
    $opts[CURLOPT_HTTPHEADER] = $headers;
    curl_setopt_array($ch, $opts);

    $res  = curl_exec($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);
    if ($code !== 200 || !is_string($res)) return null;
    $j = json_decode($res, true);
    return is_array($j) ? $j : null;
}

/** Куда публикуем. Страницы задаёт владелец настройкой, по умолчанию — ВК и МАКС. */
function smm_target_pages(): array {
    $raw = trim((string) setting('smm_pages', '2543792,2561963'));
    return array_values(array_filter(array_map('intval', preg_split('~[,\s]+~', $raw) ?: [])));
}

/**
 * Опубликовать пост. Перед отправкой ещё раз проверяется окно: между подготовкой
 * и публикацией проходят часы, и крон может запуститься руками в воскресенье.
 */
function smm_publish(array $post, bool $force = false): array {
    if (!$force && function_exists('outreach_window_ok') && !outreach_window_ok()) {
        return [false, 'вне окна публикаций: ' . (function_exists('outreach_window_reason') ? outreach_window_reason() : '')];
    }

    $pages = smm_target_pages();
    if (!$pages) return [false, 'не заданы страницы публикации'];

    $text = (string) $post['text_full'];
    if (trim($text) === '') return [false, 'пустой текст'];
    // Телефон и график берём сегодняшние: пост мог пролежать в очереди три дня.
    if (function_exists('smm_footer_svezhiy')) $text = smm_footer_svezhiy($text);

    $attachments = [];
    $img = (string) ($post['image_path'] ?? '');
    if ($img !== '' && is_file($img)) {
        $up = smm_hooppy_call('files/media/upload', 'POST', ['file_id' => bin2hex(random_bytes(16))], $img);
        $photo = $up['photo'] ?? null;
        if (!is_array($photo)) return [false, 'картинка не загрузилась в Hooppy'];
        $attachments[] = ['type' => 'photos', 'data' => [$photo]];
    }

    $res = smm_hooppy_call('posts', 'POST', [
        'publication_when_type' => 1,            // публиковать сейчас
        'publication_how_type'  => 1,            // соцсети указаны вручную
        'selected_pages_ids'    => $pages,
        'texts'                 => [['text' => $text, 'source_id' => 0]],
        'attachments'           => $attachments,
    ]);

    $id = (int) ($res['id'] ?? 0);
    if ($id <= 0) return [false, 'Hooppy не принял пост'];

    return [true, (string) $id];
}

/**
 * Найти ссылку на опубликованную запись ВКонтакте. Hooppy ссылку не отдаёт, а
 * владельцу в отчёте нужна именно она. Стена читается ключом сообщества и только
 * с боевого сервера — правило о российском адресе без прокси.
 */
function smm_vk_last_link(): string {
    /* ЧИТАЕТ СТЕНУ ЛИЧНЫЙ КЛЮЧ, А НЕ КЛЮЧ СООБЩЕСТВА.
     *
     * Ключу сообщества wall.get недоступен вовсе: ВК отвечает «error 27, method
     * is unavailable with group auth». Функция молча возвращала пустоту, и у
     * трёх опубликованных постов ссылки в базе не оказалось. Чтение чужой и
     * своей стены — ровно тот случай, для которого личный ключ и оставлен
     * запасным (правило о ключах от 11.09.2026); писать в сообщество
     * по-прежнему обязан ключ сообщества. */
    $token = trim((string) (cfgv('vk_token') ?: cfgv('MUZMIR_VK_TOKEN') ?: ''));
    if ($token === '') $token = trim((string) (cfgv('vk_group_token') ?: ''));
    $owner = (int) (cfgv('vk_group_id') ?: 211325055);
    if ($token === '' || $owner === 0) return '';

    $url = 'https://api.vk.ru/method/wall.get?owner_id=-' . $owner . '&count=1&v=5.199&access_token=' . urlencode($token);
    $ch = curl_init($url);
    curl_setopt_array($ch, [CURLOPT_RETURNTRANSFER => true, CURLOPT_TIMEOUT => 30]);
    $res = curl_exec($ch);
    curl_close($ch);
    if (!is_string($res)) return '';
    $j = json_decode($res, true);
    $id = (int) ($j['response']['items'][0]['id'] ?? 0);
    return $id > 0 ? ('https://vk.com/wall-' . $owner . '_' . $id) : '';
}
