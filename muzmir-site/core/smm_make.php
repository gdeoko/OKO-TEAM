/**
 * Придумать тему, которой ещё не было. Модель получает живой срез центра и полный
 * список уже вышедших тем как прямой запрет, а дальше её предложение всё равно
 * проверяется нашим антиповтором: модель охотно выдаёт перефразировку вчерашнего,
 * если список длинный, и верить ей на слово нельзя.
 *
 * Попыток несколько: отказ по повтору — обычный ход событий, а не сбой.
 */
function smm_make_topic(string $layer, int $stage, string $age = '', int $tries = 6,
                        string $вид = 'совет', array $повод = [], string $сюжет = '',
                        string $напр = '', string $сторона = ''): ?array {
    /* ПОЧЕМУ ТЕМА НЕ НАШЛАСЬ — ВИДНО СНАРУЖИ.
     *
     * Причина отказа писалась в $r['_rejected'], а $r на следующем заходе
     * затирался: наружу уходил только null, и журнал три дня повторял «тема не
     * нашлась (все попытки повторяли вышедшее)». Под этой строкой прячутся
     * РАЗНЫЕ беды: кончилась квота модели (ответа нет вовсе), выдуманный факт,
     * настоящий повтор. Лечатся они по-разному, а различить их было нельзя.
     * Теперь причины копятся здесь, и cron/smm_prepare.php печатает их словами. */
    $GLOBALS['SMM_TOPIC_REJECTS'] = [];
    $ctx  = smm_context();
    $used = smm_used_topics();

    /* ОСЬ ТЕМЫ НАЗВАНА МОДЕЛИ ПРЯМО (правка владельца 19.10.2026). Полный список
       вышедших тем у неё и так есть запретом, но на четырёхсот строках он не
       работает: модель читает их как фон и выдаёт очередной совет про запись
       номера. Поэтому ось приходит извне одним требованием, а шесть последних
       тем названы отдельно и коротко - их она видит. */
    $осьБлок = '';
    if ($напр !== '' && isset(SMM_NAPRAVLENIYA[$напр])) {
        $осьБлок .= "НАПРАВЛЕНИЕ ЭТОГО ПОСТА: " . SMM_NAPRAVLENIYA[$напр] . "\n"
                  . "Тема обязана быть про него, а не про творчество вообще.\n\n";
    }
    if ($вид === 'совет' && $сторона !== '' && isset(SMM_SOVET_STORONY[$сторона])) {
        $осьБлок .= "СТОРОНА СОВЕТА: " . SMM_SOVET_STORONY[$сторона] . "\n"
                  . "Возьми ровно эту сторону: остальные у центра уже разобраны.\n\n";
    }
    $свежие  = array_slice($used, 0, 6);
    $свежБлок = $свежие
        ? ("Вот последние шесть тем центра. Твоя обязана быть НЕ ПРО ТО ЖЕ и не про "
         . "соседнее по смыслу:\n- " . implode("\n- ", $свежие) . "\n\n")
        : '';

    $comps = [];
    foreach ($ctx['competitions'] as $c) {
        $comps[] = sprintf(
            '%s (%s, %s, приём до %s%s)',
            $c['name'],
            $c['type'] === 'international' ? 'международный' : 'всероссийский',
            (int) $c['is_paid'] ? ('оргвзнос ' . (int) $c['price'] . ' ₽') : 'бесплатный',
            (string) $c['end_date'],
            trim((string) ($c['results_date'] ?? '')) !== '' ? (', итоги ' . $c['results_date']) : ''
        );
    }

    $stageNames = [
        1 => 'первое знакомство с центром',
        2 => 'доверие и экспертность',
        3 => 'польза без продажи',
        4 => 'снятие возражений и страхов',
        5 => 'разбор того, как всё устроено',
        6 => 'выгода для педагога или учреждения',
        7 => 'прямое приглашение подать заявку',
    ];

    /* ВОЗРАСТ АДРЕСАТА СТОИТ В ЗАДАНИИ ОТДЕЛЬНОЙ СТРОКОЙ, И С ЧИСЛАМИ.
     *
     * Правка владельца 13.10.2026: «Содержание статей должно быть направленно
     * не только не детскую аудиторию, но и на взрослую и пожилых». Без этого
     * блока модель брала взрослую роль («педагог», «учреждение») и всё равно
     * писала про ребёнка: так устроены её представления о конкурсе для детей.
     * Числа идут из базы (smm_ages_line), а не из промпта: они меняются каждый
     * месяц, и вписанные однажды руками через месяц станут неправдой. */
    $возраст = SMM_AGES[$age] ?? null;
    $ageBlock = '';
    if ($возраст) {
        $ageBlock = "Возрастная группа этого поста: " . $возраст['кому'] . " (категории заявки: "
            . $возраст['категории'] . ").\n"
            . "ЦЕНТР РАБОТАЕТ НЕ ТОЛЬКО С ДЕТЬМИ. " . smm_ages_line($ctx) . " "
            . ($ctx['adult_noms'] ?? [] ? ('Взрослые заявляются прежде всего в номинации: '
                . implode(', ', array_slice((array) $ctx['adult_noms'], 0, 6)) . '. ') : '')
            . "Поэтому тема обязана быть про НАЗВАННУЮ возрастную группу. Если это молодёжь, "
            . "взрослые или старшее поколение — в посте НЕТ ни ребёнка, ни ученика, ни "
            . "родителя: там взрослый человек, который поёт в народном хоре или ансамбле "
            . "ветеранов, читает со сцены, играет на инструменте, занимается в клубе при ДК "
            . "или впервые решился записать свой номер. Если это дети или подростки — наоборот, "
            . "не пиши про взрослых участников. Возраст в теме не называется цифрами категории, "
            . "он виден по сюжету.\n\n";
    }

    /* АФИША СОБИРАЕТСЯ ОТ ПОВОДА, А НЕ ОТ ПОИСКА ТЕМЫ. Тему уже назвал календарь,
       и перебирать варианты незачем: нужны только слова поздравления и одна
       проверяемая строчка о том, за что этого человека помнят. Сама дата
       сверяется отдельно и ДО всякой траты. */
    if ($вид === 'афиша' && $повод) {
        $кто = smm_kal_строка($повод);
        $праздник = (string) ($повод['повод'] ?? '') === 'праздник';
        $задание = "Ты редактор соцсетей Культурного центра «Музыкальный Мир» - онлайн-конкурсы "
            . "для детей и взрослых по восьми направлениям искусства.\n\n"
            . smm_afisha_kogda($повод, $кто)
            . "Собери ПОЗДРАВИТЕЛЬНУЮ АФИШУ центра к этому поводу.\n"
            . ($праздник
                ? "Это общий праздник: поздравляем читателей, а не одного человека.\n"
                : "Это день рождения деятеля культуры. Если человек жив - поздравляем его; "
                . "если его уже нет - вспоминаем и говорим о памяти, без «поздравляем с днём "
                . "рождения».\n")
            . "ЗАПРЕЩЕНО выдумывать произведения, годы, цитаты и подробности биографии: "
            . "бери только то, что знает любой справочник.\n\n"
            . "Верни строго JSON: {\"topic\":\"о чём афиша одной строкой\","
            . "\"fact\":\"одно предложение: чем этот человек или праздник важен\","
            . "\"source\":\"откуда это известно\",\"angle\":\"тон поздравления\","
            . "\"title\":\"ЗАГОЛОВОК НА АФИШУ ЗАГЛАВНЫМИ, 2-4 слова\","
            . "\"subtitle\":\"подзаголовок на афишу, до 60 знаков\","
            . "\"person\":\"имя и фамилия, если афиша о человеке, иначе пусто\","
            . "\"wiki\":\"название статьи русской Википедии о нём, иначе пусто\"}";
        for ($з = 0; $з < 3; $з++) {
            $r = smm_ask_json($задание);
            if ($r && !empty($r['topic'])) {
                $r['_повод'] = $повод;
                if (!$праздник) {
                    if (empty($r['person'])) $r['person'] = (string) $повод['имя'];
                    if (empty($r['wiki']))   $r['wiki']   = (string) ($повод['вики'] ?? '');
                }
                return $r;
            }
            if ((int) ($GLOBALS['SMM_BRAIN_RESTING'] ?? 0) > time()) break;
        }
        $GLOBALS['SMM_TOPIC_REJECTS'][] = 'афиша: модель не ответила';
        return null;
    }

    for ($i = 0; $i < $tries; $i++) {
        $prompt = "Ты редактор соцсетей Культурного центра «Музыкальный Мир» — онлайн-конкурсы "
            . "для детей и взрослых по восьми направлениям: вокал, хореография, инструментальное "
            . "исполнительство, художественное слово, театр, изобразительное искусство, "
            . "декоративно-прикладное творчество, цирковое искусство.\n\n"
            . "Придумай ОДНУ тему поста.\n\n"
            . "Адресат: " . $layer . ".\n"
            . "Задача поста: " . ($stageNames[$stage] ?? 'польза') . ".\n\n"
            . $ageBlock
            . "Сейчас открыт приём:\n- " . implode("\n- ", $comps ?: ['конкурсы месяца']) . "\n\n"
            . ($ctx['nominations'] ? "Чаще всего заявляют номинации: " . implode(', ', array_slice($ctx['nominations'], 0, 10)) . ".\n\n" : '')
            . ($ctx['questions'] ? "О чём недавно спрашивали участники:\n- " . implode("\n- ", array_slice($ctx['questions'], 0, 15)) . "\n\n" : '')
            . "ЗАПРЕЩЕНО повторять эти темы, они уже выходили:\n- " . implode("\n- ", $used) . "\n\n"
            . $осьБлок
            . $свежБлок
            /* ПОДВИД ИСТОРИИ ПРИХОДИТ ИЗВНЕ (правка владельца 15.10.2026): про
               человека, про мир музыки прошлого и про сегодняшний день - по
               кругу. Текст подвида лежит в ОДНОМ месте, SMM_SYUZHETY в
               core/smm.php: вторая копия разошлась бы молча. */
            . ($вид === 'история'
                ? ("ВИД ПОСТА: ИСТОРИЯ, А НЕ СОВЕТ.\n"
                 . "Нужен " . (string) (SMM_SYUZHETY[$сюжет] ?? SMM_SYUZHETY['деятель']) . "\n"
                 . "Имена, годы и суть случая обязаны быть настоящими и общеизвестными: "
                 . "выдуманная подробность видна сразу и бьёт по доверию сильнее любой "
                 . "другой ошибки. Не уверен в подробности - бери другой сюжет, их тысячи. "
                 . "История обязана быть ИНТЕРЕСНОЙ: такой, которую хочется пересказать "
                 . "знакомым, а не похожей на справку из учебника.\n\n")
                : '')
            . "Требования к теме:\n"
            . "1. Тема узкая и конкретная, не «о пользе музыки», а один ясный сюжет.\n"
            . "2. В основе — проверяемый факт одного из трёх видов: широко известное "
            . "исследование, которое ты точно знаешь; исторический случай с именем и годом; "
            . "или устройство профессии, жанра, инструмента.\n"
            . "ВЫДУМЫВАТЬ ИССЛЕДОВАНИЯ, ФАМИЛИИ, УНИВЕРСИТЕТЫ, ГОДЫ И ПРОЦЕНТЫ ЗАПРЕЩЕНО. "
            . "Не приписывай настоящего учёного чужому университету и не дорисовывай цифру, "
            . "которой не знаешь наверняка. Если точного процента нет — обходись без него: "
            . "честное «заметно точнее» лучше выдуманных «на 30 %». Сомневаешься в "
            . "исследовании — бери устройство профессии, там вымысел невозможен.\n"
            . "3. Источник не должен повторять уже использованные.\n"
            . "4. Тема полезна адресату сама по себе, даже если он никогда не подаст заявку.\n\n"
            . "Верни строго JSON: {\"topic\":\"тема одной строкой\",\"fact\":\"факт в одном "
            . "предложении\",\"source\":\"источник факта: университет, учёный, год\","
            . "\"angle\":\"под каким углом подаём\",\"title\":\"ЗАГОЛОВОК НА КАРТИНКУ ЗАГЛАВНЫМИ, "
            . "2-4 слова\",\"subtitle\":\"подзаголовок на картинку, до 60 знаков\""
            /* У истории про мир музыки героя-человека может не быть вовсе
               (премьера, инструмент, зал), и требовать имя значит заставить
               модель его выдумать. Пусто - кадр соберётся без портрета. */
            . ($вид === 'история'
                ? ",\"person\":\"имя и фамилия героя, если история о человеке, иначе пусто\","
                . "\"wiki\":\"статья о нём в русской Википедии, иначе пусто\"}"
                : "}");

        $r = smm_ask_json($prompt);
        if (!$r || empty($r['topic'])) {
            if ((int) ($GLOBALS['SMM_BRAIN_RESTING'] ?? 0) > time()) {
                $GLOBALS['SMM_TOPIC_REJECTS'][] = 'мозг отдыхает по квоте до '
                    . date('H:i', (int) $GLOBALS['SMM_BRAIN_RESTING']);
                break;
            }
            $GLOBALS['SMM_TOPIC_REJECTS'][] = 'модель не ответила темой (квота, таймаут или не-JSON)';
            continue;
        }

        /* ЗАГОЛОВОК ОБЯЗАТЕЛЕН, И ЭТО КУПЛЕНО ЖИВЫМ ПОСТОМ.
         *
         * 16.10.2026 в ленту вышел пост #21 про премьеру «Весны священной», у
         * которого поле заголовка осталось ПУСТЫМ: мозг прислал тему и
         * подзаголовок, а title забыл. В задание кадра ушло дословно
         * `The HEADLINE reads exactly ""`, и модель придумала заголовок сама -
         * «ОСВИСТАННЫЙ БАЛЕТ, СТАВШИЙ КЛАССИКОЙ», - а рядом напечатала
         * подзаголовок почти теми же словами. На листе одно и то же дважды.
         * Ни одна проверка этого не видела: пустая строка не ошибка.
         * Тема без заголовка не годится - берём следующую. */
        if (trim((string) ($r['title'] ?? '')) === '') {
            $GLOBALS['SMM_TOPIC_REJECTS'][] = mb_substr((string) $r['topic'], 0, 50)
                . ' → заголовка нет: на лист ушла бы пустая строка, и модель придумала бы его сама';
            continue;
        }

        /* ИСТОРИЯ БЕЗ НАСТОЯЩЕГО СЛУЧАЯ - ЭТО СОВЕТ ПОД ЧУЖИМ ИМЕНЕМ.
         *
         * Правка владельца 19.10.2026 отдала утренний слот истории, и подмена
         * стала дорогой: пост #63 «Как подростки с помощью видео находят свой
         * голос в пении» лежал в очереди как ИСТОРИЯ, а в нём ни имени, ни года,
         * ни события - общее рассуждение, то есть ровно тот однообразный совет,
         * от которого и просили уйти. Требуем примету настоящего случая: имя
         * героя или год. Нет ни того, ни другого - берём следующую тему. */
        if ($вид === 'история') {
            $всёТемы = (string) $r['topic'] . ' ' . (string) ($r['fact'] ?? '')
                     . ' ' . (string) ($r['source'] ?? '');
            if (trim((string) ($r['person'] ?? '')) === ''
                && !preg_match('~(1[5-9]\d\d|20\d\d)~u', $всёТемы)) {
                $GLOBALS['SMM_TOPIC_REJECTS'][] = mb_substr((string) $r['topic'], 0, 50)
                    . ' → история без имени и без года: это рассуждение, а не случай';
                continue;
            }
        }

        [$fresh, $why] = smm_topic_is_fresh(
            (string) $r['topic'], (string) ($r['fact'] ?? ''), (string) ($r['source'] ?? '')
        );
        if (!$fresh) { $GLOBALS['SMM_TOPIC_REJECTS'][] = mb_substr((string) $r['topic'], 0, 50) . ' → ' . $why; continue; }

        [$factOk, $factWhy] = smm_fact_check((string) ($r['fact'] ?? ''), (string) ($r['source'] ?? ''), $вид);

        /* СОМНИТЕЛЬНЫЙ ФАКТ ЧИНИМ, А НЕ ВЫБРАСЫВАЕМ ВМЕСТЕ С ТЕМОЙ.
         *
         * Модель тянется к цифре: «по данным арт-платформ, награды повышают
         * доверие на 40 %». Тема при этом бывает хорошая, негодна только
         * приписка. Выбрасывать всё целиком — значит часами не находить ни одной
         * темы и оставить ленту пустой, чего и просили не допустить. Поэтому
         * факт переписывается без недостоверной части и проверяется заново;
         * если после чистки от него ничего не остаётся — вот тогда тема уходит. */
        if (!$factOk) {
            $fixed = smm_fact_repair((string) ($r['fact'] ?? ''), (string) ($r['source'] ?? ''), $factWhy, $вид);
            if ($fixed === null) { $GLOBALS['SMM_TOPIC_REJECTS'][] = mb_substr((string) $r['topic'], 0, 50) . ' → факт не подтверждён: ' . $factWhy; continue; }

            [$factOk, $factWhy] = smm_fact_check($fixed['fact'], $fixed['source'], $вид);
            if (!$factOk) { $GLOBALS['SMM_TOPIC_REJECTS'][] = mb_substr((string) $r['topic'], 0, 50) . ' → факт не чинится: ' . $factWhy; continue; }

            $r['fact']   = $fixed['fact'];
            $r['source'] = $fixed['source'];

            /* Починенный факт — другой факт. Сверяем заново: вдруг после чистки
               он совпал с тем, что уже выходило. */
            [$fresh2, $why2] = smm_topic_is_fresh((string) $r['topic'], $r['fact'], $r['source']);
            if (!$fresh2) { $GLOBALS['SMM_TOPIC_REJECTS'][] = mb_substr((string) $r['topic'], 0, 50) . ' → ' . $why2; continue; }
        }

        return $r;
    }
    return null;
}

/**
 * Проверка факта отдельным вопросом — обязательная ступень, а не перестраховка.
 *
 * Первый же прогон конвейера выдал «исследование Университета Макгилла под
 * руководством доктора Патриции Култ, 2021, ускорение обработки фонетики на 30 %».
 * Патриция Кул действительно изучает восприятие речи, но работает в Вашингтонском
 * университете, а процент выдуман целиком. Такой пост центр не переживёт: любой
 * педагог проверит ссылку за минуту и перестанет верить всему остальному.
 *
 * Модель, которую спрашивают «придумай тему», склонна склеивать настоящую фамилию
 * с чужим университетом и дорисовывать убедительную цифру. Та же модель, которую
 * спрашивают «это правда?» отдельным вопросом, без обязанности что-то сочинить,
 * такие склейки замечает. Поэтому вопрос задаётся заново и сомнение трактуется
 * против факта: не подтвердилось — тема выбрасывается, тем всё равно бесконечно.
 */
function smm_fact_check(string $fact, string $source, string $вид = 'совет'): array {
    $fact = trim($fact);
    if ($fact === '') return [false, 'факт пустой'];

    /* У СОВЕТА И У ИСТОРИИ ЛОЖЬ РАЗНАЯ, ЗНАЧИТ И ПРОВЕРКА РАЗНАЯ.
     *
     * Сторож писался под совет, где факт это исследование: учёный, университет,
     * процент, год - там и врёт модель, склеивая настоящую фамилию с чужим
     * институтом. У истории (правило 41) факт биографический: человек, год,
     * произведение, случай из жизни. Задавать ей те же четыре вопроса значит
     * браковать всё подряд, и 14.10.2026 так и вышло: тринадцать заходов за
     * историей отбиты со словами «источник указан расплывчато», «нет страницы и
     * издания», «причинная связь не доказана». Дневная норма мозга сгорела
     * впустую, а ни одной истории лента не получила. Для общеизвестного
     * биографического случая ссылка на биографию - достаточный источник;
     * придираться надо к выдуманной детали, а не к отсутствию номера страницы. */
    /* У АФИШИ ФАКТ БИОГРАФИЧЕСКИЙ, КАК У ИСТОРИИ, И ЭТО СТОИЛО ПОЗДРАВЛЕНИЯ.
       Правило 44 дало свои критерии истории, а афиша осталась в ветке «научного
       редактора» - и в ночь на 15.10.2026 сторож забраковал поздравление
       Лермонтову, САМ ЖЕ написав в причине: «родился 3 (15) октября 1814 года,
       поэтому 212-летие приходится на 2026 год и корректно. Однако в тексте нет
       выдуманных дат, поэтому этот пункт не является выдумкой» - и вердикт
       doubt. Текст переписывался дважды и был пропущен совсем, слот остался
       пустым. Поздравление ко дню рождения это тот же биографический факт:
       человек, год, произведения. Дата вдобавок уже сверена отдельным заслоном
       (`smm_kal_проверить`) и запомнена.
       Ветки ТЕКСТА (объём, абзацы) это НЕ трогает: у афиши там свои числа
       (SMM_BODY_MIN_AFISHA, правило 41). */
    if ($вид === 'история' || $вид === 'афиша') {
        /* ИСТОРИЯ БЫВАЕТ НЕ ТОЛЬКО ПРО ЧЕЛОВЕКА (правка владельца 15.10.2026):
           про премьеру, инструмент, зал, оркестр и запись - тоже. Вопросы,
           спрашивавшие только про человека, на такой истории не срабатывали бы. */
        $prompt = "Проверь утверждение по истории культуры и музыки. Отвечай как "
            . "редактор, который обязан поймать выдумку до публикации.\n\n"
            . "Утверждение: " . $fact . "\n"
            . "Указанный источник: " . $source . "\n\n"
            . "Проверь по пунктам:\n"
            . "1. Существовали ли названные люди, произведения, коллективы, залы "
            . "и события и верно ли они названы.\n"
            . "2. Было ли описанное на самом деле, или это домысел "
            . "и красивая легенда, выдаваемая за факт.\n"
            . "3. Верны ли год и период. Ошибка в десятилетие — это ложь.\n"
            . "4. Не приписаны ли человеку или коллективу чужие произведения, "
            . "должности, награды или слова.\n\n"
            . "ЧЕГО НЕ ТРЕБУЙ: точного издания, страницы и цитаты — для "
            . "общеизвестного биографического случая ссылки на биографию "
            . "достаточно. Не требуй и доказанной причинной связи: история это "
            . "случай из жизни, а не научная работа. Общая формулировка сама по "
            . "себе не ложь.\n"
            . "Вердикт «doubt» ставь, когда названное НЕВЕРНО или выдумано, а не "
            . "когда источник назван широко.\n"
            /* Модель проверяла пункт, писала «корректно, это не выдумка» и всё
               равно ставила doubt: привычка к осторожности оказалась сильнее
               вердикта. Поэтому сказано прямо - проверил и сошлось, ставь ok. */
            . "Если по всем пунктам сошлось - ставь \"ok\". Проверил пункт и он верен "
            . "- это НЕ повод для \"doubt\".\n\n"
            . "Верни строго JSON: {\"verdict\":\"ok|doubt\",\"why\":\"коротко, что не так\"}";
    } else {
    $prompt = "Проверь утверждение на достоверность. Отвечай строго и придирчиво, "
        . "как научный редактор, который обязан поймать ошибку до публикации.\n\n"
        . "Утверждение: " . $fact . "\n"
        . "Указанный источник: " . $source . "\n\n"
        . "Проверь по пунктам:\n"
        . "1. Существует ли такое исследование или факт на самом деле.\n"
        . "2. Тот ли это учёный и правда ли он работает в названном университете. "
        . "Частая ошибка — настоящая фамилия приписана чужому учреждению.\n"
        . "3. Не выдуманы ли числа и проценты. Если точной цифры в источнике нет — это ложь.\n"
        . "4. Соответствует ли год действительности.\n\n"
        . "Если хоть один пункт вызывает сомнение — вердикт «doubt». "
        . "«ok» ставится только когда ты уверен во всех четырёх.\n\n"
        . "Верни строго JSON: {\"verdict\":\"ok|doubt\",\"why\":\"коротко, что не так\"}";
    }

    $r = smm_ask_json($prompt, 60);
    if (!is_array($r)) return [false, 'проверка не ответила'];

    $v = mb_strtolower(trim((string) ($r['verdict'] ?? '')), 'UTF-8');
    return $v === 'ok' ? [true, ''] : [false, (string) ($r['why'] ?? 'сомнение без пояснения')];
}

/**
 * Переписать факт честно. Возвращает null, если спасать нечего: бывает, что
 * утверждение целиком держалось на выдуманном исследовании, и после вычёркивания
 * вымысла остаётся пустота — такую тему и правда надо отпустить.
 */
function smm_fact_repair(string $fact, string $source, string $why, string $вид = 'совет'): ?array {
    /* У ИСТОРИИ ЧИНИТЬ НАДО ДРУГОЕ. Совету велят выбросить выдуманный процент и
       поправить учёного с институтом; у биографического случая ни того, ни
       другого нет, зато бывает приписанная чужая деталь или сдвинутый год. */
    /* У АФИШИ ФАКТ БИОГРАФИЧЕСКИЙ, КАК У ИСТОРИИ, И ЭТО СТОИЛО ПОЗДРАВЛЕНИЯ.
       Правило 44 дало свои критерии истории, а афиша осталась в ветке «научного
       редактора» - и в ночь на 15.10.2026 сторож забраковал поздравление
       Лермонтову, САМ ЖЕ написав в причине: «родился 3 (15) октября 1814 года,
       поэтому 212-летие приходится на 2026 год и корректно. Однако в тексте нет
       выдуманных дат, поэтому этот пункт не является выдумкой» - и вердикт
       doubt. Текст переписывался дважды и был пропущен совсем, слот остался
       пустым. Поздравление ко дню рождения это тот же биографический факт:
       человек, год, произведения. Дата вдобавок уже сверена отдельным заслоном
       (`smm_kal_проверить`) и запомнена.
       Ветки ТЕКСТА (объём, абзацы) это НЕ трогает: у афиши там свои числа
       (SMM_BODY_MIN_AFISHA, правило 41). */
    if ($вид === 'история' || $вид === 'афиша') {
        $prompt = "Биографический факт для поста не прошёл проверку.\n\n"
            . "Факт: " . $fact . "\n"
            . "Источник: " . $source . "\n"
            . "Что не так: " . $why . "\n\n"
            . "Перепиши его так, чтобы каждое слово было правдой:\n"
            . "- убери домыслы и красивые легенды, оставь то, что правда было;\n"
            . "- поправь год и период, если они сдвинуты;\n"
            . "- убери чужие произведения, должности и слова, приписанные человеку;\n"
            . "- не выдумывай цитат и диалогов.\n"
            . "Случай должен остаться СЮЖЕТОМ с именем и годом, а не превратиться "
            . "в перечень заслуг.\n\n"
            . "Если после чистки от случая ничего не остаётся, верни пустую строку "
            . "в поле fact.\n\n"
            . "Верни строго JSON: {\"fact\":\"честный факт\",\"source\":\"честный источник\"}";
        $r = smm_ask_json($prompt, 60);
        if (!is_array($r)) return null;
        $f2 = trim((string) ($r['fact'] ?? ''));
        if ($f2 === '') return null;
        return ['fact' => $f2, 'source' => trim((string) ($r['source'] ?? $source))];
    }

    $prompt = "Факт для поста не прошёл проверку достоверности.\n\n"
        . "Факт: " . $fact . "\n"
        . "Источник: " . $source . "\n"
        . "Что не так: " . $why . "\n\n"
        . "Перепиши факт так, чтобы он стал полностью достоверным:\n"
        . "- убери проценты и числа, которых нет в настоящих источниках;\n"
        . "- убери или исправь неверную привязку учёного к учреждению и неверный год;\n"
        . "- если исследование выдумано — замени утверждение на то, что проверяемо: "
        . "устройство профессии, жанра или инструмента, общеизвестный исторический "
        . "случай. Там вымысел невозможен.\n"
        . "Качественное утверждение без цифры («заметно точнее», «быстрее обычного») "
        . "лучше точной выдумки.\n\n"
        . "Если после удаления всего недостоверного от факта ничего не остаётся, "
        . "верни пустую строку в поле fact.\n\n"
        . "Верни строго JSON: {\"fact\":\"честный факт\",\"source\":\"честный источник\"}";

    $r = smm_ask_json($prompt, 60);
    if (!is_array($r)) return null;

    $fact2 = trim((string) ($r['fact'] ?? ''));
    if ($fact2 === '' || mb_strlen($fact2, 'UTF-8') < 25) return null;

    return ['fact' => $fact2, 'source' => trim((string) ($r['source'] ?? ''))];
}

