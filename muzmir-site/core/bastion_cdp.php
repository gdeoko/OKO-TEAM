<?php
/**
 * ПОРТ БРАУЗЕРА С ВХОДОМ В CHATGPT СПРАШИВАЕМ У БАСТИОНА, А НЕ ПОМНИМ.
 *
 * В четырёх скриптах генерации был вписан порт 9222, и рядом стояло пояснение
 * «9222 - профиль центра, где выполнен вход в ChatGPT». 16.10.2026 это оказалось
 * неправдой: порты на бастионе развели (в его же кроне строка так и называется -
 * «ПАУЗА (ChatGPT на 9222, развожу порты)»), вход живёт на 9280, а на 9222
 * браузера нет вовсе. Пересборка афиши шесть минут ждала картинку и кончилась
 * словами «Не дождался картинки», а настоящая причина лежала в логе бастиона:
 * connect ECONNREFUSED 127.0.0.1:9222.
 *
 * Вписанный номер устаревает молча, поэтому порт ищется ПО ФАКТУ: у какого
 * браузера открыта вкладка chatgpt.com, тот и нужен. Ответ помнится на время
 * одного прогона - бастион не нужно спрашивать на каждую картинку.
 *
 * @param callable $bastion  функция «выполнить команду на бастионе и вернуть вывод»
 */
declare(strict_types=1);

const BASTION_CDP_PORTS = '9280 9222 9333 9281 9223';

function bastion_cdp_url(callable $bastion): string {
    static $найден = null;
    if ($найден !== null) return $найден;

    $raw = (string) $bastion('for p in ' . BASTION_CDP_PORTS
         . '; do if curl -s --max-time 3 http://127.0.0.1:$p/json/list 2>/dev/null'
         . ' | grep -qi chatgpt; then echo $p; break; fi; done', 60);
    $порт = '';
    foreach (preg_split('~\R~', trim($raw)) as $стр) {
        if (preg_match('~^\s*(\d{4,5})\s*$~', (string) $стр, $m)) { $порт = $m[1]; break; }
    }
    if ($порт === '') {
        /* Говорим словами: «не дождался картинки» без причины читается как сбой
         * генерации, и чинить начинают промпт, а не браузер. */
        fwrite(STDERR, "ВНИМАНИЕ: на бастионе нет браузера с открытым ChatGPT "
             . "(проверены порты " . BASTION_CDP_PORTS . "). Генерация, скорее всего, не выйдет: "
             . "подними браузер с профилем, где выполнен вход, и повтори.\n");
        return $найден = 'http://127.0.0.1:9280';
    }
    return $найден = 'http://127.0.0.1:' . $порт;
}
