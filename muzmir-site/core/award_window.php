 * когда результат стал известен участнику: публикация списка (длинный
 * конкурс), письмо с результатом (короткий), иначе дата оценки.
 */
declare(strict_types=1);

const AWARD_ORDER_DAYS = 60;

/** Текст для участника — одинаковый везде: страницы, письма, бот. */
function award_window_text(): string {
    return 'Подать заявку на изготовление наградного материала (согласно аттестационному результату) возможно '
         . 'в течение ' . AWARD_ORDER_DAYS . ' дней после оглашения (получения) аттестационного результата. '
         . 'По истечении этого срока заявки на изготовление по данному результату не принимаются.';
}

/**
 * День оглашения результата для заявки. $app может уже нести поля конкурса
 * (comp_results_pub); если их нет — дочитываем из базы.
 */
function award_window_since(array $app): string {
    $pub = trim((string) ($app['comp_results_pub'] ?? ''));
    if ($pub === '' && !empty($app['competition_id'])) {
        try {
            $pub = trim((string) (scalar("SELECT COALESCE(results_published_at,'') FROM competitions WHERE id=?",
                                         [(int) $app['competition_id']]) ?: ''));
        } catch (\Throwable $e) { $pub = ''; }
    }
    if ($pub !== '') return $pub;
    $sent = trim((string) ($app['result_sent_at'] ?? ''));
    if ($sent !== '') return $sent;
    return trim((string) ($app['graded_at'] ?? ''));
}

/** До какого момента (unix) можно подать заявку на изготовление; 0 — даты нет, срок не считаем. */
function award_window_until(array $app): int {
    $s = award_window_since($app);
    $t = $s !== '' ? strtotime($s) : false;
    return $t ? $t + AWARD_ORDER_DAYS * 86400 : 0;
}

/** Открыт ли ещё приём заявок на изготовление по этой заявке. */
function award_window_open(array $app): bool {
    $u = award_window_until($app);
    return $u === 0 || time() <= $u;
}
