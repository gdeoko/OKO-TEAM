/**
 * ПИСЬМО УЧАСТНИКУ, ЧЬЮ ЗАЯВКУ СНЯЛИ С КОНКУРСА «ТОЛЬКО ДЛЯ ЧЛЕНОВ КЛУБА».
 *
 * Слово владельца 16.10.2026: приём заявок в платный конкурс «Мировой акцент»
 * идёт только от участников Элитного клуба (правило 72). Признак появился
 * позже самих заявок, и четыре человека успели подать до него: форма их
 * приняла, трое оплатили оргвзнос. Владелец решил снять эти заявки, извиниться
 * и предложить вступить в Клуб.
 *
 * ПОЧЕМУ ПИСЬМО СОБИРАЕТСЯ ЗДЕСЬ, А НЕ В РАЗОВОМ СКРИПТЕ. Признак стоит у
 * конкурса, конкурсы заводятся каждый месяц заново (правило 11), и такое
 * снятие повторится при любой новой правке условий приёма. Разовый текст
 * пришлось бы писать заново и он разошёлся бы с привилегиями Клуба - а они
 * живут в `core/club_perks.php` и меняются словом владельца.
 *
 * ПРИВИЛЕГИИ НЕ ПЕРЕПИСЫВАЮТСЯ СЛОВАМИ. Сетка берётся у `mmc_vip_perks_grid()`,
 * то есть у того же единого списка, что на странице Клуба и в карточке каждого
 * письма центра. Вторая редакция обещания расходится молча: это уже стоило
 * центру неверных обещаний тысячами писем (правила 33, 46, 56а, 64, 69).
 *
 * ЦЕНЫ ТОЖЕ НЕ ВПИСАНЫ: `club_price` и `club_price_year` из настроек.
 *
 * ДЕНЬГИ ЦЕНТР НЕ ДВИГАЕТ (правило 8а): письмо только ОБЕЩАЕТ возврат, который
 * владелец проводит руками. Поэтому сумма возврата приходит параметром, а не
 * считается тут и уж точно не отправляется в кассу.
 */
declare(strict_types=1);

/**
 * Текст и тема письма.
 *
 * @param array $a       заявка целиком
 * @param array $c       конкурс целиком
 * @param int   $возврат сумма к возврату в рублях; 0 - денег центр не получил
 * @return array{subject:string,html:string,name:string,email:string}
 */
function club_entry_mail_html(array $a, array $c, int $возврат = 0): array {
    require_once BASE_PATH . '/core/result_mail.php';
    require_once BASE_PATH . '/core/mail_campaigns.php';
    require_once BASE_PATH . '/core/club_free.php';

    $номер = (string) ($a['number'] ?? '');
    $конк  = (string) ($c['name'] ?? '');

    /* ИМЯ: у заявки коллектива `full_name` пуст, и безличное «Здравствуйте!»
       в письме с извинением читается особенно сухо (урок правила 31). Тогда
       берём педагога - письмо и уходит на его почту. */
    $имя = trim((string) ($a['full_name'] ?? ''));
    if ($имя === '') {
        /* ЯРЛЫК ДОЛЖНОСТИ СНИМАЕТ ЕДИНЫЙ ПОМОЩНИК, А НЕ СВОЯ РЕГУЛЯРКА.
           Здесь стояло снятие только «Педагог:», а в поле бывают ещё
           «Руководитель:» (245 заявок), «Преподаватель:» (50), «Хормейстер:»
           и несколько человек сразу. Такому письму доставалось обращение
           «Здравствуйте, Руководитель: Дычко Анатолий Александрович!».
           Несколько человек в поле - здороваемся безлично. */
        if (!function_exists('curator_split_teachers')) {
            require_once BASE_PATH . '/core/curator_awards.php';
        }
        $__ped = curator_split_teachers((string) ($a['teacher'] ?? ''));
        $имя = count($__ped) === 1 ? trim($__ped[0]) : '';
    }
    $привет = $имя !== '' ? 'Здравствуйте, ' . h($имя) . '!' : 'Здравствуйте!';

    /* Чья это заявка в первой фразе: у коллектива называем коллектив. */
    /* НАЗВАНИЕ КОЛЛЕКТИВА УЖЕ НЕСЁТ СВОЙ ВИД И СВОИ КАВЫЧКИ. Первая сборка
       писала «Заявка ансамбля «Ансамбль народного танца «Крымские искорки»»» -
       слово «ансамбль» дважды и кавычки внутри кавычек. */
    $чья = trim((string) ($a['group_name'] ?? '')) !== ''
        ? 'Заявка коллектива ' . h(trim((string) $a['group_name']))
        : 'Ваша заявка';

    $цена     = (int) (function_exists('setting') ? setting('club_price', 1000) : 1000);
    $ценаГод  = (int) (function_exists('setting') ? setting('club_price_year', 10000) : 10000);
    $льгота   = function_exists('club_free_limit') ? club_free_limit() : 3;
    $скидка   = function_exists('mm_vip_discount') ? mm_vip_discount() : 20;

    $navy = RM_NAVY; $muted = RM_MUTED;

    /* Блок про деньги. Обещаем ровно то, что сказал владелец: сутки на возврат,
       и возврат он делает сам. Денег центр не получал - говорим и это, иначе
       человек будет ждать перевода, которого не будет. */
    $деньги = $возврат > 0
        ? '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin:0 0 20px;background:#EAF7EF;border:1px solid #BFE6CC;border-radius:14px;">'
          . '<tr><td style="padding:16px 22px;">'
          . '<div style="font-size:12px;letter-spacing:.1em;text-transform:uppercase;color:#1E7A44;margin-bottom:6px;">Возврат оргвзноса</div>'
          . '<div style="font-size:14px;line-height:1.7;color:' . RM_INK . ';">Оргвзнос <b>' . $возврат . ' ₽</b> возвращается в полном объёме на тот же способ оплаты. '
          . 'Возврат будет проведён в течение суток, зачисление в банке занимает до трёх рабочих дней.</div>'
          . '</td></tr></table>'
        : '<p style="margin:0 0 20px;color:' . $muted . ';font-size:14px;">Оргвзнос по этой заявке в центр не поступал: попытки оплаты не завершились. '
          . 'Возвращать нечего, и списаний по ним не было.</p>';

    $inner =
          '<h1 style="margin:0 0 16px;font-family:Georgia,\'Times New Roman\',serif;font-size:24px;line-height:1.3;font-weight:700;color:' . $navy . ';">'
        . 'Заявка №' . h($номер) . ' снята с конкурса</h1>'
        . '<p style="margin:0 0 14px;">' . $привет . '</p>'
        . '<p style="margin:0 0 14px;">Приносим извинения. ' . $чья . ' на конкурс «' . h($конк) . '» была принята формой сайта по ошибке: '
        . 'из-за технического сбоя система не проверила условие приёма. Приём заявок на этот конкурс идёт '
        . '<b style="color:' . $navy . ';">только от участников Элитного клуба</b> Культурного центра «Музыкальный Мир». '
        . 'Заявку пришлось снять, и вина за это наша.</p>'
        . rm_mail_app_card($a, $c)
        . $деньги
        . '<h2 style="margin:26px 0 10px;font-family:Georgia,\'Times New Roman\',serif;font-size:19px;line-height:1.3;font-weight:700;color:' . $navy . ';">'
        . 'Элитный клуб: что он даёт</h2>'
        . '<p style="margin:0 0 6px;">Членство в Клубе открывает участие в платных конкурсах центра и даёт ещё целый ряд привилегий. '
        . 'Платный конкурс у центра один в месяц, и до ' . $льгота . ' заявок в нём участник Клуба подаёт '
        . '<b style="color:' . $navy . ';">без оргвзноса</b>, как оплаченные: с электронными дипломами и в короткий срок. '
        . 'На всё остальное платное действует скидка ' . $скидка . '%.</p>'
        . mmc_vip_perks_grid()
        . '<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin:0 0 18px;background:' . RM_CARD . ';border:1px solid ' . RM_LINE . ';border-radius:14px;">'
        . '<tr><td style="padding:16px 22px;">'
        . '<div style="font-size:12px;letter-spacing:.1em;text-transform:uppercase;color:' . $muted . ';margin-bottom:6px;">Стоимость членства</div>'
        . '<div style="font-size:15px;line-height:1.7;color:' . RM_INK . ';"><b>' . number_format($цена, 0, ',', ' ') . ' ₽</b> в месяц '
        . 'или <b>' . number_format($ценаГод, 0, ',', ' ') . ' ₽</b> за год. Продление автоматическое, отменить можно в любое время в личном кабинете.</div>'
        . '</td></tr></table>'
        . '<p style="margin:0 0 6px;color:' . $muted . ';font-size:14px;">Бесплатные конкурсы центра открыты для всех, и заявку в них можно подать прямо сейчас. '
        . 'Если останутся вопросы, ответим по телефону колл-центра или письмом на этот адрес.</p>';

    $html = mm_email_tx($inner, [
        'preheader' => 'Заявка №' . $номер . ' снята: приём на этот конкурс идёт только от участников Элитного клуба. '
                     . ($возврат > 0 ? 'Оргвзнос возвращается в течение суток.' : 'Оргвзнос не списывался.'),
        'hero'      => mm_cta_primary(url('/club'), 'Вступить в Элитный клуб',
                                      'До ' . $льгота . ' заявок в месяц без оргвзноса · скидка ' . $скидка . '%'),
        'actions'   => [['Бесплатные конкурсы', url('/competitions')], ['Личный кабинет', url('/cabinet')]],
        /* Карточку Клуба в подвале снимаем: полная сетка привилегий стоит в теле
           письма, и вторая, укороченная, читалась бы как повтор. */
        'vip'       => false,
    ]);

    return [
        'subject' => 'Заявка №' . $номер . ' снята с конкурса «' . $конк . '» - приносим извинения',
        'html'    => $html,
        'name'    => $имя,
        'email'   => trim((string) ($a['email'] ?? '')),
    ];
}

/**
 * Ставит письмо в очередь. Возвращает id письма в очереди или 0.
 *
 * Время отправки - ближайшее рабочее (`ga_next_worktime()`): наружу ничего не
 * уходит ночью и в воскресенье, а письмо с извинением тем более (правило 7).
 */
function club_entry_mail_send(int $appId, int $возврат = 0): int {
    $a = one("SELECT * FROM applications WHERE id=?", [$appId]);
    if (!$a || trim((string) ($a['email'] ?? '')) === '') return 0;
    $c = one("SELECT * FROM competitions WHERE id=?", [(int) $a['competition_id']]) ?: [];
    $m = club_entry_mail_html((array) $a, (array) $c, $возврат);
    if ($m['email'] === '') return 0;
    require_once BASE_PATH . '/core/grade_apply.php';
    return mail_queue($m['email'], $m['name'], $m['subject'], $m['html'], '',
                      function_exists('ga_next_worktime') ? ga_next_worktime() : '');
}
