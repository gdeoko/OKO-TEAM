/** Ссылки нового сайта — единственный источник адресов для всех шаблонов. */
function ct_links(): array {
    $site = rtrim((string) cfgv('base_url', ''), '/');
    if ($site === '') $site = 'https://' . trim((string) cfgv('domain', 'музыкальный-мир.рф'), '/');
    return [
        'site'      => $site,
        'apply'     => $site . '/apply',
        'comps'     => $site . '/competitions',
        'awards'    => $site . '/awards',
        'order'     => $site . '/order-awards',
        'faq'       => $site . '/faq',
        'reviews'   => $site . '/reviews',
        'results'   => $site . '/results',
        'verify'    => $site . '/verify',
        'cabinet'   => $site . '/cabinet',
        'track'     => 'https://www.pochta.ru/tracking',
    ];
}

/** Справочный блок центра. Ставится один раз за разговор, а не под каждым ответом. */
function ct_reference_block(): string {
    $l = ct_links();
    return "🕑 График работы: " . (string) cfgv('org_hours', 'Пн-Пт 09:00-18:00, Сб 10:00-16:00, Вс выходной (МСК)') . "\n"
         . "☎️ Колл-центр: " . (string) cfgv('org_phone', '') . " (звонки со скрытых номеров блокируются)\n"
         . "🌍 Сообщество ВКонтакте: " . (string) cfgv('org_vk', '') . "\n"
         . "📖 Справка и частые вопросы: " . $l['faq'];
}

