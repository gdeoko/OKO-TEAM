/**
 * Канон для системного промпта бота: коротко, темами, с прямым запретом копировать.
 * Полные тексты в промпт не тянем — важна структура, а не буквы.
 */
function chat_templates_prompt(): string {
    $out = ["КАНОН ОТВЕТОВ ЦЕНТРА (структура и тон, НЕ текст для копирования — пиши каждый раз своими словами):"];
    foreach (chat_templates() as $key => $tpl) {
        $short = trim((string) preg_replace('~\s+~u', ' ', $tpl['text']));
        $out[] = '• ' . $tpl['title'] . ' (' . $tpl['when'] . '): ' . mb_substr($short, 0, 320);
    }
    $out[] = 'Плейсхолдеры вида НАЗВАНИЕ, НОМЕР подставляй настоящими данными участника, а если их нет — спроси.';
    $out[] = 'Справочный блок (график, телефон, сообщество) добавляй ОДИН раз за разговор и только по делу.';
    return implode("\n", $out);
}
