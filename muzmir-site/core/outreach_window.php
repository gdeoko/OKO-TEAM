/**
 * КОГДА ЦЕНТРУ ВООБЩЕ МОЖНО ПИСАТЬ И ПУБЛИКОВАТЬ НАРУЖУ.
 *
 * Правило владельца, действующее для всей рассылки, было записано только для
 * писем (core/send_timing.php): рабочее окно 09:00–18:00, воскресенье нерабочее,
 * ночью не уходит ничего. Записи в чужие сообщества и сообщения администраторам
 * этой проверки не имели, и в ночь на воскресенье наружу ушли публикации,
 * которых там быть не должно.
 *
 * Здесь проверка одна на все наружные каналы и стоит она внутри самих
 * отправщиков, а не в расписании крона. Расписание можно случайно поменять,
 * скрипт можно запустить руками, а это правило учреждение видит на своей стене
 * и по нему судит о центре: запись в час ночи в воскресенье выглядит как
 * рассылка робота, чем она и является.
 *
 * Окно шире почтового на час: последняя дневная волна записей приходится на
 * 18:00, и она должна успеть уйти целиком.
 */
declare(strict_types=1);

/** Начало и конец рабочего окна наружных публикаций, часы МСК. */
const OUTREACH_HOUR_FROM = 9;
const OUTREACH_HOUR_TO   = 19;   // не включительно: последняя волна в 18:xx

/**
 * Можно ли прямо сейчас публиковать и писать наружу.
 * $force — ручной обход для проверок; в кронах не используется.
 */
function outreach_window_ok(bool $force = false): bool {
    if ($force) return true;
    $now = new \DateTime('now');
    if ((int) $now->format('w') === 0) return false;                  // воскресенье
    $h = (int) $now->format('G');
    return $h >= OUTREACH_HOUR_FROM && $h < OUTREACH_HOUR_TO;
}

/** Человеческая причина отказа — для журналов и для отчёта в консоли. */
function outreach_window_reason(): string {
    $now = new \DateTime('now');
    if ((int) $now->format('w') === 0) return 'воскресенье — наружу ничего не уходит';
    $h = (int) $now->format('G');
    if ($h < OUTREACH_HOUR_FROM) return 'до начала рабочего окна (' . OUTREACH_HOUR_FROM . ':00 МСК)';
    if ($h >= OUTREACH_HOUR_TO)  return 'после конца рабочего окна (' . OUTREACH_HOUR_TO . ':00 МСК)';
    return '';
}

/**
 * Остановить выполнение, если сейчас не рабочее окно.
 * Возвращает true, когда работать можно; иначе печатает причину и возвращает false.
 */
function outreach_window_guard(bool $force = false): bool {
    if (outreach_window_ok($force)) return true;
    if (PHP_SAPI === 'cli') echo '  наружу сейчас нельзя: ' . outreach_window_reason() . "\n";
    return false;
}
