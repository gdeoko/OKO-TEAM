<?php
/**
 * core/nenadezhnyi.php — СЕРАЯ ГАЛОЧКА: ЧЕЛОВЕК НЕ ЗАБРАЛ ОТПРАВЛЕННУЮ ПОСЫЛКУ.
 *
 * Правка владельца 15.10.2026: часть участников, заказавших оригиналы, не
 * забирает посылку с почты. В разделе «Заказы оригиналов», в подразделе
 * «Отправлено», оператор отмечает это руками двумя кнопками — «ЗАБРАЛ» и
 * «НЕ ЗАБРАЛ», — и после «НЕ ЗАБРАЛ» рядом с ником этого участника во ВСЕХ его
 * заявках (на участие, на изготовление и дальше по разделам) стоит серая
 * галочка: он ненадёжный.
 *
 * ПОЧЕМУ ГАЛОЧКА НЕ ХРАНИТСЯ ОТДЕЛЬНЫМ ПРИЗНАКОМ, А СЧИТАЕТСЯ ОТ ЗАКАЗА.
 * Признак «ненадёжный» в таблице `users` был бы ВТОРОЙ записью одного и того же
 * факта: первая — отметка на самом заказе. Две записи расходятся молча, и это
 * в проекте оплачено уже четыре раза (правила 33, 35, 45, 47: пункты положения,
 * ссылки, заслон на дополнительный диплом, срок на плашке). Поэтому факт живёт
 * в ОДНОМ месте — в колонке `awards_orders.pickup`, — а галочка каждый раз
 * считается от него. Нажали «ЗАБРАЛ» — галочка исчезает везде сама, и чистить
 * вторую запись не нужно: её нет. Ровно это и значит «для ручного управления».
 *
 * ПОЧЕМУ ЧЕЛОВЕК УЗНАЁТСЯ ТРЕМЯ КЛЮЧАМИ, А НЕ ОДНИМ `user_id`.
 * У заказа плательщик бывает не записан вовсе (оформлен без входа), а в очереди
 * отправок у строки заказа колонки `user_id` нет по построению (правило 47).
 * Поэтому ненадёжность узнаётся по номеру пользователя, по почте и по номеру
 * заявки, из которой уехала посылка. Почта сверяется в нижнем регистре: в
 * заявке и в кабинете один адрес написан по-разному у каждого третьего.
 * Номер заявки нужен отдельно: заказ на ученика оформляет руководитель, и его
 * почта может не совпадать с почтой заявки — но посылка уехала именно по ЭТОЙ
 * заявке, и в ней галочка обязана стоять.
 *
 * ПУСТАЯ ГАЛОЧКА НЕ ЧИТАЕТСЯ НИКОГДА (урок правила 45 про удержание посылки):
 * в подсказке к значку названы номера заказов и дата отметки, а не просто
 * «ненадёжный». Через неделю оператор не помнит, за что она стоит.
 */
declare(strict_types=1);

/** Состояния колонки `awards_orders.pickup`. Пусто — ещё не известно. */
const PICKUP_ZABRAL     = 'taken';
const PICKUP_NE_ZABRAL  = 'missed';

/**
 * Цвет серой галочки. Назван владельцем словом «серая», поэтому берём
 * нейтральный серый, а не синий из палитры клуба (#2C7BE5) и не золотой
 * оргкомитета (#C79322): три галочки рядом обязаны различаться с одного взгляда.
 */
const NENADEZHNYI_CVET = '#8C8C94';

/** Почта для сверки: регистр и пробелы в адресах участников пляшут. */
function nenadezhnyi_pochta(string $email): string {
    return mb_strtolower(trim($email));
}

/**
 * ВСЕ НЕЗАБРАННЫЕ ПОСЫЛКИ — ОДНИМ ЗАПРОСОМ НА ВЕСЬ ЗАПРОС СТРАНИЦЫ.
 *
 * Список заявок рисует до восьмисот строк, и спрашивать базу на каждую строку
 * нельзя. Незабранных посылок единицы, поэтому весь список держим в памяти.
 *
 * @param bool $zanovo перечитать (после записи в том же запросе)
 * @return array{uid:array<int,array>, email:array<string,array>, app:array<int,array>}
 */
function nenadezhnye(bool $zanovo = false): array {
    static $память = null;
    if ($zanovo) $память = null;
    if ($память !== null) return $память;

    $пусто = ['uid' => [], 'email' => [], 'app' => []];
    try {
        $строки = all("SELECT id, COALESCE(user_id,0) uid, COALESCE(email,'') em,
                              COALESCE(application_id,0) app, COALESCE(pickup_at,'') kogda
                         FROM awards_orders WHERE pickup = ?", [PICKUP_NE_ZABRAL]);
    } catch (\Throwable $e) {
        // Колонки ещё нет (миграция не прошла) — галочек просто нет.
        return $память = $пусто;
    }

    $к = $пусто;
    foreach ($строки as $o) {
        $случай = [
            'заказ'  => (int) $o['id'],
            'когда'  => (string) $o['kogda'],
            'заявка' => (int) $o['app'],
        ];
        if ((int) $o['uid'] > 0) $к['uid'][(int) $o['uid']][] = $случай;
        $em = nenadezhnyi_pochta((string) $o['em']);
        if ($em !== '')          $к['email'][$em][] = $случай;
        if ((int) $o['app'] > 0) $к['app'][(int) $o['app']][] = $случай;
    }
    return $память = $к;
}

/**
 * НЕЗАБРАННЫЕ ПОСЫЛКИ ЭТОГО ЧЕЛОВЕКА.
 *
 * @param int    $uid   номер пользователя (0 — нет)
 * @param string $email почта из строки списка
 * @param int    $appId номер ЗАЯВКИ, если строка про заявку или про её бланк
 * @return array<int,array{заказ:int,когда:string,заявка:int}>
 */
function nenadezhnyi_sluchai(int $uid, string $email = '', int $appId = 0): array {
    $все = nenadezhnye();
    if (!$все['uid'] && !$все['email'] && !$все['app']) return [];

    $найдено = [];
    if ($uid > 0 && isset($все['uid'][$uid])) {
        foreach ($все['uid'][$uid] as $с) $найдено[$с['заказ']] = $с;
    }
    $em = nenadezhnyi_pochta($email);
    if ($em !== '' && isset($все['email'][$em])) {
        foreach ($все['email'][$em] as $с) $найдено[$с['заказ']] = $с;
    }
    if ($appId > 0 && isset($все['app'][$appId])) {
        foreach ($все['app'][$appId] as $с) $найдено[$с['заказ']] = $с;
    }
    ksort($найдено);
    return array_values($найдено);
}

/** Коротко: ненадёжный ли. */
function nenadezhnyi_est(int $uid, string $email = '', int $appId = 0): bool {
    return nenadezhnyi_sluchai($uid, $email, $appId) !== [];
}

/** Дата отметки человеку: «15.10.2026». Непонятную строку отдаём как есть. */
function nenadezhnyi_data(string $когда): string {
    $t = strtotime(trim($когда));
    return $t ? date('d.m.Y', $t) : trim($когда);
}

/**
 * ГОТОВАЯ СЕРАЯ ГАЛОЧКА ДЛЯ АДМИНКИ — или пустая строка.
 * Ставится РЯДОМ С ИМЕНЕМ, там же, где синяя галочка клуба (`vip_mark`).
 */
function nenadezhnyi_metka(int $uid, string $email = '', int $appId = 0): string {
    $случаи = nenadezhnyi_sluchai($uid, $email, $appId);
    if (!$случаи) return '';

    $н = [];
    foreach ($случаи as $с) {
        $д = trim((string) $с['когда']);
        $н[] = '№' . (int) $с['заказ'] . ($д !== '' ? ' от ' . nenadezhnyi_data($д) : '');
    }
    $подсказка = 'Ненадёжный участник: не забрал отправленную посылку с почты. '
        . (count($н) > 1 ? 'Заказы: ' : 'Заказ ') . implode(', ', $н) . '. '
        . 'Отметка снимается кнопкой «ЗАБРАЛ» в разделе «Заказы оригиналов».';

    return '<span title="' . h($подсказка) . '" style="display:inline-flex;vertical-align:-3px;margin-left:4px">'
        . '<svg width="16" height="16" viewBox="0 0 24 24" fill="' . NENADEZHNYI_CVET . '" aria-hidden="true">'
        . '<circle cx="12" cy="12" r="10"/>'
        . '<path d="M7.6 12.3l3 3 5.8-6.2" stroke="#fff" stroke-width="2.1" fill="none"'
        . ' stroke-linecap="round" stroke-linejoin="round"/>'
        . '</svg></span>';
}

/** Та же правда словами — для журналов, отчётов владельцу и аудита. */
function nenadezhnyi_slovami(int $uid, string $email = '', int $appId = 0): string {
    $случаи = nenadezhnyi_sluchai($uid, $email, $appId);
    if (!$случаи) return 'посылки забирает';
    $н = [];
    foreach ($случаи as $с) $н[] = '№' . (int) $с['заказ'];
    return 'не забрал посылку, ' . (count($н) > 1 ? 'заказы ' : 'заказ ') . implode(', ', $н);
}

/**
 * СОСТОЯНИЕ ПОСЫЛКИ (группы заказов одного получателя).
 *
 * Посылка едет одной коробкой, и забирают её целиком: у группы состояние одно.
 * Хоть один «не забрал» — значит не забрали; все «забрал» — забрали; иначе
 * ещё неизвестно.
 *
 * @param array $orders строки `awards_orders` одной посылки
 */
function nenadezhnyi_sostoyanie_posylki(array $orders): string {
    $забрал = 0; $всего = 0;
    foreach ($orders as $o) {
        $всего++;
        $с = (string) ($o['pickup'] ?? '');
        if ($с === PICKUP_NE_ZABRAL) return PICKUP_NE_ZABRAL;
        if ($с === PICKUP_ZABRAL) $забрал++;
    }
    return ($всего > 0 && $забрал === $всего) ? PICKUP_ZABRAL : '';
}

/** Когда отметили — по той же группе. */
function nenadezhnyi_kogda_posylki(array $orders): string {
    foreach ($orders as $o) {
        $д = trim((string) ($o['pickup_at'] ?? ''));
        if ($д !== '') return $д;
    }
    return '';
}
