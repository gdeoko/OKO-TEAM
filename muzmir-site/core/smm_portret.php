/**
 * ПОРТРЕТ ДЕЯТЕЛЯ — НАСТОЯЩИЙ, А НЕ ПРИДУМАННЫЙ МОДЕЛЬЮ.
 *
 * Правка владельца 13.10.2026: «использовать по необходимости портреты тех
 * людей, о которых создан пост». Нарисованный моделью «Чайковский» похож на
 * Чайковского ровно настолько, насколько ей повезло: лицо выходит чужим, и на
 * поздравительной афише ко дню рождения это читается как подделка. Поэтому
 * портрет берётся НАСТОЯЩИЙ - из Викисклада, и только тот, что в общественном
 * достоянии, - и уходит в генерацию ВТОРЫМ референсом рядом с нашим знаком.
 *
 * ЛИЦЕНЗИЯ ПРОВЕРЯЕТСЯ, А НЕ ПРЕДПОЛАГАЕТСЯ. У деятелей XIX и начала XX века
 * портреты давно в общественном достоянии, а вот фотография Плисецкой или
 * Шостаковича вполне может быть под охраной: такой файл НЕ берём и кадр
 * собираем без лица. Признак свободы у самой Википедии - `page_image_free`,
 * а точную лицензию отдаёт Викисклад в `extmetadata`.
 *
 * Кэш в настройках: один и тот же человек спрашивается у Викисклада один раз в
 * месяц, а не на каждый пост.
 */

/**
 * Лицензии, при которых портрет можно ставить в кадр.
 *
 * ТОЛЬКО ОБЩЕСТВЕННОЕ ДОСТОЯНИЕ И CC0, И ЭТО НАРОЧНО УЖЕ. CC BY тоже свободна,
 * но требует указать автора, а кадр уходит в ленту без подписей под картинкой:
 * выполнить условие лицензии негде. У деятелей XIX и начала XX века портреты в
 * общественном достоянии есть почти всегда, у современников портрета просто не
 * будет - и кадр соберётся без лица, что честнее нарушенной лицензии.
 */
const SMM_PORTRET_СВОБОДНЫЕ = ['public domain', 'pd-', 'cc0'];

/** Запрос к API Викимедиа. Пусто - значит не ответили. */
function smm_wiki_api(string $host, array $args): array {
    $url = 'https://' . $host . '/w/api.php?' . http_build_query($args + ['format' => 'json']);
    $ch = curl_init($url);
    curl_setopt_array($ch, [
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_TIMEOUT => 25,
        CURLOPT_FOLLOWLOCATION => true,
        /* Викимедиа требует внятного User-Agent и без него отдаёт 403. */
        CURLOPT_USERAGENT => 'MuzmirCultureBot/1.0 (https://музыкальный-мир.рф; kc@музыкальный-мир.рф)',
    ]);
    $res = curl_exec($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);
    if ($code !== 200 || !is_string($res)) return [];
    $j = json_decode($res, true);
    return is_array($j) ? $j : [];
}

/**
 * Портрет человека: адрес картинки, подпись лицензии и автор.
 *
 * Возвращает ['url' => …, 'лицензия' => …, 'автор' => …, 'файл' => …] либо
 * ['нет' => 'почему']. Второе - обычное дело, а не сбой: у современников
 * свободного портрета часто нет вовсе.
 */
function smm_portret(string $имя, int $ширина = 1200): array {
    $имя = trim($имя);
    if ($имя === '') return ['нет' => 'имя не названо'];

    $ключ = 'smm_portret_' . md5(mb_strtolower($имя));
    $кэш = json_decode((string) setting($ключ, ''), true);
    if (is_array($кэш) && (int) ($кэш['когда'] ?? 0) > time() - 30 * 86400) {
        unset($кэш['когда']);
        return $кэш;
    }
    $запомнить = static function (array $о) use ($ключ): array {
        set_setting($ключ, (string) json_encode($о + ['когда' => time()], JSON_UNESCAPED_UNICODE));
        return $о;
    };

    /* Шаг 1. Статья в русской Википедии и её СВОБОДНОЕ изображение. */
    $j = smm_wiki_api('ru.wikipedia.org', [
        'action' => 'query', 'prop' => 'pageprops', 'redirects' => 1, 'titles' => $имя,
    ]);
    $страницы = (array) ($j['query']['pages'] ?? []);
    $файл = '';
    foreach ($страницы as $с) {
        $файл = (string) ($с['pageprops']['page_image_free'] ?? '');
        if ($файл !== '') break;
    }
    if ($файл === '') {
        /* ЗАПАСНОЙ ПУТЬ: у части статей карточка без свободного файла, хотя на
           Викискладе портрет есть (так у Рахманинова). Спрашиваем поиском по
           файлам - один лишний вызов и только когда первый путь пуст. */
        $файл = smm_portret_поиском($имя);
    }
    if ($файл === '') return $запомнить(['нет' => 'свободного портрета не нашлось']);

    /* Шаг 2. Лицензия и адрес уменьшенной копии - у Викисклада. */
    $j2 = smm_wiki_api('commons.wikimedia.org', [
        'action' => 'query', 'prop' => 'imageinfo',
        'iiprop' => 'extmetadata|url', 'iiurlwidth' => $ширина,
        'titles' => 'File:' . $файл,
    ]);
    $стр = (array) ($j2['query']['pages'] ?? []);
    $ii = [];
    foreach ($стр as $с) { $ii = (array) (($с['imageinfo'] ?? [[]])[0] ?? []); break; }
    $мета = (array) ($ii['extmetadata'] ?? []);
    $лиц = trim((string) ($мета['LicenseShortName']['value'] ?? ''));
    $url = (string) ($ii['thumburl'] ?? $ii['url'] ?? '');
    if ($url === '') return $запомнить(['нет' => 'Викисклад не отдал адрес файла']);

    $низ = mb_strtolower($лиц);
    $свободна = false;
    foreach (SMM_PORTRET_СВОБОДНЫЕ as $с) {
        if ($с !== '' && mb_strpos($низ, $с) !== false) { $свободна = true; break; }
    }
    if (!$свободна) {
        return $запомнить(['нет' => 'лицензия не свободная: ' . ($лиц !== '' ? $лиц : 'не названа')]);
    }

    $автор = trim(strip_tags((string) ($мета['Artist']['value'] ?? '')));
    return $запомнить([
        'url'       => $url,
        'лицензия'  => $лиц,
        'автор'     => mb_substr($автор, 0, 120),
        'файл'      => $файл,
    ]);
}

/**
 * Поиск файла-портрета прямо по Викискладу. Берём первый файл, в названии
 * которого есть фамилия: поиск по пространству файлов и так сортирует по
 * совпадению, а проверку лицензии всё равно делает вызывающий.
 */
function smm_portret_поиском(string $имя): string {
    $фамилия = trim((string) (preg_split('~[,\s]+~u', $имя)[0] ?? ''));
    if ($фамилия === '') return '';
    $j = smm_wiki_api('commons.wikimedia.org', [
        'action' => 'query', 'list' => 'search', 'srnamespace' => 6,
        'srlimit' => 8, 'srsearch' => $фамилия . ' portrait',
    ]);
    foreach ((array) ($j['query']['search'] ?? []) as $н) {
        $т = (string) ($н['title'] ?? '');
        if ($т === '') continue;
        $т = preg_replace('~^File:~u', '', $т) ?? $т;
        if (!preg_match('~\.(jpe?g|png)$~ui', $т)) continue;
        if (mb_stripos($т, $фамилия) === false) continue;
        return $т;
    }
    return '';
}
