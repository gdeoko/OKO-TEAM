/**
 * Паспорт направления для задания модели.
 * Пустая строка означает, что направление не указано или незнакомо: тогда работает
 * общая рубрика номинации, и выдумывать специфику нельзя.
 */
function gk_direction_prompt(string $subgroup): string {
    $sub = trim($subgroup);
    if ($sub === '') return '';
    $all = gk_directions();
    $d = $all[$sub] ?? null;
    if (!$d) {
        // Иногда направление приходит с уточнением в скобках или иным регистром.
        foreach ($all as $name => $row) {
            if (mb_stripos($sub, $name) === 0 || mb_stripos($name, $sub) === 0) { $d = $row; break; }
        }
    }
    if (!$d) return '';

    return implode("\n", [
        'ПАСПОРТ НАПРАВЛЕНИЯ «' . $sub . '» — читай перед тем, как ставить баллы:',
        '  НА ЧТО СМОТРИТ ЭКСПЕРТ: ' . $d['look'],
        '  ПРОФЕССИОНАЛЬНЫЕ ТЕРМИНЫ (употребляй точно и поясняй простыми словами, комментарий читает и педагог, и родитель): ' . $d['terms'],
        '  ТИПИЧНЫЕ ОШИБКИ: ' . $d['errors'],
        '  НЕ СЧИТАЕТСЯ ДОСТОИНСТВОМ: ' . $d['not_merit'],
        '  ВОЗРАСТ: ' . $d['age'],
    ]);
}
