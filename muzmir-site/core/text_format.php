if (!function_exists('tf_extract_country')) {
    /**
     * Вырезать название страны ИЗ ЛЮБОГО МЕСТА строки.
     *
     * Страну ищут по краям, а пишут где придётся: в базе лежит
     * «Россия, г. Россия Г. Мосальск» — форма подставила страну, человек
     * дописал свою, и вышло «город Россия». Проверка краёв такое не ловит,
     * потому что посередине стоит приставка. Здесь строка разбирается по
     * словам, и каждое сочетание из одного-трёх слов сверяется со справочником
     * стран: что совпало — вырезается, что осталось — и есть населённый пункт.
     *
     * @param string $found сюда попадёт каноническое имя найденной страны
     */
    function tf_extract_country(string $s, string &$found): string {
        $words = preg_split('~\s+~u', trim($s)) ?: [];
        $n = count($words);
        $keep = [];
        for ($i = 0; $i < $n; ) {
            $matched = 0;
            for ($len = min(3, $n - $i); $len >= 1; $len--) {
                $chunk = implode(' ', array_slice($words, $i, $len));
                $c = tf_country_canon($chunk);
                if ($c !== '') {
                    if ($found === '') $found = $c;
                    $matched = $len;
                    break;
                }
            }
            if ($matched > 0) { $i += $matched; continue; }
            $keep[] = $words[$i];
            $i++;
        }
        return trim(implode(' ', $keep));
    }
}

if (!function_exists('city_resolve')) {
    /**
     * Разбирает произвольный ввод города («Москва», «г. минск», «Россия, г. Москва»,
     * «село Ивановка») в структуру:
     *   ['ok'=>bool, 'country'=>, 'prefix'=>'г.', 'display'=>'Москва', 'stem'=>'москов',
     *    'canonical'=>'Россия, г. Москва']
     * ok=false — пустой ввод.
     */
    function city_resolve(string $s): array {
        $out = ['ok'=>false,'country'=>'Россия','prefix'=>'г.','display'=>'','stem'=>'','canonical'=>''];
        $s = trim(preg_replace('~\s+~u',' ', $s) ?? '');
        if ($s === '') return $out;
        // Если ввод уже «Страна, г. Город» — последний сегмент это населённый пункт,
        // а всё, что перед ним, может быть страной. Страну запоминаем: справочник
        // знает не каждый город мира, и без этого «Республика Беларусь, г. Столбцы»
        // превращалось в российские Столбцы.
        $saidCountry = '';
        if (mb_strpos($s, ',') !== false) {
            $parts = array_map('trim', explode(',', $s));
            // Страна может стоять и перед городом, и после него: «ОАЭ, Дубай» и
            // «Дубай, ОАЭ» пишут одинаково часто. Забираем из строки все куски,
            // которые являются страной, а городом считаем то, что осталось.
            $rest = [];
            foreach ($parts as $p) {
                $c = tf_country_canon($p);
                if ($c !== '' && $saidCountry === '') { $saidCountry = $c; continue; }
                if ($c !== '') continue;
                if ($p !== '') $rest[] = $p;
            }
            $s = $rest ? (string) array_pop($rest) : '';
            if ($s === '' && $saidCountry !== '') {
                // Назвали только страну, города нет. Выдумывать город нельзя.
                $out['country'] = $saidCountry;
                return $out;
            }
        }
        // Название страны или региона, написанное без запятой, — не часть имени
        // города. Без этого «украина донецк» превращалось в населённый пункт
        // «Украина Донецк», и справочник его, разумеется, не находил.
        if (preg_match('~^\s*([\p{L}\s]+?)\s+(?=(город|гор\.|г\.|пгт|посёлок|поселок|п\.|село|с\.|деревня|д\.|станица|ст\.|хутор|х\.|аул)\s|\p{Lu})~u', $s, $mc)) {
            $c = tf_country_canon($mc[1]);
            if ($c !== '') { if ($saidCountry === '') $saidCountry = $c; $s = trim(mb_substr($s, mb_strlen($mc[0]))); }
        }
        // Страна, приписанная в конце без запятой: «Дубай ОАЭ», «Минск Беларусь».
        if (preg_match('~^(.+?)\s+([\p{L}\s\-]{2,40})$~u', $s, $mt)) {
            $c = tf_country_canon($mt[2]);
            if ($c !== '' && trim($mt[1]) !== '') {
                if ($saidCountry === '') $saidCountry = $c;
                $s = trim($mt[1]);
            }
        }
        // Названия непризнанных образований и областей, написанные перед городом,
        // частью имени города не являются: «украина донецк» давало населённый пункт
        // «Украина Донецк», которого справочник, разумеется, не находил.
        $s = (string) preg_replace(
            '~^\s*(украина|ukraine|россия|российская федерация|рф|russia|беларусь|республика беларусь|'
          . 'казахстан|республика казахстан|днр|лнр|донецкая народная республика|луганская народная республика|'
          . 'запорожская область|херсонская область)\s+~ui', '', $s);
        // Снимаем тип-приставку населённого пункта, запоминаем её.
        $prefix = 'г.';
        /* Приставок бывает две подряд: «г. Р.п. Нахабино» — так получается, когда
         * форма подставила «г.», а человек написал свой тип посёлка. Снимаем обе,
         * оставляя ту, что ближе к названию: она и есть настоящая. */
        for ($pass = 0; $pass < 2; $pass++) {
            // «р.п.» (рабочий посёлок) пишут и через точки, и слитно.
            // Пробела после «р.п.» может не быть вовсе: в базе лежит «Р.п.ордынское».
            $s = (string) preg_replace('~^\s*р\s*\.\s*п\s*\.?\s*(?=\p{L})~ui', 'рп ', $s);
            $s = (string) preg_replace('~^\s*рп\.?\s*(?=\p{L})~ui', 'рп ', $s);
            if (!preg_match('~^(город|гор\.?|г\.?|пгт\.?|посёлок городского типа|посёлок|поселок|п\.?|село|с\.?|деревня|дер\.?|д\.?|станица|ст-ца|ст\.?|хутор|х\.?|аул|рп\.?)\s+~ui', $s, $m)) break;
            $raw = mb_strtolower($m[1], 'UTF-8');
            $s = trim(mb_substr($s, mb_strlen($m[0])));
            if (preg_match('~^(село|с)~u',$raw)) $prefix='с.';
            elseif (preg_match('~^(деревня|дер|д)~u',$raw)) $prefix='д.';
            elseif (preg_match('~^(посёлок|поселок|пгт|рп|п)~u',$raw)) $prefix='пгт';
            elseif (preg_match('~^(станица|ст)~u',$raw)) $prefix='ст.';
            elseif (preg_match('~^(хутор|х)~u',$raw)) $prefix='х.';
            elseif (preg_match('~^аул~u',$raw)) $prefix='аул';
            else $prefix='г.';
        }
        $s = tf_strip_quotes($s);
        if ($s === '') return $out;

        /* Страна могла остаться внутри строки: «Россия Г. Мосальск». Вырезаем её
         * отовсюду, где бы она ни стояла, и при необходимости снимаем приставку
         * ещё раз — она могла прятаться за вырезанным словом. */
        $inner = '';
        $cut = tf_extract_country($s, $inner);
        if ($cut !== '' && $cut !== $s) {
            $s = $cut;
            if ($saidCountry === '' && $inner !== '') $saidCountry = $inner;
            if (preg_match('~^(город|гор\.?|г\.?|пгт\.?|посёлок|поселок|п\.?|село|с\.?|деревня|дер\.?|д\.?|станица|ст\.?|хутор|х\.?|аул|рп\.?)\s+~ui', $s, $m3)) {
                $raw = mb_strtolower($m3[1], 'UTF-8');
                $s = trim(mb_substr($s, mb_strlen($m3[0])));
                if (preg_match('~^(село|с)~u',$raw)) $prefix='с.';
                elseif (preg_match('~^(деревня|дер|д)~u',$raw)) $prefix='д.';
                elseif (preg_match('~^(посёлок|поселок|пгт|рп|п)~u',$raw)) $prefix='пгт';
                elseif (preg_match('~^(станица|ст)~u',$raw)) $prefix='ст.';
                elseif (preg_match('~^(хутор|х)~u',$raw)) $prefix='х.';
                elseif (preg_match('~^аул~u',$raw)) $prefix='аул';
                else $prefix='г.';
            }
        }
        // Ввели только страну, города нет: города не выдумываем.
        if ($s === '') { $out['country'] = $saidCountry !== '' ? $saidCountry : 'Россия'; return $out; }
        // Строка целиком оказалась страной («Россия») — тот же случай.
        if ($saidCountry === '' && tf_country_canon($s) !== '') {
            $out['country'] = tf_country_canon($s);
            return $out;
        }

        /* Страна могла прятаться ЗА приставкой: «Россия, г. Беларусь Гомель» —
         * так пишут, когда страну подставила форма, а человек дописал свою.
         * Приставку мы уже сняли, поэтому проверяем ещё раз: город важнее того,
         * что стояло в начале строки. */
        if (preg_match('~^\s*([\p{L}\s\-]{2,40}?)\s+(\p{L}[\p{L}\-]+)\s*$~u', $s, $m2)) {
            $c2 = tf_country_canon($m2[1]);
            if ($c2 !== '') { $saidCountry = $c2; $s = trim($m2[2]); }
        }

        /* РЕГИОН — НЕ ГОРОД.
         * «Краснодарский край» превращался в «г. Краснодарский Край»: приставка
         * ставилась всему, что вообще было введено. Регион оставляем регионом,
         * без «г.» — это честнее, чем выдуманный населённый пункт. */
        if (preg_match('~(край|область|обл\.|республика|округ|автономный округ|район)\s*$~ui', $s)
            && !preg_match('~^(город|г\.)~ui', $s)) {
            $out['ok'] = true;
            $out['country'] = $saidCountry !== '' ? $saidCountry : 'Россия';
            $out['prefix'] = '';
            $out['display'] = tf_smart_title($s);
            $out['stem'] = str_replace('ё','е', mb_strtolower($s, 'UTF-8'));
            $out['canonical'] = $out['country'] . ', ' . $out['display'];
            return $out;
        }

        $key = str_replace('ё','е', mb_strtolower($s, 'UTF-8'));
        $geo = city_geo();
        if (isset($geo[$key])) {
            [$country,$stem,$display] = $geo[$key];
            $out['ok']=true; $out['country']=$country; $out['prefix']=$prefix;
            $out['display']=$display; $out['stem']=str_replace('ё','е',$stem);
        } else {
            // Неизвестный город — Россия по умолчанию, аккуратный регистр, основа из корня.
            $display = tf_smart_title($s);
            // Многословные/дефисные — каждое значимое слово с заглавной.
            $display = (string) preg_replace_callback('~(^|[\s\-])(\p{L})~u',
                static fn(array $mm): string => $mm[1] . mb_strtoupper($mm[2],'UTF-8'), mb_strtolower($s,'UTF-8'));
            $stem = str_replace('ё','е', mb_strtolower($s,'UTF-8'));
            $stem = (string) preg_replace('~[аяьыиоеу]$~u','',$stem); // грубая основа
            // Справочник города не знает. Если человек назвал страну — верим ему;
            // если не назвал — Россия, потому что девяносто девять участников из ста
            // из России. Раньше страну не спрашивали вовсе, и белорусский городок
            // становился российским молча.
            $out['ok']=true; $out['country']= $saidCountry !== '' ? $saidCountry : 'Россия';
            $out['prefix']=$prefix;
            $out['display']=$display; $out['stem']=$stem;
        }
        $out['canonical'] = $out['country'] . ', ' . $out['prefix'] . ' ' . $out['display'];
        return $out;
    }
}

