if (!function_exists('city_resolve')) {
    /**
     * Разбирает произвольный ввод города («Москва», «г. минск», «Россия, г. Москва»,
     * «село Ивановка») в структуру:
     *   ['ok'=>bool, 'country'=>, 'prefix'=>'г.', 'display'=>'Москва', 'stem'=>'москов',
     *    'canonical'=>'Россия, г. Москва']
     * ok=false — пустой ввод.
     */
    function city_resolve(string $s): array {
        $out = ['ok'=>false,'country'=>'Россия','prefix'=>'г.','display'=>'','stem'=>'','canonical'=>''];
        $s = trim(preg_replace('~\s+~u',' ', $s) ?? '');
        if ($s === '') return $out;
        // Если ввод уже «Страна, г. Город» — берём последний сегмент как населённый пункт.
        if (mb_strpos($s, ',') !== false) {
            $parts = array_map('trim', explode(',', $s));
            $s = (string) end($parts);
        }
        // Снимаем тип-приставку населённого пункта, запоминаем её.
        $prefix = 'г.';
        if (preg_match('~^(город|гор\.?|г\.?|пгт\.?|посёлок городского типа|посёлок|поселок|п\.?|село|с\.?|деревня|дер\.?|д\.?|станица|ст-ца|ст\.?|хутор|х\.?|аул|рп\.?)\s+~ui', $s, $m)) {
            $raw = mb_strtolower($m[1], 'UTF-8');
            $s = trim(mb_substr($s, mb_strlen($m[0])));
            if (preg_match('~^(село|с)~u',$raw)) $prefix='с.';
            elseif (preg_match('~^(деревня|дер|д)~u',$raw)) $prefix='д.';
            elseif (preg_match('~^(посёлок|поселок|пгт|рп|п)~u',$raw)) $prefix='пгт';
            elseif (preg_match('~^(станица|ст)~u',$raw)) $prefix='ст.';
            elseif (preg_match('~^(хутор|х)~u',$raw)) $prefix='х.';
            elseif (preg_match('~^аул~u',$raw)) $prefix='аул';
            else $prefix='г.';
        }
        $s = tf_strip_quotes($s);
        if ($s === '') return $out;
        $key = str_replace('ё','е', mb_strtolower($s, 'UTF-8'));
        $geo = city_geo();
        if (isset($geo[$key])) {
            [$country,$stem,$display] = $geo[$key];
            $out['ok']=true; $out['country']=$country; $out['prefix']=$prefix;
            $out['display']=$display; $out['stem']=str_replace('ё','е',$stem);
        } else {
            // Неизвестный город — Россия по умолчанию, аккуратный регистр, основа из корня.
            $display = tf_smart_title($s);
            // Многословные/дефисные — каждое значимое слово с заглавной.
            $display = (string) preg_replace_callback('~(^|[\s\-])(\p{L})~u',
                static fn(array $mm): string => $mm[1] . mb_strtoupper($mm[2],'UTF-8'), mb_strtolower($s,'UTF-8'));
            $stem = str_replace('ё','е', mb_strtolower($s,'UTF-8'));
            $stem = (string) preg_replace('~[аяьыиоеу]$~u','',$stem); // грубая основа
            $out['ok']=true; $out['country']='Россия'; $out['prefix']=$prefix;
            $out['display']=$display; $out['stem']=$stem;
        }
        $out['canonical'] = $out['country'] . ', ' . $out['prefix'] . ' ' . $out['display'];
        return $out;
    }
}

if (!function_exists('city_normalize')) {
    /** Канонический «Страна, г. Город» из любого ввода. Пусто → ''. */
    function city_normalize(string $s): string {
        $r = city_resolve($s);
        return $r['ok'] ? $r['canonical'] : '';
    }
}

if (!function_exists('institution_with_city')) {
    /**
     * Учреждение + город, но БЕЗ дублирования: если название учреждения уже содержит
     * город (буквально «Москва» или прилагательное «Московский» — по основе), город не
     * добавляется. Иначе → «Учреждение, г. Город» (без страны). Пустое учреждение → ''.
     */
    function institution_with_city(string $inst, string $city): string {
        $inst = trim($inst);
        if ($inst === '') return '';
        $r = city_resolve($city);
        if (!$r['ok']) return $inst;
        $instLow = str_replace('ё','е', mb_strtolower($inst,'UTF-8'));
        $disLow  = str_replace('ё','е', mb_strtolower($r['display'],'UTF-8'));
        $stem    = $r['stem'];
        $hasCity = ($disLow !== '' && mb_strpos($instLow,$disLow) !== false)
                || ($stem !== '' && mb_strlen($stem) >= 4 && mb_strpos($instLow,$stem) !== false);
        if ($hasCity) return $inst;
        return $inst . ', ' . $r['prefix'] . ' ' . $r['display'];
    }
}

if (!function_exists('work_title_for_list')) {
    /**
     * Для списка длинного конкурса — только «Название».
     * Из «песня «Жаворонок» М.И.Глинка» → «Жаворонок». Если «…» нет — срезаем жанровые
     * слова в начале (песня/танец/стих…) и оборачиваем.
     */
    function work_title_for_list(string $s): string {
        $s = trim($s);
        if ($s === '') return '';
        if (preg_match('~[«"“](.+?)[»"”]~u', $s, $m)) {   // берём первый кавычечный сегмент
            return '«' . tf_smart_title(trim($m[1])) . '»';
        }
        $genre = '~^\s*(песня|песни|танец|танца|стих(отворение)?|стиха|романс|произведение|номер|композиция|вокал|хореография|инструментал\w*)\s+~ui';
        $s = preg_replace($genre, '', $s) ?? $s;
        return '«' . tf_smart_title(tf_strip_quotes($s)) . '»';
    }
}
