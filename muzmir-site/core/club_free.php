/**
 * core/club_free.php — БЕСПЛАТНЫЕ ЗАЯВКИ ЭЛИТНОГО КЛУБА В ПЛАТНЫХ КОНКУРСАХ.
 *
 * Правило владельца 15.10.2026, постоянное: «принимать без оплаты оргвзноса
 * (бесплатно), до 3 штук заявок от одного и того же участника вип клуба в
 * платных конкурсах». Остальные скидки и привилегии Клуба сохраняются.
 *
 * ЛЬГОТА БЫЛА ТОЛЬКО СЛОВАМИ, А В КОДЕ ЕЁ НЕ БЫЛО ВОВСЕ. На странице Клуба и в
 * карточке каждого письма стоял пункт «Бесплатный конкурс каждый месяц: 1 заявка
 * с 1 номером в месяц — бесплатно», но дверь подачи (`api/v1/apply.php`) про него
 * не знала: платная заявка участника Клуба ждала оплаты, как у всех, и человек
 * платил полную цену со скидкой 20%. Центр обещал то, чего не исполнял.
 *
 * СЧЁТ ИДЁТ ПО КАЛЕНДАРНОМУ МЕСЯЦУ, И ЭТО СЛОВО ВЛАДЕЛЬЦА 15.10.2026:
 * «Только один платный конкурс с оргвзносом проводится один раз в месяц, каждый
 * месяц. В платный конкурс с оргвзносом допускается участие без оргвзноса не
 * более 3 заявок на участие, только от членов элитного вип клуба... ЗА МЕСЯЦ».
 * Сегодня платный конкурс в месяце один, и «три за месяц» равно «три в этом
 * конкурсе» - но считать надо ПО МЕСЯЦУ: заведи владелец два платных конкурса
 * в одном месяце, счёт по конкурсу молча выдал бы шесть бесплатных заявок
 * вместо трёх.
 * Месяц берётся по МЕСТНОМУ календарю (`date('Y-m')`), как и сутки у имени
 * оператора (правило 34): иначе льгота обновлялась бы посреди ночи и посреди
 * месяца. Первое число - новый счёт, и это совпадает с приёмом заявок 01-25.
 *
 * ОТКЛОНЁННАЯ ЗАЯВКА СЛОТ ВОЗВРАЩАЕТ. Отклонение по п. 4.1/4.2 означает, что
 * участия не было вовсе, и держать за него израсходованную льготу нечестно.
 * Автоматических отклонений в центре нет (правило 14), решает человек, поэтому
 * злоупотребить этим нельзя.
 *
 * ЛЬГОТА СЧИТАЕТСЯ ТОЛЬКО ВОШЕДШЕМУ. Членство живёт у номера пользователя, и без
 * входа в кабинет узнать его нельзя - ровно как со скидкой 20%, которая тоже
 * требует входа. Поэтому витрина говорит об этом словами, а не молчит.
 */
declare(strict_types=1);

/**
 * Сколько заявок участник Клуба подаёт БЕЗ ОРГВЗНОСА в одном платном конкурсе.
 * Число владельца (15.10.2026). Живёт в коде, как и клубный срок 3 рабочих дня
 * (правило 37): настройки у него нет намеренно - это обещание, а не параметр.
 */
const CLUB_FREE_APPS = 3;

/** Колонка-отметка на заявке. Ставится ОДИН раз, в двери подачи. */
function club_free_migrate(): void {
    static $было = false;
    if ($было) return;
    $было = true;
    try { db()->exec("ALTER TABLE applications ADD COLUMN club_free INTEGER DEFAULT 0"); }
    catch (\Throwable $e) {}
}

/** Предел словами и числом - один источник на витрину, письма, бота и аудит. */
function club_free_limit(): int { return CLUB_FREE_APPS; }

/** Месяц счёта: «2026-10». По местному календарю, а не по UTC. */
function club_free_month(string $когда = ''): string {
    $t = $когда !== '' ? strtotime($когда) : time();
    return date('Y-m', $t ?: time());
}

/**
 * Сколько бесплатных по Клубу уже засчитано участнику ЗА МЕСЯЦ.
 * Отклонённые не считаются: льгота возвращается.
 *
 * @param string $ym месяц «ГГГГ-ММ»; пусто - текущий
 */
function club_free_used(int $uid, string $ym = ''): int {
    if ($uid <= 0) return 0;
    club_free_migrate();
    $ym = $ym !== '' ? $ym : club_free_month();
    try {
        return (int) (scalar(
            "SELECT COUNT(*) FROM applications
              WHERE user_id = ?
                AND COALESCE(club_free,0) = 1
                AND COALESCE(status,'') <> 'rejected'
                AND substr(COALESCE(created_at,''), 1, 7) = ?", [$uid, $ym]) ?? 0);
    } catch (\Throwable $e) { return 0; }
}

/** Сколько бесплатных заявок осталось участнику в этом месяце. */
function club_free_left(int $uid, string $ym = ''): int {
    $л = club_free_limit() - club_free_used($uid, $ym);
    return $л > 0 ? $л : 0;
}

/**
 * ПОЛОЖЕНА ЛИ ЛЬГОТА ЭТОЙ ЗАЯВКЕ - главная дверь решения.
 *
 * Три условия вместе: платный конкурс (у бесплатного взноса нет вовсе и льгота
 * бессмысленна), живое членство в Клубе, и остался хотя бы один слот.
 *
 * @param array $comp строка `competitions`: нужны `id` и `is_paid`
 */
function club_free_polozheno(int $uid, array $comp): bool {
    if ($uid <= 0) return false;
    if (!(int) ($comp['is_paid'] ?? 0)) return false;
    if (!function_exists('club_is_active')) {
        if (!is_file(BASE_PATH . '/core/club.php')) return false;
        require_once BASE_PATH . '/core/club.php';
    }
    try { if (!club_is_active($uid)) return false; }
    catch (\Throwable $e) { return false; }
    return club_free_left($uid) > 0;
}

/** «осталось 2 из 3» - для витрины, кабинета и ответа бота. */
function club_free_slovami(int $left): string {
    $n = club_free_limit();
    if ($left <= 0) return 'бесплатные заявки по Клубу в этом месяце исчерпаны (' . $n . ' из ' . $n . ')';
    return 'бесплатно по Клубу: осталось ' . $left . ' из ' . $n . ' в этом месяце';
}

/**
 * Текст привилегии - ОДИН на страницу Клуба, письма, бота и записи ВК.
 * Двух редакций обещания в центре быть не должно: они разойдутся молча
 * (грабля правил 33, 46, 56а).
 */
function club_free_perk_text(): string {
    return 'До ' . club_free_limit() . ' заявок в месяц - без оргвзноса';
}

/* ═══════════ НАГРАДНЫЕ ДОКУМЕНТЫ ПО ЛЬГОТНОЙ ЗАЯВКЕ - БЕСПЛАТНО ═══════════
 *
 * Слово владельца 15.10.2026, постоянное. Им СНЯТА привилегия «Закрытые
 * конкурсы Клуба» и на её место поставлена эта:
 *   «Привилегия для участников элитного клуба:
 *    3 заявки на участие бесплатно (без оргвзноса).
 *    Бесплатно дипломы, дополнительные дипломы, благодарственные письма,
 *    по этим заявкам на участие.»
 *
 * ЧТО ИМЕННО БЕСПЛАТНО: ТОЛЬКО ЭЛЕКТРОННЫЕ ВЕРСИИ ЭТИХ ТРЁХ ДОКУМЕНТОВ.
 * Слово владельца 15.10.2026 на прямой вопрос: «Бесплатны только электронные,
 * оригиналы по прайсу со скидкой». Оригинал на бланке едет почтой, его печатают
 * и собирают в посылку - он остаётся платным, со клубной скидкой 20%.
 * ИМЕННОЙ диплом, кубок, статуэтка и медаль не входят вовсе: их владелец не
 * называл. Оба списка закрытые НАМЕРЕННО - и список документов, и список видов:
 * «бесплатно всё» это другое решение и другие деньги.
 *
 * ЧЕСТНОЕ ЧИСЛО ЭТОЙ ЛЬГОТЫ. В платном конкурсе электронные основной и
 * дополнительный дипломы и так входят в оргвзнос и приходят сами (правило 37),
 * заказать их нельзя вовсе. Значит по ЗАКАЗУ эта привилегия снимает цену ровно с
 * электронного благодарственного письма педагогу (300 руб), а остальные два
 * документа она подтверждает словами. Названо владельцу прямо: решение его, и
 * обещание теперь ровно то, что исполняет код.
 *
 * «ПО ЭТИМ ЗАЯВКАМ» - ТОЛЬКО ПО ЛЬГОТНЫМ. Отметка `applications.club_free`
 * ставится в двери подачи (api/v1/apply.php) той заявке, которую приняли без
 * оргвзноса. Четвёртая заявка месяца платная, и наградные документы по ней
 * обычные: иначе привилегия в три заявки не значила бы ничего.
 */

/** Документы, бесплатные по льготной заявке. Канонические имена (award_canon_item). */
const CLUB_FREE_AWARDS = ['Основной диплом', 'Дополнительный диплом', 'Благодарность'];

/** Вид, который бесплатен. Только электронный - слово владельца 15.10.2026. */
const CLUB_FREE_AWARD_KIND = 'digital';

/** Этот ли ВИД позиции бесплатен. Оригинал на бланке платный, со скидкой Клуба. */
function club_free_award_kind(string $kind): bool {
    return trim(mb_strtolower($kind)) === CLUB_FREE_AWARD_KIND;
}

/** Список для витрины и проверок - один источник. */
function club_free_award_items(): array { return CLUB_FREE_AWARDS; }

/** Этот ли документ бесплатен по льготной заявке. Сверяем ПО КАНОНУ. */
function club_free_award_item(string $item): bool {
    $item = trim($item);
    if ($item === '') return false;
    if (!function_exists('award_canon_item') && is_file(BASE_PATH . '/core/orders.php')) {
        require_once BASE_PATH . '/core/orders.php';
    }
    /* Имя позиции приходит с витрины в разных видах («Благодарность педагогу»,
       «Благодарственное письмо»), и сравнивать строкой нельзя - канон на то и
       есть (та же грабля, что с ценами конкурсов 19 и 20 в api/v1/order.php). */
    $c = function_exists('award_canon_item') ? award_canon_item($item) : $item;
    return in_array($c, CLUB_FREE_AWARDS, true);
}

/** Льготная ли это заявка (принята без оргвзноса по Клубу). */
function club_free_zayavka(int $appId): bool {
    if ($appId <= 0) return false;
    club_free_migrate();
    try {
        return (int) (scalar("SELECT COALESCE(club_free,0) FROM applications WHERE id=?", [$appId]) ?? 0) === 1;
    } catch (\Throwable $e) { return false; }
}

/**
 * ГЛАВНАЯ ДВЕРЬ РЕШЕНИЯ: бесплатен ли этот документ по этой заявке.
 * Её зовут и сервер (api/v1/order.php), и витрина (templates/site/pages/awards.php):
 * витрина обязана думать как сервер, иначе человек собирает корзину по одной цене,
 * а касса считает по другой (урок правил 45 и 64).
 */
function club_free_award_besplatno(int $appId, string $item, string $kind = CLUB_FREE_AWARD_KIND): bool {
    /* ВИД ПРОВЕРЯЕТСЯ ПЕРВЫМ И ОБЯЗАТЕЛЬНО. Оригинал на бланке печатают и везут
       почтой, и он остаётся платным: без этой проверки льгота отдавала бы
       изделие даром (слово владельца 15.10.2026, вариант «только электронные»). */
    return club_free_award_kind($kind)
        && club_free_award_item($item)
        && club_free_zayavka($appId);
}

/** Заголовок привилегии - один на страницу Клуба, письма, бота и записи ВК. */
function club_free_awards_perk_text(): string {
    return 'Электронные документы по льготным заявкам - бесплатно';
}

/** Та же привилегия словами, одной строкой. Оригиналы названы ТУТ ЖЕ, а не умолчанием. */
function club_free_awards_text(): string {
    return 'Электронные дипломы, дополнительные дипломы и благодарственные письма по '
         . 'заявкам, принятым без оргвзноса, изготавливаются бесплатно; оригиналы на '
         . 'бланках по прайсу со клубной скидкой';
}

/* ═══════════ ПРИЁМ ЗАЯВОК ТОЛЬКО ОТ ЧЛЕНОВ КЛУБА ═══════════
 *
 * Слово владельца 16.10.2026: «Приём заявок на участие в платном конкурсе
 * „Мировой акцент" только от членов элитного клуба».
 *
 * Признак у конкурса свой — `club_entry_only`, и он меняет РОВНО ОДНО: кого
 * пускает дверь подачи. Цена, положение, афиша и льгота на три заявки в месяц
 * остаются прежними. Почему не `club_only` — сказано в core/db.php у самой
 * колонки.
 *
 * РЕШЕНИЕ И СЛОВА ЖИВУТ ЗДЕСЬ, В ОДНОМ МЕСТЕ. Их спрашивают дверь подачи,
 * витрина формы, правила чат-мозга и его запасной ответ, афиша и аудит. Копия
 * условия или второй редакции отказа разошлись бы молча — грабля оплачена
 * правилами 33, 35, 45, 47, 56а, 64.
 */

/** Нужно ли членство в Клубе, чтобы подать заявку на этот конкурс. */
function club_vhod_tolko_chlenam(array $comp): bool {
    /* НЕПОЛНЫЙ SELECT ПРИЗНАК НЕ ПРЯЧЕТ (урок правил 47, 72в).
     *
     * Половина страниц сайта берёт конкурс перечнем колонок, а не `SELECT *`, и
     * обеих колонок признака в этом перечне не было. Тогда ответ «членство не
     * нужно» означал не факт, а экономию в запросе - и у «Мирового акцента»
     * страница «Положения конкурсов» обещала людям результаты за 5 рабочих
     * дней вместо 3 (слово владельца 18.10.2026). Поэтому: НЕТ ОБЕИХ КОЛОНОК В
     * СТРОКЕ, но есть номер - спрашиваем у базы. Колонка есть и равна нулю -
     * это ответ, и второго запроса не будет. */
    $естьEntry = array_key_exists('club_entry_only', $comp);
    $естьClub  = array_key_exists('club_only', $comp);
    if (!$естьEntry && !$естьClub && (int) ($comp['id'] ?? 0) > 0) {
        static $память = [];
        $id = (int) $comp['id'];
        if (!array_key_exists($id, $память)) {
            try {
                $r = one("SELECT COALESCE(club_entry_only,0) e, COALESCE(club_only,0) k
                            FROM competitions WHERE id = ?", [$id]);
            } catch (\Throwable $e) { $r = null; }
            $память[$id] = $r ? ((int) $r['e'] === 1 || (int) $r['k'] === 1) : false;
        }
        return $память[$id];
    }

    /* Конкурс Клуба (`club_only`) тоже пускает только членов, и у него это одно
       из нескольких условий. Для вопроса «нужно ли членство, чтобы подать» оба
       признака значат одно, поэтому ответ тут один на двоих. */
    return (int) ($comp['club_entry_only'] ?? 0) === 1
        || (int) ($comp['club_only'] ?? 0) === 1;
}

/**
 * Пометка рядом с названием конкурса — для списков бота, афиши и писем.
 * Пусто, если членство не нужно: лишнего слова в ответе быть не должно.
 */
function club_vhod_pometka(array $comp): string {
    return club_vhod_tolko_chlenam($comp)
        ? ', приём заявок только от участников Элитного клуба'
        : '';
}

/**
 * Отказ двери СЛОВАМИ, с объяснением, что даёт членство.
 *
 * «Нельзя» без объяснения это тупик: человек прочитает отказ и уйдёт, так и не
 * узнав, что членство у центра продаётся и даёт три заявки в месяц без взноса.
 * Текст один на дверь, на форму и на бота.
 */
function club_vhod_otkaz(array $comp): string {
    $имя = trim((string) ($comp['name'] ?? ''));
    return 'Заявки на конкурс' . ($имя !== '' ? ' «' . $имя . '»' : '')
         . ' принимаются только от участников Элитного клуба. Членство даёт до '
         . club_free_limit() . ' заявок в месяц без организационного взноса, '
         . 'остальные — по прайсу со клубной скидкой.';
}
