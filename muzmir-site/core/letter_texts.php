/** «1 работу / 2 работы / 5 работ», счётная форма для русского текста. */
function ol_plural(int $n, string $one, string $few, string $many): string {
    $n = abs($n) % 100;
    $d = $n % 10;
    if ($n > 10 && $n < 20) return $many;
    if ($d > 1 && $d < 5)   return $few;
    if ($d === 1)           return $one;
    return $many;
}

