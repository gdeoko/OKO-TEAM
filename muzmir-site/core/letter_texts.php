/**
 * Создаёт обращение: заводит запись в реестре исходящих и возвращает готовый HTML.
 *
 * @param array $o kind, org, person, person_role, region, email, city
 * @return array ['number'=>..,'html'=>..,'id'=>int]
 */
function ol_create(array $o): array {
    ol_migrate();
    $kind = ((string) ($o['kind'] ?? 'support')) === 'institution' ? 'institution' : 'support';

    $number = ol_next_number();
    $id = 0;
    try {
        $id = (int) insert('official_letters', [
            'number'         => $number,
            'kind'           => $kind,
            'org'            => (string) ($o['org'] ?? ''),
            'person'         => (string) ($o['person'] ?? ''),
            'person_role'    => (string) ($o['person_role'] ?? ''),
            'region'         => (string) ($o['region'] ?? ''),
            'email'          => mb_strtolower(trim((string) ($o['email'] ?? ''))),
            'competition_id' => (int) ($o['competition_id'] ?? 0),
            'season'         => date('Y-m'),
        ]);
    } catch (\Throwable $e) { $id = 0; }

    $html = ol_html_for($number, $o);
    return ['id' => $id, 'number' => $number, 'html' => $html];
}

/** Готовый HTML обращения по номеру и данным адресата (без записи в реестр). */
function ol_html_for(string $number, array $o): string {
    $kind = ((string) ($o['kind'] ?? 'support')) === 'institution' ? 'institution' : 'support';

    $org    = trim((string) ($o['org'] ?? ''));
    $person = trim((string) ($o['person'] ?? ''));
    $role   = trim((string) ($o['person_role'] ?? ''));

    // Кому. Строим по правилам делопроизводства: должность и организация в
    // дательном падеже уже приходят готовой строкой, ФИО отдельной строкой.
    $to = [];
    if ($role !== '') $to[] = $role;
    if ($org  !== '') $to[] = $org;
    if ($person !== '') $to[] = $person;

    // Обращение по имени и отчеству — если они известны. «Уважаемый коллега!»
    // ставим только когда ФИО нет: безличное обращение к человеку, чьё имя мы
    // знаем, выглядит небрежностью.
    $salut = '';
    if ($person !== '') {
        $parts = preg_split('~\s+~u', $person) ?: [];
        if (count($parts) >= 3) {
            // «Иванов Иван Иванович» → «Уважаемый Иван Иванович!»
            $salut = ol_salut_word($parts[2]) . ' ' . $parts[1] . ' ' . $parts[2] . '!';
        } elseif (count($parts) === 2) {
            $salut = ol_salut_word($parts[1]) . ' ' . $parts[1] . '!';
        }
    }
    if ($salut === '') $salut = $kind === 'institution' ? 'Уважаемые коллеги!' : 'Уважаемый руководитель!';

    if ($kind === 'institution') {
        $comps = ol_comps(false);
        $body  = ol_body_institution($comps, $o);
        $title = 'Обращение';
        $att   = ['Положения конкурсов сезона (по ссылке на официальном сайте).'];
    } else {
        $comps = ol_comps(true);
        $body  = ol_body_support($comps, $o);
        $title = 'Обращение';
        $att   = [
            'Положение о конкурсе (бесплатное участие).',
            'Афиша конкурса.',
            'Логотип Культурного центра «Музыкальный Мир».',
        ];
    }

    return ol_render([
        'number'      => $number,
        'title'       => $title,
        'addressee'   => $to,
        'salutation'  => $salut,
        'body'        => $body,
        'attachments' => $att,
        'paper'       => 'beige',
        // Встраивание картинок нужно только для печати в PDF и для вложения:
        // на обычной странице они идут ссылками и кэшируются браузером.
        'embed'       => !empty($o['embed']),
    ]);
}

/**
 * «Уважаемый» или «Уважаемая» — по отчеству.
 *
 * Ошибиться здесь дороже, чем кажется: официальное письмо, где к женщине
 * обращаются в мужском роде, читают как небрежность и дальше не читают. Отчество
 * даёт род однозначно; когда его нет — обращаемся нейтрально по должности.
 */
function ol_salut_word(string $patronymic): string {
    $p = mb_strtolower(trim($patronymic));
    if ($p === '') return 'Уважаемый';
    if (mb_substr($p, -3) === 'вна' || mb_substr($p, -4) === 'чна' || mb_substr($p, -4) === 'нична') {
        return 'Уважаемая';
    }
    if (mb_substr($p, -2) === 'ич' || mb_substr($p, -2) === 'ыч') return 'Уважаемый';
    return 'Уважаемый';
}
