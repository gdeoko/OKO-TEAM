/** Срок приёма по самому раннему закрытию: обещать больше, чем есть, нельзя. */
function ol_deadline(array $comps): string {
    $d = '';
    foreach ($comps as $c) {
        $e = trim((string) ($c['end_date'] ?? ''));
        if ($e === '') continue;
        if ($d === '' || $e < $d) $d = $e;
    }
    return $d;
}

