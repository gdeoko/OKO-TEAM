 * `core/launch_combo.php`, `core/launch_run.php`, `cron/engagement.php` и ещё
 * десяток мест. Статус переключает ночной крон, и в спокойный день разницы не
 * видно. А 14.10.2026 конкурс «Мировые Таланты» (приём 01-25.08, закрыт
 * полтора месяца назад) оказался сохранён в админке со статусом open - и для
 * всего кода он СРАЗУ стал действующим: по базе ушло 5943 письма «Открыт приём
