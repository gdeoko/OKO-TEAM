 * ВКонтакте его запись разносилась по расписанию вместе с тремя другими
 * августовскими конкурсами.
 *
 * Полная проверка была ровно в ОДНОМ месте - `chat_open_competitions()` в
 * чат-мозге (правило 35). Она и переехала сюда, чтобы ею пользовались все, а
 * не только бот: три условия ВМЕСТЕ - `launched=1` (запуск объявляет владелец,
 * правило 16), `status='open'` и СЕГОДНЯ внутри приёма по датам.
 *
 * ДАТА СИЛЬНЕЕ СТАТУСА. Статус это переключатель, его ставит человек руками и
 * крон ночью; даты приёма - это обещание, напечатанное в положении и в письме.
 * Поэтому кончился приём - конкурс не действующий, что бы ни стояло в статусе.
 */
declare(strict_types=1);

/**
 * Действующие конкурсы: приём идёт СЕГОДНЯ.
 *
 * @return array<int, array<string, mixed>> строки `competitions`, порядок витрины
 */
function comps_open_now(): array {
    $today = date('Y-m-d');
    try {
        $rows = all("SELECT * FROM competitions
                      WHERE COALESCE(launched,0) = 1 AND status = 'open'
                   ORDER BY sort, id");
    } catch (\Throwable $e) { return []; }
    $out = [];
    foreach ($rows as $c) {
        $s = trim((string) ($c['start_date'] ?? ''));
        $e = trim((string) ($c['end_date'] ?? ''));
        if ($s !== '' && substr($s, 0, 10) > $today) continue;   // ещё не начался
        if ($e !== '' && substr($e, 0, 10) < $today) continue;   // приём кончился
        $out[] = $c;
    }
    return $out;
}

/** Идёт ли приём по этому конкурсу прямо сейчас (по номеру). */
function comp_open_now(int $id): bool {
    if ($id <= 0) return false;
    foreach (comps_open_now() as $c) if ((int) $c['id'] === $id) return true;
    return false;
}

/** То же по слагу: в текстах постов и писем конкурс назван ссылкой `/konkurs-<слаг>`. */
function comp_open_now_slug(string $slug): bool {
    $slug = trim($slug);
    if ($slug === '') return false;
    foreach (comps_open_now() as $c) if ((string) $c['slug'] === $slug) return true;
    return false;
}

/**
 * ПРИГЛАШАТЬ ЛИ ПО ЭТОМУ ТЕКСТУ.
 *
 * Готовая запись для ленты или чужого сообщества зовёт на конкретный конкурс
 * ссылкой `музыкальный-мир.рф/konkurs-<слаг>`. Слаг и есть единственная
 * надёжная связь текста с конкурсом: названия в тексте пишутся заглавными, в
 * кавычках и падежах, а ссылка стоит как есть.
 *
 * Вернёт список СЛАГОВ, по которым приём уже кончился. Пусто - текст звать
 * можно.
 *
 * @return array<int, string>
 */
function comp_closed_slugs_in(string $text): array {
    if (trim($text) === '') return [];
    if (!preg_match_all('~/konkurs-([a-z0-9\-]+)~u', $text, $m)) return [];
    $плохие = [];
    foreach (array_unique($m[1]) as $slug) {
        if (!comp_open_now_slug((string) $slug)) $плохие[] = (string) $slug;
    }
    return $плохие;
}

/**
 * СЛАГИ КОНКУРСОВ, НАЗВАННЫЕ В ТЕКСТЕ ПИСЬМА.
 *
 * В ЗАПИСЯХ ДЛЯ ВК конкурс стоит ссылкой `/konkurs-<слаг>`, и ею судит
 * comp_closed_slugs_in(). В ПИСЬМАХ всё иначе, и на этом заслон 14.10 прошёл
 * мимо: у волны «Мировые Таланты» в теле не было НИ ОДНОЙ такой ссылки. Адрес
 * конкурса там `/competition/<слаг>`, да ещё завёрнутый в счётчик переходов
 * `/api/v1/track.php?e=c&t=…&u=<base64 адреса>` - то есть в тексте его не видно
 * вовсе, пока не развернёшь.
 *
 * Поэтому смотрим три вида сразу: оба написания адреса и содержимое `u=`.
 *
 * @return array<int, string> слаги, в порядке появления, без повторов
 */
function comp_slugs_in_text(string $text): array {
    if (trim($text) === '') return [];
    $сено = $text;
    // Развернуть счётчик переходов: внутри лежит сам адрес, закодированный base64.
    /* Перед `u=` в живом письме стоит не «&», а «&amp;»: ссылка лежит в HTML, и
       амперсанд там заэкранирован. Шаблон с одним «[?&]» на живом теле волны
       «Мировые Таланты» не нашёл НИ ОДНОГО слага - поймало письмо только по
       названию. Поэтому разделитель берём во всех трёх видах. */
    if (preg_match_all('~(?:[?&]|&amp;|&#38;)u=([A-Za-z0-9_\-=]{16,})~', $text, $mu)) {
        foreach ($mu[1] as $b64) {
            $raw = base64_decode(strtr($b64, '-_', '+/'), false);
            if (is_string($raw) && $raw !== '') $сено .= ' ' . $raw;
        }
    }
    $out = [];
    if (preg_match_all('~/(?:konkurs-|competition/)([a-z0-9\-]+)~u', $сено, $m)) {
        foreach ($m[1] as $slug) $out[(string) $slug] = 1;
    }
    return array_keys($out);
}

/* Обороты приглашения. Массовое письмо об ИТОГАХ закрытого конкурса законно:
   людям до сих пор отвечают про результаты и дипломы (правило 35). Запрещено
   ЗВАТЬ на конкурс, приём которого кончился, поэтому заслон ищет именно зов. */
const COMP_ZOV = ['приём заявок', 'прием заявок', 'открыт приём', 'открыт прием',
                  'приглашаем вас принять участие', 'приглашаем принять участие',
                  'новый конкурс', 'подать заявку', 'успейте подать'];

/**
 * ЗОВЁТ ЛИ ЭТО МАССОВОЕ ПИСЬМО НА КОНКУРС С КОНЧИВШИМСЯ ПРИЁМОМ.
 *
 * Возвращает причину СЛОВАМИ или пустую строку. Слова нужны: «письмо не ушло»
 * без объяснения читается как сбой канала, и следующая сессия полезет чинить
 * почту (так уже было с Яндексом, правило 26).
 *
 * Условия вместе: в тексте есть зов, назван закрытый конкурс и НЕ назван ни
 * один идущий. Третье обязательно - волна «4 конкурса» зовёт сразу на
 * несколько, и один закрытый среди живых не повод её останавливать.
 *
 * ЛИЧНЫЕ ПИСЬМА ЭТИМ ЗАСЛОНОМ НЕ СУДЯТСЯ, и это решает вызывающий: письмо
 * «Заявка №MZ-2026-00042 принята» законно называет закрытый «Мир звёзд» и ни
 * одного идущего конкурса - по такому письму заслон обязан молчать.
 */
function comp_pismo_zovet_na_zakrytyi(string $subject, string $body): string {
    $текст = $subject . ' ' . $body;
    $плоский = mb_strtolower((string) preg_replace('~\s+~u', ' ',
                   html_entity_decode(strip_tags($текст), ENT_QUOTES | ENT_HTML5, 'UTF-8')));
    if ($плоский === '') return '';

    $зов = false;
    foreach (COMP_ZOV as $о) { if (mb_strpos($плоский, $о) !== false) { $зов = true; break; } }
    if (!$зов) return '';

    $идёт = [];
    foreach (comps_open_now() as $c) $идёт[(string) $c['slug']] = (string) $c['name'];

    // Что названо: и слагом в адресе, и живым названием в тексте.
    $слаги = comp_slugs_in_text($текст);
    $закрытые = []; $живые = [];
    try { $все = all("SELECT id, slug, name, end_date FROM competitions WHERE COALESCE(launched,0)=1"); }
    catch (\Throwable $e) { return ''; }
    foreach ($все as $c) {
        $slug = (string) $c['slug'];
        $имя  = trim((string) $c['name']);
        $названо = in_array($slug, $слаги, true)
                || ($имя !== '' && mb_strpos($плоский, mb_strtolower($имя)) !== false);
        if (!$названо) continue;
        if (isset($идёт[$slug])) $живые[] = $имя;
        else $закрытые[$имя] = trim((string) ($c['end_date'] ?? ''));
    }
    if (!$закрытые || $живые) return '';

    $части = [];
    foreach ($закрытые as $имя => $до) {
        $части[] = '«' . $имя . '»' . ($до !== '' ? ' (приём до ' . $до . ')' : '');
    }
    return 'письмо зовёт на конкурс с кончившимся приёмом: ' . implode(', ', $части)
         . '; ни одного идущего конкурса в тексте нет';
}
