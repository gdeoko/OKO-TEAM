<?php
/**
 * КТО В ЧАТЕ ОТВЕЧАЕТСЯ ПЕРВЫМ.
 *
 * Участник Клуба получает ответ сразу, обычный — в течение пяти минут
 * (chat_delay_regular_sec, правило владельца 24.08.2026). Это единственное место,
 * где привилегия Клуба видна человеку в ту минуту, когда она ему нужна.
 *
 * ЧЕГО ЗДЕСЬ БОЛЬШЕ НЕ ДОЛЖНО СЛУЧИТЬСЯ. 19.08.2026 очередь пришлось выключить,
 * потому что она выглядела поломкой: готовый ответ приходил мгновенно, и следом
 * за ним прилетало «отвечу в течение 15 минут» — одной и той же фразой и на
 * первое сообщение, и на десятое. Дословно от владельца: «отвечает на вопрос
 * сразу, а потом говорит, что в течение 5 минут даст ответ — это как глюк
 * выглядит». Возвращая очередь, держим три правила:
 *   1. Ответ и подтверждение не приходят вместе. Пока идёт пауза, человек видит
 *      только подтверждение; сам ответ скрыт до своего срока (visible_at в вебе,
 *      отложенная отправка в ВК).
 *   2. Обещанный срок равен фактическому — chat_promise_minutes считается от
 *      chat_delay_regular_sec, а не задаётся отдельной цифрой.
 *   3. Формулировка подтверждения чередуется, про Клуб говорим один раз за
 *      диалог. Слово в слово каждый раз — подпись робота.
 *
 * Настройки:
 *   chat_delay_regular_sec — задержка обычному участнику (сейчас 300 = 5 минут;
 *                            0 возвращает моментальный ответ всем)
 *   chat_promise_minutes   — запасная цифра для фразы, если задержка выключена
 */
declare(strict_types=1);

/** Участник Клуба: членство активно прямо сейчас. */
function chat_is_vip(?int $userId): bool {
    $uid = (int) ($userId ?? 0);
    if ($uid <= 0) return false;
    if (!function_exists('club_is_active') && is_file(BASE_PATH . '/core/club.php')) {
        require_once BASE_PATH . '/core/club.php';
    }
    if (!function_exists('club_is_active')) return false;
    try { return club_is_active($uid); } catch (\Throwable $e) { return false; }
}

/**
 * Через сколько секунд участник получит ответ.
 * Ноль — моментально (Клуб, а также операторские и служебные случаи).
 */
function chat_reply_delay_sec(?int $userId): int {
    if (chat_is_vip($userId)) return 0;
    $sec = (int) (function_exists('setting') ? setting('chat_delay_regular_sec', '0') : 0);
    return max(0, min(900, $sec));   // потолок 15 минут: больше обещанного ждать нельзя
}

/**
 * Сколько минут обещаем словами обычному участнику.
 *
 * ОБЕЩАНИЕ СЧИТАЕТСЯ ОТ ФАКТИЧЕСКОЙ ЗАДЕРЖКИ, а не задаётся отдельно. Раньше это
 * были две независимые настройки, и они разъезжались: пауза 5 минут, а бот обещал
 * 15 — человек ждал впустую втрое дольше названного срока, либо наоборот получал
 * ответ позже обещанного. Отдельная настройка chat_promise_minutes остаётся
 * страховкой на случай, когда задержка выключена, но фразу всё же надо назвать.
 */
function chat_promise_minutes(): int {
    $sec = (int) (function_exists('setting') ? setting('chat_delay_regular_sec', '0') : 0);
    $sec = max(0, min(900, $sec));
    if ($sec > 0) return max(1, (int) ceil($sec / 60));
    $m = (int) (function_exists('setting') ? setting('chat_promise_minutes', '15') : 15);
    return max(1, min(60, $m));
}

/**
 * Подтверждение приёма вопроса — ТОЛЬКО когда ответ действительно придёт позже.
 *
 * При выключенной задержке (обычный режим) эта фраза не показывается вовсе:
 * сообщать «готовлю ответ» одновременно с готовым ответом значит выглядеть
 * сломанной автоматикой. Формулировки чередуются: одно и то же слово в слово
 * на каждое сообщение это тоже подпись робота.
 */
function chat_wait_notice(int $delaySec, string $name = '', bool $mentionClub = false): string {
    if ($delaySec <= 0) return '';
    $mins = max(1, (int) ceil($delaySec / 60));
    $word = $mins . ' ' . plural_ru($mins, 'минуты', 'минут', 'минут');
    $hi   = trim($name) !== '' ? trim($name) . ', ' : '';
    $vars = [
        $hi . 'вижу Ваш вопрос, отвечу в течение ' . $word . '.',
        $hi . 'сейчас посмотрю по Вашей заявке и вернусь с ответом в течение ' . $word . '.',
        $hi . 'секунду, уточню и отвечу — не дольше ' . $word . '.',
    ];
    $out = $vars[random_int(0, count($vars) - 1)];

    /* ПРО КЛУБ ГОВОРИМ ОДИН РАЗ ЗА ДИАЛОГ, НЕ КАЖДЫМ СООБЩЕНИЕМ.
     *
     * Пауза для «неклубных» — единственное место, где привилегия Клуба видна
     * человеку в момент, когда она ему нужна, поэтому назвать её стоит. Но
     * приписка к каждому подтверждению превращает поддержку в рекламный автомат,
     * а на это владелец уже ругался. Решает вызывающий код: первое ожидание в
     * диалоге — с упоминанием, дальше молча. */
    if ($mentionClub) {
        $out .= ' Участникам Клуба отвечаю сразу, без ожидания: /club';
    }
    return $out;
}

/** Русское склонение числительных для коротких фраз бота. */
if (!function_exists('plural_ru')) {
    function plural_ru(int $n, string $one, string $few, string $many): string {
        $n = abs($n) % 100;
        $n1 = $n % 10;
        if ($n > 10 && $n < 20) return $many;
        if ($n1 > 1 && $n1 < 5)  return $few;
        if ($n1 === 1)           return $one;
        return $many;
    }
}
