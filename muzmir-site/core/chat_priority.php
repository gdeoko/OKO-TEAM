/** Русское склонение числительных для коротких фраз бота. */
if (!function_exists('plural_ru')) {
    function plural_ru(int $n, string $one, string $few, string $many): string {
        $n = abs($n) % 100;
        $n1 = $n % 10;
        if ($n > 10 && $n < 20) return $many;
        if ($n1 > 1 && $n1 < 5)  return $few;
        if ($n1 === 1)           return $one;
        return $many;
    }
}
