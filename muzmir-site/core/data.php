/**
 * Допустимые формы исполнения. Подраздел сильнее номинации, неизвестная
 * номинация — универсальный набор.
 * Второй аргумент необязателен: вызов без него работает как прежде, поэтому
 * старые места не ломаются, а новые сужают набор.
 */
function FORMATIONS_FOR(string $nomination, string $subgroup = ''): array {
    $nomination = trim($nomination);
    $subgroup   = trim($subgroup);
    if ($nomination !== '' && $subgroup !== '') {
        $узкий = FORMATIONS_SUB_MAP()[$nomination][$subgroup] ?? null;
        if ($узкий) return $узкий;
    }
    $map = FORMATIONS_MAP();
    if ($nomination !== '' && isset($map[$nomination])) return $map[$nomination];
    return ['Соло', 'Дуэт', 'Ансамбль', 'Коллектив'];
}

/** Плоский список всех форм (для админки/фильтров, где номинация не задана). */
function FORMATIONS(): array {
    $all = [];
    foreach (FORMATIONS_MAP() as $list) foreach ($list as $f) $all[$f] = true;
    // Набор подраздела тоже считается: иначе фильтр админки не нашёл бы форму,
    // которая есть только у подраздела.
    foreach (FORMATIONS_SUB_MAP() as $subs) foreach ($subs as $list) foreach ($list as $f) $all[$f] = true;
    return array_keys($all);
}

