/** Допустимые формы исполнения для номинации. Неизвестная номинация — универсальный набор. */
function FORMATIONS_FOR(string $nomination): array {
    $map = FORMATIONS_MAP();
    $nomination = trim($nomination);
    if ($nomination !== '' && isset($map[$nomination])) return $map[$nomination];
    return ['Соло', 'Дуэт', 'Ансамбль', 'Коллектив'];
}

/** Плоский список всех форм (для админки/фильтров, где номинация не задана). */
function FORMATIONS(): array {
    $all = [];
    foreach (FORMATIONS_MAP() as $list) foreach ($list as $f) $all[$f] = true;
    return array_keys($all);
}

