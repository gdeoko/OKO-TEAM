/** 10-балльная шкала → результат. */
function GRADE_SCALE(): array {
    return [
        [9, 10, 'ГРАН-ПРИ'],
        [8, 9,  'ЛАУРЕАТ 1 степени'],
        [7, 8,  'ЛАУРЕАТ 2 степени'],
        [6, 7,  'ЛАУРЕАТ 3 степени'],
        [5, 6,  'ДИПЛОМАНТ 1 степени'],
        [4, 5,  'ДИПЛОМАНТ 2 степени'],
        [1, 4,  'ДИПЛОМАНТ 3 степени'],
    ];
}
function score_to_result(?float $score): string {
    if ($score === null) return '';
    foreach (GRADE_SCALE() as [$lo, $hi, $title]) {
        if ($score >= $lo && $score <= $hi) return $title;
    }
    return '';
}

