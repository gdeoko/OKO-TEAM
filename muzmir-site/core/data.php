/**
 * 10-балльная шкала → звание. Интервалы полуоткрытые (нижняя граница включается):
 * верхняя граница относится к следующему званию, максимальный балл 10 → ГРАН-ПРИ.
 * Строки идут по убыванию нижней границы, результат — первое совпадение score >= lo.
 */
function GRADE_SCALE(): array {
    return [
        [9, 10, 'ГРАН-ПРИ'],
        [8, 9,  'ЛАУРЕАТ 1 степени'],
        [7, 8,  'ЛАУРЕАТ 2 степени'],
        [6, 7,  'ЛАУРЕАТ 3 степени'],
        [5, 6,  'ДИПЛОМАНТ 1 степени'],
        [4, 5,  'ДИПЛОМАНТ 2 степени'],
        [1, 3,  'ДИПЛОМАНТ 3 степени'],
    ];
}
function score_to_result(?float $score): string {
    if ($score === null) return '';
    foreach (GRADE_SCALE() as [$lo, $hi, $title]) {
        if ($score >= $lo) return $title;
    }
    return '';
}

