/**
 * ДОПИСАТЬ ПУНКТ В ГОТОВОЕ ПОЛОЖЕНИЕ - ОДИН ИСТОЧНИК НА ДВОИХ.
 *
 * Её зовут инструмент `scripts/reg_point_add.php` (пункт владельца во все
 * положения и эталоны) и `regulation_generate()` ниже (пункт, зависящий от
 * признака конкурса). Вторая копия этой механики разошлась бы молча - грабля
 * оплачена правилами 33, 35, 45, 47, 56а, 64.
 *
 * Пункт НЕ рисуется с нуля: берётся абзац-образец (тот, что указан в $after),
 * копируется целиком со всем оформлением, и в копии подменяется только текст -
 * поэтому шрифт, отступы и выключка у нового пункта те же, что у соседей.
 * Служебные метки w14:paraId из копии убираются: два абзаца с одним
 * идентификатором Word считает ошибкой разметки.
 *
 * Возвращает СЛОВА: '' - пункт вставлен, 'уже есть' - он и так на месте, иначе
 * причину. «Не вставилось» без объяснения читается как сбой файла, и следующая
 * сессия чинит документ вместо условия.
 */
function reg_point_vstavit(string $path, string $after, string $no, string $text, bool $dry = false, bool $скопировать = true): string {
    if (!is_file($path)) return 'нет файла ' . basename($path);

    $z = new \ZipArchive();
    if ($z->open($path) !== true) return 'не открылся ' . basename($path);
    $xml = (string) $z->getFromName('word/document.xml');
    $z->close();
    if ($xml === '') return 'в документе нет word/document.xml';

    // Уже дописан - второй раз не кладём.
    $plainAll = html_entity_decode(strip_tags($xml), ENT_QUOTES | ENT_XML1, 'UTF-8');
    if (preg_match('~(?<!\d)' . preg_quote($no, '~') . '\.\s~u', $plainAll)) return 'уже есть';

    if (!preg_match_all('~<w:p[ >].*?</w:p>~us', $xml, $m, PREG_OFFSET_CAPTURE)) {
        return 'разметка не разобралась';
    }
    $srcP = null; $srcOffset = null; $srcLen = null;
    foreach ($m[0] as $pp) {
        $plain = trim(html_entity_decode(strip_tags($pp[0]), ENT_QUOTES | ENT_XML1, 'UTF-8'));
        if (preg_match('~^' . preg_quote($after, '~') . '\.\s~u', $plain)) {
            $srcP = $pp[0]; $srcOffset = $pp[1]; $srcLen = strlen($pp[0]);
            break;
        }
    }
    if ($srcP === null) return 'нет абзаца-образца п. ' . $after;
    if ($dry) return '';

    /* Копия образца с подменённым текстом. Текстовых прогонов в этих абзацах по
       одному; если их вдруг больше, весь текст кладём в первый, остальные гасим -
       иначе от старого пункта останутся хвосты. */
    $full  = $no . '. ' . $text;
    $copy  = preg_replace('~\s+w14:(paraId|textId)="[^"]*"~u', '', $srcP) ?? $srcP;
    $first = true;
    $copy  = preg_replace_callback('~<w:t(\s[^>]*)?>.*?</w:t>~us', function (array $mm) use (&$first, $full): string {
        if ($first) {
            $first = false;
            return '<w:t xml:space="preserve">' . htmlspecialchars($full, ENT_QUOTES | ENT_XML1, 'UTF-8') . '</w:t>';
        }
        return '<w:t xml:space="preserve"></w:t>';
    }, $copy) ?? $copy;

    /* КОПИЯ ЛОЖИТСЯ ВНЕ public, И ЭТО НЕ ПРИДИРКА.
     *
     * Копия звалась `<положение>.docx.bak-<дата>` и ложилась РЯДОМ с живым
     * файлом, то есть в `public/uploads/regulations/`. Замер 16.10.2026: таких
     * копий там лежало 26, и сервер отдавал любую по прямой ссылке кодом 200 -
     * то есть наружу было открыто устаревшее положение, подписанное
     * генеральным директором. Теперь копии живут в `data/regulations_bak/`,
     * куда веб-сервер хода не имеет.
     *
     * Перегенерации копия не нужна вовсе ($скопировать = false): файл только
     * что собран из эталона, терять нечего, а каждое сохранение конкурса
     * оставляло бы по новой копии. */
    $bak = '';
    if ($скопировать) {
        $dirBak = BASE_PATH . '/data/regulations_bak';
        if (!is_dir($dirBak) && !@mkdir($dirBak, 0775, true) && !is_dir($dirBak)) {
            return 'не удалось создать ' . $dirBak;
        }
        $bak = $dirBak . '/' . basename($path) . '.bak-' . date('Ymd-His');
        if (!@copy($path, $bak)) return 'не удалось снять копию ' . basename($bak);
    }

    $new = substr($xml, 0, $srcOffset + $srcLen) . $copy . substr($xml, $srcOffset + $srcLen);
    $z = new \ZipArchive();
    if ($z->open($path) !== true) return 'не открылся на запись ' . basename($path);
    $z->addFromString('word/document.xml', $new);
    $z->close();
    // Инструмент идёт под root, а положение пересобирает веб-сервер под
    // www-data: без этого следующая перегенерация из админки падает на copy().
    reg_file_vladelec($path);

    // Сверка: пункт читается тем же разбором, которым его видит бот.
    require_once BASE_PATH . '/core/chat_regulation.php';
    $pts = reg_points_from_text(reg_docx_text($path));
    if (!isset($pts[$no])) {
        if ($bak !== '' && is_file($bak)) {
            @copy($bak, $path);
            reg_file_vladelec($path);
            return 'пункт не прочитался обратно, файл возвращён из копии';
        }
        /* Копии нет (перегенерация её не делает) - но и терять нечего: собрать
           положение заново из эталона можно в любой момент. Называем причину. */
        return 'пункт не прочитался обратно';
    }
    return '';
}

/**
 * Текст абзаца, в котором встретился $needle (склейка всех <w:t>), или null.
 * Нужен, чтобы спросить У ДОКУМЕНТА, есть ли в нём такой абзац, а не гадать по
 * тому, из какого эталона он собран.
 */
function reg_para_naidi(string $xml, string $needle): ?string {
    if (!preg_match_all('~<w:p\b[^>]*>.*?</w:p>~su', $xml, $m)) return null;
    foreach ($m[0] as $p) {
        if (!preg_match_all('~<w:t[^>]*>([^<]*)</w:t>~su', $p, $tm)) continue;
        $joined = reg_xml_decode(implode('', $tm[1]));
        if (mb_strpos($joined, $needle) !== false) return $joined;
    }
    return null;
}

/**
 * Весь текст абзаца с $needle заменяется на $text; пустая строка — абзац пустеет.
 * В отличие от reg_para_text_replace() не требует знать прежнюю формулировку:
 * предложение собирается кодом целиком, и подстрока из эталона тут не ориентир.
 */
function reg_para_set_text(string $xml, string $needle, string $text, int &$hits): string {
    return (string) preg_replace_callback('~<w:p\b[^>]*>.*?</w:p>~su',
        function (array $m) use ($needle, $text, &$hits): string {
            $p = $m[0];
            if (!preg_match_all('~<w:t[^>]*>([^<]*)</w:t>~su', $p, $tm)) return $p;
            $joined = reg_xml_decode(implode('', $tm[1]));
            if (mb_strpos($joined, $needle) === false) return $p;
            $hits++;
            $first = true;
            return (string) preg_replace_callback('~<w:t[^>]*>[^<]*</w:t>~su',
                function () use (&$first, $text): string {
                    if ($first) {
                        $first = false;
                        return '<w:t xml:space="preserve">' . reg_xml_esc($text) . '</w:t>';
                    }
                    return '<w:t xml:space="preserve"></w:t>';
                }, $p);
        }, $xml);
}

/**
 * ПРЕДЛОЖЕНИЕ О СПОСОБЕ И СРОКЕ РАССЫЛКИ РЕЗУЛЬТАТОВ — ОДНО НА ВЕСЬ ЦЕНТР.
 * Способ решает `results_mode`, число рабочих дней — `prioritet_dnei_konkursa()`:
 * своя копия условия разошлась бы молча (правила 33, 35, 45, 47, 73).
 */
function reg_fraza_rezultatov(array $c, string $resDate, bool $естьАбзацВК): string {
    if ((string) ($c['results_mode'] ?? '') === 'list') {
        /* ДАТА ТОЛЬКО ИЗ `results_date`. Прежде она бралась «results_date или
           end_date», и у конкурса без даты оглашения положение назначало его на
           последний день приёма: так «25.10.2026» попало в «Территорию таланта»
           и «Вершину творчества». Даты нет — говорим словами, а не чужим числом. */
        $фраза = $resDate !== ''
            ? 'Аттестационные результаты будут опубликованы ' . $resDate . ' года'
            : 'Аттестационные результаты будут опубликованы в дату оглашения итогов, объявленную оргкомитетом';
        /* ГДЕ опубликованы — сказано следующим абзацем эталона. Нет его (платный
           эталон) — предложение обязано быть самодостаточным. */
        if (!$естьАбзацВК) $фраза .= ' на официальной странице сообщества ВКонтакте: ' . REG_REZ_VK_URL;
        return $фраза;
    }
    if (!function_exists('prioritet_dnei_konkursa') && defined('BASE_PATH')) {
        require_once BASE_PATH . '/core/prioritet.php';
    }
    $дней = function_exists('prioritet_dnei_konkursa') ? (int) prioritet_dnei_konkursa($c) : REG_SROK_ETALONA;
    /* «С ДАТЫ ПОДАЧИ ЗАЯВКИ» СКАЗАНО ПРЯМО. Срок без начала человек проверить не
       может: он не знает и не может узнать, когда жюри взяло его номер. Код
       считает от подачи, так же говорят письма центра и бот (правило 37). */
    return 'Аттестационный результат отправляется каждому участнику в течение ' . $дней
         . ' рабочих дней с даты подачи заявки, на электронную почту, указанную в заявке на участие.';
}

/**
 * Число прописью в именительном падеже — после «через»: «через 5 (пять)
 * рабочих дней» (формулировка владельца от 22.10.2026; раньше стояло «в
 * течение 5 (пяти)», и число было в родительном). Список закрыт сроками,
 * которые центр правда называет: выдумывать склонения на все числа незачем.
 */
function reg_chislo_propisyu(int $n): string {
    $с = [3 => 'три', 4 => 'четыре', 5 => 'пять', 6 => 'шесть', 7 => 'семь', 10 => 'десять'];
    return $с[$n] ?? '';
}

/**
 * СРОК ИЗГОТОВЛЕНИЯ ЭЛЕКТРОННЫХ НАГРАД СЛОВАМИ - ОДИН НА ОБА АБЗАЦА ПОЛОЖЕНИЯ.
 * Числа у `core/prioritet.php`, как и расчёт: вписанная копия ломается ровно в
 * день правки (правила 56, 61), а разошедшееся обещание человек читает как
 * обман центра (правила 33, 35, 45, 46).
 *
 * У конкурса, который принимает заявки только от членов Клуба, все участники
 * клубные по построению - клубная оговорка там лишняя, срок один.
 */
function reg_sroki_izgotovleniya(array $c): array {
    if (!function_exists('prioritet_dnei_konkursa') && defined('BASE_PATH')) {
        require_once BASE_PATH . '/core/prioritet.php';
    }
    $общий = function_exists('prioritet_dnei_konkursa') ? (int) prioritet_dnei_konkursa($c) : 5;
    $клуб  = defined('PRIORITET_SROK_KLUBA') ? PRIORITET_SROK_KLUBA : 3;
    $срок  = static function (int $n): string {
        $сл = reg_chislo_propisyu($n);
        // «через», а не «в течение»: электронный наградной материал уходит в
        // назначенный день, по истечении срока (слово владельца 22.10.2026).
        return 'через ' . $n . ($сл !== '' ? ' (' . $сл . ')' : '') . ' ' . (in_array($n % 10, [2, 3, 4], true) && ($n % 100 < 10 || $n % 100 > 20) ? 'рабочих дня' : 'рабочих дней');
    };
    /* ОТДАЁМ ПАРУ, А НЕ ГОТОВУЮ ФРАЗУ: срок назван в положении ДВУМЯ абзацами с
       разной грамматикой, и собрать из одной строки оба нельзя. Числа и слова
       считаются здесь ровно один раз. */
    return [
        'общий'    => $срок($общий),
        'оговорка' => $общий !== $клуб ? ', а участникам Элитного клуба ' . $срок($клуб) : '',
    ];
}

/**
 * АБЗАЦ «СРОКИ ИЗГОТОВЛЕНИЯ И НАПРАВЛЕНИЯ НАГРАДНОГО МАТЕРИАЛА».
 *
 * Слово владельца 16.10.2026: «Изготовление электронных дипломов 5 рабочих дней.
 * Для членов элитного клуба - 3 рабочих дня.» Прежняя формулировка говорила
 * «Наградной материал ... направляется на электронную почту», и срок читался как
 * общий на ВСЁ, включая оригиналы на бланках. Теперь электронный вид назван
 * прямо, а абзац про оригиналы (7 рабочих дней всем) остаётся нетронутым.
 *
 * «Другой наградной материал в электронном виде» стоит рядом с дипломами не для
 * красоты: по той же почте уходят именной диплом и благодарственное письмо в
 * электронном виде, и сузив обещание до одних дипломов, центр отобрал бы у них
 * названный срок.
 */
function reg_fraza_izgotovleniya(array $c): string {
    $с = reg_sroki_izgotovleniya($c);
    /* Срок подачи заявки на изготовление — тем же абзацем, рядом со сроками
       изготовления (правило владельца 22.10.2026, core/award_window.php). */
    if (!function_exists('award_window_text') && defined('BASE_PATH')) require_once BASE_PATH . '/core/award_window.php';
    return 'Электронные дипломы и другой наградной материал в электронном виде изготавливаются'
         . ' и направляются на электронную почту, указанную в заявке, '
         . $с['общий'] . $с['оговорка'] . '.'
         . (function_exists('award_window_text') ? ' ' . award_window_text() : '');
}

/**
 * АБЗАЦ ПЕРЕЧНЯ «ЧТО ВХОДИТ В ОРГВЗНОС» (только платный эталон).
 *
 * Начало счёта здесь ДРУГОЕ, и подменять его нельзя: электронные дипломы,
 * входящие в оргвзнос, считаются от получения аттестационного результата, а не
 * от оплаты заказа (правило 37). Меняются только срок и клубная оговорка.
 */
function reg_fraza_rassylki(array $c): string {
    $с = reg_sroki_izgotovleniya($c);
    return '— Рассылка наградного материала осуществляется на электронную почту, указанную'
         . ' в заявке на участие, ' . $с['общий'] . ' с момента получения аттестационного'
         . ' результата' . $с['оговорка'] . '.';
}

function regulation_generate(int $competitionId): string {
    $c = one("SELECT * FROM competitions WHERE id=?", [$competitionId]);
    if (!$c) throw new \RuntimeException('Конкурс #' . $competitionId . ' не найден');

    $isPaid = (int) ($c['is_paid'] ?? 0) === 1;
    /* КОНКУРС КЛУБА ИДЁТ ПО СВОЕМУ ЭТАЛОНУ.
     *
     * Он бесплатный, но не для всех: участвовать могут только участники Клуба,
     * и у серии есть годовой призовой фонд, которого нет ни в одном другом
     * конкурсе. Бесплатный эталон этого не говорит, а дописывать условия
     * вручную каждый месяц — верный способ однажды забыть. Эталон собирается
     * скриптом scripts/build_etalon_club.php из бесплатного. */
    $clubOnly = (int) ($c['club_only'] ?? 0) === 1;
    $file = $clubOnly ? 'etalon_5.docx' : ($isPaid ? 'etalon_2.docx' : 'etalon_4.docx');
    $etalon = BASE_PATH . '/docs/polozheniya/' . $file;
    if (!is_file($etalon)) throw new \RuntimeException('Эталон положения не найден: ' . basename($etalon));
    // Частая причина сбоя copy(): эталон залит с правами 600 (root-only) и недоступен
    // php-fpm (www-data) для чтения. Пробуем самолечение, иначе — понятная ошибка про ИСТОЧНИК.
    if (!is_readable($etalon)) {
        @chmod($etalon, 0644);
        clearstatcache(true, $etalon);
        if (!is_readable($etalon)) {
            throw new \RuntimeException('Эталон недоступен для чтения: ' . basename($etalon)
                . ' — выставьте права 644 (chmod 644 docs/polozheniya/*.docx)');
        }
    }

    $slug = trim((string) ($c['slug'] ?? ''));
    if ($slug === '') $slug = 'competition-' . $competitionId;

    $dir = BASE_PATH . '/public/uploads/regulations';
    if (!is_dir($dir) && !@mkdir($dir, 0775, true) && !is_dir($dir)) {
        throw new \RuntimeException('Не удалось создать каталог ' . $dir);
    }
    $dest = $dir . '/' . $slug . '.docx';
    if (!@copy($etalon, $dest)) throw new \RuntimeException('Не удалось скопировать эталон в ' . $dest);
    @chmod($dest, 0664);

    $zip = new \ZipArchive();
    if ($zip->open($dest) !== true) throw new \RuntimeException('Не удалось открыть DOCX: ' . $dest);
    $xml = $zip->getFromName('word/document.xml');
    if ($xml === false || $xml === '') { $zip->close(); throw new \RuntimeException('В DOCX нет word/document.xml'); }

    $fmt = static function (?string $d): string {
        $d = trim((string) $d);
        if ($d === '') return '';
        $ts = strtotime($d);
        return $ts ? date('d.m.Y', $ts) : '';
    };
    $nameUp  = mb_strtoupper(trim((string) ($c['name'] ?? '')));
    $endDate = $fmt($c['end_date'] ?? null);
    /* ДАТА ОГЛАШЕНИЯ — ТОЛЬКО СВОЯ. Отката на `end_date` здесь больше нет:
       он назначал оглашение на последний день приёма (правило 73ж). */
    $resDate = $fmt($c['results_date'] ?? null);
    $isNational = (($c['type'] ?? 'international') === 'national');

    // ДАТА УТВЕРЖДЕНИЯ в шапке («УТВЕРЖДАЮ … Ильясов А.И. <дата> год»).
    // Правило владельца: всегда ПЕРВОЕ число месяца, в котором конкурс запущен.
    // Раньше сюда попадала дата прямо из эталона (11.05.2026) — она и была «неверной
    // датой в шапке» на всех положениях.
    $approveBase = trim((string) ($c['launched_at'] ?? '')) !== '' ? (string) $c['launched_at']
                 : (trim((string) ($c['start_date'] ?? '')) !== '' ? (string) $c['start_date'] : 'now');
    $approveTs   = strtotime($approveBase) ?: time();
    $approveDate = date('01.m.Y', $approveTs);          // всегда 01 число месяца запуска

    /* ССЫЛКА НА ОБРАЗЦЫ И ЗАКАЗ — СРАЗУ НА СВОЙ КОНКУРС.
       В эталоне стоит общий адрес витрины наград; участник попадал на список
       конкурсов и искал свой. Подставляем прямую страницу конкурса. */
    $awardsUrl = 'https://музыкальный-мир.рф/awards?comp=' . $competitionId;
    $xml = str_replace('https://музыкальный-мир.рф/awards', $awardsUrl, $xml);

    $nameHits = 0; $dateHits = 0; $misc = 0;
    if ($isPaid) {
        // etalon_2 «ЭВРИКА»: тематика уже «СВОБОДНАЯ», в титуле «Международный».
        $xml = reg_run_replace_exact($xml, 'ЭВРИКА', $nameUp, $nameHits);
        if ($isNational) $xml = reg_run_replace_exact($xml, 'Международный ', 'Всероссийский ', $misc);
        if ($endDate !== '') $xml = reg_para_text_replace($xml, 'Приём заявок', '25.06.2026', $endDate, $dateHits);

        // ОРГВЗНОС — ИЗ БАЗЫ, А НЕ ИЗ ЭТАЛОНА.
        //
        // В эталоне сумма зашита как «500 ₽ (пятьсот рублей)» и раньше не менялась.
        // Владелец поднял цену «Мировых Талантов» до 1000 ₽ в админке — и получилось,
        // что на сайте одна цена, а в положении, которое участник скачивает и по
        // которому платит, другая. Для конкурса это расхождение в документе, на
        // который он же и ссылается.
        //
        // Сумма встречается дважды: в шапке титульного листа («Орг. взнос — 500 ₽»)
        // и в разделе о стоимости («в данном конкурсе: 500₽»). Пишется и цифрой, и
        // прописью, с пробелом перед ₽ и без — заменяем все написания.
        $price = (int) ($c['price'] ?? 0);
        if ($price > 0 && $price !== 500) {
            // Разряды разделяем ПРОБЕЛОМ — «1 000 ₽», как принято в русских
            // документах. Точка в этой роли читается как десятичная: «1.000» можно
            // понять и как одну целую, а сумма в положении спорной быть не должна.
            // Пропись в скобках снимает любые сомнения окончательно.
            $num   = number_format($price, 0, ',', ' ');
            $words = reg_rub_words($price);
            $priceHits = 0;
            foreach (['500 ₽ (пятьсот рублей)', '500₽ (пятьсот рублей)'] as $old) {
                $sep = mb_strpos($old, '₽') === 3 ? '' : ' ';
                $new = $num . $sep . '₽ (' . $words . ')';
                $xml = reg_para_text_replace($xml, '500', $old, $new, $priceHits);
            }
            $misc += $priceHits;
        }
    } else {
        // etalon_4 «СЛАВА РОССИИ»: в титуле «Всероссийский», тематика патриотическая.
        $xml = reg_run_replace_exact($xml, 'СЛАВА РОССИИ', $nameUp, $nameHits);
        if (!$isNational) $xml = reg_run_replace_exact($xml, 'Всероссийский ', 'Международный ', $misc);
        if ($endDate !== '') $xml = reg_para_text_replace($xml, 'Приём заявок', '07.06.2026', $endDate, $dateHits);
        $xml = reg_run_replace_exact($xml, 'ПАТРИОТИЧЕСКАЯ (В СООТВЕТСТВИИ С НАЗВАНИЕМ КОНКУРСА)', 'СВОБОДНАЯ', $misc);
    }

    // Дата утверждения в шапке — во всех эталонах строка «11.05.2026». В DOCX она
    // склеена с соседним текстом («11.05.2026 год») и разбита по ранам, поэтому
    // точное сравнение рана не срабатывает — заменяем на уровне абзаца.
    /* СПОСОБ И СРОК РАССЫЛКИ АТТЕСТАЦИОННЫХ РЕЗУЛЬТАТОВ - ИЗ КОДА, А НЕ ИЗ ЭТАЛОНА.
     *
     * Правка владельца 16.10.2026: «В положении конкурсов "Территория таланта" и
     * "Вершина творчества" не верно написаны сроки и способы рассылки
     * аттестационных результатов». Бесплатный эталон обещал публикацию списком на
     * странице сообщества, а у обоих конкурсов `results_mode='email'`: результат
     * уходит письмом на почту из заявки, списком не публикуется ничего. Дата при
     * этом подставлялась из `end_date`, то есть документ назначал оглашение на
     * последний день приёма.
     *
     * Правка того же дня до неё: «срок аттестации написан 5 дней вместо 3» - у
     * конкурса, который принимает заявки только от членов Клуба, срок три рабочих
     * дня (правила 72, 72г), все его участники клубные.
     *
     * Предложение целиком собирает `reg_fraza_rezultatov()`: способ по
     * `results_mode`, число дней у `prioritet_dnei_konkursa()`. Абзац про страницу
     * сообщества у письма снимается - обещать оба способа сразу документ не вправе.
     *
     * Правка живёт ЗДЕСЬ, в перегенерации, а не в эталоне: эталон один на все
     * бесплатные конкурсы, а режим оглашения у них разный (урок правила 72а). */
    if (!function_exists('prioritet_dnei_konkursa')) require_once BASE_PATH . '/core/prioritet.php';
    $списком  = (string) ($c['results_mode'] ?? '') === 'list';
    $естьВК   = reg_para_naidi($xml, REG_REZ_NEEDLE_VK) !== null;
    $srokHits = 0;
    $фразаРез = reg_fraza_rezultatov($c, $resDate, $естьВК);
    /* ИГЛУ ВЫБИРАЕМ ПО ДОКУМЕНТУ, А НЕ ПЕРЕБОРОМ: собранное предложение само
       содержит обе приметы, и второй заход переписывал бы уже готовый абзац. */
    $__игла = reg_para_naidi($xml, REG_REZ_NEEDLE_PUB) !== null ? REG_REZ_NEEDLE_PUB : REG_SROK_NEEDLE;
    $xml = reg_para_set_text($xml, $__игла, $фразаРез, $srokHits);
    $vkHits = 0;
    if (!$списком && $естьВК) $xml = reg_para_set_text($xml, REG_REZ_NEEDLE_VK, '', $vkHits);
    /* ПУСТОЙ СЧЁТ - НЕ МЕЛОЧЬ: в документе осталась формулировка эталона, то есть
       он может обещать не тот способ. Сборку не валим (иначе владелец не сохранит
       конкурс), но причина обязана попасть в журнал словами, а аудит видит это
       фактом по живому .docx. */
    if ($srokHits === 0) {
        error_log('regulation_generate(' . $competitionId . '): абзац о рассылке результатов не найден,'
            . ' в документе осталась формулировка эталона');
    }

    /* СРОК ИЗГОТОВЛЕНИЯ ЭЛЕКТРОННЫХ НАГРАД - ИЗ КОДА (правило 73з).
     *
     * В эталоне абзац обещает один срок всем, а у участника Элитного клуба он
     * три рабочих дня, и так считает код (`дней_изготовление` в
     * `core/prioritet.php`, его же берут `cron/send_diplomas.php` и
     * `order_issue_diplomas()`). Абзац про ОРИГИНАЛЫ остаётся как есть: их
     * изготовление одинаково для всех, и клубной оговорки там быть не должно. */
    $izgHits = 0;
    $xml = reg_para_set_text($xml, REG_IZG_NEEDLE, reg_fraza_izgotovleniya($c), $izgHits);
    if ($izgHits === 0) {
        error_log('regulation_generate(' . $competitionId . '): абзац о сроке изготовления'
            . ' наградного материала не найден, в документе осталась формулировка эталона');
    }

    /* ВТОРОЙ АБЗАЦ С ТЕМ ЖЕ СРОКОМ - в перечне того, что входит в оргвзнос.
       Есть он только в платном эталоне, поэтому сперва спрашиваем У ДОКУМЕНТА:
       пустой счёт у бесплатного конкурса это норма, а не беда, и красная строка
       в журнале на ровном месте прячет настоящие отказы (правило 47). */
    if (reg_para_naidi($xml, REG_RASS_NEEDLE) !== null) {
        $rassHits = 0;
        $xml = reg_para_set_text($xml, REG_RASS_NEEDLE, reg_fraza_rassylki($c), $rassHits);
        if ($rassHits === 0) {
            error_log('regulation_generate(' . $competitionId . '): абзац о рассылке наградного'
                . ' материала по оргвзносу найден, но не переписан');
        }
    }

    $approveHits = 0;
    $xml = reg_para_text_replace($xml, '11.05.2026', '11.05.2026', $approveDate, $approveHits);

    if ($nameUp !== '' && $nameHits === 0) {
        $zip->close(); @unlink($dest);
        throw new \RuntimeException('Название конкурса из эталона не найдено (эталон изменился?)');
    }

    if (!$zip->addFromString('word/document.xml', $xml)) {
        $zip->close();
        throw new \RuntimeException('Не удалось записать word/document.xml');
    }
    $zip->close();

    reg_file_vladelec($dest);

    /* ПРИЁМ ТОЛЬКО ОТ ЧЛЕНОВ КЛУБА - ПУНКТ ДОПИСЫВАЕТСЯ ЗДЕСЬ, ПОСЛЕ СБОРКИ.
     *
     * Решение берём у единого источника (`club_vhod_tolko_chlenam`, правило 72),
     * а не считаем своей копией условия. Отказ не валит сборку: положение без
     * пункта остаётся верным документом, а недостачу громко показывает аудит -
     * но причина обязана попасть в журнал словами, иначе её никто не найдёт. */
    if (!function_exists('club_vhod_tolko_chlenam')) require_once BASE_PATH . '/core/club_free.php';
    if (function_exists('club_vhod_tolko_chlenam') && club_vhod_tolko_chlenam($c)) {
        $__пр = reg_point_vstavit($dest, REG_PUNKT_KLUB_VHOD_AFTER, REG_PUNKT_KLUB_VHOD_NO,
                                  REG_PUNKT_KLUB_VHOD, false, false);
        if ($__пр !== '' && $__пр !== 'уже есть') {
            error_log('regulation_generate(' . $competitionId . '): пункт '
                . REG_PUNKT_KLUB_VHOD_NO . ' про приём только для членов Клуба не вписан: ' . $__пр);
        }
    }

    update('competitions', ['regulation_pdf' => $dest], 'id=:wid', ['wid' => $competitionId]);
    return $dest;
}
