<?php
declare(strict_types=1);
/**
 * core/diploma_fio.php — РАЗБОР поля ФИО на отдельных людей.
 *
 * Зачем. В applications.full_name руководители вписывают не одного человека, а
 * всех участников подряд: «Ишмуков Вячеслав Михайлович Криволапов Максим
 * Вячеславович Заверяева Дарья Вадимовна». Вёрстка бланка балансировала строки
 * ПО СЛОВАМ и резала человека пополам - на MZ-2026-00087 вышло «Криволапов
 * Максим / Вячеславович». Слово владельца 18.10.2026: ФИО каждого участника
 * пишется в одну строку, как у первого.
 *
 * Разбор ОДИН на все движки бланка (v1..v4 лежат в своих пространствах имён):
 * копия условия разошлась бы молча.
 *
 * ОТВЕЧАЕМ ТОЛЬКО КОГДА УВЕРЕНЫ. Пусто - значит «делить не берусь», и бланк
 * собирается как прежде. Замерено по всем 1023 живым заявкам: делится 15, и во
 * всех пятнадцати это правда несколько человек. Не делятся (и правильно):
 * «Федотова Варвара - Солистка Образцового … Ансамбля Радуга» (человек плюс
 * звание), «Народный вокальный ансамбль «Эхо Красного камня»» (коллектив),
 * «Богданова Валерия Озерная Мария Гандрабура Мария» (три человека без отчеств,
 * делить по три слова нельзя - вышло бы «Богданова Валерия Озерная»).
 */

/** Окончания отчеств. Список ЗАКРЫТЫЙ: добавлять только по замеру живой базы. */
const DIPLOMA_FIO_OTCHESTVO = '~(ович|евич|ьич|оглы|ызы|овна|евна|ична|инична)$~ui';

function diploma_fio_slova(string $s): array {
    return preg_split('~\s+~u', trim($s), -1, PREG_SPLIT_NO_EMPTY) ?: [];
}

/** Похоже на ФИО одного человека: 2-4 слова, каждое с заглавной кириллицы. */
function diploma_fio_imennye(array $w): bool {
    $n = count($w);
    if ($n < 2 || $n > 4) return false;
    foreach ($w as $x) {
        if (!preg_match('~^[А-ЯЁ][а-яё]+(-[А-ЯЁ]?[а-яё]+)?$~u', $x)) return false;
    }
    return true;
}

/**
 * Разложить поле на людей. Возвращает список из двух и более ФИО либо пустоту.
 *
 * Два пути, и второй намеренно строже первого:
 *   1) явный разделитель (точка с запятой, запятая, «и») - делим по нему, если
 *      каждый кусок похож на ФИО человека;
 *   2) разделителя нет - делим по три слова, и ТОЛЬКО когда каждое третье слово
 *      оканчивается отчеством. Без этой проверки «Богданова Валерия Озерная
 *      Мария Гандрабура Мария» развалилось бы по чужим границам.
 */
function diploma_fio_lyudi(string $s): array {
    $s = trim((string) preg_replace('~\s+~u', ' ', $s));
    if ($s === '') return [];

    foreach ([';', ',', ' и ', ' И '] as $sep) {
        if (mb_strpos($s, $sep) === false) continue;
        $parts = array_values(array_filter(array_map('trim', explode($sep, $s)),
            static fn($x) => $x !== ''));
        if (count($parts) < 2) continue;
        $ok = true;
        foreach ($parts as $p) if (!diploma_fio_imennye(diploma_fio_slova($p))) { $ok = false; break; }
        if ($ok) return $parts;
    }

    $w = diploma_fio_slova($s);
    if (count($w) >= 6 && count($w) % 3 === 0) {
        $tr = array_chunk($w, 3);
        $ok = true;
        foreach ($tr as $t) {
            if (!diploma_fio_imennye($t) || !preg_match(DIPLOMA_FIO_OTCHESTVO, $t[2])) { $ok = false; break; }
        }
        if ($ok) return array_map(static fn($t) => implode(' ', $t), $tr);
    }
    return [];
}
