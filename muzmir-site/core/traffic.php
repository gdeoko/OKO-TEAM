<?php
/**
 * ОТКУДА ПРИШЁЛ ЧЕЛОВЕК.
 *
 * Каналов стало много: письма по своей базе, письма учреждениям, анонсы в
 * сообществах ВКонтакте, сообщения администраторам, посты своего сообщества,
 * когда-нибудь реклама. Без пометки источника все они сливаются в одну кучу
 * «заявки за август», и решать, что усиливать, а что выключать, приходится на
 * ощупь. Одна колонка в заявке снимает этот вопрос навсегда.
 *
 * КАК РАБОТАЕТ. В ссылках стоит utm_source (и при желании utm_campaign). При
 * первом заходе метка кладётся в куку на 90 дней и больше не перезаписывается:
 * если человек пришёл из анонса в сообществе, а через неделю вернулся из письма,
 * заслуга остаётся за первым касанием — именно оно его привело.
 *
 * Ничего личного не хранится: только короткое имя канала и кампании.
 */
declare(strict_types=1);

const TRAFFIC_COOKIE = 'mm_src';

/**
 * Запомнить источник, если он пришёл в ссылке. Вызывается на каждой странице.
 * Ничего не делает, если метка уже стоит: первое касание важнее последнего.
 */
function traffic_capture(): void {
    if (PHP_SAPI === 'cli' || headers_sent()) return;
    $src = trim((string) ($_GET['utm_source'] ?? $_GET['src'] ?? ''));
    if ($src === '' || isset($_COOKIE[TRAFFIC_COOKIE])) return;

    $camp  = trim((string) ($_GET['utm_campaign'] ?? ''));
    $value = mb_substr(preg_replace('~[^a-zA-Z0-9_\-]~', '', $src) ?? '', 0, 24);
    if ($value === '') return;
    if ($camp !== '') {
        $value .= '/' . mb_substr(preg_replace('~[^a-zA-Z0-9_\-]~', '', $camp) ?? '', 0, 32);
    }
    setcookie(TRAFFIC_COOKIE, $value, [
        'expires'  => time() + 90 * 86400,
        'path'     => '/',
        'httponly' => true,
        'samesite' => 'Lax',
    ]);
    $_COOKIE[TRAFFIC_COOKIE] = $value;
}

/** Источник для записи в заявку: 'vk/vk-promo-2026-08', 'email', '' если неизвестен. */
function traffic_src(): string {
    return mb_substr((string) ($_COOKIE[TRAFFIC_COOKIE] ?? ''), 0, 64);
}
