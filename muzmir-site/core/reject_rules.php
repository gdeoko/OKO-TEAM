/**
 * ЧТО ИМЕННО ДОЛЖНО БЫТЬ ВИДНО — ЗАВИСИТ ОТ НОМИНАЦИИ (п. 8.3).
 *
 * В положении сказано «чётко должны быть видны руки, ноги и лицо исполнителя»,
 * но с оговоркой «в соответствии с номинацией», и оговорка эта решающая.
 * Прежде задание перечисляло все три требования подряд, без разбора: работу по
 * художественному слову (#1748) сняли за то, что у чтеца не видно рук, — а
 * руки у чтеца не значат ничего, читают не ими.
 *
 * Правило владельца, дословно: руки смотрят у инструменталистов — там видна
 * постановка и работа пальцев; лицо — у вокалистов; ноги — у танцоров. Что не
 * относится к номинации, основанием для отказа не бывает.
 */
function rr_visible_rule(string $nomination): string {
    $n = mb_strtolower(trim($nomination));
    $head = "  8.3. ЧТО ДОЛЖНО БЫТЬ ЧЁТКО ВИДНО — ПО ЭТОЙ НОМИНАЦИИ:\n";

    if (str_contains($n, 'инструм')) {
        return $head
            . "       РУКИ исполнителя: у пианиста — клавиатура и обе руки, у скрипача — смычок и\n"
            . "       пальцы на грифе, у гитариста и баяниста — обе руки на инструменте. Это здесь\n"
            . "       главное: по рукам видно постановку, и без них номер не оценить.\n"
            . "       Лицо и ноги в этой номинации основанием для отказа НЕ бывают.\n";
    }
    if (str_contains($n, 'вокал') || str_contains($n, 'песн')) {
        return $head
            . "       ЛИЦО исполнителя: открыто, освещено, видна артикуляция. Съёмка со спины, против\n"
            . "       света или из дальнего конца зала, где лица не разобрать, — нарушение.\n"
            . "       Руки и ноги в этой номинации основанием для отказа НЕ бывают.\n";
    }
    if (str_contains($n, 'хорео') || str_contains($n, 'танц') || str_contains($n, 'цирк')) {
        return $head
            . "       ФИГУРА ЦЕЛИКОМ, и прежде всего НОГИ: стопы не обрезаны кадром на протяжении\n"
            . "       номера. Танец судят по линии всего тела, и срезанные стопы — нарушение.\n";
    }
    if (str_contains($n, 'слов') || str_contains($n, 'театр')) {
        return $head
            . "       ЛИЦО исполнителя: видно, освещено, слышна и видна речь. Руки к делу не относятся —\n"
            . "       читают и играют не ими, и отказ по рукам здесь НЕВЕРЕН.\n";
    }
    if (str_contains($n, 'зобраз') || str_contains($n, 'прикладн') || str_contains($n, 'фото')) {
        return $head . "       Требование к исполнителю не применяется: работа — это снимок, а не выступление.\n";
    }
    return $head
        . "       То, чем номер исполняется: у инструменталиста — руки, у вокалиста — лицо,\n"
        . "       у танцора — ноги и фигура целиком. Остальное основанием для отказа не бывает.\n";
}
