declare(strict_types=1);

require_once __DIR__ . '/media_date.php';

/**
 * Проверить заявку по всем машинно-проверяемым основаниям.
 *
 * Порядок важен: сначала то, что делает оценку бессмысленной (нет доступа к
 * работе, работа чужая или не одна), потом возраст. Первое сработавшее и
 * возвращается — участнику нужна одна понятная причина, а не список.
 *
 * @param  array  $app   строка applications (нужны id, video_url, full_name)
 * @param  string $deadline дата закрытия приёма конкурса (срок возраста считаем от неё)
 * @return array{reject:bool, code:string, reason:string, note:string}
 */
function rr_check(array $app, string $deadline = ''): array {
    $ok = ['reject' => false, 'code' => '', 'reason' => '', 'note' => '', 'hint' => ''];
    $url = trim((string) ($app['video_url'] ?? ''));
    if ($url === '') {
        return ['reject' => true, 'code' => 'no_link',
                'reason' => "Заявка на участие заполнена неверно (п. 4.2 положения).\nСсылка на конкурсный материал не указана.",
                'note' => 'ссылки нет', 'hint' => ''];
    }

    foreach (['rr_check_shared_link', 'rr_check_platform', 'rr_check_reachable', 'rr_check_age'] as $fn) {
        $r = $fn($app, $deadline);
        if ($r['reject']) return $r + ['hint' => ''];
        if ($r['note'] !== '') $ok['note'] = trim($ok['note'] . ' ' . $r['note']);
        // Проверка сработала, но до отказа не дотянула (граница срока): причина
        // посчитана и должна дойти до человека готовой, а не пропасть.
        if ((string) ($r['reason'] ?? '') !== '') $ok['hint'] = (string) $r['reason'];
    }
    return $ok;
}

/**
 * ОДНА ССЫЛКА У РАЗНЫХ УЧАСТНИКОВ.
 *
 * Так подают целым классом: педагог выкладывает все работы в одну папку облака и
 * вписывает её адрес в каждую заявку. Формально ссылка рабочая, содержательно —
 * заявка не заполнена: по ней не видно, какая из тридцати работ принадлежит
 * этому ребёнку. Владелец отклонил все тридцать семь таких заявок без единого
 * исключения, и это самое массовое основание отказа за месяц.
 *
 * ПОРОГ. Две-три заявки на одну ссылку — обычное дело у ансамбля или у одного
 * участника с несколькими номерами, и такие владелец принимал. Считаем поэтому
 * не заявки, а РАЗНЫХ участников: от четырёх — это общая папка.
 */
function rr_check_shared_link(array $app, string $deadline = ''): array {
    $ok = ['reject' => false, 'code' => '', 'reason' => '', 'note' => ''];
    $url = trim((string) ($app['video_url'] ?? ''));
    if ($url === '') return $ok;

    try {
        $n = (int) (scalar("SELECT COUNT(DISTINCT mb_lower(TRIM(full_name))) FROM applications
                             WHERE video_url = ? AND COALESCE(full_name,'') <> ''", [$url]) ?? 0);
    } catch (\Throwable $e) { return $ok; }
    if ($n < 4) return $ok;

    return ['reject' => true, 'code' => 'shared_link',
        'reason' => "Заявка на участие заполнена неверно (п. 4.2 положения).\n"
                  . 'Неверная ссылка на конкурсный материал: по этому адресу выложены работы '
                  . 'нескольких участников (' . $n . '), и определить конкурсный номер именно этого '
                  . 'участника невозможно. Нужна прямая ссылка на одну свою работу.',
        'note' => 'ссылка общая на ' . $n . ' участников'];
}

/**
 * ЗАПРЕЩЁННАЯ ПЛОЩАДКА (пп. 8.8 и 8.9).
 *
 * Пункт 8.9 называет запрещённые ресурсы поимённо, и здесь отказ бесспорный.
 * А вот п. 8.8 со списком разрешённых площадок центр на практике трактует шире:
 * Облако Mail.ru в списке не названо, но работы оттуда принимаются постоянно.
 * Поэтому «нет в списке разрешённых» отказом не считаем — только прямой запрет.
 */
function rr_check_platform(array $app, string $deadline = ''): array {
    $ok = ['reject' => false, 'code' => '', 'reason' => '', 'note' => ''];
    $host = mb_strtolower((string) (parse_url(trim((string) ($app['video_url'] ?? '')), PHP_URL_HOST) ?: ''));
    if ($host === '') return $ok;

    $banned = ['instagram.com' => 'Instagram', 'www.instagram.com' => 'Instagram',
               'facebook.com' => 'Facebook', 'www.facebook.com' => 'Facebook', 'fb.watch' => 'Facebook',
               'tiktok.com' => 'TikTok', 'www.tiktok.com' => 'TikTok', 'vm.tiktok.com' => 'TikTok',
               'youtube.com' => 'YouTube', 'www.youtube.com' => 'YouTube', 'youtu.be' => 'YouTube',
               'm.youtube.com' => 'YouTube'];
    foreach ($banned as $h => $name) {
        if ($host === $h || str_ends_with($host, '.' . $h)) {
            return ['reject' => true, 'code' => 'banned_platform',
                'reason' => 'Материал размещён на запрещённом интернет-ресурсе (' . $name . '): такие материалы '
                          . 'не допускаются к участию в конкурсе (п. 8.9 положения).',
                'note' => 'площадка ' . $name . ' запрещена'];
        }
    }
    return $ok;
}

/**
 * ССЫЛКА ПЕРЕСТАЛА ОТКРЫВАТЬСЯ (п. 8.10).
 *
 * «Ссылка на конкурсный материал должна быть актуальна вплоть до оглашения
 * результатов» — четырнадцать отказов за месяц именно об этом: участник подал
 * заявку, а потом убрал файл, закрыл альбом или сделал аккаунт приватным. Жюри
 * открывает ссылку и видит пустоту.
 *
 * ПРОВЕРЯЕМ В МОМЕНТ РАЗБОРА, А НЕ ПО СТАРОЙ ОТМЕТКЕ. В link_check заявки лежит
 * результат проверки на день подачи, и он говорит «принята» — потому что тогда
 * ссылка и правда работала. Основание же возникает позже, поэтому спрашиваем
 * площадку заново.
 *
 * ОСТОРОЖНО С СЕТЬЮ. Площадка молчит чаще, чем участник обманывает: таймаут,
 * защита от роботов, ночные работы у хостера. Поэтому отклоняем только при
 * прямом «нет такого файла» (video_verify вернул bad с указанием причины), а
 * «проверить не удалось» пропускаем дальше — там решает человек по записи.
 */
function rr_check_reachable(array $app, string $deadline = ''): array {
    $ok = ['reject' => false, 'code' => '', 'reason' => '', 'note' => ''];
    $url = trim((string) ($app['video_url'] ?? ''));
    if ($url === '' || !is_file(BASE_PATH . '/core/link_check.php')) return $ok;
    require_once BASE_PATH . '/core/link_check.php';
    if (!function_exists('video_verify')) return $ok;

    try { $v = video_verify($url, (string) ($app['nomination'] ?? '')); }
    catch (\Throwable $e) { return $ok; }

    if (!empty($v['ok']) || (string) ($v['state'] ?? '') !== 'bad') return $ok;

    /* ОДНОГО «НЕДОСТУПНО» МАЛО.
     *
     * При сверке по базе одна и та же заявка (#246) в первом заходе получила
     * «видео ВКонтакте недоступно», а через минуту — «ссылка принята»: площадка
     * притормозила, и проверка приняла это за закрытый доступ. Цена такой
     * ошибки — снятый с конкурса участник, поэтому спрашиваем второй раз. */
    sleep(3);
    try { $v2 = video_verify($url, (string) ($app['nomination'] ?? '')); }
    catch (\Throwable $e) { return $ok; }
    if (!empty($v2['ok']) || (string) ($v2['state'] ?? '') !== 'bad') {
        return ['reject' => false, 'code' => '', 'reason' => '',
                'note' => 'ссылка ответила не сразу — проверена повторно, доступна'];
    }

    /* РАБОТА, КОТОРУЮ УЖЕ ОЦЕНИЛИ, НАЗАД НЕ ОТЗЫВАЕТСЯ.
     *
     * Ссылки участников мрут и после конкурса: из пятисот шестидесяти семи
     * принятых работ восемнадцать сейчас недоступны — файл убрали, альбом
     * закрыли. Звание уже присвоено, диплом отправлен, и снимать человека с
     * конкурса задним числом нельзя. Основание остаётся заметкой для человека. */
    if (trim((string) ($app['result'] ?? '')) !== '' || (float) ($app['score'] ?? 0) > 0) {
        return ['reject' => false, 'code' => 'link_dead_after',
                'reason' => '',
                'note' => 'ссылка перестала открываться уже после оценки — итог не пересматривается'];
    }

    /* Возраст материала эта же проверка умеет назвать сама (stale), но у неё свой
       отсчёт — от «сегодня». Возрастом занимается rr_check_age, где срок считается
       от закрытия приёма, поэтому такой ответ пропускаем ему. */
    if (!empty($v['stale'])) return $ok;

    $why = trim((string) ($v['reason'] ?? ''));
    return ['reject' => true, 'code' => 'link_dead',
        'reason' => "Ссылка на конкурсный материал недействительна: она должна быть актуальна вплоть "
                  . "до оглашения результатов (п. 8.10 положения).\n"
                  . ($why !== '' ? $why . ' ' : '')
                  . 'Возможно, файл удалён или доступ к нему закрыт настройками аккаунта.',
        'note' => 'ссылка не открывается: ' . ($why !== '' ? $why : 'площадка вернула отказ')];
}

/**
 * ВОЗРАСТ МАТЕРИАЛА (п. 8.11).
 *
 * Считаем от закрытия приёма, а не от «сегодня»: работа, поданная в срок и
 * разобранная месяцем позже, не должна становиться просроченной сама по себе.
 * Отказ пишем так же, как его пишет владелец: пункт, потом дата съёмки.
 */
function rr_check_age(array $app, string $deadline = ''): array {
    $ok = ['reject' => false, 'code' => '', 'reason' => '', 'note' => ''];
    $url = trim((string) ($app['video_url'] ?? ''));
    if ($url === '') return $ok;

    /* Дату съёмки мог уже прочитать мост: файла на сайте нет, а creation_time
       контейнера он отдаёт вместе с подготовленными дорожками. Своё показание
       главнее облачного — оно из самой записи. */
    if ((int) ($app['__shot_ts'] ?? 0) > 0) {
        $ts = (int) $app['__shot_ts'];
        $limit = strtotime('-' . MEDIA_MAX_AGE_YEARS . ' year', $deadline !== '' ? (int) strtotime($deadline) : time());
        $days = (int) floor(($limit - $ts) / 86400);
        if ($days > 14) {
            return ['reject' => true, 'code' => 'too_old',
                'reason' => 'Конкурсный материал старше 1 года с момента исполнения (п. 8.11 положения).' . "\n"
                          . 'Дата съёмки: ' . date('d.m.Y', $ts),
                'note' => 'дата съёмки ' . date('d.m.Y', $ts) . ' (метка в записи, прочитана мостом)'];
        }
        if ($days > 0) {
            return ['reject' => false, 'code' => 'too_old_edge',
                'reason' => 'Конкурсный материал старше 1 года с момента исполнения (п. 8.11 положения).' . "\n"
                          . 'Дата съёмки: ' . date('d.m.Y', $ts),
                'note' => 'на границе срока: дата съёмки ' . date('d.m.Y', $ts) . ', старше допустимого на '
                        . $days . ' дн., решение за человеком'];
        }
        return ['reject' => false, 'code' => '', 'reason' => '',
                'note' => 'дата съёмки ' . date('d.m.Y', $ts) . ' (метка в записи)'];
    }

    $age = media_too_old($url, (string) ($app['__file'] ?? ''), $deadline !== '' ? $deadline : null);
    if (!$age['old']) return ['reject' => false, 'code' => '', 'reason' => '', 'note' => (string) $age['note']];

    /* У САМОЙ ГРАНИЦЫ РЕШАЕТ ЧЕЛОВЕК.
     *
     * Сверка с решениями владельца показала два случая, где работа старше срока
     * на пять и на девять дней, и обе он принял. Это не оплошность: срок в
     * положении — граница, а не секундомер, и снимать участника с конкурса из-за
     * недели, да ещё по дате ЗАГРУЗКИ, которая съёмку только ограничивает
     * сверху, — цена ошибки несопоставима с выигрышем.
     *
     * Поэтому две недели у границы отдаём человеку: причина уже посчитана и
     * лежит в подсказке, нажать «отклонить» он может одним движением. Всё, что
     * старше на месяцы (а таких среди принятых нашлось шесть, вплоть до записи
     * 2021 года), отклоняется как обычно. */
    $ts    = (int) ($age['ts'] ?? 0);
    $limit = strtotime('-' . MEDIA_MAX_AGE_YEARS . ' year', $deadline !== '' ? (int) strtotime($deadline) : time());
    $days  = $ts > 0 ? (int) floor(($limit - $ts) / 86400) : 999;
    if ($days <= 14) {
        return ['reject' => false, 'code' => 'too_old_edge', 'reason' => (string) $age['reason'],
            'note' => 'на границе срока: ' . (string) $age['note'] . ' — старше допустимого на '
                    . $days . ' дн., решение за человеком'];
    }

    return ['reject' => true, 'code' => 'too_old',
        'reason' => (string) $age['reason'],   // формулировка одна на всю систему, см. media_date.php
        'note' => (string) $age['note']];
}

/**
 * СВОД ОСНОВАНИЙ ДЛЯ ЗАДАНИЯ МОДЕЛИ.
 *
 * Модель видит запись и решает, есть ли нарушение. До сих пор в задании стояли
 * только те требования, что попали в рубрику: монтаж, номинация, состав. Из-за
 * этого разбор ни разу не отметил ни съёмку с рук, ни спрятанные за кадром ноги
 * танцора, ни чужой водяной знак — хотя владелец за это отклоняет.
 *
 * Здесь раздел 8 приведён целиком, с номерами и с оговорками, которых в тексте
 * положения нет, но которые видны по решениям: что считается фонограммой, а что
 * нормой жанра; почему Облако Mail.ru принимается, хотя в списке его нет.
 */
/**
 * @param string $nomination номинация заявки: требование «чётко видны руки, ноги
 *        и лицо» в положении дано С ОГОВОРКОЙ «в соответствии с номинацией», и
 *        оговорка эта не формальная. Владелец: руки смотрят у инструменталистов
 *        (фортепиано, скрипка, гитара — там видна постановка и аппликатура),
 *        лицо — у вокалистов, ноги — у танцоров. У чтеца руки не значат ничего,
 *        и отказ по ним неверен: одна работа по художественному слову (#1748)
 *        была снята именно так.
 */
function rr_prompt_block(string $nomination = ''): string {
    return "\n\nТРЕБОВАНИЯ ПОЛОЖЕНИЯ К КОНКУРСНОМУ МАТЕРИАЛУ (РАЗДЕЛ 8) — ПРОВЕРЬ КАЖДОЕ ПО ЗАПИСИ.\n"
    . "  8.1. Одна заявка — один конкурсный номер. Подборка из нескольких номеров в одном файле — нарушение.\n"
    . "  8.2. Съёмка на сцене, импровизированной сцене или дома, на СТАТИЧНУЮ камеру или телефон.\n"
    . "       Съёмка с рук допустима, если кадр в целом устойчив; нарушение — когда камера ходит\n"
    . "       за исполнителем, переезжает с плана на план или снимает на ходу.\n"
    . rr_visible_rule($nomination)
    . "  8.5. НЕТ монтажа, склеек, стоп-кадров, видеоэффектов и наложенных аудиодорожек. Номер идёт\n"
    . "       одним куском. Титры в начале или в конце нарушением не считаются, склейка внутри номера — да.\n"
    . "  8.6. Качество: разрешение не ниже 480p и картинка по существу различима — но судить\n"
    . "       надо по номинации, а не по цифрам. Плохо, когда не видно ГЛАВНОГО: у инструменталиста\n"
    . "       смазаны руки, у вокалиста не разобрать лица, у танцора фигура тонет в темноте, у рисунка\n"
    . "       не видно линий и цвета. Зернистость или дрожание кадра сами по себе, если номер при этом\n"
    . "       виден и слышен, отказом не бывают. Съёмка экраном с экрана и чужие водяные знаки поверх\n"
    . "       работы недопустимы.\n"
    . "  8.7. ФОНОГРАММА — ЭТО НЕ ОТКАЗ, А СНИЖЕНИЕ ДО ДИПЛОМАНТА. Работу с конкурса не снимают.\n"
    . "  8.7.1. Звук должен быть слышен: аккомпанемент, минусовка и голос прослушиваются, не перегружены,\n"
