function smm_compose(string $body): string {
    return rtrim($body) . "\n\n" . smm_footer();
}

/**
 * ФУТЕР ПЕРЕСОБИРАЕТСЯ ПЕРЕД ОТПРАВКОЙ, А НЕ ЗАМОРАЖИВАЕТСЯ ПРИ ПОДГОТОВКЕ.
 *
 * Готовый текст поста (`text_full`) собирается в `smm_prepare` и лежит в
 * очереди ДО ТРЁХ ДНЕЙ, а решения владельца приходят каждую неделю. 15.10.2026
 * это стоило живого поста: график сменили утром (суббота с 10:00), в настройках
 * и во всех живых выходах он стал новым, а афиша Лермонтова ушла в 10:00 со
 * СТАРОЙ субботой - футер в ней был впаян накануне. Та же грабля, что со
 * слотами ротации ВК (правило 50): запись живёт дольше решения.
 *
 * Подменяем ровно хвост от разделительной черты: тело поста не трогаем.
 * Черты нет - текст отдаём как есть, дописывать футер задним числом не наше
 * дело (так собран, например, текст, правленный руками в админке).
 */
function smm_footer_svezhiy(string $текст): string {
    // Знак пишем через \u{...} и ТОЛЬКО в двойных кавычках: в одинарных PHP
    // печатает его буквально (грабли правил 35а и 40).
    $поз = mb_strpos($текст, "\u{2501}");
    if ($поз === false) return $текст;
    return rtrim(mb_substr($текст, 0, $поз)) . "\n\n" . smm_footer();
}

