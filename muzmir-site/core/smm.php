/**
 * Последний рубеж перед очередью. Проверяются те правила, нарушение которых
 * участник увидит и которые стоят центру доверия.
 *
 * Запрет на обещание бесплатных благодарностей — не придирка: 02.10.2026 пост
 * «Концертмейстер» обещал бесплатную выдачу благодарственных писем и дипломов
 * куратора, а на сайте эта выдача выключена (curator_free_enabled=0, только
 * партнёрам от 5 заявок). Педагог пришёл бы за документом, которого нет.
 */
/**
 * ЖЁСТКАЯ ЦЕНЗУРА ТЕКСТА. Слово владельца 19.10.2026: «используй жёсткую цензуру
 * на всё то что запрещено к публикации, согласно законодательству Российской
 * Федерации».
 *
 * СПИСОК УЗКИЙ И ЗАКРЫТЫЙ НАМЕРЕННО. Двусмысленные слова сюда НЕ входят:
 * «насилие» законно стоит в разборе сюжета оперы, «вино» - в биографии
 * композитора, и широкий список остановил бы ленту на верном тексте. Красное на
 * ровном месте прячет настоящие отказы (правила 47, 62). Замерено по всему
 * корпусу перед правкой: совпадение ОДНО, и то в черновике #13, снятом аудитом
 * ещё 06.10 и в ленту не идущем.
 *
 * АЛКОГОЛЬ И ТАБАК ВЫКЛЮЧЕНЫ И В ТЕКСТАХ (слово владельца 19.10.2026), поэтому
 * списков ТРИ: русское слово ловится по-разному, и одним способом тут нельзя.
 * ПОДСТРОКОЙ ищется то, чего в живом русском тексте больше нигде нет.
 * С НАЧАЛА СЛОВА - то, что иначе ловит чужое: «водк» сидит в «сводке», «пьян» в
 * «фортепьяно», «табак» в «табакерке», а «Музыкальная табакерка» это Лядов.
 * ЦЕЛЫМ СЛОВОМ - «вино» и «пиво»: «вина», «виноват», «виновник», «виноград»,
 * «винил» и «винтаж» это не алкоголь, и широкий корень забраковал бы пост о
 * премьере, в которой центр не виноват. Вина в рюмке ловится СОЧЕТАНИЕМ.
 * ИСКЛЮЧЕНИЯ названы нарочно: «пьянящий успех» в истории о премьере и
 * «табакерка» в разборе пьесы законны, и останавливать их нельзя.
 * Замерено до правки: 13 ловушек языка целы, 13 лживых фраз поймано, по всему
 * живому корпусу ленты (25 постов) совпадений ноль.
 */
const SMM_ZAPRET_SLOVA = ['наркот', 'порно', 'суицид', 'самоубий', 'экстремист', 'террорист',
                          'нацист', 'свастик', 'педофил', 'лгбт', 'гомосексуал', 'казино',
                          'букмекер', 'азартн', 'алкогол', 'спирт', 'шампанск', 'коньяк',
                          'коньяч', 'ликёр', 'ликер', 'портвейн', 'самогон', 'сигар', 'табач',
                          'кальян', 'вейп', 'выпивк', 'рюмк', 'пивовар', 'пивн', 'курильщик',
                          'курени'];
const SMM_ZAPRET_NACHALO = ['водк', 'виски', 'пьян', 'табак', 'курить', 'курящ'];
const SMM_ZAPRET_TOCHNO  = ['вино', 'вином', 'пиво', 'пива', 'пиве', 'пивом'];
const SMM_ZAPRET_SOCHET  = ['бокал вина', 'бокалы вина', 'бутылка вина', 'бутылки вина',
                            'бутылку вина', 'стакан вина', 'рюмка вина', 'рюмку вина',
                            'глоток вина'];
const SMM_ZAPRET_ISKL    = ['пьянящ', 'табакерк'];

/**
 * Найти в тексте запрещённое к публикации. Отдаёт найденное слово или пустую
 * строку. Решает ОДИН помощник: его зовут и валидатор, и аудит, а вторая копия
 * условия разошлась бы молча (правила 33, 35, 45, 47).
 */
function smm_zapret_v_tekste(string $текст): string {
    $низ = mb_strtolower($текст);
    foreach (SMM_ZAPRET_SLOVA as $к) {
        if (mb_strpos($низ, $к) !== false) return $к;
    }
    foreach (SMM_ZAPRET_NACHALO as $к) {
        if (!preg_match_all('~\b' . preg_quote($к, '~') . '[\p{L}\-]*~u', $низ, $m)) continue;
        foreach ($m[0] as $слово) {
            $иск = false;
            foreach (SMM_ZAPRET_ISKL as $и) {
                if (mb_strpos($слово, $и) === 0) { $иск = true; break; }
            }
            if (!$иск) return $слово;
        }
    }
    foreach (SMM_ZAPRET_TOCHNO as $к) {
        if (preg_match('~\b' . preg_quote($к, '~') . '\b~u', $низ)) return $к;
    }
    foreach (SMM_ZAPRET_SOCHET as $с) {
        if (mb_strpos($низ, $с) !== false) return $с;
    }
    return '';
}

function smm_validate(string $body, string $textFull, string $вид = 'совет'): array {
    $err = [];
    $len = mb_strlen($body, 'UTF-8');

    /* У АФИШИ СВОЙ НИЖНИЙ ПРЕДЕЛ, И ОН НИЖЕ НАРОЧНО. Поздравление длиной в две
       тысячи знаков перестаёт быть поздравлением: там нужны повод, кто этот
       человек, одна живая деталь и доброе слово от центра. Разбор на две тысячи
       знаков - это уже другой вид поста. */
    $низ = $вид === 'афиша' ? SMM_BODY_MIN_AFISHA : SMM_BODY_MIN;
    if ($len < $низ) $err[] = "тело поста короткое: {$len} знаков, нужно от " . $низ;
    if ($len > SMM_BODY_MAX) $err[] = "тело поста длинное: {$len} знаков, предел " . SMM_BODY_MAX;

    if (!str_contains($textFull, 'РЕСУРСЫ И КОНТАКТЫ')) $err[] = 'потерян футер';

    /* ЖЁСТКАЯ ЦЕНЗУРА ТЕКСТА (слово владельца 19.10.2026): то, что запрещено к
       публикации в России, в ленту центра не уходит. */
    $__з = smm_zapret_v_tekste($body . ' ' . $textFull);
    if ($__з !== '') $err[] = 'запрещённое к публикации слово в тексте: ' . $__з;
    /* ТЕЛЕФОН СВЕРЯЕМ С НАСТРОЙКОЙ, А НЕ С ВПИСАННОЙ СТРОКОЙ. Здесь стоял
       формат «+7 (999) 504-88-99», и 14.10.2026 владелец сменил написание на
       +7(999)504-88-99: проверка забраковала бы КАЖДЫЙ пост словами «нет
       телефона центра», хотя телефон на месте. Мерка, сверяющая живое значение
       с вписанной копией, ломается ровно в день правки. */
    $__tel = trim((string) cfgv('org_phone', ''));
    if ($__tel !== '' && !str_contains($textFull, $__tel)) $err[] = 'нет телефона центра';

    /* Телефон центра один. Любой другой номер в теле — чужой или устаревший. */
    if (preg_match_all('~\+7\s*\(?\d{3}\)?[\s-]?\d{3}[\s-]?\d{2}[\s-]?\d{2}~u', $body, $m)) {
        foreach ($m[0] as $phone) {
            if (preg_replace('~\D~', '', $phone) !== '79995048899') $err[] = 'чужой телефон в тексте: ' . $phone;
        }
    }

    /* АНГЛИЙСКОЕ СЛОВО ПОСРЕДИ РУССКОЙ ФРАЗЫ.
     *
     * Замер ночи 15.10.2026: в готовой афише Лермонтова стояло «прожил
     * недолгую, but яркую жизнь» - модель уронила английский союз в середину
     * предложения, и пост лежал `ready` с нулём ошибок. В десять утра это ушло
     * бы в ВК и МАКС от имени центра.
     *
     * РИМСКИЕ ЦИФРЫ ПРОПУСКАЕМ: «XIX век» стоит в живом посте #21 и написан
     * латинскими буквами по самой своей природе. Остальная латиница в теле
     * поста это промах модели: названия площадок канон в тексте не упоминает,
     * а ссылки живут в футере, который проверяется отдельно. */
    if (preg_match_all('~(?<![A-Za-z])[A-Za-z]{2,}(?![A-Za-z])~u', $body, $m)) {
        $чужие = [];
        foreach (array_unique($m[0]) as $сл) {
            if (preg_match('~^[IVXLCDM]+$~', $сл)) continue;   // римские цифры
            $чужие[] = $сл;
        }
        if ($чужие) $err[] = 'латиница в русском тексте: ' . implode(', ', array_slice($чужие, 0, 5));
    }

    $lower = mb_strtolower($body, 'UTF-8');

    /* Telegram в постах не упоминаем — решение владельца. */
    foreach (['telegram', 'телеграм', 't.me'] as $w) {
        if (str_contains($lower, $w)) { $err[] = 'упоминание Telegram'; break; }
    }

    /* Обещание бесплатных благодарностей педагогам — только если выдача включена. */
    $freeOn = (int) setting('curator_free_enabled', '0') === 1;
    if (!$freeOn) {
        $hasThanks = str_contains($lower, 'благодарствен') || str_contains($lower, 'диплом куратора');
        $hasFree   = str_contains($lower, 'бесплатно') || str_contains($lower, 'без заказа');
        if ($hasThanks && $hasFree) {
            $err[] = 'обещание бесплатных благодарностей педагогам, а выдача выключена (curator_free_enabled=0)';
        }
    }

    /* ДИПЛОМ САМ НЕ ПРИХОДИТ — ОБЕЩАТЬ ЭТО НЕЛЬЗЯ.
     *
     * Автовыдача документов включена только у платных конкурсов
     * (cron/send_diplomas.php: c.is_paid=1). В бесплатных участник получает
     * РЕЗУЛЬТАТ — звание, — а сам диплом оформляет отдельно. Модель устойчиво
     * дописывает «официальный диплом придёт на указанную почту»: так вышло в
     * посте на 8 октября. Человек пришёл бы за документом, которого не получит, —
     * ровно та же история, что с бесплатными благодарностями педагогам. */
    $promisesDoc = preg_match('~(диплом|благодарност)\w*[^.]{0,80}(придёт|придет|приходит|поступит|отправим|пришлём|пришлем|получите)~ui', $body)
                || preg_match('~(придёт|придет|приходит|поступит)[^.]{0,60}(диплом|благодарност)~ui', $body);
    if ($promisesDoc && preg_match('~(почт|email|e-mail|кабинет)~ui', $body)) {
        $err[] = 'обещание, что документ придёт сам: в бесплатных конкурсах диплом оформляется отдельно';
    }

    /* Цена клуба в постах не пишется — решение владельца от 02.10.2026. */
    if (preg_match('~клуб~ui', $body) && preg_match('~\b\d{3,5}\s*(₽|руб)~ui', $body)) {
        $err[] = 'цена клуба в тексте поста';
    }

    /* КОНКУРСЫ ОНЛАЙН. Модель дописывает «приезжайте на площадку», «пройдите отбор»,
       «выступите на сцене перед жюри» — у центра ничего этого нет, участник
       записывает номер дома. Такой пост приводит человека не туда. */
    /* Слово ловится только без отрицания рядом: «без отборочного тура» и «никакого
       отбора нет» — правда про центр и писать так можно, а «пройдите отборочный
       тур» — выдумка. Первая версия проверки браковала как раз честные фразы. */
    foreach (['отборочн', 'отбор', 'приезжайт', 'очный тур', 'очного тура'] as $w) {
        $pos = mb_strpos($lower, $w, 0, 'UTF-8');
        if ($pos === false) continue;
        /* Окно берём по обе стороны одной строкой: отрицание стоит то перед словом
           («без отборочного тура»), то после («отбора нет»), а у слова в самом
           начале текста левого окна попросту не существует. */
        $from   = max(0, $pos - 45);
        $window = mb_substr($lower, $from, ($pos - $from) + mb_strlen($w, 'UTF-8') + 45, 'UTF-8');
        $denied = (bool) preg_match('~(без|нет|не\s|никак|минуя|не\s+нужн|не\s+требу|не\s+провод|не\s+предусмотр)~u', $window);
        if (!$denied) { $err[] = 'обещание того, чего у центра нет: ' . $w; break; }
    }

    /* Бот не гадает — пост тоже. Догадки о причинах запрещены (правило от 03.09). */
    foreach (['возможно, задержка', 'скорее всего банк', 'иногда бывает', 'проверим вручную'] as $w) {
        if (str_contains($lower, $w)) { $err[] = 'догадка вместо факта: ' . $w; break; }
    }

    return $err;
}

