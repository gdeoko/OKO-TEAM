/**
 * Рабочий ли это день для публикации. Воскресенье закрыто правилом владельца:
 * запись в чужой ленте в выходной читается как рассылка робота.
 */
function smm_is_work_day(string $date): bool {
    return (int) (new DateTime($date))->format('w') !== 0;
}

/**
 * ПУБЛИКУЕМ ЛИ В ЭТОТ СЛОТ. Один источник на открытие слотов и на публикацию.
 *
 * Воскресенье закрыто целиком: наружу в воскресенье не уходит ничего. Суббота
 * рабочая, но УКОРОЧЕННАЯ, 10:00-16:00 - значит вечернего поста в 17:00 в
 * субботу не бывает (слово владельца 19.10.2026). Проверка обязана стоять И в
 * открытии слотов, И в публикации: очередь отстаёт на трое суток, и в субботу
 * в 17:00 публикация взяла бы ЧУЖОЙ вечерний пост, которому слот не открывали.
 */
function smm_slot_rabochiy(string $date, int $hour): bool {
    if (!smm_is_work_day($date)) return false;
    if ((int) (new DateTime($date))->format('w') === 6 && $hour >= SMM_SLOT_EVENING) return false;
    return true;
}

/**
 * КОГДА ВЫХОДИТ АФИША ЭТОГО ПОВОДА. Дату повода не переносят: Вишневскую
 * нельзя поздравить в другой день. Но лента выходит только в свои слоты, а
 * 100-летие Вишневской (25.10.2026) приходится на воскресенье. Поздравить
 * ПОЗЖЕ нельзя - опоздавшее поздравление хуже отсутствующего (урок правила
 * 43), - поэтому афиша уходит в ближайшее рабочее утро ДО повода, а в тексте
 * стоят обе даты. Дальше трёх дней не отступаем: поздравление за неделю это
 * уже не повод.
 */
function smm_slot_povoda(string $поводДата, int $назадДней = 3): ?array {
    if (smm_slot_rabochiy($поводДата, SMM_SLOT_MORNING)) {
        return ['date' => $поводДата, 'hour' => SMM_SLOT_MORNING, 'сдвиг' => 0];
    }
    $d = new DateTime($поводДата);
    for ($i = 1; $i <= $назадДней; $i++) {
        $дата = (clone $d)->modify("-{$i} day")->format('Y-m-d');
        if (!smm_slot_rabochiy($дата, SMM_SLOT_MORNING)) continue;
        return ['date' => $дата, 'hour' => SMM_SLOT_MORNING, 'сдвиг' => $i];
    }
    return null;
}

/**
 * ПОВОД, КОТОРЫЙ ОБСЛУЖИВАЕТ ЭТОТ СЛОТ, с обеими датами внутри: `дата_повода`
 * и `выход`. Свой повод дня сильнее сдвинутого: в день рождения поздравляют в
 * сам день, а двух афиш в один слот не бывает.
 */
function smm_povod_slota(string $date, int $назадДней = 3): array {
    if (!function_exists('smm_kal_повод')) return [];
    $свой = smm_kal_повод($date);
    if ($свой && smm_slot_rabochiy($date, SMM_SLOT_MORNING)) {
        $свой['дата_повода'] = $date;
        $свой['выход']       = $date;
        return $свой;
    }
    $d = new DateTime($date);
    for ($i = 1; $i <= $назадДней; $i++) {
        $дата = (clone $d)->modify("+{$i} day")->format('Y-m-d');
        $п = smm_kal_повод($дата);
        if (!$п) continue;
        $слот = smm_slot_povoda($дата, $назадДней);
        if (!$слот || (string) $слот['date'] !== $date) continue;
        $п['дата_повода'] = $дата;
        $п['выход']       = $date;
        return $п;
    }
    return [];
}

/** Дата словами для текста афиши: «25 октября». */
function smm_data_slovami(string $ymd): string {
    $м = ['', 'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
          'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
    $t = strtotime($ymd);
    if (!$t) return $ymd;
    return (int) date('j', $t) . ' ' . (string) ($м[(int) date('n', $t)] ?? '');
}

/**
 * Предупреждение о сдвинутом дне выхода; у повода в свой день пусто.
 * Без него афиша, уходящая накануне, написала бы «сегодня» про чужой день.
 */
function smm_afisha_sdvig_note(array $повод): string {
    $пд = (string) ($повод['дата_повода'] ?? '');
    $вх = (string) ($повод['выход'] ?? '');
    if ($пд === '' || $вх === '' || $пд === $вх) return '';
    return 'Повод приходится на ' . smm_data_slovami($пд) . ', а эта афиша выходит '
         . smm_data_slovami($вх) . ": в день повода лента центра не выходит.\n"
         . 'Поэтому НЕ пиши «сегодня», «в этот день» и «ровно сто лет назад в этот день»: '
         . 'назови дату повода словами (' . smm_data_slovami($пд)
         . ") и поздравь заранее.\n\n";
}

/** Строка «когда» для задания афиши: одна дата или обе. */
function smm_afisha_kogda(array $повод, string $кто): string {
    $нота = smm_afisha_sdvig_note($повод);
    if ($нота === '') return 'Сегодня ' . $кто . ".\n\n";
    return 'ПОВОД: ' . $кто . ".\n" . $нота;
}

/**
 * Слоты, которые нужно заполнить на ближайшие дни. Конвейер смотрит вперёд, а не
 * в текущий час: картинка генерируется несколько минут, и готовить пост в момент
 * публикации — значит однажды опоздать и оставить день пустым.
 */
function smm_pending_slots(int $daysAhead = 3, int $поводДней = 7): array {
    $slots = [];
    $now   = new DateTime('now');
    for ($d = 0; $d <= $daysAhead; $d++) {
        $day = (clone $now)->modify("+{$d} day");
        $date = $day->format('Y-m-d');
        foreach ([SMM_SLOT_MORNING, SMM_SLOT_EVENING] as $h) {
            if (!smm_slot_rabochiy($date, $h)) continue;               // вс и субботний вечер
            if ($d === 0 && (int) $now->format('G') >= $h) continue;   // час уже прошёл
            $exists = scalar("SELECT id FROM smm_posts WHERE slot_date = ? AND slot_hour = ?", [$date, $h]);
            if (!$exists) $slots[] = ['date' => $date, 'hour' => $h];
        }
    }
    /* У АФИШИ ЗАПАС БОЛЬШЕ, И ЭТО НЕ ПРИХОТЬ. Обычный пост можно собрать хоть
       за час до слота, а поздравление привязано к дате намертво: если именно в
       эти сутки мозг упрётся в квоту, афиша сорвётся и повод уйдёт на год.
       Поэтому дни с поводом открываются на неделю вперёд - и только утренний
       слот, чтобы не занимать весь день заранее. */
    if ($поводДней > $daysAhead && function_exists('smm_kal_повод')) {
        /* ДЕНЬ ВЫХОДА БЫВАЕТ РАНЬШЕ ПОВОДА: в нерабочий день лента не выходит,
           а поздравление не ждёт, и афиша уходит утром ДО повода
           (smm_slot_povoda). Поэтому идём от первого же дня: сдвинутый слот
           может оказаться и внутри близкого окна, уже открытого выше. */
        $открыт  = [];
        foreach ($slots as $s) $открыт[$s['date'] . '|' . $s['hour']] = true;
        $сегодня = $now->format('Y-m-d');
        for ($d = 1; $d <= $поводДней; $d++) {
            $поводДата = (clone $now)->modify("+{$d} day")->format('Y-m-d');
            if (!smm_kal_повод($поводДата)) continue;
            $слот = smm_slot_povoda($поводДата);
            if (!$слот) continue;
            $дата = (string) $слот['date'];
            $час  = (int) $слот['hour'];
            if ($дата < $сегодня) continue;
            if ($дата === $сегодня && (int) $now->format('G') >= $час) continue;
            if (isset($открыт[$дата . '|' . $час])) continue;
            if (scalar("SELECT id FROM smm_posts WHERE slot_date = ? AND slot_hour = ?",
                       [$дата, $час])) continue;
            $slots[] = ['date' => $дата, 'hour' => $час];
            $открыт[$дата . '|' . $час] = true;
        }
    }

    return $slots;
}


/**
 * Освобождает слот в день с поводом, если очередь забила его советами.
 *
 * ПОЧЕМУ БЕЗ ЭТОГО ПОВОД ТЕРЯЕТСЯ МОЛЧА. У пары (slot_date, slot_hour) в базе
 * стоит уникальность: в слот ложится ровно один пост. Подготовка смотрит на три
 * дня вперёд и набивает очередь советами, и к приходу повода оба слота его дня
 * уже заняты - положить афишу НЕКУДА, и никто об этом не скажет. Ровно так и
 * вышло 13.10.2026: очередь была забита до 16.10, а 15.10 Лермонтову 212 лет.
 * Слот тогда освободила сессия руками, и это не починка: следующий повод
 * (100-летие Вишневской 25.10) потерялся бы так же.
 *
 * ОСВОБОЖДАЕТСЯ УТРЕННИЙ СЛОТ, И ЭТО ДАЁТ АФИШЕ ВТОРОЙ ШАНС. Отбор публикации
 * берёт афишу по ДАТЕ, а не по часу: стоящая на утреннем слоте, она выйдет
 * вечером того же дня, если утром что-то сорвалось. На вечернем слоте такого
 * запаса нет.
 *
 * Совет при этом не теряется и не переписывается: едет целиком, со своим
 * текстом, кадром и возрастом, на ближайший свободный слот - темы у нас не
 * новостные, и день выхода совету безразличен.
 *
 * Возвращает описания переносов для журнала.
 */
function smm_osvobodit_pod_povod(int $поводДней = 7): array {
    if (!function_exists('smm_kal_повод')) return [];
    smm_migrate();
    $now = new DateTime('now');
    $сделано = [];

    /* С завтрашнего дня: сегодняшние слоты уже прошли или опубликованы, и
       переносить из них нечего. */
    for ($d = 1; $d <= $поводДней; $d++) {
        $поводДата = (clone $now)->modify("+{$d} day")->format('Y-m-d');
        if (!smm_kal_повод($поводДата)) continue;

        /* ОСВОБОЖДАЕМ УТРО ДНЯ ВЫХОДА, А НЕ ДНЯ ПОВОДА: повод, попавший на
           нерабочий день, выходит утром ДО него. У 100-летия Вишневской
           (25.10.2026, воскресенье) день выхода это суббота 24.10. */
        $слот = smm_slot_povoda($поводДата);
        if (!$слот) {
            $сделано[] = 'повод ' . $поводДата . ': рабочего утра рядом нет — афиша не встанет';
            continue;
        }
        $date = (string) $слот['date'];
        if ($date < $now->format('Y-m-d')) continue;

        /* Афиша на этот день уже есть - место занято ею самой. */
        if (scalar("SELECT id FROM smm_posts WHERE slot_date = ? AND kind = 'афиша'", [$date])) continue;

        /* Утренний слот свободен - подготовка поставит афишу прямо в него. */
        $пост = one(
            "SELECT id, status, kind, topic FROM smm_posts WHERE slot_date = ? AND slot_hour = ?",
            [$date, SMM_SLOT_MORNING]
        );
        if (!$пост) continue;

        /* Опубликованный не трогаем никогда: он уже у людей, и перенос
           переписал бы историю. Афиша тогда обойдётся вечерним слотом. */
        if ((string) $пост['status'] === 'published') continue;

        /* КУДА ПЕРЕСЕЛИТЬ СОВЕТ. Сначала пробуем вечерний слот ТОГО ЖЕ ДНЯ:
           когда он свободен, это обмен внутри дня - ни одного нового слота, ни
           одной лишней генерации, а афиша переезжает с вечера на утро и получает
           свой второй шанс. Только если вечер тоже занят, совет уезжает вперёд. */
        $куда = null;
        if (smm_slot_rabochiy($date, SMM_SLOT_EVENING)
            && !scalar("SELECT id FROM smm_posts WHERE slot_date = ? AND slot_hour = ?",
                       [$date, SMM_SLOT_EVENING])) {
            $куда = ['date' => $date, 'hour' => SMM_SLOT_EVENING];
        } else {
            $куда = smm_свободный_слот($date);
        }
        if (!$куда) {
            $сделано[] = 'день ' . $date . ' занят советами, а свободного слота впереди нет — афиша не встанет';
            continue;
        }

        update('smm_posts', ['slot_date' => $куда['date'], 'slot_hour' => $куда['hour']],
               'id=:id', ['id' => (int) $пост['id']]);
        $сделано[] = 'под повод ' . $поводДата . ' освобождён утренний слот ' . $date
                   . ': совет #' . (int) $пост['id']
                   . ($куда['date'] === $date ? ' сдвинут на вечер того же дня' : ' переехал на ' . $куда['date'])
                   . ' ' . sprintf('%02d:00', (int) $куда['hour']);
    }

    return $сделано;
}


/**
 * Ближайший свободный слот после названной даты.
 *
 * Утренний слот дня с поводом намеренно пропускается: он держится для афиши, и
 * занять его советом значит через час снова его освобождать.
 */
function smm_свободный_слот(string $после, int $пределДней = 21): ?array {
    $day = new DateTime($после);
    for ($d = 1; $d <= $пределДней; $d++) {
        $date = (clone $day)->modify("+{$d} day")->format('Y-m-d');
        if (!smm_is_work_day($date)) continue;
        foreach ([SMM_SLOT_MORNING, SMM_SLOT_EVENING] as $h) {
            if (!smm_slot_rabochiy($date, $h)) continue;
            /* Утро, которое обслуживает повод (свой или сдвинутый), советом не
               занимаем: через час его пришлось бы освобождать снова. */
            if ($h === SMM_SLOT_MORNING && smm_povod_slota($date)) continue;
            if (!scalar("SELECT id FROM smm_posts WHERE slot_date = ? AND slot_hour = ?", [$date, $h])) {
                return ['date' => $date, 'hour' => $h];
            }
        }
    }
    return null;
}

/** Пост, который пора публиковать прямо сейчас. */
function smm_due_post(): ?array {
    $now  = new DateTime('now');
    $date = $now->format('Y-m-d');
    $hour = (int) $now->format('G');

    /* ДВА ПОСТА В ДЕНЬ — ЗНАЧИТ РОВНО ДВА, В СВОИ ЧАСЫ.
     *
     * Задание проверяется каждые десять минут, чтобы не потерять публикацию из-за
     * занятого сервера. Но «пора публиковать» и «можно публиковать ещё раз» —
     * разные вопросы, и пока их путали, выходило вот что: 7 октября в очереди
     * лежали два вчерашних поста и один сегодняшний, и конвейер выпустил их в
     * 09:00, 09:10 и 10:00 — три штуки за час вместо одного в десять.
     *
     * Поэтому решает не наличие готового поста, а СЛОТ: утренний и вечерний.
     * В каждый слот уходит один пост и только один; занят слот — до следующего
     * конвейер молчит, сколько бы готового ни лежало. Отставшие посты разойдутся
     * сами, по одному за слот. */
    $slot = $hour >= SMM_SLOT_EVENING ? SMM_SLOT_EVENING
          : ($hour >= SMM_SLOT_MORNING ? SMM_SLOT_MORNING : 0);
    if ($slot === 0) return null;                       // до утреннего часа не публикуем

    /* СУББОТА УКОРОЧЕННАЯ, ВЕЧЕРНЕГО ПОСТА В НЕЙ НЕТ. Проверка нужна именно
       здесь, а не только в открытии слотов: очередь отстаёт, и в субботу в
       17:00 отбор взял бы ЧУЖОЙ вечерний пост, которому слот не открывали. */
    if (!smm_slot_rabochiy($date, $slot)) return null;

    $taken = (int) (scalar(
        "SELECT COUNT(*) FROM smm_posts
          WHERE status = 'published' AND date(published_at) = ?
            AND CAST(strftime('%H', published_at) AS INTEGER) >= ?",
        [$date, $slot]
    ) ?? 0);
    if ($taken > 0) return null;                        // в этот слот уже публиковали

    /* АФИША ИДЁТ ТОЛЬКО В СВОЙ ДЕНЬ, И В ЭТОМ ОНА ПРОТИВОПОЛОЖНА СОВЕТУ.
     *
     * Правило ниже («берём самый старый») писалось под советы, и для них оно
     * верно: тема не новостная, вчерашний текст не устаревает. Но очередь
     * ОТСТАЁТ — на 13.10.2026 в ней лежали готовые посты с датой слота 12.10,
     * потому что лента неделю стояла, а догонять её нельзя: два поста в день
     * это слово владельца, и отставание уже не рассасывается. При таком
     * отставании поздравление с днём рождения Лермонтова, собранное на слот
     * 15.10, ушло бы в ленту 17-18 октября — то есть центр поздравил бы с
     * опозданием на два дня, публично и от своего имени.
     *
     * Поэтому афиша живёт по другому закону: она забирает ближайший слот
     * СВОЕГО дня вперёд всей очереди, а если день прошёл — не выходит вовсе
     * (её снимает smm_afisha_prosrochit()). Советы ждут столько, сколько надо;
     * повод не ждёт. */
    $afisha = one(
        "SELECT * FROM smm_posts
          WHERE status = 'ready' AND attempts < 5
            AND kind = 'афиша' AND slot_date = ?
       ORDER BY slot_hour LIMIT 1",
        [$date]
    );
    if ($afisha) return $afisha;

    /* Внутри слота берём самый старый невыпущенный: вчерашний текст не устаревает,
       темы у нас не новостные, и очередь должна идти по порядку. Афиши из этой
       очереди исключены: у них свой закон выше, и афиша чужого дня не имеет
       права занять слот обычного поста. */
    $row = one(
        "SELECT * FROM smm_posts
          WHERE status = 'ready' AND attempts < 5
            AND (kind IS NULL OR kind = '' OR kind <> 'афиша')
            AND (slot_date < ? OR (slot_date = ? AND slot_hour <= ?))
       ORDER BY slot_date, slot_hour LIMIT 1",
        [$date, $date, $hour]
    );
    return $row ?: null;
}


/**
 * Снимает афиши, чей день прошёл.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ УБОРКА. Афиша не имеет права выйти задним числом (см.
 * smm_due_post), а значит сама она из очереди уже не уйдёт и будет висеть
 * «в очереди» вечно, путая и пульт, и подсчёт занятых слотов. Повод при этом
 * потерян — Чайковского нельзя поздравить завтра, — и об этом владелец должен
 * узнать словами, а не из тишины: собрать афишу заново к той же дате можно
 * только через год.
 *
 * Возвращает описания снятых, чтобы крон написал их в журнал и в Телеграм.
 */
function smm_afisha_prosrochit(): array {
    smm_migrate();
    $date = (new DateTime('now'))->format('Y-m-d');
    $rows = all(
        "SELECT id, slot_date, slot_hour, povod, person FROM smm_posts
          WHERE kind = 'афиша' AND status IN ('ready','draft','failed')
            AND slot_date < ?
       ORDER BY slot_date, slot_hour",
        [$date]
    );
    $снятые = [];
    foreach ($rows as $r) {
        update('smm_posts', [
            'status' => 'skipped',
            'error'  => 'повод прошёл ' . (string) $r['slot_date'] . ' — афиша задним числом не публикуется',
        ], 'id=:id', ['id' => (int) $r['id']]);
        $снятые[] = '#' . (int) $r['id'] . ' ' . (string) $r['slot_date']
                  . ' — ' . ((string) $r['povod'] !== '' ? (string) $r['povod'] : (string) $r['person']);
    }
    return $снятые;
}


