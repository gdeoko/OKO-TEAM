/**
 * Возрастная группа следующего поста.
 *
 * ГЛАВНОЕ ПРАВИЛО: два поста одного дня - из РАЗНЫХ половин. Так в каждом дне
 * есть и детская тема, и взрослая, и это не зависит от удачи жребия: ровная
 * случайная ротация по шести группам нет-нет да даст два детских поста в день, а
 * просили обратного. Внутри половины берётся то, чего не было в последних трёх
 * постах.
 */
function smm_pick_age(string $slotDate, int $slotHour): string {
    $все     = array_keys(SMM_AGES);
    $младшие = array_values(array_filter($все, static fn($a) => (int) SMM_AGES[$a]['млад'] === 1));
    $старшие = array_values(array_filter($все, static fn($a) => (int) SMM_AGES[$a]['млад'] === 0));

    $сосед = (string) (scalar(
        "SELECT age_group FROM smm_posts
          WHERE slot_date = ? AND slot_hour <> ? AND COALESCE(age_group,'') <> '' LIMIT 1",
        [$slotDate, $slotHour]
    ) ?? '');

    if ($сосед !== '' && isset(SMM_AGES[$сосед])) {
        $пул = ((int) SMM_AGES[$сосед]['млад'] === 1) ? $старшие : $младшие;
    } else {
        /* Соседа нет (первый пост дня) - берём половину, которой меньше в
           последних шести: иначе лента кренится неделями. */
        $последние = array_column(all(
            "SELECT age_group FROM smm_posts WHERE COALESCE(age_group,'') <> ''
              ORDER BY slot_date DESC, slot_hour DESC LIMIT 6"
        ), 'age_group');
        $млад = 0;
        foreach ($последние as $a) if (isset(SMM_AGES[$a]) && (int) SMM_AGES[$a]['млад'] === 1) $млад++;
        $стар = count($последние) - $млад;
        if ($млад > $стар)      $пул = $старшие;
        elseif ($стар > $млад)  $пул = $младшие;
        else                    $пул = array_merge($младшие, $старшие);
    }

    $свежие3 = array_column(all(
        "SELECT age_group FROM smm_posts WHERE COALESCE(age_group,'') <> ''
          ORDER BY slot_date DESC, slot_hour DESC LIMIT 3"
    ), 'age_group');
    $свежие = array_values(array_filter($пул, static fn($a) => !in_array($a, $свежие3, true)));
    if (!$свежие) $свежие = $пул;

    return $свежие[array_rand($свежие)];
}

