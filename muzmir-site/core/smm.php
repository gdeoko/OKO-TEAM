/**
 * Выбрать значение оси так, чтобы оно не повторяло последние заходы.
 *
 * ПАМЯТЬ ЧИТАЕТСЯ ИЗ САМИХ ПОСТОВ, и хранить отдельно нечего: ось лежит в своей
 * колонке. Выбор ДЕТЕРМИНИРОВАН по слоту - повторный заход того же слота
 * (переписывание очереди, правило 70в) даёт то же значение и не ломает то, что
 * уже собрано. Все значения оказались в памяти - берём весь набор, иначе на
 * восьмом посте подряд ось отдала бы пустоту.
 */
function smm_pick_os(string $колонка, array $набор, string $slotDate, int $slotHour,
                     int $кромеId = 0, int $память = 4): string {
    $ключи = array_keys($набор);
    if (!$ключи) return '';
    $были = array_column(all(
        "SELECT {$колонка} FROM smm_posts WHERE COALESCE({$колонка},'') <> '' AND id <> ?
          ORDER BY slot_date DESC, slot_hour DESC LIMIT " . max(1, $память),
        [$кромеId]
    ), $колонка);
    $свободные = array_values(array_diff($ключи, $были));
    if (!$свободные) $свободные = $ключи;
    return (string) $свободные[abs(crc32($slotDate . '|' . $slotHour)) % count($свободные)];
}

/**
 * Какой пост в этом слоте и по какому поводу.
 *
 * АФИША ГЛАВНЕЕ ОЧЕРЕДИ: дата не переносится, Чайковскому нельзя «поздравить
 * завтра». Но афиша в день одна - второй слот того же дня забирает обычный
 * пост, иначе лента в такой день говорит только про одного человека.
 *
 * СОВЕТ И ИСТОРИЯ ЧЕРЕДУЮТСЯ ЧЕРЕЗ ОДИН - правка владельца 15.10.2026: «что бы
 * контент в постах был увлекательным и интересным». Прежнее правило («история не
 * чаще раза в три поста») давало на 28 постов 18 советов и 7 историй, то есть
 * лента почти целиком состояла из советов. Теперь история идёт, если ею не был
 * ПРЕДЫДУЩИЙ пост, - выходит примерно половина на половину. Двух историй в один
 * день по-прежнему не бывает: иначе день целиком говорит о прошлом.
 */
function smm_pick_kind(string $slotDate, int $slotHour): array {
    /* ПОВОД БЕРЁМ У СЛОТА, А НЕ У КАЛЕНДАРЯ НАПРЯМУЮ: повод, попавший на
       нерабочий день, обслуживает утро ДО него (smm_povod_slota), и обе даты
       приезжают внутри самого повода. */
    $повод = smm_povod_slota($slotDate);

    $афишаВДень = (string) (scalar(
        "SELECT kind FROM smm_posts WHERE slot_date = ? AND slot_hour <> ? AND kind = 'афиша' LIMIT 1",
        [$slotDate, $slotHour]
    ) ?? '');

    /* АФИША ТОЛЬКО В УТРЕННЕМ СЛОТЕ (правка владельца 19.10.2026): вечер
       принадлежит совету или истории, и поздравление туда не уходит. Без
       проверки часа вечерний слот тоже получал афишу, когда утреннего поста в
       базе ещё нет: `$афишаВДень` пуст, и условие проходило. Замерено на
       04.11.2026 (День народного единства) до правки: 10:00 афиша и 17:00
       афиша - то есть день целиком о поводе, чего владелец не просил. */
    if ($повод && $slotHour <= SMM_SLOT_MORNING && $афишаВДень === '') {
        return ['вид' => 'афиша', 'повод' => $повод];
    }

    return smm_vid_po_slotu($slotDate, $slotHour) + ['повод' => []];
}

/**
 * ВИД И СЮЖЕТ ПОСТА ПО ЕГО МЕСТУ В ОЧЕРЕДИ - ОДИН ИСТОЧНИК НА ВЕСЬ КОНВЕЙЕР.
 *
 * Чередование смотрит ПРЕДЫДУЩИЙ ПО СЛОТУ пост, а не «последний заведённый».
 * Для нового слота это одно и то же, а для переписывания готовой очереди
 * (`cron/smm_perepisat.php`, слово владельца 15.10.2026) - нет: там слоты
 * прошлые, и самый свежий пост им не сосед вовсе. Одна мерка на оба случая,
 * потому что копия правила разошлась бы молча (правила 33, 35, 45, 47, 56а,
 * 64).
 *
 * `$кромеId` исключает сам переписываемый пост: иначе он спорит сам с собой -
 * видит свой же вид соседом и никогда его не меняет.
 */
function smm_vid_po_slotu(string $slotDate, int $slotHour, int $кромеId = 0): array {
    /* УТРО - ИСТОРИЯ ИЛИ ЗНАМЕНАТЕЛЬНАЯ ДАТА, ВЕЧЕР - СОВЕТ. Правка владельца
       19.10.2026: «В следующих запланированных публикациях утром в 10.00
       публикация должна быть не выдуманной интересной историей из мира культуры
       и искусства… или освещение знаменательной даты… Вечерняя публикация должна
       быть каким то нужным советом участникам, преподавателям, педагогам,
       родителям… или не выдуманная интересная история».
       Афишу выбирает `smm_pick_kind()` выше: она привязана к календарю, и
       отменить её нельзя. Здесь остаётся вторая половина утреннего правила.
       ВЕЧЕР ОТДАЁТ ИСТОРИЮ, ЕСЛИ УТРО ЗАБРАЛА АФИША: иначе в день с поводом
       лента не рассказывает ни одной истории вовсе, а владелец разрешил вечером
       и то, и другое. */
    if ($slotHour <= SMM_SLOT_MORNING) {
        return ['вид' => 'история'] + smm_syuzhet_po_krugu($кромеId);
    }
    $утро = (string) (scalar(
        "SELECT kind FROM smm_posts WHERE slot_date = ? AND slot_hour = ? AND id <> ? LIMIT 1",
        [$slotDate, SMM_SLOT_MORNING, $кромеId]
    ) ?? '');
    if ($утро === 'афиша') return ['вид' => 'история'] + smm_syuzhet_po_krugu($кромеId);
    return ['вид' => 'совет', 'подвид' => ''];
}

/**
 * Сюжет истории по кругу: человек, прошлое мира музыки, сегодняшний день.
 * Счёт идёт по уже заведённым историям, поэтому круг продолжается и после
 * перезапуска, и хранить отдельно ничего не нужно.
 */
function smm_syuzhet_po_krugu(int $кромеId = 0): array {
    $ключи = array_keys(SMM_SYUZHETY);
    $было  = (int) (scalar("SELECT COUNT(*) FROM smm_posts WHERE kind = 'история' AND id <> ?",
                           [$кромеId]) ?? 0);
    return ['подвид' => $ключи[$было % count($ключи)]];
}

/** «101 год», «105 лет», «187 лет» - падеж числительного, а не «101 лет». */
function smm_let(int $n): string {
    $n = abs($n);
    $сто = $n % 100;
    $дес = $n % 10;
    if ($сто >= 11 && $сто <= 14) return $n . ' лет';
    if ($дес === 1) return $n . ' год';
    if ($дес >= 2 && $дес <= 4) return $n . ' года';
    return $n . ' лет';
}

