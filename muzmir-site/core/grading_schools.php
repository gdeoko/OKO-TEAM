/** Коллективный ли состав: для хора и ансамбля добавляется своя система. */
function gs_is_group(string $formation): bool {
    $f = mb_strtolower(trim($formation));
    if ($f === '') return false;
    foreach (['ансамбл', 'хор', 'коллектив', 'группа', 'дуэт', 'трио', 'квартет', 'квинтет', 'секстет'] as $w) {
        if (str_contains($f, $w)) return true;
    }
    return false;
}

/** Одна система судейства, развёрнутая в текст промпта. */
function gs_render(array $s, string $head): string {
    $L = [];
    $L[] = $head;
    $L[] = '  Эталон: ' . $s['name'] . '.';
    $L[] = '  Из чего складывается профессиональная оценка:';
    foreach ($s['parts'] as $p) $L[] = '    • ' . $p;
    $L[] = '  Что значат уровни на международной шкале (наши баллы приведены к ней):';
    foreach ($s['levels'] as $l) $L[] = '    • ' . $l;
    if (!empty($s['rules'])) {
        $L[] = '  Правила этой школы, которые обязаны отразиться в оценке:';
        foreach ($s['rules'] as $r) $L[] = '    • ' . $r;
    }
    return implode("\n", $L);
}

/** Блок для промпта: система судейства, по которой оценивают это направление в мире. */
function gs_block(string $nomination, string $subgroup, string $formation = ''): string {
    $fam = gs_family($nomination, $subgroup);
    $all = gs_schools();
    $s   = $all[$fam] ?? $all['general'];

    $out = [gs_render($s, 'ПО КАКОЙ СИСТЕМЕ СУДЯТ ЭТО НАПРАВЛЕНИЕ В МИРЕ')];

    // Поющий коллектив оценивается ещё и как коллектив: строй, слитность,
    // баланс. Пропустить это значит разобрать хор как группу солистов.
    if (gs_is_group($formation) && in_array($fam, ['academic_voice', 'folk', 'popular_music'], true)) {
        $out[] = gs_render($all['choir_add'], 'СОСТАВ КОЛЛЕКТИВНЫЙ — ДОБАВЛЯЕТСЯ АНСАМБЛЕВАЯ СИСТЕМА');
    }
    return implode("\n\n", $out);
}
