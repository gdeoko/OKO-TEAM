/** Семья, к которой относится направление. Одна система судейства на семью. */
function gs_family(string $nomination, string $subgroup): string {
    $s = mb_strtolower(trim($subgroup));
    $n = mb_strtolower(trim($nomination));
    $map = [
        'академический вокал' => 'academic_voice',
        'народный вокал'      => 'folk',
        'эстрадный вокал'     => 'popular_music',
        'джазовый вокал'      => 'popular_music',
        'фортепиано'          => 'instrument',
        'струнные'            => 'instrument',
        'духовые'             => 'instrument',
        'народные инструменты' => 'folk_instrument',
        'ударные'             => 'instrument',
        'народный танец'      => 'folk',
        'эстрадный танец'     => 'dance',
        'современный танец'   => 'dance',
        'бальный танец'       => 'ballroom',
        'драматический театр' => 'theatre',
        'музыкальный театр'   => 'theatre',
        'театр кукол'         => 'puppetry',
        'проза'               => 'word',
        'поэзия'              => 'word',
        'авторское произведение' => 'word',
        'живопись'            => 'visual',
        'графика'             => 'visual',
        'скульптура'          => 'visual',
        'декоративно-прикладное искусство' => 'visual',
        'фотография'          => 'photo',
        'видеоарт'            => 'screen',
        'клип'                => 'screen',
        'короткий метр'       => 'screen',
        'акробатика'          => 'acro',
        'гимнастика'          => 'acro',
        'жонглирование'       => 'juggling',
        'клоунада'            => 'clown',
        'иллюзия'             => 'magic',
        'дрессура'            => 'animals',
    ];
    if (isset($map[$s])) return $map[$s];
    // Направление не указано: определяем по номинации, иначе общий случай.
    if (str_contains($n, 'вокал'))        return 'academic_voice';
    if (str_contains($n, 'инструмент'))   return 'instrument';
    if (str_contains($n, 'хореограф'))    return 'dance';
    if (str_contains($n, 'театр'))        return 'theatre';
    if (str_contains($n, 'слов'))         return 'word';
    if (str_contains($n, 'изобразит') || str_contains($n, 'декоратив')) return 'visual';
    if (str_contains($n, 'цирк'))         return 'clown';
    if (str_contains($n, 'фото'))         return 'photo';
    if (str_contains($n, 'видео') || str_contains($n, 'кино')) return 'screen';
    return 'general';
}

