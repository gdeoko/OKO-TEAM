<?php
/**
 * ЧТО ЧАТ-БОТУ РАЗРЕШЕНО ГОВОРИТЬ УЧАСТНИКУ ПРО ЕГО РЕЗУЛЬТАТ.
 *
 * Повод для этого файла простой и неприятный: бот назвал участнице звание по
 * длинному бесплатному конкурсу «Величие России» за две недели до оглашения.
 * Жюри проставило оценку в админке, оценка легла в applications.result — и она
 * же ушла в подсказку модели вместе со словами «покажи результат». Модель
 * послушалась. Итог: человек узнал итог раньше публикации, а публикация 28-го
 * числа со списком и рассылкой потеряла смысл. Восстановить это нельзя: сказанное
 * не забирается назад.
 *
 * Правило центра, из которого всё следует:
 *   участник узнаёт результат ровно тогда, когда результат ПРИШЁЛ К НЕМУ.
 *   Короткий конкурс — письмо на почту из заявки (applications.result_sent_at).
 *   Длинный  конкурс — публикация списка (competitions.results_published_at).
 * Всё, что раньше этого момента, для участника не существует, кем бы он ни
 * спрашивал и как бы ни настаивал. То же самое уже сделано в личном кабинете
 * (templates/site/pages/cabinet.php) и в лестнице статусов (core/app_status.php) —
 * здесь ровно те же условия, чтобы кабинет, админка и бот говорили одно и то же.
 *
 * Файл отвечает на три вопроса:
 *   1. Что по этой заявке можно раскрыть — chat_gate_app();
 *   2. Что сказать вместо результата (дата, очередь, где смотреть) — оно же, поле 'say';
 *   3. Как поймать модель за руку, если она всё-таки назовёт звание — chat_gate_guard().
 *
 * Третий пункт — не паранойя. Промпт это просьба, а не запрет: языковая модель
 * может вывести звание из общей эрудиции, из истории диалога или просто ошибиться.
 * Поэтому последний рубеж — сверка готового ответа с реальными скрытыми оценками
 * этого участника. Совпало — ответ подменяется честным «когда и где будет».
 */
declare(strict_types=1);

/** Сколько рабочих дней от подачи до результата в коротком конкурсе (обычный участник). */
const CHAT_GATE_WORKDAYS = 5;

/** Русская дата «28 августа 2026». */
function chat_gate_date_ru(string $dt): string {
    $ts = strtotime(trim($dt));
    if (!$ts) return '';
    $m = [1 => 'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
          'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
    return (int) date('j', $ts) . ' ' . $m[(int) date('n', $ts)] . ' ' . date('Y', $ts);
}

/** «через 3 дня» / «завтра» / «сегодня» — сколько ждать от сегодняшнего дня. */
function chat_gate_in_days(string $dt): string {
    $ts = strtotime(trim($dt));
    if (!$ts) return '';
    $d = (int) floor((strtotime(date('Y-m-d', $ts)) - strtotime(date('Y-m-d'))) / 86400);
    if ($d < 0)  return '';
    if ($d === 0) return 'сегодня';
    if ($d === 1) return 'завтра';
    $last = $d % 10; $t2 = $d % 100;
    $word = ($last === 1 && $t2 !== 11) ? 'день' : (($last >= 2 && $last <= 4 && ($t2 < 12 || $t2 > 14)) ? 'дня' : 'дней');
    return 'через ' . $d . ' ' . $word;
}

/**
 * МЕСТО ЗАЯВКИ В ОЧЕРЕДИ НА АТТЕСТАЦИЮ.
 *
 * Владелец просил: по короткому конкурсу бот должен не отмахиваться «ожидайте», а
 * находить очередь и называть срок. Очередь считаем честно — сколько ещё не
 * разобранных заявок этого конкурса стоит перед этой (поданных раньше). Отклонённые
 * не в счёт: они из очереди вышли.
 *
 * @return array{pos:int, total:int}  pos=0 — заявка уже разобрана, очереди нет
 */
function chat_gate_queue(array $a): array {
    $cid = (int) ($a['competition_id'] ?? 0);
    $id  = (int) ($a['id'] ?? 0);
    if (!$cid || !$id) return ['pos' => 0, 'total' => 0];
    if (trim((string) ($a['result'] ?? '')) !== '') return ['pos' => 0, 'total' => 0];
    try {
        $pos = (int) scalar(
            "SELECT COUNT(*) FROM applications
              WHERE competition_id=? AND COALESCE(result,'')='' AND COALESCE(status,'')<>'rejected' AND id<=?",
            [$cid, $id]);
        $total = (int) scalar(
            "SELECT COUNT(*) FROM applications
              WHERE competition_id=? AND COALESCE(result,'')='' AND COALESCE(status,'')<>'rejected'",
            [$cid]);
    } catch (\Throwable $e) { return ['pos' => 0, 'total' => 0]; }
    return ['pos' => $pos, 'total' => $total];
}

/**
 * КОГДА РЕЗУЛЬТАТ ПРИДЁТ НА ПОЧТУ (короткий конкурс).
 *
 * Порядок источников — от самого точного к расчётному:
 *   уже отправлен            → его дата (тут скрывать нечего);
 *   назначен план отправки   → applications.result_send_at, это и есть обещание крона;
 *   ничего не назначено      → подача + 5 рабочих дней (правило центра, воскресенье не в счёт).
 * Расчётную дату никогда не отодвигаем в прошлое: если срок уже вышел, а письма нет,
 * честнее сказать «в ближайшее рабочее время», чем называть вчерашнее число.
 */
function chat_gate_result_eta(array $a): string {
    $sent = trim((string) ($a['result_sent_at'] ?? ''));
    if ($sent !== '') return $sent;
    $plan = trim((string) ($a['result_send_at'] ?? ''));
    if ($plan !== '') return $plan;
    if (!function_exists('working_days_add') && is_file(BASE_PATH . '/core/send_timing.php')) {
        require_once BASE_PATH . '/core/send_timing.php';
    }
    $created = trim((string) ($a['created_at'] ?? ''));
    if ($created === '' || !function_exists('working_days_add')) return '';
    try { return working_days_add($created, CHAT_GATE_WORKDAYS)->format('Y-m-d H:i:s'); }
    catch (\Throwable $e) { return ''; }
}

/**
 * ЧТО МОЖНО СКАЗАТЬ ПО ОДНОЙ ЗАЯВКЕ.
 *
 * @param array $a строка applications + поля конкурса (comp_name, comp_paid,
 *                 comp_results_mode, comp_results_date, comp_results_pub, comp_slug)
 * @return array{
 *   long:bool, published:bool, may_result:bool, may_diploma:bool,
 *   result:string, hidden_result:string, say:string, status:string
 * }
 *   may_result    — разрешено называть звание;
 *   hidden_result — реальная оценка, КОТОРУЮ НАЗЫВАТЬ НЕЛЬЗЯ (для сторожа ответа);
 *   say           — что бот обязан сказать вместо результата.
 */
function chat_gate_app(array $a): array {
    $long      = (string) ($a['comp_results_mode'] ?? $a['results_mode'] ?? '') === 'list';
    $published = trim((string) ($a['comp_results_pub'] ?? $a['results_published_at'] ?? '')) !== '';
    $result    = trim((string) ($a['result'] ?? ''));
    $sentAt    = trim((string) ($a['result_sent_at'] ?? ''));
    $rejected  = (string) ($a['status'] ?? '') === 'rejected';
    $comp      = trim((string) ($a['comp_name'] ?? ''));
    $num       = trim((string) ($a['number'] ?? ''));

    // Диплом «дошёл» только если письмо с ним ушло. Файл, лежащий в очереди на
    // отправку, для участника не существует — ровно как в кабинете.
    $dipSent = 0;
    if (!empty($a['id'])) {
        try {
            $dipSent = (int) scalar(
                "SELECT COUNT(*) FROM diplomas WHERE application_id=? AND COALESCE(sent_at,'')<>''",
                [(int) $a['id']]);
        } catch (\Throwable $e) { $dipSent = 0; }
    }

    $out = ['long' => $long, 'published' => $published, 'may_result' => false, 'may_diploma' => $dipSent > 0,
            'result' => '', 'hidden_result' => '', 'say' => '', 'status' => ''];

    if ($rejected) {
        $out['status'] = 'отклонена оргкомитетом';
        $out['say']    = 'Заявка отклонена, письмо с причиной уже отправлено на почту из заявки.';
        return $out;
    }

    /* ── ДЛИННЫЙ КОНКУРС: итоги только списком, в назначенный день ──────────── */
    if ($long) {
        if ($published) {
            $out['may_result'] = true;
            $out['result']     = $result;
            $out['status']     = 'аттестационные результаты опубликованы';
            $out['say']        = 'Список аттестационных результатов конкурса «' . $comp . '» опубликован '
                . 'на официальной странице сообщества ВКонтакте и на официальном сайте Культурного центра '
                . '«Музыкальный Мир» в разделе «Результаты».';
            return $out;
        }
        $when = trim((string) ($a['comp_results_date'] ?? $a['results_date'] ?? ''));
        $d    = $when !== '' ? chat_gate_date_ru($when) : '';
        $in   = $when !== '' ? chat_gate_in_days($when) : '';
        $out['hidden_result'] = $result;   // оценка есть, но она под замком
        $out['status'] = 'заявка принята, идёт аттестация';
        $out['say'] = 'Оглашение аттестационных результатов конкурса «' . $comp . '» состоится '
            . ($d !== '' ? $d . ' года' : 'в дату, указанную в положении конкурса')
            . ($in !== '' ? ' (' . $in . ')' : '')
            . ' на официальной странице сообщества ВКонтакте и на официальном сайте Культурного центра '
            . '«Музыкальный Мир» в разделе «Результаты». В этот же день письмо с аттестационным результатом '
            . 'уйдёт каждому участнику на почту, указанную в заявке. '
            . 'До этой даты аттестационные результаты не разглашаются никому — ни в чате, ни по телефону: '
            . 'правило одинаково для всех участников. Сроки и порядок оглашения указаны в положении конкурса.';
        return $out;
    }

    /* ── КОРОТКИЙ КОНКУРС: персональное письмо каждому ──────────────────────── */
    if ($sentAt !== '' && $result !== '') {
        $out['may_result'] = true;
        $out['result']     = $result;
        $out['status']     = 'результат отправлен ' . chat_gate_date_ru($sentAt);
        $out['say']        = 'Результат уже отправлен на почту из заявки ' . chat_gate_date_ru($sentAt) . '.';
        return $out;
    }

    $eta = chat_gate_result_eta($a);
    $d   = $eta !== '' ? chat_gate_date_ru($eta) : '';
    $in  = $eta !== '' ? chat_gate_in_days($eta) : '';
    $q   = chat_gate_queue($a);

    $out['hidden_result'] = $result;   // оценка может быть, но письмо ещё не ушло
    $out['status'] = $result !== '' ? 'аттестация завершена, письмо готовится к отправке' : 'на аттестации жюри';
    $out['say'] = 'Заявка' . ($num !== '' ? ' №' . $num : '') . ' на аттестации жюри. '
        . ($q['pos'] > 0 ? 'Сейчас она ' . $q['pos'] . '-я в очереди на аттестацию по этому конкурсу. ' : '')
        . 'Результат придёт на электронную почту, указанную в заявке'
        . ($d !== '' ? ', ' . $d . ($in !== '' && $in !== 'сегодня' ? ' (' . $in . ')' : '') : ' в течение 5 рабочих дней со дня подачи')
        . '. Раньше письма результат не сообщается.';
    return $out;
}

