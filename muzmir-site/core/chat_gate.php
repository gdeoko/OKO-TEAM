/**
 * СТОРОЖ ГОТОВОГО ОТВЕТА.
 *
 * Промпт — просьба, а не гарантия. Здесь ответ сверяется с фактами: если в тексте
 * всплыло звание, которое участнику ещё не отправлено, ответ целиком заменяется на
 * честное «когда и где». Заменяем, а не вырезаем слово: обрезанная фраза («Ваш
 * результат — .») тревожит сильнее прямого ответа и всё равно выдаёт, что результат
 * есть.
 *
 * Ловим два случая:
 *   1) в ответе стоит РОВНО та оценка, которая скрыта у этого участника;
 *   2) в ответе есть звание вместе с личным обращением («Вы получили Лауреата»),
 *      а у участника есть хоть одна скрытая заявка — значит это про него.
 * Общий рассказ про 10-балльную шкалу под второе правило не попадает: там нет
 * личного обращения.
 *
 * @param string $reply готовый ответ модели
 * @param array  $gates массив chat_gate_app() по заявкам этого собеседника
 */
function chat_gate_guard(string $reply, array $gates): string {
    if (trim($reply) === '' || !$gates) return $reply;

    $hidden = [];
    $says   = [];
    foreach ($gates as $g) {
        $h = trim((string) ($g['hidden_result'] ?? ''));
        if ($h !== '') $hidden[] = $h;
        if (empty($g['may_result']) && trim((string) ($g['say'] ?? '')) !== '') $says[] = (string) $g['say'];
    }
    if (!$hidden && !$says) return $reply;

    $low = mb_strtolower($reply);

    // 1) Дословное совпадение со скрытой оценкой.
    $hit = false;
    foreach ($hidden as $h) {
        if ($h !== '' && mb_strpos($low, mb_strtolower($h)) !== false) { $hit = true; break; }
    }

    // 2) Звание + личное обращение.
    if (!$hit && $hidden) {
        $title = '~(гран[\s\-]?при|лауреат|дипломант)~ui';
        $person = '~(вы\s|вам\b|вас\b|ваш|у\s+вас|поздравля|присвоен|получил|заняли|стали)~ui';
        if (preg_match($title, $reply) && preg_match($person, $reply)) $hit = true;
    }

    // 3) Ссылка на диплом, которого участнику ещё не отправляли.
    if (!$hit && preg_match('~/diploma/~i', $reply)) {
        $anySent = false;
        foreach ($gates as $g) if (!empty($g['may_diploma'])) { $anySent = true; break; }
        if (!$anySent) $hit = true;
    }

    if (!$hit) return $reply;

    if (function_exists('error_log')) {
        error_log('chat_gate: ответ подменён — модель назвала результат до срока');
    }
    $safe = $says ? implode(' ', array_slice(array_unique($says), 0, 2)) : '';
    if ($safe === '') {
        $safe = 'Результат сообщается участнику письмом на почту из заявки (а по конкурсам с общим списком — в день публикации итогов). '
              . 'Раньше этого срока итоги не разглашаются.';
    }
    return $safe;
}
