<?php
/**
 * core/prioritet.php — ОТ КОГО ПРИШЛА ЗАЯВКА И КАКОЙ СРОК У НЕЁ НА САМОМ ДЕЛЕ.
 *
 * Правка владельца 14.10.2026: оператор обязан видеть в админке, что заявка на
 * участие или заказ наградного материала пришли от УЧРЕЖДЕНИЯ-ПАРТНЁРА или от
 * участника ЭЛИТНОГО КЛУБА, потому что у них другие сроки, и успеть разобрать
 * заявку и собрать бланк в этот короткий срок, а не в общий.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ДВА `if` В ШАБЛОНЕ. Срок уже считается в двух
 * местах: `_plan_send_at()` в `cron/send_diplomas.php` (результат и наградные
 * дипломы) и `order_issue_diplomas()` в `core/orders.php` (изготовление по
 * оплаченному заказу). Если плашка в админке посчитает срок своей копией
 * условий, копии разойдутся молча, и оператор будет торопиться к числу, которого
 * код не держит, или спокойно ждать там, где письмо уже ушло. Эта грабля в
 * проекте уже оплачена дважды (правила 33 и 35: пункты положения и ссылки
 * расходились между мозгом и запасным ответом). Поэтому здесь ОДИН источник, а
 * оба расчёта и вся админка зовут его.
 *
 * ЛЕСТНИЦА СРОКОВ, слово владельца 13.10.2026 (правило 37, заново не обсуждаем):
 *   обычный участник — 5 рабочих дней,
 *   участник от учреждения-партнёра — 4 (`institutions.partner_priority_days`),
 *   участник Элитного клуба — 3 (за него платят, он и самый короткий).
 *
 * ЛЕСТНИЦА ДЕЙСТВУЕТ ТОЛЬКО НА КОРОТКИХ КОНКУРСАХ (слово владельца 14.10.2026):
 * «Данные сроки аттестации для партнёров действуют только на короткие конкурсы.
 * По длинным конкурсам сроки аттестации согласно дате указанной в положении
 * конкурса». У длинного конкурса (`competitions.results_mode='list'`) итоги
 * оглашаются СПИСКОМ в объявленную дату, одну на всех, и рабочих дней там не
 * считает никто: ни партнёру, ни участнику Элитного клуба результат раньше этой
 * даты не приходит. Поэтому на длинном конкурсе плашка называет САМУ ДАТУ, а не
 * число дней - иначе оператор увидел бы «4 рабочих дня» там, где решение всё
 * равно огласят 28 октября вместе со всеми.
 * Дата живёт в карточке конкурса (`competitions.results_date`): в самих .docx
 * положениях НЕТ НИ ОДНОЙ ДАТЫ, это сверено по всем 40 пунктам (правило 37),
 * поэтому берём её из базы, а не из документа.
 *
 * ИЗГОТОВЛЕНИЕ НАГРАДНОГО МАТЕРИАЛА — ЭТО ДРУГОЙ СРОК, И У ПАРТНЁРА ЕГО НЕТ.
 * Привилегия партнёра называется «Приоритетная аттестация» и обещана только на
 * РЕЗУЛЬТАТ. По оплаченному заказу наград код даёт клубу 3 рабочих дня, всем
 * остальным 5, партнёру в том числе. Выдумывать партнёру короткий срок
 * изготовления здесь нельзя: это обещание 41 принятому учреждению, которого
 * центр не давал. Поэтому у заказа плашка партнёра честно говорит, что срок
 * общий, и оператор не ждёт от бланка невозможного.
 */
declare(strict_types=1);

/** Общий срок, рабочих дней: и на результат, и на изготовление. */
const PRIORITET_SROK_OBSHIY = 5;
/** Срок участника Элитного клуба, рабочих дней. Живёт в коде, настройки нет. */
const PRIORITET_SROK_KLUBA = 3;
/* ИЗГОТОВЛЕНИЕ ОРИГИНАЛОВ ОДИНАКОВОЕ ДЛЯ ВСЕХ - слово владельца 16.10.2026:
   «Сроки изготовления электронных дипломов для участников элитного клуба 3 дня
   для остальных 5 дней. Сроки изготовления оригиналов для всех одинаковые».
   Клубного срока у бланка и изделия нет и быть не должно: их печатают и везут
   почтой, и короткий срок тут никому не обещан. */
const PRIORITET_SROK_ORIGINALA = 7;
/** Доставка Почтой России, рабочих дней (до). Зависит от региона. */
const PRIORITET_SROK_DOSTAVKI = 14;

/**
 * СРОКИ ИЗГОТОВЛЕНИЯ СЛОВАМИ - ОДНА ФРАЗА НА ВИТРИНУ, ПИСЬМА, БОТА И ПОЛОЖЕНИЕ.
 * Числа берутся у тех же констант, что и расчёт: вписанная копия ломается ровно
 * в день правки (урок правил 56 и 61), а разошедшееся обещание человек читает
 * как обман центра (правила 33, 35, 45, 46).
 */
function prioritet_fraza_elektronnyh(): string {
    return 'электронные - ' . prioritet_dney(PRIORITET_SROK_OBSHIY) . ' с момента оплаты заказа, '
         . 'у участников Элитного клуба - ' . prioritet_dney(PRIORITET_SROK_KLUBA);
}

function prioritet_fraza_originalov(): string {
    return 'оригиналы на бланках и изделия - ' . prioritet_dney(PRIORITET_SROK_ORIGINALA)
         . ' на изготовление, срок одинаковый для всех, и до ' . PRIORITET_SROK_DOSTAVKI
         . ' рабочих дней на доставку Почтой России';
}

function prioritet_fraza_izgotovleniya(): string {
    return prioritet_fraza_elektronnyh() . '; ' . prioritet_fraza_originalov() . '.';
}

/**
 * Приоритет ОДНОГО ПОЛЬЗОВАТЕЛЯ (членство в клубе или команда центра).
 * Ответ запоминается на время запроса: список заявок рисует до восьмисот строк,
 * и каждая спрашивала бы базу заново.
 *
 * @return array{клуб:bool, команда:bool}
 */
/**
 * СКОЛЬКО РАБОЧИХ ДНЕЙ ОБЕЩАЕТ САМ КОНКУРС - ВСЕМ, КТО В НЕГО ПОДАЁТ.
 *
 * Слово владельца 16.10.2026: у «Мирового акцента» на витрине и на афише стояло
 * «Результаты в течение 5 рабочих дней», и это стало неправдой в тот день, когда
 * приём закрыли для всех, кроме участников Элитного клуба (правило 72): подать
 * может ТОЛЬКО член Клуба, а у него срок клубный - три рабочих дня. Пять там
 * обещало человеку больше ожидания, чем центр на самом деле берёт.
 *
 * Лестница не трогается (правило 37): обычный 5, партнёрский 4, клубный 3. Здесь
 * считается не льгота человека, а ОБЕЩАНИЕ КОНКУРСА: у конкурса с приёмом только
 * для членов Клуба все участники клубные по построению, значит и обещание одно.
 * Число берётся у той же пары констант, что и `prioritet_zayavki()`.
 */
function prioritet_dnei_konkursa(array $c): int {
    if (!function_exists('club_vhod_tolko_chlenam') && is_file(BASE_PATH . '/core/club_free.php')) {
        require_once BASE_PATH . '/core/club_free.php';
    }
    if (function_exists('club_vhod_tolko_chlenam') && club_vhod_tolko_chlenam($c)) {
        return PRIORITET_SROK_KLUBA;
    }
    return PRIORITET_SROK_OBSHIY;
}

function prioritet_polzovatelya(int $uid): array {
    static $память = [];
    if ($uid <= 0) return ['клуб' => false, 'команда' => false];
    if (isset($память[$uid])) return $память[$uid];

    $нет = ['клуб' => false, 'команда' => false];
    if (!function_exists('club_is_active')) {
        if (!is_file(BASE_PATH . '/core/club.php')) return $память[$uid] = $нет;
        require_once BASE_PATH . '/core/club.php';
    }
    try {
        $команда = function_exists('club_is_staff') && club_is_staff($uid);
        $клуб    = club_is_active($uid);                 // у команды это тоже true
    } catch (\Throwable $e) { return $память[$uid] = $нет; }

    return $память[$uid] = ['клуб' => $клуб, 'команда' => $команда];
}

/**
 * Приоритет УЧРЕЖДЕНИЯ: партнёр ли оно и сколько рабочих дней обещано.
 * Условие то же, что в расчёте срока: только `partner_status='accepted'`.
 * Метка в cookie живёт 90 дней и переживает отказ, поэтому непринятому
 * учреждению заявка не засчитывается (`partner_attach_application`).
 *
 * @return array{партнёр:bool, имя:string, дней:int}
 */
function prioritet_uchrezhdeniya(int $instId): array {
    static $память = [];
    $нет = ['партнёр' => false, 'имя' => '', 'дней' => 0];
    if ($instId <= 0) return $нет;
    if (isset($память[$instId])) return $память[$instId];
    try {
        $r = one("SELECT name, COALESCE(partner_priority_days,0) d FROM institutions
                   WHERE id=? AND partner_status='accepted'", [$instId]);
    } catch (\Throwable $e) { return $память[$instId] = $нет; }
    if (!$r) return $память[$instId] = $нет;
    return $память[$instId] = [
        'партнёр' => true,
        'имя'     => trim((string) ($r['name'] ?? '')),
        'дней'    => (int) ($r['d'] ?? 0),
    ];
}

/**
 * ДЛИННЫЙ ЛИ КОНКУРС И КОГДА У НЕГО ОГЛАШЕНИЕ.
 *
 * @return array{длинный:bool, дата:string}
 */
function prioritet_konkursa(int $compId): array {
    static $память = [];
    $нет = ['длинный' => false, 'дата' => ''];
    if ($compId <= 0) return $нет;
    if (isset($память[$compId])) return $память[$compId];
    try {
        $c = one("SELECT results_mode, results_date FROM competitions WHERE id=?", [$compId]);
    } catch (\Throwable $e) { return $память[$compId] = $нет; }
    if (!$c) return $память[$compId] = $нет;
    return $память[$compId] = [
        'длинный' => (string) ($c['results_mode'] ?? '') === 'list',
        'дата'    => trim((string) ($c['results_date'] ?? '')),
    ];
}

/**
 * ПРИОРИТЕТ ЗАЯВКИ НА УЧАСТИЕ — главная дверь.
 *
 * @param array $app строка `applications`. Нужны `user_id` и `institution_id`;
 *                   если `institution_id` в строке нет (неполный SELECT), он
 *                   берётся по `id` — молча считать «не партнёр» нельзя, иначе
 *                   плашка пропадёт из-за экономии в запросе.
 * @return array{клуб:bool, команда:bool, партнёр:bool, учреждение:string,
 *               дней_результат:int, дней_изготовление:int, uid:int, инст:int}
 */
function prioritet_zayavki(array $app): array {
    $uid = (int) ($app['user_id'] ?? 0);
    /* Колонок может не быть в запросе (список дипломов, очередь отправок) -
       тогда добираем их по номеру заявки одним запросом. Молча считать «не
       партнёр» и «короткий конкурс» из-за экономии в SELECT нельзя: плашка
       пропала бы в половине разделов, а на длинном конкурсе ещё и соврала. */
    $добор = (array_key_exists('institution_id', $app) && array_key_exists('competition_id', $app))
        ? ['инст' => (int) ($app['institution_id'] ?? 0), 'конкурс' => (int) ($app['competition_id'] ?? 0)]
        : prioritet_po_zayavke((int) ($app['id'] ?? 0), $app);
    $инст    = (int) $добор['инст'];
    $конкурс = (int) $добор['конкурс'];

    $u = prioritet_polzovatelya($uid);
    $i = prioritet_uchrezhdeniya($инст);
    $k = prioritet_konkursa($конкурс);

    /* СЧЁТ ТОТ ЖЕ, ЧТО В `grade_apply.php` И `_plan_send_at()`, И ПОРЯДОК ТОЖЕ:
       обычный 5 → клуб 3 → партнёр опускает только то, что выше трёх.
       У ДЛИННОГО конкурса рабочих дней нет вовсе: итоги оглашаются списком в
       объявленную дату, и ноль здесь значит «срок задаёт дата, а не счёт». */
    $дней = PRIORITET_SROK_OBSHIY;
    if ($u['клуб']) $дней = PRIORITET_SROK_KLUBA;
    if ($i['партнёр'] && $дней > PRIORITET_SROK_KLUBA
        && $i['дней'] > 0 && $i['дней'] < $дней) $дней = $i['дней'];
    if ($k['длинный']) $дней = 0;

    return [
        'клуб'              => $u['клуб'],
        'команда'           => $u['команда'],
        'партнёр'           => $i['партнёр'],
        'учреждение'        => $i['имя'],
        'длинный'           => $k['длинный'],
        'партнёр_дней'      => (int) $i['дней'],
        'дата_оглашения'    => $k['дата'],
        'дней_результат'    => $дней,
        'дней_изготовление' => $u['клуб'] ? PRIORITET_SROK_KLUBA : PRIORITET_SROK_OBSHIY,
        'uid'               => $uid,
        'инст'              => $инст,
        'конкурс'           => $конкурс,
    ];
}

/** Учреждение и конкурс по номеру заявки — когда в строке списка колонок нет. */
function prioritet_po_zayavke(int $appId, array $app = []): array {
    static $память = [];
    $есть = [
        'инст'    => (int) ($app['institution_id'] ?? 0),
        'конкурс' => (int) ($app['competition_id'] ?? 0),
    ];
    if ($appId <= 0) return $есть;
    if (isset($память[$appId])) return $память[$appId];
    try {
        $r = one("SELECT COALESCE(institution_id,0) i, COALESCE(competition_id,0) c
                    FROM applications WHERE id=?", [$appId]);
    } catch (\Throwable $e) { return $есть; }
    if (!$r) return $память[$appId] = $есть;
    return $память[$appId] = ['инст' => (int) $r['i'], 'конкурс' => (int) $r['c']];
}

/**
 * ПРИОРИТЕТ ЗАКАЗА НАГРАДНОГО МАТЕРИАЛА.
 *
 * Клуб смотрим у плательщика заказа, а партнёрство — у ЗАЯВКИ: заказ оформляет
 * руководитель, а по партнёрской ссылке приходила именно заявка. У клубной
 * подписки (`kind='club'`) заявки нет вовсе, и это не ошибка.
 *
 * @param array $order строка `awards_orders`
 */
function prioritet_zakaza(array $order): array {
    /* КЛУБНАЯ ПОДПИСКА — ЭТО НЕ НАГРАДА, И СРОКА ИЗГОТОВЛЕНИЯ У НЕЁ НЕТ.
     * У такого заказа (`kind='club'`) нет ни заявки, ни бланка: человек купил
     * членство. Плашка «изготовление 3 рабочих дня» на нём обещала бы документ,
     * которого никто не заказывал, поэтому срок с неё снимается. */
    $подписка = (string) ($order['kind'] ?? '') === 'club';
    $app = [
        'id'      => (int) ($order['application_id'] ?? 0),
        'user_id' => (int) ($order['user_id'] ?? 0),
    ];
    if ((int) $app['user_id'] === 0 && (int) $app['id'] > 0) {
        // У заказа плательщик бывает не записан (оформлен без входа) — тогда
        // членство клуба ищем у хозяина заявки, иначе клубный срок потеряется.
        try {
            $app['user_id'] = (int) (scalar("SELECT COALESCE(user_id,0) FROM applications WHERE id=?",
                                            [$app['id']]) ?? 0);
        } catch (\Throwable $e) {}
    }
    return ['подписка' => $подписка] + prioritet_zayavki($app);
}

/** Есть ли вообще что показывать. */
function prioritet_est(array $p): bool {
    return !empty($p['клуб']) || !empty($p['партнёр']);
}

/**
 * ВЕС ДЛЯ ОЧЕРЕДИ АТТЕСТАЦИИ: 0 заявка участника Элитного клуба,
 * 1 заявка от учреждения-партнёра, 2 все остальные.
 *
 * Слово владельца 16.10.2026: в «Оценке коротких» сначала идут клубные
 * заявки, за ними партнёрские, чтобы не пропустить срок отправки
 * результатов: у них он короче (3 и 4 рабочих дня против 5).
 *
 * ПОРЯДОК ТОТ ЖЕ, ЧТО У СРОКА, И ЭТО ГЛАВНОЕ В ВЕСЕ. Клуб всегда короче
 * партнёра (за него платят, правило 37), поэтому у человека с обоими
 * признаками вес клубный. Своей копии условий очередь держать не вправе:
 * копии расходятся молча, и тогда плашка говорит одно, а порядок строк
 * другое (грабля правил 33, 35, 45, 47).
 *
 * КОМАНДА ЦЕНТРА ИДЁТ КАК КЛУБ НАРОЧНО: у неё `клуб` тоже true и срок
 * тоже три дня, а очередь выстраивается именно по сроку.
 */
function prioritet_ves(array $p, string $что = 'заявка'): int {
    /* У ИЗГОТОВЛЕНИЯ ЛЕСТНИЦА ДРУГАЯ, И ПАРТНЁРА В НЕЙ НЕТ (правило 47).
       Привилегия партнёра называется «Приоритетная аттестация» и обещана только
       на РЕЗУЛЬТАТ: по наградам код даёт клубу 3 рабочих дня, всем остальным 5,
       партнёру в том числе. Поднять партнёрскую строку в начало очереди наград
       значит пообещать оператору срок, которого в заказе нет, и плашка на той же
       строке скажет обратное - «изготовление в общий срок». */
    if ($что === 'изготовление') {
        // Клубная подписка это не награда: изготавливать нечего, срока нет.
        if (!empty($p['подписка'])) return 2;
        return !empty($p['клуб']) ? 0 : 2;
    }
    /* У ДЛИННОГО КОНКУРСА СРОК ЗАДАЁТ ДАТА ОГЛАШЕНИЯ, А НЕ СЧЁТ ДНЕЙ (правило
       47): итоги объявляют списком в одну дату на всех, и ни клубу, ни партнёру
       результат раньше не приходит - значит и поднимать их некуда. */
    if (!empty($p['длинный'])) return 2;
    if (!empty($p['клуб']))    return 0;
    if (!empty($p['партнёр'])) return 1;
    return 2;
}

/**
 * ПЛАШКА ДЛЯ АДМИНКИ. Говорит СРОК, а не только «клуб»: синяя галочка рядом с
 * именем (`vip_mark`) уже была, и по ней оператор всё равно не знал, сколько у
 * него дней. Поэтому здесь число и слова.
 *
 * @param string $что 'заявка' — срок разбора и результата;
 *                    'изготовление' — срок наградного материала по заказу.
 */
function prioritet_plashka(array $p, string $что = 'заявка'): string {
    if (!prioritet_est($p)) return '';
    $изг = $что === 'изготовление';
    $out = [];

    /* У ДЛИННОГО КОНКУРСА СРОК АТТЕСТАЦИИ ЗАДАЁТ ДАТА ОГЛАШЕНИЯ, А НЕ СЧЁТ ДНЕЙ
       (слово владельца 14.10.2026). Это касается только ветки «заявка»: срок
       ИЗГОТОВЛЕНИЯ наградного материала считается от оплаты заказа одинаково у
       длинных и коротких конкурсов, оглашение итогов к нему отношения не имеет. */
    $списком = !$изг && !empty($p['длинный']);
    $огл = $списком
        ? ('итоги списком' . (trim((string) ($p['дата_оглашения'] ?? '')) !== ''
            ? ' ' . prioritet_data((string) $p['дата_оглашения'])
            : ', дата оглашения не назначена'))
        : '';

    if (!empty($p['клуб'])) {
        $дней  = $изг ? (int) $p['дней_изготовление'] : (int) $p['дней_результат'];
        $имя   = !empty($p['команда']) ? 'Оргкомитет центра' : 'Элитный клуб';
        if ($изг && !empty($p['подписка'])) {
            // Покупка членства: изготавливать нечего, срок называть не о чем.
            return prioritet_chip($имя . ' · подписка', '#2C7BE5',
                'Это покупка членства в Элитном клубе, а не наградной материал: изготовления и срока у неё нет');
        }
        if ($списком) {
            $out[] = prioritet_chip($имя . ' · ' . $огл, '#2C7BE5',
                'Длинный конкурс: итоги оглашаются списком в объявленную дату, одну на всех. '
                . 'Короткий срок Элитного клуба к аттестации здесь не применяется, '
                . 'он остаётся на изготовлении наградного материала');
        } else {
            $подск = !empty($p['команда'])
                ? 'Команда центра: привилегии клуба без срока и без оплаты'
                : ($изг
                    ? 'Участник Элитного клуба: наградной материал ' . $дней . ' рабочих дня от оплаты заказа вместо '
                      . PRIORITET_SROK_OBSHIY
                    : 'Участник Элитного клуба: результат ' . $дней . ' рабочих дня от подачи заявки вместо '
                      . PRIORITET_SROK_OBSHIY);
            $out[] = prioritet_chip($имя . ' · ' . prioritet_dney($дней), '#2C7BE5', $подск);
        }
    }

    if (!empty($p['партнёр'])) {
        $имя = trim((string) $p['учреждение']);
        if ($имя === '') $имя = 'учреждение-партнёр';
        if ($изг) {
            /* У ПАРТНЁРА НЕТ КОРОТКОГО СРОКА ИЗГОТОВЛЕНИЯ, И ПЛАШКА ГОВОРИТ ЭТО
               ПРЯМО. Промолчать значит дать оператору додумать: он прочитает
               «партнёр» рядом с бланком и начнёт торопиться к четвёртому дню,
               которого в заказе нет. */
            $out[] = prioritet_chip('Партнёр: ' . $имя . ' · изготовление в общий срок, '
                                    . prioritet_dney((int) $p['дней_изготовление']),
                '#1E7A46',
                'Заявка пришла от учреждения-партнёра. Ускоренная выдача обещана только на '
                . 'результат аттестации, наградной материал изготавливается в общий срок '
                . PRIORITET_SROK_OBSHIY . ' рабочих дней от оплаты заказа'
                . (!empty($p['клуб']) ? '. Клубный срок короче, действует он' : ''));
        } elseif ($списком) {
            /* ПРИОРИТЕТНАЯ АТТЕСТАЦИЯ ПАРТНЁРА НА ДЛИННЫЙ КОНКУРС НЕ
               РАСПРОСТРАНЯЕТСЯ - слово владельца 14.10.2026. Назвать здесь
               «4 рабочих дня» значит обещать учреждению результат раньше
               общего оглашения, которого всё равно не будет: итоги длинного
               конкурса объявляются списком в одну дату для всех. */
            $out[] = prioritet_chip('Партнёр: ' . $имя . ' · ' . $огл, '#1E7A46',
                'Заявка пришла от учреждения-партнёра. Длинный конкурс: итоги оглашаются списком '
                . 'в объявленную дату, и приоритетная аттестация за '
                . (int) ($p['партнёр_дней'] ?? 4) . ' рабочих дня здесь НЕ действует '
                . '(она только на коротких конкурсах)');
        } else {
            $своих = (int) $p['дней_результат'];
            $хвост = !empty($p['клуб'])
                ? ' · срок по клубу, он короче'
                : ' · ' . prioritet_dney($своих);
            $out[] = prioritet_chip('Партнёр: ' . $имя . $хвост, '#1E7A46',
                'Заявка пришла от учреждения-партнёра. Приоритетная аттестация: результат '
                . $своих . ' рабочих дней от подачи вместо ' . PRIORITET_SROK_OBSHIY
                . (!empty($p['клуб'])
                    ? '. У участника ещё и Элитный клуб, поэтому действует самый короткий срок'
                    : ''));
        }
    }

    return implode(' ', $out);
}

/** Дата оглашения человеку: «28.10.2026». Непонятную строку отдаём как есть. */
function prioritet_data(string $iso): string {
    $t = strtotime(trim($iso));
    return $t ? date('d.m.Y', $t) : trim($iso);
}

/** «3 рабочих дня» / «4 рабочих дня» / «5 рабочих дней» — без ошибок в падеже. */
function prioritet_dney(int $n): string {
    $о = $n % 10; $д = $n % 100;
    $сл = ($о === 1 && $д !== 11) ? 'день'
        : (($о >= 2 && $о <= 4 && ($д < 12 || $д > 14)) ? 'дня' : 'дней');
    $раб = $сл === 'день' ? 'рабочий' : ($сл === 'дня' ? 'рабочих' : 'рабочих');
    return $n . ' ' . $раб . ' ' . $сл;
}

/** Сама плашка. Инлайновый стиль намеренно: своего класса в админке нет. */
function prioritet_chip(string $текст, string $цвет, string $подсказка = ''): string {
    return '<span class="small" title="' . h($подсказка) . '"'
        . ' style="display:inline-block;margin:3px 4px 0 0;padding:1px 8px;border-radius:999px;'
        . 'border:1px solid ' . $цвет . ';color:' . $цвет . ';background:' . $цвет . '14;'
        /* ПЕРЕНОСА У ПЛАШКИ НЕТ - СЛОВО ВЛАДЕЛЬЦА 18.10.2026.
         *
         * `white-space:nowrap` держал плашку одной строкой, и самая длинная
         * («Партнёр: Центр развития молодежи «ART.Платформа» · срок по клубу,
         * он короче», 81 знак) растягивала колонку «От кого» до 604 точек при
         * остальных по 100-180. Замером: таблица заявок выходила на 1474 точки
         * в обёртке 1037, то есть 437 за правым краем, и три колонки справа
         * приходилось доставать прокруткой вбок.
         *
         * Теперь плашка переносится по словам и занимает столько, сколько ей
         * дадут. Чип стоит в девяти разделах админки, и перенос касается всех
         * сразу - это и просили. */
        . 'font-weight:700'
        . '">' . h($текст) . '</span>';
}

/** Та же правда словами — для журналов, писем владельцу и аудита. */
function prioritet_slovami(array $p): string {
    if (!prioritet_est($p)) {
        return 'обычный участник, ' . (!empty($p['длинный'])
            ? ('итоги списком' . (trim((string) ($p['дата_оглашения'] ?? '')) !== ''
                ? ' ' . prioritet_data((string) $p['дата_оглашения']) : ', дата не назначена'))
            : prioritet_dney(PRIORITET_SROK_OBSHIY));
    }
    $ч = [];
    if (!empty($p['команда'])) $ч[] = 'оргкомитет центра';
    elseif (!empty($p['клуб'])) $ч[] = 'Элитный клуб';
    if (!empty($p['партнёр'])) $ч[] = 'партнёр «' . trim((string) $p['учреждение']) . '»';
    $рез = !empty($p['длинный'])
        ? ('итоги списком' . (trim((string) ($p['дата_оглашения'] ?? '')) !== ''
            ? ' ' . prioritet_data((string) $p['дата_оглашения']) : ', дата не назначена'))
        : prioritet_dney((int) $p['дней_результат']);
    return implode(', ', $ч) . '; результат ' . $рез
         . ', изготовление ' . prioritet_dney((int) $p['дней_изготовление']);
}
