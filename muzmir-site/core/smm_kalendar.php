/**
 * КАЛЕНДАРЬ ЗНАМЕНАТЕЛЬНЫХ ДАТ КУЛЬТУРЫ.
 *
 * Правка владельца 13.10.2026: «Публиковать праздничные поздравительные афиши
 * от Культурного центра „Музыкальный Мир" в дни рождения и празднования
 * выдающихся деятелей Культуры и искусства или государственных праздников
 * Российской Федерации, связанные с музыкой, творчеством, поэзией, театром».
 *
 * Данные лежат отдельным файлом `data/smm_kalendar.json`, а не в коде: владелец
 * может дописать свою дату, не трогая PHP, и файл читается заново на каждый
 * заход. Даты людей - по НОВОМУ стилю (у дореволюционных это важно: Чайковский
 * родился 25 апреля по старому и 7 мая по новому, и в ленте должен стоять
 * новый). У пересчитанных записей стоит пометка «стиль», чтобы следующая
 * сессия не «починила» дату обратно.
 *
 * ВЕС РЕШАЕТ, БУДЕТ ЛИ АФИША, и это защита от календарного спама: занятых дней
 * в году 93, и афиша каждый такой день превратила бы ленту в численник. Вес 1 -
 * афиша всегда (43 даты в году, примерно три-четыре в месяц). Вес 2 - только на
 * круглую дату (кратную 25 годам).
 *
 * ДАТА ПРОВЕРЯЕТСЯ МОДЕЛЬЮ ПЕРЕД ВЫПУСКОМ. Календарь собран человеком и в нём
 * возможна описка, а поздравление не с тем числом - публичная ошибка центра.
 * Поэтому `smm_kal_проверить()` спрашивает отдельно, и при сомнении афиша не
 * выходит: слот спокойно занимает обычный пост.
 */

/** Весь календарь. Пустой массив - файла нет или он битый. */
function smm_kal_загрузить(): array {
    static $кэш = null;
    if (is_array($кэш)) return $кэш;
    $путь = BASE_PATH . '/data/smm_kalendar.json';
    $с = @file_get_contents($путь);
    $j = is_string($с) ? json_decode($с, true) : null;
    $кэш = (is_array($j) && is_array($j['даты'] ?? null)) ? $j['даты'] : [];
    return $кэш;
}

/** Все записи на день «ММ-ДД». */
function smm_kal_на_дату(string $день): array {
    $день = mb_substr(trim($день), -5);           // принимаем и «2026-10-13»
    $о = [];
    foreach (smm_kal_загрузить() as $з) {
        if ((string) ($з['дата'] ?? '') === $день) $о[] = $з;
    }
    return $о;
}

/**
 * Один повод на дату слота, уже с подсчитанным возрастом даты, либо пусто.
 *
 * Выбор не случайный: сперва вес, потом круглая дата, потом Россия - иначе в
 * день, где сошлись Пушкинский день и день рождения Хачатуряна, лента
 * поздравляла бы кого придётся.
 */
function smm_kal_повод(string $датаСлота): array {
    $год = (int) mb_substr($датаСлота, 0, 4);
    $ряд = [];
    foreach (smm_kal_на_дату($датаСлота) as $з) {
        $рожд = (int) ($з['год'] ?? 0);
        $лет = ($рожд > 0 && $год > $рожд) ? ($год - $рожд) : 0;
        $з['лет'] = $лет;
        $з['круглая'] = $лет > 0 && $лет % 25 === 0;
        $ряд[] = $з;
    }
    if (!$ряд) return [];

    usort($ряд, static function (array $a, array $b): int {
        $va = (int) ($a['вес'] ?? 2); $vb = (int) ($b['вес'] ?? 2);
        if ($va !== $vb) return $va <=> $vb;                       // 1 важнее 2
        $ka = !empty($a['круглая']); $kb = !empty($b['круглая']);
        if ($ka !== $kb) return $ka ? -1 : 1;
        $ra = mb_strpos((string) ($a['страна'] ?? 'Россия'), 'Росси') !== false;
        $rb = mb_strpos((string) ($b['страна'] ?? 'Россия'), 'Росси') !== false;
        if ($ra !== $rb) return $ra ? -1 : 1;
        return 0;
    });

    $лучший = $ряд[0];
    /* Вес 2 попадает в ленту только круглой датой. */
    if ((int) ($лучший['вес'] ?? 2) !== 1 && empty($лучший['круглая'])) return [];
    $лучший['рядом'] = array_slice(array_column($ряд, 'имя'), 1, 2);
    return $лучший;
}

/** Строка повода для правил модели: кого и с чем поздравляем. */
function smm_kal_строка(array $п): string {
    if (!$п) return '';
    if ((string) ($п['повод'] ?? '') === 'праздник') {
        return (string) $п['имя'] . ((string) ($п['что'] ?? '') !== '' ? (' (' . $п['что'] . ')') : '');
    }
    $лет = (int) ($п['лет'] ?? 0);
    return (string) $п['имя'] . ', ' . (string) ($п['кто'] ?? '')
         . ($лет > 0 ? (', исполняется ' . $лет . ' лет со дня рождения (' . (int) $п['год'] . ')') : '');
}

/**
 * Проверить дату у модели. Три исхода, и «не замерено» - честный третий.
 *
 * Возвращает ['ок'=>true] | ['ок'=>false,'почему'=>…] | ['молчит'=>true].
 * Молчание модели (кончилась квота) афишу НЕ разрешает: лучше обычный пост,
 * чем поздравление не с тем числом.
 */
/**
 * Ключ памяти сверки. В него входят имя, дата и год ИЗ КАЛЕНДАРЯ: поправили
 * дату в data/smm_kalendar.json - память сбрасывается сама, и повод сверяется
 * заново. Иначе ошибка в календаре осталась бы заверенной навсегда.
 */
function smm_kal_ключ_сверки(array $п): string {
    return 'smm_kal_sverka:' . substr(md5(
        (string) ($п['имя'] ?? '') . '|' . (string) ($п['дата'] ?? '') . '|' . (string) ($п['год'] ?? '')
    ), 0, 16);
}

function smm_kal_проверить(array $п): array {
    if (!$п) return ['ок' => false, 'почему' => 'повода нет'];

    /* ДАТА РОЖДЕНИЯ НЕ МЕНЯЕТСЯ, А СПРАШИВАЛИ ЕЁ КАЖДЫЙ ЧАС.
     *
     * Замер 14.10.2026: подготовка просыпается каждый час, за сутки 20 заходов,
     * и КАЖДЫЙ заново сверял одну и ту же дату Лермонтова по три попытки. До 60
     * вызовов мозга в сутки на один вопрос - ровно вся дневная норма (60), и к
     * 17:15 собирать ленту было уже нечем: ни афиши, ни совета, ни кадра у
     * доводчика. Сверка пройдена - значит пройдена: ответ запоминается.
     *
     * «Молчит» в память НЕ пишется (это не ответ), но и ломиться каждый час
     * незачем: следующая попытка не раньше чем через четыре часа. Так за сутки
     * выходит до шести попыток вместо шестидесяти, и повод всё равно успевает:
     * дни с поводом открываются на неделю вперёд (правило 41). */
    $ключ = smm_kal_ключ_сверки($п);
    $было = (string) setting($ключ, '');
    if ($было !== '') {
        $d = json_decode($было, true);
        if (is_array($d) && (isset($d['ок']) || isset($d['молчит']))) {
            if (!empty($d['ок'])) return ['ок' => true];
            if (isset($d['ок'])) return ['ок' => false, 'почему' => (string) ($d['почему'] ?? 'сверка не прошла')
                . ' (по памяти сверки)'];
        }
    }
    $попытка = (int) setting($ключ . ':try', '0');
    if ($попытка > 0 && (time() - $попытка) < 4 * 3600) {
        return ['молчит' => true, 'почему' => 'мозг молчал на сверке меньше четырёх часов назад, не переспрашиваем'];
    }
    $день = (int) mb_substr((string) $п['дата'], 3, 2);
    $мес  = (int) mb_substr((string) $п['дата'], 0, 2);
    $месяцы = [1 => 'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
               'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
    $когда = $день . ' ' . ($месяцы[$мес] ?? '');

    /* СПРАШИВАЕМ ДАТУ, А НЕ СОГЛАСИЕ С ФОРМУЛИРОВКОЙ.
     *
     * Первый вопрос звучал «родился ли X 15 октября по новому стилю?» - и на нём
     * заслон отменил афишу Лермонтова, хотя дата верна: модель ответила
     * «неверно», а верной назвала ТО ЖЕ 15 октября 1814, поспорив лишь о том,
     * юлианский это календарь или григорианский. Для деятеля XIX века такой
     * спор неизбежен: пересчёт стилей модель путает охотнее, чем сам день, а
     * пересчёт у нас уже сделан руками и помечен в календаре. Поэтому просим
     * НАЗВАТЬ обе даты и сверяем ЧИСЛО с месяцем, а не её вердикт. */
    $праздник = (string) ($п['повод'] ?? '') === 'праздник';
    $вопрос = $праздник
        ? ('Какого числа в России отмечается «' . $п['имя'] . '»?' . "\n"
           . 'Верни строго JSON: {"дата":"ДД месяца","знаю":true|false}')
        : ('Когда родился ' . $п['имя'] . ' (' . (string) ($п['кто'] ?? '') . ', '
           . (int) ($п['год'] ?? 0) . ' год)? Назови день рождения по НОВОМУ стилю '
           . '(григорианский календарь, как отмечают в наши дни) и по СТАРОМУ '
           . '(юлианский).' . "\n"
           . 'Верни строго JSON: {"новый_стиль":"ДД месяца","старый_стиль":"ДД месяца",'
           . '"знаю":true|false}');

    /* ЗАХОДОВ ТРИ, И ЭТО НЕ «СПРАШИВАЙ, ПОКА НЕ СОГЛАСИТСЯ».
     *
     * Замер 14.10.2026: один и тот же вопрос про Лермонтова запасной мозг
     * (haiku) отвечает то «новый_стиль 15 октября, старый 3 октября, знаю:true»,
     * то «знаю:false», то вовсе без нужных ключей. По первому прогону заслон
     * отменял афишу - и повод уходил на год из-за случайности одной выдачи.
     * Поэтому повторяем ТОЛЬКО молчание и неуверенность: это не ответ по
     * существу. Названная дата, совпала она или нет, закрывает вопрос сразу -
     * переспрашивать несогласную модель значит выпрашивать нужный ответ. */
    $наш = ['день' => $день, 'мес' => $мес];
    $хвост = "\n\nОтветь честно. Если не знаешь наверняка - поставь \"знаю\":false "
           . 'и не угадывай.';
    $последнее = 'мозг молчит';

    for ($заход = 1; $заход <= 3; $заход++) {
        $GLOBALS['smm_brain_raw'] = '';
        $r = smm_ask_json($вопрос . $хвост, 60);

        /* МОДЕЛЬ ОТКАЗАЛАСЬ ОТ ФОРМАТА, А ДАТУ НАЗВАЛА.
         *
         * Замер ночи 14.10.2026: на вопрос о дате haiku ответил «I'm unable to
         * respond to your request in the format specified. You've asked for only
         * a JSON…», и заслон прочитал это как молчание. Там, где дата в тексте
         * правда есть, терять повод из-за формата незачем.
         *
         * Берём дату ТОЛЬКО рядом со словом про новый стиль: в таком ответе
         * обычно названы обе даты, и первая по тексту запросто окажется старым
         * стилем - тогда заслон соврал бы «дата расходится» на верном
         * календаре. Нет слов про новый стиль - считаем, что ответа нет. */
        if ((!is_array($r) || !$r) && !$праздник) {
            $д = smm_kal_дата_нового_стиля((string) ($GLOBALS['smm_brain_raw'] ?? ''));
            if ($д) $r = ['новый_стиль' => $д['день'] . '.' . $д['мес'], 'из_текста' => true];
        }

        if (!is_array($r) || !$r) { $последнее = 'мозг молчит'; continue; }

        $новый  = smm_kal_дата_разобрать((string) ($r[$праздник ? 'дата' : 'новый_стиль'] ?? ''));
        $старый = $праздник ? null : smm_kal_дата_разобрать((string) ($r['старый_стиль'] ?? ''));

        /* Дата названа - это ответ по существу, даже если «знаю» пришло пустым:
           модель охотно ставит false по привычке к осторожности, а дату при этом
           называет верно. Судим по дате. */
        if ($новый && $новый == $наш) {
            set_setting($ключ, json_encode(['ок' => true], JSON_UNESCAPED_UNICODE));
            set_setting($ключ . ':try', '0');
            return ['ок' => true];
        }

        /* У НАС СТОИТ ДАТА СТАРОГО СТИЛЯ - ЭТО БЕДА КАЛЕНДАРЯ, И НАЗЫВАЕМ ЕЁ ТАК.
           Правило 41 требует новый стиль, и молча поздравлять на двенадцать дней
           раньше нельзя: поправить надо data/smm_kalendar.json. */
        if ($старый && $старый == $наш) {
            $итог = ['ок' => false, 'почему' => 'в календаре дата СТАРОГО стиля, по новому — '
                . mb_substr((string) ($r['новый_стиль'] ?? '—'), 0, 30)
                . ' (поправить data/smm_kalendar.json)'];
            set_setting($ключ, json_encode($итог, JSON_UNESCAPED_UNICODE));
            return $итог;
        }

        if ($новый) {
            $итог = ['ок' => false, 'почему' => 'дата расходится: модель называет «'
                . mb_substr((string) ($r[$праздник ? 'дата' : 'новый_стиль'] ?? '—'), 0, 40) . '»'];
            set_setting($ключ, json_encode($итог, JSON_UNESCAPED_UNICODE));
            return $итог;
        }

        $последнее = array_key_exists('знаю', $r) && empty($r['знаю'])
            ? 'модель не уверена в дате'
            : 'ответ без даты: ' . mb_substr(json_encode($r, JSON_UNESCAPED_UNICODE) ?: '', 0, 60);
    }

    /* Три захода и ни одной названной даты. Афишу не выпускаем: поздравление не
       с тем числом - публичная ошибка центра, а слот спокойно возьмёт совет.
       Время попытки запоминаем, чтобы следующий час не жёг норму заново. */
    set_setting($ключ . ':try', (string) time());
    return ['молчит' => true, 'почему' => $последнее];
}


/**
 * Разобрать русскую дату «15 октября» (год, если есть, отбрасываем).
 *
 * Модель пишет день словами по-разному: «15 октября», «15 октября 1814 года»,
 * «15.10», «October 15». Берём число и название месяца, остальное не нужно:
 * сверяется только день с месяцем, год у нас свой и проверен.
 */
/**
 * Достать из вольного текста дату НОВОГО стиля.
 *
 * Нужна там, где модель отказалась от формата JSON, но дату назвала словами.
 * Берём не «первую дату рядом со словом», а дату из того ФРАГМЕНТА, где стоит
 * слово про новый стиль: в живом ответе обычно названы обе даты сразу
 * («родился 3 октября по старому стилю, что соответствует 15 октября по
 * новому»), и окно вокруг слова цепляет чужую. Фрагмент со словом про старый
 * стиль или юлианский календарь пропускаем целиком - иначе заслон соврал бы
 * «дата расходится» на верном календаре и повод ушёл бы на год.
 */
function smm_kal_дата_нового_стиля(string $текст): ?array {
    $текст = trim($текст);
    if ($текст === '') return null;

    /* РЕЖЕМ И ПО СОЮЗУ «И», А НЕ ТОЛЬКО ПО ЗНАКАМ.
       Живой ответ умещает обе даты в одно предложение без запятой: «родился
       25 апреля по старому стилю и 7 мая по новому стилю». Целый такой кусок
       содержит оба маркера сразу и отбрасывался, хотя нужная дата в нём есть. */
    $куски = preg_split('~[,;.()\n]+|\s+и\s+|\s+-\s+|\s+—\s+~u', $текст) ?: [];
    /* Маркер требует слова «стиль» рядом, и эллипсис «по новому — 7 мая» мы
       НЕ ловим намеренно: одного «нового» без «стиля» полно в живой речи («по
       новому адресу», «по новому правилу»), и широкий шаблон начал бы выдавать
       за дату нового стиля что попало. Такой ответ честно читается как
       молчание - три захода, и следующая попытка через четыре часа.
       Проверено на 12 формулировках: 11 разбираются верно. */
    $старый = '~стар\w*\s+стил\w*|юлиан\w*~ui';
    $новый  = '~нов\w*\s+стил\w*|григориан\w*~ui';

    foreach ($куски as $i => $кусок) {
        if (!preg_match($новый, $кусок)) continue;
        if (preg_match($старый, $кусок)) continue;
        $д = smm_kal_дата_разобрать($кусок);
        if ($д) return $д;

        /* МАРКЕР БЕЗ ДАТЫ СМОТРИТ В ОБЕ СТОРОНЫ, И ОБЕ ЖИВЫЕ.
           Назад - когда уточнение стоит после даты: «Родился 15 октября 1814
           (григорианский календарь)». Вперёд - когда маркер идёт заголовком:
           «По новому стилю — 15 октября 1814 года». Соседа со словом про старый
           стиль не берём ни с какой стороны. */
        foreach ([$i - 1, $i + 1] as $сосед) {
            if (!isset($куски[$сосед])) continue;
            if (preg_match($старый, (string) $куски[$сосед])) continue;
            $д = smm_kal_дата_разобрать((string) $куски[$сосед]);
            if ($д) return $д;
        }
    }
    return null;
}

function smm_kal_дата_разобрать(string $s): ?array {
    $s = mb_strtolower(trim($s));
    if ($s === '') return null;
    $месяцы = ['янв' => 1, 'фев' => 2, 'мар' => 3, 'апр' => 4, 'ма' => 5, 'июн' => 6,
               'июл' => 7, 'авг' => 8, 'сен' => 9, 'окт' => 10, 'ноя' => 11, 'дек' => 12];
    if (preg_match('~(\d{1,2})\s*[\.\-/]\s*(\d{1,2})~u', $s, $m)) {
        $д = (int) $m[1]; $мс = (int) $m[2];
        if ($д >= 1 && $д <= 31 && $мс >= 1 && $мс <= 12) return ['день' => $д, 'мес' => $мс];
    }
    if (!preg_match('~(\d{1,2})~u', $s, $m)) return null;
    $день = (int) $m[1];
    if ($день < 1 || $день > 31) return null;
    /* «мая» и «марта» начинаются одинаково на две буквы, поэтому ключ «ма»
       проверяется последним: иначе март уехал бы в май. */
    foreach (['янв', 'фев', 'мар', 'апр', 'июн', 'июл', 'авг', 'сен', 'окт', 'ноя', 'дек', 'ма'] as $к) {
        if (mb_strpos($s, $к) !== false) return ['день' => $день, 'мес' => $месяцы[$к]];
    }
    return null;
}
