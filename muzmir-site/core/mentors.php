<?php
/**
 * НАСТАВНИКИ УЧАСТНИКА: ДОЛЖНОСТЬ И ФИО.
 *
 * Поле заявки было одно — «Педагог», и в него вписывали кого придётся: одного
 * человека, двоих через запятую, иногда с припиской «конц.» или «рук.». На
 * дипломе всё это выходило строкой «Педагог: Иванов И.И., Иванова Н.В.» —
 * концертмейстер становился педагогом, руководитель коллектива тоже. Участница
 * с концертмейстером написала в поддержку: где его указать? Указать было негде.
 *
 * Теперь у каждого наставника есть должность. Хранится всё в том же поле
 * applications.teacher, одной строкой:
 *
 *     Педагог: Иванов Иван Владимирович; Концертмейстер: Иванова Наталья Владимировна
 *
 * ПОЧЕМУ НЕ ОТДЕЛЬНАЯ ТАБЛИЦА. Поле teacher читают полтора десятка мест: бланк
 * диплома, благодарности, реестр наград, письма, кабинет, админка, выгрузки.
 * Новая таблица означала бы правку каждого из них разом, и любое пропущенное
 * место молча теряло бы педагога из документа. Строка остаётся строкой: старые
 * заявки без должностей читаются как прежде, новые — с должностями.
 *
 * mentors_parse()  — строка → список ['role' => …, 'fio' => …]
 * mentors_format() — список → строка
 * mentors_fio()    — только ФИО, через запятую (для мест, где должность не нужна)
 */
declare(strict_types=1);

/** Должности из выпадающего списка. Порядок — как в форме заявки. */
function mentors_roles(): array {
    return [
        'Педагог',
        'Преподаватель',
        'Руководитель',
        'Концертмейстер',
        'Балетмейстер',
        'Хормейстер',
        'Художественный руководитель',
        'Директор',
    ];
}

/** Сколько наставников можно указать в одной заявке (решение владельца). */
const MENTORS_MAX = 5;

/**
 * Разбирает строку наставников.
 *
 * Понимает оба вида записи:
 *   «Педагог: Иванов И.И.; Концертмейстер: Петрова А.А.» — новый, с должностями;
 *   «Иванов И.И., Петрова А.А.»                          — старый, без них.
 *
 * @return array<int,array{role:string,fio:string}>
 */
function mentors_parse(string $raw): array {
    $raw = trim(preg_replace('~\s+~u', ' ', $raw));
    if ($raw === '') return [];

    /* Точка с запятой — разделитель наставников в новом формате. Запятая ею быть
     * не может: она встречается внутри старых записей между ФИО, и делить по ней
     * строку с должностями значило бы рвать «Педагог: Иванов И.И., Петрова А.А.»
     * на «Педагог: Иванов И.И.» и безымянную «Петрова А.А.». */
    $chunks = str_contains($raw, ';')
        ? preg_split('~\s*;\s*~u', $raw, -1, PREG_SPLIT_NO_EMPTY)
        : [$raw];

    $out = [];
    foreach ($chunks as $chunk) {
        $chunk = trim((string) $chunk);
        if ($chunk === '') continue;

        // «Должность: ФИО» — двоеточие есть только в новом формате.
        if (preg_match('~^([^:]{3,40}):\s*(.+)$~u', $chunk, $m)) {
            $role = trim($m[1]);
            $fio  = trim($m[2]);
            if ($fio !== '') { $out[] = ['role' => $role, 'fio' => $fio]; continue; }
        }

        /* Старая запись без должностей: несколько ФИО через запятую. Каждому
         * ставим «Педагог» — именно так эти записи и читались до сих пор, и
         * менять их смысл задним числом нельзя. */
        foreach (preg_split('~\s*,\s*~u', $chunk, -1, PREG_SPLIT_NO_EMPTY) ?: [] as $one) {
            $one = trim((string) $one);
            if ($one !== '') $out[] = ['role' => 'Педагог', 'fio' => $one];
        }
    }

    return array_slice($out, 0, MENTORS_MAX);
}

/**
 * Собирает список наставников обратно в строку для хранения.
 *
 * @param array<int,array{role?:string,fio?:string}> $list
 */
function mentors_format(array $list): string {
    $parts = [];
    foreach ($list as $m) {
        $fio  = trim((string) ($m['fio'] ?? ''));
        if ($fio === '') continue;
        $role = trim((string) ($m['role'] ?? '')) ?: 'Педагог';
        // Двоеточие и точка с запятой — служебные знаки формата, из имён их убираем,
        // иначе запись развалится при следующем разборе.
        $role = trim(str_replace([':', ';'], ' ', $role));
        $fio  = trim(str_replace([':', ';'], ' ', $fio));
        $parts[] = $role . ': ' . $fio;
        if (count($parts) >= MENTORS_MAX) break;
    }
    return implode('; ', $parts);
}

/** Только ФИО, через запятую — там, где должность не нужна (поиск, реестры). */
function mentors_fio(string $raw): string {
    $fios = array_map(static fn($m) => $m['fio'], mentors_parse($raw));
    return implode(', ', array_filter($fios));
}

/**
 * Строки для документа: «Педагог: Иванов И.И.», «Концертмейстер: Петрова А.А.».
 *
 * Одинаковые должности склеиваются в одну строку с общим заголовком во
 * множественном числе: два педагога на бланке — это «Педагоги: Иванов, Петров»,
 * а не две строки «Педагог» подряд, на которые в бланке просто нет места.
 *
 * @return array<string,string> заголовок => значение
 */
function mentors_doc_lines(string $raw): array {
    $byRole = [];
    foreach (mentors_parse($raw) as $m) {
        $byRole[$m['role']][] = $m['fio'];
    }
    $out = [];
    foreach ($byRole as $role => $fios) {
        $label = count($fios) > 1 ? mentors_role_plural($role) : $role;
        $out[$label] = implode(', ', $fios);
    }
    return $out;
}

/** Множественное число должности для бланка. */
function mentors_role_plural(string $role): string {
    $map = [
        'Педагог'                     => 'Педагоги',
        'Преподаватель'               => 'Преподаватели',
        'Руководитель'                => 'Руководители',
        'Концертмейстер'              => 'Концертмейстеры',
        'Балетмейстер'                => 'Балетмейстеры',
        'Хормейстер'                  => 'Хормейстеры',
        'Художественный руководитель' => 'Художественные руководители',
        'Директор'                    => 'Директора',
    ];
    return $map[$role] ?? $role;
}
