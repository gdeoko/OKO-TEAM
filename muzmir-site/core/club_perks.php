/** Пункты для карточки в письме: те, у которых mail = true. */
function club_perks_mail(int $discount = 0, int $days = 0): array {
    return array_values(array_filter(club_perks($discount, $days), static fn(array $p): bool => !empty($p['mail'])));
}
