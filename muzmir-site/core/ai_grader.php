/** Таблицы оценки заводятся лениво, как всё остальное в проекте. */
function ag_migrate(): void {
    static $done = false;
    if ($done) return;
    $done = true;
    try {
        db()->exec("CREATE TABLE IF NOT EXISTS grading_runs (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            application_id INTEGER NOT NULL,
            model TEXT DEFAULT '',
            status TEXT DEFAULT 'new',        -- new|ok|failed|skipped
            formal TEXT DEFAULT '',           -- JSON формальных проверок
            scores TEXT DEFAULT '',           -- JSON баллов по критериям
            total REAL DEFAULT 0,
            title TEXT DEFAULT '',            -- звание по шкале
            jury_comment TEXT DEFAULT '',     -- для участника
            internal_note TEXT DEFAULT '',    -- для оргкомитета
            confidence REAL DEFAULT 0,
            red_flags TEXT DEFAULT '',
            level_guess TEXT DEFAULT '',      -- звание прямым выбором модели, до перевода балла
            extra_award TEXT DEFAULT '',      -- предложенный дополнительный диплом ('' — не предлагается)
            extra_award_why TEXT DEFAULT '',  -- за что именно, с привязкой ко времени записи
            applied INTEGER DEFAULT 0,        -- решение перенесено в заявку
            applied_at TEXT DEFAULT '',
            error TEXT DEFAULT '',
            seconds REAL DEFAULT 0,
            created_at TEXT DEFAULT (datetime('now','localtime')))");
        // Поле появилось после первых сверок: на уже созданной таблице его надо добавить.
        try { db()->exec("ALTER TABLE grading_runs ADD COLUMN level_guess TEXT DEFAULT ''"); } catch (\Throwable $e) {}
        try { db()->exec("ALTER TABLE grading_runs ADD COLUMN extra_award TEXT DEFAULT ''"); } catch (\Throwable $e) {}
        try { db()->exec("ALTER TABLE grading_runs ADD COLUMN extra_award_why TEXT DEFAULT ''"); } catch (\Throwable $e) {}
        /* РЕКОМЕНДАЦИЯ ОТКЛОНИТЬ.
           Формальное нарушение положения — это не низкая оценка, а отказ. Раньше
           такая работа получала звание «ТРЕБУЕТ ПРОВЕРКИ» и уходила в общий
           список: жюри видело, что что-то не так, но не знало, что именно и по
           какому пункту, и заново разбиралось само. Теперь разбор сразу называет
           пункт положения и то, что увидел, — решение остаётся за человеком, но
           оно готово к одному нажатию. */
        try { db()->exec("ALTER TABLE grading_runs ADD COLUMN reject_hint TEXT DEFAULT ''"); } catch (\Throwable $e) {}
        db()->exec("CREATE INDEX IF NOT EXISTS idx_gr_app ON grading_runs(application_id)");
        db()->exec("CREATE INDEX IF NOT EXISTS idx_gr_status ON grading_runs(status)");
        db()->exec("CREATE TABLE IF NOT EXISTS grading_rubrics (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            nomination TEXT NOT NULL,
            subgroup TEXT DEFAULT '',
            payload TEXT NOT NULL,
            updated_at TEXT DEFAULT (datetime('now','localtime')))");
        db()->exec("CREATE UNIQUE INDEX IF NOT EXISTS idx_grub ON grading_rubrics(nomination, subgroup)");
    } catch (\Throwable $e) {}
}

/**
 * ПОТОЛКИ БАЛЛА ПО НАЗВАННЫМ НЕДОСТАТКАМ.
 *
 * Просить модель «не ставить выше 78, если назван зажим» бесполезно: она
 * называет зажим, дребезг, плоскую динамику и ученический характер — и ставит
 * 82-90, потому что исполнение звучит старательно. Здесь то же правило
 * применяется как арифметика, а не как пожелание: разбор остаётся её,
 * ограничение балла наше.
 *
 * Это продолжение общего принципа файла: модели доверяем наблюдения, а не
 * арифметику. Что названо в обосновании, то и определяет потолок.
 *
 * Формулировки взяты из требований экзаменационных систем: перечисленные
 * признаки означают, что задача решена не до конца, а значит уровень не выше
 * Merit, а по части признаков — не выше Pass.
 *
 * @return array{0:array,1:array} исправленные баллы и список ограничений
 */
function ag_apply_ceilings(array $scores): array {
    $rules = [
        // потолок => признаки в обосновании
        78 => ['зажим', 'зажат', 'скован', 'напряжен', 'напряжён', 'неверная постановка', 'неправильная постановка',
               'микропауз', 'просад', 'ускорен', 'замедлен', 'темп плыв', 'запазд', 'расхожден'],
        75 => ['дребезг', 'недожат', 'призвук', 'глух', 'срыв звука', 'блекл', 'поверхностн', 'сухов', 'тускл',
               'форсир', 'крикл', 'плоский звук'],
        // «Плоский» само по себе не признак: плоские пальцы левой руки это про
        // технику, а не про динамику. Берём только сочетания, где смысл однозначен.
        72 => ['плоская динамика', 'динамика плоск', 'динамический план плоск', 'плоский нюанс',
               'однообразн', 'ученическ', 'учебн', 'без фразировки', 'не хватает фразировки',
               'кульминация не', 'нет кульминации', 'сглажен', 'монотон', 'наигрыш', 'штамп',
               'образа нет', 'образ не создан'],
        70 => ['фальш', 'заниж', 'завыш', 'детонац', 'интонация плыв', 'мимо ноты', 'нечист', 'не строит'],
    ];
    $capped = [];
    foreach ($scores as $key => $c) {
        $note = mb_strtolower((string) ($c['note'] ?? ''));
        if ($note === '') continue;
        $limit = 100.0;
        $hit   = '';
        foreach ($rules as $cap => $words) {
            foreach ($words as $w) {
                if (str_contains($note, $w) && $cap < $limit) { $limit = (float) $cap; $hit = $w; }
            }
        }
        if ($limit < 100.0 && (float) $c['score'] > $limit) {
            $capped[] = sprintf('%s: %.0f → %.0f (названо «%s»)', (string) $c['title'], (float) $c['score'], $limit, $hit);
            $scores[$key]['score'] = $limit;
        }
    }
    return [$scores, $capped];
}

/**
 * ЗАМЕР СТРОЯ ПО ЗВУКОВОЙ ДОРОЖКЕ.
 *
 * Модель описывает исполнение хорошо, а высоту звука слышит плохо: на живой
 * работе с фальшью она дважды поставила высокий балл за интонацию, потому что
 * исполнение было уверенным и текст выученным. Поэтому интонация измеряется
 * отдельно и попадает в запрос как число, а не как впечатление.
 *
 * Замер идёт по основному тону, поэтому он честен для одноголосия (соло, пение,
 * духовые) и неполон для аккордов: фальшь внутри созвучия он не видит. Это
 * прямо сказано модели, чтобы она не выдавала ограниченный замер за приговор.
 *
 * @return array{} пусто, если замер невозможен
 */
function ag_pitch_measure(string $audio): array {
    if ($audio === '' || !is_file($audio)) return [];
    $py = BASE_PATH . '/scripts/pitch_check.py';
    if (!is_file($py)) return [];
    $out = [];
    @exec('timeout 180 python3 ' . escapeshellarg($py) . ' ' . escapeshellarg($audio) . ' 2>/dev/null', $out);
    $j = json_decode(trim(implode('', $out)), true);
    return (is_array($j) && !empty($j['ok'])) ? $j : [];
}

