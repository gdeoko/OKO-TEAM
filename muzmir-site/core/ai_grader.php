               'Оценка не проводилась: ' . (string) $rr['note'] . '. Работа не допускается по положению '
               . 'независимо от качества.', $runId]);
        } catch (\Throwable $e) {}
        return ['ok' => true, 'run_id' => $runId, 'total' => 0.0,
                'title' => 'ТРЕБУЕТ ПРОВЕРКИ', 'why' => (string) $rr['reason']];
    }

    // 1. Достаём запись.
