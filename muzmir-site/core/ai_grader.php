/**
 * Спросить модель через браузер агента на мосту.
 *
 * Файл на мост не передаём: мост забирает его сам по временной ссылке с сайта
 * (см. маршрут /grade-media в public/index.php). Так не нужен ни обратный ssh,
 * ни base64 в теле команды — конкурсная запись весит десятки мегабайт.
 *
 * @param  string   $prompt  задание для модели (тот же, что уходит в API)
 * @param  string[] $files   подготовленные дорожки: запись, звук, изображение
 * @return array{ok:bool, text:string, why:string}
 */
function ag_ask_bridge(string $prompt, array $files): array {
    $bad = static fn(string $w): array => ['ok' => false, 'text' => '', 'why' => $w];

    // Имена настроек те же, что у печати дипломов (core/diploma_render.php):
    // мост один, и заводить ему второй комплект ключей незачем.
    $poster = rtrim((string) cfgv('poster_url', ''), '/');
    $token  = (string) cfgv('poster_token', '');
    if ($poster === '' || $token === '') return $bad('мост не настроен (poster_url/poster_token)');

    $files = array_values(array_filter($files, 'is_file'));
    if (!$files) return $bad('нет подготовленных дорожек');

    // Раздаём файлы по одноразовой ссылке: имя не угадать, живёт полчаса,
    // чистится сразу после разбора (и по расписанию, если разбор оборвался).
    $share = BASE_PATH . '/data/grade_share';
    if (!is_dir($share)) @mkdir($share, 0775, true);
    $tag = bin2hex(random_bytes(16));
    $links = []; $copies = [];
    foreach ($files as $i => $f) {
        $ext  = strtolower(pathinfo($f, PATHINFO_EXTENSION)) ?: 'bin';
        $dst  = $share . '/' . $tag . '_' . $i . '.' . $ext;
        if (!@copy($f, $dst)) continue;
        $copies[] = $dst;
        $links[]  = ['url' => rtrim((string) (cfgv('site_url') ?: url('/')), '/') . '/grade-media/' . $tag . '/' . $i,
                     'name' => 'g' . $i . '.' . $ext];
    }
    if (!$links) return $bad('файлы не удалось выложить для моста');

    $rm = static function (array $paths): void { foreach ($paths as $p) @unlink($p); };

    /* БРАУЗЕР НА МОСТУ ОДИН, И ВКЛАДКА В НЁМ ОДНА.
     *
     * Два разбора одновременно попадают в одно и то же окно Gemini: второй
     * прикрепляет свои файлы поверх чужого вопроса, а ответ достаётся тому, кто
     * первый успел прочитать. Пока по ключу работали несколько потоков сразу,
     * это было нормально; с мостом — нет. Поэтому очередь: кто пришёл вторым,
     * ждёт до получаса и только потом сдаётся с понятной причиной. */
    $lockDir = BASE_PATH . '/data/locks';
    if (!is_dir($lockDir)) @mkdir($lockDir, 0775, true);
    $lock = @fopen($lockDir . '/bridge.lock', 'c');
    if ($lock) {
        $waited = 0;
        while (!flock($lock, LOCK_EX | LOCK_NB)) {
            if ($waited >= 1800) { fclose($lock); $rm($copies); return $bad('браузер агента занят другим разбором'); }
            sleep(5); $waited += 5;
        }
    }
    $unlock = static function () use ($lock): void {
        if ($lock) { flock($lock, LOCK_UN); fclose($lock); }
    };

    // Команда мосту: забрать файлы, положить задание, позвать драйвер, отдать ответ.
    $work = '/tmp/grade_' . $tag;
    $cmd  = 'set -e; mkdir -p ' . $work . '; cd ' . $work . '; ';
    $mfiles = [];
    foreach ($links as $l) {
        $cmd .= 'curl -sSL --max-time 300 -o ' . escapeshellarg($l['name']) . ' ' . escapeshellarg($l['url']) . '; ';
        $mfiles[] = $work . '/' . $l['name'];
    }
    $cmd .= 'printf %s ' . escapeshellarg($prompt) . ' > zadanie.txt; ';
    /* КАКОЙ БРАУЗЕР НА МОСТУ БЕРЁМ.
     *
     * Порт 9222 на мосту общий: там сидит браузер, которым пользуются и другие
     * задачи, и его выход может смотреть куда угодно. Для Gemini это решающе —
     * с российского или европейского адреса Google отдаёт витрину со словами
     * «Gemini пока не поддерживается в вашей стране» вместо приложения, и разбор
     * возвращается пустым. Поэтому у аттестации свой браузер с тем же входом, но
     * через выход США (порт 9333, профиль profiles/gemini_us). */
    $cdp = trim((string) (function_exists('setting') ? setting('grade_cdp', 'http://127.0.0.1:9333') : 'http://127.0.0.1:9333'));
    $cmd .= 'cd /opt/oko-poster && CHROME_CDP=' . escapeshellarg($cdp !== '' ? $cdp : 'http://127.0.0.1:9333')
          . ' NODE_PATH=/opt/oko-poster/node_modules timeout 900 node gemini_grade.mjs '
          . escapeshellarg($work . '/zadanie.txt') . ' ' . escapeshellarg($work . '/otvet.txt') . ' '
          . escapeshellarg(implode(',', $mfiles)) . ' 600 >/dev/null 2>&1 || true; ';
    $cmd .= 'echo "===OTVET==="; cat ' . escapeshellarg($work . '/otvet.txt') . ' 2>/dev/null; ';
    $cmd .= 'rm -rf ' . $work;

    $ch = curl_init($poster);
    curl_setopt_array($ch, [
        CURLOPT_POST => 1, CURLOPT_RETURNTRANSFER => 1, CURLOPT_TIMEOUT => 1200,
        CURLOPT_HTTPHEADER => ['Authorization: Bearer ' . $token, 'Content-Type: application/json'],
        CURLOPT_POSTFIELDS => json_encode(['cmd' => $cmd], JSON_UNESCAPED_SLASHES),
    ]);
    $resp = (string) curl_exec($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);
    $rm($copies);
    $unlock();

    if ($code !== 200) return $bad('мост ответил кодом ' . $code);

    // Мост отвечает конвертом {"exit":..,"stdout":..,"stderr":..}, а не голым выводом.
    $j   = json_decode($resp, true);
    $out = is_array($j) ? (string) ($j['stdout'] ?? '') : $resp;
    $pos = strpos($out, '===OTVET===');
    if ($pos === false) return $bad('мост не вернул ответ модели');
    $text = trim(substr($out, $pos + 11));
    if ($text === '') return $bad('браузер агента ответа не дал');
    return ['ok' => true, 'text' => $text, 'why' => ''];
}

/**
 * ПОДГОТОВКА ЗАПИСИ ДЛЯ МОДЕЛИ.
 *
 * Видео ужимаем до 480p и 12 кадров в секунду: для оценки чистоты линий,
 * синхронности и мимики этого достаточно, а объём падает в десятки раз. Звук
 * вынимаем отдельно и не жалеем на него битрейт — по нему оценивается всё, что
 * касается интонации, тембра и дикции.
 *
 * @return array{ok:bool, video:string, audio:string, seconds:int, why:string}
 */
function ag_prepare_media(string $path): array {
    $bad = static fn(string $w): array => ['ok' => false, 'video' => '', 'audio' => '', 'seconds' => 0, 'why' => $w];
    if (!is_file($path)) return $bad('файл записи не найден');

    /* РАБОТА МОЖЕТ БЫТЬ КАРТИНКОЙ, А НЕ ЗАПИСЬЮ.
     *
     * По изобразительному искусству, декоративно-прикладному творчеству и
     * фотографии участник присылает не видео, а изображение: снимок рисунка,
     * поделки, фотоработы. Конвейер же требовал видеодорожку и звук — ffmpeg
     * на картинке возвращал «Output file does not contain any stream», и весь
     * разбор считался неудачным. Из 47 работ по изобразительному искусству
     * оценённой оказалась одна: остальные молча висели «в очереди».
     *
     * Изображение отдаётся модели как есть, без ffmpeg: она разбирает рисунок
     * не хуже, чем видеозапись номера, а звука там нет и быть не должно. */
    if (preg_match('~\.(jpe?g|png|webp|heic|heif|bmp|tiff?)$~i', $path)) {
        return ['ok' => true, 'video' => '', 'audio' => '', 'image' => $path,
                'seconds' => 0, 'why' => ''];
    }

    $maxSec = max(60, (int) (function_exists('setting') ? setting('grade_video_max_sec', '900') : 900));
    $dur    = vf_duration($path);
    $stem   = preg_replace('~\.[a-z0-9]+$~i', '', $path);
    $video  = $stem . '_s.mp4';
    $audio  = $stem . '_a.mp3';

    // -an у видео: звук в этом файле не нужен, он поедет отдельной дорожкой.
    $cmdV = 'ffmpeg -y -loglevel error -i ' . escapeshellarg($path)
          . ' -t ' . $maxSec . ' -vf "scale=-2:480,fps=12" -c:v libx264 -preset veryfast -crf 30 -an '
          . escapeshellarg($video) . ' 2>&1';
    @exec($cmdV, $o1, $rc1);

    // Звук не жалеем. Прежняя дорожка (моно, 32 кГц, 96 кбит) съедала верхние
    // обертоны и биения — то самое, по чему слышна фальшь и расстроенный
    // инструмент. Для оценки интонации это решающие килогерцы, а лишний
    // мегабайт ничего не стоит.
    $cmdA = 'ffmpeg -y -loglevel error -i ' . escapeshellarg($path)
          . ' -t ' . $maxSec . ' -vn -ac 2 -ar 44100 -b:a 160k ' . escapeshellarg($audio) . ' 2>&1';
    @exec($cmdA, $o2, $rc2);

    $okV = $rc1 === 0 && is_file($video) && filesize($video) > 50000;
    $okA = $rc2 === 0 && is_file($audio) && filesize($audio) > 20000;
    if (!$okV && !$okA) return $bad('запись не читается: ' . mb_substr(implode(' ', array_slice($o1 ?: $o2 ?: [], 0, 2)), 0, 200));

    return ['ok' => true, 'video' => $okV ? $video : '', 'audio' => $okA ? $audio : '',
            'image' => '', 'seconds' => $dur, 'why' => ''];
}

/**
 * Загрузка файла в Gemini File API (простой протокол: один запрос со стартом,
 * второй с телом). Возвращает file_uri, который подставляется в запрос оценки.
 */
function ag_upload(string $file, string $mime, string $key): array {
    if (!is_file($file)) return ['ok' => false, 'uri' => '', 'why' => 'нет файла'];
    $size = (int) filesize($file);
    $base = ag_base();

    $ch = curl_init($base . '/upload/v1beta/files?key=' . rawurlencode($key));
    curl_setopt_array($ch, [
        CURLOPT_POST => 1, CURLOPT_RETURNTRANSFER => 1, CURLOPT_TIMEOUT => 60,
        CURLOPT_HEADER => 1,
        CURLOPT_HTTPHEADER => [
            'X-Goog-Upload-Protocol: resumable',
            'X-Goog-Upload-Command: start',
            'X-Goog-Upload-Header-Content-Length: ' . $size,
            'X-Goog-Upload-Header-Content-Type: ' . $mime,
            'Content-Type: application/json',
        ],
        CURLOPT_POSTFIELDS => json_encode(['file' => ['display_name' => basename($file)]]),
    ]);
    $resp = (string) curl_exec($ch);
    curl_close($ch);
    if (!preg_match('~x-goog-upload-url:\s*(\S+)~i', $resp, $m)) {
        return ['ok' => false, 'uri' => '', 'why' => 'сервис не принял начало загрузки'];
    }
    $up = trim($m[1]);

    $fh = fopen($file, 'rb');
    $ch = curl_init($up);
    curl_setopt_array($ch, [
        CURLOPT_CUSTOMREQUEST => 'POST',
        CURLOPT_RETURNTRANSFER => 1,
        CURLOPT_TIMEOUT => 900,
        CURLOPT_UPLOAD => 1,
        CURLOPT_INFILE => $fh,
        CURLOPT_INFILESIZE => $size,
        CURLOPT_HTTPHEADER => [
            'X-Goog-Upload-Offset: 0',
            'X-Goog-Upload-Command: upload, finalize',
            'Content-Type: ' . $mime,
        ],
    ]);
    $body = (string) curl_exec($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);
    if (is_resource($fh)) fclose($fh);

    $j = json_decode($body, true);
    $uri = (string) ($j['file']['uri'] ?? '');
    if ($code >= 400 || $uri === '') {
        return ['ok' => false, 'uri' => '', 'why' => 'загрузка не удалась (код ' . $code . ')'];
    }

    // Файл становится доступен не мгновенно: ждём состояния ACTIVE, иначе
    // запрос оценки вернёт «файл ещё обрабатывается» и попытка пропадёт зря.
    $name = (string) ($j['file']['name'] ?? '');
    for ($i = 0; $i < 30; $i++) {
        $st = json_decode((string) file_get_contents(ag_base() . '/v1beta/' . $name . '?key=' . rawurlencode($key)), true);
        $state = (string) ($st['state'] ?? '');
        if ($state === 'ACTIVE') break;
        if ($state === 'FAILED') return ['ok' => false, 'uri' => '', 'why' => 'сервис не смог обработать запись'];
        sleep(2);
    }
    return ['ok' => true, 'uri' => $uri, 'why' => ''];
}

