     *
     * Ключ остаётся запасным путём — если браузер агента не ответил (Google
     * поменял разметку, профиль потерял вход, машина занята), работа не должна
     * зависать в очереди: доспрашиваем через API, как раньше. */
    $raw = ''; $code = 0; $usedModel = ''; $gotFiles = false; $bridgeText = '';
    if (ag_transport() === 'bridge') {
        /* В API строгий JSON обеспечивает responseMimeType. В браузере такого
           рычага нет: модель охотно добавляет вступление, рассуждения и
           markdown-обёртку, и разбор рассыпается. Поэтому требование формата
           дописываем словами, отдельным последним абзацем — его модель видит
           непосредственно перед ответом. */
        $br = ag_ask_bridge($prompt . "\n\n"
            . 'ФОРМАТ ОТВЕТА. Верни РОВНО ОДИН объект JSON и больше ничего: '
            . 'без вступления, без пояснений после, без markdown и без слова JSON перед скобкой. '
            . 'Первый символ ответа — «{», последний — «}».', $uploaded);
        if ($br['ok'] && ag_parse_json($br['text'])) {
            $bridgeText = $br['text'];
            $gotFiles   = true;
            $usedModel  = 'браузер агента';
            $code       = 200;
        } else {
            // Печатаем начало ответа: без него «не разобран» ничего не объясняет,
            // а поправить промпт можно только увидев, что модель на самом деле ответила.
            error_log('ai_grade(' . $appId . '): мост не дал разбор ('
                . ($br['why'] ?: 'ответ не разобран') . ') — иду через ключ. Ответ моста: '
                . mb_substr(preg_replace('~\s+~u', ' ', (string) ($br['text'] ?? '')), 0, 300));
        }
    }
    foreach (($bridgeText === '' ? $keys : []) as $k2) {
        $parts = $uploadAll($k2);
        if (!$parts) continue;
        $gotFiles = true;
        $body = $mkBody($parts);
        foreach ($models as $mi => $mdl) {
            $ch = curl_init(ag_base() . '/v1beta/models/' . rawurlencode($mdl) . ':generateContent?key=' . rawurlencode($k2));
            curl_setopt_array($ch, [
                CURLOPT_POST => 1, CURLOPT_RETURNTRANSFER => 1, CURLOPT_TIMEOUT => 900,
                CURLOPT_HTTPHEADER => ['Content-Type: application/json'],
                CURLOPT_POSTFIELDS => json_encode($body, JSON_UNESCAPED_UNICODE),
            ]);
            $raw  = (string) curl_exec($ch);
            $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
            curl_close($ch);
            if ($code === 200) { $usedModel = $mdl; break 2; }
            // 429 и 503 проходят сами, остальные коды пробовать повторно незачем.
            if (!in_array($code, [429, 500, 502, 503, 504], true)) break 2;
            sleep(min(20, 3 + $mi * 4));
        }
    }
    if (!$gotFiles) {
        vf_cleanup($dl['path']);
        foreach ($uploaded as $f) @unlink($f);
        return $bad('запись не удалось передать на аттестацию', $runId);
    }
    if ($usedModel !== '' && $usedModel !== ag_model()) {
        try { q("UPDATE grading_runs SET model=? WHERE id=?", [$usedModel, $runId]); } catch (\Throwable $e) {}
    }

    // Временные файлы больше не нужны: запись принадлежит участнику.
    vf_cleanup($dl['path']);
    foreach ($uploaded as $f) @unlink($f);

    if ($code >= 400) {
        $j = json_decode($raw, true);
        return $bad('сервис оценки ответил ошибкой ' . $code . ': ' . mb_substr((string) ($j['error']['message'] ?? ''), 0, 200), $runId);
    }
    $j    = json_decode($raw, true);
    $text = $bridgeText !== ''
        ? $bridgeText
        : (string) ($j['candidates'][0]['content']['parts'][0]['text'] ?? '');
    $out  = ag_parse_json($text);
    if (!$out || empty($out['criteria'])) return $bad('ответ модели не разобран', $runId);

    // 5. Считаем сами: веса и границы званий — наша сторона, не модели.
    $total = 0.0; $wsum = 0; $scores = [];
    foreach ((array) ($rubric['criteria'] ?? []) as $key2 => $c) {
        $s = (float) ($out['criteria'][$key2]['score'] ?? -1);
        if ($s < 0) continue;
        $s = max(0.0, min(100.0, $s));
        $w = (int) $c['weight'];
        $total += $s * $w;
        $wsum  += $w;
        $scores[$key2] = ['title' => $c['title'], 'weight' => $w, 'score' => $s,
                          'note' => mb_substr((string) ($out['criteria'][$key2]['note'] ?? ''), 0, 900)];
    }
    if ($wsum === 0) return $bad('модель не поставила ни одной оценки', $runId);

    // Потолки по названным недостаткам: сначала ограничиваем баллы, потом
    // считаем сумму — иначе ограничение не дошло бы до итога.
    [$scores, $capped] = ag_apply_ceilings($scores);
    $total = 0.0;
    foreach ($scores as $c) $total += (float) $c['score'] * (int) $c['weight'];
    $total = $total / $wsum;
    // Два и больше ограничений означают добротную учебную работу, а не уровень
    // Distinction, каким бы уверенным ни было исполнение.
    if (count($capped) >= 2) $total = min($total, 82.0);

    // ПОПРАВКА ШКАЛЫ ПО СВЕРКЕ С ЖЮРИ.
    //
    // Машина может систематически строжить или мягчить относительно того, как
    // оценивает жюри именно этого центра. Это не ошибка критериев, а разница
    // калибровки, и правится она одним числом: scripts/ai_grade_calibrate.php
    // считает средний сдвиг по уже оценённым работам и записывает поправку.
    // Ноль означает «сверка показала совпадение, поправка не нужна».
    //
    // Важно: при квантильной шкале поправка НЕ применяется. Пороги званий там
    // считаются по сырым баллам разборов, и если сдвинуть балл до перевода в
    // звание, черта окажется не там, где её проводила сверка. Два способа
    // нормировать одно и то же, применённые подряд, дают не двойную точность,
    // а мусор.
    $scaleMode = (string) (function_exists('setting') ? setting('grade_scale_mode', 'linear') : 'linear');
    $gain  = $scaleMode === 'quantile' ? 1.0 : (float) (function_exists('setting') ? setting('grade_scale_gain', '1') : 1);
    $shift = $scaleMode === 'quantile' ? 0.0 : (float) (function_exists('setting') ? setting('grade_scale_shift', '0') : 0);
    // Своя поправка номинации сильнее общей: сверка показала, что в разных
    // номинациях машина ошибается в разные стороны, и одно число на всех
    // исправляет одну ценой другой.
    $nomFixAll = json_decode((string) (function_exists('setting') ? setting('grade_scale_by_nomination', '') : ''), true);
    $nomKey = trim((string) ($app['nomination'] ?? ''));
    if ($scaleMode !== 'quantile' && is_array($nomFixAll) && $nomKey !== '' && isset($nomFixAll[$nomKey]['gain'])) {
        $gain  = (float) $nomFixAll[$nomKey]['gain'];
        $shift = (float) $nomFixAll[$nomKey]['shift'];
    }
    if ($gain > 0 && ($gain !== 1.0 || $shift !== 0.0)) $total = $gain * $total + $shift;
    $total = round(max(0.0, min(100.0, $total)), 1);

    // Формальное нарушение снимает вопрос о звании: это отказ, а не оценка.
    $formal = (array) ($out['formal'] ?? []);
    $formalFail = [];
    foreach (gr_formal_checks() as $k => $_) {
        if (array_key_exists($k, $formal) && $formal[$k] === false) $formalFail[] = $k;
    }
    // ЗВАНИЕ ПО ПОРОГАМ СВЕРКИ, ЕСЛИ ОНИ ЗАДАНЫ.
    //
    // Пороги считает scripts/ai_grade_calibrate.php: он раздаёт звания в тех же
    // долях, в каких их даёт жюри центра, а порядок работ остаётся тем, который
    // выстроила машина по критериям. Пока сверки не было, работает общая шкала.
    $titleByScore = static function (float $sc): string {
        $mode = (string) (function_exists('setting') ? setting('grade_scale_mode', 'linear') : 'linear');
        if ($mode === 'quantile') {
            $th = json_decode((string) setting('grade_score_thresholds', ''), true);
            if (is_array($th) && $th) {
                foreach (['ГРАН-ПРИ', 'ЛАУРЕАТ I СТЕПЕНИ', 'ЛАУРЕАТ II СТЕПЕНИ', 'ЛАУРЕАТ III СТЕПЕНИ',
                          'ДИПЛОМАНТ I СТЕПЕНИ', 'ДИПЛОМАНТ II СТЕПЕНИ', 'ДИПЛОМАНТ III СТЕПЕНИ',
                          'УЧАСТНИК КОНКУРСА'] as $t) {
                    if (isset($th[$t]) && $sc >= (float) $th[$t]) return $t;
                }
                return 'УЧАСТНИК КОНКУРСА';
            }
        }
        return gr_title_by_score($sc);
    };
    // ЗВАНИЕ ПРЯМЫМ ВЫБОРОМ.
    //
    // По баллам машина различает работы плохо: почти всё ложится в 76-80, и
    // черта между званиями проходит по разнице в полбалла, которая ничего не
    // значит. Отдельным вопросом «какое звание ты присудила бы» она отвечает
    // увереннее, потому что сравнивает работу с эталонами целиком, а не через
    // сумму весов. Балл остаётся: он объясняет решение и держит порядок работ.
    $lvlRaw   = mb_strtoupper(trim((string) ($out['level'] ?? '')));
    $levels   = ['ГРАН-ПРИ', 'ЛАУРЕАТ I СТЕПЕНИ', 'ЛАУРЕАТ II СТЕПЕНИ', 'ЛАУРЕАТ III СТЕПЕНИ',
                 'ДИПЛОМАНТ I СТЕПЕНИ', 'ДИПЛОМАНТ II СТЕПЕНИ', 'ДИПЛОМАНТ III СТЕПЕНИ', 'УЧАСТНИК КОНКУРСА'];
    $levelPick = in_array($lvlRaw, $levels, true) ? $lvlRaw : '';
    $byScore   = $titleByScore($total);
    // Способ выбора звания задаётся настройкой, потому что решает его не спор о
    // подходе, а сверка с жюри: что показало лучшее совпадение, то и стоит.
    $src = (string) (function_exists('setting') ? setting('grade_title_source', 'score') : 'score');
    $title = $byScore;
    if ($levelPick !== '') {
        if ($src === 'level') {
            $title = $levelPick;
        } elseif ($src === 'mix') {
            // Середина между двумя решениями, при расхождении в пользу строгого:
            // завышенное звание дороже заниженного, его придётся отзывать.
            $ri = array_flip($levels);                 // 0 — высшее
            $m  = (int) ceil((($ri[$byScore] ?? 4) + $ri[$levelPick]) / 2);
            $title = $levels[max(0, min(count($levels) - 1, $m))];
        }
    }
    /* ПОПРАВКА ПО ПРАВКАМ ЖЮРИ.
     *
     * Машина предлагает, человек ставит своё — и если центр раз за разом
     * поправляет предложение в одну сторону, следующая оценка должна это
     * учитывать, а не повторять ту же ошибку в сотый раз. Поправка считается по
     * накопленным решениям (медиана расхождения в ступенях) и включается только
     * на статистике: по номинации от пяти правок, общая от пятнадцати.
     *
     * Применяется ДО потолка за фонограмму: потолок — пункт положения, он выше
     * любой калибровки и должен оставаться последним словом. */
    if (is_file(BASE_PATH . '/core/grade_feedback.php')) {
        require_once BASE_PATH . '/core/grade_feedback.php';
        $bias = gfb_bias((string) ($app['nomination'] ?? ''));
        if (($bias['steps'] ?? 0) !== 0) {
            $before = $title;
            $title  = gfb_shift_title($title, (int) $bias['steps']);
            if ($title !== $before) {
                $capped[] = sprintf('поправка по решениям жюри (%s, %d правок): %s → %s',
                                    $bias['scope'], (int) $bias['n'], $before, $title);
            }
        }
    }

    /* ФОНОГРАММА — ПОТОЛОК ДИПЛОМАНТА, ЭТО ПУНКТ ПОЛОЖЕНИЯ, А НЕ МНЕНИЕ.
     *
     * П. 8.7 всех положений: «За использование фонограммы (согласно номинации),
     * оценка автоматически будет снижена компетентным жюри, до ДИПЛОМАНТа».
     * Раз это записано в положении, решение не может зависеть от того, насколько
     * ярким показался номер: лауреатское звание под фонограмму участник вправе
     * оспорить, показав нам наш же документ. Звание опускается до ДИПЛОМАНТА I,
     * а балл — до его верхней границы, чтобы балл и звание не расходились. */
    $phono = !empty($out['phonogram']);
    if ($phono) {
        $capIdx = array_search('ДИПЛОМАНТ I СТЕПЕНИ', $levels, true);
        $curIdx = array_search($title, $levels, true);
        if ($curIdx !== false && $capIdx !== false && $curIdx < $capIdx) {
            $title = $levels[$capIdx];
            $ceil  = function_exists('gr_score_floor') ? gr_score_floor('ДИПЛОМАНТ II СТЕПЕНИ') : 70.0;
            $total = min($total, max(0.0, $ceil + 4.9));   // верх дипломанта I
            // Формулировка общая (core/presets.php): у автоматической аттестации
            // и у жюри причина снижения записана одними и теми же словами.
            if (!defined('PHONOGRAM_NOTE')) require_once BASE_PATH . '/core/presets.php';
            $capped[] = PHONOGRAM_NOTE;
        }
    }

    if ($formalFail) $title = 'ТРЕБУЕТ ПРОВЕРКИ';

    $extraAward = mb_strtoupper(trim((string) ($out['extra_award'] ?? '')));
    $extraWhy   = mb_substr(trim((string) ($out['extra_award_why'] ?? '')), 0, 500);
    // Формулировка без обоснования, слишком длинная или не начинающаяся с «ЗА»
    // отбрасывается: такой диплом человеку не защитить перед участником.
    if ($extraAward !== '' && (!str_starts_with($extraAward, 'ЗА ') || mb_strlen($extraAward) > 60 || $extraWhy === '')) {
        $extraAward = '';
        $extraWhy   = '';
    }
    // Формальное нарушение снимает и дополнительный диплом: сначала решение человека.
    if ($formalFail) { $extraAward = ''; $extraWhy = ''; }

    $upd = [
        'status'        => 'ok',
        'formal'        => json_encode($formal, JSON_UNESCAPED_UNICODE),
        'scores'        => json_encode($scores, JSON_UNESCAPED_UNICODE),
        'total'         => $total,
        'title'         => $title,
        'level_guess'   => $levelPick,
        // Дополнительный диплом: формулировка приводится к виду, принятому в
        // центре (заглавными, с «ЗА»), и не принимается без обоснования —
        // иначе он превращается в украшение, раздаваемое каждому второму.
        'extra_award'     => $extraAward,
        'extra_award_why' => $extraWhy,
        'jury_comment'  => mb_substr(trim((string) ($out['jury_comment'] ?? '')), 0, 4000),
        'internal_note' => mb_substr(trim(
            ($capped ? 'Баллы ограничены по названным недостаткам: ' . implode('; ', $capped) . '. ' : '')
            . (string) ($out['internal_note'] ?? '')), 0, 2000),
        'confidence'    => max(0.0, min(1.0, (float) ($out['confidence'] ?? 0))),
        'red_flags'     => json_encode(array_values((array) ($out['red_flags'] ?? [])), JSON_UNESCAPED_UNICODE),
        'seconds'       => round(microtime(true) - $t0, 1),
    ];
    /* СБОЙ ЗАПИСИ НЕ ДОЛЖЕН БЫТЬ НЕМЫМ.
     *
     * Раньше здесь стоял пустой catch. Когда сохранение падало, разбор всё равно
     * возвращал звание и балл, а в базе запись оставалась в состоянии «new» — со
     * стороны это выглядело как «оценка не работает», хотя работало всё, кроме
     * одной строки. Теперь причина видна и в самой записи, и в журнале. */
    try {
        update('grading_runs', $upd, 'id=:id', ['id' => $runId]);
    } catch (\Throwable $e) {
        $why = 'разбор получен, но не сохранён: ' . mb_substr($e->getMessage(), 0, 300);
        error_log('ag_grade_application(' . $appId . '): ' . $why);
        try { q("UPDATE grading_runs SET status='failed', error=? WHERE id=?", [$why, $runId]); } catch (\Throwable $e2) {}
        return ['ok' => false, 'run_id' => $runId, 'total' => 0.0, 'title' => '', 'why' => $why];
    }

    /* ГОТОВАЯ ПРИЧИНА ОТКЛОНЕНИЯ — СРАЗУ, А НЕ ПОТОМ.
     *
     * Если положение нарушено, работе не звание нужно, а отказ. Считаем причину
     * здесь же, словами положения и с номером пункта, и кладём в разбор: в
     * списке жюри увидит «отклонить» вместо непонятного «требует проверки», а в
     * карточке причина уже подставлена в форму. Само отклонение не происходит:
     * в режиме подсказки решает человек, в полном автомате — cron/ai_grade. */
    /* ВОЗРАСТ У САМОЙ ГРАНИЦЫ. Работа разобрана и звание посчитано, но материал
       старше срока на считанные дни. Отказывать машине здесь нельзя (владелец в
       таких случаях принимал), забыть тоже нельзя — поэтому причина ложится в
       подсказку рядом с готовой оценкой, и человек выбирает одно из двух. */
    if (($ageEdge ?? '') !== '') {
        try {
            update('grading_runs', ['reject_hint' => mb_substr($ageEdge, 0, 900)], 'id=:id', ['id' => $runId]);
        } catch (\Throwable $e) {}
    }

    if ($formalFail) {
        try {
            $runRow = one("SELECT * FROM grading_runs WHERE id=?", [$runId]);
            $compRow = one("SELECT c.* FROM competitions c
                             JOIN applications a ON a.competition_id = c.id WHERE a.id=?", [$appId]);
            [$doReject, $reason] = ag_auto_reject((array) $runRow, (array) $compRow);
            // Даже когда до автоматического отказа не дотягивает (мало уверенности
            // или нарушение из спорных), причину показать полезно: человеку она
            // экономит разбор, а решение всё равно его.
            if (!$doReject && $reason === '') {
                $names = [];
                foreach (gr_formal_checks() as $k => $text) {
                    if (array_key_exists($k, $formal) && $formal[$k] === false) $names[] = $text;
                }
                $issues = (array) ($formal['issues'] ?? []);
                $reason = $names ? ('Нарушение требований к конкурсному материалу: ' . implode(' ', $names)) : '';
                if ($reason !== '' && $issues) $reason .= "\n\nЧто именно: " . mb_substr(implode('; ', array_map('strval', $issues)), 0, 400);
            }
            if ($reason !== '') {
                update('grading_runs', ['reject_hint' => mb_substr($reason, 0, 900)], 'id=:id', ['id' => $runId]);
            }
        } catch (\Throwable $e) { /* подсказка не важнее разбора */ }
    }

    return ['ok' => true, 'run_id' => $runId, 'total' => $total, 'title' => $title, 'why' => ''];
}

/**
 * МОЖНО ЛИ ПРИМЕНИТЬ ОЦЕНКУ БЕЗ ЧЕЛОВЕКА.
 *
 * Даже в полностью автоматическом режиме есть случаи, где решение обязан
 * принять человек: формальное нарушение (это отказ и возврат взноса), низкая
 * уверенность модели, тревожные признаки и края шкалы. Гран-при и отказ имеют
 * последствия за пределами одной заявки, и ошибка здесь стоит дороже, чем
 * задержка на день.
 */
function ag_can_apply(array $run): array {
    $minConf = (float) (function_exists('setting') ? setting('grade_min_confidence', '0.75') : 0.75);
    $flags   = (array) json_decode((string) ($run['red_flags'] ?? '[]'), true);
    $formal  = (array) json_decode((string) ($run['formal'] ?? '[]'), true);
    $title   = (string) ($run['title'] ?? '');

    foreach (gr_formal_checks() as $k => $_) {
        if (array_key_exists($k, $formal) && $formal[$k] === false) {
            return [false, 'формальное несоответствие положению (' . $k . ') — решает человек'];
        }
    }
    if ($flags)                                   return [false, 'есть тревожные признаки: ' . mb_substr(implode('; ', $flags), 0, 200)];
    if ((float) ($run['confidence'] ?? 0) < $minConf) return [false, 'низкая уверенность оценки'];
    // ПОГРАНИЧНЫЙ БАЛЛ.
    //
    // Повторный разбор одной и той же записи даёт расхождение около балла: это
    // свойство любой оценки, машинной и человеческой. Внутри ступени такое
    // расхождение ничего не меняет, а у самой черты меняет звание. Проверка на
    // работах центра показала это прямо: 94.0 и 95.1 у одной записи, то есть
    // «лауреат первой степени» и «Гран-при». Поэтому работы у границы уходят
    // человеку: решает не арифметика, а тот, кто подпишет диплом.
    $edge  = (float) (function_exists('setting') ? setting('grade_edge_margin', '1.5') : 1.5);
    $floor = gr_score_floor($title);
    $tot   = (float) ($run['total'] ?? 0);
    if ($edge > 0 && $floor > 0 && abs($tot - $floor) < $edge) {
        return [false, sprintf('балл %.1f у самой границы звания (%.0f) — решает человек', $tot, $floor)];
    }
    if ($title === 'ГРАН-ПРИ')                    return [false, 'Гран-при подтверждает человек'];
    if ($title === 'УЧАСТНИК КОНКУРСА')           return [false, 'работа без звания — решает человек'];
    if ($title === 'ТРЕБУЕТ ПРОВЕРКИ')            return [false, 'работа отмечена для проверки'];
    return [true, ''];
}

/**
 * ОТКЛОНИТЬ ЛИ ЗАЯВКУ АВТОМАТИЧЕСКИ ПО НАРУШЕНИЮ ПОЛОЖЕНИЯ.
 *
 * Правила площадки — это не совет, а условие участия: работа с монтажом или
 * чужим исполнением не может получить звание. Раньше такие заявки просто
 * складывались в очередь к человеку, и участник неделями ждал результат, которого
 * по положению быть не может.
 *
 * Но отклонение необратимо и стоит денег: у платной заявки уходит возврат, а
 * участнику — письмо о снятии с конкурса. Поэтому автоматически отклоняем ТОЛЬКО
 * то, что видно однозначно и названо пунктом положения:
 *
 *   integrity   — монтаж, склейки, стоп-кадры внутри номера (п. 8.5);
 *   no_overdub  — студийный вокал поверх живого исполнения (п. 8.5);
 *   one_piece   — в одной заявке несколько номеров (п. 8.1);
 *   nomination  — работа не той номинации, что заявлена (п. 4.2);
 *   playable    — записи нет: не открывается, нет звука или изображения (п. 8.6).
 *
 * Спорное остаётся человеку: состав (дуэт приняли за трио), продолжительность,
 * личность участника — там ошибка машины стоит участия живому человеку.
 * И даже разрешённое нарушение отклоняется лишь при высокой уверенности разбора.
 *
 * @return array{0:bool,1:string} [отклонять ли, причина 1:1 из положения]
 */
function ag_auto_reject(array $run, array $comp = []): array {
    if ((string) (function_exists('setting') ? setting('grade_auto_reject', '1') : '1') !== '1') {
        return [false, ''];
    }
    $formal = (array) json_decode((string) ($run['formal'] ?? '[]'), true);
    $conf   = (float) ($run['confidence'] ?? 0);
    $minConf = (float) (function_exists('setting') ? setting('grade_reject_confidence', '0.85') : 0.85);

    // Ключ нарушения → ключ основания в REJECT_REASONS.
    $map = [
        'integrity'  => 'montazh',
        'no_overdub' => 'montazh',
        'one_piece'  => 'odna',
        'nomination' => 'п. 4.2',
        'playable'   => 'video',
    ];
    $hit = '';
    foreach ($map as $check => $_) {
        if (array_key_exists($check, $formal) && $formal[$check] === false) { $hit = $check; break; }
    }
    if ($hit === '') return [false, ''];
    if ($conf < $minConf) return [false, ''];

    if (!function_exists('REJECT_REASONS')) require_once BASE_PATH . '/core/presets.php';
    $reasons = REJECT_REASONS($comp);

    // Подбираем формулировку из списка оснований: она уже написана словами
    // положения и с номером пункта, значит участнику её можно показать как есть.
    $needle = [
        'integrity'  => 'монтаж',
        'no_overdub' => 'монтаж',
        'one_piece'  => 'одной заявкой',
        'nomination' => 'заполнена неверно',
        'playable'   => 'ненадлежащего качества',
    ][$hit] ?? '';
    $reason = '';
    foreach ($reasons as $text) {
        if ($needle !== '' && mb_stripos($text, $needle) !== false) { $reason = $text; break; }
    }
    if ($reason === '') return [false, ''];

    // К основанию добавляем, что именно увидел разбор: участник должен понимать,
    // о каком месте записи речь, а не получать голый номер пункта.
    $issues = (array) ($formal['issues'] ?? []);
    $note   = trim(implode('; ', array_map('strval', array_slice($issues, 0, 2))));
    if ($note !== '') $reason .= "\n\nЧто именно: " . mb_substr($note, 0, 400);

    return [true, $reason];
}
