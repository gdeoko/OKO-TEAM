            if ($f === '' || !is_file($f)) continue;
            $up = ag_upload($f, $mime, $key);
            if (!$up['ok']) continue;
            $parts[] = ['file_data' => ['mime_type' => $mime, 'file_uri' => $up['uri']]];
        }
        return $parts;
    };
