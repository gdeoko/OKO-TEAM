                try {
                    q("UPDATE grading_runs SET status='failed', error=?, reject_hint=? WHERE id=?",
                      [mb_substr($why, 0, 500), mb_substr($why, 0, 900), $runId]);
                } catch (\Throwable $e) {}
                return ['ok' => false, 'run_id' => $runId, 'total' => 0.0, 'title' => '', 'why' => $why];
            }
