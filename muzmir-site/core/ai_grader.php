    }

    /* 0б. ОСНОВАНИЯ, ВИДНЫЕ ПО ОДНОЙ ССЫЛКЕ.
     *
     * Общая папка класса вместо своей работы и запрещённая площадка не требуют
     * ни скачивания, ни модели: причина известна заранее и написана словами
