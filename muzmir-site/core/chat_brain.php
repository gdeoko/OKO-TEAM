/**
 * Снять представление из ответа мозга, если оператор уже представился строкой
 * приветствия. Иначе выходит «Меня зовут Михаил… Меня зовут Михаил»: правила
 * разрешают представиться, и в первом ответе модель делает это охотно.
 * Режем только НАЧАЛО ответа и только собственное имя оператора.
 */
function chat_strip_selfintro(string $text, string $self): string {
    $self = trim($self);
    if ($self === '' || $text === '') return $text;
    $nm = preg_quote($self, '~');

    /* 1. Начало ответа: «Здравствуйте! Меня зовут Михаил, рад помочь.» —
          уходит вместе с приветствием, его мы уже сказали строкой выше. */
    $out = preg_replace('~^\s*(?:Здравствуйте[^.!?\n]*[.!?]\s*)?Меня зовут\s+'
        . $nm . '[^.!?\n]*[.!?]\s*~u', '', $text, 1);
    if (!is_string($out) || trim($out) === '') $out = $text;

    /* 2. ПРЕДСТАВЛЕНИЕ БЫВАЕТ И В СЕРЕДИНЕ: «Заявку подают на сайте. Меня зовут
          Михаил — обращайтесь.» Берём предложение целиком, но только то, которое
          С НЕГО НАЧИНАЕТСЯ: «диплом на имя Михаила Петрова» трогать нельзя.
          Взгляд назад ровно на два знака (точка и пробел) — переменной длины
          PCRE не допускает. */
    $out2 = preg_replace('~(?<=[.!?]\s)Меня зовут\s+' . $nm . '[^.!?\n]*[.!?]\s*~u', '', (string) $out);
    if (is_string($out2) && trim($out2) !== '') $out = $out2;

    return trim((string) $out);
}

/**
 * Снять второе «Здравствуйте» из ответа мозга: поздоровались мы сами, строкой
 * приветствия с именем. Режем ТОЛЬКО начало и только само приветствие — если за
 * ним сразу идёт дело («Здравствуйте! Заявку подают на сайте»), дело остаётся.
 */
/**
 * ЗА ДАТОЙ И СРОКОМ В ПОЛОЖЕНИЕ НЕ ОТПРАВЛЯЕМ: ИХ ТАМ НЕТ.
 *
 * Сверено по всем 40 пунктам положений: ни одной даты и ни одного срока в них
 * нет вовсе, там только правила. Дата оглашения стоит у карточки конкурса, срок
 * результата считает код от даты подачи (`core/send_timing.php`).
 *
 * Правило об этом в промпте стоит, и модель его слушает через раз: живой ответ
 * 13.10 всё равно кончился словами «публикуется в дату, указанную на странице
 * конкурса и в его положении». Для человека это прямое указание пойти и
 * прочитать то, чего нет, - и он возвращается с тем же вопросом, уже сердитый.
 *
 * Поэтому ссылка на положение за ДАТОЙ или СРОКОМ снимается по факту. Правила,
 * номинации и требования к видео в положении есть, и упоминать их можно: шаблон
 * узкий, он требует рядом слово «дата» или «срок».
 */
function chat_fix_reg_dates(string $t): string {
    if ($t === '' || mb_stripos($t, 'положени') === false) return $t;

    /* РАЗБИРАЕМ ПО ПРЕДЛОЖЕНИЯМ, А НЕ ПО ВСЕМУ ОТВЕТУ.
       Сплошной шаблон по тексту давал две беды сразу: обрывал фразу
       («оглашаются в дату, указанную.») и залезал в чужое предложение. */
    $куски = preg_split('~(?<=[.!?])(\s+)~u', $t, -1, PREG_SPLIT_DELIM_CAPTURE) ?: [$t];

    foreach ($куски as $k => $фраза) {
        if (mb_stripos((string) $фраза, 'положени') === false) continue;

        /* ИСКЛЮЧЕНИЕ, И ОНО ВАЖНОЕ: срок ВОЗВРАТА ВЗНОСА в положении правда
           есть - пункт 7.10, десять рабочих дней. Там же живут правила,
           номинации и требования к видео. Если в предложении речь о взносе,
           возврате или названном пункте, оно верное и трогать его нельзя. */
        if (preg_match('~взнос|возврат|пункт|п\.\s*\d~ui', (string) $фраза)) continue;

        /* Дальше - только предложения про ДАТУ или СРОК. */
        if (!preg_match('~дат\w*|срок\w*~ui', (string) $фраза)) continue;

        if (preg_match('~страниц\w*|карточк\w*|афиш\w*|раздел\w*~ui', (string) $фраза)) {
            /* Верное место уже названо, положение приписано рядом - снимаем
               только приписку: «в дату, указанную на странице конкурса и в его
               положении» → «…на странице конкурса». */
            $o = preg_replace('~\s*(?:,|и)?\s+(?:а\s+)?(?:так\s*же\s+)?в\s+'
                . '(?:его\s+|данном\s+|соответствующем\s+)?положени\w+~ui', '', (string) $фраза);
        } else {
            /* Верного места нет вовсе - называем его: «Сроки указаны в
               положении конкретного конкурса» → «…у карточки конкурса». */
            $o = preg_replace('~в\s+(?:его\s+|данном\s+|конкретного\s+конкурса\s+)?положени\w+'
                . '(?:\s+конкретного\s+конкурса|\s+конкурса)?~ui', 'у карточки конкурса', (string) $фраза);
            /* ТОТ ЖЕ ОБМАН В ТВОРИТЕЛЬНОМ ПАДЕЖЕ: «в дату, установленную
               ПОЛОЖЕНИЕМ конкурса». Предлога «в» нет, и правило выше его не
               видело - живой ответ так и вышел. Падеж причастия не трогаем
               («установленную», «установленный», «установленной» - любое), меняем
               только само слово: дату назначает ОРГКОМИТЕТ, и это и правда, и
               чистая фраза в любом падеже. */
            $o2 = preg_replace('~положени(?:ем|ями)(?:\s+(?:данного\s+|этого\s+)?конкурса)?~ui',
                'оргкомитетом', (string) $o);
            if (is_string($o2) && trim($o2) !== '') $o = $o2;
        }
        if (is_string($o) && trim($o) !== '') $куски[$k] = $o;
    }

    $out = implode('', $куски);
    return trim($out) !== '' ? $out : $t;
}

function chat_strip_hello(string $text): string {
    if ($text === '') return $text;
    $out = preg_replace('~^\s*(?:Здравствуйте|Добрый день|Доброе утро|Добрый вечер|Приветствую)'
        . '[^.!?\n]*[.!?]\s*~u', '', $text, 1);
    return (is_string($out) && trim($out) !== '') ? ltrim($out) : $text;
}

/**
 * Нужно ли здороваться в этом сообщении. Здороваемся один раз в начале диалога
 * и снова после перерыва 24 часа или после завершения предыдущего диалога.
 * Считаем: есть ли наш ответ в этой сессии за последние 24 часа и после
 * последнего маркера завершения диалога. Нет — значит это начало нового диалога.
 */
function chat_should_greet(string $sessionKey): bool {
    try {
        $lastEndId = (int) (scalar("SELECT MAX(id) FROM chat_messages WHERE session_key=? AND role='dialog_end'", [$sessionKey]) ?: 0);
        $recent = (int) scalar(
            "SELECT COUNT(*) FROM chat_messages WHERE session_key=? AND role IN ('assistant','assistant_followup') AND id>? AND created_at > datetime('now','localtime','-1 day')",
            [$sessionKey, $lastEndId]
        );
        return $recent === 0;
    } catch (\Throwable $e) {
        return true;
    }
}

/** Пользователь завершает диалог: «спасибо», «пока», «всё понятно» и т.п. */
/**
 * Прощание ли это.
 *
 * ВАЖНО: сообщение должно СОСТОЯТЬ из благодарности, а не содержать её.
 * Раньше слово-маркер искалось в любом месте текста любой длины — и фраза
 * «Спасибо, а когда придёт диплом?» распознавалась как конец разговора: «мозг»
 * не вызывался вовсе, вместо ответа уходило «Рады были Вам помочь», а сам вопрос
 * исчезал. Люди в России почти всегда начинают вопрос с «спасибо» или
 * «благодарю» — то есть съедался каждый второй вопрос.
 *
 * Правило: есть вопросительный знак — не прощание. Осталось значимое слово после
 * вычёркивания вежливости — не прощание.
 */
function chat_is_closing(string $text): bool {
    $t = mb_strtolower(trim($text));
    if ($t === '') return false;
    if (mb_strpos($t, '?') !== false) return false;          // в вопросе прощания нет

    // Убираем пунктуацию и эмодзи, оставляем буквы, цифры и пробелы.
    $t = preg_replace('~[^\p{L}\p{N}\s]+~u', ' ', $t);
    $t = trim(preg_replace('~\s+~u', ' ', (string) $t));
    if ($t === '') return false;

    // Формулы прощания и вежливости целиком.
    $phrases = ['спасибо большое', 'большое спасибо', 'огромное спасибо', 'спасибо вам',
                'до свидания', 'всего доброго', 'всего хорошего', 'хорошего дня', 'доброго дня',
                'всё понятно', 'все понятно', 'всё ясно', 'все ясно', 'вопросов нет',
                'больше вопросов нет', 'больше вопросов', 'вы мне помогли', 'вы помогли',
                'я разобрался', 'я разобралась', 'уже разобрался', 'уже разобралась'];
    foreach ($phrases as $p) $t = trim((string) str_replace($p, ' ', $t));
    $t = trim(preg_replace('~\s+~u', ' ', $t));

    // Отдельные слова вежливости и «шум».
    $words = ['спасибо', 'спс', 'спасиб', 'благодарю', 'благодарствую', 'благодарим', 'благодарность',
              'пока', 'ок', 'окей', 'хорошо', 'ясно', 'понятно', 'понял', 'поняла', 'принято',
              'угу', 'ага', 'да', 'нет', 'всё', 'все', 'здорово', 'отлично', 'супер', 'класс',
              'помогли', 'разобрался', 'разобралась', 'вам', 'мне', 'и', 'а', 'ну', 'вот'];
    $rest = [];
    foreach (explode(' ', $t) as $w) {
        $w = trim($w);
        if ($w === '' || in_array($w, $words, true)) continue;
        $rest[] = $w;
    }

    // Прощание — только если после вычёркивания вежливости ничего не осталось
    // и при этом что-то вежливое в сообщении действительно было.
    if ($rest) return false;
    return (bool) preg_match(
        '~спасиб|спс|благодар|пока|свидан|доброго|хорошего дня|ясно|понятн|вопросов нет|помогли|разобрал~u',
        mb_strtolower(trim($text))
    );
}

