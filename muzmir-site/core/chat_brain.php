 *
 * Имени страницы часто нет: у Николая Буланова (аккаунт 9883, девять заявок,
 * пятнадцать заказов) страница ВК подписана одним словом «Николай», и
 * 22.10.2026 бот пригласил его «зарегистрироваться на сайте». Зато в
 * разговоре почти всегда есть то, что однозначно ведёт к аккаунту:
 *   • почта или телефон, которые человек написал сам;
 *   • номер заявки (TT-2026-00096) или заказа («заказ №690»), названный в
 *     диалоге кем угодно — участником, ботом или оператором.
 * Подходит, если по признаку нашёлся аккаунт с заявками или заказами.
 *
 * Правило то же, что у сверки по имени: ответ — только «да/нет», чтобы
 * ПРОМОЛЧАТЬ о регистрации. Номер аккаунта наружу не отдаём: педагог мог
 * написать почту ученика, и раскрывать по ней чьи-то данные нельзя.
 */
function chat_vk_kabinet_po_perepiske(string $sessionKey): bool {
    try {
        $rows = all("SELECT role, text FROM chat_messages
                      WHERE session_key=? AND text<>''
                        AND created_at > datetime('now','localtime','-90 days')
                   ORDER BY id DESC LIMIT 300", [$sessionKey]);
    } catch (\Throwable $e) { return false; }
    $emails = $phones = $apps = $orders = [];
    foreach ($rows as $r) {
        $tx = (string) $r['text'];
        if (preg_match_all('~[A-Za-z]{2,4}-20\d\d-\d{4,5}~u', $tx, $m)) foreach ($m[0] as $x) $apps[mb_strtoupper($x)] = 1;
        if (preg_match_all('~заказ\w*\s*(?:№|N|#)\s*(\d{2,6})~ui', $tx, $m)) foreach ($m[1] as $x) $orders[(int) $x] = 1;
        // Почту и телефон берём только из слов самого участника: в ответах
        // центра стоят адреса и номера центра.
        if ((string) $r['role'] !== 'user') continue;
        if (preg_match_all('~[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}~u', $tx, $m)) foreach ($m[0] as $x) $emails[mb_strtolower($x)] = 1;
        if (preg_match_all('~(?:\+7|8)[\s\-(]*\d{3}[\s\-)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}~u', $tx, $m)) {
            foreach ($m[0] as $x) { $d = preg_replace('~\D~', '', $x); if (strlen($d) >= 10) $phones[substr($d, -10)] = 1; }
        }
    }
    $has = "(EXISTS (SELECT 1 FROM applications a WHERE a.user_id = u.id)
             OR EXISTS (SELECT 1 FROM awards_orders o WHERE o.user_id = u.id))";
    try {
        foreach (array_slice(array_keys($emails), 0, 10) as $e) {
            if ((int) (scalar("SELECT u.id FROM users u WHERE lower(trim(u.email))=? AND $has LIMIT 1", [$e]) ?: 0) > 0) return true;
        }
        foreach (array_slice(array_keys($apps), 0, 10) as $n) {
            if ((int) (scalar("SELECT COALESCE(user_id,0) FROM applications WHERE UPPER(number)=? LIMIT 1", [$n]) ?: 0) > 0) return true;
        }
        foreach (array_slice(array_keys($orders), 0, 10) as $id) {
            if ((int) (scalar("SELECT COALESCE(user_id,0) FROM awards_orders WHERE id=?", [$id]) ?: 0) > 0) return true;
        }
        foreach (array_slice(array_keys($phones), 0, 5) as $p) {
            // Телефон в базе пишут как придётся — сверяем по последним десяти цифрам.
            $cand = all("SELECT u.id, u.phone FROM users u WHERE u.phone LIKE ? AND $has LIMIT 5", ['%' . substr($p, -4)]);
            foreach ($cand as $c) if (substr(preg_replace('~\D~', '', (string) $c['phone']), -10) === $p) return true;
        }
    } catch (\Throwable $e) { return false; }
    return false;
}

function chat_said_in_dialogue(string $sessionKey, string $re): bool {
    if ($sessionKey === '') return false;
    try {
        $lastEnd = (int) (scalar("SELECT MAX(id) FROM chat_messages
                                   WHERE session_key=? AND role='dialog_end'", [$sessionKey]) ?: 0);
        $rows = all("SELECT text FROM chat_messages
                      WHERE session_key=? AND role IN ('assistant','assistant_followup')
                        AND id > ? AND created_at > datetime('now','localtime','-1 day')
                   ORDER BY id DESC LIMIT 40", [$sessionKey, $lastEnd]);
    } catch (\Throwable $e) { return false; }
    foreach ($rows as $r) {
        if (preg_match($re, (string) ($r['text'] ?? ''))) return true;
    }
    return false;
}

/**
 * ВТОРОЙ РАЗ ЗА РАЗГОВОР ЭТОГО НЕ ГОВОРИМ (слово владельца 13.10.2026).
 *
 * Два приглашения, и у каждого своё условие:
 *   • ПОЛОЖЕНИЕ - один раз за диалог и только там, где речь об участии. Второй
 *     раз человек читает это как напоминание, которое ему уже дали, а в третий
 *     как придирку.
 *   • РЕГИСТРАЦИЯ - только ГОСТЮ и только один раз. Вошедшему участнику она не
 *     нужна вовсе: он уже внутри, и «зарегистрируйтесь на сайте» в ответе
 *     человеку с кабинетом выглядит так, будто бот его не узнал.
 *
 * Режем ПРЕДЛОЖЕНИЯМИ, а не словами: вырезанное слово оставляет обрубок, и
 * ответ выходит рваным.
 */
function chat_limit_repeat_offers(string $answer, string $sessionKey, ?int $uid = null,
                                  string $question = ''): string {
    $t = trim($answer);
    if ($t === '') return $answer;

    /* ПРЯМОЙ ВОПРОС ЗАМОК НЕ РЕЖЕТ (слово владельца 13.10.2026). Спросили, как
       зарегистрироваться или где прочитать положение - ответ уходит целиком,
       кто бы ни спрашивал: вошедший участник, гость или спросивший за
       знакомого. */
    $спросил_регистрацию = $question !== '' && chat_asks_about_signup($question);
    $спросил_положение   = $question !== ''
        && (bool) preg_match('~положени\w*|регламент~ui', $question);

    $снять = [];
    /* Положение: оставляем только первое упоминание за разговор. Своё
       дописанное предложение заслон уже не ставит (см. chat_ensure_apply_links),
       поэтому здесь ловим то, что написала сама модель. */
    if (!$спросил_положение
        && chat_said_in_dialogue($sessionKey, '~/regulations|положени\w*[^.!?]{0,80}https?://~ui')) {
        /* Хвост ПОСЛЕ ссылки тоже часть предложения: «…: <ссылка> — там всё
           написано.» Без него от фразы оставался обрубок «— там всё написано.» */
        /* ССЫЛКА В ШАБЛОНЕ - БЕЗ ТОЧКИ ЗА НЕЙ. После маскировки внутри адреса
           точек не бывает, а «\S+» дотягивался до точки, которой кончается
           предложение, и замок прихватывал следующую фразу («Если останутся
           вопросы, напишите.»). Класс [^\s.!?] кончается ровно на адресе. */
        $снять[] = '~[^.!?\n]*положени\w*[^.!?\n]{0,120}https?://[^\s.!?]+[^.!?\n]*[.!?]?~ui';
        $снять[] = '~[^.!?\n]*https?://[^\s.!?]*/regulations[^\s.!?]*[^.!?\n]*[.!?]?~ui';
    }
    /* Регистрация: вошедшему - никогда, гостю - один раз за разговор.
       Во ВКонтакте аккаунт известен только по привязке vk_id, а она есть у
       немногих - поэтому там спрашиваем ещё и chat_vk_kabinet_est (имя
       страницы, почта, телефон, номер заявки или заказа из переписки). */
    $зарегистрирован = (int) $uid > 0
        || (str_starts_with($sessionKey, 'vk_') && chat_vk_kabinet_est((int) substr($sessionKey, 3)));
    if (!$спросил_регистрацию && ($зарегистрирован || chat_signup_offered($sessionKey))) {
        $снять[] = '~[^.!?\n]*(?:зарегистрир\w+|регистраци\w+\s+на\s+(?:нашем|сайте)|'
                 . 'завед\w+\s+(?:личный\s+)?кабинет|создайте\s+(?:личный\s+)?кабинет)'
                 . '[^.!?\n]*[.!?]?~ui';
        /* ПРЕДУПРЕЖДЕНИЕ ПРО ПОЧТУ - ЧАСТЬ ТОГО ЖЕ ПРИГЛАШЕНИЯ. Оно идёт
           отдельным предложением («При создании аккаунта укажите ту же
           почту…») и, оставшись одно, читается сиротой: человек не знает, о
           каком создании речь. */
        $снять[] = '~[^.!?\n]*при\s+(?:создании\s+(?:аккаунт\w*|кабинет\w*)|регистрации)'
                 . '[^.!?\n]*[.!?]?~ui';
    }
    if (!$снять) return $answer;

    /* ПОРОГ НИЗКИЙ НАРОЧНО. Сначала тут стояло «сорок знаков», и правка молча
       отменялась на коротких ответах: «Результаты видны в кабинете.
       Обязательно зарегистрируйтесь…» после снятия приглашения оставляет 28
       знаков - и приглашение уходило вошедшему участнику как ни в чём не бывало.
       Порог нужен только чтобы не отдать человеку пустоту. */
    /* ССЫЛКИ ПРЯЧЕМ ДО РЕЗКИ: точка внутри адреса - не конец предложения. */
    $out = chat_mask_links($t);
    foreach ($снять as $re) {
        $o = preg_replace($re, '', $out);
        if (is_string($o) && mb_strlen(trim($o)) >= 15) $out = $o;
    }
    /* После вырезанного предложения остаются двойные пробелы и пустые строки. */
    $out = preg_replace('~[^\S\n]{2,}~u', ' ', $out) ?? $out;
    $out = preg_replace('~\n{3,}~u', "\n\n", $out) ?? $out;
    $out = preg_replace('~^[^\S\n]+~mu', '', $out) ?? $out;
    /* На месте вырезанного остаётся висящий знак: «письмом. — там…» или
       «кабинете. :». Снимаем разделитель, если он стоит сразу за точкой. */
    $out = preg_replace('~(?<=[.!?])[^\S\n]*[\x{2014}\x{2013}:;,-]+[^\S\n]*~u', ' ', $out) ?? $out;
    $out = preg_replace('~[^\S\n]{2,}~u', ' ', $out) ?? $out;
    $out = chat_unmask_links(trim($out));
    return $out !== '' ? $out : $answer;
}

/**
 * ССЫЛКА - ОДНО СЛОВО, И РЕЗАТЬ ПО ТОЧКЕ ВНУТРИ НЕЁ НЕЛЬЗЯ.
 *
 * Замки вырезают из готового ответа целые ПРЕДЛОЖЕНИЯ, а границу предложения
 * видят по точке. В адресе сайта точек две («музыкальный-мир.рф/cabinet»), и
 * для такого правила ссылка - конец одного предложения и начало другого.
 * 13.10.2026 так и ушло живому человеку: на вопрос «как зарегистрироваться на
 * вашем сайте?» замок снимал приглашение регистрации и начал резать с точки
 * ВНУТРИ ссылки - участник прочитал ответ, начинающийся с обрубка
 * «рф/cabinet. При создании аккаунта…».
 *
 * Поэтому перед любой резкой по предложениям точки, «?» и «!» внутри адресов
 * прячутся под служебные знаки, а сразу после - возвращаются. Служебные знаки
 * взяты из управляющей зоны: в живом тексте их не бывает, и в класс
 * «не точка, не ! и не ?» они попадают как обычные буквы.
 */
function chat_mask_links(string $t): string {
    $re = '~https?://\S+'
        . '|(?:музыкальный-мир\.рф|xn----7sbugdeiegh1b0a9hen\.xn--p1ai)(?:/\S*)?'
        . '~ui';
    /* ЗНАКИ ПОСЛЕ ССЫЛКИ В МАСКУ НЕ ПОПАДАЮТ, И ЭТО ГЛАВНОЕ ЗДЕСЬ.
       «\S+» это «всё, что не пробел», и точка в конце предложения
       («…/cabinet. Хорошего дня!») тоже не пробел - она уезжала внутрь ссылки
       вместе с маской. Граница предложения исчезала, и замок вырезал заодно
       следующую фразу: на прогоне так пропало «Хорошего дня!». Поэтому хвост
       из знаков препинания отделяется и остаётся как был. */
    return (string) (preg_replace_callback(
        $re,
        static function (array $m): string {
            $url = $m[0];
            $хвост = '';
            if (preg_match('~^(.*?)([.,;:!?\x{00BB}\x{201D}")\]]+)$~u', $url, $p)) {
                $url   = $p[1];
                $хвост = $p[2];
            }
            return strtr($url, ['.' => "\x01", '?' => "\x02", '!' => "\x03"]) . $хвост;
        },
        $t
    ) ?? $t);
}

/** Возврат спрятанных знаков ссылки. Зовётся сразу после резки. */
function chat_unmask_links(string $t): string {
    return strtr($t, ["\x01" => '.', "\x02" => '?', "\x03" => '!']);
}

/**
 * ЧЕЛОВЕК СПРОСИЛ ПРО РЕГИСТРАЦИЮ - ЗНАЧИТ, ОТВЕТ ПРО РЕГИСТРАЦИЮ ЕМУ НУЖЕН
 * ЦЕЛИКОМ.
 *
 * Слово владельца 13.10.2026: «Ответ на подобный вопрос, у всех участников в
 * дальнейшем должна быть полная информация в ответе». Замок на повторы снимает
 * НАВЯЗАННОЕ приглашение («кстати, зарегистрируйтесь»), а не ответ на прямой
 * вопрос - иначе у вошедшего участника от такого ответа не остаётся ничего.
 *
 * «Зарегистрироваться на конкурс» и «регистрация заявки» - это ПОДАЧА ЗАЯВКИ, а
 * не аккаунт: такой вопрос сюда не относится и уходит в свою ветку.
 */
function chat_asks_about_signup(string $question): bool {
    $q = mb_strtolower(trim($question));
    if ($q === '') return false;
    if (preg_match('~(?:регистрац\w*|зарегистрир\w*)[^.!?]{0,24}'
                 . '(?:заявк|на\s+конкурс|в\s+конкурс|на\s+участ)~u', $q)) return false;
    if (preg_match('~зарегистрир\w*|регистрац\w*|аккаунт|учётн\w*\s+запис|учетн\w*\s+запис~u', $q)) {
        return true;
    }
    return (bool) (preg_match('~кабинет|профил~u', $q)
        && preg_match('~\bкак\b|созда|завест|заведу|открыт|оформит|войт|вход|доступ|'
                    . 'нужен|нужно|хочу~u', $q));
}

/**
 * СПРОСИЛИ ПРО РЕГИСТРАЦИЮ - АДРЕС СТРАНИЦЫ СТОИТ В САМОМ ТЕКСТЕ.
 *
 * Та же грабля, что со ссылками на заявку (правило 35): в веб-канале модели
 * сказано не писать адреса текстом, «они уезжают в кнопки», а КНОПКИ У
 * ЗАДЕРЖАННОГО ОТВЕТА НЕ ПЕРЕДАЮТСЯ ВОВСЕ - обычный участник получает ответ
 * через две минуты из истории. На живом прогоне так и вышло: ответ про
 * регистрацию был полным по шагам, но без единой ссылки, и человеку оставалось
 * искать страницу самому. Поэтому адрес дописывается в текст, если его там нет.
 */
function chat_ensure_signup_link(string $question, string $answer): string {
    $t = trim($answer);
    if ($t === '' || !chat_asks_about_signup($question)) return $answer;
    if (mb_strpos($t, '/register') !== false) return $answer;
    /* Говорим ли мы вообще о регистрации: на «не могу войти в кабинет» ответ
       бывает про пароль, и страница регистрации там ни к чему. */
    if (!preg_match('~регистрац\w*|зарегистрир\w*|аккаунт|кабинет~ui', $t)) return $answer;
    return rtrim($t, " \t\n") . "\n" . 'Страница регистрации: ' . url('/register') . '.';
}

/** Приглашали ли уже этого человека зарегистрироваться в этом разговоре. */
function chat_signup_offered(string $sessionKey): bool {
    /* ГРАНИЦА - ПОСЛЕДНЕЕ СЛОВО УЧАСТНИКА, А НЕ МЕТКА ЗАВЕРШЕНИЯ (см.
       chat_dialogue_granica): метку ставит прощание, в котором это приглашение
       и уходит, поэтому по старой границе оно само себя не видело.
       «У Вас уже есть личный кабинет» добавлено в список намеренно: смысл тот
       же, и сказав это, второй раз приглашать завести кабинет нельзя. */
    return chat_said_since_user($sessionKey,
        '~зарегистрирова\w*|регистраци\w*\s+на\s+(?:нашем|сайте)'
        . '|завест\w*\s+(?:личный\s+)?кабинет'
        . '|уже\s+есть\s+(?:личный\s+)?кабинет~ui');
}

/**
 * ЗАМОК НА ПОРЯДОК ЗАКАЗА: «ОТДЕЛЬНО ОТ ОСНОВНОГО» ИЗ ОТВЕТА ВЫРЕЗАЕТСЯ.
 *
 * Правило центра (правило 45, слово владельца 14.10.2026): дополнительный
 * диплом, благодарность педагогу, кубок, статуэтка и медаль заказываются только
 * вместе с основным или именным дипломом, и дополнительный тоже - ни
 * электронный, ни оригинал. В знаниях бота это правило стоит дословно, и всё
 * равно 14.10 он написал Татьяне Волосатовой: «Вы можете заказать его как
 * отдельно, так и вместе с основным дипломом».
 *
 * ПОЧЕМУ ПРОМПТА НЕ ХВАТИЛО. Модель учится манере по живым ответам операторов
 * (chat_style_examples), и в эталонах лежал настоящий ответ от 03.09.2026:
 * «Дипломы, Дополнительные Дипломы и Благодарственные письма заказываются
 * отдельно». Тогда это было верно, сейчас - нет, а эталон сильнее правила:
 * та же грабля, что с именем оператора (правило 34). Поэтому правило держит
 * замок на выходе, и он смотрит на ТЕКСТ, который уходит человеку.
 *
 * РЕЖЕМ ТОЧНО, А НЕ ПО СЛОВУ «ОТДЕЛЬНО». «Наградные материалы оплачиваются
 * отдельно» - правда: в бесплатном конкурсе они не входят в участие. Ложь это
 * «отдельно ОТ ОСНОВНОГО», и у неё узнаваемые обороты. Слепая замена сломала бы
 * честный ответ про оплату.
 */
function chat_fix_dop_zakaz(string $answer): string {
    if (trim($answer) === '') return $answer;
    $предмет = '(дополнительн|доп\\.?\\s*диплом|благодарност|кубок|статуэтк|медал)';
    /* Признак «речь о наградах» шире самого предмета: модель называет дополнение
       один раз, а дальше говорит «его» - зато рядом почти всегда стоит «вместе с
       основным дипломом». Без этого фраза «можете заказать его как отдельно, так
       и вместе с основным дипломом» проходила мимо замка, когда предмет назван
       только местоимением. */
    $речьОНаградах = '(' . mb_substr($предмет, 1, -1) . '|основн\\w*\\s+диплом|именн\\w*\\s+диплом)';
    if (!preg_match('~' . $речьОНаградах . '~ui', $answer)) return $answer;   // речь не о наградах

    /* Точки внутри адресов прячем: разбор идёт по предложениям, а в
       «музыкальный-мир.рф/awards» точка не конец фразы (правило 39). */
    $t = function_exists('chat_mask_links') ? chat_mask_links($answer) : $answer;

    /* ПРАВИМ ОБОРОТ, А НЕ ВЫБРАСЫВАЕМ ПРЕДЛОЖЕНИЕ.
     *
     * У Татьяны ложь стояла в том же предложении, что ссылка на «Награды» и
     * цены: снять предложение целиком значит отобрать у человека и адрес, и
     * суммы, за которыми он и писал. Поэтому меняется ровно неверная связка. */
    $безусловно = [
        '~как\\s+отдельно,?\\s*так\\s+и\\s+вместе\\s+с\\s+основным(\\s+дипломом)?~ui'
            => 'только вместе с основным или именным дипломом',
        '~как\\s+отдельно,?\\s*так\\s+и\\s+вместе~ui'
            => 'только вместе с основным или именным дипломом',
        '~и\\s+отдельно,?\\s*и\\s+вместе~ui'
            => 'только вместе с основным или именным дипломом',
        '~отдельно\\s+от\\s+основно\\w*(\\s+диплома)?~ui'
            => 'только вместе с основным или именным дипломом',
        '~отдельно\\s+от\\s+именно\\w*(\\s+диплома)?~ui'
            => 'только вместе с основным или именным дипломом',
        '~основной\\s+диплом\\s+(?:при\\s+этом\\s+)?не\\s+обязателен~ui'
            => 'основной или именной диплом нужен обязательно',
        '~не\\s+обязательно\\s+заказывать\\s+основно\\w*~ui'
            => 'основной или именной диплом нужен обязательно',
    ];

    $t2 = $t;
    foreach ($безусловно as $re => $to) $t2 = preg_replace($re, $to, (string) $t2) ?? $t2;

    /* «Можно заказать отдельно» правим только там, где речь ИДЁТ о дополнении.
       Про основной диплом та же фраза верна: в бесплатном конкурсе он и правда
       заказывается сам по себе, отдельно от участия. Поэтому смотрим окно из
       текущего и предыдущего предложения - предмет часто назван раньше, а в
       следующей фразе стоит уже «его» (так и было у Татьяны). */
    $куски = preg_split('~(?<=[.!?])\\s+~u', (string) $t2);
    if (is_array($куски)) {
        $усл = '~((?:вы\\s+)?(?:можете|можно)\\s+(?:его|их\\s+)?\\s*(?:заказать|оформить)'
             . '(?:\\s+(?:его|их))?)\\s+отдельно~ui';
        foreach ($куски as $i => $фраза) {
            if (!preg_match($усл, (string) $фраза)) continue;
            $окно = (string) $фраза . ' ' . (string) ($куски[$i - 1] ?? '');
            if (!preg_match('~' . $речьОНаградах . '~ui', $окно)) continue;
            if (preg_match('~основн\\w*\\s+диплом\\w*\\s+(?:можете|можно)~ui', (string) $фраза)) continue;
            $куски[$i] = preg_replace($усл, '$1 только вместе с основным или именным дипломом',
                                      (string) $фраза) ?? $фраза;
        }
        $t2 = implode(' ', $куски);
    }

    if ($t2 === $t) return $answer;                 // нечего было править
    $out = trim(preg_replace('~[^\\S\\n]{2,}~u', ' ', (string) $t2) ?? '');
    if (mb_strlen($out) < 15) return $answer;       // не отдаём обрубок
    return function_exists('chat_unmask_links') ? chat_unmask_links($out) : $out;
}

