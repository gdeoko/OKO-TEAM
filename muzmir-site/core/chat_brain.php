function chat_rule_reply(string $text): string {
    $t        = mb_strtolower($text);
    $orgEmail = cfgv('org_email');
    $has = static function (array $words) use ($t): bool {
        foreach ($words as $w) if (mb_strpos($t, $w) !== false) return true;
        return false;
    };
    $tail = "";

    /* ---- Узкие темы: их формулировки пересекаются с широкими, поэтому раньше ---- */

    // График работы. «Во сколько работаете» содержит «сколько» — до этой ветки
    // вопрос уходил в рассказ про стоимость.
    if ($has(['во сколько', 'режим работ', 'график', 'когда вы работ', 'до скольки',
              'рабочее время', 'работаете'])) {
        /* ЧТО ОБЕЩАЕМ, ТО И ДЕЛАЕМ. Вне графика бот не отвечает по существу:
