/**
 * ПРИПИСКА К ССЫЛКЕ НА САЙТ: «На нашем официальном сайте Культурного центра
 * «Музыкальный Мир»». Слово владельца 13.10.2026, дословно, во всех диалогах,
 * где упоминается музыкальный-мир.рф.
 *
 * ЗАЧЕМ. Голая ссылка в переписке читается настороженно: участник не знает,
 * ведёт она на сайт центра или куда-то ещё, а про мошеннические письма «от
 * конкурсов» слышали все. Приписка снимает этот вопрос до того, как он
 * возникнет, и заодно говорит человеку, что сайт у центра ОДИН и официальный.
 *
 * ЗАМОК, А НЕ ПРОСЬБА. Правило стоит и в правилах модели, но правило в промпте
 * модель выполняет через раз, а ссылку дописывает и сам код
 * (`chat_ensure_apply_links`, `chat_rule_reply`, цены наград). Поэтому приписка
 * проверяется по факту в готовом тексте.
 *
 * Адрес узнаём в ДВУХ начертаниях: красивом («музыкальный-мир.рф», так пишет
 * модель во ВКонтакте) и punycode («xn----7sbugdeiegh1b0a9hen.xn--p1ai», так
 * отдаёт `url()`). Одного мало: половина ссылок прошла бы мимо.
 *
 * Приписка ставится ОДИН раз, отдельной строкой перед первой строкой со
 * ссылкой. Втискивать её внутрь чужого предложения нельзя: выходит «можно
 * подать на нашем официальном сайте Культурного центра «Музыкальный Мир» на
 * странице …» - текст, который никто не писал и никто не правил.
 */
function chat_ensure_site_phrase(string $answer): string {
    $t = trim($answer);
    if ($t === '') return $answer;
    /* Уже сказано своими словами - ничего не добавляем: модель, выполнившая
       правило, второй раз приписку не получит. */
    if (preg_match('~официальн\w*\s+сайт~ui', $t)) return $answer;

    $домены = ['музыкальный-мир.рф', 'xn----7sbugdeiegh1b0a9hen.xn--p1ai'];
    $есть_ссылку = static function (string $x) use ($домены): bool {
        foreach ($домены as $д) if (mb_stripos($x, $д) !== false) return true;
        return false;
    };

    $строки = preg_split('~\R~u', $t) ?: [$t];
    $i = -1;
    foreach ($строки as $n => $стр) {
        if ($есть_ссылку($стр)) { $i = (int) $n; break; }
    }
    if ($i < 0) return $answer;   // ссылки на сайт в ответе нет

    $приписка = 'На нашем официальном сайте Культурного центра «Музыкальный Мир»:';

    /* СТАВИМ РЯДОМ СО ССЫЛКОЙ, А НЕ НАД ВСЕМ АБЗАЦЕМ.
       Строка в ответе бывает длинной: «Прямо сейчас приём заявок идёт в такие
       конкурсы… Подать заявку: <ссылка>…». Приписка, поставленная перед такой
       строкой, читается заголовком над текстом, который про другое. Поэтому
       строка делится на предложения, и приписка встаёт перед тем, в котором
       ссылка. Делим по точке с пробелом: сокращения вроде «руб.» внутри
       предложения точку с заглавной буквой за ней не дают. */
    $куски = preg_split('~(?<=[.!?])\s+~u', (string) $строки[$i]) ?: [];
    if (count($куски) > 1) {
        foreach ($куски as $k => $кусок) {
            if (!$есть_ссылку($кусок)) continue;
            $до    = trim(implode(' ', array_slice($куски, 0, $k)));
            $после = trim(implode(' ', array_slice($куски, $k)));
            $новые = array_values(array_filter([$до, $приписка, $после], static fn($x) => $x !== ''));
            array_splice($строки, $i, 1, $новые);
            return implode("\n", $строки);
        }
    }

    array_splice($строки, $i, 0, [$приписка]);
    return implode("\n", $строки);
}

/**
 * БЫЛО ЛИ ЭТО УЖЕ СКАЗАНО В ЭТОМ РАЗГОВОРЕ.
 *
 * Слово владельца 13.10.2026: ссылка на положение уходит участнику ОДИН РАЗ за
 * весь диалог, приглашение зарегистрироваться - тоже один раз и только гостю.
 * Значит нужна память разговора, а флаг в настройках для этого плох: он живёт
 * дольше разговора и разъезжается с правдой. Поэтому смотрим ФАКТ - свои
 * прежние ответы в этом же разговоре.
 *
 * Границы разговора берём те же, по которым бот решает, здороваться ли
 * (`chat_should_greet`): после последней метки завершения и не старше суток.
 * Иначе «один раз за диалог» превратилось бы в «один раз в жизни»: человек
 * вернулся через месяц с тем же вопросом и ссылки не получил.
 */
/**
 * ГРАНИЦА РАЗГОВОРА ДЛЯ ТОГО, ЧТО ГОВОРИМ ОДИН РАЗ.
 *
 * Правило 38 считает диалог от последней метки `dialog_end`. Для ссылки на
 * положение это верно, а для ПРОЩАНИЯ и приглашения зарегистрироваться - нет,
 * и 14.10.2026 это стоило участнице восьми сообщений на два её собственных.
 * Беда в том, что метку ставит САМО прощание: после него граница уезжает
 * вперёд, своё же прощание оказывается «до границы», память пуста, и следующий
 * повод прощается заново. Татьяна Волосатова получила прощание пять раз и
 * приглашение зарегистрироваться трижды, не написав после «спасибо» ни слова.
 *
 * Поэтому здесь граница другая: последняя метка завершения, стоящая ПЕРЕД
 * последним словом участника. Человек молчит - граница не двигается, и всё
 * сказанное ему видно. Человек заговорил снова - граница сдвинулась вместе с
 * его сообщением, и правило 38 работает как прежде: вернулся через месяц -
 * получил и ссылку, и приглашение.
 */
function chat_dialogue_granica(string $sessionKey): int {
    if ($sessionKey === '') return 0;
    try {
        $lastUser = (int) (scalar("SELECT MAX(id) FROM chat_messages
                                    WHERE session_key=? AND role='user'
                                      AND TRIM(COALESCE(text,''))<>''", [$sessionKey]) ?: 0);
        if ($lastUser <= 0) return 0;
        return (int) (scalar("SELECT MAX(id) FROM chat_messages
                               WHERE session_key=? AND role='dialog_end' AND id < ?",
                             [$sessionKey, $lastUser]) ?: 0);
    } catch (\Throwable $e) { return 0; }
}

/**
 * БЫЛО ЛИ ЭТО СКАЗАНО ПОСЛЕ ПОСЛЕДНЕГО СЛОВА УЧАСТНИКА.
 *
 * Брат `chat_said_in_dialogue` с границей из `chat_dialogue_granica`. Суточного
 * предела здесь НЕТ намеренно: сторож закрытия диалогов работает в окне до двух
 * суток, и с суточным пределом прощание повторилось бы на вторые сутки - ровно
 * то, от чего эта мерка и ставится.
 */
function chat_said_since_user(string $sessionKey, string $re, int $limit = 40): bool {
    if ($sessionKey === '') return false;
    $granica = chat_dialogue_granica($sessionKey);
    $lim = max(1, min(200, $limit));
    /* СУДИМ И ПО НОМЕРУ, И ПО ВРЕМЕНИ, И ВТОРОЕ ВАЖНЕЕ.
       Ответы оператора, написанные прямо из ВКонтакте, попадают в историю
       подтягиванием (vk_import_outgoing), и номер им достаётся НОВЫЙ, а время
       своё - настоящее. По одному номеру позавчерашний ответ выглядел бы
       сказанным только что, и нужное человеку приглашение мы бы проглотили.
       Поэтому берём только то, что сказано не раньше последнего слова
       участника. */
    $после = '';
    try {
        $после = (string) (scalar("SELECT created_at FROM chat_messages
                                    WHERE session_key=? AND role='user'
                                      AND TRIM(COALESCE(text,''))<>''
                                 ORDER BY id DESC LIMIT 1", [$sessionKey]) ?: '');
    } catch (\Throwable $e) { $после = ''; }
    /* Условие по времени собираем в PHP, а не в тексте запроса. В первой
       сборке «$после» стояло прямо в SQL, и при пустом значении запрос
       становился «( = '' OR …)» - синтаксическая ошибка, которую ловил catch и
       отдавал false. То есть у разговора без сообщений участника память молча
       слепла: сломанная мерка показывала бы «ничего не говорили». */
    $где = "session_key=? AND role IN ('assistant','assistant_followup') AND id > ?";
    $арг = [$sessionKey, $granica];
    if ($после !== '') { $где .= " AND COALESCE(created_at,'') >= ?"; $арг[] = $после; }
    try {
        $rows = all("SELECT text FROM chat_messages WHERE " . $где
                    . " ORDER BY id DESC LIMIT " . $lim, $арг);
    } catch (\Throwable $e) { return false; }
    foreach ($rows as $r) {
        if (preg_match($re, (string) ($r['text'] ?? ''))) return true;
    }
    return false;
}

