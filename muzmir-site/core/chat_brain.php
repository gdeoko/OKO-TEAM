        $gates[] = $g;

        $paidComp = (int) ($a['comp_paid'] ?? 0) === 1;
        $num  = (string) ($a['number'] ?? $a['id'] ?? '');
        $who  = trim((string) ($a['group_name'] ?? '')) !== '' ? trim((string) $a['group_name']) : trim((string) ($a['full_name'] ?? ''));
