/**
 * Единый оркестратор ответа: Gemini → Claude → внешний агент → rule-based.
 * @param string   $text       текст входящего сообщения
 * @param string   $sessionKey ключ диалога (веб-сессия или "vk_<peer_id>")
 * @param int|null $uid        id пользователя сайта, если известен
 */
function chat_brain_reply(string $text, string $sessionKey, ?int $uid = null, string $channel = 'vk'): string {
    $GLOBALS['chat_channel']   = $channel; // 'web' = ссылки кнопками, 'vk' = прямыми ссылками
    $GLOBALS['chat_fell_back'] = false;    // признак: «мозг» не ответил, ушли в rule-фолбэк
    $reply = null;

    // Бесплатный тариф Gemini даёт всего пара десятков запросов, и на людном часе
    // квота выбивается за минуты: дальше «мозг» молчит, а участник получает шаблон
    // вместо ответа. Поэтому ключей несколько, и упёршийся в лимит уступает место
    // следующему. Порядок перебора меняется каждый час, чтобы нагрузка расходилась
    // по ключам, а не выжигала первый.
    foreach (chat_gemini_keys() as $key) {
        $reply = chat_gemini_reply($key, $sessionKey, $text);
        if ($reply !== null && $reply !== '') break;
    }
    $apiKey = (string) (cfgv('claude_api_key') ?: '');
    if (($reply === null || $reply === '') && $apiKey !== '') {
        $reply = chat_claude_reply($apiKey, $sessionKey, $text);
    }
    // Внешний мозг-агент, если настроен и выше никто не ответил.
    if (($reply === null || $reply === '') && function_exists('agent_chat_proxy') && ($agentUrl = cfgv('agent_url'))) {
        $reply = agent_chat_proxy((string) $agentUrl, (string) cfgv('agent_token'), $text, $sessionKey, $uid);
    }
    if ($reply === null || $reply === '') {
        // Ни Gemini, ни Claude, ни агент не дали ответа — общий шаблон по ключевым словам.
        // Признак поднимаем, чтобы вызывающий код (веб/ВК) мог эскалировать «нет ответа».
        $reply = chat_rule_reply($text);
        $GLOBALS['chat_fell_back'] = true;
    }

    // ПОСЛЕДНЯЯ ПРОВЕРКА ПЕРЕД ОТПРАВКОЙ. Запрет в промпте — просьба, а не замок:
    // модель может назвать звание по памяти диалога, по догадке участника или просто
    // ошибиться. Сторож сверяет готовый текст с реальными скрытыми оценками этого
    // собеседника и подменяет ответ на честное «когда и где», если итог всплыл раньше
    // срока. Подробности — core/chat_gate.php.
    if (!function_exists('chat_gate_guard') && is_file(BASE_PATH . '/core/chat_gate.php')) {
        require_once BASE_PATH . '/core/chat_gate.php';
    }
    if (function_exists('chat_gate_guard')) {
        $reply = chat_gate_guard((string) $reply, (array) ($GLOBALS['chat_gates'] ?? []));
    }
    return trim($reply);
}

/**
 * Эскалация «нет ответа»: «мозг» ушёл в rule-фолбэк (не смог точно ответить по вопросу).
 * Один раз за сессию (маркер role='escalated_noanswer', отдельно от keyword-эскалации):
 *   (а) возвращает пользователю текст-приписку с просьбой позвонить в колл-центр;
 *   (б) уведомляет владельца в Телеграм (owner_notify): имя/фамилия, все заявки со
 *       статусами, телефон (если нет — почта/ссылка ВК), краткая суть обращения.
 * @param int|null $uid     id пользователя сайта (в ВК — привязанный к peer, если есть)
 * @param string   $channel 'web' | 'vk'
 * @param array    $extra   доп. поля для владельца (напр. ссылка на диалог ВК)
 * @return string текст-приписка для пользователя ('' — если уже эскалировали в этой сессии)
 */
function chat_escalate_no_answer(?int $uid, string $sessionKey, string $name, string $userText, string $channel = 'web', array $extra = []): string {
    // Строго один раз за сессию.
    try {
        $done = (int) scalar("SELECT COUNT(*) FROM chat_messages WHERE session_key=? AND role='escalated_noanswer'", [$sessionKey]);
        if ($done > 0) return '';
    } catch (\Throwable $e) { return ''; }

    $tel = (string) cfgv('org_phone');

    // Контактные данные участника: ФИО, телефон, почта.
    $fio = trim($name); $phone = ''; $email = '';
    if ($uid) {
        try {
            $u = one("SELECT full_name, phone, email FROM users WHERE id=?", [$uid]);
            if ($u) {
                $fio   = trim((string) ($u['full_name'] ?? '')) ?: $fio;
                $phone = trim((string) ($u['phone'] ?? ''));
                $email = trim((string) ($u['email'] ?? ''));
            }
        } catch (\Throwable $e) { /* тихо */ }
    }

    // Все заявки участника со статусами (компактно, для владельца).
    $appsLines = [];
    if ($uid) {
        $stMap = ['new' => 'на рассмотрении', 'pending' => 'на рассмотрении', 'submitted' => 'принята, ожидает аттестации',
            'paid' => 'оплачена, ожидает аттестации', 'review' => 'на аттестации жюри', 'judging' => 'на аттестации жюри',
            'scored' => 'аттестована (результат готов)', 'done' => 'аттестована (результат готов)',
            'rejected' => 'отклонена', 'unpaid' => 'ожидает оплаты'];
        try {
            $apps = all("SELECT a.number, a.status, a.result, c.name AS comp_name
                           FROM applications a JOIN competitions c ON c.id = a.competition_id
                          WHERE a.user_id = ? ORDER BY a.id DESC LIMIT 15", [$uid]);
            foreach ($apps as $a) {
                $st  = $stMap[(string) ($a['status'] ?? '')] ?? (string) ($a['status'] ?? '—');
                $res = trim((string) ($a['result'] ?? ''));
                $ln  = '№' . (string) ($a['number'] ?? '') . ' «' . (string) ($a['comp_name'] ?? '') . '» — ' . $st;
                if ($res !== '') $ln .= ', результат: ' . $res;
                $appsLines[] = $ln;
            }
        } catch (\Throwable $e) { /* тихо */ }
    }

    // Транскрипт последних сообщений — краткая суть обращения для оператора.
    $lines = [];
    try {
        $rows = all("SELECT role, text FROM chat_messages WHERE session_key=? AND role IN ('user','assistant') ORDER BY id DESC LIMIT 10", [$sessionKey]);
        foreach (array_reverse($rows) as $r) {
            $who = ($r['role'] ?? '') === 'user' ? '👤' : '🤖';
            $tx  = trim((string) $r['text']);
            if ($tx !== '') $lines[] = $who . ' ' . mb_substr($tx, 0, 220);
        }
    } catch (\Throwable $e) {}
    if (!$lines) $lines[] = '👤 ' . mb_substr(trim($userText), 0, 220);

    // Контакт для оператора: телефон → почта → ссылка/пометка ВК.
    $contact = $phone !== '' ? $phone : ($email !== '' ? $email : '');
    if ($contact === '' && !empty($extra['Ссылка'])) $contact = (string) $extra['Ссылка'];

    if (!function_exists('owner_notify') && is_file(BASE_PATH . '/core/notify_owner.php')) {
        require_once BASE_PATH . '/core/notify_owner.php';
    }
    if (function_exists('owner_notify')) {
        $fields = [
            'Участник' => ($fio !== '' ? $fio : 'гость') . ($channel === 'vk' ? ' (ВКонтакте)' : ''),
            'Телефон'  => $phone,
            'Почта'    => $email,
            'Заявки'   => $appsLines ? mb_substr(implode('; ', $appsLines), 0, 500) : '—',
            'Суть'     => mb_substr(trim($userText), 0, 240),
            'Сессия'   => $sessionKey,
            '_event'   => 'chat_escalation_no_answer',
            '_meta'    => ['session' => $sessionKey, 'uid' => (int) ($uid ?? 0), 'channel' => $channel],
        ] + $extra;
        try {
            owner_notify('ЧАТ-БОТ', '🔔 Бот не смог ответить — нужен оператор', implode("\n", $lines), $fields);
        } catch (\Throwable $e) { /* тихо */ }
    }

    // Маркер: эскалация «нет ответа» уже выполнена в этой сессии.
    try { insert('chat_messages', ['user_id' => $uid, 'session_key' => $sessionKey, 'role' => 'escalated_noanswer', 'text' => '', 'file' => '']); } catch (\Throwable $e) {}

    // Текст-приписка пользователю.
    return 'К сожалению, по этому вопросу мне лучше подключить сотрудника. '
        . 'Просим позвонить по телефону колл-центра ' . $tel
        . ' для решения вопроса. Мы обязательно поможем.';
}

/**
 * Пронумерованный список действующих заявок участника — для ВК (клавиатур нет,
 * поэтому список цифрами/номерами прямо в тексте). Аналог выпадающего <select>
 * на сайте. Показываем только когда: вопрос про результат/диплом, действующих
 * заявок больше одной и конкретный номер ещё не назван. Иначе — '' (список не нужен,
 * бот отвечает сразу; при одной заявке уточнять нечего).
 */
function chat_apps_numbered_text(?int $uid, string $userText): string {
    if (!$uid) return '';
    $t = mb_strtolower($userText);
    $ask = false;
    foreach (['результат', 'итог', 'балл', 'оцен', 'диплом', 'сертификат', 'аттест', 'провер', 'готов', 'когда'] as $w) {
        if (mb_strpos($t, $w) !== false) { $ask = true; break; }
    }
    if (!$ask) return '';
    try {
        // Поля конкурса нужны, чтобы подпись к заявке не проговорилась о результате
        // раньше срока: «аттестована, результат готов» — это уже половина ответа.
        $apps = all("SELECT a.*, c.name AS comp_name,
                            c.results_mode AS comp_results_mode, c.results_date AS comp_results_date,
                            c.results_published_at AS comp_results_pub
                       FROM applications a JOIN competitions c ON c.id = a.competition_id
                      WHERE a.user_id = ? AND a.status NOT IN ('rejected')
                   ORDER BY a.id DESC LIMIT 15", [$uid]);
    } catch (\Throwable $e) { return ''; }
    if (count($apps) <= 1) return '';
    // Конкретный номер уже назван (номер заявки как подстрока сообщения) — список не нужен.
    foreach ($apps as $a) {
        $num = trim((string) ($a['number'] ?? ''));
        if ($num !== '' && mb_stripos($userText, $num) !== false) return '';
    }
    if (!function_exists('chat_gate_app')) require_once BASE_PATH . '/core/chat_gate.php';
    $L = ['У Вас несколько заявок. Подскажите, пожалуйста, по какой именно вопрос — ответьте её номером (например, №' . (string) ($apps[0]['number'] ?? '') . '):'];
    $i = 0;
    foreach ($apps as $a) {
        $i++;
        $num = (string) ($a['number'] ?? '');
        $g   = chat_gate_app((array) $a);
        $L[] = $i . ') Заявка №' . $num . ' «' . (string) ($a['comp_name'] ?? '') . '» — ' . $g['status'];
    }
    return implode("\n", $L);
}

/* ==================== Правила диалога: приветствие и подпись ==================== */

/** Подпись оргкомитета (ставится только при завершении диалога). */
function chat_signoff(): string {
    return '🌍 С уважением, оргкомитет культуры и искусства Культурного центра «Музыкальный Мир» 🌍';
}

/** Строка приветствия. С именем, если известно: «Здравствуйте, Имя.». */
function chat_greet_line(string $name = ''): string {
    $name = trim($name);
    return $name !== '' ? 'Здравствуйте, ' . $name . '.' : 'Здравствуйте!';
}

/**
 * Нужно ли здороваться в этом сообщении. Здороваемся один раз в начале диалога
 * и снова после перерыва 24 часа или после завершения предыдущего диалога.
 * Считаем: есть ли наш ответ в этой сессии за последние 24 часа и после
 * последнего маркера завершения диалога. Нет — значит это начало нового диалога.
 */
function chat_should_greet(string $sessionKey): bool {
    try {
        $lastEndId = (int) (scalar("SELECT MAX(id) FROM chat_messages WHERE session_key=? AND role='dialog_end'", [$sessionKey]) ?: 0);
        $recent = (int) scalar(
            "SELECT COUNT(*) FROM chat_messages WHERE session_key=? AND role IN ('assistant','assistant_followup') AND id>? AND created_at > datetime('now','localtime','-1 day')",
            [$sessionKey, $lastEndId]
        );
        return $recent === 0;
    } catch (\Throwable $e) {
        return true;
    }
}

/** Пользователь завершает диалог: «спасибо», «пока», «всё понятно» и т.п. */
/**
 * Прощание ли это.
 *
 * ВАЖНО: сообщение должно СОСТОЯТЬ из благодарности, а не содержать её.
 * Раньше слово-маркер искалось в любом месте текста любой длины — и фраза
 * «Спасибо, а когда придёт диплом?» распознавалась как конец разговора: «мозг»
 * не вызывался вовсе, вместо ответа уходило «Рады были Вам помочь», а сам вопрос
 * исчезал. Люди в России почти всегда начинают вопрос с «спасибо» или
 * «благодарю» — то есть съедался каждый второй вопрос.
 *
 * Правило: есть вопросительный знак — не прощание. Осталось значимое слово после
 * вычёркивания вежливости — не прощание.
 */
function chat_is_closing(string $text): bool {
    $t = mb_strtolower(trim($text));
    if ($t === '') return false;
    if (mb_strpos($t, '?') !== false) return false;          // в вопросе прощания нет

    // Убираем пунктуацию и эмодзи, оставляем буквы, цифры и пробелы.
    $t = preg_replace('~[^\p{L}\p{N}\s]+~u', ' ', $t);
    $t = trim(preg_replace('~\s+~u', ' ', (string) $t));
    if ($t === '') return false;

    // Формулы прощания и вежливости целиком.
    $phrases = ['спасибо большое', 'большое спасибо', 'огромное спасибо', 'спасибо вам',
                'до свидания', 'всего доброго', 'всего хорошего', 'хорошего дня', 'доброго дня',
                'всё понятно', 'все понятно', 'всё ясно', 'все ясно', 'вопросов нет',
                'больше вопросов нет', 'больше вопросов', 'вы мне помогли', 'вы помогли',
                'я разобрался', 'я разобралась', 'уже разобрался', 'уже разобралась'];
    foreach ($phrases as $p) $t = trim((string) str_replace($p, ' ', $t));
    $t = trim(preg_replace('~\s+~u', ' ', $t));

    // Отдельные слова вежливости и «шум».
    $words = ['спасибо', 'спс', 'спасиб', 'благодарю', 'благодарствую', 'благодарим', 'благодарность',
              'пока', 'ок', 'окей', 'хорошо', 'ясно', 'понятно', 'понял', 'поняла', 'принято',
              'угу', 'ага', 'да', 'нет', 'всё', 'все', 'здорово', 'отлично', 'супер', 'класс',
              'помогли', 'разобрался', 'разобралась', 'вам', 'мне', 'и', 'а', 'ну', 'вот'];
    $rest = [];
    foreach (explode(' ', $t) as $w) {
        $w = trim($w);
        if ($w === '' || in_array($w, $words, true)) continue;
        $rest[] = $w;
    }

    // Прощание — только если после вычёркивания вежливости ничего не осталось
    // и при этом что-то вежливое в сообщении действительно было.
    if ($rest) return false;
    return (bool) preg_match(
        '~спасиб|спс|благодар|пока|свидан|доброго|хорошего дня|ясно|понятн|вопросов нет|помогли|разобрал~u',
        mb_strtolower(trim($text))
    );
}

/**
 * Финальное сообщение при завершении диалога: «Благодарим за обращение…» + подпись.
 * Ссылки в тексте прямые (для ВК); на сайте chat_web_format превратит их в кнопки.
 */
function chat_closing_message(string $name = ''): string {
    $vk  = (string) cfgv('org_vk');
    $tel = (string) cfgv('org_phone');
    $hrs = (string) cfgv('org_hours');
    $L = [];
    $L[] = '🙏 Благодарим Вас за обращение. Рады были Вам помочь.';
    $L[] = 'В случае возникновения дополнительных вопросов Вы можете обратиться в чат нашего официального сообщества ВКонтакте ' . $vk . ' или по телефону колл-центра ' . $tel . '.';
    $L[] = '🕑 График работы: ' . $hrs . '.';
    $L[] = '';
    $L[] = chat_signoff();
    return implode("\n", $L);
}

/** Нормализация текста вопроса для сравнения (нижний регистр, без пунктуации). */
function chat_norm(string $text): string {
    $t = mb_strtolower(trim($text));
    $t = preg_replace('~[^\p{L}\p{N}\s]+~u', ' ', $t);
    $t = preg_replace('~\s+~u', ' ', (string) $t);
    return trim((string) $t);
}

/**
 * Сколько раз в текущем диалоге пользователь уже задавал по сути ТОТ ЖЕ вопрос
 * (на который мы уже отвечали). 0 — вопрос новый. Служит для короткого ответа
 * «уже писал(а) выше» вместо повторной простыни (и против троллинга/спама).
 * Текущее сообщение уже записано в chat_messages, поэтому его исключаем.
 */
function chat_repeat_count(string $sessionKey, string $text): int {
    $norm = chat_norm($text);
    if (mb_strlen($norm) < 6) return 0;
    $words = array_values(array_unique(array_filter(explode(' ', $norm), fn($w) => mb_strlen($w) >= 3)));
    if (count($words) < 2) return 0;
    try {
        $lastEndId = (int) (scalar("SELECT MAX(id) FROM chat_messages WHERE session_key=? AND role='dialog_end'", [$sessionKey]) ?: 0);
        $curId     = (int) (scalar("SELECT MAX(id) FROM chat_messages WHERE session_key=? AND role='user'", [$sessionKey]) ?: 0);
        $rows = all("SELECT text FROM chat_messages WHERE session_key=? AND role='user' AND id>? AND id<? AND text<>''",
            [$sessionKey, $lastEndId, $curId]);
    } catch (\Throwable $e) { return 0; }
    $set = array_fill_keys($words, 1);
    $hits = 0;
    foreach ($rows as $r) {
        $pw = array_values(array_unique(array_filter(explode(' ', chat_norm((string) $r['text'])), fn($w) => mb_strlen($w) >= 3)));
        if (!$pw) continue;
        $inter = 0; foreach ($pw as $w) if (isset($set[$w])) $inter++;
        $union = count(array_unique(array_merge($words, $pw)));
        if ($union > 0 && ($inter / $union) >= 0.6) $hits++;
    }
    return $hits;
}

/** Короткий человеческий ответ на повторный вопрос (варьируется, без простыни). */
function chat_repeat_reply(int $count, string $name = ''): string {
    if ($count >= 3) {
        $v = [
            'Я всё так же отвечу — вся информация в моих сообщениях выше 🙂 Если появился другой вопрос, с удовольствием помогу.',
            'Ответ прежний, он есть чуть выше по переписке. Задавайте, пожалуйста, если будет новый вопрос.',
        ];
    } else {
        $v = [
            'Я уже отвечала на этот вопрос чуть выше 🙂 Посмотрите, пожалуйста, моё предыдущее сообщение. Если что-то осталось непонятным — уточните, что именно.',
            'Этот момент я поясняла выше по переписке. Подскажите, что именно осталось неясным — с радостью распишу подробнее.',
        ];
    }
    return $v[$count % count($v)];
}

/** Пометить диалог завершённым (следующее сообщение начнёт новый диалог с приветствием). */
function chat_mark_dialog_end(string $sessionKey): void {
    try {
        insert('chat_messages', ['user_id' => null, 'session_key' => $sessionKey, 'role' => 'dialog_end', 'text' => '', 'file' => '']);
    } catch (\Throwable $e) {}
}

/**
 * Собрать финальный ответ по правилам диалога: приветствие в начале, суть,
 * подпись — только при завершении. $core — суть ответа от «мозга».
 */
function chat_wrap_reply(string $sessionKey, string $core, string $name, bool $greet, bool $closing): string {
    $parts = [];
    if ($greet)   $parts[] = chat_greet_line($name);
    if ($core !== '') $parts[] = trim($core);
    if ($closing) $parts[] = "\n" . chat_signoff();
    return trim(implode("\n\n", $parts));
}

/**
 * Форматирование ответа для ВЕБ-ЧАТА сайта: голые ссылки из текста превращаются
 * в красивые кнопки (same-origin, открываются в приложении), а из текста ссылки
 * убираются. В ВК это НЕ применяется — там ссылки остаются прямыми и кликабельными.
 * @return array{text:string,actions:array}
 */
function chat_web_format(string $reply, array $actions): array {
    $labels = [
        '/apply'        => 'Подать заявку',
        '/competitions' => 'Конкурсы и положения',
        '/documents'    => 'Положения конкурсов',
        '/awards'       => 'Заказать награды',
        '/faq'          => 'Справка и сроки',
        '/verify'       => 'Проверить диплом',
        '/reviews'      => 'Оставить отзыв',
        '/results'      => 'Результаты конкурсов',
        '/club'         => 'Клуб участников',
        '/contacts'     => 'Контакты',
    ];
    // Уже занятые пути (чтобы не плодить дубликаты кнопок).
    $seen = [];
    foreach ($actions as $a) {
        if (!empty($a['url'])) { $p = rtrim((string) parse_url($a['url'], PHP_URL_PATH), '/'); if ($p !== '') $seen[$p] = 1; }
    }
    if (preg_match_all('~https?://[^\s<>"\')]+~u', $reply, $mm)) {
        foreach (array_unique($mm[0]) as $u) {
            $u   = rtrim($u, ".,;:!?)]»”\"'");   // отрезаем хвостовую пунктуацию предложения
            $host = (string) parse_url($u, PHP_URL_HOST);
            $path = rtrim((string) parse_url($u, PHP_URL_PATH), '/');
            $isLocal = $host !== '' && (mb_stripos($host, 'музыкальный-мир') !== false || stripos($host, 'xn--') !== false);
            if ($isLocal) {
                if ($path === '' || isset($seen[$path])) continue;
                $actions[] = ['type' => 'link', 'label' => $labels[$path] ?? 'Открыть раздел', 'url' => url($path)];
                $seen[$path] = 1;
            } else {
                $actions[] = ['type' => 'link', 'label' => (stripos($u, 'pochta') !== false ? 'Отследить посылку' : 'Открыть ссылку'), 'url' => $u];
            }
        }
    }
    // Убираем ссылки и «мусорные» вводные из текста.
    $t = preg_replace('~https?://[^\s<>"\')]+~u', '', $reply);
    $t = preg_replace('~^[ \t]*кнопк[аи][^\n]*$~uim', '', (string) $t); // на случай, если модель написала «Кнопка: …» текстом
    $t = preg_replace('~(?:,?\s*)?(?:по\s+)?(?:данной\s+|этой\s+|следующей\s+)?ссылке\s*[:：]?~ui', '', (string) $t);
    $t = preg_replace('~\(\s*\)~u', '', (string) $t);            // пустые скобки от «(ссылка)»
    $t = preg_replace('~[«"“]\s*[»"”]~u', '', (string) $t);      // пустые кавычки
    $t = preg_replace('~[ \t]*[:：]\s*(?=[.\n)]|$)~u', '', (string) $t); // висячее двоеточие
    $t = preg_replace('~[ \t]{2,}~u', ' ', (string) $t);
    $t = preg_replace('~[ \t]+\n~u', "\n", (string) $t);
    $t = preg_replace('~\n{3,}~u', "\n\n", (string) $t);
    return ['text' => trim((string) $t), 'actions' => $actions];
}


