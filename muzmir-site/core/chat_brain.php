              . '), участник: ' . ($who ?: '—');
        if ($work !== '') $line .= ', номер: ' . $work;
        $line .= ', статус: ' . $g['status'];
        if ($date !== '') $line .= ', подана ' . mb_substr($date, 0, 10);
