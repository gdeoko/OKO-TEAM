/**
 * ЕСТЬ ЛИ У ЭТОЙ СТРАНИЦЫ ВК КАБИНЕТ НА САЙТЕ.
 *
 * Прямой признак один - привязка `users.vk_id`, и она надёжна. Но её почти ни у
 * кого нет: Татьяна Волосатова зарегистрирована (аккаунт 9867, её почта стоит в
 * обеих заявках), а страницу ВК к аккаунту не привязывала - и код трижды
 * пригласил её «завести кабинет», который у неё давно есть.
 *
 * Поэтому при отсутствии привязки смотрим ИМЯ страницы: при ЕДИНСТВЕННОМ полном
 * совпадении имени и фамилии с аккаунтом, у которого есть заявки, человек
 * гостем не считается.
 *
 * ЭТО ГОДИТСЯ ТОЛЬКО ЧТОБЫ ПРОМОЛЧАТЬ, и никогда чтобы раскрыть данные. Цена
 * ошибки в эту сторону - одно неотправленное приглашение; цена обратной (выдать
 * чужие заявки по совпадению имён) непоправима, поэтому номер аккаунта функция
 * не возвращает вовсе: для данных остаётся строгая привязка.
 *
 * Сравнение идёт через LIKE, а он в SQLite для кириллицы различает регистр.
 * Совпадение в другом регистре мы просто не найдём, и это верная сторона
 * ошибки: не нашли - промолчали только о приглашении.
 */
function chat_vk_kabinet_est(int $peer): bool {
    if ($peer <= 0) return false;
    try {
        if ((int) (scalar("SELECT id FROM users WHERE vk_id = ?", [(string) $peer]) ?: 0) > 0) return true;
        $t = trim((string) (scalar("SELECT title FROM chat_dialogs WHERE session_key=?",
                                   ['vk_' . $peer]) ?: ''));
        $w = preg_split('~\s+~u', $t, -1, PREG_SPLIT_NO_EMPTY) ?: [];
        if (count($w) >= 2) {
            $rows = all("SELECT u.id FROM users u
                          WHERE u.full_name LIKE ? AND u.full_name LIKE ?
                            AND EXISTS (SELECT 1 FROM applications a WHERE a.user_id = u.id)
                          LIMIT 3", ['%' . $w[0] . '%', '%' . $w[1] . '%']);
            if (count($rows) === 1) return true;
        }
        return chat_vk_kabinet_po_perepiske('vk_' . $peer);
    } catch (\Throwable $e) { return false; }
}

