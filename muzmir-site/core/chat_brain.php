         . 'Наградной материал предлагай оформлять только по заявке, результат которой участнику уже сообщён.';
    return implode("\n", $L);
}

/**
 * «Обучение на диалоге»: если участник (гость или не привязанный ВК) назвал в переписке
 * НОМЕР ЗАЯВКИ или своё ПОЛНОЕ ФИО / название коллектива, находим его заявки в базе и
 * подтягиваем контекст — чтобы бот отвечал по РЕАЛЬНЫМ данным, а не «из воздуха».
 * Сканируем текущее сообщение и последние реплики участника в этой сессии.
 * @return string готовый блок контекста ('' — ничего не нашли)
 */
function chat_context_from_dialogue(string $sessionKey, string $text): string {
    $blob = ' ' . $text . ' ';
    try {
        foreach (all("SELECT text FROM chat_messages WHERE session_key=? AND role='user' AND text<>'' ORDER BY id DESC LIMIT 12", [$sessionKey]) as $r) {
            $blob .= ' ' . (string) $r['text'];
        }
    } catch (\Throwable $e) {}

    $found = [];
    // 1) По номеру заявки (например VR-2026-00006 / MT-2026-00012).
    if (preg_match_all('~[A-Za-zА-Яа-яЁё]{1,5}-\d{4}-\d{3,6}~u', $blob, $m)) {
        foreach (array_unique($m[0]) as $num) {
            try {
                $a = one("SELECT a.*, c.name AS comp_name, c.is_paid AS comp_paid, c.slug AS comp_slug,
                                 c.results_mode AS comp_results_mode, c.results_date AS comp_results_date,
                                 c.results_published_at AS comp_results_pub
                            FROM applications a JOIN competitions c ON c.id=a.competition_id
                           WHERE UPPER(a.number)=UPPER(?) LIMIT 1", [$num]);
                if ($a) $found[(int) $a['id']] = $a;
            } catch (\Throwable $e) {}
        }
    }
    // 2) По полному ФИО (3 слова с заглавной) — точное совпадение с заявкой/коллективом.
    if (count($found) < 8 && preg_match_all('~([А-ЯЁ][а-яё]+)\s+([А-ЯЁ][а-яё]+)\s+([А-ЯЁ][а-яё]+)~u', $blob, $mm, PREG_SET_ORDER)) {
        foreach ($mm as $set) {
            $fio = $set[1] . ' ' . $set[2] . ' ' . $set[3];
            try {
                $rows = all("SELECT a.*, c.name AS comp_name, c.is_paid AS comp_paid, c.slug AS comp_slug,
                                    c.results_mode AS comp_results_mode, c.results_date AS comp_results_date,
                                    c.results_published_at AS comp_results_pub
                               FROM applications a JOIN competitions c ON c.id=a.competition_id
                              WHERE a.full_name=? ORDER BY a.id DESC LIMIT 8", [$fio]);
                foreach ($rows as $a) $found[(int) $a['id']] = $a;
            } catch (\Throwable $e) {}
            if (count($found) >= 8) break;
        }
    }
    if (!$found) return '';

    // ВТОРОЙ ФАКТОР ОБЯЗАТЕЛЕН.
    //
    // Номер заявки и ФИО — не пароль. Номера идут подряд и печатаются в дипломе,
    // ФИО победителей центр сам публикует в итогах. Раньше этого хватало, чтобы бот
    // выложил кому угодно статус чужой работы, её название и результат аттестации:
    // достаточно было написать в сообщество «MT-2026-00012». Это персональные данные
    // ребёнка, и отдавать их по одному лишь номеру нельзя.
    //
    // Опознание — почта или телефон из САМОЙ заявки, названные в этом же диалоге.
    // Пока их нет, модели сообщается только факт «заявка найдена» и указание
    // попросить подтверждение. Ни ФИО, ни номера работы, ни результата.
    $verified = [];
    $blobLow  = mb_strtolower($blob);
    $digits   = preg_replace('~\D+~', '', $blob);
    foreach ($found as $id => $a) {
        $mail = mb_strtolower(trim((string) ($a['email'] ?? '')));
        $ph   = preg_replace('~\D+~', '', (string) ($a['phone'] ?? ''));
        $okMail = $mail !== '' && mb_strpos($blobLow, $mail) !== false;
        // Телефон сверяем по последним 10 цифрам: люди пишут его как угодно.
        $okPhone = false;
        if ($ph !== '' && mb_strlen($ph) >= 10) {
            $tail = substr($ph, -10);
            $okPhone = $tail !== '' && str_contains((string) $digits, $tail);
        }
        if ($okMail || $okPhone) $verified[$id] = $a;
    }

    if ($verified) {
        // ОДИН РАЗ НАЗВАЛ — БОЛЬШЕ НЕ СПРАШИВАЕМ.
        //
        // Человек уже подтвердил личность почтой или телефоном из заявки, но в
        // следующем разговоре бот снова просил их назвать: связь между страницей
        // ВКонтакте и участником нигде не сохранялась. На 8 261 участника таких
        // связей было ровно 20, то есть почти каждый диалог в сообществе начинался
        // с опознания заново. Здесь связь и запоминается — по подтверждённой заявке.
        chat_bind_vk_peer(array_values($verified));
        return "НАЙДЕНО ПО НАЗВАННЫМ ДАННЫМ, ЛИЧНОСТЬ ПОДТВЕРЖДЕНА (совпали почта или телефон из заявки) — "
            . "отвечай строго по этим заявкам:\n" . _chat_apps_lines(array_values($verified));
    }

    return "ПО НАЗВАННОМУ НОМЕРУ ИЛИ ФИО ЗАЯВКА В БАЗЕ ЕСТЬ (" . count($found) . " шт.), НО ЛИЧНОСТЬ НЕ ПОДТВЕРЖДЕНА.\n"
        . "СТРОГО ЗАПРЕЩЕНО называть по ней хоть что-нибудь: ни ФИО участника, ни конкурс, ни название номера, "
        . "ни статус, ни результат, ни дату подачи. Это персональные данные, и часто данные ребёнка.\n"
        . "Что сделать: сказать, что заявка с такими данными в базе есть, и вежливо попросить назвать "
        . "электронную почту или телефон, указанные при подаче, — только для сверки. "
        . "После того как человек их назовёт, данные откроются сами.";
}

/**
 * ЗАПОМНИТЬ, ЧЬЯ ЭТО СТРАНИЦА ВКОНТАКТЕ.
 *
 * Вызывается только после подтверждения личности (совпали почта или телефон из
 * заявки), поэтому привязка безопасна. Чужую связь не трогаем: если у участника
 * уже стоит другая страница или этот peer закреплён за кем-то ещё, оставляем как
 * есть и пишем в журнал — разберётся человек.
 */
function chat_bind_vk_peer(array $apps): void {
    $peer = (int) ($GLOBALS['chat_vk_peer'] ?? 0);
    if ($peer <= 0 || !$apps) return;
    try {
        $busy = (int) (scalar("SELECT COUNT(*) FROM users WHERE vk_id=?", [(string) $peer]) ?? 0);
        if ($busy > 0) return;                      // страница уже за кем-то закреплена
        foreach ($apps as $a) {
            $uid = (int) ($a['user_id'] ?? 0);
            if ($uid <= 0) {
                $mail = mb_strtolower(trim((string) ($a['email'] ?? '')));
                if ($mail === '') continue;
                $uid = (int) (scalar("SELECT id FROM users WHERE LOWER(email)=?", [$mail]) ?? 0);
            }
            if ($uid <= 0) continue;
            $cur = trim((string) (scalar("SELECT COALESCE(vk_id,'') FROM users WHERE id=?", [$uid]) ?? ''));
            if ($cur !== '') return;                // у участника уже своя страница
            q("UPDATE users SET vk_id=? WHERE id=?", [(string) $peer, $uid]);
            if (function_exists('audit')) audit('chat_vk_bound', 'user', $uid, ['peer' => $peer]);
            return;
        }
    } catch (\Throwable $e) { /* привязка не критична для ответа */ }
}

/**
 * Справка центра (раздел «Вопросы и ответы») одним блоком для промпта.
 * Читается из той же таблицы, что показывает сайт, — расхождение исключено.
 */
function chat_faq_prompt(): string {
    static $cached = null;
    if ($cached !== null) return $cached;
    $rows = [];
    try {
        $rows = all("SELECT question, answer FROM faq WHERE COALESCE(active,1)=1
                      AND TRIM(COALESCE(question,''))<>'' AND TRIM(COALESCE(answer,''))<>''
                   ORDER BY COALESCE(sort,999), id");
    } catch (\Throwable $e) { $rows = []; }
    if (!$rows) return $cached = '';
    $out = ["СПРАВКА ЦЕНТРА — ОФИЦИАЛЬНЫЕ ОТВЕТЫ. Это позиция центра, а не пересказ: "
          . "если вопрос участника про то, что здесь написано, отвечай ЭТИМ, своими словами и без "
          . "выдумок. Ничего не добавляй от себя — придуманная площадка, срок или условие "
          . "превращаются в обещание, которое центру потом исполнять:"];
    foreach ($rows as $r) {
        $out[] = '— ' . trim((string) $r['question']) . ' ' . trim((string) $r['answer']);
    }
    return $cached = implode("\n", $out);
}

