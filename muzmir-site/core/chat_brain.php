/** Нормализация текста вопроса для сравнения (нижний регистр, без пунктуации). */
function chat_norm(string $text): string {
    $t = mb_strtolower(trim($text));
    $t = preg_replace('~[^\p{L}\p{N}\s]+~u', ' ', $t);
    $t = preg_replace('~\s+~u', ' ', (string) $t);
    return trim((string) $t);
}

/**
 * Сколько раз в текущем диалоге пользователь уже задавал по сути ТОТ ЖЕ вопрос
 * (на который мы уже отвечали). 0 — вопрос новый. Служит для короткого ответа
 * «уже писал(а) выше» вместо повторной простыни (и против троллинга/спама).
 * Текущее сообщение уже записано в chat_messages, поэтому его исключаем.
 */
function chat_repeat_count(string $sessionKey, string $text): int {
    $norm = chat_norm($text);
    if (mb_strlen($norm) < 6) return 0;
    $words = array_values(array_unique(array_filter(explode(' ', $norm), fn($w) => mb_strlen($w) >= 3)));
    if (count($words) < 2) return 0;
    try {
        $lastEndId = (int) (scalar("SELECT MAX(id) FROM chat_messages WHERE session_key=? AND role='dialog_end'", [$sessionKey]) ?: 0);
        $curId     = (int) (scalar("SELECT MAX(id) FROM chat_messages WHERE session_key=? AND role='user'", [$sessionKey]) ?: 0);
        $rows = all("SELECT text FROM chat_messages WHERE session_key=? AND role='user' AND id>? AND id<? AND text<>''",
            [$sessionKey, $lastEndId, $curId]);
    } catch (\Throwable $e) { return 0; }
    $set = array_fill_keys($words, 1);
    $hits = 0;
    foreach ($rows as $r) {
        $pw = array_values(array_unique(array_filter(explode(' ', chat_norm((string) $r['text'])), fn($w) => mb_strlen($w) >= 3)));
        if (!$pw) continue;
        $inter = 0; foreach ($pw as $w) if (isset($set[$w])) $inter++;
        $union = count(array_unique(array_merge($words, $pw)));
        if ($union > 0 && ($inter / $union) >= 0.6) $hits++;
    }
    return $hits;
}

