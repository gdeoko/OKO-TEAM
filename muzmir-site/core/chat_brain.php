/**
 * Единый оркестратор ответа: Gemini → Claude → внешний агент → rule-based.
 * @param string   $text       текст входящего сообщения
 * @param string   $sessionKey ключ диалога (веб-сессия или "vk_<peer_id>")
 * @param int|null $uid        id пользователя сайта, если известен
 */
function chat_brain_reply(string $text, string $sessionKey, ?int $uid = null, string $channel = 'vk'): string {
    $GLOBALS['chat_channel']   = $channel; // 'web' = ссылки кнопками, 'vk' = прямыми ссылками
    $GLOBALS['chat_session_key'] = $sessionKey;  // по нему выбирается имя оператора на сегодня
    $GLOBALS['chat_uid'] = $uid;                 // вошёл человек или гость: от этого зависит приглашение
    $GLOBALS['chat_fell_back'] = false;    // признак: «мозг» не ответил, ушли в rule-фолбэк
    $reply = null;

    // Бесплатный тариф Gemini даёт всего пара десятков запросов, и на людном часе
    // квота выбивается за минуты: дальше «мозг» молчит, а участник получает шаблон
    // вместо ответа. Поэтому ключей несколько, и упёршийся в лимит уступает место
    // следующему. Порядок перебора меняется каждый час, чтобы нагрузка расходилась
    // по ключам, а не выжигала первый.
    foreach (chat_gemini_keys() as $key) {
        $reply = chat_gemini_reply($key, $sessionKey, $text);
        if ($reply !== null && $reply !== '') break;
    }
    $apiKey = (string) (cfgv('claude_api_key') ?: '');
    if (($reply === null || $reply === '') && $apiKey !== '') {
        $reply = chat_claude_reply($apiKey, $sessionKey, $text);
    }
    // Внешний мозг-агент, если настроен и выше никто не ответил.
    if (($reply === null || $reply === '') && function_exists('agent_chat_proxy') && ($agentUrl = cfgv('agent_url'))) {
        $reply = agent_chat_proxy((string) $agentUrl, (string) cfgv('agent_token'), $text, $sessionKey, $uid);
    }
    /* ЗАПАСНОЙ МОЗГ — ПОСЛЕДНИЙ ПЕРЕД ЗАГОТОВКОЙ.
     * Он платный, поэтому стоит в самом конце очереди: пока бесплатная норма
     * Gemini жива, сюда не доходит ни один вопрос. */
    if ($reply === null || $reply === '') {
        $reply = chat_apimodels_reply($sessionKey, $text);
    }
    if ($reply === null || $reply === '') {
        // Ни один мозг не ответил — общий шаблон по ключевым словам.
        // Признак поднимаем, чтобы вызывающий код (веб/ВК) мог эскалировать «нет ответа».
        $reply = chat_rule_reply($text);
        $GLOBALS['chat_fell_back'] = true;
    }

    // ПОСЛЕДНЯЯ ПРОВЕРКА ПЕРЕД ОТПРАВКОЙ. Запрет в промпте — просьба, а не замок:
    // модель может назвать звание по памяти диалога, по догадке участника или просто
    // ошибиться. Сторож сверяет готовый текст с реальными скрытыми оценками этого
    // собеседника и подменяет ответ на честное «когда и где», если итог всплыл раньше
    // срока. Подробности — core/chat_gate.php.
    if (!function_exists('chat_gate_guard') && is_file(BASE_PATH . '/core/chat_gate.php')) {
        require_once BASE_PATH . '/core/chat_gate.php';
    }
    if (function_exists('chat_gate_guard')) {
        $reply = chat_gate_guard((string) $reply, (array) ($GLOBALS['chat_gates'] ?? []));
    }
    $reply = chat_strip_escalation((string) $reply, $text);
    $reply = chat_wordfix((string) $reply);
    $reply = chat_fix_reg_dates((string) $reply);   // за датой в положение не отправляем: её там нет
    $reply = chat_strip_reference((string) $reply, $text);

    /* ЗАМОК 1: НА ВОПРОС НЕ ОТВЕЧАЮТ ПРОЩАНИЕМ.
       Эталоны, на которых учится модель, заканчиваются формулой «Благодарим Вас
       за обращение… график работы…», и на живом вопросе («Сколько стоит
       участие?») модель иногда выдаёт ОДНУ эту концовку: человек спросил цену, а
       получил вежливое «до свидания». Ловим по факту: вопрос задан, а в ответе
       только прощание — отвечаем по правилам центра. */
    $isQuestion = mb_strpos($text, '?') !== false
        || preg_match('~^\s*(сколько|как|какая|какие|какой|когда|где|что|почему|зачем|можно|нужно|правда|а если)~ui', trim($text));
    if ($isQuestion && preg_match('~благодарим вас за обращение|рады были вам помочь~ui', $reply)) {
        $core = preg_replace('~🙏?\s*благодарим вас за обращение.*$~uis', '', $reply);
        /* Убираем ТОЛЬКО прощание, не трогая разбивку на строки.
         * Здесь стояло схлопывание любых пробелов подряд в один — и вместе с
         * лишними отступами оно склеивало перечень конкурсов в одну сплошную
         * строку: четыре пункта со сроками приёма читались как абзац. Пробелы
         * внутри строк выправит chat_plain_text() на выходе, ему и оставим. */
        $core = trim(preg_replace('~[ \t]{2,}~u', ' ', (string) $core));
        $reply = mb_strlen($core) >= 40 ? $core : chat_rule_reply($text);
    }

    /* ЗАМОК 2: ПОРЯДОК ЗАКАЗА НАГРАД - НЕ НА УСМОТРЕНИЕ МОДЕЛИ.
       Бот отвечал участнику, что дополнительный диплом можно взять отдельно, а
       касса такой заказ не принимает: человек собирал корзину и упирался в
       отказ. Правило центра жёсткое, поэтому и ответ жёсткий. */
    $qLow = mb_strtolower($text);
    /* ДОПОЛНИТЕЛЬНЫЙ ДИПЛОМ ЛЮДИ НАЗЫВАЮТ ЕГО НОМИНАЦИЕЙ, А НЕ СЛОВОМ «ДОПОЛНИТЕЛЬНЫЙ».
     *
     * Татьяна Волосатова 14.10.2026 спросила «диплом за артистизм надо отдельно
     * оплачивать, или он придёт вместе с основным» - слова «дополнительный
     * диплом» в вопросе нет вовсе, распознаватель её вопрос не узнал, и бот
     * ответил «можете заказать его как отдельно, так и вместе с основным».
     * Жюри присуждает такие дипломы именно номинациями: за артистизм, за
     * патриотизм, за ансамблевую культуру, за сохранение традиций, за
     * искренность исполнения. Поэтому берём и номинацию, и сокращение «доп.». */
    $доп = '(дополнительн\w*\s+диплом|доп\.?\s*диплом|диплом\w*\s+за\s+\w+|за\s+артистизм'
         . '|за\s+патриотизм|за\s+ансамблев|за\s+сохранение\s+традиц|за\s+искренност'
         . '|благодарност|кубок|статуэтк|медал)';
    $askOrderAlone = preg_match('~' . $доп . '~u', $qLow)
        && preg_match('~(без основн|без именн|только доп|отдельно|не нужен основн|не нужна основн)~u', $qLow);
    if ($askOrderAlone && !preg_match('~только вместе с основным~ui', $reply)) {
        $reply = 'Отдельно, без основного или именного диплома, эти награды заказать нельзя — '
               . 'дополнительный диплом, благодарность педагогу, кубок, статуэтка и медаль оформляются '
               . 'только вместе с основным или именным дипломом. Вид при этом выбираете сами: например, '
               . 'основной диплом в электронном виде, а дополнительный — оригиналом на бланке. '
               . 'Собрать заказ можно на нашем официальном сайте Культурного центра '
               . '«Музыкальный Мир», страница «Награды»: ' . url('/awards') . '.';
    }

    /* ЗАМОК 2б: ЛОЖЬ ЛОВИМ В ОТВЕТЕ, А НЕ ТОЛЬКО В ВОПРОСЕ.
       Замок 2 выше срабатывает по вопросу участника, а Татьяне бот сказал
       неправду на вопрос, в котором триггера не было. Вопрос может звучать как
       угодно - проверять надо то, что уходит человеку. */
    $reply = chat_fix_dop_zakaz((string) $reply);

    /* ЗАМОК 3: ЦЕНА И УЧАСТИЕ НЕ УХОДЯТ БЕЗ ДВУХ ССЫЛОК (слово владельца 13.10.2026).
       Стоит последним, после всех подмен ответа выше: любая из них могла отдать
       текст без ссылок, и заслон обязан видеть то, что действительно уйдёт. */
    $reply = chat_ensure_apply_links($text, (string) $reply);

    /* ЗАМОК 3б: ПРЯМОЙ ВОПРОС ПРО РЕГИСТРАЦИЮ УХОДИТ С АДРЕСОМ СТРАНИЦЫ.
       До приписки о сайте: она обязана видеть окончательный текст со ссылкой. */
    $reply = chat_ensure_signup_link($text, (string) $reply);

    /* ЗАМОК 4: САЙТ НАЗЫВАЕТСЯ НАШИМ ОФИЦИАЛЬНЫМ (слово владельца 13.10.2026).
       Стоит ПОСЛЕ заслона на ссылки: тот мог их дописать, и приписка обязана
       видеть окончательный текст. Прощание сюда не попадает вовсе - его
       подшивает chat_wrap_reply уже после мозга, и правило 28 велит отдавать
       его дословно. */
    $reply = chat_ensure_site_phrase((string) $reply);

    /* ЗАМОК 5: ВТОРОЙ РАЗ ЗА РАЗГОВОР НЕ ПРЕДЛАГАЕМ (слово владельца 13.10.2026).
       Самым последним: к этому месту ответ окончателен, и видно, что в нём
       правда осталось. */
    $reply = chat_limit_repeat_offers((string) $reply, $sessionKey, $uid, $text);

    /* ЗАМОК 6: ГОСТЬ ПОЛУЧАЕТ ПРИГЛАШЕНИЕ НА САЙТ (слово владельца 14.10.2026).
       Стоит ПОСЛЕ замка 5: тот снимает повторы предложений, и приглашение,
       дописанное до него, он бы и снял. Здесь ответ окончателен, а проверка
       «не звали ли уже» идёт по самому разговору. */
    $reply = chat_ensure_signup_invite((string) $reply, $sessionKey, $uid);

    /* ЗАМОК 7: АДРЕСА ЧИТАЕМЫЕ, А НЕ PUNYCODE. Самым последним: до этого места
       ссылку мог дописать любой замок. */
    $reply = chat_pretty_links((string) $reply);

    return chat_plain_text($reply);
}

/**
 * РАЗМЕТКИ У НАС НЕТ НИ В ОДНОМ КАНАЛЕ — ЗНАЧИТ, ЕЁ НЕ ДОЛЖНО БЫТЬ И В ОТВЕТЕ.
 *
 * Модель охотно пишет «**В конкурсах с оргвзносом**» и раскладывает перечни
 * звёздочками. ВКонтакте разметку не понимает вовсе, а чат сайта экранирует
 * текст (`esc()` в templates/site/pages/chat.php) — то есть в обоих каналах
 * человек видит ровно эти звёздочки и решётки. Ответ по смыслу правильный
 * выглядит при этом как черновик, отданный по ошибке.
 *
 * Поэтому готовый текст приводится к простому виду: жирное и курсив теряют
 * пометки, перечни становятся точками «•», ссылки в квадратных скобках
 * разворачиваются в обычный адрес. Делаем это ОДИН раз, на выходе из мозга, —
 * тогда любой канал и любая будущая модель получают уже чистый текст.
 */
function chat_plain_text(string $s): string {
    $s = trim($s);
    if ($s === '') return '';

    // [название](адрес) → «название: адрес»; голый <адрес> → адрес.
    $s = preg_replace('~\[([^\]]{1,120})\]\((https?://[^\s)]+)\)~u', '$1: $2', $s) ?? $s;
    $s = preg_replace('~<(https?://[^\s>]+)>~u', '$1', $s) ?? $s;

    // Заголовки и цитаты решёткой в разговоре ни к чему.
    $s = preg_replace('~^[ \t]{0,3}#{1,6}\s*~mu', '', $s) ?? $s;
    $s = preg_replace('~^[ \t]{0,3}>\s?~mu', '', $s) ?? $s;

    // Перечни: «* », «- », «+ », «• » в начале строки — единая точка.
    /* ПРОБЕЛ У ПУНКТА БЫВАЕТ НЕРАЗРЫВНЫМ, И ЭТО НЕ ПРИДИРКА.
       Модель ставит вокруг значка не обычный пробел, а неразрывный (U+00A0) или
       тонкий (U+2009, U+202F) - на вид то же место, для `[ \t]` ничего. Живой
       ответ 13.10 про сроки изготовления так и ушёл бы человеку: «...3 рабочих
       дня. *   Оригиналы на бланках...» - со звёздочкой посреди фразы. Поэтому
       в классе пробелов перечислены и невидимые. */
    /* ПРОБЕЛ БЕРЁМ ЛЮБОЙ, А НЕ СПИСКОМ ВИДОВ.
       Сначала тут стоял `[ \t]`, потом к нему дописали неразрывный и тонкий - и
       живой ответ ВСЁ РАВНО ушёл со звёздочкой посреди фразы. Пробелов в
       Юникоде десятка полтора, и угадывать, какой пришлёт модель в следующий
       раз, бессмысленно: `[^\S\n]` это «любой пробельный знак, кроме перевода
       строки», то есть все они сразу. */
    $s = preg_replace('~^[^\S\n]{0,6}[*+\-\x{2022}][^\S\n]+~mu', '• ', $s) ?? $s;
    /* СПИСОК, СКЛЕЕННЫЙ В ОДНУ СТРОКУ.
       Модель ставит второй пункт следом за первым, в той же строке: «…1000
       рублей за одну заявку. *   В конкурсах «Гордость поколения»…». Построчное
       правило выше такой пункт не видит, и звёздочка с отбивкой остаётся в
       тексте мусором — человек читает «заявку. *   В конкурсах». Возвращаем
       пункту его строку.
       Дефис в список знаков НЕ входит: в русском тексте он сплошь между словами
       («диплом - электронный»), и правило разорвало бы живую фразу. */
    /* Вслед за значком пункта идёт не только буква: у центра почти все перечни
       начинаются названием конкурса в кавычках — «• «Гордость поколения» —
       участие бесплатное». С требованием буквы такой пункт оставался в строке. */
    $s = preg_replace('~([.!?;:\)])[^\S\n]+[*+\x{2022}][^\S\n]+(?=[\x{00AB}"\x{201C}\p{L}\p{N}])~u', "$1\n\u{2022} ", $s) ?? $s;

    // Жирное и курсив. Двойные пометки снимаем первыми, иначе от «**» остаётся «*».
    $s = preg_replace('~\*\*(.+?)\*\*~us', '$1', $s) ?? $s;
    $s = preg_replace('~__(.+?)__~us', '$1', $s) ?? $s;
    $s = preg_replace('~(?<!\S)\*(\S.*?\S|\S)\*(?!\S)~us', '$1', $s) ?? $s;
    $s = preg_replace('~(?<!\S)_(\S.*?\S|\S)_(?!\S)~us', '$1', $s) ?? $s;

    // Моноширинный текст: ограда и одиночные обратные кавычки.
    $s = preg_replace('~```[a-z]*\n?~ui', '', $s) ?? $s;
    $s = preg_replace('~`([^`]+)`~u', '$1', $s) ?? $s;

    // Пустых строк подряд — не больше одной.
    $s = preg_replace('~[ \t]+$~mu', '', $s) ?? $s;
    $s = preg_replace('~\n{3,}~u', "\n\n", $s) ?? $s;

    return trim($s);
}

/**
 * СПРАВОЧНЫЙ ХВОСТ: ГРАФИК, ТЕЛЕФОН, ПОЧТА, СООБЩЕСТВО.
 *
 * В каноне центра сказано прямо: справочный блок ставится ОДИН раз за разговор и
 * только если про это спросили. Модель всё равно подписывает им каждый второй
 * ответ: человек спросил, до какого числа принимают заявки, и получил дату плюс
 * график работы, колл-центр, почту и ссылку на сообщество. Живой оператор так не
 * пишет, а переписка превращается в автоответчик.
 *
 * Поэтому хвост снимается по факту. Спросили про контакты, график, телефон или
 * почту — всё остаётся: там это и есть ответ. Снимаются только строки В КОНЦЕ:
 * справка в середине ответа может оказаться частью объяснения.
 */
function chat_strip_reference(string $reply, string $question = ''): string {
    $reply = trim($reply);
    if ($reply === '') return '';

    $q = mb_strtolower($question);
    foreach (['контакт', 'телефон', 'позвон', 'звон', 'колл-центр', 'график', 'режим работ',
              'часы работ', 'когда вы работ', 'почт', 'написать вам', 'связат', 'вконтакте',
              'сообществ', 'куда обращат'] as $w) {
        if (mb_strpos($q, $w) !== false) return $reply;
    }

    $lines = preg_split('~\R~u', $reply) ?: [$reply];
    $isRef = static function (string $l): bool {
        $l = trim($l);
        if ($l === '') return false;
        /* Строка справки начинается с названия реквизита, иногда со значка перед ним. */
        $l = preg_replace('~^[^\p{L}\d]+~u', '', $l) ?? $l;
        return (bool) preg_match('~^(график работы|колл-центр|телефон|почта|сообщество вконтакте|'
            . 'справка и частые вопросы|мы на связи|звонки со скрытых)~ui', $l);
    };
    while ($lines && ($isRef((string) end($lines)) || trim((string) end($lines)) === '')) array_pop($lines);

    $out = trim(implode("\n", $lines));

    /* СПРАВКА БЫВАЕТ И СТРОКОЙ, А НЕ СТОЛБЦОМ.
     *
     * Модель охотно дописывает её в подбор, прямо в абзац: «…заполнить форму.
     * График работы: Пн-Пт 09:00-18:00. Колл-центр: +7… Сообщество ВКонтакте:
     * https://…». Построчная чистка такое не видит, поэтому следом снимаются
     * хвостовые ПРЕДЛОЖЕНИЯ, начинающиеся с названия реквизита. */
    $доРезки = $out;   // с чем пришли: по нему видно, резали хвост или нет

    $tail = '~(?:\s|^)(?:график работы|колл-центр|телефон|почта|сообщество вконтакте|'
          . 'справка и частые вопросы)\s*[:—-].*$~uis';
    $cut = preg_replace($tail, '', $out);
    if (is_string($cut) && mb_strlen(trim($cut)) >= 40) $out = trim($cut);

    /* ДВОЕТОЧИЯ ПОСЛЕ «ГРАФИК РАБОТЫ» МОЖЕТ И НЕ БЫТЬ.
       Живой ответ 13.10.2026 на вопрос о цене кончался так: «График работы Пн-Пт
       09:00-18:00, Сб 10:00-16:00 … колл-центр +7 … почта kc@…» — без единого
       двоеточия, и правило выше хвост не нашло. Человек спросил цену и получил
       в придачу телефон центра, который канон приписывать к обычному ответу
       запрещает.
       Отдельным правилом идёт ТОЛЬКО «график работы»: этот оборот в середине
       живого ответа не встречается, а вопросы про график и телефон функция
       отпускает ещё в начале. «Колл-центр» без двоеточия сюда НЕ берём — он
       законно стоит в ответе про неработающую форму заявки («позвонить в
       колл-центр, там помогут подать заявку по телефону»), и такую подсказку
       резать нельзя. */
    $cut2 = preg_replace('~(?:\s|^)график работы\b.*$~uis', '', $out);
    if (is_string($cut2) && mb_strlen(trim($cut2)) >= 40) $out = trim($cut2);

    /* ПОСЛЕ СНЯТОГО ХВОСТА ВИСИТ ЗНАЧОК ИЛИ РАЗДЕЛИТЕЛЬ — ЕГО И СНИМАЕМ. БОЛЬШЕ НИЧЕГО.
     *
     * Здесь стояло «снять с конца все знаки и символы», и работало это на КАЖДОМ
     * ответе, даже когда хвоста не было вовсе. Ответ, законно кончавшийся
     * закрывающей кавычкой с точкой — «оформляется на странице «Награды».» —
     * терял оба знака и получал точку внутрь кавычек: «на странице «Награды.».
     * Кавычка осталась незакрытой, и так уходило людям.
     * Поэтому, во-первых, чистим только когда хвост ДЕЙСТВИТЕЛЬНО срезан;
     * во-вторых, снимаем лишь то, что после резки и правда висит в воздухе:
     * пробелы, значки, точку с запятой, запятую, двоеточие, тире. Точка,
     * восклицательный и вопросительный знаки, скобка и кавычка — законный конец
     * предложения, их не трогаем. */
    if ($out !== $доРезки) {
        $out = trim(preg_replace('~[\s\p{S};:,\x{2014}\x{2013}\x{2022}-]+$~u', '', $out) ?? $out);
        if ($out !== '' && !preg_match('~[.!?)»]$~u', $out)) $out .= '.';
    }

    return $out !== '' ? $out : $reply;   // весь ответ и был справкой — оставляем
}

/**
 * СЛОВА, КОТОРЫЕ ЦЕНТР НЕ УПОТРЕБЛЯЕТ.
 *
 * Правило владельца от 13.10.2026: центр не «рассказывает», а отвечает на
 * вопросы, объясняет и поясняет. Запрет стоит и в правилах модели, но правила
 * это просьба, а не замок: на длинном ответе модель всё равно соскальзывает в
 * привычное «расскажу подробнее». Поэтому слово правится по факту, в готовом
 * тексте.
 *
 * Замены идут от длинных оборотов к коротким: сперва целые обороты, у которых
 * есть своя естественная форма («и я всё расскажу» → «и я отвечу на все Ваши
 * вопросы»), и только потом одиночное слово. Наоборот нельзя: заменив слово
 * первым, оборот уже не узнать.
 *
 * Регистр первой буквы сохраняется: «Расскажу» в начале фразы обязано остаться
 * с заглавной.
 */
function chat_wordfix(string $reply): string {
    $reply = trim($reply);
    if ($reply === '' || mb_stripos($reply, 'расска') === false) return $reply;

    $phrases = [
        /* Предлог может стоять и ПЕРЕД глаголом: «об этом расскажут в положении».
           «Объяснят» здесь тоже не встаёт, а по-человечески это «сказано». */
        '~\b(об|о)\s+(этом|н[её]м|ней|них)\s+расскаж(?:ет|ут|у|ем)~ui' => '$1 $2 сказано',
        '~\bи я вс[её] расскажу~ui'            => 'и я отвечу на все Ваши вопросы',
        '~\bвс[её] подробно расскажу~ui'       => 'подробно отвечу на Ваши вопросы',
        '~\bрасскажу подробн(ее|ей)~ui'        => 'объясню подробнее',
        '~\bрасскажу обо вс[её]м~ui'           => 'отвечу на все Ваши вопросы',
        '~\bмогу рассказать\s+(об|о)\b~ui'    => 'могу ответить на вопрос $1',
        '~\bмогу рассказать~ui'                => 'могу объяснить',
        '~\bрасскажу(?:\s+(?:вам|Вам|тебе|им|ему|ей))?\s+(об|о)\b~ui'          => 'отвечу на Ваш вопрос $1',
        '~\bрасскажем(?:\s+(?:вам|Вам|тебе|им|ему|ей))?\s+(об|о)\b~ui'         => 'ответим на Ваш вопрос $1',
        '~\bрасскажет(?:\s+(?:вам|Вам|тебе|им|ему|ей))?\s+(об|о)\b~ui'         => 'ответит на Ваш вопрос $1',
        '~\bрасскажут(?:\s+(?:вам|Вам|тебе|им|ему|ей))?\s+(об|о)\b~ui'         => 'ответят на Ваш вопрос $1',
        '~\bрассказать\s+(об|о)\b~ui'        => 'ответить на вопрос $1',
        '~\bрасскаж(и|ите) о себе~ui'          => 'напишите, пожалуйста, о себе',
        '~\bрасскаж(и|ите) подробн(ее|ей)~ui'  => 'уточните, пожалуйста, подробности',
    ];
    $words = [
        '~\bрасскажу\b~ui'    => 'объясню',
        '~\bрасскажем\b~ui'   => 'объясним',
        '~\bрасскажет\b~ui'   => 'объяснит',
        '~\bрасскажут\b~ui'   => 'объяснят',
        '~\bрассказать\b~ui'  => 'объяснить',
        '~\bрассказыва(ю|ем)\b~ui' => 'объясняем',
    ];

    $keepCase = static function (string $src, string $dst): string {
        $first = mb_substr($src, 0, 1);
        if ($first === mb_strtoupper($first) && $first !== mb_strtolower($first)) {
            return mb_strtoupper(mb_substr($dst, 0, 1)) . mb_substr($dst, 1);
        }
        return $dst;
    };

    foreach ([$phrases, $words] as $set) {
        foreach ($set as $re => $to) {
            $reply = preg_replace_callback($re, static function (array $m) use ($to, $keepCase): string {
                /* В части замен есть обратная ссылка ($1 — предлог «о» или «об»):
                   «объяснить» этим предлогом не управляет, и «объяснит о сроках»
                   звучит сломанно. Подставляем ссылку до того, как чинится регистр. */
                $out = $to;
                for ($i = count($m) - 1; $i >= 1; $i--) {
                    $out = str_replace('$' . $i, (string) $m[$i], $out);
                }
                return $keepCase($m[0], $out);
            }, $reply) ?? $reply;
        }
    }
    return $reply;
}

/**
 * ПОСЛЕДНЯЯ ЧИСТКА: «К СОЖАЛЕНИЮ, ОБРАТИТЕСЬ К СОТРУДНИКУ».
 *
 * Запрет в промпте — просьба, а не замок: модель всё равно нет-нет да допишет
 * «к сожалению, мне лучше подключить сотрудника» или «позвоните в колл-центр»
 * после нормального ответа. Для участника это значит одно: ему не ответили, и
 * разговаривает он с автоответчиком. Поэтому такие предложения вырезаются из
 * готового текста — по факту, а не по обещанию модели.
 *
 * Вырезаются именно предложения, а не весь ответ: остальное человеку полезно.
 * Если после чистки не осталось ничего — значит весь ответ и был отговоркой,
 * и тогда лучше честная фраза «уточню и вернусь», чем просьба звонить.
 *
 * Не трогаем случай, когда человек сам спросил про телефон, звонок или пожаловался
 * на неработающий сайт: там контакт — это и есть ответ.
 */
function chat_strip_escalation(string $reply, string $question = ''): string {
    $reply = trim($reply);
    if ($reply === '') return '';
    $q = mb_strtolower($question);
    foreach (['телефон', 'позвон', 'звонк', 'колл-центр', 'не работает', 'не открыва', 'жалоб',
              'верните деньги', 'возврат', 'оператор', 'руководител'] as $w) {
        if (mb_strpos($q, $w) !== false) return $reply;   // спросили сами — отвечаем как есть
    }

    $bad = '~(к сожалению[^.!?]{0,40}(не могу|не смогу|нет возможности|лучше)'
         . '|подключить (сотрудника|оператора|специалиста)'
         . '|переда(м|ю|ла)[^.!?]{0,30}(оператор|специалист|сотрудник|коллег)'
         . '|обратит(есь|ься)[^.!?]{0,40}(колл-центр|оператор|сотрудник)'
         . '|(позвонит[ье]|звоните|наберите)[^.!?]{0,60}(колл-центр|\+7|телефон)'
         . '|просим позвонить'
         . ')~ui';

    $parts = preg_split('~(?<=[.!?])\s+~u', $reply) ?: [$reply];
    $keep = [];
    foreach ($parts as $sent) {
        if (preg_match($bad, $sent)) continue;
        $keep[] = $sent;
    }
    $out = trim(implode(' ', $keep));
    // Пустые строки и «висящие» переносы после вырезанного куска.
    $out = trim(preg_replace('~\n{3,}~u', "

", $out) ?? $out);
    // Порог низкий нарочно: «Диплом придёт в течение 5 рабочих дней» — это 39
    // символов и полноценный ответ. Заглушка нужна только если не осталось
    // вообще ничего, кроме огрызка.
    if (mb_strlen($out) >= 25) return $out;
    return 'Уточню этот вопрос у коллег из оргкомитета и вернусь к Вам с ответом.';
}

/**
 * Эскалация «нет ответа»: «мозг» ушёл в rule-фолбэк (не смог точно ответить по вопросу).
 * Один раз за сессию (маркер role='escalated_noanswer', отдельно от keyword-эскалации):
 *   (а) возвращает пользователю текст-приписку с просьбой позвонить в колл-центр;
 *   (б) уведомляет владельца в Телеграм (owner_notify): имя/фамилия, все заявки со
 *       статусами, телефон (если нет — почта/ссылка ВК), краткая суть обращения.
 * @param int|null $uid     id пользователя сайта (в ВК — привязанный к peer, если есть)
 * @param string   $channel 'web' | 'vk'
 * @param array    $extra   доп. поля для владельца (напр. ссылка на диалог ВК)
 * @return string текст-приписка для пользователя ('' — если уже эскалировали в этой сессии)
 */
function chat_escalate_no_answer(?int $uid, string $sessionKey, string $name, string $userText, string $channel = 'web', array $extra = []): string {
    // Строго один раз за сессию.
    try {
        $done = (int) scalar("SELECT COUNT(*) FROM chat_messages WHERE session_key=? AND role='escalated_noanswer'", [$sessionKey]);
        if ($done > 0) return '';
    } catch (\Throwable $e) { return ''; }

    $tel = (string) cfgv('org_phone');

    // Контактные данные участника: ФИО, телефон, почта.
    $fio = trim($name); $phone = ''; $email = '';
    if ($uid) {
        try {
            $u = one("SELECT full_name, phone, email FROM users WHERE id=?", [$uid]);
            if ($u) {
                $fio   = trim((string) ($u['full_name'] ?? '')) ?: $fio;
                $phone = trim((string) ($u['phone'] ?? ''));
                $email = trim((string) ($u['email'] ?? ''));
            }
        } catch (\Throwable $e) { /* тихо */ }
    }

    // Все заявки участника со статусами (компактно, для владельца).
    $appsLines = [];
    if ($uid) {
        $stMap = ['new' => 'на рассмотрении', 'pending' => 'на рассмотрении', 'submitted' => 'принята, ожидает аттестации',
            'paid' => 'оплачена, ожидает аттестации', 'review' => 'на аттестации жюри', 'judging' => 'на аттестации жюри',
            'scored' => 'аттестована (результат готов)', 'done' => 'аттестована (результат готов)',
            'rejected' => 'отклонена', 'unpaid' => 'ожидает оплаты'];
        try {
            $apps = all("SELECT a.number, a.status, a.result, c.name AS comp_name
                           FROM applications a JOIN competitions c ON c.id = a.competition_id
                          WHERE a.user_id = ? ORDER BY a.id DESC LIMIT 15", [$uid]);
            foreach ($apps as $a) {
                $st  = $stMap[(string) ($a['status'] ?? '')] ?? (string) ($a['status'] ?? '—');
                $res = trim((string) ($a['result'] ?? ''));
                $ln  = '№' . (string) ($a['number'] ?? '') . ' «' . (string) ($a['comp_name'] ?? '') . '» — ' . $st;
                if ($res !== '') $ln .= ', результат: ' . $res;
                $appsLines[] = $ln;
            }
        } catch (\Throwable $e) { /* тихо */ }
    }

    // Транскрипт последних сообщений — краткая суть обращения для оператора.
    $lines = [];
    try {
        $rows = all("SELECT role, text FROM chat_messages WHERE session_key=? AND role IN ('user','assistant') ORDER BY id DESC LIMIT 10", [$sessionKey]);
        foreach (array_reverse($rows) as $r) {
            $who = ($r['role'] ?? '') === 'user' ? '👤' : '🤖';
            $tx  = trim((string) $r['text']);
            if ($tx !== '') $lines[] = $who . ' ' . mb_substr($tx, 0, 220);
        }
    } catch (\Throwable $e) {}
    if (!$lines) $lines[] = '👤 ' . mb_substr(trim($userText), 0, 220);

    // Контакт для оператора: телефон → почта → ссылка/пометка ВК.
    $contact = $phone !== '' ? $phone : ($email !== '' ? $email : '');
    if ($contact === '' && !empty($extra['Ссылка'])) $contact = (string) $extra['Ссылка'];

    if (!function_exists('owner_notify') && is_file(BASE_PATH . '/core/notify_owner.php')) {
        require_once BASE_PATH . '/core/notify_owner.php';
    }
    /* ВЛАДЕЛЬЦА ДЁРГАЕМ ТОЛЬКО ПО ДЕНЬГАМ И ЖЁСТКОЙ ЖАЛОБЕ.
     *
     * Сюда попадают все случаи, когда «мозг» ушёл в запасной разбор по правилам:
     * кончилась квота модели, оборвался запрос, был таймаут. Это техническая
     * осечка, а не сложный вопрос — ответ участник всё равно получает. Уведомление
     * при этом называлось «Бот не смог ответить — нужен оператор», и владелец
     * читал его как сигнал вмешаться. Приходили они постоянно и обесценили сами
     * себя: среди них терялось то единственное, ради чего оператор и нужен.
     *
     * Правило владельца от 03.09.2026: звать человека — только на возврат денег
     * и жёсткую жалобу. Всё остальное бот доводит сам, а осечка модели остаётся
     * отметкой в базе, по которой её видно в админке и в статистике. */
    $urgent = (bool) preg_match(
        '~верн\w*\s+деньг|возврат|вернуть\s+(деньги|оргвзнос|средства)|компенсац'
        . '|жалоб|прокуратур|роспотребнадзор|суд\b|исков|мошенн|обман\w*|развод\w*'
        . '|полици|заявлени\w*\s+в\s+|отзыв\w*\s+(везде|на всех)|159\s*ук~ui',
        $userText);

    if ($urgent && function_exists('owner_notify')) {
        $fields = [
            'Участник' => ($fio !== '' ? $fio : 'гость') . ($channel === 'vk' ? ' (ВКонтакте)' : ''),
            'Телефон'  => $phone,
            'Почта'    => $email,
            'Заявки'   => $appsLines ? mb_substr(implode('; ', $appsLines), 0, 500) : '—',
            'Суть'     => mb_substr(trim($userText), 0, 240),
            'Сессия'   => $sessionKey,
            '_event'   => 'chat_escalation_no_answer',
            '_meta'    => ['session' => $sessionKey, 'uid' => (int) ($uid ?? 0), 'channel' => $channel],
        ] + $extra;
        try {
            owner_notify('ЧАТ-БОТ', '🔔 Бот не смог ответить — нужен оператор', implode("\n", $lines), $fields);
        } catch (\Throwable $e) { /* тихо */ }
    }

    // Маркер: эскалация «нет ответа» уже выполнена в этой сессии.
    try { insert('chat_messages', ['user_id' => $uid, 'session_key' => $sessionKey, 'role' => 'escalated_noanswer', 'text' => '', 'file' => '']); } catch (\Throwable $e) {}

    /* УЧАСТНИКУ ЗДЕСЬ НИЧЕГО НЕ ДОПИСЫВАЕМ.
     *
     * Раньше к каждому ответу, где «мозг» не справился, цеплялась приписка
     * «мне лучше подключить сотрудника, позвоните в колл-центр». Человек читал
     * нормальный ответ на свой вопрос — и тут же просьбу звонить, будто ему
     * ничего не ответили. Такие приписки и делают из помощника автоответчик.
     *
     * Владелец в Телеграме уведомление получает по-прежнему (выше): он видит,
     * что бот не справился, и может вмешаться. А участник видит только ответ.
     * Звать человека вслух уместно лишь в срочном — жалоба, возврат, спор, —
     * и этим занимается chat_maybe_escalate по своим ключевым словам. */
    return '';
}

/**
 * Пронумерованный список действующих заявок участника — для ВК (клавиатур нет,
 * поэтому список цифрами/номерами прямо в тексте). Аналог выпадающего <select>
 * на сайте. Показываем только когда: вопрос про результат/диплом, действующих
 * заявок больше одной и конкретный номер ещё не назван. Иначе — '' (список не нужен,
 * бот отвечает сразу; при одной заявке уточнять нечего).
 */
function chat_apps_numbered_text(?int $uid, string $userText): string {
    if (!$uid) return '';
    $t = mb_strtolower($userText);
    $ask = false;
    foreach (['результат', 'итог', 'балл', 'оцен', 'диплом', 'сертификат', 'аттест', 'провер', 'готов', 'когда'] as $w) {
        if (mb_strpos($t, $w) !== false) { $ask = true; break; }
    }
    if (!$ask) return '';
    try {
        // Поля конкурса нужны, чтобы подпись к заявке не проговорилась о результате
        // раньше срока: «аттестована, результат готов» — это уже половина ответа.
        $apps = all("SELECT a.*, c.name AS comp_name,
                            c.results_mode AS comp_results_mode, c.results_date AS comp_results_date,
                            c.results_published_at AS comp_results_pub
                       FROM applications a JOIN competitions c ON c.id = a.competition_id
                      WHERE a.user_id = ? AND a.status NOT IN ('rejected')
                   ORDER BY a.id DESC LIMIT 15", [$uid]);
    } catch (\Throwable $e) { return ''; }
    if (count($apps) <= 1) return '';
    // Конкретный номер уже назван (номер заявки как подстрока сообщения) — список не нужен.
    foreach ($apps as $a) {
        $num = trim((string) ($a['number'] ?? ''));
        if ($num !== '' && mb_stripos($userText, $num) !== false) return '';
    }
    if (!function_exists('chat_gate_app')) require_once BASE_PATH . '/core/chat_gate.php';
    $L = ['У Вас несколько заявок. Подскажите, пожалуйста, по какой именно вопрос — ответьте её номером (например, №' . (string) ($apps[0]['number'] ?? '') . '):'];
    $i = 0;
    foreach ($apps as $a) {
        $i++;
        $num = (string) ($a['number'] ?? '');
        $g   = chat_gate_app((array) $a);
        $L[] = $i . ') Заявка №' . $num . ' «' . (string) ($a['comp_name'] ?? '') . '» — ' . $g['status'];
    }
    return implode("\n", $L);
}

