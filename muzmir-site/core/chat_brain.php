/**
 * КЛЮЧ РАЗГОВОРА В ВЕБЕ — ОДИН НА ВСЮ СТРАНИЦУ И НА ОТВЕТЫ.
 *
 * По ключу выбирается имя оператора на сегодня, и окно чата должно взять ТО ЖЕ
 * имя, которым помощник подпишется в ответе. Ключ рождался внутри api/v1/chat.php,
 * то есть только при первом вопросе: страница, нарисованная раньше, имени ещё не
 * знала и назвала бы другое. Поэтому ключ заводится здесь, и обе стороны берут
 * его отсюда.
 */
function chat_web_session_key(): string {
    if (session_status() !== PHP_SESSION_ACTIVE) @session_start();
    if (!isset($_SESSION['chat_key']) || !is_string($_SESSION['chat_key']) || $_SESSION['chat_key'] === '') {
        $_SESSION['chat_key'] = bin2hex(random_bytes(8));
    }
    return (string) $_SESSION['chat_key'];
}

/**
 * Строка приветствия. С именем участника, если известно, и с представлением
 * оператора, когда разговор только начинается.
 *
 * ПОЧЕМУ ПРЕДСТАВЛЕНИЕ ЗДЕСЬ, А НЕ В ПРАВИЛАХ МОЗГА. В правилах стоит «если
 * уместно представиться», и уместность модель решала сама: в половине разговоров
 * она сразу переходила к делу, и человек ни разу не слышал имени. Владелец
 * просил имя именно в приветственном диалоге, поэтому первая строка нового
 * разговора несёт его всегда, а мозг тут ни при чём.
 */
function chat_greet_line(string $name = '', string $self = ''): string {
    $name = trim($name);
    $line = $name !== '' ? 'Здравствуйте, ' . $name . '!' : 'Здравствуйте!';
    $self = trim($self);
    if ($self !== '') {
        $line .= ' Меня зовут ' . $self . ', я оператор Культурного центра «Музыкальный Мир».';
    }
    return $line;
}

