 * иначе они разойдутся — так уже было с пунктами положения (правило 33).
 *
 * «Действующий» это ТРИ условия вместе, и каждое ловит свою беду:
 *   • launched=1 — запуск объявляет владелец, черновик людям не показываем;
 *   • status='open' — аттестация и завершённый конкурс заявок не принимают;
 *   • СЕГОДНЯ внутри приёма — у закрытого конкурса статус переключает крон
 *     ночью, и до его прихода «open» с кончившимся приёмом врал бы ещё сутки.
 *     Та же проверка спасает от конкурса следующего месяца, заведённого заранее.
 */
/**
 * Срок результата У ЭТОГО конкурса словами, пусто - если срок задаёт дата.
 *
 * Общая лестница (5 обычному, 4 партнёру, 3 клубному) верна, но на вопрос
 * «когда результаты Мирового акцента» человек читает ПЕРВОЕ число и уходит
 * ждать пять дней вместо трёх. У конкурса, куда пускают только членов Клуба,
 * все участники клубные, и срок у него один - свой (слово владельца
 * 18.10.2026). Число берёт `prioritet_dnei_konkursa()`, своей копии тут нет:
 * копия обещания расходится молча (правила 33, 35, 45, 47).
 */
function chat_srok_konkursa(array $c): string {
    if ((string) ($c['results_mode'] ?? '') === 'list') return '';   // срок задаёт дата оглашения
    if (!function_exists('prioritet_dnei_konkursa') && is_file(BASE_PATH . '/core/prioritet.php')) {
        require_once BASE_PATH . '/core/prioritet.php';
    }
    if (!function_exists('prioritet_dnei_konkursa')) return '';
    $дней = prioritet_dnei_konkursa($c);
    return 'результат за ' . (function_exists('prioritet_dney')
        ? prioritet_dney($дней) : $дней . ' рабочих дней');
}

