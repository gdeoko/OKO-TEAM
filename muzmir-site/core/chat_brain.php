            "SELECT role, text FROM chat_messages WHERE session_key=? AND text<>'' ORDER BY id DESC LIMIT 12",
            [$sessionKey]
        );
        foreach (array_reverse($rows) as $r) {
            $role = ($r['role'] ?? '') === 'assistant' ? 'model' : 'user';
            if (!$contents && $role === 'model') continue;
            $contents[] = ['role' => $role, 'parts' => [['text' => (string) $r['text']]]];
        }
    } catch (\Throwable $e) { $contents = []; }
    if (!$contents || end($contents)['role'] !== 'user') {
        $contents[] = ['role' => 'user', 'parts' => [['text' => $text]]];
    }

    /* НЕ ОДНА МОДЕЛЬ, А ОЧЕРЕДЬ.
     *
     * У бесплатных ключей лимит считается по каждой модели отдельно, и тяжёлая
     * выбивает квоту первой: сегодня к полудню основная отвечала 429, а лёгкие
     * работали как ни в чём не бывало — но помощник этого не знал и весь день
     * молчал бы шаблонами. Теперь при отказе по квоте или перегрузке пробуем
     * следующую модель из очереди. Порядок — от лучшей к самой выносливой. */
    $models = array_values(array_filter(array_map('trim',
        preg_split('~[,\s]+~', (string) (cfgv('gemini_models') ?: '')) ?: [])));
    if (!$models) {
        $models = [(string) (cfgv('gemini_model') ?: 'gemini-2.5-flash'),
                   'gemini-3-flash-preview', 'gemini-flash-lite-latest', 'gemini-3.1-flash-lite'];
    }
    $models = array_values(array_unique($models));
    $payload = json_encode([
        'systemInstruction' => ['parts' => [['text' => chat_system_prompt()]]],
        'contents'          => $contents,
        /* РАЗМЫШЛЕНИЯ ВЫКЛЮЧЕНЫ. Новые модели по умолчанию сначала «думают
         * вслух», и эти черновики приходят такими же частями ответа: участник
         * получал английский разбор промпта вместо ответа оператора. Оператору
         * колл-центра размышления не нужны — нужен короткий готовый ответ. */
        'generationConfig'  => ['maxOutputTokens' => 1000, 'temperature' => 0.4,
                                'thinkingConfig' => ['thinkingBudget' => 0]],
    ], JSON_UNESCAPED_UNICODE);

    $base = rtrim((string) (cfgv('gemini_base_url') ?: 'https://generativelanguage.googleapis.com'), '/');
    $resp = null; $err = 0; $code = 0; $model = '';
    foreach ($models as $try) {
    $model = $try;
    $ch = curl_init($base . '/v1beta/models/'
        . rawurlencode($model) . ':generateContent?key=' . rawurlencode($apiKey));
    curl_setopt_array($ch, [
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_POST           => true,
        CURLOPT_POSTFIELDS     => $payload,
        CURLOPT_HTTPHEADER     => ['Content-Type: application/json'],
        /* ДВЕНАДЦАТИ СЕКУНД НЕ ХВАТАЛО.
         * Модель с большим системным промптом отвечает около десяти секунд, и
         * запрос обрывался почти на финише: «мозг» считался молчащим, участник
         * получал шаблон с просьбой позвонить. Ответ всё равно показывается не
         * мгновенно (обычному участнику — через пять минут), так что лишние
         * секунды ожидания ему ничего не стоят, а живой ответ стоят. */
        /* ОДНА МОДЕЛЬ НЕ ИМЕЕТ ПРАВА СЪЕСТЬ ВЕСЬ ОТВЕТ.
         *
         * Здесь стояло 25 секунд на попытку — и ровно столько уходило впустую,
         * когда основная модель задумывалась: очередь моделей до лёгкой не
         * доходила, участник получал шаблон. Замерено: gemini-3.5-flash
         * отвечает за 7–9 секунд, иногда не отвечает вовсе;
         * gemini-flash-lite — за одну. Значит ждать первую дольше
         * четырнадцати секунд незачем: лучше спросить следующую и ответить
         * человеку живым текстом, чем молчать до таймаута. */
        CURLOPT_TIMEOUT        => max(5, (int) (cfgv('chat_model_timeout') ?: 14)),
        CURLOPT_CONNECTTIMEOUT => 5,
    ]);
    $resp = curl_exec($ch);
    $err  = curl_errno($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
    curl_close($ch);

    /* ПУСТОЙ ОТВЕТ — ТОЖЕ ОТКАЗ. Модель отвечает «200 OK», а внутри
     * finishReason=MAX_TOKENS и ни одной части текста: весь бюджет ушёл на
     * размышления. Раньше это возвращалось как null и разговор кончался
     * шаблоном, хотя соседняя модель ответила бы за секунду. */
    $empty = false;
    if (!$err && $code < 400) {
        $dd = json_decode((string) $resp, true);
        $parts = $dd['candidates'][0]['content']['parts'] ?? [];
        $txt = '';
        foreach ((array) $parts as $p) { if (empty($p['thought']) && isset($p['text'])) $txt .= (string) $p['text']; }
        $empty = trim($txt) === '';
    }
    // Ошибку «мозга» пишем в лог: без неё молчание выглядит как исправная работа,
    // а участник получает шаблон, и никто не знает почему.
    if (($err || $code >= 400 || $empty) && function_exists('mail_log')) {
        mail_log('CHAT gemini ' . ($err ? ('curl ' . $err) : ($empty ? 'пустой ответ' : ('HTTP ' . $code)))
                 . ' key=' . substr($apiKey, 0, 8) . ' model=' . $model);
    }
    // Модель не ответила по своей причине — спрашиваем следующую тем же ключом:
    // кончилась квота (429), перегружена (503), задумалась до таймаута или
    // прислала пустоту. Прочие ошибки перебирать незачем — они про запрос.
    if ($code === 429 || $code === 503 || $err === CURLE_OPERATION_TIMEDOUT || $empty) continue;
    break;
    }
    // Ключ считаем выбитым, только если по квоте отказали ВСЕ модели: иначе
    // завтрашняя очередь начнётся с ключа, который на самом деле работает.
    if ($code === 429) chat_gemini_mark_exhausted($apiKey, chat_gemini_retry_after((string) $resp));
    // Молчал на всех моделях — ключ не в форме, следующие сообщения начнём с другого.
    if ($err === CURLE_OPERATION_TIMEDOUT) chat_gemini_mark_silent($apiKey);
    if ($err || !$resp || $code >= 400) return null;

    $d = json_decode((string) $resp, true);
    if (!is_array($d) || empty($d['candidates'][0]['content']['parts'])) return null;
    $out = '';
    foreach ($d['candidates'][0]['content']['parts'] as $p) {
        // Часть с thought=true — это черновик рассуждения модели, а не ответ.
        // Просить не думать мало: если модель всё же прислала мысли, они не
        // должны попасть человеку.
        if (!empty($p['thought'])) continue;
        if (isset($p['text'])) $out .= (string) $p['text'];
    }
    $out = trim($out);
    return $out !== '' ? $out : null;
}

/**
 * ЗАПАСНОЙ МОЗГ ПОМОЩНИКА: apimodels, тот же счёт, что у картинок конвейера.
 *
 * ЗАЧЕМ. Квота Gemini у центра ОДНА на чат и на конвейер постов
 * (`MUZMIR_GEMINI_KEYS`), и конвейер способен выесть её за утро. Дальше участник
 * вместо ответа получает заготовку по ключевым словам — вежливую, но мимо
 * вопроса: про заявку он спросил одно, а ему пришёл общий текст про сроки.
 * Пока бесплатная норма есть, деньги не тратятся: сюда доходит только то, на что
 * Gemini не ответил.
 *
 * ВКЛЮЧАЕТ ВЛАДЕЛЕЦ (`chat_brain_fallback=1` на пульте «Чат-бот»), и у мозга
 * свой дневной предел вызовов: один ответ участнику это один вызов, поэтому
 * предел считается в ответах и по умолчанию двести в сутки.
 *
 * Модель отвечает ОБЫЧНЫМ ТЕКСТОМ, а не JSON (в отличие от конвейера постов):
 * ответ участнику дальше проходит те же замки, что и ответ Gemini — сторож
 * результатов, чистка слов, снятие справочного хвоста.
 */
function chat_apimodels_reply(string $sessionKey, string $text): ?string {
    if ((int) setting('chat_brain_fallback', '0') !== 1) return null;
    $key = trim((string) (cfgv('apimodels_key') ?: ''));
    if ($key === '') return null;

    $day = json_decode((string) setting('chat_brain_day', '{}'), true);
    if (!is_array($day) || ($day['date'] ?? '') !== date('Y-m-d')) {
        $day = ['date' => date('Y-m-d'), 'calls' => 0, 'in' => 0, 'out' => 0];
    }
    $limit = (int) setting('chat_brain_fallback_limit', '200');
    if ($limit > 0 && (int) $day['calls'] >= $limit) {
        if (function_exists('mail_log')) mail_log('CHAT запасной мозг: дневной предел ' . $limit . ' исчерпан');
        return null;
    }

    $GLOBALS['chat_last_question'] = $text;   // по нему подбираются уроки для промпта

    /* История та же, что у основного мозга: без неё помощник переспрашивает то,
       что человек уже написал двумя репликами выше. */
    $msgs = [];
    try {
        $rows = all("SELECT role, text FROM chat_messages WHERE session_key=? AND text<>'' ORDER BY id DESC LIMIT 12",
                    [$sessionKey]);
        foreach (array_reverse($rows) as $r) {
            $role = ($r['role'] ?? '') === 'assistant' ? 'assistant' : 'user';
            if (!$msgs && $role === 'assistant') continue;   // первым обязан идти человек
            $msgs[] = ['role' => $role, 'content' => (string) $r['text']];
        }
    } catch (\Throwable $e) { $msgs = []; }
    if (!$msgs || end($msgs)['role'] !== 'user') $msgs[] = ['role' => 'user', 'content' => $text];

    $model = (string) setting('chat_brain_fallback_model', 'claude-haiku-5-5');
    $base  = rtrim((string) (cfgv('apimodels_base') ?: 'https://api.apimodels.app/v1'), '/');
    $body  = json_encode([
        'model'       => $model,
        'messages'    => array_merge([['role' => 'system', 'content' => chat_system_prompt()]], $msgs),
        'max_tokens'  => 1000,
        'temperature' => 0.4,
    ], JSON_UNESCAPED_UNICODE);

    $ch = curl_init($base . '/chat/completions');
    curl_setopt_array($ch, [
        CURLOPT_POST => true,
        CURLOPT_POSTFIELDS => $body,
        CURLOPT_HTTPHEADER => ['Content-Type: application/json', 'Authorization: Bearer ' . $key],
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_TIMEOUT => 60,
    ]);
    $res  = curl_exec($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);

    if ($code !== 200 || !is_string($res)) {
        $why = '';
        if (is_string($res)) {
            $j = json_decode($res, true);
            $why = trim((string) ($j['msg'] ?? $j['error']['message'] ?? ''));
        }
        if (function_exists('mail_log')) mail_log("CHAT запасной мозг ответил {$code} {$why}");
        return null;
    }

    $j = json_decode($res, true);
    $day['calls']++;
    $day['in']  += (int) ($j['usage']['prompt_tokens'] ?? 0);
    $day['out'] += (int) ($j['usage']['completion_tokens'] ?? 0);
    set_setting('chat_brain_day', json_encode($day));

    $out = trim((string) ($j['choices'][0]['message']['content'] ?? ''));
    if ($out === '') return null;
    if (function_exists('mail_log')) mail_log("CHAT ответил запасной мозг ({$model})");
    return $out;
}

/** Вызов Claude API (api.anthropic.com /v1/messages). Тихий фолбэк на null при любой ошибке. */
function chat_claude_reply(string $apiKey, string $sessionKey, string $text): ?string {
    $GLOBALS['chat_last_question'] = $text;   // по нему подбираются уроки для промпта
    // Последние сообщения сессии -> messages для API (первым обязан идти user).
    $messages = [];
    try {
        $rows = all(
            "SELECT role, text FROM chat_messages WHERE session_key=? AND text<>'' ORDER BY id DESC LIMIT 12",
            [$sessionKey]
        );
        foreach (array_reverse($rows) as $r) {
            $role = ($r['role'] ?? '') === 'assistant' ? 'assistant' : 'user';
            if (!$messages && $role === 'assistant') continue;
            $messages[] = ['role' => $role, 'content' => (string) $r['text']];
        }
    } catch (\Throwable $e) { $messages = []; }
    if (!$messages || end($messages)['role'] !== 'user') {
        $messages[] = ['role' => 'user', 'content' => $text];
    }

    $payload = json_encode([
        'model'      => 'claude-haiku-4-5-20251001',
        'max_tokens' => 500,
        'system'     => chat_system_prompt(),
        'messages'   => $messages,
    ], JSON_UNESCAPED_UNICODE);

    $ch = curl_init('https://api.anthropic.com/v1/messages');
    curl_setopt_array($ch, [
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_POST           => true,
        CURLOPT_POSTFIELDS     => $payload,
        CURLOPT_HTTPHEADER     => [
            'Content-Type: application/json',
            'x-api-key: ' . $apiKey,
            'anthropic-version: 2023-06-01',
        ],
        CURLOPT_TIMEOUT        => 12,
        CURLOPT_CONNECTTIMEOUT => 5,
    ]);
    $resp = curl_exec($ch);
    $err  = curl_errno($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
    curl_close($ch);
    if ($err || !$resp || $code >= 400) return null;

    $d = json_decode((string) $resp, true);
    if (!is_array($d) || ($d['type'] ?? '') === 'error') return null;
    if (($d['stop_reason'] ?? '') === 'refusal') return null;
    $out = '';
    foreach (($d['content'] ?? []) as $b) {
        if (($b['type'] ?? '') === 'text') $out .= (string) ($b['text'] ?? '');
    }
    $out = trim($out);
    return $out !== '' ? $out : null;
}

