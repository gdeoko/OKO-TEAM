/**
 * Персональные данные участника для «мозга»: его заявки, статусы, результаты —
 * чтобы бот отвечал по КОНКРЕТНОЙ заявке («почему не пришёл результат/диплом»).
 */
function chat_user_context(?int $uid): string {
    if (!$uid) return '';
    try {
        // Поля конкурса тянем обязательно: без results_mode и results_published_at
        // нельзя отличить длинный конкурс от короткого, а значит нельзя понять,
        // разрешено ли вообще называть результат (см. core/chat_gate.php).
        $apps = all(
            "SELECT a.*, c.name AS comp_name, c.is_paid AS comp_paid, c.slug AS comp_slug,
                    c.results_mode AS comp_results_mode, c.results_date AS comp_results_date,
                    c.results_published_at AS comp_results_pub
               FROM applications a JOIN competitions c ON c.id = a.competition_id
              WHERE a.user_id = ? ORDER BY a.id DESC LIMIT 15", [$uid]);
    } catch (\Throwable $e) { return ''; }
    if (!$apps) return 'ДАННЫЕ УЧАСТНИКА: у него пока нет поданных заявок. Предложи подать заявку и уточни, какой конкурс из списка интересует.';
    return "ДАННЫЕ ЭТОГО УЧАСТНИКА (отвечай точно по его заявкам; если заявок несколько — уточни, по какой из них вопрос):\n"
        . _chat_apps_lines($apps);
}

