/**
 * Вызов Gemini API (generativelanguage.googleapis.com generateContent).
 * Та же база знаний (chat_system_prompt) через systemInstruction.
 * Тихий фолбэк на null при любой ошибке — дальше Claude/агент/rule-based.
 */
/** Короткая метка ключа для журнала и настроек — сам ключ никуда не пишем. */
function chat_gemini_tag(string $key): string { return 'gemquota:' . substr(md5($key), 0, 10); }

/**
 * Отметить, что у ключа кончилась квота, и НА СКОЛЬКО.
 *
 * Метка жила до конца календарных суток: считалось, что лимит Gemini суточный.
 * На деле служба отвечает иначе — «Please retry in 2h6m23s», и свободная норма
 * возвращается сама через пару часов. Из-за суточной метки бот после ОДНОГО
 * отказа в два часа ночи до полуночи отвечал людям шаблоном, хотя ключ давно
 * работал: 13.10.2026 так и было — ключ отвечал 200, а помощник числил его
 * выбитым и выдавал заготовку на любой вопрос.
 *
 * Поэтому срок называет сама служба, а сутки остаются лишь потолком: месячный
 * потолок трат (платный ключ) за час не рассосётся, но и держать его выбитым
 * дольше суток незачем — владелец может поднять лимит в любой момент.
 */
function chat_gemini_mark_exhausted(string $key, int $seconds = 3600): void {
    if (!function_exists('set_setting')) return;
    $seconds = max(60, min($seconds, 86400));
    try { set_setting(chat_gemini_tag($key), (string) (time() + $seconds)); } catch (\Throwable $e) {}
}

/** Выбит ли ключ прямо сейчас. */
function chat_gemini_is_exhausted(string $key): bool {
    if (!function_exists('setting')) return false;
    try {
        $v = trim((string) setting(chat_gemini_tag($key), ''));
        if ($v === '') return false;
        /* Старые метки были датой «2026-10-13». Числом они не читаются, и такой
           ключ считаем свободным: переживший формат не должен держать бота. */
        if (!ctype_digit($v)) return false;
        return (int) $v > time();
    } catch (\Throwable $e) { return false; }
}

/** Сколько ждать по словам службы: «Please retry in 2h6m23s» или «in 90.5s». */
function chat_gemini_retry_after(string $body, int $default = 3600): int {
    if (!preg_match('~retry in ([0-9hms.]+)~i', $body, $m)) return $default;
    $v = $m[1];
    if (preg_match('~^([0-9.]+)s?$~', $v, $one)) return max(60, (int) $one[1]);
    preg_match('~(\d+)h~', $v, $h);
    preg_match('~(\d+)m~', $v, $mi);
    $sec = ((int) ($h[1] ?? 0)) * 3600 + ((int) ($mi[1] ?? 0)) * 60;
    return $sec > 0 ? $sec : $default;
}

/**
 * Ключи Gemini в том порядке, в каком их пробовать.
 *
 * Порядок здесь — не формальность, а деньги. Первым идёт ключ с бесплатной квотой:
 * пока она есть, центр не платит ни копейки. Когда бесплатный упрётся в лимит,
 * очередь доходит до оплаченного, и разговор с участником не прерывается.
 *
 * Но ходить в выбитый ключ на каждом сообщении — значит дарить участнику лишние
 * секунды ожидания и без толку долбить Google отказами. Поэтому исчерпанный ключ
 * до конца суток уходит в конец очереди, а назавтра возвращается на первое место
 * сам: суточные лимиты обнуляются по календарю.
 *
 * Если выбитыми оказались все — пробуем всё равно: вдруг лимит уже сброшен.
 */
function chat_gemini_keys(): array {
    $raw = trim((string) (cfgv('gemini_api_keys') ?: ''));
    $keys = $raw !== '' ? preg_split('~[,\s]+~', $raw) : [];
    $one = trim((string) (cfgv('gemini_api_key') ?: ''));
    if ($one !== '') $keys[] = $one;
    $keys = array_values(array_unique(array_filter(array_map('trim', $keys))));

    /* МОЛЧАЛИВЫЙ КЛЮЧ — ТОЖЕ В КОНЕЦ ОЧЕРЕДИ.
     *
     * Выбитый ключ отвечает «429» за долю секунды, и очередь идёт дальше. Но
     * ключ может не отвечать ВООБЩЕ: запрос висит до таймаута и обрывается.
     * Проверено 8 сентября: первый ключ молчал двадцать пять секунд, второй
     * отвечал за четыре. Квотой это не считается, отметки «исчерпан» не
     * появлялось, и каждое сообщение участника начиналось с двадцати пяти
     * секунд ожидания впустую — а весь ответ бота и так должен уложиться в
     * жизнь запроса. Отсюда и «бот перестал отвечать».
     *
     * Молчание помним четверть часа: этого хватает пересидеть заминку у
     * провайдера и мало, чтобы забыть про ключ насовсем. */
    $fresh = []; $slow = []; $spent = [];
    foreach ($keys as $k) {
        if (chat_gemini_is_exhausted($k))   { $spent[] = $k; continue; }
        if (chat_gemini_is_silent($k))      { $slow[]  = $k; continue; }
        $fresh[] = $k;
    }
    return array_merge($fresh, $slow, $spent);
}

/** Отметить ключ молчащим (не ответил до таймаута) на N минут. */
function chat_gemini_mark_silent(string $key, int $minutes = 15): void {
    if (!function_exists('set_setting')) return;
    try { set_setting(chat_gemini_tag($key) . ':silent', (string) (time() + $minutes * 60)); }
    catch (\Throwable $e) {}
}

/** Молчит ли ключ прямо сейчас (отметка ещё не истекла). */
function chat_gemini_is_silent(string $key): bool {
    if (!function_exists('setting')) return false;
    try { return (int) setting(chat_gemini_tag($key) . ':silent', '0') > time(); }
    catch (\Throwable $e) { return false; }
}

