/** Кто сегодня отвечает этому собеседнику: ['имя' => …, 'она' => bool]. */
function chat_operator(?string $sessionKey = null): array {
    $sk = (string) ($sessionKey ?? ($GLOBALS['chat_session_key'] ?? ''));
    $n  = count(CHAT_OPERATORS);
    /* Сутки берём ПО МЕСТНОМУ календарю, а не делением time() на 86400:
       иначе имя менялось бы в три часа ночи по Москве, посреди суток. */
    $day = (int) floor((int) strtotime(date('Y-m-d')) / 86400);
    $i   = (int) ((abs(crc32($sk)) % $n) + ($day % $n)) % $n;
    return CHAT_OPERATORS[$i];
}

