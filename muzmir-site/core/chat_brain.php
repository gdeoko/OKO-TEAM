/**
 * Вызов Gemini API (generativelanguage.googleapis.com generateContent).
 * Та же база знаний (chat_system_prompt) через systemInstruction.
 * Тихий фолбэк на null при любой ошибке — дальше Claude/агент/rule-based.
 */
/** Короткая метка ключа для журнала и настроек — сам ключ никуда не пишем. */
function chat_gemini_tag(string $key): string { return 'gemquota:' . substr(md5($key), 0, 10); }

/**
 * Отметить, что у ключа кончилась квота.
 *
 * Суточные лимиты Gemini обнуляются по календарным суткам, поэтому и метка живёт
 * до конца дня: завтра ключ снова пробуется первым.
 */
function chat_gemini_mark_exhausted(string $key): void {
    if (!function_exists('set_setting')) return;
    try { set_setting(chat_gemini_tag($key), date('Y-m-d')); } catch (\Throwable $e) {}
}

/** Исчерпан ли ключ сегодня. */
function chat_gemini_is_exhausted(string $key): bool {
    if (!function_exists('setting')) return false;
    try { return (string) setting(chat_gemini_tag($key), '') === date('Y-m-d'); }
    catch (\Throwable $e) { return false; }
}

/**
 * Ключи Gemini в том порядке, в каком их пробовать.
 *
 * Порядок здесь — не формальность, а деньги. Первым идёт ключ с бесплатной квотой:
 * пока она есть, центр не платит ни копейки. Когда бесплатный упрётся в лимит,
 * очередь доходит до оплаченного, и разговор с участником не прерывается.
 *
 * Но ходить в выбитый ключ на каждом сообщении — значит дарить участнику лишние
 * секунды ожидания и без толку долбить Google отказами. Поэтому исчерпанный ключ
 * до конца суток уходит в конец очереди, а назавтра возвращается на первое место
 * сам: суточные лимиты обнуляются по календарю.
 *
 * Если выбитыми оказались все — пробуем всё равно: вдруг лимит уже сброшен.
 */
function chat_gemini_keys(): array {
    $raw = trim((string) (cfgv('gemini_api_keys') ?: ''));
    $keys = $raw !== '' ? preg_split('~[,\s]+~', $raw) : [];
    $one = trim((string) (cfgv('gemini_api_key') ?: ''));
    if ($one !== '') $keys[] = $one;
    $keys = array_values(array_unique(array_filter(array_map('trim', $keys))));

    $fresh = []; $spent = [];
    foreach ($keys as $k) { chat_gemini_is_exhausted($k) ? $spent[] = $k : $fresh[] = $k; }
    return array_merge($fresh, $spent);
}

function chat_gemini_reply(string $apiKey, string $sessionKey, string $text): ?string {
    $GLOBALS['chat_last_question'] = $text;   // по нему подбираются уроки для промпта
    // История сессии -> contents (роли user/model, первым обязан идти user).
    $contents = [];
    try {
        $rows = all(
            "SELECT role, text FROM chat_messages WHERE session_key=? AND text<>'' ORDER BY id DESC LIMIT 12",
            [$sessionKey]
        );
        foreach (array_reverse($rows) as $r) {
            $role = ($r['role'] ?? '') === 'assistant' ? 'model' : 'user';
            if (!$contents && $role === 'model') continue;
            $contents[] = ['role' => $role, 'parts' => [['text' => (string) $r['text']]]];
        }
    } catch (\Throwable $e) { $contents = []; }
    if (!$contents || end($contents)['role'] !== 'user') {
        $contents[] = ['role' => 'user', 'parts' => [['text' => $text]]];
    }

    /* НЕ ОДНА МОДЕЛЬ, А ОЧЕРЕДЬ.
     *
     * У бесплатных ключей лимит считается по каждой модели отдельно, и тяжёлая
     * выбивает квоту первой: сегодня к полудню основная отвечала 429, а лёгкие
     * работали как ни в чём не бывало — но помощник этого не знал и весь день
     * молчал бы шаблонами. Теперь при отказе по квоте или перегрузке пробуем
     * следующую модель из очереди. Порядок — от лучшей к самой выносливой. */
    $models = array_values(array_filter(array_map('trim',
        preg_split('~[,\s]+~', (string) (cfgv('gemini_models') ?: '')) ?: [])));
    if (!$models) {
        $models = [(string) (cfgv('gemini_model') ?: 'gemini-2.5-flash'),
                   'gemini-3-flash-preview', 'gemini-flash-lite-latest', 'gemini-3.1-flash-lite'];
    }
    $models = array_values(array_unique($models));
    $payload = json_encode([
        'systemInstruction' => ['parts' => [['text' => chat_system_prompt()]]],
        'contents'          => $contents,
        /* РАЗМЫШЛЕНИЯ ВЫКЛЮЧЕНЫ. Новые модели по умолчанию сначала «думают
         * вслух», и эти черновики приходят такими же частями ответа: участник
         * получал английский разбор промпта вместо ответа оператора. Оператору
         * колл-центра размышления не нужны — нужен короткий готовый ответ. */
        'generationConfig'  => ['maxOutputTokens' => 1000, 'temperature' => 0.4,
                                'thinkingConfig' => ['thinkingBudget' => 0]],
    ], JSON_UNESCAPED_UNICODE);

    $base = rtrim((string) (cfgv('gemini_base_url') ?: 'https://generativelanguage.googleapis.com'), '/');
    $resp = null; $err = 0; $code = 0; $model = '';
    foreach ($models as $try) {
    $model = $try;
    $ch = curl_init($base . '/v1beta/models/'
        . rawurlencode($model) . ':generateContent?key=' . rawurlencode($apiKey));
    curl_setopt_array($ch, [
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_POST           => true,
        CURLOPT_POSTFIELDS     => $payload,
        CURLOPT_HTTPHEADER     => ['Content-Type: application/json'],
        /* ДВЕНАДЦАТИ СЕКУНД НЕ ХВАТАЛО.
         * Модель с большим системным промптом отвечает около десяти секунд, и
         * запрос обрывался почти на финише: «мозг» считался молчащим, участник
         * получал шаблон с просьбой позвонить. Ответ всё равно показывается не
         * мгновенно (обычному участнику — через пять минут), так что лишние
         * секунды ожидания ему ничего не стоят, а живой ответ стоят. */
        CURLOPT_TIMEOUT        => 25,
        CURLOPT_CONNECTTIMEOUT => 5,
    ]);
    $resp = curl_exec($ch);
    $err  = curl_errno($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
    curl_close($ch);
    // Ошибку «мозга» пишем в лог: без неё молчание выглядит как исправная работа,
    // а участник получает шаблон, и никто не знает почему.
    if (($err || $code >= 400) && function_exists('mail_log')) {
        mail_log('CHAT gemini ' . ($err ? ('curl ' . $err) : ('HTTP ' . $code))
                 . ' key=' . substr($apiKey, 0, 8) . ' model=' . $model);
    }
    // Квота этой модели кончилась (429) или она перегружена (503) — пробуем
    // следующую из очереди, ключ тот же. Прочие ошибки перебирать незачем.
    if ($code === 429 || $code === 503) continue;
    break;
    }
    // Ключ считаем выбитым, только если по квоте отказали ВСЕ модели: иначе
    // завтрашняя очередь начнётся с ключа, который на самом деле работает.
    if ($code === 429) chat_gemini_mark_exhausted($apiKey);
    if ($err || !$resp || $code >= 400) return null;

    $d = json_decode((string) $resp, true);
    if (!is_array($d) || empty($d['candidates'][0]['content']['parts'])) return null;
    $out = '';
    foreach ($d['candidates'][0]['content']['parts'] as $p) {
        // Часть с thought=true — это черновик рассуждения модели, а не ответ.
        // Просить не думать мало: если модель всё же прислала мысли, они не
        // должны попасть человеку.
        if (!empty($p['thought'])) continue;
        if (isset($p['text'])) $out .= (string) $p['text'];
    }
    $out = trim($out);
    return $out !== '' ? $out : null;
}

/** Вызов Claude API (api.anthropic.com /v1/messages). Тихий фолбэк на null при любой ошибке. */
function chat_claude_reply(string $apiKey, string $sessionKey, string $text): ?string {
    $GLOBALS['chat_last_question'] = $text;   // по нему подбираются уроки для промпта
    // Последние сообщения сессии -> messages для API (первым обязан идти user).
    $messages = [];
    try {
        $rows = all(
            "SELECT role, text FROM chat_messages WHERE session_key=? AND text<>'' ORDER BY id DESC LIMIT 12",
            [$sessionKey]
        );
        foreach (array_reverse($rows) as $r) {
            $role = ($r['role'] ?? '') === 'assistant' ? 'assistant' : 'user';
            if (!$messages && $role === 'assistant') continue;
            $messages[] = ['role' => $role, 'content' => (string) $r['text']];
        }
    } catch (\Throwable $e) { $messages = []; }
    if (!$messages || end($messages)['role'] !== 'user') {
        $messages[] = ['role' => 'user', 'content' => $text];
    }

    $payload = json_encode([
        'model'      => 'claude-haiku-4-5-20251001',
        'max_tokens' => 500,
        'system'     => chat_system_prompt(),
        'messages'   => $messages,
    ], JSON_UNESCAPED_UNICODE);

    $ch = curl_init('https://api.anthropic.com/v1/messages');
    curl_setopt_array($ch, [
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_POST           => true,
        CURLOPT_POSTFIELDS     => $payload,
        CURLOPT_HTTPHEADER     => [
            'Content-Type: application/json',
            'x-api-key: ' . $apiKey,
            'anthropic-version: 2023-06-01',
        ],
        CURLOPT_TIMEOUT        => 12,
        CURLOPT_CONNECTTIMEOUT => 5,
    ]);
    $resp = curl_exec($ch);
    $err  = curl_errno($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
    curl_close($ch);
    if ($err || !$resp || $code >= 400) return null;

    $d = json_decode((string) $resp, true);
    if (!is_array($d) || ($d['type'] ?? '') === 'error') return null;
    if (($d['stop_reason'] ?? '') === 'refusal') return null;
    $out = '';
    foreach (($d['content'] ?? []) as $b) {
        if (($b['type'] ?? '') === 'text') $out .= (string) ($b['text'] ?? '');
    }
    $out = trim($out);
    return $out !== '' ? $out : null;
}

/**
 * Ответы по ключевым словам — то, что человек получает, когда «мозг» не ответил.
 *
 * ЭТО НЕ ЗАПАСНОЙ ПУТЬ, А ОСНОВНОЙ. Модель отвечает не всегда: бесплатная квота
 * Gemini — двадцать запросов в сутки, платные кредиты кончаются, сеть моргает.
 * В такие часы весь чат центра — вот эти строки, и человек не должен по ним
 * понять, что что-то сломалось.
 *
 * ПОРЯДОК ПРАВИЛ ВАЖНЕЕ САМИХ ПРАВИЛ. Раньше проверка про стоимость стояла
 * четвёртой и ловила слово «сколько» — а «во сколько вы работаете?» это вопрос
 * про график. Человек спрашивал режим работы и получал рассказ про оргвзнос.
 * Поэтому узкие темы (график, возврат, техника) идут ПЕРЕД широкими, а слово
 * «сколько» само по себе больше ничего не решает: цену спрашивают словами
 * «сколько стоит», «сколько платить», «какая цена».
 */
function chat_rule_reply(string $text): string {
    $t        = mb_strtolower($text);
    $orgEmail = cfgv('org_email');
    $has = static function (array $words) use ($t): bool {
        foreach ($words as $w) if (mb_strpos($t, $w) !== false) return true;
        return false;
    };
    $tail = "";

    /* ---- Узкие темы: их формулировки пересекаются с широкими, поэтому раньше ---- */

    // График работы. «Во сколько работаете» содержит «сколько» — до этой ветки
    // вопрос уходил в рассказ про стоимость.
    if ($has(['во сколько', 'режим работ', 'график', 'когда вы работ', 'до скольки',
              'рабочее время', 'работаете'])) {
        return 'График работы Оргкомитета: ' . cfgv('org_hours') . '. Телефон ' . cfgv('org_phone')
             . ', почта ' . $orgEmail . '. Вне графика можно написать здесь — вопрос не потеряется, '
             . 'вернусь к нему в начале рабочего дня.';
    }

    // Возврат оргвзноса. Раньше ловилось словом «оргвзнос» и уходило в прайс —
    // человек спрашивал про деньги назад и получал, за что он их платит.
    if ($has(['верн', 'возврат', 'отказ от участ', 'передумал', 'отмен'])
