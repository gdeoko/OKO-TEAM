<?php
/**
 * ПОДГОНКА БЛАНКА ПОД ФОН: ГДЕ КОНЧАЕТСЯ РИСУНОК И НАЧИНАЕТСЯ МЕСТО ДЛЯ ТЕКСТА.
 *
 * У каждого конкурса свой фон, и рамка на нём своя: где-то орнамент занимает
 * два сантиметра с краю, где-то пять, а внизу лежат инструменты и свитки. Поля
 * бланка были заданы раз и навсегда одним числом, поэтому на новых фонах строки
 * заезжали на балалайку и на резную раму - документ выглядел браком.
 *
 * Здесь фон разбирается по пикселям: от каждого края к центру ищется место, где
 * картинка успокаивается - перестаёт быть пёстрой и становится ровной подложкой.
 * Это и есть граница рисунка. Отступы возвращаются в миллиметрах листа A4, и
 * бланк сам расставляет по ним поля.
 *
 * Заодно измеряется яркость середины: на светлой бумаге текст должен быть
 * тёмным, на тёмном фоне - светлым. Раньше цвет был всегда белый, и на светлом
 * фоне «Наследия России» строки терялись.
 *
 * Результат кэшируется рядом с фоном: разбор занимает доли секунды, но он не
 * нужен на каждый выданный диплом.
 */
declare(strict_types=1);

/**
 * @return array{pad_top:float, pad_right:float, pad_bottom:float, pad_left:float,
 *               dark:bool, ink:string, muted:string, shadow:string}
 *         Поля - в миллиметрах листа A4 (210×297).
 */
function diploma_fit(string $bgPath): array
{
    // Значения по умолчанию: прежние поля бланка. Ими же отвечаем, если фон
    // недоступен - лучше прежнее поведение, чем пустая страница.
    $def = [
        'pad_top' => 8.0, 'pad_right' => 12.0, 'pad_bottom' => 7.0, 'pad_left' => 12.0,
        'dark' => true, 'ink' => '#ffffff', 'muted' => 'rgba(255,255,255,.85)',
        'shadow' => 'drop-shadow(0 1px 3px rgba(0,0,0,.55))',
    ];
    if ($bgPath === '' || !is_file($bgPath)) return $def;

    $cache = $bgPath . '.fit.json';
    if (is_file($cache) && filemtime($cache) >= filemtime($bgPath)) {
        $j = json_decode((string) file_get_contents($cache), true);
        if (is_array($j) && isset($j['pad_left'])) return $j + $def;
    }

    $img = @imagecreatefromstring((string) @file_get_contents($bgPath));
    if (!$img) return $def;
    $W = imagesx($img); $H = imagesy($img);
    if ($W < 100 || $H < 100) { imagedestroy($img); return $def; }

    /** Яркость точки, 0..255. */
    $lum = static function (int $rgb): float {
        return 0.299 * (($rgb >> 16) & 255) + 0.587 * (($rgb >> 8) & 255) + 0.114 * ($rgb & 255);
    };

    /**
     * Насколько пёстро вокруг точки. Орнамент даёт большой разброс яркости,
     * ровная подложка - маленький. Считаем по окну 9 точек.
     */
    $noise = static function (int $x, int $y) use ($img, $W, $H, $lum): float {
        $vals = [];
        for ($dx = -4; $dx <= 4; $dx += 2) {
            for ($dy = -4; $dy <= 4; $dy += 2) {
                $xx = max(0, min($W - 1, $x + $dx));
                $yy = max(0, min($H - 1, $y + $dy));
                $vals[] = $lum(imagecolorat($img, $xx, $yy));
            }
        }
        $avg = array_sum($vals) / count($vals);
        $d = 0.0;
        foreach ($vals as $v) $d += ($v - $avg) ** 2;
        return sqrt($d / count($vals));
    };

    /**
     * Идём от края к центру, пока картинка не успокоится на протяжении
     * нескольких шагов подряд. Возвращаем долю стороны (0..0.35).
     */
    $edge = static function (string $side) use ($img, $W, $H, $noise): float {
        $limit = 0.35;                       // дальше центра не заходим
        $calm  = 0;                          // сколько шагов подряд спокойно
        $need  = 4;                          // столько подряд - значит рисунок кончился
        $steps = 70;
        for ($i = 2; $i < $steps; $i++) {
            $t = $i / $steps * $limit;
            $probes = [];
            if ($side === 'left' || $side === 'right') {
                $x = $side === 'left' ? (int) ($W * $t) : (int) ($W * (1 - $t));
                foreach ([0.25, 0.4, 0.5, 0.6, 0.75] as $ky) $probes[] = [$x, (int) ($H * $ky)];
            } else {
                $y = $side === 'top' ? (int) ($H * $t) : (int) ($H * (1 - $t));
                foreach ([0.3, 0.45, 0.55, 0.7] as $kx) $probes[] = [(int) ($W * $kx), $y];
            }
            $max = 0.0;
            foreach ($probes as [$px, $py]) $max = max($max, $noise($px, $py));
            // Порог подобран по нашим фонам: орнамент даёт разброс заметно выше.
            /* Порог: бумага с текстурой тоже слегка «шумит», поэтому спокойным
             * считаем всё ниже четырнадцати - иначе граница рисунка уезжает к
             * середине листа и поля получаются в четыре сантиметра. */
            if ($max < 14.0) { $calm++; if ($calm >= $need) return $t; }
            else            { $calm = 0; }
        }
        return $limit;
    };

    $l = $edge('left'); $r = $edge('right'); $t = $edge('top'); $b = $edge('bottom');

    // Яркость середины листа - по ней выбираем цвет текста.
    $sum = 0.0; $n = 0;
    for ($ky = 0.35; $ky <= 0.65; $ky += 0.05) {
        for ($kx = 0.3; $kx <= 0.7; $kx += 0.05) {
            $sum += $lum(imagecolorat($img, (int) ($W * $kx), (int) ($H * $ky)));
            $n++;
        }
    }
    imagedestroy($img);
    $bright = $n ? $sum / $n : 0.0;
    $dark   = $bright < 140;                 // тёмная подложка - пишем светлым

    /* Переводим доли в миллиметры листа и добавляем дыхание, чтобы буквы не
     * прижимались к рисунку вплотную. Держим в разумных границах: слишком
     * широкие поля сжали бы текст в узкую колонку. */
    $mm = static fn(float $frac, float $side, float $extra, float $min, float $max): float
        => max($min, min($max, round($frac * $side + $extra, 1)));

    $out = [
        /* Потолки держим умеренными: поля в четыре сантиметра с каждой стороны
         * сжали бы название конкурса в узкую колонку и переносили бы его. */
        /* Потолки умеренные. Лист свёрстан плотно: шапка с реквизитами, гербы,
         * название, поля заявки и блок подписей уже занимают почти всю высоту.
         * Широкие поля не освобождают место, а отнимают его - строки начинают
         * наезжать на подписи. Задача полей - только не дать тексту заехать на
         * боковой орнамент, поэтому прибавка к прежним значениям небольшая. */
        /* Поля идут ПО ГРАНИЦЕ РИСУНКА, с небольшим отступом внутрь: текст не
         * должен касаться орнамента рамки. Раньше потолок был занижен, чтобы
         * строки не наезжали на подписи, - теперь эту задачу решает сжатие
         * содержимого (scale в бланке), и поля можно брать честные. */
        'pad_top'    => $mm($t, 297.0, 2.0,  8.0, 26.0),
        'pad_right'  => $mm($r, 210.0, 3.0, 12.0, 30.0),
        /* Низу даём больше запаса: там на фоне лежат инструменты, свитки и
         * тяжёлый орнамент, а на них садятся подписи и печать. */
        'pad_bottom' => $mm($b, 297.0, 4.0, 12.0, 38.0),
        'pad_left'   => $mm($l, 210.0, 3.0, 12.0, 30.0),
        'dark'       => $dark,
        'ink'        => $dark ? '#ffffff' : '#2A1A0B',
        'muted'      => $dark ? 'rgba(255,255,255,.88)' : 'rgba(42,26,11,.86)',
        'shadow'     => $dark
            ? 'drop-shadow(0 1px 3px rgba(0,0,0,.55))'
            : 'drop-shadow(0 1px 2px rgba(255,255,255,.75))',
    ];
    @file_put_contents($cache, json_encode($out, JSON_UNESCAPED_UNICODE));
    return $out;
}
