    for c,n in by_cat.most_common():
        tops=collections.Counter({a:addr_cat[a][c] for a in addr_cat if addr_cat[a][c]})
        w.writerow([c,n,", ".join(f"{a} ({k})" for a,k in tops.most_common(5))])

