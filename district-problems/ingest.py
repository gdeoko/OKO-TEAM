def zone_of(addr):
    for pref, z in ZONES:
        if addr.startswith(pref): return z
    return 'Прочие адреса'

if __name__ == "__main__":
    raw = ""
    for fn in sorted(os.listdir(BASE + "/inbox")):
        if fn.endswith(".txt"):
            raw += open(BASE + "/inbox/" + fn, encoding="utf-8").read() + "\n\n"
    recs, skipped = parse(raw)
    uniq, agg = aggregate(recs)

    by_zone = collections.Counter()
    for p in agg["points"]:
        p["zone"] = zone_of(p["address"])
        by_zone[p["zone"]] += p["requests_total"]
    agg["by_zone"] = [dict(zone=z, count=n) for z, n in by_zone.most_common()]
    agg["totals"]["categories"] = len(agg["by_category"])
    agg["source"] = "Обход жителей, поселение Сосенское и соседние (НАО Москвы)"
