def _num(m):
    house = (m.group(1) or '') + (m.group(2) or '')
    sep, corp = m.group(3), m.group(4)
    if not corp: return house
    return house + ('с' if sep and sep.lower().startswith('стр') else 'к') + corp

def find_addr(text):
    """Ищем «<улица> <номер>» где угодно в строке -> (адрес, остаток текста)."""
    for pat, name in RULES:
        m = re.search('(?:' + pat + ')' + NUM, text, re.I)
        if m and m.group(1):
            return f'{name}, {_num(m)}', (text[:m.start()] + ' ' + text[m.end():]).strip(' .,;')
    for pat, name in RULES:
        m = re.search(pat, text, re.I)
        if m:
            return name, (text[:m.start()] + ' ' + text[m.end():]).strip(' .,;')
    return None, text

