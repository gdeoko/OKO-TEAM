  'первая смена картинки до 2,5 с',
  'склейки, средний план 1,5-4 с, провалы без изменений',
  'не больше пяти смысловых объектов на экране',
  'субтитры по слову, смена каждые 0,5-1,5 с, выделение ключевого',
  'безопасные поля снизу и справа под интерфейс площадки',
