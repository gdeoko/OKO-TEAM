      Object.keys(s.контент).forEach(function (k) { (s.контент[k] || []).forEach(function (f) { по[f] = (по[f] || 0) + 1; }); });
      var строки = ФОРМАТЫ.filter(function (f) { return по[f.k]; })
        .map(function (f) { return [f.t, String(по[f.k])]; });
      if (строки.length) h += таблица([['Формат', 'Сколько вышло']].concat(строки));
