    var сдвиг = (дни[0].getDay() + 6) % 7;
    for (var i = 0; i < сдвиг; i++) сетка += '<span class="sy3-day-off"></span>';
    сетка += дни.map(function (d) {
      var к = дата(d), v = s.контент[к] || [];
      if (v.length) { было++; всего += v.length; }
      var сег = к === дата(сегодня());
      var подпись = d.getDate() + ' ' + МЕСЯЦЫ[d.getMonth()] + ', '
        + (v.length ? v.length + ' ' + скл(v.length, 'публикация', 'публикации', 'публикаций') : 'пусто');
      return '<button class="sy3-day' + (v.length ? ' on' : '') + (сег ? ' now' : '') + '"'
        + ' data-oko-hit="1" onclick="okoSy3.день(\'' + к + '\')" aria-label="' + подпись + '">'
        + '<span class="sy3-day-n">' + d.getDate() + '</span>'
        + (v.length ? '<span class="sy3-day-c">' + v.length + '</span>' : '')
        + '</button>';
    }).join('');

    var стрик = серия(s);
    var h = '';
    h += '<div class="sy3-stats">'
      + плитка(String(было), 'из 30 дней с публикацией')
      + плитка(String(всего), 'единиц контента')
      + плитка(стрик ? String(стрик) : '—', стрик ? скл(стрик, 'день подряд', 'дня подряд', 'дней подряд') : 'серии пока нет')
      + '</div>';
    h += '<div class="sy3-grid30">' + сетка + '</div>';
    h += '<p class="sy3-hint">Нажми на день и отметь, что вышло. Прошедшие дни тоже открыты — трекер '
      + 'нужен, чтобы видеть правду, а не чтобы наказывать за пропуск.</p>';
