    try { k = (typeof sysActiveSection !== 'undefined') ? sysActiveSection : null; } catch (e) {}
    if (!body || (k !== 'track' && k !== 'kp')) {
      try { if (typeof openSystemPreview === 'function') openSystemPreview(true); } catch (e) {}
      return;
    }
    var скроллер = D.querySelector('#systemView .sv-body');
    var поз = скроллер ? скроллер.scrollTop : 0;
    try { body.innerHTML = window.sysSectionHtml(k, анкета()); } catch (e) { return; }
