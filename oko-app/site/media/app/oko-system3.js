/* ============================================================================
   OKO · oko-system3.js — ТРЕКЕРЫ и ЭТАЛОН СБОРКИ КП
   ----------------------------------------------------------------------------
   Правка Даниэля: «у агента есть эталон системы, только туда ещё контент-плана
   добавить нужно календарь, ещё визуал брендбук трекеры и тд, чего не хватает
   добавить также красиво и сделать эталон сборки КП, там тоже последовательность
   с анализом клиента, конкурентов и т.д. идёт».

   Что уже было в системе роста: контент-план с календарём 7×N, бизнес-план,
   чек-лист, материалы, визуал с брендбуком, перспективы. Не было двух вещей —
   их и добавляем седьмым и восьмым разделами:

     07 · ТРЕКЕРЫ — пять таблиц, куда человек сам вносит свои числа, а система
          считает из них производные: серию публикаций, конверсию воронки,
          средний чек, процент до цели из анкеты.

     08 · ЭТАЛОН КП — последовательность сборки коммерческого предложения из
          девяти шагов: клиент → его цифры → конкуренты → решение → состав →
          сроки → смета → рамки → следующий шаг. На выходе — готовый документ.

   ЧЕСТНОСТЬ (правила проекта 09.08)
   ---------------------------------
   • Ни одного придуманного числа. Пустой трекер показывает, что он пуст,
     и объясняет, что туда вносить. Проценты считаются только когда есть из
     чего считать; делить на ноль и рисовать «0%» как достижение — нельзя.
   • Прогресс учёбы читается из настоящего состояния Академии (localStorage
     'oko-academy'), а не выдумывается.
   • Никаких обещаний работы несуществующей команды и серверных экспортов.
     КП сохраняется файлом прямо из браузера — это единственное, что тут
     действительно происходит.
   • Иконки только из спрайта. Эмодзи в интерфейсе нет.

   ХРАНЕНИЕ
   --------
   'oko-sy3-track' — трекеры, 'oko-sy3-kp' — черновик КП. Оба на устройстве,
   как и весь остальной план: сервера у приложения пока нет, и делать вид,
   что данные где-то синхронизируются, было бы ложью.
   ============================================================================ */
