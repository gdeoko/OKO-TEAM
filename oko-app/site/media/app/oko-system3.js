  function E(s) {
    return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }
  function ico(n) { return '<svg class="i"><use href="#i-' + n + '"/></svg>'; }
  function T(m) { try { if (typeof toast === 'function') toast(m); } catch (e) {} }
  function num(v) {
    if (v === null || v === undefined || v === '') return null;
    var n = parseFloat(String(v).replace(/[^\d.,-]/g, '').replace(',', '.'));
    return isFinite(n) ? n : null;
  }
  function руб(n) {
    if (n === null || n === undefined || !isFinite(n)) return '—';
    return Math.round(n).toLocaleString('ru-RU') + ' ₽';
  }
  function проц(a, b) {
    if (!b || b <= 0 || a === null || a === undefined) return '—';
    return (Math.round(a / b * 1000) / 10) + '%';
  }
  function скл(n, one, few, many) {
    var m = n % 100;
    if (m >= 11 && m <= 14) return many;
    m = n % 10;
    return m === 1 ? one : (m >= 2 && m <= 4 ? few : many);
  }

  function читать(k, поум) {
    try { var v = JSON.parse(localStorage.getItem(k)); return v && typeof v === 'object' ? v : поум; }
    catch (e) { return поум; }
  }
  function писать(k, v) { try { localStorage.setItem(k, JSON.stringify(v)); } catch (e) {} }

