# -*- coding: utf-8 -*-
"""Сколько единиц DIESEL выпускаем сегодня. Лесенка идёт сама по дням.

Слово владельца 08.09.2026: начинаем с одной в день, дальше 2, 3, 4, 5,
на пятёрке держимся, через пятнадцать дней поднимаемся до десяти, и так же
дальше.

Раньше норма стояла числом в ramp_state.json, и поднимать её надо было руками.
Ровно этот шаг и забывают: аккаунт неделю выпускает по одному ролику, потому
что никто не поправил число. Теперь норма считается от даты старта.

    python3 diesel_norma_dnya.py            сколько сегодня, и записать
    python3 diesel_norma_dnya.py план       вся лесенка на два месяца вперёд
    python3 diesel_norma_dnya.py 2026-10-01 сколько будет в этот день
"""
import datetime as дт
import json
import os
import sys

БАЗА = "/opt/oko-poster"
ПЛАН = f"{БАЗА}/cfg/ramp_plan.json"
СОСТОЯНИЕ = f"{БАЗА}/cfg/ramp_state.json"

ПО_УМОЛЧАНИЮ = {
    "старт": "2026-09-08",
    "первая_ступень": 5,      # лесенка 1,2,3,4,5 в первые пять дней
    "полка_дней": 15,         # столько держим достигнутый потолок
    "прибавка_ступени": 5,    # следующий потолок: 5, потом 10, потом 15
    "потолок": 30,            # выше не поднимаемся без отдельного слова
    "почему": "слово владельца 08.09.2026: 1, 2, 3, 4, 5, держим, через 15 дней 10, и так далее",
}


def план():
    if os.path.exists(ПЛАН):
        д = json.load(open(ПЛАН, encoding="utf-8"))
        return {**ПО_УМОЛЧАНИЮ, **д}
    os.makedirs(os.path.dirname(ПЛАН), exist_ok=True)
    json.dump(ПО_УМОЛЧАНИЮ, open(ПЛАН, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    return dict(ПО_УМОЛЧАНИЮ)


def норма(день: дт.date, п: dict) -> int:
    """День первый это день старта, в него выпускаем одну единицу."""
    старт = дт.date.fromisoformat(п["старт"])
    н = (день - старт).days
    if н < 0:
        return 0
    ступень = int(п["первая_ступень"])
    шаг = int(п["прибавка_ступени"])
    полка = int(п["полка_дней"])
    потолок = int(п["потолок"])
    было = 0                       # сколько уже выпускали в предыдущий день лесенки
    курсор = 0                     # номер дня, с которого идёт текущий подъём
    while True:
        # подъём: каждый день на одну больше, пока не дойдём до ступени
        подъём = ступень - было
        if н < курсор + подъём:
            return min(было + (н - курсор) + 1, потолок)
        курсор += подъём
        было = ступень
        # полка: держим достигнутое
        if н < курсор + полка:
            return min(ступень, потолок)
        курсор += полка
        if ступень >= потолок:
            return потолок
        ступень = min(ступень + шаг, потолок)


def записать(ц: int):
    с = {}
    if os.path.exists(СОСТОЯНИЕ):
        с = json.load(open(СОСТОЯНИЕ, encoding="utf-8"))
    сегодня = дт.datetime.utcnow().strftime("%Y-%m-%d")
    if с.get("date") != сегодня:
        с.update(date=сегодня, posted_A=0, posted_B=0)
    с["target_per_batch"] = ц
    с["note"] = ПО_УМОЛЧАНИЮ["почему"]
    json.dump(с, open(СОСТОЯНИЕ, "w", encoding="utf-8"), ensure_ascii=False)
    return с


if __name__ == "__main__":
    п = план()
    арг = sys.argv[1] if len(sys.argv) > 1 else ""
    if арг == "план":
        старт = дт.date.fromisoformat(п["старт"])
        for i in range(60):
            д = старт + дт.timedelta(days=i)
            print(д.isoformat(), "день", str(i + 1).rjust(2), "норма", норма(д, п))
    elif арг:
        д = дт.date.fromisoformat(арг)
        print(арг, "норма", норма(д, п))
    else:
        сегодня = дт.datetime.utcnow().date()
        ц = норма(сегодня, п)
        с = записать(ц)
        print("сегодня", сегодня.isoformat(), "норма", ц,
              "| выпущено A", с.get("posted_A", 0), "B", с.get("posted_B", 0))
