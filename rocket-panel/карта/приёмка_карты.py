#!/usr/bin/env python3
"""Приёмка арендованной карты. Запускается НА карте, до переноса моделей.

Смысл один: отличить карту, которая держит мощность, от карты, которая
её держать не будет. Немецкая A100 на холодную выдала 219,91 TFLOPS и
выглядела здоровой; под нагрузкой ушла на 15,73 — в тринадцать раз
меньше, потому что была хронически задушена по температуре. Ни одно
поле в каталоге Vast этого не показывало: `gpu_max_temp` у ВСЕХ девяти
A100 площадки равен 92, это паспортный предел, а не наблюдение.

Поэтому карта проверяется не паспортом, а работой: холодный замер,
потом пять минут непрерывного счёта с опросом частот, температуры,
потребления и ПРИЧИН торможения. Стоит это центы и минуты, а ловит то,
ради чего мы платим за месяц вперёд.
"""
import json
import subprocess
import sys
import time

import torch

МИНУТ_НАГРУЗКИ = float(sys.argv[1]) if len(sys.argv) > 1 else 5.0
РАЗМЕР = 8192


def смотреть():
    """Снимок счётчиков карты. Пустой ответ — не повод падать: тест под
    нагрузкой важнее телеметрии."""
    поля = ("clocks.sm,clocks.max.sm,temperature.gpu,power.draw,"
            "power.limit,utilization.gpu,clocks_throttle_reasons.active")
    try:
        r = subprocess.run(
            ["nvidia-smi", "--query-gpu=" + поля, "--format=csv,noheader,nounits"],
            capture_output=True, text=True, timeout=20)
        ч = [x.strip() for x in r.stdout.strip().split(",")]
        return {"sm": float(ч[0]), "sm_max": float(ч[1]), "темп": float(ч[2]),
                "ватт": float(ч[3]), "ватт_предел": float(ч[4]),
                "занятость": float(ч[5]), "причины": ч[6]}
    except Exception as e:
        return {"ошибка": str(e)[:80]}


def тормоза():
    """Расшифровка причин торможения. Отдельным вызовом: в `--query-gpu`
    приходит шестнадцатеричная маска, а здесь — человеческие строки, и
    именно по ним немецкая карта и попалась."""
    try:
        r = subprocess.run(["nvidia-smi", "-q", "-d", "PERFORMANCE"],
                           capture_output=True, text=True, timeout=20)
        из = {}
        for строка in r.stdout.splitlines():
            if "Slowdown" in строка or "Throttle" in строка:
                имя, _, знач = строка.partition(":")
                if знач.strip():
                    из[имя.strip()] = знач.strip()
        return из
    except Exception as e:
        return {"ошибка": str(e)[:80]}


def тфлопс(секунд):
    """Замер матричного умножения в bf16 — то же, чем занят сэмплер."""
    a = torch.randn(РАЗМЕР, РАЗМЕР, device="cuda", dtype=torch.bfloat16)
    b = torch.randn(РАЗМЕР, РАЗМЕР, device="cuda", dtype=torch.bfloat16)
    for _ in range(3):
        a @ b
    torch.cuda.synchronize()
    начало = time.time()
    шагов = 0
    while time.time() - начало < секунд:
        for _ in range(20):
            a @ b
        шагов += 20
    torch.cuda.synchronize()
    прошло = time.time() - начало
    return 2 * РАЗМЕР ** 3 * шагов / прошло / 1e12


печать = []


def сказать(с):
    print(с, flush=True)
    печать.append(с)


имя = torch.cuda.get_device_name(0)
память = torch.cuda.get_device_properties(0).total_memory / 1e9
сказать("КАРТА: %s, %.0f ГБ, torch %s, cuda %s"
        % (имя, память, torch.__version__, torch.version.cuda))

с0 = смотреть()
сказать("ДО НАГРУЗКИ: %s" % json.dumps(с0, ensure_ascii=False))

холод = тфлопс(8)
сказать("")
сказать("ХОЛОДНЫЙ ЗАМЕР: %.2f TFLOPS (bf16)" % холод)

сказать("")
сказать("НАГРУЗКА %.0f минут — смотрю, удержит ли:" % МИНУТ_НАГРУЗКИ)
сказать("%6s %8s %8s %7s %8s  %s" % ("мин", "TFLOPS", "МГц", "°C", "Вт", "причина торможения"))

замеры = []
началось = time.time()
while time.time() - началось < МИНУТ_НАГРУЗКИ * 60:
    т = тфлопс(20)
    с = смотреть()
    замеры.append((т, с))
    сказать("%6.1f %8.1f %8.0f %7.0f %8.0f  %s"
            % ((time.time() - началось) / 60, т, с.get("sm", 0), с.get("темп", 0),
               с.get("ватт", 0), с.get("причины", "?")))

горячие = [т for т, _ in замеры[len(замеры) // 2:]] or [холод]
под_нагрузкой = sum(горячие) / len(горячие)
просадка = холод / под_нагрузкой if под_нагрузкой else 0
макс_темп = max((с.get("темп", 0) for _, с in замеры), default=0)
мин_частота = min((с.get("sm", 0) for _, с in замеры), default=0)
макс_частота = max((с.get("sm_max", 0) for _, с in замеры), default=0)
макс_ватт = max((с.get("ватт", 0) for _, с in замеры), default=0)
предел_ватт = max((с.get("ватт_предел", 0) for _, с in замеры), default=0)

сказать("")
сказать("=" * 62)
сказать("ИТОГ ПРИЁМКИ")
сказать("  холодная скорость      %.2f TFLOPS" % холод)
сказать("  под нагрузкой          %.2f TFLOPS" % под_нагрузкой)
сказать("  просадка               %.2f x   %s"
        % (просадка, "ПЛОХО" if просадка > 1.5 else "норма"))
сказать("  температура макс.      %.0f °C" % макс_темп)
сказать("  частота мин / паспорт  %.0f / %.0f МГц" % (мин_частота, макс_частота))
сказать("  потребление макс.      %.0f / %.0f Вт" % (макс_ватт, предел_ватт))
т = тормоза()
сказать("  причины торможения:")
for к, з in sorted(т.items()):
    сказать("      %-34s %s" % (к, з))

плохо = []
if просадка > 1.5:
    плохо.append("скорость падает под нагрузкой в %.1f раза" % просадка)

# ЧАСТОТУ С ПАСПОРТНОЙ НЕ СРАВНИВАЕМ.
#
# Было правило «ниже половины `clocks.max.sm` — отказ», и оно забраковало
# исправную карту. 3090 МГц у RTX PRO 6000 — это пиковый boost на лёгкой
# нагрузке; под плотным bf16-матричным умножением карта с пределом 300 Вт
# обязана сидеть примерно на 1200 МГц, и это норма, а не поломка.
#
# Смысл имеет не уровень частоты, а её ПОСТОЯНСТВО: здоровая карта
# выходит на свою частоту и держит её, задушенная — пилит вниз. Поэтому
# сравниваем минимум с медианой собственных замеров.
частоты = sorted(с.get("sm", 0) for _, с in замеры if с.get("sm"))
if len(частоты) >= 4:
    медиана = частоты[len(частоты) // 2]
    if медиана and мин_частота < медиана * 0.7:
        плохо.append("частота гуляет: %.0f МГц при обычных %.0f"
                     % (мин_частота, медиана))

# МОЩНОСТЬ — ГЛАВНЫЙ ПРИЗНАК. Немецкая A100 брала 110 Вт из 400: карта,
# которой не дают питание, не считает, сколько её ни проси.
if предел_ватт and макс_ватт < предел_ватт * 0.7:
    плохо.append("берёт %.0f Вт из разрешённых %.0f" % (макс_ватт, предел_ватт))

# ТОРМОЖЕНИЕ ЧИТАЕМ ПО ЖИВОЙ МАСКЕ, А НЕ ПО СЧЁТЧИКУ.
#
# `nvidia-smi -q -d PERFORMANCE` отдаёт НАКОПИТЕЛЬНЫЕ счётчики за всю
# жизнь машины — вместе с прошлыми арендаторами. Сто секунд в строке
# «SW Thermal Slowdown» ничего не говорят о том, что происходит сейчас:
# карта могла перегреваться неделю назад у другого клиента.
#
# Что происходит СЕЙЧАС, показывает маска `clocks_throttle_reasons.active`,
# снятая во время нагрузки. Биты: 0x04 — упёрлись в разрешённую мощность
# (это норма, карта работает на полную), 0x20 и 0x40 — температурное
# торможение, 0x08 — аппаратное. Вот они и есть отказ.
ТЕРМО = 0x20 | 0x40 | 0x08
горячих = 0
for _, с in замеры:
    try:
        горячих += 1 if int(с.get("причины", "0x0"), 16) & ТЕРМО else 0
    except (TypeError, ValueError):
        pass
if горячих:
    плохо.append("температурное торможение в %d замерах из %d"
                 % (горячих, len(замеры)))

сказать("")
сказать("ВЕРДИКТ: " + ("ОТКАЗ — " + "; ".join(плохо) if плохо
                       else "ГОДНА, мощность держит"))
сказать("=" * 62)

open("/root/priemka.txt", "w", encoding="utf-8").write("\n".join(печать))
