"""Проверки менеджера карты.

Тесты появились после того, как крон дважды за один день погасил
свежеподнятую карту. Оба раза причина была одна и та же, и оба раза её
не увидели глазами: отметку о подъёме ставил ВЫЗЫВАЮЩИЙ, а не сам
подъём, поэтому она зависела от способа вызова.

Здесь нет ни одного обращения к Hyperstack: всё, что ходит наружу,
подменяется. Проверяется только своя логика — та, в которой и были
ошибки.
"""
import json
import os
import sys
import tempfile
import time
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import карта                                                  # noqa: E402


class ОтметкаОПодъёме(unittest.TestCase):
    """ПОДЪЁМ — ЭТО АКТИВНОСТЬ, КАК БЫ ЕГО НИ ПОЗВАЛИ.

    Цена ошибки известна: 24.09.2026 подняли A100 руками для замера,
    отметки не осталось, крон посчитал простой от последнего задания
    бота — 269 минут — и удалил машину. Замер сорван, час карты
    оплачен впустую.
    """

    def setUp(self):
        self.папка = tempfile.mkdtemp()
        self.старое = карта.СОСТОЯНИЕ
        карта.СОСТОЯНИЕ = os.path.join(self.папка, "состояние.json")
        self.поднимали = []
        self.настоящий = карта._поднять
        карта._поднять = lambda: self.поднимали.append(1) or "https://проба"

    def tearDown(self):
        карта.СОСТОЯНИЕ = self.старое
        карта._поднять = self.настоящий

    def test_подъём_оставляет_отметку(self):
        карта.поднять()
        self.assertEqual(len(self.поднимали), 1)
        м = карта.момент_подъёма()
        self.assertIsNotNone(м)
        self.assertLess(abs(time.time() - м), 5)

    def test_отметка_не_зависит_от_способа_вызова(self):
        """Главное в этом файле. Раньше «поднята» писала только
        `нужна()`, то есть подъём по кнопке клиента; подъём руками
        отметки не оставлял, и крон гасил свежую карту."""
        карта.поднять()
        первая = карта.момент_подъёма()
        self.assertIsNotNone(первая)
        with open(карта.СОСТОЯНИЕ, encoding="utf-8") as ф:
            self.assertEqual(json.load(ф)["что"], "поднята")

    def test_адрес_попадает_в_отметку(self):
        карта.поднять()
        with open(карта.СОСТОЯНИЕ, encoding="utf-8") as ф:
            self.assertEqual(json.load(ф)["адрес"], "https://проба")

    def test_после_гашения_подъёма_нет(self):
        """Погашенная карта не должна выглядеть свежеподнятой — иначе
        крон не погасит её уже никогда."""
        карта.поднять()
        карта.отметить("погашена", простой=30)
        self.assertIsNone(карта.момент_подъёма())

    def test_нет_файла_нет_отметки(self):
        self.assertIsNone(карта.момент_подъёма())

    def test_битый_файл_не_роняет(self):
        with open(карта.СОСТОЯНИЕ, "w", encoding="utf-8") as ф:
            ф.write("{это не json")
        self.assertIsNone(карта.момент_подъёма())


class СчётПростоя(unittest.TestCase):
    """Простой считается от ПОЗДНЕЙШЕГО из двух событий: последней
    работы бота и подъёма карты."""

    def test_позднее_берёт_большее(self):
        self.assertEqual(карта.позднее(100, 200), 200)
        self.assertEqual(карта.позднее(200, 100), 200)

    def test_позднее_переживает_пустоту(self):
        """Не знаем одного — считаем по другому. Не знаем ничего —
        None, и тогда крон не гасит: ошибиться в сторону включённой
        карты дешевле, чем оборвать оплаченную работу."""
        self.assertEqual(карта.позднее(None, 200), 200)
        self.assertEqual(карта.позднее(100, None), 100)
        self.assertIsNone(карта.позднее(None, None))


class ПереборЖелеза(unittest.TestCase):
    """Список железа — это про то, чтобы человек, нажавший кнопку,
    получил свою работу."""

    def test_только_восьмидесятигиговые_и_l40(self):
        имена = [м for _, м, _ in карта.ЖЕЛЕЗО]
        self.assertIn("A100-80G-PCIe-spot", имена)
        self.assertIn("A100-80G-PCIe", имена)

    def test_порядок_по_возрастанию_цены_кроме_запасной(self):
        """Спотовая A100 дешевле обычной и идёт первой. L40 последняя
        не по цене, а по пригодности: 48 ГБ против 80."""
        цены = [ц for _, _, ц in карта.ЖЕЛЕЗО]
        self.assertEqual(цены[0], 1.08)
        self.assertEqual(цены[1], 1.35)

    def test_дорогое_отсечено_потолком(self):
        """H100 за 2,00 и дороже в перебор попадать не должен: вдвое
        дороже A100 ради скорости, которую никто не просил."""
        for _, _, ц in карта.ЖЕЛЕЗО:
            self.assertLessEqual(ц, карта.ПОТОЛОК_ЦЕНЫ)
        self.assertLess(карта.ПОТОЛОК_ЦЕНЫ, 2.00)


if __name__ == "__main__":
    unittest.main(verbosity=2)
