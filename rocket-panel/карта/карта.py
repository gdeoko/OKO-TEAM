def обслужить():
    """Для крона: погасить карту, если она давно никому не нужна.

    БУДИТЬ ПО РАСПИСАНИЮ НЕ НАДО. Карта поднимается сама, когда человек
    нажимает кнопку (`нужна`), и заранее угадывать этот момент незачем —
    угадаешь неверно, заплатишь за пустые часы.

    НЕ ГАСИМ, ПОКА ЧТО-ТО СЧИТАЕТСЯ. Очередь панели спрашивается у неё
    самой: задание живёт минуты, и погасить карту посреди него значит
    забрать у человека оплаченную работу.
    """
    м = машина()
    # Счёт ведём ВСЕГДА, даже когда карты нет: так фиксируется момент
    # последнего шага, и следующий шаг знает, от чего отсчитывать.
    д = учесть_расход(м)
    всего = round(д.get("рубли", 0.0) + ТОМ_РУБ_В_МЕСЯЦ)
    доля = всего / БЮДЖЕТ_РУБ if БЮДЖЕТ_РУБ else 0.0
    print("за месяц: %.1f ч, %d ₽ из %d (%.0f %%)"
          % (д.get("часы", 0.0), всего, БЮДЖЕТ_РУБ, доля * 100), flush=True)

    if доля >= 1.0 and not д.get("остановлено"):
        д["остановлено"] = True
        _расход_записать(д)
        сказать_владельцу(
            "AMBERRY: потолок месяца выбран — %d ₽ из %d. Карта гасится и "
            "больше не поднимается до конца месяца. Поднять потолок: "
            "AMBERRY_БЮДЖЕТ_РУБ в /etc/amberry.env." % (всего, БЮДЖЕТ_РУБ))
    elif доля >= ПРЕДУПРЕДИТЬ_НА and not д.get("предупредили"):
        д["предупредили"] = True
        _расход_записать(д)
        сказать_владельцу(
            "AMBERRY: израсходовано %d ₽ из %d за месяц (%.0f %%). "
            "Пока всё идёт как надо, просто знай."
            % (всего, БЮДЖЕТ_РУБ, доля * 100))

    if not м:
        print("карты нет — гасить нечего", flush=True)
        return
    if доля >= 1.0:
        print("потолок месяца выбран — гашу независимо от простоя", flush=True)
        погасить()
        отметить("погашена по бюджету")
        return
    занята = очередь()
    if занята:
        print("карта считает (%s в очереди) — не трогаю" % занята, flush=True)
        return
    # ПОДЪЁМ — ТОЖЕ АКТИВНОСТЬ, И ЭТО НЕ ПРИДИРКА.
    #
    # Простой считался только по заданиям, и получилось так: человек
    # нажал кнопку, карта поднималась четыре минуты, а крон на
    # следующей же минуте увидел «последнее задание было семьдесят
    # минут назад» и удалил её. Замер 24.09.2026: карта прожила после
    # пробуждения 88 секунд. Человек отстоял бы очередь и остался ни
    # с чем.
    #
    # Раз карту подняли — значит, она кому-то понадобилась, и отсчёт
    # начинается заново.
    когда = позднее(последняя_работа(), момент_подъёма())
    if когда is None:
        # Не смогли прочитать базу — НЕ гасим. Ошибиться в эту сторону
        # значит оставить включённую карту; в другую — оборвать работу.
        print("не знаю, когда была последняя работа — не гашу", flush=True)
        return
    простой = (time.time() - когда) / 60.0
    if простой < ПРОСТОЙ_МИНУТ:
        print("простой %.0f мин из %d — рано" % (простой, ПРОСТОЙ_МИНУТ), flush=True)
        return
    print("простой %.0f мин — гашу" % простой, flush=True)
    погасить()
    отметить("погашена", простой=round(простой))


def очередь():
    """Сколько заданий на карте прямо сейчас. 0 — свободна."""
    адрес = открыть_адрес()
    if not адрес:
        return 0
    try:
        import urllib.request as u
        import base64 as b
        р = u.Request(адрес.rstrip("/") + "/api/stats")
        р.add_header("Authorization", "Basic " + b.b64encode(
            ("rocket:" + os.environ.get("ROCKET_GPU_PASS", "")).encode()).decode())
        return int(json.load(u.urlopen(р, timeout=15)).get("queue", 0))
    except Exception:                                    # noqa: BLE001
        # Панель не отвечает — считаем, что работы нет: иначе повисшая
        # панель держала бы карту включённой вечно.
        return 0


