def службы_живы(адрес):
    """Спросить саму машину, работают ли на ней службы.

    Это второе мнение о живости, и без него нельзя. Панель во время
    счёта РОЛИКА отвечает не сразу: `/api/stats` ходит в ComfyUI, а тот
    занят своим циклом. Молчание панели не значит, что карта мертва, —
    чаще всего значит, что она как раз работает.
    """
    if not адрес:
        return False
    р = ssh(адрес, "systemctl is-active comfyui rocket-panel | tr '\n' ' '", 60)
    return р.returncode == 0 and р.stdout.count("active") >= 2


def панель_жива(адрес=None):
    """Карта на ходу. НЕ ПУТАТЬ С «ПАНЕЛЬ ОТВЕТИЛА СРАЗУ».

    ЭТО САМОЕ ОПАСНОЕ МЕСТО ВО ВСЁМ ХОЗЯЙСТВЕ, и вот почему. Ответ
    «нет» отсюда ведёт в `поднять`, а тот на живой машине запускает
    `загрузка.sh`, которая ПЕРЕЗАПУСКАЕТ службы. То есть ошибочное
    «карта мертва» убивает чужую оплаченную работу.

    Разыграть это проще простого, и на запуске оно случилось бы в
    первый же вечер: один человек заказал десятисекундный ролик,
    карта считает его двадцать минут и отвечает медленно; второй
    человек нажал кнопку; бот спросил «жива ли карта», получил «нет»
    — и перезапустил её вместе с чужим роликом.

    Поэтому спрашиваем дважды и по-разному: сперва даём панели
    ответить с запасом и несколькими попытками, а если молчит —
    заходим по ssh и смотрим, работают ли службы. Живая карта под
    нагрузкой отвечает на второй вопрос всегда.
    """
    for попытка in range(3):
        if _панель_ответила(25):
            return True
        if попытка < 2:
            time.sleep(5)
    if службы_живы(адрес):
        print("панель молчит, но службы на карте работают — не трогаю",
              flush=True)
        return True
    return False


