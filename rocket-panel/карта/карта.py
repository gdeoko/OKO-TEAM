# СКОЛЬКО ЖДАТЬ ПЕРЕД ГАШЕНИЕМ.
#
# Двадцать минут, и цифра взята из замера, а не из головы. Разбор
# промежутков между заданиями показал ФОРМУ: либо следующее задание
# приходит за минуты (тот же человек делает несколько кадров подряд —
# 37 % промежутков короче пяти минут), либо через часы. Середины почти
# нет.
#
# Значит, длинное окно ожидания не ловит никого: тот, кто вернётся,
# вернётся за минуты, а остальные придут завтра. Двадцать минут — это
# вчетверо больше наблюдаемой «очереди» одного человека, и при этом
# сорок лишних минут аренды в каждом хвосте мы больше не платим.
#
# Ошибиться сюда дёшево: лишнее гашение стоит человеку три с половиной
# минуты ожидания и нам около четырёх центов на повторный подъём.
# Ошибиться в другую сторону — 1,08 $ за каждый лишний час.
#
# Меняется одной переменной в /etc/amberry.env, без выкладки.
ПРОСТОЙ_МИНУТ = int(os.environ.get("AMBERRY_IDLE_MIN", "20"))
БАЗА_БОТА = os.environ.get("ROCKET_DB", "/srv/amberry/amberry.db")


def последняя_работа():
    """Когда последний раз что-то считали. None — не знаем.

    Берётся позднейшее из `at` (задание заведено) и `done_at` (задание
    закончено). Только по `at` считать нельзя: длинный ролик заводится
    один раз, а считается десять минут, и к концу его «последняя
    работа» была бы уже десятиминутной давности.

    Имена столбцов сверены с живой базой, а не взяты по памяти: в
    первой версии тут стоял `created_at`, которого в таблице нет
    вовсе. Ошибка была безопасной — карта осталась включённой, — но
    только потому, что незнание тут означает «не гасить».
    """
    import sqlite3
    try:
        с = sqlite3.connect("file:%s?mode=ro" % БАЗА_БОТА, uri=True, timeout=10)
        try:
            р = с.execute("select max(max(coalesce(at,0)), "
                          "max(coalesce(done_at,0))) from jobs").fetchone()
        finally:
            с.close()
        return int(р[0]) if р and р[0] else None
    except Exception as e:                               # noqa: BLE001
        print("база бота не прочиталась:", str(e)[:120], flush=True)
        return None


# ДЕНЬГИ: СЧЁТЧИК И ЖЁСТКИЙ ПОТОЛОК.
#
# Требование владельца: при работе бота 6–8 часов в день расход за
# месяц не превышает 100 000 ₽. Расчёт по прайсу Hyperstack и курсу
# из pricing.py (92 ₽/$):
#
#     A100 1,08 $/ч   7 ч/день     20 900 ₽ + том 1 900 ₽
#     H100 2,00 $/ч   7 ч/день     38 600 ₽ + том 1 900 ₽
#     L40  0,80 $/ч   7 ч/день     15 500 ₽ + том 1 900 ₽
#
# То есть при нормальной работе мы втрое под потолком, даже на самой
# дорогой карте. Превысить 100 000 ₽ можно РОВНО ОДНИМ способом —
# если карта останется включённой круглосуточно:
#
#     A100 круглосуточно      71 500 ₽   ещё в бюджете
#     H100 круглосуточно     132 500 ₽   ПРЕВЫШЕНИЕ
#
# Поэтому сторожим не цену за час, а НАРАБОТКУ. Крон на каждом шаге
# прибавляет время, которое карта реально прожила, в счётчик месяца.
# Так учитывается и то, чего мы не ждали: сорванное гашение, зависший
# подъём, забытая руками включённая карта.
# ИМЕНА ПЕРЕМЕННЫХ ОКРУЖЕНИЯ — ТОЛЬКО ЛАТИНИЦА, И ЭТО НЕ ВКУСОВЩИНА.
#
# Настройки лежат в /etc/amberry.env и подгружаются шелловской строкой
# `. /etc/amberry.env`. bash кириллицу в ИМЕНИ переменной не понимает:
# строка `AMBERRY_ПРОСТОЙ=20` даёт «command not found», и весь файл
# настроек молча читается наполовину. Python такие имена принимает, и
# из-за этого ошибка не видна, пока не позовёшь из крона.
#
# Та же грабля в этой работе попадалась трижды: в именах массивов
# bash, в переменной цикла и здесь. Значения кириллицей можно, имена
# нет.
БЮДЖЕТ_РУБ = float(os.environ.get("AMBERRY_BUDGET_RUB", "100000"))
КУРС = float(os.environ.get("AMBERRY_USD_RUB", "92"))     # как в pricing.py
ТОМ_РУБ_В_МЕСЯЦ = 300 * 0.000096774 * 24 * 30 * КУРС   # том платится всегда
ПРЕДУПРЕДИТЬ_НА = 0.70                                  # доля потолка
РАСХОД = "/srv/amberry/карта_расход.json"


def _расход_прочесть():
    месяц = time.strftime("%Y-%m")
    try:
        with open(РАСХОД, encoding="utf-8") as ф:
            д = json.load(ф)
    except (OSError, ValueError):
        д = {}
    if д.get("месяц") != месяц:
        # Новый месяц — счёт с нуля, и предупреждение снова заряжено.
        д = {"месяц": месяц, "рубли": 0.0, "часы": 0.0,
             "отмечено": None, "предупредили": False, "остановлено": False}
    return д


def _расход_записать(д):
    try:
        os.makedirs(os.path.dirname(РАСХОД), exist_ok=True)
        врем = РАСХОД + ".новый"
        with open(врем, "w", encoding="utf-8") as ф:
            json.dump(д, ф, ensure_ascii=False)
        os.replace(врем, РАСХОД)
    except OSError as e:                                 # noqa: BLE001
        print("счётчик расхода не записался:", str(e)[:120], flush=True)


def цена_машины(м):
    """$/час для поднятой машины. Неизвестный флавор считаем дорогим:
    ошибиться в сторону экономии безопаснее."""
    имя = (м.get("flavor") or {}).get("name") if м else None
    for ф, _, ц in ЖЕЛЕЗО:
        if ф == имя:
            return ц
    return max(ц for _, _, ц in ЖЕЛЕЗО)


def учесть_расход(м):
    """Прибавить время, прожитое картой с прошлого шага крона.

    Считаем ПО ЧАСАМ РАБОТЫ, а не по событиям включения и выключения:
    события теряются, если гашение сорвалось или машину подняли руками,
    а время идёт в любом случае.
    """
    д = _расход_прочесть()
    сейчас = time.time()
    было = д.get("отмечено")
    if м and было:
        часы = max(0.0, (сейчас - было) / 3600.0)
        # Разрыв больше двух часов означает, что крон не работал, а не
        # что карта столько молотила. Считаем по шагу крона.
        часы = min(часы, 2.0)
        д["часы"] = round(д.get("часы", 0.0) + часы, 4)
        д["рубли"] = round(д.get("рубли", 0.0) + часы * цена_машины(м) * КУРС, 2)
    д["отмечено"] = сейчас
    _расход_записать(д)
    return д


def расход_месяца():
    д = _расход_прочесть()
    д["всего_руб"] = round(д.get("рубли", 0.0) + ТОМ_РУБ_В_МЕСЯЦ, 2)
    д["доля"] = д["всего_руб"] / БЮДЖЕТ_РУБ if БЮДЖЕТ_РУБ else 0.0
    return д


def в_бюджете():
    """(можно ли поднимать, что сказать). Потолок жёсткий."""
    д = расход_месяца()
    if д["доля"] < 1.0:
        return True, ""
    return False, ("потолок месяца выбран: %.0f из %.0f ₽"
                   % (д["всего_руб"], БЮДЖЕТ_РУБ))


