"""Приёмка кадра НА КАРТЕ, рядом с генерацией. Без квот и без денег.

## Почему здесь, а не в облаке

Пробовали облаком: у Gemini «платный» ключ оказался на бесплатном
тарифе (20 запросов в сутки), у Claude API нулевой баланс. Проверка,
которая работает первые двадцать кадров в сутки, не проверка. А карта
уже оплачена, и CLIP на ней считает одну картинку меньше секунды на
процессоре — быстрее, чем сама генерация.

## Что именно проверяем

CLIP умеет отвечать на вопрос «что из этого списка больше похоже на
картинку». Три вопроса, и каждый закрывает тот брак, из-за которого
владелец кадры БРАКОВАЛ на самом деле:

  1. ОДЕЖДА. «Совсем голая» против «в лифчике» и «в трусах». Замер
     23.09.2026: чистые кадры дают 0.91–0.98 за наготу, кадры с
     остатком белья — 0.10–0.18. Разделение честное, порог 0.5.
  2. СОСТАВ. «Одна женщина» / «две женщины» / «мужчина и женщина».
     Тот самый кадр МЖ, который владелец назвал браком, дал 0.49 за
     «мужчина и женщина» против 0.48 за «двое мужчин» — то есть
     женщину в нём и правда не видно. Порог 0.6.
  3. СХОДСТВО С ПРИНЯТЫМ КАДРОМ. Мера слабая (у каждого клиента своё
     лицо и своя комната), поэтому порог низкий: она ловит не
     «чуть-чуть не так», а «совсем другое».

Мелкую анатомию не проверяем НАРОЧНО: пальцы эта сборка почти никогда
не рисует идеально, а владелец такие кадры принял. Придирка к ним
означала бы три лишние генерации на каждую кнопку и тот же результат.

## Что она ловит на самом деле (замер 23.09.2026)

Сорок два кадра, по два зерна на каждую из двадцати одной кнопки,
против норм с принятых кадров:

    годен   35
    брак     7   из них пять настоящих: оторванная голова, кадр
                 в другой позе, чёрно-белый кадр, второе тело,
                 посторонний предмет между ног

Две придирки из семи — ложные: тесный кадр «Крупный план» и кадр
с игрушкой она читает как двоих. Цена ложной придирки — один лишний
кадр (двадцать секунд карты), и человек всё равно получает работу:
после трёх попыток отдаётся последняя, какой бы она ни была. Цена
пропущенного второго тела — жалоба и возврат. Размен честный.

Все девять парных кнопок (МЖ и ЖЖ) прошли без единой придирки.
"""
import json
import os
import sys

import torch
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import сходство as S

ОДЕЖДА = ["a completely naked person, bare skin, no clothing at all",
          "a person wearing a bikini top or a bra",
          "a person wearing panties, shorts or underwear"]

СОСТАВ = {"одна": "one woman alone",
          "две_ж": "two women together",
          "мж": "a man and a woman together",
          "два_м": "two men together"}

# Какой состав ожидается у кнопки.
ОЖИДАЕМ = {"mf": "мж", "ff": "две_ж", "mm": "два_м"}

# Кнопки, где одежда в кадре — замысел, а не брак (см. постановки:
# «Раздвинуть ножки» снята в задранной юбке, «Снимает трусики» и
# «Снимает лифчик» — там вещь и есть действие).
ОДЕЖДА_РАЗРЕШЕНА = {"un_sit", "ph_push", "ph_below", "ac_push", "ac_below"}

# ПОРОГ БЕРЁТСЯ У ПРИНЯТОГО КАДРА, А НЕ ИЗ ГОЛОВЫ.
#
# Две версии до этой брали цифру наугад, и обе браковали то, что
# владелец принял.
#
#   «нагота ниже 0,5 — значит одежда». Замер на сорока двух кадрах:
#   у кадра СО СПИНЫ чистая нагота даёт 0,41, потому что со спины
#   «голая» и «в трусах» для CLIP почти одно и то же.
#
#   «кто победил, тот и прав». Со спины побеждает «в трусах» — 0,59
#   против 0,41. На кадре, где одежды нет вовсе.
#
# Дело не в порогах, а в том, что у РАЗНЫХ РАКУРСОВ разная цена
# уверенности, и одной цифры на все не бывает. Зато у каждой кнопки
# есть кадр, который владелец принял, — он и задаёт норму. Считаем его
# один раз и требуем от новых кадров не абсолютной цифры, а НЕ ХУЖЕ
# ПРИНЯТОГО с запасом.
#
# Кнопка без нормы проверяется только на сходство: соврать наугад хуже,
# чем промолчать.
НОРМЫ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "нормы.json")
ХУЖЕ_НОРМЫ = 0.20          # насколько можно уступить принятому кадру

# Сходство с принятым кадром. Мера слабая нарочно: у каждого клиента
# своё лицо и своя комната, и близко к единице она не подойдёт никогда.
# Порог ловит не «чуть-чуть не так», а «совсем другое».
ПОРОГ_СХОДСТВА = 0.55

_нормы = None


def нормы():
    global _нормы
    if _нормы is None:
        try:
            with open(НОРМЫ, encoding="utf-8") as ф:
                _нормы = json.load(ф)
        except Exception:                               # noqa: BLE001
            _нормы = {}
    return _нормы


def _очки(и, варианты):
    м, п = S._загрузить()
    вх = п(text=варианты, images=и, return_tensors="pt", padding=True)
    with torch.no_grad():
        p = м(**вх).logits_per_image.softmax(dim=1)[0]
    return [float(x) for x in p]


def состав_кнопки(ключ):
    ч = str(ключ or "").split("_")
    if len(ч) >= 3 and ч[1] in ОЖИДАЕМ:
        return ОЖИДАЕМ[ч[1]]
    return "одна"


def замер(путь, ключ):
    """(нагота, своё в составе, кто победил в составе)."""
    и = Image.open(путь).convert("RGB")
    нагота = _очки(и, ОДЕЖДА)[0]
    ключи = list(СОСТАВ)
    о = _очки(и, [СОСТАВ[k] for k in ключи])
    return нагота, о[ключи.index(состав_кнопки(ключ))], ключи[о.index(max(о))]


def посчитать_нормы(карта):
    """карта: {ключ кнопки: путь к принятому кадру}. Пишет `нормы.json`."""
    out = {}
    for ключ, путь in карта.items():
        if not os.path.exists(путь):
            print("НЕТ ФАЙЛА", ключ, путь, flush=True)
            continue
        н, с, _ = замер(путь, ключ)
        out[ключ] = {"нагота": round(н, 4), "состав": round(с, 4)}
        print("норма %-14s нагота %.2f состав %.2f" % (ключ, н, с), flush=True)
    with open(НОРМЫ, "w", encoding="utf-8") as ф:
        json.dump(out, ф, ensure_ascii=False, indent=1)
    global _нормы
    _нормы = out
    return out


def проверить(путь, ключ):
    """(годен, причины). Причины — списком, по-русски, для журнала."""
    if not os.path.exists(путь):
        return True, ["файла нет"]
    норма = нормы().get(ключ)
    причины = []

    if норма:
        нагота, своё, победил = замер(путь, ключ)
        можно_одежду = any(str(ключ or "").endswith(к)
                           for к in ОДЕЖДА_РАЗРЕШЕНА)
        if not можно_одежду and нагота < норма["нагота"] - ХУЖЕ_НОРМЫ:
            причины.append(f"одежда в кадре (нагота {нагота:.2f} против "
                           f"{норма['нагота']:.2f} у принятого)")
        # СОСТАВ БРАКУЕТСЯ ПО ДВУМ ПРИЗНАКАМ СРАЗУ, и это не
        # перестраховка. Поодиночке каждый ошибается:
        #
        #   только «кто победил» — на тесном кадре («Мастурбация
        #   сбоку», «Крупный план») в кадре одни бёдра и руки, и CLIP
        #   легко читает их как двоих;
        #   только «хуже нормы» — у одиночных кнопок эталон даёт
        #   0,77…0,97, а правильный кадр другого кадрирования 0,3…0,6,
        #   и браковались верные кадры.
        #
        # Вместе они ловят то, ради чего всё затевалось: второе тело в
        # кадре, где человек один. У такого кадра и чужой состав
        # побеждает, и своё далеко ниже принятого.
        свой = состав_кнопки(ключ)
        if победил != свой and своё < норма["состав"] - ХУЖЕ_НОРМЫ:
            причины.append(f"состав не тот: вышло «{победил}», своё "
                           f"{своё:.2f} против {норма['состав']:.2f} "
                           f"у принятого")

    сх = S.проверить(путь, ключ)
    if сх is not None and сх < ПОРОГ_СХОДСТВА:
        причины.append(f"кадр далёк от принятого ({сх:.2f})")

    return (not причины), (причины or ["годен"])


if __name__ == "__main__":
    if sys.argv[1] == "--нормы":
        посчитать_нормы(json.load(open(sys.argv[2], encoding="utf-8")))
    else:
        годен, причины = проверить(sys.argv[1], sys.argv[2])
        print(json.dumps({"ок": годен, "причины": причины},
                         ensure_ascii=False))
