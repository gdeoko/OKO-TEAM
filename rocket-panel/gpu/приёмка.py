"""Приёмка кадра НА КАРТЕ, рядом с генерацией. Без квот и без денег.

## Почему здесь, а не в облаке

Пробовали облаком: у Gemini «платный» ключ оказался на бесплатном
тарифе (20 запросов в сутки), у Claude API нулевой баланс. Проверка,
которая работает первые двадцать кадров в сутки, не проверка. А карта
уже оплачена, и CLIP на ней считает одну картинку меньше секунды на
процессоре — быстрее, чем сама генерация.

## Что именно проверяем

CLIP умеет отвечать на вопрос «что из этого списка больше похоже на
картинку». Три вопроса, и каждый закрывает тот брак, из-за которого
владелец кадры БРАКОВАЛ на самом деле:

  1. ОДЕЖДА. «Совсем голая» против «в лифчике» и «в трусах». Замер
     23.09.2026: чистые кадры дают 0.91–0.98 за наготу, кадры с
     остатком белья — 0.10–0.18. Разделение честное, порог 0.5.
  2. СОСТАВ. «Одна женщина» / «две женщины» / «мужчина и женщина».
     Тот самый кадр МЖ, который владелец назвал браком, дал 0.49 за
     «мужчина и женщина» против 0.48 за «двое мужчин» — то есть
     женщину в нём и правда не видно. Порог 0.6.
  3. СХОДСТВО С ПРИНЯТЫМ КАДРОМ. Мера слабая (у каждого клиента своё
     лицо и своя комната), поэтому порог низкий: она ловит не
     «чуть-чуть не так», а «совсем другое».

Мелкую анатомию не проверяем НАРОЧНО: пальцы эта сборка почти никогда
не рисует идеально, а владелец такие кадры принял. Придирка к ним
означала бы три лишние генерации на каждую кнопку и тот же результат.
"""
import json
import os
import sys

import torch
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import сходство as S

ОДЕЖДА = ["a completely naked person, bare skin, no clothing at all",
          "a person wearing a bikini top or a bra",
          "a person wearing panties, shorts or underwear"]

СОСТАВ = {"одна": "one woman alone",
          "две_ж": "two women together",
          "мж": "a man and a woman together",
          "два_м": "two men together"}

# Какой состав ожидается у кнопки.
ОЖИДАЕМ = {"mf": "мж", "ff": "две_ж", "mm": "два_м"}

# Кнопки, где одежда в кадре — замысел, а не брак (см. постановки:
# «Раздвинуть ножки» снята в задранной юбке, «Снимает трусики» и
# «Снимает лифчик» — там вещь и есть действие).
ОДЕЖДА_РАЗРЕШЕНА = {"un_sit", "ph_push", "ph_below", "ac_push", "ac_below"}

ПОРОГ_НАГОТЫ = 0.5
ПОРОГ_СОСТАВА = 0.6
ПОРОГ_СХОДСТВА = 0.70


def _очки(и, варианты):
    м, п = S._загрузить()
    вх = п(text=варианты, images=и, return_tensors="pt", padding=True)
    with torch.no_grad():
        p = м(**вх).logits_per_image.softmax(dim=1)[0]
    return [float(x) for x in p]


def состав_кнопки(ключ):
    ч = str(ключ or "").split("_")
    if len(ч) >= 3 and ч[1] in ОЖИДАЕМ:
        return ОЖИДАЕМ[ч[1]]
    return "одна"


def проверить(путь, ключ):
    """(годен, причины). Причины — списком, по-русски, для журнала."""
    если_нет = (True, ["файла нет"])
    if not os.path.exists(путь):
        return если_нет
    и = Image.open(путь).convert("RGB")
    причины = []

    голый = не_нужен = None
    if not any(str(ключ or "").endswith(к) for к in ОДЕЖДА_РАЗРЕШЕНА):
        о = _очки(и, ОДЕЖДА)
        голый = о[0]
        if голый < ПОРОГ_НАГОТЫ:
            причины.append(f"одежда в кадре (нагота {голый:.2f})")

    ключи = list(СОСТАВ)
    о = _очки(и, [СОСТАВ[k] for k in ключи])
    ждём = состав_кнопки(ключ)
    очко = о[ключи.index(ждём)]
    if очко < ПОРОГ_СОСТАВА:
        лучший = ключи[о.index(max(о))]
        причины.append(f"состав не тот: ждали «{ждём}» ({очко:.2f}), "
                       f"вышло «{лучший}» ({max(о):.2f})")

    сх = S.проверить(путь, ключ)
    if сх is not None and сх < ПОРОГ_СХОДСТВА:
        причины.append(f"кадр далёк от принятого ({сх:.2f})")

    return (not причины), (причины or ["годен"])


if __name__ == "__main__":
    годен, причины = проверить(sys.argv[1], sys.argv[2])
    print(json.dumps({"ок": годен, "причины": причины}, ensure_ascii=False))
