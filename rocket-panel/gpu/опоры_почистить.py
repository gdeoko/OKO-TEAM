# -*- coding: utf-8 -*-
"""Убрать из опор разметку ЛИЦА и КИСТЕЙ. НА КАРТЕ.

## Зачем

Препроцессор openpose рисует не только тело, но и кисти (вееры из
двадцати точек на пальцы) и лицо (семьдесят точек плотным облаком).
При силе опоры 1.8 эта мелочь впечатывается прямо в кожу: владелец
видел белые завитки на паху (разметка кисти, лежащей у бедра) и
серебристые трещины на лице (облако точек поверх лица).

Проверка 29.09.2026: шестнадцать опор из двадцати трёх несут эту
разметку. Пересобраны были только семь из раздевания.

## Почему чистим, а не пересобираем

Пересборка требует знать, из какого эталона сделана каждая опора, а у
девяти парных кнопок этой связи в коде нет вовсе. Чистка её не требует
и вдобавок сохраняет ТОТ САМЫЙ скелет, который владелец принял.

Разметка лица и кистей рисуется БЕЛЫМ, а скелет тела - насыщенными
цветами (красный, зелёный, синий, пурпурный). Значит убираем ровно
бесцветное и яркое, и тело остаётся нетронутым.

    python3 опоры_почистить.py            почистить все
    python3 опоры_почистить.py --проверить  только посчитать
"""
import glob
import os
import shutil
import sys

import cv2
import numpy as np

ПОЗЫ = os.environ.get("ROCKET_POZY", "/root/ПОЗЫ")


def доля_белого(кадр):
    сер = cv2.cvtColor(кадр, cv2.COLOR_BGR2GRAY)
    б, г, р = cv2.split(кадр.astype(np.int16))
    бело = (сер > 200) & (abs(б - г) < 30) & (abs(г - р) < 30)
    return бело, float(бело.mean() * 100)


def почистить(путь, проверить=False):
    кадр = cv2.imread(путь)
    if кадр is None:
        return None
    бело, доля = доля_белого(кадр)
    if проверить or доля < 0.005:
        return доля
    # Копию с разметкой держим рядом: вернуть надо уметь одной командой.
    if not os.path.exists(путь + ".с_кистями"):
        shutil.copy2(путь, путь + ".с_кистями")
    # Расширяем на пару точек: у линий есть мягкий край, и без запаса
    # от веера пальцев остаётся серый призрак, который тоже печатается.
    маска = cv2.dilate(бело.astype(np.uint8), np.ones((3, 3), np.uint8), 1)
    кадр[маска > 0] = 0
    cv2.imwrite(путь, кадр)
    return доля


if __name__ == "__main__":
    проверить = "--проверить" in sys.argv
    чищено = 0
    for п in sorted(glob.glob(os.path.join(ПОЗЫ, "*.png"))):
        доля = почистить(п, проверить)
        если = "проверка" if проверить else "почищена"
        знак = "ГРЯЗНАЯ " if доля and доля >= 0.005 else "чистая  "
        print(f"{знак} {доля:7.4f} % {os.path.basename(п)}")
        if доля and доля >= 0.005 and not проверить:
            чищено += 1
    print(f"\nпочищено: {чищено}")
