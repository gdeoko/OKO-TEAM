# Бьёт по двум жалобам владельца разом: «намасленные тела» и «всё
# замазано, детализации нет». Негатив тут по-прежнему почти не слышен
# (CFG полтора), поэтому сказано УТВЕРЖДЕНИЯМИ.
ТЕКСТ_ПРОХОДА = os.environ.get("ROCKET_HIRES_PROMPT", "").strip()


def _второй_проход(g, вход, w, h, seed, узел=60, множитель=None,
                   текст=None):
    """Досыпает узлы второго прохода и отдаёт (граф, новый выход).

    `вход` — пара [узел, слот] с картинкой первого прохода.
    Выключается `ROCKET_HIRES=1` (тогда проход не досыпается вовсе).
    """
    # ПОРОГ ПО ПЛОЩАДИ ОТМЕНЁН 28.09.2026, и вот почему.
    #
    # Рассуждение было такое: на листе 1536 второй проход считает
    # 2304 на 4032, грузит карту на сто процентов и растягивает кадр до
    # одиннадцати минут, а детализацию к этому моменту даёт сам лист.
    # Рассуждение оказалось неверным, и проверила это боевая пачка:
    #
    #     лист 1536 со вторым проходом    заливка кожи  2.1 - 3.7 %
    #     лист 1536 без второго прохода   заливка кожи 15 - 41 %
    #
    # То есть микрофактуру кожи даёт именно ВТОРОЙ ПРОХОД, а лист лишь
    # даёт ему место для работы. Поодиночке не работает ни то, ни другое.
    множитель = ВТОРОЙ_ПРОХОД if множитель is None else float(множитель)
    # Ноль выключает проход. Единица оставляет его, но БЕЗ увеличения:
    # кадр пересчитывается в своём размере. Это разные вещи, и раньше
    # они путались - множитель 1.0 выключал проход совсем.
    #
    # Смысл различия в цене. Проход с множителем 1.5 на листе 1536
    # считает 2304 на 4032, то есть вдвое больше самого кадра, и стоит
    # 87 секунд. Тот же проход без увеличения считает 4.1 мегапикселя
    # вместо 9.3. Если фактуру даёт повторный расчёт, а не увеличение,
    # она обойдётся втрое дешевле.
    if множитель <= 0:
        return g, вход
    множитель = max(1.0, множитель)
    W = int(w * множитель) // 8 * 8
    H = int(h * множитель) // 8 * 8
    n = str(узел)
    # Увеличиваем В ПИКСЕЛЯХ, а не в латенте: латентное увеличение у
    # этой сборки даёт сетку квадратов по всему кадру.
    g[n] = {"class_type": "ImageScale",
            "inputs": {"image": вход, "width": W, "height": H,
                       "upscale_method": "lanczos", "crop": "disabled"}}
    g[str(узел + 1)] = {"class_type": "VAEEncode",
                        "inputs": {"pixels": [n, 0], "vae": ["1", 2]}}
    # Модель берётся ТА ЖЕ, что у первого прохода: если подключена
    # лора, второй проход обязан идти с ней. Раньше тут стояло
    # ["1", 0] в обход лоры, и половина кадра считалась с ней, а
    # половина без - на плоской груди это давало разъезжающуюся форму.
    модель = g["7"]["inputs"].get("model", ["1", 0])
    # Свой текст проходу: узел 4 копируется целиком со всеми снимками,
    # меняется только строка. Так проход видит тех же людей, что и
    # основной, и не теряет ни лица, ни сложения.
    свой = текст if текст is not None else ТЕКСТ_ПРОХОДА
    условие = ["4", 0]
    if свой and "4" in g:
        имя_у = str(узел + 4)
        g[имя_у] = {"class_type": g["4"]["class_type"],
                    "inputs": dict(g["4"]["inputs"])}
        ключ = "prompt" if "prompt" in g[имя_у]["inputs"] else "text"
        g[имя_у]["inputs"][ключ] = свой
        условие = [имя_у, 0]
    g[str(узел + 2)] = {"class_type": "KSampler",
                        "inputs": {"model": модель, "positive": условие,
                                   "negative": ["5", 0],
                                   "latent_image": [str(узел + 1), 0],
                                   # Зерно ДРУГОЕ: с тем же второй проход
                                   # повторяет ошибки первого вместо того,
                                   # чтобы их исправить.
                                   "seed": (seed + 1) if seed else 0,
                                   "steps": ВТОРОЙ_ШАГИ2[0], "cfg": CFG_ФОТО,
                                   "sampler_name": "euler",
                                   "scheduler": "simple",
                                   "denoise": ВТОРОЙ_DENOISE2[0]}}
    g[str(узел + 3)] = {"class_type": "VAEDecode",
                        "inputs": {"samples": [str(узел + 2), 0],
                                   "vae": ["1", 2]}}
    return g, [str(узел + 3), 0]


def _апскейл(g, вход, узел=90, лист=None):
    """Досыпает узлы подъёма разрешения и отдаёт (граф, новый выход).

    `вход` — пара [узел, слот] с готовой картинкой. `лист` — (ширина,
    высота) заказанного кадра; без него подъём не делается, потому что
    без пропорции его не к чему привести.

    Апскейлера нет на диске — возвращаем вход как есть: отдать кадр в
    родном разрешении лучше, чем уронить задание, за которое уже
    списаны коины.
    """
    if not лист or not all(лист):
        return g, вход
    if not os.path.exists(os.path.join(UPSCALE_DIR, АПСКЕЙЛЕР)):
        print(f"апскейлер {АПСКЕЙЛЕР} не найден — отдаю родное разрешение", flush=True)
        return g, вход
    g[str(узел)]={"class_type":"UpscaleModelLoader",
                  "inputs":{"model_name":АПСКЕЙЛЕР}}
    g[str(узел+1)]={"class_type":"ImageUpscaleWithModel",
                    "inputs":{"upscale_model":[str(узел),0],"image":вход}}
    # Кратно восьми: не кратный размер ломает часть узлов и даёт
    # однопиксельную кайму по краю.
    w=int(лист[0]*ПОДЪЁМ)//8*8
    h=int(лист[1]*ПОДЪЁМ)//8*8
    g[str(узел+2)]={"class_type":"ImageScale",
                    "inputs":{"image":[str(узел+1),0],"width":w,"height":h,
                              "upscale_method":"lanczos","crop":"disabled"}}
    return g, [str(узел+2),0]

