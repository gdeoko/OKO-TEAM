# NAG - Normalized Attention Guidance. Ноль значит выключено.
#
# ЗАЧЕМ. При CFG 1.0 ComfyUI негативную ветку не считает вовсе, при 1.5
# она слышна примерно на четверть. Отсюда то, что владелец видел глазами:
# в негативе стоят plastic skin, poreless, oiled skin, а кожа всё равно
# восковая и блестит. Поднять CFG до штатных для Qwen-Image-Edit 4.0
# нельзя - ускоритель сборки ломается, проверено 28.09.2026: свет
# становится жёстким, фон подменяется на чужой.
#
# NAG работает не через CFG, а в пространстве внимания, и придуман
# ровно под дистиллированные сборки. Значит негатив начинает звучать,
# а свет и фон остаются свои.
NAG_СИЛА = float(os.environ.get("ROCKET_NAG", "0"))
NAG_АЛЬФА = float(os.environ.get("ROCKET_NAG_ALPHA", "0.5"))
NAG_ТАУ = float(os.environ.get("ROCKET_NAG_TAU", "1.5"))


def _наг(g, узел=70, сила=None):
    """Прицепить NAGuidance к модели сэмплера. Возвращает граф.

    Патчит МОДЕЛЬ, поэтому встаёт между лорой и сэмплером и не трогает
    ни условия, ни латент.
    """
    сила = NAG_СИЛА if сила is None else float(сила)
    if сила <= 0:
        return g
    n = str(узел)
    вход = g["7"]["inputs"].get("model", ["1", 0])
    # Входов у узла ровно четыре, условия среди них нет: негатив он
    # берёт из негативной ветки сэмплера сам. Проверено по object_info
    # карты - выдуманный вход ComfyUI молча проглотил бы, а граф
    # посчитался бы без NAG вовсе.
    g[n] = {"class_type": "NAGuidance",
            "inputs": {"model": вход,
                       "nag_scale": сила,
                       "nag_alpha": NAG_АЛЬФА,
                       "nag_tau": NAG_ТАУ}}
    g["7"]["inputs"]["model"] = [n, 0]
    return g


