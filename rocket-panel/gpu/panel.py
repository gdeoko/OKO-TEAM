def лоры_комфи(силой=False):
    """Какие лоры ВИДИТ ComfyUI — не какие лежат на диске.

    Это разные вещи, и разница стоила молчаливой поломки. ComfyUI читает
    список моделей ОДИН РАЗ при запуске. Файл, доехавший позже (перенос
    на новую карту, докачка), лежит на месте, `os.path.exists` его
    находит — а ComfyUI отвечает `Value not in list: lora_name ... not
    in []` и выбрасывает узел. Задание при этом не падает: оно считается
    БЕЗ лоры и отдаёт человеку кадр, в котором просто нет того, за что
    он платил. Проверено 25.09.2026 на трёх заказах подряд.

    Поэтому спрашиваем сам ComfyUI. Ответ держим полминуты: список
    меняется только при перезапуске службы, а дёргать его на каждый
    заказ незачем.

    Не ответил — возвращаем ПУСТО, то есть считаем без лоры. Ошибиться
    в сторону кадра без лоры дешевле, чем в сторону упавшего заказа.
    """
    if not силой and time.time()-_ЛОРЫ_КЭШ["когда"]<30:
        return _ЛОРЫ_КЭШ["список"]
    try:
        о=json.load(urllib.request.urlopen(
            COMFY+"/object_info/LoraLoaderModelOnly",timeout=10))
        сп=о["LoraLoaderModelOnly"]["input"]["required"]["lora_name"][0]
        _ЛОРЫ_КЭШ["список"]=frozenset(сп)
    except Exception as e:                              # noqa: BLE001
        print("список лор не прочитался:",str(e)[:120],flush=True)
        _ЛОРЫ_КЭШ["список"]=frozenset()
    _ЛОРЫ_КЭШ["когда"]=time.time()
    return _ЛОРЫ_КЭШ["список"]


def _лора(g, имя, сила, узел="20"):
    """Подмешать веса к модели. Условия не трогаем: лора учит рисовать,
    а не понимать текст, и `LoraLoaderModelOnly` — ровно про это.

    НЕТ ФАЙЛА — РАБОТАЕМ БЕЗ НЕГО, А НЕ ПАДАЕМ.

    Умолчание ползунка «как на фото» берёт середину, то есть силу БОЛЬШЕ
    НУЛЯ, — значит лора подмешивается почти к каждому заказу. Пока файл
    лежал на карте, этого никто не замечал; при переезде на другую
    площадку он не доехал, и `LoraLoaderModelOnly` стал валить задание
    целиком. Человек платит коины и получает ошибку — за файл, который
    всего лишь уточняет размер груди.

    Поэтому отсутствие файла понижает требование: кадр выйдет с тем
    размером, который рисует сама сборка. Панель об этом честно
    сообщает в `/api/готовность`, а заказ доходит.
    """
    if not имя or float(сила) <= 0:
        return g
    if имя not in лоры_комфи():
        print(f"ComfyUI не видит лору {имя} — считаю без неё, заказ не роняю",
              flush=True)
        return g
    # ЛОРЫ ЦЕПЛЯЮТСЯ ЦЕПОЧКОЙ, а не каждая к чекпоинту. Вторая обязана
    # брать модель у первой, иначе она просто отменит её: у обеих на
    # входе был бы ["1",0], и в дело пошла бы только последняя.
    предыдущая = g["7"]["inputs"].get("model", ["1", 0])
    g[узел]={"class_type":"LoraLoaderModelOnly",
             "inputs":{"model":предыдущая,"lora_name":имя,
                       "strength_model":float(сила)}}
    g["7"]["inputs"]["model"]=[узел,0]
    return g


def плоскость(заказ, images, чей=0):
    """Сила лоры: число от бота или «авто» — замер по снимку.

    Число приходит, когда человек САМ выбрал фигуру в боте: он знает
    своё тело лучше любой меры, и спорить с ним нечем. «Авто» приходит
    на умолчании «как на фото» — там мы и правда не знаем, и мера
    решает (см. `плоскость_по_снимку` в приёмке).

    `чей` — НОМЕР ЖЕНСКОГО СНИМКА, и он обязателен именно у пар. В
    сценах МЖ первым идёт МУЖЧИНА (так требует сборка, иначе выходят
    две женщины), а мера, наведённая на мужскую грудь, честно отвечает
    «плоская»: замер 24.09.2026 дал 0,97 и 1,00 на двух мужских
    снимках. Без этого номера лора на полной силе прилетала бы
    ЖЕНЩИНЕ в кадре — за то, что рядом с ней стоит мужчина.
    """
    if str(заказ).strip().lower() in ("авто", "auto"):
        if not images:
            return 0.0
        try:
            import приёмка
            н = чей if 0 <= чей < len(images) else 0
            return приёмка.плоскость_по_снимку(os.path.join(IN, images[н]))
        except Exception as e:                          # noqa: BLE001
            # Мера — удобство, а не условие работы: не смогла — кадр
            # всё равно считается, просто без лоры.
            print("плоскость: осечка", str(e)[:120], flush=True)
            return 0.0
    try:
        return max(0.0, min(1.5, float(заказ or 0)))
    except (TypeError, ValueError):
        return 0.0


def _фото_база(p, neg, seed, images=None, denoise=1.0):
    """Общий каркас фото-графа. images — до трёх имён файлов.

    `denoise` — СКОЛЬКО ОТ ИСХОДНИКА ОСТАВИТЬ, и это не тонкая
    настройка, а разница между двумя товарами.

    При denoise=1.0 стартовый латент стирается целиком: снимок влияет
    на кадр только через `TextEncodeQwenImageEditPlus`, то есть через
    условие. Лицо модель старается сохранить, а комнату сочиняет
    заново — сколько ни пиши в промпте «оставь ту же обстановку».
    Ровно это и случилось у владельца 21.09.2026: он не выбирал место,
    а героиня оказалась в чужом помещении.

    При denoise<1 исходник переживает часть шагов, и обстановка, поза и
    сложение остаются узнаваемыми. Это и есть «фон с референса».
    """
    g={}
    if ПОЛНАЯ:
        # ПОЛНАЯ МОДЕЛЬ. Дистиллят собран «всё в одном» и грузится одним
        # узлом, полная - тремя раздельными: веса, кодировщик, vae.
        #
        # Зачем она. Дистиллят считает 4-8 шагов и физически не успевает
        # положить микрорельеф: он заменяет его обобщением, и кадр
        # выходит живописью. Владелец и сетевой администратор сказали об
        # этом одними словами - «как кистью», «мона лиза». Полная модель
        # идёт двадцать-тридцать шагов, и фактура появляется именно на
        # поздних, которые дистиллят пропускает.
        g["1a"]={"class_type":"UNETLoader","inputs":{
            "unet_name":UNET_ПОЛНЫЙ,"weight_dtype":"default"}}
        g["1b"]={"class_type":"CLIPLoader","inputs":{
            "clip_name":CLIP_ПОЛНЫЙ,"type":"qwen_image"}}
        g["1c"]={"class_type":"VAELoader","inputs":{"vae_name":VAE_ПОЛНЫЙ}}
        МОДЕЛЬ,КЛИП,ВАЕ=["1a",0],["1b",0],["1c",0]
        шагов=ШАГИ_ПОЛНОЙ
        cfg=CFG_ПОЛНОЙ
    else:
        g["1"]={"class_type":"CheckpointLoaderSimple","inputs":{"ckpt_name":CKPT_PHOTO}}
        МОДЕЛЬ,КЛИП,ВАЕ=["1",0],["1",1],["1",2]
        шагов=шаги_под_denoise(denoise)
        cfg=CFG_ФОТО
    g["5"]={"class_type":"CLIPTextEncode","inputs":{"clip":КЛИП,"text":neg or PHOTO_NEG}}
    g["7"]={"class_type":"KSampler","inputs":{"model":МОДЕЛЬ,"positive":["4",0],
        "negative":["5",0],"seed":seed,"steps":шагов,"cfg":cfg,
        "sampler_name":"euler","scheduler":"simple",
        "denoise":max(0.05,min(1.0,float(denoise)))}}
    g["8"]={"class_type":"VAEDecode","inputs":{"samples":["7",0],"vae":ВАЕ}}
    images=[x for x in (images or []) if x][:MAX_REF]
    if images:
        # Снимки идут в УСЛОВИЕ: так модель держит лицо и сложение.
        # Каркас кадра (обстановка, поза) приходит не отсюда, а из
        # стартового латента — и только при denoise<1, см. `_фото_база`.
        узел={"clip":КЛИП,"prompt":p,"vae":ВАЕ}
        for i,имя in enumerate(images,1):
            g[f"3{i}"]={"class_type":"LoadImage","inputs":{"image":имя,"upload":"image"}}
            узел[f"image{i}"]=[f"3{i}",0]
        g["4"]={"class_type":"TextEncodeQwenImageEditPlus","inputs":узел}
    else:
        g["4"]={"class_type":"CLIPTextEncode","inputs":{"clip":КЛИП,"text":p}}
    return g


def опора_файл(ключ, вид=None):
    """Ключ кнопки → имя файла опоры внутри `input` ComfyUI.

    Опоры лежат отдельными папками по видам, а `LoadImage` умеет читать
    только из `input`, поэтому нужная переносится туда при первом
    обращении. Переносится копией, а не ссылкой: ComfyUI чистит `input`
    сам, и по ссылке он удалил бы оригинал.
    """
    ключ=(ключ or "").strip()
    if not ключ or "/" in ключ or "\\" in ключ:
        return None
    папка=ВИДЫ_ОПОР.get(вид or ОПОРА_ВИД,ВИДЫ_ОПОР[ОПОРА_ВИД])[0]
    откуда=os.path.join(папка,ключ+".png")
    if not os.path.exists(откуда):
        return None
    имя="opora_%s_%s.png" % (вид or ОПОРА_ВИД,ключ)
    куда=os.path.join(IN,имя)
    if not os.path.exists(куда) or os.path.getmtime(куда)<os.path.getmtime(откуда):
        shutil.copy(откуда,куда)
    return имя


def _опора(g,w,h,имя,сила,до,вид=None):
    """Прицепить опору к обоим условиям. См. «ОПОРА» в шапке.

    Узлы нумеруются с 50: ниже заняты каркасом фото, снимками (31–33) и
    апскейлом (90+). Пересечение номеров ComfyUI не ловит — он молча
    берёт последний, и граф считается не тот, что задуман.
    """
    g["50"]={"class_type":"ControlNetLoader",
             "inputs":{"control_net_name":CN_UNION}}
    g["51"]={"class_type":"SetUnionControlNetType",
             "inputs":{"control_net":["50",0],
                       "type":ВИДЫ_ОПОР.get(вид or ОПОРА_ВИД,
                                            ВИДЫ_ОПОР[ОПОРА_ВИД])[1]}}
    g["52"]={"class_type":"LoadImage","inputs":{"image":имя,"upload":"image"}}
    # Опора приводится к размеру кадра. `crop:"center"` обязателен:
    # эталон и заказанный лист бывают разной пропорции, а растянутая
    # опора — это растянутый человек.
    g["53"]={"class_type":"ImageScale",
             "inputs":{"image":["52",0],"width":w,"height":h,
                       "upscale_method":"lanczos","crop":"center"}}
    g["54"]={"class_type":"ControlNetApplyAdvanced",
             "inputs":{"positive":["4",0],"negative":["5",0],
                       "control_net":["51",0],"image":["53",0],
                       "strength":float(сила),"start_percent":0.0,
                       "end_percent":float(до),"vae":["1",2]}}
    g["7"]["inputs"]["positive"]=["54",0]
    g["7"]["inputs"]["negative"]=["54",1]
    return g


def wf_photo(p,w,h,seed,images=None,neg=None,denoise=1.0,
             опора=None,опора_сила=None,опора_до=None,ключ_опоры="",
             опора_вид=None,плоскость=0.0,nag=None,cfg=None,hires=None,
             шаги=None,шаги_прохода=None,сэмплер=None,планировщик=None,
             denoise_прохода=None,текст_прохода=None,реализм=None,
             кожа=None):
    """Текст в фото и фото в фото — один граф, разница в наличии снимков."""
    # Без снимков стартового латента нет вовсе, и частичный denoise
    # означал бы недосчитанный шум вместо картинки.
    if not images:
        denoise=1.0
    g=_фото_база(p,neg,seed,images,denoise)
    if cfg:
        g["7"]["inputs"]["cfg"]=max(1.0,min(8.0,float(cfg)))
    # Шаги параметром: сборка Rapid рассчитана на 4-8, а компенсация
    # `шаги_под_denoise` просит все десять. Цена шага на листе 1536
    # заметна, и перебрать её надо замером, а не рассуждением.
    if шаги:
        g["7"]["inputs"]["steps"]=max(2,min(20,int(шаги)))
    # СЭМПЛЕР И ПЛАНИРОВЩИК ЗАПРОСОМ. У фото они были зашиты в
    # euler/simple, и перебрать их было нечем, хотя пластиковая кожа -
    # первая жалоба владельца, а разные сэмплеры дают заметно разную
    # микрофактуру при тех же шагах и той же цене.
    if сэмплер:
        g["7"]["inputs"]["sampler_name"]=str(сэмплер)
    if планировщик:
        g["7"]["inputs"]["scheduler"]=str(планировщик)
    g=_лора(g,ЛОРА_ПЛОСКАЯ,плоскость)
    # Реализм подмешивается ПОСЛЕ плоскости: порядок в цепочке не
    # важен для результата, но узел нужен свой.
    g=_лора(g,ЛОРА_РЕАЛИЗМ,
            РЕАЛИЗМ_СИЛА if реализм is None else реализм, узел="21")
    # Своя лора кожи третьим звеном цепочки. Ноль означает, что узла не
    # будет вовсе, поэтому выключенная она не стоит ни секунды.
    g=_лора(g,ЛОРА_КОЖА,
            КОЖА_СИЛА if кожа is None else кожа, узел="22")
    if опора:
        своя=ОПОРА_СВОЯ.get(ключ_опоры or "",{})
        g=_опора(g,w,h,опора,
                 своя.get("сила",ОПОРА_СИЛА) if опора_сила is None else опора_сила,
                 своя.get("до",ОПОРА_ДО) if опора_до is None else опора_до,
                 опора_вид or своя.get("вид",ОПОРА_ВИД))
    # Порядок важен: сперва ПЕРЕСЧЁТ в большом разрешении (настоящие
    # детали), потом уже подъём до отдаваемого размера. Наоборот -
    # значит растягивать мыло и пересчитывать растянутое.
    g=_наг(g,сила=nag)
    # Шаги прохода приходят запросом через держатель и возвращаются
    # обратно в `finally`: панель обслуживает задания подряд, и
    # настройка одного не должна доставаться следующему.
    было_шагов=ВТОРОЙ_ШАГИ2[0]
    было_силы=ВТОРОЙ_DENOISE2[0]
    if шаги_прохода:
        ВТОРОЙ_ШАГИ2[0]=max(2,min(20,int(шаги_прохода)))
    if denoise_прохода:
        ВТОРОЙ_DENOISE2[0]=max(0.05,min(0.9,float(denoise_прохода)))
    try:
        g,выход=_второй_проход(g,["8",0],w,h,seed,множитель=hires,
                               текст=текст_прохода)
    finally:
        ВТОРОЙ_ШАГИ2[0]=было_шагов
        ВТОРОЙ_DENOISE2[0]=было_силы
    g,выход=_апскейл(g,выход,лист=(w,h))
    g["9"]={"class_type":"SaveImage","inputs":{"images":выход,"filename_prefix":"photo"}}
    if not images:
        g["6"]={"class_type":"EmptySD3LatentImage","inputs":{"width":w,"height":h,"batch_size":1}}
        g["7"]["inputs"]["latent_image"]=["6",0]
    else:
        # Размер задаёт первый снимок, растянутый до нужного кадра.
        g["40"]={"class_type":"ImageScale","inputs":{"image":["31",0],"width":w,"height":h,
                 "upscale_method":"lanczos","crop":"center"}}
        g["41"]={"class_type":"VAEEncode","inputs":{"pixels":["40",0],"vae":["1",2]}}
        g["7"]["inputs"]["latent_image"]=["41",0]
    return g


def wf_inpaint(p,seed,image,mask,feather=24,grow=8,neg=None,кожа=None):
    """Правка по области: белое в маске переписывается, остальное остаётся
    пиксель в пиксель. Композит в конце обязателен — без него модель
    подменяет и то, что не просили.

    ЛОРА КОЖИ ЗДЕСЬ БЫЛА НУЖНА, А ЕЁ НЕ БЫЛО ВОВСЕ: `_фото_база` лор не
    цепляет, их вешает `wf_photo` уже поверх. Правка по маске - это
    раздевание, то есть проход, который и ПЕЧАТАЕТ кожу; проба
    30.09.2026 показала, что мокрую пластмассу делает именно он, а не
    общая генерация. Композицию лора тут сломать не может: область
    держит маска."""
    g=_фото_база(p,neg,seed,[image])
    # НОМЕРА УЗЛОВ 60 И 61, А НЕ 21 И 22. В этом графе двадцатые заняты
    # самой маской: 20 это её загрузка, 21 перевод в маску, 22 рост, 23
    # растушёвка, 24 латент, 25 композит. Повесив лоры на 21 и 22, я
    # затёрла маску - ComfyUI отвечал на такой граф «400 Bad Request», и
    # раздевание молча пропускалось три прогона подряд.
    g=_лора(g,ЛОРА_РЕАЛИЗМ,РЕАЛИЗМ_СИЛА,узел="60")
    g=_лора(g,ЛОРА_КОЖА,КОЖА_СИЛА if кожа is None else кожа,узел="61")
    g["20"]={"class_type":"LoadImage","inputs":{"image":mask,"upload":"image"}}
    g["21"]={"class_type":"ImageToMask","inputs":{"image":["20",0],"channel":"red"}}
    g["22"]={"class_type":"GrowMask","inputs":{"mask":["21",0],"expand":int(grow),
             "tapered_corners":True}}
    g["23"]={"class_type":"FeatherMask","inputs":{"mask":["22",0],"left":int(feather),
             "top":int(feather),"right":int(feather),"bottom":int(feather)}}
    g["41"]={"class_type":"VAEEncode","inputs":{"pixels":["31",0],"vae":["1",2]}}
    g["24"]={"class_type":"SetLatentNoiseMask","inputs":{"samples":["41",0],"mask":["23",0]}}
    g["7"]["inputs"]["latent_image"]=["24",0]
    g["25"]={"class_type":"ImageCompositeMasked","inputs":{"destination":["31",0],
             "source":["8",0],"mask":["23",0],"x":0,"y":0,"resize_source":False}}
    # Апскейл ПОСЛЕ композита. Наоборот нельзя: композит склеивает
    # правку с исходником пиксель в пиксель, а у поднятой картинки и
    # исходника размеры разные — шов пойдёт по всей маске.
    #
    # `лист` не передаётся, и подъёма у правки НЕТ вовсе. Размер здесь
    # задаёт присланный файл, а он уже поднят нами при выдаче; прежний
    # код приводил правку к жёстким 1152×2048 с обрезкой по центру — то
    # есть клиент отправлял на правку свой кадр и получал его обрезком.
    g,выход=_апскейл(g,["25",0])
    g["9"]={"class_type":"SaveImage","inputs":{"images":выход,"filename_prefix":"inpaint"}}
    return g


def wf_video(p,w,h,frames,seed,images=None,neg=None,shift=8.0,сэмплер=None,планировщик=None,steps=None,cfg=None):
    """Три режима одним графом, по числу снимков:

        нет снимков  — текст в видео
        один         — оживление снимка
        два          — ролик с двумя людьми, оба с референсов

    СНИМКИ ИДУТ ЧЕРЕЗ VACE, И ЭТО ЕДИНСТВЕННЫЙ ПУТЬ, КОТОРЫЙ РАБОТАЕТ.
    Замеры на карте 22.09.2026, один и тот же кадр, один текст, одно
    зерно, отличался ровно узел:

        WanImageToVideo(start_image)        чужая женщина с нулевого
                                            кадра
        WanFirstLastFrameToVideo(start/end) то же самое, чужая
        WanVaceToVideo(reference_image)     она же: лицо, грудь, фон —
                                            и держится до конца

    Сборка грузится как WAN21_Vace и снимок принимает только своим
    входом; мимо него кадр до модели не доходит вовсе. Поэтому режима
    «первый и последний кадр» больше нет: эта сборка его обещание не
    держит. Два снимка теперь значат двух ЛЮДЕЙ — оба уходят в
    `reference_image` одним пакетом, и оба остаются собой. Ровно так
    их и присылает бот в парных роликах.
    """
    images=[x for x in (images or []) if x][:2]
    g={
     "1":{"class_type":"CheckpointLoaderSimple","inputs":{"ckpt_name":CKPT_VIDEO}},
     "12":{"class_type":"ModelSamplingSD3","inputs":{"model":["1",0],"shift":float(shift)}},
     "4":{"class_type":"CLIPTextEncode","inputs":{"clip":["1",1],"text":p}},
     "5":{"class_type":"CLIPTextEncode","inputs":{"clip":["1",1],"text":neg or WAN_NEG}},
     "7":{"class_type":"KSampler","inputs":{"model":["12",0],"seed":seed,
          # CFG запросом. Единица означает, что негативная ветка не
          # считается вовсе, то есть весь негатив ролика - мёртвый
          # текст. Перебрать это было нечем: величина была зашита.
          "steps":int(steps or STEPS),
          "cfg":max(1.0,min(8.0,float(cfg))) if cfg else CFG,
          "sampler_name":сэмплер or САМПЛЕР_ВИДЕО,
          "scheduler":планировщик or ПЛАНИРОВЩИК_ВИДЕО,"denoise":1.0}},
     "8":{"class_type":"VAEDecode","inputs":{"samples":["7",0],"vae":["1",2]}},
     # КАДРАМИ, А НЕ АНИМИРОВАННЫМ WEBP.
     #
     # `SaveAnimatedWEBP` — единственный узел для роликов в голом
     # ComfyUI, и он отдаёт файл, который телеграм показывает вложением,
     # а не видео. Перегнать его в mp4 не выходит: ffmpeg не читает
     # анимированный webp от ComfyUI («invalid TIFF header in Exif
     # data», проверено на карте 22.09.2026).
     #
     # Поэтому webp не появляется вовсе: кадры ложатся отдельными PNG, а
     # mp4 собирается из них (`собрать_mp4`). Заодно уходит лишнее
     # сжатие с потерями посередине.
     "9":{"class_type":"SaveImage","inputs":{"images":["8",0],
          "filename_prefix":ВИДЕО_ПРЕФИКС}},
    }
    общее={"positive":["4",0],"negative":["5",0],"vae":["1",2],
           "width":w,"height":h,"length":frames,"batch_size":1}
    for i,имя in enumerate(images,1):
        g[f"3{i}"]={"class_type":"LoadImage","inputs":{"image":имя,"upload":"image"}}
        g[f"4{i}"]={"class_type":"ImageScale","inputs":{"image":[f"3{i}",0],"width":w,"height":h,
                    "upscale_method":"lanczos","crop":"center"}}
    if len(images)>=2:
        # Оба снимка одним пакетом: VACE берёт reference_image как
        # набор, и каждый человек в наборе остаётся собой.
        g["43"]={"class_type":"ImageBatch",
                 "inputs":{"image1":["41",0],"image2":["42",0]}}
        g["6"]={"class_type":"WanVaceToVideo",
                "inputs":{**общее,"strength":1.0,"reference_image":["43",0]}}
    elif images:
        # VACE, А НЕ ОБЫЧНЫЙ i2v. Замер на карте 22.09.2026, один кадр,
        # один текст, одно зерно, отличался только этот узел:
        #
        #   WanImageToVideo(start_image)  чужая женщина УЖЕ НА НУЛЕВОМ
        #                                 кадре: другое лицо, другая
        #                                 грудь, другая комната
        #   WanVaceToVideo(reference_image)  она же: то же лицо, та же
        #                                 грудь, тот же фон, и держится
        #                                 до конца ролика
        #
        # Сборка `wan2.2-rapid-mega-aio` грузится как WAN21_Vace, и
        # снимок она принимает только через вход VACE. Через start_image
        # кадр до неё просто не доходил — отсюда и «вообще другой
        # человек», на который жаловался владелец.
        g["6"]={"class_type":"WanVaceToVideo",
                "inputs":{**общее,"strength":1.0,"reference_image":["41",0]}}
    else:
        g["6"]={"class_type":"WanImageToVideo","inputs":общее}
    g["7"]["inputs"]["positive"]=["6",0]
    g["7"]["inputs"]["negative"]=["6",1]
    g["7"]["inputs"]["latent_image"]=["6",2]
    return g

