# СВОЙ ТЕКСТ ВТОРОМУ ПРОХОДУ. Пустая строка значит «тот же, что у
# основного».
#
# Зачем отдельный. Основной текст описывает СЦЕНУ: позу, обстановку,
# ракурс, сложение - две-три тысячи знаков, среди которых про кожу
# сказано одним абзацем. Второй проход сцену уже не строит, он проходит
