def кнопки_узла(имя, со_скрытыми=False):
    """Видимые сцены узла по его названию: «Раздевание», «Интим».

    СКРЫТЫЕ КНОПКИ НЕ ГОНЯЕМ. Владелец убрал из бота четыре кнопки
    раздевания, четыре видео и семь парных - «они сложные и не
    получались». Прогон 30.09.2026 считал их наравне с живыми: карта
    тратилась на кадры, которых человек не увидит, а их числа портили
    свод. Показать их можно нарочно - `SKRYTYE=1`.
    """
    со_скрытыми = со_скрытыми or (os.environ.get("SKRYTYE") or "") not in ("", "0")
    найдено = []

    def обойти(узлы, путь=""):
        for у in узлы:
            здесь = путь + "/" + (getattr(у, "title", "") or "")
            if (getattr(у, "title", "") or "").lower() == имя.lower():
                найдено.extend(getattr(у, "scenes", None) or [])
            обойти(getattr(у, "дети", None) or [], здесь)

    обойти(catalog.РАЗДЕЛЫ)
    return найдено if со_скрытыми else [с for с in найдено if not с.скрыт]


