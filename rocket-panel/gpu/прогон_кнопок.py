def _сочетания():
    """Пары (место, сложение) для перебора. По умолчанию одна - как у бота."""
    имена = [ч.strip() for ч in (os.environ.get("MESTA") or "").split(",")
             if ч.strip()]
    if имена == ["все"]:
        выбор = catalog.видимые_места()
    elif имена:
        по_ключу = {м.key: м for м in catalog.видимые_места()}
        выбор = [по_ключу[и] for и in имена if и in по_ключу]
        # Названный, но спрятанный фон это не «взяли молча другой», а
        # ошибка в задании: кадр по нему в бот не попадёт никогда.
        мимо = [и for и in имена if и not in по_ключу]
        if мимо:
            sys.exit("в боте нет таких фонов (или они спрятаны): "
                     + ", ".join(мимо))
    else:
        выбор = [места.КАК_НА_ФОТО]
    сл = [ч.strip() for ч in (os.environ.get("SLOJ") or "").split(",")
          if ч.strip()]
    if сл == ["все"]:
        сл = list(prompts.СЛОЖЕНИЕ)
    ложения = сл or [None]
    # «как_на_фото» и пустое сложение это одно и то же, и считать их
    # дважды значит платить картой за одинаковые кадры.
    ложения = [None if с == "как_на_фото" else с for с in ложения]
    видно = []
    for с in ложения:
        if с not in видно:
            видно.append(с)
    return [(м, с) for м in выбор for с in видно]


def _метка(место, сложение):
    """Хвост имени файла: пусто у умолчаний бота, иначе фон и сложение."""
    куски = []
    if место is not None and not место.референс:
        куски.append(место.key)
    if сложение:
        куски.append(сложение)
    return ("_" + "_".join(куски)) if куски else ""


def _поза(ключ, путь):
    """Расхождение позы с принятым эталоном, готовой строкой.

    Владелец 30.09.2026: «ЖЖ МЖ сейчас все позы стало не те, которые
    утвердили. Ты видишь расхождение с эталоном ракурса и позы?» Не
    видела: прогон печатал резкость и шум, а позу не мерил вовсе, хотя
    кнопка обещает человеку конкретный кадр.
    """
    if not путь or not путь.endswith(".png"):
        return " " * 9
    try:
        import поза_сверка
        о = поза_сверка.сверить(ключ, путь)
    except Exception:                                   # noqa: BLE001
        return " " * 9
    if о.get("беда") or о.get("расхождение") is None:
        return "поза  ?  "
    з = о["расхождение"]
    return f"поза {з:5.3f}" + ("" if о.get("совпала") else " УШЛА")


