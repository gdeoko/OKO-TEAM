def главное():
    узел = sys.argv[1] if len(sys.argv) > 1 else "Раздевание"
    только = set(sys.argv[2:])
    сцены = [с for с in кнопки_узла(узел) if not только or с.key in только]
    if not сцены:
        sys.exit(f"в узле «{узел}» нет таких кнопок")
    print(f"вход: {ВХОД}")
    print(f"кнопок: {len(сцены)}, зерно {ЗЕРНО}, плоскость {ПЛОСКОСТЬ}\n")
    карта = gpu.Gpu(os.environ.get("ROCKET_GPU_URL", ""),
                    os.environ.get("ROCKET_GPU_USER", "rocket"),
                    os.environ.get("ROCKET_GPU_PASS", ""))
    карта.выбрать("фото")
    вход = карта.upload(os.path.basename(ВХОД), open(ВХОД, "rb").read())
    # РАЗДЕВАНИЕ ПО МАСКЕ идёт до всякой сцены, ровно как у бота.
    # Проба без него 30.09.2026 оставила штаны и кроссовки на кнопке «в
    # полный рост», а парная сцена осталась одетой целиком.
    if (os.environ.get("RAZDET", "1") or "") != "0":
        вход = _раздеть(карта, ВХОД, вход) or вход
    лицо = None
    # Кроп лица отключается переменной, чтобы мерить его вклад ОТДЕЛЬНО
    # от разрешения: первый заход менял и то, и другое разом, и понять,
    # что подняло сходство, а что уронило, было нечем.
    путь_лица = (None if os.environ.get("NOFACE")
                 else лицо_реф.кроп_лица(ВХОД))
    if путь_лица:
        лицо = карта.upload(os.path.basename(путь_лица),
                            open(путь_лица, "rb").read())
        print(f"лицо вторым референсом: {путь_лица} "
              f"(в кадре {лицо_реф.доля_лица(ВХОД)} % высоты)")
    else:
        print("лица на входе не нашлось, идём одним референсом")
    # Место и сложение - умолчания бота: обстановка с присланного фото,
    # сложение не задано. Меняются они человеком, и проба обязана идти
    # на том же, что видит большинство.
    место = места.КАК_НА_ФОТО
    сложение = None
    # ВТОРОЙ ЧЕЛОВЕК ПАРНОЙ СЦЕНЫ. Без него парная кнопка меряется по
    # кадру, где половина людей выдумана, и любые числа по ней врут.
    ВХОД2 = os.environ.get("VHOD2") or ""
    вход2 = None
    if ВХОД2 and os.path.exists(ВХОД2):
        вход2 = карта.upload(os.path.basename(ВХОД2),
                             open(ВХОД2, "rb").read())
        print(f"второй человек: {ВХОД2}")
    итог = []
    for с in сцены:
        полы = catalog.полы(с.key)
        парная = len(полы) > 1
        if парная and not вход2:
            print(f"ПРОПУСК {с.key}: парной сцене нужен ВХОД2")
            итог.append({"ключ": с.key, "название": с.title, "файл": None,
                         "секунд": 0, "беда": "нет второго снимка"})
            continue
        # У МЖ первым идёт мужчина. ВХОД у нас женский, значит для МЖ
        # снимки меняются местами, а для ЖЖ порядок не значит ничего.
        порядок = ([вход2, вход] if полы[:2] == ("м", "ж") else [вход, вход2])
        файлы = ([ВХОД2, ВХОД] if полы[:2] == ("м", "ж") else [ВХОД, ВХОД2])
        путь, сек, беда = прогнать(
            карта, с, порядок[0] if парная else вход, место, сложение, лицо,
            второй=порядок[1] if парная else None,
            файлы_рефов=файлы if парная else [ВХОД])
        знак = "ок  " if путь else "МИМО"
