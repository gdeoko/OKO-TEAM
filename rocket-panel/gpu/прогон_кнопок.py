"""Прогнать пачку кнопок ТЕМ ЖЕ путём, что идёт клиент.

## Зачем именно так

Первая проба 28.09.2026 расходилась с продуктом в трёх местах разом:
негатив брала из сцены вместо `prompts.негатив()`, опору не слала
вовсе, силу лоры не брала из выбора человека. Кадры выходили не те,
что получает клиент, и чинить по ним значило чинить не то.

Поэтому здесь ничего не собирается заново: промпт, негатив, опора,
лист и лора берутся у того же кода, что обслуживает бота.

## Как запускать

Запускать НА СЕРВЕРЕ БОТА (там лежит каталог и настройки), карта
дёргается по сети - как и у бота.

    python3 прогон_кнопок.py Раздевание            вся пачка
    python3 прогон_кнопок.py Раздевание un_close   одна кнопка
    ВХОД=/путь/фото.jpg python3 прогон_кнопок.py Раздевание

Один вход на всю пачку нарочно: если менять и вход, и кнопку, потом не
понять, что именно изменило кадр.
"""
import json
import os
import sys
import time

БОТ = os.environ.get("AMBERRY_BOT_DIR", "/opt/amberry/rocket-panel/bot")
sys.path.insert(0, БОТ)

import catalog                                          # noqa: E402
import gpu                                              # noqa: E402
import лицо_реф                                         # noqa: E402
import места                                            # noqa: E402
import prompts                                          # noqa: E402
import детейлер                                         # noqa: E402

# Вход по умолчанию - тот же кадр Ники, на котором владелец смотрел
# пробы: одетая, в пол роста, лицом в камеру.
ВХОД = os.environ.get("ВХОД") or os.environ.get(
    "VHOD", "/srv/amberry/пробы/ника-одета-полроста.jpg")
КУДА = os.environ.get("КУДА") or os.environ.get("KUDA", "/srv/amberry/пробы")

# Одно зерно на всю пачку: разница между кадрами должна быть разницей
# КНОПКИ, а не везения.
ЗЕРНО = int(os.environ.get("ЗЕРНО") or os.environ.get("ZERNO", "4242"))

# Сила лоры плоской груди - как у человека по умолчанию (см. каталог).
ПЛОСКОСТЬ = float(os.environ.get("ПЛОСКОСТЬ")
                  or os.environ.get("PLOSKOST", "0") or 0)


def кнопки_узла(имя):
    """Все сцены узла по его названию: «Раздевание», «Интим»."""
    найдено = []

    def обойти(узлы, путь=""):
        for у in узлы:
            здесь = путь + "/" + (getattr(у, "title", "") or "")
            if (getattr(у, "title", "") or "").lower() == имя.lower():
                найдено.extend(getattr(у, "scenes", None) or [])
            обойти(getattr(у, "дети", None) or [], здесь)

    обойти(catalog.РАЗДЕЛЫ)
    return найдено


# Лист. Замер 28.09.2026: на боевых 768 заливка кожи 13 %, на 1536
# всего 2.1 % при эталонных 4.9 % у настоящего фото. Разрешение и
# лечит «всё замазано», ничего другого так не лечит.
ЛИСТ = os.environ.get("LIST") or ""


def прогнать(карта, сцена, вход_на_карте, место, сложение, лицо=None,
             второй=None, файлы_рефов=None):
    """Один кадр по кнопке. Возвращает (файл, секунды, беда).

    Промпт, негатив, лист и опора берутся у того же кода, что
    обслуживает бота (`Scene.промпт`, `prompts.негатив`,
    `catalog.лист`, `catalog.опора`) - см. шапку, почему это важно.

    `второй` - второй человек парной сцены. Без него парная кнопка
    считается по одному снимку, и модель рисует второго из головы:
    мерить по такому кадру нечего, потому что половина кадра не наша.
    """
    промпт = сцена.промпт(место=место, сложение=сложение)
    # ВИДЕО ИЛИ ФОТО - по виду сцены, а не по узлу. У кнопки бывает два
    # ключа на одну картинку («ac_close» и «ph_close»), и отличает их
    # именно `job`: цена и режим у ролика и снимка разные.
    сем = prompts.семейство(сцена.job)
    видео = сем not in ("t2i", "i2i", "inpaint")
    params = {
        "prompt": промпт,
        "size": catalog.лист(сцена.key),
        # Шаги и CFG здесь заглушка: панель их из запроса не берёт
        # вовсе, реальные величины живут в gpu/panel.py. Шлём то же,
        # что шлёт бот, чтобы запрос совпадал байт в байт.
        "steps": 4, "cfg": 1.0, "seed": ЗЕРНО,
        "neg": prompts.негатив(промпт),
        # 0.85 - фон с референса, как у бота, когда место не выбрано.
        "denoise": 0.85,
        "mode": "video" if видео else "photo",
        # Второй снимок - плотный кроп лица. Энкодер режет КАЖДЫЙ вход
        # до 384 на 384, и в кадре во весь рост на лицо приходится
        # около тридцати пикселей. Отдельным слотом лицо получает весь
        # бюджет целиком.
        # Порядок снимков тот же, что у бота: у пары МЖ первым идёт
        # МУЖЧИНА (catalog.порядок_фото), и на этот порядок завязана
        # лора плоской груди. Кроп лица подклеивается только одиночной
        # сцене: у пары три слота заняты людьми, а их всего три.
        "images": ([вход_на_карте, второй] if второй
                   else [вход_на_карте] + ([лицо] if лицо else [])),
    }
    if видео:
        # Длина ролика та же, что у бота: пять секунд по умолчанию.
        params["secs"] = float(os.environ.get("SECS", "5"))
        з = os.environ.get("VSTEPS")
        if з:
            params["шагов"] = int(з)
    if ЛИСТ:
        params["_лист"] = [int(ч) for ч in ЛИСТ.split("x")]
    # Сила NAG и сила опоры идут ЗАПРОСОМ: панель живёт на карте и
    # переменных окружения сервера не видит.
    for ключ, имя in (("nag", "NAG"), ("опора_сила", "OPORA_SILA"),
                      ("опора_до", "OPORA_DO"), ("hires", "HIRES"),
                      ("шаги", "STEPS"),
                      # CFG основного прохода. Ниже двух негативная
                      # ветка почти не считается, и весь негатив -
                      # мёртвый текст.
                      ("cfg_свой", "CFG_SVOY"),
                      ("шаги_прохода", "HSTEPS")):
        з = os.environ.get(имя)
        if з not in (None, ""):
            params[ключ] = float(з)
    # Сэмплер и планировщик строкой, а не числом: они имена узлов.
    for ключ, имя in (("сэмплер", "SAMPLER"), ("планировщик", "SCHED")):
        з = os.environ.get(имя)
        if з:
            params[ключ] = з
    опора = catalog.опора(сцена.key)
    if опора:
        params["опора"] = опора
    # Задание кладём рядом с кадром: по нему опыт на карте повторит
    # ровно этот запрос, не пересобирая промпт заново. Пересборка была
    # бы вторым источником правды, и он однажды разойдётся с первым.
    try:
        os.makedirs(КУДА, exist_ok=True)
        import json as _json
        _json.dump(params, open(os.path.join(КУДА, f"{сцена.key}.json"), "w",
                                encoding="utf-8"), ensure_ascii=False, indent=1)
    except OSError:
        pass
    плоскость = prompts.плоскость(сложение)
    if плоскость:
        params["плоскость"] = плоскость
    т = time.time()
    try:
        # start отдаёт ПАРУ (задание, зерно), wait - словарь с полем
        # `file`. Передать пару целиком нельзя: она уходит прямо в
        # адрес запроса и ломает его скобками.
        jid, _зерно = карта.start(**params)
        готово = карта.wait(jid, limit=900)
        файлы = готово.get("files") or []
        if not файлы:
            return None, time.time() - т, "карта не вернула файл"
        данные = карта.fetch(файлы[0])
    except Exception as e:                              # noqa: BLE001
        return None, time.time() - т, str(e)[:200]
    os.makedirs(КУДА, exist_ok=True)
    # Расширение по тому, ЧТО вернула карта: ролик приезжает mp4, и
    # положить его под именем .png значит не открыть его потом ничем.
    хвост = os.path.splitext(файлы[0])[1] or (".mp4" if видео else ".png")
    путь = os.path.join(КУДА, f"{сцена.key}{хвост}")
    open(путь, "wb").write(данные)
    # Доработка зоны идёт СРАЗУ: мерить надо то, что получит человек, а
    # не промежуточный кадр. Отключается переменной NODETAIL. Ролику она
    # не достаётся: каждый кадр стоил бы дороже самого ролика.
    if not видео and not os.environ.get("NODETAIL"):
        try:
            зоны = tuple((os.environ.get("ZONES") or "лицо").split(","))
            # Полы и референсы по сцене: на парной каждый человек
            # считается отдельно, со своим снимком и своим полом. В
            # пробе снимок один на обоих - это нарочно, проба меряет
            # зоны, а не подбор людей.
            полы = catalog.полы(сцена.key)
            рефы = list(файлы_рефов or [ВХОД])[:len(полы)]
            рефы += [рефы[-1]] * (len(полы) - len(рефы))
            готово = детейлер.доработать(путь, рефы[0], зоны, карта=карта,
                                         рефы=рефы, полы=полы)
            if готово and готово != путь:
                os.replace(готово, путь)
        except Exception as e:                          # noqa: BLE001
            print(f"детейлер не отработал: {str(e)[:140]}", flush=True)
    return путь, time.time() - т, None


def главное():
    узел = sys.argv[1] if len(sys.argv) > 1 else "Раздевание"
    только = set(sys.argv[2:])
    сцены = [с for с in кнопки_узла(узел) if not только or с.key in только]
    if not сцены:
        sys.exit(f"в узле «{узел}» нет таких кнопок")
    print(f"вход: {ВХОД}")
    print(f"кнопок: {len(сцены)}, зерно {ЗЕРНО}, плоскость {ПЛОСКОСТЬ}\n")
    карта = gpu.Gpu(os.environ.get("ROCKET_GPU_URL", ""),
                    os.environ.get("ROCKET_GPU_USER", "rocket"),
                    os.environ.get("ROCKET_GPU_PASS", ""))
    карта.выбрать("фото")
    вход = карта.upload(os.path.basename(ВХОД), open(ВХОД, "rb").read())
    лицо = None
    # Кроп лица отключается переменной, чтобы мерить его вклад ОТДЕЛЬНО
    # от разрешения: первый заход менял и то, и другое разом, и понять,
    # что подняло сходство, а что уронило, было нечем.
    путь_лица = (None if os.environ.get("NOFACE")
                 else лицо_реф.кроп_лица(ВХОД))
    if путь_лица:
        лицо = карта.upload(os.path.basename(путь_лица),
                            open(путь_лица, "rb").read())
        print(f"лицо вторым референсом: {путь_лица} "
              f"(в кадре {лицо_реф.доля_лица(ВХОД)} % высоты)")
    else:
        print("лица на входе не нашлось, идём одним референсом")
    # Место и сложение - умолчания бота: обстановка с присланного фото,
    # сложение не задано. Меняются они человеком, и проба обязана идти
    # на том же, что видит большинство.
    место = места.КАК_НА_ФОТО
    сложение = None
    # ВТОРОЙ ЧЕЛОВЕК ПАРНОЙ СЦЕНЫ. Без него парная кнопка меряется по
    # кадру, где половина людей выдумана, и любые числа по ней врут.
    ВХОД2 = os.environ.get("ВХОД2") or os.environ.get("VHOD2") or ""
    вход2 = None
    if ВХОД2 and os.path.exists(ВХОД2):
        вход2 = карта.upload(os.path.basename(ВХОД2),
                             open(ВХОД2, "rb").read())
        print(f"второй человек: {ВХОД2}")
    итог = []
    for с in сцены:
        полы = catalog.полы(с.key)
        парная = len(полы) > 1
        if парная and not вход2:
            print(f"ПРОПУСК {с.key}: парной сцене нужен ВХОД2")
            итог.append({"ключ": с.key, "название": с.title, "файл": None,
                         "секунд": 0, "беда": "нет второго снимка"})
            continue
        # У МЖ первым идёт мужчина. ВХОД у нас женский, значит для МЖ
        # снимки меняются местами, а для ЖЖ порядок не значит ничего.
        порядок = ([вход2, вход] if полы[:2] == ("м", "ж") else [вход, вход2])
        файлы = ([ВХОД2, ВХОД] if полы[:2] == ("м", "ж") else [ВХОД, ВХОД2])
        путь, сек, беда = прогнать(
            карта, с, порядок[0] if парная else вход, место, сложение, лицо,
            второй=порядок[1] if парная else None,
            файлы_рефов=файлы if парная else [ВХОД])
        знак = "ок  " if путь else "МИМО"
        print(f"{знак} {с.key:10s} {с.title:22s} {сек:5.1f}с "
              f"{беда or os.path.basename(путь)}")
        итог.append({"ключ": с.key, "название": с.title, "файл": путь,
                     "секунд": round(сек, 1), "беда": беда})
    json.dump(итог, open(os.path.join(КУДА, "прогон.json"), "w",
                         encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"\nготово: {КУДА}")


if __name__ == "__main__":
    главное()
