def очередь(граф):
    ид = str(uuid.uuid4())
    тело = json.dumps({"prompt": граф, "client_id": ид}).encode()
    з = urllib.request.Request(COMFY + "/prompt", data=тело,
                               headers={"Content-Type": "application/json"})
    try:
        о = json.load(urllib.request.urlopen(з, timeout=60))
    except urllib.error.HTTPError as e:
        # ComfyUI объясняет отказ в теле ответа: без него «400 Bad
        # Request» не говорит ничего, а там лежит имя узла и поля.
        тело = e.read().decode("utf-8", "ignore")[:1800]
        raise RuntimeError(f"ComfyUI отверг граф: {тело}") from None
    return о["prompt_id"]


def дождаться(pid, предел=600):
    т = time.time()
    while time.time() - т < предел:
        try:
            h = json.load(urllib.request.urlopen(
                f"{COMFY}/history/{pid}", timeout=30))
        except Exception:                               # noqa: BLE001
            time.sleep(2)
            continue
        if pid in h:
            вых = h[pid].get("outputs", {})
            for узел in вых.values():
                for к in узел.get("images", []):
                    return к["filename"], time.time() - т
            return None, time.time() - т
        time.sleep(2)
    return None, предел


def аргументы(задание):
    """Задание панели -> аргументы `wf_photo`, ровно как это делает сама
    панель (`/gen`, ветка mode == "photo").

    Задание это ТЕЛО ЗАПРОСА к панели (prompt, size, denoise, опора), а
    `wf_photo` принимает уже разложенные величины (p, w, h, файл опоры).
    Первый заход опыта 28.09.2026 слал задание как есть и падал на
    `unexpected keyword argument 'prompt'` во всех вариантах сразу.

    Перевод повторяем здесь, а не зовём панель по сети: опыту надо
    подменять её константы, а через сеть они не передаются - так
    задумано, чтобы чужие значения не ломали ускоритель.
    """
    d = задание
    w, h = d.pop("_лист", None) or panel.SZ["photo"].get(
        d.get("size", "vert"), (768, 1344))
    ключ_оп = str(d.get("опора") or "")
    вид_оп = (d.get("опора_вид")
              or panel.ОПОРА_СВОЯ.get(ключ_оп, {}).get("вид")
              or panel.ОПОРА_ВИД)
    return dict(
        p=d["prompt"], w=w, h=h, seed=int(d.get("seed", ЗЕРНО)),
        images=d.get("images"), neg=d.get("neg"),
        denoise=max(0.3, min(1.0, float(d.get("denoise", 1.0)))),
        опора=panel.опора_файл(d.get("опора"), вид_оп),
        опора_сила=d.get("опора_сила"), опора_до=d.get("опора_до"),
        ключ_опоры=ключ_оп, опора_вид=вид_оп,
        плоскость=panel.плоскость(d.get("плоскость"), d.get("images"),
                                  int(d.get("женский_снимок", 0) or 0)))


def главное():
    только = set(sys.argv[1:])
    os.makedirs(КУДА, exist_ok=True)
    задание = json.load(open(ПРОМПТ_ФАЙЛ, encoding="utf-8"))
    for имя, правка in варианты().items():
        if только and имя not in только:
            continue
        правка = dict(правка)
        конст = dict(правка.pop("_константы", {}))
        д = аргументы({**задание, **правка})
        было = {к: getattr(panel, к) for к in конст}
        for к, v in конст.items():
            setattr(panel, к, v)
        т0 = time.time()
        try:
            граф = panel.wf_photo(**д)
            pid = очередь(граф)
            файл, сек = дождаться(pid)
        except Exception as e:                          # noqa: BLE001
            print(f"МИМО {имя:26s} {str(e)[:140]}")
            continue
        finally:
            for к, v in было.items():
                setattr(panel, к, v)
        if not файл:
            print(f"МИМО {имя:26s} нет файла за {сек:.0f}с")
            continue
        исход = os.path.join(ДОМ, "ComfyUI/output", файл)
        цель = os.path.join(КУДА, f"{имя}.png")
        if os.path.exists(исход):
            os.replace(исход, цель)
        print(f"ок   {имя:26s} {сек:5.1f}с  {цель}")


if __name__ == "__main__":
    главное()
