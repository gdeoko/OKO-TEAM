#!/usr/bin/env bash
#
# КОПИЯ БОТА ДЛЯ ПАРТНЁРА: завести, выключить, спросить состояние.
#
#   партнёр.sh пуск      <tg_id> <токен> [@имя]
#   партнёр.sh стоп      <tg_id>
#   партнёр.sh состояние <tg_id>
#
# Раньше франшиза заканчивалась строкой «Запуск - в панели»: токен
# принимался, админу уходило письмо, и копии не возникало. Этот скрипт
# и есть тот запуск - и он же рубильник для админки.
#
# ЧТО У КОПИИ СВОЁ, А ЧТО ОБЩЕЕ - главное решение здесь.
#
#   СВОЁ: токен, имя бота, база (его клиенты, их балансы, их работы),
#         папка работ, админ (сам партнёр). Клиентские данные копий не
#         смешиваются ни при каких условиях: это разные базы, а не
#         колонка «чей» в одной.
#
#   ОБЩЕЕ: карта, ключи моделей, каталог сценариев, цены, заставка,
#         запреты. Это и есть товар франшизы - партнёр покупает наш
#         движок, а не право развести свои цены. Каталог кладётся
#         симлинками, поэтому правка владельца в админке доезжает до
#         всех копий сразу, без перезапуска и без обхода серверов.
#
# ЕГО ЗОВЁТ БОТ ЧЕРЕЗ sudo, А ЗНАЧИТ ОТ ROOT И С ЧУЖИМИ ДАННЫМИ.
# Токен сюда приезжает из сообщения в телеграме, то есть его пишет
# посторонний человек. Поэтому оба аргумента проверяются по строгому
# образцу ДО всякого их использования: id только цифры, токен только
# то, что выдаёт BotFather. Без этой проверки перевод строки внутри
# «токена» дописал бы в env-файл службы любую переменную - от чужого
# пароля к карте до подмены базы.
#
# ИМЕНА ПЕРЕМЕННЫХ ТОЛЬКО ЛАТИНИЦЕЙ. bash не считает кириллицу годной
# для идентификатора и читает `ОТВЕТ=...` как имя команды: скрипт не
# падает, а идёт дальше с пустой переменной. В комментариях и в
# сообщениях писать по-русски можно.
set -euo pipefail

# ВЫХОД ИЗ ПЕСОЧНИЦЫ ВЫЗЫВАЮЩЕГО - без этого скрипт бесполезен.
#
# Бот и админка запущены с ProtectSystem=strict, то есть в своём
# пространстве монтирования, где /etc только для чтения. sudo даёт нам
# права root, но НЕ выводит из этого пространства: root внутри
# песочницы всё равно не может записать /etc/amberry/<id>.env и падает
# с «Read-only file system».
#
# Ослаблять песочницу боту нельзя: чтобы `systemctl enable` работал
# изнутри, пришлось бы открыть ему на запись /etc/systemd/system, а это
# ровно то, чем становятся root: написал юнит - получил что угодно.
#
# Поэтому настоящую работу делает временная служба: systemd-run
# поднимает её от PID 1, вне чужой песочницы, и ждёт её кода возврата.
# Замок в sudoers при этом держится - посторонний может запустить
# только этот скрипт и только с проверенными им же аргументами.
if [ -z "${AMBERRY_PARTNER_DIRECT:-}" ] && [ -x /usr/bin/systemd-run ]; then
  exec systemd-run --quiet --pipe --wait --collect \
    --setenv=AMBERRY_PARTNER_DIRECT=1 \
    /usr/local/sbin/amberry-partner "$@"
fi

CMD=${1:-}
ID=${2:-}

case "$ID" in
  ''|*[!0-9]*) echo "нужен числовой tg_id партнёра" >&2; exit 2;;
esac

BASE=/srv/amberry/partners/$ID
ENVD=/etc/amberry
UNIT=amberry@$ID

case "$CMD" in

пуск)
  TOKEN=${3:?нужен токен бота}
  NAME=${4:-}
  # Образец BotFather. Проверяем до curl: иначе «токен» с пробелом или
  # переводом строки уехал бы в аргументы и в env-файл как есть.
  #
  # ДВЕ ПРОВЕРКИ, И ПЕРВАЯ ОБЯЗАТЕЛЬНА. `grep` сверяет ПОСТРОЧНО, и
  # для строки «123456:aaa…\nROCKET_DB=/чужое» он видит первую строку,
  # радуется ей и отвечает «годится» - то есть пропускает ровно тот
  # перевод строки, ради которого проверка и заведена. `case` смотрит
  # на строку целиком и отбивает любой посторонний знак, включая
  # перевод строки и пробел.
  case "$TOKEN" in
    *[!0-9A-Za-z:_-]*|"")
      echo "это не похоже на токен из @BotFather" >&2; exit 2;;
  esac
  if ! printf '%s' "$TOKEN" | grep -qE '^[0-9]{6,}:[A-Za-z0-9_-]{30,}$'; then
    echo "это не похоже на токен из @BotFather" >&2; exit 2
  fi

  # Токен живой? Проверяем ДО того, как заведём службу: служба с
  # мёртвым токеном уходит в Restart=always и молотит журнал раз в
  # пять секунд, а снаружи выглядит как «копия запущена».
  ANS=$(curl -s --max-time 20 "https://api.telegram.org/bot$TOKEN/getMe")
  if ! printf '%s' "$ANS" | grep -q '"ok":true'; then
    echo "телеграм не принял токен: $(printf '%s' "$ANS" | head -c 160)" >&2
    exit 1
  fi
  [ -n "$NAME" ] || NAME=$(printf '%s' "$ANS" |
    sed -n 's/.*"username":"\([^"]*\)".*/\1/p')
  NAME=${NAME#@}
  case "$NAME" in
    ''|*[!A-Za-z0-9_]*) echo "странное имя бота: $NAME" >&2; exit 1;;
  esac

  install -d -o amberry -g amberry -m 750 "$BASE" "$BASE/works"
  install -d -m 750 "$ENVD"

  # Общее - симлинками, а не копиями. Копия файла застывает в том виде,
  # в каком её сняли, и через неделю у партнёра свой каталог из прошлого.
  for F in каталог.json запрет.json заставка.mp4 оферта.json; do
    # `|| true` обязателен: под set -e компаунд `[ -e ] && ln` возвращает
    # 1, когда файла нет, и обрывает запуск из-за необязательного файла.
    [ -e "/srv/amberry/$F" ] && ln -sfn "/srv/amberry/$F" "$BASE/$F" || true
  done

  # Пишем через временный файл: env-файл читается службой при старте, и
  # застать его наполовину записанным значит поднять бота без токена.
  TMPF=$(mktemp "$ENVD/.$ID.XXXX")
  cat > "$TMPF" <<EOF
# Копия AMBERRY для партнёра $ID (@$NAME). Собрано партнёр.sh.
# Общее (карта, ключи, звёзды) приезжает из /etc/amberry.env.
ROCKET_BOT_TOKEN=$TOKEN
ROCKET_BOT_NAME=$NAME
ROCKET_ADMINS=$ID
ROCKET_DB=$BASE/amberry.db
AMBERRY_DATA_DIR=$BASE
AMBERRY_WORKS_DIR=$BASE/works
AMBERRY_OFFER_FILE=$BASE/оферта.json
AMBERRY_PARTNER=$ID
EOF
  chown root:amberry "$TMPF"; chmod 640 "$TMPF"
  mv -f "$TMPF" "$ENVD/$ID.env"

  systemctl daemon-reload
  systemctl enable --now "$UNIT" >/dev/null
  # Повторный пуск (партнёр сменил токен у BotFather) до сюда доходит
  # с уже поднятой службой, и enable --now её не перечитает.
  systemctl restart "$UNIT"

  sleep 3
  if ! systemctl is-active --quiet "$UNIT"; then
    echo "служба не поднялась:" >&2
    journalctl -u "$UNIT" -n 20 --no-pager >&2
    exit 1
  fi
  echo "запущено @$NAME"
  ;;

стоп)
  # ВЫКЛЮЧАЕТ, А НЕ СТИРАЕТ. База партнёра, его работы и env остаются
  # на месте: выключение - это спор о деньгах или пауза, и вернуть
  # копию надо будет тем же нажатием. Удаление данных партнёра руками
  # владельца и только по его отдельному решению.
  systemctl disable --now "$UNIT" >/dev/null 2>&1 || true
  echo "выключено"
  ;;

состояние)
  systemctl is-active "$UNIT" 2>/dev/null || true
  ;;

*)
  echo "команды: пуск <id> <токен> [@имя] | стоп <id> | состояние <id>" >&2
  exit 2;;
esac
