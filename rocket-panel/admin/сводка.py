"""Данные для админ-панели и действия, которые она делает.

Страница только рисует. Всё, что она спрашивает и всё, что просит
сделать, собрано здесь — чтобы не заводить SQL внутри обработчика
запросов и чтобы это можно было проверить тестом без браузера.

## Почему рассылка живёт тут, а не в боте

Бот занят людьми: он отвечает на нажатия и считает кадры. Рассылка на
несколько тысяч адресов — это полчаса ожиданий между посылками, и
делать её в потоке бота значит на полчаса занять того, кто в этот
момент платит. Панель шлёт сама, своим потоком, через тот же токен.

Темп жёсткий: телеграм пускает около тридцати сообщений в секунду на
бота, но это потолок для ВСЕГО бота, а не для рассылки. Берём пятую
часть — четыре в секунду: остальное остаётся живым клиентам, которые
в эту минуту жмут кнопки.
"""
import json
import os
import threading
import time
import urllib.error
import urllib.request

ТОКЕН = os.environ.get("ROCKET_BOT_TOKEN", "")
API = "https://api.telegram.org/bot" + ТОКЕН

# Сообщений в секунду. См. шапку: это доля от потолка бота, а не сам
# потолок — живой клиент важнее скорости рассылки.
В_СЕКУНДУ = 4.0

# Коды, после которых адресата больше не трогаем: человек заблокировал
# бота или удалил аккаунт. Это не сбой сети, повторять бессмысленно.
МЁРТВЫЕ = ("bot was blocked", "user is deactivated", "chat not found",
           "bot can't initiate conversation")


def _телеграм(метод, **поля):
    данные = json.dumps(поля).encode()
    зап = urllib.request.Request(f"{API}/{метод}", data=данные,
                                 headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(зап, timeout=30) as о:
            return json.loads(о.read())
    except urllib.error.HTTPError as e:
        try:
            return json.loads(e.read())
        except Exception:                               # noqa: BLE001
            return {"ok": False, "description": f"http {e.code}"}
    except Exception as e:                              # noqa: BLE001
        return {"ok": False, "description": str(e)[:200]}


def написать(кому, текст):
    """Одно сообщение человеку. (получилось, «насмерть»)."""
    о = _телеграм("sendMessage", chat_id=кому, text=текст,
                  parse_mode="HTML", disable_web_page_preview=True)
    if о.get("ok"):
        return True, False
    беда = (о.get("description") or "").lower()
    return False, any(м in беда for м in МЁРТВЫЕ)


# ---------- поддержка ----------

def ответить(store, кому, текст, приставка="Ответ поддержки:"):
    """Ответ владельца человеку. Пишем в базу только то, что дошло:
    иначе в переписке остаются наши реплики, которых человек не видел,
    и следующий разговор идёт мимо."""
    ушло, насмерть = написать(кому, f"<b>{приставка}</b>\n\n{текст}")
    if ушло:
        store.поддержка_записать(кому, "мы", текст)
    return ушло, насмерть


# ---------- рассылка ----------

_ИДЁТ = {"ид": None, "всего": 0, "дошло": 0, "отказ": 0}


def состояние():
    return dict(_ИДЁТ)


def разослать(store, текст, кому="всем"):
    """Завести рассылку и погнать её в отдельном потоке.

    Возвращает (ид, сколько адресатов). Вторая рассылка поверх идущей
    не заводится: две очереди на один токен — это удвоенный темп и
    мгновенный бан на посылки.
    """
    if _ИДЁТ["ид"]:
        raise RuntimeError("рассылка уже идёт")
    адресаты = store.рассылка_кому(кому)
    ид = store.рассылка_завести(текст, кому)
    store.рассылка_итог(ид, всего=len(адресаты), состояние="идёт")
    _ИДЁТ.update({"ид": ид, "всего": len(адресаты), "дошло": 0, "отказ": 0})
    threading.Thread(target=_гнать, args=(store, ид, текст, адресаты),
                     daemon=True).start()
    return ид, len(адресаты)


def _гнать(store, ид, текст, адресаты):
    дошло = отказ = 0
    пауза = 1.0 / В_СЕКУНДУ
    try:
        for i, кому in enumerate(адресаты, 1):
            ушло, насмерть = написать(кому, текст)
            if ушло:
                дошло += 1
            else:
                отказ += 1
                if насмерть:
                    # Человек выгнал бота. Это не «не дошло сегодня», а
                    # «больше не дойдёт никогда» — снимаем с рассылок,
                    # чтобы каждая следующая не билась о него снова.
                    store.заблокировать(кому, True)
            _ИДЁТ.update({"дошло": дошло, "отказ": отказ})
            if i % 25 == 0:
                store.рассылка_итог(ид, дошло=дошло, отказ=отказ)
            time.sleep(пауза)
        store.рассылка_итог(ид, дошло=дошло, отказ=отказ, состояние="готова")
    except Exception as e:                              # noqa: BLE001
        print("рассылка оборвалась:", str(e)[:200], flush=True)
        store.рассылка_итог(ид, дошло=дошло, отказ=отказ,
                            состояние="оборвана")
    finally:
        _ИДЁТ["ид"] = None


# ---------- то, что показывает панель ----------

def по_дням(пары, дней):
    """Дополнить ряд нулями до полного числа дней, старые первыми.

    База отдаёт только дни, в которые что-то было. График по таким
    дырявым рядам врёт дважды: пустой день исчезает, и «вчера» с
    «месяц назад» встают рядом. А один-единственный день рисуется во
    весь холст и читается как рекорд.
    """
    было = dict(пары)
    сегодня = time.time()
    ряд = []
    for шаг in range(дней - 1, -1, -1):
        д = time.strftime("%Y-%m-%d", time.gmtime(сегодня - шаг * 86400))
        ряд.append((д, было.get(д, 0)))
    return ряд


def срез(store, pricing, catalog, дней=30):
    """Всё для главного экрана одним ответом."""
    д = store.сводка_панели(дней)
    for поле in ("деньги_по_дням", "работы_по_дням", "новые_по_дням"):
        д[поле] = по_дням(д[поле], дней)
    д["топ_кнопок"] = [{"ключ": к, "сколько": n,
                        "имя": _имя_кнопки(catalog, к)}
                       for к, n in store.топ_кнопок(дней)]
    д["визиты_по_дням"] = по_дням(store.события_по_дням(дней, "вход"), дней)
    д["рассылка"] = состояние()
    д["коин_в_рублях"] = round(pricing.rub_per_coin(), 1)
    return д


# Кнопки, за которыми нет ни сценария, ни узла каталога. Без этого в
# «чаще всего нажимают» стояли сырые `m:menu` и `pay:stars:p3` — след
# для отладки, а не ответ на вопрос владельца, куда ходят люди.
СВОИ_ИМЕНА = {
    "m:menu": "Главное меню", "m:lang": "Смена языка",
    "m:pay": "Экран оплаты", "m:works": "Мои работы",
    "m:cab": "Кабинет", "m:ref": "Позвать друзей",
    "m:prices": "Цены", "fig": "Выбор фигуры",
    "pay": "Способ оплаты", "undo": "Убрать снимок",
    "own": "Свой промпт", "pop": "Популярное",
}


def _имя_кнопки(catalog, ключ):
    """«sc:un_three» -> «Поставить раком». В следе лежит сырое `data`
    нажатия, и владельцу оно ничего не говорит."""
    ключ = ключ or ""
    if ключ in СВОИ_ИМЕНА:
        return СВОИ_ИМЕНА[ключ]
    if ":" not in ключ:
        return СВОИ_ИМЕНА.get(ключ, ключ)
    голова, хвост = ключ.split(":", 1)
    if голова in СВОИ_ИМЕНА:
        return СВОИ_ИМЕНА[голова]
    хвост = хвост.split(":")[0]
    if голова in ("sc", "go", "run", "pl"):
        try:
            return catalog.scene(хвост).title
        except KeyError:
            return хвост
    if голова in ("cat", "sub", "nd"):
        try:
            return catalog.узел(хвост).title
        except KeyError:
            return хвост
    if голова == "buy":
        return "покупка " + хвост
    return ключ


def услуги(pricing, catalog):
    """Ступени оплаты и цены видов работ — для раздела «Услуги»."""
    пакеты = [{"ид": p["id"], "коинов": p["coins"], "рублей": p["rub"],
               "рынок": p.get("market_rub"),
               "скидка": pricing.скидка(p["id"]),
               "за_коин": round(p["rub"] / p["coins"], 1),
               "скрыт": catalog.скрыт("pack:" + p["id"])}
              for p in pricing.PACKS]
    работы = [{"ключ": j.key, "имя": j.title, "коинов": j.coins}
              for j in pricing.В_ПРОДАЖЕ]
    return {"пакеты": пакеты, "работы": работы}
