# -*- coding: utf-8 -*-
"""Мост админки к двум заслонам бота: слова и проверка снимка.

## Зачем отдельный модуль

Раздел «Запрет слов» уже жил в админке и был убран 26.09.2026: панель
импортировала `запрет` прямо в шапке, падала при запуске и отдавала
502. Пропал не только этот раздел - легла вся админка, вместе со
сводкой, людьми и оплатами.

Отсюда правило, ради которого этот файл и существует: **чужой модуль
не имеет права ронять панель**. Он поднимается лениво, в момент
запроса, и любая его беда превращается в понятную строку на экране, а
не в 502 на весь кабинет.

Оба заслона живут в боте, там же где работают:

    bot/запрет.py         слова в запросе
    bot/возраст_фото.py   сам присланный снимок

Админка их не дублирует, она показывает и правит. Второй источник
правды означал бы, что однажды они разойдутся, и заслон на экране
будет не тем, что стоит в двери.
"""
import json
import os

БОТ = os.environ.get("AMBERRY_BOT_DIR", "/opt/amberry/rocket-panel/bot")
ЖУРНАЛ = os.environ.get("AMBERRY_AGE_LOG",
                        "/srv/amberry/журнал_возраста.jsonl")


def _модуль(имя):
    """Модуль бота или None. Своим путём, не трогая общий sys.path."""
    import importlib.util
    п = os.path.join(БОТ, f"{имя}.py")
    if not os.path.exists(п):
        return None
    try:
        # Каталог бота нужен в путях: модули бота импортируют друг
        # друга по коротким именам.
        import sys
        if БОТ not in sys.path:
            sys.path.insert(0, БОТ)
        спец = importlib.util.spec_from_file_location(имя, п)
        м = importlib.util.module_from_spec(спец)
        спец.loader.exec_module(м)
        return м
    except Exception as e:                              # noqa: BLE001
        print(f"модуль {имя} не поднялся:", str(e)[:200], flush=True)
        return None


# ------------------------------------------------------------ слова

def слова_состояние():
    м = _модуль("запрет")
    if м is None:
        return {"есть": False, "почему": "модуль запрета не читается"}
    try:
        с = м.состояние()
        базовые = с.get("базовые")
        return {"есть": True, "слова": с.get("слова", []),
                "исключения": с.get("исключения", []),
                "базовые": базовые if isinstance(базовые, list) else [],
                "взрослый_с": с.get("взрослый_с"),
                "как_базовые": с.get("как_базовые")}
    except Exception as e:                              # noqa: BLE001
        return {"есть": False, "почему": str(e)[:200]}


def слова_записать(слова, исключения):
    м = _модуль("запрет")
    if м is None:
        raise RuntimeError("модуль запрета не читается")
    м.записать(list(слова or []), list(исключения or []))
    return слова_состояние()


def слова_базовые():
    м = _модуль("запрет")
    if м is None:
        raise RuntimeError("модуль запрета не читается")
    м.вернуть_базовые()
    return слова_состояние()


def слова_проверить(текст):
    """Прогнать текст через живой заслон. Это не украшение: владелец
    правит список и должен видеть на своём примере, ловится он или
    нет, не гоняя бота."""
    м = _модуль("запрет")
    if м is None:
        return {"есть": False, "почему": "модуль запрета не читается"}
    плохо, что = м.нельзя(str(текст or ""))
    return {"есть": True, "нельзя": bool(плохо), "нашлось": что}


# ------------------------------------------------------- снимок

def фото_состояние():
    """Настройки заслона снимков плюс сводка по журналу.

    Журнал читается с конца: он растёт вечно, а показать надо
    последнее. Три тысячи строк с конца это заведомо больше, чем
    поместится на экран, и заведомо меньше, чем весь файл на диске.
    """
    м = _модуль("возраст_фото")
    итог = {"есть": м is not None}
    if м is not None:
        модели = []
        try:
            модели = list(м.СУДЬИ)
        except Exception:                               # noqa: BLE001
            pass
        итог.update({
            "включён": м.включён(),
            "порог": м.ПОРОГ,
            "взрослый_с": м.ВЗРОСЛЫЙ_С,
            "спорно_от": м.СПОРНО_ОТ,
            "спорно_до": м.СПОРНО_ДО,
            "модели": модели,
            "поля": list(getattr(м, "ПОЛЯ_НАБОР", ())),
        })
    итог["журнал"] = журнал_срез()
    return итог


def журнал_срез(сколько=40):
    """(всего, принято, отбито, последние). Файла нет - нули, не ошибка:
    заслон мог просто ещё ни разу не сработать."""
    строки = []
    try:
        with open(ЖУРНАЛ, "rb") as ф:
            ф.seek(0, os.SEEK_END)
            хвост = min(ф.tell(), 600_000)
            ф.seek(ф.tell() - хвост)
            куски = ф.read().decode("utf-8", "ignore").splitlines()
        # Первая строка хвоста может быть обрезана посередине.
        for с in куски[1:] if хвост >= 600_000 else куски:
            с = с.strip()
            if not с:
                continue
            try:
                строки.append(json.loads(с))
            except ValueError:
                continue
    except OSError:
        return {"всего": 0, "принято": 0, "отбито": 0, "последние": []}
    принято = sum(1 for з in строки if з.get("принят"))
    return {"всего": len(строки), "принято": принято,
            "отбито": len(строки) - принято,
            "последние": строки[-сколько:][::-1]}
