#!/usr/bin/env python3
"""Каналы для закупки рекламы AMBERRY: аудит и оценка цены.

Откуда список. Рейтинги TGStat по категориям «Для взрослых»,
«Эротика», «Юмор и развлечения» (публичные русские каналы от 50 000
подписчиков), плюс каналы, которые назвал владелец. Отбор ручной:
военные, новостные, детские, женские и каналы-«сливы» (интим реальных
людей без их согласия) выкинуты - там нашей аудитории нет, либо
соседство с таким контентом бьёт по нам.

Как проверяется «живая аудитория». По публичной ленте t.me/s/<канал>:
    средний просмотр поста старше суток  ->  охват
    охват / подписчики                     ->  ERR (вовлечённость)
    разброс просмотров                     ->  ровные = накрутка
    дата последнего поста                  ->  жив ли канал
У части 18+ каналов телеграм ленту наружу не показывает - там охват
берётся из рейтинга TGStat, и это помечено.

Цена - ОЦЕНКА по CPM рынка (цена за тысячу просмотров), а не прайс
канала: 18+ ~250 ₽, юмор ~400 ₽. Реальную цену называет админ.

    python3 оценка.py             пересобрать каналы.json из свежих лент
"""
import json, os, re, sys

ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ТУТ)

CPM = {"18+ и эротика": 250, "Мужской юмор и двач": 400, "Сетка Топора": 400}
CTR = 0.01          # переходов в бота на просмотр поста - осторожная оценка

# Цены, которые известны точно, а не по CPM.
# Пусто: у Telega.in есть прайс «Топор 18+» (1,2 млн ₽), но это другой
# канал сетки, не @toporlive, - переносить его сюда нельзя.
ИЗВЕСТНО = {}

# Карточки биржи Telega.in по нику канала (собираются отдельно, см.
# биржа.json): цена «от», совпадает ли канал, принимает ли заявки.
try:
    БИРЖА = json.load(open(os.path.join(ТУТ, "биржа.json"), encoding="utf-8"))
except (OSError, ValueError):
    БИРЖА = {}


def число(s):
    s = str(s or "").replace(",", ".").strip()
    m = re.match(r"([\d.]+)\s*([kKmM]?)", s)
    if not m:
        return 0
    return int(float(m.group(1)) * {"": 1, "k": 1e3, "K": 1e3, "m": 1e6, "M": 1e6}[m.group(2)])


def оценить(r):
    охват = r.get("avg") or 0
    источник = "лента канала"
    if not охват and r.get("reach_tgstat"):
        охват, источник = число(r["reach_tgstat"]), "TGStat (лента закрыта)"
    подп = r.get("subs") or 0
    err = охват / подп * 100 if подп else 0
    плохо, так_себе, хорошо = [], [], []
    if err < 2:
        плохо.append("читают меньше 2% подписчиков - база мёртвая или накрученная")
    elif err < 4:
        так_себе.append("вовлечённость низкая, %.1f%%" % err)
    elif err <= 60:
        хорошо.append("вовлечённость %.0f%% - аудитория смотрит" % err)
    else:
        так_себе.append("просмотров больше, чем обычно бывает (%.0f%%): посты разлетаются "
                        "репостами или охват подкручен" % err)
    cv = r.get("cv")
    if cv is not None and cv < 0.04 and (r.get("n") or 0) >= 10:
        так_себе.append("просмотры подозрительно ровные - проверить на накрутку")
    elif cv is not None and cv >= 0.1:
        хорошо.append("просмотры живые, скачут от поста к посту")
    ч = r.get("last_h")
    if ч is not None and ч > 72:
        так_себе.append("последний пост %d дн. назад" % (ч // 24))
    elif ч is not None:
        хорошо.append("постит регулярно, %s в день" % r.get("per_day"))
    if источник.startswith("TGStat"):
        так_себе.append("лента скрыта телеграмом, охват по TGStat")
    вердикт = "рискованный" if плохо else ("с оговорками" if так_себе else "живой")

    цена, откуда = ИЗВЕСТНО.get(r["u"], (None, None))
    if not цена:
        цена = max(1000, round(охват * CPM[r["group"]] / 1000 / 500) * 500)
        откуда = "оценка по CPM %d ₽" % CPM[r["group"]]
    # КАК КУПИТЬ. Сначала биржа Telega.in - там сделка с гарантией и
    # оплатой сразу, но только если карточка биржи - ЭТОТ канал (по нику
    # там бывает чужой, мелкий) и он принимает заявки. Дальше - люди:
    # контакт из рекламной строки надёжнее ника из описания.
    купить = []
    б = БИРЖА.get(r["u"])
    if б and б.get("совпадает"):
        купить.append({"вид": "биржа", "url": б["url"], "цена": б["от"],
                       "принимает": not б.get("не_принимает")})
        цена, откуда = б["от"], ("цена Telega.in" + ("" if not б.get("не_принимает")
                                                   else ", заявки сейчас закрыты"))
    рекл = r.get("ad_contacts") or []
    for н in рекл[:3]:
        купить.append({"вид": "бот рекламы" if н.lower().endswith("bot") else "рекламный контакт",
                       "ник": н})
    for н in (r.get("contacts") or []):
        if н not in рекл and len(купить) < 4:
            купить.append({"вид": "бот" if н.lower().endswith("bot") else "админ из описания",
                           "ник": н})
    контакты = [к["ник"] for к in купить if "ник" in к]
    return {
        "u": r["u"], "название": r.get("title") or r["u"], "группа": r["group"],
        "подписчиков": подп, "охват": охват, "err": round(err, 1),
        "источник": источник, "постов_в_день": r.get("per_day"),
        "вердикт": вердикт, "плохо": плохо, "так_себе": так_себе, "хорошо": хорошо,
        "цена": цена, "цена_откуда": откуда,
        "переходов": int(охват * CTR),
        "контакты": контакты[:4], "купить": купить,
        "описание": (r.get("desc") or "")[:300],
    }


if __name__ == "__main__":
    сырьё = json.load(open(sys.argv[1])) if len(sys.argv) > 1 else None
    if сырьё is None:
        raise SystemExit("нужен файл сырого аудита (см. лента.py)")
    итог = [оценить(r) for r in сырьё if (r.get("subs") or 0) >= 50000]
    # Без единого способа связаться канал бесполезен: купить в нём
    # рекламу нельзя, сколько бы живых людей его ни читало.
    выкинуты = [к["u"] for к in итог if not к["купить"]]
    итог = [к for к in итог if к["купить"]]
    print("без контакта, убраны:", выкинуты)
    порядок = {"живой": 0, "с оговорками": 1, "рискованный": 2}
    итог.sort(key=lambda к: (порядок[к["вердикт"]], -к["охват"]))
    json.dump({"собрано": __import__("time").strftime("%d.%m.%Y"), "каналы": итог},
              open(os.path.join(ТУТ, "каналы.json"), "w"), ensure_ascii=False, indent=1)
    from collections import Counter
    print(len(итог), Counter(к["вердикт"] for к in итог))
