#!/usr/bin/env python3
"""Кого можно рекламировать, а кого нельзя: разбор лент каналов.

Два вопроса к каждому каналу, и оба решают судьбу закупки.

**Возьмут ли 18+.** Надёжный ответ один: канал УЖЕ ставил такую рекламу.
Ищем в ленте посты с рекламной пометкой и рядом - приметы нашей ниши
(бот, который раздевает или оживляет фото, нейросеть «для взрослых»).
Нашли - «брал 18+», это лучший признак, какой можно получить не
спрашивая админа.

**Возраст аудитории по тексту НЕ определяется, и мы этого не делаем.**
Первая версия считала слова «школа», «ЕГЭ», «уроки» - и записала в
запрещённые научпоп про людей, где эти слова стоят в научном тексте, а
молодёжные видеоканалы пропустила: у них текста почти нет. Догадка,
выданная за факт, тут стоит дороже пустой клетки: по ней либо не купят
хороший канал, либо купят подростковый. Поэтому возраст решает человек,
глядя на канал, а разбор даёт ему цифры, а не приговор.

Итог - уровень допуска:
    можно      канал уже брал 18+ рекламу или сам 18+ по теме
    спросить   всё остальное: ответ знает только админ канала
"""
import json, os, re, sys, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from лента import get, txt

РЕКЛАМА = re.compile(r"#реклама|erid|реклам\w*|партнёрск|по вопросам рекл", re.I)
НАША_НИША = re.compile(r"раздева|разде́|оживля|нейросет\w* .{0,20}(фото|девуш)|"
                       r"18\+ ?бот|бот .{0,15}18\+|undress|deepnude|нюдс|"
                       r"эротик|интим|секс-?бот|порно", re.I)
# Приметы взрослой аудитории. Это НЕ пропуск и не запрет, а цифра в
# помощь человеку: канал, где говорят про ипотеку, работу и 18+, скорее
# взрослый. Обратное не работает: молчание о взрослом ничего не значит.
ВЗРОСЛОЕ = re.compile(r"\b18\+|🔞|\bдля взрослых\b|\bалкогол|\bвиски\b|"
                      r"ипотек|зарплат|\bработ\w* в офис|\bжена\b|\bмуж\b", re.I)


def разобрать(u, страниц=6):
    посты, до = [], None
    for _ in range(страниц):
        s = get("https://t.me/s/%s%s" % (u, "?before=%d" % до if до else ""))
        if not s:
            break
        куски = re.findall(r'tgme_widget_message_text[^>]*>(.*?)</div>', s, re.S)
        посты += [txt(к) for к in куски]
        ид = [int(x) for x in re.findall(r'data-post="[^/]+/(\d+)"', s)]
        if not ид or (до and min(ид) >= до):
            break
        до = min(ид)
    if not посты:
        return {"постов": 0, "брал_18": 0, "взрослое": 0}
    return {"постов": len(посты),
            "брал_18": sum(1 for п in посты
                           if РЕКЛАМА.search(п) and НАША_НИША.search(п)),
            "взрослое": sum(1 for п in посты if ВЗРОСЛОЕ.search(п))}


def уровень(к, р):
    """Уровень допуска и одной строкой почему."""
    if р["брал_18"]:
        return "можно", "уже ставил рекламу 18+ (%d раз в ленте)" % р["брал_18"]
    if к["группа"] == "18+ и эротика":
        return "можно", "канал сам 18+ по теме"
    if not р["постов"]:
        return "спросить", "лента закрыта: проверить нечем, спросить админа"
    взр = р["взрослое"]
    хвост = (", в ленте %d упоминаний взрослых тем" % взр) if взр else ""
    return "спросить", "18+ рекламы в ленте не видно%s" % хвост


if __name__ == "__main__":
    путь = os.path.join(os.path.dirname(os.path.abspath(__file__)), "каналы.json")
    д = json.load(open(путь))
    import concurrent.futures as cf
    with cf.ThreadPoolExecutor(6) as ex:
        разборы = dict(zip([к["u"] for к in д["каналы"]],
                           ex.map(lambda к: разобрать(к["u"]), д["каналы"])))
    счёт = collections.Counter()
    for к in д["каналы"]:
        р = разборы[к["u"]]
        к["допуск"], к["допуск_почему"] = уровень(к, р)
        к["лента_разбор"] = р
        счёт[к["допуск"]] += 1
    json.dump(д, open(путь, "w"), ensure_ascii=False, indent=1)
    print(счёт)
    for к in д["каналы"]:
        if к["допуск"] != "спросить":
            print(" ", к["допуск"], к["u"], "-", к["допуск_почему"])
