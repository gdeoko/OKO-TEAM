#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Конвейер жилы: просмотреть ВСЁ общественное достояние цветной эпохи.

Два сита подряд по всему списку, а не по десятку лент, выбранных вручную:

    1. маска кожи по миниатюрам archive.org (дёшево, локально)
    2. взгляд модели на то, что прошло (молодая, одета, чувственно)

На выходе - очередь сцен с временными метками: `очередь.json`. Формат 4
кормится из неё, а не из ручного поиска. Это и есть жила: не один фильм,
а перечень всего годного, что лежит в общественном достоянии.

Считается долго (часы), поэтому продолжает с места: уже просмотренные
ленты пропускаются по кэшу.

    python3 жила_полная.py [от] [до] [сколько]
"""
import json
import os
import sys

ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ТУТ)
import золотая_жила as Ж                                      # noqa: E402
import взгляд as В                                            # noqa: E402

МИН_ГОРЯЧИХ = 3        # меньше - лента даже до модели не доходит

# С 1978 года копирайт в США встаёт сам, без пометки и продления, и
# «public domain» в карточке archive.org - это слово загрузчика, а не
# факт. В выдаче такие ленты попадаются (испанское softcore 1981-83), и
# кожи в них много. В очередь они идут с меткой: брать в ролик только
# после проверки прав руками.
ГОД_БЕЗ_ДОВЕРИЯ = 1978


def сомнительна(год):
    try:
        return int(str(год)[:4]) >= ГОД_БЕЗ_ДОВЕРИЯ
    except Exception:
        return True


def главное(от=1955, до=1985, сколько=960):
    ленты = Ж.кандидаты(от, до, сколько)
    print("лент в списке: %d" % len(ленты), flush=True)
    имена = {д["identifier"]: д for д in ленты}

    # Сито 1: кожа
    первое = []
    for i, ид in enumerate(имена, 1):
        о = Ж.оценить(ид)
        if о and о["горячих"] >= МИН_ГОРЯЧИХ:
            первое.append(о)
        if i % 25 == 0:
            print("  кожа: %d из %d, прошло %d" % (i, len(имена), len(первое)),
                  flush=True)
    print("после маски кожи: %d лент" % len(первое), flush=True)

    # Сито 2: взгляд
    очередь = []
    for i, о in enumerate(sorted(первое, key=lambda x: -x["горячих"]), 1):
        путь = os.path.join(В.ОТВЕТЫ, о["ид"] + ".json")
        if os.path.exists(путь):
            с = json.load(open(путь, encoding="utf-8"))
        else:
            с = В.оценить(о["ид"])
        if not с:
            continue
        if с["годных"] >= 2:
            д = имена.get(о["ид"], {})
            очередь.append({"ид": о["ид"], "год": д.get("year", "?"),
                            "название": str(д.get("title", ""))[:60],
                            "годных": с["годных"], "кадров": с["кадров"],
                            "права_проверить": сомнительна(д.get("year")),
                            "кадры": с.get("секунды", [])})
            print("  ЖИЛА %-40s %-5s годных %2d" % (о["ид"][:40],
                  д.get("year", "?"), с["годных"]), flush=True)
        if i % 20 == 0:
            print("  взгляд: %d из %d" % (i, len(первое)), flush=True)

    очередь.sort(key=lambda x: -x["годных"])
    with open(os.path.join(ТУТ, "очередь.json"), "w", encoding="utf-8") as ф:
        json.dump(очередь, ф, ensure_ascii=False, indent=1)
    print("\n== ОЧЕРЕДЬ: %d лент, %d сцен ==" % (
        len(очередь), sum(x["годных"] for x in очередь)), flush=True)
    for x in очередь[:30]:
        print("%-42s %-5s %2d  %s" % (x["ид"][:42], x["год"], x["годных"],
              x["название"][:38]), flush=True)
    return очередь


if __name__ == "__main__":
    а = [int(x) for x in sys.argv[1:]]
    главное(*(а or [1955, 1985, 960]))
