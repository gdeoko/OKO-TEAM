#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Прогон настоящей кнопки бота с техпаспортом. Запускать НА сервере бота.

Зачем отдельный прогон, если есть `ролик-снятие/результат.py`. Тот писался
под ролики и по дороге расходится с продуктом в трёх местах сразу, и
каждое из них тихо меняет картинку:

    негатив     результат.py брал `сцена.negative`, а бот строит свой
                через `prompts.негатив(промпт)`. Негатив - ровно то, что
                не даёт дорисовать мужские органы женщине.
    опора       панель берёт её ПОЛЕМ ЗАПРОСА `опора`. Не послали - она
                считает без опоры, а по замерам владельца именно опора
                держит фигуру: без неё тело выходит «как у скелета».
    лора        сила «плоской груди» приходит из выбора человека
                (`prompts.плоскость`), а не из воздуха.

Поэтому здесь ничего своего не пишется: всё берётся из `catalog` и
`prompts`, то есть из того же кода, что обслуживает клиента.

К каждому кадру кладётся техпаспорт: какая кнопка, какой job, какой лист,
какая опора и НАШЛАСЬ ЛИ ОНА НА ДИСКЕ, какая сила лоры, сколько знаков в
промпте и негативе, зерно, denoise. Без паспорта «тут каша» не к чему
привязать.

    python3 проба_кнопки.py ph_close un_full        фото
    python3 проба_кнопки.py ac_close --видео        ролик
"""
import json
import os
import sys
import time

БОТ = "/opt/amberry/rocket-panel/bot"
sys.path.insert(0, БОТ)
ТУТ = os.path.dirname(os.path.abspath(__file__))
ВХОД = os.environ.get("ПРОБА_ВХОД", os.path.join(
    os.path.dirname(ТУТ), "ролик-снятие", "вход-ника-отель-ночь-одежда.jpg"))

import catalog          # noqa: E402
import prompts          # noqa: E402
import gpu              # noqa: E402
import bot as Б         # noqa: E402


def сцены():
    def обойти(узлы):
        for у in узлы:
            for с in (getattr(у, "scenes", None) or []):
                yield с
            for с in обойти(getattr(у, "дети", None) or []):
                yield с
    return {с.key: с for с in обойти(catalog.РАЗДЕЛЫ)}


def опора_на_диске(ключ):
    """Есть ли файл опоры ТАМ, где её ищет панель карты.

    Отдельной проверкой, потому что промах по пути ничего не ломает
    громко: задание считается без опоры и отдаёт кадр, в котором просто
    нет того, за что заплачено. Ровно это и случилось 28.09.2026 -
    опоры лежали в /root/карта/ГЛУБИНА вместо /root/ГЛУБИНА.
    """
    if not ключ:
        return "кнопка без опоры"
    # Спрашиваем саму карту, а не диск сервера бота: опоры лежат НА
    # КАРТЕ, и промах по пути виден только оттуда.
    try:
        import subprocess
        р = subprocess.run(
            ["ssh", "-i", "/root/.ssh/vast_amberry", "-o",
             "StrictHostKeyChecking=no", "-p", os.environ.get("VAST_PORT", ""),
             os.environ.get("VAST_HOST", ""),
             "ls /root/ГЛУБИНА/%s.png" % ключ],
            capture_output=True, text=True, timeout=60)
        return "есть на карте" if р.returncode == 0 else "НЕТ НА КАРТЕ"
    except Exception as e:
        return "не проверено (%s)" % type(e).__name__


def прогнать(ключ, выход=None):
    с = сцены().get(ключ)
    if not с:
        raise SystemExit("нет кнопки %s" % ключ)
    место = __import__("места").КАК_НА_ФОТО if os.path.exists(
        os.path.join(БОТ, "места.py")) else None
    промпт = с.промпт(место=место) if место else с.промпт()
    фото_промпт = (с.prompt_фото(место, None) if место else None) or промпт
    лист = catalog.лист(ключ)
    опора = catalog.опора(ключ)
    цепочка = bool(getattr(с, "двухшаговый", False))
    kind = с.job
    негатив = prompts.негатив(промпт)

    паспорт = {
        "кнопка": ключ, "название": с.title, "job": kind, "лист": лист,
        "опора": опора or "(нет)", "цепочка": цепочка,
        "знаков в промпте": len(промпт), "знаков в негативе": len(негатив),
        "семейство": prompts.семейство(kind),
        "опора на карте": опора_на_диске(опора),
    }
    print(json.dumps(паспорт, ensure_ascii=False, indent=1), flush=True)

    # Грузим тем же путём, что и бот: он сам знает, какая карта сейчас
    # основная и как к ней стучаться.
    фото = Б.отдать_карте([ВХОД])

    начало = time.time()
    if цепочка:
        имя, кадр, _ = Б._фото_с_приёмкой("i2i", фото_промпт, фото,
                                          denoise=1.0, лист=лист, scene=ключ)
        фото = [Б.gpu.upload(имя, кадр)]
        print("  промежуточный кадр готов", flush=True)
    итог = (Б._фото_с_приёмкой(kind, промпт, фото, denoise=1.0, лист=лист,
                               scene=ключ)
            if prompts.семейство(kind) in ("t2i", "i2i")
            else Б._проход(kind, промпт, фото, лист=лист, опора=опора))
    имя, данные, сек = итог[:3]
    выход = выход or os.path.join(ТУТ, "проба-%s-%s" % (ключ, имя))
    with open(выход, "wb") as ф:
        ф.write(данные)
    паспорт["секунд"] = round(сек or (time.time() - начало), 1)
    паспорт["файл"] = выход
    паспорт["байт"] = len(данные)
    print(json.dumps(паспорт, ensure_ascii=False), flush=True)
    return выход


if __name__ == "__main__":
    ключи = [а for а in sys.argv[1:] if not а.startswith("--")]
    if not ключи:
        raise SystemExit(__doc__)
    for к in ключи:
        прогнать(к)
