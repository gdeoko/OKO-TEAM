#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Завод роликов AMBERRY: пять пачек по четыре формата, двадцать в день.

Один вызов - день работы. Пачка это четыре ролика, по одному на формат:

    1  «Реальный показ бота»   ролик-показ/
    2  «Снимает лишнее»        ролик-снятие/     (нужна видеокарта)
    3  «Сток с заголовком»     ролик-сток/
    4  «Кадр из кино»          ролик-кино/

**Реестр держит ролики разными.** Всё израсходованное - лицо, заголовок,
стоковый клип, сцена из фильма, музыкальное семя - ложится в
`завод/реестр.json` и второй раз не берётся. Без него пачки разъезжаются
по одному накатанному пути: та же героиня, тот же текст, тот же трек, и
лента читает это как один повторяющийся ролик.

**Завод не врёт про сделанное.** Ролик, который не собрался, помечается
причиной и в отчёт идёт как несобранный, а не пропускается молча: иначе
«двадцать в день» превращается в двенадцать, и никто этого не замечает.

    python3 завод.py [пачек]            # по умолчанию 5
    python3 завод.py 1 --формат 4       # одна пачка, только формат 4
"""
import datetime
import json
import os
import random
import subprocess
import sys

ТУТ = os.path.dirname(os.path.abspath(__file__))
ЗАВОД = os.path.join(ТУТ, "завод")
РЕЕСТР = os.path.join(ЗАВОД, "реестр.json")
ЛИЦА = ["ника", "мира", "ева", "юки", "сая"]
ФОРМАТЫ = [1, 2, 3, 4]

# ДЕНЬГИ ЗАВОД САМ НЕ ТРАТИТ. Форматы 1 и 2 растут из генераций: кадры
# сцены делает APIMODELS, движение - наша карта. И то и другое платное, а
# правило владельца на этот счёт одно - спрашивать каждый раз. Поэтому
# генерация включается только ключом --платно; без него формат честно
# помечается несобранным, и в отчёте видно, чего не хватило.
ПЛАТНО = False


def реестр():
    if os.path.exists(РЕЕСТР):
        with open(РЕЕСТР, encoding="utf-8") as ф:
            return json.load(ф)
    return {"лица": [], "заголовки": [], "стоки": [], "сцены": [], "семена": []}


def записать_реестр(р):
    os.makedirs(ЗАВОД, exist_ok=True)
    with open(РЕЕСТР, "w", encoding="utf-8") as ф:
        json.dump(р, ф, ensure_ascii=False, indent=1)


def свежее(р, раздел, кандидаты):
    """Первое, чего ещё не брали. Кончились - берём самое давнее."""
    было = set(р.get(раздел, []))
    для_нас = [к for к in кандидаты if к not in было]
    return (для_нас or кандидаты)[0] if кандидаты else None


def пометить(р, раздел, значение):
    if значение is None:
        return
    р.setdefault(раздел, [])
    if значение in р[раздел]:
        р[раздел].remove(значение)
    р[раздел].append(значение)          # самое свежее - в конец


def папка_дня():
    д = os.path.join(ЗАВОД, datetime.date.today().isoformat())
    os.makedirs(д, exist_ok=True)
    return д


# ── ФОРМАТ 4: КАДР ИЗ КИНО ──────────────────────────────────────────────
КИНО = os.path.join(ТУТ, "ролик-кино")
ОЧЕРЕДЬ = os.path.join(КИНО, "очередь.json")
ОТРЕЗОК_С = 42.0          # длина куска фильма в ролике


def секунда_кадра(ид, номер, длина):
    """Номер миниатюры archive.org - ЭТО СЕКУНДА фильма, а не кадр.

    Имя файла выглядит как номер кадра (`_000600.jpg`), и я сперва счёл
    его таким: делил на наибольший номер и брал долю от длины. Вышло мимо
    - отрезок попал на базарную площадь вместо сцены. Сверка расставила
    всё по местам: у ленты 93 миниатюры, наибольший номер 5530, а сама
    она идёт 5531 секунду. Номер и есть секунда.

    Долевой расчёт врал ещё и потому, что наибольший номер брался из
    КЭША, а в кэш кладётся лишь выборка миниатюр - её последняя обрывается
    задолго до конца фильма.
    """
    return min(float(номер), max(0.0, длина - 1))


def формат4(р, куда, имя):
    sys.path.insert(0, КИНО)
    import проверить_цвет as Ц
    import раскадровка as Р
    import сборка_кино as С
    import urllib.parse

    if not os.path.exists(ОЧЕРЕДЬ):
        return None, "очереди нет: сперва python3 ролик-кино/жила_полная.py"
    with open(ОЧЕРЕДЬ, encoding="utf-8") as ф:
        очередь = json.load(ф)
    # Ленты с непроверенными правами завод не берёт САМ. Их метит
    # жила_полная: с 1978 года «public domain» в карточке archive.org -
    # слово загрузчика, а не факт, и ошибка тут стоит иска.
    годные = [x for x in очередь if not x.get("права_проверить") and x.get("кадры")]
    if not годные:
        return None, "в очереди нет лент с проверенными правами"

    взятые = set(р.get("сцены", []))
    выбор = None
    for лента in годные:
        for кадр in лента["кадры"]:
            метка = "%s:%d" % (лента["ид"], кадр)
            if метка not in взятые:
                выбор = (лента, кадр, метка)
                break
        if выбор:
            break
    if not выбор:
        return None, "все сцены очереди уже разобраны"
    лента, кадр, метка = выбор

    фильм = os.path.join(КИНО, "фильмы", лента["ид"] + ".mp4")
    os.makedirs(os.path.dirname(фильм), exist_ok=True)
    if not os.path.exists(фильм):
        файл, _ = Ц.лучший_файл(лента["ид"])
        if not файл:
            return None, "у ленты %s нет mp4" % лента["ид"]
        url = "https://archive.org/download/%s/%s" % (
            лента["ид"], urllib.parse.quote(файл))
        subprocess.run(["curl", "-sL", "-o", фильм, url], check=True)

    длина = Р.длительность(фильм)
    начало = max(0.0, min(длина - ОТРЕЗОК_С - 1,
                          секунда_кадра(лента["ид"], кадр, длина) - 2.0))
    отрезок = os.path.join(КИНО, "отрезки", "%s.mp4" % имя)
    os.makedirs(os.path.dirname(отрезок), exist_ok=True)
    subprocess.run([Р.ffmpeg(), "-y", "-hide_banner", "-loglevel", "error",
                    "-nostdin", "-ss", "%.2f" % начало, "-i", фильм,
                    "-t", "%.2f" % ОТРЕЗОК_С, "-c:v", "libx264", "-crf", "17",
                    "-preset", "fast", "-c:a", "aac", "-b:a", "160k",
                    отрезок], check=True)
    выход = os.path.join(куда, имя + ".mp4")
    С.собрать(отрезок, выход, семя=имя)
    пометить(р, "сцены", метка)
    return выход, "%s, %s, с %d:%02d" % (лента["ид"][:28], лента.get("год", "?"),
                                         int(начало)//60, int(начало) % 60)


# ── ФОРМАТ 3: СТОК С ЗАГОЛОВКОМ ─────────────────────────────────────────
СТОК = os.path.join(ТУТ, "ролик-сток")
ТЕКСТЫ = os.path.join(ТУТ, "тексты")


def заголовок(р, стадия="tofu"):
    """Свежий заголовок с оценкой. Повтор в ленте читается как спам."""
    sys.path.insert(0, ТЕКСТЫ)
    import заголовки as З
    # пачка() отдаёт словари {текст, механика, балл}, уже с оценкой.
    варианты = З.пачка("сток", стадия, семя=str(random.random()), сколько=9)
    порядок = [в["текст"] for в in sorted(варианты, key=lambda в: -в["балл"])]
    т = свежее(р, "заголовки", порядок)
    пометить(р, "заголовки", т)
    return т


def формат3(р, куда, имя):
    sys.path.insert(0, СТОК)
    import поиск_движение as П
    import сборка_стока as С

    запас = os.path.join(СТОК, "кандидаты")
    файлы = sorted(f for f in os.listdir(запас)
                   if f.endswith(".mp4")) if os.path.isdir(запас) else []
    if not файлы:
        П.собрать(12)
        файлы = sorted(f for f in os.listdir(запас) if f.endswith(".mp4"))
    клип = свежее(р, "стоки", файлы)
    if not клип:
        return None, "сток не нашёлся"
    т = заголовок(р)
    выход = os.path.join(куда, имя + ".mp4")
    С.собрать(os.path.join(запас, клип), т, выход=выход, семя=имя, длина=18.0)
    пометить(р, "стоки", клип)
    return выход, "%s | «%s»" % (клип, т)


# ── ФОРМАТ 1: РЕАЛЬНЫЙ ПОКАЗ БОТА ───────────────────────────────────────
ПОКАЗ = os.path.join(ТУТ, "ролик-показ")
СНЯТИЕ = os.path.join(ТУТ, "ролик-снятие")


def пара_кадров(лицо):
    """Входное фото и результат для экрана бота.

    Пара делается на видеокарте (сцена одетой и та же сцена в купальнике)
    и лежит в ролик-снятие. Нет пары - формат честно не собирается: экран
    бота без настоящего результата показывать нечего.
    """
    вход = sorted(f for f in os.listdir(СНЯТИЕ)
                  if f.startswith("вход-%s-" % лицо) and f.endswith("одежда.jpg"))
    if not вход:
        return None, None
    имя = вход[0]
    пара = имя.replace("одежда.jpg", "купальник.jpg")
    п1 = os.path.join(СНЯТИЕ, имя)
    п2 = os.path.join(СНЯТИЕ, пара)
    return (п1, п2) if os.path.exists(п2) else (п1, None)


def формат1(р, куда, имя):
    лицо = свежее(р, "лица", ЛИЦА)
    вход, результат = пара_кадров(лицо)
    if (not вход or not результат) and ПЛАТНО:
        сцена = random.randrange(len(_сцены()))
        subprocess.run([sys.executable, os.path.join(СНЯТИЕ, "кадр_снятия.py"),
                        лицо, str(сцена)], check=False)
        вход, результат = пара_кадров(лицо)
    if not вход or not результат:
        return None, ("нет пары кадров для «%s»: нужна генерация "
                      "(включается ключом --платно)" % лицо)
    выход = os.path.join(куда, имя + ".mp4")
    subprocess.run([sys.executable, os.path.join(ПОКАЗ, "сборка_ролика.py"),
                    лицо, вход, результат, выход], check=True)
    пометить(р, "лица", лицо)
    return выход, "лицо %s" % лицо


# ── ФОРМАТ 2: СНИМАЕТ ЛИШНЕЕ ────────────────────────────────────────────
def _сцены():
    sys.path.insert(0, СНЯТИЕ)
    import кадр_снятия as К
    return К.СЦЕНЫ


def формат2(р, куда, имя):
    """Генерация: кадры сцены на APIMODELS, движение на нашей карте.

    Весь проход уже собран в `ролик-снятие/сделать.py` - завод его только
    зовёт, со своим лицом и своей сценой. Тот скрипт продолжает с места
    обрыва: готовый шаг заново не считается, поэтому упасть на шестом
    проходе не значит потерять пять предыдущих.
    """
    сделать = os.path.join(СНЯТИЕ, "сделать.py")
    if not os.path.exists(сделать):
        return None, "движка снятия нет"
    if not ПЛАТНО:
        return None, "генерация платная: включается ключом --платно"
    лицо = свежее(р, "лица", ЛИЦА)
    сцены = _сцены()
    номер = random.randrange(len(сцены))
    п = subprocess.run([sys.executable, сделать, лицо, str(номер)],
                       capture_output=True, text=True)
    готовый = os.path.join(СНЯТИЕ, "соцсети-%s-%s.mp4"
                           % (лицо, сцены[номер]["имя"]))
    if not os.path.exists(готовый):
        хвост = (п.stderr or п.stdout or "").strip().splitlines()
        return None, "генерация не дала файла: %s" % (хвост[-1] if хвост else "?")
    выход = os.path.join(куда, имя + ".mp4")
    subprocess.run(["cp", готовый, выход], check=True)
    пометить(р, "лица", лицо)
    return выход, "лицо %s, сцена %s" % (лицо, сцены[номер]["имя"])


СБОРЩИКИ = {1: формат1, 2: формат2, 3: формат3, 4: формат4}


def пачка(номер, куда, р, форматы=ФОРМАТЫ):
    строки = []
    for ф in форматы:
        имя = "п%d-ф%d" % (номер, ф)
        try:
            путь, примечание = СБОРЩИКИ[ф](р, куда, имя)
        except Exception as e:
            путь, примечание = None, "сорвалось: %s: %s" % (type(e).__name__, e)
        строки.append((ф, путь, примечание))
        печать = "готов" if путь else "НЕ СОБРАН"
        print("  пачка %d формат %d: %-9s %s" % (номер, ф, печать, примечание),
              flush=True)
        записать_реестр(р)
    return строки


def главное(пачек=5, форматы=ФОРМАТЫ):
    куда = папка_дня()
    р = реестр()
    всё = []
    for н in range(1, пачек + 1):
        всё += пачка(н, куда, р, форматы)
    собрано = sum(1 for _, п, _ in всё if п)
    print("\n== ИТОГ: %d из %d ==" % (собрано, len(всё)), flush=True)
    for ф, п, прим in всё:
        if not п:
            print("  формат %d не собран: %s" % (ф, прим), flush=True)
    print("папка дня:", куда, flush=True)
    return всё


if __name__ == "__main__":
    а = sys.argv[1:]
    пачек = int(а[0]) if а and а[0].isdigit() else 5
    ф = ФОРМАТЫ
    if "--формат" in а:
        ф = [int(а[а.index("--формат") + 1])]
    if "--платно" in а:
        globals()["ПЛАТНО"] = True
        print("генерация ВКЛЮЧЕНА: форматы 1 и 2 будут тратить кредиты",
              flush=True)
    главное(пачек, ф)
