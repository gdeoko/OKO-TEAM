# -*- coding: utf-8 -*-
"""Слоты дня и постановка в Zernio.

СЛОВО ВЛАДЕЛЬЦА: шесть слотов на пачку в окне 10:00-22:00. Шесть единиц
это четыре ролика, пост и карусель, значит слоты раскладываются РОВНО
по числу единиц, а не по сетке «каждые два часа»: сетка на пяти пачках
дала бы тридцать публикаций в одни и те же минуты, и площадки читают это
как залп.

ПЯТЬ ПАЧЕК РАЗВЕДЕНЫ ПО МИНУТАМ. У пачки свой сдвиг внутри часа, так что
в один момент наружу идёт одна единица, а не пять. Сдвиг считается от
номера пачки, а не случайно: тогда расписание повторяемо и его можно
сверить глазами.

ВРЕМЯ ХРАНИТСЯ В UTC, называется в МСК. Сервер живёт в UTC, человек
читает Москву, и путать это значит однажды выложить в четыре утра.
"""
import datetime, json, os

ОКНО_НАЧАЛО = 10        # МСК
ОКНО_КОНЕЦ = 22         # МСК, включительно - последний слот ровно в 22:00
МСК_СДВИГ = 3           # Москва = UTC+3
РАЗВОД_ПАЧЕК = 7        # минут между пачками внутри одного слота


ПАЧЕК = 5               # сколько пачек разводим внутри окна


def слоты_мск(единиц=6, пачка_номер=0, пачек=ПАЧЕК):
    """Ровные слоты по числу единиц плюс сдвиг пачки.

    СЧЁТ ИДЁТ В МИНУТАХ, а не в часах с дробью. Считая часами, я уже
    получила слоты 22:07-22:28: сдвиг пачки выносил последнюю единицу за
    окно, а заслон сравнивал ЧАСЫ (22 не больше 22) и этого не видел.
    Верх окна поэтому заранее поджат на максимальный сдвиг: у последней
    пачки последний слот попадает ровно в 22:00, у первой раньше, и ни
    одна единица за окно не выходит ПО ПОСТРОЕНИЮ.
    """
    if единиц <= 0:
        return []
    сдвиг = (пачка_номер % max(пачек, 1)) * РАЗВОД_ПАЧЕК
    макс_сдвиг = (max(пачек, 1) - 1) * РАЗВОД_ПАЧЕК
    низ = ОКНО_НАЧАЛО * 60 + сдвиг
    верх = ОКНО_КОНЕЦ * 60 - макс_сдвиг + сдвиг
    if единиц == 1:
        точки = [(низ + верх) // 2]
    else:
        шаг = (верх - низ) / float(единиц - 1)
        точки = [низ + шаг * н for н in range(единиц)]
    итог = []
    for м in точки:
        м = int(round(м))
        м = min(м, ОКНО_КОНЕЦ * 60)     # за окно не выходим никогда
        итог.append((м // 60, м % 60))
    return итог


def слоты_utc(единиц=6, пачка_номер=0, день=None, пачек=ПАЧЕК):
    """То же в UTC, строками ISO - в таком виде их ждёт Zernio."""
    д = день or datetime.date.today()
    итог = []
    for ч, м in слоты_мск(единиц, пачка_номер, пачек):
        мск = datetime.datetime(д.year, д.month, д.day, ч, м)
        итог.append((мск - datetime.timedelta(hours=МСК_СДВИГ)).strftime("%Y-%m-%dT%H:%M:%SZ"))
    return итог


def расписание(пачки, единиц=6, день=None):
    """Полная раскладка дня: пачка -> список времён.

    Сразу видно глазами, что в один момент идёт одна единица.
    """
    д = день or datetime.date.today()
    итог = {}
    for н, п in enumerate(пачки):
        мск = слоты_мск(единиц, н, len(пачки))
        utc = слоты_utc(единиц, н, д, len(пачки))
        итог[п] = [{"мск": "%02d:%02d" % (ч, м), "utc": u}
                   for (ч, м), u in zip(мск, utc)]
    return итог


def занято_ли(расп):
    """Проверка развода: две единицы в одну минуту это залп, а не слот."""
    все = {}
    for пачка, слоты in расп.items():
        for с in слоты:
            все.setdefault(с["utc"], []).append(пачка)
    столкнулись = {в: п for в, п in все.items() if len(п) > 1}
    return {"ок": not столкнулись, "столкновения": столкнулись}


if __name__ == "__main__":
    р = расписание(["ника", "мария", "ева", "юки", "юля"])
    for п, с in р.items():
        print(п, " ".join(x["мск"] for x in с))
    print("развод:", занято_ли(р))
