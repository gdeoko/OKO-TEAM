# -*- coding: utf-8 -*-
"""Обложка становится ПЕРВЫМ КАДРОМ ролика.

ПОЧЕМУ ИМЕННО ТАК. Площадки берут превью с первого кадра сами, поэтому
обложка, лежащая файлом рядом, не видна никому: за неё заплачено, а в
ленте её нет. Отдельным вложением её тоже не цепляют - тогда вместо
одного ролика выходит два элемента, и это уже ловили на ВКонтакте.

КАДР ЗАМЕНЯЕТСЯ, А НЕ ВСТАВЛЯЕТСЯ. Вставка сдвинула бы картинку на одну
тридцатую секунды относительно звука, и на длинном ролике губы и удары
музыки поедут. Замена не двигает ничего, а одного кадра при тридцати в
секунду зритель не замечает.
"""
import os, shutil, subprocess


def ffmpeg():
    return ("/usr/local/bin/ffmpeg" if os.path.exists("/usr/local/bin/ffmpeg")
            else "ffmpeg")


def длина(файл):
    try:
        п = subprocess.run(["ffprobe", "-v", "error", "-show_entries",
                            "format=duration", "-of",
                            "default=nw=1:nk=1", файл],
                           capture_output=True, text=True, timeout=60)
        return float((п.stdout or "0").strip() or 0)
    except Exception:
        return None          # НЕ ЗАМЕРЕНО, и это не ноль


def поставить(ролик, обложка, выход=None):
    """Заменить первый кадр ролика обложкой. Три исхода.

    Длина сверяется ДО и ПОСЛЕ: расхождение больше кадра значит, что мы
    не заменили кадр, а пересобрали ролик другой длины, и такой файл
    наружу не идёт.
    """
    if not os.path.exists(ролик):
        return {"ок": False, "почему": "ролика нет: %s" % ролик}
    if not os.path.exists(обложка):
        return {"ок": False, "почему": "обложки нет: %s" % обложка}
    было = длина(ролик)
    цель = выход or ролик
    врем = цель + ".part.mp4"
    # Обложка подаётся вторым входом и накрывает ровно первый кадр: пока
    # `enable` держит её на первых 1/30 секунды, дальше идёт сам ролик.
    фильтр = ("[1:v]scale=iw:ih[о];[0:v][о]overlay=0:0:"
              "enable='lte(t,0.033)'[v]")
    к = [ffmpeg(), "-y", "-hide_banner", "-loglevel", "error", "-nostdin",
         "-i", ролик, "-i", обложка, "-filter_complex", фильтр,
         "-map", "[v]", "-map", "0:a?", "-c:v", "libx264", "-crf", "18",
         "-preset", "fast", "-pix_fmt", "yuv420p", "-c:a", "copy", врем]
    п = subprocess.run(к, capture_output=True, text=True)
    if not os.path.exists(врем):
        хвост = (п.stderr or "").strip().splitlines()
        return {"ок": False, "почему": "ffmpeg не дал файла: %s"
                % (хвост[-1] if хвост else "молча")}
    стало = длина(врем)
    if было is not None and стало is not None and abs(было - стало) > 0.05:
        os.remove(врем)
        return {"ок": False, "почему": "длина поехала: было %.3f, стало %.3f"
                % (было, стало)}
    os.replace(врем, цель)
    return {"ок": True, "файл": цель, "длина": стало,
            "как": ("длина сошлась" if стало is not None else
                    "длина НЕ ЗАМЕРЕНА (нет ffprobe)")}
