def карусель(з, выход, папка, лента):
    """Слайды карусели. У неё СВОЙ путь, и это не придирка.

    `карусель.py` кладёт слайды В СВОЮ ПАПКУ под своими именами и отдаёт
    их списком - выхода она не принимает вовсе. Общий `сборщиком` ждёт
    файл по заданному пути, не находит его и честно говорит «не дал
    файла» ПОСЛЕ того, как пять слайдов по три цента уже оплачены. Беда
    той породы, где деньги ушли, а код отчитался провалом.

    Поэтому: запускаем, забираем СВЕЖИЕ png из её папки (новее нашего
    старта) и переносим в папку дня. По времени, а не по имени: имена она
    выбирает сама и готовые с прошлых заходов переиспользует.
    """
    if лента is None:
        return {"ок": False, "почему": "дверь ленты не передана: карусели "
                "нужен адрес фото, а не путь"}
    в = лента.выложить(з["фото_дня"])
    if not в.get("ок"):
        return {"ок": False, "почему": "фото дня не выложено: %s" % в.get("почему")}
    ц = round(С.ЦЕНЫ["кадр_2k_high"] * С.СЛАЙДОВ_ГЕНЕРАЦИЕЙ, 4)
    р = _пустить(ц)
    if not р.get("ок"):
        return {"ок": False, "почему": "потолок: %s" % р.get("почему")}
    е, почему = окружение_ленты()
    if е is None:
        return {"ок": False, "почему": почему}
    папка_карусели = os.path.dirname(КАРУСЕЛЬ)
    т0 = time.time()
    п = subprocess.run([sys.executable, КАРУСЕЛЬ, в["адрес"]],
                       capture_output=True, text=True, env=е,
                       cwd=папка_карусели)
    свежие = []
    for имя in sorted(os.listdir(папка_карусели)):
        if not имя.lower().endswith(".png"):
            continue
        путь = os.path.join(папка_карусели, имя)
        try:
            if os.path.getmtime(путь) >= т0 - 1:
                свежие.append(путь)
        except OSError:
            pass
    if not свежие:
        хвост = (п.stderr or п.stdout or "").strip().splitlines()
        return {"ок": False, "почему": "карусель не дала слайдов: %s"
                % (хвост[-1] if хвост else "молча")}
    куда = []
    for н, путь in enumerate(свежие, 1):
        цель = os.path.join(папка, "%s-slide%d.png" % (
            os.path.basename(выход), н))
        with open(путь, "rb") as и, open(цель + ".part", "wb") as ф:
            ф.write(и.read())
        os.replace(цель + ".part", цель)
        куда.append(цель)
    # ШЕСТОЙ СЛАЙД - ВОРОНКА, И СОБИРАЕТ ЕЁ КОД. Смета обещает «5 слайдов
    # плюс финал кодом», а звал его НИКТО: карусель уходила без слайда с
    # призывом, то есть без того единственного места, где у неё воронка.
    # Зовём импортом: у `финал.py` аргументы позиционные, и флаги уехали
    # бы в него путём к файлу. Подложка - СВОЁ фото пачки: жёсткое имя
    # образца на сервере не лежит, и слайд падал бы каждый день.
    финал = os.path.join(папка, os.path.basename(выход) + "-slide%d.png"
                         % (len(куда) + 1))
    try:
        sys.path.insert(0, os.path.dirname(ФИНАЛ_СЛАЙД))
        import importlib.util as _иу
        _с = _иу.spec_from_file_location("финал_слайда", ФИНАЛ_СЛАЙД)
        _м = _иу.module_from_spec(_с)
        _с.loader.exec_module(_м)
        # ЛЕНТА АНГЛИЙСКАЯ ЦЕЛИКОМ, И СЛАЙД ТОЖЕ. Умолчание карточки
        # русское (им пользуется сам бот), а здесь слова задаёт лента.
        # Кнопка говорит ДЕЙСТВИЕ, а не повторяет строку выше: «first
        # photo free» и «first one is free» на одном слайде это одна
        # мысль дважды. Слово то же, что в воронке описаний.
        _м.собрать(финал, "OPEN IN TELEGRAM", len(куда) + 1, len(куда) + 1,
                   кадр=з.get("фото_дня"),
                   заголовок='TRY IT <span class="hi">ON&nbsp;YOUR</span> OWN PHOTO',
                   даром='FIRST PHOTO <span>FREE</span>')
        if os.path.exists(финал):
            куда.append(финал)
        else:
            беда_финала = "финал не дал файла"
    except Exception as е:
        беда_финала = "%s: %s" % (type(е).__name__, str(е)[:80])
    else:
        беда_финала = None
    о = _трата("карусель", ц, None, None, "слайдов %d" % len(куда))
    о.update({"ок": True, "файл": куда[0], "файлы": куда,
              "сек": round(time.time() - т0, 1), "слайдов": len(куда)})
    if беда_финала:
        о["финал"] = "слайда воронки нет: %s" % беда_финала
    return о


# РАЗМЕР НЕ СУДЬЯ, И ЭТО ЗАМЕРЕНО: чёрный ролик на три секунды весит
# 5 КБ, пустой кадр 7.7 КБ - порог в 50 КБ забраковал бы годное и
# отправил его собираться ЗАНОВО, за деньги, то есть сделал бы ровно ту
# беду, от которой написана дверь «было». Порог остался один - «это не
# пустая заготовка», судит ЧИТАЕМОСТЬ.
МАЛО_РОЛИКА = 2 * 1024
МАЛО_КАДРА = 512


def читается(файл):
    """Файл не только ЛЕЖИТ, но и ОТКРЫВАЕТСЯ. Три исхода.

    Обрыв посреди записи оставляет файл, который проходит по РАЗМЕРУ и не
    читается ничем: у ролика нет moov, у png обрезан хвост. Принять такой
    за готовый - значит увезти огрызок в ленту и в канал, а разбираться
    придётся по жалобе человека.

    Третий исход честный: прочитать НЕЧЕМ (нет ffprobe, нет PIL) - мы не
    выдаём файл за годный и не браним его, а говорим словами.
    """
    if not файл or not os.path.exists(файл):
        return False, "файла нет"
    try:
        размер = os.path.getsize(файл)
    except OSError as е:
        return False, "размер не спросился: %s" % е
    низ = str(файл).lower()
    видео = низ.endswith((".mp4", ".mov", ".webm"))
    # ЗВУК СУДИТСЯ СВОИМ СПОСОБОМ, А НЕ КАК КАРТИНКА. Мера смотрит
    # расширение, и без этой ветки трек серии (.mp3) уходил в PIL,
    # честно там не открывался и объявлялся битым - то есть пять
    # оплаченных треков каждый раз покупались заново.
    звук = низ.endswith((".mp3", ".m4a", ".wav", ".aac", ".ogg", ".opus"))
    мало = МАЛО_РОЛИКА if (видео or звук) else МАЛО_КАДРА
    if размер < мало:
        return False, "%d байт, это меньше %d" % (размер, мало)
    if видео or звук:
        try:
            п = subprocess.run(["ffprobe", "-v", "error", "-show_entries",
                                "format=duration", "-of", "csv=p=0", файл],
                               capture_output=True, text=True, timeout=60)
        except (OSError, subprocess.SubprocessError) as е:
            return None, "ffprobe не спросился: %s" % е
        try:
            длина = float((п.stdout or "").strip() or 0)
        except ValueError:
            return False, "ffprobe длины не дал: %s" % (п.stderr or "").strip()[:80]
        if длина <= 0.1:
            return False, "длина %.2f с" % длина
        # ДЕКОДИРУЕМ ФАЙЛ ЦЕЛИКОМ, И ЭТО НЕ ПЕРЕСТРАХОВКА. Длина берётся
        # из moov, и у НАШИХ файлов он лежит в начале: `+faststart` стоит
        # в восьми сборщиках, формат 3 среди них. Значит у обрезанного
        # файла длина ЧЕСТНАЯ при оборванных кадрах, и проба последних
        # трёх десятых секунды его пропускает - замерено живьём, срезанный
        # на 40 % стримовый ролик прошёл как целый. Полный проход ловит
        # его и стоит секунды на нашей длине.
        try:
            х = subprocess.run(["ffmpeg", "-v", "error", "-stats", "-i", файл,
                                "-f", "null", "-"],
                               capture_output=True, text=True, timeout=600)
        except (OSError, subprocess.SubprocessError) as е:
            return None, "декодирование не спросилось: %s" % е
        ошибки = [с for с in (х.stderr or "").splitlines()
                  if с.strip() and not с.lstrip().startswith(("size=", "frame=",
                                                              "video:", "audio:"))
                  and "time=" not in с]
        if х.returncode != 0 or ошибки:
            return False, "файл не декодируется: %s" % (
                ошибки[-1][:90] if ошибки else "код %d" % х.returncode)
        # ДЛИНА БЕРЁТСЯ ИЗ ДЕКОДИРОВАНИЯ, А НЕ ИЗ ЗАГОЛОВКА, И ЭТО ЗАМЕР:
        # обрезанный mp3 декодируется МОЛЧА (у потока нет целостной
        # структуры), а заголовок держит прежние 5.04 с при живых 1.7 -
        # и `веер` с `-shortest` обрезал бы минутный эпизод до двух
        # секунд, не сказав ни слова. Расхождение заголовка с живой
        # длиной и есть обрыв.
        живая = None
        for с in reversed((х.stderr or "").splitlines()):
            if "time=" in с:
                кусок = с.split("time=")[-1].split()[0]
                ч = кусок.split(":")
                try:
                    if len(ч) == 3:
                        живая = int(ч[0]) * 3600 + int(ч[1]) * 60 + float(ч[2])
                    else:
                        живая = float(кусок)
                except ValueError:
                    живая = None
                break
        if живая is None:
            return None, "живую длину замерить нечем (ffmpeg не дал time=)"
        if длина - живая > 0.5:
            return False, ("обрезан: в заголовке %.2f с, декодируется %.2f с"
                           % (длина, живая))
        return True, "%.2f с, %d КБ, декодируется целиком" % (живая, размер // 1024)
    try:
        from PIL import Image
    except Exception as е:
        return None, "PIL нет: %s" % е
    try:
        with Image.open(файл) as и:
            и.verify()
    except Exception as е:
        return False, "кадр не открылся: %s" % е
    return True, "%d КБ" % (размер // 1024)


def готовое(з, папка):
    """Единица, собранная сегодня, второй раз НЕ ПОКУПАЕТСЯ. Три исхода.

    Прогон обрывается по-разному: предел шага, упавший сервис, рука
    человека. Без этой двери второй запуск заново купил бы всё, что уже
    лежит собранным, - на тридцати единицах это весь дневной бюджет во
    второй раз, и потолок суток тут не помощник: он не даст уйти выше
    пяти долларов, но уже потраченное на готовое не вернёт.

    Отметка идёт по ФАЙЛУ в папке дня, а не по журналу расхода: журнал
    говорит, что мы платили, а годен ли результат - говорит только сам
    файл. Поэтому сперва читаемость, потом «было».

    Обложку повторно НЕ ставим: она уже первым кадром, и второй проход
    по тому же кадру это трата за ничто. Её состояние называется словами
    по соседнему файлу, а не додумывается.
    """
    вид = з.get("вид")
    выход = з.get("выход")
    if not выход:
        return None
    if вид == "карусель":
        основа = os.path.join(папка, os.path.basename(выход) + "-slide")
        слайды = sorted(п for п in (
            os.path.join(папка, и) for и in os.listdir(папка)
            if и.startswith(os.path.basename(выход) + "-slide")
            and и.lower().endswith(".png")))
        if len(слайды) < С.СЛАЙДОВ_ГЕНЕРАЦИЕЙ:
            return None
        for п in слайды:
            годен, почему = читается(п)
            if годен is not True:
                return None
        return {"ок": True, "было": True, "файл": слайды[0], "файлы": слайды,
                "$факт": 0.0, "сек": 0.0, "слайдов": len(слайды),
                "как": "было с прошлого захода: слайдов %d" % len(слайды)}
    годен, почему = читается(выход)
    if годен is not True:
        return None
    обл = выход + "-cover.png"
    о = {"ок": True, "было": True, "файл": выход, "$факт": 0.0, "сек": 0.0,
         "как": "было с прошлого захода (%s)" % почему}
    if вид in ("формат1", "формат2", "формат3"):
        о["обложка"] = ("была первым кадром" if os.path.exists(обл)
                        else "прошлый заход собрал без обложки")
    return о


def _собрать(з, api, папка, лента=None):
    """Собрать одно задание дня. Вид решает, чем собирать.

    Возврат всегда одной формы: ок, файл, $факт, сек, почему. Разная форма
    у разных видов заставила бы вызывающего разбирать каждый по-своему, и
    один из них однажды разберут неверно.

    Зовётся ТОЛЬКО из `единица`: там стоят дверь готового и проверка
    файлом, и обойти их, позвав сборщик напрямую, значит заплатить за
    готовое или увезти в ленту нечитаемый файл.
    """
    вид = з.get("вид")
    выход = з.get("выход")
    if вид == "кадр_одетой":
        # Лицо идёт референсом, иначе персона каждый день другая.
        return кадр(api, з["промпт"], выход, буквы=False,
                    рефы=з.get("рефы") or ())
    if вид == "ответ_бота":
        return ответ_бота(з["вход"], з["кнопка"], з["место"], папка, выход)
    if вид == "формат1":
        о = сборщиком(ПОКАЗ, [з["персона"], з["вход"], з["результат"], выход],
                      выход, "формат1")
        if о.get("ок"):
            м = подложить_музыку(выход, os.path.basename(выход))
            о["музыка"] = м.get("как") or м.get("почему")
        return с_обложкой(о, з, 1, папка)
    if вид == "формат2":
        промпт = ("She slowly removes the outer layer in one continuous motion, "
                  "the camera holds still, her face and hands stay steady, "
                  "no slow motion, no speed up, natural pace")
        о = клип(api, промпт, з["первый"], з["последний"],
                 С.СЕКУНД_ФОРМАТА2, выход)
        if о.get("ок"):
            # h3-lite отдаёт свой звук сам, но проверяем файлом: обещание
            # сервиса это не дорожка в файле.
            м = подложить_музыку(выход, os.path.basename(выход))
            о["музыка"] = м.get("как") or м.get("почему")
        return с_обложкой(о, з, 2, папка)
    if вид == "формат3":
        # СТОК ЗОВЁТСЯ ИМПОРТОМ, А НЕ КОМАНДНОЙ СТРОКОЙ. Его CLI читает
        # аргументы ПОЗИЦИОННО (сток, текст, призыв), выхода не принимает
        # вовсе, и мои флаги «--текст» уехали бы в него первым аргументом
        # как путь к клипу. Замерено чтением его `__main__`, а не угадано.
        return с_обложкой(формат3(з, выход, папка), з, 3, папка)
    if вид == "пост":
        return сборщиком(ПОСТ, [з["панель_лево"], з["панель_право"], выход],
                         выход, "пост", цена=С.ЦЕНЫ["кадр_2k_high"],
                         платный=True)
    if вид == "карусель":
        return карусель(з, выход, папка, лента)
    if вид == "серия":
        return {"ок": False, "почему": "серия собирается своей дверью «сериал», "
                "а не здесь: один файл на пять пачек"}
    return {"ок": False, "почему": "вид «%s» не знает ни один сборщик" % вид}

def единица(з, api, папка, лента=None):
    """ОДНА ДВЕРЬ единицы дня: готовое не покупаем, собранное проверяем.

    Три шага, и порядок между ними точный:
      1. готовое с прошлого захода отдаётся даром;
      2. сборка;
      3. собранный файл ЧИТАЕТСЯ, иначе это не единица, а брак.

    Третий шаг не перестраховка. Сборщик отвечает «ок» по факту ЗАПИСИ
    файла, а записанный файл бывает нечитаемым: оборвался ffmpeg, кончилось
    место, сервис отдал огрызок. Такой файл проходит все проверки наличия и
    уезжает в ленту и в канал - там его и находит человек.

    Деньги при этом УЖЕ потрачены, и отказ их не возвращает: поэтому
    `$факт` остаётся в ответе, чтобы дневной счёт не соврал, а беда
    называет и файл, и причину.
    """
    б = готовое(з, папка)
    if б is not None:
        return б
    о = _собрать(з, api, папка, лента=лента)
    if not о.get("ок"):
        return о
    пути = о.get("файлы") or ([о.get("файл")] if о.get("файл") else [])
    for путь in пути:
        годен, почему = читается(путь)
        if годен is False:
            return {"ок": False, "$факт": о.get("$факт") or 0.0,
                    "сек": о.get("сек") or 0.0,
                    "почему": "собрано, но файл не читается (%s): %s"
                              % (почему, os.path.basename(путь or "")),
                    "брак": путь}
        # годен is None - прочитать было НЕЧЕМ. Пробел замера не повод
        # хоронить оплаченную единицу: ведём как раньше и говорим словами.
        if годен is None:
            о.setdefault("не_замерено", почему)
    return о
