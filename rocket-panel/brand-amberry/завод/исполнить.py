def с_обложкой(о, з, формат, папка):
    """Собранному ролику ставим обложку ПЕРВЫМ КАДРОМ.

    Обложка, лежащая файлом рядом, не видна никому: площадка берёт превью
    с первого кадра сама. Значит либо она становится первым кадром, либо
    за неё заплачено впустую - третьего нет.

    Неудача обложки РОЛИК НЕ ХОРОНИТ: единица уже собрана и годна, а
    превью площадка возьмёт с её собственного первого кадра. Беда
    называется словами и уезжает в отчёт.
    """
    if not о.get("ок"):
        return о
    строки = [с for с in (з.get("описание") or "").splitlines() if с.strip()]
    заг = (строки[0] if строки else "").strip().rstrip(".")[:40].upper()
    подзаг = (строки[2] if len(строки) > 2 else "").strip()[:40]
    if not заг:
        о["обложка"] = "описание пусто: обложку собрать нечем"
        return о
    путь = os.path.join(папка, os.path.basename(з["выход"]) + "-cover.png")
    об = обложка(формат, заг, подзаг or "FIRST ONE IS FREE", путь)
    if not об.get("ок"):
        о["обложка"] = "не вышла: %s" % об.get("почему")
        return о
    ОП = _сосед("обложка_первым")
    п = ОП.поставить(о["файл"], путь)
    о["обложка"] = "первым кадром" if п.get("ок") else "не встала: %s" % п.get("почему")
    о["$факт"] = round(float(о.get("$факт") or 0) + float(об.get("$факт") or 0), 4)
    о["сек"] = round(float(о.get("сек") or 0) + float(об.get("сек") or 0), 1)
    return о


def клип_стока(папка):
    """Свежий клип стока. Сток даровой: Pexels по ключу, curl'ом.

    Занятое помнит журнал - иначе один красивый клип уедет во все пять
    лент, и это самый заметный повтор из возможных: кадр один в один.
    """
    запас = os.path.join(КОРЕНЬ, "ролик-сток", "кандидаты")
    было = lambda: sorted(ф for ф in os.listdir(запас)
                          if ф.endswith(".mp4")) if os.path.isdir(запас) else []
    файлы = было()
    о = Ж.свободное("лента", "сток", файлы)
    if not о.get("ок") or о.get("как") in ("круг", "тесно") or not файлы:
        # Добираем ровно под нехватку: качать сотню клипов впрок значит
        # жечь лимит ключа и место на диске.
        сборщиком(СТОК_ПОИСК, [4], запас, "поиск стока")
        файлы = было()
        о = Ж.свободное("лента", "сток", файлы)
    если = о.get("что")
    if not если:
        return None, "сток не нашёлся и не добрался"
    Ж.занять("лента", "сток", если)
    return os.path.join(запас, если), ""


def формат3(з, выход, папка):
    """Сток с заголовком. Заголовок берётся из первой строки описания:
    второго списка заголовков у ленты нет, и заводить его значит однажды
    выпустить ролик, у которого в кадре одно, а в описании другое."""
    клип_путь, почему = клип_стока(папка)
    if not клип_путь:
        return {"ок": False, "почему": почему}
    заг = (з.get("описание") or "").splitlines()[0].strip().rstrip(".")[:40].upper()
    if not заг:
        return {"ок": False, "почему": "описание пусто: заголовок кадра брать негде"}
    т0 = time.time()
    сток_папка = os.path.join(КОРЕНЬ, "ролик-сток")
    if сток_папка not in sys.path:
        sys.path.insert(0, сток_папка)
    try:
        import сборка_стока as СБ
        СБ.собрать(клип_путь, заг, выход=выход, семя=os.path.basename(выход),
                   длина=10.0)
    except Exception as e:
        return {"ок": False, "почему": "сборка стока: %s: %s"
                % (type(e).__name__, e)}
    if not os.path.exists(выход):
        return {"ок": False, "почему": "сборка стока прошла, а файла нет"}
    return {"ок": True, "файл": выход, "сек": round(time.time() - т0, 1),
            "$факт": 0.0, "как": "сток даровой", "заголовок": заг}


def единица(з, api, папка, лента=None):
    """Исполнить одно задание дня. Вид решает, чем собирать.

    Возврат всегда одной формы: ок, файл, $факт, сек, почему. Разная форма
    у разных видов заставила бы вызывающего разбирать каждый по-своему, и
    один из них однажды разберут неверно.
    """
    вид = з.get("вид")
    выход = з.get("выход")
    if вид == "кадр_одетой":
        # Лицо идёт референсом, иначе персона каждый день другая.
        return кадр(api, з["промпт"], выход, буквы=False,
                    рефы=з.get("рефы") or ())
    if вид == "ответ_бота":
        return ответ_бота(з["вход"], з["кнопка"], з["место"], папка, выход)
    if вид == "формат1":
        о = сборщиком(ПОКАЗ, [з["персона"], з["вход"], з["результат"], выход],
                      выход, "формат1")
        return с_обложкой(о, з, 1, папка)
    if вид == "формат2":
        промпт = ("She slowly removes the outer layer in one continuous motion, "
                  "the camera holds still, her face and hands stay steady, "
                  "no slow motion, no speed up, natural pace")
        о = клип(api, промпт, з["первый"], з["последний"],
                 С.СЕКУНД_ФОРМАТА2, выход)
        return с_обложкой(о, з, 2, папка)
    if вид == "формат3":
        # СТОК ЗОВЁТСЯ ИМПОРТОМ, А НЕ КОМАНДНОЙ СТРОКОЙ. Его CLI читает
        # аргументы ПОЗИЦИОННО (сток, текст, призыв), выхода не принимает
        # вовсе, и мои флаги «--текст» уехали бы в него первым аргументом
        # как путь к клипу. Замерено чтением его `__main__`, а не угадано.
        return с_обложкой(формат3(з, выход, папка), з, 3, папка)
    if вид == "пост":
        return сборщиком(ПОСТ, [з["панель_лево"], з["панель_право"], выход],
                         выход, "пост", цена=С.ЦЕНЫ["кадр_2k_high"],
                         платный=True)
    if вид == "карусель":
        # Карусель хочет ССЫЛКУ на фото модели дня, а не путь: выкладываем
        # той же дверью, которой потом ставим единицу в слот.
        if лента is None:
            return {"ок": False, "почему": "дверь ленты не передана: "
                    "карусели нужен адрес фото, а не путь"}
        в = лента.выложить(з["фото_дня"])
        if not в.get("ок"):
            return {"ок": False, "почему": "фото дня не выложено: %s"
                    % в.get("почему")}
        return сборщиком(КАРУСЕЛЬ, [в["адрес"]], выход, "карусель",
                         цена=round(С.ЦЕНЫ["кадр_2k_high"]
                                    * С.СЛАЙДОВ_ГЕНЕРАЦИЕЙ, 4), платный=True)
    if вид == "серия":
        return {"ок": False, "почему": "серия собирается своей дверью «сериал», "
                "а не здесь: один файл на пять пачек"}
    return {"ок": False, "почему": "вид «%s» не знает ни один сборщик" % вид}
