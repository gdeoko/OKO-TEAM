def клип_стока(папка):
    """Свежий клип стока. Сток даровой: Pexels по ключу, curl'ом.

    Занятое помнит журнал - иначе один красивый клип уедет во все пять
    лент, и это самый заметный повтор из возможных: кадр один в один.
    """
    запас = os.path.join(КОРЕНЬ, "ролик-сток", "кандидаты")
    было = lambda: sorted(ф for ф in os.listdir(запас)
                          if ф.endswith(".mp4")) if os.path.isdir(запас) else []
    файлы = было()
    о = Ж.свободное("лента", "сток", файлы)
    if not о.get("ок") or о.get("как") in ("круг", "тесно") or not файлы:
        # Добираем ровно под нехватку: качать сотню клипов впрок значит
        # жечь лимит ключа и место на диске.
        сборщиком(СТОК_ПОИСК, [4], запас, "поиск стока")
        файлы = было()
        о = Ж.свободное("лента", "сток", файлы)
