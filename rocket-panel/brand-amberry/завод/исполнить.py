def _сосед(имя):
    import importlib.util
    с = importlib.util.spec_from_file_location(имя, os.path.join(ТУТ, имя + ".py"))
    м = importlib.util.module_from_spec(с)
    с.loader.exec_module(м)
    return м


Ж = _сосед("журнал")
