def есть_звук(файл):
    """Есть ли в файле аудиодорожка. Три исхода, и третий не «нет»."""
    try:
        п = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "a",
                            "-show_entries", "stream=codec_type", "-of",
                            "default=nw=1:nk=1", файл],
                           capture_output=True, text=True, timeout=60)
        return bool((п.stdout or "").strip())
    except Exception:
        return None          # НЕ ЗАМЕРЕНО: лучше не трогать файл


def подложить_музыку(файл, семя):
    """Музыка в ролик, если её там нет.

    ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ ДВЕРЬ. Сборщик показа (формат 1) звука не
    кладёт вовсе - сухой прогон дал ролик 18,7 с с ОДНОЙ дорожкой h264.
    В ленте молчащий ролик читается как брак, а канон просит трек на
    каждый. Сток (формат 3) музыку кладёт сам, поэтому сперва спрашиваем
    файл и второй трек поверх первого не вшиваем.

    Музыка даровая: Freesound CC0 той же дверью, что у стока.
    """
    был = есть_звук(файл)
    if был is None:
        return {"ок": True, "как": "звук НЕ ЗАМЕРЕН, файл не тронут"}
    if был:
        return {"ок": True, "как": "музыка уже есть"}
    if СНЯТИЕ not in sys.path:
        sys.path.insert(0, СНЯТИЕ)
    ОП = _сосед("обложка_первым")
    длина = ОП.длина(файл)
    if not длина:
        return {"ок": False, "почему": "длину не замерить, музыку не кладём"}
    try:
        import звук as З
        дор = файл + ".m4a"
        З.дорожка(семя, длина, [], ОП.ffmpeg(), дор)
    except Exception as e:
        return {"ок": False, "почему": "музыка не собралась: %s: %s"
                % (type(e).__name__, e)}
    if not os.path.exists(дор):
        return {"ок": False, "почему": "дверь музыки не дала файла"}
    врем = файл + ".sound.mp4"
    subprocess.run([ОП.ffmpeg(), "-y", "-hide_banner", "-loglevel", "error",
                    "-nostdin", "-i", файл, "-i", дор, "-map", "0:v",
                    "-map", "1:a", "-c:v", "copy", "-c:a", "aac", "-b:a",
                    "160k", "-shortest", врем], capture_output=True, text=True)
    if not os.path.exists(врем):
        return {"ок": False, "почему": "музыка не вшилась"}
    os.replace(врем, файл)
    try:
        os.remove(дор)
    except OSError:
        pass
    return {"ок": True, "как": "музыка подложена"}


def с_обложкой(о, з, формат, папка):
    """Собранному ролику ставим обложку ПЕРВЫМ КАДРОМ.

    Обложка, лежащая файлом рядом, не видна никому: площадка берёт превью
    с первого кадра сама. Значит либо она становится первым кадром, либо
    за неё заплачено впустую - третьего нет.

    Неудача обложки РОЛИК НЕ ХОРОНИТ: единица уже собрана и годна, а
    превью площадка возьмёт с её собственного первого кадра. Беда
    называется словами и уезжает в отчёт.
    """
    if not о.get("ок"):
        return о
    строки = [с for с in (з.get("описание") or "").splitlines() if с.strip()]
    О = _сосед("описания")
    заг = (з.get("заголовок_кадра")
           or О.заголовок_кадра(з.get("персона") or "лента", журнал=Ж)).upper()
    # Подзаголовок - вторая мысль описания целиком до точки, а не срез по
    # знакам: на обложке обрывок читается так же плохо, как в кадре.
    подзаг = ""
    if len(строки) > 2:
        подзаг = строки[2].split(".")[0].strip()[:40]
    if not заг:
        о["обложка"] = "описание пусто: обложку собрать нечем"
        return о
    # ОБЛОЖКА ЛОЖИТСЯ РЯДОМ СО СВОИМ ФАЙЛОМ, А НЕ В ПАПКУ ДНЯ. У
    # форматов это одно и то же место, а у серии файл лежит в подпапке
    # `seria`: обложка уходила в папку дня, искалась рядом с эпизодом и
    # не находилась НИКОГДА - то есть покупалась заново каждым запуском.
    # Замерено репетицией: пять обложек собраны, рядом с эпизодами ноль.
    путь = о["файл"] + "-cover.png"
