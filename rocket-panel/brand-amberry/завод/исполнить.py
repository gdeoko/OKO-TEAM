def _сосед(имя):
    import importlib.util
    с = importlib.util.spec_from_file_location(имя, os.path.join(ТУТ, имя + ".py"))
    м = importlib.util.module_from_spec(с)
    с.loader.exec_module(м)
    return м


Ж = _сосед("журнал")
С = _сосед("смета")


def апи():
    """Дверь APIMODELS на ключе ЗАВОДА. Три исхода, пустой ключ не пускаем."""
    if БОТ not in sys.path:
        sys.path.insert(0, БОТ)
    try:
        import apimodels as А
    except Exception as e:
        return None, "дверь apimodels не поднялась: %s: %s" % (type(e).__name__, e)
    к = А.ключ_завода()
    if not к:
        return None, ("APIMODELS_KEY_ZAVOD не задан. Лента идёт на ключе завода "
                      "ОКО; ключ бота подставлять нельзя - с него платят люди")
    try:
        return А.Api(key=к), ""
    except Exception as e:
        return None, "Api не создался: %s: %s" % (type(e).__name__, e)


def _баланс(api):
    try:
        return float(api.баланс(свежий=True))
    except Exception:
        return None          # НЕ ЗАМЕРЕНО: отчёт скажет это словами


def _трата(статья, ожидали, до, после, подробно=""):
    """Запись расхода. Факт по счёту, а при незамеренном счёте - прайс.

    Прайс вместо факта это ПОМЕТКА, а не замер: день, в котором счёт не
    читается, обязан это сказать, иначе отчёт выглядит точным.
    """
    if до is not None and после is not None:
        факт = round(max(0.0, до - после), 4)
        как = "по счёту"
    else:
        факт = round(float(ожидали), 4)
        как = "по прайсу (счёт НЕ ЗАМЕРЕН)"
    Ж.расход_записать(статья, факт, "%s | %s" % (подробно, как))
    return {"$факт": факт, "как": как, "$ожидали": round(float(ожидали), 4)}


def _пустить(сколько):
    """Разрешение на трату. Потолок спрашивается ДО вызова."""
    return С.влезет(сколько, Ж.потрачено())


def кадр(api, промпт, выход, буквы=False, рефы=(), стороны="vert", цена=None):
    """Один кадр. Буквы идут дорогой ячейкой, остальное дешёвой."""
    ц = цена if цена is not None else (С.ЦЕНЫ["кадр_2k_high"] if буквы
                                       else С.ЦЕНЫ["кадр_1k_low"])
    в = _пустить(ц)
    if not в.get("ок"):
        return {"ок": False, "почему": "потолок: %s" % в.get("почему")}
    пар = {"mode": "photo", "prompt": промпт, "size": стороны,
           "model": МОДЕЛЬ_БУКВ if буквы else МОДЕЛЬ_КАДРА,
           "res": "2K" if буквы else "1K",
           "qual": "high" if буквы else "low",
           "neg": НЕГАТИВ_КАДРА if not буквы else ""}
    имена = []
    for р in рефы:
        if not os.path.exists(р):
            return {"ок": False, "почему": "референса нет: %s" % р}
        имена.append(api.upload(os.path.basename(р), open(р, "rb").read()))
    if имена:
        пар["images"] = имена
    до = _баланс(api)
    т0 = time.time()
    try:
        тид, _ = api.start(**пар)
        о = api.wait(тид)
    except Exception as e:
        # За отказ денег не берут, но сказать о нём надо точно: по
        # «не получилось» чинить нечего.
        return {"ок": False, "почему": "%s: %s" % (type(e).__name__, e)}
    файлы = о.get("files") or []
    if not файлы:
        return {"ок": False, "почему": "задача готова, а файла нет"}
    os.makedirs(os.path.dirname(выход) or ".", exist_ok=True)
    врем = выход + ".part"
    with open(врем, "wb") as ф:
        ф.write(api.fetch(файлы[0]))
    os.replace(врем, выход)
    т = _трата("кадр букв" if буквы else "кадр", ц, до, _баланс(api),
               os.path.basename(выход))
    т.update({"ок": True, "файл": выход, "сек": round(time.time() - т0, 1)})
    return т


def клип(api, промпт, первый, последний, секунд, выход):
    """Клип h3-lite: первый и последний кадр.

    ДВА КАДРА ОБЯЗАТЕЛЬНЫ. С одним сервис не ругается, а молча считает
    задачу как текст-в-видео: кадр пропадает совсем, и деньги уходят за
    ролик, которого никто не задумывал.
    """
    ц = round(С.ЦЕНЫ["клип_3с"] / 3.0 * float(секунд), 4)
    в = _пустить(ц)
    if not в.get("ок"):
        return {"ок": False, "почему": "потолок: %s" % в.get("почему")}
    for п in (первый, последний):
        if not п or not os.path.exists(п):
            return {"ок": False, "почему": "кадра нет: %s" % п}
    имена = [api.upload(os.path.basename(п), open(п, "rb").read())
             for п in (первый, последний)]
    до = _баланс(api)
    т0 = time.time()
    try:
        тид, _ = api.start(mode="video", prompt=промпт, size="vert",
                           secs=int(секунд), images=имена)
        о = api.wait(тид)
    except Exception as e:
        return {"ок": False, "почему": "%s: %s" % (type(e).__name__, e)}
    файлы = о.get("files") or []
    if not файлы:
        return {"ок": False, "почему": "клип готов, а файла нет"}
    врем = выход + ".part"
    with open(врем, "wb") as ф:
        ф.write(api.fetch(файлы[0]))
    os.replace(врем, выход)
    т = _трата("клип %gс" % секунд, ц, до, _баланс(api), os.path.basename(выход))
    т.update({"ок": True, "файл": выход, "сек": round(time.time() - т0, 1)})
    return т


def ответ_бота(вход, кнопка, место, папка, выход):
    """Живой конвейер бота: та же кнопка, что нажимает человек.

    Своего пути снятия у завода нет НАРОЧНО. Лента показывает бота, и
    показывать она обязана то, что бот правда делает: отдельный «заводской»
    движок разойдётся с ботом на первой же правке, и ролик начнёт обещать
    качество, которого в боте нет.
    """
    ц = С.ЦЕНЫ["снятие_ботом"]
    в = _пустить(ц)
    if not в.get("ок"):
        return {"ок": False, "почему": "потолок: %s" % в.get("почему")}
    if БОТ not in sys.path:
        sys.path.insert(0, БОТ)
    т0 = time.time()
    try:
        import конвейер_соло as К
        import места as М
        м = М.по_ключу(место)
        о = К.собрать(кнопка, вход, папка, м)
    except Exception as e:
        return {"ок": False, "почему": "конвейер бота: %s: %s" % (type(e).__name__, e)}
    # ФОРМА ОТВЕТА ЗАМЕРЕНА, А НЕ УГАДАНА: конвейер отдаёт
    # {"ок", "файл", "шаги"} либо {"ок": False, "почему", "шаги"}. Сперва
    # читаем `ок`: взяв сразу «файл», мы потеряли бы причину отказа и
    # печатали бы «конвейер не дал файла» там, где он честно сказал, что
    # именно не вышло.
    о = о or {}
    if not о.get("ок"):
        return {"ок": False, "почему": "конвейер бота: %s" % (о.get("почему")
                or "ответ без причины"), "шаги": о.get("шаги")}
    путь = о.get("файл") or ""
    if not путь or not os.path.exists(путь):
        return {"ок": False, "почему": "конвейер сказал «ок», а файла нет: %s"
                % str(путь)[:120], "шаги": о.get("шаги")}
    if путь != выход:
        os.makedirs(os.path.dirname(выход) or ".", exist_ok=True)
        with open(путь, "rb") as и, open(выход + ".part", "wb") as ф:
            ф.write(и.read())
        os.replace(выход + ".part", выход)
    # ЦЕНУ НАЗЫВАЕТ САМ СЕРВИС, И ОНА ЛЕЖИТ В ШАГАХ. Конвейер кладёт в
    # шаг кадра поле `цена` из ответа APIMODELS, то есть факт у нас есть
    # и мерить его своим балансом не нужно: конвейер ходит своим ключом,
    # и наш баланс его трату не покажет вовсе.
    шаги = о.get("шаги") or {}
    своя = 0.0
    for ш in шаги.values():
        if isinstance(ш, dict) and ш.get("цена"):
            try:
                своя += float(ш["цена"])
            except (TypeError, ValueError):
                pass
    if своя > 0:
        т = {"$факт": round(своя, 4), "как": "по счёту сервиса",
             "$ожидали": round(ц, 4)}
        Ж.расход_записать("снятие ботом", своя,
                          "%s/%s | по счёту сервиса" % (кнопка, место))
    else:
        т = _трата("снятие ботом", ц, None, None, "%s/%s" % (кнопка, место))
    т.update({"ок": True, "файл": выход, "сек": round(time.time() - т0, 1),
              "шаги": шаги})
    return т


def окружение_ленты():
    """Окружение подпроцесса-сборщика с ключом ЗАВОДА.

    Пост и карусель читают `APIMODELS_KEY` прямо из окружения, то есть по
    умолчанию встают на ключ БОТА - тот, с которого платят живые люди за
    свои работы. Подменяем его на заводской В ОКРУЖЕНИИ ПОДПРОЦЕССА, а не
    правкой их кода: бот этими же файлами пользуется, и менять им ключ
    нельзя. Ключа нет - сборщик не зовём вовсе.
    """
    if БОТ not in sys.path:
        sys.path.insert(0, БОТ)
    try:
        import apimodels as А
        к = А.ключ_завода()
    except Exception as e:
        return None, "ключ завода не спросился: %s" % type(e).__name__
    if not к:
        return None, "APIMODELS_KEY_ZAVOD не задан: сборщик пошёл бы ключом бота"
    е = dict(os.environ)
    е["APIMODELS_KEY"] = к
    е["ROCKET_API_PHOTO"] = МОДЕЛЬ_БУКВ      # сборщики рисуют буквы
    е["ROCKET_API_SIZE"] = "2K"
    return е, ""


def сборщиком(скрипт, аргументы, выход, статья, цена=0.0, платный=False):
    """Единица, которую собирает готовый скрипт проекта (ffmpeg, вёрстка).

    Монтаж денег не стоит, поэтому цена по умолчанию ноль: писать в расход
    нули значит засорять журнал тем, за что не платили. `платный` ставится
    там, где скрипт сам ходит в APIMODELS (оправа поста, слайды карусели):
    тогда ему нужен ключ завода и разрешение потолка.
    """
    if not os.path.exists(скрипт):
        return {"ок": False, "почему": "сборщика нет: %s" % скрипт}
    е = None
    if платный:
        в = _пустить(цена)
        if not в.get("ок"):
            return {"ок": False, "почему": "потолок: %s" % в.get("почему")}
        е, почему = окружение_ленты()
        if е is None:
            return {"ок": False, "почему": почему}
    т0 = time.time()
    п = subprocess.run([sys.executable, скрипт] + [str(а) for а in аргументы],
                       capture_output=True, text=True, env=е,
                       cwd=os.path.dirname(скрипт) or None)
    if not os.path.exists(выход):
        хвост = (п.stderr or п.stdout or "").strip().splitlines()
        return {"ок": False, "почему": "%s не дал файла: %s"
                % (os.path.basename(скрипт), хвост[-1] if хвост else "молча")}
    о = {"ок": True, "файл": выход, "сек": round(time.time() - т0, 1)}
    if цена:
        о.update(_трата(статья, цена, None, None, os.path.basename(выход)))
    return о


