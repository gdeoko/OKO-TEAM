# -*- coding: utf-8 -*-
"""Смета дня: считается ДО первой траты, и она же держит потолок.

ПОЧЕМУ ТАК. Потолок, который проверяют ПОСЛЕ вызова, это не потолок:
деньги уже списаны. Поэтому день сперва считается арифметикой по
прайсу, и если расчёт выше потолка, день НЕ СТАРТУЕТ ВОВСЕ и говорит
числами, что именно не влезло. Факт сверяется с планом в конце дня: план
врёт в обе стороны, и расхождение надо видеть, а не подгонять.

ЦЕНЫ ЗАМЕРЕНЫ, А НЕ ВСПОМНЕНЫ. Каждая строка несёт, чем замерена. Где
не замерено - так и написано, и такая строка идёт В СМЕТУ С ЗАПАСОМ:
незамеренная цена, посчитанная нулём, и есть перерасход.
"""

ПОТОЛОК_ДНЯ = 5.00          # слово владельца: пять долларов в день на всё
ПОТОЛОК_СЕРИИ = 2.00        # серия одна на пять пачек, дороже двух не берём
ЗАПАС = 0.10                # на повторы и добор, 10 % сверху расчёта
# Правило владельца 26.09.2026: формат 2 идёт 5-10 секунд ОДНИМ куском.
# Восемь это середина коридора, и именно столько дал живой замер формата
# (129 кадров, 8,06 с). Число стоит здесь одно, чтобы смета и сборщик не
# разошлись: разойдясь, они дадут честный расчёт и другую трату.
СЕКУНД_ФОРМАТА2 = 8.0
# Карусель: 5-10 слайдов, последний собирается КОДОМ (карусель/финал.py),
# то есть генераций на один меньше, чем слайдов.
СЛАЙДОВ_ГЕНЕРАЦИЕЙ = 5

# $ за единицу. Источник замера - в комментарии, иначе это не цена, а память.
ЦЕНЫ = {
    # замерено живыми списаниями 07-08.10.2026
    "кадр_2k_high":   0.030,   # gpt-image-2, 2K high - единственная под буквы
    "кадр_1k_low":    0.008,   # gpt-image-2.5-flare, 1K low - где букв нет
    "кадр_серии":     0.035,   # qwen3-image 2K - кадр эпизода сериала
    "клип_3с":        0.060,   # minimax-h3-lite, 768P, 3 с ($0.02/с)
    "снятие_ботом":   0.034,   # живой конвейер бота: описатель+spicy+FLUX
    "описатель":      0.0013,  # gemini-3.1-flash-lite
    "музыка_suno":    0.260,   # Suno v5, вызов отдаёт два варианта
    # НЕ ЗАМЕРЕНО: берём с запасом вверх, чтобы смета не соврала вниз
    "монтаж":         0.000,   # ffmpeg свой, денег не стоит
}


КАДРОВ_СЕРИИ = 18
ТРЕКОВ_НА_СЕРИАЛ = 5        # по одному на пачку: это и есть «разная музыка»
СЕРИЙ_В_СЕРИАЛЕ = 10


def серия():
    """Эпизод сериала: 18 кадров, 18 клипов по 3 с, обложка, музыка.

    МУЗЫКИ ПЯТЬ, А НЕ ОДНА, И ПЛАТИТСЯ ОНА РАЗ В ДЕСЯТЬ ДНЕЙ. Слово
    владельца: серия идёт на все пять пачек одним файлом, «просто разная
    музыка на фоне». Разная музыка это пять треков, и считать их одним
    значит занизить смету впятеро; платить их каждый день значит завысить
    вдесятеро. Трек живёт весь сериал, поэтому в сутки приходится пятая
    доля от десятой: $0.13.

    Отдельный ключ Suno не нужен: `suno-v5` живёт прямо в APIMODELS
    (замер каталога 08.10.2026: 154 модели, из них музыкальные
    kling-sound-effects, kling-video-to-audio и suno-v5).
    """
    кадры = КАДРОВ_СЕРИИ * ЦЕНЫ["кадр_серии"]
    клипы = КАДРОВ_СЕРИИ * ЦЕНЫ["клип_3с"]
    обложка = ЦЕНЫ["кадр_2k_high"]
    музыка = ЦЕНЫ["музыка_suno"] * ТРЕКОВ_НА_СЕРИАЛ / float(СЕРИЙ_В_СЕРИАЛЕ)
    итого = кадры + клипы + обложка + музыка
    return {"статья": "серия", "$": round(итого, 4),
            "строки": {"кадры 18": round(кадры, 4),
                       "клипы 18x3с": round(клипы, 4), "обложка": обложка,
                       "музыка %d трека / %d серий"
                       % (ТРЕКОВ_НА_СЕРИАЛ, СЕРИЙ_В_СЕРИАЛЕ): round(музыка, 4)}}


def пачка():
    """Одна пачка за день: 4 ролика + пост + карусель.

    ЦЕНЫ ВЗЯТЫ ИЗ ПРАВИЛ ФОРМАТОВ, А НЕ ИЗ ПАМЯТИ. Первый мой расчёт
    поставил формату 3 две генерации клипа ($0.15), а формат 3 это СТОК с
    заголовком: сток бесплатен, платит только обложка. И наоборот, формату
    2 я дала один клип на 3 с, а правило владельца от 26.09 просит 5-10
    секунд одним куском, то есть вдвое дороже. Смета, собранная по памяти,
    врёт в обе стороны сразу.

    ПАРА КАДРОВ ОДНА НА ПАЧКУ. Одетый кадр и результат бота платятся РАЗ
    и служат формату 1 (экран бота), формату 2 (первый и последний кадр),
    посту (две панели) и карусели (фото модели дня). Платить за них в
    каждой единице значит платить четыре раза за одну и ту же девушку -
    и получить в посте «до/после» двух разных.
    """
    пара = ЦЕНЫ["кадр_1k_low"] + ЦЕНЫ["снятие_ботом"]      # одетая + ответ бота
    ф1 = пара + ЦЕНЫ["кадр_2k_high"]                       # показ экрана бота
    ф2 = ЦЕНЫ["клип_3с"] / 3.0 * СЕКУНД_ФОРМАТА2 + ЦЕНЫ["кадр_2k_high"]
    ф3 = ЦЕНЫ["кадр_2k_high"]                              # сток даровой
    серия_хвост = ЦЕНЫ["кадр_2k_high"]                     # своя обложка пачки
    пост = ЦЕНЫ["кадр_2k_high"]                            # оправа, панели хромакеем
    карусель = ЦЕНЫ["кадр_2k_high"] * СЛАЙДОВ_ГЕНЕРАЦИЕЙ   # финал собирается кодом
    итого = ф1 + ф2 + ф3 + серия_хвост + пост + карусель
    return {"статья": "пачка", "$": round(итого, 4),
            "строки": {"формат1 (пара кадров + обложка)": round(ф1, 4),
                       "формат2 (%g с + обложка)" % СЕКУНД_ФОРМАТА2: round(ф2, 4),
                       "формат3 (сток даровой + обложка)": round(ф3, 4),
                       "обложка серии": серия_хвост, "пост (оправа)": пост,
                       "карусель (%d слайдов)" % СЛАЙДОВ_ГЕНЕРАЦИЕЙ: round(карусель, 4)}}


def день(пачек=5, с_серией=True):
    """Смета дня. Три исхода: влезает / не влезает / нечего считать."""
    if пачек <= 0:
        return {"ок": False, "почему": "пачек ноль, считать нечего"}
    строки = []
    итого = 0.0
    if с_серией:
        с = серия()
        if с["$"] > ПОТОЛОК_СЕРИИ:
            return {"ок": False, "$": с["$"],
                    "почему": "серия %.2f дороже своего потолка %.2f" % (с["$"], ПОТОЛОК_СЕРИИ)}
        строки.append(с)
        итого += с["$"]
    п = пачка()
    for н in range(пачек):
        строки.append({"статья": "пачка %d" % (н + 1), "$": п["$"], "строки": п["строки"]})
        итого += п["$"]
    с_запасом = итого * (1 + ЗАПАС)
    ок = с_запасом <= ПОТОЛОК_ДНЯ
    о = {"ок": ок, "$": round(итого, 4), "$с_запасом": round(с_запасом, 4),
         "потолок": ПОТОЛОК_ДНЯ, "пачек": пачек, "серия": с_серией, "строки": строки}
    if not ок:
        # Говорим ЧИСЛАМИ, что снять, а не просто «дорого».
        лишнее = с_запасом - ПОТОЛОК_ДНЯ
        о["почему"] = ("расчёт %.2f (с запасом %.2f) выше потолка %.2f: лишних %.2f, "
                       "это %.1f пачки" % (итого, с_запасом, ПОТОЛОК_ДНЯ, лишнее,
                                           лишнее / п["$"] if п["$"] else 0))
        о["влезает_пачек"] = int((ПОТОЛОК_ДНЯ / (1 + ЗАПАС) -
                                  (серия()["$"] if с_серией else 0)) // п["$"])
    return о


def влезет(сколько, уже_потрачено):
    """Пустить ли следующую трату. НЕ ЗАМЕРЕНО значит НЕ ПУСКАЕМ.

    Потолок, который при нечитаемом журнале расхода пропускает трату,
    бесполезен: именно в такой день и уходит лишнее.
    """
    if уже_потрачено is None:
        return {"ок": False, "почему": "расход за день НЕ ЗАМЕРЕН, трату не пускаем"}
    будет = уже_потрачено + float(сколько)
    if будет > ПОТОЛОК_ДНЯ:
        return {"ок": False, "почему": "%.2f + %.2f = %.2f выше потолка %.2f"
                % (уже_потрачено, сколько, будет, ПОТОЛОК_ДНЯ)}
    return {"ок": True, "будет": round(будет, 4), "остаток": round(ПОТОЛОК_ДНЯ - будет, 4)}


