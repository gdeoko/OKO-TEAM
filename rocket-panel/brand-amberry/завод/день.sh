#!/bin/bash
# ДЕНЬ ЛЕНТЫ AMBERRY. Запускается кроном раз в сутки.
#
# ИМЕНА ПЕРЕМЕННЫХ ТОЛЬКО ASCII. bash кириллическое имя за имя не считает
# вовсе и отвечает «No such file or directory» на строку присваивания -
# первая версия этого файла умерла ровно так, с кодом 2, и выглядело это
# как сломанный путь, а не как сломанное имя. По-русски пишем в Python.
#
# ПРЕДЕЛ ШАГА ОБЯЗАТЕЛЕН. Что бы ни повисло внутри - сеть, сервис, ffmpeg -
# шаг умрёт раньше своего окна и отпустит замок. Без предела один висяк
# держит замок сутками, и крон молча уходит каждый раз: снаружи это
# читается как «завод не запускается».
#
# ЗАМОК БЕЗ ОЖИДАНИЯ (-n). Два прогона по одной папке дня дают огрызки
# вместо единиц: второй пишет в те же файлы, пока первый их читает.
set -u
LOG=/srv/amberry/zavod-den.log
LOCK=/tmp/amberry_den.lock
DEN=/opt/amberry/rocket-panel/brand-amberry/завод/день.py
set -a
. /etc/amberry.env
set +a
exec >>"$LOG" 2>&1
echo "=== $(date -u +%FT%TZ) старт $* ==="
if ! flock -n "$LOCK" true 2>/dev/null; then
  echo "ПРОПУСК: прогон уже идёт, замок держат с $(stat -c %y "$LOCK" 2>/dev/null)"
  echo "=== $(date -u +%FT%TZ) конец, код 0 (пропуск) ==="
  exit 0
fi
flock -n "$LOCK" timeout 7200 python3 "$DEN" "$@"
CODE=$?
[ $CODE -eq 124 ] && echo "ПРЕДЕЛ ШАГА: два часа вышли, прогон снят"
echo "=== $(date -u +%FT%TZ) конец, код $CODE ==="
exit $CODE
