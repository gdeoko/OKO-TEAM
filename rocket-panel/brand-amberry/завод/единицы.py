def без_кириллицы(текст):
    """Есть ли в английском промпте русские буквы.

    Промпт весь английский, и русское слово в нём это не мелочь: модель
    либо не понимает его вовсе, либо принимает за надпись и рисует буквами
    прямо на кадре. Первая сборка промпта вклеила «чёрные волны,
    изумрудные глаза» из паспорта и выглядела при этом рабочей.
    """
    куски = [с for с in текст if "а" <= с.lower() <= "я" or с.lower() == "ё"]
    return (not куски), "".join(sorted(set(куски)))


def промпт_одетой(ключ_персоны, запись, набор):
    """Промпт входного кадра: одетая героиня, та сцена, что увидит бот.

    Кадр идёт БЕЗ БУКВ, поэтому ячейка дешёвая (1K low). Зеркал и
    отражений в гардеробе нет нарочно: отражение рисует второе лицо, и бот
    снимает одежду с одного, оставляя второе одетым.

    ТРИ ИСХОДА, и третий не молчит: промпт готов / внешности по-английски
    нет (поле `внешность_англ` не заведено - честный отказ, а не русский
    текст в английском промпте) / в собранном промпте нашлась кириллица.
    """
    в = (запись.get("внешность_англ") or "").strip()
    if not в:
        return {"ок": False, "почему": "у «%s» нет поля «внешность_англ»: "
                "русская внешность в английский промпт не идёт" % ключ_персоны}
    части = [
        "Vertical 9:16 photograph of one young woman, alone in frame.",
        "Appearance: %s." % в,
        "She wears %s." % набор.get("одежда", ""),
        "Location: %s." % набор.get("локации", ""),
        "Camera: %s." % набор.get("ракурсы", ""),
        "Light: %s." % набор.get("свет", ""),
        "Full body visible from head to below the hips, she looks into the camera.",
        "Photorealistic, natural skin texture, sharp focus, 85mm lens, "
        "shallow depth of field.",
        "No mirrors, no reflections, no second person, no text, no logo, no watermark.",
    ]
    промпт = " ".join(ч for ч in части if ч.strip())
    чисто, буквы = без_кириллицы(промпт)
    if not чисто:
        return {"ок": False, "почему": "в промпте кириллица: %s" % буквы,
                "промпт": промпт}
    return {"ок": True, "промпт": промпт}


def _сосед(имя):
    """Сосед по папке завода. Грузим по ПУТИ, а не пакетом: модули дня
    зовутся и как скрипт, и как модуль, и пакетный импорт в первом случае
    падает `attempted relative import`."""
    import importlib.util
    п = os.path.join(os.path.dirname(os.path.abspath(__file__)), имя + ".py")
    с = importlib.util.spec_from_file_location(имя, п)
    м = importlib.util.module_from_spec(с)
    с.loader.exec_module(м)
    return м


def задания_пачки(ключ_персоны, запись, набор, кнопка, место, номер, папка):
    """Восемь записей пачки: шесть единиц плюс пара служебных кадров.

    Цена каждой берётся из сметы, а не пишется здесь второй раз: два места
    с одним числом разойдутся, и тогда расчёт дня честно покажет одно, а
    трата будет другой.
    """
    С = _сосед("смета")
    ц = С.ЦЕНЫ
    имя = lambda в: os.path.join(папка, "%s-%s" % (ключ_персоны, в))
    пара_одета = имя("odeta") + ".jpg"
    пара_ответ = имя("otvet") + ".jpg"
    з = []
    п = промпт_одетой(ключ_персоны, запись, набор)
    if not п.get("ок"):
        # Задание, которое нельзя исполнить, не кладётся в день вовсе:
        # иначе смета обещает трату, а сборка встанет на первой единице.
        return {"ок": False, "почему": "кадр одетой: %s" % п.get("почему")}
    лицо, почему_лица = лицо_эталон(ключ_персоны)
    if not лицо:
        return {"ок": False, "почему": "кадр одетой: %s" % почему_лица}
    з.append({"вид": "кадр_одетой", "служебное": True, "$": ц["кадр_1k_low"],
              "как": "apimodels 1K low, лицо референсом", "выход": пара_одета,
              "промпт": п["промпт"], "рефы": [лицо]})
    з.append({"вид": "ответ_бота", "служебное": True, "$": ц["снятие_ботом"],
              "как": "живой конвейер бота", "выход": пара_ответ,
              "кнопка": кнопка, "место": место, "вход": пара_одета})
    з.append({"вид": "формат1", "$": ц["кадр_2k_high"], "как": "ролик-показ + обложка",
              "выход": имя("f1") + ".mp4", "вход": пара_одета,
              "результат": пара_ответ, "кнопка": кнопка})
    з.append({"вид": "формат2", "$": round(ц["клип_3с"] / 3.0 * С.СЕКУНД_ФОРМАТА2
                                           + ц["кадр_2k_high"], 4),
              "как": "h3-lite, первый и последний кадр, %g с" % С.СЕКУНД_ФОРМАТА2,
              "выход": имя("f2") + ".mp4", "первый": пара_одета, "последний": пара_ответ})
    з.append({"вид": "формат3", "$": ц["кадр_2k_high"], "как": "сток + заголовок",
              "выход": имя("f3") + ".mp4"})
    з.append({"вид": "серия", "$": ц["кадр_2k_high"], "как": "общий файл серии + своя музыка и обложка",
              "выход": имя("seria") + ".mp4"})
    з.append({"вид": "пост", "$": ц["кадр_2k_high"], "как": "оправа + хромакей",
              "выход": имя("post") + ".jpg", "панель_лево": пара_одета,
              "панель_право": пара_ответ})
    з.append({"вид": "карусель", "$": round(ц["кадр_2k_high"] * С.СЛАЙДОВ_ГЕНЕРАЦИЕЙ, 4),
              "как": "%d слайдов 4:5 + финал кодом" % С.СЛАЙДОВ_ГЕНЕРАЦИЕЙ,
              "выход": имя("carousel"), "фото_дня": пара_одета})
    for e in з:
        e["персона"] = ключ_персоны
        e["пачка"] = номер
        e["кнопка"] = e.get("кнопка", кнопка)
        e["место"] = e.get("место", место)
    return {"ок": True, "задания": з, "$": round(sum(e["$"] for e in з), 4),
            "набор": набор, "кнопка": кнопка, "место": место}
