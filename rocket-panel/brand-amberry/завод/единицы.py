def _бот(имя):
    if БОТ not in sys.path:
        sys.path.insert(0, БОТ)
    return __import__(имя)


def кнопки():
    """Соло-кнопки раздевания - те же, что в боте. Три исхода."""
    try:
        return list(_бот("конвейер_соло").СОЛО), ""
    except Exception as e:
        return [], "кнопки у бота не спросились (%s): НЕ ЗАМЕРЕНО" % type(e).__name__


def места():
    try:
        return [м.key for м in _бот("места").ВСЕ], ""
    except Exception as e:
        return [], "места у бота не спросились (%s): НЕ ЗАМЕРЕНО" % type(e).__name__


def лицо_эталон(ключ):
    """Эталонное лицо персоны - референс в КАЖДЫЙ её кадр.

    Без него кадр одетой рождается из одного текстового описания, и лицо
    плывёт день ко дню: «пять персон» превращаются в пять описаний, под
    которыми каждый раз другая девушка, а лента держится именно на том,
    что её узнают.

    Версия «-лого» НЕ ГОДИТСЯ: на ней стоит знак бренда, и модель
    перенесёт его в кадр как часть лица.
    """
    папка = os.path.join(КОРЕНЬ, "персонажи")
    чистое = os.path.join(папка, "аватар-%s.jpg" % ключ)
    if os.path.exists(чистое):
        return чистое, ""
    return "", "эталона лица нет: %s" % чистое


def персоны():
    """Пять лиц. Ключи с подчёркиванием это заметки файла, а не люди:
    первый замер насчитал шесть персон из-за `_о_файле`, и день построил бы
    шестую пачку, у которой нет ни гардероба, ни аккаунтов."""
    import json
    with open(ПЕРСОНЫ, encoding="utf-8") as ф:
        д = json.load(ф)
    if not isinstance(д, dict):
        return {}
    return {к: з for к, з in д.items()
            if not к.startswith("_") and isinstance(з, dict)}


