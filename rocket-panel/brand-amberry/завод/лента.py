# -*- coding: utf-8 -*-
"""Дверь ленты AMBERRY: выложить файл и поставить публикацию в слот.

ПОЧЕМУ ОНА ЕСТЬ. `admin/соцсети.py` умеет только ЧИТАТЬ Zernio (профили,
аккаунты, свод) - POST там нет ни строкой, то есть поставить собранную
единицу в слот было нечем вовсе. Это дверь записи, и она одна: второй
путь публикации однажды уйдёт мимо заслонов.

ГРАБЛИ, КУПЛЕННЫЕ ЗАВОДОМ ОКО (повторять их заново незачем):
- поле зовётся `mediaItems`, и элемент это ОБЪЕКТ с url и type. С полем
  `media` подключение отвечает 400 «Tiktok posts require media content»,
  при загруженном файле и верном адресе;
- Zernio принимает ТОЛЬКО адреса. Локальный путь это 400 «Invalid media
  URL», поэтому выкладка живёт В ЭТОЙ ЖЕ двери: вызывающий не обязан про
  неё помнить;
- время идёт в `scheduledFor` плюс `timezone`. Мгновенная публикация
  пачкой это спам, и у нас её нет вовсе: лента живёт слотами.

ТРИ ИСХОДА У ПОСТАНОВКИ, и третий главный: поставлено / отказ сервиса с
причиной / НЕ ЗАМЕРЕНО (ключа нет, аккаунтов нет, сеть молчит). Пустой
успех при неподключённой площадке хуже отказа: по нему никто не идёт
подключать.
"""
import json, os, re, shutil, secrets, time, urllib.request, urllib.error

БАЗА = "https://zernio.com/api/v1"
ПАПКА_ЛЕНТЫ = os.environ.get("AMBERRY_LENTA_DIR", "/srv/lenta")
АДРЕС_ЛЕНТЫ = os.environ.get("AMBERRY_LENTA_URL", "https://amberry.app/lenta")
ПОЯС = "Europe/Moscow"
# Сколько держим выложенный файл. Площадка забирает его в момент слота,
# дальше он ей не нужен, а 18+ файл в открытой папке лишний день это лишний
# день. Чистка идёт в `подмести`, её зовёт конвейер дня.
ЖИВЁТ_ЧАСОВ = 48

ВИДЫ = {"ролик": "video", "пост": "image", "карусель": "image", "серия": "video"}


def _ключ():
    return (os.environ.get("ZERNIO_API_KEY") or "").strip()


def _запрос(метод, путь, тело=None, таймаут=30):
    """Возврат (ответ, почему). Пустое «почему» значит успех."""
    к = _ключ()
    if not к:
        return None, "ZERNIO_API_KEY не задан: НЕ ЗАМЕРЕНО, ставить нечем"
    данные = json.dumps(тело, ensure_ascii=False).encode() if тело is not None else None
    зап = urllib.request.Request(БАЗА + путь, data=данные, method=метод)
    зап.add_header("Authorization", "Bearer " + к)
    зап.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(зап, timeout=таймаут) as о:
            сырое = о.read().decode("utf-8", "replace")
        return (json.loads(сырое) if сырое.strip() else {}), ""
    except urllib.error.HTTPError as e:
        тело_о = ""
        try:
            тело_о = e.read().decode("utf-8", "replace")[:400]
        except Exception:
            pass
        # Причина берётся ИЗ ТЕЛА ответа, а не из кода: «400» не говорит,
        # что именно сервис не принял, и по нему чинить нечего.
        return None, "код %s: %s" % (e.code, тело_о or e.reason)
    except Exception as e:
        return None, "%s: %s" % (type(e).__name__, e)


ВИДЕО_ХВОСТЫ = (".mp4", ".mov", ".webm", ".m4v")


def тип_медиа(путь):
    """video или image. Тип идёт рядом с адресом: без него площадка берёт
    ролик за картинку и отдаёт один кадр."""
    н = str(путь).lower()
    return "video" if н.endswith(ВИДЕО_ХВОСТЫ) else "image"


def выложить(путь):
    """Локальный файл -> публичный адрес. Имя со случайным хвостом.

    Хвост не украшение: папка отдаётся статикой без листинга, и угадать
    имя соседней единицы по нашему же шаблону имён не должно получаться.
    """
    if not путь:
        return {"ок": False, "почему": "путь пуст"}
    if str(путь).startswith(("http://", "https://")):
        return {"ок": True, "адрес": путь, "как": "уже адрес"}
    if not os.path.exists(путь):
        return {"ок": False, "почему": "файла нет: %s" % путь}
    os.makedirs(ПАПКА_ЛЕНТЫ, exist_ok=True)
    осн, расш = os.path.splitext(os.path.basename(путь))
    # ИМЯ В АДРЕСЕ ТОЛЬКО ASCII. Первая проба дала
    # «https://amberry.app/lenta/проба-5c3388ba9d60.jpg»: такой адрес живёт
    # ровно до первой площадки, которая не разберёт percent-encoding, а
    # выглядит он работающим. Кириллица в имени не несёт смысла никому:
    # файл называет единицу, а не человека.
    осн = re.sub(r"[^a-z0-9-]+", "-", осн.lower()).strip("-")[:40] or "unit"
    расш = re.sub(r"[^a-z0-9.]+", "", (расш or ".bin").lower()) or ".bin"
    имя = "%s-%s%s" % (осн, secrets.token_hex(6), расш)
    цель = os.path.join(ПАПКА_ЛЕНТЫ, имя)
    врем = цель + ".part"
    shutil.copy2(путь, врем)
    os.replace(врем, цель)          # читатель не видит недописанный файл
    try:
        os.chmod(цель, 0o644)
    except Exception:
        pass
    return {"ок": True, "адрес": "%s/%s" % (АДРЕС_ЛЕНТЫ.rstrip("/"), имя),
            "файл": цель, "как": "выложено"}


def аккаунты_лица(ник, только_живые=True):
    """Живые аккаунты персоны в Zernio: список (платформа, ид).

    Ник берётся из паспорта персоны и сравнивается без собачки и регистра:
    в сервисе он лежит то так, то так.
    """
    о, почему = _запрос("GET", "/accounts")
    if о is None:
        return {"ок": False, "почему": почему, "площадки": []}
    строки = о if isinstance(о, list) else None
    if строки is None:
        for поле in ("data", "accounts", "items"):
            if isinstance(о.get(поле), list):
                строки = о[поле]
                break
    if строки is None:
        return {"ок": False, "почему": "ответ сервиса не содержит списка аккаунтов",
                "площадки": []}
    цель = str(ник or "").lstrip("@").lower()
    площадки, мёртвые = [], []
    for а in строки:
        н = str(а.get("username") or а.get("name") or "").lstrip("@").lower()
        if н != цель:
            continue
        жив = bool(а.get("isActive", True))
        пара = (а.get("platform"), а.get("id") or а.get("_id"))
        if жив or not только_живые:
            площадки.append(пара)
        else:
            мёртвые.append(пара)
    о2 = {"ок": True, "площадки": площадки, "мёртвые": мёртвые}
    if not площадки:
        о2["ок"] = False
        о2["почему"] = ("у «%s» живых аккаунтов нет%s: подключить в панели, "
                        "кодом это не лечится" % (ник,
                        (", мёртвых %d" % len(мёртвые)) if мёртвые else ""))
    return о2


def поставить(текст, площадки, когда, медиа=None, вид="ролик"):
    """Поставить единицу в слот. `когда` это ISO UTC, `площадки` - пары.

    Мгновенной публикации тут нет НАРОЧНО: лента живёт слотами, а залп на
    один аккаунт площадки читают как спам.
    """
    if not текст or not str(текст).strip():
        return {"ок": False, "почему": "текст пуст"}
    if not площадки:
        return {"ок": False, "почему": "площадок ноль: ставить некуда"}
    if not когда:
        return {"ок": False, "почему": "слот не назван: мгновенной публикации нет"}
    адреса = []
    for м in (медиа or []):
        в = выложить(м)
        if not в.get("ок"):
            return {"ок": False, "почему": "медиа не выложено: %s" % в.get("почему")}
        адреса.append({"url": в["адрес"], "type": тип_медиа(м)})
    тело = {"content": текст,
            "platforms": [{"platform": п, "accountId": a} for п, a in площадки],
            "scheduledFor": когда, "timezone": ПОЯС}
    if адреса:
        тело["mediaItems"] = адреса
    о, почему = _запрос("POST", "/posts", тело=тело)
    if о is None:
        return {"ок": False, "почему": почему, "слот": когда}
    return {"ок": True, "ид": о.get("id") or о.get("_id") or "",
            "слот": когда, "площадок": len(площадки), "медиа": len(адреса)}


def подмести(часов=ЖИВЁТ_ЧАСОВ):
    """Снять выложенное старше срока. 18+ файл не живёт в открытой папке дольше нужного."""
    if not os.path.isdir(ПАПКА_ЛЕНТЫ):
        return {"ок": True, "снято": 0}
    порог = time.time() - часов * 3600
    снято = 0
    for имя in os.listdir(ПАПКА_ЛЕНТЫ):
        п = os.path.join(ПАПКА_ЛЕНТЫ, имя)
        try:
            if os.path.isfile(п) and os.path.getmtime(п) < порог:
                os.remove(п)
                снято += 1
        except Exception:
            pass
    return {"ок": True, "снято": снято}
