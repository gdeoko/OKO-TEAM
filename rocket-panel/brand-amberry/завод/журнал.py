# -*- coding: utf-8 -*-
"""Журнал завода: что уже занято и сколько потрачено.

ПОЧЕМУ ОН ЕСТЬ. Реестра повторов у AMBERRY нет (у ОКО он в ядре, здесь
своего дома). Без журнала пять лент через неделю идут по кругу: та же
одежда, та же локация, тот же ракурс, та же кнопка бота - структура-то
одна. Журнал делает повтор невозможным ПО ПОСТРОЕНИЮ, а не по памяти
сборщика.

ТРИ ИСХОДА У ВЫБОРА, и третий главный: взяли незанятое / всё занято,
круг начат заново с пометкой / спросить было нечем (журнал не читается)
- тогда ведём себя как раньше и говорим это словами, а не молчим.

РАСХОД ПИШЕТСЯ ПО ФАКТУ ОТВЕТА СЕРВИСА, а не по плану: план врёт в обе
стороны, а счёт не врёт. Потолок дня держит `смета`, здесь только учёт.
"""
import datetime, json, os, fcntl, contextlib

ТУТ = os.path.dirname(os.path.abspath(__file__))
ПАПКА = os.path.join(ТУТ, "данные")
ЗАНЯТО = os.path.join(ПАПКА, "занято.json")
РАСХОД = os.path.join(ПАПКА, "расход.json")
# Сколько дней держим занятое, прежде чем вещь снова станет свободной.
# Одежда и локация примелькаются раньше ракурса, поэтому сроки разные.
ЗАБВЕНИЕ = {"одежда": 21, "локации": 14, "ракурсы": 7, "свет": 5,
            "кнопка": 10, "тема": 30, "формат_входа": 4, "музыка": 30}


def _день(сдвиг=0):
    return (datetime.date.today() + datetime.timedelta(days=сдвиг)).isoformat()


@contextlib.contextmanager
def _замок(путь):
    """Замок на СОСЕДНЕМ файле: на самом он слетает при подмене inode."""
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    зам = путь + ".lock"
    ф = open(зам, "a+")
    try:
        fcntl.flock(ф, fcntl.LOCK_EX)
        yield
    finally:
        try:
            fcntl.flock(ф, fcntl.LOCK_UN)
        finally:
            ф.close()


def _читать(путь):
    try:
        return json.load(open(путь, encoding="utf-8"))
    except FileNotFoundError:
        return {}
    except Exception:
        # Рваный json читается как ПУСТО и говорит об этом вызывающему,
        # а не притворяется «всё свободно»: иначе повторы пойдут пачкой.
        return None


def _писать(путь, д):
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    врем = путь + ".tmp"
    json.dump(д, open(врем, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    os.replace(врем, путь)


def свободное(персона, раздел, кандидаты, кроме=()):
    """Первое незанятое из списка. Три исхода в поле «как».

    как = «взято» / «круг» (всё занято, начали заново) / «не замерено».

    `кроме` ЭТО РАЗВЯЗКА ВНУТРИ ДНЯ, и без неё журнал бесполезен для
    ленты из пяти лиц. Журнал помнит занятое ПО ПЕРСОНЕ, поэтому пять
    пачек одного дня честно берут каждая «первое свободное у себя» - и
    получают одну и ту же кнопку, одно место, один ракурс и один хук.
    Живой сухой прогон дал ровно это: пять пачек, у всех `un_close` и
    `sc_bed`. Двадцать роликов оказались одним роликом в пяти лицах.
    """
    if not кандидаты:
        return {"ок": False, "как": "не замерено", "почему": "список пуст"}
    вне = set(кроме or ())
    свои_сегодня = [к for к in кандидаты if к not in вне]
    if свои_сегодня:
        кандидаты = свои_сегодня
    else:
        # Кандидатов меньше, чем пачек: развязать нечем, и это надо
        # сказать, а не молча повторить соседа.
        return {"ок": True, "что": кандидаты[0], "как": "тесно",
                "почему": "все %d заняты сегодня другими пачками" % len(кандидаты)}
    д = _читать(ЗАНЯТО)
    if д is None:
        return {"ок": True, "что": кандидаты[0], "как": "не замерено",
                "почему": "журнал не читается, ведём себя как раньше"}
    срок = ЗАБВЕНИЕ.get(раздел, 14)
    порог = _день(-срок)
    свои = (д.get(персона) or {}).get(раздел) or {}
    живые = {к: в for к, в in свои.items() if в >= порог}
    для_взятия = [к for к in кандидаты if к not in живые]
    if для_взятия:
        return {"ок": True, "что": для_взятия[0], "как": "взято"}
    return {"ок": True, "что": кандидаты[0], "как": "круг",
            "почему": "все %d заняты за %d дней" % (len(кандидаты), срок)}


def занять(персона, раздел, значение):
    """Пометить взятое. Идемпотентно: повтор в тот же день ничего не портит."""
    with _замок(ЗАНЯТО):
        д = _читать(ЗАНЯТО)
        if д is None:
            д = {}
        д.setdefault(персона, {}).setdefault(раздел, {})[значение] = _день()
        _писать(ЗАНЯТО, д)
    return True


def набор(персона, гардероб, нужно=("одежда", "локации", "ракурсы", "свет"),
          кроме=None):
    """Комплект на единицу: по одному незанятому из каждого раздела.

    `кроме` это {раздел: множество занятого СЕГОДНЯ}: ракурсы и свет у
    персон списками совпадают, и без развязки все пять пачек встают в один
    ракурс при одном свете.
    """
    # ПУСТОЙ СЛОВАРЬ ЛОЖЕН, И `or` ПОДМЕНЯЕТ ЕГО НОВЫМ. Стояло
    # `кроме = кроме or {}`, и на первой пачке дня (когда занятого ещё
    # нет) записи уходили в свежий словарь, а не в дневной: пачки 1 и 2
    # честно получали один ракурс при одном свете, а с третьей развязка
    # «заработала» - потому что к тому времени день успевал положить туда
    # кнопку и место. Беда, которая лечится сама по ходу, и есть самая
    # дорогая: она выглядит случайностью.
    if кроме is None:
        кроме = {}
    итог, пометки = {}, []
    for раздел in нужно:
        о = свободное(персона, раздел, гардероб.get(раздел) or [],
                      кроме=кроме.get(раздел) or ())
        if not о.get("ок"):
            return {"ок": False, "почему": "%s: %s" % (раздел, о.get("почему"))}
        итог[раздел] = о["что"]
        if о["как"] != "взято":
            пометки.append("%s: %s" % (раздел, о["как"]))
        кроме.setdefault(раздел, set()).add(о["что"])   # следующая пачка не повторит
    return {"ок": True, "набор": итог, "пометки": пометки}


def закрепить(персона, набор_):
    for раздел, значение in (набор_ or {}).items():
        занять(персона, раздел, значение)


def расход_записать(статья, сумма, подробно=""):
    """Факт списания. День берётся по UTC, как и счёт сервиса."""
    with _замок(РАСХОД):
        д = _читать(РАСХОД) or {}
        день = д.setdefault(_день(), {"итого": 0.0, "строки": []})
        день["итого"] = round(день["итого"] + float(сумма), 4)
        день["строки"].append({"статья": статья, "$": round(float(сумма), 4),
                               "что": подробно,
                               "когда": datetime.datetime.utcnow().strftime("%H:%M:%S")})
        _писать(РАСХОД, д)
        return день["итого"]


def потрачено(день=None):
    д = _читать(РАСХОД)
    if д is None:
        return None          # НЕ ЗАМЕРЕНО, а не ноль
    return float((д.get(день or _день()) or {}).get("итого") or 0.0)


def свод_расхода(день=None):
    д = _читать(РАСХОД) or {}
    return д.get(день or _день()) or {"итого": 0.0, "строки": []}
