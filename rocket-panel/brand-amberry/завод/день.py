def прогон(п):
    """Живой день: серия первой, пачки, постановка, канал, отчёт.

    ПОРЯДОК НЕ ПЕРЕСТАВЛЯЕТСЯ. Серия дороже всего и одна на пять пачек:
    упёршись в потолок на ней последней, день потеряет её после того, как
    двадцать единиц уже оплачены.

    ОДНА БЕДА НЕ ХОРОНИТ ДЕНЬ. Единица, которая не собралась, называется
    словами и пропускается: двадцать девять вышедших лучше нуля, а
    молчаливый пропуск хуже обоих - по нему никто не идёт чинить.
    """
    api, почему = И.апи()
    if api is None:
        return {"ок": False, "почему": почему}
    т0 = time.time()
    папка = п["папка"]
    было = Ж.потрачено() or 0.0
    собрано, беды, поставлено, время = [], [], [], {}

    # 1. СЕРИЯ ПЕРВОЙ
    ключ_сериала, номер = СР.сегодня(п["день"])
    план_серии = СР.план(ключ_сериала, номер)
    серия_файлы = {}
    if план_серии.get("ок"):
        тс = time.time()
        с = СР.собрать(план_серии, os.path.join(папка, "seria"), api)
        время["серия"] = round(time.time() - тс, 1)
        if с.get("ок"):
            в = СР.веер(с["файл"], [пач["персона"] for пач in п["пачки"]],
                        os.path.join(папка, "seria"))
            серия_файлы = в.get("файлы") or {}
            беды += ["серия/веер: %s" % б for б in (в.get("беды") or [])]
            беды += ["серия: %s" % б for б in (с.get("беды") or [])]
        else:
            беды.append("серия: %s" % с.get("почему"))
    else:
        беды.append("серия: %s" % план_серии.get("почему"))

    # 2. ПАЧКИ
    for пач in п["пачки"]:
        # ЗАНЯТОЕ ЗАКРЕПЛЯЕТСЯ ПРИ ИСПОЛНЕНИИ, А НЕ ПРИ ПЛАНИРОВАНИИ.
        # Журнал разводил наборы внутри дня, а в постоянную память не
        # писал ничего - `закрепить` не звал никто, и завтра та же персона
        # честно взяла бы ту же одежду, ту же локацию и ту же кнопку:
        # сроки забвения (21 день одежде, 14 локации, 7 ракурсу) не
        # работали вовсе. Закрепляем здесь, потому что план бесплатен и
        # гоняется кроном каждый день: закрепляя в плане, мы съедали бы
        # запас разнообразия без выпуска единиц.
        Ж.закрепить(пач["персона"], пач["набор"])
        Ж.занять(пач["персона"], "кнопка", пач["кнопка"])
        Ж.занять(пач["персона"], "место", пач["место"])
        for з in пач["задания"]:
            if з["вид"] == "серия":
                ф = серия_файлы.get(пач["персона"])
                if ф:
                    з["файл"] = ф
                    собрано.append(з)
                else:
                    беды.append("%s/серия: файла веера нет" % пач["персона"])
                continue
            тз = time.time()
            о = И.единица(з, api, папка, лента=Л)
            время.setdefault(з["вид"], []).append(round(time.time() - тз, 1))
            if о.get("ок"):
                з["файл"] = о.get("файл")
                з["обложка"] = о.get("обложка")
                if о.get("файлы"):
                    з["файлы"] = о["файлы"]
                if not з.get("служебное"):
                    собрано.append(з)
            else:
                беды.append("%s/%s: %s" % (пач["персона"], з["вид"],
                                           о.get("почему")))
                # Пара кадров держит четыре единицы: без неё пачку дальше
                # вести бессмысленно, и это говорится один раз.
                if з.get("служебное"):
                    беды.append("%s: пачка снята, пара кадров не вышла"
                                % пач["персона"])
                    break

    # 3. ПОСТАНОВКА В СЛОТЫ. Площадок нет - говорим ОДИН раз, а не
    # тридцать: тридцать одинаковых бед в отчёте прячут настоящие.
    живых = sum(len((Л.аккаунты_лица((Е.персоны().get(пач["персона"]) or {})
                                     .get("ник") or пач["персона"])
                     ).get("площадки") or []) for пач in п["пачки"])
    if not живых:
        беды.append("постановка пропущена: живых площадок в Zernio ноль, "
                    "единицы лежат файлами в %s" % папка)
    for з in (собрано if живых else []):
        if з.get("служебное") or not з.get("файл"):
            continue
        персона = з["персона"]
        ник = (Е.персоны().get(персона) or {}).get("ник") or персона
        а = Л.аккаунты_лица(ник)
        if not а.get("ок"):
            беды.append("%s/%s: %s" % (персона, з["вид"], а.get("почему")))
            continue
        # Карусель идёт ВСЕМИ слайдами: один файл из пяти это не карусель.
        о = Л.поставить(з.get("описание") or "", а["площадки"], з.get("слот"),
                        медиа=(з.get("файлы") or [з["файл"]]), вид=з["вид"])
        if о.get("ок"):
            поставлено.append({"персона": персона, "вид": з["вид"],
                               "слот": з.get("слот_мск"), "ид": о.get("ид")})
        else:
            беды.append("%s/%s постановка: %s" % (персона, з["вид"],
                                                  о.get("почему")))

    # 4. КАНАЛ: одна пачка, без цензуры
    в_канал = []
    чья = п.get("в канал")
    for з in собрано:
        if з["персона"] == чья and з["вид"] in В_КАНАЛ and з.get("файл"):
            в_канал.append(з)
    канал = К.пачкой(в_канал) if в_канал else {"ок": False,
                                               "почему": "в канал нечего"}
    стало = Ж.потрачено() or 0.0
    return {"ок": not беды, "беды": беды, "собрано": len(собрано),
            "поставлено": поставлено, "канал": канал, "время": время,
            "$план": п["смета"]["$"], "$факт": round(стало - было, 4),
            "сек": round(time.time() - т0, 1), "папка": папка}


def печать_итога(и, всего_сек):
    if not и.get("ок") and и.get("почему"):
        print("ПРОГОН НЕ ПОШЁЛ:", и["почему"])
        return
    print("собрано единиц: %d | поставлено в слоты: %d | в канал: %s"
          % (и["собрано"], len(и["поставлено"]),
             len((и["канал"] or {}).get("ушло") or [])))
    print("расход: план $%.3f, ФАКТ $%.3f (%s)"
          % (и["$план"], и["$факт"],
             "дешевле плана" if и["$факт"] <= и["$план"] else "ДОРОЖЕ ПЛАНА"))
    print("время: сборка %.1f мин, весь прогон %.1f мин"
          % (и["сек"] / 60.0, всего_сек / 60.0))
    for вид, в in (и.get("время") or {}).items():
        if isinstance(в, list) and в:
            print("   %-12s %d шт, по %.1f с (всего %.1f мин)"
                  % (вид, len(в), sum(в) / len(в), sum(в) / 60.0))
        elif isinstance(в, (int, float)):
            print("   %-12s %.1f с (%.1f мин)" % (вид, в, в / 60.0))
    if и.get("беды"):
        print("\nБЕДЫ (%d):" % len(и["беды"]))
        for б in и["беды"]:
            print("  -", б)
    сводка = Ж.свод_расхода()
    print("\nжурнал расхода за день: $%.4f, строк %d"
          % (сводка["итого"], len(сводка["строки"])))


