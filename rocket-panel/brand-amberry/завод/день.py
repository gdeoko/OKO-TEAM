def папка_дня(день=None):
    д = os.path.join(ПАПКА_ДНЕЙ, (день or datetime.date.today().isoformat()))
    os.makedirs(д, exist_ok=True)
    return д


def ворота(платно):
    """Что обязано быть на месте ДО первой траты. Три исхода у каждого."""
    беды, пометки = [], []
    п = Е.персоны()
    if len(п) != ПАЧЕК:
        беды.append("персон %d, а пачек %d: лента не сойдётся" % (len(п), ПАЧЕК))
    for ключ, запись in п.items():
        г = запись.get("гардероб") or {}
        пусто = [р for р in ("одежда", "локации", "ракурсы", "свет") if not г.get(р)]
        if пусто:
            беды.append("у «%s» пуст гардероб: %s" % (ключ, ", ".join(пусто)))
        if not (запись.get("внешность_англ") or "").strip():
            беды.append("у «%s» нет англ. внешности" % ключ)
    к, пк = Е.кнопки()
    м, пм = Е.места()
    if не_вышло(к, пк):
        беды.append("кнопки: %s" % пк)
    if не_вышло(м, пм):
        беды.append("места: %s" % пм)
    # ПЛОЩАДКИ. Их отсутствие НЕ останавливает сборку: собранная единица
    # лежит и ждёт подключения, а вот пустой успех постановки обманывал бы.
    живых = 0
    for ключ, запись in п.items():
        а = Л.аккаунты_лица(запись.get("ник") or ключ)
        if а.get("ок"):
            живых += len(а.get("площадки") or [])
        else:
            пометки.append("«%s»: %s" % (ключ, а.get("почему")))
    if not живых:
        пометки.append("живых площадок НОЛЬ: день соберётся, но ставить некуда")
    # ДЕНЬГИ. КЛЮЧ И БАЛАНС СПРАШИВАЮТСЯ ВСЕГДА, ОНИ СТОЯТ НУЛЯ.
    # Прежде ключ спрашивался только в платной ветке, и сухой прогон
    # печатал «ключ завода НЕТ» при живом ключе: не замерено выдавалось
    # за отсутствие. По такой печати владелец ищет ключ, который лежит.
    ключ_завода, баланс = "", None
    try:
        sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(ТУТ)), "bot"))
        import apimodels as А
        ключ_завода = А.ключ_завода()
        if ключ_завода:
            try:
                баланс = float(А.Api(key=ключ_завода).баланс(свежий=True))
            except Exception as e:
                пометки.append("баланс не спросился (%s): НЕ ЗАМЕРЕНО"
                               % type(e).__name__)
    except Exception as e:
        (беды if платно else пометки).append(
            "дверь apimodels не спросилась: %s" % type(e).__name__)
    см = С.день(ПАЧЕК, с_серией=True)
    if not ключ_завода:
        (беды if платно else пометки).append(
            "APIMODELS_KEY_ZAVOD не задан: лента идёт на ключе ЗАВОДА ОКО, "
            "а не бота, и подставлять ключ бота нельзя")
    # ДЕНЕГ НА СЧЁТЕ ДОЛЖНО ХВАТИТЬ НА ВЕСЬ ДЕНЬ, А НЕ НА ПЕРВЫЙ ВЫЗОВ.
    # Иначе прогон встанет на середине: двадцать единиц оплачены, серия
    # или карусель нет, и день выглядит браком при целом коде.
    if баланс is not None and баланс < см.get("$с_запасом", 0):
        (беды if платно else пометки).append(
            "на счёте $%.2f, а дню нужно $%.2f с запасом" % (баланс, см["$с_запасом"]))
    if платно:
        if not см.get("ок"):
            беды.append("смета: %s" % см.get("почему"))
        в = С.влезет(см.get("$", 0), Ж.потрачено())
        if not в.get("ок"):
            беды.append("потолок дня: %s" % в.get("почему"))
    return {"ок": not беды, "беды": беды, "пометки": пометки,
            "персон": len(п), "кнопок": len(к), "мест": len(м),
            "живых площадок": живых, "ключ завода": bool(ключ_завода),
            "баланс": баланс}


def не_вышло(список, почему):
    return (not список) or bool(почему)


def план(пачек=ПАЧЕК, день=None):
    """Полный план дня: серия, пачки, описания, слоты. Ни одной траты."""
    д = день or datetime.date.today().isoformat()
    папка = папка_дня(д)
    персоны = Е.персоны()
    к, _ = Е.кнопки()
    м, _ = Е.места()
    если_нет = {"ок": False, "почему": "кнопки или места не спросились у бота"}
    if not к or not м:
        return если_нет
    # СЕРИЯ ПЕРВОЙ И ОДНА НА ПЯТЬ ПАЧЕК. План её строится здесь же, чтобы
    # день было видно целиком: какой сериал, какая серия, сколько кадров.
    ключ_сериала, номер_серии_ = СР.сегодня(д)
    план_серии = СР.план(ключ_сериала, номер_серии_)
    серия = С.серия()
    серия["сериал"] = ключ_сериала
    серия["имя"] = план_серии.get("имя")
    серия["номер"] = номер_серии_
    серия["тема"] = план_серии.get("тема")
    серия["кадров"] = len(план_серии.get("кадры") or [])
    серия["план ок"] = план_серии.get("ок")
    серия["почему"] = план_серии.get("почему")
    пачки, беды = [], []
    if not план_серии.get("ок"):
        беды.append("серия: %s" % план_серии.get("почему"))
    # ЗАНЯТОЕ ДНЁМ ОДНО НА ВСЕ ПАЧКИ. Журнал помнит по персоне, а повтор
    # между лицами виден именно тому, кто смотрит две наши ленты сразу.
    занято = {}
    ключи = list(персоны)[:пачек]
    for н, ключ in enumerate(ключи, 1):
        запись = персоны[ключ]
        наб = Ж.набор(ключ, запись.get("гардероб") or {}, кроме=занято)
        if not наб.get("ок"):
            беды.append("%s: %s" % (ключ, наб.get("почему")))
            continue
        # Кнопка и место тоже идут через журнал: иначе пять пачек каждый
        # день берут первую кнопку списка, и «двадцать роликов» оказываются
        # одним роликом в двадцати лицах.
        кн = Ж.свободное(ключ, "кнопка", к, кроме=занято.get("кнопка") or ())
        мс = Ж.свободное(ключ, "место", м, кроме=занято.get("место") or ())
        занято.setdefault("кнопка", set()).add(кн.get("что"))
        занято.setdefault("место", set()).add(мс.get("что"))
        о = Е.задания_пачки(ключ, запись, наб["набор"], кн.get("что"),
                            мс.get("что"), н, папка)
        if not о.get("ок"):
            беды.append("%s: %s" % (ключ, о.get("почему")))
            continue
        слоты = СЛ.слоты_utc(ЕДИНИЦ_В_ПАЧКЕ, н - 1,
                             datetime.date.fromisoformat(д), пачек)
        мск = СЛ.слоты_мск(ЕДИНИЦ_В_ПАЧКЕ, н - 1, пачек)
        видимые = [з for з in о["задания"] if not з.get("служебное")]
        for i, з in enumerate(видимые):
            з["слот"] = слоты[i] if i < len(слоты) else ""
            з["слот_мск"] = ("%02d:%02d" % мск[i]) if i < len(мск) else ""
            оп = О.собрать(з["вид"], ключ, журнал=Ж, серия_номер=номер_серии_,
                           кроме=занято)
            з["описание"] = оп["текст"]
            з["описание_ок"] = оп["ок"]
            if not оп["ок"]:
                беды.append("%s/%s: описание %s" % (ключ, з["вид"], оп["беды"]))
        пачки.append({"персона": ключ, "номер": н, "набор": наб["набор"],
                      "кнопка": кн.get("что"), "место": мс.get("что"),
                      "$": о["$"], "задания": о["задания"],
                      "пометки": наб.get("пометки", [])})
    смета = С.день(len(пачки), с_серией=True)
    return {"ок": not беды, "беды": беды, "день": д, "папка": папка,
            "серия": серия, "пачки": пачки, "смета": смета,
            "в канал": канальная_пачка(д, [п["персона"] for п in пачки])}


def номер_серии(день):
    """Серия идёт по одной в сутки: номер это день месяца, 1-10 в сериале."""
    д = datetime.date.fromisoformat(день)
    return (д.toordinal() % 10) + 1


def канальная_пачка(день, ключи):
    """Чья пачка уходит в канал сегодня. По дню, а не случайно."""
    if not ключи:
        return ""
    д = datetime.date.fromisoformat(день)
    return ключи[д.toordinal() % len(ключи)]


