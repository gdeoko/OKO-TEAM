#!/usr/bin/env python3
"""Хвост ролика: результат есть, но его не видно.

Решение владельца 26.09.2026. Резкий чёрный экран в конце читается как
обрыв или ошибка: человек думает, что ролик битый, и уходит. Здесь
кадр НЕ обрывается - он продолжает двигаться, но с момента, где
начинается то, чего площадка не пустит, уходит в муть. Видно, что бот
работает и выдал результат; не видно, какой. Это и есть предложение.

Три вещи, на которых держится приём:

МУТЬ НАРАСТАЕТ, А НЕ ВКЛЮЧАЕТСЯ. Мгновенная подмена кадра выглядит
склейкой - глаз читает её как «тут отрезали». За 0.4 секунды кадр
уходит в муть плавно, и это читается как «идёт обработка».

МУТЬ ОДНА, НО СИЛЬНАЯ. Крупный пиксель убран решением владельца
26.09.2026: сетка квадратов на движении мерцает, кадр рябит в глазах и
выглядит браком. Осталось размытие, и раз оно теперь одно - оно взято
заметно крепче прежнего. Слабое размытие восстановимо и оставляет
читаемый силуэт; сильное не оставляет ничего, кроме движения, а это и
есть то, что мы показываем. Половинная муть, сквозь которую угадывается
тело, хуже полной по обеим статьям сразу: площадке видно, что спрятано,
а человеку видно достаточно, чтобы не идти в бота.

ПЛАШКА НЕ НАЗЫВАЕТ ТО, ЧТО СПРЯТАНО. «Продолжение в боте» - можно.
Подпись, объясняющая, что именно под мутью, превращает ролик в рекламу
наготы, и дальше вопрос только в том, кто пожалуется первым.

    python3 замутить.py ролик.mp4 3.5            муть с 3.5 секунды
    python3 замутить.py ролик.mp4 3.5 --призыв 2
"""
import os
import re
import subprocess
import sys

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ТУТ = os.path.dirname(os.path.abspath(__file__))
БРЕНД = os.path.dirname(ТУТ)
ЛОГО = os.path.join(БРЕНД, "amberry-icon-512-alpha.png")
ШРИФТ_Ж = "/home/user/OKO-TEAM/.claude/skills/reels-machine/fonts/montserrat-v31-cyrillic_latin-900.ttf"
ШРИФТ_П = "/home/user/OKO-TEAM/.claude/skills/reels-machine/fonts/montserrat-v31-cyrillic_latin-700.ttf"

РОЗОВЫЙ = (255, 10, 140)
ФИОЛЕТОВЫЙ = (122, 43, 255)
БЕЛЫЙ = (255, 255, 255)
НИК = "@theamberrybot"

# Те же призывы, что в аутро: хвост и аутро - одна мысль, разорви её
# разными словами, и человек прочитает их как два разных предложения.
ПРИЗЫВЫ = [
    "ПРОДОЛЖЕНИЕ В БОТЕ",
    "ССЫЛКА В ПРОФИЛЕ",
    "ДАЛЬШЕ — ПО ССЫЛКЕ",
    "ОСТАЛЬНОЕ ТАМ",
    "ПЕРВАЯ — БЕСПЛАТНО",
]

# Насколько плавно кадр уходит в муть. Меньше 0.25 с глаз читает как
# склейку, больше 0.6 с - успеваешь разглядеть то, что прячем.
РАЗГОН = 0.4

# РАЗГОН НАЧИНАЕТСЯ ЗАРАНЕЕ, А НЕ В САМ МОМЕНТ.
#
# Первая версия закрывала кадр начиная с указанной секунды - и ровно
# эти 0.4 секунды, пока муть набирала силу, показывали то, ради чего
# всё и затевалось. Поэтому секунда, которую называют скрипту, это
# момент, когда показывать УЖЕ НЕЛЬЗЯ, и к нему кадр обязан прийти
# закрытым. Разгон кладётся перед ней.


def ffmpeg():
    """Тот ffmpeg, что есть. Системного в облачной сессии нет."""
    for путь in ("/usr/bin/ffmpeg", "/usr/local/bin/ffmpeg"):
        if os.path.exists(путь):
            return путь
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


def размер(видео):
    """Ширина, высота, длительность и частота кадров.

    ffprobe рядом нет - читаем то, что ffmpeg пишет в stderr про вход.
    """
    п = subprocess.run([ffmpeg(), "-hide_banner", "-i", видео],
                       capture_output=True, text=True)
    текст = п.stderr
    м = re.search(r"(\d{2,5})x(\d{2,5})", текст)
    д = re.search(r"Duration: (\d+):(\d+):([\d.]+)", текст)
    if not м or not д:
        raise SystemExit(f"не разобрать видео: {видео}")
    ч, мин, с = д.groups()
    к = re.search(r"([\d.]+) fps", текст)
    return (int(м.group(1)), int(м.group(2)),
            int(ч) * 3600 + int(мин) * 60 + float(с),
            float(к.group(1)) if к else 30.0)


def неон(холст, текст, шрифт, y, цвет=РОЗОВЫЙ, ядро=БЕЛЫЙ, сила=16):
    """Надпись неоновой трубкой - как в аутро и на аватарках."""
    слой = Image.new("RGBA", холст.size, (0, 0, 0, 0))
    д = ImageDraw.Draw(слой)
    x0, y0, x1, y1 = д.textbbox((0, 0), текст, font=шрифт)
    x = (холст.size[0] - (x1 - x0)) // 2 - x0
    д.text((x, y), текст, font=шрифт, fill=цвет + (255,))
    свечение = слой.filter(ImageFilter.GaussianBlur(сила))
    холст.alpha_composite(свечение)
    холст.alpha_composite(свечение)
    ImageDraw.Draw(холст).text((x, y), текст, font=шрифт, fill=ядро + (255,))


def плашка(ш, в, призыв):
    """Прозрачная плашка поверх мути: рамка, призыв, лого, ник.

    Центр пустой - под ним должно быть видно движение. Если закрыть
    кадр целиком, получится та же чёрная заставка, от которой уходим.
    """
    холст = Image.new("RGBA", (ш, в), (0, 0, 0, 0))

    # Неоновая рамка по краю: она отделяет «так задумано» от «видео
    # сломалось». Без рамки муть читается как брак кодека.
    рамка = Image.new("RGBA", (ш, в), (0, 0, 0, 0))
    д = ImageDraw.Draw(рамка)
    поле = max(8, ш // 90)
    д.rounded_rectangle((поле, поле, ш - поле, в - поле),
                        radius=max(18, ш // 34),
                        outline=РОЗОВЫЙ + (230,), width=max(4, ш // 200))
    холст.alpha_composite(рамка.filter(ImageFilter.GaussianBlur(max(6, ш // 90))))
    холст.alpha_composite(рамка.filter(ImageFilter.GaussianBlur(2)))

    # Затемнение к низу, чтобы текст читался на любой мути.
    тень = Image.new("L", (ш, в), 0)
    т = ImageDraw.Draw(тень)
    for i in range(в // 3):
        y = в - 1 - i
        т.line((0, y, ш, y), fill=int(215 * (i / (в / 3)) ** 2.0))
    холст.alpha_composite(Image.composite(
        Image.new("RGBA", (ш, в), (7, 6, 10, 255)),
        Image.new("RGBA", (ш, в), (0, 0, 0, 0)), тень))

    лого = Image.open(ЛОГО).convert("RGBA")
    бок = max(96, ш // 7)
    лого = лого.resize((бок, бок), Image.LANCZOS)
    низ = в - int(в * 0.055)
    y_лого = низ - бок - int(ш * 0.20)
    свет = Image.new("RGBA", (ш, в), (0, 0, 0, 0))
    свет.paste(лого, ((ш - бок) // 2, y_лого), лого)
    холст.alpha_composite(свет.filter(ImageFilter.GaussianBlur(max(10, ш // 60))))
    холст.alpha_composite(свет)

    ж = ImageFont.truetype(ШРИФТ_Ж, max(34, ш // 16))
    п = ImageFont.truetype(ШРИФТ_П, max(22, ш // 30))
    неон(холст, призыв, ж, y_лого + бок + int(ш * 0.045))
    неон(холст, НИК, п, y_лого + бок + int(ш * 0.045) + int(ш * 0.085),
         цвет=ФИОЛЕТОВЫЙ, сила=12)
    return холст


def замутить(видео, момент, призыв_i=0, выход=None):
    ш, в, длит, кадров = размер(видео)
    if момент >= длит:
        raise SystemExit(f"момент {момент} с за пределами ролика ({длит:.1f} с)")
    призыв = ПРИЗЫВЫ[призыв_i % len(ПРИЗЫВЫ)]
    начало = max(0.0, момент - РАЗГОН)
    выход = выход or os.path.splitext(видео)[0] + "-муть.mp4"

    png = os.path.join(ТУТ, ".плашка.png")
    плашка(ш, в, призыв).save(png)

    # Одно размытие, но крепкое: пиксельная сетка снята (рябила), и её
    # долю в сокрытии забрала сигма - она вдвое больше прежней.
    сигма = max(34, ш // 11)
    т = f"{начало:.3f}"
    доля = f"min(1,max(0,(T-{т})/{РАЗГОН}))"

    # Плашка ПРОЯВЛЯЕТСЯ вместе с мутью, а не выскакивает готовой:
    # выскочившая читается как баннер поверх чужого видео, проявленная -
    # как часть самого ролика. Отсюда loop+fade: одиночную картинку
    # нечем растянуть во времени, а fade без кадров не работает.
    фильтр = (
        f"[0:v]split=2[чист][грязь];"
        f"[грязь]gblur=sigma={сигма}:steps=4[муть];"
        f"[чист][муть]blend=all_expr='A*(1-{доля})+B*{доля}'[кадр];"
        f"[1:v]format=rgba,loop=loop=-1:size=1:start=0,"
        f"fps={кадров:.4f},setpts=N/FRAME_RATE/TB,"
        f"fade=t=in:st={т}:d={РАЗГОН}:alpha=1[плашка];"
        f"[кадр][плашка]overlay=0:0:shortest=1:format=auto[вых]"
    )
    cmd = [ffmpeg(), "-y", "-hide_banner", "-loglevel", "error",
           "-i", видео, "-i", png,
           "-filter_complex", фильтр, "-map", "[вых]"]
    # Звук переносим как есть, если он был.
    cmd += ["-map", "0:a?", "-c:a", "copy"]
    cmd += ["-c:v", "libx264", "-preset", "medium", "-crf", "19",
            "-pix_fmt", "yuv420p", "-movflags", "+faststart", выход]
    subprocess.run(cmd, check=True)
    os.remove(png)
    return выход


if __name__ == "__main__":
    сырое = sys.argv[1:]
    i, арг = 0, []
    пропустить = False
    for н, a in enumerate(сырое):
        if пропустить:
            пропустить = False
            continue
        if a == "--призыв":
            i = int(сырое[н + 1])
            пропустить = True          # иначе номер призыва уедет в имя файла
        elif not a.startswith("--"):
            арг.append(a)
    if len(арг) < 2:
        raise SystemExit(__doc__)
    готово = замутить(арг[0], float(арг[1]), i,
                      арг[2] if len(арг) > 2 else None)
    print(готово)
