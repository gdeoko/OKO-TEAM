#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Заголовок ролика: пачка от семи вариантов, выбор числом.

Правило завода (`oko-rezultat`): ОДИН ХУК ЭТО НЕ ВЫБОР. На каждый ролик
пишется от семи вариантов, и лучший берётся по баллу, а не на глаз.
Второй по баллу не выбрасывается - уходит во второй заход.

Балл считается вычитанием из ста: штамп минус сорок, вода минус двадцать
пять, нет конкретики минус двадцать, длиннее ста знаков минус до тридцати.
Здесь добавлены два своих штрафа под нашу ленту: наведение на живого
человека (это не штраф, а полный запрет, ноль баллов) и повтор заголовка,
который уже выходил.

    python3 заголовки.py <формат> <стадия> [семя]
    python3 заголовки.py 2 tofu ника-пирс-20260927
"""
import hashlib
import json
import os
import random
import re
import sys

ТУТ = os.path.dirname(os.path.abspath(__file__))
РЕЕСТР = os.path.join(ТУТ, ".реестр-заголовков.json")

# ── ЗАПРЕТ, КОТОРЫЙ НЕ ОБСУЖДАЕТСЯ ──────────────────────────────────────
# Наведение на конкретного живого человека. Не осторожность: это
# единственная формулировка, за которую площадки сносят аккаунт целиком
# вместе с доменом бота, без разбора и без апелляции.
ЗАПРЕТ = ("её", "ее", "бывш", "сосед", "однокласс", "коллег", "подруг",
          "жену", "сестр", "училк", "препод", "знакому")

# Из раздела 1.4б контент-завода: что бракует текст целиком.
ШТАМПЫ = ("уникальн", "эксклюзив", "революцион", "комплексн", "ключев",
          "актуальн", "лучш", "топов", "гарантирован", "не просто",
          "качественн", "профессиональн", "инновацион")
# Метка возраста в заголовке ролика - прямой повод для проверки площадкой.
ВОЗРАСТ = ("18+", "18 +", "21+", "xxx", "nsfw")
ВОДА = ("возможно", "довольно", "весьма", "некотор", "различн", "разнообразн",
        "поистине", "настоящ", "просто так", "в целом", "именно то")


def балл(текст):
    """Сто минус штрафы. Ноль значит заголовок не выйдет никогда."""
    н = текст.lower()
    if any(с in н for с in ЗАПРЕТ):
        return 0
    б = 100
    if any(с in н for с in ВОЗРАСТ):
        б -= 60
    if any(с in н for с in ШТАМПЫ):
        б -= 40
    if any(с in н for с in ВОДА):
        б -= 25
    # Конкретика - это число, срок, факт или указание на то, что в кадре.
    конкретика = (re.search(r"\d", текст)
                  or re.search(r"размыт|цензур|бесплатн|секунд|фото|бот", н))
    if not конкретика:
        б -= 20
    if len(текст) > 100:
        б -= min(30, (len(текст) - 100) // 2)
    if "—" in текст or "–" in текст:      # длинное тире запрещено везде
        б -= 15
    if re.search(r"не .+,\s*а ", н):       # противопоставление «не X, а Y»
        б -= 20
    return max(0, б)


# ── МЕХАНИКИ ────────────────────────────────────────────────────────────
#
# Заготовки не список на все времена, а образцы механики: под каждый ролик
# берётся механика и пишется своё. Разбор 25 хуков-лидеров Virlo показал,
# что в топе НЕТ ни одного рекламного - лидеры звучат как реплика
# человека, который что-то заметил, а продукт появляется после.

# Форматы 1 и 2: наша модель, наша муть. Можно указывать на то, что в
# кадре, потому что это наша работа и она там правда есть.
СВОИ = {
    "муть": ["Здесь размыто. В боте нет",
             "Это всё, что можно показать здесь",
             "Дальше площадка не пропускает",
             "Размытие поставили мы. В боте его нет"],
    "площадка": ["Соцсети режут. Бот нет",
                 "Тут нельзя. Там можно",
                 "Бот не спрашивает, что можно показывать"],
    "цифра": ["26 секунд на одно фото",
              "Одно фото. 26 секунд",
              "Первое фото бесплатно"],
    # МЕТКИ «18+» В ЗАГОЛОВКЕ НЕТ. Снято владельцем 27.09.2026: площадки
    # ловят её как объявление взрослого контента и задают вопросы ещё до
    # того, как посмотрят сам ролик. Намёк работает так же, а вопросов не
    # вызывает.
    "намёк": ["Полная версия там, где её не режут",
              "Остальное не для ленты",
              "Продолжение не здесь"],
}

# Формат 3: чужой сток. Про кадр говорить нельзя - модель снималась для
# другого, и лицензия прямо запрещает показывать её в порочащем виде.
# Говорим про инструмент и про фото зрителя.
СТОК = {
    "инструмент": ["Любое фото. Без одежды. 26 секунд",
                   "Здесь фото раздеваются",
                   "Фото оживёт. И разденется"],
    "намёк": ["Тут показать нельзя",
              "Остальное в боте",
              "Здесь только половина"],
    "вход": ["Первое бесплатно. Дальше сам решишь",
             "Первое фото ничего не стоит"],
    "обращение": ["Ты знаешь, зачем ты здесь",
                  "Открой бота и проверь"],
}

# Стадия воронки решает, о чём заголовок (`oko-funnel`). Первое касание
# без цены: в первом ролике «бесплатно» читается как реклама.
СТАДИИ = {
    "tofu": ("муть", "площадка", "намёк", "обращение"),
    "mofu": ("цифра", "инструмент", "муть"),
    "bofu": ("вход", "цифра", "намёк"),
}


def пачка(формат, стадия="tofu", семя="", сколько=7):
    """Семь и больше вариантов под формат и стадию, уже с баллами."""
    набор = СТОК if str(формат) == "3" else СВОИ
    сл = random.Random(hashlib.sha1(str(семя).encode()).hexdigest())
    годные = [м for м in СТАДИИ.get(стадия, СТАДИИ["tofu"]) if м in набор]
    if not годные:
        годные = list(набор)
    варианты = []
    for м in годные:
        варианты += [(т, м) for т in набор[м]]
    # Семь вариантов это минимум по правилу завода, а не пожелание. Если
    # механик стадии не хватило - добираем из остальных того же формата,
    # иначе выбор превращается в «что было, то и взяли».
    if len(варианты) < сколько:
        for м, список in набор.items():
            if м in годные:
                continue
            варианты += [(т, м) for т in список]
    сл.shuffle(варианты)

    было = прошлые()
    итог = []
    for т, м in варианты:
        б = балл(т)
        if т in было:
            б -= 50            # повтор в ленте читается как штамповка
        итог.append({"текст": т, "механика": м, "балл": max(0, б)})
    итог.sort(key=lambda в: -в["балл"])
    return итог[:max(сколько, 7)]


def прошлые():
    if not os.path.exists(РЕЕСТР):
        return set()
    with open(РЕЕСТР, encoding="utf-8") as ф:
        return set(json.load(ф).get("вышли", []))


def записать(текст):
    было = sorted(прошлые() | {текст})
    with open(РЕЕСТР, "w", encoding="utf-8") as ф:
        json.dump({"вышли": было}, ф, ensure_ascii=False, indent=1)


def выбрать(формат, стадия="tofu", семя=""):
    п = пачка(формат, стадия, семя)
    лучший, второй = п[0], (п[1] if len(п) > 1 else None)
    return {"лучший": лучший, "второй": второй, "пачка": п}


if __name__ == "__main__":
    а = sys.argv[1:]
    и = выбрать(а[0] if а else "2", а[1] if len(а) > 1 else "tofu",
                а[2] if len(а) > 2 else "проба")
    for в in и["пачка"]:
        print("%3d  %-12s %s" % (в["балл"], в["механика"], в["текст"]))
    print("\nв ролик:", и["лучший"]["текст"])
    if и["второй"]:
        print("во второй заход:", и["второй"]["текст"])
