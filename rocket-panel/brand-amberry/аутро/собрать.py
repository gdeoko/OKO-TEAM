#!/usr/bin/env python3
"""Аутро роликов AMBERRY: последний кадр, ради которого ролик и снимают.

Собирается КОДОМ, а не генерацией: лого должно быть настоящим, пиксель в
пиксель из пака, а не перерисованной моделью ягодой. Канон разрешает
инфографику и аутро кодом, а вот наложение текста поверх сгенерированного
кадра - нет, поэтому аутро это отдельный кадр, а не плашка на видео.

Формат 1080x1920 под вертикаль. Держим четыре вещи и ничего лишнего:
ягода, слово AMBERRY, ник бота с иконкой Телеграма, призыв.

Призыв меняется от ролика к ролику - одинаковый в каждом кадре
примелькается и перестаёт читаться. Список в ПРИЗЫВЫ, берём по кругу.

    python3 собрать.py            все варианты
    python3 собрать.py 0          один
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ТУТ = os.path.dirname(os.path.abspath(__file__))
БРЕНД = os.path.dirname(ТУТ)
ЛОГО = os.path.join(БРЕНД, "amberry-icon-512.png")
ШРИФТ_Ж = "/home/user/OKO-TEAM/.claude/skills/reels-machine/fonts/montserrat-v31-cyrillic_latin-900.ttf"
ШРИФТ_П = "/home/user/OKO-TEAM/.claude/skills/reels-machine/fonts/montserrat-v31-cyrillic_latin-700.ttf"

Ш, В = 1080, 1920
РОЗОВЫЙ = (255, 10, 140)
СВЕТЛЫЙ = (255, 180, 215)
БЕЛЫЙ = (255, 255, 255)
ЧЁРНЫЙ = (7, 6, 10)
НИК = "@theamberrybot"

ПРИЗЫВЫ = [
    "ПРОДОЛЖЕНИЕ В БОТЕ",
    "ССЫЛКА В ПРОФИЛЕ",
    "ДАЛЬШЕ — ПО ССЫЛКЕ",
    "ОСТАЛЬНОЕ ТАМ",
    "ПЕРВАЯ — БЕСПЛАТНО",
]


ФИОЛЕТОВЫЙ = (122, 43, 255)


def фон():
    """Чёрный, свечение от лого и фирменные неоновые трубки по краям.

    Трубки те же, что в кадрах персонажей и на заставке бота: розовая
    слева, фиолетовая справа. Без них аутро выглядит пустой заставкой и
    не читается как продолжение ролика.
    """
    к = Image.new("RGB", (Ш, В), ЧЁРНЫЙ)
    свет = Image.new("L", (Ш, В), 0)
    д = ImageDraw.Draw(свет)
    д.ellipse((Ш // 2 - 430, В // 2 - 640, Ш // 2 + 430, В // 2 - 80), fill=125)
    свет = свет.filter(ImageFilter.GaussianBlur(190))
    розовый = Image.new("RGB", (Ш, В), РОЗОВЫЙ)
    к = Image.composite(розовый, к, свет).convert("RGBA")

    трубки = Image.new("RGBA", (Ш, В), (0, 0, 0, 0))
    т = ImageDraw.Draw(трубки)
    # слева две розовые, справа две фиолетовые, разной длины и яркости
    for x, y0, y1, ширина, цвет, alpha in (
            (58, 120, 980, 30, РОЗОВЫЙ, 235),
            (150, 620, 1560, 18, РОЗОВЫЙ, 150),
            (Ш - 64, 240, 1180, 30, ФИОЛЕТОВЫЙ, 235),
            (Ш - 158, 60, 760, 18, ФИОЛЕТОВЫЙ, 150)):
        т.rounded_rectangle((x - ширина // 2, y0, x + ширина // 2, y1),
                            radius=ширина // 2, fill=цвет + (alpha,))
    сияние = трубки.filter(ImageFilter.GaussianBlur(46))
    к.alpha_composite(сияние)
    к.alpha_composite(сияние)
    к.alpha_composite(трубки.filter(ImageFilter.GaussianBlur(3)))
    return к


def неон(холст, текст, шрифт, y, цвет=РОЗОВЫЙ, ядро=БЕЛЫЙ, сила=18):
    """Надпись неоновой трубкой: мягкое свечение и светлое ядро."""
    слой = Image.new("RGBA", холст.size, (0, 0, 0, 0))
    д = ImageDraw.Draw(слой)
    x0, y0, x1, y1 = д.textbbox((0, 0), текст, font=шрифт)
    x = (Ш - (x1 - x0)) // 2 - x0
    д.text((x, y), текст, font=шрифт, fill=цвет + (255,))
    свечение = слой.filter(ImageFilter.GaussianBlur(сила))
    холст.alpha_composite(свечение)
    холст.alpha_composite(свечение)
    ImageDraw.Draw(холст).text((x, y), текст, font=шрифт, fill=ядро + (255,))
    return y1 - y0


def телеграм(размер):
    """Иконка Телеграма: рисуем сами, чтобы не тащить чужой файл."""
    и = Image.new("RGBA", (размер, размер), (0, 0, 0, 0))
    д = ImageDraw.Draw(и)
    д.ellipse((0, 0, размер, размер), fill=БЕЛЫЙ + (255,))
    м = размер / 100.0
    # самолётик
    д.polygon([(22 * м, 52 * м), (78 * м, 28 * м), (66 * м, 74 * м),
               (50 * м, 60 * м), (40 * м, 70 * м), (40 * м, 57 * м)],
              fill=(20, 20, 26, 255))
    return и


def кадр(призыв, путь):
    к = фон()
    # ягода
    лого = Image.open(ЛОГО).convert("RGBA")
    # у файла чёрный фон - вырезаем его, чтобы ягода легла на свечение
    пиксели = лого.load()
    for yy in range(лого.size[1]):
        for xx in range(лого.size[0]):
            r, g, b, a = пиксели[xx, yy]
            if r + g + b < 60:
                пиксели[xx, yy] = (0, 0, 0, 0)
    лого = лого.resize((430, 430), Image.LANCZOS)
    сияние = лого.filter(ImageFilter.GaussianBlur(40))
    к.alpha_composite(сияние, ((Ш - 430) // 2, 430))
    к.alpha_composite(лого, ((Ш - 430) // 2, 430))

    неон(к, "AMBERRY", ImageFont.truetype(ШРИФТ_Ж, 168), 900)
    # ник с иконкой Телеграма
    ш_ник = ImageFont.truetype(ШРИФТ_П, 62)
    д = ImageDraw.Draw(к)
    шир = д.textbbox((0, 0), НИК, font=ш_ник)[2]
    икона = телеграм(76)
    всего = 76 + 26 + шир
    x = (Ш - всего) // 2
    к.alpha_composite(икона, (x, 1118))
    д.text((x + 76 + 26, 1124), НИК, font=ш_ник, fill=СВЕТЛЫЙ + (255,))
    # призыв
    неон(к, призыв, ImageFont.truetype(ШРИФТ_Ж, 76), 1320, цвет=РОЗОВЫЙ,
         ядро=БЕЛЫЙ, сила=14)
    к.convert("RGB").save(путь, quality=95)
    return путь


if __name__ == "__main__":
    какие = [int(sys.argv[1])] if len(sys.argv) > 1 else range(len(ПРИЗЫВЫ))
    for i in какие:
        п = кадр(ПРИЗЫВЫ[i], os.path.join(ТУТ, "аутро-%d.jpg" % (i + 1)))
        print("готово:", os.path.basename(п), "|", ПРИЗЫВЫ[i])
