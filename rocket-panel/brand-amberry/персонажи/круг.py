#!/usr/bin/env python3
"""Как аватарка будет выглядеть в кружке соцсети.

Квадрат в ленте режется в круг, и по углам уходит примерно 21% площади.
На глаз это не считается: осевая раскладка бренд-аватарки выглядела
безупречно квадратом, а в круге у слова AMBERRY срезало первую «A» и
последнюю «Y» - в ленте читалось «AMBERR». Поэтому каждую аватарку
прогоняем здесь ДО публикации.

    python3 круг.py аватар-ника.jpg [ещё файлы...]

Рядом с каждым файлом кладёт `<имя>-в-круге.jpg`.
"""
import os
import sys

from PIL import Image, ImageDraw

ФОН = (10, 6, 12)          # как тёмная тема ленты, чтобы срез был виден


def в_круге(путь):
    им = Image.open(путь).convert("RGB")
    ш, в = им.size
    if ш != в:
        print("%s: не квадрат (%dx%d) - соцсеть обрежет ещё и по краям" % (
            os.path.basename(путь), ш, в))
        р = min(ш, в)
        им = им.crop(((ш - р) // 2, (в - р) // 2, (ш + р) // 2, (в + р) // 2))
        ш = в = р
    маска = Image.new("L", (ш, ш), 0)
    ImageDraw.Draw(маска).ellipse((0, 0, ш, ш), fill=255)
    круг = Image.new("RGB", (ш, ш), ФОН)
    круг.paste(им, (0, 0), маска)
    имя = os.path.splitext(путь)[0] + "-в-круге.jpg"
    круг.save(имя, quality=92)
    print("готово:", os.path.basename(имя))
    return имя


if __name__ == "__main__":
    файлы = sys.argv[1:]
    if not файлы:
        raise SystemExit(__doc__)
    for ф in файлы:
        в_круге(ф)
