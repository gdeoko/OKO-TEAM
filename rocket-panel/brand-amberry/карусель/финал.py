#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Последний слайд карусели: настоящий кадр бота под мутью, аутро поверх.

Решение владельца 28.09.2026: все слайды кроме последнего - генерация
APIMODELS, а последний собирается кодом из НАСТОЯЩЕГО результата бота.
Смысл тот же, что у хвоста ролика (`../цензура/замутить.py`): видно, что
бот выдал результат, и не видно, какой. Нарисованный «результат» этого не
даёт - человек читает картинку как обещание, а не как работу.

Четыре слоя снизу вверх:

    1. кадр бота, обрезанный под 4:5 и размытый до цветовых пятен
    2. карточка аутро из `../ролик-снятие/карточка.py` - ОДНО описание
       на ролики и на карусель: разойдутся два - разойдётся и вид
    3. вырезанная девушка с заставки, та же, что в аутро роликов
    4. нумерация слайдов

МУТЬ БЕРЁТСЯ ТОЙ ЖЕ СИЛЫ, ЧТО В РОЛИКАХ (`сигма = ш // 11`, четыре
прохода). Половинная муть хуже полной по обеим статьям сразу: площадке
видно, что спрятано, а человеку видно достаточно, чтобы не идти в бота.
Считается она тут не ffmpeg'ом, а уменьшением и обратным растягиванием -
для одной картинки это то же самое на глаз и втрое быстрее.

    python3 финал.py [выход.png] [призыв]
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ТУТ = os.path.dirname(os.path.abspath(__file__))
БРЕНД = os.path.dirname(ТУТ)
sys.path.insert(0, os.path.join(БРЕНД, "ролик-снятие"))

Ш, В = 1080, 1350
КАРТА_В = 1150             # карточка живёт выше, чтобы призыв не закрыла девушка
ДЕВУШКА_В = 430            # НИЖЕ призыва, справа, как в аутро роликов
ВЫРЕЗ = os.path.join(БРЕНД, "рамка", "без-фона", "и0001.png")
ШРИФТ_Ж = "/home/user/OKO-TEAM/.claude/skills/reels-machine/fonts/montserrat-v31-cyrillic_latin-900.ttf"

# Настоящий результат бота для Ники. Наружу резким не уходит никогда -
# маска `результат-*` лежит в .gitignore, и здесь он только под мутью.
КАДР = os.path.join(БРЕНД, "ролик-снятие",
                    "результат-ника-пляж-вечер-купальник.jpg")


def подложка():
    """Кадр бота: обрезка под 4:5 по центру и муть до цветовых пятен."""
    и = Image.open(КАДР).convert("RGB")
    к = max(Ш / и.width, В / и.height)
    и = и.resize((round(и.width * к), round(и.height * к)), Image.LANCZOS)
    x, y = (и.width - Ш) // 2, (и.height - В) // 2
    и = и.crop((x, y, x + Ш, y + В))
    # Первая проба была замутнена вшестеро слабее - и сквозь неё читалось
    # тело целиком. Это худший из возможных исходов: площадке видно, что
    # спрятано, а человеку видно достаточно, чтобы не идти в бота. От
    # кадра остаются цветовые пятна и ничего больше.
    и = и.resize((Ш // 34, В // 34), Image.BILINEAR)
    и = и.resize((Ш, В), Image.BICUBIC).filter(ImageFilter.GaussianBlur(22))
    return и.convert("RGBA")


def карточка_аутро(призыв):
    import карточка as к
    п = os.path.join(ТУТ, ".карта.png")
    # Рамку рисуем сами: карточка обвела бы свои 1150, а лист 1350,
    # и прямоугольник кончился бы посреди слайда.
    к.карточка(п, призыв, ш=Ш, в=КАРТА_В, фон=False, рамка=False)
    return Image.open(п).convert("RGBA")


def девушка():
    д = Image.open(ВЫРЕЗ).convert("RGBA")
    ш = round(д.width * ДЕВУШКА_В / д.height)
    return д.resize((ш, ДЕВУШКА_В), Image.LANCZOS)


def рамка(холст):
    """Неоновый край на весь лист - тот же приём, что в хвосте ролика."""
    слой = Image.new("RGBA", (Ш, В), (0, 0, 0, 0))
    р = ImageDraw.Draw(слой)
    р.rounded_rectangle((12, 12, Ш - 13, В - 13), radius=32,
                        outline=(255, 10, 140, 255), width=5)
    свет = слой.filter(ImageFilter.GaussianBlur(18))
    холст.alpha_composite(свет)
    холст.alpha_composite(слой)


def нумерация(холст, номер, всего):
    р = ImageDraw.Draw(холст)
    ш = ImageFont.truetype(ШРИФТ_Ж, 40)
    т = "%d/%d" % (номер, всего)
    к = р.textbbox((0, 0), т, font=ш)
    x, y = Ш - (к[2] - к[0]) - 52, 44
    for сдвиг, цвет in (((0, 0), (255, 10, 140, 190)),):
        р.text((x + сдвиг[0], y + сдвиг[1]), т, font=ш, fill=цвет,
               stroke_width=6, stroke_fill=(255, 10, 140, 130))
    р.text((x, y), т, font=ш, fill=(255, 255, 255, 235))


def собрать(выход, призыв="ПЕРВАЯ — БЕСПЛАТНО", номер=6, всего=6):
    холст = подложка()
    рамка(холст)
    холст.alpha_composite(карточка_аутро(призыв), (0, 0))
    д = девушка()
    холст.alpha_composite(д, (Ш - д.width - 24, В - д.height))
    нумерация(холст, номер, всего)
    холст.convert("RGB").save(выход, quality=95)
    п = os.path.join(ТУТ, ".карта.png")
    if os.path.exists(п):
        os.remove(п)
    return выход


if __name__ == "__main__":
    выход = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ТУТ, "6-финал.jpg")
    призыв = sys.argv[2] if len(sys.argv) > 2 else "ПЕРВАЯ — БЕСПЛАТНО"
    print(собрать(выход, призыв))
