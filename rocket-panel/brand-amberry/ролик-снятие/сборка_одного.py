#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Две версии из ОДНОЙ генерации: для соцсетей и для телеграма.

    python3 сборка_одного.py <лицо> <ролик.mp4> <момент> [призыв]

Генерация одна и та же, монтаж разный:

    соцсети   муть с указанной секунды + живой интерфейс бота + карточка
    телеграм  без мути, только карточка в конце - кнопка на бота
              вешается на сам пост

МОМЕНТ - секунда, В КОТОРУЮ показывается то, что нельзя показывать.
Разгон мути кладётся ПЕРЕД ней (РАЗГОН), иначе ровно эти доли секунды
покажут то, ради чего всё и затевалось.

Три правила владельца, на которых держится весь монтаж (26.09.2026):

1. Муть ПОЗЖЕ и МЯГЧЕ. Ранняя и глухая муть убивает ролик: зритель не
   успевает понять, что это тот же человек и то же движение, и читает
   кадр как серое пятно. Под мутью ОБЯЗАНО идти движение - не стоп-кадр:
   силуэт продолжает раздеваться, и человек верит, что это правда.
2. Наложения РАЗНЫЕ на каждый ролик. Набор, места и секунды берёт
   `наложения.расклад()` по семени - лента не должна узнавать кадр.
3. Звук ОБЯЗАТЕЛЕН и всегда свой: музыка с проявкой и затуханием плюс
   щелчок на каждое нажатие (`звук.дорожка()`).
"""
import os
import re
import subprocess
import sys

ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ТУТ)
import карточка as К                                          # noqa: E402
import наложения as Н                                         # noqa: E402
import звук as З                                              # noqa: E402

Ш, В, КАДРЫ = 1080, 1920, 30

# Муть: короткий разгон вплотную к моменту и умеренная сила. Прежние
# 0.5 с и sigma=98 владелец забраковал - «рановато и слишком сильная,
# ничего не понятно». 46 на ширине 1080 стирает детали тела начисто, но
# силуэт, поза и движение остаются читаемыми.
РАЗГОН, ДЕРЖАТЬ = 0.32, 0.15
# ГРОМКОСТЬ РОДНОГО ЗВУКА МОДЕЛИ в общей смеси. Своя дорожка (музыка и
# щелчки по кнопкам) остаётся как была, родной звук ложится ПОД неё: он
# даёт комнату и движение, которых у музыки нет. Ноль — вернуть прежнее
# поведение, когда слышна только наша дорожка.
РОДНОЙ_ЗВУК = float(os.environ.get("AMBERRY_NATIVE_AUDIO", "0.8"))
СИГМА = 34

ВСПЫШКА, ПРОЯВКА = 0.30, 0.22
ВСПЛЫТИЕ = 52          # на столько пикселей элемент подъезжает снизу
ПОДЪЁМ = 0.26          # за столько секунд


def ffmpeg():
    for п in ("/usr/bin/ffmpeg", "/usr/local/bin/ffmpeg"):
        if os.path.exists(п):
            return п
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


def длительность(в):
    п = subprocess.run([ffmpeg(), "-hide_banner", "-i", в], capture_output=True, text=True)
    м = re.search(r"Duration: (\d+):(\d+):([\d.]+)", п.stderr)
    ч, мин, с = м.groups()
    return int(ч)*3600 + int(мин)*60 + float(с)


def ровно(вход, выход):
    """Лента к общему виду: 1080x1920 и 30 к/с.

    ПЛАВНОСТЬ ДЕЛАЕТСЯ ИНТЕРПОЛЯЦИЕЙ, А НЕ ДУБЛИРОВАНИЕМ. Карта отдаёт
    16 к/с, ролик идёт в 30: простой `fps=30` повторяет то один кадр, то
    два - движение начинает дёргаться в одном и том же ритме, и это
    владелец 27.09.2026 назвал «видео лагает». `minterpolate` дорисовывает
    промежуточные кадры по движению, и рывки уходят.

    Считается это ДО увеличения кадра: на 640x1152 проход занимает
    секунды, на 1080x1920 - минуты, а результат тот же."""
    subprocess.run([ffmpeg(), "-y", "-hide_banner", "-loglevel", "error", "-i", вход,
                    "-vf", f"minterpolate=fps={КАДРЫ}:mi_mode=mci:mc_mode=aobmc:"
                           f"me_mode=bidir:vsbmc=1,"
                           f"scale={Ш}:{В}:force_original_aspect_ratio=increase,"
                           f"crop={Ш}:{В},format=yuv420p",
                    # ЗВУК ЛЕНТЫ СОХРАНЯЕМ. Здесь стояло `-an`, и это было
                    # верно, пока ролики считала карта: звука у неё нет
                    # вовсе, глушить было нечего. `minimax-h3-lite` отдаёт
                    # РОДНУЮ синхронную дорожку в том же файле (проверено
                    # 01.10.2026: aac LC, 32000 Hz, stereo), и `-an` стирал
                    # её до того, как кто-то услышал. Копируем как есть:
                    # интерполяция кадров звука не касается, а у немого
                    # исходника копировать просто нечего — ffmpeg от этого
                    # не падает.
                    "-c:a", "copy",
                    "-c:v", "libx264", "-preset", "medium", "-crf", "16",
                    выход], check=True)
    return выход


def есть_звук(файл):
    """Есть ли в файле звуковая дорожка. Разбор того же `-i`, которым
    рядом меряется длительность: отдельный ffprobe на серверах бывает не
    установлен, а ffmpeg есть всегда."""
    п = subprocess.run([ffmpeg(), "-hide_banner", "-i", файл],
                       capture_output=True, text=True)
    return bool(re.search(r"Stream #\d+:\d+.*: Audio:", п.stderr))


# Холст под элемент: с запасом по ширине, иначе длинная строка обрежется
# по краю PNG, а не по рамке.
РАЗМЕРЫ = {"кнопка": (900, 250), "пузырь": (1010, 280), "работа": (940, 320),
           "цена": (900, 230), "готово": (860, 230), "списано": (680, 210)}


def картинки(набор, раб):
    """PNG на каждый элемент расклада: обычный и, у кнопок, нажатый."""
    пути = []
    for i, э in enumerate(набор):
        ш, в_ = РАЗМЕРЫ[э["вид"]]
        своё = {"файл": os.path.join(раб, "н%d.png" % i), "ш": ш, "в": в_}
        Н.сделать(э["вид"], своё["файл"], э["текст"], "", ш, в_)
        if э.get("нажатие"):
            своё["нажат"] = os.path.join(раб, "н%dн.png" % i)
            Н.сделать(э["вид"], своё["нажат"], э["текст"], "нажата", ш, в_)
        пути.append(своё)
    return пути


def слой(поток, имя, нач, кон, y, подъём=True, проявка=ПРОЯВКА):
    """Один элемент: проявляется, подъезжает снизу, тает.

    Подъём идёт выражением по t прямо в overlay - отдельным кадрам
    анимации тут взяться неоткуда, а статичная плашка, возникающая из
    ничего, смотрится как баннер, а не как интерфейс.

    ПОДЪЁМ БЫВАЕТ ТОЛЬКО У ПОЯВЛЕНИЯ. Раньше кнопка резалась на три
    куска (до нажатия, нажата, после), и каждый кусок подъезжал снизу
    заново: кнопка дёргалась, а на стыках в кадре были видны ДВЕ её
    копии на разной высоте, полупрозрачные, одна над другой. Это и есть
    «глюки в кнопках» от 27.09.2026."""
    вход = (f"[{поток}:v]format=rgba,loop=loop=-1:size=1:start=0,"
            f"fps={КАДРЫ},setpts=N/FRAME_RATE/TB,"
            f"fade=t=in:st={нач:.2f}:d={проявка}:alpha=1,"
            f"fade=t=out:st={max(нач, кон-проявка):.2f}:d={проявка}:alpha=1[{имя}]")
    сдвиг = f"{y}+{ВСПЛЫТИЕ}*(1-min(1\\,max(0\\,(t-{нач:.2f})/{ПОДЪЁМ})))"
    y_ = f"'{сдвиг}'" if подъём else str(y)
    нал = (f"overlay=(W-w)/2:{y_}:"
           f"enable='between(t,{нач:.2f},{кон:.2f})':format=auto:shortest=1")
    return вход, нал


def собрать(лицо, клип, момент=None, призыв=None, с_мутью=True, выход=None,
            семя=None):
    раб = os.path.join(ТУТ, ".работа")
    os.makedirs(раб, exist_ok=True)
    призыв = призыв or К.ПРИЗЫВЫ[0]
    лента = ровно(клип, os.path.join(раб, "лента-одна.mp4"))
    полная = длительность(лента)
    момент = float(момент) if момент else полная * 0.7
    семя = семя or ("%s-%s" % (лицо, os.path.basename(клип)))
    выход = выход or os.path.join(
        ТУТ, "%s-%s.mp4" % ("соцсети" if с_мутью else "телеграм", лицо))

    # Карточка выходит сразу за закрытием кадра, а в телеграме - к концу.
    старт = (момент + ДЕРЖАТЬ) if с_мутью else max(0.5, полная - 2.6)
    до = (момент - РАЗГОН - 0.25) if с_мутью else полная - 3.0
    набор = Н.расклад(семя, max(1.5, до))
    файлы = картинки(набор, раб)

    ряд = os.path.join(раб, "ряд")
    К.ряд(ряд, призыв)

    входы = ["-i", лента, "-framerate", str(КАДРЫ), "-i", os.path.join(ряд, "кадр%03d.png")]
    номер = 2
    for э, ф_ in zip(набор, файлы):
        э["поток"] = номер
        входы += ["-i", ф_["файл"]]
        номер += 1
        if "нажат" in ф_:
            э["поток_нажат"] = номер
            входы += ["-i", ф_["нажат"]]
            номер += 1

    ф = []
    if с_мутью:
        т = f"{max(0.0, момент - РАЗГОН):.3f}"
        доля = f"min(1,max(0,(T-{т})/{РАЗГОН}))"
        ф += ["[0:v]split=2[чист][грязь]",
              f"[грязь]gblur=sigma={СИГМА}:steps=4[муть]",
              f"[чист][муть]blend=all_expr='A*(1-{доля})+B*{доля}'[кадр]"]
    else:
        ф.append("[0:v]null[кадр]")
    пред = "кадр"

    нажатия = []
    for i, (э, ф_) in enumerate(zip(набор, файлы)):
        y = int(В * э["y"])
        # Элемент лежит ОДНИМ слоем на весь свой срок, и только вспышка
        # нажатия кладётся поверх него - тем же кадром, той же высоты,
        # просто ярче. Раньше он резался на куски, и кнопка прыгала.
        куски = [("эл%d" % i, э["поток"], э["вход"], э["уход"], True, ПРОЯВКА)]
        if "поток_нажат" in э:
            нажат_в = э.get("нажат_в", (э["вход"] + э["уход"]) / 2)
            нажат_в = min(max(нажат_в, э["вход"] + ПРОЯВКА),
                          э["уход"] - ВСПЫШКА - 0.05)
            if нажат_в > э["вход"]:
                нажатия.append(round(нажат_в, 2))
                куски.append(("наж%d" % i, э["поток_нажат"], нажат_в,
                              нажат_в + ВСПЫШКА, False, 0.05))
        for имя, поток, нач, кон, подъём, пр in куски:
            if кон <= нач:
                continue
            вход, нал = слой(поток, имя, нач, кон, y, подъём, пр)
            ф.append(вход)
            ф.append(f"[{пред}][{имя}]{нал}[н{имя}]")
            пред = "н" + имя

    ф.append(f"[1:v]format=rgba,fps={КАДРЫ},tpad=stop_mode=clone:stop_duration=30,"
             f"setpts=PTS-STARTPTS+{старт:.3f}/TB[карта]")
    ф.append(f"[{пред}][карта]overlay=0:0:enable='gte(t,{старт:.3f})':"
             f"format=auto:shortest=1[вых]")

    немой = os.path.join(раб, "немой-%s.mp4" % ("соц" if с_мутью else "тг"))
    subprocess.run([ffmpeg(), "-y", "-hide_banner", "-loglevel", "error"] + входы + [
        "-filter_complex", ";".join(ф), "-map", "[вых]", "-an",
        "-c:v", "libx264", "-preset", "medium", "-crf", "19",
        "-pix_fmt", "yuv420p", немой], check=True)

    дор = None
    try:
        дор = З.дорожка(семя, полная, sorted(нажатия),
                        ffmpeg(), os.path.join(раб, "звук-%s.m4a" % (
                            "соц" if с_мутью else "тг")))
    except Exception as e:
        print("звук не собрался (%s) - ролик выйдет немым" % e, flush=True)
    # РОДНОЙ ЗВУК МОДЕЛИ сводится с нашей дорожкой здесь, на последнем
    # шаге: к этому моменту длительности уже сошлись, и `amix` нечего
    # растягивать. Раньше в этом месте выбиралась ровно одна дорожка -
    # наша, - потому что родной не существовало.
    родной = РОДНОЙ_ЗВУК > 0 and есть_звук(лента)
    общее = [ffmpeg(), "-y", "-hide_banner", "-loglevel", "error", "-i", немой]
    if дор and родной:
        subprocess.run(общее + ["-i", дор, "-i", лента, "-filter_complex",
                                "[2:a]volume=%.2f[своё];"
                                "[1:a][своё]amix=inputs=2:duration=first:"
                                "dropout_transition=0,"
                                "aformat=sample_fmts=fltp:sample_rates=48000:"
                                "channel_layouts=stereo[звук]" % РОДНОЙ_ЗВУК,
                                "-map", "0:v", "-map", "[звук]",
                                "-c:v", "copy", "-c:a", "aac", "-b:a", "192k",
                                "-shortest", "-movflags", "+faststart",
                                выход], check=True)
        print("звук: наша дорожка + родная модели (%.0f%%)"
              % (РОДНОЙ_ЗВУК * 100), flush=True)
    elif дор:
        subprocess.run(общее + ["-i", дор, "-map", "0:v", "-map", "1:a",
                                "-c:v", "copy", "-c:a", "aac", "-b:a", "192k",
                                "-shortest", "-movflags", "+faststart",
                                выход], check=True)
    elif родной:
        # Своя дорожка не собралась — родная лучше тишины.
        subprocess.run(общее + ["-i", лента, "-map", "0:v", "-map", "1:a",
                                "-c:v", "copy", "-c:a", "aac", "-b:a", "192k",
                                "-shortest", "-movflags", "+faststart",
                                выход], check=True)
        print("звук: только родной модели", flush=True)
    else:
        subprocess.run(общее + ["-c", "copy", "-movflags", "+faststart",
                                выход], check=True)

    что = ", ".join("%s %s %.1f-%.1f" % (э["вид"], э["текст"][:14], э["вход"], э["уход"])
                    for э in набор)
    print("наложения:", что, flush=True)
    print("готово:", выход, os.path.getsize(выход), "байт", flush=True)
    return выход


if __name__ == "__main__":
    а = sys.argv[1:]
    if len(а) < 3:
        raise SystemExit(__doc__)
    лицо, клип, момент = а[0], а[1], а[2]
    призыв = а[3] if len(а) > 3 else None
    собрать(лицо, клип, момент, призыв, с_мутью=True)
    собрать(лицо, клип, момент, призыв, с_мутью=False)
