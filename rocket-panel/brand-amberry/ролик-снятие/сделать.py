"""Формат 2 одной командой: от пустого места до готового ролика.

    export APIMODELS_KEY=... ROCKET_GPU_URL=... ROCKET_GPU_USER=... ROCKET_GPU_PASS=...
    python3 сделать.py ника 1                 # лицо и номер сцены
    python3 сделать.py ника 1 --момент 2.9    # если шов ставить руками

Шесть проходов подряд, каждый со своим файлом на диске:

    1. кадр «одета»        APIMODELS
    2. кадр «в купальнике» APIMODELS
    3. кадр «результат»    наша карта, промптом самого бота
    4-6. три отрезка       наша карта, из каждого кадра свой
    7. сборка              ffmpeg: швы, муть, кнопки, карточка

ПРОДОЛЖАЕТ С МЕСТА ОБРЫВА. Готовый файл шагом считается сделанным и
заново не считается: проходов много, длятся они минутами, и упасть на
шестом, потеряв пять, - это терять карту и кредиты на ровном месте.
Переделать шаг - удалить его файл.
"""
import os
import subprocess
import sys

ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ТУТ)

import кадр_снятия as К                                       # noqa: E402
import движение as Д                                          # noqa: E402
import результат as Р                                         # noqa: E402
import сборка_ролика as С                                     # noqa: E402


def есть(путь):
    return путь and os.path.exists(путь) and os.path.getsize(путь) > 10_000


def кадр(лицо, номер, вид):
    п = os.path.join(ТУТ, "вход-%s-%s-%s.jpg" % (лицо, К.СЦЕНЫ[номер]["имя"], вид))
    if есть(п):
        print("есть, пропускаю:", os.path.basename(п), flush=True)
        return п
    # Фильтр модели иногда отказывает на ровном месте - он стохастический,
    # и вторая попытка тем же текстом обычно проходит.
    # Третья попытка идёт ПОСПОКОЙНЕЕ: фильтр отбивает не вещь, а
    # плотность слов вокруг неё, и то же самое более простыми словами
    # проходит там, где подробное описание не проходит никогда.
    for попытка in range(4):
        try:
            если = К.сделать(лицо, номер, вид, мягче=(попытка >= 2))
        except Exception as e:
            print("  сбой:", str(e)[:150], flush=True)
            если = None
        if есть(если):
            return если
        print("  попытка %d не дала кадра" % (попытка + 1), flush=True)
    raise SystemExit("не вышло сделать кадр %s/%s" % (вид, К.СЦЕНЫ[номер]["имя"]))


def подрезать_тёмное(кадр_пути):
    """У кадра-результата низ приезжает тёмным - так устроен промпт бота.
    Под мутью тёмная полоса читается как смена сцены, поэтому она уходит
    до генерации отрезка."""
    from PIL import Image
    import numpy as np
    вых = кадр_пути.replace(".jpg", "-кадр.jpg")
    if есть(вых):
        return вых
    и = Image.open(кадр_пути).convert("RGB")
    строки = np.asarray(и.convert("L").resize((64, 200)), dtype=float).mean(axis=1)
    порог = строки[:120].mean() * 0.45
    край = 200
    for y in range(120, 200):
        if строки[y:].max() < порог:
            край = y
            break
    и.crop((0, 0, и.width, int(и.height * край / 200))) \
     .resize((С.Ш, С.В), Image.LANCZOS).save(вых, quality=95)
    print("низ подрезан на %d%%: %s" % (100 - край // 2, os.path.basename(вых)), flush=True)
    return вых


def отрезок(кадр_пути, шаг, лицо, имя_сцены):
    п = os.path.join(ТУТ, ".работа", "%s-%s-%s.mp4" % (лицо, имя_сцены, шаг))
    os.makedirs(os.path.dirname(п), exist_ok=True)
    if есть(п):
        print("есть, пропускаю:", os.path.basename(п), flush=True)
        return п
    return Д.снять(кадр_пути, шаг, п, 5)


def сделать(лицо, номер, призыв=None):
    сцена = К.СЦЕНЫ[номер]["имя"]
    print("=== %s, сцена %s ===" % (лицо, сцена), flush=True)
    одета = кадр(лицо, номер, "одежда")
    купальник = кадр(лицо, номер, "купальник")

    рез = os.path.join(ТУТ, "результат-%s-%s-купальник.jpg" % (лицо, сцена))
    if not есть(рез):
        рез = Р.снять(купальник, "un_full", рез)
    else:
        print("есть, пропускаю:", os.path.basename(рез), flush=True)
    рез = подрезать_тёмное(рез)

    a = отрезок(одета, "одежда", лицо, сцена)
    b = отрезок(купальник, "купальник", лицо, сцена)
    c = отрезок(рез, "результат", лицо, сцена)

    вых = os.path.join(ТУТ, "снятие-%s-%s.mp4" % (лицо, сцена))
    return С.собрать(лицо, a, b, c, вых, призыв)


if __name__ == "__main__":
    а = [x for x in sys.argv[1:] if not x.startswith("--")]
    if not а:
        raise SystemExit(__doc__)
    лицо = а[0].lower()
    номер = int(а[1]) if len(а) > 1 else 0
    сделать(лицо, номер, а[2] if len(а) > 2 else None)
