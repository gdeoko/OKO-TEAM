#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Формат 2 «Снимает лишнее»: из кадра движения собирает готовый ролик.

    python3 сборка_ролика.py <лицо> <движение.mp4> [выход.mp4] [момент] [призыв]

Складывает ffmpeg, а не браузер: Chromium не пишет видео с прозрачностью,
а запись играющего мутного кадра 1080x1920 в headless теряет кадры.
Прозрачные наложения - кнопки и карточка - снимаются отдельными кадрами
(`карточка.py`) и кладутся поверх фильтром overlay.

ЧТО ПРОИСХОДИТ ВО ВРЕМЕНИ

    0.0                      момент                    конец
    |---- она снимает лишнее ---|------ муть + карточка ------|
         кнопки бота всплывают   ^
                                 к этой секунде кадр
                                 ОБЯЗАН быть закрыт

МОМЕНТ - это секунда, когда показывать уже нельзя, а не когда начинать
прятать. Разгон мути кладётся ПЕРЕД ней: в первой версии `замутить.py`
эти доли секунды показывали ровно то, ради чего всё затевалось.

ХВОСТ РАСТЯГИВАЕТСЯ. Карта отдаёт пять секунд, из них на муть с карточкой
остаётся полторы - за них карточку не прочитать. Поэтому кусок после
момента идёт медленнее почти вдвое. Под сильной мутью замедление не
видно: там нет ни одной детали, по которой глаз мог бы сверить скорость.
"""
import os
import re
import subprocess
import sys

ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ТУТ)
import карточка as К                                          # noqa: E402

Ш, В, КАДРЫ = 1080, 1920, 30
РАЗГОН = 0.5          # сколько муть набирает силу, в секундах
ЗАМЕДЛЕНИЕ = 1.8      # во сколько раз тянем хвост под мутью
ДЕРЖАТЬ = 0.15        # пауза между закрытием кадра и выходом карточки

# Кнопки бота: что и когда всплывает. Две за ролик, максимум три, и
# только в нижней трети - на лице им делать нечего.
КНОПКИ = ["Раздеть", "Соло"]
ВСПЫШКА = 0.32        # сколько держится нажатая кнопка
ПРОЯВКА = 0.22        # сколько кнопка проявляется и тает


def расставить(окно):
    """Разложить кнопки по окну до мути. Числа не вшиты: ролик бывает
    короче, и жёсткие секунды у такого налезли бы на закрытый кадр."""
    доля = окно / len(КНОПКИ)
    ряд = []
    for i, текст in enumerate(КНОПКИ):
        н = i * доля + доля * 0.12
        ряд.append({"текст": текст, "вход": round(н, 2),
                    "нажатие": round(н + доля * 0.45, 2),
                    "уход": round(н + доля * 0.80, 2)})
    return ряд


def ffmpeg():
    for п in ("/usr/bin/ffmpeg", "/usr/local/bin/ffmpeg"):
        if os.path.exists(п):
            return п
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


def размер(видео):
    """Ширина, высота, длительность. ffprobe рядом нет - читаем stderr ffmpeg."""
    п = subprocess.run([ffmpeg(), "-hide_banner", "-i", видео],
                       capture_output=True, text=True)
    м = re.search(r"(\d{2,5})x(\d{2,5})", п.stderr)
    д = re.search(r"Duration: (\d+):(\d+):([\d.]+)", п.stderr)
    if not м or not д:
        raise SystemExit("не разобрать видео: " + видео)
    ч, мин, с = д.groups()
    return int(м.group(1)), int(м.group(2)), int(ч)*3600 + int(мин)*60 + float(с)


def выровнять(вход, выход):
    """Привести к 1080x1920 и 30 к/с: карта отдаёт свой размер и свои кадры."""
    subprocess.run([ffmpeg(), "-y", "-hide_banner", "-loglevel", "error",
                    "-i", вход, "-vf",
                    f"scale={Ш}:{В}:force_original_aspect_ratio=increase,"
                    f"crop={Ш}:{В},fps={КАДРЫ},format=yuv420p",
                    "-an", "-c:v", "libx264", "-preset", "medium", "-crf", "17",
                    выход], check=True)
    return выход


def растянуть(вход, выход, момент):
    """Замедлить всё после момента. Отдаёт путь И новый момент на новой ленте:
    лента после растяжки другая, и старая секунда на ней уже не та."""
    рез = max(0.0, момент - РАЗГОН)
    subprocess.run([ffmpeg(), "-y", "-hide_banner", "-loglevel", "error",
                    "-i", вход, "-filter_complex",
                    f"[0:v]trim=0:{рез:.3f},setpts=PTS-STARTPTS[a];"
                    f"[0:v]trim={рез:.3f},setpts=(PTS-STARTPTS)*{ЗАМЕДЛЕНИЕ}[b];"
                    f"[a][b]concat=n=2:v=1[v]",
                    "-map", "[v]", "-an", "-c:v", "libx264", "-preset", "medium",
                    "-crf", "17", "-pix_fmt", "yuv420p", выход], check=True)
    return выход, рез + РАЗГОН * ЗАМЕДЛЕНИЕ


def собрать(лицо, движение, выход=None, момент=None, призыв=None):
    выход = выход or os.path.join(ТУТ, "снятие-%s.mp4" % лицо)
    призыв = призыв or К.ПРИЗЫВЫ[sum(map(ord, os.path.basename(выход))) % len(К.ПРИЗЫВЫ)]
    раб = os.path.join(ТУТ, ".работа")
    os.makedirs(раб, exist_ok=True)

    ровно = выровнять(движение, os.path.join(раб, "ровно.mp4"))
    _, _, длит = размер(ровно)
    # По умолчанию закрываем на двух третях: к этому времени вещь снята,
    # а дальше по промпту бота пошло бы то, чего показывать нельзя.
    момент = float(момент) if момент else round(длит * 0.66, 2)
    print("движение: %.1f с, закрываем на %.2f с" % (длит, момент), flush=True)

    лента, закрыт = растянуть(ровно, os.path.join(раб, "лента.mp4"), момент)
    _, _, полная = размер(лента)
    print("после растяжки хвоста: %.1f с, кадр закрыт на %.2f с"
          % (полная, закрыт), flush=True)

    кнопки = расставить(max(1.2, закрыт - РАЗГОН - 0.15))
    print("кнопки:", ", ".join("%s %.1f-%.1f" % (к["текст"], к["вход"], к["уход"])
                               for к in кнопки), flush=True)

    # наложения
    ряд = os.path.join(раб, "ряд")
    К.ряд(ряд, призыв)
    пути = {}
    for i, к in enumerate(кнопки):
        for сост in ("", "нажата"):
            п = os.path.join(раб, "кн%d%s.png" % (i, сост or "0"))
            К.кнопка(п, к["текст"], сост)
            пути[(i, сост)] = п

    входы = ["-i", лента, "-framerate", str(КАДРЫ), "-i",
             os.path.join(ряд, "кадр%03d.png")]
    for i, _ in enumerate(кнопки):
        входы += ["-i", пути[(i, "")], "-i", пути[(i, "нажата")]]

    сигма = max(34, Ш // 11)
    т = f"{max(0.0, закрыт - РАЗГОН):.3f}"
    доля = f"min(1,max(0,(T-{т})/{РАЗГОН}))"
    ф = [f"[0:v]split=2[чист][грязь]",
         f"[грязь]gblur=sigma={сигма}:steps=4[муть]",
         f"[чист][муть]blend=all_expr='A*(1-{доля})+B*{доля}'[кадр]"]

    # кнопки: проявляются, вспыхивают нажатием, тают
    предыдущий = "кадр"
    for i, к in enumerate(кнопки):
        об, наж = 2 + i*2, 3 + i*2
        y = int(В * (0.60 + i * 0.085))
        for имя, поток, нач, кон in (
                ("об%d" % i, об, к["вход"], к["нажатие"]),
                ("наж%d" % i, наж, к["нажатие"], к["нажатие"] + ВСПЫШКА),
                ("пос%d" % i, об, к["нажатие"] + ВСПЫШКА, к["уход"])):
            if кон <= нач:
                continue
            ф.append(f"[{поток}:v]format=rgba,loop=loop=-1:size=1:start=0,"
                     f"fps={КАДРЫ},setpts=N/FRAME_RATE/TB,"
                     f"fade=t=in:st={нач:.2f}:d={ПРОЯВКА}:alpha=1,"
                     f"fade=t=out:st={max(нач, кон-ПРОЯВКА):.2f}:d={ПРОЯВКА}:alpha=1[{имя}]")
            # shortest=1 ОБЯЗАТЕЛЕН: кнопка зациклена бесконечно (loop=-1),
            # и без него overlay тянет ленту до длины бесконечного входа -
            # ролик на семь секунд выходил тридцатичетырёхсекундным.
            ф.append(f"[{предыдущий}][{имя}]overlay=(W-w)/2:{y}:"
                     f"enable='between(t,{нач:.2f},{кон:.2f})':"
                     f"format=auto:shortest=1[н{имя}]")
            предыдущий = "н" + имя

    # карточка: выходит анимацией сразу после закрытия кадра и держится до конца
    старт = закрыт + ДЕРЖАТЬ
    ф.append(f"[1:v]format=rgba,fps={КАДРЫ},"
             f"tpad=stop_mode=clone:stop_duration=30,"
             f"setpts=PTS-STARTPTS+{старт:.3f}/TB[карта]")
    ф.append(f"[{предыдущий}][карта]overlay=0:0:enable='gte(t,{старт:.3f})':"
             f"format=auto:shortest=1[вых]")

    cmd = [ffmpeg(), "-y", "-hide_banner", "-loglevel", "error"] + входы + [
        "-filter_complex", ";".join(ф), "-map", "[вых]", "-an",
        "-c:v", "libx264", "-preset", "medium", "-crf", "19",
        "-pix_fmt", "yuv420p", "-movflags", "+faststart", выход]
    subprocess.run(cmd, check=True)
    print("готово:", выход, os.path.getsize(выход), "байт", flush=True)
    print("призыв:", призыв, flush=True)
    return выход


if __name__ == "__main__":
    а = sys.argv[1:]
    if len(а) < 2:
        raise SystemExit(__doc__)
    собрать(а[0], а[1], а[2] if len(а) > 2 else None,
            а[3] if len(а) > 3 else None, а[4] if len(а) > 4 else None)
