#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Формат 2: из трёх отрезков собирает ОДНО непрерывное видео.

    python3 сборка_ролика.py <лицо> <A.mp4> <B.mp4> <C.mp4> [выход.mp4] [призыв]

ПОЧЕМУ ОТРЕЗКОВ ТРИ, А ВИДЕО ОДНО

Режима «первый кадр в последний» на нашей сборке нет: снят 22.09.2026,
отдавал чужое лицо, а два снимка в одном задании значат двух ЛЮДЕЙ. Поэтому
каждое действие снимается своим заданием со своей резкой опоры - и склеивается
так, чтобы шва не было видно:

    A  одета        снимает футболку        режется НА ПИКЕ ПОДЪЁМА
    B  в купальнике руки уходят к завязке   берётся с поднятых рук
    C  результат    движение продолжается   целиком под мутью

**Первый шов - на поднятых руках.** В конце A руки вверху и держат подол, в
начале B руки идут вверх к затылку. Наплыв между двумя такими кадрами глаз
читает как «вещь ушла через голову», а не как склейку: поза одна, свет один,
фон один, купальник один и тот же чёрный - он назван в обоих кадрах.

**Второй шов - внутри мути.** К нему кадр уже закрыт полностью, и видеть там
нечего по определению.

МОМЕНТ - это секунда, к которой кадр ОБЯЗАН быть закрыт, а не когда начинать
прятать: разгон мути кладётся перед ней.
"""
import os
import re
import subprocess
import sys

ТУТ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ТУТ)
import карточка as К                                          # noqa: E402

Ш, В, КАДРЫ = 1080, 1920, 30
РАЗГОН = 0.5          # сколько муть набирает силу
ДЕРЖАТЬ = 0.15        # пауза между закрытием кадра и выходом карточки

# Что берём из каждого отрезка. Секунды выбраны по раскадровке, а не на
# глаз: в A подол наверху к полутора секундам, в B руки уходят к затылку
# с полутора и стоят там до конца.
КУСКИ = {
    "A": (0.0, 1.70),
    "B": (1.40, 4.00),
    "C": (0.00, 3.60),
}
ШОВ1, ШОВ2 = 0.35, 0.40      # длительность наплывов

КНОПКИ = ["Раздеть", "Соло"]
ВСПЫШКА, ПРОЯВКА = 0.32, 0.22


def ffmpeg():
    for п in ("/usr/bin/ffmpeg", "/usr/local/bin/ffmpeg"):
        if os.path.exists(п):
            return п
    import imageio_ffmpeg
    return imageio_ffmpeg.get_ffmpeg_exe()


def длительность(видео):
    п = subprocess.run([ffmpeg(), "-hide_banner", "-i", видео],
                       capture_output=True, text=True)
    д = re.search(r"Duration: (\d+):(\d+):([\d.]+)", п.stderr)
    if not д:
        raise SystemExit("не разобрать видео: " + видео)
    ч, м, с = д.groups()
    return int(ч)*3600 + int(м)*60 + float(с)


def ровно(вход, выход, начало, конец):
    """Кусок отрезка в 1080x1920 и 30 к/с. Карта отдаёт 704x1280 и 16 к/с,
    и до сложения всё обязано стать одним размером: xfade разного не терпит."""
    subprocess.run([ffmpeg(), "-y", "-hide_banner", "-loglevel", "error",
                    "-ss", "%.3f" % начало, "-to", "%.3f" % конец, "-i", вход,
                    "-vf", f"scale={Ш}:{В}:force_original_aspect_ratio=increase,"
                           f"crop={Ш}:{В},fps={КАДРЫ},format=yuv420p",
                    "-an", "-c:v", "libx264", "-preset", "medium", "-crf", "16",
                    выход], check=True)
    return выход


def склеить(куски, выход):
    """Три куска в одну ленту двумя наплывами. Возвращает ленту и её длину."""
    a, b, c = куски
    да, дб, дв = (длительность(x) for x in куски)
    сдвиг1 = max(0.0, да - ШОВ1)
    сдвиг2 = max(0.0, да + дб - ШОВ1 - ШОВ2)
    ф = (f"[0:v][1:v]xfade=transition=fade:duration={ШОВ1}:offset={сдвиг1:.3f}[ab];"
         f"[ab][2:v]xfade=transition=fade:duration={ШОВ2}:offset={сдвиг2:.3f}[v]")
    subprocess.run([ffmpeg(), "-y", "-hide_banner", "-loglevel", "error",
                    "-i", a, "-i", b, "-i", c, "-filter_complex", ф,
                    "-map", "[v]", "-an", "-c:v", "libx264", "-preset", "medium",
                    "-crf", "16", "-pix_fmt", "yuv420p", выход], check=True)
    полная = да + дб + дв - ШОВ1 - ШОВ2
    return выход, полная, сдвиг2


def расставить(окно):
    доля = окно / len(КНОПКИ)
    ряд = []
    for i, текст in enumerate(КНОПКИ):
        н = i * доля + доля * 0.12
        ряд.append({"текст": текст, "вход": round(н, 2),
                    "нажатие": round(н + доля * 0.45, 2),
                    "уход": round(н + доля * 0.80, 2)})
    return ряд


def собрать(лицо, a, b, c, выход=None, призыв=None):
    выход = выход or os.path.join(ТУТ, "снятие-%s.mp4" % лицо)
    призыв = призыв or К.ПРИЗЫВЫ[sum(map(ord, os.path.basename(выход))) % len(К.ПРИЗЫВЫ)]
    раб = os.path.join(ТУТ, ".работа")
    os.makedirs(раб, exist_ok=True)

    куски = []
    for имя, файл in (("A", a), ("B", b), ("C", c)):
        н, к = КУСКИ[имя]
        куски.append(ровно(файл, os.path.join(раб, "%s.mp4" % имя), н, к))
    лента, полная, шов2 = склеить(куски, os.path.join(раб, "лента.mp4"))

    # Кадр обязан быть закрыт ДО второго шва: за ним начинается результат.
    закрыт = max(РАЗГОН + 0.1, шов2 - 0.25)
    print("лента %.2f с, второй шов на %.2f, кадр закрыт на %.2f"
          % (полная, шов2, закрыт), flush=True)

    кнопки = расставить(max(1.2, закрыт - РАЗГОН - 0.2))
    print("кнопки:", ", ".join("%s %.1f-%.1f" % (к["текст"], к["вход"], к["уход"])
                               for к in кнопки), flush=True)

    ряд = os.path.join(раб, "ряд")
    К.ряд(ряд, призыв)
    пути = {}
    for i, к in enumerate(кнопки):
        for сост in ("", "нажата"):
            п = os.path.join(раб, "кн%d%s.png" % (i, сост or "0"))
            К.кнопка(п, к["текст"], сост)
            пути[(i, сост)] = п

    входы = ["-i", лента, "-framerate", str(КАДРЫ), "-i",
             os.path.join(ряд, "кадр%03d.png")]
    for i, _ in enumerate(кнопки):
        входы += ["-i", пути[(i, "")], "-i", пути[(i, "нажата")]]

    сигма = max(34, Ш // 11)
    т = f"{max(0.0, закрыт - РАЗГОН):.3f}"
    доля = f"min(1,max(0,(T-{т})/{РАЗГОН}))"
    ф = ["[0:v]split=2[чист][грязь]",
         f"[грязь]gblur=sigma={сигма}:steps=4[муть]",
         f"[чист][муть]blend=all_expr='A*(1-{доля})+B*{доля}'[кадр]"]

    предыдущий = "кадр"
    for i, к in enumerate(кнопки):
        об, наж = 2 + i*2, 3 + i*2
        y = int(В * (0.60 + i * 0.085))
        for имя, поток, нач, кон in (
                ("об%d" % i, об, к["вход"], к["нажатие"]),
                ("наж%d" % i, наж, к["нажатие"], к["нажатие"] + ВСПЫШКА),
                ("пос%d" % i, об, к["нажатие"] + ВСПЫШКА, к["уход"])):
            if кон <= нач:
                continue
            ф.append(f"[{поток}:v]format=rgba,loop=loop=-1:size=1:start=0,"
                     f"fps={КАДРЫ},setpts=N/FRAME_RATE/TB,"
                     f"fade=t=in:st={нач:.2f}:d={ПРОЯВКА}:alpha=1,"
                     f"fade=t=out:st={max(нач, кон-ПРОЯВКА):.2f}:d={ПРОЯВКА}:alpha=1[{имя}]")
            # shortest=1 обязателен: кнопка зациклена бесконечно, и без
            # него overlay тянет ленту до длины бесконечного входа.
            ф.append(f"[{предыдущий}][{имя}]overlay=(W-w)/2:{y}:"
                     f"enable='between(t,{нач:.2f},{кон:.2f})':"
                     f"format=auto:shortest=1[н{имя}]")
            предыдущий = "н" + имя

    старт = закрыт + ДЕРЖАТЬ
    ф.append(f"[1:v]format=rgba,fps={КАДРЫ},"
             f"tpad=stop_mode=clone:stop_duration=30,"
             f"setpts=PTS-STARTPTS+{старт:.3f}/TB[карта]")
    ф.append(f"[{предыдущий}][карта]overlay=0:0:enable='gte(t,{старт:.3f})':"
             f"format=auto:shortest=1[вых]")

    subprocess.run([ffmpeg(), "-y", "-hide_banner", "-loglevel", "error"] + входы + [
        "-filter_complex", ";".join(ф), "-map", "[вых]", "-an",
        "-c:v", "libx264", "-preset", "medium", "-crf", "19",
        "-pix_fmt", "yuv420p", "-movflags", "+faststart", выход], check=True)
    print("готово:", выход, os.path.getsize(выход), "байт", flush=True)
    print("призыв:", призыв, flush=True)
    return выход


if __name__ == "__main__":
    а = sys.argv[1:]
    if len(а) < 4:
        raise SystemExit(__doc__)
    собрать(а[0], а[1], а[2], а[3],
            а[4] if len(а) > 4 else None, а[5] if len(а) > 5 else None)
