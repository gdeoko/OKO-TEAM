# -*- coding: utf-8 -*-
"""Подобрать эталон под каждую кнопку без опоры и снять с него глубину.

## Зачем

Свод 30.09.2026: из шестидесяти четырёх кнопок тридцать идут БЕЗ
ОПОРЫ. Опора это карта глубины принятого кадра, и держит позу именно
она - текст её не держит, это записано в панели ценой отдельного
разбора. Тридцать кнопок, где позу не держит ничто, и есть причина
ломаной анатомии на парных сценах: модель складывает тела как придётся.

Опоры этих кнопок не потерялись, их никогда не было: пары «кадр →
кнопка» восстанавливались из подписей в каталоге, и у пар мж и жж
подписей нет вовсе (ключ описывает РАКУРС, файл - ДЕЙСТВИЕ).

## Откуда берётся кадр

Из живых эталонов, которых у нас тысяча семьсот. Подбирает CLIP по
тексту самой сцены: у каждой кнопки есть подробное описание позы и
камеры, и это ровно то, что CLIP умеет сопоставлять с картинкой.

Подбор проверяется ГЛАЗАМИ перед тем, как класть в работу. Промах
даёт человеку не ту позу за его деньги, и узнает он об этом раньше
нас - поэтому инструмент сначала собирает контрольный лист, и только
отдельной командой снимает глубину.

## ЧЕМ ЭТО КОНЧИЛОСЬ (проба 30.09.2026)

Не сработало, и класть такие опоры в работу нельзя. CLIP выдал ОДИН И
ТОТ ЖЕ кадр сразу четырём кнопкам (`ph_pull`, `ph_mirror`, `ph_slow` и
все четыре `ac_*`), а баллы вышли 0.20-0.34 при том, что осмысленное
совпадение начинается примерно с 0.30 и растёт к 0.4 у точного.

Причина понятна: наши описания позы написаны для диффузии - длинные,
про вес на задней ноге и мягкое колено, - а CLIP их режет до
семидесяти семи токенов и сводит к «женщина стоит». Различить по такому
тексту «сбоку» и «сверху» нечем, вот он и берёт самую типичную
картинку папки.

Одна опора на четыре кнопки это одна поза на четыре кнопки, то есть
ровно тот штамп, которого у нас быть не должно. Инструмент оставлен
как след пробы и как готовая обвязка: подбор, лист на проверку, счёт.
Менять надо источник, а не код - опора делается из НАШЕГО кадра,
принятого глазами, и другого честного пути пока не видно.

## Чего он не сделает

Мужских пар в эталонах нет, значит кнопкам `pf_mm_*` и `pr_mm_*`
подбирать не из чего. Инструмент говорит это прямо, а не подсовывает
женскую пару вместо мужской.

    python3 -m tools.опоры_подбор подобрать      кто к какой кнопке
    python3 -m tools.опоры_подбор лист           картинка на проверку
    python3 -m tools.опоры_подбор снять          глубина на карту
"""
import json
import os
import sys

БОТ = "/opt/amberry/rocket-panel/bot"
ЭТАЛОНЫ = os.environ.get("OPORY_ETALONY", "/root/эталоны")
ВЫБОР = os.environ.get("OPORY_VYBOR", "/root/опоры_выбор.json")
ЛИСТ = os.environ.get("OPORY_LIST", "/root/опоры_лист.jpg")
МОДЕЛЬ = "openai/clip-vit-base-patch32"

# Папки эталонов по составу сцены. Пара ищется среди пар, одиночка
# среди одиночек: эталон с двумя людьми под одиночную кнопку даст
# опору, которая приведёт в кадр второго человека.
ПО_СОСТАВУ = {
    ("ж",): ["hegre"],
    ("ж", "ж"): ["сеть/пара_жж"],
    ("м", "ж"): ["сеть/пара_мж"],
}


def кнопки_без_опоры():
    sys.path.insert(0, БОТ)
    import catalog as К
    итог = []
    for с in К.все_сценарии():
        if К.опора(с.key):
            continue
        # У ролика опора общая с его фотографией, и спрашивать её
        # отдельно незачем: `catalog.опора` уже свёл ac_→ph_ и pr_→pf_.
        # Сюда попадают только те, у кого нет ни своей, ни родственной.
        итог.append(с)
    return итог


def _текст_сцены(с):
    """Короткое описание позы и камеры. Именно его ищет CLIP.

    Полный промпт брать нельзя: в нём две тысячи знаков про свет,
    материалы и запреты, а CLIP режет текст на семьдесят семь токенов и
    от позы не останется ничего.
    """
    куски = [getattr(с, "поза", "") or "", getattr(с, "камера", "") or ""]
    т = " ".join(к for к in куски if к).strip()
    if not т:
        try:
            т = (с.промпт() or "")[:300]
        except Exception:                                   # noqa: BLE001
            т = с.title or с.key
    return т[:300]


def _вектор(что):
    """Развернуть ответ CLIP до тензора.

    В transformers пятой ветки `get_image_features` отдаёт не тензор, а
    объект с полями, и прежний код падал на `.norm`. Разворот
    универсальный: он переживёт и обратную смену.
    """
    if hasattr(что, "norm"):
        return что
    for поле in ("image_embeds", "text_embeds", "pooler_output",
                 "last_hidden_state"):
        зн = getattr(что, поле, None)
        if зн is not None and hasattr(зн, "norm"):
            return зн if зн.dim() == 2 else зн.mean(dim=1)
    raise TypeError(f"не тензор: {type(что)}")


def подобрать():
    import torch
    from PIL import Image
    from transformers import CLIPModel, CLIPProcessor
    sys.path.insert(0, БОТ)
    import catalog as К
    приёмник = CLIPProcessor.from_pretrained(МОДЕЛЬ)
    модель = CLIPModel.from_pretrained(МОДЕЛЬ)
    модель.eval()

    кеш = {}                       # папка -> (файлы, признаки)

    def признаки(папки):
        ключ = tuple(папки)
        if ключ in кеш:
            return кеш[ключ]
        файлы = []
        for п in папки:
            полная = os.path.join(ЭТАЛОНЫ, п)
            if not os.path.isdir(полная):
                continue
            файлы += [os.path.join(полная, и) for и in sorted(os.listdir(полная))
                      if и.lower().endswith((".jpg", ".jpeg", ".png"))]
        if not файлы:
            кеш[ключ] = ([], None)
            return кеш[ключ]
        части = []
        for н in range(0, len(файлы), 32):
            картинки = []
            for ф in файлы[н:н + 32]:
                try:
                    картинки.append(Image.open(ф).convert("RGB"))
                except Exception:                           # noqa: BLE001
                    картинки.append(Image.new("RGB", (224, 224)))
            с = приёмник(images=картинки, return_tensors="pt")
            with torch.no_grad():
                в = _вектор(модель.get_image_features(**с))
            части.append(в / в.norm(dim=-1, keepdim=True))
            print(f"   признаки {н + len(картинки)}/{len(файлы)}", flush=True)
        кеш[ключ] = (файлы, torch.cat(части))
        return кеш[ключ]

    выбор, нечем = {}, []
    for с in кнопки_без_опоры():
        полы = tuple(К.полы(с.key))
        папки = ПО_СОСТАВУ.get(полы)
        if not папки:
            нечем.append((с.key, f"нет эталонов состава {полы}"))
            continue
        файлы, в = признаки(папки)
        if not файлы:
            нечем.append((с.key, f"папки пусты: {папки}"))
            continue
        т = приёмник(text=[_текст_сцены(с)], return_tensors="pt",
                     padding=True, truncation=True, max_length=77)
        with torch.no_grad():
            тв = _вектор(модель.get_text_features(**т))
        тв = тв / тв.norm(dim=-1, keepdim=True)
        баллы = (в @ тв.T).squeeze(1)
        лучший = int(баллы.argmax())
        выбор[с.key] = {"кадр": файлы[лучший],
                        "балл": round(float(баллы[лучший]), 4),
                        "состав": list(полы),
                        "текст": _текст_сцены(с)[:120]}
        print(f"{с.key:14s} {баллы[лучший]:.3f}  "
              f"{os.path.basename(файлы[лучший])}", flush=True)
    json.dump({"выбор": выбор, "нечем": нечем}, open(ВЫБОР, "w"),
              ensure_ascii=False, indent=1)
    print(f"\nподобрано: {len(выбор)}, без эталонов: {len(нечем)}")
    for к, б in нечем:
        print(f"  {к:14s} {б}")
    return выбор


def лист():
    """Один лист со всеми парами: кнопка и выбранный кадр.

    Смотреть подбор по одному файлу нельзя - их два десятка, и на
    третьем глаз перестаёт помнить первый.
    """
    import cv2
    import numpy as np
    д = json.load(open(ВЫБОР))["выбор"]
    if not д:
        print("подбора нет, сначала `подобрать`")
        return None
    строк = (len(д) + 3) // 4
    бок = 320
    холст = np.full((строк * (бок + 28), 4 * бок, 3), 24, np.uint8)
    for н, (ключ, зн) in enumerate(sorted(д.items())):
        к = cv2.imread(зн["кадр"])
        if к is None:
            continue
        в, ш = к.shape[:2]
        м = бок / max(в, ш)
        к = cv2.resize(к, (int(ш * м), int(в * м)))
        r, c = divmod(н, 4)
        y, x = r * (бок + 28) + 28, c * бок
        холст[y:y + к.shape[0], x:x + к.shape[1]] = к
        cv2.putText(холст, f"{ключ} {зн['балл']}", (x + 4, y - 8),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255, 255, 255), 1)
    cv2.imwrite(ЛИСТ, холст, [cv2.IMWRITE_JPEG_QUALITY, 88])
    print("лист ->", ЛИСТ)
    return ЛИСТ


if __name__ == "__main__":
    что = sys.argv[1] if len(sys.argv) > 1 else "подобрать"
    if что == "подобрать":
        подобрать()
    elif что == "лист":
        лист()
