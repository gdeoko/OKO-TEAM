# -*- coding: utf-8 -*-
"""Сделать из живого эталона кадр с НАШИМ дефектом.

## Зачем это нужно

Лора на одиночных кропах не обучилась вовсе: Qwen-Image-Edit это модель
правки, и ей нужна пара - что было и что должно стать. Пара у нас есть,
и она даже лучше набора картинок: слева наш дефект, справа живая кожа.
Так учат все реставраторы, и так же вылечилось лицо.

Взять для пары настоящий кадр нашего конвейера нельзя: это семьсот
генераций на карте, то есть сутки. Поэтому дефект воспроизводится
кодом - и не на глаз, а по числам, которыми он же и меряется.

## Из чего состоит наш дефект

Три вещи, и все три названы владельцем своими словами.

1. **«Как нарисовано кистью»** - модель стирает микрорельеф кожи и
   оставляет ровные заливки. Это `bilateral`: он ровняет плоскости и
   бережёт границы, ровно как мазок.
2. **«Помехи видно»** - перешарп по краям. У наших кадров лаплас 525
   при 174-239 у живых. Это `unsharp` поверх сглаженного: края
   становятся жёстче, а поверхность остаётся мёртвой.
3. **«Точки белые чёрные, царапины»** - крапины. У нас их 1557 на
   миллион точек кожи против 880 у живого кадра.

## Как проверяется

Деградация не подгоняется на глаз. `подобрать` гоняет числа по тем же
мерам, что и приёмка, и сходится к цели делением отрезка пополам. Если
числа не сошлись, набор не собирается: пара, где «до» не похоже на наш
брак, учит модель чинить чужую беду.

    python3 -m tools.деградация подобрать <папка эталонов>
    python3 -m tools.деградация пары <папка эталонов> <куда>
"""
import json
import os
import sys

import cv2
import numpy as np

# Цель задана ОТНОШЕНИЕМ, а не абсолютным числом. Наши кадры мерились
# по зоне органов (лаплас 525, крапин 1557), живые эталоны там же дают
# 174-239 и 880. Ровный кусок кожи из набора по природе спокойнее любой
# зоны с границами, и абсолютные числа зоны на нём не достигаются
# никакой порчей: первый подбор упёрся в край и выдал лаплас в пятнадцать
# раз выше цели. Отношение переносится между масштабами, абсолют нет.
ВО_СКОЛЬКО = {"лаплас": 525.0 / 200.0, "крапин": 1557.0 / 880.0}
ДОПУСК_ДОЛЯ = 0.18          # восемнадцать процентов от цели

ПОДОБРАННОЕ = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "деградация.json")


def испортить(кадр, кисть=9, резкость=1.6, крапин=0.0018, зерно=2.2,
              сила_крапины=45):
    """Наш дефект поверх живого кадра.

    Порядок важен: сначала стираем микрорельеф, потом задираем края.
    Наоборот получится просто резкий живой кадр, а нам нужен мёртвый.
    """
    к = кадр.astype(np.uint8)
    # 1. Мазок кистью: плоскости ровняются, границы остаются.
    мягкий = cv2.bilateralFilter(к, int(кисть) | 1, 45, 45)
    # 2. Перешарп поверх мёртвой поверхности.
    размыт = cv2.GaussianBlur(мягкий, (0, 0), 2.0)
    остро = cv2.addWeighted(мягкий, 1.0 + резкость, размыт, -резкость, 0)
    # 3. Крапины. Светлые и тёмные поровну: владелец назвал обе.
    #    Сдвигом от своего значения, а НЕ до чистого белого и чёрного:
    #    жёсткая соль-перец одна, без всякой резкости, задирала лаплас в
    #    два с лишним раза выше цели, а на наших кадрах точка это
    #    пятнышко на сорок единиц, а не выбитый пиксель.
    из_ = остро.astype(np.int16)
    н = np.random.default_rng(0).random(из_.shape[:2])
    из_[н < крапин / 2] += сила_крапины
    из_[н > 1 - крапин / 2] -= сила_крапины
    # 4. Зерно: без него крапины лежат на стерильном фоне и читаются
    #    как пыль на сканере, а не как шум генерации.
    из_ = из_ + np.random.default_rng(1).normal(0, зерно, из_.shape)
    return np.clip(из_, 0, 255).astype(np.uint8)


def _меры(кадр):
    """Те же числа, что у приёмки. Свои, чтобы модуль ехал один."""
    сер = cv2.cvtColor(кадр, cv2.COLOR_BGR2GRAY)
    лаплас = float(cv2.Laplacian(сер, cv2.CV_64F).var())
    # Крапины: точка, резко выбитая из своей округи.
    медиана = cv2.medianBlur(сер, 3)
    выброс = np.abs(сер.astype(np.int16) - медиана.astype(np.int16)) > 18
    # Кожа ищется по СГЛАЖЕННОМУ кадру. Белая точка и чёрная точка из
    # диапазона кожи выпадают, и маска по исходнику вычёркивала ровно те
    # крапины, которые мы считаем: засыпали два процента кадра, а мера
    # показывала сто семьдесят на миллион вместо двадцати тысяч.
    ycrcb = cv2.cvtColor(cv2.medianBlur(кадр, 5), cv2.COLOR_BGR2YCrCb)
    кожа = cv2.inRange(ycrcb, (0, 133, 77), (255, 180, 127)) > 0
    точек = int(кожа.sum())
    крапин = float((выброс & кожа).sum()) / max(1, точек) * 1e6
    return {"лаплас": лаплас, "крапин": крапин}


def подобрать(папка, сколько=12):
    """Найти силу порчи, дающую наши числа. Делением отрезка пополам."""
    файлы = [os.path.join(папка, и) for и in sorted(os.listdir(папка))
             if и.lower().endswith((".jpg", ".jpeg", ".png"))][:сколько]
    if not файлы:
        print("нет эталонов в", папка)
        return None
    кадры = [к for к in (cv2.imread(ф) for ф in файлы) if к is not None]

    def числа(резкость, крапин):
        о = [_меры(испортить(к, резкость=резкость, крапин=крапин))
             for к in кадры]
        return {и: float(np.median([х[и] for х in о])) for и in ВО_СКОЛЬКО}

    чистое = {и: float(np.median([х[и] for х in (_меры(к) for к in кадры)]))
              for и in ВО_СКОЛЬКО}
    ЦЕЛЬ = {и: чистое[и] * ВО_СКОЛЬКО[и] for и in ВО_СКОЛЬКО}

    # КРАПИНЫ ПЕРВЫМИ, и это не вкус. Крапина это скачок яркости на одну
    # точку, то есть самая сильная добавка к лапласу: при подборе
    # наоборот резкость сходилась к нижнему краю, а лаплас всё равно
    # оставался в пятнадцать раз выше цели. Сначала ставим точки, потом
    # добираем резкость тем, что осталось.
    # Круги подбора. Один круг не сходится: резкость поднимает уже
    # поставленные точки, и крапин выходило на восемнадцать процентов
    # больше цели при точном попадании по лапласу. Три круга хватает.
    крапин, резкость = 0.0005, 0.0
    for _ in range(3):
        низ, верх = 0.00001, 0.02
        for _ in range(16):
            сер = (низ + верх) / 2
            if числа(резкость, сер)["крапин"] < ЦЕЛЬ["крапин"]:
                низ = сер
            else:
                верх = сер
        крапин = round((низ + верх) / 2, 7)

        низ, верх = 0.0, 6.0
        for _ in range(14):
            сер = (низ + верх) / 2
            if числа(сер, крапин)["лаплас"] < ЦЕЛЬ["лаплас"]:
                низ = сер
            else:
                верх = сер
        резкость = round((низ + верх) / 2, 3)

    итог = числа(резкость, крапин)
    сошлось = all(abs(итог[и] - ЦЕЛЬ[и]) <= ЦЕЛЬ[и] * ДОПУСК_ДОЛЯ
                  for и in ЦЕЛЬ)
    найдено = {"резкость": резкость, "крапин": крапин,
               "вышло": {и: round(итог[и], 1) for и in итог},
               "чистое": {и: round(чистое[и], 1) for и in чистое},
               "цель": {и: round(ЦЕЛЬ[и], 1) for и in ЦЕЛЬ},
               "сошлось": сошлось}
    json.dump(найдено, open(ПОДОБРАННОЕ, "w"), ensure_ascii=False, indent=1)
    print(json.dumps(найдено, ensure_ascii=False, indent=1))
    return найдено


def пары(папка, куда, подписи=None):
    """Собрать `control` рядом с целевыми кадрами.

    Имена совпадают - так их ждёт тренер. Целевые кадры остаются на
    месте, копировать их незачем.
    """
    настройки = {}
    if os.path.exists(ПОДОБРАННОЕ):
        настройки = json.load(open(ПОДОБРАННОЕ))
        if not настройки.get("сошлось"):
            print("ВНИМАНИЕ: подбор не сошёлся, пары не собираю")
            return 0
    резкость = настройки.get("резкость", 1.6)
    крапин = настройки.get("крапин", 0.0018)
    os.makedirs(куда, exist_ok=True)
    сделано = 0
    for и in sorted(os.listdir(папка)):
        if not и.lower().endswith((".jpg", ".jpeg", ".png")):
            continue
        кадр = cv2.imread(os.path.join(папка, и))
        if кадр is None:
            continue
        cv2.imwrite(os.path.join(куда, os.path.splitext(и)[0] + ".png"),
                    испортить(кадр, резкость=резкость, крапин=крапин))
        сделано += 1
        if сделано % 100 == 0:
            print("  ", сделано, flush=True)
    print("пар собрано:", сделано, "->", куда)
    return сделано


if __name__ == "__main__":
    что = sys.argv[1] if len(sys.argv) > 1 else "подобрать"
    if что == "подобрать":
        подобрать(sys.argv[2])
    elif что == "пары":
        пары(sys.argv[2], sys.argv[3])
