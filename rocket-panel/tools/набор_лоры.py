# -*- coding: utf-8 -*-
"""Нарезать обучающий набор для лоры из живых эталонов.

## Зачем

Лицо вылечила чужая модель, обученная на тысячах настоящих лиц. Тело
лечить нечем: такой модели для кожи и органов не существует. Значит её
нужно сделать - на двух тысячах эталонов, собранных с открытых витрин.

## Чему учим и чему НЕ учим

Учим ФАКТУРЕ: как кожа рассеивает свет, какой у неё микрорельеф, как
читается складка, как выглядит настоящий сосок и настоящий орган.

НЕ учим форме, размеру и цвету. Их даёт референс клиента, и защита тут
двойная. Первая - разнообразие: в наборе тысячи разных тел, и выучить
«правильную грудь» на них невозможно. Вторая - глубина применения:
лора работает в проходе по зоне на глубине 0.25, где содержимое кадра
переписать нельзя физически.

Лиц в наборе нет вовсе. Лицо держат свои два механизма - референс
клиента и восстановитель, - и мешать им лора не должна.

## Что на выходе

Пары «кроп + описание» в одной папке, как ждут все тренеры лор.
Описание короткое и про поверхность, а не про сцену: длинный текст учит
модель композиции, а нам нужна кожа.

    python3 -m tools.набор_лоры [сколько_на_зону]
"""
import os
import sys

import cv2

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))), "bot"))

ИСТОЧНИКИ = ["/root/эталоны/hegre",
             "/root/эталоны/сеть/пара_жж",
             "/root/эталоны/сеть/пара_мж"]
КУДА = os.environ.get("LORA_DIR", "/root/набор_лоры")
# Верхняя граница, а НЕ размер набора. Первый набор растягивал каждый
# кусок до 768, и это убило его целиком: зона груди на эталоне 1600x900
# занимает триста точек, растяжка дала мыло с резкостью 13 против 174 у
# живого кадра. Набор из мыла учит модель делать мыло.
ПОТОЛОК = int(os.environ.get("LORA_SIDE", "768"))
# Ниже этого кусок не берём вовсе: на ста точках фактуры кожи нет.
ПОЛ = int(os.environ.get("LORA_MIN", "320"))


def _вписать(кусок):
    """Уменьшить, если больше потолка. Увеличивать нельзя никогда."""
    б = min(кусок.shape[:2])
    if б <= ПОТОЛОК:
        return кусок
    к = ПОТОЛОК / б
    return cv2.resize(кусок, (int(кусок.shape[1] * к), int(кусок.shape[0] * к)),
                      interpolation=cv2.INTER_AREA)

# Описания по зонам. Нарочно про поверхность и без оценок: слово
# «beautiful» учит модель рисовать глянец, слово «detailed» - перешарп.
ПОДПИСИ = {
    "грудь": ("a photograph of a bare human chest, real skin texture, "
              "natural nipples, fine skin surface, matte skin"),
    "пах": ("a photograph of bare human hips and groin, real skin "
            "texture, natural anatomy, fine skin surface, matte skin"),
    "руки": ("a photograph of a human hand, five fingers, real skin "
             "texture, knuckle creases, short natural fingernails"),
    "тело": ("a photograph of bare human skin, real skin texture, fine "
             "skin surface, natural tone variation, matte skin"),
}


def кропы_кадра(путь, зоны_модуль):
    """Куски одного эталона по зонам. Лицо не берём.

    Кадр, где зон не нашлось, пропускается целиком: кроп наугад с
    большой вероятностью окажется простынёй, а простыня в наборе учит
    модель рисовать простыню.
    """
    кадр = cv2.imread(путь)
    if кадр is None:
        return []
    try:
        зоны = зоны_модуль._зоны_по_скелету(кадр)
    except Exception:                                       # noqa: BLE001
        return []
    if not зоны:
        return []
    итог = []

    def взять(имя, x, y, б):
        кусок = кадр[y:y + б, x:x + б]
        if кусок.size == 0 or min(кусок.shape[:2]) < ПОЛ:
            return False
        # Кожи должно быть больше половины: иначе в набор попадёт
        # простыня, стена или одежда, и лора выучит их.
        ycrcb = cv2.cvtColor(кусок, cv2.COLOR_BGR2YCrCb)
        м = cv2.inRange(ycrcb, (0, 133, 77), (255, 180, 127))
        if float((м > 0).mean()) < 0.5:
            return False
        итог.append((имя, _вписать(кусок)))
        return True

    for имя, (x, y, б) in зоны.items():
        if имя in ПОДПИСИ:
            взять(имя, x, y, б)

    # КОЖА ВСЕГО ТЕЛА. Скелет такой зоны не даёт, а это главное: бёдра,
    # живот, спина и плечи занимают большую часть кадра, и именно там
    # владелец видит «точки» и «мазок». Берём куски по сетке и оставляем
    # те, где кожи много, а зоны органов не задеты.
    #
    # Пересечение с зонами НЕ исключаем. Эталоны это кропы, и зоны
    # покрывают на них почти весь кадр: с запретом пересечения кусков
    # тела не набралось ни одного за тысячу эталонов. Зато поднят порог
    # кожи: кусок идёт в набор, только если кожи в нём больше семи
    # десятых, иначе лора выучит простыню.
    в, ш = кадр.shape[:2]
    бок = max(ПОЛ, min(в, ш) // 3)
    взято_тел = 0
    for y in range(0, max(1, в - бок), max(64, бок // 2)):
        for x in range(0, max(1, ш - бок), max(64, бок // 2)):
            if взято_тел >= 2:                 # не больше двух с кадра
                break
            кусок = кадр[y:y + бок, x:x + бок]
            if кусок.size == 0:
                continue
            ycrcb = cv2.cvtColor(кусок, cv2.COLOR_BGR2YCrCb)
            м = cv2.inRange(ycrcb, (0, 133, 77), (255, 180, 127))
            if float((м > 0).mean()) < 0.7:
                continue
            итог.append(("тело", _вписать(кусок)))
            взято_тел += 1
    return итог


def собрать(на_зону=400):
    import детейлер
    os.makedirs(КУДА, exist_ok=True)
    счёт = {и: 0 for и in ПОДПИСИ}
    всего = 0
    for папка in ИСТОЧНИКИ:
        if not os.path.isdir(папка):
            continue
        for и in sorted(os.listdir(папка)):
            if not и.lower().endswith((".jpg", ".jpeg", ".png")):
                continue
            if all(с >= на_зону for с in счёт.values()):
                break
            for имя, кусок in кропы_кадра(os.path.join(папка, и), детейлер):
                if счёт[имя] >= на_зону:
                    continue
                номер = счёт[имя]
                основа = os.path.join(КУДА, f"{имя}_{номер:04d}")
                cv2.imwrite(основа + ".png", кусок)
                open(основа + ".txt", "w").write(ПОДПИСИ[имя])
                счёт[имя] += 1
                всего += 1
            if всего and всего % 50 == 0:
                print("  собрано", счёт, flush=True)
    print("ИТОГО", счёт, "->", КУДА)
    return счёт


def только_кожа(на_зону=900, папки=None):
    """Набор из одних кусков кожи, без скелета.

    Скелет на карте не поднять: он тянет детейлер, а тот тянет клиента
    к панели, и обучение оказалось бы завязано на работающий ComfyUI.
    Куски кожи по сетке дают ровно то, на что жалуется владелец -
    поверхность тела, где видны точки и мазок, - а руки попадают в них
    сами: на кисти кожи больше семи десятых.
    """
    os.makedirs(КУДА, exist_ok=True)
    счёт = 0
    for папка in (папки or ИСТОЧНИКИ):
        if not os.path.isdir(папка):
            continue
        for и in sorted(os.listdir(папка)):
            if счёт >= на_зону:
                break
            if not и.lower().endswith((".jpg", ".jpeg", ".png")):
                continue
            кадр = cv2.imread(os.path.join(папка, и))
            if кадр is None:
                continue
            в, ш = кадр.shape[:2]
            бок = max(ПОЛ, min(в, ш) // 3)
            взято = 0
            for y in range(0, max(1, в - бок), max(64, бок // 2)):
                for x in range(0, max(1, ш - бок), max(64, бок // 2)):
                    if взято >= 3 or счёт >= на_зону:
                        break
                    кусок = кадр[y:y + бок, x:x + бок]
                    if кусок.size == 0 or min(кусок.shape[:2]) < ПОЛ:
                        continue
                    ycrcb = cv2.cvtColor(кусок, cv2.COLOR_BGR2YCrCb)
                    м = cv2.inRange(ycrcb, (0, 133, 77), (255, 180, 127))
                    if float((м > 0).mean()) < 0.7:
                        continue
                    основа = os.path.join(КУДА, f"тело_{счёт:04d}")
                    cv2.imwrite(основа + ".png", _вписать(кусок))
                    open(основа + ".txt", "w").write(ПОДПИСИ["тело"])
                    счёт += 1
                    взято += 1
            if счёт and счёт % 100 == 0:
                print("  ", счёт, flush=True)
    print("ИТОГО кусков кожи:", счёт, "->", КУДА)
    return счёт


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "кожа":
        только_кожа(int(sys.argv[2]) if len(sys.argv) > 2 else 900,
                    sys.argv[3:] or None)
    else:
        собрать(int(sys.argv[1]) if len(sys.argv) > 1 else 400)
