#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Дословные промпты принятых эталонов - из метаданных самих кадров.

## Зачем

Владелец 30.09.2026, глядя на старые кадры: «на тех кадрах как будто
лучше и кожа, и всё остальное: позы, ракурсы, лица, гениталии». Кадры
эти он же и принял, а рецепт их лежал прямо в файле: ComfyUI пишет весь
граф в чанк `prompt` каждого PNG.

Сверка показала, что текст в боте разошёлся с текстом эталона у ВСЕХ
двадцати кнопок, и всегда в одну сторону - поле `жёстко` короче на
300-1300 знаков. Когда эталонные тексты переносили в каталог, их
обрезали: обстановку, свет и описание внешности сняли, решив, что их
поставят общие блоки. Общие блоки их и ставят - своими словами, и слова
эти спорят с постановкой:

    эталон:  CLOSE SHOT, её вульва заполняет ЦЕНТР кадра
    блок:    Whole subject inside the frame, nothing important cropped away

    эталон:  чёрная студия, розовый неон, мягкий свет спереди
    блок:    available daylight from a window, overcast day, amateur snapshot

Модель получает два взаимоисключающих приказа и разрешает их как
придётся - отсюда «позы стали не те, которые утвердили».

## Что делает этот инструмент

Читает эталоны, достаёт из каждого позитивный промпт ПО СВЯЗИ С
СЭМПЛЕРОМ и складывает в один файл рядом с ними. Связь важна: в графе
два текстовых узла, и негатив у Qwen такой же длинный, как позитив.
Первый заход брал первый похожий узел и намерил «у эталона 2934 знака»
там, где позитива 1584.

Заодно записывает, КАК кадр считался: лист, шаги, CFG, сэмплер, лоры.
По этим числам видно, что все двадцать эталонов сделаны одним рецептом -
768x1344, восемь шагов, CFG 2.0, euler/simple, без единой лоры.

    python3 -m tools.промпты_эталонов            собрать
    python3 -m tools.промпты_эталонов un_close   показать один
"""
import json
import os
import sys

БОТ = os.environ.get("AMBERRY_BOT_DIR", "/opt/amberry/rocket-panel/bot")
if БОТ not in sys.path:
    sys.path.insert(0, БОТ)

ЭТАЛОНЫ = os.environ.get("AMBERRY_ETALONS_DIR", "/srv/amberry/эталоны")
ФАЙЛ = os.environ.get("AMBERRY_ET_PROMPTS",
                      "/srv/amberry/эталонные_промпты.json")


def граф(путь):
    """Граф ComfyUI из метаданных PNG или None."""
    from PIL import Image
    try:
        и = Image.open(путь)
    except Exception:                                   # noqa: BLE001
        return None
    инфо = getattr(и, "text", None) or getattr(и, "info", {})
    сыро = инфо.get("prompt")
    if not сыро:
        return None
    try:
        return json.loads(сыро)
    except Exception:                                   # noqa: BLE001
        return None


def позитив(г):
    """Текст, который сэмплер взял ПОЛОЖИТЕЛЬНЫМ условием.

    Искать по классу узла нельзя: негатив у Qwen такой же длинный, и
    первый попавшийся текстовый узел оказывается им в половине графов.
    """
    for узел in (г or {}).values():
        if узел.get("class_type") != "KSampler":
            continue
        ид = (узел.get("inputs", {}).get("positive") or [None])[0]
        вх = (г.get(str(ид)) or {}).get("inputs", {})
        return (вх.get("prompt") or вх.get("text") or "").strip() or None
    return None


def как_считался(г):
    """Лист, шаги, CFG, сэмплер и лоры - чем кадр сделан."""
    о = {}
    for узел in (г or {}).values():
        т = узел.get("class_type")
        вх = узел.get("inputs", {})
        if т == "KSampler":
            о.update(шаги=вх.get("steps"), cfg=вх.get("cfg"),
                     сэмплер=вх.get("sampler_name"),
                     планировщик=вх.get("scheduler"),
                     denoise=вх.get("denoise"))
        elif т in ("ImageScale", "EmptySD3LatentImage"):
            о.setdefault("лист", [вх.get("width"), вх.get("height")])
        elif т in ("LoraLoader", "LoraLoaderModelOnly"):
            о.setdefault("лоры", []).append(вх.get("lora_name"))
        elif т == "CheckpointLoaderSimple":
            о["модель"] = вх.get("ckpt_name")
    return о


def собрать():
    """{ключ кнопки: {промпт, как_считался, файл}} по всем видимым кнопкам."""
    import catalog
    import примеры
    итог = {}
    for у in catalog.С_ВАРИАНТАМИ:
        if у.скрыт:
            continue
        for с in у.scenes:
            if с.скрыт:
                continue
            # Ключ правок общий у фотографии и ролика: ph_close и
            # ac_close это одна кнопка с двумя видами работы, и
            # принятый кадр у них один.
            имя = None
            for к in (с.key, "pr_" + с.key[3:], "ac_" + с.key[3:],
                      "pf_" + с.key[3:], "ph_" + с.key[3:]):
                имя = примеры.КАДР.get(к)
                if имя:
                    break
            if not имя:
                continue
            путь = os.path.join(ЭТАЛОНЫ, имя)
            if not os.path.exists(путь):
                continue
            г = граф(путь)
            п = позитив(г)
            if not п:
                continue
            итог[с.key] = {"промпт": п, "файл": имя,
                           "как_считался": как_считался(г),
                           "одежда": одежда_в_кадре(п)}
    return итог


# ОДЕЖДА, КОТОРАЯ ОБЯЗАНА ОСТАТЬСЯ В КАДРЕ
#
# Владелец 30.09.2026, про задранную юбку на кнопке «Раздвинуть ножки»:
# «юбка там должна быть». Он прав, и это записано в его же принятом
# кадре дословно: «SHE IS WEARING A SHORT SKIRT AND NOTHING ELSE: the
# skirt is pushed up around her waist».
#
# Таких кнопок три, и у каждой одежда это и есть сюжет:
#
#     un_sit     короткая юбка задрана к талии, под ней ничего
#     ph_below   футболка поднята к ключицам и скатана в валик
#     ph_push    юбка на талии, трусики спущены до середины бёдер
#
# Раздевание входа по маске снимает одежду ЦЕЛИКОМ, и на этих кнопках
# оно уносит то, ради чего кнопку нажали. Отсюда правило: там, где
# принятый кадр называет одежду утвердительно, вход не раздевается.
#
# Список считается из самих эталонов, а не пишется руками: написанный
# руками он разойдётся с кадрами при первой же правке промпта.
_ОДЕЖДА = ("skirt", "dress", "panties", "knickers", "bra", "t-shirt",
           "tshirt", "shirt", "lingerie", "underwear", "thong", "shorts",
           "stockings", "fabric", "hem")
# Отрицания, после которых предмет одежды означает его отсутствие:
# «no panties on her», «nothing under it», «without her bra».
_ОТРИЦАНИЯ = ("no ", "not ", "nothing ", "without ", "never ", "removed ",
              "discarded ", "off ")


def одежда_в_кадре(промпт):
    """Предметы одежды, названные УТВЕРДИТЕЛЬНО. Список, может быть пуст.

    Отрицание ищется в том же предложении и ДО предмета: «no panties on
    her» это отсутствие трусиков, а «pulled her panties down» это
    трусики в кадре. Проверять весь промпт целиком нельзя - слово «no»
    в нём найдётся всегда.
    """
    import re
    найдено = []
    for предложение in re.split(r"(?<=[.!?])\s+", промпт or ""):
        for предмет in _ОДЕЖДА:
            м = re.search(r"\b" + re.escape(предмет) + r"\b", предложение,
                          re.I)
            if not м:
                continue
            до = предложение[:м.start()].lower()
            # Смотрим только ближний хвост перед предметом: отрицание в
            # начале длинного предложения к нему уже не относится.
            хвост = до[-28:]
            if any(о in хвост for о in _ОТРИЦАНИЯ):
                continue
            if предмет not in найдено:
                найдено.append(предмет)
    return найдено


def загрузить():
    """Собранные промпты. Пустой словарь, если файла нет."""
    try:
        return json.load(open(ФАЙЛ, encoding="utf-8"))
    except Exception:                                   # noqa: BLE001
        return {}


def одежда_кнопки(ключ):
    """Одежда, обязанная остаться в кадре у этой кнопки. Список."""
    з = загрузить().get(ключ) or {}
    # Признак считается при сборке и лежит рядом с промптом, чтобы его
    # можно было прочитать глазами, а не пересчитывать каждый раз.
    if "одежда" in з:
        return з["одежда"]
    return одежда_в_кадре(з.get("промпт") or "")


def главное():
    if len(sys.argv) > 1:
        з = загрузить().get(sys.argv[1])
        if not з:
            sys.exit("нет эталонного промпта у кнопки " + sys.argv[1])
        print(json.dumps(з["как_считался"], ensure_ascii=False))
        print()
        print(з["промпт"])
        return
    о = собрать()
    json.dump(о, open(ФАЙЛ, "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    print("собрано кнопок:", len(о), "->", ФАЙЛ)
    for ключ, з in о.items():
        к = з["как_считался"]
        л = к.get("лист") or ["?", "?"]
        print("  %-14s %5d зн  %sx%s  %s ш  cfg %s  %s  одежда: %s" % (
            ключ, len(з["промпт"]), л[0], л[1], к.get("шаги"), к.get("cfg"),
            к.get("сэмплер"), ", ".join(з.get("одежда") or []) or "нет"))


if __name__ == "__main__":
    главное()
