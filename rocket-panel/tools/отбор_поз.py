# -*- coding: utf-8 -*-
"""Отбор референсов под кнопку по СОВПАДЕНИЮ ПОЗЫ, а не по впечатлению.

## Зачем

Под каждую кнопку нужны эталонные кадры в её ракурсе и позе. Выбирать их
глазами долго и ненадёжно: «похоже» у двух человек разное, а решает тут
не сюжет, а геометрия - куда смотрит камера, как лежит тело, где руки и
колени. Это меряется числом.

Меру уже держит `bot/поза_сверка.py`: снимает скелет через mediapipe,
приводит его к общему масштабу, сравнивает с принятым кадром кнопки.
На повторе принятых кадров она давала 0.017-0.140 при пороге 0.12.
Здесь та же мера разворачивается с одного кадра на пачку.

## Как пользоваться

    python3 -m tools.отбор_поз ph_close /папка/с/кадрами
    python3 -m tools.отбор_поз ph_close,pf_ff_close,pr_mf_ride /папка --сколько 3

Печатает таблицу «файл - расхождение», от лучшего к худшему, и кладёт
лучшие в `<папка>/отобрано/<ключ>/`. Дальше человек смотрит короткий
список и говорит, какие берём.

## Почему скелеты снимаются ПАЧКОЙ

`поза_сверка.сверить` поднимает mediapipe на каждый вызов, а старт стоит
около двух секунд. На сотне кадров это три минуты одних запусков, и
столько же на сто первом. Здесь скелеты снимаются кусками по полсотни
путей за заход, а сравнение потом идёт в памяти.

Разбиение на куски не украшение: путей в командной строке подпроцесса
конечное число, и на длинном списке запуск падает с «Argument list too
long» - отказ, который выглядит как «mediapipe не работает».

## Чего этот инструмент НЕ делает

Он не ходит по сайтам и ничего не скачивает. На вход ему дают папку с
уже собранными кадрами. Разделение намеренное: отбор по числу это
машинная работа, выбор источника и самих кадров остаётся за человеком.
"""
import json
import os
import shutil
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "bot"))
import поза_сверка as П                                      # noqa: E402

РАСШИРЕНИЯ = (".png", ".jpg", ".jpeg", ".webp", ".bmp")
КУСОК = 50


def кадры_папки(папка):
    """Картинки папки, кроме нашей же выгрузки. Отсортированы по имени."""
    о = []
    for корень, папки, файлы in os.walk(папка):
        # Свою выгрузку не перебираем: иначе второй прогон сравнивает
        # отобранное с ним же и выдаёт дубликаты первой тройки.
        папки[:] = [п for п in папки if п != "отобрано"]
        for ф in файлы:
            if ф.lower().endswith(РАСШИРЕНИЯ):
                о.append(os.path.join(корень, ф))
    return sorted(о)


def скелеты_пачкой(пути, кусок=КУСОК):
    """{путь: узлы или None} для длинного списка, кусками."""
    о = {}
    for н in range(0, len(пути), кусок):
        о.update(П._скелеты(*пути[н:н + кусок]) or {})
    return о


def отобрать(ключ, папка, сколько=3, эталон=None):
    """Кадры папки, отсортированные по совпадению позы с кнопкой.

    Возвращает {"эталон": путь, "ряд": [(файл, расхождение, отражено)],
    "беда": текст}. Ряд отсортирован от лучшего к худшему; кадры, на
    которых человек не найден, в ряд не попадают вовсе и считаются
    отдельно: «скелета нет» это не «поза не совпала», и валить их в один
    список значит прятать одно за другим.
    """
    э = эталон or П.эталон_кнопки(ключ)
    if not э:
        return {"беда": "у кнопки %s нет принятого кадра" % ключ}
    кадры = кадры_папки(папка)
    if not кадры:
        return {"беда": "в папке %s нет картинок" % папка}

    ск = скелеты_пачкой([э] + кадры)
    а = П._привести(ск.get(э))
    if not а:
        return {"беда": "на принятом кадре кнопки скелет не найден"}

    ряд, без_скелета = [], []
    for к in кадры:
        б = П._привести(ск.get(к))
        if not б:
            без_скелета.append(к)
            continue
        прямо, _ = П._разойтись(а, б)
        зерк, _ = П._разойтись(а, П._зеркально(б))
        # Зеркальная поза это та же поза: ни одна кнопка не требует
        # именно правой руки. Берём меньшее из двух.
        лучшее, отражено = прямо, False
        if зерк is not None and (прямо is None or зерк < прямо):
            лучшее, отражено = зерк, True
        if лучшее is None:
            без_скелета.append(к)
            continue
        ряд.append((к, round(лучшее, 3), отражено))
    ряд.sort(key=lambda з: з[1])

    куда = os.path.join(папка, "отобрано", ключ)
    if ряд:
        os.makedirs(куда, exist_ok=True)
        for н, (к, мера, _) in enumerate(ряд[:сколько], 1):
            # Имя несёт меру: потом видно, чем кадр заслужил место, и
            # разговор идёт про число, а не про «этот вроде лучше».
            новое = "%d_%s_%s" % (н, ("%.3f" % мера).replace(".", "_"),
                                  os.path.basename(к))
            shutil.copy2(к, os.path.join(куда, новое))
    return {"эталон": э, "ряд": ряд, "без_скелета": без_скелета,
            "куда": куда if ряд else "", "порог": П.ПОРОГ}


def напечатать(ключ, о, сколько=3):
    print("\n" + "=" * 64)
    print("КНОПКА", ключ)
    if о.get("беда"):
        print("  беда:", о["беда"])
        return
    print("  принятый кадр:", os.path.basename(о["эталон"]))
    print("  кадров со скелетом: %d, без скелета: %d"
          % (len(о["ряд"]), len(о["без_скелета"])))
    print("  порог совпадения:", о["порог"])
    print("\n  %-4s %-9s %-9s %s" % ("№", "мера", "зеркально", "файл"))
    for н, (к, мера, отр) in enumerate(о["ряд"][:max(сколько * 3, 10)], 1):
        метка = "<- берём" if н <= сколько else ""
        print("  %-4d %-9.3f %-9s %s %s"
              % (н, мера, "да" if отр else "", os.path.basename(к), метка))
    if о["куда"]:
        print("\n  лучшие лежат в:", о["куда"])


def главная(доводы):
    if len(доводы) < 2:
        print(__doc__)
        return 1
    ключи = [к.strip() for к in доводы[0].split(",") if к.strip()]
    папка = доводы[1]
    сколько = 3
    if "--сколько" in доводы:
        сколько = int(доводы[доводы.index("--сколько") + 1])
    свод = {}
    for ключ in ключи:
        о = отобрать(ключ, папка, сколько)
        напечатать(ключ, о, сколько)
        свод[ключ] = {"беда": о.get("беда"),
                      "лучшие": [{"файл": к, "мера": м, "зеркально": з}
                                 for к, м, з in о.get("ряд", [])[:сколько]]}
    путь = os.path.join(папка, "отбор.json")
    try:
        with open(путь, "w", encoding="utf-8") as ф:
            json.dump(свод, ф, ensure_ascii=False, indent=1)
        print("\nсвод:", путь)
    except OSError as e:
        print("свод не записался:", e)
    return 0


if __name__ == "__main__":
    sys.exit(главная(sys.argv[1:]))
