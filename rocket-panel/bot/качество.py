# -*- coding: utf-8 -*-
"""Приёмщик кадра: дефекты генерации числами, а не на глаз.

## Зачем это есть

Владелец 28.09.2026 разобрал пробу по зонам и назвал десять дефектов:
мыло и замазанность, мазки, лишние точки, пятна, неверные цвета,
нечёткие соски, гениталии кашей, смазанное лицо, перепутанный пол,
склеенные тела и вывернутые конечности. Кнопок в боте 64, у каждой свои
позы, и смотреть их глазами дороже, чем производить.

Глаз к тому же врёт в обе стороны. «Стало лучше» после правки CFG
оказывалось «стало ярче», а настоящая фактура при этом падала. Поэтому
каждый кадр меряется числами, и правка принимается только если число
выросло.

## Что меряется и почему именно так

**Фактура кожи** считается ТОЛЬКО по коже, а не по всему кадру. Кадр
целиком включает волосы, ткань и фон, у них своя частота, и замыленная
кожа рядом с резкими волосами даёт «хорошую» общую цифру. Маска кожи
берётся по YCrCb: этот цветовой простор отделяет тон от яркости, и
загорелая кожа в тени попадает в ту же область, что освещённая.

**Высокие частоты** считаются отдельно от Лапласа. Лаплас растёт и от
контраста тоже: задерите контраст, и «фактура» вырастет без единой
новой детали. Доля энергии выше порога в спектре на контраст не
реагирует, и мыло ловит честнее.

**Лицо меряется отдельно.** В полный рост лицо занимает около десятой
части высоты кадра, и его резкость тонет в общем числе. Жалоба «лицо
смазано, чем дальше тем хуже» появилась раньше, чем общая мера успела
шевельнуться.

**Сходство лица** считается косинусом эмбеддингов InsightFace, той же
моделью, что стоит в заслоне возраста. Порог 0.45 - обычная граница
«тот же человек» для buffalo_l, но нам важно не абсолютное значение, а
падение относительно прошлой сборки.

**Точки и пятна** ищутся как отклонение от МЕСТНОГО среднего, а не от
общего. Тень под грудью темнее среднего по кадру на столько же, на
сколько чёрная крапина темнее соседней кожи, и порог по общему среднему
считает тень дефектом.

**Анатомия** проверяется позой MediaPipe: сколько людей нашлось, все ли
конечности на месте, нет ли лишних. Это грубая проверка, она не поймает
шестой палец, но ловит то, что владелец назвал первым: пропавшую ногу,
третью руку, склеенные в одно тела.

Ни одна мера не выносит приговор в одиночку. `оценить` собирает их в
отчёт, а решение принимает `вердикт` по порогам, и пороги живут здесь
же, чтобы их можно было двигать замерами, а не спором.

    python3 -m качество <кадр.png> [референс.jpg]
"""

