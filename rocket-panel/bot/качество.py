# Пороги. Выставлены по замерам 28.09.2026 на пробах «в полный рост»:
# исходное фото Ники (настоящая камера) и её же вывод карты.
#
#     фактура кожи   настоящее фото 10.4 при яркости 61
#                    вывод карты    19.5 при яркости 150
#
# Прямое сравнение двух чисел бессмысленно: фактура растёт с яркостью и
# с контрастом. Поэтому порогом служит не абсолют, а доля высоких
# частот, она от яркости почти не зависит.
# КАЛИБРОВКА 28.09.2026. Пороги выставлены по паре «настоящее фото
# против нашего вывода» на одной и той же героине и одном плане:
#
#     мера              настоящее фото   вывод карты
#     плоской кожи            4.9 %        14.9 и 15.1 %
#     точек на коже           0.97 %        0.83 и 1.06 %
#     сходство лица           0.99          0.59 и 0.55
#     резкость лица          15.7          37.3 и 34.7
#
# Отсюда два вывода, которые стоили первой негодной версии приёмщика.
#
# ПЛОЩАДЬ ЗАЛИВКИ - главная мера. Разрыв втрое, и он ровно про то, на
# что жалуется владелец: «всё замазано чем-то».
#
# РЕЗКОСТЬ ЛИЦА МЕРОЙ НЕ СЛУЖИТ. У вывода она ВДВОЕ выше, чем у
# настоящего фото, потому что апскейлер добавляет высокочастотное
# зерно, и Лаплас считает его деталями. Мера, которая объявляет
# замыленный кадр резче эталона, не мера. Оставлена справочно.
#
# ТОЧКИ у эталона и у вывода сопоставимы, значит по этой мере кадры уже
# не отличаются, и порог ставится выше обоих - иначе он бракует всё.
ПОРОГИ = {
    "плоской_кожи": 8.0,        # процент кожи, замазанной в заливку
    "плоской_кожи_лица": 10.0,  # то же, но только по лицу
    "сходство_лица": 0.62,      # косинус InsightFace с референсом
    "точек_на_коже": 1.5,       # процент площади кожи
    "пересветов": 3.0,          # процент площади кадра
}

# К какой высоте лица приводится кадр перед мерами. Сравнивать кадры
# «как есть» нельзя: в полный рост лицо занимает 200 пикселей, в
# крупном плане 900, и любая мера резкости у крупного выше от одного
# лишь масштаба. Замер 28.09.2026: настоящее фото от gpt-image-2
# получило резкость лица 10.8, а замыленный вывод карты 18.1 - ровно
# потому, что у вывода лицо было мельче и его растянули.
ЛИЦО_К = 200

_лица = None


def _модель_лиц():
    """InsightFace на процессоре. Та же, что в заслоне возраста."""
    global _лица
    if _лица is None:
        from insightface.app import FaceAnalysis
        _лица = FaceAnalysis(name="buffalo_l",
                             providers=["CPUExecutionProvider"])
        # 640 вместо 320: в полный рост лицо мелкое, на 320 оно теряется
        # вовсе, и «лица нет» читается как дефект кадра, хотя дефект наш.
        _лица.prepare(ctx_id=-1, det_size=(640, 640))
    return _лица


def маска_кожи(кадр):
    """Где на кадре кожа. Возвращает маску 0/255.

    YCrCb, а не HSV: в HSV загорелая кожа в тени уезжает по яркости и
    выпадает из диапазона, и мерить остаётся только освещённый бок.
    Границы Cr и Cb взяты общепринятые для тона кожи и проверены на
    наших кадрах - в маску не попадают ни серый фон, ни белые кроссовки.
    """
    ycrcb = cv2.cvtColor(кадр, cv2.COLOR_BGR2YCrCb)
    маска = cv2.inRange(ycrcb, (0, 133, 77), (255, 180, 127))
    # Волосы и брови тоже иногда попадают в диапазон. Открытие сносит
    # тонкие пряди, оставляя сплошные участки тела.
    ядро = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (9, 9))
    маска = cv2.morphologyEx(маска, cv2.MORPH_OPEN, ядро)
    return cv2.morphologyEx(маска, cv2.MORPH_CLOSE, ядро)


def доля_высоких_частот(серый, маска=None, порог=0.25):
    """Сколько в куске энергии выше порога. Мера «замыленности».

    Считается по спектру, а не по градиенту: градиент растёт вместе с
    контрастом, и поднятая кривая выдаёт себя за детализацию. Доля
    энергии на высоких частотах к контрасту почти безразлична.
    """
    к = серый.astype(np.float32)
    if маска is not None:
        # Пустые места заполняем средним, иначе край маски сам даст
        # резкий перепад и попадёт в высокие частоты как «деталь».
        ср = float(к[маска > 0].mean()) if (маска > 0).any() else float(к.mean())
        к = np.where(маска > 0, к, ср)
    к = к - к.mean()
    спектр = np.abs(np.fft.fftshift(np.fft.fft2(к)))
    h, w = спектр.shape
    yy, xx = np.ogrid[:h, :w]
    r = np.hypot(yy - h / 2, xx - w / 2) / (np.hypot(h, w) / 2)
    вся = спектр.sum()
    return float(спектр[r > порог].sum() / вся) if вся else 0.0


def _кожа_кусками(кадр, маска, сторона=192):
    """Куски кадра, где кожи больше половины. По ним и меряем.

    Кусками, а не всей маской разом: сплошная маска включает границы
    тела и тени между ногами, на них спектр врёт. Кусок внутри бедра
    или живота это чистая кожа и ничего больше.
    """
    h, w = маска.shape
    куски = []
    for y in range(0, h - сторона, сторона):
        for x in range(0, w - сторона, сторона):
            м = маска[y:y + сторона, x:x + сторона]
            if (м > 0).mean() > 0.9:
                куски.append(кадр[y:y + сторона, x:x + сторона])
    return куски


def плоскость_кожи(кадр, маска):
    """Доля кожи, замазанной в сплошную заливку.

    Самая прямая мера того, на что жалуется владелец. У настоящей кожи
    даже в тени есть микрофактура: местное отклонение яркости держится
    около трёх-шести единиц. У «пластиковой» кожи оно падает почти к
    нулю, и участок становится заливкой.

    Считается местное стандартное отклонение в окне 7 на 7 и берётся
    доля кожи, где оно ниже порога. Мера не зависит ни от яркости, ни
    от контраста, ни от размера кадра - в отличие от Лапласа, который
    растёт от любого из них.
    """
    if (маска > 0).mean() < 0.02:
        return None
    г = cv2.cvtColor(кадр, cv2.COLOR_BGR2GRAY).astype(np.float32)
    ср = cv2.blur(г, (7, 7))
    дисп = cv2.blur(г * г, (7, 7)) - ср * ср
    ско = np.sqrt(np.maximum(дисп, 0))
    кожа = маска > 0
    return round(float((ско[кожа] < 2.0).mean() * 100), 1)


def привести(кадр, высота_лица=None):
    """Привести кадр к одному масштабу по высоте лица.

    Все меры кожи и лица считаются ПОСЛЕ этого, иначе кадры разного
    плана несравнимы между собой (см. ЛИЦО_К).
    """
    if not высота_лица or высота_лица < 20:
        return кадр
    к = ЛИЦО_К / высота_лица
    if 0.95 < к < 1.05:
        return кадр
    сп = cv2.INTER_AREA if к < 1 else cv2.INTER_CUBIC
    return cv2.resize(кадр, (max(8, int(кадр.shape[1] * к)),
                             max(8, int(кадр.shape[0] * к))), interpolation=сп)


def высота_лица(кадр):
    """Высота самого крупного лица в пикселях, 0 если лица нет."""
    try:
        найдено = _модель_лиц().get(кадр)
    except Exception:                                       # noqa: BLE001
        return 0
    if not найдено:
        return 0
    л = max(найдено, key=lambda f: (f.bbox[3] - f.bbox[1]))
    return float(л.bbox[3] - л.bbox[1])


def детализация(кадр):
    """Насколько кожа выглядит кожей, а не заливкой."""
    маска = маска_кожи(кадр)
    доля = float((маска > 0).mean())
    куски = _кожа_кусками(кадр, маска)
    if not куски:
        return {"кожи_в_кадре": round(доля * 100, 1), "кусков": 0,
                "плоской_кожи": плоскость_кожи(кадр, маска),
                "высокие_частоты": None, "фактура": None}
    вч, факт = [], []
    for к in куски:
        г = cv2.cvtColor(к, cv2.COLOR_BGR2GRAY)
        вч.append(доля_высоких_частот(г))
        факт.append(float(cv2.Laplacian(г, cv2.CV_64F).std()))
    return {"кожи_в_кадре": round(доля * 100, 1), "кусков": len(куски),
            "плоской_кожи": плоскость_кожи(кадр, маска),
            # Медиана, а не среднее: один кусок с волосами или швом
            # одежды поднимает среднее и прячет мыло на остальных.
            "высокие_частоты": round(float(np.median(вч)), 4),
            "фактура": round(float(np.median(факт)), 2)}


def пятна_и_точки(кадр):
    """Тёмные крапины и белёсые пятна на коже.

    Отклонение считается от МЕСТНОГО среднего (большое размытие), а не
    от среднего по кадру: тень под грудью темнее кадра ровно настолько
    же, насколько крапина темнее соседней кожи.
    """
    маска = маска_кожи(кадр)
    если_нет = {"точек": None, "пятен": None, "крупных_пятен": 0}
    if (маска > 0).mean() < 0.02:
        return если_нет
    серый = cv2.cvtColor(кадр, cv2.COLOR_BGR2GRAY).astype(np.float32)
    местное = cv2.GaussianBlur(серый, (0, 0), 25)
    разница = серый - местное
    кожа = маска > 0
    # -25, а не -14: на мягком пороге в «точки» попадала обычная
    # светотень, и 28.09.2026 его провалили ВСЕ кадры разом, включая
    # настоящее фото. Порог, который не проходит эталон, не мера.
    тёмные = (разница < -25) & кожа
    светлые = (разница > 25) & кожа
    площадь = float(кожа.sum())
    # Крупные светлые области это не блик, а призрак: блик мягкий и
    # вытянут по форме тела, призрак сплошной и с резким краем.
    n, _, стат, _ = cv2.connectedComponentsWithStats(
        светлые.astype(np.uint8), 8)
    крупных = int(sum(1 for i in range(1, n)
                      if стат[i, cv2.CC_STAT_AREA] > площадь * 0.004))
    # Точка мелкая по определению: крупное тёмное это тень от руки или
    # складки, и считать её дефектом значит браковать анатомию кадра.
    nт, _, статт, _ = cv2.connectedComponentsWithStats(тёмные.astype(np.uint8), 8)
    мелких = float(sum(статт[i, cv2.CC_STAT_AREA] for i in range(1, nт)
                       if статт[i, cv2.CC_STAT_AREA] < площадь * 0.0006))
    return {"точек": round(мелких / площадь * 100, 3),
            "пятен": round(float(светлые.sum()) / площадь * 100, 3),
            "крупных_пятен": крупных}


def лицо(кадр, референс=None):
    """Резкость лица и сходство с референсом.

    Лицо меряется отдельно от тела: в полный рост оно занимает около
    десятой части высоты, и его мыло тонет в общей цифре.
    """
    итог = {"лиц": 0, "резкость_лица": None, "сходство_лица": None,
            "доля_лица": None}
    try:
        м = _модель_лиц()
        найдено = м.get(кадр)
    except Exception as e:                                  # noqa: BLE001
        итог["ошибка"] = str(e)[:120]
        return итог
    итог["лиц"] = len(найдено)
    if not найдено:
        return итог
    # Самое крупное: остальные это лица второго плана или ложные срабатывания.
    л = max(найдено, key=lambda f: (f.bbox[2] - f.bbox[0]) * (f.bbox[3] - f.bbox[1]))
    x1, y1, x2, y2 = [int(v) for v in л.bbox]
    h, w = кадр.shape[:2]
    x1, y1 = max(0, x1), max(0, y1)
    x2, y2 = min(w, x2), min(h, y2)
    if x2 - x1 < 12 or y2 - y1 < 12:
        return итог
    кусок = кадр[y1:y2, x1:x2]
    итог["доля_лица"] = round((y2 - y1) / h * 100, 1)
    # Второго приведения тут нет: кадр уже нормирован по высоте лица в
    # `оценить`, и лишний ресайз только добавил бы мыла.
    г = cv2.cvtColor(кусок, cv2.COLOR_BGR2GRAY)
    итог["резкость_лица"] = round(float(cv2.Laplacian(г, cv2.CV_64F).std()), 2)
    итог["высокие_частоты_лица"] = round(доля_высоких_частот(г), 4)
    # Заливка ПО ЛИЦУ отдельно: жалоба «лицо смазано» появлялась раньше,
    # чем шевелилась общая мера по телу, потому что лицо занимает около
    # десятой части кадра и тонет в ней.
    итог["плоской_кожи_лица"] = плоскость_кожи(кусок, маска_кожи(кусок))
    if референс is not None:
        эт = _модель_лиц().get(референс)
        if эт:
            э = max(эт, key=lambda f: (f.bbox[2] - f.bbox[0]) * (f.bbox[3] - f.bbox[1]))
            a = л.normed_embedding
            b = э.normed_embedding
            итог["сходство_лица"] = round(float(np.dot(a, b)), 3)
    return итог


def анатомия(кадр, людей_ждём=1):
    """Сколько людей и все ли конечности на месте.

    Грубая проверка позой MediaPipe. Шестой палец она не поймает, но
    ловит то, что владелец назвал первым: пропавшую ногу, третью руку,
    склеенные в одно тела.
    """
    итог = {"людей_поза": None, "видимых_точек": None,
            "нет_конечностей": [], "людей_ждём": людей_ждём}
    try:
        import mediapipe as mp
    except Exception as e:                                  # noqa: BLE001
        итог["ошибка"] = str(e)[:100]
        return итог
    try:
        with mp.solutions.pose.Pose(static_image_mode=True,
                                    model_complexity=2,
                                    min_detection_confidence=0.4) as поза:
            о = поза.process(cv2.cvtColor(кадр, cv2.COLOR_BGR2RGB))
    except Exception as e:                                  # noqa: BLE001
        итог["ошибка"] = str(e)[:100]
        return итог
    if not о.pose_landmarks:
        итог["людей_поза"] = 0
        return итог
    точки = о.pose_landmarks.landmark
    видимых = sum(1 for т in точки if т.visibility > 0.5)
    итог["людей_поза"] = 1
    итог["видимых_точек"] = видимых
    # Конечность считается пропавшей, когда не видно НИ ОДНОГО её узла:
    # кисть за спиной это нормально, а отсутствие всей руки нет.
    ЧАСТИ = {"левая рука": (11, 13, 15), "правая рука": (12, 14, 16),
             "левая нога": (23, 25, 27), "правая нога": (24, 26, 28)}
    for имя, узлы in ЧАСТИ.items():
        if all(точки[i].visibility < 0.3 for i in узлы):
            итог["нет_конечностей"].append(имя)
    return итог


def цвет_кожи(кадр):
    """Средний тон кожи в Lab. Нужен, чтобы ловить уехавший цвет."""
    маска = маска_кожи(кадр)
    if (маска > 0).mean() < 0.02:
        return None
    lab = cv2.cvtColor(кадр, cv2.COLOR_BGR2LAB)
    сред = [float(np.median(lab[:, :, i][маска > 0])) for i in range(3)]
    return [round(с, 1) for с in сред]


def оценить(путь, референс=None, людей=1):
    """Полный отчёт по кадру. Числа, без приговора."""
    исходный = cv2.imread(путь)
    if исходный is None:
        return {"ошибка": f"кадр не читается: {путь}"}
    эталон_исх = cv2.imread(референс) if референс else None
    серый = cv2.cvtColor(исходный, cv2.COLOR_BGR2GRAY)
    о = {"файл": os.path.basename(путь),
         "размер": f"{исходный.shape[1]}x{исходный.shape[0]}",
         "яркость": round(float(серый.mean()), 1),
         "пересветов": round(float((серый > 245).mean() * 100), 2)}
    # ВСЕ меры кожи и лица считаются по приведённому кадру: иначе
    # крупный план всегда выигрывает у общего от одного лишь масштаба.
    вл = высота_лица(исходный)
    о["высота_лица_px"] = round(вл)
    кадр = привести(исходный, вл)
    эт = привести(эталон_исх, высота_лица(эталон_исх)) \
        if эталон_исх is not None else None
    о.update(детализация(кадр))
    о.update(пятна_и_точки(кадр))
    # Сходство лица считается по ИСХОДНЫМ кадрам: приведение теряет
    # пиксели, а модель лиц и так приводит вырезку к своему размеру.
    о.update(лицо(кадр, эталон_исх))
    о.update(анатомия(исходный, людей))
    о["цвет_кожи"] = цвет_кожи(кадр)
    if эт is not None:
        цэ = цвет_кожи(эт)
        if цэ and о["цвет_кожи"]:
            # Разница только по тону (a, b), без яркости: свет сцены
            # меняется по замыслу, а тон кожи человека нет.
            о["сдвиг_тона"] = round(float(np.hypot(
                о["цвет_кожи"][1] - цэ[1], о["цвет_кожи"][2] - цэ[2])), 1)
    о["беды"] = вердикт(о)
    return о


def вердикт(о, людей=None):
    """Что именно плохо. Пустой список значит претензий нет."""
    беды = []
    пл = о.get("плоской_кожи")
    if пл is not None and пл > ПОРОГИ["плоской_кожи"]:
        беды.append(f"кожа замазана в заливку ({пл}% против "
                    f"{ПОРОГИ['плоской_кожи']}%)")
    пл_л = о.get("плоской_кожи_лица")
    if пл_л is not None and пл_л > ПОРОГИ["плоской_кожи_лица"]:
        беды.append(f"лицо замазано ({пл_л}% против "
                    f"{ПОРОГИ['плоской_кожи_лица']}%)")
    сл = о.get("сходство_лица")
    if сл is not None and сл < ПОРОГИ["сходство_лица"]:
        беды.append(f"лицо не совпало с референсом ({сл})")
    т = о.get("точек")
    if т is not None and т > ПОРОГИ["точек_на_коже"]:
        беды.append(f"точки на коже ({т}%)")
    if о.get("пересветов", 0) > ПОРОГИ["пересветов"]:
        беды.append(f"пересветы ({о['пересветов']}%)")
    if о.get("нет_конечностей"):
        беды.append("пропала конечность: " + ", ".join(о["нет_конечностей"]))
    ждём = людей if людей is not None else о.get("людей_ждём", 1)
    лиц = о.get("лиц")
    if лиц is not None and ждём and лиц != ждём:
        беды.append(f"лиц в кадре {лиц}, а нужно {ждём}")
    return беды


