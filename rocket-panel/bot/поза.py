# -*- coding: utf-8 -*-
"""Анатомия кадра позой MediaPipe. Запускается ОТДЕЛЬНЫМ питоном.

## Почему отдельным

MediaPipe тянет за собой numpy первой версии, а в боевом окружении
живёт вторая: там стоят insightface и заслон возраста, и понижение
numpy ломает их обоих. 28.09.2026 я поставила mediapipe прямо в боевой
venv и откатывала это в ту же минуту - заслон возраста перестал
подниматься.

Поэтому mediapipe живёт в своём окружении `/opt/amberry/.venv-poza`, а
зовётся подпроцессом. Цена - запуск процесса на кадр, примерно секунда.
Выигрыш - проверка того, на что владелец жаловался первым: «руки ноги
наизнанку, отсутствует нога или рука, по 3 руки».

## Что считается

Людей в кадре, видимые узлы каждого, пропавшие конечности. Конечность
считается пропавшей, когда не видно НИ ОДНОГО её узла: кисть за спиной
это нормально, отсутствие всей руки нет.

    from поза import разобрать
    разобрать("/кадр.png", людей=2)
"""

import json
import os
import subprocess
import sys

ПИТОН = os.environ.get("ROCKET_POZA_PY", "/opt/amberry/.venv-poza/bin/python")

# Тело скрипта, который исполняется ТЕМ питоном. Держим строкой, а не
# отдельным файлом: файл рядом с этим модулем боевой питон однажды
# импортирует сам, и mediapipe утянет numpy обратно.
_СКРИПТ = r'''
import json, sys
import cv2, numpy as np, mediapipe as mp

путь = sys.argv[1]
кадр = cv2.imread(путь)
if кадр is None:
    print(json.dumps({"ошибка": "кадр не читается"})); raise SystemExit
ЧАСТИ = {"левая рука": (11, 13, 15), "правая рука": (12, 14, 16),
         "левая нога": (23, 25, 27), "правая нога": (24, 26, 28)}
# Многолюдный разбор: у MediaPipe Pose один человек на вызов, поэтому
# людей ищем детектором лиц СНАРУЖИ и сюда отдаём уже вырезки. Здесь
# считается один человек на кадр или на вырезку.
with mp.solutions.pose.Pose(static_image_mode=True, model_complexity=2,
                            min_detection_confidence=0.4) as поза:
    о = поза.process(cv2.cvtColor(кадр, cv2.COLOR_BGR2RGB))
if not о.pose_landmarks:
    print(json.dumps({"людей_поза": 0})); raise SystemExit
т = о.pose_landmarks.landmark
итог = {"людей_поза": 1,
        "видимых_точек": sum(1 for у in т if у.visibility > 0.5),
        "нет_конечностей": [и for и, у in ЧАСТИ.items()
                            if all(т[k].visibility < 0.3 for k in у)]}
# Вывернутая конечность: локоть или колено должны лежать МЕЖДУ своими
# соседями. Если узел вылетел далеко за отрезок плечо-кисть, сустав
# согнут не туда - ровно то, что владелец зовёт «руки наизнанку».
def вывернут(a, b, c):
    A = np.array([т[a].x, т[a].y]); B = np.array([т[b].x, т[b].y])
    C = np.array([т[c].x, т[c].y])
    if min(т[a].visibility, т[b].visibility, т[c].visibility) < 0.5:
        return False
    длина = np.linalg.norm(C - A)
    if длина < 1e-3:
        return False
    # Доля, на которой средний узел проецируется на отрезок. За
    # пределами [-0.35, 1.35] сустав выехал за собственную конечность.
    доля = float(np.dot(B - A, C - A) / (длина * длина))
    return доля < -0.35 or доля > 1.35
кривые = [и for и, (a, b, c) in {"левый локоть": (11, 13, 15),
                                 "правый локоть": (12, 14, 16),
                                 "левое колено": (23, 25, 27),
                                 "правое колено": (24, 26, 28)}.items()
          if вывернут(a, b, c)]
if кривые:
    итог["вывернуто"] = кривые
print(json.dumps(итог, ensure_ascii=False))
'''


def доступна():
    """Есть ли на машине окружение позы."""
    return os.path.exists(ПИТОН)


def разобрать(путь, таймаут=90):
    """Анатомия одного человека на кадре или на вырезке."""
    if not доступна():
        return {"ошибка": f"нет окружения позы ({ПИТОН})"}
    try:
        о = subprocess.run([ПИТОН, "-c", _СКРИПТ, путь],
                           capture_output=True, text=True, timeout=таймаут)
    except subprocess.TimeoutExpired:
        return {"ошибка": "поза не ответила"}
    строка = (о.stdout or "").strip().splitlines()
    if not строка:
        return {"ошибка": (о.stderr or "поза молчит")[-160:]}
    try:
        return json.loads(строка[-1])
    except ValueError:
        return {"ошибка": строка[-1][:160]}


if __name__ == "__main__":
    print(json.dumps(разобрать(sys.argv[1]), ensure_ascii=False, indent=1))
