def включён():
    """Выключается только переменной, и это осознанно: выключенный
    заслон означает, что бот снова принимает любые снимки."""
    return os.environ.get("AMBERRY_AGE", "1") != "0"


# ------------------------------------------------------- лицо на снимке

_лица = None
_лица_нет = False


def _модель_лиц():
    """InsightFace, поднятая один раз на весь процесс.

    Поднимать на каждый снимок нельзя: разбор весит секунды, а сама
    проверка - доли секунды.
    """
    global _лица, _лица_нет
    if _лица is not None or _лица_нет:
        return _лица
    try:
        from insightface.app import FaceAnalysis
        м = FaceAnalysis(name=os.environ.get("AMBERRY_AGE_PACK", "buffalo_l"),
                         providers=["CPUExecutionProvider"])
        # 640 на 640: на меньшем размере детектор теряет лицо в полный
        # рост, а именно так снимки и присылают.
        м.prepare(ctx_id=-1, det_size=(640, 640))
        _лица = м
        return м
    except Exception as e:                              # noqa: BLE001
        print("модель лиц не поднялась:", str(e)[:200], flush=True)
        _лица_нет = True
        return None


def вырезать_лицо(байты):
    """(виды_лица, сколько_лиц, доля_кадра). Лица нет - ([], 0, 0).

    Берётся САМОЕ КРУПНОЕ лицо: на снимке бывает второй человек в
    глубине кадра, а проверять надо того, кого прислали.

    Видов несколько: три размера полей и зеркало к каждому. Зачем -
    в шапке у `ПОЛЯ_НАБОР`.

    `сколько_лиц = None` означает «модель не работает», и это не то же
    самое, что ноль: ноль - отказ, неработающая модель - отдельный
    разговор выше по течению.
    """
    м = _модель_лиц()
    if м is None:
        return [], None, 0.0
    try:
        import cv2
        import numpy as np
        from PIL import Image
        кадр = cv2.imdecode(np.frombuffer(байты, np.uint8), cv2.IMREAD_COLOR)
        if кадр is None:
            return [], None, 0.0
        лица = м.get(кадр)
        if not лица:
            return [], 0, 0.0
        л = max(лица, key=lambda x: (x.bbox[2] - x.bbox[0])
                * (x.bbox[3] - x.bbox[1]))
        x1, y1, x2, y2 = [float(v) for v in л.bbox]
        ш, в = x2 - x1, y2 - y1
        доля = round(ш * в / (кадр.shape[0] * кадр.shape[1]), 4)
        виды = []
        for поля in ПОЛЯ_НАБОР:
            a = max(0, int(x1 - ш * поля))
            b = max(0, int(y1 - в * поля))
            c = min(кадр.shape[1], int(x2 + ш * поля))
            d = min(кадр.shape[0], int(y2 + в * поля))
            кусок = кадр[b:d, a:c]
            if кусок.size == 0:
                continue
            им = Image.fromarray(cv2.cvtColor(кусок, cv2.COLOR_BGR2RGB))
            виды.append(им)
            виды.append(им.transpose(Image.FLIP_LEFT_RIGHT))
        return виды, len(лица), доля
    except Exception as e:                              # noqa: BLE001
        print("вырезать лицо не вышло:", str(e)[:200], flush=True)
        return [], None, 0.0


# --------------------------------------------------- модели возраста

_судьи = {}
_судьи_нет = False


def _поднять_судей():
    """Три модели, поднятые один раз. Пустой список - ни одна не встала."""
    global _судьи_нет
    if _судьи or _судьи_нет:
        return _судьи
    try:
        import torch                                    # noqa: F401
        from transformers import (AutoImageProcessor,
                                  AutoModelForImageClassification)
    except Exception as e:                              # noqa: BLE001
        print("библиотеки моделей возраста не встали:", str(e)[:150],
              flush=True)
        _судьи_нет = True
        return _судьи
    for имя in СУДЬИ:
        try:
            о = AutoImageProcessor.from_pretrained(имя)
            м = AutoModelForImageClassification.from_pretrained(имя)
            м.eval()
            _судьи[имя] = (о, м)
        except Exception as e:                          # noqa: BLE001
            print(f"модель {имя} не поднялась:", str(e)[:150], flush=True)
    if not _судьи:
        _судьи_нет = True
    return _судьи


def _границы(метка):
    """(снизу, сверху) по названию корзины. Названия у всех свои:
    «Teenager 13-20», «age 11-20», «16-20», «80 +»."""
    ч = [int(x) for x in re.findall(r"\d+", метка)]
    if not ч:
        return None
    if "+" in метка and len(ч) == 1:
        return float(ч[0]), float(ч[0]) + 15
    if len(ч) == 1:
        return float(ч[0]), float(ч[0]) + 0.99
    return float(ч[0]), float(ч[1])


def _доля_младше(обработчик, модель, виды):
    """Вероятность «младше восемнадцати» по одной модели, по всем видам.

    Спрашивается именно доля, а не «сколько лет»: все эти модели дают
    корзины, и корзина «13-20» сама по себе ответа не содержит. Зато
    распределение по корзинам содержит, причём вместе с мерой
    собственной неуверенности.

    Виды усредняются: см. `ПОЛЯ_НАБОР`.
    """
    import torch
    if not виды:
        return None
    # Все виды идут ОДНИМ заходом, а не по очереди: шесть отдельных
    # прогонов через три модели занимали 1,1 секунды, батч делает то же
    # за треть. Человек ждёт эту разницу вживую.
    вход = обработчик(images=list(виды), return_tensors="pt")
    with torch.no_grad():
        веро = torch.softmax(модель(**вход).logits, dim=-1).tolist()
    метки = модель.config.id2label
    # Веса корзин считаются ОДИН раз на модель, а не на каждый вид:
    # они зависят только от разметки классов.
    вес = []
    for i in range(len(метки)):
        г = _границы(str(метки[i]))
        if not г:
            вес.append(0.0)
            continue
        снизу, сверху = г
        if сверху < ВЗРОСЛЫЙ_С:
            вес.append(1.0)
        elif снизу < ВЗРОСЛЫЙ_С < сверху:
            # Корзина лежит по обе стороны порога: берём ту долю, что
            # ниже. Ровное деление, потому что внутри корзины модель
            # распределения не даёт, а выдумывать его нельзя.
            вес.append((ВЗРОСЛЫЙ_С - снизу) / (сверху - снизу))
        else:
            вес.append(0.0)
    итог = [sum(p * в for p, в in zip(ряд, вес)) for ряд in веро]
    return sum(итог) / len(итог) if итог else None


def насколько_младше(виды):
    """(средняя доля, разбор по моделям). `None` - ни одна не ответила."""
    судьи = _поднять_судей()
    if not судьи or not виды:
        return None, {}
    доли = {}
    for имя, (о, м) in судьи.items():
        try:
            д = _доля_младше(о, м, виды)
            if д is not None:
                доли[имя.split("/")[-1]] = round(д, 3)
        except Exception as e:                          # noqa: BLE001
            print(f"модель {имя} сорвалась:", str(e)[:120], flush=True)
    if not доли:
        return None, {}
    return sum(доли.values()) / len(доли), доли


