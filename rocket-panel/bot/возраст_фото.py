"""Заслон на детские снимки: проверка САМОГО ФОТО до всякой работы.

## Зачем

Список запрещённых слов стоит и работает, но честно говорит о себе
сам: «присланное фото ребёнка с нейтральным „раздень её“ ни одно слово
не сработает». 28.09.2026 это случилось живьём.

Цена ошибки не в качестве кадра. Сервис за неё закрывают целиком.

## Где стоит

В `on_photo`, сразу после того как снимок скачан, и ДО того как он лёг
к нам на диск, ушёл на карту и списал коины.

## Правило владельца 28.09.2026: ровно восемнадцать

«18 лет разрешено, 17 лет уже нет», и отдельно: «очень внимательно,
чтобы не отказывать фоткам после 18». Это две разные ошибки, и обе
стоят денег: пропустить ребёнка - потерять сервис, завернуть взрослую
клиентку - потерять клиента.

## Всё считается на нашем сервере и бесплатно

    1. InsightFace находит лицо и вырезает его        0,15 с
    2. Три модели возраста смотрят вырезанное лицо    0,05 с каждая
    3. Решение по их согласию                         мгновенно

Ни одна не спрашивает интернет, ни одна не стоит денег, снимок клиента
никуда не уходит. Последнее и само по себе довод: человек прислал своё
фото нам, а не чужому сервису.

Gemini остался, но ТОЛЬКО как необязательное второе мнение в спорной
зоне. Его молчание ничего не ломает: бесплатная квота там 20 запросов
в сутки на модель, и строить на ней заслон значит строить на песке.

## Почему лицо вырезается, а не отдаётся весь кадр

Замер 28.09.2026 на трёх эталонах владельца, доля «младше 18» по
ансамблю:

    по всему кадру    подросток 45,6 %   взрослые 38,8 и 37,6 %
    по лицу           подросток 72,9 %   взрослые 48,5 и 11,3 %

На снимке в полный рост лицо занимает полтора процента площади, и
модель разглядывает джинсы и стену. Разделения при этом почти нет.

## Почему моделей три, и почему именно эти

Каждая ошибается по-своему, и порознь любая однажды пропустит ребёнка.
Состав выбран не на слух, а перебором ВСЕХ сочетаний из шести моделей
на эталонах владельца, мерой служил зазор между худшим ребёнком и
худшей взрослой.

Две модели из шести выбыли за инверсию: `facial_age_image_detection`
поставила шестнадцатилетней 0,350, а двадцатилетней 0,457, то есть
перепутала их местами; `facial-age-detection` объявила взрослую
подростком на 78 %. Модель, которая путает сторону порога, не
улучшает среднее, а портит его - и первый состав заслона, где стояла
первая из них, ровно на шестнадцатилетней и сломался.

Взят не самый узкий состав, хотя `open-age-detection` в одиночку дала
зазор 0,342 против 0,200 у тройки. На шести снимках такая разница
неотличима от везения, а три независимые модели ошибаются на новом
лице реже, чем одна удачная на старых.

## Почему не InsightFace, хотя она уже стояла

Она отлично находит лицо и никуда не годится в возрасте: снимку
девочки 16-17 лет она выдала **45 лет**, взрослым 25 и 32. Её `age` в
решении не участвует вовсе, и это не осторожность, а прямой вывод из
замера.

## Осечка это отказ, и это не как у приёмки кадра

`контроль.py` при осечке пропускает: там проверка может только
улучшать. Здесь наоборот. Нет лица, не поднялись модели - снимок не
принимается. Иначе заслон снимает любой, кто сумеет его уронить, а
роняют его ровно ради этого.
"""

