# Предохранитель на второе мнение.
#
# Живой журнал 28.09.2026: спорный снимок ждал Gemini 4,27 секунды и
# получил 503, а решение всё равно принял ансамбль. Пока квота выбрана,
# каждый такой вызов это чистая задержка человеку.
#
# Поэтому после трёх осечек подряд второе мнение отключается на час.
# Час, а не навсегда: суточная квота обновляется, и заслон должен
# подобрать её сам, без нашего участия.
_осечек = [0]
_молчим_до = [0.0]
ОСЕЧЕК_ХВАТИТ = 3
ОТДЫХ = 3600


def второе_мнение(байты, таймаут=8):
    """Оценка возраста от Gemini или None. Ждём недолго: это добавка к
    готовому решению, а не оно само, и держать человека ради неё
    нельзя."""
    if time.time() < _молчим_до[0]:
        return None, "отдыхает после осечек"
    все = ключи()
    if not все:
        return None, "нет ключей"
    тело = json.dumps({"contents": [{"parts": [
        {"text": ВОПРОС},
        {"inline_data": {"mime_type": "image/jpeg",
                         "data": base64.b64encode(байты).decode()}}]}],
        "generationConfig": {
            "temperature": 0, "maxOutputTokens": 200,
            # Думать не надо, надо смотреть: с бюджетом мысли ответ
            # уходит в рассуждение и JSON не доезжает.
            "thinkingConfig": {"thinkingBudget": 0},
            "responseMimeType": "application/json"}}).encode()
    последняя = "не пробовали"
    # Одна попытка на пару «модель-ключ» и ни одного повтора: в спорной
    # зоне человек уже ждёт, а перебор с паузами занимал сорок пять
    # секунд (замер 28.09.2026).
    for модель in МОДЕЛИ_GEMINI[:2]:
        к = все[_с_какого[0] % len(все)]
        _с_какого[0] += 1
        try:
            з = urllib.request.Request(
                АДРЕС % (модель, к), data=тело,
                headers={"Content-Type": "application/json"})
            о = json.load(urllib.request.urlopen(з, timeout=таймаут))
            т = о["candidates"][0]["content"]["parts"][0]["text"]
            m = re.search(r"\{.*\}", т, re.S)
            if not m:
                последняя = "ответ без JSON"
                continue
            лет = json.loads(m.group(0)).get("age")
            if лет is not None:
                _осечек[0] = 0
                return float(лет), модель
        except Exception as e:                          # noqa: BLE001
            последняя = str(e)[:80]
    _осечек[0] += 1
    if _осечек[0] >= ОСЕЧЕК_ХВАТИТ:
        _молчим_до[0] = time.time() + ОТДЫХ
        _осечек[0] = 0
        print(f"второе мнение замолчало на {ОТДЫХ // 60} минут: {последняя}",
              flush=True)
    return None, последняя


# ---------------------------------------------------------- решение

_помню = {}
ПОМНИТЬ = int(os.environ.get("AMBERRY_AGE_CACHE", "4000"))


def отпечаток(байты):
    return hashlib.sha256(байты).hexdigest()[:32]


def проверить(байты, помнить=True):
    """(можно, почему, свод). `можно=False` - снимок не принимаем."""
    if not включён():
        return True, "заслон выключен", {"заслон": "выкл"}

    отп = отпечаток(байты)
    if помнить and отп in _помню:
        было = _помню[отп]
        return было[0], было[1], {**было[2], "из памяти": True}

    начало = time.time()
    свод = {"отпечаток": отп}

    виды, лиц, доля = вырезать_лицо(байты)
    свод["лиц"] = лиц
    свод["доля лица"] = доля
    свод["видов"] = len(виды)

    if лиц is None:
        # Модель лиц не работает. Проверять нечем - значит не принимаем.
        свод["сек"] = round(time.time() - начало, 2)
        return _итог(отп, False, "поиск лица недоступен", свод, помнить)

    if not виды:
        свод["сек"] = round(time.time() - начало, 2)
        return _итог(отп, False, "на снимке не видно лица", свод, помнить)

    средняя, по_моделям = насколько_младше(виды)
    свод["младше18"] = None if средняя is None else round(средняя, 3)
    свод["модели"] = по_моделям

    if средняя is None:
        свод["сек"] = round(time.time() - начало, 2)
        return _итог(отп, False, "модели возраста недоступны", свод, помнить)

    # Спорная полоса: спрашиваем Gemini, если он жив. Он именно
    # уточняет, а не решает, и его молчание ничего не меняет.
    if СПОРНО_ОТ <= средняя <= СПОРНО_ДО:
        лет, чем = второе_мнение(байты)
        свод["второе мнение"] = лет
        свод["чем"] = чем
        if лет is not None and лет < ВЗРОСЛЫЙ_С - 1:
            свод["сек"] = round(time.time() - начало, 2)
            return _итог(отп, False,
                         f"спорный снимок, вторая проверка дала {лет:.0f} лет",
                         свод, помнить)

    свод["сек"] = round(time.time() - начало, 2)
    if средняя > ПОРОГ:
        return _итог(отп, False,
                     f"на снимке несовершеннолетний ({средняя * 100:.0f}%)",
                     свод, помнить)
    return _итог(отп, True, f"взрослый ({средняя * 100:.0f}% младше 18)",
                 свод, помнить)


def _итог(отп, можно, почему, свод, помнить):
    if помнить:
        if len(_помню) >= ПОМНИТЬ:
            # Проще вычистить половину разом, чем вести порядок
            # обращений: память тут ради скорости, а не ради точности
            # попаданий.
            for к in list(_помню)[:ПОМНИТЬ // 2]:
                _помню.pop(к, None)
        _помню[отп] = (можно, почему, свод)
    return можно, почему, свод


def журнал(путь, tg_id, можно, почему, свод):
    """Строка в журнал. Он нужен трём разным людям сразу.

    Банку - доказательство, что заслон работает и работал. Нам - чтобы
    видеть, не бракуем ли мы взрослых и на чём именно. Поддержке -
    чтобы ответить человеку, почему его снимок не взяли.

    Записывается и пропуск, и отказ: журнал из одних отказов не
    отвечает на первый вопрос проверяющего, сколько всего проверено.
    """
    запись = {"когда": int(time.time()), "кто": tg_id,
              "принят": bool(можно), "почему": почему, **(свод or {})}
    try:
        каталог = os.path.dirname(путь)
        if каталог:
            os.makedirs(каталог, exist_ok=True)
        with open(путь, "a", encoding="utf-8") as ф:
            ф.write(json.dumps(запись, ensure_ascii=False) + "\n")
    except OSError as e:                                # noqa: BLE001
        print("журнал возраста не записался:", str(e)[:120], flush=True)
    return запись


