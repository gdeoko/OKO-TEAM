def ключи():
    """Все ключи Gemini, какие есть, без повторов."""
    имена = ("AMBERRY_QC_KEY", "GEMINI_KEY_FREE", "GEMINI_KEY_PAID",
             "GEMINI_MUZMIR_FREE", "GEMINI_MUZMIR_PAID")
