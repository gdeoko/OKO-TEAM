def семейство(вид):
    """Вид генерации -> семейство промпта. i2v_5 и i2v_10 отличаются
    длиной, а не словами, поэтому текст у них общий."""
    return вид.rsplit("_", 1)[0] if вид[-1].isdigit() else вид


