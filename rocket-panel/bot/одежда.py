# -*- coding: utf-8 -*-
"""Маска одежды: что именно надо снять с кадра.

## Зачем

Раздевание шло правкой всего кадра, и модель сама решала, что снять.
На крупном плане получалось, а на полном росте нет: проба 30.09.2026
сняла свитер и оставила штаны и кроссовки, а парная сцена оставила
одежду целиком и вдобавок срастила тела. Причина одна - чем больше
одежды в кадре, тем крепче её держит исходник на той глубине правки,
на которой мы работаем.

Маска снимает этот выбор с модели. Внутри маски глубина правки полная,
снаружи кадр не трогается вовсе: лицо, волосы и фон остаются свои.

## Откуда берётся

`segformer_b2_clothes` - сегментация одежды на восемнадцать классов:
верх, юбка, штаны, платье, ремень, левая туфля, правая туфля, шляпа,
сумка, шарф. Волосы, лицо, руки и ноги у неё свои классы, поэтому
причёска и лицо в маску не попадают вовсе.

Самодельный порог по цвету пробовали первым, и он провалился ровно
там, где нужнее всего: кремовый свитер в YCrCb неотличим от кожи, и
маска его не взяла. Штаны и кроссовки она брала, свитер оставляла -
то же самое, что делала модель без маски.

## Как звать

    from bot import одежда
    м = одежда.маска(кадр)            # белое - снять
    одежда.доля(м)                    # сколько кадра под одеждой
"""
import os

import cv2
import numpy as np

МОДЕЛЬ = os.environ.get("ROCKET_CLOTH_MODEL",
                        "mattmdjaga/segformer_b2_clothes")
# Классы, которые снимаем. Волосы, лицо, руки и ноги сюда не входят и
# входить не должны: причёску и лицо мы бережём отдельными проходами.
СНЯТЬ = {1: "шляпа", 4: "верх", 5: "юбка", 6: "штаны", 7: "платье",
         8: "ремень", 9: "туфля левая", 10: "туфля правая",
         16: "сумка", 17: "шарф"}
ОБУВЬ = {9, 10}

_модель = None
_приёмник = None

# Ниже этой доли маску не считаем одеждой вовсе: одиночные крапины
# кожи на светлом фоне дают россыпь точек, и правка по ним только
# портит кадр.
МИНИМУМ = float(os.environ.get("ROCKET_CLOTH_MIN", "0.01"))
# Запас вокруг найденной одежды. Край ткани всегда шире самой ткани:
# тень, складка и полтона по границе остаются, если брать впритык.
ЗАПАС = int(os.environ.get("ROCKET_CLOTH_GROW", "12"))


def _разбор(кадр):
    """Карта классов на кадр. Модель поднимается один раз на процесс."""
    global _модель, _приёмник
    import torch
    from PIL import Image
    if _модель is None:
        from transformers import (AutoModelForSemanticSegmentation,
                                  SegformerImageProcessor)
        _приёмник = SegformerImageProcessor.from_pretrained(МОДЕЛЬ)
        _модель = AutoModelForSemanticSegmentation.from_pretrained(МОДЕЛЬ)
        _модель.eval()
    рб = Image.fromarray(cv2.cvtColor(кадр, cv2.COLOR_BGR2RGB))
    с = _приёмник(images=рб, return_tensors="pt")
    with torch.no_grad():
        логиты = _модель(**с).logits
    # Обратно к размеру кадра: модель считает на своей сетке, и без
    # растяжки маска не совпадёт с кадром ни по одной границе.
    вверх = torch.nn.functional.interpolate(
        логиты, size=кадр.shape[:2], mode="bilinear", align_corners=False)
    return вверх.argmax(dim=1)[0].numpy().astype(np.uint8)


def маска(кадр, снимать_обувь=True, классы=None):
    """Белое - то, что надо снять. None, если одежды не нашлось."""
    try:
        карта = _разбор(кадр)
    except Exception:                                       # noqa: BLE001
        return None
    брать = set(классы or СНЯТЬ)
    if not снимать_обувь:
        брать -= ОБУВЬ
    одежда = np.isin(карта, list(брать)).astype(np.uint8) * 255
    # Дыры внутри ткани закрываем: пуговица, застёжка и блик уходят в
    # свои классы, и посреди штанов остаются острова, которые модель
    # оставит одеждой.
    одежда = cv2.morphologyEx(одежда, cv2.MORPH_CLOSE,
                              cv2.getStructuringElement(
                                  cv2.MORPH_ELLIPSE, (25, 25)))
    число, метки, статы, _ = cv2.connectedComponentsWithStats(одежда, 8)
    итог = np.zeros_like(одежда)
    порог = одежда.size * 0.001
    for и in range(1, число):
        if статы[и, cv2.CC_STAT_AREA] >= порог:
            итог[метки == и] = 255
    if ЗАПАС:
        итог = cv2.dilate(итог, cv2.getStructuringElement(
            cv2.MORPH_ELLIPSE, (ЗАПАС * 2 + 1, ЗАПАС * 2 + 1)))
    return итог if доля(итог) >= МИНИМУМ else None


def что_надето(кадр):
    """Что именно на человеке. Для журнала и разбора неудач."""
    try:
        карта = _разбор(кадр)
    except Exception:                                       # noqa: BLE001
        return {}
    итог = {}
    for н, имя in СНЯТЬ.items():
        д = float((карта == н).mean())
        if д > 0.002:
            итог[имя] = round(д, 4)
    return итог


def доля(м):
    """Какую часть кадра занимает маска."""
    if м is None:
        return 0.0
    return float((м > 0).mean())


def сохранить(кадр, куда):
    """Маска файлом рядом с кадром. Путь или None."""
    м = маска(кадр)
    if м is None:
        return None
    cv2.imwrite(куда, м)
    return куда


if __name__ == "__main__":
    import sys
    к = cv2.imread(sys.argv[1])
    м = маска(к)
    print("доля одежды:", round(доля(м), 4), "|", что_надето(к))
    if м is not None and len(sys.argv) > 2:
        cv2.imwrite(sys.argv[2], м)
        print("маска ->", sys.argv[2])
