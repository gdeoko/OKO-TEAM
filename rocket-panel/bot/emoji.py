def тег(эмодзи_id, запасной):
    """HTML-разметка премиум-эмодзи.

    `запасной` виден там, где премиум не показывается: у клиента без
    Premium, в уведомлении, в списке чатов. Поэтому он обязан быть
    осмысленным сам по себе — не «точка», а похожий обычный символ.
    """
    return f'<tg-emoji emoji-id="{эмодзи_id}">{запасной}</tg-emoji>'


def шапка(текст=ИМЯ):
    """Слово премиум-буквами. Шапка главного экрана.

    Запасной символ — сама буква: без Premium человек прочитает
    AMBERRY обычным текстом, и ничего не сломается.
    """
    куски = []
    for с in текст:
        if с.upper() in _БУКВЫ:
            куски.append(тег(буква(с), с.upper()))
        elif с.isdigit():
            куски.append(тег(цифра(с), с))
        else:
            куски.append(с)
    return "".join(куски)


