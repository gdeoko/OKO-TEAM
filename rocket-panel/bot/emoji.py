def _один_эмодзи(с):
    """Годится ли строка под премиум-иконку.

    Телеграм принимает под `tg-emoji` РОВНО ОДИН эмодзи. Проверено на
    живом боте 21.09.2026: буква «C» — ENTITY_TEXT_INVALID, два эмодзи
    подряд — тоже, один эмодзи — проходит. Ошибка приходит на отправку
    целиком: одна такая вставка роняет всё сообщение, а не портит
    значок.
    """
    if not с or any(ord(x) < 128 for x in с):
        return False
    # Считать по длине нельзя: «❤️» — два кодовых знака (сам символ и
    # селектор начертания), «😏😏» — тоже два. Поэтому считаем БАЗОВЫЕ
    # знаки, отбрасывая служебные: селекторы начертания, соединитель
    # нулевой ширины и модификаторы тона кожи. Их должно остаться ровно
    # столько, сколько эмодзи, — то есть один.
    СЛУЖЕБНЫЕ = {0xFE0F, 0xFE0E, 0x200D}
    базовых = sum(1 for x in с
                  if ord(x) not in СЛУЖЕБНЫЕ
                  and not 0x1F3FB <= ord(x) <= 0x1F3FF)
    # Соединитель склеивает несколько знаков в ОДИН эмодзи («семья»),
    # поэтому при нём базовых законно больше одного.
    return базовых == 1 or "‍" in с


def тег(эмодзи_id, запасной=None):
    """HTML-разметка премиум-эмодзи.

    `запасной` виден там, где премиум не показывается: у клиента без
    Premium, в уведомлении, в списке чатов. Он ОБЯЗАН быть ровно одним
    эмодзи — иначе Телеграм отобьёт всё сообщение. Не передали —
    берём тот, что закреплён за иконкой в наборе (`ЗАПАСНОЙ`).
    """
    з = запасной or ЗАПАСНОЙ.get(эмодзи_id)
    if not _один_эмодзи(з):
        raise ValueError(
            f"под премиум-иконку годится только один эмодзи, а не {з!r}. "
            f"Телеграм отобьёт всё сообщение целиком.")
    return f'<tg-emoji emoji-id="{эмодзи_id}">{з}</tg-emoji>'


def шапка(текст=ИМЯ):
    """Название в шапке главного экрана.

    ПРОСТЫМ ТЕКСТОМ, а не премиум-буквами. Раньше здесь слово
    складывалось из букв набора — и Телеграм отбивал сообщение целиком:
    под премиум-иконкой должен стоять эмодзи, а буква «A» им не
    является. Спеллинг эмодзи-буквами возможен только поверх семи
    эмодзи-заглушек, и без Premium человек увидел бы семь одинаковых
    рожиц вместо названия.

    Название бренда и так читается. Ломать ради украшения весь экран
    приветствия — плохой размен.
    """
    return текст


def баланс(сколько, яз=None):
    """Баланс коинами. Знак валюты берётся только отсюда — см. блок
    «Знак валюты» выше.

    `яз` принимается и не используется: число и значок одинаковы на
    любом языке. Параметр есть, чтобы вызывающий код не гадал, какие
    из его строк переводятся, а какие нет, — и чтобы появление
    языковой разницы (если она однажды понадобится) не потребовало
    править двадцать мест.
    """
    return f"{сколько} {тег(МОНЕТА, СИМВОЛ)}"
