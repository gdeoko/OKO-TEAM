"""Курс доллара к рублю. Живой, с памятью и запасом.

## Зачем

Цены партнёрки и безлимита владелец назвал в ДОЛЛАРАХ: 500 $ за своего
бота, 1 000 $ за безлимит на месяц. Платит же человек звёздами
телеграма, а их курс мы считаем от рубля. Значит доллар надо во что-то
переводить, и делать это цифрой в коде нельзя: она устареет молча, и
однажды мы продадим бота втрое дешевле, чем думали.

## Откуда берём

Центробанк, `www.cbr-xml-daily.ru/daily_json.js` — открытая выкладка
официального курса, без ключей и без лимитов. Это не биржевой курс: он
двигается раз в сутки, и это ровно то, что нужно прайсу. Прайс,
который дёргается вслед за биржей, невозможно ни назвать вслух, ни
напечатать в рекламе.

## Что будет, если ЦБ молчит

Ответ держится в памяти шесть часов, а на диске — сколько угодно
долго. Сеть отвалилась — берём вчерашний с диска. Диска тоже нет —
берём ЗАПАС из кода.

Запас намеренно ЗАВЫШЕН относительно текущего курса. Ошибиться в
сторону «дороже» значит недосчитаться одной продажи, о которой мы
узнаем; ошибиться в сторону «дешевле» значит продать бота за полцены
и не узнать об этом вовсе.
"""

import json
import os
import time
import urllib.request

ИСТОЧНИК = "https://www.cbr-xml-daily.ru/daily_json.js"
ФАЙЛ = os.environ.get("AMBERRY_RATE_FILE", "/srv/amberry/курс.json")
ЗАПАС = float(os.environ.get("AMBERRY_USD_RUB_FALLBACK", "105"))
ЖИВЁТ = 6 * 3600          # сколько держим ответ в памяти

_память = {"когда": 0.0, "курс": 0.0}


def _с_диска():
    try:
        with open(ФАЙЛ, encoding="utf-8") as ф:
            д = json.load(ф)
        к = float(д.get("курс") or 0)
        return к if к > 0 else 0.0
    except (OSError, ValueError, TypeError):
        return 0.0


def _на_диск(курс):
    try:
        os.makedirs(os.path.dirname(ФАЙЛ) or ".", exist_ok=True)
        врем = ФАЙЛ + ".врем"
        with open(врем, "w", encoding="utf-8") as ф:
            json.dump({"курс": курс, "когда": int(time.time())}, ф)
        os.replace(врем, ФАЙЛ)
    except OSError as e:
        print("курс не сохранился:", str(e)[:120], flush=True)


def _из_сети(таймаут=10):
    try:
        with urllib.request.urlopen(ИСТОЧНИК, timeout=таймаут) as о:
            д = json.load(о)
        к = float(д["Valute"]["USD"]["Value"])
        # Рубль за доллар вне этих границ означает не «новый курс», а
        # что мы читаем не то поле или не тот ответ. Пусть лучше
        # останется вчерашний.
        return к if 30 < к < 500 else 0.0
    except Exception as e:                              # noqa: BLE001
        print("курс не получен:", str(e)[:120], flush=True)
        return 0.0


def usd_rub(силой=False):
    """Сколько рублей в долларе. Всегда возвращает число больше нуля."""
    если_свеж = (not силой
                 and _память["курс"] > 0
                 and time.time() - _память["когда"] < ЖИВЁТ)
    if если_свеж:
        return _память["курс"]
    к = _из_сети()
    if к:
        _на_диск(к)
    else:
        к = _с_диска() or ЗАПАС
    _память.update(курс=к, когда=time.time())
    return к


def в_рублях(долларов, кратно=50):
    """Доллары -> рубли, округлённые ВВЕРХ до круглого числа.

    Вверх и кратно — потому что это ценник, а не бухгалтерия.
    «8 000 ₽» человек читает как цену, «7 847 ₽» — как ошибку или как
    попытку показаться дешевле, чем есть.
    """
    сырое = float(долларов) * usd_rub()
    if кратно <= 1:
        return int(сырое + 0.999)
    return int(-(-сырое // кратно) * кратно)
