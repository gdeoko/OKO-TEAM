"""Франшиза: свой бот клиента на нашем движке, выручка пополам.

## Что продаётся

Человек платит один раз и получает СВОЙ телеграм-бот: то же железо, те
же сборки, те же кнопки и те же принятые кадры, но под его именем, с
его аватаркой и с его каналом продвижения. Клиенты платят ему, половина
выручки остаётся ему, половина нам.

От него нужна одна вещь — токен бота из @BotFather. Всё остальное
(сервер, карта, модели, каталог, оплаты, панель) уже стоит и работает.

## Почему цена одна, а не пакет

Это не коины, и в коинах её считать нельзя: коины сгорают в
генерациях, а франшиза покупается один раз навсегда. Поэтому у неё
свой товар и свой `payload`, а зачисление на баланс НЕ делается — см.
`bot.on_paid`.

## Деньги партнёру

ВЫПЛАТЫ ДЕЛАЕТ ВЛАДЕЛЕЦ РУКАМИ. Этот код считает, сколько причитается,
и показывает список в панели; перевести он не может и не должен.
Перевод необратим, а ошибка в доле или в адресе не откатывается ничем.

## Токен

Проверяется до того, как мы возьмём на себя обязательство: `getMe`
подтверждает, что токен живой, и заодно отдаёт имя бота — его же и
показываем человеку, чтобы он видел, что мы подключили именно его
бота, а не опечатку.

Токен — ключ от чужого бота. В журнал он не пишется, наружу отдаётся
хвостом, полностью — только по отдельному запросу владельца.
"""
