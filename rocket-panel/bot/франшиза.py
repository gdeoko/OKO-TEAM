# под кнопками, чтобы карточка была одна на весь бот.
_ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КАДР = os.path.join(_ЗДЕСЬ, "..", "brand-amberry", "franchise.jpg")
ЗНАК = os.path.join(_ЗДЕСЬ, "..", "brand-amberry", "amberry-icon-256.png")
КАРТИНКА = os.path.join(
    os.environ.get("AMBERRY_DATA_DIR", "/srv/amberry"), "франшиза.jpg")


def обложка(заголовок, подзаголовок, описание):
    """Собрать обложку, если её ещё нет. Возвращает путь или пустое."""
    if os.path.exists(КАРТИНКА) and \
            os.path.getmtime(КАРТИНКА) >= os.path.getmtime(КАДР):
        return КАРТИНКА
    if not os.path.exists(КАДР):
        return ""
    import оформление
    os.makedirs(os.path.dirname(КАРТИНКА), exist_ok=True)
    return оформление.карточка(КАДР, заголовок, подзаголовок, описание,
                               КАРТИНКА,
                               ЗНАК if os.path.exists(ЗНАК) else None)


# ЦЕНА НАЗВАНА В ДОЛЛАРАХ, РУБЛИ СЧИТАЮТСЯ САМИ.
#
# Владелец поднял цену до 500 $ (25.09.2026) и попросил рубли считать
# по курсу автоматически. Раньше тут стояли две цифры разом, 100 $ и
# 8 000 ₽, и это работало ровно до первого движения курса: рублёвая
# застывала, и в какой-то день мы продавали бота вдвое дешевле
# долларовой цены, не заметив этого.
#
# Теперь истина одна — доллары. Рубли берутся из курса ЦБ и
# округляются вверх до полусотни (см. `курс.в_рублях`).
ДОЛЛАРОВ = 500
ДОЛЯ = 50                 # процент выручки, остающийся партнёру


def рублей():
    """Цена в рублях на сегодня. Считается, а не хранится."""
    import курс
    return курс.в_рублях(ДОЛЛАРОВ)

# Как выглядит токен из BotFather: «1234567890:AA...». Проверка грубая
# и нарочно: точную проверку делает сам телеграм в `getMe`, а эта
# отсекает случайно вставленное «привет» до сетевого запроса.
ТОКЕН_ВИД = re.compile(r"^\d{6,}:[A-Za-z0-9_\-]{30,}$")


def похоже_на_токен(строка):
    return bool(ТОКЕН_ВИД.match((строка or "").strip()))


def чей_бот(токен, таймаут=15):
    """(имя бота, беда). Имя — «@name», беда — строка или пустое.

    Отдельной функцией, чтобы бот не лез в сеть внутри обработчика
    сообщений и чтобы это можно было подменить в тесте.
    """
    if not похоже_на_токен(токен):
        return "", "это не похоже на токен из @BotFather"
    адрес = f"https://api.telegram.org/bot{токен.strip()}/getMe"
    try:
        with urllib.request.urlopen(адрес, timeout=таймаут) as о:
            д = json.loads(о.read())
    except urllib.error.HTTPError as e:
        if e.code == 401:
            return "", "телеграм не принял этот токен"
        return "", f"телеграм ответил {e.code}"
    except Exception as e:                              # noqa: BLE001
        return "", f"не дозвонились до телеграма: {str(e)[:80]}"
    if not д.get("ok"):
        return "", "телеграм не принял этот токен"
    имя = (д.get("result") or {}).get("username")
    return ("@" + имя) if имя else "", ""


def спрятать(токен):
    """Токен для показа: хвост и ничего больше."""
    т = (токен or "").strip()
    return ("…" + т[-6:]) if т else ""
