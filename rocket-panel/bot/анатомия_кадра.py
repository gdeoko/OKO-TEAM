"""Пропавшие руки и дубли частей тела: то, что приёмка пропускала.

Пересмотр двадцати готовых кадров глазами нашёл два дефекта, которых
счёт «не больше нормы» не видит по устройству.

ПРОПАВШИЕ РУКИ. На `ff_face` у обеих женщин нет рук вовсе, на
`un_three` нет левой, на `un_close` правой. Прежняя проверка ругалась
только на ЛИШНЕЕ запястье: третья рука при двух людях это брак. А ноль
рук при одном человеке она считала нормой, хотя владелец назвал
«отсутствие или много рук» одной бедой.

ДУБЛИ НИЗА. На `un_back` под стоящей фигурой нарисован второй таз с
ногами, на `un_sit` под её бёдрами ещё один лобок. Скелет при этом
один, тел «одно», запястий ровно два - по всем числам кадр чистый.
Ловится иначе: маска человека сравнивается с рамками найденных
скелетов. Пиксели тела, которые не принадлежат ни одному скелету, и
есть дубль; порог взят с запасом, потому что рамка скелета обрезает
волосы и ступни даже на верном кадре.
"""
import os

import cv2
import numpy as np

# Руки не видно по постановке: кадр сзади, сверху или снизу, где они
# за телом. Список поимённый, потому что «не вижу рук» и «рук нет» это
# разные вещи, и путать их значит браковать верные кадры.
БЕЗ_РУК = ("ph_above", "ff_face", "un_back")
ЗАПАС_РАМКИ = float(os.environ.get("OKO_ANAT_ZAPAS", "0.12"))
ПОРОГ_ЧУЖОГО = float(os.environ.get("OKO_ANAT_CHUZHOE", "0.18"))


def _рамки(скелеты, кадр):
    """Рамки скелетов с запасом: рамка режет волосы и ступни."""
    в, ш = кадр.shape[:2]
    из = []
    for т in скелеты:
        точки = [(x, y) for x, y, c in т if c > 0.4]
        if len(точки) < 4:
            continue
        xs = [x for x, _ in точки]
        ys = [y for _, y in точки]
        дш, дв = (max(xs) - min(xs)) * ЗАПАС_РАМКИ, (max(ys) - min(ys)) * ЗАПАС_РАМКИ
        из.append((max(0, int(min(xs) - дш)), max(0, int(min(ys) - дв)),
                   min(ш, int(max(xs) + дш)), min(в, int(max(ys) + дв))))
    return из


def чужое_тело(кадр, скелеты, маска_человека):
    """Доля тела, не принадлежащая ни одному скелету."""
    if маска_человека is None or not скелеты:
        return 0.0
    м = маска_человека.astype(np.uint8)
    if м.shape[:2] != кадр.shape[:2]:
        м = cv2.resize(м, (кадр.shape[1], кадр.shape[0]),
                       interpolation=cv2.INTER_NEAREST)
    своё = np.zeros_like(м)
    for x1, y1, x2, y2 in _рамки(скелеты, кадр):
        своё[y1:y2, x1:x2] = 1
    всего = float(м.sum())
    if всего < 500:
        return 0.0
    return float((м & (1 - своё)).sum()) / всего


def беды(кадр, ключ, скелеты, числа, маска_человека=None):
    """Дефекты, которых не видно по одному счёту конечностей."""
    из = []
    надо_рук = 0 if ключ in БЕЗ_РУК else (2 if len(скелеты) > 1 else 1)
    if числа.get("запястий", 0) < надо_рук:
        из.append("рук в кадре %d, надо хотя бы %d"
                  % (числа.get("запястий", 0), надо_рук))
    доля = чужое_тело(кадр, скелеты, маска_человека)
    if доля > ПОРОГ_ЧУЖОГО:
        из.append("тело без скелета на %.0f%% кадра (дубль)" % (доля * 100))
    return из
