# Руки не видно по постановке: кадр сзади, сверху или снизу, где они
# за телом. Список поимённый, потому что «не вижу рук» и «рук нет» это
# разные вещи, и путать их значит браковать верные кадры.
БЕЗ_РУК = ("ph_above", "ff_face", "un_back")


def беды(кадр, ключ, скелеты, числа):
    """Руки, которых в кадре нет."""
    надо = 0 if ключ in БЕЗ_РУК else (2 if len(скелеты) > 1 else 1)
    есть = числа.get("запястий", 0)
    if есть < надо:
        return ["рук в кадре %d, надо хотя бы %d" % (есть, надо)]
    return []
