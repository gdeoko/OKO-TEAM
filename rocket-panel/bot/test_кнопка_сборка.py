class Карта(unittest.TestCase):
    def test_каждая_кнопка_каталога_в_карте_сборки(self):
        """Кнопка не из карты считается сборкой по умолчанию, и это не
        беда, а слепое пятно: у неё никто не мерил ни анатомию, ни позу."""
        нет = [к for к in К.КОМНАТЫ if к not in С.СБОРКА]
        self.assertEqual(нет, [], "кнопки без своей сборки: %s" % нет)

    def test_модели_карты_существуют(self):
        for кнопка, (модель, вес) in С.СБОРКА.items():
            self.assertIn(модель, С.МОДЕЛИ, кнопка)
            self.assertTrue(0.0 <= вес <= 1.0, "%s: вес %s" % (кнопка, вес))

    def test_у_каждой_кнопки_есть_принятый_кадр(self):
        """Двадцать кадров, отобранных владельцем, нашлись 03.10.2026 и
        лежат в `эталоны/`. Кнопка без кадра лишается и листа, и позы:
        лист падает в умолчание, а приёмка меряет силуэт по карте, то
        есть по снимку снимка."""
        нет = [к for к in С.СБОРКА if С.эталон(к) is None]
        self.assertEqual(нет, [], "кнопки без принятого кадра: %s" % нет)

    def test_лист_кнопки_из_принятого_кадра(self):
        """Лист называет сам кадр, а не таблица. Шесть кадров из
        двадцати владелец принял горизонтальными, а бот просил вертикаль
        у всех: поза, снятая поперёк листа, в вертикальный кадр не
        влезает, и сборка её перестраивает."""
        for кнопка in С.СБОРКА:
            э = С.эталон(кнопка)
            ш, в = С.размер(кнопка)
            гориз_кадра = э.shape[1] > э.shape[0]
            self.assertEqual(ш > в, гориз_кадра, кнопка)

    def test_лист_согласован_с_каталогом(self):
        """Сборка и каталог обязаны просить один лист: ролик начинается
        с фотографии, и разойтись им негде."""
        for кнопка in С.СБОРКА:
            из_каталога = catalog.лист_эталона(кнопка)
            self.assertEqual(из_каталога,
                             "horiz" if С.лист(кнопка) == "гориз" else "vert",
                             кнопка)

    def test_карта_глубины_под_кадр(self):
        """Карта обязана прийти ровно того размера, что и кадр: иначе
        ControlNet получит сплющенную позу."""
        for кнопка in С.СБОРКА:
            ш, в = С.размер(кнопка)
            г = С.карта_глубины(кнопка, ш, в)
            self.assertIsNotNone(г, кнопка)
            self.assertEqual((г.shape[1], г.shape[0]), (ш, в), кнопка)

    def test_кадр_ровно_как_принятый(self):
        """Кадр кнопки совпадает с принятым кадром пиксель в пиксель,
        и значит карту глубины не надо ни растягивать, ни поджимать.

        Прежде кнопки шли в 3:2 против 7:4 у кадров: позу жало на
        семнадцать процентов даже там, где лист угадан, а на парных
        кнопках карту растягивало вдвое, и от этого срастались тела."""
        for кнопка in С.СБОРКА:
            э = С.эталон(кнопка)
            self.assertEqual(С.размер(кнопка), (э.shape[1], э.shape[0]),
                             кнопка)

    def test_стороны_кадра_кратны_64(self):
        """Сеть берёт только кратное 64, иначе кадр молча округлят и
        карта разойдётся с кадром на десяток пикселей."""
        for кнопка in С.СБОРКА:
            ш, в = С.размер(кнопка)
            self.assertEqual((ш % 64, в % 64), (0, 0), "%s: %dx%d"
                             % (кнопка, ш, в))

    def test_чужой_лист_вписывается_полями(self):
        """У кнопки без принятого кадра карта может оказаться в чужом
        листе. Тогда её вписывают с чёрными полями, а не растягивают."""
        г = С.карта_глубины("un_close", 1216, 832)   # кадр вертикальный
        сер = cv2.cvtColor(г, cv2.COLOR_BGR2GRAY)
        self.assertLess(float(сер[:, :40].mean()), 8.0)


class Роли(unittest.TestCase):
    """Кто на парном кадре клиентка, а кто наша модель."""

    def _лицо(self, x, пол="F", ш=100):
        return {"bbox": [x, 100.0, x + ш, 100.0 + ш], "пол": пол}

    def test_мж_различает_по_полу(self):
        кадр = np.zeros((600, 800, 3), np.uint8)
        р = Р.кто_где(кадр, "mf_behind",
                      [self._лицо(500, "M"), self._лицо(100, "F")])
        self.assertEqual(р["кто"], "марк")
        self.assertEqual(р["клиентка"]["пол"], "F")
        self.assertEqual(р["партнёр"]["пол"], "M")

    def test_жж_берёт_ту_что_светлее(self):
        """Во всех эталонах ЖЖ клиентка это «THE BLONDE», а партнёрша
        «THE DARK-HAIRED ONE»."""
        кадр = np.zeros((600, 800, 3), np.uint8)
        кадр[40:100, 80:220] = 230          # светлые волосы слева
        кадр[40:100, 480:620] = 20          # тёмные справа
        р = Р.кто_где(кадр, "ff_close",
                      [self._лицо(500), self._лицо(100)])
        self.assertEqual(р["кто"], "юлия")
        self.assertEqual(р["клиентка"]["bbox"][0], 100.0)

    def test_одно_лицо_ролей_не_даёт(self):
        self.assertIsNone(Р.кто_где(np.zeros((10, 10, 3), np.uint8),
                                    "mf_behind", [self._лицо(10)]))

    def test_соло_кнопка_ролей_не_даёт(self):
        self.assertIsNone(Р.кто_где(np.zeros((10, 10, 3), np.uint8),
                                    "un_close",
                                    [self._лицо(10), self._лицо(200)]))


class Сшивка(unittest.TestCase):
    def test_вне_маски_кадр_не_меняется(self):
        """Голова берётся с другого кадра, всё остальное обязано
        остаться пиксель в пиксель: иначе поедут анатомия и комната."""
        основа = np.full((300, 240, 3), 90, np.uint8)
        основа[:, :, 1] = 140
        новый = np.full((300, 240, 3), 200, np.uint8)
        маска = np.zeros((300, 240), np.uint8)
        cv2.circle(маска, (120, 90), 40, 255, -1)
        готово = сшивка_лица.встроить(основа, новый, маска, зерно=False)
        далеко = (slice(220, 300), slice(0, 240))
        self.assertTrue(np.array_equal(готово[далеко], основа[далеко]))

    def test_пустая_маска_отдаёт_основу(self):
        основа = np.full((80, 60, 3), 10, np.uint8)
        новый = np.full((80, 60, 3), 240, np.uint8)
        готово = сшивка_лица.встроить(основа, новый,
                                      np.zeros((80, 60), np.uint8))
        self.assertTrue(np.array_equal(готово, основа))


class Приёмка(unittest.TestCase):
    """Что именно приёмка считает браком.

    Сам детектор здесь не зовётся: он грузит двести мегабайт весов, а
    проверять надо не его, а наши правила поверх него.
    """

    def setUp(self):
        import люди_в_кадре
        self.м = люди_в_кадре
        self.было = люди_в_кадре.разбор

    def tearDown(self):
        self.м.разбор = self.было

    def _ответ(self, **кв):
        числа = {"тел": 1, "запястий": 2, "щиколоток": 2, "голов": 1,
                 "срезано_голов": 0}
        числа.update(кв)
        self.м.разбор = lambda кадр: числа

    def test_чистый_кадр_проходит(self):
        self._ответ()
        беды, _ = self.м.беды(None, 1)
        self.assertEqual(беды, [])

    def test_лишний_человек_это_брак(self):
        """Самый частый брак парной кнопки: в кадре трое вместо двоих."""
        self._ответ(тел=3, запястий=4, щиколоток=4, голов=3)
        беды, _ = self.м.беды(None, 2)
        self.assertTrue(any("людей в кадре 3" in б for б in беды))

    def test_пропавший_человек_это_брак(self):
        self._ответ(тел=1, голов=1)
        беды, _ = self.м.беды(None, 2)
        self.assertTrue(any("людей в кадре 1" in б for б in беды))

    def test_третье_запястье_это_лишняя_рука(self):
        """Сколько бы тел ни соприкасалось, запястий не бывает больше
        двух на человека."""
        self._ответ(запястий=3)
        беды, _ = self.м.беды(None, 1)
        self.assertTrue(any("запястий 3" in б for б in беды))

    def test_срезанная_голова_это_брак(self):
        self._ответ(срезано_голов=1)
        беды, _ = self.м.беды(None, 1)
        self.assertTrue(any("срезано" in б for б in беды))

    def test_четыре_запястья_у_двоих_это_норма(self):
        self._ответ(тел=2, запястий=4, щиколоток=4, голов=2)
        беды, _ = self.м.беды(None, 2)
        self.assertEqual(беды, [])


if __name__ == "__main__":
    unittest.main(verbosity=1)
