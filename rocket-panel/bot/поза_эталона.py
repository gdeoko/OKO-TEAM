# -*- coding: utf-8 -*-
"""Насколько поза кадра совпала с позой эталона кнопки.

Приёмка по телам и конечностям ловит сросшиеся тела и лишние руки, но
про постановку не знает ничего: кадр с двумя целыми людьми в СОВСЕМ
другой позе она пропускает как годный. Именно это и выходило на слабом
гайде - анатомия чистая, а кнопка показывает не то, что обещала.

Силуэт эталона брать неоткуда: самих эталонных кадров в репозитории
нет. Зато есть карты глубины, снятые с них: фон на карте чёрный, а
человек светлый, значит бинаризованная карта и ЕСТЬ силуэт эталона.
Порог берётся по Оцу, а не числом: у каждой карты своя яркость, и
общий порог срезал бы на одних картах человека, на других оставлял фон.

ОБЕ МАСКИ ВПИСЫВАЮТСЯ В КВАДРАТ, А НЕ РАСТЯГИВАЮТСЯ. Прежняя сверка
приводила кадр к 208x304, и горизонтальный кадр сплющивался вдвое:
силуэт переставал совпадать с эталоном даже при верной позе, и мера
врала ровно на тех пяти парных кнопках, которые каталог генерит
горизонтально.
"""
import os

import cv2
import konveyer as К
import numpy as np
import priyomka_kadra as ПК

СТОРОНА = 256
_эт = {}


def _в_квадрат(маска):
    """Вписать маску в квадрат по длинной стороне, добить пустым."""
    м = маска.astype(np.uint8)
    в, ш = м.shape[:2]
    к = СТОРОНА / float(max(в, ш))
    м = cv2.resize(м, (max(1, int(ш * к)), max(1, int(в * к))),
                   interpolation=cv2.INTER_NEAREST)
    поле = np.zeros((СТОРОНА, СТОРОНА), np.uint8)
    y, x = (СТОРОНА - м.shape[0]) // 2, (СТОРОНА - м.shape[1]) // 2
    поле[y:y + м.shape[0], x:x + м.shape[1]] = м
    return поле > 0


def силуэт_эталона(ключ):
    к = К.короткий(ключ)
    if к not in _эт:
        г = cv2.imread(os.path.join(К.ГАЙДЫ, к + ".jpg"), cv2.IMREAD_GRAYSCALE)
        if г is None:
            _эт[к] = None
        else:
            _, б = cv2.threshold(г, 0, 255,
                                 cv2.THRESH_BINARY + cv2.THRESH_OTSU)
            _эт[к] = _в_квадрат(б)
    return _эт[к]


def совпадение(кадр, ключ):
    """Доля общего силуэта кадра и эталона. 1.0 - тот же силуэт."""
    э = силуэт_эталона(ключ)
    if э is None:
        return None
    с = ПК.силуэт(кадр)
    if с is None:
        return None
    # `силуэт` уже привёл кадр к своему размеру, поэтому пропорции
    # восстанавливаем по исходному кадру, а не по его маске.
    в, ш = кадр.shape[:2]
    с = cv2.resize(с.astype(np.uint8), (ш, в),
                   interpolation=cv2.INTER_NEAREST)
    с = _в_квадрат(с)
    return float((с & э).sum()) / (float((с | э).sum()) or 1.0)
