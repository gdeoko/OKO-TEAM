"""Карточка кнопки для бота: кадр + знак AMBERRY + название и описание.

Это то, что клиент видит ДО оплаты, под каждой кнопкой генерации. Кадр
здесь — обещание: «нажмёшь — получишь такое». Поэтому берётся не
случайная генерация, а ТОТ САМЫЙ кадр, который владелец принял, и
который бот теперь воспроизводит жёсткой постановкой.

## Что на карточке

    ┌─────────────────────────┐
    │                         │
    │        КАДР             │   без надписей, чистый
    │                         │
    │╌╌╌╌╌╌╌ затемнение ╌╌╌╌╌╌│
    │ ● AMBERRY               │   знак бренда, мелко
    │ СЕКС РАКОМ              │   заголовок, крупно
    │ Пара МЖ · фото          │   подзаголовок
    │ Он сзади, оба без       │   описание в две строки
    │ одежды, лица видно      │
    └─────────────────────────┘

## Правила бренда, которые здесь соблюдены

* Знак берётся ФАЙЛОМ из `brand-amberry`, не рисуется заново.
* Цвета только свои: чёрный фон, неон #FF0A8C, белый текст.
* Никаких эмодзи — только знак и текст.
* Кадр не растягивается: обрезается по центру под 4:5.

Размер 1080×1350 — вертикаль 4:5. В телеграме такая картинка занимает
почти весь экран телефона, а горизонтальная — полоску в треть.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ШИР, ВЫС = 1080, 1350
НЕОН = (255, 10, 140)
БЕЛЫЙ = (255, 255, 255)
СЕРЫЙ = (168, 165, 175)
ЧЁРНЫЙ = (0, 0, 0)

ШРИФТЫ = "/home/ubuntu/шрифты"


def шрифт(имя, размер):
    п = os.path.join(ШРИФТЫ, имя)
    if os.path.exists(п):
        return ImageFont.truetype(п, размер)
    зап = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
    return ImageFont.truetype(зап, размер)


def кадр_целиком(путь, ширина, высота):
    """Кадр ВПИСЫВАЕТСЯ целиком, а не обрезается.

    Первая версия резала под 4:5 — и у горизонтальных кадров («Раком»,
    «Кунилингус») срезало голову. А кадр на карточке это обещание
    клиенту: «нажмёшь — получишь такое». Резать обещание нельзя.
    """
    и = Image.open(путь).convert("RGB")
    к = min(ширина / и.width, высота / и.height)
    return и.resize((int(и.width * к), int(и.height * к)), Image.LANCZOS)


def перенос(текст, ф, ширина, рисовалка):
    слова, строки, текущая = текст.split(), [], ""
    for с in слова:
        проба = (текущая + " " + с).strip()
        if рисовалка.textlength(проба, font=ф) <= ширина:
            текущая = проба
        else:
            if текущая:
                строки.append(текущая)
            текущая = с
    if текущая:
        строки.append(текущая)
    return строки


def карточка(кадр_путь, заголовок, подзаголовок, описание, выход,
             знак_путь=None):
    """Кадр сверху, текст снизу на чёрном. Текст НЕ лежит на коже:
    на светлом теле серые буквы исчезают — проверено на первой версии."""
    лист = Image.new("RGB", (ШИР, ВЫС), ЧЁРНЫЙ)
    д = ImageDraw.Draw(лист)
    поле = 60

    # Сколько отдать тексту. Заголовок в одну-две строки плюс
    # подзаголовок плюс две строки описания — это примерно 360 точек.
    ф_заг = шрифт("Unbounded-Bold.ttf", 78)
    ф_под = шрифт("Montserrat-Medium.ttf", 32)
    ф_оп = шрифт("Montserrat-Medium.ttf", 33)
    строк_заг = len(перенос(заголовок.upper(), ф_заг, ШИР - поле * 2, д))
    строк_оп = len(перенос(описание, ф_оп, ШИР - поле * 2, д)[:2])
    низ = 40 + строк_заг * 92 + 52 + строк_оп * 46 + 44

    # Кадр ставится по ЦЕНТРУ отведённой ему области, а не под верхний
    # край: у горизонтального кадра иначе остаётся чёрная яма между ним
    # и текстом в треть карточки.
    к = кадр_целиком(кадр_путь, ШИР, ВЫС - низ)
    лист.paste(к, ((ШИР - к.width) // 2, (ВЫС - низ - к.height) // 2))

    # ЗНАК БРЕНДА поверх кадра, слева сверху.
    if знак_путь and os.path.exists(знак_путь):
        з = Image.open(знак_путь).convert("RGBA")
        в = 78
        з = з.resize((int(з.width * в / з.height), в), Image.LANCZOS)
        лист.paste(з, (поле, 44), з)
        д.text((поле + з.width + 18, 60), "AMBERRY",
               font=шрифт("Unbounded-Bold.ttf", 38), fill=БЕЛЫЙ)
    else:
        д.text((поле, 50), "AMBERRY",
               font=шрифт("Unbounded-Bold.ttf", 44), fill=НЕОН)

    # Тонкая неоновая черта между кадром и текстом — граница, а не рамка.
    y = ВЫС - низ
    д.line([(0, y), (ШИР, y)], fill=НЕОН, width=3)

    y += 40
    for строка in перенос(заголовок.upper(), ф_заг, ШИР - поле * 2, д):
        д.text((поле, y), строка, font=ф_заг, fill=БЕЛЫЙ)
        y += 92
    y += 6
    д.text((поле, y), подзаголовок.upper(), font=ф_под, fill=НЕОН)
    y += 46
    for строка in перенос(описание, ф_оп, ШИР - поле * 2, д)[:2]:
        д.text((поле, y), строка, font=ф_оп, fill=СЕРЫЙ)
        y += 46

    лист.save(выход, "JPEG", quality=92)
    return выход


if __name__ == "__main__":
    import json
    задания = json.load(open(sys.argv[1], encoding="utf-8"))
    for з in задания:
        карточка(з["кадр"], з["заголовок"], з["подзаголовок"],
                 з["описание"], з["выход"], з.get("знак"))
        print("готово", з["выход"], flush=True)
