"""Карточка кнопки для бота: принятый кадр + надписи ПОВЕРХ него.

Это то, что клиент видит ДО оплаты, под каждой кнопкой генерации. Кадр
здесь — обещание: «нажмёшь — получишь такое». Поэтому берётся не
случайная генерация, а ТОТ САМЫЙ кадр, который владелец принял, и
который бот теперь воспроизводит жёсткой постановкой.

## Правило владельца от 23.09.2026 (постоянное)

    «Не добавляй лишних полей никаких, не меняй размер, как есть
    поверх карточки красиво добавить текст в стиле логотип и бренда.
    Чтобы красиво было без обрезаний, изменений размеров, чёрных
    полей и тд.»

Поэтому здесь НЕТ ни одной из трёх вещей, которые были в первой версии:

* нет обрезки под 4:5 — у горизонтальных кнопок («Раком», «Кунилингус»)
  она срезала голову, то есть резала само обещание;
* нет масштабирования — кадр сохраняется точка в точку, как вышел из
  генерации (1344×768 или 768×1344);
* нет чёрной подложки снизу — надписи легли бы на пустоту, а вертикаль
  4:5 из горизонтального кадра давала треть карточки чёрного.

Размер карточки РАВЕН размеру кадра. Надписи лежат на самом кадре.

## Как надписи остаются читаемыми на голой коже

Буквы поверх фотографии исчезают: на светлом теле серый текст не виден,
на тёмной простыне белый сливается с тенью. Решение — не рамка и не
плашка (это и есть «лишнее поле»), а ЗАТЕМНЕНИЕ-ГРАДИЕНТ: снизу вверх
от почти чёрного к полностью прозрачному. Кадр сквозь него виден, буквы
читаются, границы у затемнения нет — она бы читалась как та же плашка.

Сверху такое же затемнение, но короткое и слабое: только чтобы держать
знак бренда.

    ┌─────────────────────────────┐
    │ ● AMBERRY      ← слабое затемнение
    │                             │
    │          К А Д Р            │  целиком, без обрезки
    │                             │
    │  СЕКС РАКОМ         ← сильное затемнение снизу
    │  ПАРА МЖ · ФОТО             │
    │  Он сзади, оба без одежды   │
    └─────────────────────────────┘

## Правила бренда, которые здесь соблюдены

* Знак берётся ФАЙЛОМ (`amberry-icon.png`), не рисуется заново.
* Цвета только свои: неон #FF0A8C, белый, серый.
* Никаких эмодзи — только знак и текст.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

НЕОН = (255, 10, 140)
БЕЛЫЙ = (255, 255, 255)
СЕРЫЙ = (208, 205, 214)

ШРИФТЫ = os.environ.get("AMBERRY_ШРИФТЫ", "/home/ubuntu/шрифты")

# Доли от высоты кадра. Вертикальный кадр выше горизонтального в 1.75
# раза, и если задать размеры в точках, на вертикали надписи окажутся
# мелкими, а на горизонтали — во весь лист. Доли держат один вид.
ДОЛЯ_ЗАГОЛОВКА = 0.062
ДОЛЯ_ПОДЗАГОЛОВКА = 0.026
ДОЛЯ_ОПИСАНИЯ = 0.027
ДОЛЯ_ПОЛЯ = 0.045
ДОЛЯ_ЗНАКА = 0.055


def шрифт(имя, размер):
    п = os.path.join(ШРИФТЫ, имя)
    if os.path.exists(п):
        return ImageFont.truetype(п, размер)
    зап = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
    return ImageFont.truetype(зап, размер)


def перенос(текст, ф, ширина, рисовалка):
    слова, строки, текущая = текст.split(), [], ""
    for с in слова:
        проба = (текущая + " " + с).strip()
        if рисовалка.textlength(проба, font=ф) <= ширина:
            текущая = проба
        else:
            if текущая:
                строки.append(текущая)
            текущая = с
    if текущая:
        строки.append(текущая)
    return строки


def _затемнение(ширина, высота, сверху, докуда, сила):
    """Полоса «прозрачное → чёрное» высотой `высота`.

    `сверху=False` — тёмное внизу (под надписи), `сверху=True` — тёмное
    вверху (под знак). `сила` — до какой непрозрачности доходит чёрный,
    0..255. Переход не линейный, а в квадрате: у линейного видно, где
    полоса кончается, и это читается как край плашки.
    """
    слой = Image.new("L", (1, высота), 0)
    for y in range(высота):
        доля = (высота - y) / высота if сверху else y / высота
        слой.putpixel((0, y), int(сила * доля * доля))
    слой = слой.resize((ширина, высота))
    чёрный = Image.new("RGBA", (ширина, высота), (0, 0, 0, 255))
    чёрный.putalpha(слой)
    return чёрный


def карточка(кадр_путь, заголовок, подзаголовок, описание, выход,
             знак_путь=None):
    """Кадр как есть, надписи поверх. Возвращает путь к готовому файлу."""
    лист = Image.open(кадр_путь).convert("RGBA")
    Ш, В = лист.size
    поле = int(В * ДОЛЯ_ПОЛЯ)
    д = ImageDraw.Draw(лист)

    ф_заг = шрифт("Unbounded-Bold.ttf", int(В * ДОЛЯ_ЗАГОЛОВКА))
    ф_под = шрифт("Montserrat-Medium.ttf", int(В * ДОЛЯ_ПОДЗАГОЛОВКА))
    ф_оп = шрифт("Montserrat-Medium.ttf", int(В * ДОЛЯ_ОПИСАНИЯ))

    # Ширина текстового столбца — 78% листа. Во всю ширину надпись
    # упирается в противоположный край и выглядит как вёрстка газеты,
    # а не как подпись к кадру.
    столбец = int(Ш * 0.78)
    строки_заг = перенос(заголовок.upper(), ф_заг, столбец, д)
    строки_оп = перенос(описание, ф_оп, столбец, д)[:2]

    шаг_заг = int(В * ДОЛЯ_ЗАГОЛОВКА * 1.22)
    шаг_оп = int(В * ДОЛЯ_ОПИСАНИЯ * 1.45)
    блок = (len(строки_заг) * шаг_заг + int(В * 0.012)
            + int(В * ДОЛЯ_ПОДЗАГОЛОВКА * 1.6)
            + len(строки_оп) * шаг_оп)

    # Затемнение выше текста ровно вдвое: буквам нужен разгон, иначе
    # верхняя строка заголовка стоит на светлой коже.
    тень_низ = min(В, блок + поле * 2 + int(В * 0.10))
    лист.alpha_composite(_затемнение(Ш, тень_низ, False, 232),
                         (0, В - тень_низ))
    тень_верх = int(В * 0.20)
    лист.alpha_composite(_затемнение(Ш, тень_верх, True, 150), (0, 0))

    д = ImageDraw.Draw(лист)

    # ЗНАК БРЕНДА в левом верхнем углу.
    высота_знака = int(В * ДОЛЯ_ЗНАКА)
    сдвиг = поле
    if знак_путь and os.path.exists(знак_путь):
        з = Image.open(знак_путь).convert("RGBA")
        з = з.resize((max(1, int(з.width * высота_знака / з.height)),
                      высота_знака), Image.LANCZOS)
        лист.alpha_composite(з, (поле, поле))
        сдвиг = поле + з.width + int(В * 0.016)
    ф_знак = шрифт("Unbounded-Bold.ttf", int(высота_знака * 0.52))
    д.text((сдвиг, поле + высота_знака * 0.26), "AMBERRY",
           font=ф_знак, fill=БЕЛЫЙ)

    # НАДПИСИ снизу вверх: описание, подзаголовок, заголовок. Считаем от
    # нижнего края, чтобы нижняя строка всегда стояла на одном месте, как
    # бы ни разрослась верхняя.
    y = В - поле - len(строки_оп) * шаг_оп
    для_описания = y
    for строка in строки_оп:
        д.text((поле, y), строка, font=ф_оп, fill=СЕРЫЙ)
        y += шаг_оп

    y = для_описания - int(В * ДОЛЯ_ПОДЗАГОЛОВКА * 1.6)
    д.text((поле, y), подзаголовок.upper(), font=ф_под, fill=НЕОН)

    y -= int(В * 0.012)
    for строка in reversed(строки_заг):
        y -= шаг_заг
        д.text((поле, y), строка, font=ф_заг, fill=БЕЛЫЙ)

    лист.convert("RGB").save(выход, "JPEG", quality=94)
    return выход


if __name__ == "__main__":
    import json
    задания = json.load(open(sys.argv[1], encoding="utf-8"))
    for з in задания:
        карточка(з["кадр"], з["заголовок"], з["подзаголовок"],
                 з["описание"], з["выход"], з.get("знак"))
        print("готово", з["выход"], flush=True)
