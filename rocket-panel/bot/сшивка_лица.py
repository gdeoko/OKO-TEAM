# -*- coding: utf-8 -*-
"""Встраивание головы в кадр без видимого края.

Жалоба владельца: «лицо выглядит как вклеенное», «видно везде что лицо
прорисовано». Причина не в лице, а в СТЫКЕ: голова берётся с другого
кадра, где свет, цвет и зерно свои, и кладётся в эллипс. Внутри эллипса
одна картинка, снаружи другая, граница читается с первого взгляда.

Сетевые пути это не лечат. PuLID ставит личность внутри генерации и шва
не делает вовсе, но он несовместим с ControlNet, и поза уходит с 0.96
до 0.45 - владелец требует позу эталона, значит путь закрыт. Доводка
всего кадра img2img шов убирает, но вместе с ним и личность: 0.82 падает
до 0.55 даже на силе 0.08. FLUX Fill референс лица не слушает вовсе и
рисует постороннего человека (узнаваемость около нуля).

Поэтому стык лечится в коде, тремя приёмами разом:

  Пуассон     `seamlessClone` переносит не пиксели, а ГРАДИЕНТ: внутрь
              кадра встраивается рельеф лица, а освещение и тон берутся
              от кожи вокруг. Край исчезает без размывания черт.
  зерно       шум у двух кадров свой. Зерно основы замеряется кольцом
              вокруг головы и добавляется на вставку, иначе лицо
              выходит глаже тела и читается как ретушь.
  резкость    выравнивание детализации проверено и ВЫКЛЮЧЕНО по
              умолчанию: оно размывало всю голову, и кадр выглядел
              хуже исходного. Пуассона против стыка хватает одного.
"""
import cv2
import numpy as np


def _кольцо(маска, толщина=24):
    """Полоса кожи вокруг головы: по ней меряются зерно и резкость."""
    я = cv2.dilate(маска, np.ones((толщина, толщина), np.uint8))
    return cv2.subtract(я, маска)


def _шум(кадр, где):
    """Сила зерна: разброс того, что осталось после размытия."""
    сер = cv2.cvtColor(кадр, cv2.COLOR_BGR2GRAY).astype(np.float32)
    остаток = сер - cv2.GaussianBlur(сер, (0, 0), 1.6)
    точки = остаток[где > 0]
    return float(точки.std()) if точки.size > 40 else 0.0


def _резкость(кадр, где):
    сер = cv2.cvtColor(кадр, cv2.COLOR_BGR2GRAY)
    л = cv2.Laplacian(сер, cv2.CV_32F)
    точки = l if False else л[где > 0]
    return float(точки.var()) if точки.size > 40 else 0.0


def встроить(основа, новый, маска, зерно=True, резкость=False):
    """Голова с `новый` в кадр `основа` по маске, без видимого стыка."""
    if новый.shape[:2] != основа.shape[:2]:
        новый = cv2.resize(новый, (основа.shape[1], основа.shape[0]))
    м = маска if маска.ndim == 2 else cv2.cvtColor(маска, cv2.COLOR_BGR2GRAY)
    м = (м > 127).astype(np.uint8) * 255
    я, х, ш, в = cv2.boundingRect(м)
    if ш < 8 or в < 8:
        return основа
    центр = (я + ш // 2, х + в // 2)
    кольцо = _кольцо(м)
    гот = новый.copy()
    if резкость:
        # Лицо из второго прохода резче кадра: лишнюю детализацию
        # снимаем до встраивания, иначе она и выдаёт вставку.
        р_о, р_н = _резкость(основа, кольцо), _резкость(новый, м)
        if р_н > р_о * 1.25 and р_о > 0:
            сила = min(1.6, (р_н / max(р_о, 1e-6)) ** 0.5 * 0.5)
            гот = cv2.GaussianBlur(гот, (0, 0), сила)
    if зерно:
        ш_о, ш_н = _шум(основа, кольцо), _шум(гот, м)
        if ш_о > ш_н + 0.4:
            добавка = np.random.normal(0, (ш_о ** 2 - ш_н ** 2) ** 0.5,
                                       гот.shape).astype(np.float32)
            гот = np.clip(гот.astype(np.float32) + добавка, 0, 255).astype(np.uint8)
    try:
        return cv2.seamlessClone(гот, основа, м, центр, cv2.NORMAL_CLONE)
    except cv2.error:
        # Маска у самого края кадра Пуассону не даётся: отступаем на
        # мягкую альфу, она хуже, но кадр не теряется.
        а = (cv2.GaussianBlur(м, (41, 41), 0).astype(np.float32) / 255.0)[..., None]
        return (гот * а + основа * (1 - а)).astype(np.uint8)
