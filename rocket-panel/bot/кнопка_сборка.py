# -*- coding: utf-8 -*-
"""Кнопка целиком: основа, приёмка, лица по ролям, сборка без шва.

Собрано по итогам прогона семисот с лишним кадров на четырёх площадках.
Каждое решение здесь стоит замера, а не вкуса.

ПОЧЕМУ НЕ SDXL. LUSTIFY (SDXL, 2023) на парных позах путал тела: лишняя
пара ног, срезанная голова партнёра, руки, не принадлежащие никому. Это
ровно те дефекты, которые владелец возвращал. Flux держит стыки тел, и
на тех же кнопках и промптах брак пропал.

ПОЧЕМУ МОДЕЛЬ И ВЕС ГАЙДА СВОИ У КАЖДОЙ КНОПКИ. Одна сборка на все
двадцать не работает: `stoiqo` с весом 0.25 даёт три чистых кадра из
трёх на семи парных кнопках, но на `mf_face` падает до одного из трёх,
а там выигрывает `pixelwave` без гайда вовсе. Карта собрана прогоном
318 кадров, а не выбрана на глаз.

ПОЧЕМУ ПРИЁМКА СЧИТАЕТ СКЕЛЕТЫ. Маска силуэта сливала соприкасающиеся
тела в одно, счёт лиц терял отвёрнутых, коробки YOLO подавлялись NMS на
переплетённых телах. Скелет различает тела по ключевым точкам и на
пробе совпал с глазом в девяти случаях из десяти.

ПОЧЕМУ ПОЗА МЕРЯЕТСЯ СИЛУЭТОМ ГАЙДА. Эталонных кадров в репозитории
нет, зато есть карты глубины, снятые с них: бинаризованная карта и есть
силуэт эталона. Без этой проверки кадр с двумя целыми людьми в другой
позе проходил приёмку как годный.

ПОЧЕМУ ЛИЦО ВСТРАИВАЕТСЯ, А НЕ ВСТАВЛЯЕТСЯ. Жалоба «лицо выглядит как
вклеенное» это про стык, а не про лицо: внутри эллипса один кадр,
снаружи другой. `seamlessClone` переносит градиент, и тон с освещением
берутся от кожи вокруг - узнаваемость при этом не падает вовсе
(0.826 против 0.824 на замере). Сетевые пути проверены и отвергнуты:
PuLID роняет позу с 0.96 до 0.45, доводка кадра роняет узнаваемость с
0.82 до 0.55, FLUX Fill референс лица не слушает вовсе.

ПОЧЕМУ ЛИЦ ДВА. На парной кнопке клиентка и наш партнёр - Марк на МЖ,
Юлия на ЖЖ. PuLID с одним референсом ставит одно лицо ВСЕМ, и мужчина
выходил с женским лицом.

ПОЧЕМУ КАДРИРОВАНИЕ ТОЖЕ СВОЁ У КАЖДОЙ КНОПКИ. Все двадцать карт
глубины сняты с ВЕРТИКАЛЬНЫХ эталонов, а пять парных кнопок каталог
генерит горизонтально. Карта при этом растягивалась вдвое по ширине:
ControlNet получал сплющенные тела, и ровно на этих кнопках выходили
сросшиеся фигуры. Способов три, и лучший у каждой кнопки свой.
"""
import concurrent.futures as futures
import os
import uuid

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))

import cv2
import konveyer as К
import numpy as np
import runware
import люди_в_кадре as люди
import поза_эталона
import роли_парной as роли
import сшивка_лица as сшивка

CN_FLUX_D = "runware:27@1"
KLEIN = "runware:400@2"
ШАГИ = 28
CFG = 3.5
ЗЁРНА = (11, 202, 777, 4242)
# Больше трёх кругов не окупается: на прогоне 318 кадров кнопка, не
# прошедшая за три зерна, не проходила и за шесть - её чинит смена
# сборки, а не новая лотерея.
КРУГОВ = 3

МОДЕЛИ = {
    "stoiqo": "civitai:161068@979329",
    "pixelwave": "civitai:141592@992642",
    "iniv": "civitai:226533@973626",
    "carnival": "civitai:732481@819105",
}

# Сборка каждой кнопки: (модель, вес гайда, кадр). Собрано прогоном.
#   верт          кадр вертикальный, как сама карта глубины
#   гориз_поля    карта вписана по высоте, бока отданы комнате
#   гориз_растяг  карта растянута в широкий кадр (так было всегда)
СБОРКА = {
    # соло: кадр вертикальный, как и карты глубины
    "un_close": ("iniv", 0.25, "верт"),
    "un_full": ("pixelwave", 0.35, "верт"),
    "un_back": ("carnival", 0.35, "верт"),
    "un_three": ("iniv", 0.35, "верт"),
    "un_sit": ("carnival", 0.35, "верт"),
    "un_lie": ("stoiqo", 0.35, "верт"),
    "ph_close": ("pixelwave", 0.25, "верт"),
    "ph_side": ("pixelwave", 0.35, "верт"),
    "ph_above": ("iniv", 0.35, "верт"),
    "ph_below": ("pixelwave", 0.35, "верт"),
    "ph_push": ("pixelwave", 0.35, "верт"),
    # парные. Каталог просил пять из них горизонтально, но карты
    # глубины вертикальные, и в широком кадре они растягивались вдвое:
    # поза падала с 0.62 до 0.33, а тела срастались. Четыре кнопки
    # вернулись в вертикаль, mf_near держится вписыванием с полями.
    "ff_close": ("carnival", 0.65, "верт"),
    "ff_near": ("carnival", 0.50, "верт"),
    "mf_face": ("stoiqo", 0.65, "верт"),
    "mf_pov": ("pixelwave", 0.50, "верт"),
    "ff_behind": ("stoiqo", 0.65, "верт"),
    "ff_face": ("stoiqo", 0.35, "верт"),
    "ff_pov": ("stoiqo", 0.50, "верт"),
    "mf_behind": ("pixelwave", 0.35, "верт"),
    "mf_near": ("pixelwave", 0.35, "гориз_поля"),
}
ПО_УМОЛЧАНИЮ = ("stoiqo", 0.35, "верт")


def сборка(ключ):
    з = СБОРКА.get(К.короткий(ключ))
    if not з:
        return ПО_УМОЛЧАНИЮ
    return з if len(з) == 3 else (з[0], з[1], "верт")


def размер(ключ):
    return (1216, 832) if сборка(ключ)[2].startswith("гориз") else (832, 1216)


def карта_глубины(ключ, ш, в):
    """Карта глубины кнопки под нужное кадрирование."""
    как = сборка(ключ)[2]
    г = cv2.imread(os.path.join(К.ГАЙДЫ, К.короткий(ключ) + ".jpg"),
                   cv2.IMREAD_GRAYSCALE)
    if г is None:
        return None
    if как == "гориз_поля":
        # Вписываем по высоте и добиваем чёрным: фигура сохраняет
        # пропорции, а бока широкого кадра остаются комнате.
        к = int(г.shape[1] * в / г.shape[0])
        поле = np.zeros((в, ш), np.uint8)
        м = cv2.resize(г, (к, в))
        x = max(0, (ш - к) // 2)
        поле[:, x:x + min(к, ш)] = м[:, :min(к, ш)]
        г = поле
    else:
        г = cv2.resize(г, (ш, в))
    return cv2.cvtColor(г, cv2.COLOR_GRAY2BGR)


class Кнопка:
    """Один кадр кнопки от основы до готового файла."""

    def __init__(self, рв=None, лица_моделей=None):
        self.рв = рв or runware.Runware()
        self.ури = runware._дата_ури
        self.модели = лица_моделей or os.path.join(ЗДЕСЬ, "лица_моделей")

    # --- сеть ---------------------------------------------------------
    def _кадр(self, т):
        о = self.рв._зов([т])
        б = self.рв._скачать(о[0]["imageURL"])
        return б, cv2.imdecode(np.frombuffer(б, np.uint8), cv2.IMREAD_COLOR)

    def _тело(self, ключ, зерно):
        модель, вес, _ = сборка(ключ)
        ш, в = размер(ключ)
        т = {"taskType": "imageInference", "taskUUID": str(uuid.uuid4()),
             "model": МОДЕЛИ[модель],
             "positivePrompt": К.промпт_основы(ключ),
             "negativePrompt": К.негатив_основы(
                 ключ, К.эталонный_промпт(ключ) or ""),
             "width": ш, "height": в, "steps": ШАГИ, "CFGScale": CFG,
             "numberResults": 1, "seed": int(зерно),
             "outputType": "URL", "outputFormat": "PNG"}
        г = карта_глубины(ключ, ш, в) if вес > 0 else None
        if г is not None:
            т["controlNet"] = [{
                "model": CN_FLUX_D, "weight": вес, "startStep": 1,
                "endStep": int(ШАГИ * 0.8),
                "guideImage": self.ури(cv2.imencode(".png", г)[1].tobytes())}]
        return т

    # --- основа -------------------------------------------------------
    def основа(self, ключ, кругов=КРУГОВ):
        """Лучший кадр: без дефектов и ближе к позе эталона.

        ПЕРВОЕ ЗЕРНО СЧИТАЕТСЯ ОДНО, и это замер, а не осторожность.
        Три зерна разом выглядят бесплатными, но сервис ставит их в
        очередь: кнопка занимала 95-100 секунд вместо тридцати при
        норме владельца в минуту. А чистым с первого зерна выходит
        каждый кадр соло-кнопки и почти каждый парной, то есть платили
        мы за очередь впустую.

        Не прошло - остальные зёрна идут пачкой: тут ждать уже нечего,
        дефект зависит именно от зерна, и два кадра разом дешевле двух
        по очереди.
        """
        надо = 2 if К.пара(ключ) else 1
        зёрна = list(ЗЁРНА)[:кругов]
        оценённые = []

        def оценить(пара_кадра):
            б, к = пара_кадра
            if к is None:
                return None
            дефекты, _ = люди.беды(к, надо)
            поза = поза_эталона.совпадение(к, ключ) or 0.0
            # Дефект весит больше любой позы: кадр с лишней рукой в
            # точной позе клиентка вернёт, кадр без дефектов в
            # неточной - нет.
            return (len(дефекты) * 10.0 - поза, б, к, дефекты, поза)

        первый = оценить(self._безопасно(ключ, зёрна[0]))
        if первый is not None:
            оценённые.append(первый)
        if первый is None or первый[3]:
            with futures.ThreadPoolExecutor(
                    max_workers=max(1, len(зёрна) - 1)) as пул:
                for г in пул.map(lambda з: self._безопасно(ключ, з),
                                 зёрна[1:]):
                    о = оценить(г)
                    if о is not None:
                        оценённые.append(о)
        if not оценённые:
            raise RuntimeError("ни один кадр основы не досчитался")
        _, б, к, дефекты, поза = min(оценённые, key=lambda о: о[0])
        return {"байты": б, "кадр": к, "дефекты": дефекты, "поза": поза}

    def _безопасно(self, ключ, зерно):
        try:
            return self._кадр(self._тело(ключ, зерно))
        except Exception:                                   # noqa: BLE001
            return None, None

    # --- лица ---------------------------------------------------------
    def _реф(self, имя):
        п = os.path.join(self.модели, имя + "_фронт.png")
        if not os.path.exists(п):
            return None
        return self.ури(open(п, "rb").read())

    def _маска(self, кадр, рамка):
        """Эллипс по найденной рамке лица, с запасом на лоб и подбородок."""
        x1, y1, x2, y2 = [float(з) for з in рамка]
        ш, в = x2 - x1, y2 - y1
        м = np.zeros(кадр.shape[:2], np.uint8)
        cv2.ellipse(м, (int(x1 + ш / 2), int(y1 + в / 2 + в * 0.06)),
                    (int(ш * 0.92), int(в * 0.86)), 0, 0, 360, 255, -1)
        return м

    def лицо(self, основа_байты, основа_кадр, реф_ури, ш, в, зерно=101):
        _, нов = self._кадр(К.тело_лица(основа_байты, реф_ури, ш, в,
                                        зерно, self.ури))
        return нов

    def поставить_лица(self, ключ, осн_байты, осн, лицо_клиентки,
                       найти_лица):
        """Лицо клиентки, а на парной кнопке и лицо нашего партнёра.

        `найти_лица` зовётся отдельным процессом: insightface требует
        protobuf шестой, mediapipe младше пятого, в одном окружении
        живёт только один.
        """
        ш, в = осн.shape[1], осн.shape[0]
        найденные = найти_лица(осн)
        if not найденные:
            return осн, "лиц на основе нет"
        задачи = []
        if К.пара(ключ) and len(найденные) == 2:
            р = роли.кто_где(осн, К.короткий(ключ), найденные)
            if р:
                задачи.append((р["клиентка"]["bbox"], лицо_клиентки))
                реф = self._реф(р["кто"])
                if реф:
                    задачи.append((р["партнёр"]["bbox"], реф))
        if not задачи:
            кр = max(найденные,
                     key=lambda л: л["bbox"][2] - л["bbox"][0])
            задачи.append((кр["bbox"], лицо_клиентки))
        готово = осн
        with futures.ThreadPoolExecutor(max_workers=len(задачи)) as пул:
            кадры = list(пул.map(
                lambda з: self.лицо(осн_байты, осн, з[1], ш, в), задачи))
        for (рамка, _), нов in zip(задачи, кадры):
            if нов is None:
                continue
            готово = сшивка.встроить(готово, нов, self._маска(осн, рамка))
        return готово, None
