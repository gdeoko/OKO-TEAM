def job(key):
    if key not in JOBS:
        raise KeyError(f"неизвестный вид генерации: {key}")
    return JOBS[key]


def pack(pack_id):
    for p in PACKS:
        if p["id"] == pack_id:
            return p
    raise KeyError(f"неизвестный пакет: {pack_id}")




def rub_per_coin(pack_id="p3"):
    """Во сколько обходится коин в этом пакете. p3 — средний, его и
    показываем, когда надо назвать одну цифру."""
    p = pack(pack_id)
    return p["rub"] / p["coins"]


def скидка(pack_id):
    """Насколько коин в этом пакете дешевле, чем во входном, в процентах.

    Считается от НАШЕГО входного пакета, а не от конкурента: это выгода
    от объёма, и человек сравнивает её с соседней кнопкой, а не с чужим
    ботом. Сравнение с рынком живёт отдельно — `vs_market`.
    """
    вход = rub_per_coin(PACKS[0]["id"])
    return int(round((1 - rub_per_coin(pack_id) / вход) * 100))


def coins_per_rub(offer):
    """Курс предложения. Пакет и подписка считаются одинаково."""
    return offer["coins"] / offer["rub"]


def vs_market(offer):
    """Доля от цены конкурента: 0,75 значит ровно на четверть дешевле."""
    return offer["rub"] / offer["market_rub"]


def best_pack_rate():
    return max(coins_per_rub(p) for p in PACKS)
