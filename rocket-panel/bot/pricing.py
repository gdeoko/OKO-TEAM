def коинов(кристаллов):
    """Его цена в кристаллах -> наша в коинах. Всегда вниз."""
    return кристаллов // КРИСТАЛЛОВ_В_КОИНЕ


class Job:
    """Вид генерации: чего стоит клиенту и сколько занимает карту.

    `crystals` — его цена за ту же услугу. Хранится именно она, а
    коины считаются из неё: так цена не может разойтись с обещанием
    при правке руками.

    `фото_нужно` — сколько снимков просить у человека: (минимум,
    максимум). Это не украшение интерфейса, а свойство модели, и
    разойтись они не имеют права. Qwen-Image-Edit берёт до ТРЁХ
    референсов, потому что они идут в условие, а не в латент: каркас
    кадра модель строит заново, поэтому позу и план можно менять
    полностью. Видео берёт стартовый кадр, а с VACE внутри — ещё и
    последний, отсюда (1, 2).
    """

    def __init__(self, key, title, crystals, seconds, note="",
                 фото_нужно=(0, 0), маска=False, plan=None, в_продаже=True):
        self.key = key
        self.title = title
        self.crystals = crystals
        self.seconds = seconds
        self.note = note
        self.фото_нужно = фото_нужно
        self.маска = маска
        self.plan = plan          # None — доступно всем, иначе нужен план
        # Цена посчитана, но кнопки нет. Не то же самое, что удалить:
        # удалённый вид ломает старые записи в базе — `store.works`
        # спрашивает у прайса заголовок по ключу, и «Мои работы» упали бы
        # на первой же прошлой генерации.
        self.в_продаже = в_продаже

    @property
    def нужно_фото(self):
        return self.фото_нужно[0] > 0

    @property
    def макс_фото(self):
        return self.фото_нужно[1]

    @property
    def coins(self):
        return коинов(self.crystals)

    @property
    def cost_rub(self):
        return self.seconds * GPU_USD_PER_SECOND * USD_RUB

    def rub(self, pack_id=None):
        """Во сколько обходится клиенту при курсе выбранного пакета."""
        return self.coins * rub_per_coin(pack_id)

    def margin(self, pack_id=None):
        c = self.cost_rub
        return float("inf") if c == 0 else self.rub(pack_id) / c


