def job(key):
    if key not in JOBS:
        raise KeyError(f"неизвестный вид генерации: {key}")
    return JOBS[key]


def pack(pack_id):
    for p in PACKS:
        if p["id"] == pack_id:
            return p
    raise KeyError(f"неизвестный пакет: {pack_id}")


def sub(sub_id):
    for s in SUBS:
        if s["id"] == sub_id:
            return s
    raise KeyError(f"неизвестная подписка: {sub_id}")


def quality(qid):
    for q in QUALITY:
        if q["id"] == qid:
            return q
    raise KeyError(f"неизвестное качество: {qid}")


def rub_per_token(pack_id="p3"):
    """Во сколько обходится жетон в этом пакете. p3 — средний, его и
    показываем, когда надо назвать одну цифру."""
    p = pack(pack_id)
    return p["rub"] / p["tokens"]


def tokens_per_rub(offer):
    """Курс предложения. Пакет и подписка считаются одинаково."""
    return offer["tokens"] / offer["rub"]


def vs_market(offer):
    """Доля от цены конкурента: 0,75 значит ровно на четверть дешевле."""
    return offer["rub"] / offer["market_rub"]


def sub_rub_per_day(s):
    return s["rub"] / s["дней"]


def best_pack_rate():
    return max(tokens_per_rub(p) for p in PACKS)
