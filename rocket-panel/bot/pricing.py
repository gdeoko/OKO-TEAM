def job(key):
    if key not in JOBS:
        raise KeyError(f"неизвестный вид генерации: {key}")
    return JOBS[key]


def pack(pack_id):
    for p in PACKS:
        if p["id"] == pack_id:
            return p
    raise KeyError(f"неизвестный пакет: {pack_id}")


def pack_total(pack_id):
    """Сколько жетонов реально придёт на баланс, с бонусом."""
    p = pack(pack_id)
    return p["tokens"] + p["bonus"]


def sub(sub_id):
    for s in SUBS:
        if s["id"] == sub_id:
            return s
    raise KeyError(f"неизвестная подписка: {sub_id}")


def offer_usd(offer):
    """Цена предложения в долларах. Пакеты заданы в долларах, подписки в
    рублях — этот рынок торгуется в рублях."""
    return offer["usd"] if "usd" in offer else offer["rub"] / USD_RUB


def tokens_per_usd(offer):
    """Курс жетона в конкретном предложении — пакете или подписке."""
    всего = offer["tokens"] + offer.get("bonus", 0)
    return всего / offer_usd(offer)


def sub_rub_per_day(s):
    """Во сколько обходится день подписки. Длинный срок обязан быть дешевле."""
    return s["rub"] / s["дней"]


def sub_vs_market(s):
    """Доля от цены конкурента: 0,85 значит мы на 15 % дешевле."""
    return s["rub"] / s["market_rub"]


def rub(usd):
    return round(usd * USD_RUB)


def tokens_to_rub(tokens):
    return rub(tokens / TOKENS_PER_USD)
