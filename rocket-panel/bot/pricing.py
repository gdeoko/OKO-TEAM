def job(key):
    if key not in JOBS:
        raise KeyError(f"неизвестный вид генерации: {key}")
    return JOBS[key]


def pack(pack_id):
    for p in PACKS:
        if p["id"] == pack_id:
            return p
    raise KeyError(f"неизвестный пакет: {pack_id}")


def quality(qid):
    for q in QUALITY:
        if q["id"] == qid:
            return q
    raise KeyError(f"неизвестное качество: {qid}")


def rub_per_heart(pack_id="p3"):
    """Во сколько обходится сердечко в этом пакете. p3 — средний, его и
    показываем, когда надо назвать одну цифру."""
    p = pack(pack_id)
    return p["rub"] / p["hearts"]


def hearts_per_rub(offer):
    """Курс предложения. Пакет и подписка считаются одинаково."""
    return offer["hearts"] / offer["rub"]


def vs_market(offer):
    """Доля от цены конкурента: 0,75 значит ровно на четверть дешевле."""
    return offer["rub"] / offer["market_rub"]


def best_pack_rate():
    return max(hearts_per_rub(p) for p in PACKS)
