"""Цены бота. Единственный источник правды по деньгам.

Всё считается в жетонах и рублях. Доллар тут не нужен: этот рынок
торгуется в рублях.

## Откуда взялись цифры

Весь прайс конкурента Exclusive AI (@exclusive_ai_bot) снят изнутри бота
20.09.2026, разбор — в ВЕБКАМ_БОТ_ЦЕНЫ_РЫНКА.md. Цена генерации стоит у
него на кнопке запуска и видна только после загрузки фото.

## Главное решение: жетон = его кристалл

Генерации стоят РОВНО столько же жетонов, сколько у него кристаллов, а
пакеты жетонов — на 25 % дешевле его пакетов. Тогда обещание «мы на
четверть дешевле» верно на каждом пакете, а не в среднем, и проверяется
вычитанием.

Так вышло не сразу. Первая версия считалась от себестоимости (фото за
три копейки при рыночных семидесяти), вторая — от общей вилки сегмента,
и она развалилась при встрече с живыми цифрами: фото оказалось на 42 %
дешевле него, а пятисекундный ролик на 39 % ДОРОЖЕ. Сравнивать надо с
тем, с кем конкурируешь, и в его же единицах.

Себестоимость (замеры на нашей A6000, 0,50 $/час) осталась только затем,
чтобы видеть маржу и ловить уход в минус.
"""

USD_RUB = 92

# Стоимость карты в секунду, доллары. Отсюда считается себестоимость.
GPU_USD_PER_SECOND = 0.50 / 3600

# На сколько мы обязаны быть дешевле конкурента. Решение владельца
# 20.09.2026: ровно на четверть, везде, без исключений.
СКИДКА_К_РЫНКУ = 0.25


class Job:
    """Вид генерации: чего стоит клиенту и сколько занимает карту.

    `tokens` намеренно равен числу кристаллов за ту же услугу у
    конкурента — на этом держится вся сверка цен.
    """

    def __init__(self, key, title, tokens, seconds, note="", plan=None):
        self.key = key
        self.title = title
        self.tokens = tokens
        self.seconds = seconds
        self.note = note
        self.plan = plan          # None — доступно всем, иначе нужен план

    @property
    def cost_rub(self):
        return self.seconds * GPU_USD_PER_SECOND * USD_RUB

    def rub(self, pack_id="p3"):
        """Во сколько обходится клиенту при курсе выбранного пакета."""
        return self.tokens * rub_per_token(pack_id)

    def margin(self, pack_id="p3"):
        c = self.cost_rub
        return float("inf") if c == 0 else self.rub(pack_id) / c


# Секунды карты — замеры на A6000: двухсекундный вертикальный ролик
