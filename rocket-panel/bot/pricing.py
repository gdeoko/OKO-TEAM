"""Цены бота. Единственный источник правды по деньгам.

Всё считается в жетонах. Курс к доллару задан здесь и больше нигде.

Опорные цифры себестоимости — замеры на нашей A6000 (0,50 $/час):

    фото 1024              4,0 с   0,00056 $
    фото по референсу     10,0 с   0,0014  $
    ролик 2 с, горизонт   61,0 с   0,0085  $
    ролик 2 с, вертикаль 149,0 с   0,0207  $

Себестоимость — копейки, поэтому от неё цену НЕ считаем: так и вышла
первая версия тарифов, где фото стоило три копейки при рыночных
девяноста. Цена ставится от рынка (см. ВЕБКАМ_БОТ_ЦЕНЫ_РЫНКА.md,
замер 20.09.2026), себестоимость нужна лишь чтобы видеть маржу.

Ориентир рынка на 20.09.2026:
    фото у конкурента в телеграме   ~0,99 $ за кредит (вход)
    ролик                           ~5 $ (5 кредитов)
    подписки                         4,99 / 9,99 / 19,99 / 39,99 $
Мы встаём примерно вчетверо ниже поштучно и держим ту же лестницу
подписок: на эти четыре цифры аудитория уже приучена.
"""

TOKENS_PER_USD = 100
USD_RUB = 92

# Стоимость карты в секунду, доллары. Отсюда считается себестоимость.
GPU_USD_PER_SECOND = 0.50 / 3600

# Что берёт конкурент за то же самое, доллары. Только для отчётов и
# витрины «у нас дешевле» — в расчёте списаний не участвует.
MARKET_USD = {
    "photo": 0.99, "photo_ref": 0.99, "inpaint": 0.99,
    "video_2": 4.95, "video_3": 4.95, "video_5": 4.95, "animate": 4.95,
}


class Job:
    """Вид генерации: чего стоит клиенту и сколько занимает карту."""

    def __init__(self, key, title, tokens, seconds, note=""):
        self.key = key
        self.title = title
        self.tokens = tokens
        self.seconds = seconds
        self.note = note

    @property
    def cost_usd(self):
        """Себестоимость: сколько карты съедает одна такая генерация."""
        return self.seconds * GPU_USD_PER_SECOND

    @property
    def price_usd(self):
        return self.tokens / TOKENS_PER_USD

    @property
    def margin(self):
        """Во сколько раз цена выше себестоимости."""
        c = self.cost_usd
        return float("inf") if c == 0 else self.price_usd / c

    @property
    def market_usd(self):
        return MARKET_USD.get(self.key)

    @property
    def cheaper_than_market(self):
        """Во сколько раз мы дешевле конкурента. None — если не с чем сравнить."""
        m = self.market_usd
        return (m / self.price_usd) if m and self.price_usd else None


JOBS = {
    j.key: j
    for j in [
        Job("photo",       "Фото",              25,   4.0,  "по описанию"),
        Job("photo_ref",   "Фото по образцу",   40,  10.0,  "с вашим фото, поза и сцена любые"),
        Job("inpaint",     "Правка фото",       40,  12.0,  "меняем обведённое, лицо не трогаем"),
        # Длинный ролик дешевле в пересчёте на секунду: на рынке видео
        # стоит одинаково независимо от длины, и ровная цена за секунду
        # подводит пятисекундный вплотную к конкуренту.
        Job("video_2",     "Ролик 2 секунды",  150, 149.0,  "вертикальный"),
        Job("video_3",     "Ролик 3 секунды",  200, 220.0,  "вертикальный"),
        Job("video_5",     "Ролик 5 секунд",   300, 370.0,  "вертикальный"),
        Job("animate",     "Оживить фото",     150, 149.0,  "ваше фото оживает"),
    ]
}

# Пакеты жетонов. Купленные не сгорают никогда.
# Курс нарочно разный: мелкий пакет дороже за жетон, крупный дешевле.
# Верхняя планка — 125 жетонов за доллар: выше начинается подписка, и
# пакет не имеет права быть выгоднее её, иначе подписку никто не купит.
PACKS = [
    {"id": "p1", "tokens": 300,   "usd": 5,   "bonus": 0},
    {"id": "p2", "tokens": 700,   "usd": 10,  "bonus": 100},
    {"id": "p3", "tokens": 2000,  "usd": 25,  "bonus": 300},
    {"id": "p4", "tokens": 5000,  "usd": 50,  "bonus": 500},
    {"id": "p5", "tokens": 12000, "usd": 100, "bonus": 500},
]

# Подписки — главный доход. Лестница цен взята с рынка один в один.
# Жетоны подписки СГОРАЮТ в конце месяца, в этом её смысл: иначе
# человек копит и не продлевает. Купленные пакеты не сгорают никогда.
# Курс у подписки лучше, чем у любого пакета, — это и держит продление.
SUBS = [
    {"id": "s1", "title": "Проба", "usd": 4.99,  "tokens": 500,  "priority": False},
    {"id": "s2", "title": "Старт", "usd": 9.99,  "tokens": 1400, "priority": False},
    {"id": "s3", "title": "Про",   "usd": 19.99, "tokens": 3400, "priority": True},
    {"id": "s4", "title": "Макс",  "usd": 39.99, "tokens": 8000, "priority": True},
]

# Сколько жетонов даём новичку, чтобы он попробовал до всякой оплаты.
# Хватает ровно на два фото — попробовать, но не нажиться.
WELCOME_TOKENS = 50

# Сколько получает пригласивший и приглашённый.
REFERRAL_INVITER = 100
REFERRAL_INVITEE = 50


def job(key):
    if key not in JOBS:
        raise KeyError(f"неизвестный вид генерации: {key}")
    return JOBS[key]


def pack(pack_id):
    for p in PACKS:
        if p["id"] == pack_id:
            return p
    raise KeyError(f"неизвестный пакет: {pack_id}")


def pack_total(pack_id):
    """Сколько жетонов реально придёт на баланс, с бонусом."""
    p = pack(pack_id)
    return p["tokens"] + p["bonus"]


def sub(sub_id):
    for s in SUBS:
        if s["id"] == sub_id:
            return s
    raise KeyError(f"неизвестная подписка: {sub_id}")


def tokens_per_usd(offer):
    """Курс жетона в конкретном предложении — пакете или подписке."""
    if "bonus" in offer:
        return (offer["tokens"] + offer["bonus"]) / offer["usd"]
    return offer["tokens"] / offer["usd"]


def rub(usd):
    return round(usd * USD_RUB)


def tokens_to_rub(tokens):
    return rub(tokens / TOKENS_PER_USD)
