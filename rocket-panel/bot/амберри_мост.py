# -*- coding: utf-8 -*-
"""Мост: новая цепочка кадра внутри старого бота.

Бот собирает промпт из двух десятков блоков под FLUX с картой глубины и
считает его на выбранном движке. Новая цепочка устроена иначе: один
текст под `z-image-spicy-pro`, апскейл по ссылке и лицо последним
слоем. Чтобы не переписывать бот целиком, мост встаёт в две точки:

    подготовить()  до запуска: подменяет промпт, негатив и лист
    довести()      после кадра: 4K и лица

Выключается переменной `AMBERRY_NOVAYA=0`: тогда бот работает как
работал. Любая беда внутри моста тоже означает старый путь, а не
осечку: человек получает кадр, пусть и прежним способом.

## Описание клиентки считается ОДИН раз

Описатель стоит около цента, и платить его на каждый кадр незачем:
внешность не меняется. Ответ запоминается по снимку (md5) в памяти
процесса и в файле рядом с ботом, поэтому переживает и перезапуск.

## Партнёр на парной кнопке

Лицо клиентки идёт на женщину, лицо нашей модели на второго человека:
Марк на кнопках МЖ, Юлия на ЖЖ. Кто есть кто решает сходство, см.
`амберри_лицо`.
"""
import hashlib
import json
import os
import tempfile

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ВКЛЮЧЁН = os.environ.get("AMBERRY_NOVAYA", "1") not in ("0", "нет", "")
ПАМЯТЬ = os.environ.get("AMBERRY_OPIS_FILE",
                        os.path.join(ЗДЕСЬ, "описания_клиенток.json"))
МОДЕЛИ = os.path.join(ЗДЕСЬ, "лица_моделей")
# Предел длины промпта: сервис рвёт связь между 2915 и 3100 знаками.
ПРЕДЕЛ = int(os.environ.get("AMBERRY_PREDEL", "2800"))
ПАРТНЁР = {"mf": "марк", "ff": "юлия"}

_опис = {}


def включён():
    return ВКЛЮЧЁН


def _короткий(ключ):
    """Ключ кнопки без приставки бота: `pf_mf_near` -> `mf_near`."""
    к = str(ключ or "")
    for п in ("pr_", "pf_", "vi_", "ac_"):
        if к.startswith(п):
            ост = к[len(п):]
            return ("ph_" + ост) if п == "ac_" else ост
    return к


def знает(ключ):
    import амберри_промпты as ПР
    к = _короткий(ключ)
    return к in ПР.СОЛО or к in ПР.ПАРНЫЕ


def снята(ключ):
    import амберри_промпты as ПР
    return _короткий(ключ) in ПР.СНЯТЫ


def _из_памяти(метка):
    if метка in _опис:
        return _опис[метка]
    try:
        _опис.update(json.load(open(ПАМЯТЬ, encoding="utf-8")))
    except Exception:                                       # noqa: BLE001
        pass
    return _опис.get(метка)


def _в_память(метка, текст):
    _опис[метка] = текст
    try:
        json.dump(_опис, open(ПАМЯТЬ, "w", encoding="utf-8"),
                  ensure_ascii=False, indent=1)
    except Exception:                                       # noqa: BLE001
        pass


def описание(снимок, пол="ж"):
    """Внешность со снимка словами. Пустая строка - описателя нет."""
    if not снимок:
        return ""
    метка = hashlib.md5(снимок).hexdigest() + ("_" + str(пол))
    есть = _из_памяти(метка)
    if есть is not None:
        return есть
    try:
        import амберри_описатель as О
        т = О.описать(снимок, пол)
    except Exception as e:                                  # noqa: BLE001
        print("МОСТ: описатель не вышел: %s" % str(e)[:120], flush=True)
        т = ""
    _в_память(метка, т)
    return т


def подготовить(scene, kind, снимок=None, видео=False):
    """Промпт новой цепочки или None, если кнопка не наша.

    Возвращает словарь {"prompt", "neg", "лист"}.
    """
    if not включён() or not знает(scene):
        return None
    try:
        import амберри_промпты as ПР
        к = _короткий(scene)
        if видео:
            д = ПР.видео(к)
            return {"prompt": д["промпт"], "neg": д["негатив"]}
        наша = описание(снимок, "ж") if снимок else ""
        партнёр = ""
        вторая = ""
        if к in ПР.ПАРНЫЕ:
            кто = ПАРТНЁР.get(к[:2], "")
            п = os.path.join(МОДЕЛИ, кто + "_фронт.png")
            if os.path.exists(п):
                опис = описание(open(п, "rb").read(),
                                "м" if кто == "марк" else "ж")
                if кто == "марк":
                    партнёр = опис
                else:
                    вторая = опис
        д = ПР.промпт(к, она=наша, он=партнёр, вторая=вторая)
        # ПРЕДЕЛ ДЛИНЫ. Сервис рвёт связь на промптах от трёх тысяч
        # знаков (замер 01.10.2026: 2915 проходит, 3100 нет), а подробное
        # описание клиентки и партнёра весит под тысячу на двоих. Если
        # вместе вышло длинно, укорачиваем ОПИСАНИЯ, а не постановку:
        # поза и ракурс держат кадр, а лишняя примета внешности нет.
        if len(д["промпт"]) > ПРЕДЕЛ:
            import амберри_описатель as О
            д = ПР.промпт(к, она=О.коротко(наша), он=О.коротко(партнёр),
                          вторая=О.коротко(вторая))
            print("МОСТ %s: описания укорочены, промпт %d знаков"
                  % (к, len(д["промпт"])), flush=True)
        return {"prompt": д["промпт"], "neg": д["негатив"],
                "лист": д["лист"]}
    except Exception as e:                                  # noqa: BLE001
        print("МОСТ: промпт не собрался: %s" % str(e)[:140], flush=True)
        return None


def довести(данные, scene, ссылка=None, снимок=None):
    """4K и лица на готовом кадре. Возвращает байты (старые при беде)."""
    if not включён() or not данные or not знает(scene):
        return данные
    к = _короткий(scene)
    папка = tempfile.mkdtemp(prefix="амберри_")
    путь = os.path.join(папка, "кадр.png")
    open(путь, "wb").write(данные)
    try:
        import амберри_цепочка as Ц
        import амберри_промпты as ПР
        if ссылка:
            try:
                путь = Ц._до_4k(ссылка, os.path.join(папка, "4k.png"))
            except Exception as e:                          # noqa: BLE001
                print("МОСТ: 4K не вышло: %s" % str(e)[:120], flush=True)
        доноры = {}
        if снимок:
            клиентка = os.path.join(папка, "клиентка.jpg")
            open(клиентка, "wb").write(снимок)
            доноры["она"] = клиентка
        if к in ПР.ПАРНЫЕ:
            кто = ПАРТНЁР.get(к[:2], "")
            п = os.path.join(МОДЕЛИ, кто + "_фронт.png")
            if os.path.exists(п):
                доноры[кто] = п
        if доноры:
            путь, отчёт = __import__("амберри_лицо").поставить(
                путь, доноры, os.path.join(папка, "готово.png"))
            print("МОСТ %s: лица %s" % (к, json.dumps(
                отчёт, ensure_ascii=False)[:160]), flush=True)
        return open(путь, "rb").read()
    except Exception as e:                                  # noqa: BLE001
        print("МОСТ: доводка не вышла: %s" % str(e)[:140], flush=True)
        return данные
    finally:
        pass
