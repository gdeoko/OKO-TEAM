"""Предупреждения по детским снимкам и заявка на ручную модерацию.

## Решение владельца и сетевого администратора, 28.09.2026

Обсуждали, блокировать ли автоматом. Сошлись на другом:

    Даниэль:  Или автоматически поставить блокировку? 3 предупреждения = блок
    Админ:    ну так то лучше автоматом
    Даниэль:  Иногда просто в 18 лет даже молодо выглядит и можно
              определить как 16-17 например
    Админ:    или после 3 предупреждений чтобы нам саппорт приходил
              запрос на ручную блокировку (модерацию)
    Даниэль:  Все равно даже человек по фото не поймет 17 или 18,
              тут тонкая грань
    Админ:    согласен

Поэтому **автоблокировки нет**. Три отказа по возрасту поднимают
ЗАЯВКУ НА МОДЕРАЦИЮ, и решение принимает человек.

Причина ровно та, что назвал владелец: заслон отделяет ребёнка от
взрослого с запасом, но саму границу 17/18 по лицу не берёт никто,
включая людей. Автомат на такой границе выносил бы приговор живым
клиентам по своей же неуверенности, и обжаловать его было бы нечем.

## Что считается предупреждением

Только отказ ПО ВОЗРАСТУ. Кадр без лица и сорвавшаяся проверка - не
предупреждения: в первом человек просто прислал спину, во втором
виноваты мы. Считать их значило бы копить приговор за наши поломки.

Повторная присылка ТОГО ЖЕ снимка тоже считается один раз: заслон
помнит отпечаток, и три попытки отправить одно и то же фото - это одно
предупреждение, а не три.

## Где живёт счёт

В той же таблице событий, которую бот пишет и так (`events`, вид
`возраст`). Отдельной таблицы нет нарочно: счёт обязан совпадать с
журналом, по которому потом объясняются с человеком, а две таблицы
однажды разойдутся.
"""

import os
import time

# Сколько отказов поднимают заявку. Три - слово владельца.
ПОРОГ = int(os.environ.get("AMBERRY_AGE_WARNINGS", "3"))

# Окно, за которое считаются предупреждения. Без него человек,
# ошибшийся трижды за полгода, однажды попадёт на модерацию за давность.
ОКНО_ДНЕЙ = int(os.environ.get("AMBERRY_AGE_WINDOW_DAYS", "90"))

ВИД = "возраст"
ВИД_ЗАЯВКА = "возраст_модерация"


def _метка(свод):
    """Чем отличать повторы одного снимка. Отпечаток заслон уже считает."""
    return (свод or {}).get("отпечаток") or ""


def засчитать(store, tg_id, почему, свод):
    """Записать отказ и сказать, надо ли поднимать заявку.

    Возвращает (сколько_предупреждений, нужна_заявка).

    Событие пишется ВСЕГДА, даже когда до порога далеко: журнал нужен
    целиком, а не с порога. Заявка поднимается ровно один раз на
    каждые ПОРОГ предупреждений, иначе на четвёртом снимке менеджеры
    получат вторую такую же заявку.
    """
    store.событие(tg_id, ВИД, _метка(свод) or (почему or "")[:60])
    сколько = счёт(store, tg_id)
    if сколько < ПОРОГ:
        return сколько, False
    # Одна заявка на каждые ПОРОГ предупреждений: на третьем, шестом,
    # девятом. Без этого счёта заявка поднималась и на четвёртом тоже -
    # менеджеры получали вторую такую же через один снимок (поймано
    # тестом 28.09.2026).
    if сколько // ПОРОГ <= _заявок(store, tg_id):
        return сколько, False
    store.событие(tg_id, ВИД_ЗАЯВКА, str(сколько))
    return сколько, True


def счёт(store, tg_id):
    """Сколько РАЗНЫХ снимков человека отбито за окно.

    Разных, а не всего: один и тот же кадр, присланный трижды, это одно
    предупреждение. Люди пересылают фото повторно, когда не поняли
    отказ, и это не новая попытка.
    """
    с = int(time.time()) - ОКНО_ДНЕЙ * 86400
    try:
        with store._db() as c:
            r = c.execute(
                "SELECT COUNT(DISTINCT COALESCE(NULLIF(ключ,''), rowid)) n"
                " FROM events WHERE tg_id=? AND вид=? AND at>=?",
                (tg_id, ВИД, с)).fetchone()
            return int(r[0] or 0)
    except Exception as e:                              # noqa: BLE001
        print("счёт предупреждений не прочитался:", str(e)[:120], flush=True)
        return 0


def _заявок(store, tg_id):
    с = int(time.time()) - ОКНО_ДНЕЙ * 86400
    try:
        with store._db() as c:
            r = c.execute(
                "SELECT COUNT(*) FROM events WHERE tg_id=? AND вид=? AND at>=?",
                (tg_id, ВИД_ЗАЯВКА, с)).fetchone()
            return int(r[0] or 0)
    except Exception:                                   # noqa: BLE001
        return 0


def на_модерации(store, дней=None):
    """Люди с предупреждениями: кого показывать в админке.

    Сортировка по числу предупреждений, а не по свежести: разбирать
    надо сначала того, у кого их больше.
    """
    с = int(time.time()) - (дней or ОКНО_ДНЕЙ) * 86400
    try:
        with store._db() as c:
            rs = c.execute(
                "SELECT e.tg_id,"
                "       COUNT(DISTINCT COALESCE(NULLIF(e.ключ,''), e.rowid)) n,"
                "       MAX(e.at) последний,"
                "       COALESCE(u.username,'') username,"
                "       COALESCE(u.blocked,0) blocked,"
                "       (SELECT COUNT(*) FROM events z WHERE z.tg_id=e.tg_id"
                "         AND z.вид=? AND z.at>=?) заявок"
                "  FROM events e LEFT JOIN users u ON u.tg_id=e.tg_id"
                " WHERE e.вид=? AND e.at>=?"
                " GROUP BY e.tg_id ORDER BY n DESC, последний DESC LIMIT 200",
                (ВИД_ЗАЯВКА, с, ВИД, с)).fetchall()
            return [{"tg_id": r[0], "предупреждений": r[1], "последний": r[2],
                     "username": r[3], "заблокирован": bool(r[4]),
                     "на_модерации": r[1] >= ПОРОГ and not r[4]}
                    for r in rs]
    except Exception as e:                              # noqa: BLE001
        print("список модерации не прочитался:", str(e)[:120], flush=True)
        return []


def снять(store, tg_id):
    """Снять предупреждения: человек разобран и признан взрослым.

    Нужна отдельной кнопкой, потому что иначе разобранный человек
    остаётся в списке навсегда и мозолит глаза наравне с неразобранными.
    """
    try:
        with store._db() as c:
            c.execute("DELETE FROM events WHERE tg_id=? AND вид IN (?,?)",
                      (tg_id, ВИД, ВИД_ЗАЯВКА))
        return True
    except Exception as e:                              # noqa: BLE001
        print("предупреждения не снялись:", str(e)[:120], flush=True)
        return False


def письмо_модератору(tg_id, username, сколько, почему):
    """Текст заявки. Уходит в группу менеджеров.

    Прямо сказано, что решение за человеком и какое именно: иначе
    менеджер решит, что бот уже заблокировал, и не сделает ничего.
    """
    кто = f"@{username}" if username else f"id {tg_id}"
    return (f"Нужна модерация: {кто}\n\n"
            f"Заслон отклонил {сколько} разных снимка по возрасту.\n"
            f"Последняя причина: {почему}\n\n"
            f"Автоматически НЕ заблокирован: граница 17/18 по фото не "
            f"берётся надёжно, решение за человеком.\n"
            f"Блокировка и снятие предупреждений - в админке, раздел "
            f"«Проверка фото».")
