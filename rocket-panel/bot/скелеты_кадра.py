# -*- coding: utf-8 -*-
"""Карта поз в стиле OpenPose, нарисованная из скелетов YOLO.

Зачем своя. Карта глубины на парной кнопке сливает два тела в одну
массу: чем выше её вес, тем охотнее модель рисует из этой массы одну
фигуру. Скелет такой беды не знает - у каждого человека свой набор
точек. Но готового скелета взять неоткуда: препроцессор поз на
Runware читает карту глубины как пустоту (он обучен на фотографиях), а
на готовом кадре находит ОДНОГО человека из двух - ровно ту половину,
которая и так получалась.

`yolo11x-pose` находит обоих: это замерено, девять совпадений с глазом
из десяти. Его точки (COCO, 17 штук) переводятся в раскладку OpenPose
(18 точек): шея считается серединой плеч, её в COCO нет вовсе.

Цвета берутся из OpenPose не для красоты: ControlNet обучен именно на
них, и серая палка на месте цветной конечности читается им хуже.
"""
import os

import cv2
import numpy as np

# COCO: 0 нос, 1-2 глаза, 3-4 уши, 5-6 плечи, 7-8 локти, 9-10 запястья,
# 11-12 бёдра, 13-14 колени, 15-16 щиколотки.
ШЕЯ = 17                                  # считается, в COCO её нет
КОСТИ = (
    (ШЕЯ, 6, (255, 0, 0)), (6, 8, (255, 85, 0)), (8, 10, (255, 170, 0)),
    (ШЕЯ, 5, (255, 255, 0)), (5, 7, (170, 255, 0)), (7, 9, (85, 255, 0)),
    (ШЕЯ, 12, (0, 255, 0)), (12, 14, (0, 255, 85)), (14, 16, (0, 255, 170)),
    (ШЕЯ, 11, (0, 255, 255)), (11, 13, (0, 170, 255)), (13, 15, (0, 85, 255)),
    (ШЕЯ, 0, (0, 0, 255)), (0, 2, (85, 0, 255)), (2, 4, (170, 0, 255)),
    (0, 1, (255, 0, 255)), (1, 3, (255, 0, 170)),
)
ТОЧКИ_ЦВЕТ = (
    (255, 0, 0), (255, 85, 0), (255, 170, 0), (255, 255, 0), (170, 255, 0),
    (85, 255, 0), (0, 255, 0), (0, 255, 85), (0, 255, 170), (0, 255, 255),
    (0, 170, 255), (0, 85, 255), (0, 0, 255), (85, 0, 255), (170, 0, 255),
    (255, 0, 255), (255, 0, 170), (255, 255, 255),
)
ВИДНО = 0.5


def _с_шеей(точки):
    """Точки человека плюс шея: середина плеч, если оба видны."""
    т = list(точки)
    лп, пп = т[5], t if False else т[6]
    if лп[2] > ВИДНО and пп[2] > ВИДНО:
        т.append(((лп[0] + пп[0]) / 2.0, (лп[1] + пп[1]) / 2.0,
                  min(лп[2], пп[2])))
    else:
        т.append((0.0, 0.0, 0.0))
    return т


def нарисовать(кадр, скелеты, толщина=None):
    """Чёрный холст размером с кадр и цветные скелеты на нём."""
    в, ш = кадр.shape[:2]
    холст = np.zeros((в, ш, 3), np.uint8)
    т = толщина or max(3, int(min(в, ш) / 160))
    for точки in скелеты:
        точки = _с_шеей(точки)
        for a, b, цвет in КОСТИ:
            if точки[a][2] <= ВИДНО or точки[b][2] <= ВИДНО:
                continue
            cv2.line(холст, (int(точки[a][0]), int(точки[a][1])),
                     (int(точки[b][0]), int(точки[b][1])), цвет, т,
                     cv2.LINE_AA)
        for и, (x, y, c) in enumerate(точки):
            if c > ВИДНО:
                cv2.circle(холст, (int(x), int(y)), т + 1,
                           ТОЧКИ_ЦВЕТ[и % len(ТОЧКИ_ЦВЕТ)], -1, cv2.LINE_AA)
    return холст


def с_кадра(кадр):
    """Скелеты кадра точками: сюда же ходит и приёмка."""
    import люди_в_кадре as люди
    with люди._замок:
        о = люди._модель().predict(кадр, conf=люди.ПОРОГ, iou=люди.IOU,
                                   verbose=False)[0]
    из = []
    точки = о.keypoints.data if о.keypoints is not None else []
    for т in точки:
        т = т.cpu().numpy() if hasattr(т, "cpu") else np.asarray(т)
        из.append([(float(x), float(y), float(c)) for x, y, c in т])
    return из


def карта(кадр):
    return нарисовать(кадр, с_кадра(кадр))
