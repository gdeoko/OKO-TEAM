"""Кто на парном кадре клиентка, а кто наша модель.

Владелец спросил прямо: «Ты с Марком делала? Почему не 2 наших
модели?». На парной кнопке лиц ДВА, и они разные: клиентка и наш
партнёр - Марк на кнопках МЖ, Юлия на кнопках ЖЖ. Прежний конвейер
ставил одно лицо и ставил его тому, кого первым нашёл: на половине
кадров лицо клиентки уезжало партнёру.

PuLID эту задачу не решает вовсе: с одним референсом он ставит ОДНО
лицо всем людям в кадре разом, и на пробе мужчина вышел с женским
лицом. Поэтому роли разбираются по кадру, и каждому лицу идёт свой
референс.

  МЖ   по полу: клиентка это женское лицо, Марк мужское. Пол даёт
       `buffalo_l`, и на пробе он не ошибся ни разу.
  ЖЖ   по волосам: во всех эталонах ЖЖ клиентка это ТА, ЧТО СВЕТЛЕЕ
       («THE BLONDE»), партнёрша тёмная («THE DARK-HAIRED ONE»).
       Светлота меряется на основе, до переноса лица, поэтому
       настоящий цвет волос клиентки роли не меняет.

Светлота считается по тёмной половине пикселей над лицом: блики на
волосах у обеих одинаково белые, а разделяет их именно основная масса.
"""
import os

import cv2
import numpy as np

ПАРТНЁР = {"mf": "марк", "ff": "юлия"}


def _волосы(кадр, рамка):
    """Яркость волос над лицом: полоса в полголовы высотой."""
    x1, y1, x2, y2 = [int(з) for з in рамка]
    ш, в = x2 - x1, y2 - y1
    вx1, вx2 = max(0, x1 - int(ш * 0.35)), min(кадр.shape[1], x2 + int(ш * 0.35))
    вy1, вy2 = max(0, y1 - int(в * 0.62)), max(0, y1 - int(в * 0.06))
    кусок = кадр[вy1:вy2, вx1:вx2]
    if кусок.size < 300:
        return None
    сер = cv2.cvtColor(кусок, cv2.COLOR_BGR2GRAY).reshape(-1)
    # Блики на волосах одинаково белые у блондинки и у брюнетки,
    # поэтому берём тёмную половину - основную массу волос.
    тёмные = np.sort(сер)[:max(1, len(сер) // 2)]
    return float(тёмные.mean())


def кто_где(кадр, ключ, лица):
    """Два лица кадра по ролям.

    `лица` - список словарей {"bbox": [x1, y1, x2, y2], "пол": "F"},
    а не объекты insightface: распознавание живёт в ОТДЕЛЬНОМ процессе
    (protobuf шестой против младше пятого), и через границу процесса
    проходят только простые значения.

    Возвращает {"клиентка": лицо, "партнёр": лицо, "кто": "марк"/"юлия"}
    или None, если лиц не два.
    """
    род = ключ[:2]
    if len(лица) != 2 or род not in ПАРТНЁР:
        return None
    а, б = лица
    if род == "mf":
        полы = [str(л.get("пол") or "").upper() for л in (а, б)]
        if полы[0] == "F" and полы[1] == "M":
            кл, па = а, б
        elif полы[1] == "F" and полы[0] == "M":
            кл, па = б, а
        else:
            # Пол не разобрался - берём того, кто ближе к камере: на
            # всех эталонах МЖ женщина крупнее в кадре.
            кл, па = sorted((а, б), key=_площадь, reverse=True)
    else:
        я = [_волосы(кадр, л["bbox"]) for л in (а, б)]
        if None in я or abs(я[0] - я[1]) < 4:
            # Волосы не различились - у эталонов ЖЖ блондинка СЛЕВА.
            кл, па = sorted((а, б), key=lambda л: л["bbox"][0])
        else:
            кл, па = (а, б) if я[0] > я[1] else (б, а)
    return {"клиентка": кл, "партнёр": па, "кто": ПАРТНЁР[род]}


def _площадь(л):
    b = л["bbox"]
    return (b[2] - b[0]) * (b[3] - b[1])
