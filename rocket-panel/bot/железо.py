"""Разбудить карту перед заданием.

## Зачем это здесь

Карта арендуется почасово и гасится, когда никому не нужна: круглые
сутки она стоит около 780 $ в месяц, а работает от силы несколько часов
в день. Поднимается она обратно не по расписанию, а по первому же
нажатию кнопки — угадывать заранее, когда придёт человек, значит платить
за неугаданное.

Подъём делает `/opt/amberry-card/карта.py` на этом же сервере: он
создаёт машину, цепляет том с моделями, заводит службы и записывает
новый адрес туннеля в файл, который бот перечитывает перед каждым
обращением (`gpu.ФАЙЛ_АДРЕСА`). Перезапускать бота для этого не нужно —
и не нужно НАРОЧНО: будит карту бот посреди запроса живого человека.

## Главное правило: сперва карта, потом деньги

`нужна()` вызывается ДО списания коинов. Если железа в регионе не
оказалось, человек получает понятный отказ и остаётся при своём
балансе. Списать сначала, а потом выяснить, что поднять нечего, —
значит взять деньги за ожидание.
"""
import os
import subprocess
import time

УПРАВЛЕНИЕ = os.environ.get("AMBERRY_CARD_TOOL",
                            "/opt/amberry-card/карта.py")
# ПОДЪЁМ КАРТЫ ИДЁТ ЧЕРЕЗ sudo, И ЭТО НЕ ЛЕНЬ.
#
# Бот работает под `amberry`, а поднять карту без root нельзя: ключ от
# карты лежит в /root/.ssh, замок в /run, адрес пишется в
# /etc/amberry.env. Первая версия звала карту напрямую, и живой запрос
# упал на «Permission denied: /run/amberry-карта.lock».
#
# Права выданы ровно на одну команду и ни на что больше — см.
# /etc/sudoers.d/amberry-karta. Отдавать боту root целиком ради
# запуска одной программы значит чинить дырку дверью.
ЗОВ = ["sudo", "-n", "/usr/bin/python3", УПРАВЛЕНИЕ, "нужна"]
# Подъём карты: создание машины, том, пакеты, ComfyUI, туннель. Замер
# полного цикла — около четырёх минут; берём вдвое с запасом, потому
# что упереться в собственный таймаут на третьей минуте хуже, чем
# подождать лишнее.
ЖДЁМ_ПОДЪЁМА = int(os.environ.get("AMBERRY_WAKE_WAIT", "600"))


# ПОСТОЯННАЯ КАРТА БУДИТЬ СЕБЯ НЕ ДАЁТ, И НЕ ДОЛЖНА.
#
# На Hyperstack карта почасовая и гасится в простое — её поднимает
# первое нажатие кнопки. На Vast карта снята круглосуточно: она уже
# работает, её никто не создаёт и не удаляет, а попытка «поднять» там
# означала бы создать ВТОРУЮ машину за наши деньги.
#
# Поэтому в постоянном режиме мы только проверяем, отвечает ли панель.
# Не отвечает — честно говорим человеку, что сейчас недоступно, и НЕ
# пытаемся чинить это созданием машины.
ПОСТОЯННАЯ = os.environ.get("AMBERRY_CARD_MODE", "") == "постоянная"


def включено():
    """Управление картой установлено. Нет — работаем как раньше."""
    if ПОСТОЯННАЯ:
        return False
    return os.path.exists(УПРАВЛЕНИЕ)


def нужна_проверена(gpu):
    """Карта отвечает прямо сейчас — будить не надо и экран ожидания
    показывать не надо. Днём это обычный случай."""
    try:
        return bool(gpu.настроена and gpu.alive())
    except Exception:                                    # noqa: BLE001
        return False


def нужна(gpu, на_тик=None):
    """Карта обязана отвечать. (получилось, что сказать человеку).

    `на_тик(секунд)` — чтобы показывать, что мы не зависли: подъём
    идёт минуты, и неподвижный экран читается как поломка.
    """
    # Быстрый путь: карта уже работает. Это обычный случай — днём она
    # поднята, и ни одного лишнего действия тут быть не должно.
    if gpu.настроена and gpu.alive():
        return True, ""
    if ПОСТОЯННАЯ:
        # Карта снята круглосуточно и должна отвечать всегда. Молчит —
        # это поломка, а не «спит»: создавать вторую машину нельзя.
        print("постоянная карта не отвечает", flush=True)
        return False, "ошибка"
    if not включено():
        return False, "нет"

    п = subprocess.Popen(ЗОВ, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, text=True)
    т0 = time.time()
    последний = -1
    while п.poll() is None:
        if time.time() - т0 > ЖДЁМ_ПОДЪЁМА:
            п.kill()
            return False, "долго"
        сек = int(time.time() - т0)
        if на_тик and сек != последний:
            на_тик(сек)
            последний = сек
        time.sleep(1)
    вывод = (п.stdout.read() if п.stdout else "") or ""
    if п.returncode != 0:
        print("карта не поднялась:", вывод[-600:], flush=True)
        # «Нет железа» и «сломалось» человеку объясняем по-разному:
        # в первом случае имеет смысл попробовать позже, во втором нет.
        if "карта занята" in вывод:
            return False, "занята"
        return False, ("нет_железа" if "железа нет" in вывод else "ошибка")
    # Панель отвечает? Адрес записан управлением, бот перечитает его
    # сам — но убедиться обязаны мы, иначе первое же задание уйдёт в
    # пустоту и человек заплатит за осечку.
    for _ in range(10):
        if gpu.alive():
            return True, ""
        time.sleep(3)
    return False, "ошибка"
