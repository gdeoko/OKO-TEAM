# -*- coding: utf-8 -*-
"""Снять с кожи то, что дорисовала сборка: жирные блики и крапины.

## Почему это приходится делать кодом

За день перебраны все способы сказать это словами, и все уперлись в
одно и то же. Негатив при CFG полтора почти не звучит, а выше полутора
эта сборка ломается (замер: при 3.5 заливка кожи 56 % против 11).
Положительный текст помогает, пока не назовёшь деталь по имени -
«pores», «grain», «blemishes» все просили фактуру, а давали грязь.

Осталось убрать артефакт после генерации. Это не приукрашивание: мы
снимаем ровно то, чего на присланном снимке не было и что дорисовала
модель. Ровно так же работает ретушёр, и ровно это владелец называет
«грязь» и «намасленное».

## Что НЕ трогаем, и это важнее того, что трогаем

**Родинки и веснушки с референса остаются.** Слово владельца
28.09.2026: «если поставишь запрет, она уберёт и с реального референса
тоже». Поэтому крапины снимаются ТОЛЬКО В ГУСТЫХ СКОПЛЕНИЯХ: у
настоящей родинки соседей нет, а у выдуманной сборкой грязи их
десятки на том же клочке кожи. Одиночная точка не трогается вовсе.

**Широкие блики остаются.** Свет на бедре и плече это форма тела, без
неё выйдет плоская вырезка. Снимаются только МЕЛКИЕ жёсткие блики -
те, по которым и меряется «намасленность» (`качество.блеск_кожи`):
масляная плёнка отражает точками, сухая кожа широко и мягко.

    from ретушь import почистить
    почистить("/кадр.png")            правит файл на месте
"""

import os

import cv2
import numpy as np

# Насколько гасить мелкий блик: 1.0 - до уровня соседней кожи, 0 - не
# трогать. Не единица: полностью снятый блик делает кожу матовой до
# мертвизны, а на настоящей коже он есть, просто мягкий.
СИЛА_БЛИКА = float(os.environ.get("ROCKET_RETUSH_BLICK", "0.75"))

# Насколько гасить крапину. Здесь можно смелее: выдуманной крапины на
# референсе нет вовсе.
СИЛА_ТОЧКИ = float(os.environ.get("ROCKET_RETUSH_TOCHKA", "0.9"))

# Сколько соседей должно быть у точки, чтобы считать её грязью, а не
# родинкой. Считается в окне радиусом в сорок точек.
СОСЕДЕЙ = int(os.environ.get("ROCKET_RETUSH_SOSEDEY", "6"))


def _маска_кожи(кадр):
    """Где кожа. Тот же признак, что у приёмщика, чтобы не разойтись."""
    ycrcb = cv2.cvtColor(кадр, cv2.COLOR_BGR2YCrCb)
    м = cv2.inRange(ycrcb, (0, 133, 77), (255, 180, 127))
    я = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (9, 9))
    м = cv2.morphologyEx(м, cv2.MORPH_OPEN, я)
    return cv2.morphologyEx(м, cv2.MORPH_CLOSE, я)


def _мягко(кадр, маска, куда, сила):
    """Подмешать `куда` в кадр по маске с растушёвкой.

    Растушёвка обязательна: жёсткая замена оставляет ступеньку по
    краю пятна, и вместо блика получается заплатка.
    """
    if not маска.any():
        return кадр
    м = cv2.GaussianBlur(маска.astype(np.float32), (0, 0), 2.0)
    м = np.clip(м * сила, 0, 1)[..., None]
    return (кадр * (1 - м) + куда * м).astype(np.uint8)


def снять_блики(кадр, маска_кожи=None):
    """Погасить МЕЛКИЕ жёсткие блики, оставив широкий свет."""
    кожа = маска_кожи if маска_кожи is not None else _маска_кожи(кадр)
    если = кожа > 0
    if если.mean() < 0.02:
        return кадр, 0.0
    lab = cv2.cvtColor(кадр, cv2.COLOR_BGR2LAB).astype(np.float32)
    L, a, b = lab[:, :, 0], lab[:, :, 1], lab[:, :, 2]
    нас = np.hypot(a - 128.0, b - 128.0)
    сL, снас = float(np.median(L[если])), float(np.median(нас[если]))
    ярко = (если & (L > сL + 22) & (нас < снас * 0.72)).astype(np.uint8)
    n, метки, стат, _ = cv2.connectedComponentsWithStats(ярко, 8)
    площадь = float(если.sum())
    мелкие = np.zeros_like(ярко, bool)
    for i in range(1, n):
        if стат[i, cv2.CC_STAT_AREA] < площадь * 0.005:
            мелкие |= метки == i
    доля = float(мелкие.sum()) / площадь * 100
    if not мелкие.any():
        return кадр, 0.0
    # Чем заменить: кожей вокруг. Медианное размытие берёт соседний тон
    # и не тащит в него сам блик.
    сосед = cv2.medianBlur(кадр, 31)
    return _мягко(кадр, мелкие, сосед, СИЛА_БЛИКА), round(доля, 2)


def снять_крапины(кадр, маска_кожи=None):
    """Убрать тёмные крапины, но ТОЛЬКО там, где их много рядом."""
    кожа = маска_кожи if маска_кожи is not None else _маска_кожи(кадр)
    если = кожа > 0
    if если.mean() < 0.02:
        return кадр, 0.0
    серый = cv2.cvtColor(кадр, cv2.COLOR_BGR2GRAY).astype(np.float32)
    местное = cv2.GaussianBlur(серый, (0, 0), 25)
    тёмные = ((серый - местное) < -25) & если
    n, метки, стат, центры = cv2.connectedComponentsWithStats(
        тёмные.astype(np.uint8), 8)
    площадь = float(если.sum())
    мелкие = [i for i in range(1, n)
              if стат[i, cv2.CC_STAT_AREA] < площадь * 0.0006]
    if not мелкие:
        return кадр, 0.0
    # ГУСТОТА. Настоящая родинка одна на своём клочке кожи, грязь идёт
    # россыпью. Считаем соседей каждой точки в радиусе сорока точек.
    точки = np.array([центры[i] for i in мелкие], np.float32)
    грязь = np.zeros_like(тёмные)
    if len(точки) > СОСЕДЕЙ:
        дер = cv2.flann_Index(точки, {"algorithm": 1, "trees": 4})
        _, дист = дер.knnSearch(точки, СОСЕДЕЙ + 1)
        # Расстояния квадратичные: сорок точек это 1600.
        густо = дист[:, СОСЕДЕЙ] < 40.0 ** 2
        for н, i in enumerate(мелкие):
            if густо[н]:
                грязь |= метки == i
    доля = float(грязь.sum()) / площадь * 100
    if not грязь.any():
        return кадр, 0.0
    сосед = cv2.medianBlur(кадр, 9)
    return _мягко(кадр, грязь, сосед, СИЛА_ТОЧКИ), round(доля, 3)


def почистить(путь, куда=None):
    """Снять блики и крапины. Правит файл на месте, если `куда` не дан."""
    кадр = cv2.imread(путь)
    if кадр is None:
        return None
    кожа = _маска_кожи(кадр)
    кадр, бликов = снять_блики(кадр, кожа)
    кадр, крапин = снять_крапины(кадр, кожа)
    куда = куда or путь
    cv2.imwrite(куда, кадр)
    print(f"ретушь: бликов {бликов} %, крапин {крапин} % площади кожи",
          flush=True)
    return куда


if __name__ == "__main__":
    import sys
    print(почистить(sys.argv[1],
                    sys.argv[2] if len(sys.argv) > 2 else None))
