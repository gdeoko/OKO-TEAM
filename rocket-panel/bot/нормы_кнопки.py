# -*- coding: utf-8 -*-
"""Нормы приёмки, снятые с ПРИНЯТОГО кадра кнопки.

Проверка, которой не было и быть не могло: эталонных кадров в
репозитории не лежало вовсе, и нормы задавались списками руками -
`БЕЗ_ЛИЦА`, `БЕЗ_РУК`, «на паре надо два тела». Кадры нашлись
03.10.2026, и первый же замер показал цену этих списков: приёмка
забраковала бы СЕМЬ из двадцати кадров, которые владелец сам принял и
за которые клиент платит.

    ff_behind    рук в кадре 0, надо хотя бы 2; вывернуты оба колена
    ff_close     лица клиентки некуда ставить
    mf_face      людей в кадре 1, надо 2
    mf_near      голов срезано кромкой: 1
    mf_pov       рук в кадре 1, надо хотя бы 2
    ph_below     вывернуты оба локтя
    un_lie       вывернуто колено слева

Ни одна из этих семи записей не про дефект. На «наезднице» мужчина
под женщиной, и детектор видит одно тело; на «вдвоём раком» руки
скрыты телами; на «минете» руки за кадром; у «секса раком» голова
стоит у самой кромки, потому что так снято; колени на четвереньках
согнуты сильнее, чем порог считает человеческим. Это не брак, а
постановка, которую владелец утвердил.

Браком считается то, что ХУЖЕ принятого кадра, а не то, что
отличается от общего правила. Поэтому нормы снимаются с самого кадра:
сколько тел видит детектор, сколько запястий и щиколоток, стоит ли
голова у кромки, находится ли лицо, какие суставы он называет
вывернутыми. Любая проверка, бракующая принятый кадр, настроена строже,
чем нужно, и каждый её ложный брак стоит ещё одного зерна и ещё
полминуты - при норме владельца в минуту на кадр.

Нормы считаются один раз и лежат в `эталоны/нормы.json`: YOLO с
mediapipe на двадцати кадрах это полторы минуты, и гонять их при
каждом запуске бота нельзя. Кадр изменился - поменялась его сумма, и
нормы пересчитаются сами.
"""
import hashlib
import io
import json
import os

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ФАЙЛ = os.path.join(ЗДЕСЬ, "эталоны", "нормы.json")
_память = {}

# Чего нет в нормах - то берётся отсюда. Кнопка без принятого кадра
# живёт по прежним правилам: лучше общее правило, чем никакого.
ПО_УМОЛЧАНИЮ = {"тел": None, "запястий": None, "щиколоток": None,
                "голов": None, "срез_головы": False, "лицо": True,
                "вывернуто": []}


def _сумма(ф):
    return hashlib.md5(io.open(ф, "rb").read()).hexdigest()[:16]


def _снять(ключ, кадр):
    """Числа принятого кадра глазами наших же проверок."""
    import люди_в_кадре as люди
    import priyomka_kadra as ПК
    import скелеты_кадра
    import сустав_кадра

    р = люди.разбор(кадр)
    ск = скелеты_кадра.с_кадра(кадр)
    return {"тел": р["тел"], "запястий": р["запястий"],
            "щиколоток": р["щиколоток"], "голов": р["голов"],
            "срез_головы": bool(р["срезано_голов"]),
            "лицо": bool(ПК.лицо(кадр)),
            "вывернуто": sorted(set(сустав_кадра.кривые(ск)))}


def _прочесть():
    try:
        return json.load(io.open(ФАЙЛ, encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def нормы(ключ, пересчитать=False):
    """Нормы кнопки. Пусто у кнопки без принятого кадра."""
    import konveyer as К
    import кнопка_сборка as КС

    к = К.короткий(ключ)
    if к in _память and not пересчитать:
        return _память[к]
    ф = os.path.join(КС.ЭТАЛОНЫ, к + ".jpg")
    if not os.path.exists(ф):
        _память[к] = dict(ПО_УМОЛЧАНИЮ)
        return _память[к]
    свод = _прочесть()
    сумма = _сумма(ф)
    з = свод.get(к)
    if пересчитать or not з or з.get("сумма") != сумма:
        import cv2
        н = _снять(к, cv2.imread(ф))
        н["сумма"] = сумма
        свод[к] = н
        try:
            io.open(ФАЙЛ, "w", encoding="utf-8").write(
                json.dumps(свод, ensure_ascii=False, indent=1,
                           sort_keys=True))
        except OSError:
            pass
        з = н
    _память[к] = з
    return з


# НОРМА С КАДРА ТОЛЬКО ОСЛАБЛЯЕТ ТРЕБОВАНИЕ, НИКОГДА НЕ УСИЛИВАЕТ.
# Эталон это один кадр, и его числа местами случайны: на `ff_face`
# детектор насчитал три запястья из четырёх, хотя обе женщины целы.
# Требуй мы «не меньше, чем на эталоне», и приёмка стала бы строже
# прежней там, где эталону просто не повезло с ракурсом. Поэтому
# берётся меньшее из двух: общее правило и то, что видно на принятом
# кадре.


def тел_надо(ключ, по_каталогу):
    """Сколько тел обязано быть видно.

    На парной кнопке их два по смыслу, но видит их детектор, а не
    смысл: на «наезднице» мужчина под женщиной, и тел ровно одно - на
    принятом кадре тоже. Требовать два значит браковать каждый кадр
    этой кнопки до последнего зерна.
    """
    з = нормы(ключ).get("тел")
    return min(по_каталогу, з) if з else по_каталогу


def рук_надо(ключ, по_умолчанию=2):
    """Сколько запястий обязано быть видно, по принятому кадру."""
    з = нормы(ключ).get("запястий")
    return по_умолчанию if з is None else min(по_умолчанию, з)


def срез_головы_можно(ключ):
    """У «секса раком» голова стоит у кромки на самом принятом кадре."""
    return bool(нормы(ключ).get("срез_головы"))


def лицо_надо(ключ):
    """Нет лица на принятом кадре - некуда ставить и в работе."""
    return bool(нормы(ключ).get("лицо", True))


def сустав_свой(ключ, сустав):
    """Детектор называет этот сустав вывернутым и на принятом кадре."""
    return сустав in (нормы(ключ).get("вывернуто") or [])


def пересчитать_все():
    """Пересчёт по всем кнопкам. Зовётся руками после смены кадров."""
    import кнопка_сборка as КС
    из = {}
    for к in sorted(КС.СБОРКА):
        из[к] = нормы(к, пересчитать=True)
    return из


if __name__ == "__main__":
    for к, н in sorted(пересчитать_все().items()):
        print("%-11s тел %s руки %s щик %s голов %s срез %-5s лицо %-5s %s"
              % (к, н["тел"], н["запястий"], н["щиколоток"], н["голов"],
                 н["срез_головы"], н["лицо"],
                 ", ".join(н["вывернуто"]) or "-"))
