# -*- coding: utf-8 -*-
"""Приёмка кадра кнопки: счёт тел и ГЕОМЕТРИЯ касания.

## Зачем ещё одна приёмка

Счёт тел, голов и запястий ловит сросшиеся фигуры и лишних людей, но не
знает, ЧТО в кадре происходит. На `ff_69` счёт был чистый на обоих
зёрнах, а голова лежащей оказывалась у груди вместо паха: по числам
кадр годный, а кнопка показывает не то, что обещала.

Проверяем это скелетом, а не зрением: `yolo11x-pose` даёт у каждого
человека нос, плечи и бёдра. «Рот у паха» - это нос одного ближе к
середине таза другого, чем половина его же торса. Числа взяты от
размера человека В КАДРЕ, поэтому работают и на крупном плане, и на
общем.

Способ бесплатный и мгновенный. Платного судью (`gemini`, `gpt`) мы
пробовали: один отказывается смотреть вовсе, второй говорит «нет» на
верных кадрах, третий «да» на явном браке с четырьмя телами. Доверять
им нельзя, а скелет не врёт.

## Чего приёмка НЕ умеет

Она не видит качества кожи, света и красоты. Это по-прежнему глаз
владельца. Её дело - не пропустить кадр, где обещанного действия нет
вовсе.
"""
import os

import cv2
import numpy as np

import люди_в_кадре as люди

# ПОРОГИ СВОИ У КАЖДОЙ КНОПКИ, И ЭТО НЕ ПРИДИРКА. Расстояние меряется
# от носа до СЕРЕДИНЫ таза, а в позе сзади эта середина далеко от того
# места, куда дотянулись губы: на верном кадре `ph_above` вышло 0.90, и
# общий порог 0.60 забраковал бы годное. Числа сняты с кадров, которые
# владелец принял.
РОТ_У_ПАХА = {"mf_behind": 0.75, "mf_pov": 0.9, "ff_near": 0.75,
              "ff_close": 0.9, "ff_pov": 0.75, "ff_69": 1.3}
РУКА_МЕЖДУ_НОГ = {"ph_close": 0.75, "ph_side": 0.75, "ph_above": 1.1}
ТАЗ_К_ТАЗУ = {"mf_near": 1.0, "mf_face": 1.0}
# Позы, где тела НАРОЧНО перекрываются: счётчик тел сливает их в одно и
# ругается «людей 1». На принятом владельцем кадре `ff_69` он так и
# сделал. Для них счёт тел не проверяем вовсе, только явный перебор.
ПЕРЕКРЫТИЕ = {"ff_69", "mf_behind", "ff_near", "ff_pov", "mf_above",
              "ff_above", "mf_close"}
# «В ЗЕРКАЛЕ»: ОТРАЖЕНИЕ СЧИТАЕТСЯ ВТОРЫМ ЧЕЛОВЕКОМ, И ЭТО ВЕРНО.
# Счётчик видит тело и его отражение как двоих, запястий насчитывает
# четыре, и по общему правилу кадр уходил в брак. На этой кнопке так и
# должно быть: отражение обязано быть в кадре.
ЗЕРКАЛО = {"ph_mirror"}

НОС, ПЛЕЧО_Л, ПЛЕЧО_П = 0, 5, 6
ЗАПЯСТЬЕ_Л, ЗАПЯСТЬЕ_П = 9, 10
БЕДРО_Л, БЕДРО_П = 11, 12
ВИДНО = 0.4


def _точки(кадр):
    """Скелеты людей: список массивов 17x3 в координатах кадра."""
    длинная = max(кадр.shape[:2])
    к = min(1.0, люди.ДЛИННАЯ / float(длинная))
    м = кадр if к == 1.0 else cv2.resize(
        кадр, (int(кадр.shape[1] * к), int(кадр.shape[0] * к)))
    with люди._замок:
        о = люди._модель().predict(м, conf=люди.ПОРОГ, iou=люди.IOU,
                                   verbose=False)[0]
    if о.keypoints is None or not len(о.keypoints.data):
        return []
    итог = []
    for т in о.keypoints.data.cpu().numpy():
        т = т.copy()
        т[:, :2] /= к
        итог.append(т)
    return итог


def _середина(т, а, б):
    if т[а][2] < ВИДНО or т[б][2] < ВИДНО:
        return None
    return np.array([(т[а][0] + т[б][0]) / 2.0, (т[а][1] + т[б][1]) / 2.0])


def _торс(т):
    """Длина торса: мера роста человека В КАДРЕ, а не в сантиметрах."""
    плечи = _середина(т, ПЛЕЧО_Л, ПЛЕЧО_П)
    бёдра = _середина(т, БЕДРО_Л, БЕДРО_П)
    if плечи is None or бёдра is None:
        return None
    д = float(np.linalg.norm(плечи - бёдра))
    return д if д > 1 else None


def рот_у_паха(скелеты, доля=0.75):
    """Есть ли пара, где нос одного у таза другого. (да, расстояние)."""
    лучшее = None
    for i, а in enumerate(скелеты):
        if а[НОС][2] < ВИДНО:
            continue
        нос = np.array([а[НОС][0], а[НОС][1]])
        for j, б in enumerate(скелеты):
            if i == j:
                continue
            таз = _середина(б, БЕДРО_Л, БЕДРО_П)
            торс = _торс(б)
            if таз is None or торс is None:
                continue
            д = float(np.linalg.norm(нос - таз)) / торс
            if лучшее is None or д < лучшее:
                лучшее = д
    if лучшее is None:
        return None, None
    return лучшее <= доля, round(лучшее, 2)


def рука_между_ног(скелеты, доля=0.60):
    """Запястье человека у его же таза."""
    лучшее = None
    for т in скелеты:
        таз = _середина(т, БЕДРО_Л, БЕДРО_П)
        торс = _торс(т)
        if таз is None or торс is None:
            continue
        for з in (ЗАПЯСТЬЕ_Л, ЗАПЯСТЬЕ_П):
            if т[з][2] < ВИДНО:
                continue
            д = float(np.linalg.norm(
                np.array([т[з][0], т[з][1]]) - таз)) / торс
            if лучшее is None or д < лучшее:
                лучшее = д
    if лучшее is None:
        return None, None
    return лучшее <= доля, round(лучшее, 2)


def тазы_рядом(скелеты, доля=1.0):
    """Два таза ближе, чем торс: тела соединены."""
    тазы = [( _середина(т, БЕДРО_Л, БЕДРО_П), _торс(т)) for т in скелеты]
    тазы = [(п, т) for п, т in тазы if п is not None and т]
    if len(тазы) < 2:
        return None, None
    д = float(np.linalg.norm(тазы[0][0] - тазы[1][0]))
    мера = д / max(тазы[0][1], тазы[1][1])
    return мера <= доля, round(мера, 2)


def проверить(кадр, ключ, пара=False):
    """Вердикт по кадру: (годен, список причин, числа).

    Причина «не проверено» не считается браком: скелет не всегда
    находит обе пары бёдер, и забраковать кадр из-за своей слепоты
    хуже, чем пропустить его на глаз владельцу.
    """
    причины, числа = [], {}
    надо = 2 if пара else 1
    if ключ in ЗЕРКАЛО:
        деф, _ = люди.беды(кадр, надо, срез_можно=True, тел_макс=2)
        деф = [д for д in деф if "запястий" not in д and "надо" not in д]
        причины.extend(деф)
        скелеты = _точки(кадр)
        числа["скелетов"] = len(скелеты)
        return (not причины), причины, числа
    if ключ in ПЕРЕКРЫТИЕ:
        # Считаем только перебор: недостача здесь это слепота счётчика.
        деф, _ = люди.беды(кадр, надо, срез_можно=True, тел_макс=надо + 1)
        деф = [д for д in деф if "надо" not in д or "в кадре %d" % (надо + 1)
               in д or "в кадре %d" % (надо + 2) in д]
    else:
        деф, _ = люди.беды(кадр, надо)
    причины.extend(деф)
    скелеты = _точки(кадр)
    числа["скелетов"] = len(скелеты)
    ключ = str(ключ or "")
    if ключ in РОТ_У_ПАХА:
        ок, д = рот_у_паха(скелеты, РОТ_У_ПАХА[ключ])
        числа["рот_у_паха"] = д
        if ок is False:
            причины.append("рот не у паха (%.2f торса)" % д)
    if ключ in РУКА_МЕЖДУ_НОГ:
        ок, д = рука_между_ног(скелеты, РУКА_МЕЖДУ_НОГ[ключ])
        числа["рука_у_паха"] = д
        if ок is False:
            причины.append("рука не между ног (%.2f торса)" % д)
    if ключ in ТАЗ_К_ТАЗУ:
        ок, д = тазы_рядом(скелеты, ТАЗ_К_ТАЗУ[ключ])
        числа["тазы"] = д
        if ок is False:
            причины.append("тела не соединены (%.2f торса)" % д)
    return (not причины), причины, числа
