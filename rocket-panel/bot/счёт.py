"""Оплата счётом через эквайринг: карты, СБП, кошельки.

## Почему это единственный способ платить

Решение владельца 25.09.2026: «у нас не будет оплаты звёздами или ещё
чем-то, у нас будет оплата только через счёт». Звёзды и крипта из меню
убираются, как только эквайринг настроен, - см. `ui.меню_способов`.

Причина не в удобстве. ЗВЁЗДЫ ПРИХОДЯТ ВЛАДЕЛЬЦУ БОТА, а у франшизы
ботов много и владельцы у них разные: деньги за наши генерации
оседали бы у партнёра, и делить их пришлось бы обратным переводом.
Счёт же выставляет НАША касса в любой копии - значит вся выручка
приходит нам, а партнёру уходит его половина. Поэтому же партнёр не
может вывести себе сам: он пишет в поддержку, и выплату делает
владелец руками (`франшиза.py`, правило 8а в памяти проекта).

## Почему конфигурация лежит в ОБЩЕМ окружении

Ключи кассы живут в `/etc/amberry.env`, который читают ВСЕ копии, а
личный файл партнёра (`/etc/amberry/<id>.env`) их не перекрывает и не
имеет права. Так касса переезжает в новую копию сама, в тот же миг,
когда её завели, - владельцу не нужно вписывать ключ в каждого бота.
Проверяется тестом: в личном файле партнёра нет ни одного `AMBERRY_PAY_*`.

## Провайдер за швом

Какой именно эквайринг подключат, на день написания не решено. Поэтому
наружу тут торчат три функции - `настроен`, `выставить`, `состояние`, -
а внутри `_ЮКАССА` знает про ЮKassa, которой холдинг уже пользуется в
другом проекте. Другой провайдер - это ещё одна такая функция и одна
строка в `ПРОВАЙДЕРЫ`; трогать бота при этом не придётся.

## Опросом, а не вебхуком

Тем же способом, что и крипта: человек жмёт «я оплатил», мы
спрашиваем кассу. Вебхук требует открытого наружу адреса и проверки
подписи, а главное - он молчит, когда что-то сломалось, и деньги
зависают без единой записи. Опрос отвечает всегда и повторяется
столько раз, сколько человек нажмёт.
"""

import base64
import json
import os
import urllib.error
import urllib.request
import uuid


class ОшибкаОплаты(Exception):
    pass


ПРОВАЙДЕР = os.environ.get("AMBERRY_PAY_PROVIDER", "yookassa").strip().lower()
МАГАЗИН = os.environ.get("AMBERRY_PAY_SHOP", "").strip()
КЛЮЧ = os.environ.get("AMBERRY_PAY_SECRET", "").strip()
# Куда касса вернёт человека после оплаты. Пусто - вернётся в бота.
ВОЗВРАТ = os.environ.get("AMBERRY_PAY_RETURN", "").strip()


def настроен():
    """Есть ли касса. Пусто - бот показывает прежние способы оплаты.

    Отдельной функцией, потому что от этого ответа зависит, что
    человек увидит в меню, и проверять его будут из трёх мест.
    """
    return bool(МАГАЗИН and КЛЮЧ and ПРОВАЙДЕР in ПРОВАЙДЕРЫ)


def _зов(адрес, данные=None, заголовки=None, метод=None):
    тело = json.dumps(данные).encode() if данные is not None else None
    з = {"Content-Type": "application/json", **(заголовки or {})}
    зпр = urllib.request.Request(адрес, data=тело, headers=з, method=метод)
    try:
        with urllib.request.urlopen(зпр, timeout=30) as о:
            return json.load(о)
    except urllib.error.HTTPError as e:
        # Текст кассы нужен целиком: «нет денег на счёте» и «неверный
        # ключ» разбираются по-разному, а код у них один.
        подробно = e.read().decode("utf-8", "replace")[:300]
        raise ОшибкаОплаты(f"касса ответила {e.code}: {подробно}")
    except Exception as e:                              # noqa: BLE001
        raise ОшибкаОплаты(f"не дозвонились до кассы: {str(e)[:120]}")


# --- ЮKassa -----------------------------------------------------------
# Холдинг уже работает с ней в другом проекте, поэтому она и взята
# первой. Идемпотентность обязательна: касса требует ключ на каждый
# создаваемый платёж, иначе повтор запроса создаёт ВТОРОЙ платёж, и
# человек платит дважды.

_ЮКАССА_API = "https://api.yookassa.ru/v3"


def _юкасса_заголовки(идемпотентность=None):
    ключ = base64.b64encode(f"{МАГАЗИН}:{КЛЮЧ}".encode()).decode()
    з = {"Authorization": "Basic " + ключ}
    if идемпотентность:
        з["Idempotence-Key"] = идемпотентность
    return з


def _юкасса_выставить(рублей, описание, назначение, возврат):
    о = _зов(_ЮКАССА_API + "/payments", {
        "amount": {"value": "%.2f" % рублей, "currency": "RUB"},
        "capture": True,
        "confirmation": {"type": "redirect", "return_url": возврат},
        "description": описание[:128],
        "metadata": {"назначение": назначение},
    }, _юкасса_заголовки(str(uuid.uuid4())))
    адрес = (о.get("confirmation") or {}).get("confirmation_url")
    if not адрес:
        raise ОшибкаОплаты("касса не дала ссылку на оплату")
    return {"url": адрес, "invoice_id": о["id"]}


def _юкасса_состояние(ид):
    о = _зов(f"{_ЮКАССА_API}/payments/{ид}", None, _юкасса_заголовки())
    # succeeded - деньги у нас. pending - человек ещё платит.
    # canceled - отменён. waiting_for_capture у нас не бывает: платим
    # с capture=True, то есть списываем сразу.
    return {"succeeded": "оплачен", "pending": "ждём",
            "canceled": "отменён"}.get(о.get("status"), "ждём")


ПРОВАЙДЕРЫ = {"yookassa": (_юкасса_выставить, _юкасса_состояние)}


def выставить(рублей, описание, назначение, вернуть_в=""):
    """Счёт на оплату. Возвращает {'url', 'invoice_id'}.

    `назначение` - наш payload: что человек покупает. Он же приезжает
    обратно в метаданных платежа, и по нему зачисляется купленное.
    """
    if not настроен():
        raise ОшибкаОплаты("касса не подключена")
    рублей = float(рублей)
    if рублей <= 0:
        raise ОшибкаОплаты("сумма должна быть больше нуля")
    выставить_, _ = ПРОВАЙДЕРЫ[ПРОВАЙДЕР]
    return выставить_(рублей, описание, назначение,
                      вернуть_в or ВОЗВРАТ or "https://t.me")


def состояние(invoice_id):
    """«оплачен» | «ждём» | «отменён»."""
    if not настроен():
        raise ОшибкаОплаты("касса не подключена")
    _, состояние_ = ПРОВАЙДЕРЫ[ПРОВАЙДЕР]
    return состояние_(str(invoice_id))
