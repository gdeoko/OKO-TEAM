# -*- coding: utf-8 -*-
"""Светлый контур по границе карты глубины: след сильного ControlNet.

На `mf_face` вышел кадр, обведённый светлой каймой ровно по силуэту
карты: модель при большом весе гайда следует ей буквально, и граница
маски проступает в кадре линией. Приёмка по телам и конечностям этого
не видит вовсе - анатомия там целая, - а клиентка видит в первую
очередь: кадр выглядит аппликацией, вырезанной ножницами.

Ловится сравнением двух полос ВДОЛЬ границы силуэта: узкой по самой
границе и широкой рядом с ней. Ореол это систематическое превышение
яркости на границе, одинаковое по всему контуру, поэтому берётся
медиана, а не среднее: блик на коже задерёт среднее в одном месте, а
медиану сдвинет только настоящая кайма вдоль всего контура.
"""
import os

import cv2
import konveyer as К
import numpy as np

ПОРОГ = float(os.environ.get("OKO_KAJMA_POROG", "6.0"))
_карты = {}


def _граница(ключ, ш, в, как="верт"):
    """Полоса по контуру силуэта карты и полоса рядом с ней."""
    клч = (К.короткий(ключ), ш, в, как)
    if клч in _карты:
        return _карты[клч]
    г = cv2.imread(os.path.join(К.ГАЙДЫ, К.короткий(ключ) + ".jpg"),
                   cv2.IMREAD_GRAYSCALE)
    if г is None:
        _карты[клч] = (None, None)
        return _карты[клч]
    if как == "гориз_поля":
        к = int(г.shape[1] * в / г.shape[0])
        поле = np.zeros((в, ш), np.uint8)
        м = cv2.resize(г, (к, в))
        x = max(0, (ш - к) // 2)
        поле[:, x:x + min(к, ш)] = м[:, :min(к, ш)]
        г = поле
    else:
        г = cv2.resize(г, (ш, в))
    _, б = cv2.threshold(г, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)
    контур = cv2.morphologyEx(б, cv2.MORPH_GRADIENT, np.ones((3, 3), np.uint8))
    узкая = cv2.dilate(контур, np.ones((5, 5), np.uint8)) > 0
    широкая = (cv2.dilate(контур, np.ones((23, 23), np.uint8)) > 0) & ~узкая
    _карты[клч] = (узкая, широкая)
    return _карты[клч]


def сила(кадр, ключ, как="верт"):
    """Насколько кайма вдоль границы светлее соседней кожи."""
    узкая, широкая = _граница(ключ, кадр.shape[1], кадр.shape[0], как)
    if узкая is None or узкая.sum() < 200 or широкая.sum() < 200:
        return 0.0
    сер = cv2.cvtColor(кадр, cv2.COLOR_BGR2GRAY).astype(np.float32)
    return float(np.median(сер[узкая]) - np.median(сер[широкая]))


def есть(кадр, ключ, как="верт", порог=None):
    return сила(кадр, ключ, как) >= (ПОРОГ if порог is None else порог)
