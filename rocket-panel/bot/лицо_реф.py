# -*- coding: utf-8 -*-
"""Плотный кроп лица вторым референсом. Это и есть «лицо 1:1».

## Почему без этого лицо не совпадает никогда

Узел `TextEncodeQwenImageEditPlus` режет каждый входной снимок до
384 на 384 пикселей СУММАРНО - столько видит текстовый энкодер
Qwen2.5-VL (исходник ComfyUI, `comfy_extras/nodes_qwen.py`:
`total = int(384 * 384)`).

Портретный кадр 768 на 1344 после такой обрезки становится примерно
290 на 508. Лицо человека, снятого в полный рост, занимает в нём около
тридцати пикселей по ширине. Тридцать пикселей это не лицо, это пятно,
и совпасть с референсом оно не может ни при каком промпте. Замер
28.09.2026 показывал сходство 0.44-0.56 при пороге узнавания 0.62.

Лечится это не моделью, а входом: ВТОРЫМ снимком идёт плотный кроп
лица, и весь бюджет 384 на 384 у этого слота уходит на одно лицо.
Разница в подробности выходит примерно в десять раз по площади.

Слот есть: панель принимает до трёх снимков (`MAX_REF`), а боевой путь
шлёт один.

    from лицо_реф import кроп_лица
    файл = кроп_лица("/путь/фото.jpg")     # None, если лица нет
"""

import os

import cv2

# Запас вокруг лица. Одно лицо без шеи и волос модель читает хуже:
# ей нужны линия челюсти, уши и начало волос, чтобы понять форму
# головы, а не только черты.
ЗАПАС = 1.6

# Сторона кроп-кадра. Больше 768 смысла нет: энкодер всё равно ужмёт
# до 384 на 384, а лишние пиксели это только вес файла и время
# передачи.
СТОРОНА = 768

_лица = None


def _модель():
    """InsightFace на процессоре. Та же, что в заслоне возраста."""
    global _лица
    if _лица is None:
        from insightface.app import FaceAnalysis
        _лица = FaceAnalysis(name="buffalo_l",
                             providers=["CPUExecutionProvider"])
        _лица.prepare(ctx_id=-1, det_size=(640, 640))
    return _лица


def найти(кадр):
    """Рамка самого крупного лица (x1, y1, x2, y2) или None.

    Самого крупного, а не первого: на снимке бывает второй человек на
    заднем плане, и вырезать надо героя, а не прохожего.
    """
    try:
        найдено = _модель().get(кадр)
    except Exception as e:                                  # noqa: BLE001
        print("детектор лиц не поднялся:", str(e)[:120], flush=True)
        return None
    if не_пусто := найдено:
        л = max(не_пусто, key=lambda f: (f.bbox[2] - f.bbox[0])
                * (f.bbox[3] - f.bbox[1]))
        return [float(v) for v in л.bbox]
    return None


def все(кадр, мельче=0.02):
    """ВСЕ лица кадра, крупные первыми: рамка, пол, возраст, вектор.

    Нужно парным сценам. `найти` отдаёт одно самое крупное лицо, и на
    сцене МЖ этого хватает ровно на одного человека: второй оставался
    без пересчёта, отчего у него плыло лицо и путались гениталии.

    Мелочь отсеивается по доле высоты кадра: на заднем плане у модели
    регулярно всплывает лицо-призрак в отражении или в узоре обоев, и
    считать его за человека значит пересчитать кусок стены.

    Пол берётся у самой InsightFace (`sex`, 'M' или 'F'). Он не
    безупречен, но на сцене МЖ ошибиться ему трудно: у двух лиц он
    сравнивает их между собой, а не с абсолютной шкалой.
    """
    try:
        найдено = _модель().get(кадр)
    except Exception as e:                                  # noqa: BLE001
        print("детектор лиц не поднялся:", str(e)[:120], flush=True)
        return []
    h = кадр.shape[0]
    люди = []
    for л in найдено or []:
        x1, y1, x2, y2 = (float(v) for v in л.bbox)
        if (y2 - y1) < h * мельче:
            continue
        люди.append({
            "рамка": [x1, y1, x2, y2],
            "высота": y2 - y1,
            "пол": getattr(л, "sex", None) or "?",
            "возраст": int(getattr(л, "age", 0) or 0),
            "вектор": getattr(л, "normed_embedding", None),
        })
    люди.sort(key=lambda ч: -ч["высота"])
    return люди


def вектор(путь):
    """Вектор лица со СНИМКА - чтобы сличать кадр с референсом."""
    кадр = cv2.imread(путь)
    if кадр is None:
        return None
    люди = все(кадр)
    return люди[0]["вектор"] if люди else None


def кроп_лица(путь, куда=None, сторона=СТОРОНА, запас=ЗАПАС):
    """Вырезать лицо с запасом и сохранить квадратом. Путь или None.

    Квадратом, потому что энкодер ужимает по площади: вытянутый кроп
    потерял бы часть бюджета на пустоту сверху и снизу.
    """
    кадр = cv2.imread(путь)
    if кадр is None:
        return None
    рамка = найти(кадр)
    if not рамка:
        return None
    x1, y1, x2, y2 = рамка
    cx, cy = (x1 + x2) / 2, (y1 + y2) / 2
    # Квадрат по большей стороне лица, чтобы пропорции не поехали.
    бок = max(x2 - x1, y2 - y1) * запас
    h, w = кадр.shape[:2]
    # Кроп у края кадра сдвигается внутрь, а не обрезается: срезанный
    # подбородок модель понимает как форму лица.
    л = int(max(0, min(w - бок, cx - бок / 2)))
    в = int(max(0, min(h - бок, cy - бок / 2)))
    бок = int(min(бок, w, h))
    кусок = кадр[в:в + бок, л:л + бок]
    if кусок.size == 0 or бок < 48:
        return None
    # Увеличиваем кубической: кроп бывает мельче цели, а INTER_AREA
    # умеет только уменьшать и на увеличении даёт ступеньки.
    сп = cv2.INTER_AREA if бок > сторона else cv2.INTER_CUBIC
    кусок = cv2.resize(кусок, (сторона, сторона), interpolation=сп)
    куда = куда or os.path.splitext(путь)[0] + ".лицо.jpg"
    cv2.imwrite(куда, кусок, [cv2.IMWRITE_JPEG_QUALITY, 96])
    return куда


def доля_лица(путь):
    """Какую долю высоты кадра занимает лицо. Для журнала и порогов."""
    кадр = cv2.imread(путь)
    if кадр is None:
        return None
    рамка = найти(кадр)
    if not рамка:
        return None
    return round((рамка[3] - рамка[1]) / кадр.shape[0] * 100, 1)


if __name__ == "__main__":
    import sys
    для = sys.argv[1]
    print(кроп_лица(для) or "лица не нашлось",
          "| доля лица в кадре:", доля_лица(для), "%")
