"""Правки прайса владельцем: цены пакетов и цены видов работ.

## Зачем отдельный файл, а не правка кода

Цены — это то, что владелец меняет чаще всего и всегда срочно: увидел
конверсию, подвинул ступень, посмотрел снова. Через код это значит
правку, коммит, выкладку и перезапуск бота — то есть полчаса и чужие
руки. Через файл это значит кнопку в админке.

Устроено ровно как у каталога (`данные.py`): в коде лежит НАБОР ПО
УМОЛЧАНИЮ, в файле — только то, что владелец изменил. Поэтому новая
ступень, заведённая в коде, доезжает до работающего бота, а не
затирается вчерашним снимком прайса.

## Правки накладываются НА МЕСТЕ

`pricing.JOBS` и `pricing.PACKS` разошлись по всему коду: их держит
интерфейс, сводка, админка, расчёт маржи. Поэтому правка не создаёт
новые объекты, а меняет СТАРЫЕ — те самые, на которые все уже смотрят.
Иначе половина бота считала бы по новой цене, а половина по старой, и
разошлись бы они молча.

## Что правится, а что нет

Правится: цена в кристаллах, название, подпись, в продаже или нет,
сколько снимков просить. Цена пакета в рублях, сколько коинов даёт,
цена у конкурента (нужна для честной пометки «дешевле рынка»).

НЕ правится: секунды карты. Это замер, а не решение — он нужен для
расчёта себестоимости, и выдуманное число сделало бы расчёт маржи
враньём, которое выглядит как правда.

## Удалять вид работ нельзя, и это не упрямство

У снятого с продажи вида остаётся история: `store.works` спрашивает у
прайса заголовок по ключу, и стёртый вид уронил бы «Мои работы» на
первой же прошлой генерации. Поэтому вид СНИМАЕТСЯ С ПРОДАЖИ — кнопки
нет, цена и название живут. Пакет удалить можно: он ничего не держит.
"""
import json
import os
import tempfile

ФАЙЛ = os.environ.get("ROCKET_PRICE_FILE", "/srv/amberry/прайс.json")

# Поля вида работ, которые владелец вправе менять. Всё остальное —
# свойство модели или замер, и в правку не берётся.
ПОЛЯ_ВИДА = ("title", "crystals", "note", "в_продаже", "фото_нужно")
ПОЛЯ_ПАКЕТА = ("id", "coins", "rub", "market_rub")


def загрузить(путь=None):
    """{"виды": {...}, "пакеты": [...]}. Нет файла — пусто."""
    try:
        with open(путь or ФАЙЛ, encoding="utf-8") as ф:
            д = json.load(ф)
    except (OSError, ValueError):
        return {}
    if not isinstance(д, dict):
        return {}
    виды = д.get("виды")
    пакеты = д.get("пакеты")
    из = {}
    if isinstance(виды, dict):
        из["виды"] = {str(к): в for к, в in виды.items() if isinstance(в, dict)}
    if isinstance(пакеты, list):
        из["пакеты"] = [п for п in пакеты if isinstance(п, dict) and п.get("id")]
    return из


def сохранить(правки, путь=None):
    """Записать ЦЕЛИКОМ и одним движением.

    Бот перечитывает файл на ходу и не должен застать половину: через
    временный файл и `os.replace`, который на одной файловой системе
    атомарен.
    """
    п = путь or ФАЙЛ
    папка = os.path.dirname(п)
    if папка:
        os.makedirs(папка, exist_ok=True)
    ф = tempfile.NamedTemporaryFile(
        "w", encoding="utf-8", dir=папка or ".", delete=False, suffix=".новый")
    try:
        json.dump(правки or {}, ф, ensure_ascii=False, indent=1)
        ф.close()
        os.replace(ф.name, п)
    except BaseException:
        try:
            os.unlink(ф.name)
        except OSError:
            pass
        raise
    return загрузить(п)


def метка(путь=None):
    """Отпечаток файла: по нему видно, что его правили."""
    try:
        st = os.stat(путь or ФАЙЛ)
    except OSError:
        return None
    return (st.st_mtime_ns, st.st_size)
