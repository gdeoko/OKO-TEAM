# -*- coding: utf-8 -*-
"""Сколько в кадре людей и целы ли у них конечности.

Правило написано ценой трёх неверных измерителей, и каждый отвечал
«чисто» ровно на тех кадрах, которые владелец вернул.

  маска силуэта   сливала соприкасающиеся тела в одну фигуру: на парной
                  кнопке тела соприкасаются ВСЕГДА, и кадр с тремя
                  людьми читался как кадр с одним.
  счёт лиц        ловил лишнего человека, но терял отвёрнутого: лицо
                  вниз или затылком детектор не видит вовсе.
  коробки YOLO    на переплетённых телах вторую коробку подавляет NMS,
                  и счёт прыгал с единицы на тройку от порога.

Держит приёмку `yolo11x-pose`: он ищет СКЕЛЕТ, и два тесно лежащих тела
различает по ключевым точкам, а не по рамке. Замер на десяти кадрах с
известным глазу ответом: девять из десяти, и ответ НЕ МЕНЯЕТСЯ при
пороге от 0.2 до 0.4 - у прежних мерил он прыгал втрое.

Лишняя рука ловится третьим запястьем: сколько бы тел ни соприкасалось,
запястий не бывает больше двух на человека.

Берётся САМАЯ ТЯЖЁЛАЯ модель, и это замерено: `yolo11m` отвечает втрое
быстрее (0.18 с против 0.57), но расходится с ней на двенадцати кадрах
из шестидесяти. Полсекунды на кадр дешевле, чем каждый пятый кадр с
пропущенным дефектом.
"""
import os
import threading

import numpy as np

_поза = None
_замок = threading.Lock()
ПОРОГ = float(os.environ.get("OKO_YOLO_ПОРОГ", "0.30"))
IOU = float(os.environ.get("OKO_YOLO_IOU", "0.5"))
ВИДНО = 0.5                       # уверенность ключевой точки
ЗАПЯСТЬЯ = (9, 10)
ЩИКОЛОТКИ = (15, 16)
ГОЛОВА = (0, 1, 2, 3, 4)          # нос, глаза, уши
МОДЕЛЬ = os.environ.get("OKO_YOLO_МОДЕЛЬ", "yolo11x-pose.pt")
# Кадр ужимается до этой длинной стороны ПЕРЕД разбором. Полный кадр
# 1216x832 держал столько памяти, что разбор пачки умирал молча на
# середине, а ответ от уменьшения не менялся: скелет ищется по фигуре,
# а не по порам кожи. Координаты возвращаются в долях кадра, поэтому
# уменьшение на выводы не влияет.
ДЛИННАЯ = int(os.environ.get("OKO_YOLO_СТОРОНА", "1024"))


def _модель():
    global _поза
    if _поза is None:
        from ultralytics import YOLO
        _поза = YOLO(МОДЕЛЬ)
    return _поза


def разбор(кадр):
    """Тела, запястья, щиколотки, головы и сколько из них срезано."""
    длинная = max(кадр.shape[:2])
    if длинная > ДЛИННАЯ:
        к = ДЛИННАЯ / float(длинная)
        import cv2 as _cv
        кадр = _cv.resize(кадр, (int(кадр.shape[1] * к),
                                 int(кадр.shape[0] * к)))
    with _замок:
        о = _модель().predict(кадр, conf=ПОРОГ, iou=IOU, verbose=False)[0]
    В = кадр.shape[0]
    тел = int(len(о.boxes)) if о.boxes is not None else 0
    зап = щик = голов = срез = 0
    точки = о.keypoints.data if о.keypoints is not None else []
    for т in точки:
        т = т.cpu().numpy() if hasattr(т, "cpu") else np.asarray(т)
        зап += sum(1 for и in ЗАПЯСТЬЯ if т[и][2] > ВИДНО)
        щик += sum(1 for и in ЩИКОЛОТКИ if т[и][2] > ВИДНО)
        верх = [т[и][1] for и in ГОЛОВА if т[и][2] > ВИДНО]
        if верх:
            голов += 1
            # Темя у самой кромки означает, что макушка осталась за
            # кадром: два процента высоты это и есть «впритык».
            if min(верх) < В * 0.02:
                срез += 1
    return {"тел": тел, "запястий": зап, "щиколоток": щик,
            "голов": голов, "срезано_голов": срез}


def беды(кадр, надо, голов_надо=None):
    """Дефекты кадра словами. Пусто - кадр принят."""
    р = разбор(кадр)
    из = []
    if р["тел"] != надо:
        из.append("людей в кадре %d, надо %d" % (р["тел"], надо))
    if р["запястий"] > надо * 2:
        из.append("запястий %d, надо не больше %d" % (р["запястий"], надо * 2))
    if р["щиколоток"] > надо * 2:
        из.append("щиколоток %d, надо не больше %d"
                  % (р["щиколоток"], надо * 2))
    if р["срезано_голов"]:
        из.append("голов срезано кромкой: %d" % р["срезано_голов"])
    if голов_надо is not None and р["голов"] < голов_надо:
        из.append("лиц видно %d, надо %d" % (р["голов"], голов_надо))
    return из, р
