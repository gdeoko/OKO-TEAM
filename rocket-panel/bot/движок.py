"""Чем считаем: APIMODELS или своя видеокарта.

## Почему переключатель, а не замена

Боевой движок с 01.10.2026 — API: считает сразу, параллельно, без
очереди и без подъёма карты. Карта остаётся на запас — на случай, когда
на счёте API кончились деньги или модель отказывается считать
откровенную кнопку. Решение владельца; переключается в админке и
командой `/движок` в боте, без перевыкладки.

## Как подмена ничего не ломает

`Выбор` отвечает на те же вызовы, что `gpu.Gpu`, и просто передаёт их
выбранному движку. В боте остаётся один объект `gpu` и те же тридцать
обращений к нему.

## ДВИЖОК ДЕРЖИТСЯ НА ВСЁ ЗАДАНИЕ, И ЭТО ГЛАВНОЕ ЗДЕСЬ

Снимки, номер задания и готовый файл живут внутри одного движка:
имя, выданное картой, для API ничего не значит, и наоборот. Поэтому
движок выбирается РАЗ в начале задания (`выбрать`) и хранится в потоке
до конца (`отпустить`) — ровно там же, где карта уже выбирала себя из
нескольких (`gpu.выбрать`). Читать настройку перед каждым вызовом
нельзя: владелец щёлкнет тумблером посреди чужой генерации, и половина
задания уйдёт в другой движок — человек получит осечку за свои деньги.
"""

import os
import threading
import time

from gpu import GpuError                                   # noqa: F401

КЛЮЧ = "движок"                     # имя настройки в базе
ПО_УМОЛЧАНИЮ = os.environ.get("ROCKET_ENGINE", "api")
ЗНАЧЕНИЯ = ("api", "карта")

# Сколько секунд верим прочитанной настройке. Нужна не скорость, а
# тишина в журнале: без этого один запрос к базе приходился бы на каждое
# обращение к движку, а их в задании десятки.
НАСТРОЙКА_ЖИВЁТ = 5


class Выбор:
    def __init__(self, карта, апи, store=None):
        self.карта = карта
        self.апи = апи
        self.store = store
        self._поток = threading.local()
        self._кэш = (None, 0.0)

    # ---------- кто считает ----------

    def желание(self):
        """Что выбрано владельцем: 'api' или 'карта'."""
        знач, когда = self._кэш
        if знач and time.time() - когда < НАСТРОЙКА_ЖИВЁТ:
            return знач
        знач = ПО_УМОЛЧАНИЮ
        if self.store is not None:
            try:
                знач = (self.store.настройка(КЛЮЧ, ПО_УМОЛЧАНИЮ)
                        or ПО_УМОЛЧАНИЮ)
            except Exception:                               # noqa: BLE001
                знач = ПО_УМОЛЧАНИЮ
        знач = знач if знач in ЗНАЧЕНИЯ else ПО_УМОЛЧАНИЮ
        self._кэш = (знач, time.time())
        return знач

    def записать(self, знач):
        """Переключить движок. Возвращает, что получилось."""
        знач = знач if знач in ЗНАЧЕНИЯ else ПО_УМОЛЧАНИЮ
        if self.store is not None:
            self.store.настройка_записать(КЛЮЧ, знач)
        self._кэш = (знач, time.time())
        return знач

    def _кем(self):
        """Движок на СЕЙЧАС: выбранный в задании или по настройке.

        Запас включается сам ровно в двух случаях, и оба про «нечем
        считать», а не про «плохо получилось»: движка нет в настройках
        вовсе или на счёте API не осталось денег. Качество кадра
        движками не подменяется — это решение владельца, не программы.
        """
        свой = getattr(self._поток, "движок", None)
        if свой is not None:
            return свой
        if self.желание() == "карта":
            return self.карта if self.карта.настроена else self.апи
        if not self.апи.настроена:
            return self.карта
        return self.апи if self.апи.alive() else self.карта

    def на_карте(self):
        """Это задание считает карта. Доработки, которые живут только на
        ней (восстановитель лица, тело от SDXL, правка по маске), бот
        зовёт только когда это правда."""
        return self._кем() is self.карта

    def имя(self):
        return "карта" if self.на_карте() else "api"

    # ---------- то же, что у карты ----------

    def выбрать(self, род=None):
        движок = self._кем()
        self._поток.движок = движок
        try:
            return движок.выбрать(род)
        except TypeError:
            return движок.выбрать()

    def отпустить(self):
        движок = getattr(self._поток, "движок", None)
        self._поток.движок = None
        if движок is not None:
            движок.отпустить()

    @property
    def настроена(self):
        return bool(self.апи.настроена or self.карта.настроена)

    @property
    def base(self):
        return self._кем().base

    def карты(self):
        return self._кем().карты()

    def alive(self):
        return self._кем().alive()

    def free_vram(self):
        return self._кем().free_vram()

    def upload(self, filename, content):
        return self._кем().upload(filename, content)

    def start(self, **params):
        return self._кем().start(**params)

    def poll(self, job_id):
        return self._кем().poll(job_id)

    def wait(self, job_id, limit=900, on_tick=None):
        return self._кем().wait(job_id, limit=limit, on_tick=on_tick)

    def fetch(self, filename):
        return self._кем().fetch(filename)

    def лицо(self, filename, content, сила=0.5):
        return self._кем().лицо(filename, content, сила)

    def тело(self, filename, content, кожа=None, зоны=None, сзади=False,
             пара=False):
        return self._кем().тело(filename, content, кожа=кожа, зоны=зоны,
                                сзади=сзади, пара=пара)
