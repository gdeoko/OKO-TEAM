"""Архив работ: всё сгенерированное остаётся у нас.

## Зачем это отдельный модуль

Без архива «Мои работы» показывать нечего, и восстановить задним числом
нельзя вовсе — ни одним способом:

  * видеокарта арендуется почасово, её диск стирается при возврате;
  * в базе лежало только ИМЯ файла на карте — после возврата оно
    указывает в никуда;
  * телеграм отдаёт файл по `file_id`, но и его мы нигде не держали.

То есть каждая генерация, отправленная человеку до этого модуля,
потеряна безвозвратно. Поэтому архив заводится ДО запуска, а не «когда
понадобится».

## Два адреса одного результата

  * **файл на нашем диске** — то, чем мы владеем. Переживёт возврат
    видеокарты, смену хостера и капризы телеграма. Это и есть то
    хранилище, ради которого куплен отдельный сервер.
  * **telegram file_id** — им переслать работу человеку стоит ноль:
    файл уже лежит у телеграма, второй раз заливать не нужно.

Показываем по `file_id`, на диск опираемся, когда телеграм файл забыл.
Один без другого не годится: только диск — каждый показ это лишняя
заливка мегабайтов; только file_id — работа живёт у чужой стороны,
которая нам ничего не должна.

## Раскладка

    <корень>/<tg_id>/<job_id>.<расширение>

На человека — своя папка: так удаление по просьбе «сотрите мои работы»
это удаление одной папки, а не выборка по всей куче.
"""

import os
import re
import shutil

# Корень архива. На сервере — рядом с базой, на своём диске.
КОРЕНЬ = os.environ.get("AMBERRY_WORKS_DIR", "data/works")

# Что вообще может прийти с панели. Список закрытый: имя файла приходит
# с чужой стороны, и расширение из него — единственное, что попадает в
# путь на диске. Открытый список означал бы «запиши что угодно куда
# угодно», стоит панели отдать имя с точкой в неожиданном месте.
РАСШИРЕНИЯ = {".png", ".jpg", ".jpeg", ".webp", ".gif", ".mp4", ".webm"}
ПО_УМОЛЧАНИЮ = ".bin"

_ЧИСТО = re.compile(r"[^A-Za-z0-9_-]")


def расширение(имя):
    """Расширение из имени файла — только из белого списка."""
    точка = os.path.splitext(имя or "")[1].lower()
    return точка if точка in РАСШИРЕНИЯ else ПО_УМОЛЧАНИЮ


def путь_для(tg_id, job_id, имя):
    """Куда ляжет результат. Оба ключа чистятся: tg_id приходит от
    телеграма, job_id наш, но путь собирается из них обоих, и «..»
    в любом из них увело бы запись за пределы архива."""
    ч = f"{int(tg_id)}"
    з = _ЧИСТО.sub("", str(job_id))[:64] or "noid"
    return os.path.join(ч, з + расширение(имя))


def сохранить(tg_id, job_id, имя, данные):
    """Кладёт байты в архив и отдаёт путь ОТНОСИТЕЛЬНО корня.

    Относительный — чтобы запись в базе пережила переезд архива на
    другой диск или другой сервер: меняется только `AMBERRY_WORKS_DIR`.
    """
    отн = путь_для(tg_id, job_id, имя)
    полный = os.path.join(КОРЕНЬ, отн)
    os.makedirs(os.path.dirname(полный), exist_ok=True)
    # Пишем через временный файл: оборванная запись не должна оставить
    # обрезанный файл, который потом молча отдадут человеку как работу.
    врем = полный + ".part"
    with open(врем, "wb") as f:
        f.write(данные)
    os.replace(врем, полный)
    return отн


def байты(отн):
    """Содержимое работы или None, если файла нет. None — не ошибка:
    архив могли почистить, а показать в таком случае всё равно есть что
    (file_id у телеграма)."""
    if not отн:
        return None
    полный = os.path.join(КОРЕНЬ, отн)
    try:
        with open(полный, "rb") as f:
            return f.read()
    except OSError:
        return None


def есть(отн):
    return bool(отн) and os.path.exists(os.path.join(КОРЕНЬ, отн))


def забыть_человека(tg_id):
    """Удаляет папку человека целиком — на просьбу «сотрите мои работы».
    Возвращает, было ли что удалять."""
    п = os.path.join(КОРЕНЬ, f"{int(tg_id)}")
    if not os.path.isdir(п):
        return False
    shutil.rmtree(п)
    return True


def место():
    """Сколько архив занимает и сколько осталось на диске, в байтах.

    Нужно не для красоты: архив растёт без потолка, а когда диск
    кончается, SQLite перестаёт писать — встаёт весь бот, не только
    «Мои работы»."""
    занято = 0
    for корень, _, файлы in os.walk(КОРЕНЬ):
        for ф in файлы:
            try:
                занято += os.path.getsize(os.path.join(корень, ф))
            except OSError:
                pass
    try:
        st = os.statvfs(КОРЕНЬ if os.path.isdir(КОРЕНЬ) else ".")
        свободно = st.f_bavail * st.f_frsize
    except OSError:
        свободно = None
    return {"занято": занято, "свободно": свободно}
