"""Что владелец меняет сам: названия кнопок и откровенные строки.

## Почему отдельно от кода

Каталог состоит из двух слоёв, и у них разные хозяева.

  * КОД держит то, что делает кадр рабочим: сохранение лица, кожу,
    анатомию, поведение ткани, свет, объектив, композицию, запреты.
    Три с лишним тысячи знаков на сценарий, одинаково для всех.
  * ВЛАДЕЛЕЦ держит две вещи на сценарий: как кнопка называется и что
    происходит в кадре.

Раньше второй слой лежал в `ОТКРОВЕННОЕ.txt` и правился в блокноте.
Теперь он в JSON и правится страницей в браузере — потому что правок
будет много, а лезть на сервер ради строки текста неправильно.

## Формат

    {"un_close": {"название": "...", "строка": "...", "строка_рус": "..."},
     ...}

`строка` уходит МОДЕЛИ и обязана быть по-английски: модели обучены на
нём, русский даёт мусор — причём молча, на готовой картинке, когда
коины уже списаны. `строка_рус` показывается ЧЕЛОВЕКУ на экране
сценария до оплаты, чтобы он понимал, за что платит.

Пусто — не поломка: сценарий соберётся и покажет героиню в заданном
ракурсе, просто без явного действия.

## Почему JSON, а не база

Этот файл правит человек и читает человек. Его надо уметь открыть
глазами, скопировать, положить в git (без строк) и восстановить из
копии. Таблица в SQLite всё это усложняет ради выигрыша, которого на
сорока записях не существует.
"""

import json
import os
import tempfile

ПАПКА = os.environ.get("AMBERRY_DATA_DIR",
                       os.path.dirname(os.path.abspath(__file__)))
ФАЙЛ = os.path.join(ПАПКА, "каталог.json")

# Что владелец может менять у сценария. Список закрытый: страница
# редактирования шлёт JSON, и принимать оттуда произвольные ключи
# означало бы позволить ей переписать что угодно.
#
# ДВЕ СТРОКИ НА СЦЕНАРИЙ, и это решение владельца 21.09.2026 — после
# того, как полей стало пять и карточка перестала помещаться в экран
# телефона:
#
#   строка_рус — что происходит, по-русски. Видит РУССКИЙ клиент.
#   строка     — то же по-английски. Видит МОДЕЛЬ, и она же
#                показывается АНГЛИЙСКОМУ клиенту.
#
# Отдельной английской подписи для клиента нет нарочно. Она была, и её
# пришлось бы писать третьей — при том что английский текст владелец
# уже написал во второй строке. Переводчика в этой схеме нет вовсе:
# английский берётся оттуда, где он и так есть.
#
# Название кнопки (`название`, `название_en`) правится по желанию и на
# странице спрятано за «Переименовать»: у всех сорока восьми кнопок
# названия уже есть, и трогают их редко.
#
# `скрыт` — «1» убирает пункт из бота.
#
# Именно УБИРАЕТ, а не удаляет. Сценарий — это не строчка текста, а
# три с лишним тысячи знаков промпта в коде: свет, объектив, анатомия,
# поведение ткани. Стереть их из браузера значит потерять их навсегда,
# и вернуть пункт владелец сам уже не сможет. Скрытый пункт лежит на
# месте и возвращается тем же нажатием.
#
# Тем же полем скрываются разделы и подразделы — у них свои ключи, и
# никаких других правок им не нужно.
ПОЛЯ = ("название", "название_en", "строка", "строка_рус", "скрыт")


def загрузить(путь=None):
    """Правки владельца. Нет файла или он битый — пустой словарь: бот
    обязан подняться и работать на умолчаниях кода."""
    try:
        with open(путь or ФАЙЛ, encoding="utf-8") as f:
            д = json.load(f)
    except (OSError, ValueError):
        return {}
    if not isinstance(д, dict):
        return {}
    out = {}
    for ключ, знач in д.items():
        if isinstance(знач, dict):
            out[str(ключ)] = {p: str(знач.get(p) or "").strip() for p in ПОЛЯ}
    return out


def сохранить(правки, путь=None):
    """Пишет через временный файл и os.replace.

    Обрыв посреди записи не имеет права оставить обрезанный JSON: бот
    перечитывает этот файл при перезапуске, и битый файл означал бы
    молча слетевшие названия у всего каталога.
    """
    путь = путь or ФАЙЛ
    чистое = {}
    for ключ, знач in (правки or {}).items():
        знач = {p: str((знач or {}).get(p) or "").strip() for p in ПОЛЯ}
        if any(знач.values()):          # пустые записи не храним
            чистое[str(ключ)] = знач
    os.makedirs(os.path.dirname(путь) or ".", exist_ok=True)
    fd, врем = tempfile.mkstemp(dir=os.path.dirname(путь) or ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(чистое, f, ensure_ascii=False, indent=1, sort_keys=True)
            f.flush()
            os.fsync(f.fileno())
        os.replace(врем, путь)
    except BaseException:
        try:
            os.unlink(врем)
        except OSError:
            pass
        raise
    return len(чистое)


def перенести_из_txt(txt_путь, путь=None):
    """Разовый перенос из старого `ОТКРОВЕННОЕ.txt`, если владелец уже
    что-то туда вписал. Ничего не затирает: существующие записи
    сильнее."""
    if os.path.exists(путь or ФАЙЛ):
        return 0
    перенесено = {}
    try:
        with open(txt_путь, encoding="utf-8") as f:
            for строка in f:
                строка = строка.strip()
                if not строка or строка.startswith("#") or "=" not in строка:
                    continue
                ключ, _, хвост = строка.partition("=")
                англ, _, рус = хвост.partition("|")
                if англ.strip():
                    перенесено[ключ.strip()] = {
                        "название": "", "строка": англ.strip(),
                        "строка_рус": рус.strip()}
    except OSError:
        return 0
    if перенесено:
        сохранить(перенесено, путь)
    return len(перенесено)
