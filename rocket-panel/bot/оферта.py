"""Документы сервиса на telegra.ph: одна страница, одна ссылка.

## Почему страница, а не сообщение бота

Владелец назвал образец прямо — так же оформлены документы у
конкурентов. И это правильнее нашего прежнего способа:

  * страница открывается ПОВЕРХ чата и закрывается одним движением,
    не засоряя переписку;
  * её видно без бота: можно дать в поддержку, в рекламу, в спор;
  * она правится нами в любой момент, и у всех, кому её уже показали,
    обновится сама — ссылка та же.

Кнопка под первым сообщением ведёт СРАЗУ сюда. Промежуточного
сообщения «вот условия» нет нарочно: человек нажал «ознакомиться»,
значит хочет читать документ, а не ещё один экран бота.

## Где живёт

Страница создаётся один раз, дальше правится. Токен доступа и адрес
лежат в `/srv/amberry/оферта.json`: без токена страницу уже не
изменить, и потерять его значит навсегда остаться с той редакцией,
что есть.

Нет файла — модуль просто отдаёт пустую ссылку, и бот показывает
условия текстом, как раньше. Документ это обязательство, а не
украшение: упасть из-за него нельзя.
"""

import json
import os
import re
import urllib.parse
import urllib.request

API = "https://api.telegra.ph"
ФАЙЛ = os.environ.get("AMBERRY_OFFER_FILE", "/srv/amberry/оферта.json")
ЗАГОЛОВОК = "Документы сервиса AMBERRY"


def _зов(метод, **поля):
    данные = urllib.parse.urlencode(
        {к: (json.dumps(з, ensure_ascii=False) if isinstance(з, (list, dict))
             else з)
         for к, з in поля.items() if з is not None}).encode()
    with urllib.request.urlopen(API + "/" + метод, data=данные,
                                timeout=30) as о:
        о = json.load(о)
    if not о.get("ok"):
        raise RuntimeError(str(о.get("error"))[:200])
    return о["result"]


def _память():
    try:
        with open(ФАЙЛ, encoding="utf-8") as ф:
            return json.load(ф)
    except (OSError, ValueError):
        return {}


def _запомнить(д):
    try:
        os.makedirs(os.path.dirname(ФАЙЛ) or ".", exist_ok=True)
        врем = ФАЙЛ + ".врем"
        with open(врем, "w", encoding="utf-8") as ф:
            json.dump(д, ф, ensure_ascii=False, indent=1)
        os.replace(врем, ФАЙЛ)
    except OSError as e:
        print("оферта не сохранилась:", str(e)[:150], flush=True)


def ссылка():
    """Адрес страницы. Пусто — страницы ещё нет."""
    return _память().get("url") or ""


# Разбор нашей же разметки в узлы telegra.ph. Своего парсера HTML тут
# не заводим: в текстах документов ровно два тега, <b> и перевод
# строки, и городить ради них зависимость незачем.
_ЖИРНЫЙ = re.compile(r"<b>(.*?)</b>", re.S)


def _строка_в_узлы(строка):
    узлы, край = [], 0
    for м in _ЖИРНЫЙ.finditer(строка):
        if м.start() > край:
            узлы.append(строка[край:м.start()])
        узлы.append({"tag": "b", "children": [м.group(1)]})
        край = м.end()
    if край < len(строка):
        узлы.append(строка[край:])
    return узлы or [""]


_ЦЕЛИКОМ_ЖИРНАЯ = re.compile(r"^<b>([^<]*)</b>$")


def _текст_в_узлы(текст):
    """Абзацы разделены пустой строкой.

    СТРОКА ЦЕЛИКОМ В <b> СТАНОВИТСЯ ЗАГОЛОВКОМ, а не жирной строкой
    внутри абзаца. В сообщении бота разницы нет, на странице она
    решающая: телеграф ставит вокруг заголовка воздух, а жирную строку
    с переводом строки лепит вплотную к тексту, и выходит
    «1. ВозрастБот делает материалы для взрослых».

    Заголовок при этом отделяется от своего абзаца: первая строка
    уезжает в h4, остальные остаются абзацем под ним.
    """
    узлы = []
    for абзац in текст.split("\n\n"):
        абзац = абзац.strip("\n")
        if not абзац:
            continue
        строки = абзац.split("\n")
        м = _ЦЕЛИКОМ_ЖИРНАЯ.match(строки[0].strip())
        if м:
            узлы.append({"tag": "h4", "children": [м.group(1)]})
            строки = строки[1:]
            if not строки:
                continue
        дети = []
        for н, строка in enumerate(строки):
            if н:
                дети.append({"tag": "br"})
            дети.extend(_строка_в_узлы(строка))
        узлы.append({"tag": "p", "children": дети})
    return узлы


def собрать(условия, оферта):
    """Содержимое страницы: два раздела под общим заголовком."""
    узлы = []
    узлы.extend(_текст_в_узлы(условия))
    узлы.append({"tag": "hr"})
    узлы.extend(_текст_в_узлы(оферта))
    return узлы


def опубликовать(условия, оферта, токен=None):
    """Создать страницу или обновить уже созданную. Возвращает адрес.

    Идём по памяти: есть путь — правим, нет — создаём. Так ссылка,
    которую мы уже показали людям, остаётся прежней навсегда.
    """
    п = _память()
    токен = токен or п.get("token") or os.environ.get("AMBERRY_TELEGRAPH_TOKEN")
    if not токен:
        сч = _зов("createAccount", short_name="AMBERRY",
                  author_name="AMBERRY",
                  author_url="https://t.me/theamberrybot")
        токен = сч["access_token"]
    содержимое = собрать(условия, оферта)
    общее = {"access_token": токен, "title": ЗАГОЛОВОК,
             "author_name": "AMBERRY",
             "author_url": "https://t.me/theamberrybot",
             "content": содержимое, "return_content": "false"}
    if п.get("path"):
        р = _зов("editPage", path=п["path"], **общее)
    else:
        р = _зов("createPage", **общее)
    _запомнить({"token": токен, "path": р["path"], "url": р["url"]})
    return р["url"]


# --- ДВЕ ОТДЕЛЬНЫЕ СТРАНИЦЫ -------------------------------------------
#
# Платёжная система спрашивает ДВА адреса: на пользовательское
# соглашение и на оферту. Это разные документы с разной силой -
# соглашение описывает правила пользования, оферта является публичным
# предложением заключить договор, - и сводить их в один адрес нельзя:
# в анкету вписывают по ссылке на каждый.
#
# Сводная страница при этом остаётся: на неё ведут кнопка в боте и
# первое сообщение, и менять уже показанный людям адрес незачем.

ФАЙЛ2 = os.environ.get("AMBERRY_DOCS_FILE", "/srv/amberry/документы.json")


def _память2():
    try:
        with open(ФАЙЛ2, encoding="utf-8") as ф:
            return json.load(ф)
    except (OSError, ValueError):
        return {}


def ссылки():
    """{'условия': url, 'оферта': url}. Пусто - страниц ещё нет."""
    п = _память2()
    return {"условия": п.get("условия") or "", "оферта": п.get("оферта") or ""}


def опубликовать_раздельно(условия, оферта_, токен=None):
    """Две страницы, по одной на документ. Возвращает оба адреса.

    Токен берётся тот же, что у сводной страницы: аккаунт telegra.ph
    один, и плодить их значит однажды потерять доступ к части своих же
    документов.
    """
    п = _память()
    токен = токен or п.get("token") or os.environ.get("AMBERRY_TELEGRAPH_TOKEN")
    if not токен:
        raise RuntimeError("нет токена telegra.ph: сначала сводная страница")
    было = _память2()
    итог = {}
    for ключ, заголовок, текст in (
            ("условия", "Пользовательское соглашение AMBERRY", условия),
            ("оферта", "Публичная оферта AMBERRY", оферта_)):
        общее = {"access_token": токен, "title": заголовок,
                 "author_name": "AMBERRY",
                 "author_url": "https://t.me/theamberrybot",
                 "content": _текст_в_узлы(текст), "return_content": "false"}
        путь = было.get(ключ + "_path")
        р = (_зов("editPage", path=путь, **общее) if путь
             else _зов("createPage", **общее))
        итог[ключ] = р["url"]
        итог[ключ + "_path"] = р["path"]
    try:
        os.makedirs(os.path.dirname(ФАЙЛ2) or ".", exist_ok=True)
        врем = ФАЙЛ2 + ".врем"
        with open(врем, "w", encoding="utf-8") as ф:
            json.dump(итог, ф, ensure_ascii=False, indent=1)
        os.replace(врем, ФАЙЛ2)
    except OSError as e:
        print("документы не сохранились:", str(e)[:150], flush=True)
    return итог
