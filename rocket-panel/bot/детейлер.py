def _перекрытие(а, б):
    """Доля меньшего квадрата, накрытая другим. Ноль, если второго нет."""
    if not а or not б:
        return 0.0
    ax, ay, аб = а
    бx, бy, бб = б
    ш = max(0, min(ax + аб, бx + бб) - max(ax, бx))
    в = max(0, min(ay + аб, бy + бб) - max(ay, бy))
    меньший = min(аб * аб, бб * бб)
    return (ш * в) / меньший if меньший else 0.0


def _зоны_по_лицу(кадр, рамка=None):
    """Запасной путь: грудь и пах пропорциями от лица.

    У взрослого человека тело укладывается примерно в семь с половиной
    голов, и на стоящем человеке это работает. На любой другой позе
    промахивается, поэтому идёт вторым после скелета.

    `рамка` - лицо КОНКРЕТНОГО человека. Без неё берётся самое крупное
    лицо кадра, и на парной сцене оба тела считаются от одного лица:
    зона паха женщины уезжает на бедро мужчины.
    """
    import лицо_реф
    рамка = рамка or лицо_реф.найти(кадр)
    if not рамка:
        return {}
    x1, y1, x2, y2 = рамка
    голова = y2 - y1
    cx = (x1 + x2) / 2
    h, w = кадр.shape[:2]

    def квадрат(cy, бок):
        бок = min(бок, w, h)
        л = int(max(0, min(w - бок, cx - бок / 2)))
        в = int(max(0, min(h - бок, cy - бок / 2)))
        return (л, в, int(бок))

    # Грудь примерно в двух головах ниже подбородка, пах в четырёх.
    # Квадраты НЕ ПЕРЕСЕКАЮТСЯ, и это важно: на пересечении две зоны
    # вклеиваются одна поверх другой, каждая со своей подгонкой тона, и
    # полоса стыка выходит третьего оттенка. Грудь кончается на 3.1
    # головы, пах начинается на 3.2.
    return {"грудь": квадрат(y2 + голова * 1.9, голова * 2.4),
            "пах": квадрат(y2 + голова * 4.3, голова * 2.2)}


def _квадрат_лица(кадр, рамка):
    x1, y1, x2, y2 = рамка
    бок = max(x2 - x1, y2 - y1) * ЗАПАС["лицо"]
    h, w = кадр.shape[:2]
    бок = int(min(бок, w, h))
    л = int(max(0, min(w - бок, (x1 + x2) / 2 - бок / 2)))
    в = int(max(0, min(h - бок, (y1 + y2) / 2 - бок / 2)))
