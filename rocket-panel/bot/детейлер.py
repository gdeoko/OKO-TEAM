def _зоны_по_позе(кадр):
    """Где искать грудь и пах, если детектора зон нет.

    По лицу: у взрослого человека тело укладывается примерно в семь с
    половиной голов, и от подбородка вниз пропорции держатся устойчиво.
    Это грубо, но это работает на любом теле и не требует ни сторонних
    моделей, ни интернета - а точность тут нужна до зоны, а не до
    миллиметра: кроп берётся с запасом и вклеивается по мягкой маске.
    """
    import лицо_реф
    рамка = лицо_реф.найти(кадр)
    if not рамка:
        return {}
    x1, y1, x2, y2 = рамка
    голова = y2 - y1
    cx = (x1 + x2) / 2
    h, w = кадр.shape[:2]

    def квадрат(cy, бок):
        бок = min(бок, w, h)
        л = int(max(0, min(w - бок, cx - бок / 2)))
        в = int(max(0, min(h - бок, cy - бок / 2)))
        return (л, в, int(бок))

    # Грудь примерно в двух головах ниже подбородка, пах в четырёх.
    return {"грудь": квадрат(y2 + голова * 2.0, голова * 2.6),
            "пах": квадрат(y2 + голова * 4.2, голова * 2.2)}


def зоны(кадр, какие=("лицо",)):
    """Квадраты зон на кадре: {имя: (x, y, сторона)}."""
    import лицо_реф
    итог = {}
    if "лицо" in какие:
        рамка = лицо_реф.найти(кадр)
        if рамка:
            x1, y1, x2, y2 = рамка
            бок = max(x2 - x1, y2 - y1) * ЗАПАС["лицо"]
            h, w = кадр.shape[:2]
            бок = int(min(бок, w, h))
            л = int(max(0, min(w - бок, (x1 + x2) / 2 - бок / 2)))
            в = int(max(0, min(h - бок, (y1 + y2) / 2 - бок / 2)))
            итог["лицо"] = (л, в, бок)
    прочие = [з for з in какие if з != "лицо"]
    if прочие:
        по_позе = _зоны_по_позе(кадр)
        for з in прочие:
            if з in по_позе:
                итог[з] = по_позе[з]
    return итог


def подогнать_цвет(кусок, каким_был):
    """Подтянуть тон пересчитанной зоны к тому, что было.

    Без этого вклеенная зона садится пятном другого оттенка: модель
    свободна в цвете, и лицо выходит то розовее, то желтее тела. Тон
    правится по среднему и разбросу в Lab, отдельно по каждому каналу.
    Яркость трогаем мягко, чтобы не убить новую фактуру.
    """
    a = cv2.cvtColor(кусок, cv2.COLOR_BGR2LAB).astype(np.float32)
    b = cv2.cvtColor(каким_был, cv2.COLOR_BGR2LAB).astype(np.float32)
    for i, доля in ((0, 0.5), (1, 1.0), (2, 1.0)):
        са, сб = a[:, :, i].mean(), b[:, :, i].mean()
        ра, рб = a[:, :, i].std() + 1e-6, b[:, :, i].std() + 1e-6
        новое = (a[:, :, i] - са) * (рб / ра) + сб
        a[:, :, i] = a[:, :, i] * (1 - доля) + новое * доля
    return cv2.cvtColor(np.clip(a, 0, 255).astype(np.uint8), cv2.COLOR_LAB2BGR)


def вклеить(кадр, кусок, место, мягкость=0.12):
    """Вставить пересчитанную зону обратно без шва.

    Маска с растушёвкой по краю: жёсткая вставка видна рамкой, потому
    что зона пересчитана и её шум не совпадает с соседним.
    """
    x, y, бок = место
    кусок = cv2.resize(кусок, (бок, бок), interpolation=cv2.INTER_AREA)
    было = кадр[y:y + бок, x:x + бок]
    кусок = подогнать_цвет(кусок, было)
    маска = np.zeros((бок, бок), np.float32)
    поле = max(4, int(бок * мягкость))
    маска[поле:-поле, поле:-поле] = 1.0
    маска = cv2.GaussianBlur(маска, (0, 0), поле / 2)[..., None]
    кадр[y:y + бок, x:x + бок] = (кусок * маска + было * (1 - маска)
                                  ).astype(np.uint8)
    return кадр


def доработать(путь, референс=None, какие=("лицо",), карта=None,
               куда=None, denoise=None, зерно=7):
    """Пересчитать зоны крупно и вклеить. Возвращает путь к готовому.

    Зоны считаются ПО ОЧЕРЕДИ и каждая своим запросом: одна общая
    генерация на весь кадр это ровно то, от чего мы уходим.
    """
    кадр = cv2.imread(путь)
    if кадр is None:
        return None
    найдено = зоны(кадр, какие)
    if not найдено:
        print("детейлер: зон не нашлось", flush=True)
        return путь
    # Свой клиент с большим таймаутом, даже когда карта передана
    # снаружи. У боевого клиента он тридцать секунд, а детейлер идёт
    # СРАЗУ после основной генерации, когда карта ещё разгребает
    # очередь: первая же пачка 28.09.2026 потеряла доработку на всех
    # кадрах с «The read operation timed out», и кадры молча уходили
    # недоработанными.
    import gpu
    карта = gpu.Gpu(os.environ.get("ROCKET_GPU_URL", ""),
                    os.environ.get("ROCKET_GPU_USER", "rocket"),
                    os.environ.get("ROCKET_GPU_PASS", ""),
                    timeout=int(os.environ.get("ROCKET_ZONE_TIMEOUT", "180")))
    карта.выбрать("фото")
    # Лицу отдельным референсом идёт кроп лица с исходного снимка: в
    # проходе по зоне весь бюджет энкодера достаётся одному лицу.
    реф_лица = None
    if референс and "лицо" in найдено:
        import лицо_реф
        реф_лица = лицо_реф.кроп_лица(референс)
    # Зоны считаются ПАРАЛЛЕЛЬНО. Каждая это мегапиксель, и три таких
    # помещаются на карте разом, а по очереди они стоили сто секунд из
    # ста пятидесяти четырёх - больше, чем сам кадр.
    #
    # Вклейка идёт потом и по очереди: она правит один и тот же массив,
    # и параллельная запись затёрла бы соседнюю зону.
    def посчитать(имя, место):
        x, y, бок = место
        кусок = кадр[y:y + бок, x:x + бок]
        if кусок.size == 0:
            return имя, место, None
        кусок = cv2.resize(кусок, (ЛИСТ, ЛИСТ), interpolation=cv2.INTER_CUBIC)
        врем = f"/tmp/зона_{имя}_{os.getpid()}.jpg"
        cv2.imwrite(врем, кусок, [cv2.IMWRITE_JPEG_QUALITY, 97])
        try:
            снимки = [карта.upload(os.path.basename(врем),
                                   open(врем, "rb").read())]
            if имя == "лицо" and реф_лица:
                снимки.append(карта.upload(os.path.basename(реф_лица),
                                           open(реф_лица, "rb").read()))
            jid, _ = карта.start(
                prompt=ПРОМПТЫ[имя], size="sq", steps=ШАГИ, seed=зерно,
                cfg_свой=CFG, neg=НЕГАТИВ, шаги=ШАГИ,
                denoise=float(denoise or DENOISE), mode="photo",
                images=снимки, _лист=[ЛИСТ, ЛИСТ])
            готово = карта.wait(jid, limit=900)
            файлы = готово.get("files") or []
            if not файлы:
                print(f"детейлер {имя}: карта не вернула кадр", flush=True)
                return имя, место, None
            return имя, место, cv2.imdecode(
                np.frombuffer(карта.fetch(файлы[0]), np.uint8),
                cv2.IMREAD_COLOR)
        except Exception as e:                              # noqa: BLE001
            print(f"детейлер {имя}: {str(e)[:140]}", flush=True)
            return имя, место, None
        finally:
            if os.path.exists(врем):
                os.remove(врем)

    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(max_workers=len(найдено)) as пул:
        готовые = list(пул.map(lambda п: посчитать(*п), найдено.items()))
    for имя, место, новый in готовые:
        if новый is None:
            continue
        кадр = вклеить(кадр, новый, место)
        print(f"детейлер {имя}: зона {место[2]}px пересчитана на {ЛИСТ}",
              flush=True)
    куда = куда or os.path.splitext(путь)[0] + ".детейл.png"
    cv2.imwrite(куда, кадр)
    return куда


if __name__ == "__main__":
    import sys
    к = sys.argv[1]
    р = sys.argv[2] if len(sys.argv) > 2 else None
    з = sys.argv[3].split(",") if len(sys.argv) > 3 else ["лицо"]
    print(доработать(к, р, з))
