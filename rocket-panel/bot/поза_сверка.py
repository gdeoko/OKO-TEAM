# -*- coding: utf-8 -*-
"""Совпадает ли поза кадра с принятым эталоном кнопки.

## Зачем

Владелец 30.09.2026: «ЖЖ МЖ сейчас все позы стало не те, которые
утвердили. В самом боте есть примеры эталоны поз, и они должны быть
такие или ещё лучше».

Он прав, и дыра здесь не в модели, а в проверке. Всю ночь качество
мерилось по КОЖЕ - резкость, шум, крапины, блики, - а поза не
проверялась вовсе, ни числом, ни глазом. Кнопка обещает человеку
конкретный кадр (`примеры.КАДР` показывает его прямо под кнопкой), и
обещание это надо сверять, а не предполагать.

## Что считается

Скелет эталона против скелета нашего кадра. Оба приводятся к общему
масштабу по плечам и бёдрам - иначе крупный план и полный рост
разойдутся на любом кадре просто из-за размера человека.

Расхождение печатается и общим числом, и ПО УЗЛАМ: «правое запястье
ушло на 0.31» это разговор о конкретной руке, а «поза не совпала» -
разговор ни о чём.

## Чего эта мера не умеет

Одного человека. `mediapipe.pose` находит один скелет на кадр, и на
парной сцене сверяется тот, кого он выбрал сам. Для пар это половина
ответа, и честно считать её половиной: полноценно парные позы меряет
DWPose на карте, он находит всех.

    python3 -m bot.поза_сверка <кнопка> <кадр.png>
    from bot import поза_сверка
    поза_сверка.сверить("pf_ff_close", "/путь/кадр.png")
"""
import json
import os
import subprocess
import tempfile

ПИТОН_MP = os.environ.get("ROCKET_MP_PY", "/opt/amberry/venv-mp/bin/python")
ЭТАЛОНЫ = os.environ.get("AMBERRY_ETALONS_DIR", "/srv/amberry/эталоны")

# Расхождение, выше которого поза считается ДРУГОЙ. Доля от роста
# человека в кадре: 0.12 это больше ладони у стоящего в полный рост.
ПОРОГ = float(os.environ.get("ROCKET_POZA_POROG", "0.12"))

_СКРИПТ = r'''
import sys, json
import cv2, numpy as np, mediapipe as mp
ВАЖНЫЕ = {
    "нос": 0, "плечо_л": 11, "плечо_п": 12, "локоть_л": 13, "локоть_п": 14,
    "кисть_л": 15, "кисть_п": 16, "бедро_л": 23, "бедро_п": 24,
    "колено_л": 25, "колено_п": 26, "стопа_л": 27, "стопа_п": 28,
}
итог = {}
поза = mp.solutions.pose.Pose(static_image_mode=True, model_complexity=2,
                              min_detection_confidence=0.3)
for путь in sys.argv[1:]:
    кадр = cv2.imread(путь)
    if кадр is None:
        итог[путь] = None
        continue
    от = поза.process(cv2.cvtColor(кадр, cv2.COLOR_BGR2RGB))
    if not от.pose_landmarks:
        итог[путь] = None
        continue
    т = от.pose_landmarks.landmark
    итог[путь] = {и: [round(т[k].x, 4), round(т[k].y, 4), round(т[k].visibility, 3)]
                  for и, k in ВАЖНЫЕ.items()}
поза.close()
print(json.dumps(итог))
'''


def _скелеты(*пути):
    """Скелеты нескольких кадров одним заходом. {путь: узлы или None}."""
    with tempfile.TemporaryDirectory() as д:
        с = os.path.join(д, "s.py")
        open(с, "w").write(_СКРИПТ)
        try:
            от = subprocess.run([ПИТОН_MP, с, *пути],
                                capture_output=True, timeout=300)
        except Exception:                                   # noqa: BLE001
            return {}
        for строка in (от.stdout or b"").decode("utf-8", "ignore").splitlines():
            if строка.strip().startswith("{"):
                try:
                    return json.loads(строка)
                except Exception:                           # noqa: BLE001
                    return {}
    return {}


def эталон_кнопки(ключ):
    """Путь к принятому кадру кнопки или None."""
    import sys
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import примеры
    # Ключ правок общий у фотографии и ролика: pf_/pr_ и ac_/ph_ это
    # одна кнопка с двумя видами работы, и кадр у них один.
    for к in (ключ, "pr_" + ключ[3:], "ac_" + ключ[3:]):
        имя = примеры.КАДР.get(к)
        if имя:
            п = os.path.join(ЭТАЛОНЫ, имя)
            return п if os.path.exists(п) else None
    return None


def _привести(узлы):
    """Скелет в общем масштабе: начало между бёдрами, рост в единицу.

    Без приведения крупный план и полный рост расходятся всегда, просто
    потому что человек в кадре разного размера, и мера говорила бы о
    кадрировании вместо позы.
    """
    if not узлы:
        return None
    б = [узлы.get("бедро_л"), узлы.get("бедро_п")]
    п = [узлы.get("плечо_л"), узлы.get("плечо_п")]
    if not all(б) or not all(п):
        return None
    цx = (б[0][0] + б[1][0]) / 2
    цy = (б[0][1] + б[1][1]) / 2
    пy = (п[0][1] + п[1][1]) / 2
    рост = abs(цy - пy)
    if рост < 0.02:                     # человек лежит поперёк кадра
        рост = max(abs(б[0][0] - б[1][0]), 0.02)
    return {и: [(з[0] - цx) / рост, (з[1] - цy) / рост, з[2]]
            for и, з in узлы.items()}


def сверить(ключ, кадр, эталон=None):
    """Расхождение позы с эталоном кнопки. Словарь с разбором."""
    э = эталон or эталон_кнопки(ключ)
    if not э:
        return {"беда": f"у кнопки {ключ} нет принятого кадра"}
    if not os.path.exists(кадр):
        return {"беда": "нет файла кадра"}
    ск = _скелеты(э, кадр)
    а = _привести(ск.get(э))
    б = _привести(ск.get(кадр))
    if not а:
        return {"беда": "на эталоне скелет не найден"}
    if not б:
        return {"беда": "на кадре скелет не найден"}
    по_узлам = {}
    for и in а:
        if и not in б:
            continue
        # Узел, которого не видно ни там, ни там, в счёт не идёт: за
        # спиной рука у обоих, и спорить не о чем.
        if а[и][2] < 0.4 and б[и][2] < 0.4:
            continue
        по_узлам[и] = round(((а[и][0] - б[и][0]) ** 2
                             + (а[и][1] - б[и][1]) ** 2) ** 0.5, 3)
    среднее = (sum(по_узлам.values()) / len(по_узлам)) if по_узлам else None
    худшие = sorted(по_узлам.items(), key=lambda п: -п[1])[:4]
    return {"эталон": os.path.basename(э),
            "расхождение": round(среднее, 3) if среднее is not None else None,
            "совпала": bool(среднее is not None and среднее <= ПОРОГ),
            "ушли": [f"{и} {з}" for и, з in худшие if з > ПОРОГ],
            "по_узлам": по_узлам}


if __name__ == "__main__":
    import sys
    о = сверить(sys.argv[1], sys.argv[2])
    print(json.dumps(о, ensure_ascii=False, indent=1))
