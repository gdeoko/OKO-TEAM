"""Экраны бота: клавиатуры, шапки, премиум-иконки на кнопках.

Держится отдельно от bot.py нарочно. В bot.py — что происходит, здесь —
как это выглядит. Иначе правка одной подписи требует лезть в разбор
callback'ов, а переименование кнопки тихо ломает переход.

## Премиум-эмодзи на кнопках

У InlineKeyboardButton и KeyboardButton есть поле `icon_custom_emoji_id`
с ограничением:

    Can only be used by bots that purchased additional usernames on
    Fragment or in the messages directly sent by the bot to private,
    group and supergroup chats if the owner of the bot has a Telegram
    Premium subscription.

Мы во втором случае: бот пишет в личку, у владельца Premium. Но
ограничение хрупкое — Premium может кончиться, и тогда Телеграм
откажется рисовать иконку. Поэтому иконка НИКОГДА не несёт смысла
сама: подпись кнопки полна и понятна без неё. Пропадут иконки —
интерфейс станет скучнее, но не сломается.

## Два меню, и у них разная работа

**Нижнее** (`НИЖНЕЕ`, reply-клавиатура под полем ввода) — постоянное и
БЕЗ иконок. Решение владельца 21.09.2026. Там только самое основное:
создать, баланс, пополнить, мои работы. Это навигация, а не витрина —
иконки в ней соревнуются за внимание с кнопками в сообщении, где они
и должны работать. К тому же нижние кнопки видны всегда, и мигающий
премиум-значок в них быстро надоедает.

**В сообщениях** (inline) — всё остальное, и вот там премиум-иконки
уместны: каталог, сценарии, пакеты, способы оплаты, кабинет.

Нижнее не заменяет inline, а страхует его: inline живёт в конкретном
сообщении, и стоит пролистать чат вверх, как человек остаётся без
навигации.

## Язык

Каждая функция, которая рисует текст или кнопку, принимает `яз` —
`"ru"` или `"en"`. Не глобальная настройка и не переменная модуля: бот
один, а люди в нём разные, и два человека с разными языками пишут ему
одновременно. Глобальный язык означал бы, что ответ приходит на языке
того, кто написал последним.

Умолчание `"ru"` стоит для тестов и служебных вызовов, а не как
«главный язык»: в живом коде `яз` передаётся всегда, из базы.
"""

