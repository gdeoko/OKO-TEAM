    return клава([
        [кнопка(t("кн.позвать", яз), url=поделиться, иконка=emoji.БАНТ,
                стиль="primary")],
        [кнопка(t("кн.назад", яз), "m:cab", emoji.ВЛЕВО)],
    ])


