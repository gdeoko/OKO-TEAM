def кнопка(текст, данные=None, иконка=None, стиль=None, url=None):
    """Одна inline-кнопка. Иконка и стиль необязательны."""
    b = {"text": текст}
    if данные:
        b["callback_data"] = данные
    if url:
        b["url"] = url
    if иконка:
        b["icon_custom_emoji_id"] = иконка
    if стиль:
        b["style"] = стиль          # danger | success | primary
    return b


def _по_смыслу(текст):
    """Узнаём слово в названии кнопки -> иконка по смыслу."""
    низ = (текст or "").lower()
    for слова, ик in emoji.ПО_СМЫСЛУ:
        if any(w in низ for w in слова):
            return ик
    return None


def _добор(ключ, занято):
    """Устойчивая иконка из россыпи. Одна и та же кнопка получает одну и
    ту же картинку всегда.

    Не случайная и не по порядку: случайная менялась бы при каждом
    открытии экрана, а по порядку — съезжала бы у всех кнопок разом,
    стоит владельцу спрятать один вариант. Считается от callback'а,
    который переживает и переименование, и правку каталога.
    """
    if not emoji.РОССЫПЬ:
        return None
    н = int(hashlib.sha1(ключ.encode()).hexdigest()[:8], 16)
    for шаг in range(len(emoji.РОССЫПЬ)):
        ик = emoji.РОССЫПЬ[(н + шаг) % len(emoji.РОССЫПЬ)]
        if ик not in занято:
            return ик
    # Кнопок больше, чем картинок. Повтор некрасив, но пустая кнопка
    # посреди наряженных — заметнее.
    return emoji.РОССЫПЬ[н % len(emoji.РОССЫПЬ)]


def раздать_иконки(ряды):
    """Иконка слева у КАЖДОЙ кнопки, и в одном сообщении — разные.

    Требование владельца 21.09.2026. Делается здесь, в одном месте, а
    не при сборке каждого экрана: экранов полтора десятка, и правило
    «на каждой кнопке и все разные» иначе пришлось бы соблюдать
    пятнадцать раз подряд, а нарушить — один.

    Поставленное руками не трогаем: «Назад» со стрелкой, пакет с
    валютой, оплата с картой уже сказаны по смыслу, и добор обязан их
    обходить, а не спорить с ними.
    """
    занято = {b["icon_custom_emoji_id"] for ряд in ряды for b in ряд
              if b.get("icon_custom_emoji_id")}
    # Два прохода: сперва все, кого узнали по слову, потом добор. Иначе
    # добор успел бы занять губы под «Крупный план», и «Минет» ниже по
    # списку получил бы что попало.
    for проход in (_по_смыслу, None):
        for ряд in ряды:
            for b in ряд:
                if b.get("icon_custom_emoji_id"):
                    continue
                ик = (проход(b.get("text", "")) if проход else
                      _добор(b.get("callback_data") or b.get("url")
                             or b.get("text", ""), занято))
                if ик and ик not in занято:
                    b["icon_custom_emoji_id"] = ик
                    занято.add(ик)
    return ряды


def клава(ряды):
    """ряды — списки кортежей (текст, данные) или готовых словарей."""
    out = []
    for ряд in ряды:
        r = []
        for к in ряд:
            r.append(к if isinstance(к, dict) else кнопка(*к))
        out.append(r)
    return {"inline_keyboard": раздать_иконки(out)}




# Нижнее меню. Четыре кнопки: больше в один ряд не влезает читаемо, а
# второй ряд снизу занимает пол-экрана телефона.
def нижнее(яз="ru"):
    """Собирается под язык человека и ставится заново при его смене.

    Reply-клавиатура живёт не в сообщении, а в чате: сменив язык, её
    надо переслать, иначе снизу навсегда останутся русские кнопки —
    и `bot.НИЖНИЕ_КНОПКИ` перестанет их узнавать.
    """
    return {
        "keyboard": [[{"text": t("низ.создать", яз)},
                      {"text": t("низ.файлы", яз)}],
                     [{"text": t("низ.кабинет", яз)},
                      {"text": t("низ.пополнить", яз)}]],
        "resize_keyboard": True,
        "is_persistent": True,
    }


# Иконки категорий берутся по имени из emoji.py: в каталоге лежит
# строка, а не сам id, чтобы каталог не зависел от набора эмодзи.
def иконка_категории(cat):
    return getattr(emoji, cat.иконка, None) if cat.иконка else None


# Премиум-иконки у «Своего промпта»: фото и ролик — разные товары с
# разной ценой, и на глаз они должны различаться так же, как в цене.
ИКОНКА_СВОБОДНОГО = {"own_photo": emoji.ПАПКА, "own_video": emoji.ЭФИР}


def иконка_раздела(р):
    return getattr(emoji, р.иконка, None) if р.иконка else None


def главное_меню(популярное=None, яз="ru"):
    """Верхние узлы и ничего больше.

    `популярное` — узел, посчитанный из базы. Его нет на старте, пока
    заказов не было: пустая кнопка на самом видном месте хуже
    отсутствующей.
    """
    ряды = []
    if популярное and популярное.scenes:
        ряды.append([кнопка(популярное.назв(яз), f"n:{популярное.key}",
                            иконка_категории(популярное))])
    ряды += [[кнопка(у.назв(яз), f"n:{у.key}", иконка_раздела(у))]
             for у in catalog.РАЗДЕЛЫ if not у.пустой]
    ряды.append([
        кнопка(t("кн.баланс", яз), "m:balance", emoji.МОНЕТА),
        кнопка(t("кн.пополнить", яз), "m:buy", emoji.МОНЕТЫ, стиль="primary"),
    ])
    # ФРАНШИЗА - отдельной широкой строкой под оплатой, а не в ряду с
    # ней: это не «ещё одна кнопка меню», а самый дорогой товар бота, и
    # владелец просил поставить её на видное место. Прячется тем же
    # способом, что и всё остальное.
    if not catalog.скрыт("франшиза"):
        ряды.append([кнопка(t("фр.кнопка", яз), "m:fr", emoji.КОРОНА)])
    return клава(ряды)


def _назад(у):
    """Куда ведёт «Назад». Наверху — в меню, иначе к родителю."""
    род = getattr(у, "родитель", None)
    return f"n:{род.key}" if род else "m:menu"


def строка_цены(сцены, яз):
    """«13 вариантов, любой - фото за 1 💞».

    Цена ушла с кнопок (см. `catalog.Scene.button`), но не из
    интерфейса: конкурент прячет её до загрузки фото, и это наше
    отличие. В подразделе вид работы один на всех, поэтому одной строки
    хватает. Если видов вдруг несколько (так бывает в «Популярном»,
    где соседствуют фото и ролики), цена не называется — назвать
    ОДНУ цену для разных товаров хуже, чем не называть никакой.
    """
    n = len(сцены)
    виды = {s.job for s in сцены}
    if len(виды) != 1:
        return t("подр.сценариев_просто", яз, n=n, слово=язык.вариантов(n, яз))
    job = pricing.job(сцены[0].job)
    return t("подр.сценариев", яз, n=n, слово=язык.вариантов(n, яз),
             что=язык.job_title(job, яз).lower(),
             цена=f"{job.coins} {pricing.СИМВОЛ}")


def _уточнять(сцены, яз):
    """Нашлись ли в списке два варианта с одинаковым именем.

    Так бывает в «Групповом»: владелец назвал «69» и у МЖ, и у ЖЖ, и у
    ММ — акты одинаковые, составы разные. Три одинаковые кнопки подряд
    человек читает как ошибку, поэтому к таким именам приписывается
    состав. Переименовывать за владельца нельзя, а промолчать нельзя
    тем более.
    """
    имена = [s.назв(яз) for s in сцены]
    повтор = {и for и in имена if имена.count(и) > 1}
    return {s.key for s in сцены if s.назв(яз) in повтор}


def меню_узла(у, яз="ru"):
    """Дети или сценарии — смотря что внутри."""
    ряды = []
    if у.свободный:
        ряды = []
    elif у.видимые_дети:
        # У свободного ребёнка свой переход: внутри него не список
        # вариантов, а сразу сбор референса. Вести туда общим «n:»
        # значило бы показать пустой экран с одной кнопкой «Назад».
        ряды = [[кнопка(д.назв(яз) if д.свободный else д.button(яз),
                        f"{'own' if д.свободный else 'n'}:{д.key}",
                        ИКОНКА_СВОБОДНОГО.get(д.key) if д.свободный else None)]
                for д in у.видимые_дети]
    else:
        сцены = у.видимые
        уточнить = _уточнять(сцены, яз)
        ряды = [[кнопка(s.button(яз, s.key in уточнить), f"sc:{s.key}")]
                for s in сцены]
    ряды.append([кнопка(t("кн.назад", яз), _назад(у), emoji.ВЛЕВО),
                 кнопка(t("кн.меню", яз), "m:menu", emoji.ВЫВЕСКА)])
    return клава(ряды)


def текст_узла(у, яз="ru"):
    ик = иконка_раздела(у)
    значок = emoji.тег(ик) + " " if ик else ""
    строки = [f"{значок}<b>{у.назв(яз)}</b>", f"<i>{у.подзаг(яз)}</i>", ""]
    for д in у.видимые_дети:
        n = len(д.видимые)
        хвост = (" - " + t("разд.вариантов", яз, n=n,
                           слово=язык.вариантов(n, яз))) if n else ""
        строки.append(f"<b>{д.назв(яз)}</b>{хвост}\n<i>{д.подзаг(яз)}</i>")
    if not у.видимые_дети and у.видимые:
        строки.append(строка_цены(у.видимые, яз))
    return "\n".join(строки)


