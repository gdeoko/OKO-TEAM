def текст_оплаты(яз="ru"):
    строки = [f"{emoji.тег(emoji.МОНЕТЫ, pricing.СИМВОЛ)} "
              + t("оп.коины", яз), ""]
    for j in pricing.В_ПРОДАЖЕ:
        строки.append(t("оп.строка_вида", яз, что=язык.job_title(j, яз),
                        цена=j.coins, символ=pricing.СИМВОЛ))
    строки += ["", t("оп.подписки_нет", яз), "", t("оп.пакеты", яз), ""]
    for p in pricing.PACKS:
        строки.append(t("оп.пакет_строка", яз, коинов=p["coins"],
                        символ=pricing.СИМВОЛ, рублей=p["rub"],
                        рынок=p["market_rub"]))
    return "\n".join(строки)


