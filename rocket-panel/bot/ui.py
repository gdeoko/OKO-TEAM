#
# Отдельный экран, а не «баланс и всё»: человек приходит сюда не только
# за цифрой, но и настроить под себя. Всё, что он может про себя
# изменить или узнать, обязано лежать в одном месте — иначе настройка
# живёт в переписке с поддержкой.

def меню_кабинета(яз="ru"):
    return клава([
        [кнопка(t("кн.работы", яз), "m:works", emoji.ПАПКА),
         кнопка(t("кн.пополнить", яз), "m:buy", emoji.МОНЕТЫ, стиль="primary")],
        [кнопка(t("кн.друзья", яз), "m:ref", emoji.БАНТ)],
        # Подпись кнопки языка — НА ТОМ языке, на который она
        # переключит, а не на текущем. Человек, попавший на чужие
        # кнопки, ищет глазами знакомые буквы; «Language · English» на
        # русском экране он поймёт, а «Сменить язык» на английском —
        # нет, потому что не прочтёт.
        [кнопка(t("кн.язык", яз), "m:lang")],
        [кнопка(t("кн.удалить", яз), "m:forget", стиль="danger")],
        [кнопка(t("кн.назад", яз), "m:menu", emoji.ВЛЕВО)],
    ])


def текст_кабинета(баланс, св, имя=None, яз="ru"):
    кто = f"<b>{имя}</b>\n" if имя else ""
    строки = [
        f"{emoji.тег(emoji.МОНЕТА, pricing.СИМВОЛ)} " + t("каб.заголовок", яз), "",
        кто + t("гл.баланс", яз, баланс=emoji.баланс(баланс, яз)),
        "",
        t("каб.сделано", яз, сколько=св["работ"])
        + (t("каб.осечек", яз, сколько=св["осечек"]) if св["осечек"] else ""),
        t("каб.потрачено", яз, потрачено=св["потрачено"], куплено=св["куплено"],
          символ=pricing.СИМВОЛ),
    ]
    if св["позвано"]:
        строки.append(t("каб.друзья", яз, сколько=св["позвано"],
                        коинов=св["за_друзей"], символ=pricing.СИМВОЛ))
    return "\n".join(строки)


