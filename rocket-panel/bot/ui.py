def меню_мест(sc, яз="ru"):
    """Выбор обстановки. «Как на твоём фото» первым: это и самый частый
    выбор, и самый безопасный — своя комната на снимке уже есть."""
    ряды = [[кнопка(catalog.место_назв(м, яз),
                    f"sc:{sc.key}" if м.референс else f"sc:{sc.key}:{м.key}")]
            for м in catalog.видимые_места()]
    ряды.append([кнопка(t("кн.назад", яз), f"sc:{sc.key}", emoji.ВЛЕВО)])
    return клава(ряды)


def текст_мест(sc, яз="ru"):
    строки = [t("место.заголовок", яз, что=sc.назв(яз)), ""]
    for м in catalog.видимые_места():
        строки.append(f"<b>{catalog.место_назв(м, яз)}</b> - "
                      f"<i>{catalog.место_подпись(м, яз)}</i>")
    строки += ["", t("место.цена_та_же", яз)]
    return "\n".join(строки)


def текст_своего_промпта(у, яз="ru"):
    """Экран режима «Свой промпт»: фото одним проходом, видео двумя."""
