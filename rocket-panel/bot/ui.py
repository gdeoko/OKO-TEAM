def сколько_фото(job):
    """Человеческая строка «сколько снимков нести». Берётся из прайса —
    там же, где живёт свойство модели."""
    мин, макс = job.фото_нужно
    if макс == 0:
        return "Фото не нужно — хватит описания."
    if макс == 1:
        return "Нужен <b>один</b> снимок."
    if job.key.startswith("i2v"):
        return ("Нужен <b>один</b> снимок — он станет первым кадром. "
                "Можно прислать <b>второй</b>: он станет последним, и "
                "движение придёт к нему.")
    return (f"Можно прислать до <b>{макс}</b> снимков: чем больше ракурсов, "
            f"тем точнее лицо. Хватит и одного.")


def шапка_сценария(sc, баланс):
    job = pricing.job(sc.job)
    хватает = баланс >= sc.coins
    итог = (f"Спишем <b>{sc.coins} {pricing.СИМВОЛ}</b>, останется {баланс - sc.coins}."
            if хватает else
            f"Нужно <b>{sc.coins} {pricing.СИМВОЛ}</b>, на балансе {баланс}. "
            f"{emoji.тег(emoji.МОНЕТА_ПУСТО, pricing.СИМВОЛ)} Пополни — и сделаем.")
    return (f"<b>{sc.title}</b>\n"
            f"<i>{sc.подпись}</i>\n\n"
            f"{job.title} · {sc.coins} {pricing.СИМВОЛ}\n"
            f"{сколько_фото(job)}\n\n{итог}")


def просьба_о_фото(job, собрано=0):
    """Экран ожидания снимков. Показывает, сколько уже принято: без
    этого человек не понимает, ждёт бот ещё или уже можно запускать."""
    мин, макс = job.фото_нужно
    if собрано == 0:
        return f"{сколько_фото(job)}\n\nПришли фото."
    если_ещё = (f"\n\nМожно добавить ещё {макс - собрано} — или жми "
                f"«Хватит, поехали»." if собрано < макс else
                "\n\nБольше модель не возьмёт. Запускаю?")
    return (f"Принято снимков: <b>{собрано}</b> из {макс}.{если_ещё}")


