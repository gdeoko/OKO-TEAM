def сколько_фото(job, нужно=None, яз="ru"):
    """Человеческая строка «сколько снимков нести».

    По умолчанию берётся из прайса — там же, где живёт свойство модели.
    `нужно` перебивает: у парных сценариев снимков ровно два, по одному
    на человека, и это свойство сценария, а не вида работы.
    """
    мин, макс = нужно or job.фото_нужно
    if макс == 0:
        return t("фото.нет", яз)
    if мин == макс == 2:
        return t("фото.пара", яз)
    if макс == 1:
        return t("фото.один", яз)
    if job.key.startswith("i2v"):
        return t("фото.видео", яз)
    return t("фото.до_трёх", яз, макс=макс)


def шапка_сценария(sc, баланс, яз="ru", место=None):
    """Экран сценария. Строки — ракурс, место, действие — стоят здесь не
    для красоты.

    Человек платит ДО того, как увидит результат. Пока на экране было
    только название и цена, он покупал кота в мешке: «Крупный план» не
    говорит ни где она окажется, ни что будет делать. Теперь говорит.
    """
    место = место or места.КАК_НА_ФОТО
    job = pricing.job(sc.job)
    хватает = баланс >= sc.coins
    цена = f"{sc.coins} {pricing.СИМВОЛ}"
    итог = (t("сц.спишем", яз, цена=цена, остаток=баланс - sc.coins)
            if хватает else
            t("сц.не_хватает", яз, цена=цена, баланс=баланс,
              значок=emoji.тег(emoji.МОНЕТА_ПУСТО, pricing.СИМВОЛ)))

    строки = [f"<b>{sc.назв(яз)}</b>", ""]
    if sc.пара:
        # У пары состав важнее ракурса: акты у МЖ, ЖЖ и ММ владелец
        # писал разные, и человек должен видеть, за какой платит.
        строки.append(t("сц.в_кадре", яз, что=sc.состав(яз)))
        строки.append(t("сц.расстановка", яз, что=sc.подп(яз)))
    else:
        строки.append(t("сц.ракурс", яз, что=sc.подп(яз)))
    строки.append(t("сц.место", яз, что=catalog.место_назв(место, яз)))
    действие = sc.действие(яз)
    if действие:
        строки.append(t("сц.действие", яз, что=действие))
    строки += ["", f"{язык.job_title(job, яз)} · {цена}",
               сколько_фото(job, sc.фото_нужно, яз)]
    порядок = catalog.порядок_фото(sc, яз)
    if порядок:
        строки.append(порядок)
    строки += ["", итог]
    return "\n".join(строки)


def просьба_о_фото(job, собрано=0, нужно=None, яз="ru"):
    """Экран ожидания снимков. Показывает, сколько уже принято: без
    этого человек не понимает, ждёт бот ещё или уже можно запускать."""
    мин, макс = нужно or job.фото_нужно
    if собрано == 0:
        return f"{сколько_фото(job, нужно, яз)}\n\n{t('фото.пришли', яз)}"
    if собрано < мин:
        # Парные сцены: одного снимка мало, и «Хватит, поехали» тут не
        # должно появляться вовсе — запуск с одним референсом отдаст
        # одного человека там, где заплачено за двоих.
        return (t("фото.принято", яз, есть=собрано, всего=мин) + "\n\n"
                + t("фото.ещё_нужен", яз, сколько=мин - собрано))
    если_ещё = ("\n\n" + t("фото.можно_ещё", яз, сколько=макс - собрано)
                if собрано < макс else "\n\n" + t("фото.хватит", яз))
    return t("фото.принято", яз, есть=собрано, всего=макс) + если_ещё


def текст_сбора_фото(sc, job, собрано, яз="ru"):
    """Экран ожидания снимков у КОНКРЕТНОГО варианта: к общему тексту
    добавляется порядок, если он важен (см. `catalog.порядок_фото`)."""
    куски = [просьба_о_фото(job, собрано, sc.фото_нужно, яз)]
    порядок = catalog.порядок_фото(sc, яз)
    if порядок and собрано < 2:
        куски.append(порядок)
    return "\n\n".join(куски)


