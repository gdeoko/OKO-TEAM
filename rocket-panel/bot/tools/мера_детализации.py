# -*- coding: utf-8 -*-
"""Мера детализации, устойчивая к большим ровным местам.

Разброс лапласиана по всему кадру путает «мягкий кадр» с «кадром, где
много ровного фона». Поэтому здесь берётся не средний разброс, а СИЛА
САМЫХ КОНТРАСТНЫХ 5% точек: если кадр резкий, у него есть много точек с
крутым перепадом, сколько бы ровного места ни было рядом."""
import glob, os, sys
from PIL import Image, ImageFilter

ЛАПЛАС = ImageFilter.Kernel((3, 3), [0, 1, 0, 1, -4, 1, 0, 1, 0], scale=1)


def сила(им):
    г = им.convert("L").filter(ЛАПЛАС)
    точки = sorted(г.getdata(), reverse=True)
    верх = точки[:max(1, len(точки) // 20)]
    return sum(верх) / len(верх)


def доля_резких(им, порог=40):
    г = им.convert("L").filter(ЛАПЛАС)
    всего = г.size[0] * г.size[1]
    сильных = sum(1 for т in г.getdata() if т >= порог)
    return 100.0 * сильных / всего


for путь in sorted(sys.argv[1:] or glob.glob("/root/proba/[sp]_*.png")):
    им = Image.open(путь)
    ш, в = им.size
    пах = им.crop((0, int(в * .45), ш, int(в * .70)))
    print("%-34s сила верхних 5%%: всё %5.1f · пах %5.1f | резких точек: всё %4.1f%% · пах %4.1f%%"
          % (os.path.basename(путь), сила(им), сила(пах),
             доля_резких(им), доля_резких(пах)))
