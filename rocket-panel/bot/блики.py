# -*- coding: utf-8 -*-
"""Снять с кожи мокрый блеск и белые мазки.

## Зачем

Владелец про кадры: «всё как нарисованное кистью», «царапины», «точки
белые чёрные». Разбор крупным планом 30.09.2026 показал, что это одно и
то же: по животу и груди идут БЕЛЫЕ ШТРИХИ И БРЫЗГИ, будто тело облито
маслом или водой. На живом фото такого нет.

Перепробовано и не помогло:

  * запрет в промпте («The skin is MATTE and DRY») - стоит с 28.09;
  * запрет в негативе («oiled skin, wet shiny skin, glossy») - стоит;
  * чужая лора реализма - она резкость СНИЖАЕТ, проверено числом;
  * своя лора кожи в зонах на глубине 0.25 и 0.40 - кадр тот же.

Причина одна: так рисует сама сборка, а слова на низком CFG дистиллята
почти не слышны. Значит блик снимается после генерации, кодом.

## ЧЕМ ЭТО КОНЧИЛОСЬ, честно

Числа пришли к живой норме, а ВИД НЕ ИЗМЕНИЛСЯ. Доля блика на коже
0.016 -> 0.006 (у эталонов 0.006), доля штрихов 0.034 -> 0.015 (у
эталонов ноль), а кроп груди и живота на глаз тот же самый: те же
белёсые разводы, тот же мокрый вид.

Вывод из этого такой. Мокрым кадр делают не яркие пятна, которые ловит
эта мера, а СТРУКТУРА: полупрозрачная белёсая плёнка средней яркости,
которая не выбивается из окружения ни светлотой, ни насыщенностью и
потому не находится порогом вовсе. Это дефект генерации, а не
пересвет, и постобработкой он не лечится - лечится весами.

Поэтому модуль ВЫКЛЮЧЕН по умолчанию. Он честно снимает пересвет там,
где тот есть, и пригодится, когда структуру вылечит лора; включать его
вместо лечения причины значит возить числа, не трогая кадр.

## Как отличается блик от светлого места

Блик это не «яркая кожа». У него три признака разом, и порознь каждый
ошибается:

1. **Яркость сильно выше окружения.** Не абсолютная - светлая кожа на
   солнце тоже яркая, - а по сравнению с СОСЕДЯМИ по коже.
2. **Насыщенность падает.** Кожа всегда цветная, блик белёсый: свет
   отражается от плёнки жира и теряет цвет тела.
3. **Он мелкий.** Тело, освещённое сбоку, светлеет плавно и широко;
   мазок и брызга это штрих в несколько точек.

Проверяются все три, иначе вместе с бликами уйдёт светлая сторона тела
и кадр станет плоским.

## Что делает

Найденные блики притягиваются к локальной яркости и локальному цвету -
не к среднему по кадру. Рельеф остаётся: гасится ПЕРЕсвет, а не форма.

    from bot import блики
    блики.снять("кадр.png")            # правит на месте
    блики.доля(кадр)                   # сколько кожи под бликом
"""
import os

import cv2
import numpy as np

# Насколько блик ярче своей округи, в единицах яркости. Замер на живых
# эталонах: у них выбросов выше тридцати почти нет, у наших кадров их
# целые дорожки.
ПОРОГ_ЯРЧЕ = float(os.environ.get("ROCKET_BLIK_YARCHE", "26"))
# Насколько бледнее окружения. Блик теряет цвет, светлая кожа нет.
ПОРОГ_БЛЕДНЕЕ = float(os.environ.get("ROCKET_BLIK_BLEDNEE", "4"))
# Норма живого фото. Замер по восемнадцати эталонам при этих же порогах:
# доля бликов 0.006, доля штрихов РОВНО НОЛЬ. Пороги подобраны по
# разделению групп, а не на глаз: при них живые дают ноль штрихов, наши
# 0.041, и это лучший разрыв из двадцати проверенных пар.
БЛИКОВ_НОРМА = float(os.environ.get("ROCKET_BLIK_NORMA", "0.006"))
# Округа, с которой сравниваем. Мельче - и широкий пересвет не найдётся
# вовсе, крупнее - и в блик попадёт вся освещённая сторона тела.
ОКРУГА = int(os.environ.get("ROCKET_BLIK_OKRUGA", "41")) | 1
# Насколько гасим. Ноль не трогает, единица стирает блик начисто и
# делает кожу плоской. Половина снимает мокрый вид и оставляет объём.
СИЛА = float(os.environ.get("ROCKET_BLIK_SILA", "0.62"))


def _кожа(кадр):
    """Маска кожи по медианно сглаженному кадру.

    Сглаживание обязательно: сам блик из диапазона кожи выпадает, и по
    исходнику маска вырезала бы ровно то, что мы ищем.
    """
    ycrcb = cv2.cvtColor(cv2.medianBlur(кадр, 5), cv2.COLOR_BGR2YCrCb)
    м = cv2.inRange(ycrcb, (0, 133, 77), (255, 180, 127))
    # Закрываем дыры: маска, дырявая на месте бликов, оставит их
    # нетронутыми - тот же провал, что и без сглаживания.
    return cv2.morphologyEx(м, cv2.MORPH_CLOSE,
                            cv2.getStructuringElement(
                                cv2.MORPH_ELLIPSE, (25, 25)))


def найти(кадр):
    """Маска бликов: три признака разом."""
    hsv = cv2.cvtColor(кадр, cv2.COLOR_BGR2HSV)
    яркость = hsv[:, :, 2].astype(np.float32)
    насыщ = hsv[:, :, 1].astype(np.float32)
    окружение_я = cv2.medianBlur(hsv[:, :, 2], ОКРУГА).astype(np.float32)
    окружение_н = cv2.medianBlur(hsv[:, :, 1], ОКРУГА).astype(np.float32)
    ярче = (яркость - окружение_я) > ПОРОГ_ЯРЧЕ
    бледнее = (окружение_н - насыщ) > ПОРОГ_БЛЕДНЕЕ
    м = ((ярче & бледнее) & (_кожа(кадр) > 0)).astype(np.uint8) * 255
    # Мелкая связка убирает одиночные точки шума, а крупные пятна
    # оставляет: широкий пересвет на плече это тоже блик.
    return cv2.morphologyEx(м, cv2.MORPH_OPEN,
                            cv2.getStructuringElement(
                                cv2.MORPH_ELLIPSE, (3, 3)))


def доля(кадр):
    """Какая часть кожи занята бликом. Для замера и для журнала."""
    кожа = _кожа(кадр) > 0
    точек = int(кожа.sum())
    if not точек:
        return 0.0
    return float(((найти(кадр) > 0) & кожа).sum()) / точек


# Что считать штрихом. Замер 30.09.2026 по двадцати пяти живым эталонам
# и четырём нашим кадрам: доля бликов у живых 0.006 против наших 0.012,
# а доля ШТРИХОВ у живых РОВНО НОЛЬ против наших 0.037. Вот она,
# разница, которую владелец называет «мазки кистью»: дело не в том,
# сколько блика, а в том, что он вытянут в тонкую полосу.
ВЫТЯНУТОСТЬ = float(os.environ.get("ROCKET_BLIK_DLINA", "3.0"))
ПЛОТНОСТЬ = float(os.environ.get("ROCKET_BLIK_PLOTNOST", "0.45"))
МЕЛОЧЬ = 12                    # меньше двенадцати точек это шум, не штрих


def _разделить(м):
    """Разложить блики на штрихи и округлые пятна. (штрихи, пятна)."""
    н, метки, статы, _ = cv2.connectedComponentsWithStats(м, 8)
    штрихи = np.zeros_like(м)
    пятна = np.zeros_like(м)
    for и in range(1, н):
        пл = статы[и, cv2.CC_STAT_AREA]
        if пл < МЕЛОЧЬ:
            continue
        ш = статы[и, cv2.CC_STAT_WIDTH]
        в = статы[и, cv2.CC_STAT_HEIGHT]
        вытянут = max(ш, в) / max(1, min(ш, в))
        плотно = пл / max(1, ш * в)
        куда = (штрихи if (вытянут >= ВЫТЯНУТОСТЬ and плотно < ПЛОТНОСТЬ)
                else пятна)
        куда[метки == и] = 255
    return штрихи, пятна


def доля_штрихов(кадр):
    """Доля вытянутых бликов среди всех. У живого фото это ноль."""
    м = найти(кадр)
    н, _, статы, _ = cv2.connectedComponentsWithStats(м, 8)
    всего = длинных = 0
    for и in range(1, н):
        пл = статы[и, cv2.CC_STAT_AREA]
        if пл < МЕЛОЧЬ:
            continue
        ш = статы[и, cv2.CC_STAT_WIDTH]
        в = статы[и, cv2.CC_STAT_HEIGHT]
        всего += 1
        if (max(ш, в) / max(1, min(ш, в)) >= ВЫТЯНУТОСТЬ
                and пл / max(1, ш * в) < ПЛОТНОСТЬ):
            длинных += 1
    return (длинных / всего) if всего else 0.0


def снять(путь_или_кадр, куда=None, сила=None):
    """Погасить блики. Путь (если дан файл) или кадр."""
    файл = isinstance(путь_или_кадр, str)
    кадр = cv2.imread(путь_или_кадр) if файл else путь_или_кадр
    if кадр is None:
        return None
    м = найти(кадр)
    если_нет = (путь_или_кадр if файл else кадр)
    if not (м > 0).any():
        return если_нет
    сила = СИЛА if сила is None else сила
    # ШТРИХ ГАСИТСЯ ПОЧТИ НАСУХО, ПЯТНО ЕДВА. Живое фото блики имеет, и
    # немало: гася их подряд, мы сделали бы кожу плоской, а на кадре
    # пропал бы объём. Разница живого и нашего ровно в штрихах, их и
    # убираем.
    штрихи, пятна = _разделить(м)
    местное = cv2.medianBlur(кадр, ОКРУГА)
    ш_мягко = cv2.GaussianBlur(штрихи.astype(np.float32) / 255.0, (0, 0), 2.0)
    п_мягко = cv2.GaussianBlur(пятна.astype(np.float32) / 255.0, (0, 0), 3.0)

    def свести(доля_пятен):
        мягкая = np.clip(ш_мягко * min(1.0, сила * 1.45)
                         + п_мягко * доля_пятен, 0, 1)[:, :, None]
        сведено = (кадр.astype(np.float32) * (1 - мягкая)
                   + местное.astype(np.float32) * мягкая)
        return np.clip(сведено, 0, 255).astype(np.uint8)

    # ПЯТНА ГАСЯТСЯ РОВНО ДО ЖИВОЙ НОРМЫ, а не на глаз. Гашение одних
    # штрихов снимает меру, но не снимает мокрый вид: его делает общий
    # глянец, и он тоже меряется - доля блика на коже. Тянем её к 0.006,
    # какая она у живых эталонов, делением отрезка пополам.
    #
    # Ноль тут не цель и целью быть не может: кожа без единого блика
    # плоская, и объём с кадра уходит вместе с глянцем.
    итог = свести(сила * 0.35)
    if доля(итог) > БЛИКОВ_НОРМА:
        низ, верх = сила * 0.35, 1.0
        for _ in range(7):
            сер = (низ + верх) / 2
            проба = свести(сер)
            if доля(проба) > БЛИКОВ_НОРМА:
                низ = сер
            else:
                верх = сер
            итог = проба
        итог = свести(верх)
    if файл:
        cv2.imwrite(куда or путь_или_кадр, итог)
        return куда or путь_или_кадр
    return итог


if __name__ == "__main__":
    import sys
    к = cv2.imread(sys.argv[1])
    print("бликов %.3f  штрихов %.3f   (у живого фото 0.006 и 0.000)"
          % (доля(к), доля_штрихов(к)))
    if len(sys.argv) > 2:
        снять(sys.argv[1], sys.argv[2])
        п = cv2.imread(sys.argv[2])
        print("после:  бликов %.3f  штрихов %.3f"
              % (доля(п), доля_штрихов(п)))
