# за спиной владельца»: выбор модели остаётся его, а здесь закрыт
# единственный случай, где выбранная модель физически не делает
# оплаченную работу.
ПОСЛЕДНИЙ_КАДР_УМЕЕТ = ("minimax-h3-lite",)
ЗАПАС_ДЛЯ_ДВУХ_КАДРОВ = "minimax-h3-lite"

КЛЮЧ_ФОТО = "api_фото"
КЛЮЧ_ВИДЕО = "api_видео"
КЛЮЧ_КАЧЕСТВО = "api_качество"
НАСТРОЙКА_ЖИВЁТ = 5


class Api:
    def __init__(self, key=None, base=БАЗА, timeout=180, store=None):
        self.key = key if key is not None else os.environ.get("APIMODELS_KEY", "")
        self.base = (base or БАЗА).rstrip("/")
        self.timeout = timeout
        self.store = store
        self._умолч_фото = МОДЕЛЬ_ФОТО
        self._умолч_видео = МОДЕЛЬ_ВИДЕО
        self._кэш_настроек = (None, 0.0)
        self._замок = threading.Lock()
        self._байты = {}              # имя -> содержимое (снимки и результаты)
        self._задачи = {}             # task_id -> {вид, т0, готово}
        self._счёт = 0
        self._баланс = (0.0, 0.0)     # (сколько, когда спрашивали)
        # Берёт ли этот вид запроса негатив. None — ещё не пробовали,
        # False — ответил отказом, больше не предлагаем. Спрашивается
        # один раз за жизнь процесса и ничего не стоит: запрос, который
        # не приняли, кадра не тратит.
        self._негатив = {}
        # Берёт ли этот вид запроса зерно. Спрашивается так же, как
        # негатив, и так же один раз: отказ кадра не тратит.
        self._зерно = {}
        # Берёт ли видео-модель настоящий первый кадр. None — не
        # пробовали, False — отказала, дальше шлём референсом персонажа
        # (хуже: сцену придумает сама, но ролик всё же будет).
        self._первый_кадр = None

    # ---------- что выбрано в админке ----------

    def _настройки(self):
        """Модель фото, модель видео и качество видео из базы.

        Кэш на пять секунд — ровно по той же причине, что у движка:
        нужна не скорость, а тишина в журнале, иначе один запрос к базе
        приходился бы на каждое обращение, а их в задании десятки.
        """
        знач, когда = self._кэш_настроек
        if знач and time.time() - когда < НАСТРОЙКА_ЖИВЁТ:
            return знач
        фото, видео, качество = self._умолч_фото, self._умолч_видео, КАЧЕСТВО_ВИДЕО
        if self.store is not None:
            try:
                фото = self.store.настройка(КЛЮЧ_ФОТО, фото) or фото
                видео = self.store.настройка(КЛЮЧ_ВИДЕО, видео) or видео
                качество = self.store.настройка(КЛЮЧ_КАЧЕСТВО, качество) or качество
            except Exception:                               # noqa: BLE001
                pass
        фото = фото if фото in ФОТО_МОДЕЛИ else self._умолч_фото
        видео = видео if видео in ВИДЕО_МОДЕЛИ else self._умолч_видео
        можно = ВИДЕО_КАЧЕСТВО.get(видео) or (КАЧЕСТВО_ВИДЕО,)
        if качество not in можно:
            качество = ВИДЕО_КАЧЕСТВО_УМОЛЧ.get(видео, можно[0])
        знач = (фото, видео, качество)
        self._кэш_настроек = (знач, time.time())
        return знач

    @property
    def модель_фото(self):
        return self._настройки()[0]

    @property
    def модель_видео(self):
        return self._настройки()[1]

    @property
    def качество_видео(self):
        return self._настройки()[2]

    def выбор(self):
        """Что показать в админке: что выбрано и что можно выбрать."""
        фото, видео, качество = self._настройки()
        return {"фото": фото, "видео": видео, "качество": качество,
                "фото_можно": dict(ФОТО_МОДЕЛИ),
                "видео_можно": dict(ВИДЕО_МОДЕЛИ),
                "качество_можно": list(ВИДЕО_КАЧЕСТВО.get(видео) or ())}

    def выбрать_модель(self, фото=None, видео=None, качество=None):
        """Записать выбор владельца. Возвращает то же, что `выбор`."""
        if self.store is None:
            return self.выбор()
        if фото in ФОТО_МОДЕЛИ:
            self.store.настройка_записать(КЛЮЧ_ФОТО, фото)
        if видео in ВИДЕО_МОДЕЛИ:
            self.store.настройка_записать(КЛЮЧ_ВИДЕО, видео)
            можно = ВИДЕО_КАЧЕСТВО[видео]
            умолч = ВИДЕО_КАЧЕСТВО_УМОЛЧ.get(видео, можно[0])
            # Качество у моделей разное: 768p у lite и 1080p у wan не
            # пересекаются вовсе. Переключили модель - качество обязано
            # стать её собственным, иначе запрос уйдёт с чужим словом и
            # сервис ответит отказом за наши деньги.
            теперь = self.store.настройка(КЛЮЧ_КАЧЕСТВО, "")
            if теперь not in можно:
                self.store.настройка_записать(КЛЮЧ_КАЧЕСТВО, умолч)
        if качество:
            _, в, _ = self._настройки()
            если_можно = ВИДЕО_КАЧЕСТВО.get(видео if видео in ВИДЕО_МОДЕЛИ else в)
            if качество in (если_можно or ()):
                self.store.настройка_записать(КЛЮЧ_КАЧЕСТВО, качество)
        self._кэш_настроек = (None, 0.0)
        return self.выбор()

    # ---------- то же, что у карты ----------

    @property
    def настроена(self):
        return bool(self.key)

    def карты(self):
        """У API нет карт. Один «адрес» — чтобы бот не считал движок
        ненастроенным там, где он смотрит на список."""
        return [self.base] if self.настроена else []

    def выбрать(self, род=None):
        """Выбирать нечего: задачи считаются параллельно и очереди нет.
        Метод оставлен, потому что бот зовёт его на каждом задании."""
        return self.base

    def отпустить(self):
        return None

    def alive(self):
        """Ключ рабочий и на счёте есть деньги."""
        if not self.настроена:
            return False
        try:
            return self.баланс() > МИНИМУМ
        except GpuError:
            return False

    def free_vram(self):
        """(остаток в долларах, он же, очередь). Памяти у API нет, а
        очередь всегда ноль: работы идут параллельно."""
        try:
            б = self.баланс()
        except GpuError:
            б = None
        return б, б, 0

    def лицо(self, filename, content, сила=0.5):
        """Восстановителя лиц в API нет. None — бот отдаст кадр как есть."""
        return None

    def тело(self, filename, content, кожа=None, зоны=None, сзади=False,
             пара=False):
        """Дорисовки кожи и органов в API нет. None — кадр как есть."""
        return None

    def upload(self, filename, content):
        """«Залить» снимок. У API нет хранилища имён, поэтому байты
        остаются у нас, а наружу уходит имя — его бот и передаёт в
        `start`, как передавал имя на карте."""
        with self._замок:
            self._счёт += 1
            имя = "%04d_%s" % (self._счёт, os.path.basename(filename or "in.png"))
            self._положить(имя, content)
        return имя

    def start(self, **params):
        """Запустить задачу. Возвращает (task_id, seed) — как карта.

        Запрос отправляется ПОЛНЫМ, а на отказ по конкретному полю
        упрощается и повторяется. Спросить дешевле, чем решить за
        сервис заранее: отказ стоит ноль и кадра не тратит, а решение
        «этого у них наверняка нет» уже стоило нам и одетых кадров, и
        роликов с выдуманной комнатой.
        """
        вид, тело = self._запрос(params)
        for _ in range(3):
            try:
                о = self._зов("/%s/generations" % вид, тело)
                break
            except GpuError as e:
                if not self._упростить(вид, тело, e):
                    raise
        else:
            raise GpuError("сервис отказал на все варианты запроса")
        tid = о.get("taskId") or о.get("task_id") or о.get("id")
        if not tid:
            raise GpuError("задачу не приняли: %s" % json.dumps(
                о, ensure_ascii=False)[:200])
        with self._замок:
            self._задачи[tid] = {"вид": вид, "т0": time.time(), "готово": None}
        print("APIMODELS %s: задача %s, модель %s"
              % (вид, tid, тело.get("model")), flush=True)
        return tid, params.get("seed") or 0

    def poll(self, job_id):
        """Состояние задачи словарём бота: state ok/err/run, files, sec."""
        with self._замок:
            з = self._задачи.get(job_id)
        if not з:
            raise GpuError("задача %s не наша" % str(job_id)[:40])
        if з["готово"]:
            return з["готово"]
        о = self._зов("/%s/generations?task_id=%s" % (з["вид"], job_id))
        сек = int(time.time() - з["т0"])
        сост = str(о.get("state") or о.get("status") or "").lower()
        ссылки = [с for с in (о.get("resultUrls") or о.get("result_urls") or [])
                  if с]
        if not ссылки:
            один = о.get("resultUrl") or о.get("url")
            if один:
                ссылки = [один]
        # Готовность по ССЫЛКЕ, а не по слову: названия состояний у
        # моделей разные, ссылка одна и та же.
        if ссылки or сост in ГОТОВО:
            if not ссылки:
                raise GpuError("задача готова, но файла нет: %s"
                               % json.dumps(о, ensure_ascii=False)[:200])
            имя = self._забрать(job_id, ссылки[0])
            итог = {"state": "ok", "sec": сек, "files": [имя],
                    "цена": self._цена(о)}
            with self._замок:
                self._задачи[job_id]["готово"] = итог
                # ССЫЛКА НА ГОТОВЫЙ ФАЙЛ ЗАПОМИНАЕТСЯ, И ВОТ ЗАЧЕМ.
                # Апскейлер `real-esrgan` принимает ТОЛЬКО публичный
                # адрес: ни base64, ни файл он не берёт. Единственный
                # публичный адрес нашего кадра - этот, свой же ответ
                # сервиса. Без него путь к 4K пришлось бы открывать
                # выкладкой откровенных кадров на наш домен.
                self._задачи[job_id]["ссылка"] = ссылки[0]
            return итог
        if сост in ПРОВАЛ:
            with self._замок:
                if job_id in self._задачи:
                    self._задачи[job_id]["отказ"] = о
            return {"state": "err", "sec": сек,
                    "error": _почему(о, job_id, сост)}
        return {"state": сост or "run", "sec": сек}

    def ссылка(self, job_id):
        """Публичный адрес готового файла задачи или пустая строка."""
        with self._замок:
            return (self._задачи.get(job_id) or {}).get("ссылка") or ""

    def повторяемый(self, job_id):
        """Отказ был на канале до провайдера, а не по делу.

        Сервис помечает такие сам (`retryable`) и денег за них не берёт:
        у пробы 01.10.2026 `UPSTREAM_FAILED` стоил ноль кредитов. Повтор
        бесплатен, а человек иначе получает осечку на ровном месте.
        """
        with self._замок:
            з = self._задачи.get(job_id) or {}
        о = з.get("отказ") or {}
        if о.get("retryable") is True:
            return True
        код = str(о.get("failCode") or о.get("fail_code") or "").upper()
        return код in ПОВТОРИТЬ_КОДЫ

    def wait(self, job_id, limit=900, on_tick=None):
        """Ждать результат. on_tick(секунд) — чтобы бот показывал счёт."""
        т0 = time.time()
        прошлый = -1
        while time.time() - т0 < limit:
            j = self.poll(job_id)
            if j.get("state") == "ok":
                return j
            if j.get("state") == "err":
                raise GpuError(j.get("error") or "генерация не удалась")
            сек = int(j.get("sec") or 0)
            if on_tick and сек != прошлый:
                on_tick(сек)
                прошлый = сек
            time.sleep(3)
        raise GpuError("слишком долго, отменяю")

    def fetch(self, filename):
        """Отдать байты по имени — снимка или готового файла."""
        with self._замок:
            данные = self._байты.get(filename)
        if данные is None:
            raise GpuError("файла %s уже нет" % str(filename)[:60])
        return данные

    # ---------- своё ----------

    def баланс(self, свежий=False):
        сколько, когда = self._баланс
        if not свежий and время_прошло(когда) < БАЛАНС_ЖИВЁТ:
            return сколько
        д = self._зов("/balance")
        сколько = float(д.get("balance") or 0)
        self._баланс = (сколько, time.time())
        return сколько

    def _запрос(self, params):
        """Параметры бота -> тело запроса APIMODELS."""
        режим = params.get("mode") or "photo"
        if режим == "inpaint":
            raise GpuError("правка по маске есть только на карте")
        стороны = СТОРОНЫ.get(params.get("size") or "vert", "9:16")
        рефы = self._рефы(params)
        промпт = params.get("prompt") or ""
        if режим == "video":
            вид = "video"
            # Квадрата у этой модели нет: только альбом и вертикаль.
            if стороны not in ("16:9", "9:16"):
                стороны = "9:16"
            тело = {"model": self.модель_видео, "prompt": промпт,
                    "resolution": self.качество_видео, "ratio": стороны,
                    "duration": int(params.get("secs") or 5)}
            # КАДРЫ: РЕЖИМ ВЫБИРАЕТ ИХ ЧИСЛО, И ЭТО ПРОВЕРЕНО ДЕНЬГАМИ.
            #
            # Два снимка (кнопка `i2v` умеет взять и последний кадр) —
            # это режим «первый плюс последний»: ролик идёт ОТ нашего
            # кадра, поза и фон сохраняются.
            #
            # Один снимок — только `images`, референс персонажа. Режиму
            # первого кадра нужны ОБА кадра, и с одним сервис не ругается,
            # а молча считает задачу как текст-в-видео: проба 01.10.2026
            # вернула `modelType: TEXT_TO_VIDEO`, то есть кадр пропал
            # совсем. Это хуже референса: там хотя бы лицо своё.
            if (len(рефы) > 1 and self._первый_кадр is not False
                    and тело["model"] not in ПОСЛЕДНИЙ_КАДР_УМЕЕТ):
                # Два снимка — это оплаченный «первый плюс последний».
                # Модель, которая берёт один, такую работу не сделает.
                тело["model"] = ЗАПАС_ДЛЯ_ДВУХ_КАДРОВ
                можно = ВИДЕО_КАЧЕСТВО[ЗАПАС_ДЛЯ_ДВУХ_КАДРОВ]
                if тело.get("resolution") not in можно:
                    тело["resolution"] = ВИДЕО_КАЧЕСТВО_УМОЛЧ[
                        ЗАПАС_ДЛЯ_ДВУХ_КАДРОВ]
                print("два кадра: считает %s %s"
                      % (тело["model"], тело["resolution"]), flush=True)
            своё = ПОЛЕ_КАДРА.get(тело["model"])
            if своё and рефы:
                # Модель берёт РОВНО ОДИН первый кадр своим полем.
                тело[своё] = рефы[0]
            elif len(рефы) > 1 and self._первый_кадр is not False:
                тело["first_frame_url"] = рефы[0]
                тело["last_frame_url"] = рефы[1]
            elif рефы and self._первый_кадр is not False:
                # ОДИН СНИМОК УХОДИТ И ПЕРВЫМ, И ПОСЛЕДНИМ КАДРОМ.
                #
                # Полем `images` он был РЕФЕРЕНСОМ ПЕРСОНАЖА: модель
                # брала из него лицо и тело, а сцену сочиняла заново.
                # Владелец это и увидел: «были зумы, типо приложение».
                # На пробе камера отъезжала и меняла точку, комната
                # дорисовывалась лампой и диваном, у женщины отрастали
                # волосы, появлялись трусы, которых на фото не было, и
                # поза менялась совсем.
                #
                # Режим первого кадра требует ОБА кадра, и с одним
                # сервис молча считает задачу как текст-в-видео. Но
                # никто не запрещает подать ОДИН И ТОТ ЖЕ снимок с
                # обеих сторон: ролик стартует ровно с нашего фото и
                # возвращается к нему, кадрирование стоит на месте,
                # двигаются только люди.
                #
                # Замер на одном кадре и одном промпте: расхождение
                # первого кадра ролика с фото 3 против 25 у `images`,
                # и на контрольных кадрах 9-21 против 25-30.
                тело["first_frame_url"] = рефы[0]
                тело["last_frame_url"] = рефы[0]
            elif рефы:
                тело["images"] = рефы
        else:
            вид = "images"
            тело = {"model": self.модель_фото, "prompt": промпт,
                    "aspect_ratio": стороны, "resolution": РАЗМЕР_ФОТО}
            if str(self.модель_фото).startswith("z-image"):
                # Пропорции он не понимает, а точки понимает. И отдаёт
                # вместе с кадром публичную ссылку на него - ту самую,
                # которой потом кормится апскейлер.
                тело.pop("aspect_ratio", None)
                тело.pop("resolution", None)
                тело["size"] = Z_РАЗМЕРЫ.get(params.get("size") or "vert",
                                             Z_РАЗМЕРЫ["vert"])
            if рефы:
                тело["image"] = рефы
                тело["image_urls"] = рефы
        # НЕГАТИВ — ПОЛОВИНА РАБОТЫ, А НЕ УКРАШЕНИЕ. В нём список
        # «не одевай её», и без него модель оставляет одежду с референса.
        негатив = params.get("neg")
        if негатив and self._негатив.get(вид) is not False:
            тело["negative_prompt"] = негатив
        # ЗЕРНО, И БЕЗ НЕГО «ПОПРОБУЙ ЕЩЁ РАЗ» НЕ РАБОТАЕТ ВОВСЕ.
        #
        # На ОДИНАКОВЫЙ запрос сервис отвечает прежней задачей: тот же
        # task_id и тот же кадр. Проба 02.10.2026: семь кругов подряд
        # вернули один кадр с точностью до сотых по всем мерам, потому
        # что текст запроса не менялся.
        #
        # Человек жмёт «ещё раз» именно тогда, когда кадр не понравился,
        # и получал ровно тот же. Зерно это разрывает: при том же промпте
        # выходит другой кадр. Сервис поля не знает - снимаем его так же,
        # как негатив, и дальше не шлём.
        зерно = params.get("seed")
        if зерно and self._зерно.get(вид) is not False:
            тело["seed"] = int(зерно)
        return вид, тело

    def _упростить(self, вид, тело, ошибка):
        """Снять поле, на котором споткнулся сервис. True — стоит повторить.

        Снимаем ТОЛЬКО то, на что прямо указала ошибка. Повторять на
        «кончились деньги» или на модерации нельзя: это второй платёж за
        тот же отказ, а кадр при этом выйдет хуже того, что мы просили.
        """
        if "negative_prompt" in тело and _про_поле(ошибка, "negative"):
            print("APIMODELS: %s не берёт negative_prompt, дальше без него"
                  % вид, flush=True)
            self._негатив[вид] = False
            тело.pop("negative_prompt")
            return True
        if "seed" in тело and _про_поле(ошибка, "seed"):
            print("APIMODELS: %s не берёт seed, дальше без него"
                  % вид, flush=True)
            self._зерно[вид] = False
            тело.pop("seed")
            return True
        if "first_frame_url" in тело and _про_поле(ошибка, "frame"):
            # Первого кадра не вышло — отдаём снимки референсом
            # персонажа. Ролик будет, но сцену модель сочинит свою, и
            # ради этого промежуточный кадр считать больше незачем.
            print("APIMODELS: %s не берёт first_frame_url, дальше "
                  "референсом персонажа" % вид, flush=True)
            self._первый_кадр = False
            кадры = [тело.pop("first_frame_url")]
            if "last_frame_url" in тело:
                кадры.append(тело.pop("last_frame_url"))
            тело["images"] = кадры
            return True
        return False

    def _рефы(self, params):
        """Имена снимков -> data-URI. Имя, которого у нас нет, — ошибка:
        молча считать кадр без референса значит отдать человеку чужое
        лицо за его деньги."""
        имена = list(params.get("images") or [])
        if not имена and params.get("image"):
            имена = [params["image"]]
        итог = []
        for имя in имена:
            if isinstance(имя, str) and имя.startswith(("http", "data:")):
                итог.append(имя)
                continue
            итог.append("data:image/png;base64," + base64.b64encode(
                self.fetch(имя)).decode())
        return итог

    def _положить(self, имя, данные):
        """Байты под именем. Вызывать под замком."""
        if len(self._байты) >= ХРАНИМ:
            self._байты.pop(next(iter(self._байты)), None)
        self._байты[имя] = данные

    def _забрать(self, tid, ссылка):
        """Скачать результат и положить под нашим именем."""
        расш = ".mp4" if ".mp4" in ссылка.lower() else ".png"
        for гадать in (".jpg", ".jpeg", ".webp", ".webm"):
            if гадать in ссылка.lower():
                расш = гадать
                break
        имя = "out_%s%s" % (str(tid)[:16], расш)
        данные = self._скачать(ссылка)
        with self._замок:
            self._положить(имя, данные)
        return имя

    def _скачать(self, ссылка):
        """Забрать файл с раздачи. Байты или своя ошибка с разбором.

        Два разных способа подряд, и это не перестраховка. Кадр к этому
        моменту УЖЕ ПОСЧИТАН И ОПЛАЧЕН: не донеся его, мы теряем деньги
        и отдаём человеку осечку за них же. `curl` ходит своей
        библиотекой TLS и со своими умолчаниями - там, где споткнулся
        питон, он часто проходит, и наоборот.

        В ошибку кладётся ХОЗЯИН ссылки и причина каждой попытки:
        «403 от раздачи» и «сеть не пустила» лечатся по-разному, а общее
        «не скачался» их не различает. Сама ссылка подписанная и длинная,
        целиком её в переписку не тащим.
        """
        хозяин = urllib.parse.urlsplit(ссылка).netloc or "?"
        заголовки = dict(БРАУЗЕР)
        # Своей же раздаче показываем ключ: часть ответов сервиса лежит
        # за той же дверью, что и API.
        if хозяин.endswith("apimodels.app"):
            заголовки["Authorization"] = "Bearer " + self.key
        беды = []
        for попытка in range(1, СКАЧАТЬ_ПОПЫТОК + 1):
            try:
                з = urllib.request.Request(ссылка, headers=заголовки)
                with urllib.request.urlopen(з, timeout=self.timeout) as р:
                    данные = р.read()
                if данные:
                    return данные
                беды.append("%d/питон: пусто" % попытка)
            except Exception as e:                          # noqa: BLE001
                беды.append("%d/питон: %s" % (попытка, str(e)[:90]))
            try:
                п = subprocess.run(
                    ["curl", "-sL", "--max-time", str(self.timeout),
                     "-A", БРАУЗЕР["User-Agent"], ссылка],
                    capture_output=True, timeout=self.timeout + 30)
                if п.returncode == 0 and п.stdout:
                    return п.stdout
                беды.append("%d/curl: код %s" % (попытка, п.returncode))
            except Exception as e:                          # noqa: BLE001
                беды.append("%d/curl: %s" % (попытка, str(e)[:90]))
            if попытка < СКАЧАТЬ_ПОПЫТОК:
                time.sleep(2)
        raise GpuError("результат не скачался с %s: %s"
                       % (хозяин, "; ".join(беды)[:300]))

    @staticmethod
    def _цена(о):
        for к in ("credits", "cost", "price", "consume"):
            if isinstance(о.get(к), (int, float)):
                return о[к]
        return None

    def _зов(self, путь, тело=None):
        if not self.настроена:
            raise GpuError("APIMODELS не подключён (нет APIMODELS_KEY)")
        з = urllib.request.Request(
            self.base + путь,
            data=json.dumps(тело).encode() if тело is not None else None,
            method="POST" if тело is not None else "GET",
            headers={"Authorization": "Bearer " + self.key,
                     "Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(з, timeout=self.timeout) as р:
                о = json.loads(р.read() or b"{}")
        except urllib.error.HTTPError as e:
            # Текст отказа модерации приходит ИМЕННО ЗДЕСЬ, и он нужен
            # целиком: «не вышло» про откровенную кнопку и «кончились
            # деньги» — разные беды с разным лечением.
            raise GpuError("%s: %s" % (
                e.code, e.read()[:300].decode("utf-8", "replace"))) from None
        except Exception as e:                              # noqa: BLE001
            raise GpuError(str(e)[:200]) from None
        if о.get("code") not in (200, None, 0):
            raise GpuError("APIMODELS %s: %s"
                           % (о.get("code"), str(о.get("msg"))[:200]))
        д = о.get("data")
        return д if isinstance(д, dict) else (о if isinstance(о, dict) else {})


def время_прошло(когда):
    return time.time() - (когда or 0)


# Слова, которыми сервис сообщает «такого поля я не знаю» или «это
# поле заполнено не так». Ровно на них и только на них запрос стоит
# упрощать: «кончились деньги» и «модерация» сюда не попадают нарочно.
ПРО_ПОЛЕ = ("400", "unknown", "unsupported", "invalid", "unexpected",
            "not allowed", "required", "missing", "must be")


# ГДЕ СЕРВИС ДЕРЖИТ ПРИЧИНУ ОТКАЗА. Полей несколько и называются они
# по-разному; первая версия искала `failReason`, которого нет, и человек
# получал голое слово состояния — «движок api: failed». Такое сообщение
# не отличает модерацию от пустого счёта, а лечатся они по-разному.
# Коды отказов, которые лечатся повтором: беда не в нашем запросе, а в
# канале до провайдера. Сервис помечает их `retryable` и не берёт денег.
ПОВТОРИТЬ_КОДЫ = ("UPSTREAM_FAILED", "UPSTREAM_TIMEOUT", "TIMEOUT",
                  "INTERNAL_ERROR", "SERVICE_UNAVAILABLE")

ПОЧЕМУ_ПОЛЯ = ("failMsg", "fail_msg", "failReason", "fail_reason",
               "errorMessage", "error_message", "error", "msg", "message",
               "detail")


def _почему(ответ, задача, состояние):
    """Причина отказа словами, и всегда с номером задачи.

    Номер нужен не для красоты: по нему задачу видно в консоли сервиса
    целиком — с промптом, параметрами и списанием. Без него жалоба
    «не вышло» ни к чему не привязана.
    """
    куски = []
    for к in ПОЧЕМУ_ПОЛЯ:
        з = ответ.get(к)
        if з and str(з).strip() and str(з).strip().lower() != состояние:
            куски.append(str(з).strip())
            break
    код = ответ.get("failCode") or ответ.get("fail_code")
    if код and str(код) not in " ".join(куски):
        куски.append("код %s" % код)
    if not куски:
        # Совсем пусто — отдаём состояние, но хотя бы с номером задачи.
        куски.append(состояние or "без объяснения")
    куски.append("задача %s" % задача)
    return " · ".join(куски)[:300]


def _про_поле(ошибка, имя):
    """Отказ именно про это поле, а не про что-нибудь ещё."""
    т = str(ошибка).lower()
    return имя in т and any(с in т for с in ПРО_ПОЛЕ)
