# -*- coding: utf-8 -*-
"""Кадр кнопки целиком: описание -> z-image -> 4K -> лицо -> резкость.

## Порядок шагов и почему он такой

    1. описатель   фото клиентки -> текст: лицо, волосы, кожа, фигура
    2. z-image     кадр по промпту кнопки с этим описанием внутри
    3. апскейл     real-esrgan на APIMODELS, ×4 и вниз до 4K
    4. лицо        inswapper ставит личность, GPEN возвращает резкость

Владелец назвал порядок «лицо, детализация, апскейл». Он так и идёт по
смыслу, но апскейл стоит ТРЕТЬИМ, и это не вольность. `real-esrgan`
принимает только публичную ссылку, а публичная ссылка есть ровно у
одного файла - у кадра, который только что отдал z-image. Отправить
туда кадр с уже поставленным лицом не через что: выкладывать
откровенные кадры на наш домен ради одного запроса нельзя.

Выигрыш от этого есть: лицо становится ПОСЛЕДНИМ слоем, и после него
кадр уже ничем не пересчитывается. Апскейл лицо бы размазал.

## Размер генерации выбран пределом апскейлера

`real-esrgan` отказывает на входе больше 2 096 704 точек. 1920×1280 это
2 457 600 - отказ. Поэтому генерим 1728×1152 (1 990 656) и 1152×1728:
та же пропорция, под пределом, и после ×4 выходит 6912×4608, что мы
сводим к 3840 по длинной стороне. Сведение вниз это не потеря, а
сглаживание: детали остаются, шум уходит.

## Деньги и время на кадр

    z-image      $0.03   18 с
    real-esrgan  $0.004  24 с
    лицо         0       13 с
    описатель    $0.01   один раз на клиентку, не на кадр
"""
import base64
import json
import os
import subprocess
import tempfile
import time
import urllib.request

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
БАЗА = os.environ.get("APIMODELS_BASE", "https://api.apimodels.app/v1")
МОДЕЛЬ = os.environ.get("AMBERRY_PHOTO", "z-image-spicy-pro")
АПСКЕЙЛ = os.environ.get("AMBERRY_UPSCALE", "real-esrgan")
ДЛИННАЯ_4K = int(os.environ.get("AMBERRY_4K", "3840"))
# Предел апскейлера по точкам входа, замерен его же отказом.
ПРЕДЕЛ_ТОЧЕК = 2096704
# РАЗМЕР ГЕНЕРАЦИИ ВЫБРАН ТЕМ, ЧТО ТЯНЕТ АПСКЕЙЛЕР.
#
# `real-esrgan` на APIMODELS отказывает по видеопамяти: 1728×1152 не
# прошло ни вчетверо, ни вдвое («CUDA out of memory, tried to allocate
# 3.80 GiB»). 1536×1024 проходит вчетверо и даёт 6144×4096, которые мы
# сводим до 3840 по длинной стороне. Сведение вниз не теряет детали, а
# усредняет шум: кадр выходит чище, чем нативные 1728.
РАЗМЕРЫ = {"horiz": (1536, 1024), "vert": (1024, 1536)}

import амберри_лицо as ЛИЦО
import амберри_приёмка as ПРИЁМКА
import амберри_промпты as ПР

# ЗЁРНА ПЕРЕСЧЁТА. Поза выходит не с первого раза примерно у одной
# кнопки из пяти: на `ff_69` голова лежащей оказывалась у груди вместо
# паха, и по счёту тел это был чистый кадр. Пересчёт с другим зерном
# стоит три копейки и двадцать секунд, круг правок с человеком - сутки.
# Больше трёх не берём: на прогоне кнопка, не вышедшая за три зерна,
# не выходила и за шесть.
ЗЁРНА = (777, 4242, 101)


def _ключ():
    return (os.environ.get("APIMODELS_KEY")
            or os.environ.get("ROCKET_API_KEY") or "")


def _зов(тело, таймаут=240):
    req = urllib.request.Request(
        БАЗА + "/images/generations", data=json.dumps(тело).encode(),
        headers={"Authorization": "Bearer " + _ключ(),
                 "Content-Type": "application/json"}, method="POST")
    with urllib.request.urlopen(req, timeout=таймаут) as о:
        д = json.loads(о.read().decode())
    д = д.get("data") or {}
    return д[0] if isinstance(д, list) else д


def _состояние(tid, таймаут=50):
    req = urllib.request.Request(
        БАЗА + "/images/generations?task_id=" + tid,
        headers={"Authorization": "Bearer " + _ключ()})
    with urllib.request.urlopen(req, timeout=таймаут) as о:
        return json.loads(о.read().decode()).get("data", {})


def _скачать(ссылка, куда):
    """Через curl: urllib на раздачу отвечает отказом прокси."""
    б = subprocess.run(["curl", "-sS", "-m", "180", ссылка],
                       capture_output=True).stdout
    if not б:
        raise RuntimeError("файл не скачался: %s" % ссылка[:80])
    open(куда, "wb").write(б)
    return куда


def кадр(ключ, она="", он="", вторая="", зерно=None, папка=None,
         доноры=None, апскейл=True, лицо=True, метка="", кругов=3):
    """Кадр с пересчётом: берём первое зерно, которое прошло приёмку."""
    зёрна = [зерно] if зерно else list(ЗЁРНА[:max(1, кругов)])
    лучший, лучшие_причины = None, None
    for н, з in enumerate(зёрна):
        о = _один(ключ, она=она, он=он, вторая=вторая, зерно=з, папка=папка,
                  доноры=None, апскейл=False, лицо=False,
                  метка=(метка or ключ) + "_%d" % з)
        import cv2
        ок, причины, числа = ПРИЁМКА.проверить(
            cv2.imread(о["файл"]), о["ключ"], пара=ключ in ПР.ПАРНЫЕ)
        о["приёмка"] = {"годен": ок, "причины": причины, "числа": числа,
                        "зерно": з, "круг": н + 1}
        if лучший is None or (лучшие_причины and len(причины) < len(лучшие_причины)):
            лучший, лучшие_причины = о, причины
        if ок:
            break
        print("АМБЕРРИ %s зерно %d: %s" % (ключ, з, "; ".join(причины)),
              flush=True)
    о = лучший
    # Апскейл и лицо считаются ОДИН раз и только на выбранном кадре:
    # платить за 4K у кадра, который мы всё равно выбросим, незачем.
    if апскейл and о.get("ссылка"):
        т1 = time.time()
        try:
            путь4k = _до_4k(о["ссылка"], о["файл"].replace(
                "_основа.png", "_4k.jpg"))
            о["4k"] = путь4k
            о["файл"] = путь4k
            о["цена"] += 0.004
        except Exception as e:                              # noqa: BLE001
            о["апскейл_не_вышел"] = str(e)[:120]
        о["сек_апскейл"] = round(time.time() - т1)
    if лицо and доноры:
        т2 = time.time()
        готово = о["файл"].replace("_основа.png", "_готово.jpg").replace(
            "_4k.jpg", "_готово.jpg")
        о["файл"], о["лицо"] = ЛИЦО.поставить(о["файл"], доноры, готово)
        о["сек_лицо"] = round(time.time() - т2)
    return о


def _один(ключ, она="", он="", вторая="", зерно=None, папка=None,
          доноры=None, апскейл=True, лицо=True, метка=""):
    """Кадр кнопки целиком. Возвращает словарь с путём и мерами.

    `доноры` - словарь роли -> путь к фото живого человека для подмены
    лица. Пусто - шаг лица пропускается молча.
    """
    д = ПР.промпт(ключ, она=она, он=он, вторая=вторая)
    ш, в = РАЗМЕРЫ[д["лист"]]
    папка = папка or tempfile.mkdtemp(prefix="амберри_")
    os.makedirs(папка, exist_ok=True)
    метка = метка or ("%s_%s" % (д["ключ"], зерно or "0"))
    отчёт = {"ключ": д["ключ"], "лист": д["лист"], "цена": 0.0,
             "знаков": len(д["промпт"])}
    т0 = time.time()
    тело = {"model": МОДЕЛЬ, "prompt": д["промпт"],
            "negative_prompt": д["негатив"], "size": "%dx%d" % (ш, в),
            "n": 1}
    if зерно:
        тело["seed"] = int(зерно)
    о = _зов(тело)
    путь = os.path.join(папка, "%s_основа.png" % метка)
    if о.get("b64_json"):
        open(путь, "wb").write(base64.b64decode(о["b64_json"]))
    elif о.get("url"):
        _скачать(о["url"], путь)
    else:
        raise RuntimeError("кадр не пришёл: %s" % json.dumps(о)[:200])
    отчёт["основа"] = путь
    отчёт["файл"] = путь
    отчёт["сек_кадр"] = round(time.time() - т0)
    ссылка = о.get("url")
    отчёт["ссылка"] = ссылка

    # Апскейл и лицо здесь НЕ делаются: их делает обёртка `кадр`,
    # и делает ОДИН раз на выбранном зерне. Считать их на каждом
    # круге значит платить за кадры, которые мы выбросим.
    отчёт["файл"] = путь
    отчёт["цена"] += 0.03
    отчёт["сек"] = round(time.time() - т0)
    return отчёт


def _до_4k(ссылка, куда):
    """real-esrgan, потом вниз до 4K по длинной стороне.

    Кратность пробуем сначала четыре, потом два. Вчетверо наш кадр
    1728×1152 сервису не по памяти: «CUDA out of memory, tried to
    allocate 3.80 GiB». Вдвое проходит и даёт 3456×2304 - это уже
    больше, чем отдаёт телеграм, и глазу хватает. Падать на этом нельзя:
    кадр к этому моменту посчитан и оплачен.
    """
    import cv2
    беда = None
    for кратность in (4, 2):
        try:
            _апскейл_раз(ссылка, куда, кратность)
            беда = None
            break
        except Exception as e:                              # noqa: BLE001
            беда = e
            print("АПСКЕЙЛ ×%d не вышел: %s" % (кратность, str(e)[:110]),
                  flush=True)
    if беда is not None:
        raise беда
    к = cv2.imread(куда)
    если = ДЛИННАЯ_4K / float(max(к.shape[:2]))
    if если < 1.0:
        к = cv2.resize(к, (int(к.shape[1] * если), int(к.shape[0] * если)),
                       interpolation=cv2.INTER_AREA)
    cv2.imwrite(куда, к, [cv2.IMWRITE_JPEG_QUALITY, 95])
    return куда


def _апскейл_раз(ссылка, куда, кратность):
    о = _зов({"model": АПСКЕЙЛ, "prompt": "upscale", "scale": кратность,
              "image_urls": [ссылка]})
    tid = о.get("taskId")
    if not tid and о.get("url"):
        _скачать(о["url"], куда)
    else:
        т0 = time.time()
        while time.time() - т0 < 240:
            time.sleep(4)
            с = _состояние(tid)
            сост = str(с.get("state") or "").lower()
            if сост == "completed":
                _скачать((с.get("resultUrls") or [""])[0], куда)
                break
            if сост in ("failed", "error"):
                raise RuntimeError(str(с.get("failMsg"))[:120])
        else:
            raise RuntimeError("апскейл не дождались")
    return куда
