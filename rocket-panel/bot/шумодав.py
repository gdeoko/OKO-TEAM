# -*- coding: utf-8 -*-
"""Привести кожу к числам эталона. Силу выбирает мера, а не вкус.

## Что заменяет и почему

`ретушь.py` снимала блики и крапины поштучно и подставляла на их место
медианное размытие. Замер на живых эталонах показал, что от этого
становится ХУЖЕ: кадр после ретуши имеет резкость 533 и шум 5.79 против
475 и 5.39 без неё, при цели 239 и 2.77. Причина в самом приёме:
точечная замена оставляет мозаику из тронутых и нетронутых мест, а
граница между ними это новый резкий переход, то есть ровно то, от чего
мы избавлялись.

Здесь наоборот. Кожа обрабатывается ЦЕЛИКОМ, одним мягким шумодавом с
сохранением краёв, и сила подбирается так, чтобы шум пришёл к целевому
числу этой группы сцен. Ни больше, ни меньше: недобор оставит грязь,
перебор сделает кожу пластиком, а оба видны числом.

## Почему края сохраняются

Обычное размытие уводит и шум, и форму: соски, складки и волосы
смазываются вместе с мусором. Нелокальные средние усредняют пиксель по
ПОХОЖИМ местам кадра, поэтому ровная кожа сглаживается, а граница
остаётся границей. На замере это видно: после него доля спокойной кожи
растёт до 54 при цели 48, а резкость падает мягко.

## Родинки

Не трогаются и не должны: правило владельца от 28.09.2026. Шумодав
работает по амплитуде мелкого шума, а родинка это пятно с формой и
контрастом - для нелокальных средних она такой же значимый элемент,
как сосок, и остаётся на месте.

    from шумодав import привести
    привести("/кадр.png", цель={"шум": 2.77})
"""
import os

import cv2
import numpy as np

# Границы поиска силы. Ноль это «не трогать», выше двенадцати начинает
# есть форму даже нелокальный шумодав.
МИН, МАКС = 0.0, 12.0
ШАГОВ = int(os.environ.get("ROCKET_DENOISE_STEPS", "5"))


def _маска_кожи(кадр):
    """Где кожа. Тот же признак, что у приёмщика, чтобы не разойтись."""
    ycrcb = cv2.cvtColor(кадр, cv2.COLOR_BGR2YCrCb)
    м = cv2.inRange(ycrcb, (0, 133, 77), (255, 180, 127))
    я = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (9, 9))
    м = cv2.morphologyEx(м, cv2.MORPH_OPEN, я)
    return cv2.morphologyEx(м, cv2.MORPH_CLOSE, я)


def шум(кадр, маска=None):
    """Сколько в кадре мелкого мусора. То же число, что у приёмщика."""
    сер = cv2.cvtColor(кадр, cv2.COLOR_BGR2GRAY).astype(np.float32)
    мед = cv2.medianBlur(сер.astype(np.uint8), 3).astype(np.float32)
    разн = сер - мед
    if маска is not None and маска.any():
        разн = разн[маска > 0]
    return float(np.std(разн))


def _чистить(кадр, сила):
    """Нелокальные средние по яркости и цвету. Края остаются краями."""
    if сила <= 0.05:
        return кадр
    return cv2.fastNlMeansDenoisingColored(
        кадр, None, float(сила), float(сила), 7, 21)


def привести(путь_или_кадр, цель_шума, куда=None):
    """Довести шум кожи до целевого числа. Возвращает (кадр, сила, шум).

    Сила ищется делением отрезка пополам, а не перебором: каждый проход
    нелокальных средних стоит секунды, и пять делений дают точность
    заведомо выше, чем разброс самой меры.
    """
    кадр = (cv2.imread(путь_или_кадр)
            if isinstance(путь_или_кадр, str) else путь_или_кадр)
    if кадр is None:
        return None, 0.0, 0.0
    кожа = _маска_кожи(кадр)
    было = шум(кадр, кожа)
    if было <= цель_шума * 1.05:
        # Уже тише цели. Трогать нечего: лишний проход только съест
        # фактуру, которой и так в обрез.
        return кадр, 0.0, было

    низ, верх, лучший, лучший_шум, сила = МИН, МАКС, кадр, было, 0.0
    for _ in range(ШАГОВ):
        проба = (низ + верх) / 2
        получилось = _чистить(кадр, проба)
        ш = шум(получилось, кожа)
        if abs(ш - цель_шума) < abs(лучший_шум - цель_шума):
            лучший, лучший_шум, сила = получилось, ш, проба
        if ш > цель_шума:
            низ = проба
        else:
            верх = проба

    # Шумодав идёт ТОЛЬКО по коже. Волосы, глаза, ткань и фон остаются
    # как были: там мелкая деталь это содержание кадра, а не мусор.
    м = cv2.GaussianBlur(кожа.astype(np.float32) / 255.0, (0, 0), 3.0)[..., None]
    итог = (кадр * (1 - м) + лучший * м).astype(np.uint8)

    if isinstance(путь_или_кадр, str):
        cv2.imwrite(куда or путь_или_кадр, итог)
    return итог, round(сила, 2), round(шум(итог, кожа), 2)


if __name__ == "__main__":
    import sys
    п = sys.argv[1]
    ц = float(sys.argv[2]) if len(sys.argv) > 2 else 2.77
    _, с, ш = привести(п, ц, sys.argv[3] if len(sys.argv) > 3 else None)
    print(f"{п}: сила {с}, шум стал {ш} при цели {ц}")
