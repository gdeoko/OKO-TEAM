# -*- coding: utf-8 -*-
"""Вывернутые колени и локти по скелетам YOLO.

Прежняя проверка жила на mediapipe и видела ОДНОГО человека: на парной
кнопке вывернутая нога второго проходила мимо неё. YOLO даёт скелет
каждому, поэтому считаем по всем.

Угол меряется только когда видны все три точки сустава: невидимую
кость детектор ставит наугад, и по ней выходит вывернутым каждый
второй верный кадр. Порог 25 градусов - колено и локоть так не
складываются ни в одной позе из наших эталонов.
"""
import os

import numpy as np

ВИДНО = 0.6
ПОРОГ = float(os.environ.get("OKO_SUSTAV_POROG", "25"))
СУСТАВЫ = (("локоть слева", 5, 7, 9), ("локоть справа", 6, 8, 10),
           ("колено слева", 11, 13, 15), ("колено справа", 12, 14, 16))


def кривые(скелеты):
    """Названия вывернутых суставов по всем людям кадра."""
    из = []
    for точки in скелеты:
        for имя, a, b, c in СУСТАВЫ:
            if min(точки[a][2], точки[b][2], точки[c][2]) < ВИДНО:
                continue
            A = np.array(точки[a][:2], dtype=np.float32)
            B = np.array(точки[b][:2], dtype=np.float32)
            C = np.array(точки[c][:2], dtype=np.float32)
            v1, v2 = A - B, C - B
            н = float(np.linalg.norm(v1) * np.linalg.norm(v2))
            if н < 1e-3:
                continue
            к = float(np.dot(v1, v2)) / н
            if np.degrees(np.arccos(np.clip(к, -1, 1))) < ПОРОГ:
                из.append(имя)
    return из
