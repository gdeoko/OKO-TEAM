"""Безлимит на месяц: генерации без коинов, но не без правил.

## Что продаём

Месяц без счётчика коинов за 1 000 $. Внутри месяца:

  * ПЕРВЫЕ 100 РАБОТ идут в быстрой полосе, наравне со всеми, кто
    платит поштучно;
  * ДАЛЬШЕ — безлимитно, но в медленном режиме: задание уходит на
    карту только когда её очередь пуста.

Два режима, а не «бери сколько влезет», по арифметике. Карта одна и
считает по одному заданию за раз. Подписчик, который займёт её
целиком, оставит без генерации всех остальных — а они платят поштучно
и ждать не подряжались.

## Почему это окупается

Карта стоит примерно 88 500 ₽ в месяц, сервер ещё 12 000. Тысяча
долларов по курсу — больше, чем оба вместе. То есть ОДИН подписчик
окупает всю инфраструктуру, даже если займёт карту на весь месяц:
в месяце 730 часов, а его тысяча долларов покрывает по нашей цене
секунды около 840 часов работы карты.

Отсюда и правило ёмкости: один безлимитчик — одна карта. Второго
такого же продавать можно только вместе со второй картой, иначе
медленный режим станет очень медленным у обоих.

## Чего здесь нет

Здесь нет автопродления. Месяц кончился — кончился; человек покупает
заново, если захочет. Молча списывать деньги за следующий месяц с
того, кто про это забыл, мы не будем.
"""

import os

# Цена названа в долларах, рубли считаются по курсу ЦБ (см. `курс.py`).
# Одной цифрой в двух валютах эту цену держать нельзя: рублёвая
# застынет, и однажды мы продадим месяц втрое дешевле долларового.
ДОЛЛАРОВ = int(os.environ.get("AMBERRY_UNLIM_USD", "1000"))

# Сколько работ идёт в быстрой полосе. Стоит нам это копейки: сто фото
# это около 1 500 секунд карты, то есть примерно 50 ₽.
БЫСТРЫХ = int(os.environ.get("AMBERRY_UNLIM_FAST", "100"))

# Длина месяца в сутках. Тридцать, а не «календарный месяц»: человек
# покупает одинаковый срок независимо от того, в феврале он платит или
# в августе.
СУТОК = int(os.environ.get("AMBERRY_UNLIM_DAYS", "30"))

СЕКУНД = СУТОК * 24 * 3600


def рублей():
    """Цена в рублях на сегодня. Считается, а не хранится."""
    import курс
    return курс.в_рублях(ДОЛЛАРОВ)


def это_безлимит(payload):
    """Наш ли это платёж. Метка та же, что кладётся в счёт."""
    return (payload or "").split(":")[0] == "unlim"
