def группа(имя):
    """К какой группе сцен относится сет по своему названию.

    Имя даёт позу и состав («anna-l-and-danny-doggy-style»), но не даёт
    ракурс. Что не опознано, идёт в «прочее» и в пороги не попадает:
    кадр, про который неизвестно, что на нём, портит число молча.
    """
    н = имя.lower()
    # Два имени через «and» это почти всегда пара; пол разберут слова.
    for гр, слова in ПРИЗНАКИ:
        if any(с in н for с in слова):
            return гр
    if "-and-" in н:
        return "пара_мж"
    # Соло-ню это основной жанр площадки, и по словам оно опознаётся
    # хуже всего: название даёт место и настроение («ibiza», «sunset»),
    # а не позу. Половина кадров уходила в «прочее» и в пороги не
    # попадала вовсе, хотя это обычные соло-кадры одного человека.
    return "соло_ню"


def раскладка(папка):
    """Кадры папки по группам сцен. Возвращает {группа: [пути]}."""
    итог = {}
    for и in sorted(os.listdir(папка)):
        if not и.lower().endswith((".jpg", ".jpeg", ".png")):
            continue
        итог.setdefault(группа(и), []).append(os.path.join(папка, и))
    return итог


# Надписи на обложке стоят по краям: логотип справа сверху, название
# справа снизу, подпись фотографа слева вертикально, счётчик кадров
# слева снизу. Середина чистая, её и берём.
ПОЛЯ = (0.12, 0.06, 0.72, 0.94)          # слева, сверху, справа, снизу


def поля_обложки(кадр, поля=ПОЛЯ):
    """Чистая середина обложки, без логотипа и подписей."""
    в, ш = кадр.shape[:2]
    л, вв, п, н = поля
    return кадр[int(в * вв):int(в * н), int(ш * л):int(ш * п)]


def _белый_текст(кадр):
    """Доля площади, занятой белыми надписями. Проверка обрезки.

    Буквы это почти чистый белый и тонкие штрихи. Если после обрезки
    такого больше полупроцента, надпись в кадр всё-таки попала, и
    мерить по нему нельзя.
    """
    сер = cv2.cvtColor(кадр, cv2.COLOR_BGR2GRAY)
    ярко = (сер > 245).astype(np.uint8)
    тонко = cv2.morphologyEx(ярко, cv2.MORPH_OPEN, np.ones((3, 3), np.uint8))
    return 100.0 * float(тонко.sum()) / max(1, тонко.size)


def пороги(папка, мера):
    """Числа эталона по группам сцен.

    `мера` это функция кадра, возвращающая словарь чисел: сюда
    передаётся приёмщик, чтобы эталон и наши кадры мерились ОДНИМ
    кодом. Считается медиана, а не среднее: один неудачный кадр не
    должен двигать порог.
    """
    итог = {}
    for гр, пути in раскладка(папка).items():
        числа = {}
        for п in пути:
            кадр = cv2.imread(п)
            if кадр is None:
                continue
            кадр = поля_обложки(кадр)
            if _белый_текст(кадр) > 0.5:
                continue
            for к, з in (мера(кадр) or {}).items():
                if з is not None:
                    числа.setdefault(к, []).append(float(з))
        итог[гр] = {к: round(float(np.median(в)), 2)
                    for к, в in числа.items() if в}
        итог[гр]["кадров"] = len(пути)
    return итог


