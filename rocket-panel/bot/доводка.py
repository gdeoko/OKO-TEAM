# -*- coding: utf-8 -*-
"""Довести кожу до чисел живого фото. Крапины и шум, обе меры по цели.

## Что нашли и почему это не лечилось раньше

Владелец три дня повторял одно: «точки по телу», «грязь», «каша».
Лечилось это словами в запрете - freckles, moles, dark spots - и не
лечилось никогда. Причина простая: при силе подсказки 1.5 негативная
ветка считается на четверть, а выше эта сборка разваливается. Мы
запрещали крапины текстом, которого модель почти не слышит.

Замер 29.09.2026, крапин на миллион точек кожи:

    входное фото Ники     488
    НАШ КАДР             1984
    живые фото            880

То есть модель выдумывает вдвое больше крапин, чем бывает на коже, и
вчетверо больше, чем было на референсе. Шум при этом 5.83 против 2.8.

## Почему не «убрать всё»

У настоящей кожи крапины ЕСТЬ: родинки, поры, неровность тона. Кадр без
них выходит пластиковым, и это второй дефект, на который владелец
жаловался отдельно. Поэтому цель не ноль, а восемьсот восемьдесят:
срезаем ровно избыток.

## Чем это отличается от прежней ретуши

`ретушь.py` снимала точки поштучно и подставляла медианное размытие.
Замер показал, что от этого хуже: резкость 533 против 475 без неё.
Заплатка оставляет край, а край это новый резкий переход.

Здесь кожа обрабатывается целиком мягким шумодавом с сохранением краёв,
и сила подбирается делением отрезка пополам, пока крапины не сойдутся к
норме. Никаких заплаток, никаких границ.

    from доводка import довести
    довести("/кадр.png")            правит файл на месте
"""
import os

import cv2
import numpy as np

# Нормы живого фото. Крапины считаются на миллион точек кожи, чтобы
# число не зависело от того, сколько тела попало в кадр.
КРАПИН_НОРМА = float(os.environ.get("ROCKET_KRAPIN", "880"))
ШУМ_НОРМА = float(os.environ.get("ROCKET_SHUM", "2.8"))

МАКС_СИЛА = 14.0
ШАГОВ = int(os.environ.get("ROCKET_DOVODKA_STEPS", "6"))


def маска_кожи(кадр):
    """Где кожа. Тот же признак, что у приёмщика, чтобы не разойтись."""
    ycrcb = cv2.cvtColor(кадр, cv2.COLOR_BGR2YCrCb)
    м = cv2.inRange(ycrcb, (0, 133, 77), (255, 180, 127))
    я = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (9, 9))
    м = cv2.morphologyEx(м, cv2.MORPH_OPEN, я)
    return cv2.morphologyEx(м, cv2.MORPH_CLOSE, я)


def меры(кадр, кожа=None):
    """Крапины на миллион точек кожи и шум кожи. Обе как у приёмщика."""
    кожа = кожа if кожа is not None else маска_кожи(кадр)
    если = кожа > 0
    площадь = float(если.sum())
    if площадь < 1000:
        return {"крапин": 0.0, "шум": 0.0}
    сер = cv2.cvtColor(кадр, cv2.COLOR_BGR2GRAY).astype(np.float32)
    # Крапина это локально тёмное пятнышко, а не тень: сравниваем с
    # ОКРЕСТНОСТЬЮ, а не с общей яркостью кадра.
    местное = cv2.GaussianBlur(сер, (0, 0), 25)
    тёмные = ((сер - местное) < -20) & если
    n, _, стат, _ = cv2.connectedComponentsWithStats(тёмные.astype(np.uint8), 8)
    мелких = sum(1 for i in range(1, n)
                 if стат[i, cv2.CC_STAT_AREA] < площадь * 0.0004)
    мед = cv2.medianBlur(сер.astype(np.uint8), 3).astype(np.float32)
    return {"крапин": мелких / max(1.0, площадь / 1e6),
            "шум": float(np.std((сер - мед)[если]))}


def _чистить(кадр, сила):
    """Нелокальные средние: ровная кожа сглаживается, края остаются."""
    if сила <= 0.05:
        return кадр
    return cv2.fastNlMeansDenoisingColored(
        кадр, None, float(сила), float(сила), 7, 21)


def довести(путь_или_кадр, куда=None, крапин=None, шума=None):
    """Срезать избыток крапин и шума. Возвращает (кадр, сила, меры).

    Сила ищется делением отрезка пополам по КРАПИНАМ: они и есть то,
    что владелец видит глазами, а шум идёт за ними следом.
    """
    кадр = (cv2.imread(путь_или_кадр)
            if isinstance(путь_или_кадр, str) else путь_или_кадр)
    if кадр is None:
        return None, 0.0, {}
    цель_к = КРАПИН_НОРМА if крапин is None else float(крапин)
    цель_ш = ШУМ_НОРМА if шума is None else float(шума)
    кожа = маска_кожи(кадр)
    было = меры(кадр, кожа)
    if было["крапин"] <= цель_к * 1.1 and было["шум"] <= цель_ш * 1.1:
        # Уже в норме. Лишний проход только съест фактуру, которой и
        # так в обрез: кадр без единой крапины выходит пластиковым.
        return кадр, 0.0, было

    низ, верх = 0.0, МАКС_СИЛА
    лучший, лучшие, сила = кадр, было, 0.0
    промах = abs(было["крапин"] - цель_к) / max(1.0, цель_к)
    for _ in range(ШАГОВ):
        проба = (низ + верх) / 2
        вышло = _чистить(кадр, проба)
        м = меры(вышло, кожа)
        п = abs(м["крапин"] - цель_к) / max(1.0, цель_к)
        if п < промах:
            лучший, лучшие, сила, промах = вышло, м, проба, п
        if м["крапин"] > цель_к:
            низ = проба
        else:
            верх = проба

    # Чистим ТОЛЬКО кожу. Волосы, глаза, ткань и фон остаются как были:
    # там мелкая деталь это содержание кадра, а не мусор.
    м = cv2.GaussianBlur(кожа.astype(np.float32) / 255.0, (0, 0), 3.0)[..., None]
    итог = (кадр * (1 - м) + лучший * м).astype(np.uint8)
    if isinstance(путь_или_кадр, str):
        cv2.imwrite(куда or путь_или_кадр, итог)
    стало = меры(итог, кожа)
    print(f"доводка: крапин {было['крапин']:.0f} -> {стало['крапин']:.0f} "
          f"(норма {цель_к:.0f}), шум {было['шум']:.2f} -> {стало['шум']:.2f} "
          f"(норма {цель_ш:.2f}), сила {сила:.1f}", flush=True)
    return итог, round(сила, 2), стало


if __name__ == "__main__":
    import sys
    довести(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
