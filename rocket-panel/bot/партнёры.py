"""Копии бота у партнёров: поднять, погасить, спросить состояние.

## Зачем прослойка, а если можно звать скрипт напрямую

Её зовут из ДВУХ мест - из бота (когда партнёр прислал токен) и из
админки (рубильник у владельца). Пока команда собиралась бы на месте,
эти два места разъехались бы: в одном забыли бы таймаут, в другом
записали бы токен в журнал.

## Почему через sudo, а не от root

Бот работает под пользователем `amberry` и не имеет права на
`systemctl` - и не должен иметь. Правило в `/etc/sudoers.d` разрешает
ему ровно одну команду: наш скрипт, и ничего больше. `sudo systemctl`
дал бы боту возможность перезапустить что угодно на сервере, включая
админку и резервное копирование.

## Токен в журнал не попадает

`пуск()` получает ключ от чужого бота. В `print` уходит только tg_id и
итог; сам токен не печатается ни при удаче, ни при ошибке - в том
числе когда скрипт вернул его в тексте своей жалобы (отсюда `почистить`).

## Нет скрипта - нет беды

На машине разработчика и в тестах скрипта нет. Все три функции в этом
случае честно отвечают «не вышло» и говорят почему, а не роняют
обработчик сообщения: франшиза не должна ломать бота, который её
продаёт.
"""

import os
import subprocess

СКРИПТ = os.environ.get("AMBERRY_PARTNER_CMD",
                        "/usr/local/sbin/amberry-partner")

# Пуск ждёт телеграм (getMe) и три секунды смотрит, поднялась ли
# служба. Шестьдесят секунд - с запасом на медленный ответ телеграма,
# но не настолько, чтобы обработчик сообщения завис навсегда.
ЖДЁМ = 60


def _позвать(*аргументы, ждём=ЖДЁМ):
    """(получилось, что сказал скрипт)."""
    if not os.path.exists(СКРИПТ):
        return False, "на сервере нет скрипта запуска копий"
    try:
        п = subprocess.run(["sudo", "-n", СКРИПТ, *аргументы],
                           capture_output=True, text=True, timeout=ждём)
    except subprocess.TimeoutExpired:
        return False, "запуск не уложился в срок"
    except Exception as e:                              # noqa: BLE001
        return False, str(e)[:160]
    сказал = (п.stdout + "\n" + п.stderr).strip()
    return п.returncode == 0, сказал[-300:]


def почистить(текст, токен):
    """Убрать токен из текста, который пойдёт в журнал или на экран."""
    т = (токен or "").strip()
    return (текст or "").replace(т, "…" + т[-6:]) if т else (текст or "")


def пуск(tg_id, токен, имя=""):
    """Поднять копию. (получилось, что сказал скрипт)."""
    ок, сказал = _позвать("пуск", str(int(tg_id)), str(токен).strip(),
                          (имя or "").lstrip("@"))
    сказал = почистить(сказал, токен)
    print("копия партнёра %s: %s" % (tg_id, "поднята" if ок else сказал),
          flush=True)
    return ок, сказал


def стоп(tg_id):
    """Погасить копию. Данные партнёра остаются на месте."""
    ок, сказал = _позвать("стоп", str(int(tg_id)), ждём=30)
    print("копия партнёра %s: %s" % (tg_id, "погашена" if ок else сказал),
          flush=True)
    return ок, сказал


def работает(tg_id):
    """Жива ли копия прямо сейчас.

    Спрашиваем систему, а не свою же колонку в базе: колонка
    показывает, что мы ХОТЕЛИ, а владельцу в админке нужно видеть, что
    ЕСТЬ. Упавшая копия расходится с колонкой молча.
    """
    ок, сказал = _позвать("состояние", str(int(tg_id)), ждём=20)
    return сказал.strip() == "active"
