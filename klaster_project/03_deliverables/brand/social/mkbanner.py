#!/usr/bin/env python3
"""Обложка канала YouTube: сгенерированный фон плюс настоящий знак и текст.

Всё, что должно быть видно на телефоне, лежит внутри безопасной зоны
1546 на 423 в середине кадра 2560 на 1440. На телевизоре видно весь кадр,
на компьютере широкую полосу, поэтому по краям только фон.

  python3 mkbanner.py <фон.jpg> <эмблема.png> <куда.jpg>
"""
import sys
from PIL import Image, ImageDraw, ImageFont, ImageFilter

ФОН, ЗНАК, КУДА = sys.argv[1], sys.argv[2], sys.argv[3]

Ш, В = 2560, 1440
БШ, БВ = 1546, 423                      # безопасная зона
БX, БY = (Ш - БШ) // 2, (В - БВ) // 2

ШР = "/usr/share/fonts/truetype/oko/"
oswald = lambda р: ImageFont.truetype(ШР + "Oswald-Bold.ttf", р)
mont   = lambda р, н="SemiBold": ImageFont.truetype(ШР + "Montserrat-%s.ttf" % н, р)

ЗОЛОТО = (224, 188, 90)
СВЕТ   = (238, 240, 244)
СЕРЫЙ  = (168, 176, 190)

# ---- фон: вписываем в 2560x1440 по центру ----
ф = Image.open(ФОН).convert("RGB")
к = max(Ш / ф.width, В / ф.height)
ф = ф.resize((round(ф.width * к), round(ф.height * к)), Image.LANCZOS)
ф = ф.crop(((ф.width - Ш) // 2, (ф.height - В) // 2,
            (ф.width - Ш) // 2 + Ш, (ф.height - В) // 2 + В))

# ---- притемняем середину, чтобы текст читался на любом фоне ----
тень = Image.new("L", (Ш, В), 0)
д = ImageDraw.Draw(тень)
д.rectangle([БX - 150, БY - 90, БX + БШ + 150, БY + БВ + 90], fill=150)
тень = тень.filter(ImageFilter.GaussianBlur(120))
ф = Image.composite(Image.new("RGB", (Ш, В), (9, 11, 15)), ф, тень)

кадр = ф.convert("RGBA")
d = ImageDraw.Draw(кадр)

# ---- знак слева в безопасной зоне ----
з = Image.open(ЗНАК).convert("RGBA")
высота_знака = 268
з = з.resize((round(з.width * высота_знака / з.height), высота_знака), Image.LANCZOS)

# ---- считаем блок текста заранее, чтобы ничего не налезало ----
ф_имя  = oswald(150)
ф_под  = mont(31)
ф_факт = mont(35, "Regular")
ф_связь = mont(37)

ПОДПИСЬ = "Б И З Н Е С - П А Р К   ·   М О С К В А ,   Ю А О"
ФАКТЫ   = "Производство · Склад · Офис · от 100 до 12 000 м²"
СВЯЗЬ   = "clusterspace.ru      8 985 331-02-71"

def высота(текст, шрифт):
    a, b, c, d2 = шрифт.getbbox(текст)
    return d2 - b, b

в_имя,  сдв_имя  = высота("КЛАСТЕР", ф_имя)
в_под,  сдв_под  = высота(ПОДПИСЬ, ф_под)
в_факт, сдв_факт = высота(ФАКТЫ, ф_факт)
в_связь, сдв_связь = высота(СВЯЗЬ, ф_связь)

ЗАЗОР1, ЗАЗОР2, ЗАЗОР3, ЗАЗОР4 = 26, 30, 24, 20   # между строками и вокруг линии
блок = в_имя + ЗАЗОР1 + в_под + ЗАЗОР2 + ЗАЗОР3 + в_факт + ЗАЗОР4 + в_связь
верх = БY + (БВ - блок) // 2

# знак по центру блока текста
зx = БX + 8
зy = БY + (БВ - высота_знака) // 2
кадр.paste(з, (зx, зy), з)

x = зx + з.width + 60
y = верх

d.text((x, y - сдв_имя), "КЛАСТЕР", font=ф_имя, fill=ЗОЛОТО)
y += в_имя + ЗАЗОР1

d.text((x + 4, y - сдв_под), ПОДПИСЬ, font=ф_под, fill=СВЕТ)
y += в_под + ЗАЗОР2

d.line([(x + 4, y), (БX + БШ - 30, y)], fill=(224, 188, 90, 110), width=2)
y += ЗАЗОР3

d.text((x + 4, y - сдв_факт), ФАКТЫ, font=ф_факт, fill=СЕРЫЙ)
y += в_факт + ЗАЗОР4

d.text((x + 4, y - сдв_связь), СВЯЗЬ, font=ф_связь, fill=СВЕТ)

итог = кадр.convert("RGB")
итог.save(КУДА, quality=92, subsampling=0, optimize=True)

# контрольный кадр: что увидит телефон
итог.crop((БX, БY, БX + БШ, БY + БВ)).save(КУДА.replace(".jpg", "-safe.jpg"), quality=90)
print("готово:", КУДА, итог.size)
