    if ($новый && empty(($d['участники'][(string)$uid] ?? [])['анкета'])) {
        сказать($чат,
            "Ответьте на три коротких вопроса — на туре подойдём к вам с готовой подборкой блоков под ваш запрос.",
            [[['text' => 'Ответить (1 минута)', 'callback_data' => 'anketa']],
             [['text' => 'Позже', 'callback_data' => 'menu']]]);
    }
}

function старт($чат, $uid, $из, $аргумент) {
    global $СОБЫТИЕ, $КФ;
    шаг_анкеты($uid, false);                       // любой /start прерывает анкету
    if (strpos($аргумент, 'ref_') === 0) запомнить_реферала($uid, substr($аргумент, 4));
    $есть = isset(база()['участники'][(string)$uid]);
    list($да, $почему) = подписан($uid);
    // Гейт включается только когда бот реально может проверить и человек не подписан.
    if (!$да && $почему === 'не_подписан') {
        if ($есть) {
            сказать($чат,
                "Чтобы открыть билет и рейтинг, верните подписку на канал «Кластера» и нажмите «Я подписался». "
              . "Билет никуда не делся.",
                [[['text' => '📢 Подписаться на канал', 'url' => $КФ['channel_url']]],
                 [['text' => '✅ Я подписался', 'callback_data' => 'proverit']]]);
        } else {
            $n = count(база()['участники']);
            $соц = $n >= 10 ? "Уже зарегистрировано {$n} брокеров.\n\n" : '';
            сказать($чат,
                "<b>{$СОБЫТИЕ['название']}</b>\n{$СОБЫТИЕ['дата']}, {$СОБЫТИЕ['время']}. {$СОБЫТИЕ['адрес']}\n\n"
              . $соц
              . "Один шаг до билета: подпишитесь на канал «Кластера» и нажмите «Я подписался». "
              . "Билет и ссылка для приглашений придут сразу.",
                [[['text' => '📢 Подписаться на канал', 'url' => $КФ['channel_url']]],
                 [['text' => '✅ Я подписался', 'callback_data' => 'proverit']]]);
        }
        return;
    }
    list($новый, $привёл) = зарегистрировать($uid, $из);
    выдать_билет($чат, $uid, $новый || !$есть, $новый);
    if ($новый && $привёл) {
        сказать((int)$привёл, "По вашей ссылке зарегистрировался ещё один участник. "
              . 'Всего приглашено: <b>' . баллы(база(), $привёл) . '</b>.');
    }
}

function показать_приглашение($чат, $uid) {
    $d = база();
    $с = $d['участники'][(string)$uid] ?? null;
    if (!$с) { сказать($чат, 'Сначала получите билет: /start', null, true); return; }
    $сс = ссылка_приглашения($с['код']);
    $поделиться = 'https://t.me/share/url?url=' . rawurlencode($сс) . '&text='
        . rawurlencode('Брокер-тур «Кластер» 2 сентября: свободные блоки, планы корпусов и цифры по объекту. Регистрация по ссылке.');
    сказать($чат,
        "<b>Ваша ссылка для приглашений</b>\n<code>" . htmlspecialchars($сс) . "</code>\n\n"
      . 'Приглашено коллег: <b>' . баллы($d, $uid) . "</b>\n\n"
      . "Отправьте её коллегам-брокерам. Балл засчитывается, когда человек сам заканчивает регистрацию.",
        [[['text' => 'Отправить коллеге', 'url' => $поделиться]]]);
}

