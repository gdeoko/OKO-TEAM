function читать($путь, $по_умолчанию = []) {
    if (!is_file($путь)) return $по_умолчанию;
    $d = json_decode((string)file_get_contents($путь), true);
    return is_array($d) ? $d : $по_умолчанию;
}

/** Запись под блокировкой с атомарной подменой: читатель никогда не видит
 *  усечённый файл, потому что новую версию пишем во временный и rename(). */
function изменить($путь, callable $что) {
    @mkdir(dirname($путь), 0775, true);
    $замок = fopen($путь . '.lock', 'c');
    if ($замок) flock($замок, LOCK_EX);
    $d = json_decode((string)@file_get_contents($путь), true);
    if (!is_array($d)) $d = [];
    $d = $что($d);
    $врем = $путь . '.' . getmypid() . '.tmp';
    file_put_contents($врем, json_encode($d, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT));
    @rename($врем, $путь);
    if ($замок) { flock($замок, LOCK_UN); fclose($замок); }
    return $d;
}

