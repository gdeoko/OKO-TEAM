/**
 * Фиксация победителей с повторной проверкой подписки: тот, кто вошёл, набрал
 * баллы и вышел из канала, не занимает место у выполнивших условие до конца.
 * При недоступном API не фиксируем ничего.
 */
function победители($предел = null) {
    global $КФ;
    $предел = $предел ?: $КФ['prizes'];
    $из = "<b>Победители по приглашениям</b>\n\n";
    $взяли = 0; $мимо = 0;
    foreach (рейтинг(база()) as $р) {
        list($да, $почему) = подписан((int)$р['uid']);
        if (!$да && ($почему === 'сбой' || $почему === 'нет_канала')) {
            return $из . 'Проверка подписок сейчас недоступна. Победители не зафиксированы: '
                 . 'проверьте канал и права бота, затем повторите.';
        }
        if (!$да) { $мимо++; continue; }
        $взяли++;
        $знак = $взяли === 1 ? '🥇' : ($взяли === 2 ? '🥈' : '🥉');
        $из .= $знак . ' ' . htmlspecialchars((string)($р['имя'] ?? 'участник'))
             . ' — <b>' . (int)$р['баллы'] . '</b> <code>' . $р['uid'] . "</code>\n";
        if ($взяли >= $предел) break;
    }
    if (!$взяли) $из .= "Пока нет участников с подтверждённой подпиской.\n";
    if ($мимо)  $из .= "\nНе прошли повторную проверку: {$мимо}.";
    return $из;
}

