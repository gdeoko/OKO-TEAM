function читать($путь, $по_умолчанию = []) {
    if (!is_file($путь)) return $по_умолчанию;
    $d = json_decode((string)file_get_contents($путь), true);
    return is_array($d) ? $d : $по_умолчанию;
}

/** Запись под блокировкой: два одновременных нажатия не должны затирать друг друга. */
function изменить($путь, callable $что) {
    @mkdir(dirname($путь), 0775, true);
    $f = fopen($путь, 'c+');
    if (!$f) return null;
    flock($f, LOCK_EX);
    $сыро = stream_get_contents($f);
    $d = json_decode((string)$сыро, true);
    if (!is_array($d)) $d = [];
    $d = $что($d);
    ftruncate($f, 0); rewind($f);
    fwrite($f, json_encode($d, JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT));
    fflush($f); flock($f, LOCK_UN); fclose($f);
    return $d;
}

