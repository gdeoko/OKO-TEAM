function код($uid)             { global $КФ; return strtoupper(substr(hash_hmac('sha256', 'tour:' . $uid, $КФ['salt']), 0, 10)); }
function ссылка_приглашения($к){ global $КФ; return 'https://t.me/' . $КФ['bot'] . '?start=ref_' . rawurlencode($к); }

function имя_из($из) {
    $н = trim((string)($из['first_name'] ?? '') . ' ' . (string)($из['last_name'] ?? ''));
    if ($н === '' && !empty($из['username'])) $н = '@' . $из['username'];
    return mb_substr($н !== '' ? $н : 'участник', 0, 80);
}

function запомнить_реферала($uid, $к) {
    $к = strtoupper(preg_replace('~[^A-F0-9]~', '', (string)$к));
    if ($к === '') return;
    изменить(ФАЙЛ_УЧАСТНИКОВ, function ($d) use ($uid, $к) {
        $d['участники'] = $d['участники'] ?? [];
        $d['ожидают']   = $d['ожидают'] ?? [];
        if (!isset($d['участники'][(string)$uid])) $d['ожидают'][(string)$uid] = $к;
        return $d;
    });
}

/** [новый, кто_привёл]. */
function зарегистрировать($uid, $из) {
    $новый = false; $привёл = null;
    изменить(ФАЙЛ_УЧАСТНИКОВ, function ($d) use ($uid, $из, &$новый, &$привёл) {
        $d['участники'] = $d['участники'] ?? [];
        $d['ожидают']   = $d['ожидают'] ?? [];
        $d['счётчик']   = $d['счётчик'] ?? 0;
        $ключ = (string)$uid;
        if (isset($d['участники'][$ключ])) { $привёл = $d['участники'][$ключ]['привёл'] ?? null; return $d; }
        $мой = код($uid);
        $чужой = strtoupper((string)($d['ожидают'][$ключ] ?? ''));
        if ($чужой !== '' && $чужой !== $мой) {
            foreach ($d['участники'] as $rid => $стр) {
                if (strtoupper((string)($стр['код'] ?? '')) === $чужой && (string)$rid !== $ключ) { $привёл = (string)$rid; break; }
            }
        }
        $d['счётчик']++;
        $d['участники'][$ключ] = [
            'код' => $мой, 'номер' => $d['счётчик'], 'имя' => имя_из($из),
            'ник' => mb_substr((string)($из['username'] ?? ''), 0, 64),
            'когда' => date('Y-m-d H:i:s'), 'привёл' => $привёл, 'анкета' => [], 'формат' => '',
        ];
        unset($d['ожидают'][$ключ]);
        $новый = true;
        return $d;
    });
    return [$новый, $привёл];
}

function баллы($d, $uid) {
    $n = 0;
    foreach ((array)($d['участники'] ?? []) as $с) if ((string)($с['привёл'] ?? '') === (string)$uid) $n++;
    return $n;
}

function рейтинг($d) {
    $ряды = [];
    foreach ((array)($d['участники'] ?? []) as $uid => $с) { $с['uid'] = (string)$uid; $с['баллы'] = баллы($d, $uid); $ряды[] = $с; }
    usort($ряды, function ($a, $b) {
        if ($a['баллы'] !== $b['баллы']) return $b['баллы'] <=> $a['баллы'];
        return strcmp((string)($a['когда'] ?? ''), (string)($b['когда'] ?? ''));
    });
    return $ряды;
}

