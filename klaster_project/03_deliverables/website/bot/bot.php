/** Фиксация победителей: повторная проверка подписки только по кандидатам топа,
 *  один транзиентный сбой не обрывает список. */
function победители($предел = null) {
    global $КФ;
    $предел = $предел ?: $КФ['prizes'];
    $кандидаты = array_slice(рейтинг(база()), 0, max($предел * 3, 10));
    $из = "<b>Топ по приглашениям</b>\n\n";
    $взяли = 0; $мимо = 0; $непроверено = 0;
    foreach ($кандидаты as $р) {
        if ((int)$р['баллы'] === 0) break;
        list($да, $почему) = подписан((int)$р['uid']);
        if (!$да && ($почему === 'сбой' || $почему === 'нет_канала')) { $непроверено++; $да = true; }
        if (!$да) { $мимо++; continue; }
        $взяли++;
        $знак = $взяли === 1 ? '🥇' : ($взяли === 2 ? '🥈' : ($взяли === 3 ? '🥉' : '·'));
        $из .= $знак . ' ' . htmlspecialchars((string)($р['имя'] ?? 'участник'))
             . ' — <b>' . (int)$р['баллы'] . '</b> <code>' . $р['uid'] . "</code>\n";
        if ($взяли >= $предел) break;
    }
    if (!$взяли) $из .= "Пока нет приглашений.\n";
    if ($мимо)        $из .= "\nОтписались от канала: {$мимо}.";
    if ($непроверено) $из .= "\nПодписку не удалось проверить (бот не админ канала): {$непроверено}.";
    return $из;
}

