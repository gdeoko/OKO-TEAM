/**
 * [подписан, причина]. «сбой»/«нет_канала» это НЕ «не подписан»: по такому
 * ответу гейт не включаем, билет выдаём.
 */
function подписан($uid) {
    global $КФ;
    if ($КФ['channel'] === '') return [false, 'нет_канала'];
    $о = тг('getChatMember', ['chat_id' => $КФ['channel'], 'user_id' => (int)$uid]);
    if (empty($о['ok']) || empty($о['result'])) return [false, 'сбой'];
    $с = (string)($о['result']['status'] ?? '');
    $да = in_array($с, ['creator', 'administrator', 'member'], true)
       || ($с === 'restricted' && !empty($о['result']['is_member']));
    return [$да, $да ? 'ok' : 'не_подписан'];
}

