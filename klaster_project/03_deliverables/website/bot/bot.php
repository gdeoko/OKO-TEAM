/* ── Telegram ──────────────────────────────────────────────────────────── */

function тг($метод, array $поля = []) {
    global $КФ;
    $c = curl_init('https://api.telegram.org/bot' . $КФ['token'] . '/' . $метод);
    curl_setopt_array($c, [
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_POST           => true,
        CURLOPT_POSTFIELDS     => json_encode($поля, JSON_UNESCAPED_UNICODE),
        CURLOPT_HTTPHEADER     => ['Content-Type: application/json'],
        CURLOPT_TIMEOUT        => 25,
    ]);
    if (!empty($КФ['proxy'])) curl_setopt($c, CURLOPT_PROXY, $КФ['proxy']);
    $о = curl_exec($c);
    curl_close($c);
    $d = json_decode((string)$о, true);
    return is_array($d) ? $d : ['ok' => false];
}

function сказать($чат, $текст, $кнопки = null) {
    $поля = ['chat_id' => $чат, 'text' => $текст, 'parse_mode' => 'HTML',
             'link_preview_options' => ['is_disabled' => true]];
    if ($кнопки) $поля['reply_markup'] = ['inline_keyboard' => $кнопки];
    return тг('sendMessage', $поля);
}

/**
 * Возвращает [подписан, причина]. Причина «сбой» это не «не подписан»:
 * решения по такому ответу принимать нельзя.
 */
function подписан($uid) {
    global $КФ;
    if ($КФ['channel'] === '') return [false, 'нет_канала'];
    $о = тг('getChatMember', ['chat_id' => $КФ['channel'], 'user_id' => (int)$uid]);
    if (empty($о['ok']) || empty($о['result'])) return [false, 'сбой'];
    $с = (string)($о['result']['status'] ?? '');
    $да = in_array($с, ['creator', 'administrator', 'member'], true)
       || ($с === 'restricted' && !empty($о['result']['is_member']));
    return [$да, $да ? 'ok' : 'не_подписан'];
}

