    case 'настройки':
        $п = площадки();
        $подключено = [];
        foreach ($п['площадки'] as $к => $о) {
            $подключено[$к] = ['имя' => $о['имя'], 'адрес' => $о['адрес'],
                               'снимается' => $о['данные'] !== null];
        }
        ответ([
            'площадки' => $подключено,
            'трекер' => ['стоит' => is_dir(СОБЫТИЯ), 'событий_сегодня' =>
                is_file(СОБЫТИЯ . '/' . date('Y-m-d') . '.jsonl')
                    ? count(file(СОБЫТИЯ . '/' . date('Y-m-d') . '.jsonl', FILE_SKIP_EMPTY_LINES)) : 0],
            'сборщик' => ['последний_запуск' => площадки()['обновлено']],
            'уведомления' => настройки()['уведомления'] ?? null,
        ]);

    case 'выгрузка':
        отдать_csv((string)($_GET['таблица'] ?? 'заявки'));

    default:
        ответ(['ошибка' => 'не знаю такой ручки: ' . $что], 404);
}
