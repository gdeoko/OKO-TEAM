/* ---------- площадки ---------- */

function площадки(): array {
    $д = читать_json(ДАННЫЕ . '/social.json');
    $список = [
        'telegram'  => ['имя' => 'Telegram',   'адрес' => 'https://t.me/radialnya'],
        'youtube'   => ['имя' => 'YouTube',    'адрес' => 'https://www.youtube.com/@klasterofficial'],
        'instagram' => ['имя' => 'Instagram',  'адрес' => 'https://www.instagram.com/klasterofficial/'],
        'dzen'      => ['имя' => 'Дзен',       'адрес' => 'https://dzen.ru/id/6a7efef4e6a5266cd0d106ba'],
        'vc'        => ['имя' => 'vc.ru',      'адрес' => 'https://vc.ru/'],
        'vk'        => ['имя' => 'ВКонтакте',  'адрес' => ''],
    ];
    $из = [];
    foreach ($список as $ключ => $о) {
        $снято = $д['площадки'][$ключ] ?? null;
        // Сборщиков два и пишут они по-разному. Питоновский кладёт всё в
        // «метрики» с вложенным «значение», браузерный пишет плоско.
        // Приводим к одному виду, чтобы панель не знала про эту разницу.
        if (is_array($снято)) {
            if (isset($снято['метрики']) && is_array($снято['метрики'])) {
                foreach ($снято['метрики'] as $имя => $м) {
                    $з = is_array($м) ? ($м['значение'] ?? null) : $м;
                    if ($з === null) continue;
                    $имя = ($имя === 'подписчики') ? 'подписчиков' : $имя;
                    if (!isset($снято[$имя])) $снято[$имя] = $з;
                }
            }
            if (!isset($снято['подписчиков']) && isset($снято['подписчики'])) {
                $снято['подписчиков'] = $снято['подписчики'];
            }
        }
        // запись с полем «ошибка» это не данные, а объяснение, почему их нет
        $живое = is_array($снято) && !isset($снято['ошибка']) && isset($снято['подписчиков']);
        $из[$ключ] = [
            'имя'   => $о['имя'],
            'адрес' => $о['адрес'],
            'данные' => $живое ? $снято : null,
            'почему' => $живое ? '' : ($ключ === 'vk'
                ? 'Сообщество заводит клиент, ждём ссылку.'
                : (is_array($снято) && !empty($снято['ошибка'])
                    ? (string)$снято['ошибка']
                    : 'Сборщик метрик ещё не отработал первый раз.')),
        ];
    }
    return [
        'обновлено' => $д['обновлено'] ?? null,
        'площадки'  => $из,
        'история'   => $д['история'] ?? null,
    ];
}


/* ---------- публикации ---------- */

/** Реестр публикаций: что и куда вышло, с метриками по каждой.
    Пишут его агенты постинга и сборщик метрик, панель только читает. */
function публикации(): array {
    $д = читать_json(ДАННЫЕ . '/posts.json');
    $записи = is_array($д['записи'] ?? null) ? $д['записи'] : [];
    usort($записи, fn($a, $b) => strcmp((string)($b['когда'] ?? ''), (string)($a['когда'] ?? '')));

    $итог = ['постов' => 0, 'просмотров' => 0, 'лайков' => 0, 'комментариев' => 0,
             'репостов' => 0, 'переходов' => 0, 'сохранений' => 0];
    $по_площадкам = [];
    foreach ($записи as $з) {
        $итог['постов']++;
        $п = (string)($з['площадка'] ?? '?');
        $по_площадкам[$п] ??= ['постов' => 0, 'просмотров' => 0, 'лайков' => 0,
                               'комментариев' => 0, 'репостов' => 0, 'переходов' => 0];
        $по_площадкам[$п]['постов']++;
        foreach (['просмотров', 'лайков', 'комментариев', 'репостов', 'переходов', 'сохранений'] as $м) {
            $v = $з['метрики'][$м] ?? null;
            if (is_int($v)) {
                $итог[$м] += $v;
                if (isset($по_площадкам[$п][$м])) $по_площадкам[$п][$м] += $v;
            }
        }
    }
    // переходы на сайт с площадок берём из трекера, это надёжнее счётчиков площадок
    $соб = события(30);
    $с_площадок = [];
    foreach ($соб as $с) {
        if (($с['t'] ?? '') !== 'view' || !empty($с['bot'])) continue;
        $и = откуда($с);
        if (in_array($и, ['Telegram', 'Instagram', 'YouTube', 'Дзен', 'vc.ru', 'ВКонтакте'], true)) {
            $с_площадок[$и] = ($с_площадок[$и] ?? 0) + 1;
        }
    }
    return [
        'записи' => $записи,
        'итог' => $итог,
        'по_площадкам' => $по_площадкам,
        'переходы_с_площадок' => $с_площадок,
        'почему' => $записи ? '' :
            'Публикаций ещё не было. Как выйдет первый пост, он встанет сюда вместе с просмотрами, реакциями и переходами на сайт.',
    ];
}

