/* ---------- CSV ---------- */

function отдать_csv(string $таблица): never {
    $строки = match ($таблица) {
        'заявки'      => заявки(),
        'подписчики'  => подписчики()['база'],
        'события'     => события(30),
        'публикации'  => публикации()['записи'],
        default       => [],
    };
    header('Content-Type: text/csv; charset=utf-8');
    header('Content-Disposition: attachment; filename="klaster-' . $таблица . '-' . date('Y-m-d') . '.csv"');
    $вых = fopen('php://output', 'w');
    fprintf($вых, chr(0xEF) . chr(0xBB) . chr(0xBF));   // BOM, чтобы Excel не ломал кириллицу
    if ($строки) {
        $ключи = array_keys((array)$строки[0]);
        fputcsv($вых, $ключи, ';');
        foreach ($строки as $с) {
            $r = [];
            foreach ($ключи as $к) {
                $v = ((array)$с)[$к] ?? '';
                $r[] = is_scalar($v) ? (string)$v : json_encode($v, JSON_UNESCAPED_UNICODE);
            }
            fputcsv($вых, $r, ';');
        }
    } else {
        fputcsv($вых, ['данных нет'], ';');
    }
    fclose($вых);
    exit;
}

