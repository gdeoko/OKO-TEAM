const ДАННЫЕ   = '/var/www/klaster-data';
const СОБЫТИЯ  = ДАННЫЕ . '/events';
const ПОЯС     = 'Europe/Moscow';
const КУКА     = 'klaster_admin';
const ЖИЗНЬ    = 86400 * 7;

