        $из = [];
        if (is_file($ф)) {
            $строки = array_slice(file($ф, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES), -200);
            foreach (array_reverse($строки) as $с) {
                $д = json_decode($с, true);
                if (is_array($д)) $из[] = $д;
