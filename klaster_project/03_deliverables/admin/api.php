/* ---------- мелочи ---------- */

function ответ(array $д, int $код = 200): never {
    http_response_code($код);
    echo json_encode($д, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    exit;
}

function читать_json(string $путь): mixed {
    if (!is_file($путь)) return null;
    $с = @file_get_contents($путь);
    if ($с === false || $с === '') return null;
    $д = json_decode($с, true);
    return is_array($д) ? $д : null;
}

/** Единый вид «метрики нет»: панель по нему рисует честную заглушку. */
function нет_данных(string $почему, string $когда_будет = ''): array {
    return ['значение' => null, 'нет_данных' => true,
            'почему' => $почему, 'когда' => $когда_будет];
}

function настройки(): array {
    $ф = ДАННЫЕ . '/admin_config.json';
    $д = читать_json($ф);
    return is_array($д) ? $д : [];
}

/* ---------- вход ---------- */

function секрет(): string {
    $ф = ДАННЫЕ . '/admin_secret.txt';
    if (!is_file($ф)) {
        $s = bin2hex(random_bytes(32));
        @file_put_contents($ф, $s);
        @chmod($ф, 0600);
        return $s;
    }
    return trim((string)file_get_contents($ф));
}

function хеш_пароля(): string {
    $ф = ДАННЫЕ . '/admin_pass.txt';
    return is_file($ф) ? trim((string)file_get_contents($ф)) : '';
}

function выдать_куку(): void {
    $до = time() + ЖИЗНЬ;
    $тело = $до . '.' . hash_hmac('sha256', (string)$до, секрет());
    setcookie(КУКА, $тело, [
        'expires' => $до, 'path' => '/', 'httponly' => true,
        'samesite' => 'Strict', 'secure' => true,
    ]);
}

function вошли(): bool {
    $к = (string)($_COOKIE[КУКА] ?? '');
    if (!str_contains($к, '.')) return false;
    [$до, $подпись] = explode('.', $к, 2);
    if (!ctype_digit($до) || (int)$до < time()) return false;
    return hash_equals(hash_hmac('sha256', $до, секрет()), $подпись);
}

function требуем_вход(): void {
    if (!вошли()) ответ(['ошибка' => 'нужен вход'], 401);
}

/* ---------- журнал действий ---------- */

function записать_в_журнал(string $что, array $ещё = []): void {
    $строка = json_encode(array_merge(
        ['время' => date('c'), 'что' => $что,
         'ip' => substr(hash('sha256', ($_SERVER['REMOTE_ADDR'] ?? '') . секрет()), 0, 12)],
        $ещё), JSON_UNESCAPED_UNICODE);
    @file_put_contents(ДАННЫЕ . '/admin_log.jsonl', $строка . "\n", FILE_APPEND | LOCK_EX);
}

/* ---------- события трекера ---------- */

/** Читает события за N дней. Возвращает плоский список. */
function события(int $дней = 30): array {
    $из = [];
    for ($i = 0; $i < $дней; $i++) {
        $ф = СОБЫТИЯ . '/' . date('Y-m-d', strtotime("-$i days")) . '.jsonl';
        if (!is_file($ф)) continue;
        $fh = @fopen($ф, 'r');
        if (!$fh) continue;
        while (($с = fgets($fh)) !== false) {
            $д = json_decode(trim($с), true);
            if (is_array($д)) $из[] = $д;
        }
        fclose($fh);
    }
    return $из;
}

function пусто_по_дням(int $дней): array {
    $из = [];
    for ($i = $дней - 1; $i >= 0; $i--) $из[date('Y-m-d', strtotime("-$i days"))] = 0;
    return $из;
}

function свод_сайта(int $дней = 30): array {
    /* Разбираем то, что реально пишет track.php. Ключи у него короткие:
       t тип, srv время сервера, d день, sid сессия, vid посетитель, u адрес,
       ref откуда пришли, dev устройство, sd глубина прокрутки, dur секунды,
       el цель нажатия, bot признак робота. Роботов в счёт не берём. */
    $соб = события($дней);
    $по_дням    = пусто_по_дням($дней);
    $сессии     = [];
    $посетители = [];
    $источники  = [];
    $страницы   = [];
    $устройства = [];
    $клики      = [];
    $глубина    = ['25' => 0, '50' => 0, '75' => 0, '100' => 0];
    $время      = [];
    $воронка    = ['заход' => 0, 'подбор' => 0, 'форма_начата' => 0, 'форма_отправлена' => 0];

    foreach ($соб as $с) {
        if (!empty($с['bot'])) continue;                 // робот, не человек
        $тип = (string)($с['t'] ?? '');
        $день = (string)($с['d'] ?? substr((string)($с['srv'] ?? ''), 0, 10));
        $сид = (string)($с['sid'] ?? '');
        $вид = (string)($с['vid'] ?? '');

        if ($тип === 'view') {
            if (isset($по_дням[$день])) $по_дням[$день]++;
            $воронка['заход']++;
            $стр = (string)($с['u'] ?? '/');
            $страницы[$стр] = ($страницы[$стр] ?? 0) + 1;

            $ист = откуда($с);
            $источники[$ист] = ($источники[$ист] ?? 0) + 1;

            $у = (string)($с['dev'] ?? 'desktop');
            $устройства[имя_устройства($у)] = ($устройства[имя_устройства($у)] ?? 0) + 1;

            if ($сид !== '') $сессии[$сид] = 1;
            if ($вид !== '') $посетители[$вид] = 1;
        }
        if ($тип === 'click') {
            $ц = (string)($с['el'] ?? 'other');
            $клики[$ц] = ($клики[$ц] ?? 0) + 1;
            if ($ц === 'selector') $воронка['подбор']++;
        }
        if ($тип === 'scroll') {
            $п = (int)($с['sd'] ?? 0);
            foreach ([100, 75, 50, 25] as $порог) {
                if ($п >= $порог) { $глубина[(string)$порог]++; break; }
            }
        }
        if ($тип === 'time' || $тип === 'exit') {
            $д = (int)($с['dur'] ?? 0);
            if ($д > 0 && $д < 3600) $время[] = $д;
        }
        if ($тип === 'form_start')  $воронка['форма_начата']++;
        if ($тип === 'form_submit') $воронка['форма_отправлена']++;
    }

    arsort($источники); arsort($страницы); arsort($клики);
    $всего = array_sum($по_дням);

    return [
        'есть_данные'   => $всего > 0,
        'посещений'     => $всего,
        'уникальных'    => count($посетители) ?: count($сессии),
        'сессий'        => count($сессии),
        'среднее_время' => $время ? (int)round(array_sum($время) / count($время)) : null,
        'по_дням'       => $по_дням,
        'источники'     => array_slice($источники, 0, 12, true),
        'страницы'      => array_slice($страницы, 0, 12, true),
        'устройства'    => $устройства,
        'клики'         => $клики,
        'глубина'       => $глубина,
        'воронка'       => $воронка,
        'почему_пусто'  => $всего > 0 ? '' :
            'Маячок только что поставлен на сайт. Первые цифры появятся, как только на сайт зайдёт живой человек.',
    ];
}

/** Приводим referrer и utm к понятному названию источника. */
function откуда(array $с): string {
    $utm = $с['utm'] ?? [];
    if (is_array($utm) && !empty($utm['source'])) return (string)$utm['source'];
    $ref = (string)($с['ref'] ?? '');
    if ($ref === '') return 'прямой заход';
    $хост = parse_url($ref, PHP_URL_HOST);
    if (!$хост) return 'прямой заход';
    $хост = preg_replace('/^www\./', '', strtolower($хост));
    if (str_contains($хост, 'clusterspace')) return 'внутренний переход';
    $карта = [
        'yandex' => 'Яндекс', 'google' => 'Google', 't.me' => 'Telegram',
        'telegram' => 'Telegram', 'instagram' => 'Instagram', 'youtube' => 'YouTube',
        'dzen' => 'Дзен', 'vc.ru' => 'vc.ru', 'vk.com' => 'ВКонтакте',
        'avito' => 'Авито', 'cian' => 'ЦИАН',
    ];
    foreach ($карта as $кусок => $имя) if (str_contains($хост, $кусок)) return $имя;
    return $хост;
}

function имя_устройства(string $к): string {
    return ['desktop' => 'компьютер', 'mobile' => 'телефон', 'tablet' => 'планшет'][$к] ?? $к;
}

