ПРЕДЕЛ_ПОДПИСИ = 1024


def проверить():
    """Всё, что должно быть верно до отправки."""
    import hashlib, os, sys
    sys.path.insert(0, "/opt/oko-agents")
    from core import humanize
    from PIL import Image
    беды, хеши = [], {}
    for п in ПУБЛИКАЦИИ:
        чистый = п["текст"].replace("<b>", "").replace("</b>", "")
        if len(чистый) > ПРЕДЕЛ_ПОДПИСИ:
            беды.append(f"пост {п['ключ']}: подпись {len(чистый)} знаков, Телеграм режет на 1024")
        if "забира" in чистый.lower():
            беды.append(f"пост {п['ключ']}: слово «забираете», его просили не ставить")
        # Тексты Добермана не правим, но смотрим на свои.
        if п["ключ"] not in ("2", "5"):
            d = humanize.check(п["текст"])
            if not d["ok"]:
                беды.append(f"пост {п['ключ']}: язык {d['bad']}")
        к = п["кадр"]
        if not os.path.exists(к):
            беды.append(f"пост {п['ключ']}: нет кадра {к}"); continue
        ш, в = Image.open(к).size
        if max(ш, в) < 1400:
            беды.append(f"пост {п['ключ']}: кадр {ш}x{в}, мелко")
        h = hashlib.md5(open(к, "rb").read()).hexdigest()
        if h in хеши:
            беды.append(f"пост {п['ключ']}: кадр повторяет пост {хеши[h]}")
        хеши[h] = п["ключ"]
    return беды


if __name__ == "__main__":
    б = проверить()
    for п in ПУБЛИКАЦИИ:
        ч = п["текст"].replace("<b>", "").replace("</b>", "")
        print(f"пост {п['ключ']}: подпись {len(ч)} знаков, кадр {п['кадр'].split('/')[-1]}")
    print("ПРОВЕРКА:", б or "всё чисто")
