if __name__ == "__main__":
    os.makedirs(КУДА, exist_ok=True)
    for ключ, фото, сдвиг, строки, низ, где in РАБОТЫ:
        и = подписать(свет(кадр(фото, сдвиг)), строки, низ, где)
