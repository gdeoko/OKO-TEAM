# -*- coding: utf-8 -*-
"""Ищет каннибализацию: близкие по смыслу единицы, стоящие рядом по календарю.

Мера близости - доля общих смысловых слов (шинглов из трёх слов). Соседство
считаем по дате: один день, соседние дни, одна неделя.
"""
import re, sys, glob, itertools, collections
import tehproverka as t

СЛУЖЕБНЫЕ = set("и в во не что он на я с со как а то все она так его но да ты к у же вы за бы по "
                "только ее мне было вот от меня еще нет о из ем ему теперь когда даже ну вдруг ли "
                "если уже или ни быть был него до вас нибудь опять уж вам ведь там потом себя ничего "
                "ей может они тут где есть надо ней для мы тебя их чем была сам чтоб без будто чего "
                "раз тоже себе под будет ж тогда кто этот того потому этого какой совсем ним здесь "
                "этом один почти мой тем чтобы нее сейчас были куда зачем всех никогда можно при "
                "наконец два об другой хоть после над больше тот через эти нас про всего них какая "
                "много разве три эту моя впрочем хорошо свою этой перед иногда лучше чуть том нельзя "
                "такой им более всегда конечно всю между это её".split())


def слова(текст):
    из = [с for с in re.findall(r"[а-яёa-z0-9]+", текст.lower()) if с not in СЛУЖЕБНЫЕ and len(с) > 2]
    return из


def шинглы(текст, n=3):
    с = слова(текст)
    return {" ".join(с[i:i + n]) for i in range(max(0, len(с) - n + 1))}


def близость(a, b):
    if not a or not b: return 0.0
    return len(a & b) / min(len(a), len(b))


def день(д):
    m = re.match(r"(\d\d)\.(\d\d)", д or "")
    return int(m.group(2)) * 31 + int(m.group(1)) if m else 0


def главное(цели, порог=0.18):
    сп = []
    for ц in цели:
        файлы = sorted(glob.glob(ц + "/*.md")) if not ц.endswith(".md") else [ц]
        for ф in файлы:
            for е in t.единицы(ф):
                if not е["публикация"]: continue
                е["ш"] = шинглы(е["публикация"])
                е["д"] = день(е["дата"])
                сп.append(е)
    пары = []
    for a, b in itertools.combinations(сп, 2):
        if abs(a["д"] - b["д"]) > 7: continue
        к = близость(a["ш"], b["ш"])
        if к >= порог:
            пары.append((к, a, b))
    пары.sort(key=lambda x: -x[0])
    for к, a, b in пары:
        расст = abs(a["д"] - b["д"])
        print(f"{к:.0%} · разрыв {расст} дн · {a['дата']} {a['загол'][:44]}"
              f"  ||  {b['дата']} {b['загол'][:44]}")
    print(f"\nединиц {len(сп)}, пересечений выше {порог:.0%}: {len(пары)}")
    return len(пары)


if __name__ == "__main__":
    sys.exit(главное(sys.argv[1:] or ["MESYAC_1"]))
