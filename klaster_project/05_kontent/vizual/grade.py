# -*- coding: utf-8 -*-
"""Кинематографический грейдинг кадров «Кластера».

Генерация отдаёт чистую картинку без оптики. Здесь добавляется то, что в рекламном
продакшене делают на посте и что глаз читает как «снято на плёнку, а не собрано
нейросетью»: свечение вокруг источников, разведение теней и светов по температуре,
аберрация к краям, зерно, виньетка, локальный контраст.

    python3 grade.py вход.png выход.png [сила]

сила: 0.6 сдержанно, 1.0 норма, 1.4 выраженно.
"""
import sys
import numpy as np
import cv2

вход, выход = sys.argv[1], sys.argv[2]
K = float(sys.argv[3]) if len(sys.argv) > 3 else 1.0

img = cv2.imread(вход, cv2.IMREAD_COLOR).astype(np.float32) / 255.0
h, w = img.shape[:2]


def в_линейное(x):
    return np.power(np.clip(x, 0, 1), 2.2)


def в_гамму(x):
    return np.power(np.clip(x, 0, 1), 1 / 2.2)


lin = в_линейное(img)

# --- 1. Halation. Свет вокруг ярких участков подтекает в красный канал.
# Плёночный эффект: галоген в цеху и амбер-подсветка получают тёплый ореол.
яркость = lin.max(axis=2)
порог = np.clip((яркость - 0.62) / 0.38, 0, 1)[..., None]
маска = lin * порог
радиус = max(3, int(min(h, w) * 0.012) | 1)
halo = cv2.GaussianBlur(маска, (радиус * 4 + 1, радиус * 4 + 1), радиус * 1.6)
halo[..., 2] *= 1.0      # красный держим
halo[..., 1] *= 0.72     # зелёный меньше
halo[..., 0] *= 0.42     # синий почти гасим, ореол уходит в тепло
lin = lin + halo * (0.32 * K)

# --- 2. Bloom. Общее мягкое свечение, снимает цифровую сухость.
bloom = cv2.GaussianBlur(маска, (0, 0), min(h, w) * 0.035)
lin = lin + bloom * (0.14 * K)

img = в_гамму(lin)

# --- 3. Разведение по температуре. Света теплее, тени холоднее и плотнее.
# Это и есть та самая «дорогая» картинка: цвет работает на объём.
L = img.mean(axis=2, keepdims=True)
тени = np.clip(1.0 - L * 2.1, 0, 1)
света = np.clip((L - 0.55) * 2.2, 0, 1)
img[..., 2:3] += света * 0.055 * K - тени * 0.012 * K      # R
img[..., 1:2] += света * 0.022 * K - тени * 0.004 * K      # G
img[..., 0:1] += тени * 0.045 * K - света * 0.030 * K      # B

# --- 4. Локальный контраст. Фактура бетона и металла проступает.
lab = cv2.cvtColor(np.clip(img, 0, 1), cv2.COLOR_BGR2LAB)
l = lab[..., 0]
clahe = cv2.createCLAHE(clipLimit=1.6 * K, tileGridSize=(8, 8))
lab[..., 0] = clahe.apply((l * 255 / 100).astype(np.uint8)).astype(np.float32) * 100 / 255
img = cv2.cvtColor(lab, cv2.COLOR_LAB2BGR)

# --- 5. Кинокривая. Мягкое плечо в светах, приподнятая подошва теней:
# чёрный перестаёт быть провалом, белый перестаёт выжигаться.
x = np.clip(img, 0, 1)
img = x * x * (3 - 2 * x) * 0.92 + x * 0.08
img = img * 0.985 + 0.012

# --- 6. Хроматическая аберрация. Каналы расходятся к краям кадра.
сдвиг = max(1, int(min(h, w) * 0.0016 * K))
if сдвиг:
    M = cv2.getRotationMatrix2D((w / 2, h / 2), 0, 1 + сдвиг * 2.0 / w)
    img[..., 2] = cv2.warpAffine(img[..., 2], M, (w, h), borderMode=cv2.BORDER_REPLICATE)
    M2 = cv2.getRotationMatrix2D((w / 2, h / 2), 0, 1 - сдвиг * 1.4 / w)
    img[..., 0] = cv2.warpAffine(img[..., 0], M2, (w, h), borderMode=cv2.BORDER_REPLICATE)

# --- 7. Виньетка. Мягкая, оптическая, не «фотошопный круг».
yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
r = np.sqrt(((xx - w / 2) / (w / 2)) ** 2 + ((yy - h / 2) / (h / 2)) ** 2)
img *= (1 - np.clip(r - 0.55, 0, 1) ** 2 * 0.42 * K)[..., None]

# --- 8. Зерно. Монохромное, привязано к яркости: в тенях крупнее, в светах тише.
шум = np.random.default_rng(7).normal(0, 1, (h, w)).astype(np.float32)
шум = cv2.GaussianBlur(шум, (0, 0), 0.6)
сила_зерна = (0.016 * K) * (1.15 - img.mean(axis=2))
img += (шум * сила_зерна)[..., None]

# --- 9. Финальная резкость по краям, без ореолов.
размытое = cv2.GaussianBlur(img, (0, 0), 1.1)
img = np.clip(img + (img - размытое) * (0.42 * K), 0, 1)

cv2.imwrite(выход, (np.clip(img, 0, 1) * 255).astype(np.uint8),
            [cv2.IMWRITE_PNG_COMPRESSION, 6])
print("готово:", выход)
