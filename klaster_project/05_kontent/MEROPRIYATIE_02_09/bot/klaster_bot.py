def код(uid):
    return hmac.new(КФ["соль"].encode(), f"tour:{uid}".encode(),
                    hashlib.sha256).hexdigest()[:10].upper()


def ссылка_приглашения(к):
    return f"https://t.me/{КФ['бот']}?start=ref_{к}"


def имя(из):
    н = " ".join(x for x in (из.get("first_name"), из.get("last_name")) if x).strip()
    if not н and из.get("username"):
        н = "@" + из["username"]
    return (н or "участник")[:80]


def запомнить_реферала(uid, к):
    к = "".join(c for c in (к or "").upper() if c in "0123456789ABCDEF")
    if not к:
        return
    д = база()
    if str(uid) not in д["участники"]:
        д["ожидают"][str(uid)] = к
        писать(ФАЙЛ_УЧАСТНИКОВ, д)


def зарегистрировать(uid, из):
    """Заводит участника и начисляет балл пригласившему. Возвращает (новый, кто_привёл)."""
    д = база()
    ключ = str(uid)
    if ключ in д["участники"]:
        return False, д["участники"][ключ].get("привёл")
    мой = код(uid)
    чужой = (д["ожидают"].get(ключ) or "").upper()
    привёл = None
    if чужой and чужой != мой:
        for rid, стр in д["участники"].items():
            if (стр.get("код") or "").upper() == чужой and rid != ключ:
                привёл = rid
                break
    д["счётчик"] += 1
    д["участники"][ключ] = {
        "код": мой,
        "номер": д["счётчик"],
        "имя": имя(из),
        "ник": (из.get("username") or "")[:64],
        "когда": time.strftime("%Y-%m-%d %H:%M:%S"),
        "привёл": привёл,
        "анкета": {},
        "формат": "",
    }
    д["ожидают"].pop(ключ, None)
    писать(ФАЙЛ_УЧАСТНИКОВ, д)
    return True, привёл


def баллы(д, uid):
    return sum(1 for с in д["участники"].values() if str(с.get("привёл") or "") == str(uid))


def рейтинг(д):
    ряды = []
    for uid, с in д["участники"].items():
        с = dict(с); с["uid"] = uid; с["баллы"] = баллы(д, uid)
        ряды.append(с)
    ряды.sort(key=lambda с: (-с["баллы"], с.get("когда", "")))
    return ряды


