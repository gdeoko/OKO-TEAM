def победители(предел=None):
    """Фиксация с повторной проверкой подписки. Если API недоступен, не
    фиксируем ничего: техническая ошибка не должна выглядеть как отписка."""
    предел = предел or КФ["призов"]
    ряды = рейтинг(база())
    из = "<b>Победители по приглашениям</b>\n\n"
    взяли, мимо = 0, 0
    for р in ряды:
        да, причина = подписан(int(р["uid"]))
        if причина in ("сбой", "нет_канала"):
            return из + ("Проверка подписок сейчас недоступна. Победители не зафиксированы: "
                         "проверьте канал и права бота, затем повторите.")
        if not да:
            мимо += 1
            continue
        взяли += 1
        знак = "🥇" if взяли == 1 else "🥈" if взяли == 2 else "🥉"
        из += f"{знак} {р.get('имя')} — <b>{р['баллы']}</b> <code>{р['uid']}</code>\n"
        if взяли >= предел:
            break
    if not взяли:
        из += "Пока нет участников с подтверждённой подпиской.\n"
    if мимо:
        из += f"\nНе прошли повторную проверку: {мимо}."
    return из


