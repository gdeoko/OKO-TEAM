def читать(путь, по_умолчанию):
    try:
        return json.load(io.open(путь, encoding="utf-8"))
    except Exception:
        return по_умолчанию


def писать(путь, данные):
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    врем = путь + ".tmp"
    json.dump(данные, io.open(врем, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    os.replace(врем, путь)


def база():
    д = читать(ФАЙЛ_УЧАСТНИКОВ, {})
