# ── Telegram ─────────────────────────────────────────────────────────────────
def тг(метод, **поля):
    try:
        о = requests.post(API + метод, json=поля, proxies=СЕТЬ, timeout=40)
        return о.json()
    except Exception as e:
        return {"ok": False, "description": str(e)[:200]}


def сказать(чат, текст, кнопки=None, изменить=None):
    поля = {"chat_id": чат, "text": текст, "parse_mode": "HTML",
            "link_preview_options": {"is_disabled": True}}
    if кнопки:
        поля["reply_markup"] = {"inline_keyboard": кнопки}
    if изменить:
        поля["message_id"] = изменить
        return тг("editMessageText", **поля)
    return тг("sendMessage", **поля)


def подписан(uid):
    """Возвращает (подписан ли, причина). Причина «сбой» значит, что проверить
    не удалось: это не то же самое, что «не подписан», и решения по такому
    ответу принимать нельзя."""
    if not КФ["канал"]:
        return False, "нет_канала"
    о = тг("getChatMember", chat_id=КФ["канал"], user_id=uid)
    if not о.get("ok") or not о.get("result"):
        return False, "сбой"
    с = о["result"].get("status", "")
    да = с in ("creator", "administrator", "member") or (
        с == "restricted" and о["result"].get("is_member"))
    return bool(да), "ok" if да else "не_подписан"


