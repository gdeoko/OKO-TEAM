ШАПКА = """📋 <b>Неделя 1 переписана целиком. Забирайте на вычитку</b>

Что было не так и что исправили.

Тексты уходили подписью к фотографии, а Телеграм режет подпись на 1024 знаках. Поэтому половина постов обрывалась на полуслове. Теперь картинка идёт отдельно, текст отдельно, целиком.

Переписали все 16 единиц: первая строка теперь сцена, а не заголовок из отчёта, короткие абзацы, живая речь. В постах для канала премиум-эмодзи вашего набора, в остальных соцсетях те же значки обычными.

В каждом тексте есть повод переслать и сохранить, вопрос аудитории и кодовое слово для директа: КВАРТАЛ, МОЩНОСТЬ, ПРОСМОТР, СМЕТА. Так люди сами начинают разговор, а мы видим, какая тема цепляет.

Цифры привели к вашему паспорту: 5 т/м² на первом этаже, 1,2 на верхних, мощность от 20 кВт с увеличением до 300 кВт. Слово «технопарк» не ставим, пока не будет статуса.

Числа теперь везде цифрами, как пишут живые каналы, а не прописью. Рубленых огрызков по два слова нет: их клиент справедливо назвал почерком нейросети.

Добавили свежие цифры отрасли: 9100 цехов в токийском районе Ота в 1983 году и 3481 к 2014, средний возраст токаря за 55 лет, рост зарплат станочников на 39 % за год. Такие цифры цитируют и пересылают.

Каждая единица прошла 2 аудита: 35 пунктов по структуре, фактам и воронке и отдельная проверка на живой язык. Замечаний ноль.

Карусель собрана вертикалью 4:5, все 8 слайдов одной генерацией: фото, логотип, заголовок, футер с доменом и нумерацией. Ничего не наложено поверх картинки.

Дальше идут публикации по порядку: сначала картинка, следом её текст."""


def подпись(е):
    """Строка-заголовок перед каждой публикацией."""
    рубрика = f" · рубрика «{е['рубрика']}»" if е.get("рубрика") else ""
    return f"<b>{е['день']} · {е['площадка']} · {е['формат']}</b>{рубрика}"


def тело(е):
    т = е.get("текст", "")
    if not т and е.get("слайды"):
        т = "Раскладка кадров:\n\n" + "\n\n".join(е["слайды"])
    оформ = премиум if е["площадка"] == "Telegram" else обычные
    куски = [подпись(е), оформ(т)]
    if е.get("слайды") and е.get("текст"):
        куски.append("<b>Слайды:</b>\n" + "\n".join(е["слайды"]))
    if е.get("опрос"):
        куски.append("<b>Опрос:</b> " + " · ".join(е["опрос"]))
    if е.get("хештеги"):
        куски.append(е["хештеги"])
    return "\n\n".join(к for к in куски if к)


async def main():
    # Какую неделю отправляем: НЕДЕЛЯ=w2 шлёт только вторую.
    метка = os.getenv("НЕДЕЛЯ", "")
    единицы = [е for е in всё() if not метка or е["код"].startswith(метка)]
    print(f"к отправке единиц: {len(единицы)}")
    os.makedirs(ВРЕМЕНКА, exist_ok=True)
    for к in ("", "-journal", "-wal", "-shm"):
        и = os.path.join(str(config.SESSIONS_DIR), f"{ACC}.session{к}")
        if os.path.exists(и):
            shutil.copy2(и, os.path.join(ВРЕМЕНКА, os.path.basename(и)))
    app = Client(ACC, api_id=config.PYROGRAM_API_ID, api_hash=config.PYROGRAM_API_HASH,
                 workdir=ВРЕМЕНКА, **tg_net.как_ходить(ACC))
    await app.start()
    я = await app.get_me()
    print(f"шлю от @{я.username}, премиум: {getattr(я, 'is_premium', False)}")

    было = set()
    async for m in app.get_chat_history(ФОРУМ, limit=120):
        т = " ".join((m.caption or m.text or "").split())
        if т:
            было.add(т[:80])

    async def послать(текст, метка):
        чистый = " ".join(текст.replace("<b>", "").replace("</b>", "").split())
        if чистый[:80] in было:
            print(f"{метка}: уже есть, пропускаю"); return
        try:
            m = await app.send_message(ФОРУМ, текст, parse_mode=ParseMode.HTML,
                                       message_thread_id=ВЕТКА,
                                       disable_web_page_preview=True)
            print(f"{метка}: id {m.id}")
        except Exception as беда:
            # Премиум-эмодзи без подписки Телеграм не пропускает: шлём обычными.
            if "PREMIUM" in str(беда).upper() or "CUSTOM_EMOJI" in str(беда).upper():
                простой = обычные(текст)
                m = await app.send_message(ФОРУМ, простой, parse_mode=ParseMode.HTML,
                                           message_thread_id=ВЕТКА,
                                           disable_web_page_preview=True)
                print(f"{метка}: id {m.id} (обычные эмодзи, у аккаунта нет премиума)")
            else:
                print(f"{метка}: НЕ УШЛО, {str(беда)[:90]}")
        await asyncio.sleep(7)

    if not метка:
        await послать(ШАПКА, "шапка")
    for е in единицы:
        кадр = f"{КАДРЫ}/{е['кадр'].split('..')[0]}.png" if е.get("кадр") else ""
        if кадр and os.path.exists(кадр):
            try:
                m = await app.send_photo(ФОРУМ, кадр, caption=подпись(е),
                                         parse_mode=ParseMode.HTML,
                                         message_thread_id=ВЕТКА)
                print(f"{е['код']} кадр: id {m.id}")
                await asyncio.sleep(7)
            except Exception as беда:
                print(f"{е['код']} кадр не ушёл: {str(беда)[:70]}")
        await послать(тело(е), f"{е['код']} текст")
    await app.stop()


if __name__ == "__main__":
    asyncio.run(main())
