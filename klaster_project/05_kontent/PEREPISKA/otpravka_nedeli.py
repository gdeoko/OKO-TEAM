def подпись(е):
    """Строка-заголовок перед каждой публикацией."""
    рубрика = f" · рубрика «{е['рубрика']}»" if е.get("рубрика") else ""
    return f"<b>{е['день']} · {е['площадка']} · {е['формат']}</b>{рубрика}"


def кадры(е):
    """Карусель и истории уходят всей серией, обычный пост одним кадром."""
    имя = (е.get("кадр") or "").split("..")[0]
    if not имя or "снимаем" in имя:
        return []
    основа = имя.rsplit("-", 1)[0] if имя[-1].isdigit() else имя
    ряд = sorted(glob.glob(os.path.join(КАДРЫ, основа + "-*.png")))
    if ряд and ("карусель" in е["формат"] or "истори" in е["формат"]):
        return ряд
    один = os.path.join(КАДРЫ, имя + ".png")
    return [один] if os.path.exists(один) else []


def тело(е):
    т = е.get("текст", "")
    if not т and е.get("слайды"):
        т = "Раскладка кадров:\n\n" + "\n\n".join(е["слайды"])
    оформ = премиум if е["площадка"] == "Telegram" else обычные
    куски = [подпись(е), оформ(т)]
    if е.get("слайды") and е.get("текст"):
        куски.append("<b>Слайды:</b>\n" + "\n".join(е["слайды"]))
    if е.get("опрос"):
        куски.append("<b>Опрос:</b> " + " · ".join(е["опрос"]))
    if е.get("хештеги"):
        куски.append(е["хештеги"])
    return "\n\n".join(к for к in куски if к)


