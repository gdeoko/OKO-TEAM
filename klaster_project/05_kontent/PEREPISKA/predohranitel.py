# -*- coding: utf-8 -*-
"""Предохранитель от AUTH_KEY_DUPLICATED.

Служба агентов держит сессии Телеграма в памяти постоянно. Любое второе
подключение тем же файлом сессии сервер считает утечкой ключа и аннулирует
авторизацию НАВСЕГДА, без предупреждения. Так уже погибли acc1, acc2, acc3
и acc4. Восстановление возможно только входом по номеру телефона с кодом,
то есть руками владельца.

Поэтому каждый скрипт, который открывает Client, сначала спрашивает у
системы, работает ли служба, и при работающей службе просто отказывается
запускаться. Отправлять при живой службе надо мостом задач:

    from core import taskqueue as q
    t = q.enqueue("generic", CHAT_ID, "acc4")
    q.mark(t, "done", {"text": "...", "message_thread_id": 9})
"""
import subprocess
import sys


def служба_работает() -> bool:
    try:
        r = subprocess.run(["systemctl", "is-active", "oko-agents"],
                           capture_output=True, text=True, timeout=15)
        return (r.stdout or "").strip() == "active"
    except Exception:
        # Не смогли спросить - считаем, что работает: цена ошибки это мёртвый акк.
        return True


def проверить_или_выйти():
    if служба_работает():
        print("СТОП: служба oko-agents работает и держит сессии Телеграма.\n"
              "Второе подключение тем же ключом убивает аккаунт навсегда.\n"
              "Отправляйте через мост задач taskqueue, читать чат нечем.")
        sys.exit(1)
