# -*- coding: utf-8 -*-
"""Премиум-эмодзи клиента для постов в Телеграм.

Набор клиента уже стоит в их боте, берём те же идентификаторы, чтобы канал и
бот выглядели одинаково. В других соцсетях премиум-эмодзи нет, поэтому
`обычные()` отдаёт тот же текст с простыми значками.
"""
import re

НАБОР = {
    "билет":   ("5258260149037965799", "💼"),
    "дата":    ("5258105663359294787", "🗓"),
    "место":   ("5258509201306557640", "📍"),
    "люди":    ("5258513401784573443", "👥"),
    "ворота":  ("5258084656674250503", "🚪"),
    "док":     ("5258477770735885832", "📄"),
    "ток":     ("5258152182150077732", "⚡"),
    "здания":  ("5257963315258204021", "🏘"),
    "галочка": ("5260726538302660868", "✅"),
    "связь":   ("5258215846450305872", "💬"),
    "бот":     ("5258093637450866522", "🤖"),
}

МЕТКА = re.compile(r"\{(\w+)\}")


def премиум(текст: str) -> str:
    """Метки вида {ток} превращаем в премиум-эмодзи Телеграма."""
    def замена(м):
        имя = м.group(1)
        if имя not in НАБОР:
            return м.group(0)
        ид, запас = НАБОР[имя]
        return f'<tg-emoji emoji-id="{ид}">{запас}</tg-emoji>'
    return МЕТКА.sub(замена, текст)


def обычные(текст: str) -> str:
    """Для ВК, Инстаграма и статей: те же значки, но без премиума."""
    def замена(м):
        имя = м.group(1)
        return НАБОР[имя][1] if имя in НАБОР else м.group(0)
    return МЕТКА.sub(замена, текст)


def без_разметки(текст: str) -> str:
    """Чистый текст для проверок длины и языка."""
    т = обычные(текст)
    return re.sub(r"</?b>|</?i>|</?u>", "", т)
