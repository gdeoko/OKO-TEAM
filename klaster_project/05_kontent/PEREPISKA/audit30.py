# -*- coding: utf-8 -*-
"""Аудит контента по тридцати пунктам перед показом клиенту.

Проверяем то, на что клиент уже жаловался, и то, что решает судьбу поста в
ленте: живой язык, хук в первой строке, длина под площадку, факты по паспорту
объекта, воронка и повод переслать.

Пункты сгруппированы: язык, структура, факты, воронка, площадка, оформление.
Каждый пункт либо проходит, либо возвращает конкретную претензию, а не
абстрактную оценку.

    python3 audit30.py            проверить всё
    python3 audit30.py w1-01      проверить одну единицу
"""
import re
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from emo import без_разметки, НАБОР

# Паспорт объекта: цифры, которые нельзя путать.
ПАСПОРТ = {
    "5 т/м²": ["5 т/м²", "5 тонн"],
    "1,2 на верхних": ["1,2"],
    "мощность": ["20 кВт", "300 кВт"],
    "адрес": ["6-я Радиальная"],
    "телефон": ["8 985 331 02 71"],
    "сайт": ["clusterspace.ru"],
}
УСТАРЕЛО = ["до 100 кВт", "100 кВт на помещение", "1,2 тонны на втором",
            "технопарк", "Технопарк"]
КАНЦЕЛЯРИТ = ["важно отметить", "стоит отметить", "таким образом", "кроме того",
              "в рамках", "на сегодняшний день", "комплексный подход",
              "индивидуальный подход", "в кратчайшие сроки", "позволяет вам",
              "во-первых", "во-вторых", "данный", "осуществляется",
              "является", "необходимо отметить"]
ПРОТИВОПОСТАВЛЕНИЯ = re.compile(r"\bне [^.,;!?]{2,40}, а \b")
ПРЕДЕЛЫ = {"Telegram": 4096, "ВКонтакте": 15000, "Instagram": 2200,
           "Дзен": 60000, "vc.ru": 60000}
# Повод переслать бывает разными словами. Держать один «сохраните» на
# все пятьдесят шесть единиц значит писать штампом, и это видно в ленте.
ПОВОД_ПЕРЕСЛАТЬ = ["перешлите", "сохраните", "покажите", "отправьте",
                   "передайте", "заберите", "распечатайте", "скиньте",
                   "киньте", "возьмите с собой", "возьмите эти"]
# Призыв это глагол действия, а не одно слово «напишите» на весь месяц.
# Список широкий намеренно: лента с одинаковым финалом читается как рассылка.
ПРИЗЫВЫ = ["напишите", "пришлите", "приезжайте", "запишитесь", "ответьте",
           "проверьте", "посчитайте", "сохраните", "расскажите", "скажите",
           "назовите", "отпишитесь", "покажите", "передайте", "заберите",
           "сравните", "задайте", "возьмите", "сделайте", "пройдите",
           "сверьте", "выпишите", "отправьте", "распечатайте", "скиньте"]


def пункты(е):
    """Тридцать четыре проверки. Возвращает список (номер, название, беда)."""
    т = без_разметки(е.get("текст", ""))
    строки = [с for с in т.split("\n") if с.strip()]
    первая = строки[0] if строки else ""
    абзацы = [а for а in т.split("\n\n") if а.strip()]
    слова = т.split()
    площадка = е["площадка"]
    из = []

    def п(н, имя, беда=""):
        из.append((н, имя, беда))

    # ── язык ──────────────────────────────────────────────────────────────
    п(1, "длинное тире", "есть длинное тире" if "—" in т or "–" in т else "")
    # Ищем канцелярит по границам слова: «появляется» содержит «явля», но
    # канцеляритом от этого не становится.
    низ = т.lower()
    найден = [к for к in КАНЦЕЛЯРИТ
              if re.search(r"\b" + re.escape(к) + r"\w{0,3}\b", низ)]
    п(2, "канцелярит", f"обороты: {', '.join(найден[:3])}" if найден else "")
    м = ПРОТИВОПОСТАВЛЕНИЯ.search(т)
    п(3, "противопоставление не X, а Y", f"«{м.group(0).strip()}»" if м else "")
    длинные = [а for а in абзацы if len(а) > 600]
    п(4, "абзац длиннее 600 знаков", f"{len(длинные)} шт" if длинные else "")
    п(5, "нет слова клиент в третьем лице",
      "слово «клиент» как обезличенное" if re.search(r"\bклиент(ов|ам|ы)?\b", т.lower())
      and площадка in ("Telegram", "Instagram") and "вашего клиента" not in т.lower() else "")
    п(6, "нет двойных пробелов", "двойные пробелы" if "  " in т else "")
    п(7, "нет обрыва на полуслове",
      "текст кончается на полуслове" if т.rstrip().endswith((",", "и", "в", "с", "на", "-")) else "")

    # ── структура ─────────────────────────────────────────────────────────
    п(8, "хук в первой строке",
      "первая строка без сцены или цифры"
      if not (re.search(r"\d", первая) or len(первая) < 90) else "")
    п(9, "первая строка не длиннее 120 знаков",
      f"{len(первая)} знаков" if len(первая) > 120 else "")
    п(10, "есть абзацы", "текст одним куском" if len(абзацы) < 3 and т else "")
    п(11, "нет заголовка в каждом абзаце",
      "похоже на список заголовков"
      if sum(1 for а in абзацы if а.endswith(":")) > len(абзацы) / 2 and абзацы else "")
    п(12, "объём под площадку",
      f"{len(т)} знаков, предел {ПРЕДЕЛЫ.get(площадка, 4096)}"
      if len(т) > ПРЕДЕЛЫ.get(площадка, 4096) else "")
    п(13, "текст не короче нормы",
      f"всего {len(т)} знаков"
      if т and len(т) < (400 if площадка != "Telegram" else 500) else "")

    # ── факты ─────────────────────────────────────────────────────────────
    старое = [у for у in УСТАРЕЛО if у in т]
    п(14, "нет устаревших цифр и запретных слов",
      f"нашла: {', '.join(старое)}" if старое else "")
    п(15, "телефон на месте",
      "нет телефона" if т and ПАСПОРТ["телефон"][0] not in т
      and е["формат"] != "3 истории" and "истории" not in е["формат"] else "")
    п(16, "сайт или адрес на месте",
      "нет сайта и адреса"
      if т and not any(з in т for з in ("clusterspace.ru", "6-я Радиальная")) else "")
    п(17, "цифры нагрузки верные",
      "нагрузка без указания этажа"
      if "5 т/м²" in т and "1,2" not in т else "")
    п(18, "мощность по паспорту",
      "мощность без вилки 20-300"
      if "кВт" in т and not ("20 кВт" in т and "300 кВт" in т) else "")

    # ── воронка ───────────────────────────────────────────────────────────
    п(19, "есть призыв к действию",
      "нет призыва" if т and not any(п_ in т.lower() for п_ in ПРИЗЫВЫ) else "")
    п(20, "есть повод переслать или сохранить",
      "нет повода переслать"
      if т and not any(п_ in т.lower() for п_ in ПОВОД_ПЕРЕСЛАТЬ) else "")
    п(21, "есть вопрос аудитории",
      "нет вопроса" if т and "?" not in т else "")
    п(22, "кодовое слово или ясный вход",
      "нет кодового слова и почты"
      if т and not (re.search(r"слово [А-ЯЁ]{4,}", т) or "arenda@activity.su" in т
                    or "комментариях" in т) else "")
    п(23, "один призыв, а не пять",
      "слишком много призывов"
      if sum(т.lower().count(п_) for п_ in ПРИЗЫВЫ) > 6 else "")

    # ── площадка и оформление ─────────────────────────────────────────────
    метки = re.findall(r"\{(\w+)\}", е.get("текст", ""))
    п(24, "премиум-эмодзи в Телеграме",
      "нет премиум-эмодзи" if площадка == "Telegram" and not метки else "")
    п(25, "эмодзи не пачкой",
      f"{len(метки)} штук подряд" if len(метки) > 6 else "")
    п(26, "эмодзи из набора клиента",
      f"чужие метки: {[м for м in метки if м not in НАБОР]}"
      if [м for м in метки if м not in НАБОР] else "")
    п(27, "хештеги там, где нужны",
      "нет хештегов"
      if площадка == "Instagram" and not е.get("хештеги") and е.get("текст") else "")
    п(28, "визуал описан",
      "нет кадра" if not е.get("кадр") else "")
    п(29, "слайды для карусели и историй",
      "нет раскладки слайдов"
      if ("карусель" in е["формат"] or "истории" in е["формат"])
      and not е.get("слайды") else "")
    п(30, "рубрика указана", "нет рубрики" if not е.get("рубрика") else "")

    # ── живая речь, а не рубленые огрызки ────────────────────────────────
    # Два-три слова в предложении подряд читаются как заикание и выдают
    # нейросеть быстрее любого канцелярита. Клиент назвал это прямо.
    предложения = [п_.strip() for п_ in re.split(r"(?<=[.!?])\s+", т) if п_.strip()]
    коротких_подряд, худшее = 0, 0
    for пр in предложения:
        if len(пр.split()) <= 3:
            коротких_подряд += 1
            худшее = max(худшее, коротких_подряд)
        else:
            коротких_подряд = 0
    п(31, "нет рубленых огрызков подряд",
      f"{худшее} коротких предложения подряд" if худшее >= 2 else "")
    очень_короткие = [пр for пр in предложения if len(пр.split()) <= 2]
    п(32, "нет предложений из двух слов",
      f"{len(очень_короткие)} шт: {очень_короткие[:2]}" if очень_короткие else "")
    односложные_абзацы = [а for а in абзацы
                          if len(а.split()) <= 5 and not а.strip().endswith(":")]
    п(33, "нет абзацев в три слова",
      f"{len(односложные_абзацы)} шт" if len(односложные_абзацы) > 1 else "")
    # Живые каналы пишут числа цифрами: «85,7 м²», «7 лет», «2000 отделений».
    # Пропись в посте читается как книга, а не как лента.
    ПРОПИСЬ = [r"\bодин\b", r"\bдва\b", r"\bтри\b", r"\bчетыре\b", r"\bпять\b",
               r"\bшесть\b", r"\bсемь\b", r"\bвосемь\b", r"\bдевять\b",
               r"\bдесять\b", r"\bдвенадцать\b", r"\bпятнадцать\b",
               r"\bдвадцать\b", r"\bтридцать\b", r"\bсорок\b",
               r"\bпятьдесят\b", r"\bсто\b", r"\bтысяча\b", r"\bтысячи\b",
               r"\bполгода\b", r"\bтрёх\b", r"\bпяти\b", r"\bдесяти\b"]
    прописью = [re.search(п_, низ).group(0) for п_ in ПРОПИСЬ if re.search(п_, низ)]
    п(35, "числа цифрами, а не прописью",
      f"пропись: {', '.join(х.strip() for х in прописью[:4])}" if прописью else "")

    средняя = (sum(len(пр.split()) for пр in предложения) / len(предложения)
               if предложения else 0)
    п(34, "средняя длина предложения живая",
      f"{средняя:.1f} слов, текст рубленый" if предложения and средняя < 7 else "")
    return из


def проверить(единицы, фильтр=""):
    всего, беды = 0, 0
    for е in единицы:
        if фильтр and е["код"] != фильтр:
            continue
        всего += 1
        плохие = [(н, имя, б) for н, имя, б in пункты(е) if б]
        беды += len(плохие)
        знак = "чисто" if not плохие else f"замечаний {len(плохие)}"
        print(f"\n{е['код']} · {е['площадка']} · {е['формат']} · {знак}")
        for н, имя, б in плохие:
            print(f"   п{н:02d} {имя}: {б}")
    print(f"\nПРОВЕРЕНО единиц: {всего}, замечаний всего: {беды}")
    return беды


def всё():
    """Все недели месяца, какие уже переписаны."""
    из = []
    for модуль in ("nedelya1_chast1", "nedelya1_chast2", "nedelya2",
                   "nedelya3", "nedelya4"):
        try:
            из += __import__(модуль).ЕДИНИЦЫ
        except ModuleNotFoundError:
            continue
    return из


if __name__ == "__main__":
    фильтр = sys.argv[1] if len(sys.argv) > 1 else ""
    sys.exit(1 if проверить(всё(), фильтр) else 0)
