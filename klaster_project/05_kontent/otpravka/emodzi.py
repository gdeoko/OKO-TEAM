# -*- coding: utf-8 -*-
"""Премиум-эмодзи Телеграма: разметка {🔥} превращается в кастомный эмодзи.

Идентификаторы взяты из наборов, доступных аккаунту @ktodaniel (premium=True):
tgmacicons, IslomjonAnimeEmoji, AR_PREMIUM, vector_icons_by_fStikBot.
Обычный эмодзи оставляем как есть, если пары в карте нет: пост от этого
не ломается, просто вместо кастомного встанет системный.
"""
import re

КАРТА = {
    "🌠": "5258212268742549391",   # падающая звезда
    "📸": "5258205968025525531",   # камера
    "⭐️": "5258185631355378853",
    "🌙": "5350311932530270693",
    "✨": "5350444080084033572",
    "👥": "5258513401784573443",
    "🗓": "5258105663359294787",
    "💡": "5258216851472654189",
    "⚡️": "5258152182150077732",
    "📈": "5258391025281408576",
    "📊": "5282734530547951466",
    "🖼": "5258050709252743821",
    "👏": "5258501105293205250",
    "❤️": "5258179403652801593",
    "⚙️": "5350396951407895212",
    "🔥": "5267389686141166350",
}
КАРТА["🪐"] = КАРТА["⭐️"]


def развернуть(текст):
    """{🌠} превращает в html-тег кастомного эмодзи, остальное не трогает."""
    def замена(m):
        э = m.group(1)
        i = КАРТА.get(э)
        return f'<emoji id="{i}">{э}</emoji>' if i else э
    return re.sub(r"\{([^\s{}]{1,4})\}", замена, текст)
