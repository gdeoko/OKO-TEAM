# -*- coding: utf-8 -*-
"""Опись пакета на согласование: что уходит клиенту и какими кадрами.

Кадры лежат на сервере и весят по два с половиной мегабайта. Тащить их сюда,
чтобы собрать папки и отправить обратно, значит гонять триста мегабайт по мосту
кусками base64. Поэтому здесь собирается только опись: текст публикации и имена
кадров по ключу промпта. Сборка папок и отправка идут на сервере, где кадры уже
лежат.

    python3 manifest.py MESYAC_1 opis_mesyac_1.json promts_mesyac_1.json
"""
import glob
import io
import json
import os
import re
import sys

ПЛОЩАДКИ = {"Telegram": "TG", "ВКонтакте": "VK", "Instagram": "IG",
            "Дзен": "DZEN", "vc.ru": "VC", "РБК": "RBK"}


def тип(з):
    if "карусел" in з: return "карусель"
    if "истори" in з: return "истории"
    if "Reels" in з or "кружок" in з: return "видео"
    if re.match(r"(Дзен|vc\.ru|РБК)", з): return "статья"
    return "пост"


def латиница(с):
    таблица = {"а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
               "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
               "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
               "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
               "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya"}
    из = []
    for б in с.lower():
        if б in таблица: из.append(таблица[б])
        elif б.isalnum(): из.append(б)
        else: из.append("-")
    return re.sub(r"-+", "-", "".join(из)).strip("-")[:46]


def единицы(папка):
    сп = []
    for путь in sorted(glob.glob(os.path.join(папка, "NEDELYA_*.md"))):
        s = io.open(путь, encoding="utf-8").read()
        дата = ""
        for кусок in re.split(r"\n(?=(?:# \d\d\.\d\d |## ))", s):
            г = кусок.split("\n")[0]
            m = re.match(r"# (\d\d\.\d\d) ([А-Я]{2})", г)
            if m:
                дата = f"{m.group(1)} {m.group(2).lower()}"
                continue
            if not re.match(r"## (Instagram|Telegram|ВКонтакте|Дзен|vc\.ru|РБК)", г):
                continue
            з = г[3:].strip()
            заг = re.search(r"\n\*\*(.+?)\*\*", кусок)
            текст = re.search(r"```\n(.*?)\n```", кусок, re.S)
            слайды = re.findall(r"^\*\*(\d+)\.\*\* ([^\n]+)\n> ([^\n]+)", кусок, re.M)
            хеш = re.search(r"Хештеги: ([^\n]+)", кусок)
            промпт = re.findall(r"промпт[ы]? `([^`]+)`", кусок)
            сп.append({"дата": дата, "загол": з, "площадка": з.split(" ·")[0].strip(),
                       "тип": тип(з), "тема": заг.group(1) if заг else "",
                       "текст": текст.group(1) if текст else "", "слайды": слайды,
                       "хештеги": хеш.group(1) if хеш else "",
                       "промпт": промпт[0] if промпт else ""})
    return сп


def тело(е):
    """То, что уходит клиенту: тема, текст, слайды, хештеги. Без служебного."""
    части = [е["тема"], ""]
    if е["тип"] in ("карусель", "истории"):
        for н, заг, подп in е["слайды"]:
            части.append(f"Слайд {н}. {заг}")
            части.append(f"   {подп}")
        if е["текст"]:
            части += ["", "Описание к публикации:", "", е["текст"]]
    else:
        части.append(е["текст"])
    if е["хештеги"]:
        части += ["", е["хештеги"]]
    return "\n".join(части).strip() + "\n"


def главное(месяц, куда, список_промптов=""):
    # Часть визуалов принципиально не генерится: карта из официального источника,
    # кружок живой съёмки, ролик. Сколько кадров ждать, честнее всего спросить у
    # самого списка промптов, а не угадывать по типу единицы.
    ключи = set()
    if список_промптов and os.path.exists(список_промптов):
        ключи = set(json.load(io.open(список_промптов, encoding="utf-8")))
    сп = единицы(месяц)
    опись = []
    for н, е in enumerate(сп, 1):
        имя = (f"{н:02d}_{е['дата'].split()[0].replace('.', '-')}_"
               f"{ПЛОЩАДКИ.get(е['площадка'], 'X')}_{латиница(е['тема'])}")
        # Ролик и кружок снимаются живьём, кадра под них в списке промптов нет:
        # требовать его значит вечно держать пакет неполным.
        нужно = (len(е["слайды"]) if е["тип"] in ("карусель", "истории")
                 else 0 if е["тип"] == "видео" and not е["промпт"] else 1)
        if ключи:
            к = е["промпт"]
            серия = [x for x in ключи
                     if к and x.startswith(к + "-") and x[len(к) + 1:].isdigit()]
            нужно = len(серия) if серия else (1 if к in ключи else 0)
        опись.append({"имя": имя, "дата": е["дата"], "площадка": е["площадка"],
                      "тип": е["тип"], "тема": е["тема"], "ключ": е["промпт"],
                      "кадров_нужно": нужно, "статья": е["тип"] == "статья",
                      "текст": тело(е)})
    json.dump(опись, io.open(куда, "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    print(f"единиц в описи: {len(опись)}, кадров нужно: "
          f"{sum(о['кадров_нужно'] for о in опись)}")
    return опись


if __name__ == "__main__":
    главное(sys.argv[1] if len(sys.argv) > 1 else "MESYAC_1",
            sys.argv[2] if len(sys.argv) > 2 else "opis.json",
            sys.argv[3] if len(sys.argv) > 3 else "")
