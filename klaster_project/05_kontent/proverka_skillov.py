# -*- coding: utf-8 -*-
"""Проверка контента по критериям скиллов OKO: хук, виральность, удержание, воронка, CTA.

Дополняет audit.py (десять пунктов качества текста) четырьмя проверками,
которые взяты дословно из скиллов oko-hook, oko-virality, oko-retention,
oko-funnel и oko-cta.

    python3 proverka_skillov.py MESYAC_1
"""
import re, sys, os, collections
sys.path.insert(0, "/home/user/OKO-TEAM/kontent_mesyats")
import audit

# oko-hook: восемь рабочих заходов
ЗАХОДЫ = {
    "цифра в лоб": r"^\D{0,90}\d",
    "отрицание ожидания": r"^(Без|Не |Никто|Ни один)|\bбез единого\b|\bни одного\b",
    "вопрос болью": r"\?",
    "обещание срока": r"за \d+\s*(минут|час|дн|недел|месяц)|через \d+",
    "против правила": r"обычно|чаще всего|принято|все думают|кажется",
    "результат сразу": r"^\d[\d\s,.]*(₽|руб|%|процент|м²|кВт|МВт|кг|тонн)",
    "прямое обращение": r"\bв(?:ы|ам|ас|аш\w*)\b|\bсвой\b|\bсвою\b|\bсвоего\b",
    "незаконченное действие": r"^[А-ЯЁ][а-яё]+ (доехал|пришл|уш[ёе]л|встал|заш[ёе]л|открыва)",
    # смена состояния: «было X, теперь Y» - тот же слом ожидания, только через время
    "смена состояния": r"\bтеперь\b|\bдальше\b|\bосталось\b|\bстало\b|\bпревратил|\bуже не\b",
    # закавыченная реплика: чужая фраза в зачине читается как сцена
    "чужая реплика": r"«[^»]{3,}»",
}

# oko-virality: шесть репост-триггеров, нужно минимум два
ТРИГГЕРЫ = {
    "полезность": r"сохран|список|инструкц|чек-лист|шаг \d|пункт|вопрос(?:ов|ы)? ",
    "эмоция": r"страх|боится|обидн|развалит|потер\w+|рушит|съедает|теря\w+|"
               r"простой|простоя|срыв|проигрыва\w+|ломается|дорого обходится|стоит недел|съеда\w+|"
               r"стоит денег|за ваш счёт|цена ошибки|бьёт по",
    "идентичность": r"\bу вас\b|ваш цех|ваша смена|если у вас|вашего производства",
    "соц-валюта": r"мало кто\b|почти никто|редко называют|редко расска\w+|редко пишут|"
                   r"не пишут|молчат|обычно не счита\w+|никто не счита\w+|не знает никто|"
                   r"об этом не знает|узнают потом|задним числом|о ней почти никто",
    "спор и мнение": r"как думаете|напишите|опрос|стикер|а вы |что у вас",
    "практическая ценность": r"проверьте|посчитайте|возьмите|откройте|отправьте|пришлите|сравните",
}

# oko-funnel: стадия по рубрике
СТАДИЯ = {
    "Промышленный город": "TOFU", "Площадки мира": "TOFU", "Отрасль": "TOFU",
    "Цифры отрасли": "TOFU", "Цена киловатта": "TOFU", "Кадры цеха": "TOFU",
    "Рынок": "TOFU", "Кто стоит у станка": "TOFU", "За что дают": "TOFU",
    "Цена ошибки": "TOFU", "Событие": "TOFU", "Деньги цеха": "MOFU", "Не снесут": "MOFU",
    "Как выбирать": "MOFU", "Цифры цеха": "MOFU", "Сколько отсюда ехать": "MOFU",
    "Сколько стоит место": "MOFU", "Сто производств": "MOFU",
    "Стройка будущего": "MOFU", "Воронка": "BOFU",
}
ЦЕЛЬ = {"TOFU": 60, "MOFU": 30, "BOFU": 10}

# oko-cta: сильный призыв
CTA_ГЛАГОЛ = re.compile(r"напиши|пришли|посчитай|сохран|проверь|отправь|перешли|подпис|"
                        r"приезжай|приходи|заходи|спроси|спрашивай|возьми|откр(?:ой|ойте)|займи|сравни|"
                        r"сверь|умнож|сложи|задай|сделай|ответь|найди|начни|встань|позвони|"
                        r"пиши|покажи|разлож|прогони|поставь|назов(?:и|ите)|перешл(?:и|ите)|сверь(?:те)?", re.I)
CTA_ПРИЧИНА = re.compile(r"чтобы|если |и мы |скажем|покажем|подскажем|соберём|посчитаем|пришлём")


def разобрать(папка):
    сп = audit.единицы(папка)
    итог = []
    for е in сп:
        слайды = " ".join(a + " " + b for _, a, b in е["слайды"])
        полный = (е["текст"] + " " + слайды).strip()
        первая = (е["слайды"][0][1] if е["слайды"] and not е["текст"]
                  else (е["текст"].split("\n")[0] if е["текст"] else ""))
        руб = re.search(r"рубрика «([^»]+)»", е["загол"])
        руб = руб.group(1) if руб else ""
        заходы = [и for и, ш in ЗАХОДЫ.items() if re.search(ш, первая, re.I)]
        триггеры = [и for и, ш in ТРИГГЕРЫ.items() if re.search(ш, полный, re.I)]
        абзацы = [p for p in е["текст"].split("\n\n") if p.strip()]
        # призыв ищем в двух последних абзацах: адресная строка часто идёт после него
        последний = " ".join(абзацы[-2:]) if абзацы else слайды
        итог.append({
            "файл": е["файл"], "загол": е["загол"], "рубрика": руб,
            "заходы": заходы, "триггеры": триггеры,
            "стадия": СТАДИЯ.get(руб, "?"),
            # у серии историй интерактив (опрос, вопрос, викторина) это и есть действие
            "cta": bool(CTA_ГЛАГОЛ.search(последний)) or bool(
                re.search(r"истори", е["загол"]) and re.search(r"опрос|вопрос|викторин|стикер|слайдер", е["блок"], re.I)),
            "cta_причина": bool(CTA_ПРИЧИНА.search(последний)),
            "длинных_абзацев": len([p for p in абзацы if len(p) > 420]),
        })
    return итог


def главное(папка):
    сп = разобрать(папка)
    n = len(сп)
    беды = []
    ст = collections.Counter(е["стадия"] for е in сп)
    print(f"единиц: {n}")
    print("\nхук (oko-hook, нужен хотя бы один заход из восьми)")
    без = [е for е in сп if not е["заходы"]]
    print(f"  с заходом: {n - len(без)} из {n}")
    беды += [(е, "хук: ни одного захода") for е in без]
    print("\nвиральность (oko-virality, нужно минимум два репост-триггера)")
    слабо = [е for е in сп if len(е["триггеры"]) < 2]
    print(f"  два и больше триггеров: {n - len(слабо)} из {n}")
    беды += [(е, f"виральность: триггеров {len(е['триггеры'])}") for е in слабо]
    print("\nудержание (oko-retention, абзац не длиннее 420 знаков)")
    длин = [е for е in сп if е["длинных_абзацев"]]
    print(f"  без длинных абзацев: {n - len(длин)} из {n}")
    беды += [(е, f"удержание: длинных абзацев {е['длинных_абзацев']}") for е in длин]
    print("\nворонка (oko-funnel, цель TOFU 60 / MOFU 30 / BOFU 10)")
    for с in ("TOFU", "MOFU", "BOFU", "?"):
        if ст[с]: print(f"  {с:5} {ст[с]:4}  {ст[с]*100//n:3} %   цель {ЦЕЛЬ.get(с, '-')}")
    беды += [(е, "воронка: стадия не задана") for е in сп if е["стадия"] == "?"]
    print("\nпризыв (oko-cta, глагол действия в финале)")
    без_cta = [е for е in сп if not е["cta"]]
    print(f"  с призывом: {n - len(без_cta)} из {n}")
    беды += [(е, "призыв: нет глагола действия в финале") for е in без_cta]
    print(f"\nвсего замечаний: {len(беды)}")
    for е, б in беды[:25]:
        print(f"   [{е['файл']}] {е['загол'][:46]:46} {б}")


if __name__ == "__main__":
    главное(sys.argv[1] if len(sys.argv) > 1 else ".")
