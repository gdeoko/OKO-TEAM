# -*- coding: utf-8 -*-
"""Техническая проверка контента по правилам площадок и стоп-листу OKO.

Детерминированный слой: то, что можно посчитать, считается, а не оценивается.
Запуск:  python3 tehproverka.py MESYAC_1 MESYAC_2 MESYAC_3 REZERV.md
"""
import re, sys, os, glob, collections

# лимиты площадок, знаки
ЛИМИТЫ = {
    "Telegram": 1024,      # подпись к фото, пост с картинкой упирается в неё
    "Instagram": 2200,
    "ВКонтакте": 16000,
    "Дзен": 200000,
    "VC": 200000,
    "РБК": 200000,
}
# Запрещён именно подменный оборот «это не X, а Y», где на месте X стоит имя,
# а не действие. Живая фраза «никто не спрашивает, а платит» под запрет не попадает:
# там «не» относится к глаголу и никакой подмены понятий нет. Отсекаем по хвосту
# последнего слова перед запятой: глагольное окончание значит законный оборот.
_ХВОСТ = re.compile(r"(ться|ть|ешь|ёшь|ишь|ете|ёте|ите|ет|ёт|ит|ут|ют|ат|ят|ел|ёл|ил|ал|ял|"
                    r"ла|ло|ли|ем|им|ся|сь|л|ю|у)$", re.I)
_ПОДМЕНА = re.compile(r"\bне\s+([А-Яа-яЁё][А-Яа-яЁё\s]{1,34}?),\s*а\s+", re.I)


def подмены(текст):
    """Находит обороты подмены понятий, пропуская отрицание при глаголе."""
    из = []
    for м in _ПОДМЕНА.finditer(текст):
        # глагол ищем во всей группе: между «не» и запятой может стоять
        # наречие («не спрашивает на просмотре»), и хвост тогда не глагольный
        if not any(_ХВОСТ.search(с) for с in м.group(1).split()):
            из.append(м.group(0))
    return из


# что ищем: (имя, регулярка, где искать, пояснение)
ЗАПРЕТЫ = [
    ("длинное тире", r"[—–]", "всюду", "по правилу OKO только дефис"),
    ("технопарк", r"технопарк", "всюду", "стоп-слово, Департамент промышленности"),
    ("голый эмодзи", r"(?<!\{)[\U0001F300-\U0001FAFF☀-➿️](?!\})", "всюду",
     "эмодзи допустимы только разметкой премиум {🔥}"),
    ("нарисованная кнопка", r"кнопк[аиуе]\s+(в кадре|на картинке|«)", "визуал", "кнопки на картинке не кликабельны"),
    ("иишный оборот", r"в современном мире|не секрет,? что|стоит отметить|важно понимать,? что|"
                      r"в заключение|подводя итог|давайте разберём", "всюду", "штамп"),
]
# хештеги разрешены только этим видам
# Хештеги живут только в описаниях каруселей и роликов в соцсетях. В Телеграме их
# нет вообще, включая кружки: там хештег читается как мусор под личным сообщением.
ХЕШТЕГИ_МОЖНО = ("карусел", "ролик", "reels", "рилс", "описани")

ЗАГ = re.compile(r"^##\s+(.+)$", re.M)
БЛОК = re.compile(r"```\n(.*?)\n```", re.S)
# истории и карусели пишутся не блоком кода, а нумерованными кадрами «**1.** текст»
КАДР = re.compile(r"^\*\*(\d+)\.\*\*\s*(.+)$", re.M)


ТЕМА = re.compile(r"\n\*\*(.+?)\*\*", re.S)


def публикуемое(тело):
    """Собирает то, что реально уйдёт в публикацию: блоки кода плюс кадры историй."""
    из = [b.strip() for b in БЛОК.findall(тело)]
    if not из:
        из = [т.strip() for _, т in КАДР.findall(тело)]
    # Заголовок уходит в публикацию первой строкой (так собирает sborka_otpravki),
    # значит в лимит подписи он тоже входит. Считаем вместе с ним.
    тема = ТЕМА.search(тело)
    if тема and из:
        из.insert(0, тема.group(1).strip())
    return "\n\n".join(из)


def единицы(путь):
    """Режет файл недели на единицы: заголовок раздела плюс тело до следующего."""
    т = open(путь, encoding="utf-8").read()
    м = list(ЗАГ.finditer(т))
    дата = ""
    for i, з in enumerate(м):
        нач = з.end()
        кон = м[i + 1].start() if i + 1 < len(м) else len(т)
        тело = т[нач:кон]
        д = re.findall(r"^#\s+(\d\d\.\d\d\s+[А-Я]{2})\s*$", т[:з.start()], re.M)
        yield {"файл": os.path.basename(путь), "дата": д[-1] if д else дата,
               "загол": з.group(1).strip(), "тело": тело,
               "публикация": публикуемое(тело)}


def площадка(загол):
    for п in ЛИМИТЫ:
        if загол.lower().startswith(п.lower()):
            return п
    return ""


def проверить(е):
    беды = []
    пуб, тело = е["публикация"], е["тело"]
    п = площадка(е["загол"])
    if п and пуб:
        д = len(пуб)
        if д > ЛИМИТЫ[п]:
            беды.append(f"длина {д} при лимите {п} {ЛИМИТЫ[п]}")
    for имя, рег, где, поясн in ЗАПРЕТЫ:
        цель = тело if где == "всюду" else тело
        н = re.findall(рег, цель, re.I)
        if н:
            беды.append(f"{имя} x{len(н)}: {поясн} → {н[:3]}")
    п_подмен = подмены(тело)
    if п_подмен:
        беды.append(f"противопоставление x{len(п_подмен)}: оборот «не X, а Y» запрещён → {п_подмен[:3]}")
    хеш = re.findall(r"(?<!\w)#[А-Яа-яЁёA-Za-z][\w]{2,}", тело)
    if хеш:
        загол_н = е["загол"].lower()
        можно = (not загол_н.startswith("telegram")
                 and any(с in загол_н for с in ХЕШТЕГИ_МОЖНО))
        if not можно:
            беды.append(f"хештеги x{len(хеш)} там, где их быть не должно: {хеш[:4]}")
        elif len(хеш) > 30:
            беды.append(f"хештегов {len(хеш)}, лимит площадок 30")
    if пуб:
        абз = [а for а in пуб.split("\n") if len(а) > 420]
        if абз:
            беды.append(f"абзац длиннее 420 знаков x{len(абз)}")
    return беды


def main(цели):
    файлы = []
    for ц in цели:
        п = os.path.join(os.path.dirname(os.path.abspath(__file__)), ц)
        файлы += sorted(glob.glob(os.path.join(п, "*.md"))) if os.path.isdir(п) else [п]
    всего = плохих = 0
    счёт = collections.Counter()
    for ф in файлы:
        for е in единицы(ф):
            if not е["публикация"] and "визуал" not in е["загол"].lower():
                continue
            всего += 1
            б = проверить(е)
            if б:
                плохих += 1
                print(f"\n[{е['файл']} · {е['дата']}] {е['загол']}")
                for с in б:
                    print("   ·", с)
                    счёт[с.split(":")[0].split(" x")[0]] += 1
    print(f"\nединиц {всего}, с бедами {плохих}")
    for к, в in счёт.most_common():
        print(f"  {к}: {в}")
    return плохих


if __name__ == "__main__":
    sys.exit(0 if main(sys.argv[1:] or ["MESYAC_1"]) == 0 else 1)
