# -*- coding: utf-8 -*-
"""Сборка месяца в папку файлов под отправку в рабочий чат.

Служебные пометки про визуал в пакет не кладём: клиенту нужен готовый
материал, а не наша кухня. Чем закрывается недостающий кадр, пишем
один раз в сопроводительном сообщении.

Без сопроводительных текстов: пост это картинка и текст, карусель это все
слайды и описание, статья это обложка и файл текста, серия историй это кадры
и подписи. Каждая единица идёт своей папкой с номером и датой.

    python3 sborka_otpravki.py MESYAC_1 [папка-с-кадрами] [куда]
"""
import re, os, sys, io, json, shutil, glob

ПЛОЩАДКИ = {"Telegram": "TG", "Instagram": "IG", "ВКонтакте": "VK",
            "Дзен": "DZEN", "vc.ru": "VC", "РБК": "RBK"}
ЖИВЫЕ = {"P-05-lift", "P-11-shattl", "P-94-kvartal-karta", "P-01-krt-karta"}


def латиница(с):
    таб = {"а":"a","б":"b","в":"v","г":"g","д":"d","е":"e","ё":"e","ж":"zh","з":"z","и":"i",
           "й":"y","к":"k","л":"l","м":"m","н":"n","о":"o","п":"p","р":"r","с":"s","т":"t",
           "у":"u","ф":"f","х":"h","ц":"c","ч":"ch","ш":"sh","щ":"sch","ъ":"","ы":"y","ь":"",
           "э":"e","ю":"yu","я":"ya"}
    вышло = "".join(таб.get(б, таб.get(б.lower(), б).upper() if б.isupper() else б) for б in с.lower())
    return re.sub(r"[^a-z0-9]+", "-", вышло).strip("-")[:38]


def тип(з):
    if "карусел" in з: return "карусель"
    if "истори" in з: return "истории"
    if "Reels" in з or "кружок" in з: return "видео"
    if re.match(r"(Дзен|vc\.ru|РБК)", з): return "статья"
    return "пост"


def единицы(папка):
    сп = []
    for путь in sorted(glob.glob(os.path.join(папка, "NEDELYA_*.md"))):
        s = io.open(путь, encoding="utf-8").read()
        дата = ""
        for кусок in re.split(r"\n(?=(?:# \d\d\.\d\d |## ))", s):
            г = кусок.split("\n")[0]
            m = re.match(r"# (\d\d\.\d\d) ([А-Я]{2})", г)
            if m: дата = f"{m.group(1)} {m.group(2).lower()}"; continue
            if not re.match(r"## (Instagram|Telegram|ВКонтакте|Дзен|vc\.ru|РБК)", г): continue
            з = г[3:].strip()
            заг = re.search(r"\n\*\*(.+?)\*\*", кусок)
            текст = re.search(r"```\n(.*?)\n```", кусок, re.S)
            слайды = re.findall(r"^\*\*(\d+)\.\*\* ([^\n]+)\n> ([^\n]+)", кусок, re.M)
            хеш = re.search(r"Хештеги: ([^\n]+)", кусок)
            промпт = re.findall(r"промпт[ы]? `([^`]+)`", кусок)
            сп.append({"дата": дата, "загол": з, "площадка": з.split(" ·")[0].strip(),
                       "тип": тип(з), "тема": заг.group(1) if заг else "",
                       "текст": текст.group(1) if текст else "", "слайды": слайды,
                       "хештеги": хеш.group(1) if хеш else "",
                       "промпт": промпт[0] if промпт else ""})
    return сп


def кадры(ключ, папка):
    """Файлы кадров по ключу: сам ключ или серия ключ-01, ключ-02."""
    если_один = os.path.join(папка, ключ + ".png")
    if os.path.exists(если_один): return [если_один]
    серия = sorted(glob.glob(os.path.join(папка, ключ + "-*.png")))
    return серия


def главное(месяц, визуал, куда):
    сп = единицы(месяц)
    if os.path.isdir(куда): shutil.rmtree(куда)
    os.makedirs(куда)
    индекс = []
    for н, е in enumerate(сп, 1):
        имя = f"{н:02d}_{е['дата'].split()[0].replace('.','-')}_{ПЛОЩАДКИ.get(е['площадка'],'X')}_{латиница(е['тема'])}"
        папка = os.path.join(куда, имя)
        os.makedirs(папка, exist_ok=True)
        # текст
        части = []
        if е["тип"] in ("карусель", "истории"):
            части.append(е["тема"])
            части.append("")
            for н2, заг, подп in е["слайды"]:
                части.append(f"Слайд {н2}. {заг}")
                части.append(f"   {подп}")
            if е["текст"]:
                части += ["", "Описание к публикации:", "", е["текст"]]
        else:
            части.append(е["тема"])
            части.append("")
            части.append(е["текст"])
        if е["хештеги"]: части += ["", е["хештеги"]]
        имя_текста = "statya.txt" if е["тип"] == "статья" else "text.txt"
        io.open(os.path.join(папка, имя_текста), "w", encoding="utf-8").write("\n".join(части).strip() + "\n")
        # кадры
        найдено = кадры(е["промпт"], визуал) if е["промпт"] and визуал else []
        for i, ф in enumerate(найдено, 1):
            shutil.copy(ф, os.path.join(папка, f"{i:02d}.png"))
        нужно = len(е["слайды"]) if е["тип"] in ("карусель", "истории") else 1
        статус = "готово" if len(найдено) >= нужно else (
            "живая съёмка" if е["промпт"] in ЖИВЫЕ else f"кадров {len(найдено)} из {нужно}")
        индекс.append(f"{н:02d} | {е['дата']:9} | {ПЛОЩАДКИ.get(е['площадка'],'X'):4} | {е['тип']:8} | {статус:16} | {е['тема'][:58]}")
    io.open(os.path.join(куда, "00_SPISOK.txt"), "w", encoding="utf-8").write(
        f"Кластер, {месяц}: {len(сп)} единиц\n\n" + "\n".join(индекс) + "\n")
    print(f"собрано единиц: {len(сп)} в {куда}")
    готово = sum(1 for с in индекс if "готово" in с)
    print(f"с полным визуалом: {готово}, ждут кадров: {len(сп)-готово}")


if __name__ == "__main__":
    месяц = sys.argv[1] if len(sys.argv) > 1 else "MESYAC_1"
    визуал = sys.argv[2] if len(sys.argv) > 2 else ""
    куда = sys.argv[3] if len(sys.argv) > 3 else "otpravka_" + месяц.lower()
    главное(месяц, визуал, куда)
