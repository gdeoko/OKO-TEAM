/* Высоту документа берём из общего кэша: прямой вопрос заставляет
   браузер досчитать вёрстку, а спрашиваем мы её в каждом кадре. */
var DOCH = (window.RC_BOX && window.RC_BOX.docH) || function () {
  return document.documentElement.scrollHeight || 1;
};

var doc = document, root = doc.documentElement;

/* Переменные оформления публикуем через общий кэш: запись на корне
   документа инвалидирует стиль всему дереву, а зовём мы её каждый
   кадр. Пишем только то, что действительно изменилось. */
var V = (g.RC_VAR && g.RC_VAR.set) || function (el, n, v) {
  if (el && el.style) el.style.setProperty(n, v);
};
var T = null;                    /* three.js, появляется вместе с объёмным слоем */
var reduced = false;
try { reduced = matchMedia("(prefers-reduced-motion: reduce)").matches; } catch (e) {}

var TAU = Math.PI * 2;
/* Угол, на котором в рубке стоит приборная панель. Он же публикуется
   для слоя кабины (rc-cockpit), чтобы картинка пульта и поворот
   камеры считались от одного числа и не могли разъехаться.

   Ровно минус сорок пять градусов - это шов между седьмой и восьмой
   стеновыми панелями. Так пост управления встаёт не поверх стены, а
   вместо двух её плит: обе они не строятся, в оболочке на их месте
   вырезан проём, и в проёме стоит остекление. Раньше угол был
   произвольным (-0.62), панель приходилась на середину плиты, и
   пульт неизбежно оказывался наклейкой поверх стеллажа. */
var TH_CON = -Math.PI / 4;

/* Проём остекления: половина угла и высота пояса, в котором в
   оболочке нет стены. Всё, что связано с носовым окном - вырез в
   обшивке, стекло, рама, пропуск плит и стойки - считается из этих
   четырёх чисел, поэтому окно и дыра под него не могут разъехаться. */
var WIN_HALF = 0.60;             /* 34 градуса в каждую сторону от TH_CON */
var WIN_Y0 = 1.12;               /* низ проёма над полом */
var WIN_Y1 = 2.62;               /* верх проёма */
var R_SHELL = 2.6;               /* радиус обшивки: окно лежит в ней заподлицо */

/* Азимут (наша система: точка th лежит в R sin th, y, -R cos th) в
   угол цилиндра three.js (там точка лежит в r sin O, y, r cos O).
   Ровно один минус разницы, но без него вырез в обшивке оказывается
   в противоположном углу комнаты. */
function thetaOf(th) { return Math.PI - th; }

/* Попадает ли азимут в проём. Нормализуем разницу в отрезок
   (-пи, пи]: угол пульта отрицательный, а углы плит растут от нуля
   до полного круга, и без нормализации восьмая плита в проём не
   попадала. */
function inWindow(th, pad) {
  var d = th - TH_CON;
  while (d > Math.PI) d -= TAU;
  while (d < -Math.PI) d += TAU;
  return Math.abs(d) < WIN_HALF + (pad || 0);
}

/* ── Палитра рубки: единственный источник цвета ───────────────
   Раньше объёмная рубка, снимок пульта и стили формы красились
   каждый своим набором чисел. Из-за этого три соседних кадра -
   салон, пульт, кабина игры - читались как три разных сайта: у них
   не совпадали ни цвет стен, ни цветовая температура света.

   Теперь цвет объявлен ровно один раз здесь и тем же составом
   уходит в CSS (--int-*), поэтому оформление пульта физически не
   может разойтись с рубкой по тону: они берут одни и те же числа.
   Для полупрозрачных заливок рядом публикуется тройка каналов
   (--int-*-rgb), её удобно подставлять внутрь rgba(). */
var COL = {
  deep:  0x050C15,   /* дальний воздух и туман, самый тёмный тон */
  hull:  0x0A1524,   /* обшивка, корпуса приборов */
  wall:  0x0E1D2E,   /* стеновая панель рубки */
  panel: 0x14283D,   /* лицевая плита прибора, фон экранов */
  emis:  0x123C5C,   /* внутреннее свечение плиты */
  cyan:  0x42B2DC,   /* фирменный циан: швы, кромки, диоды */
  vio:   0x8A59F6,   /* фирменный фиолет: тёплая подсветка */
  lit:   0xCFE9F5    /* свет из остекления, холодный */
};

function hex6(n) {
  var s = n.toString(16);
  while (s.length < 6) s = "0" + s;
  return "#" + s;
}

/* Отдаём палитру в CSS сразу при загрузке файла, не дожидаясь
   сборки сцены: оформление секции контактов обязано быть в тон даже
   если объёмный слой ещё не поднялся или не поднимется вовсе. */
/* ── Кому отдавать доли рубки ────────────────────────────────
   Три числа - вход в тамбур, подъезд к пульту и отъезд от него -
   раньше писались на корень документа. Одна запись вместо пяти
   выглядела экономно, но переменная наследуемая: каждая такая
   запись помечала устаревшим стиль всего документа, а зовём мы их
   в каждом кадре. Трассировка на телефоне показала полный пересчёт
   дерева на кадр - две тысячи узлов ради пяти читателей.

   Читателей ровно пять, и все они известны поимённо: тамбур, его
   обшивка, слой кабины, секция контактов и голограмма эпилога.
   Пишем адресно им - и остальная страница о смене чисел даже не
   узнаёт. Список пересобираем, пока не соберётся весь: слои кабины
   и тамбура появляются в разметке позже первого кадра. */
var PUB_SEL = ".rc-int-air, .rc-int-lock, .rc-cockpit, #contact, .epi-holo";
var pubList = null, pubAt = 0, pubWant = 5;
function pubEls() {
  var now = Date.now();
  if (!pubList || (pubList.length < pubWant && now - pubAt > 400)) {
    pubAt = now;
    pubList = [].slice.call(doc.querySelectorAll(PUB_SEL));
  }
  return pubList;
}
function pub(name, val) {
  var list = pubEls();
  for (var i = 0; i < list.length; i++) V(list[i], name, val);
}

function paintCSS() {
  var k, v;
  for (k in COL) {
    if (!COL.hasOwnProperty(k)) continue;
    v = COL[k];
    V(root, "--int-" + k, hex6(v));
    V(root, "--int-" + k + "-rgb",
      ((v >> 16) & 255) + "," + ((v >> 8) & 255) + "," + (v & 255));
  }
}
paintCSS();

/* Геометрия рубки. Восемь стеновых панелей по кругу: на первых
   четырёх стоят карточки надёжности, на пятой - бортовой
   справочник с вопросами, остальные держат стену, чтобы при
   обороте в кадре не было глухого места. */
var PANELS = 8;
/* Азимут, на котором мы оказываемся, переступив порог: между
   первым экраном и остеклением, чтобы кадр входа не упирался ни в
   текст, ни в окно */
var ENTER_AZ = 0.35;
var STEP = TAU / PANELS;         /* сорок пять градусов на остановку */
var R_WALL = 2.52;               /* радиус, на котором висят панели */
var H_WALL = 1.75;               /* высота их центра над полом */
var EYE = 1.6;                   /* глаза человека, он же центр круга */

/* Пороги сцены. В сценарии они записаны процентами прокрутки, но
   проценты живут ровно до первой правки текста: добавили абзац -
   и рубка начинается посреди сценариев применения. Поэтому проценты
   мы считаем из настоящих позиций блоков, которые переехали внутрь
   корабля: надёжность, вопросы, форма. Числа из сценария остаются
   запасным вариантом на случай, если блоков вдруг нет. */
var P_PREP = 0.58;               /* с этого места начинаем строить */
var P_LOCK = 0.72;               /* тамбур */
var P_IN   = 0.76;               /* мы внутри */
var P_TURN = 0.88;               /* оборот закончен, дальше пульт */
var P_CON  = 0.965;              /* камера доехала до пульта, анкета в кадре */
var P_OUT  = 0.999;              /* конец сцены: дальше игра */

/* Расписание оборота: узлы вида [доля прокрутки, поворот в радианах].
   Между узлами идёт синусная кривая, в самих узлах камера стоит.
   Узел - это панель, напротив которой человек читает. */
var KNOT = [];
var PLAN = { step: STEP, rel: [], faq: STEP * 4.5, con: TAU, n: 4 };

function relCards() {
  var n = doc.querySelectorAll("#reliability .card").length;
  return n > 0 ? n : 4;
}

function measure() {
  var maxS = Math.max(1, DOCH() - innerHeight);
  var rel = doc.getElementById("reliability");
  var con = doc.getElementById("contact");
  if (!rel || !con) return;
  var faq = doc.getElementById("faq");
  var y = g.pageYOffset || doc.documentElement.scrollTop || 0;
  var relBox = rel.getBoundingClientRect();
  var conBox = con.getBoundingClientRect();
  var relTop = relBox.top + y, relBot = relBox.bottom + y;
  var conTop = conBox.top + y, conBot = conBox.bottom + y;
  var faqTop = relTop;
  if (faq) faqTop = faq.getBoundingClientRect().top + y;

  /* Надёжность — ещё полноценный раздел сайта: человек обязан
     дочитать его до конца. В прежней версии вход начинался у его
     верхней кромки, поэтому блок исчезал посреди чтения, а ракета
     оказывалась поверх карточек. Порог переносим к справочнику:
     сначала заканчивается раздел, затем открывается люк, и только
     потом вопросы становятся голограммой на стекле корабля. */
  P_IN   = Math.max(0.05, Math.min(0.95, (faqTop - innerHeight * 0.38) / maxS));
  /* Подход к люку начинается сильно раньше, чем раньше.

     Замер живьём на мониторе 1280x720: страница прокручивается на
     14641 точек, порог входа стоит на доле 0.829, а тамбур начинался
     на 0.809 - то есть весь подход занимал две сотых страницы,
     примерно триста точек прокрутки. А перед ним, от 0.72 до 0.81,
     картинка не менялась ВООБЩЕ: снимки подряд отличались на одну
     десятую единицы яркости при семи-сорока на живых участках.
     Десятая часть сайта, на которой человек крутит колесо, а кадр
     стоит. Проход по шлюзу к этому моменту уже закончен (камера
     замерла на отметке 1.7), а салон ещё не включился.

     Растягиваем подход на две высоты экрана. Дыра закрывается
     движением: камера всё это время едет к люку, а не ждёт. Прежняя
     мерка в четыре десятых экрана остаётся нижней границей на
     случай очень короткой страницы. */
  P_LOCK = Math.max(0.03, P_IN - Math.max(innerHeight * 0.4, innerHeight * 2.0) / maxS);
  P_TURN = Math.max(P_IN + 0.02, Math.min(0.985, (conTop - innerHeight * 0.4) / maxS));
  /* Подход к пульту заканчивается вместе с формой: дальше по
     сценарию камера не едет вперёд, а отступает. */
  P_CON  = Math.max(P_TURN + 0.01, Math.min(0.994, (conBot - innerHeight * 0.2) / maxS));
  /* А наружу мы не выходим вовсе. Раньше сцена заканчивалась на
     форме, и эпилог играл уже на улице: в кадре снова летела
     ракета, а кнопка старта висела на фоне сайта. Клиент назвал
     это нелогичным, и он прав - мы сидим внутри этой ракеты.
     Поэтому рубка держится до конца эпилога, а сам эпилог мы
     смотрим сквозь остекление кабины. */
  var epi = doc.getElementById("epilogue");
  var outBase = conBot;
  if (epi) {
    var eBox = epi.getBoundingClientRect();
    outBase = eBox.bottom + y;
  }
  /* Эпилог - последняя секция страницы, и низа у сцены попросту нет:
     докрутив до самого дна, человек всё ещё сидит в кресле корабля.
     Раньше порог стоял чуть выше конца документа, и на последних
     пикселях прокрутки рубка выключалась - в кадре снова появлялась
     ракета, из которой мы по сценарию не выходили. Поэтому с
     эпилогом выход вниз закрыт совсем: наружу можно только назад,
     обратной прокруткой через люк. */
  P_OUT = epi
    ? 1.0001
    : Math.max(P_CON + 0.004, Math.min(0.9995, (outBase - innerHeight * 0.1) / maxS));
  P_PREP = Math.max(0.2, P_LOCK - 0.12);
  /* Ракета обязана приземлиться до того, как мы войдём в люк:
     заходить внутрь корабля, который ещё летит, странно. */
  g.RC_LAND_AT = P_LOCK;

  /* ── Узлы оборота ──────────────────────────────────────────
     Владелец описал этот проход по шагам: «зашли на 20 градусов,
     повернулись вокруг до 350, и на 360 стоит та самая панель чуть
     дальше, мы приближаемся к ней».

     Так и разложено. Вход смотрит между экранами - на двадцати
     градусах, чтобы первый кадр внутри не упирался в текст. Дальше
     семь остановок по числу экранов на стенах: сорок пять, девяносто
     и так до трёхсот пятнадцати. Ноль азимута занят остеклением, и
     круг замыкается ровно на нём - на трёхстах шестидесяти.

     Остановки раскладываем по отрезку от входа до конца оборота
     равномерно. Раньше они считались от прямоугольников разделов, и
     это было верно, пока экраны были карточками сайта. Теперь экраны
     стоят на стенах салона и от вёрстки не зависят: их семь всегда, и
     делить между ними надо не разделы, а прокрутку. */
  PLAN.n = 7;
  PLAN.rel = [];
  KNOT = [[P_IN, ENTER_AZ]];
  var span = Math.max(0.004, P_TURN - P_IN);
  /* У каждой остановки не точка, а плато. Это принципиально: с
     одной точкой камера стоит напротив экрана ровно мгновение, а
     всё остальное время едет - и человек, листающий спокойно,
     видит не экраны, а стены между ними, да ещё и с обрезанным
     текстом по краям кадра.

     Поэтому на каждый экран отводится отрезок, и внутри него камера
     сначала стоит неподвижно, а остаток уходит на переход к
     следующему. Читать успевают, а поворот всё равно читается
     живым - он идёт с плавным входом и выходом (см. yawAt). */
  var seg = 0.86 / 7;                 /* доля отрезка на один экран */
  for (var i = 1; i <= 7; i++) {
    var a = i * STEP;
    PLAN.rel.push(a);
    var s0 = 0.09 + seg * (i - 1);
    /* Доли переезда и стоянки. Было 0.34 и 0.94, то есть на переход
       между экранами оставалось 40 процентов отрезка, а 60 камера
       стояла. При косинусном разгоне это даёт пиковую скорость почти
       вчетверо выше средней, и оборот читался рывками: замер шагами
       по 96 точек дал приросты 8,6°, 9,0°, 3,8°, 25,7°, 12,9° -
       разброс почти в семь раз при одинаковом шаге прокрутки. Ровно
       это заказчик и назвал «оборот неровный».

       Теперь переезд занимает 60 процентов отрезка, стоянка 40:
       прочитать по-прежнему успевают, а пик скорости падает в
       полтора раза. */
    KNOT.push([P_IN + span * (s0 + seg * 0.20), a]);   /* встали */
    KNOT.push([P_IN + span * (s0 + seg * 0.60), a]);   /* стоим */
  }
  PLAN.faq = 5 * STEP;
  /* Оборот замыкается ПОЛНОСТЬЮ к P_TURN, а не за десять градусов до
     него. Раньше последние 0.175 радиана докручивались уже во время
     подъезда, и два движения шли одновременно: замер показал долю
     кадра у панели 0.59 при незакрытом обороте (yaw 5.38 из 6.28) и
     полный кадр при yaw 6.11 - то есть панель вырастала на весь экран
     ещё в повороте. Владелец описал порядок иначе и однозначно:
     «сделали 360 оборот - она остаётся в своей позиции; ПОСЛЕ 360
     остановились смотря на неё; и приблизились».
     Теперь так и есть: круг закрыт, камера встала лицом к панели,
     и только потом начинается подъезд. */
  /* Оборот закрывается ЧУТЬ РАНЬШЕ рубежа, а не ровно на нём.

     Угол сходится к расписанию плавно, с запаздыванием - это и
     нужно, иначе поворот идёт рывками. Но пока последний узел стоял
     ровно на рубеже, к самому рубежу фактический угол отставал: замер
     показал 5.10 радиана из 6.28 в тот момент, когда подъезд к пульту
     уже начался. То есть последняя пятая часть круга проходила на
     ходу к панели, а заказчик просил разделить: сначала оборот
     целиком, потом подъезд.

     Даём запаздыванию место: расписание доводит угол до полного круга
     на пять сотых прокрутки раньше рубежа и держит его там. К рубежу
     угол успевает дойти по-настоящему, и подъезд получает свой
     промежуток целиком, без сжатия. */
  KNOT.push([Math.max(P_IN + 0.01, P_TURN - 0.05), TAU]);
  KNOT.push([P_TURN, TAU]);
  /* Подъезд идёт строго по оси окна: угол уже пришёл, держим его */
  KNOT.push([P_CON, TAU]);
  PLAN.con = TAU;

  /* Узлы обязаны идти строго по возрастанию: иначе на коротком
     блоке камера дёрнется назад посреди сектора. */
  for (i = 1; i < KNOT.length; i++) {
    if (KNOT[i][0] <= KNOT[i - 1][0]) KNOT[i][0] = KNOT[i - 1][0] + 0.0008;
  }
}

/* Поворот камеры для любой точки страницы. Одна функция на весь
   сайт: и сцена, и карточки спрашивают именно её. */
function yawAt(p) {
  if (!KNOT.length) return 0;
  if (p <= KNOT[0][0]) return KNOT[0][1];
  var last = KNOT.length - 1;
  if (p >= KNOT[last][0]) return KNOT[last][1];
  for (var i = 1; i <= last; i++) {
    if (p > KNOT[i][0]) continue;
    var p0 = KNOT[i - 1][0], p1 = KNOT[i][0];
    var t = (p - p0) / Math.max(1e-6, p1 - p0);
    /* Синус: на концах отрезка скорость ноль, значит камера сама
       останавливается напротив панели и текст успевают прочитать */
    var e = 0.5 - 0.5 * Math.cos(Math.PI * t);
    return KNOT[i - 1][1] + e * (KNOT[i][1] - KNOT[i - 1][1]);
  }
  return KNOT[last][1];
}

