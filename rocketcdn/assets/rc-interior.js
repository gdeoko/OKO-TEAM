function boot() {
  if (root.classList.contains("rc-reduced")) return;
  T = g.THREE;
  if (!T) return;
  /* Второй раз сюда заходить нельзя.

     Снизу стоит `addEventListener("rc:3d", boot)` И следом
     `if (g.THREE) boot()`. Объёмный слой грузится списком со снятым
     async, то есть строго по порядку, и three.js в этом списке идёт
     РАНЬШЕ этого файла: к моменту его выполнения g.THREE уже есть,
     и второй вызов срабатывает сразу. Потом приходит событие rc:3d и
     зовёт boot ещё раз.

     Защёлки не было, и всё, что boot подписывает, вешалось по два
     раза: смена языка, resize, load, люк, прокрутка, pageshow,
     видимость вкладки. Замер живьём: подписок на rc:hatch три,
     на pageshow две. Хуже всего прокрутка - обработчик прогресса
     стоял в списке дважды, и весь пересчёт геометрии рубки с
     проекцией панелей на пульте шёл вдвое чаще нужного на КАЖДЫЙ
     тик прокрутки. */
  if (boot.готово) return;
  boot.готово = true;
  measure();
  doc.addEventListener("rc:lang", function () { setTimeout(measure, 200); });
  addEventListener("resize", function () { setTimeout(measure, 250); }, { passive: true });
  addEventListener("load", function () { setTimeout(measure, 400); });

  /* Люк корабля открылся - подхватываем сцену тем же кадром, не
     дожидаясь следующего тика прокрутки: окно перехода короткое, и
     опоздание на кадр читается провалом в пустоту. */
  addEventListener("rc:hatch", function (e) {
    if (e && e.detail && e.detail.deep) setProgress(st.p);
  });

  /* Слушаем общий прогресс страницы */
  if (g.RC_MOTION) g.RC_MOTION.on(function (p) { setProgress(p); });
  else addEventListener("scroll", function () {
    var max = Math.max(1, DOCH() - innerHeight);
    setProgress((g.pageYOffset || 0) / max);
  }, { passive: true });

  /* BFCache/возврат во вкладку может восстановить scrollTop без
     события scroll. Синхронизируем сцену немедленно, чтобы старый
     класс кабины не блокировал страницу после возврата назад. */
  addEventListener("pageshow", function () {
    var max = Math.max(1, DOCH() - innerHeight);
    setProgress((g.pageYOffset || 0) / max);
  }, { passive: true });
  doc.addEventListener("visibilitychange", function () {
    if (!doc.hidden) {
      var max = Math.max(1, DOCH() - innerHeight);
      setProgress((g.pageYOffset || 0) / max);
    }
  }, { passive: true });
}

/* Ступени качества. Общий сторож кадров в rc-motion.js считает
   тяжёлые кадры и сообщает ступень: на первой мы считаем меньше
   пикселей, на второй гасим планету за окном и её ободок, на
   третьей рубка не поднимается вовсе - вместо кино человек
   получает обычную страницу, но без рывков. */
/* Качеством салона теперь распоряжается сцена игры: он часть её
   мира, и снижать разрешение отдельно ему нечем. Ступень нужна
   только для того, чтобы на самом слабом устройстве не поднимать
   объём вовсе. */
addEventListener("rc:degrade", function (e) {
  var step = (e && e.detail && e.detail.step) || 0;
  st.degrade = step;
});

