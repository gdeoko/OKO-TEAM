/* ═══════════════════════════════════════════════════════════
   Rocket CDN · музыкальная тема

   Заказчик выбрал тему сам и сказал главное о ней: она должна быть
   фоном, не действовать на нервы и не заставлять спешить. Поэтому
   здесь взят спокойный кусок с 3:48, из него собрана петля с
   перекрёстным затуханием - конец переходит в начало без шва, и
   человек не слышит, где трек пошёл по кругу.

   Как включается. На первом же действии человека на странице:
   прокрутка, щелчок, касание, нажатие клавиши - что случится раньше.
   Так просил заказчик: зашли на сайт, тронули его - тема играет.

   Почему не сразу на загрузке. Без действия человека браузер звук не
   пускает вовсе, это не наше решение и обойти его нечем. Поэтому
   тема ждёт первого касания страницы, а не ждёт, пока найдут кнопку.

   Почему прокрутки одной может не хватить. Колесо и прокрутка -
   это не то действие, которое браузер считает разрешением на звук:
   разрешение дают нажатие, касание и клавиша. Поэтому попытка на
   прокрутке делается честно, но если play() отклонён, слушатели
   остаются на месте и ждут настоящего нажатия. Тишины «навсегда»
   из-за одной неудачной попытки не бывает.

   Что заводится. Не тема отдельно, а весь звук сайта через
   RC_SOUND.start(): кнопка в шапке одна на всё, и если завести мимо
   неё, она покажет «выключено» при играющей музыке. Так уже было, и
   именно из-за этого автозапуск когда-то сняли. Здесь он вернулся
   вместе с кнопкой, а не в обход неё.

   Что при этом бережётся:
     · пока человек не тронул страницу, не качается ни один байт темы;
     · выключили тумблер - тема останавливается, выбор запоминается,
       и больше её не заводит ни первый жест, ни следующий визит;
     · класс music-on и событие rc:music держат кнопку в шапке в том
       же положении, в каком находится сам звук.

   Громкость. Ниже, чем кажется правильным на первый взгляд: тема
   должна читаться как воздух комнаты, а не как саундтрек поверх
   текста. Вход - шесть секунд, чтобы музыка не «включилась», а
   проявилась. Уход - меньше полусекунды: «выключить» обязано
   ощущаться нажатием, а не ожиданием. При грохоте старта и посадки
   тема отступает на пару секунд и возвращается.

   Выключение. Тот же тумблер, что и у звуков ракеты, и решение
   человека запоминается: сказал «выключить» - больше не включаем
   ни сейчас, ни в следующий раз.
   ═══════════════════════════════════════════════════════════ */
(function (g) {
"use strict";

var doc = document, root = doc.documentElement;
var KEY = "rcdn.sound";               /* один ключ на весь звук сайта */
var SRC_WEBM = "assets/audio/theme.webm";
var SRC_M4A  = "assets/audio/theme.m4a";

/* Уровень темы. Сознательно тихо: под ней должен читаться текст. */
var VOL = 0.30;
var VOL_QUIET = 0.16;                 /* когда человек в форме или в справочнике */
var FADE = 6.0;                       /* секунд на проявление */

var el = null, want = 0, cur = 0, raf = null, last = 0;
var started = false, killed = false, duckUntil = 0, boosted = false;

/* Человек уже говорил «выключить» - помним это между визитами.
   Ключ общий со звуками ракеты: кнопка в шапке одна на весь звук. */
function muteChoice() {
  try { return localStorage.getItem(KEY) === "off"; } catch (e) { return false; }
}

function build() {
  if (el) return el;
  el = doc.createElement("audio");
  el.loop = true;
  /* Строим элемент только когда музыку уже попросили, поэтому и
     качаем сразу всё: ждать больше нечего. */
  el.preload = "auto";
  el.volume = 0;
  el.setAttribute("playsinline", "");
  el.setAttribute("aria-hidden", "true");

  var a = doc.createElement("source");
  a.src = SRC_WEBM; a.type = "audio/webm; codecs=opus";
  var b = doc.createElement("source");
  b.src = SRC_M4A; b.type = "audio/mp4; codecs=mp4a.40.2";
  el.appendChild(a); el.appendChild(b);

  /* Файла нет или формат не понят - молчим, кнопку возвращаем в
     положение «выключено», чтобы она не врала про играющий звук */
  el.addEventListener("error", function () {
    killed = true;
    want = 0; cur = 0; started = false;
    root.classList.remove("music-on");
    tell(false);
  }, true);

  el.style.cssText = "position:absolute;width:0;height:0;opacity:0;pointer-events:none";
  doc.body.appendChild(el);
  return el;
}

function tell(on) {
  try { dispatchEvent(new CustomEvent("rc:music", { detail: { on: !!on } })); } catch (e) {}
}

/* Кадровый цикл поднимаем только когда есть что вести: громкость
   едет, тема пригнулась под грохот или трек ещё не завёлся. */
function kick() {
  if (!raf) { last = 0; raf = requestAnimationFrame(frame); }
}

/* Плавность ведём сами: у элемента нет своих переходов громкости,
   а резкое включение как раз и есть то, что бьёт по нервам. */
function frame(ts) {
  var moving = Math.abs(cur - want) > 0.002 || duckUntil > ts || (want > 0 && !started);
  raf = moving ? requestAnimationFrame(frame) : 0;
  if (!raf) last = 0;

  var dt = last ? Math.min(0.1, (ts - last) / 1000) : 0.016;
  last = ts;
  if (!el) return;

  var goal = want;
  if (duckUntil > ts) goal *= 0.42;   /* грохот старта: тема отступает */

  /* Вниз идём заметно быстрее, чем вверх. Шесть секунд на проявление
     это про то, чтобы музыка не «включилась», а появилась. А вот
     «выключить» обязано ощущаться нажатием: с общим временем тема
     после нажатия таяла ещё около четырёх секунд, и человек успевал
     нажать второй раз, решив, что кнопка не сработала. */
  var шаг = goal < cur ? 0.45 : (FADE / 6);
  if (Math.abs(cur - goal) < 0.002) { cur = goal; }
  else cur += (goal - cur) * Math.min(1, dt / шаг);

  var v = cur < 0 ? 0 : (cur > 1 ? 1 : cur);
  try { if (Math.abs(el.volume - v) > 0.003) el.volume = v; } catch (e) {}

  /* Дошли до нуля - останавливаем совсем. Держать трек на паузе
     без звука незачем: немого прогона в этой схеме нет. */
  if (v < 0.004 && !want && started) { try { el.pause(); } catch (e2) {} started = false; }
}

function play() {
  if (!el || killed) return null;
  var r = null;
  try { r = el.play(); } catch (e) { return null; }
  if (r && r.then) {
    r.then(function () { started = true; завелось(); }).catch(function () {
      /* Браузер отказал даже после нажатия - значит звука нет, и
         кнопка обязана это показать, а не гореть «включено» */
      started = false;
      want = 0; cur = 0;
      root.classList.remove("music-on");
      tell(false);
      неЗавелось();
    });
  } else { started = true; завелось(); }
  return r;
}

/* ── Включение ───────────────────────────────────────────────
   Зовётся из обработчика жеста: нажатия на кнопку звука в шапке
   или первого действия человека на странице. И то и другое - жест,
   ради которого браузер вообще разрешает звук. Здесь же начинается
   загрузка файла. */
function on(level) {
  if (killed) return;
  /* Слово человека сильнее любого вызова: сказал «выключить» - тема не
     поднимается, кто бы её ни звал. Кнопка звука пишет «on» в этот же
     ключ ДО того, как позвать нас, поэтому собственное нажатие сюда
     не упирается. */
  if (muteChoice()) return;
  build();
  want = level === undefined ? VOL : level;
  if (!started || el.paused) play();
  root.classList.add("music-on");
  tell(true);
  kick();
}

function silence() {
  want = 0;
  root.classList.remove("music-on");
  tell(false);
  kick();
}

/* ── Наружу ──────────────────────────────────────────────────
   Тумблер звука в шапке дёргает и тему тоже: у человека одна
   кнопка на весь звук сайта, а не две. */
g.RC_MUSIC = {
  on: on,
  off: silence,
  quiet: function (yes) { if (want) { want = yes ? VOL_QUIET : VOL; kick(); } },
  /* Полёт: музыка встаёт в полный рост - клиент просил громче,
     когда летим. Выход из полёта возвращает фоновый уровень.
     Завести молчащую тему полёт не может: раньше boost(true) сам
     звал on(), и человек, не трогавший кнопку звука, получал
     музыку от одного нажатия «Начать полёт». */
  boost: function (yes) {
    if (!want) { boosted = false; return; }
    boosted = !!yes;
    want = yes ? 0.55 : VOL;
    kick();
  },
  duck: function (ms) { duckUntil = performance.now() + (ms || 2200); kick(); },
  /* Для кнопки в шапке: «включено» это намерение играть плюс живой
     трек. Ждать, пока шестисекундное проявление доедет до слышимой
     громкости, кнопка не должна - иначе первые секунды после
     нажатия она показывает «выключено» при играющей музыке. */
  playing: function () { return !!(el && want > 0 && !el.paused); },
  level: function () { return cur; },
  state: function () {
    return {
      файл: el ? (el.currentSrc || "").split("/").pop() : null,
      создан: !!el,
      идёт: !!(el && !el.paused),
      громкость: +cur.toFixed(3), цель: +want.toFixed(3),
      сломан: killed,
      жест: жест
    };
  }
};

/* ── Первое действие человека ─────────────────────────────────
   Ноль - ещё ждём, 1 - попытка в ходу, 2 - завелось, больше не лезем.
   Промежуточное состояние нужно, чтобы не заводить звук заново на
   каждом событии, пока браузер думает над первым play().

   Итог попытки приходит из самого play(): его обещание и есть ответ
   браузера, пустил он звук или нет. Раньше здесь стоял замер по
   таймеру на 600 мс, и он врал: полмегабайта темы не всегда успевают
   доехать за это время, замер видел «не играет» и оставлял
   слушатели на месте. Дальше любой щелчок заводил звук заново и
   вместе с ним сбрасывал громкость к фоновой - в полёте, где музыка
   должна стоять в полный рост, и у пульта, где она должна отступать. */
var жест = 0;
var ЖЕСТЫ = ["pointerdown", "touchstart", "keydown", "wheel", "scroll", "click"];

/* Тема пошла - откуда бы её ни завели. Ждать первого действия больше
   незачем, и слушатели уходят. Условия «только если попытка была
   нашей» здесь нет намеренно: человек может первым же движением
   нажать на сам тумблер звука, тема заиграет от него, а слушатели
   останутся висеть и на следующем щелчке заведут звук по второму
   разу - вместе со сбросом громкости к фоновой. */
function завелось() {
  жест = 2;
  слушатьЖесты(false);
}

/* Браузер отказал. Обычно это прокрутка колесом: разрешением на звук
   она не считается. Возвращаемся в ожидание настоящего нажатия. */
function неЗавелось() {
  if (жест === 1) жест = 0;
}

function слушатьЖесты(вкл) {
  for (var i = 0; i < ЖЕСТЫ.length; i++) {
    if (вкл) addEventListener(ЖЕСТЫ[i], первыйЖест, { passive: true, capture: true });
    else removeEventListener(ЖЕСТЫ[i], первыйЖест, true);
  }
}

function первыйЖест(e) {
  if (жест) return;
  /* Человек уже говорил «выключить» - его слово сильнее заказчика */
  if (muteChoice() || killed) { слушатьЖесты(false); return; }

  /* Нажатие на сам тумблер звука пропускаем мимо: слушаем мы в фазе
     погружения, то есть раньше кнопки, и если завести звук отсюда,
     собственный обработчик кнопки увидит его уже включённым и
     честно выключит. Человек нажал «включить» и получил тишину.
     Пусть кнопка распоряжается собой сама. */
  var ц = e && e.target;
  if (ц && ц.closest && ц.closest(".js-sound")) return;

  жест = 1;

  /* Через общий выключатель, а не мимо него: он заведёт и тему, и
     звуки корабля, и приведёт кнопку в шапке в положение
     «включено». Если Web Audio на устройстве нет, RC_SOUND тоже
     нет - тогда поднимаем одну тему. */
  if (g.RC_SOUND && g.RC_SOUND.start) { try { g.RC_SOUND.start(); } catch (e) {} }
  else on();

  /* Страховка на случай, когда ответа нет вовсе: звукового узла не
     завелось, до play() дело не дошло, и обещание некому исполнить.
     Без неё попытка осталась бы «в ходу» навсегда, и следующее
     действие человека уже ничего бы не завело. */
  setTimeout(неЗавелось, 6000);
}

/* ── Обстановка вокруг темы ──────────────────────────────────
   Всё это работает только когда музыка уже играет: пока want ноль,
   слушатели просто ничего не делают и ни байта не качают. */
function wire() {
  слушатьЖесты(true);

  /* Тише там, где читают и пишут. Справочник и пульт - места, где
     человек думает над текстом, музыка там отходит на шаг назад и
     возвращается, когда сцена снова становится полётом. */
  addEventListener("rc:act", function (e) {
    var a = e && e.detail && e.detail.act;
    if (!want || boosted) return;
    want = (a === "console" || a === "manual") ? VOL_QUIET : VOL;
    kick();
  });
  doc.addEventListener("focusin", function (e) {
    if (!want || boosted) return;
    var n = e.target && e.target.tagName;
    if (n === "INPUT" || n === "TEXTAREA" || n === "SELECT") { want = VOL_QUIET; kick(); }
  });
  doc.addEventListener("focusout", function () {
    if (want) setTimeout(function () {
      if (!want || boosted) return;
      var a = doc.activeElement && doc.activeElement.tagName;
      if (a !== "INPUT" && a !== "TEXTAREA" && a !== "SELECT") {
        var act = g.RC_SCENE && g.RC_SCENE.act;
        want = (act === "console" || act === "manual") ? VOL_QUIET : VOL;
        /* Кадровый цикл засыпает, когда громкость доехала: без толчка
           новый уровень остался бы числом в переменной, а не звуком */
        kick();
      }
    }, 60);
  });

  /* Ушли со вкладки - тема замолкает и не играет в пустоту.
     Вернулись при включённом звуке - продолжаем с того же места. */
  doc.addEventListener("visibilitychange", function () {
    if (!el || !want) return;
    if (doc.hidden) { try { el.pause(); } catch (e) {} started = false; }
    else { play(); kick(); }
  });

  /* Человек сказал «выключить» в другой вкладке - гасим и здесь */
  addEventListener("storage", function (e) {
    if (e && e.key === KEY && e.newValue === "off" && want) silence();
  });
}

if (doc.readyState === "loading") doc.addEventListener("DOMContentLoaded", wire);
else wire();

})(window);
