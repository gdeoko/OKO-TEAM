/* ═══════════════════════════════════════════════════════════
   Rocket CDN · прокол: переход на сайт RocketVPN через пространство

   ЗАЧЕМ. Уход с причала VPN был мгновенной сменой адреса: причал
   разгорался семьсот миллисекунд, и браузер уезжал на другую страницу.
   На той стороне человека встречает акт «Выход», где сеть уже открыта,
   и он оказывается там без всякого объяснения, как будто нажал ссылку
   в меню. Владелец просил другого: голограмма должна открывать прокол
   и высаживать человека на сайте VPN.

   Прокол это единственное место, где два сайта соприкасаются, и он
   обязан выглядеть одинаково с обеих сторон. На стороне VPN он уже
   есть: линза, кольцо входа, полосы тоннеля, ядро с той стороны. Здесь
   собрано то же самое явление, только навстречу и своим цветом.

   ПОЧЕМУ ХОЛСТ, А НЕ ШЕЙДЕР. На той стороне прокол живёт внутри
   трёхмерной сцены акта и рисуется шейдером на весь кадр. Здесь его
   надо показать поверх ЛЮБОГО состояния: и когда открыт космос со
   своим контекстом, и когда человек стоит в рубке, и когда объёмного
   слоя нет вовсе. Просить второй контекст WebGL ради полутора секунд
   значит рисковать тем, что его не дадут, и переход исчезнет. Плоский
   холст рисует то же явление и не зависит ни от чего.

   ПОЧЕМУ ПЕРЕХОД НЕ ОТМЕНЯЕТСЯ. Прокол это уже уход: как только он
   пошёл, адрес сменится. Отмена посреди перехода оставила бы человека
   в кадре, который ничего не значит. Короткий ход у него есть раньше,
   в самом стыковочном узле: «Остаться в космосе» и Escape.

   ПОРЯДОК КАДРОВ. Ровно тот же, что на стороне VPN, и в тех же долях:
     0.00-0.30  линза: сетка пространства стягивается к середине;
     0.18-0.62  кольцо входа сходится из-за края кадра к центру;
     0.34-0.86  полосы тоннеля идут навстречу, кадр набирает скорость;
     0.70-1.00  ядро: свет с той стороны заливает кадр целиком.
   ═══════════════════════════════════════════════════════════ */
(function (g) {
"use strict";

var doc = document;

/* Полторы секунды. Меньше секунды прокол читается вспышкой и не
   успевает стать местом; больше двух он начинает восприниматься как
   задержка загрузки, и человек тянется к кнопке «назад». */
var ХОД = 1500;

/* Цвет той стороны. Индиго это марка RocketVPN, и человек видит его
   на причале ещё до нажатия: свет в тоннеле обязан быть тем же, иначе
   переход выглядит уходом неизвестно куда. */
var ИНДИГО = [138, 156, 255];

var идёт = false;

function тише() {
  try { return matchMedia("(prefers-reduced-motion: reduce)").matches; }
  catch (e) { return false; }
}

function мягко(a, b, x) {
  if (x <= a) return 0;
  if (x >= b) return 1;
  var t = (x - a) / (b - a);
  return t * t * (3 - 2 * t);
}

function цвет(c, a) {
  return "rgba(" + c[0] + "," + c[1] + "," + c[2] + "," + a.toFixed(3) + ")";
}

/* ── Кадр ─────────────────────────────────────────────────────
   Всё считается от середины кадра и от его половинной диагонали:
   тогда явление одинаково лежит и на телефоне в портрете, и на
   мониторе 21:9, и ни одна его часть не уходит за край. */
function кадр(x, ш, в, доля) {
  var сх = ш / 2, су = в / 2;
  var R = Math.sqrt(ш * ш + в * в) / 2;
  var i;

  x.clearRect(0, 0, ш, в);

  /* Подложка: пространство темнеет по мере входа. Без неё полосы
     тоннеля идут по живой странице, и прокол читается наложением
     поверх сайта, а не местом, куда мы попали. */
  x.fillStyle = "rgba(2,5,12," + мягко(0.00, 0.55, доля).toFixed(3) + ")";
  x.fillRect(0, 0, ш, в);

  /* 1. Линза. Сетка пространства, стянутая к середине: линии, которые
     были прямыми, изгибаются внутрь. Рисуем дугами по кольцам, шаг
     кольца сжимается вместе с ходом. */
  var линза = мягко(0.00, 0.30, доля) * (1 - мягко(0.66, 0.92, доля));
  if (линза > 0.004) {
    x.lineWidth = 1;
    for (i = 1; i <= 9; i++) {
      var к = i / 9;
      /* Кольцо подтягивается к центру тем сильнее, чем дальше оно
         стояло: так и работает линза. */
      var r = R * к * (1 - 0.42 * линза * к);
      x.strokeStyle = цвет(ИНДИГО, 0.10 + 0.18 * линза * (1 - к));
      x.beginPath();
      x.arc(сх, су, r, 0, 6.283);
      x.stroke();
    }
    /* Меридианы: без них кольца читаются мишенью, а не пространством. */
    for (i = 0; i < 16; i++) {
      var а = i / 16 * 6.283;
      x.strokeStyle = цвет(ИНДИГО, 0.07 + 0.12 * линза);
      x.beginPath();
      x.moveTo(сх + Math.cos(а) * R * 0.18, су + Math.sin(а) * R * 0.18);
      x.lineTo(сх + Math.cos(а) * R * 1.05, су + Math.sin(а) * R * 1.05);
      x.stroke();
    }
  }

  /* 2. Кольцо входа. Приходит из-за края кадра и сходится к середине:
     это и есть край прокола, сквозь который мы проходим. */
  var кольцоХод = мягко(0.18, 0.62, доля);
  if (кольцоХод > 0 && кольцоХод < 1) {
    var rк = R * (1.18 - 1.06 * кольцоХод);
    var яркость = Math.sin(кольцоХод * Math.PI);
    x.lineWidth = 2 + 10 * яркость;
    x.strokeStyle = цвет(ИНДИГО, 0.30 + 0.55 * яркость);
    x.beginPath();
    x.arc(сх, су, rк, 0, 6.283);
    x.stroke();
    /* Внутренняя нить: у кольца есть толщина, и без второй линии оно
       выглядит нарисованным, а не светящимся. */
    x.lineWidth = 1.5;
    x.strokeStyle = "rgba(226,236,255," + (0.35 * яркость).toFixed(3) + ")";
    x.beginPath();
    x.arc(сх, су, rк * 0.965, 0, 6.283);
    x.stroke();
  }

  /* 3. Полосы тоннеля. Идут НАВСТРЕЧУ, от середины к краю: мы входим,
     а не смотрим со стороны. Длина полосы растёт с ходом, поэтому под
     конец кадр читается скоростью. */
  var тоннель = мягко(0.34, 0.86, доля);
  if (тоннель > 0.004) {
    var полос = 64;
    for (i = 0; i < полос; i++) {
      /* Псевдослучайно, но одинаково от кадра к кадру: полосы обязаны
         стоять на своих местах, иначе тоннель мерцает шумом. */
      var s = Math.sin(i * 12.9898) * 43758.5453;
      var фаза = s - Math.floor(s);
      var уг = i / полос * 6.283 + фаза * 0.09;
      var от = R * (0.06 + 0.52 * фаза) * (1 - тоннель * 0.6);
      var до = от + R * (0.10 + 0.70 * тоннель) * (0.4 + фаза);
      var а2 = тоннель * (0.10 + 0.34 * фаза);
      x.strokeStyle = цвет(ИНДИГО, а2);
      x.lineWidth = 1 + 2.6 * фаза * тоннель;
      x.beginPath();
      x.moveTo(сх + Math.cos(уг) * от, су + Math.sin(уг) * от);
      x.lineTo(сх + Math.cos(уг) * до, су + Math.sin(уг) * до);
      x.stroke();
    }
  }

  /* 4. Ядро. Свет с той стороны. К концу заливает кадр целиком, и
     страница уходит из-под человека уже в этом свете: следующее, что
     он увидит, будет сайт VPN. */
  var ядро = мягко(0.70, 1.00, доля);
  if (ядро > 0.002) {
    var rя = R * (0.05 + 1.30 * ядро * ядро * ядро);
    var гр = x.createRadialGradient(сх, су, 0, сх, су, Math.max(1, rя));
    гр.addColorStop(0, "rgba(240,245,255," + Math.min(1, ядро * 1.25).toFixed(3) + ")");
    гр.addColorStop(0.35, цвет(ИНДИГО, Math.min(1, ядро * 1.05)));
    гр.addColorStop(1, цвет(ИНДИГО, 0));
    x.fillStyle = гр;
    x.fillRect(0, 0, ш, в);
  }
}

/* ── Открыть ──────────────────────────────────────────────────
   Возвращает true, если прокол пошёл. Ложь означает, что показать его
   нечем, и звать надо было сразу: тот, кто вызвал, обязан в этом
   случае уйти по адресу сам. */
function открыть(готово) {
  if (идёт) return true;

  var завершить = function () {
    if (typeof готово === "function") { готово(); }
  };

  /* «Уменьшить движение» это не просьба показать то же самое медленнее.
     Человеку с этой настройкой полторы секунды летящих полос стоят
     дороже, чем ему даёт переход. Уходим сразу. */
  if (тише()) { завершить(); return true; }

  var хол = doc.createElement("canvas");
  хол.className = "rc-prokol";
  хол.setAttribute("aria-hidden", "true");
  var кон = null;
  try { кон = хол.getContext("2d"); } catch (e) {}
  if (!кон) return false;

  идёт = true;
  doc.body.appendChild(хол);
  doc.documentElement.classList.add("rc-prokol-idet");

  /* Плотность режем по двойке: явление это пятна света и тонкие линии,
     на трёх точках устройства оно не становится лучше, а заливка
     растёт вдвое ровно в тот момент, когда браузер ещё и грузит
     следующую страницу. */
  var пл = Math.min(2, g.devicePixelRatio || 1);
  var ш = 0, в = 0;
  function размер() {
    ш = innerWidth; в = innerHeight;
    хол.width = Math.round(ш * пл);
    хол.height = Math.round(в * пл);
    хол.style.width = ш + "px";
    хол.style.height = в + "px";
    кон.setTransform(пл, 0, 0, пл, 0, 0);
  }
  размер();
  addEventListener("resize", размер, { passive: true });

  try {
    if (g.RC_SOUND && g.RC_SOUND.hyper) g.RC_SOUND.hyper();
  } catch (e2) {}

  /* Убрать за собой. Обычно это не понадобится: следующим кадром
     браузер уходит на другую страницу и уносит всё разом. Но переход
     может и не случиться - сеть отвалилась, передача ответила
     ошибкой, человек нажал «назад». Тогда залитый светом кадр
     останется висеть поверх живого сайта, и выйти из него будет
     нечем. Через четыре секунды после конца снимаем холст сами. */
  function убрать() {
    removeEventListener("resize", размер);
    if (хол.parentNode) хол.parentNode.removeChild(хол);
    doc.documentElement.classList.remove("rc-prokol-idet");
    идёт = false;
  }

  var начало = 0;
  var ушли = false;
  function довести() {
    if (ушли) return;
    ушли = true;
    завершить();
    setTimeout(убрать, 4000);
  }
  function шаг(t) {
    if (!начало) начало = t;
    var доля = Math.min(1, (t - начало) / ХОД);
    кадр(кон, ш, в, доля);
    if (доля < 1) { g.requestAnimationFrame(шаг); return; }
    довести();
  }
  g.requestAnimationFrame(шаг);

  /* Страховка. Вкладку могли увести в фон, и тогда кадры не приходят
     вовсе: человек вернётся и обнаружит, что переход не случился.
     Сторож ждёт вдвое дольше хода и уводит сам. */
  setTimeout(довести, ХОД * 2 + 400);

  return true;
}

/* ── Один кадр по доле хода ───────────────────────────────────
   Ход прокола на глаз не проверить: полторы секунды, а снимок в
   песочнице делается дольше, чем идёт половина явления. Через эту
   точку приёмка ставит долю руками и снимает кадр таким, каким его
   увидит человек ровно в этот момент. На боевом кадре её никто не
   зовёт, стоить она ничего не может. */
function кадрПоДоле(доля) {
  var хол = doc.querySelector(".rc-prokol-проба");
  var кон;
  if (!хол) {
    хол = doc.createElement("canvas");
    хол.className = "rc-prokol rc-prokol-проба";
    хол.setAttribute("aria-hidden", "true");
    doc.body.appendChild(хол);
  }
  try { кон = хол.getContext("2d"); } catch (e) { return false; }
  if (!кон) return false;
  var пл = Math.min(2, g.devicePixelRatio || 1);
  хол.width = Math.round(innerWidth * пл);
  хол.height = Math.round(innerHeight * пл);
  хол.style.width = innerWidth + "px";
  хол.style.height = innerHeight + "px";
  кон.setTransform(пл, 0, 0, пл, 0, 0);
  кадр(кон, innerWidth, innerHeight, Math.max(0, Math.min(1, +доля || 0)));
  return true;
}

g.RC_PROKOL = {
  "открыть": открыть,
  "идёт": function () { return идёт; },
  "ход": ХОД,
  "_кадр": кадрПоДоле
};

})(window);
