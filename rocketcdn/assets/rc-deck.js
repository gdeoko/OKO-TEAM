function создать(wrap) {
  var cv = doc.createElement("canvas");
  cv.className = "rcf-instr";
  cv.setAttribute("aria-hidden", "true");
  var c = cv.getContext("2d");

  /* Черновики: содержимое ниши рисуется в свой холст, а потом
     вливается в четырёхугольник. Так содержимое считает в удобных
     прямых координатах и не знает про сходимость пульта. */
  var буф = doc.createElement("canvas");
  var бк = буф.getContext("2d");
  /* Второй черновик под сияние. Размывать приходится ровно один раз
     на нишу: если размывать при вливании, фильтр ложится на каждую из
     двух десятков полос, и на слабой машине кадр падает в пол. Сайт и
     так упрекали за тормоза, повторять эту ошибку нельзя. */
  var ор = doc.createElement("canvas");
  var орк = ор.getContext("2d");
  /* Холст под отражение пульта в стекле. */
  var зерк = doc.createElement("canvas");

  var сост = { фаза: 0, тяга: 0.62, щит: 0.86, корпус: 1, тангаж: 0, крен: 0,
               метки: [], подписи: true,
               /* Во сколько раз черновик крупнее экрана. Приборы
                  рисуются в буфер 1.6x с учётом плотности пикселей,
                  и кегль, заданный числом в черновике, на экране
                  выходил вдвое-втрое мельче: замер дал подписи
                  приборов ростом 3,75-6,4 точки. Держим здесь, чтобы
                  каждая подпись знала, сколько это в точках экрана. */
               кД: 1.6 };
  var сила = [];           /* свет каждой клавиши, 0..1 */
  var зоны = [];           /* четырёхугольники клавиш на экране */
  var W = 0, H = 0, DPR = 1, meta = null, разметка = null, ru = true;

  function размер(w, h, dpr) {
    W = w; H = h; DPR = dpr;
    cv.width = Math.round(w * dpr);
    cv.height = Math.round(h * dpr);
    cv.style.width = w + "px";
    cv.style.height = h + "px";
  }

  function буфер(w, h) {
    w = Math.max(2, Math.round(w)); h = Math.max(2, Math.round(h));
    if (буф.width !== w || буф.height !== h) { буф.width = w; буф.height = h; }
    else бк.clearRect(0, 0, w, h);
    return { w: w, h: h };
  }

  /* Подмешивает к содержимому ниши его же размытую копию: у света под
     стеклом всегда есть ореол, без него линии выглядят наклейкой. */
  function сияние(w, h, r) {
    if (r < 0.6) return;
    if (ор.width !== w || ор.height !== h) { ор.width = w; ор.height = h; }
    else орк.clearRect(0, 0, w, h);
    орк.save();
    орк.filter = "blur(" + r.toFixed(1) + "px)";
    орк.drawImage(буф, 0, 0);
    орк.restore();
    бк.save();
    бк.globalCompositeOperation = "lighter";
    бк.globalAlpha = 0.6;
    бк.drawImage(ор, 0, 0);
    бк.restore();
  }

  function кадр(dt) {
    if (!meta || !разметка || !cv.width) return;
    сост.фаза = (сост.фаза + dt * 0.22) % 1;
    var п = покрытие(meta, cv.width, cv.height);
    /* Плотность черновика меняется вместе с плотностью экрана -
       обновляем её каждый кадр, а не берём начальное значение. */
    сост.кД = 1.6 * DPR;
    c.setTransform(1, 0, 0, 1, 0, 0);
    c.clearRect(0, 0, cv.width, cv.height);
    c.globalCompositeOperation = "lighter";

    var э = разметка["экраны"] || [];
    for (var i = 0; i < э.length; i++) {
      var q = угол(п, ужать(э[i]["угол"], 0.05));
      var ш = Math.hypot(q[1].x - q[0].x, q[1].y - q[0].y);
      var в = Math.hypot(q[3].x - q[0].x, q[3].y - q[0].y);
      /* Черновик берём вдвое крупнее места на экране: после вливания
         полосами остаётся запас на сглаживание, и линии не рвутся. */
      var б = буфер(ш * 1.6, в * 1.6);
      var f = ПРИБОР[э[i]["ид"]];
      if (f) { бк.save(); f(бк, б.w, б.h, сост); бк.restore(); }
      сияние(б.w, б.h, б.h * 0.05);
      влить(c, буф, q, б.w, б.h);
    }

    зоны.length = 0;
    var K = g.RC_KEYS ? g.RC_KEYS.KEYS : [];
    var п_ = разметка["полосы"] || [];
    var n = 0;

    /* Подписи ставим или всем клавишам, или никому.

       Решение принималось по каждой клавише отдельно, и на широком
       экране вышло вразнобой: у КУРС и СКАН места чуть меньше, подписи
       нет, у соседних УЗЕЛ и ЗАЛП есть. Пульт от этого читается
       собранным из разных наборов. Меряем самое тесное место на плите
       и по нему решаем за весь пульт. */
    var самоеТесное = 1e9;
    for (var s0 = 0; s0 < п_.length; s0++) {
      var кв0 = места(ужать(п_[s0]["угол"], 0.03), п_[s0]["мест"], п_[s0]["зазор"]);
      for (var j0 = 0; j0 < кв0.length; j0++) {
        var q0 = угол(п, кв0[j0]);
        var в0 = Math.hypot(q0[3].x - q0[0].x, q0[3].y - q0[0].y) / DPR;
        if (в0 < самоеТесное) самоеТесное = в0;
      }
    }
    /* ── В каком порядке раздаём команды ─────────────────────
       Полосы лежат в файле разметки в том порядке, в каком их снял
       обмерщик с фотографии плиты, а не по важности. На широкой
       плите первой в списке оказалась боковая ниша на скошенной
       панели: верхнее ребро у неё наклонено на сорок градусов. Туда
       и попадала первая команда - КУРС. На кадре она стояла ромбом
       наискось, подпись вместе с ней, а соседние СКАН, УЗЕЛ и
       СПРАВКА - строго горизонтально. Владелец увидел ровно это:
       «кнопки криво встроены».

       Порядок теперь по наклону: сначала ровные ниши главного ряда,
       потом скошенные боковые. Первые команды садятся на ровное
       место, а на скошенные панели уходят последние - зум и снимок,
       ровно как и задумано в самой разметке («ещё четыре команды
       лежат в боковых нишах на скошенных панелях»). Сортировка
       устойчивая: внутри одной степени наклона порядок файла
       сохраняется. */
    var порядок = [];
    for (var п0 = 0; п0 < п_.length; п0++) порядок.push(п0);
    порядок.sort(function (a, b) {
      var ф = function (i) {
        var q = п_[i]["угол"];
        return Math.abs(Math.atan2(q[1][1] - q[0][1], q[1][0] - q[0][0])) > 0.17 ? 1 : 0;
      };
      var d = ф(a) - ф(b);
      return d !== 0 ? d : a - b;
    });
    for (var sп = 0; sп < порядок.length; sп++) {
      var s = порядок[sп];
      /* Ужимали место на десятую часть, и свет уходил вглубь ниши: в
         кадре получалась ВТОРАЯ скруглённая рамка меньшего размера с
         неравными полями, а глаз читает такую как наклейку внутри
         ниши. Углы, снятые cabniche, это и есть дно ниши, поджимать
         его почти не надо - только на толщину самой световой нити. */
      var кв = места(ужать(п_[s]["угол"], 0.03), п_[s]["мест"], п_[s]["зазор"]);
      var спис = п_[s]["ключи"];
      for (var j = 0; j < кв.length; j++, n++) {
        /* Какая команда где: полоса вправе назвать свои клавиши. На
           телефоне мест мало, и там нужны не первые попавшиеся, а те
           четыре, без которых в полёте не обойтись. */
        /* Ниш на плите может быть БОЛЬШЕ, чем команд. Здесь стоял
           перебор по кругу (n % K.length), и лишняя ниша получала
           первую команду второй раз: на широкой плите двенадцать ниш
           против одиннадцати команд, и «КУРС» рисовался дважды. Второй
           был полноценным лицом с иконкой и подписью, а кнопки за ним
           не было вовсе - замер показал нишу в точке (1343; 828)
           размером 64x38 без единого узла разметки. Человек видит
           клавишу, жмёт, ничего не происходит.

           Круга больше нет: команды кончились - ниша остаётся пустой.
           Пустая ниша это часть плиты, фантомная клавиша - поломка. */
        var k = K[спис ? спис[j] : n];
        if (!k) {
          /* Команды кончились, а гнездо на плите есть. Пустое место
             мы уже не подписываем чужой командой (фантомную клавишу
             убрали), но и оставлять его чёрным нельзя: на кадре
             широкой плиты два гнезда правого крыла читались как
             «часть кнопок погасла». В железе такое гнездо закрывают
             глухой заглушкой, вот её и рисуем: тихий свет по кромке
             и ровное дно, без значка и без слова. Плита выглядит
             целой, а нажимать там нечего - зону нажатия сюда не
             кладём. */
          var qп = угол(п, кв[j]);
          var шп = Math.hypot(qп[1].x - qп[0].x, qп[1].y - qп[0].y);
          var вп2 = Math.hypot(qп[3].x - qп[0].x, qп[3].y - qп[0].y);
          if (шп > 2 && вп2 > 2) {
            var бп = буфер(шп * 1.6, вп2 * 1.6);
            бк.save();
            стекло(бк, бп.w, бп.h, 0.30);
            рамка(бк, бп.w, бп.h, бп.h * 0.22, 0.14);
            бк.restore();
            сияние(бп.w, бп.h, бп.h * 0.06);
            влить(c, буф, qп, бп.w, бп.h);
          }
          continue;
        }
        var qq = угол(п, кв[j]);
        зоны.push(qq);
        if (сила[n] == null) сила[n] = 0;
        сила[n] *= Math.max(0, 1 - dt * 3.4);
        var шш = Math.hypot(qq[1].x - qq[0].x, qq[1].y - qq[0].y);
        var вв = Math.hypot(qq[3].x - qq[0].x, qq[3].y - qq[0].y);
        var б2 = буфер(шш * 1.6, вв * 1.6);
        бк.save(); клавиша(бк, б2.w, б2.h, k, сила[n], ru, самоеТесное, 1.6 * DPR); бк.restore();
        сияние(б2.w, б2.h, б2.h * 0.06);
        влить(c, буф, qq, б2.w, б2.h);
      }
    }
    /* Отражение кладём последним: оно снимает уже нарисованный свет
       приборов, значит рисовать его раньше нечего. */
    if (meta["контур"]) отражение(c, cv, зерк, meta, п, meta["контур"]);
    c.globalCompositeOperation = "source-over";
  }

  return {
    canvas: cv,
    вид: function (m, d, язык) { meta = m; разметка = d; ru = язык !== false; },
    размер: размер,
    кадр: кадр,
    данные: function (o) { for (var k in o) if (o.hasOwnProperty(k)) сост[k] = o[k]; },
    нажать: function (i) { сила[i] = 1; },
    место: function (i) { return зоны[i] || null; },
    попал: function (x, y) {
      for (var i = 0; i < зоны.length; i++) if (внутри(зоны[i], x, y)) return i;
      return -1;
    },
    мест: function () { return зоны.length; }
  };
}

g.RC_DECK = { создать: создать, покрытие: покрытие, какой: какой };
