<?php
/* Rocket CDN -> Rocket VPN: передача человека через космос.

   ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПРОСТО ССЫЛКА. Сайт VPN закрыт и пускает
   только по подписанному ключу. Подписать ключ можно лишь тем секретом,
   которым он проверяется, а секрет нельзя отдавать в браузер: ключ,
   собранный на стороне человека, сможет собрать кто угодно. Поэтому
   ссылка ведёт сюда, ключ подписывается ЗДЕСЬ, на сервере, и человек
   уходит уже с готовым ключом в адресе.

   Секрет общий у двух сайтов и живёт в окружении каждого из них. В
   репозиторий он не попадает никогда. Нет секрета - никуда не ведём и
   говорим об этом прямо, а не отправляем человека в закрытый створ: там
   он увидит «створ закрыт» и решит, что сломался переход. */

$СЕКРЕТ = getenv('RV_SITE_SECRET');

/* Куда ведём. Домен rocketvpn.top живёт на сервере клиента, доступа к
   нему у нас пока нет, и до переезда сайт VPN стоит стендом на этом же
   сервере под тем же створом. Адрес берём из окружения: переезд станет
   правкой одной переменной в конфигурации, а не выкладкой кода. */
$САЙТ = getenv('RV_SITE_URL');
if (!$САЙТ) $САЙТ = '/vpn/';

if (!$СЕКРЕТ) {
  /* Тихо и честно. 503, а не 500: это не поломка кода, а отсутствие
     настройки, и она поправима без выкладки. */
  http_response_code(503);
  header('Content-Type: text/plain; charset=utf-8');
  echo "Переход временно недоступен.";
  exit;
}

$метка = time();
$подпись = substr(hash_hmac('sha256', 'rv|' . $метка, $СЕКРЕТ), 0, 24);

/* Признак from=cdn нужен не для доступа, а для сценария: сайт VPN по
   нему понимает, что человек пришёл через прокол, и встречает его сразу
   в акте выхода, а не отматывает к первому экрану. */
$адрес = $САЙТ . (strpos($САЙТ, '?') === false ? '?' : '&') . 'k=' . rawurlencode($метка . '.' . $подпись) . '&from=cdn';

/* 302, а не 301: ключ живёт неделю, и постоянное перенаправление
   осталось бы в памяти браузера вместе с протухшим ключом. */
header('Cache-Control: no-store');
header('Referrer-Policy: no-referrer');
header('Location: ' . $адрес, true, 302);
