def записать(папки):
    # Векторные лежат в .tgs, снятое и новое кодовое - в .webm. Telegram
    # держит в одном наборе оба формата, проверено живьём на боевом боте.
    свод = [{"key": k, "file": k + (".tgs" if k.endswith("_v") else ".webm"),
             "emoji": э, "title": т} for k, э, т in ПАК]
    for п in папки:
        нет = [x["key"] for x in свод
               if not os.path.exists(os.path.join(п, x["file"]))]
        if нет:
            print("%s: нет файлов - %s" % (п, ", ".join(нет)))
        with open(os.path.join(п, "manifest.json"), "w", encoding="utf-8") as f:
            json.dump(свод, f, ensure_ascii=False, indent=1)
        print("%s: %d единиц" % (п, len(свод)))


