# -*- coding: utf-8 -*-
"""Молния: разряд рисуется кодом, и каждый кадр свой.

Снимок молнии это застывшая молния. Её узнают не по форме, а по тому,
что она живая: канал дрожит, ветки вспыхивают и гаснут, свет заливает
кадр и уходит. Нарисованная кодом, она это умеет, а фотография - нет.

Канал строится смещением середины: отрезок делится пополам, середина
уводится вбок, и так пока ломаная не станет похожа на разряд. Приём
старый и работает именно потому, что даёт излом на каждом масштабе -
ровно так ветвится настоящий пробой.
"""

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

import foto_sticker as F

ПОЛЕ = F.SIZE
КАДРОВ = F.FRAMES

ЯДРО = (245, 252, 255)
СРЕДНЕЕ = (120, 216, 250)      # CYAN_LIT
ОРЕОЛ = (66, 178, 220)         # CYAN
ДАЛЬ = (91, 50, 201)           # VIOLET_DEEP


def канал(a, b, разброс, шаг=6, rs=None):
    """Ломаная от a к b: середину уводим вбок, потом каждую половину."""
    rs = rs or np.random.RandomState(0)
    точки = [np.array(a, dtype=np.float64), np.array(b, dtype=np.float64)]
    for _ in range(шаг):
        новые = [точки[0]]
        for i in range(len(точки) - 1):
            p, q = точки[i], точки[i + 1]
            m = (p + q) / 2.0
            d = q - p
            n = np.array([-d[1], d[0]])
            дл = np.hypot(*n)
            if дл > 1e-6:
                m = m + n / дл * rs.normal(0, разброс)
            новые += [m, q]
        точки = новые
        разброс *= 0.52
    return [(float(p[0]), float(p[1])) for p in точки]


def разряд(rs, ветки=4):
    """Главный канал сверху вниз плюс короткие ветки в стороны."""
    верх = (ПОЛЕ * (0.44 + rs.uniform(-0.05, 0.05)), ПОЛЕ * 0.08)
    низ = (ПОЛЕ * (0.56 + rs.uniform(-0.05, 0.05)), ПОЛЕ * 0.94)
    главный = канал(верх, низ, ПОЛЕ * 0.085, 6, rs)
    пути = [(главный, 1.0)]
    for _ in range(ветки):
        i = rs.randint(len(главный) // 5, len(главный) - len(главный) // 5)
        нач = главный[i]
        дл = ПОЛЕ * rs.uniform(0.12, 0.26)
        угол = rs.uniform(-1.1, 1.1) + (np.pi / 2)
        сторона = 1 if rs.rand() > 0.5 else -1
        кон = (нач[0] + сторона * дл * np.cos(угол - np.pi / 2) * 1.8,
               нач[1] + дл * np.sin(угол))
        пути.append((канал(нач, кон, ПОЛЕ * 0.03, 4, rs), rs.uniform(0.6, 0.85)))
    return пути


def нарисовать(пути, сила):
    """Слои свечения: далёкий ореол, средний, раскалённое ядро.

    Один проход дал бы синюю верёвку. Свет так не работает: у разряда
    широкий слабый ореол, средний слой и узкое белое ядро, и читается
    он именно этой лесенкой.
    """
    # Толщины подняты после первой пробы: на листе в пятьсот точек разряд
    # читался, а в размере эмодзи - сто точек - превращался в волосок.
    # Стикер смотрят мелким, и толщину надо брать от мелкого.
    слои = [(ДАЛЬ, 0.135, 30, 0.42), (ОРЕОЛ, 0.070, 15, 0.75),
            (СРЕДНЕЕ, 0.042, 6, 1.0), (ЯДРО, 0.022, 1, 1.0)]
    итог = Image.new("RGBA", (ПОЛЕ, ПОЛЕ), (0, 0, 0, 0))
    for цвет, толщ, размыв, вес in слои:
        сл = Image.new("RGBA", (ПОЛЕ, ПОЛЕ), (0, 0, 0, 0))
        d = ImageDraw.Draw(сл)
        for путь, я in пути:
            w = max(2, int(ПОЛЕ * толщ * (0.62 + 0.38 * я)))
            a = int(255 * вес * я * сила)
            d.line(путь, fill=цвет + (a,), width=w, joint="curve")
        if размыв:
            сл = сл.filter(ImageFilter.GaussianBlur(размыв))
        итог = Image.alpha_composite(итог, сл)
    return итог


def собрать():
    rs = np.random.RandomState(12)
    # два удара за три секунды: один читается как случайность, три
    # превращают стикер в мигалку
    удары = [(4, 26), (46, 72)]
    формы = {}
    кадры = []
    for i in range(КАДРОВ):
        сила, ключ = 0.0, None
        for н, (a, b) in enumerate(удары):
            if a <= i <= b:
                ключ = н
                t = (i - a) / float(b - a)
                # вспышка резкая, угасание долгое: так ведёт себя разряд
                сила = (t / 0.12) if t < 0.12 else (1.0 - (t - 0.12) / 0.88) ** 1.8
        if ключ is None:
            кадры.append(Image.new("RGBA", (ПОЛЕ, ПОЛЕ), (0, 0, 0, 0)))
            continue
        # форма перерисовывается каждые три кадра: канал живой, но не
        # трясётся с частотой съёмки, иначе выходит рябь
        кл = (ключ, i // 3)
        if кл not in формы:
            формы[кл] = разряд(np.random.RandomState(rs.randint(1 << 30)))
        кадры.append(нарисовать(формы[кл], max(0.0, min(1.0, сила))))
    return кадры


def main():
    import os
    дом = "/opt/oko-poster/rocketpack"
    ks = собрать()
    for папка, предел, сторона in ((os.path.join(дом, "out"), F.LIMIT, None),
                                   (os.path.join(дом, "out_emo"),
                                    F.LIMIT_EMO, F.SIDE_EMO)):
        os.makedirs(папка, exist_ok=True)
        br, n = F.собрать(ks, os.path.join(папка, "bolt.webm"), предел, сторона)
        print("молния -> %s: %d кб (%s)" % (папка, n // 1024, br))


if __name__ == "__main__":
    main()
