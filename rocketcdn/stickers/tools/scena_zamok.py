# -*- coding: utf-8 -*-
"""Замок и ключ одним стикером: ключ приезжает, входит, поворачивается,
дужка откидывается.

Растворение между «закрыт» и «открыт» показывает результат и прячет
причину. Владелец просил показать причину: ключ вставили - открылся.
Значит части снимка должны двигаться по-настоящему, каждая своим ходом
и в своё время.

Снимок разбирается по собственной геометрии (`mehanika`), ничего не
дорисовывается: корпус остаётся корпусом, дужка дужкой, ключ ключом.
"""

import os

import numpy as np
from PIL import Image

import foto_sticker as F
import mehanika as M

КАДРОВ = F.FRAMES
ПОЛЕ = F.SIZE


def _плавно(t):
    """Мягкий вход и выход: механизм не дёргается на старте."""
    t = min(max(t, 0.0), 1.0)
    return t * t * (3 - 2 * t)


def _отрезок(i, a, b):
    """Доля прохождения кадра i по отрезку [a, b] кадров."""
    if i <= a:
        return 0.0
    if i >= b:
        return 1.0
    return _плавно((i - a) / float(b - a))


def собрать(дом, ключ_имя="lock", масштаб=0.94):
    корпус_ф = os.path.join(дом, "lock_a.png")
    ключ_ф = os.path.join(дом, "key.png")

    замок = F.снять_с_чёрного(корпус_ф, сквозная=True)
    корпус, дужка, рубеж = M.части_замка(замок)
    ось = M.опора_дужки(дужка, рубеж)
    скв, скв_р = M.скважина(корпус)

    # Срез дужки: там, где её отделили от корпуса, остаётся плоский
    # яркий край. Пока дужка закрыта, он спрятан в плечах корпуса, а на
    # открытом замке выезжает наружу белой заплатой. У настоящей дужки
    # это торец, и он в тени - притемняем нижние строки слоя.
    низ = дужка[..., 3].nonzero()[0]
    if len(низ):
        край = int(низ.max())
        толщ = max(3, int((край - int(низ.min())) * 0.045))
        полоса = дужка[край - толщ:край + 1]
        полоса[..., :3] = (полоса[..., :3].astype(np.float32) * 0.42
                           ).astype(np.uint8)

    ключ = F.снять_с_чёрного(ключ_ф, сквозная=True)
    угол, _ = M.ось_предмета(ключ)

    # Ключ снят по диагонали, а входит он горизонтально. Поворачиваем его
    # к горизонтали ОДИН раз, до анимации: крутить на каждом кадре значит
    # тридцать раз пересемплировать одну и ту же картинку и растерять
    # резкость на бородке, по которой ключ и узнаётся.
    ki = Image.fromarray(ключ, "RGBA").rotate(угол, Image.BICUBIC, expand=True)
    ключ_р = np.asarray(ki)
    ключ_р, _ = M.обрезать(ключ_р)
    # бородка должна смотреть ВЛЕВО: она входит в скважину первой, а
    # тяжёлая головка остаётся снаружи справа
    ka = ключ_р[..., 3] > 40
    масса_слева = ka[:, :ka.shape[1] // 2].sum()
    if масса_слева > ka[:, ka.shape[1] // 2:].sum():
        ключ_р = ключ_р[:, ::-1].copy()

    # общий масштаб: замок занимает свою долю кадра, ключ подгоняется под
    # скважину, а не под себя
    зам_об, сдвиг = M.обрезать(замок)
    # Черновой масштаб: точный даст вписывание по общей рамке в конце.
    k = (ПОЛЕ * 0.62) / float(max(зам_об.shape[:2]))
    сx = ПОЛЕ / 2.0 - (сдвиг[0] + зам_об.shape[1] / 2.0) * k
    сy = ПОЛЕ / 2.0 - (сдвиг[1] + зам_об.shape[0] / 2.0) * k

    def на_листе(x, y):
        return (сx + x * k, сy + y * k)

    # Ключ подгоняется ПОД СКВАЖИНУ, а не под себя: бородка должна войти
    # в отверстие, а не лечь рядом. Высота ключа берётся с запасом к
    # размеру скважины - у настоящего ключа бородка чуть уже отверстия.
    kk = (скв_р * 2.2 * k) / float(ключ_р.shape[0])

    скв_л = на_листе(*скв)
    ось_л = на_листе(*ось)

    кадры = []
    for i in range(КАДРОВ):
        лист = Image.new("RGBA", (ПОЛЕ, ПОЛЕ), (0, 0, 0, 0))

        подъезд = _отрезок(i, 6, 34)      # ключ подъезжает справа
        поворот = _отрезок(i, 36, 52)     # поворот ключа в скважине
        откид = _отрезок(i, 50, 74)       # дужка идёт вверх
        свет = _отрезок(i, 40, 60)        # вставка разгорается

        тело = M.подсветить(корпус, свет * 0.9)
        д = M.подсветить(дужка, свет * 0.5)

        # дужка уходит назад: она за корпусом, а не поверх него
        # Дужка откидывается ПРОТИВ часовой вокруг левой ноги: правая
        # нога выходит из плеча и идёт вверх. По часовой она уехала бы
        # вниз, сквозь корпус, и замок «закрылся бы ещё сильнее».
        M.положить(лист, д, ось_л,
                   угол=31.0 * откид,
                   вокруг=(ось[0], ось[1]), масштаб=k)
        M.положить(лист, тело, на_листе(0, 0), вокруг=(0, 0), масштаб=k)

        # ключ: входит по горизонтали, потом поворачивается вокруг бородки
        дальше = ПОЛЕ * 0.62
        x = скв_л[0] + дальше * (1.0 - подъезд)
        M.положить(лист, ключ_р, (x, скв_л[1]),
                   угол=-90.0 * поворот,
                   вокруг=(4, ключ_р.shape[0] / 2.0), масштаб=kk)

        кадры.append(лист)
    # Габарит за три секунды меняется: открытый замок шире закрытого.
    # Поэтому вписываем всю последовательность разом, по общей рамке.
    return F.вписать_кадры(кадры, запас=масштаб,
                           по=list(range(34, КАДРОВ)))


def main():
    дом = "/opt/oko-poster/rocketpack"
    кадры = собрать(дом)
    вых = os.path.join(дом, "out")
    эмо = os.path.join(дом, "out_emo")
    os.makedirs(вых, exist_ok=True)
    os.makedirs(эмо, exist_ok=True)
    br, n = F.собрать(кадры, os.path.join(вых, "lock.webm"))
    _, m = F.собрать(кадры, os.path.join(эмо, "lock.webm"), F.LIMIT_EMO,
                     F.SIDE_EMO)
    print("замок: стикер %d кб (%s), эмодзи %d кб" % (n // 1024, br, m // 1024))


if __name__ == "__main__":
    main()
