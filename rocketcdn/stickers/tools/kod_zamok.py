# -*- coding: utf-8 -*-
"""Замок и ключ, нарисованные целиком кодом.

Ни снимка, ни видео: корпус, дужка и ключ заданы формулами, объём даёт
свет на поверхности (`obyom`). Поэтому геометрия ровная по построению -
скругления одинаковые, дужка круглая, скважина по центру, - а движение
можно задать любое, потому что двигаются не пиксели, а параметры.

Ход: замок закрыт, ключ подъезжает справа, входит в скважину,
поворачивается, дужка откидывается, фирменная вставка разгорается.
"""

import numpy as np

import obyom as O

# Бренд Rocket это чёрный с цианом, поэтому корпус тёмный, а не серый:
# светлый замок на светлом фоне чата теряется, а тёмный держит силуэт.
ХРОМ = (0.88, 0.92, 0.97)
КОРПУС = (0.075, 0.095, 0.125)
ЛАТУНЬ = (0.92, 0.74, 0.34)


def _локал(x, y, центр, угол):
    """Координаты в системе повёрнутой детали.

    Чтобы нарисовать деталь повёрнутой, поворачивают не её, а систему
    отсчёта - в обратную сторону. Так форма остаётся формулой и не
    теряет резкость на пересчёте растра.
    """
    c, s = np.cos(-угол), np.sin(-угол)
    dx, dy = x - центр[0], y - центр[1]
    return dx * c - dy * s, dx * s + dy * c


def _корпус(x, y):
    return O.короб(x, y, 0.335, 0.270, скруг=0.068, c=(0.0, 0.45))


def _скважина(x, y):
    return O.объединить(O.круг(x, y, 0.052, c=(0.0, 0.40)),
                        O.короб(x, y, 0.022, 0.068, скруг=0.010,
                                c=(0.0, 0.495)))


def _дужка(x, y, угол):
    """Дуга с двумя ногами. Откидывается вокруг низа левой ноги.

    Размер выбран по настоящему замку: над корпусом дужка поднимается
    примерно на половину его высоты. В первой пробе она была вдвое ниже,
    и замок читался сумочкой, а не замком.
    """
    ось = (-0.240, 0.18)
    lx, ly = _локал(x, y, ось, угол)
    x2, y2 = lx + ось[0], ly + ось[1]
    r, т = 0.240, 0.050
    return O.объединить(
        O.дуга(x2, y2, r, т, np.pi, 2 * np.pi, c=(0.0, 0.18)),
        O.капсула(x2, y2, (-r, 0.18), (-r, 0.36), т),
        O.капсула(x2, y2, (r, 0.18), (r, 0.36), т))


def _ключ(x, y, центр, угол, k=1.0):
    """Стержень, бородка с зубьями и круглая головка."""
    lx, ly = _локал(x, y, центр, угол)
    lx, ly = lx / k, ly / k
    стержень = O.капсула(lx, ly, (-0.26, 0.0), (0.14, 0.0), 0.028)
    головка = O.кольцо(lx, ly, 0.082, 0.030, c=(0.225, 0.0))
    шейка = O.капсула(lx, ly, (0.12, 0.0), (0.16, 0.0), 0.040)
    зубья = O.объединить(
        O.короб(lx, ly, 0.016, 0.036, скруг=0.005, c=(-0.245, 0.052)),
        O.короб(lx, ly, 0.016, 0.052, скруг=0.005, c=(-0.185, 0.060)),
        O.короб(lx, ly, 0.016, 0.030, скруг=0.005, c=(-0.125, 0.046)))
    return O.объединить(стержень, головка, шейка, зубья) * k


def _полоса_блика(x, y, сдвиг=0.0):
    """Косая полоса отражения студии на лицевой стороне.

    Полированный металл отражает источник полосой, а не ровным тоном.
    Без неё лицо корпуса выходит матовой заглушкой, сколько ни правь свет.
    """
    d = (x * 0.80 + (y - 0.45) * 0.60) - сдвиг
    return np.exp(-(d * d) / (2 * 0.11 ** 2))


def кадр(размер, шаг_ключа, поворот_ключа, откид, свет):
    x, y = O.лист(размер)

    д = _дужка(x, y, откид)
    тело = _корпус(x, y)
    скв = _скважина(x, y)
    вставка = O.пересечь(O.короб(x, y, 0.275, 0.013, скруг=0.007,
                                 c=(0.0, 0.30)), тело)
    тело_со_скв = O.вычесть(тело, скв)

    kx = 0.0 + 1.85 * (1.0 - шаг_ключа)
    ключ = _ключ(x, y, (kx, 0.40), поворот_ключа, k=0.62)

    слои = [O.тень(O.объединить(тело, д), сила=0.30, размыв=0.020,
                   сдвиг=(0.0, 0.022))]

    # дужка за корпусом: она уходит в его плечи, а не лежит поверх
    слои.append(O.материал(O.высота(д, фаска=0.024, выпукл=0.18), д, ХРОМ,
                           металл=1.0, шерох=0.12, отраж=1.0, ободок=0.30))

    # чернота скважины кладётся ПОД корпус: тогда у отверстия появляется
    # глубина, а не вмятина. Вмятину даёт одна фаска без темноты внутри.
    дыра = np.zeros(x.shape + (4,), np.uint8)
    дыра[..., :3] = np.array(O.INK, np.uint8)
    дыра[..., 3] = (np.clip(-скв * 300, 0, 1) * 255).astype(np.uint8)
    слои.append(дыра)

    корп = O.материал(O.высота(тело_со_скв, фаска=0.030, выпукл=0.10),
                      тело_со_скв, КОРПУС, металл=1.0, шерох=0.10,
                      отраж=0.88, ободок=0.42)
    пол = _полоса_блика(x, y, -0.16) * (тело_со_скв < 0)
    корп[..., :3] = np.clip(корп[..., :3].astype(np.float32)
                            + пол[..., None] * 78, 0, 255).astype(np.uint8)
    слои.append(корп)

    м = (вставка < 0).astype(np.float32)
    if свет > 0.01:
        слои.append(O.свечение(м, O.CYAN_LIT, 0.042, свет * 1.15))
    пол2 = np.zeros(вставка.shape + (4,), np.uint8)
    яр = 0.45 + 0.55 * свет
    пол2[..., :3] = np.array([int(c * яр) for c in O.CYAN_LIT], np.uint8)
    пол2[..., 3] = (np.clip(-вставка * 300, 0, 1) * 255).astype(np.uint8)
    слои.append(пол2)

    слои.append(O.материал(O.высота(ключ, фаска=0.016, выпукл=0.25), ключ,
                           ЛАТУНЬ, металл=1.0, шерох=0.14, отраж=0.95,
                           ободок=0.30, ободок_цвет=O.CYAN_LIT))
    return O.слить(*слои)


def _плавно(t):
    t = min(max(t, 0.0), 1.0)
    return t * t * (3 - 2 * t)


def _отрезок(i, a, b):
    return 0.0 if i <= a else (1.0 if i >= b else _плавно((i - a) / float(b - a)))


def собрать(размер=512, кадров=90):
    out = []
    for i in range(кадров):
        out.append(кадр(размер,
                        _отрезок(i, 8, 34),
                        -np.pi / 2 * _отрезок(i, 37, 53),
                        np.radians(46.0) * _отрезок(i, 52, 76),
                        _отрезок(i, 40, 62)))
    return out


def выпустить(дом="/opt/oko-poster/rocketpack", ключ="lock"):
    import os
    import foto_sticker as F
    ks = собрать(F.SIZE, F.FRAMES)
    for папка, предел, сторона in ((os.path.join(дом, "out"), F.LIMIT, None),
                                   (os.path.join(дом, "out_emo"),
                                    F.LIMIT_EMO, F.SIDE_EMO)):
        os.makedirs(папка, exist_ok=True)
        br, n = F.собрать(ks, os.path.join(папка, ключ + ".webm"), предел,
                          сторона)
        print("%-8s -> %-28s %3d кб (%s)"
              % (ключ, os.path.basename(папка), n // 1024, br))


if __name__ == "__main__":
    import sys
    if "--выпустить" in sys.argv:
        выпустить()
        raise SystemExit(0)
    from PIL import Image
    ks = собрать(int(sys.argv[1]) if len(sys.argv) > 1 else 512)
    K = 200
    идx = [0, 20, 34, 45, 58, 72, 88]
    л = Image.new("RGB", (K * len(идx), K), (245, 245, 245))
    px = л.load()
    for yy in range(K):
        for xx in range(л.width):
            if ((xx // 10) + (yy // 10)) % 2:
                px[xx, yy] = (222, 222, 222)
    for i, n in enumerate(идx):
        e = ks[n].resize((K, K), Image.LANCZOS)
        л.paste(e, (K * i, 0), e)
    л.save("/opt/oko-poster/rocketpack/kz.png")
    print("кадров", len(ks))
