# -*- coding: utf-8 -*-
"""Движок объёма: предмет рисуется кодом и выходит объёмным.

Плоская заливка формы даёт наклейку, а владелец просит объём. Объём в
рисунке делает не форма, а СВЕТ на ней, значит нужна поверхность, а не
силуэт. Порядок такой:

    форма -> расстояние до края -> высота -> нормали -> свет -> цвет

Форма задаётся расстоянием: для каждой точки листа известно, насколько
она внутри фигуры. Из расстояния строится высота - фигура как бы
надувается к середине и заваливается к краю фаской. По высоте считаются
нормали, а дальше это обычная закраска: рассеянный свет, блик, отражение
студии и ободок по краю.

Считается всё сразу по всему листу массивами, поэтому кадр рисуется за
сотые доли секунды, а геометрия выходит идеально ровной: её задаёт
формула, а не рука.
"""

import numpy as np
from PIL import Image
from scipy import ndimage

# Палитра бренда Rocket, снята с их сайта
CYAN = (0x42, 0xB2, 0xDC)
CYAN_LIT = (0x7F, 0xD8, 0xFA)
CYAN_DEEP = (0x0A, 0x58, 0x97)
VIOLET = (0x8A, 0x59, 0xF6)
VIOLET_DEEP = (0x5B, 0x32, 0xC9)
INK = (0x05, 0x0C, 0x15)
БЕЛЫЙ = (0xF2, 0xF7, 0xFC)


def лист(размер):
    """Сетка листа в долях: центр в нуле, край в единице."""
    y, x = np.mgrid[0:размер, 0:размер].astype(np.float32)
    c = (размер - 1) / 2.0
    return (x - c) / c, (y - c) / c


# --- формы: возвращают расстояние со знаком, минус внутри --------------

def круг(x, y, r, c=(0.0, 0.0)):
    return np.hypot(x - c[0], y - c[1]) - r


def кольцо(x, y, r, толщ, c=(0.0, 0.0)):
    return np.abs(np.hypot(x - c[0], y - c[1]) - r) - толщ


def короб(x, y, w, h, скруг=0.0, c=(0.0, 0.0)):
    dx = np.abs(x - c[0]) - (w - скруг)
    dy = np.abs(y - c[1]) - (h - скруг)
    вне = np.hypot(np.maximum(dx, 0), np.maximum(dy, 0))
    внутри = np.minimum(np.maximum(dx, dy), 0)
    return вне + внутри - скруг


def капсула(x, y, a, b, r):
    """Отрезок с закруглёнными концами: из него собирается что угодно."""
    ax, ay = a
    bx, by = b
    px, py = x - ax, y - ay
    dx, dy = bx - ax, by - ay
    дл2 = dx * dx + dy * dy + 1e-9
    t = np.clip((px * dx + py * dy) / дл2, 0.0, 1.0)
    return np.hypot(px - t * dx, py - t * dy) - r


def дуга(x, y, r, толщ, начало, конец, c=(0.0, 0.0)):
    """Часть кольца между двумя углами, с закруглёнными концами.

    Дужка замка это именно дуга, а не полукольцо: у неё есть концы, и
    они круглые. Рисовать её отрезками значит получить гранёный обод.
    """
    px, py = x - c[0], y - c[1]
    a = np.arctan2(py, px)
    ш = (конец - начало) / 2.0
    с = (конец + начало) / 2.0
    d = np.abs(((a - с + np.pi) % (2 * np.pi)) - np.pi)
    внутри = d <= ш
    кольц = np.abs(np.hypot(px, py) - r) - толщ
    к1 = (c[0] + r * np.cos(начало), c[1] + r * np.sin(начало))
    к2 = (c[0] + r * np.cos(конец), c[1] + r * np.sin(конец))
    концы = np.minimum(круг(x, y, толщ, к1), круг(x, y, толщ, к2))
    return np.where(внутри, кольц, концы)


def многоугольник(x, y, точки):
    """Расстояние до замкнутого контура, минус внутри.

    Нужен там, где фигуру не собрать из кругов и капсул: у звезды пять
    острых лучей, а объединение пяти капсул даёт снежинку с круглыми
    концами - именно это и вышло на первой пробе.

    Знак берётся по числу пересечений луча с рёбрами: нечётное значит
    внутри. Считается сразу по всему листу, поэтому дёшево.
    """
    т = np.asarray(точки, np.float32)
    d = np.full(x.shape, 1e9, np.float32)
    внутри = np.zeros(x.shape, bool)
    n = len(т)
    for i in range(n):
        ax, ay = т[i]
        bx, by = т[(i + 1) % n]
        ex, ey = bx - ax, by - ay
        wx, wy = x - ax, y - ay
        дл2 = ex * ex + ey * ey + 1e-9
        h = np.clip((wx * ex + wy * ey) / дл2, 0.0, 1.0)
        d = np.minimum(d, np.hypot(wx - ex * h, wy - ey * h))
        пересек = ((y >= ay) != (y >= by)) & (x < ax + ex * (y - ay) / (ey + 1e-9))
        внутри ^= пересек
    return np.where(внутри, -d, d)


def звезда_лучи(x, y, r, лучей=5, впадина=0.46, поворот=-np.pi / 2):
    """Звезда как контур: острые концы, ровные углы."""
    точки = []
    for i in range(лучей * 2):
        a = поворот + np.pi * i / лучей
        рад = r if i % 2 == 0 else r * впадина
        точки.append((рад * np.cos(a), рад * np.sin(a)))
    return многоугольник(x, y, точки)


def объединить(*ф):
    out = ф[0]
    for f in ф[1:]:
        out = np.minimum(out, f)
    return out


def вычесть(a, b):
    return np.maximum(a, -b)


def пересечь(a, b):
    return np.maximum(a, b)


# --- поверхность -------------------------------------------------------

def высота(sdf, фаска=0.035, выпукл=0.55):
    """Из расстояния - высоту.

    У края высота падает по дуге (фаска), к середине выходит на полку и
    чуть выпукла. Ровно эта дуга у края и делает предмет объёмным: на
    ней ломается свет, и глаз читает толщину.
    """
    d = np.clip(-sdf, 0.0, None)
    t = np.clip(d / фаска, 0.0, 1.0)
    борт = np.sqrt(1.0 - (1.0 - t) ** 2)         # четверть окружности
    полка = 1.0 + выпукл * np.clip(d - фаска, 0, None) / max(фаска, 1e-6) * 0.25
    return борт * np.minimum(полка, 1.0 + выпукл * 0.35)


def нормали(h, сила=1.0, размыв=1.0):
    """Нормали по высоте. Лёгкое размытие убирает ступеньку растра."""
    hh = ndimage.gaussian_filter(h.astype(np.float32), размыв)
    gy, gx = np.gradient(hh)
    nx, ny = -gx * сила * 40.0, -gy * сила * 40.0
    nz = np.ones_like(nx)
    дл = np.sqrt(nx * nx + ny * ny + nz * nz)
    return nx / дл, ny / дл, nz / дл


def среда(nx, ny, nz, верх=(0.82, 0.88, 0.96), низ=(0.05, 0.07, 0.11)):
    """Отражение студии: сверху светлый купол, снизу тёмный пол.

    Металл без отражения выглядит пластиком. Полноценной сцены тут нет,
    и она не нужна: хватает того, что верх светлый, а низ тёмный - глаз
    достраивает остальное сам.
    """
    t = np.clip(0.5 - ny * 0.5 + nz * 0.12, 0, 1)[..., None]
    в = np.array(верх, np.float32)
    н = np.array(низ, np.float32)
    return н + (в - н) * t


def материал(h, sdf, цвет=(0.8, 0.85, 0.9), металл=1.0, шерох=0.25,
             отраж=0.9, свет=(-0.45, -0.62), ободок=0.55,
             ободок_цвет=CYAN, сила_нормали=1.0):
    """Закрасить поверхность: рассеянный свет, блик, среда, ободок."""
    nx, ny, nz = нормали(h, сила_нормали)
    lx, ly = свет
    lz = np.sqrt(max(1.0 - lx * lx - ly * ly, 0.05))
    лам = np.clip(nx * lx + ny * ly + nz * lz, 0, 1)

    баз = np.array(цвет, np.float32)
    if max(баз) > 1.5:
        баз = баз / 255.0

    рассеян = баз * (0.22 + 0.78 * лам)[..., None]
    зерк = среда(nx, ny, nz) * отраж
    # Тёмный полированный металл всё равно ЗЕРКАЛИТ. Если домножить
    # отражение на его тёмный цвет, зеркало гаснет и выходит крашеный
    # пластик - ровно это и получилось на первой пробе: весь замок стал
    # одинаково бледным. Цвет металла подкрашивает отражение, а не душит.
    тон = 0.35 + 0.65 * баз
    цв = рассеян * (1.0 - металл * 0.72) + зерк * тон * металл

    # блик по Блинну: половинный вектор между светом и взглядом
    hx, hy, hz = lx, ly, lz + 1.0
    дл = np.sqrt(hx * hx + hy * hy + hz * hz)
    спек = np.clip(nx * hx / дл + ny * hy / дл + nz * hz / дл, 0, 1)
    острота = 2.0 / max(шерох, 0.02) ** 2
    цв = цв + np.power(спек, острота)[..., None] * (1.0 - шерох) * 1.25

    # ободок: подсветка по самому краю силуэта
    if ободок:
        край = np.clip(1.0 - nz, 0, 1) ** 2.0
        оц = np.array(ободок_цвет, np.float32) / 255.0
        цв = цв + край[..., None] * оц * ободок

    цв = np.clip(цв, 0, 1)
    a = np.clip(-sdf * 260.0, 0, 1)          # мягкий край силуэта
    out = np.zeros(h.shape + (4,), np.uint8)
    out[..., :3] = (цв * 255).astype(np.uint8)
    out[..., 3] = (a * 255).astype(np.uint8)
    return out


def тень(sdf, размыв=0.025, сдвиг=(0.0, 0.03), сила=0.45, размер=None):
    """Мягкая тень под предметом: отрывает его от фона."""
    n = sdf.shape[0]
    м = (sdf < 0).astype(np.float32)
    м = ndimage.shift(м, (сдвиг[1] * n, сдвиг[0] * n), order=1)
    м = ndimage.gaussian_filter(м, размыв * n)
    out = np.zeros(sdf.shape + (4,), np.uint8)
    out[..., 3] = (np.clip(м, 0, 1) * 255 * сила).astype(np.uint8)
    return out


def слить(*слои):
    """Сложить слои в порядке от дальнего к ближнему."""
    итог = Image.fromarray(слои[0], "RGBA")
    for с in слои[1:]:
        итог = Image.alpha_composite(итог, Image.fromarray(с, "RGBA"))
    return итог


def свечение(маска, цвет=CYAN_LIT, радиус=0.05, сила=1.0):
    """Свет вокруг светящейся детали."""
    n = маска.shape[0]
    м = ndimage.gaussian_filter(маска.astype(np.float32), радиус * n)
    м = np.clip(м * сила, 0, 1)
    out = np.zeros(маска.shape + (4,), np.uint8)
    out[..., :3] = np.array(цвет, np.uint8)
    out[..., 3] = (м * 255).astype(np.uint8)
    return out
