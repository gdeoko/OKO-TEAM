"""Новые эмодзи Rocket, нарисованные кодом.

Каждый предмет задан формулой, объём даёт свет на поверхности
(`obyom`), движение - изменение параметров от кадра к кадру. Отсюда и
ровность: скругления считает формула, а не рука, и одинаковых деталей
не бывает «почти одинаковых».

Палитра фирменная: тёмный корпус, циан как свет, фиолетовый как второй
акцент. Чёрного фона нет вовсе - всё уходит в прозрачность.
"""

import numpy as np
from PIL import Image

import obyom as O

ТЕМНО = (0.075, 0.095, 0.125)
ХРОМ = (0.88, 0.92, 0.97)
ЦИАН = tuple(c / 255.0 for c in O.CYAN)
ЦИАН_СВ = tuple(c / 255.0 for c in O.CYAN_LIT)
ФИОЛ = tuple(c / 255.0 for c in O.VIOLET)


def _плавно(t):
    t = min(max(t, 0.0), 1.0)
    return t * t * (3 - 2 * t)


def _пила(t):
    """Туда и обратно за оборот: движение без рывка на склейке."""
    return 1.0 - abs(2.0 * (t % 1.0) - 1.0)


def _светяшка(форма, цвет, яркость=1.0, радиус=0.05):
    """Светящаяся деталь плюс её ореол."""
    м = (форма < 0).astype(np.float32)
    гало = O.свечение(м, tuple(int(c * 255) for c in цвет), радиус, яркость)
    тело = np.zeros(форма.shape + (4,), np.uint8)
    тело[..., :3] = np.array([int(min(1.0, c * (0.55 + 0.45 * яркость)) * 255)
                              for c in цвет], np.uint8)
    тело[..., 3] = (np.clip(-форма * 300, 0, 1) * 255).astype(np.uint8)
    return гало, тело


def _корпус(форма, цвет=ТЕМНО, фаска=0.030, ободок=0.42, шерох=0.11):
    return O.материал(O.высота(форма, фаска=фаска, выпукл=0.12), форма, цвет,
                      металл=1.0, шерох=шерох, отраж=0.92, ободок=ободок)


def _поворот(x, y, угол, ц=(0.0, 0.0)):
    c, s = np.cos(-угол), np.sin(-угол)
    dx, dy = x - ц[0], y - ц[1]
    return dx * c - dy * s + ц[0], dx * s + dy * c + ц[1]


