def кнопка(x, y, t):
    """Кнопка питания: обод разгорается, значок вспыхивает."""
    ф = _пила(t * 2.0)
    шайба = O.круг(x, y, 0.72)
    обод = O.кольцо(x, y, 0.60, 0.035)
    палка = O.капсула(x, y, (0.0, -0.42), (0.0, -0.06), 0.055)
    дуг = O.дуга(x, y, 0.30, 0.055, np.radians(-62), np.radians(242))
    знак = O.объединить(палка, дуг)
    слои = [O.тень(шайба, сила=0.32), _корпус(шайба, ТЕМНО, 0.075, 0.40)]
    for ф2, цв, р in ((обод, ЦИАН, 0.055), (знак, ЦИАН_СВ, 0.045)):
        г, т = _светяшка(ф2, цв, 0.40 + 0.60 * ф, р)
        слои += [г, т]
    return O.слить(*слои)


def шестерня(x, y, t):
    """Шестерня крутится ровно: зубья считает формула."""
    угол = t * 2 * np.pi / 8.0
    rx, ry = _поворот(x, y, угол)
    тело = O.круг(rx, ry, 0.52)
    зуб = None
    for i in range(8):
        a = 2 * np.pi * i / 8.0
        c = (0.60 * np.cos(a), 0.60 * np.sin(a))
        k = O.короб(*_поворот(rx, ry, -a, c), 0.13, 0.085, скруг=0.030, c=c)
        зуб = k if зуб is None else O.объединить(зуб, k)
    форма = O.вычесть(O.объединить(тело, зуб), O.круг(rx, ry, 0.20))
    ободок = O.кольцо(rx, ry, 0.335, 0.020)
    г, тт = _светяшка(O.пересечь(ободок, форма), ЦИАН, 0.9, 0.04)
    return O.слить(O.тень(форма, сила=0.30), _корпус(форма), г, тт)


def радар(x, y, t):
    """Луч обходит круг, за ним тает след."""
    шайба = O.круг(x, y, 0.70)
    сетка = None
    for r in (0.22, 0.42, 0.62):
        k = O.кольцо(x, y, r, 0.008)
        сетка = k if сетка is None else O.объединить(сетка, k)
    сетка = O.объединить(сетка, O.капсула(x, y, (-0.68, 0.0), (0.68, 0.0), 0.007),
                         O.капсула(x, y, (0.0, -0.68), (0.0, 0.68), 0.007))
    сетка = O.пересечь(сетка, шайба)

    угол = t * 2 * np.pi
    a = np.arctan2(y, x)
    хвост = (угол - a) % (2 * np.pi)
    веер = np.clip(1.0 - хвост / np.radians(70.0), 0, 1) ** 1.6
    веер = веер * (np.hypot(x, y) < 0.70)
    луч = np.zeros(x.shape + (4,), np.uint8)
    луч[..., :3] = np.array(O.CYAN_LIT, np.uint8)
    луч[..., 3] = (веер * 190).astype(np.uint8)

    метка = O.круг(x, y, 0.045, c=(0.30 * np.cos(1.1), 0.30 * np.sin(1.1)))
    вид = np.clip(1.0 - ((угол - 1.1) % (2 * np.pi)) / np.radians(220.0), 0, 1)
    г, тт = _светяшка(метка, ЦИАН_СВ, вид, 0.05)
    сг, ст = _светяшка(сетка, ЦИАН, 0.45, 0.02)
    return O.слить(O.тень(шайба, сила=0.30), _корпус(шайба, ТЕМНО, 0.070),
                   сг, ст, луч, г, тт)


def эквалайзер(x, y, t):
    """Полосы трафика дышат, каждая своим ритмом."""
    слои = [None]
    формы = None
    свет = []
    for i in range(5):
        фаза = t * 2 * np.pi * (1.0 + 0.22 * i) + i * 1.7
        h = 0.22 + 0.42 * (0.5 + 0.5 * np.sin(фаза))
        cx = -0.52 + i * 0.26
        стол = O.короб(x, y, 0.085, h, скруг=0.070, c=(cx, 0.62 - h))
        формы = стол if формы is None else O.объединить(формы, стол)
        шапка = O.короб(x, y, 0.085, 0.035, скруг=0.030,
                        c=(cx, 0.62 - 2 * h + 0.035))
        свет.append(O.пересечь(шапка, стол))
    слои = [O.тень(формы, сила=0.30), _корпус(формы, ТЕМНО, 0.035, 0.45)]
    for i, ш in enumerate(свет):
        цв = ЦИАН if i % 2 == 0 else ФИОЛ
        г, тт = _светяшка(ш, цв, 0.95, 0.04)
        слои += [г, тт]
    return O.слить(*слои)


def секундомер(x, y, t):
    """Стрелка бежит по кругу, обод отсчитывает долю."""
    корп = O.объединить(O.круг(x, y, 0.62),
                        O.короб(x, y, 0.075, 0.09, скруг=0.030,
                                c=(0.0, -0.68)))
    шкала = None
    for i in range(12):
        a = 2 * np.pi * i / 12.0
        p = (0.50 * np.sin(a), -0.50 * np.cos(a))
        q = (0.57 * np.sin(a), -0.57 * np.cos(a))
        k = O.капсула(x, y, p, q, 0.018 if i % 3 == 0 else 0.010)
        шкала = k if шкала is None else O.объединить(шкала, k)
    a = t * 2 * np.pi
    стрелка = O.объединить(
        O.капсула(x, y, (0.0, 0.0), (0.44 * np.sin(a), -0.44 * np.cos(a)), 0.022),
        O.круг(x, y, 0.045))
    сг, ст = _светяшка(шкала, ЦИАН, 0.55, 0.02)
    хг, хт = _светяшка(стрелка, ЦИАН_СВ, 0.95, 0.045)
    return O.слить(O.тень(корп, сила=0.30), _корпус(корп, ТЕМНО, 0.065),
                   сг, ст, хг, хт)


def узел(x, y, t):
    """Пакет бежит по линии от узла к узлу."""
    a = (-0.55, 0.0)
    b = (0.55, 0.0)
    линия = O.капсула(x, y, a, b, 0.022)
    точки = O.объединить(O.круг(x, y, 0.155, c=a), O.круг(x, y, 0.155, c=b))
    д = _пила(t)
    п = (a[0] + (b[0] - a[0]) * д, 0.0)
    пакет = O.круг(x, y, 0.075, c=п)
    лг, лт = _светяшка(линия, ЦИАН, 0.45, 0.03)
    пг, пт = _светяшка(пакет, ЦИАН_СВ, 1.0, 0.06)
    return O.слить(O.тень(точки, сила=0.30), лг, лт,
                   _корпус(точки, ТЕМНО, 0.045, 0.55), пг, пт)


def батарея(x, y, t):
    """Заряд набирается, обод светится."""
    корп = O.объединить(O.короб(x, y, 0.62, 0.34, скруг=0.10),
                        O.короб(x, y, 0.055, 0.11, скруг=0.030, c=(0.68, 0.0)))
    д = _пила(t)
    ш = 0.08 + 0.44 * д
    заряд = O.короб(x, y, ш, 0.21, скруг=0.055, c=(-0.52 + ш, 0.0))
    заряд = O.пересечь(заряд, O.короб(x, y, 0.54, 0.26, скруг=0.07))
    цв = ЦИАН_СВ if д > 0.55 else ФИОЛ
    г, тт = _светяшка(заряд, цв, 0.85 + 0.15 * д, 0.045)
    return O.слить(O.тень(корп, сила=0.30), _корпус(корп, ТЕМНО, 0.045), г, тт)


def звезда(x, y, t):
    """Объёмная звезда: пять острых лучей, по граням ходит блик.

    Первая проба собирала её из пяти капсул и давала снежинку с круглыми
    концами - звезду делают именно острые концы, значит нужен контур.
    """
    дых = 1.0 + 0.045 * np.sin(t * 2 * np.pi)
    форма = O.звезда_лучи(x, y, 0.74 * дых)
    свет = (-0.45 + 0.9 * _пила(t), -0.55)
    м = O.материал(O.высота(форма, фаска=0.085, выпукл=0.60), форма,
                   (0.99, 0.84, 0.34), металл=1.0, шерох=0.11, отраж=1.0,
                   свет=свет, ободок=0.45, ободок_цвет=O.CYAN_LIT)
    г = O.свечение((форма < 0).astype(np.float32), O.CYAN_LIT, 0.05,
                   0.30 + 0.28 * _пила(t * 2))
    return O.слить(O.тень(форма, сила=0.28), г, м)


def колокол(x, y, t):
    """Колокольчик качается, язычок отстаёт - как настоящий."""
    угол = np.radians(15.0) * np.sin(t * 2 * np.pi * 2)
    rx, ry = _поворот(x, y, угол, (0.0, -0.62))
    купол = O.пересечь(O.круг(rx, ry, 0.46, c=(0.0, 0.02)),
                       O.короб(rx, ry, 0.5, 0.30, c=(0.0, -0.12)))
    юбка = O.короб(rx, ry, 0.44, 0.055, скруг=0.050, c=(0.0, 0.24))
    ушко = O.кольцо(rx, ry, 0.075, 0.028, c=(0.0, -0.46))
    тело = O.объединить(купол, юбка, ушко)
    a2 = np.radians(22.0) * np.sin(t * 2 * np.pi * 2 - 0.7)
    lx, ly = _поворот(x, y, a2, (0.0, -0.62))
    язык = O.круг(lx, ly, 0.075, c=(0.0, 0.38))
    г, тт = _светяшка(юбка, ЦИАН, 0.75, 0.045)
    return O.слить(O.тень(тело, сила=0.30), _корпус(тело, ТЕМНО, 0.045),
                   г, тт, _корпус(язык, (0.9, 0.78, 0.35), 0.030, 0.35))


def кольцо_готово(x, y, t):
    """Кольцо замыкается и внутри вспыхивает галочка."""
    доля = _плавно(min(1.0, t * 1.55))
    обод = O.кольцо(x, y, 0.58, 0.055)
    a = np.arctan2(y, x)
    пройдено = ((a + np.pi / 2) % (2 * np.pi)) <= доля * 2 * np.pi
    дуга = np.where(пройдено, обод, 1.0)
    гк = 0.0 if t < 0.62 else _плавно((t - 0.62) / 0.22)
    галка = O.объединить(
        O.капсула(x, y, (-0.22, 0.03), (-0.05, 0.20), 0.055),
        O.капсула(x, y, (-0.05, 0.20), (0.25, -0.18), 0.055))
    слои = [O.тень(обод, сила=0.26), _корпус(обод, ТЕМНО, 0.030, 0.30)]
    г, тт = _светяшка(дуга, ЦИАН_СВ, 1.0, 0.05)
    слои += [г, тт]
    if гк > 0.01:
        гг, гт = _светяшка(галка, ЦИАН_СВ, гк, 0.055)
        слои += [гг, гт]
    return O.слить(*слои)


