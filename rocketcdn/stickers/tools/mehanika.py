# -*- coding: utf-8 -*-
"""Механика: стикер собирается из частей одного снимка и движется кодом.

Растворение между двумя снимками показывает «было и стало», но не
показывает КАК. Замок владелец просил именно так: замок закрыт, ключ
вставили, он открылся. Значит ключ должен приехать, войти в скважину,
повернуться, и только тогда дужка пойдёт вверх.

Для этого снимок разбирается на части по своей же геометрии - корпус,
дужка, ключ, - и каждая часть движется отдельно. Фотография остаётся
фотографией: ничего не дорисовано, переставлено только то, что и
должно двигаться.
"""

import numpy as np
from PIL import Image
from scipy import ndimage


def части_замка(rgba):
    """Разложить снимок замка на корпус и дужку.

    Граница видна по ширине строки: дужка это две тонкие ноги и дуга,
    корпус - сплошной прямоугольник вдвое шире. Там, где ширина резко
    прыгает, и кончается дужка. Искать её по цвету бесполезно: дужка и
    корпус из одного металла.
    """
    al = rgba[..., 3] > 40
    шир = al.sum(1)
    ys = np.where(шир > 0)[0]
    верх, низ = int(ys[0]), int(ys[-1])
    # Идём вверх не от самого низа, а от самой широкой строки. Снизу у
    # корпуса скруглённый край, там ширина падает сразу, и поиск
    # заканчивался на первой же строке - дужкой оказывался весь замок.
    старт = int(np.argmax(шир))
    ширк = шир[старт]
    рубеж = верх
    for y in range(старт, верх, -1):
        if шир[y] < ширк * 0.85:
            рубеж = y
            break
    дужка = rgba.copy()
    дужка[рубеж:] = 0
    корпус = rgba.copy()
    корпус[:рубеж] = 0
    return корпус, дужка, рубеж


def опора_дужки(дужка, рубеж):
    """Ось, вокруг которой дужка откидывается: низ её левой ноги."""
    ряд = дужка[max(0, рубеж - 6), :, 3] > 40
    x = np.where(ряд)[0]
    if len(x) == 0:
        return (дужка.shape[1] // 2, рубеж)
    разрыв = np.where(np.diff(x) > 8)[0]
    лев = x[:разрыв[0] + 1] if len(разрыв) else x
    return (int(lev_c(лев)), int(рубеж))


def lev_c(a):
    return (a[0] + a[-1]) / 2.0


def скважина(корпус):
    """Скважина: тёмное КОМПАКТНОЕ пятно в середине лицевой стороны.

    Первая проверка искала просто самое тёмное и близкое к центру пятно и
    нашла тёмную полосу вдоль нижней кромки корпуса: шириной во весь
    замок, высотой в девятнадцать точек. Ключ уезжал под неё, к самому
    краю. Скважину отличает не темнота, а форма: она маленькая, почти
    круглая и лежит на лицевой стороне, а не по кромке.
    """
    al = корпус[..., 3] > 40
    ys, xs = np.where(al)
    if len(ys) == 0:
        return (корпус.shape[1] // 2, корпус.shape[0] // 2), 24
    x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
    ш, в = float(x1 - x0), float(y1 - y0)
    тело = float(al.sum())

    ярк = корпус[..., :3].astype(np.float32).mean(2)
    тьма = al & (ярк < np.percentile(ярк[al], 18))
    тьма = ndimage.binary_opening(тьма, np.ones((5, 5)))
    метки, n = ndimage.label(тьма)

    лучший, оценка, размер = None, None, 24
    for i in range(1, n + 1):
        my, mx = np.where(метки == i)
        пл = len(my)
        if пл < тело * 0.002 or пл > тело * 0.06:
            continue
        пш, пв = mx.max() - mx.min() + 1, my.max() - my.min() + 1
        if not (0.35 <= пш / float(пв) <= 2.6):
            continue                      # полоса вдоль кромки - не скважина
        цx, цy = mx.mean(), my.mean()
        if abs(цx - (x0 + ш / 2)) > ш * 0.30 or not (y0 + в * 0.2 < цy < y0 + в * 0.9):
            continue                      # далеко от середины лица
        d = abs(цx - (x0 + ш / 2)) / ш
        if оценка is None or d < оценка:
            оценка, лучший, размер = d, (int(цx), int(цy)), int(max(пш, пв))
    if лучший is None:
        return (int(x0 + ш / 2), int(y0 + в * 0.62)), int(в * 0.12)
    return лучший, размер


def обрезать(rgba):
    """Свести слой к его собственной рамке и вернуть смещение."""
    al = rgba[..., 3] > 8
    if not al.any():
        return rgba, (0, 0)
    ys, xs = np.where(al)
    y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    return rgba[y0:y1, x0:x1], (int(x0), int(y0))


def ось_предмета(rgba):
    """Угол вытянутого предмета и какой конец тяжелее.

    Ключ снят по диагонали, а вставлять его надо горизонтально. Угол
    берётся по главной оси пятна, а не по рамке: рамка у диагонали
    квадратная и про наклон не говорит ничего.
    """
    al = rgba[..., 3] > 40
    ys, xs = np.where(al)
    x = xs - xs.mean()
    y = ys - ys.mean()
    cov = np.cov(np.vstack([x, y]))
    зн, вект = np.linalg.eigh(cov)
    v = вект[:, int(np.argmax(зн))]
    угол = np.degrees(np.arctan2(v[1], v[0]))
    # какой конец толще: проекция на ось, масса по половинам
    p = x * v[0] + y * v[1]
    голова = (p > 0).sum() < (p < 0).sum()   # True - масса в отрицательной
    return float(угол), bool(голова)


def положить(лист, слой, xy, угол=0.0, вокруг=None, масштаб=1.0):
    """Положить слой на лист с поворотом вокруг названной точки."""
    im = Image.fromarray(слой, "RGBA")
    вок = вокруг or (im.size[0] / 2.0, im.size[1] / 2.0)
    if масштаб != 1.0:
        нов = (max(1, int(im.size[0] * масштаб)), max(1, int(im.size[1] * масштаб)))
        im = im.resize(нов, Image.LANCZOS)
        вок = (вок[0] * масштаб, вок[1] * масштаб)
    if угол:
        # поворот вокруг точки: сдвинуть её в центр, повернуть, вернуть
        w, h = im.size
        поле = int(np.hypot(w, h)) + 4
        большой = Image.new("RGBA", (поле, поле), (0, 0, 0, 0))
        большой.paste(im, (int(поле / 2 - вок[0]), int(поле / 2 - вок[1])))
        большой = большой.rotate(угол, Image.BICUBIC, center=(поле / 2, поле / 2))
        im, вок = большой, (поле / 2.0, поле / 2.0)
    лист.alpha_composite(im, (int(round(xy[0] - вок[0])), int(round(xy[1] - вок[1]))))
    return лист


def подсветить(rgba, сила):
    """Разжечь фирменную вставку: то, что и так синее, становится ярче.

    Рисовать свечение отдельным пятном нельзя - оно ляжет поверх металла
    заплатой. Поднимаем яркость там, где синий уже перевешивает красный:
    это ровно вставка и её отсвет на хроме.
    """
    if сила <= 0:
        return rgba
    a = rgba.astype(np.float32)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    маска = np.clip((b - r * 1.15) / 60.0, 0, 1) * np.clip(g / 90.0, 0, 1)
    k = 1.0 + сила * 1.5 * маска
    a[..., 0] = np.clip(r * (1 + сила * 0.5 * маска), 0, 255)
    a[..., 1] = np.clip(g * k, 0, 255)
    a[..., 2] = np.clip(b * k, 0, 255)
    return a.astype(np.uint8)
