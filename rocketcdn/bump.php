<?php
/* ══════════════════════════════════════════════════════════
   Rocket CDN · версии статики

   Браузер кеширует наши файлы надолго - и правильно делает. Беда
   в другом: index.html он мог взять свежий, а словарь языка или
   таблицу стилей отдать из кеша старые. Тогда на экране появляется
   служебный ключ вместо слова или ломается вёрстка.

   Скрипт проставляет каждой ссылке на свой файл метку версии по
   времени последней правки этого файла. Поменялся файл - поменялась
   метка, браузер забирает новое. Не поменялся - берёт из кеша, как
   и раньше.

   Запускать после каждой выкладки:  php bump.php
   ══════════════════════════════════════════════════════════ */

$root = __DIR__;
$pages = ['index.html', 'admin.html', 'app.html', 'splash.html', 'splash-lk.html', 'offer.html', 'privacy.html'];
$total = 0;

/* ══════════════════════════════════════════════════════════
   Отдельный случай: загрузчик объёмного слоя

   assets/rc-gl.js подтягивает три-джей, паспорта рубки и все модули
   сцены сам, и версию им ставит СВОЮ - ту, с которой загрузили его
   самого. Правило «метка по времени правки файла» на них поэтому не
   работает вовсе: правишь rc-flight.js, а в адресе у него остаётся
   старая метка rc-gl.js, и браузер честно отдаёт из кеша прежний
   файл. При заголовке max-age в неделю это значит, что выложенная
   правка неделю не доезжает до тех, кто уже был на сайте.

   Замер на боевом это и показал: rc-gl.js стоял с меткой
   1787869026, а изменённые в тот же день модули сцены грузились с
   ней же. То есть выложено - не значит доставлено.

   Лечим здесь, а не в коде страницы: метку самого rc-gl.js берём не
   по нему одному, а по САМОМУ СВЕЖЕМУ файлу из всех, что он грузит.
   Поменялся любой модуль сцены - поменялась метка загрузчика, а
   вместе с ней и адреса всех модулей. Список читаем из самого
   rc-gl.js, чтобы он не разъезжался с кодом. */
$групповые = [];
$glFile = $root . '/assets/rc-gl.js';
if (is_file($glFile)) {
    $gl = file_get_contents($glFile);
    $макс = filemtime($glFile);
    if (preg_match('~var FILES = \[(.*?)\];~s', $gl, $м)) {
        preg_match_all('~"([^"]+\.js)"~', $м[1], $имена);
        foreach ($имена[1] as $имя) {
            $f = $root . '/assets/' . $имя;
            if (is_file($f)) $макс = max($макс, filemtime($f));
        }
    }
    $групповые['assets/rc-gl.js'] = $макс;
}

foreach ($pages as $page) {
    $file = $root . '/' . $page;
    if (!is_file($file)) continue;
    $html = file_get_contents($file);
    $было = $html;

    $html = preg_replace_callback(
        '~(src|href)="(assets/[^"?#]+\.(?:js|css))(\?v=[0-9]+)?"~',
        function ($m) use ($root, &$total, $групповые) {
            $target = $root . '/' . $m[2];
            if (!is_file($target)) return $m[0];
            $total++;
            $мт = isset($групповые[$m[2]]) ? $групповые[$m[2]] : filemtime($target);
            return $m[1] . '="' . $m[2] . '?v=' . $мт . '"';
        },
        $html
    );

    /* Пишем ТОЛЬКО если что-то изменилось: безусловная запись двигала
       время правки страницы на КАЖДОЙ выкладке, даже когда штамп не
       поменялся ни разу.

       Оговорка честная: метка версии живёт внутри самой страницы,
       поэтому правка любого её ассета страницу всё равно переписывает
       и двигает дату. Для карты сайта это верно по смыслу - у
       страницы действительно изменилось содержимое, - но «дата правки
       текста» это не она. */
    if ($html !== $было) {
        file_put_contents($file, $html);
        echo $page . ": готово\n";
    } else {
        echo $page . ": без изменений\n";
    }
}
echo "ссылок проштамповано: {$total}\n";

/* ── Дата правки в карте сайта ──────────────────────────────
   lastmod стоял руками и отставал от страниц на недели: поисковик
   не видел повода перечитать сайт. Берём дату из самого файла
   страницы, на которую указывает адрес. */
$карта = $root . '/sitemap.xml';
if (is_file($карта)) {
    $xml = file_get_contents($карта);
    $былаКарта = $xml;
    $файлПоАдресу = function ($loc) {
        $путь = parse_url($loc, PHP_URL_PATH);
        $имя = ($путь === null || $путь === '' || $путь === '/') ? 'index.html' : ltrim($путь, '/');
        return $имя;
    };
    $правок = 0;
    $xml = preg_replace_callback(
        '~<loc>([^<]+)</loc><lastmod>[^<]*</lastmod>~',
        function ($m) use ($root, $файлПоАдресу, &$правок) {
            $файл = $root . '/' . $файлПоАдресу($m[1]);
            if (!is_file($файл)) return $m[0];
            $правок++;
            return '<loc>' . $m[1] . '</loc><lastmod>' . date('Y-m-d', filemtime($файл)) . '</lastmod>';
        },
        $xml
    );
    if ($xml !== $былаКарта) {
        file_put_contents($карта, $xml);
        echo "карта сайта: дат обновлено {$правок}\n";
    } else {
        echo "карта сайта: без изменений\n";
    }
}
