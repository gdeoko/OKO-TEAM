<?php
/* ══════════════════════════════════════════════════════════
   Rocket CDN · версии статики

   Браузер кеширует наши файлы надолго - и правильно делает. Беда
   в другом: index.html он мог взять свежий, а словарь языка или
   таблицу стилей отдать из кеша старые. Тогда на экране появляется
   служебный ключ вместо слова или ломается вёрстка.

   Скрипт проставляет каждой ссылке на свой файл метку версии по
   времени последней правки этого файла. Поменялся файл - поменялась
   метка, браузер забирает новое. Не поменялся - берёт из кеша, как
   и раньше.

   Запускать после каждой выкладки:  php bump.php
   ══════════════════════════════════════════════════════════ */

$root = __DIR__;
$pages = ['index.html', 'admin.html', 'app.html', 'splash.html', 'splash-lk.html', 'offer.html', 'privacy.html'];
$total = 0;

foreach ($pages as $page) {
    $file = $root . '/' . $page;
    if (!is_file($file)) continue;
    $html = file_get_contents($file);
    $было = $html;

    $html = preg_replace_callback(
        '~(src|href)="(assets/[^"?#]+\.(?:js|css))(\?v=[0-9]+)?"~',
        function ($m) use ($root, &$total) {
            $target = $root . '/' . $m[2];
            if (!is_file($target)) return $m[0];
            $total++;
            return $m[1] . '="' . $m[2] . '?v=' . filemtime($target) . '"';
        },
        $html
    );

    /* Пишем ТОЛЬКО если что-то изменилось. Безусловная запись
       двигала время правки каждой страницы на любой выкладке, а по
       нему ниже считается lastmod карты сайта: дата уезжала вперёд
       даже там, где менялись одни ассеты, и обещание «берём дату из
       самого файла страницы» превращалось в «берём дату выкладки». */
    if ($html !== $было) {
        file_put_contents($file, $html);
        echo $page . ": готово\n";
    } else {
        echo $page . ": без изменений\n";
    }
}
echo "ссылок проштамповано: {$total}\n";

/* ── Дата правки в карте сайта ──────────────────────────────
   lastmod стоял руками и отставал от страниц на недели: поисковик
   не видел повода перечитать сайт. Берём дату из самого файла
   страницы, на которую указывает адрес. */
$карта = $root . '/sitemap.xml';
if (is_file($карта)) {
    $xml = file_get_contents($карта);
    $файлПоАдресу = function ($loc) {
        $путь = parse_url($loc, PHP_URL_PATH);
        $имя = ($путь === null || $путь === '' || $путь === '/') ? 'index.html' : ltrim($путь, '/');
        return $имя;
    };
    $правок = 0;
    $xml = preg_replace_callback(
        '~<loc>([^<]+)</loc><lastmod>[^<]*</lastmod>~',
        function ($m) use ($root, $файлПоАдресу, &$правок) {
            $файл = $root . '/' . $файлПоАдресу($m[1]);
            if (!is_file($файл)) return $m[0];
            $правок++;
            return '<loc>' . $m[1] . '</loc><lastmod>' . date('Y-m-d', filemtime($файл)) . '</lastmod>';
        },
        $xml
    );
    file_put_contents($карта, $xml);
    echo "карта сайта: дат обновлено {$правок}\n";
}
