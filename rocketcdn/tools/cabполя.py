#!/usr/bin/env python3
"""
Настоящая ФОРМА каждой ячейки приборов, а не её габарит.

Зачем. Ниши на снимке рубки шестиугольные и пятиугольные: у них
срезаны углы, а боковые ещё и развёрнуты. Разметка приборов
(assets/gen/cab/deck.js) описывает каждую ячейку четырьмя углами -
этого хватало, чтобы поставить прибор на место, но не хватает,
чтобы его залить. Прямоугольная заливка в шестиугольной ячейке
оставляет тёмные треугольники по срезам, и прибор читается
квадратной наклейкой поверх ячейки другой формы. Заказчик
сформулировал прямо: «на ПК они квадратные, а ячейки другой формы,
нужно сделать заливку под форму и размер ячейки 1:1».

Что делает. Берёт снимок кокпита и разметку приборов, для каждого
прибора находит на снимке то самое тёмное поле ниши, в котором
стоит его четырёхугольник, и отдаёт КОНТУР этого поля - выпуклую
оболочку, упрощённую до десятка вершин. Дальше слой приборов
заливает ячейку по контуру, а не по габариту.

Выделение поля - тем же способом, что и в cabniche.py: ниша темнее
своего размытого окружения, металл рамки светлее. Иначе два
обмерщика разошлись бы в границах, и контур не совпал бы с углами
из той же разметки.

  python3 tools/cabполя.py                 - все три кадра, правит deck.js
  python3 tools/cabполя.py --показать      - только напечатать, не писать
"""
import json
import math
import re
import sys
from collections import deque

import numpy as np
from PIL import Image, ImageFilter

КАДРЫ = {
    "широкая": "assets/gen/cockpit-wide-hd.webp",
    "средняя": "assets/gen/cockpit-mid-hd.webp",
    "высокая": "assets/gen/cockpit-tall-hd.webp",
}
РАЗМЕТКА = "assets/gen/cab/deck.js"


def поле_ниш(путь, разм=0.008, порог=0.8):
    """Маска тёмных полей ниш. Один в один с cabniche.ниши."""
    im = Image.open(путь).convert("RGBA")
    w, h = im.size
    a = np.asarray(im).astype(np.float32)
    alpha = a[:, :, 3]
    lum = 0.2126 * a[:, :, 0] + 0.7152 * a[:, :, 1] + 0.0722 * a[:, :, 2]
    ys = np.nonzero((alpha < 128).any(axis=1))[0]
    низ = int(ys.max()) if len(ys) else int(h * 0.75)
    сер = np.asarray(Image.fromarray(lum.astype(np.uint8), "L")
                     .filter(ImageFilter.GaussianBlur(w * разм))).astype(np.float32)
    стена = np.asarray(Image.fromarray(((lum - сер > порог) * 255).astype(np.uint8), "L")
                       .filter(ImageFilter.MaxFilter(3))) > 127
    поле = (~стена) & (alpha > 200) & (lum > 2)
    поле[:низ, :] = False
    return поле, w, h


def пятно(поле, y0, x0, окно):
    """Связная область, в которую попала точка, в пределах окна.

    Ограничение окном не украшение. Тёмные поля соседних ниш на
    снимке местами смыкаются через тень, и свободная заливка
    утекала в общее чёрное поле консоли: у мобильного кадра из-за
    этого не нашлось ни одной ячейки. Окно вокруг габарита
    четырёхугольника держит заливку внутри своей ниши.

    Возвращает точки и признак того, что пятно упёрлось в границу
    окна - тогда окно нужно расширить, иначе контур получит
    прямую грань там, где у ниши её нет.
    """
    h, w = поле.shape
    x1, y1, x2, y2 = окно
    if not (y1 <= y0 < y2 and x1 <= x0 < x2) or not поле[y0, x0]:
        return None, False
    видели = np.zeros((y2 - y1, x2 - x1), bool)
    видели[y0 - y1, x0 - x1] = True
    q = deque([(y0, x0)])
    точки = []
    упёрлось = 0
    while q:
        cy, cx = q.popleft()
        точки.append((cx, cy))
        if cy in (y1, y2 - 1) or cx in (x1, x2 - 1):
            упёрлось += 1
        for ny, nx in ((cy - 1, cx), (cy + 1, cx), (cy, cx - 1), (cy, cx + 1)):
            if y1 <= ny < y2 and x1 <= nx < x2 and поле[ny, nx] and not видели[ny - y1, nx - x1]:
                видели[ny - y1, nx - x1] = True
                q.append((ny, nx))
    return точки, упёрлось > max(8, len(точки) * 0.002)


def оболочка(точки):
    """Выпуклая оболочка по обходу Эндрю. Без сторонних библиотек."""
    т = sorted(set(точки))
    if len(т) < 3:
        return т

    def крест(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    низ = []
    for p in т:
        while len(низ) >= 2 and крест(низ[-2], низ[-1], p) <= 0:
            низ.pop()
        низ.append(p)
    верх = []
    for p in reversed(т):
        while len(верх) >= 2 and крест(верх[-2], верх[-1], p) <= 0:
            верх.pop()
        верх.append(p)
    return низ[:-1] + верх[:-1]


def упростить(конт, доля=0.012):
    """Рамер-Дуглас-Пекер: убираем вершины, которые ничего не меняют.

    Порог задан долей габарита пятна, а не пикселями: ниши на разных
    кадрах разного размера, а форма у них одна.
    """
    if len(конт) < 4:
        return конт
    xs = [p[0] for p in конт]
    ys = [p[1] for p in конт]
    eps = max(1.0, доля * max(max(xs) - min(xs), max(ys) - min(ys)))

    def рекурс(пт):
        if len(пт) < 3:
            return pt_list(пт)
        a, b = пт[0], пт[-1]
        dx, dy = b[0] - a[0], b[1] - a[1]
        д = math.hypot(dx, dy) or 1.0
        худ, где = -1.0, 0
        for i in range(1, len(пт) - 1):
            p = пт[i]
            от = abs(dy * (p[0] - a[0]) - dx * (p[1] - a[1])) / д
            if от > худ:
                худ, где = от, i
        if худ <= eps:
            return [a, b]
        лев = рекурс(пт[:где + 1])
        прав = рекурс(пт[где:])
        return лев[:-1] + прав

    def pt_list(x):
        return list(x)

    # Замкнутый контур режем на две дуги по самой дальней паре вершин,
    # иначе алгоритм схлопнет его в отрезок.
    n = len(конт)
    дальше, пара = -1.0, (0, n // 2)
    for i in range(n):
        p = конт[i]
        q = конт[(i + n // 2) % n]
        д = math.hypot(p[0] - q[0], p[1] - q[1])
        if д > дальше:
            дальше, пара = д, (i, (i + n // 2) % n)
    i, j = пара
    дуга1 = конт[i:j + 1] if i < j else конт[i:] + конт[:j + 1]
    дуга2 = конт[j:] + конт[:i + 1] if i < j else конт[j:i + 1]
    из_ = рекурс(дуга1)[:-1] + рекурс(дуга2)[:-1]
    return из_ if len(из_) >= 3 else конт


def контур_ячейки(поле, w, h, угол):
    """Контур ниши, в которой стоит этот четырёхугольник."""
    цx = sum(p[0] for p in угол) / 4.0
    цy = sum(p[1] for p in угол) / 4.0
    шир = max(p[0] for p in угол) - min(p[0] for p in угол)
    выс = max(p[1] for p in угол) - min(p[1] for p in угол)
    # Центр четырёхугольника может попасть на светлую перемычку внутри
    # ниши - пробуем его и восемь точек вокруг, ближе к центру.
    проба = [(цx, цy)]
    for дx in (-0.25, 0.0, 0.25):
        for дy in (-0.25, 0.0, 0.25):
            проба.append((цx + дx * шир, цy + дy * выс))
    лучшее = None
    for запас in (0.55, 1.1, 2.0):
        x1 = max(0, int((цx - шир * (0.5 + запас)) * w))
        x2 = min(w, int((цx + шир * (0.5 + запас)) * w) + 1)
        y1 = max(0, int((цy - выс * (0.5 + запас)) * h))
        y2 = min(h, int((цy + выс * (0.5 + запас)) * h) + 1)
        for u, v in проба:
            точки, упёрлось = пятно(поле, int(v * h), int(u * w), (x1, y1, x2, y2))
            if not точки or упёрлось:
                continue
            if лучшее is None or len(точки) > len(лучшее):
                лучшее = точки
        if лучшее:
            break
    if not лучшее:
        return None
    об = оболочка(лучшее)
    об = упростить(об)
    if len(об) < 3:
        return None
    return [[round(x / float(w), 4), round(y / float(h), 4)] for x, y in об]


def мин_прямоугольник(точки):
    """Наименьший прямоугольник вокруг контура, углы в порядке
    левый верх - правый верх - правый низ - левый низ.

    Порядок обязателен: слой приборов кладёт содержимое в этот
    четырёхугольник аффинным преобразованием, и если начать обход с
    другого угла, лента курса ляжет боком или вверх ногами.
    """
    xx = np.array([p[0] for p in точки], dtype=np.float64)
    yy = np.array([p[1] for p in точки], dtype=np.float64)
    лучший = None
    for град in range(0, 90):
        a = град * math.pi / 180.0
        ca, sa = math.cos(a), math.sin(a)
        u = xx * ca + yy * sa
        v = -xx * sa + yy * ca
        пл = (u.max() - u.min()) * (v.max() - v.min())
        if лучший is None or пл < лучший[0]:
            лучший = (пл, ca, sa, u.min(), u.max(), v.min(), v.max())
    _, ca, sa, u0, u1, v0, v1 = лучший
    углы = [(u0, v0), (u1, v0), (u1, v1), (u0, v1)]
    из_ = [(u * ca - v * sa, u * sa + v * ca) for u, v in углы]
    # Начало обхода - верхний левый угол: сумма координат у него
    # наименьшая при любом развороте прямоугольника.
    старт = min(range(4), key=lambda i: из_[i][0] + из_[i][1])
    из_ = из_[старт:] + из_[:старт]
    # Второй угол обязан быть правым верхним, а не левым нижним:
    # у прямоугольника, найденного под углом, обход мог пойти против
    # часовой стрелки, и тогда содержимое встало бы зеркально.
    if из_[1][0] - из_[0][0] < из_[3][0] - из_[0][0]:
        из_ = [из_[0], из_[3], из_[2], из_[1]]
    return из_


def разметка():
    s = open(РАЗМЕТКА, encoding="utf-8").read()
    тело = s[s.index("{", s.index("RC_CAB_DECK")):]
    тело = тело[:тело.rindex("}") + 1]
    return json.loads(тело), s


def главная(писать=True):
    D, исходник = разметка()
    итог = {}
    for имя, путь in КАДРЫ.items():
        если = D.get(имя)
        if not если or "экраны" not in если:
            continue
        поле, w, h = поле_ниш(путь)
        нашли = 0
        for э in если["экраны"]:
            к = контур_ячейки(поле, w, h, э["угол"])
            if к:
                э["контур"] = к
                # Четырёхугольник размещения пересчитываем по контуру.
                # Прежний снят габаритом пятна и у мобильной ленты
                # уходил в наклон, которого у самой ниши нет.
                э["угол"] = [[round(x, 4), round(y, 4)]
                             for x, y in мин_прямоугольник(к)]
                э.pop("поджать", None)
                нашли += 1
            elif "контур" in э:
                del э["контур"]
        итог[имя] = (нашли, len(если["экраны"]))
        print("%-9s ячеек %d, контур снят у %d" % (имя, len(если["экраны"]), нашли))
        for э in если["экраны"]:
            print("   %-10s вершин %s" % (э["ид"], len(э.get("контур", [])) or "-"))
    if not писать:
        return
    шапка = исходник[:исходник.index("{", исходник.index("RC_CAB_DECK"))]
    хвост = исходник[исходник.rindex("}") + 1:]
    open(РАЗМЕТКА, "w", encoding="utf-8").write(
        шапка + json.dumps(D, ensure_ascii=False, indent=1) + хвост)
    print("записано в", РАЗМЕТКА)


if __name__ == "__main__":
    главная(писать="--показать" not in sys.argv)
