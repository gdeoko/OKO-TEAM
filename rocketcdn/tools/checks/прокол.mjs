/* Прокол на сайт RocketVPN: явление идёт и уводит.

   Что проверяем, по порядку.

   1. МОДУЛЬ НА МЕСТЕ. Без него причал VPN тихо возвращается к прежней
      мгновенной смене адреса, и заметить это по кадру нельзя.

   2. ХОД ИДЁТ В ОДНУ СТОРОНУ. Снимаем восемь долей хода и на каждой
      считаем СРЕДНЮЮ НЕПРОЗРАЧНОСТЬ холста: насколько прокол закрыл
      собой страницу. Считать долю пикселей с ненулевой прозрачностью
      бессмысленно, подложка ложится на весь кадр с первой же доли, и
      мера упирается в сто процентов на втором снимке. Непрозрачность
      обязана расти: где она проседает, там явление мигает, а мигание
      посреди перехода человек читает сбоем загрузки. Сравниваем с
      запасом, кадр рисует живой браузер.

   3. КОНЕЦ ЗАЛИТ. На последней доле страница должна быть закрыта
      почти целиком: она уходит из-под человека уже в свете с той
      стороны. Останется дырка, и он увидит на прощание кусок сайта, с
      которого уходит.

   4. ПРОКОЛ УВОДИТ. Зовём его по-настоящему и ждём, что он вызовет
      переданный ход. Не вызовет - человек останется в залитом кадре
      навсегда, и это хуже, чем полное отсутствие перехода.

   5. ПРИЧАЛ ЗОВЁТ ПРОКОЛ. Стыковочный узел это единственный путь на
      сайт VPN, и он обязан идти через прокол. Подменяем сам прокол
      сторожем, нажимаем причал и смотрим, позвали ли.

   Запуск: RC_URL=http://127.0.0.1:8123/?rcdbg=1 node tools/checks/прокол.mjs
*/
import { АДРЕС, ПК, браузер } from "./общее.mjs";

const ДОЛИ = [0.08, 0.22, 0.38, 0.52, 0.68, 0.82, 0.92, 1.00];
/* Насколько непрозрачность может ПРОСЕСТЬ между соседними снимками.
   Ноль требовать нельзя: кольцо входа на своём ходу сначала светлеет,
   потом гаснет, и на этом месте мера честно колеблется на проценты.
   Всё, что больше, это уже мигание. */
const ПРОСАДКА = 0.04;
/* Насколько страница обязана быть закрыта на последней доле. */
const КОНЕЦ = 0.97;

const беды = [];
const b = await браузер();
const pg = await b.newPage({ viewport: ПК.vp, deviceScaleFactor: 1 });
const ошибки = [];
pg.on("pageerror", e => ошибки.push("PE: " + e.message));
pg.on("console", m => { if (m.type() === "error") ошибки.push("CE: " + m.text().slice(0, 140)); });

await pg.goto(АДРЕС, { waitUntil: "domcontentloaded", timeout: 180000 });
await pg.waitForTimeout(7000);

const модуль = await pg.evaluate(() => !!(window.RC_PROKOL && window.RC_PROKOL["открыть"]));
if (!модуль) {
  беды.push("модуля RC_PROKOL нет: причал VPN уходит мгновенной сменой адреса");
} else {
  /* ── Ход ────────────────────────────────────────────────────
     Занятость считаем по самому холсту прокола, а не по снимку всей
     страницы: снимок ловит ещё и живой сайт под ним, и «занято» на
     первых долях оказалось бы стопроцентным просто потому, что там
     нарисована шапка. */
  const занято = [];
  for (const д of ДОЛИ) {
    const ок = await pg.evaluate((v) => window.RC_PROKOL._кадр(v), д);
    if (!ок) { беды.push(`кадр не нарисовался на доле ${д}`); break; }
    const доля = await pg.evaluate(() => {
      const c = document.querySelector(".rc-prokol-проба");
      if (!c) return null;
      const x = c.getContext("2d");
      const p = x.getImageData(0, 0, c.width, c.height).data;
      let сумма = 0, всего = 0;
      /* Шагаем через пиксель: точность нам нужна в процентах, а не в
         пикселях, а полный обход четырёхмегапиксельного холста в
         песочнице стоит секунды. */
      for (let i = 0; i < p.length; i += 4 * 7) {
        всего++;
        сумма += p[i + 3];
      }
      return всего ? сумма / всего / 255 : null;
    });
    if (доля == null) { беды.push(`холст прокола пропал на доле ${д}`); break; }
    занято.push({ д, доля });
  }

  for (const з of занято) console.log(`   доля хода ${з.д.toFixed(2)} · страница закрыта на ${(з.доля * 100).toFixed(1)}%`);

  for (let i = 1; i < занято.length; i++) {
    const пад = занято[i - 1].доля - занято[i].доля;
    if (пад > ПРОСАДКА) {
      беды.push(`между долями ${занято[i - 1].д} и ${занято[i].д} прокол просел на ` +
                `${(пад * 100).toFixed(1)}%: явление мигает`);
    }
  }
  const последняя = занято[занято.length - 1];
  if (последняя && последняя.доля < КОНЕЦ) {
    беды.push(`в конце хода страница закрыта на ${(последняя.доля * 100).toFixed(1)}% ` +
              `при нужных ${(КОНЕЦ * 100).toFixed(0)}%: человек увидит на прощание кусок сайта`);
  }

  /* ── Прокол уводит ──────────────────────────────────────────*/
  await pg.evaluate(() => {
    const c = document.querySelector(".rc-prokol-проба");
    if (c && c.parentNode) c.parentNode.removeChild(c);
  });
  const увёл = await pg.evaluate(() => new Promise((готово) => {
    let ответил = false;
    const т = setTimeout(() => { if (!ответил) готово(false); }, 6000);
    window.RC_PROKOL["открыть"](() => {
      ответил = true; clearTimeout(т); готово(true);
    });
  }));
  console.log("   прокол вызвал уход: " + (увёл ? "да" : "нет"));
  if (!увёл) беды.push("прокол доиграл и не позвал уход: человек остаётся в залитом кадре");

  /* Холст обязан убраться сам, если переход так и не случился. */
  await pg.waitForTimeout(4600);
  const висит = await pg.evaluate(() => !!document.querySelector(".rc-prokol:not(.rc-prokol-проба)"));
  console.log("   холст после хода: " + (висит ? "висит" : "убран"));
  if (висит) беды.push("холст прокола остался поверх страницы: выйти из него нечем");
}

/* ── Причал зовёт прокол ───────────────────────────────────────
   Сторож вместо настоящего прокола: он не рисует и не уводит, только
   отмечается. Так проверка не уносит страницу и не зависит от того,
   отвечает ли передача /vpn.php. */
const звали = await pg.evaluate(() => new Promise((готово) => {
  if (!window.RC_DOCK || !window.RC_DOCK["открыть"]) { готово("нет узла"); return; }
  window.RC_PROKOL = { "открыть": function () { готово("да"); return true; },
                       "идёт": function () { return true; } };
  const открылся = window.RC_DOCK["открыть"]();
  if (!открылся) { готово("узел не открылся"); return; }
  setTimeout(() => {
    const b = document.querySelector('.rcf-berth[data-марка="vpn"]');
    if (!b) { готово("причала VPN нет"); return; }
    b.click();
  }, 120);
  setTimeout(() => готово("причал не позвал прокол"), 5000);
}));
console.log("   причал VPN зовёт прокол: " + звали);
if (звали !== "да") беды.push("причал VPN не идёт через прокол: " + звали);

if (ошибки.length) беды.push("ошибки в консоли: " + ошибки.slice(0, 3).join(" | "));

await b.close();

if (беды.length) {
  console.log("ГРЯЗНО  прокол");
  for (const б of беды) console.log("   " + б);
  process.exit(1);
}
console.log("ЧИСТО  прокол идёт одним ходом и уводит на сайт VPN");
