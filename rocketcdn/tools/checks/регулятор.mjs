/* Та же арифметика, что в регуляторе rc-flight.js. Проверяем, что
   решение верное на всех сочетаниях: медиана, шаг развёртки,
   текущая плотность, потолок. */
function решение(мед, шаг, тек, пот, сНизу) {
  const пол = 0.72;
  let нов = 0;
  if (мед > Math.max(0.024, шаг * 1.5) && тек > пол) нов = Math.max(пол, тек * 0.85);
  else if (мед < шаг * 1.12 && тек < пот && сНизу > 4000) нов = Math.min(пот, тек * 1.08);
  if (нов && Math.abs(нов - тек) > 0.02) return нов;
  return тек;
}
