#!/usr/bin/env bash
# Все живые проверки подряд. Возвращает ненулевой код, если хоть одна
# нашла беду, поэтому годится и для руки, и для автоматики.
#
# Сервер поднимать самому:  php -S 127.0.0.1:8123 -t .
#
# Имена переменных латиницей намеренно: bash в этом окружении
# кириллические идентификаторы не принимает.
set -u
dir="$(cd "$(dirname "$0")" && pwd)"
code=0
for name in маршрут клавиши метки панели мусор панель-одна; do
  echo "── $name ────────────────────────────────"
  HTTPS_PROXY= node "$dir/$name.mjs" || code=1
done
echo "──────────────────────────────────────"
if [ "$code" = 0 ]; then echo "все проверки чисты"; else echo "есть беды, смотри выше"; fi
exit "$code"
