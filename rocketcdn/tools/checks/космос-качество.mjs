/* АУДИТ КОСМОСА ИГРЫ: РЕЗКОСТЬ, СЛОИ, ОБЪЕКТЫ.

   Владелец: «на телефоне очень некачественно смотрится, как будто всё
   мутное, как каша; вроде реалистично, но мутно, какая-то муть или
   туман; на компьютере ещё более-менее получше. Полупрозрачные белые
   пятна летают - нереалистично. Нужно, чтобы космос был чёткий, 8K,
   ultra HD, как в жизни».

   Проверка не спорит о вкусе, она собирает числа, по которым мутность
   отличается от чёткости, и делает это на ОБЕИХ ширинах:

     1. ПЛОТНОСТЬ КАДРА. Сколько точек рисует движок на одну точку
        экрана. Ниже единицы - картинку растягивают, и это первая
        причина мыла на телефоне. Печатаем и потолок, и то, во что
        упёрся саморегулятор.
     2. РЕЗКОСТЬ САМОГО КАДРА. Средний перепад между соседними точками
        (градиент). Мутный кадр даёт низкий перепад при любой яркости,
        и этим он отличается от просто тёмного.
     3. БЕЛЫЕ ПЯТНА. Доля точек, которые светлые и при этом БЕЗ
        деталей вокруг: ровная светлая клякса. Звезда тоже светлая, но
        у неё резкий край, и в эту долю она не попадает.
     4. ЧТО ВООБЩЕ НАРИСОВАНО. Список видимых крупных узлов сцены с их
        именами: по нему видно и лишнее (чёрная дыра), и пропавшее.

   Снимки кладутся рядом, чтобы можно было посмотреть глазами.

   Запуск: node tools/checks/космос-качество.mjs [тел|пк]
*/
const { chromium } = await import(process.env.RC_PW ||
  await Promise.any([
    import("/tmp/node_modules/playwright/index.mjs").then(() => "/tmp/node_modules/playwright/index.mjs"),
    import("/tmp/node_modules/playwright-core/index.mjs").then(() => "/tmp/node_modules/playwright-core/index.mjs")
  ]));
import { mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";

const { БРАУЗЕР } = await import("../../../rocketvpn/tools/браузер.mjs");

const АДРЕС = process.env.RC_URL || "http://127.0.0.1:8123";
const КТО = process.argv[2] || "тел";
const экран = КТО === "пк"
  ? { w: 1440, h: 900, dpr: 2, mob: false }
  : { w: 390, h: 844, dpr: 3, mob: true };
const КУДА = "/tmp/космос-аудит/" + КТО;
mkdirSync(КУДА, { recursive: true });

/* Точки маршрута: начало, Луна, разгон, Марс, Сатурн, дальний край,
   прыжок, дом. Смотрим весь путь, а не один кадр. */
const ТОЧКИ = [0.02, 0.15, 0.27, 0.36, 0.50, 0.63, 0.76, 0.90];

/* ── ЧИСЛА КАДРА СЧИТАЕМ КАРТИНКОЙ ──────────────────────────────
   Резкость это средний перепад яркости между соседями. Мутный кадр
   даёт низкий перепад при ЛЮБОЙ средней яркости, поэтому темнота его
   не подделает. Белая клякса это светлая точка, вокруг которой
   перепада нет: звезда светлая, но у неё резкий край.

   ── ПЛАНЕТА ЭТО НЕ КЛЯКСА, И ЭТО НАДО РАЗЛИЧАТЬ РАЗМЕРОМ ───────
   Мерка «светлое и ровное» не различала два совершенно разных
   явления. Владелец жаловался на «полупрозрачные белые пятна
   летают», то есть на мелкую висящую дымку. Но под то же условие
   попадает и гладкий бок планеты: на точке маршрута 0.36 кадр
   занимает Сатурн, и мерка честно насчитала двадцать два процента
   при пороге полпроцента.

   Значит вердикт был красным всегда и ни о чём не говорил: половина
   точек маршрута это подлёт к планете. По такой мерке уже чинили
   космос, которого она не видела.

   Различаем размером, и границы у дымки ДВЕ.

   Сверху: планета это ОДНО огромное пятно, кусок крупнее трёх
   процентов кадра это тело.

   Снизу: ЗВЕЗДА. В шапке проверки написано, что звезда сюда не
   попадёт из-за резкого края, и это оказалось неправдой на телефоне:
   при плотности три точка звезды после тональной кривой размазана, и
   перепад внутри неё ниже порога. Пустой кадр на доле 0.50 давал
   четыреста пятнадцать кусков и два с половиной процента - это всё
   были звёзды. Кусок в одну-две клетки сетки это звезда, дымка так
   мелкой не бывает.

   Разметка идёт по уменьшенной сетке: полтора миллиона точек обходить
   незачем, а пятно в пол процента кадра на сетке в триста точек всё
   равно занимает сотни клеток.

   Прежнее число печатаем рядом и НЕ выбрасываем: по нему видно, что
   в кадре вообще много светлого, и это отдельный полезный признак. */
function кадрЧисла(файл) {
  const из = execFileSync("python3", ["-c", `
import sys
from PIL import Image, ImageFilter, ImageStat
from collections import deque
im = Image.open(sys.argv[1]).convert("L")
w, h = im.size
# ── МЕРИМ СТЕКЛО, А НЕ РУБКУ ────────────────────────────────────
# Обрезка резала только верх и низ, и в замер попадали стойки рубки по
# бокам, строка маршрута, плашка «Осмотреться» и счётчик сети. Всё это
# светлое и ровное, то есть ровно то, что мерка называет кляксой.
#
# Кадр на доле 0.50 это чистый чёрный космос с резкими звёздами, и на
# него мерка давала два с половиной процента - целиком за счёт
# интерфейса. Поэтому берём середину окна: ниже плашек, выше пульта и
# без боковых стоек.
im = im.crop((int(w*0.14), int(h*0.28), int(w*0.86), int(h*0.58)))
гр = im.filter(ImageFilter.FIND_EDGES)
s = ImageStat.Stat(im); г = ImageStat.Stat(гр)
я = list(im.getdata()); кр = list(гр.getdata())
n = len(я)
W, H = im.size
светлых = sum(1 for v in я if v > 70)
маска = [1 if (я[i] > 70 and кр[i] < 12) else 0 for i in range(n)]
клякс = sum(маска)

# Уменьшенная сетка под разметку связных кусков.
СЕТКА = 300
шаг = max(1, W // СЕТКА)
gw, gh = (W + шаг - 1)//шаг, (H + шаг - 1)//шаг
мал = [0]*(gw*gh)
for y in range(H):
    гy = y//шаг; ряд = y*W
    for x in range(W):
        if маска[ряд + x]: мал[гy*gw + x//шаг] = 1

видели = [0]*(gw*gh)
мелких = 0; всегоКлеток = 0; кусков = 0; крупнейший = 0
ПРЕДЕЛ = max(4, int(gw*gh*0.03))   # кусок крупнее трёх процентов это тело, а не дымка
НИЗ = 3                            # кусок в одну-две клетки это звезда, а не дымка
for старт in range(gw*gh):
    if not мал[старт] or видели[старт]: continue
    оч = deque([старт]); видели[старт] = 1; кусок = []
    while оч:
        к = оч.popleft(); кусок.append(к)
        кx = к % gw; кy = к // gw
        for дx, дy in ((1,0),(-1,0),(0,1),(0,-1)):
            нx, нy = кx+дx, кy+дy
            if 0 <= нx < gw and 0 <= нy < gh:
                с = нy*gw + нx
                if мал[с] and not видели[с]:
                    видели[с] = 1; оч.append(с)
    кусков += 1; всегоКлеток += len(кусок)
    if len(кусок) > крупнейший: крупнейший = len(кусок)
    if НИЗ <= len(кусок) <= ПРЕДЕЛ: мелких += len(кусок)

мелкаяДоля = (клякс * (мелких / всегоКлеток) * 100.0 / n) if всегоКлеток else 0.0
print(round(s.mean[0], 2), round(г.mean[0], 3),
      round(светлых * 100.0 / n, 2), round(клякс * 100.0 / n, 3),
      round(мелкаяДоля, 3), кусков, round(крупнейший * 100.0 / (gw*gh), 2))
`, файл], { encoding: "utf8" });
  const [яркость, резкость, светлых, кляксы, мелкие, кусков, крупнейший] =
    из.trim().split(/\s+/).map(Number);
  return { яркость, резкость, светлых, кляксы, мелкие, кусков, крупнейший };
}

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"]
});
const стр = await бр.newPage({
  viewport: { width: экран.w, height: экран.h },
  deviceScaleFactor: экран.dpr, isMobile: экран.mob, hasTouch: экран.mob
});
const беды = [];
стр.on("pageerror", (e) => беды.push("ИСКЛ " + e.message.slice(0, 160)));

await стр.goto(АДРЕС + "/?flight=1", { waitUntil: "domcontentloaded", timeout: 90000 });
await стр.waitForFunction(() => window.RC_FLIGHT && window.RC_FLIGHT.open, null, { timeout: 120000 })
  .catch(() => беды.push("полёт не поднялся"));
await стр.waitForTimeout(1500);
await стр.evaluate(() => { try { window.RC_FLIGHT.open(); } catch (e) {} });
/* Сцена собирается этапами, и первые секунды в кадре пусто. Ждём, пока
   в ней появятся тела, а не отсчитываем секунды на глаз. */
/* Сцена собирается этапами. Ждём, пока движок начнёт рисовать
   заметное число треугольников, а не отсчитываем секунды на глаз. */
await стр.waitForFunction(() => {
  try { const с = window.RC_FLIGHT.stats(); return !!(с && с["треугольники"] > 20000); }
  catch (e) { return false; }
}, null, { timeout: 180000 }).catch(() => {});

/* ── БРИФИНГ УБИРАЕМ, ИНАЧЕ МЕРИМ ЕГО, А НЕ КОСМОС ───────────────
   Проверка снимала кадр с ОТКРЫТОЙ плашкой «Готов к старту»: большая
   светлая панель во весь экран плюс две кнопки под ней. Мерка «белые
   пятна» ищет ровное светлое без деталей - и находила ровно её.

   Оттого вердикт был красным всегда и ничего не значил: 7.5 процента
   кадра при пороге 0.5 это плашка интерфейса, а не каша в космосе.
   Снимок это показал сразу, стоило на него посмотреть.

   Красная мерка, меряющая не то, хуже отсутствующей: по ней уже
   чинили космос, которого она не видела. Закрываем брифинг тем же
   нажатием, каким это делает портретная проверка, и только потом
   снимаем. */
await стр.evaluate(() => {
  const б = document.querySelector('.rcf-brief [data-mode="manual"]');
  if (б) б.click();
});
await стр.waitForTimeout(6000);

console.log(`\n${КТО} ${экран.w}x${экран.h} dpr ${экран.dpr}`);

const ряд = [];
for (const p of ТОЧКИ) {
  await стр.evaluate((p) => {
    /* Перемотка по маршруту у полёта называется seek и сбрасывает
       цель с автопилотом: нам нужен ровно кадр в этой точке пути. */
    try { if (window.RC_FLIGHT && window.RC_FLIGHT.seek) window.RC_FLIGHT.seek(p); } catch (e) {}
  }, p);
  await стр.waitForTimeout(2600);
  const файл = `${КУДА}/${p.toFixed(2)}.png`;
  await стр.screenshot({ path: файл });
  const ч = кадрЧисла(файл);
  const сцена = await стр.evaluate(() => {
    /* Сам мир наружу не отдан, и это правильно: снаружи его трогать
       незачем. Но числа кадра нужны, а `stats` их даёт вместе с
       обходом сцены. Плотность спрашиваем у холста: сколько точек
       буфера приходится на точку разметки - это и есть мыло. */
    const F = window.RC_FLIGHT;
    let плотность = null, узлы = [], тр = null;
    const хл = document.querySelector(".rc-flight canvas, canvas.rcf-canvas, canvas");
    if (хл) {
      const к = хл.getBoundingClientRect();
      if (к.width > 0) плотность = +(хл.width / к.width).toFixed(3);
    }
    try { const с = F.stats && F.stats(); if (с) { тр = с["треугольники"]; } } catch (e) {}
    const w = null;
    if (w && w.scene) {
      w.scene.traverse(function (о) {
        if (!о.isMesh && !о.isPoints) return;
        let в = о.visible, р = о.parent;
        while (в && р) { в = р.visible; р = р.parent; }
        if (!в) return;
        let имя = "";
        for (let у = о; у; у = у.parent) { if (у.name) { имя = у.name; break; } }
        if (имя) узлы.push(имя);
      });
    }
    return { плотность: плотность, треугольники: тр, узлы: [...new Set(узлы)].slice(0, 14) };
  });
  ряд.push({ p, ...ч, ...сцена });
  console.log(`  p ${p.toFixed(2)}  плотность ${сцена.плотность}  треуг ${сцена.треугольники}` +
              `  яркость ${ч.яркость}  резкость ${ч.резкость}  светлых ${ч.светлых}%` +
              `  кляксы ${ч.кляксы}%  из них мелких ${ч.мелкие}%  кусков ${ч.кусков}  крупнейший ${ч.крупнейший}%`);
}

/* ── ВЕРДИКТ ────────────────────────────────────────────────────
   Пороги сняты с этих же кадров и названы явно, чтобы правка их
   двигала осознанно, а не подгонкой под сегодняшний результат. */
const срез = (к) => ряд.reduce((a, с) => a + с[к], 0) / ряд.length;
console.log(`\n  в среднем: резкость ${срез("резкость").toFixed(3)}, кляксы ${срез("кляксы").toFixed(3)}%` +
            `, из них мелких ${срез("мелкие").toFixed(3)}%`);

for (const с of ряд) {
  if (с.плотность !== null && с.плотность < 1) {
    беды.push(`p ${с.p}: плотность кадра ${с.плотность} - картинку растягивают, отсюда мыло`);
  }
}
/* ── ПОРОГ РЕЗКОСТИ ПРИНАДЛЕЖИТ ОБРЕЗКЕ ─────────────────────────
   Стояла шестёрка, и она была снята с ПРЕЖНЕГО окна замера, куда
   попадали стойки рубки и плашки интерфейса: у металла перепад
   большой, и он один вытягивал число. Окно сузили до стекла, и то же
   самое небо стало давать 1.77 - то есть старый порог краснел бы на
   любом кадре, даже идеальном.

   Новый порог снят замером, а не выбран: тот же набор кадров, замыленный
   по гауссу, даёт

     чистый       1.772
     мыло 1 точка 1.276
     мыло 2 точки 0.857

   Ставим 1.5: выше замыленного на точку и ниже чистого. Меньше
   половины точки размытия глаз на телефоне и не заметит, а всё, что
   заметно, проверка поймает.

   Порог и обрезка связаны намертво: меняешь одно - перемеряй второе. */
if (срез("резкость") < 1.5) {
  беды.push(`кадр мутный: средний перепад ${срез("резкость").toFixed(3)} при пороге 1.5` +
            ` (чистый кадр этого маршрута даёт 1.77, замыленный на точку - 1.28)`);
}
/* Судим по МЕЛКИМ пятнам. Общее число светлого и ровного остаётся в
   печати, но приговором быть не может: планета во весь кадр даёт по
   нему двадцать два процента, и вердикт краснел на подлёте к Сатурну,
   а не на дымке. Разбор и числа - в шапке у самой мерки. */
if (срез("мелкие") > 0.5) {
  беды.push(`белёсые пятна: ${срез("мелкие").toFixed(3)}% кадра мелкая светлая дымка при пороге 0.5` +
            ` (всего светлого и ровного ${срез("кляксы").toFixed(3)}%, крупное это тела)`);
}
const сДырой = ряд.filter((с) => с.узлы.some((и) => /дыра|hole|горизонт/i.test(и)));
if (сДырой.length) беды.push("в кадре осталась чёрная дыра на долях: " + сДырой.map((с) => с.p).join(", "));

if (беды.length) {
  console.log("\nКРАСНОЕ:");
  for (const с of [...new Set(беды)]) console.log("   " + с);
} else {
  console.log("\nзелено: кадр резкий, клякс нет, дыры нет");
}
console.log(`  снимки: ${КУДА}`);
await бр.close();
process.exit(беды.length ? 1 : 0);
