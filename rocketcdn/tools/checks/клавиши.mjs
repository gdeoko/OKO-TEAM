/* Каждая клавиша пульта нажатием.

   Так нашлась мёртвая клавиша СЕТЬ: она переключала класс, на
   который не было ни одного правила, поэтому загоралась и не делала
   ничего. Проверка смотрит не на код, а на последствия: изменилось
   ли хоть что-то в состоянии полёта или на экране. */
import { браузер, вПолёт, ТЕЛЕФОН, итог } from "./общее.mjs";

const КЛАВИШИ = ["rcf-navkey", "rcf-scan-key", "rcf-deploy", "rcf-help-key",
                 "rcf-auto-key", "rcf-stop-key", "rcf-map-key", "rcf-shot",
                 "rcf-zoom-in", "rcf-zoom-out"];

const b = await браузер();
const { pg, ошибки } = await вПолёт(b, ТЕЛЕФОН);
const беды = [];

const слепок = () => pg.evaluate(() => {
  const s = window.RC_FLIGHT.state();
  /* Раньше здесь шёл обход ВСЕХ элементов слоя с чтением стилей: на
     песочнице без видеокарты это минуты на один прогон, а точности
     не добавляло - фон шевелится сам по себе и любое нажатие
     выглядело осмысленным. Берём то, что действительно меняют
     клавиши: раскрытые панели, тумблеры, зум, тягу и счётчики. */
  const открыта = сел => {
    const e = document.querySelector(сел);
    if (!e) return false;
    const cs = getComputedStyle(e);
    return cs.display !== "none" && cs.visibility !== "hidden" && +cs.opacity > 0.06;
  };
  const и = window.RC_FLIGHT._interaction ? window.RC_FLIGHT._interaction() : null;
  return JSON.stringify({
    p: s.p, цель: s["цель"], рукав: s["вселенная"], и: и,
    панели: [".rcf-menu.on", ".rcf-help.on", ".rcf-dos.on", ".rcf-netlist.on"].map(открыта),
    сеть: (document.querySelector(".rcf-net") || {}).textContent,
    подпись: (document.querySelector(".rcf-cap") || {}).textContent
  });
});

/* Некоторым клавишам нужно состояние, в котором их работа вообще
   заметна. СТОП гасит ход и снимает цель: на неподвижном корабле без
   цели он честно ничего не меняет, и проверка соврала бы, что
   клавиша мёртвая. Даём ход и цель заранее. */
const ПОДГОТОВКА = {
  "rcf-stop-key": async () => {
    await pg.evaluate(() => { window.RC_FLIGHT._go("mars"); window.RC_FLIGHT.seek(0.10, 0.06); });
    await pg.waitForTimeout(2000);
  }
};

for (const к of КЛАВИШИ) {
  if (ПОДГОТОВКА[к]) await ПОДГОТОВКА[к]();
  const до = await слепок();
  const есть = await pg.evaluate(s => {
    const e = document.querySelector("." + s);
    if (!e) return false;
    e.click();
    return true;
  }, к);
  if (!есть) { беды.push(к + ": нет в разметке"); continue; }
  await pg.waitForTimeout(1700);
  const после = await слепок();
  const немая = до === после;
  console.log("  ", к.padEnd(14), немая ? "НИЧЕГО НЕ ПРОИЗОШЛО" : "отзывается");
  if (немая) беды.push(к + ": нажатие ничего не меняет");
  /* Переключатель возвращаем в исходное, иначе следующая клавиша
     меряется в чужом состоянии. */
  await pg.evaluate(s => {
    const e = document.querySelector("." + s);
    if (e && e.classList.contains("cur")) e.click();
  }, к);
  await pg.waitForTimeout(900);
}

/* ── Поворот экрана и обратно ──────────────────────────────────
   Раскладка пульта считается заново под каждый размер окна, и у неё
   есть цикл, который снимает клавиши, которым не хватило ниши: у них
   убирается признак `rcf-phys-hit`, инлайновая позиция и display.
   Если после возвращения в прежний размер клавиша не получит всё это
   назад, она останется в разметке, но невидимой и ненажимаемой.

   Заказчик ловил ровно это дважды: «на 1920 у пульта ноль рабочих
   клавиш». Проверка гоняет телефон → монитор → телефон и считает,
   сколько клавиш пригодно к нажатию в конце. */
async function пригодных() {
  return pg.evaluate((список) => {
    let n = 0;
    список.forEach((к) => {
      const e = document.querySelector("." + к);
      if (!e) return;
      const cs = getComputedStyle(e);
      const r = e.getBoundingClientRect();
      const виден = cs.display !== "none" && cs.visibility !== "hidden" &&
                    +cs.opacity > 0.06 && r.width > 8 && r.height > 8 &&
                    r.right > 0 && r.left < innerWidth && r.bottom > 0 && r.top < innerHeight;
      if (виден) n++;
    });
    return n;
  }, КЛАВИШИ);
}

async function размер(ш, в) {
  await pg.setViewportSize({ width: ш, height: в });
  /* Слою нужно пересобрать плиту и пересчитать ниши. На песочнице без
     видеокарты это секунды, а не миллисекунды. */
  await pg.waitForTimeout(3800);
  return пригодных();
}

/* Порядок важен. Клавиши, которым не хватило ниши, СНИМАЮТСЯ с плиты:
   у них убирают признак `rcf-phys-hit`, инлайновую позицию и display.
   Значит ловить надо не «широкий → узкий», а ВОЗВРАЩЕНИЕ: узкий →
   широкий, где снятая клавиша обязана получить всё назад. Первый
   вариант этой проверки шёл телефон → монитор → телефон и не ловил
   ничего: на телефоне те три клавиши и должны быть спрятаны, число
   сходилось при любой поломке.

   На сегодня обе стороны сходятся: 7 → 10 → 7 → 10. Проверка стоит
   здесь не потому, что что-то сломано, а потому что заказчик ловил
   пустой пульт дважды («на 1920 у пульта ноль рабочих клавиш»), и
   молча вернуться это не должно. */
const наУзком = await пригодных();
const наШироком = await размер(1440, 900);
const сноваУзкий = await размер(412, 800);
const сноваШирокий = await размер(1440, 900);
console.log("   пригодны к нажатию: узкий " + наУзком + ", широкий " + наШироком +
            ", снова узкий " + сноваУзкий + ", снова широкий " + сноваШирокий);
if (наШироком === 0) беды.push("на широком экране не осталось ни одной клавиши");
if (сноваУзкий !== наУзком) {
  беды.push("узкий экран после широкого дал другое число клавиш: " +
            наУзком + " -> " + сноваУзкий);
}
if (сноваШирокий < наШироком) {
  беды.push("клавиши не вернулись на плиту после сужения и расширения: " +
            наШироком + " -> " + сноваШирокий);
}

await b.close();
process.exit(итог("клавиши пульта", беды, ошибки));
