/* Дальние тела обязаны возвращаться поодиночке, а не разом.

   Что ломалось. На время салона дальние тела прятали, а возвращали
   одним порогом: до восьми десятых подъезда спрятано всё, после -
   видно всё. Прокрутка по восемьдесят точек ловила ровно это: за
   один шаг число видимых узлов сцены прыгало с одиннадцати на
   тридцать. Девятнадцать тел, появившихся в одном кадре, человек
   читает подменой содержимого окна.

   Что меряем. Идём прокруткой по двадцать точек от входа в салон до
   низа страницы и на каждом шаге спрашиваем сцену, сколько узлов в
   ней видно. Самый большой прирост за один шаг и есть та самая
   подмена. До правки он был девятнадцать, после - четыре.

   Замер живёт на служебном ходе `_узлы`, а он стоит за признаком
   ?rcdbg=1 в адресе. В боевой сборке этой двери нет.

   Запуск: RC_URL=http://127.0.0.1:8123/?rcdbg=1 node tools/checks/тела-по-очереди.mjs
*/
import { АДРЕС, ПК, браузер } from "./общее.mjs";

/* Сколько тел разрешено вернуть за один шаг прокрутки в двадцать
   точек. Шесть, а не четыре: замер идёт на программном растеризаторе
   в песочнице, и доля подъезда за шаг гуляет от прогона к прогону.
   Порог ловит возврат прежнего поведения (девятнадцать), а не дрожь. */
const ПРЕДЕЛ = 6;

const беды = [];
const b = await браузер();
const pg = await b.newPage({ viewport: ПК.vp, deviceScaleFactor: 1 });
await pg.goto(АДРЕС, { waitUntil: "domcontentloaded", timeout: 180000 });
await pg.waitForTimeout(8000);

/* Сам ход есть всегда, а вот сцена собирается позже: на первом кадре
   страницы мира ещё нет, и _узлы честно отдаёт пусто. Поэтому здесь
   проверяем только наличие двери, а её молчание разбираем в конце -
   если сцена так и не собралась, мерить было нечего. */
const дверь = await pg.evaluate(() => !!(window.RC_FLIGHT && window.RC_FLIGHT._узлы));
if (!дверь) {
  console.log("ГРЯЗНО  тела по очереди");
  console.log("   служебный ход _узлы недоступен: в адресе нет ?rcdbg=1");
  await b.close();
  process.exit(1);
}

const H = await pg.evaluate(() => document.documentElement.scrollHeight - innerHeight);
const y0 = await pg.evaluate(() => {
  const e = document.querySelector("#reliability");
  return e ? Math.round(e.getBoundingClientRect().top + scrollY - innerHeight * 0.5) : 0;
});

/* До салона идём крупно: там мерить нечего, а время прогона не
   бесконечное. Внутри - мелким шагом. */
let y = 0;
while (y < y0) { y += 80; await pg.evaluate(v => scrollTo(0, v), Math.min(y, y0)); await pg.waitForTimeout(40); }

let было = null, худший = 0, гдеХудший = null, замеров = 0;
while (y < H) {
  y += 20;
  await pg.evaluate(v => scrollTo(0, v), Math.min(y, H));
  await pg.waitForTimeout(90);
  const с = await pg.evaluate(() => {
    const у = window.RC_FLIGHT._узлы();
    if (!у) return null;
    return { видно: у.filter(x => x.видно && x.мешей).length,
             акт: document.documentElement.getAttribute("data-act") };
  });
  if (!с) continue;
  замеров++;
  if (было != null && с.видно - было > худший) { худший = с.видно - было; гдеХудший = { y, акт: с.акт }; }
  было = с.видно;
}

if (замеров < 10) {
  беды.push(`сцена так и не собралась: удачных замеров ${замеров}, мерить было нечего`);
}
console.log(`   наибольший прирост видимых тел за шаг: ${худший}` +
            (гдеХудший ? ` (y=${гдеХудший.y}, акт ${гдеХудший.акт})` : ""));
if (худший > ПРЕДЕЛ) {
  беды.push(`за один шаг прокрутки вернулось ${худший} тел при пределе ${ПРЕДЕЛ}`);
}

await b.close();

if (беды.length) {
  console.log("ГРЯЗНО  тела по очереди");
  for (const б of беды) console.log("   " + б);
  process.exit(1);
}
console.log("ЧИСТО  дальние тела возвращаются поодиночке");
