/* Общая панель на два сайта: считает ли она и с чем связана.

   Всё, что здесь проверяется, ломалось молча. Молча - ключевое
   слово: ни одна из этих бед не давала ошибки ни на экране, ни в
   журнале, и находились они только руками.

   ПОДПАПКА ПЛОЩАДКИ. Счётчик VPN отвечал «принято», а писать было
   некуда: папки `stats/vpn` не существовало, запись уходила в
   никуда. Сутки статистики просто не было, и панель честно рисовала
   ноль. Поэтому проверка шлёт событие и требует, чтобы оно ВЕРНУЛОСЬ
   в сводке, а не чтобы сервер сказал «ок».

   МЕТКИ АКТОВ. Акты фильма VPN складывались в один счётчик, и
   воронка делила его на восемь - «в среднем по больнице». Теперь
   акты лежат поимённо, и проверка требует именно имя.

   БЕЛЫЙ СПИСОК ДОМЕНОВ. Панель лежит на двух доменах и ходит на один
   сервер. Заголовок с любым источником сделал бы наш счётчик и приём
   заявок доступным любой чужой странице. Проверяем оба конца: своему
   домену разрешено, чужому нет.

   ОДНА ПАНЕЛЬ, А НЕ ДВЕ КОПИИ. С обоих доменов обязан отдаваться
   БАЙТ В БАЙТ один файл. Копия разошлась бы с оригиналом на первой
   же правке, и заказчик увидел бы разные панели по двум ссылкам.

   След от проверки: одно событие «акт» с уникальной меткой на каждую
   площадку за прогон. Заход (`view`) не шлём намеренно - просмотры и
   люди в отчётах заказчика остаются нетронутыми.

   Проверка живая и ходит на боевой сервер, поэтому ключ панели берём
   из окружения и в репозиторий не кладём:

     RC_KEY=... node tools/checks/общая-панель.mjs
*/
const БОЕВОЙ = process.env.RC_API || "https://rocketcdn.ru";
const VPN    = process.env.RV_URL || "https://rocketvpn.top";
const КЛЮЧ   = process.env.RC_KEY || "";

const беды = [];
const метка = "проверка-" + Date.now().toString(36);

async function зов(действие, тело, заголовки = {}) {
  const о = await fetch(БОЕВОЙ + "/api.php?action=" + encodeURIComponent(действие), {
    method: "POST",
    headers: Object.assign({ "Content-Type": "application/json" }, заголовки),
    body: JSON.stringify(тело)
  });
  const т = await о.text();
  try { return JSON.parse(т); } catch (e) { return { ok: false, error: "не JSON: " + т.slice(0, 80) }; }
}

/* ── Счётчик пишет в подпапку своей площадки ─────────────── */
for (const сайт of ["vpn", "game"]) {
  /* Площадку кладём в тело, а не в адрес: действие уходит через
     encodeURIComponent, и амперсанд в нём превратился бы в часть
     имени действия. */
  const о = await зов("track", {
    site: сайт,
    sid: метка + "-" + сайт,
    ref: "",
    events: [{ t: "акт", l: метка }]
  });
  if (!о.ok) беды.push(`счётчик ${сайт}: сервер ответил ${JSON.stringify(о)}`);
}

if (!КЛЮЧ) {
  беды.push("нет RC_KEY, сводку проверить нечем (это половина проверки)");
} else {
  for (const сайт of ["vpn", "game"]) {
    const с = await зов("stats", { key: КЛЮЧ, days: 2, site: сайт });
    if (!с.ok) { беды.push(`сводка ${сайт}: ${JSON.stringify(с).slice(0, 120)}`); continue; }
    const акты = с["акты"] || {};
    if (!акты[метка]) {
      беды.push(`сводка ${сайт}: событие принято, но в статистике его нет - ` +
                `похоже, писать некуда (подпапка stats/${сайт})`);
    }
  }

  /* ── Обзор знает про все три площадки ──────────────────── */
  const об = await зов("обзор", { key: КЛЮЧ, days: 7 });
  if (!об.ok) беды.push("обзор: " + JSON.stringify(об).slice(0, 120));
  else for (const с of ["cdn", "vpn", "game"]) {
    if (!об["сайты"] || !об["сайты"][с]) беды.push("обзор не знает площадку " + с);
  }

  /* ── Связка с ботом и темами ───────────────────────────── */
  const св = await зов("связка", { key: КЛЮЧ });
  if (!св.ok) беды.push("связка: " + JSON.stringify(св).slice(0, 120));
  else {
    if (!св["чат"]) беды.push("связка: чат команды не привязан, уведомления идти некуда");
    for (const т of ["формы", "ошибки", "аналитика"]) {
      if (!(св["темы"] || {})[т]) беды.push("связка: тема «" + т + "» не привязана");
    }
    if (!св["бот"]) беды.push("связка: бот не отвечает и в памяти его нет");
  }
}

/* ── Белый список доменов, а не любой источник ───────────── */
async function проба(источник) {
  const о = await fetch(БОЕВОЙ + "/api.php?action=stats", {
    method: "OPTIONS",
    headers: { Origin: источник, "Access-Control-Request-Method": "POST" }
  });
  return о.headers.get("access-control-allow-origin") || "";
}
if (await проба(VPN) !== VPN) беды.push("домену VPN кросс-запрос не разрешён, панель там останется пустой");
const чужому = await проба("https://example.invalid");
if (чужому) беды.push("кросс-запрос разрешён чужому домену: " + чужому);

/* ── Панель одна на два адреса ───────────────────────────── */
const адреса = [БОЕВОЙ + "/admin", VPN + "/admin"];
const тела = [];
for (const а of адреса) {
  const о = await fetch(а);
  if (!о.ok) { беды.push("панель по адресу " + а + " отвечает " + о.status); тела.push(null); continue; }
  тела.push(await о.text());
}
if (тела[0] && тела[1] && тела[0] !== тела[1]) {
  беды.push("по двум адресам отдаются РАЗНЫЕ панели: завелась копия, она разойдётся с оригиналом");
}

console.log((беды.length ? "ПЛОХО  " : "ЧИСТО  ") + "общая панель");
беды.forEach((б) => console.log("   ", б));
process.exit(беды.length ? 1 : 0);
