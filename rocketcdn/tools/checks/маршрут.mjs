/* Проход маршрута от начала до конца.

   Этой проверкой ловились две поломки, из-за которых полёт нельзя
   было пройти вовсе: пробой всегда бросал в один и тот же рукав, а
   возврат домой клал корабль обратно в зону прыжка и выкидывал
   заново. Обе видны только в связке, по одной их не поймать. */
import { браузер, вПолёт, ТЕЛЕФОН, итог } from "./общее.mjs";

const b = await браузер();
const { pg, ошибки } = await вПолёт(b, ТЕЛЕФОН);
const беды = [];

const состояние = () => pg.evaluate(() => {
  const s = window.RC_FLIGHT.state();
  return { p: +s.p.toFixed(3), рукав: s["вселенная"], цель: s["цель"] };
});

const шаг = async (что, fn) => {
  try { await fn(); } catch (e) { беды.push(что + ": " + e.message); }
  await pg.waitForTimeout(2600);
  const s = await состояние();
  console.log("  ", что.padEnd(22), JSON.stringify(s));
  return s;
};

await шаг("курс на Луну", () => pg.evaluate(() => window.RC_FLIGHT._go("moon")));
await шаг("подошли к Луне", () => pg.evaluate(() => window.RC_FLIGHT.seek(0.155, 0)));
const зона = await pg.evaluate(() => {
  const м = window.RC_FLIGHT.state()["отметки"];
  return [м.jump0, м.jump1];
});
/* Ставим корабль ПЕРЕД окном пробоя, а не в него: вспышка живёт в
   узкой полосе около трёх четвертей пути по зоне, и если сесть уже
   за ней, корабль просто пролетит мимо и проверка соврёт, будто
   пробоя нет. В зоне тяга сама разгоняется, так что окно корабль
   проходит за секунду с небольшим. */
await шаг("перед пробоем", () => pg.evaluate(v => window.RC_FLIGHT.seek(v, 0.02), зона[0] + (зона[1] - зона[0]) * 0.55));
/* Ждём пробоя по ФАКТУ, а не по секундомеру.

   Стояло ровно 5,2 секунды, и на загруженной машине проверка врала:
   слой отдаёт два-три кадра в секунду, корабль за это время проходит
   по зоне сотые доли, до окна вспышки не доезжает, и проверка писала
   «пробой не увёл в чужой рукав», хотя код тут ни при чём. Ждём
   смены рукава до минуты, но выходим сразу, как она случилась. */
const пробой = await шаг("после пробоя", async () => {
  for (var т = 0; т < 60; т++) {
    var с = await состояние();
    if (с.рукав !== 0) return;
    await pg.waitForTimeout(1000);
  }
});
if (пробой.рукав === 0) беды.push("пробой не увёл в чужой рукав");

const дом = await шаг("домой", () => pg.evaluate(() => window.RC_FLIGHT.jump(0)));
if (дом.рукав !== 0) беды.push("возврат домой не сработал");
if (дом.p <= зона[1]) беды.push("после возврата корабль внутри зоны прыжка: p=" + дом.p + " при границе " + зона[1]);
if (дом.цель) беды.push("после возврата домой в курсе остался чужой мир: " + дом.цель);

const конец = await шаг("до конца маршрута", () => pg.evaluate(() => window.RC_FLIGHT.seek(1, 0)));
if (конец.p < 0.999) беды.push("маршрут не дошёл до конца: p=" + конец.p);

await b.close();
process.exit(итог("маршрут", беды, ошибки));
