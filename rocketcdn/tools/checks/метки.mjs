/* Вылет подписей тел за проём рубки.

   Заказчик видел "ЗЕМЛ", "АСТЕРОИ", "ЧЁРНАЯ ДЫ". Причина оказалась
   не в ширине карточки: полёт присылал границы проёма в координатах
   экрана, а метки слой ставит в своих, и его левый край сам сдвинут.
   Прижим срабатывал на эти же полсотни точек правее.

   Меряем самый большой вылет за проём по всем слоям карточки на
   нескольких точках маршрута. Ноль - значит прижим работает. */
import { браузер, вПолёт, проём, ТЕЛЕФОН, ПК, итог } from "./общее.mjs";

const ТОЧКИ = [0.06, 0.15, 0.24, 0.37, 0.54, 0.90];
const СЛОИ = ".rch-body, .rch-halo, .rch-glow, .rch-tname, .rch-title, .rch-rows, .rch-edge";

const b = await браузер();
const беды = [];
const всеОшибки = [];

for (const э of [ТЕЛЕФОН, ПК]) {
  const { pg, ошибки } = await вПолёт(b, э);
  let худший = { вылет: 0, кто: "", p: 0 };
  for (const p of ТОЧКИ) {
    await pg.evaluate(v => window.RC_FLIGHT.seek(v, 0), p);
    await pg.waitForTimeout(2600);
    const гр = await проём(pg);
    const r = await pg.evaluate(([л, п, сел]) => {
      let макс = 0, кто = "";
      document.querySelectorAll(".rch-tag:not(.off)").forEach(t => {
        t.querySelectorAll(сел).forEach(e => {
          const rr = e.getBoundingClientRect();
          if (!rr.width) return;
          const вылет = Math.max(л - rr.left, rr.right - п);
          if (вылет > макс) { макс = вылет; кто = e.className + " " + (t.textContent || "").trim().slice(0, 14); }
        });
      });
      return { вылет: Math.round(макс), кто };
    }, [гр.л, гр.п, СЛОИ]);
    if (r.вылет > худший.вылет) худший = { ...r, p };
  }
  console.log("  ", э.имя.padEnd(8), "наибольший вылет за проём:", худший.вылет, "px",
              худший.кто ? "| " + худший.кто : "", "| p=" + худший.p);
  /* Две точки запаса на округление подпикселей: на дробном
     масштабе рамка и метка считаются разными путями. */
  if (худший.вылет > 2) беды.push(э.имя + ": подпись вылезает за проём на " + худший.вылет + " px (" + худший.кто + ")");
  всеОшибки.push(...ошибки);
  await pg.close();
}

await b.close();
process.exit(итог("подписи тел", беды, всеОшибки));
