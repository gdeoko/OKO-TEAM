/* ПАНЕЛЬ: У КАЖДОЙ ПЛОЩАДКИ СВОЙ ПОЛНЫЙ РАЗДЕЛ.

   Владелец: «админку сделай более детальную, либо лучше раздельные -
   для CDN своя, для VPN своя».

   Раздельными файлами это делать нельзя: панель полторы тысячи строк, и
   две копии разойдутся после первой правки, причём молча. Разделение
   сделано по содержанию: раздел площадки отвечает на ВСЁ о ней.

   Проверка заходит в живую панель и смотрит глазами браузера, а не по
   исходнику: половина плит собирается скриптом уже после ответа
   сервера, и в разметке файла их нет вовсе. Для каждой площадки
   считаем её плиты по заголовкам и проверяем, что раздел не пустой.

   Пароль берём из окружения, в файл он не попадает:
     RC_ADMIN_KEY=... node tools/checks/панель-площадок.mjs
*/
/* Браузер берём тем же способом, что и соседние проверки этого сайта:
   пакет лежит не в корне репозитория, и прямой import его не находит. */
const { chromium } = await import(process.env.RC_PW ||
  await Promise.any([
    import("/tmp/node_modules/playwright/index.mjs").then(() => "/tmp/node_modules/playwright/index.mjs"),
    import("/tmp/node_modules/playwright-core/index.mjs").then(() => "/tmp/node_modules/playwright-core/index.mjs"),
    import("../../../rocketvpn/node_modules/playwright/index.mjs")
      .then(() => "../../../rocketvpn/node_modules/playwright/index.mjs")
  ]));

const АДРЕС = process.env.RC_URL || "https://rocketcdn.ru/admin.html";
const КЛЮЧ = process.env.RC_ADMIN_KEY || "";
if (!КЛЮЧ) { console.log("нет RC_ADMIN_KEY - проверять нечем"); process.exit(0); }

/* Плиты, без которых раздел площадки не отвечает на свои вопросы.
   Воронка и заявки есть не у каждой: у игры нет ни формы, ни ступеней,
   и требовать их значило бы красить исправное в красное. */
const ЖДЁМ = {
  cdn: ["Воронка площадки", "Посещения по дням", "События", "Часы суток",
        "Докуда доходят", "Откуда приходили", "Устройства и система",
        "Ошибки у людей", "Заявки площадки", "Адреса площадки"],
  vpn: ["Посещения по дням", "События", "Часы суток", "Докуда доходят",
        "Откуда приходили", "Устройства и система", "Ошибки у людей",
        "Заявки площадки", "Адреса площадки"],
  game: ["Посещения по дням", "События", "Часы суток",
         "Откуда приходили", "Устройства и система", "Ошибки у людей"]
};

/* Путь к самому Chromium тоже спрашиваем у папки, а не помним: сессия
   в облаке поднимается с новой версией браузера, и прописанный путь
   падает на первой строке, хотя браузер стоит рядом. */
const { БРАУЗЕР } = await import("../../../rocketvpn/tools/браузер.mjs");
/* Наружу из облачной сессии ходят только через прокси окружения. У
   curl он берётся сам, у Chromium нет: без этой строки заход на боевую
   панель падает «соединение сброшено», и выглядит это как лежащий
   сайт, хотя сайт отвечает. */
/* Прокси ставим ТОЛЬКО когда идём наружу. Список обхода у Chromium
   тут не помог: свой же стенд на 127.0.0.1 всё равно уходил в прокси и
   получал в ответ «этот прокси принимает только CONNECT», а выглядело
   это как пустая панель без поля пароля. Решаем по адресу. */
const местный = /^https?:\/\/(127\.0\.0\.1|localhost|\[::1\])/.test(АДРЕС);
const ПРОКСИ = местный ? "" : (process.env.HTTPS_PROXY || process.env.HTTP_PROXY || "");
const бр = await chromium.launch(Object.assign(
  { executablePath: БРАУЗЕР },
  ПРОКСИ ? { proxy: { server: ПРОКСИ } } : {}));
const стр = await бр.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const беды = [];
стр.on("pageerror", (e) => беды.push("ИСКЛ " + e.message.slice(0, 160)));

await стр.goto(АДРЕС, { waitUntil: "domcontentloaded", timeout: 60000 });
await стр.fill("#пароль", КЛЮЧ);
await стр.click("#войти");
await стр.waitForSelector("#полотно:not(.нет)", { timeout: 40000 });
/* Разделы площадок собираются после ответа сервера по каждой из них,
   и это несколько обращений подряд. Ждём появления первой плиты, а не
   отсчитываем секунды на глаз. */
await стр.waitForFunction(() => {
  const т = document.querySelector("#телоCdn");
  return т && т.querySelectorAll("h3").length > 0;
}, null, { timeout: 60000 }).catch(() => беды.push("раздел CDN не собрался за минуту"));

console.log("");
for (const [с, нужно] of Object.entries(ЖДЁМ)) {
  const ид = "#тело" + с.charAt(0).toUpperCase() + с.slice(1);
  const есть = await стр.$$eval(ид + " h3", (уз) => уз.map((у) => у.textContent.trim()));
  const нет = нужно.filter((н) => !есть.some((е) => е.indexOf(н) === 0));
  console.log(`  ${с}: плит ${есть.length}` + (нет.length ? `, НЕ ХВАТАЕТ: ${нет.join(", ")}` : ""));
  if (нет.length) беды.push(`${с}: нет плит - ${нет.join(", ")}`);
  /* Пустой раздел это не «мало данных», а несобранная страница: плиты
     рисуются всегда, числа в них могут быть нулями. */
  if (!есть.length) беды.push(`${с}: раздел пустой`);
}

/* Кнопка «Открыть список» обязана и переключить раздел, и поставить
   фильтр. Переход без фильтра это не переход, а начало поиска. */
/* Раздел площадки надо СНАЧАЛА открыть: закрытые стоят с display:none,
   и нажатие по спрятанной кнопке ждёт её появления до предела времени.
   Первый заход этой проверки ровно так и «не нашёл кнопку», хотя она
   стояла на месте.

   Пункт меню при этом на телефоне лежит в выезжающей шторе, за краем
   экрана, и нажатие по нему упирается в то же самое. Весь код панели
   завёрнут в замыкание, снаружи её функций нет, поэтому дёргаем сам
   обработчик: это тот же путь, каким идёт палец, только без ожидания
   выезда шторы. */
await стр.evaluate(() => document.querySelector('.пункт[data-р="vpn"]').click());
await стр.waitForTimeout(500);
await стр.evaluate(() => {
  const к = document.querySelector("#телоVpn [data-кЗаявкам]");
  if (!к) throw new Error("нет кнопки");
  к.click();
}).catch(() => беды.push("нет кнопки к заявкам у VPN"));
await стр.waitForTimeout(600);
const ушли = await стр.evaluate(() => {
  const р = document.querySelector('.раздел.вкл');
  const ф = document.querySelector('#фильтрЗаявок button[data-ф="vpn"]');
  return { раздел: р ? р.getAttribute("data-р") : "", фильтрВидим: !!ф,
           подсвечен: ф ? /border-color/.test(ф.getAttribute("style") || "") : false };
});
console.log(`  кнопка к заявкам: раздел «${ушли.раздел}», фильтр VPN подсвечен ${ушли.подсвечен}`);
if (ушли.раздел !== "заявки") беды.push("кнопка к заявкам не открыла раздел заявок");
if (!ушли.подсвечен) беды.push("кнопка к заявкам не поставила фильтр площадки");

if (беды.length) {
  console.log("\nКРАСНОЕ:");
  for (const с of беды) console.log("   " + с);
} else {
  console.log("\nзелено: у каждой площадки свой полный раздел");
}
await бр.close();
process.exit(беды.length ? 1 : 0);
