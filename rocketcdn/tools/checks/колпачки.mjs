/* Колпачки пульта отвечают на руку.

   Что было. Клавиша это колпачок в нише, у него есть лицо, боковины и
   зазор посадки, и всё это честно строится перспективой от центра
   кадра. Но стоял он неподвижно: тела клавиш рисуются один раз и
   кэшируются, а нажатие показывалось только светом. В коде так и было
   написано - подсвет разгорается, «как будто колпачок ушёл в нишу».
   Как будто. Наведения не было вовсе: рука ехала по пульту, и пульт
   на неё никак не отзывался.

   Что проверяем. Берём одну клавишу и снимаем её в трёх состояниях:
   покой, под указателем, нажата. Требуем три вещи.

   1. Свет растёт: покой тусклее наведения, наведение тусклее нажатия.
      Ровно в этом порядке и без равенств.
   2. Нажатие МЕНЯЕТ ГЕОМЕТРИЮ, а не только яркость: колпачок уходит в
      нишу, и его лицо становится мельче.

      Меряем это НЕ по снимку. Пробовали двумя мерами - долей
      изменившихся пикселей и смещением середины света, - и обе на
      старом коде, где колпачок стоял неподвижно, показали то же
      самое, что на новом: разгоревшийся свет перебивает движение
      предмета целиком. Поэтому спрашиваем сам слой через служебный
      ход `_пульт` и сравниваем площадь лица в покое и под нажатием.
   3. Зона нажатия НЕ ЕДЕТ вслед за колпачком. Цель под пальцем обязана
      стоять на месте, иначе нажатие сбивает собственную зону.

   Запуск: RC_URL=http://127.0.0.1:8123/?rcdbg=1 node tools/checks/колпачки.mjs
*/
import { АДРЕС, ПК, браузер, вПолёт } from "./общее.mjs";

/* Насколько обязан подрасти свет. Проценты, а не единицы яркости:
   плита у разных видов разной светимости. */
const ПРИРОСТ = 0.015;
/* На сколько обязано ужаться лицо колпачка при нажатии. Подъём падает
   с пяти сотых почти до нуля, лицо садится ближе к дну ниши, и его
   площадь заметно уменьшается. Порог с запасом: он ловит неподвижный
   колпачок, а не разницу в доли процента. */
const УЖАТИЕ = 0.02;
/* Насколько зона нажатия может уехать, точки. Ноль требовать нельзя:
   разметка ставит места в долях и округляет их до сотых. */
const УЕЗД = 1.5;

const беды = [];
const b = await браузер();
const { pg, ошибки } = await вПолёт(b, ПК);
await pg.waitForTimeout(2500);

const кнопки = await pg.$$(".rcf-phys-hit");
if (кнопки.length < 3) {
  беды.push(`клавиш на плите ${кнопки.length}: мерить нечего`);
} else {
  const цель = кнопки[2];
  const коробка = async () => await цель.boundingBox();

  /* Рамка снимка чуть шире клавиши: колпачок при нажатии уходит внутрь
     ниши, и её кромка обязана попасть в кадр. */
  const b0 = await коробка();
  const рамка = {
    x: Math.max(0, Math.round(b0.x - 6)), y: Math.max(0, Math.round(b0.y - 6)),
    width: Math.round(b0.width + 12), height: Math.round(b0.height + 12)
  };

  async function снять() {
    const b64 = (await pg.screenshot({ clip: рамка })).toString("base64");
    return await pg.evaluate(async (d) => {
      const im = new Image();
      im.src = "data:image/png;base64," + d;
      await im.decode();
      const c = document.createElement("canvas");
      c.width = im.width; c.height = im.height;
      const x = c.getContext("2d");
      x.drawImage(im, 0, 0);
      const p = x.getImageData(0, 0, c.width, c.height).data;
      let сумма = 0, всего = 0;
      for (let i = 0; i < p.length; i += 4) {
        сумма += (p[i] * 299 + p[i + 1] * 587 + p[i + 2] * 114) / 1000;
        всего++;
      }
      return { яркость: сумма / всего / 255 };
    }, b64);
  }

  /* Указатель уводим в угол: иначе он остаётся там, где его бросил
     предыдущий шаг, и «покой» окажется наведением. */
  /* Площади лиц ВСЕХ колпачков. По номеру одной клавиши спрашивать
     нельзя: порядок кнопок разметки и порядок мест на плите это два
     разных списка, и третья кнопка в разметке оказалась второй
     клавишей на плите. Берём все и смотрим, какая просела. */
  const площади = async () => await pg.evaluate(() => {
    const d = window.RC_FLIGHT && window.RC_FLIGHT._пульт && window.RC_FLIGHT._пульт();
    if (!d || !d["лицо"]) return null;
    const из = [];
    for (let i = 0; i < d["мест"](); i++) {
      const q = d["лицо"](i);
      if (!q) { из.push(null); continue; }
      /* Площадь четырёхугольника формулой шнурования: колпачок не
         прямоугольник, у него перспектива. */
      let s = 0;
      for (let k = 0; k < 4; k++) {
        const a = q[k], b = q[(k + 1) % 4];
        s += a.x * b.y - b.x * a.y;
      }
      из.push(Math.abs(s) / 2);
    }
    return из;
  });

  await pg.mouse.move(4, 4);
  await pg.waitForTimeout(600);
  const покой = await снять();
  const лицаПокой = await площади();
  const зонаПокой = await коробка();

  await цель.hover();
  await pg.waitForTimeout(600);
  const наведение = await снять();

  await pg.mouse.down();
  await pg.waitForTimeout(220);
  const нажатие = await снять();
  const лицаНажатие = await площади();
  const зонаНажатие = await коробка();
  await pg.mouse.up();

  console.log(`   яркость: покой ${(покой.яркость * 100).toFixed(2)}% · ` +
              `наведение ${(наведение.яркость * 100).toFixed(2)}% · ` +
              `нажатие ${(нажатие.яркость * 100).toFixed(2)}%`);

  if (наведение.яркость - покой.яркость < ПРИРОСТ) {
    беды.push(`наведение не читается: ${(покой.яркость * 100).toFixed(2)}% против ` +
              `${(наведение.яркость * 100).toFixed(2)}% при нужном приросте ` +
              `${(ПРИРОСТ * 100).toFixed(1)} процентного пункта`);
  }
  if (нажатие.яркость - наведение.яркость < ПРИРОСТ) {
    беды.push(`нажатие не отличается от наведения: ${(наведение.яркость * 100).toFixed(2)}% ` +
              `против ${(нажатие.яркость * 100).toFixed(2)}%`);
  }
  if (!лицаПокой || !лицаНажатие) {
    беды.push("слой пульта не отдал лица колпачков: проверить провал нечем");
  } else {
    const просели = [];
    for (let i = 0; i < лицаПокой.length; i++) {
      if (!лицаПокой[i] || !лицаНажатие[i]) continue;
      const у = 1 - лицаНажатие[i] / лицаПокой[i];
      if (у >= УЖАТИЕ) просели.push({ i, у });
    }
    const лучшая = просели.slice().sort((a, b2) => b2.у - a.у)[0];
    console.log(`   провалились колпачки: ` +
                (просели.length ? просели.map(п => `№${п.i} на ${(п.у * 100).toFixed(1)}%`).join(", ") : "ни один"));
    if (!лучшая) {
      беды.push("ни один колпачок не ужался при нажатии: провала нет, меняется только свет");
    }
    if (просели.length > 1) {
      беды.push(`при нажатии одной клавиши провалились ${просели.length}: ` +
                "нажатие обязано быть у той, на которую нажали");
    }
  }
  const уехала = Math.max(Math.abs(зонаПокой.x - зонаНажатие.x),
                          Math.abs(зонаПокой.y - зонаНажатие.y),
                          Math.abs(зонаПокой.width - зонаНажатие.width),
                          Math.abs(зонаПокой.height - зонаНажатие.height));
  console.log(`   зона нажатия сдвинулась на ${уехала.toFixed(2)} точки`);
  if (уехала > УЕЗД) {
    беды.push(`зона нажатия уехала на ${уехала.toFixed(2)} точки вслед за колпачком: ` +
              `цель под пальцем обязана стоять`);
  }
}

if (ошибки.length) беды.push("ошибки в консоли: " + ошибки.slice(0, 3).join(" | "));

await b.close();

if (беды.length) {
  console.log("ГРЯЗНО  колпачки пульта");
  for (const б of беды) console.log("   " + б);
  process.exit(1);
}
console.log("ЧИСТО  колпачки отвечают на руку: свет, провал, зона на месте");
