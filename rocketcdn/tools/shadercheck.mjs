/* Сторож кириллицы в шейдерах.
   GLSL принимает только латиницу в именах. Кириллическая переменная
   внутри строки шейдера ломает компиляцию МОЛЧА: экран становится
   чёрным, в консоли VALIDATE_STATUS false, и найти это можно только
   разглядывая кадр. За время работы над проектом это случалось трижды,
   поэтому проверка встроена в предстартовую и запускается перед
   каждой выкладкой. */
import fs from 'fs';
import path from 'path';

const КАТАЛОГ = 'assets';
/* Слова, по которым строка опознаётся как кусок шейдера. */
const ПРИЗНАК = /\b(gl_FragColor|gl_Position|gl_PointSize|gl_PointCoord|varying|attribute|uniform|precision|vec2|vec3|vec4|mat3|mat4|sampler2D|float |void main)\b/;
const КИРИЛЛИЦА = /[а-яА-ЯёЁ]/;

let плохих = 0, файлов = 0;
for (const имя of fs.readdirSync(КАТАЛОГ)) {
  if (!имя.endsWith('.js')) continue;
  const путь = path.join(КАТАЛОГ, имя);
  const строки = fs.readFileSync(путь, 'utf8').split('\n');
  файлов++;
  строки.forEach((стр, i) => {
    /* Смотрим только содержимое строковых литералов: комментарии
       по-русски это норма проекта и трогать их нельзя. */
    const литералы = стр.match(/"([^"\\]|\\.)*"|'([^'\\]|\\.)*'/g);
    if (!литералы) return;
    for (const л of литералы) {
      if (!ПРИЗНАК.test(л)) continue;
      if (!КИРИЛЛИЦА.test(л)) continue;
      плохих++;
      console.log(`КИРИЛЛИЦА В ШЕЙДЕРЕ  ${путь}:${i + 1}`);
      console.log(`   ${л.trim().slice(0, 100)}`);
    }
  });
}
/* ── ВТОРОЕ ОБЪЯВЛЕНИЕ ОДНОГО ИМЕНИ В ОДНОМ main() ──────────────
   Правило написано 11.09.2026 ценой шейдера дома на соседнем сайте.
   Блок разброса цвета переписывался туда из другого шейдера, и вместе
   с кодом приехало имя, которое в этом же main уже было занято под
   другой тип. GLSL такую программу не собирает вовсе: материал молча
   перестаёт рисоваться, и в консоли при этом пусто. Проверка искала
   только кириллицу, то есть ровно один из двух способов не собрать
   шейдер.

   Считаем объявления ВЕРХНЕГО УРОВНЯ в теле main: строка литерала
   вида `  тип имя =` с отступом ровно в два пробела. Вложенные блоки
   (там отступ больше) не трогаем: у них своя область видимости, и
   повтор имени в них законен. */
for (const имя of fs.readdirSync(КАТАЛОГ)) {
  if (!имя.endsWith('.js')) continue;
  const путь = path.join(КАТАЛОГ, имя);
  const строки = fs.readFileSync(путь, 'utf8').split('\n');
  let вMain = false;
  let вКомм = false;
  const имена = new Map();
  строки.forEach((стр, i) => {
    const м = стр.match(/^\s*"((?:[^"\\]|\\.)*)"\s*,?\s*$/);
    if (!м) {
      /* ── РАЗНЫЕ ВЕТКИ ЭТО РАЗНЫЕ ШЕЙДЕРЫ ────────────────────────
         Первый заход этой проверки поднял ложную тревогу на
         rc-planets.js: там `float rcNdl` объявлен дважды, но в РАЗНЫХ
         ветках `if/else` обычного JS - в собранную программу попадает
         ровно одна. Проверка читает исходник построчно и про ветки не
         знает, поэтому договариваемся так: подряд идущие строковые
         литералы это один кусок шейдера, а живая строка кода между
         ними (закрытая скобка, else, присваивание) кусок обрывает и
         сбрасывает счёт имён. Комментарии и пустые строки не в счёт:
         они внутри куска встречаются постоянно, и та настоящая
         поломка, ради которой проверка написана, лежала как раз через
         комментарий. */
      /* Комментарий кусок НЕ обрывает, и различать их надо по
         состоянию, а не по первому знаку строки: у многострочного
         разбора середина начинается обычным словом, а кончается
         знаком закрытия, и по первому знаку она читалась бы живым
         кодом. Через такой разбор как раз и лежала та поломка, ради
         которой проверка написана. */
      const г = стр.trim();
      if (вКомм) { if (г.indexOf("*" + "/") >= 0) вКомм = false; return; }
      if (г.startsWith("//") || !г) return;
      if (г.startsWith("/" + "*")) { if (г.indexOf("*" + "/") < 0) вКомм = true; return; }
      имена.clear();
      return;
    }
    const тело = м[1];
    if (/^\s*void\s+main\s*\(/.test(тело)) { имена.clear(); вMain = true; return; }
    if (!вMain) return;
    const о = тело.match(/^  (float|vec2|vec3|vec4|int|bool|mat2|mat3|mat4)\s+([A-Za-z_][A-Za-z0-9_]*)\s*(=|;)/);
    if (!о) return;
    if (имена.has(о[2])) {
      плохих++;
      console.log(`ДВА ОБЪЯВЛЕНИЯ ОДНОГО ИМЕНИ  ${путь}:${i + 1}`);
      console.log(`   «${о[2]}» уже объявлено на строке ${имена.get(о[2])} в этом же main`);
    } else {
      имена.set(о[2], i + 1);
    }
  });
}

if (плохих) {
  console.log(`\nнайдено ${плохих} строк. GLSL их не примет, экран станет чёрным.`);
  process.exit(1);
}
console.log(`шейдеры чисты: проверено ${файлов} файлов`);
