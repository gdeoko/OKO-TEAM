/* Возвращается ли камера в ту же точку, если долистать обратно.

   ЗАЧЕМ. Проверка полёта докладывает расхождение до девяноста шести
   единиц: те же доли ленты, пройденные вниз и вверх, дают разные места
   камеры. Звучит как настоящая беда - человек листает назад и попадает
   не туда, откуда пришёл.

   Но с тех пор камера получила сглаживание прокрутки igloo (две
   подтяжки, 0.075 и 0.15): она ДОГОНЯЕТ заданную долю, а не прыгает на
   неё. Замер через фиксированную паузу на такой камере меряет не место,
   а недоезд, и недоезд этот всегда направлен в сторону, откуда пришли.

   ── ПОЧЕМУ НЕ «ПОДОЖДАТЬ, ПОКА КАМЕРА ВСТАНЕТ» ──────────────────
   Первая редакция ждала тишины: пять кадров без движения. Она не
   умеет отличить «доехала и встала» от «ещё не тронулась», и на
   первом же прогоне выдала три доли подряд с одинаковой точкой -
   камера просто не успела стартовать за пять медленных кадров.

   Сравнивать проходы между собой тоже мало: два прохода могут
   разойтись и потому, что один из них не доехал.

   Спрашиваем ЭТАЛОН. У ядра есть `проба(y)` - чистая функция, которая
   считает позу камеры для любой прокрутки, ничего не помня и ничего не
   сглаживая. Значит правильное место для доли известно ТОЧНО. Ждём,
   пока живая камера сойдётся с пробой, и меряем расхождение с ней же.
   Тогда «не доехал» и «приехал не туда» перестают быть одним числом.

   Запуск: node tools/обратимость.mjs */
import { chromium } from "playwright";

const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const ДОЛИ = [0.0, 0.2, 0.4, 0.5, 0.6, 0.8, 1.0];

const бр = await chromium.launch({
  executablePath: process.env.RV_CHROME || "/opt/pw-browsers/chromium-1234/chrome-linux64/chrome",
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"]
});
const стр = await бр.newPage({ viewport: { width: 1440, height: 900 } });
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 90000 });
await стр.waitForFunction(
  () => window.RV_WORLD && window.RV_WORLD["вступлениеИдёт"] && !window.RV_WORLD["вступлениеИдёт"](),
  null, { timeout: 240000 }).catch(() => {});

async function встать(доля) {
  await стр.evaluate((д) => {
    const h = document.documentElement.scrollHeight - innerHeight;
    window.__цельY = Math.round(h * д);
    scrollTo(0, window.__цельY);
  }, доля);
  /* Ждём, пока живая камера СОЙДЁТСЯ С ПРОБОЙ для этой прокрутки.
     Сглаживание догоняет долю за несколько десятков кадров, и на
     программном отрисовщике это секунды. */
  const сошлась = await стр.waitForFunction(() => {
    const W = window.RV_WORLD;
    const п = W["проба"](window.__цельY);
    if (!п || !п["камера"]) return false;
    const э = п["камера"];
    const c = W["мир"]().cam;
    const d = Math.hypot(c.position.x - э[0], c.position.y - э[1], c.position.z - э[2]);
    window.__зазор = d;
    return d < 0.35;
  }, null, { timeout: 45000, polling: 150 }).then(() => true).catch(() => false);
  return стр.evaluate(([сош]) => {
    const W = window.RV_WORLD;
    const c = W["мир"]().cam;
    const п = W["проба"](window.__цельY);
    return {
      x: c.position.x, y: c.position.y, z: c.position.z,
      эx: п && п["камера"] ? п["камера"][0] : null,
      эy: п && п["камера"] ? п["камера"][1] : null,
      эz: п && п["камера"] ? п["камера"][2] : null,
      зазор: window.__зазор == null ? -1 : window.__зазор,
      сошлась: сош
    };
  }, [сошлась]);
}

const вниз = {};
for (const д of ДОЛИ) вниз[д] = await встать(д);
const вверх = {};
for (const д of [...ДОЛИ].reverse()) вверх[д] = await встать(д);

console.log("доля    эталон (проба) x,y,z      вниз зазор  вверх зазор  между проходами");
let худшийЗазор = 0, худшееМежду = 0, недоехали = 0;
for (const д of ДОЛИ) {
  const a = вниз[д], b = вверх[д];
  const между = Math.hypot(a.x - b.x, a.y - b.y, a.z - b.z);
  if (между > худшееМежду) худшееМежду = между;
  const з = Math.max(a.зазор, b.зазор);
  if (з > худшийЗазор) худшийЗазор = з;
  if (!a.сошлась || !b.сошлась) недоехали++;
  console.log(
    д.toFixed(2).padEnd(7),
    ((a.эx == null ? "?" : a.эx.toFixed(1)) + "," +
     (a.эy == null ? "?" : a.эy.toFixed(1)) + "," +
     (a.эz == null ? "?" : a.эz.toFixed(1))).padEnd(26),
    (a.зазор.toFixed(2) + (a.сошлась ? "" : " НЕ ДОЕХАЛ")).padStart(11),
    (b.зазор.toFixed(2) + (b.сошлась ? "" : " НЕ ДОЕХАЛ")).padStart(12),
    между.toFixed(2).padStart(16));
}
console.log(`\nхудший зазор до эталона: ${худшийЗазор.toFixed(2)} · ` +
            `худшее между проходами: ${худшееМежду.toFixed(2)} · не доехали: ${недоехали}`);
console.log(недоехали === 0 && худшееМежду < 1
  ? "ход ОБРАТИМ: с обеих сторон камера садится в точку эталона"
  : (недоехали > 0
    ? "камера не сошлась с эталоном на " + недоехали + " долях: место зависит от того, откуда пришли"
    : "ход НЕ обратим: проходы расходятся при сошедшемся эталоне"));
await бр.close();
