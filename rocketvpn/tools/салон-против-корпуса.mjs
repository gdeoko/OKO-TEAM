/* САЛОН И КОРПУС: ОДНОГО ЛИ ОНИ РАЗМЕРА.

   ЗАЧЕМ. Владелец: «в открытых дверях видно кашу в салоне салон не тот
   что внутри. Захожу и меняется что-то и снова панель вначале была
   близко панель потом снова далеко странно».

   Перебор гашением в проёме назвал виновника числом: гашение узла
   «чужой корабль» меняет 82.6 процента точек проёма. А снимок показал,
   ЧТО это значит: под этим узлом лежит ВЕСЬ КОРПУС ракеты, и когда он
   уходит, в кадре остаётся крошечная коробка размером сто шестьдесят на
   сто двадцать точек экрана. Эта коробка и есть салон.

   То есть салон меньше корпуса, в который вставлен, и сквозь проём люка
   человек видит его СНАРУЖИ: тёмную раму, бежевый настил и остекление с
   торца. Ни одно из этого не похоже на рубку, которая появляется после
   входа, - и не должно быть похоже, это вид с другой стороны.

   ЧТО МЕРИМ. Мировые габариты трёх тел: корпус снаружи, салон и пульт.
   Плюс радиус обшивки, который отдаёт сам модуль финала. Если салон
   меньше внутреннего объёма корпуса, числа скажут это прямо, и станет
   видно, во сколько раз.

   Запуск: node tools/салон-против-корпуса.mjs [пк|тел] [доля] */
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";

const КТО = process.argv[2] || "пк";
const ДОЛЯ = +(process.argv[3] || 0.50);
const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const экран = КТО === "пк" ? { width: 1440, height: 900 } : { width: 390, height: 844 };

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader",
         "--force-device-scale-factor=1"]
});
const кон = await бр.newContext({
  viewport: экран, deviceScaleFactor: 1,
  isMobile: КТО === "тел", hasTouch: КТО === "тел"
});
const стр = await кон.newPage();
стр.on("pageerror", (e) => console.log("ИСКЛ " + e.message.slice(0, 160)));
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 180000 });
await стр.waitForFunction(() => window.RV_WORLD && window.RV_WORLD["мир"] && window.RV_WORLD["мир"](),
                          null, { timeout: 300000 });
await стр.waitForTimeout(3000);
await стр.evaluate((д) => window.RV_MOTION["кПунктy"]("финал", д), ДОЛЯ);
await стр.waitForTimeout(3500);

const из = await стр.evaluate(() => {
  const W = window.RV_WORLD["мир"]();
  const T = W.T;
  function габарит(имя) {
    let узел = null;
    W.scene.traverse(function (о) { if (!узел && о.name === имя) узел = о; });
    if (!узел) return null;
    узел.updateMatrixWorld(true);
    const б = new T.Box3().setFromObject(узел);
    if (б.isEmpty()) return { имя: имя, пусто: true };
    const р = б.getSize(new T.Vector3());
    const ц = б.getCenter(new T.Vector3());
    const м = new T.Vector3();
    узел.getWorldScale(м);
    return {
      имя: имя,
      размер: [+р.x.toFixed(3), +р.y.toFixed(3), +р.z.toFixed(3)],
      центр: [+ц.x.toFixed(2), +ц.y.toFixed(2), +ц.z.toFixed(2)],
      масштаб: +м.x.toFixed(4),
      детей: узел.children.length
    };
  }
  const камера = W.cam.getWorldPosition(new T.Vector3());
  return {
    тела: ["чужой корабль", "снаружи", "салон", "борт", "финал"].map(габарит).filter(Boolean),
    камера: [+камера.x.toFixed(2), +камера.y.toFixed(2), +камера.z.toFixed(2)],
    рубка: (window.RV_ФИНАЛ && window.RV_ФИНАЛ["замерРубки"]) ? window.RV_ФИНАЛ["замерРубки"]() : null
  };
});
await бр.close();

console.log(`САЛОН ПРОТИВ КОРПУСА ${КТО} ${экран.width}x${экран.height}, финал доля ${ДОЛЯ}`);
console.log(`  камера в мире ${из.камера.join(", ")}`);
for (const т of из.тела) {
  if (т.пусто) { console.log(`  «${т.имя}»: пустой габарит (детей ${т.детей})`); continue; }
  console.log(`  «${т.имя}»: размер ${т.размер.join(" x ")}  центр ${т.центр.join(", ")}` +
              `  масштаб узла ${т.масштаб}  детей ${т.детей}`);
}
if (из.рубка) {
  console.log(`  из модуля финала: радиус обшивки ${из.рубка["радиусОбшивки"]}, ` +
              `высота глаза ${из.рубка["высотаГлаза"]}, дистанция панели ${из.рубка["дистанцияПанели"]}`);
  console.log(`  глаз над настилом ${из.рубка["глазНадНастилом"]}, ` +
              `глаз до стены панели ${из.рубка["глазДоСтеныПанели"]}`);
}

/* Приговор считаем, а не пересказываем: салон обязан заполнять корпус
   изнутри. Берём поперечник обоих и делим. */
const корпус = из.тела.filter((т) => т.имя === "снаружи" && !т.пусто)[0]
            || из.тела.filter((т) => т.имя === "чужой корабль" && !т.пусто)[0];
const салон = из.тела.filter((т) => т.имя === "салон" && !т.пусто)[0];
if (корпус && салон) {
  const пК = Math.max(корпус.размер[0], корпус.размер[2]);
  const пС = Math.max(салон.размер[0], салон.размер[2]);
  const доля = пС / пК;
  console.log(`  поперечник корпуса ${пК.toFixed(3)}, салона ${пС.toFixed(3)}, ` +
              `салон занимает ${(доля * 100).toFixed(1)}% ширины корпуса`);
  console.log(`  высота корпуса ${корпус.размер[1].toFixed(3)}, салона ${салон.размер[1].toFixed(3)}`);
  if (доля < 0.55) {
    console.log("  КРАСНОЕ  салон существенно меньше корпуса: сквозь проём люка");
    console.log("  человек видит его СНАРУЖИ, а не изнутри. Это и есть «каша в дверях»");
    console.log("  и «панель то близко, то далеко» - камера входит не в рубку,");
    console.log("  а в коробку внутри большого пустого корпуса.");
    process.exit(1);
  }
  console.log("  ок  салон заполняет корпус изнутри");
}
