/* РАЗЛЁТ КЛАДКИ СЧИТАЕТСЯ ПО КИРПИЧАМ В КАДРЕ, А НЕ НА ГЛАЗ.

   Владелец про стену: «должна вся стена разлететься также по
   кирпичикам как и собралась только эти кирпичики должны за пределы за
   рамки сайта во все стороны вылететь чтобы их видно не было вообще и
   потом обратно прилететь и собраться в тоннель». И сразу приговор
   тому, что есть: «просто дырка появляется и мы сквозь дырку
   пролетаем».

   Глазом это спорно: на снимке доли 0.30 кладки почти нет, и кажется,
   что улетела. Число отвечает точно. Здесь на каждой доле акта берётся
   КАЖДЫЙ кирпич кладки, его центр переводится в координаты экрана, и
   считается:

     · в кадре       - сколько кирпичей попало внутрь рамки экрана;
     · у стены       - сколько ещё стоит на своём месте (разлёт < 0.02);
     · середина      - средняя удалённость кирпича от центра кадра в
                       долях полуэкрана: единица это рамка, больше
                       единицы значит кладка ушла за край;
     · на трубе      - сколько уже притянуто к кольцам (сбор).

   Требование владельца выполнено, если между концом разлёта и началом
   сбора есть хотя бы одна доля, где «в кадре» это НОЛЬ.

   ВАЖНО, КАКОЙ АКТ СПРАШИВАТЬ. Разлёт случается на ПЕРИМЕТРЕ: там
   камера стоит, кладка видна целиком, и человек успевает увидеть, как
   она уходит. Прокол принимает стену уже почти снятой и добирает
   углы за первые сотые доли, дальше кирпичи летят обратно кольцами.
   Спрашивать надо оба, и требования к ним разные.

   Запуск: node tools/разлёт-кладки.mjs [пк|тел] [акт] [от] [до] [шаг] */
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";

const КТО = process.argv[2] || "пк";
const АКТ = process.argv[3] || "прокол";
const ОТ = +(process.argv[4] || 0.0);
const ДО = +(process.argv[5] || 0.72);
const ШАГ = +(process.argv[6] || 0.04);
const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const экран = КТО === "тел" ? { width: 390, height: 844 } : { width: 1440, height: 900 };

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader",
         "--force-device-scale-factor=1"]
});
const кон = await бр.newContext({
  viewport: экран, deviceScaleFactor: 1, isMobile: КТО === "тел", hasTouch: КТО === "тел"
});
const стр = await кон.newPage();
const беды = [];
стр.on("pageerror", (e) => беды.push(e.message.slice(0, 140)));
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 120000 });
await стр.waitForFunction(() => window.RV_WORLD && window.RV_WORLD["мир"] && window.RV_WORLD["мир"](),
                          null, { timeout: 300000 });
await стр.waitForTimeout(4000);

async function кадры(n) {
  await стр.evaluate((к) => new Promise((г) => {
    let i = 0; (function ш() { requestAnimationFrame(() => (++i >= к ? г() : ш())); })();
  }), n);
}

/* Разбор кладки идёт В СТРАНИЦЕ: матрицы экземпляров лежат в памяти
   сцены, вынимать их наружу незачем. Кирпич переводится в мировые
   координаты своим корнем, дальше камерой в нормальные координаты
   устройства, и уже там сравнивается с рамкой. */
async function кладка() {
  return await стр.evaluate(() => {
    const К = window.RV_КИРПИЧИ;
    if (!К || !К["корень"]) return { нет: "модуля кладки нет" };
    const корень = К["корень"]();
    const з = К["замер"] ? К["замер"]() : {};
    if (!корень || !з["собрано"]) return { нет: "кладка не собрана", замер: з };
    if (!корень.visible) return { видно: false, пробой: з["пробой"], целых: з["целых"] };
    const T = window.THREE;
    const мир = window.RV_WORLD["мир"]();
    const cam = мир && (мир.cam || мир.камера || мир.camera);
    if (!cam) return { нет: "камеры нет" };
    let меш = null;
    корень.traverse((о) => { if (!меш && о.isInstancedMesh) меш = о; });
    if (!меш) return { нет: "экземпляров нет" };
    корень.updateWorldMatrix(true, true);
    cam.updateMatrixWorld(true);
    const м = new T.Matrix4(), п = new T.Vector3();
    let вКадре = 0, уСтены = 0, сзади = 0, сумма = 0, n = 0;
    const raz = меш.geometry.getAttribute("aRaz");
    for (let i = 0; i < меш.count; i++) {
      меш.getMatrixAt(i, м);
      п.setFromMatrixPosition(м).applyMatrix4(меш.matrixWorld);
      п.project(cam);
      /* Кирпич за спиной камеры или за дальней плоскостью в кадре не
         виден вовсе, как бы близко к середине он ни проецировался. */
      const за = п.z > 1 || п.z < -1;
      if (за) сзади++;
      /* Удалённость от середины кадра в долях полуэкрана: рамка это
         единица по обеим осям, поэтому берём большую из двух. */
      const д = Math.max(Math.abs(п.x), Math.abs(п.y));
      if (!за) { сумма += д; n++; if (д <= 1) вКадре++; }
      if (raz && raz.array[i] < 0.02) уСтены++;
    }
    return {
      видно: true, всего: меш.count, вКадре, уСтены, сзади,
      середина: n ? +(сумма / n).toFixed(2) : null,
      пробой: з["пробой"],
    };
  });
}

const строки = [];
for (let д = ОТ; д <= ДО + 1e-9; д += ШАГ) {
  await стр.evaluate(([и, x]) => window.RV_MOTION["кПунктy"](и, x), [АКТ, +д.toFixed(3)]);
  await кадры(8);
  строки.push({ доля: +д.toFixed(3), ...(await кладка()) });
}

console.log(`РАЗЛЁТ КЛАДКИ ${КТО} ${экран.width}x${экран.height}, акт «${АКТ}»`);
console.log("  доля   пробой  всего  в кадре  у стены  середина");
for (const с of строки) {
  if (с.нет) { console.log(`  ${с.доля.toFixed(2)}   ${с.нет}`); continue; }
  if (!с.видно) { console.log(`  ${с.доля.toFixed(2)}   кладка скрыта`); continue; }
  const полоса = "#".repeat(Math.min(40, Math.round(с.вКадре / Math.max(1, с.всего) * 40)));
  console.log(`  ${с.доля.toFixed(2)}   ${String(с.пробой).padStart(6)}  ${String(с.всего).padStart(5)}` +
              `  ${String(с.вКадре).padStart(7)}  ${String(с.уСтены).padStart(7)}` +
              `  ${String(с.середина).padStart(8)}  ${полоса}`);
}

/* Вердикт. Нужна хотя бы одна доля, где кладки в кадре нет вовсе, и
   она обязана лежать МЕЖДУ концом разлёта и сбором в кольца. */
const видимые = строки.filter((с) => с.видно);
const пусто = видимые.filter((с) => с.вКадре === 0);
const беды2 = [];
if (!видимые.length) беды2.push("кладка ни на одной доле не видна");
else {
  const первая = видимые[0];
  /* Требование к началу отрезка своё у каждого акта. Периметр обязан
     начинаться ЦЕЛОЙ стеной: это единственное место, где человек видит
     её стоящей и где разлёт ему показывают. Прокол принимает её уже
     снятой, и целых кирпичей там законно нет. */
  if (АКТ === "периметр" && первая.уСтены < первая.всего * 0.9) {
    беды2.push(`периметр начинается с уже разбитой стены: целых ${первая.уСтены} из ${первая.всего}`);
  }
  if (АКТ === "периметр" && первая.вКадре < 4) {
    беды2.push(`стену в начале периметра почти не видно: в кадре ${первая.вКадре} из ${первая.всего}`);
  }
  if (!пусто.length) {
    const мин = видимые.reduce((а, б) => (б.вКадре < а.вКадре ? б : а));
    беды2.push(`кладка НИ РАЗУ не уходит из кадра целиком: меньше всего ` +
               `${мин.вКадре} из ${мин.всего} на доле ${мин.доля}`);
  } else {
    console.log(`  пусто на долях: ${пусто.map((с) => с.доля.toFixed(2)).join(", ")}`);
  }
}
if (беды.length) беды2.push("исключения: " + беды.slice(0, 2).join(" | "));
if (беды2.length) {
  console.log("ГРЯЗНО  разлёт кладки");
  for (const б of беды2) console.log("   " + б);
} else {
  console.log("ЧИСТО  стена уходит из кадра целиком и возвращается кольцами");
}
await бр.close();
