<?php
/* Роутер стенда Rocket VPN. Нужен, чтобы гонять проверки локально.

   Створ (index.php) это ЕДИНСТВЕННЫЙ вход на боевом, и запуск стенда
   как `php -S ... index.php` повторяет боевое поведение только на
   первый взгляд: встроенный сервер тогда шлёт через створ ВСЁ, включая
   стили, скрипты и модели. Браузер получает на месте `rv-track.js`
   страницу HTML, спотыкается на первом же `<` и валит в консоль
   «Unexpected token '<'». Проверка приёмки ловит эти три ошибки и
   краснеет, хотя на боевом статику отдаёт nginx и всё цело.

   Здесь: существующий файл отдаём как есть, остальное - через створ.
   Плёнку и створ наружу не отдаём, как и на боевом.

   Запуск:
     RV_SITE_SECRET=стенд RV_SITE_OPEN=1 RV_SITE_URL=/ \
       php -S 127.0.0.1:8170 tools/стенд.php
*/
/* Адрес приходит в процентах, а на диске имена кириллицей:
   `assets/rv-лист.js` в запросе выглядит как `rv-%D0%BB%D0%B8...`, и
   без раскодирования is_file его не узнаёт. Такой файл уходил через
   створ страницей HTML, браузер спотыкался на первом `<`, а проверка
   приёмки краснела тремя «Unexpected token '<'» на ровном месте. */
$п = rawurldecode((string)parse_url($_SERVER['REQUEST_URI'], PHP_URL_PATH));

/* Выход за корень закрываем до обращения к диску: стенд стендом, а
   привычка отдавать `../../` по запросу однажды переезжает в боевое. */
$корень = realpath(__DIR__ . '/..');
$ф = realpath($корень . $п);
$своё = $ф !== false && strpos($ф, $корень . DIRECTORY_SEPARATOR) === 0;

if ($п !== '/' && $своё && is_file($ф) && !preg_match('~/(frame|stvor)\.html$~', $п)) return false;
require __DIR__ . '/../index.php';
