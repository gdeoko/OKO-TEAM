/* ОДИН КОСМОС НА ВЕСЬ ФИЛЬМ.

   Владелец, второй раз подряд: «космос вначале не реалистичный, а потом
   его нету, а потом есть и тд», «оставь 1 вариант космоса - 1 вариант
   стены - 1 вариант дома - 1 вариант материала кирпичей - 1 ракету, и
   чтобы они ни от чего не менялись, не поменялись и тем более не
   накладывались».

   ЗАЧЕМ ОТДЕЛЬНАЯ ПРОВЕРКА. Небом на сайте распоряжаются три файла
   четырьмя разными способами: `RV_ЛУНА.нужна` (кто просит небо),
   `RV_ЛУНА.подземка` (запрет сверху), `RV_ФОН.сила` (оболочка
   подземелья, закрывающая небо собой) и видимость узлов сцены. Каждый
   сам по себе разумен, а вместе они дают то, что человек видит как «то
   есть, то нету».

   Держать это в голове нельзя, поэтому проверка проходит ВЕСЬ фильм по
   долям и на каждой печатает две вещи: что показывает кадр и что при
   этом думают признаки. Расхождение между ними и есть ответ.

   Судим по двум правилам:
     1. НЕБО НЕ ПРОПАДАЕТ ТАМ, ГДЕ ОНО ДОЛЖНО БЫТЬ. Наверху (станция,
        периметр) звёзды и Земля обязаны быть в кадре всегда. Под землёй
        (после прокола) их быть не должно - это не пропажа, а потолок
        над головой.
     2. НЕБО НЕ МЕНЯЕТСЯ САМО. Пока мы наверху, яркость и тон верхней
        части кадра держатся: два разных космоса подряд это ровно та
        жалоба, с которой всё началось.

   Запуск: node tools/космос-один.mjs [тел|пк]
*/
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";
import { mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";

const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const КТО = process.argv[2] || "тел";
const КУДА = "/tmp/космос";
const экран = КТО === "пк"
  ? { w: 1440, h: 900, dpr: 1, mob: false }
  : { w: 390, h: 844, dpr: 1, mob: true };

/* Наверху мы в станции и периметре целиком, и в проколе до того, как
   камера ушла под грунт. Дальше подземелье, и там неба нет по замыслу. */
const ПУТЬ = [
  ["станция", 0.10, "наверху"],
  ["станция", 0.50, "наверху"],
  ["станция", 0.90, "наверху"],
  ["периметр", 0.10, "наверху"],
  ["периметр", 0.50, "наверху"],
  ["периметр", 0.90, "наверху"],
  ["прокол", 0.10, "наверху"],
  ["прокол", 0.50, "под землёй"],
  ["прокол", 0.90, "под землёй"],
  ["финал", 0.20, "под землёй"],
  ["финал", 0.80, "под землёй"]
];

mkdirSync(КУДА, { recursive: true });

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"]
});
const стр = await бр.newPage({
  viewport: { width: экран.w, height: экран.h },
  deviceScaleFactor: экран.dpr, isMobile: экран.mob, hasTouch: экран.mob
});
const беды = [];
стр.on("pageerror", (e) => беды.push("ИСКЛ " + e.message.slice(0, 200)));

await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 90000 });
await стр.waitForFunction(
  () => window.RV_WORLD && window.RV_WORLD["вступлениеИдёт"] && !window.RV_WORLD["вступлениеИдёт"](),
  null, { timeout: 240000 }).catch(() => console.log("вступления не дождались"));
await стр.waitForTimeout(2000);

/* Небо меряем полосой НАД содержимым сцены: дом, стена и ракета стоят на
   грунте, то есть в нижних двух третях. Считаем яркость, разброс (по
   нему видно звёзды: ровная заливка разброса не даёт) и доли каналов. */
function небоВКадре(файл) {
  const из = execFileSync("python3", ["-c", `
import sys
from PIL import Image, ImageStat
im = Image.open(sys.argv[1]).convert("RGB")
w, h = im.size
k = im.crop((0, int(h*0.30), w, int(h*0.46)))
s = ImageStat.Stat(k)
то = list(k.getdata())
я = sorted(sum(p) for p in то)
p99 = я[len(я)*99//100] / 3.0
R, G, B = s.mean
с = max(1.0, R + G + B)
print(round((R+G+B)/3, 1), round(s.stddev[0], 1), round(p99, 1),
      round(R/с, 4), round(G/с, 4), round(B/с, 4))
`, файл], { encoding: "utf8" });
  const [я, раз, p99, r, g, b] = из.trim().split(/\s+/).map(Number);
  return { яркость: я, разброс: раз, ярчайшее: p99, r: r, g: g, b: b };
}

const ряд = [];
for (const [акт, доля, где] of ПУТЬ) {
  await стр.evaluate(([а, д]) => window.RV_MOTION["кПунктy"](а, д), [акт, доля]);
  let было = null, тихих = 0, кругов = 0;
  while (тихих < 3 && кругов < 60) {
    const п = await стр.evaluate(() => {
      const c = window.RV_WORLD["мир"]().cam.position;
      return [c.x, c.y, c.z];
    });
    if (было) {
      const d = Math.hypot(п[0] - было[0], п[1] - было[1], п[2] - было[2]);
      тихих = d < 0.02 ? тихих + 1 : 0;
    }
    было = п; кругов++;
    await стр.waitForTimeout(250);
  }
  await стр.waitForTimeout(1200);

  const признаки = await стр.evaluate(() => {
    const м = window.RV_WORLD["мир"]();
    let звёзды = false, земля = false;
    if (м && м.scene) м.scene.traverse(function (о) {
      const и = (о.name || "") + "";
      let в = о.visible, р = о.parent;
      while (в && р) { в = р.visible; р = р.parent; }
      if (/звёзд|звезд|небо|луна/i.test(и) && в) звёзды = true;
      if (/земл|планет/i.test(и) && в) земля = true;
    });
    let фон = null;
    try { фон = window.RV_ФОН && window.RV_ФОН["замер"] ? window.RV_ФОН["замер"]()["сила"] : null; } catch (e) {}
    return { звёзды: звёзды, земля: земля, фон: фон };
  });

  const файл = `${КУДА}/${КТО}-${акт}-${доля.toFixed(2)}.png`;
  await стр.screenshot({ path: файл });
  const н = небоВКадре(файл);
  ряд.push({ акт, доля, где, н, признаки });
  console.log(`  ${акт} ${доля.toFixed(2)} (${где}): яркость ${н.яркость}, разброс ${н.разброс}, ` +
              `тон ${н.r}/${н.g}/${н.b} | звёзды ${признаки.звёзды}, земля ${признаки.земля}, оболочка ${признаки.фон}`);
}

const итог = [];
const наверху = ряд.filter((з) => з.где === "наверху");

/* ── НАВЕРХУ НЕБО ЕСТЬ ВСЕГДА ───────────────────────────────────── */
for (const з of наверху) {
  if (!з.признаки.звёзды) итог.push(`${з.акт} ${з.доля}: звёзд нет, хотя мы наверху`);
  if (!з.признаки.земля) итог.push(`${з.акт} ${з.доля}: Земли нет, хотя мы наверху`);
  if (з.признаки.фон != null && з.признаки.фон > 0.05)
    итог.push(`${з.акт} ${з.доля}: оболочка подземелья поднята до ${з.признаки.фон} наверху`);
}

/* ── НЕБО НЕ МЕНЯЕТСЯ САМО ──────────────────────────────────────── */
if (наверху.length >= 2) {
  const тона = ["r", "g", "b"].map((к) => {
    const п = наверху.map((з) => з.н[к]);
    return { к, размах: Math.max(...п) - Math.min(...п), ряд: п };
  });
  const худ = тона.reduce((a, b) => (b.размах > a.размах ? b : a));
  const я = наверху.map((з) => з.н.яркость);
  console.log(`\n  наверху яркость неба: ${я.join(" -> ")}`);
  for (const т of тона) console.log(`  доля ${т.к}: ${т.ряд.join(" -> ")}  размах ${(т.размах * 100).toFixed(2)}%`);
  if (худ.размах * 100 > 2.0)
    итог.push(`тон неба гуляет на ${(худ.размах * 100).toFixed(2)}% по каналу ${худ.к}: два разных космоса`);
}

if (беды.length) итог.push("ошибки страницы: " + [...new Set(беды)].slice(0, 5).join(" | "));

if (итог.length) {
  console.log("\nКРАСНОЕ:");
  for (const с of итог) console.log("   " + с);
} else {
  console.log("\nзелено: космос один и на месте");
}
await бр.close();
process.exit(итог.length ? 1 : 0);
