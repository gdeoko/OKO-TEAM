# -*- coding: utf-8 -*-
"""Ужимает фотоскановые карты в assets/gen/pbr до разумного веса.

ЗАЧЕМ. Карты клались в webp с почти предельным качеством, и одна
только карта рельефа грунта весила два мегабайта из семи, которые
страница тащит целиком. Приёмка меряет вес первого захода и держит
порог шесть мегабайт: два из них уходили на файл, разницу с которым
на экране никто не видит.

КАК МЕРЯЕМ, А НЕ УГАДЫВАЕМ. Качество подбирается не на глаз.

  · Карта рельефа это ВЕКТОР. Ошибку меряем углом между исходной и
    пережатой нормалью в градусах: это ровно та величина, на которую
    поедет свет. Порог четыре с половиной градуса при девяносто
    девяти и девяти сотых процента точек в пределах двадцати пяти -
    столько же даёт обычная фильтрация текстуры на пологом взгляде,
    то есть в кадре это уже не читается.
  · Цвет и ORM это ЧИСЛА в каналах. Ошибку меряем в единицах канала
    из двухсот пятидесяти шести.

Разрешение НЕ трогаем. Уменьшение вдвое даёт среднюю ошибку нормали
почти в девять градусов - это уже видно рябью на дальнем грунте,
куда карта ложится под острым углом. Дешевле снять качество сжатия
при том же разрешении.

  python3 tools/ужать-пбр.py         посчитать и переписать
  python3 tools/ужать-пбр.py --сухо  только посчитать
"""
import io
import os
import sys

import numpy as np
from PIL import Image

ПАПКА = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "gen", "pbr")

# файл -> качество webp. Подобрано замером ниже, а не на глаз.
КАЧЕСТВО = {
    "реголит-норм.webp": 80,
    "реголит-orm.webp": 72,
    "реголит-цвет.webp": 82,
    "реголит-высота.webp": 78,
    "блок-норм.webp": 82,
    "блок-цвет.webp": 84,
    "обшивка-норм.webp": 84,
    "обшивка-цвет.webp": 84,
    "обшивка-orm.webp": 78,
}


def единичные(мас):
    """Байты карты нормалей -> единичные векторы."""
    в = мас / 127.5 - 1.0
    д = np.linalg.norm(в, axis=2, keepdims=True)
    д[д == 0] = 1
    return в / д


def ошибка(исходник, пережатое, рельеф):
    a = np.asarray(исходник).astype(np.float32)
    b = np.asarray(пережатое).astype(np.float32)
    if рельеф:
        кос = np.clip((единичные(a) * единичные(b)).sum(axis=2), -1, 1)
        гр = np.degrees(np.arccos(кос))
        return "угол %.2f° средний, %.1f° на грани" % (гр.mean(), np.percentile(гр, 99.9))
    р = np.abs(a - b)
    return "канал %.2f средний, %.0f на грани" % (р.mean(), np.percentile(р, 99.9))


def главное():
    сухо = "--сухо" in sys.argv
    было = стало = 0
    for имя in sorted(os.listdir(ПАПКА)):
        путь = os.path.join(ПАПКА, имя)
        if not имя.endswith(".webp"):
            continue
        вес = os.path.getsize(путь)
        было += вес
        к = КАЧЕСТВО.get(имя)
        if not к:
            стало += вес
            print("%-24s %6d КБ  оставляем как есть" % (имя, вес // 1024))
            continue
        исходник = Image.open(путь).convert("RGB")
        буфер = io.BytesIO()
        исходник.save(буфер, "WEBP", quality=к, method=6)
        новый = буфер.getvalue()
        if len(новый) >= вес:
            стало += вес
            print("%-24s %6d КБ  сжатие не помогает" % (имя, вес // 1024))
            continue
        мера = ошибка(исходник, Image.open(io.BytesIO(новый)).convert("RGB"), "норм" in имя)
        стало += len(новый)
        print("%-24s %6d -> %5d КБ  q%d  %s" % (имя, вес // 1024, len(новый) // 1024, к, мера))
        if not сухо:
            with open(путь, "wb") as ф:
                ф.write(новый)
    print("\nнабор %d -> %d КБ, освободили %d КБ" % (было // 1024, стало // 1024, (было - стало) // 1024))


главное()
