/* ПОДПИСЬ НЕ ДОЛЖНА ЛЕЖАТЬ ПОД ГЛЫБОЙ, И ЭТО СЧИТАЕТСЯ ЧИСЛОМ.

   На снимке владельца слово «открывается» закрыто ледяной плитой: у
   глыбы яркая кромка и плотное тело, и подпись под ней пропадает.
   Глазом такое ловится только на том устройстве, где совпало, а
   совпадает оно от поворота глыбы и ширины кадра.

   По строке идёт сетка точек, из каждой пускается луч от камеры, и
   считается доля точек, где первым телом на пути оказался лёд. Ноль
   означает, что текст виден весь. Порог стоит на двадцати сотых и
   объяснён у самой проверки.

   Запуск: node tools/подписи-и-глыбы.mjs [тел|пк] [доля-периметра] [проба]

   Третьим словом «проба» проверка проверяет САМА СЕБЯ: каждая глыба
   переносится ВПЕРЁД своей подписи, и замер обязан покраснеть. Нужно
   это потому, что мера здесь однажды поменяла смысл. Первый заход
   считал накрытие пересечением габаритных коробок, коробка косой глыбы
   наполовину пустая, и замер давал треть строки «под камнем» там, где
   текст лежит на чистой кладке. Луч эту ошибку убрал, но вместе с ней
   мог бы убрать и саму способность что-то поймать, а проверка, которая
   всегда зелёная, хуже её отсутствия. Проба отвечает на это числом:
   живой кадр 6 и 2 процента, проба 53 и 98. */
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";

const КТО = process.argv[2] || "тел";
const ДОЛЯ = +(process.argv[3] || 0.66);
const ПРОБА = process.argv[4] === "проба";
const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const экран = КТО === "тел" ? { width: 390, height: 844 } : { width: 1440, height: 900 };

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader",
         "--force-device-scale-factor=1"]
});
const кон = await бр.newContext({
  viewport: экран, deviceScaleFactor: 1, isMobile: КТО === "тел", hasTouch: КТО === "тел"
});
const стр = await кон.newPage();
стр.on("pageerror", (e) => console.log("ИСКЛ " + e.message.slice(0, 140)));
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 120000 });
await стр.waitForFunction(() => window.RV_WORLD && window.RV_WORLD["мир"] && window.RV_WORLD["мир"](),
                          null, { timeout: 300000 });
await стр.waitForTimeout(4000);
await стр.evaluate((д) => window.RV_MOTION["кПунктy"]("периметр", д), ДОЛЯ);
await стр.evaluate(() => new Promise((г) => {
  let i = 0; (function ш() { requestAnimationFrame(() => (++i >= 20 ? г() : ш())); })();
}));

const из = await стр.evaluate((проба) => {
  const T = window.THREE, мир = window.RV_WORLD["мир"](), cam = мир.cam;
  /* ── САМОПРОБА ДВИГАЕТ ЛЁД, А НЕ ПОДПИСЬ ──────────────────────
     Первый заход пробы сажал подпись на глыбу и ждал красного, а замер
     отвечал нулём - и отвечал ВЕРНО. Подпись стоит на выноске, выноска
     вынесена вперёд, и текст оказывался БЛИЖЕ льда к камере. Луч
     упирался в букву первой, то есть человек видел бы её целиком.
     Проба проверяла не ту беду.

     Беда была обратная и записана в шапке: ледяная плита встала ПЕРЕД
     словом «открывается» и закрыла его. Значит и проба обязана ставить
     лёд перед подписью: берём каждую глыбу и переносим её на середину
     ближайшей строки, придвинув к камере. */
  if (проба) {
    let к = cam; while (к.parent) к = к.parent;
    к.updateMatrixWorld(true);
    const строки = [];
    к.traverse((о) => {
      if (о.isMesh && (о.name || "").indexOf("текст: ") === 0 &&
          о.parent && о.parent.name === "выноска") строки.push(о);
    });
    const камера = cam.getWorldPosition(new T.Vector3());
    к.traverse((о) => {
      if (!о.isMesh || (о.name || "").indexOf("лёд:") !== 0) return;
      const м = о.getWorldPosition(new T.Vector3());
      let лучшая = null, ближе = 1e9;
      for (const с of строки) {
        const д = с.getWorldPosition(new T.Vector3()).distanceTo(м);
        if (д < ближе) { ближе = д; лучшая = с; }
      }
      if (!лучшая) return;
      /* Середина строки плюс четверть пути к камере: глыба заведомо
         впереди буквы, и луч обязан встретить сначала её. */
      const цель = лучшая.getWorldPosition(new T.Vector3());
      цель.lerp(камера, 0.25);
      о.parent.worldToLocal(цель);
      о.position.copy(цель);
    });
    к.updateMatrixWorld(true);
  }
  cam.updateMatrixWorld(true);
  let сцена = cam; while (сцена.parent) сцена = сцена.parent;
  сцена.updateMatrixWorld(true);
  const короб = new T.Box3(), п = new T.Vector3();
  function виден(о) { for (let у = о; у; у = у.parent) if (!у.visible) return false; return true; }
  /* Прямоугольник тела на экране в долях кадра. Считаем по углам его
     же габаритной коробки: точнее не нужно, а дешевле не бывает. */
  function рамка(о) {
    try { короб.setFromObject(о); } catch (e) { return null; }
    if (короб.isEmpty()) return null;
    let x0 = 9, x1 = -9, y0 = 9, y1 = -9, спереди = 0;
    for (let b = 0; b < 8; b++) {
      п.set(b & 1 ? короб.max.x : короб.min.x,
            b & 2 ? короб.max.y : короб.min.y,
            b & 4 ? короб.max.z : короб.min.z).project(cam);
      if (п.z > -1 && п.z < 1) спереди++;
      x0 = Math.min(x0, п.x); x1 = Math.max(x1, п.x);
      y0 = Math.min(y0, п.y); y1 = Math.max(y1, п.y);
    }
    return спереди ? { x0, x1, y0, y1 } : null;
  }
  const глыбы = [], подписи = [];
  сцена.traverse((о) => {
    if (!о.isMesh || !виден(о)) return;
    const имя = о.name || "";
    if (имя.indexOf("лёд:") === 0) {
      const р = рамка(о);
      if (р) глыбы.push({ имя, р });
    } else if (имя.indexOf("текст:") === 0 && о.parent &&
               о.parent.name === "выноска") {
      /* Берём ТОЛЬКО подписи глыб: заголовки акта живут у камеры и к
         камню отношения не имеют. */
      const р = рамка(о);
      if (р) подписи.push({ имя, р });
    }
  });
  /* ── СЧИТАЕМ ЛУЧОМ, А НЕ ПЕРЕСЕЧЕНИЕМ ПРЯМОУГОЛЬНИКОВ ──────────
     Первый заход считал накрытие по габаритным коробкам: попала точка
     строки в коробку глыбы - значит закрыта. Глыба стоит вполоборота и
     наклонена (rv-снаряды.js разворачивает её тангажом, рыском и
     креном), поэтому её коробка на экране это квадрат вокруг косого
     осколка, и добрая половина квадрата это пустой камень рядом.

     Замер и врал ровно на эту половину: снимок давал 30 процентов
     строки «под камнем» там, где глазом текст лежит на чистой кладке и
     читается целиком. По такому числу можно было либо поднять порог
     (то есть заглушить проверку), либо двигать подпись от беды,
     которой нет.

     Луч из камеры отвечает на тот самый вопрос, который и задавался:
     что человек увидит в этой точке экрана - букву или лёд. Берём
     первое, во что луч попал, и если это глыба, точка закрыта. */
  const луч = new T.Raycaster();
  const тела = [];
  сцена.traverse((о) => { if (о.isMesh && виден(о)) тела.push(о); });
  function подЛьдом(x, y) {
    луч.setFromCamera({ x, y }, cam);
    const п = луч.intersectObjects(тела, false);
    for (const т of п) {
      const имя = т.object.name || "";
      if (имя.indexOf("текст: ") === 0) return false;  /* буква впереди */
      if (имя.indexOf("лёд:") === 0) return true;      /* лёд впереди */
    }
    return false;
  }
  /* Доля подписи, накрытая глыбами. Считаем объединение накрытий сеткой
     по самой подписи: прямоугольники могут перекрываться между собой, и
     складывать их площади значило бы посчитать одно место дважды. */
  /* ── КВАД ГЛИФА ШИРЕ САМОЙ БУКВЫ ──────────────────────────────
     Габаритная коробка msdf-строки обводит КВАДЫ, а не буквы: в атласе
     ячейка шириной 33 при шаге набора 25 и высотой 57 при строке 55, то
     есть по бокам каждой буквы лежит запас в четверть её ширины, а сам
     знак внутри него уже. Меряя по коробке, проверка считала подпись
     закрытой там, где камень стоял в пустом поле между словами и краем
     строки, и кричала о четверти строки при читаемом тексте.

     Ужимаем коробку до настоящих букв: двенадцать сотых с каждой
     стороны по ширине и две сотых по высоте. Числа взяты из самого
     атласа, а не подобраны. */
  const свод = подписи.map((т0) => {
    const вш = (т0.р.x1 - т0.р.x0) * 0.12, вв = (т0.р.y1 - т0.р.y0) * 0.02;
    const т = { имя: т0.имя, р: { x0: т0.р.x0 + вш, x1: т0.р.x1 - вш,
                                  y0: т0.р.y0 + вв, y1: т0.р.y1 - вв } };
    const Ш = 40, В = 14;
    let накрыто = 0;
    for (let j = 0; j < В; j++) {
      for (let i = 0; i < Ш; i++) {
        const x = т.р.x0 + (т.р.x1 - т.р.x0) * ((i + 0.5) / Ш);
        const y = т.р.y0 + (т.р.y1 - т.р.y0) * ((j + 0.5) / В);
        if (подЛьдом(x, y)) накрыто++;
      }
    }
    return { подпись: т.имя.replace("текст: ", ""),
             доляПодНожом: +(накрыто / (Ш * В)).toFixed(3),
             рамка: [+т.р.x0.toFixed(2), +т.р.y0.toFixed(2), +т.р.x1.toFixed(2), +т.р.y1.toFixed(2)] };
  });
  return { глыб: глыбы.length, глыбы: глыбы.map((г) => ({
    имя: г.имя, рамка: [+г.р.x0.toFixed(2), +г.р.y0.toFixed(2), +г.р.x1.toFixed(2), +г.р.y1.toFixed(2)] })), свод };
}, ПРОБА);

console.log(`ПОДПИСИ И ГЛЫБЫ ${КТО} ${экран.width}x${экран.height}, периметр ${ДОЛЯ}` +
            (ПРОБА ? "  [САМОПРОБА: лёд поставлен перед подписями, ждём ГРЯЗНО]" : ""));
for (const г of из.глыбы) console.log(`  глыба ${г.имя.padEnd(16)} ${JSON.stringify(г.рамка)}`);
for (const с of из.свод) {
  console.log(`  подпись «${с.подпись}» ${JSON.stringify(с.рамка)}` +
              `  под камнем ${Math.round(с.доляПодНожом * 100)}%`);
}
/* ── ПОРОГ ПОСТАВЛЕН ПО ЗАМЕРУ, А НЕ ПО ДОГАДКЕ ──────────────────
   Проверка заводилась против НЕПРОЗРАЧНОГО тела на строке: пятый
   снаряд летел голой коробкой и закрывал слово «открывается»
   наглухо. Это она и обязана ловить.

   Числа под лучом другие, чем были под коробками, и порог пересчитан
   вместе с мерой. Живой кадр доли 0.66 на телефоне: «Никто не читает»
   0, «Сайт открывается целиком» 6 процентов, «Держит на белых
   списках» 2. Это край строки, задевающий просвечивающий угол льда, -
   на снимке текст читается целиком, проверено глазом.

   Самопроба (`проба` третьим словом) ставит лёд ПЕРЕД подписями и
   даёт 53 и 98 процентов. Значит между принятым состоянием и
   настоящей бедой лежит порядок величины, и порог может стоять где
   угодно между ними. Двадцать сотых оставлены прежними: запас втрое
   от нынешнего и вчетверо до беды.

   Двигать подписи ради этих процентов нельзя: в комментариях
   rv-снаряды.js записаны три круга правок, где подпись то уезжала за
   кромку кадра, то садилась на соседнюю глыбу, то на заголовок. */
const беды = из.свод.filter((с) => с.доляПодНожом > 0.20);
if (беды.length) {
  console.log(ПРОБА ? "САМОПРОБА ПРОЙДЕНА: подпись на глыбе замером поймана"
                    : "ГРЯЗНО  подпись под глыбой");
  for (const б of беды) {
    console.log(`   «${б.подпись}»: ${Math.round(б.доляПодНожом * 100)}% строки закрыто камнем`);
  }
  await бр.close();
  process.exit(ПРОБА ? 0 : 1);
}
if (ПРОБА) {
  console.log("САМОПРОБА ПРОВАЛЕНА: подписи сидят на глыбах, а замер их не видит");
  await бр.close();
  process.exit(1);
}
console.log("ЧИСТО  ни одна подпись не закрыта глыбой");
await бр.close();
