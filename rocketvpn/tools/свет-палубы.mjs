/* ОТЧЕГО СВЕТИТ ПАЛУБА В ФИНАЛЕ, И ЧТО ИЗ ЭТОГО ПОМОГАЕТ.

   ── ЧТО УЖЕ ИЗМЕРЕНО ──────────────────────────────────────────────
   Яркость низа кадра 64.1 у нас против 7.1 у соседа. Рама пульта при
   этом на обеих сторонах совпадает до четвёртого знака (доли кадра
   0.0129 / 0.0146 / 0.0931 / 0.2025), и это не совпадение: лицо пульта
   не геометрия, плоская рама считается в экранных координатах и от
   камеры не зависит вовсе. Значит рама не при чём, и расходится СВЕТ,
   который падает на настил.

   Перепись света (tools/рубки-рядом.mjs) назвала расхождение числом:

     VPN  6 ламп, сумма сил 8.449
     CDN  5 ламп, сумма сил 4.415

   Две причины видно прямо в переписи.

   ПЕРВАЯ. У нас есть направленное «солнце за окном» (0xfff0dc, сила
   2.2), у соседа направленного света в рубке нет ни одного. Заведено
   оно честно: без него у Земли не будет ночной стороны, карта огней
   горела бы и на дневной половине. Но у направленного света нет
   дальности, поэтому он светит и внутрь рубки - в коде это записано
   как «мягко подсвечивает раму изнутри», и вот это «мягко» при силе
   2.2 и есть залитый настил.

   ВТОРАЯ. Сосед ГАСИТ свет рубки к концу полёта, а мы нет:

     dim = (прогресс - 0.55) / 0.4
     hemi  = 1.45 * (1 - dim * 0.92)   ->  0.116
     ceilL = 1.35 * (1 - dim * 0.95)   ->  0.068
     warmL = 1.70 * (1 - dim * 0.95)   ->  0.085

   Числа сходятся с замером до третьего знака, то есть закон именно
   такой. У нас потолочная так и стоит на 1.85, как её собрал rc-cabin
   (файл рубки у сайтов байт в байт один, дело не в нём).

   ── ЧТО ПРОВЕРЯЕТ ЭТА ПРОБА ───────────────────────────────────────
   Прежде чем править, надо знать, что помогает. Проба меряет яркость
   низа кадра в четырёх состояниях:

     1. как есть;
     2. солнце отсечено СЛОЯМИ - светит только Земле;
     3. свет рубки погашен законом соседа;
     4. и то, и другое.

   Слои проверяются живьём намеренно. По памяти «свет освещает только
   объекты своего слоя» верно, но встроенный отрисовщик менял это
   поведение между версиями, а у нас three r152 своей сборкой. Ставить
   правку на знание, которое не проверено на НАШЕЙ сборке, значит
   получить в кадре тёмную Землю и искать причину заново.

   Запуск: node tools/свет-палубы.mjs [пк|тел] */
import { chromium } from "playwright";
import { execFileSync } from "node:child_process";
import { БРАУЗЕР } from "./браузер.mjs";

const КТО = process.argv[2] || "пк";
const ДОЛЯ = +(process.argv[3] || 0.99);
const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const экран = КТО === "пк" ? { width: 1440, height: 900 } : { width: 390, height: 844 };

/* Яркость полосы. Низ кадра это настил под рамой пульта: рама снизу
   занимает 0.2025 высоты, значит настил смотрит в полосу под ней.
   Земля меряется своей полосой в середине - иначе правка «отсечь
   солнце» выглядела бы улучшением, погасив заодно планету. */
/* ── МЕРКА ТА ЖЕ, ЧТО НАШЛА ДЕФЕКТ ───────────────────────────────
   Здесь стояла МЕДИАНА по последним двенадцати процентам высоты, и она
   давала 4 во всех четырёх состояниях, то есть не видела дефекта вовсе.
   Дефект нашла другая мерка: СРЕДНЯЯ по последним трём процентам
   (tools/полоса-во-времени.mjs, там 9 -> 78 -> 9). Медиана широкой
   полосы яркую узкую кромку не двигает по построению.

   Мерка обязана совпадать с той, которой беду нашли, иначе проба
   честно докладывает «чисто» о том, чего не мерила. */
function полосы(файл, h) {
  const низ0 = Math.round(h * 0.97), низ1 = h;
  const сер0 = Math.round(h * 0.30), сер1 = Math.round(h * 0.55);
  const из = execFileSync("python3", ["-c", `
import sys, statistics
from PIL import Image
im = Image.open(sys.argv[1]).convert("L")
w, h = im.size
def med(y0, y1):
    d = list(im.crop((0, y0, w, y1)).getdata())
    return round(sum(d) / len(d), 1), round(max(d), 1)
n = med(${низ0}, ${низ1})
s = med(${сер0}, ${сер1})
print(n[0], n[1], s[0], s[1])
`, файл], { encoding: "utf8" }).trim().split(/\s+/).map(Number);
  return { низ: из[0], низПик: из[1], середина: из[2], серПик: из[3] };
}

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader",
         "--force-device-scale-factor=1"]
});
const кон = await бр.newContext({
  viewport: экран, deviceScaleFactor: 1,
  isMobile: КТО === "тел", hasTouch: КТО === "тел"
});
const стр = await кон.newPage();
стр.on("pageerror", (e) => console.log("ИСКЛ " + e.message.slice(0, 140)));
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 120000 });
await стр.waitForFunction(() => window.RV_WORLD && window.RV_WORLD["мир"] && window.RV_WORLD["мир"](),
                          null, { timeout: 300000 });
await стр.waitForTimeout(3500);
/* ── МЕРИМ НА ПИКЕ ВСПЫШКИ, А НЕ ДО НЕЁ ───────────────────────────
   Первый заход снимал через тридцать кадров, то есть ДО подъёма, и
   писал «ни одно состояние не помогает». Полоса при приходе в финал
   идёт 9 -> 78 -> 9 за несколько секунд, поэтому состояния надо
   сравнивать на ОДНОЙ фазе: иначе разность состояний смешивается с
   разностью времени. Приходим прокруткой, как человек, и ждём пик тем
   же отсчётом, что у замера полосы. */
const место = await стр.evaluate(() => {
  const к = window.RV_WORLD["кривая"] ? window.RV_WORLD["кривая"]() : null;
  if (!к || !к["станции"]) return null;
  const ф = к["станции"].filter((с) => с["имя"] === "финал")[0];
  return ф ? Math.round(ф["верх"] + ф["ход"] * 0.99) : null;
});
if (место == null) {
  await стр.evaluate((д) => window.RV_MOTION["кПунктy"]("финал", д), ДОЛЯ);
} else {
  for (let i = 1; i <= 90; i++) {
    await стр.evaluate((y) => window.scrollTo(0, y), Math.round(место * (i / 90)));
    await стр.evaluate(() => new Promise((г) => {
      let k = 0; (function ш() { requestAnimationFrame(() => (++k >= 2 ? г() : ш())); })();
    }));
  }
}
await стр.evaluate(() => new Promise((г) => {
  let i = 0; (function ш() { requestAnimationFrame(() => (++i >= 60 ? г() : ш())); })();
}));
await стр.waitForTimeout(2000);
await стр.evaluate(() => new Promise((г) => {
  let i = 0; (function ш() { requestAnimationFrame(() => (++i >= 24 ? г() : ш())); })();
}));

/* Кладём в страницу переключатели. Ничего не собираем заново: только
   меняем силу уже стоящих ламп и слой уже стоящего солнца, поэтому
   каждое состояние снимается с того же кадра. */
await стр.evaluate(() => {
  const W = window.RV_WORLD["мир"]();
  const салон = (function () {
    let н = null;
    W.scene.traverse((о) => { if (!н && о.name === "салон") н = о; });
    return н;
  })();
  const лампы = [];
  const корень = салон || W.scene;
  корень.traverse((о) => { if (о.isLight) лампы.push(о); });
  window.__свет = {
    лампы: лампы,
    было: лампы.map((л) => ({ сила: л.intensity, маска: л.layers.mask })),
    солнце: лампы.filter((л) => л.isDirectionalLight),
    земли: []
  };
  /* Кто обязан остаться освещённым солнцем: Земля и её облака. Ищем по
     именам узлов модуля финала, а не по всему миру. */
  корень.traverse((о) => {
    if (!о.isMesh) return;
    const и = (о.name || "").toLowerCase();
    if (/земл|earth|облак|cloud/.test(и)) window.__свет.земли.push(о);
  });

  window.__солнцеСлоями = function (да) {
    const с = window.__свет;
    for (const л of с.солнце) {
      if (да) л.layers.set(2); else л.layers.mask = 1;
    }
    for (const о of с.земли) {
      if (да) о.layers.enable(2); else о.layers.mask = 1;
    }
  };
  window.__гаситьРубку = function (да) {
    const с = window.__свет;
    for (let i = 0; i < с.лампы.length; i++) {
      const л = с.лампы[i];
      if (л.isDirectionalLight) continue;
      /* Закон соседа при полном прогрессе: dim = 1. */
      if (!да) { л.intensity = с.было[i].сила; continue; }
      if (л.isHemisphereLight) л.intensity = 1.45 * (1 - 0.92);
      else л.intensity = с.было[i].сила * 0.05;
    }
  };
  window.__землиСколько = function () { return window.__свет.земли.length; };
  window.__лампСколько = function () { return window.__свет.лампы.length; };
});

const земель = await стр.evaluate(() => window.__землиСколько());
const ламп = await стр.evaluate(() => window.__лампСколько());

async function состояние(имя, солнце, гасить, файл) {
  await стр.evaluate(([с, г]) => {
    window.__солнцеСлоями(с);
    window.__гаситьРубку(г);
  }, [солнце, гасить]);
  /* Ровно два кадра: состояние снимается на той же фазе вспышки, а
     каждый лишний кадр уводит полосу вниз по кривой спада. */
  await стр.evaluate(() => new Promise((г) => {
    let i = 0; (function ш() { requestAnimationFrame(() => (++i >= 2 ? г() : ш())); })();
  }));
  await стр.screenshot({ path: файл });
  return Object.assign({ имя: имя }, полосы(файл, экран.height));
}

const свод = [];
свод.push(await состояние("как есть", false, false, "/tmp/свет-1.png"));
свод.push(await состояние("солнце слоями", true, false, "/tmp/свет-2.png"));
свод.push(await состояние("рубка погашена", false, true, "/tmp/свет-3.png"));
свод.push(await состояние("и то, и другое", true, true, "/tmp/свет-4.png"));
await бр.close();

console.log(`СВЕТ ПАЛУБЫ ${КТО} ${экран.width}x${экран.height}, финал доля ${ДОЛЯ}`);
console.log(`  ламп в салоне ${ламп}, узлов Земли найдено ${земель}`);
console.log("  состояние            низ кадра   пик низа   середина   пик середины");
for (const с of свод) {
  console.log(`  ${с.имя.padEnd(20)} ${String(с.низ).padEnd(11)} ${String(с.низПик).padEnd(10)}` +
              ` ${String(с.середина).padEnd(10)} ${с.серПик}`);
}
