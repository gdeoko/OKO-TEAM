# WebP: нормали чувствительны к артефактам сильнее всего, им качество выше.
КАЧЕСТВО = {"цвет": 84, "норм": 92, "orm": 86, "высота": 88}


def распаковать(zip_путь, куда):
    if os.path.isdir(куда):
        shutil.rmtree(куда)
    os.makedirs(куда, exist_ok=True)
    with zipfile.ZipFile(zip_путь) as z:
        for имя in z.namelist():
            if имя.lower().endswith((".jpg", ".jpeg", ".png")):
                z.extract(имя, куда)
    return куда


def найти(папка, хвост):
    """Карта ищется по хвосту имени: внутри набора имена стабильны."""
    for корень, _, файлы in os.walk(папка):
        for ф in файлы:
            if ф.lower().endswith(хвост.lower()):
                return os.path.join(корень, ф)
    return None


def открыть(путь, режим="RGB"):
    им = Image.open(путь)
    return им.convert(режим)


def подогнать(им, размер):
    if им.size != (размер, размер):
        им = им.resize((размер, размер), Image.LANCZOS)
    return им


def лунный(им, обесцветить, яркость, тепло):
    """Снятие пигмента и посадка альбедо. Работаем в float, чтобы не
       ловить ступеньки на восьми битах."""
    a = np.asarray(им, dtype=np.float32) / 255.0
    сер = (a[..., 0] * 0.2126 + a[..., 1] * 0.7152 + a[..., 2] * 0.0722)[..., None]
    a = a * (1.0 - обесцветить) + сер * обесцветить
    a = a * яркость
    a[..., 0] *= тепло
    a[..., 2] *= 2.0 - тепло
    return Image.fromarray(np.clip(a * 255.0, 0, 255).astype(np.uint8), "RGB")


def собрать_orm(ao_путь, rough_путь, металл, размер):
    """R = затенение, G = шероховатость, B = металл. Ровно glTF."""
    if ao_путь:
        ao = np.asarray(подогнать(открыть(ao_путь, "L"), размер), dtype=np.uint8)
    else:
        ao = np.full((размер, размер), 255, dtype=np.uint8)
    if rough_путь:
        rг = np.asarray(подогнать(открыть(rough_путь, "L"), размер), dtype=np.uint8)
    else:
        rг = np.full((размер, размер), 200, dtype=np.uint8)
    м = np.full((размер, размер), int(round(металл * 255)), dtype=np.uint8)
    return Image.fromarray(np.dstack([ao, rг, м]), "RGB")


def сделать(ключ, н):
    zip_путь = os.path.join(ИСХОД, ключ + ".zip")
    if not os.path.isfile(zip_путь):
        print("  пропуск, нет архива:", zip_путь)
        return []
    расп = распаковать(zip_путь, os.path.join(ИСХОД, "_расп", ключ))
    имя = н["имя"]
    сделано = []

    цв_путь = найти(расп, "_Color.jpg")
    if цв_путь:
        им = подогнать(открыть(цв_путь), н["цвет"])
        им = лунный(им, н["обесцветить"], н["яркость"], н["тепло"])
        п = os.path.join(ВЫХОД, f"{имя}-цвет.webp")
        им.save(п, "WEBP", quality=КАЧЕСТВО["цвет"], method=6)
        сделано.append(п)

    # NormalGL: зелёный канал направлен вверх, это соглашение OpenGL и
    # three.js. DX-вариант из того же архива дал бы вывернутый рельеф.
    н_путь = найти(расп, "_NormalGL.jpg") or найти(расп, "_Normal.jpg")
    if н_путь:
        им = подогнать(открыть(н_путь), н["норм"])
        п = os.path.join(ВЫХОД, f"{имя}-норм.webp")
        им.save(п, "WEBP", quality=КАЧЕСТВО["норм"], method=6)
        сделано.append(п)

    orm = собрать_orm(найти(расп, "_AmbientOcclusion.jpg"),
                      найти(расп, "_Roughness.jpg"),
                      н["металл"], н["orm"])
    п = os.path.join(ВЫХОД, f"{имя}-orm.webp")
    orm.save(п, "WEBP", quality=КАЧЕСТВО["orm"], method=6)
    сделано.append(п)

    if н["высота"]:
        в_путь = найти(расп, "_Displacement.jpg")
        if в_путь:
            им = подогнать(открыть(в_путь, "L"), н["высота"])
            п = os.path.join(ВЫХОД, f"{имя}-высота.webp")
            им.save(п, "WEBP", quality=КАЧЕСТВО["высота"], method=6)
            сделано.append(п)

    shutil.rmtree(расп, ignore_errors=True)
    return сделано


def главное():
    os.makedirs(ВЫХОД, exist_ok=True)
    всего = 0
    for ключ, н in НАБОРЫ.items():
        print(ключ, "->", н["имя"])
        for п in сделать(ключ, н):
            вес = os.path.getsize(п)
            всего += вес
            print(f"   {os.path.basename(п):24s} {вес/1024:8.0f} КБ")
    print(f"\nитого материалов: {всего/1024/1024:.2f} МБ")


if __name__ == "__main__":
    sys.exit(главное())
