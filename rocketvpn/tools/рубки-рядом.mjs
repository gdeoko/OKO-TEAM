/* ДВЕ РУБКИ ОДНОЙ МЕРКОЙ. Владелец: «почему не скопировать и вставить?»

   Салон у нас УЖЕ скопирован целиком - rc-cabin.js лежит в обоих
   сайтах одним файлом. Не скопирована камера, и не могла быть: у
   соседа рубка ставится ПОД камеру полёта, у нас камеру ведёт лента
   актов, а рубка стоит в мире. Один и тот же кадр приходится получать
   с двух сторон.

   Пока сверять было нечем, наш код повторял их формулы пересказом в
   комментариях. Пересказ разошёлся на четверть метра (щит у нас стоит
   не на обшивке), и это дало три круга подгонки по снимкам.

   Здесь обе стороны отвечают ОДНИМИ И ТЕМИ ЖЕ тремя числами, и каждое
   можно поправить формулой, а не подбором:

     · высота глаза над настилом;
     · расстояние от глаза до стены с панелью;
     · наклон взгляда.

   Числа местные, в единицах салона: узел финала у нас ужат, мировые
   единицы разные, а местные те же - салон собирает их же файл.

   Запуск: node tools/рубки-рядом.mjs [пк|тел] */
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";

const КТО = process.argv[2] || "пк";
const ДОЛЯ = +(process.argv[3] || 0.99);
const VPN = process.env.RV_URL || "http://127.0.0.1:8170";
const CDN = process.env.RC_URL || "http://127.0.0.1:8171";
const экран = КТО === "пк" ? { width: 1440, height: 900 } : { width: 390, height: 844 };

/* Пороги. Высота и дистанция в единицах салона (обшивка радиусом
   3.05), поэтому сотая доля это сантиметр с небольшим - глазом такое
   не читается, а вдвое больше уже сдвигает пульт в кадре. Наклон в
   градусах: полградуса при поле 72 это меньше процента высоты кадра. */
const ДОП_ВЫСОТА = 0.02;
const ДОП_ДИСТАНЦИЯ = 0.03;
const ДОП_НАКЛОН = 0.5;

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader",
         "--force-device-scale-factor=1"]
});

async function снять(адрес, готов, довести, читать) {
  const кон = await бр.newContext({
    viewport: экран, deviceScaleFactor: 1,
    isMobile: КТО === "тел", hasTouch: КТО === "тел"
  });
  const стр = await кон.newPage();
  стр.on("pageerror", (e) => console.log("  ИСКЛ " + e.message.slice(0, 120)));
  await стр.goto(адрес + "/", { waitUntil: "domcontentloaded", timeout: 120000 });
  await стр.waitForFunction(готов, null, { timeout: 300000 });
  await стр.waitForTimeout(3500);
  await довести(стр);
  const из = await стр.evaluate(читать);
  await кон.close();
  return из;
}

const впн = await снять(
  VPN,
  () => window.RV_WORLD && window.RV_WORLD["мир"] && window.RV_WORLD["мир"](),
  async (стр) => {
    await стр.evaluate((д) => window.RV_MOTION["кПунктy"]("финал", д), ДОЛЯ);
    await стр.evaluate(() => new Promise((г) => {
      let i = 0; (function ш() { requestAnimationFrame(() => (++i >= 20 ? г() : ш())); })();
    }));
  },
  () => (window.RV_ФИНАЛ && window.RV_ФИНАЛ["замерРубки"])
    ? window.RV_ФИНАЛ["замерРубки"]() : { нет: "нет замерРубки" }
);

const кдн = await снять(
  CDN,
  () => window.RC_GL && window.RC_GL.ready3d,
  async (стр) => {
    /* Досюда доезжаем прокруткой: финал у соседа это конец ленты. */
    const высота = await стр.evaluate(() =>
      Math.max(0, document.documentElement.scrollHeight - window.innerHeight));
    for (let i = 1; i <= 90; i++) {
      await стр.evaluate((y) => window.scrollTo(0, y), Math.round(высота * (i / 90)));
      await стр.evaluate(() => new Promise((г) => {
        let i = 0; (function ш() { requestAnimationFrame(() => (++i >= 2 ? г() : ш())); })();
      }));
    }
  },
  () => (window.RC_FLIGHT && window.RC_FLIGHT["замерРубки"])
    ? window.RC_FLIGHT["замерРубки"]() : { нет: "нет замерРубки" }
);

console.log(`РУБКИ РЯДОМ ${КТО} ${экран.width}x${экран.height}, VPN доля ${ДОЛЯ}`);
if (!впн || впн.нет || !кдн || кдн.нет) {
  console.log("  VPN: " + JSON.stringify(впн));
  console.log("  CDN: " + JSON.stringify(кдн));
  console.log("ГРЯЗНО  рубку не спросить");
  await бр.close();
  process.exit(1);
}

const беды = [];
function строка(имя, ключ, доп, ед) {
  const а = впн[ключ], б = кдн[ключ];
  const р = +(а - б).toFixed(4);
  const плохо = Math.abs(р) > доп;
  console.log(`  ${имя.padEnd(22)} VPN ${String(а).padEnd(9)} CDN ${String(б).padEnd(9)}` +
              ` разница ${(р > 0 ? "+" : "") + р}${ед}` + (плохо ? "  ← за порогом " + доп : ""));
  if (плохо) беды.push(`${имя}: ${а} против ${б}, разница ${р}${ед} при пороге ${доп}`);
}
строка("глаз над настилом", "глазНадНастилом", ДОП_ВЫСОТА, "");
строка("глаз до стены панели", "глазДоСтеныПанели", ДОП_ДИСТАНЦИЯ, "");
строка("наклон взгляда", "тангажГрадусов", ДОП_НАКЛОН, "°");
console.log(`  ${"поле объектива".padEnd(22)} VPN ${впн["поле"]}      CDN ${кдн["поле"]}`);
console.log(`  ${"радиус обшивки".padEnd(22)} VPN ${впн["радиусОбшивки"]}   CDN ${кдн["радиусОбшивки"]}`);

/* ── РАМА ПУЛЬТА И СВЕТ ПОД НЕЙ ─────────────────────────────────
   Первый заход мерил здесь мировой габарит пульта и с обеих сторон
   получил «коробка пуста». Это был ОТВЕТ, а не поломка: лицо пульта не
   геометрия вовсе, плоская рама считается в экранных координатах и
   кладётся обводкой поверх кадра (rc-panel.js, `flatBuild`).

   Отсюда два следствия, и оба меняют, что надо мерить.

   ПЕРВОЕ. Рама зависит только от размера кадра, поля зрения и паспорта
   раскладки, а от камеры не зависит. Значит в кадре она стоит одинаково
   ПО ПОСТРОЕНИЮ, и прежняя догадка «пульт у нас крупнее соседского на
   восемь процентов» мерила не пульт: так может выглядеть силуэт на
   снимке, в который попало что-то ещё. Доли кадра сверяем, но ждём
   совпадения - это проверка построения, а не поиск беды.

   ВТОРОЕ. Расходится то, что видно ПОД рамой: яркость низа кадра 64.1 у
   VPN против 7.1 у CDN. Рама одна, вырез один, значит в вырез смотрят
   разные вещи, и разница в СВЕТЕ на настиле. Его и переписываем целиком:
   вид, сила, цвет, место, включена ли. Лишняя лампа или лишняя сила
   видна сразу, без снимков и без подбора. */
const ДОП_ДОЛИ = 0.01;
if (впн["пультДоли"] && кдн["пультДоли"]) {
  for (const к of ["слева", "справа", "сверху", "снизу"]) {
    const а = впн["пультДоли"][к], б = кдн["пультДоли"][к];
    const р = +(а - б).toFixed(4);
    const плохо = Math.abs(р) > ДОП_ДОЛИ;
    console.log(`  ${("рама, " + к).padEnd(22)} VPN ${String(а).padEnd(9)} CDN ${String(б).padEnd(9)}` +
                ` разница ${(р > 0 ? "+" : "") + р}` + (плохо ? "  ← за порогом " + ДОП_ДОЛИ : ""));
    if (плохо) беды.push(`рама ${к}: ${а} против ${б}, разница ${р}`);
  }
} else {
  console.log(`  ${"рама пульта".padEnd(22)} VPN ${впн["пультНет"] || JSON.stringify(впн["пультДоли"])}` +
              `  ·  CDN ${кдн["пультНет"] || JSON.stringify(кдн["пультДоли"])}`);
  беды.push(`доли рамы не измерены: VPN ${впн["пультНет"] || "?"}, CDN ${кдн["пультНет"] || "?"}`);
}

/* ── ТОЧКИ РУБКИ НА ЭКРАНЕ ──────────────────────────────────────
   Самая прямая мерка из всех, что тут есть: одни и те же точки салона в
   его местных координатах, спроецированные живой камерой каждой
   стороны. Файл рубки у сайтов байт в байт один, значит и точки одни.

   Расходятся доли - расходится проекция, и сразу видно, на сколько и в
   какую сторону. Сходятся - значит рубка тут не при чём, и разницу в
   кадре делает то, что нарисовано поверх неё.

   Порог два процента кадра: меньше человек не различает, а четверть
   кадра, которую показали снимки, это двенадцать порогов. */
const ДОП_ТОЧКИ = 0.02;
if (впн["точкиРубки"] && кдн["точкиРубки"]) {
  for (const имя of Object.keys(впн["точкиРубки"])) {
    const а = впн["точкиРубки"][имя], б = кдн["точкиРубки"][имя];
    if (!а || !б) {
      console.log(`  ${("точка: " + имя).padEnd(22)} VPN ${JSON.stringify(а)} CDN ${JSON.stringify(б)}` +
                  "  (за камерой у одной из сторон)");
      continue;
    }
    const дx = +(а[0] - б[0]).toFixed(4), дy = +(а[1] - б[1]).toFixed(4);
    const плохо = Math.abs(дx) > ДОП_ТОЧКИ || Math.abs(дy) > ДОП_ТОЧКИ;
    console.log(`  ${("точка: " + имя).padEnd(22)} VPN ${JSON.stringify(а).padEnd(18)}` +
                ` CDN ${JSON.stringify(б).padEnd(18)} разница [${дx}, ${дy}]` +
                (плохо ? "  ← за порогом " + ДОП_ТОЧКИ : ""));
    if (плохо) беды.push(`точка «${имя}»: VPN ${JSON.stringify(а)} против CDN ${JSON.stringify(б)}`);
  }
} else {
  console.log("  точки рубки          не измерены: " +
              `VPN ${JSON.stringify(впн["точкиРубки"])}, CDN ${JSON.stringify(кдн["точкиРубки"])}`);
}

/* Свет печатаем полностью, а не сводим в одно число. Сумма сил ничего
   не скажет: одна лампа в упор на настил светит его сильнее, чем три
   слабых под потолком, и разницу видно только по месту. */
function лампыСтрокой(имя, список) {
  if (!список) { console.log(`  свет ${имя}: не измерен`); return; }
  const живые = список.filter((л) => л["видно"]);
  console.log(`  свет ${имя}: ламп ${список.length}, из них включено ${живые.length}`);
  for (const л of живые) {
    console.log(`    ${String(л["вид"]).padEnd(18)} сила ${String(л["сила"]).padEnd(7)}` +
                ` ${String(л["цвет"]).padEnd(8)} даль ${String(л["даль"]).padEnd(7)}` +
                ` где ${JSON.stringify(л["где"])}`);
  }
}
лампыСтрокой("VPN", впн["лампыРубки"]);
лампыСтрокой("CDN", кдн["лампыРубки"]);

/* Вердикт по свету: сверяем СУММУ СИЛ включённых ламп и их число.
   Порог по силе десятая доля: рубка собирается одним файлом, и лампы в
   ней обязаны быть те же. Расхождение здесь и есть ответ на палубу. */
if (впн["лампыРубки"] && кдн["лампыРубки"]) {
  const сумма = (л) => л.filter((x) => x["видно"]).reduce((s, x) => s + x["сила"], 0);
  const чис = (л) => л.filter((x) => x["видно"]).length;
  const сВ = +сумма(впн["лампыРубки"]).toFixed(3), сК = +сумма(кдн["лампыРубки"]).toFixed(3);
  const нВ = чис(впн["лампыРубки"]), нК = чис(кдн["лампыРубки"]);
  console.log(`  ${"свет, сумма сил".padEnd(22)} VPN ${String(сВ).padEnd(9)} CDN ${String(сК).padEnd(9)}` +
              ` разница ${+(сВ - сК).toFixed(3)}`);
  if (нВ !== нК) беды.push(`ламп в рубке разное число: VPN ${нВ}, CDN ${нК}`);
  if (Math.abs(сВ - сК) > 0.1) беды.push(`сумма сил света разошлась: VPN ${сВ}, CDN ${сК}`);
}

if (беды.length) {
  console.log("ГРЯЗНО  рубки стоят по-разному");
  for (const б of беды) console.log("   " + б);
  await бр.close();
  process.exit(1);
}
console.log("ЧИСТО  глаз стоит в рубке одинаково");
await бр.close();
