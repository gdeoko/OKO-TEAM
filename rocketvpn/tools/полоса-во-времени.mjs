/* ── ТРИ ПОЛОСЫ РАЗОМ: НИЗ, СЕРЕДИНА, ВЕСЬ КАДР ──────────────────
   Последняя развилка в этом поиске решается одним числом. Если горб
   виден только в НИЗУ, его рисует тело или слой внизу кадра. Если он
   идёт вместе с серединой и со всем кадром, дело в самом кадре:
   экспозиция и свечение с нулевым порогом (rv-ореол.js) красят всё
   разом, и искать предмет бессмысленно.

   Шесть предыдущих мерок дали мимо, и последние четыре по одной
   причине: я сравнивал разные МОМЕНТЫ ВРЕМЕНИ, думая, что сравниваю
   состояния. Здесь сравнения нет вовсе, только три числа с одного
   снимка, поэтому испортить нечего. */
function полоса(файл, h) {
  const низ0 = Math.round(h * 0.97);
  const сер0 = Math.round(h * 0.30), сер1 = Math.round(h * 0.55);
  const из = execFileSync("python3", ["-c", `
import sys
from PIL import Image
im = Image.open(sys.argv[1]).convert("L")
w, h = im.size
def ср(y0, y1):
    d = list(im.crop((0, y0, w, y1)).getdata())
    return round(sum(d) / len(d), 1)
print(ср(${низ0}, h), ср(${сер0}, ${сер1}), ср(0, h))
`, файл], { encoding: "utf8" }).trim().split(/\s+/).map(Number);
  return { низ: из[0], середина: из[1], кадр: из[2] };
}

