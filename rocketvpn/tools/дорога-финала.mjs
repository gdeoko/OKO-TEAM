/* Замер ДОРОГИ ФИНАЛА: где стоит камера на каждой доле акта.

   ЗАЧЕМ. Снимок доли 0.30 на мониторе показал вместо подхода к ракете
   тёмную гнутую стену во весь кадр. Глазом отсюда не понять, что
   случилось: камера уже внутри, камера уткнулась в обшивку снаружи или
   корабль просто не там, куда смотрит поза. Число отвечает сразу.

   ── ЧЕМ ЭТОТ ЗАМЕР ВРАЛ И ПОЧЕМУ ЭТО ВАЖНЕЕ САМОГО ЗАМЕРА ──────────
   Первая редакция брала место корабля как `узел.position` и радиус
   обшивки как записанное в модуле 3.45. Оба числа МЕСТНЫЕ.

   Узел финала лежит внутри группы акта, которая сама стоит в гнезде и
   ужата до 0.377. Его собственное position это ноль - и замер честно
   печатал «корабль стоит в 0,0,0», меряя расстояние от начала мира, а
   не от корабля. Радиус 3.45 в мировых единицах это 1.30, то есть
   «зазор до обшивки» был завышен больше чем вдвое.

   Числа при этом выглядели совершенно правдоподобно, и по ним уже
   делались выводы. Замер, который меряет НЕ ТО, что нарисовано, хуже
   отсутствия замера: он отправляет искать поломку туда, где её нет.

   Поэтому здесь всё берётся из мировых матриц: место корабля - мировая
   точка узла, размеры - мировая коробка его наружной части. Ни одного
   числа, записанного руками.

   Печатает на каждую долю: мировую точку глаза, направление взгляда,
   расстояние глаза до ОСИ корабля, зазор до наружной обшивки (минус
   значит «глаз внутри корпуса») и поле зрения.

   Запуск: node tools/дорога-финала.mjs [доли через запятую] */
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";

const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const доли = (process.argv[2] || "0,0.15,0.30,0.45,0.60,0.75,0.90,1").split(",").map(Number);

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"]
});
const стр = await бр.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });

/* ── ЖИВУЮ КАМЕРУ НЕ СПРАШИВАЕМ ВОВСЕ ─────────────────────────────
   Здесь дважды стояло ожидание, и оба раза оно врало в одну сторону:
   печатало ПРЕЖНЮЮ точку и рисовало этим плато, которого нет.

   Сначала ждали по часам, семьсот миллисекунд, и на крупном шаге доли
   камера не успевала. Потом ждали по условию «камера перестала
   двигаться четыре опроса подряд» - и стало хуже, потому что сразу
   после прыжка она ЕЩЁ не тронулась, а не УЖЕ приехала. Условие не
   различает эти два покоя и засчитывает первый.

   Поймано живьём 14.09.2026: доли 0.60 и 0.90, снятые сверху вниз,
   дали ОДНУ И ТУ ЖЕ точку с шагом 0.00, хотя между ними шестнадцать
   единиц мира. Отдельная проба с постоянным ожиданием показала честные
   11.87 и -4.16, повторяемые в любом порядке. То есть беда была
   исключительно в замере, а замер этот про то, стоит ли камера, и
   ровно про это он и соврал.

   Ждать не нужно НИЧЕГО. Ход камеры это чистая функция прокрутки, и
   мир отдаёт её наружу: `RV_WORLD.проба(y)` считает позу в любой точке
   ленты, не трогая живую камеру и не ожидая кадра. Отделка (дрожь,
   дыхание, расхождение поля на скорости) в пробу намеренно не входит -
   она функция времени и скорости пальца, а не ленты, и в замере дороги
   была бы шумом.

   Отрезок ленты под актом берём у самого мира (`кривая().станции`), а
   не пересчитываем долю в пиксели здесь: второй пересчёт разойдётся с
   первым ровно тогда, когда сценарий поменяют. */
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 90000 });
await стр.waitForFunction(
  () => window.RV_WORLD && window.RV_WORLD["вступлениеИдёт"] && !window.RV_WORLD["вступлениеИдёт"](),
  null, { timeout: 240000 }).catch(() => {});
await стр.waitForTimeout(2000);

/* Габариты корабля снимаем ОДИН раз и в мировых единицах: акт может
   стоять в гнезде, быть ужат и повёрнут, и всё это уже сложено в его
   мировую матрицу. */
await стр.evaluate(() => window.RV_MOTION["кПунктy"]("финал", 0.5));
await стр.waitForTimeout(700);
const корабль = await стр.evaluate(() => {
  const W = window.RV_WORLD["мир"]();
  const узел = window.RV_ФИНАЛ["узел"]();
  if (!узел) return null;
  узел.updateMatrixWorld(true);
  const место = new W.T.Vector3();
  узел.getWorldPosition(место);
  const масштаб = new W.T.Vector3();
  узел.getWorldScale(масштаб);
  /* Радиус обшивки берём коробкой наружной части, а не записанным
     числом: коробка знает и про масштаб, и про то, что в узле выросло
     после последней правки. */
  const коробка = new W.T.Box3().setFromObject(узел);
  const размер = new W.T.Vector3();
  коробка.getSize(размер);
  return {
    x: место.x, y: место.y, z: место.z,
    масштаб: масштаб.x,
    борт: Math.max(размер.x, размер.z) / 2,
    низ: коробка.min.y, верх: коробка.max.y
  };
});

if (!корабль) {
  console.log("узла финала нет: акт не собран");
  await бр.close();
  process.exit(1);
}
console.log(`корабль: середина ${корабль.x.toFixed(2)},${корабль.y.toFixed(2)},${корабль.z.toFixed(2)}` +
            ` · масштаб ${корабль.масштаб.toFixed(3)} · борт ${корабль.борт.toFixed(2)}` +
            ` · по высоте ${корабль.низ.toFixed(1)}..${корабль.верх.toFixed(1)}\n`);

console.log("доля   глаз x,y,z                взгляд x,y,z             до оси  до обшивки  поле   шаг");
/* Отрезок ленты под финалом: доля 0 это его верх, доля 1 конец хода. */
const отрезок = await стр.evaluate(() => {
  const с = window.RV_WORLD["кривая"]()["станции"].find((э) => э["имя"] === "финал");
  return с ? { верх: с["верх"], ход: с["ход"] } : null;
});
if (!отрезок) {
  console.log("акта финала нет в списке станций");
  await бр.close();
  process.exit(1);
}

let прежний = null;
for (const д of доли) {
  const r = await стр.evaluate(({ верх, ход, доля }) => {
    const п = window.RV_WORLD["проба"](верх + ход * доля);
    if (!п) return null;
    /* «взгляд» у пробы это ТОЧКА, куда камера смотрит, а «напр» -
       единичный вектор туда же. Печатаем направление: столбец так и
       назван, и по точке о развороте камеры не судить. */
    const г = п["камера"], н = п["напр"] || [0, 0, -1];
    return { гx: г[0], гy: г[1], гz: г[2],
             вx: н[0], вy: н[1], вz: н[2], поле: п["поле"] };
  }, { верх: отрезок.верх, ход: отрезок.ход, доля: д });
  if (!r) { console.log(д.toFixed(2) + "  проба не отвечает: мир ещё не собран"); continue; }
  /* Расстояние до ОСИ корабля: ось вертикальная, значит меряем в
     плоскости пола, без высоты. */
  const dx = r.гx - корабль.x, dz = r.гz - корабль.z;
  const ось = Math.sqrt(dx * dx + dz * dz);
  const шаг = прежний
    ? Math.hypot(r.гx - прежний.гx, r.гy - прежний.гy, r.гz - прежний.гz) : 0;
  прежний = r;
  console.log(
    д.toFixed(2).padEnd(6),
    (r.гx.toFixed(1) + "," + r.гy.toFixed(1) + "," + r.гz.toFixed(1)).padEnd(24),
    (r.вx.toFixed(2) + "," + r.вy.toFixed(2) + "," + r.вz.toFixed(2)).padEnd(24),
    ось.toFixed(2).padStart(6),
    (ось - корабль.борт).toFixed(2).padStart(10),
    r.поле.toFixed(1).padStart(5),
    шаг.toFixed(2).padStart(6)
  );
}
await бр.close();
