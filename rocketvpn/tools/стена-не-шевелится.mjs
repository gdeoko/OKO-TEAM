/* СТЕНА СТОИТ НЕПОДВИЖНО, ПОКА НЕ РАЗЛЕТИТСЯ.

   Владелец: «там не только яркость, там количество кирпичей и формы
   даже меняется, обрати внимание - с правой стороны два кирпича
   появляются и цвет меняется. Можно чтобы вообще ничего не
   происходило со стеной до того, как она распадётся?»

   Прежние мои заходы мерили ЯРКОСТЬ куска картинки и находили то
   одно, то другое. Яркость это следствие, а вопрос владельца про
   причину, и причин может быть три разных:

     СКОЛЬКО кирпичей стоит   - счётчик копий у кладки;
     КАКОГО она размера       - габаритная коробка в мире;
     КАКОГО она цвета         - числа самого материала.

   Поэтому меряем все три по долям акта и печатаем рядом. Меняется
   что-то одно - видно, что именно, и правка идёт по адресу.

   Судим просто: до начала разлёта ни одно из трёх чисел не имеет права
   меняться вовсе. Разлёт начинается в проколе, до него стена стоит.

   Запуск: node tools/стена-не-шевелится.mjs [тел|пк]
*/
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";
import { mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";

const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const КТО = process.argv[2] || "тел";
const экран = КТО === "пк"
  ? { w: 1440, h: 900, dpr: 1, mob: false }
  : { w: 390, h: 844, dpr: 1, mob: true };

/* Идём по хвосту станции и по всему периметру: стена собирается на
   станции и стоит весь периметр. Прокол не трогаем - там ей и положено
   разлетаться. */
/* Начинаем с той доли, на которой перелёт уже кончился: до неё стена
   ещё собирается, и это задумано. Меряем то, что человек читает как
   стоящую стену. */
const ПУТЬ = [
  ["станция", 0.66], ["станция", 0.75], ["станция", 0.84], ["станция", 0.92],
  ["периметр", 0.05], ["периметр", 0.20], ["периметр", 0.40], ["периметр", 0.60]
];
const КУДА = "/tmp/стена-шаги";
mkdirSync(КУДА, { recursive: true });

/* ── СРАВНИВАЕМ САМУ КАРТИНКУ, А НЕ ТОЛЬКО ЧИСЛА ─────────────────
   Числа материала и счётчик копий у двух кладок свои, и по ним видно
   не всё: камни переставляет матрица копий, а она в числа не попадает.
   Владелец смотрит на кадр, поэтому и сверяем кадр - долю точек,
   которые отличаются от первого снимка больше чем на глаз. Берём
   полосу, где стоит кладка, без подписи и без низа. */
function яркость(файл) {
  const из = execFileSync("python3", ["-c", `
import sys
from PIL import Image, ImageStat
im = Image.open(sys.argv[1]).convert("RGB")
w, h = im.size
# Полоса кладки без подписи сверху и без грунта снизу.
k = im.crop((int(w*0.15), int(h*0.40), int(w*0.85), int(h*0.66)))
s = ImageStat.Stat(k)
print(round(sum(s.mean)/3, 1))
`, файл], { encoding: "utf8" });
  return +из.trim();
}

function отличие(а, б) {
  const из = execFileSync("python3", ["-c", `
import sys
from PIL import Image, ImageChops
a = Image.open(sys.argv[1]).convert("L"); b = Image.open(sys.argv[2]).convert("L")
w, h = a.size
к = (0, int(h*0.30), w, int(h*0.82))
a = a.crop(к); b = b.crop(к)
р = ImageChops.difference(a, b)
то = list(р.getdata())
сильных = sum(1 for v in то if v > 26) * 100.0 / len(то)
print(round(сильных, 2), round(sum(то)/len(то), 2))
`, а, б], { encoding: "utf8" });
  const [доля, средн] = из.trim().split(/\s+/).map(Number);
  return { доля, средн };
}

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"]
});
const стр = await бр.newPage({
  viewport: { width: экран.w, height: экран.h },
  deviceScaleFactor: экран.dpr, isMobile: экран.mob, hasTouch: экран.mob
});
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 90000 });
await стр.waitForFunction(
  () => window.RV_WORLD && window.RV_WORLD["вступлениеИдёт"] && !window.RV_WORLD["вступлениеИдёт"](),
  null, { timeout: 240000 }).catch(() => console.log("вступления не дождались"));
await стр.waitForTimeout(2000);

/* ── ПЕРВЫЙ ЗАМЕР БЕРЁТСЯ ПОСЛЕ РАЗОГРЕВА ────────────────────────
   Прыжок с нуля на середину ленты это не шаг замера: ход ведёт камеру
   поводком, и первое показание снимается с недоехавшей сцены. В
   соседней проверке это уже давало ложный рывок, здесь - ложный скачок
   яркости на первом же шаге. Встаём на начало пути заранее и ждём. */
await стр.evaluate(([а, д]) => window.RV_MOTION["кПунктy"](а, д), ПУТЬ[0]);
await стр.waitForTimeout(5000);

console.log(`\n${КТО} ${экран.w}x${экран.h}`);
const ряд = [];
for (const [акт, д] of ПУТЬ) {
  await стр.evaluate(([а, д]) => window.RV_MOTION["кПунктy"](а, д), [акт, д]);
  await стр.waitForTimeout(2200);
  const з = await стр.evaluate(() => {
    const м = window.RV_WORLD["мир"]();
    const T = м.T;
    let кладка = null;
    м.scene.traverse(function (о) { if (о.name === "кладка") кладка = о; });
    if (!кладка) return null;
    кладка.updateMatrixWorld(true);
    const к = new T.Box3().setFromObject(кладка);
    const р = к.getSize(new T.Vector3());
    /* Копии, которые реально рисуются. У InstancedMesh это `count`, и
       именно его крутят, когда «добавляют кирпичи». */
    const копий = кладка.count;
    const всего = кладка.instanceMatrix ? кладка.instanceMatrix.count : кладка.count;
    /* Числа материала: цвета камня и света. Их подмена и есть «цвет
       меняется», и по картинке её от тени не отличить. */
    const ун = {};
    const м2 = кладка.material;
    if (м2 && м2.uniforms) {
      for (const кл in м2.uniforms) {
        const з = м2.uniforms[кл] && м2.uniforms[кл].value;
        if (typeof з === "number") ун[кл] = +з.toFixed(3);
        else if (з && typeof з.r === "number") ун[кл] = [з.r, з.g, з.b].map((ч) => +ч.toFixed(3)).join(",");
      }
    }
    let видна = кладка.visible, р2 = кладка.parent;
    while (видна && р2) { видна = р2.visible; р2 = р2.parent; }
    return {
      копий: копий, всего: всего, видна: видна,
      габарит: [+р.x.toFixed(2), +р.y.toFixed(2), +р.z.toFixed(2)].join("x"),
      непрозр: м2 ? +(+m2opacity(м2)).toFixed(3) : 1,
      ун: ун
    };
    function m2opacity(м) { return м.opacity == null ? 1 : м.opacity; }
  });
  if (!з) { console.log(`  ${акт} ${д}: кладки в сцене нет`); continue; }
  const файл = `${КУДА}/${КТО}-${акт}-${д.toFixed(2)}.png`;
  await стр.screenshot({ path: файл });
  ряд.push({ акт, д, файл, ...з });
  console.log(`  ${акт} ${д.toFixed(2)}  копий ${String(з.копий).padStart(4)}/${з.всего}` +
              `  габарит ${з.габарит}  видна ${з.видна}  непрозр ${з.непрозр}`);
}

const беды = [];
if (ряд.length >= 2) {
  const первый = ряд[0];
  for (const с of ряд.slice(1)) {
    if (с.копий !== первый.копий) {
      беды.push(`${с.акт} ${с.д}: копий ${с.копий}, а было ${первый.копий} - кирпичи добавляются на глазах`);
    }
    if (с.габарит !== первый.габарит) {
      беды.push(`${с.акт} ${с.д}: габарит ${с.габарит}, а был ${первый.габарит} - стена меняет форму`);
    }
    for (const к of new Set([...Object.keys(первый.ун), ...Object.keys(с.ун)])) {
      /* Время идёт всегда, его не считаем. Свечение шва тоже: оно
         ДЫШИТ по замыслу, ровно как мерцают звёзды, и держать его
         намертво значило бы погасить кладку. Замер это подтверждает -
         uShov гуляет в пределах четырёх сотых и никуда не уходит, а
         яркость самой кладки при этом стоит (см. шаги ниже). */
      if (/time|время|uTime|uShov/i.test(к)) continue;
      if (первый.ун[к] !== с.ун[к]) {
        беды.push(`${с.акт} ${с.д}: ${к} ${первый.ун[к]} -> ${с.ун[к]} - меняется цвет или свет камня`);
      }
    }
  }
}

/* ── СРАВНИВАЕМ СОСЕДЕЙ, А НЕ ВСЁ С ПЕРВЫМ КАДРОМ ────────────────
   Первый заход мерил каждый кадр против самого первого и краснел на
   половине пути. Требование было неверным: по периметру в стену летят
   глыбы льда, это задумано и меняет кадр честно. Ошибкой считается
   СКАЧОК между соседними шагами - именно его человек и видит, листая.

   Скачок меряем яркостью полосы кладки: форма и число камней уже
   сверены числами выше, а тут ловится подмена материала на стыке. */
if (ряд.length >= 2) {
  console.log("");
  let пред = null;
  for (const с of ряд) {
    const я = яркость(с.файл);
    console.log(`  ${с.акт} ${с.д.toFixed(2)}: яркость кладки ${я}` +
                (пред === null ? "" : `  шаг ${(я - пред > 0 ? "+" : "")}${(я - пред).toFixed(1)}`));
    if (пред !== null && Math.abs(я - пред) > пред * 0.06) {
      беды.push(`${с.акт} ${с.д}: яркость кладки скакнула ${пред.toFixed(1)} -> ${я} за один шаг`);
    }
    пред = я;
  }
}

if (беды.length) {
  console.log("\nКРАСНОЕ:");
  for (const с of [...new Set(беды)]) console.log("   " + с);
} else {
  console.log("\nзелено: до разлёта со стеной не происходит ничего");
}
await бр.close();
process.exit(беды.length ? 1 : 0);
