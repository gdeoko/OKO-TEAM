/* Проверка: в шейдерах нет кириллицы.

   ЗАЧЕМ. Весь код сайта написан русскими именами, и это работает везде,
   кроме одного места: GLSL знает только ASCII. Кириллическая буква в
   имени переменной шейдера не даёт ни исключения, ни строчки в консоли
   браузера - программа просто не собирается, и материал молча
   перестаёт рисоваться. На экране это выглядит как «объект пропал»,
   и искать причину приходится по всей сцене.

   Ловушка сработала уже дважды: один раз на банке откликов роя
   (`float цель`), один раз раньше. Третьего раза не будет: строки,
   из которых склеиваются шейдеры, проверяются здесь.

   ЧТО СЧИТАЕТСЯ ШЕЙДЕРНОЙ СТРОКОЙ. Строка в массиве, который собирается
   через join и лежит в переменной с именем вида В_ЧТО-ТО, Ф_ЧТО-ТО,
   *_GLSL, ИХ_ФУНКЦИИ - то есть по тому же признаку, по которому их
   узнаёт человек. Проверка нарочно грубая: лучше лишний раз спросить
   про строку, которая шейдером не является, чем пропустить настоящую.

   КОММЕНТАРИИ НЕ ТРОГАЕМ. Пояснения между строками шейдера пишутся
   по-русски и в текст программы не попадают: их собирает не join, а
   разборщик JavaScript выбрасывает.

   Запуск: node tools/checks/глсл.mjs */
import fs from "node:fs";
import path from "node:path";

const ПАПКА = path.resolve(process.cwd(), "assets");
const КИРИЛЛИЦА = /[Ѐ-ӿ]/;

/* Имя переменной, за которым стоит массив строк шейдера. */
const ИМЯ_ШЕЙДЕРА = /^\s*var\s+([А-ЯЁ]{1,2}_[А-ЯЁ_]+|[A-Z]{1,2}_[A-Z_]+)\s*=\s*\[\s*$/;

let бед = 0, файлов = 0, строк = 0;

for (const имя of fs.readdirSync(ПАПКА)) {
  if (!имя.endsWith(".js")) continue;
  const путь = path.join(ПАПКА, имя);
  const строки = fs.readFileSync(путь, "utf8").split("\n");
  let вШейдере = false, скобок = 0, своё = 0;
  /* Имена, объявленные в теле текущего main, и строка первого
     объявления. Сбрасывается на каждом новом main. */
  const имена = new Map();
  let вMain = false;
  for (let i = 0; i < строки.length; i++) {
    const с = строки[i];
    if (!вШейдере) {
      if (ИМЯ_ШЕЙДЕРА.test(с)) { вШейдере = true; скобок = 1; своё = 0; имена.clear(); вMain = false; }
      continue;
    }
    /* Конец массива: строка, закрывающая скобку. */
    if (/^\s*\]\s*\./.test(с) || /^\s*\]\s*;/.test(с)) { вШейдере = false; continue; }
    /* Строка шейдера это строковый литерал. Всё остальное внутри массива
       (комментарии, вставки других кусков через имя) пропускаем. */
    const м = с.match(/^\s*"((?:[^"\\]|\\.)*)"\s*,?\s*$/);
    if (!м) continue;
    своё++; строк++;
    if (КИРИЛЛИЦА.test(м[1])) {
      бед++;
      console.log("  " + имя + ":" + (i + 1) + "  " + м[1].trim().slice(0, 100));
    }
    /* ── ДВА ОБЪЯВЛЕНИЯ ОДНОГО ИМЕНИ В ОДНОМ main() ─────────────
       Правило написано 11.09.2026 ценой шейдера дома. Блок разброса
       цвета переписывался в него из кладки, и вместе с кодом приехало
       имя `zerno`, которое в этом же main() уже было занято под
       трёхкомпонентный шум нормали. GLSL такую программу не собирает
       вовсе, и дом не нарисовался бы НИ ОДНИМ кадром - а проверка
       молчала, потому что искала только кириллицу.

       Считаем объявления верхнего уровня внутри тела main: строка
       вида `тип имя =` с отступом ровно в два пробела. Вложенные
       блоки (в них отступ больше) не трогаем: там своя область
       видимости, и повтор имени законен. */
    const тело = м[1];
    if (/^\s*void\s+main\s*\(/.test(тело)) { имена.clear(); вMain = true; continue; }
    if (вMain) {
      const о = тело.match(/^  (float|vec2|vec3|vec4|int|bool|mat2|mat3|mat4)\s+([A-Za-z_][A-Za-z0-9_]*)\s*(=|;)/);
      if (о) {
        const имяПер = о[2];
        if (имена.has(имяПер)) {
          бед++;
          console.log("  " + имя + ":" + (i + 1) + "  имя «" + имяПер +
                      "» объявлено второй раз в одном main (первое на строке " + имена.get(имяПер) + ")");
        } else {
          имена.set(имяПер, i + 1);
        }
      }
    }
  }
  файлов++;
}

console.log("проверено файлов " + файлов + ", строк шейдера " + строк);
if (бед) {
  console.log("ГРЯЗНО глсл: " + бед + " строк(а) не пройдут сборку.");
  console.log("  GLSL знает только ASCII, и второго объявления одного имени");
  console.log("  в одном main он тоже не прощает. Такая программа не");
  console.log("  собирается, и материал молча перестаёт рисоваться -");
  console.log("  ни ошибки в консоли, ни следа в кадре, просто пусто.");
  process.exit(1);
}
console.log("ЧИСТО глсл: кириллицы в шейдерах нет");
