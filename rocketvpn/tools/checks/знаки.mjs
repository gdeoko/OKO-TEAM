/* КАЖДЫЙ ЗНАК РАЗМЕТКИ ЕСТЬ В АТЛАСЕ ШРИФТА.

   ЗАЧЕМ. Владелец прислал снимок станции, и в надзаголовке читается
   «ROCKET VPN ? РАЗБЛОКИРОВКА МОБИЛЬНОГО ИНТЕРНЕТА». Вопросительного
   знака в разметке нет: там стояла средняя точка `&middot;`.

   Слова актов рисуются полем расстояний (rv-msdf.js) по атласу
   `assets/gen/шрифт/plex.json`. В нём двести знаков, и U+00B7 среди них
   нет. Отсутствующий знак подменяется вопросительным - молча, без
   единой ошибки в журнале. Глазом это ловится только на снимке, а в
   коде выглядит правильным словом.

   Ошибка дешёвая в починке и дорогая в пропуске: она стоит на первом
   экране сайта. Поэтому проверяется кодом, а не внимательностью.

   ЧТО ПРОВЕРЯЕТ. Весь текст, который уходит в объём: надзаголовок,
   заголовок, абзац, подписи карточек и глыб. Разбор разметки идёт по
   тем же выборкам, что у rv-слово3d.js, поэтому список знаков совпадает
   с тем, что попадёт в атлас.

   Запуск: node tools/checks/знаки.mjs */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

const атлас = JSON.parse(readFileSync(join(КОРЕНЬ, "assets/gen/шрифт/plex.json"), "utf8"));
const есть = new Set();
for (const г of (атлас.chars || атлас.glyphs || [])) {
  if (г && typeof г.char === "string") есть.add(г.char);
}
/* Пробел и перевод строки в атласе не нужны: набор их не рисует. */
есть.add(" "); есть.add("\n"); есть.add("\t");

const разметка = readFileSync(join(КОРЕНЬ, "frame.html"), "utf8");

/* Именованные сущности HTML разворачиваем в тот знак, который увидит
   браузер: именно он и уходит в набор. Числовые тоже. */
const СУЩНОСТИ = {
  "&middot;": "·", "&nbsp;": " ", "&ndash;": "–",
  "&mdash;": "—", "&hellip;": "…", "&laquo;": "«",
  "&raquo;": "»", "&rsquo;": "’", "&lsquo;": "‘",
  "&amp;": "&", "&lt;": "<", "&gt;": ">", "&quot;": "\"", "&numero;": "№"
};
function развернуть(т) {
  let из = т;
  for (const [к, з] of Object.entries(СУЩНОСТИ)) из = из.split(к).join(з);
  из = из.replace(/&#x([0-9a-fA-F]+);/g, (_, ч) => String.fromCodePoint(parseInt(ч, 16)));
  из = из.replace(/&#(\d+);/g, (_, ч) => String.fromCodePoint(+ч));
  return из;
}

/* Строки, которые уходят в объём. Берём каждую секцию акта и в ней те
   же узлы, что читает rv-слово3d.js: rv-над span, rv-заг, rv-абз, а
   также b и span у карточек rv-карты. Разбор простой намеренно: нужен
   набор ЗНАКОВ, а не дерево. */
const строки = [];
const секции = разметка.split(/<section\b/).slice(1);
for (const с of секции) {
  const актM = с.match(/data-акт="([^"]+)"/);
  if (!актM) continue;
  const акт = актM[1];
  const слой = (с.split(/<\/section>/)[0] || "");
  const взять = (рег, где) => {
    let m;
    const р = new RegExp(рег, "gsu");
    while ((m = р.exec(слой))) {
      const голый = развернуть(m[1].replace(/<[^>]*>/g, "")).replace(/\s+/g, " ").trim();
      if (голый) строки.push({ акт: акт, где: где, текст: голый });
    }
  };
  взять('<p class="rv-над"[^>]*>\\s*<span>(.*?)</span>', "надзаголовок");
  взять('<h[123] class="rv-заг"[^>]*>(.*?)</h[123]>', "заголовок");
  взять('<p class="rv-абз"[^>]*>(.*?)</p>', "абзац");
  взять('<li[^>]*>\\s*<b>(.*?)</b>', "подпись карточки");
}

const плохие = new Map();
for (const с of строки) {
  for (const з of Array.from(с.текст)) {
    if (есть.has(з)) continue;
    const ключ = з;
    if (!плохие.has(ключ)) плохие.set(ключ, []);
    плохие.get(ключ).push(с);
  }
}

console.log(`ЗНАКИ В АТЛАСЕ  знаков в атласе ${есть.size - 3}, строк в объёме ${строки.length}`);
if (!плохие.size) {
  console.log("  ок  каждый знак разметки есть в атласе");
  process.exit(0);
}
for (const [з, где] of плохие) {
  const код = "U+" + з.codePointAt(0).toString(16).toUpperCase().padStart(4, "0");
  console.log(`  КРАСНОЕ  знака «${з}» (${код}) в атласе НЕТ, он выйдет вопросительным:`);
  for (const с of где.slice(0, 4)) {
    console.log(`      ${с.акт} / ${с.где}: ${с.текст.slice(0, 90)}`);
  }
}
console.log("  лечится заменой на знак из атласа либо пересборкой атласа");
process.exit(1);
