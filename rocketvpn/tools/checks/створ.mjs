/* Проверка: сайт не отдаётся без ключа.

   Три случая, и все три должны выглядеть ОДИНАКОВО: ключа нет, ключ
   неверный, ключ просрочен. Если хоть один отличается ответом или
   видом, перебор превращается в игру «угадай, где теплее». */
import { браузер, БАЗА, адрес, ключ, ПК, доложить } from "./общее.mjs";

const беды = [];
const b = await браузер();

async function состояние(url) {
  const pg = await b.newPage({ viewport: ПК.vp });
  await pg.goto(url, { waitUntil: "domcontentloaded", timeout: 60000 });
  await pg.waitForTimeout(1500);
  const r = await pg.evaluate(() => ({
    /* Ищем створ по КЛАССУ, а не по идентификатору. Закрытых состояний
       два, и оба правильные: серверный створ - отдельная страница, где
       плёнки нет вовсе; браузерный - слой поверх плёнки, когда сайт
       отдан статикой без PHP. Проверять надо не «какой именно створ», а
       «содержимое недостижимо». */
    створ: !!document.querySelector(".rv-створ"),
    открыт: document.documentElement.classList.contains("rv-открыт"),
    /* «нет» - это ЛУЧШИЙ исход, а не худший: плёнки на странице нет
       совсем, значит и прятать нечего. */
    плёнка: (function () {
      const э = document.querySelector(".rv-плёнка");
      return э ? getComputedStyle(э).visibility : "нет";
    })(),
    загрузка: !!document.querySelector(".rv-загр")
  }));
  await pg.close();
  return r;
}

const безКлюча = await состояние(БАЗА + "/");
const кривой   = await состояние(БАЗА + "/?k=" + encodeURIComponent("1700000000.deadbeefdeadbeefdeadbeef"));
const старый   = await состояние(БАЗА + "/?k=" + encodeURIComponent(ключ(-8 * 24 * 3600)));
const годный   = await состояние(адрес());

if (безКлюча.открыт) беды.push("без ключа сайт открылся");
if (кривой.открыт) беды.push("неверный ключ открыл сайт");
if (старый.открыт) беды.push("просроченный ключ открыл сайт");
if (!годный.открыт) беды.push("годный ключ НЕ открыл сайт");

for (const [имя, с] of [["без ключа", безКлюча], ["неверный", кривой], ["просроченный", старый]]) {
  if (!с.створ) беды.push(имя + ": створа нет на экране");
  if (с.плёнка !== "hidden" && с.плёнка !== "нет") {
    беды.push(имя + ": содержимое видно сквозь створ (" + с.плёнка + ")");
  }
  if (с.загрузка) беды.push(имя + ": за закрытым створом крутится экран загрузки");
}

/* Три закрытых случая обязаны быть неотличимы друг от друга. */
const слепок = с => [с.створ, с.открыт, с.плёнка, с.загрузка].join("|");
if (слепок(безКлюча) !== слепок(кривой) || слепок(безКлюча) !== слепок(старый)) {
  беды.push("закрытые случаи различаются между собой: " +
    слепок(безКлюча) + " / " + слепок(кривой) + " / " + слепок(старый));
}

await b.close();
доложить("створ закрыт без ключа", беды);
