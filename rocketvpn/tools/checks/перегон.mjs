/* Проверка: НА ЛЕНТЕ НЕТ ПУСТОГО КУСКА.

   Беда, ради которой написана. Между двумя соседними актами лежит
   перегон РОВНО В ОДНО ОКНО, и это не оплошность вёрстки, а следствие
   мерки: доля акта считается от «верх секции на верху окна» до «низ
   секции на низу окна» (rv-world.js, `с.ход = высота - выОкна`). Значит
   доля предыдущего акта упирается в единицу на целое окно раньше, чем
   доля следующего трогается с нуля.

   На двух стыках из трёх это незаметно: в кадре стоят большие
   предметы, и они переезжают из акта в акт сами. На третьем - между
   проколом и финалом - тоннель к своему концу намеренно гаснет, а зал
   с ракетой никто не показывал. Замер спуска дал 0.13% непустых точек
   на долях 0.625, 0.640 и 0.655 при 899 точках прокрутки: почти
   полный экран чёрного посреди фильма. Глазами по снимкам это видно
   сразу, а ни одна проверка на это не смотрела.

   Три пути, и все три проверяются, потому что ломались они по-разному:
     вниз    человек проходит ленту сверху вниз (зал не был собран);
     вверх   он же отматывает назад из корабля (зал стоял погашенным);
     прыжок  приход по якорю или из космоса соседнего сайта.

   Шаг мелкий и с выдержкой: мир едет к цели плавно, и после большого
   прыжка камера первые кадры ещё не тронулась. Крупный шаг эту беду
   пропускает - ровно так весь сайт и снимался двадцатью пятью долями,
   и пустой кусок в отчёт не попал.

   Запуск:
     RV_URL=http://127.0.0.1:8170 node tools/checks/перегон.mjs
     RV_ONE=ПК node tools/checks/перегон.mjs
*/
import { mkdirSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { PNG } from "pngjs";
import { браузер, открыть, лентаВсего, кПрокрутке, доложить, ТЕЛЕФОН, ПК } from "./общее.mjs";

const КУДА = (process.env.RV_СНИМКИ || join(tmpdir(), "rv-перегон")) + "/";
mkdirSync(КУДА, { recursive: true });

/* Шаг по ленте. Сотая доли это около двухсот точек на ПК: мельче
   человека, который крутит колесом, и крупнее, чем нужно проверке. */
const ШАГ = 0.01;
/* Порог пустоты. Звёздное небо на чёрном даёт 0.1-0.3%, освещённый зал
   от трёх процентов и выше. Полтора процента стоят между ними с
   запасом в обе стороны: замеры чинёного перегона дают 5.6-9.9%, а
   сломанного - 0.13-0.57%. */
const ПОРОГ = 1.5;
/* Сколько шагов подряд ниже порога считать бедой. Один шаг это
   законная затемнённая доля (например вспышка прокола), три подряд это
   уже кусок ленты, на котором смотреть нечего. */
const ПОДРЯД = 2;
/* Яркость точки, выше которой она считается непустой. Подложка неба
   даёт 20-40 пунктов, звёзды и предметы - выше сотни. */
const ЯРКО = 60;
/* Шапка сайта стоит всегда и к содержимому ленты отношения не имеет. */
const ШАПКА = 70;

function непусто(файл) {
  const п = PNG.sync.read(readFileSync(файл));
  let n = 0;
  const низ = п.height;
  for (let y = ШАПКА; y < низ; y++) {
    for (let x = 0; x < п.width; x++) {
      const i = (п.width * y + x) << 2;
      if ((п.data[i] + п.data[i + 1] + п.data[i + 2]) / 3 > ЯРКО) n++;
    }
  }
  return +(100 * n / (п.width * (низ - ШАПКА))).toFixed(2);
}

/* Ждём КАДРАМИ, а не секундами. На программном отрисовщике кадр идёт
   втрое дольше, чем на живой машине, и полторы секунды ожидания это
   четыре кадра вместо полусотни: мир к цели ещё не доехал, а проверка
   уже снимает. Ровно на этом краснела проверка света. */
async function устояться(pg) {
  await pg.waitForTimeout(500);
  await pg.evaluate(() => new Promise((г) => {
    let n = 0;
    (function ш() { requestAnimationFrame(() => (++n >= 8 ? г() : ш())); })();
  })).catch(() => {});
}

async function замерить(pg, всего, доли, метка) {
  const ряд = [];
  for (const д of доли) {
    await кПрокрутке(pg, всего * д);
    await устояться(pg);
    const ф = КУДА + метка + "-" + д.toFixed(3) + ".png";
    await pg.screenshot({ path: ф });
    ряд.push({ доля: д, доб: непусто(ф), файл: ф });
  }
  return ряд;
}

/* Подряд идущие пустые доли одним куском: в отчёт нужна ГРАНИЦА
   куска и его длина в точках прокрутки, а не двадцать строк подряд. */
function куски(ряд, всего) {
  const из = [];
  let н = -1;
  for (let i = 0; i <= ряд.length; i++) {
    const пусто = i < ряд.length && ряд[i].доб < ПОРОГ;
    if (пусто && н < 0) н = i;
    if (!пусто && н >= 0) {
      if (i - н >= ПОДРЯД) {
        /* Обратный проход идёт от единицы к нулю, и разность долей там
           отрицательная: без модуля отчёт печатал «-824 точек». Поймано
           живой пробой на откате, не рассуждением. */
        const а = ряд[н].доля, б = ряд[i - 1].доля;
        из.push({
          от: Math.min(а, б), до: Math.max(а, б), шагов: i - н,
          точек: Math.round((Math.abs(б - а) + ШАГ) * всего),
          худ: Math.min(...ряд.slice(н, i).map((р) => р.доб))
        });
      }
      н = -1;
    }
  }
  return из;
}

const беды = [];
const один = process.env.RV_ONE;
const b = await браузер();
try {
  for (const э of [ПК, ТЕЛЕФОН]) {
    if (один && э.имя !== один) continue;
    const { pg, ошибки } = await открыть(b, э);
    await устояться(pg);
    const всего = await лентаВсего(pg);

    /* Сетка долей: считаем от начала ленты до конца. */
    const вниз = [];
    for (let д = 0; д <= 1.0001; д += ШАГ) вниз.push(Math.min(1, +д.toFixed(4)));
    const вверх = вниз.slice().reverse();

    for (const [метка, доли] of [["вниз", вниз], ["вверх", вверх]]) {
      const ряд = await замерить(pg, всего, доли, э.имя + "-" + метка);
      const к = куски(ряд, всего);
      for (const п of к) {
        беды.push(э.имя + " " + метка + ": пусто на долях " + п.от.toFixed(3) +
          ".." + п.до.toFixed(3) + " (" + п.точек + " точек прокрутки, худший кадр " +
          п.худ + "% при пороге " + ПОРОГ + "%)");
      }
      const худ = Math.min(...ряд.map((р) => р.доб));
      console.log("  " + э.имя + " " + метка + ": худший кадр " + худ + "%, пустых кусков " + к.length);
    }

    /* Прыжок: приход по якорю мимо всей ленты. Берём доли стыков -
       там, где доля предыдущего акта уже единица, а следующего ещё
       ноль. Их считает сам мир. */
    const стыки = await pg.evaluate(() => {
      const к = window.RV_WORLD && window.RV_WORLD["кривая"] ? window.RV_WORLD["кривая"]() : null;
      const л = window.RV_СКРОЛЛ["лента"]() - window.innerHeight;
      if (!к || !к.станции || !л) return [];
      const из = [];
      for (let i = 0; i < к.станции.length - 1; i++) {
        const низ = к.станции[i].верх + к.станции[i].ход;
        const верх = к.станции[i + 1].верх;
        if (верх - низ < 10) continue;
        for (const ч of [0.25, 0.5, 0.75]) из.push(+((низ + (верх - низ) * ч) / л).toFixed(4));
      }
      return из;
    });
    if (стыки.length) {
      /* Перед каждым прыжком возвращаемся наверх: смысл проверки в том,
         что человек попадает на стык БЕЗ прохода по ленте. */
      for (const д of стыки) {
        await кПрокрутке(pg, 0);
        await устояться(pg);
        const ряд = await замерить(pg, всего, [д], э.имя + "-прыжок");
        if (ряд[0].доб < ПОРОГ) {
          беды.push(э.имя + " прыжок на долю " + д.toFixed(3) + ": кадр пуст, " +
            ряд[0].доб + "% при пороге " + ПОРОГ + "%");
        }
      }
      console.log("  " + э.имя + " прыжок: проверено стыков " + стыки.length);
    }
    for (const о of ошибки) беды.push(э.имя + ": " + о);
    await pg.close();
  }
} finally {
  await b.close();
}
доложить("перегон", беды);
