/* Проверка: лента листается вниз и вверх ОДИНАКОВО.

   ЗАЧЕМ. Владелец, 8 сентября 2026, дословно: «остановил лситание вниз и
   чуть чуть обратно покрутил у меня опять появляется резко собранный дом
   и текст 1 экрана… потом снова дом собирается и так бесконечно туда
   сюда. т.е. в ту сторону и в обратную лтстание должно быть одинаково не
   должно быть так что дом может быть там где я уже на 20% весь сайт
   пролистнул».

   Это корневой баг, из которого растёт половина его списка: улетающие
   обратно глыбы, исчезающий текст, рывки. Причина в том, что кадр сцены
   НЕ является чистой функцией от прокрутки: часть состояния копится по
   времени (пружины, сглаживание `лерпК`, счётчик вступления `М.интро`) и
   часть держится защёлками вида `М.открытоБыло`, которые переключаются
   при пересечении доли и обратно уже не возвращаются.

   ПОЧЕМУ НЕЛЬЗЯ МЕРИТЬ ТЕЛЕПОРТОМ. Соседние проверки ставят ленту на
   долю через `RV_MOTION.кПунктy(акт, доля)`. Для этой проверки такой
   способ бесполезен: он ставит прокрутку одним прыжком, а баг живёт
   ровно в НАКОПЛЕНИИ состояния по дороге. Поэтому здесь лента едет
   мелкими шагами, как под пальцем, и кадр снимается на контрольных
   точках по пути.

   КАК СЧИТАЕТСЯ. Сначала проход сверху вниз со снимками в контрольных
   точках, потом проход снизу вверх со снимками в ТЕХ ЖЕ точках. Пары
   сравниваются по средней разнице точек кадра.

   ПОРОГ 12, И ЭТО НЕ С ПОТОЛКА. В сцене есть движение по времени, а не
   по прокрутке: звёзды, дыхание блоков, зерно плёнки. Соседние кадры на
   одной и той же доле расходятся на 1.5-2 единицы просто от него, и
   проверка движения меряет тот же шум. Двенадцать это заведомо выше
   шума и заведомо ниже смены сцены: возврат дома вместо стены даёт
   разницу в десятки единиц.

   Запуск: node tools/checks/обратно.mjs [ПК|тел] */
import { chromium } from "playwright";
import { PNG } from "pngjs";
import fs from "node:fs";

const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const КТО = process.argv[2] || "ПК";
const вьюпорт = КТО === "тел" ? { width: 390, height: 844 } : { width: 1440, height: 900 };

/* Контрольных точек девять: по одной примерно на акт и по одной на стык.
   Больше не нужно - каждая точка это два снимка и две паузы. */
const ТОЧКИ = [0.10, 0.20, 0.30, 0.40, 0.50, 0.60, 0.70, 0.80, 0.90];
/* Шагов между точками. Десять шагов на десятую долю ленты это примерно
   один оборот колеса на шаг: достаточно мелко, чтобы пружины и защёлки
   успевали сработать так же, как под пальцем. */
const ШАГОВ_МЕЖДУ = 10;
const ПОРОГ = 12.0;

const беды = [];

const бр = await chromium.launch({
  executablePath: process.env.RV_CHROME || "/opt/pw-browsers/chromium-1234/chrome-linux64/chrome",
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--disable-lcd-text"]
});
const стр = await бр.newPage({ viewport: вьюпорт, deviceScaleFactor: 1 });
стр.on("pageerror", (e) => беды.push("ИСКЛ " + e.message.slice(0, 140)));

await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 90000 });

/* Ждём, пока лента соберётся целиком. Признак на корне документа это
   единственный надёжный знак: чистая консоль тут не доказывает ничего,
   исключения внутри сборки бывают невидимыми. */
await стр.waitForFunction(
  () => document.documentElement.classList.contains("рв-слова-в-сцене"),
  null, { timeout: 240000 }).catch(() => беды.push("лента не собралась за четыре минуты"));

/* Вступление на программном отрисовщике растягивается в полминуты, и всё
   это время камера подмешана к вступительной точке. */
await стр.waitForFunction(
  () => !(window.RV_WORLD && window.RV_WORLD["вступлениеИдёт"] && window.RV_WORLD["вступлениеИдёт"]()),
  null, { timeout: 240000 }).catch(() => беды.push("вступление не кончилось за четыре минуты"));
await стр.waitForTimeout(2000);

const высота = await стр.evaluate(() =>
  Math.max(0, document.documentElement.scrollHeight - window.innerHeight));
if (!(высота > 0)) {
  беды.push("лента нулевой длины: прокручивать нечего");
}

async function ехать(куда) {
  await стр.evaluate((y) => window.scrollTo(0, y), Math.round(куда));
  /* Два кадра отрисовки на шаг: первый принимает новую прокрутку, второй
     рисует по ней. Одного мало - снимок успевает застать прежний кадр. */
  await стр.evaluate(() => new Promise((р) => requestAnimationFrame(() => requestAnimationFrame(р))));
}

async function снять() {
  /* Пауза перед снимком даёт пружинам осесть. Если сцена честная, за это
     время ничего не поменяется; если нечестная, она как раз доедет до
     своего накопленного состояния, и проверка это увидит. */
  await стр.waitForTimeout(1200);
  return await стр.screenshot();
}

function разница(a, b) {
  const A = PNG.sync.read(a).data, B = PNG.sync.read(b).data;
  let сум = 0, n = 0;
  for (let i = 0; i < A.length; i += 16) {
    сум += Math.abs(A[i] - B[i]) + Math.abs(A[i + 1] - B[i + 1]) + Math.abs(A[i + 2] - B[i + 2]);
    n += 3;
  }
  return сум / n;
}

const вниз = {}, вверх = {};

/* ── ПРОХОД ВНИЗ ───────────────────────────────────────────────── */
await ехать(0);
await стр.waitForTimeout(1500);
let было = 0;
for (const т of ТОЧКИ) {
  const цель = высота * т;
  for (let i = 1; i <= ШАГОВ_МЕЖДУ; i++) {
    await ехать(было + (цель - было) * (i / ШАГОВ_МЕЖДУ));
  }
  было = цель;
  вниз[т] = await снять();
}

/* ── ПРОХОД ВВЕРХ ──────────────────────────────────────────────── */
/* Доезжаем до самого низа: владелец жаловался именно на возврат ПОСЛЕ
   того, как лента пройдена. */
for (let i = 1; i <= ШАГОВ_МЕЖДУ; i++) {
  await ехать(было + (высота - было) * (i / ШАГОВ_МЕЖДУ));
}
было = высота;
await стр.waitForTimeout(1500);

for (const т of [...ТОЧКИ].reverse()) {
  const цель = высота * т;
  for (let i = 1; i <= ШАГОВ_МЕЖДУ; i++) {
    await ехать(было + (цель - было) * (i / ШАГОВ_МЕЖДУ));
  }
  было = цель;
  вверх[т] = await снять();
}

await бр.close();

/* Пары кадров кладутся на диск ВСЕГДА, а не только при расхождении.
   Число говорит, что сцена разная, но не говорит чем; посмотреть глазами
   на пару это единственный способ понять, что именно вернулось. */
const ПАПКА = process.env.RV_OUT || "/tmp/обратно";
try { fs.mkdirSync(ПАПКА, { recursive: true }); } catch (e) {}

console.log("доля ленты  разница кадра вниз против кадра вверх");
for (const т of ТОЧКИ) {
  if (!вниз[т] || !вверх[т]) continue;
  const d = разница(вниз[т], вверх[т]);
  const имя = т.toFixed(2).replace(".", "");
  try {
    fs.writeFileSync(ПАПКА + "/" + имя + "-вниз.png", вниз[т]);
    fs.writeFileSync(ПАПКА + "/" + имя + "-вверх.png", вверх[т]);
  } catch (e) {}
  const метка = d >= ПОРОГ ? "  <== РАСХОДИТСЯ" : "";
  console.log("   " + т.toFixed(2) + "      " + d.toFixed(1).padStart(6) + метка);
  if (d >= ПОРОГ) {
    беды.push("на доле " + т.toFixed(2) + " кадр вниз и кадр вверх разные (" +
      d.toFixed(1) + " при пороге " + ПОРОГ + ")");
  }
}

if (беды.length) {
  console.log("ГРЯЗНО обратно: лента листается вниз и вверх по-разному");
  for (const б of беды) console.log("   " + б);
  process.exit(1);
}
console.log("ЧИСТО обратно: одна доля прокрутки даёт один и тот же кадр");
