/* ОДИН КАМЕНЬ НА ВЕСЬ ФИЛЬМ. СТЕНА НЕ МЕНЯЕТ ВИД НА СТЫКЕ АКТОВ.

   ЗАЧЕМ. Владелец говорил это трижды, последний раз так: «материал снова
   начал меняться до этого так небыло ты снова вернула проблему». Кладок
   в мире две - дом складывается в стену своим модулем, а глыбы бьют в
   кладку периметра (rv-кирпичи.js), - и до доли 0.94 стену держит дом, с
   0.94 периметр. Оба камня настроены на одни цвета, но светят двумя
   разными формулами, и на стыке это видно.

   ЧТО МЕРИМ. Один и тот же кусок кладки в трёх местах ленты: перед
   передачей, после передачи и в следующем акте. Три числа на каждое
   место: яркость, контраст (разброс яркости) и синий канал. Контраст
   нужен затем, что пелена поверх камня светлее его и РОВНЕЕ - она
   съедает зерно, а не только темнит.

   ── СНАЧАЛА ДОКАЗЫВАЕМ, ЧТО СЦЕНА УСТОЯЛАСЬ ──────────────────────
   Это главное в проверке, и написано оно ценой сорванной пробы. Перебор
   гашением на доле 0.92 дал такие числа: «как есть» 145.3, потом 148.9,
   потом 150.8 - три разных значения одной и той же доли, - а возврат
   последнего тела ушёл ВЫШЕ базы. То есть сцена на этой доле ещё
   доезжает сама, и любое сравнение снимков внутри её дрейфа показывает
   не правку, а время. Ровно на этом я уже обожглась с полосой низа
   кадра в финале.

   Поэтому каждое место снимается ДВАЖДЫ с паузой, и пока два снимка не
   сойдутся, проверка не судит вовсе, а честно говорит «сцена не
   устоялась». Зелёное на неустоявшейся сцене хуже красного.

   Запуск: node tools/checks/один-камень.mjs [пк|тел] */
import { chromium } from "playwright";
import { execFileSync } from "node:child_process";
import { БРАУЗЕР } from "../браузер.mjs";

const КТО = process.argv[2] || "пк";
const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const экран = КТО === "пк" ? { width: 1440, height: 900 } : { width: 390, height: 844 };

/* Кусок чистой кладки в середине кадра: там стена стоит во всех трёх
   местах, и в него не попадают ни подписи выносок, ни глыбы. */
const КУСОК = { x0: 0.40, y0: 0.45, x1: 0.62, y1: 0.67 };

/* Три места ленты. Первое - дом ещё держит стену, второе - её уже принял
   периметр, третье - следующий акт. Второе и третье обязаны совпасть по
   построению (там один модуль), и это встроенная проверка самой мерки:
   разойдутся они - виновата мерка, а не стена. */
const МЕСТА = [
  { акт: "станция", доля: 0.92, имя: "стену держит дом" },
  { акт: "станция", доля: 0.97, имя: "стену принял периметр" },
  { акт: "периметр", доля: 0.08, имя: "следующий акт" }
];

/* Допуски. Яркость и синий в уровнях из 255, контраст в тех же уровнях.
   Шесть уровней это чуть больше двух процентов диапазона: глаз такой
   разницы на камне не читает, а прежний разрыв был девятнадцать. */
const ДОПУСК = { яркость: 6, контраст: 3, синий: 8 };
/* Насколько два снимка одного места могут разойтись, чтобы сцена
   считалась устоявшейся. */
const ПОКОЙ = 1.5;

function мерка(файл) {
  const ч = execFileSync("python3", ["-c", `
import sys
from PIL import Image, ImageStat
im = Image.open(sys.argv[1]).convert("RGB")
w, h = im.size
k = im.crop((int(w * ${КУСОК.x0}), int(h * ${КУСОК.y0}),
             int(w * ${КУСОК.x1}), int(h * ${КУСОК.y1})))
s = ImageStat.Stat(k.convert("L")); c = ImageStat.Stat(k)
print(round(s.mean[0], 1), round(s.stddev[0], 1), round(c.mean[2], 1))
`, файл], { encoding: "utf8" }).trim().split(/\s+/).map(Number);
  return { яркость: ч[0], контраст: ч[1], синий: ч[2] };
}

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader",
         "--force-device-scale-factor=1"]
});
const кон = await бр.newContext({
  viewport: экран, deviceScaleFactor: 1,
  isMobile: КТО === "тел", hasTouch: КТО === "тел"
});
const стр = await кон.newPage();
стр.on("pageerror", (e) => console.log("ИСКЛ " + e.message.slice(0, 160)));
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 180000 });
await стр.waitForFunction(() => window.RV_WORLD && window.RV_WORLD["мир"] && window.RV_WORLD["мир"](),
                          null, { timeout: 300000 });
await стр.waitForTimeout(3000);

console.log(`ОДИН КАМЕНЬ ${КТО} ${экран.width}x${экран.height}`);
const снято = [];
let неустоялось = 0;
for (const м of МЕСТА) {
  const ок = await стр.evaluate(([а, д]) => {
    try { window.RV_MOTION["кПунктy"](а, д); return true; } catch (e) { return false; }
  }, [м.акт, м.доля]);
  if (!ок) { console.log(`  ${м.акт} ${м.доля}: к этой доле не встать`); неустоялось++; continue; }
  /* Первый снимок после долгой паузы, второй через ещё одну: сцена этой
     доли доезжает сама, и один снимок про неё ничего не говорит. */
  await стр.waitForTimeout(4000);
  const ф1 = `/tmp/камень-${м.акт}-${м.доля}-а.png`;
  await стр.screenshot({ path: ф1 });
  const а = мерка(ф1);
  await стр.waitForTimeout(2500);
  const ф2 = `/tmp/камень-${м.акт}-${м.доля}-б.png`;
  await стр.screenshot({ path: ф2 });
  const б = мерка(ф2);
  const дрейф = Math.max(Math.abs(а.яркость - б.яркость), Math.abs(а.синий - б.синий));
  const устоялась = дрейф <= ПОКОЙ;
  console.log(`  ${м.акт} ${м.доля} (${м.имя}): яркость ${б.яркость} контраст ${б.контраст} синий ${б.синий}` +
              `   дрейф между снимками ${дрейф.toFixed(1)} ${устоялась ? "" : "- СЦЕНА НЕ УСТОЯЛАСЬ"}`);
  if (!устоялась) неустоялось++;
  снято.push({ м: м, ч: б, устоялась: устоялась });
}
await бр.close();

if (неустоялось) {
  console.log(`ГРЯЗНО  мест с неустоявшейся сценой: ${неустоялось}.`);
  console.log("  судить нельзя: сравнение снимков внутри дрейфа показывает время, а не правку");
  process.exit(1);
}

let грязно = 0;
for (let i = 1; i < снято.length; i++) {
  const а = снято[0], б = снято[i];
  const дЯ = Math.abs(а.ч.яркость - б.ч.яркость);
  const дК = Math.abs(а.ч.контраст - б.ч.контраст);
  const дС = Math.abs(а.ч.синий - б.ч.синий);
  const плохо = дЯ > ДОПУСК.яркость || дК > ДОПУСК.контраст || дС > ДОПУСК.синий;
  if (плохо) грязно++;
  console.log(`  «${а.м.имя}» против «${б.м.имя}»: яркость ${дЯ.toFixed(1)}/${ДОПУСК.яркость}` +
              ` контраст ${дК.toFixed(1)}/${ДОПУСК.контраст} синий ${дС.toFixed(1)}/${ДОПУСК.синий}` +
              `  ${плохо ? "КРАСНОЕ" : "ок"}`);
}
console.log(грязно ? "ГРЯЗНО  камень на стыке меняет вид" : "ЧИСТО  камень один во всех трёх местах");
process.exit(грязно ? 1 : 0);
