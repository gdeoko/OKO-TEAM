/* Проверка: чужой человек ВИДИТ сайт на открытой витрине.

   ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ ПРОВЕРКА. Створов на сайте два: серверный
   (index.php) и браузерный (rv-gate.js). Пока сайт был закрытым стендом,
   они всегда работали в паре: ключ в адресе открывал сразу оба.

   С переходом на открытую витрину сервер стал отдавать плёнку без
   ключа - а браузерный створ ключа не нашёл и закрылся. На боевом
   домене человек получал «Створ закрыт» ПОВЕРХ полностью отданного
   сайта: все акты лежали в разметке и были накрыты заглушкой.

   ПРОВЕРКА CURL'ОМ ЭТОГО НЕ ЛОВИТ, и это здесь главное. В ответе
   сервера всё на месте: двести, заголовок, акты, шрифты, звук.
   Закрывает их скрипт уже в браузере. Поймано снимком живого браузера,
   и только им.

   Поэтому проверка спрашивает не «что в ответе», а «что на экране».

   Запуск: RV_OPEN_URL=http://127.0.0.1:8171 node tools/checks/витрина.mjs
*/
import { браузер, доложить, ПК, ТЕЛЕФОН } from "./общее.mjs";

const АДРЕС = process.env.RV_OPEN_URL || "http://127.0.0.1:8171";
const беды = [];
const б = await браузер();

for (const э of [ПК, ТЕЛЕФОН]) {
  const pg = await б.newPage({
    viewport: э.vp, deviceScaleFactor: э.dpr, isMobile: э.mob, hasTouch: э.mob
  });
  const ошибки = [];
  pg.on("pageerror", (e) => ошибки.push("ИСКЛ: " + e.message.slice(0, 140)));

  /* Заходим ЧУЖИМ: без ключа в адресе, с чистой памятью браузера.
     Именно так придёт человек из бота или из рекламы. */
  await pg.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 90000 });
  await pg.waitForTimeout(7000);

  const в = await pg.evaluate(() => {
    /* Заголовок ПЕРВОГО акта, каким бы он ни назывался. Прежде здесь
       стояло имя «видно» - так звался первый акт по старому сценарию.
       Владелец переписал сценарий на пять экранов, акт стал зваться
       «станция», и проверка честно докладывала, что заголовка не видно,
       хотя он стоял на месте. Имя акта тут вообще ни при чём: человек
       на витрине обязан увидеть ПЕРВЫЕ СЛОВА сайта. */
    const заг = document.querySelector('.rv-акт .rv-заг');
    const створ = document.getElementById("rvСтвор");
    const видим = (э) => {
      if (!э) return false;
      const с = getComputedStyle(э);
      if (с.display === "none" || с.visibility === "hidden") return false;
      if (parseFloat(с.opacity) < 0.05) return false;
      const r = э.getBoundingClientRect();
      return r.width > 8 && r.height > 8;
    };
    return {
      открыт: document.documentElement.classList.contains("rv-открыт"),
      створВиден: видим(створ),
      заголовокВиден: видим(заг),
      заголовок: заг ? (заг.textContent || "").trim().slice(0, 40) : "",
      плёнкаВидна: (function () {
        const п = document.querySelector(".rv-плёнка");
        return п ? getComputedStyle(п).visibility !== "hidden" : false;
      })(),
      актов: document.querySelectorAll(".rv-акт").length,
      /* ── СЛОВА МОГУТ СТОЯТЬ В ОБЪЁМЕ, И ЭТО НЕ БЕДА ─────────────
         Заголовки уехали в сцену (rv-слово3d.js): их рисуют буквами в
         трёхмерном мире, а разметку гасит стиль под признаком
         рв-слова-в-сцене. Разметка при этом ОСТАЁТСЯ - для поисковика
         и для тех, кто пришёл без объёма, - но человеку на витрине
         слова показывает мир, а не она.

         Проверка требовала видимого h2 и потому краснела ровно на том
         устройстве, где всё работает лучше всего. Спрашиваем оба пути:
         либо разметка видна, либо слова подняты в объём. */
      словаВОбъёме: document.documentElement.classList.contains("рв-слова-в-сцене"),
      высота: document.documentElement.scrollHeight,
      окно: innerHeight
    };
  });

  const где = э.имя;
  if (!в.открыт) беды.push(`${где}: браузерный створ не открылся на витрине`);
  if (в.створВиден) беды.push(`${где}: заглушка «Створ закрыт» видна на открытом сайте`);
  if (!в.плёнкаВидна) беды.push(`${где}: плёнка спрятана оформлением`);
  /* Либо разметка видна, либо слова подняты в объём: и то и другое
     означает, что человек первые слова сайта ВИДИТ. Разметка при этом
     обязана быть на месте всегда - для поисковика и для тех, кто
     пришёл без объёма. */
  if (!в.заголовокВиден && !в.словаВОбъёме) {
    беды.push(`${где}: заголовок первого акта не виден человеку («${в.заголовок}»)`);
  }
  if (!в.заголовок) беды.push(`${где}: заголовка нет в разметке вовсе`);
  /* Сколько актов - решает сценарий, а не проверка. Стояло восемь по
     старому плану, стало шесть по пяти экранам владельца, и завтра
     станет иначе. Смысл мерки в другом: витрина обязана отдавать ФИЛЬМ,
     а не одну заглушку. Четыре это заведомо фильм. */
  if (в.актов < 4) беды.push(`${где}: актов на странице ${в.актов}, ждали хотя бы четыре`);
  /* Лента обязана быть лентой: если высота документа близка к окну,
     содержимое не собралось и крутить нечего. */
  if (в.высота < в.окно * 8) {
    беды.push(`${где}: лента короче восьми экранов (${в.высота} при окне ${в.окно})`);
  }

  await pg.close();
  for (const о of ошибки) беды.push(`${где}: ${о}`);
  console.log(`${где.padEnd(9)} открыт=${в.открыт} заглушка=${в.створВиден} ` +
              `заголовок=${в.заголовокВиден} объём=${в.словаВОбъёме} актов=${в.актов} ` +
              `лента=${Math.round(в.высота / в.окно)} экранов`);
}

await б.close();
доложить("витрина: чужой человек видит сайт", беды);
