/* ОДИН КАМЕНЬ НА ВЕСЬ ФИЛЬМ.

   ЗАЧЕМ. Кладок в фильме три: дом (объект «кладка», rv-act-станция.js),
   стена периметра и тоннель («кирпичи прокола», rv-кирпичи.js) и ракета
   в зале («кирпичи ракеты», rv-ракета-кирпичи.js). Любое расхождение
   между ними читается подменой материала, и владелец писал об этом не
   один десяток раз.

   ПОЧЕМУ ПРОВЕРКА ПЕРЕПИСАНА. Прежняя сверяла стык актов: станцию на
   0.92 против периметра на 0.08. Ровно в этой точке обе кладки уже
   сведены к одной сетке, камень к камню, и проверка печатала «чисто» -
   а владелец смотрел на ленту и писал «подмена стены осталась». Мерили
   то место, где расхождения быть не может по устройству.

   Замер живой сцены показал, где оно есть:

     станция 0.10   дом      2.075 x 1.503     стена 1.194 x 0.673
     станция 0.50   дом      1.877 x 1.473     стена 1.194 x 0.673
     станция 0.92   дом      1.194 x 0.673     стена 1.194 x 0.673

   Блок дома ВТРОЕ крупнее кирпича стены по площади и ужимается до него
   за весь акт. Это по сценарию: дом сложен крупным камнем, как иглу у
   igloo. Беда была в другом - фотоскан ложился фиксированным числом
   плиток на грань любого размера, поэтому зерно породы на доме выходило
   вдвое крупнее, чем на стене, и менялось прямо в полёте. Одна порода
   не может иметь два зерна; глаз читает это как два материала.

   Плюс обе кладки стояли в кадре РАЗОМ: на станции 0.10 замер нашёл и
   дом, и стену периметра. Правило «в кадре ровно одна кладка» держали
   периметр и прокол, а кадр идёт только у того акта, что на экране.

   ЧТО ПРОВЕРЯЕТСЯ ТЕПЕРЬ
     1. Зерно привязано к мировому размеру камня (vUv * vRazmer), а не к
        постоянному числу плиток. Это читается в самом шейдере: уравнять
        материал в коде и разойтись в кадре тут нельзя.
     2. В актах стены в кадре ровно одна кладка.
     3. На стыке размер камня, зерно и светлота совпадают.
     4. У всех кладок есть развёртка и доехавший фотоскан.

   Запуск: node tools/checks/кирпич.mjs [адрес] */
import { chromium } from "playwright";
import { execFileSync } from "node:child_process";
import { БРАУЗЕР } from "../браузер.mjs";

const АДРЕС = process.env.RV_URL || process.argv[2] || "http://127.0.0.1:8170";
/* Пороги. Размер камня на стыке обязан совпасть точно (это одно число
   из одной сетки), поверхность меряется картинкой и имеет право
   разойтись на четверть: у дома светятся швы, и совсем ровно не будет
   никогда. */
const ПОРОГ_РАЗМЕРА = 0.02;
const ПОРОГ_ЗЕРНА = 0.35;
const ПОРОГ_СВЕТЛОТЫ = 12;

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"]
});
const стр = await бр.newPage({ viewport: { width: 1440, height: 900 } });
const беды = [];
стр.on("pageerror", (e) => беды.push("ИСКЛ " + e.message.slice(0, 160)));
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 120000 });
await стр.waitForFunction(
  () => window.RV_WORLD && window.RV_WORLD["вступлениеИдёт"] && !window.RV_WORLD["вступлениеИдёт"](),
  null, { timeout: 240000 }).catch(() => {});
await стр.waitForTimeout(1500);

async function встать(акт, доля) {
  await стр.evaluate(([и, x]) => window.RV_MOTION["кПунктy"](и, x), [акт, доля]);
  let было = null, тихих = 0, кругов = 0;
  while (тихих < 3 && кругов < 60) {
    const п = await стр.evaluate(() => {
      const c = window.RV_WORLD["мир"]().cam.position; return [c.x, c.y, c.z];
    });
    if (было) {
      const d = Math.hypot(п[0] - было[0], п[1] - было[1], п[2] - было[2]);
      тихих = d < 0.02 ? тихих + 1 : 0;
    }
    было = п; кругов++;
    await стр.waitForTimeout(250);
  }
}

/* Все кладки сцены разом: видимые и скрытые. Размер меряется по МИРОВОЙ
   матрице экземпляра - местный масштаб ничего не значит, купол стоит в
   своей группе со своим множителем, а ракета в зале со своим. */
async function кладки() {
  return стр.evaluate(() => {
    const мир = window.RV_WORLD["мир"](), T = мир.T, из = [];
    мир.scene.traverse((о) => {
      if (!о.isInstancedMesh) return;
      if (!/^(кладка|кирпичи прокола|кирпичи ракеты)$/.test(о.name || "")) return;
      let p = о, видно = true;
      while (p) { if (!p.visible) { видно = false; break; } p = p.parent; }
      о.updateMatrixWorld();
      const m = new T.Matrix4(), s = new T.Vector3(), поз = new T.Vector3(), q = new T.Quaternion();
      let ш = 0, в = 0, n = 0;
      const шаг = Math.max(1, Math.floor(о.count / 12));
      for (let i = 0; i < о.count; i += шаг) {
        о.getMatrixAt(i, m); m.premultiply(о.matrixWorld); m.decompose(поз, q, s);
        ш += Math.abs(s.x); в += Math.abs(s.y); n++;
      }
      const ф = о.material.fragmentShader || "";
      из.push({
        имя: о.name, видно: видно,
        ширина: +(ш / n).toFixed(3), высота: +(в / n).toFixed(3),
        развёртка: !!о.geometry.attributes.uv,
        фотоскан: !!(о.material.uniforms && о.material.uniforms.tBlok && о.material.uniforms.tBlok.value),
        доляТекстуры: о.material.uniforms && о.material.uniforms.uTex ? о.material.uniforms.uTex.value : null,
        /* Зерно от мирового размера камня. Строка одна на оба шейдера:
           разъедься она - вернётся то самое «гладкий дом, шершавая
           стена». */
        зерноПоМиру: /vUv\s*\*\s*vRazmer/.test(ф)
      });
    });
    return из;
  });
}

/* Поверхность меряется по картинке: зерно (средний перепад яркости
   между соседями) и светлота. Один и тот же кусок кадра у обеих стен -
   середина экрана, где стена и стоит. */
function поверхность(файл) {
  const из = execFileSync("python3", ["-c", `
import sys, statistics
from PIL import Image
im = Image.open(sys.argv[1]).convert("L").crop((350, 380, 1050, 560))
w, h = im.size
d = list(im.getdata())
g = [abs(d[y*w+x+1]-d[y*w+x-1]) + abs(d[(y+1)*w+x]-d[(y-1)*w+x])
     for y in range(1, h-1, 2) for x in range(1, w-1, 2)]
print(round(sum(g)/len(g), 2), round(statistics.median(d), 1))
`, файл], { encoding: "utf8" }).trim().split(/\s+/).map(Number);
  return { зерно: из[0], светлота: из[1] };
}

/* Четыре места вместо двух. Два первых ловят подмену там, где она
   видна: целый дом против стены периметра. Два последних держат стык,
   ради которого проверка и заводилась. */
const места = [
  ["станция", 0.10, "/tmp/кирпич-иглу.png", "одна"],
  ["станция", 0.92, "/tmp/кирпич-дом.png", "одна"],
  ["периметр", 0.08, "/tmp/кирпич-периметр.png", "одна"],
  ["прокол", 0.30, "/tmp/кирпич-тоннель.png", "любая"]
];
const собрано = [];
for (const [акт, доля, файл, сколько] of места) {
  await встать(акт, доля);
  const к = await кладки();
  await стр.screenshot({ path: файл });
  собрано.push({ акт: акт, доля: доля, сколько: сколько, кладки: к, кадр: поверхность(файл) });
}
await бр.close();

const красное = [];
const видимые = (с) => с.кладки.filter((к) => к.видно);

for (const с of собрано) {
  const где = `${с.акт} ${с.доля}`;
  const в = видимые(с);
  if (!в.length) { красное.push(`${где}: кладки в кадре нет вовсе`); continue; }
  /* Ракета в зале стоит рядом со стеной законно: это разные предметы в
     разных местах, а не две стены в одной плоскости. */
  const стены = в.filter((к) => к.имя !== "кирпичи ракеты");
  if (с.сколько === "одна" && стены.length > 1) {
    красное.push(`${где}: в кадре ${стены.length} кладки разом - ` +
                 стены.map((к) => `${к.имя} ${к.ширина}x${к.высота}`).join(", "));
  }
  for (const к of в) {
    if (!к.развёртка) красное.push(`${где}: у «${к.имя}» нет развёртки - фотоскан не читается, камень выйдет пластиком`);
    if (!к.фотоскан) красное.push(`${где}: у «${к.имя}» фотоскан не доехал`);
    if (к.доляТекстуры !== 1) красное.push(`${где}: у «${к.имя}» доля фотоскана ${к.доляТекстуры}, а не 1`);
    if (!к.зерноПоМиру) {
      красное.push(`${где}: у «${к.имя}» зерно не привязано к размеру камня - ` +
                   `на крупном блоке порода выйдет крупнее, это и есть подмена стены`);
    }
  }
}

/* Стык: дом уже стал стеной, периметр её принимает. Здесь обязаны
   сойтись и размер камня, и поверхность в кадре. */
const дом = собрано.find((с) => с.акт === "станция" && с.доля === 0.92);
const пер = собрано.find((с) => с.акт === "периметр");
if (дом && пер && видимые(дом).length && видимые(пер).length) {
  const а = видимые(дом)[0], б = видимые(пер)[0];
  const дШ = Math.abs(а.ширина - б.ширина) / Math.max(а.ширина, б.ширина);
  const дВ = Math.abs(а.высота - б.высота) / Math.max(а.высота, б.высота);
  if (дШ > ПОРОГ_РАЗМЕРА || дВ > ПОРОГ_РАЗМЕРА) {
    красное.push(`стык: размер камня разошёлся - дом ${а.ширина}x${а.высота}, ` +
                 `периметр ${б.ширина}x${б.высота}`);
  }
  const дЗ = Math.abs(дом.кадр.зерно - пер.кадр.зерно) / Math.max(дом.кадр.зерно, пер.кадр.зерно);
  if (дЗ > ПОРОГ_ЗЕРНА) {
    красное.push(`стык: зерно поверхности разошлось - дом ${дом.кадр.зерно}, ` +
                 `периметр ${пер.кадр.зерно} (на ${Math.round(дЗ * 100)}%)`);
  }
  const дС = Math.abs(дом.кадр.светлота - пер.кадр.светлота);
  if (дС > ПОРОГ_СВЕТЛОТЫ) {
    красное.push(`стык: светлота разошлась - дом ${дом.кадр.светлота}, периметр ${пер.кадр.светлота}`);
  }
}
for (const б of беды) красное.push(б);

for (const с of собрано) {
  const в = видимые(с);
  console.log(`${с.акт} ${с.доля}: ` +
    (в.length ? в.map((к) => `${к.имя} ${к.ширина}x${к.высота}` +
      `${к.зерноПоМиру ? "" : " БЕЗ ЗЕРНА ПО МИРУ"}`).join(" | ") : "пусто") +
    `, зерно ${с.кадр.зерно}, светлота ${с.кадр.светлота}`);
}
if (красное.length) {
  console.log("\nКРАСНОЕ кирпич:");
  for (const с of красное) console.log("  " + с);
  process.exit(1);
}
console.log("\nЧИСТО кирпич: один камень, одна кладка в кадре");
