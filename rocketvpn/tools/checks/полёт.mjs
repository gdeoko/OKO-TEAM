/* Проверка: камера ЕДЕТ через весь сайт одним ходом.

   Проверяется не впечатление, а числа:
   1. на каждом шаге доли прокрутки камера сдвинулась заметно (нет
      мёртвых кусков, где мир стоит);
   2. ход обратим - те же доли, пройденные вверх, дают те же точки;
   3. в кадре есть содержимое (кадр не чёрный) там, где оно должно быть;
   4. приход из космоса Rocket CDN сажает камеру сразу к станции выхода,
      а не заставляет её проехать всю ленту.

   Заодно кладёт ленту кадров НА СТОРОНУ, а не в дерево проекта:
   смотреть их глазами обязательно (числа чёрный экран уже дважды
   пропускали), но десятки мегабайт снимков в репозитории - мусор.
   Путь можно задать переменной RV_СНИМКИ. */
import { mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { браузер, открыть, ПК, ТЕЛЕФОН, доложить } from "./общее.mjs";

const беды = [];
const b = await браузер();
const КУДА = (process.env.RV_СНИМКИ || join(tmpdir(), "rv-снимки")) + "/";
mkdirSync(КУДА, { recursive: true });
console.log("снимки: " + КУДА);

const ШАГИ = 11;   /* доли 0, 0.1 ... 1.0 */

async function поставить(pg, доля) {
  await pg.evaluate((д) => {
    const h = document.documentElement.scrollHeight - innerHeight;
    window.scrollTo(0, Math.round(h * д));
  }, доля);
  await pg.waitForTimeout(420);
  return pg.evaluate(() => (window.RV_WORLD && window.RV_WORLD["ход"] ? window.RV_WORLD["ход"]() : null));
}

for (const э of [ПК, ТЕЛЕФОН]) {
  const { pg, ошибки } = await открыть(b, э, {});
  const лента = [];

  for (let i = 0; i < ШАГИ; i++) {
    const д = i / (ШАГИ - 1);
    const х = await поставить(pg, д);
    лента.push({ д, х });
    const имя = `${КУДА}полёт-${э.имя}-${String(i).padStart(2, "0")}.png`;
    await pg.screenshot({ path: имя });
  }

  /* 1. Мёртвые куски. Камера обязана идти на каждом шаге. */
  let всего = 0;
  const стоянки = [];
  for (let i = 1; i < лента.length; i++) {
    const a = лента[i - 1].х, c = лента[i].х;
    if (!a || !c || !a.камера || !c.камера) { беды.push(э.имя + ": ядро не отдало ход камеры"); break; }
    const s = Math.hypot(c.камера[0] - a.камера[0], c.камера[1] - a.камера[1], c.камера[2] - a.камера[2]);
    всего += s;
    /* Порог шесть единиц на десятую долю ленты. Он не взят с потолка:
       самый медленный кусок сайта - «Рубка», и медленный он законно
       (щит стоит вплотную к тексту, наезжать на него некуда, работает
       дуга). Замер даёт там девять-десять единиц. До правки на том же
       куске было три - вот это и есть стояние, которое порог обязан
       ловить. */
    if (s < 6) стоянки.push(`${лента[i - 1].д.toFixed(1)}->${лента[i].д.toFixed(1)}: ${s.toFixed(1)}`);
  }
  if (стоянки.length) беды.push(э.имя + ": камера стоит на кусках " + стоянки.join(", "));
  if (всего < 900) беды.push(э.имя + ": за весь сайт камера прошла всего " + Math.round(всего) + " единиц");

  /* 2. Обратимость. Идём вверх по тем же долям и сравниваем. */
  const назад = [];
  for (let i = ШАГИ - 1; i >= 0; i--) назад.push(await поставить(pg, i / (ШАГИ - 1)));
  for (let i = 0; i < ШАГИ; i++) {
    const впер = лента[ШАГИ - 1 - i].х, обр = назад[i];
    if (!впер || !обр || !впер.камера || !обр.камера) continue;
    const р = Math.hypot(обр.камера[0] - впер.камера[0], обр.камера[1] - впер.камера[1], обр.камера[2] - впер.камера[2]);
    if (р > 1.5) {
      беды.push(`${э.имя}: ход не обратим на доле ${лента[ШАГИ - 1 - i].д.toFixed(1)}, разошлись на ${р.toFixed(1)}`);
    }
  }

  /* 3. Кадр не чёрный там, где идёт объёмный акт. Считаем среднюю
     яркость холста мира прямо в браузере: снимок страницы сюда не
     годится, поверх него лежит разметка. */
  for (const [имя, доля] of [["оболочка", 0.5], ["прокол", 0.5], ["выход", 0.5], ["рубка", 0.5], ["стыковка", 0.5]]) {
    await pg.evaluate(([и, д]) => {
      if (window.RV_MOTION && window.RV_MOTION["кПунктy"]) window.RV_MOTION["кПунктy"](и, д);
    }, [имя, доля]);
    await pg.waitForTimeout(900);
    /* Яркость снимаем ЧИТКОЙ БУФЕРА в том же кадре, в котором ядро
       нарисовало сцену. Через drawImage нельзя: у холста мира не
       сохраняется буфер рисования, и копия выходит пустой всегда -
       именно так эта проверка сначала объявила чёрными все пять актов,
       хотя на снимках экрана они были на месте. */
    const ярко = await pg.evaluate(() => new Promise((готово) => {
      /* Два кадра, а не один. Первый может прийтись на кадр, в котором
         ядро ещё не рисовало (акт только что стал видимым), и тогда
         буфер пуст не потому, что сцена чёрная. Один кадр запаса
         однажды уже объявил акт «Выход» чёрным на ровном месте. */
      requestAnimationFrame(() => requestAnimationFrame(() => {
        const c = document.getElementById("rvМир");
        if (!c) return готово(-1);
        const gl = c.getContext("webgl2") || c.getContext("webgl");
        if (!gl) return готово(-2);
        const ш = gl.drawingBufferWidth, в = gl.drawingBufferHeight;
        const бук = new Uint8Array(ш * в * 4);
        gl.readPixels(0, 0, ш, в, gl.RGBA, gl.UNSIGNED_BYTE, бук);
        let s = 0, n = 0, mx = 0;
        for (let i = 0; i < бук.length; i += 4 * 37) {
          const v = (бук[i] + бук[i + 1] + бук[i + 2]) / 3 * (бук[i + 3] / 255);
          s += v; if (v > mx) mx = v; n++;
        }
        готово({ средняя: Math.round(s / n * 100) / 100, макс: Math.round(mx) });
      }));
    }));
    if (ярко.средняя < 0.3 || ярко.макс < 40) {
      беды.push(`${э.имя}: акт «${имя}» на середине даёт пустой кадр (средняя ${ярко.средняя}, макс ${ярко.макс})`);
    }
  }

  await pg.close();
  for (const о of ошибки) беды.push(э.имя + ": " + о);
}

/* 4. Приход из космоса: камера обязана сразу оказаться у станции
   выхода, а не проехать к ней всю ленту. */
for (const э of [ПК, ТЕЛЕФОН]) {
  const { pg } = await открыть(b, э, { from: "cdn" });
  const х = await pg.evaluate(() => (window.RV_WORLD ? window.RV_WORLD["ход"]() : null));
  if (!х) беды.push(э.имя + ": ядро не отдало ход после прихода из космоса");
  else {
    /* Станция «Выход» третья по счёту, её узел на кривой - восьмой
       (пролог, потом по три на станцию). Ждём камеру рядом с ним. */
    if (!(х.место > 6.4 && х.место < 8.6)) {
      беды.push(э.имя + ": пришедший из космоса встал на месте кривой " + х.место + ", ждали 6.4..8.6");
    }
    if (х.видны.indexOf("выход") < 0) беды.push(э.имя + ": станции выхода нет в кадре после прихода");
    /* Мало числиться в кадре - надо в нём БЫТЬ. Приход случается в
       первую секунду, когда акт ещё собирается, и его узел легко
       остаётся спрятанным: человек получает звёздное поле без планеты,
       а все числа при этом сходятся. */
    const виден = await pg.evaluate(() => (window.RV_ВЫХОД ? window.RV_ВЫХОД["состояние"]()["виден"] : null));
    if (!виден) беды.push(э.имя + ": после прихода из космоса узел акта выхода спрятан");
  }
  await pg.screenshot({ path: `${КУДА}приход-${э.имя}.png` });
  await pg.close();
}

await b.close();
доложить("полёт", беды);
