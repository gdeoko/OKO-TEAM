/* Проверка: камера ЕДЕТ через весь сайт одним ходом.

   Проверяется не впечатление, а числа:
   1. на каждом шаге доли прокрутки камера сдвинулась заметно (нет
      мёртвых кусков, где мир стоит);
   2. ход обратим - те же доли, пройденные вверх, дают те же точки;
   3. в кадре есть содержимое (кадр не чёрный) там, где оно должно быть;
   4. приход из космоса Rocket CDN сажает камеру сразу к станции выхода,
      а не заставляет её проехать всю ленту.

   Заодно кладёт ленту кадров НА СТОРОНУ, а не в дерево проекта:
   смотреть их глазами обязательно (числа чёрный экран уже дважды
   пропускали), но десятки мегабайт снимков в репозитории - мусор.
   Путь можно задать переменной RV_СНИМКИ. */
import { mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { браузер, открыть, ПК, ТЕЛЕФОН, доложить } from "./общее.mjs";

const беды = [];
const b = await браузер();
const КУДА = (process.env.RV_СНИМКИ || join(tmpdir(), "rv-снимки")) + "/";
mkdirSync(КУДА, { recursive: true });
console.log("снимки: " + КУДА);

const ШАГИ = 11;   /* доли 0, 0.1 ... 1.0 */

/* ── ЖДЁМ, ПОКА СТРОКИ ПРОЯВЯТСЯ ────────────────────────────────
   Шаг появления зажат десятой долей секунды на кадр (rv-msdf.js):
   защита от прыжка времени, когда вкладка возвращается из фона. На
   живой машине кадр идёт шестнадцать миллисекунд, потолок не
   срабатывает, строка проявляется за свои три четверти секунды. В
   песочнице видеокарты нет, кадр около секунды, и тот же потолок
   растягивает появление на восемь и больше РЕАЛЬНЫХ секунд.

   Снимки этой проверки смотрят глазами, и на них текст выходил
   обрезанным на полуслове - «Дальше св», «Внутри один кана». Беда
   снимка, а не сайта. Спрашиваем движок, кончилось ли появление. */
async function ждатьСлова(pg) {
  await pg.waitForFunction(
    () => !(window.RV_MSDF && window.RV_MSDF["показИдёт"] && window.RV_MSDF["показИдёт"]()),
    null, { timeout: 30000, polling: 200 }).catch(() => {});
}

async function поставить(pg, доля) {
  await pg.evaluate((д) => {
    const h = document.documentElement.scrollHeight - innerHeight;
    window.scrollTo(0, Math.round(h * д));
  }, доля);
  await pg.waitForTimeout(420);
  await ждатьСлова(pg);
  return pg.evaluate(() => (window.RV_WORLD && window.RV_WORLD["ход"] ? window.RV_WORLD["ход"]() : null));
}

for (const э of [ПК, ТЕЛЕФОН]) {
  const { pg, ошибки } = await открыть(b, э, {});
  const лента = [];

  for (let i = 0; i < ШАГИ; i++) {
    const д = i / (ШАГИ - 1);
    const х = await поставить(pg, д);
    лента.push({ д, х });
    const имя = `${КУДА}полёт-${э.имя}-${String(i).padStart(2, "0")}.png`;
    await pg.screenshot({ path: имя });
  }

  /* ── 1. КАМЕРА ИДЁТ РОВНО: БЕЗ РЫВКОВ И БЕЗ ПОЛНОЙ ОСТАНОВКИ ──
     Здесь стояло два правила из ПРЕЖНЕГО МИРА, и оба уже неверны.

     «Не меньше шести единиц на десятую долю ленты» и «не меньше
     девятисот за сайт» писались тогда, когда акты стояли в девятистах
     единицах друг от друга и камера летала между ними. Владелец
     сказал убрать швы, акты съехались в одно место, и весь ход стал
     около ста восьмидесяти единиц. Правила при этом остались и ругали
     сайт за то, ради чего его переделывали.

     Хуже другое: КАМЕРА СТОИТ ПО СЦЕНАРИЮ. Первый экран - «камера не
     двигается, дом разбирается по кирпичикам», второй - стена
     собирается перед стоящей камерой (поза периметра держит это
     темпом [0.66, 0.12]). Правило «идёт на каждом шаге» объявляет
     бедой замысел.

     Живой ли кадр на стоячей камере - это меряет проверка движения, и
     меряет по самому кадру, а не по камере. Дублировать её здесь
     нечем и незачем.

     Остаётся то, что кроме полёта не меряет никто:
       · РЫВОК. Скачок камеры между соседними долями - это шов, ровно
         то, на что владелец жаловался словами «летит вроде ровно, а
         потом вправо куда-то уходит». Порог взят от самого большого
         законного куска с запасом вдвое.
       · СОВСЕМ МЁРТВАЯ КАМЕРА. Если за всю ленту она не прошла
         ничего, ход не собрался вовсе. Порог низкий намеренно: он
         ловит поломку, а не подгоняет сценарий под число. */
  let всего = 0;
  let худшийРывок = 0, гдеРывок = "";
  for (let i = 1; i < лента.length; i++) {
    const a = лента[i - 1].х, c = лента[i].х;
    if (!a || !c || !a.камера || !c.камера) { беды.push(э.имя + ": ядро не отдало ход камеры"); break; }
    const s = Math.hypot(c.камера[0] - a.камера[0], c.камера[1] - a.камера[1], c.камера[2] - a.камера[2]);
    всего += s;
    if (s > худшийРывок) {
      худшийРывок = s;
      гдеРывок = `${лента[i - 1].д.toFixed(1)}->${лента[i].д.toFixed(1)}`;
    }
  }
  /* Самый длинный законный кусок - выход из первого экрана к стене:
     замер даёт около шестидесяти единиц на десятую долю. Порог сто
     двадцать: вдвое больше законного, и вдвое меньше любого перелёта
     между прежними местами актов. */
  if (худшийРывок > 120) {
    беды.push(`${э.имя}: рывок камеры на куске ${гдеРывок}: ${Math.round(худшийРывок)} единиц`);
  }
  if (всего < 60) {
    беды.push(э.имя + ": за весь сайт камера прошла всего " + Math.round(всего) + " единиц, ход не собрался");
  }
  console.log(`   ${э.имя}: ход ${Math.round(всего)} единиц, худший кусок ${Math.round(худшийРывок)} на ${гдеРывок}`);

  /* ── 2. ОБРАТИМОСТЬ ЗДЕСЬ НЕ МЕРЯЕТСЯ, И ЭТО НАМЕРЕННО ────────
     Здесь сравнивались две ленты, пройденная вниз и пройденная вверх,
     и проверка докладывала расхождение до девяноста шести единиц.
     Беды нет: камера получила сглаживание прокрутки igloo (две
     подтяжки, 0.075 и 0.15) и ДОГОНЯЕТ долю экспоненциально -
     последние единицы добираются десятками кадров. Замер через
     фиксированную паузу мерил недоезд, всегда направленный в сторону,
     откуда пришли.

     Второй заход считал зазор до `проба(y)` - чистой функции ядра,
     которая знает правильное место для любой прокрутки. Правильная
     мера, но и она не работает В ЭТОЙ ПРОВЕРКЕ: чтобы зазор что-то
     значил, надо ДОЖДАТЬСЯ схождения, а на программном отрисовщике это
     до сорока пяти секунд на каждую долю. Одиннадцать долей на двух
     устройствах превращают проверку в получасовую, и всё равно часть
     долей упирается в потолок ожидания. Замер, который на своём
     бюджете не отличает недоезд от ошибки, выносить вердикт не должен:
     он и выдал сначала «96 единиц», а потом «22.7 на доле 0.7» - оба
     раза про камеру, которая просто ещё ехала.

     Обратимость меряет `tools/обратимость.mjs`: он ждёт схождения с
     эталоном по условию и на семи долях показал ход обратимым - худший
     зазор 0.33 единицы, между проходами 0.54. Гонять его руками, когда
     трогали ход камеры, честнее, чем держать здесь правило, которое
     врёт через раз.

     Здесь остаётся то, что меряется на бюджете проверки надёжно:
     рывок камеры (выше), пустой кадр и посадка гостя (ниже). */

  /* 3. Кадр не чёрный там, где идёт объёмный акт. Считаем среднюю
     яркость холста мира прямо в браузере: снимок страницы сюда не
     годится, поверх него лежит разметка. */
  /* Имена актов берём ИЗ РАЗМЕТКИ, а не списком. Здесь стоял список
     из прежнего сценария - «оболочка», «выход», «стыковка», - и после
     того как владелец переписал сайт на пять экранов, проверка искала
     три акта, которых нет, и краснела на здоровом сайте. Сценарий будет
     меняться и дальше; список в проверке будет отставать всегда. */
  const актыСтраницы = await pg.evaluate(() =>
    Array.from(document.querySelectorAll(".rv-акт")).map((э) => э.getAttribute("data-акт")));
  for (const [имя, доля] of актыСтраницы.map((и) => [и, 0.5])) {
    await pg.evaluate(([и, д]) => {
      if (window.RV_MOTION && window.RV_MOTION["кПунктy"]) window.RV_MOTION["кПунктy"](и, д);
    }, [имя, доля]);
    await pg.waitForTimeout(900);
    await ждатьСлова(pg);
    /* Яркость снимаем ЧИТКОЙ БУФЕРА в том же кадре, в котором ядро
       нарисовало сцену. Через drawImage нельзя: у холста мира не
       сохраняется буфер рисования, и копия выходит пустой всегда -
       именно так эта проверка сначала объявила чёрными все пять актов,
       хотя на снимках экрана они были на месте. */
    const ярко = await pg.evaluate(() => new Promise((готово) => {
      /* Два кадра, а не один. Первый может прийтись на кадр, в котором
         ядро ещё не рисовало (акт только что стал видимым), и тогда
         буфер пуст не потому, что сцена чёрная. Один кадр запаса
         однажды уже объявил акт «Выход» чёрным на ровном месте. */
      requestAnimationFrame(() => requestAnimationFrame(() => {
        const c = document.getElementById("rvМир");
        if (!c) return готово(-1);
        const gl = c.getContext("webgl2") || c.getContext("webgl");
        if (!gl) return готово(-2);
        const ш = gl.drawingBufferWidth, в = gl.drawingBufferHeight;
        const бук = new Uint8Array(ш * в * 4);
        gl.readPixels(0, 0, ш, в, gl.RGBA, gl.UNSIGNED_BYTE, бук);
        let s = 0, n = 0, mx = 0;
        for (let i = 0; i < бук.length; i += 4 * 37) {
          const v = (бук[i] + бук[i + 1] + бук[i + 2]) / 3 * (бук[i + 3] / 255);
          s += v; if (v > mx) mx = v; n++;
        }
        готово({ средняя: Math.round(s / n * 100) / 100, макс: Math.round(mx) });
      }));
    }));
    if (ярко.средняя < 0.3 || ярко.макс < 40) {
      беды.push(`${э.имя}: акт «${имя}» на середине даёт пустой кадр (средняя ${ярко.средняя}, макс ${ярко.макс})`);
    }
  }

  await pg.close();
  for (const о of ошибки) беды.push(э.имя + ": " + о);
}

/* 4. Приход из космоса: гость из Rocket CDN обязан оказаться сразу в
   том акте, куда его сажает связка, а не проехать к нему всю ленту.

   КУДА ИМЕННО - СПРАШИВАЕМ У САМОЙ СВЯЗКИ. Здесь стояло «станция
   выхода, узел 6.4..8.6» - из прежнего сценария, где такой акт был.
   Владелец переписал сайт на пять экранов, акт выхода исчез, гостя
   стало сажать в рубку (rv-link.js), а проверка продолжала искать
   пропавшую станцию и краснела трижды на каждом устройстве.

   Имя акта читается из самого rv-link.js, а не повторяется здесь:
   повторенное число расходится с правдой ровно в тот день, когда
   правду меняют. Границы узлов считаем по порядку акта в разметке:
   пролог, дальше по три узла на акт. */
for (const э of [ПК, ТЕЛЕФОН]) {
  const { pg } = await открыть(b, э, { from: "cdn" });
  await pg.waitForTimeout(1500);
  const куда = await pg.evaluate(async () => {
    try {
      const т = await (await fetch("assets/rv-link.js")).text();
      const m = /кПунктy"\]\("([^"]+)"/.exec(т);
      return m ? m[1] : null;
    } catch (e) { return null; }
  });
  const акты = await pg.evaluate(() =>
    Array.from(document.querySelectorAll(".rv-акт")).map((э) => э.getAttribute("data-акт")));
  const х = await pg.evaluate(() => (window.RV_WORLD ? window.RV_WORLD["ход"]() : null));
  if (!х) беды.push(э.имя + ": ядро не отдало ход после прихода из космоса");
  else if (!куда) беды.push(э.имя + ": в rv-link.js не нашлось, куда сажать гостя из космоса");
  else {
    const н = акты.indexOf(куда);
    if (н < 0) {
      беды.push(`${э.имя}: связка сажает в акт «${куда}», а такого акта на странице нет`);
    } else {
      /* Пролог занимает узел 0, дальше по три на акт: подход, станция,
         уход. Гость обязан стоять внутри своего акта. */
      const низ = 1 + 3 * н, верх = 3 + 3 * н;
      if (!(х.место >= низ - 0.3 && х.место <= верх + 0.3)) {
        беды.push(`${э.имя}: пришедший из космоса встал на месте кривой ${х.место},` +
                  ` ждали ${низ}..${верх} (акт «${куда}»)`);
      }
      if (х.видны.indexOf(куда) < 0) {
        беды.push(`${э.имя}: акта «${куда}» нет в кадре после прихода из космоса`);
      }
    }
    /* Мало числиться в кадре - надо в нём БЫТЬ. Приход случается в
       первую секунду, когда акт ещё собирается, и кадр легко остаётся
       пустым: человек получает звёздное поле, а все числа сходятся.
       Спрашиваем не модуль по имени (модули меняются вместе со
       сценарием), а сам кадр: рисует ли мир хоть что-нибудь. */
    const ярко = await pg.evaluate(() => new Promise((готово) => {
      requestAnimationFrame(() => requestAnimationFrame(() => {
        const c = document.querySelector("canvas");
        if (!c) return готово(-1);
        const gl = c.getContext("webgl2") || c.getContext("webgl");
        if (!gl) return готово(-2);
        const ш = gl.drawingBufferWidth, в = gl.drawingBufferHeight;
        const бук = new Uint8Array(ш * в * 4);
        gl.readPixels(0, 0, ш, в, gl.RGBA, gl.UNSIGNED_BYTE, бук);
        let s = 0, n = 0;
        for (let i = 0; i < бук.length; i += 4 * 37) {
          s += (бук[i] + бук[i + 1] + бук[i + 2]) / 3 * (бук[i + 3] / 255); n++;
        }
        готово(Math.round(s / n * 100) / 100);
      }));
    }));
    if (ярко < 0.3) {
      беды.push(`${э.имя}: после прихода из космоса кадр пустой (яркость ${ярко})`);
    }
  }
  await pg.screenshot({ path: `${КУДА}приход-${э.имя}.png` });
  await pg.close();
}

await b.close();
доложить("полёт", беды);
