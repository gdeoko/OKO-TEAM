/* Стоянки камеры и возвраты назад.

   ЗАЧЕМ ОТДЕЛЬНАЯ ПРОВЕРКА. Владелец описал ход камеры двумя правилами,
   и оба про то, чего быть НЕ должно:

     «камера стоит на месте пока ракета перед нами, текст сверху ракеты,
      потом текст пропадает, двери открываются и камера вперёд»
     «то вроде в туннель заходит и потом в сторону зачем-то улетает»

   То есть там, где обещана стоянка, камера обязана стоять по-настоящему,
   а дальше идти только вперёд. Соседняя `ход-камеры.mjs` меряет ровность:
   угловую скорость, полёт боком, зазоры до железа. Стоянку она не ловит
   вовсе - стоящая камера для неё образцово ровная, - и возврат назад
   тоже: ехать задом наперёд можно совершенно плавно.

   ЧТО МЕРЯЕТСЯ.

   1. СТОЯНКА. Акт объявляет её парой чисел `темп: [держим, ползком]`
      (см. rv-world.js). «Держим» это доля акта, до которой камера почти
      стоит, «ползком» - какую долю пути она за это время всё же
      проходит. Проверка берёт числа у самого акта и сверяет их с
      настоящим путём, а не с намерением.

   2. СЛОВА И СТОЯНКА СОВПАДАЮТ. У финала стоянка держит текст:
      `data-слова-до` в разметке и «держим» в позе обязаны быть одним
      числом. Разойдутся - человек либо поедет к люку с недочитанным
      заголовком, либо будет стоять перед пустым небом.

   3. ВОЗВРАТЫ. Шаг, направленный против общего хода акта, это и есть
      «камера поехала назад». Обход вокруг предмета из этого исключён:
      там камера идёт по кругу ПО ЗАМЫСЛУ, и проекция на хорду обязана
      менять знак. Признак `обход` отдаёт сама проба.

   4. ДЫХАНИЕ В КОНЦЕ. У панели камера не имеет права ездить вверх-вниз:
      внутри неподвижной рубки вертикальный ход метёт кромкой кадра по
      самосветящимся кольцам, и нижняя полоса мигает.

   ПОЧЕМУ ПРОБОЙ, А НЕ ПРОКРУТКОЙ. Ход камеры это чистая функция ленты,
   и мир отдаёт её наружу (`RV_WORLD.проба`). Живая прокрутка требует
   ждать кадра, а ожидание на замере стоянки врёт в одну сторону: сразу
   после прыжка камера ЕЩЁ не тронулась, и это неотличимо от «УЖЕ
   приехала». Ровно так замер дороги финала 14.09.2026 выдал одну и ту
   же точку на долях 0.60 и 0.90, между которыми шестнадцать единиц
   мира. Проверка про стоянку, поверившая ложной стоянке, бесполезна.

   Запуск: HTTPS_PROXY= https_proxy= node tools/checks/стоянки.mjs */
import { браузер, открыть, ПК, ТЕЛЕФОН, доложить } from "./общее.mjs";

/* Шагов на акт. Двести это два-три пикселя ленты на шаг у самого
   длинного акта: мельче ничего не меняет, крупнее теряется стык. */
const ШАГОВ = 200;

/* Запас к обещанному ползку. Проба считает путь ломаной по точкам, и
   на повороте ломаная всегда короче дуги: часть запаса уходит туда. */
const ЗАПАС_ПОЛЗКА = 0.03;

/* Возврат меньше этого не считаем: числа с плавающей точкой и та же
   ломаная дают доли сотой единицы туда-сюда на ровном ходу. */
const ПОРОГ_ВОЗВРАТА = 0.05;

/* Дыхание у панели. Размах по высоте на последней пятой части финала.
   Живое дыхание камеры было 0.09 и его видно, поэтому порог вдвое ниже. */
const ДЫХАНИЕ_ХВОСТ = 0.20;
const ХВОСТ_ДОЛЯ = 0.20;

const беды = [];
const b = await браузер();

for (const э of [ПК, ТЕЛЕФОН]) {
  const { pg, ошибки } = await открыть(b, э);
  await pg.waitForTimeout(3000);

  /* ── АКТ ПОЯВЛЯЕТСЯ В СПИСКЕ, КОГДА СОБРАН ───────────────────────
     Позу мир получает от самого акта, а акт собирается, когда доходит
     до экрана. На свежей странице в `кривая().станции` лежат три акта
     из четырёх: финала там нет вовсе, и проверка молча проходила мимо
     него - то есть мимо того единственного места, ради которого она и
     писалась. Заходим в каждый акт разметки, потом читаем список. */
  const имена = await pg.evaluate(() =>
    [...new Set([...document.querySelectorAll("[data-акт]")]
      .map((э) => э.getAttribute("data-акт")))]);
  for (const имя of имена) {
    await pg.evaluate((и) => window.RV_MOTION["кПунктy"](и, 0.5), имя);
    await pg.waitForTimeout(600);
  }
  await pg.evaluate(() => window.RV_MOTION["кПунктy"]("станция", 0));
  await pg.waitForTimeout(600);

  const свод = await pg.evaluate(({ шагов, хвостДоля, имена }) => {
    const W = window.RV_WORLD;
    if (!W || !W["кривая"] || !W["проба"]) return { нет: "мира нет" };
    const кр = W["кривая"]();
    if (!кр || !кр["станции"] || !кр["станции"].length) return { нет: "станций нет" };

    /* Акт разметки, которого нет в списке станций, это не мелочь:
       значит он не собрался, и всё, что о нём говорит проверка, было бы
       молчанием вместо ответа. */
    const собраны = кр["станции"].map((с) => с["имя"]);
    const пропали = имена.filter((и) => собраны.indexOf(и) < 0);

    const акты = [];
    for (const с of кр["станции"]) {
      const имя = с["имя"], верх = с["верх"], ход = с["ход"];
      if (!(ход > 0)) continue;

      /* Темп и слова берём у разметки и у мира, а не записываем сюда.
         Темп отдаёт сама станция: `RV_WORLD.поза` это установщик, и
         вызов её одним доводом стёр бы позу акта. */
      const узел = document.querySelector('[data-акт="' + имя + '"]');
      const темп = с["темп"] || null;
      const словаДо = узел && узел.getAttribute("data-слова-до");

      const точки = [];
      for (let i = 0; i <= шагов; i++) {
        const п = W["проба"](верх + ход * (i / шагов));
        if (!п) { точки.length = 0; break; }
        точки.push({ к: п["камера"], обход: !!п["обход"] });
      }
      if (!точки.length) { акты.push({ имя, нет: "проба молчит" }); continue; }

      /* Путь ломаной и его накопление: по нему считается доля пути,
         пройденная к любой доле акта. */
      const накоп = [0];
      for (let i = 1; i < точки.length; i++) {
        const a = точки[i - 1].к, c = точки[i].к;
        накоп.push(накоп[i - 1] + Math.hypot(c[0] - a[0], c[1] - a[1], c[2] - a[2]));
      }
      const путь = накоп[накоп.length - 1];

      /* Общее направление акта: хорда от первой точки к последней. */
      const п0 = точки[0].к, пН = точки[точки.length - 1].к;
      let хx = пН[0] - п0[0], хy = пН[1] - п0[1], хz = пН[2] - п0[2];
      const длХ = Math.hypot(хx, хy, хz) || 1;
      хx /= длХ; хy /= длХ; хz /= длХ;

      let возврат = 0, возвратГде = null;
      for (let i = 1; i < точки.length; i++) {
        if (точки[i].обход || точки[i - 1].обход) continue;
        const a = точки[i - 1].к, c = точки[i].к;
        const пр = (c[0] - a[0]) * хx + (c[1] - a[1]) * хy + (c[2] - a[2]) * хz;
        if (-пр > возврат) { возврат = -пр; возвратГде = i / шагов; }
      }

      /* Высота на хвосте акта: размах по y. */
      const сХвоста = Math.floor(точки.length * (1 - хвостДоля));
      let yМин = Infinity, yМакс = -Infinity;
      for (let i = сХвоста; i < точки.length; i++) {
        const y = точки[i].к[1];
        if (y < yМин) yМин = y;
        if (y > yМакс) yМакс = y;
      }

      const о = { имя, путь: +путь.toFixed(3), возврат: +возврат.toFixed(3), возвратГде,
                  хвостРазмах: +(yМакс - yМин).toFixed(3),
                  темп: темп, словаДо: словаДо == null ? null : +словаДо };
      if (темп) {
        const держим = +темп[0], ползком = +темп[1];
        const iД = Math.round(шагов * держим);
        о.держим = держим;
        о.ползком = ползком;
        о.прошлаДоля = путь > 1e-6 ? +(накоп[Math.min(iД, накоп.length - 1)] / путь).toFixed(4) : 0;
        о.прошлаЕдиниц = +накоп[Math.min(iД, накоп.length - 1)].toFixed(3);
      }
      акты.push(о);
    }
    return { акты, пропали };
  }, { шагов: ШАГОВ, хвостДоля: ХВОСТ_ДОЛЯ, имена });

  if (свод.нет) { беды.push(э.имя + ": " + свод.нет); await pg.close(); continue; }

  for (const и of (свод.пропали || [])) {
    беды.push(э.имя + ": акт " + и + " не собрался и в список станций не попал");
  }

  console.log("=== " + э.имя + " ===");
  for (const а of свод.акты) {
    if (а.нет) { беды.push(э.имя + ": акт " + а.имя + " - " + а.нет); continue; }
    console.log("  " + а.имя.padEnd(10) +
      " путь " + String(а.путь).padStart(8) +
      "  возврат " + String(а.возврат).padStart(6) +
      "  хвост±y " + String(а.хвостРазмах).padStart(6) +
      (а.темп ? "  стоянка до " + а.держим + ": прошла " + а.прошлаДоля +
                " при обещанных " + а.ползком : ""));

    if (а.возврат > ПОРОГ_ВОЗВРАТА) {
      беды.push(э.имя + ": акт " + а.имя + " - камера едет назад на " + а.возврат +
        " ед на доле " + а.возвратГде + " (порог " + ПОРОГ_ВОЗВРАТА + ")");
    }
    if (а.темп && а.прошлаДоля > а.ползком + ЗАПАС_ПОЛЗКА) {
      беды.push(э.имя + ": акт " + а.имя + " - стоянки нет: до доли " + а.держим +
        " камера прошла " + а.прошлаДоля + " пути (обещано " + а.ползком +
        ", запас " + ЗАПАС_ПОЛЗКА + ")");
    }
    /* Слова и стоянка это одно число. Сверяем только там, где разметка
       про слова вообще говорит: у остальных актов текст живёт весь акт. */
    if (а.темп && а.словаДо != null && Math.abs(а.словаДо - а.держим) > 0.001) {
      беды.push(э.имя + ": акт " + а.имя + " - слова стоят до " + а.словаДо +
        ", а камера трогается на " + а.держим + "; числа обязаны совпадать");
    }
    if (а.имя === "финал" && а.хвостРазмах > ДЫХАНИЕ_ХВОСТ) {
      беды.push(э.имя + ": у панели камера ездит вверх-вниз на " + а.хвостРазмах +
        " ед (порог " + ДЫХАНИЕ_ХВОСТ + ", дыхание внутри рубки обязано быть в нуле)");
    }
  }

  for (const о of ошибки) беды.push(э.имя + ": " + о);
  await pg.close();
}

await b.close();
доложить("стоянки камеры и возвраты (хвост " + ХВОСТ_ДОЛЯ + " акта)", беды);
