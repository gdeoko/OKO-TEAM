/* Хвосты переименований.

   ЗАЧЕМ. Этот класс ошибки один раз уже убил всю ленту: в перекраске
   осталось имя `свой`, которого в новой редакции функции нет, весь
   разбор файла падал молча, и на сайте не собиралось НИЧЕГО (см.
   приёмку, «Исключения бывают невидимыми»). Глаз такое не ловит:
   переименовал в одном месте, забыл в трёх, и три забытых места ждут
   своего часа.

   Проверка сводит вместе пары «кто объявляет» и «кто зовёт»:
     · имена RV_* в окне;
     · события: посланные против слушаемых;
     · гнёзда data-заполнить: разметка против кода;
     · id: getElementById против разметки и строк innerHTML;
     · script src против файлов на диске и обратно.

   Ничего не запускает и браузера не поднимает: читает исходники. Идёт
   за секунду, поэтому её можно гонять после каждой правки.

   ВАЖНО про поиск объявлений. Модули объявляют имена и точкой
   (`g.RV_ФОН = ...`), и скобкой (`g["RV_КАБИНА"] = ...`), и лежат не
   только в assets, но и в assets/gen. Первая редакция этого не знала и
   выдала шесть ложных тревог подряд. Ложная тревога в проверке хуже
   молчания: на неё перестают смотреть. */
import fs from "fs";
import path from "path";

const корень = path.resolve(new URL(".", import.meta.url).pathname, "../..");
const разметка = path.join(корень, "frame.html");

function собратьJS(дир, наружу) {
  for (const имя of fs.readdirSync(дир, { withFileTypes: true })) {
    const п = path.join(дир, имя.name);
    if (имя.isDirectory()) собратьJS(п, наружу);
    else if (имя.name.endsWith(".js") && !п.includes("/vendor/")) наружу.push(п);
  }
  return наружу;
}

const файлы = собратьJS(path.join(корень, "assets"), []);
const текст = {};
let всё = "";
for (const ф of файлы) { текст[ф] = fs.readFileSync(ф, "utf8"); всё += текст[ф]; }
const html = fs.readFileSync(разметка, "utf8");
const коротко = (ф) => path.relative(корень, ф);

const беды = [];
function беда(что) { беды.push(что); }

/* ── Имена RV_* ─────────────────────────────────────────────────── */
const объявлены = new Set();
for (const m of всё.matchAll(/\b(?:g|window|globalThis)\s*\.\s*(RV_[A-ZА-ЯЁ_0-9]+)\s*=/g)) объявлены.add(m[1]);
for (const m of всё.matchAll(/\b(?:g|window|globalThis)\s*\[\s*["'](RV_[A-ZА-ЯЁ_0-9]+)["']\s*\]\s*=/g)) объявлены.add(m[1]);

const зовут = new Map();
for (const ф of файлы) {
  const t = текст[ф];
  const строки = t.split("\n");
  for (let i = 0; i < строки.length; i++) {
    const с = строки[i];
    /* Обращение с запасным значением через `||` не тревога: модуль
       готов работать без соседа, так и задумано. */
    if (/\|\|/.test(с)) continue;
    for (const m of с.matchAll(/\b(?:g|window|globalThis)\s*(?:\.\s*|\[\s*["'])(RV_[A-ZА-ЯЁ_0-9]+)/g)) {
      if (объявлены.has(m[1])) continue;
      if (!зовут.has(m[1])) зовут.set(m[1], new Set());
      зовут.get(m[1]).add(коротко(ф) + ":" + (i + 1));
    }
  }
}
for (const [имя, где] of [...зовут].sort()) {
  беда("имя " + имя + " зовут, но нигде не объявляют: " + [...где].join(", "));
}

/* ── События ────────────────────────────────────────────────────── */
const шлют = new Set();
for (const m of всё.matchAll(/CustomEvent\(\s*["']([^"']+)["']/g)) шлют.add(m[1]);
for (const m of всё.matchAll(/initEvent\(\s*["']([^"']+)["']/g)) шлют.add(m[1]);
for (const m of всё.matchAll(/fire\(\s*["']([^"']+)["']/g)) шлют.add(m[1]);
const слушают = new Map();
for (const ф of файлы) {
  for (const пат of [/addEventListener\(\s*["'](rv[:\-][^"']+)["']/g, /\[\s*["'](rv[:\-][^"']+)["']\s*,/g]) {
    for (const m of текст[ф].matchAll(пат)) {
      if (!слушают.has(m[1])) слушают.set(m[1], new Set());
      слушают.get(m[1]).add(коротко(ф));
    }
  }
}
for (const [имя, где] of [...слушают].sort()) {
  if (!шлют.has(имя)) беда("событие " + имя + " слушают, но никто не шлёт: " + [...где].join(", "));
}

/* ── Гнёзда разметки ────────────────────────────────────────────── */
const гнёздаHTML = new Set([...html.matchAll(/data-заполнить="([^"]+)"/g)].map((m) => m[1]));
const гнёздаJS = new Set([...всё.matchAll(/гнездо\("([^"]+)"\)/g)].map((m) => m[1]));
for (const и of гнёздаJS) if (!гнёздаHTML.has(и)) беда('гнездо data-заполнить="' + и + '" код заполняет, а разметки под него нет');
for (const и of гнёздаHTML) if (!гнёздаJS.has(и)) беда('гнездо data-заполнить="' + и + '" стоит в разметке, а заполнять его некому');

/* ── Имена id ───────────────────────────────────────────────────── */
const idРазметки = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]));
/* Другие страницы сайта: игра живёт своей. */
for (const стр of fs.readdirSync(корень).filter((и) => и.endsWith(".html"))) {
  const т = fs.readFileSync(path.join(корень, стр), "utf8");
  for (const m of т.matchAll(/\bid="([^"]+)"/g)) idРазметки.add(m[1]);
}
/* id рождаются и в коде: присваиванием и строками разметки внутри него. */
for (const m of всё.matchAll(/\.id\s*=\s*["']([^"']+)["']/g)) idРазметки.add(m[1]);
for (const m of всё.matchAll(/id=\\?["']([A-Za-zА-Яа-яЁё_][\wА-Яа-яЁё-]*)/g)) idРазметки.add(m[1]);
/* ── ОБЩИЕ МОДУЛИ ИЩУТ ЭЛЕМЕНТЫ СТРАНИЦЫ СОСЕДА ────────────────
   Рубка, пульт и оснастка лежат одним файлом в обоих сайтах (правило
   «копии модулей рубки свести»). Эти модули спрашивают у страницы свои
   элементы, и часть из них живёт только на странице соседа: формы
   заявки, разделы надёжности, эпилог. Там они закрыты проверкой на
   существование и молча ничего не делают - так и задумано.

   Проверка звала это хвостами: семь строк подряд про rc-desk и
   rc-interior. Семь ложных тревог в отчёте из десяти строк означают,
   что отчёт перестают читать, и настоящий хвост уедет вместе с ними.

   Берём разметку соседа как ещё один источник известных имён. Это не
   послабление, а расширение того же правила: id, который сосед честно
   создаёт, существует - просто не на нашей странице. Соседа нет рядом
   (отдельный клон) - список остаётся прежним, и проверка становится
   строже, а не мягче. */
const сосед = path.join(корень, "..", "rocketcdn");
if (fs.existsSync(сосед)) {
  for (const стр of fs.readdirSync(сосед).filter((и) => и.endsWith(".html"))) {
    const т = fs.readFileSync(path.join(сосед, стр), "utf8");
    for (const m of т.matchAll(/\bid="([^"]+)"/g)) idРазметки.add(m[1]);
  }
}
for (const ф of файлы) {
  const строки = текст[ф].split("\n");
  for (let i = 0; i < строки.length; i++) {
    if (/\|\|/.test(строки[i])) continue;
    for (const m of строки[i].matchAll(/getElementById\(\s*["']([^"']+)["']/g)) {
      if (!idРазметки.has(m[1])) беда("id " + m[1] + " код ищет, а создать его некому: " + коротко(ф) + ":" + (i + 1));
    }
  }
}

/* ── Скрипты ────────────────────────────────────────────────────── */
/* ── ФАЙЛ БЫВАЕТ ПОДКЛЮЧЁН НЕ ТЕГОМ ─────────────────────────────
   Проверка искала только `src="assets/..."` в одной странице и на этом
   считала список подключённых закрытым. С тех пор у сайта появилось три
   других законных способа довезти модуль, и все три она звала хвостами:

     · отложенная пачка во frame.html - список файлов лежит в JSON
       внутри страницы и грузится после прогрева кадра, чтобы не
       отбирать канал у первого экрана;
     · игра на своей странице igra.html со своим набором тегов;
     · rc-gl.js, который подтягивает три.js и полтора десятка модулей
       игры сам, по нажатию кнопки.

   Девятнадцать живых файлов объявлялись мусором, и на такой список
   перестают смотреть целиком - вместе с настоящим хвостом, ради
   которого проверка и писалась.

   Считаем подключённым файл, который назван ЛЮБЫМ из трёх способов:
   тегом в любой странице сайта, строкой в отложенном списке или
   строкой в коде загрузчика.

   Списка ДВА, и это важно. «Тегами» отвечает на вопрос «подключено, а
   файла нет»: тег обещает файл по адресу, и если его там нет, страница
   получит 404. «Названы» отвечает на обратный вопрос «файл есть, а
   подключать некому», и сюда идут все три способа. Один список на два
   вопроса врёт в обе стороны: упоминание имени в коде не обещает файла
   по адресу, а тег не единственный способ его довезти. */
const тегами = new Set();
const названы = new Set();
for (const стр of fs.readdirSync(корень).filter((и) => и.endsWith(".html"))) {
  const т = fs.readFileSync(path.join(корень, стр), "utf8");
  for (const m of т.matchAll(/src="assets\/([^"]+\.js)"/g)) { тегами.add(m[1]); названы.add(m[1]); }
  /* Отложенный список: те же пути, но внутри JSON страницы. */
  for (const m of т.matchAll(/"src"\s*:\s*"assets\/([^"]+\.js)"/g)) названы.add(m[1]);
}
/* Загрузчики в самом коде: rc-gl тянет модули игры по имени. */
for (const m of всё.matchAll(/["'`]assets\/([\w./-]+\.js)["'`]/g)) названы.add(m[1]);
for (const m of всё.matchAll(/["'`]([\w-]+\.js)["'`]/g)) названы.add(m[1]);
const подключены = тегами;
for (const с of подключены) if (!fs.existsSync(path.join(корень, "assets", с))) беда("скрипт assets/" + с + " подключён, а файла нет");
for (const ф of файлы) {
  const отн = path.relative(path.join(корень, "assets"), ф);
  if (отн.startsWith("gen/")) continue;
  if (!названы.has(отн)) беда("файл assets/" + отн + " лежит в репозитории, а подключать его некому");
}

console.log("проверено файлов " + файлы.length + ", имён RV_* " + объявлены.size +
  ", событий " + шлют.size + ", гнёзд " + гнёздаHTML.size);
if (!беды.length) {
  console.log("ЧИСТО хвосты: мёртвых имён, событий и гнёзд нет");
  process.exit(0);
}
for (const б of беды) console.log("   " + б);
console.log("ХВОСТЫ: " + беды.length);
process.exit(1);
