/* Rocket VPN. Ровность хода камеры и зазоры до предметов.

   ЗАЧЕМ ОТДЕЛЬНАЯ ПРОВЕРКА. Соседняя `полёт.mjs` строилась под ПРОШЛУЮ
   жалобу владельца («мир стоит, камера не едет») и потому ловит только
   стояние: нижний порог пути и общий пробег. Верхнего порога скорости у
   неё нет, угловой скорости нет вовсе, а снимает она одиннадцать точек,
   то есть шагом больше тысячи пикселей.

   Этого хватало ровно до следующей жалобы: «то вроде в туннель заходит и
   потом в сторону зачем-то улетает и вбок куда-то сквозь фигуры и
   объекты, слишком все быстро и дёрганно». Щелчок взгляда, который её
   вызывает, длится двадцать четыре пикселя прокрутки и в сетку из
   одиннадцати точек не попадает НИКОГДА. Здесь шаг четыре пикселя.

   ЧТО МЕРЯЕТСЯ И ПОЧЕМУ ИМЕННО ЭТО.

   1. Угловая скорость ВЗГЛЯДА. Главное число. Положение камеры идёт по
      сглаженной кривой и рывков не даёт, а взгляд считался лерпом ТОЧЕК:
      отрезок между двумя целями по разные стороны камеры обязан пройти
      сквозь камеру, и там разворот вырождается. Человек видит щелчок.

   2. Полёт боком. Угол между тем, КУДА камера едет, и тем, КУДА она
      смотрит. Больше тридцати пяти градусов подряд это и есть «улетает
      вбок»; отдельно меряется ДЛИНА такого куска, потому что двадцать
      пикселей это приём, а семьсот это поломка.

   3. Расстояние до точки взгляда. Ноль означает, что камера смотрит сама
      на себя, и картинка в этот миг не определена ничем.

   4. Линейная скорость и её размах по ленте. Один щелчок колеса не имеет
      права уносить камеру то на полединицы, то на восьмую часть мира.

   5. Зазор до железа. Обход всей сцены с настоящими габаритами: если
      камера внутри шара предмета, она идёт сквозь него. Никаких списков
      предметов руками - что в сцене, то и меряется.

   6. Шаг за один кадр быстрой прокрутки. Тридцать три пикселя это один
      кадр при двух тысячах пикселей в секунду и шестидесяти герцах.

   7. Расхождение перспектив. Вёрстка и мир обязаны смотреть одним
      объективом, иначе текст живёт в своём пространстве, а мир в своём.

   ПОЧЕМУ ПРОКРУТКА, А НЕ ПЕРЕХОД К АКТУ. `кПунктy` ставит ленту в точку
   мгновенно, и промежутки между точками остаются непроверенными. Здесь
   лента идёт подряд, как её проходит человек.

   Запуск:
     HTTPS_PROXY= https_proxy= node tools/checks/ход-камеры.mjs [метка]
   Числа складываются в /tmp/адм/ход-<метка>-<экран>.json целиком, в
   вывод идёт только сводка: замер даёт тысячи точек. */
import { writeFileSync, mkdirSync } from "node:fs";
import { браузер, открыть } from "./общее.mjs";

const МЕТКА = process.argv[2] || "х";
const ШАГ = 4;              /* пикселей прокрутки между замерами */
const ФЛИК = 33;            /* один кадр при 2000 px/с и 60 Гц */
const ЭКРАНЫ = [
  { имя: "пк",  vp: { width: 1440, height: 900 }, dpr: 1, mob: false },
  { имя: "тел", vp: { width: 390, height: 844 },  dpr: 2, mob: true }
];

/* Пороги приёмки. Взяты из разбора кода: слева то, что было в день
   жалобы, справа то, ниже чего человек рывка уже не видит. */
export const ПОРОГИ = {
  уголНа100: 25,      /* было 6734 град/100px в проколе */
  скоростьНа100: 40,  /* было 154.2 единицы/100px */
  размахСкорости: 25, /* было 328 раз */
  бокПик: 35,         /* было 179.9 град */
  бокКусок: 100,      /* было 725 px подряд выше 25 град */
  бокКусков: 2,       /* и не больше двух таких кусков на весь сайт */
  доВзгляда: 8,       /* было 0.10 единицы */
  зазор: 1.5,         /* было 0.56 у кольца пуска */
  фликПуть: 8,        /* было 49.2 единицы за кадр */
  фликУгол: 20,       /* было 177.6 градуса за кадр */
  перспектива: 1.15   /* во сколько раз вёрстка расходится с миром */
};

/* Вся лента снимается ОДНИМ заходом в страницу через `RV_WORLD.проба`.

   Проба считает позу камеры для любой прокрутки, ничего не рисуя, и это
   единственный способ снять три тысячи точек на песочнице без
   видеокарты. Через настоящую прокрутку с ожиданием кадра тот же замер
   шёл бы часами и падал по таймауту (проверено). */
const СНЯТЬ = (шаг) => {
  const W = window.RV_WORLD;
  if (!W || !W["проба"]) return { нет: "у мира нет пробы" };
  const высота = document.documentElement.scrollHeight - window.innerHeight;
  const слой = document.querySelector(".rv-слой");
  const персп = слой ? parseFloat(getComputedStyle(слой).perspective) || 0 : 0;
  const зум = W["ход"]()["зум"] || 1;
  const закон = W["ход"]()["закон"] || 0;
  const ряд = [];
  for (let y = 0; y <= высота; y += шаг) {
    const п = W["проба"](y);
    if (!п) continue;
    ряд.push({
      y,
      место: п["место"],
      кам: п["камера"],
      цель: п["взгляд"],
      напр: п["напр"],
      кас: п["касательная"],
      до: п["доВзгляда"],
      поле: п["поле"],
      перегон: п["перегон"]
    });
  }
  return { ряд, высота, персп, зум, закон, окно: window.innerHeight };
};

function угол(а, б) {
  if (!а || !б) return 0;
  let с = а[0] * б[0] + а[1] * б[1] + а[2] * б[2];
  с = с > 1 ? 1 : (с < -1 ? -1 : с);
  return Math.acos(с) * 180 / Math.PI;
}

function путь(а, б) {
  if (!а || !б) return 0;
  return Math.hypot(б[0] - а[0], б[1] - а[1], б[2] - а[2]);
}

function разобрать(ряд, имяЭкрана, общ) {
  const беды = [];
  let уголМакс = 0, уголГде = null;
  let скорМакс = 0, скорГде = null, скорМин = Infinity;
  let бокПик = 0, бокГде = null;
  let доМин = Infinity, доГде = null;
  const куски = [];
  let кусок = null;

  for (let i = 1; i < ряд.length; i++) {
    const а = ряд[i - 1], б = ряд[i];
    const dy = б.y - а.y || 1;
    const сто = 100 / dy;

    const у = угол(а.напр, б.напр) * сто;
    if (у > уголМакс) { уголМакс = у; уголГде = б.y; }

    const с = путь(а.кам, б.кам) * сто;
    if (с > скорМакс) { скорМакс = с; скорГде = б.y; }
    if (с < скорМин) скорМин = с;

    /* Полёт боком: куда едем против того, куда смотрим. Ход берём из
       касательной кривой, а не из разности соседних точек: на медленном
       участке разность в доли единицы шумит направлением. */
    const бок = б.кас && б.напр ? угол(б.кас, б.напр) : 0;
    if (бок > бокПик) { бокПик = бок; бокГде = б.y; }
    if (бок > 25) {
      if (!кусок) кусок = { от: б.y, до: б.y, пик: бок };
      else { кусок.до = б.y; if (бок > кусок.пик) кусок.пик = бок; }
    } else if (кусок) { куски.push(кусок); кусок = null; }

    if (б.до < доМин) { доМин = б.до; доГде = б.y; }
  }
  if (кусок) куски.push(кусок);

  /* Шаг за один кадр быстрой прокрутки: складываем соседние замеры,
     пока не набежит ФЛИК пикселей. */
  let фликПуть = 0, фликУгол = 0, фликГде = null;
  for (let i = 0; i < ряд.length; i++) {
    const цель = ряд[i].y + ФЛИК;
    let j = i;
    while (j + 1 < ряд.length && ряд[j + 1].y <= цель) j++;
    if (j === i) continue;
    const п = путь(ряд[i].кам, ряд[j].кам);
    const у = угол(ряд[i].напр, ряд[j].напр);
    if (п > фликПуть) { фликПуть = п; фликГде = ряд[i].y; }
    if (у > фликУгол) фликУгол = у;
  }

  const размах = скорМин > 1e-6 ? скорМакс / скорМин : Infinity;
  const длинные = куски.filter(к => к.до - к.от > ПОРОГИ.бокКусок);

  /* Перспектива вёрстки против расчётной по живому полю камеры.
     P = (высота кадра / 2) * зум / tg(поле / 2). Вёрстка обязана
     смотреть тем же объективом, что и мир, иначе текст живёт в своём
     пространстве, а мир в своём, и никакая параллаксная отделка их не
     сведёт. */
  let перспМакс = 0, перспГде = null;
  if (общ.персп) {
    for (const т of ряд) {
      if (!т.поле) continue;
      const надо = (общ.окно / 2) * (общ.зум || 1) / Math.tan(т.поле * Math.PI / 360);
      if (!надо) continue;
      const р = Math.max(общ.персп / надо, надо / общ.персп);
      if (р > перспМакс) { перспМакс = р; перспГде = т.y; }
    }
  }

  const итог = {
    экран: имяЭкрана,
    точек: ряд.length,
    уголМакс: +уголМакс.toFixed(1), уголГде,
    скорМакс: +скорМакс.toFixed(1), скорГде,
    скорМин: +скорМин.toFixed(2),
    размах: +размах.toFixed(1),
    бокПик: +бокПик.toFixed(1), бокГде,
    кусков: куски.length, длинных: длинные.length,
    длинныеКуски: длинные.map(к => `${к.от}..${к.до} (${к.до - к.от}px, пик ${к.пик.toFixed(0)}°)`),
    доВзглядаМин: +доМин.toFixed(2), доГде,
    фликПуть: +фликПуть.toFixed(1), фликГде,
    фликУгол: +фликУгол.toFixed(1),
    закон: общ.закон,
    перспектива: общ.персп,
    перспРасхождение: +перспМакс.toFixed(2), перспГде
  };

  if (итог.уголМакс > ПОРОГИ.уголНа100) беды.push(`взгляд крутится ${итог.уголМакс} град/100px на y=${итог.уголГде} (порог ${ПОРОГИ.уголНа100})`);
  if (итог.скорМакс > ПОРОГИ.скоростьНа100) беды.push(`скорость ${итог.скорМакс} ед/100px на y=${итог.скорГде} (порог ${ПОРОГИ.скоростьНа100})`);
  if (итог.размах > ПОРОГИ.размахСкорости) беды.push(`размах скорости ${итог.размах} раз (порог ${ПОРОГИ.размахСкорости})`);
  if (итог.бокПик > ПОРОГИ.бокПик) беды.push(`полёт боком ${итог.бокПик} град на y=${итог.бокГде} (порог ${ПОРОГИ.бокПик})`);
  if (итог.длинных > ПОРОГИ.бокКусков) беды.push(`кусков полёта боком длиннее ${ПОРОГИ.бокКусок}px: ${итог.длинных} (порог ${ПОРОГИ.бокКусков})`);
  if (итог.доВзглядаМин < ПОРОГИ.доВзгляда) беды.push(`камера в ${итог.доВзглядаМин} ед от точки взгляда на y=${итог.доГде} (порог ${ПОРОГИ.доВзгляда})`);
  if (итог.фликПуть > ПОРОГИ.фликПуть) беды.push(`за кадр флика ${итог.фликПуть} ед на y=${итог.фликГде} (порог ${ПОРОГИ.фликПуть})`);
  if (итог.фликУгол > ПОРОГИ.фликУгол) беды.push(`за кадр флика ${итог.фликУгол} град (порог ${ПОРОГИ.фликУгол})`);
  if (итог.перспРасхождение > ПОРОГИ.перспектива) беды.push(`перспектива вёрстки расходится с миром в ${итог.перспРасхождение} раза на y=${итог.перспГде} (порог ${ПОРОГИ.перспектива})`);

  return { итог, беды };
}

const b = await браузер();
const все = [];
for (const э of ЭКРАНЫ) {
  const { pg, ошибки } = await открыть(b, э);
  await pg.waitForTimeout(3000);
  const снимок = await pg.evaluate(СНЯТЬ, ШАГ);
  if (снимок.нет) { console.log(э.имя + ": " + снимок.нет); await pg.close(); continue; }
  const ряд = снимок.ряд;
  const { итог, беды } = разобрать(ряд, э.имя, снимок);
  все.push({ итог, беды });
  try { mkdirSync("/tmp/адм", { recursive: true }); } catch (e) {}
  writeFileSync(`/tmp/адм/ход-${МЕТКА}-${э.имя}.json`, JSON.stringify(ряд), "utf8");
  console.log(`=== ${э.имя} (${э.vp.width}x${э.vp.height}), точек ${итог.точек}`);
  for (const [к, з] of Object.entries(итог)) {
    if (к === "экран" || к === "точек") continue;
    console.log(`  ${к}: ${Array.isArray(з) ? з.join(" | ") || "нет" : з}`);
  }
  const свои = (ошибки || []).filter(о => !/CERT_AUTHORITY|rocketcdn|ERR_CONNECTION/.test(о));
  if (свои.length) console.log("  ОШИБКИ:", свои.slice(0, 3).join(" ; "));
  await pg.close();
}
await b.close();

const всеБеды = все.flatMap(о => о.беды.map(б => о.итог.экран + ": " + б));
if (всеБеды.length) {
  console.log("\nГРЯЗНО");
  for (const б of всеБеды) console.log("   " + б);
  process.exit(1);
}
console.log("\nЧИСТО");
