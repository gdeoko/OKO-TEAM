/* Проверка: сайт говорит по-человечески.

   Правило проекта действует везде - в переписке, в договорах, в постах
   и здесь. Оно короткое:

     1. Длинного тире не бывает. Только дефис. Длинное тире это первый
        признак машины: в переписке его не ставит никто.
     2. Никаких противопоставлений «не X, а Y». Говорим прямо, одним
        утверждением.
     3. Никаких иишных оборотов: «важно отметить», «таким образом»,
        «комплексный подход», «в кратчайшие сроки», «позволяет вам».

   ПОЧЕМУ ПРОВЕРКОЙ, А НЕ ГЛАЗАМИ. Текст сайта живёт в трёх местах: в
   разметке, в досье продукта и в сборщике блоков. Вычитать глазами
   можно один раз; после любой правки всё начинается заново, и длинное
   тире возвращается ровно тем же путём, каким пришло в прошлый раз.

   Проверка читает ВИДИМЫЙ текст живой страницы, а не исходники: то, что
   человек прочтёт, собирается из трёх источников, и ловить надо
   результат.

   Запуск: RV_URL=http://127.0.0.1:8170 node tools/checks/речь.mjs
*/
import { браузер, открыть, ПК, доложить } from "./общее.mjs";

/* Запреты. Каждый - выражение и объяснение, почему нельзя: сообщение об
   ошибке обязано говорить, что делать, а не только что плохо. */
/* ГРАНИЦА СЛОВА ЗДЕСЬ СВОЯ, И ЭТО НЕ ПРИДИРКА. В JavaScript \b и \w
   считают словом только латиницу: между пробелом и буквой «н» границы
   слова НЕТ, а «\w+» после кириллического корня не совпадает ни с чем.
   Первая версия этих правил прошла на сайте с первого раза - и на
   собственных примерах тоже: «Важно отметить, что мы используем
   комплексный подход» она объявляла чистым. Проверка, которая не ловит
   свой же образец, хуже отсутствующей: она даёт ложное спокойствие.

   Поэтому граница слова набрана руками через кириллический диапазон, а
   у каждого правила есть образец, на котором оно обязано сработать. */
const К = "а-яёА-ЯЁ";
const ДО = `(^|[^${К}])`;      /* начало слова: не буква перед ним */

const ЗАПРЕТЫ = [
  [new RegExp("[—–]", "g"),
   "длинное или среднее тире. Ставим дефис: длинное тире в русской переписке не пишет никто, и оно выдаёт машину",
   "Это не сайт — это система"],

  [new RegExp(`${ДО}не\\s+[^,.;:!?]{2,40},\\s*а\\s+`, "gi"),
   "противопоставление «не X, а Y». Говорим прямо, одним утверждением",
   "Тариф выбирается не строкой в таблице, а тем, что помещается"],

  [new RegExp(`важно отметить|стоит отметить|таким образом|кроме того,|на сегодняшний день|комплексн[${К}]+ подход|индивидуальн[${К}]+ подход|в кратчайшие сроки|позволяет вам|в рамках `, "gi"),
   "иишный оборот",
   "Важно отметить, что мы используем комплексный подход"],

  [new RegExp("во-первых|во-вторых", "gi"),
   "перечисление «во-первых, во-вторых»",
   "Во-первых, это удобно"],

  [new RegExp(`${ДО}(клиент|заказчик|пользовател)[${К}]*`, "gi"),
   "разговор о человеке в третьем лице. Обращаемся на «ты»",
   "Каждый пользователь получает доступ"],
];

/* Самопроверка. Правило, которое не ловит свой образец, до сайта не
   допускается: молчащая проверка опаснее отсутствующей. */
for (const [выр, чем, образец] of ЗАПРЕТЫ) {
  выр.lastIndex = 0;
  if (!выр.test(образец)) {
    console.log("СЛОМАНО правило «" + чем + "»: не ловит собственный образец «" + образец + "»");
    process.exit(2);
  }
  выр.lastIndex = 0;
}

/* Чего проверка НЕ трогает. Это не исключения ради удобства, а места,
   где слово стоит законно и по делу. */
const МОЖНО = [
  /9 из 10 пользователей/,        /* цифра сервиса, цитата из их канала */
  /Полный список точек выхода/,
];

const беды = [];
const б = await браузер();
const { pg, ошибки } = await открыть(б, ПК, {});

/* Собираем видимый текст блоками, а не одной простынёй: сообщение об
   ошибке обязано показать, ГДЕ найдено, иначе искать придётся глазами
   по всему сайту - ровно то, от чего проверка избавляет. */
const куски = await pg.evaluate(() => {
  const из = [];
  const узлы = document.querySelectorAll(
    ".rv-слой p, .rv-слой h1, .rv-слой h2, .rv-слой li, .rv-слой .rv-док, " +
    ".rv-подвал p, .rv-подвал a, .rv-створ p, title, meta[name='description']");
  for (const у of узлы) {
    const т = (у.tagName === "META" ? у.getAttribute("content") : у.textContent || "").trim();
    if (т.length < 3) continue;
    const акт = у.closest("[data-акт]");
    из.push({
      где: (акт ? акт.getAttribute("data-акт") : у.tagName.toLowerCase()) + "/" +
           (у.className || у.tagName.toLowerCase()),
      текст: т
    });
  }
  return из;
});

if (!куски.length) беды.push("на странице не нашлось ни одного куска текста");

for (const к of куски) {
  if (МОЖНО.some((р) => р.test(к.текст))) continue;
  for (const [выр, чем] of ЗАПРЕТЫ) {
    выр.lastIndex = 0;
    const м = к.текст.match(выр);
    if (м) {
      беды.push(`${к.где}: ${чем} - «${м[0].trim().slice(0, 40)}» в «${к.текст.slice(0, 64)}...»`);
    }
  }
}

console.log("прочитано кусков:", куски.length);
await pg.close();
await б.close();
for (const о of ошибки) беды.push(о);
доложить("речь: сайт говорит по-человечески", беды);
