/* Живая проверка: звук идёт за плёнкой, а на проколе есть тишина.

   Звук нельзя сдать снимком, и «вроде играет» это не сдача. Проверка
   ведёт сайт по долям хода и читает замер из RV_SOUND: состояние
   контекста и текущие громкости голосов. Дальше сравнивает с тем, что
   обещает сценарий.

   Что обязано выполняться:
     1. Контекст живой после включения.
     2. Гул есть в первых актах и он ГРОМЧЕ в периметре, чем в сети:
        стена ближе.
     3. На проколе перед броском гул уходит В НОЛЬ - это та самая
        тишина, ради которой всё и затевалось.
     4. После тишины гул возвращается: тоннель звучит.
     5. Ведёт звук только идущий акт. Проверяется тем, что в разных
        актах громкости РАЗНЫЕ: одинаковые означали бы, что последний
        подписчик затирает текущий.

   Запуск:
     RV_URL=http://127.0.0.1:8170 node tools/checks/звук.mjs
*/
import { браузер, открыть, кАкту, доложить, ПК } from "./общее.mjs";

const б = await браузер();
const { pg: п, ошибки: беды } = await открыть(б, ПК);
await п.waitForTimeout(2500);

const есть = await п.evaluate(() => !!(window.RV_SOUND && window.RV_MOTION));
if (!есть) {
  console.log("ПРОПУСК  звука или плёнки нет на странице");
  await б.close();
  process.exit(0);
}

await п.evaluate(() => window.RV_SOUND["включить"](true));

/* Звук теперь не синтезируется, а качается: пятнадцать файлов на
   без малого мегабайт. Ждём не «немного», а ПОКА ПРИЕДЕТ - иначе
   проверка меряет тишину незагруженного банка и объявляет её бедой. */
await п.waitForFunction(() => {
  const з = window.RV_SOUND["замер"]();
  return з["подложек"] >= 6 && з["разовых"] >= 9;
}, null, { timeout: 60000 }).catch(() => беды.push("банк звука не доехал за минуту"));
await п.waitForTimeout(600);

const банк = await п.evaluate(() => window.RV_SOUND["замер"]());
console.log("банк     ", JSON.stringify(банк));

async function замер(имя, доля) {
  await кАкту(п, имя, доля);
  return п.evaluate(() => window.RV_SOUND["замер"]());
}

const состояние = (await п.evaluate(() => window.RV_SOUND["замер"]()))["состояние"];
if (состояние !== "running") беды.push(`контекст звука не запущен: ${состояние}`);

/* ── ПРОВЕРКА МЕРИЛА АКТЫ, КОТОРЫХ НЕТ ────────────────────────────
   Здесь стояли имена «видно» и «выход». Таких актов в плёнке нет уже
   давно: она переписана под сценарий владельца и состоит из станции,
   периметра, прокола, рубки и пуска. Переход к несуществующему акту
   молча ничего не делал, замер читал состояние ПРЕДЫДУЩЕГО шага, и
   проверка годами говорила «в первом акте нет гула» про акт, до
   которого не доезжала.

   Первый акт сайта - станция, последний из озвученных - пуск. */
const сеть = await замер("станция", 0.5);
const периметр = await замер("периметр", 0.5);
const доБроска = await замер("прокол", 0.40);
const тоннель = await замер("прокол", 0.70);
const выход = await замер("пуск", 0.4);

if (!(сеть["гул"] > 0.02)) беды.push(`в первом акте (станция) нет гула: ${сеть["гул"]}`);
if (!(периметр["гул"] > сеть["гул"])) {
  беды.push(`периметр не громче станции: ${периметр["гул"]} против ${сеть["гул"]}`);
}
/* ── ТИШИНУ МЕРЯЕМ ПОДЛОЖКАМИ, А НЕ ХВОСТАМИ ─────────────────────
   Здесь проверялось ещё и что в окне тишины прямо сейчас не звучит ни
   одного разового. Проверка ПРЫГАЕТ по актам мгновенно, а разовый звук
   длится секунды: свип, начатый в периметре, догорал уже в проколе, и
   проверка показывала «перед броском нет тишины» на совершенно
   правильном звуке. Досиживать окно тоже нельзя: за полторы секунды
   лента уезжает за его край.

   Тишина в замысле это молчание ПОДЛОЖЕК: их гасит сам акт, и они
   меряются мгновенно и честно. Разовые в окне закрыты отдельно, в
   rv-sound.js: обработчики отклика роя, смены текста и касания купола
   спрашивают тихоСейчас() и молчат. */
if (доБроска["гул"] > 0.02) {
  беды.push(`перед броском гул не смолк: ${доБроска["гул"]}`);
}
if (!(тоннель["гул"] > 0.05)) беды.push(`после тишины тоннель молчит: ${тоннель["гул"]}`);

const все = [сеть["гул"], периметр["гул"], тоннель["гул"], выход["гул"]];
const разных = new Set(все.map((v) => v.toFixed(3))).size;
if (разных < 3) беды.push(`громкости почти одинаковы во всех актах: ${все.join(", ")}`);

console.log("сеть     ", JSON.stringify(сеть));
console.log("периметр ", JSON.stringify(периметр));
console.log("до броска", JSON.stringify(доБроска));
console.log("тоннель  ", JSON.stringify(тоннель));
console.log("выход    ", JSON.stringify(выход));

await б.close();
доложить("звук идёт за плёнкой, тишина перед ударом на месте", беды);
