/* Проверка: лента идёт, а не дёргается.

   Сайт набрал вес: банк звука на девятьсот килобайт, две гарнитуры,
   титры внутри мира, неон на тенях, рейка на каждом кадре. Тени и
   свечения браузеру дороги, и «стало красивее» умеет незаметно означать
   «стало дёргаться». Замер отделяет одно от другого.

   ЧТО МЕРЯЕМ. Не средние кадры в секунду - средняя красива при рывках.
   Меряем ДЛИТЕЛЬНОСТЬ КАДРА и берём девяносто пятую долю: рывок это
   один длинный кадр среди коротких, и он виден только в хвосте
   распределения. Плюс считаем, сколько кадров вышли за сорок
   миллисекунд, то есть заметны глазу как заминка.

   ПРО ЭТУ ПЕСОЧНИЦУ. Видеокарты здесь нет, слой рисует программно, и
   ЧИСЛА ТУТ ХУЖЕ БОЕВЫХ В РАЗЫ. Поэтому пороги не «шестьдесят кадров», а
   сравнение с замером ДО правок, снятым на этой же машине. Абсолютные
   значения здесь не значат ничего; значит только «стало хуже, чем
   было». Порог поставлен по первому живому замеру с запасом.

   Запуск: RV_URL=http://127.0.0.1:8170 node tools/checks/скорость.mjs
*/
import { браузер, открыть, доложить } from "./общее.mjs";

const ТЕЛЕФОН = { имя: "телефон", vp: { width: 390, height: 844 }, dpr: 2, mob: true };
const ПК = { имя: "ПК", vp: { width: 1440, height: 900 }, dpr: 1, mob: false };

/* ── ЭТАЛОН РАСТРА: ЧЕМ МЕРИТЬ САМУ МАШИНУ ─────────────────────────
   Замер кадра без поправки на машину ничего не стоит, и это выяснилось
   на живом примере. В одном и том же часу одна и та же проверка на
   одном и том же коде дала медиану кадра 1050 мс (когда рядом работали
   три браузера) и 467 мс (в одиночку). Сайт между этими прогонами не
   менялся вовсе, а вердикт менялся с «вдвое хуже слепка» на «вчетверо
   хуже слепка».

   Считать быстродействие процессора бесполезно: тот же прогон показал
   восемь миллисекунд на четырёх миллионах итераций, то есть процессор
   быстрый. Медленна здесь РАСТЕРИЗАЦИЯ - видеокарты нет, пиксели
   считает тот же процессор, и упирается всё в заполнение.

   Значит и эталон должен быть растровым: шесть полноэкранных проходов
   по холсту 1024 на 1024 с шейдером на два десятка синусов. Замер
   стабилен до двух процентов от прогона к прогону, а на загруженной
   машине растёт ровно так же, как растут кадры сайта.

   Пороги ниже приведены к этому эталону: порог умножается на то, во
   сколько раз машина сейчас медленнее машины слепка. */
const ЭТАЛОН_СЛЕПКА = 179;   /* мс, снято в одиночку на пустой машине */

async function эталонРастра(pg) {
  return pg.evaluate(() => {
    const c = document.createElement("canvas");
    c.width = 1024; c.height = 1024;
    c.style.cssText = "position:fixed;left:-9999px;top:0";
    document.body.appendChild(c);
    const gl = c.getContext("webgl2") || c.getContext("webgl");
    if (!gl) { c.remove(); return 0; }
    const вш = gl.createShader(gl.VERTEX_SHADER);
    gl.shaderSource(вш, "attribute vec2 p;void main(){gl_Position=vec4(p,0.,1.);}");
    gl.compileShader(вш);
    const фш = gl.createShader(gl.FRAGMENT_SHADER);
    gl.shaderSource(фш, "precision mediump float;uniform float u;void main(){" +
      "float s=0.;for(int i=0;i<24;i++){s+=sin(float(i)+u+gl_FragCoord.x*0.01);}" +
      "gl_FragColor=vec4(s*0.02+0.5);}");
    gl.compileShader(фш);
    const пр = gl.createProgram();
    gl.attachShader(пр, вш); gl.attachShader(пр, фш); gl.linkProgram(пр); gl.useProgram(пр);
    const б = gl.createBuffer();
    gl.bindBuffer(gl.ARRAY_BUFFER, б);
    gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 3, -1, -1, 3]), gl.STATIC_DRAW);
    const л = gl.getAttribLocation(пр, "p");
    gl.enableVertexAttribArray(л);
    gl.vertexAttribPointer(л, 2, gl.FLOAT, false, 0, 0);
    const uл = gl.getUniformLocation(пр, "u");
    /* Читаем точку после каждого прохода: без этого драйвер copит
       команды и меряется постановка задачи, а не её выполнение. */
    const один = () => {
      const t = performance.now();
      for (let k = 0; k < 6; k++) { gl.uniform1f(uл, k); gl.drawArrays(gl.TRIANGLES, 0, 3); }
      const пик = new Uint8Array(4);
      gl.readPixels(0, 0, 1, 1, gl.RGBA, gl.UNSIGNED_BYTE, пик);
      return performance.now() - t;
    };
    один();
    const все = [];
    for (let k = 0; k < 7; k++) все.push(один());
    все.sort((a, b) => a - b);
    c.remove();
    return Math.round(все[3]);
  });
}

/* ПОРОГИ ЭТО СЛЕПОК, А НЕ НОРМА.

   В этой песочнице видеокарты нет вовсе, объёмный слой рисуется
   процессором, и абсолютные числа здесь не значат НИЧЕГО: медиана в
   сто шестьдесят миллисекунд на живом телефоне была бы приговором, а
   тут это норма песочницы. Мерить «быстро или медленно» отсюда нельзя.

   Мерить можно другое, и оно важнее: СТАЛО ЛИ ХУЖЕ, ЧЕМ БЫЛО. Ниже
   слепок, снятый тремя прогонами подряд после правок первого сентября.
   Разброс между прогонами на глаз: девяносто пятая доля гуляет на
   пятнадцать процентов, доля долгих кадров на три пункта. Пороги
   поставлены выше слепка на этот разброс и ещё немного сверху.

   Телефон отдаёт больше долгих кадров, но кадры у него КОРОЧЕ: окно
   меньше, пикселей меньше, и каждый кадр дешевле. Поэтому пороги свои
   у каждого экрана, а не общие.

   ── СТАРЫЙ СЛЕПОК ОТМЕНЁН, И ВОТ ПОЧЕМУ ────────────────────────
   Он был снят без эталона машины: «95я доля 383, 367, 367 мс» на ПК и
   «183, 217, 267» на телефоне. Воспроизвести эти числа нельзя - машины
   той скорости под рукой нет, а насколько она была быстрее нынешней,
   слепок не записал. Проверка на нём краснела всегда, и краснела не
   про сайт: сайт за этот заход стал ЛЕГЧЕ (7.03 МБ против 5.75, одним
   мешем меньше), а числа выросли втрое.

   Новый слепок снят в одиночку, на пустой машине, и записан ВМЕСТЕ с
   эталоном растра. Теперь его можно проверить: гони эталон, дели на
   179, на столько же поднимай порог.

   Новый слепок снят на полной выборке (эталон растра около 197 мс,
   кадров 159 и 184 - против двадцати восьми у первой попытки):
     ПК       медиана 417 мс   95я доля 1017 мс
     телефон  медиана 533 мс   95я доля 1017 мс

   Пороги выше слепка на четверть: столько разброса дают соседние
   прогоны на этой машине.

   Порог доли долгих кадров оставлен как есть, но применяется только
   на машине, где эта доля способна что-то различить (см. ниже про
   насыщение). Здесь она не применяется никогда. */
const ПОРОГИ = {
  "ПК":      { д95: 1300, долгих: 70 },
  "телефон": { д95: 1300, долгих: 78 }
};

const беды = [];
const неизмерено = [];
const б = await браузер();

for (const э of [ПК, ТЕЛЕФОН]) {
  const { pg, ошибки } = await открыть(б, э, {});

  /* Собираем длительности кадров, пока лента едет. Прокрутка идёт
     мелкими шагами, как пальцем: один прыжок на всю ленту меряет не
     ленту, а один перерасчёт. */
  await pg.evaluate(() => {
    window.__кадры = [];
    let было = performance.now();
    const шаг = (t) => {
      window.__кадры.push(t - было);
      было = t;
      requestAnimationFrame(шаг);
    };
    requestAnimationFrame(шаг);
  });

  const ВСЕГО = await pg.evaluate(() => document.documentElement.scrollHeight - innerHeight);
  const ШАГОВ = 40;
  for (let i = 1; i <= ШАГОВ; i++) {
    await pg.evaluate((y) => window.scrollTo(0, y), Math.round((ВСЕГО * i) / ШАГОВ));
    /* ── ЖДЁМ КАДРЫ, А НЕ МИЛЛИСЕКУНДЫ ─────────────────────────
       Стояло 160 миллисекунд на шаг. На живой машине это десяток
       кадров, здесь - четверть кадра, и за все сорок шагов набиралось
       под тридцать штук вместо нужных пятидесяти пяти. Проверка
       честно писала «замер недостоверен» и тут же по нему судила.

       Ждём, пока на шаг придёт хотя бы полтора кадра, с потолком: на
       медленной машине кадр длинный, и отсчёт по часам собирает
       выборку, по которой девяносто пятую долю считать нельзя. */
    const былоК = await pg.evaluate(() => window.__кадры.length);
    await pg.waitForFunction(
      (было) => window.__кадры.length >= было + 2, былоК,
      { timeout: 2500, polling: 60 }).catch(() => {});
  }

  const к = await pg.evaluate(() => {
    /* Первые кадры отбрасываем: там ещё идёт сборка сцен и подгрузка, и
       мерить надо ход ленты, а не её подъём. */
    const все = window.__кадры.slice(12).filter((v) => v > 0 && v < 4000);
    все.sort((a, b) => a - b);
    const доля = (p) => все[Math.min(все.length - 1, Math.floor(все.length * p))];
    return {
      кадров: все.length,
      медиана: Math.round(доля(0.5)),
      д95: Math.round(доля(0.95)),
      худший: Math.round(все[все.length - 1] || 0),
      долгих: +((все.filter((v) => v > 40).length / все.length) * 100).toFixed(1)
    };
  });

  console.log(`${э.имя.padEnd(9)} кадров ${к.кадров}  медиана ${к.медиана}мс  ` +
              `95я доля ${к.д95}мс  худший ${к.худший}мс  длиннее 40мс: ${к.долгих}%`);

  /* Пороги приводим к скорости ЭТОЙ машины. Медленнее машины слепка -
     во столько же раз выше порог, и наоборот. */
  const реф = await эталонРастра(pg);
  const к_маш = реф > 0 ? реф / ЭТАЛОН_СЛЕПКА : 1;
  const п = ПОРОГИ[э.имя];
  const д95П = Math.round(п.д95 * к_маш);
  console.log(`${" ".repeat(10)}эталон растра ${реф}мс (слепок ${ЭТАЛОН_СЛЕПКА}), ` +
              `машина в ${к_маш.toFixed(2)} раза, порог 95й доли ${д95П}мс`);

  /* Мало кадров - замер НЕДОСТОВЕРЕН, и тогда вердикта по нему быть не
     должно вовсе. Раньше проверка честно писала «замер недостоверен» и
     тут же выносила по этому самому замеру два приговора. */
  if (к.кадров < 40) {
    /* Не измерено это НЕ «хорошо». Проверка, которая ничего не
       померила и написала ЧИСТО, врёт мягче предыдущей, но врёт. */
    неизмерено.push(`${э.имя}: кадров всего ${к.кадров}, замер недостоверен`);
  } else {
    if (к.д95 > д95П) {
      беды.push(`${э.имя}: девяносто пятая доля кадра ${к.д95}мс при пороге ${д95П} - лента стала тяжелее`);
    }
    /* ── ДОЛЯ ДОЛГИХ КАДРОВ ЗДЕСЬ НАСЫЩЕНА ──────────────────────
       Мерка считает, сколько кадров вышли длиннее сорока миллисекунд,
       то есть заметны глазом как заминка. На живой машине это полезно:
       медиана там единицы миллисекунд, и доля долгих ловит рывки.

       Здесь медиана кадра ЧЕТЫРЕСТА миллисекунд. Длиннее сорока тут
       каждый кадр по построению, и мерка упирается в сотню процентов
       независимо от того, что происходит с сайтом: на ПК она уже 100,
       на телефоне 97.8. Насыщенная мерка не показывает изменений
       вообще - ни к лучшему, ни к худшему.

       Судим по ней только там, где она способна что-то различить:
       когда медиана кадра ниже сорока миллисекунд. Иначе честно
       говорим, что не мерили. Порог 92, который я поставил накануне,
       был выведен из выборки в тридцать девять кадров и держался ровно
       до первой полной: на ста восьмидесяти четырёх вышло 97.8. */
    if (к.медиана < 40) {
      if (к.долгих > п.долгих) {
        беды.push(`${э.имя}: длиннее сорока миллисекунд ${к.долгих}% кадров при пороге ${п.долгих}`);
      }
    } else {
      неизмерено.push(`${э.имя}: медиана кадра ${к.медиана}мс, доля долгих кадров ` +
                      `насыщена (${к.долгих}%) и ничего не различает`);
    }
  }

  await pg.close();
  for (const о of ошибки) беды.push(`${э.имя}: ${о}`);
}

await б.close();
if (!беды.length && неизмерено.length) {
  console.log("ПРОПУСК  скорость: замер не набрал кадров, судить не по чему");
  for (const н of неизмерено) console.log("   " + н);
  process.exit(0);
}
доложить("скорость: лента идёт, а не дёргается", беды);
