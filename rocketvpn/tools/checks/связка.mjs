/* Проверка: переход между сайтами Rocket VPN и Rocket CDN.

   Смысл связки в том, что человек, пришедший через космос, попадает
   ГЛУБЖЕ первого экрана: он уже прошёл сюжет проблемы на той стороне,
   и показывать ему заново «тебя видно» значит отмотать его назад.
   Проверяем именно это, а не наличие ссылки.

   КУДА ИМЕННО - на рабочий пульт финала, доля 0.90 (rv-link.js). Имя
   акта и доля берутся у самого модуля, а не записываются сюда второй
   раз: проверка уже дважды краснела на работающей связке из-за того,
   что сценарий менялся, а она помнила прежнее имя. Сначала искала акт
   «выход», потом акт «рубка» - обоих в разметке давно нет. */
import { браузер, открыть, ПК, ТЕЛЕФОН, доложить } from "./общее.mjs";

const беды = [];
const b = await браузер();

for (const э of [ПК, ТЕЛЕФОН]) {
  /* Приход из космоса. */
  const { pg, ошибки } = await открыть(b, э, { from: "cdn" });
  const приход = await pg.evaluate(() => {
    const a = document.querySelector('[data-акт="финал"]');
    if (!a) return { есть: false };
    const к = a.getBoundingClientRect();
    return {
      есть: true,
      вКадре: к.top <= 0 && к.bottom > innerHeight * 0.5,
      доля: +(getComputedStyle(a).getPropertyValue("--д") || 0),
      признак: document.documentElement.getAttribute("data-из")
    };
  });
  if (!приход.есть) беды.push(э.имя + ": акта финала нет в разметке");
  else {
    if (!приход.вКадре) беды.push(э.имя + ": пришедший из космоса не попал в финал");
    /* Пульт стоит в последней четверти акта: связка приводит на 0.90,
       и попасть надо именно туда, а не в начало подхода. */
    if (!(приход.доля > 0.70 && приход.доля <= 1)) {
      беды.push(э.имя + ": доля финала при приходе " + приход.доля + ", ждали 0.70..1");
    }
  }

  /* ── КНОПКИ УХОДА В CDN БОЛЬШЕ НЕТ, И ЭТО РЕШЕНИЕ ВЛАДЕЛЬЦА ─────
     Здесь стояло «кнопки ухода в CDN нет» красной бедой. Кнопку сняли
     по прямому слову владельца 14.09.2026: «просто кнопки с сайтов
     убрать». Сайты остались связаны приходом (признак from=cdn выше),
     а увода человека на соседний сайт больше нет ни с одной стороны.

     Проверка теперь смотрит в обратную сторону: кнопки быть НЕ должно.
     Вернётся - скажем об этом, потому что вернуться она может только
     по недосмотру. Если владелец однажды попросит её назад, красным
     станет эта строка, и правка будет ровно здесь, одним местом.

     Заодно снят разбор адреса ухода (ключ, noreferrer, from=vpn): он
     проверял то, чего нет. Мёртвая проверка живёт годами и однажды
     начинает оправдывать чужой код. */
  const уход = await pg.evaluate(() => {
    const a = document.getElementById("rvКcdn");
    return a ? { href: a.getAttribute("href") || "" } : null;
  });
  if (уход) беды.push(э.имя + ": кнопка ухода в CDN вернулась на страницу (" + уход.href + ")");

  /* Обычный заход без признака не должен никуда прыгать. */
  await pg.close();
  const обычный = await открыть(b, э, {});
  const где = await обычный.pg.evaluate(() => window.scrollY);
  if (где > 40) беды.push(э.имя + ": обычный заход почему-то уехал на " + где + " точек");
  for (const о of обычный.ошибки) беды.push(э.имя + ": " + о);
  for (const о of ошибки) беды.push(э.имя + ": " + о);
  await обычный.pg.close();
}

await b.close();
доложить("связка с Rocket CDN", беды);
