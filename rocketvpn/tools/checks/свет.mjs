/* Проверка: в кадре есть на что смотреть на ВСЁМ ходу каждого акта.

   Снимок в середине акта ловит не всё. Главный акт сайта - «Прокол» -
   на середине выглядел роскошно, а последнюю треть держал чёрный экран:
   труба честно рисовалась, только мимо кадра. Замер по одной доле этого
   не видел, и человек видел, а проверка нет.

   Поэтому идём по акту ШАГАМИ и меряем яркость общего холста мира в
   каждой точке. Три числа на шаг:
     средняя      - сколько света в кадре вообще,
     макс         - есть ли в нём хоть одно яркое место,
     доля ярких   - сколько кадра занято светом, в процентах.

   Порог по доле ярких, а не по средней: средняя проходит и от одной
   яркой точки на чёрном поле, а человек в этот момент видит чёрное поле.

   Акты, у которых объёмной сцены нет вовсе (первые два рисуются своим
   плоским холстом и снятой в Blender стеной), в проверку не входят: у
   них холст мира законно пуст.

   Запуск: RV_URL=http://127.0.0.1:8170 node tools/checks/свет.mjs
*/
import { браузер, открыть, кАкту, доложить } from "./общее.mjs";

const ТЕЛЕФОН = { имя: "телефон", vp: { width: 390, height: 844 }, dpr: 3, mob: true };
const ПК = { имя: "ПК", vp: { width: 1440, height: 900 }, dpr: 1, mob: false };

/* имя акта -> с какой доли он обязан светиться. Начало и конец у актов
   законно тёмные: там вход и уход. */
const АКТЫ = [
  ["оболочка", 0.20, 0.85],
  ["прокол",   0.42, 0.96],
  ["выход",    0.15, 0.90],
  ["рубка",    0.15, 0.90],
  ["пуск",     0.20, 0.85],
  ["стыковка", 0.15, 0.90]
];
const ШАГ = 0.08;

/* Пороги. Взяты не с потолка: до правки тоннеля мёртвый кусок давал
   0.01 процента ярких точек при 14-17 на живом, а щит на телефоне,
   который Даниэль назвал невидимым, давал 5.2 при 10-16 у соседних
   актов. Ставим порог посередине между «видно» и «не видно». */
const МИН_ДОЛЯ = 2.0;    /* процентов кадра занято светом */
const МИН_МАКС = 90;     /* хоть одно по-настоящему яркое место */

const беды = [];
const б = await браузер();

/* На широком экране кадр поделён пополам намеренно: слева слова с
   притемнением под ними, справа мир. Мерить яркость по ВСЕМУ кадру там
   значит наполовину мерить ту темноту, которую сами и поставили, - и
   честный акт объявлять тёмным. Меряем ту половину, где живёт мир. На
   телефоне колонок нет, мир занимает кадр целиком, и меряем всё. */
async function свет(pg, широко) {
  return pg.evaluate((широко) => new Promise((готово) => {
    /* Два кадра запаса: первый может прийтись на кадр, в котором ядро
       ещё не рисовало, и буфер окажется пуст не потому, что сцена
       чёрная. Читаем буфер рисования прямо здесь - через drawImage
       нельзя, у холста мира не хранится буфер, и копия выходит пустой
       всегда. */
    requestAnimationFrame(() => requestAnimationFrame(() => {
      const c = document.getElementById("rvМир");
      if (!c) return готово(null);
      const gl = c.getContext("webgl2") || c.getContext("webgl");
      if (!gl) return готово(null);
      const ш = gl.drawingBufferWidth, в = gl.drawingBufferHeight;
      const от = широко ? (ш >> 1) : 0;
      const шир = ш - от;
      const бук = new Uint8Array(шир * в * 4);
      gl.readPixels(от, 0, шир, в, gl.RGBA, gl.UNSIGNED_BYTE, бук);
      let s = 0, n = 0, mx = 0, ярких = 0;
      for (let i = 0; i < бук.length; i += 4 * 17) {
        const v = (бук[i] + бук[i + 1] + бук[i + 2]) / 3 * (бук[i + 3] / 255);
        s += v; if (v > mx) mx = v; if (v > 40) ярких++; n++;
      }
      готово({ средняя: +(s / n).toFixed(2), макс: Math.round(mx),
               доля: +(ярких / n * 100).toFixed(2) });
    }));
  }), широко);
}

for (const э of [ПК, ТЕЛЕФОН]) {
  const { pg, ошибки } = await открыть(б, э, {});
  for (const [акт, от, до] of АКТЫ) {
    const строка = [];
    for (let д = от; д <= до + 1e-6; д += ШАГ) {
      const доля = +д.toFixed(2);
      await кАкту(pg, акт, доля);
      const с = await свет(pg, э.vp.width >= 1000);
      if (!с) { беды.push(`${э.имя}/${акт}: холст мира не прочитан`); break; }
      строка.push(`${доля}:${с.доля}%`);
      if (с.доля < МИН_ДОЛЯ || с.макс < МИН_МАКС) {
        беды.push(`${э.имя}/${акт}@${доля}: тёмный кадр - ` +
                  `светом занято ${с.доля}% (порог ${МИН_ДОЛЯ}), макс ${с.макс}`);
      }
    }
    console.log(`${э.имя.padEnd(9)} ${акт.padEnd(10)} ${строка.join("  ")}`);
  }
  await pg.close();
  for (const о of ошибки) беды.push(`${э.имя}: ${о}`);
}

await б.close();
доложить("свет: в кадре есть на что смотреть на всём ходу актов", беды);
