/* Проверка: в кадре есть на что смотреть на ВСЁМ ходу каждого акта.

   Снимок в середине акта ловит не всё. Главный акт сайта - «Прокол» -
   на середине выглядел роскошно, а последнюю треть держал чёрный экран:
   труба честно рисовалась, только мимо кадра. Замер по одной доле этого
   не видел, и человек видел, а проверка нет.

   Поэтому идём по акту ШАГАМИ и меряем яркость общего холста мира в
   каждой точке. Три числа на шаг:
     средняя      - сколько света в кадре вообще,
     макс         - есть ли в нём хоть одно яркое место,
     доля ярких   - сколько кадра занято светом, в процентах.

   Порог по доле ярких, а не по средней: средняя проходит и от одной
   яркой точки на чёрном поле, а человек в этот момент видит чёрное поле.

   Акты, у которых объёмной сцены нет вовсе (первые два рисуются своим
   плоским холстом и снятой в Blender стеной), в проверку не входят: у
   них холст мира законно пуст.

   Запуск: RV_URL=http://127.0.0.1:8170 node tools/checks/свет.mjs
*/
import { PNG } from "pngjs";
import { браузер, открыть, кАкту, актыСтраницы, доложить } from "./общее.mjs";

const ТЕЛЕФОН = { имя: "телефон", vp: { width: 390, height: 844 }, dpr: 3, mob: true };
const ПК = { имя: "ПК", vp: { width: 1440, height: 900 }, dpr: 1, mob: false };

/* имя акта -> с какой доли он обязан светиться. Начало и конец у актов
   законно тёмные: там вход и уход. */
/* ── ИМЕНА АКТОВ БЫЛИ СТАРЫЕ, И ТРЁХ ИЗ ШЕСТИ БОЛЬШЕ НЕТ ─────────
   Здесь стояли «оболочка», «выход» и «стыковка». В разметке таких
   актов нет ни одного: лента идёт станция, периметр, прокол, рубка,
   пуск, финал. Проверка честно печатала по ним проценты - ядро на
   незнакомое имя не падает, - и ни разу не смотрела на первый экран,
   на стену и на финал. То есть на три из шести актов, и ровно на те,
   про которые владелец написал больше всего.

   Это тот же разряд беды, что записан в паспорте приёмки: замер,
   который меряет не то, что нарисовано, хуже отсутствия замера.
   Имена сверены с `frame.html` и держатся его порядком. */
/* Имена актов спрашиваются у страницы (общее.актыСтраницы): держать
   их здесь значит однажды проверить акт, которого нет, и молча
   пропустить тот, который есть. Так уже было дважды. Пределы доли
   общие на все акты: края ленты акта, где смена сцены самая резкая. */
const ОТ = 0.15, ДО = 0.90;
const ШАГ = 0.08;

/* Пороги. Взяты не с потолка: до правки тоннеля мёртвый кусок давал
   0.01 процента ярких точек при 14-17 на живом, а щит на телефоне,
   который Даниэль назвал невидимым, давал 5.2 при 10-16 у соседних
   актов. Ставим порог посередине между «видно» и «не видно». */
const МИН_ДОЛЯ = 2.0;    /* процентов кадра занято светом */
const МИН_МАКС = 90;     /* хоть одно по-настоящему яркое место */

const беды = [];
const б = await браузер();

/* ── ГДЕ СЛОВА, СПРАШИВАЕМ У РАЗМЕТКИ ───────────────────────────
   Кадр резался ПОПОЛАМ ПО ШИРИНЕ: «слева слова с притемнением, справа
   мир». Довод верный, привязка неверная. Ни один акт на этом сайте слова
   сбоку не ставит: все четыре объявляют `data-слова="сверху"`
   (frame.html), то есть слова идут НАД миром, а мир занимает всю ширину.
   Половина кадра отрезалась зря.

   Теперь режем верхнюю полосу с притемнением и меряем остальное во всю
   ширину, а сторону берём из объявления акта. Объявит когда-нибудь акт
   слова сбоку - боковой рез вернётся сам, по тому же объявлению.

   ЭТО НЕ ЗАКРЫЛО ЛОЖНЫЙ ПРИГОВОР ПО ФИНАЛУ, и запись об этом стоит
   здесь нарочно. Первая догадка была такая: ракета в финале стоит по
   центру, справа намеренно пустое небо, оттого и «тёмный кадр». Замер её
   опроверг - во всю ширину финал отдавал те же 0.16-0.63 процента.
   Настоящая причина лежала в способе чтения, и разобрана она ниже. */
const ДОЛЯ_СЛОВ_СВЕРХУ = 0.30;

/* ── МЕРИМ СНИМОК ЭКРАНА, А НЕ БУФЕР РИСОВАНИЯ ──────────────────
   Здесь стоял `gl.readPixels` по холсту мира, и вся проверка на этом
   держалась неверно.

   У холста мира `preserveDrawingBuffer` не включён - и правильно, он
   стоит памяти и скорости. Значит содержимое буфера после того, как
   кадр показан, НЕ ОПРЕДЕЛЕНО: читать его можно только внутри того же
   кадра отрисовки, в котором рисовали. Проверка же читала его из своего
   requestAnimationFrame, то есть в начале СЛЕДУЮЩЕГО кадра, когда буфер
   уже очищен. Что она при этом получит, зависит от того, чей обработчик
   кадра встал раньше.

   Наружу это выходило дикими качелями: финал на доле 0.15 отдавал 100
   процентов, а на 0.31-0.71 от 0.16 до 0.63 - и проверка писала «тёмный
   кадр» на шести долях подряд. Снимок того же места
   (`node tools/кадр.mjs финал 0.55`) показывает ракету на освещённой
   площадке в звёздах: смотреть есть на что, и приговор был ложный.

   Снимок страницы идёт через сборщик кадра браузера и показывает ровно
   то, что видит человек. Он же ловит то, чего буфер мира не покажет
   никогда: погасший слой поверх сцены, залитую плашку, чёрный оверлей.

   Слова у всех актов объявлены сверху (`data-слова`), поэтому режем
   верхнюю полосу с притемнением и меряем остальное во всю ширину. Довод
   прежней половинной резки («слева слова, справа мир») к этому сайту не
   относился вовсе: ни один акт слова сбоку не ставит. */
async function свет(pg, широко, где) {
  const снимок = await pg.screenshot();
  const png = PNG.sync.read(снимок);
  const ш = png.width, в = png.height;
  const сверху = где && где["слова"] === "сверху";
  const сбоку = где && (где["слова"] === "слева" || где["слова"] === "справа");
  const x0 = сбоку && широко ? (ш >> 1) : 0;
  const y0 = сверху ? Math.round(в * где["долясверху"]) : 0;
  let s = 0, n = 0, mx = 0, ярких = 0;
  /* Через строку и через четыре точки: выборки хватает с запасом, а
     полный обход снимка на восьмидесяти замерах стоит минуты. */
  for (let y = y0; y < в; y += 2) {
    for (let x = x0; x < ш; x += 4) {
      const i = (y * ш + x) << 2;
      const v = (png.data[i] + png.data[i + 1] + png.data[i + 2]) / 3;
      s += v; if (v > mx) mx = v; if (v > 40) ярких++; n++;
    }
  }
  if (!n) return null;
  return { средняя: +(s / n).toFixed(2), макс: Math.round(mx),
           доля: +(ярких / n * 100).toFixed(2) };
}

/* Где акт держит слова. Спрашиваем саму разметку: она это объявляет
   атрибутом, и второй раз угадывать по ширине экрана незачем. */
async function гдеСлова(pg, акт, доляСверху) {
  return pg.evaluate(([имя, дс]) => {
    const с = document.querySelector('.rv-акт[data-акт="' + имя + '"]');
    return { "слова": (с && с.getAttribute("data-слова")) || "", "долясверху": дс };
  }, [акт, доляСверху]);
}

for (const э of [ПК, ТЕЛЕФОН]) {
  const { pg, ошибки } = await открыть(б, э, {});
  const АКТЫ = await актыСтраницы(pg);
  if (!АКТЫ.length) беды.push(э.имя + ": в разметке нет ни одного акта");
  for (const акт of АКТЫ) {
    const от = ОТ, до = ДО;
    const где = await гдеСлова(pg, акт, ДОЛЯ_СЛОВ_СВЕРХУ);
    const строка = [];
    for (let д = от; д <= до + 1e-6; д += ШАГ) {
      const доля = +д.toFixed(2);
      await кАкту(pg, акт, доля);
      const с = await свет(pg, э.vp.width >= 1000, где);
      if (!с) { беды.push(`${э.имя}/${акт}: холст мира не прочитан`); break; }
      строка.push(`${доля}:${с.доля}%`);
      if (с.доля < МИН_ДОЛЯ || с.макс < МИН_МАКС) {
        беды.push(`${э.имя}/${акт}@${доля}: тёмный кадр - ` +
                  `светом занято ${с.доля}% (порог ${МИН_ДОЛЯ}), макс ${с.макс}`);
      }
    }
    console.log(`${э.имя.padEnd(9)} ${акт.padEnd(10)} ${строка.join("  ")}`);
  }
  await pg.close();
  for (const о of ошибки) беды.push(`${э.имя}: ${о}`);
}

await б.close();
доложить("свет: в кадре есть на что смотреть на всём ходу актов", беды);
