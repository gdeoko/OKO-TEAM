/* ШОВ МЕЖДУ ТУННЕЛЕМ И РАКЕТОЙ, ПО ЖИВОЙ ПРОКРУТКЕ.

   Владелец: «после туннеля камера куда-то наверх дёргается и потом
   только ровно на ракету смотрит».

   ПОЧЕМУ НЕ ГОДИТСЯ ПРЫЖОК ПО ДОЛЯМ. `кПунктy` ставит камеру сразу в
   акт, перескакивая ПЕРЕГОН - экран прокрутки между концом одного акта
   и началом следующего, на котором камера как раз и переезжает из
   туннеля к ракете. Замер прыжком показывал скачок в семнадцать единиц
   и объявлял его рывком, хотя это была вся длина перегона, пройденная
   за один шаг замера. Ровно на перегоне и живёт беда, значит идти надо
   САМОЙ ПРОКРУТКОЙ, мелким шагом, и мерить не только место, но и
   НАПРАВЛЕНИЕ ВЗГЛЯДА: «дёргается наверх» это про взгляд.

   Судим по трём числам на каждом шаге:
     место   - насколько камера сдвинулась;
     высота  - сдвиг по вертикали отдельно, рывок именно там;
     взгляд  - угол между направлениями взгляда соседних шагов.
   Рывок это шаг, заметно больший СОСЕДНИХ (сравниваем с медианой всего
   отрезка): постоянный порог тут не годится, у перегона своя скорость.

   Запуск: node tools/шов-туннеля.mjs [тел|пк]
*/
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";
import { mkdirSync } from "node:fs";

const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const КТО = process.argv[2] || "тел";
const КУДА = "/tmp/шов-туннеля";
const экран = КТО === "пк"
  ? { w: 1440, h: 900, dpr: 1, mob: false }
  : { w: 390, h: 844, dpr: 1, mob: true };

/* Отрезок меряется ЭКРАНАМИ от конца прокола: перегон и хвост туннеля
   на разных телефонах разной длины в точках, а в экранах одинаковы.
   Ширину окна задаём снаружи, чтобы одной и той же проверкой смотреть и
   сам шов, и весь хвост туннеля перед ним. */
const ШАГОВ = +(process.env.RV_STEPS || 26);
const ДО_ШВА = +(process.env.RV_BEFORE || 0.6);      /* экранов до конца прокола */
const ПОСЛЕ_ШВА = +(process.env.RV_AFTER || 0.34); /* доля финала после */

mkdirSync(КУДА, { recursive: true });

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"]
});
const стр = await бр.newPage({
  viewport: { width: экран.w, height: экран.h },
  deviceScaleFactor: экран.dpr, isMobile: экран.mob, hasTouch: экран.mob
});
const беды = [];
стр.on("pageerror", (e) => беды.push("ИСКЛ " + e.message.slice(0, 200)));

await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 90000 });
await стр.waitForFunction(
  () => window.RV_WORLD && window.RV_WORLD["вступлениеИдёт"] && !window.RV_WORLD["вступлениеИдёт"](),
  null, { timeout: 240000 }).catch(() => console.log("вступления не дождались"));
await стр.waitForTimeout(2000);

/* Границы отрезка берём у самой ленты: верх акта плюс его ход. Считать
   их на бумаге нельзя - высота акта зависит от экрана. */
const границы = await стр.evaluate(() => {
  const кто = (имя) => document.querySelector('.rv-акт[data-акт="' + имя + '"]');
  const вы = window.RV_СКРОЛЛ["высота"]();
  const y0 = window.RV_СКРОЛЛ["y"]();
  const пр = кто("прокол"), фи = кто("финал");
  const вп = y0 + пр.getBoundingClientRect().top;
  const вф = y0 + фи.getBoundingClientRect().top;
  return { верхПрокола: вп, ходПрокола: pr(пр), верхФинала: вф, ходФинала: pr(фи), окно: вы };
  function pr(эл) { return Math.max(1, эл.getBoundingClientRect().height - вы); }
});

const конецПрокола = границы.верхПрокола + границы.ходПрокола;
const A = Math.max(границы.верхПрокола, конецПрокола - границы.окно * ДО_ШВА);
const B = границы.верхФинала + границы.ходФинала * ПОСЛЕ_ШВА;
console.log(`\n${КТО} ${экран.w}x${экран.h}`);
console.log(`  конец прокола ${Math.round(конецПрокола)}, начало финала ${Math.round(границы.верхФинала)}, ` +
            `перегон ${Math.round(границы.верхФинала - конецПрокола)} точек`);
console.log(`  идём с ${Math.round(A)} по ${Math.round(B)}, ${ШАГОВ} шагов\n`);

/* ── ПЕРВЫЙ ШАГ ВСЕГДА ВРАЛ ──────────────────────────────────────
   Прокрутка с нуля на десять тысяч точек это не шаг замера, а прыжок
   через весь фильм, и камера доезжает до места дольше, чем сторож
   покоя готов ждать: он видит её замершей на полдороге и снимает
   показание. В каждом прежнем прогоне первая строка печатала одно и то
   же место (17.54 129.09) независимо от того, куда мы встали, и дальше
   объявлялась рывком в восемьдесят шесть единиц.

   Встаём на начало отрезка заранее и ждём с запасом, а первое
   показание берём уже оттуда. */
await стр.evaluate((y) => window.RV_СКРОЛЛ["к"](y, false), A);
await стр.waitForTimeout(4000);

const ряд = [];
for (let i = 0; i <= ШАГОВ; i++) {
  const y = A + (B - A) * (i / ШАГОВ);
  await стр.evaluate((y) => window.RV_СКРОЛЛ["к"](y, false), y);
  /* Ждём, пока камера сядет: у хода есть поводок, и снимок сразу после
     прокрутки поймал бы её на подлёте. */
  let было = null, тихих = 0, кругов = 0;
  while (тихих < 3 && кругов < 40) {
    const п = await стр.evaluate(() => {
      const c = window.RV_WORLD["мир"]().cam.position;
      return [c.x, c.y, c.z];
    });
    if (было) {
      const d = Math.hypot(п[0] - было[0], п[1] - было[1], п[2] - было[2]);
      тихих = d < 0.02 ? тихих + 1 : 0;
    }
    было = п; кругов++;
    await стр.waitForTimeout(160);
  }

  const з = await стр.evaluate(() => {
    const м = window.RV_WORLD["мир"]();
    const c = м.cam;
    c.updateMatrixWorld(true);
    const е = new м.T.Vector3(0, 0, -1).applyQuaternion(c.quaternion).normalize();
    let ракета = null;
    if (м.scene) м.scene.traverse(function (о) {
      if (ракета) return;
      if (!/ракет|корабл/i.test((о.name || "") + "")) return;
      let в = о.visible, р = о.parent;
      while (в && р) { в = р.visible; р = р.parent; }
      о.updateMatrixWorld(true);
      const п = new м.T.Vector3();
      п.setFromMatrixPosition(о.matrixWorld);
      ракета = { видна: в, y: +п.y.toFixed(2) };
    });
    const дело = document.querySelector('.rv-дело[data-сектор="финал:0"]');
    const rd = дело ? дело.getBoundingClientRect() : null;
    return {
      кам: [+c.position.x.toFixed(2), +c.position.y.toFixed(2), +c.position.z.toFixed(2)],
      взгляд: [+е.x.toFixed(4), +е.y.toFixed(4), +е.z.toFixed(4)],
      ракета: ракета,
      кнопка: rd ? { верх: Math.round(rd.top), видно: +(+getComputedStyle(дело).opacity).toFixed(2) } : null
    };
  });
  ряд.push({ y: Math.round(y), ...з });
}

const места = [], высоты = [], углы = [];
for (let i = 1; i < ряд.length; i++) {
  const a = ряд[i - 1], b = ряд[i];
  места.push(Math.hypot(b.кам[0] - a.кам[0], b.кам[1] - a.кам[1], b.кам[2] - a.кам[2]));
  высоты.push(b.кам[1] - a.кам[1]);
  const т = Math.min(1, Math.max(-1,
    a.взгляд[0] * b.взгляд[0] + a.взгляд[1] * b.взгляд[1] + a.взгляд[2] * b.взгляд[2]));
  углы.push(Math.acos(т) * 180 / Math.PI);
}
const мед = (м) => { const с = [...м].sort((x, y) => x - y); return с[Math.floor(с.length / 2)] || 0.001; };
const медМеста = мед(места), медУгла = мед(углы), медВыс = мед(высоты.map(Math.abs));

for (let i = 0; i < ряд.length; i++) {
  const з = ряд[i];
  const м = i ? места[i - 1] : 0, в = i ? высоты[i - 1] : 0, у = i ? углы[i - 1] : 0;
  const р = з.ракета;
  console.log(
    `  y ${String(з.y).padStart(6)}  камера ${з.кам.join(" ")}` +
    `  шаг ${м.toFixed(2)} (выс ${в > 0 ? "+" : ""}${в.toFixed(2)})` +
    `  взгляд ${з.взгляд.map((ч) => (ч >= 0 ? " " : "") + ч.toFixed(3)).join(" ")} (${у.toFixed(1)} гр)` +
    `  ракета ${р ? (р.видна ? "y" + р.y : "скрыта") : "нет"}` +
    (з.кнопка ? `  кнопка верх ${з.кнопка.верх} видно ${з.кнопка.видно}` : ""));
}
console.log(`\n  медианы: место ${медМеста.toFixed(2)}, высота ${медВыс.toFixed(2)}, взгляд ${медУгла.toFixed(1)} гр`);

const итог = [];
for (let i = 1; i < ряд.length; i++) {
  if (углы[i - 1] > Math.max(3, медУгла * 4)) {
    итог.push(`рывок взгляда между y ${ряд[i - 1].y} и ${ряд[i].y}: ` +
              `${углы[i - 1].toFixed(1)} гр при медиане ${медУгла.toFixed(1)}`);
  }
  if (Math.abs(высоты[i - 1]) > Math.max(1.0, медВыс * 5)) {
    итог.push(`рывок по высоте между y ${ряд[i - 1].y} и ${ряд[i].y}: ` +
              `${высоты[i - 1].toFixed(2)} при медиане ${медВыс.toFixed(2)}`);
  }
}

/* Ракета обязана ПРИЕХАТЬ, а не возникнуть. */
const сР = ряд.filter((з) => з.ракета && з.ракета.видна).map((з) => з.ракета.y);
if (сР.length >= 2) {
  const ход = Math.max(...сР) - Math.min(...сР);
  console.log(`  ход ракеты по высоте: ${ход.toFixed(2)}`);
  if (ход < 0.5) итог.push(`ракета не садится: её высота меняется на ${ход.toFixed(2)}`);
}

/* Кнопка выходит ПОСЛЕ посадки, снизу. Ищем первый шаг, где её видно,
   и сверяем с шагом, на котором ракета уже села. */
const первВид = ряд.findIndex((з) => з.кнопка && з.кнопка.видно > 0.05);
const села = ряд.findIndex((з) => з.ракета && з.ракета.видна &&
  Math.abs(з.ракета.y - Math.min(...сР)) < 0.05);
if (первВид >= 0 && села >= 0) {
  console.log(`  кнопка проступает на y ${ряд[первВид].y}, ракета села на y ${ряд[села].y}`);
  if (первВид < села) итог.push(`кнопка выходит раньше посадки: y ${ряд[первВид].y} против ${ряд[села].y}`);
} else if (первВид < 0) {
  console.log("  кнопка на отрезке не проступила ни разу");
}

if (беды.length) итог.push("ошибки страницы: " + [...new Set(беды)].slice(0, 5).join(" | "));

if (итог.length) {
  console.log("\nКРАСНОЕ:");
  for (const с of итог) console.log("   " + с);
} else {
  console.log("\nзелено: шов без рывка, ракета садится, кнопка после неё");
}
await бр.close();
process.exit(итог.length ? 1 : 0);
