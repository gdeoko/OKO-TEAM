/* ЧТО ЗА ШАР СТОИТ ПЕРЕД РАКЕТОЙ И КУДА ДЕВАЕТСЯ САМА РАКЕТА.

   Владелец, дважды: «после разлёта стены появляется вдалеке круг
   какой-то непонятный», «перед входом в ракету баг с космосом и
   пропаданием». На снимках видно бежевый шар за ракетой, а ещё кадр,
   где корпуса нет вовсе и в шаре висит одна кабина.

   Угадывать тут нечего: сцена знает свои узлы по именам. Идём по
   финалу долями и на каждой печатаем ВСЕ видимые узлы, которые
   попадают в кадр, с их местом, размером на экране и именем. Шар
   назовёт себя сам, а пропажу корпуса видно по тому, что узел ракеты
   перестал быть видимым, - и это разные беды с разным лечением.

   Запуск: node tools/шар-перед-ракетой.mjs [тел|пк]
*/
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";

const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const КТО = process.argv[2] || "тел";
const экран = КТО === "пк"
  ? { w: 1440, h: 900, dpr: 1, mob: false }
  : { w: 390, h: 844, dpr: 1, mob: true };

const ДОЛИ = [0.00, 0.10, 0.20, 0.30, 0.44, 0.55, 0.65, 0.75, 0.85, 0.95];

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"]
});
const стр = await бр.newPage({
  viewport: { width: экран.w, height: экран.h },
  deviceScaleFactor: экран.dpr, isMobile: экран.mob, hasTouch: экран.mob
});
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 90000 });
await стр.waitForFunction(
  () => window.RV_WORLD && window.RV_WORLD["вступлениеИдёт"] && !window.RV_WORLD["вступлениеИдёт"](),
  null, { timeout: 240000 }).catch(() => console.log("вступления не дождались"));
await стр.waitForTimeout(2000);

console.log(`\n${КТО} ${экран.w}x${экран.h}`);
const ряд = [];
for (const д of ДОЛИ) {
  await стр.evaluate((д) => window.RV_MOTION["кПунктy"]("финал", д), д);
  await стр.waitForTimeout(2200);
  const з = await стр.evaluate(() => {
    const м = window.RV_WORLD["мир"]();
    const T = м.T, cam = м.cam;
    cam.updateMatrixWorld(true);
    /* Кадром считаем то, что проецируется внутрь экрана и стоит перед
       камерой. Размер на экране берём у габаритной коробки: по нему
       видно, шар это на весь кадр или точка вдалеке. */
    const из = [];
    м.scene.traverse(function (о) {
      if (!о.isMesh && !о.isPoints) return;
      let в = о.visible, р = о.parent;
      while (в && р) { в = р.visible; р = р.parent; }
      if (!в) return;
      let имя = "";
      for (let у = о; у; у = у.parent) { if (у.name) { имя = у.name; break; } }
      if (!имя) имя = о.type;
      о.updateMatrixWorld(true);
      const к = new T.Box3().setFromObject(о);
      if (!isFinite(к.min.x) || к.isEmpty()) return;
      const ц = к.getCenter(new T.Vector3());
      const р2 = к.getSize(new T.Vector3()).length() * 0.5;
      const вК = ц.clone().project(cam);
      if (!(вК.z > -1 && вК.z < 1)) return;
      if (Math.abs(вК.x) > 1.4 || Math.abs(вК.y) > 1.4) return;
      const даль = cam.position.distanceTo(ц);
      /* Доля экрана по высоте: радиус в единицах, делённый на половину
         видимой высоты кадра на этой дальности. */
      const полВысоты = Math.tan(cam.fov * Math.PI / 360) * Math.max(0.001, даль);
      из.push({ имя: имя, доля: +(р2 / полВысоты).toFixed(2), даль: +даль.toFixed(1),
                x: +вК.x.toFixed(2), y: +вК.y.toFixed(2) });
    });
    /* Одно имя может носить много кусков; оставляем самый крупный. */
    const лучшее = {};
    for (const о of из) {
      if (!лучшее[о.имя] || о.доля > лучшее[о.имя].доля) лучшее[о.имя] = о;
    }
    let фон = null;
    try { фон = window.RV_ФОН && window.RV_ФОН["замер"] ? window.RV_ФОН["замер"]()["сила"] : null; } catch (e) {}
    /* Печатаем восьмёрку крупнейших, а СУДИМ по всему списку: на доле
       0.30 в кадре стоят четыре строки объёмного текста, они вытесняют
       корабль из восьмёрки, и проверка объявляла пропажу там, где
       корабль стоит на месте. */
    const всё = Object.values(лучшее).sort((a, b) => b.доля - a.доля);
    return { узлы: всё.slice(0, 8), все: всё, фон: фон };
  });
  ряд.push({ д, ...з });
  console.log(`  доля ${д.toFixed(2)}  оболочка ${з.фон}`);
  for (const у of з.узлы) {
    console.log(`     ${у.имя.padEnd(26)} экран ${String(у.доля).padStart(6)}  даль ${String(у.даль).padStart(7)}  центр ${у.x}/${у.y}`);
  }
}

const беды = [];
/* Оболочка подземелья это ПОТОЛОК над головой, а не предмет в кадре.
   Стоит она шаром радиуса сто, и если камера оказалась снаружи, тот же
   шар читается бежевым мячом вдалеке - ровно то, что прислал владелец. */
for (const с of ряд) {
  const об = с.узлы.find((у) => /оболочк|подземел/i.test(у.имя));
  if (об && об.доля < 3) {
    беды.push(`доля ${с.д}: оболочка подземелья видна ПРЕДМЕТОМ (${об.доля} экрана, даль ${об.даль}), а должна быть потолком`);
  }
}
/* ── РАКЕТА В КАДРЕ, ПОКА МЫ СНАРУЖИ ─────────────────────────────
   Первый заход требовал корпус на ВСЕХ долях и краснел на половине
   акта. Требование было неверным: войдя внутрь, человек стоит в
   корабле, и корпус вокруг него в кадр не проецируется - это не
   пропажа, а то самое «зашли». Меряем там, где корпус обязан быть:
   на подходе, пока за окном ещё ничего не видно. */
const снаружи = ряд.filter((с) => !(с.все || с.узлы).some((у) => /Орбита за окном/i.test(у.имя)));
const безРакеты = снаружи.filter((с) => с.д > 0.02 &&
  !(с.все || с.узлы).some((у) => /ракет|корабл/i.test(у.имя)));
if (безРакеты.length) {
  беды.push("на подходе ракеты нет в кадре на долях: " + безРакеты.map((с) => с.д.toFixed(2)).join(", "));
}

if (беды.length) {
  console.log("\nКРАСНОЕ:");
  for (const с of беды) console.log("   " + с);
} else {
  console.log("\nзелено: лишнего шара нет, ракета в кадре всю дорогу");
}
await бр.close();
process.exit(беды.length ? 1 : 0);
