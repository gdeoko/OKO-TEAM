/* ЭКРАННАЯ СКОРОСТЬ ЛЕНТЫ: сколько долей экрана проезжает то, на что
   человек смотрит, за тысячу пикселей прокрутки.

   Владелец: «скорость движения камеры по всему сайту точно такая же,
   как на igloo; все анимации, действия сценария должны быть в одной
   скорости и движении, привязанные к скроллу».

   ── ПОЧЕМУ НЕ МИРОВАЯ СКОРОСТЬ ────────────────────────────────────
   Соседняя проверка (tools/скорость-ленты.mjs) меряет путь камеры в
   единицах мира на пиксель прокрутки, и по ней прокол едет 20.1, а
   финал 4.5 - вчетверо медленнее. Но единиц мира человек не видит. Он
   видит, как быстро картинка ползёт по экрану, а это зависит от
   расстояния до того, на что он смотрит: в пустом ледяном просторе
   двадцать единиц выглядят медленнее, чем пять единиц внутри рубки,
   где стена в двух метрах от глаза.

   Паспорт igloo (docs/РАЗБОР-IGLOO-ДВИЖЕНИЕ.md) замерен ровно так же:
   поводок ±0.5625 ЭКРАНА, ограничение 4.5 ЭКРАНА в секунду. Значит и
   ровность ленты надо мерить в экранах, иначе мы сверяемся с igloo по
   мерке, которой у igloo нет.

   ── ГЛУБИНУ БЕРЁМ У МИРА, А НЕ У ЛУЧЕМЁТА ─────────────────────────
   Первый заход этой мерки пускал сетку лучей в сцену и брал точки
   попадания. Считалось это ПЯТЬ СЕКУНД на пробу: `intersectObjects`
   идёт по всем видимым сеткам, а их в акте сотни, и ещё требовалась
   прокрутка с отрисовкой, чтобы акт успел собраться. На ленте в
   восемнадцать тысяч пикселей это часы.

   А глубину мир знает и так: `проба(y)` отдаёт `доВзгляда` -
   расстояние от камеры до точки, на которую она смотрит по сценарию.
   Это ровно та глубина, на которой человек и смотрит. Ставим на ней
   крест из пяти точек, проецируем его двумя позами и меряем сдвиг.
   Ни одной отрисовки, ни одного луча; вся лента считается секунды.

   Поза берётся у пробы, а не у живой камеры: проба не включает дрожь
   и дыхание (они функция времени, а не ленты) и потому не шумит.

   Запуск: node tools/экранная-скорость.mjs [пк|тел] [акт] */
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";

const КТО = process.argv[2] || "пк";
const ПРОФИЛЬ = process.argv[3] || "";
const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const экран = КТО === "пк" ? { width: 1440, height: 900 } : { width: 390, height: 844 };
/* Имя переменной окружения латиницей: bash в этом окружении
   кириллические имена не принимает («not a valid identifier»), об этом
   уже записано в rocketcdn/tools/checks/все.sh. */
const ШАГ = +(process.env.RV_STEP || 30);      /* пикселей ленты между пробами */

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader",
         "--force-device-scale-factor=1"]
});
const кон = await бр.newContext({
  viewport: экран, deviceScaleFactor: 1,
  isMobile: КТО === "тел", hasTouch: КТО === "тел"
});
const стр = await кон.newPage();
стр.on("pageerror", (e) => console.log("ИСКЛ " + e.message.slice(0, 120)));
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 120000 });
await стр.waitForFunction(() => window.RV_WORLD && window.RV_WORLD["мир"] && window.RV_WORLD["мир"](),
                          null, { timeout: 300000 });
await стр.waitForTimeout(4000);

const акты = await стр.evaluate(() => {
  const к = window.RV_WORLD["кривая"] ? window.RV_WORLD["кривая"]() : null;
  if (!к || !к["станции"]) return null;
  return к["станции"].filter((с) => с["ход"] > 0).map((с) => ({
    имя: с["имя"], верх: с["верх"], ход: с["ход"]
  }));
});
if (!акты) {
  console.log("мир не отдал список актов через кривую()");
  await бр.close();
  process.exit(1);
}

const всего = await стр.evaluate(() =>
  Math.max(0, document.documentElement.scrollHeight - window.innerHeight));

const пробы = await стр.evaluate(([шаг, конец]) => {
  const W = window.RV_WORLD["мир"]();
  const T = W.T;
  const камА = new T.PerspectiveCamera(50, 1, 0.05, 8000);
  const камБ = new T.PerspectiveCamera(50, 1, 0.05, 8000);
  const стор = (window.innerWidth || 1) / (window.innerHeight || 1);

  function поставить(кам, п) {
    кам.fov = п["поле"] || 50;
    кам.aspect = стор;
    кам.position.set(п["камера"][0], п["камера"][1], п["камера"][2]);
    кам.up.set(0, 1, 0);
    кам.lookAt(п["взгляд"][0], п["взгляд"][1], п["взгляд"][2]);
    кам.updateMatrixWorld(true);
    кам.updateProjectionMatrix();
  }

  /* Крест из пяти точек на глубине взгляда. Одной точки мало: чистый
     поворот камеры вокруг оси взгляда центр не двигает вовсе, а
     картинка при этом крутится. Смещения берём в долях полукадра на
     этой глубине, чтобы крест всегда занимал одну и ту же часть
     экрана независимо от того, далеко смотрит камера или близко. */
  const КРЕСТ = [[0, 0], [-0.5, 0], [0.5, 0], [0, -0.5], [0, 0.5]];

  function точки(п) {
    const гл = Math.max(0.05, п["доВзгляда"] || 1);
    const тан = Math.tan(((п["поле"] || 50) * Math.PI / 180) / 2);
    const полуВ = гл * тан, полуШ = полуВ * стор;
    const центр = new T.Vector3(п["взгляд"][0], п["взгляд"][1], п["взгляд"][2]);
    const вперёд = new T.Vector3().subVectors(
      центр, new T.Vector3(п["камера"][0], п["камера"][1], п["камера"][2])).normalize();
    const право = new T.Vector3().crossVectors(вперёд, new T.Vector3(0, 1, 0));
    if (право.lengthSq() < 1e-8) право.set(1, 0, 0); else право.normalize();
    const верх = new T.Vector3().crossVectors(право, вперёд).normalize();
    return КРЕСТ.map(([дx, дy]) => центр.clone()
      .addScaledVector(право, дx * полуШ)
      .addScaledVector(верх, дy * полуВ));
  }

  const из = [];
  for (let y = 0; y + шаг <= конец; y += шаг) {
    const пА = window.RV_WORLD["проба"](y), пБ = window.RV_WORLD["проба"](y + шаг);
    if (!пА || !пБ) return null;
    поставить(камА, пА);
    поставить(камБ, пБ);
    const мир = точки(пА);
    const сдвиги = [];
    for (const т of мир) {
      const а = т.clone().project(камА);
      const б = т.clone().project(камБ);
      /* NDC по вертикали от -1 до 1, то есть два «экрана» на высоту.
         Делим на два, чтобы получить доли высоты экрана. Горизонталь
         приводим к тому же масштабу через отношение сторон, иначе
         широкий кадр занижал бы боковой сдвиг. */
      const дx = (б.x - а.x) * 0.5 * стор, дy = (б.y - а.y) * 0.5;
      сдвиги.push(Math.hypot(дx, дy));
    }
    сдвиги.sort((a, b) => a - b);
    из.push({ y: y, сдвиг: сдвиги[2], глубина: +(пА["доВзгляда"] || 0).toFixed(2) });
  }
  return из;
}, [ШАГ, всего]);

if (!пробы) {
  console.log("проба мира вернула пусто");
  await бр.close();
  process.exit(1);
}

function медиана(м) {
  if (!м.length) return 0;
  const с = м.slice(); с.sort((a, b) => a - b);
  return с[Math.floor(с.length / 2)];
}

/* Ниже двух процентов экрана на тысячу пикселей ход не виден: это
   меньше двух пикселей на щелчок колеса. Такие куски в ходовую
   скорость не попадают - иначе долгая стоянка в рубке занизила бы
   медиану акта и ровность ленты стала бы неразличима. */
const ЕДЕТ = 0.02;

const свод = [];
for (const а of акты) {
  const свои = пробы.filter((п) => п.y >= а.верх && п.y + ШАГ <= а.верх + а.ход);
  if (свои.length < 3) continue;
  const скор = свои.map((п) => п.сдвиг / ШАГ * 1000);
  const едут = скор.filter((v) => v >= ЕДЕТ);
  свод.push({
    имя: а.имя, ход: Math.round(а.ход), проб: свои.length,
    медиана: +медиана(скор).toFixed(3),
    ходовая: едут.length ? +медиана(едут).toFixed(3) : 0,
    доляХода: Math.round(едут.length / скор.length * 100),
    пик: +Math.max.apply(null, скор).toFixed(3),
    глубина: медиана(свои.map((п) => п.глубина)),
    профиль: скор.map((v) => +v.toFixed(2))
  });
}

console.log(`ЭКРАННАЯ СКОРОСТЬ ${КТО} ${экран.width}x${экран.height}, шаг ${ШАГ}px`);
console.log("  акт            лента,px   экранов/1000px   на ходу   доля хода   пик     глубина");
for (const с of свод) {
  console.log(`  ${с.имя.padEnd(14)} ${String(с.ход).padEnd(10)} ${String(с.медиана).padEnd(16)}` +
              ` ${String(с.ходовая).padEnd(9)} ${(с.доляХода + "%").padEnd(11)} ${String(с.пик).padEnd(7)} ${с.глубина}`);
}

if (ПРОФИЛЬ) {
  for (const с of свод) {
    if (с.имя !== ПРОФИЛЬ) continue;
    console.log(`  профиль «${с.имя}», экранов на 1000px:`);
    console.log("    " + с.профиль.join("  "));
  }
}

/* ── ВЕРДИКТ ────────────────────────────────────────────────────
   Сверяем ХОДОВУЮ скорость: медиану по тем кускам, где картинка
   реально едет. Медиана по всему акту занижена там, где камера по
   замыслу долго стоит (рубка финала, разбор дома по кирпичикам), и по
   ней ровность ленты не видна вовсе.

   Порог разброса - вдвое. Абсолютной «правильной» цифры нет: у igloo
   замерено ограничение 4.5 экрана в секунду, а это про палец, не про
   ленту. Нам нужно, чтобы акты не расходились между собой. Вдвое это
   предел, за которым переход между актами читается как смена темпа. */
const ходовые = свод.filter((с) => с.ходовая > 0);
if (ходовые.length >= 2) {
  const мин = Math.min.apply(null, ходовые.map((с) => с.ходовая));
  const макс = Math.max.apply(null, ходовые.map((с) => с.ходовая));
  const раз = макс / мин;
  const кто = ходовые.filter((с) => с.ходовая === мин || с.ходовая === макс).map((с) => с.имя);
  console.log(`  разброс ходовой скорости ${раз.toFixed(1)}x` +
              ` (от ${мин} до ${макс} экрана на 1000px: ${кто.join(" и ")})`);
  if (раз > 2) {
    console.log("ГРЯЗНО  акты идут с разной экранной скоростью");
    await бр.close();
    process.exit(1);
  }
}
console.log("ЧИСТО  экранная скорость ровная");
await бр.close();
