/* СКОРОСТЬ КАМЕРЫ ПО ВСЕЙ ЛЕНТЕ, АКТ ЗА АКТОМ.

   Владелец: «скорость движения камеры по всему сайту точно такая же,
   как на igloo; все анимации, действия сценария должны быть в одной
   скорости и движении, привязанные к скроллу».

   Прокрутка у нас уже сделана по igloo: те же две подтяжки 0.075 и
   0.15, тот же поводок, то же ограничение скорости (rv-motion.js).
   Вопрос в другом - сколько МИРА проезжает камера за один и тот же
   ход прокрутки в разных актах.

   Здесь это считается прямо: у каждого акта берётся его отрезок ленты
   в пикселях и путь камеры по нему в единицах мира. Отношение и есть
   скорость. Ровная лента - это когда она у актов одна.

   Ход внутри акта тоже мерим: камера может пройти свой путь рывком.
   Для этого отрезок делится на двадцать частей и считается размах
   скорости внутри акта.

   Запуск: node tools/скорость-ленты.mjs [пк|тел] */
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";

const КТО = process.argv[2] || "пк";
const ПРОФИЛЬ = process.argv[3] || "";
const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const экран = КТО === "пк" ? { width: 1440, height: 900 } : { width: 390, height: 844 };

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader",
         "--force-device-scale-factor=1"]
});
const кон = await бр.newContext({
  viewport: экран, deviceScaleFactor: 1,
  isMobile: КТО === "тел", hasTouch: КТО === "тел"
});
const стр = await кон.newPage();
стр.on("pageerror", (e) => console.log("ИСКЛ " + e.message.slice(0, 120)));
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 120000 });
await стр.waitForFunction(() => window.RV_WORLD && window.RV_WORLD["мир"] && window.RV_WORLD["мир"](),
                          null, { timeout: 300000 });
await стр.waitForTimeout(4000);

/* Список актов с их отрезками ленты. Спрашиваем мир, а не считаем сами:
   отрезки он раскладывает по высоте секций разметки. */
const акты = await стр.evaluate(() => {
  const к = window.RV_WORLD["кривая"] ? window.RV_WORLD["кривая"]() : null;
  if (!к || !к["станции"]) return null;
  return к["станции"].filter((с) => с["ход"] > 0).map((с) => ({
    имя: с["имя"], верх: с["верх"], ход: с["ход"]
  }));
});
if (!акты) {
  console.log("мир не отдал список актов через замер()");
  await бр.close();
  process.exit(1);
}

/* ── БЕРЁМ ПРОБУ МИРА, А НЕ ЖИВУЮ КАМЕРУ ──────────────────────
   Мир отдаёт `RV_WORLD.проба(y)` - позу камеры в любой точке ленты,
   посчитанную по тем же кривым БЕЗ отрисовки. Она намеренно не
   включает отделку хода (дрожь, дыхание, расхождение поля на
   скорости): это функция времени и скорости пальца, а не ленты, и в
   замере ровности пути она шум. Так прямо и написано у самой пробы -
   «ради этой пробы и разделён ход».

   Два первых захода этой проверки мерили ЖИВУЮ камеру и поэтому
   мерили шум. Прыжками по актам станция давала путь 0.34 в одном
   прогоне и 15.15 в другом; сквозным проходом профиль финала
   начинался с 18.32, 0.15, 2.2, 16.81, 0.2 - это не закон движения, а
   дрожь плюс сборка акта, которая случается ровно в тот кадр, когда
   лента до него дошла. По таким числам искать беду в законе движения
   бессмысленно.

   Проба заодно в разы быстрее: не нужно ждать кадры отрисовки. */
const ШАГ = 8;
const всего = await стр.evaluate(() =>
  Math.max(0, document.documentElement.scrollHeight - window.innerHeight));
const точки = await стр.evaluate(([шаг, конец]) => {
  const из = [];
  for (let y = 0; y <= конец; y += шаг) {
    const п = window.RV_WORLD["проба"](y);
    if (!п) return null;
    const к = п["камера"] || п["кам"] || п["поз"] || null;
    if (!к) return { нет: Object.keys(п) };
    из.push({ y: y, п: [к[0], к[1], к[2]] });
  }
  return из;
}, [ШАГ, всего]);
if (!точки || точки.нет) {
  console.log("проба вернула не то: " + JSON.stringify(точки));
  await бр.close();
  process.exit(1);
}

const свод = [];
for (const а of акты) {
  /* Куски этого акта: пары соседних точек, попавшие в его отрезок. */
  const свои = точки.filter((т) => т.y >= а.верх && т.y <= а.верх + а.ход);
  if (свои.length < 3) continue;
  const скор = [];
  let путь = 0;
  for (let i = 1; i < свои.length; i++) {
    const a = свои[i - 1].п, b = свои[i].п;
    const d = Math.hypot(b[0] - a[0], b[1] - a[1], b[2] - a[2]);
    const dy = Math.max(1, свои[i].y - свои[i - 1].y);
    путь += d;
    скор.push(d / dy);
  }
  const мин = Math.min.apply(null, скор), макс = Math.max.apply(null, скор);
  /* ── РАЗРЫВ, А НЕ РАЗМАХ ────────────────────────────────────────
     Размах скорости по акту ничего не говорит о плавности: чтобы
     «сначала почти стоять, потом поехать», любая кривая обязана иметь
     большой размах, и у igloo он такой же. Рывок это другое - ОБРЫВ
     скорости между соседними кусками.

     Меряем скачок относительно локальной скорости. Плавная кривая на
     шаге тридцать пикселей даёт единицы процентов; обрыв даёт
     десятки. Первый заход этой проверки мерил размах и поэтому
     пропустил бы настоящую беду - линейный первый кусок в темпАкта,
     который обрывал скорость впятеро посередине финала. */
  /* ── И ТОЛЬКО ТАМ, ГДЕ КАМЕРА РЕАЛЬНО ЕДЕТ ────────────────────
     Относительный обрыв при почти стоящей камере ничего не значит: в
     хвосте финала скорость падает до 0.1 единицы на 1000 пикселей, и
     переход с 0.34 на 0.14 даёт «минус 59 процентов» при движении,
     которого человек не видит вовсе. Первый заход этой мерки краснел
     ровно на таком: станция 100 процентов при пути 0.3 на весь акт.

     Порог берём от самой ленты: одна единица мира на тысячу пикселей
     прокрутки это примерно три пикселя мира на щелчок колеса - ниже
     этого ход неразличим. Обрыв считаем только там, где хотя бы одна
     из двух соседних скоростей выше. */
  /* Порог проходят ОБА соседних куска, а не больший из них. Иначе в
     мерку попадают трогание с места и остановка: переход с нуля на
     ход всегда «сто процентов», и станция краснела на y=24, то есть
     на первых двух десятках пикселей ленты, где камера только встаёт
     в начальную позу. Трогание и остановка это не обрыв хода, их
     плавность держит сама ступенька темпа. */
  const ЕДЕТ = 0.001;   /* единиц мира на пиксель прокрутки */
  let обрыв = 0, обрывГде = null;
  for (let i = 1; i < скор.length; i++) {
    const б = Math.max(скор[i], скор[i - 1]);
    if (Math.min(скор[i], скор[i - 1]) < ЕДЕТ) continue;
    const о = Math.abs(скор[i] - скор[i - 1]) / б;
    if (о > обрыв) { обрыв = о; обрывГде = свои[i].y; }
  }
  свод.push({
    имя: а.имя, верх: Math.round(а.верх), ход: Math.round(а.ход),
    кусков: скор.length, путь: +путь.toFixed(2),
    средняя: +(путь / Math.max(1, а.ход)).toFixed(5),
    мин: +мин.toFixed(6), макс: +макс.toFixed(6),
    размах: мин > 1e-9 ? +(макс / мин).toFixed(1) : Infinity,
    обрыв: +(обрыв * 100).toFixed(0), обрывГде: обрывГде,
    профиль: скор.map((v) => +(v * 1000).toFixed(2))
  });
}

console.log(`СКОРОСТЬ ЛЕНТЫ ${КТО} ${экран.width}x${экран.height}`);
console.log("  акт            лента,px   путь мира   ед/1000px   размах   обрыв скорости");
for (const с of свод) {
  console.log(`  ${с.имя.padEnd(14)} ${String(с.ход).padEnd(10)} ${String(с.путь).padEnd(11)}` +
              ` ${(с.средняя * 1000).toFixed(1).padEnd(11)} ${(с.размах + "x").padEnd(8)}` +
              ` ${с.обрыв}%` + (с.обрывГде != null ? ` на y=${с.обрывГде}` : ""));
}

if (ПРОФИЛЬ) {
  for (const с of свод) {
    if (с.имя !== ПРОФИЛЬ) continue;
    console.log(`  профиль «${с.имя}» по двадцати кускам, единиц на 1000px:`);
    console.log("    " + с.профиль.join("  "));
  }
}

/* ── ВЕРДИКТ ────────────────────────────────────────────────────
   Мерим ОБРЫВ, а не размах. Размах по акту большой у любого движения,
   которое начинается с покоя, - он такой же и у igloo. Рывок это обрыв
   скорости между соседними кусками ленты.

   Порог сорок процентов. Плавная кривая на шаге тридцать пикселей даёт
   единицы процентов; линейный кусок, стыкованный со ступенькой, давал
   у финала девяносто шесть. Сорок - это запас на шум замера при почти
   стоящей камере, где доли единицы пути шумят направлением.

   Акты, где камера стоит по замыслу (станция и периметр: «камера стоит
   на месте, дом разбирается по кирпичикам»), из проверки не
   исключаются, но их обрыв считается только там, где есть ход: при
   пути меньше четверти единицы на весь акт мерить нечего. */
const беды = [];
for (const с of свод) {
  if (с.путь < 0.25) continue;
  if (с.обрыв > 40) {
    беды.push(`акт «${с.имя}»: обрыв скорости ${с.обрыв}% на y=${с.обрывГде}`);
  }
}
if (беды.length) {
  console.log("ГРЯЗНО  лента идёт с разной скоростью");
  for (const б of беды) console.log("   " + б);
  await бр.close();
  process.exit(1);
}
console.log("ЧИСТО  скорость ленты ровная");
await бр.close();
