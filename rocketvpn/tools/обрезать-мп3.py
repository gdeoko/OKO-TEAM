#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Обрезка MP3 по границам кадров, без перекодирования.

ЗАЧЕМ. Фоновую дорожку сайта надо играть с пятнадцатой секунды и
зациклить. Первый заход делал это перемоткой в браузере, и он оказался
негодным: файл едет потоком, и браузер разрешает перемотку только внутрь
уже скачанного куска. Замер поймал это точно - просили 15.5 секунды,
получили 2.3, потому что к тому мгновению приехало 2.3. На сервере без
поддержки запросов по диапазону перемотка вперёд невозможна вовсе, а
повторные попытки только дёргают дорожку назад в ноль.

Правильно решать это до браузера: отрезать вступление в самом файле.
Тогда в коде не остаётся ни перемотки, ни ожидания буфера - обычная
петля с нуля, которая работает везде и всегда.

ПОЧЕМУ БЕЗ ПЕРЕКОДИРОВАНИЯ. MP3 это поток независимых кадров, каждый со
своим заголовком и своей длительностью. Резать можно ровно по их
границам, и тогда звук остаётся бит в бит тем же: ни потери качества, ни
второго прохода кодировщиком. Заодно файл легчает на длину отрезанного.

ЧТО УЧТЕНО. Тег ID3v2 в начале пропускается по его собственной длине.
Первый кадр может нести таблицу Xing или Info (её кладут кодировщики с
переменным битрейтом); такой кадр отбрасывается вместе со вступлением,
потому что после обрезки таблица всё равно врёт.

    python3 tools/обрезать-мп3.py вход.mp3 выход.mp3 15.5
"""

import os
import sys

# Битрейты MPEG1 Layer III, кбит/с. Ноль означает запрещённое значение.
БИТРЕЙТ = [0, 32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320, 0]
ЧАСТОТА = [44100, 48000, 32000, 0]
# Битрейты MPEG2/2.5 Layer III: у них своя таблица.
БИТРЕЙТ2 = [0, 8, 16, 24, 32, 40, 48, 56, 64, 80, 96, 112, 128, 144, 160, 0]


def кадры(д, i):
    """Идёт по кадрам от смещения i. Отдаёт (начало, длина, секунды)."""
    n = len(д)
    while i < n - 4:
        if д[i] != 0xFF or (д[i + 1] & 0xE0) != 0xE0:
            i += 1
            continue
        верс = (д[i + 1] >> 3) & 0x03      # 3 = MPEG1, 2 = MPEG2, 0 = MPEG2.5
        слой = (д[i + 1] >> 1) & 0x03      # 1 = Layer III
        бит = (д[i + 2] >> 4) & 0x0F
        част = (д[i + 2] >> 2) & 0x03
        доп = (д[i + 2] >> 1) & 0x01
        if слой != 1 or бит == 0 or бит == 15 or част == 3 or верс == 1:
            i += 1
            continue
        сч = ЧАСТОТА[част]
        if верс == 2:
            сч //= 2
        elif верс == 0:
            сч //= 4
        бр = (БИТРЕЙТ[бит] if верс == 3 else БИТРЕЙТ2[бит]) * 1000
        if not бр or not сч:
            i += 1
            continue
        # Отсчётов в кадре: 1152 у MPEG1, 576 у MPEG2 и 2.5.
        отсч = 1152 if верс == 3 else 576
        длина = (отсч // 8) * бр // сч + доп
        if длина < 24 or i + длина > n:
            i += 1
            continue
        yield i, длина, отсч / сч
        i += длина


def главное(вход, выход, сколько):
    д = open(вход, "rb").read()
    i = 0
    if д[:3] == b"ID3":
        размер = ((д[6] & 0x7F) << 21 | (д[7] & 0x7F) << 14 |
                  (д[8] & 0x7F) << 7 | (д[9] & 0x7F))
        i = 10 + размер

    ушло = 0.0
    всего = 0.0
    начало = None
    штук = 0
    for нач, длина, сек in кадры(д, i):
        штук += 1
        всего += сек
        if начало is None:
            if ушло + сек > сколько:
                начало = нач
            else:
                ушло += сек

    if начало is None:
        print("обрезать нечего: дорожка короче отреза")
        return 1

    хвост = д[начало:]
    open(выход, "wb").write(хвост)
    print(f"кадров всего      {штук}")
    print(f"длина была        {всего:.1f} с ({int(всего // 60)}:{int(всего % 60):02d})")
    print(f"отрезано          {ушло:.2f} с")
    print(f"длина стала       {всего - ушло:.1f} с")
    print(f"вес   {len(д) / 1024 / 1024:.2f} МБ -> {len(хвост) / 1024 / 1024:.2f} МБ")
    return 0


if __name__ == "__main__":
    if len(sys.argv) < 4:
        print(__doc__)
        sys.exit(2)
    sys.exit(главное(sys.argv[1], sys.argv[2], float(sys.argv[3])))
