/* ОЧАГ ТРЕЩИН ДОЛЖЕН БЫТЬ ПОД ГЛЫБОЙ, И ЭТО СЧИТАЕТСЯ ЧИСЛОМ.

   Владелец на живом сайте: «трещины должны появляться в месте удара
   глыбы льда, сейчас не там появляется».

   Глазом такое спорно: звёзды разломов крупные, глыба тоже, и «рядом»
   легко принять за «в точке». Число отвечает точно. Здесь у каждой
   вставшей глыбы берутся ДВЕ вещи в одних и тех же координатах экрана:

     · где стоит сама плита глыбы (её центр, спроецированный в кадр);
     · где шейдер рисует очаг разлома (точка из uHits, переведённая
       тем же путём, каким её читает шейдер: плюс положение корня
       кладки, потом проекция).

   Печатается расстояние между ними в долях полуэкрана. Ноль означает,
   что uHits доехали до шейдера в тех координатах, в которых он их
   читает.

   Но одних uHits мало: они могут быть верными, а рисовать шейдер может
   всё равно не там. Поэтому дальше идёт замер по САМОМУ КАДРУ -
   разность двух снимков, с трещинами и с обнулёнными силами ударов.
   Разбор у него же, перед вызовом.

   Запуск: node tools/очаг-трещин.mjs [тел|пк] [доля-периметра] */
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";

const КТО = process.argv[2] || "тел";
const ДОЛЯ = +(process.argv[3] || 0.66);
const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const экран = КТО === "тел" ? { width: 390, height: 844 } : { width: 1440, height: 900 };

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader",
         "--force-device-scale-factor=1"]
});
const кон = await бр.newContext({
  viewport: экран, deviceScaleFactor: 1, isMobile: КТО === "тел", hasTouch: КТО === "тел"
});
const стр = await кон.newPage();
const беды = [];
стр.on("pageerror", (e) => беды.push(e.message.slice(0, 140)));
await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 120000 });
await стр.waitForFunction(() => window.RV_WORLD && window.RV_WORLD["мир"] && window.RV_WORLD["мир"](),
                          null, { timeout: 300000 });
await стр.waitForTimeout(4000);
await стр.evaluate((д) => window.RV_MOTION["кПунктy"]("периметр", д), ДОЛЯ);
await стр.evaluate(() => new Promise((г) => {
  let i = 0; (function ш() { requestAnimationFrame(() => (++i >= 20 ? г() : ш())); })();
}));

const из = await стр.evaluate(() => {
  const К = window.RV_КИРПИЧИ, С = window.RV_СНАРЯДЫ, T = window.THREE;
  if (!К || !С) return { нет: "модулей нет" };
  const корень = К["корень"] ? К["корень"]() : null;
  if (!корень) return { нет: "кладка не собрана" };
  const мир = window.RV_WORLD["мир"](), cam = мир.cam;
  cam.updateMatrixWorld(true);
  корень.updateWorldMatrix(true, true);
  /* Материал кладки несёт те самые числа, по которым рисует шейдер.
     Спрашиваем ЕГО, а не пересчитываем: между исходной целью снаряда и
     тем, что доехало до шейдера, и лежит вся разница, которую меряем. */
  let меш = null;
  корень.traverse((о) => { if (!меш && о.isInstancedMesh) меш = о; });
  if (!меш) return { нет: "экземпляров нет" };
  const у = (Array.isArray(меш.material) ? меш.material[0] : меш.material).uniforms;
  const из2 = { корень: [+корень.position.x.toFixed(2), +корень.position.y.toFixed(2),
                         +корень.position.z.toFixed(2)], пары: [] };
  /* Плиты глыб: у каждой своя, и стоят они в корне АКТА. Берём их
     мировое положение через матрицу, а не через position: родителей у
     них несколько. */
  const плиты = [];
  let сцена = cam; while (сцена.parent) сцена = сцена.parent;
  сцена.traverse((о) => {
    if (о.isMesh && о.material && о.material.uniforms &&
        о.material.uniforms.uFly !== undefined && о.visible) плиты.push(о);
  });
  const п = new T.Vector3();
  for (let h = 0; h < 5; h++) {
    const сила = у.uHitPow.value[h];
    if (!(сила > 0.001)) continue;
    /* Точка удара так, как её понимает шейдер: она лежит в координатах
       кладки, значит в мир переводится матрицей корня кладки. */
    п.copy(у.uHits.value[h]).applyMatrix4(корень.matrixWorld);
    const очагМир = п.clone();
    п.project(cam);
    const очаг = [+п.x.toFixed(3), +п.y.toFixed(3)];
    /* Ближайшая к очагу плита: их три, и какая чья, решаем по
       расстоянию, а не по номеру - порядок у модулей свой. */
    let лучшая = null, лучшееD = 1e9, размер = 0;
    for (const пл of плиты) {
      пл.updateWorldMatrix(true, false);
      const ц = new T.Vector3().setFromMatrixPosition(пл.matrixWorld);
      const d = ц.distanceTo(очагМир);
      if (d < лучшееD) {
        лучшееD = d; лучшая = ц;
        const g = пл.geometry;
        g.computeBoundingSphere();
        размер = g.boundingSphere ? g.boundingSphere.radius *
                 Math.max(пл.scale.x, пл.scale.y) : 1;
      }
    }
    if (!лучшая) continue;
    const цП = лучшая.clone().project(cam);
    const глыба = [+цП.x.toFixed(3), +цП.y.toFixed(3)];
    из2.пары.push({
      удар: h, сила: +сила.toFixed(2), очаг, глыба,
      мимо: +Math.hypot(очаг[0] - глыба[0], очаг[1] - глыба[1]).toFixed(3),
      вМире: +лучшееD.toFixed(2), размерГлыбы: +размер.toFixed(2),
    });
  }
  return из2;
});

console.log(`ОЧАГ ТРЕЩИН ${КТО} ${экран.width}x${экран.height}, периметр ${ДОЛЯ}`);
if (из.нет) { console.log("  " + из.нет); await бр.close(); process.exit(1); }
console.log(`  корень кладки ${JSON.stringify(из.корень)}`);
if (!из.пары.length) console.log("  ни одного удара с силой выше нуля");
for (const п of из.пары) {
  console.log(`  удар ${п.удар} сила ${п.сила}: очаг ${JSON.stringify(п.очаг)}` +
              ` глыба ${JSON.stringify(п.глыба)}  мимо ${п.мимо} полуэкрана` +
              `  (в мире ${п.вМире} при размере глыбы ${п.размерГлыбы})`);
}

/* ── ТРЕЩИНЫ ВЫДЕЛЯЕМ РАЗНОСТЬЮ ДВУХ КАДРОВ ───────────────────
   Первый заход этой проверки был пустым: он брал точку из uHits,
   переводил её в мир матрицей корня кладки и сравнивал с плитой,
   которая в ту же точку и поставлена. Ноль выходил у всех трёх ударов
   всегда, при любой ошибке в шейдере - мерилось одно число против
   самого себя.

   Второй заход искал «светлые точки вокруг глыбы» и врал в другую
   сторону: в квадрат вокруг глыбы попадает сама глыба, а у льда яркая
   кромка. Она и перетягивала центр тяжести - замер писал «центр
   свечения ушёл на 0.83», хотя на снимке звёзды разломов расходятся
   ровно из-под камня. У нижней плиты порог `фон * 1.35 + 12` не брал
   ничего вовсе, и выходило «свечения трещин почти нет».

   Разность двух кадров снимает оба confound'а разом. Снимаем кадр как
   есть, потом обнуляем силы ударов (uHitPow) и снимаем ещё раз. Всё,
   что поменялось между кадрами, и ЕСТЬ трещины: ни камень, ни лёд, ни
   кромка, ни небо за это время не двигались. Дальше вопрос простой -
   лежит ли эта разность у точек удара.

   Меру берём честную: доля всей разности, попавшая в круг радиусом
   `predel` вокруг какой-нибудь точки удара. Радиус берём тот же, по
   которому шейдер и рисует (uStena * (0.30 * sila + 0.06)), и
   переводим его в точки экрана проекцией. Единица значит, что ВСЯ
   трещина лежит у ударов и нигде больше. */
const свеч = await стр.evaluate((пары) => new Promise((готово) => {
  const К = window.RV_КИРПИЧИ, T = window.THREE;
  const мир = window.RV_WORLD["мир"](), cam = мир.cam;
  const корень = К["корень"]();
  let меш = null;
  корень.traverse((о) => { if (!меш && о.isInstancedMesh) меш = о; });
  const у = (Array.isArray(меш.material) ? меш.material[0] : меш.material).uniforms;
  const W = innerWidth, H = innerHeight;
  const c = document.createElement("canvas");
  c.width = W; c.height = H;
  const x = c.getContext("2d", { willReadFrequently: true });
  const холсты = [].slice.call(document.querySelectorAll("canvas")).filter((cv) => {
    const к = cv.getBoundingClientRect();
    return к.width > W * 0.8 && к.height > H * 0.8;
  });
  /* Снимок ОБЯЗАН делаться в том же кадре, где мир рисовал: без
     preserveDrawingBuffer буфер WebGL к следующему кадру уже пуст. */
  function снять(готов) {
    requestAnimationFrame(() => {
      x.clearRect(0, 0, W, H);
      for (const cv of холсты) { try { x.drawImage(cv, 0, 0, W, H); } catch (e) {} }
      готов(x.getImageData(0, 0, W, H).data);
    });
  }
  const силы = [];
  for (let i = 0; i < 5; i++) силы.push(у.uHitPow.value[i]);
  снять((сТрещинами) => {
    for (let i = 0; i < 5; i++) у.uHitPow.value[i] = 0;
    /* Один кадр на то, чтобы обнуление доехало до экрана, и только
       потом снимаем. */
    requestAnimationFrame(() => снять((безТрещин) => {
      for (let i = 0; i < 5; i++) у.uHitPow.value[i] = силы[i];
      /* Точки удара и их радиусы в точках экрана. */
      const стена = у.uStena ? у.uStena.value : 30;
      const круги = [];
      const т = new T.Vector3(), т2 = new T.Vector3();
      for (let h = 0; h < 5; h++) {
        const сила = силы[h];
        if (!(сила > 0.001)) continue;
        т.copy(у.uHits.value[h]).applyMatrix4(корень.matrixWorld);
        т2.copy(у.uHits.value[h]);
        т2.x += стена * (0.30 * сила + 0.06);
        т2.applyMatrix4(корень.matrixWorld);
        т.project(cam); т2.project(cam);
        const цx = (т.x * 0.5 + 0.5) * W, цy = (-т.y * 0.5 + 0.5) * H;
        const кx = (т2.x * 0.5 + 0.5) * W, кy = (-т2.y * 0.5 + 0.5) * H;
        круги.push({ удар: h, x: цx, y: цy, r: Math.hypot(кx - цx, кy - цy) });
      }
      /* Разность по яркости. Порог в четыре единицы отсекает шум
         сглаживания: одна и та же кромка кирпича между двумя кадрами
         гуляет на единицу-две. */
      let всего = 0;
      const своё = {};
      for (const к of круги) своё[к.удар] = 0;
      let вне = 0, внеX = 0, внеY = 0;
      for (let py = 0; py < H; py += 2) {
        for (let px = 0; px < W; px += 2) {
          const i = (py * W + px) * 4;
          const л1 = сТрещинами[i] * 0.2126 + сТрещинами[i + 1] * 0.7152 + сТрещинами[i + 2] * 0.0722;
          const л2 = безТрещин[i] * 0.2126 + безТрещин[i + 1] * 0.7152 + безТрещин[i + 2] * 0.0722;
          const d = Math.abs(л1 - л2);
          if (d < 4) continue;
          всего += d;
          let чей = -1, ближе = 1e9;
          for (const к of круги) {
            const р = Math.hypot(px - к.x, py - к.y);
            if (р <= к.r && р < ближе) { ближе = р; чей = к.удар; }
          }
          if (чей >= 0) своё[чей] += d;
          else { вне += d; внеX += px * d; внеY += py * d; }
        }
      }
      готово({
        всего: +всего.toFixed(0),
        круги: круги.map((к) => ({ удар: к.удар,
          экран: [Math.round(к.x), Math.round(к.y)], радиус: Math.round(к.r),
          доля: всего > 0 ? +(своё[к.удар] / всего).toFixed(3) : 0 })),
        вне: всего > 0 ? +(вне / всего).toFixed(3) : 0,
        центрВне: вне > 0 ? [Math.round(внеX / вне), Math.round(внеY / вне)] : null,
      });
    }));
  });
}), из.пары);

console.log(`  разность двух кадров: всего света трещин ${свеч.всего}`);
for (const к of свеч.круги) {
  console.log(`  удар ${к.удар}: экран ${JSON.stringify(к.экран)} радиус ${к.радиус} точек,` +
              ` в нём ${Math.round(к.доля * 100)}% всего света трещин`);
}
console.log(`  вне всех кругов ${Math.round(свеч.вне * 100)}%` +
            (свеч.центрВне ? `, центр остатка ${JSON.stringify(свеч.центрВне)}` : ""));

/* ── ВЕРДИКТ ──────────────────────────────────────────────────
   Три требования, и каждое отвечает на свой вопрос владельца.

   1. Трещины вообще есть. Пустая разность значит, что удар не рисует
      ничего, и «не там появляется» превратилось бы в «не появляется».
   2. У КАЖДОГО удара своя трещина. Доля ниже десятой части значит, что
      этот камень стоит в стене без разлома.
   3. Вне кругов почти ничего. Это и есть «появляется не там»: свет
      разлома, лежащий дальше своего радиуса от любой точки удара.
      Четверть это запас на мягкий край шейдера (dalnost гаснет
      smoothstep'ом ровно к predel, и часть его хвоста выходит за
      радиус) и на дрожь сглаживания. */
const беды2 = [];
if (!из.пары.length) беды2.push("ударов в кадре нет, мерить нечего");
if (свеч.всего < 400) {
  беды2.push(`трещин в кадре нет вовсе: разность двух кадров дала ${свеч.всего}`);
} else {
  for (const к of свеч.круги) {
    if (к.доля < 0.10) {
      беды2.push(`удар ${к.удар}: у своей глыбы всего ${Math.round(к.доля * 100)}% света трещин`);
    }
  }
  if (свеч.вне > 0.25) {
    беды2.push(`${Math.round(свеч.вне * 100)}% света трещин лежит вне радиуса ударов` +
               (свеч.центрВне ? ` (центр остатка ${JSON.stringify(свеч.центрВне)})` : ""));
  }
}
if (беды.length) беды2.push("исключения: " + беды.slice(0, 2).join(" | "));
if (беды2.length) {
  console.log("ГРЯЗНО  очаг трещин");
  for (const б of беды2) console.log("   " + б);
  await бр.close();
  process.exit(1);
}
console.log("ЧИСТО  трещины расходятся из-под глыб");
await бр.close();
