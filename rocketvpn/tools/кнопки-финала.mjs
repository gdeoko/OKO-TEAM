/* КНОПКИ ПОСЛЕДНЕГО ЭКРАНА: КУДА ВЕДУТ И ЧТО ДЕЛАЮТ.

   Владелец: «всё, что я по кнопкам просил, так и не сделано, ссылки
   неверные, тексты тоже; концовка - игру кнопка не запускает».

   Проверка отвечает на оба вопроса РАЗДЕЛЬНО, потому что это разные
   беды с разным лечением:

     1. НАДПИСИ И АДРЕСА. Читаем их из живой страницы и сверяем со
        списком, который владелец назвал дословно. Список тут, а не в
        голове: «поправил текст» и «поправил тот текст, который просили»
        это разные вещи, и отличить их можно только сверкой.

     2. КНОПКА ИГРЫ РЕАЛЬНО ОТКРЫВАЕТ ИГРУ. Мало найти обработчик в
        файле: он открывает гнездо ТОЛЬКО когда мир поднялся и не спит
        (`RV_WORLD.готов`, `RV_WORLD.тихо`), иначе молча пропускает
        нажатие, и браузер уходит по запасному адресу на соседний сайт.
        Снаружи это выглядит ровно как «кнопка не запускает игру».
        Поэтому жмём её по-настоящему и смотрим, открылось ли гнездо
        ЗДЕСЬ, а не ушли ли мы куда-то.

   Запуск: node tools/кнопки-финала.mjs [тел|пк]
*/
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";

const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const КТО = process.argv[2] || "тел";
const экран = КТО === "пк"
  ? { w: 1440, h: 900, dpr: 1, mob: false }
  : { w: 390, h: 844, dpr: 1, mob: true };

/* Дословно со слов владельца. Правка списка это правка договорённости,
   и делать её надо здесь, а не в разметке втихую. */
const ЖДЁМ = [
  { где: "герой", текст: "Тест-драйв 24 часа", адрес: "https://rocketweb.top" },
  { где: "герой", текст: "Открыть в Telegram", адрес: "https://t.me/RocketCompanyVPN_bot" },
  { где: "ракета", текст: "Следите за обновлениями", адрес: "https://t.me/rocketvpnnews" },
  { где: "вопросы", текст: "Запустить VPN", адрес: "https://rocketweb.top" },
  { где: "вопросы", текст: "Погрузиться", адрес: null }   /* адрес запасной, дело в игре */
];

/* Слова, которых на сайте больше быть не должно. «Три дня» сняты
   руководством, форма обратной связи с VPN убрана. */
const ЗАПРЕЩЕНО = ["три дня", "3 дня", "Оставить заявку", "Запустить игру"];

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"]
});
const стр = await бр.newPage({
  viewport: { width: экран.w, height: экран.h },
  deviceScaleFactor: экран.dpr, isMobile: экран.mob, hasTouch: экран.mob
});
const беды = [];
стр.on("pageerror", (e) => беды.push("ИСКЛ " + e.message.slice(0, 160)));

await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 90000 });
await стр.waitForFunction(
  () => window.RV_WORLD && window.RV_WORLD["вступлениеИдёт"] && !window.RV_WORLD["вступлениеИдёт"](),
  null, { timeout: 240000 }).catch(() => беды.push("вступление не кончилось"));
await стр.waitForTimeout(2000);

console.log(`\n${КТО} ${экран.w}x${экран.h}`);

/* ── 1. Надписи и адреса ─────────────────────────────────────── */
const кнопки = await стр.$$eval("a.rv-кн, a.кн, .rv-дело a, .рв-фин a, .rv-внутрь-кнопки a", (уз) =>
  уз.map((у) => ({ текст: (у.textContent || "").trim(), адрес: у.getAttribute("href") || "",
                   игра: у.hasAttribute("data-к-игре") })));
for (const ж of ЖДЁМ) {
  const н = кнопки.find((к) => к.текст === ж.текст);
  if (!н) { беды.push(`нет кнопки «${ж.текст}» (${ж.где})`); continue; }
  console.log(`  ${ж.текст.padEnd(24)} -> ${н.адрес}`);
  if (ж.адрес && н.адрес !== ж.адрес) {
    беды.push(`«${ж.текст}»: адрес ${н.адрес}, а просили ${ж.адрес}`);
  }
}

const весьТекст = await стр.evaluate(() => document.body.innerText);
for (const с of ЗАПРЕЩЕНО) {
  if (весьТекст.toLowerCase().indexOf(с.toLowerCase()) >= 0) беды.push(`на странице осталось «${с}»`);
}

/* ── 2. Кнопка игры открывает игру ЗДЕСЬ ─────────────────────── */
await стр.evaluate(() => window.RV_MOTION["кПунктy"]("финал", 0.99));
await стр.waitForTimeout(3500);
const доНажатия = await стр.evaluate(() => window.RV_ПАНЕЛЬ_КНОПКИ["замер"]());
console.log(`  до нажатия: гнездо ${доНажатия["гнездоЕсть"]}, игра открыта ${доНажатия["играОткрыта"]}, ` +
            `клавиш игры ${доНажатия["клавишИгры"]}`);

/* ── ЖМЁМ ТУ КЛАВИШУ, КОТОРУЮ ВИДИТ ЧЕЛОВЕК ──────────────────────
   Первый заход этой проверки жал `[data-к-игре]` из разметки и писал
   зелёное, пока владелец смотрел на неработающую кнопку. Разгадка в
   том, что пульт финала собирает СВОИ клавиши кодом (rc-desk.js,
   признак `data-go`), а разметочные прячет. То есть проверялась
   кнопка, до которой палец не доходит.

   Поэтому ищем клавишу на самом пульте и только если её там нет -
   берём разметочную. И надпись читаем с неё же: подпись пульта берётся
   из словаря, а не из разметки, и правка разметки её не меняет. */
const ушли = [];
стр.on("framenavigated", (ф) => { if (ф === стр.mainFrame()) ушли.push(ф.url()); });
const подписьИгры = await стр.evaluate(() => {
  const п = document.querySelector('.rc-desk [data-go="lead"]');
  return п ? (п.textContent || "").trim() : null;
});
console.log(`  клавиша игры на пульте: ${подписьИгры === null ? "нет, только разметочная" : "«" + подписьИгры + "»"}`);
if (подписьИгры !== null && подписьИгры !== "Погрузиться") {
  беды.push(`клавиша игры подписана «${подписьИгры}», а просили «Погрузиться»`);
}
/* Клавиша «Запустить VPN» на пульте уводит не ссылкой, а окном, и
   адрес у неё свой, в коде. Проверить его чтением разметки нельзя:
   разметочная кнопка рядом ведёт куда надо, а нажимают эту. Подменяем
   открыватель окон и смотрим, что ему передали. */
const кудаVPN = await стр.evaluate(() => {
  const к = document.querySelector('.rc-desk [data-go="call"]');
  if (!к) return null;
  let адрес = "";
  const было = window.open;
  window.open = function (u) { адрес = u || ""; return null; };
  к.click();
  window.open = было;
  return { подпись: (к.textContent || "").trim(), адрес: адрес };
});
if (кудаVPN) {
  console.log(`  клавиша «${кудаVPN.подпись}» на пульте ведёт -> ${кудаVPN.адрес || "никуда"}`);
  if (кудаVPN.подпись !== "Запустить VPN") {
    беды.push(`первая клавиша пульта подписана «${кудаVPN.подпись}», а просили «Запустить VPN»`);
  }
  if (кудаVPN.адрес !== "https://rocketweb.top") {
    беды.push(`«Запустить VPN» на пульте ведёт на ${кудаVPN.адрес || "никуда"}, а просили https://rocketweb.top`);
  }
} else {
  console.log("  клавиши «Запустить VPN» на пульте нет");
}

await стр.evaluate(() => {
  const к = document.querySelector('.rc-desk [data-go="lead"]') || document.querySelector("[data-к-игре]");
  if (!к) throw new Error("нет клавиши игры");
  к.click();
}).catch((e) => беды.push("нажатие не прошло: " + e.message));
await стр.waitForTimeout(2500);

/* ── СМОТРИМ НА КАДР, А НЕ НА ПРИЗНАК ────────────────────────────
   Прошлый заход спрашивал у модуля его собственный флаг «игра открыта»
   и писал зелёное, пока владелец смотрел на пустой экран. Флаг честный:
   гнездо действительно перестало быть `hidden`. Только сам пульт живёт
   в другом слое, и разметочную ячейку он прячет целиком - гнездо
   открывается ВНУТРИ спрятанного родителя и остаётся невидимым.

   Поэтому меряем то же, что видит глаз: есть ли у гнезда размер на
   экране и не спрятан ли кто-то из его родителей. */
const после = await стр.evaluate(() => {
  const м = window.RV_ПАНЕЛЬ_КНОПКИ ? window.RV_ПАНЕЛЬ_КНОПКИ["замер"]() : null;
  const гн = document.getElementById("rvИграГнездо");
  let видно = false, ширина = 0, высота = 0, ктоПрячет = "";
  if (гн) {
    const к = гн.getBoundingClientRect();
    ширина = Math.round(к.width); высота = Math.round(к.height);
    видно = ширина > 40 && высота > 40 && !!гн.offsetParent;
    for (let у = гн; у && у !== document.documentElement; у = у.parentElement) {
      const с = getComputedStyle(у);
      if (у.hidden || с.display === "none" || с.visibility === "hidden") {
        ктоПрячет = (у.id || у.className || у.tagName) + "";
        break;
      }
    }
  }
  const холст = document.getElementById("rvИграХолст") || гн && гн.querySelector("canvas");
  return { флаг: м, видно: видно, ширина: ширина, высота: высота, ктоПрячет: ктоПрячет,
           холстЕсть: !!холст };
}).catch(() => null);

if (!после) {
  беды.push("после нажатия страница ушла на другой адрес: " + (ушли.pop() || "неизвестно"));
} else {
  const ф = после.флаг || {};
  console.log(`  после нажатия: флаг «игра открыта» ${ф["играОткрыта"]}, вопросы видны ${ф["вопросыВидны"]}`);
  console.log(`  гнездо игры в кадре: ${после.видно} (${после.ширина}x${после.высота})` +
              (после.ктоПрячет ? `, прячет «${после.ктоПрячет}»` : ""));
  if (!ф["играОткрыта"]) беды.push("клавиша не открыла игру: гнездо осталось закрытым");
  if (ф["вопросыВидны"]) беды.push("вопросы не ушли: список лежит поверх игры");
  if (!после.видно) {
    беды.push("игра открыта по признаку, но её НЕ ВИДНО в кадре" +
              (после.ктоПрячет ? ": прячет «" + после.ктоПрячет + "»" : ""));
  }
}

if (беды.length) {
  console.log("\nКРАСНОЕ:");
  for (const с of [...new Set(беды)]) console.log("   " + с);
} else {
  console.log("\nзелено: надписи, адреса и запуск игры на месте");
}
await бр.close();
process.exit(беды.length ? 1 : 0);
