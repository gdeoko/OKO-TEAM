#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Переукладка MSDF-атласа в РОВНУЮ СЕТКУ.

ЗАЧЕМ. Приём появления текста у igloo держится на одной строке шейдера:

    vUv.x = mod(uv.x + 0.125 * mod(floor((1.0 - tr2) * 5.753), 8.0), 1.0);

Здесь 0.125 это 1/8, ширина одного столбца их атласа. Буква на глазах
перебирает пять-шесть ЧУЖИХ глифов, сдвигаясь по столбцам, и садится на
свой. Весь фокус в том, что сдвиг на ровно один столбец обязан попадать
ровно в соседний глиф.

Генератор атласа этого не даёт: он пакует глифы плотно, каждый своего
размера, и сдвиг на восьмую часть ширины попадёт в середину чужой буквы.
Поэтому атлас перекладывается сюда, в сетку с одинаковой ячейкой.

ПОЧЕМУ ЭТО ВООБЩЕ ВОЗМОЖНО. Шрифт моноширинный (xadvance у всех двухсот
глифов равен 25), значит одинаковая ячейка не врёт метрике: буква и так
занимает в строке одну и ту же ширину.

ЧТО СЧИТАЕТСЯ. Ячейка выводится из настоящих габаритов глифов, а не
назначается числом: берётся крайний левый xoffset, крайний правый
xoffset+width, верх и низ по yoffset. Глиф кладётся в ячейку на своё
место относительно пера, поэтому подмена UV на чужую ячейку рисует чужую
букву ровно там, где стояла бы своя.

СТОРОНА ЛИСТА ОКРУГЛЯЕТСЯ ДО ЧЕТЫРЁХ, А НЕ ДО СТЕПЕНИ ДВОЙКИ. Степень
двойки нужна мипмапам и повторению текстуры, а у MSDF нет ни того, ни
другого: карта берётся один раз, без мипмапов (они смазали бы поле
расстояний и съели резкость букв) и с зажатием по краям.

Цена ошибки видна числом: сетка занимает 551 на 583 точки, а округление
до степени двойки раздувало лист до 1024 на 1024. Это три четверти
видеопамяти под пустоту, три мегабайта против одного.

    python3 tools/сетка-атласа.py вход.json вход.png выход.json выход.png
"""

import io
import json
import math
import sys

from PIL import Image


def кратно(n, к=4):
    return ((n + к - 1) // к) * к


def главное(вхJson, вхPng, выхJson, выхPng):
    d = json.load(io.open(вхJson, encoding="utf-8"))
    глифы = d["chars"]
    ист = Image.open(вхPng).convert("RGB")

    видимые = [г for г in глифы if г["width"] > 0 and г["height"] > 0]
    лево = min(г["xoffset"] for г in видимые)
    право = max(г["xoffset"] + г["width"] for г in видимые)
    верх = min(г["yoffset"] for г in видимые)
    низ = max(г["yoffset"] + г["height"] for г in видимые)

    # ЗАЗОР ВОКРУГ ЯЧЕЙКИ. Глиф, прижатый к краю ячейки, при линейной
    # фильтрации подмешивает в себя соседа: видеокарта берёт четыре
    # точки вокруг координаты и через край ячейки хватает чужое поле
    # расстояний. Две точки поля с каждой стороны это дешевле любого
    # лечения в шейдере и не мешает приёму igloo - сдвиг на один
    # столбец по-прежнему попадает ровно в соседнюю ячейку.
    ЗАЗОР = 2
    кШ = право - лево + ЗАЗОР * 2
    кВ = низ - верх + ЗАЗОР * 2
    N = len(глифы)
    # столбцов подбираем так, чтобы лист вышел ближе к квадрату
    стлб = max(1, int(round(math.sqrt(N * кВ / float(кШ)))))
    рядов = int(math.ceil(N / float(стлб)))

    Ш = кратно(стлб * кШ)
    В = кратно(рядов * кВ)
    лист = Image.new("RGB", (Ш, В), (0, 0, 0))

    новые = []
    for i, г in enumerate(глифы):
        ряд, стб = divmod(i, стлб)
        цX = стб * кШ
        цY = ряд * кВ
        if г["width"] > 0 and г["height"] > 0:
            кусок = ист.crop((г["x"], г["y"], г["x"] + г["width"], г["y"] + г["height"]))
            лист.paste(кусок, (цX + ЗАЗОР + (г["xoffset"] - лево), цY + ЗАЗОР + (г["yoffset"] - верх)))
        нов = dict(г)
        # Ячейка целиком: квад буквы теперь один на все буквы, а разница
        # между ними живёт внутри текстуры. Ровно так же устроен igloo.
        нов["x"] = цX
        нов["y"] = цY
        нов["width"] = кШ
        нов["height"] = кВ
        нов["xoffset"] = лево - ЗАЗОР
        нов["yoffset"] = верх - ЗАЗОР
        нов["ячейка"] = [стб, ряд]
        новые.append(нов)

    d["chars"] = новые
    d["common"]["scaleW"] = Ш
    d["common"]["scaleH"] = В
    # Сетка нужна шейдеру: он сдвигает координату на 1/столбцов и обязан
    # знать это число. Кладём его в файл, чтобы не задавать дважды.
    d["сетка"] = {"столбцов": стлб, "рядов": рядов, "ячейкаШ": кШ, "ячейкаВ": кВ,
                  "листШ": Ш, "листВ": В}
    лист.save(выхPng)
    io.open(выхJson, "w", encoding="utf-8").write(
        json.dumps(d, ensure_ascii=False, separators=(",", ":")))

    print("глифов          %d" % N)
    print("сетка           %d x %d" % (стлб, рядов))
    print("ячейка          %d x %d точек" % (кШ, кВ))
    print("лист            %d x %d" % (Ш, В))
    print("сдвиг столбца   %.6f" % (1.0 / стлб))
    return 0


if __name__ == "__main__":
    if len(sys.argv) < 5:
        print(__doc__)
        sys.exit(2)
    sys.exit(главное(*sys.argv[1:5]))
