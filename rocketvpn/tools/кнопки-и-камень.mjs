/* КНОПКИ ПЕРВОГО ЭКРАНА И ЦВЕТ КАМНЯ ПО ХОДУ СЦЕНЫ.

   Две правки владельца за один проход, обе по акту станции.

   1. «Снизу есть 2 кнопки. Когда я листаю, внизу они уходят вверх,
      улетают. Сделай так, чтобы они появлялись снизу, выезжали, и когда
      я листаю вниз, чтобы они туда же уходили, когда дом в стену
      превращается. И это должно произойти ДО того, как стена соберётся,
      чтобы кнопки на стене не были».

      Меряем ПОЛОЖЕНИЕ кнопок и их видимость по долям. Правильно это
      выглядит так: на нуле кнопки на месте, дальше уходят ВНИЗ (верх
      растёт, а не уменьшается), и к доле сборки стены их уже нет.
      Уехать вверх значит провалить правку тем же способом, что и
      раньше, поэтому направление проверяется знаком.

   2. «Стена из светящегося кирпича вначале, из материала дома, а потом
      становится другого цвета. Убери подмену материала».

      Это проверяется по ШЕЙДЕРУ, а не по снимку, и почему именно так -
      разобрано ниже, у самой проверки. Коротко: три попытки судить
      материал по картинке дали три ложных вердикта, а снятая подмена
      была почти нейтральной по каналам, то есть тон её не поймал бы.
      Числа со снимков печатаются для глаза и вердикта не выносят.

   Запуск: node tools/кнопки-и-камень.mjs [тел|пк]
*/
import { chromium } from "playwright";
import { БРАУЗЕР } from "./браузер.mjs";
import { mkdirSync, readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const АДРЕС = process.env.RV_URL || "http://127.0.0.1:8170";
const КТО = process.argv[2] || "тел";
const КУДА = "/tmp/кнопки-камень";
const экран = КТО === "пк"
  ? { w: 1440, h: 900, dpr: 1, mob: false }
  : { w: 390, h: 844, dpr: 1, mob: true };

/* Дом складывается в стену с 0.22 по 0.92. Кнопок не должно быть уже на
   0.30: это «до того, как стена соберётся» с большим запасом. */
const ДОЛИ = [0.02, 0.10, 0.18, 0.30, 0.55, 0.85];
const СТЕНА_С = 0.30;

mkdirSync(КУДА, { recursive: true });

const бр = await chromium.launch({
  executablePath: БРАУЗЕР,
  args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"]
});
const стр = await бр.newPage({
  viewport: { width: экран.w, height: экран.h },
  deviceScaleFactor: экран.dpr, isMobile: экран.mob, hasTouch: экран.mob
});
const беды = [];
стр.on("pageerror", (e) => беды.push("ИСКЛ " + e.message.slice(0, 200)));

await стр.goto(АДРЕС + "/", { waitUntil: "domcontentloaded", timeout: 90000 });
await стр.waitForFunction(
  () => window.RV_WORLD && window.RV_WORLD["вступлениеИдёт"] && !window.RV_WORLD["вступлениеИдёт"](),
  null, { timeout: 240000 }).catch(() => console.log("вступления не дождались"));
await стр.waitForTimeout(2000);

/* ── МЕРИМ ТОН КАМНЯ, А НЕ ЕГО ЯРКОСТЬ ─────────────────────────
   Мерка переписана дважды, и оба раза потому, что мерила не то.

   Сначала тут стояло среднее по полосе. Прогон выдал разброс 60.7 и
   вердикт «подмена материала». Ложь: на долях 0.30 и 0.55 блоки летят
   вразнобой, и половину полосы занимает чёрное небо между ними, а на
   0.85 стена стоит сплошняком. Мерилось, СКОЛЬКО камня в кадре.

   Потом стоял верхний процентиль яркости. Он честно принадлежит камню,
   и всё равно дал разброс 48: дом на 0.02 стоит дальше и боком, а
   собранная стена на 0.85 вплотную и фронтально к свету. Мерилось,
   КАК ОСВЕЩЁН камень.

   Владелец сказал про третье: «становится другого ЦВЕТА». Цвет от угла
   и расстояния не зависит, от подмены материала зависит прямо. Поэтому
   берём самые светлые точки полосы (это заведомо камень) и считаем у
   них ДОЛИ КАНАЛОВ в общей сумме. Уехал блок в тень, подъехала камера,
   сменилась фаза сборки - доли не двинутся; сменился материал - двинутся
   сразу. Яркость остаётся в распечатке для глаза, вердикт по ней не
   выносится. */
function уровень(файл) {
  const из = execFileSync("python3", ["-c", `
import sys
from PIL import Image
im = Image.open(sys.argv[1]).convert("RGB")
w, h = im.size
k = im.crop((int(w*0.34), int(h*0.42), int(w*0.66), int(h*0.66)))
то = list(k.getdata())
я = sorted(sum(p) for p in то)
порог = я[len(я)*80//100]
камень = [p for p in то if sum(p) >= порог]
if not камень: камень = то
R = sum(p[0] for p in камень) / len(камень)
G = sum(p[1] for p in камень) / len(камень)
B = sum(p[2] for p in камень) / len(камень)
с = max(1.0, R + G + B)
print(round((R+G+B)/3, 1), round(R/с, 4), round(G/с, 4), round(B/с, 4))
`, файл], { encoding: "utf8" });
  const [я, r, g, b] = из.trim().split(/\s+/).map(Number);
  return { яркость: я, r: r, g: g, b: b };
}

const ряд = [];
for (const доля of ДОЛИ) {
  await стр.evaluate((д) => window.RV_MOTION["кПунктy"]("станция", д), доля);
  let было = null, тихих = 0, кругов = 0;
  while (тихих < 3 && кругов < 60) {
    const п = await стр.evaluate(() => {
      const c = window.RV_WORLD["мир"]().cam.position;
      return [c.x, c.y, c.z];
    });
    if (было) {
      const d = Math.hypot(п[0] - было[0], п[1] - было[1], п[2] - было[2]);
      тихих = d < 0.02 ? тихих + 1 : 0;
    }
    было = п; кругов++;
    await стр.waitForTimeout(250);
  }
  await стр.waitForTimeout(1200);

  const кн = await стр.evaluate(() => {
    const p = document.querySelector('.rv-акт[data-акт="станция"] .rv-кнопки');
    if (!p) return null;
    const r = p.getBoundingClientRect();
    const ст = getComputedStyle(p);
    const роди = p.closest(".rv-слой");
    const рст = роди ? +getComputedStyle(роди).opacity : 1;
    return {
      верх: Math.round(r.top), низ: Math.round(r.bottom),
      видно: +(+ст.opacity * рст).toFixed(3)
    };
  });

  const файл = `${КУДА}/${КТО}-станция-${доля.toFixed(2)}.png`;
  await стр.screenshot({ path: файл });
  const ур = уровень(файл);
  ряд.push({ доля, кн, ур });
  console.log(`  доля ${доля.toFixed(2)}  кнопки верх ${кн ? кн.верх : "?"} ` +
              `видно ${кн ? кн.видно : "?"}   камень ${ур.яркость}, ` +
              `тон ${ур.r}/${ур.g}/${ур.b}`);
}

const итог = [];

/* ── КНОПКИ УХОДЯТ ВНИЗ, А НЕ ВВЕРХ ─────────────────────────────
   Сравниваем верхнюю кромку, пока кнопки ещё видны. Растёт - уходят
   вниз, это правка; падает - уходят вверх, это прежняя беда. */
const видимые = ряд.filter((з) => з.кн && з.кн.видно > 0.05);
if (видимые.length >= 2) {
  const первый = видимые[0], последний = видимые[видимые.length - 1];
  const сдвиг = последний.кн.верх - первый.кн.верх;
  console.log(`\n  кнопки, пока видны: верх ${первый.кн.верх} -> ${последний.кн.верх} (${сдвиг > 0 ? "+" : ""}${сдвиг})`);
  if (сдвиг < -8) итог.push(`кнопки уходят ВВЕРХ на ${-сдвиг} точек, а должны вниз`);
}

const поздние = ряд.filter((з) => з.доля >= СТЕНА_С && з.кн && з.кн.видно > 0.05);
if (поздние.length) {
  итог.push("кнопки видны на долях " +
            поздние.map((з) => з.доля.toFixed(2) + " (" + з.кн.видно + ")").join(", ") +
            " - они окажутся на собранной стене");
}

/* ── ОДИН КАМЕНЬ ПРОВЕРЯЕТСЯ ПО ШЕЙДЕРУ, А НЕ ПО КАРТИНКЕ ───────
   Три попытки судить материал по снимку, три ложных вердикта, и каждый
   следующий тоньше предыдущего:

     среднее по полосе      разброс 60.7  мерило, сколько камня в кадре
     верхний процентиль     разброс 48    мерило, как он освещён
     доли каналов у света   разброс 2.17% мерило, сколько неба рядом

   Последний ряд это видно прямо в числах: на долях 0.02-0.30, где кадр
   по составу одинаков, тон держится до сотых долей процента (b 0.3600,
   0.3609, 0.3608, 0.3607). Уходит он там, где меняется фон: 0.55 с
   летящими блоками и синим свечением между ними даёт 0.3672, а 0.85 со
   сплошной кладкой без единого просвета - 0.3455.

   И решающее. Снятый множитель был ПОЧТИ НЕЙТРАЛЬНЫМ по каналам: 0.834
   по яркости против 0.819 по синему, полтора процента разницы. Мерка
   тона не поймала бы ту самую подмену, ради которой написана. Мерить
   картинкой тут нечего: ракурс, свет и фон шумят сильнее, чем сам
   дефект.

   Зато дефект точно описывается в коде. Подмена материала это
   умножение цвета камня на что-либо, зависящее от `uStena`, то есть от
   ХОДА СБОРКИ. Свет, тени, швы и кромки от доли зависеть имеют право;
   сам цвет камня - нет. Это и проверяем, и обмануть такую проверку
   ракурсом невозможно.

   Числа со снимков остаются в распечатке: глазу они полезны, вердикт по
   ним не выносится. */
{
  const шейдер = readFileSync("assets/rv-act-станция.js", "utf8");
  const строки = шейдер.split("\n");
  const виноватые = [];
  for (let i = 0; i < строки.length; i++) {
    const с = строки[i];
    if (/^\s*\/[*/]/.test(с)) continue;            /* комментарий, не код */
    if (!/"\s*color\s*\*=/.test(с)) continue;      /* не про цвет камня */
    if (!/uStena/.test(с)) continue;
    виноватые.push(`${i + 1}: ${с.trim().slice(0, 90)}`);
  }
  console.log(`  цвет камня умножается на долю сборки: ${виноватые.length ? "ДА" : "нет"}`);
  for (const в of виноватые) console.log("     " + в);
  if (виноватые.length) итог.push("цвет камня умножается на uStena: подмена материала по ходу сборки");
}

if (беды.length) итог.push("ошибки страницы: " + [...new Set(беды)].slice(0, 5).join(" | "));

if (итог.length) {
  console.log("\nКРАСНОЕ:");
  for (const с of итог) console.log("   " + с);
} else {
  console.log("\nзелено: кнопки уходят вниз и до стены, камень один");
}
await бр.close();
process.exit(итог.length ? 1 : 0);
