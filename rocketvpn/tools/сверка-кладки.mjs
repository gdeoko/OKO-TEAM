/* Одна ли кладка во всех трёх местах: дом, стена, проход за стену.

   ЗАЧЕМ. Владелец: «вначале стена собирается не из тех кирпичей, а
   появляется готовая из другого материала, а потом тоннель тоже не из
   этих». Спорить тут не о чем, это проверяется числами: у каждой
   каменной поверхности в сцене свои краски в однородных значениях
   шейдера (uKamen, uTen, uVerh, uNiz, uGlow). Совпадают - камень один.
   Расходятся - человек видит ровно то, о чём сказал.

   ПОЧЕМУ НЕ ПО СНИМКУ. Снимок мешает камень со светом, туманом и
   ореолом: две одинаковые стены под разным светом дают разные точки, а
   две разные под одинаковым - похожие. Однородные значения это сам
   материал, до всякого света, и врать им нечем.

   Обходим сцену на нескольких долях ленты, потому что кладка живёт не
   всё время: у дома она одна, у стены другая, и собираются они в разные
   минуты фильма.

   Запуск: RV_URL=http://127.0.0.1:8170 node tools/сверка-кладки.mjs */
import { браузер, открыть, ПК } from "./checks/общее.mjs";

const ДОЛИ = [0.10, 0.22, 0.34, 0.46, 0.58];

const b = await браузер();
const { pg } = await открыть(b, ПК, {});
await pg.waitForFunction(
  () => window.RV_WORLD && window.RV_WORLD["вступлениеИдёт"] && !window.RV_WORLD["вступлениеИдёт"](),
  null, { timeout: 240000 }).catch(() => console.log("вступления не дождались"));

const собрано = new Map();

for (const д of ДОЛИ) {
  await pg.evaluate((доля) => {
    scrollTo(0, (document.documentElement.scrollHeight - innerHeight) * доля);
  }, д);
  await pg.waitForTimeout(2500);

  const краски = await pg.evaluate(() => {
    const мир = window.RV_WORLD && window.RV_WORLD["мир"] ? window.RV_WORLD["мир"]() : null;
    if (!мир || !мир.scene) return [];
    const хекс = (ц) => "#" + [ц.r, ц.g, ц.b]
      .map((к) => Math.round(Math.min(1, Math.max(0, к)) * 255).toString(16).padStart(2, "0")).join("");
    const найдено = [];
    мир.scene.traverse((узел) => {
      const мат = узел.material;
      if (!мат || !мат.uniforms || !мат.uniforms.uKamen) return;
      /* Имя узла редко ставят, поэтому подписываемся цепочкой родителей:
         по ней сразу видно, чей это камень. */
      let путь = [], у = узел;
      for (let i = 0; i < 4 && у; i++, у = у.parent) путь.unshift(у.name || у.type);
      найдено.push({
        путь: путь.join("/"),
        виден: !!узел.visible,
        краски: ["uKamen", "uTen", "uVerh", "uNiz", "uGlow"]
          .filter((и) => мат.uniforms[и] && мат.uniforms[и].value && "r" in мат.uniforms[и].value)
          .map((и) => и + " " + хекс(мат.uniforms[и].value)).join("  ")
      });
    });
    return найдено;
  });

  console.log(`\n── доля ${д.toFixed(2)}`);
  for (const к of краски) {
    console.log(`   ${к.виден ? "виден " : "скрыт "} ${к.путь}\n            ${к.краски}`);
    if (к.виден && к.краски) собрано.set(к.путь, к.краски);
  }
}

console.log("\n══ свод по видимой кладке");
const наборы = new Map();
for (const [путь, краски] of собрано) {
  if (!наборы.has(краски)) наборы.set(краски, []);
  наборы.get(краски).push(путь);
}
let n = 0;
for (const [краски, пути] of наборы) {
  console.log(`\n набор ${++n}: ${краски}`);
  for (const п of пути) console.log("   " + п);
}
console.log(наборы.size === 1
  ? "\nОДНА кладка во всех местах"
  : `\nРАЗНЫХ КЛАДОК ${наборы.size}: человек видит разный камень`);

await b.close();
