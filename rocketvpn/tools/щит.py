# Распределительный щит шлюзовой рубки. Модель для акта 5.
#
#   blender -b -noaudio -P щит.py
#
# ЗАЧЕМ. Акт «Рубка» задуман правильно: поворотный щит, доки, кораблики,
# звено. Но собран он из тонких колец и цилиндров, и на кадре читается
# чертежом, а не железом. Чертёж не продаёт: человек видит схему тарифа
# вместо машины, которая этот тариф исполняет.
#
# РАЗДЕЛЕНИЕ ТРУДА. Модель даёт ТЕЛО: раму, лицевую плиту, утопленные
# гнёзда доков, направляющие, кожухи, кабельный лоток, болты. Свет,
# кольца причалов, кораблики и звено остаются кодом: они живут, меняются
# и подсвечиваются, а тело стоит.
#
# ОРИЕНТАЦИЯ. Щит стоит лицом к камере: лицо смотрит по +Z в Blender,
# после экспорта с yup это +Z сцены three. Центр щита в начале координат,
# ширина по X, высота по Y.
#
# БЮДЖЕТ. До восьми тысяч треугольников: щит в кадре один и занимает
# половину экрана, ему можно больше, чем станции.

import bpy, math, os

# Размеры сняты с самого акта: рама щита там объявлена как рw=1.75 и
# рh=3.7, доки стоят на y=2.05 и y=-1.25 с причалами радиусом 1.25 и
# 1.5. Модель обязана сесть на эти же числа, иначе тело и свет разъедутся.
Ш = 3.50   # ширина щита
В = 7.40   # высота щита
Т = 0.26   # толщина

def чисто():
    bpy.ops.wm.read_factory_settings(use_empty=True)

def короб(имя, sx, sy, sz, x=0, y=0, z=0, rz=0.0):
    bpy.ops.mesh.primitive_cube_add(size=1, location=(x, y, z))
    о = bpy.context.object
    о.name = имя
    о.scale = (sx, sy, sz)
    о.rotation_euler[2] = rz
    return о

def цилиндр(имя, r, h, грани, x=0, y=0, z=0, ось="z"):
    bpy.ops.mesh.primitive_cylinder_add(vertices=грани, radius=r, depth=h,
                                        location=(x, y, z))
    о = bpy.context.object
    о.name = имя
    if ось == "x":
        о.rotation_euler[1] = math.pi / 2
    elif ось == "y":
        о.rotation_euler[0] = math.pi / 2
    return о

def тор(имя, R, r, N, n, x=0, y=0, z=0):
    bpy.ops.mesh.primitive_torus_add(major_radius=R, minor_radius=r,
                                     major_segments=N, minor_segments=n,
                                     location=(x, y, z))
    о = bpy.context.object
    о.name = имя
    return о

def сплав(имена, имя):
    объекты = [bpy.data.objects[и] for и in имена if и in bpy.data.objects]
    bpy.ops.object.select_all(action="DESELECT")
    for о in объекты:
        о.select_set(True)
    bpy.context.view_layer.objects.active = объекты[0]
    if len(объекты) > 1:
        bpy.ops.object.join()
    о = bpy.context.object
    о.name = имя
    return о

def собрать():
    чисто()
    ч = []

    # ── Рама. Четыре бруса по краю: щит это шкаф, а не лист железа.
    ч.append(короб("рама_низ", Ш, 0.20, Т, y=-В / 2 + 0.10).name)
    ч.append(короб("рама_верх", Ш, 0.20, Т, y=В / 2 - 0.10).name)
    ч.append(короб("рама_лев", 0.20, В, Т, x=-Ш / 2 + 0.10).name)
    ч.append(короб("рама_прав", 0.20, В, Т, x=Ш / 2 - 0.10).name)

    # Лицевая плита утоплена внутрь рамы: у щита есть глубина.
    ч.append(короб("плита", Ш - 0.34, В - 0.34, Т * 0.42, z=-Т * 0.22).name)

    # ── Гнёзда доков. Два утопленных круга: в них садятся причальные
    #    кольца, которые рисует код. Воротник по краю даёт кромке блик.
    for имя, y0, R in (("док1", 2.05, 1.46), ("док2", -1.25, 1.68)):
        ч.append(тор("%s_воротник" % имя, R, 0.055, 44, 8, y=y0, z=Т * 0.06).name)
        # Второе кольцо внутри читалось конфоркой: убрано. Вместо него
        # четыре коротких упора, как на настоящем причальном гнезде.
        for у in range(4):
            a = у * math.pi / 2 + math.pi / 4
            ч.append(короб("%s_упор%d" % (имя, у), 0.16, 0.07, 0.05,
                           x=math.cos(a) * R * 0.72,
                           y=y0 + math.sin(a) * R * 0.72, z=Т * 0.06, rz=a).name)
        # Дно гнезда: чуть глубже плиты, иначе кольцо висит в воздухе.
        ч.append(цилиндр("%s_дно" % имя, R * 0.96, 0.05, 36, y=y0, z=-Т * 0.16).name)
        # Крепёж по кругу.
        for i in range(8):
            a = i * math.pi / 4 + 0.2
            ч.append(цилиндр("%s_болт%d" % (имя, i), 0.035, 0.05, 6,
                             x=math.cos(a) * R, y=y0 + math.sin(a) * R,
                             z=Т * 0.12).name)

    # ── Направляющие. Две горизонтальные рейки: по ним на настоящем
    #    щите ходят модули.
    for y in (-В / 2 + 0.50, В / 2 - 0.52):
        ч.append(короб("рейка%.2f" % y, Ш - 0.44, 0.075, 0.07, y=y, z=Т * 0.10).name)
        for i in range(11):
            x = -Ш / 2 + 0.36 + i * (Ш - 0.72) / 10
            ч.append(короб("зуб%.2f_%d" % (y, i), 0.035, 0.11, 0.05,
                           x=x, y=y, z=Т * 0.14).name)

    # ── Кожухи и модули на лице. Разного размера: одинаковые читаются
    #    обоями, разные - оборудованием.
    модули = ((-1.28, 3.28, 0.34, 0.22), (0.30, 3.30, 0.56, 0.18),
              (1.24, 3.26, 0.30, 0.22), (-1.30, 0.42, 0.30, 0.20),
              (1.28, 0.42, 0.30, 0.20), (-1.10, -3.16, 0.44, 0.22),
              (0.62, -3.18, 0.52, 0.20))
    for i, (x, y, sx, sy) in enumerate(модули):
        ч.append(короб("модуль%d" % i, sx, sy, 0.10, x=x, y=y, z=Т * 0.14).name)
        ч.append(короб("щель%d" % i, sx * 0.72, 0.03, 0.03,
                       x=x, y=y + sy * 0.22, z=Т * 0.20).name)

    # ── Кабельный лоток внизу: он и говорит, что щит подключён.
    ч.append(короб("лоток", Ш - 0.6, 0.14, 0.09, y=-В / 2 + 0.24, z=Т * 0.12).name)
    for i in range(7):
        x = -Ш / 2 + 0.5 + i * (Ш - 1.0) / 6
        ч.append(цилиндр("кабель%d" % i, 0.022, 0.34, 6,
                         x=x, y=-В / 2 + 0.42, z=Т * 0.14, ось="y").name)

    # ── Ворота на сторону CDN: рамка внизу справа. Пока закрыты, и
    #    поэтому это просто железная рамка без света.
    # Ворота на сторону CDN живут не на щите, а в рубке: щит
    # поворачивается, а створ к соседям стоит. Поэтому здесь их нет.


    # ── Уголки рамы: без них рама читается нарисованной.
    for sx in (-1, 1):
        for sy in (-1, 1):
            ч.append(короб("уголок%d%d" % (sx, sy), 0.30, 0.30, Т * 1.06,
                           x=sx * (Ш / 2 - 0.16), y=sy * (В / 2 - 0.16)).name)

    о = сплав(ч, "щит")
    # Начало координат объекта после слияния сидит на первой детали, а
    # не в середине щита. Поворот вокруг такого начала уводит всю модель
    # вбок: на первом же кадре щит уехал из середины экрана. Ставим
    # начало в середину геометрии и только потом поворачиваем.
    bpy.ops.object.origin_set(type="ORIGIN_GEOMETRY", center="BOUNDS")
    о.location = (0, 0, 0)
    # Щит собран лежащим лицом вверх: так проще считать координаты. На
    # сайте он стоит лицом к человеку, поэтому ставим его на ребро.
    # Поворот на четверть вокруг X плюс перевод в Y-вверх при экспорте
    # дают лицо, смотрящее на камеру.
    о.rotation_euler[0] = math.pi / 2
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    bpy.ops.object.shade_smooth()
    м = о.modifiers.new("фаска", "BEVEL")
    м.width = 0.010
    м.segments = 1
    м.limit_method = "ANGLE"
    м.angle_limit = math.radians(40)
    bpy.ops.object.modifier_apply(modifier="фаска")

    bpy.ops.object.mode_set(mode="EDIT")
    bpy.ops.mesh.select_all(action="SELECT")
    bpy.ops.uv.smart_project(angle_limit=math.radians(66), island_margin=0.02)
    bpy.ops.object.mode_set(mode="OBJECT")
    return о


о = собрать()
треуг = sum(len(p.vertices) - 2 for p in о.data.polygons)
путь = "/opt/oko-poster/cab/щит.glb"
bpy.ops.export_scene.gltf(filepath=путь, export_format="GLB",
                          export_apply=True, export_materials="NONE",
                          export_normals=True, export_texcoords=True,
                          export_yup=True)
print("ГОТОВО треугольников", треуг, "байт", os.path.getsize(путь))
