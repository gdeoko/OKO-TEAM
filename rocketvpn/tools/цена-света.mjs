/* СКОЛЬКО СТОИТ ЖИВОЙ СВЕТ. Замер перед запеканием, а не после.

   План эталонов (docs/ПЛАН-ЭТАЛОН.md, п.6) говорит запечь свет в
   текстуры, и довод там такой: «свет живой и тяжёлый, это источник и
   пересвета, и нагрузки на телефоне». Довод прочитан по коду, а не
   снят замером. Запекание это день работы, чужая развёртка на моделях
   NASA и риск испортить картинку - за такое берутся, когда цена
   названа числом.

   Меряем так: на каждой доле ленты снимаем время кадра при живом свете,
   потом гасим ВСЕ источники (intensity 0) и снимаем снова. Разница это
   и есть цена света в миллисекундах. Гасим, а не удаляем: удаление
   пересобирает программы материалов, и в замер попала бы компиляция.

   Отрисовщик тут программный (swiftshader), и абсолютные числа выше
   живых. Для решения это годится: программный отрисовщик считает
   пиксель на процессоре, то есть ведёт себя как слабый телефон, только
   заметнее. Смотрим ДОЛЮ, а не миллисекунды.

   Запуск: node tools/цена-света.mjs [шагов]
*/
import { браузер, открыть, лентаВсего, кПрокрутке, ТЕЛЕФОН, ПК } from "./checks/общее.mjs";

const ШАГОВ = Number(process.argv[2] || 9);
/* Кадров на замер. Первые отбрасываем: после прокрутки сцена ещё
   доезжает, и в среднее попало бы движение, а не свет. */
const ПРОГРЕВ = 12, СЧЁТ = 30;

async function времяКадра(pg) {
  return pg.evaluate(([п, с]) => new Promise((готово) => {
    const т = [];
    let n = 0, прошлое = performance.now();
    (function шаг() {
      requestAnimationFrame(() => {
        const т2 = performance.now();
        if (++n > п) т.push(т2 - прошлое);
        прошлое = т2;
        if (т.length >= с) {
          т.sort((a, b) => a - b);
          /* Медиана, а не среднее: один длинный кадр сборки предмета
             тянет среднее на треть, а медиану не трогает. */
          готово(Math.round(т[Math.floor(т.length / 2)] * 10) / 10);
        } else шаг();
      });
    })();
  }), [ПРОГРЕВ, СЧЁТ]);
}

/* ── ВЫКЛЮЧАТЕЛЬ ОБЯЗАН ПЕРЕЖИТЬ ЧУЖУЮ ЗАПИСЬ ──────────────────
   Первый заход просто писал `intensity = 0`, и проверка выключателя
   (tools/держится-ли.mjs) поймала, что на долях 0.80 и 1.00 из
   пятнадцати ламп через две секунды снова горят двенадцать: акт финала
   пишет силу КАЖДЫМ кадром (станСила в rv-act-финал.js). То есть в
   салоне, где ламп больше всего и ради которого всё и меряется,
   прежний замер не выключал ничего и честно печатал «цена ноль».

   Поэтому гасим не присваиванием, а подменой самого свойства: геттер
   отдаёт ноль, сеттер молча съедает чужую запись и запоминает её.
   Вернуть - удалить подменённое свойство, значение уже в прототипе. */
async function лампы(pg, гасить) {
  return pg.evaluate((г) => {
    const мир = window.RV_WORLD["мир"]();
    /* ── СПИСОК ЛАМП СОБИРАЕМ ЗАНОВО КАЖДЫЙ РАЗ ──────────────────
       Он кешировался с первого вызова, то есть с доли ноль, где в
       сцене всего четыре источника. Салон корабля собирается позже и
       приносит ещё двенадцать - в кеш они не попадали НИКОГДА, и замер
       гасил четыре лампы вместо шестнадцати, ровно мимо того места,
       ради которого затевался. Видно это было только по столбцу
       «ламп»: на телефоне там стояло 9-10, на ПК 4, при одной и той же
       сцене. */
    window.__силы = [];
    мир.scene.traverse(function (о) { if (о.isLight) window.__силы.push(о); });
    let n = 0;
    for (const л of window.__силы) {
      let вид = л.visible, у = л.parent;
      while (у) { if (!у.visible) вид = false; у = у.parent; }
      if (вид && л.intensity > 0) n++;
      if (г) {
        if (!Object.getOwnPropertyDescriptor(л, "__тень")) {
          Object.defineProperty(л, "__тень", { value: { с: л.intensity }, writable: true, configurable: true });
          Object.defineProperty(л, "intensity", {
            get: function () { return 0; },
            set: function (v) { this.__тень.с = v; },
            configurable: true
          });
        }
      } else if (Object.getOwnPropertyDescriptor(л, "__тень")) {
        const с = л.__тень.с;
        delete л.intensity;
        delete л.__тень;
        л.intensity = с;
      }
    }
    return n;
  }, гасить);
}

/* Выключатель проверяем на месте: две секунды живых кадров и читаем
   обратно. Не удержался - замер по этой доле недействителен, и это
   печатается, а не замалчивается. */
async function держится(pg) {
  return pg.evaluate(() =>
    window.__силы.filter((л) => л.intensity > 0).length);
}

const b = await браузер();
try {
  for (const э of [ПК, ТЕЛЕФОН]) {
    const { pg } = await открыть(b, э);
    await pg.waitForTimeout(4000);
    const всего = await лентаВсего(pg);
    console.log("\n=== " + э.имя + " " + э.vp.width + "x" + э.vp.height + " ===");
    console.log("доля   ламп   свет есть   свет погашен   цена      выключатель");
    for (let i = 0; i <= ШАГОВ; i++) {
      const д = i / ШАГОВ;
      await кПрокрутке(pg, всего * д);
      await pg.waitForTimeout(2500);
      const n = await лампы(pg, false);
      const сЖивым = await времяКадра(pg);
      await лампы(pg, true);
      await pg.waitForTimeout(2000);
      const горит = await держится(pg);
      const беЗСвета = await времяКадра(pg);
      await лампы(pg, false);
      const цена = Math.round((сЖивым - беЗСвета) * 10) / 10;
      const доля = беЗСвета > 0 ? Math.round(100 * цена / сЖивым) : 0;
      console.log(д.toFixed(2).padStart(5), String(n).padStart(5),
        String(сЖивым).padStart(11) + " мс", String(беЗСвета).padStart(11) + " мс",
        String(цена).padStart(7) + " мс = " + String(доля + "%").padEnd(6),
        горит === 0 ? "держится" : "НЕ ДЕРЖИТСЯ, горит " + горит);
    }
    await pg.close();
  }
} finally {
  await b.close();
}
