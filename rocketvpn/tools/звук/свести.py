# -*- coding: utf-8 -*-
"""Сведение слоёв банка Rocket VPN в готовые файлы сайта.

Слои приезжают из ElevenLabs каждый со своей задачей и своей громкостью.
Здесь они складываются в один звук: у каждого слоя свой уровень, свой
сдвиг по времени и свой фильтр - ровно то, что делает сведение сведением,
а не суммой.

ЧТО ДЕЛАЕТСЯ ПО ПОРЯДКУ
  1. Каждый слой приводится к моно 44,1 кГц, получает свой фильтр
     (обрезка полос, чтобы слои не спорили за одно место) и свою
     громкость, и сдвигается на своё место во времени.
  2. Слои складываются. amix делит сумму на число входов, поэтому
     громкость возвращается умножением обратно: иначе трёхслойный звук
     выходит втрое тише однослойного.
  3. Хвост. У разовых звуков края режутся по тишине, у петель НЕ
     режутся никогда: обрезка ломает стык, и петля начинает щёлкать.
  4. Громкость приводится к одному уровню по всему банку, дальше
     ограничитель ловит одиночные пики.
  5. Замер: длина, пик и средняя громкость каждого файла. Пустышку и
     перегруз видно числом, без прослушивания.

ПОЧЕМУ ПОДЛОЖКИ ТИШЕ РАЗОВЫХ. Подложка звучит непрерывно и не должна
занимать внимание; удар звучит раз и обязан. Разница в четыре децибела
взята не на вкус: при равной громкости удар прокола переставал читаться
как событие, потому что фон уже занимал столько же места.
"""
import os, subprocess, sys

КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))
СЛОИ_ПУТЬ = os.path.join(КОРЕНЬ, "слои")
ГОТОВО = os.path.join(КОРЕНЬ, "готово")

sys.path.insert(0, КОРЕНЬ)
from банк import БАНК

# Целевая громкость. Подложки тише разовых на четыре децибела.
ГРОМКО_ПЕТЛЯ = -23.0
ГРОМКО_РАЗОВЫЙ = -19.0


def петля(имя):
    return БАНК[имя][0][2]


def свести(имя):
    слои = БАНК[имя]
    вход = []
    цепь = []
    метки = []
    for k, (суф, сек, цикл, влиян, промпт, гр, сдв, фильтр) in enumerate(слои):
        путь = os.path.join(СЛОИ_ПУТЬ, имя + "." + суф + ".mp3")
        if not os.path.exists(путь):
            print("НЕТ СЛОЯ", путь)
            return False
        вход += ["-i", путь]
        части = ["aformat=channel_layouts=mono:sample_rates=44100"]
        if фильтр:
            части.append(фильтр)
        if сдв > 0:
            части.append("adelay=%d" % int(сдв * 1000))
        части.append("volume=%.3f" % гр)
        цепь.append("[%d:a]%s[с%d]" % (k, ",".join(части), k))
        метки.append("[с%d]" % k)

    n = len(слои)
    граф = ";".join(цепь)
    if n > 1:
        # amix делит на число входов - возвращаем громкость обратно.
        граф += ";%samix=inputs=%d:duration=longest:normalize=0[см]" % ("".join(метки), n)
    else:
        граф += ";%sanull[см]" % метки[0]

    цикл = петля(имя)
    хвост = "[см]"
    if not цикл:
        # Тишину по краям режем только у разовых: у петли это стык.
        граф += (";%ssilenceremove=start_periods=1:start_silence=0.02:"
                 "start_threshold=-52dB:detection=peak,areverse,"
                 "silenceremove=start_periods=1:start_silence=0.05:"
                 "start_threshold=-56dB:detection=peak,areverse[рез]") % хвост
        хвост = "[рез]"
    цель = ГРОМКО_ПЕТЛЯ if цикл else ГРОМКО_РАЗОВЫЙ
    граф += (";%sloudnorm=I=%.1f:TP=-1.2:LRA=11,"
             "alimiter=limit=0.78:level=disabled[вых]") % (хвост, цель)

    выход = os.path.join(ГОТОВО, имя + ".mp3")
    к = subprocess.run(
        ["ffmpeg", "-v", "error", "-y"] + вход +
        ["-filter_complex", граф, "-map", "[вых]",
         "-ac", "1", "-ar", "44100", "-b:a", "88k" if цикл else "80k", выход],
        capture_output=True, text=True)
    if к.returncode != 0:
        print("ОШИБКА ffmpeg", имя, к.stderr[:400])
        return False
    return True


def замер(путь):
    д = subprocess.run(["ffprobe", "-v", "error", "-show_entries",
                        "format=duration", "-of", "csv=p=0", путь],
                       capture_output=True, text=True).stdout.strip()[:5]
    ст = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", путь,
                         "-af", "astats", "-f", "null", "-"],
                        capture_output=True, text=True).stderr
    пик = rms = "?"
    for с in ст.split("\n"):
        if "Peak level dB" in с and пик == "?":
            пик = с.split(":")[-1].strip()
        if "RMS level dB" in с and rms == "?":
            rms = с.split(":")[-1].strip()
    return д, пик, rms, os.path.getsize(путь)


def главное():
    os.makedirs(ГОТОВО, exist_ok=True)
    только = set(sys.argv[1:])
    сделано = []
    for имя in БАНК:
        if только and имя not in только:
            continue
        if свести(имя):
            сделано.append(имя)
    print("=== замеры (имя  сек  пик_дБ  RMS_дБ  байт) ===")
    всего = 0
    беды = []
    for имя in сделано:
        путь = os.path.join(ГОТОВО, имя + ".mp3")
        д, пик, rms, б = замер(путь)
        всего += б
        print("%-12s %5s  %8s  %8s  %8d" % (имя, д, пик, rms, б))
        try:
            if float(rms) < -46:
                беды.append(имя + ": почти тишина, RMS " + rms)
            if float(пик) > -0.3:
                беды.append(имя + ": перегруз, пик " + пик)
        except ValueError:
            беды.append(имя + ": замер не прочитан")
    print("=== всего %d файлов, %.0f КБ ===" % (len(сделано), всего / 1024.0))
    for б in беды:
        print("БЕДА", б)


главное()
