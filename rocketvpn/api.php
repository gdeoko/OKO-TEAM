<?php
/* Rocket VPN. Приёмник событий счётчика и заявок с форм.

   ЗАЧЕМ ОН ПОЯВИЛСЯ. Счётчик сайта и форма обратной связи отправляли
   данные ПРЯМО на https://rocketcdn.ru/api.php - то есть браузер
   КАЖДОГО посетителя VPN сам, без всякой кнопки, ходил на соседний
   домен. Форма при этом несла туда имя человека и его способ связи. Это связка
   между двумя сайтами прочнее любой ссылки: она видна в инструментах
   разработчика у любого, кто откроет вкладку «Сеть», и срабатывает
   автоматически, а не по нажатию.

   Заказчик просил закрыть именно это: «если из впн на cdn будет
   свободный переход, мою личность установить будет крайне легко». Он
   говорил про кнопку, но кнопка была меньшей из двух дорожек.

   ЧТО ТЕПЕРЬ. Браузер шлёт события на СВОЙ домен, сюда. Отсюда они
   уходят на общую панель уже с сервера, и ни один посетитель этого не
   видит: соединение между машинами, а не между браузером и чужим
   сайтом. Общая аналитика при этом сохранилась целиком, ветки
   «аналитика CDN» и «аналитика VPN» продолжают наполняться.

   ПОЧЕМУ ОТВЕЧАЕМ РАНЬШЕ, ЧЕМ ПЕРЕСЫЛАЕМ. Счётчик ждёт ответа и при
   неудаче копит очередь и шлёт заново. Если ответ будет ждать чужой
   сервер, страница будет ждать его же: медленная панель означала бы
   медленный сайт. Поэтому сначала «ок» человеку, потом пересылка.

   ПОЧЕМУ АДРЕС ПАНЕЛИ В ОКРУЖЕНИИ. В коде сайта чужих адресов не
   держим по той же причине, по которой убрали ссылку: исходник
   страницы читается кем угодно, а этот файл наружу не отдаётся вовсе.
   Нет переменной - события просто принимаются и никуда не идут, сайт
   от этого не ломается. */

header('Content-Type: application/json; charset=utf-8');
header('Cache-Control: no-store');
/* Своему домену заголовки доступа не нужны, и давать их не будем:
   принимаем только то, что пришло со своей же страницы. */

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
  http_response_code(405);
  echo '{"ok":false}';
  exit;
}

$тело = file_get_contents('php://input');
if ($тело === false || strlen($тело) > 65536) {
  http_response_code(413);
  echo '{"ok":false}';
  exit;
}

/* Отвечаем сразу и отпускаем браузер. Дальше работаем уже без него. */
echo '{"ok":true}';
if (function_exists('fastcgi_finish_request')) {
  fastcgi_finish_request();
} else {
  /* Без FPM закрываем соединение руками: иначе браузер будет держать
     его до конца пересылки, и весь смысл пропадёт. */
  ignore_user_abort(true);
  header('Connection: close');
  header('Content-Length: ' . strlen('{"ok":true}'));
  if (ob_get_level()) { ob_end_flush(); }
  flush();
}

/* Действие передаём дальше как есть: на той стороне один и тот же
   разбор для счётчика и для заявок, и знать о нём здесь незачем.
   Список закрытый: пересылать всё подряд значит отдать чужой панели
   дверь, которой у неё в нашем коде нет. */
$действие = isset($_GET['action']) ? (string)$_GET['action'] : '';
if ($действие !== 'track' && $действие !== 'lead') exit;

$панель = (string)getenv('RV_API_UPSTREAM');
if ($панель === '' || strncmp($панель, 'https://', 8) !== 0) exit;
$панель .= (strpos($панель, '?') === false ? '?' : '&')
        . 'action=' . rawurlencode($действие) . '&site=vpn';

/* Пересылка server-to-server. Короткий срок ожидания нарочно: панель
   недоступна - теряем пачку событий, а не время. Счётчик на стороне
   человека при этом считает доставку успешной, и правильно: он своё
   дело сделал. */
$ч = curl_init($панель);
curl_setopt_array($ч, [
  CURLOPT_POST => true,
  CURLOPT_POSTFIELDS => $тело,
  CURLOPT_HTTPHEADER => ['Content-Type: application/json'],
  CURLOPT_RETURNTRANSFER => true,
  CURLOPT_TIMEOUT => 4,
  CURLOPT_CONNECTTIMEOUT => 2,
]);
curl_exec($ч);
curl_close($ч);
