<?php
/* Rocket VPN. Створ: сайт отдаётся только по ключу.

   ЭТОТ ФАЙЛ - ЕДИНСТВЕННЫЙ ВХОД. Он называется index.php намеренно:
   сервер отдаёт его на голый адрес каталога, и мимо створа пройти
   некуда. Сама плёнка лежит в frame.html и наружу не отдаётся: её
   закрывает правило в .htaccess (и такое же правило для nginx описано
   в DEPLOY.md).

   Раньше плёнка называлась index.html и отдавалась сервером напрямую -
   створ обходился набором полного имени файла. Поймано собственной
   проверкой «тишина»: она заметила, что у ответа нет заголовка запрета
   индексации, и это оказалось не косметикой, а открытой дверью.

   Условие владельца: сайт доступен по прямой ссылке или тому, кто пришёл
   из Rocket CDN через космос. В открытой сети и в поисковой выдаче его
   быть не должно.

   ПОЧЕМУ ПРОВЕРКА ЖИВЁТ НА СЕРВЕРЕ, А НЕ В БРАУЗЕРЕ. Проверка в браузере
   закрывает только глаза: разметка всё равно уезжает к тому, кто её
   запросил, и достаётся одной строкой в консоли. Створ, который держит
   только браузер, это не закрытый сайт, а закрытый вид на открытый сайт.

   ПОЧЕМУ НЕ ПАРОЛЬ В АДРЕСЕ. Пароль в адресе не имеет срока: утёкшая
   ссылка работает вечно. Здесь ключ подписан и несёт в себе дату - утёк
   он или нет, через свой срок он перестаёт открывать.

   ПОЧЕМУ НЕ ПРОВЕРЯЕМ ЗАГОЛОВОК ИСТОЧНИКА ПЕРЕХОДА. Он ставится кем
   угодно и не ставится вовсе в половине случаев. Как единственная
   защита он бесполезен, а как дополнительная создаёт ложное чувство
   закрытости.

   ЧТО ЗДЕСЬ НАМЕРЕННО ОДИНАКОВО. Неверный ключ, просроченный ключ и
   отсутствие ключа дают ОДИН И ТОТ ЖЕ ответ. По виду створа нельзя
   понять, существует ли за ним что-нибудь: иначе перебор превращается в
   игру «угадай, где теплее». */

/* Секрет живёт в окружении, а не в файле. В репозиторий не попадает
   никогда. Если его нет - створ закрыт для всех, включая владельца: это
   безопаснее, чем открыться всем из-за пустой переменной. */
$СЕКРЕТ = getenv('RV_SITE_SECRET');

/* Срок жизни ключа. Неделя - разумный размен: ссылку успевают открыть,
   а утёкшая перестаёт работать сама, без чьего-либо участия. */
define('RV_СРОК', 7 * 24 * 3600);

function rv_подпись($метка, $секрет) {
  return substr(hash_hmac('sha256', 'rv|' . $метка, $секрет), 0, 24);
}

/* Ключ это метка времени и подпись. Метка нужна, чтобы ключ старел;
   подпись - чтобы его нельзя было сочинить. */
function rv_выдать_ключ($секрет, $сдвиг = 0) {
  $метка = time() + $сдвиг;
  return $метка . '.' . rv_подпись($метка, $секрет);
}

function rv_ключ_годен($ключ, $секрет) {
  if (!$секрет || !$ключ) return false;
  $ч = explode('.', $ключ, 2);
  if (count($ч) !== 2) return false;
  $метка = (int)$ч[0];
  if ($метка <= 0) return false;
  /* Будущее не принимаем: ключ с меткой вперёд означает либо сбой часов,
     либо попытку выдать себе вечный ключ. Небольшой допуск оставлен под
     честное расхождение часов между машинами. */
  if ($метка > time() + 300) return false;
  if (time() - $метка > RV_СРОК) return false;
  /* Сравнение постоянного времени: обычное сравнение строк выходит из
     цикла на первом несовпавшем знаке, и по времени ответа подпись
     подбирается по одному знаку. */
  return hash_equals(rv_подпись($метка, $секрет), $ч[1]);
}

/* ── Открыт или закрыт ────────────────────────────────────────
   С переездом на боевой домен клиента сайт перестал быть стендом. На
   rocketvpn.top приходят люди из бота и из рекламы, у них нет и не
   может быть подписанного ключа, и створ на этом адресе означал бы
   закрытую дверь перед покупателем.

   Открытость задаётся ОКРУЖЕНИЕМ, а не правкой кода: тот же файл
   работает и витриной на боевом домене, и закрытым стендом там, где
   стенд ещё нужен. Разница - одна строка в настройке сервера.

   Проверка ключа при этом НЕ УДАЛЕНА и остаётся рабочей: закрыть сайт
   обратно можно снятием переменной, без выкладки. */
$ОТКРЫТ = getenv('RV_SITE_OPEN') === '1';

/* ── Что отдаём ───────────────────────────────────────────────── */

/* Запрет индексации. На закрытом стенде он безусловный. На открытой
   витрине индексация разрешается отдельной переменной: пускать сайт в
   поиск - решение владельца сервиса, а не наше, и по умолчанию мы его
   за него не принимаем. Из поиска страницу потом не вынуть одним
   движением, а не пустить в него - можно всегда. */
if (!$ОТКРЫТ || getenv('RV_SITE_INDEX') !== '1') {
  header('X-Robots-Tag: noindex, nofollow, noarchive, nosnippet, noimageindex');
}
/* Кэш. У закрытого стенда ключ у каждого свой, и общий кэш означает,
   что чужой ключ откроет чужую копию, - поэтому там no-store.

   У открытой витрины страница одна на всех, но держать её в кэше по
   времени нельзя, и это не про свежесть вёрстки. До переезда сайта
   адрес rocketvpn.top отвечал ПОСТОЯННЫМ редиректом (301) на бота в
   телеграме. Постоянный редирект браузеры и встроенный браузер
   телеграма запоминают навсегда и больше к серверу не ходят: у людей,
   открывавших ссылку до переезда, она продолжает уводить в бота, и с
   сервера этого никак не отменить. Владелец поймал это на своём
   телефоне.

   no-cache здесь означает «спрашивай сервер каждый раз», а не «не
   храни»: тело всё равно берётся из кэша при неизменном ответе, но
   через вопрос серверу. Так ни один будущий редирект и ни одна ошибка
   не смогут залипнуть у человека навсегда. Сами ассеты по-прежнему
   кэшируются надолго, у них в адресе метка версии. */
if ($ОТКРЫТ) header('Cache-Control: no-cache, must-revalidate');
else header('Cache-Control: no-store, private');
header('Referrer-Policy: no-referrer');

/* Метка версии у каждого своего скрипта и стиля. Ассеты отдаются с
   кэшем на неделю (для повторных заходов это дешевле всего), а значит
   после выкладки браузер неделю держал бы старый rv-real.js при новой
   разметке: ровно так у людей неделю не рисовались бы корпуса, чей
   шейдер починен сегодня. Время правки файла в адресе меняет адрес
   при каждой выкладке, и старый кэш просто не спрашивается. */
function rv_версии($html) {
  return preg_replace_callback(
    '~(href|src)="(assets/[^"?]+\.(?:js|css))"~',
    function ($m) {
      $ф = __DIR__ . '/' . $m[2];
      $в = is_file($ф) ? (string)filemtime($ф) : '0';
      return $m[1] . '="' . $m[2] . '?v=' . $в . '"';
    },
    $html);
}

/* Открытая витрина отдаёт плёнку сразу, никого не спрашивая. */
if ($ОТКРЫТ) {
  $плёнка = rv_версии(file_get_contents(__DIR__ . '/frame.html'));

  /* СТВОРОВ ДВА, И ОТКРЫВАТЬ НАДО ОБА.

     Второй живёт в браузере (assets/rv-gate.js) и нужен на случай, когда
     сайт отдаётся статикой без PHP: тогда серверного створа нет вовсе.
     Пока сайт был стендом, они всегда работали в паре - ключ в адресе
     открывал сразу оба.

     С переходом на открытую витрину сервер стал отдавать плёнку без
     ключа, а браузерный створ ключа не увидел и честно закрылся. На
     боевом домене человек получал «Створ закрыт» поверх полностью
     отданного сайта. Проверка curl'ом этого НЕ ЛОВИТ: разметка в ответе
     полная, все восемь актов на месте, а закрывает их скрипт уже в
     браузере. Поймано снимком живого браузера.

     Признак ставится на корневом узле в самой разметке, до всякого
     скрипта: браузерный створ читает его первым делом и не закрывается. */
  $плёнка = preg_replace('~<html lang="ru">~i', '<html lang="ru" data-открыт="1">', $плёнка, 1);

  /* Метка индексации в разметке и заголовок ответа обязаны говорить
     ОДНО И ТО ЖЕ. Если разрешить индексацию заголовком, а в разметке
     оставить запрет, победит запрет - и переменная будет тихо не
     работать. Поэтому при разрешённой индексации метка снимается
     здесь же, при отдаче. */
  if (getenv('RV_SITE_INDEX') === '1') {
    $плёнка = preg_replace(
      '~<meta name="robots"[^>]*>~i',
      '<meta name="robots" content="index,follow">',
      $плёнка, 1);
  }
  echo $плёнка;
  exit;
}

$ключ = isset($_GET['k']) ? (string)$_GET['k'] : '';
/* Ключ, уже принятый однажды, кладётся в кук: иначе человек теряет
   доступ, стоит ему обновить страницу без адреса с ключом. */
if (!$ключ && isset($_COOKIE['rv_k'])) $ключ = (string)$_COOKIE['rv_k'];

if (rv_ключ_годен($ключ, $СЕКРЕТ)) {
  /* Путь кука берём из того, где сайт стоит на самом деле.

     Раньше здесь было прибито `/site`, потому что сайт жил под этим
     путём. Он переехал в корень домена, а строка осталась: браузер
     держал кук для `/site` и на корневой адрес его не слал вовсе.
     Человек, вошедший по ключу, терял доступ на первом же обновлении
     страницы - незаметно, потому что корень домена сейчас открыт
     переменной и створ до проверки кука не доходит. Стоит закрыть
     корень, и дыра открылась бы в тот же день. */
  $путь = (string)getenv('RV_SITE_URL');
  if ($путь === '' || $путь[0] !== '/') $путь = '/';
  setcookie('rv_k', $ключ, [
    'expires'  => time() + RV_СРОК,
    'path'     => $путь,
    'secure'   => true,
    'httponly' => true,
    'samesite' => 'Lax'
  ]);

  /* Ключ из адресной строки убирает rv-gate.js, а не этот файл.
     Серверная чистка была бы РАНЬШЕ браузерного створа и вырезала бы
     ключ у него из-под носа: створ читает ключ из адреса, и без него
     сайт не открывался вовсе - ровно это и поймала проверка створа. */
  echo rv_версии(file_get_contents(__DIR__ . '/frame.html'));
  exit;
}

/* Створ закрыт. Отдаём 404, а не 403: отказ в доступе сообщает, что
   доступать есть куда, а «не найдено» не сообщает ничего. */
http_response_code(404);
header('Content-Type: text/html; charset=utf-8');
readfile(__DIR__ . '/stvor.html');
