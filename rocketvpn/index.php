/* Rocket VPN. Створ: сайт отдаётся только по ключу.

   ЭТОТ ФАЙЛ - ЕДИНСТВЕННЫЙ ВХОД. Он называется index.php намеренно:
   сервер отдаёт его на голый адрес каталога, и мимо створа пройти
   некуда. Сама плёнка лежит в frame.html и наружу не отдаётся: её
   закрывает правило в .htaccess (и такое же правило для nginx описано
   в DEPLOY.md).

   Раньше плёнка называлась index.html и отдавалась сервером напрямую -
   створ обходился набором полного имени файла. Поймано собственной
   проверкой «тишина»: она заметила, что у ответа нет заголовка запрета
   индексации, и это оказалось не косметикой, а открытой дверью.

   Условие владельца: сайт доступен по прямой ссылке или тому, кто пришёл
   из Rocket CDN через космос. В открытой сети и в поисковой выдаче его
   быть не должно.

   ПОЧЕМУ ПРОВЕРКА ЖИВЁТ НА СЕРВЕРЕ, А НЕ В БРАУЗЕРЕ. Проверка в браузере
   закрывает только глаза: разметка всё равно уезжает к тому, кто её
   запросил, и достаётся одной строкой в консоли. Створ, который держит
   только браузер, это не закрытый сайт, а закрытый вид на открытый сайт.

   ПОЧЕМУ НЕ ПАРОЛЬ В АДРЕСЕ. Пароль в адресе не имеет срока: утёкшая
   ссылка работает вечно. Здесь ключ подписан и несёт в себе дату - утёк
   он или нет, через свой срок он перестаёт открывать.

   ПОЧЕМУ НЕ ПРОВЕРЯЕМ ЗАГОЛОВОК ИСТОЧНИКА ПЕРЕХОДА. Он ставится кем
   угодно и не ставится вовсе в половине случаев. Как единственная
   защита он бесполезен, а как дополнительная создаёт ложное чувство
   закрытости.

   ЧТО ЗДЕСЬ НАМЕРЕННО ОДИНАКОВО. Неверный ключ, просроченный ключ и
   отсутствие ключа дают ОДИН И ТОТ ЖЕ ответ. По виду створа нельзя
   понять, существует ли за ним что-нибудь: иначе перебор превращается в
   игру «угадай, где теплее». */

/* Секрет живёт в окружении, а не в файле. В репозиторий не попадает
   никогда. Если его нет - створ закрыт для всех, включая владельца: это
   безопаснее, чем открыться всем из-за пустой переменной. */
$СЕКРЕТ = getenv('RV_SITE_SECRET');

/* Срок жизни ключа. Неделя - разумный размен: ссылку успевают открыть,
   а утёкшая перестаёт работать сама, без чьего-либо участия. */
define('RV_СРОК', 7 * 24 * 3600);

function rv_подпись($метка, $секрет) {
  return substr(hash_hmac('sha256', 'rv|' . $метка, $секрет), 0, 24);
}

/* Ключ это метка времени и подпись. Метка нужна, чтобы ключ старел;
   подпись - чтобы его нельзя было сочинить. */
function rv_выдать_ключ($секрет, $сдвиг = 0) {
  $метка = time() + $сдвиг;
  return $метка . '.' . rv_подпись($метка, $секрет);
}

function rv_ключ_годен($ключ, $секрет) {
  if (!$секрет || !$ключ) return false;
  $ч = explode('.', $ключ, 2);
  if (count($ч) !== 2) return false;
  $метка = (int)$ч[0];
  if ($метка <= 0) return false;
  /* Будущее не принимаем: ключ с меткой вперёд означает либо сбой часов,
     либо попытку выдать себе вечный ключ. Небольшой допуск оставлен под
     честное расхождение часов между машинами. */
  if ($метка > time() + 300) return false;
  if (time() - $метка > RV_СРОК) return false;
  /* Сравнение постоянного времени: обычное сравнение строк выходит из
     цикла на первом несовпавшем знаке, и по времени ответа подпись
     подбирается по одному знаку. */
  return hash_equals(rv_подпись($метка, $секрет), $ч[1]);
}

/* ── Что отдаём ───────────────────────────────────────────────── */

/* Запрет индексации ставится ЗАГОЛОВКОМ, а не только меткой в разметке.
   Заголовок действует и на то, у чего разметки нет вовсе, и его нельзя
   не заметить, разбирая страницу частями. */
header('X-Robots-Tag: noindex, nofollow, noarchive, nosnippet, noimageindex');
/* Промежуточным хранилищам эту страницу держать незачем: ключ у каждого
   свой, а общий кэш означает, что чужой ключ откроет чужую копию. */
header('Cache-Control: no-store, private');
header('Referrer-Policy: no-referrer');

$ключ = isset($_GET['k']) ? (string)$_GET['k'] : '';
/* Ключ, уже принятый однажды, кладётся в кук: иначе человек теряет
   доступ, стоит ему обновить страницу без адреса с ключом. */
if (!$ключ && isset($_COOKIE['rv_k'])) $ключ = (string)$_COOKIE['rv_k'];

if (rv_ключ_годен($ключ, $СЕКРЕТ)) {
  setcookie('rv_k', $ключ, [
    'expires'  => time() + RV_СРОК,
    'path'     => '/site',
    'secure'   => true,
    'httponly' => true,
    'samesite' => 'Lax'
  ]);
  readfile(__DIR__ . '/frame.html');
  exit;
}

/* Створ закрыт. Отдаём 404, а не 403: отказ в доступе сообщает, что
   доступать есть куда, а «не найдено» не сообщает ничего. */
http_response_code(404);
header('Content-Type: text/html; charset=utf-8');
readfile(__DIR__ . '/stvor.html');
