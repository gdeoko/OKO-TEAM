/* Rocket VPN. Раскладка фактов по разметке.

   Разметка держит ПУСТЫЕ гнёзда с пометкой data-заполнить, а числа
   приезжают сюда из одного файла фактов. Так цена живёт в одном месте,
   и её правка не требует искать её по странице.

   Почему сборка строками, а не по узлу за раз: блоков мало, они
   собираются один раз за жизнь страницы, и читаемость здесь важнее
   микроскопической разницы в скорости. */
(function (g, d) {
  "use strict";

  function эк(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  }

  /* Разряд в цене. Неразрывный пробел, а не обычный: иначе на узком
     экране «4 199 рублей» переносится посередине числа. */
  function деньги(n) {
    return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " ") + " ₽";
  }

  /* Склонение. Три устройства, но пять устройств. Правило русского
     счёта короткое, и брать ради него библиотеку незачем, а оставлять
     «5 устройства» на сайте нельзя. */
  function устройств(n) {
    var д = n % 10, дд = n % 100;
    if (дд > 10 && дд < 20) return "устройств";
    if (д === 1) return "устройство";
    if (д >= 2 && д <= 4) return "устройства";
    return "устройств";
  }

  function гнездо(имя) {
    return d.querySelector('[data-заполнить="' + имя + '"]');
  }

  function станции(D) {
    var э = гнездо("станции"); if (!э) return;
    var h = '<ul class="rv-станции">';
    for (var i = 0; i < D["станции"].length; i++) {
      var с = D["станции"][i];
      h += '<li><b>' + эк(с["имя"]) + '</b><span>' + эк(с["нота"]) + '</span></li>';
    }
    h += '</ul><p class="rv-сноска">' + эк(D["станцииОговорка"]) + '</p>';
    э.innerHTML = h;
  }

  function тарифы(D) {
    var э = гнездо("тарифы"); if (!э) return;
    var h = '<div class="rv-доки">';
    for (var i = 0; i < D["тарифы"].length; i++) {
      var т = D["тарифы"][i];
      h += '<div class="rv-док">' +
             '<b>' + эк(т["имя"]) + '</b>' +
             '<i>' + т["устройств"] + " " + устройств(т["устройств"]) + '</i>' +
             '<u>' + деньги(т["цены"]["1"]) + ' в месяц</u>' +
             '<span>' + деньги(т["цены"]["12"]) + ' за год</span>' +
           '</div>';
    }
    h += '</div><p class="rv-сноска">Трафик безлимитный, складывать тарифы ' +
         'можно на любой срок. Первые ' + эк(D["проба"]) + '.</p>';
    э.innerHTML = h;
  }

  function звено(D) {
    var э = гнездо("звено"); if (!э) return;
    var у = D["звено"]["уровни"];
    var h = '<div class="rv-звено">';
    for (var i = 0; i < у.length; i++) {
      h += '<div class="rv-орбита"><b>' + у[i] + ' %</b><i>' +
           (i === 0 ? "с пополнений друга" : (i === 1 ? "с друзей друга" : "третий круг")) +
           '</i></div>';
    }
    h += '</div><p class="rv-сноска">' + эк(D["звено"]["бонус"]) + ', вывод ' +
         эк(D["звено"]["вывод"]) + '. Приглашённому - ' +
         эк(D["звено"]["приглашённому"]) + ': зовёшь не в пустоту.</p>';
    э.innerHTML = h;
  }

  /* Надёжность. Единственное место сайта, где стоят часы и минуты, и
     стоят они намеренно: «мы быстро реагируем» не значит ничего, а
     «сообщили в 17:37, восстановили в 18:46» проверяется по каналу.

     Набрано прозой, а не карточками. Карточки на телефоне съедали два
     экрана и выталкивали призыв за нижнюю кромку, а доказательство
     здесь работает именно как речь: две даты подряд, без оформления. */
  function надёжность(D) {
    var э = гнездо("надёжность"); if (!э) return;
    var а = D["аварии"] || [];
    if (!а.length) return;
    var ф = "";
    for (var i = 0; i < а.length; i++) {
      ф += эк(а[i]["дата"]) + " " + эк(а[i]["что"]) + ": сообщили в " +
           эк(а[i]["сообщили"]) + ", вернули в " +
           эк(а[i]["восстановили"]) + ". ";
    }
    э.innerHTML =
      '<p class="rv-сноска">Когда ломается, чинят в тот же вечер. ' + ф +
        'Это не обещание, а две даты из канала.</p>';
  }

  /* Призыв. Одна кнопка и одна строка под ней, снимающая два возражения
     разом: «сначала деньги» и «а вдруг это не про мою беду».

     Ссылка ведёт в бот из того же файла фактов, что и подвал: адрес бота
     у сервиса один, и разойтись эти два места не должны. */
  function призыв(D) {
    var э = гнездо("призыв"); if (!э) return;
    э.innerHTML =
      '<p><a class="rv-кн rv-кн-гл" href="' + D["связь"]["бот"] +
        '" target="_blank" rel="noopener noreferrer">Забрать ' +
        эк(D["проба"]) + '</a></p>' +
      '<p class="rv-сноска">' + эк(D["выбор"]) + ' пользователей приходят ' +
        'сюда именно за разблокировкой мобильного интернета. Пробный период ' +
        'включается в боте, до всякой оплаты.</p>';
  }

  /* Последнее слово. Сначала интонация сервиса - она у него своя и её
     стоит показать дословно, - потом розыгрыш. Розыгрыш стоит здесь не
     как приманка (он завершён, и обещать новый нельзя), а как единственное
     на сайте доказательство честности, которое можно пересчитать. */
  function итог(D) {
    var э = гнездо("итог"); if (!э) return;
    var р = D["розыгрыш"];
    э.innerHTML =
      '<p class="rv-сноска">Мы все в одной лодке. И даже когда что-то падает, ' +
        'остаются ' + эк(D["запасные"]) + '.</p>' +
      '<p class="rv-сноска">' + эк(р["когда"]) + ' сервис разыграл ' +
        эк(р["фонд"]) + '. Хеш случайного зерна опубликовали до старта, само ' +
        'зерно - после итогов: пересчитать результат мог любой из ' +
        эк(р["участников"]) + ' участников.</p>';
  }

  function технологии(D) {
    var э = гнездо("технологии"); if (!э) return;
    var h = '<ul class="rv-тех">';
    for (var i = 0; i < D["технологии"].length; i++) {
      var т = D["технологии"][i];
      h += '<li><b>' + эк(т["имя"]) + '</b><span>' + эк(т["что"]) + '</span></li>';
    }
    э.innerHTML = h + '</ul>';
  }

  function контакты(D) {
    var э = гнездо("контакты"); if (!э) return;
    var с = D["связь"];
    /* Первая ссылка это кнопка, а не строка: подвал у длинной ленты
       остаётся последним местом, где человек решает, и одинаковые
       ссылки в ряд не дают ему решить ничего.

       noreferrer в придачу к noopener: на ту сторону не должно уехать
       даже имя закрытой страницы, с которой человек ушёл. */
    э.innerHTML =
      '<a class="rv-кн rv-кн-гл" href="' + с["бот"] + '" target="_blank" ' +
        'rel="noopener noreferrer">Забрать ' + эк(D["проба"]) + '</a>' +
      '<a href="' + с["помощь"] + '" target="_blank" rel="noopener noreferrer">Написать в поддержку</a>' +
      '<a href="' + с["канал"] + '" target="_blank" rel="noopener noreferrer">Канал: новости и аварии</a>' +
      '<a href="' + с["партнёрам"] + '" target="_blank" rel="noopener noreferrer">Партнёрам</a>' +
      '<a href="' + с["кабинет"] + '" target="_blank" rel="noopener noreferrer">Личный кабинет</a>';
  }

  /* Адрес кабинета на кнопке входа. Сама кнопка стоит в разметке и
     работает без скрипта - это правильно, за ней приходит платящий
     человек. Здесь адрес только ПОДТВЕРЖДАЕТСЯ из досье, чтобы при
     смене домена правка была одна, а не две. */
  function вход(D) {
    var э = d.getElementById("rvВход");
    var а = D["связь"] && D["связь"]["кабинет"];
    if (э && а) э.setAttribute("href", а);
  }

  function старт() {
    var D = g.RV_DATA;
    if (!D) return;
    станции(D); тарифы(D); звено(D); технологии(D);
    надёжность(D); призыв(D); итог(D); контакты(D); вход(D);
  }

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", старт);
  else старт();
})(window, document);
