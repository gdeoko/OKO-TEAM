/* Rocket VPN. Акт 3 «Прокол» - подпись всего сценария.

   ЗДЕСЬ САЙТ ДЕЛАЕТ ТО, ЧЕГО НЕТ У ROCKET CDN. У CDN движение боковое и
   длинное: ракета идёт по дуге, человек летает между планетами. Здесь
   движение одно - внутрь экрана, рывком. Поэтому в этом акте нет ни
   одного бокового смещения: ни камеры, ни содержимого. Всё, что
   двигается, двигается вдоль оси взгляда. Стоит добавить сюда хоть один
   боковой проезд, и акт перестанет отличаться от родственного сайта.

   ТРИ ЯВЛЕНИЯ ПОДРЯД, И ОНИ РАЗНЫЕ ПО ПРИРОДЕ.
   1. Линза. Полноэкранное искривление: свет за ней ЗАГИБАЕТСЯ к центру,
      а не размывается по краям. Размытие читалось бы как «плохо видно»,
      а нужно «пространство гнётся».
   2. Свёртка стены в кольцо. Стену человек только что разглядывал в акте
      «Периметр», поэтому она обязана быть узнаваемой: та же решётка
      сегментов, просто теперь её стягивает в воронку и закручивает.
      Кольцо в конце свёртки и оказывается входом.
   3. Тоннель. Короткий и очень быстрый. Встречные потоки света вдоль
      стен, ускорение до конца акта, никакой болтанки.

   КАМЕРУ ЭТОТ АКТ НЕ ТРОГАЕТ, И ПРИ ЭТОМ ИМЕННО ЗДЕСЬ ОНА ИДЁТ БЫСТРЕЕ
   ВСЕГО. Камера в этом мире одна на весь сайт, и ведёт её ядро по общей
   кривой (см. rv-world.js). Акт только объявляет свою позу, а в ней
   сказано главное: уход камеры за станцию на сорок шесть единиц, то
   есть ВНУТРЬ трубы. Ось тоннеля смотрит точно на следующую станцию,
   поэтому перегон от прокола к выходу человек проходит внутри тоннеля,
   а не мимо него.

   Содержимое при этом продолжает идти навстречу: кольцо надвигается и
   уходит за спину, поток разгоняется. Ход камеры и ход содержимого
   складываются, и это единственное место сайта, где они складываются
   намеренно.

   Ступень качества меняет густоту сетки стены, число граней тоннеля и
   размер мишени линзы. Ни линза, ни свёртка, ни тоннель не отключаются
   ни на одной ступени: на слабом устройстве прокол становится проще, но
   он остаётся проколом. */
(function (g, d) {
  "use strict";

  var М = {};
  var W = null;
  var собрано = false;

  function зажать(v, a, b) { return v < a ? a : (v > b ? b : v); }

  function мягко(край0, край1, v) {
    var t = зажать((v - край0) / (край1 - край0), 0, 1);
    return t * t * (3 - 2 * t);
  }

  /* ── Шейдеры ──────────────────────────────────────────────────
     Имена внутри GLSL латиницей: не-ASCII идентификатор часть драйверов
     не соберёт, и акт станет чёрным пятном. Объяснения - в JS. */

  /* Свёртка. Стена переводится в полярные координаты и стягивается к
     кольцу радиуса uRing. Одновременно центр уходит от камеры: без этого
     ухода стена сворачивается в блин, а нам нужна воронка, в которую
     можно войти.

     ПОЧЕМУ СЕТКА КОЛЬЦЕВАЯ, А НЕ ПРЯМОУГОЛЬНАЯ. Плоскость при свёртке
     вырождается в своём центре: вершина, стоявшая на нуле, обязана
     уехать на радиус кольца, и треугольники вокруг неё растягиваются в
     кашу. На снимке это выглядело как мутное пятно вместо входа. У
     кольцевой сетки центра нет вовсе, поэтому вырождаться нечему. */
  var В_СТЕНА = [
    "uniform float uFold;",
    "uniform float uRing;",
    "varying vec2 vUv;",
    "varying vec2 vP;",
    "varying float vR;",
    "varying float vA;",
    "void main(){",
    "  vUv = uv;",
    "  vP = position.xy;",
    "  vec3 p = position;",
    "  float r = length(p.xy);",
    "  float a = atan(p.y, p.x);",
    "  float t = clamp(r / 26.0, 0.0, 1.0);",
    /* Сжатие к кольцу неполное намеренно. Стянуть всё в узкий обод
       значит положить десяток рядов решётки на несколько пикселей: они
       сольются в мутную полосу, и вход перестанет читаться входом. */
    "  float rr = mix(r, uRing + (r - uRing) * 0.30, uFold);",
    "  a += uFold * 1.7 * (1.0 - t);",
    "  float z = -uFold * 15.0 * (1.0 - t) * (1.0 - t);",
    "  p.x = cos(a) * rr;",
    "  p.y = sin(a) * rr;",
    "  p.z = z;",
    "  vR = rr;",
    "  vA = a * 0.15915 + 0.5;",
    "  gl_Position = projectionMatrix * modelViewMatrix * vec4(p, 1.0);",
    "}"
  ].join("\n");

  /* Решётка обязана быть узнаваемой: это та же стена, что человек
     разглядывал в акте «Периметр». Поэтому ячеек немного, линии толстые,
     а на пересечениях стоят узлы - без них решётка читается как
     миллиметровка, а не как блокпост. */
  var Ф_СТЕНА = [
    "uniform float uFold;",
    "uniform float uRing;",
    "uniform float uBright;",
    "uniform vec3 uIndigo;",
    "uniform vec3 uGlow;",
    "varying vec2 vUv;",
    "varying vec2 vP;",
    "varying float vR;",
    "varying float vA;",
    "void main(){",
    /* Пока стена стоит стеной, её решётка считается по мировым
       координатам, а не по uv кольца: иначе клетка расходилась бы
       веером от центра и стена сразу выдавала бы, что она круглая. */
    "  vec2 cell = abs(fract(vP / 3.0) - 0.5) * 2.0;",
    "  float line = 1.0 - smoothstep(0.02, 0.12, min(cell.x, cell.y));",
    "  float node = 1.0 - smoothstep(0.06, 0.26, length(cell));",
    "  float grid0 = line * 0.6 + node * 0.7;",
    /* Свёрнутая стена рисуется не той же решёткой, а спицами и кольцами.
       Прямоугольная клетка, натянутая на воронку, даёт муар и слипается
       у горловины; спицы с кольцами держат ту же плотность и остаются
       читаемыми до самого центра. */
    "  float sp = 1.0 - smoothstep(0.02, 0.16, abs(fract(vA * 30.0) - 0.5) * 2.0);",
    "  float rg = 1.0 - smoothstep(0.02, 0.18, abs(fract(vR * 0.55) - 0.5) * 2.0);",
    "  float fold = sp * 0.55 + rg * 0.75;",
    "  float grid = mix(grid0, fold, uFold);",
    "  float rim = exp(-pow((vR - uRing) * 0.60, 2.0)) * uFold;",
    "  vec3 c = uIndigo * grid * 1.0 * (0.7 + uFold * 0.7) + uGlow * rim * 1.0;",
    "  float a = (grid * 0.5 + rim * 0.8) * uBright;",
    "  gl_FragColor = vec4(c, clamp(a, 0.0, 1.0));",
    "}"
  ].join("\n");

  /* Линза. Смещение выборки направлено к центру и обратно пропорционально
     расстоянию: это и есть загиб света, а не размытие. Кольцо на
     фиксированном радиусе - тот самый ободок, по которому гравитационную
     линзу узнают. */
  var В_ЭКРАН = [
    "varying vec2 vUv;",
    "void main(){ vUv = uv; gl_Position = projectionMatrix * modelViewMatrix * vec4(position,1.0); }"
  ].join("\n");

  var Ф_ЛИНЗА = [
    "uniform sampler2D uFrame;",
    "uniform vec2 uRes;",
    "uniform float uPow;",
    "uniform float uAspect;",
    "uniform float uRich;",
    "uniform vec3 uGlow;",
    "void main(){",
    "  vec2 uv = gl_FragCoord.xy / uRes;",
    "  vec2 dv = (uv - 0.5) * vec2(uAspect, 1.0);",
    "  float r = length(dv) + 0.05;",
    /* Смещение ограничено сверху. Без потолка выборка у самого центра
       уезжает на пол-экрана, и вместо загиба света получается каша, в
       которой не читается ни стена, ни кольцо. */
    "  float bend = min(uPow * 0.05 / r, 0.085);",
    "  vec2 off = -normalize(dv) * bend;",
    "  vec4 s = texture2D(uFrame, uv + off);",
    "  vec3 c = s.rgb;",
    "  if (uRich > 0.5) {",
    "    c.r = texture2D(uFrame, uv + off * 1.03).r;",
    "    c.b = texture2D(uFrame, uv + off * 0.97).b;",
    "  }",
    "  float ring = exp(-pow((r - 0.22) * 11.0, 2.0)) * uPow;",
    "  c += uGlow * ring * 0.45;",
    "  float a = clamp(max(max(c.r, c.g), c.b) * 2.4 + ring * 0.5, 0.0, 1.0);",
    "  gl_FragColor = vec4(c, a);",
    "}"
  ].join("\n");

  /* Тоннель. Потоки идут НА камеру: время прибавляется к продольной
     координате, и полосы съезжают в сторону зрителя. Метки скорости -
     редкие короткие штрихи, которые ярче остальных: без них поток
     читается как обои, а не как скорость. */
  var Ф_ТОННЕЛЬ = [
    "uniform float uRun;",
    "uniform float uBright;",
    "uniform vec3 uIndigo;",
    "uniform vec3 uGlow;",
    "varying vec2 vUv;",
    "float noi(vec2 p){ return fract(sin(dot(p, vec2(13.71, 7.13))) * 43758.5453); }",
    "void main(){",
    "  float lane = floor(vUv.x * 44.0);",
    "  float seed = noi(vec2(lane, 3.0));",
    "  float v = vUv.y * 16.0 + uRun * (0.65 + seed * 0.7);",
    "  float cell = floor(v);",
    "  float f = fract(v);",
    "  float k = noi(vec2(lane, cell));",
    "  float len = 0.16 + k * 0.55;",
    "  float streak = 1.0 - smoothstep(0.0, len, f);",
    "  streak *= step(0.30, k);",
    "  float mark = step(0.92, k);",
    "  float inl = 1.0 - smoothstep(0.0, 0.5, abs(fract(vUv.x * 44.0) - 0.5) * 2.0);",
    /* Кольца - это и есть стены тоннеля. Без них поток читается как
       звёздный разлёт, то есть как полёт в пустоте, а нам нужна труба,
       у которой видно обшивку. */
    "  float rw = fract(vUv.y * 9.0 + uRun * 0.07);",
    "  float ring = pow(1.0 - abs(rw - 0.5) * 2.0, 14.0);",
    "  float depth = smoothstep(0.0, 0.22, vUv.y) * (1.0 - smoothstep(0.90, 1.0, vUv.y));",
    "  float i = (streak * inl * (0.5 + k * 1.1 + mark * 2.0) + ring * 0.45) * depth;",
    "  vec3 c = mix(uIndigo, uGlow, min(1.0, k * 0.8 + mark));",
    "  gl_FragColor = vec4(c * i * uBright * 1.8, clamp(i * uBright * 1.4, 0.0, 1.0));",
    "}"
  ].join("\n");

  /* Вспышка входа и дальний зрачок тоннеля - один и тот же простой
     радиальный градиент, разной жёсткости. */
  var Ф_ПЯТНО = [
    "uniform vec3 uCol;",
    "uniform float uBright;",
    "uniform float uHard;",
    "uniform float uCore;",
    "varying vec2 vUv;",
    "void main(){",
    "  float dd = length(vUv - 0.5) * 2.0;",
    "  float base = max(0.0, 1.0 - dd);",
    "  float a = pow(base, uHard);",
    /* Белое ядро внутри цветного гало. Без него вспышка читается как
       мягкая подсветка, а на входе в прокол нужен удар. */
    "  vec3 c = uCol + vec3(1.0) * pow(base, 6.0) * uCore;",
    "  gl_FragColor = vec4(c, clamp(a * uBright, 0.0, 1.0));",
    "}"
  ].join("\n");

  /* ── Сборка ───────────────────────────────────────────────────*/
  function построить(мир) {
    if (собрано) return true;
    W = мир || W;
    if (!W || !W.T || !W.scene || !W.r) return false;
    var T = W.T;

    М.корень = new T.Group();
    М.корень.visible = false;
    /* Гнездо станции вместо сцены: содержимое акта стоит в своей точке
       мира, а не возле начала координат вместе со всеми. Ось -Z гнезда
       смотрит от камеры вглубь, и тоннель, уходящий по ней, оказывается
       ровно тем коридором, по которому камера летит к следующей
       станции. Это не совпадение, это и есть замысел: перегон от
       прокола к выходу проходит ВНУТРИ тоннеля. */
    var гн = g.RV_WORLD && g.RV_WORLD["гнездо"] ? g.RV_WORLD["гнездо"]("прокол") : null;
    (гн || W.scene).add(М.корень);

    var цИндиго = new T.Color(0x3048A8);
    var цПерелив = new T.Color(0x6078D8);
    var цСвет = new T.Color(0x8A9CFF);

    /* ── Стена периметра ────────────────────────────────────────
       Сегментов по кругу много: свёртка идёт в вершинном шейдере, и на
       редкой сетке кольцо получилось бы многоугольником. Это отделка,
       поэтому на слабой ступени сетка реже, но сама стена и её свёртка
       есть везде. Внутренний радиус ненулевой - см. пояснение к В_СТЕНА. */
    var сег = W.ступень === 0 ? [72, 22] : (W.ступень === 1 ? [128, 40] : [200, 60]);
    М.мСтена = new T.ShaderMaterial({
      uniforms: {
        uFold: { value: 0 },
        uRing: { value: 4.8 },
        uBright: { value: 1 },
        uIndigo: { value: цИндиго },
        uGlow: { value: цСвет }
      },
      vertexShader: В_СТЕНА, fragmentShader: Ф_СТЕНА,
      transparent: true, depthWrite: false, side: T.DoubleSide,
      blending: T.AdditiveBlending
    });
    М.стена = new T.Mesh(new T.RingGeometry(0.9, 26, сег[0], сег[1]), М.мСтена);
    М.стена.position.z = -6;
    М.стена.renderOrder = 1;
    М.корень.add(М.стена);

    /* ── Тоннель ────────────────────────────────────────────────
       Цилиндр развёрнут осью вдоль взгляда и смотрит внутрь. Длина
       большая не ради красоты: короткая труба выдаёт свой дальний край,
       и «очень быстро» превращается в «быстро и приехали». */
    var граней = W.ступень === 0 ? 24 : (W.ступень === 1 ? 40 : 64);
    М.мТоннель = new T.ShaderMaterial({
      uniforms: {
        uRun: { value: 0 },
        uBright: { value: 0 },
        uIndigo: { value: цИндиго },
        uGlow: { value: цСвет }
      },
      vertexShader: В_ЭКРАН, fragmentShader: Ф_ТОННЕЛЬ,
      transparent: true, depthWrite: false, side: T.BackSide,
      blending: T.AdditiveBlending
    });
    /* Ось трубы кладём В САМУ СЕТКУ, а не в поворот узла. Узлу поворот
       нужен свободным: труба разворачивается на камеру каждым кадром
       (см. ниже), а lookAt переписывает поворот целиком и заодно стёр
       бы этот прямой угол. */
    var гТоннель = new T.CylinderGeometry(3.6, 3.6, 220, граней, 1, true);
    гТоннель.rotateX(1.5708);
    М.тоннель = new T.Mesh(гТоннель, М.мТоннель);
    М.тоннель.position.z = -100;
    М.тоннель.renderOrder = 2;
    М.тоннель.visible = false;
    М.корень.add(М.тоннель);

    /* Дальний зрачок: точка, к которой идёт тоннель. Он не приближается -
       к нему идут вечно, и именно это читается как «насквозь», а не
       «доехали». */
    М.зрачок = new T.Mesh(
      new T.PlaneGeometry(6, 6),
      new T.ShaderMaterial({
        uniforms: { uCol: { value: цПерелив }, uBright: { value: 0 }, uHard: { value: 3.0 }, uCore: { value: 0.6 } },
        vertexShader: В_ЭКРАН, fragmentShader: Ф_ПЯТНО,
        transparent: true, depthWrite: false, blending: T.AdditiveBlending
      })
    );
    М.зрачок.position.z = -196;
    /* Черновики для перевода в местные единицы гнезда. Заводим один
       раз: новый вектор на каждом кадре это шестьдесят мусорных
       объектов в секунду. */
    М.лок = new T.Vector3();
    М.впер = new T.Vector3();
    М.точка = new T.Vector3();
    М.зрачок.renderOrder = 2;
    М.корень.add(М.зрачок);

    /* ── Пакет человека ─────────────────────────────────────────
       Его втягивает в кольцо. Он и есть тот, кого протаскивают сквозь
       прокол, поэтому он уходит вглубь раньше стен. */
    М.свой = new T.Mesh(
      new T.SphereGeometry(0.20, W.ступень === 0 ? 12 : 20, W.ступень === 0 ? 8 : 14),
      new T.MeshBasicMaterial({ color: цСвет, transparent: true })
    );
    М.свой.renderOrder = 3;
    М.корень.add(М.свой);

    М.свойОреол = new T.Mesh(
      new T.PlaneGeometry(1.7, 1.7),
      new T.ShaderMaterial({
        uniforms: { uCol: { value: цСвет }, uBright: { value: 0.3 }, uHard: { value: 3.0 }, uCore: { value: 0.0 } },
        vertexShader: В_ЭКРАН, fragmentShader: Ф_ПЯТНО,
        transparent: true, depthWrite: false, blending: T.AdditiveBlending
      })
    );
    М.свойОреол.renderOrder = 3;
    М.корень.add(М.свойОреол);

    /* ── Вспышка входа ──────────────────────────────────────────
       Одна на весь акт. Вспышек больше одной превратили бы прокол в
       мигание, а по сценарию за вспышкой идёт тишина и скорость. */
    М.вспышка = new T.Mesh(
      new T.PlaneGeometry(2, 2),
      new T.ShaderMaterial({
        uniforms: { uCol: { value: цСвет }, uBright: { value: 0 }, uHard: { value: 1.1 }, uCore: { value: 1.4 } },
        vertexShader: В_ЭКРАН, fragmentShader: Ф_ПЯТНО,
        transparent: true, depthWrite: false, depthTest: false,
        blending: T.AdditiveBlending
      })
    );
    М.вспышка.renderOrder = 950;
    М.вспышка.visible = false;
    /* Полноэкранные слои висят НА КАМЕРЕ, а не в сцене. Раньше они
       стояли в мировых координатах на z = 11.2 и держались перед
       объективом только потому, что камера стояла в нуле на z = 12.
       Камера теперь едет через весь сайт, и это перестало быть правдой
       в тот же кадр, в котором она тронулась. Подвес на камеру решает
       это раз и навсегда: слой перед объективом при любой позе. */
    if (g.RV_WORLD && g.RV_WORLD["наКамеру"]) g.RV_WORLD["наКамеру"](М.вспышка, 0.8);
    else { М.вспышка.position.z = 11.2; W.scene.add(М.вспышка); }

    /* ── Линза ──────────────────────────────────────────────────
       Квад стоит вплотную к камере и рисуется последним поверх всего.
       Пока линза работает, содержимое акта уходит в мишень и на экран
       попадает только через неё - иначе картинка удвоится. */
    М.доляМишени = W.ступень === 0 ? 0.45 : (W.ступень === 1 ? 0.6 : 0.7);
    М.мишень = new T.WebGLRenderTarget(2, 2, {
      minFilter: T.LinearFilter, magFilter: T.LinearFilter
    });
    М.мЛинза = new T.ShaderMaterial({
      uniforms: {
        uFrame: { value: М.мишень.texture },
        uRes: { value: new T.Vector2(2, 2) },
        uPow: { value: 0 },
        uAspect: { value: 1.6 },
        uRich: { value: W.ступень === 0 ? 0 : 1 },
        uGlow: { value: цСвет }
      },
      vertexShader: В_ЭКРАН, fragmentShader: Ф_ЛИНЗА,
      transparent: true, depthWrite: false, depthTest: false
    });
    М.линза = new T.Mesh(new T.PlaneGeometry(2, 2), М.мЛинза);
    М.линза.renderOrder = 900;
    М.линза.visible = false;
    if (g.RV_WORLD && g.RV_WORLD["наКамеру"]) g.RV_WORLD["наКамеру"](М.линза, 1.0);
    else { М.линза.position.z = 11.0; W.scene.add(М.линза); }

    М.бег = 0;
    собрано = true;
    размерить(g.innerWidth, g.innerHeight);
    return true;
  }

  /* ── Полноэкранные слои ───────────────────────────────────────
     Размер считается КАЖДЫЙ кадр, а не на смену размера окна. Причина:
     угол обзора камеры теперь ведёт ядро, и на проколе он сужается
     (это и есть ощущение ускорения). Слой, посчитанный один раз, при
     сужении угла перестал бы закрывать кадр, и по краям появилась бы
     нетронутая полоса сцены. */
  function слоиПоКадру(w, h) {
    if (!собрано || !W) return;
    var выс = 2 * Math.tan(W.cam.fov * Math.PI / 360);
    var шир = выс * (w / h);
    М.линза.scale.set(шир / 2 * 1.06, выс / 2 * 1.06, 1);
    /* Вспышка стоит ближе линзы, поэтому её запас больше: тот же
       множитель на меньшем расстоянии закрыл бы меньшую долю кадра. */
    М.вспышка.scale.set(шир / 2 * 1.2, выс / 2 * 1.2, 1);
  }

  /* ── Размер ───────────────────────────────────────────────────*/
  function размерить(w, h) {
    if (!собрано || !W) return;
    var T = W.T;
    слоиПоКадру(w, h);

    var р = W.r.getDrawingBufferSize(new T.Vector2());
    М.мЛинза.uniforms.uRes.value.set(Math.max(2, р.x), Math.max(2, р.y));
    М.мЛинза.uniforms.uAspect.value = w / h;
    М.мишень.setSize(
      Math.max(2, Math.round(р.x * М.доляМишени)),
      Math.max(2, Math.round(р.y * М.доляМишени))
    );

    /* На узком экране кольцо входа не помещается по ширине, и человек
       видит не вход, а обрезанную дугу. Уменьшаем всю сцену акта, а не
       двигаем её вбок: боковых смещений в этом акте нет. */
    var к = w < 760 ? 0.62 : 1.0;
    М.стена.scale.setScalar(к);
    М.мСтена.uniforms.uRing.value = w < 760 ? 3.0 : 4.8;
  }

  /* ── Кадр ─────────────────────────────────────────────────────*/
  function кадр(доля, dt, часы) {
    if (!собрано && !построить(g.RV_WORLD ? g.RV_WORLD["мир"]() : null)) return;

    слоиПоКадру(g.innerWidth, g.innerHeight);

    /* Три фазы. Границы намеренно ранние: по сценарию прокол короткий,
       и больше половины акта человек уже летит внутри. */
    var свёртка = мягко(0.00, 0.34, доля);
    var вход = мягко(0.28, 0.46, доля);
    /* Труба гаснет к концу акта, и это не отделка.

       С тех пор как она едет за камерой, у неё нет своего края - в этом
       и был смысл правки. Но камера после прокола идёт к станции
       выхода, а секция акта уходит из окна не мгновенно, и трубу стало
       видно В СЛЕДУЮЩЕМ АКТЕ: белые росчерки летели сквозь планету и
       ложились прямо под заголовок «С той стороны сеть снова открыта».
       Замер контраста поймал это числом - 1,55 при пороге 3.

       Гасим в последней десятой хода: прокол к этому моменту уже
       рассказан, а следующий акт ещё не начался. */
    var полёт = мягко(0.40, 0.62, доля) * (1 - мягко(0.90, 1.00, доля));

    /* 1. Стена сворачивается и одновременно надвигается: кольцо должно
       пройти мимо зрителя, а не остаться висеть вдалеке. */
    М.мСтена.uniforms.uFold.value = свёртка;
    М.мСтена.uniforms.uBright.value = 1 - мягко(0.42, 0.56, доля);
    М.стена.position.z = -6 + вход * 15;
    М.стена.visible = М.мСтена.uniforms.uBright.value > 0.01;
    /* Кольцо медленно проворачивается вокруг оси взгляда. Это
       единственное вращение в акте, и оно продольное: боковых движений
       здесь нет ни одного. */
    М.стена.rotation.z = свёртка * 0.5 + часы * 0.05 * свёртка;

    /* 2. Пакет человека втягивает внутрь раньше, чем дойдут стены. */
    var тяга = мягко(0.10, 0.44, доля);
    М.свой.position.set(0, 0, 2.0 - тяга * 24);
    /* Втянутый пакет гаснет, а не улетает точкой: точка под линзой
       размазывается в цветные дуги и читается как сбой картинки. */
    М.свой.material.opacity = (1 - тяга) * (1 - тяга);
    М.свой.visible = тяга < 0.97;
    М.свойОреол.position.copy(М.свой.position);
    М.свойОреол.visible = М.свой.visible;
    М.свойОреол.material.uniforms.uBright.value = 0.30 * (1 - тяга) * (1 - тяга);

    /* 3. Вспышка на входе. Короткая: подъём быстрый, спад чуть длиннее,
       чтобы за ней читалась тишина, а не обрыв. */
    /* Вспышка укорочена и приглушена по замеру, а не на глаз. Замер
       яркости кадра по всей длине акта дал пик на доле 0.45: средняя
       яркость 134.8 из 255 при 9-33 на всех прочих долях, и контраст
       абзаца к фону под ним падал до 1.12 при пороге 4.5 - то есть
       текст в этот момент не читался вовсе.

       Окно сужено (0.41-0.46 против 0.38-0.55) и сила снижена вдвое:
       вспышка остаётся ударом, но перестаёт быть белым листом. Сам
       текст в этот миг уводится оформлением - ему в момент прокола
       делать нечего, и это не костыль, а часть сцены. */
    var вс = мягко(0.41, 0.445, доля) * (1 - мягко(0.445, 0.49, доля));
    М.вспышка.visible = вс > 0.004;
    М.вспышка.material.uniforms.uBright.value = вс * 0.62;

    /* 4. Тоннель. Скорость растёт до самого конца акта: замедление в
       конце прочиталось бы как «приехали», а прокол не имеет остановки
       внутри себя. */
    var скорость = 3 + полёт * 46;
    М.бег += dt * скорость;
    М.мТоннель.uniforms.uRun.value = М.бег;
    М.мТоннель.uniforms.uBright.value = полёт;
    М.тоннель.visible = полёт > 0.01;
    М.зрачок.material.uniforms.uBright.value = полёт * 0.55;

    /* ТОННЕЛЬ ЕДЕТ ЗА КАМЕРОЙ, а не стоит в своей точке гнезда.

       Стоял он там ровно до восьми десятых своей длины. Труба длиной
       220 единиц, камера идёт от подхода к следующей станции и на
       шести с половиной десятых акта ВЫХОДИТ ЗА ЕЁ ДАЛЬНИЙ КРАЙ. С
       этого места и до конца акта человек видел чёрный экран.

       Замер яркости кадра это показал числом: на доле 0.62 средняя
       яркость 20 и яркими заняты 17 процентов кадра, на 0.70 средняя
       0.33 и ярких 0.01 процента. То есть последняя треть ГЛАВНОГО
       акта сайта была пустой. На снимках это чёрное поле справа от
       заголовка «Не в обход. Насквозь».

       Удлинять трубу бессмысленно: любая конечная длина кончится, а
       обещание сценария - идти насквозь, а не доехать до края. Держим
       камеру на постоянном месте внутри трубы: сто единиц впереди,
       сто десять позади. Коридор становится бесконечным по построению,
       и «приехали» в нём не наступает никогда.

       Бег текстуры при этом НЕ трогаем: он и есть ощущение скорости, и
       он идёт от времени, а не от места. */
    if (М.тоннель.visible && W.cam) {
      /* Труба садится НА ВЗГЛЯД камеры: центр в ста единицах впереди,
         ось развёрнута вдоль направления взгляда. Пришпилить её только
         по месту было мало - камера на перегоне доворачивается к
         следующей станции, и труба, стоящая по оси гнезда, уходила из
         кадра вбок. Замер: на доле 0.62 яркими занято 17 процентов
         кадра, на 0.70 - одна сотая процента при живом и ярком
         тоннеле. То есть он честно рисовался мимо экрана. */
      W.cam.getWorldDirection(М.впер);
      М.точка.copy(W.cam.position).addScaledVector(М.впер, 100);
      М.корень.worldToLocal(М.точка);
      М.тоннель.position.copy(М.точка);
      /* Смотрит труба НА камеру: её собственная ось +Z в этом случае
         направлена назад по взгляду, а дальний край - вперёд. Именно в
         этой раскладке начало развёртки лежит на дальнем крае, и
         затухание в шейдере растворяет даль, а не ближний край. */
      М.тоннель.lookAt(W.cam.position);

      /* Зрачок держится на постоянном выносе впереди и повёрнут к
         человеку. Он не приближается никогда, и в этом весь его смысл:
         к нему идут, а не доезжают. */
      М.точка.copy(W.cam.position).addScaledVector(М.впер, 196);
      М.корень.worldToLocal(М.точка);
      М.зрачок.position.copy(М.точка);
      М.зрачок.lookAt(W.cam.position);
    }

    /* 5. Линза. Работает только на свёртке и входе: дальше пространство
        уже сложено, гнуть больше нечего. */
    var силаЛинзы = свёртка * (1 - мягко(0.33, 0.42, доля));
    var линзаЖива = силаЛинзы > 0.012;
    М.мЛинза.uniforms.uPow.value = силаЛинзы;

    if (линзаЖива) {
      /* Содержимое акта уходит в мишень, а на экран попадает только квад
         линзы. Порядок именно такой: сначала снимок без квада, потом
         показ квада вместо содержимого.

         Корень обязательно возвращается в кадр ПЕРЕД снимком. Он был
         спрятан в конце прошлого кадра, и без этой строки в мишень
         попадает пустая сцена: линза честно показывает пустоту, а на
         экране остаётся мутное пятно вместо свёртки. Ровно это и было
         поймано снимком. */
      М.корень.visible = true;
      М.линза.visible = false;
      М.вспышка.visible = false;
      var прежняя = W.r.getRenderTarget();
      W.r.setRenderTarget(М.мишень);
      W.r.render(W.scene, W.cam);
      W.r.setRenderTarget(прежняя);
      М.корень.visible = false;
      М.линза.visible = true;
      М.вспышка.visible = вс > 0.004;
    } else {
      М.линза.visible = false;
      М.корень.visible = true;
    }
  }

  /* ── Договор с ядром ──────────────────────────────────────────*/
  var МОДУЛЬ = {
    "собрать": function (мир) { построить(мир); },
    "показать": function (да) {
      if (да && !собрано) построить(g.RV_WORLD ? g.RV_WORLD["мир"]() : null);
      if (!собрано) return;
      М.корень.visible = !!да;
      /* Полноэкранные квады живут вне корня акта: они рисуются поверх
         всего и обязаны исчезать вместе с актом, иначе линза останется
         висеть над соседним. */
      if (!да) { М.линза.visible = false; М.вспышка.visible = false; }
    },
    "кадр": кадр,
    "размер": function (w, h) { размерить(w, h); }
  };

  function встать() {
    if (!g.RV_WORLD) return;
    /* ПОЗА АКТА. Станция прокола стоит в ста семидесяти единицах вглубь
       от оболочки и заметно вбок: перегон между ними обязан читаться
       ходом, а не наездом по прямой.

       Разворот станции подобран так, чтобы ось тоннеля смотрела точно
       на следующую станцию («Выход»). Тоннель длиной в двести двадцать
       единиц перекрывает больше половины перегона, и человек проходит
       этот перегон ВНУТРИ него. Это и есть обещание сценария: не обход,
       а насквозь.

       Уход минус сорок шесть - единственное место на сайте, где камера
       уходит ЗА свою станцию. Кольцо входа проходит мимо неё примерно
       на четырёх десятых акта, и дальше камера уже в трубе.

       Поле зрения сужается с пятидесяти до тридцати четырёх. Сужение
       угла на ходу читается как разгон: края кадра перестают отдавать
       обзор и начинают тянуться навстречу. Крен растёт к тому же
       концу - вращение вокруг оси взгляда есть только здесь. */
    g.RV_WORLD["поза"]("прокол", {
      "на": [-34, 12, -170],
      "от": [-36.4, 13.02, -158.29],
      "подход": 4,
      "уход": -46,
      "поле": [50, 42, 34],
      /* Вбок ноль. Сценарий это запрещает прямо: «камера идёт строго
         вглубь, ни одного бокового движения». Прокол - единственное
         место сайта, где боковой ход был бы прямым враньём. */
      "бок": [0, 0, 0],
      "крен": [0.06, 0.14, 0.30]
    });
    g.RV_WORLD["акт"]("прокол", МОДУЛЬ);
    /* Пульс акта для живых проверок. Снимок чёрного кадра не говорит,
       ПОЧЕМУ он чёрный: акт спрятан, тоннель невидим или камера вне
       трубы. Числа говорят. */
    g.RV_ПРОКОЛ_ПУЛЬС = function () {
      if (!собрано) return { "собрано": 0 };
      return {
        "собрано": 1,
        "виденКорень": !!М.корень.visible,
        "виденТоннель": !!М.тоннель.visible,
        "яркостьТоннеля": +М.мТоннель.uniforms.uBright.value.toFixed(3),
        "zТоннеля": +М.тоннель.position.z.toFixed(1),
        "виденВМире": !!(g.RV_WORLD["акты"] && g.RV_WORLD["акты"]()["прокол"])
      };
    };
  }

  if (g.RV_WORLD && g.RV_WORLD["готов"] && g.RV_WORLD["готов"]()) встать();
  else g.addEventListener("rv:мир", встать);
})(window, document);
