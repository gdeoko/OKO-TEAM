/* Rocket VPN. Живое звёздное поле: один космос от дома до тоннеля.

   ЗАЧЕМ ЭТО ЗАВЕДЕНО. Небо сайта было ОДНОЙ печатной панорамой на
   сфере: облака газа, полоса млечного пути и звёзды, нарисованные
   прямо в текстуру. Панорама натянута на сферу радиусом 1800, и в
   кадр при поле зрения около пятидесяти градусов попадает малая её
   доля: каждый напечатанный тексель растягивается на экране в
   несколько пикселей. Звезда в один-два текселя превращается в мягкий
   квадрат, а яркое пятно газа в большое размытое кольцо.

   Владелец увидел ровно это и описал точно: «до того как стена
   сломалась на фоне нету этого чёрного кольца со звёздами, а как
   сломалась из ниоткуда появляется». Кольцо никуда не появлялось: это
   напечатанное на панораме сгущение млечного пути, и оно вплывает в
   кадр, когда камера после слома стены поворачивается. Пятно стоит на
   месте, поворачивается взгляд.

   Лечится это тем же способом, которым лечили небо игры: звёзды
   перестают быть картинкой и становятся ТОЧКАМИ В ПРОСТРАНСТВЕ. Точка
   рисуется в свой размер в пикселях при любом разрешении, значит она
   остаётся точкой и на телефоне, и на мониторе, и не размывается
   растяжкой никогда.

   ПОЧЕМУ РАЗМЕР В ПИКСЕЛЯХ, А НЕ В ЕДИНИЦАХ МИРА. У обычной точки
   three размер задан в мире и делится на расстояние: ближняя звезда
   раздувается в белую кляксу, дальняя пропадает совсем. Это и было
   главной причиной «белых полупрозрачных пятен» в игре. Здесь
   sizeAttenuation выключен, размер считается в точках БУФЕРА и
   умножается на плотность рендерера, а не экрана: буфер рисуется с
   поджатой плотностью, и звезда, посчитанная по экранным трём,
   вышла бы втрое крупнее задуманного.

   ПОЧЕМУ ТРЕТЬ ЗВЁЗД СОБРАНА К ПЛОСКОСТИ. Млечный путь это прежде
   всего СГУЩЕНИЕ, звёзд там на порядок больше на ту же площадь, и
   именно поэтому он читается рекой. Прибавка к яркости без прибавки
   к числу даёт светлое место, а не полосу.

   Числа, распределения и шейдер сняты с поля игры (rc-flight.js,
   starMats) и намеренно не переизобретались: небо у двух проектов
   обязано быть одним и тем же, иначе человек, прошедший из сайта в
   игру, увидит смену вселенной на ровном месте.

   API:
     RV_ЗВЁЗДЫ.собрать(мир)      построить поле и положить в сцену
     RV_ЗВЁЗДЫ.кадр(часы)        вести за камерой, мерцание
     RV_ЗВЁЗДЫ.плотность()       пересчитать размер под новую плотность
     RV_ЗВЁЗДЫ.видно(да)         показать или убрать
     RV_ЗВЁЗДЫ.замер()           сколько звёзд, какого размера */
(function (g) {
  "use strict";

  var W = null, T = null;
  var группа = null, поле = null, мат = null, уни = null;
  var собрано = false;
  var место = null;

  /* Доли спектральных классов для ВИДИМОГО неба, а не для всех звёзд
     подряд: глазом видны горячие и яркие, поэтому голубых и белых
     среди них заметно больше, чем в галактике. Температуры настоящие
     границы классов. Таблица та же, что в игре: разойтись они не
     должны. */
  var КЛАССЫ = [
    [0.10, 11000, 26000, 0],   /* O и B, голубовато-белые */
    [0.22, 7600, 11000, 0],    /* A, белые с голубизной */
    [0.24, 6100, 7600, 1],     /* F, белые тёплые */
    [0.20, 5300, 6100, 1],     /* G, жёлтые, как наше Солнце */
    [0.17, 3900, 5300, 2],     /* K, оранжевые */
    [0.07, 2600, 3900, 2]      /* M, красные */
  ];

  /* Цвет по температуре, приближение Планка. Нормируем по самому
     яркому каналу: яркость несёт величина, а тройка отвечает только
     за оттенок. Без этого красные карлики выходили бы темнее
     положенного дважды, и по величине, и по цвету. */
  function планк(K) {
    var t = K / 100, r, gg, b;
    if (t <= 66) r = 255;
    else r = 329.698727446 * Math.pow(t - 60, -0.1332047592);
    if (t <= 66) gg = 99.4708025861 * Math.log(t) - 161.1195681661;
    else gg = 288.1221695283 * Math.pow(t - 60, -0.0755148492);
    if (t >= 66) b = 255;
    else if (t <= 19) b = 0;
    else b = 138.5177312231 * Math.log(t - 10) - 305.0447927307;
    r = Math.max(0, Math.min(255, r));
    gg = Math.max(0, Math.min(255, gg));
    b = Math.max(0, Math.min(255, b));
    var м = Math.max(r, Math.max(gg, b)) || 1;
    return [r / м, gg / м, b / м];
  }

  /* Своя случайность, а не Math.random: небо обязано быть одним и тем
     же при каждом заходе, иначе снимок ленты нельзя сравнить со
     вчерашним, и приёмка по кадрам перестаёт работать. */
  function поток(сид) {
    var с = сид >>> 0;
    return function () {
      с ^= с << 13; с >>>= 0;
      с ^= с >>> 17;
      с ^= с << 5;  с >>>= 0;
      return с / 4294967296;
    };
  }

  function плотностьРендерера() {
    var п = 1;
    try { п = W.r.getPixelRatio(); } catch (e) { п = g.devicePixelRatio || 1; }
    if (!(п > 0)) п = 1;
    return Math.min(2, п);
  }

  /* Сколько звёзд. Поле разложено по полной сфере, это 12.57
     стерадиана; в кадр телефона попадает около процента неба. При
     шестидесяти тысячах в окне стоит три с половиной тысячи точек, из
     них заметных около тысячи - столько глаз и читает как «полное
     звёзд небо». Стоит это ОДНОГО вызова отрисовки: слабые точки
     отбрасываются в шейдере до растеризации, а шестьдесят тысяч
     вершин это меньше, чем в одной планете.

     Ступень режет число, а не размер: убрать половину звёзд глаз не
     замечает вовсе, а сделать их мельче замечает сразу. */
  function сколько() {
    var ст = (W && typeof W.ступень === "number") ? W.ступень : 2;
    if (ст === 0) return 22000;
    if (ст === 1) return 38000;
    return 60000;
  }

  var В_ШЕЙДЕР = [
    "attribute float aMag;",
    "attribute vec3 aCol;",
    "attribute float aGrp;",
    "attribute float aPh;",
    "uniform float uT;",
    "uniform float uPx;",
    "uniform vec3 uTint0;",
    "uniform vec3 uTint1;",
    "uniform vec3 uTint2;",
    "varying vec3 vCol;",
    "varying float vMag;",
    "varying float vTop;",
    "void main() {",
    "  vec4 mv = modelViewMatrix * vec4(position, 1.0);",
    "  gl_Position = projectionMatrix * mv;",
    /* Мерцание на двух временах: медленное качание и быстрое дрожание
       поверх него. Одна синусоида читается заводным маятником, две
       живой сцинтилляцией. Множит только ЯРКОСТЬ: тот же множитель в
       размере точки дал бы пульсацию в объёме, и это ровно тот
       детский приём, который с фона сайта убирали. */
    "  float tw = 1.0 + (sin(uT * 2.3 + aPh) * 0.62 +",
    "                    sin(uT * 6.7 + aPh * 2.7) * 0.38) * 0.14 * aMag;",
    /* Размер от величины, потолок жёсткий: звезда крупнее нескольких
       пикселей уже не звезда, а пятно. Нижняя граница РОВНО ОДНА точка
       буфера: у точки мельче единицы расстояние в gl_PointCoord почти
       всегда больше единицы, и шейдер отбрасывает её до того, как она
       успеет загореться. Так когда-то не рисовались три четверти
       неба. */
    "  vTop = smoothstep(0.88, 0.97, aMag);",
    "  float px = (1.0 + pow(aMag, 2.1) * 2.3 + vTop * 2.3) * uPx;",
    "  gl_PointSize = clamp(px, uPx, 5.3 * uPx);",
    "  vec3 tint = aGrp < 0.5 ? uTint0 : (aGrp < 1.5 ? uTint1 : uTint2);",
    "  vCol = aCol * tint;",
    "  vMag = aMag * tw;",
    "}"
  ].join("\n");

  /* ВНИМАНИЕ: имена внутри шейдера только латиницей. Кириллица тут уже
     ломала сборку однажды: GLSL её не принимает, а падает молча, экран
     просто чёрный. */
  var Ф_ШЕЙДЕР = [
    "precision mediump float;",
    "varying vec3 vCol;",
    "varying float vMag;",
    "varying float vTop;",
    "void main() {",
    "  vec2 p = gl_PointCoord * 2.0 - 1.0;",
    "  float d = length(p);",
    "  if (d > 1.0) discard;",
    /* Ядро острое, ореол широкий и слабый: так свет звезды и ложится
       на матрицу. Один гауссов колокол давал мягкое пятно, поэтому их
       два с разной шириной. */
    "  float core = exp(-d * d * 34.0);",
    "  float halo = exp(-d * d * 7.0) * 0.13;",
    /* Крест лучей от оправы объектива только у самых ярких: у слабых
       его нет и в жизни. Порог высокий нарочно, иначе небо выходит
       колючим, как гирлянда. */
    "  float ray = 0.0;",
    "  if (vTop > 0.0) {",
    "    float hx = exp(-abs(p.y) * 24.0) * exp(-abs(p.x) * 1.4);",
    "    float vy = exp(-abs(p.x) * 24.0) * exp(-abs(p.y) * 1.4);",
    "    ray = (hx + vy) * 0.26 * vTop;",
    "  }",
    "  float a = (core + halo + ray) * (0.22 + vMag * 0.88);",
    /* Порог отбрасывания. Одна ступень восьмибитной яркости это
       0.0039, и всё, что ниже двух ступеней, на чёрном небе не видно
       вовсе, а фрагмент стоит столько же, сколько видимый. */
    "  if (a < 0.009) discard;",
    /* Ядро самых ярких выбелено: перегруженный пиксель матрицы теряет
       цвет и уходит в белый. */
    "  vec3 col = mix(vCol, vec3(1.0), core * vMag * 0.7);",
    "  gl_FragColor = vec4(col, a);",
    "}"
  ].join("\n");

  function построить() {
    var n = сколько();
    var geo = new T.BufferGeometry();
    var pos = new Float32Array(n * 3);
    var aMag = new Float32Array(n);
    var aCol = new Float32Array(n * 3);
    var aGrp = new Float32Array(n);
    var aPh = new Float32Array(n);

    /* Ближняя и дальняя стенки слоя. Отношение почти два с половиной:
       по обратным квадратам это шесть раз по яркости, столько глубины
       глаз уже читает. Радиусы меньше, чем в игре: у сайта сфера неба
       стоит на 1800, и звёзды обязаны быть ВНУТРИ неё, иначе их
       закроет полотно. */
    var БЛИЖЕ = 900, ДАЛЬШЕ = 1650;
    var сл = поток(4021977);
    var i;
    for (i = 0; i < n; i++) {
      /* Две трети раскиданы ровно по сфере, это гало, оно даёт небо в
         любую сторону. Треть собрана к плоскости диска, это Млечный
         Путь. Ровное распределение по сфере берём через косинус
         широты: равномерная широта сбивает звёзды к полюсам, и на
         потолке это видно сразу. Гауссово отклонение от плоскости
         собираем суммой трёх равномерных, предельная теорема даёт
         колокол дешевле, чем логарифм с корнем. */
      var вДиске = сл() < 0.34;
      var z = сл() * 2 - 1;
      if (вДиске) {
        z = (сл() + сл() + сл() - 1.5) * 0.30;
        if (z < -1) z = -1; else if (z > 1) z = 1;
      }
      var r = Math.sqrt(Math.max(0, 1 - z * z));
      var a = сл() * 6.283185;
      /* Степень меньше единицы гонит больше звёзд к дальней стенке.
         Так и в жизни: объёма на дальнем радиусе больше. */
      var дист = БЛИЖЕ + (ДАЛЬШЕ - БЛИЖЕ) * Math.pow(сл(), 0.62);
      pos[i * 3] = Math.cos(a) * r * дист;
      pos[i * 3 + 1] = z * дист;
      pos[i * 3 + 2] = Math.sin(a) * r * дист;

      /* Светимость по степенному закону: ярких единицы. Видимая
         яркость из неё же, но по закону обратных квадратов, вот откуда
         у слоя берётся глубина. Прибавка полосы идёт в СВЕТИМОСТЬ, а
         не в готовую величину: прибавка к величине сбивала бы каждую
         десятую звезду в кучу у верхнего края. */
      var сила = Math.pow(сл(), 3.1);
      if (Math.abs(z) < 0.22 && сл() < 0.5) сила *= 1.5 + сл() * 1.2;
      var спад = (БЛИЖЕ / дист) * (БЛИЖЕ / дист);
      /* Мягкое насыщение вместо обрезки по единице: обрезка сбивает
         все пересветы ровно в 1.0, и «самая яркая звезда неба»
         становится не одной, а сотнями одинаковых. */
      var m = 1 - Math.exp(-сила * спад * 3.4);
      aMag[i] = m;

      var t = сл(), сум = 0, кл = КЛАССЫ[0], ки;
      for (ки = 0; ки < КЛАССЫ.length; ки++) {
        сум += КЛАССЫ[ки][0];
        if (t <= сум) { кл = КЛАССЫ[ки]; break; }
      }
      var тон = планк(кл[1] + (кл[2] - кл[1]) * сл());
      /* Слабые звёзды глаз видит обесцвеченными: на пороге
         чувствительности цвет пропадает первым. */
      var нас = 0.35 + m * 0.65;
      aCol[i * 3] = 1 + (тон[0] - 1) * нас;
      aCol[i * 3 + 1] = 1 + (тон[1] - 1) * нас;
      aCol[i * 3 + 2] = 1 + (тон[2] - 1) * нас;
      aGrp[i] = кл[3];
      aPh[i] = сл() * 6.283185;
    }

    geo.setAttribute("position", new T.BufferAttribute(pos, 3));
    geo.setAttribute("aMag", new T.BufferAttribute(aMag, 1));
    geo.setAttribute("aCol", new T.BufferAttribute(aCol, 3));
    geo.setAttribute("aGrp", new T.BufferAttribute(aGrp, 1));
    geo.setAttribute("aPh", new T.BufferAttribute(aPh, 1));

    уни = {
      uT: { value: 0 },
      uPx: { value: плотностьРендерера() },
      uTint0: { value: new T.Color(0xcfe9f5) },
      uTint1: { value: new T.Color(0xffffff) },
      uTint2: { value: new T.Color(0xffe9c9) }
    };
    мат = new T.ShaderMaterial({
      transparent: true,
      depthWrite: false,
      depthTest: false,
      blending: T.AdditiveBlending,
      fog: false,
      uniforms: уни,
      vertexShader: В_ШЕЙДЕР,
      fragmentShader: Ф_ШЕЙДЕР
    });

    поле = new T.Points(geo, мат);
    поле.frustumCulled = false;
    /* Сразу за полотном неба и до всего остального. У полотна -100,
       глубина не пишется ни там, ни тут: звёзды обязаны лечь на небо и
       уйти под любой предмет сцены. */
    поле.renderOrder = -99;
    группа = new T.Group();
    группа.add(поле);
    группа.frustumCulled = false;
    return группа;
  }

  g.RV_ЗВЁЗДЫ = {
    "собрать": function (мир) {
      if (собрано) return группа;
      W = мир; T = W.T;
      if (!T || !W.scene) return null;
      место = new T.Vector3();
      построить();
      W.scene.add(группа);
      собрано = true;
      return группа;
    },

    /* Поле едет ЗА камерой, как и полотно неба: иначе на перегоне в
       сотни единиц камера дойдёт до его стенки и звёзды кончатся.
       Параллакса внутри поля здесь нет нарочно: у сайта камера ходит
       по короткой ленте, и отставание слоёв на таких дистанциях
       читалось бы дрожанием, а не глубиной. */
    "кадр": function (часы) {
      if (!собрано || !группа || !W.cam) return;
      группа.position.copy(W.cam.getWorldPosition(место));
      if (уни) уни.uT.value = часы || 0;
    },

    "плотность": function () {
      if (уни) уни.uPx.value = плотностьРендерера();
    },

    "видно": function (да) {
      if (группа) группа.visible = !!да;
    },

    "замер": function () {
      if (!собрано || !поле) return null;
      return {
        "звёзд": поле.geometry.attributes.position.count,
        "точек": уни ? Math.round(уни.uPx.value * 100) / 100 : 0,
        "видно": !!(группа && группа.visible),
        "ступень": W ? W.ступень : null
      };
    }
  };
})(window);
