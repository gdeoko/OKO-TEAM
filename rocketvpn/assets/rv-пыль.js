/* Rocket VPN. Скоростная пыль перегонов: росчерки по вектору скорости.

   Пыль ядра (rv-world.js) это точки одного размера, и на перегоне они
   выдают ровно одно: что камера едет. Скорости в них нет: точка не знает,
   куда летит, и на быстром перегоне в четыреста единиц кадр читается так
   же, как на медленном проезде внутри акта. Здесь каждая частица это
   квад, вытянутый вдоль ЭКРАННОГО направления своего движения: на
   перегоне частицы становятся росчерками, у станции снова собираются в
   точки. Направление росчерка считается по перспективе (частица сбоку
   кадра при полёте вперёд бежит радиально), поэтому кадр на скорости
   расходится из точки схода, как в кино, а не сдвигается стеной.

   ПОЧЕМУ ВСЁ В ВЕРШИННОМ ШЕЙДЕРЕ. Ядро двигает свои точки циклом на
   процессоре каждый кадр. Тысяча точек это терпимо, шесть тысяч вершин
   уже нет. Здесь база частицы лежит в атрибуте, а заворот по кубу вокруг
   камеры, растяжение и ориентация считаются картой: процессору остаётся
   три униформы на кадр.

   Ступень 0 не трогается вовсе: остаётся точечная пыль ядра. На 1 и 2
   пыль ядра снимается со сцены и ставится эта. */
(function (g, d) {
  "use strict";

  var КУБ = 56;           /* тот же куб, что у пыли ядра: облако вокруг камеры */
  var ОБЪЁМ = [0, 900, 1600];

  /* Оценка скорости камеры. Мир её не отдаёт, поэтому меряем сами по ходу
     камеры между кадрами и сглаживаем: без сглаживания росчерки дрожат
     от кадра к кадру, потому что прокрутка приходит толчками. Отдаётся
     наружу (RV_ПЫЛЬ.скорость), чтобы соседним модулям не мерить заново. */
  var прошлоеМесто = null, прошлыеЧасы = -1;
  var вектор = null, сглаж = 0;
  var СКОРОСТЬ = { "напр": null, "норм": 0 };

  function мерить(T, кам, часы) {
    if (!вектор) {
      вектор = new T.Vector3();
      прошлоеМесто = new T.Vector3().copy(кам.position);
      прошлыеЧасы = часы;
      СКОРОСТЬ["напр"] = new T.Vector3(0, 0, -1);
      return СКОРОСТЬ;
    }
    var dt = часы - прошлыеЧасы;
    if (dt <= 0) return СКОРОСТЬ;
    /* Плёнка рисует сцену тем же кадром: второй вызов в тот же час
       ничего не меняет. Долгая пауза (вкладка спала) сбрасывает мерку,
       иначе первый кадр после сна считает скачок за полёт. */
    if (dt > 0.3) {
      прошлоеМесто.copy(кам.position); прошлыеЧасы = часы; сглаж = 0;
      return СКОРОСТЬ;
    }
    вектор.copy(кам.position).sub(прошлоеМесто);
    прошлоеМесто.copy(кам.position);
    прошлыеЧасы = часы;
    var путь = вектор.length();
    /* Полторы сотни единиц в секунду это быстрый перегон (та же мерка,
       что у плёнки); медленный проезд по акту даёт сотые доли. */
    var v = путь > 1e-5 ? Math.min(1, путь / dt / 150) : 0;
    var k = 1 - Math.exp(-dt / 0.12);
    сглаж += (v - сглаж) * k;
    if (путь > 1e-5) {
      вектор.multiplyScalar(1 / путь);
      СКОРОСТЬ["напр"].lerp(вектор, k).normalize();
    }
    СКОРОСТЬ["норм"] = сглаж;
    return СКОРОСТЬ;
  }

  /* Внутри GLSL только латиница: кириллица ломает разбор, и материал
     молча не собирается. */
  var ВЕРШ = [
    "uniform vec3 uCam;",
    "uniform vec3 uVel;",
    "uniform float uSpeed;",
    "uniform float uTime;",
    "attribute vec2 aCorner;",
    "attribute float aSize;",
    "attribute float aTone;",
    "attribute float aPh;",
    "varying vec2 vC;",
    "varying float vA;",
    "varying float vTone;",
    "void main(){",
    "  vec3 dw = position - uCam;",
    "  dw -= floor(dw / " + КУБ.toFixed(1) + " + 0.5) * " + КУБ.toFixed(1) + ";",
    "  float dist = length(dw);",
    /* Ближняя дырка мягкая: частица в упор растворяется, а не прыгает
       на другую сторону куба, как у пыли ядра. Дальняя граница гасит
       угол куба, иначе облако читается коробкой. */
    "  float fade = smoothstep(2.0, 6.0, dist) * (1.0 - smoothstep(24.0, 34.0, dist));",
    "  vec3 P = (viewMatrix * vec4(uCam + dw, 1.0)).xyz;",
    "  vec3 V = mat3(viewMatrix) * uVel;",
    /* Экранная скорость точки P при движении камеры на V: производная
       проекции. Даёт радиальные росчерки от точки схода. */
    "  vec2 ds = V.xy * (-P.z) + P.xy * V.z;",
    "  float dsl = length(ds);",
    "  vec2 along = dsl > 1e-4 ? ds / dsl : (length(P.xy) > 1e-3 ? normalize(P.xy) : vec2(1.0, 0.0));",
    "  vec2 perp = vec2(-along.y, along.x);",
    "  float near = smoothstep(28.0, 6.0, dist);",
    /* Растяжение делится на экранную скорость точки: у точки схода
       экранный ход мал, и росчерк там короткий сам собой, к краям
       кадра длинный. Без этого все росчерки одной длины, и кадр
       сдвигается стеной вместо разлёта из точки схода. */
    "  float razlet = clamp(dsl / max(dist, 1.0) * 1.6, 0.25, 1.0);",
    "  float stretch = 1.0 + 16.0 * uSpeed * near * razlet;",
    "  float len = aSize * stretch;",
    "  P.xy += along * aCorner.x * len + perp * aCorner.y * aSize;",
    "  vC = aCorner;",
    /* Свет размазывается по длине росчерка: яркость падает обратно
       корню растяжения, иначе на перегоне кадр заливает белым. */
    "  vA = fade * inversesqrt(stretch) * (0.85 + 0.15 * sin(uTime * 3.0 + aPh));",
    "  vTone = aTone;",
    "  gl_Position = projectionMatrix * vec4(P, 1.0);",
    "}"
  ].join("\n");

  var ФРАГ = [
    "uniform float uSpeed;",
    "varying vec2 vC;",
    "varying float vA;",
    "varying float vTone;",
    "void main(){",
    "  float ax = abs(vC.x), ay = abs(vC.y);",
    /* Гауссово пятно по обеим осям квада: в покое круглое зерно, на
       росчерке (квад вытянут по x) вытянутый эллипс с мягкими концами.
       Прежний профиль (1-ay)^1.6 (1-ax^2) держал углы квада видимыми,
       и пыль на снимке читалась бумажными квадратиками. Хвост гаснет
       к концам сильнее на скорости: росчерк это след, а не палка. */
    "  float a = exp(-(ax * ax + ay * ay) * 3.2) - 0.04;",
    "  if (a <= 0.0) discard;",
    "  a *= (1.0 - ax * uSpeed * 0.6) * vA * 0.9;",
    /* Три тона: индиго основа, тёплый и бирюзовый акценты. Тёплых мало
       намеренно: два-три в кадре дают глубину, десяток дают ёлку. */
    "  vec3 c = vec3(0.682, 0.737, 0.941);",
    "  if (vTone > 0.92) c = vec3(0.561, 0.890, 1.0);",
    "  else if (vTone > 0.70) c = vec3(1.0, 0.851, 0.690);",
    "  gl_FragColor = vec4(c * a * 1.15, a);",
    "}"
  ].join("\n");

  var сетка = null, униф = null;

  function собрать(W) {
    if (сетка) return;
    var T = W.T, ст = W.ступень;
    var n = ОБЪЁМ[ст] || 0;
    if (!n) return;

    /* Пыль ядра снимается со сцены, а не прячется: ядро само ставит ей
       visible каждый живой кадр. Снятая со сцены она не рисуется, а её
       цикл на процессоре стоит десятые доли миллисекунды. */
    var дети = W.scene.children, i;
    for (i = дети.length - 1; i >= 0; i--) {
      var о = дети[i];
      var ядра = о.name === "rv-пыль" ||
        (о.isPoints && о.material && о.material.isPointsMaterial && о.renderOrder === -1);
      if (ядра) W.scene.remove(о);
    }

    var поз = new Float32Array(n * 4 * 3);
    var угол = new Float32Array(n * 4 * 2);
    var разм = new Float32Array(n * 4);
    var тон = new Float32Array(n * 4);
    var фаза = new Float32Array(n * 4);
    var инд = new Uint16Array(n * 6);
    /* Тот же генератор и семя, что у пыли ядра: облако обязано быть
       одним и тем же при каждом заходе, чтобы снимки сравнивались. */
    var s = 1234567;
    function сл() { s = (s * 1103515245 + 12345) % 2147483648; return s / 2147483648; }
    var УГЛЫ = [-1, -1, 1, -1, 1, 1, -1, 1];
    for (i = 0; i < n; i++) {
      var x = сл() * КУБ, y = сл() * КУБ, z = сл() * КУБ;
      /* Логарифмический разброс размера: много мелких, редкие крупные.
         Равномерный давал облако одинаковых бусин. Верх намеренно
         мал: квады до 0.22 на снимке стояли мутными квадратами в
         полэкрана, ореол плёнки раздувал каждый ещё вдвое. Пыль это
         зерно, крупность ей даёт росчерк, а не тело. */
      var р = 0.018 * Math.pow(0.085 / 0.018, сл());
      var т = сл(), ф = сл() * 6.2832;
      for (var k = 0; k < 4; k++) {
        var в = i * 4 + k;
        поз[в * 3] = x; поз[в * 3 + 1] = y; поз[в * 3 + 2] = z;
        угол[в * 2] = УГЛЫ[k * 2]; угол[в * 2 + 1] = УГЛЫ[k * 2 + 1];
        разм[в] = р; тон[в] = т; фаза[в] = ф;
      }
      var б = i * 4, и = i * 6;
      инд[и] = б; инд[и + 1] = б + 1; инд[и + 2] = б + 2;
      инд[и + 3] = б; инд[и + 4] = б + 2; инд[и + 5] = б + 3;
    }
    var гео = new T.BufferGeometry();
    гео.setAttribute("position", new T.BufferAttribute(поз, 3));
    гео.setAttribute("aCorner", new T.BufferAttribute(угол, 2));
    гео.setAttribute("aSize", new T.BufferAttribute(разм, 1));
    гео.setAttribute("aTone", new T.BufferAttribute(тон, 1));
    гео.setAttribute("aPh", new T.BufferAttribute(фаза, 1));
    гео.setIndex(new T.BufferAttribute(инд, 1));

    униф = {
      uCam: { value: new T.Vector3() },
      uVel: { value: new T.Vector3(0, 0, -1) },
      uSpeed: { value: 0 },
      uTime: { value: 0 }
    };
    var мат = new T.ShaderMaterial({
      uniforms: униф,
      vertexShader: ВЕРШ,
      fragmentShader: ФРАГ,
      transparent: true,
      depthWrite: false,
      depthTest: true,
      blending: T.AdditiveBlending
    });
    сетка = new T.Mesh(гео, мат);
    сетка.name = "rv-пыль-стрики";
    /* Вершины заворачиваются вокруг камеры в шейдере, коробка объекта
       врёт всегда: отсечение по ней выкинуло бы облако из кадра. */
    сетка.frustumCulled = false;
    сетка.renderOrder = -1;
    сетка.onBeforeRender = function (r, сц, кам) {
      /* Скорость берётся у мира, если он её отдаёт: одна мерка на пыль
         и плёнку, иначе росчерки и размыв кадра расходятся по фазе.
         Без неё своя мерка по ходу камеры. */
      var ск = null;
      try { if (g.RV_WORLD["скорость"]) ск = g.RV_WORLD["скорость"](); } catch (e) { ск = null; }
      if (ск && ск["напр"] && ск["напр"].length === 3) {
        униф.uVel.value.fromArray(ск["напр"]);
        униф.uSpeed.value = ск["норм"] || 0;
      } else {
        ск = мерить(T, кам, W.часы);
        униф.uVel.value.copy(ск["напр"]);
        униф.uSpeed.value = ск["норм"];
      }
      униф.uCam.value.copy(кам.position);
      униф.uTime.value = W.часы;
    };
    W.scene.add(сетка);
  }

  function встать() {
    if (!g.RV_WORLD || !g.RV_WORLD["мир"]) return;
    var W = g.RV_WORLD["мир"]();
    if (!W || !W.готов || !W.ступень) return;
    /* В очередь прогрева, следом за пылью ядра: тогда к нашей сборке она
       уже стоит в сцене и её можно снять. Очередь крутят акты, они
       встают по тому же событию позже нас. */
    g.RV_WORLD["работа"]("пыль-стрики", function () { собрать(W); });
  }

  g.RV_ПЫЛЬ = {
    "скорость": function () { return СКОРОСТЬ; },
    "сетка": function () { return сетка; }
  };

  if (g.RV_WORLD && g.RV_WORLD["готов"] && g.RV_WORLD["готов"]()) встать();
  else g.addEventListener("rv:мир", встать);
})(window, document);
