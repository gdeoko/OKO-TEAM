/* Rocket VPN. Акт «Финал»: подходим к ракете и заходим внутрь.

   ЗАЧЕМ. Владелец описал конец сценария дословно: «а в конце мы
   приближаемся в сторону ракеты, открываются двери, мы заходим внутрь
   (оборот на 360 как на сайте CDN мы делать не будем, мы просто заходим
   внутрь и подходим к панели управления, на которой будет анкета, часто
   задаваемые вопросы, кнопка запустить VPN и кнопка запустить игру,
   такая же как на сайте CDN)».

   ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ И ЧЕГО НЕ ДЕЛАЕТ. Сцену финала - корабль, люк,
   створки, зал и пульт - целиком собирает rv-финал.js, и числа там сняты
   с родственного проекта Rocket CDN. Здесь только три вещи: поставить
   эту сцену в мир, отдать миру её позу и вести её долей акта. Ни одного
   своего размера тут нет намеренно: два места, где живёт форма корабля,
   разошлись бы на первой же правке.

   ГДЕ ОН СТОИТ. Дальше комнаты по той же оси, на её же полу. Комната
   лежит в (0, 14, -4), человек обходит фигуру по окружности радиусом
   двадцать шесть, то есть дальняя точка обхода это z минус тридцать.
   Корабль стоит на z минус семьдесят восемь: сорок восемь единиц чистого
   промежутка. Меньше нельзя - край орбиты обхода попадал бы в кадр
   подхода, и человек видел бы два корабля разом, тот, вокруг которого
   только что ходил, и тот, в который заходит.

   ПОЧЕМУ ОДНА ПРЯМАЯ. Оборот владелец отменил, и поза, которую отдаёт
   rv-финал.js, идёт по одной линии: точка взгляда у пульта, подход
   отодвигает камеру назад по той же линии за люк. Ни одного поворота на
   всей дороге; отворот взгляда прижат до двадцати градусов.

   ЧЕМ ЭТО СВЯЗАНО С МИНИ-ИГРОЙ. Ракета в комнате становится объёмной,
   когда человек выиграл (rv-комната.js, «ПРЕВРАЩЕНИЕ РОЯ В КОРАБЛЬ»).
   Финал этого не ждёт: зайти внутрь можно всегда, иначе конец сайта
   доставался бы только тем, кто выиграл, а анкета и частые вопросы
   нужны всем. Победа меняет одно - надпись на пульте.
   ═══════════════════════════════════════════════════════════ */
(function (g, d) {
  "use strict";

  var W = null, T = null;
  var собрано = false;
  var корень = null;

  /* ── КОРАБЛЬ СТОИТ ТАМ ЖЕ, ГДЕ РОЙ. ЭТО И ЕСТЬ ГЛАВНЫЙ ШОВ ────
     Владелец: «камера летит вроде ровно к ракете сверху, и потом
     вправо куда-то уходит, и ракета в другом месте появляется сразу,
     шов есть».

     Ракет в мире было ДВЕ, и это замерено (tools/две-ракеты.mjs):

       предмет            центр            размер (ш x в x г)
       рой в комнате      0, 23.28, -3.99  6.11 x  9.34 x 6.11
       цельная ракета     0, 22.63, -4.00  4.49 x 10.64 x 4.90
       корабль финала     0, 17.96, -78.0  8.42 x 28.21 x 8.42

     Человек обходил одну, а заходил в другую, стоящую за семьдесят
     четыре единицы и втрое крупнее. Никакой правкой хода это не
     лечится: чинить надо место.

     Корабль финала переезжает НА МЕСТО РОЯ и ужимается до его роста.
     Множитель 10.64 / 28.21 = 0.377 взят по ВЫСОТЕ, а не по ширине:
     ракету глаз читает по росту, и высоты сходятся в ноль, тогда как
     ширины у двух моделей расходятся по построению.

     Высота узла считается от коробки: середина корабля стоит на 3.96
     выше своего узла, после ужатия на 1.49, а середина роя стоит на
     22.63 - отсюда 22.63 - 1.49 = 21.14. */
  var МАСШТАБ = 0.377;
  var МЕСТО = { "x": 0, "y": 21.14, "z": -4 };

  /* ── ЛЮК СМОТРИТ ТУДА, ГДЕ КОНЧИЛСЯ ОБЛЁТ ────────────────────
     Владелец: «у нас нету вправо влево вообще, у нас либо вперёд, либо
     вверх, либо облёт вокруг ракеты».

     Вход в корабль стоит по местной оси +Z, то есть на азимуте ноль.
     Облёт же кончается совсем в другом месте: рубка ведёт камеру от
     нуля до пятидесяти градусов, пуск от семидесяти до ста двадцати
     (rv-act-bridge.js и rv-act-пуск.js, одна окружность радиусом
     двадцать шесть на два акта). Оставь люк на нуле - и человеку после
     облёта пришлось бы проехать вокруг корабля ещё сто двадцать
     градусов, только чтобы найти дверь.

     Поворачиваем корабль. Тогда камера, дойдя до конца облёта, стоит
     ровно напротив люка, и весь финал это движение ПО ПРЯМОЙ внутрь -
     без единого шага вбок.

     Сто двадцать градусов были концом ДУГИ пуска: станция на девяноста
     пяти, узел ухода на двадцать пять дальше. Дуги больше нет - пуск
     переписан на прямой подход вдоль плюс Z, вбок ноль во всех узлах, -
     и старый угол остался висеть чужим числом.

     Замер стыка это поймал: камера вылетала вбок на двадцать четыре
     единицы и возвращалась, перелом курса на стыке доходил до ста
     двадцати градусов, а сама ракета уезжала из середины кадра на
     девяносто четыре точки влево. Владелец про это писал каждым
     сообщением: «камера не должна вообще никогда вправо влево уходить»,
     «ракета всегда в центре».

     Ноль ставит люк туда же, откуда камера приходит по прямой из
     пуска. */
  var УГОЛ_ЛЮКА = 0;

  function построить(мир) {
    if (собрано) return true;
    W = мир || W;
    if (!W || !W.T || !W.scene) return false;
    T = W.T;
    if (!g.RV_ФИНАЛ || !g.RV_ФИНАЛ["собрать"]) return false;

    /* Гнездо мира тут не годится. Оно ставит узел в точку «на» и
       разворачивает его лицом к «от», а поза финала СЧИТАЕТСЯ по
       мировой матрице собранной сцены: узел встал бы по позе, поза
       пересчиталась бы по узлу, и место поехало бы на каждом кадре.
       Поэтому узел стоит в своей точке без поворотов, а поза берётся у
       него уже потом. */
    корень = new T.Group();
    корень.name = "финал";
    корень.position.set(МЕСТО.x, МЕСТО.y, МЕСТО.z);
    /* Масштаб узла тянет за собой ВСЁ: обшивку, створки, зал, пульт и
       дорогу камеры (поза считается по мировой матрице точки глаза,
       см. rv-финал.js «поза»). Внутри корабля от этого не меняется
       ничего - и предметы, и глаз ужались одинаково.

       Свет так не ужимается: у точечного источника дальность задана в
       мировых единицах и живёт мимо матрицы. Её пересчитывает сам
       rv-финал.js по этому же числу. */
    корень.scale.setScalar(МАСШТАБ);
    корень.rotation.y = УГОЛ_ЛЮКА;
    корень.visible = false;
    W.scene.add(корень);

    if (!g.RV_ФИНАЛ["собрать"](W, корень)) return false;
    /* Дальность ламп пересчитывается ПОСЛЕ сборки: до неё их ещё нет. */
    if (g.RV_ФИНАЛ["мирУжат"]) g.RV_ФИНАЛ["мирУжат"](МАСШТАБ);
    собрано = true;
    return true;
  }

  function кадр(доля, dt, часы) {
    if (!собрано) return;

    /* ── В САЛОНЕ ПЛЁНКА СНИМАЕТ СВОЙ ПОЛ ─────────────────────────
       Пол это индиговая вуаль подложки: она поднимает каждую точку
       кадра и нужна лунным актам, где чистая чернота читается дырой.
       Внутри корабля она портит всё.

       Замер двух кадров одной панели, нашей и соседской: у соседей
       55.1% кадра это чистый чёрный, у нас 0.0%; средняя яркость 23.5
       против 40.2. Владелец посмотрел сверку и сказал: «ты же сама
       видишь что всё отличается». Отличалось именно это - у них
       глубина, у нас серая муть, в которой тонут и рама, и приборы.

       Уходит вуаль вместе с входом в корабль, а не рывком: доля от
       0.10 до 0.42 это как раз проход двери. Рывок по яркости на стыке
       читался бы вспышкой. */
    try {
      var мир = g.RV_WORLD && g.RV_WORLD["мир"] ? g.RV_WORLD["мир"]() : null;
      var плёнка = мир && мир["плёнка"];
      if (плёнка && плёнка.пол) {
        var k = (доля - 0.10) / 0.32;
        k = k < 0 ? 0 : (k > 1 ? 1 : k);
        плёнка.пол(1 - k);
      }
    } catch (eП) {}

    /* ── ВОКРУГ КОРАБЛЯ ОБЯЗАН БЫТЬ АНГАР ────────────────────────
       Акт стоит на дне шахты, на сорок восемь единиц дальше комнаты
       обхода, и до этой правки он не заявлял вокруг себя НИЧЕГО. Всё,
       что было видно, оставалось от предыдущего акта: работало, пока
       человек доезжал сюда по ленте, и рассыпалось, если он попадал в
       финал прямо (по якорю, по перезагрузке на этом месте, откатом
       назад из подвала).

       Замер на мониторе показал цену: на доле 0.30 сорок процентов
       кадра стояло чистым чёрным по бокам от корабля, средняя яркость
       59 против 151 на телефоне. Телефон это прятал шириной кадра -
       узкую рамку корабль накрывал собой целиком.

       Спрашиваем ровно то же и в том же порядке, что рубка и пуск: у
       трёх соседних актов одно место, и разное окружение в них читалось
       бы монтажной склейкой. */
    /* ── ОБОЛОЧКА ПОДЗЕМЕЛЬЯ ГАСНЕТ К КОРАБЛЮ ────────────────────
       Оболочка (rv-фон.js) СВЕТЛАЯ намеренно: это их lightroom, и
       нужен он рою частиц - тёмная частица рисует силуэт только на
       светлом. Для акта обхода это верно и остаётся.

       Кораблю она мешает ровно наоборот. Снимок доли 0.02 показал: на
       светло-сером листе площадка с бортиком и огнями читается хорошо,
       а сам металл корпуса почти пропадает - светло-серое на
       светло-сером. У соседей за ракетой чёрный космос со звёздами,
       владелец прислал этот кадр первым.

       Гасим БЫСТРО, за первую двадцатую доли. Первый заход растягивал
       спад на треть акта, второй на десятую, и оба раза снимок первых
       сотых доли показывал одно: кадр «ракета целиком на площадке» -
       это и есть самое начало акта, и оболочка там ещё в силе. На
       снимке доли 0.00 от корабля оставались площадка и ноги, корпус
       пропадал целиком - светло-серое на светло-сером.

       Совсем резать всё равно нельзя: на нуле человек только что вышел
       из зала обхода, и мгновенная смена фона была бы склейкой ровно
       там, где мы шов и убирали. Двадцатая доли это четверть экрана
       прокрутки - глаз читает это как «свет уходит», а не как
       монтажный стык. Остаток оболочки тоже ниже: восемь десятых
       гасили её до двух, и этих двух хватало, чтобы дальний корпус
       тонул. */
    /* Спад начат ещё в пуске (rv-act-пуск.js, последние пять сотых его
       доли), поэтому здесь он уже ЗАКОНЧЕН на нуле: свет ушёл до стыка,
       и первый кадр финала - ракета на площадке в темноте, как на кадре
       владельца. Постоянное число здесь честнее ступеньки: акт может
       начаться и не со стыка (переход по якорю, откат ленты назад), и
       тогда ступенька снова показала бы полный свет на первом кадре -
       ровно ту беду, которую чиним. */
    var силаФона = 0.12;
    if (g.RV_ФОН) { g.RV_ФОН["собрать"](W); g.RV_ФОН["сила"](силаФона); g.RV_ФОН["кадр"](часы); }
    try { if (g.RV_ЛУНА && g.RV_ЛУНА["подземка"]) g.RV_ЛУНА["подземка"](true); } catch (eЛ) {}
    try { if (g.RV_КОРИДОР && g.RV_КОРИДОР["подземка"]) g.RV_КОРИДОР["подземка"](true); } catch (eК) {}
    try { if (g.RV_ПЫЛЬ && g.RV_ПЫЛЬ["подземка"]) g.RV_ПЫЛЬ["подземка"](true); } catch (eП) {}
    /* Порог ореола подземный, тот же, что у рубки и пуска. */
    /* ── ПОДЗЕМНЫЙ ПОРОГ ПОДНЯТ С 0.12 ДО 0.45 ──────────────────────
       Ноль у igloo работает потому, что их подземелье СНЯТО тёмным
       камнем: светятся кромки, а не всё подряд. У нас за трубой стоит
       оболочка подземелья - полноэкранный переход от 0x6a6f7d к
       0xe1e6f1, то есть от шестидесяти до восьмидесяти восьми сотых
       яркости. При пороге 0.12 в ореол уходит ВЕСЬ этот фон, пирамида
       размазывает его по кадру и складывает поверх себя же.

       На снимке доли 0.95 прокола от тоннеля оставалось ровное белое
       поле: ни колец, ни глубины, ни текста. Владелец: «всё нечитаемо,
       всё непонятно».

       0.45 ниже кромок и колец и выше самой оболочки: светится то, что
       и должно светиться. */
    try { if (W.плёнка && W.плёнка.порог) W.плёнка.порог(0.45); } catch (eО) {}

    /* ── КОМНАТА ОСТАЁТСЯ, ФИГУРА УХОДИТ ─────────────────────────
       Корабль стоит на месте роя, значит рой и цельная ракета обязаны
       уступить: два корпуса в одной точке это тот самый шов. Пол,
       дымка, кольца и цилиндр текста остаются - человек по-прежнему в
       ангаре, и фон не меняется на стыке актов. */
    /* ── ЗАЛОМ РАСПОРЯЖАЕТСЯ ТОТ, ЧЕЙ АКТ ИДЁТ ───────────────────
       Секции ленты высокие и липкие, поэтому кадры финала начинают
       приходить ещё на хвосте прокола - с долей ровно ноль, то есть до
       своего начала. А зал он звал безусловно и долей единица.

       Числа это показали прямо: на проколе 0.90 сборка каменной ракеты
       стояла на единице вместо 0.57, а превращение в металл ушло на
       0.087. Человек ещё летел по тоннелю, а на дне шахты уже стоял
       готовый корабль и сквозь кладку торчали опоры и раструб.

       Пока своей доли нет, зал остаётся за проколом. */
    if (g.RV_КОМНАТА && g.RV_КОМНАТА["собрать"] && доля > 0.0005) {
      g.RV_КОМНАТА["собрать"](W, g.RV_КОМНАТА["место"]());
      g.RV_КОМНАТА["видно"](true, "финал");
      /* ── ПОБЕДУ ОБЪЯВЛЯЕМ ТОЛЬКО КОГДА ФИНАЛ ДЕЙСТВИТЕЛЬНО ИДЁТ ──
         Корпус собран ещё в пуске и обязан остаться собранным. Но
         ставить это безусловно нельзя, и я это уже поймала кадром:
         зал (рубка) идёт ДО пуска, а код финала успевает отработать в
         том же кадре и уводил превращение в единицу задолго до своего
         акта. Рой в зале от этого разлетался и гас до десятой доли -
         на снимке зала 0.50 текст стоял, а ракеты не было вовсе.

         Порог тот же, с которого пуск начинает собирать корпус. */
      /* Корабль в зале уже собран рубкой: финал принимает его целым и
         ничего не разбирает обратно. */
      /* Второй довод - «ставить сразу». На стыке (первая пятая акта)
         переход обязан быть виден, дальше он уже кончился, и догонять
         его по времени значит показывать растворяющийся камень тому,
         кто пришёл по ссылке в середину финала. */
      if (g.RV_КОМНАТА["победа"]) g.RV_КОМНАТА["победа"](true, доля > 0.20);
      // The room updates its particle opacity; apply the handoff afterwards.
      if (g.RV_КОМНАТА["кадр"]) g.RV_КОМНАТА["кадр"](1, dt, часы);
      /* ── РОЙ УХОДИТ СРАЗУ, КОРАБЛЬ ВСТАЁТ НА ЕГО МЕСТО ───────────
         Рой держался до трети акта, и всё это время человек шёл
         именно к НЕМУ: облако точек в форме ракеты, без борта и без
         люка. Дверь открывать было не в чем, и владелец сказал про
         этот кусок прямо - «каша».

         Теперь передача идёт в первую десятую долю: рой гаснет,
         сплошной корабль зажигается, и дальше по сценарию открывается
         его люк. Один корпус в кадре в любой момент. */
      /* ── ПЕРЕДАЧУ ВЕДЁТ ПРЕВРАЩЕНИЕ, А НЕ ДОЛЯ АКТА ──────────────
         Камень гас по доле прокрутки, металл рос по превращению, и два
         числа шли вразнобой: при быстрой прокрутке кладка успевала
         пропасть раньше, чем обшивка дорастала, и в кадре на секунду
         не оставалось корабля вовсе.

         Число теперь одно на обе фигуры. Зал возвращает его из
         победа(), там же стоят пороги: камень целый до 0.10, тает к
         0.55, металл трогается с 0.40. */
      var пр = g.RV_КОМНАТА["победа"] ? g.RV_КОМНАТА["победа"]() : 1;
      var кРой = 1 - Math.min(1, Math.max(0, (пр - 0.10) / 0.45));
      if (g.RV_СБОРКА && g.RV_СБОРКА["проявить"]) g.RV_СБОРКА["проявить"](кРой);
      if (g.RV_КОМНАТА["фигураВидна"]) g.RV_КОМНАТА["фигураВидна"](кРой > 0.003);
      if (g.RV_КОМНАТА["приглушить"]) g.RV_КОМНАТА["приглушить"](1 - кРой);
    }
    /* ── ДАЛЬ ЗА СТЕКЛОМ НУЖНА ───────────────────────────────────
       Первый заход гасил её: корабль стоит под грунтом, звёзды в
       подземелье выглядят странно. Владелец прислал пятый и шестой
       кадры их финала и сказал «1:1»: в окне рубки стоит Земля.
       Голое окно без предмета читается дырой в борту, а не окном.
       Возвращаем. */
    /* ── КОРАБЛЬ СНАРУЖИ ВИДЕН, ПОКА МЫ НЕ ВОШЛИ ─────────────────
         Метод был, звать его было некому, и борт с люком не показывался
         ни разу за весь фильм. Зажигаем его ровно на подходе: от начала
         акта до входа в проём. Дальше он мешал бы - камера уже внутри,
         и обшивка встала бы перед стеклом. */
    /* ── ЛУННОЕ СОЛНЦЕ НЕ СВЕТИТ ВНУТРИ КОРАБЛЯ ───────────────────
       Мир держит три направленных источника на всю ленту: холодный
       ключ, синее заполнение и ТЁПЛЫЙ контровой 0xFFC8A2 в силе 2.4
       (rv-real.js, «световой стан»). Снаружи это ровно то, что нужно:
       по ним читается объём станции и корабля.

       Внутри рубки они всё портят. Замер ламп в кадре 0.58 показал
       одиннадцать источников разом, и среди них лунное солнце било
       наискось по обшивке: стены и настил читались песочными панелями,
       а не кораблём. Рядом с соседским кадром это первое, что видно -
       у них внутри холодный синий с цианом, у нас беж.

       Стан гасится по ходу входа и возвращается на выходе: сила
       множится на долю, а не записывается насовсем, поэтому обратная
       прокрутка честно зажигает его обратно. */
    станСила(доля < 0.40 ? 1 : (доля > 0.60 ? 0.10 : 1 - 0.90 * ((доля - 0.40) / 0.20)));
    /* ── КОРАБЛЬ СНАРУЖИ ЖДЁТ СВОЕЙ ДОЛИ ────────────────────────
       Кадры финала приходят ещё на хвосте прокола, с долей ровно ноль:
       секции ленты высокие и липкие. Условие «доля меньше 0.62»
       выполняется и на нуле, поэтому борт зажигался заранее. Снимок
       прокола 0.88 показал цену: на площадке стоял готовый синий
       корабль, а каменные кирпичи слетались ПОВЕРХ него. Два корпуса в
       одной точке, ровно та каша, ради которой всё это и переделано.

       Площадка при этом ОСТАЁТСЯ: она общая, на ней стоит и каменная
       ракета. Уходит только корпус - иначе каменная ракета повисает над
       полом без опоры (снимок прокола 0.93). */
    if (g.RV_ФИНАЛ["снаружи"]) g.RV_ФИНАЛ["снаружи"](доля < 0.62);
    if (g.RV_ФИНАЛ["корпус"]) g.RV_ФИНАЛ["корпус"](доля > 0.0005);
    /* ── КОСМОС ЗА СТЕКЛОМ ЗАЖИГАЕТСЯ, КОГДА ЕСТЬ СТЕКЛО ─────────
       Даль стояла включённой весь акт, и на подходе это читалось
       грубой ошибкой: посреди ангара, за спиной у корабля, висел
       плоский прямоугольник звёздного неба с планетой сбоку. Он и
       задуман как вид ИЗ ОКНА рубки, а не как декорация зала.

       Зажигаем её ровно тогда, когда камера прошла проём и стекло
       появилось в кадре. Створки к этому времени уже настежь (0.52),
       глаз входит на 0.59: берём середину. */
    if (g.RV_ФИНАЛ["даль"]) g.RV_ФИНАЛ["даль"](доля > 0.55);

    if (g.RV_ФИНАЛ["кадр"]) g.RV_ФИНАЛ["кадр"](доля, dt, часы);
  }

  /* Световой стан мира и его полная сила. Ищем один раз: обход сцены
     каждый кадр ради трёх ламп это работа впустую. */
  var стан = null, станБаза = null;
  function станСила(к) {
    if (!W || !W.scene) return;
    if (!стан) {
      W.scene.traverse(function (о) { if (о.name === "rv-свет") стан = о; });
      if (!стан) return;
      станБаза = [];
      стан.traverse(function (о) {
        if (о.isLight) станБаза.push({ л: о, сила: о.intensity });
      });
    }
    if (!станБаза) return;
    var д = к < 0 ? 0 : (к > 1 ? 1 : к);
    for (var i = 0; i < станБаза.length; i++) станБаза[i].л.intensity = станБаза[i].сила * д;
  }

  var МОДУЛЬ = {
    "собрать": function (мир) { if (построить(мир)) позу(); },
    "показать": function (да) {
      if (да && !собрано) построить(g.RV_WORLD ? g.RV_WORLD["мир"]() : null);
      if (!собрано) return;
      корень.visible = !!да;
      /* Гнездо акта держит мир, и погашенному акту он его гасит. Пока
         корабль стоит в чужом разделе, гнездо обязано быть открыто:
         иначе виден он только в своём акте, а зал остаётся пустым. */
      if (g.RV_WORLD && g.RV_WORLD["гнездо"]) {
        var гн = g.RV_WORLD["гнездо"]("финал");
        if (гн) гн.visible = true;
      }
      if (g.RV_ФИНАЛ["видно"]) g.RV_ФИНАЛ["видно"](!!да);
      /* Ушли из финала - возвращаем фигуру комнате и отпускаем саму
         комнату. Человек, прокрутивший ленту назад, обязан увидеть тот
         же ангар с той же ракетой, а не пустую площадку. */
      try {
        if (g.RV_КОМНАТА) {
          if (!да && g.RV_КОМНАТА["фигураВидна"]) g.RV_КОМНАТА["фигураВидна"](true);
          /* Прокрутил назад - рой обязан вернуться в полную силу, иначе
             зал встретит человека пустой площадкой. */
          if (!да && g.RV_СБОРКА && g.RV_СБОРКА["проявить"]) {
            try { g.RV_СБОРКА["проявить"](1); } catch (eЧ2) {}
          }
          if (!да && g.RV_КОМНАТА["приглушить"]) g.RV_КОМНАТА["приглушить"](0);
          if (g.RV_КОМНАТА["видно"]) g.RV_КОМНАТА["видно"](!!да, "финал");
        }
      } catch (eК) {}
    },
    "кадр": кадр,
    "размер": function () {
      /* Поворот телефона переставляет глаз у пульта: лежачий кадр
         смотрит с двух с половиной метров, стоячий с четырёх. Числа
         пересчитывает сам модуль, а перечитать позу обязан акт. */
      if (g.RV_ФИНАЛ["размер"]) g.RV_ФИНАЛ["размер"]();
      позу();
    }
  };

  function позу() {
    if (!собрано) return;
    if (!g.RV_WORLD || !g.RV_WORLD["поза"] || !g.RV_ФИНАЛ || !g.RV_ФИНАЛ["поза"]) return;
    g.RV_WORLD["поза"]("финал", g.RV_ФИНАЛ["поза"]());
  }

  /* ПОЗА ОБЪЯВЛЯЕТСЯ ТОЛЬКО ПОСЛЕ СБОРКИ, и это не мелочь порядка.
     Пока сцена не собрана, rv-финал.js отдаёт запасную позу в СВОИХ
     координатах, без нашего смещения: мир получил бы точку у начала
     координат и повёл бы туда камеру через весь фильм. Собираем
     первыми, спрашиваем вторыми. */
  function встать() {
    построить(g.RV_WORLD["мир"] ? g.RV_WORLD["мир"]() : null);
    позу();
    g.RV_WORLD["акт"]("финал", МОДУЛЬ);
  }

  /* Поворот телефона слушаем ОТДЕЛЬНО от мира. Мир ловит только
     «resize» и «resize» видимой области, а на части телефонов при
     повороте раньше них приходит «orientationchange», и один кадр
     панель успевает встать по старым числам: глубина глаза у пульта
     считается от отношения сторон. Пересчёт дешёвый (кэш мест и одна
     поза), лишний вызов ничего не стоит. */
  g.addEventListener("orientationchange", function () {
    if (МОДУЛЬ["размер"]) МОДУЛЬ["размер"]();
  });

  if (g.RV_WORLD && g.RV_WORLD["готов"] && g.RV_WORLD["готов"]()) встать();
  else g.addEventListener("rv:мир", встать);
})(window, document);
