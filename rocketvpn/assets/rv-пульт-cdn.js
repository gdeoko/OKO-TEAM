/* Rocket VPN. Мост к пульту соседнего сайта.

   ЗАЧЕМ. Владелец сказал дословно: «когда дошли до панели у нас
   появляется точно такой же по стилю меню в котором вопросы и кнопки
   так же как на сайте КДН просто другой текст другие вопросы другие
   кнопки и другие ссылки а визуально один в один должен быть».

   Меню пульта на соседнем сайте рисует `rc-desk.js`. Он перенесён сюда
   БУКВА В БУКВУ вместе со своими стилями `rc-desk.css` и правиться не
   должен: разойдутся два файла - разойдётся и вид, а владелец просил
   именно один в один. Всё, что отличает наш пульт от соседского,
   объявляется ЗДЕСЬ, снаружи, тремя способами.

   1. ПОДПИСИ. `rc-desk.js` берёт каждую строку через свой `t(ключ,
      запас)`, а тот смотрит в `RC_I18N`. Значит подписи меняются без
      единой правки кода: заголовок справочника и три кнопки объявлены
      ниже.

   2. ДОЛИ КАМЕРЫ. Меню зажигается по `RC_INTERIOR.con()` (подъезд к
      пульту) и гаснет по `RC_INTERIOR.back()` (отход назад). У соседей
      это отдаёт их сцена корабля, у нас таких модулей нет и не будет:
      они тянут за собой второй движок целиком. Обе доли считаются здесь
      из доли нашего акта финала.

   3. ДЕЙСТВИЯ КНОПОК. У соседей это звонок, заявка и полёт. У нас
      запуск VPN, игра и возврат. Нажатия перехватываются на слое пульта
      по признаку `data-go`, до того как до них доберётся родной
      обработчик.

   ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Оборота на 360 и текста на стенах салона.
   Владелец: «внутри салона ракеты когда мы уже вошли там нету оборота
   на 360 то есть на стенах там текст никакой не висит мы просто заходим
   в открывающиеся двери и уже сразу идём прямо никуда не поворачивая
   идём прямо к панели». Поэтому соседские `rc-interior.js` и
   `rc-cockpit.js`, которые как раз про оборот и коридор, сюда не
   переносятся вовсе - только их две доли, и те считаются заново. */
(function (g, d) {
  "use strict";

  /* ── 1. ПОДПИСИ ────────────────────────────────────────────────
     Ключи те же, что у соседей, значения наши. Список полный: любой
     ключ, который `rc-desk.js` спрашивает, обязан быть здесь, иначе
     на пульте вылезет запасная строка про CDN. */
  var НАШИ = {
    "faq.h": "Частые вопросы",
    "cta.callback": "Запустить VPN",
    "ct.send": "Запустить игру",
    "epi.btn": "Назад",
    "ui.back": "Назад",
    /* Эти два ключа сосед показывает над формами, которые он забирает
       со страницы. Форм на пульте VPN нет, но ключи объявлены: пустой
       ответ `t()` вернул бы запасную строку про проект CDN. */
    "cb.h": "Оставить заявку",
    "ct.h": "Написать нам"
  };

  if (!g.RC_I18N) g.RC_I18N = {};
  if (!g.RC_I18N.ru) g.RC_I18N.ru = {};
  for (var к in НАШИ) {
    if (Object.prototype.hasOwnProperty.call(НАШИ, к) && g.RC_I18N.ru[к] == null) {
      g.RC_I18N.ru[к] = НАШИ[к];
    }
  }

  /* ── 2. ДОЛИ КАМЕРЫ ────────────────────────────────────────────
     `con` это подъезд к пульту, ноль в начале акта и единица у самого
     стекла. `back` это отход назад, у нас его НЕТ вовсе: панель это
     конец ленты, дальше не скроллится ничего (прямое слово владельца),
     и камера от пульта не отъезжает. Поэтому `back` всегда ноль.

     Порог подъезда взят из самого `rc-desk.js`: он зажигает голограмму
     на (con - 0.62) / 0.34, то есть в последней трети. Наша доля идёт
     ровно так же от нуля до единицы, и пересчитывать её не нужно. */
  var ПОДЪЕЗД_ОТ = 0.34;   /* до этой доли акта человек ещё в дверях */

  function доляФинала() {
    try {
      if (g.RV_MOTION && g.RV_MOTION["доля"]) {
        var д = g.RV_MOTION["доля"]("финал");
        if (typeof д === "number") return д < 0 ? 0 : (д > 1 ? 1 : д);
      }
    } catch (e) {}
    return 0;
  }

  if (!g.RC_INTERIOR) {
    g.RC_INTERIOR = {
      "con": function () {
        var д = доляФинала();
        if (д <= ПОДЪЕЗД_ОТ) return 0;
        return (д - ПОДЪЕЗД_ОТ) / (1 - ПОДЪЕЗД_ОТ);
      },
      "back": function () { return 0; }
    };
  }

  /* ── 3. ДЕЙСТВИЯ КНОПОК ────────────────────────────────────────
     Слой пульта собирается позже нас, поэтому слушаем на документе и
     ловим на всплытии. Признак `data-go` ставит сам `rc-desk.js`:
     `call` первая кнопка, `lead` вторая, `fly` третья. Мы их не
     переименовываем - переименование means правка чужого файла. */
  var АДРЕСА = {
    "call": null,   /* запуск VPN: адрес бота берётся из досье продукта */
    "lead": null,   /* игра живёт на этой же странице */
    "fly": null     /* возврат наверх */
  };

  function ботВПН() {
    try {
      var D = g.RV_DATA;
      if (D && D["связь"] && D["связь"]["бот"]) return D["связь"]["бот"];
    } catch (e) {}
    return "https://t.me/RocketCompanyVPN_bot";
  }

  d.addEventListener("click", function (со) {
    var ц = со.target;
    if (!ц || !ц.closest) return;
    var кн = ц.closest("[data-go]");
    if (!кн) return;
    var слой = кн.closest(".rc-desk");
    if (!слой) return;          /* чужая кнопка с тем же признаком */
    var что = кн.getAttribute("data-go");

    if (что === "call") {
      со.preventDefault(); со.stopPropagation();
      try { g.open(ботВПН(), "_blank", "noopener,noreferrer"); } catch (e) {}
      return;
    }
    if (что === "lead") {
      со.preventDefault(); со.stopPropagation();
      /* Игра стоит на этой же странице и открывается своим модулем. */
      try {
        if (g.RV_ПАНЕЛЬ_КНОПКИ && g.RV_ПАНЕЛЬ_КНОПКИ["игра"]) g.RV_ПАНЕЛЬ_КНОПКИ["игра"]();
        else g.location.hash = "#rvИгра";
      } catch (e) {}
      return;
    }
    if (что === "fly") {
      со.preventDefault(); со.stopPropagation();
      try { g.scrollTo({ top: 0, behavior: "smooth" }); } catch (e) { g.scrollTo(0, 0); }
    }
  }, true);

  /* ── 4. ОТВЕТЫ РАСКРЫВАЮТСЯ ────────────────────────────────────
     На соседнем сайте раскрытием заведует rc-app.js, а он весит
     семьдесят пять килобайт и тянет пол-сайта. Здесь то же поведение
     в пятнадцати строках: нажали вопрос - открыли ответ, нажали
     повторно - закрыли, соседний при этом закрывается.

     Признаки доступности ставятся честно: `aria-expanded` на кнопке и
     `inert` на области ответа. Без них список читается голосовым
     помощником как восемь одинаковых кнопок без содержимого. */
  d.addEventListener("click", function (со) {
    var ц = со.target;
    if (!ц || !ц.closest) return;
    var кн = ц.closest(".faq-q");
    if (!кн) return;
    var гнездо = кн.closest(".faq-i");
    if (!гнездо) return;
    var ответ = гнездо.querySelector(".faq-a");
    if (!ответ) return;
    со.preventDefault();
    var открыт = кн.getAttribute("aria-expanded") === "true";
    var список = гнездо.parentNode;
    if (список && !открыт) {
      var все = список.querySelectorAll(".faq-i");
      for (var i = 0; i < все.length; i++) {
        var к2 = все[i].querySelector(".faq-q"), о2 = все[i].querySelector(".faq-a");
        if (к2) к2.setAttribute("aria-expanded", "false");
        if (о2) { о2.setAttribute("inert", ""); все[i].classList.remove("faq-открыт"); }
      }
    }
    кн.setAttribute("aria-expanded", открыт ? "false" : "true");
    if (открыт) { ответ.setAttribute("inert", ""); гнездо.classList.remove("faq-открыт"); }
    else { ответ.removeAttribute("inert"); гнездо.classList.add("faq-открыт"); }
  }, false);

  /* ── 5. СТАРАЯ КАРТОЧКА УХОДИТ, КОГДА ПРИШЁЛ ПУЛЬТ ─────────────
     До переноса пульта вопросы и кнопки рисовала своя карточка
     (`.рв-фин-впр` в разметке). Обе разом дают то, что видно на
     снимке: два списка вопросов внахлёст и два ряда кнопок.

     Убирать её из разметки насовсем нельзя. Во-первых, в ней живут
     гнёзда `data-заполнить` с тарифами, точками и шагами установки -
     это половина товара. Во-вторых, она работает без объёмной графики
     вовсе, а пульт соседей без неё не собирается: человек с отключённым
     WebGL остался бы у пустого экрана.

     Поэтому карточка не удаляется, а УСТУПАЕТ: как только слой пульта
     собрался, на корне документа встаёт признак, и правило стилей
     убирает старую. Не собрался - всё остаётся как было. */
  var ПРИЗНАК = "рв-пульт-cdn";
  function следитьЗаПультом() {
    var было = false;
    function проверить() {
      var есть = !!d.querySelector(".rc-desk");
      if (есть === было) return;
      было = есть;
      try { d.documentElement.classList.toggle(ПРИЗНАК, есть); } catch (e) {}
    }
    проверить();
    /* ОПРОС, А НЕ НАБЛЮДАТЕЛЬ, И ЭТО ПРОВЕРЕНО ЗАМЕРОМ. Здесь стоял
       MutationObserver на теле документа без обхода поддерева, и он не
       срабатывал ни разу: слой пульта собирается не прямым потомком
       тела и появляется только на подходе к финалу, то есть много позже
       нас. Замер показал `слойDsk: false` при живом мосте и видимой
       старой карточке.

       Наблюдатель с обходом всего поддерева ловил бы КАЖДУЮ правку
       разметки на сайте, а их тут сотни в секунду: слова акта, карточки,
       переменные оформления. Опрос раз в полсекунды стоит одной проверки
       селектора и не зависит от того, куда именно слой встанет. */
    g.setInterval(проверить, 500);
  }
  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", следитьЗаПультом);
  else следитьЗаПультом();

  g.RV_ПУЛЬТ_CDN = {
    "подписи": function () { return НАШИ; },
    "замер": function () {
      var слой = d.querySelector(".rc-desk");
      return {
        "слой": !!слой,
        "виден": !!(слой && слой.offsetParent !== null),
        "подъезд": Math.round(g.RC_INTERIOR["con"]() * 1000) / 1000,
        "вопросов": d.querySelectorAll("#faqList .faq-i").length,
        "кнопок": слой ? слой.querySelectorAll("[data-go]").length : 0
      };
    }
  };
})(window, document);
