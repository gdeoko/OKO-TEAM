/* ОДИН ВОПРОС ВИДЕОКАРТЕ НА ВЕСЬ САЙТ.

   Вердикт «слабая карта» нужен трём разным местам, и каждое решало
   по-своему:

     · rc-fallback.js  ступень качества игры - по памяти и ядрам;
     · rc-rocket.js    качество ракеты       - по памяти и ядрам;
     · rc-gl.js        когда грузить объёмный слой - по карте, но
                       вердикт складывался в локальный флаг и наружу
                       не выходил.

   Отсюда дыра, о которой писал заказчик. Дешёвый телефон вроде Infinix
   несёт восемь ядер и четыре гигабайта при графике начального уровня:
   по памяти и ядрам он середняк, по видеокарте слабый. Полный буфер и
   полные частицы на такой карте дают двадцать-тридцать кадров.

   Списков моделей должно быть РОВНО ОДИН. Два списка в двух файлах
   расходятся молча: правку вносят в один, второй продолжает считать
   по-старому, и наружу это выходит не ошибкой, а разным поведением
   одной и той же машины на двух экранах сайта.

   ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ФУНКЦИЯ В СОСЕДНЕМ. Вердикт спрашивают
   и в самом начале страницы (ступень качества стоит в шапке, до
   отрисовки), и сильно позже (объёмный слой едет отложенно). Общий
   предок у них только документ, поэтому модуль подключается первым и
   синхронно, а весит он меньше килобайта. У соседнего сайта игра
   живёт отдельной страницей без rc-fallback вовсе, и там этот файл -
   единственный, кто карту спрашивает.

   ПРОБА СТОИТ ОДИН КОНТЕКСТ И СРАЗУ ЖЕ ЕГО ОТДАЁТ. Контекст WebGL не
   бесплатный: браузер держит их ограниченное число, и забытый
   съедает место у настоящей сцены. Гасим его вручную.

   ИМЯ КАРТЫ БЫВАЕТ ЗАКРЫТО (приватное окно, Safari, часть сборок
   Firefox). Тогда вердикт ЛОЖЬ, а не «слабая»: чужое железо по
   умолчанию считаем исправным. Иначе мы срежем качество всем, кто
   просто закрыл имя карты, - а таких больше, чем слабых телефонов.

   Наружу:  RC_СЛАБАЯ_КАРТА   true только при УЗНАННОЙ слабой карте
            RC_ИМЯ_КАРТЫ      строка как её назвал драйвер, для отладки
*/
(function (g) {
  "use strict";
  if (typeof g.RC_СЛАБАЯ_КАРТА === "boolean") return;

  /* Семейства, которые в живых замерах не вытягивают полноэкранный
     WebGL на плотном экране. Список НЕ полный перечень слабых карт, а
     те, что стоят в дешёвых телефонах и встречаются в трафике чаще
     прочих.

     Здесь сведены два списка, которые жили порознь: у соседнего сайта
     (rv-world.js) он был полнее - младшие Mali с одним и двумя блоками
     исполнения, встроенная графика Intel старых поколений.

     ЧТО ИЗ ТОГО СПИСКА СЮДА НЕ ПЕРЕЕХАЛО И ПОЧЕМУ. Там стояло
     `angle \(google`, и это ложное срабатывание: так подписывается не
     только программная отрисовка, но и НАСТОЯЩАЯ карта, когда Chrome
     идёт через Vulkan - «ANGLE (Google, Vulkan 1.1.128 (Mali-G78...))».
     По этой строке флагманский Pixel попадал в слабые. Программную
     отрисовку и без неё видно по слову swiftshader. */
  var СЛАБЫЕ = [
    /* Mali-G52 MC2, G57 MC1, G37, G31 и соседи по классу */
    /mali-?g(31|37|51|52|57)\b/,
    /mali-?g(3[0-9]|5[0-9]|6[0-8])\b.*(mc1|mc2|\bmp1\b|\bmp2\b)/,
    /mali-?(t6|t7|t8|450|400)/,
    /* PowerVR начального уровня */
    /powervr.*(ge8|ge7|rogue ge)/,
    /* Adreno до 610: всё, что ниже, тоже сюда */
    /adreno.*\b(3[0-9]{2}|4[0-9]{2}|5[0-9]{2}|60[0-9]|610)\b/,
    /* Встроенная графика Intel старых поколений */
    /intel.*(hd graphics (3000|4000|4400|500|510|520|530)|uhd graphics 6[01]0)/,
    /* Отрисовка без видеокарты вовсе */
    /swiftshader|llvmpipe|software renderer|microsoft basic render/
  ];

  var имя = "";
  try {
    var к = document.createElement("canvas");
    var гл = к.getContext("webgl") || к.getContext("experimental-webgl");
    var р = гл && гл.getExtension("WEBGL_debug_renderer_info");
    if (р) имя = String(гл.getParameter(р.UNMASKED_RENDERER_WEBGL) || "");
    var пот = гл && гл.getExtension("WEBGL_lose_context");
    if (пот) пот.loseContext();
  } catch (e) { имя = ""; }

  var н = имя.toLowerCase();
  var слабая = false;
  if (н) {
    for (var i = 0; i < СЛАБЫЕ.length; i++) {
      if (СЛАБЫЕ[i].test(н)) { слабая = true; break; }
    }
  }

  g.RC_ИМЯ_КАРТЫ = имя;
  g.RC_СЛАБАЯ_КАРТА = слабая;
})(window);
