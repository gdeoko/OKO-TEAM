/* Rocket VPN. Чертёжная сетка загрузки.

   ЗАЧЕМ. Владелец: «у них ещё есть какая-то сетка рисованная красивая
   анимационная при загрузочном экране, посмотри тоже».

   ЧТО У НИХ. Разобрано по четырём его снимкам загрузки igloo. Пока мир
   собирается, весь кадр накрыт РАВНОСТОРОННЕЙ ТРЕУГОЛЬНОЙ СЕТКОЙ:
   тонкие белые линии в изометрии, у части узлов двузначные числа, часть
   ячеек подсвечена ярче. Сетка не статична - линии проступают волной
   слева направо, числа перещёлкиваются, отдельные узлы вспыхивают
   засечкой. Поверх неё сперва идёт каркас дома (одни рёбра), потом дом
   проявляется материалом, и сетка гаснет последней.

   Читается это как чертёж, по которому мир собирают у тебя на глазах, и
   именно поэтому оно и работает: загрузка перестаёт быть ожиданием.

   КАК ЗДЕСЬ. Двумерный холст поверх сцены. Не WebGL намеренно: во время
   загрузки видеокарта занята сборкой мира, шейдерами и картами, и
   отбирать у неё кадры ради заставки значит удлинять саму загрузку.
   Линии рисуются обычным путём по канве, это стоит доли миллисекунды.

   ЖИЗНЬ. Появляется сразу с открытием страницы, живёт всю сборку и весь
   прилёт камеры, гаснет по «rv:вступление-конец» за 0.9 секунды.

   API:
     RV_СЕТКА.показать(да)
     RV_СЕТКА.замер() */
(function (g, d) {
  "use strict";

  /* ШАГ СЕТКИ. У них на снимке телефона (920 точек в ширину) по ширине
     умещается около шести ячеек, то есть сторона треугольника примерно
     155 точек. Держим ту же долю от короткой стороны кадра, поэтому на
     мониторе ячейка крупнее по числу точек и той же доли по кадру. */
  var ДОЛЯ_ЯЧЕЙКИ = 0.168;
  /* Волна проявления: сколько секунд идёт от левого края к правому. */
  /* 0.9, а не 1.7. Волна обязана ДОЙТИ до правого края раньше, чем
     кончится загрузка: замер поймал, что мир на быстрой машине готов уже
     через 1.3 секунды, и чертёж успевал проступить только на левой
     половине кадра - выглядело как незакрашенный угол, а не как
     чертёж. */
  var ВОЛНА = 0.9;
  /* Гашение по концу вступления. */
  var ГАШЕНИЕ = 0.9;

  var холст = null, кт = null;
  var идёт = false, гаснет = 0, время = 0;
  var кадрТаймер = 0;
  var узлы = [];
  var ш = 0, в = 0, шагX = 0, шагY = 0;

  function зажать(v, н, вв) { return v < н ? н : (v > вв ? вв : v); }

  /* ── Узлы ─────────────────────────────────────────────────────
     Сетка равносторонняя: шаг по горизонтали это сторона треугольника,
     по вертикали - её высота (корень из трёх пополам), нечётные ряды
     сдвинуты на полшага. Числа и яркость узла берутся ДЕТЕРМИНИРОВАННО
     от его места: при перерисовке они обязаны остаться теми же, иначе
     сетка мерцает целиком, а не отдельными узлами. */
  function хэш(x, y) {
    var s = Math.sin(x * 127.1 + y * 311.7) * 43758.5453;
    return s - Math.floor(s);
  }

  function собратьУзлы() {
    узлы = [];
    шагX = Math.max(48, Math.round(Math.min(ш, в) * ДОЛЯ_ЯЧЕЙКИ));
    шагY = Math.round(шагX * 0.8660254);
    var рядов = Math.ceil(в / шагY) + 2;
    var встроке = Math.ceil(ш / шагX) + 2;
    for (var р = -1; р < рядов; р++) {
      for (var с = -1; с < встроке; с++) {
        var сдв = (р % 2) ? шагX * 0.5 : 0;
        var x = с * шагX + сдв, y = р * шагY;
        var h = хэш(с, р);
        узлы.push({
          x: x, y: y,
          /* Число у узла: две цифры, как у них. Показываются не у всех -
             сетка с числом в каждом узле читается таблицей. */
          число: h < 0.34 ? (10 + Math.floor(хэш(с + 7.1, р - 3.3) * 89)) : 0,
          /* Засечка: короткий крест, отмечающий узел. */
          крест: h > 0.86,
          /* Собственная фаза мерцания. */
          фаза: хэш(с - 2.7, р + 5.1) * 6.28
        });
      }
    }
  }

  function размер() {
    if (!холст) return;
    var п = Math.min(2, g.devicePixelRatio || 1);
    ш = g.innerWidth || 1; в = g.innerHeight || 1;
    холст.width = Math.round(ш * п);
    холст.height = Math.round(в * п);
    холст.style.width = ш + "px";
    холст.style.height = в + "px";
    кт.setTransform(п, 0, 0, п, 0, 0);
    собратьУзлы();
  }

  /* ── Рисование ────────────────────────────────────────────────
     Волна проявления идёт слева направо: у линии, чей левый конец ещё не
     дошёл до фронта волны, прозрачность ноль. Фронт мягкий - иначе
     виден край, ползущий по кадру, а нужен именно проступающий чертёж. */
  function рисовать() {
    if (!кт) return;
    кт.clearRect(0, 0, ш, в);
    var общая = гаснет > 0 ? зажать(1 - гаснет / ГАШЕНИЕ, 0, 1) : 1;
    if (общая <= 0.001) return;
    var фронт = зажать(время / ВОЛНА, 0, 1) * (ш + шагX * 2) - шагX;

    кт.lineWidth = 1;
    кт.font = Math.round(шагX * 0.085) + "px ui-monospace, SFMono-Regular, Menlo, monospace";
    кт.textAlign = "left";
    кт.textBaseline = "middle";

    for (var i = 0; i < узлы.length; i++) {
      var у = узлы[i];
      var видим = зажать((фронт - у.x) / (шагX * 1.6), 0, 1);
      if (видим <= 0.002) continue;
      /* Мерцание узла: медленное дыхание с собственной фазой. */
      var пульс = 0.72 + 0.28 * Math.sin(время * 1.6 + у.фаза);
      var а = видим * общая * пульс;

      /* Три луча из узла: вправо, вправо-вниз и влево-вниз. Этими тремя
         и замыкается равносторонняя сетка, четвёртый был бы повтором
         соседского. */
      кт.strokeStyle = "rgba(226, 236, 255, " + (а * 0.30).toFixed(3) + ")";
      кт.beginPath();
      кт.moveTo(у.x, у.y); кт.lineTo(у.x + шагX, у.y);
      кт.moveTo(у.x, у.y); кт.lineTo(у.x + шагX * 0.5, у.y + шагY);
      кт.moveTo(у.x, у.y); кт.lineTo(у.x - шагX * 0.5, у.y + шагY);
      кт.stroke();

      if (у.крест) {
        var р = шагX * 0.055;
        кт.strokeStyle = "rgba(236, 243, 255, " + (а * 0.85).toFixed(3) + ")";
        кт.beginPath();
        кт.moveTo(у.x - р, у.y); кт.lineTo(у.x + р, у.y);
        кт.moveTo(у.x, у.y - р); кт.lineTo(у.x, у.y + р);
        кт.stroke();
      }
      if (у.число) {
        кт.fillStyle = "rgba(214, 226, 250, " + (а * 0.55).toFixed(3) + ")";
        кт.fillText(String(у.число), у.x + шагX * 0.075, у.y - шагX * 0.055);
      }
    }
  }

  function шаг(т) {
    if (!идёт) return;
    var dt = кадрТаймер ? Math.min(0.1, (т - кадрТаймер) / 1000) : 0.016;
    кадрТаймер = т;
    время += dt;
    if (проситьГашение && гаснет <= 0 && время >= МИНИМУМ) {
      проситьГашение = false;
      гаснет = ГАШЕНИЕ;
    }
    if (гаснет > 0) {
      гаснет -= dt;
      if (гаснет <= 0) { снять(); return; }
    }
    рисовать();
    g.requestAnimationFrame(шаг);
  }

  function поднять() {
    if (холст) return;
    холст = d.createElement("canvas");
    холст.className = "rv-сетка";
    холст.setAttribute("aria-hidden", "true");
    кт = холст.getContext("2d");
    d.body.appendChild(холст);
    размер();
    g.addEventListener("resize", размер, { passive: true });
    идёт = true;
    кадрТаймер = 0;
    g.requestAnimationFrame(шаг);
  }

  function снять() {
    идёт = false;
    if (холст && холст.parentNode) холст.parentNode.removeChild(холст);
    холст = null; кт = null;
    g.removeEventListener("resize", размер);
  }

  /* Минимальная жизнь чертежа. На быстрой машине мир готов за секунду с
     небольшим, и сетка, погашенная по готовности, мелькала бы вспышкой:
     человек не успел бы понять, что видел. Две с половиной секунды это
     нижняя граница, на которой приём читается. */
  var МИНИМУМ = 2.5;
  var проситьГашение = false;
  function погасить() {
    if (!идёт || гаснет > 0) return;
    if (время < МИНИМУМ) { проситьГашение = true; return; }
    гаснет = ГАШЕНИЕ;
  }

  /* Поднимаемся сразу: сетка нужна ДО того, как соберётся мир, в этом
     весь её смысл. Гаснет по концу вступления, а если вступления не
     случилось вовсе - по страховке в девять секунд, чтобы не остаться
     чертежом навсегда. */
  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", поднять);
  else поднять();
  g.addEventListener("rv:вступление-конец", погасить);
  g.setTimeout(погасить, 9000);

  g.RV_СЕТКА = {
    "показать": function (да) { if (да) поднять(); else погасить(); },
    "замер": function () {
      return {
        "идёт": идёт, "узлов": узлы.length, "шаг": шагX,
        "время": +время.toFixed(2), "гаснет": +гаснет.toFixed(2)
      };
    }
  };
})(window, document);
