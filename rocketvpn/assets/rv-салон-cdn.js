/* Rocket VPN. Салон финала - тот самый, что у соседей, без единой правки.

   ЗАЧЕМ ЭТОТ ФАЙЛ ЕСТЬ. Владелец сказал дословно: «зайди в файлы и код
   сайта cdn и скопируй ctrl c ctrl v из сайта cdn в сайт vpn всю
   финальную сцену с ракетой и вход в неё и подход к панели. финальная
   сцена сайтов cdn VPN 1:1 без отличий скопировать вставить просто.
   только на сайте vpn вырезать 360 оборот с карточками на стенах».

   До сих пор салон VPN был ПЕРЕСКАЗОМ соседского: те же числа, свои
   руки. Пересказ расходится с оригиналом на каждой правке, и именно это
   владелец и видел - «финальная сцена все ещё не такая как в CDN».

   Поэтому салон больше не пересказывается. Рядом лежат настоящие файлы
   соседей, скопированные как есть:

     assets/rc-cabin.js       обшивка, настил, потолок, экраны, свет
     assets/rc-panel.js       пульт со снимка рубки
     assets/rc-keys.js        клавиши пульта
     assets/rc-deck.js        раскладка приборов
     assets/gen/cab/*         паспорта и текстуры рубки

   Менять их НЕЛЬЗЯ. Разошлись с соседями - копировать оттуда заново,
   а разницу держать здесь, в этом файле: он один знает, чем мир VPN
   отличается от мира CDN.

   ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ. Ровно три вещи.

   1. Подкладывает соседским модулям RC_REAL. У них он свой, у нас
      RV_REAL, и без переходника пульт собирается без отражений и без
      плёнки - то есть плоским. Переходник отдаёт им наш рисовальщик и
      наше окружение.

   2. Зовёт RC_CABIN.build с нашими долями кадра.

   3. Гасит оборот. У соседей по стене стоят семь экранов с текстом, и
      камера обходит их полным кругом. Владелец этот оборот на VPN
      отменил: «на Vpn только в конце вопросы и кнопки как на сайте cdn
      1:1». Экраны снимаются, стена остаётся стеной.

   API:
     RV_САЛОН_CDN.есть()            -> модули соседей доехали
     RV_САЛОН_CDN.собрать(T, о)     -> объект сборки RC_CABIN или null
     RV_САЛОН_CDN.замер() */
(function (g) {
  "use strict";

  // RC_CABIN builds Phong materials, then asks this adapter to upgrade them.
  // Supplying only renderer/env silently skipped that step on the VPN site.
  function upgradeTree(T, root, rules) {
    if (!root) return 0;
    var made = new Map(), spent = new Set();
    root.traverse(function (mesh) {
      if (!mesh.isMesh || !mesh.material) return;
      function convert(old) {
        if (!old || (!old.isMeshPhongMaterial && !old.isMeshLambertMaterial)) return old;
        var hint = rules ? rules(mesh, old) : {};
        if (hint === false) return old;
        hint = hint || {};
        var key = old.uuid + ":" + JSON.stringify(hint);
        if (made.has(key)) return made.get(key);
        var material = new T.MeshStandardMaterial({
          color: old.color, roughness: hint.roughness == null ? 0.5 : hint.roughness,
          metalness: hint.metalness == null ? 0.5 : hint.metalness,
          envMapIntensity: hint.envMapIntensity == null ? 1 : hint.envMapIntensity,
          map: old.map, alphaMap: old.alphaMap, bumpMap: old.bumpMap,
          bumpScale: old.bumpScale, normalMap: old.normalMap,
          emissive: old.emissive, emissiveMap: old.emissiveMap,
          emissiveIntensity: old.emissiveIntensity == null ? 1 : old.emissiveIntensity,
          transparent: old.transparent, opacity: old.opacity, side: old.side,
          depthWrite: old.depthWrite, depthTest: old.depthTest, alphaTest: old.alphaTest,
          fog: old.fog, vertexColors: old.vertexColors, toneMapped: old.toneMapped,
          polygonOffset: old.polygonOffset, polygonOffsetFactor: old.polygonOffsetFactor,
          polygonOffsetUnits: old.polygonOffsetUnits
        });
        if (old.normalScale) material.normalScale.copy(old.normalScale);
        material.name = old.name;
        made.set(key, material); spent.add(old);
        return material;
      }
      mesh.material = Array.isArray(mesh.material) ? mesh.material.map(convert) : convert(mesh.material);
    });
    spent.forEach(function (material) { material.dispose(); });
    return made.size;
  }

  /* ── Переходник к нашей физике ────────────────────────────────
     rc-panel читает у RC_REAL ровно два поля: рисовальщик (ему нужен
     предел анизотропии) и окружение (карта отражений). rc-cabin ещё
     умеет позвать upgradeTree, но зовёт его через проверку, поэтому
     без него собирается честно и просто остаётся на своих материалах.

     Мы не подсовываем сюда RV_REAL целиком: у него другой набор имён,
     и соседский код полез бы в поля, которых нет. Отдаём то, что он
     спрашивает, и ничего сверх. */
  function переходник() {
    if (g.RC_REAL) return;
    var W = g.RV_WORLD;
    /* ── ИМЕНА ПОЛЕЙ МИРА ЛАТИНСКИЕ, А НЕ РУССКИЕ ─────────────────
       Здесь стояло `.рисовальщик` и `.сцена`, и оба поля НЕ
       СУЩЕСТВУЮТ: объект мира объявлен в rv-world.js строкой 51 и несёт
       `r`, `scene`, `cam`, `часы`, `ступень`, `акты`. Геттеры молча
       отдавали null - у них свой try/catch, - и соседский пульт
       собирался без предела анизотропии и без карты отражений.

       Это и есть одна из причин, по которой финал «всё ещё не 1:1 с
       CDN»: у соседей приборы держат отражение павильона и резкую
       наклонную текстуру, у нас те же меши стояли матовыми и мыльными.
       Проверено чтением: RV_WORLD["мир"]() возвращает именно W. */
    g.RC_REAL = {
      upgradeTree: upgradeTree,
      get renderer() {
        try { var м = W && W["мир"](); return м ? м.r : null; } catch (e) { return null; }
      },
      get env() {
        try {
          var м2 = W && W["мир"]();
          return м2 && м2.scene ? м2.scene.environment : null;
        } catch (e) { return null; }
      }
    };
  }

  /* Число точек присутствия соседи печатают на одном из экранов рубки.
     Экраны мы снимаем, но модуль спрашивает это число при сборке, и
     без ответа он падать не должен. */
  function геометрия() {
    if (!g.RC_GEO) g.RC_GEO = { COUNT: 218 };
  }

  /* Палитра корабля у соседей общая для рубки, ракеты и стойки. У нас
     та же: чёрный корпус, стальные рёбра, циан и фиолет на приборах. */
  /* ПАЛИТРА ВЗЯТА У СОСЕДЕЙ ЦЕЛИКОМ, ДЕВЯТЬ ЦВЕТОВ ИЗ ДЕВЯТИ.
     Здесь стояло пять, и три из них были ПЕРЕКРАШЕНЫ: panel 0x101d2b
     вместо 0x060d14, steel 0x6e829a вместо 0x566675. Четырёх не было
     вовсе: deep, hull, wall и warm. Владелец просил финал один в один с
     соседним сайтом, а корпус, стены и тёплый свет приборов брались с
     потолка - отсюда и «ракета стала цветной».

     Числа скопированы из rocketcdn/assets/rc-rocket.js (RC_SHIP_STYLE)
     буква в букву. Расходиться им нельзя: это один и тот же корабль. */
  function палитра() {
    if (!g.RC_SHIP_STYLE) {
      g.RC_SHIP_STYLE = {
        deep: 0x02060a,
        hull: 0x101923,
        wall: 0x182633,
        panel: 0x060d14,
        steel: 0x566675,
        cyan: 0x5fc8ef,
        cyanSoft: 0x9fe0f6,
        violet: 0xa974f5,
        warm: 0xffa85c
      };
    }
  }

  /* ── СНИМКИ РУБКИ ЛЕЖАТ У НАС ПО ДРУГОМУ АДРЕСУ ────────────────
     Паспорт плоской рамы соседей (gen/cab/flat.js) указывает на
     assets/gen/cockpit-*.webp. У нас те же самые файлы, байт в байт (я
     сверила md5), лежат в assets/gen/каб/ - они приехали сюда раньше, с
     нашим собственным портом пульта.

     Копировать их вторым комплектом нельзя: приёмка меряет вес
     страницы, предел шесть мегабайт, и три лишних снимка по сто с
     лишним килобайт его пробивали. Править сам паспорт тоже нельзя, в
     его шапке написано «собран tools/cabflat.py, руками не править», и
     следующее копирование от соседей вернуло бы старые пути молча.

     Поэтому адреса подменяются ЗДЕСЬ, на месте, один раз перед сборкой.
     Файл соседей остаётся их файлом, а знание о нашей раскладке живёт в
     нашем. */
  var путиПоправлены = false;
  function поправитьПути() {
    if (путиПоправлены) return;
    путиПоправлены = true;
    var M = g.RC_CAB_FLAT;
    if (!M) return;
    for (var к in M) {
      if (!Object.prototype.hasOwnProperty.call(M, к)) continue;
      var м = M[к];
      if (м && typeof м["файл"] === "string") {
        м["файл"] = м["файл"].replace("assets/gen/cockpit-", "assets/gen/каб/cockpit-");
      }
    }
  }

  /* ── ДИСТАНЦИЯ ПАНЕЛИ: ФУНКЦИЯ СОСЕДЕЙ, ПЕРЕНЕСЁННАЯ ЦЕЛИКОМ ───
     rc-cabin режет проём под пульт по числу opts["dПан"] (rc-cabin.js,
     строка 1008). Мы его не передавали вовсе, и модуль брал запасные
     0.86 - то есть проём считался НЕ ПО НАШЕМУ кадру. Окно и панель
     расходились, и по краям панели показывалась обшивка.

     У соседей это число считает панельD (rc-flight.js, строка 10927).
     Сам rc-flight мы не грузим, он на десять тысяч строк и тянет за
     собой весь их полёт. Функция перенесена сюда БЕЗ ЕДИНОЙ ПРАВКИ по
     смыслу: те же пределы по дуге обшивки, по высоте рубки и по тому,
     чтобы кромка кадра не ушла ниже настила. Всё, что ей нужно
     (RC_DECK, RC_CAB_FLAT, RC_PANEL), у нас загружено.

     Разойтись с соседями она может только вместе с ними: правится там,
     копируется сюда. */
  function панельD(Ш, В, поле) {
    var тан = Math.tan((поле * Math.PI / 180) / 2);
    var Hк = 2 * 0.86 * тан;                 /* запасной прежний размер */
    try {
      var вид = g.RC_DECK["какой"](Ш, В);
      var мета = g.RC_CAB_FLAT[вид] || g.RC_CAB_FLAT["широкая"];
      var пк = g.RC_DECK["покрытие"](мета, Ш, В);
      var кб = мета["коробка"];
      var Rст = (g.RC_PANEL && g.RC_PANEL.R_WALL) || 3.05;
      var хорда = 2 * Rст * Math.sin(0.70);          /* сорок градусов */
      var долW = Math.max(0.05, (кб.r - кб.l)) * (пк.dw / В);
      var поДуге = хорда / долW;
      var поВысоте = 4.2 * 1.02 / (пк.dh / В);
      Hк = Math.max(2 * 0.86 * тан, Math.min(поДуге, поВысоте));
      var Eгл = (g.RC_PANEL && g.RC_PANEL.EYE) || 1.62;
      var зазор = 0.06;
      var поНизу = (Eгл - зазор) / тан;
      var поВерху = (4.2 - Eгл - зазор) / тан;
      var Dмакс = Math.min(1.55, поНизу, поВерху);
      if ((Hк / 2) / тан > Dмакс) Hк = 2 * Dмакс * тан;
    } catch (eП) {}
    return (Hк / 2) / тан;
  }

  function есть() {
    return !!(g.RC_CABIN && g.RC_CABIN.build);
  }

  var последний = null;

  function собрать(T, о) {
    if (!есть()) return null;
    переходник();
    геометрия();
    палитра();
    поправитьПути();
    о = о || {};

    var Ш = о.width || g.innerWidth || 390;
    var В = о.height || g.innerHeight || 844;
    var узко = Ш < 760;

    var сборка = null;
    try {
      сборка = g.RC_CABIN.build(T, {
        tiny: узко,
        aspect: Ш / Math.max(1, В),
        /* Поле зрения берём НАШЕ, а не соседское. Проём под пульт
           режется проекцией из кресла, и с чужим углом он разойдётся
           с панелью: по краям панели показался бы космос. */
        fov: о.fov || 72,
        /* Дистанция панели: по ней режется проём под пульт. Без неё
           модуль соседей брал свои запасные 0.86, проём считался не по
           нашему кадру, и по краям панели показывалась обшивка. */
        /* Расстояние от глаза до стекла. Мир знает его точно и
           передаёт числом; своя формула остаётся запасной на случай,
           когда зовут без него (например из проверки). */
        "dПан": о["dПан"] > 0 ? о["dПан"] : панельD(Ш, В, о.fov || 72),
        "плотность": Math.min(g.devicePixelRatio || 1, узко ? 1.0 : 2.0),
        /* Отрисовщик нужен модулю, чтобы знать версию WebGL: под
           первой версией текстуры экранов собираются другим сэмплером,
           иначе читаемый текст рубки ужимается вдвое. */
        renderer: (g.RV_WORLD && g.RV_WORLD["мир"] && g.RV_WORLD["мир"]() &&
                   g.RV_WORLD["мир"]().r) || null,
        /* Лицо секции НЕ поджимаем: единица, как у соседей.

           Поджатие 1.28 вводилось, когда поле кадра у нас стояло 84
           градуса против соседских 99 на телефоне: узкий угол оставлял
           по краям тёмную обшивку, и лицо растягивали, чтобы рубка
           дошла до кромок. Поле теперь считается той же формулой, что
           у них (rv-финал.js, полеКадра), и поджатие стало лишним: с
           ним пульт вылезал за кадр, а подписи клавиш обрезались по
           краям (снимок телефона 11.09.2026). Один кадр на два сайта
           значит и одни числа. */
        width: Ш, height: В
      });
    } catch (e) {
      сборка = null;
    }
    if (!сборка) return null;

    /* ── ОБОРОТА НА VPN НЕТ ────────────────────────────────────────
       Семь экранов по стене живут ради него: камера идёт по кругу и
       читает их один за другим. Владелец оборот отменил, значит и
       экранам стоять незачем - иначе по стене висят семь табличек,
       мимо которых никто не проходит.

       Гасим показом, а не удалением: соседский модуль держит на них
       ссылки (screens, cassettes, diodes), и вырезанный узел означал
       бы падение на первом же его обращении. */
      var гасить = ["screens", "cassettes", "diodes"];
    for (var i = 0; i < гасить.length; i++) {
      var набор = сборка[гасить[i]];
      if (!набор || !набор.length) continue;
      /* ИМЯ ПОЛЯ У КАЖДОГО НАБОРА СВОЁ, И ЭТО ПРОВЕРЕНО СНИМКОМ.
         Здесь искалось только `mesh`, а семь настенных экранов лежат в
         `screens` записями вида `{ obj, th, tex, i }` - поле называется
         `obj`. Условие не срабатывало ни разу, экраны оставались
         видимыми, и на снимке финала по стенам висели «СПРАВОЧНИК»,
         «Коротко о главном» и список наших же вопросов вторым
         экземпляром.

         Владелец про это сказал прямо: «внутри салона ракеты когда мы
         уже вошли там нету оборота на 360 то есть на стенах там текст
         никакой не висит». Перебираем оба имени и сам элемент. */
      for (var j = 0; j < набор.length; j++) {
        var зап = набор[j];
        if (!зап) continue;
        var у = зап.obj || зап.mesh || зап;
        if (у && у.isObject3D) у.visible = false;
      }
    }

    последний = сборка;
    return сборка;
  }

  g.RV_САЛОН_CDN = {
    "есть": есть,
    "собрать": собрать,
    /* Дистанция панели наружу: по ней финал ставит глаз ровно туда же,
       куда его ставит игра соседей. Пока она жила только внутри этого
       файла, кадр финала считался своими подобранными числами, и два
       сайта показывали один корабль с разных мест. */
    "дистанцияПанели": панельD,
    "замер": function () {
      return {
        "модульСоседей": !!(g.RC_CABIN && g.RC_CABIN.build),
        "пультСоседей": !!(g.RC_PANEL && g.RC_PANEL.build),
        "паспортРубки": !!g.RC_CAB_META,
        "переходник": !!g.RC_REAL,
        "собрано": !!последний,
        "радиус": последний ? последний.R : null,
        "глаз": последний ? последний.eye : null,
        "полуОкна": последний ? +Number(последний.winHalf).toFixed(3) : null
      };
    }
  };
})(window);
