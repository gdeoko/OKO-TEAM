/* Rocket VPN. Слово в мире: заголовки и текст живут в сцене.

   Почему тут вообще есть скрипт. Весь ход слова считается вёрсткой из
   двух чисел, которые уже идут по ленте: доля акта --д и инерция
   камеры --пар-x/--пар-y. Браузеру для этого нужно ровно одно, чего он
   сам не умеет: слово должно быть ОТДЕЛЬНОЙ коробкой со своей маской,
   иначе у восьми узлов акта на всех одна прозрачность и один сдвиг, и
   текст гаснет плитой. Разрезать абзац на слова умеет только скрипт.

   Всё остальное отсюда наружу уходит переменными и делается в
   rv-слово.css. Своего кадрового цикла тут нет намеренно: ещё один
   requestAnimationFrame рядом с миром, плитами и плёнкой это четвёртая
   очередь чтений и записей раскладки на кадр. */
(function (g, d) {
  "use strict";

  /* Признак ставится сразу и синхронно. Он несёт не только анимацию:
     на нём висит вся типографика файла, а она обязана быть на месте
     даже если ниже что-то упадёт. */
  var корень = d.documentElement;
  корень.classList.add("рв-слово");

  var тихо = false;
  try {
    тихо = g.matchMedia && g.matchMedia("(prefers-reduced-motion: reduce)").matches;
  } catch (e) {}
  if (g.RV_WORLD && g.RV_WORLD["тихо"] && g.RV_WORLD["тихо"]()) тихо = true;
  if (тихо) корень.classList.add("рв-слово-тихо");

  /* ── Разрезание ────────────────────────────────────────────────
     Слово кладётся в две коробки. Внешняя это МАСКА: она обрезает всё,
     что вылезло вниз за её край, и потому слово может стоять под ней и
     выезжать. Внутренняя это само слово, ей достаётся сдвиг, поворот и
     размытие.

     Маска обрезана clip-path, а не overflow. Разница не косметическая:
     inline-block с непрозрачным overflow меняет базовую линию строки на
     свой нижний край, и заголовок в две строки после такого разрезания
     уезжает по вертикали. clip-path на раскладку не влияет вовсе.

     Обрезка идёт с запасом сверху и по бокам (полкегля): у заголовка
     неон уходит за габарит буквы, и обрезка по габариту срезала бы ему
     зарево. Снизу запас крошечный - именно снизу слово и прячется. */
  function разрезать(узел, порядок) {
    if (!узел || узел.getAttribute("data-рв-резан")) return 0;
    var ходок = d.createTreeWalker(узел, NodeFilter.SHOW_TEXT, null, false);
    var тексты = [], n;
    while ((n = ходок.nextNode())) if (n.nodeValue && n.nodeValue.trim()) тексты.push(n);
    if (!тексты.length) return 0;

    var слова = [], i, k;
    for (i = 0; i < тексты.length; i++) {
      var т = тексты[i];
      var части = т.nodeValue.split(/(\s+)/);
      var фраг = d.createDocumentFragment();
      for (k = 0; k < части.length; k++) {
        var ч = части[k];
        if (!ч) continue;
        if (/^\s+$/.test(ч)) { фраг.appendChild(d.createTextNode(" ")); continue; }
        var маска = d.createElement("span");
        маска.className = "рв-мск";
        var сл = d.createElement("span");
        сл.className = "рв-сл";
        сл.textContent = ч;
        маска.appendChild(сл);
        фраг.appendChild(маска);
        слова.push(сл);
      }
      т.parentNode.replaceChild(фраг, т);
    }

    /* Вес слова в волне. Порядок 0 значит фронт идёт от первого слова,
       1 от последнего, 0.5 из середины в обе стороны. Считаем здесь, а
       не в вёрстке: в вёрстке для этого нужен модуль разности, а он в
       браузерах этой ленты ещё не везде есть, и правило молча
       перестало бы считаться целиком.

       Обратный вес нужен уходу: слово уходит вверх волной с другого
       конца строки, иначе вход и выход читаются одним движением. */
    var н = слова.length;
    var делитель = Math.max(порядок, 1 - порядок) || 1;
    for (k = 0; k < н; k++) {
      var доля = н > 1 ? k / (н - 1) : 0;
      var в = Math.abs(доля - порядок) / делитель;
      слова[k].style.setProperty("--в", в.toFixed(3));
      слова[k].style.setProperty("--вр", (1 - в).toFixed(3));
      слова[k].style.setProperty("--и", String(k));
    }
    узел.setAttribute("data-рв-резан", "1");
    узел.style.setProperty("--н", String(н));
    return н;
  }

  /* ── Лента технологий ──────────────────────────────────────────
     Горизонтальный ход внутри вертикальной прокрутки. Вёрстка умеет
     ехать долей акта, но не знает, НА СКОЛЬКО ехать: это разница между
     шириной ряда карточек и шириной окна, и она живёт только в
     раскладке. Меряем её здесь и отдаём числом.

     Меряем через scrollWidth контейнера, а не сложением ширин
     карточек: у ряда есть зазоры, поля и своя доля от --rv-поле, и
     сложение по карточкам разошлось бы с правдой на каждой ширине
     экрана по-своему. */
  function померитьЛенту() {
    var гнездо = d.getElementById("rvТех");
    if (!гнездо) return;
    var ряд = гнездо.querySelector(".rv-тех");
    if (!ряд) return;
    /* Признак ставится ДО замера. Пока его нет, ряд стоит сеткой в
       четыре колонки по ширине окна, и мерить в этот момент значит
       мерить старую раскладку: ход всегда выходил бы нулём, и лента
       никогда бы не включилась. */
    гнездо.setAttribute("data-лента", "1");
    var ход = Math.max(0, ряд.offsetWidth - гнездо.clientWidth);
    гнездо.style.setProperty("--лента-ход", Math.round(ход) + "px");
    /* Пока ряд помещается целиком, ехать некуда, и разворот карточек
       без хода читался бы просто кривым рядом. */
    if (ход <= 24) гнездо.setAttribute("data-лента", "0");
  }

  function собрать() {
    var i, узлы;
    /* Заголовок: волна от первого слова. Он читается слева направо, и
       фронт обязан идти в ту же сторону, что и чтение. */
    узлы = d.querySelectorAll(".rv-акт .rv-заг");
    for (i = 0; i < узлы.length; i++) разрезать(узлы[i], 0);
    /* Абзац: фронт из первой четверти. Волна ровно от первого слова на
       сорока словах превращается в бегущую строку, из четверти она
       читается как проявление всего абзаца сразу с наклоном. */
    узлы = d.querySelectorAll(".rv-акт .rv-абз");
    for (i = 0; i < узлы.length; i++) разрезать(узлы[i], 0.25);
    /* Слейт акта: имя без номера. Номер это счётчик ленты, он стоит на
       месте и мигать вместе с именем ему незачем. */
    узлы = d.querySelectorAll(".rv-акт .rv-над span");
    for (i = 0; i < узлы.length; i++) разрезать(узлы[i], 0);
    /* Сноска не режется намеренно: это техническая приписка в тринадцать
       точек, волна по её словам стоила бы столько же, сколько по
       заголовку, а увидеть её нельзя. */
    померитьЛенту();
  }

  var ждём = 0;
  function поРазмеру() {
    if (ждём) return;
    ждём = 1;
    g.requestAnimationFrame(function () { ждём = 0; померитьЛенту(); });
  }

  function старт() {
    собрать();
    g.addEventListener("resize", поРазмеру);
    /* Ряд карточек приезжает из досье продукта, а не из разметки:
       пока rv-fill.js его не собрал, мерить нечего. Второй замер после
       готовности шрифтов - ширина карточек зависит от начертания. */
    g.addEventListener("rv:наполнено", поРазмеру);
    if (d.fonts && d.fonts.ready && d.fonts.ready.then) {
      d.fonts.ready.then(поРазмеру, function () {});
    }
    g.setTimeout(поРазмеру, 1200);
    g.setTimeout(поРазмеру, 3000);
  }

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", старт);
  else старт();

  g.RV_СЛОВО = {
    "пересобрать": собрать,
    "померить": померитьЛенту
  };
})(window, document);
