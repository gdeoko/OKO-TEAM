/* Rocket VPN. Текст в мире: блоки разделов живут в сцене камеры.

   ЗАКОН, КОТОРЫЙ ЗДЕСЬ ДЕРЖИТСЯ. Владелец задал его словами: «сделать
   по скроллу по движению камеры красивое появление и исчезание текста,
   если вправо камера то текст влево уходит, влево - вправо, вглубь если
   идём вперёд, то текст расширяется и исчезает, если идём назад то
   отдаляется». Четыре правила, и все четыре от НАСТОЯЩЕГО хода камеры:

     1. камера вправо - блок влево, знак противоположный, величина от
        боковой составляющей скорости камеры в мировых единицах;
     2. камера вверх-вниз - блок наоборот по знаку;
     3. камера сближается с предметом акта - блок РАСТЁТ и растворяется,
        он проходит мимо объектива вместе со всем кадром;
     4. камера отдаляется - блок УМЕНЬШАЕТСЯ и уходит вглубь.

   Появления и исчезания как отдельной анимации нет: блок приходит с той
   стороны, откуда камера на него наезжает, и уходит туда, куда камера от
   него уезжает. Пословной нарезки, весов по словам и разнонаправленных
   волн тоже нет - их убрали по живому просмотру («с этим движением
   текста рандомным вообще хуже стало»). Абзац это ОДИН блок, заголовок
   ОДИН блок, карточка ОДИН блок; внутри блока буквы своей жизни не
   живут.

   ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ. Сам он ничего не двигает: движение считает
   вёрстка в rv-слово.css из величин, которые тут публикуются. Их две
   породы.

   Мировые. Договор с работой «ход камеры»: мир пишет в documentElement
   --rv-перспектива, --rv-схода-x/y, --rv-крен, --rv-крупность. Пока он
   их не пишет, ровно те же величины считает и публикует этот файл под
   именами --сл-*, и вёрстка берёт их вторым запасом:
   var(--rv-перспектива, var(--сл-персп, 1150px)). Задержка соседней
   работы сайт не ломает.

   Свои. Боковая и вертикальная составляющие скорости камеры (--сл-бок,
   --сл-верт, мировые единицы в секунду) и сырая доля акта (--сд).

   Про кадровый цикл. Прежде тут его не было намеренно: четвёртая
   очередь ЧТЕНИЙ И ЗАПИСЕЙ РАСКЛАДКИ на кадр стоит дорого. Цикл ниже не
   читает раскладку ВООБЩЕ (ни getBoundingClientRect, ни
   getComputedStyle) и пишет только те произвольные свойства, значение
   которых изменилось: два десятка действий с числами и до семи записей
   строки. Замеров раскладки в нём ноль, и запрет его не касается. Доля
   акта берётся вообще без своего цикла - подпиской на кадр плёнки. */
(function (g, d) {
  "use strict";

  /* Признак ставится сразу и синхронно. Он несёт не только движение: на
     нём висит вся типографика файла, а она обязана быть на месте даже
     если ниже что-то упадёт. */
  var корень = d.documentElement;
  корень.classList.add("рв-слово");

  var тихо = false;
  try {
    тихо = g.matchMedia && g.matchMedia("(prefers-reduced-motion: reduce)").matches;
  } catch (e) {}
  if (g.RV_WORLD && g.RV_WORLD["тихо"] && g.RV_WORLD["тихо"]()) тихо = true;
  if (тихо) корень.classList.add("рв-слово-тихо");

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }

  /* ── Лента технологий ──────────────────────────────────────────
     Горизонтальный ход внутри вертикальной прокрутки. Вёрстка умеет
     ехать долей акта, но не знает, НА СКОЛЬКО ехать: это разница между
     шириной ряда карточек и шириной окна, и она живёт только в
     раскладке. Меряем её здесь и отдаём числом.

     Меряем через scrollWidth контейнера, а не сложением ширин
     карточек: у ряда есть зазоры, поля и своя доля от --rv-поле, и
     сложение по карточкам разошлось бы с правдой на каждой ширине
     экрана по-своему. */
  function померитьЛенту() {
    var гнездо = d.getElementById("rvТех");
    if (!гнездо) return;
    var ряд = гнездо.querySelector(".rv-тех");
    if (!ряд) return;
    /* Признак ставится ДО замера. Пока его нет, ряд стоит сеткой в
       четыре колонки по ширине окна, и мерить в этот момент значит
       мерить старую раскладку: ход всегда выходил бы нулём, и лента
       никогда бы не включилась. */
    гнездо.setAttribute("data-лента", "1");
    var ход = Math.max(0, ряд.offsetWidth - гнездо.clientWidth);
    гнездо.style.setProperty("--лента-ход", Math.round(ход) + "px");
    /* Пока ряд помещается целиком, ехать некуда, и разворот карточек
       без хода читался бы просто кривым рядом. */
    if (ход <= 24) гнездо.setAttribute("data-лента", "0");
  }

  /* ══════════════════════════════════════════════════════════════
     МОСТ В МИР
     ══════════════════════════════════════════════════════════════ */

  function мирГотов() {
    var W = g.RV_WORLD;
    return !!(W && W["готов"] && W["готов"]() && W["мир"] && W["мир"]() && W["мир"]().cam);
  }

  /* Мир уже пишет своё? Проверяем по инлайновому стилю корня: это
     чтение карты свойств, раскладку оно не трогает. */
  function мирПишет(имя) {
    return !!корень.style.getPropertyValue(имя);
  }

  var глоб = { п: "", сх: "", сy: "", кр: "", бк: "", вр: "" };

  function писатьГлоб(имя, знач, поле) {
    if (глоб[поле] === знач) return;
    глоб[поле] = знач;
    корень.style.setProperty(имя, знач);
  }

  /* Кадр моста. Только числа и записи произвольных свойств. */
  function кадрМоста() {
    g.requestAnimationFrame(кадрМоста);
    if (тихо || !мирГотов()) return;
    var W = g.RV_WORLD["мир"]();
    var кам = W.cam;
    var m = кам.matrixWorld.elements;

    /* ПЕРСПЕКТИВА. Ровно та формула, по которой её считает замер
       ход-камеры.mjs: P = (высота окна / 2) * зум / tg(поле / 2). Это и
       есть один объектив на вёрстку и мир. */
    if (!мирПишет("--rv-перспектива")) {
      var поле = кам.fov || 52, зум = кам.zoom || 1;
      var вы = g.innerHeight || d.documentElement.clientHeight || 800;
      var т = Math.tan(поле * Math.PI / 360);
      if (т > 1e-4) {
        var P = (вы / 2) * зум / т;
        писатьГлоб("--сл-персп", зажать(P, 320, 4200).toFixed(0) + "px", "п");
      }
    }

    /* ТОЧКА СХОДА. Мир считает её каждый кадр и кладёт в
       скорость().экран долями кадра, причём Y там снизу вверх (это
       нормированные координаты отсечения). Вёрстка меряет сверху, и
       поэтому здесь 1 - y, а не y.

       Величина тянется к покойным 28/46 с весом 0.35, а не идёт сырой.
       Замер показал, почему: сырая точка схода уходила на 1324 из 1440
       точек кадра, то есть на 92 процента ширины, и заголовок, стоящий
       у левого поля, при наплыве отбрасывало от неё за кромку экрана на
       161 точку. С весом 0.35 точка схода ходит по кадру от 28 до 47
       процентов - видно и глазом, и на замере, а текст остаётся в
       кадре. */
    if (!мирПишет("--rv-схода-x") && g.RV_WORLD["скорость"]) {
      var ск = g.RV_WORLD["скорость"]();
      var э = ск["экран"];
      if (э) {
        var сx = 28 + (зажать(э[0], -0.3, 1.3) * 100 - 28) * 0.35;
        var сy = 46 + ((1 - зажать(э[1], -0.3, 1.3)) * 100 - 46) * 0.35;
        писатьГлоб("--сл-сх-x", зажать(сx, 10, 72).toFixed(1) + "%", "сх");
        писатьГлоб("--сл-сх-y", зажать(сy, 18, 82).toFixed(1) + "%", "сy");
      }

      /* БОКОВАЯ И ВЕРТИКАЛЬНАЯ СОСТАВЛЯЮЩИЕ ХОДА КАМЕРЫ - первые два
         правила владельца. Вектор скорости у мира уже сглажен (лерп с
         постоянной 0.15 с), поэтому дрожи он не даёт. Раскладываем его
         по осям КАМЕРЫ: первый столбец матрицы мира это её правая ось,
         второй - верхняя. Величина уходит в мировых единицах в секунду,
         как есть; в точки её переводит вёрстка, там же стоит и потолок.

         Прежняя инерция от rv-плиты.js сюда не годилась: она приходит
         уже зажатой в десять точек на ПК и шесть на телефоне (это один
         процент кадра, глаз такого движения не видит) и подмешивает в
         бок ещё и крен. */
      if (!мирПишет("--rv-бок")) {
        var в = ск["вектор"];
        if (в) {
          var бок = в[0] * m[0] + в[1] * m[1] + в[2] * m[2];
          var верт = в[0] * m[4] + в[1] * m[5] + в[2] * m[6];
          писатьГлоб("--сл-бок", зажать(бок, -400, 400).toFixed(2), "бк");
          писатьГлоб("--сл-верт", зажать(верт, -400, 400).toFixed(2), "вр");
        }
      }
    }

    /* КРЕН В ГРАДУСАХ, без потолка в три. У камеры без крена правая ось
       лежит в горизонте, её высота и есть синус крена: это второй
       элемент первого столбца матрицы мира. Прежний --кр от rv-плиты.js
       упирался в потолок уже на 3.82 градуса, а прокол объявляет 17.2,
       то есть четыре пятых крена вёрстка не видела вовсе. */
    if (!мирПишет("--rv-крен")) {
      var кр = Math.asin(зажать(m[1], -1, 1)) * -180 / Math.PI;
      писатьГлоб("--сл-крен", кр.toFixed(2), "кр");
    }
  }

  /* ── Крупность по актам ────────────────────────────────────────
     Третье и четвёртое правила владельца держатся на одном числе: во
     сколько раз мир вырос относительно станционного расстояния.
     Станционное это длина от точки, откуда акт смотрят, до точки, на
     которую смотрят; живое берётся у мира каждый кадр. Больше единицы -
     камера ближе станции, то есть идёт ВПЕРЁД, и текст обязан расти и
     растворяться. Меньше - камера отдаляется, и текст уходит вглубь.

     У актов без станции («видно», «периметр») предмета нет вовсе, а
     камера всё равно идёт вперёд весь акт. Там крупность берётся из
     доли акта тем же законом: вперёд - значит растёт. */
  var мостАкты = [];

  /* Список актов собирается ОДИН раз, из разметки: подписки на плёнку
     держат эти самые записи, и пересборка списка оставила бы их висеть
     на выброшенных объектах. Станции доезжают позже и дописываются в те
     же записи. */
  function собратьАкты() {
    if (мостАкты.length) return;
    var узлы = d.querySelectorAll(".rv-акт");
    for (var i = 0; i < узлы.length; i++) {
      мостАкты.push({
        узел: узлы[i], имя: узлы[i].getAttribute("data-акт") || "",
        на: null, д0: 0, было: ""
      });
    }
  }

  function подтянутьСтанции() {
    var станции = [];
    try {
      if (g.RV_WORLD && g.RV_WORLD["кривая"]) станции = g.RV_WORLD["кривая"]()["станции"] || [];
    } catch (e) {}
    if (!станции.length) return 0;
    var нашли = 0;
    for (var i = 0; i < мостАкты.length; i++) {
      var a = мостАкты[i];
      for (var k = 0; k < станции.length; k++) {
        var ст = станции[k];
        if (ст["имя"] !== a.имя || !ст["на"] || !ст["от"]) continue;
        a.на = ст["на"];
        a.д0 = Math.sqrt(
          Math.pow(ст["на"][0] - ст["от"][0], 2) +
          Math.pow(ст["на"][1] - ст["от"][1], 2) +
          Math.pow(ст["на"][2] - ст["от"][2], 2));
        нашли++;
      }
    }
    return нашли;
  }

  /* Подписка вешается не сразу. Порядок в разметке такой: rv-слово.js
     стоит ВЫШЕ rv-motion.js, оба с defer, и к моменту исполнения этого
     файла RV_MOTION ещё не существует - readyState уже «interactive»,
     поэтому старт идёт сразу, а плёнка объявится ниже по списку.
     Поймано замером: подписка молча не вешалась, --сд не появлялась
     вовсе, и вся глубина текста считалась по значению по умолчанию. */
  var мостПовешен = false;

  /* Кадровая запись по акту. Идёт подпиской на плёнку, поэтому своего
     цикла не заводит и лишнего замера раскладки не делает.
       --сд      сырая доля акта, БЕЗ двух подтяжек. Две подтяжки с
                 мягкостью 0.30 дают около 93 мс отставания, при
                 2000 px/с это 187 точек прокрутки, то есть треть акта:
                 лента ехала бы там, где камера давно прошла.
       --сл-круп крупность мира для этого акта. */
  function повеситьМост() {
    собратьАкты();
    if (мостПовешен) return true;
    if (!g.RV_MOTION || !g.RV_MOTION["слушать"]) return false;
    мостПовешен = true;
    for (var i = 0; i < мостАкты.length; i++) {
      (function (a) {
        g.RV_MOTION["слушать"](a.имя, function (д, зап) {
          var с = зап && зап["цель"] != null ? зап["цель"] : д;
          var стиль = a.узел.style;
          стиль.setProperty("--сд", с.toFixed(4));
          if (мирПишет("--rv-крупность")) return;
          var кр;
          if (a.на && a.д0 && g.RV_WORLD && g.RV_WORLD["доСтанции"]) {
            var жив = g.RV_WORLD["доСтанции"](a.имя);
            кр = жив > 0.001 ? a.д0 / жив : 1;
          } else {
            /* Акт без станции: камера идёт вперёд весь акт, значит
               крупность растёт весь акт. 0.62..1.38 это тот же размах,
               который дают станционные акты. */
            кр = 0.62 + с * 0.76;
          }
          var знач = зажать(кр, 0.2, 6).toFixed(4);
          if (знач !== a.было) { a.было = знач; стиль.setProperty("--сл-круп", знач); }
        });
      })(мостАкты[i]);
    }
    return true;
  }

  var ждём = 0;
  function поРазмеру() {
    if (ждём) return;
    ждём = 1;
    g.requestAnimationFrame(function () { ждём = 0; померитьЛенту(); });
  }

  function старт() {
    померитьЛенту();
    повеситьМост();
    g.requestAnimationFrame(кадрМоста);
    if (!мостПовешен) d.addEventListener("DOMContentLoaded", повеситьМост);
    /* Мир поднимается секундами: на песочнице без видеокарты сборка
       сцены идёт три-шесть секунд, и до неё станций ещё нет. */
    var попыток = 0;
    var догон = g.setInterval(function () {
      if (++попыток > 40) { g.clearInterval(догон); return; }
      повеситьМост();
      if (!мирГотов()) return;
      if (!подтянутьСтанции()) return;
      if (мостПовешен) g.clearInterval(догон);
    }, 400);
    g.addEventListener("resize", поРазмеру);
    /* Ряд карточек приезжает из досье продукта, а не из разметки:
       пока rv-fill.js его не собрал, мерить нечего. Второй замер после
       готовности шрифтов - ширина карточек зависит от начертания. */
    g.addEventListener("rv:наполнено", поРазмеру);
    if (d.fonts && d.fonts.ready && d.fonts.ready.then) {
      d.fonts.ready.then(поРазмеру, function () {});
    }
    g.setTimeout(поРазмеру, 1200);
    g.setTimeout(поРазмеру, 3000);
  }

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", старт);
  else старт();

  g.RV_СЛОВО = {
    "померить": померитьЛенту
  };
})(window, document);
