/* Rocket VPN. Кабина финала: та же панель, что на соседнем сайте.

   ЗАЧЕМ. Владелец: «финальную сцену 1:1 как на сайте CDN - такая же
   ракета, салон, панель, просто скопируй её, и убери 360, и вопросы и
   кнопки поставить на самый последний кадр».

   Панель у Rocket CDN это не набор плит, нарисованных кодом. Три
   предыдущих рамы там были нарисованы, и все три владелец отверг
   одними словами: «не реалистично и некрасиво». Победил снимок:
   фотореальный кадр рубки с ПРОЗРАЧНОЙ дырой на месте окна. Металл,
   микрорельеф, затёртости и свет на нём сняты целиком, а не собраны из
   градиентов - потому он и выглядит снятым камерой.

   Здесь берётся ровно тот же снимок (три кадра под три раскладки) и
   ровно та же арифметика раскладки, что у них. Ни одного своего числа:
   разойдись они - и окно рамы перестанет совпадать с окном разметки.

   ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Это не слой поверх объёмного салона. Окно рамы
   прозрачно, и сквозь него виден настоящий зал корабля с настоящим
   светом: рама стоит НА КРОМКЕ кадра, а середина принадлежит сцене. У
   соседей был заход, где картинка кабины наезжала поверх объёмной
   рубки, и владелец сказал ровно про него: «панель появляется поверх
   окна салона, хотя должна быть частью салона, вшитой». Поэтому здесь
   рама приходит только тогда, когда объёмного пульта в кадре уже нет.

   ЧТО ОТДАЁТ НАРУЖУ. Прямоугольник окна в процентах экрана
   переменными --рв-каб-*. В них садятся вопросы, анкета и кнопки, и
   именно поэтому они не заезжают под переплёт.

     RV_КАБИНА.сила(k)   0 нет кабины, 1 рама в полную силу
     RV_КАБИНА.замер()   для приёмки
   ═══════════════════════════════════════════════════════════ */
(function (g, d) {
  "use strict";

  var слой = null, кадрИмг = null, имяСейчас = "";
  var силаСейчас = -1;
  var окноБыло = "";

  /* ── Какой кадр под этот экран ───────────────────────────────
     Правило снято у соседей (rc-deck, «какой») слово в слово: широкий
     работает от 1.55 и шире, средний на четыре к трём и близких,
     высокий на телефоне. Правило одно на всех - по нему выбирается и
     кадр, и разметка окна, и две копии разошлись бы. */
  function какой(ш, в) {
    if (в > ш) return "высокая";
    return (ш / в < 1.55) ? "средняя" : "широкая";
  }

  /* Доля кадра, ниже которой на снимке ничего важного нет: пульт с
     нишами кончается здесь, дальше тёмный ближний край. */
  var ДНО = 0.978;

  /* ── Раскладка кадра ─────────────────────────────────────────
     Снимок лежит с object-fit: cover. Чтобы окно рамы попало ровно
     туда, где оно на снимке, повторяем ту же арифметику: масштаб по
     большей нужде, остаток уходит за края.

     По вертикали кадр держится НЕ по центру. На широком мониторе
     снимок семь к четырём обрезается сверху и снизу почти на
     четверть, и первым уходит пульт - нижняя кромка окна вместе с
     ним. Сдвигаем кадр вниз ровно настолько, чтобы низ рамы влез, и
     ни на пиксель больше: лишний сдвиг съел бы верхнюю кромку. */
  function покрытие(мета, ш, в) {
    var k = Math.max(ш / мета.w, в / мета.h);
    var dw = мета.w * k, dh = мета.h * k;
    var д = 0.5;
    if (dh > в) {
      д = (в - ДНО * dh) / (в - dh);
      if (д < 0.5) д = 0.5;
      if (д > 1) д = 1;
    }
    return { k: k, dw: dw, dh: dh, ox: (ш - dw) / 2, oy: (в - dh) * д };
  }

  function мета() {
    var М = g["RV_КАБ_ПЛОСКАЯ"];
    if (!М) return null;
    var ш = g.innerWidth || 1280, в = g.innerHeight || 720;
    var имя = какой(ш, в);
    return М[имя] || М["широкая"] || null;
  }

  function построить() {
    if (слой) return слой;
    слой = d.createElement("div");
    слой.className = "рв-каб";
    /* От чтения с экрана прячем только саму раму: вопросы и кнопки
       живут в разметке акта, а не здесь, и признак с предка потомку
       уже не отменить. */
    слой.setAttribute("aria-hidden", "true");
    кадрИмг = d.createElement("img");
    кадрИмг.className = "рв-каб-кадр";
    кадрИмг.alt = "";
    кадрИмг.decoding = "async";
    слой.appendChild(кадрИмг);
    d.body.appendChild(слой);
    источник();
    return слой;
  }

  /* Файл под текущий экран и окно рамы наружу. */
  function источник() {
    var м = мета();
    if (!м || !кадрИмг) return;
    var файл = м["файл"] || "";
    /* Пути в паспорте написаны под соседний сайт (assets/gen/...).
       Кадры лежат у нас в своей папке, поэтому берём только имя
       файла: паспорт правится инструментом и руками не трогается. */
    var имяФайла = файл.split("/").pop();
    var путь = "assets/gen/каб/" + имяФайла;
    if (путь !== имяСейчас) { имяСейчас = путь; кадрИмг.setAttribute("src", путь); }
    окно(м);
  }

  /* ── Окно рамы в процентах экрана ────────────────────────────
     Паспорт держит коробку окна в долях СНИМКА. На экране снимок
     обрезан по cover, поэтому доли снимка и доли экрана это разные
     числа, и переводить их обязан тот же счёт, что кладёт картинку. */
  function окно(м) {
    м = м || мета();
    if (!м || !м["коробка"]) return;
    var ш = g.innerWidth || 1280, в = g.innerHeight || 720;
    var п = покрытие(м, ш, в);
    var к = м["коробка"];
    function пx(u) { return (п.ox + u * п.dw) / ш * 100; }
    function пy(v) { return (п.oy + v * п.dh) / в * 100; }
    var л = пx(к.l), пр = пx(к.r), вх = пy(к.t), нз = пy(к.b);
    /* Запас внутрь на процент кадра: кромка рамы на снимке мягкая, и
       текст, поставленный вплотную к коробке, ложится на подсветку
       переплёта. */
    л += 1; пр -= 1; вх += 1; нз -= 1;
    var ключ = л.toFixed(2) + пр.toFixed(2) + вх.toFixed(2) + нз.toFixed(2);
    if (ключ === окноБыло) return;
    окноБыло = ключ;
    var кор = d.documentElement;
    кор.style.setProperty("--рв-каб-л", л.toFixed(2) + "%");
    кор.style.setProperty("--рв-каб-п", пр.toFixed(2) + "%");
    кор.style.setProperty("--рв-каб-в", вх.toFixed(2) + "%");
    кор.style.setProperty("--рв-каб-н", нз.toFixed(2) + "%");
    кор.style.setProperty("--рв-каб-ш", (пр - л).toFixed(2) + "%");
    кор.style.setProperty("--рв-каб-выс", (нз - вх).toFixed(2) + "%");
  }

  /* Сколько кабины в кадре. Ноль это не «спрятать красиво», а вовсе
     убрать: рама на весь экран стоит недёшево на телефоне, и держать
     её включённой на семи актах из восьми незачем. */
  function сила(k) {
    var з = k == null ? 0 : (k < 0 ? 0 : (k > 1 ? 1 : k));
    if (Math.abs(з - силаСейчас) < 0.002) return;
    силаСейчас = з;
    if (з <= 0.001) {
      if (слой) слой.style.opacity = "0";
      d.documentElement.classList.remove("рв-кабина-есть");
      return;
    }
    построить();
    слой.style.opacity = з.toFixed(3);
    d.documentElement.classList.add("рв-кабина-есть");
  }

  g.addEventListener("resize", function () {
    if (!слой) return;
    источник();
  });
  g.addEventListener("orientationchange", function () {
    if (!слой) return;
    источник();
  });

  g["RV_КАБИНА"] = {
    "сила": сила,
    "окно": окно,
    "замер": function () {
      var м = мета();
      return {
        "есть": !!слой,
        "сила": +силаСейчас.toFixed(3),
        "кадр": имяСейчас,
        "окно": окноБыло,
        "паспорт": !!м
      };
    }
  };
})(window, document);
