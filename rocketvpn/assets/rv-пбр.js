/* Rocket VPN. Фотореалистичные материалы мира.

   ЗАЧЕМ ЭТОТ ФАЙЛ ЕСТЬ. Владелец сказал про визуал прямо: «текстуры, все
   3д объекты, фон, элементы, всё должно быть не отлично от реальной
   жизни». Ни один процедурный материал этого не даёт и дать не может. У
   нарисованной кодом поверхности нет двух вещей, по которым глаз и
   узнаёт настоящее: НЕРОВНОСТИ РЕЛЬЕФА в тысячах мелких точек и
   НЕРОВНОСТИ БЛЕСКА, когда соседние миллиметры отражают по-разному.
   Синус и шум дают правильную статистику и неправильную частность, и
   мозг читает такую поверхность как рисунок за долю секунды.

   Даёт это фотограмметрия: настоящая поверхность, снятая в поле с
   десятков ракурсов и разложенная на карты. Наборы взяты с ambientCG под
   лицензией CC0, то есть общественное достояние. Чужого права там нет
   вовсе, и в коммерческий сайт клиента такой материал ставится без
   единого риска. Сырьё пережато конвейером tools/пбр-конвейер.py.

   ЧЕТЫРЕ НАБОРА, И КАЖДЫЙ РАБОТАЕТ В НЕСКОЛЬКИХ АКТАХ.
     реголит  грунт Луны. Цвет и нормаль по 2048: этот грунт человек
              разглядывает в упор весь первый акт, ему нужно больше всех.
     блок     панель купола, она же блок стены досмотра. Один материал
              на оба акта намеренно: по сценарию стена собирается ИЗ
              КУПОЛА, и если материал сменится, превращение развалится.
     металл   обшивка ракеты и оснастка ангара.
     обшивка  стенка тоннеля.

   ORM-ПАКОВКА. Затенение, шероховатость и металл лежат в трёх каналах
   ОДНОГО файла по соглашению glTF: R затенение, G шероховатость, B
   металл. В three.js один и тот же объект текстуры кладётся сразу в
   aoMap, roughnessMap и metalnessMap, и движок сам берёт из каждого свой
   канал. Три карты весом одной, и на одну выборку из текстуры меньше.

   КАРТА ЗАТЕНЕНИЯ И ВТОРОЙ НАБОР КООРДИНАТ. three.js читает aoMap не по
   тем же координатам, что остальные карты: ему нужен отдельный набор
   (uv1 в свежих сборках, uv2 в тех, что постарше). У наших геометрий он
   не заведён, и без него затенение молча не рисуется вовсе. Поэтому
   перед выдачей материала геометрию надо прогнать через готовьГео: она
   копирует основной набор в оба имени сразу, и файл работает на обеих
   сборках движка.

   НИЧЕГО НЕ ЖДЁМ. Материал возвращается СРАЗУ, ещё без карт, и работает
   как ровная поверхность нужного цвета. Карты доезжают и подставляются
   потом. Иначе первый акт стоял бы чёрным экраном три мегабайта, а
   человек за это время уходит. */
(function (g, d) {
  "use strict";

  var БАЗА = "assets/gen/pbr/";

  /* Настройки набора. «повтор» это сколько раз плитка ложится на единицу
     размера предмета: у грунта плитка мелкая и частая, у панели крупная.
     «нормаль» это сила рельефа, единица означает как снято. */
  var НАБОРЫ = {
    "реголит": { повтор: 26, нормаль: 1.0, шерох: 0.98, металл: 0.0, высота: true },
    "блок":    { повтор: 1.6, нормаль: 0.85, шерох: 0.92, металл: 0.0 },
    "металл":  { повтор: 2.2, нормаль: 0.7, шерох: 0.42, металл: 1.0 },
    "обшивка": { повтор: 3.4, нормаль: 1.0, шерох: 0.55, металл: 1.0 }
  };

  var кэш = {};      /* имя -> {цвет, норм, orm, высота} */
  var ждут = {};     /* имя -> [материалы, которым доложить карты] */
  var загрузчик = null;
  var анизо = 4;

  function T() { return g.THREE; }

  function ступень() {
    try {
      if (g.RV_WORLD && g.RV_WORLD["ступень"]) return g.RV_WORLD["ступень"]();
    } catch (e) {}
    return 2;
  }

  /* Анизотропия это единственная настройка, без которой фотоскан на
     ПОЛУ выглядит хуже процедурного. Грунт уходит к горизонту под очень
     острым углом, и без неё дальняя половина кадра превращается в
     мыло с муаром. Восьми хватает, выше цена растёт, а разницы нет. */
  function поднятьАнизо(рисовальщик) {
    try {
      var м = рисовальщик.capabilities.getMaxAnisotropy();
      анизо = Math.max(1, Math.min(8, м));
    } catch (e) { анизо = 4; }
  }

  function текстура(файл, цветовая) {
    var t = T();
    if (!загрузчик) загрузчик = new t.TextureLoader();
    var тек = загрузчик.load(БАЗА + файл);
    настроитьТек(тек, цветовая);
    return тек;
  }

  function настроитьТек(тек, цветовая) {
    var t = T();
    тек.wrapS = тек.wrapT = t.RepeatWrapping;
    тек.anisotropy = анизо;
    /* Цвет живёт в sRGB, всё остальное это ЧИСЛА, а не цвет: рельеф,
       шероховатость, затенение. Прогнать их через кривую sRGB значит
       исказить сами числа, и рельеф поедет. */
    if (цветовая) {
      тек.colorSpace = t.SRGBColorSpace || тек.colorSpace;
    } else {
      тек.colorSpace = t.NoColorSpace || t.LinearSRGBColorSpace || тек.colorSpace;
    }
    return тек;
  }

  /* Загрузка набора. Идёт один раз на набор, сколько бы материалов его
     ни просило: карты у них общие, и грузить одно и то же по второму
     разу значит платить памятью за копию. */
  function набор(имя) {
    if (кэш[имя]) return кэш[имя];
    var н = НАБОРЫ[имя];
    if (!н) return null;
    var к = {
      цвет: текстура(имя + "-цвет.webp", true),
      орм: текстура(имя + "-orm.webp", false),
      норм: null,
      высота: null
    };
    /* На нищей ступени рельеф снимается: карта нормалей это самый
       тяжёлый файл набора (у грунта два мегабайта), а на слабом
       устройстве она и так съедается вместе с частотой кадров. */
    if (ступень() >= 1) к.норм = текстура(имя + "-норм.webp", false);
    if (н.высота && ступень() >= 2) к.высота = текстура(имя + "-высота.webp", false);
    кэш[имя] = к;
    return к;
  }

  /* Раскладка плитки. Величина одна на все карты набора: разъехавшийся
     повтор между цветом и рельефом даёт поверхность, у которой блики
     стоят не там, где бугры, и это видно сразу. */
  function повторить(имя, u, v) {
    var к = кэш[имя];
    if (!к) return;
    var карты = [к.цвет, к.орм, к.норм, к.высота];
    for (var i = 0; i < карты.length; i++) {
      if (карты[i]) { карты[i].repeat.set(u, v); карты[i].needsUpdate = true; }
    }
  }

  /* Второй набор координат для карты затенения. Пишем ОБА имени: uv1 в
     сборках от r152, uv2 в тех, что старше. Лишний атрибут движку не
     мешает, а отсутствие нужного гасит затенение молча. */
  function готовьГео(гео) {
    if (!гео || !гео.attributes || !гео.attributes.uv) return гео;
    if (!гео.attributes.uv1) гео.setAttribute("uv1", гео.attributes.uv);
    if (!гео.attributes.uv2) гео.setAttribute("uv2", гео.attributes.uv);
    return гео;
  }

  /* ═══════════════════════════════════════════════════════════════
     ВЫДАЧА МАТЕРИАЛА
     ═══════════════════════════════════════════════════════════════ */
  function материал(имя, о) {
    var t = T();
    о = о || {};
    var н = НАБОРЫ[имя] || {};
    var м = new t.MeshStandardMaterial({
      color: о["цвет"] != null ? о["цвет"] : 0xFFFFFF,
      roughness: о["шерох"] != null ? о["шерох"] : (н.шерох != null ? н.шерох : 0.9),
      metalness: о["металл"] != null ? о["металл"] : (н.металл != null ? н.металл : 0.0),
      envMapIntensity: о["отражения"] != null ? о["отражения"] : 1.0
    });
    if (о["прозрачно"]) { м.transparent = true; м.opacity = о["прозрачность"] != null ? о["прозрачность"] : 1; }
    if (о["сторона"] != null) м.side = о["сторона"];

    var к = набор(имя);
    if (!к) return м;

    м.map = к.цвет;
    /* Один и тот же объект в трёх местах: движок сам возьмёт из него R,
       G и B. Это и есть смысл паковки. */
    м.aoMap = к.орм;
    м.roughnessMap = к.орм;
    м.metalnessMap = к.орм;
    м.aoMapIntensity = о["затенение"] != null ? о["затенение"] : 1.0;
    if (к.норм) {
      м.normalMap = к.норм;
      var с = о["рельеф"] != null ? о["рельеф"] : (н.нормаль != null ? н.нормаль : 1);
      м.normalScale = new t.Vector2(с, с);
    }
    var п = о["повтор"] != null ? о["повтор"] : (н.повтор != null ? н.повтор : 1);
    var пu = п, пv = п;
    if (о["повторUV"]) { пu = о["повторUV"][0]; пv = о["повторUV"][1]; }
    повторить(имя, пu, пv);
    м.needsUpdate = true;
    return м;
  }

  /* ОДЕТЬ ГОТОВЫЙ МАТЕРИАЛ.

     Половина мира собрана не здесь: тоннель, оснастка и модели берут
     материал у RV_REAL.корпус, и он уже настроен по цвету, металлу и
     отражениям под свой акт. Переделывать их на материал() значит
     потерять эту настройку. Здесь на готовый материал просто вешаются
     карты, всё остальное в нём остаётся как было.

     Работает только с теми материалами, у которых карты вообще есть
     (MeshStandardMaterial и его потомки). needsUpdate обязателен: без
     него движок не пересоберёт программу шейдера, и карты не появятся. */
  function одеть(м, имя, о) {
    if (!м) return м;
    о = о || {};
    var t = T();
    var н = НАБОРЫ[имя] || {};
    var к = набор(имя);
    if (!к) return м;
    м.map = к.цвет;
    м.aoMap = к.орм;
    м.roughnessMap = к.орм;
    м.metalnessMap = к.орм;
    м.aoMapIntensity = о["затенение"] != null ? о["затенение"] : 1.0;
    if (к.норм) {
      м.normalMap = к.норм;
      var с = о["рельеф"] != null ? о["рельеф"] : (н.нормаль != null ? н.нормаль : 1);
      м.normalScale = new t.Vector2(с, с);
    }
    var п = о["повтор"] != null ? о["повтор"] : (н.повтор != null ? н.повтор : 1);
    var пu = п, пv = п;
    if (о["повторUV"]) { пu = о["повторUV"][0]; пv = о["повторUV"][1]; }
    повторить(имя, пu, пv);
    м.needsUpdate = true;
    return м;
  }

  /* Карта высоты грунта отдаётся отдельно: её кладут не в материал, а в
     вершинный сдвиг плоскости, и делает это акт Луны сам. */
  function высота(имя) {
    var к = набор(имя);
    return к ? к.высота : null;
  }

  function прогреть(имена) {
    for (var i = 0; i < имена.length; i++) набор(имена[i]);
  }

  g.RV_ПБР = {
    "материал": материал,
    "одеть": одеть,
    "готовьГео": готовьГео,
    "повторить": повторить,
    "высота": высота,
    "прогреть": прогреть,
    "анизо": поднятьАнизо,
    "наборы": function () { var с = []; for (var k in НАБОРЫ) с.push(k); return с; }
  };
})(window, document);
