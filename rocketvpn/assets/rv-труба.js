  /* ══════════════════════════════════════════════════════════════════
     КАРТА ВЕТРА
     ══════════════════════════════════════════════════════════════════
     Их wind_noise.ktx2 одна на все пять дымов. Числа сняты с
     распакованной карты: минимум 33, максимум 203, среднее 121.0,
     среднеквадратичное 29.5. Спектр по мощности: период 256 точек 43.8
     процента, 128 - 11.8, 85 - 26.4, 64 - 5.5, выше восьмой гармоники
     всего 5.7. Полосы вытянуты вдвое вдоль 150 градусов - шум как будто
     протащили по потоку.

     ПОЧЕМУ НЕ БЕРЁМ КАРТУ ЛУНЫ. У неё размах 0..255 при среднем 102.6 и
     ско 61.0, то есть ВДВОЕ шире. Их шейдеры перемножают ТРИ выборки и
     возводят в куб или четвёртую степень: результат живёт на хвосте
     распределения, и вдвое больший размах даёт на порядок более яркие
     пятна. Замер прямой: их карта в трубе даёт потолок альфы 0.068 и ни
     одной точки ярче 0.2, наша - потолок 0.681 и 0.35 процента точек
     ярче 0.2. Одна наша труба выходила сильнее их дыма колец. */
  function картаВетра() {
    var Р = 256;
    var поле = new Float32Array(Р * Р);

    /* Тайловый ценностный шум: решётка n на n, гладкий шаг, обход по
       остатку - шов замкнут по определению. */
    function решётка(n, семя) {
      var a = new Float32Array(n * n), s = семя >>> 0;
      for (var i = 0; i < n * n; i++) {
        s = (s * 1664525 + 1013904223) >>> 0;
        a[i] = s / 4294967296;
      }
      return a;
    }
    function выборка(a, n, x, y) {
      var x0 = Math.floor(x), y0 = Math.floor(y);
      var fx = x - x0, fy = y - y0;
      fx = fx * fx * (3 - 2 * fx); fy = fy * fy * (3 - 2 * fy);
      function у(i, j) { return a[(((j % n) + n) % n) * n + (((i % n) + n) % n)]; }
      var v00 = у(x0, y0), v10 = у(x0 + 1, y0);
      var v01 = у(x0, y0 + 1), v11 = у(x0 + 1, y0 + 1);
      return (v00 + (v10 - v00) * fx) * (1 - fy) + (v01 + (v11 - v01) * fx) * fy;
    }

    /* Амплитуды это корни из их долей мощности: 0.438, 0.118, 0.264,
       0.055 плюс хвост. */
    var ОКТ = [[1, 0.662, 11], [2, 0.344, 29], [3, 0.514, 53],
               [4, 0.234, 71], [6, 0.187, 97], [8, 0.148, 131]];
    var сл = [], k;
    for (k = 0; k < ОКТ.length; k++) сл.push(решётка(ОКТ[k][0], ОКТ[k][2]));
    /* Поле искажения для вытянутости 2 к 1 вдоль 150 градусов. Оно само
       периодично, значит и вся карта остаётся тайловой. */
    var иск = решётка(2, 7);
    var дх = Math.cos(150 * Math.PI / 180), ду = Math.sin(150 * Math.PI / 180);

    var i, j, сум = 0, сум2 = 0;
    for (j = 0; j < Р; j++) {
      for (i = 0; i < Р; i++) {
        var u = i / Р, v = j / Р;
        var сдвиг = (выборка(иск, 2, u * 2, v * 2) - 0.5) * 1.6;
        var wu = u + дх * сдвиг / 3, wv = v + ду * сдвиг / 3;
        var s = 0;
        for (k = 0; k < ОКТ.length; k++) {
          s += ОКТ[k][1] * выборка(сл[k], ОКТ[k][0], wu * ОКТ[k][0], wv * ОКТ[k][0]);
        }
        поле[j * Р + i] = s;
        сум += s; сум2 += s * s;
      }
    }
    var ср = сум / (Р * Р);
    var ско = Math.sqrt(Math.max(1e-9, сум2 / (Р * Р) - ср * ср));

    var х = d.createElement("canvas"); х.width = Р; х.height = Р;
    var к = х.getContext("2d");
    var img = к.createImageData(Р, Р);
    for (j = 0; j < Р; j++) {
      for (i = 0; i < Р; i++) {
        /* Их три числа разом: среднее 121, ско 29.5, границы 33 и 203. */
        var б = 121 + (поле[j * Р + i] - ср) * (29.5 / ско);
        б = Math.round(зажать(б, 33, 203));
        var o = (j * Р + i) * 4;
        img.data[o] = б; img.data[o + 1] = б; img.data[o + 2] = б; img.data[o + 3] = 255;
      }
    }
    к.putImageData(img, 0, 0);
    var тек = new T.CanvasTexture(х);
    тек.wrapS = T.RepeatWrapping;
    тек.wrapT = T.RepeatWrapping;
    /* Их режим загрузки "linear-repeat" читает числа СЫРЫМИ, без разбора
       sRGB: карта это маска, а не цвет. */
    if (T.NoColorSpace !== undefined) тек.colorSpace = T.NoColorSpace;
    тек.needsUpdate = true;
    return тек;
  }

  /* ══════════════════════════════════════════════════════════════════
     ГЕОМЕТРИЯ КОЛЬЦА
     ══════════════════════════════════════════════════════════════════
     Кольцо строится как ЗАМКНУТЫЙ обод и режется плоскостями по углу.
     Каждый осколок продлевается за номинальную линию реза на 0..2.5
     градуса, и величина захода зависит от места в сечении: у обода
     сечения в среднем 0.55 градуса, в середине 1.45-1.53. Тогда
     сомкнутое кольцо не имеет ни одного просвета, а разлетевшееся
     показывает ступенчатый рваный торец.

     Плоскость кольца - XY, толщина по Z: их модель лежит так же, и их
     вершинный шейдер крутит осколок внутри плоскости строкой
     pos.xy = rotate(...). В плоскости XZ этот поворот уводил бы осколки
     из кольца вбок. */
  function профильСечения() {
    var rIn = С_ВНУТР, rOut = 1.0, zB = С_НИЗ, zT = С_ВЕРХ, cr = С_ФАСКА;
    var углы = [
      [rOut - cr, zB + cr, -90],   /* низ-наружу */
      [rOut - cr, zT - cr, 0],     /* верх-наружу */
      [rIn + cr, zT - cr, 90],     /* верх-внутрь */
      [rIn + cr, zB + cr, 180]     /* низ-внутрь */
    ];
    var т = [], i, ш;
    for (i = 0; i < 4; i++) {
      for (ш = 0; ш < 4; ш++) {
        var a = (углы[i][2] + ш * 30) * Math.PI / 180;
        var r = углы[i][0] + cr * Math.cos(a);
        var z = углы[i][1] + cr * Math.sin(a);
        /* Вес захода: единица в середине стенки или грани, около трети у
           фаски. Их разбивка по местам даёт ровно такую форму. */
        var dr = (r - rIn) / (rOut - rIn), dz = (z - zB) / (zT - zB);
        var м = Math.max(4 * dr * (1 - dr), 4 * dz * (1 - dz));
        т.push({ r: r, z: z, w: 0.36 + 0.64 * м });
      }
    }
    return т;
  }

  function кольцоГеометрия(T, вид) {
    var осколки = РАЗЛОМ[вид];
    var П = профильСечения();
    var НП = П.length;
    var поз = [], нор = [], уф = [], цен = [], рнд = [], инд = [];
    var база = 0;
    var грубо = (W && W.ступень === 0);

    function нормаль(a, b, c) {
      var ux = b[0] - a[0], uy = b[1] - a[1], uz = b[2] - a[2];
      var vx = c[0] - a[0], vy = c[1] - a[1], vz = c[2] - a[2];
      var nx = uy * vz - uz * vy, ny = uz * vx - ux * vz, nz = ux * vy - uy * vx;
      var l = Math.sqrt(nx * nx + ny * ny + nz * nz) || 1;
      return [nx / l, ny / l, nz / l];
    }
    function точка(p, u, v, н) {
      поз.push(p[0], p[1], p[2]);
      нор.push(н[0], н[1], н[2]);
      уф.push(u, v);
    }
    /* Четырёхугольник кладётся так, чтобы его нормаль смотрела НАРУЖУ от
       опорного направления. Иначе сторона FrontSide съедает половину
       треугольников, и на подлёте кольцо частями пропадает. */
    function четыре(a, b, c, e, u0, u1, v0, v1, опора) {
      var н = нормаль(a, b, c);
      if (н[0] * опора[0] + н[1] * опора[1] + н[2] * опора[2] < 0) {
        var t1 = b; b = e; e = t1;
        var t2 = v0; v0 = v1; v1 = t2;
        н = нормаль(a, b, c);
      }
      точка(a, u0, v0, н); точка(b, u0, v1, н);
      точка(c, u1, v1, н); точка(e, u1, v0, н);
      инд.push(база, база + 1, база + 2, база, база + 2, база + 3);
      база += 4;
    }
    function треугольник(a, b, c, u, v0, v1, v2, опора) {
      var н = нормаль(a, b, c);
      if (н[0] * опора[0] + н[1] * опора[1] + н[2] * опора[2] < 0) {
        var t1 = b; b = c; c = t1;
        var t2 = v1; v1 = v2; v2 = t2;
        н = нормаль(a, b, c);
      }
      точка(a, u, v0, н); точка(b, u, v1, н); точка(c, u, v2, н);
      инд.push(база, база + 1, база + 2);
      база += 3;
    }

    for (var к = 0; к < осколки.length; к++) {
      var о = осколки[к];
      var a0 = о[0] * Math.PI / 180;
      var a1 = о[1] * Math.PI / 180;
      if (a1 <= a0) a1 += Math.PI * 2;
      var дуга = (a1 - a0) * 180 / Math.PI;
      /* Их медианное ребро сетки 5 процентов внешнего радиуса. Девять
         градусов на деление держат ту же плотность при внешнем радиусе
         в наших единицах и не раздувают сетку на большом осколке. */
      var шагов = Math.max(3, Math.round(дуга / (грубо ? 18 : 9)));
      var станций = шагов + 2;    /* два крайних это рваные торцы */

      /* Заход за линию реза на каждый узел профиля. */
      var e0 = [], e1 = [], j;
      for (j = 0; j < НП; j++) {
        e0.push(ЗАХОД * П[j].w * (0.5 + 0.5 * псевдо(вид * 91.3 + к * 13.7 + j * 3.9)));
        e1.push(ЗАХОД * П[j].w * (0.5 + 0.5 * псевдо(вид * 91.3 + к * 13.7 + j * 3.9 + 57.1)));
      }

      /* Узлы. Станция 0 это торец начала, станция `станций` - торец
         конца, внутренние станции идут ровно по дуге. */
      var ряды = [], i;
      for (i = 0; i <= станций; i++) {
        var ряд = [];
        for (j = 0; j < НП; j++) {
          var у;
          if (i === 0) у = a0 - e0[j];
          else if (i === станций) у = a1 + e1[j];
          else у = a0 + (a1 - a0) * ((i - 1) / (станций - 2));
          var r = П[j].r * К_ВНЕШ;
          ряд.push([Math.cos(у) * r, Math.sin(у) * r, П[j].z * К_ВНЕШ]);
        }
        ряды.push(ряд);
      }

      var с0 = база;

      /* Боковая поверхность: шестнадцать полос вдоль дуги. Опора наружу
         это луч от середины сечения к узлу профиля, повёрнутый на
         текущий угол. */
      var сер = (С_ВНУТР + 1.0) * 0.5, серZ = (С_НИЗ + С_ВЕРХ) * 0.5;
      for (i = 0; i < станций; i++) {
        var u0 = i / станций, u1 = (i + 1) / станций;
        var уср = a0 + (a1 - a0) * (i + 0.5) / станций;
        for (j = 0; j < НП; j++) {
          var j2 = (j + 1) % НП;
          var pr = (П[j].r + П[j2].r) * 0.5 - сер;
          var pz = (П[j].z + П[j2].z) * 0.5 - серZ;
          var опора = [Math.cos(уср) * pr, Math.sin(уср) * pr, pz];
          четыре(ряды[i][j], ряды[i][j2], ряды[i + 1][j2], ряды[i + 1][j],
                 u0, u1, j / НП, (j + 1) / НП, опора);
        }
      }
      /* Торцы разлома. */
      крышка(ряды[0], 0, [-Math.cos(a0), -Math.sin(a0), 0]);
      крышка(ряды[станций], 1, [Math.cos(a1), Math.sin(a1), 0]);

      /* centr это середина габарита осколка, ПОДЕЛЁННАЯ НА 0.3. Проверено
         на всех десяти их осколках: centr*0.3 совпадает с серединой
         габарита до 0.0002. Прежний код клал саму середину, и ось
         вращения оказывалась в просвете кольца, а разлёт выходил втрое
         слабее нужного. */
      var мнx = 1e9, мкx = -1e9, мнy = 1e9, мкy = -1e9, мнz = 1e9, мкz = -1e9;
      for (i = с0 * 3; i < база * 3; i += 3) {
        if (поз[i] < мнx) мнx = поз[i];
        if (поз[i] > мкx) мкx = поз[i];
        if (поз[i + 1] < мнy) мнy = поз[i + 1];
        if (поз[i + 1] > мкy) мкy = поз[i + 1];
        if (поз[i + 2] < мнz) мнz = поз[i + 2];
        if (поз[i + 2] > мкz) мкz = поз[i + 2];
      }
      var цx = (мнx + мкx) * 0.5 / 0.3;
      var цy = (мнy + мкy) * 0.5 / 0.3;
      var цz = (мнz + мкz) * 0.5 / 0.3;
      for (i = с0; i < база; i++) {
        цен.push(цx, цy, цz);
        рнд.push(о[2], о[3], о[4]);
      }

      function крышка(ряд, u, опора) {
        var сx = 0, сy = 0, сz = 0, т;
        for (т = 0; т < НП; т++) { сx += ряд[т][0]; сy += ряд[т][1]; сz += ряд[т][2]; }
        var ц = [сx / НП, сy / НП, сz / НП];
        for (т = 0; т < НП; т++) {
          треугольник(ц, ряд[т], ряд[(т + 1) % НП], u,
                      0.5, т / НП, ((т + 1) % НП) / НП, опора);
        }
      }
    }

    var гео = new T.BufferGeometry();
    гео.setAttribute("position", new T.Float32BufferAttribute(поз, 3));
    гео.setAttribute("normal", new T.Float32BufferAttribute(нор, 3));
    гео.setAttribute("uv", new T.Float32BufferAttribute(уф, 2));
    гео.setAttribute("centr", new T.Float32BufferAttribute(цен, 3));
    гео.setAttribute("rand", new T.Float32BufferAttribute(рнд, 3));
    гео.setIndex(инд);
    return гео;
  }

  /* ══════════════════════════════════════════════════════════════════
     ДИСК ДЫМА (их shattered_ring_smoke и ceilingsmoke)
     ══════════════════════════════════════════════════════════════════
     Одна заготовка на оба: у дыма колец просто отрезаны первые шесть
     колец. Радиусы идут ровным шагом 0.03397, высота берётся из таблицы
     купола, развёртка их: u линеен по радиусу (ноль на оси, единица на
     внешнем крае 0.6201), v это угол, делённый на два пи.

     `купол` это множитель высоты: единица для дыма колец (кривая
     3.339*Yc + 0.0999), 0.1 для потолочного и напольного, где их
     собственный масштаб по высоте купол всё равно сплющивает. */
  function куполВысота(r) {
    var t = (r - КУПОЛ_R0) / КУПОЛ_ШАГ;
    var i = Math.floor(t);
    if (i < 0) return КУПОЛ[0];
    if (i >= КУПОЛ.length - 1) return КУПОЛ[КУПОЛ.length - 1];
    return КУПОЛ[i] + (КУПОЛ[i + 1] - КУПОЛ[i]) * (t - i);
  }

  function дискГеометрия(T, r0, r1, колец, сегм, куполК, знак) {
    var поз = [], нор = [], уф = [], инд = [];
    var i, j;
    for (i = 0; i <= колец; i++) {
      var r = r0 + (r1 - r0) * (i / колец);
      var h = (3.339 * куполВысота(r) + 0.0999) * куполК;
      /* Их развёртка: u = 1.6356 * радиус - 0.0142. */
      var u = (r - КУПОЛ_R0) / (0.6201 - КУПОЛ_R0);
      for (j = 0; j <= сегм; j++) {
        var a = j / сегм * Math.PI * 2;
        поз.push(Math.cos(a) * r * МОД, Math.sin(a) * r * МОД, h * МОД);
        нор.push(0, 0, знак);
        уф.push(u, j / сегм);
      }
    }
    for (i = 0; i < колец; i++) {
      for (j = 0; j < сегм; j++) {
        var а = i * (сегм + 1) + j, б = а + 1;
        var в = (i + 1) * (сегм + 1) + j, г = в + 1;
        инд.push(а, в, б, б, в, г);
      }
    }
    var гео = new T.BufferGeometry();
    гео.setAttribute("position", new T.Float32BufferAttribute(поз, 3));
    гео.setAttribute("normal", new T.Float32BufferAttribute(нор, 3));
    гео.setAttribute("uv", new T.Float32BufferAttribute(уф, 2));
    гео.setIndex(инд);
    return гео;
  }

  /* ══════════════════════════════════════════════════════════════════
     ЛЕНТЫ ДЫМНЫХ СЛЕДОВ (их smoke_trail)
     ══════════════════════════════════════════════════════════════════
     Две отдельные ленты постоянной ширины, закрученные наружу от оси. Не
     кольцо и не купол. Числа сняты с их модели по связным кускам и
     осевым линиям:

       лента 1: длина 1.825, ширина 0.3878, радиус 0.059 -> 1.425,
                подъём 0.75, азимут +24 -> -160 градусов;
       лента 2: длина 1.631, ширина 0.3881, радиус 0.281 -> 1.586,
                высота держится низко (-0.32..-0.05), азимут +28 -> -37.

     Максимальный радиус 1.635 БОЛЬШЕ радиуса трубы 1.3: ленты торчат
     сквозь стенку тоннеля, и это работает, потому что проверка глубины
     у них выключена. */
  var ЛЕНТЫ = [
    { рядов: 40, колонок: 6, r0: 0.059, r1: 1.425, a0: 24, a1: -160, z0: -0.014, z1: 0.734, ш: 0.3878 },
    { рядов: 36, колонок: 5, r0: 0.281, r1: 1.586, a0: 28, a1: -37, z0: -0.197, z1: -0.247, ш: 0.3881 }
  ];

  function следГеометрия(T) {
    var поз = [], нор = [], уф = [], инд = [];
    var база = 0;
    for (var л = 0; л < ЛЕНТЫ.length; л++) {
      var L = ЛЕНТЫ[л];
      var рядов = (W && W.ступень === 0) ? Math.round(L.рядов * 0.5) : L.рядов;
      var кол = L.колонок - 1;
      for (var i = 0; i <= рядов; i++) {
        var t = i / рядов;
        /* Радиус растёт с ускорением: у них лента отрывается от оси
           медленно и разгоняется наружу. */
        var r = (L.r0 + (L.r1 - L.r0) * (t * t * 0.45 + t * 0.55)) * МОД;
        var a = (L.a0 + (L.a1 - L.a0) * t) * Math.PI / 180;
        var z = (L.z0 + (L.z1 - L.z0) * t + Math.sin(t * Math.PI) * 0.06) * МОД;
        /* Направление поперёк ленты берётся радиальным: половина её
           треугольников у них лежит плашмя. */
        var кx = Math.cos(a), кy = Math.sin(a);
        for (var j = 0; j <= кол; j++) {
          var s = (j / кол - 0.5) * L.ш * МОД;
          поз.push(кx * r + кx * s, кy * r + кy * s, z);
          нор.push(0, 0, -1);
          уф.push(j / кол, t);
        }
      }
      for (i = 0; i < рядов; i++) {
        for (j = 0; j < кол; j++) {
          var а2 = база + i * (кол + 1) + j, б2 = а2 + 1;
          var в2 = база + (i + 1) * (кол + 1) + j, г2 = в2 + 1;
          инд.push(а2, в2, б2, б2, в2, г2);
        }
      }
      база += (рядов + 1) * (кол + 1);
    }
    var гео = new T.BufferGeometry();
    гео.setAttribute("position", new T.Float32BufferAttribute(поз, 3));
    гео.setAttribute("normal", new T.Float32BufferAttribute(нор, 3));
    гео.setAttribute("uv", new T.Float32BufferAttribute(уф, 2));
    гео.setIndex(инд);
    return гео;
  }

