    "  vFalloff = smoothstep(3.5, 2.3, depth);",
    "  pos.xz = rot2(pos.xz, spinFalloff * 3.14159 * 0.25 * (1.0 - firstRingMask));",
    "  pos.xy = rot2(pos.xy, spinFalloff2 * 3.14159 * 0.25 + uRingY * 0.5);",
