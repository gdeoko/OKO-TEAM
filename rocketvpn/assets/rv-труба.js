    "  float spinFalloff  = falloffsmooth(dist,  8.0, 2.0, 5.0, 0.5);",
    "  float spinFalloff2 = falloffsmooth(dist, 10.0, 2.0, 8.0, 0.5);",
    /* Из плоскости наклоняется ТОЛЬКО самое глубокое поле: маска
       раскрывается в единицу для двух верхних (-1.5 и -4.0) и в ноль для
       нижнего (-6.5). */
    "  float firstRingMask = falloff(uRingY, -4.5, -4.51, 0.01, 0.5);",
