/* Rocket VPN. Фон подземных сцен: экранный градиент по числам igloo.

   ЗАЧЕМ. Владелец: «фон такой же как у них сделать, где частицы, 1:1
   чисто точно такой же». Речь про сцену входа igloo - ту, где камера
   падает сквозь кольца и выходит в комнату с фигурой из частиц. Там у
   них нет ни неба, ни тумана: весь фон это ОДИН экранный градиент.

   ИХ ЧИСЛА (docs/РАЗБОР-IGLOO.md, приём 3 и раздел про большие
   градиенты; docs/РАЗБОР-IGLOO-ДВИЖЕНИЕ.md):

     цвета        #09121f и #6b7685
     разворот     -0.66 радиана
     форма        pow(uv.y, 3.0) * 0.5
     дитеринг     gradient += hash12(vUv * 1000.0 + time) * 0.01

   ПОЧЕМУ ЭКРАННЫЙ, А НЕ НА СФЕРЕ. Градиент считается от gl_FragCoord,
   то есть в координатах экрана. Он не едет и не крутится вместе с
   камерой и остаётся одним полотном на весь кадр - при падении с
   разворотом кадра на полоборота это единственный способ не получить
   вращающийся фон. Наше прежнее небо это оттиск на сфере: он крутился
   бы вместе со взглядом.

   ПОЧЕМУ КУБ ТРЕТЬЕЙ СТЕПЕНИ. Линейный градиент отдаёт середину кадра
   средним цветом, и подземелье выходит серым. Куб прижимает светлое к
   самому верху, а низ держит почти чёрным: свет идёт сверху, из проёма,
   через который мы падаем.

   ПОЧЕМУ ДИТЕРИНГ ОБЯЗАТЕЛЕН. Большой градиент из двух близких тёмных
   цветов на восьми битах распадается на полосы. Амплитуда 0.01 это две
   с половиной ступени из 255, и слагаемое времени меняет узор каждый
   кадр - на глаз это зерно плёнки, а не грязь.

   API:
     RV_ФОН.собрать(мир) -> Mesh | null
     RV_ФОН.сила(v)      - 0 нет фона, 1 фон целиком
     RV_ФОН.кадр(часы)
     RV_ФОН.замер() */
(function (g) {
  "use strict";

  var W = null, T = null;
  var М = {};
  var собрано = false;

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }

  var В_ФОН = [
    "void main(){ gl_Position = vec4(position.xy, 0.999, 1.0); }"
  ].join("\n");

  var Ф_ФОН = [
    "uniform vec2 uRes;",
    "uniform vec3 uC1;",
    "uniform vec3 uC2;",
    "uniform float uTime;",
    "uniform float uSila;",
    "float hash12(vec2 p){",
    "  vec3 p3 = fract(vec3(p.xyx) * 0.1031);",
    "  p3 += dot(p3, p3.yzx + 33.33);",
    "  return fract((p3.x + p3.y) * p3.z);",
    "}",
    "void main(){",
    "  vec2 uv = gl_FragCoord.xy / uRes;",
    /* Разворот вокруг середины кадра: -0.66 радиана, их число. Свет
       после разворота идёт не сверху, а сверху-слева, и это заметно
       живее ровной горизонтали. */
    "  vec2 c = uv - 0.5;",
    "  float ko = cos(-0.66), si = sin(-0.66);",
    "  vec2 r = vec2(c.x * ko - c.y * si, c.x * si + c.y * ko) + 0.5;",
    "  float grad = pow(clamp(r.y, 0.0, 1.0), 3.0) * 0.5;",
    "  grad += hash12(uv * 1000.0 + uTime) * 0.01;",
    "  vec3 color = mix(uC1, uC2, clamp(grad, 0.0, 1.0));",
    "  gl_FragColor = vec4(color, uSila);",
    "}"
  ].join("\n");

  function собрать(мир) {
    if (собрано) return М.квад;
    W = мир || W;
    if (!W || !W.T || !W.cam) return null;
    T = W.T;

    М.мат = new T.ShaderMaterial({
      uniforms: {
        uRes: { value: new T.Vector2(g.innerWidth || 1, g.innerHeight || 1) },
        /* Тёмный конец в низ кадра, светлый в верх: свет идёт из проёма
           над головой, через который мы упали. */
        uC1: { value: new T.Color(0x09121f) },
        uC2: { value: new T.Color(0x6b7685) },
        uTime: { value: 0 },
        uSila: { value: 0 }
      },
      vertexShader: В_ФОН, fragmentShader: Ф_ФОН,
      transparent: true, depthWrite: false, depthTest: false, fog: false
    });

    /* Квад висит на камере и рисуется ПЕРВЫМ. Глубина 0.999 в
       вершинном шейдере ставит его у самой дальней плоскости отсечения,
       поэтому он ничего не закрывает даже без проверки глубины. */
    М.квад = new T.Mesh(new T.PlaneGeometry(2, 2), М.мат);
    М.квад.name = "фон подземелья";
    М.квад.frustumCulled = false;
    /* ПОСЛЕ НЕБА, НО ДО ВСЕГО ОСТАЛЬНОГО. Небо мира стоит на -100, и
       при равном порядке кто рисуется вторым, тот и виден: наш фон
       ложился ПОД звёздное поле, и в шахте сквозь него светили звёзды и
       Земля. Минус девяносто ставит его поверх неба и под всё, что
       принадлежит сцене. Проверки глубины у него нет, поэтому небо он
       закрывает целиком. */
    М.квад.renderOrder = -90;
    М.квад.visible = false;
    W.cam.add(М.квад);
    собрано = true;
    return М.квад;
  }

  function сила(v) {
    if (!собрано) return;
    var с = зажать(v || 0, 0, 1);
    М.мат.uniforms.uSila.value = с;
    М.квад.visible = с > 0.002;
  }

  function кадр(часы) {
    if (!собрано) return;
    М.мат.uniforms.uTime.value = часы || 0;
    var ш = g.innerWidth || 1, в = g.innerHeight || 1;
    var р = М.мат.uniforms.uRes.value;
    if (р.x !== ш || р.y !== в) р.set(ш, в);
  }

  g.RV_ФОН = {
    "собрать": собрать,
    "сила": сила,
    "кадр": кадр,
    "замер": function () {
      if (!собрано) return { "собрано": false };
      return {
        "собрано": true,
        "сила": +М.мат.uniforms.uSila.value.toFixed(3),
        "видно": !!М.квад.visible,
        "цвета": ["#" + М.мат.uniforms.uC1.value.getHexString(),
                  "#" + М.мат.uniforms.uC2.value.getHexString()]
      };
    }
  };
})(window);
