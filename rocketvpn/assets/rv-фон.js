/* Rocket VPN. Оболочка подземелья: их `lightroom`, число в число.

   ГЛАВНОЕ, ЧТО ВЫЯСНИЛОСЬ ПРИ ВТОРОМ РАЗБОРЕ ИХ СБОРКИ. Подземелье у
   igloo СВЕТЛОЕ. Мы держали его тёмным (#09121f -> #6b7685) и потому
   получали ровно то, на что владелец и указал: «комната убогая, вообще
   не реалистичная», «частицы вообще не похожи».

   Тёмная пара действительно есть в их коде, но она принадлежит ДРУГОЙ
   сцене (класс HF, свой треугольник во весь экран с поворотом -0.66).
   Комнату же держит класс `dF` - `lightroom`:

     геометрия  Sphere(100, 32, 32), side BackSide
     место      y = -12.15, renderOrder 2
     цвета      #6a6f7d и #e1e6f1, и вся заливка ещё умножается на 1.1
     градиент   диагональный, по ЭКРАНУ, размытый двумя синус-шумами
     крапины    точечная карта 200 x 100, каждая мигает своей фазой

   ПОЧЕМУ ЭТО МЕНЯЕТ ВСЁ. Частица у них тёмная (#222b42) на светлой
   стороне и светло-серая (#bdc6d4) на освещённой. На тёмном фоне
   половина фигуры пропадает, и вместо статуи из песка остаётся редкая
   россыпь искр - ровно это и было на снимке. На светлом фоне тёмные
   частицы РИСУЮТ силуэт, и фигура читается телом.

   ПОЧЕМУ ЭКРАННЫЙ ГРАДИЕНТ, А НЕ ОТТИСК НА СФЕРЕ. Он считается от
   gl_FragCoord, то есть в координатах экрана, и не едет вместе с
   камерой. При падении с разворотом кадра на полоборота это
   единственный способ не получить вращающийся фон.

   ПОЧЕМУ КВАД НА КАМЕРЕ, А НЕ СФЕРА РАДИУСОМ СТО. Раз заливка всё равно
   считается по экрану, форма носителя не значит ничего: сфера нужна им
   только чтобы попасть в общий проход отрисовки. Квад на дальней
   плоскости отсечения даёт тот же кадр и не требует ни ста единиц
   геометрии, ни попадания камеры внутрь неё.

   API:
     RV_ФОН.собрать(мир) -> Mesh | null
     RV_ФОН.сила(v)      - 0 нет фона, 1 фон целиком
     RV_ФОН.кадр(часы)
     RV_ФОН.замер() */
(function (g) {
  "use strict";

  var W = null, T = null;
  var М = {};
  var собрано = false;

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }

  var В_ФОН = [
    "void main(){ gl_Position = vec4(position.xy, 0.999, 1.0); }"
  ].join("\n");

  var Ф_ФОН = [
    "uniform vec2 uRes;",
    "uniform vec3 uC1;",
    "uniform vec3 uC2;",
    "uniform float uTime;",
    "uniform float uSila;",
    "float hash12(vec2 p){",
    "  vec3 p3 = fract(vec3(p.xyx) * 0.1031);",
    "  p3 += dot(p3, p3.yzx + 33.33);",
    "  return fract((p3.x + p3.y) * p3.z);",
    "}",
    /* Их sinenoise1: шесть синусов на несоизмеримых частотах. */
    "float sinenoise1(vec3 p){",
    "  float val = 0.0;",
    "  val += sin(dot(p, vec3(1.5, 3.4598, 1.234)));",
    "  val += sin(dot(p, vec3(3.12, -3.234, 4.221)));",
    "  val += sin(dot(p, vec3(0.355, 2.3, -1.375)));",
    "  val += sin(dot(p, vec3(-0.156, -3.34, -0.4566)));",
    "  val += sin(dot(p, vec3(-4.1235, -0.485, -1.45)));",
    "  val += sin(dot(p, vec3(2.54, -0.879, -2.123)));",
    "  return val / 6.0;",
    "}",
    "void main(){",
    "  vec2 screenUv = gl_FragCoord.xy / uRes;",
    /* Их ramp: диагональ, дважды размытая шумом. Один шум даёт полосы,
       два на разных частотах и разных скоростях дают облачность. */
    "  float ramp = (screenUv.x + screenUv.y) * 0.5;",
    "  ramp *= sinenoise1(vec3(screenUv, uTime * 0.614)) * 0.5 + 0.5;",
    "  ramp *= sinenoise1(vec3(screenUv * 2.0, uTime * 0.17)) * 0.5 + 0.5;",
    "  vec3 color = mix(uC1, uC2, clamp(ramp, 0.0, 1.0));",
    "  color *= 1.1;",
    /* Крапины. У них это карта dot_pattern на сетке 200 x 100, каждая
       точка мигает своей фазой. Карту считаем: сетка и мягкий кружок в
       ячейке дают тот же рисунок и не требуют файла. */
    /* КРАПИНЫ МЕЛКИЕ И РЕДКИЕ. Первый заход давал кружок в треть ячейки
       и силу в половину: на снимке подземелье стояло в крупный горох во
       весь экран. У них `dots` это значение КАРТЫ, а карта почти везде
       ноль - светится десятая часть ячеек, и пятнышко в ней мельче
       точки экрана. Радиус вшестеро меньше, порог выше, сила вшестеро
       слабее: крапины стали зерном, каким и были. */
    "  vec2 dotUv = screenUv * vec2(200.0, 100.0);",
    "  vec2 kl = floor(dotUv);",
    "  vec2 vn = fract(dotUv) - 0.5;",
    "  float dots = smoothstep(0.13, 0.02, length(vn)) * step(0.93, hash12(kl + 3.7));",
    "  float dotid = hash12(kl);",
    "  float dotfade = 1.0 - abs(fract(dotid + uTime * 0.1) - 0.5) * 2.0;",
    "  color += dots * dotfade * 0.09;",
    "  gl_FragColor = vec4(color, uSila);",
    "}"
  ].join("\n");

  function собрать(мир) {
    if (собрано) return М.квад;
    W = мир || W;
    if (!W || !W.T || !W.cam) return null;
    T = W.T;

    М.мат = new T.ShaderMaterial({
      uniforms: {
        uRes: { value: new T.Vector2(g.innerWidth || 1, g.innerHeight || 1) },
        uC1: { value: new T.Color(0x6a6f7d) },
        uC2: { value: new T.Color(0xe1e6f1) },
        uTime: { value: 0 },
        uSila: { value: 0 }
      },
      vertexShader: В_ФОН, fragmentShader: Ф_ФОН,
      transparent: true, depthWrite: false, depthTest: false, fog: false
    });

    /* Квад висит на камере. Глубина 0.999 в вершинном шейдере ставит его
       у самой дальней плоскости отсечения, поэтому он ничего не
       закрывает даже без проверки глубины. */
    М.квад = new T.Mesh(new T.PlaneGeometry(2, 2), М.мат);
    М.квад.name = "оболочка подземелья";
    М.квад.frustumCulled = false;
    /* ПОСЛЕ НЕБА, НО ДО ВСЕГО ОСТАЛЬНОГО. Небо мира стоит на -100, и при
       равном порядке кто рисуется вторым, тот и виден: наш фон ложился
       ПОД звёздное поле, и в шахте сквозь него светили звёзды и Земля.
       Минус девяносто ставит его поверх неба и под всё, что принадлежит
       сцене. Проверки глубины у него нет, поэтому небо он закрывает
       целиком. */
    М.квад.renderOrder = -90;
    М.квад.visible = false;
    /* Накладка: слой слов гасит камерные узлы перед закадровыми
       снимками, и фон обязан гаснуть вместе с ними. */
    М.квад.userData["накладка"] = true;
    W.cam.add(М.квад);
    собрано = true;
    return М.квад;
  }

  function сила(v) {
    if (!собрано) return;
    var с = зажать(v || 0, 0, 1);
    М.мат.uniforms.uSila.value = с;
    М.квад.visible = с > 0.002;
  }

  function кадр(часы) {
    if (!собрано) return;
    М.мат.uniforms.uTime.value = часы || 0;
    var ш = g.innerWidth || 1, в = g.innerHeight || 1;
    var р = М.мат.uniforms.uRes.value;
    if (р.x !== ш || р.y !== в) р.set(ш, в);
  }

  g.RV_ФОН = {
    "собрать": собрать,
    "сила": сила,
    "кадр": кадр,
    "замер": function () {
      if (!собрано) return { "собрано": false };
      return {
        "собрано": true,
        "сила": +М.мат.uniforms.uSila.value.toFixed(3),
        "видно": !!М.квад.visible,
        "цвета": ["#" + М.мат.uniforms.uC1.value.getHexString(),
                  "#" + М.мат.uniforms.uC2.value.getHexString()]
      };
    }
  };
})(window);
