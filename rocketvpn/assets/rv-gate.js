/* Rocket VPN. Створ на стороне браузера.

   ЭТО ВТОРОЙ УРОВЕНЬ, А НЕ ЕДИНСТВЕННЫЙ. Разметка к этому моменту уже
   у человека, и открыть её можно одной строкой в консоли. Смысл этого
   слоя ровно один: сайт может отдаваться статикой, без PHP, и тогда
   серверного створа нет вовсе. В таком случае этот слой закрывает вход
   от того, кто просто набрал адрес, - и не более того.

   Поэтому здесь НЕ проверяется подпись и НЕ хранится секрет: секрет,
   уехавший в браузер, перестаёт быть секретом. Настоящая проверка живёт
   в gate.php, и когда PHP есть, до этого файла дело не доходит вовсе:
   без ключа сервер отдаёт не эту страницу, а створ.

   Загружается БЕЗ отсрочки, первым: содержимое до решения не должно
   мигнуть даже на кадр. */
(function (g, d) {
  "use strict";

  var КЛЮЧ = "rv_k";
  var СРОК = 7 * 24 * 3600 * 1000;

  function изАдреса() {
    try {
      var m = /[?&]k=([^&#]+)/.exec(g.location.search || "");
      return m ? decodeURIComponent(m[1]) : "";
    } catch (e) { return ""; }
  }

  function изПамяти() {
    try { return g.localStorage.getItem(КЛЮЧ) || ""; } catch (e) { return ""; }
  }

  function запомнить(к) {
    try {
      g.localStorage.setItem(КЛЮЧ, к);
      g.localStorage.setItem(КЛЮЧ + "_t", String(Date.now()));
    } catch (e) {}
  }

  /* Форма ключа: метка времени, точка, подпись. Подпись здесь НЕ
     проверяется - проверить её без секрета нельзя, а секрет сюда класть
     нельзя. Проверяется только форма и возраст: этого хватает, чтобы
     отсеять случайный заход и просроченную ссылку. */
  function формаГодна(к) {
    if (!к) return false;
    var ч = /^(\d{9,12})\.([a-f0-9]{16,64})$/.exec(к);
    if (!ч) return false;
    var метка = parseInt(ч[1], 10) * 1000;
    if (метка > Date.now() + 300000) return false;
    return (Date.now() - метка) <= СРОК;
  }

  function открыть() {
    d.documentElement.classList.add("rv-открыт");
    var с = d.getElementById("rvСтвор");
    if (с && с.parentNode) с.parentNode.removeChild(с);
  }

  var изАдр = изАдреса();
  var к = изАдр || изПамяти();

  if (формаГодна(к)) {
    if (изАдр) запомнить(изАдр);
    открыть();
    /* Ключ из адреса убираем сразу после того, как он принят. Причины
       две. Человек копирует адрес из строки и делится им, не думая о
       том, что делится ключом. И адрес с ключом попадает в историю, в
       закладки и в заголовок источника перехода на чужие сайты. */
    if (изАдр && g.history && g.history.replaceState) {
      try {
        var чистый = g.location.pathname +
          (g.location.search || "").replace(/([?&])k=[^&#]*&?/, "$1").replace(/[?&]$/, "") +
          (g.location.hash || "");
        g.history.replaceState(null, "", чистый);
      } catch (e2) {}
    }
  }

  /* Наружу отдаём только то, что нужно связке: сам ключ, чтобы передать
     его на родственный сайт, и открыт ли створ. Ни одной ручки, которая
     открывает створ по вызову: такая ручка сделала бы весь слой
     бессмысленным. */
  g.RV_GATE = {
    "ключ": function () { return к || ""; },
    "открыт": function () { return d.documentElement.classList.contains("rv-открыт"); }
  };
})(window, document);
