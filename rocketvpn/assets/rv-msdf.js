/* Rocket VPN. Текст в сцене: MSDF по устройству igloo.inc.

   ЗАЧЕМ. Владелец: «текста нету вообще как у igloo текст = код да?» и
   «текст 1:1 как у игло и шрифты и размеры и стиль и цвет и анимации».
   У них в разметке действительно пусто: `<body></body>`, а единственная
   строка настоящего текста на всём сайте это заглушка «WebGL2 не
   поддержан». Всё остальное нарисовано в сцене полем расстояний.

   ШРИФТ ТОТ ЖЕ. У них IBMPlexMono-Medium. Ровно этот шрифт уже лежал в
   проекте, кириллица у IBM Plex своя. Атлас собран из него же
   (tools/сетка-атласа.py), 200 глифов против их ста: нам нужна ещё
   кириллица.

   ГЛАВНЫЙ ПРИЁМ ПОДАЧИ, ДОСЛОВНО ИХ СТРОКА:

       vUv.x = mod(uv.x + 0.125 * mod(floor((1.0 - tr2) * 5.753), 8.0), 1.0);

   Здесь 0.125 это 1/8, ширина столбца ИХ атласа, а 8.0 это число его
   столбцов. Буква прыгает по соседним ячейкам, успевает показать пять-
   шесть ЧУЖИХ глифов и садится на свой, когда прогресс доходит до
   единицы. Дробное 5.753 взято, чтобы буквы не мигали в такт.

   У нас атлас другого размера, поэтому оба числа берутся из его файла:
   ширина ячейки делится на ширину листа (33 на 628), столбцов
   девятнадцать. Всё остальное в строке до символа то же самое.

   ДВЕ СКОРОСТИ, ИХ ЧИСЛА. uShow1 за 0.4 секунды с полем 0.1 это
   непрозрачность, короткий жёсткий фронт слева направо. uShow2 за 0.75
   секунды с полем 1.0 это перебор глифов, размазанный на всю строку.
   Гашение это тот же uShow1 в ноль за 0.2 секунды.

   ПЯТЬ ВЕСОВ. Воркер у них считает пять разных нормированных номеров:
   буквы подряд, слова подряд, буквы внутри строки, слова внутри строки,
   строки. Пять законов, по которым текст может проявляться, и всё это
   считается ОДИН раз при сборке, а в шейдере остаётся один falloff.
   Считаем так же, воркер не заводим: строки сайта короткие, сборка
   пятидесяти глифов занимает доли миллисекунды.

   КЕРНИНГА НЕТ. У них пустой массив, и это честно: шрифт моноширинный,
   xadvance у всех двухсот глифов равен 25.

   API:
     RV_MSDF.готов(колбэк)             дождаться атласа
     RV_MSDF.строка(текст, о)          -> Mesh с геометрией текста
     RV_MSDF.показать(меш, да)         запустить появление или гашение
     RV_MSDF.кадр(dt)                  двигать все живые тексты
     RV_MSDF.мера(текст, о)            -> {ширина, высота, строк} без сборки
   ═══════════════════════════════════════════════════════════════════ */
(function (g) {
  "use strict";

  var АТЛАС = "assets/gen/шрифт/plex.webp";
  var МЕТРИКИ = "assets/gen/шрифт/plex.json";

  /* Их числа, менять только вместе с igloo. */
  var ПОКАЗ1 = 0.4;    /* секунды: непрозрачность */
  var ПОЛЕ1 = 0.1;     /* поле волны непрозрачности */
  var ПОКАЗ2 = 0.75;   /* секунды: перебор глифов */
  var ПОЛЕ2 = 1.0;     /* поле волны перебора */
  var ГАШЕНИЕ = 0.2;   /* секунды */
  var ПРЫЖКОВ = 5.753; /* сколько чужих глифов успеет показать буква */

  var Ш = null;        /* метрики шрифта */
  var Т = null;        /* текстура атласа */
  var ждут = [];
  var живые = [];
  var T = null;

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }

  /* ── Загрузка ─────────────────────────────────────────────────
     Атлас и метрики едут параллельно. Пока не доехали, строка()
     возвращает пустой меш и достраивается сама, когда файлы придут:
     акт не обязан знать про очередь загрузки. */
  var грузим = false;
  function поднять(мир) {
    if (грузим || !мир || !мир.T) return;
    грузим = true;
    T = мир.T;
    var загр = new T.TextureLoader();
    загр.load(АТЛАС, function (т) {
      /* MSDF читается как ДАННЫЕ, а не как цвет: три канала это поле
         расстояний, и перевод в sRGB испортил бы их арифметику. */
      т.colorSpace = T.NoColorSpace || T.LinearSRGBColorSpace || т.colorSpace;
      /* Мипмапов нет: они усредняют поле расстояний соседних глифов и
         буквы расплываются на дальних планах. Зажатие по краям вместо
         повторения по той же причине. */
      т.generateMipmaps = false;
      т.minFilter = T.LinearFilter;
      т.magFilter = T.LinearFilter;
      т.wrapS = т.wrapT = T.ClampToEdgeWrapping;
      Т = т;
      готово();
    });
    var зп = new XMLHttpRequest();
    зп.open("GET", МЕТРИКИ, true);
    зп.onload = function () {
      try { Ш = разобрать(JSON.parse(зп.responseText)); } catch (e) { Ш = null; }
      готово();
    };
    зп.send();
  }

  function готово() {
    if (!Ш || !Т) return;
    var о = ждут; ждут = [];
    for (var i = 0; i < о.length; i++) {
      try { о[i](); } catch (e) {}
    }
  }

  /* ── Метрики ──────────────────────────────────────────────────
     Всё переводится в единицы кегля: кегль это единица мира. Тогда
     размер текста задаётся одним масштабом меша, а числа внутри не
     зависят от того, в каком акте он стоит. */
  function разобрать(d) {
    var с = d["сетка"], общ = d["common"], инф = d["info"];
    var кегль = инф["size"];
    var карта = {};
    var глифы = d["chars"];
    for (var i = 0; i < глифы.length; i++) карта[глифы[i]["id"]] = глифы[i];
    return {
      глифы: карта,
      кегль: кегль,
      база: общ["base"],
      строка: общ["lineHeight"] / кегль,
      листШ: с["листШ"], листВ: с["листВ"],
      ячШ: с["ячейкаШ"], ячВ: с["ячейкаВ"],
      столбцов: с["столбцов"],
      /* Сдвиг на один столбец В ДОЛЯХ ТЕКСТУРЫ. Считается делением
         ячейки на лист, а не единицей на число столбцов: лист округлён
         до кратного четырём, и девятнадцать ячеек по 33 точки дают 627
         при листе 628. Единица на девятнадцать промахнулась бы на точку
         в каждом столбце, и к правому краю атласа перебор уезжал бы на
         соседний глиф целиком. */
      сдвиг: с["ячейкаШ"] / с["листШ"],
      шаг: 0   /* заполнится ниже: xadvance одинаков у всех */
    };
  }

  /* ЗАМЕНЫ ДЛЯ ЗНАКОВ, КОТОРЫХ НЕТ В АТЛАСЕ.

     В атласе двести глифов - кириллица, латиница, цифры и обычная
     пунктуация. Рубля там нет, и строка «499 ₽ месяц» выходила в кадр
     как «499 ? месяц»: вопрос вместо цены, на самом видном месте акта
     про тарифы.

     Молчаливая замена лучше вопроса. Рубль становится буквой «р» - так
     цену пишут в любом прайсе, и человек прочтёт её без запинки. Знак
     доллара и евро в атласе есть, менять их не нужно. Длинное тире по
     правилу проекта у нас не пишется вовсе, но если чужой текст его
     принесёт - станет дефисом, а не вопросом. */
  var ЗАМЕНЫ = {
    8381: 1088,   /* ₽ -> р */
    8212: 45,     /* — -> - */
    8211: 45,     /* – -> - */
    160: 32       /* неразрывный пробел -> обычный */
  };

  function глиф(код) {
    var г = Ш.глифы[код];
    if (г) return г;
    var зам = ЗАМЕНЫ[код];
    if (зам != null && Ш.глифы[зам]) return Ш.глифы[зам];
    return Ш.глифы[63] || null;   /* нет и замены - ставим вопрос */
  }

  /* ── Разбивка на строки ───────────────────────────────────────
     Их воркер копит ширину и при выходе за предел откатывается к
     последнему пробелу. Повторяем: перенос по словам, а по буквам
     только если одно слово длиннее строки целиком. */
  function разбить(текст, ширина) {
    var слова = String(текст).split(/\s+/).filter(function (с) { return с.length; });
    var шагЕд = 0;
    var пробн = глиф(65);
    if (пробн) шагЕд = пробн["xadvance"] / Ш.кегль;
    if (!ширина || ширина <= 0) return [слова.join(" ")];
    var строки = [], тек = "";
    for (var i = 0; i < слова.length; i++) {
      var сл = слова[i];
      var проба = тек ? тек + " " + сл : сл;
      if (проба.length * шагЕд <= ширина || !тек) {
        /* Слово длиннее всей строки: режем по буквам, иначе оно уедет
           за край и утащит с собой выравнивание. */
        if (!тек && сл.length * шагЕд > ширина) {
          var влезает = Math.max(1, Math.floor(ширина / шагЕд));
          while (сл.length > влезает) {
            строки.push(сл.slice(0, влезает));
            сл = сл.slice(влезает);
          }
          тек = сл;
          continue;
        }
        тек = проба;
      } else {
        строки.push(тек);
        тек = сл;
      }
    }
    if (тек) строки.push(тек);
    return строки;
  }

  function мера(текст, о) {
    if (!Ш) return { ширина: 0, высота: 0, строк: 0 };
    о = о || {};
    var строки = разбить(текст, о["ширина"] || 0);
    var шаг = глиф(65)["xadvance"] / Ш.кегль;
    var макс = 0;
    for (var i = 0; i < строки.length; i++) макс = Math.max(макс, строки[i].length * шаг);
    return { ширина: макс, высота: строки.length * Ш.строка, строк: строки.length };
  }

  /* ── Сборка геометрии ─────────────────────────────────────────
     Четыре вершины и шесть индексов на глиф. Пробелы и переводы строк
     места не занимают, ровно как у них. */
  function геометрия(текст, о) {
    var ширПред = о["ширина"] || 0;
    var выравн = о["выравнивание"] || "лево";
    var строки = разбить(текст, ширПред);
    var шаг = глиф(65)["xadvance"] / Ш.кегль;

    /* Сначала считаем, сколько будет видимых глифов и слов: пять весов
       нормируются на общее число, и знать его надо до укладки. */
    var всегоГлифов = 0, всегоСлов = 0;
    var поСтрокам = [];
    for (var с = 0; с < строки.length; с++) {
      var видимых = строки[с].replace(/\s/g, "").length;
      var слов = строки[с].split(/\s+/).filter(function (x) { return x.length; }).length;
      поСтрокам.push({ глифов: видимых, слов: слов });
      всегоГлифов += видимых;
      всегоСлов += слов;
    }
    if (!всегоГлифов) return null;

    var поз = new Float32Array(всегоГлифов * 4 * 3);
    var уф = new Float32Array(всегоГлифов * 4 * 2);
    var маска = new Float32Array(всегоГлифов * 4 * 4);
    var весТ = new Float32Array(всегоГлифов * 4 * 2);
    var весС = new Float32Array(всегоГлифов * 4 * 3);
    var центр = new Float32Array(всегоГлифов * 4 * 3);
    var инд = new Uint16Array(всегоГлифов * 6);

    var к = 0;              /* сквозной номер глифа */
    var номСлова = 0;       /* сквозной номер слова */
    var делГ = Math.max(1, всегоГлифов - 1);
    var делС = Math.max(1, всегоСлов - 1);
    var делСтр = Math.max(1, строки.length - 1);
    var верхБлока = 0;

    for (var л = 0; л < строки.length; л++) {
      var стр = строки[л];
      var шир = стр.length * шаг;
      var x0 = 0;
      if (выравн === "центр") x0 = -шир * 0.5;
      else if (выравн === "право") x0 = -шир;
      var y0 = верхБлока - л * Ш.строка;
      var вСтроке = 0, словоВСтроке = 0;
      var делГС = Math.max(1, поСтрокам[л].глифов - 1);
      var делСС = Math.max(1, поСтрокам[л].слов - 1);
      var новоеСлово = true;

      for (var i = 0; i < стр.length; i++) {
        var симв = стр.charCodeAt(i);
        if (симв === 32) { x0 += шаг; новоеСлово = true; continue; }
        if (новоеСлово) { новоеСлово = false; } else if (i > 0) { /* внутри слова */ }
        var г = глиф(симв);
        if (!г) { x0 += шаг; continue; }

        /* Квад глифа. Верх и низ считаются от базовой линии: bmfont
           меряет y сверху строки вниз, а сцена снизу вверх. */
        var лx = x0 + г["xoffset"] / Ш.кегль;
        var пx = лx + г["width"] / Ш.кегль;
        var вy = y0 + (Ш.база - г["yoffset"]) / Ш.кегль;
        var нy = вy - г["height"] / Ш.кегль;

        var u0 = г["x"] / Ш.листШ;
        var u1 = (г["x"] + г["width"]) / Ш.листШ;
        var v0 = 1 - (г["y"] + г["height"]) / Ш.листВ;
        var v1 = 1 - г["y"] / Ш.листВ;

        var о4 = к * 4;
        var вx = [лx, пx, пx, лx], вy4 = [нy, нy, вy, вy];
        var уx = [u0, u1, u1, u0], уy = [v0, v0, v1, v1];
        var цx = (лx + пx) * 0.5, цy = (нy + вy) * 0.5;

        var тx = к / делГ;
        var тy = номСлова / делС;
        var сx = вСтроке / делГС;
        var сy = словоВСтроке / делСС;
        var сz = л / делСтр;

        for (var в = 0; в < 4; в++) {
          var п3 = (о4 + в) * 3, п2 = (о4 + в) * 2, п4 = (о4 + в) * 4;
          поз[п3] = вx[в]; поз[п3 + 1] = вy4[в]; поз[п3 + 2] = 0;
          уф[п2] = уx[в]; уф[п2 + 1] = уy[в];
          /* uvMask это границы своей ячейки. У них он нужен второй,
             невключённой анимации; держим его, чтобы шейдер мог при
             желании зажать езду по UV внутри глифа. */
          маска[п4] = u0; маска[п4 + 1] = u1; маска[п4 + 2] = v0; маска[п4 + 3] = v1;
          весТ[п2] = тx; весТ[п2 + 1] = тy;
          весС[п3] = сx; весС[п3 + 1] = сy; весС[п3 + 2] = сz;
          центр[п3] = цx; центр[п3 + 1] = цy; центр[п3 + 2] = 0;
        }
        var и = к * 6;
        инд[и] = о4; инд[и + 1] = о4 + 1; инд[и + 2] = о4 + 2;
        инд[и + 3] = о4; инд[и + 4] = о4 + 2; инд[и + 5] = о4 + 3;

        к++; вСтроке++;
        x0 += шаг;
      }
      /* Слова считаем по строке целиком: внутри цикла по буквам номер
         слова пришлось бы догонять пробелами, и последнее слово строки
         получило бы номер следующей. */
      номСлова += поСтрокам[л].слов;
      словоВСтроке = 0;
    }

    var гео = new T.BufferGeometry();
    гео.setAttribute("position", new T.BufferAttribute(поз, 3));
    гео.setAttribute("uv", new T.BufferAttribute(уф, 2));
    гео.setAttribute("uvMask", new T.BufferAttribute(маска, 4));
    гео.setAttribute("textWeights", new T.BufferAttribute(весТ, 2));
    гео.setAttribute("lineWeights", new T.BufferAttribute(весС, 3));
    гео.setAttribute("centr", new T.BufferAttribute(центр, 3));
    гео.setIndex(new T.BufferAttribute(инд, 1));
    гео.computeBoundingSphere();
    гео.userData["строк"] = строки.length;
    гео.userData["высота"] = строки.length * Ш.строка;
    return гео;
  }

  /* ── Шейдер ───────────────────────────────────────────────────
     Их falloff дословно: волна шириной margin, которая едет по значению
     веса от start-margin до end по мере роста progress. Одна формула
     закрывает и появление, и исчезание, и любой из пяти весов. */
  var В_ТЕКСТ = [
    "attribute vec4 uvMask;",
    "attribute vec2 textWeights;",
    "attribute vec3 lineWeights;",
    "attribute vec3 centr;",
    "uniform float uShow1;",
    "uniform float uShow2;",
    "uniform float uShift;",
    "uniform float uCols;",
    "uniform float uJumps;",
    "uniform float uBillboard;",
    "varying vec2 vUv;",
    "varying float vAlpha;",
    "varying float vWeight;",
    "float _linstep(float b, float e, float t){ return clamp((t - b) / (e - b), 0.0, 1.0); }",
    "float falloff(float x, float start, float end, float margin, float progress){",
    "  float m = margin * sign(end - start);",
    "  float p = mix(start - m, end, progress);",
    "  return _linstep(p + m, p, x);",
    "}",
    "void main(){",
    "  float tr1 = falloff(textWeights.x, 0.0, 1.0, 0.1, clamp(uShow1, 0.0, 1.0));",
    "  float tr2 = falloff(textWeights.x, 0.0, 1.0, 1.0, clamp(uShow2, 0.0, 1.0));",
    "  vUv = uv;",
    /* Их строка. Ширина столбца и число столбцов вынесены в униформы:
       у нас атлас другого размера, всё остальное до символа то же. */
    "  vUv.x = mod(uv.x + uShift * mod(floor((1.0 - tr2) * uJumps), uCols), 1.0);",
    "  vAlpha = tr1;",
    "  vWeight = textWeights.x;",
    "  vec4 mv;",
    /* Билборд: разворот лицом к камере с сохранением масштаба. Столбцы
       поворота берутся у видовой матрицы, поэтому текст всегда читается
       плашмя, куда бы ни ехала камера. */
    "  if (uBillboard > 0.5) {",
    "    vec3 sc = vec3(length(modelMatrix[0].xyz), length(modelMatrix[1].xyz), length(modelMatrix[2].xyz));",
    "    vec3 mid = (modelMatrix * vec4(0.0, 0.0, 0.0, 1.0)).xyz;",
    "    vec3 pv = viewMatrix[0].xyz * (position.x * sc.x) + viewMatrix[1].xyz * (position.y * sc.y);",
    "    mv = viewMatrix * vec4(mid + pv, 1.0);",
    "  } else {",
    "    mv = viewMatrix * modelMatrix * vec4(position, 1.0);",
    "  }",
    "  gl_Position = projectionMatrix * mv;",
    "}"
  ].join("\n");

  var Ф_ТЕКСТ = [
    "uniform sampler2D tMap;",
    "uniform vec3 uColor;",
    "uniform float uOpacity;",
    "uniform float uThickness;",
    "varying vec2 vUv;",
    "varying float vAlpha;",
    "varying float vWeight;",
    "float median(float r, float g, float b){ return max(min(r, g), min(max(r, g), b)); }",
    "void main(){",
    "  vec3 s = texture2D(tMap, vUv).rgb;",
    "  float sd = median(s.r, s.g, s.b);",
    /* Ширина сглаживания берётся производной самого поля, а не числом.
       Число пришлось бы подбирать под каждый масштаб текста в сцене, а
       производная знает настоящий размер буквы на экране: у дальнего
       заголовка край мягче, у ближнего резче, и оба остаются чистыми. */
    "  float w = fwidth(sd);",
    "  float a = smoothstep(0.5 - w - uThickness, 0.5 + w - uThickness, sd);",
    "  a *= vAlpha * uOpacity;",
    "  if (a < 0.004) discard;",
    "  gl_FragColor = vec4(uColor, a);",
    "}"
  ].join("\n");

  function строка(текст, о) {
    о = о || {};
    var меш = new T.Mesh(new T.BufferGeometry(), новыйМатериал(о));
    меш.name = "текст: " + String(текст).slice(0, 24);
    меш.frustumCulled = false;
    меш.userData["текст"] = текст;
    меш.userData["о"] = о;
    меш.userData["показ"] = { пок1: 0, пок2: 0, цель: 0, живёт: false };

    function собрать() {
      var гео = геометрия(текст, о);
      if (!гео) return;
      меш.geometry.dispose();
      меш.geometry = гео;
      меш.material.uniforms.tMap.value = Т;
      меш.material.uniforms.uShift.value = Ш.сдвиг;
      меш.material.uniforms.uCols.value = Ш.столбцов;
      меш.userData["высота"] = гео.userData["высота"];
      меш.userData["строк"] = гео.userData["строк"];
    }
    if (Ш && Т) собрать(); else ждут.push(собрать);
    return меш;
  }

  function новыйМатериал(о) {
    var цвет = о["цвет"] == null ? 0xE8EAF6 : о["цвет"];
    return new T.ShaderMaterial({
      uniforms: {
        tMap: { value: Т },
        uColor: { value: new T.Color(цвет) },
        uOpacity: { value: о["прозрачность"] == null ? 1 : о["прозрачность"] },
        /* Утолщение сдвигает порог поля расстояний. Ноль это шрифт как
           он есть; лёгкий минус даёт жирнее, плюс тоньше. Нужен там, где
           мелкий текст на светлом фоне съедается сглаживанием. */
        uThickness: { value: о["толщина"] || 0 },
        uShow1: { value: 0 },
        uShow2: { value: 0 },
        uShift: { value: Ш ? Ш.сдвиг : 0.125 },
        uCols: { value: Ш ? Ш.столбцов : 8 },
        uJumps: { value: о["прыжков"] || ПРЫЖКОВ },
        uBillboard: { value: о["билборд"] ? 1 : 0 }
      },
      vertexShader: В_ТЕКСТ, fragmentShader: Ф_ТЕКСТ,
      transparent: true, depthWrite: false, fog: false,
      side: о["двусторонний"] ? T.DoubleSide : T.FrontSide
    });
  }

  /* ── Показ и гашение ──────────────────────────────────────────
     Их две скорости: непрозрачность за 0.4 секунды, перебор глифов за
     0.75. Гашение это та же непрозрачность в ноль за 0.2. */
  function показать(меш, да) {
    if (!меш || !меш.userData["показ"]) return;
    var п = меш.userData["показ"];
    п.цель = да ? 1 : 0;
    if (!п.живёт) { п.живёт = true; живые.push(меш); }
  }

  function кадр(dt) {
    var шаг = Math.min(0.1, Math.max(0.001, dt || 0.016));
    for (var i = живые.length - 1; i >= 0; i--) {
      var меш = живые[i];
      var п = меш.userData["показ"];
      var у = меш.material.uniforms;
      if (п.цель > 0.5) {
        п.пок1 = Math.min(1, п.пок1 + шаг / ПОКАЗ1);
        п.пок2 = Math.min(1, п.пок2 + шаг / ПОКАЗ2);
      } else {
        п.пок1 = Math.max(0, п.пок1 - шаг / ГАШЕНИЕ);
        /* Перебор при гашении откатывается вместе с прозрачностью: буквы
           уходят, снова рассыпаясь по чужим глифам. */
        п.пок2 = Math.max(0, п.пок2 - шаг / ГАШЕНИЕ);
      }
      у.uShow1.value = п.пок1;
      у.uShow2.value = п.пок2;
      var кончилось = (п.цель > 0.5 && п.пок1 >= 1 && п.пок2 >= 1) ||
                      (п.цель < 0.5 && п.пок1 <= 0 && п.пок2 <= 0);
      if (кончилось) { п.живёт = false; живые.splice(i, 1); }
    }
  }

  g.RV_MSDF = {
    "поднять": поднять,
    "готов": function (кб) { if (Ш && Т) кб(); else ждут.push(кб); },
    "есть": function () { return !!(Ш && Т); },
    "строка": строка,
    "мера": мера,
    "показать": показать,
    "кадр": кадр,
    "поле": function () { return { ПОКАЗ1: ПОКАЗ1, ПОЛЕ1: ПОЛЕ1, ПОКАЗ2: ПОКАЗ2, ПОЛЕ2: ПОЛЕ2 }; },
    "замер": function () {
      if (!Ш || !Т) return { "готов": false };
      return {
        "готов": true, "глифов": Object.keys(Ш.глифы).length,
        "сетка": [Ш.столбцов, Math.round(Ш.листВ / Ш.ячВ)],
        "сдвиг": +Ш.сдвиг.toFixed(6), "кегль": Ш.кегль,
        "строка": +Ш.строка.toFixed(3), "живых": живые.length
      };
    }
  };
})(window);
