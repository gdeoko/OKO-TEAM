/* Rocket VPN. Объект из частиц: ракета, собранная из десятков тысяч точек.

   ЗАЧЕМ. Владелец показал кадры igloo.inc, где голова моаи и буква M
   набраны не поверхностью, а РОЕМ МЕЛКИХ ТОЧЕК, и сказал: «частицы тоже
   даже не в цветах стиля а 1:1», «ракету делаем сами но по механике как
   у них сделаны частицы со свечением».

   ЧТО У НИХ (разбор их кода, docs/РАЗБОР-IGLOO-ДВИЖЕНИЕ.md, раздел 4):
   сто пятьдесят тысяч точек THREE.Points, положение считается на
   видеокарте по двум мишеням 388x388, а ФОРМУ задаёт трёхмерная
   текстура знакового расстояния, снятая с объёмной модели. Силы: к
   поверхности 0.0015, пружина домой 0.001, завихрение 0.0002, трение
   0.9. Размер точки 10/дальность, помноженное на высоту кадра к 1300.
   Свечение своим смешиванием плюс блум с нулевым порогом.

   ЧТО ЗДЕСЬ И ПОЧЕМУ ИНАЧЕ. Объёмной текстуры знакового расстояния у нас
   нет и делать её нечем: она печётся из модели в VDB отдельным
   конвейером. Но она нужна им ровно для одного - знать, КУДА тянуть
   точку, чтобы та села на поверхность. Мы это знаем и без неё: точки
   снимаются С САМОЙ ПОВЕРХНОСТИ при сборке, и место каждой запоминается
   как её дом. Тогда сила «к поверхности» становится силой «домой», а
   это ровно одна пружина вместо двух и никакой мишени.

   Отсюда и главное следствие: считать положение на видеокарте больше
   незачем. Дом лежит атрибутом, отклонение от дома целиком описывается
   завихрением по времени, и всё это укладывается в вершинный шейдер за
   один проход, без мишеней, без чтения текстур и без прогрева в тысячу
   кадров, который им нужен для раскачки решателя.

   СНЯТИЕ ТОЧЕК ПО ПЛОЩАДИ, А НЕ ПО ВЕРШИНАМ. Если брать вершины меша,
   рой повторит его сетку: густо там, где мелкие треугольники, пусто на
   крупных гранях. Точка ставится в случайное место случайного
   треугольника, а треугольник выбирается с весом своей площади. Тогда
   плотность роя одинакова по всей поверхности, как и должно быть. */
(function (g, d) {
  "use strict";

  var T = null, W = null;

  /* ── Ракета: своя геометрия ───────────────────────────────────
     Корпус, носовой конус, юбка сопла и четыре киля. Собирается из
     примитивов и сплавляется в один список треугольников: рою всё равно,
     из чего снята поверхность, ему нужны только треугольники. */
  function ракетаГео() {
    var части = [];
    function влить(гео, сдвиг, поворот, масштаб) {
      var м = new T.Matrix4();
      var кв = new T.Quaternion();
      if (поворот) кв.setFromEuler(new T.Euler(поворот[0], поворот[1], поворот[2]));
      м.compose(new T.Vector3(сдвиг[0], сдвиг[1], сдвиг[2]), кв,
                new T.Vector3(масштаб ? масштаб[0] : 1, масштаб ? масштаб[1] : 1, масштаб ? масштаб[2] : 1));
      гео.applyMatrix4(м);
      части.push(гео.index ? гео.toNonIndexed() : гео);
    }
    /* Корпус: чуть сужается кверху, как у настоящей ступени. */
    влить(new T.CylinderGeometry(0.30, 0.34, 1.70, 28, 1, true), [0, 0.15, 0]);
    /* Носовой конус. */
    влить(new T.ConeGeometry(0.30, 0.78, 28, 1, true), [0, 1.39, 0]);
    /* Юбка сопла. */
    влить(new T.CylinderGeometry(0.34, 0.21, 0.30, 24, 1, true), [0, -0.85, 0]);
    /* Четыре киля, развёрнутые крестом. */
    for (var k = 0; k < 4; k++) {
      var г = new T.BoxGeometry(0.03, 0.46, 0.34);
      влить(г, [Math.cos(k * Math.PI / 2) * 0.40, -0.55, Math.sin(k * Math.PI / 2) * 0.40],
            [0, -k * Math.PI / 2, 0]);
    }
    /* Сплав: три числа на вершину, всё подряд. */
    var всего = 0, i;
    for (i = 0; i < части.length; i++) всего += части[i].attributes.position.count;
    var поз = new Float32Array(всего * 3);
    var о = 0;
    for (i = 0; i < части.length; i++) {
      поз.set(части[i].attributes.position.array, о);
      о += части[i].attributes.position.count * 3;
      части[i].dispose();
    }
    return поз;
  }

  /* Снятие точек с поверхности по площади треугольников. */
  function снять(поз, сколько, семя) {
    var треуг = числоТреугольников(поз);
    var площ = new Float64Array(треуг);
    var сум = 0, i;
    for (i = 0; i < треуг; i++) {
      var a = i * 9;
      var ax = поз[a], ay = поз[a + 1], az = поз[a + 2];
      var bx = поз[a + 3], by = поз[a + 4], bz = поз[a + 5];
      var cx = поз[a + 6], cy = поз[a + 7], cz = поз[a + 8];
      var ux = bx - ax, uy = by - ay, uz = bz - az;
      var vx = cx - ax, vy = cy - ay, vz = cz - az;
      var nx = uy * vz - uz * vy, ny = uz * vx - ux * vz, nz = ux * vy - uy * vx;
      сум += 0.5 * Math.sqrt(nx * nx + ny * ny + nz * nz);
      площ[i] = сум;
    }
    var с = семя || 1;
    function сл() { с = (с * 1103515245 + 12345) % 2147483648; return с / 2147483648; }
    var дом = new Float32Array(сколько * 3);
    var шум = new Float32Array(сколько * 3);
    for (var p = 0; p < сколько; p++) {
      /* Треугольник выбирается двоичным поиском по накопленной площади:
         большая грань получает пропорционально больше точек. */
      var ц = сл() * сум, лев = 0, прав = треуг - 1;
      while (лев < прав) { var с2 = (лев + прав) >> 1; if (площ[с2] < ц) лев = с2 + 1; else прав = с2; }
      var b = лев * 9;
      /* Равномерная точка внутри треугольника: корень первой случайной
         снимает скос к одной вершине. */
      var r1 = Math.sqrt(сл()), r2 = сл();
      var w0 = 1 - r1, w1 = r1 * (1 - r2), w2 = r1 * r2;
      дом[p * 3] = поз[b] * w0 + поз[b + 3] * w1 + поз[b + 6] * w2;
      дом[p * 3 + 1] = поз[b + 1] * w0 + поз[b + 4] * w1 + поз[b + 7] * w2;
      дом[p * 3 + 2] = поз[b + 2] * w0 + поз[b + 5] * w1 + поз[b + 8] * w2;
      шум[p * 3] = сл(); шум[p * 3 + 1] = сл(); шум[p * 3 + 2] = сл();
    }
    return { дом: дом, шум: шум };
  }
  function числоТреугольников(поз) { return Math.floor(поз.length / 9); }

  /* ── Шейдеры ──────────────────────────────────────────────────*/
  var В_РОЙ = [
    "attribute vec3 aHome;",
    "attribute vec3 aRnd;",
    "uniform float uTime;",
    "uniform float uScatter;",
    "uniform float uH;",
    "uniform float uSize;",
    "uniform float uFar;",
    "varying float vBr;",
    /* Завихрение: три синуса по месту и времени. Настоящий curl-шум тут
       не нужен - от него отличается только рисунок вихря, а стоит он
       втрое дороже на точку. */
    "vec3 vihr(vec3 p, float t){",
    "  return vec3(",
    "    sin(p.y * 3.1 + t * 0.7) + sin(p.z * 2.3 - t * 0.5),",
    "    sin(p.z * 2.7 - t * 0.6) + sin(p.x * 3.3 + t * 0.4),",
    "    sin(p.x * 2.9 + t * 0.5) + sin(p.y * 2.1 - t * 0.8));",
    "}",
    "void main(){",
    "  vec3 p = aHome;",
    /* Покойное дыхание роя: точка всегда чуть гуляет вокруг дома, иначе
       рой читается пыльной моделью, а не живым облаком. */
    "  vec3 w = vihr(aHome * 1.7 + aRnd * 6.28, uTime);",
    "  p += w * 0.006;",
    /* Разлёт: та же сила, но множителем наружу и с разбросом по точке,
       поэтому рой рассыпается неровно, как у них. */
    "  p += w * uScatter * mix(0.10, 0.55, aRnd.x);",
    "  p += normalize(aHome + 0.001) * uScatter * mix(0.05, 0.40, aRnd.z);",
    "  vec4 mv = modelViewMatrix * vec4(p, 1.0);",
    /* Их формула размера: обратная дальность, приведённая к высоте кадра
       через 1300. Зажим снизу нужен, иначе дальние точки пропадают в
       субпиксель и рой рвётся. */
    "  gl_PointSize = clamp(uSize / max(0.35, -mv.z) * (uH / 1300.0), 1.0, 7.0);",
    /* Дальние тише: даёт глубину без всякого тумана. */
    /* ОКНО ВИДИМОСТИ ПО ДАЛЬНОСТИ. Стояло 2..26 единиц, и рой пропадал
       насовсем: акты ставят предметы в своих гнёздах за сотни единиц от
       начала мира, и до роя выходило заметно больше двадцати шести.
       Замер поймал это точно - точки есть, узел в кадре и видим, а на
       экране пусто. Окно расширено до 140 и вынесено в униформу, чтобы
       акт мог подогнать его под своё расстояние. */
    "  vBr = smoothstep(0.3, 2.0, -mv.z) * smoothstep(uFar, uFar * 0.16, -mv.z);",
    "  vBr *= mix(0.55, 1.0, aRnd.y);",
    "  vBr *= 1.0 - uScatter * 0.35;",
    "  gl_Position = projectionMatrix * mv;",
    "}"
  ].join("\n");

  var Ф_РОЙ = [
    "uniform vec3 uCol;",
    "uniform vec3 uCore;",
    "varying float vBr;",
    "void main(){",
    "  vec2 pc = gl_PointCoord - 0.5;",
    "  float r = length(pc) * 2.0;",
    "  if (r > 1.0) discard;",
    /* Мягкий круг с ядром: у igloo точка не плоский квадрат, у неё есть
       середина и спад. Степень 1.8 даёт спад, похожий на шарик. */
    "  float a = pow(1.0 - r, 1.8);",
    "  vec3 c = mix(uCol, uCore, pow(1.0 - r, 3.0));",
    "  gl_FragColor = vec4(c, a * vBr);",
    "}"
  ].join("\n");

  /* ── Сборка ───────────────────────────────────────────────────*/
  var М = {};
  var собрано = false;

  function собрать(мир, гнездо, опц) {
    if (собрано) return М.рой;
    W = мир; T = W.T;
    опц = опц || {};
    var ст = W.ступень;
    /* У них полтораста тысяч на объём. У нас поверхность, а не объём:
       той же плотности хватает вчетверо меньшего числа, потому что точки
       не тратятся на внутренность, которой не видно. */
    var сколько = ст === 0 ? 9000 : (ст === 1 ? 24000 : 46000);

    var поз = ракетаГео();
    var снято = снять(поз, сколько, 2024);

    var гео = new T.BufferGeometry();
    /* position нужен движку для отсечения по объёму; настоящее место
       точки считает шейдер из aHome. */
    гео.setAttribute("position", new T.BufferAttribute(снято.дом.slice(), 3));
    гео.setAttribute("aHome", new T.BufferAttribute(снято.дом, 3));
    гео.setAttribute("aRnd", new T.BufferAttribute(снято.шум, 3));

    М.uTime = { value: 0 };
    М.uScatter = { value: 0 };
    М.мат = new T.ShaderMaterial({
      uniforms: {
        uTime: М.uTime, uScatter: М.uScatter,
        uH: { value: 900 },
        uSize: { value: опц["размер"] != null ? опц["размер"] : 9.0 },
        uFar: { value: опц["даль"] != null ? опц["даль"] : 140.0 },
        uCol: { value: new T.Color(опц["цвет"] != null ? опц["цвет"] : 0x8FA6E8) },
        uCore: { value: new T.Color(опц["ядро"] != null ? опц["ядро"] : 0xEAF1FF) }
      },
      vertexShader: В_РОЙ, fragmentShader: Ф_РОЙ,
      transparent: true, depthWrite: false,
      blending: T.AdditiveBlending, fog: false
    });
    М.рой = new T.Points(гео, М.мат);
    М.рой.name = "ракета-рой";
    М.рой.frustumCulled = false;
    М.рой.renderOrder = 6;
    (гнездо || W.scene).add(М.рой);
    собрано = true;
    return М.рой;
  }

  function кадр(dt, часы) {
    if (!собрано) return;
    М.uTime.value = часы;
    if (W.r && W.r.getDrawingBufferSize) {
      if (!М._р) М._р = new T.Vector2();
      W.r.getDrawingBufferSize(М._р);
      М.мат.uniforms.uH.value = М._р.y || 900;
    }
  }

  function разлёт(v) { if (М.uScatter) М.uScatter.value = v; }

  g.RV_ЧАСТИЦЫ = {
    "собрать": собрать,
    "кадр": кадр,
    "разлёт": разлёт,
    "узел": function () { return М.рой || null; },
    "замер": function () {
      return {
        "собрано": собрано,
        "точек": М.рой ? М.рой.geometry.attributes.position.count : 0,
        "разлёт": М.uScatter ? +М.uScatter.value.toFixed(3) : 0
      };
    }
  };
})(window, document);
