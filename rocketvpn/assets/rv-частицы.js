/* Rocket VPN. Ракета из частиц: механика и вид igloo.inc, один в один.

   ЗАЧЕМ ПЕРЕПИСАНО. Владелец: «частицы вообще не похожи ни коем образом
   на igloo ... модель ракеты должна быть с такими же частицами 1:1 как
   igloo». Прежний рой светился аддитивно мягкими голубыми пятнами и
   читался пылью. У них не так, и разбор их сборки это показывает прямо
   (docs/РАЗБОР-IGLOO-ТОННЕЛЬ.md, раздел про фигуру):

   ЧАСТИЦА У НИХ ЭТО ЗАТЕНЁННЫЙ ШАРИК, А НЕ ИСКРА. В кадре считается
   нормаль полушария, по ней берётся свет от источника (-0.75, 1, -0.1),
   и цвет идёт от тёмно-синего #222b42 в тени до светло-серого #bdc6d4 на
   свету. Быстрые точки уходят в #d7ebfa. Смешивание СВОЁ: источник по
   своей прозрачности, приёмник по ЦВЕТУ источника - тёмная частица
   ЗАТЕМНЯЕТ фон, а не подсвечивает его. Из этого и получается статуя из
   песка вместо роя светлячков.

   Их числа, перенесённые сюда дословно:

     uSize 10, gl_PointSize = uSize / length(viewPos) * (высота / 1300)
     uColorDark #222b42  uColorLight #bdc6d4
     uColorFast #d7ebfa  uColorInitial #b5d5ff
     uLightPos (-0.75, 1, -0.1), обёрнутый диффуз с wrap 0.25 и отскоком 0.1
     alpha *= max(uInitialGlow, pow(fit(vVel, 0.002, 0.007, 1.0, 0.0), 2.0) * 0.5 + 0.5)
     depthTest true, depthWrite true
     blending Custom, equation Add, src SrcAlpha, dst SrcColor
     вращение фигуры 0.75 радиана в секунду

   ЧТО ОСТАЛОСЬ НАШИМ И ПОЧЕМУ. Форму они берут из объёмной текстуры
   знакового расстояния, испечённой из модели отдельным конвейером (VDB).
   Такого конвейера у нас нет, и качать чужой объём нельзя. Но нужен он
   им ровно для двух чисел: КУДА тянуть точку и КАКАЯ ТАМ НОРМАЛЬ. Оба мы
   знаем без него - точка снимается С САМОЙ ПОВЕРХНОСТИ ракеты при сборке,
   и нормаль её треугольника запоминается рядом. Поэтому решателя на
   видеокарте здесь нет, а вид получается тот же: затенение считается по
   настоящей нормали поверхности, а не по выдуманной.

   СНЯТИЕ ТОЧЕК ПО ПЛОЩАДИ, А НЕ ПО ВЕРШИНАМ. Если брать вершины меша,
   рой повторит его сетку: густо там, где мелкие треугольники, пусто на
   крупных гранях. Точка ставится в случайное место случайного
   треугольника, а треугольник выбирается с весом своей площади. */
(function (g, d) {
  "use strict";

  var T = null, W = null;

  /* ── Ракета: своя геометрия ───────────────────────────────────
     Корпус, носовой конус, юбка сопла и четыре киля. Собирается из
     примитивов и сплавляется в один список треугольников: рою всё равно,
     из чего снята поверхность, ему нужны только треугольники. */
  function ракетаГео() {
    var части = [];
    function влить(гео, сдвиг, поворот, масштаб) {
      var м = new T.Matrix4();
      var кв = new T.Quaternion();
      if (поворот) кв.setFromEuler(new T.Euler(поворот[0], поворот[1], поворот[2]));
      м.compose(new T.Vector3(сдвиг[0], сдвиг[1], сдвиг[2]), кв,
                new T.Vector3(масштаб ? масштаб[0] : 1, масштаб ? масштаб[1] : 1, масштаб ? масштаб[2] : 1));
      гео.applyMatrix4(м);
      части.push(гео.index ? гео.toNonIndexed() : гео);
    }
    /* Корпус: чуть сужается кверху, как у настоящей ступени. */
    влить(new T.CylinderGeometry(0.30, 0.34, 1.70, 28, 1, true), [0, 0.15, 0]);
    /* Носовой конус. */
    влить(new T.ConeGeometry(0.30, 0.78, 28, 1, true), [0, 1.39, 0]);
    /* Юбка сопла. */
    влить(new T.CylinderGeometry(0.34, 0.21, 0.30, 24, 1, true), [0, -0.85, 0]);
    /* Четыре киля, развёрнутые крестом. */
    for (var k = 0; k < 4; k++) {
      var г = new T.BoxGeometry(0.03, 0.46, 0.34);
      влить(г, [Math.cos(k * Math.PI / 2) * 0.40, -0.55, Math.sin(k * Math.PI / 2) * 0.40],
            [0, -k * Math.PI / 2, 0]);
    }
    /* Сплав: три числа на вершину, всё подряд. */
    var всего = 0, i;
    for (i = 0; i < части.length; i++) всего += части[i].attributes.position.count;
    var поз = new Float32Array(всего * 3);
    var о = 0;
    for (i = 0; i < части.length; i++) {
      поз.set(части[i].attributes.position.array, о);
      о += части[i].attributes.position.count * 3;
      части[i].dispose();
    }
    return поз;
  }

  /* Снятие точек с поверхности по площади треугольников. Вместе с местом
     запоминается НОРМАЛЬ треугольника: у igloo её роль играет градиент
     объёмной текстуры, и без неё затенение частицы посчитать нечем. */
  function снять(поз, сколько, семя) {
    var треуг = Math.floor(поз.length / 9);
    var площ = new Float64Array(треуг);
    var нормТр = new Float32Array(треуг * 3);
    var сум = 0, i;
    for (i = 0; i < треуг; i++) {
      var a = i * 9;
      var ax = поз[a], ay = поз[a + 1], az = поз[a + 2];
      var bx = поз[a + 3], by = поз[a + 4], bz = поз[a + 5];
      var cx = поз[a + 6], cy = поз[a + 7], cz = поз[a + 8];
      var ux = bx - ax, uy = by - ay, uz = bz - az;
      var vx = cx - ax, vy = cy - ay, vz = cz - az;
      var nx = uy * vz - uz * vy, ny = uz * vx - ux * vz, nz = ux * vy - uy * vx;
      var дл = Math.sqrt(nx * nx + ny * ny + nz * nz);
      сум += 0.5 * дл;
      площ[i] = сум;
      дл = дл || 1;
      нормТр[i * 3] = nx / дл; нормТр[i * 3 + 1] = ny / дл; нормТр[i * 3 + 2] = nz / дл;
    }
    var с = семя || 1;
    function сл() { с = (с * 1103515245 + 12345) % 2147483648; return с / 2147483648; }
    var дом = new Float32Array(сколько * 3);
    var нор = new Float32Array(сколько * 3);
    var шум = new Float32Array(сколько * 3);
    for (var p = 0; p < сколько; p++) {
      /* Треугольник выбирается двоичным поиском по накопленной площади:
         большая грань получает пропорционально больше точек. */
      var ц = сл() * сум, лев = 0, прав = треуг - 1;
      while (лев < прав) { var с2 = (лев + прав) >> 1; if (площ[с2] < ц) лев = с2 + 1; else прав = с2; }
      var b = лев * 9;
      /* Равномерная точка внутри треугольника: корень первой случайной
         снимает скос к одной вершине. */
      var r1 = Math.sqrt(сл()), r2 = сл();
      var w0 = 1 - r1, w1 = r1 * (1 - r2), w2 = r1 * r2;
      дом[p * 3] = поз[b] * w0 + поз[b + 3] * w1 + поз[b + 6] * w2;
      дом[p * 3 + 1] = поз[b + 1] * w0 + поз[b + 4] * w1 + поз[b + 7] * w2;
      дом[p * 3 + 2] = поз[b + 2] * w0 + поз[b + 5] * w1 + поз[b + 8] * w2;
      var нx = нормТр[лев * 3], нy = нормТр[лев * 3 + 1], нz = нормТр[лев * 3 + 2];
      нор[p * 3] = нx; нор[p * 3 + 1] = нy; нор[p * 3 + 2] = нz;
      /* ── РАКЕТА НАБИТА ЧАСТИЦАМИ, А НЕ ОКЛЕЕНА ИМИ ────────────
         Владелец: «ракета из частиц должна быть полностью заполнена
         частицами, как у igloo». До этого точка всегда садилась НА
         поверхность, и фигура была полой скорлупой: на просвет сквозь
         неё видно фон, силуэт рвётся по краю, а на повороте она
         мигает - передняя стенка и задняя стоят в одном пикселе.

         У igloo фигура берётся из ОБЪЁМНОЙ текстуры знакового
         расстояния, то есть точка может стоять где угодно внутри тела.
         Своей объёмной текстуры у нас нет, но внутрь от поверхности
         ведёт её же нормаль: часть точек уходит по минус нормали на
         случайную глубину, и тело набивается изнутри.

         Две трети внутрь, треть на коже. Кожа обязана остаться густой:
         силуэт и блик держит именно она, и полностью размазанный по
         объёму рой теряет форму ракеты. Глубина - четверть единицы,
         это радиус корпуса: глубже точке уходить некуда, она вышла бы
         с другой стороны.

         Нормаль при этом НЕ МЕНЯЕТСЯ. Внутренняя точка светится так
         же, как участок поверхности, из-под которого она ушла, - ровно
         это делает и градиент их объёмной текстуры внутри тела. */
      var вглубь = сл();
      if (вглубь < 0.66) {
        var шаг = (вглубь / 0.66) * 0.26;
        дом[p * 3] -= нx * шаг;
        дом[p * 3 + 1] -= нy * шаг;
        дом[p * 3 + 2] -= нz * шаг;
      }
      шум[p * 3] = сл(); шум[p * 3 + 1] = сл(); шум[p * 3 + 2] = сл();
    }
    return { дом: дом, норм: нор, шум: шум };
  }

  /* ── Шейдеры ──────────────────────────────────────────────────*/
  var В_РОЙ = [
    "attribute vec3 aHome;",
    "attribute vec3 aNorm;",
    "attribute vec3 aRnd;",
    "uniform float uTime;",
    "uniform float uScatter;",
    "uniform float uH;",
    "uniform float uSize;",
    "uniform float uScale;",
    "uniform vec3 uLightPos;",
    /* Отклик на касание: сила (гаснет сама), номер движения и фаза. */
    "uniform float uPush;",
    "uniform float uMode;",
    "uniform float uFaza;",
    /* ── ВСПЛЕСК ОТ ТОЧКИ КАСАНИЯ ────────────────────────────────
       У igloo движение частиц считает настоящая жидкость на видеокарте
       (пинг-понг FBO 388x388, две цели - положение и скорость), и
       касание там это SPLAT: местный толчок в точке пальца, радиусом
       0.22 и силой 35 в их единицах, который расходится и гаснет
       (densityDissipation 0.88, velocityDissipation 0.98). Числа
       сверены по их бандлу, свод - docs/РАЗБОР-IGLOO-КОД.md.

       Полного солвера у нас нет и он тут не нужен: главное в их отклике
       не жидкость сама по себе, а то, что толчок МЕСТНЫЙ - он идёт от
       точки, где человек тронул, а не двигает фигуру целиком. Это и
       повторяем: точка касания в местных координатах роя, радиус в её
       единицах и сила, которая гаснет вместе с фазой.

       uVsplesk.xyz - место касания, uVsplesk.w - радиус. */
    "uniform vec4 uVsplesk;",
    "varying float vShadow;",
    "varying float vVel;",
    /* Завихрение: три синуса по месту и времени. Их curl-шум четвёртого
       порядка стоит втрое дороже на точку, а отличается только рисунком
       вихря, которого на размере частицы всё равно не видно. */
    "vec3 vihr(vec3 p, float t){",
    "  return vec3(",
    "    sin(p.y * 3.1 + t * 0.7) + sin(p.z * 2.3 - t * 0.5),",
    "    sin(p.z * 2.7 - t * 0.6) + sin(p.x * 3.3 + t * 0.4),",
    "    sin(p.x * 2.9 + t * 0.5) + sin(p.y * 2.1 - t * 0.8));",
    "}",
    /* ── БАНК ОТКЛИКОВ НА КАСАНИЕ ────────────────────────────────
       Владелец: «когда мы свайпаем, кликаем, скроллим по ракете, у
       частиц анимация и свечение должно быть как у igloo, минимум
       пятьдесят разных движений по фигуре».

       Пятьдесят разных анимаций руками не пишут и не должны: у igloo
       это тоже не пятьдесят кусков кода, а ОДНО поле смещения с
       параметрами. Здесь так же. Двенадцать базовых полей - волна,
       кручение, разлёт, стяжка, дыхание, разрез, спираль, дрожь,
       круги от точки касания, тягучка, тор, кручение с волной -
       умножаются на выбор рабочей оси (три) и на знак (два). Семьдесят
       две различимые глазом отклика, и каждый из них честно СВОЙ: ось
       меняет плоскость движения, знак разворачивает его наизнанку.

       Номер приходит целым числом снаружи, разбирается здесь. Ничего
       случайного внутри шейдера нет: тот же номер даёт то же движение,
       и отклик воспроизводим. */
    "vec3 osiRot(vec3 v, float os){",
    /* Перестановка координат вместо матрицы поворота: то же самое для
       поля смещения и втрое дешевле. */
    "  if (os < 0.5) return v;",
    "  if (os < 1.5) return v.yzx;",
    "  return v.zxy;",
    "}",
    "vec3 otklik(vec3 p, vec3 rnd, float t, float mode, float faza){",
    "  float baza = mod(mode, 12.0);",
    "  float os = mod(floor(mode / 12.0), 3.0);",
    "  float znak = mod(floor(mode / 36.0), 2.0) * 2.0 - 1.0;",
    "  vec3 q = osiRot(p, os);",
    "  vec3 d = vec3(0.0);",
    "  float r = length(q.xz) + 0.001;",
    "  vec3 naruzhu = vec3(q.x, 0.0, q.z) / r;",
    "  if (baza < 0.5) {",
    /* 0. Волна вдоль оси: бегущий поперечный горб. */
    "    d = vec3(0.0, 1.0, 0.0) * sin(q.y * 6.0 - faza * 9.0) * 0.55;",
    "    d += naruzhu * cos(q.y * 6.0 - faza * 9.0) * 0.35;",
    "  } else if (baza < 1.5) {",
    /* 1. Кручение: угол растёт с высотой. */
    "    float a = q.y * 1.6 * sin(faza * 3.14159);",
    "    d = vec3(q.x * cos(a) - q.z * sin(a) - q.x, 0.0, q.x * sin(a) + q.z * cos(a) - q.z);",
    "  } else if (baza < 2.5) {",
    /* 2. Разлёт наружу по нормали с возвратом. */
    "    d = normalize(q + 0.001) * sin(faza * 3.14159) * (0.35 + rnd.x * 0.85);",
    "  } else if (baza < 3.5) {",
    /* 3. Стяжка к оси: фигура на миг схлопывается в нить. */
    "    d = -naruzhu * r * sin(faza * 3.14159) * 0.75;",
    "  } else if (baza < 4.5) {",
    /* 4. Дыхание: равномерное расширение. */
    "    d = q * sin(faza * 6.28318) * 0.30;",
    "  } else if (baza < 5.5) {",
    /* 5. Разрез: половины расходятся и сходятся обратно. */
    "    d = vec3(sign(q.x) * sin(faza * 3.14159) * 0.55, 0.0, 0.0);",
    "  } else if (baza < 6.5) {",
    /* 6. Спираль: кручение вместе с подъёмом. */
    "    float a2 = (q.y + r) * 2.2 * sin(faza * 3.14159);",
    "    d = vec3(q.x * cos(a2) - q.z * sin(a2) - q.x, sin(faza * 3.14159) * 0.30,",
    "             q.x * sin(a2) + q.z * cos(a2) - q.z);",
    "  } else if (baza < 7.5) {",
    /* 7. Дрожь: мелкий шум, гаснущий к концу. */
    "    d = (vihr(q * 9.0 + rnd * 6.28, t * 3.0)) * sin(faza * 3.14159) * 0.22;",
    "  } else if (baza < 8.5) {",
    /* 8. Круги от касания: сферическая волна из точки. */
    "    float dl = length(q);",
    "    d = normalize(q + 0.001) * sin(dl * 7.0 - faza * 12.0) * sin(faza * 3.14159) * 0.45;",
    "  } else if (baza < 9.5) {",
    /* 9. Тягучка: тянется по оси, сужаясь поперёк. */
    "    float k = sin(faza * 3.14159);",
    "    d = vec3(-q.x * k * 0.35, q.y * k * 0.75, -q.z * k * 0.35);",
    "  } else if (baza < 10.5) {",
    /* 10. Тор: точки уходят на кольцо и возвращаются. */
    "    float koltso = 0.85;",
    "    d = naruzhu * (koltso - r) * sin(faza * 3.14159) * 0.80;",
    "  } else {",
    /* 11. Кручение с волной: два поля сразу. */
    "    float a3 = q.y * 1.3 * sin(faza * 3.14159);",
    "    d = vec3(q.x * cos(a3) - q.z * sin(a3) - q.x,",
    "             sin(q.y * 5.0 - faza * 8.0) * 0.35,",
    "             q.x * sin(a3) + q.z * cos(a3) - q.z);",
    "  }",
    "  return osiRot(d * znak, mod(3.0 - os, 3.0));",
    "}",
    "void main(){",
    "  vec3 p = aHome;",
    /* Покойное дыхание роя: точка всегда чуть гуляет вокруг дома, иначе
       рой читается пыльной моделью, а не живым облаком. */
    "  vec3 w = vihr(aHome * 1.7 + aRnd * 6.28, uTime);",
    "  p += w * 0.006;",
    /* Разлёт: та же сила, но множителем наружу и с разбросом по точке. */
    "  p += w * uScatter * mix(0.10, 0.55, aRnd.x);",
    "  p += normalize(aHome + 0.001) * uScatter * mix(0.05, 0.40, aRnd.z);",
    /* Отклик на касание поверх покоя. Разброс по точке (0.72..1.28)
       не даёт фигуре ходить единым куском: у igloo движение по рою
       всегда идёт волной, а не сдвигом всей статуи. */
    "  vec3 otk = otklik(aHome, aRnd, uTime, uMode, uFaza);",
    "  p += otk * uPush * mix(0.72, 1.28, aRnd.y);",
    /* Всплеск поверх общего движения: чем ближе точка к месту касания,
       тем сильнее её выносит наружу от него. Спад по гауссиане - у
       жидкости splat так и устроен. Волна догоняет: множитель фазы
       сдвинут, поэтому дальние точки трогаются позже ближних. */
    "  vec3 ot = aHome - uVsplesk.xyz;",
    "  float dl = length(ot);",
    "  float bliz = exp(-(dl * dl) / max(0.0001, uVsplesk.w * uVsplesk.w));",
    "  float hod = clamp(uFaza * 2.2 - dl / max(0.001, uVsplesk.w) * 0.35, 0.0, 1.0);",
    "  float sila = sin(hod * 3.14159) * bliz * uPush;",
    "  p += normalize(ot + 0.0001) * sila * uVsplesk.w * 1.9;",
    "  vec4 mv = modelViewMatrix * vec4(p, 1.0);",
    /* ЗАТЕНЕНИЕ ТОЧКИ - их обёрнутый диффуз по нормали поверхности.
       У них нормаль приходит градиентом объёмной текстуры, у нас лежит
       атрибутом: считается одно и то же. wrap 0.25 разводит свет за
       терминатор, отскок в десятую долю не даёт теневой стороне упасть
       в чёрное. */
    "  vec3 L = normalize(uLightPos);",
    "  float dp = dot(L, normalize(aNorm));",
    "  float wrap = 0.25;",
    "  float wrapDiffuse = max(0.0, (dp + wrap) / (1.0 + wrap));",
    "  wrapDiffuse += max(0.0, -dp) * 0.1;",
    "  vShadow = wrapDiffuse;",
    /* Скорость точки. У них она приходит из решателя и красит быстрые
       частицы в светлый. Разлёт это и есть быстрое движение, поэтому
       скорость берём из него и из размаха завихрения - в тех же
       единицах, в которых их шейдер её потом растягивает. */
    /* Скорость точки красит её в светлый: у них быстрая частица уходит
       в #d7ebfa. Отклик на касание это самое быстрое движение роя, и
       именно из него получается вспышка по фигуре, которую владелец
       называет свечением. */
    "  vVel = 0.0016 + length(w) * 0.0004 + uScatter * 0.006 + length(otk) * uPush * 0.010 + sila * 0.020;",
    /* Их формула размера. Множитель масштаба нужен потому, что фигура у
       нас крупнее их в несколько раз и камера стоит во столько же раз
       дальше: без него точки схлопнулись бы в субпиксель. */
    "  gl_PointSize = clamp(uSize * uScale / max(0.35, -mv.z) * (uH / 1300.0), 1.0, 14.0);",
    "  gl_Position = projectionMatrix * mv;",
    "}"
  ].join("\n");

  /* Фрагментный шейдер - их, слово в слово. */
  var Ф_РОЙ = [
    "uniform vec3 uColorLight;",
    "uniform vec3 uColorDark;",
    "uniform vec3 uColorInitial;",
    "uniform vec3 uColorFast;",
    "uniform vec3 uLightPos;",
    "uniform float uVisible;",
    "uniform float uAlpha;",
    "uniform float uInitialGlow;",
    "varying float vShadow;",
    "varying float vVel;",
    "float fitl(float x, float a1, float a2, float b1, float b2){",
    "  float v = b1 + ((x - a1) * (b2 - b1)) / (a2 - a1);",
    "  return clamp(v, min(b1, b2), max(b1, b2));",
    "}",
    "void main(){",
    "  float alpha = step(length(gl_PointCoord.xy - 0.5), 0.5) * uVisible;",
    "  if (alpha < 0.001) discard;",
    /* Нормаль полушария: точка это шарик, а не плоский кружок. */
    "  vec2 uv = 2.0 * gl_PointCoord.xy - 1.0;",
    "  vec3 n = vec3(uv, sqrt(1.0 - clamp(dot(uv, uv), 0.0, 1.0)));",
    "  n.y = 1.0 - n.y;",
    /* Их источник повёрнут на пол-оборота вокруг Y. */
    "  vec3 L = normalize(vec3(-uLightPos.x, uLightPos.y, -uLightPos.z));",
    "  float lightShadow = max(0.0, dot(L, normalize(n)));",
    "  float ramp = lightShadow * vShadow;",
    "  vec3 color = mix(uColorDark, uColorLight, ramp);",
    "  color = mix(color, uColorFast, pow(fitl(vVel, 0.003, 0.005, 0.0, 1.0), 2.0));",
    /* Их «бедняцкое смазывание»: быстрая точка бледнее. */
    "  alpha *= max(uInitialGlow, pow(fitl(vVel, 0.002, 0.007, 1.0, 0.0), 2.0) * 0.5 + 0.5);",
    /* Их приём проявления: спрятанное состояние это alpha 0, свечение 1
       и белый цвет; сначала едет прозрачность, цвет подтягивается за ней. */
    "  vec3 fadeInColor = mix(vec3(1.0), uColorInitial, clamp(uAlpha, 0.0, 1.0));",
    "  color = mix(color, fadeInColor, uInitialGlow);",
    "  gl_FragColor = vec4(clamp(color, 0.0, 1.0), alpha * uAlpha);",
    "}"
  ].join("\n");

  /* ── Сборка ───────────────────────────────────────────────────*/
  var М = {};
  var собрано = false;

  function собрать(мир, гнездо, опц) {
    if (собрано) return М.рой;
    W = мир; T = W.T;
    опц = опц || {};
    var ст = W.ступень;
    /* У них полтораста тысяч. Точка стоит дёшево, дорога только её
       заливка, а здесь точка мелкая; на полной ступени берём их число
       целиком - без него рой рвётся на просвет и статуи не выходит. */
    var сколько = ст === 0 ? 22000 : (ст === 1 ? 65000 : 150000);

    var поз = ракетаГео();
    var снято = снять(поз, сколько, 2024);

    var гео = new T.BufferGeometry();
    /* position нужен движку для отсечения по объёму; настоящее место
       точки считает шейдер из aHome. */
    гео.setAttribute("position", new T.BufferAttribute(снято.дом.slice(), 3));
    гео.setAttribute("aHome", new T.BufferAttribute(снято.дом, 3));
    гео.setAttribute("aNorm", new T.BufferAttribute(снято.норм, 3));
    гео.setAttribute("aRnd", new T.BufferAttribute(снято.шум, 3));

    М.uTime = { value: 0 };
    М.uScatter = { value: 0 };
    М.uVisible = { value: 1 };
    М.uAlpha = { value: 1 };
    М.uInitialGlow = { value: 0 };
    М.uScale = { value: опц["масштаб"] != null ? опц["масштаб"] : 1 };
    М.uPush = { value: 0 };
    М.uMode = { value: 0 };
    М.uFaza = { value: 0 };
    /* Место касания в местных координатах роя и радиус всплеска.
       Радиус 0.22 их единицы при фигуре высотой 1.44 - это шестая часть
       роста. У нашей ракеты рост около 3.2 местных единиц, значит та же
       доля даёт примерно 0.5. */
    М.uVsplesk = { value: new T.Vector4(0, 0, 0, 0.5) };
    М.мат = new T.ShaderMaterial({
      uniforms: {
        uTime: М.uTime, uScatter: М.uScatter,
        uH: { value: 900 },
        uSize: { value: опц["размер"] != null ? опц["размер"] : 10.0 },
        uScale: М.uScale,
        uVisible: М.uVisible, uAlpha: М.uAlpha, uInitialGlow: М.uInitialGlow,
        uPush: М.uPush, uMode: М.uMode, uFaza: М.uFaza, uVsplesk: М.uVsplesk,
        uLightPos: { value: new T.Vector3(-0.75, 1, -0.1) },
        uColorLight: { value: new T.Color(0xbdc6d4) },
        uColorDark: { value: new T.Color(0x222b42) },
        uColorFast: { value: new T.Color(0xd7ebfa) },
        uColorInitial: { value: new T.Color(0xb5d5ff) }
      },
      vertexShader: В_РОЙ, fragmentShader: Ф_РОЙ,
      transparent: true,
      /* ИХ СМЕШИВАНИЕ, А НЕ СЛОЖЕНИЕ. Приёмник умножается на ЦВЕТ
         источника: тёмная частица гасит фон под собой, светлая пропускает
         его. Сложение, стоявшее здесь раньше, умело только подсвечивать,
         и рой светился насквозь вместо того, чтобы стоять телом. */
      blending: T.CustomBlending,
      blendEquation: T.AddEquation,
      blendSrc: T.SrcAlphaFactor,
      blendDst: T.SrcColorFactor,
      depthTest: true, depthWrite: true, fog: false
    });
    М.рой = new T.Points(гео, М.мат);
    М.рой.name = "ракета-рой";
    М.рой.frustumCulled = false;
    М.рой.renderOrder = 6;
    (гнездо || W.scene).add(М.рой);
    собрано = true;
    return М.рой;
  }

  /* ── ОТКЛИК ЖИВЁТ СВОИМ ВРЕМЕНЕМ, А НЕ ЛЕНТОЙ ─────────────────
     Касание это событие, а не место на прокрутке: человек может ткнуть
     фигуру и не крутить вовсе. Поэтому у отклика свои часы. Фаза идёт
     от нуля до единицы за ОТКЛИК_СЕК и на этом кончается; сила гаснет
     вместе с ней по синусу, поэтому движение начинается с нуля,
     доходит до предела и возвращает точку домой ровно туда, откуда
     взяло. Ни одной накопленной величины: два касания подряд не
     складываются в уползающую фигуру. */
  var ОТКЛИК_СЕК = 1.15;
  /* Семьдесят два различимых отклика: двенадцать полей, три оси, два
     знака. Номер идёт по кругу, а не жребием: подряд идущие касания
     обязаны давать РАЗНОЕ, а случайный выбор из семидесяти двух
     повторяется чаще, чем кажется. */
  var ОТКЛИКОВ = 72;
  var _откл = { начало: -1, номер: 0 };
  /* Часы отклика идут по НАСТОЯЩЕМУ времени, а не по сумме шагов кадра.
     Сумма шагов с потолком в десятую долю секунды (обычная защита от
     скачка после переключения вкладки) на слабой машине растягивает
     секунду отклика в шесть: замер на песочнице без видеокарты показал
     силу отклика 1.0 там, где она давно обязана быть нулём. У человека
     со слабым телефоном вышло бы то же самое - движение, которое не
     кончается. */
  function сейчасСек() {
    return (g.performance && g.performance.now ? g.performance.now() : 0) / 1000;
  }

  var _мировая = null;
  function толкнуть(номер, точкаМира) {
    if (!собрано) return 0;
    var н = номер == null ? (_откл.номер + 1) % ОТКЛИКОВ : (номер | 0) % ОТКЛИКОВ;
    _откл.номер = н;
    _откл.начало = сейчасСек();
    М.uMode.value = н;
    М.uFaza.value = 0;
    М.uPush.value = 0;
    /* ── ГДЕ ИМЕННО ТРОНУЛИ ──────────────────────────────────────
       У igloo всплеск идёт от точки пальца, а не от середины фигуры.
       Точка приходит в мировых координатах, шейдер считает в местных -
       переводим её узлом роя. Не сказали где - берём середину: отклик
       тогда расходится из центра, и это честно означает «тронули
       вообще, а не в конкретном месте». */
    if (точкаМира && М.рой) {
      if (!_мировая) _мировая = new T.Vector3();
      _мировая.copy(точкаМира);
      М.рой.updateMatrixWorld();
      М.рой.worldToLocal(_мировая);
      М.uVsplesk.value.set(_мировая.x, _мировая.y, _мировая.z, М.uVsplesk.value.w);
    } else {
      М.uVsplesk.value.set(0, 0, 0, М.uVsplesk.value.w);
    }
    return н;
  }

  /* ── КУДА ПОПАЛ ПАЛЕЦ ─────────────────────────────────────────
     Рой это точки, по ним лучом не попасть: у отдельной точки нет
     площади, и raycast по Points требует порога, который на нашем
     размере даёт то попадание, то промах. Берём проще и надёжнее:
     плоскость, проходящую через середину роя перпендикулярно взгляду.
     Луч из-под пальца пересекает её всегда, а по фигуре это ровно то
     место, куда человек смотрел, когда тыкал. */
  var _луч = null, _плос = null, _точкаМира = null, _норм = null;
  function точкаКасания(x, y) {
    if (!собрано || !М.рой || !W || !W.cam) return null;
    if (!_луч) {
      _луч = new T.Raycaster();
      _плос = new T.Plane();
      _точкаМира = new T.Vector3();
      _норм = new T.Vector3();
    }
    var ш = g.innerWidth || 1, в = g.innerHeight || 1;
    _луч.setFromCamera({ x: (x / ш) * 2 - 1, y: -(y / в) * 2 + 1 }, W.cam);
    М.рой.updateMatrixWorld();
    var серед = new T.Vector3().setFromMatrixPosition(М.рой.matrixWorld);
    W.cam.getWorldDirection(_норм);
    _плос.setFromNormalAndCoplanarPoint(_норм, серед);
    return _луч.ray.intersectPlane(_плос, _точкаМира) ? _точкаМира : серед;
  }

  function кадр(dt, часы) {
    if (!собрано) return;
    М.uTime.value = часы;
    if (_откл.начало >= 0) {
      var ф = (сейчасСек() - _откл.начало) / ОТКЛИК_СЕК;
      if (ф >= 1) { _откл.начало = -1; М.uPush.value = 0; М.uFaza.value = 0; }
      else {
        М.uFaza.value = ф;
        /* Сила по синусу фазы: ноль на входе, ноль на выходе. */
        М.uPush.value = Math.sin(ф * Math.PI);
      }
    }
    if (W.r && W.r.getDrawingBufferSize) {
      if (!М._р) М._р = new T.Vector2();
      W.r.getDrawingBufferSize(М._р);
      М.мат.uniforms.uH.value = М._р.y || 900;
    }
  }

  function разлёт(v) { if (М.uScatter) М.uScatter.value = v; }

  /* Проявление по их ленте: сначала прозрачность за две с половиной
     секунды, потом свечение уходит за одну. */
  function проявить(альфа, свечение) {
    if (!собрано) return;
    М.uAlpha.value = альфа == null ? 1 : Math.max(0, Math.min(1, альфа));
    М.uInitialGlow.value = свечение == null ? 0 : Math.max(0, Math.min(1, свечение));
    М.uVisible.value = М.uAlpha.value > 0.002 ? 1 : 0;
  }

  /* Масштаб фигуры в мире: нужен формуле размера точки. Ставит его тот,
     кто ставит саму фигуру, иначе точки схлопываются в субпиксель. */
  function масштаб(k) { if (М.uScale) М.uScale.value = k > 0 ? k : 1; }

  /* ── КАСАНИЕ, СВАЙП И ПРОКРУТКА ПО ФИГУРЕ ─────────────────────
     Владелец: «когда мы свайпаем, кликаем, скроллим по ракете, у
     частиц анимация и свечение должно быть».

     Слушаем здесь, а не в акте: фигура одна на весь сайт, и по ней
     ходят три акта подряд. Акту пришлось бы повторять подписку трижды
     и трижды же её снимать.

     Отклик даётся, только когда рой ВИДЕН и уже проявлен: тычок по
     первому экрану не должен копить движение в фигуре, которой на
     экране нет. Прокрутка идёт с придержкой в треть секунды - иначе
     одно движение колеса выдаёт двадцать откликов подряд и рой
     трясётся вместо того, чтобы отвечать.

     Звук берёт тот же обработчик: у igloo отклик фигуры всегда со
     звуком, и владелец просил его отдельно. */
  var _прошлыйЗвук = 0;
  function виденРой() {
    if (!собрано || !М.рой) return false;
    if (!М.рой.visible) return false;
    if (М.uAlpha && М.uAlpha.value < 0.2) return false;
    /* Родитель мог погасить всю ветку. */
    var у = М.рой.parent;
    while (у) { if (!у.visible) return false; у = у.parent; }
    return true;
  }
  var _последнееКасание = { x: -1, y: -1 };
  function откликнуться(мягкий) {
    if (!виденРой()) return;
    var т = null;
    if (_последнееКасание.x >= 0) {
      try { т = точкаКасания(_последнееКасание.x, _последнееКасание.y); } catch (eТ) { т = null; }
    }
    толкнуть(null, т);
    var сейчас = (g.performance && g.performance.now ? g.performance.now() : 0) / 1000;
    if (сейчас - _прошлыйЗвук > 0.45) {
      _прошлыйЗвук = сейчас;
      try {
        g.dispatchEvent(new CustomEvent("rv:рой", {
          detail: { "что": "отклик", "номер": _откл.номер, "мягкий": !!мягкий }
        }));
      } catch (eС) {}
    }
  }
  var _когдаКрутил = 0;
  function поПрокрутке() {
    var т = (g.performance && g.performance.now ? g.performance.now() : 0);
    if (т - _когдаКрутил < 330) return;
    _когдаКрутил = т;
    откликнуться(true);
  }
  g.addEventListener("pointerdown", function (е) {
    _последнееКасание.x = е.clientX; _последнееКасание.y = е.clientY;
    откликнуться(false);
  }, { passive: true });
  /* Мышь без нажатия тоже запоминается: прокрутка колесом идёт под
     курсором, и всплеск обязан пойти оттуда, а не из середины. */
  g.addEventListener("pointermove", function (е) {
    if (е.pointerType === "touch") return;
    _последнееКасание.x = е.clientX; _последнееКасание.y = е.clientY;
  }, { passive: true });
  g.addEventListener("wheel", поПрокрутке, { passive: true });
  g.addEventListener("touchmove", поПрокрутке, { passive: true });
  g.addEventListener("scroll", поПрокрутке, { passive: true });

  g.RV_ЧАСТИЦЫ = {
    "собрать": собрать,
    "кадр": кадр,
    "разлёт": разлёт,
    "проявить": проявить,
    "масштаб": масштаб,
    "толкнуть": толкнуть,
    "откликов": function () { return ОТКЛИКОВ; },
    /* Радиус всплеска наружу: его ставит тот, кто знает размер фигуры
       в мире. Доля от роста берётся у igloo - шестая часть. */
    "радиусВсплеска": function (r) { if (М.uVsplesk && r > 0) М.uVsplesk.value.w = r; },
    "узел": function () { return М.рой || null; },
    "замер": function () {
      return {
        "собрано": собрано,
        "точек": М.рой ? М.рой.geometry.attributes.position.count : 0,
        "разлёт": М.uScatter ? +М.uScatter.value.toFixed(3) : 0,
        "альфа": М.uAlpha ? +М.uAlpha.value.toFixed(3) : 0,
        "свечение": М.uInitialGlow ? +М.uInitialGlow.value.toFixed(3) : 0,
        "масштаб": М.uScale ? +М.uScale.value.toFixed(2) : 1,
        "откликов": ОТКЛИКОВ,
        "отклик": _откл.номер,
        "сила": М.uPush ? +М.uPush.value.toFixed(3) : 0
      };
    }
  };
})(window, document);
