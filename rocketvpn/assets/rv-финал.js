/* Rocket VPN. Финал: вход в ракету и панель управления.

   ЗАЧЕМ. Владелец описал конец сценария дословно: «мы приближаемся в
   сторону ракеты, открываются двери, мы заходим внутрь (оборот на 360
   как на сайте CDN мы делать не будем, мы просто заходим внутрь и
   подходим к панели управления, на которой будет анкета, часто
   задаваемые вопросы, кнопка запустить VPN и кнопка запустить игру,
   такая же как на сайте CDN)».

   ОТКУДА ЧИСЛА. Всё, что касается корабля, взято у родственного проекта
   Rocket CDN и НЕ подобрано на глаз:

     rc-cabin.js    R_WALL 3.05 радиус обшивки, H_ROOM 4.2 высота зала,
                    EYE 1.62 высота глаз над настилом, восемь секторов
                    по сорок пять градусов, экран на стене 1.52 x 1.34.
     rc-panel.js    проём остекления WIN_Y0 0.17, WIN_Y1 3.06,
                    WIN_HALF 0.43 радиана, камера в 0.86 от стекла.
     rc-rocket.js   люк DOOR_Y 0.10, DOOR_H 1.34, DOOR_HALF 0.62
                    радиана (полураствор, не метры), запас на кромку
                    проёма 1.07, чтобы створка и вырез не совпадали
                    ровно и стык не показывал щель.
     rc-airlock.js  порядок входа: щель светится, замки расцепляются
                    коротким рывком внутрь, створки уходят по обшивке в
                    стороны, и последним кадр прикрывает труба люка -
                    подмены за ней не видно.
     rc-rocket.js   палитра RC_SHIP_STYLE, единственный источник правды
                    по цвету корабля. Скопирована ниже один в один.

   ЧТО ИЗ ЭТОГО ИЗМЕНЕНО И ПОЧЕМУ. Размер люка. У CDN он 1.34 высотой, а
   в ширину полураствор 0.62 радиана на корпусе радиусом 0.64 даёт всего
   0.74 метра. Это люк на борту ракеты, мимо которого летит камера, и
   человек в него не проходит вовсе. У нас в него ВХОДИТ человек, поэтому
   высота 2.10 и ширина 1.94: проём человеческий, с запасом на плечи. От
   CDN здесь взят только принцип (проём вырезан в самой обшивке, створки
   ходят по ней и уходят за кромку), числа проёма наши.

   ОБОРОТА НЕТ. У CDN человек входит и обходит салон кругом. Владелец
   этот круг отменил, поэтому весь финал идёт по ОДНОЙ ПРЯМОЙ: люк, зал
   и пульт стоят на одной оси, вход смотрит на +Z, окно и пульт на -Z.
   Мир ведёт камеру одной позой (см. «поза» ниже): точка взгляда у
   пульта, а подход отодвигает камеру назад по той же прямой примерно на
   двадцать единиц - и она оказывается снаружи, перед люком. Точное
   число считается каждый раз от СТАРТ_Z и глубины глаза у пульта.
   Ни одного поворота на всей дороге.

   АНКЕТУ И ИГРУ ЭТОТ ФАЙЛ НЕ ПИШЕТ. Они уже есть: rv-анкета.js и
   rv-игра.js, разметка в frame.html по именам rvАнкета и rvИгра. Здесь
   только сцена и МЕСТО, куда они встают: каждый кадр модуль считает,
   где на экране стоят экран анкеты, экран частых вопросов и ряд
   клавиш, и публикует эти прямоугольники переменными оформления.
   Разметка садится в них и едет вместе с кадром, а не висит поверх.

   ШЕЙДЕРОВ ЗДЕСЬ НЕТ НИ ОДНОГО НАМЕРЕННО. Кириллица в GLSL молча не
   собирается, и материал пропадает без единой строчки в консоли; на
   финале сайта такая потеря стоит дороже всего. Всё держится на
   обычных материалах слоя и холстах, и терять здесь нечему.

   API:
     RV_ФИНАЛ.собрать(мир, родитель) -> Group | null
     RV_ФИНАЛ.кадр(доля, dt, часы)     доля 0 подходим, 1 у пульта
     RV_ФИНАЛ.видно(да)
     RV_ФИНАЛ.замер() */
(function (g, d) {
  "use strict";

  var W = null, T = null;
  var М = {};
  var собрано = false;
  var видноСейчас = false;
  var доляСейчас = 0;
  var дальНужна = true;
  var снаружиНужно = true;

  var TAU = Math.PI * 2;

  /* ── Палитра корабля ──────────────────────────────────────────
     Один в один RC_SHIP_STYLE из rocketcdn/assets/rc-rocket.js. Своих
     цветов у корабля быть не может: это тот же корабль, и разойтись им
     негде. Если палитра там поменяется, менять и здесь. */
  var Ц = {
    глубь: 0x02060a,
    корпус: 0x101923,
    стена: 0x182633,
    пульт: 0x060d14,
    сталь: 0x566675,
    циан: 0x5fc8ef,
    цианМягкий: 0x9fe0f6,
    фиолет: 0xa974f5,
    тёплый: 0xffa85c
  };

  /* ── Размеры корабля ──────────────────────────────────────────
     Метры. Разбор каждого числа - в шапке файла. */
  var R_СТЕНА = 3.05;          /* обшивка изнутри (rc-cabin R_WALL) */
  var R_БОРТ = 3.45;           /* обшивка снаружи: сорок сантиметров железа */
  var H_ЗАЛ = 4.2;             /* высота зала (rc-cabin H_ROOM) */
  var ГЛАЗ = 1.62;             /* глаз над настилом (rc-cabin EYE) */

  var ОКНО_ПОЛ = 0.43;         /* полураствор остекления, радианы */
  var ОКНО_НИЗ = 0.17;
  var ОКНО_ВЕРХ = 3.06;

  var ЛЮК_НИЗ = 0.17;          /* порог вровень с низом остекления */
  var ЛЮК_ВЕРХ = 2.27;         /* высота проёма 2.10 */
  var ЛЮК_ПШ = 0.97;           /* полуширина проёма: 2.10 * 0.925 / 2 */
  /* Полураствор проёма считается по КАЖДОМУ радиусу отдельно: одна и та
     же ширина в метрах на большем радиусе занимает меньший угол. Иначе
     проём в наружной обшивке оказался бы шире внутреннего, и в кадре
     появилась бы ступенька. */
  var ЛЮК_УГ_В = Math.asin(ЛЮК_ПШ / R_СТЕНА);
  var ЛЮК_УГ_Н = Math.asin(ЛЮК_ПШ / R_БОРТ);
  /* Створка шире выреза в обшивке в 1.07 раза. Запас тот же, что у CDN
     (rc-rocket, cut = DOOR_HALF * 1.07), развёрнут в другую сторону: у
     них створки утоплены в проём и вырез шире их, у нас створки ходят
     ПО обшивке снаружи и перекрывают её кромку сами. Смысл один: створка
     и вырез не совпадают ровно, иначе по стыку видно щель. */
  var СТВ_УГ = ЛЮК_УГ_Н * 1.07;
  var ПРИТВОР = 0.028;         /* нахлёст створок в закрытом положении */
  var РАСПАХ = СТВ_УГ * 2 + 0.12;   /* на сколько каждая створка уезжает */

  /* ── Пульт ────────────────────────────────────────────────────
     Стоит в приборной нише под остеклением - ровно там, где он стоит у
     CDN («приборная ниша под окном и корпус кабины в проёме»).

     Ширина 1.86, а не два с половиной. Первый заход мерился живьём:
     при 2.40 и глазе в трёх метрах прямоугольник анкеты вылезал за
     край кадра на восемьдесят семь процентов ширины, то есть форму
     было некуда поставить. Метр восемьдесят шесть влезает и в лежачий
     кадр, и в стоячий - см. полеУПульта ниже. */
  var П_Z = -2.55;             /* середина тумбы по глубине */
  var П_Ш = 1.86;              /* ширина пульта */
  var ЭКР_Z = -2.86;           /* стойка экранов у самой стены */
  var ЭКР_Y = 1.62;
  var ПОЛКА_Y = 1.02, ПОЛКА_Z = -2.42, ПОЛКА_НАКЛОН = -0.38;
  var ЭКР_ПЛОСКОСТЬ = -2.80;   /* где стоят экраны по оси корабля */
  var ПУЛЬТ_КАДР = 2.10;       /* сколько метров пульта обязано влезть в кадр */

  /* Где стоит глаз в конце и куда он смотрит. Отсюда собирается поза
     акта, и отсюда же считается кадр: два разных набора чисел на одну
     дорогу рано или поздно разъезжаются. Глубина глаза считается по
     кадру (местоУПульта), здесь стоит её значение для монитора. */
  var ГЛАЗ_ПУЛЬТ = [0, 1.66, ЭКР_ПЛОСКОСТЬ + 2.4];
  /* Прицел стоит на середине щита, а не ниже: замер на мониторе показал
     верхний край панели за краем кадра на 1.3 процента. Смотрим в
     панель, а не под неё. */
  var ПРИЦЕЛ_ПУЛЬТ = [0, ЭКР_Y, -2.90];
  /* Откуда начинается акт: одиннадцать с половиной по оси корабля, то
     есть в восьми метрах от борта. Ракета видна целиком, люк по
     середине кадра. Отход камеры считается от этой точки, а не задан
     числом: глубина глаза у пульта меняется по кадру, и постоянный
     отход уводил бы начало акта то ближе, то дальше. */
  /* Двадцать, а не одиннадцать. На одиннадцати живой снимок показал не
     ракету, а стену обшивки во весь кадр: корабль 28 метров ростом, и с
     восьми метров в кадр влезает один пояс борта. Владелец просил
     «приближаемся в сторону ракеты», значит в первом кадре она обязана
     быть ракетой. */
  /* ── ДВАДЦАТИ МАЛО: КОРАБЛЬ ОБЯЗАН ВЛЕЗТЬ В КАДР ЦЕЛИКОМ ─────
     Владелец прислал первый кадр их финала: ракета стоит на площадке
     ЦЕЛИКОМ, занимая меньше половины высоты кадра, вокруг звёзды.
     Наш первый кадр показывал вместо этого пояс обшивки со швом люка
     во весь экран - снимок доли 0.05 это поймал прямо.

     Считаем, а не подбираем. Корабль двадцать восемь единиц ростом,
     поле зрения на подходе сорок шесть градусов. Чтобы он занял сорок
     пять процентов высоты, видимая высота кадра обязана быть вдвое с
     небольшим больше него:

       даль = рост * 2.21 / (2 * tan(46/2)) ... то есть 2.6 роста

     Отсюда 28.2 * 2.6 = 74. */
  var СТАРТ_Z = 74;
  var УХОД = -0.35;

  /* ── Ракета снаружи ───────────────────────────────────────────
     Зал сидит внутри настоящего корпуса, а не в бочке. Пропорции взяты
     у нашей же ракеты из rv-частицы.js (ракетаГео): корпус 0.30 на
     0.34 радиусом и 1.70 длиной, конус 0.78, юбка сопла 0.30, четыре
     киля крестом. Рой частиц снят с этой самой формы, и корабль, в
     который человек входит, обязан быть тем же, каким он летел
     облаком точек.

     Пересчёт один: радиус корпуса модели 0.34 равен нашему борту 3.45,
     отсюда множитель 10.15. Всё остальное умножено на него. */
  var МАСШТАБ = R_БОРТ / 0.34;
  /* Корпус модели идёт по y от -0.70 до 1.00 (цилиндр 1.70 длиной с
     серединой на 0.15). Зал с люком и пультом сидит внутри этого
     отрезка, в семи метрах над срезом сопла. */
  var КОРПУС_НИЗ = -0.70 * МАСШТАБ;
  var КОРПУС_ВЕРХ = 1.00 * МАСШТАБ;

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }
  function плавно(t) { t = зажать(t, 0, 1); return t * t * (3 - 2 * t); }
  function отрезок(д, a, b) { return плавно((д - a) / (b - a)); }

  /* Точка на азимуте. Запись та же, что у CDN (rc-cabin, at): азимут
     ноль смотрит на +Z, и это направление входа. */
  function точка(th, r, y) { return [r * Math.sin(th), y, r * Math.cos(th)]; }

  /* ── Где встать у пульта ───────────────────────────────────────
     Ни одно постоянное расстояние здесь не годится, и это замерено, а
     не предположено. Живой снимок телефона 412x915 при глазе в трёх
     метрах: щит пульта занял 114 процентов ширины кадра, то есть
     анкету было некуда поставить, она вылезала за оба края. На
     мониторе тот же глаз давал 71 процент - там всё в порядке.

     У CDN эта беда решена двумя наборами чисел (WIN_TALL и WIN_WIDE в
     rc-cockpit), и такие наборы живут ровно до первого планшета.
     Поэтому считаем.

     Раздвигать поле зрения нельзя: чтобы влезть на телефон, ему нужно
     под восемьдесят градусов, а на таком поле прямые гнутся по углам и
     панель выглядит снятой рыбьим глазом. Значит меняем не объектив, а
     МЕСТО: на узком экране человек стоит от пульта дальше. Так это и
     работает в жизни.

     Числа: поле сорок на лежачем кадре и пятьдесят восемь на стоячем,
     расстояние подбирается под ширину ПУЛЬТ_КАДР. Пределы 2.4 и 5.4 -
     ближе камера упирается в тумбу, дальше выходит за обшивку зала
     (радиус 3.05 плюс сам пульт). */
  function местоУПульта() {
    var ш = g.innerWidth || 1280, в = g.innerHeight || 800;
    var отн = в > 0 ? ш / в : 1.6;
    var поле = отн >= 1 ? 40 : 58;
    var L = ПУЛЬТ_КАДР / (2 * Math.tan(поле * Math.PI / 360) * отн);
    return { "поле": поле, "даль": зажать(L, 2.4, 5.4) };
  }

  /* Сколько граней на дугу. Считается от доли окружности, а не задаётся
     числом: пояс в четверть круга с шестьюдесятью гранями стоит столько
     же, сколько полный круг, и не выглядит лучше. */
  function граней(длина) {
    var ст = W && W.ступень != null ? W.ступень : 2;
    var всего = ст === 0 ? 26 : (ст === 1 ? 44 : 72);
    return Math.max(5, Math.round(всего * Math.abs(длина) / TAU));
  }

  /* ── Холсты ───────────────────────────────────────────────────
     Всё, что светится (экраны, надписи клавиш, щель между створками),
     нарисовано на холсте. Шейдер тут не нужен, а нужен он был бы только
     для того, чтобы вернуть себе право потерять материал молча. */
  function холст(ш, в, рисовать) {
    var c = d.createElement("canvas");
    c.width = ш; c.height = в;
    var к = c.getContext("2d");
    рисовать(к, ш, в);
    var т = new T.CanvasTexture(c);
    т.colorSpace = T.SRGBColorSpace || т.colorSpace;
    т.anisotropy = 4;
    return т;
  }

  function цветСтрокой(hex, альфа) {
    var r = (hex >> 16) & 255, gп = (hex >> 8) & 255, b = hex & 255;
    return "rgba(" + r + "," + gп + "," + b + "," + альфа + ")";
  }

  /* Экран приборной панели. СЛОВ НА ХОЛСТЕ НЕТ.

     Первый заход писал сюда заголовок и подпись, и на снимке пульта
     каждое слово стояло дважды: рамка разметки садится ровно на этот
     экран (см. рамка("анк") и рамка("впр") ниже - те же x, y, ширина и
     высота), поэтому «ОСТАЛСЯ ВОПРОС» с холста и «Остался вопрос» из
     h3 накладывались буква на букву и не читались ни то, ни другое.

     Холст держит прибор: заливку, сетку стекла, кромку и две полоски
     показателей. Слова держит разметка - она одна, её можно выделить,
     прочитать голосом и найти поиском. */
  function экранХолст() {
    return холст(512, 320, function (к, ш, в) {
      var зал = к.createLinearGradient(0, 0, 0, в);
      зал.addColorStop(0, цветСтрокой(0x0b1826, 1));
      зал.addColorStop(1, цветСтрокой(Ц.пульт, 1));
      к.fillStyle = зал;
      к.fillRect(0, 0, ш, в);
      /* Сетка приборного стекла: без неё чёрный прямоугольник читается
         дырой в панели, а не выключенным экраном. */
      к.strokeStyle = цветСтрокой(Ц.циан, 0.10);
      к.lineWidth = 1;
      var i;
      for (i = 32; i < ш; i += 32) {
        к.beginPath(); к.moveTo(i, 0); к.lineTo(i, в); к.stroke();
      }
      for (i = 32; i < в; i += 32) {
        к.beginPath(); к.moveTo(0, i); к.lineTo(ш, i); к.stroke();
      }
      к.strokeStyle = цветСтрокой(Ц.циан, 0.55);
      к.lineWidth = 4;
      к.strokeRect(10, 10, ш - 20, в - 20);
      /* Полоска-подложка под заголовок разметки. Тёмная строка под
         светлыми буквами h3 держит их читаемыми на любом свете зала:
         сам заголовок стоит разметкой, здесь под ним только место. */
      к.fillStyle = цветСтрокой(0x081320, 0.55);
      к.fillRect(24, 26, ш - 48, 46);
      /* Две служебные полоски внизу: приборная панель без бегущих
         показателей выглядит макетом. */
      к.fillStyle = цветСтрокой(Ц.циан, 0.35);
      к.fillRect(34, в - 62, (ш - 68) * 0.62, 6);
      к.fillStyle = цветСтрокой(Ц.фиолет, 0.35);
      к.fillRect(34, в - 44, (ш - 68) * 0.38, 6);
    });
  }

  /* Настенное табло салона. Здесь слово ОСТАЁТСЯ: разметка на стену не
     садится, накрывать нечего, а голая плита в четырёх местах по кругу
     читалась бы забытой заготовкой. Слово одно и служебное, с текстом
     пульта оно не спорит. */
  function таблоХолст(строка) {
    return холст(512, 320, function (к, ш, в) {
      var зал = к.createLinearGradient(0, 0, 0, в);
      зал.addColorStop(0, цветСтрокой(0x0b1826, 1));
      зал.addColorStop(1, цветСтрокой(Ц.пульт, 1));
      к.fillStyle = зал;
      к.fillRect(0, 0, ш, в);
      к.strokeStyle = цветСтрокой(Ц.циан, 0.45);
      к.lineWidth = 4;
      к.strokeRect(10, 10, ш - 20, в - 20);
      к.fillStyle = цветСтрокой(Ц.цианМягкий, 0.80);
      к.font = "600 44px Montserrat, system-ui, sans-serif";
      к.textBaseline = "top";
      к.fillText(строка, 34, 36);
      к.fillStyle = цветСтрокой(Ц.циан, 0.30);
      к.fillRect(34, в - 62, (ш - 68) * 0.62, 6);
      к.fillStyle = цветСтрокой(Ц.фиолет, 0.30);
      к.fillRect(34, в - 44, (ш - 68) * 0.38, 6);
    });
  }

  /* Плита клавиши. Слова на ней тоже НЕ пишем по той же причине, что и
     на экранах: рамка("кн") накрывает обе клавиши, и ссылки разметки
     «Запустить VPN» и «Запустить игру» встают ровно на них. Холст даёт
     клавише корпус - тёмное поле, светящуюся кромку и подсветку своего
     цвета, - а нажимает человек по ссылке, которая и уводит в бота. */
  function клавишаХолст(цвет) {
    return холст(512, 160, function (к, ш, в) {
      к.fillStyle = цветСтрокой(0x0a121c, 1);
      к.fillRect(0, 0, ш, в);
      к.strokeStyle = цветСтрокой(цвет, 0.75);
      к.lineWidth = 6;
      к.strokeRect(8, 8, ш - 16, в - 16);
      к.fillStyle = цветСтрокой(цвет, 0.16);
      к.fillRect(8, 8, ш - 16, в - 16);
      /* Блик по верхней трети: ровная заливка читается наклейкой, а
         клавиша обязана читаться выпуклой. */
      var блик = к.createLinearGradient(0, 8, 0, в * 0.62);
      блик.addColorStop(0, цветСтрокой(0xffffff, 0.12));
      блик.addColorStop(1, цветСтрокой(0xffffff, 0));
      к.fillStyle = блик;
      к.fillRect(8, 8, ш - 16, в * 0.62);
    });
  }

  /* Полоса свечения: яркая середина, мягкие края. Ею светится щель
     между створками и проём люка изнутри. */
  function полосаХолст(цвет) {
    return холст(64, 256, function (к, ш, в) {
      var гр = к.createLinearGradient(0, 0, ш, 0);
      гр.addColorStop(0, цветСтрокой(цвет, 0));
      гр.addColorStop(0.42, цветСтрокой(цвет, 0.55));
      гр.addColorStop(0.5, цветСтрокой(цвет, 1));
      гр.addColorStop(0.58, цветСтрокой(цвет, 0.55));
      гр.addColorStop(1, цветСтрокой(цвет, 0));
      к.fillStyle = гр;
      к.fillRect(0, 0, ш, в);
      /* Концы гасим: иначе полоса упирается в кромку прямым срезом. */
      var верт = к.createLinearGradient(0, 0, 0, в);
      верт.addColorStop(0, "rgba(0,0,0,1)");
      верт.addColorStop(0.14, "rgba(0,0,0,0)");
      верт.addColorStop(0.86, "rgba(0,0,0,0)");
      верт.addColorStop(1, "rgba(0,0,0,1)");
      к.globalCompositeOperation = "destination-out";
      к.fillStyle = верт;
      к.fillRect(0, 0, ш, в);
    });
  }

  /* Пятно света. Им горит проём изнутри и стекло остекления. */
  function пятноХолст(цвет) {
    return холст(256, 256, function (к, ш, в) {
      var гр = к.createRadialGradient(ш / 2, в * 0.52, 0, ш / 2, в * 0.52, ш / 2);
      гр.addColorStop(0, цветСтрокой(цвет, 0.95));
      гр.addColorStop(0.45, цветСтрокой(цвет, 0.34));
      гр.addColorStop(1, цветСтрокой(цвет, 0));
      к.fillStyle = гр;
      к.fillRect(0, 0, ш, в);
    });
  }

  /* Даль за остеклением. Не звёздное поле мира, а именно ДАЛЬ: без неё
     в окне стоит чёрный прямоугольник, и кадр читается вырезанным. */
  function дальХолст() {
    return холст(512, 512, function (к, ш, в) {
      /* Даль тёмная намеренно. Первый заход был светлее на две
         ступени, и на живом снимке окно читалось не космосом, а
         подсвеченным матовым стеклом: звёзд на нём не видно вовсе.
         Небо обязано быть темнее любой стены зала, иначе оно
         перестаёт быть далью. */
      var гр = к.createLinearGradient(0, 0, 0, в);
      гр.addColorStop(0, цветСтрокой(Ц.глубь, 1));
      гр.addColorStop(0.58, цветСтрокой(0x050c18, 1));
      гр.addColorStop(1, цветСтрокой(0x0a1830, 1));
      к.fillStyle = гр;
      к.fillRect(0, 0, ш, в);
      var сияние = к.createRadialGradient(ш * 0.68, в * 0.78, 0, ш * 0.68, в * 0.78, ш * 0.62);
      сияние.addColorStop(0, цветСтрокой(Ц.циан, 0.18));
      сияние.addColorStop(1, цветСтрокой(Ц.циан, 0));
      к.fillStyle = сияние;
      к.fillRect(0, 0, ш, в);
      /* Звёзды: детерминированный разброс, чтобы кадр не менялся между
         перезагрузками и снимки проверки сходились. */
      var семя = 20260905;
      function сл() { семя = (семя * 1103515245 + 12345) % 2147483648; return семя / 2147483648; }
      /* Звёзды мелкие и частые. Первый заход рисовал их крупными
         кружками, и в окне получалось не небо, а горох: настоящее
         звёздное поле читается плотностью, а не размером точки. */
      for (var i = 0; i < 900; i++) {
        var x = сл() * ш, y = сл() * в, r = сл() * сл() * 1.3 + 0.35;
        к.fillStyle = "rgba(232,242,255," + (0.30 + сл() * 0.70).toFixed(2) + ")";
        к.beginPath(); к.arc(x, y, r, 0, TAU); к.fill();
      }

      /* ── ПЛАНЕТА ЗА СТЕКЛОМ ──────────────────────────────────
         Владелец прислал пятый и шестой кадры их финала: в окне рубки
         стоит Земля, занимая половину проёма. Голое звёздное поле там
         было первым заходом и читалось дырой в борту - у неба без
         предмета нет ни масштаба, ни глубины.

         Рисунок повторяет их (rc-interior, planetTex): материки
         пятнами, а не точками (точки читаются шумом, глазу нужен
         контур), полярные шапки, облачные завихрения и огни ночных
         городов вдоль побережий. Проекция другая - у них развёртка на
         шар, у нас диск на плоской дали, - поэтому всё считается от
         середины диска. */
      var пx = ш * 0.62, пy = в * 0.60, пR = ш * 0.30;
      var шар = к.createRadialGradient(пx - пR * 0.35, пy - пR * 0.40, пR * 0.06,
                                       пx, пy, пR);
      шар.addColorStop(0, "#1a6ea8");
      шар.addColorStop(0.42, "#0a4a80");
      шар.addColorStop(0.76, "#08223c");
      шар.addColorStop(1, "#040c18");
      к.save();
      к.beginPath(); к.arc(пx, пy, пR, 0, TAU); к.clip();
      к.fillStyle = шар;
      к.fillRect(пx - пR, пy - пR, пR * 2, пR * 2);

      /* Материки. Форма собирается синусами по углу: ровный овал
         читается кляксой, а не сушей. */
      function суша(cx, cy, rx, ry, пов, цвет) {
        к.save();
        к.translate(cx, cy); к.rotate(пов);
        к.beginPath();
        var n = 22;
        for (var k2 = 0; k2 <= n; k2++) {
          var a = k2 / n * TAU;
          var w = 0.66 + 0.34 * (Math.sin(a * 3 + cx) * 0.5 + Math.sin(a * 5 + cy) * 0.5 + 1) / 2;
          var px = Math.cos(a) * rx * w, py = Math.sin(a) * ry * w;
          if (!k2) к.moveTo(px, py); else к.lineTo(px, py);
        }
        к.closePath();
        к.fillStyle = цвет;
        к.fill();
        к.restore();
      }
      var мат = [
        [-0.42, -0.18, 0.24, 0.30, 0.3], [-0.10, 0.30, 0.17, 0.26, -0.4],
        [0.16, -0.34, 0.30, 0.26, 0.2], [0.34, 0.22, 0.19, 0.28, 0.7],
        [0.60, -0.10, 0.22, 0.30, -0.2]
      ];
      for (var м2 = 0; м2 < мат.length; м2++) {
        var сx = пx + мат[м2][0] * пR, сy = пy + мат[м2][1] * пR;
        суша(сx, сy, мат[м2][2] * пR, мат[м2][3] * пR, мат[м2][4], "#123f4a");
        суша(сx, сy, мат[м2][2] * пR * 0.82, мат[м2][3] * пR * 0.8, мат[м2][4], "#1a5a52");
      }
      /* Облачные завихрения: мягкие светлые дуги поверх суши. */
      к.globalAlpha = 0.16;
      к.fillStyle = "#dceaf6";
      for (var о2 = 0; о2 < 70; о2++) {
        var оx = пx + (сл() * 2 - 1) * пR, оy = пy + (сл() * 2 - 1) * пR;
        к.beginPath();
        к.ellipse(оx, оy, пR * (0.06 + сл() * 0.22), пR * (0.02 + сл() * 0.06),
                  сл() * 1.2 - 0.6, 0, TAU);
        к.fill();
      }
      к.globalAlpha = 1;
      /* Огни ночных городов вдоль побережий. */
      к.fillStyle = "rgba(255,214,160,.7)";
      for (var г2 = 0; г2 < 160; г2++) {
        к.fillRect(пx + (сл() * 2 - 1) * пR * 0.92,
                   пy + (сл() * 2 - 1) * пR * 0.92, 1.4, 1.4);
      }
      /* Тень: половина шара уходит в ночь, иначе он читается
         наклейкой, а не телом в свете далёкого солнца. */
      var ночь = к.createLinearGradient(пx - пR, пy - пR, пx + пR, пy + пR);
      ночь.addColorStop(0, "rgba(2,5,12,0)");
      ночь.addColorStop(0.52, "rgba(2,5,12,0.10)");
      ночь.addColorStop(1, "rgba(2,5,12,0.86)");
      к.fillStyle = ночь;
      к.fillRect(пx - пR, пy - пR, пR * 2, пR * 2);
      к.restore();
      /* Кромка атмосферы. */
      var атм = к.createRadialGradient(пx, пy, пR * 0.94, пx, пy, пR * 1.10);
      атм.addColorStop(0, "rgba(120,190,255,0.30)");
      атм.addColorStop(1, "rgba(120,190,255,0)");
      к.fillStyle = атм;
      к.beginPath(); к.arc(пx, пy, пR * 1.10, 0, TAU); к.fill();
    });
  }

  /* ── Оболочка с вырезами ──────────────────────────────────────
     Обшивка строится ПОЯСАМИ, а не одним телом вращения с накладками.
     Это прямой урок CDN: там люк сперва был накладкой на сплошном
     корпусе, и на открытии из-под створок показывалась целая обшивка.
     Пояс с вырезом честно не имеет там железа.

     Поясов четыре, границы задают проёмы:
       0 .. ЛЮК_НИЗ           полный круг
       ЛЮК_НИЗ .. ЛЮК_ВЕРХ    две дуги: вырезаны люк и окно
       ЛЮК_ВЕРХ .. ОКНО_ВЕРХ  одна дуга: вырезано окно
       ОКНО_ВЕРХ .. H_ЗАЛ     полный круг */
  function оболочка(r, угЛюка, мат, имя) {
    var гр = new T.Group();
    гр.name = имя;

    function пояс(y0, y1, thСтарт, thДлина) {
      var h = y1 - y0;
      if (h <= 0.001 || thДлина <= 0.001) return;
      var гео = new T.CylinderGeometry(r, r, h, граней(thДлина), 1, true, thСтарт, thДлина);
      var м = new T.Mesh(гео, мат);
      м.position.y = (y0 + y1) / 2;
      гр.add(м);
    }

    пояс(0, ЛЮК_НИЗ, 0, TAU);
    пояс(ЛЮК_НИЗ, ЛЮК_ВЕРХ, угЛюка, Math.PI - ОКНО_ПОЛ - угЛюка);
    пояс(ЛЮК_НИЗ, ЛЮК_ВЕРХ, Math.PI + ОКНО_ПОЛ, Math.PI - ОКНО_ПОЛ - угЛюка);
    пояс(ЛЮК_ВЕРХ, ОКНО_ВЕРХ, Math.PI + ОКНО_ПОЛ, TAU - ОКНО_ПОЛ * 2);
    пояс(ОКНО_ВЕРХ, H_ЗАЛ, 0, TAU);
    return гр;
  }

  /* ── Откосы проёма ────────────────────────────────────────────
     Между внутренней обшивкой (3.05) и наружной (3.45) сорок
     сантиметров пустоты. Если её не закрыть, в кромке проёма видно
     двойной срез, и корабль читается двумя жестянками, вставленными
     одна в другую.

     Горизонтальные откосы - кольцевые сектора: кольцо, положенное
     плашмя, закрывает зазор точно по форме. Угол кольца отсчитывается
     от +X против часовой, наш азимут от +Z, разница ровно четверть
     оборота - отсюда «- Math.PI / 2» ниже. */
  function откосГор(y, thСтарт, thДлина, мат) {
    var гео = new T.RingGeometry(R_СТЕНА, R_БОРТ, граней(thДлина), 1,
                                 thСтарт - Math.PI / 2, thДлина);
    var м = new T.Mesh(гео, мат);
    м.rotation.x = -Math.PI / 2;
    м.position.y = y;
    return м;
  }

  /* Вертикальный откос: плоскость поперёк проёма. Поворот на азимут
     минус четверть оборота ставит её шириной вдоль радиуса, а
     нормалью по касательной - то есть лицом в проём. */
  function откосВерт(th, y0, y1, мат) {
    var гео = new T.PlaneGeometry(R_БОРТ - R_СТЕНА, y1 - y0);
    var м = new T.Mesh(гео, мат);
    var т = точка(th, (R_СТЕНА + R_БОРТ) / 2, (y0 + y1) / 2);
    м.position.set(т[0], т[1], т[2]);
    м.rotation.y = th - Math.PI / 2;
    return м;
  }

  /* ── Корабль вокруг зала ──────────────────────────────────────
     Всё, что делает бочку ракетой: корпус выше и ниже палубы, носовой
     конус, юбка сопла и четыре киля. Форма и пропорции - те же, что у
     роя частиц (rv-частицы.js, ракетаГео), потому что это тот же
     корабль: человек весь сайт смотрел на него облаком точек и должен
     войти именно в него, а не в похожий.

     Узел отдельный: акт, который поднимет настоящую объёмную ракету
     соседним модулем, погасит его одним вызовом «снаружи(false)» и
     получит вход в ту ракету, без второго корпуса в кадре. */
  function корабльСнаружи(матКорпус) {
    var гр = new T.Group();
    гр.name = "корабль снаружи";
    var сег = граней(TAU);

    /* Ниже палубы и выше палубы. Пояса самой палубы уже построены
       оболочкой: там вырезы под люк и остекление. */
    var низ = new T.Mesh(
      new T.CylinderGeometry(R_БОРТ, R_БОРТ, -КОРПУС_НИЗ, сег, 1, true), матКорпус);
    низ.position.y = КОРПУС_НИЗ / 2;
    гр.add(низ);

    var верх = new T.Mesh(
      new T.CylinderGeometry(R_БОРТ, R_БОРТ, КОРПУС_ВЕРХ - H_ЗАЛ, сег, 1, true), матКорпус);
    верх.position.y = (КОРПУС_ВЕРХ + H_ЗАЛ) / 2;
    гр.add(верх);

    /* Носовой конус: 0.78 длины модели при радиусе 0.30. */
    var конусВ = 0.78 * МАСШТАБ;
    var конус = new T.Mesh(
      new T.ConeGeometry(R_БОРТ * 0.882, конусВ, сег, 1, true), матКорпус);
    конус.position.y = КОРПУС_ВЕРХ + конусВ / 2;
    гр.add(конус);

    /* Юбка сопла: 0.34 к 0.21 радиусом, 0.30 длиной. */
    var юбкаВ = 0.30 * МАСШТАБ;
    var юбка = new T.Mesh(
      new T.CylinderGeometry(R_БОРТ, R_БОРТ * 0.618, юбкаВ, сег, 1, true), матКорпус);
    юбка.position.y = КОРПУС_НИЗ - юбкаВ / 2;
    гр.add(юбка);

    /* Предупредительная разметка по ободу - тот же приём, что у CDN на
       корпусе (rc-rocket, «те же цвета, что на люке»). Два кольца
       холодного света выше и ниже люка. Они делают двойную работу:
       говорят, где у корабля вход, и не дают ему пропасть в кадре, пока
       карта окружения ещё не собралась. */
    var кольцоМат = new T.MeshBasicMaterial({
      color: Ц.циан, transparent: true, opacity: 0.42,
      side: T.DoubleSide, fog: false
    });
    var высоты = [ЛЮК_ВЕРХ + 0.55, ЛЮК_НИЗ - 0.55];
    for (var в = 0; в < высоты.length; в++) {
      var ободок = new T.Mesh(
        new T.CylinderGeometry(R_БОРТ + 0.02, R_БОРТ + 0.02, 0.07, сег, 1, true),
        кольцоМат);
      ободок.position.y = высоты[в];
      гр.add(ободок);
    }

    /* Четыре киля крестом. Их разворот повторяет rv-частицы дословно,
       иначе рой и корпус разойдутся на четверть оборота. */
    for (var k = 0; k < 4; k++) {
      var киль = new T.Mesh(
        new T.BoxGeometry(0.03 * МАСШТАБ, 0.46 * МАСШТАБ, 0.34 * МАСШТАБ), матКорпус);
      киль.position.set(Math.cos(k * Math.PI / 2) * 0.40 * МАСШТАБ,
                        -0.55 * МАСШТАБ,
                        Math.sin(k * Math.PI / 2) * 0.40 * МАСШТАБ);
      киль.rotation.y = -k * Math.PI / 2;
      гр.add(киль);
    }
    return гр;
  }

  /* ── Створки ──────────────────────────────────────────────────
     Две половины проёма на радиусе чуть больше борта: настоящий люк на
     цилиндре ходит ПО обшивке, а не утапливается в неё. */
  function створка(левая, мат) {
    var гнездо = new T.Group();
    var h = ЛЮК_ВЕРХ - ЛЮК_НИЗ + 0.12;
    var thСтарт = левая ? -СТВ_УГ : -ПРИТВОР;
    var thДлина = СТВ_УГ + ПРИТВОР;
    var гео = new T.CylinderGeometry(R_БОРТ + 0.035, R_БОРТ + 0.035, h,
                                     граней(thДлина), 1, true, thСтарт, thДлина);
    var м = new T.Mesh(гео, мат);
    м.position.y = (ЛЮК_НИЗ + ЛЮК_ВЕРХ) / 2;
    гнездо.add(м);

    /* Кромка притвора: узкая полоса светлее створки по линии стыка. Без
       неё две половины на общем радиусе читаются одним листом железа, и
       движение створок в первый момент не видно вовсе. */
    var кр = new T.Mesh(
      new T.PlaneGeometry(0.06, h * 0.94),
      new T.MeshBasicMaterial({ color: Ц.сталь, transparent: true, opacity: 0.5, fog: false })
    );
    var тк = точка(левая ? ПРИТВОР * 0.5 : -ПРИТВОР * 0.5, R_БОРТ + 0.08,
                   (ЛЮК_НИЗ + ЛЮК_ВЕРХ) / 2);
    кр.position.set(тк[0], тк[1], тк[2]);
    кр.rotation.y = левая ? ПРИТВОР * 0.5 : -ПРИТВОР * 0.5;
    гнездо.add(кр);

    /* Маркировка. У CDN на створках номер люка и марка проекта; берём то
       же самое своими словами. Плоскость лицом наружу, поэтому поворот
       равен азимуту (нормаль смотрит по радиусу). */
    var под = левая ? -СТВ_УГ * 0.5 : СТВ_УГ * 0.5;
    var тек = холст(256, 128, function (к, ш, в) {
      к.clearRect(0, 0, ш, в);
      к.fillStyle = цветСтрокой(Ц.цианМягкий, 0.62);
      к.font = "600 46px Montserrat, system-ui, sans-serif";
      к.textAlign = "center";
      к.textBaseline = "middle";
      к.fillText(левая ? "ROCKET" : "VPN-01", ш / 2, в / 2);
    });
    var зн = new T.Mesh(
      new T.PlaneGeometry(0.72, 0.36),
      new T.MeshBasicMaterial({ map: тек, transparent: true, depthWrite: false, fog: false })
    );
    var тз = точка(под, R_БОРТ + 0.10, 1.62);
    зн.position.set(тз[0], тз[1], тз[2]);
    зн.rotation.y = под;
    гнездо.add(зн);

    return гнездо;
  }

  /* ── Пульт ────────────────────────────────────────────────────
     Три тела: тумба, наклонная полка под клавиши и откинутая стойка с
     экранами. Разделение не украшение: полка и стойка стоят под разными
     углами, и разметка, которая на них садится, обязана ехать вместе с
     ними - поэтому у каждой свой узел, и точки привязки висят на нём. */
  function пульт(матКорпус) {
    var гр = new T.Group();
    гр.name = "пульт";

    var тумба = new T.Mesh(new T.BoxGeometry(П_Ш, 0.98, 0.62), матКорпус);
    тумба.position.set(0, 0.49, П_Z);
    гр.add(тумба);

    /* Светящаяся губа по низу тумбы. Тот же приём, что у CDN на кольцах
       и на кромке остекления: пола под пультом почти не видно, и без
       подсветки предмет висит в воздухе. */
    var губа = new T.Mesh(
      new T.PlaneGeometry(П_Ш * 0.96, 0.06),
      new T.MeshBasicMaterial({ color: Ц.циан, transparent: true, opacity: 0.5, fog: false })
    );
    губа.position.set(0, 0.09, П_Z + 0.315);
    гр.add(губа);

    /* Лицо тумбы. На стоячем кадре под щитом остаётся треть экрана, и
       на первом снимке телефона там стояла ровная тёмная плита - кадр
       выглядел недорисованным. Полоса света и шесть контрольных
       огоньков занимают это место тем, чем его занял бы настоящий
       пульт: показателями. */
    var лицо = new T.Mesh(
      new T.PlaneGeometry(П_Ш * 0.90, 0.05),
      new T.MeshBasicMaterial({ color: Ц.цианМягкий, transparent: true,
                                opacity: 0.34, fog: false })
    );
    лицо.position.set(0, 0.72, П_Z + 0.316);
    гр.add(лицо);

    var огоньМат = [
      new T.MeshBasicMaterial({ color: Ц.циан, transparent: true, opacity: 0.62, fog: false }),
      new T.MeshBasicMaterial({ color: Ц.фиолет, transparent: true, opacity: 0.52, fog: false }),
      new T.MeshBasicMaterial({ color: Ц.тёплый, transparent: true, opacity: 0.48, fog: false })
    ];
    for (var о = 0; о < 6; о++) {
      var огонёк = new T.Mesh(new T.PlaneGeometry(0.16, 0.045), огоньМат[о % 3]);
      огонёк.position.set(-П_Ш * 0.36 + о * (П_Ш * 0.145), 0.50, П_Z + 0.316);
      гр.add(огонёк);
    }

    /* Стойка экранов. Откинута на 0.12 радиана: панель, стоящая строго
       вертикально, бликует ровно в глаз и читается стеклом, а не
       прибором. */
    М.стойка = new T.Group();
    М.стойка.position.set(0, ЭКР_Y, ЭКР_Z);
    М.стойка.rotation.x = 0.12;
    гр.add(М.стойка);

    var щит = new T.Mesh(new T.BoxGeometry(П_Ш, 1.34, 0.10), матКорпус);
    М.стойка.add(щит);

    function экран(x, y, ш, в) {
      var м = new T.Mesh(
        new T.PlaneGeometry(ш, в),
        /* Прозрачность объявляется здесь, а не в кадре: смена признака
           у материала заставляет слой пересобрать программу, и делать
           это каждый кадр значит платить за неё шестьдесят раз в
           секунду ни за что. */
        new T.MeshBasicMaterial({ map: экранХолст(),
                                  transparent: true, fog: false })
      );
      м.position.set(x, y, 0.056);
      М.стойка.add(м);
      return м;
    }

    /* Левый экран шире: на нём три поля анкеты, правому хватает списка
       вопросов. Числа сняты с экрана CDN (1.52 x 1.34) и ужаты под нашу
       панель шириной 1.86. Оба подняты в верхнюю часть щита: под ними
       живут клавиши. */
    М.экрАнкета = экран(-0.36, 0.22, 1.06, 0.74);
    М.экрВопросы = экран(0.58, 0.22, 0.62, 0.74);

    /* ── Клавиши стоят на ЩИТЕ, а не на полке ────────────────────
       Первый заход клал их на наклонную полку, как на настоящем пульте,
       и живой замер это отменил: ряд клавиш, снятый почти с торца,
       занимал полтора процента высоты кадра. Разметке некуда сесть, а
       палец на телефоне в такую полосу не попадёт.

       Полка осталась полкой - столешницей пульта, - а клавиши переехали
       на щит под экраны, лицом к человеку. Так их видно, и разметка
       садится в честный прямоугольник. */
    М.полка = new T.Group();
    М.полка.position.set(0, ПОЛКА_Y, ПОЛКА_Z);
    М.полка.rotation.x = ПОЛКА_НАКЛОН;
    гр.add(М.полка);
    М.полка.add(new T.Mesh(new T.BoxGeometry(П_Ш, 0.09, 0.46), матКорпус));

    function клавиша(x, цвет) {
      var тело = new T.Mesh(new T.BoxGeometry(0.80, 0.24, 0.06), матКорпус);
      тело.position.set(x, -0.42, 0.06);
      М.стойка.add(тело);
      /* Лицо УЖЕ тела клавиши. Оно стоит на три сантиметра ближе к
         человеку, а значит проецируется крупнее: равные размеры дают в
         кадре рамку, вылезающую за клавишу. */
      var лицоКл = new T.Mesh(
        new T.PlaneGeometry(0.72, 0.20),
        new T.MeshBasicMaterial({ map: клавишаХолст(цвет), transparent: true, fog: false })
      );
      лицоКл.position.set(x, -0.42, 0.092);
      М.стойка.add(лицоКл);
      return лицоКл;
    }

    /* Обе клавиши те же, что у CDN на пульте: пуск и игра. Слова на них
       пишет разметка, цвет - холст: циан на пуске, фиолет на игре. */
    М.клВПН = клавиша(-0.45, Ц.циан);
    М.клИгра = клавиша(0.45, Ц.фиолет);

    return гр;
  }

  /* ── Точки привязки разметки ──────────────────────────────────
     Четыре пустых узла на каждый прямоугольник. Висят на том же узле,
     что и сам предмет, поэтому наклон полки и откид стойки достаются им
     даром: считать поворот руками значило бы повторять то, что граф
     сцены уже сделал, и разойтись с ним на первой же правке. */
  function рамка(имя, родитель, x, y, z, ш, в) {
    var углы = [], i;
    var пары = [[-1, -1], [1, -1], [1, 1], [-1, 1]];
    for (i = 0; i < 4; i++) {
      var у = new T.Object3D();
      у.position.set(x + пары[i][0] * ш / 2, y + пары[i][1] * в / 2, z);
      родитель.add(у);
      углы.push(у);
    }
    return { "имя": имя, "углы": углы, "лево": -1, "верх": -1, "ш": -1, "в": -1 };
  }

  /* ── Сборка ───────────────────────────────────────────────────*/
  function собрать(мир, родитель) {
    if (собрано) return М.корень;
    W = мир || W;
    if (!W || !W.T || !родитель) return null;
    T = W.T;
    var ст = W.ступень == null ? 2 : W.ступень;

    var корпусМат = (g.RV_REAL && g.RV_REAL["корпус"])
      /* Металличность 0.82, а не 0.92, и свечение теплее нуля. Металл
         узнают по отражениям, и пока карта окружения мира не доехала,
         корпус на 0.92 рисуется чёрной плитой - первый снимок подхода
         это и показал. Восемь десятых оставляют металл металлом и не
         дают кораблю пропасть в те секунды, пока карта собирается. */
      ? g.RV_REAL["корпус"](T, { "цвет": Ц.корпус, "металл": 0.82, "шерох": 0.34,
                                 "свет": 0x0d1626, "жар": 0.30 })
      : new T.MeshStandardMaterial({ color: Ц.корпус, metalness: 0.9, roughness: 0.3,
                                     side: T.DoubleSide });
    var стенаМат = (g.RV_REAL && g.RV_REAL["корпус"])
      ? g.RV_REAL["корпус"](T, { "цвет": Ц.стена, "металл": 0.52, "шерох": 0.54,
                                 "свет": 0x0d1a2a, "жар": 0.30 })
      : new T.MeshStandardMaterial({ color: Ц.стена, metalness: 0.5, roughness: 0.55,
                                     side: T.DoubleSide });
    var сталь = (g.RV_REAL && g.RV_REAL["корпус"])
      ? g.RV_REAL["корпус"](T, { "цвет": Ц.сталь, "металл": 0.88, "шерох": 0.36,
                                 "свет": 0x101c2c, "жар": 0.24 })
      : new T.MeshStandardMaterial({ color: Ц.сталь, metalness: 0.85, roughness: 0.36,
                                     side: T.DoubleSide });
    var пультМат = (g.RV_REAL && g.RV_REAL["корпус"])
      ? g.RV_REAL["корпус"](T, { "цвет": Ц.пульт, "металл": 0.70, "шерох": 0.42,
                                 "свет": 0x0a1526, "жар": 0.34 })
      : new T.MeshStandardMaterial({ color: Ц.пульт, metalness: 0.7, roughness: 0.42,
                                     side: T.DoubleSide });

    М.корень = new T.Group();
    М.корень.name = "финал: вход в ракету";

    /* ── Снаружи: корабль, борт с проёмом и створки ── */
    М.снаружи = new T.Group();
    М.снаружи.name = "снаружи";
    М.корень.add(М.снаружи);

    /* ── КОРАБЛЬ СНАРУЖИ БЕРЁМ У СОСЕДНЕГО САЙТА ─────────────────
       Владелец прислал восемь снимков финала Rocket CDN: «вот как на
       сайте rocketcdn.ru 1:1 должен быть финал (кроме разворота на
       360)». На первом снимке ракета стоит на круглой площадке с
       разметкой, бортиком в жёлто-чёрную полосу и огнями по ободу,
       обшивка в заклёпках и швах, три опоры с тарелками.

       Своего корабля тут больше нет. rv-корабль.js это их геометрия,
       перенесённая как есть, вместе с люком, створками и салоном за
       ними. Наш строился по их числам, но рисовался нашими руками, и
       разница была видна с первого снимка.

       Запасной путь остаётся: не доехал модуль - собираем прежний
       корпус. Пустой кадр хуже своего корабля. */
    М.чужой = null;
    if (g["RV_КОРАБЛЬ"] && g["RV_КОРАБЛЬ"]["собрать"]) {
      /* ── ЧУЖОЙ КОРАБЛЬ ЖИВЁТ В СВОИХ ЕДИНИЦАХ ──────────────────
         У соседей обшивка радиусом 0.65, у нас 3.45; проём у них
         посередине на 0.10, у нас между 0.17 и 2.27. Оба набора
         правильные, каждый в своём файле, и подгонять надо не числа, а
         УЗЕЛ: множитель считается из тех же величин, а не берётся с
         потолка, и переживёт правку любой из них.

         Ставим по РАДИУСУ ОБШИВКИ: салон, пульт и дорога камеры внутри
         построены от него, и разойдись обшивка с ними - человек вошёл
         бы в стену. Высоту проёма после этого сверяем и подвигаем узел
         так, чтобы середина их люка встала в середину нашего. */
      var гнездо = new T.Group();
      гнездо.name = "чужой корабль";
      М.снаружи.add(гнездо);
      М.чужой = g["RV_КОРАБЛЬ"]["собрать"](W, гнездо);
      if (М.чужой) {
        var мк = g["RV_КОРАБЛЬ"]["мерки"]();
        var кМ = R_БОРТ / мк["борт"];
        гнездо.scale.setScalar(кМ);
        гнездо.position.y = (ЛЮК_НИЗ + ЛЮК_ВЕРХ) / 2 - мк["люкY"] * кМ;
        М.гнездоЧужого = гнездо;
      } else {
        М.снаружи.remove(гнездо);
      }
    }
    if (!М.чужой) {
      М.снаружи.add(корабльСнаружи(корпусМат));
      М.борт = оболочка(R_БОРТ, ЛЮК_УГ_Н, корпусМат, "борт");
      М.снаружи.add(М.борт);

      М.створкаЛев = створка(true, корпусМат);
      М.створкаПрав = створка(false, корпусМат);
      М.снаружи.add(М.створкаЛев);
      М.снаружи.add(М.створкаПрав);
    }

    /* Щель между створками. Живёт снаружи, поэтому радиус больше
       створок: свет из щели бьёт НА обшивку, а не из-под неё. */
    М.щель = new T.Mesh(
      new T.PlaneGeometry(0.42, ЛЮК_ВЕРХ - ЛЮК_НИЗ),
      new T.MeshBasicMaterial({ map: полосаХолст(Ц.цианМягкий), transparent: true,
                                blending: T.AdditiveBlending, depthWrite: false,
                                opacity: 0, fog: false })
    );
    var тщ = точка(0, R_БОРТ + 0.12, (ЛЮК_НИЗ + ЛЮК_ВЕРХ) / 2);
    М.щель.position.set(тщ[0], тщ[1], тщ[2]);
    М.щель.renderOrder = 6;
    М.снаружи.add(М.щель);

    /* ── Труба люка ──────────────────────────────────────────────
       То самое, чем CDN прикрывает вход: «люк это труба в обшивке.
       Когда мы в неё входим, кадр по краям честно упирается в её
       стенки». У нас она настоящая геометрия, а не слой поверх кадра:
       камера проходит внутрь трубы, и края кадра темнеют сами. */
    М.труба = new T.Group();
    М.труба.name = "труба люка";
    М.труба.add(откосГор(ЛЮК_НИЗ, -ЛЮК_УГ_В, ЛЮК_УГ_В * 2, сталь));
    М.труба.add(откосГор(ЛЮК_ВЕРХ, -ЛЮК_УГ_В, ЛЮК_УГ_В * 2, сталь));
    М.труба.add(откосВерт(ЛЮК_УГ_В, ЛЮК_НИЗ, ЛЮК_ВЕРХ, сталь));
    М.труба.add(откосВерт(-ЛЮК_УГ_В, ЛЮК_НИЗ, ЛЮК_ВЕРХ, сталь));
    М.корень.add(М.труба);

    /* Свет в конце трубы: тёплое пятно на внутренней кромке проёма.
       Ради него туда и идут. */
    М.светПроёма = new T.Mesh(
      new T.PlaneGeometry(ЛЮК_ПШ * 2.2, (ЛЮК_ВЕРХ - ЛЮК_НИЗ) * 1.1),
      new T.MeshBasicMaterial({ map: пятноХолст(Ц.тёплый), transparent: true,
                                blending: T.AdditiveBlending, depthWrite: false,
                                opacity: 0, fog: false })
    );
    var тс = точка(0, R_СТЕНА - 0.04, (ЛЮК_НИЗ + ЛЮК_ВЕРХ) / 2);
    М.светПроёма.position.set(тс[0], тс[1], тс[2]);
    М.светПроёма.renderOrder = 5;
    М.корень.add(М.светПроёма);

    /* ── Салон ── */
    М.салон = new T.Group();
    М.салон.name = "салон";
    М.корень.add(М.салон);

    М.салон.add(оболочка(R_СТЕНА, ЛЮК_УГ_В, стенаМат, "обшивка изнутри"));

    /* Настил матовый, а не полированный. На первом снимке он был из
       того же материала, что пульт (металличность 0.70), и лампа зала
       расплавила на нём белое пятно во весь пол. Настил в корабле это
       противоскользящая палуба: почти не отражает и заметно шершавее
       всего остального. */
    var настилМат = (g.RV_REAL && g.RV_REAL["корпус"])
      ? g.RV_REAL["корпус"](T, { "цвет": 0x141d2a, "металл": 0.22, "шерох": 0.78,
                                 "свет": 0x080f1a, "жар": 0.18, "лак": 0 })
      : new T.MeshStandardMaterial({ color: 0x141d2a, metalness: 0.22, roughness: 0.78,
                                     side: T.DoubleSide });

    var настил = new T.Mesh(new T.CircleGeometry(R_СТЕНА, граней(TAU)), настилМат);
    настил.rotation.x = -Math.PI / 2;
    настил.position.y = 0.001;
    М.салон.add(настил);

    var потолок = new T.Mesh(new T.CircleGeometry(R_СТЕНА, граней(TAU)), пультМат);
    потолок.rotation.x = Math.PI / 2;
    потолок.position.y = H_ЗАЛ - 0.001;
    М.салон.add(потолок);

    /* Балки потолка. Стоячий кадр телефона показал верх зала ровным
       светлым пятном: круг под лампой без единой детали читается не
       потолком, а засветкой. Восемь рёбер дают ему размер и
       направление. Отделка, поэтому нищая ступень без них. */
    if (ст >= 1) {
      for (var бi = 0; бi < 8; бi++) {
        var балка = new T.Mesh(new T.BoxGeometry(0.11, 0.13, R_СТЕНА * 0.94), сталь);
        var уг = бi * TAU / 8;
        балка.position.set(Math.sin(уг) * R_СТЕНА * 0.47, H_ЗАЛ - 0.08,
                           Math.cos(уг) * R_СТЕНА * 0.47);
        балка.rotation.y = уг;
        М.салон.add(балка);
      }
    }

    /* Кольца настила. У igloo дно комнаты ступенчатое, и по той же
       причине: гладкий круг не даёт глазу масштаба. Ступень 0 обходится
       без них - это отделка, а не смысл. */
    if (ст >= 1) {
      var кольцоМат = new T.MeshBasicMaterial({ color: Ц.циан, transparent: true,
                                                opacity: 0.16, fog: false });
      for (var кi = 1; кi <= 3; кi++) {
        var рв = R_СТЕНА * (кi / 3.4);
        var кольцо = new T.Mesh(new T.RingGeometry(рв - 0.02, рв, граней(TAU)), кольцоМат);
        кольцо.rotation.x = -Math.PI / 2;
        кольцо.position.y = 0.004;
        М.салон.add(кольцо);
      }
    }

    /* Откосы остекления: тот же зазор в сорок сантиметров, что и у
       люка, и закрывается он тем же способом. */
    М.салон.add(откосГор(ОКНО_НИЗ, Math.PI - ОКНО_ПОЛ, ОКНО_ПОЛ * 2, сталь));
    М.салон.add(откосГор(ОКНО_ВЕРХ, Math.PI - ОКНО_ПОЛ, ОКНО_ПОЛ * 2, сталь));
    М.салон.add(откосВерт(Math.PI - ОКНО_ПОЛ, ОКНО_НИЗ, ОКНО_ВЕРХ, сталь));
    М.салон.add(откосВерт(Math.PI + ОКНО_ПОЛ, ОКНО_НИЗ, ОКНО_ВЕРХ, сталь));

    /* Даль за остеклением. Отдельным узлом: акт, который поставит финал
       посреди живого мира, погасит её одним вызовом и получит в окне
       настоящий космос. */
    /* Размер и место дали посчитаны так, чтобы её было видно ТОЛЬКО
       сквозь окно. Первый заход ставил полотно 26 на 18 в четырнадцати
       метрах, и снимок подхода показал звёзды по обе стороны корабля:
       полотно шире ракеты, и снаружи оно торчало из-за неё.

       Девять на восемь в восьми с половиной метрах: угловой размер
       дали (0.27) меньше углового размера борта (0.41) с точки, откуда
       начинается акт, значит снаружи корабль закрывает её целиком. А
       изнутри конус взгляда через окно на этом расстоянии шириной семь
       метров, и полотна хватает с запасом. */
    М.даль = new T.Mesh(
      new T.PlaneGeometry(9, 8),
      new T.MeshBasicMaterial({ map: дальХолст(), fog: false, depthWrite: false })
    );
    М.даль.position.set(0, 1.9, -8.5);
    М.даль.renderOrder = -1;
    М.салон.add(М.даль);

    /* Блик стекла. Слабый, аддитивный: остекление без блика читается
       дырой в обшивке, а сильный блик закрывает даль. */
    var блик = new T.Mesh(
      new T.CylinderGeometry(R_СТЕНА - 0.06, R_СТЕНА - 0.06, ОКНО_ВЕРХ - ОКНО_НИЗ,
                             граней(ОКНО_ПОЛ * 2), 1, true,
                             Math.PI - ОКНО_ПОЛ, ОКНО_ПОЛ * 2),
      new T.MeshBasicMaterial({ color: Ц.цианМягкий, transparent: true, opacity: 0.055,
                                side: T.DoubleSide, depthWrite: false,
                                blending: T.AdditiveBlending, fog: false })
    );
    блик.position.y = (ОКНО_НИЗ + ОКНО_ВЕРХ) / 2;
    М.салон.add(блик);

    /* Световая полоса по стене на высоте плеча. Свет в салоне важнее
       любой отделки: владелец отдельно жаловался, что телефон темнее
       ПК, и гасить его по ступени нельзя. Полоса стоит на всех
       ступенях, дробится только число кусков. */
    var полосМат = new T.MeshBasicMaterial({ color: Ц.цианМягкий, transparent: true,
                                             opacity: 0.42, side: T.DoubleSide, fog: false });
    var кусков = ст === 0 ? 2 : 4;
    for (var пi = 0; пi < кусков; пi++) {
      var шаг = (TAU - ОКНО_ПОЛ * 2 - ЛЮК_УГ_В * 2) / кусков;
      var н = ЛЮК_УГ_В + пi * шаг + 0.06;
      var пм = new T.Mesh(
        new T.CylinderGeometry(R_СТЕНА - 0.03, R_СТЕНА - 0.03, 0.05,
                               граней(шаг - 0.12), 1, true, н, шаг - 0.12),
        полосМат
      );
      пм.position.y = 2.62;
      М.салон.add(пм);
    }

    /* Настенные экраны CDN (1.52 x 1.34) у нас не нужны: разделы текста
       живут в разметке и стоят на пульте. Вместо них по стене идут
       служебные табло - они держат стену занятой и не спорят с
       содержимым. Ступень 0 обходится без них. */
    if (ст >= 1) {
      var таблоМат = new T.MeshBasicMaterial({
        map: таблоХолст("БОРТ"), transparent: true, fog: false,
        opacity: 0.7, side: T.DoubleSide
      });
      var места = [1.15, -1.15, 2.05, -2.05];
      for (var тi = 0; тi < места.length; тi++) {
        var т2 = new T.Mesh(new T.PlaneGeometry(0.86, 0.54), таблоМат);
        var тт = точка(места[тi], R_СТЕНА - 0.04, 1.72);
        т2.position.set(тт[0], тт[1], тт[2]);
        т2.rotation.y = места[тi] + Math.PI;
        М.салон.add(т2);
      }
    }

    М.пульт = пульт(пультМат);
    М.салон.add(М.пульт);

    /* ── Свет салона ──────────────────────────────────────────────
       Первый заход ставил тёплую лампу в 3.4 с затуханием 1.6, и живой
       снимок показал ровно то, чего делать нельзя: белое выжженное
       пятно на настиле под пультом и провал в тень по кругу. Затухание
       поднято до двадцати метров, а показатель спада убран почти в
       единицу - свет расходится по залу, а не садится лужей под
       лампой.

       Небесная составляющая нужна отдельно: точечные источники дают
       форму, но не дают воздуха, и теневая сторона предметов уходит в
       чёрное. Владелец на это жаловался прямо, поэтому она не зависит
       ни от ступени качества, ни от доли. */
    М.лампаТёплая = new T.PointLight(0xFFD8B4, 1.9, 26, 1.0);
    М.лампаТёплая.position.set(0, 3.70, 0.60);
    М.салон.add(М.лампаТёплая);

    М.лампаПульта = new T.PointLight(Ц.цианМягкий, 1.7, 11, 1.35);
    М.лампаПульта.position.set(0, 1.95, -1.75);
    М.салон.add(М.лампаПульта);

    М.небоЗала = new T.HemisphereLight(0x9FBEDD, 0x2C3550, 0.95);
    М.салон.add(М.небоЗала);

    /* ── Прямоугольники под разметку ──────────────────────────────
       Четвёртый, «окно», обводит весь щит пульта целиком. Он нужен
       узкому экрану: там анкета и вопросы уже не встают рядом, и
       вёрстка складывает их столбиком внутри одного окна вместо двух
       отдельных мест. Считать это в разметке нечем - оба прямоугольника
       она получает готовыми. */
    М.рамки = [
      рамка("анк", М.стойка, -0.36, 0.22, 0.10, 1.06, 0.74),
      рамка("впр", М.стойка, 0.58, 0.22, 0.10, 0.62, 0.74),
      рамка("окно", М.стойка, 0, 0, 0.10, П_Ш - 0.10, 1.24),
      рамка("кн", М.стойка, 0, -0.42, 0.10, 1.70, 0.26)
    ];

    /* Узлы позы. Держим их узлами сцены, а не тройками чисел: акт
       спрашивает мировые координаты, а группа финала может стоять где
       угодно и как угодно повёрнутой. */
    М.глазТ = new T.Object3D();
    М.глазТ.position.set(ГЛАЗ_ПУЛЬТ[0], ГЛАЗ_ПУЛЬТ[1], ГЛАЗ_ПУЛЬТ[2]);
    М.корень.add(М.глазТ);
    М.прицелТ = new T.Object3D();
    М.прицелТ.position.set(ПРИЦЕЛ_ПУЛЬТ[0], ПРИЦЕЛ_ПУЛЬТ[1], ПРИЦЕЛ_ПУЛЬТ[2]);
    М.корень.add(М.прицелТ);

    М.в3 = new T.Vector3();

    родитель.add(М.корень);
    М.корень.visible = false;
    М.салон.visible = false;
    собрано = true;
    return М.корень;
  }

  /* ── Публикация мест разметки ─────────────────────────────────
     Каждый кадр считаем, где на экране стоят экран анкеты, экран
     вопросов и ряд клавиш, и пишем это переменными оформления на корне
     документа. Разметка садится в них и едет вместе с кадром.

     Запись на корне помечает устаревшим стиль всего дерева, поэтому
     пишем ТОЛЬКО изменившееся и только с точностью до сотых процента:
     дрожание в четвёртом знаке заставляло бы браузер пересчитывать
     вёрстку каждый кадр, ничего при этом не двигая. */
  var кэшСтиля = {};
  function писать(имя, знач) {
    if (кэшСтиля[имя] === знач) return;
    кэшСтиля[имя] = знач;
    d.documentElement.style.setProperty(имя, знач);
  }

  function публиковать(видима) {
    if (!собрано || !W || !W.cam) return;
    if (!видима) {
      писать("--рв-фин-к", "0");
      return;
    }
    var кам = W.cam;
    М.корень.updateMatrixWorld();
    var i, j;
    for (i = 0; i < М.рамки.length; i++) {
      var р = М.рамки[i];
      var x0 = 1e9, x1 = -1e9, y0 = 1e9, y1 = -1e9, сзади = false;
      for (j = 0; j < 4; j++) {
        р.углы[j].getWorldPosition(М.в3);
        М.в3.project(кам);
        /* Точка за спиной камеры приходит вывернутой: её координаты
           зеркалятся, и прямоугольник растягивается на весь экран.
           Такой кадр публиковать нельзя вовсе. */
        if (М.в3.z > 1) { сзади = true; break; }
        if (М.в3.x < x0) x0 = М.в3.x;
        if (М.в3.x > x1) x1 = М.в3.x;
        if (М.в3.y < y0) y0 = М.в3.y;
        if (М.в3.y > y1) y1 = М.в3.y;
      }
      if (сзади) continue;
      var лево = (x0 * 0.5 + 0.5) * 100;
      var верх = (0.5 - y1 * 0.5) * 100;
      var ш = (x1 - x0) * 50;
      var в = (y1 - y0) * 50;
      писать("--рв-фин-" + р["имя"] + "-x", лево.toFixed(2) + "%");
      писать("--рв-фин-" + р["имя"] + "-y", верх.toFixed(2) + "%");
      писать("--рв-фин-" + р["имя"] + "-ш", ш.toFixed(2) + "%");
      писать("--рв-фин-" + р["имя"] + "-в", в.toFixed(2) + "%");
      р["лево"] = лево; р["верх"] = верх; р["ш"] = ш; р["в"] = в;
    }
  }

  /* ── Кадр ─────────────────────────────────────────────────────
     Доля 0 - камера снаружи, перед закрытым люком. Доля 1 - глаз у
     пульта. Между ними всё чистая функция доли: лента отматывается
     назад, и дверь обязана честно закрыться, а не остаться открытой
     потому, что «уже играли».

     Порядок взят у CDN (rc-airlock): щель светится раньше движения,
     замки дёргаются внутрь, створки уходят по обшивке, свет из проёма
     разгорается к самой узкой точке прохода. */
  var звукЛюка = false, звукПульта = false;

  function кадр(доля, dt, часы) {
    if (!собрано) return;
    var д = зажать(доля == null ? 0 : доля, 0, 1);
    доляСейчас = д;
    var ч = часы || 0;

    /* ── ПОРОГИ ВХОДА СЧИТАНЫ ОТ ХОДА КАМЕРЫ, А НЕ НА ГЛАЗОК ──────
       Ход камеры по этому акту измерен (tools/дорога-финала.mjs) и
       подправлен темпом в позе ниже: наружную обшивку глаз пересекает
       на доле 0.54, у пульта встаёт на 0.59. Всё, что происходит с
       люком, обязано закончиться ДО 0.54 - иначе человек входит сквозь
       закрытые створки, и ровно это тут и было.

       Запас между «створки настежь» (0.50) и «глаз в проёме» (0.54)
       четыре сотых доли: меньше не берём, потому что доля на живой
       прокрутке идёт поводком и на быстром жесте перешагивает узкие
       окна целиком. */
    var кСтв = отрезок(д, 0.24, 0.50);          /* распах створок */
    /* Щель гаснет, как только створки поехали. Первый заход держал её
       почти в полную силу до 0.62, и на снимке 0.42 посреди уже
       открытого проёма стоял световой столб: свет из щели остаётся,
       когда самой щели давно нет. Щель светится ДО движения, дальше
       кадр принадлежит проёму. */
    var кЩель = отрезок(д, 0.10, 0.24) * (1 - отрезок(д, 0.24, 0.40));
    var кСвет = отрезок(д, 0.28, 0.60);         /* свет из проёма */
    var кСалон = отрезок(д, 0.40, 0.74);
    /* Пульт набирает силу с 0.58, а не с 0.70. Замер поймал прямую
       дыру: на 0.72 доля пульта была 0.02, признак «мы у панели» ещё не
       стоял, и анкета с клавишами появлялась только на самой последней
       доле - то есть человек подходил к пульту, на котором ничего нет.
       Полный ход к 0.92 оставляет хвост ленты на «постоять и почитать»,
       а не на догоняющее проявление интерфейса. */
    var кПульт = отрезок(д, 0.52, 0.86);

    /* Расцепление замков. Настоящий люк не трогается вбок из
       запертого положения: сперва фиксаторы уводят створки внутрь и
       отпускают. Окно короткое, восемь сотых доли, и на ступени 0 его
       нет - это украшение, а не сценарий. */
    var ст = W && W.ступень != null ? W.ступень : 2;
    var рывок = 0;
    if (ст >= 1 && д > 0.18 && д < 0.26) {
      рывок = Math.sin(отрезок(д, 0.18, 0.26) * Math.PI) * 0.035;
    }

    if (М.снаружи.visible !== снаружиНужно) М.снаружи.visible = снаружиНужно;

    /* Люк ведёт сам корабль: у него свои створки, свой отжим притвора
       и свой свет в щели, все три по числам соседнего сайта. Наши
       створки живут только запасным путём, когда модуль не доехал. */
    if (М.чужой && g["RV_КОРАБЛЬ"] && g["RV_КОРАБЛЬ"]["кадр"]) {
      g["RV_КОРАБЛЬ"]["кадр"](кСтв, dt, ч);
    } else if (М.створкаЛев) {
      М.створкаЛев.rotation.y = -РАСПАХ * кСтв;
      М.створкаПрав.rotation.y = РАСПАХ * кСтв;
      М.створкаЛев.position.z = -рывок;
      М.створкаПрав.position.z = -рывок;
    }

    /* Щель нашего люка не нужна, когда стоит чужой: у него своя
       светящаяся кромка по притвору, и две полосы света в одном
       проёме читаются двумя дверями. */
    М.щель.material.opacity = М.чужой ? 0 : кЩель * 0.85;
    М.щель.visible = !М.чужой && кЩель > 0.004;
    /* Щель ширится вместе со створками, пока её видно: полоса света
       обязана расти по проёму, а не оставаться ниткой. */
    М.щель.scale.x = 1 + кСтв * 3.2;

    М.светПроёма.material.opacity = кСвет * 0.72;
    М.светПроёма.visible = кСвет > 0.004;

    /* Салон включаем ровно тогда, когда в щель уже что-то видно.
       Раньше нельзя: обшивка непрозрачная, и зал за ней считался бы
       впустую. */
    var салонНужен = д > 0.28;
    if (М.салон.visible !== салонНужен) М.салон.visible = салонНужен;
    if (М.даль.visible !== дальНужна) М.даль.visible = дальНужна;

    if (салонНужен) {
      /* Свет зала разгорается вместе с входом, но снизу не гаснет
         никогда: тёмный салон на телефоне владелец уже видел, и это
         была отдельная жалоба. Нижний предел взят от кадра, а не от
         вкуса: при 0.45 тёмная сторона пульта ещё читается. */
      М.лампаТёплая.intensity = 1.9 * (0.45 + 0.55 * кСалон);
      М.лампаПульта.intensity = 1.7 * (0.40 + 0.60 * кПульт);
      /* Экраны и клавиши дышат: приборная панель с намертво ровным
         свечением читается наклейкой. Амплитуда маленькая, четыре
         сотых, - это дыхание, а не мигание. */
      var дых = 0.96 + Math.sin(ч * 1.7) * 0.04;
      М.экрАнкета.material.opacity = зажать(0.35 + кПульт * 0.65, 0, 1) * дых;
      М.экрВопросы.material.opacity = зажать(0.35 + кПульт * 0.65, 0, 1) * дых;
      М.клВПН.material.opacity = зажать(0.30 + кПульт * 0.70, 0, 1);
      М.клИгра.material.opacity = зажать(0.30 + кПульт * 0.70, 0, 1) *
                                  (0.92 + Math.sin(ч * 2.3 + 1.1) * 0.08);
    }

    /* ── ПОСЛЕДНИЙ КАДР ПРИНАДЛЕЖИТ РАМЕ РУБКИ ───────────────────
       Владелец: «финальную сцену 1:1 как на сайте CDN - такая же
       ракета, салон, панель, просто скопируй её; вопросы и кнопки
       поставить на самый последний кадр».

       Панель у соседей это фотореальный снимок рубки с прозрачной
       дырой на месте окна (rv-кабина.js). Он приходит НА ХВОСТЕ акта,
       когда камера уже встала у панели, и ровно тогда объёмная стойка
       из плит уходит: две панели разом это тот шов, на который у
       соседей владелец уже жаловался («панель появляется поверх окна
       салона, а должна быть частью салона»).

       Окно рамы прозрачно, и сквозь него видно настоящий зал: рама
       стоит на кромке кадра, середина принадлежит сцене. */
    var кРама = отрезок(д, 0.80, 0.94);
    if (g.RV_КАБИНА && g.RV_КАБИНА["сила"]) {
      g.RV_КАБИНА["сила"](кРама);
      /* Приборы в нишах живые: у них бегут полосы и дышат подсветки.
         Стоячая дека читается наклейкой поверх снимка. */
      if (g.RV_КАБИНА["кадр"]) g.RV_КАБИНА["кадр"](dt);
    }
    /* Стойка гаснет НАВСТРЕЧУ раме, а не по своему порогу: пока рама
       не набрала силу, панель в кадре обязана быть хоть какая-то. */
    var стойкаНужна = кРама < 0.92;
    if (М.стойка && М.стойка.visible !== стойкаНужна) М.стойка.visible = стойкаНужна;
    if (М.полка && М.полка.visible !== стойкаНужна) М.полка.visible = стойкаНужна;

    /* ── ТЕКСТ ПРИХОДИТ ВМЕСТЕ С РАМОЙ, А НЕ РАНЬШЕ ──────────────
       Признак стоял на доле подхода к пульту (кПульт с 0.52), и снимок
       доли 0.60 показал, чем это кончается: анкета, вопросы и кнопки
       висят посреди пустой тёмной сцены, потому что рамы ещё нет, а
       объёмная стойка отсюда уже не видна.

       Текст этого финала живёт В ОКНЕ РАМЫ и нигде больше. Значит и
       приходить он обязан вместе с ней. Порог маленький: рама
       проступает за четырнадцать сотых доли, и ждать её полной силы
       значит отдать человеку последний экран пустым. */
    var уПульта = кРама > 0.10;
    var кл = d.documentElement.classList;
    if (уПульта !== кл.contains("рв-финал-пульт")) кл.toggle("рв-финал-пульт", уПульта);

    писать("--рв-фин-к", кРама.toFixed(3));
    публиковать(уПульта);

    /* Звук. Шипение пневматики один раз на открытие, щелчок пульта один
       раз на подходе. Оба сбрасываются при откате ленты назад: человек,
       вернувшийся к люку, услышит его снова. */
    if (g.RV_SOUND && g.RV_SOUND["разом"]) {
      try {
        if (!звукЛюка && кСтв > 0.05) { звукЛюка = true; g.RV_SOUND["разом"]("dock", 0.7); }
        if (звукЛюка && кСтв < 0.02) звукЛюка = false;
        if (!звукПульта && кПульт > 0.55) { звукПульта = true; g.RV_SOUND["разом"]("gate", 0.7); }
        if (звукПульта && кПульт < 0.35) звукПульта = false;
      } catch (e) {}
    }
  }

  /* ── Видимость ────────────────────────────────────────────────
     Уходя из кадра, финал обязан убрать за собой признаки на разметке:
     иначе анкета и клавиши остались бы стоять на экране посреди
     другого акта. */
  function видно(да) {
    if (!собрано) return;
    видноСейчас = !!да;
    М.корень.visible = видноСейчас;
    if (!видноСейчас) {
      d.documentElement.classList.remove("рв-финал-пульт");
      писать("--рв-фин-к", "0");
      /* Рама рубки принадлежит этому акту и только ему. Оставь её
         включённой - и человек, откативший ленту назад, увидит стены
         кабины поверх лунного дома. */
      if (g.RV_КАБИНА && g.RV_КАБИНА["сила"]) g.RV_КАБИНА["сила"](0);
    }
  }

  g.RV_ФИНАЛ = {
    "собрать": собрать,

    /* ── АКТ УЖАЛ ВЕСЬ КОРАБЛЬ, СВЕТ ОБ ЭТОМ НЕ ЗНАЕТ ────────────
       Корабль переехал на место роя и ужат до его роста (см.
       rv-act-финал.js). Матрица узла тянет за собой геометрию и
       дорогу камеры, но НЕ дальность точечных источников: она задана
       в мировых единицах и живёт мимо графа. Без пересчёта тёплая
       лампа с дальностью двадцать шесть заливала ужатый втрое зал
       целиком, а с ним и обшивку снаружи.

       Зовётся один раз, из акта, сразу после установки масштаба. */
    "мирУжат": function (к) {
      if (!собрано || !(к > 0)) return;
      if (М.лампаТёплая) М.лампаТёплая.distance = 26 * к;
      if (М.лампаПульта) М.лампаПульта.distance = 11 * к;
    },
    "кадр": кадр,
    "видно": видно,
    "узел": function () { return собрано ? М.корень : null; },

    /* Поза акта одной прямой. Мир ведёт камеру от «на» с отходом
       «подход» назад по линии взгляда: отход около двадцати ставит её
       снаружи перед люком, а конец акта - у пульта. Оборота нет нигде,
       и это ровно то, о чём просил владелец.

       Координаты отдаём МИРОВЫЕ: группа финала может стоять где угодно,
       и акт не обязан знать, куда её поставили. */
    "поза": function () {
      var м = местоУПульта();
      var глазZ = ЭКР_ПЛОСКОСТЬ + м["даль"];
      /* ── ОТХОД МЕРЯЕТСЯ В МИРОВЫХ ЕДИНИЦАХ ────────────────────
         «на» и «от» уходят наружу мировыми точками, а «подход» и
         «уход» это ДЛИНЫ, и мир откладывает их в мировых единицах по
         той же линии. Пока узел стоял без масштаба, местные единицы и
         мировые совпадали, и разницы не было видно.

         Корабль переехал на место роя и ужат втрое (rv-act-финал.js).
         Отход в двадцать местных единиц стал бы двадцатью МИРОВЫМИ,
         то есть втрое дальше нужного: человек начинал бы акт не перед
         люком, а в другом конце ангара. Умножаем на настоящий масштаб
         узла, а не на записанное где-то число - узел один, и правда о
         его размере лежит в нём. */
      var к = 1;
      if (собрано && М.корень) {
        М.корень.updateMatrixWorld(true);
        var сВ = new T.Vector3();
        М.корень.getWorldScale(сВ);
        if (сВ.x > 0) к = сВ.x;
      }
      var база = {
        /* Отход считается от постоянной точки старта: где бы человек ни
           встал у пульта, ракета в начале акта видна одинаково. */
        "подход": +((СТАРТ_Z - глазZ) * к).toFixed(2),
        "уход": +(УХОД * к).toFixed(3),
        /* Поле сужается к пульту: на подходе видно ракету целиком, у
           панели кадр обязан сесть на приборы. */
        "поле": [46, (46 + м["поле"]) / 2, м["поле"]],
        /* Отворот взгляда почти запрещён: вся дорога прямая, и любой
           увод в сторону разворачивал бы человека боком к люку. */
        "обзор": 20,
        /* ── ТЕМП: КАМЕРА НЕ ОБГОНЯЕТ СТВОРКИ ────────────────────
           Без темпа доля акта ложится на дорогу поровну: узел подхода
           стоит на доле 0, узел у пульта на 0.5. Замер хода
           (tools/дорога-финала.mjs) показал, чем это кончалось:

             доля   0.00   0.15   0.30   0.45   0.60   1.00
             z     -58.0  -73.9  -77.5  -78.3  -78.5  -78.7

           Наружная обшивка стоит на z -74.55. Камера пересекала её
           между 0.15 и 0.30, то есть около 0.22 - а створки в кадре
           начинали расходиться только на 0.30 и вставали настежь на
           0.58. Человек ВХОДИЛ СКВОЗЬ ЗАКРЫТЫЙ ЛЮК, и дальше две трети
           акта стоял у пульта, потому что весь ход был давно пройден.

           Темп это чинит на месте: первые три десятых доли камера идёт
           к кораблю не спеша (восемнадцать сотых пути, корабль растёт в
           кадре), дальше плавная ступенька доводит её до пульта. По той
           же формуле обшивка пересекается на 0.54, пульт достаётся на
           0.59, и остаток ленты человек стоит у панели и читает - как и
           задумано. Пороги створок ниже пересчитаны под эти числа. */
        "темп": [0.30, 0.18]
      };
      if (!собрано) {
        база["на"] = ПРИЦЕЛ_ПУЛЬТ.slice();
        база["от"] = [ГЛАЗ_ПУЛЬТ[0], ГЛАЗ_ПУЛЬТ[1], глазZ];
        return база;
      }
      М.глазТ.position.z = глазZ;
      М.корень.updateMatrixWorld(true);
      var от = new T.Vector3(), на = new T.Vector3();
      М.глазТ.getWorldPosition(от);
      М.прицелТ.getWorldPosition(на);
      база["на"] = [на.x, на.y, на.z];
      база["от"] = [от.x, от.y, от.z];
      return база;
    },

    /* Корабль снаружи. Погасить его нужно акту, который поднимет
       настоящую объёмную ракету соседним модулем: два корпуса в одном
       кадре это два корабля, и человек увидит шов между ними. Люк,
       труба и салон при этом остаются - вход всегда наш. */
    "снаружи": function (да) {
      снаружиНужно = !!да;
      if (собрано && М.снаружи) М.снаружи.visible = снаружиНужно;
    },

    /* Даль за остеклением. Акту, который поставит финал посреди живого
       мира, она не нужна: в окне будет настоящий космос. */
    "даль": function (да) {
      дальНужна = !!да;
      if (собрано && М.даль) М.даль.visible = дальНужна && М.салон.visible;
    },

    "замер": function () {
      if (!собрано) return { "собрано": false };
      var р = {}, i;
      for (i = 0; i < М.рамки.length; i++) {
        var к = М.рамки[i];
        р[к["имя"]] = [+к["лево"].toFixed(1), +к["верх"].toFixed(1),
                       +к["ш"].toFixed(1), +к["в"].toFixed(1)];
      }
      return {
        "собрано": true,
        "видно": !!М.корень.visible,
        "доля": +доляСейчас.toFixed(3),
        "салон": !!М.салон.visible,
        "распах": +(М.створкаПрав.rotation.y).toFixed(3),
        "распахПредел": +РАСПАХ.toFixed(3),
        "щель": +М.щель.material.opacity.toFixed(3),
        "светПроёма": +М.светПроёма.material.opacity.toFixed(3),
        "лампаЗала": +М.лампаТёплая.intensity.toFixed(2),
        "лампаПульта": +М.лампаПульта.intensity.toFixed(2),
        "уПульта": d.documentElement.classList.contains("рв-финал-пульт"),
        "снаружи": !!М.снаружи.visible,
        "местоУПульта": местоУПульта(),
        "рамки": р,
        "люк": { "ширина": +(ЛЮК_ПШ * 2).toFixed(2),
                 "высота": +(ЛЮК_ВЕРХ - ЛЮК_НИЗ).toFixed(2) },
        "зал": { "радиус": R_СТЕНА, "высота": H_ЗАЛ, "глаз": ГЛАЗ }
      };
    },

    /* Поворот телефона меняет две вещи: места разметки надо переписать
       заново (кэш записей сбрасываем), и глаз у пульта переезжает -
       лежачий кадр смотрит с двух с половиной метров, стоячий с
       четырёх. Позу после этого обязан перечитать акт, поэтому здесь
       двигаем только сам узел, а числа отдаём тем же вызовом «поза». */
    "размер": function () {
      кэшСтиля = {};
      if (собрано) М.глазТ.position.z = ЭКР_ПЛОСКОСТЬ + местоУПульта()["даль"];
    }
  };
})(window, document);
