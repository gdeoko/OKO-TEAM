/* Rocket VPN. Акт «видно»: первый экран внутри объёмного мира.

   ПОЧЕМУ ПЕРВЫЙ ЭКРАН ТЕПЕРЬ В ОБЪЁМЕ. Сайт продаёт мир, а начинался
   он плоской картинкой: два первых акта рисовал двумерный холст, мир
   включался с третьего экрана, и человек видел шов ровно там, где
   лента обещала единый фильм. Теперь решётка сети лежит в самой сцене,
   перед прологом камеры: камера идёт по оси z от 92 к 18, смотрит в
   начало координат, и решётка стоит у неё на пути, наклонённой
   плоскостью ниже линии взгляда. Ближние ряды крупнее дальних сами, без
   нарисованной перспективы, а на прокрутке ряды уходят под камеру.

   ПОЧЕМУ БЕЗ ПОЗЫ. Станции кривой пересчитаны проверками полёта: узел
   выхода восьмой, и новая станция сдвинула бы всё. Акт регистрируется
   плоским, содержимое кладётся в сцену в мировых координатах, а живым
   он объявляет себя сам, пока не кончился периметр.

   ПОЧЕМУ МОДЕЛЬ СЕТИ ОДНА. Узлы, рёбра и пакеты берутся из rv-net.js:
   тот же генератор, те же рёбра, тот же ход пакетов. Пакет, который во
   втором акте отбили на воротах, обязан быть тем же пакетом, что шёл
   по решётке на первом экране, а две независимые математики этого не
   дают никогда. Ярлыки вскрытия остаются текстом в двумерном холсте:
   текст в нём резче, чем любой атлас. Этот акт лишь считает, где на
   экране стоит пакет, и отдаёт точки холсту. */
(function (g, d) {
  "use strict";

  var W = null;
  var М = {};
  var собрано = false;
  var показан = false;
  var тихо = false;

  /* Решётка в мировых единицах. Ширина больше высоты: камера на ПК
     смотрит широким кадром, а на телефоне видит только среднюю
     полосу, и там ширина ничего не стоит. */
  var ШИР = 60, ВЫС = 34;
  /* Наклон в радианах: нижние ряды к камере, верхние в глубину. При
     нуле плоскость встаёт стеной и перспектива живёт только в проезде,
     при прямом угле ложится полом и верхние ряды съезжают к горизонту
     в одну линию. Между ними ряды читаются по отдельности. */
  var НАКЛОН = -0.95;
  var ПЕРИОД = 4.2;   /* ход луча, как у двумерной версии */
  /* Трубка ребра толще одной точки экрана намеренно: в одну точку
     растр берёт её через раз, и под светом луча такое ребро
     рассыпалось цепочкой белых зёрен вдоль всей длины. */
  var Р_УЗЛА = 0.36, Р_РЕБРА = 0.11, Р_ПАКЕТА = 0.18, Р_СВОЙ = 0.32;

  function зажать(v, a, b) { return v < a ? a : (v > b ? b : v); }
  function мягко(a, b, v) { var t = зажать((v - a) / (b - a), 0, 1); return t * t * (3 - 2 * t); }

  function модель() { return g.RV_СЕТЬ_МОДЕЛЬ || null; }

  /* Узел модели (0..1 по обеим осям, верх это малый y) в местные
     координаты решётки: верхний ряд уходит в плюс по y, то есть после
     наклона - в глубину. */
  function местное(у, куда) {
    куда.x = (у.x - 0.5) * ШИР;
    куда.y = (0.5 - у.y) * ВЫС;
    куда.z = 0;
    return куда;
  }

  /* ── Шейдеры. Только латиница внутри: кириллица ломает разбор. ── */
  var В_ЛУЧ = [
    "varying vec2 vUv;",
    "void main(){ vUv = uv; gl_Position = projectionMatrix * modelViewMatrix * vec4(position,1.0); }"
  ].join("\n");

  /* Профиль поперёк полосы: широкое мягкое пятно и тонкое ядро. Одно
     без другого читается либо туманом, либо чертёжной линией. Концы
     полосы гаснут, иначе луч торчит за решётку прямоугольником. */
  var Ф_ЛУЧ = [
    "uniform vec3 uCol;",
    "uniform float uBright;",
    "varying vec2 vUv;",
    "void main(){",
    "  float dd = abs(vUv.y - 0.5) * 2.0;",
    "  float across = pow(1.0 - smoothstep(0.0, 1.0, dd), 2.2);",
    "  float core = pow(max(0.0, 1.0 - dd), 18.0);",
    "  float ends = 1.0 - smoothstep(0.30, 0.5, abs(vUv.x - 0.5));",
    "  float a = (across * 0.24 + core * 0.22) * uBright * ends;",
    "  gl_FragColor = vec4(uCol * (0.6 + core * 0.5), a);",
    "}"
  ].join("\n");

  function ореолТекстура(T) {
    var c = d.createElement("canvas");
    c.width = 64; c.height = 64;
    var x = c.getContext("2d");
    var гр = x.createRadialGradient(32, 32, 0, 32, 32, 32);
    гр.addColorStop(0, "rgba(140,165,255,0.85)");
    гр.addColorStop(0.35, "rgba(120,150,255,0.30)");
    гр.addColorStop(1, "rgba(120,150,255,0)");
    x.fillStyle = гр;
    x.fillRect(0, 0, 64, 64);
    var т = new T.CanvasTexture(c);
    if (T.SRGBColorSpace) т.colorSpace = T.SRGBColorSpace;
    return т;
  }

  /* ── Сборка ─────────────────────────────────────────────────── */
  function построить(мир) {
    if (собрано) return true;
    W = мир || W;
    if (!W || !W.T || !W.scene || !W.r) return false;
    var мод = модель();
    if (!мод) return false;
    var T = W.T, ст = W.ступень;
    var сет = мод["сеть"], пак = мод["пакеты"];
    var i;

    тихо = !!(g.RV_WORLD && g.RV_WORLD["тихо"] && g.RV_WORLD["тихо"]());

    М.корень = new T.Group();
    М.корень.name = "решётка видно";
    М.корень.visible = false;
    М.корень.rotation.x = НАКЛОН;
    W.scene.add(М.корень);

    /* ── Узлы: стеклянные бусины ─────────────────────────────────
       Не светящиеся точки, а тела с бликом: металл узнают по
       отражениям, стекло по блику и тёмной сердцевине. Свечение
       внутри слабое: сильное превращает бусину в лампу. */
    var n = сет["узлы"].length;
    var сегм = ст === 0 ? [10, 7] : (ст === 1 ? [14, 10] : [18, 14]);
    М.мУзлы = new T.MeshPhysicalMaterial({
      color: 0x1B2450,
      metalness: 0,
      roughness: 0.12,
      /* Лак только на полной ступени: второй блик стоит кадров. */
      clearcoat: ст === 2 ? 1 : 0,
      clearcoatRoughness: 0.08,
      emissive: 0x3048A8,
      emissiveIntensity: 0.6,
      envMapIntensity: 1.8
    });
    /* Луч и волна зажигания живут в самом материале. Перебор матриц
       отпал: сто семнадцать матриц на кадр это работа процессора, а
       две величины в шейдере ничего не стоят. Под лучом бусина растёт и
       разгорается; волна зажигания идёт от середины решётки. */
    М.мУзлы.onBeforeCompile = function (ш) {
      ш.uniforms.uBeamY = М.uBeamY;
      ш.uniforms.uWave = М.uWave;
      ш.uniforms.uDim = М.uDim;
      ш.vertexShader = ш.vertexShader
        .replace("#include <common>",
          "#include <common>\nuniform float uBeamY;\nuniform float uWave;\nvarying float vBeam;\nvarying float vWave;")
        .replace("#include <begin_vertex>",
          "#include <begin_vertex>\n"
          + "  float ny = instanceMatrix[3].y;\n"
          + "  float nx = instanceMatrix[3].x;\n"
          + "  float kb = 1.0 - smoothstep(0.0, 1.6, abs(ny - uBeamY));\n"
          + "  float kw = smoothstep(0.0, 1.0, uWave * 1.6 - length(vec2(nx, ny)) / 28.0);\n"
          + "  transformed *= (1.0 + 0.6 * kb) * kw;\n"
          + "  vBeam = kb; vWave = kw;");
      ш.fragmentShader = ш.fragmentShader
        .replace("#include <common>",
          "#include <common>\nuniform float uDim;\nvarying float vBeam;\nvarying float vWave;")
        .replace("#include <emissivemap_fragment>",
          "#include <emissivemap_fragment>\n"
          + "  totalEmissiveRadiance *= (1.0 + 2.0 * vBeam) * vWave * uDim;");
    };
    М.мУзлы.customProgramCacheKey = function () { return "rv-vidno-uzel"; };
    М.uBeamY = { value: 99 };
    М.uWave = { value: тихо ? 9 : 0 };
    М.uDim = { value: 1 };

    М.узлы = new T.InstancedMesh(new T.SphereGeometry(Р_УЗЛА, сегм[0], сегм[1]), М.мУзлы, n);
    var м4 = new T.Matrix4(), п3 = new T.Vector3();
    for (i = 0; i < n; i++) {
      местное(сет["узлы"][i], п3);
      м4.makeTranslation(п3.x, п3.y, п3.z);
      М.узлы.setMatrixAt(i, м4);
    }
    М.узлы.instanceMatrix.needsUpdate = true;
    /* Коробка экземпляров считается по одной сфере, экземпляры в неё
       не входят: отсечение по ней выкинуло бы решётку из кадра целиком. */
    М.узлы.frustumCulled = false;
    М.узлы.renderOrder = 2;
    М.корень.add(М.узлы);

    /* ── Рёбра: металлические трубки ─────────────────────────────
       Тот же корпус, что у станции и корабля: одна физика на весь
       мир. Матрица каждой трубки собирается по паре узлов один раз. */
    var е = сет["рёбра"].length;
    /* Без лака и с фактурой почти в ноль: на трубке в две точки
       толщиной разнобой шероховатости рвал блик ключевого света в
       цепочку белых бусин вдоль ребра, и их путали с пакетами (снимок
       полной ступени). Ровная шероховатость даёт по трубке одну
       сплошную полоску блика, как на настоящей трубе. */
    М.мРёбра = (g.RV_REAL && g.RV_REAL["корпус"])
      ? g.RV_REAL["корпус"](T, { "цвет": 0x4A5690, "металл": 0.92, "шерох": 0.5, "жар": 0.1, "лак": 0, "фактура": 0.2 })
      : new T.MeshStandardMaterial({ color: 0x4A5690, metalness: 0.9, roughness: 0.3 });
    М.рёбра = new T.InstancedMesh(
      new T.CylinderGeometry(Р_РЕБРА, Р_РЕБРА, 1, ст === 0 ? 5 : 6, 1, true), М.мРёбра, е);
    var q = new T.Quaternion(), ось = new T.Vector3(0, 1, 0);
    var а = new T.Vector3(), б = new T.Vector3(), напр = new T.Vector3(), сер = new T.Vector3(), масш = new T.Vector3();
    for (i = 0; i < е; i++) {
      var р = сет["рёбра"][i];
      местное(сет["узлы"][р[0]], а);
      местное(сет["узлы"][р[1]], б);
      напр.subVectors(б, а);
      var дл = напр.length();
      напр.normalize();
      q.setFromUnitVectors(ось, напр);
      сер.addVectors(а, б).multiplyScalar(0.5);
      масш.set(1, дл, 1);
      м4.compose(сер, q, масш);
      М.рёбра.setMatrixAt(i, м4);
    }
    М.рёбра.instanceMatrix.needsUpdate = true;
    М.рёбра.frustumCulled = false;
    М.рёбра.renderOrder = 1;
    М.корень.add(М.рёбра);

    /* ── Пакеты: светящиеся зёрна на рёбрах ──────────────────────
       Не тонированы намеренно: им положено уходить за порог плёнки и
       давать ореол, это единственный настоящий свет на первом экране
       кроме луча. Яркость каждого своя через цвет экземпляра: под
       лучом вспышка, у отбитого угасание. */
    var пк = пак.length;
    М.мПакеты = new T.MeshBasicMaterial({ color: 0xffffff, toneMapped: false });
    М.пакеты = new T.InstancedMesh(new T.SphereGeometry(Р_ПАКЕТА, ст === 0 ? 8 : 12, ст === 0 ? 6 : 8), М.мПакеты, пк);
    М.цвПакета = new T.Color(0xC8D6FF);
    М.цв = new T.Color();
    for (i = 0; i < пк; i++) {
      м4.makeTranslation(0, 0, 0);
      М.пакеты.setMatrixAt(i, м4);
      М.пакеты.setColorAt(i, М.цвПакета);
    }
    М.пакеты.instanceMatrix.needsUpdate = true;
    М.пакеты.frustumCulled = false;
    М.пакеты.renderOrder = 3;
    М.корень.add(М.пакеты);

    /* Свой пакет крупнее и с ореолом: человек находит его глазами без
       подсказки, как и в двумерной версии. */
    М.свой = new T.Mesh(
      new T.SphereGeometry(Р_СВОЙ, ст === 0 ? 10 : 16, ст === 0 ? 8 : 12),
      new T.MeshBasicMaterial({ color: new T.Color(0x7896FF).multiplyScalar(3.2), toneMapped: false })
    );
    М.свой.renderOrder = 4;
    М.корень.add(М.свой);
    М.ореол = new T.Sprite(new T.SpriteMaterial({
      map: ореолТекстура(T), transparent: true, depthWrite: false,
      blending: T.AdditiveBlending, opacity: 0.9
    }));
    М.ореол.scale.set(3.2, 3.2, 1);
    М.ореол.renderOrder = 4;
    М.корень.add(М.ореол);

    /* ── Луч досмотра ────────────────────────────────────────────
       Полоса чуть над плоскостью: лежащая ровно в ней спорила бы с
       трубками за глубину и мерцала. */
    М.мЛуч = new T.ShaderMaterial({
      uniforms: { uCol: { value: new T.Color(0xC8D6FF) }, uBright: { value: 1.0 } },
      vertexShader: В_ЛУЧ, fragmentShader: Ф_ЛУЧ,
      /* ПРОВЕРКА ГЛУБИНЫ ВКЛЮЧЕНА. Она была снята, чтобы полоса не
         спорила с трубками за глубину, но от спора уже спасает вынос на
         0.3 вперёд, который стоит строкой ниже. Снятая проверка делает
         другое: плоскость шириной в шестьдесят шесть единиц рисуется
         ПОВЕРХ ВСЕГО, включая предметы соседних актов.

         Поймано замером на стене станции: на доле 0.99 поперёк собранной
         кладки шла светлая полоса без источника. Разбор по объектам
         показал, что источник стоит в СЛЕДУЮЩЕМ акте, в сорока семи
         единицах за стеной, и виден только потому, что не спрашивает
         глубину. Стена его теперь честно закрывает. */
      transparent: true, depthWrite: false,
      blending: T.AdditiveBlending
    });
    М.луч = new T.Mesh(new T.PlaneGeometry(ШИР + 6, 2.6), М.мЛуч);
    М.луч.position.z = 0.3;
    М.луч.renderOrder = 5;
    М.корень.add(М.луч);

    /* Свет, который едет с лучом: бусины под ним получают настоящий
       блик вместо подкрашенного свечения. Только на полной ступени: ещё
       один источник дорожает каждому физическому материалу в кадре.

       Источник стоит в сцене всегда и гасится силой, видимость не трогаем:
       смена числа видимых источников заставляет плёнку пересобирать
       все программы материалов, и это рывок на секунду. */
    /* Высота над плоскостью шесть единиц. На двух, вплотную к
       трубкам источник давал на них жёсткий блик, рваный фактурой в
       цепочку бусин, и рёбра под ним путались с пакетами. Выше свет
       ложится на бусины ровно, а трубки лишь чуть светлеют. */
    if (ст === 2) {
      М.свет = new T.PointLight(0xC8D6FF, 0, 30, 2);
      М.свет.position.set(0, 0, 6);
      М.корень.add(М.свет);
    }

    М.ярлыки = [];
    М.волна = 0;
    М.в3 = new T.Vector3();
    М.м4 = м4;
    М.а = а; М.б = б; М.п3 = п3;

    собрано = true;
    размерить(g.innerWidth, g.innerHeight);
    return true;
  }

  /* ── Размер ─────────────────────────────────────────────────────
     На ПК колонка слов стоит слева, и решётка сдвинута вправо: под
     заголовком остаются только дальние тусклые ряды. На телефоне в
     кадр влезает лишь средняя полоса решётки, и её место ниже слов. */
  function размерить(w, h) {
    if (!собрано) return;
    var узко = w < 760;
    /* На телефоне решётка выше и положе: узкий кадр видит только её
       среднюю полосу, и без этого верхняя половина экрана стояла
       пустой, а вся сеть жалась к нижней кромке. */
    М.базаY = узко ? -4.5 : -5.5;
    М.корень.position.set(узко ? 0 : 5, М.базаY, 52);
    М.корень.rotation.x = узко ? НАКЛОН + 0.1 : НАКЛОН;
  }

  /* ── Кадр ───────────────────────────────────────────────────────*/
  function кадр(доля, dt, часы) {
    if (!собрано && !построить(g.RV_WORLD ? g.RV_WORLD["мир"]() : null)) return;
    var мод = модель();
    if (!мод) return;
    var сет = мод["сеть"], пак = мод["пакеты"];
    var дПер = g.RV_MOTION ? g.RV_MOTION["доля"]("периметр") : 0;
    var i;

    /* Волна зажигания отсчитывается от первого показа: до сборки
       решётки зажигать нечего, и отсчёт от загрузки прошёл бы впустую. */
    if (М.волна < 3) М.волна += dt;
    М.uWave.value = тихо ? 9 : М.волна;

    /* Периметр: решётка уходит ВНИЗ из-под камеры, а свет на ней
       гаснет по той же кривой, по которой проявляется плита блокпоста
       (rv.css, с 0.05). Без ухода вниз камера въезжала в ближние ряды в
       упор: бусина размером в полэкрана и ореол своего пакета на всю
       нижнюю кромку, поймано снимком на доле 0.12. Уход читается как
       перелёт над решёткой к стене. Когда плита уже плотная, решётка
       прячется целиком: рисовать под непрозрачной плитой нечего. */
    var гас = 1 - мягко(0.05, 0.45, дПер);
    М.uDim.value = гас;
    М.корень.position.y = М.базаY - 34 * мягко(0.02, 0.40, дПер);
    М.корень.visible = показан && дПер < 0.62;
    if (!М.корень.visible) { if (М.свет) М.свет.intensity = 0; М.ярлыки.length = 0; return; }

    /* Луч: сверху (из глубины) вниз (к камере), ход длиннее решётки,
       чтобы он входил и выходил за её краем без возникновения на кромке. */
    var фаза = (часы % ПЕРИОД) / ПЕРИОД;
    var yЛуча = ВЫС / 2 + 5 - фаза * (ВЫС + 10);
    М.луч.position.y = yЛуча;
    М.uBeamY.value = yЛуча;
    М.мЛуч.uniforms.uBright.value = гас;
    if (М.свет) {
      М.свет.position.set(0, yЛуча, 6);
      М.свет.intensity = 110 * гас;
    }

    /* Пакеты по общей модели: положение это ребро и доля пути на нём,
       двумерный холст двигает их сам. Здесь только раскладка. */
    var м4 = М.м4, а = М.а, б = М.б, п3 = М.п3, цв = М.цв;
    var первый = дПер < 0.02;
    М.ярлыки.length = 0;
    var ш = g.innerWidth || 1, в = g.innerHeight || 1;
    М.корень.updateMatrixWorld(true);
    for (i = 0; i < пак.length; i++) {
      var п = пак[i];
      var р = сет["рёбра"][п["ребро"]];
      местное(сет["узлы"][р[0]], а);
      местное(сет["узлы"][р[1]], б);
      п3.lerpVectors(а, б, п["t"]);
      п3.z = Р_ПАКЕТА * 0.4;
      var ярк = 2.2;
      if (п["состояние"] === "отбит") {
        /* Отбитый подпрыгивает над решёткой и гаснет: «не пустили»,
           а не «исчез». */
        п3.z += Math.sin(п["отбой"] * 3.14159) * 1.6;
        ярк *= 1 - п["отбой"];
      }
      var kb = 1 - зажать(Math.abs(п3.y - yЛуча) / 1.2, 0, 1);
      ярк *= (1 + kb * 1.4) * гас;
      /* Вскрытие под лучом ставим только на первом экране: в периметре
         луч двумерный и янтарный, и ставит его тот холст. */
      if (первый && Math.abs(п3.y - yЛуча) < 0.9) п["вскрыт"] = 1;

      if (п["свой"]) {
        М.свой.position.copy(п3);
        М.ореол.position.copy(п3);
        М.ореол.position.z += 0.2;
        М.ореол.material.opacity = (0.55 + 0.25 * Math.sin(часы * 2.3)) * гас;
        /* Свой пакет в решётке не дублируем: его экземпляр прячется в
           ноль масштабом. */
        м4.makeScale(0, 0, 0);
        М.пакеты.setMatrixAt(i, м4);
      } else {
        м4.makeTranslation(п3.x, п3.y, п3.z);
        М.пакеты.setMatrixAt(i, м4);
        цв.copy(М.цвПакета).multiplyScalar(ярк);
        М.пакеты.setColorAt(i, цв);
      }

      /* Ярлык на экран: точка над пакетом в мировых координатах,
         спроецированная камерой. Холст дорисует слово. */
      if (п["вскрыт"] > 0.01 && гас > 0.02) {
        М.в3.set(п3.x, п3.y, п3.z + 0.5).applyMatrix4(М.корень.matrixWorld).project(W.cam);
        if (М.в3.z < 1 && М.в3.z > -1) {
          М.ярлыки.push({
            "x": (М.в3.x * 0.5 + 0.5) * ш,
            "y": (0.5 - М.в3.y * 0.5) * в,
            "текст": п["ярлык"],
            "а": п["вскрыт"] * гас,
            "свой": !!п["свой"]
          });
        }
      }
    }
    М.пакеты.instanceMatrix.needsUpdate = true;
    if (М.пакеты.instanceColor) М.пакеты.instanceColor.needsUpdate = true;
  }

  /* ── Договор с ядром ────────────────────────────────────────────*/
  var МОДУЛЬ = {
    "собрать": function (мир) { построить(мир); },
    "показать": function (да) {
      if (да && !собрано) построить(g.RV_WORLD ? g.RV_WORLD["мир"]() : null);
      if (!собрано) return;
      if (да && !показан) М.волна = 0;
      показан = !!да;
      М.корень.visible = показан;
      if (М.свет && !показан) М.свет.intensity = 0;
    },
    "кадр": кадр,
    "размер": function (w, h) { размерить(w, h); },
    /* Живой на обоих плоских актах, пока периметр не кончился. По доле
       ядро счло бы первый экран мёртвым: до прокрутки она ровно ноль. */
    "вКадре": function () {
      /* При просьбе убрать движение холст мира скрыт вёрсткой, и
         держать его живым значило бы рисовать в никуда каждый кадр;
         первый экран там остаётся плоским, как был. */
      if (g.RV_WORLD && g.RV_WORLD["тихо"] && g.RV_WORLD["тихо"]()) return false;
      var дПер = g.RV_MOTION ? g.RV_MOTION["доля"]("периметр") : 0;
      return дПер < 0.98;
    }
  };

  /* Наружу, для двумерного холста: пока решётка живёт в объёме, холст
     рисует только ярлыки, и берёт их отсюда. */
  g.RV_ВИДНО = {
    "живой": function () { return собрано && показан; },
    "ярлыки": function () { return М.ярлыки || []; }
  };

  function встать() {
    if (!g.RV_WORLD) return;
    g.RV_WORLD["акт"]("видно", МОДУЛЬ);
  }

  if (g.RV_WORLD && g.RV_WORLD["готов"] && g.RV_WORLD["готов"]()) встать();
  else g.addEventListener("rv:мир", встать);
})(window, document);
