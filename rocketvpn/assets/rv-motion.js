/* Rocket VPN. Плёнка: прокрутка превращается в долю внутри каждого акта.

   Почему не «анимации по появлению в окне». Сайт задуман как единая
   лента, где кадр в любой момент однозначно считается из положения
   прокрутки. Появление в окне даёт события, а нужна ВЕЛИЧИНА: сцены
   должны уметь отмотаться назад ровно так же, как шли вперёд, иначе
   человек, крутящий вверх, видит не обратный ход, а сбой.

   Величина у каждого акта своя и лежит в 0..1. Наружу она уходит двумя
   путями: переменной оформления --д на самом акте (это нужно вёрстке) и
   вызовом подписчика (это нужно объёмным сценам). Один источник, два
   потребителя, никакой второй математики. */
(function (g, d) {
  "use strict";

  var АКТЫ = [];
  var подписки = {};
  var идёт = false;
  var последнееY = -1;

  /* Мягкость. Сырая доля прокрутки на телефоне идёт ступенями (браузер
     отдаёт её не каждый кадр), и сцена от этого дёргается. Подтягиваем
     показанную величину к сырой, а не показываем сырую.

     Коэффициент крупнее прежних 0.18, потому что подтяжек теперь ДВЕ
     (см. шаг): две по 0.18 догоняли бы цель вдвое дольше одной, и
     лента заметно отставала бы от пальца. */
  /* ── ЧИСЛА ВЗЯТЫ У IGLOO ──────────────────────────────────────
     Владелец дважды сказал одно и то же: «я листаю, и она летит со
     скоростью света, а нужна такая же скорость и плавность движения
     камеры по скроллу, как у igloo». Числа сняты с их сборки
     (App3D-f554a111.js, класс контроллера сцен):

       scrollMultiplier = 0.00075
       targetY1 = lerpFPSLimited(targetY1, targetY2, 0.075, 100 * mult)
       y        = lerpFPS(y, targetY1, 0.15)
       поводок  = clamp(targetY2, y - 750*mult, y + 750*mult)
       защёлка  при |y - targetY2| < 0.1 * mult

     ГЛАВНОЕ У НИХ - ПОВОДОК, а не коэффициенты. Мы читаем родную
     прокрутку страницы: рывок пальцем двигает её МГНОВЕННО на сколько
     угодно, и две подтяжки потом честно догоняют этот прыжок - отсюда и
     «скорость света». У igloo прокрутки страницы нет вовсе, колесо идёт
     через свой счётчик, и цель не имеет права убежать от текущего места
     дальше чем на 0.5625 экрана. Сколько ни крути, камера идёт своим
     ходом.

     Поводок переносится сюда как есть, только в долях акта: у них он в
     ЭКРАНАХ, а доля акта это его высота в экранах. */
  var СГЛ1 = 0.075;      /* их первая подтяжка */
  var СГЛ2 = 0.15;       /* их вторая */
  var ПОВОДОК_ЭКРАНОВ = 0.5625;   /* 750 * 0.00075 */
  var ШАГ_ЭКРАНОВ = 0.075;        /* 100 * 0.00075, предел первой подтяжки */
  var МЯГКОСТЬ = 0.30;   /* остаётся для тех, кто зовёт подтяжку сам */

  /* Кадронезависимая подтяжка.

     Прежняя формула д += (цель - д) * k считала КАДРЫ, а не время. На
     телефоне со 120 герцами она догоняла цель ровно вдвое быстрее, чем
     на 60-герцовом, и одно и то же движение на двух телефонах выходило
     разным: на быстром резким, на медленном вязким. Владелец это и
     увидел как «идёт резко». Здесь коэффициент пересчитывается на долю
     кадра при шестидесяти герцах, и скорость подтяжки становится
     свойством времени, а не железа.

     Потолок в четыре кадра нужен для возврата из фона: там между двумя
     кадрами проходят секунды, и без потолка первая же подтяжка
     схлопнула бы всю разницу в один приём - то есть дала бы ровно тот
     рывок, от которого мы уходим. */
  function подтяжка(k, dt) {
    var раз = dt * 60;
    if (раз > 4) раз = 4;
    if (!(раз > 0.05)) раз = 0.05;
    return 1 - Math.pow(1 - k, раз);
  }

  function зажать(v) { return v < 0 ? 0 : (v > 1 ? 1 : v); }

  /* Ход акта - это отрезок прокрутки, на котором доля идёт от нуля до
     единицы: высота акта минус экран, пока кадр липнет к окну.

     Нижний предел не единица, а больше половины экрана. С единицей
     короткий акт получал ДВОИЧНУЮ долю: она прыгала с нуля на единицу
     за один пиксель прокрутки, объёмная сцена не успевала ожить и сразу
     считалась кончившейся. Это случается не в теории: ровно так ведут
     себя ВСЕ акты при просьбе убрать движение, где высота акта
     становится своей собственной.

     Функция одна на весь файл намеренно. Формула стояла в двух местах,
     и они уже разошлись: пересчёт кадра считал по одной, а переход к
     акту по другой, и приход из космоса вставал не туда, куда
     показывала доля. */
  function ходАкта(высотаАкта, высотаОкна) {
    return Math.max(высотаОкна * 0.6, высотаАкта - высотаОкна);
  }

  function собрать() {
    АКТЫ.length = 0;
    var узлы = d.querySelectorAll(".rv-акт");
    for (var i = 0; i < узлы.length; i++) {
      var э = узлы[i];
      АКТЫ.push({
        узел: э,
        имя: э.getAttribute("data-акт") || ("акт" + i),
        д: 0, сыр: 0, цель: 0,
        подход: 0, уход: 1, пБыло: "", уБыло: ""
      });
    }
  }

  function пересчитать() {
    var вы = g.innerHeight || d.documentElement.clientHeight;
    for (var i = 0; i < АКТЫ.length; i++) {
      var a = АКТЫ[i];
      var к = a.узел.getBoundingClientRect();
      var ход = ходАкта(к.height, вы);
      a.цельСырая = зажать(-к.top / ход);
      /* Высота акта в экранах: поводок у igloo измеряется в них. */
      a.экранов = Math.max(0.5, ход / Math.max(1, вы));
      /* ПОДХОД И УХОД: где акт находится ОТНОСИТЕЛЬНО ЭКРАНА, а не
         внутри своего хода.

         Ход акта начинается только когда его кадр прилип к верху, то
         есть когда верх секции дошёл до нуля. До этого доля равна нулю
         ровно, и весь экран прокрутки, за который акт подъезжает
         снизу, текст стоял невидимым - при том что кадр в это время
         УЖЕ на экране. То же на выходе: кадр отлипает и уезжает вверх
         ещё экран, а доля к этому времени давно единица.

         Семь границ по два таких промежутка и дали то, что владелец
         увидел как «между блоками постоянно чёрный экран, и он очень
         долго идёт». Сцена в эти секунды рисует пустой космос, а
         сказать ей нечего: слов нет.

         Подход: ноль, когда верх секции у нижней кромки экрана,
         единица - когда дошёл до верхней. Уход: единица, пока низ
         секции у нижней кромки, ноль - когда низ дошёл до верхней. По
         ним вёрстка выводит текст ЗАРАНЕЕ и убирает ПОЗЖЕ, и на
         границе два соседних акта перекрываются, а не гаснут оба. */
      a.подход = зажать((вы - к.top) / вы);
      a.уход = зажать(к.bottom / вы);
    }
  }

  /* ДВЕ подтяжки подряд, а не одна.

     Одна подтяжка это чистая экспонента: наибольшая скорость у неё в
     первый же кадр после того, как цель сдвинулась, а дальше только
     спад. Глаз читает такой старт щелчком - движение возникает сразу
     на полном ходу и потом дотягивается. Две подтяжки подряд дают
     s-образную кривую с НУЛЕВОЙ производной в начале: величина трогается
     с места, разгоняется и тормозит. Это и есть та масса, которой
     движению не хватало.

     Промежуточная величина у акта своя (сыр), наружу по-прежнему уходит
     одна доля. */
  function шаг(dt) {
    var шевелится = false;
    var сгл1 = подтяжка(СГЛ1, dt);
    var сгл2 = подтяжка(СГЛ2, dt);
    var раз60 = Math.min(4, Math.max(0.05, dt * 60));
    for (var i = 0; i < АКТЫ.length; i++) {
      var a = АКТЫ[i];
      var экр = a.экранов || 1;
      /* ── ПОВОДОК ──────────────────────────────────────────────
         Цель не имеет права убежать от показанного места дальше чем на
         их полэкрана. Рывок пальцем на десять экранов вниз двигает
         родную прокрутку мгновенно, но акт узнаёт о ней порциями, и
         камера идёт своим ходом, а не телепортируется. */
      var поводок = ПОВОДОК_ЭКРАНОВ / экр;
      var цс = a.цельСырая == null ? a.цель : a.цельСырая;
      a.цель = цс < a.д - поводок ? a.д - поводок : (цс > a.д + поводок ? a.д + поводок : цс);
      var раз = a.цель - a.д;
      /* Их защёлка: у самой цели величина садится на неё ровно, иначе
         экспонента вечно ползёт последними тысячными и не даёт циклу
         остановиться. */
      if (Math.abs(цс - a.д) < 0.0004 && Math.abs(цс - a.сыр) < 0.0004) {
        if (a.д !== цс) { a.сыр = цс; a.д = цс; шевелится = true; }
      } else {
        /* Первая подтяжка ещё и ОГРАНИЧЕНА ПО ШАГУ: у них
           lerpFPSLimited со шагом 0.075 экрана за кадр при шестидесяти
           герцах. Это второй поводок, уже на скорость. */
        var предел = (ШАГ_ЭКРАНОВ / экр) * раз60;
        var шагСыр = (a.цель - a.сыр) * сгл1;
        if (шагСыр > предел) шагСыр = предел;
        else if (шагСыр < -предел) шагСыр = -предел;
        a.сыр += шагСыр;
        a.д += (a.сыр - a.д) * сгл2;
        шевелится = true;
      }
      a.узел.style.setProperty("--д", a.д.toFixed(4));
      /* Пишем только при заметной разнице: это две лишние записи стиля
         на акт на кадр, и на восьми актах они складываются. */
      var п = a.подход.toFixed(3), у = a.уход.toFixed(3);
      if (п !== a.пБыло) { a.узел.style.setProperty("--подход", п); a.пБыло = п; }
      if (у !== a.уБыло) { a.узел.style.setProperty("--уход", у); a.уБыло = у; }
      /* Фаза акта: начало, середина, конец. Нужна там, где по доле
         недостаточно ОТТЕНКА, а нужно ПЕРЕКЛЮЧЕНИЕ - например убрать
         блок из-под пальца, а не только притушить его. Прозрачностью
         этого не сделать: невидимый блок продолжает ловить касания, и
         человек жмёт в пустоту.

         Три ступени, а не больше: чем их больше, тем чаще меняется
         разметка, а каждая смена стоит браузеру пересчёта. */
      var ф = a.д < 0.34 ? "0" : (a.д < 0.67 ? "1" : "2");
      if (a.фаза !== ф) {
        a.фаза = ф;
        a.узел.setAttribute("data-фаза", ф);
      }
      var п = подписки[a.имя];
      if (п) for (var j = 0; j < п.length; j++) {
        try { п[j](a.д, a); } catch (e) {}
      }
    }
    if (шевелится) g.requestAnimationFrame(тик);
    else { идёт = false; прошлыйТик = 0; }
  }

  /* Время прошлого кадра. Обнуляется на остановке цикла: между
     остановкой и следующим толчком проходит сколько угодно, и считать
     этот промежуток кадром значит один раз прыгнуть. */
  var прошлыйТик = 0;
  function тик(ts) {
    var t = ts || 0;
    var dt = (прошлыйТик && t > прошлыйТик) ? (t - прошлыйТик) / 1000 : 1 / 60;
    прошлыйТик = t;
    var y = g.scrollY || g.pageYOffset || 0;
    if (y !== последнееY) { последнееY = y; пересчитать(); }
    шаг(dt);
  }

  function толкнуть() {
    if (идёт) return;
    идёт = true;
    g.requestAnimationFrame(тик);
  }

  /* Пересборка по изменению размера идёт через кадр, а не сразу: на
     телефоне поворот экрана присылает несколько событий подряд, и
     считать по каждому значит считать впустую. */
  var ждёмРазмер = 0;
  function поРазмеру() {
    if (ждёмРазмер) return;
    ждёмРазмер = 1;
    g.requestAnimationFrame(function () {
      ждёмРазмер = 0;
      собрать(); пересчитать();
      /* Размер меняет положение всех актов сразу, поэтому мягкость тут
         не нужна: подтягиваем показанное к цели одним махом, иначе
         после поворота экрана сцена доезжает на глазах. */
      for (var i = 0; i < АКТЫ.length; i++) АКТЫ[i].сыр = АКТЫ[i].д = АКТЫ[i].цель;
      толкнуть();
    });
  }

  g.RV_MOTION = {
    /* Подписка объёмной сцены на свой акт. Возвращает отписку: сцену
       могут снести при переходе на слабую ступень качества, и она
       обязана уметь отцепиться. */
    "слушать": function (имя, дело) {
      if (!подписки[имя]) подписки[имя] = [];
      подписки[имя].push(дело);
      return function () {
        var п = подписки[имя], k = п.indexOf(дело);
        if (k >= 0) п.splice(k, 1);
      };
    },
    "доля": function (имя) {
      for (var i = 0; i < АКТЫ.length; i++) if (АКТЫ[i].имя === имя) return АКТЫ[i].д;
      return 0;
    },
    /* Довести человека до нужного акта без прокрутки на глазах. Нужно
       для прихода из космоса Rocket CDN: он должен оказаться сразу в
       акте выхода, а не на первом экране. */
    "кПунктy": function (имя, доля) {
      for (var i = 0; i < АКТЫ.length; i++) {
        if (АКТЫ[i].имя !== имя) continue;
        var к = АКТЫ[i].узел.getBoundingClientRect();
        var вы = g.innerHeight || 800;
        var ход = ходАкта(к.height, вы);
        var y = (g.scrollY || 0) + к.top + ход * зажать(доля == null ? 0 : доля);
        g.scrollTo(0, Math.round(y));
        собрать(); пересчитать();
        /* ── ПРЫЖОК САДИТСЯ НА СЫРУЮ ЦЕЛЬ, А НЕ НА ПРЕЖНЮЮ ────────
           Здесь стояло `сыр = д = цель`, и это снимало сглаживание, но
           не сам прыжок: `цель` считает шаг цикла, притягивая её к
           `цельСырая` не быстрее поводка, а `пересчитать` обновляет
           только `цельСырая`. Прыжок садился на ЦЕЛЬ ПРЕДЫДУЩЕГО КАДРА,
           то есть на то место, откуда прыгали, и дальше акт полз к
           новому месту поводком по полэкрана за кадр.

           На живой машине это доли секунды и глазом не ловится. На
           замерах видно в упор: приход из космоса Rocket CDN должен
           открывать нужный акт, а открывал прежний, и шахта в проколе
           стояла погашенной, потому что модуль получал долю 0.14 вместо
           0.70 - при том что камера мира, чистая функция прокрутки,
           давно стояла на месте. */
        for (var j = 0; j < АКТЫ.length; j++) {
          var а = АКТЫ[j];
          if (а.цельСырая != null) а.цель = а.цельСырая;
          а.сыр = а.д = а.цель;
        }
        /* И камеру тоже сажаем на место. У неё своё сглаживание по
           числам igloo (rv-world.js, вестиПрокрутку), и без защёлки
           прыжок в акт превращался бы в проезд к нему на глазах: замер
           снимал бы кадр по дороге, а приход из космоса Rocket CDN
           открывал бы человеку не свою точку, а путь к ней. */
        try {
          if (g.RV_WORLD && g.RV_WORLD["прокруткуНаМесто"]) g.RV_WORLD["прокруткуНаМесто"]();
        } catch (eП) {}
        толкнуть();
        return true;
      }
      return false;
    },
    "обновить": поРазмеру
  };

  function старт() {
    /* Признак «плёнка идёт». Вёрстка вешает на него ЕДИНЫЙ закон
       появления текста: слой акта проявляется в начале хода и уходит в
       конце, и это один закон на все семь актов.

       Признак нужен затем, что закон опирается на переменную --д,
       которую ставит этот файл. Не доехал файл, отключён скрипт,
       упала сборка - и без признака весь текст сайта остался бы
       невидимым. С признаком в этом случае просто нет анимации, а
       текст на месте. */
    d.documentElement.classList.add("rv-плёнка-идёт");
    собрать(); пересчитать();
    for (var i = 0; i < АКТЫ.length; i++) АКТЫ[i].сыр = АКТЫ[i].д = АКТЫ[i].цель;
    толкнуть();
    /* «Человек тронул ленту». Нужен ровно одному месту - приглашению
       листать на первом экране, - но ставится здесь, потому что здесь
       уже слушают прокрутку, и второй слушатель на то же событие был бы
       лишней работой на каждом кадре ленты.

       Порог в четыре точки, а не ноль: телефон отдаёт крошечные сдвиги
       прокрутки от касания, которое человек прокруткой не считал. */
    var тронул = function () {
      if ((g.scrollY || g.pageYOffset || 0) < 4) return;
      d.documentElement.classList.add("rv-тронул");
      g.removeEventListener("scroll", тронул);
    };
    g.addEventListener("scroll", тронул, { passive: true });
    g.addEventListener("scroll", толкнуть, { passive: true });
    g.addEventListener("resize", поРазмеру);
    /* Появление и скрытие адресной строки на телефоне меняет высоту
       окна без события resize в части браузеров. Ловим отдельно. */
    if (g.visualViewport) g.visualViewport.addEventListener("resize", поРазмеру);
  }

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", старт);
  else старт();
})(window, document);
