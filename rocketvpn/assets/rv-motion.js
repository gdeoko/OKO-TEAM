/* Rocket VPN. Плёнка: прокрутка превращается в долю внутри каждого акта.

   Почему не «анимации по появлению в окне». Сайт задуман как единая
   лента, где кадр в любой момент однозначно считается из положения
   прокрутки. Появление в окне даёт события, а нужна ВЕЛИЧИНА: сцены
   должны уметь отмотаться назад ровно так же, как шли вперёд, иначе
   человек, крутящий вверх, видит не обратный ход, а сбой.

   Величина у каждого акта своя и лежит в 0..1. Наружу она уходит двумя
   путями: переменной оформления --д на самом акте (это нужно вёрстке) и
   вызовом подписчика (это нужно объёмным сценам). Один источник, два
   потребителя, никакой второй математики. */
(function (g, d) {
  "use strict";

  var АКТЫ = [];
  var подписки = {};
  var идёт = false;
  var последнееY = -1;

  /* Мягкость. Сырая доля прокрутки на телефоне идёт ступенями (браузер
     отдаёт её не каждый кадр), и сцена от этого дёргается. Подтягиваем
     показанную величину к сырой, а не показываем сырую. */
  var МЯГКОСТЬ = 0.18;

  function зажать(v) { return v < 0 ? 0 : (v > 1 ? 1 : v); }

  /* Ход акта - это отрезок прокрутки, на котором доля идёт от нуля до
     единицы: высота акта минус экран, пока кадр липнет к окну.

     Нижний предел не единица, а больше половины экрана. С единицей
     короткий акт получал ДВОИЧНУЮ долю: она прыгала с нуля на единицу
     за один пиксель прокрутки, объёмная сцена не успевала ожить и сразу
     считалась кончившейся. Это случается не в теории: ровно так ведут
     себя ВСЕ акты при просьбе убрать движение, где высота акта
     становится своей собственной.

     Функция одна на весь файл намеренно. Формула стояла в двух местах,
     и они уже разошлись: пересчёт кадра считал по одной, а переход к
     акту по другой, и приход из космоса вставал не туда, куда
     показывала доля. */
  function ходАкта(высотаАкта, высотаОкна) {
    return Math.max(высотаОкна * 0.6, высотаАкта - высотаОкна);
  }

  function собрать() {
    АКТЫ.length = 0;
    var узлы = d.querySelectorAll(".rv-акт");
    for (var i = 0; i < узлы.length; i++) {
      var э = узлы[i];
      АКТЫ.push({
        узел: э,
        имя: э.getAttribute("data-акт") || ("акт" + i),
        д: 0, цель: 0
      });
    }
  }

  function пересчитать() {
    var вы = g.innerHeight || d.documentElement.clientHeight;
    for (var i = 0; i < АКТЫ.length; i++) {
      var a = АКТЫ[i];
      var к = a.узел.getBoundingClientRect();
      var ход = ходАкта(к.height, вы);
      a.цель = зажать(-к.top / ход);
    }
  }

  function шаг() {
    var шевелится = false;
    for (var i = 0; i < АКТЫ.length; i++) {
      var a = АКТЫ[i];
      var раз = a.цель - a.д;
      if (Math.abs(раз) < 0.0005) {
        if (a.д !== a.цель) { a.д = a.цель; шевелится = true; }
      } else {
        a.д += раз * МЯГКОСТЬ;
        шевелится = true;
      }
      a.узел.style.setProperty("--д", a.д.toFixed(4));
      var п = подписки[a.имя];
      if (п) for (var j = 0; j < п.length; j++) {
        try { п[j](a.д, a); } catch (e) {}
      }
    }
    if (шевелится) g.requestAnimationFrame(тик);
    else идёт = false;
  }

  function тик() {
    var y = g.scrollY || g.pageYOffset || 0;
    if (y !== последнееY) { последнееY = y; пересчитать(); }
    шаг();
  }

  function толкнуть() {
    if (идёт) return;
    идёт = true;
    g.requestAnimationFrame(тик);
  }

  /* Пересборка по изменению размера идёт через кадр, а не сразу: на
     телефоне поворот экрана присылает несколько событий подряд, и
     считать по каждому значит считать впустую. */
  var ждёмРазмер = 0;
  function поРазмеру() {
    if (ждёмРазмер) return;
    ждёмРазмер = 1;
    g.requestAnimationFrame(function () {
      ждёмРазмер = 0;
      собрать(); пересчитать();
      /* Размер меняет положение всех актов сразу, поэтому мягкость тут
         не нужна: подтягиваем показанное к цели одним махом, иначе
         после поворота экрана сцена доезжает на глазах. */
      for (var i = 0; i < АКТЫ.length; i++) АКТЫ[i].д = АКТЫ[i].цель;
      толкнуть();
    });
  }

  g.RV_MOTION = {
    /* Подписка объёмной сцены на свой акт. Возвращает отписку: сцену
       могут снести при переходе на слабую ступень качества, и она
       обязана уметь отцепиться. */
    "слушать": function (имя, дело) {
      if (!подписки[имя]) подписки[имя] = [];
      подписки[имя].push(дело);
      return function () {
        var п = подписки[имя], k = п.indexOf(дело);
        if (k >= 0) п.splice(k, 1);
      };
    },
    "доля": function (имя) {
      for (var i = 0; i < АКТЫ.length; i++) if (АКТЫ[i].имя === имя) return АКТЫ[i].д;
      return 0;
    },
    /* Довести человека до нужного акта без прокрутки на глазах. Нужно
       для прихода из космоса Rocket CDN: он должен оказаться сразу в
       акте выхода, а не на первом экране. */
    "кПунктy": function (имя, доля) {
      for (var i = 0; i < АКТЫ.length; i++) {
        if (АКТЫ[i].имя !== имя) continue;
        var к = АКТЫ[i].узел.getBoundingClientRect();
        var вы = g.innerHeight || 800;
        var ход = ходАкта(к.height, вы);
        var y = (g.scrollY || 0) + к.top + ход * зажать(доля == null ? 0 : доля);
        g.scrollTo(0, Math.round(y));
        собрать(); пересчитать();
        for (var j = 0; j < АКТЫ.length; j++) АКТЫ[j].д = АКТЫ[j].цель;
        толкнуть();
        return true;
      }
      return false;
    },
    "обновить": поРазмеру
  };

  function старт() {
    собрать(); пересчитать();
    for (var i = 0; i < АКТЫ.length; i++) АКТЫ[i].д = АКТЫ[i].цель;
    толкнуть();
    g.addEventListener("scroll", толкнуть, { passive: true });
    g.addEventListener("resize", поРазмеру);
    /* Появление и скрытие адресной строки на телефоне меняет высоту
       окна без события resize в части браузеров. Ловим отдельно. */
    if (g.visualViewport) g.visualViewport.addEventListener("resize", поРазмеру);
  }

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", старт);
  else старт();
})(window, document);
