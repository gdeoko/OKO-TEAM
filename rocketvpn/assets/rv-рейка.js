/* Rocket VPN. Рейка ленты: где человек стоит и куда может прыгнуть.

   БЕДА. Лента шестнадцать экранов и ни одного указателя положения.
   Человек, попавший в середину, не знает ни сколько прошёл, ни сколько
   осталось, ни как вернуться к ценам, которые видел минуту назад. У
   обычного сайта эту работу делает меню; здесь меню было бы враньём -
   акты не страницы, между ними нельзя прыгать без хода камеры.

   ЧТО ДЕЛАЕМ. Тонкая рейка у правой кромки: по метке на акт. Метка
   пройденного акта залита, текущего - горит и подписана, будущего -
   пуста. Щелчок ведёт к акту ПРОКРУТКОЙ, а не прыжком: мир едет
   камерой, и прыжок по якорю оборвал бы ленту склейкой.

   ПОЧЕМУ СПРАВА И ТОНКОЙ. Слова живут слева, мир справа, и толстая
   рейка отняла бы у мира полосу. Восемь точек ширины хватает, чтобы
   рейку заметили, и мало, чтобы она мешала.

   ПОЧЕМУ НЕ НА ТЕЛЕФОНЕ. Там кадр и так узкий, палец и так ходит по
   краю экрана, а вертикальная полоска у кромки на телефоне читается
   как полоса прокрутки и провоцирует тянуть её. Вместо рейки телефон
   получает ту же величину другой формой - тонкую нить сверху.
   ═══════════════════════════════════════════════════════════ */
(function (g, d) {
  "use strict";

  var АКТЫ = [];
  var рейка = null, нить = null;
  var текущий = -1;

  function собрать() {
    var узлы = d.querySelectorAll(".rv-акт[data-акт]");
    if (узлы.length < 2) return;

    рейка = d.createElement("nav");
    рейка.className = "rv-рейка";
    рейка.setAttribute("aria-label", "Ход ленты");

    for (var i = 0; i < узлы.length; i++) {
      var имя = узлы[i].getAttribute("data-акт") || ("акт" + i);
      /* Подпись берём из слейта того же акта: он уже написан, и второй
         список имён неминуемо разошёлся бы с первым. */
      var слейт = узлы[i].querySelector(".rv-над span");
      var подпись = слейт ? (слейт.textContent || "").trim() : имя;

      var б = d.createElement("button");
      б.type = "button";
      б.className = "rv-рейка-метка";
      б.setAttribute("data-акт", имя);
      б.setAttribute("aria-label", "Акт " + (i + 1) + ": " + подпись);
      б.innerHTML = '<i></i><em>' + подпись + '</em>';
      (function (имя) {
        б.addEventListener("click", function () { кАкту(имя); });
      })(имя);
      рейка.appendChild(б);
      АКТЫ.push({ имя: имя, узел: узлы[i], метка: б });
    }
    d.body.appendChild(рейка);

    /* Нить телефона: та же величина, другой формой. */
    нить = d.createElement("div");
    нить.className = "rv-нить";
    нить.setAttribute("aria-hidden", "true");
    нить.innerHTML = '<i></i>';
    d.body.appendChild(нить);

    подписаться();
    g.addEventListener("scroll", вести, { passive: true });
    вести();
  }

  /* Ход по всей ленте: доля прокрутки документа. Считается от документа,
     а не от суммы актов: в ленте есть подвал, и он тоже часть пути. */
  function долиЛенты() {
    var в = g.innerHeight || 800;
    var всего = (d.documentElement.scrollHeight || 0) - в;
    if (всего <= 0) return 0;
    return Math.min(1, Math.max(0, (g.scrollY || g.pageYOffset || 0) / всего));
  }

  var ждём = 0;
  function вести() {
    if (ждём) return;
    ждём = 1;
    g.requestAnimationFrame(function () {
      ждём = 0;
      var д = долиЛенты();
      if (нить) нить.firstChild.style.transform = "scaleX(" + д.toFixed(4) + ")";

      /* Текущий акт - тот, чья середина ближе всего к середине окна.
         Не «первый пересёкший верх»: акты разной высоты, и первый
         пересёкший держался бы в подсветке весь свой длинный ход, пока
         человек смотрит уже на следующий. */
      var в = g.innerHeight || 800;
      var лучший = -1, ближе = Infinity;
      for (var i = 0; i < АКТЫ.length; i++) {
        var к = АКТЫ[i].узел.getBoundingClientRect();
        if (к.bottom < 0 || к.top > в) continue;
        var р = Math.abs((к.top + к.bottom) / 2 - в / 2);
        if (р < ближе) { ближе = р; лучший = i; }
      }
      if (лучший < 0 || лучший === текущий) return;
      текущий = лучший;
      for (var j = 0; j < АКТЫ.length; j++) {
        var м = АКТЫ[j].метка;
        м.classList.toggle("rv-идёт", j === лучший);
        м.classList.toggle("rv-пройден", j < лучший);
        м.setAttribute("aria-current", j === лучший ? "true" : "false");
      }
    });
  }

  /* Ход к акту прокруткой. Не якорем: мир едет камерой по положению
     прокрутки, и мгновенный прыжок оборвал бы ленту склейкой. Плавная
     прокрутка отдаёт ядру те же промежуточные положения, что и палец. */
  function кАкту(имя) {
    for (var i = 0; i < АКТЫ.length; i++) {
      if (АКТЫ[i].имя !== имя) continue;
      var к = АКТЫ[i].узел.getBoundingClientRect();
      var y = (g.scrollY || g.pageYOffset || 0) + к.top + 4;
      /* Уважаем просьбу убрать движение: там плавный ход это то самое
         движение, от которого человек попросил избавить. */
      var тихо = g.matchMedia && g.matchMedia("(prefers-reduced-motion: reduce)").matches;
      try {
        g.scrollTo({ top: Math.round(y), behavior: тихо ? "auto" : "smooth" });
      } catch (e) {
        g.scrollTo(0, Math.round(y));
      }
      return true;
    }
    return false;
  }

  /* Подсветка идёт и от плёнки тоже: она знает долю точнее прокрутки,
     потому что сглаживает её. Если плёнки нет, работает одна прокрутка -
     рейка обязана жить и без объёмного слоя. */
  function подписаться() {
    if (!g.RV_MOTION || !g.RV_MOTION["слушать"]) return;
    for (var i = 0; i < АКТЫ.length; i++) {
      (function (а) {
        g.RV_MOTION["слушать"](а.имя, function (д) {
          а.метка.style.setProperty("--ход", д.toFixed(3));
        });
      })(АКТЫ[i]);
    }
  }

  g.RV_РЕЙКА = { "кАкту": кАкту, "текущий": function () { return текущий; } };

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", собрать);
  else собрать();
})(window, document);
