/* Rocket VPN. Глыба льда с иконкой внутри и выноской сбоку.

   ЗАЧЕМ ОНА ЕСТЬ. Сценарий владельца дословно: «можно и не карточки,
   можно придумать что-то поинтереснее, как у igloo сделать глыбы льда,
   которые влетают в стену, разбивая часть кирпичей, и втыкаются в неё, а
   текст как будто внутри глыбы... взять именно такие же формы льда, как
   у них, сделать разные формы, внутри льда у нас крутые 3D иконки... от
   самой глыбы посмотри, как сделано у igloo: у них там какие-то линии,
   стрелочки и текст, типа описание, сделано очень круто».

   ЧТО ЗДЕСЬ. Одна глыба это:
     · корпус - гранёный кристалл, у каждой глыбы своя форма;
     · иконка внутри - объёмный знак, светящийся сквозь лёд;
     · выноска - тонкая линия с изломом, засечка на конце и две подписи,
       как на их снимках («PORTFOLIO_CO_01 / PUDGY PENGUINS» слева вверху,
       «TEMP 35.56» справа, «CLICK TO EXPLORE» справа внизу).

   ПОЧЕМУ ЛЁД СЧИТАЕТСЯ, А НЕ БЕРЁТСЯ КАРТИНКОЙ. Настоящее преломление
   (MeshPhysicalMaterial.transmission) требует снимка сцены за предметом
   каждый кадр, а глыб три и они летят. Здесь тот же вид собирается из
   трёх слагаемых, которые и делают лёд льдом на глаз: Френель по краю,
   мутная толща внутри и яркие рёбра граней. Иконка при этом остаётся
   ВИДНА - она рисуется раньше, а лёд идёт без записи в буфер глубины.

   ФОРМЫ ВЗЯТЫ С ИХ СНИМКОВ. Четыре штуки: острый кристалл, рубленый
   брусок, плоская плита и окатанный обломок. Каждая строится своим
   набором вершин с шумом по ним, нормали плоские - гранёный лёд ловит
   свет ребром, и без плоских нормалей он читается пластиком.

   API:
     RV_ГЛЫБА.собрать(мир, о) -> { корень, лёд, иконка, выноска, кадр(...) }
     RV_ГЛЫБА.формы() -> имена форм */
(function (g) {
  "use strict";

  var T = null;

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }

  /* ── Шейдер льда ───────────────────────────────────────────────
     Три слагаемых, каждое отвечает за своё.

     ФРЕНЕЛЬ. Поверхность, повёрнутая от глаза, отражает почти всё, и
     именно поэтому у настоящей льдины светится контур, а середина
     остаётся прозрачной. Без него глыба читается матовым камнем.

     ТОЛЩА. Мутный слой внутри: шум по координатам МЕСТА, а не экрана,
     поэтому муть живёт в теле глыбы и вращается вместе с ней. Ближе к
     краям она гуще - там луч идёт сквозь лёд по касательной и проходит
     больше пути.

     РЁБРА. Грань кристалла ловит свет полосой. Считается по тому,
     насколько нормаль грани смотрит в сторону света: у соседних граней
     нормали разные, и на стыке получается резкий перелом яркости. */
  var В_ЛЁД = [
    "varying vec3 vNor;",
    "varying vec3 vPos;",
    "varying vec3 vView;",
    "varying float vMvz;",
    "void main(){",
    "  vPos = position;",
    "  vNor = normalize(normalMatrix * normal);",
    "  vec4 mv = modelViewMatrix * vec4(position, 1.0);",
    "  vView = mv.xyz;",
    "  vMvz = mv.z;",
    "  gl_Position = projectionMatrix * mv;",
    "}"
  ].join("\n");

  var Ф_ЛЁД = [
    "uniform vec3 uIce;",
    "uniform vec3 uDeep;",
    "uniform vec3 uEdge;",
    "uniform float uTime;",
    "uniform float uOpacity;",
    "uniform float uHot;",
    "varying vec3 vNor;",
    "varying vec3 vPos;",
    "varying vec3 vView;",
    "varying float vMvz;",
    "float hash13(vec3 p){",
    "  p = fract(p * 0.1031);",
    "  p += dot(p, p.yzx + 33.33);",
    "  return fract((p.x + p.y) * p.z);",
    "}",
    "float noise3(vec3 p){",
    "  vec3 i = floor(p), f = fract(p);",
    "  f = f * f * (3.0 - 2.0 * f);",
    "  float n000 = hash13(i), n100 = hash13(i + vec3(1,0,0));",
    "  float n010 = hash13(i + vec3(0,1,0)), n110 = hash13(i + vec3(1,1,0));",
    "  float n001 = hash13(i + vec3(0,0,1)), n101 = hash13(i + vec3(1,0,1));",
    "  float n011 = hash13(i + vec3(0,1,1)), n111 = hash13(i + vec3(1,1,1));",
    "  return mix(mix(mix(n000,n100,f.x), mix(n010,n110,f.x), f.y),",
    "             mix(mix(n001,n101,f.x), mix(n011,n111,f.x), f.y), f.z);",
    "}",
    "void main(){",
    "  vec3 n = normalize(vNor);",
    "  vec3 V = normalize(-vView);",
    "  if (!gl_FrontFacing) n = -n;",
    "  float NdV = max(dot(n, V), 0.0);",
    /* Френель по Шлику с показателем пять: контур загорается быстро, а
       середина остаётся почти чистой. */
    "  float fres = pow(1.0 - NdV, 5.0);",
    /* Толща: два масштаба шума, крупный даёт облака, мелкий - крупу
       пузырьков, какая и бывает в намёрзшем льду. */
    "  float mut = noise3(vPos * 2.6 + vec3(0.0, uTime * 0.05, 0.0)) * 0.65",
    "            + noise3(vPos * 7.4) * 0.35;",
    "  float tolshcha = mix(0.20, 1.0, 1.0 - NdV);",
    "  vec3 color = mix(uDeep, uIce, clamp(mut * 0.85 + 0.25, 0.0, 1.0));",
    "  color = mix(color, uIce, tolshcha * 0.55);",
    /* Рёбра. Свет стоит спереди-сверху, как во всей сцене. */
    "  vec3 L = normalize(vec3(-0.3, 0.72, 0.62));",
    "  float sol = max(dot(n, L), 0.0);",
    "  color += uEdge * pow(sol, 14.0) * 0.85;",
    "  color += uEdge * fres * 1.15;",
    /* Вспышка при ударе о стену и при наведении. */
    "  color += uEdge * uHot * 0.7;",
    /* Дальше от камеры лёд глуше: воздух подземелья не пустой. */
    "  float dal = 1.0 - smoothstep(26.0, 110.0, -vMvz);",
    "  color *= mix(0.55, 1.0, dal);",
    "  float a = clamp(0.30 + fres * 0.62 + tolshcha * 0.22, 0.0, 1.0) * uOpacity;",
    "  gl_FragColor = vec4(color, a);",
    "}"
  ].join("\n");

  /* ── Формы ─────────────────────────────────────────────────────
     Четыре силуэта с их снимков. Строятся из простой заготовки, по
     вершинам которой пущен шум: ровный многогранник читается кристаллом
     из учебника, а лёд всегда рваный.

     Шум детерминированный (семя от номера формы), иначе три глыбы на
     стене менялись бы при каждой перезагрузке, и снимок проверки
     никогда бы не совпал с прошлым. */
  var ФОРМЫ = ["кристалл", "брусок", "плита", "обломок"];

  function шумСемя(семя) {
    var s = семя * 9301 + 49297;
    return function () { s = (s * 9301 + 49297) % 233280; return s / 233280; };
  }

  function геометрия(форма, семя) {
    var гео;
    if (форма === "кристалл") {
      /* Острый кристалл: восьмигранная призма, вытянутая вверх, с
         сужением к обоим концам. Их первая глыба именно такая. */
      гео = new T.CylinderGeometry(0.62, 0.42, 1.85, 8, 3);
    } else if (форма === "брусок") {
      гео = new T.BoxGeometry(1.0, 1.45, 0.86, 2, 3, 2);
    } else if (форма === "плита") {
      гео = new T.BoxGeometry(1.55, 1.30, 0.52, 3, 3, 1);
    } else {
      гео = new T.IcosahedronGeometry(0.85, 1);
    }
    гео = гео.toNonIndexed ? гео.toNonIndexed() : гео;
    var п = гео.attributes.position;
    var сл = шумСемя(семя);
    /* Шум кладётся по КЛЮЧУ ВЕРШИНЫ, а не по её номеру: у неиндексной
       сетки одна и та же точка встречается в нескольких треугольниках, и
       разный сдвиг порвал бы грань на части. */
    var карта = {};
    for (var i = 0; i < п.count; i++) {
      var x = п.getX(i), y = п.getY(i), z = п.getZ(i);
      var кл = Math.round(x * 1e3) + "_" + Math.round(y * 1e3) + "_" + Math.round(z * 1e3);
      if (!карта[кл]) {
        карта[кл] = [
          (сл() - 0.5) * 0.30, (сл() - 0.5) * 0.26, (сл() - 0.5) * 0.30
        ];
      }
      var д = карта[кл];
      п.setXYZ(i, x + д[0], y + д[1], z + д[2]);
    }
    п.needsUpdate = true;
    /* Плоские нормали: гранёный лёд ловит свет ребром. Сглаженные
       нормали дали бы мыло, в котором ни одной грани не видно. */
    гео.computeVertexNormals();
    гео.computeBoundingSphere();
    return гео;
  }

  /* ── Иконки внутри льда ────────────────────────────────────────
     Владелец: «внутри льда находится иконка какая-то или логотип, на
     всех трёх разный... нужно подумать, какие будут иконки, связанные с
     VPN».

     Три знака про то, что делает сервис, собранные из примитивов - без
     файлов, чтобы не тянуть модели по сети ради предмета размером с
     ноготь:
       щит    - трафик закрыт;
       шар    - выход в любой стране;
       молния - канал не проседает по скорости.
     Четвёртый, ключ, остаётся про доступ туда, куда не пускают. */
  function иконка(вид, цвет) {
    var гр = new T.Group();
    гр.name = "иконка: " + вид;
    var мат = new T.MeshStandardMaterial({
      color: цвет, roughness: 0.32, metalness: 0.55,
      emissive: new T.Color(цвет).multiplyScalar(0.35)
    });
    function часть(гео, x, y, z, rx, ry, rz, s) {
      var м = new T.Mesh(гео, мат);
      м.position.set(x || 0, y || 0, z || 0);
      м.rotation.set(rx || 0, ry || 0, rz || 0);
      if (s) м.scale.setScalar(s);
      гр.add(м);
      return м;
    }
    if (вид === "щит") {
      /* Щит: пятиугольная пластина со скруглённым верхом. Собирается из
         цилиндра на пять граней, сплюснутого по глубине. */
      var щ = часть(new T.CylinderGeometry(0.5, 0.0, 0.9, 5, 1), 0, -0.05, 0, Math.PI, 0, 0);
      щ.scale.set(1, 1, 0.34);
      часть(new T.CylinderGeometry(0.5, 0.5, 0.34, 5, 1), 0, 0.28, 0, 0, 0, 0).scale.set(1, 1, 0.34);
    } else if (вид === "шар") {
      часть(new T.SphereGeometry(0.44, 18, 12));
      /* Меридианы и экватор: без них шар это просто шар, а нужен глобус. */
      for (var м = 0; м < 3; м++) {
        часть(new T.TorusGeometry(0.45, 0.028, 8, 32), 0, 0, 0, Math.PI / 2, м * Math.PI / 3, 0);
      }
      часть(new T.TorusGeometry(0.45, 0.028, 8, 32), 0, 0, 0, 0, 0, 0);
    } else if (вид === "молния") {
      /* Молния: три бруска зигзагом. Настоящий знак молнии рисуется
         многоугольником, но в объёме зигзаг из брусков читается лучше -
         у него есть толщина и он ловит свет гранями. */
      часть(new T.BoxGeometry(0.20, 0.52, 0.16), 0.10, 0.26, 0, 0, 0, 0.42);
      часть(new T.BoxGeometry(0.42, 0.16, 0.16), -0.02, 0.02, 0, 0, 0, 0.10);
      часть(new T.BoxGeometry(0.20, 0.52, 0.16), -0.10, -0.26, 0, 0, 0, 0.42);
    } else {
      /* Ключ: кольцо и бородка. */
      часть(new T.TorusGeometry(0.26, 0.08, 10, 24), 0, 0.28, 0, 0, 0, 0);
      часть(new T.BoxGeometry(0.11, 0.60, 0.11), 0, -0.16, 0);
      часть(new T.BoxGeometry(0.26, 0.10, 0.10), 0.10, -0.34, 0);
      часть(new T.BoxGeometry(0.20, 0.10, 0.10), 0.07, -0.50, 0);
    }
    /* Иконка рисуется РАНЬШЕ льда и пишет глубину, лёд идёт после и
       глубину не пишет: тогда знак виден сквозь толщу, а не срезается
       ею. */
    гр.traverse(function (о) { if (о.isMesh) { о.renderOrder = 4; о.frustumCulled = false; } });
    return гр;
  }

  /* ── Выноска ───────────────────────────────────────────────────
     У igloo от каждой глыбы идут две выноски: слева вверху шифр и имя,
     справа внизу дата и «CLICK TO EXPLORE», плюс отдельно справа вверху
     температура. Линия тонкая, с одним изломом, и упирается в глыбу
     тремя тонкими лучами, как ножки циркуля.

     Здесь то же самое: полка, наклонный поводок и лучи. Текст ставит
     тот, кто зовёт (ему виднее, что писать), здесь только линии. */
  function выноска(сторона, длина, спуск) {
    var гр = new T.Group();
    гр.name = "выноска";
    var зн = сторона < 0 ? -1 : 1;
    var мат = new T.LineBasicMaterial({
      color: 0xE8F0FF, transparent: true, opacity: 0.85, depthWrite: false
    });
    function линия(точки) {
      var гео = new T.BufferGeometry().setFromPoints(точки.map(function (т) {
        return new T.Vector3(т[0], т[1], т[2] || 0);
      }));
      var л = new T.Line(гео, мат);
      л.renderOrder = 12;
      л.frustumCulled = false;
      гр.add(л);
      return л;
    }
    /* Полка с изломом: горизонталь под подпись, потом наклон к предмету. */
    линия([[0, 0], [зн * длина * 0.62, 0], [зн * длина, -спуск]]);
    /* Три луча в тело глыбы: они и делают выноску приборной, а не
       подписью в рамке. */
    for (var i = 0; i < 3; i++) {
      var р = 0.34 + i * 0.30;
      линия([[зн * длина, -спуск], [зн * (длина + р * 0.9), -спуск - р * 0.55]]);
    }
    гр.userData["конец"] = [зн * длина, -спуск, 0];
    гр.userData["мат"] = мат;
    return гр;
  }

  function собрать(мир, о) {
    if (!мир || !мир.T) return null;
    T = мир.T;
    о = о || {};
    var форма = о["форма"] || ФОРМЫ[0];
    var семя = о["семя"] == null ? 17 : о["семя"];
    var размер = о["размер"] || 1;

    var корень = new T.Group();
    корень.name = "глыба: " + форма;

    var мат = new T.ShaderMaterial({
      uniforms: {
        /* Палитра льда взята у их снимка: тело светло-голубое, толща
           уходит в серо-синее, рёбра почти белые. */
        uIce: { value: new T.Color(о["цвет"] || 0xCFE0F2) },
        uDeep: { value: new T.Color(о["цветТолщи"] || 0x53627D) },
        uEdge: { value: new T.Color(о["цветРёбер"] || 0xEAF3FF) },
        uTime: { value: 0 },
        uOpacity: { value: 1 },
        uHot: { value: 0 }
      },
      vertexShader: В_ЛЁД, fragmentShader: Ф_ЛЁД,
      transparent: true, depthWrite: false, side: T.DoubleSide,
      fog: false
    });

    var лёд = new T.Mesh(геометрия(форма, семя), мат);
    лёд.name = "лёд: " + форма;
    лёд.renderOrder = 6;
    лёд.frustumCulled = false;
    лёд.scale.setScalar(размер);
    корень.add(лёд);

    var знак = null;
    if (о["иконка"]) {
      знак = иконка(о["иконка"], о["цветЗнака"] || 0x9CC8FF);
      знак.scale.setScalar(размер * (о["размерЗнака"] || 0.62));
      корень.add(знак);
    }

    var вын = null;
    if (о["выноска"]) {
      вын = выноска(о["сторона"] == null ? -1 : о["сторона"],
                    размер * (о["длинаВыноски"] || 1.6),
                    размер * (о["спускВыноски"] || 0.55));
      вын.position.set(0, размер * (о["верхВыноски"] || 0.75), размер * 0.2);
      корень.add(вын);
    }

    var М = {
      "корень": корень, "лёд": лёд, "иконка": знак, "выноска": вын,
      "мат": мат, "форма": форма,
      /* Часы, вспышка и медленное собственное вращение знака внутри.
         Знак крутится, лёд стоит: так видно, что он ВНУТРИ, а не
         нарисован на грани. */
      "кадр": function (dt, часы, горячо) {
        мат.uniforms.uTime.value = часы || 0;
        var ц = зажать(горячо == null ? 0 : горячо, 0, 1);
        var у = мат.uniforms.uHot;
        у.value += (ц - у.value) * зажать((dt || 0.016) * 6, 0, 1);
        if (знак) {
          знак.rotation.y += (dt || 0.016) * 0.55;
          знак.rotation.x = Math.sin((часы || 0) * 0.7) * 0.10;
        }
      },
      "прозрачность": function (v) { мат.uniforms.uOpacity.value = зажать(v, 0, 1); },
      "замер": function () {
        return {
          "форма": форма, "размер": размер,
          "иконка": о["иконка"] || null,
          "вершин": лёд.geometry.attributes.position.count,
          "видна": !!корень.visible
        };
      }
    };
    return М;
  }

  g.RV_ГЛЫБА = {
    "собрать": собрать,
    "формы": function () { return ФОРМЫ.slice(); }
  };
})(window);
