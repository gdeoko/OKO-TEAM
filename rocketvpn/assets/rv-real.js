/* Rocket VPN. Слой достоверности: свет и плёнка.

   ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ. Заказчик посмотрел собранный сайт и сказал:
   «сухо и не красиво, уступает CDN». Он прав, и причина нашлась не на
   глаз, а обходом кода: во ВСЕЙ сцене не было НИ ОДНОГО источника
   света, а все материалы были самосветящимися. Такая сцена физически не
   может дать объём: у неё нет ни теней, ни бликов, ни разницы между
   обращённой к свету стороной и обратной. Она читается чертежом.

   Второе: не было плёнки. Ни свечения, ни тональной кривой, ни
   виньетки. Яркая точка в такой сцене остаётся точкой, а в жизни она
   расплывается ореолом в оптике глаза и объектива - именно ореол делает
   светящееся СВЕТЯЩИМСЯ, а не просто светлым.

   ЧТО ЗДЕСЬ ЕСТЬ.
   · Световой стан: ключевой источник, заполняющий и контровой. Три
     источника, а не один: с одним сцена читается плоско освещённой, и
     объём не появляется даже при честных материалах.
   · Карта окружения, собранная процедурно из неба сцены. Она даёт
     отражения, без которых металл выглядит серой краской.
   · Плёнка: пирамида ореола, тональная кривая, виньетка, зерно.

   ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Тумана и глубины резкости. Оба съедают
   читаемость подписей, а на этом сайте подписи несут факты.

   Файл НЕ трогает акты и ничего в них не требует. Акт, который хочет
   объёма, просто берёт материал с откликом на свет; акт, которому нужен
   чертёж, оставляет самосветящийся. Оба живут в одной сцене. */
(function (g) {
  "use strict";

  var ВЕРШ = "varying vec2 vUv; void main(){ vUv = uv; gl_Position = vec4(position.xy, 0.0, 1.0); }";

  /* Выделение ярких мест. Порог мягкий, а не резкий: с резким по кромке
     светящегося тела идёт ступенька, и ореол выглядит наклейкой. */
  var ЯРКОЕ = [
    "precision highp float;",
    "varying vec2 vUv;",
    "uniform sampler2D tD;",
    "uniform float thr;",
    "uniform float soft;",
    "uniform float hicap;",
    "void main(){",
    "  vec3 c = texture2D(tD, vUv).rgb;",
    "  float l = dot(c, vec3(0.2126, 0.7152, 0.0722));",
    "  float k = smoothstep(thr, thr + soft, l);",
    /* Потолок нужен, чтобы одна пересвеченная точка не утащила весь
       ореол в белое: без него вспышка прокола заливала кадр. */
    "  c = min(c, vec3(hicap));",
    "  gl_FragColor = vec4(c * k, 1.0);",
    "}"
  ].join("\n");

  /* Размытие одной строкой отсчётов. Веса Гаусса зашиты числами: считать
     их в шейдере дороже, чем написать. */
  var РАЗМЫВ = [
    "precision highp float;",
    "varying vec2 vUv;",
    "uniform sampler2D tD;",
    "uniform vec2 dir;",
    "void main(){",
    "  vec3 s = texture2D(tD, vUv).rgb * 0.227027;",
    "  s += texture2D(tD, vUv + dir * 1.3846).rgb * 0.316216;",
    "  s += texture2D(tD, vUv - dir * 1.3846).rgb * 0.316216;",
    "  s += texture2D(tD, vUv + dir * 3.2308).rgb * 0.070270;",
    "  s += texture2D(tD, vUv - dir * 3.2308).rgb * 0.070270;",
    "  gl_FragColor = vec4(s, 1.0);",
    "}"
  ].join("\n");

  /* Сборка. Здесь же тональная кривая, виньетка и зерно: три полных
     прохода по кадру вместо одного стоили бы дороже всего остального
     вместе взятого. */
  var СБОРКА = [
    "precision highp float;",
    "varying vec2 vUv;",
    "uniform sampler2D tD;",
    "uniform sampler2D t1;",
    "uniform sampler2D t2;",
    "uniform sampler2D t3;",
    "uniform vec4 halo;",
    "uniform float glow;",
    "uniform float vig;",
    "uniform float grain;",
    "uniform float time;",
    "uniform float expo;",
    /* Пол плёнки. У настоящей плёнки есть базовая вуаль подложки: даже
       неэкспонированный кадр не пропускает свет полностью, и на экране
       его чернота это тёмный цвет, а не выключенный пиксель. Цифра тут
       не украшение: тональная кривая ниже усиливает низа всего в 0.21
       раза, и всё, что пришло в неё ниже 0.013, выходило на экран
       яркостью меньше 12 из 255 - ровно порог, по которому замер
       считает точку чисто чёрной. На ПК так уходило 55-62% точек кадра.
       Цвет пола индиговый, а не серый: подмес белого вернул бы тот
       пересвет, который с плёнки только что сняли, и обесцветил бы
       ночь. */
    "uniform vec3 pol;",
    "uniform vec2 px;",
    "uniform float ca;",
    "uniform float sharp;",
    "uniform float aa;",
    /* События кадра: скорость камеры (0..1), точка схода в долях кадра
       и толчок (0..1) от прокола, выбора станции, стыковки. В покое
       все три нули, и ветки ниже не стоят ни одной выборки. */
    "uniform float speed;",
    "uniform vec2 vpt;",
    "uniform float boost;",
    /* Чересстрочный градиентный шум вместо синуса от uv: у синуса
       видна решётка при увеличении, и он застывал при больших часах,
       когда точности числа переставало хватать на дробную часть. */
    "float ign(vec2 p){ return fract(52.9829189 * fract(0.06711056 * p.x + 0.00583715 * p.y)); }",
    "float luma(vec3 c){ return dot(c, vec3(0.299, 0.587, 0.114)); }",
    /* ── СГЛАЖИВАНИЕ ──────────────────────────────────────────────
       Кромка, набранная ступенями, это первое, по чему глаз отличает
       игрушку от съёмки. Встроенное сглаживание слоя включалось только
       на верхней ступени качества, то есть на телефоне мир стоял в
       лесенках всегда.

       Здесь честный краевой поиск: яркость в кресте вокруг точки,
       направление наибольшего перепада, подмешивание соседа ПОПЕРЁК
       него. Ровные места не трогаются вовсе, размешиваются только
       ступени на кромке. Четыре лишние выборки на точку - цена, за
       которую покупается весь вид.

       Имена внутри шейдера латиницей: кириллица в GLSL не имя, а
       ошибка разбора, и материал молча не собирается. */
    "vec3 sgladit(vec2 uv){",
    "  vec3 c = texture2D(tD, uv).rgb;",
    /* На нищей ступени сглаживание выключается ЦЕЛИКОМ, а не сходит на
       нет по силе: пять выборок текстуры на точку берутся до всякой
       проверки, и «сила ноль» их не экономит. Одна ветка по постоянной
       величине - и слабая машина не платит за них вовсе. */
    "  if (aa < 0.5) return c;",
    "  float lC = luma(c);",
    "  float lN = luma(texture2D(tD, uv + vec2(0.0, px.y)).rgb);",
    "  float lS = luma(texture2D(tD, uv - vec2(0.0, px.y)).rgb);",
    "  float lE = luma(texture2D(tD, uv + vec2(px.x, 0.0)).rgb);",
    "  float lW = luma(texture2D(tD, uv - vec2(px.x, 0.0)).rgb);",
    "  float mx = max(lC, max(max(lN, lS), max(lE, lW)));",
    "  float mn = min(lC, min(min(lN, lS), min(lE, lW)));",
    "  float kr = mx - mn;",
    "  if (kr < 0.045) return c;",
    "  vec2 d = normalize(vec2(abs(lE - lW) + 1e-5, abs(lN - lS) + 1e-5));",
    "  vec2 pop = vec2(-d.y, d.x) * px * 1.35;",
    "  vec3 a = texture2D(tD, uv + pop).rgb;",
    "  vec3 b = texture2D(tD, uv - pop).rgb;",
    "  float sila = clamp(kr * 3.4, 0.0, 1.0);",
    "  return mix(c, (a + b + c * 2.0) * 0.25, sila);",
    "}",
    "void main(){",
    /* ── ХРОМАТИЧЕСКАЯ АБЕРРАЦИЯ ─────────────────────────────────
       Настоящее стекло преломляет цвета чуть по-разному, и к краю кадра
       каналы расходятся. Величина крошечная - доли точки в середине и
       полторы у кромки, - но именно она отличает кадр, снятый оптикой,
       от кадра, посчитанного машиной. Расхождение растёт от центра
       квадратично, как у линзы, а не ровно по всему полю. */
    "  vec2 ot = vUv - 0.5;",
    "  float r2 = dot(ot, ot);",
    /* На скорости и при толчке каналы расходятся сильнее: линза на
       рывке «плывёт» ровно так, и это первое, что делает удар прокола
       ударом, а не сменой яркости. */
    "  float caK = ca + 0.010 * speed + 0.02 * boost;",
    "  vec2 sdv = ot * r2 * caK;",
    /* Сглаживание считается ОДИН раз, по зелёному каналу, а красный и
       синий берутся простой выборкой со сдвигом.

       Первый заход звал сглаживание трижды, по разу на канал: пятнадцать
       выборок текстуры на точку вместо семи, и проверка скорости честно
       поймала утяжеление ленты. Разница на глаз при этом нулевая: яркость
       кадра глаз собирает почти целиком из зелёного (три пятых по
       кривой видности), а расхождение каналов у кромки и так меряется
       долями точки - сглаживать то, что смещено на полторы точки и
       вдесятеро слабее по вкладу, значит платить за невидимое. */
    "  vec3 g = sgladit(vUv);",
    "  vec3 c = vec3(",
    "    texture2D(tD, vUv + sdv).r,",
    "    g.g,",
    "    texture2D(tD, vUv - sdv).b);",
    "  c = mix(c, g, 0.15);",
    /* Контурная резкость после сглаживания. Сглаживание неизбежно
       мягчит кадр целиком; малая добавка разницы с размытым возвращает
       материалу фактуру, не возвращая ступеней. */
    "  vec3 mjk = (texture2D(tD, vUv + vec2(px.x, 0.0)).rgb",
    "            + texture2D(tD, vUv - vec2(px.x, 0.0)).rgb",
    "            + texture2D(tD, vUv + vec2(0.0, px.y)).rgb",
    "            + texture2D(tD, vUv - vec2(0.0, px.y)).rgb) * 0.25;",
    "  c += (c - mjk) * sharp;",
    /* ── РАЗМЫТИЕ ПО СКОРОСТИ ────────────────────────────────────
       Пока камера летит, края кадра тянутся к точке схода: шесть
       выборок вдоль луча от неё, веса убывают. Ветка по униформе: в
       покое кадр чистый и не платит ни одной выборки. */
    "  if (speed > 0.02) {",
    "    vec2 dir = (vUv - vpt) * 0.006 * speed;",
    "    vec3 rz = texture2D(tD, vUv - dir).rgb",
    "            + texture2D(tD, vUv - dir * 2.0).rgb * 0.85",
    "            + texture2D(tD, vUv - dir * 3.0).rgb * 0.70",
    "            + texture2D(tD, vUv - dir * 4.0).rgb * 0.55",
    "            + texture2D(tD, vUv - dir * 5.0).rgb * 0.45",
    "            + texture2D(tD, vUv - dir * 6.0).rgb * 0.40;",
    "    c = mix(c, rz / 3.95, 0.7 * speed);",
    "  }",
    /* Нимб чуть теплее ядра: у настоящей оптики широкий ореол
       отдаёт в жёлтое, и без этого свечение читается неоновой краской. */
    "  vec3 h = texture2D(t1, vUv).rgb * halo.x",
    "         + texture2D(t2, vUv).rgb * halo.y",
    "         + texture2D(t3, vUv).rgb * halo.z * vec3(1.08, 0.98, 0.92);",
    "  c += h * glow;",
    /* Экспозиция ДО кривой, а не после. Кривая ниже сама по себе
       опускает середину (так она и задумана: чтобы яркое не слипалось
       в белое), и без поправки весь кадр уезжает в темноту. Замер
       первого захода: средняя яркость 1.93 из 255 при 31.4 у сцены
       без плёнки. */
    "  c *= expo * (1.0 + 0.45 * boost);",
    /* Тональная кривая. Плёночная, а не обрезание по единице: обрезание
       превращает всё яркое в одинаково белое, и вспышка теряет форму. */
    "  c = (c * (2.51 * c + 0.03)) / (c * (2.43 * c + 0.59) + 0.14);",
    /* Пол поднимается ПОСЛЕ кривой и так, что белое остаётся белым:
       единица переходит в единицу, а ноль в цвет вуали. Потолок не
       двигается вовсе, поэтому доля выбитых в белый точек от этого не
       растёт (замер: 0.02% на ПК до и после). Отдаёт эта правка тем
       кадрам, где темнота занимает площадь: прокол на исходе тоннеля
       поднялся с 29.6 до 47, а оболочка, где темноты почти нет, всего
       на девять единиц - разница между актами от этого сохраняется. */
    "  c = pol + (vec3(1.0) - pol) * c;",
    /* Виньетка. Слабая: сильная читается как дырка в объективе, а нужна
       лишь опора для взгляда в середине кадра. */
    "  float r = distance(vUv, vec2(0.5));",
    "  c *= 1.0 - vig * (1.0 + 0.6 * speed) * smoothstep(0.35, 0.95, r);",
    /* Перевод в sRGB. Сцена считается в линейном свете (цель HalfFloat),
       а экран ждёт sRGB. three сам переводит только при рисовании прямо
       на экран, в цель он пишет линейные числа, и плёнка отдавала их
       как есть. Тени от этого проваливались в чёрное, свет слипался,
       а экспозицию приходилось задирать до 1.85, чтобы кадр вообще
       читался. Кривая выше уже вернула кадр в 0..1, здесь ровно
       стандартная передаточная функция без выдумок. */
    "  c = clamp(c, 0.0, 1.0);",
    "  c = mix(12.92 * c, 1.055 * pow(c, vec3(1.0 / 2.4)) - 0.055, step(vec3(0.0031308), c));",
    /* Зерно. Без него ровные тёмные заливки идут ступенями: экран не
       умеет показать сотни оттенков почти чёрного, и переходы рвутся на
       полосы. Зерно эти полосы размешивает. Кладётся уже после перевода
       в sRGB: в линейном свете та же щепотка раздувалась кривой в грязь
       по теням и пропадала в светах. */
    /* Шум от координаты точки экрана, а не от uv: на uv зерно
       растягивалось с окном и «плыло» при повороте телефона. Сдвиг по
       часам через дробную часть: часы растут без предела, а дробь
       остаётся точной. Отдельная тысячная сверх художественного зерна
       это дизеринг против полос на тёмных заливках: на нищей ступени
       зерна нет, а полосы там есть. */
    "  float n = ign(gl_FragCoord.xy + vec2(fract(time * 0.37) * 97.0)) - 0.5;",
    "  c += n * grain + n * (1.0 / 255.0);",
    "  gl_FragColor = vec4(c, 1.0);",
    "}"
  ].join("\n");

  /* Уровни ореола идут без буфера глубины: там рисуется один квадрат
     во весь кадр, и глубина ему не нужна. Мишень СЦЕНЫ берёт глубину
     обязательно: без неё непрозрачные тела ложатся в порядке обхода
     графа, и станция из восьмидесяти тысяч вершин перекрывала сама
     себя как попало, а спинка щита пропускала сквозь себя звено. */
  function мишень(T, w, h, тип, глубина, выборки) {
    var о = new T.WebGLRenderTarget(Math.max(2, w), Math.max(2, h), {
      minFilter: T.LinearFilter, magFilter: T.LinearFilter,
      format: T.RGBAFormat, type: тип, depthBuffer: !!глубина, stencilBuffer: false,
      samples: выборки || 0
    });
    return о;
  }

  /* Текстура глубины к мишени сцены. Пересоздаётся при каждой смене
     размера: у three размер самой текстуры глубины за мишенью не
     следует, и после поворота телефона она оставалась старого размера,
     а слой ругался неполным буфером кадра. */
  function глубинаК(T, цель, w, h) {
    if (цель.depthTexture) { try { цель.depthTexture.dispose(); } catch (e) {} }
    var г = new T.DepthTexture(Math.max(2, w), Math.max(2, h), T.UnsignedIntType);
    г.format = T.DepthFormat;
    г.minFilter = T.NearestFilter; г.magFilter = T.NearestFilter;
    цель.depthTexture = г;
    return г;
  }

  g.RV_REAL = {

    /* ── Световой стан ────────────────────────────────────────────
       Три источника - это минимум, на котором появляется объём.
       Ключевой лепит форму, заполняющий вынимает из черноты теневую
       сторону, контровой отделяет тело от фона кромкой.

       Затухания у источников нет (последний довод в вызове - ноль):
       мир растянут на сотни единиц, а физическое затухание по квадрату
       расстояния означало бы, что дальний акт стоит в темноте. Нам
       нужно направление света, а не его дальнобойность. */
    "свет": function (T, сцена) {
      var стан = new T.Group();
      стан.name = "rv-свет";

      /* Ключ почти белый, контровой ТЁПЛЫЙ. Раньше все три источника
         были синими разных оттенков, и теневая сторона тела отличалась
         от освещённой только яркостью: кадр читался одноцветной
         гравюрой. Тёплая кромка сзади против холодного заполнения
         спереди даёт разницу ЦВЕТОМ, а это то, по чему глаз узнаёт
         объём в кино. Те же два цвета стоят в карте окружения ниже,
         иначе отражения спорили бы с тенями. */
      var ключ = new T.DirectionalLight(0xE9E4FF, 3.2);
      ключ.position.set(-0.55, 0.72, 0.85);
      стан.add(ключ);

      /* Заполнение 2.4 вместо 2.0 (а до того 1.4): теневая сторона
         предметов на подходах к актам (обломки, маяки коридора, дальний
         план) проваливалась в чёрное вместе с небом. Ключ не трогаем:
         пересвет на бликах начинается именно с него, а доля выбитых в
         белый точек держится 0.02% и терять этот запас нельзя. */
      var заполн = new T.DirectionalLight(0x334BAE, 2.1);
      заполн.position.set(0.9, -0.35, 0.35);
      стан.add(заполн);

      var контр = new T.DirectionalLight(0xFFC8A2, 2.4);
      контр.position.set(0.15, 0.25, -1);
      стан.add(контр);

      /* Небесный источник: верх холоднее, низ теплее. Он не лепит
         форму, а убирает мёртвую черноту в тенях - без него теневая
         сторона проваливается в ноль и тело теряет объём именно там,
         где его читают. */
      /* Сила 2.9 и оба цвета светлее прежних (0x3A50B4/0x1E1A34 при 2.4,
         ещё раньше 0x2A3A8C/0x141020 при 1.3). Нижний цвет тут главный:
         0x1E1A34 это яркость 27 в цвете и почти ноль после плёнки, и
         всё, что смотрело вниз, уходило в чёрное. Ночному небу подняли
         пол, и свет от неба обязан подняться вместе с ним, иначе
         предметы стоят чёрными силуэтами на посветлевшем фоне.

         Второй смысл подъёма: он достаётся кадрам с телами, а не
         пустому небу. Именно этим держится разница между актами -
         стыковка и пуск набирают на нём 8-12 единиц, а рубка,
         смотрящая в небо, почти ничего. Без такого перекоса подъём пола
         сравнял бы все восемь актов по яркости. */
      var небо = new T.HemisphereLight(0x3E54B9, 0x262443, 2.5);
      стан.add(небо);

      /* ── ДЕНЬ И НОЧЬ ОДНИМ СТАНОМ ──────────────────────────────
         Днём сцена рисуется по-настоящему дневной, без переворота
         холста: небо светлое, значит и свет обязан прийти дневной.
         Ночные числа держат кино, дневные держат правду: сильный
         тёплый ключ сверху, холодное заполнение от неба, плотная
         небесная составляющая, чтобы теневая сторона предмета на
         светлом небе не проваливалась в чёрный силуэт. */
      var НОЧЬ = [[0xE9E4FF, 3.2], [0x334BAE, 2.1], [0xFFC8A2, 2.4], [0x3E54B9, 0x262443, 2.5]];
      var ДЕНЬ = [[0xFFF4E2, 3.9], [0x9DB4E8, 2.7], [0xFFDCB4, 1.7], [0xCBDAF6, 0x8C9AB8, 3.1]];
      function светПоТеме() {
        var н = document.documentElement.getAttribute("data-тема") === "светлая" ? ДЕНЬ : НОЧЬ;
        ключ.color.setHex(н[0][0]); ключ.intensity = н[0][1];
        заполн.color.setHex(н[1][0]); заполн.intensity = н[1][1];
        контр.color.setHex(н[2][0]); контр.intensity = н[2][1];
        небо.color.setHex(н[3][0]); небо.groundColor.setHex(н[3][1]); небо.intensity = н[3][2];
      }
      светПоТеме();
      window.addEventListener("rv-тема", светПоТеме);

      сцена.add(стан);
      return стан;
    },

    /* ── Корпус ───────────────────────────────────────────────────
       ОДИН материал на все настоящие модели сайта: станция, корабль,
       щит рубки. До него у каждой был свой самописный шейдер, и это
       была не разница характеров, а три разных физики в одном кадре.

       Что они делали. Станция считала свет по формуле «немного
       рассеянного плюс блик» и добавляла френелевскую кромку по ВСЕМУ
       силуэту - предмет с горящим контуром по кругу глаз читает как
       голограмму, а не как железо. Корабль выводился с transparent и
       альфой из яркости: где темнее, там прозрачнее, и сквозь корпус
       буквально просвечивал фон. Владелец назвал ровно это:
       «полупрозрачные, пересвеченные, некачественные».

       Ни один из них не видел ни источников сцены, ни карты
       окружения. Металл узнают по ОТРАЖЕНИЯМ, и пока отражать нечего,
       любая формула даёт крашеный картон.

       Здесь обычный физический материал: его считает сам слой по тем
       же законам, что и настоящую съёмку, он берёт наш стан света и
       нашу карту окружения. Металличность высокая, шероховатость
       средняя - обшивка корабля это не зеркало и не резина. Свечение
       отдельным цветом: им акты зажигают предмет, не трогая корпус.

       Прозрачности нет НИГДЕ и никогда: корпус это корпус. */
    "корпус": function (T, о) {
      о = о || {};
      /* Ступень качества решает, что корпус себе позволит. Лак и
         процедурная фактура стоят кадров: замер до и после показал рост
         медианы кадра в полтора раза на слабой машине. Отдавать этот
         рост телефону нельзя, а отнимать вид у машины, которая его
         тянет, глупо. Поэтому дорогое включается сверху вниз, а не
         одинаково всем. */
      var ст = 2;
      try { if (g.RV_WORLD && g.RV_WORLD["ступень"]) ст = g.RV_WORLD["ступень"](); } catch (e) {}
      var м = new T.MeshPhysicalMaterial({
        color: о.цвет == null ? 0x39415E : о.цвет,
        /* Числа из продакшн-библии, раздел материалов: металл это
           металличность 0.90 при шероховатости 0.28. Стояло 0.86 и 0.38,
           подобранные на глаз, и на глаз же выходил не металл, а
           крашеный пластик: шероховатость под сорок сотых съедает блик,
           а без острого блика металла не бывает. */
        metalness: о.металл == null ? 0.90 : о.металл,
        roughness: о.шерох == null ? 0.28 : о.шерох,
        emissive: о.свет == null ? 0x0A1030 : о.свет,
        emissiveIntensity: о.жар == null ? 0.35 : о.жар,
        envMapIntensity: о.отражения == null ? 1.45 : о.отражения,
        /* Лак поверх краски. У обшивки есть тонкий защитный слой, и он
           даёт ВТОРОЙ блик, более острый, поверх основного. Два блика
           разной резкости - то, по чему глаз узнаёт покрытие, а не
           голый металл. */
        clearcoat: ст < 2 ? 0 : (о.лак == null ? 0.35 : о.лак),
        clearcoatRoughness: о.лакШерох == null ? 0.22 : о.лакШерох,
        transparent: false,
        /* Обе стороны намеренно. Обшивка, собранная из фотографий,
           местами имеет вывернутые нормали: с односторонней отбраковкой
           в таких местах в корпусе появляется дыра, сквозь которую
           видно фон, и предмет снова выглядит дырявым. */
        side: T.DoubleSide
      });
      /* ── ФАКТУРА БЕЗ РАЗВЁРТКИ ────────────────────────────────
         Ровный металл не бывает ровным. У настоящей обшивки есть
         разнобой шероховатости: полированные места, затёртые, следы
         сварки, окисел у стыков. Именно этот разнобой глаз и читает как
         «настоящее» - он рвёт блик на куски. Ровный материал даёт одно
         гладкое пятно и выдаёт себя мгновенно.

         Обычно это карта шероховатости. Здесь нельзя: две модели из
         трёх приехали БЕЗ развёртки, только положения и нормали
         (проверено разбором glb). Текстуре не по чему лечь.

         Поэтому фактура считается в шейдере по МИРОВЫМ координатам
         точки. Развёртка не нужна: у каждой точки корпуса есть своё
         место в пространстве, и трёх октав шума по нему хватает. Заодно
         это устойчиво к масштабу - одна и та же деталь на большой
         станции и на малом корабле выходит одного размера, как в жизни.

         Швы обшивки идут отдельной сеткой: узкие полосы более
         шершавого и менее зеркального металла. Ровно они превращают
         гладкое тело в собранное из панелей. */
      /* На нищей ступени фактуры нет вовсе: там дорог каждый кадр, а
         разнобой шероховатости - украшение, а не смысл. */
      if (ст === 0) {
        м.жар = function (v) {
          м.emissiveIntensity = (о.жар == null ? 0.35 : о.жар) + Math.max(0, v) * 0.5;
        };
        м.масштаб = function () {};
        return м;
      }
      /* Униформы общие на все программы материала (материал с DoubleSide
         и разными сетками собирается не один раз): один объект, чтобы
         м.масштаб(v) менял число сразу везде. */
      /* Имя униформы в GLSL остаётся латинским (uMasht): шейдер кириллицу
         не соберёт. Кириллица только у объекта на стороне JS. */
      var uМасштаб = { value: 1.0 };
      var uRim = { value: ст === 2 ? 0.35 : 0.22 };
      var uRimCol = { value: new T.Vector3(0.54, 0.61, 1.0) };
      /* fwidth на первом WebGL живёт в расширении, которого на старых
         телефонах нет, и шейдер с ним не собирается. Включаем только на
         втором. Слой берём у мира, если он уже поднят; иначе судим по
         наличию класса в окне: ложное «да» здесь дороже ложного «нет». */
      var второйWebGL = false;
      try {
        var мир = g.RV_WORLD && g.RV_WORLD["мир"] ? g.RV_WORLD["мир"]() : null;
        второйWebGL = мир && мир.r ? !!мир.r.capabilities.isWebGL2 : !!g.WebGL2RenderingContext;
      } catch (eW) { второйWebGL = false; }
      /* Анизотропия: блик тянется вдоль обшивки, как на шлифованном
         металле, а не лежит круглым пятном. Стоит вторую выборку карты
         окружения на точку, поэтому только на полной ступени. */
      if (ст === 2) { м.anisotropy = 0.55; м.anisotropyRotation = 0; }
      м.onBeforeCompile = function (ш) {
        ш.uniforms.chast = { value: о.фактура == null ? 2.6 : о.фактура };
        ш.uniforms.uMasht = uМасштаб;
        ш.uniforms.uRim = uRim;
        ш.uniforms.uRimCol = uRimCol;
        /* Фактура в ОБЪЕКТНЫХ координатах, а не в мировых. По мировым швы
           стояли на месте, пока станция вращалась под ними, и ползли по
           корпусу как проекция с фонаря. Масштаб отдельным числом: акт
           с крупной моделью ставит его так, чтобы панели вышли того же
           размера, что на малом корабле. */
        ш.vertexShader = ш.vertexShader
          .replace("#include <common>", "#include <common>\nvarying vec3 vMir;\nuniform float uMasht;")
          .replace("#include <worldpos_vertex>",
            "#include <worldpos_vertex>\n"
            + "  vMir = transformed * uMasht;");
        ш.fragmentShader = ш.fragmentShader
          .replace("#include <common>",
            "#include <common>\n"
            + "varying vec3 vMir;\n"
            + "uniform float chast;\n"
            + "uniform float uRim;\n"
            + "uniform vec3 uRimCol;\n"
            + "float sh1(vec3 p){\n"
            + "  vec3 i = floor(p); vec3 f = fract(p);\n"
            + "  f = f * f * (3.0 - 2.0 * f);\n"
            + "  float n = dot(i, vec3(1.0, 57.0, 113.0));\n"
            + "  float a = fract(sin(n) * 43758.5453);\n"
            + "  float b = fract(sin(n + 1.0) * 43758.5453);\n"
            + "  float c = fract(sin(n + 57.0) * 43758.5453);\n"
            + "  float d = fract(sin(n + 58.0) * 43758.5453);\n"
            + "  float e = fract(sin(n + 113.0) * 43758.5453);\n"
            + "  float g2 = fract(sin(n + 114.0) * 43758.5453);\n"
            + "  float h = fract(sin(n + 170.0) * 43758.5453);\n"
            + "  float k = fract(sin(n + 171.0) * 43758.5453);\n"
            + "  return mix(mix(mix(a,b,f.x), mix(c,d,f.x), f.y),\n"
            + "             mix(mix(e,g2,f.x), mix(h,k,f.x), f.y), f.z);\n"
            + "}\n"
            + (ст < 2
               /* Средняя ступень: одна октава. Швы обшивки при этом
                  остаются - они и держат впечатление собранного из
                  панелей корпуса, а мелкий разнобой поверх них глаз на
                  телефоне всё равно не разбирает. */
               ? "float fakt(vec3 p){ return sh1(p); }"
               : "float fakt(vec3 p){\n"
            /* Две октавы, не три. Третья добавляла к виду доли процента, а
               стоила восьми синусов на точку: на телефоне это заметно, на
               глаз - нет. */
            + "  return sh1(p) * 0.66 + sh1(p * 3.1) * 0.34;\n"
            + "}"))
          /* Фактура и швы считаются в куске цвета: он идёт раньше
             шероховатости и металличности, и обе потом берут готовые
             числа. Заодно швы и полости темнеют в самом цвете: стык
             панелей это не только шершавее, это ещё и окисел в щели. */
          .replace("#include <color_fragment>",
            "#include <color_fragment>\n"
            + "  float fk = fakt(vMir * chast);\n"
            + "  vec3 setka = abs(fract(vMir * 0.42) - 0.5);\n"
            + "  float shov = 1.0 - smoothstep(0.0, 0.035, min(min(setka.x, setka.y), setka.z));\n"
            + "  diffuseColor.rgb *= 1.0 - shov * 0.32 - max(0.0, fk - 0.78) * 0.40;")
          .replace("#include <roughnessmap_fragment>",
            "#include <roughnessmap_fragment>\n"
            + "  roughnessFactor = clamp(roughnessFactor + (fk - 0.5) * 0.34 + shov * 0.22, 0.04, 1.0);")
          /* Металличность правится в СВОЁМ куске, следом за
             шероховатостью: three объявляет metalnessFactor только в
             metalnessmap_fragment, который идёт после roughnessmap.
             Правка внутри куска шероховатости не собиралась вовсе, а
             предмет с несобранной программой three не рисует: станция
             и корабль выпадали из кадра целиком, молча. */
          .replace("#include <metalnessmap_fragment>",
            "#include <metalnessmap_fragment>\n"
            + "  metalnessFactor = clamp(metalnessFactor - shov * 0.18 - max(0.0, fk - 0.72) * 0.25, 0.0, 1.0);")
          /* Сглаживание блика по кромке. Там, где нормаль меняется
             быстрее точки экрана, острый блик рассыпается искрами и
             мерцает при движении; шероховатость поднимается ровно на
             столько, сколько нормаль уходит за точку. */
          .replace("#include <normal_fragment_maps>",
            "#include <normal_fragment_maps>\n"
            + (второйWebGL
               ? "  roughnessFactor = max(roughnessFactor, clamp(length(fwidth(normal)) * 0.9, 0.0, 0.35));"
               : ""))
          /* Кромка Френеля: у настоящего металла край, повёрнутый к глазу
             ребром, отражает сильнее лица. Степень четыре держит её у
             самого силуэта: ниже кромка расползается по всему телу, и
             предмет снова читается голограммой, от которой мы ушли. */
          .replace("#include <opaque_fragment>",
            "  float rimK = pow(1.0 - saturate(dot(normalize(normal), normalize(vViewPosition))), 4.0);\n"
            + "  outgoingLight += uRimCol * rimK * uRim;\n"
            + "#include <opaque_fragment>");
      };
      м.customProgramCacheKey = function () { return "rv-korpus-3-" + ст + (второйWebGL ? "w2" : "w1"); };
      м.масштаб = function (v) { uМасштаб.value = v > 0 ? v : 1.0; };

      /* Зажигание. Акты меняли uniform самописного шейдера; здесь тот
         же смысл выражен собственным свечением материала, а вызов
         остаётся одной строкой. Прибавка 0.5, а не 1.15: с честным
         переводом в sRGB прежняя прибавка заливала выбранную станцию
         ровным бело-голубым, без единой тени (кроп акта «выход»), а
         свечение вокруг и так даёт ореол. */
      м.жар = function (v) {
        м.emissiveIntensity = (о.жар == null ? 0.35 : о.жар) + Math.max(0, v) * 0.5;
      };
      return м;
    },

    /* ── Карта окружения ──────────────────────────────────────────
       Собирается процедурно, из градиента с несколькими светящимися
       пятнами, а не грузится картинкой: лишний файл на критическом
       пути стоит дороже, чем эта сборка, и она разовая.

       Без карты окружения металл в сцене выглядит серой краской: ему
       нечего отражать. */
    "окружение": function (T, рисовальщик, сцена) {
      /* ── Павильон вместо картинки ──────────────────────────────
         Прежняя карта рисовалась на холсте 2D: градиент и круглые
         пятна в восемь бит. У такой карты нет ничего ярче единицы, и
         металл отражал «светлое место», а не источник: блика с формой
         на корпусе не было вовсе, кромка не читалась. Здесь карта
         снимается с МИНИ-СЦЕНЫ: сфера с градиентом и четыре длинных
         софтбокса, чей цвет умножен в разы. Материал без тонального
         сжатия отдаёт число как есть, и в карте появляются настоящие
         пики: металл отражает прямоугольник лампы со скруглённым краем,
         как в павильоне.

         Софтбоксы стоят там, откуда светят источники стана, тех же
         цветов: тёплый ключ, холодный контровой, индиго-заполнение.
         Иначе отражения спорили бы с тенями. Снизу полоса планетного
         отсвета: без неё нижняя половина корпуса мёртвая.

         Карта СВЕТИТ, а не красит фон. Первый заход когда-то сделал её
         в цвет неба сайта, и кадр стал в шестнадцать раз темнее. */
      function мягкийКрай() {
        /* Спад по краю лампы: без него в блике читается ступенька, а
           у настоящего софтбокса край размыт рассеивателем. */
        var хол = document.createElement("canvas");
        хол.width = 64; хол.height = 16;
        var x = хол.getContext("2d");
        var им = x.createImageData(64, 16);
        for (var j = 0; j < 16; j++) for (var i = 0; i < 64; i++) {
          var ax = Math.min(i + 0.5, 63.5 - i) / (64 * 0.15);
          var ay = Math.min(j + 0.5, 15.5 - j) / (16 * 0.15);
          var a = Math.min(1, ax) * Math.min(1, ay);
          a = a * a * (3 - 2 * a);
          var к = (j * 64 + i) * 4;
          им.data[к] = им.data[к + 1] = им.data[к + 2] = Math.round(a * 255);
          им.data[к + 3] = 255;
        }
        x.putImageData(им, 0, 0);
        var тек = new T.CanvasTexture(хол);
        тек.colorSpace = T.NoColorSpace || тек.colorSpace;
        return тек;
      }

      function собрать() {
        var мини = new T.Scene();
        var мусор = [];

        var сф = new T.SphereGeometry(50, 32, 24);
        var поз = сф.attributes.position;
        var цв = new Float32Array(поз.count * 3);
        var верх = new T.Color(0x1A2450).multiplyScalar(1.2);
        var гор = new T.Color(0x0B1030);
        var низ = new T.Color(0x04060F);
        var ц = new T.Color();
        for (var i = 0; i < поз.count; i++) {
          var y = поз.getY(i) / 50;
          if (y >= 0) ц.copy(гор).lerp(верх, y);
          else ц.copy(гор).lerp(низ, -y);
          цв[i * 3] = ц.r; цв[i * 3 + 1] = ц.g; цв[i * 3 + 2] = ц.b;
        }
        сф.setAttribute("color", new T.BufferAttribute(цв, 3));
        var мНебо = new T.MeshBasicMaterial({ vertexColors: true, side: T.BackSide, toneMapped: false });
        мини.add(new T.Mesh(сф, мНебо));
        мусор.push(сф, мНебо);

        var край = мягкийКрай();
        мусор.push(край);
        function лампа(ш, в, r, gg, b, k, x, y, z, поворотX) {
          var гео = new T.PlaneGeometry(ш, в);
          var мат = new T.MeshBasicMaterial({
            toneMapped: false, transparent: true, alphaMap: край, side: T.DoubleSide,
            depthWrite: false
          });
          /* setRGB без пространства пишет число в рабочее, линейное:
             множитель не сжимается кривой и уходит в карту как есть. */
          мат.color.setRGB(r * k, gg * k, b * k);
          var м = new T.Mesh(гео, мат);
          м.position.set(x, y, z);
          if (поворотX != null) м.rotation.x = поворотX;
          else м.lookAt(0, 0, 0);
          мини.add(м);
          мусор.push(гео, мат);
        }
        /* Ключ тёплый и длинный, контровой холодный и узкий,
           заполнение широкое и слабое, планетный отсвет снизу. Множители
           подобраны так, чтобы СРЕДНЯЯ яркость карты осталась рядом с
           прежней (щит рубки и модели держат envMapIntensity 1.8 и 1.25,
           пересветить их нельзя), а пики ушли в разы выше единицы. */
        лампа(14, 2.2, 1.00, 0.86, 0.70, 9.0, -18, 16, 20);
        лампа(10, 1.6, 0.62, 0.72, 1.00, 6.0, 4, 7, -26);
        лампа(9, 9, 0.28, 0.36, 0.85, 2.6, 24, -5, 8);
        лампа(30, 1.2, 0.55, 0.62, 1.00, 1.8, 0, -14, 0, Math.PI / 2);

        var pm = new T.PMREMGenerator(рисовальщик);
        pm.compileCubemapShader();
        var цель = pm.fromScene(мини, 0.04);
        сцена.environment = цель.texture;
        pm.dispose();
        for (var k = 0; k < мусор.length; k++) { try { мусор[k].dispose(); } catch (e) {} }
        return цель.texture;
      }

      /* Сборка карты стоит десятки миллисекунд: это работа прогрева, а
         не подъёма. Мир до первого объёмного акта всё равно не рисует,
         очередь успевает. Если очереди нет (мир поднят иначе), собираем
         сразу: карта важнее одного длинного кадра. */
      try {
        if (g.RV_WORLD && g.RV_WORLD["работа"]) {
          g.RV_WORLD["работа"]("окружение", function () { try { собрать(); } catch (e) {} });
          return null;
        }
        return собрать();
      } catch (e) {
        return null;
      }
    },

    /* ── Плёнка ───────────────────────────────────────────────────
       Пирамида ореола: каждый следующий уровень вдвое мельче и
       строится из уже размытого. Радиус на ступень удваивается почти
       даром, и ореол получает то, что есть у настоящей оптики - тугое
       ядро вплотную к источнику и широкий слабый нимб.

       Один буфер одного размера дал бы либо ядро, либо нимб, но не оба:
       именно так выглядит «нарисованное» свечение. */
    "плёнка": function (T, рисовальщик, ступень, w, h, опции) {
      опции = опции || {};
      var П = {};
      /* Полуплавающая мишень только там, где в неё можно рисовать: на
         первом WebGL без расширения буфер кадра выходит неполным, и
         слой молча рисует в никуда. Тогда восемь бит и потолок яркого
         в единицу: ореол грубее, но кадр есть. */
      var второйWebGL = false, полуМожно = false;
      try {
        второйWebGL = !!рисовальщик.capabilities.isWebGL2;
        полуМожно = второйWebGL || рисовальщик.extensions.has("EXT_color_buffer_half_float");
      } catch (eК) {}
      var полу = полуМожно ? (T.HalfFloatType || T.FloatType) : T.UnsignedByteType;

      /* Сглаживание слоя на полной ступени: четыре выборки на точку.
         Плёнка рисует сцену в мишень, а не на экран, и встроенное
         сглаживание холста до мишени не доходило: ступень 2 платила за
         antialias и не получала его. Только на втором WebGL: первый
         мультисэмпл в мишени не умеет. */
      var выборки = (ступень === 2 && второйWebGL) ? 4 : 0;
      П.сцена = мишень(T, w, h, полу, true, выборки);
      /* Глубина наружу: пыль и плиты по ней мягко гаснут у поверхностей.
         Только на полной ступени: остальным лишняя текстура ни к чему. */
      П.глубина = (ступень === 2 && второйWebGL) ? глубинаК(T, П.сцена, w, h) : null;

      /* Сколько уровней. На нищей ступени два: ореол станет грубее, но
         останется. Отменять его нельзя - без ореола сцена мгновенно
         возвращается к тому чертежу, из-за которого всё и затевалось. */
      var СДВИГ = ступень === 0 ? [2, 4] : (ступень === 1 ? [1, 3, 4] : [1, 2, 4]);
      var ВЕС = ступень === 0 ? [1.0, 0.42] : [1.0, 0.55, 0.30];

      П.уровни = [];
      var i;
      for (i = 0; i < СДВИГ.length; i++) {
        var лw = Math.max(2, w >> СДВИГ[i]), лh = Math.max(2, h >> СДВИГ[i]);
        П.уровни.push({
          сдвиг: СДВИГ[i], w: лw, h: лh,
          a: мишень(T, лw, лh, полу), b: мишень(T, лw, лh, полу)
        });
      }

      var сумма = 0;
      for (i = 0; i < П.уровни.length; i++) сумма += ВЕС[i];
      var веса = new T.Vector4(0, 0, 0, 0);
      for (i = 0; i < П.уровни.length && i < 4; i++) веса.setComponent(i, ВЕС[i] / сумма);

      var кам = new T.OrthographicCamera(-1, 1, 1, -1, 0, 1);

      var мЯркое = new T.ShaderMaterial({
        uniforms: {
          tD: { value: П.сцена.texture },
          thr: { value: опции["порог"] != null ? опции["порог"] : 0.62 },
          soft: { value: 0.26 },
          hicap: { value: опции["потолок"] != null ? опции["потолок"] : (полуМожно ? 6.0 : 1.0) }
        },
        vertexShader: ВЕРШ, fragmentShader: ЯРКОЕ,
        depthTest: false, depthWrite: false
      });

      var мРазмыв = new T.ShaderMaterial({
        uniforms: { tD: { value: null }, dir: { value: new T.Vector2() } },
        vertexShader: ВЕРШ, fragmentShader: РАЗМЫВ,
        depthTest: false, depthWrite: false
      });

      var чёрн = new T.DataTexture(new Uint8Array([0, 0, 0, 255]), 1, 1);
      чёрн.needsUpdate = true;
      function слой(k) { return П.уровни[k] ? П.уровни[k].a.texture : чёрн; }

      var мСборка = new T.ShaderMaterial({
        uniforms: {
          tD: { value: П.сцена.texture },
          t1: { value: слой(0) }, t2: { value: слой(1) }, t3: { value: слой(2) },
          halo: { value: веса },
          glow: { value: опции["свечение"] != null ? опции["свечение"] : 0.72 },
          /* 0.26 вместо 0.34. Углы это большая площадь кадра: при 0.34
             крайняя точка теряла 21% яркости, и в актах, где по краям
             стоит одно небо, эти углы уходили в чисто чёрное целыми
             долями процента экрана. Опора для взгляда в середине кадра
             от 0.26 никуда не делась, а пол по углам поднялся на 3-4
             единицы яркости. */
          vig: { value: опции["виньетка"] != null ? опции["виньетка"] : 0.26 },
          grain: { value: ступень === 0 ? 0.0 : 0.012 },
          /* 0.75, а не 1.85: прежняя цифра лишь прятала пропущенный перевод в
             sRGB. Теперь середина стоит там же, света те же, а тени
             читаются: замер по актам ниже в git-описании. */
          expo: { value: опции["экспозиция"] != null ? опции["экспозиция"] : 0.75 },
          /* Чистый чёрный выходит на экран цветом 25,30,41 при яркости
             30 из 255. Порог замера на чисто чёрное это 12, и запас
             тут двукратный: даже углы под виньеткой из него не
             выпадают. Выше поднимать нельзя, ночь начнёт сереть. */
          pol: { value: new T.Vector3(0.010, 0.013, 0.0225) },
          time: { value: 0 },
          /* Размер точки в долях кадра: по нему сглаживание берёт
             соседей. Пересчитывается при каждой смене размера окна -
             иначе после поворота телефона крест выборок разъезжается. */
          px: { value: new T.Vector2(1 / Math.max(2, w), 1 / Math.max(2, h)) },
          /* На нищей ступени и расхождение каналов, и резкость
             выключены: там не хватает кадров и без них. */
          ca: { value: ступень === 0 ? 0.0 : 0.0042 },
          sharp: { value: ступень === 0 ? 0.0 : 0.22 },
          aa: { value: ступень === 0 ? 0.0 : 1.0 },
          speed: { value: 0.0 },
          vpt: { value: new T.Vector2(0.5, 0.5) },
          boost: { value: 0.0 }
        },
        vertexShader: ВЕРШ, fragmentShader: СБОРКА,
        depthTest: false, depthWrite: false
      });

      var квад = new T.Mesh(new T.PlaneGeometry(2, 2), мЯркое);
      var сценаКв = new T.Scene();
      сценаКв.add(квад);

      function прогон(мат, цель) {
        квад.material = мат;
        рисовальщик.setRenderTarget(цель || null);
        рисовальщик.render(сценаКв, кам);
      }

      П.размер = function (нw, нh) {
        w = нw; h = нh;
        П.сцена.setSize(w, h);
        if (П.глубина) П.глубина = глубинаК(T, П.сцена, w, h);
        мСборка.uniforms.px.value.set(1 / Math.max(2, w), 1 / Math.max(2, h));
        for (var k = 0; k < П.уровни.length; k++) {
          var у = П.уровни[k];
          у.w = Math.max(2, w >> у.сдвиг);
          у.h = Math.max(2, h >> у.сдвиг);
          у.a.setSize(у.w, у.h);
          у.b.setSize(у.w, у.h);
        }
      };

      /* ── События плёнки ───────────────────────────────────────
         Скорость и толчок живут ЗДЕСЬ, а не у камеры: камера едет
         мягко сама по себе, а плёнке нужна своя постоянная времени,
         чтобы росчерки не обрывались на первом же медленном кадре.
         Скорость берётся у мира, если он её отдаёт; иначе меряется по
         ходу камеры между кадрами. Точка схода это проекция точки
         далеко впереди по ходу движения: к ней и тянутся края. */
      var прежниеЧасы = -1, норм = 0, толчок = 0, проверен = false;
      var прежнееМесто = null, точка = null, ходК = null;

      function скоростьКамеры(камера, dt) {
        if (!прежнееМесто) {
          прежнееМесто = new T.Vector3(); точка = new T.Vector3(); ходК = new T.Vector3();
          прежнееМесто.copy(камера.position);
          return 0;
        }
        ходК.copy(камера.position).sub(прежнееМесто);
        прежнееМесто.copy(камера.position);
        var путь = ходК.length();
        if (путь < 1e-4 || dt <= 0) return 0;
        /* Полторы сотни единиц в секунду это быстрый перегон между
           станциями; медленный ход по акту даёт сотые и ничего не
           размывает. */
        var v = Math.min(1, путь / dt / 150);
        ходК.multiplyScalar(200 / путь);
        точка.copy(камера.position).add(ходК).project(камера);
        /* Точка позади камеры (движение назад) проецируется зеркально:
           тогда берём ту, что впереди по взгляду, росчерки те же. */
        if (!(точка.z < 1) || !isFinite(точка.x) || !isFinite(точка.y)) {
          точка.copy(камера.position).sub(ходК).project(камера);
        }
        if (isFinite(точка.x) && isFinite(точка.y)) {
          мСборка.uniforms.vpt.value.set(
            Math.max(-0.3, Math.min(1.3, точка.x * 0.5 + 0.5)),
            Math.max(-0.3, Math.min(1.3, точка.y * 0.5 + 0.5)));
        }
        return v;
      }

      /* Проверка буфера кадра один раз после первого рисования: если
         мультисэмпл с полуплавающим цветом слою не по силам, буфер
         неполный, и кадр уходит в никуда. Откат на обычную мишень. */
      function проверитьБуфер() {
        проверен = true;
        if (!(П.сцена.samples > 0)) return;
        try {
          var контекст = рисовальщик.getContext();
          var св = рисовальщик.properties.get(П.сцена);
          var буфер = св.__webglMultisampledFramebuffer || св.__webglFramebuffer;
          if (!буфер) return;
          рисовальщик.state.bindFramebuffer(контекст.FRAMEBUFFER, буфер);
          var ок = контекст.checkFramebufferStatus(контекст.FRAMEBUFFER) === контекст.FRAMEBUFFER_COMPLETE;
          рисовальщик.state.bindFramebuffer(контекст.FRAMEBUFFER, null);
          if (!ок) { П.сцена.samples = 0; П.сцена.dispose(); }
        } catch (e) {}
      }

      П.render = function (сцена, камера, часы) {
        var прежний = рисовальщик.getRenderTarget();
        var т = часы || 0;
        var dtСырой = прежниеЧасы < 0 ? 0.016 : Math.max(0, т - прежниеЧасы);
        /* Для скорости кадр длиннее десятой доли секунды считается
           десятой: иначе после залипания вкладки один кадр даёт
           скачок. Толчок же гаснет по НАСТОЯЩЕМУ времени: на медленной
           машине с кадром в треть секунды он иначе висел бы втрое
           дольше, чем задуман. */
        var dt = Math.min(0.1, dtСырой);
        прежниеЧасы = т;

        var цель = 0;
        if (ступень > 0) {
          var с = null;
          try { if (g.RV_WORLD && g.RV_WORLD["скорость"]) с = g.RV_WORLD["скорость"](); } catch (eС) {}
          if (typeof с === "number") цель = Math.max(0, Math.min(1, с));
          else if (с && typeof с["доля"] === "number") цель = Math.max(0, Math.min(1, с["доля"]));
          else if (камера) цель = скоростьКамеры(камера, dt);
        }
        норм += (цель - норм) * (1 - Math.exp(-dt / 0.12));
        толчок *= Math.exp(-Math.min(1, dtСырой) / 0.28);
        мСборка.uniforms.speed.value = норм < 0.01 ? 0 : норм;
        мСборка.uniforms.boost.value = толчок < 0.005 ? 0 : толчок;

        рисовальщик.setRenderTarget(П.сцена);
        рисовальщик.clear();
        рисовальщик.render(сцена, камера);
        if (!проверен) проверитьБуфер();

        /* Первый уровень берём из кадра, остальные - из предыдущего
           УЖЕ РАЗМЫТОГО. В этом вся дешевизна пирамиды: работа на всех
           уровнях вместе меньше, чем на одном полном кадре. */
        var источник = П.сцена.texture;
        for (var k = 0; k < П.уровни.length; k++) {
          var у = П.уровни[k];
          мЯркое.uniforms.tD.value = источник;
          прогон(мЯркое, у.b);

          мРазмыв.uniforms.tD.value = у.b.texture;
          мРазмыв.uniforms.dir.value.set(1 / у.w, 0);
          прогон(мРазмыв, у.a);

          мРазмыв.uniforms.tD.value = у.a.texture;
          мРазмыв.uniforms.dir.value.set(0, 1 / у.h);
          прогон(мРазмыв, у.b);

          /* Готовый уровень кладём в a: сборка читает именно его. */
          var t = у.a; у.a = у.b; у.b = t;
          источник = у.a.texture;
        }

        мСборка.uniforms.tD.value = П.сцена.texture;
        мСборка.uniforms.t1.value = слой(0);
        мСборка.uniforms.t2.value = слой(1);
        мСборка.uniforms.t3.value = слой(2);
        мСборка.uniforms.time.value = часы || 0;
        прогон(мСборка, null);

        рисовальщик.setRenderTarget(прежний);
      };

      П.свечение = function (v) { мСборка.uniforms.glow.value = v; };
      П.экспозиция = function (v) { мСборка.uniforms.expo.value = v; };
      П.порог = function (v) { мЯркое.uniforms.thr.value = v; };

      /* Толчок: короткий всплеск экспозиции и аберрации. Берётся
         максимум, а не сумма: два события подряд не должны заливать
         кадр белым. Гаснет сам в render за треть секунды. */
      П.толчок = function (сила) {
        var с = Number(сила);
        if (!(с > 0)) с = 1;
        толчок = Math.max(толчок, Math.min(1, с));
      };
      function поСобытию(поУмолчанию) {
        return function (e) {
          var с = поУмолчанию;
          try {
            if (e && e.detail && typeof e.detail["сила"] === "number") с = e.detail["сила"];
          } catch (x) {}
          П.толчок(с);
        };
      }
      /* Подписки на события окна, а не вызовы из актов: акты про
         плёнку не знают, и знать им незачем. Прокол бьёт в полную
         силу, выбор станции чуть, вход в ворота вполсилы. */
      var слушатели = [
        ["rv:прокол", поСобытию(1)],
        ["rv:станция", поСобытию(0.25)],
        ["rv:стыковка", поСобытию(0.5)]
      ];
      for (var сл = 0; сл < слушатели.length; сл++) {
        try { g.addEventListener(слушатели[сл][0], слушатели[сл][1]); } catch (eЛ) {}
      }

      П.dispose = function () {
        for (var сл = 0; сл < слушатели.length; сл++) {
          try { g.removeEventListener(слушатели[сл][0], слушатели[сл][1]); } catch (eЛ) {}
        }
        if (П.сцена.depthTexture) { try { П.сцена.depthTexture.dispose(); } catch (eГ) {} }
        П.сцена.dispose();
        for (var k = 0; k < П.уровни.length; k++) {
          П.уровни[k].a.dispose(); П.уровни[k].b.dispose();
        }
        мЯркое.dispose(); мРазмыв.dispose(); мСборка.dispose();
        квад.geometry.dispose();
      };

      return П;
    }
  };
})(window);
