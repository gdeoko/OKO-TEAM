/* Rocket VPN. Слой достоверности: свет и плёнка.

   ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ. Заказчик посмотрел собранный сайт и сказал:
   «сухо и не красиво, уступает CDN». Он прав, и причина нашлась не на
   глаз, а обходом кода: во ВСЕЙ сцене не было НИ ОДНОГО источника
   света, а все материалы были самосветящимися. Такая сцена физически не
   может дать объём: у неё нет ни теней, ни бликов, ни разницы между
   обращённой к свету стороной и обратной. Она читается чертежом.

   Второе: не было плёнки. Ни свечения, ни тональной кривой, ни
   виньетки. Яркая точка в такой сцене остаётся точкой, а в жизни она
   расплывается ореолом в оптике глаза и объектива - именно ореол делает
   светящееся СВЕТЯЩИМСЯ, а не просто светлым.

   ЧТО ЗДЕСЬ ЕСТЬ.
   · Световой стан: ключевой источник, заполняющий и контровой. Три
     источника, а не один: с одним сцена читается плоско освещённой, и
     объём не появляется даже при честных материалах.
   · Карта окружения, собранная процедурно из неба сцены. Она даёт
     отражения, без которых металл выглядит серой краской.
   · Плёнка: пирамида ореола, тональная кривая, виньетка, зерно.

   ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Тумана и глубины резкости. Оба съедают
   читаемость подписей, а на этом сайте подписи несут факты.

   Файл НЕ трогает акты и ничего в них не требует. Акт, который хочет
   объёма, просто берёт материал с откликом на свет; акт, которому нужен
   чертёж, оставляет самосветящийся. Оба живут в одной сцене. */
(function (g) {
  "use strict";

  var ВЕРШ = "varying vec2 vUv; void main(){ vUv = uv; gl_Position = vec4(position.xy, 0.0, 1.0); }";

  /* Выделение ярких мест. Порог мягкий, а не резкий: с резким по кромке
     светящегося тела идёт ступенька, и ореол выглядит наклейкой. */
  var ЯРКОЕ = [
    "precision highp float;",
    "varying vec2 vUv;",
    "uniform sampler2D tD;",
    "uniform float thr;",
    "uniform float soft;",
    "uniform float hicap;",
    "void main(){",
    "  vec3 c = texture2D(tD, vUv).rgb;",
    "  float l = dot(c, vec3(0.2126, 0.7152, 0.0722));",
    "  float k = smoothstep(thr, thr + soft, l);",
    /* Потолок нужен, чтобы одна пересвеченная точка не утащила весь
       ореол в белое: без него вспышка прокола заливала кадр. */
    "  c = min(c, vec3(hicap));",
    "  gl_FragColor = vec4(c * k, 1.0);",
    "}"
  ].join("\n");

  /* Размытие одной строкой отсчётов. Веса Гаусса зашиты числами: считать
     их в шейдере дороже, чем написать. */
  var РАЗМЫВ = [
    "precision highp float;",
    "varying vec2 vUv;",
    "uniform sampler2D tD;",
    "uniform vec2 dir;",
    "void main(){",
    "  vec3 s = texture2D(tD, vUv).rgb * 0.227027;",
    "  s += texture2D(tD, vUv + dir * 1.3846).rgb * 0.316216;",
    "  s += texture2D(tD, vUv - dir * 1.3846).rgb * 0.316216;",
    "  s += texture2D(tD, vUv + dir * 3.2308).rgb * 0.070270;",
    "  s += texture2D(tD, vUv - dir * 3.2308).rgb * 0.070270;",
    "  gl_FragColor = vec4(s, 1.0);",
    "}"
  ].join("\n");

  /* Сборка. Здесь же тональная кривая, виньетка и зерно: три полных
     прохода по кадру вместо одного стоили бы дороже всего остального
     вместе взятого. */
  var СБОРКА = [
    "precision highp float;",
    "varying vec2 vUv;",
    "uniform sampler2D tD;",
    "uniform sampler2D t1;",
    "uniform sampler2D t2;",
    "uniform sampler2D t3;",
    "uniform vec4 halo;",
    "uniform float glow;",
    "uniform float vig;",
    "uniform float grain;",
    "uniform float time;",
    "uniform float expo;",
    "uniform vec2 px;",
    "uniform float ca;",
    "uniform float sharp;",
    "uniform float aa;",
    "float hash(vec2 p){ return fract(sin(dot(p, vec2(12.9898, 78.233))) * 43758.5453); }",
    "float luma(vec3 c){ return dot(c, vec3(0.299, 0.587, 0.114)); }",
    /* ── СГЛАЖИВАНИЕ ──────────────────────────────────────────────
       Кромка, набранная ступенями, это первое, по чему глаз отличает
       игрушку от съёмки. Встроенное сглаживание слоя включалось только
       на верхней ступени качества, то есть на телефоне мир стоял в
       лесенках всегда.

       Здесь честный краевой поиск: яркость в кресте вокруг точки,
       направление наибольшего перепада, подмешивание соседа ПОПЕРЁК
       него. Ровные места не трогаются вовсе, размешиваются только
       ступени на кромке. Четыре лишние выборки на точку - цена, за
       которую покупается весь вид.

       Имена внутри шейдера латиницей: кириллица в GLSL не имя, а
       ошибка разбора, и материал молча не собирается. */
    "vec3 sgladit(vec2 uv){",
    "  vec3 c = texture2D(tD, uv).rgb;",
    /* На нищей ступени сглаживание выключается ЦЕЛИКОМ, а не сходит на
       нет по силе: пять выборок текстуры на точку берутся до всякой
       проверки, и «сила ноль» их не экономит. Одна ветка по постоянной
       величине - и слабая машина не платит за них вовсе. */
    "  if (aa < 0.5) return c;",
    "  float lC = luma(c);",
    "  float lN = luma(texture2D(tD, uv + vec2(0.0, px.y)).rgb);",
    "  float lS = luma(texture2D(tD, uv - vec2(0.0, px.y)).rgb);",
    "  float lE = luma(texture2D(tD, uv + vec2(px.x, 0.0)).rgb);",
    "  float lW = luma(texture2D(tD, uv - vec2(px.x, 0.0)).rgb);",
    "  float mx = max(lC, max(max(lN, lS), max(lE, lW)));",
    "  float mn = min(lC, min(min(lN, lS), min(lE, lW)));",
    "  float kr = mx - mn;",
    "  if (kr < 0.045) return c;",
    "  vec2 d = normalize(vec2(abs(lE - lW) + 1e-5, abs(lN - lS) + 1e-5));",
    "  vec2 pop = vec2(-d.y, d.x) * px * 1.35;",
    "  vec3 a = texture2D(tD, uv + pop).rgb;",
    "  vec3 b = texture2D(tD, uv - pop).rgb;",
    "  float sila = clamp(kr * 3.4, 0.0, 1.0);",
    "  return mix(c, (a + b + c * 2.0) * 0.25, sila);",
    "}",
    "void main(){",
    /* ── ХРОМАТИЧЕСКАЯ АБЕРРАЦИЯ ─────────────────────────────────
       Настоящее стекло преломляет цвета чуть по-разному, и к краю кадра
       каналы расходятся. Величина крошечная - доли точки в середине и
       полторы у кромки, - но именно она отличает кадр, снятый оптикой,
       от кадра, посчитанного машиной. Расхождение растёт от центра
       квадратично, как у линзы, а не ровно по всему полю. */
    "  vec2 ot = vUv - 0.5;",
    "  float r2 = dot(ot, ot);",
    "  vec2 sdv = ot * r2 * ca;",
    /* Сглаживание считается ОДИН раз, по зелёному каналу, а красный и
       синий берутся простой выборкой со сдвигом.

       Первый заход звал сглаживание трижды, по разу на канал: пятнадцать
       выборок текстуры на точку вместо семи, и проверка скорости честно
       поймала утяжеление ленты. Разница на глаз при этом нулевая: яркость
       кадра глаз собирает почти целиком из зелёного (три пятых по
       кривой видности), а расхождение каналов у кромки и так меряется
       долями точки - сглаживать то, что смещено на полторы точки и
       вдесятеро слабее по вкладу, значит платить за невидимое. */
    "  vec3 g = sgladit(vUv);",
    "  vec3 c = vec3(",
    "    texture2D(tD, vUv + sdv).r,",
    "    g.g,",
    "    texture2D(tD, vUv - sdv).b);",
    "  c = mix(c, g, 0.15);",
    /* Контурная резкость после сглаживания. Сглаживание неизбежно
       мягчит кадр целиком; малая добавка разницы с размытым возвращает
       материалу фактуру, не возвращая ступеней. */
    "  vec3 mjk = (texture2D(tD, vUv + vec2(px.x, 0.0)).rgb",
    "            + texture2D(tD, vUv - vec2(px.x, 0.0)).rgb",
    "            + texture2D(tD, vUv + vec2(0.0, px.y)).rgb",
    "            + texture2D(tD, vUv - vec2(0.0, px.y)).rgb) * 0.25;",
    "  c += (c - mjk) * sharp;",
    "  vec3 h = texture2D(t1, vUv).rgb * halo.x",
    "         + texture2D(t2, vUv).rgb * halo.y",
    "         + texture2D(t3, vUv).rgb * halo.z;",
    "  c += h * glow;",
    /* Экспозиция ДО кривой, а не после. Кривая ниже сама по себе
       опускает середину (так она и задумана: чтобы яркое не слипалось
       в белое), и без поправки весь кадр уезжает в темноту. Замер
       первого захода: средняя яркость 1.93 из 255 при 31.4 у сцены
       без плёнки. */
    "  c *= expo;",
    /* Тональная кривая. Плёночная, а не обрезание по единице: обрезание
       превращает всё яркое в одинаково белое, и вспышка теряет форму. */
    "  c = (c * (2.51 * c + 0.03)) / (c * (2.43 * c + 0.59) + 0.14);",
    /* Виньетка. Слабая: сильная читается как дырка в объективе, а нужна
       лишь опора для взгляда в середине кадра. */
    "  float r = distance(vUv, vec2(0.5));",
    "  c *= 1.0 - vig * smoothstep(0.35, 0.95, r);",
    /* Зерно. Без него ровные тёмные заливки идут ступенями: экран не
       умеет показать сотни оттенков почти чёрного, и переходы рвутся на
       полосы. Зерно эти полосы размешивает. */
    "  float n = hash(vUv * 900.0 + time) - 0.5;",
    "  c += n * grain;",
    "  gl_FragColor = vec4(c, 1.0);",
    "}"
  ].join("\n");

  function мишень(T, w, h, тип) {
    var о = new T.WebGLRenderTarget(Math.max(2, w), Math.max(2, h), {
      minFilter: T.LinearFilter, magFilter: T.LinearFilter,
      format: T.RGBAFormat, type: тип, depthBuffer: false, stencilBuffer: false
    });
    return о;
  }

  g.RV_REAL = {

    /* ── Световой стан ────────────────────────────────────────────
       Три источника - это минимум, на котором появляется объём.
       Ключевой лепит форму, заполняющий вынимает из черноты теневую
       сторону, контровой отделяет тело от фона кромкой.

       Затухания у источников нет (последний довод в вызове - ноль):
       мир растянут на сотни единиц, а физическое затухание по квадрату
       расстояния означало бы, что дальний акт стоит в темноте. Нам
       нужно направление света, а не его дальнобойность. */
    "свет": function (T, сцена) {
      var стан = new T.Group();
      стан.name = "rv-свет";

      var ключ = new T.DirectionalLight(0xBFCBFF, 3.4);
      ключ.position.set(-0.55, 0.72, 0.85);
      стан.add(ключ);

      var заполн = new T.DirectionalLight(0x3048A8, 1.5);
      заполн.position.set(0.9, -0.35, 0.35);
      стан.add(заполн);

      var контр = new T.DirectionalLight(0x8A9CFF, 2.6);
      контр.position.set(0.15, 0.25, -1);
      стан.add(контр);

      /* Небесный источник: верх холоднее, низ теплее. Он не лепит
         форму, а убирает мёртвую черноту в тенях - без него теневая
         сторона проваливается в ноль и тело теряет объём именно там,
         где его читают. */
      var небо = new T.HemisphereLight(0x2A3A8C, 0x0A0C1A, 1.35);
      стан.add(небо);

      сцена.add(стан);
      return стан;
    },

    /* ── Корпус ───────────────────────────────────────────────────
       ОДИН материал на все настоящие модели сайта: станция, корабль,
       щит рубки. До него у каждой был свой самописный шейдер, и это
       была не разница характеров, а три разных физики в одном кадре.

       Что они делали. Станция считала свет по формуле «немного
       рассеянного плюс блик» и добавляла френелевскую кромку по ВСЕМУ
       силуэту - предмет с горящим контуром по кругу глаз читает как
       голограмму, а не как железо. Корабль выводился с transparent и
       альфой из яркости: где темнее, там прозрачнее, и сквозь корпус
       буквально просвечивал фон. Владелец назвал ровно это:
       «полупрозрачные, пересвеченные, некачественные».

       Ни один из них не видел ни источников сцены, ни карты
       окружения. Металл узнают по ОТРАЖЕНИЯМ, и пока отражать нечего,
       любая формула даёт крашеный картон.

       Здесь обычный физический материал: его считает сам слой по тем
       же законам, что и настоящую съёмку, он берёт наш стан света и
       нашу карту окружения. Металличность высокая, шероховатость
       средняя - обшивка корабля это не зеркало и не резина. Свечение
       отдельным цветом: им акты зажигают предмет, не трогая корпус.

       Прозрачности нет НИГДЕ и никогда: корпус это корпус. */
    "корпус": function (T, о) {
      о = о || {};
      /* Ступень качества решает, что корпус себе позволит. Лак и
         процедурная фактура стоят кадров: замер до и после показал рост
         медианы кадра в полтора раза на слабой машине. Отдавать этот
         рост телефону нельзя, а отнимать вид у машины, которая его
         тянет, глупо. Поэтому дорогое включается сверху вниз, а не
         одинаково всем. */
      var ст = 2;
      try { if (g.RV_WORLD && g.RV_WORLD["ступень"]) ст = g.RV_WORLD["ступень"](); } catch (e) {}
      var м = new T.MeshPhysicalMaterial({
        color: о.цвет == null ? 0x39415E : о.цвет,
        /* Числа из продакшн-библии, раздел материалов: металл это
           металличность 0.90 при шероховатости 0.28. Стояло 0.86 и 0.38,
           подобранные на глаз, и на глаз же выходил не металл, а
           крашеный пластик: шероховатость под сорок сотых съедает блик,
           а без острого блика металла не бывает. */
        metalness: о.металл == null ? 0.90 : о.металл,
        roughness: о.шерох == null ? 0.28 : о.шерох,
        emissive: о.свет == null ? 0x0A1030 : о.свет,
        emissiveIntensity: о.жар == null ? 0.35 : о.жар,
        envMapIntensity: о.отражения == null ? 1.45 : о.отражения,
        /* Лак поверх краски. У обшивки есть тонкий защитный слой, и он
           даёт ВТОРОЙ блик, более острый, поверх основного. Два блика
           разной резкости - то, по чему глаз узнаёт покрытие, а не
           голый металл. */
        clearcoat: ст < 2 ? 0 : (о.лак == null ? 0.35 : о.лак),
        clearcoatRoughness: о.лакШерох == null ? 0.22 : о.лакШерох,
        transparent: false,
        /* Обе стороны намеренно. Обшивка, собранная из фотографий,
           местами имеет вывернутые нормали: с односторонней отбраковкой
           в таких местах в корпусе появляется дыра, сквозь которую
           видно фон, и предмет снова выглядит дырявым. */
        side: T.DoubleSide
      });
      /* ── ФАКТУРА БЕЗ РАЗВЁРТКИ ────────────────────────────────
         Ровный металл не бывает ровным. У настоящей обшивки есть
         разнобой шероховатости: полированные места, затёртые, следы
         сварки, окисел у стыков. Именно этот разнобой глаз и читает как
         «настоящее» - он рвёт блик на куски. Ровный материал даёт одно
         гладкое пятно и выдаёт себя мгновенно.

         Обычно это карта шероховатости. Здесь нельзя: две модели из
         трёх приехали БЕЗ развёртки, только положения и нормали
         (проверено разбором glb). Текстуре не по чему лечь.

         Поэтому фактура считается в шейдере по МИРОВЫМ координатам
         точки. Развёртка не нужна: у каждой точки корпуса есть своё
         место в пространстве, и трёх октав шума по нему хватает. Заодно
         это устойчиво к масштабу - одна и та же деталь на большой
         станции и на малом корабле выходит одного размера, как в жизни.

         Швы обшивки идут отдельной сеткой: узкие полосы более
         шершавого и менее зеркального металла. Ровно они превращают
         гладкое тело в собранное из панелей. */
      /* На нищей ступени фактуры нет вовсе: там дорог каждый кадр, а
         разнобой шероховатости - украшение, а не смысл. */
      if (ст === 0) {
        м.жар = function (v) {
          м.emissiveIntensity = (о.жар == null ? 0.35 : о.жар) + Math.max(0, v) * 1.15;
        };
        return м;
      }
      м.onBeforeCompile = function (ш) {
        ш.uniforms.chast = { value: о.фактура == null ? 2.6 : о.фактура };
        ш.vertexShader = ш.vertexShader
          .replace("#include <common>", "#include <common>\nvarying vec3 vMir;")
          .replace("#include <worldpos_vertex>",
            "#include <worldpos_vertex>\n"
            + "  vMir = (modelMatrix * vec4(transformed, 1.0)).xyz;");
        ш.fragmentShader = ш.fragmentShader
          .replace("#include <common>",
            "#include <common>\n"
            + "varying vec3 vMir;\n"
            + "uniform float chast;\n"
            + "float sh1(vec3 p){\n"
            + "  vec3 i = floor(p); vec3 f = fract(p);\n"
            + "  f = f * f * (3.0 - 2.0 * f);\n"
            + "  float n = dot(i, vec3(1.0, 57.0, 113.0));\n"
            + "  float a = fract(sin(n) * 43758.5453);\n"
            + "  float b = fract(sin(n + 1.0) * 43758.5453);\n"
            + "  float c = fract(sin(n + 57.0) * 43758.5453);\n"
            + "  float d = fract(sin(n + 58.0) * 43758.5453);\n"
            + "  float e = fract(sin(n + 113.0) * 43758.5453);\n"
            + "  float g2 = fract(sin(n + 114.0) * 43758.5453);\n"
            + "  float h = fract(sin(n + 170.0) * 43758.5453);\n"
            + "  float k = fract(sin(n + 171.0) * 43758.5453);\n"
            + "  return mix(mix(mix(a,b,f.x), mix(c,d,f.x), f.y),\n"
            + "             mix(mix(e,g2,f.x), mix(h,k,f.x), f.y), f.z);\n"
            + "}\n"
            + (ст < 2
               /* Средняя ступень: одна октава. Швы обшивки при этом
                  остаются - они и держат впечатление собранного из
                  панелей корпуса, а мелкий разнобой поверх них глаз на
                  телефоне всё равно не разбирает. */
               ? "float fakt(vec3 p){ return sh1(p); }"
               : "float fakt(vec3 p){\n"
            /* Две октавы, не три. Третья добавляла к виду доли процента, а
               стоила восьми синусов на точку: на телефоне это заметно, на
               глаз - нет. */
            + "  return sh1(p) * 0.66 + sh1(p * 3.1) * 0.34;\n"
            + "}"))
          .replace("#include <roughnessmap_fragment>",
            "#include <roughnessmap_fragment>\n"
            + "  float fk = fakt(vMir * chast);\n"
            + "  vec3 setka = abs(fract(vMir * 0.42) - 0.5);\n"
            + "  float shov = 1.0 - smoothstep(0.0, 0.035, min(min(setka.x, setka.y), setka.z));\n"
            + "  roughnessFactor = clamp(roughnessFactor + (fk - 0.5) * 0.34 + shov * 0.22, 0.04, 1.0);\n"
            + "  metalnessFactor = clamp(metalnessFactor - shov * 0.18 - max(0.0, fk - 0.72) * 0.25, 0.0, 1.0);");
      };
      м.customProgramCacheKey = function () { return "rv-korpus-1"; };

      /* Зажигание. Акты меняли uniform самописного шейдера; здесь тот
         же смысл выражен собственным свечением материала, а вызов
         остаётся одной строкой. */
      м.жар = function (v) {
        м.emissiveIntensity = (о.жар == null ? 0.35 : о.жар) + Math.max(0, v) * 1.15;
      };
      return м;
    },

    /* ── Карта окружения ──────────────────────────────────────────
       Собирается процедурно, из градиента с несколькими светящимися
       пятнами, а не грузится картинкой: лишний файл на критическом
       пути стоит дороже, чем эта сборка, и она разовая.

       Без карты окружения металл в сцене выглядит серой краской: ему
       нечего отражать. */
    "окружение": function (T, рисовальщик, сцена) {
      /* Вдвое подробнее прежнего. На пятистах двенадцати точках
         источники в карте выходили размером в десяток точек, и металл
         отражал не софтбокс, а ступеньку: блик по кромке шёл рваным
         пунктиром. Карта собирается один раз за сеанс, лишняя тысяча
         точек стоит миллисекунды. */
      var хол = document.createElement("canvas");
      хол.width = 1024; хол.height = 512;
      var x = хол.getContext("2d");

      /* Карта СВЕТИТ, а не красит фон, и это не одно и то же. Первый
         заход я сделал её в цвет неба сайта - почти чёрной, - и замер
         показал беду: кадр стал в шестнадцать раз ТЕМНЕЕ прежнего
         (средняя яркость 1.93 против 31.4). Металл отражает то, что
         вокруг, а вокруг было ничто.

         Настоящая студия тоже стоит в тёмной комнате, но софтбоксы в
         ней яркие. Здесь то же самое: основа тёмная, источники на ней
         яркие, и отражать становится что. */
      var гр = x.createLinearGradient(0, 0, 0, 512);
      гр.addColorStop(0, "#33427F");
      гр.addColorStop(0.42, "#1A2450");
      гр.addColorStop(0.72, "#0E1430");
      гр.addColorStop(1, "#070A18");
      x.fillStyle = гр; x.fillRect(0, 0, 1024, 512);

      /* Пятна света. Их положение неслучайно: они стоят там, откуда
         светят источники стана, иначе отражения спорили бы с тенями. */
      /* Софтбоксы. Три главных стоят там, откуда светят источники
         стана, иначе отражения спорили бы с тенями. К ним добавлены
         три слабых: без них тёмная половина отражения оставалась
         мёртвой, и корпус с теневой стороны выглядел вырезанным из
         бумаги. В настоящем павильоне тоже нет ни одной стены, которая
         не отражает совсем. */
      var пятна = [[220, 120, 260, "rgba(232,239,255,1)"],
                   [800, 192, 200, "rgba(150,175,255,0.85)"],
                   [512, 410, 320, "rgba(80,110,220,0.55)"],
                   [60,  330, 190, "rgba(70,95,190,0.34)"],
                   [660, 60,  150, "rgba(190,208,255,0.42)"],
                   [980, 300, 170, "rgba(96,124,214,0.30)"]];
      for (var i = 0; i < пятна.length; i++) {
        var п = пятна[i];
        var рг = x.createRadialGradient(п[0], п[1], 0, п[0], п[1], п[2]);
        рг.addColorStop(0, п[3]);
        рг.addColorStop(1, "rgba(0,0,0,0)");
        x.fillStyle = рг;
        x.fillRect(п[0] - п[2], п[1] - п[2], п[2] * 2, п[2] * 2);
      }

      var тек = new T.CanvasTexture(хол);
      тек.mapping = T.EquirectangularReflectionMapping;
      тек.colorSpace = T.SRGBColorSpace || тек.colorSpace;

      try {
        var pm = new T.PMREMGenerator(рисовальщик);
        pm.compileEquirectangularShader();
        var цель = pm.fromEquirectangular(тек);
        сцена.environment = цель.texture;
        pm.dispose();
        тек.dispose();
        return цель.texture;
      } catch (e) {
        /* На совсем старом слое генератора может не быть. Тогда карта
           ставится напрямую: отражения будут грубее, но они БУДУТ. */
        сцена.environment = тек;
        return тек;
      }
    },

    /* ── Плёнка ───────────────────────────────────────────────────
       Пирамида ореола: каждый следующий уровень вдвое мельче и
       строится из уже размытого. Радиус на ступень удваивается почти
       даром, и ореол получает то, что есть у настоящей оптики - тугое
       ядро вплотную к источнику и широкий слабый нимб.

       Один буфер одного размера дал бы либо ядро, либо нимб, но не оба:
       именно так выглядит «нарисованное» свечение. */
    "плёнка": function (T, рисовальщик, ступень, w, h, опции) {
      опции = опции || {};
      var П = {};
      var полу = T.HalfFloatType || T.FloatType;

      П.сцена = мишень(T, w, h, полу);

      /* Сколько уровней. На нищей ступени два: ореол станет грубее, но
         останется. Отменять его нельзя - без ореола сцена мгновенно
         возвращается к тому чертежу, из-за которого всё и затевалось. */
      var СДВИГ = ступень === 0 ? [2, 4] : (ступень === 1 ? [1, 3, 4] : [1, 2, 4]);
      var ВЕС = ступень === 0 ? [1.0, 0.42] : [1.0, 0.55, 0.30];

      П.уровни = [];
      var i;
      for (i = 0; i < СДВИГ.length; i++) {
        var лw = Math.max(2, w >> СДВИГ[i]), лh = Math.max(2, h >> СДВИГ[i]);
        П.уровни.push({
          сдвиг: СДВИГ[i], w: лw, h: лh,
          a: мишень(T, лw, лh, полу), b: мишень(T, лw, лh, полу)
        });
      }

      var сумма = 0;
      for (i = 0; i < П.уровни.length; i++) сумма += ВЕС[i];
      var веса = new T.Vector4(0, 0, 0, 0);
      for (i = 0; i < П.уровни.length && i < 4; i++) веса.setComponent(i, ВЕС[i] / сумма);

      var кам = new T.OrthographicCamera(-1, 1, 1, -1, 0, 1);

      var мЯркое = new T.ShaderMaterial({
        uniforms: {
          tD: { value: П.сцена.texture },
          thr: { value: опции["порог"] != null ? опции["порог"] : 0.62 },
          soft: { value: 0.26 },
          hicap: { value: опции["потолок"] != null ? опции["потолок"] : 6.0 }
        },
        vertexShader: ВЕРШ, fragmentShader: ЯРКОЕ,
        depthTest: false, depthWrite: false
      });

      var мРазмыв = new T.ShaderMaterial({
        uniforms: { tD: { value: null }, dir: { value: new T.Vector2() } },
        vertexShader: ВЕРШ, fragmentShader: РАЗМЫВ,
        depthTest: false, depthWrite: false
      });

      var чёрн = new T.DataTexture(new Uint8Array([0, 0, 0, 255]), 1, 1);
      чёрн.needsUpdate = true;
      function слой(k) { return П.уровни[k] ? П.уровни[k].a.texture : чёрн; }

      var мСборка = new T.ShaderMaterial({
        uniforms: {
          tD: { value: П.сцена.texture },
          t1: { value: слой(0) }, t2: { value: слой(1) }, t3: { value: слой(2) },
          halo: { value: веса },
          glow: { value: опции["свечение"] != null ? опции["свечение"] : 0.72 },
          vig: { value: опции["виньетка"] != null ? опции["виньетка"] : 0.34 },
          grain: { value: ступень === 0 ? 0.0 : 0.012 },
          expo: { value: опции["экспозиция"] != null ? опции["экспозиция"] : 1.85 },
          time: { value: 0 },
          /* Размер точки в долях кадра: по нему сглаживание берёт
             соседей. Пересчитывается при каждой смене размера окна -
             иначе после поворота телефона крест выборок разъезжается. */
          px: { value: new T.Vector2(1 / Math.max(2, w), 1 / Math.max(2, h)) },
          /* На нищей ступени и расхождение каналов, и резкость
             выключены: там не хватает кадров и без них. */
          ca: { value: ступень === 0 ? 0.0 : 0.0042 },
          sharp: { value: ступень === 0 ? 0.0 : 0.22 },
          aa: { value: ступень === 0 ? 0.0 : 1.0 }
        },
        vertexShader: ВЕРШ, fragmentShader: СБОРКА,
        depthTest: false, depthWrite: false
      });

      var квад = new T.Mesh(new T.PlaneGeometry(2, 2), мЯркое);
      var сценаКв = new T.Scene();
      сценаКв.add(квад);

      function прогон(мат, цель) {
        квад.material = мат;
        рисовальщик.setRenderTarget(цель || null);
        рисовальщик.render(сценаКв, кам);
      }

      П.размер = function (нw, нh) {
        w = нw; h = нh;
        П.сцена.setSize(w, h);
        мСборка.uniforms.px.value.set(1 / Math.max(2, w), 1 / Math.max(2, h));
        for (var k = 0; k < П.уровни.length; k++) {
          var у = П.уровни[k];
          у.w = Math.max(2, w >> у.сдвиг);
          у.h = Math.max(2, h >> у.сдвиг);
          у.a.setSize(у.w, у.h);
          у.b.setSize(у.w, у.h);
        }
      };

      П.render = function (сцена, камера, часы) {
        var прежний = рисовальщик.getRenderTarget();

        рисовальщик.setRenderTarget(П.сцена);
        рисовальщик.clear();
        рисовальщик.render(сцена, камера);

        /* Первый уровень берём из кадра, остальные - из предыдущего
           УЖЕ РАЗМЫТОГО. В этом вся дешевизна пирамиды: работа на всех
           уровнях вместе меньше, чем на одном полном кадре. */
        var источник = П.сцена.texture;
        for (var k = 0; k < П.уровни.length; k++) {
          var у = П.уровни[k];
          мЯркое.uniforms.tD.value = источник;
          прогон(мЯркое, у.b);

          мРазмыв.uniforms.tD.value = у.b.texture;
          мРазмыв.uniforms.dir.value.set(1 / у.w, 0);
          прогон(мРазмыв, у.a);

          мРазмыв.uniforms.tD.value = у.a.texture;
          мРазмыв.uniforms.dir.value.set(0, 1 / у.h);
          прогон(мРазмыв, у.b);

          /* Готовый уровень кладём в a: сборка читает именно его. */
          var t = у.a; у.a = у.b; у.b = t;
          источник = у.a.texture;
        }

        мСборка.uniforms.tD.value = П.сцена.texture;
        мСборка.uniforms.t1.value = слой(0);
        мСборка.uniforms.t2.value = слой(1);
        мСборка.uniforms.t3.value = слой(2);
        мСборка.uniforms.time.value = часы || 0;
        прогон(мСборка, null);

        рисовальщик.setRenderTarget(прежний);
      };

      П.свечение = function (v) { мСборка.uniforms.glow.value = v; };
      П.экспозиция = function (v) { мСборка.uniforms.expo.value = v; };
      П.порог = function (v) { мЯркое.uniforms.thr.value = v; };

      П.dispose = function () {
        П.сцена.dispose();
        for (var k = 0; k < П.уровни.length; k++) {
          П.уровни[k].a.dispose(); П.уровни[k].b.dispose();
        }
        мЯркое.dispose(); мРазмыв.dispose(); мСборка.dispose();
        квад.geometry.dispose();
      };

      return П;
    }
  };
})(window);
