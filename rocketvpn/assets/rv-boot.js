/* Rocket VPN. Экран загрузки.

   ПОЧЕМУ ОН ЗДЕСЬ С САМОГО НАЧАЛА. В родственном проекте Rocket CDN
   экран загрузки дописывался последним, и до этого он уходил ПО ЧАСАМ,
   а не по готовности: потолок стоял на четырёх секундах, а событие
   готовности объёмного слоя на небыстрой машине приходило на седьмой.
   То есть заставка уходила ВСЕГДА раньше, чем появлялась сцена, и
   владелец прислал «в какой-то момент все анимации, ракета и планета
   пропадают». Их там ещё и не было.

   Здесь всё наоборот с первого дня: экран уходит ПО ГОТОВНОСТИ, а часы
   стоят только страховкой на случай, когда что-то не доехало вовсе.

   ЧТО СЧИТАЕТСЯ ГОТОВНОСТЬЮ. Ровно то, без чего первый экран выглядит
   пустым: шрифт и марка. НЕ ждём объёмный слой: он нужен со второго
   акта, а до него человек будет читать первый экран секунды. Ждать его
   значило бы держать человека перед заставкой ради того, что ему
   сейчас не нужно.

   ЧЕГО НЕ ЖДЁМ СОЗНАТЕЛЬНО: события полной загрузки страницы. Оно ждёт
   всё, включая то, что лежит ниже экрана и человеку сейчас не нужно.
   В CDN оно приходило на третьей секунде, когда сцена была готова на
   первой, и держало человека впустую. */
(function (g, d) {
  "use strict";

  var ДЕРЖАТЬ = 420;    /* минимальный показ, чтобы экран не мигнул */
  var ПОТОЛОК = 7000;   /* страховка: что-то не доехало вовсе */
  var УХОД = 520;

  var э = null, кольцо = null, начало = 0, ушёл = false;
  var надо = 2, есть = 0;

  function создать() {
    э = d.createElement("div");
    э.className = "rv-загр";
    э.setAttribute("aria-hidden", "true");
    э.innerHTML =
      '<div class="rv-загр-в">' +
        '<img class="rv-загр-марка" src="assets/rv-mark.webp" width="72" height="72" alt="">' +
        '<div class="rv-загр-путь"><i></i></div>' +
      '</div>';
    d.body.appendChild(э);
    кольцо = э.querySelector(".rv-загр-путь i");
    начало = Date.now();
  }

  function ход(доля) {
    if (кольцо) кольцо.style.transform = "scaleX(" + доля.toFixed(3) + ")";
  }

  function шаг() {
    есть++;
    ход(Math.min(1, есть / надо));
    if (есть >= надо) уйти();
  }

  function уйти() {
    if (ушёл || !э) return;
    /* Держим минимальное время. Экран, мигнувший на сто миллисекунд,
       читается сбоем отрисовки, а не загрузкой: человек видит вспышку и
       не понимает, что это было. */
    var прошло = Date.now() - начало;
    if (прошло < ДЕРЖАТЬ) { setTimeout(уйти, ДЕРЖАТЬ - прошло); return; }
    ушёл = true;
    ход(1);
    э.classList.add("ушёл");
    d.documentElement.classList.add("rv-загружен");
    setTimeout(function () {
      if (э && э.parentNode) э.parentNode.removeChild(э);
      э = null;
    }, УХОД + 60);
  }

  function старт() {
    /* Пока створ закрыт, экрана загрузки быть не должно: человек не
       увидит за ним ничего, и загрузка сообщала бы о существовании
       того, что от него закрыто. */
    if (!d.documentElement.classList.contains("rv-открыт")) return;

    создать();

    /* 1. Шрифт. Без него заголовок первого экрана перескочит с
       запасной гарнитуры на свою у человека на глазах. */
    var ждёмШрифт = false;
    try {
      if (d.fonts && d.fonts.ready) {
        ждёмШрифт = true;
        d.fonts.ready.then(шаг, шаг);
      }
    } catch (e) {}
    if (!ждёмШрифт) шаг();

    /* 2. Марка. Она в первом экране крупно, и её появление рывком
       заметнее всего остального. */
    var м = new Image();
    м.onload = шаг;
    м.onerror = шаг;
    м.src = "assets/rv-mark.webp";
    /* Уже в кэше - onload может не сработать в старых движках. */
    if (м.complete) { м.onload = null; шаг(); }

    setTimeout(уйти, ПОТОЛОК);
  }

  /* Наружу для приёмки: когда ушёл и по какой причине. */
  g.RV_BOOT = {
    "ушёл": function () { return ушёл; },
    "готовность": function () { return { "надо": надо, "есть": есть }; }
  };

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", старт);
  else старт();
})(window, document);
