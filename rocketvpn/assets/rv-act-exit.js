    "uniform vec3 noch;",    /* цвет ночной стороны */
    "uniform vec3 kromka;",  /* цвет кромки атмосферы */
    "varying vec3 vN;",
    "varying vec3 vI;",
    "void main() {",
    "  float s = dot(vN, sun);",
