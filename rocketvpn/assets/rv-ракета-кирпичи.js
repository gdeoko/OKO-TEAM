/* Rocket VPN. РАКЕТА СКЛАДЫВАЕТСЯ ИЗ КИРПИЧЕЙ ТОННЕЛЯ.

   ЗАЧЕМ ЭТОТ ФАЙЛ ЕСТЬ. Владелец, глядя на ленту: «ракета из частиц -
   ты же говорила, уберёшь её вообще, удалишь и сделаешь, что как будто
   она из туннелей, из того же материала, из тех же кирпичей
   собирается», и там же про весь кусок до финала - «полная каша».

   Рой точек был перенесён с igloo.inc дословно и был там на месте: у
   них фигура из песка, и она ничего не обещает. У нас перед этим местом
   человек полторы минуты летит сквозь КАМЕННЫЙ тоннель, и когда на дне
   шахты вместо камня загорается облако голубых точек, обещание сцены
   рвётся ровно там, где его видно лучше всего. Материал должен идти
   насквозь: дом сложен из камня, стена из того же камня, тоннель из
   него же - и корабль обязан собраться из него, а не появиться из
   ниоткуда другим веществом.

   ЧТО ЗДЕСЬ ПРОИСХОДИТ. Кирпичи слетаются из темноты вокруг (оттуда,
   откуда пришёл человек) и встают в корпус ракеты: юбка сопла, тело,
   носовой конус, четыре киля. Кладка идёт СНИЗУ ВВЕРХ, как её и кладут:
   ряд встаёт целиком, следующий начинает, когда предыдущий на месте.
   К концу сборки на дне шахты стоит ракета, сложенная из камня, в
   котором узнаётся стена.

   ЧЕМ ОНА СЛОЖЕНА. Камень берётся у rv-кирпичи.js вызовом
   RV_КИРПИЧИ.камень(), брусок - RV_КИРПИЧИ.брусок(). Не копия шейдера,
   не «те же числа», а тот же материал из той же фабрики: три карты
   фотоскана, четыре краски, смена темы заодно со стеной. Копию мы уже
   писали трижды, и трижды она отставала - отсюда и «подмена стены».

   РАЗМЕР КАМНЯ. Ряд по высоте 0.673 мира, ровно как у стены: по высоте
   ряда глаз и узнаёт кладку. По ширине камень уже стенного (0.855
   против 1.19) - корпус круглый, и стенным камнем его не обойти, в ряд
   встало бы шесть штук и вышел бы шестигранник. Восемь узких камней в
   ряду дают окружность, и это ровно то, как кладут круглую башню.

   API
     RV_СБОРКА.собрать(мир, родитель, о) -> Group | null
     RV_СБОРКА.сбор(доля)      0 кирпичи в пути, 1 корпус сложен
     RV_СБОРКА.кадр(dt, часы)
     RV_СБОРКА.проявить(альфа) передача металлу: камень тает
     RV_СБОРКА.видно(да)
     RV_СБОРКА.узел() / RV_СБОРКА.короб()   подгонка объёмной ракеты */
(function (g) {
  "use strict";

  var T = null, W = null, собрано = false;
  var М = {};

  /* ── МОДЕЛЬ РАКЕТЫ В МЕСТНЫХ ЕДИНИЦАХ ─────────────────────────
     Те же габариты, что были у роя (rv-частицы.js, ракетаГео): низ
     юбки -1.00, остриё конуса 1.78. Объёмная ракета (rv-ракета.js)
     встаёт по этим числам запасным путём, и менять их здесь значит
     двигать корабль в зале. */
  var ЮБКА_НИЗ = -1.00, ЮБКА_ВЕРХ = -0.70;
  var ТЕЛО_НИЗ = -0.70, ТЕЛО_ВЕРХ = 1.00;
  var КОНУС_ВЕРХ = 1.78;
  /* ── КАМЕННАЯ ОБОЛОЧКА ШИРЕ МЕТАЛЛИЧЕСКОГО КОРПУСА ───────────
     Радиусы стояли по модели роя (0.34 и 0.30) - ровно по обшивке
     объёмной ракеты, которая встаёт на это же место. На снимке зала
     это вышло боком: во время передачи металл торчал СКВОЗЬ камень,
     из кладки лезли чёрный нос, кили и раструб, и в кадре стояли два
     корпуса разом.

     Камень обязан укрывать металл целиком: он снаружи, он кожух. Плюс
     восемнадцать процентов к радиусу - и обшивка уходит внутрь, а
     силуэт остаётся ракетным. */
  var R_НИЗ = 0.40, R_ВЕРХ = 0.355, R_ЮБКА = 0.25;

  /* Масштаб узла ставит зал (3.4). Камень считаем в мировых единицах и
     делим на него: ряд обязан совпасть со стенным по высоте, а не по
     числу, записанному наугад. */
  var МАСШТАБ_ЗАЛА = 3.4;
  var РЯД_МИР = 0.673;          /* высота ряда у стены */
  var КАМЕНЬ_МИР = 0.855;       /* ширина камня на круглом корпусе */
  var ТОЛЩ_МИР = 0.42;

  var РЯД = РЯД_МИР / МАСШТАБ_ЗАЛА;
  var ШИР = КАМЕНЬ_МИР / МАСШТАБ_ЗАЛА;
  var ТОЛЩ = ТОЛЩ_МИР / МАСШТАБ_ЗАЛА;

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }
  function плавно(a, b, x) { x = зажать((x - a) / (b - a), 0, 1); return x * x * (3 - 2 * x); }

  /* ── РАСКЛАДКА КЛАДКИ ─────────────────────────────────────────
     Кольцо камней на высоте y и радиусе r. Ширина камня считается от
     окружности, а не берётся постоянной: иначе на сужении конуса
     соседи полезут друг на друга. Каждый следующий ряд сдвинут на
     полкамня - перевязка, без неё швы встанут в одну вертикаль и
     кладка развалится на глаз. */
  function кольцо(куски, y, r, высРяда, сдвиг, ряд01, наклон) {
    var n = Math.max(3, Math.round(2 * Math.PI * r / ШИР));
    var шир = 2 * Math.PI * r / n;
    for (var i = 0; i < n; i++) {
      var th = ((i + (сдвиг ? 0.5 : 0)) / n) * Math.PI * 2;
      var кос = Math.cos(th), син = Math.sin(th);
      /* Нормаль наружу. На конусе она отклонена от горизонтали: камень
         лежит по поверхности, а не торчит из неё. */
      var норм = new T.Vector3(кос, наклон || 0, син).normalize();
      var q = new T.Quaternion().setFromUnitVectors(new T.Vector3(0, 0, 1), норм);
      /* Довернуть вокруг нормали так, чтобы ширина камня шла по кольцу. */
      var вдоль = new T.Vector3(-син, 0, кос);
      var локX = new T.Vector3(1, 0, 0).applyQuaternion(q);
      var угл = Math.atan2(локX.clone().cross(вдоль).dot(норм), локX.dot(вдоль));
      q.premultiply(new T.Quaternion().setFromAxisAngle(норм, угл));
      куски.push({
        дом: new T.Vector3(кос * r, y, син * r),
        кват: q,
        разм: new T.Vector3(шир * 1.005, высРяда * 0.97, ТОЛЩ),
        ряд01: ряд01,
        угол: th
      });
    }
  }

  /* Плоская плита киля: два столбца на три ряда, лежат в плоскости,
     проходящей через ось. Киль из одного камня читался бы доской, из
     шести - сложенным, как и всё остальное. */
  function киль(куски, угол, ряд01) {
    var кос = Math.cos(угол), син = Math.sin(угол);
    var норм = new T.Vector3(-син, 0, кос);
    var q = new T.Quaternion().setFromUnitVectors(new T.Vector3(0, 0, 1), норм);
    /* Киль крупнее, чем был. Три ряда на два столбца по 0.46 на 0.30
       давали плиту, которую съедал киль металлической обшивки под ней:
       на снимке зала из каменной ракеты торчали ЧЁРНЫЕ лопасти. Киль
       снаружи и обязан укрывать то, что под ним. */
    var ряды = 4, стлб = 2;
    var выс = 0.60 / ряды, глуб = 0.42 / стлб;
    for (var р = 0; р < ряды; р++) {
      for (var с = 0; с < стлб; с++) {
        /* Киль сужается кверху: нижний столбец уходит от корпуса
           дальше верхнего, и плита получает тот самый скос. */
        var t = (р + 0.5) / ряды;
        var отступ = 0.30 + (с + 0.5) * глуб * (1 - t * 0.40);
        var y = -0.90 + (р + 0.5) * выс;
        куски.push({
          дом: new T.Vector3(кос * отступ, y, син * отступ),
          кват: q,
          разм: new T.Vector3(глуб * 0.98, выс * 0.96, ТОЛЩ * 0.62),
          ряд01: ряд01 + р * 0.01,
          угол: угол
        });
      }
    }
  }

  /* ── ПОДОШВА: РАКЕТА СТОИТ, А НЕ ВИСИТ ────────────────────────
     Замер: верх площадки 16.30 мира, низ каменной кладки 16.86. Между
     ними пятьдесят шесть сотых пустоты. Пока рядом стоял металлический
     корабль, зазор закрывали его опоры и раструб; корабль ушёл, и на
     снимке прокола 0.93 ракета повисла над площадкой.

     Кладём подошву - кольцо камней шире юбки, от площадки до низа
     сопла. Она и закрывает зазор, и читается опорой: так ставят на
     стартовый стол. Высота ровно 0.56 мира, поделённая на масштаб зала. */
  var ПОДОШВА = 0.56 / 3.4;
  var R_ПОДОШВА = 0.46;

  function раскладка() {
    var куски = [];
    var всяВыс = КОНУС_ВЕРХ - (ЮБКА_НИЗ - ПОДОШВА);

    кольцо(куски, ЮБКА_НИЗ - ПОДОШВА * 0.5, R_ПОДОШВА, ПОДОШВА, 0, 0, 0);
    /* Подошва помечена: в габарит ракеты она не входит. По этому
       габариту объёмный корабль встаёт на её место (rv-ракета.js,
       подогнать), и опора под соплом подняла бы его на свою высоту. */
    for (var п = 0; п < куски.length; п++) куски[п].подошва = true;

    /* Юбка сопла: снизу уже, кверху шире. Кладётся первой. */
    var юбРядов = Math.max(1, Math.round((ЮБКА_ВЕРХ - ЮБКА_НИЗ) / РЯД));
    var юбВыс = (ЮБКА_ВЕРХ - ЮБКА_НИЗ) / юбРядов;
    for (var ю = 0; ю < юбРядов; ю++) {
      var yЮ = ЮБКА_НИЗ + (ю + 0.5) * юбВыс;
      var rЮ = R_ЮБКА + (R_НИЗ - R_ЮБКА) * ((ю + 0.5) / юбРядов);
      кольцо(куски, yЮ, rЮ, юбВыс, ю % 2, (yЮ - ЮБКА_НИЗ + ПОДОШВА) / всяВыс, -0.42);
    }

    /* Тело: чуть сужается кверху, как настоящая ступень. */
    var тРядов = Math.max(2, Math.round((ТЕЛО_ВЕРХ - ТЕЛО_НИЗ) / РЯД));
    var тВыс = (ТЕЛО_ВЕРХ - ТЕЛО_НИЗ) / тРядов;
    for (var т = 0; т < тРядов; т++) {
      var yТ = ТЕЛО_НИЗ + (т + 0.5) * тВыс;
      var rТ = R_НИЗ + (R_ВЕРХ - R_НИЗ) * ((т + 0.5) / тРядов);
      кольцо(куски, yТ, rТ, тВыс, т % 2, (yТ - ЮБКА_НИЗ + ПОДОШВА) / всяВыс, 0);
    }

    /* ── НОСОВОЙ КОНУС ────────────────────────────────────────
       Кольца сходятся к оси, пока в кольце помещается хотя бы три
       камня; выше встаёт ПРОБКА от последнего кольца до самого остриё.

       Прежде кольца с малым радиусом просто пропускались, а пробка
       стояла на своей высоте независимо от того, где кончилась кладка.
       Между ними зияла дыра, и на снимке зала над конусом висел
       отдельный камень - ровно то, что читается недосбором. */
    var кНиз = ТЕЛО_ВЕРХ, высК = КОНУС_ВЕРХ - ТЕЛО_ВЕРХ;
    var кРядов = Math.max(3, Math.round(высК / РЯД));
    var кВыс = высК / кРядов;
    var наклонК = R_ВЕРХ / высК;
    var верхКладки = ТЕЛО_ВЕРХ;
    for (var к = 0; к < кРядов; к++) {
      var yК = ТЕЛО_ВЕРХ + (к + 0.5) * кВыс;
      var rК = R_ВЕРХ * (1 - (yК - ТЕЛО_ВЕРХ) / высК);
      if (2 * Math.PI * rК < ШИР * 3) break;
      кольцо(куски, yК, rК, кВыс, к % 2, (yК - ЮБКА_НИЗ + ПОДОШВА) / всяВыс, наклонК);
      верхКладки = ТЕЛО_ВЕРХ + (к + 1) * кВыс;
    }
    /* Пробка закрывает всё, что осталось до остриё: её высота считается,
       а не задаётся. Открытая макушка читается дырой в носу. */
    var пВыс = Math.max(кВыс, КОНУС_ВЕРХ - верхКладки);
    куски.push({
      дом: new T.Vector3(0, верхКладки + пВыс * 0.5, 0),
      кват: new T.Quaternion(),
      разм: new T.Vector3(ШИР * 0.85, пВыс, ШИР * 0.85),
      ряд01: 1,
      угол: 0
    });

    /* Четыре киля крестом - столько же, сколько было у роя: объёмная
       ракета садится по его габариту, и менять счёт килей здесь значит
       двигать её. */
    for (var f = 0; f < 4; f++) {
      киль(куски, f * Math.PI / 2, ((-0.90) - ЮБКА_НИЗ + ПОДОШВА) / всяВыс);
    }
    return куски;
  }

  /* ── ОТКУДА ЛЕТИТ КАМЕНЬ ──────────────────────────────────────
     Из темноты вокруг и снизу, широким кругом: человек только что
     прошёл тоннель, и камень идёт оттуда же, из стен. Высоко над
     головой не берём - там пусто, и камень, падающий с потолка,
     читается обвалом, а не сборкой. */
  function исток(к, сл) {
    var уг = к.угол + (сл() - 0.5) * 2.2;
    var рад = 2.6 + сл() * 2.4;
    var выс = -1.4 + сл() * 2.6;
    return new T.Vector3(Math.cos(уг) * рад, выс, Math.sin(уг) * рад);
  }

  function собрать(мир, родитель, о) {
    if (собрано) return М.корень;
    W = мир || W;
    if (!W || !W.T || !родитель) return null;
    T = W.T;
    о = о || {};

    if (!g.RV_КИРПИЧИ || !g.RV_КИРПИЧИ["камень"]) return null;
    if (g.RV_КИРПИЧИ["готовМир"]) g.RV_КИРПИЧИ["готовМир"](W);
    var камень = g.RV_КИРПИЧИ["камень"]();
    var гео = g.RV_КИРПИЧИ["брусок"]();
    if (!камень || !гео) return null;
    М.мат = камень["мат"];

    М.куски = раскладка();
    var N = М.куски.length;

    var семя = 4211;
    function сл() { семя = (семя * 9301 + 49297) % 233280; return семя / 233280; }

    var aSeed = new Float32Array(N), aRaz = new Float32Array(N);
    for (var i = 0; i < N; i++) {
      var к = М.куски[i];
      aSeed[i] = ((к.дом.x * 12.9898 + к.дом.y * 78.233) * 43758.5453) % 1;
      if (aSeed[i] < 0) aSeed[i] += 1;
      к.исток = исток(к, сл);
      /* Кувырок в полёте свой у каждого камня, иначе стая летит одним
         телом. Ось случайная, оборотов от половины до двух. */
      к.ось = new T.Vector3(сл() - 0.5, сл() - 0.5, сл() - 0.5).normalize();
      к.оборот = (0.5 + сл() * 1.5) * Math.PI * 2 * (сл() < 0.5 ? -1 : 1);
      к.разброс = сл();
      /* Дуга полёта: камень не идёт по прямой, его ведёт вбок и вверх.
         Прямая линия от точки к точке читается телепортом. */
      к.дуга = new T.Vector3((сл() - 0.5) * 1.4, 0.6 + сл() * 1.1, (сл() - 0.5) * 1.4);
    }
    гео.setAttribute("aSeed", new T.InstancedBufferAttribute(aSeed, 1));
    гео.setAttribute("aRaz", new T.InstancedBufferAttribute(aRaz, 1));

    М.корень = new T.Group();
    М.корень.name = "ракета из кирпичей";
    М.кладка = new T.InstancedMesh(гео, М.мат, N);
    М.кладка.name = "кирпичи ракеты";
    М.кладка.frustumCulled = false;
    М.кладка.instanceMatrix.setUsage(T.DynamicDrawUsage);
    М.кладка.renderOrder = 4;
    М.корень.add(М.кладка);
    родитель.add(М.корень);

    /* Свой материал, а не общий со стеной: камень тает при передаче
       металлу, и гасить вместе с ним стену периметра нельзя.
       Складывание на кадр включается только на время передачи: у
       непрозрачного камня оно ничего не даёт, зато ставит сотню
       кирпичей в очередь сортировки по глубине. */
    М.мат.transparent = false;
    М.мат.depthWrite = true;

    М.сбор = 0;
    М.альфа = 1;
    М.село = 0;
    собрано = true;
    писать(0, 0);
    return М.корень;
  }

  /* ── КАДР ─────────────────────────────────────────────────────
     Матрицы пишутся только когда что-то изменилось: сборка стоит на
     месте большую часть ленты, и гонять сто тридцать матриц каждый
     кадр незачем. */
  var _м = null, _q = null, _v = null, _s = null, _q2 = null;
  function писать(сбор, часы) {
    if (!собрано) return;
    if (!_м) {
      _м = new T.Matrix4(); _q = new T.Quaternion(); _v = new T.Vector3();
      _s = new T.Vector3(); _q2 = new T.Quaternion();
    }
    var село = 0;
    for (var i = 0; i < М.куски.length; i++) {
      var к = М.куски[i];
      /* Очередь кладки: снизу вверх. Ряд занимает свою долю прокрутки,
         камни внутри ряда встают почти разом с малым разбросом - так
         кладут, и так это читается кладкой, а не дождём. */
      /* ── КАМНЕЙ В ВОЗДУХЕ ДОЛЖНО БЫТЬ ВИДНО МНОГО ────────────────
         Стояло: ряды разведены на 0.62 прокрутки, каждый камень летит
         0.26. На снимке доли 0.95 в воздухе оставался ОДИН камень -
         остальные уже сели, и сборки не читалось вовсе, стояла готовая
         башня. Полёт длиннее очереди даёт стаю: над корпусом всё время
         идёт десяток камней, и видно, откуда он растёт. */
      var старт = к.ряд01 * 0.52 + к.разброс * 0.08;
      var t = зажать((сбор - старт) / 0.42, 0, 1);
      /* Заход мягкий на посадке: камень подлетает быстро и садится
         медленно. Ровная скорость читается механизмом. */
      var e = 1 - Math.pow(1 - t, 3);

      _v.copy(к.исток).lerp(к.дом, e);
      /* Дуга: горб посреди пути, к посадке сходит в ноль. */
      var горб = Math.sin(e * Math.PI);
      _v.x += к.дуга.x * горб;
      _v.y += к.дуга.y * горб;
      _v.z += к.дуга.z * горб;

      /* Кувырок гаснет к посадке: камень доворачивается в своё место,
         а не втыкается в него как попало. */
      _q2.setFromAxisAngle(к.ось, к.оборот * (1 - e));
      _q.copy(к.кват).premultiply(_q2);

      /* Камень в пути мельче: он ещё далеко, и полный размер на подлёте
         читается наездом. Разница небольшая, её видно только движением. */
      if (t >= 1) село++;
      var кМас = 0.82 + 0.18 * e;
      _s.set(к.разм.x * кМас, к.разм.y * кМас, к.разм.z * кМас);
      _м.compose(_v, _q, _s);
      М.кладка.setMatrixAt(i, _м);
    }
    М.кладка.instanceMatrix.needsUpdate = true;
    if (М.мат && М.мат.uniforms && М.мат.uniforms.uTime) М.мат.uniforms.uTime.value = часы || 0;

    /* ── КАМЕНЬ, СЕВШИЙ НА МЕСТО, СЛЫШНО ─────────────────────────
       Звук идёт не на каждый камень, а на каждый ЧЕТВЁРТЫЙ: их полторы
       сотни, и полтораста ударов подряд сливаются в треск. Событие
       уходит только когда число севших выросло, поэтому обратная
       прокрутка молчит - разбирать кладку звуком удара нельзя, это
       другой звук и другое действие. */
    if (село > М.село) {
      if (Math.floor(село / 4) > Math.floor(М.село / 4)) {
        try {
          g.dispatchEvent(new CustomEvent("rv:кладка", {
            detail: { "номер": Math.floor(село / 4) }
          }));
        } catch (eС) {}
      }
    }
    М.село = село;
  }

  function кадр(dt, часы) {
    if (!собрано) return;
    писать(М.сбор, часы);
  }

  g.RV_СБОРКА = {
    "собрать": собрать,
    "кадр": кадр,
    "сбор": function (доля) {
      if (!собрано) return;
      var д = зажать(доля || 0, 0, 1);
      if (Math.abs(д - М.сбор) < 0.0004) return;
      М.сбор = д;
      писать(д, М.часы || 0);
    },
    /* Передача металлу: камень тает, а не пропадает кадром. Тает он
       СВОИМ каналом прозрачности (uAlpha в шейдере кладки), а не
       полем opacity: ShaderMaterial его не читает, и прежнее «гашение»
       через яркость давало чёрный каменный силуэт поверх обшивки.
       Глубину камень перестаёт писать на половине пути - иначе
       невидимая кладка вычищала бы корабль за собой. */
    "проявить": function (а) {
      if (!собрано) return;
      М.альфа = зажать(а == null ? 1 : а, 0, 1);
      М.мат.transparent = М.альфа < 0.999;
      М.мат.depthWrite = М.альфа > 0.5;
      if (М.мат.uniforms && М.мат.uniforms.uAlpha) {
        М.мат.uniforms.uAlpha.value = М.альфа;
      }
      if (М.кладка) М.кладка.visible = М.альфа > 0.004;
    },
    "видно": function (да) { if (собрано) М.корень.visible = !!да; },
    "глубина": function (да) { if (собрано) М.мат.depthWrite = !!да; },
    "узел": function () { return собрано ? М.кладка : null; },
    /* Габарит СЛОЖЕННОЙ ракеты в местных координатах узла. Объёмная
       ракета встаёт по нему: спрашивать текущие матрицы нельзя, на
       половине сборки камень ещё в воздухе и короб выйдет впятеро
       больше корпуса. */
    "короб": function () {
      if (!собрано) return null;
      var к = new T.Box3();
      for (var i = 0; i < М.куски.length; i++) {
        var ч = М.куски[i];
        if (ч.подошва) continue;
        к.expandByPoint(new T.Vector3(ч.дом.x, ч.дом.y - ч.разм.y * 0.5, ч.дом.z));
        к.expandByPoint(new T.Vector3(ч.дом.x, ч.дом.y + ч.разм.y * 0.5, ч.дом.z));
      }
      return к;
    },
    "замер": function () {
      if (!собрано) return { "собрано": false };
      return {
        "собрано": true,
        "кирпичей": М.куски.length,
        "сбор": +М.сбор.toFixed(3),
        "альфа": +М.альфа.toFixed(3),
        "ряд": +РЯД_МИР.toFixed(3),
        "видно": !!(М.корень && М.корень.visible && М.кладка.visible)
      };
    }
  };
})(window);
