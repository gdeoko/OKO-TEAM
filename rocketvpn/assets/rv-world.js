  /* ── Пыль ─────────────────────────────────────────────────────
     Без неё перегон между станциями не читается вовсе: в пустоте
     смещение камеры незаметно, пока в кадре нет ничего ближе станции.
     Пыль решает это дёшево - облако держится ВОКРУГ камеры и заворачи-
     вается по кубу, поэтому частиц нужно несколько сотен, а не сотни
     тысяч на весь коридор длиной в тысячу единиц.

     Это отделка, и на слабой ступени частиц меньше. Содержимое актов от
     неё не зависит ни в одной точке. */
  var пыль = null, пыльБаза = null, пыльШаг = 56;

  function пыльТекстура(T) {
    var c = d.createElement("canvas");
    c.width = 32; c.height = 32;
    var x = c.getContext("2d");
    var гр = x.createRadialGradient(16, 16, 0, 16, 16, 16);
    гр.addColorStop(0, "rgba(255,255,255,1)");
    гр.addColorStop(0.45, "rgba(210,220,255,0.5)");
    гр.addColorStop(1, "rgba(210,220,255,0)");
    x.fillStyle = гр;
    x.fillRect(0, 0, 32, 32);
    return new T.CanvasTexture(c);
  }

  function собратьПыль() {
    if (пыль || !W.готов) return;
    var T = W.T;
    var сколько = W.ступень === 0 ? 260 : (W.ступень === 1 ? 620 : 1100);
    пыльБаза = new Float32Array(сколько * 3);
    var поз = new Float32Array(сколько * 3), i;
    /* Расстановка псевдослучайная, но ПОСТОЯННАЯ: облако обязано быть
       одним и тем же при каждом заходе, иначе снимок ленты кадров
       нельзя сравнить со снимком, снятым час назад. */
    var s = 1234567;
    function сл() { s = (s * 1103515245 + 12345) % 2147483648; return s / 2147483648; }
    for (i = 0; i < сколько * 3; i++) пыльБаза[i] = сл() * пыльШаг;
    var г = new T.BufferGeometry();
    г.setAttribute("position", new T.BufferAttribute(поз, 3));
    пыль = new T.Points(г, new T.PointsMaterial({
      color: 0xAEBCF0, size: 0.10, sizeAttenuation: true,
      map: пыльТекстура(T), transparent: true, opacity: 0.85,
      depthWrite: false, blending: T.AdditiveBlending
    }));
    /* Вершины двигаются руками вокруг камеры, поэтому коробка объекта
       врёт всегда. Отсечение по ней выкинуло бы облако из кадра. */
    пыль.frustumCulled = false;
    пыль.renderOrder = -1;
    W.scene.add(пыль);
  }

  function вестиПыль() {
    if (!пыль) return;
    var поз = пыль.geometry.attributes.position.array;
    var c = W.cam.position;
    var S = пыльШаг, п = S * 0.5, i, dx, dy, dz;
    for (i = 0; i < поз.length; i += 3) {
      dx = пыльБаза[i]     - c.x; dx -= Math.round(dx / S) * S;
      dy = пыльБаза[i + 1] - c.y; dy -= Math.round(dy / S) * S;
      dz = пыльБаза[i + 2] - c.z; dz -= Math.round(dz / S) * S;
      /* Дырка вокруг камеры. Частица в упор рисуется пятном во
         пол-экрана: размер точки на экране обратен расстоянию, и на
         одной единице он доходит до полусотни точек. Выталкиваем такие
         на другую сторону куба - плотность облака от этого не меняется,
         а пятен в кадре нет. */
      if (dx * dx + dy * dy + dz * dz < 120) dz += (dz >= 0 ? -п : п);
      поз[i] = c.x + dx;
      поз[i + 1] = c.y + dy;
      поз[i + 2] = c.z + dz;
    }
    пыль.geometry.attributes.position.needsUpdate = true;
  }

