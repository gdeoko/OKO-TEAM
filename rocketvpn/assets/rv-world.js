/* Rocket VPN. Ядро объёмного мира.

   ГЛАВНОЕ АРХИТЕКТУРНОЕ РЕШЕНИЕ: ОДНА СЦЕНА НА ВЕСЬ САЙТ.

   У родственного сайта Rocket CDN объёмных холстов несколько, и это
   вышло ему дорого. Браузер держит ограниченное число контекстов
   рисования (на телефоне их три, на мониторе четыре), и когда сайт
   просит пятый, браузер молча отбирает первый: холст чернеет навсегда.
   В CDN из-за этого пришлось заводить сторожа, отдавать и забирать
   места, и всё равно один холст иногда садился на плоскую карту.

   Здесь такой болезни нет по построению. Контекст ровно один, он живёт
   от загрузки до ухода со страницы, а акты - это модули, которые
   кладут в общую сцену свои узлы и прячут их, когда их время прошло.
   Отдавать нечего и отбирать нечего.

   Второе следствие того же решения - непрерывность. Акты не сменяют
   друг друга кадром, у них общая камера. Переход из «оболочки» в
   «прокол» это ход одной камеры, а не смена двух картинок, и склейки
   между актами не существует физически.

   ТРЕТЬЕ: ПРОГРЕВ С ПЕРВОЙ СЕКУНДЫ. В CDN прогрев дописывался в конце и
   стоил недели разбирательств, почему первый вход занимает секунды.
   Здесь он часть ядра: тяжёлое считается в свободных промежутках, пока
   человек читает первый экран, а не в тот момент, когда он до этого
   докрутил. */
(function (g, d) {
  "use strict";

  var W = {
    T: null,          /* THREE, когда доедет */
    r: null,          /* рисовальщик */
    scene: null,
    cam: null,
    часы: 0,
    ступень: 2,       /* 0 нищая, 1 средняя, 2 полная */
    плотность: 1,
    акты: {},         /* имя -> модуль акта */
    готов: false,
    _подписки: []
  };

  /* ── Ступень качества ─────────────────────────────────────────
     Считается ОДИН раз по железу, а не подбирается на ходу по частоте
     кадров. Подбор на ходу выглядит как мерцание качества, и человек
     видит, что сайт «просел», даже когда он просел на четверть секунды.

     Ступень НИКОГДА не отменяет содержимое, только его отделку. Это
     прямой урок родственного проекта: там лестница качества отказывала
     в самих объектах, и владелец прислал «в какой-то момент все
     анимации, ракета и планета пропадают». */
  function ступень() {
    var пам = g.navigator && g.navigator.deviceMemory ? g.navigator.deviceMemory : 8;
    var ядер = g.navigator && g.navigator.hardwareConcurrency ? g.navigator.hardwareConcurrency : 4;
    var узко = Math.min(g.innerWidth, g.innerHeight) < 520;
    if (пам <= 2 || ядер <= 2) return 0;
    if (пам <= 4 || ядер <= 4 || узко) return 1;
    return 2;
  }

  function плотностьПо(ст) {
    var d0 = g.devicePixelRatio || 1;
    if (ст === 0) return Math.min(d0, 1);
    if (ст === 1) return Math.min(d0, 1.35);
    return Math.min(d0, 1.8);
  }

  /* ── Свободные промежутки ─────────────────────────────────────
     Тяжёлое считаем, пока браузеру нечем заняться. Замена через таймер
     нужна не для красоты: в Safari до недавнего времени свободных
     промежутков нет вовсе, и без замены прогрев там не начался бы
     никогда. */
  var вТишине = (g.requestIdleCallback) ?
    function (f) { g.requestIdleCallback(f, { timeout: 1200 }); } :
    function (f) { setTimeout(function () { f({ timeRemaining: function () { return 8; } }); }, 60); };

  var ОЧЕРЕДЬ = [], идёт = false, сделано = [];

  function работа(имя, дело) { ОЧЕРЕДЬ.push({ имя: имя, дело: дело }); }

  function крутить() {
    if (идёт || !ОЧЕРЕДЬ.length) return;
    идёт = true;
    вТишине(function (дл) {
      идёт = false;
      while (ОЧЕРЕДЬ.length) {
        var р = ОЧЕРЕДЬ.shift();
        var т = 0;
        try { т = performance.now(); } catch (e0) {}
        try { р.дело(); } catch (e) {}
        try { сделано.push([р.имя, Math.round(performance.now() - т)]); } catch (e1) {}
        /* Промежуток кончился - остальное в следующий. Иначе одна
           длинная работа съедает кадр, который браузер собирался
           нарисовать, и человек видит рывок ровно там, где мы
           старались его избежать. */
        if (!дл || !дл.timeRemaining || дл.timeRemaining() < 3) break;
      }
      if (ОЧЕРЕДЬ.length) крутить();
      else fire("rv:прогрет");
    });
  }

  function fire(имя) {
    try { g.dispatchEvent(new CustomEvent(имя)); } catch (e) {
      try { var ev = d.createEvent("Event"); ev.initEvent(имя, false, false); g.dispatchEvent(ev); } catch (e2) {}
    }
  }

  /* ── Подъём ───────────────────────────────────────────────────*/
  function поднять() {
    var T = g.THREE;
    if (!T) return false;
    var холст = d.getElementById("rvМир");
    if (!холст) return false;

    W.T = T;
    W.ступень = ступень();
    W.плотность = плотностьПо(W.ступень);

    try {
      W.r = new T.WebGLRenderer({
        canvas: холст,
        antialias: W.ступень === 2,
        alpha: true,
        powerPreference: "high-performance"
      });
    } catch (e) { return false; }

    W.r.setPixelRatio(W.плотность);
    W.r.setSize(g.innerWidth, g.innerHeight, false);
    W.r.setClearColor(0x000000, 0);

    W.scene = new T.Scene();
    W.cam = new T.PerspectiveCamera(52, g.innerWidth / g.innerHeight, 0.1, 4000);
    W.cam.position.set(0, 0, 12);

    d.documentElement.setAttribute("data-ступень", String(W.ступень));
    W.готов = true;
    fire("rv:мир");
    return true;
  }

  /* ── Размер ───────────────────────────────────────────────────
     Пересчёт откладываем на кадр: поворот телефона присылает несколько
     событий подряд, и считать по каждому значит считать впустую. */
  var ждём = 0;
  function поРазмеру() {
    if (ждём || !W.готов) return;
    ждём = 1;
    g.requestAnimationFrame(function () {
      ждём = 0;
      W.r.setSize(g.innerWidth, g.innerHeight, false);
      W.cam.aspect = g.innerWidth / g.innerHeight;
      W.cam.updateProjectionMatrix();
      for (var и in W.акты) if (W.акты.hasOwnProperty(и)) {
        var a = W.акты[и];
        if (a && a["размер"]) { try { a["размер"](g.innerWidth, g.innerHeight); } catch (e) {} }
      }
    });
  }

  /* ── Кадр ─────────────────────────────────────────────────────
     Рисуем ТОЛЬКО когда в кадре есть живой акт. Пустой кадр это не
     ноль работы: очистка буфера полноэкранная, и на слабом телефоне
     она одна съедает заметную долю заряда ни за чем. */
  var прошлое = 0;
  function кадр(ts) {
    g.requestAnimationFrame(кадр);
    if (!W.готов) return;
    var dt = прошлое ? Math.min(0.05, (ts - прошлое) / 1000) : 0.016;
    прошлое = ts;
    W.часы += dt;

    var живой = false;
    for (var и in W.акты) {
      if (!W.акты.hasOwnProperty(и)) continue;
      var a = W.акты[и];
      if (!a) continue;
      var доля = g.RV_MOTION ? g.RV_MOTION["доля"](и) : 0;
      /* Акт считается живым, пока его кадр хоть краем в окне. Доля
         строго 0 или строго 1 означает, что акт ещё не начался или уже
         кончился, и держать его в кадре незачем. */
      var вКадре = доля > 0.0001 && доля < 0.9999;
      if (a["виден"] !== вКадре) {
        a["виден"] = вКадре;
        if (a["показать"]) { try { a["показать"](вКадре); } catch (e) {} }
      }
      if (вКадре) {
        живой = true;
        if (a["кадр"]) { try { a["кадр"](доля, dt, W.часы); } catch (e2) {} }
      }
    }

    if (живой) W.r.render(W.scene, W.cam);
  }

  /* ── Наружу ───────────────────────────────────────────────────*/
  g.RV_WORLD = {
    /* Модуль акта кладёт себя сюда. Договор простой и намеренно узкий:
       показать(да/нет), кадр(доля, dt, часы), размер(w, h). Всё
       остальное модуль держит у себя. */
    "акт": function (имя, модуль) {
      W.акты[имя] = модуль;
      модуль["виден"] = false;
      if (модуль["собрать"]) работа("акт " + имя, function () { модуль["собрать"](W); });
      крутить();
    },
    "мир": function () { return W; },
    "работа": работа,
    "прогрев": function () {
      return { "сделано": сделано.slice(), "осталось": ОЧЕРЕДЬ.length };
    },
    "ступень": function () { return W.ступень; },
    "готов": function () { return W.готов; }
  };

  function старт() {
    if (!поднять()) return;
    g.addEventListener("resize", поРазмеру);
    if (g.visualViewport) g.visualViewport.addEventListener("resize", поРазмеру);
    g.requestAnimationFrame(кадр);
    крутить();
  }

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", старт);
  else старт();
})(window, document);
