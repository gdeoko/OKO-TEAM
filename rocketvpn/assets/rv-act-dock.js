/* Rocket VPN. Акт 6 «Стыковка»: вторые ворота, в космос Rocket CDN.

   ЧТО ЗДЕСЬ ПРОДАЁТСЯ. Не баннер «у нас есть партнёр», а то, что оба
   сайта делят одну вселенную. Поэтому переход показан ТЕМ ЖЕ приёмом,
   которым сайт уже один раз ударил человека в акте 3, - проколом. Тот же
   ход пространства, та же механика, другой ЦВЕТ: бирюза #30A8D8 вместо
   индиго. Бирюза на этом сайте не появляется больше нигде, и именно
   поэтому она читается как «чужая сторона», без второго акцента.

   ПОЧЕМУ ПРОКОЛ ВЫНЕСЕН В ОБЩИЙ ПРИЁМ. Проколов на сайте два: акт 3
   (индиго, вход в тоннель) и этот (бирюза, выход к соседям). Написать
   их двумя разными шейдерами значит завести два разных закона
   искривления в одной вселенной, и человек это почувствует, даже не
   поняв чем. Поэтому здесь объявлен ОДИН приём - RV_ПРОКОЛ, - у него
   параметром цвет и середина, и акт 3 обязан брать его же. Кто из двух
   файлов доедет первым, тот приём и ставит; второй берёт готовый.

   ПОЧЕМУ КАМЕРА СТОИТ. Прокол - это движение самого ПРОСТРАНСТВА.
   Как только камеру начинают везти навстречу, кадр превращается в
   обычный пролёт, каких много у родственного сайта. Здесь камера стоит
   ровно там, где её оставил акт «Рубка» (0, 0, 12), и складывается всё
   остальное. Совпадение точки с концом прошлого акта не случайно: акты
   живут в одной сцене, и на стыке оба короткое время в кадре. Разные
   позиции камеры дали бы на стыке рывок.

   КНОПКУ УХОДА ЭТОТ ФАЙЛ НЕ ТРОГАЕТ. Она уже есть в разметке, адрес ей
   ставит rv-link.js. Задача акта - довести до неё сценарием: прокол
   открывается, тоннель уходит в бирюзу, и подсветка ворот садится ровно
   за кнопку, так что нажать её оказывается единственным продолжением
   движения. Никаких своих стилей на чужой кнопке. */
(function (g, d) {
  "use strict";

  var БИРЮЗА = 0x30A8D8;   /* цвет родственного сайта, только здесь */
  var ИНДИГО = 0x8A9CFF;   /* наша сторона: корабль человека */
  var СТАЛЬ  = 0x141A34;   /* закрытые ворота, пока они закрыты */

  /* ── Приём «прокол» ───────────────────────────────────────────
     Полноэкранный шейдер. Вершины кладутся прямо в отсечённые
     координаты, поэтому положение камеры на прокол не влияет вовсе:
     это слой пространства.

     Что считает шейдер, по порядку:
     1) линза - радиус точки подтягивается к середине, и решётка стены
        изгибается внутрь, вместо того чтобы уехать вбок;
     2) кольцо - край прокола, он схлопывается по мере хода;
     3) тоннель - радиальные полосы, идущие навстречу, включаются во
        второй половине хода;
     4) ядро - свет с той стороны.

     Дешёвый режим отключает ТОЛЬКО полосы тоннеля. Кольцо, линза и
     ядро остаются на любом железе: отказ в самом содержимом кадра - это
     ровно та ошибка, на которой обожглись в родственном проекте. */
  /* ИМЕНА ВНУТРИ ШЕЙДЕРА - ЛАТИНИЦЕЙ, И ЭТО НЕ ОТСТУПЛЕНИЕ ОТ СТИЛЯ.
     GLSL допускает в именах только латиницу, цифры и подчёркивание;
     кириллическое имя он не «набирает плохо», он отказывается собирать
     программу целиком, и весь акт уходит в чёрный экран. Поймано ровно
     так: сборщик шейдера ответил «syntax error» на первой же строке с
     varying. Поэтому здесь короткий словарь и дальше латиница:
       prog   - ход прокола 0..1     ring   - кольцо входа
       aspect - соотношение сторон   wall   - решётка стены
       center - середина прокола     tunnel - полосы тоннеля
       power  - общая сила слоя      core   - свет с той стороны
       cheap  - дешёвый режим */
  var ВЕРШИНЫ = [
    "varying vec2 vUv;",
    "void main() {",
    "  vUv = uv;",
    "  gl_Position = vec4(position.xy, 0.0, 1.0);",
    "}"
  ].join("\n");

  var ТОЧКИ = [
    "precision highp float;",
    "varying vec2 vUv;",
    "uniform float prog;",
    "uniform float time;",
    "uniform float aspect;",
    "uniform float power;",
    "uniform float cheap;",
    "uniform vec2  center;",
    "uniform vec3  tint;",

    "void main() {",
    "  vec2 p = vUv - center;",
    "  p.x *= aspect;",
    "  float r = length(p);",
    "  vec2 n = r > 0.0001 ? p / r : vec2(1.0, 0.0);",
    "  float a = atan(p.y, p.x);",

    /* Кольцо схлопывается: вход был широким и стал точкой. */
    "  float R = mix(0.42, 0.11, prog);",

    /* Ранний выход. Дальше 0.72 от середины все четыре слагаемых уже
       нулевые: стена гаснет к 0.66, кольцо живёт до 0.52, тоннель до
       0.67. Считать их там - это чистая переработка на каждый пиксель
       полноэкранного слоя, а слой полноэкранный по построению. Прокол и
       так самый дорогой кадр сайта, и это названо риском в плане. */
    "  if (r > 0.72) { gl_FragColor = vec4(0.0); return; }",

    /* Линза. Тянем радиус к середине тем сильнее, чем дальше ход. */
    "  float pull = prog * (0.30 + 0.45 * prog);",
    "  float r2 = max(0.0, r - pull * R * R / (r + R * 0.5));",
    "  vec2 q = n * r2;",

    /* Стена: та же решётка, что человек разглядывал в начале сайта.
       Здесь она изгибается и уходит в прокол. */
    "  vec2 cell = q * 7.0;",
    "  vec2 f = abs(fract(cell) - 0.5);",
    "  float grid = 1.0 - smoothstep(0.0, 0.05, min(f.x, f.y));",
    "  float wall = grid * (1.0 - smoothstep(0.18, 0.66, r)) * (1.0 - prog * 0.55);",

    /* Кольцо входа. */
    "  float ring = 1.0 - smoothstep(0.0, 0.05 + 0.05 * prog, abs(r - R));",
    "  ring *= 0.6 + 0.4 * sin(time * 2.2);",

    /* Тоннель. */
    "  float t = smoothstep(0.12, 0.62, prog);",
    "  float tunnel = 0.0;",
    "  if (cheap < 0.5 && t > 0.004) {",
    "    float sd = fract(sin(floor(a * 11.0) * 7.13) * 43758.5453);",
    "    float ph = fract(-r * 3.0 + time * (0.35 + sd * 0.5) + sd * 3.0);",
    "    tunnel = pow(1.0 - abs(ph * 2.0 - 1.0), 6.0);",
    "    tunnel *= smoothstep(R * 1.6, 0.03, r) * t;",
    "  }",

    /* Свет с той стороны. */
    "  float core = smoothstep(R * 1.05, 0.0, r) * t;",

    "  float lum = (wall * 0.8 + ring * 1.45 + tunnel * 1.05 + core * 0.8) * power;",
    "  gl_FragColor = vec4(tint * lum, lum);",
    "}"
  ].join("\n");

  if (!g.RV_ПРОКОЛ) {
    g.RV_ПРОКОЛ = {
      "сделать": function (T, цвет, дёшево) {
        var поле = {
          "prog":   { value: 0 },
          "time":   { value: 0 },
          "aspect": { value: 1 },
          "power":  { value: 1 },
          "cheap":  { value: дёшево ? 1 : 0 },
          "center": { value: new T.Vector2(0.5, 0.5) },
          "tint":   { value: new T.Color(цвет) }
        };
        var м = new T.ShaderMaterial({
          uniforms: поле,
          vertexShader: ВЕРШИНЫ,
          fragmentShader: ТОЧКИ,
          transparent: true,
          depthTest: false,
          depthWrite: false,
          blending: T.AdditiveBlending
        });
        var меш = new T.Mesh(new T.PlaneGeometry(2, 2), м);
        /* Вершины уже в отсечённых координатах, обычная отбраковка по
           объёму видимости выкинула бы этот слой из кадра целиком. */
        меш.frustumCulled = false;
        меш.renderOrder = -1;
        return { "узел": меш, "поле": поле, "мат": м };
      }
    };
  }

  /* ── Состояние акта ───────────────────────────────────────────*/
  var W = null, T = null;
  var корень = null, прокол = null;
  var воротаГруппа = null, воротаЗакрыты = null, воротаОткрыты = null, марка = null;
  /* Диафрагма люка, бирюзовый свет в проёме, вспышка стыковки и
     прошлая доля захода корабля: по ней ловится момент, когда корабль
     пересёк порог, чтобы событие ушло один раз на пересечение. */
  var лепестки = null, светВорот = null, базаСвета = 0, вспышка = null, былоП = 0;
  var корабль = null, ореолКнопки = null;
  var материалы = [], подписи = [];
  var собран = false, видим = false;

  var раскладка = { серX: 0.7, серY: 0.5, сила: 1, ореол: 1 };
  var мир = { halfH: 5.85, halfW: 9.36, наПиксель: 0.013, ш: 1440, в: 900 };
  var кнопка = null;

  function зажать(v, a, b) { return v < a ? a : (v > b ? b : v); }
  function плавно(t) { t = зажать(t, 0, 1); return t * t * (3 - 2 * t); }
  function отрезок(д, a, b) { return плавно((д - a) / (b - a)); }

  function мат(цвет, прозр, добавочно) {
    var м = new T.MeshBasicMaterial({ color: цвет, transparent: true, opacity: прозр });
    if (добавочно) { м.blending = T.AdditiveBlending; м.depthWrite = false; }
    материалы.push([м, прозр]);
    return м;
  }

  function спрайт(рисовать, шПикс, вПикс, шМира) {
    var c = d.createElement("canvas");
    c.width = шПикс; c.height = вПикс;
    var кон = c.getContext("2d");
    var тек = new T.CanvasTexture(c);
    /* Глубину проверяем. Выключенная проверка ставит подпись поверх
       всего кадра независимо от её места в пространстве: подписи с
       дальней стороны причала выходили наружу сквозь корабль и
       ворота. Запись в буфер остаётся выключенной - подпись это
       плёнка без толщины и загораживать соседей не должна. */
    var м = new T.SpriteMaterial({ map: тек, transparent: true, opacity: 1,
                                   depthTest: true, depthWrite: false });
    материалы.push([м, 1]);
    var s = new T.Sprite(м);
    s.scale.set(шМира, шМира * вПикс / шПикс, 1);
    s.renderOrder = 12;
    var о = { узел: s, мат: м, перерисовать: function () {
      кон.clearRect(0, 0, шПикс, вПикс);
      рисовать(кон, шПикс, вПикс);
      тек.needsUpdate = true;
    } };
    о.перерисовать();
    подписи.push(о);
    return о;
  }

  /* Корабль человека. Тот же гранёный силуэт, что причаливал в рубке:
     через прокол уходит именно он, безымянной стрелке тут не место. Геометрия
     повторена здесь намеренно - модули актов не знают друг о друге, и
     общая на двоих деталь связала бы их порядком загрузки. */
  /* ── Корабль ПРЕДМЕТОМ ────────────────────────────────────────
     Корабль человека был двумя конусами, потом стал снимком на
     плоскости. Снимок держался на одном доводе: в кадре корабль
     уходит от камеры, значит разворота вокруг вертикали не будет, и
     плоскость сойдёт за предмет. Довод неверный. Ворота стоят под
     углом, камера ведёт корабль взглядом, и на заходе сбоку плоскость
     выдаёт себя: у предмета видна вторая сторона, у картинки нет.
     Приёмка записала это коротко: «плоский спрайт корабля у люка».

     Теперь корабль это модель. Снята с фотографии тем же ходом, что и
     станция в акте «Выход»: подробный снимок с однотонным фоном через
     рабочего GPT, из него меш на карте, сварка вершин и срез до
     шестнадцати тысяч треугольников. В кадре он маленький, и больше
     ему не нужно: файл 288 КБ.

     Нос модели смотрит по её собственной оси X, а акту нужен нос по
     локальной Z - тогда в кадре хватает lookAt на середину прокола, и
     корабль всегда идёт носом вперёд. Разворачиваем ГЕОМЕТРИЮ один
     раз при загрузке; поворот узла в каждом кадре стоил бы того же
     каждый кадр.

     Не доехала модель - остаются прежние конусы: связка важнее
     красоты, и акт не имеет права остаться без корабля. */
  var КОРПУС_ВЕРШ = [
    "varying vec3 vN;",
    "varying vec3 vI;",
    "void main() {",
    "  vec4 mir = modelMatrix * vec4(position, 1.0);",
    "  vN = normalize(mat3(modelMatrix) * normal);",
    "  vI = normalize(cameraPosition - mir.xyz);",
    "  gl_Position = projectionMatrix * viewMatrix * mir;",
    "}"
  ].join("\n");
  /* Имена внутри шейдера латиницей: кириллица в GLSL это не плохой
     стиль, а отказ собрать программу. Тот же урок уже стоил акту
     «Выход» пропавших станций. */
  var КОРПУС_ФРАГ = [
    "uniform vec3 cvet;",
    "uniform vec3 kant;",
    "uniform float sila;",
    "varying vec3 vN;",
    "varying vec3 vI;",
    "void main() {",
    /* Свет придуманный и постоянный: в акте нет ни одного источника,
       и заводить их ради одного предмета дороже, чем сосчитать
       ламберта здесь. Направление выбрано так, чтобы освещённой была
       та сторона, которая в кадре повёрнута к человеку. */
    "  vec3 sun = normalize(vec3(-0.42, 0.66, 0.62));",
    "  float s = max(dot(vN, sun), 0.0);",
    "  vec3 c = cvet * (0.30 + 0.86 * s);",
    "  vec3 refl = reflect(-sun, vN);",
    "  float spec = pow(max(dot(refl, normalize(vI)), 0.0), 22.0);",
    "  c += kant * spec * 0.55;",
    /* Кромка обязательна: корабль летит на чёрном поле прокола, и без
       неё тёмная его половина сливается с фоном в силуэт без объёма. */
    "  float kr = pow(1.0 - max(dot(vN, normalize(vI)), 0.0), 2.0);",
    "  c += kant * kr * 0.60;",
    "  gl_FragColor = vec4(c, sila);",
    "  #include <colorspace_fragment>",
    "}"
  ].join("\n");

  function корабльМоделью(г) {
    if (!g.RV_GLB || !g.RV_GLB.взятьМодель) return;
    /* Корабль настоящий: орбитальный аппарат из открытого архива NASA
       (общественное достояние) с золотой фольгой, антенной и панелями
       батарей. Развёрнут антенной по +Z и ужат до 2.3 единиц при
       сборке файла, поэтому здесь ни разворота, ни подгона. */
    g.RV_GLB.поБлизости("стыковка").then(function () {
      return g.RV_GLB.взятьМодель("assets/gen/корабль-орбитер.glb", {
        отражения: 1.25, анизотропия: 4, свет: 0x141C48, прибавка: 0.4,
        рисовальщик: W && W.r
      });
    }).then(function (модель) {
      if (!г.parent && !г.children.length) return;
      модель.scale.setScalar(0.82);
      /* Фольга аппарата на фотографии золотая, и в индиговом мире он
         читался чужим: рыжие панели среди синего и бирюзы. Цвет
         материала умножается на карту, поэтому холодный множитель
         гасит красный и жёлтый каналы, а фактура фольги и швов
         остаётся. Зелёный и синий держатся высоко, чтобы аппарат
         остался светлым и читался предметом, а не тенью. */
      /* Одного множителя мало, и это проверено снимком: в золотой
         карте синего почти нет, и умножение на холодный цвет даёт
         хаки, а не серебро. Синеву добавляет ровное свечение: жар()
         у этой модели никто не зовёт, поэтому оно не перебивается. */
      var хм = модель.материалы || [];
      for (var м = 0; м < хм.length; м++) {
        if (!хм[м] || !хм[м].color) continue;
        хм[м].color.setRGB(0.42, 0.58, 1.0);
        if (хм[м].emissive) {
          хм[м].emissive.setRGB(0.08, 0.13, 0.30);
          хм[м].emissiveIntensity = 1;
        }
      }
      г.add(модель);
      for (var i = г.children.length - 2; i >= 0; i--) {
        var о = г.children[i];
        г.remove(о);
        if (о.geometry) о.geometry.dispose();
        /* Материал конусов тоже уходит: мат() записал его в общий
           список, и кадр продолжал бы каждый раз писать прозрачность
           в предмет, которого в сцене уже нет, а программа шейдера
           жила бы в видеопамяти до конца сессии. */
        if (о.material) {
          for (var k = материалы.length - 1; k >= 0; k--) {
            if (материалы[k][0] === о.material) материалы.splice(k, 1);
          }
          о.material.dispose();
        }
      }
    }).catch(function () {});
  }

  function кораблик() {
    var г = new T.Group();
    /* Геометрию разворачиваем ОДИН раз при сборке, чтобы нос смотрел по
       локальной оси Z. Тогда в кадре хватает lookAt на середину прокола,
       и корабль всегда идёт носом вперёд - в том числе на заходе сбоку.
       Без этого разворота он летел бы боком, а на оси прокола вырождался
       бы в точку: видно только сопло. */
    var гТело = new T.CylinderGeometry(0.03, 0.115, 0.52, 6);
    гТело.rotateX(Math.PI / 2);
    г.add(new T.Mesh(гТело, мат(ИНДИГО, 0.95)));
    var гХвост = new T.CylinderGeometry(0.085, 0.03, 0.16, 6);
    гХвост.rotateX(Math.PI / 2);
    гХвост.translate(0, 0, -0.33);
    г.add(new T.Mesh(гХвост, мат(ИНДИГО, 0.5, true)));
    корабльМоделью(г);
    return г;
  }

  /* Раскрытие диафрагмы. Лепестки идут по очереди с малым запозданием
     каждый: одна общая доля на все восемь читается щелчком затвора
     вместо хода механизма. Ход с перелётом (easeOutBack): железо приходит в
     упор и чуть отдаёт назад, как настоящая заслонка. Матрица каждого
     лепестка: поворот по кругу, сдвиг к ободу, наклон вокруг своей
     радиальной оси, и порядок именно такой. */
  var мЛеп = null, мКруг = null, мСдвиг = null;
  var мСгиб = null, мСжатие = null, мШарнир = null;
  /* Шарнир лепестка чуть внутрь от края дуги (дуга до 0.97, её концы по
     радиальной оси стоят на 0.885). Ось сгиба прямая, а край дугой, и при
     шарнире на самом краю концы дуги после сгиба выходили на радиус 1.19
     (замер по вершинам): за трубу тора, клиньями. При 0.93 концы и
     середина дуги остаются в толще трубы (0.9..1.1 на этой глубине). */
  var ШАРНИР = 0.93;
  function раскрыть(доля) {
    if (!мЛеп) {
      мЛеп = new T.Matrix4(); мКруг = new T.Matrix4();
      мСдвиг = new T.Matrix4();
      мСгиб = new T.Matrix4(); мСжатие = new T.Matrix4(); мШарнир = new T.Matrix4();
      мШарнир.makeTranslation(-ШАРНИР, 0, 0);
    }
    for (var i = 0; i < 8; i++) {
      var t = зажать(доля * 1.4 - i * 0.057, 0, 1);
      var e = 1 + 2.70158 * Math.pow(t - 1, 3) + 1.70158 * Math.pow(t - 1, 2);
      мКруг.makeRotationZ(i * Math.PI / 4);
      /* Лепесток складывается ОТ камеры, в чужую сторону, на шарнире у
         обода. Прежний наклон вокруг радиальной оси до ребра выносил
         широкий край сектора на 0.4 к камере, и в перспективе лепестки
         торчали за кольцо лопастями турбины (снимки приёмки на 0.3 и
         0.35). Всё, что уходит от камеры, в проекции только сжимается к
         середине кадра, поэтому сложенный назад лепесток за обод не
         выходит ни под каким углом. Наклона вокруг своей оси нет вовсе:
         даже 0.2 рад разводили широкий край у шарнира по глубине на
         0.09, и после сгиба это уходило в радиус, за трубу. Сдвиг к
         ободу тоже малый, по той же причине. */
      мСдвиг.makeTranslation(ШАРНИР + 0.03 * e, 0, 0);
      мСгиб.makeRotationY(-1.5 * e);
      /* В конце хода лепесток втягивается в трубу обода по своей длине:
         так к полному раскрытию его уже нет в проёме, и снятие лепестков
         с кадра (visible) не читается прыжком. Без перелёта: сжатие
         считается по чистой доле, иначе длина ушла бы в минус. */
      var втяг = плавно((t - 0.55) / 0.45);
      мСжатие.makeScale(1 - 0.86 * втяг, 1, 1);
      мЛеп.copy(мКруг).multiply(мСдвиг).multiply(мСгиб)
          .multiply(мСжатие).multiply(мШарнир);
      лепестки.setMatrixAt(i, мЛеп);
    }
    лепестки.instanceMatrix.needsUpdate = true;
  }

  /* ── Сборка ───────────────────────────────────────────────────*/
  function строить() {
    корень = new T.Group();
    корень.visible = false;

    прокол = g.RV_ПРОКОЛ["сделать"](T, БИРЮЗА, W.ступень === 0);
    корень.add(прокол["узел"]);

    /* Ворота как предмет. Сначала это глухой люк цвета
       стали - ровно такой же стоит на щите в прошлом акте. Бирюза
       зажигается на нём здесь и впервые на всём сайте. */
    var г = new T.Group();
    var ст = W.ступень == null ? 2 : W.ступень;
    /* Люк железом, на общем физическом корпусе сайта. Плоский тор на
       MeshBasic в кадре терялся целиком за кольцом шейдера прокола
       (снимок «до»: ворот как предмета нет, есть только свет), а
       предмет, через который уходит корабль, обязан иметь массу.
       Железо ловит стан и карту окружения, и у люка появляется
       толщина. Грани по ступени: нищей хватает восьми на сорока восьми. */
    var железо = (g.RV_REAL && g.RV_REAL["корпус"])
      ? g.RV_REAL["корпус"](T, { цвет: 0x2C3350, металл: 0.9, шерох: 0.32,
                                 свет: 0x0A0F20, жар: 0.2, лак: 0.3 })
      : new T.MeshStandardMaterial({ color: 0x2C3350, metalness: 0.9, roughness: 0.32,
                                     emissive: 0x0A0F20 });
    /* Труба тора 0.17: при 0.11 железо на ПК читалось тонкой бледной
       чертой поверх свечения шейдера, и ворота оставались плоским
       сиянием со спицами (снимок глаза владельца, доли 0.6 и 0.9).
       Губа стоит на 0.85, и труба 0.83..1.17 её не накрывает. */
    воротаЗакрыты = new T.Mesh(
      new T.TorusGeometry(1, 0.17, ст === 0 ? 8 : 20, ст === 0 ? 48 : 96), железо);
    г.add(воротаЗакрыты);
    /* Лёгкий разворот люка к камере: кольцо ровно в плоскости кадра
       проецируется в окружность и ничем не отличается от нарисованной;
       под углом у трубы появляется ближний и дальний край, и железо
       читается телом. Угол малый, чтобы лепестки в закрытом виде
       по-прежнему накрывали ядро прокола. */
    г.rotation.set(0.14, -0.18, 0);

    /* Диафрагма: восемь лепестков-секторов одним вызовом. Сектор от
       втулки до самого тора с нахлёстом в пару градусов: закрытый люк
       глухой, без щелей, иначе сквозь него просвечивает ядро прокола
       и «закрыто» не читается. В раскрытии каждый лепесток
       складывается на шарнире у обода в чужую сторону и втягивается в
       трубу (см. раскрыть()): так люк открывается в проём, а не
       наружу, и ничего не торчит за кольцо. Раскрытие - чистая функция
       доли, прокрутка назад отматывает. */
    var форма = new T.Shape();
    var а0 = -Math.PI / 8 - 0.03, а1 = Math.PI / 8 + 0.03;
    форма.absarc(0, 0, 0.14, а0, а1, false);
    форма.absarc(0, 0, 0.97, а1, а0, true);
    var гЛеп = new T.ExtrudeGeometry(форма, { depth: 0.04, bevelEnabled: false,
                                              curveSegments: ст === 0 ? 4 : 10 });
    гЛеп.translate(0, 0, -0.02);
    лепестки = new T.InstancedMesh(гЛеп, железо, 8);
    /* Отбраковку по объёму снимаем: сфера у геометрии одного сектора,
       а восемь секторов расходятся кругом шире её. */
    лепестки.frustumCulled = false;
    г.add(лепестки);
    раскрыть(0);

    /* Губа люка: тонкое кольцо по внутренней кромке тора, единственное
       на сайте место, где зажигается бирюза. Без тонирования и с
       цветом выше единицы: ореол плёнки ловит именно то, что ярче
       порога, и губа расплывается в свет сама, без второго спрайта. */
    воротаОткрыты = new T.Mesh(
      new T.TorusGeometry(0.85, 0.03, 8, ст === 0 ? 48 : 96),
      new T.MeshBasicMaterial({ color: БИРЮЗА, transparent: true, opacity: 0,
                                toneMapped: false, depthWrite: false }));
    /* Радиус 0.85 и вынос к камере на 0.06: труба тора занимает 0.89..1.11
       по радиусу, и губа радиусом 0.93 сидела целиком внутри железа, её не
       было видно нигде (приёмка спрятала тор, и бирюза сразу появилась).
       Теперь кольцо стоит в самом проёме, перед закрытыми лепестками
       (они в плоскости z ±0.02), и в эпилоге кольцо проходит мимо камеры
       бирюзой вместо тёмного железа. */
    воротаОткрыты.position.z = 0.06;
    г.add(воротаОткрыты);

    /* Бирюзовый отсвет в проёме. Корабль, проходящий сквозь люк, ловит
       его на обшивке: модель с настоящими картами ответит сама, и «наш
       корабль на их стороне» читается по цвету отражений без подписи.
       Дальность 12: до щита рубки полторы сотни единиц, не достанет.
       На нищей ступени света нет: точечный источник дорожает каждому
       физическому материалу в кадре. Сила в канделах нынешнего three:
       названные планом 3.0 и 1.6 ушли бы в ноль на второй единице
       расстояния, поэтому они помножены на шесть. */
    if (ст > 0) {
      базаСвета = (ст === 2 ? 3.0 : 1.6) * 6;
      светВорот = new T.PointLight(БИРЮЗА, 0, 12, 2);
      корень.add(светВорот);
    }

    /* Вспышка стыковки: корабль коснулся порога. Короткая, в пятно
       ворот, поверх всего: событие должно ударить по глазу один раз. */
    var вх = d.createElement("canvas");
    вх.width = 128; вх.height = 128;
    var вк = вх.getContext("2d");
    var вг = вк.createRadialGradient(64, 64, 0, 64, 64, 64);
    вг.addColorStop(0, "rgba(235,250,255,0.95)");
    вг.addColorStop(0.3, "rgba(48,168,216,0.5)");
    вг.addColorStop(1, "rgba(48,168,216,0)");
    вк.fillStyle = вг; вк.fillRect(0, 0, 128, 128);
    вспышка = new T.Sprite(new T.SpriteMaterial({ map: new T.CanvasTexture(вх), transparent: true,
                                                  opacity: 0, depthTest: false, depthWrite: false,
                                                  blending: T.AdditiveBlending }));
    вспышка.renderOrder = 13;
    корень.add(вспышка);
    марка = спрайт(function (кон, ш, в) {
      кон.textAlign = "center"; кон.textBaseline = "middle";
      try { кон.letterSpacing = "5px"; } catch (e) {}
      кон.font = "700 34px 'Golos Text', system-ui, -apple-system, sans-serif";
      кон.fillStyle = "rgba(232,234,246,0.92)";
      кон.fillText("ROCKET CDN", ш / 2, в * 0.42);
      try { кон.letterSpacing = "2px"; } catch (e2) {}
      кон.font = "600 17px 'Golos Text', system-ui, -apple-system, sans-serif";
      кон.fillStyle = "rgba(48,168,216,0.9)";
      кон.fillText("ВТОРЫЕ ВОРОТА", ш / 2, в * 0.78);
    }, 384, 128, 2.6);
    /* Подпись НЕ ребёнок ворот. Ворота схлопываются вместе с проколом, и
       вложенная подпись сжималась бы с ними в пятно; она живёт в мире
       своим размером и просто гаснет, когда ворота перестают быть
       предметом. */
    корень.add(марка.узел);
    корень.add(г);
    воротаГруппа = г;

    корабль = кораблик();
    корабль.visible = false;
    корень.add(корабль);
    /* Свой свет на корабль, как у щита в «рубке»: общие источники
       сцены стоят под планету и станции и бьют мимо, корабль в причале
       оставался тёмной кляксой с одним бликом (кроп акта на стенде).
       Ключ спереди слева сверху, контровой сзади снизу рисует кромку.
       Живут в корне акта, снаружи корабля: приход модели вычищает
       из группы корабля всё, кроме самой модели, и свет, положенный
       туда, исчезал вместе с заглушками (в дереве сцены его не было).
       Направленному свету место не важно, важен только вектор. */
    var ключК = new T.DirectionalLight(0xEAEFFF, 3.6);
    ключК.position.set(-2.6, 3.2, 5.0);
    корень.add(ключК); корень.add(ключК.target);
    /* Контровой тёплый вместо индиго: рифма со станом и противовес
       бирюзе, которая ложится на корабль из проёма. Два холодных
       источника сливались бы в один. */
    var кромкаК = new T.DirectionalLight(0xFFC8A2, 2.2);
    кромкаК.position.set(3.0, -2.4, -3.0);
    корень.add(кромкаК); корень.add(кромкаК.target);

    /* Подсветка кнопки ухода. Это НЕ стиль на чужой кнопке: это пятно
       света в объёмной сцене, которое садится за неё. Кнопка остаётся
       ровно такой, какой её сделала вёрстка. */
    var ог = d.createElement("canvas");
    ог.width = 128; ог.height = 128;
    var ок = ог.getContext("2d");
    var гр = ок.createRadialGradient(64, 64, 0, 64, 64, 64);
    гр.addColorStop(0, "rgba(48,168,216,0.55)");
    гр.addColorStop(0.45, "rgba(48,168,216,0.18)");
    гр.addColorStop(1, "rgba(48,168,216,0)");
    ок.fillStyle = гр; ок.fillRect(0, 0, 128, 128);
    var ом = new T.SpriteMaterial({ map: new T.CanvasTexture(ог), transparent: true,
                                    opacity: 0, depthTest: false, depthWrite: false,
                                    blending: T.AdditiveBlending });
    материалы.push([ом, 1]);
    ореолКнопки = new T.Sprite(ом);
    ореолКнопки.renderOrder = 1;
    корень.add(ореолКнопки);

    /* В гнездо станции. Прокол в сторону Rocket CDN стоит
       в тысяче единиц вглубь от начала мира - это последняя станция на
       пути камеры, и человек прилетает к ней своим ходом. */
    var гн = g.RV_WORLD && g.RV_WORLD["гнездо"] ? g.RV_WORLD["гнездо"]("стыковка") : null;
    (гн || W.scene).add(корень);
    собран = true;
    размер(g.innerWidth, g.innerHeight);
    корень.visible = видим;

    if (d.fonts && d.fonts.ready && d.fonts.ready.then) {
      d.fonts.ready.then(function () {
        for (var k = 0; k < подписи.length; k++) подписи[k].перерисовать();
      });
    }
  }

  /* ── Раскладка ────────────────────────────────────────────────
     Середина прокола не совпадает с серединой экрана. На широком экране
     слева стоит текст акта, и яркое ядро под ним съело бы читаемость,
     поэтому прокол уезжает вправо. На узком тексту деваться некуда, и
     прокол уходит вниз, под текст, к самой кнопке. */
  function размер(ш, в) {
    var широко = ш >= 1000;
    /* На узком экране прокол уходит ЗАМЕТНО ниже кнопки; нижней половины
       мало. Измерено: при середине 0.33 ядро прокола садилось
       ровно под кнопку, и контраст её подписи падал до 1.5 при пороге
       4.5. Середина 0.18 уводит ядро на две трети экрана вниз, и та же
       мерка даёт запас. Заодно ослаблены общая сила слоя и ореол:
       на узком кадре светящемуся пятну некуда разойтись. */
    /* Корабль на широком экране крупнее в два с лишним раза. Замер по
       вершинам модели на ПК 1280x820 (доля 0.6): весь корабль занимал
       56x50 точек у кромки кольца в 580 точек и читался соринкой, а
       не предметом, который уходит в ворота. На узком кадре та же
       модель и так занимает втрое большую долю ширины. */
    /* На узком кадре у корабля свой заход. Замер на телефоне 412x915
       (dpr 2): модель в единичном масштабе на доле 0.6 занимала около
       150 точек и уходила к левой кромке, а на долях 0.3 и 0.9 её не
       было вовсе - окно захода 0.42-0.88 совпадало с тем отрезком, где
       на телефоне слова ещё стоят над воротами. Окно растянуто на
       0.22-0.95, корабль крупнее в полтора раза, заходит с меньшего
       бокового выноса и к порогу ужимается вдвое слабее: на широком
       экране он уходит в кольцо в 580 точек, здесь кольцо занимает всю
       ширину, и та же усадка превращала его в соринку. */
    раскладка = широко ? { серX: 0.7, серY: 0.5,  сила: 1,    ореол: 1,   корабль: 2.3,
                           заходОт: 0.42, заходДо: 0.88, вынос: 0.30, усадка: 0.80 }
                       : { серX: 0.5, серY: 0.18, сила: 0.72, ореол: 0.5, корабль: 1.5,
                           заходОт: 0.22, заходДо: 0.95, вынос: 0.18, усадка: 0.45 };

    мир.ш = ш; мир.в = в;
    подогнать();

    /* Положение кнопки берём один раз на размер:
       кадр акта прилипший, кнопка при прокрутке не двигается, зато замер
       коробки в каждом кадре заставляет браузер пересчитывать вёрстку
       ровно там, где мы бережём частоту. */
    var э = d.getElementById("rvКcdn");
    кнопка = null;
    if (э) {
      var к = э.getBoundingClientRect();
      if (к.width > 1 && к.height > 1) {
        кнопка = { x: ((к.left + к.width / 2) / ш) * 2 - 1,
                   y: 1 - ((к.top + к.height / 2) / в) * 2,
                   ш: к.width };
      }
    }

    if (!собран) return;
    прокол["поле"]["aspect"].value = ш / в;
    прокол["поле"]["center"].value.set(раскладка.серX, раскладка.серY);
    расставить();
  }

  /* Пересчёт «доли экрана -> единицы мира». Раньше здесь стояли числа
     12 и 52 - расстояние до камеры и её угол обзора, - и они были верны
     ровно до того дня, когда камера тронулась с места. Теперь и то и
     другое спрашивается у мира каждый кадр.

     Это условие работы акта, украшением оно не служит: ореол садится ЗА кнопку
     разметки, и его мировое место считается из экранного. Ошибись в
     расстоянии на четверть - и пятно света уедет мимо кнопки. */
  function подогнать() {
    var д = 12, поле = 52;
    if (g.RV_WORLD && g.RV_WORLD["доСтанции"]) д = g.RV_WORLD["доСтанции"]("стыковка");
    if (W && W.cam) поле = W.cam.fov;
    /* Ниже разумного предела не опускаемся: на последних кадрах акта
       камера проходит сквозь ворота, расстояние идёт к нулю, и всё
       содержимое иначе схлопнулось бы в точку. */
    if (!(д > 3)) д = 3;
    мир.halfH = д * Math.tan(поле * Math.PI / 360);
    мир.halfW = мир.halfH * (мир.ш / мир.в);
    мир.наПиксель = (мир.halfH * 2) / мир.в;
  }

  /* Ворота, корабль и ореол стоят в мире, а середина прокола задана в
     долях экрана. Пересчёт из одного в другое - здесь, в одном месте. */
  function расставить() {
    var x = (раскладка.серX * 2 - 1) * мир.halfW;
    var y = (раскладка.серY * 2 - 1) * мир.halfH;
    воротаГруппа.position.set(x, y, 0);
    марка.узел.position.set(x, y, 0.4);
    корабль.position.set(x, y, 6);
    /* Свет чуть перед плоскостью люка, к камере: корабль ловит бирюзу
       уже на подходе. Вспышка в самом проёме. */
    if (светВорот) светВорот.position.set(x, y, 0.5);
    if (вспышка) {
      вспышка.position.set(x, y, 0.3);
      var вс = мир.halfH * 1.1;
      вспышка.scale.set(вс, вс, 1);
    }
    if (кнопка) {
      /* Ровно в плоскости ворот (z = 0): любое смещение по глубине
         уводит пятно от кнопки в проекции, и подсветка садится мимо. */
      ореолКнопки.position.set(кнопка.x * мир.halfW, кнопка.y * мир.halfH, 0);
      var р = кнопка.ш * мир.наПиксель * 2.4;
      ореолКнопки.scale.set(р, р, 1);
      ореолКнопки.visible = true;
    } else {
      ореолКнопки.visible = false;
    }
  }

  /* ── Кадр ─────────────────────────────────────────────────────*/
  function кадр(д, dt, часы) {
    if (!собран) return;

    /* КАМЕРУ ЭТОТ АКТ БОЛЬШЕ НЕ ТРОГАЕТ.

       Здесь стояли две строки, которые ставили камеру в ноль и гасили
       её поворот. Они были самым честным признанием того, что общего
       хода в мире нет: акт просто отбирал камеру у соседа и ставил как
       ему удобно. На стыке с «Рубкой», где оба акта короткое время в
       кадре, это давало прыжок - тот самый шов, которого ядро обещало
       не допускать.

       Теперь камера приходит сюда по общей кривой, а весь расчёт
       экранной привязки идёт от НАСТОЯЩЕГО расстояния до станции. */
    подогнать();
    расставить();

    /* Как и в «Рубке»: проявление по большему из доли акта и близости
       камеры. Доля равна нулю весь перегон, и без близости ворота
       возникали бы в кадре разом вместо того, чтобы разгораться на
       подлёте. */
    var подлёт = (g.RV_WORLD && g.RV_WORLD["наСтанции"]) ? g.RV_WORLD["наСтанции"]("стыковка", 1.15) : 0;
    var явь = Math.max(плавно(д / 0.07), подлёт) * (1 - плавно((д - 0.93) / 0.07));
    var i;
    for (i = 0; i < материалы.length; i++) материалы[i][0].opacity = материалы[i][1] * явь;

    /* Ход прокола. Он начинается не сразу: сначала человек должен
       увидеть, что ворота ЕСТЬ и что они закрыты. */
    var ход = отрезок(д, 0.2, 0.95);
    прокол["поле"]["prog"].value = ход;
    прокол["поле"]["time"].value = часы;
    прокол["поле"]["power"].value = раскладка.сила * явь;

    /* Зажигание бирюзы. Первое и единственное на сайте место, где она
       появляется, - поэтому оно и читается событием. */
    var огонь = отрезок(д, 0.06, 0.26);
    var уход = отрезок(д, 0.3, 0.55);
    /* Эпилог: камера идёт сквозь ворота, пока человек дочитывает
       подвал. Всё прочее в акте к этому моменту погашено явью, кольцо
       обязано остаться: сквозь что иначе проходить. */
    var сквозь = отрезок(д, 0.93, 1);
    /* Железо не гаснет прозрачностью: корпус непрозрачен по своему
       закону. Уход люка читается тем, что лепестки уходят из проёма и
       жар металла спадает; сам тор остаётся кольцом и схлопывается
       вместе с кольцом шейдера. */
    воротаГруппа.visible = явь > 0.02 || сквозь > 0;
    if (воротаЗакрыты.material.жар) воротаЗакрыты.material.жар(огонь * 0.9 * (1 - уход * 0.6));
    /* Губа: цвет растёт с огнём выше единицы, чтобы ореол плёнки его
       подхватил; до огня она едва тлеет, и «закрыто» читается железом. */
    var пульс = 0.55 + 0.45 * Math.sin(часы * 2.4);
    var яркость = (0.2 + 4.5 * огонь) * (0.7 + 0.3 * пульс);
    воротаОткрыты.material.color.setRGB(0.188 * яркость, 0.659 * яркость, 0.847 * яркость);
    воротаОткрыты.material.opacity = Math.max(явь * (0.15 + 0.85 * огонь) * (1 - 0.5 * уход),
                                              0.55 * сквозь);
    /* Диафрагма: раскрывается позже, чем зажигается губа, и к
       середине акта проём чист; корабль подходит к плоскости люка
       ещё позже, к 0.7. К концу хода лепестки сложены за обод и втянуты
       в трубу, и снять их с кадра можно, не выдав этого глазу. */
    var раскрытие = отрезок(д, 0.10, 0.50);
    лепестки.visible = воротаГруппа.visible && раскрытие < 0.999;
    if (лепестки.visible) раскрыть(раскрытие);
    /* Свет не гаснет с уходом люка: он и нужен тогда, когда корабль
       проходит проём, а это доля 0.6 и дальше. */
    if (светВорот) светВорот.intensity = базаСвета * огонь * явь;
    марка.мат.opacity = явь * плавно(д / 0.1) * (1 - отрезок(д, 0.34, 0.52));

    /* Кольцо ворот схлопывается вместе с кольцом в шейдере: предмет и
       слой пространства обязаны идти одним движением, иначе видно, что
       их двое. */
    var м = 1 - 0.74 * ход;
    if (сквозь > 0) {
      /* В эпилоге кольцо растёт навстречу камере и расходится мимо
         неё; без этого оно съёживалось в точку под подвалом. Расстояние берём
         настоящее, без нижней планки из подогнать(): планка там
         спасает раскладку, а здесь нужен именно проход сквозь. */
      var до = (g.RV_WORLD && g.RV_WORLD["доСтанции"]) ? g.RV_WORLD["доСтанции"]("стыковка") : 12;
      if (!(до > 0.2)) до = 0.2;
      м = м * (1 - сквозь) + Math.max(0.26, 1.2 / до) * сквозь;
    }
    воротаГруппа.scale.setScalar(м * (мир.halfH * 0.84));

    /* Корабль человека уходит насквозь. Индиго в бирюзовом проколе -
       это и есть картинка связки: наш корабль на их стороне. */
    var п = отрезок(д, раскладка.заходОт || 0.42, раскладка.заходДо || 0.88);
    корабль.visible = п > 0.001 && п < 0.999;
    if (корабль.visible) {
      var x = (раскладка.серX * 2 - 1) * мир.halfW;
      var y = (раскладка.серY * 2 - 1) * мир.halfH;
      /* Заходит сбоку и снизу: корабль, летящий
         точно в середину прокола, с первого кадра стоит в самой яркой
         точке кадра и не читается вовсе. */
      /* Заход считаем в ДОЛЯХ кадра. Постоянные единицы мира отпали:
         на телефоне кадр вчетверо уже, и постоянный отступ в 2.2 единицы
         выносил корабль за левую кромку экрана. */
      /* Заходит СВЕРХУ слева и снижается к середине прокола. Направление
         выбрано не на глаз: на снимке нос корабля смотрит вправо и вниз,
         и полёт обязан идти туда же, куда смотрит нос. При заходе снизу
         корабль летел бы хвостом вперёд, и никакой доворот плоской
         картинки этого не чинит - доворот на шестьдесят градусов кладёт
         корабль набок. */
      /* На широком экране корабль ещё и ближе к камере на старте
         захода: крупный предмет вдали читается как большой, а близкий
         как летящий мимо зрителя в ворота. К порогу разница сходит на
         нет, и порог он проходит на той же глубине. */
      var кк = раскладка.корабль || 1;
      var вынос = раскладка.вынос || 0.30;
      корабль.position.set(x - мир.halfW * вынос * (1 - п),
                           y + мир.halfH * 0.34 * (1 - п),
                           2.5 - 4.0 * п + (кк - 1) * 1.2 * (1 - п));
      /* Втягивание: на последнем отрезке корабль вытягивается вдоль
         хода, как всё, что попадает в прокол. Ось Z локальная и
         совпадает с направлением полёта. */
      var р = (1.05 - п * (раскладка.усадка || 0.80)) * кк;
      корабль.scale.set(р, р, р * (1 + 1.5 * отрезок(п, 0.85, 1)));
      /* Крен на заходе и доворот носа к середине проёма: корабль снова
         предмет с объёмом, и заход сбоку без крена читался бы
         полётом по рельсу. К порогу и то и другое сходит на нет. */
      корабль.rotation.set(0, 0.25 * (1 - п),
                           -0.35 * (1 - п) * (1 - п) + Math.sin(часы * 0.7) * 0.035);
    }
    /* Событие стыковки: корабль коснулся порога. Вспышка в проёме и
       одно сообщение наружу на пересечение, плёнке и звуку есть за
       что зацепиться. Обратная прокрутка событие не повторяет. */
    вспышка.material.opacity = явь * Math.exp(-Math.pow((п - 0.88) / 0.03, 2));
    if (п >= 0.88 && былоП < 0.88 && явь > 0.01) {
      try {
        g.dispatchEvent(new CustomEvent("rv:стыковка", { detail: { сила: 0.5 } }));
      } catch (e) {}
    }
    былоП = п;

    /* Ореол за кнопкой. Он приходит тогда же, когда тоннель, - к этому
       моменту нажать кнопку и есть продолжение движения. */
    if (ореолКнопки.visible) {
      /* Пульс привязан и к ходу прокола: при прокрутке ореол дышит
         вместе с тоннелем. */
      ореолКнопки.material.opacity = отрезок(д, 0.45, 0.8) * явь * раскладка.ореол *
        (0.72 + 0.28 * Math.sin(часы * 2.0 + ход * 6));
    }
  }

  /* ── Договор с ядром ──────────────────────────────────────────*/
  var АКТ = {
    "собрать": function (мирЯдра) {
      W = мирЯдра;
      T = мирЯдра && мирЯдра.T;
      if (!T) return;
      строить();
    },
    "показать": function (да) {
      видим = да;
      if (корень) корень.visible = да;
      /* Пока ворота в кадре, помечаем документ. Своих стилей на чужой
         кнопке этот файл не ставит, но вёрстке должно быть чем зацепиться,
         если она захочет. */
      d.documentElement.setAttribute("data-ворота", да ? "в кадре" : "");
      /* Кнопка появляется вместе с актом, и её коробку надо замерить
         тогда, когда она уже разложена. */
      if (да) размер(g.innerWidth, g.innerHeight);
    },
    "кадр": кадр,
    "размер": размер
  };

  function встать() {
    /* ПОЗА АКТА. Последняя станция мира, в тысяче с лишним единиц
       вглубь от начала. Перегон от рубки сюда короткий (полторы сотни
       против трёх с половиной от выхода к рубке) - и это намеренно:
       финал не должен читаться как ещё один длинный перелёт, он должен
       читаться как «пришли».

       Эпилог в тридцать единиц уводит камеру СКВОЗЬ ворота, пока
       человек дочитывает подвал. Ход не обрывается на последнем акте:
       обрыв прочитался бы как конец плёнки, а по сценарию человек
       уходит в чужой космос без стены впереди. */
    g.RV_WORLD["поза"]("стыковка", {
      "на": [-30, 16, -1050],
      "от": [-34.28, 17.77, -1038.93],
      "подход": 5,
      "уход": -3,
      "поле": [52, 52, 52],
      /* Вбок ноль: весь акт держится на экранной привязке (ореол сидит
         за кнопкой разметки), а дуга увела бы ворота от кнопки. */
      "бок": [0, 0, 0],
      "крен": [0.03, 0, 0],
      "эпилог": 30
    });
    g.RV_WORLD["акт"]("стыковка", АКТ);
  }
  if (g.RV_WORLD && g.RV_WORLD["готов"]()) встать();
  else g.addEventListener("rv:мир", встать);
})(window, document);
