    var Ш = 1024, В = 1024;
    var c = d.createElement("canvas");
    c.width = Ш; c.height = В;
    var x = c.getContext("2d");

    var база = x.createLinearGradient(0, 0, Ш, 0);
    база.addColorStop(0.00, "#3A3F46");
    база.addColorStop(0.22, "#5C636C");
    база.addColorStop(0.50, "#464C54");
    база.addColorStop(0.78, "#626972");
    база.addColorStop(1.00, "#3A3F46");
    x.fillStyle = база;
    x.fillRect(0, 0, Ш, В);

    /* Шлифовка: борозды вдоль корпуса. Именно она отличает обработанный
       металл от заливки одним тоном. */
    var i;
    for (i = 0; i < 3400; i++) {
      x.globalAlpha = 0.030 + сл() * 0.055;
      x.fillStyle = сл() > 0.5 ? "#7C8B9C" : "#1A222C";
      x.fillRect(сл() * Ш, сл() * В, 1 + сл() * 4, 1);
    }
    /* Следы работы: потёртости у стыков и осевшая копоть. */
    for (i = 0; i < 130; i++) {
      x.globalAlpha = 0.05 + сл() * 0.10;
      x.fillStyle = сл() > 0.45 ? "#0E141C" : "#8A99AB";
      x.fillRect(сл() * Ш, сл() * В, 6 + сл() * 48, 2 + сл() * 10);
    }
    x.globalAlpha = 1;

    /* Продольные швы обшивки. */
    x.strokeStyle = "rgba(12,18,28,.55)";
    x.lineWidth = 2;
    for (i = 0; i < 8; i++) {
      var px = (i / 8) * Ш;
      x.beginPath(); x.moveTo(px, 0); x.lineTo(px, В); x.stroke();
    }

    /* Фирменные кольца. v ноль это сопло, единица нос, по холсту
       y = (1 - v) * В. */
    var гр = x.createLinearGradient(0, (1 - 0.80) * В, 0, (1 - 0.74) * В);
    гр.addColorStop(0, "#5BC4EA");
    гр.addColorStop(1, "#0A5897");
    x.fillStyle = гр;
    x.fillRect(0, (1 - 0.80) * В, Ш, 0.06 * В);

    гр = x.createLinearGradient(0, (1 - 0.20) * В, 0, (1 - 0.13) * В);
    гр.addColorStop(0, "#0A5897");
    гр.addColorStop(1, "#5BC4EA");
    x.fillStyle = гр;
    x.fillRect(0, (1 - 0.20) * В, Ш, 0.07 * В);

