/* Rocket VPN. Слова акта живут в сцене, а не поверх неё.

   ЗАЧЕМ. Владелец: «механика текста вообще не красивая, ни цвет ни шрифт
   не связка с моушеном миром 3д ничего не сделано». И раньше: «текста
   нету вообще как у igloo текст = код да?».

   Так и есть. У igloo в разметке пусто, весь текст нарисован в сцене
   полем расстояний. Пока текст лежит слоем поверх холста, он остаётся
   плакатом, приклеенным к стеклу: у него своя типографика, свой цвет,
   своя анимация, и с миром за стеклом он не связан ничем.

   ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ. Берёт слова, уже написанные в разметке, и
   переносит их в сцену: заголовок, надзаголовок, абзац и карточки
   становятся объёмными объектами рядом с предметом акта. Разметка
   остаётся на месте и служит источником правды - её читают поисковик и
   голосовой помощник, а человек видит объём.

   ПОЧЕМУ ИСТОЧНИК В РАЗМЕТКЕ, А НЕ В КОДЕ. У igloo текст зашит в
   бандл, и это их право: у них один язык и нет поисковой выдачи. Нам
   нужны оба, и держать слова в двух местах значит однажды поправить
   одно и забыть другое.

   ГДЕ СТОИТ ТЕКСТ. Слева от предмета акта, лицом к камере, в плоскости,
   перпендикулярной взгляду. Мир едет, текст едет с ним: он часть сцены,
   а не наклейка на объективе. Размер считается от кадра, поэтому на
   телефоне буквы не мельчают.

   ПОЯВЛЕНИЕ ИХ. Перебор чужих глифов по столбцам атласа, две скорости
   (0.4 секунды на прозрачность, 0.75 на перебор), всё в rv-msdf.js.
   Здесь только выбор момента: строка проявляется, когда её акт входит в
   кадр, и гаснет, когда выходит.

   API:
     RV_СЛОВО3D.поднять(мир)
     RV_СЛОВО3D.замер() */
(function (g, d) {
  "use strict";

  var W = null, T = null;
  var поднято = false;
  var АКТЫ = {};

  /* Кегли в долях высоты кадра. Считаются от него, а не назначаются в
     единицах мира: один и тот же текст должен читаться одинаково на
     мониторе и на телефоне, а кадр на телефоне вчетверо уже. */
  /* КЕГЛИ ПОД МОНОШИРИННЫЙ ШРИФТ, А НЕ ПОД ПРОПОРЦИОНАЛЬНЫЙ.

     Первые числа брались от вёрстки, где заголовок набран Unbounded. У
     IBM Plex Mono каждый знак занимает 0.595 кегля, узких букв нет
     вовсе, и та же строка выходит в полтора раза шире. На снимке
     «Канал держат за тебя» при кегле 0.088 уехал за левый край и лёг на
     кнопку.

     0.052 держит заголовок в две строки внутри колонки и оставляет
     место абзацу и карточкам под ним. */
  var КЕГЛИ = { над: 0.020, заг: 0.052, абз: 0.024, карта: 0.018 };
  /* Цвета взяты у мира, а не назначены заново: заголовок это тот же
     свет, что льётся на кладку, подпись это тот же холодный отсвет
     Земли. Так текст и сцена оказываются одним материалом. */
  var ЦВЕТА = { над: 0x9DB2F0, заг: 0xFFFFFF, абз: 0xC8D2EE, карта: 0xA9B6D8 };

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }

  /* ── Что берём из разметки ────────────────────────────────────
     Только слова. Разметка остаётся видимой для поисковика и для тех,
     кто пришёл без объёма: её гасит CSS, а не удаление из дерева. */
  function собратьСлова(секция) {
    function текст(сел) {
      var э = секция.querySelector(сел);
      if (!э) return "";
      return (э.textContent || "").replace(/\s+/g, " ").trim();
    }
    /* Карточки, которые акт уносит СЕБЕ, сюда не попадают. У периметра
       каждая из четырёх прилетает в стену отдельным снарядом, и текст
       написан на самом снаряде (rv-снаряды.js). Строкой сбоку они
       выглядели бы вторым, ненужным списком того же самого: человек
       читал бы «Горит зелёным» дважды - на летящей плите и в углу.

       Признак стоит В РАЗМЕТКЕ (класс рв-снаряды), а не в списке имён
       здесь: акт, который забирает свои карточки, знает об этом сам, а
       слой слов узнаёт об этом от него. */
    var карты = [];
    var спНабор = секция.querySelector(".rv-карты");
    var своиУАкта = спНабор && спНабор.classList.contains("рв-снаряды");
    var список = своиУАкта ? [] : секция.querySelectorAll(".rv-карты li");
    for (var i = 0; i < список.length; i++) {
      var т = список[i].querySelector("b");
      карты.push((т ? т.textContent : "").replace(/\s+/g, " ").trim());
    }
    return {
      над: текст(".rv-над span"),
      заг: текст(".rv-заг"),
      абз: текст(".rv-абз"),
      карты: карты
    };
  }

  /* ── Раскладка ────────────────────────────────────────────────
     Слова стоят слева, предмет справа. Ширина колонки берётся долей
     кадра, чтобы строка ломалась там же, где ломалась бы в вёрстке. */
  function разложить(узел, слова, кадрШ, кадрВ) {
    var ед = кадрВ;                       /* единица кегля это высота кадра */
    var лево = -кадрШ * 0.5 + кадрШ * 0.07;
    var ширКолонки = кадрШ * (кадрШ / кадрВ > 1.2 ? 0.42 : 0.84);
    /* БЛОК СЛОВ ЖИВЁТ В ВЕРХНЕЙ ПОЛОВИНЕ КАДРА.

       Кнопка осталась в разметке (в холсте по ней не попасть пальцем), и
       она стоит примерно по центру экрана. Текст сцены о ней не знает, и
       на снимке абзац лёг ровно под неё: слова в объёме, кнопка поверх,
       читается ни то ни другое.

       Сверху блок ограничен ВИЗИТКОЙ: марка с подписью занимает первые
       двести точек экрана, и на снимке надзаголовок «ЛУННАЯ СТАНЦИЯ»
       лёг ровно на слово ROCKET. Старт опущен до 0.24 высоты кадра выше
       центра: на экране в девятьсот точек это отметка 234, визитка
       кончается на 196. */
    var y = кадрВ * 0.24;

    function строка(вид, текст, кегль) {
      if (!текст) return null;
      var размер = ед * кегль;
      var м = g.RV_MSDF["строка"](текст, {
        ширина: ширКолонки / размер,      /* предел в единицах кегля */
        цвет: ЦВЕТА[вид],
        толщина: вид === "заг" ? -0.035 : -0.02,
        выравнивание: "лево"
      });
      м.scale.setScalar(размер);
      м.position.set(лево, y, 0);
      м.renderOrder = 20;
      узел.add(м);
      var высота = (м.userData["высота"] || 1.3) * размер;
      y -= высота + ед * 0.02;
      return м;
    }

    var меши = [];
    var м1 = строка("над", слова.над.toUpperCase(), КЕГЛИ.над);
    if (м1) { меши.push(м1); y -= ед * 0.035; }
    var м2 = строка("заг", слова.заг, КЕГЛИ.заг);
    if (м2) { меши.push(м2); y -= ед * 0.030; }
    var м3 = строка("абз", слова.абз, КЕГЛИ.абз);
    if (м3) { меши.push(м3); y -= ед * 0.040; }
    for (var i = 0; i < слова.карты.length && i < 4; i++) {
      var мк = строка("карта", "// " + слова.карты[i], КЕГЛИ.карта);
      if (мк) меши.push(мк);
    }
    return меши;
  }

  /* ── Сборка одного акта ───────────────────────────────────────
     Узел висит на КАМЕРЕ, а не в мире. Так текст сохраняет своё место в
     кадре при любом ходе камеры, и это честно: слова обращены к
     человеку, они не предмет мира и не должны уезжать вбок вместе с
     ним. Глубина фиксированная, поэтому размер в кадре постоянный. */
  var ДАЛЬ = 10;
  function собрать(имя, секция) {
    if (АКТЫ[имя]) return АКТЫ[имя];
    var слова = собратьСлова(секция);
    if (!слова.заг) return null;
    var узел = new T.Group();
    узел.name = "слова: " + имя;
    узел.visible = false;
    узел.position.z = -ДАЛЬ;
    /* Метка накладки. Слова висят на камере, а не в мире, и в
       закадровые снимки сцены им попадать нельзя. Линза акта свёртки
       снимает всю сцену в мишень и показывает её увеличенной: без
       метки абзац проявлялся на экране вторым, крупным призраком
       поверх собственного заголовка. Кто снимает сцену мимо экрана,
       гасит накладки через RV_WORLD.накладки(false). */
    узел.userData["накладка"] = true;
    W.cam.add(узел);
    var кадрВ = 2 * Math.tan(W.cam.fov * Math.PI / 360) * ДАЛЬ;
    var кадрШ = кадрВ * W.cam.aspect;
    var меши = разложить(узел, слова, кадрШ, кадрВ);
    АКТЫ[имя] = { узел: узел, меши: меши, слова: слова, секция: секция, виден: false, кадрВ: кадрВ, кадрШ: кадрШ };
    return АКТЫ[имя];
  }

  function пересобрать() {
    for (var имя in АКТЫ) {
      if (!Object.prototype.hasOwnProperty.call(АКТЫ, имя)) continue;
      var а = АКТЫ[имя];
      var кадрВ = 2 * Math.tan(W.cam.fov * Math.PI / 360) * ДАЛЬ;
      var кадрШ = кадрВ * W.cam.aspect;
      /* Пересобираем только при заметной смене кадра: поле зрения ходит
         каждый кадр на десятые доли градуса, и перестраивать геометрию
         строк из-за этого значит собирать её шестьдесят раз в секунду. */
      if (Math.abs(кадрВ - а.кадрВ) < а.кадрВ * 0.06 &&
          Math.abs(кадрШ - а.кадрШ) < а.кадрШ * 0.06) continue;
      /* Чистим УЗЕЛ ЦЕЛИКОМ, а не по списку мешей.

         По списку оставались сироты: пересборка идёт при смене кадра, а
         кадр меняется и в середине показа. Если между двумя пересборками
         список успел смениться, прежние строки оставались детьми узла и
         продолжали рисоваться. На снимке прокола заголовок и абзац шли
         двумя копиями со сдвигом. */
      while (а.узел.children.length) {
        var стар = а.узел.children[0];
        а.узел.remove(стар);
        if (стар.geometry) стар.geometry.dispose();
        if (стар.material) стар.material.dispose();
      }
      а.меши = разложить(а.узел, а.слова, кадрШ, кадрВ);
      а.кадрВ = кадрВ; а.кадрШ = кадрШ;
      if (а.виден) for (var j = 0; j < а.меши.length; j++) g.RV_MSDF["показать"](а.меши[j], true);
    }
  }

  function показать(имя, да) {
    var а = АКТЫ[имя];
    if (!а || а.виден === да) return;
    а.виден = да;
    if (да) а.узел.visible = true;
    for (var i = 0; i < а.меши.length; i++) g.RV_MSDF["показать"](а.меши[i], да);
    if (!да) {
      /* Ждём, пока догорит гашение (0.2 секунды по их числам), и только
         потом убираем узел из отрисовки. */
      if (а.таймер) g.clearTimeout(а.таймер);
      а.таймер = g.setTimeout(function () { if (!а.виден) а.узел.visible = false; }, 260);
    }
  }

  var поднимаемся = false;
  function поднять(мир) {
    /* ЗАМОК СТАВИТСЯ НА ВХОДЕ, А НЕ ПОСЛЕ СБОРКИ.

       Раньше защита стояла на признаке «поднято», который выставляется
       ВНУТРИ колбэка готовности атласа. Между вызовом и колбэком признак
       ещё ложный, а зовут нас двое: мир в момент своей готовности и наш
       собственный самоподъём по событию. Оба успевали пройти, вешали по
       колбэку, и строки собирались ДВАЖДЫ.

       На снимке прокола это видно прямо: заголовок и абзац идут двумя
       копиями со сдвигом в несколько точек. */
    if (поднято || поднимаемся) return;
    W = мир || W;
    if (!W || !W.T || !W.cam || !g.RV_MSDF) return;
    поднимаемся = true;
    T = W.T;
    g.RV_MSDF["поднять"](W);
    g.RV_MSDF["готов"](function () {
      var секции = d.querySelectorAll(".rv-акт[data-акт]");
      for (var i = 0; i < секции.length; i++) {
        собрать(секции[i].getAttribute("data-акт"), секции[i]);
      }
      /* Разметка гасится ТОЛЬКО когда объём собрался. Не доехал атлас,
         не поднялся объём, старая видеокарта - человек видит обычный
         текст и ничего не теряет. */
      d.documentElement.classList.add("рв-слова-в-сцене");
      поднято = true;
    });

    /* Кто в кадре, тот и говорит. Мир уже каждый кадр помечает свои
       акты признаком «виден», и второй такой счётчик тут был бы лишним:
       две независимые математики видимости однажды разойдутся, и слова
       окажутся не от той сцены.

       Плоские акты (те, у которых нет позы камеры) мир тоже помечает,
       поэтому одного признака хватает на всю ленту. */
    g.addEventListener("rv:кадр", function () {
      if (!поднято) return;
      /* ГОВОРИТ РОВНО ОДИН АКТ.

         Признак «виден» у мира держат СРАЗУ НЕСКОЛЬКО актов: секции
         соседей перекрываются по прокрутке, и плоские акты объявляют
         себя живыми сами. Для слоя поверх холста это не беда, там
         соседи разведены по вертикали разметкой. В сцене они рисуются в
         одной точке кадра, и на снимке первого экрана заголовки
         «Канал держат за тебя» и «Всё, что ты открываешь, видно со
         стороны» легли друг на друга буквами.

         Выбираем того, чья секция ближе к середине окна: это ровно тот
         акт, на который человек сейчас смотрит. Считаем по разметке, а
         не по доле мира: у плоских актов доли нет вовсе. */
      var лучший = null, лучшаяМера = -1;
      var высота = g.innerHeight || 1;
      for (var имя in АКТЫ) {
        if (!Object.prototype.hasOwnProperty.call(АКТЫ, имя)) continue;
        var сек = АКТЫ[имя].секция;
        if (!сек) continue;
        var к = сек.getBoundingClientRect();
        if (к.bottom <= 0 || к.top >= высота) continue;
        /* Мера это близость середины секции к середине окна, в долях
           экрана. Ноль означает «секция ровно по центру». */
        var сер = (к.top + к.bottom) * 0.5;
        var мера = 1 - Math.abs(сер - высота * 0.5) / высота;
        if (мера > лучшаяМера) { лучшаяМера = мера; лучший = имя; }
      }
      for (var имя2 in АКТЫ) {
        if (!Object.prototype.hasOwnProperty.call(АКТЫ, имя2)) continue;
        показать(имя2, имя2 === лучший);
      }
      пересобрать();
    });
  }

  /* ПОДНИМАЕМСЯ САМИ, А НЕ ЖДЁМ ВЫЗОВА ИЗ МИРА.

     Мир зовёт нас в момент своей готовности, но скрипты грузятся
     отложенно и по порядку: rv-world.js стоит в разметке раньше нас, и
     на момент его готовности ни RV_MSDF, ни RV_СЛОВО3D ещё не
     объявлены. Вызов просто пропускался, атлас не запрашивался ни разу,
     и текст оставался плоским.

     Событие «rv:мир» решает это без оглядки на порядок тегов: опоздали
     - ловим событие, успели - видим готовый мир и поднимаемся сразу.
     Тем же приёмом живут все акты. */
  function самоподъём() {
    if (!g.RV_WORLD || !g.RV_WORLD["готов"] || !g.RV_WORLD["готов"]()) return false;
    поднять(g.RV_WORLD["мир"]());
    return true;
  }
  if (!самоподъём()) g.addEventListener("rv:мир", самоподъём);

  g.RV_СЛОВО3D = {
    "поднять": поднять,
    "замер": function () {
      var сп = [];
      for (var имя in АКТЫ) {
        if (!Object.prototype.hasOwnProperty.call(АКТЫ, имя)) continue;
        сп.push({ "акт": имя, "строк": АКТЫ[имя].меши.length, "виден": АКТЫ[имя].виден });
      }
      return { "поднято": поднято, "акты": сп };
    }
  };
})(window, document);
