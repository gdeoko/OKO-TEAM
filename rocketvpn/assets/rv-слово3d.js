  function прилипала(с) {
    /* Знак препинания в конце это конец мысли: «стоит.» держится само
       и переносить его вниз незачем, даже если слово короткое. */
    if (/[.,;:!?)\]»"]$/.test(с)) return false;
    var ч = с.toLowerCase().replace(/[^0-9a-zа-яё]+/g, "");
    if (!ч) return false;
    /* Число без запятой на конце тянет за собой единицу измерения. На
       снимке пк-пуск-03 строка кончалась на «6999», а «р год.» уезжало
       вниз: цена оказывалась разорванной пополам. */
    if (/^\d+$/.test(ч)) return true;
    if (ПРИЛИПАЛЫ[ч]) return true;
    return ч.length <= 2;
  }

  /* Ширина знака в долях кегля. Шрифт моноширинный, у всех знаков она
     одна, поэтому длина строки это просто число знаков. Берём её у
     самого атласа: сменится шрифт - перенос поедет следом за ним.
     0.595 это запасное значение IBM Plex Mono на случай, если мера
     почему-то не ответила. */
  var _шагЗнака = 0;
