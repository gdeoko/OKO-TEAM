/* Rocket VPN. Листы: акт разводит своё содержимое во времени, когда
   оно не помещается в кадр.

   БЕДА. Сайт вертикальный и кадровый: у каждого акта ровно один экран,
   и содержимое обязано в нём помещаться. На мониторе помещается всегда.
   На телефоне 360x640 акт «Точка выхода» это заголовок, абзац, три
   карточки станций, сноска, семь строк доказательства и кнопка - почти
   тысяча точек в кадр высотой шестьсот сорок. Замер посадки поймал ровно
   это: слова уходят за верхнюю кромку на девяносто восемь точек и за
   нижнюю на девяносто восемь, то есть человек не видит НИ заголовка,
   НИ кнопки.

   ЧТО НЕ РАБОТАЕТ. Уменьшать кегль: на узком экране он и так у нижней
   границы читаемости. Резать текст: это единственное место, где сайт
   доказывает надёжность датами, и без дат остаётся обещание. Разрешать
   прокрутку внутри кадра: кадр перестаёт быть кадром, и лента ломается.

   ЧТО РАБОТАЕТ. Акт длинный - два, три экрана прокрутки. Развести
   содержимое ПО ХОДУ АКТА: сначала о чём речь, потом сама вещь, потом
   числа. Ровно так и построено кино: один кадр не показывает всё разом.

   КАК ЭТО ОБЪЯВЛЯЕТСЯ. В разметке блоку ставится data-лист с номерами
   фаз, в которых он живёт: "0", "2", "0 1". Блок БЕЗ data-лист виден
   всегда - так остаются на месте те, кого разводить нельзя (кнопка
   ухода в космос соседей должна быть под пальцем в любой момент акта).

   КОГДА ЭТО ВКЛЮЧАЕТСЯ. Только когда содержимое ДЕЙСТВИТЕЛЬНО не
   помещается, и это меряется живьём, а не угадывается по ширине экрана.
   Помещается - акт показывает всё разом, и никакого разведения нет:
   разводить помещающееся значит прятать от человека то, что он мог бы
   увидеть сразу.

   ПОЧЕМУ НЕ ПРОЗРАЧНОСТЬЮ. Невидимый блок продолжает ловить касания, и
   человек жмёт в пустоту. Ушедший лист убирается из-под пальца целиком.

   Фазу ставит rv-motion.js: она уже есть, и второй такой величины
   заводить незачем. */
(function (g, d) {
  "use strict";

  var ЗАПАС = 24;   /* воздух сверху и снизу, точек */
  var МЕРИМ = "rv-мерим";

  function листовые(акт) {
    return акт.querySelectorAll(".rv-слой > [data-лист]");
  }

  /* Высота содержимого слоя при всех показанных листах. Меряем ОТ
     первого видимого ребёнка ДО последнего: сумма высот врала бы на
     схлопнутых отступах между блоками. */
  function высотаСодержимого(слой) {
    var верх = Infinity, низ = -Infinity;
    var дети = слой.children;
    for (var i = 0; i < дети.length; i++) {
      var с = g.getComputedStyle(дети[i]);
      if (с.display === "none") continue;
      var r = дети[i].getBoundingClientRect();
      if (r.height < 1) continue;
      if (r.top < верх) верх = r.top;
      if (r.bottom > низ) низ = r.bottom;
    }
    return низ > верх ? низ - верх : 0;
  }

  function померить() {
    var акты = d.querySelectorAll(".rv-акт");
    for (var i = 0; i < акты.length; i++) {
      var акт = акты[i];
      var слой = акт.querySelector(".rv-кадр > .rv-слой");
      if (!слой) continue;
      if (!листовые(акт).length) {
        /* Разводить нечего: в акте не размечено ни одного листа. */
        акт.removeAttribute("data-тесно");
        continue;
      }
      var кадр = акт.querySelector(".rv-кадр");
      var вкадре = кадр ? кадр.getBoundingClientRect().height : g.innerHeight;

      /* Меряем при ВСЕХ показанных листах и без выравнивания по центру:
         иначе замер зависит от того, какая фаза стоит сейчас. */
      акт.classList.add(МЕРИМ);
      var надо = высотаСодержимого(слой);
      акт.classList.remove(МЕРИМ);

      /* Поля слоя тоже занимают кадр: на телефоне колонка прижата к
         верху и стоит на 17 процентах высоты, первый экран несёт отступ
         под шапку. Без них замер считал бы кадр целиком свободным, и
         акт, помещавшийся впритык по центру, уезжал бы низом за кромку. */
      var ст = g.getComputedStyle(слой);
      var поля = (parseFloat(ст.paddingTop) || 0) + (parseFloat(ст.paddingBottom) || 0);
      var тесно = надо + поля + ЗАПАС * 2 > вкадре;
      if (тесно) акт.setAttribute("data-тесно", "1");
      else акт.removeAttribute("data-тесно");
    }
  }

  /* Замер идёт после того, как содержимое приехало из досье и шрифты
     встали на место: до этого высоты врут. */
  function позже(дело) {
    if (d.fonts && d.fonts.ready && d.fonts.ready.then) {
      d.fonts.ready.then(function () { g.requestAnimationFrame(дело); });
    } else {
      g.requestAnimationFrame(дело);
    }
  }

  var ждём = 0;
  function поРазмеру() {
    if (ждём) g.clearTimeout(ждём);
    /* Поворот экрана и появление адресной строки присылают события
       пачкой. Меряем один раз, когда пачка кончилась. */
    ждём = g.setTimeout(function () {
      ждём = 0;
      померить();
      if (g.RV_MOTION && g.RV_MOTION["обновить"]) g.RV_MOTION["обновить"]();
    }, 180);
  }

  function старт() {
    позже(померить);
    /* Второй замер с запасом: блоки досье и объёмные сцены приезжают
       не мгновенно, и первый замер может застать акт полупустым. */
    g.setTimeout(померить, 1200);
    g.addEventListener("resize", поРазмеру);
    if (g.visualViewport) g.visualViewport.addEventListener("resize", поРазмеру);
  }

  g.RV_ЛИСТ = { "померить": померить };

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", старт);
  else старт();
})(window, document);
