/* Rocket VPN. Мини-игра ангара: провести ракету сквозь стену.

   ЗАЧЕМ ОНА. Владелец: «за мини игру получаешь бесплатно 3 дня ВПН
   логично?». Логично, и текст акта уже это обещает словами из паспорта
   фактов: «В ангаре стоит ракета. Проведи её сквозь стену и забери три
   дня бесплатно, до всякой оплаты».

   ПОЧЕМУ ИМЕННО СТЕНА С ПРОЁМОМ. Игра не должна быть пришитой сбоку
   аркадой. Весь сайт про одно: между тобой и сетью стоит стена, и
   Rocket проходит сквозь неё. Домик собирается в стену, стена
   пробивается тоннелем, и в ангаре человек делает то же самое своими
   руками. Кирпич тот же, проём тот же, обещание то же.

   МЕХАНИКА. Створки едут навстречу и расходятся, проём между ними
   ходит поперёк оси ракеты по синусу. Нажатие в любом месте кадра (или
   пробел) даёт пуск. Попадание считается по тому, где стоял проём в
   момент нажатия, а не по картинке: картинка отстаёт на кадр, а рука
   человека не должна платить за это.

   ТРИ ЗАХОДА, ПРОЁМ СУЖАЕТСЯ. Первый заход прощает почти всё (допуск в
   половину проёма), третий требует попасть в середину. Промах не
   наказывает: заход просто переигрывается, счётчик заходов не растёт.
   Наказывать нечем и незачем - это подарок, а не экзамен.

   ПОЧЕМУ НЕ ТАЙМЕР И НЕ ЛОВЛЯ ТОЧЕК. Оба требуют точного указания
   пальцем по мелким целям. Здесь цель одна и это весь экран: на
   телефоне игра работает так же, как на столе, и в этом весь расчёт -
   больше половины людей придёт с телефона.

   ЧЕСТНОСТЬ НАГРАДЫ. Никаких выдуманных промо-кодов: три пробных дня
   выдаёт бот и выдаёт их всем, до всякой оплаты. Победа открывает ту
   же настоящую ссылку, что и кнопка акта, и говорит правду о том, что
   за ней.

   API:
     RV_ИГРА.собрать(мир, родитель, о) -> Group | null
     RV_ИГРА.кадр(доля, dt, часы)
     RV_ИГРА.замер() -> объект для живых проверок */
(function (g, d) {
  "use strict";

  var W = null, T = null;
  var М = {};
  var собрано = false;

  /* Заходов три, допуск сужается. Числа в долях полупроёма: 0.92 это
     «попал куда угодно в проём», 0.34 - «попал в середину». */
  var ЗАХОДОВ = 3;
  var ДОПУСК = [0.92, 0.60, 0.34];
  /* Скорость хода проёма, оборотов в секунду. Растёт с заходом: третий
     не только точнее, но и быстрее. */
  var СКОРОСТЬ = [0.34, 0.44, 0.56];
  var КЛЮЧ = "rv-игра-ангар";

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }
  function плавно(a, b, x) { x = зажать((x - a) / (b - a), 0, 1); return x * x * (3 - 2 * x); }

  var В_СТВОРКА = [
    "varying vec3 vNor;",
    "varying vec3 vPos;",
    "varying float vMvz;",
    "void main(){",
    "  vNor = normalize(normalMatrix * normal);",
    "  vPos = position;",
    "  vec4 mv = modelViewMatrix * vec4(position, 1.0);",
    "  vMvz = mv.z;",
    "  gl_Position = projectionMatrix * mv;",
    "}"
  ].join("\n");

  var Ф_СТВОРКА = [
    "uniform vec3 uKamen;",
    "uniform vec3 uTen;",
    "uniform vec3 uGlow;",
    "uniform float uHot;",
    "uniform float uTime;",
    "varying vec3 vNor;",
    "varying vec3 vPos;",
    "varying float vMvz;",
    "float hash12(vec2 p){",
    "  vec3 p3 = fract(vec3(p.xyx) * 0.1031);",
    "  p3 += dot(p3, p3.yzx + 33.33);",
    "  return fract((p3.x + p3.y) * p3.z);",
    "}",
    "void main(){",
    "  vec3 n = normalize(vNor);",
    "  vec3 sv = normalize(vec3(-0.3, 0.6, 0.74));",
    "  float sol = smoothstep(-0.1, 0.6, dot(n, sv));",
    /* Кладка рисуется прямо в шейдере: створка это плита, а не сетка
       экземпляров, и полсотни лишних объектов ради шва не нужны.
       Кирпич 0.9 на 0.45, ряды со сдвигом на полкирпича. */
    "  float ryad = floor(vPos.y / 0.80);",
    "  float sdvig = mod(ryad, 2.0) * 0.80;",
    "  float shovX = abs(fract((vPos.x + sdvig) / 1.6) - 0.5) * 2.0;",
    "  float shovY = abs(fract(vPos.y / 0.80) - 0.5) * 2.0;",
    "  float shov = max(smoothstep(0.86, 1.0, shovX), smoothstep(0.82, 1.0, shovY));",
    "  vec3 color = mix(uTen, uKamen, 0.22 + 0.7 * sol);",
    "  color *= 0.88 + 0.24 * hash12(vec2(floor((vPos.x + sdvig) / 1.6), ryad));",
    "  color *= mix(1.0, 0.5, shov);",
    /* ТОНОВАЯ КРИВАЯ. Без неё лицевая грань створки, повёрнутая прямо к
       свету, отдавала полный uKamen, и ворота читались напечатанными
       обоями, а не кладкой в тёмном ангаре: на снимке победы левая
       створка вышла ровным светлым листом в половину кадра.

       Заодно затенение по высоте: у ворот свет идёт сверху, низ уходит
       в тень пола, и это единственное, что рисует им объём. */
    "  color *= 0.30 + 0.62 * sol;",
    "  color *= mix(0.55, 1.06, clamp(vPos.y / 7.0 + 0.5, 0.0, 1.0));",
    /* Кромка проёма светится: она и есть цель, и глаз должен цепляться
       именно за неё. Свечение сильнее в миг попадания (uHot). */
    "  float kraj = 1.0 - smoothstep(0.0, 0.42, abs(vPos.x) - 0.0);",
    "  color += uGlow * pow(max(0.0, 1.0 - abs(vPos.x) / 0.5), 3.0) * (0.22 + uHot * 0.9);",
    "  color *= 1.0 - smoothstep(26.0, 74.0, -vMvz) * 0.7;",
    "  color += (hash12(gl_FragCoord.xy + uTime) - 0.5) / 255.0;",
    "  gl_FragColor = vec4(color, 1.0);",
    "}"
  ].join("\n");

  /* Створка: плита шириной Ш, у которой ЛЕВЫЙ край в нуле местных
     координат. Так проём задаётся сдвигом двух створок навстречу, а
     светящаяся кромка в шейдере сидит на x = 0 у обеих. */
  function створка(Ш, В, Г, мат, зеркало) {
    var гео = new T.BoxGeometry(Ш, В, Г, Math.max(2, Math.round(Ш * 2)), Math.max(2, Math.round(В * 2)), 1);
    гео.translate(зеркало ? -Ш / 2 : Ш / 2, 0, 0);
    var м = new T.Mesh(гео, мат);
    м.name = зеркало ? "створка левая" : "створка правая";
    return м;
  }

  function собрать(мир, родитель, о) {
    if (собрано) return М.корень;
    W = мир || W;
    if (!W || !W.T || !родитель) return null;
    T = W.T;
    о = о || {};

    М.ось = о["ось"] || new T.Vector3(-3.4, 1.6, 2.0);   /* ось ракеты */
    М.размах = о["размах"] || 5.2;                        /* ход проёма поперёк */
    М.проём = о["проём"] || 1.9;                          /* полуширина проёма */
    М.zСтены = о["z"] == null ? -6.5 : о["z"];

    М.мат = new T.ShaderMaterial({
      uniforms: {
        uKamen: { value: new T.Color(0x424B60) },
        uTen: { value: new T.Color(0x141A2E) },
        uGlow: { value: new T.Color(0x9AFFDF) },
        uHot: { value: 0 }, uTime: { value: 0 }
      },
      vertexShader: В_СТВОРКА, fragmentShader: Ф_СТВОРКА, fog: false
    });

    М.корень = new T.Group();
    М.корень.name = "ворота ангара";
    М.корень.position.set(М.ось.x, М.ось.y, М.zСтены);
    /* СТВОРКА ВОСЕМЬ НА СЕМЬ, А НЕ ПЯТНАДЦАТЬ НА ОДИННАДЦАТЬ. Прежний
       размер закрывал половину кадра целиком, и ворота переставали быть
       предметом: человек видел стену на весь экран и где-то сбоку
       кольцо пуска. Восемь на семь при проёме в четыре единицы даёт
       общий размах в двадцать - кадр в этой точке двадцать пять единиц
       поперёк, и по краям остаётся тёмный ангар. */
    М.лев = створка(8, 7, 0.9, М.мат, true);
    М.прав = створка(8, 7, 0.9, М.мат, false);
    М.корень.add(М.лев);
    М.корень.add(М.прав);
    родитель.add(М.корень);
    М.корень.visible = false;

    М.заход = 0;
    М.попаданий = 0;
    М.итог = "";
    М.жар = 0;
    М.фаза = 0;
    М.живая = false;
    М.где = 0;
    М.уход = 0;
    /* Победу помним: игра дарит пробные дни, и переигрывать её ради
       того же подарка незачем. Хранилище может быть закрыто настройками
       браузера, поэтому любое обращение к нему в защите. */
    try { if (g.localStorage && g.localStorage.getItem(КЛЮЧ) === "1") { М.итог = "победа"; М.попаданий = ЗАХОДОВ; } } catch (e) {}

    разметка();
    слушать();
    собрано = true;
    return М.корень;
  }

  /* ── Панель игры ──────────────────────────────────────────────
     Разметка живёт в frame.html, здесь только связь с ней. Если
     панели нет (страница собрана без неё), игра всё равно работает в
     сцене и молча ничего не пишет. */
  function разметка() {
    М.панель = d.getElementById("rvИгра");
    if (!М.панель) return;
    М.кнопка = d.getElementById("rvИграКн");
    М.строка = d.getElementById("rvИграИтог");
    М.точки = Array.prototype.slice.call(М.панель.querySelectorAll("[data-заход]"));
    if (М.кнопка) М.кнопка.addEventListener("click", function (е) { е.preventDefault(); е.stopPropagation(); пуск(); });
    обновить();
  }

  function обновить() {
    if (!М.панель) return;
    for (var i = 0; i < М.точки.length; i++) {
      М.точки[i].setAttribute("data-взят", i < М.попаданий ? "1" : "0");
    }
    if (М.кнопка) М.кнопка.textContent = М.итог === "победа" ? "Забрать три дня в боте" : "Пуск";
    if (М.кнопка) {
      if (М.итог === "победа") М.кнопка.setAttribute("data-победа", "1");
      else М.кнопка.removeAttribute("data-победа");
    }
    if (М.строка) {
      М.строка.textContent = М.итог === "победа"
        ? "Стена пройдена. Три дня твои: забери ключ в боте и включай."
        : (М.итог === "мимо" ? "Мимо. Створки сходятся, жми, когда проём на оси." : "");
    }
  }

  function слушать() {
    /* Пуск с клавиатуры и с холста. Кнопка панели ловится отдельно:
       по ней нажимают осознанно, а по холсту - на ходу. */
    g.addEventListener("keydown", function (е) {
      if (е.code !== "Space" && е.key !== " ") return;
      if (!М.живая) return;
      var ц = d.activeElement;
      if (ц && (ц.tagName === "INPUT" || ц.tagName === "TEXTAREA" || ц.tagName === "BUTTON")) return;
      е.preventDefault();
      пуск();
    });
    g.addEventListener("pointerdown", function (е) {
      if (!М.живая) return;
      /* По кнопкам и ссылкам не стрелять: у них своё дело. */
      var ц = е.target;
      while (ц && ц !== d.body) {
        var т = ц.tagName;
        if (т === "A" || т === "BUTTON" || т === "INPUT" || т === "TEXTAREA" || т === "SELECT") return;
        ц = ц.parentNode;
      }
      пуск();
    }, { passive: true });
  }

  function событие(что, ещё) {
    try {
      var сведения = { "что": что, "заход": М.попаданий, "всего": ЗАХОДОВ };
      if (ещё) for (var к in ещё) if (Object.prototype.hasOwnProperty.call(ещё, к)) сведения[к] = ещё[к];
      g.dispatchEvent(new CustomEvent("rv:игра", { detail: сведения }));
    } catch (e) {}
  }

  function пуск() {
    if (!собрано) return;
    if (М.итог === "победа") {
      /* Победа уже взята: кнопка ведёт к настоящему боту, а не
         переигрывает. Ссылка та же, что у кнопки акта. */
      try { g.open("https://t.me/RocketCompanyVPN_bot", "_blank", "noopener"); } catch (e) {}
      return;
    }
    if (!М.живая) return;
    var и = Math.min(М.попаданий, ДОПУСК.length - 1);
    /* Попадание считается по ЧИСЛУ, а не по картинке. Место проёма
       берётся то же, что записал последний кадр: картинка на экране
       отстаёт от расчёта на кадр, и заставлять руку человека платить
       за это отставание нечестно. */
    var мимо = Math.abs(М.где) > ДОПУСК[и];
    М.жар = 1;
    if (мимо) {
      М.итог = "мимо";
      событие("мимо", { "где": +М.где.toFixed(3), "допуск": ДОПУСК[и] });
    } else {
      М.попаданий++;
      М.итог = М.попаданий >= ЗАХОДОВ ? "победа" : "попал";
      if (М.итог === "победа") {
        try { if (g.localStorage) g.localStorage.setItem(КЛЮЧ, "1"); } catch (e) {}
      }
      событие(М.итог, { "где": +М.где.toFixed(3), "допуск": ДОПУСК[и] });
    }
    обновить();
  }

  function кадр(доля, dt, часы) {
    if (!собрано) return;
    var шаг = Math.min(0.1, Math.max(0.001, dt || 0.016));
    М.мат.uniforms.uTime.value = часы || 0;
    /* Ворота живут во второй половине акта: первая отдана самому
       ангару и его словам, и играть, пока человек ещё читает, не надо. */
    var сила = плавно(0.34, 0.52, доля) * (1 - плавно(0.94, 1.0, доля));
    М.корень.visible = сила > 0.01;
    if (!М.корень.visible) { М.живая = false; return; }
    М.живая = М.итог !== "победа";

    var и = Math.min(М.попаданий, СКОРОСТЬ.length - 1);
    /* Ход проёма стоит после победы: смотреть на бегающие створки,
       когда играть уже нечего, незачем. */
    if (М.живая) М.фаза += шаг * СКОРОСТЬ[и] * Math.PI * 2;
    М.где = Math.sin(М.фаза);
    var центр = М.где * М.размах;
    /* Проём сужается с заходом вместе с допуском: игра должна быть
       видна глазом, а не только числом. */
    var пол = М.проём * (0.55 + 0.45 * (1 - и / Math.max(1, СКОРОСТЬ.length - 1)));
    М.лев.position.x = центр - пол;
    М.прав.position.x = центр + пол;
    /* Ворота выезжают из пола: без этого они на своей доле появляются
       щелчком посреди пустого ангара.

       ПОБЕДА УБИРАЕТ ИХ ВНИЗ, А НЕ РАЗВОДИТ В СТОРОНЫ. Разведённые
       створки уезжали за края кадра и стояли там двумя светлыми
       плитами по бокам: стена вроде пройдена, а закрывает она ровно
       столько же. Ворота уходят туда же, откуда пришли - в пол. */
    М.уход = М.уход == null ? 0 : М.уход + (( М.итог === "победа" ? 1 : 0) - М.уход) * (1 - Math.exp(-шаг / 0.45));
    М.корень.position.y = М.ось.y - (1 - сила) * 12 - М.уход * 12;
    М.жар = Math.max(0, М.жар - шаг * 2.2);
    М.мат.uniforms.uHot.value = М.жар;

    /* Ракета отзывается на игру: на попадании рой уходит в проём, на
       промахе рассыпается. Разлёт частиц уже умеет и то и другое. */
    if (g.RV_ЧАСТИЦЫ && g.RV_ЧАСТИЦЫ["разлёт"]) {
      var р = М.итог === "мимо" ? 0.55 * М.жар : 0;
      if (М.итог === "победа") р = 0;
      g.RV_ЧАСТИЦЫ["разлёт"](р);
    }
  }

  g.RV_ИГРА = {
    "собрать": собрать,
    "кадр": кадр,
    "замер": function () {
      if (!собрано) return { "собрано": false };
      return {
        "собрано": true, "живая": !!М.живая, "попаданий": М.попаданий, "всего": ЗАХОДОВ,
        "итог": М.итог || "идёт", "где": +М.где.toFixed(3),
        "видно": !!(М.корень && М.корень.visible)
      };
    },
    /* Для проверок: сбросить сохранённую победу и начать заново. */
    "сброс": function () {
      М.попаданий = 0; М.итог = ""; М.фаза = 0;
      try { if (g.localStorage) g.localStorage.removeItem(КЛЮЧ); } catch (e) {}
      обновить();
    }
  };
})(window, document);
