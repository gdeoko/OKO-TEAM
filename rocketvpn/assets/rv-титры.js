/* Rocket VPN. Титры: слова живут ВНУТРИ объёмного мира.

   ЗАЧЕМ. До сих пор разметка и мир были двумя слоями, наклеенными один
   на другой: сцена жила своей жизнью в холсте, буквы своей - поверх
   него. Владелец сказал об этом прямо: «текст как обычное наложение
   поверх сайта». И он прав, это видно без замеров - у наложенного
   текста нет ни глубины, ни параллакса, ни затенения предметами. Он не
   принадлежит кадру.

   ЧТО ЗДЕСЬ. Номер акта и его имя ставятся В САМУ СЦЕНУ, в гнездо
   станции, огромными и светящимися. Они:
     · стоят в мировых координатах, поэтому едут вместе с камерой и
       имеют настоящий параллакс относительно переднего плана;
     · перекрываются предметами сцены - планетой, щитом, оболочкой, -
       потому что находятся ЗА ними, а не над ними;
     · разгораются и гаснут по доле хода акта, той же величине, что
       ведёт сцену, свет и звук;
     · попадают в общую плёнку (rv-real.js) и получают тот же ореол,
       что и всё остальное в мире. Именно это и делает их частью кадра,
       а не надписью на нём.

   ПОЧЕМУ НЕ ОБЪЁМНЫЕ БУКВЫ. Выдавленный текст в кириллице требует
   шрифтового меша, а это плюс полтора мегабайта разбора шрифта в
   браузере и своя геометрия на каждую строку. Здесь тот же эффект даёт
   светящаяся плоскость с текстурой: в аддитивном свечении объём буквы
   всё равно не читается, читается СВЕТ. Экономия в полтора мегабайта
   при неотличимом кадре.

   ПОЧЕМУ ПОЗАДИ И СБОКУ. Титр не имеет права мешать читать. Он стоит
   глубоко и смещён в ту половину кадра, где живёт мир, а не слова.
   Проверка контраста меряет это числом.
   ═══════════════════════════════════════════════════════════ */
(function (g, d) {
  "use strict";

  var W = null, T = null;
  var узлы = {};          /* имя акта -> { группа, номерМат, имяМат } */
  var собран = false;

  /* Что и где. Смещение задано в единицах гнезда: X вправо от оси
     взгляда, Y вверх, Z вглубь. Глубина у всех разная не для красоты -
     на разной глубине титры идут с разной скоростью, и лента получает
     слоистость вместо плоской подложки. */
  /* Глубина подобрана по кадру, а не по вкусу. Камера стоит примерно в
     дюжине единиц перед гнездом; титр на -40 и глубже приходил
     размером в несколько точек и не читался вовсе - замер показывал
     живой узел, а на снимке его не было. Держим титр в двадцати-тридцати
     единицах от камеры: на этой дистанции плоскость в дюжину единиц
     занимает заметную часть кадра и при этом честно уходит вглубь.

     Смещение по X - всегда в ту половину кадра, где живёт мир: на
     мониторе слова стоят слева, и титр не имеет права под них лезть. */
  /* НОМЕРА В МИРЕ БОЛЬШЕ НЕТ, И ЭТО ГЛАВНАЯ ПРАВКА ЭТОГО ФАЙЛА.

     Было так: слейт разметки писал «04 ПРОКОЛ» слева, а сцена в это же
     время держала за предметами огромную цифру 04 и слово НАСКВОЗЬ.
     Одно и то же сказано дважды, разными словами и в разных местах
     кадра. Плюс обе плоскости стояли со своими смещениями, попадали
     под края предметов и обрезались ими посередине знака. Владелец
     назвал это точно: «постоянно какие-то буквы, слова, цифры, и на
     фоне это смотрится как глюк».

     Теперь в мире стоит ОДНО слово акта. Оно ниже и глубже, идёт по
     оси кадра, а не сбоку, и держит одинаковую яркость от акта к
     акту: так надпись читается фоном сцены, а не обломком в ней.
     Номер остаётся ровно в одном месте на сайте - в слейте. */
  var ТИТРЫ = {
    "оболочка": { имя: "ОБОЛОЧКА",  дх: 0.0, ду: -3.4, дz: -22, размер: 7.0 },
    "прокол":   { имя: "НАСКВОЗЬ",  дх: 0.0, ду: -3.8, дz: -24, размер: 7.4 },
    "выход":    { имя: "ОТКРЫТО",   дх: 0.0, ду: -4.2, дz: -20, размер: 6.8 },
    "рубка":    { имя: "ШЛЮЗ",      дх: 0.0, ду: -4.0, дz: -26, размер: 6.4 },
    "стыковка": { имя: "ОДИН ФЛОТ", дх: 0.0, ду: -4.0, дz: -20, размер: 6.6 }
  };

  function зажать(v, a, b) { return v < a ? a : (v > b ? b : v); }
  function плавно(t) { t = зажать(t, 0, 1); return t * t * (3 - 2 * t); }

  /* Текстура строки. Рисуем в холст с запасом по краям: свечение
     размазывается за габарит букв, и без запаса оно срезается кромкой
     текстуры ровной линией - это видно сразу и выглядит браком. */
  function текст(строка, кегль, ширинаЗнака, цвет, свеч) {
    var зап = Math.round(кегль * 0.55);
    var изм = d.createElement("canvas").getContext("2d");
    изм.font = "900 " + кегль + "px " + шрифт();
    var ш = Math.ceil(изм.measureText(строка).width + строка.length * ширинаЗнака) + зап * 2;
    var в = Math.ceil(кегль * 1.5) + зап * 2;
    var c = d.createElement("canvas");
    c.width = ш; c.height = в;
    var x = c.getContext("2d");
    x.textAlign = "center";
    x.textBaseline = "middle";
    x.font = "900 " + кегль + "px " + шрифт();
    if (ширинаЗнака) x.letterSpacing = ширинаЗнака + "px";
    /* Три прохода: широкий нимб, тело, ядро. Тот же порядок, что у
       неона в разметке, и то же ощущение газоразрядной трубки. */
    x.shadowColor = свеч;
    x.fillStyle = цвет;
    x.shadowBlur = кегль * 0.55; x.fillText(строка, ш / 2, в / 2);
    x.shadowBlur = кегль * 0.22; x.fillText(строка, ш / 2, в / 2);
    x.shadowBlur = 0;            x.fillText(строка, ш / 2, в / 2);
    var тек = new T.CanvasTexture(c);
    if (T.SRGBColorSpace) тек.colorSpace = T.SRGBColorSpace;
    тек.anisotropy = 4;
    return { тек: тек, ш: ш, в: в };
  }

  /* Гарнитура голоса. Если файл ещё не доехал, холст молча возьмёт
     запасную - титр появится, просто другим рисунком, и перерисуется
     по готовности шрифтов. */
  function шрифт() {
    return '"Unbounded", "Golos Text", system-ui, sans-serif';
  }

  function плоскость(строка, кегль, разрядка, цвет, свеч, высота) {
    var т = текст(строка, кегль, разрядка, цвет, свеч);
    var м = new T.MeshBasicMaterial({
      map: т.тек, transparent: true, opacity: 0,
      depthWrite: false, blending: T.AdditiveBlending
    });
    var ш = высота * (т.ш / т.в);
    var сетка = new T.Mesh(new T.PlaneGeometry(ш, высота), м);
    сетка.renderOrder = 0;   /* глубже всего: титр стоит ЗА предметами */
    return { сетка: сетка, мат: м };
  }

  function собрать() {
    if (собран || !g.RV_WORLD || !g.RV_WORLD["готов"] || !g.RV_WORLD["готов"]()) return;
    W = g.RV_WORLD["мир"]();
    if (!W || !W.T) return;
    T = W.T;
    собран = true;

    for (var имя in ТИТРЫ) {
      if (!ТИТРЫ.hasOwnProperty(имя)) continue;
      var т = ТИТРЫ[имя];
      var гн = g.RV_WORLD["гнездо"](имя);
      if (!гн) continue;

      var группа = new T.Group();
      группа.position.set(т.дх, т.ду, т.дz);
      гн.add(группа);

      /* Одно слово, набранное разрядкой. Разрядка здесь не украшение:
         широко расставленные знаки на дистанции в два десятка единиц
         читаются как надпись, а плотно набранные - как полоса шума. */
      var и = плоскость(т.имя, 96, 40, "#8FA3E8", "rgba(80,110,230,.8)", т.размер * 0.30);
      группа.add(и.сетка);

      узлы[имя] = { группа: группа, имя: и.мат, дz: т.дz };
      подписать(имя);
    }

    /* Шрифт мог не доехать к моменту сборки. Пересобираем текстуры по
       готовности: иначе титр навсегда останется набранным системной
       гарнитурой, и голос сайта в кадре разойдётся с голосом в
       разметке. */
    if (d.fonts && d.fonts.ready && d.fonts.ready.then) {
      d.fonts.ready.then(пересобрать);
    }
  }

  function пересобрать() {
    for (var имя in узлы) {
      if (!узлы.hasOwnProperty(имя)) continue;
      var т = ТИТРЫ[имя], у = узлы[имя];
      var и = текст(т.имя, 96, 40, "#8FA3E8", "rgba(80,110,230,.8)");
      if (у.имя.map) у.имя.map.dispose();
      у.имя.map = и.тек; у.имя.needsUpdate = true;
    }
  }

  /* Ход титра. Разгорается в первой четверти акта, держится, гаснет в
     последней. Плюс медленный уход вглубь: титр отстаёт от камеры, и
     это тот самый параллакс, ради которого он и стоит в мире.

     Яркость намеренно скромная. Титр это фон кадра, а не его герой:
     герой - сцена и слова слева. Проверка контраста меряет это числом,
     и превышать её пороги титру нельзя. */
  /* Кого ещё не подписали. Мир бывает готов РАНЬШЕ плёнки: событие
     готовности мира приходит из очереди прогрева, а плёнка заводится по
     DOMContentLoaded. Первая сборка титров попадала в этот промежуток,
     подписка тихо не заводилась - и титры стояли в сцене с нулевой
     яркостью, не двигаясь. Видно это было только по замеру: на кадре
     невидимое от несуществующего не отличить.

     Поэтому подписку не «пробуем один раз», а ДОБИВАЕМСЯ: пока плёнки
     нет, имя лежит в очереди, и попытка повторяется. */
  var ждутПодписки = [];

  function подписать(имя) {
    if (!g.RV_MOTION || !g.RV_MOTION["слушать"]) {
      if (ждутПодписки.indexOf(имя) < 0) ждутПодписки.push(имя);
      добиться();
      return;
    }
    g.RV_MOTION["слушать"](имя, function (д) {
      var у = узлы[имя];
      if (!у) return;
      var явь = плавно(д / 0.22) * (1 - плавно((д - 0.80) / 0.20));
      /* Яркость ниже прежней. Титр это воздух кадра: заметил - хорошо,
         не заметил - тоже хорошо. Прежние три десятых спорили с самой
         сценой и лезли в глаза именно тем, что были ярче предметов,
         стоящих ближе. */
      у.имя.opacity = явь * 0.15;
      у.группа.visible = явь > 0.01;
      /* Уход вглубь на треть длины перегона за акт. Титр не догоняет
         камеру и остаётся позади - как надпись на стене, мимо которой
         летишь. */
      у.группа.position.z = у.дz - д * 9;
      /* Едва заметный крен: плоскость, стоящая строго по оси, читается
         наклейкой. Наклон возвращает ей место в пространстве. */
      у.группа.rotation.z = (д - 0.5) * 0.06;
    });
  }

  var ждём = 0;
  function добиться() {
    if (ждём || !ждутПодписки.length) return;
    ждём = g.setTimeout(function () {
      ждём = 0;
      if (!g.RV_MOTION || !g.RV_MOTION["слушать"]) { добиться(); return; }
      var очередь = ждутПодписки.slice();
      ждутПодписки.length = 0;
      for (var i = 0; i < очередь.length; i++) подписать(очередь[i]);
    }, 120);
  }

  if (g.RV_WORLD && g.RV_WORLD["готов"] && g.RV_WORLD["готов"]()) собрать();
  else g.addEventListener("rv:мир", собрать);

  g.RV_ТИТРЫ = {
    "состояние": function () {
      var из = {};
      for (var имя in узлы) {
        if (!узлы.hasOwnProperty(имя)) continue;
        из[имя] = {
          "виден": !!узлы[имя].группа.visible,
          "яркость": +узлы[имя].имя.opacity.toFixed(3),
          "z": +узлы[имя].группа.position.z.toFixed(1)
        };
      }
      return из;
    }
  };
})(window, document);
