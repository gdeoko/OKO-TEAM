/* Rocket VPN. Титры: слова живут ВНУТРИ объёмного мира.

   ЗАЧЕМ. До сих пор разметка и мир были двумя слоями, наклеенными один
   на другой: сцена жила своей жизнью в холсте, буквы своей - поверх
   него. Владелец сказал об этом прямо: «текст как обычное наложение
   поверх сайта». И он прав, это видно без замеров - у наложенного
   текста нет ни глубины, ни параллакса, ни затенения предметами. Он не
   принадлежит кадру.

   ЧТО ЗДЕСЬ. Номер акта и его имя ставятся В САМУ СЦЕНУ, в гнездо
   станции, огромными и светящимися. Они:
     · стоят в мировых координатах, поэтому едут вместе с камерой и
       имеют настоящий параллакс относительно переднего плана;
     · перекрываются предметами сцены - планетой, щитом, оболочкой, -
       потому что находятся ЗА ними, а не над ними;
     · разгораются и гаснут по доле хода акта, той же величине, что
       ведёт сцену, свет и звук;
     · попадают в общую плёнку (rv-real.js) и получают тот же ореол,
       что и всё остальное в мире. Именно это и делает их частью кадра,
       а не надписью на нём.

   ПОЧЕМУ НЕ ОБЪЁМНЫЕ БУКВЫ. Выдавленный текст в кириллице требует
   шрифтового меша, а это плюс полтора мегабайта разбора шрифта в
   браузере и своя геометрия на каждую строку. Здесь тот же эффект даёт
   светящаяся плоскость с текстурой: в аддитивном свечении объём буквы
   всё равно не читается, читается СВЕТ. Экономия в полтора мегабайта
   при неотличимом кадре.

   ПОЧЕМУ ПОЗАДИ И СБОКУ. Титр не имеет права мешать читать. Он стоит
   глубоко и смещён в ту половину кадра, где живёт мир, а не слова.
   Проверка контраста меряет это числом.
   ═══════════════════════════════════════════════════════════ */
(function (g, d) {
  "use strict";

  var W = null, T = null;
  var узлы = {};          /* имя акта -> { группа, номерМат, имяМат } */
  var собран = false;

  /* Что и где. Смещение задано в единицах гнезда: X вправо от оси
     взгляда, Y вверх, Z вглубь. Глубина у всех разная не для красоты -
     на разной глубине титры идут с разной скоростью, и лента получает
     слоистость вместо плоской подложки. */
  /* Глубина подобрана по кадру, а не по вкусу. Камера стоит примерно в
     дюжине единиц перед гнездом; титр на -40 и глубже приходил
     размером в несколько точек и не читался вовсе - замер показывал
     живой узел, а на снимке его не было. Держим титр в двадцати-тридцати
     единицах от камеры: на этой дистанции плоскость в дюжину единиц
     занимает заметную часть кадра и при этом честно уходит вглубь.

     Смещение по X - всегда в ту половину кадра, где живёт мир: на
     мониторе слова стоят слева, и титр не имеет права под них лезть. */
  /* НОМЕРА В МИРЕ БОЛЬШЕ НЕТ, И ЭТО ГЛАВНАЯ ПРАВКА ЭТОГО ФАЙЛА.

     Было так: слейт разметки писал «04 ПРОКОЛ» слева, а сцена в это же
     время держала за предметами огромную цифру 04 и слово НАСКВОЗЬ.
     Одно и то же сказано дважды, разными словами и в разных местах
     кадра. Плюс обе плоскости стояли со своими смещениями, попадали
     под края предметов и обрезались ими посередине знака. Владелец
     назвал это точно: «постоянно какие-то буквы, слова, цифры, и на
     фоне это смотрится как глюк».

     Теперь в мире стоит ОДНО слово акта. Оно ниже и глубже, идёт по
     оси кадра, а не сбоку, и держит одинаковую яркость от акта к
     акту: так надпись читается фоном сцены, а не обломком в ней.
     Номер остаётся ровно в одном месте на сайте - в слейте. */
  /* Сдвиг по X действует только на широком кадре: на мониторе слова акта
     занимают левую половину, и слово мира уходит вправо, в половину
     сцены, чтобы не лезть под строки. На телефоне текст идёт во всю
     ширину, сдвигать некуда, и там титр стоит по оси (см. покадрово). */
  var ТИТРЫ = {
    "оболочка": { имя: "ОБОЛОЧКА",  дх: 6.0, ду: -3.4, дz: -22, размер: 7.0 },
    "прокол":   { имя: "НАСКВОЗЬ",  дх: 6.0, ду: -3.8, дz: -24, размер: 7.4 },
    /* Выход: планета стоит на оси гнезда и закрывала титр целиком, снимок
       со станции показывал пустоту там, где замер видел живой узел. Слово
       опущено ниже диска и подведено ближе, чтобы не потерять размер. */
    "выход":    { имя: "ОТКРЫТО",   дх: 6.0, ду: -7.6, дz: -17, размер: 6.8 },
    "рубка":    { имя: "ШЛЮЗ",      дх: 5.0, ду: -4.0, дz: -26, размер: 6.4 },
    "стыковка": { имя: "ОДИН ФЛОТ", дх: 6.0, ду: -4.0, дz: -20, размер: 6.6 }
  };

  function зажать(v, a, b) { return v < a ? a : (v > b ? b : v); }
  function плавно(t) { t = зажать(t, 0, 1); return t * t * (3 - 2 * t); }

  /* Текстура строки. Рисуем в холст с запасом по краям: свечение
     размазывается за габарит букв, и без запаса оно срезается кромкой
     текстуры ровной линией - это видно сразу и выглядит браком. */
  function текст(строка, кегль, ширинаЗнака, цвет, свеч) {
    var зап = Math.round(кегль * 0.55);
    var изм = d.createElement("canvas").getContext("2d");
    изм.font = "900 " + кегль + "px " + шрифт();
    var ш = Math.ceil(изм.measureText(строка).width + строка.length * ширинаЗнака) + зап * 2;
    var в = Math.ceil(кегль * 1.5) + зап * 2;
    var c = d.createElement("canvas");
    c.width = ш; c.height = в;
    var x = c.getContext("2d");
    x.textAlign = "center";
    x.textBaseline = "middle";
    x.font = "900 " + кегль + "px " + шрифт();
    if (ширинаЗнака) x.letterSpacing = ширинаЗнака + "px";
    /* Три прохода: широкий нимб, тело, ядро. Тот же порядок, что у
       неона в разметке, и то же ощущение газоразрядной трубки. */
    x.shadowColor = свеч;
    x.fillStyle = цвет;
    x.shadowBlur = кегль * 0.55; x.fillText(строка, ш / 2, в / 2);
    x.shadowBlur = кегль * 0.22; x.fillText(строка, ш / 2, в / 2);
    x.shadowBlur = 0;            x.fillText(строка, ш / 2, в / 2);
    var тек = new T.CanvasTexture(c);
    if (T.SRGBColorSpace) тек.colorSpace = T.SRGBColorSpace;
    тек.anisotropy = 4;
    return { тек: тек, ш: ш, в: в };
  }

  /* Гарнитура голоса. Если файл ещё не доехал, холст молча возьмёт
     запасную - титр появится, просто другим рисунком, и перерисуется
     по готовности шрифтов. */
  function шрифт() {
    return '"Unbounded", "Golos Text", system-ui, sans-serif';
  }

  /* Шейдер плоскости. Обычный материал умел только гасить титр
     прозрачностью, и слово таяло целиком, как надпись на стекле, которое
     отодвигают. Здесь слово ПРОЯВЛЯЕТСЯ: порог по шуму идёт от явь, и
     буквы собираются из отдельных морозных пятен, как иней на стекле.
     Имена внутри шейдера латиницей: кириллица ломает разбор GLSL, и
     материал молча не собирается, титр при этом исчезает без единой
     ошибки в консоли.

     Порог зеркален явь. Прямая запись smoothstep(yav-0.18, yav+0.18, n)
     при полной яви требует шум выше 0.82, а такого шума почти нет: титр
     при ней исчезал бы. Поэтому порог идёт от (1-yav) с запасом по
     краям: при явь=1 он ниже нуля и слово сплошное, при явь=0 выше
     единицы и слова нет, посередине кромка рваная. */
  var ВЕРШИНЫ = [
    "varying vec2 vUv;",
    "void main() {",
    "  vUv = uv;",
    "  gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);",
    "}"
  ].join("\n");

  var ФРАГМЕНТ = [
    "uniform sampler2D map;",
    "uniform float uYav;",
    "uniform float uBright;",
    "uniform float uTime;",
    "uniform float uNoise;",
    "uniform float uBlik;",
    "varying vec2 vUv;",
    "float hs(vec2 p) { return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453); }",
    "float vn(vec2 p) {",
    "  vec2 i = floor(p); vec2 f = fract(p);",
    "  f = f * f * (3.0 - 2.0 * f);",
    "  return mix(mix(hs(i), hs(i + vec2(1.0, 0.0)), f.x),",
    "             mix(hs(i + vec2(0.0, 1.0)), hs(i + vec2(1.0, 1.0)), f.x), f.y);",
    "}",
    "void main() {",
    "  vec4 t = texture2D(map, vUv);",
    "  float a = t.a * uYav;",
    "  if (uNoise > 0.5) {",
    "    vec2 p = vUv * 6.0 + uTime * 0.05;",
    "    float n = vn(p) * 0.65 + vn(p * 2.13 + 3.7) * 0.35;",
    "    float por = (1.0 - uYav) * 1.36 - 0.18;",
    "    a = t.a * smoothstep(por - 0.18, por + 0.18, n);",
    "  }",
    "  float bl = 1.0;",
    "  if (uBlik > 0.5) {",
    "    float dx = (vUv.x - fract(uTime / 6.0)) / 0.06;",
    "    bl += 0.35 * exp(-dx * dx);",
    "  }",
    "  gl_FragColor = vec4(t.rgb * uBright * bl, a);",
    "}"
  ].join("\n");

  function плоскость(строка, кегль, разрядка, цвет, свеч, высота) {
    var т = текст(строка, кегль, разрядка, цвет, свеч);
    var м = new T.ShaderMaterial({
      uniforms: {
        map:     { value: т.тек },
        uYav:    { value: 0 },
        uBright: { value: 0.15 },
        uTime:   { value: 0 },
        uNoise:  { value: 0 },
        uBlik:   { value: 0 }
      },
      vertexShader: ВЕРШИНЫ,
      fragmentShader: ФРАГМЕНТ,
      transparent: true, depthWrite: false, blending: T.AdditiveBlending
    });
    var ш = высота * (т.ш / т.в);
    var сетка = new T.Mesh(new T.PlaneGeometry(ш, высота), м);
    сетка.renderOrder = 0;   /* глубже всего: титр стоит ЗА предметами */
    /* Отсев по пирамиде видимости считается по положению с прошлого
       кадра, а место титру назначается в крюке рисования. Титр, ушедший
       за край, в крюк больше не попадал и вернуться в кадр не мог. Пять
       плоскостей без отсева ничего не стоят. */
    сетка.frustumCulled = false;
    return { сетка: сетка, мат: м };
  }

  /* Что из дорогого включено на этой ступени. Шум и блик считаются в
     каждой точке плоскости; площадь у титра малая, но на нищей ступени
     лишних точек нет вовсе. Проявление шумом даёт средняя, бегущий
     блик поверх него только полная. */
  function ступень() {
    return (W && typeof W.ступень === "number") ? W.ступень : 2;
  }

  function собрать() {
    if (собран || !g.RV_WORLD || !g.RV_WORLD["готов"] || !g.RV_WORLD["готов"]()) return;
    W = g.RV_WORLD["мир"]();
    if (!W || !W.T) return;
    T = W.T;
    собран = true;

    for (var имя in ТИТРЫ) {
      if (!ТИТРЫ.hasOwnProperty(имя)) continue;
      var т = ТИТРЫ[имя];
      var гн = g.RV_WORLD["гнездо"](имя);
      if (!гн) continue;

      var группа = new T.Group();
      группа.position.set(т.дх, т.ду, т.дz);
      гн.add(группа);

      /* Одно слово, набранное разрядкой. Разрядка здесь не украшение:
         широко расставленные знаки на дистанции в два десятка единиц
         читаются как надпись, а плотно набранные - как полоса шума. */
      /* Высота плоскости: холст строки на две трети состоит из запаса
         под свечение, сами буквы занимают лишь его треть. При 0.30
         размера буква на станции выходила в дюжину точек, замер видел
         живой титр, а снимок пустоту. */
      var и = плоскость(т.имя, 96, 40, "#8FA3E8", "rgba(80,110,230,.8)", т.размер * 0.42);
      группа.add(и.сетка);

      /* Сдвиг качания по имени: пять титров с одной фазой качались бы
         строем, а строй на перегоне читается как дрожь всего кадра. */
      var сдвиг = 0;
      for (var k = 0; k < имя.length; k++) сдвиг += имя.charCodeAt(k) * 0.37;

      узлы[имя] = { группа: группа, имя: и.мат, дz: т.дz, д: 0, явь: 0, яркость: 0.15, сдвиг: сдвиг };
      покадрово(имя, и.сетка);
      подписать(имя);
    }

    /* Шрифт мог не доехать к моменту сборки. Пересобираем текстуры по
       готовности: иначе титр навсегда останется набранным системной
       гарнитурой, и голос сайта в кадре разойдётся с голосом в
       разметке. */
    if (d.fonts && d.fonts.ready && d.fonts.ready.then) {
      d.fonts.ready.then(пересобрать);
    }
  }

  function пересобрать() {
    for (var имя in узлы) {
      if (!узлы.hasOwnProperty(имя)) continue;
      var т = ТИТРЫ[имя], у = узлы[имя];
      var и = текст(т.имя, 96, 40, "#8FA3E8", "rgba(80,110,230,.8)");
      var карта = у.имя.uniforms.map;
      if (карта.value) карта.value.dispose();
      карта.value = и.тек;
    }
  }

  /* Часы и качание берутся в момент рисования, а не в подписке: подписка
     молчит, пока лента стоит, а блик обязан бежать и по стоящему кадру.
     Крюк срабатывает только у видимой плоскости, поэтому невидимый титр
     не стоит ни одной операции. */
  var точка = null, цель = null, местн = null, вправо = null, кв = null;
  function покадрово(имя, сетка) {
    сетка.onBeforeRender = function () {
      var у = узлы[имя];
      if (!у) return;
      var ст = ступень();
      var u = у.имя.uniforms;
      u.uTime.value = W.часы || 0;
      u.uYav.value = у.явь;
      u.uBright.value = у.яркость;
      u.uNoise.value = ст >= 1 ? 1 : 0;
      u.uBlik.value = ст >= 2 ? 1 : 0;
      /* Рост с расстоянием. Доля акта равна нулю весь подлёт, а камера в
         это время в сотне с лишним единиц от станции: слово в два
         десятка единиц позади неё выходило в десяток точек и «встречи»
         не получалось, замер видел явь в половину, снимок ничего. Плоскость
         растёт с дистанцией не до конца (степень меньше единицы): далёкое
         слово читается, но остаётся далёким и продолжает уходить вглубь
         с параллаксом, а не висит наклейкой одного размера. */
      /* Страховка от призраков. Явь приходит из подписки, а подписка
         молчит для актов, которые лента проскочила прыжком: их доля
         застывает на полпути, и слово стоит с полной явью за сотни
         единиц от камеры - крошечным обломком в кольце чужого акта.
         Расстояние до станции в актах здесь считается заново на каждом
         кадре: дальше двух актов слова нет, что бы ни думала подписка.
         Внутри своего акта множитель равен единице и ничего не меняет. */
      var страховка = (g.RV_WORLD && g.RV_WORLD["наСтанции"]) ? зажать(2 * g.RV_WORLD["наСтанции"](имя, 1.0), 0, 1) : 1;
      у.явьФакт = у.явь * страховка;
      u.uYav.value = у.явьФакт;
      if (страховка <= 0) { сетка.scale.set(0.001, 0.001, 1); return; }
      if (W.cam) {
        if (!точка) { точка = new T.Vector3(); цель = new T.Vector3(); местн = new T.Vector3(); }
        /* Рост считается от самой плоскости, а не от гнезда: на станции
           камера стоит в дюжине единиц перед гнездом, слово же в двух с
           лишним десятках за ним, и от гнезда слово выходило вдвое
           мельче, чем принято по снимкам станции. */
        var гн = у.группа.parent || у.группа;
        сетка.getWorldPosition(точка);
        var дист = точка.distanceTo(W.cam.position);
        var к = Math.pow(Math.max(1, дист / 26), 0.9);
        if (к > 6) к = 6;
        /* Не шире шести десятых кадра. Рост с дистанцией выводил
           НАСКВОЗЬ на телефоне в четыре с половиной сотни точек при
           ширине экрана в четыре: слово не помещалось целиком ни при
           каком сдвиге. Предел считается от кадра на этой дистанции,
           поэтому на мониторе он не срабатывает вовсе. */
        var высПоля = 2 * дист * Math.tan((W.cam.fov || 50) * Math.PI / 360);
        var асп = W.cam.aspect || 1;
        var предел = 0.62 * высПоля * асп / сетка.geometry.parameters.width;
        if (к > предел) к = предел;
        сетка.scale.set(к, к, 1);
        /* Лицом к камере. Гнездо смотрит туда, где камера стоит НА
           станции, а на подлёте она заходит сбоку, и плоскость под углом
           сжималась в полосу: слово, ради которого перегон получает
           цель, читалось хуже всего именно на перегоне. Крен и качание
           кладутся поверх поворота, поэтому идут здесь, а не на группе. */
        сетка.lookAt(W.cam.position);
        сетка.rotateZ((у.д - 0.5) * 0.06);
        if (ст >= 1) сетка.rotateX(0.03 * Math.sin((W.часы || 0) * 0.4 + у.сдвиг));
        /* Сдвиг вправо считается от камеры, а не от оси гнезда: гнездо
           повёрнуто к камере на станции, а на подлёте она заходит сбоку,
           и «вправо по гнезду» на экране выходило влево, прямо под
           заголовок акта. Сдвиг растёт с той же дистанцией, что и
           плоскость: единица на подлёте в сотне единиц это пара точек.
           Только на широком кадре: на телефоне текст идёт во всю ширину,
           и сдвинутое слово вылетало бы за край. */
        /* Степень выше единицы: на станции слово стоит в просвете между
           словами и предметом. */
        var узкий = асп < 1;
        var ш = узкий ? 0 : ТИТРЫ[имя].дх * Math.pow(к, 1.3);
        if (!вправо) { вправо = new T.Vector3(); кв = new T.Quaternion(); }
        вправо.setFromMatrixColumn(W.cam.matrixWorld, 0).normalize();
        if (у.группа.parent) {
          кв.setFromRotationMatrix(у.группа.parent.matrixWorld).invert();
          вправо.applyQuaternion(кв);
        }
        местн.set(вправо.x * ш, ТИТРЫ[имя].ду + вправо.y * ш, у.дz - у.д * 9 + вправо.z * ш);
        /* Встреча на подлёте: слово ставится в кадр, а не к оси гнезда.
           Гнездо на подлёте лежит там, куда камера ещё только едет, и
           сдвиг от него на мониторе клал ШЛЮЗ ровно в хвост заголовка
           «Причаль свои», а на телефоне уносил НАСКВОЗЬ за левый край.
           Поэтому пока камера далеко (и акт ещё не начался), слово держит
           место в кадре на глубине гнезда: на мониторе правая нижняя
           четверть, где у актов нет ни строк, ни карточек; на телефоне
           небо над заголовком, единственная пустая часть кадра. По мере
           подлёта вес спадает, и слово плавно съезжает к своему месту у
           гнезда - это и есть встреча. После начала акта веса нет вовсе,
           иначе слово пройденного акта возвращалось бы в кадр на
           следующем перегоне. */
        var п = плавно((дист - 55) / 70) * (1 - плавно(у.д / 0.05));
        if (п > 0) {
          /* Глубина цели берётся от гнезда, а не от плоскости: плоскость
             сама стоит в цели, и её же дистанция, взятая за глубину, росла
             бы кадр за кадром вместе с боковым сдвигом. */
          гн.getWorldPosition(цель);
          var глубь = цель.distanceTo(W.cam.position);
          var высЦели = 2 * глубь * Math.tan((W.cam.fov || 50) * Math.PI / 360);
          цель.set((узкий ? 0.0 : 0.45) * высЦели * асп / 2, (узкий ? 0.5 : -0.5) * высЦели / 2, -глубь);
          цель.applyMatrix4(W.cam.matrixWorld);
          гн.worldToLocal(цель);
          местн.lerp(цель, п);
        }
        у.группа.position.copy(местн);
      }
      /* Микрокачание (выше, вместе с поворотом к камере): плоскость,
         стоящая неподвижно в живом мире, читается наклейкой на стекле.
         Наклон в три сотых едва заметен глазу, но снимает эту
         неподвижность. На нищей ступени без него: там и кадры реже, и
         качание превращается в дёрганье. */
    };
  }

  /* Ход титра. Разгорается в первой четверти акта, держится, гаснет в
     последней. Плюс медленный уход вглубь: титр отстаёт от камеры, и
     это тот самый параллакс, ради которого он и стоит в мире.

     Яркость намеренно скромная. Титр это фон кадра, а не его герой:
     герой - сцена и слова слева. Проверка контраста меряет это числом,
     и превышать её пороги титру нельзя. */
  /* Кого ещё не подписали. Мир бывает готов РАНЬШЕ плёнки: событие
     готовности мира приходит из очереди прогрева, а плёнка заводится по
     DOMContentLoaded. Первая сборка титров попадала в этот промежуток,
     подписка тихо не заводилась - и титры стояли в сцене с нулевой
     яркостью, не двигаясь. Видно это было только по замеру: на кадре
     невидимое от несуществующего не отличить.

     Поэтому подписку не «пробуем один раз», а ДОБИВАЕМСЯ: пока плёнки
     нет, имя лежит в очереди, и попытка повторяется. */
  var ждутПодписки = [];

  function подписать(имя) {
    if (!g.RV_MOTION || !g.RV_MOTION["слушать"]) {
      if (ждутПодписки.indexOf(имя) < 0) ждутПодписки.push(имя);
      добиться();
      return;
    }
    g.RV_MOTION["слушать"](имя, function (д) {
      var у = узлы[имя];
      if (!у) return;
      /* Встреча на подлёте. Доля акта равна нулю весь перегон к нему,
         и по одной доле титр возникал бы разом, уже на станции. Вес
         близости камеры (тот же, что проявляет станцию в акте выхода)
         поднимает слово заранее: на подлёте к рубке ШЛЮЗ уже висит в
         дымке впереди, и перегон получает цель. На подлёте титр не
         дотягивает до полной яви: слово ещё далёкое, а не встречающее. */
      var близко = (g.RV_WORLD && g.RV_WORLD["наСтанции"]) ? g.RV_WORLD["наСтанции"](имя, 1.15) : 0;
      var явь = Math.max(плавно(д / 0.22), 0.6 * близко) * (1 - плавно((д - 0.80) / 0.20));
      /* Яркость скромная. Титр это воздух кадра: заметил - хорошо,
         не заметил - тоже хорошо. Прежние три десятых спорили с самой
         сценой и лезли в глаза именно тем, что были ярче предметов,
         стоящих ближе. На подлёте чуть ярче: слов акта в кадре ещё нет,
         спорить не с кем, а далёкому слову нужен запас, чтобы читаться
         сквозь дымку. К первой восьмой хода яркость возвращается вниз:
         проверка контраста меряет от пятой доли, и к ней титр обязан
         стоять на прежней. */
      у.д = д;
      у.явь = явь;
      у.яркость = 0.15 + 0.07 * (1 - плавно(д / 0.12));
      у.группа.visible = явь > 0.01;
      /* Уход вглубь на треть длины перегона за акт. Титр не догоняет
         камеру и остаётся позади - как надпись на стене, мимо которой
         летишь. */
      у.группа.position.z = у.дz - д * 9;
      /* Едва заметный крен по доле ставится покадрово, поверх поворота
         к камере: плоскость, стоящая строго по оси, читается наклейкой,
         наклон возвращает ей место в пространстве. */
    });
  }

  var ждём = 0;
  function добиться() {
    if (ждём || !ждутПодписки.length) return;
    ждём = g.setTimeout(function () {
      ждём = 0;
      if (!g.RV_MOTION || !g.RV_MOTION["слушать"]) { добиться(); return; }
      var очередь = ждутПодписки.slice();
      ждутПодписки.length = 0;
      for (var i = 0; i < очередь.length; i++) подписать(очередь[i]);
    }, 120);
  }

  if (g.RV_WORLD && g.RV_WORLD["готов"] && g.RV_WORLD["готов"]()) собрать();
  else g.addEventListener("rv:мир", собрать);

  g.RV_ТИТРЫ = {
    "состояние": function () {
      var из = {};
      for (var имя in узлы) {
        if (!узлы.hasOwnProperty(имя)) continue;
        /* Яркость наружу отдаём итоговую, явь на силу: прежняя проверка
           читала одно число прозрачности, и его смысл сохранён. */
        /* Явь наружу идёт после страховки: именно её видит кадр. */
        var явь = typeof узлы[имя].явьФакт === "number" ? узлы[имя].явьФакт : узлы[имя].явь;
        из[имя] = {
          "виден": !!узлы[имя].группа.visible && явь > 0.01,
          "яркость": +(явь * узлы[имя].яркость).toFixed(3),
          "явь": +явь.toFixed(3),
          "z": +узлы[имя].группа.position.z.toFixed(1)
        };
      }
      return из;
    }
  };
})(window, document);
