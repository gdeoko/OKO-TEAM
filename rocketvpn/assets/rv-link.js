/* Rocket VPN. Связка с Rocket CDN: приход и уход через космос.

   Механизм один, направлений два. Оба держатся на одном соглашении об
   адресе, и оно записано здесь, чтобы не расползлось по двум сайтам:

     из CDN сюда:  rocketvpn.top/site?k=КЛЮЧ&from=cdn

   ── УХОДА ОТСЮДА В CDN БОЛЬШЕ НЕТ ────────────────────────────────
   Здесь было второе направление, rocketcdn.ru/?from=vpn. Заказчик
   попросил его закрыть: «не очень хочу, чтобы пользаки свободно шли на
   CDN сайт, VPN это серая зона бизнеса, а CDN прозрачная; если из впн
   на cdn будет свободный переход, мою личность установить будет крайне
   легко».

   Убран и адрес, и признак перехода: адрес чужого сайта в нашем коде
   это такая же связка, как и сама кнопка, и её видно любому, кто
   откроет исходник. Полёт, ради которого туда и ходили, теперь живёт
   на своём домене (index.php по признаку flight).

   Имя признака латиницей намеренно. Кириллическое имя браузер выводит в
   адресной строке в процентах (из превращается в %D0%B8%D0%B7), и такую
   ссылку нельзя ни продиктовать, ни прочитать глазами в чужой аналитике.
   Комментарии в коде на русском, а внешние договорённости - латиницей.

   ПОЧЕМУ ПРИШЕДШИЙ ИЗ КОСМОСА ПОПАДАЕТ НЕ НА ПЕРВЫЙ ЭКРАН. Человек,
   пришедший через прокол, уже прошёл сюжет проблемы: он видел космос,
   он летел. Показать ему заново «тебя видно» и «периметр» значит
   отмотать его назад и обесценить переход. Он приходит сразу в акт
   выхода - туда, где сеть уже открыта.

   ПОЧЕМУ БЕЗ ПЛАВНОЙ ПРОКРУТКИ. Пролистывание десяти экранов на глазах
   читается как сбой, а не как переход: человек видит, что его куда-то
   утащило. Ставим сразу и без движения. */
(function (g, d) {
  "use strict";

  function откуда() {
    try {
      var m = /[?&]from=([a-z]+)/i.exec(g.location.search || "");
      return m ? m[1].toLowerCase() : "";
    } catch (e) { return ""; }
  }

  var пришёл = откуда();

  function приход() {
    if (пришёл !== "cdn") return;
    if (!g.RV_MOTION || !g.RV_MOTION["кПунктy"]) return;
    /* Возврат из полёта приводит к рабочему пульту финала. */
    g.RV_MOTION["кПунктy"]("финал", 0.90);
    d.documentElement.setAttribute("data-из", "cdn");
  }

  /* Уход снят вместе с кнопкой. Функция не оставлена даже пустой:
     пустая заглушка живёт годами и однажды снова обрастает адресом. */

  function старт() {
    приход();
  }

  /* Ждём не появления плёнки, а СБОРКИ актов. Разница оказалась
     решающей: оба файла отложенные, поэтому к моменту запуска этого
     объект плёнки уже существует, а список актов ещё пуст - она
     собирает его по готовности разметки. Приход, вызванный раньше,
     молча не находил акта и оставлял человека на первом экране.

     Кадр после готовности разметки нужен затем, чтобы липкие кадры
     успели встать на места: без него положение акта считается по
     недоразложенной странице. */
  function позже() {
    g.requestAnimationFrame(function () { g.requestAnimationFrame(старт); });
  }
  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", позже);
  else позже();

  /* Наружу отдаём только «откуда пришёл»: он нужен акту выхода.
     Ход «вCDN» убран - его звали ровно из снятой кнопки. */
  g.RV_LINK = {
    "откуда": function () { return пришёл; }
  };
})(window, document);
