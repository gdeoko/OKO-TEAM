/* ═══════════════════════════════════════════════════════════
   Rocket VPN · звук фильма

   Сценарий требует звука в одном месте прямо и по имени: на проколе
   провал в тишину на треть секунды, потом низкий удар. Тишина там
   работает сильнее любого рёва, и без неё главный кадр сайта остаётся
   немым.

   ЧТО ПОМЕНЯЛОСЬ ПРОТИВ ПЕРВОЙ СБОРКИ. Раньше звук синтезировался
   прямо здесь: осцилляторы, фильтры, ноль веса. Он честно вёл фильм за
   прокруткой и честно звучал синтезатором. Сайт продаёт защиту, а
   защита не может звучать дёшево, поэтому весь звук снят студийно
   (ElevenLabs, слоями, tools/звук/банк.py) и лежит в assets/snd.

   ШЕСТЬ РЕШЕНИЙ, НА КОТОРЫХ СТОИТ ФАЙЛ.

   1. ЗВУК ИДЁТ ОТ ТОЙ ЖЕ ВЕЛИЧИНЫ, ЧТО И КАРТИНКА. Никаких событий
      «долистал до места»: громкости считаются из доли хода акта, той
      самой --д. Прокрутка вверх звучит обратным ходом, а не повтором.
      Это главное, что осталось от синтезированной сборки, и это
      важнее самого звука.

   2. ПОДЛОЖКИ ПЕРЕТЕКАЮТ, А НЕ СМЕНЯЮТСЯ. Шесть петель идут
      одновременно с нуля громкости; акт поднимает свою и опускает
      чужие. Склейки между актами не существует физически - ровно так
      же, как её нет у картинки, где камера едет по одному миру.

   3. НИЧЕГО НЕ КАЧАЕТСЯ, ПОКА НЕ ПОПРОСИЛИ. Почти мегабайт звука не
      имеет права ехать к человеку, который звук не включал. Файлы
      тянутся ТОЛЬКО после нажатия кнопки, и двумя волнами: сначала
      подложка текущего акта и мелочь интерфейса, потом всё остальное.

   4. МОЛЧИТ, ПОКА НЕ ПОПРОСИЛИ. Браузер и так не даст звука без
      действия человека, но дело не в этом: сайт, заоравший в тишине
      офиса, теряет человека навсегда. Кнопка одна, состояние помнится.

   5. НИЧЕГО НЕ ЛОМАЕТ. Нет Web Audio, отказал контекст, не доехал
      файл, запрещена автоигра - файл молча выключается. Звук это
      отделка, и он не имеет права уронить сцену.

   6. ЗВУК ОТВЕЧАЕТ НА РУКУ ЧЕЛОВЕКА. Мир отдаёт норму скорости камеры,
      подложка на быстрой прокрутке становится громче и звонче, у
      разовых уезжает высота. Ровно этим озвученный сайт отличается от
      сайта с музыкой: слышно, что звук идёт за тобой.
   ═══════════════════════════════════════════════════════════ */
(function (g, d) {
  "use strict";

  var ПАМЯТЬ = "rv.звук";
  var ПАПКА = "assets/snd/";

  var К = null;              /* AudioContext */
  var шина = null;           /* общий выход с ограничителем */
  var вкл = false;
  var собран = false;
  var кнопка = null;

  /* Шесть подложек. Ключ здесь - имя файла без расширения. */
  var ПОДЛОЖКИ = ["bed-net", "bed-wall", "bed-shell", "bed-tunnel",
                  "bed-open", "bed-bridge"];
  /* Разовые. Мелочь интерфейса едет в первой волне вместе с подложкой
     текущего акта: она нужна сразу, а весит копейки. */
  var СРАЗУ = ["tap", "hover", "pick"];
  var РАЗОВЫЕ = ["sweep", "shell-seal", "pull", "impact", "pick", "dock",
                 "gate", "tap", "hover"];

  /* Окна зажигания акта пуска. Те же три числа стоят в rv-act-пуск.js и
     означают одно и то же: шаг разметки, окно света у кольца и звук
     обязаны говорить об одном моменте. Двигать можно только вместе. */
  var ОКНА = [[0.10, 0.28], [0.34, 0.52], [0.58, 0.76]];

  /* ── Петля без щелчка ───────────────────────────────────────
     Шесть подложек лежат в файлах ровно одной длины. Пущенные разом,
     они перещёлкиваются в один и тот же миг, и повтор слышен как ритм:
     ухо ловит период раньше, чем узнаёт запись. Лечится двумя вещами
     сразу.

     Первое: у каждой подложки своя длина петли. Доли ниже нарочно не
     кратны друг другу, поэтому стыки шестерых сходятся не через два
     круга, а через сотни.

     Второе: подложку ведут ДВА источника одного файла, сдвинутые на
     полпериода, а их громкости идут встречными дугами синуса и
     косинуса. Сумма квадратов у них единица, значит громкость на слух
     ровная, а стык каждого источника приходится ровно на его
     собственный ноль: щёлкать нечему. */
  var ДОЛИПЕТЛИ = [1.000, 0.983, 0.966, 0.949, 0.932, 0.915];
  var ТОЧЕК = 33;            /* точек кривой на один период */
  var ЗАПАС = 10;            /* на сколько секунд вперёд расписан кроссфейд */

  var буферы = {};           /* имя -> AudioBuffer */
  var везут = {};            /* имя -> Promise, чтобы не тянуть дважды */
  var петли = {};            /* имя -> { уровень, кросс, период, до } */
  var гулШина = null;        /* общий вход подложек */
  var яркость = null;        /* полка верха: мир быстрее - подложка звонче */
  var часовой = 0;           /* дописывает расписание кроссфейда */
  var живых = 0;             /* сколько разовых звучит прямо сейчас */
  var сыграно = {};          /* имя -> сколько раз сыграл: это читает замер */
  var ждут = [];             /* разовые, чей файл ещё в пути */
  var скорМира = 0;          /* сглаженная норма скорости камеры */

  /* Когда каждый разовый звучал в последний раз. Без этого удар
     прокола повторяется на каждом кадре, пока доля стоит в его окне. */
  var последняя = {};

  function можно() { return !!(g.AudioContext || g.webkitAudioContext); }
  function зажать(v, a, b) { return v < a ? a : (v > b ? b : v); }

  /* Приём эталона: величина едет от «с» к «до» на отрезке [a, b] и
     стоит за его краями, вход и выход сглажены. Порог «если доля
     больше» включает звук щелчком ровно там, где человек ждёт хода, и
     этот щелчок слышен даже на тихой подложке. */
  function фит(v, a, b, с, до) {
    var t = зажать((v - a) / (b - a), 0, 1);
    t = t * t * (3 - 2 * t);
    return с + (до - с) * t;
  }

  /* ── Доставка ───────────────────────────────────────────────
     Один файл - один запрос - один разбор. Отказ любого файла НЕ
     останавливает остальные: звук без одной подложки хуже полного, но
     несравнимо лучше молчания. */
  function достать(имя) {
    if (буферы[имя]) return Promise.resolve(буферы[имя]);
    if (везут[имя]) return везут[имя];
    везут[имя] = fetch(ПАПКА + имя + ".mp3", { credentials: "same-origin" })
      .then(function (о) {
        if (!о.ok) throw new Error("нет " + имя);
        return о.arrayBuffer();
      })
      .then(function (сырое) {
        return new Promise(function (готово, беда) {
          /* Старый вид вызова с обратными вызовами: Safari до
             четырнадцатой версии не отдаёт обещание из decodeAudioData,
             и без этого запаса звук там не заводится вовсе. */
          var р = К.decodeAudioData(сырое, готово, беда);
          if (р && р.then) р.then(готово, беда);
        });
      })
      .then(function (б) {
        буферы[имя] = б;
        if (ПОДЛОЖКИ.indexOf(имя) >= 0) завестиПетлю(имя);
        else догнать(имя);
        return б;
      })
      .catch(function () { везут[имя] = null; return null; });
    return везут[имя];
  }

  /* Подложка заводится сразу по приезде и крутится до конца сеанса на
     нулевой громкости. Пуск петли по требованию давал бы щелчок входа
     ровно в тот момент, когда акт хочет тишины. */
  function завестиПетлю(имя) {
    if (!К || петли[имя] || !буферы[имя]) return;
    var б = буферы[имя];
    var к = ПОДЛОЖКИ.indexOf(имя);
    var П = б.duration * ДОЛИПЕТЛИ[к < 0 ? 0 : к];
    if (!(П > 0.5)) П = б.duration;
    /* Общий уровень подложки один на обе копии: акт говорит громкость,
       и ему незачем знать, что копий две. */
    var г = К.createGain();
    г.gain.value = 0;
    г.connect(гулШина || шина);
    var т0 = К.currentTime + 0.06;
    var кросс = [];
    for (var i = 0; i < 2; i++) {
      var и = К.createBufferSource();
      и.buffer = б;
      и.loop = true;
      и.loopStart = 0;
      и.loopEnd = П;
      var кг = К.createGain();
      кг.gain.value = 0;
      и.connect(кг); кг.connect(г);
      /* Вторая копия входит с середины периода: её стык приходится
         туда, где первая звучит в полную силу, и наоборот. */
      try { и.start(т0, i * П * 0.5); } catch (e) { return; }
      кросс.push(кг.gain);
    }
    петли[имя] = { уровень: г.gain, кросс: кросс, период: П, до: т0, ровно: false };
    расписать(имя);
    завестиЧасового();
  }

  /* Дуги кроссфейда расписываются вперёд на десяток секунд и
     дописываются часовым. Расписать весь сеанс сразу нельзя: человек
     может слушать полчаса, и очередь автоматики на полчаса браузер
     держит хуже короткой. */
  function расписать(имя) {
    var п = петли[имя];
    if (!п || !К || п.ровно) return;
    var предел = К.currentTime + ЗАПАС;
    var крА = new Float32Array(ТОЧЕК);
    var крБ = new Float32Array(ТОЧЕК);
    for (var n = 0; n < ТОЧЕК; n++) {
      var u = n / (ТОЧЕК - 1);
      крА[n] = Math.sin(Math.PI * u);
      крБ[n] = Math.abs(Math.cos(Math.PI * u));
    }
    while (п.до < предел) {
      try {
        п.кросс[0].setValueCurveAtTime(крА, п.до, п.период);
        п.кросс[1].setValueCurveAtTime(крБ, п.до, п.период);
      } catch (e) {
        /* Браузер не принял расписание - ведём обе копии ровно. Стык
           станет слышен, звук останется: молчащая подложка хуже. */
        try {
          п.кросс[0].value = 0.707;
          п.кросс[1].value = 0.707;
        } catch (e2) {}
        п.ровно = true;
        return;
      }
      п.до += п.период;
    }
  }

  function завестиЧасового() {
    if (часовой || !g.setInterval) return;
    часовой = g.setInterval(function () {
      for (var i = 0; i < ПОДЛОЖКИ.length; i++) расписать(ПОДЛОЖКИ[i]);
    }, 3000);
  }

  /* Первая волна: подложка того акта, который человек видит сейчас,
     плюс мелочь интерфейса. Вторая: всё остальное, следом и молча. */
  function везтиВсё(текущийАкт) {
    var первая = [подложкаАкта(текущийАкт)].concat(СРАЗУ);
    var очередь = [];
    for (var i = 0; i < ПОДЛОЖКИ.length; i++) {
      if (первая.indexOf(ПОДЛОЖКИ[i]) < 0) очередь.push(ПОДЛОЖКИ[i]);
    }
    for (var j = 0; j < РАЗОВЫЕ.length; j++) {
      if (первая.indexOf(РАЗОВЫЕ[j]) < 0 && очередь.indexOf(РАЗОВЫЕ[j]) < 0) {
        очередь.push(РАЗОВЫЕ[j]);
      }
    }
    Promise.all(первая.map(достать)).then(function () {
      for (var k = 0; k < очередь.length; k++) достать(очередь[k]);
    });
  }

  function подложкаАкта(имя) {
    if (имя === "видно") return "bed-net";
    if (имя === "периметр") return "bed-wall";
    if (имя === "оболочка") return "bed-shell";
    if (имя === "прокол") return "bed-tunnel";
    if (имя === "рубка") return "bed-bridge";
    if (имя === "пуск") return "bed-shell";
    return "bed-open";
  }

  /* ── Сборка ─────────────────────────────────────────────────
     Собираем один раз и по первому включению: держать контекст
     открытым, пока человек не попросил звука, значит зря греть
     телефон. */
  function собрать() {
    if (собран) return true;
    var A = g.AudioContext || g.webkitAudioContext;
    if (!A) return false;
    try { К = new A(); } catch (e) { return false; }

    /* Ограничитель на выходе. Голосов немного, но удар прокола
       сходится с подложкой тоннеля, и без него сумма щёлкает. */
    var огр = К.createDynamicsCompressor();
    огр.threshold.value = -12;
    огр.knee.value = 20;
    огр.ratio.value = 8;
    огр.attack.value = 0.004;
    огр.release.value = 0.22;

    шина = К.createGain();
    шина.gain.value = 0;
    шина.connect(огр);
    огр.connect(К.destination);

    /* Отдельный вход для подложек, и на нём одна полка верха. Ею мир
       говорит о скорости: на перегоне фон становится звонче, на
       остановке гаснет обратно. Высоту самих петель трогать нельзя -
       она увела бы стык от нуля кроссфейда, и щелчок вернулся бы.
       Разовым полка не нужна, у них своя высота на каждый вызов. */
    яркость = К.createBiquadFilter();
    яркость.type = "highshelf";
    яркость.frequency.value = 2600;
    яркость.gain.value = 0;
    гулШина = К.createGain();
    гулШина.gain.value = 1;
    гулШина.connect(яркость);
    яркость.connect(шина);
    собран = true;
    return true;
  }

  /* Скорость камеры из мира. Сглаживаем своим ходом: норма приходит
     покадрово и дёргается, а полка и громкость на дёрганье отзываются
     шипением. */
  function читатьМир() {
    var с = 0;
    try {
      if (g.RV_WORLD && g.RV_WORLD["скорость"]) {
        с = g.RV_WORLD["скорость"]()["норм"] || 0;
      }
    } catch (e) {}
    скорМира += (зажать(с, 0, 1) - скорМира) * 0.12;
    if (яркость && К) яркость.gain.setTargetAtTime(скорМира * 3.5, К.currentTime, 0.25);
  }

  /* ── Разовый звук ───────────────────────────────────────────
     Своя громкость и своя высота у каждого вызова: одинаково
     сыгранный дважды звук ухо ловит как повтор записи. */
  function пустить(имя, громко, скорость) {
    if (!вкл || !К || !буферы[имя]) return false;
    var и = К.createBufferSource();
    и.buffer = буферы[имя];
    и.playbackRate.value = скорость == null ? 1 : скорость;
    var г = К.createGain();
    г.gain.value = громко == null ? 1 : громко;
    и.connect(г); г.connect(шина);
    живых++;
    и.onended = function () { живых = живых > 0 ? живых - 1 : 0; };
    try { и.start(0); } catch (e) { живых--; return false; }
    сыграно[имя] = (сыграно[имя] || 0) + 1;
    return true;
  }

  /* Разовый с выдержкой: не чаще, чем раз в столько-то секунд.

     Вызов, чей файл ещё не доехал, раньше пропадал молча: главный удар
     акта прокола мог не сыграть вовсе, и человек об этом не узнавал.
     Теперь он ждёт в очереди четыре десятых секунды - столько живёт
     точность момента, дальше звук был бы уже про другой кадр.

     Высота едет за скоростью мира: на перегоне мелочь звенит выше. */
  function разом(имя, выдержка, громко, скорость) {
    if (!К) return;
    var t = К.currentTime;
    if (последняя[имя] && t - последняя[имя] < выдержка) return;
    последняя[имя] = t;
    var ск = (скорость == null ? 1 : скорость) * (1 + скорМира * 0.04);
    if (!буферы[имя]) {
      ждут.push({ имя: имя, срок: t + 0.4, громко: громко, скорость: ск });
      достать(имя);
      return;
    }
    пустить(имя, громко, ск);
  }

  /* Догоняем тех, кто ждал файла. Просроченное выбрасываем молча: удар,
     опоздавший на секунду, хуже несыгранного. */
  function догнать(имя) {
    if (!К || !ждут.length) return;
    var t = К.currentTime, оставить = [];
    for (var i = 0; i < ждут.length; i++) {
      var з = ждут[i];
      if (з.имя !== имя) {
        if (з.срок >= t) оставить.push(з);
        continue;
      }
      if (з.срок >= t && буферы[имя] && вкл) пустить(имя, з.громко, з.скорость);
    }
    ждут = оставить;
  }

  /* Плавная установка уровня подложки. Тянемся к цели, а не прыгаем:
     доля хода приходит ступенями, и прыжок слышен ступенькой. */
  function уровень(имя, цель, мягкость) {
    var п = петли[имя];
    if (!п || !К) return;
    /* Подъём по скорости множителем, а не слагаемым: ноль обязан
       остаться нулём. Тишина перед ударом прокола не имеет права
       зазвучать оттого, что человек листает быстро. */
    var ц = цель * (1 + скорМира * 0.16);
    п.уровень.setTargetAtTime(ц, К.currentTime, мягкость == null ? 0.30 : мягкость);
  }

  /* Все подложки, кроме названных, уводятся в ноль. Так акт не обязан
     помнить про чужие: он говорит, что звучит у него, остальное
     гасится само. */
  function толькоЭти(список, мягкость) {
    for (var i = 0; i < ПОДЛОЖКИ.length; i++) {
      var имя = ПОДЛОЖКИ[i];
      var k = список.indexOf(имя);
      if (k < 0) уровень(имя, 0, мягкость);
    }
  }

  /* ── Что звучит в каждом акте ───────────────────────────────
     Величины берутся из доли хода: звук не проигрывается, он ЕДЕТ. */
  function поАкту(имя, д) {
    if (!вкл || !К || !собран) return;
    /* Скорость читается до отбора акта: она нужна и на стыке, где
       ведущего акта нет ни одного. */
    читатьМир();

    /* Голоса общие на весь сайт, а подписчиков семь: плёнка зовёт
       каждого на каждом кадре, со своей долей. Ведёт звук ТОЛЬКО тот
       акт, который сейчас идёт: его доля строго внутри отрезка. Акты,
       которые ещё не начались (ноль) или уже кончились (единица),
       молчат и чужого не трогают.

       Без этого замер показывал одну и ту же громкость во всех местах
       сайта, включая тишину перед ударом: последний подписчик в списке
       затирал текущий. */
    if (д <= 0.002 || д >= 0.998) return;

    if (имя === "видно") {
      уровень("bed-net", 0.62 + д * 0.10, 0.4);
      толькоЭти(["bed-net"], 0.5);
      return;
    }

    if (имя === "периметр") {
      /* Стена ближе, чем сеть, поэтому громче. Перетекание идёт по
         доле: в начале акта ещё слышна сеть, к середине только стена. */
      var сеть = зажать(1 - д * 3, 0, 1);
      уровень("bed-net", сеть * 0.55, 0.35);
      уровень("bed-wall", 0.72 + д * 0.16, 0.35);
      толькоЭти(["bed-net", "bed-wall"], 0.5);
      /* Луч досмотра ходит по стене четыре раза за акт - столько же,
         сколько в картинке. Высота каждого прохода чуть своя. */
      var проход = Math.floor(д * 4);
      if (проход !== последняя.проход && д > 0.06) {
        последняя.проход = проход;
        разом("sweep", 1.2, 0.62, 0.94 + (проход % 3) * 0.05);
      }
      return;
    }

    if (имя === "оболочка") {
      /* Смыкание ровно там, где сходятся две половины. До него слышно
         стену, после - только глухую тишину внутри корпуса. */
      var снаружи = зажать(1 - (д - 0.30) * 4, 0, 1);
      уровень("bed-wall", снаружи * 0.50, 0.3);
      уровень("bed-shell", зажать((д - 0.34) * 3.2, 0, 1) * 0.80, 0.35);
      толькоЭти(["bed-wall", "bed-shell"], 0.5);
      if (д > 0.40 && д < 0.58) разом("shell-seal", 4.0, 0.85);
      return;
    }

    if (имя === "прокол") {
      /* ГЛАВНОЕ МЕСТО. До броска всё гаснет, дальше настоящая тишина,
         и на выходе из неё - удар.

         Три отрезка, границы взяты из картинки: слова уводятся с
         экрана на 0.395 и возвращаются на 0.50, и звук обязан молчать
         ровно в этом окне, а не рядом с ним. */
      if (д < 0.33) {
        /* Оболочка уходит, вместо неё тянет вытяжка. */
        уровень("bed-shell", зажать(1 - д * 3.4, 0, 1) * 0.60, 0.25);
        толькоЭти(["bed-shell"], 0.25);
        if (д > 0.24) разом("pull", 6.0, 0.95);
      } else if (д < 0.44) {
        /* ТИШИНА. Ни подложек, ни разовых. Ради неё всё и затевалось. */
        толькоЭти([], 0.05);
      } else {
        разом("impact", 5.0, 1.0);
        /* Тоннель: скорость слышна и растёт до конца акта. */
        уровень("bed-tunnel", 0.30 + (д - 0.44) * 0.95, 0.30);
        толькоЭти(["bed-tunnel"], 0.4);
      }
      return;
    }

    if (имя === "выход") {
      уровень("bed-tunnel", зажать(1 - д * 3.2, 0, 1) * 0.55, 0.4);
      уровень("bed-open", зажать((д - 0.10) * 3, 0, 1) * 0.78, 0.5);
      толькоЭти(["bed-tunnel", "bed-open"], 0.6);
      return;
    }

    if (имя === "рубка") {
      уровень("bed-open", зажать(1 - д * 3, 0, 1) * 0.45, 0.5);
      уровень("bed-bridge", 0.70, 0.5);
      толькоЭти(["bed-open", "bed-bridge"], 0.6);
      /* Стыковка устройств идёт в средней трети, там же, где щит
         занимает кадр целиком. Три причала - три захвата. */
      var причал = зажать(Math.floor((д - 0.34) * 9.09), 0, 2);
      if (д > 0.34 && д < 0.67 && причал !== последняя.причал) {
        последняя.причал = причал;
        /* Громкость растёт от причала к причалу: три одинаковых удара
           ухо слышит как заедание, три растущих - как подход. */
        разом("dock", 0.9, 0.58 + причал * 0.11, 0.95 + причал * 0.05);
      }
      return;
    }

    if (имя === "пуск") {
      /* Акта здесь не было вовсе. Человек проходил семь актов со звуком
         и попадал в инструкцию, где висел хвост чужой подложки: гул
         стоял на одном числе от начала до конца.

         Теперь у пуска своя картина, и собрана она по той же разметке,
         что и картинка: три окна зажигания у колец совпадают с тремя
         шагами списка.

         Подъём и уход идут приёмом эталона, а не порогом. Рубка сдаёт
         звук пуску, пуск сдаёт его стыковке, и ни одна передача не
         слышна щелчком. */
      var подъём = фит(д, 0.05, 0.20, 0, 1) * фит(д, 0.75, 0.95, 1, 0);
      уровень("bed-bridge", фит(д, 0.02, 0.30, 0.46, 0), 0.40);
      уровень("bed-shell", 0.16 + подъём * 0.44, 0.35);
      уровень("bed-open", фит(д, 0.62, 0.98, 0, 0.56), 0.45);
      толькоЭти(["bed-bridge", "bed-shell", "bed-open"], 0.5);
      /* Три шага: на входе в окно зубцы хватают кольцо, на выходе замок
         встаёт. Каждый следующий выше предыдущего - ступень вверх ухо
         читает как продвижение, ровные повторы как топтание. */
      /* Считаем НОМЕР пройденного окна, а не попадание в узкую полоску
         возле его края: на быстрой прокрутке кадр перешагивает полоску
         целиком, и звук шага пропадал бы ровно там, где человек летит. */
      var шаг = -1, замок = -1;
      for (var ш = 0; ш < ОКНА.length; ш++) {
        if (д >= ОКНА[ш][0]) шаг = ш;
        if (д >= ОКНА[ш][1]) замок = ш;
      }
      if (шаг >= 0 && шаг !== последняя.шаг) {
        последняя.шаг = шаг;
        разом("dock", 0.5, 0.52 + шаг * 0.09, 0.94 + шаг * 0.05);
      }
      if (замок >= 0 && замок !== последняя.замок) {
        последняя.замок = замок;
        разом("pick", 0.4, 0.62 + замок * 0.06, 1.02 + замок * 0.06);
      }
      /* Канал встал. Один раз за акт и низко: это итог трёх шагов, а не
         очередная кнопка. */
      if (д > 0.86) разом("shell-seal", 9.0, 0.62, 0.78);
      return;
    }

    if (имя === "стыковка") {
      уровень("bed-bridge", зажать(1 - д * 2.6, 0, 1) * 0.50, 0.5);
      уровень("bed-open", 0.55 + д * 0.14, 0.5);
      толькоЭти(["bed-bridge", "bed-open"], 0.6);
      /* Ворота на сторону соседей открываются один раз. */
      if (д > 0.50) разом("gate", 8.0, 0.92);
      return;
    }
  }

  /* Ответ станции: зовётся актом выхода, когда человек выбрал точку. */
  function станция() { разом("pick", 0.12, 0.85); }

  /* ── Включение ──────────────────────────────────────────────── */
  function включить(да) {
    if (да && !собрать()) return false;
    вкл = !!да;
    if (К && К.state === "suspended") { try { К.resume(); } catch (e) {} }
    if (вкл) везтиВсё(текущийАкт());
    if (шина) {
      шина.gain.setTargetAtTime(вкл ? 0.9 : 0, К.currentTime, вкл ? 0.30 : 0.12);
    }
    try { localStorage.setItem(ПАМЯТЬ, вкл ? "1" : "0"); } catch (e2) {}
    if (кнопка) {
      кнопка.setAttribute("aria-pressed", вкл ? "true" : "false");
      кнопка.setAttribute("aria-label", вкл ? "Выключить звук" : "Включить звук");
      кнопка.classList.toggle("rv-звук-вкл", вкл);
    }
    return вкл;
  }

  /* Какой акт человек видит прямо сейчас. Нужно ровно для одного: с
     какой подложки начинать доставку. */
  function текущийАкт() {
    var акты = d.querySelectorAll(".rv-акт");
    var в = g.innerHeight || 800;
    for (var i = 0; i < акты.length; i++) {
      var к = акты[i].getBoundingClientRect();
      if (к.top <= в * 0.5 && к.bottom >= в * 0.5) {
        return акты[i].getAttribute("data-акт") || "";
      }
    }
    return "видно";
  }

  function поставитьКнопку() {
    if (!можно() || кнопка) return;
    кнопка = d.createElement("button");
    кнопка.type = "button";
    кнопка.className = "rv-звук";
    кнопка.setAttribute("aria-pressed", "false");
    кнопка.setAttribute("aria-label", "Включить звук");
    кнопка.innerHTML =
      '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" ' +
      'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
      '<path d="M4 9.5h3.2L12 5.8v12.4L7.2 14.5H4z"/>' +
      '<path class="rv-звук-волна" d="M15.4 9.2a4 4 0 0 1 0 5.6"/>' +
      '<path class="rv-звук-волна" d="M17.9 6.8a7.5 7.5 0 0 1 0 10.4"/>' +
      '<path class="rv-звук-крест" d="M16.2 9.6l5 5m0-5l-5 5"/>' +
      '</svg>';
    кнопка.addEventListener("click", function () { включить(!вкл); });
    d.body.appendChild(кнопка);
  }

  /* Мелочь интерфейса. Вешается на весь документ одним слушателем, а не
     на каждый элемент: элементы приезжают из досье уже после сборки, и
     слушатель на каждом пришлось бы вешать заново. */
  function завестиМелочь() {
    d.addEventListener("pointerdown", function (е) {
      if (!вкл) return;
      var э = е.target && е.target.closest ?
        е.target.closest("a,button,.rv-станция,.rv-док") : null;
      /* Разброс высоты и громкости обязателен: пять одинаковых щелчков
         подряд по ряду карточек ухо слышит как заевшую запись, а не как
         отклик. */
      if (э && !э.classList.contains("rv-звук")) {
        разом("tap", 0.05, 0.50 + Math.random() * 0.06,
              0.94 + Math.random() * 0.12);
      }
    }, { passive: true });
    d.addEventListener("pointerover", function (е) {
      if (!вкл) return;
      var э = е.target && е.target.closest ?
        е.target.closest("a,button,.rv-станция,.rv-док") : null;
      if (э && !э.classList.contains("rv-звук")) {
        разом("hover", 0.20, 0.36 + Math.random() * 0.05,
              0.94 + Math.random() * 0.12);
      }
    }, { passive: true });
  }

  /* Удар прокола приходит событием из акта и несёт силу: вниз по ленте
     полную, вверх половинную. Играть его всегда одинаково значит врать -
     вверх стенка проходится мягче, и это слышно.

     Событие опережает окно по доле, а выдержка в пять секунд не даёт
     удару сыграть дважды: окно застаёт его уже сыгранным. */
  function завестиУдар() {
    g.addEventListener("rv:прокол", function (е) {
      if (!вкл) return;
      var с = е && е.detail ? е.detail["сила"] : null;
      с = зажать(с == null ? 1 : с, 0.2, 1);
      разом("impact", 5.0, 0.55 + с * 0.45, 1.04 - с * 0.08);
    });
  }

  function завести() {
    поставитьКнопку();
    завестиМелочь();
    завестиУдар();
    if (!g.RV_MOTION || !g.RV_MOTION["слушать"]) return;
    var акты = d.querySelectorAll(".rv-акт");
    for (var i = 0; i < акты.length; i++) {
      (function (имя) {
        g.RV_MOTION["слушать"](имя, function (д) { поАкту(имя, д); });
      })(акты[i].getAttribute("data-акт") || ("акт" + i));
    }
    /* Прошлый выбор человека. Сам звук всё равно ждёт первого касания:
       браузер не отдаёт контекст раньше, и это правильно. */
    var было = null;
    try { было = localStorage.getItem(ПАМЯТЬ); } catch (e) {}
    if (было === "1") {
      var раз = function () {
        d.removeEventListener("pointerdown", раз);
        d.removeEventListener("keydown", раз);
        включить(true);
      };
      d.addEventListener("pointerdown", раз, { once: true });
      d.addEventListener("keydown", раз, { once: true });
    }
  }

  g.RV_SOUND = {
    "включить": включить,
    "идёт": function () { return вкл; },
    "станция": станция,
    /* Замер для живой проверки. Звук нельзя оценить снимком, а
       «вроде играет» не сдача: проверка читает отсюда состояние
       контекста и текущие громкости и говорит ЧИСТО или ГРЯЗНО.

       «Гул» здесь это сумма всех подложек: у проверки один вопрос -
       звучит ли фон и насколько, - и он не должен знать, сколько у нас
       петель и как они называются. «Свип» - идёт ли прямо сейчас
       разовый звук. В окне тишины оба обязаны быть нулём. */
    "замер": function () {
      var сумма = 0, готово = 0, поимённо = {};
      for (var i = 0; i < ПОДЛОЖКИ.length; i++) {
        if (буферы[ПОДЛОЖКИ[i]]) готово++;
        var п = петли[ПОДЛОЖКИ[i]];
        if (п) {
          сумма += п.уровень.value;
          поимённо[ПОДЛОЖКИ[i]] = +п.уровень.value.toFixed(3);
        }
      }
      var счёт = {};
      for (var с = 0; с < РАЗОВЫЕ.length; с++) {
        if (сыграно[РАЗОВЫЕ[с]]) счёт[РАЗОВЫЕ[с]] = сыграно[РАЗОВЫЕ[с]];
      }
      /* Кроссфейд на стыке петли проверяется одним числом. Сумма
         квадратов двух копий обязана держаться около единицы: ноль
         означал бы, что расписание кончилось и подложка молчит, двойка -
         что копии идут в полную силу и стык слышен. Периоды показываем
         рядом: они обязаны быть РАЗНЫМИ, иначе шесть подложек снова
         перещёлкиваются в один миг. */
      var пары = [], стыки = [];
      for (var к = 0; к < ПОДЛОЖКИ.length; к++) {
        var пт = петли[ПОДЛОЖКИ[к]];
        if (!пт) continue;
        var а = пт.кросс[0].value, б = пт.кросс[1].value;
        пары.push(+(а * а + б * б).toFixed(3));
        стыки.push(+пт.период.toFixed(2));
      }
      return {
        "состояние": К ? К.state : "нет",
        "шина": шина ? +шина.gain.value.toFixed(4) : 0,
        "гул": +сумма.toFixed(4),
        "свип": живых > 0 ? 1 : 0,
        /* Поимённые уровни и счёт разовых: проверке нужна таблица, а не
           одно число. По сумме нельзя увидеть, что подложка чужая. */
        "подложки": поимённо,
        "сыграно": счёт,
        "пара": пары,
        "стыки": стыки,
        "скорость": +скорМира.toFixed(3),
        "ждут": ждут.length,
        "подложек": готово,
        "разовых": (function () {
          var n = 0;
          for (var j = 0; j < РАЗОВЫЕ.length; j++) if (буферы[РАЗОВЫЕ[j]]) n++;
          return n;
        })()
      };
    }
  };

  /* Ждём именно DOMContentLoaded, а не «не loading».

     Отложенные скрипты выполняются, когда разбор уже кончился и
     состояние документа стало interactive, но ДО события. Проверка на
     «не loading» проходила, звук заводился сразу - и не находил
     rv-motion.js, который подключён ниже по списку и ещё не выполнился.
     Подписок не появлялось вовсе: замер показывал живой контекст и
     нулевые громкости во всех актах. */
  if (d.readyState === "loading" || d.readyState === "interactive") {
    d.addEventListener("DOMContentLoaded", завести);
  } else {
    завести();
  }

})(window, document);
