/* Rocket VPN. Снаряды с текстом, которые втыкаются в стену.

   СЦЕНАРИЙ ВЛАДЕЛЬЦА ДОСЛОВНО: «с нашей стороны или справа слева
   пролетает в стену, на неё на поверхности приклеивается ну или там
   втыкается, и вот на том что прилетело в стену на нём текст. А стена по
   мере каждого прилёта у нас допустим будет четыре или пять карточек, и
   по мере каждой карточки у стены появляется всё больше трещин и внутри
   этих трещин свечение ярче. И уже на самый последний что прилетает, она
   уже прилетает без текста, оно пробивает стену и она как бы на
   кирпичике рассыпается и формируется в туннель».

   ПОЧЕМУ ЭТО СИЛЬНЕЕ ОБЫЧНЫХ КАРТОЧЕК. Список карточек читается как
   список: четыре равнозначные плитки, глаз скользит и не задерживается.
   Здесь у каждой карточки есть СОБЫТИЕ: она прилетает, попадает, и от
   попадания у стены остаётся след. Четыре удара накапливаются, стена
   держится всё хуже, и пятый её проламывает. Человек читает четыре боли
   и физически видит, как они ломают преграду.

   ЧТО ЗДЕСЬ ВНУТРИ. Плита-снаряд с текстом на лицевой стороне, полёт по
   дуге со стороны камеры в стену, удар с отдачей, трещины на стене от
   каждого попадания и свечение в них.

   ТЕКСТ НА СНАРЯДЕ РИСУЕТСЯ MSDF (rv-msdf.js), тем же шрифтом, что весь
   сайт. Плита без текста была бы просто летящим прямоугольником; текст
   на ней и есть содержание акта.

   ТРЕЩИНЫ СЧИТАЮТСЯ В ШЕЙДЕРЕ, а не рисуются картинкой. Их рисунок
   зависит от того, куда именно попал снаряд, и заранее его не нарисуешь:
   каждая трещина расходится лучами из своей точки удара, а яркость
   свечения внутри растёт с числом попаданий.

   API:
     RV_СНАРЯДЫ.собрать(мир, родитель, о)
     RV_СНАРЯДЫ.кадрСтены(доля, dt, часы)   - периметр, четыре карточки
     RV_СНАРЯДЫ.кадрПробоя(доля, dt, часы)  - прокол, пятый удар
     RV_СНАРЯДЫ.точкиУдара() -> массив для шейдера трещин
     RV_СНАРЯДЫ.замер() */
(function (g) {
  "use strict";

  var W = null, T = null;
  var М = {};
  var собрано = false;

  /* Четыре карточки с текстом и пятый снаряд без текста, который
     проламывает стену. Число взято у владельца. */
  /* ТРИ глыбы с содержанием и четвёртая без него, которая проламывает
     стену. Было четыре и пятая: столько же боли, но владелец переписал
     сценарий - «сделать например три глыбы с какими-то иконками и от них
     вот эти вот стрелочки с какой-то подписью». Три и читаются лучше:
     на стоячем кадре четыре предмета в колонке идут впритык. */
  var С_ТЕКСТОМ = 3;
  var ВСЕГО = 4;

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }
  function плавно(a, b, x) { x = зажать((x - a) / (b - a), 0, 1); return x * x * (3 - 2 * x); }
  /* Отдача при попадании: плита проскакивает в стену и отходит обратно.
     Без неё удар читается прилипанием, а не ударом. */
  function отдача(t) {
    t = зажать(t, 0, 1);
    return 1 - Math.pow(1 - t, 3) * Math.cos(t * Math.PI * 2.2);
  }

  var В_ПЛИТА = [
    "varying vec3 vNor;",
    "varying vec2 vUv;",
    "varying float vMvz;",
    "varying vec3 vViewPos;",
    "void main(){",
    "  vUv = uv;",
    "  vNor = normalize(normalMatrix * normal);",
    "  vec4 mv = modelViewMatrix * vec4(position, 1.0);",
    "  vMvz = mv.z;",
    "  vViewPos = mv.xyz;",
    "  gl_Position = projectionMatrix * mv;",
    "}"
  ].join("\n");

  var Ф_ПЛИТА = [
    "uniform vec3 uBase;",
    "uniform vec3 uEdge;",
    "uniform vec3 uGlow;",
    "uniform float uHot;",
    "uniform float uFly;",
    "varying vec3 vNor;",
    "varying vec2 vUv;",
    "varying float vMvz;",
    "varying vec3 vViewPos;",
    "float hash12(vec2 p){",
    "  vec3 p3 = fract(vec3(p.xyx) * 0.1031);",
    "  p3 += dot(p3, p3.yzx + 33.33);",
    "  return fract((p3.x + p3.y) * p3.z);",
    "}",
    "void main(){",
    "  vec3 n = normalize(vNor);",
    "  vec3 sv = normalize(vec3(-0.3, 0.5, 0.81));",
    "  float sol = smoothstep(-0.1, 0.7, dot(n, sv));",
    "  vec3 color = uBase * (0.42 + 0.72 * sol);",
    /* ── ФАКТУРА ПЛИТЫ ───────────────────────────────────────────
       Владелец: «главное реализм 1:1 как в реальной жизни на всех
       текстурах и объектах». Плита ровного цвета читается вырезанной из
       бумаги, и на фоне кладки с настоящим фотосканом это видно сразу.

       Фактура считается, а не берётся картинкой: плита летит и её видно
       секунды, лишний файл по сети того не стоит. Мелкий шум по
       поверхности даёт прокат металла, вытянутый по одной оси - следы
       вальцовки, и вместе они ловят свет неровно, как ловит его
       настоящий лист. */
    "  float zerno = hash12(floor(vUv * 220.0));",
    "  float valcy = sin(vUv.y * 168.0 + zerno * 2.0) * 0.5 + 0.5;",
    "  color *= 0.90 + 0.14 * zerno + 0.06 * valcy;",
    /* Блик по микрограням. Лист металла отражает собранно, и без этого
       члена плита остаётся матовым пятном при любом наклоне. */
    "  vec3 V = normalize(-vViewPos);",
    "  vec3 H = normalize(sv + V);",
    "  float NdH = max(dot(n, H), 0.0);",
    "  float NdV = max(dot(n, V), 0.001);",
    "  float rough = 0.30 + 0.16 * zerno;",
    "  float al = rough * rough, al2 = al * al;",
    "  float zn = NdH * NdH * (al2 - 1.0) + 1.0;",
    "  float D = al2 / (3.14159265 * zn * zn + 1e-5);",
    "  float Fr = 0.06 + 0.94 * pow(1.0 - max(dot(V, H), 0.0), 5.0);",
    "  color += uEdge * clamp(D * Fr, 0.0, 4.0) * 0.30;",
    /* Кромка плиты светится: она летит, значит у неё есть собственный
       ход, и свет по краю читается как след этого хода. */
    "  vec2 c = abs(vUv - 0.5) * 2.0;",
    "  float kraj = max(c.x, c.y);",
    "  float ramka = smoothstep(0.86, 0.995, kraj);",
    "  color = mix(color, uEdge, ramka * 0.85);",
    /* Френель по краю: поверхность, повёрнутая от глаза, отражает почти
       всё, и именно это делает край краем, а не линией обводки. */
    "  color += uEdge * pow(1.0 - NdV, 4.0) * 0.20;",
    /* В полёте кромка горит сильнее, в момент удара вспыхивает вся
       плита: это и есть отдача, видимая глазом. */
    "  color += uGlow * (ramka * (0.16 + 0.5 * uFly) + uHot * 0.45);",
    "  float dal = 1.0 - smoothstep(24.0, 90.0, -vMvz);",
    "  color *= mix(0.4, 1.0, dal);",
    "  gl_FragColor = vec4(color, 1.0);",
    "}"
  ].join("\n");

  function собрать(мир, родитель, о) {
    if (собрано) return М.корень;
    W = мир || W;
    if (!W || !W.T || !родитель) return null;
    T = W.T;
    о = о || {};
    _прошлыеО = о;

    var тексты = о["тексты"] || [];
    /* Форма льда и знак внутри объявлены в разметке акта: какая глыба о
       чём, решает содержание, а не файл сцены. */
    var формы = о["формы"] || [];
    var знаки = о["знаки"] || [];
    /* Полные описания: их человек читает, когда войдёт внутрь глыбы. */
    var описания = о["описания"] || [];
    /* Стена, в которую бьём: её плоскость и полуразмеры. Снаряды летят
       туда, а не в назначенную наугад точку. */
    М.zСтены = о["zСтены"] == null ? 0 : о["zСтены"];
    /* Насколько плита ВЫСТУПАЕТ из кладки. Ноль означал «плоскость
       стены», и плита садилась внутрь камня: на снимке доли 0.60 из
       четырёх попаданий было видно ОДНО, летящее, а три уже воткнувшихся
       тонули в кирпиче. Выступ в половину толщины кладки плюс половину
       толщины плиты ставит её на поверхность, как и просил сценарий:
       «прилетает в стену, на неё на поверхности приклеивается». */
    /* Колонка вместо ромба: см. расстановку целей ниже. Решает акт,
       потому что он же выбирает форму кладки под кадр. */
    М.колонка = !!о["колонка"];
    М.выступ = о["выступ"] == null ? 0.45 : о["выступ"];
    М.полуШ = о["полуШирина"] || 10;
    М.полуВ = о["полуВысота"] || 6;
    /* Высота середины стены над точкой гнезда. Стена стоит на грунте, а
       не висит по центру кадра, поэтому её середина поднята. Без этого
       снаряды целились бы в ноль гнезда, то есть в землю под кладкой. */
    М.центрY = о["центрВысоты"] == null ? 0 : о["центрВысоты"];

    М.корень = new T.Group();
    М.корень.name = "снаряды";
    М.корень.visible = false;
    родитель.add(М.корень);

    М.мат = new T.ShaderMaterial({
      uniforms: {
        /* Плита потемнела: белая надпись на #2C3556 давала контраст
           около четырёх к одному, а на телефоне с его мелким кеглем и
           бликом экрана этого мало. #161C33 поднимает контраст вдвое, и
           карточка при этом остаётся синей плитой нашего мира, а не
           становится чёрным прямоугольником. */
        uBase: { value: new T.Color(0x161C33) },
        uEdge: { value: new T.Color(0x8FA8FF) },
        uGlow: { value: new T.Color(0x9CC8FF) },
        uHot: { value: 0 }, uFly: { value: 0 }
      },
      vertexShader: В_ПЛИТА, fragmentShader: Ф_ПЛИТА, fog: false
    });

    М.штуки = [];
    var семя = 4127;
    function сл() { семя = (семя * 9301 + 49297) % 233280; return семя / 233280; }

    for (var i = 0; i < ВСЕГО; i++) {
      var последний = i === С_ТЕКСТОМ;
      /* Точки удара разведены по стене: четыре по углам воображаемого
         ромба, пятый ровно в середину. Последний бьёт в центр не для
         красоты - в этом месте потом раскрывается проём тоннеля, и
         пробой обязан случиться там, куда полетит камера. */
      /* ЧЕТЫРЕ УГЛА, А НЕ РОМБ. Владелец: «чтобы текст на них было
         хорошо видно, во-первых, во-вторых, чтобы текст друг на друга
         нигде не накладывался».

         Ромб ставил плиты по сторонам света: правая и левая расходились
         на две трети ширины стены, верхняя и нижняя - всего на четыре
         пятых своей высоты. При плитах, которые надо ЧИТАТЬ, верхняя с
         нижней сходились впритык, и надписи налезали одна на другую.

         По углам расстояния выходят одинаковыми в обе стороны, и между
         соседями остаётся зазор в пятую часть плиты. Пятый бьёт ровно в
         середину: там потом раскрывается проём тоннеля. */
      /* ── ДВЕ РАССТАНОВКИ ЦЕЛЕЙ ────────────────────────────────
         Ромб по углам работает на лежачей кладке широкого экрана. На
         телефоне кладка стоячая, и там карточки идут КОЛОНКОЙ сверху
         вниз - каждая почти во всю ширину стены, и текст на ней
         читается. Какая расстановка нужна, знает акт: он же решает,
         какой формы делать кладку. */
      /* ── ТРИ ГЛЫБЫ: РЯДОМ ИЛИ СТОЛБИКОМ ───────────────────────
         На лежачей кладке они идут в ряд с лёгким разбегом по высоте:
         строй по линейке читается таблицей, а разбег - россыпью
         попаданий. На стоячей идут столбиком.

         Ромб по четырём углам, который стоял раньше, писался под четыре
         карточки; с тремя он давал две сверху и одну снизу сбоку. */
      var поX = М.колонка ? 0 : (i - (С_ТЕКСТОМ - 1) * 0.5) * (2 / Math.max(1, С_ТЕКСТОМ - 1));
      var поY = М.колонка ? ((С_ТЕКСТОМ - 1) * 0.5 - i) * (2 / Math.max(1, С_ТЕКСТОМ - 1))
                          : ((i % 2) ? -0.30 : 0.24);
      var цель = последний
        ? new T.Vector3(0, М.центрY + М.полуВ * 0.10, М.zСтены + М.выступ)
        : new T.Vector3(поX * М.полуШ * (М.колонка ? 0 : 0.62),
                        М.центрY + поY * М.полуВ * (М.колонка ? 0.62 : 1.0),
                        М.zСтены + М.выступ);

      /* Прилетает СБОКУ И СЗАДИ, из-за плеча человека: снаряд должен
         пройти через кадр, а не выехать из его глубины. Стороны
         чередуются, чтобы четыре попадания не читались очередью.

         СТАРТ ЗА КРАЕМ КАДРА, А НЕ ЗА ГОРИЗОНТОМ. Было девятнадцать
         десятых полуширины стены вбок: замер экранных координат показал
         снаряды на x от -10 до +9.6 при рамке кадра в единицу, то есть
         в десяти кадрах от края. Весь полёт проходил вне экрана, и
         человек видел не полёт, а появление у стены. Тридцать процентов
         за краем: снаряд входит в кадр в первой четверти окна и
         пересекает его целиком. */
      /* ГЛУБИНА СТАРТА СЧИТАЕТСЯ ОТ СТЕНЫ, А НЕ НАЗНАЧЕНА В ЕДИНИЦАХ.
         Стояло «плюс пятнадцать»: число бралось под стену полушириной в
         двадцать шесть, а камера теперь стоит в десяти с половиной
         единицах от кладки. Снаряд начинал полёт ЗА СПИНОЙ у человека и
         проходил вплотную к объективу, закрывая собой половину кадра -
         ровно это и было на снимке доли 0.55.

         Полторы полуширины стены ставят его перед камерой, но заметно
         ближе к кладке: он входит в кадр сбоку, пересекает его и
         втыкается, ни разу не оказавшись у самого стекла. */
      var сбоку = (i % 2 ? 1 : -1) * (М.полуШ * 1.30 + сл() * М.полуШ * 0.14);
      var старт = new T.Vector3(сбоку, цель.y + М.полуВ * (0.34 + сл() * 0.34),
                                М.zСтены + М.полуШ * 1.35 + сл() * М.полуШ * 0.45);

      /* ── ГЛЫБА ЛЬДА ВМЕСТО ПЛИТЫ ──────────────────────────────
         Владелец: «можно и не карточки, можно как у igloo сделать глыбы
         льда, которые влетают в стену... внутри льда находится иконка
         какая-то, на всех трёх разная, от этих кусков льда везде
         стрелка или линия и там текст одним-двумя словами».

         Корпус, знак внутри и выноска собираются в rv-глыба.js; здесь
         только полёт, удар и подпись. Последний снаряд остаётся плитой:
         он без содержания, его работа - проломить стену, и лёд с
         пустой сердцевиной там читался бы потерянной четвёртой
         функцией. */
      /* Размер глыбы. Была 0.62 полуширины стены на лежачем кадре, и
         каждая занимала треть экрана: три таких закрывали стену целиком
         и налезали на заголовок. У igloo глыба занимает около четверти
         кадра по высоте. 0.34 и 0.50 дают ровно это. */
      var шир = последний ? М.полуШ * 0.30
                          : М.полуШ * (М.колонка ? 0.56 : 0.34);
      /* 0.56 посчитано, а не подобрано. Стоячая кладка 4.73 в высоту, три
         глыбы делят её на слоты по 1.58. В слоте кроме тела нужна ещё
         полка с подписью над ним: полуглыба 0.53, полка с надписью 0.43,
         итого 0.96 - как раз половина слота. На 0.70 подпись садилась на
         соседнюю глыбу, что и было видно на снимке. */
      var выс = последний ? шир * 0.62 : шир;
      var плита, мат, глыба = null;
      if (!последний && g.RV_ГЛЫБА) {
        глыба = g.RV_ГЛЫБА["собрать"](W, {
          "форма": формы[i] || "кристалл",
          "знак": знаки[i],
          "иконка": знаки[i],
          "семя": 17 + i * 13,
          "размер": шир * 0.5,
          "выноска": true,
          /* Стороны выносок чередуются, как у igloo: первая влево,
             вторая вправо. Две подряд в одну сторону читались бы
             списком, а не разметкой предмета. */
          /* Ноль означает «выноска сверху»: на стоячем кадре сбоку
             места под полку с подписью нет вовсе. */
          "сторона": М.колонка ? 0 : ((i % 2) ? 1 : -1),
          /* На стоячем кадре полка выноски короче: кадр в плоскости
             стены всего 3.3 единицы шириной, и полка в полтора размера
             глыбы вместе с подписью уезжала за кромку. */
          "длинаВыноски": М.колонка ? 1.35 : 1.6,
          "спускВыноски": М.колонка ? 0.45 : 0.55
        });
      }
      if (глыба) {
        плита = глыба["корень"];
        мат = глыба["мат"];
      } else {
        мат = М.мат.clone();
        мат.uniforms = T.UniformsUtils.clone(М.мат.uniforms);
        плита = new T.Mesh(new T.BoxGeometry(шир, выс, шир * 0.09), мат);
      }
      плита.name = "снаряд " + i;
      плита.frustumCulled = false;
      плита.renderOrder = 6;
      М.корень.add(плита);

      var надпись = null;
      if (!последний && тексты[i] && g.RV_MSDF) {
        /* ── ПОДПИСЬ СТОИТ НА ВЫНОСКЕ, А НЕ НА ПРЕДМЕТЕ ─────────
           У igloo текст не лежит на льдине: от неё уходит тонкая линия
           с изломом, и подпись стоит на её полке, в стороне от тела
           глыбы. Так читается и текст, и сам предмет - ни одно не
           закрывает другое.

           Раньше надпись печаталась прямо по лицу плиты, и владелец
           дважды сказал, что её не видно: на синем металле мелкий белый
           набор пропадал. */
        надпись = g.RV_MSDF["строка"](тексты[i], {
          /* Ширина колонки подписи в кеглях. На стоячем кадре девять:
             длинная подпись ложится в две строки и остаётся в кадре, а
             не уходит за правую кромку. */
          ширина: М.колонка ? 9.0 : 16.0, цвет: 0xFFFFFF, толщина: -0.16,
          выравнивание: (глыба && глыба["выноска"] &&
                         глыба["выноска"].userData["сверху"]) ? "центр"
                        : (глыба && глыба["сторона"] > 0 ? "лево" : "право")
        });
        /* Кегль от ВЫСОТЫ СТЕНЫ, а не от глыбы: подпись это часть
           разметки кадра, и она обязана читаться одинаково при любом
           размере предмета, к которому приставлена. */
        надпись.scale.setScalar(М.полуВ * (М.колонка ? 0.058 : 0.052));
        надпись.renderOrder = 13;
        if (глыба && глыба["выноска"]) {
          var кон = глыба["выноска"].userData["конец"];
          /* Подпись садится НА ПОЛКУ выноски, у её дальнего конца, и
             приподнята на высоту строки: линия идёт под текстом, как
             подчёркивание, ровно как у них. */
          if (глыба["выноска"].userData["сверху"]) {
            /* Подпись стоит НАД полкой, по центру глыбы. */
            надпись.position.set(0, кон[1] + М.полуВ * 0.055, 0.01);
          } else {
            надпись.position.set(кон[0] > 0 ? 0.04 : -0.04, шир * 0.055, 0.01);
          }
          глыба["выноска"].add(надпись);
        } else {
          надпись.position.z = шир * 0.05;
          плита.add(надпись);
        }
      }

      if (глыба) {
        глыба["описание"] = описания[i] || "";
        глыба["подпись"] = тексты[i] || "";
      }
      М.штуки.push({
        номер: i, плита: плита, надпись: надпись, мат: мат, глыба: глыба,
        старт: старт, цель: цель, последний: последний,
        крутка: new T.Vector3(сл() - 0.5, сл() - 0.5, сл() - 0.5).normalize(),
        сл: сл(), попал: false
      });
    }

    /* ── Окна полёта ────────────────────────────────────────────
       Четыре карточки живут в ПЕРИМЕТРЕ, пятый снаряд - в ПРОКОЛЕ. Это
       не разметка ради разметки, это сценарий владельца: сначала
       человек читает четыре боли у стоящей камеры, и только потом
       последний удар проламывает стену и камера трогается.

       Внутри периметра карточка занимает четверть акта, окна
       перекрываются на треть: следующий снаряд трогается, пока
       предыдущий ещё договаривает, и акт не распадается на четыре
       отдельных ожидания. Последняя успевает встать и быть прочитанной
       до конца акта, поэтому её окно кончается на 0.86, а не у самого
       края.

       Пятый бьёт в первой пятой прокола: пробой кладки начинается
       сразу за ним. */
    М.окна = [];
    for (var к = 0; к < С_ТЕКСТОМ; к++) {
      var н = 0.03 + к * 0.14;
      М.окна.push([н, н + 0.20]);
    }
    М.окноПробоя = [0.02, 0.17];
    М.точки = new Float32Array(ВСЕГО * 3);
    М.силы = new Float32Array(ВСЕГО);
    /* ── ЦЕЛИ ДЛЯ КЛИКА ───────────────────────────────────────
       Глыбы объявляются модулю погружения: он один разбирает клик лучом
       и ведёт камеру внутрь. Снаряды про это не знают ничего, кроме
       того, что у каждой глыбы есть подпись и описание. */
    if (g.RV_ВНУТРЬ && g.RV_ВНУТРЬ["цели"]) {
      var цели = [];
      for (var ц = 0; ц < С_ТЕКСТОМ; ц++) {
        var шц = М.штуки[ц];
        if (!шц || !шц.глыба) continue;
        цели.push({
          глыба: шц.глыба,
          подпись: шц.глыба["подпись"] || "",
          текст: шц.глыба["описание"] || ""
        });
      }
      g.RV_ВНУТРЬ["цели"](цели);
    }
    собрано = true;
    return М.корень;
  }

  var _в = null, _q = null;

  /* Ход одного снаряда. Общий и для карточек периметра, и для пятого,
     который пробивает стену в проколе: летят они одинаково, разница
     только в том, когда и что после этого происходит со стеной.

     ХОД ПО ВРЕМЕНИ. Прежде путь считался ДВАЖДЫ сглаженным (smoothstep
     в квадрате), и снаряд три четверти окна почти стоял на старте.
     Замер это поймал: на доле 0.10 все пять сидели за краем кадра
     (экранный x от -10 до +9.6 при рамке в единицу), а появлялись
     последним рывком, который глаз читает как подмену, а не как полёт.
     Теперь разгон полуторной степени: старт заметно медленнее середины,
     к стене снаряд приходит на скорости, и весь путь виден.

     СТАРТ БЛИЖЕ. Было девятнадцать десятых полуширины стены вбок и
     двадцать шесть единиц на камеру: снаряд выходил далеко за кадр и
     влетал в него уже у самой стены. Теперь тридцать процентов за
     краем: он входит в кадр почти сразу и пересекает его целиком. */
  function ходСнаряда(ш, о, доля, вПолёте) {
    var t = зажать((доля - о[0]) / (о[1] - о[0]), 0, 1);
    var разгон = Math.pow(t * t * (3 - 2 * t), 0.75);
    _в.copy(ш.старт).lerp(ш.цель, разгон);
    /* Дуга: снаряд идёт не по струне, а по навесной траектории, как
       брошенный предмет. Высота дуги падает к концу пути. */
    _в.y += Math.sin(разгон * Math.PI) * (М.полуВ * 0.26) * (1 - разгон * 0.4);

    var удар = t >= 1;
    if (удар) {
      /* После попадания плита стоит в стене и слегка утоплена. */
      var с = зажать((доля - о[1]) / 0.05, 0, 1);
      _в.copy(ш.цель);
      _в.z += (1 - отдача(с)) * М.полуШ * 0.12;
      if (!ш.попал) { ш.попал = true; событие("удар", ш.номер); }
    } else if (доля < о[0]) {
      ш.попал = false;
    }
    ш.плита.position.copy(_в);

    /* Кувырок гаснет к середине пути, а не к самому удару: текст на
       плите должен успеть встать ровно и быть прочитанным ДО того, как
       она воткнётся. Читать надпись в кувырке невозможно, а показывать
       нечитаемое незачем. */
    var круть = зажать(1 - разгон * 1.8, 0, 1);
    круть *= круть;
    _q.setFromAxisAngle(ш.крутка, круть * (2.6 + ш.сл * 3.4));
    ш.плита.quaternion.copy(_q);

    ш.мат.uniforms.uFly.value = вПолёте && !удар ? 1 - разгон : 0;
    ш.мат.uniforms.uHot.value = удар ? Math.max(0, 1 - (доля - о[1]) / 0.06) : 0;
    /* Своя жизнь глыбы: муть внутри плывёт, знак медленно вращается.
       Знак крутится, лёд стоит - так видно, что он ВНУТРИ, а не
       нарисован на грани. */
    if (ш.глыба) ш.глыба["кадр"](М.дт, М.часы, ш.мат.uniforms.uHot.value);

    /* Надпись зажигается на втором полупути, когда плита уже
       довернулась лицом, и гаснет только с уходом акта. */
    if (ш.надпись && g.RV_MSDF) {
      g.RV_MSDF["показать"](ш.надпись, разгон > 0.45 && доля < 0.97);
    }

    М.точки[ш.номер * 3] = ш.цель.x;
    М.точки[ш.номер * 3 + 1] = ш.цель.y;
    М.точки[ш.номер * 3 + 2] = ш.цель.z;
    /* Сила трещины растёт сразу после попадания и дальше не спадает:
       стена не заживает. */
    М.силы[ш.номер] = удар ? зажать((доля - о[1]) / 0.10, 0, 1) : 0;
    return удар;
  }

  /* ── Периметр: четыре карточки ──────────────────────────────────
     Камера почти стоит, стена цела, снаряды с текстом бьют по очереди.
     Пятый в этой фазе не участвует и стоит за кадром. */
  function кадрСтены(доля, dt, часы) {
    if (!собрано) return;
    if (!_в) { _в = new T.Vector3(); _q = new T.Quaternion(); }
    /* Шаг и часы кладём в М: ход снаряда зовётся из двух мест и таскать
       их обоими путями значило бы менять подпись в четырёх местах. */
    М.дт = dt || 0.016; М.часы = часы || 0;
    М.корень.visible = true;
    for (var i = 0; i < С_ТЕКСТОМ; i++) {
      М.штуки[i].плита.visible = true;
      ходСнаряда(М.штуки[i], М.окна[i], доля, true);
    }
    /* Пробойник прячется до своей фазы: висящая в кадре пустая плита
       выдала бы удар за минуту до того, как он случится. */
    var п = М.штуки[С_ТЕКСТОМ];
    п.плита.visible = false;
    п.попал = false;
    М.силы[С_ТЕКСТОМ] = 0;
  }

  /* ── Прокол: пятый снаряд ───────────────────────────────────────
     Он без текста. Всё, что он несёт, это удар: стена уже держится на
     четырёх трещинах, и его попадание её раскрывает. Четыре карточки к
     этому времени стоят в кладке и уезжают вместе с ней.

     Их следы остаются в силе трещин: стена, которую пробивают, обязана
     быть той же стеной, в которую били. */
  function кадрПробоя(доля, dt, часы) {
    М.дт = dt || 0.016; М.часы = часы || 0;
    if (!собрано) return;
    if (!_в) { _в = new T.Vector3(); _q = new T.Quaternion(); }
    М.корень.visible = доля < 0.62;
    if (!М.корень.visible) return;
    for (var i = 0; i < С_ТЕКСТОМ; i++) {
      var ш = М.штуки[i];
      ш.плита.visible = true;
      ш.плита.position.copy(ш.цель);
      ш.плита.quaternion.identity();
      ш.мат.uniforms.uFly.value = 0;
      ш.мат.uniforms.uHot.value = 0;
      if (ш.надпись && g.RV_MSDF) g.RV_MSDF["показать"](ш.надпись, доля < 0.14);
      М.точки[i * 3] = ш.цель.x; М.точки[i * 3 + 1] = ш.цель.y; М.точки[i * 3 + 2] = ш.цель.z;
      М.силы[i] = 1;
    }
    var п = М.штуки[С_ТЕКСТОМ];
    п.плита.visible = true;
    ходСнаряда(п, М.окноПробоя, доля, true);
  }


  function событие(что, номер) {
    try { g.dispatchEvent(new CustomEvent("rv:снаряд", { detail: { "что": что, "номер": номер } })); } catch (e) {}
  }

  /* ── ПЕРЕСБОРКА ПОД НОВЫЙ КАДР ────────────────────────────────
     Расстановка карточек зависит от формы кладки: на лежачей они по
     углам, на стоячей колонкой. Форма кладки зависит от формы экрана.
     Повернули телефон - и та, и другая меняются, значит снаряды надо
     собрать заново: подогнать масштабом нельзя, надпись поехала бы
     вместе с плитой и растянулась. */
  var _прошлыеО = null;
  function перестроить(о) {
    if (!собрано) return null;
    о = о || {};
    var новые = {};
    var к;
    for (к in _прошлыеО) if (Object.prototype.hasOwnProperty.call(_прошлыеО, к)) новые[к] = _прошлыеО[к];
    for (к in о) if (Object.prototype.hasOwnProperty.call(о, к)) новые[к] = о[к];
    var род = М.корень.parent;
    if (!род) return null;
    var видно = М.корень.visible;
    род.remove(М.корень);
    for (var i = 0; i < М.штуки.length; i++) {
      try { М.штуки[i].плита.geometry.dispose(); } catch (eГ) {}
      try { М.штуки[i].мат.dispose(); } catch (eМ) {}
    }
    собрано = false;
    var корень = собрать(W, род, новые);
    if (корень) корень.visible = видно;
    return корень;
  }

  g.RV_СНАРЯДЫ = {
    "собрать": собрать,
    "перестроить": перестроить,
    "кадрСтены": кадрСтены,
    "кадрПробоя": кадрПробоя,
    "точкиУдара": function () { return М.точки || null; },
    "силыУдара": function () { return М.силы || null; },
    "замер": function () {
      if (!собрано) return { "собрано": false };
      var попало = 0;
      for (var i = 0; i < М.штуки.length; i++) if (М.штуки[i].попал) попало++;
      return {
        "собрано": true, "снарядов": М.штуки.length, "попало": попало,
        "сТекстом": С_ТЕКСТОМ, "видно": !!(М.корень && М.корень.visible)
      };
    }
  };
})(window);
