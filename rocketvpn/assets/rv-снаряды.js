/* Rocket VPN. Снаряды с текстом, которые втыкаются в стену.

   СЦЕНАРИЙ ВЛАДЕЛЬЦА ДОСЛОВНО: «с нашей стороны или справа слева
   пролетает в стену, на неё на поверхности приклеивается ну или там
   втыкается, и вот на том что прилетело в стену на нём текст. А стена по
   мере каждого прилёта у нас допустим будет четыре или пять карточек, и
   по мере каждой карточки у стены появляется всё больше трещин и внутри
   этих трещин свечение ярче. И уже на самый последний что прилетает, она
   уже прилетает без текста, оно пробивает стену и она как бы на
   кирпичике рассыпается и формируется в туннель».

   ПОЧЕМУ ЭТО СИЛЬНЕЕ ОБЫЧНЫХ КАРТОЧЕК. Список карточек читается как
   список: четыре равнозначные плитки, глаз скользит и не задерживается.
   Здесь у каждой карточки есть СОБЫТИЕ: она прилетает, попадает, и от
   попадания у стены остаётся след. Четыре удара накапливаются, стена
   держится всё хуже, и пятый её проламывает. Человек читает четыре боли
   и физически видит, как они ломают преграду.

   ЧТО ЗДЕСЬ ВНУТРИ. Плита-снаряд с текстом на лицевой стороне, полёт по
   дуге со стороны камеры в стену, удар с отдачей, трещины на стене от
   каждого попадания и свечение в них.

   ТЕКСТ НА СНАРЯДЕ РИСУЕТСЯ MSDF (rv-msdf.js), тем же шрифтом, что весь
   сайт. Плита без текста была бы просто летящим прямоугольником; текст
   на ней и есть содержание акта.

   ТРЕЩИНЫ СЧИТАЮТСЯ В ШЕЙДЕРЕ, а не рисуются картинкой. Их рисунок
   зависит от того, куда именно попал снаряд, и заранее его не нарисуешь:
   каждая трещина расходится лучами из своей точки удара, а яркость
   свечения внутри растёт с числом попаданий.

   API:
     RV_СНАРЯДЫ.собрать(мир, родитель, о)
     RV_СНАРЯДЫ.кадр(доля, dt, часы)
     RV_СНАРЯДЫ.точкиУдара() -> массив для шейдера трещин
     RV_СНАРЯДЫ.замер() */
(function (g) {
  "use strict";

  var W = null, T = null;
  var М = {};
  var собрано = false;

  /* Четыре карточки с текстом и пятый снаряд без текста, который
     проламывает стену. Число взято у владельца. */
  var С_ТЕКСТОМ = 4;
  var ВСЕГО = 5;

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }
  function плавно(a, b, x) { x = зажать((x - a) / (b - a), 0, 1); return x * x * (3 - 2 * x); }
  /* Отдача при попадании: плита проскакивает в стену и отходит обратно.
     Без неё удар читается прилипанием, а не ударом. */
  function отдача(t) {
    t = зажать(t, 0, 1);
    return 1 - Math.pow(1 - t, 3) * Math.cos(t * Math.PI * 2.2);
  }

  var В_ПЛИТА = [
    "varying vec3 vNor;",
    "varying vec2 vUv;",
    "varying float vMvz;",
    "void main(){",
    "  vUv = uv;",
    "  vNor = normalize(normalMatrix * normal);",
    "  vec4 mv = modelViewMatrix * vec4(position, 1.0);",
    "  vMvz = mv.z;",
    "  gl_Position = projectionMatrix * mv;",
    "}"
  ].join("\n");

  var Ф_ПЛИТА = [
    "uniform vec3 uBase;",
    "uniform vec3 uEdge;",
    "uniform vec3 uGlow;",
    "uniform float uHot;",
    "uniform float uFly;",
    "varying vec3 vNor;",
    "varying vec2 vUv;",
    "varying float vMvz;",
    "void main(){",
    "  vec3 n = normalize(vNor);",
    "  vec3 sv = normalize(vec3(-0.3, 0.5, 0.81));",
    "  float sol = smoothstep(-0.1, 0.7, dot(n, sv));",
    "  vec3 color = uBase * (0.42 + 0.72 * sol);",
    /* Кромка плиты светится: она летит, значит у неё есть собственный
       ход, и свет по краю читается как след этого хода. */
    "  vec2 c = abs(vUv - 0.5) * 2.0;",
    "  float kraj = max(c.x, c.y);",
    "  float ramka = smoothstep(0.86, 0.995, kraj);",
    "  color = mix(color, uEdge, ramka * 0.85);",
    /* В полёте кромка горит сильнее, в момент удара вспыхивает вся
       плита: это и есть отдача, видимая глазом. */
    "  color += uGlow * (ramka * (0.16 + 0.5 * uFly) + uHot * 0.45);",
    "  float dal = 1.0 - smoothstep(24.0, 90.0, -vMvz);",
    "  color *= mix(0.4, 1.0, dal);",
    "  gl_FragColor = vec4(color, 1.0);",
    "}"
  ].join("\n");

  function собрать(мир, родитель, о) {
    if (собрано) return М.корень;
    W = мир || W;
    if (!W || !W.T || !родитель) return null;
    T = W.T;
    о = о || {};

    var тексты = о["тексты"] || [];
    /* Стена, в которую бьём: её плоскость и полуразмеры. Снаряды летят
       туда, а не в назначенную наугад точку. */
    М.zСтены = о["zСтены"] == null ? 0 : о["zСтены"];
    М.полуШ = о["полуШирина"] || 10;
    М.полуВ = о["полуВысота"] || 6;

    М.корень = new T.Group();
    М.корень.name = "снаряды";
    М.корень.visible = false;
    родитель.add(М.корень);

    М.мат = new T.ShaderMaterial({
      uniforms: {
        uBase: { value: new T.Color(0x2C3556) },
        uEdge: { value: new T.Color(0x8FA8FF) },
        uGlow: { value: new T.Color(0x9CC8FF) },
        uHot: { value: 0 }, uFly: { value: 0 }
      },
      vertexShader: В_ПЛИТА, fragmentShader: Ф_ПЛИТА, fog: false
    });

    М.штуки = [];
    var семя = 4127;
    function сл() { семя = (семя * 9301 + 49297) % 233280; return семя / 233280; }

    for (var i = 0; i < ВСЕГО; i++) {
      var последний = i === С_ТЕКСТОМ;
      /* Точки удара разведены по стене: четыре по углам воображаемого
         ромба, пятый ровно в середину. Последний бьёт в центр не для
         красоты - в этом месте потом раскрывается проём тоннеля, и
         пробой обязан случиться там, куда полетит камера. */
      var уголР = (i / С_ТЕКСТОМ) * Math.PI * 2 + 0.7;
      var цель = последний
        ? new T.Vector3(0, М.полуВ * 0.10, М.zСтены)
        : new T.Vector3(Math.cos(уголР) * М.полуШ * 0.46,
                        М.полуВ * 0.12 + Math.sin(уголР) * М.полуВ * 0.40,
                        М.zСтены);

      /* Прилетает СБОКУ И СЗАДИ, из-за плеча человека: снаряд должен
         пройти через кадр, а не выехать из его глубины. Стороны
         чередуются, чтобы четыре попадания не читались очередью. */
      var сбоку = (i % 2 ? 1 : -1) * (М.полуШ * 1.9 + сл() * М.полуШ * 0.5);
      var старт = new T.Vector3(сбоку, цель.y + М.полуВ * (0.5 + сл() * 0.6), М.zСтены + 26 + сл() * 8);

      var мат = М.мат.clone();
      мат.uniforms = T.UniformsUtils.clone(М.мат.uniforms);
      var шир = последний ? М.полуШ * 0.30 : М.полуШ * 0.52;
      var выс = последний ? шир * 0.62 : шир * 0.46;
      var плита = new T.Mesh(new T.BoxGeometry(шир, выс, шир * 0.09), мат);
      плита.name = "снаряд " + i;
      плита.frustumCulled = false;
      плита.renderOrder = 6;
      М.корень.add(плита);

      var надпись = null;
      if (!последний && тексты[i] && g.RV_MSDF) {
        надпись = g.RV_MSDF["строка"](тексты[i], {
          ширина: 13.5, цвет: 0xE9EEFF, толщина: -0.04, выравнивание: "центр"
        });
        /* Кегль от ширины плиты: текст обязан помещаться на своей плите
           при любом её размере, а размер зависит от стены. */
        надпись.scale.setScalar(шир * 0.052);
        надпись.position.z = шир * 0.05;
        надпись.renderOrder = 7;
        плита.add(надпись);
      }

      М.штуки.push({
        плита: плита, надпись: надпись, мат: мат,
        старт: старт, цель: цель, последний: последний,
        крутка: new T.Vector3(сл() - 0.5, сл() - 0.5, сл() - 0.5).normalize(),
        сл: сл(), попал: false
      });
    }

    /* Окна полёта. Четыре карточки идут по очереди в первых трёх
       четвертях акта, пятый снаряд бьёт в конце. Окна перекрываются на
       треть: следующий трогается, пока предыдущий ещё договаривает, и
       акт не распадается на четыре отдельных ожидания. */
    М.окна = [];
    for (var к = 0; к < ВСЕГО; к++) {
      var н = 0.06 + к * 0.155;
      М.окна.push([н, н + 0.22]);
    }
    М.точки = new Float32Array(ВСЕГО * 3);
    М.силы = new Float32Array(ВСЕГО);
    собрано = true;
    return М.корень;
  }

  var _в = null, _q = null;
  function кадр(доля, dt, часы) {
    if (!собрано) return;
    if (!_в) { _в = new T.Vector3(); _q = new T.Quaternion(); }
    М.корень.visible = доля > 0.02 && доля < 0.99;
    if (!М.корень.visible) return;

    for (var i = 0; i < М.штуки.length; i++) {
      var ш = М.штуки[i], о = М.окна[i];
      var t = зажать((доля - о[0]) / (о[1] - о[0]), 0, 1);
      var летит = t > 0 && t < 1;
      /* Путь снаряда: разгон по кубу, чтобы он приходил в стену на
         скорости, а не подъезжал к ней. */
      var ход = t * t * (3 - 2 * t);
      var разгон = ход * ход;
      _в.copy(ш.старт).lerp(ш.цель, разгон);
      /* Дуга: снаряд идёт не по струне, а по навесной траектории, как
         брошенный предмет. Высота дуги падает к концу пути. */
      _в.y += Math.sin(разгон * Math.PI) * (М.полуВ * 0.30) * (1 - разгон * 0.4);

      var удар = t >= 1 ? 1 : 0;
      if (удар) {
        /* После попадания плита стоит в стене и слегка утоплена. */
        var с = зажать((доля - о[1]) / 0.05, 0, 1);
        _в.copy(ш.цель);
        _в.z += (1 - отдача(с)) * М.полуШ * 0.12;
        if (!ш.попал) { ш.попал = true; событие("удар", i); }
      } else if (доля < о[0]) {
        ш.попал = false;
      }
      ш.плита.position.copy(_в);

      /* В полёте плита кувыркается и доворачивается лицом к стене к
         моменту удара: текст должен читаться ровно тогда, когда снаряд
         встал на место. */
      var круть = (1 - разгон) * (1 - разгон);
      _q.setFromAxisAngle(ш.крутка, круть * (2.6 + ш.сл * 3.4));
      ш.плита.quaternion.copy(_q);

      ш.мат.uniforms.uFly.value = летит ? 1 - разгон : 0;
      var жар = удар ? Math.max(0, 1 - (доля - о[1]) / 0.06) : 0;
      ш.мат.uniforms.uHot.value = жар;

      /* Текст проявляется, когда плита села: читать его в кувырке
         невозможно, а показывать нечитаемое незачем. */
      if (ш.надпись && g.RV_MSDF) {
        g.RV_MSDF["показать"](ш.надпись, !!удар && доля < 0.90);
      }

      М.точки[i * 3] = ш.цель.x;
      М.точки[i * 3 + 1] = ш.цель.y;
      М.точки[i * 3 + 2] = ш.цель.z;
      /* Сила трещины растёт сразу после попадания и дальше не спадает:
         стена не заживает. */
      М.силы[i] = удар ? зажать((доля - о[1]) / 0.10, 0, 1) : 0;
    }
  }

  function событие(что, номер) {
    try { g.dispatchEvent(new CustomEvent("rv:снаряд", { detail: { "что": что, "номер": номер } })); } catch (e) {}
  }

  g.RV_СНАРЯДЫ = {
    "собрать": собрать,
    "кадр": кадр,
    "точкиУдара": function () { return М.точки || null; },
    "силыУдара": function () { return М.силы || null; },
    "замер": function () {
      if (!собрано) return { "собрано": false };
      var попало = 0;
      for (var i = 0; i < М.штуки.length; i++) if (М.штуки[i].попал) попало++;
      return {
        "собрано": true, "снарядов": М.штуки.length, "попало": попало,
        "сТекстом": С_ТЕКСТОМ, "видно": !!(М.корень && М.корень.visible)
      };
    }
  };
})(window);
