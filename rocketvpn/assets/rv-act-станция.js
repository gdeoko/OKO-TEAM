  function толкнутьКупол(x, y, сила) {
    if (!собрано || !М.корень || !М.корень.visible) return false;
    /* Купол уже улетает в стену - трогать нечего, блоки в пути. */
    if ((М.стенаДоля || 0) > 0.5) return false;
    var т = null;
    try { т = вМестных(x, y); } catch (eТ) { т = null; }
    if (!т) return false;
    /* Попали ли ПО КУПОЛУ. Плоскость поперёк взгляда бесконечна, и без
       этой проверки клик по ссылке в углу страницы тряс бы дом. Коробка
       берётся с запасом в 0.7 радиуса: у купола есть крыльцо, и палец
       редко ложится точно в силуэт. */
    var гор = Math.sqrt(т.x * т.x + т.z * т.z);
    if (гор > R * 1.7 || т.y < -R * 0.5 || т.y > ВЫС * 1.45) return false;
    var сейчас = сейчасСек();
    /* Придержка. Свайп выдаёт события пачкой по несколько десятков в
       секунду; без неё волна перезапускалась бы каждый кадр с нулевой
       фазой и стояла бы на месте вместо того, чтобы идти. */
    if (_волна.начало >= 0 && сейчас - _волна.начало < 0.2) return false;
    _волна.x = т.x; _волна.y = т.y; _волна.z = т.z;
    _волна.начало = сейчас;
    _волна.сила = зажать(сила == null ? 1 : сила, 0.15, 1);
    куполСобытие(сила != null && сила < 0.8 ? "свайп" : "касание", _волна.сила);
    return true;
  }

