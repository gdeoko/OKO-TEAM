/* Rocket VPN. Анкета последнего раздела обхода.

   ЗАЧЕМ. Владелец про комнату с частицами: «по скроллу мы обходим
   вокруг, потом смотрим разделы с текстом и анкету и кнопки всякие».
   Последний раздел пуска так и называется - «Остался вопрос», и там
   написано «оставь имя, контакт и вопрос». Форма делает ровно это.

   КУДА УХОДИТ. Никуда. У сайта нет своего приёмника: он отдаётся одним
   PHP-створом со статикой, почтового узла и базы за ним нет. Завести их
   ради трёх полей значило бы сделать вид, что письмо кто-то читает, и
   оставить человека ждать ответа, которого не будет.

   Поэтому форма собирает три поля в одно сообщение, кладёт его в буфер
   обмена и открывает бот. Там сидит живая поддержка, и человеку
   остаётся вставить готовый текст. Ни одно поле не уходит на сторону и
   нигде не хранится: всё, что происходит, происходит в его браузере.

   Глубокая ссылка бота с текстом тут не годится. `t.me/бот?start=` несёт
   не сообщение, а полезную нагрузку до 64 знаков base64url, и вопрос в
   шестьсот знаков в неё не влезет; телеграм такую ссылку просто
   обрежет.

   ПОЧЕМУ БУФЕР МОЖЕТ НЕ СРАБОТАТЬ. `clipboard.writeText` требует
   защищённого соединения и жеста человека. Жест у нас есть (нажали
   кнопку), защищённое соединение на боевом тоже, но на стенде по http
   API просто нет. Обе беды кончаются одинаково: сообщение остаётся
   видимым в поле вопроса, человек копирует его сам, бот всё равно
   открывается. */
(function (g) {
  "use strict";

  var d = g.document;
  var БОТ = "https://t.me/RocketCompanyVPN_bot";

  function поднять() {
    var форма = d.getElementById("rvАнкета");
    if (!форма) return;
    var итог = d.getElementById("rvАнкетаИтог");

    function сказать(текст) { if (итог) итог.textContent = текст; }

    function собрать() {
      var п = форма.elements;
      var имя = (п["имя"] && п["имя"].value || "").trim();
      var связь = (п["связь"] && п["связь"].value || "").trim();
      var вопрос = (п["вопрос"] && п["вопрос"].value || "").trim();
      var строки = ["Вопрос с сайта Rocket VPN"];
      if (имя) строки.push("Имя: " + имя);
      if (связь) строки.push("Связь: " + связь);
      if (вопрос) строки.push("Вопрос: " + вопрос);
      return { текст: строки.join("\n"), пусто: !имя && !связь && !вопрос };
    }

    форма.addEventListener("submit", function (е) {
      е.preventDefault();
      var с = собрать();
      if (с.пусто) {
        сказать("Заполни хотя бы одно поле, иначе отправлять нечего.");
        var перв = форма.querySelector("input");
        if (перв) перв.focus();
        return;
      }
      /* Бот открываем СРАЗУ, в том же обработчике. Открытие после
         промиса буфера считается блокировщиком за самозваное окно и
         глохнет молча: человек нажимает, и не происходит ничего. */
      var окно = g.open(БОТ, "_blank", "noopener");
      var скопировано = false;
      try {
        if (g.navigator && g.navigator.clipboard && g.navigator.clipboard.writeText) {
          g.navigator.clipboard.writeText(с.текст);
          скопировано = true;
        }
      } catch (e) { скопировано = false; }
      сказать(скопировано
        ? "Сообщение в буфере. Открылся бот - вставь и отправь, ответим туда, где удобно."
        : "Открылся бот. Скопируй текст ниже и вставь первым сообщением.");
      if (!скопировано) {
        var поле = форма.elements["вопрос"];
        if (поле) { поле.value = с.текст; поле.focus(); поле.select(); }
      }
      if (!окно) сказать("Браузер закрыл окно бота. Открой " + БОТ + " и напиши туда.");
    });
  }

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", поднять);
  else поднять();
})(window);
