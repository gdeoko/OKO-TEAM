/* Rocket VPN. Комната внизу: то, куда падает человек из шахты.

   ЗАЧЕМ. Владелец описал ход дословно: «дальше у них движение камеры
   после туннеля сразу выходит на фигуру частицами, также и у нас, и фон
   такой же как у них сделать, где частицы, 1:1 чисто точно такой же». И
   следом: «только у нас в комнате с частицами ещё по скроллу мы обходим
   вокруг, потом ещё смотрим разделы с текстом и анкету и кнопки всякие.
   Главное, что текст не перекрывает наши 3D объекты и сцену, текст часть
   этой сцены, как у igloo».

   ЧТО У НИХ (docs/РАЗБОР-IGLOO-ДВИЖЕНИЕ.md, «Комната внизу»). Падение
   кончается, и на последней трети таймлайна включаются шесть объектов:

     пол                    3.4 с, прозрачность 0 к 1 за 5 с
     дымка у пола           3.4 с, масштаб (5, 0.1, 5)
     окружающие частицы     3.4 с, шестьдесят точек
     силовое поле           4.0 с, Cylinder(1,1,3,64,6), y -10.13, масштаб 0.28
     цилиндр с текстом      4.5 с, y -10.33, две копии: 1.75 и 3.5 с поворотом
     дымка у потолка        4.5 с

   Ни одного твина прозрачности на самих предметах: включаются
   переключением видимости, а мягкость даёт шейдер по расстоянию.

   НАШ МАСШТАБ ВЧЕТВЕРО. Их падение идёт одиннадцать единиц (с 1.5 на
   -9.83), наше сорок шесть. Все их числа умножены на четыре, поэтому
   комната относительно человека выглядит так же, как у них.

   ЦИЛИНДР ТЕКСТА ЭТО ФОН, А НЕ СОДЕРЖАНИЕ. У них на нём размытые
   четырёхугольники из атласа 256x256 - буквы, которые не читаются и не
   должны. Он делает воздух комнаты текстовым. Читаемые разделы стоят
   отдельно, буквами поля расстояний (rv-слово3d.js), и появляются по
   ходу обхода. Так текст оказывается частью сцены и при этом ничего не
   закрывает: у фона своя глубина, у слов своя.

   API:
     RV_КОМНАТА.собрать(мир, о) -> Group | null
     RV_КОМНАТА.кадр(доля, dt, часы)
     RV_КОМНАТА.видно(да)
     RV_КОМНАТА.замер() */
(function (g, d) {
  "use strict";

  var W = null, T = null;
  var М = {};
  var собрано = false;
  var просят = {};

  /* Их числа, помноженные на четыре: наше падение вчетверо длиннее. */
  var К = 4.0;

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }
  function мягко(a, b, x) { x = зажать((x - a) / (b - a), 0, 1); return x * x * (3 - 2 * x); }

  /* ── Пол ──────────────────────────────────────────────────────
     Настоящей тени в сцене нет ни одной, и у igloo её тоже нет: контакт
     предмета с полом нарисован формулой. Их строки:

       float shadow = min(1.0, length(vPos * 1.5 + vec3(1.15, 0.0, -0.55)));
       shadow = pow(shadow, 2.0);
       shadow += sin(time * 3.3 + vPos.z * 5.0) * 0.1 + 0.1;
       shadow += sin(time * 3.1 + vPos.x * 4.0) * 0.1 + 0.1;
       shadow = mix(0.5, 1.0, shadow);
       color *= mix(vec3(0.5, 0.7, 1.0) * 0.1, vec3(1.0), shadow);

     Смещение ставит центр тени под предметом, квадрат даёт мягкий спад,
     две синусоиды с частотами 3.3 и 3.1 по разным осям дают тени
     дыхание. Главное в последней строке: тень уходит НЕ В ЧЁРНОЕ, а в
     тёмно-синее (0.05, 0.07, 0.10). Тот же синий (0.5, 0.7, 1.0) кочует
     по всей их сцене как единый цвет холодного отражённого света. */
  var В_ПОЛ = [
    "varying vec3 vPos;",
    "varying vec2 vUv;",
    "void main(){",
    "  vPos = position;",
    "  vUv = uv;",
    "  gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);",
    "}"
  ].join("\n");

  var Ф_ПОЛ = [
    "uniform vec3 uC1;",
    "uniform vec3 uC2;",
    "uniform float uTime;",
    "uniform float uAlpha;",
    "varying vec3 vPos;",
    "varying vec2 vUv;",
    "float hash12(vec2 p){",
    "  vec3 p3 = fract(vec3(p.xyx) * 0.1031);",
    "  p3 += dot(p3, p3.yzx + 33.33);",
    "  return fract((p3.x + p3.y) * p3.z);",
    "}",
    "void main(){",
    /* РАДИУС ПО ПЛОСКОСТИ ДИСКА, А НЕ ПО ОДНОЙ ОСИ. Круг стоит в
       плоскости XY своей геометрии и уже потом кладётся горизонтально
       поворотом. Брать xz значит брать x и ноль: пол гас полосами по
       одной стороне и держался во всю длину по другой, а «край»,
       задуманный как мягкое растворение по окружности, работал как
       вертикальная штора. */
    "  float r = length(vPos.xy) / 24.0;",
    "  vec3 color = mix(uC2, uC1, clamp(r * 1.2, 0.0, 1.0));",
    /* Поддельная тень под фигурой, их формула в наших единицах. */
    "  float shadow = min(1.0, length(vec3(vPos.x, 0.0, vPos.y) * 0.0625 + vec3(1.15, 0.0, -0.55)));",
    "  shadow = pow(shadow, 2.0);",
    "  shadow += sin(uTime * 3.3 + vPos.y * 0.31) * 0.1 + 0.1;",
    "  shadow += sin(uTime * 3.1 + vPos.x * 0.25) * 0.1 + 0.1;",
    "  shadow = mix(0.5, 1.0, shadow);",
    "  color *= mix(vec3(0.5, 0.7, 1.0) * 0.1, vec3(1.0), shadow);",
    /* Их же фальшивый ключ сбоку: пол светлее с одной стороны. */
    "  color *= mix(0.65, 1.0, vPos.x * 0.0208 + 0.5);",
    "  color += (vPos.x * 0.0417 + 1.0) * 0.02;",
    /* Пол растворяется к краю: у комнаты нет стен, и обрубленный диск
       выдал бы её размер. */
    /* КОЛЬЦЕВЫЕ СТУПЕНИ ПОЛА. У igloo дно это не гладкий диск, а
       ступенчатая площадка: на их кадрах хорошо видны концентрические
       окружности, сходящиеся к середине, и на них же стоит фигура. Без
       них наш пол читался туманным пятном без размера - глазу не за что
       зацепиться, и комната не имеет ни дна, ни масштаба.

       Ступени считаются по радиусу: шесть колец, каждое чуть ниже и
       темнее предыдущего, со светлой кромкой на переломе. */
    "  float stup = r * 6.0;",
    "  float nomer = floor(stup);",
    "  float vnutri = fract(stup);",
    "  color *= mix(1.06, 0.90, nomer / 6.0);",
    "  float kromka = smoothstep(0.06, 0.0, vnutri) + smoothstep(0.94, 1.0, vnutri);",
    "  color += kromka * 0.055;",
    "  color *= mix(0.965, 1.0, smoothstep(0.0, 0.35, vnutri));",
    "  float kray = 1.0 - smoothstep(0.72, 1.0, r);",
    "  color += (hash12(gl_FragCoord.xy + uTime) - 0.5) / 255.0;",
    "  gl_FragColor = vec4(color, kray * uAlpha);",
    "}"
  ].join("\n");

  /* ── Цилиндр фонового текста ──────────────────────────────────
     У них это размытые четырёхугольники из атласа. Своего атласа
     размытых букв у нас нет, и печатать его ради фона незачем: рисунок
     считается. Столбцы знаков идут по окружности, каждый знак это мягкое
     пятно, и всё вместе читается стеной текста, набранного слишком
     мелко, чтобы разобрать. Ровно та роль, что у них.

     Их гашение по строкам:
       alpha *= clamp(vPos.y * 2.0, 0.0, 1.0);
       alpha *= sin(time*2.0 + vRand*10.0 + (vPos.x*2.0 + vPos.z*2.0))*0.5 + 0.5;
       alpha *= falloffsmooth(length(vPos.xz), 0.0, 10.0, 3.0, uAlpha);
       alpha *= 0.7 * uAlpha; */
  var В_ЦИЛ = [
    "varying vec2 vUv;",
    "varying vec3 vPos;",
    "void main(){",
    "  vUv = uv; vPos = position;",
    "  gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);",
    "}"
  ].join("\n");

  var Ф_ЦИЛ = [
    "uniform vec3 uCvet;",
    "uniform float uTime;",
    "uniform float uAlpha;",
    "varying vec2 vUv;",
    "varying vec3 vPos;",
    "float hash12(vec2 p){",
    "  vec3 p3 = fract(vec3(p.xyx) * 0.1031);",
    "  p3 += dot(p3, p3.yzx + 33.33);",
    "  return fract((p3.x + p3.y) * p3.z);",
    "}",
    "void main(){",
    /* РАЗМЕР ЗНАКА РЕШАЕТ ВСЁ. Первая решётка была сто двадцать на
       двадцать восемь, и на снимке комната стояла в стене ЯРКИХ КВАДРАТОВ
       по двадцать пять точек экрана каждый: это читалось пикселями, а не
       текстом. У них знак мелкий и размытый настолько, что глаз видит
       набор, но не разбирает ни слова. Четыреста двадцать столбцов и
       девяносто строк дают знак в три-четыре точки - тот же порядок. */
    "  vec2 setka = vec2(420.0, 90.0);",
    "  vec2 kl = floor(vUv * setka);",
    "  vec2 vn = fract(vUv * setka);",
    /* СЛОВА, А НЕ РОВНОЕ ПОЛЕ. Текст держит ритм пробелами: без них
       любая решётка знаков читается сеткой. Столбцы режутся на куски по
       девять, кусок целиком либо есть, либо пуст, и внутри него ещё
       выпадают отдельные знаки. */
    "  float slovo = floor(kl.x / 9.0);",
    "  float est = step(0.38, hash12(vec2(slovo, kl.y * 3.7)))",
    "            * step(0.18, hash12(kl + 2.1));",
    /* Строки тоже не сплошные: абзац кончается, дальше пустая строка. */
    "  est *= step(0.22, hash12(vec2(kl.y * 17.0, 4.0)));",
    /* Знак это МЯГКОЕ ПЯТНО. Резкие края с расстояния дают квадрат;
       плавное падение от середины ячейки к краям даёт то же, что даёт
       размытая буква - светлое ядро и растворённый контур. */
    "  vec2 c = vn - 0.5;",
    "  float pyatno = smoothstep(0.52, 0.06, length(c * vec2(1.9, 1.0)));",
    "  float znak = pyatno * est * (0.45 + 0.55 * hash12(kl + 7.3));",
    "  float a = znak;",
    /* Их четыре множителя гашения. */
    "  a *= clamp(vPos.y * 0.5 + 0.5, 0.0, 1.0);",
    "  a *= sin(uTime * 2.0 + hash12(kl) * 10.0 + (vPos.x * 0.5 + vPos.z * 0.5)) * 0.5 + 0.5;",
    /* Сила втрое ниже прежней. Складывающий режим набирает яркость сам:
       два цилиндра друг за другом при 0.7 давали стену светлее пола, и
       фигура из частиц тонула в собственном фоне. */
    "  a *= 0.22 * uAlpha;",
    "  if (a < 0.004) discard;",
    "  gl_FragColor = vec4(uCvet, a);",
    "}"
  ].join("\n");

  /* ── Дымка ────────────────────────────────────────────────────
     Плоский слой у пола и у потолка. У них поземка считается как
     pow(value*3, 3) + pow(screenUv.x, 2)*fade*0.15. */
  var Ф_ДЫМКА = [
    "uniform sampler2D tWind;",
    "uniform vec3 uCvet;",
    "uniform float uTime;",
    "uniform float uAlpha;",
    "varying vec2 vUv;",
    "varying vec3 vPos;",
    "void main(){",
    "  float t = uTime * 0.04;",
    "  float v = texture2D(tWind, vUv * 2.0 + vec2(t, -t * 0.6)).r;",
    "  v *= texture2D(tWind, vUv * 3.5 + vec2(-t * 0.7, t * 0.4)).r;",
    /* СИЛА ДЫМКИ ПЕРЕСЧИТАНА ПОД НАШУ КАРТУ ШУМА. Их множитель три
       считан под их `wind_noise`, где серединная яркость около двух
       десятых. Наша карта светлее (около четырёх десятых), и то же
       выражение упиралось в единицу почти везде: на снимке комнаты дно
       стояло сплошным облаком, сквозь которое не было видно ни пола, ни
       колец. Полтора вместо трёх возвращают дымке её роль - слой у пола,
       а не туман во весь кадр.

       Слагаемое по экранной координате снято совсем. У них оно даёт
       мягкую засветку с одной стороны кадра, но там подложка тёмная; на
       светлом подземелье складывающая засветка в пятнадцать сотых - это
       белая пелена поверх всего. */
    "  float a = pow(v * 1.5, 3.0);",
    "  float r = length(vPos.xy) / 24.0;",
    "  a *= 1.0 - smoothstep(0.45, 0.95, r);",
    "  a *= uAlpha * 0.22;",
    "  if (a < 0.004) discard;",
    "  gl_FragColor = vec4(uCvet, clamp(a, 0.0, 1.0));",
    "}"
  ].join("\n");

  function шум() {
    if (g.RV_ЛУНА && g.RV_ЛУНА["шум"]) {
      var ш = g.RV_ЛУНА["шум"]();
      if (ш) return ш;
    }
    return null;
  }

  /* ── ГДЕ СТОИТ ЗАЛ: ОДНО ЧИСЛО НА ВЕСЬ САЙТ ───────────────────
     Место комнаты знали три файла сразу (прокол, ангар, пуск), и каждый
     держал свою копию тройки координат. Пока зал стоял под Луной, копии
     совпадали; как только тоннель лёг горизонтально и зал переехал
     вперёд по курсу, любая забытая копия оставила бы свой акт смотреть
     в пустоту. Теперь место живёт здесь, а акты его спрашивают.

     Зал стоит НЕ ПОД шахтой, а ЗА ней. Тоннель идёт от кладки (z 76)
     вперёд и слегка вверх и кончается на z 40; зал стоит ещё дальше, на
     z -4, и камера выходит из трубы прямо к нему.

     Почему так далеко. Обход вокруг роя идёт по окружности радиусом
     двадцать шесть, то есть входит в зал на z 22. Между концом трубы
     (40) и этой точкой остаётся восемнадцать единиц - ровно тот
     перегон, на котором акт прокола передаёт камеру акту обхода. Стоял
     зал ближе - перегон получался нулевым, и девятьсот точек прокрутки
     между секциями не меняли в кадре ничего.

     Высота: середина ракеты обязана оказаться на 22 - это высота глаза
     на выходе из тоннеля плюс подъём последней трети. Рой сидит в
     восьми единицах над дном зала, значит дно на 14. */
  var МЕСТО = { "x": 0, "y": 14, "z": -4 };
  /* Середина роя в мире: дно зала плюс местная высота фигуры. */
  var ФИГУРА_НАД_ДНОМ = 8.0;
  function место() { return { "x": МЕСТО.x, "y": МЕСТО.y, "z": МЕСТО.z }; }
  function серединаФигуры() {
    return { "x": МЕСТО.x, "y": МЕСТО.y + ФИГУРА_НАД_ДНОМ, "z": МЕСТО.z };
  }

  /* Настоящий короб роя в местных единицах комнаты. Нужен тем, кто
     ставится ВОКРУГ фигуры: рубашка силового поля обязана её охватить, а
     не встать по числу, снятому с чужой фигуры другой формы. Мерка
     снимается с геометрии, потому что размер роя зависит и от модели, и
     от масштаба узла, и от ступени качества. */
  /* Подогнана ли рубашка под настоящий короб роя. Ставится в сборке и
     в первом кадре: рой строится после поля, и на сборке короба ещё
     нет. */
  var полеПодогнано = false;

  function подогнатьПоле() {
    if (полеПодогнано || !М.поле) return;
    var к = коробФигуры();
    if (!к) return;
    var рад = Math.max(к.радиус * 1.018, 0.4);
    М.поле.scale.set(рад, к.высота * 1.217 / 3, рад);
    М.поле.position.y = к.низ;
    полеПодогнано = true;
  }

  function коробФигуры() {
    if (!М.фигура || !М.фигура.geometry) return null;
    var г = М.фигура.geometry;
    if (!г.boundingBox) г.computeBoundingBox();
    var бб = г.boundingBox;
    if (!бб) return null;
    var s = М.фигура.scale.x || 1;
    var полуШ = Math.max(бб.max.x - бб.min.x, бб.max.z - бб.min.z) * 0.5 * s;
    var выс = (бб.max.y - бб.min.y) * s;
    return {
      "радиус": полуШ,
      "высота": выс,
      "низ": М.фигура.position.y + бб.min.y * s
    };
  }

  function собрать(мир, о) {
    if (собрано) return М.корень;
    W = мир || W;
    if (!W || !W.T) return null;
    T = W.T;
    о = о || {};

    М.корень = new T.Group();
    М.корень.name = "комната";
    М.корень.visible = false;
    /* Комната стоит под шахтой: та же ось x и z, что у проёма в кладке,
       дно на четыре единицы ниже, чем кончается падение. */
    М.корень.position.set(
      о["x"] == null ? МЕСТО.x : о["x"],
      о["y"] == null ? МЕСТО.y : о["y"],
      о["z"] == null ? МЕСТО.z : о["z"]);
    W.scene.add(М.корень);

    М.uTime = { value: 0 };
    М.uАльфаПол = { value: 0 };
    М.uАльфаЦил = { value: 0 };
    М.uАльфаДым = { value: 0 };

    /* ПОЛ. Диск, а не квадрат: у комнаты нет углов, и квадратный край
       выдал бы её как декорацию. */
    М.мПол = new T.ShaderMaterial({
      uniforms: {
        /* Их цвета пола: #6a6f7d и #e1e6f1. */
        uC1: { value: new T.Color(0x6a6f7d) },
        uC2: { value: new T.Color(0xe1e6f1) },
        uTime: М.uTime, uAlpha: М.uАльфаПол
      },
      vertexShader: В_ПОЛ, fragmentShader: Ф_ПОЛ,
      transparent: true, depthWrite: false, fog: false, side: T.DoubleSide
    });
    М.пол = new T.Mesh(new T.CircleGeometry(24, W.ступень === 0 ? 32 : 64), М.мПол);
    М.пол.name = "пол комнаты";
    М.пол.rotation.x = -Math.PI / 2;
    М.пол.renderOrder = 1;
    М.корень.add(М.пол);

    /* ЦИЛИНДР ТЕКСТА: две копии, как у них - 1.75 и 3.5 с поворотом.
       В наших единицах это семь и четырнадцать. Ближний рисуется вторым
       (renderOrder 1), дальний первым, как у них.

       НА КУПОЛ, О КОТОРОМ СКАЗАЛ ВЛАДЕЛЕЦ, ОНИ НЕ ОТВЕЧАЮТ. Я снял
       ближний по одному подозрению и снимок показал купол на месте:
       снял не то. Замер кадра (tools/что-в-кадре.mjs) назвал виновника
       прямо - «силовое поле фигуры», 265 на 546 точек, ровно
       прямоугольник купола. Цилиндры на своих местах, купол убран там,
       где он живёт (см. ниже, силовое поле). */
    М.мЦил = new T.ShaderMaterial({
      uniforms: { uCvet: { value: new T.Color(0xB6C4E4) }, uTime: М.uTime, uAlpha: М.uАльфаЦил },
      vertexShader: В_ЦИЛ, fragmentShader: Ф_ЦИЛ,
      transparent: true, depthWrite: false, side: T.BackSide,
      blending: T.AdditiveBlending, fog: false
    });
    var гЦил = new T.CylinderGeometry(1, 1, 1.2, W.ступень === 0 ? 24 : 48, 1, true);
    М.цилБлиж = new T.Mesh(гЦил, М.мЦил);
    М.цилБлиж.name = "текст комнаты ближний";
    М.цилБлиж.scale.set(7 * К * 0.25, 7 * К * 0.25, 7 * К * 0.25);
    М.цилБлиж.position.y = 5;
    М.цилБлиж.renderOrder = 1;
    М.корень.add(М.цилБлиж);
    М.цилДаль = new T.Mesh(гЦил, М.мЦил);
    М.цилДаль.name = "текст комнаты дальний";
    М.цилДаль.scale.set(14 * К * 0.25, 14 * К * 0.25, 14 * К * 0.25);
    М.цилДаль.rotation.y = Math.PI * 0.5;
    М.цилДаль.position.y = 8;
    М.цилДаль.renderOrder = 0;
    М.корень.add(М.цилДаль);

    /* ДЫМКА у пола и у потолка. Без карты шума слой не строим: ровная
       заливка вместо дыма хуже, чем его отсутствие. */
    var ш = шум();
    if (ш) {
      М.мДым = new T.ShaderMaterial({
        uniforms: { tWind: { value: ш }, uCvet: { value: new T.Color(0x8FA6D8) },
                    uTime: М.uTime, uAlpha: М.uАльфаДым },
        vertexShader: В_ПОЛ, fragmentShader: Ф_ДЫМКА,
        transparent: true, depthWrite: false, side: T.DoubleSide,
        blending: T.AdditiveBlending, fog: false
      });
      М.дымПол = new T.Mesh(new T.CircleGeometry(22, 40), М.мДым);
      М.дымПол.rotation.x = -Math.PI / 2;
      М.дымПол.position.y = 0.4;
      М.дымПол.renderOrder = 2;
      М.корень.add(М.дымПол);
      М.дымВерх = new T.Mesh(new T.CircleGeometry(20, 40), М.мДым);
      М.дымВерх.rotation.x = Math.PI / 2;
      М.дымВерх.position.y = 17;
      М.дымВерх.renderOrder = 2;
      М.корень.add(М.дымВерх);
    }

    /* ── СИЛОВОЕ ПОЛЕ ПОД ФИГУРОЙ (их forcefield, класс uF) ───────
       Здесь стоял пустой блок с обещанием, что материал живёт в модуле
       трубы. Он там не жил: разбор их сборки показал, что это отдельный
       объект со своим шейдером, и у нас его не было вовсе. Владелец про
       такие вещи говорит «стеклянные какие-то эффекты».

       ИХ ЧИСЛА. CylinderGeometry(1, 1, 3, 64, 6, открытая), сдвинутая
       translate(0, 1.5, 0) - низ на нуле, верх на трёх. Меш стоит на
       y -10.13 с масштабом 0.28, то есть в мире это рубашка радиусом
       0.28 и высотой 0.84. Фигура из частиц зажата в цилиндр радиусом
       0.275 высотой от -10.125 до -9.435, значит рубашка охватывает её
       вплотную и торчит на 0.145 выше макушки. В наших единицах (К = 4)
       радиус 1.12 и высота 3.36.

       ФРЕНЕЛЬ У НИХ ВЫВЕРНУТ, и это главное в приёме. softedge ГАСИТ
       силуэт, а не подсвечивает его: поле светится там, где смотрит на
       камеру, и пропадает по кромке. Обычный стеклянный ободок дал бы
       мыльный пузырь; их приём даёт объёмный туман в стакане. */
    var В_ПОЛЕ = [
      "varying vec2 vUv;",
      "varying vec3 vPos;",
      "varying vec3 vNormal;",
      "varying vec3 vEye;",
      "void main(){",
      "  vUv = uv;",
      "  vPos = (modelMatrix * vec4(position, 1.0)).xyz;",
      "  vNormal = normalMatrix * normal;",
      "  vEye = -(modelViewMatrix * vec4(position, 1.0)).xyz;",
      "  gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);",
      "}"
    ].join("\n");
    /* Их треугольная плитка tTriangles у нас своей текстурой не
       заведена, и заводить её ради одной рубашки дорого: рисунок мелкий
       и в кадре читается зерном. Берём тот же рисунок формулой - сетка
       треугольников через складку по трём осям развёртки. */
    var Ф_ПОЛЕ = [
      /* Их sinenoise1: шесть слоёв синусов на несоизмеримых частотах.
         Тот же, что в rv-труба.js. Повторён здесь, потому что общего
         места под шейдерные функции у сайта нет, а тащить модуль трубы
         в комнату ради шести строк дороже, чем эти шесть строк. */
      "float sinenoise1(vec3 p){",
      "  float val = 0.0;",
      "  val += sin(dot(p, vec3(1.5, 3.4598, 1.234)));",
      "  val += sin(dot(p, vec3(3.12, -3.234, 4.221)));",
      "  val += sin(dot(p, vec3(0.355, 2.3, -1.375)));",
      "  val += sin(dot(p, vec3(-0.156, -3.34, -0.4566)));",
      "  val += sin(dot(p, vec3(-4.1235, -0.485, -1.45)));",
      "  val += sin(dot(p, vec3(2.54, -0.879, -2.123)));",
      "  return val / 6.0;",
      "}",
      "uniform float uAlpha;",
      "uniform float uTime;",
      "varying vec2 vUv;",
      "varying vec3 vPos;",
      "varying vec3 vNormal;",
      "varying vec3 vEye;",
      "float treugolniki(vec2 p){",
      "  vec2 q = vec2(p.x + p.y * 0.5, p.y);",
      "  vec2 f = fract(q);",
      "  float d = min(min(f.x, f.y), abs(f.x + f.y - 1.0));",
      "  return smoothstep(0.0, 0.09, d);",
      "}",
      "void main(){",
      "  vec2 uv = vUv;",
      "  uv.x *= 2.0;",
      "  vec3 pos = vPos;",
      "  float t = uTime * 0.5;",
      "  float noise = sinenoise1(pos * 4.0 + vec3(0.0, t * 0.45, -t * 0.13)) * 0.5 + 0.5;",
      "  noise *= sinenoise1(pos * 2.0 + vec3(t * 0.3, -t * 0.27, t * 0.2)) * 0.5 + 0.5;",
      "  noise = sin(noise * 15.0 - t * 7.0) * 0.5 + 0.5;",
      "  noise = pow(noise, 4.0);",
      "  float triangles = treugolniki(uv * 6.0 + vec2(noise * 0.05));",
      "  float fresnel = 1.0 - max(0.0, dot(normalize(vNormal), normalize(vEye)));",
      "  float softedge = 1.0 - smoothstep(0.65, 0.99, fresnel);",
      "  fresnel = mix(fresnel, 1.0, 0.25);",
      "  float fadetop = 1.0 - smoothstep(0.5, 1.0, vUv.y);",
      "  float alpha = (noise * triangles * 2.0 + noise * 0.03) * fresnel * softedge * fadetop;",
      "  alpha *= uAlpha;",
      "  gl_FragColor = vec4(vec3(1.0), alpha);",
      "}"
    ].join("\n");
    М.uАльфаПоля = { value: 0 };
    var гПоле = new T.CylinderGeometry(1, 1, 3, 64, 6, true);
    гПоле.translate(0, 1.5, 0);
    М.мПоле = new T.ShaderMaterial({
      uniforms: { uAlpha: М.uАльфаПоля, uTime: М.uTime },
      vertexShader: В_ПОЛЕ, fragmentShader: Ф_ПОЛЕ,
      transparent: true, blending: T.AdditiveBlending, side: T.DoubleSide,
      fog: false
    });
    М.поле = new T.Mesh(гПоле, М.мПоле);
    М.поле.name = "силовое поле фигуры";
    /* ── МАСШТАБ СЧИТАЕТСЯ ОТ САМОЙ ФИГУРЫ, А НЕ ПЕРЕНОСИТСЯ ЧИСЛОМ
       Их рубашка стоит с равномерным масштабом 0.28: радиус 0.28 и
       высота 0.84. Это работает у них, потому что их фигура приземистая
       - радиус 0.275 при высоте 0.69, отношение два с половиной. Наша
       фигура это РАКЕТА: при том же радиусе она вчетверо с лишним выше,
       и равномерный масштаб дал бы либо рубашку по пояс, либо бочку
       вокруг.

       Переносим не число, а ПРОПОРЦИИ ОХВАТА: у них рубашка шире
       фигуры в 1.018 раза и выше её в 1.217, а низ её садится на низ
       фигуры. Эти три отношения и повторяем, сняв мерку с настоящего
       короба роя. */
    var кф = коробФигуры();
    полеПодогнано = !!кф;
    if (кф) {
      var рад = Math.max(кф.радиус * 1.018, 0.4);
      var выс = кф.высота * 1.217;
      /* Геометрия идёт от нуля до трёх по высоте и радиусом единица,
         поэтому по вертикали делим на три. */
      М.поле.scale.set(рад, выс / 3, рад);
      М.поле.position.y = кф.низ;
    } else {
      /* Рой строится НИЖЕ по этой же сборке, поэтому на этой строке
         короба ещё нет. Встаём по их числам и подтягиваемся первым же
         кадром - см. подогнатьПоле() в кадре. */
      М.поле.scale.setScalar(0.28 * К);
      М.поле.position.y = ФИГУРА_НАД_ДНОМ - 1.36;
      полеПодогнано = false;
    }
    М.поле.renderOrder = 15;
    /* СНЯТА ПО СЛОВУ ВЛАДЕЛЬЦА (см. «РУБАШКА ВОКРУГ ФИГУРЫ СНЯТА»
       в кадре комнаты). В сцену не кладём вовсе: невидимый меш всё
       равно обходится деревом каждый кадр, а вернуть его - строка. */
    М.поле.visible = false;

    /* ── КОЛЬЦО КОМНАТЫ (их roomring, класс oF) ───────────────────
       Тонкий обруч с ДВУМЯ РАЗРЫВАМИ, лежащий над дном. У нас его не
       было ни в одном модуле.

       Это единственный объект их сцены входа, который кладёт в кадр
       цвет ВЫШЕ единицы: vec3(2.0). Он и даёт ту одну точку кадра,
       которая уходит в чистый белый, а всё остальное белое у них
       собирается складыванием слоёв и ореолом. Число сохраняем как
       есть: снизить его значит потерять единственный настоящий
       источник света в комнате.

       Разрыв smoothstep(0.03, 0.1, abs(vUv.x - 0.5)) обязателен: без
       него обруч читается декоративной шайбой. */
    var В_ОБРУЧ = [
      "uniform float uTime;",
      "varying vec2 vUv;",
      "vec2 povorot(vec2 v, float a){",
      "  float s = sin(a), c = cos(a);",
      "  return mat2(c, s, -s, c) * v;",
      "}",
      "void main(){",
      "  vUv = uv;",
      "  vec3 pos = position;",
      "  pos.xz = povorot(pos.xz, -uTime * 0.2);",
      "  gl_Position = projectionMatrix * modelViewMatrix * vec4(pos, 1.0);",
      "}"
    ].join("\n");
    var Ф_ОБРУЧ = [
      "uniform float uTime;",
      "varying vec2 vUv;",
      "void main(){",
      "  float dist = length(vUv - 0.5);",
      "  float alpha = smoothstep(0.5, 0.3, dist);",
      "  alpha *= smoothstep(0.3, 0.4, dist);",
      "  alpha *= smoothstep(0.03, 0.1, abs(vUv.x - 0.5));",
      "  alpha *= mix(1.0, 0.8, sin(uTime * 2.0 + dist + vUv.x * 2.0 + vUv.y) * 0.5 + 0.5);",
      "  gl_FragColor = vec4(vec3(2.0), alpha);",
      "}"
    ].join("\n");
    var гОбруч = new T.PlaneGeometry(1, 1);
    гОбруч.rotateX(Math.PI * 0.5);
    гОбруч.translate(0, 1.5, 0);
    М.мОбруч = new T.ShaderMaterial({
      uniforms: { uTime: М.uTime },
      vertexShader: В_ОБРУЧ, fragmentShader: Ф_ОБРУЧ,
      transparent: true, blending: T.AdditiveBlending, fog: false
    });
    М.обруч = new T.Mesh(гОбруч, М.мОбруч);
    М.обруч.name = "кольцо комнаты";
    /* Их масштаб 0.57 при плоскости в единицу даёт диск радиусом 0.285,
       а сам обруч читается на 0.205..0.217 мира. В наших единицах это
       радиус около 0.84 и высота над дном 3.42. */
    М.обруч.scale.setScalar(0.57 * К);
    М.обруч.position.y = ФИГУРА_НАД_ДНОМ - 4.58;
    М.обруч.renderOrder = 3;
    М.обруч.visible = false;
    М.корень.add(М.обруч);

    /* ОКРУЖАЮЩИЕ ЧАСТИЦЫ: их шестьдесят точек. Комната без них читается
       вакуумом, а не помещением с воздухом. */
    var точек = W.ступень === 0 ? 24 : 60;
    var гТ = new T.BufferGeometry();
    var поз = new Float32Array(точек * 3), сем = new Float32Array(точек);
    var семя = 991;
    function сл() { семя = (семя * 9301 + 49297) % 233280; return семя / 233280; }
    for (var i = 0; i < точек; i++) {
      var уг = сл() * Math.PI * 2, рад = 3 + сл() * 17;
      поз[i * 3] = Math.cos(уг) * рад;
      поз[i * 3 + 1] = 1 + сл() * 15;
      поз[i * 3 + 2] = Math.sin(уг) * рад;
      сем[i] = сл();
    }
    гТ.setAttribute("position", new T.BufferAttribute(поз, 3));
    гТ.setAttribute("aSeed", new T.BufferAttribute(сем, 1));
    М.мПыль = new T.ShaderMaterial({
      uniforms: { uTime: М.uTime, uAlpha: М.uАльфаПол,
                  uCvet: { value: new T.Color(0xD6E2FF) }, uH: { value: 900 } },
      vertexShader: [
        "attribute float aSeed;",
        "uniform float uTime;",
        "uniform float uH;",
        "varying float vA;",
        "void main(){",
        "  vec3 p = position;",
        "  p.y += sin(uTime * 0.4 + aSeed * 12.0) * 1.4;",
        "  p.x += cos(uTime * 0.3 + aSeed * 9.0) * 1.0;",
        "  vec4 mv = modelViewMatrix * vec4(p, 1.0);",
        "  vA = 0.35 + 0.65 * aSeed;",
        "  gl_PointSize = (uH / 900.0) * 26.0 / max(1.0, -mv.z);",
        "  gl_Position = projectionMatrix * mv;",
        "}"
      ].join("\n"),
      fragmentShader: [
        "uniform vec3 uCvet;",
        "uniform float uAlpha;",
        "varying float vA;",
        "void main(){",
        "  float r = length(gl_PointCoord - 0.5) * 2.0;",
        "  float a = pow(1.0 - clamp(r, 0.0, 1.0), 1.7) * vA * uAlpha;",
        "  if (a < 0.01) discard;",
        "  gl_FragColor = vec4(uCvet, a);",
        "}"
      ].join("\n"),
      transparent: true, depthWrite: false, blending: T.AdditiveBlending, fog: false
    });
    М.пыль = new T.Points(гТ, М.мПыль);
    М.пыль.name = "воздух комнаты";
    М.пыль.frustumCulled = false;
    М.пыль.renderOrder = 3;
    М.корень.add(М.пыль);

    /* ── ФИГУРА В СЕРЕДИНЕ ────────────────────────────────────
       Ракета, снятая точками с собственной поверхности. Строит её
       КОМНАТА, а не акт: модуль частиц одиночка, и кто позвал его
       первым, тот и получает рой себе в корень. Пуск звал его раньше
       прокола, и фигура оказывалась в акте пуска, а не на дне шахты -
       замер показал её на местной высоте 1.6 вместо 7.5.

       Место у неё теперь одно, и принадлежит оно комнате. Кто хочет ею
       управлять - зовёт RV_ЧАСТИЦЫ по имени, а не строит заново. */
    if (g.RV_ЧАСТИЦЫ && g.RV_ЧАСТИЦЫ["собрать"]) {
      /* Размер точки их: uSize 10. Он делится на дальность, поэтому без
         множителя масштаба точка на нашей крупной фигуре схлопывается в
         субпиксель и статуя рассыпается в пыль. Масштаб отдаётся модулю
         отдельным вызовом, а не читается им из узла: узел живёт в
         гнезде акта, и его мировой масштаб не равен местному. */
      /* РАЗМЕР ТОЧКИ СЧИТАЕТСЯ ОТ ОТНОШЕНИЯ ФИГУР, А НЕ ОТ МАСШТАБА УЗЛА.

         Их закон: gl_PointSize = uSize / дальность * (высота / 1300), и
         uSize у них десять при фигуре высотой 0.69 их единицы. Экранный
         размер точки идёт от ОТНОШЕНИЯ мирового радиуса точки к
         дальности, значит при фигуре во столько же раз крупнее и камере
         во столько же раз дальше он сохраняется только если uSize вырос
         в то же число раз.

         Наша ракета это 2.8 единицы модели при масштабе 4.6, то есть
         12.9 мировых против их 0.69. Отношение 18.7 - его и передаём.
         Стоял масштаб узла (4.6), и точка выходила В ОДИН ПИКСЕЛЬ:
         замер показал 1.18 при их 3.45, и вместо статуи из песка на
         экране была цветная крупа. */
      /* РОСТ ФИГУРЫ СЧИТАН ОТ ИХ КАДРА. У igloo фигура высотой 0.69 их
         единицы стоит в трёх единицах от камеры при поле в тридцать
         градусов - это сорок три процента высоты кадра. Наша камера
         обходит по окружности радиусом двадцать шесть при поле сорок
         четыре: высота кадра там двадцать одна единица, и сорок три
         процента от неё это девять с половиной. Модель ракеты 2.8
         единицы, значит масштаб 3.4.

         Стояло 4.6, и фигура занимала шестьдесят четыре процента кадра -
         не статуя в комнате, а предмет в упор. */
      М.фигура = g.RV_ЧАСТИЦЫ["собрать"](W, М.корень, { размер: 10.0, масштаб: 13.8 });
      if (М.фигура) {
        М.фигура.position.set(0, ФИГУРА_НАД_ДНОМ, 0);
        М.фигура.scale.setScalar(3.4);
        if (g.RV_ЧАСТИЦЫ["масштаб"]) g.RV_ЧАСТИЦЫ["масштаб"](13.8);
      }
    }

    /* ── ОБЪЁМНАЯ РАКЕТА НА МЕСТЕ РОЯ ──────────────────────────
       Владелец: «когда я выигрываю в мини игру, ракета из частиц
       превращается в цветную объёмную ракету, точно такую же, как на
       сайте CDN, и мне дают три дня бесплатно».

       Корабль встаёт В КОМНАТУ, рядом с роем, а не в акт: рой живёт
       здесь, и подогнать() ищет его коробку у своего родителя. Собери
       мы ракету в акте - она искала бы рой в чужом узле и вставала бы
       мимо, ровно как когда-то вставал сам рой.

       Проявление ведёт доля, а не выключатель: металл проступает снизу
       вверх, пока рой рассыпается, и один кадр показывает обе фигуры
       разом. Это и есть превращение. */
    if (g.RV_РАКЕТА && g.RV_РАКЕТА["собрать"]) {
      М.ракета = g.RV_РАКЕТА["собрать"](W, М.корень, {});
      if (М.ракета && g.RV_РАКЕТА["подогнать"]) g.RV_РАКЕТА["подогнать"]();
      if (g.RV_РАКЕТА["проявить"]) g.RV_РАКЕТА["проявить"](0);
    }

    собрано = true;
    return М.корень;
  }

  /* ── ПОБЕДА В МИНИ-ИГРЕ ─────────────────────────────────────
     Игра сообщает о себе событием, а не общей переменной: акт пуска
     держит ворота, комната держит фигуру, и знать друг о друге им
     незачем. Победа once сохранена в хранилище (rv-игра.js), поэтому
     вернувшийся человек видит корабль сразу, а не выигрывает заново. */
  /* Насколько комната отступила за корабль финала. Ноль это обычный
     зал обхода, единица - только пол под кораблём. Ставит финал. */
  var приглушено = 0;
  var победа = 0;      /* к чему идём: 0 рой, 1 корабль */
  var превращение = 0; /* где сейчас: догоняет победу за полторы секунды */
  function победил() {
    победа = 1;
  }
  g.addEventListener("rv:игра", function (е) {
    var д = е && е.detail;
    if (д && д["итог"] === "победа") победил();
  });
  try {
    /* Тот же ключ, что у игры: она пишет победу в хранилище, мы её
       читаем. Спрашивать саму игру нельзя - её модуль может ещё не
       подняться, когда комната уже собралась. */
    if (g.localStorage && g.localStorage.getItem("rv-игра-ангар") === "1") победа = 1;
  } catch (eХ) {}

  /* Времянка их таймлайна, переведённая в долю акта. У них комната
     включается на 3.4 из 9.2 (то есть 0.37), цилиндр текста на 4.5
     (0.49). Здесь то же в долях падения: пол проступает с 0.55, цилиндр
     с 0.72 - к этому времени человек уже видит дно. */
  function кадр(доля, dt, часы) {
    if (!собрано) return;
    М.uTime.value = часы || 0;
    /* ── ПРИГЛУШЕНИЕ: КОМНАТА ОТСТУПАЕТ ЗА КОРАБЛЬ ───────────────
       Дымка и цилиндр текста считались под то, что в середине зала
       стоит фигура в десять единиц ростом и человек смотрит на неё с
       двадцати шести. Финал переставил туда КОРАБЛЬ и подвёл камеру на
       семь единиц: та же дымка, рассчитанная на дальний план, встала
       между глазом и обшивкой и вымыла кадр в ровный светло-серый -
       первый же снимок подхода это показал.

       Пол не уходит совсем, но садится до четверти. Совсем без него
       площадка висит в пустоте; в полную силу он светит белым под
       кораблём и забирает низ кадра - снимок доли 0.10 это показал.
       У соседей под ракетой темно, площадка светится сама. */
    М.uАльфаПол.value = мягко(0.55, 0.92, доля) * (1 - приглушено * 0.78);
    М.uАльфаДым.value = мягко(0.58, 0.95, доля) * (1 - приглушено * 0.88);
    М.uАльфаЦил.value = мягко(0.72, 1.0, доля) * (1 - приглушено);
    /* Цилиндры текста медленно расходятся в стороны: ближний в одну,
       дальний в другую. Комната от этого дышит, а не стоит макетом. */
    /* Фигура живёт всегда, пока комната в кадре: у igloo облако точек
       крутится само на 43 градуса в секунду и не замирает никогда. */
    if (g.RV_ЧАСТИЦЫ && М.фигура) {
      g.RV_ЧАСТИЦЫ["кадр"](dt, часы);
      М.фигура.rotation.y = -(часы || 0) * 0.75;
    }
    /* ── ПРЕВРАЩЕНИЕ РОЯ В КОРАБЛЬ ────────────────────────────
       Полторы секунды на весь переход: за это время металл успевает
       вырасти снизу вверх и человек видит, ЧТО происходит, а не
       обнаруживает подмену между кадрами. Догон идёт по времени, а не
       покадрово: на слабом устройстве кадров вдвое меньше, а переход
       обязан длиться столько же.

       Рой не гасится совсем. У ракеты своя оболочка, точки остаются
       вокруг неё редкой пылью - тем же роем, только присмиревшим.
       Полное выключение читалось бы как пропажа, а не как сборка. */
    if (М.ракета) {
      var шагП = dt == null ? 0.016 : dt;
      превращение += (победа - превращение) * (1 - Math.exp(-шагП / 0.55));
      if (превращение > 0.999) превращение = 1;
      if (превращение < 0.0005) превращение = 0;
      if (g.RV_РАКЕТА["проявить"]) g.RV_РАКЕТА["проявить"](превращение);
      if (g.RV_РАКЕТА["кадр"]) g.RV_РАКЕТА["кадр"](шагП, часы || 0);
      /* Рой уходит следом за металлом: сначала его точки разлетаются
         наружу, потом гаснут. К концу перехода остаётся четверть - та
         самая пыль вокруг корпуса. Разлёт ведёт, прозрачность идёт с
         отставанием, поэтому точки успевают отойти от корпуса прежде
         чем пропасть, и подмены в кадре не видно. */
      if (g.RV_ЧАСТИЦЫ && превращение > 0.0005) {
        if (g.RV_ЧАСТИЦЫ["разлёт"]) g.RV_ЧАСТИЦЫ["разлёт"](превращение * 0.42);
        if (g.RV_ЧАСТИЦЫ["проявить"]) {
          g.RV_ЧАСТИЦЫ["проявить"](1 - зажать((превращение - 0.25) / 0.75, 0, 1) * 0.75, 0);
        }
      }
    }
    if (М.цилБлиж) М.цилБлиж.rotation.y = (часы || 0) * 0.014;
    М.цилДаль.rotation.y = Math.PI * 0.5 - (часы || 0) * 0.009;

    /* ── РУБАШКА ВОКРУГ ФИГУРЫ СНЯТА ──────────────────────────
       Владелец, глядя на кадр ангара с телефона: «какой-то круглый
       купол вокруг ракеты, его убрать, такого у igloo нету».

       Купол это она. Замер кадра (tools/что-в-кадре.mjs) на доле 0.55
       ангара дал прямоугольники всех видимых предметов, и «силовое поле
       фигуры» заняло 265 на 546 точек - ровно тот столб, что на
       снимке. Рой ракеты внутри него 366 на 477.

       Разбор их сборки, по которому рубашка сюда попала, не врал: у
       соседей такой объект есть. Врало перенесение. У них фигура
       приземистая (радиус 0.275 при высоте 0.69), рубашка садится на
       неё чулком в палец толщиной и читается дымкой в стакане. Наша
       фигура это РАКЕТА - при том же радиусе она вчетверо выше, - и
       та же рубашка стала стеклянной колбой в полный рост. Складывающий
       режим на светлой оболочке добрал ей яркости, и с двадцати шести
       единиц колба спорит с самой ракетой.

       Держать чужой приём там, где он даёт чужой результат, незачем.
       Меш, шейдер и подгонка размеров остаются в файле: беда в том, что
       рубашка ВИДНА, а не в том, как она устроена. Захотим вернуть -
       вернётся одной строкой, и с ней вернутся все мерки.

       Обруч комнаты у них включается жёстким переключателем на progress
       выше 0.53, без единого твина прозрачности; так и делаем. */
    подогнатьПоле();
    if (М.uАльфаПоля) М.uАльфаПоля.value = 0;
    if (М.обруч) М.обруч.visible = доля > 0.53;
  }

  g.RV_КОМНАТА = {
    "собрать": собрать,
    "место": место,
    "серединаФигуры": серединаФигуры,
    "кадр": кадр,
    /* Спрашивают комнату три акта: прокол приводит в неё, ангар и пуск
       по ней ходят. Гаснет она только когда её отпустил последний -
       иначе акт, уходящий из кадра, утаскивал бы пол из-под соседа. */
    "видно": function (да, кто) {
      if (!собрано) return;
      просят[кто || "прокол"] = !!да;
      var хоть = false;
      for (var к in просят) if (просят[к]) { хоть = true; break; }
      М.корень.visible = хоть;
    },
    "узел": function () { return собрано ? М.корень : null; },

    /* ── ФИНАЛ ЗАБИРАЕТ РАКЕТУ СЕБЕ ─────────────────────────────
       Корабль финала переехал НА ЭТО ЖЕ МЕСТО (rv-act-финал.js): рой,
       цельная ракета и корабль, в который человек заходит, теперь одна
       точка мира. Владелец: «ракета в другом месте появляется сразу,
       шов есть».

       Комната остаётся: пол, дымка, кольца и цилиндр текста никуда не
       деваются, человек по-прежнему стоит в ангаре. Уходит только
       ФИГУРА - иначе в одной точке стояли бы два корпуса разом.

       Гасим рой и металл, а не корень: комната принадлежит трём актам
       сразу, и выключать её целиком значит забрать пол у соседа. */
    /* Насколько зал отступает за корабль. Ведёт финал по своей доле:
       на подходе комната ещё зал, у люка от неё остаётся пол. */
    "приглушить": function (k) {
      приглушено = k == null ? 0 : (k < 0 ? 0 : (k > 1 ? 1 : k));
    },

    "фигураВидна": function (да) {
      if (!собрано) return;
      var н = !!да;
      if (М.фигура && М.фигура.visible !== н) М.фигура.visible = н;
      if (М.ракета && М.ракета.visible !== н) М.ракета.visible = н;
      /* Рубашка не показывается вместе с фигурой: её сняли по слову
         владельца (см. «РУБАШКА ВОКРУГ ФИГУРЫ СНЯТА»). Гасим всегда. */
      if (М.поле && М.поле.visible) М.поле.visible = false;
    },
    /* Победа снаружи: финал спрашивает, стоит ли уже корабль, и
       показывает вход только когда есть куда входить. Второй вызов с
       доводом ставит победу руками - им пользуются проверки. */
    "победа": function (да) {
      if (да != null) { победа = да ? 1 : 0; if (!да) превращение = 0; }
      return превращение;
    },
    "замер": function () {
      if (!собрано) return { "собрано": false };
      return {
        "собрано": true,
        "видно": !!М.корень.visible,
        "победа": победа,
        "превращение": +превращение.toFixed(3),
        "ракета": !!М.ракета,
        /* Приёмке нужно видеть оба поля числом: они появляются по ленте
           и на снимке одной доли их легко не застать. */
        "поле": М.uАльфаПоля ? +М.uАльфаПоля.value.toFixed(3) : null,
        "полеПодогнано": полеПодогнано,
        "полеРазмер": М.поле ? [+М.поле.scale.x.toFixed(2), +(М.поле.scale.y * 3).toFixed(2),
                                +М.поле.position.y.toFixed(2)] : null,
        "обруч": М.обруч ? !!М.обруч.visible : false,
        "пол": +М.uАльфаПол.value.toFixed(3),
        "цилиндр": +М.uАльфаЦил.value.toFixed(3),
        "дымка": +М.uАльфаДым.value.toFixed(3),
        "точек": М.пыль ? М.пыль.geometry.attributes.position.count : 0,
        "место": [М.корень.position.x, М.корень.position.y, М.корень.position.z]
      };
    }
  };
})(window, document);
