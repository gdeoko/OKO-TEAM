/* Rocket VPN. Опознаватели: приборная разметка поверх объёмного мира.

   ЧТО ЭТО И ОТКУДА. Владелец показал кадры igloo.inc и сказал: «текст как
   у них крутой с какими-то опознавателями крутыми». На их кадрах поверх
   каждого предмета лежит тонкая приборная разметка: крестики в точках
   на самом предмете, волосяные линии между ними, номера у крестиков и
   подписи моноширинным вроде PORTFOLIO_CO_01, TEMP 35.42, D 06.28.2024,
   CLICK TO EXPLORE с подчёркиванием.

   ЗАЧЕМ ЭТО РАБОТАЕТ. Разметка делает предмет ИЗМЕРЯЕМЫМ. Пока картинка
   просто красивая, глаз скользит мимо; как только на ней появляются
   точки съёма и показания, мозг читает её как настоящий объект, за
   которым наблюдают приборы. Это тот же приём, что на кадрах с
   телеметрией: смотреть становится интереснее, чем на ту же картинку без
   единой цифры.

   ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: ПОКАЗАНИЯ НАСТОЯЩИЕ. Ни одно число здесь
   не выдумано и не крутится случайно. Скорость это настоящая скорость
   камеры в мировых единицах в секунду, дальность это настоящее
   расстояние до станции акта, доля это доля хода акта, счёт блоков это
   счёт блоков. Выдуманная телеметрия читается как оформление и
   обесценивает приём; настоящая держит доверие к остальному сайту.

   КАК УСТРОЕНО. Точки объявлены в МЕСТНЫХ координатах акта, то есть в
   смещениях от его станции на кривой камеры. Каждый кадр точка
   переводится в мировые, проецируется камерой в экранные и записывается
   в SVG. SVG выбран нарочно: волосяная линия в один пиксель и крестик
   рисуются им точно и дёшево, а тексту достаётся настоящий шрифт с
   кернингом, чего не даст ни канва, ни текстура.

   ЧЕГО ТУТ НЕТ. Ни одного замера раскладки: положение берётся у камеры
   счётом, размер кадра у окна. Разметка не ловит касания
   (pointer-events: none), кроме подписи «нажми», у которой своё гнездо.

   Разметка идёт ТОЛЬКО у видимого акта: держать шесть наборов на всех
   актах разом значит платить за пять невидимых. */
(function (g, d) {
  "use strict";

  var NS = "http://www.w3.org/2000/svg";

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }

  /* ── Наборы точек по актам ────────────────────────────────────

     Смещения даны от станции акта. Числа подобраны по месту предмета:
     купол стоит правее на 3.2 при радиусе 2.3, тоннель идёт по оси
     взгляда, у выхода точки лежат на кольце станций.

     «код» это подпись сверху набора, «строки» это показания. Показание
     объявляется именем величины, а не числом: число берётся живьём
     функцией ниже. */
  /* ТОЧКА ЗАДАЁТСЯ ДОЛЯМИ ГАБАРИТНОЙ КОРОБКИ ПРЕДМЕТА, А НЕ СМЕЩЕНИЕМ В
     ЕДИНИЦАХ. Первый заход задавал смещения от станции акта числами, и
     на кадре разметка повисла выше купола: у купола свой сдвиг вправо на
     широком экране, свой масштаб на узком, и попасть в него постоянными
     числами нельзя вовсе.

     Теперь у набора есть «цель» - имя предмета в сцене. Разметка находит
     его, снимает НАСТОЯЩУЮ габаритную коробку и ставит точки долями от
     её середины: [-1..1] по каждой оси. Купол уехал вправо, вырос на
     телефоне, сменил радиус - точки едут вместе с ним сами.

     Коробка снимается один раз на построение набора, а не каждый кадр:
     обход поддерева ради габаритов стоит дорого, а предмет акта за акт
     своих размеров не меняет. */
  var НАБОРЫ = {
    "станция": {
      цель: "кладка",
      сфера: true,
      код: "СТАНЦИЯ_LUNA_01",
      точки: [
        { д: [-0.62, 0.42, 0.44], н: "28" },
        { д: [0.10, 0.88, -0.10], н: "27" },
        { д: [0.74, 0.34, 0.30], н: "49" },
        { д: [-0.44, -0.30, 0.72], н: "22" },
        { д: [0.58, -0.36, 0.52], н: "27" }
      ],
      связи: [[0, 1], [1, 2], [0, 3], [3, 4], [4, 1]],
      строки: ["дальность", "доля"]
    },
    "прокол": {
      цель: "тоннель",
      код: "КАНАЛ_ПРОКОЛ",
      точки: [
        { д: [-0.70, 0.52, -0.20], н: "01" },
        { д: [0.68, 0.40, -0.46], н: "02" },
        { д: [-0.46, -0.66, -0.70], н: "03" },
        { д: [0.52, -0.50, -0.88], н: "04" }
      ],
      связи: [[0, 1], [1, 2], [2, 3]],
      строки: ["скорость", "доля"]
    },
    "выход": {
      цель: "акт-выход",
      код: "ТОЧКА_ВЫХОДА",
      точки: [
        { д: [-0.72, 0.28, 0.30], н: "NL" },
        { д: [0.04, 0.70, -0.24], н: "PL" },
        { д: [0.70, 0.16, 0.34], н: "RU" }
      ],
      связи: [[0, 1], [1, 2]],
      строки: ["дальность", "доля"]
    }
  };

  /* ── Живые показания ──────────────────────────────────────────
     Каждое отдаёт готовую строку. Ширина знакоместа у моноширинного
     одна, поэтому показание дополняется нулями слева до постоянной
     длины: иначе строка дёргалась бы при переходе через разряд. */
  function нулями(ч, знаков, дробных) {
    var с = (dробных(ч, dробных)).toString();
    var т = с.split(".");
    while (т[0].length < знаков) т[0] = "0" + т[0];
    return т.join(".");
  }
  function dробных(ч, n) { return n ? +ч.toFixed(n) : Math.round(ч); }

  function показание(имя, акт, доля) {
    var W = g.RV_WORLD;
    try {
      if (имя === "скорость" && W && W["скорость"]) {
        var в = W["скорость"]()["вектор"];
        var с = в ? Math.sqrt(в[0] * в[0] + в[1] * в[1] + в[2] * в[2]) : 0;
        return "СКОР  " + нулями(с, 3, 1);
      }
      if (имя === "дальность" && W && W["доСтанции"]) {
        return "ДАЛЬН " + нулями(W["доСтанции"](акт) || 0, 3, 1);
      }
      if (имя === "доля") return "ХОД   " + нулями(доля * 100, 3, 0) + "%";
      if (имя === "блоков") {
        var н = (g.RV_СТАНЦИЯ && g.RV_СТАНЦИЯ["замер"]) ? g.RV_СТАНЦИЯ["замер"]()["блоков"] : null;
        return "БЛОК  " + (н == null ? "---" : нулями(н, 3, 0));
      }
    } catch (e) {}
    return "";
  }

  /* ── Разметка ─────────────────────────────────────────────────*/
  var коробки = {};        /* имя акта -> габариты цели */
  var корень = null, слой = null;
  var узлы = null;          /* текущий набор в SVG */
  var текущий = null;       /* имя акта, чей набор построен */
  var живДоля = 0;
  var _v = null;

  function создать() {
    if (корень) return корень;
    корень = d.createElementNS(NS, "svg");
    корень.setAttribute("class", "rv-опозн");
    корень.setAttribute("aria-hidden", "true");
    слой = d.createElementNS(NS, "g");
    корень.appendChild(слой);
    var гнездо = d.getElementById("rvМирГнездо") || d.body;
    гнездо.appendChild(корень);
    return корень;
  }

  function очистить() {
    while (слой.firstChild) слой.removeChild(слой.firstChild);
    узлы = null;
  }

  /* Габаритная коробка цели. Ищем предмет по имени в сцене и снимаем его
     мировые границы. Ноль означает «цель ещё не собрана»: акты строят
     свои предметы лениво, и до первого показа находить нечего. */
  /* Габариты, объявленные самим актом. Это надёжнее габаритной коробки
     везде, где предмет ЖИВЁТ: у купола блоки расходятся по радиусу весь
     акт, и коробка растёт вместе с ними, унося точки съёма в небо. Акт
     же отдаёт то, что не меняется - середину и радиус в покое. */
  var ОТ_АКТА = {
    "станция": function () {
      var г = (g.RV_СТАНЦИЯ && g.RV_СТАНЦИЯ["габариты"]) ? g.RV_СТАНЦИЯ["габариты"]() : null;
      if (!г) return null;
      var р = г["радиус"];
      return { ц: г["центр"], р: [р, р, р] };
    }
  };

  function коробка(имяЦели, имяАкта) {
    if (ОТ_АКТА[имяАкта]) {
      var своё = ОТ_АКТА[имяАкта]();
      if (своё) return своё;
    }
    var W = g.RV_WORLD;
    if (!W || !W["мир"]) return null;
    var мир = W["мир"]();
    if (!мир || !мир.scene) return null;
    var T = мир.T;
    var цель = null;
    мир.scene.traverse(function (о) { if (!цель && о.name === имяЦели) цель = о; });
    if (!цель) return null;
    try {
      var б = new T.Box3().setFromObject(цель);
      if (!isFinite(б.min.x) || !isFinite(б.max.x)) return null;
      var ц = б.getCenter(new T.Vector3());
      var р = б.getSize(new T.Vector3()).multiplyScalar(0.5);
      if (!(р.x > 0.001)) return null;
      return { ц: [ц.x, ц.y, ц.z], р: [р.x, р.y, р.z] };
    } catch (e) { return null; }
  }

  function построить(имя) {
    var н = НАБОРЫ[имя];
    очистить();
    текущий = имя;
    if (!н) return;
    /* Коробка снимается на построение. Не нашли - набор не строим и
       попробуем на следующем кадре: предмет мог ещё не собраться. */
    коробки[имя] = коробка(н.цель, имя);
    if (!коробки[имя]) { текущий = null; return; }
    узлы = { связи: [], точки: [], подписи: [], код: null, строки: [] };

    /* Линии идут ПЕРВЫМИ: крестики и подписи обязаны лежать поверх. */
    for (var с = 0; с < н.связи.length; с++) {
      var л = d.createElementNS(NS, "line");
      л.setAttribute("class", "rv-опозн-линия");
      слой.appendChild(л);
      узлы.связи.push(л);
    }
    for (var i = 0; i < н.точки.length; i++) {
      var гр = d.createElementNS(NS, "g");
      гр.setAttribute("class", "rv-опозн-точка");
      var к1 = d.createElementNS(NS, "line");
      var к2 = d.createElementNS(NS, "line");
      к1.setAttribute("x1", -4); к1.setAttribute("x2", 4);
      к1.setAttribute("y1", 0); к1.setAttribute("y2", 0);
      к2.setAttribute("x1", 0); к2.setAttribute("x2", 0);
      к2.setAttribute("y1", -4); к2.setAttribute("y2", 4);
      гр.appendChild(к1); гр.appendChild(к2);
      var т = d.createElementNS(NS, "text");
      т.setAttribute("x", 8); т.setAttribute("y", -6);
      т.textContent = н.точки[i].н;
      гр.appendChild(т);
      слой.appendChild(гр);
      узлы.точки.push(гр);
    }
    /* Код набора и показания стоят у первой точки блоком. */
    узлы.кодГр = d.createElementNS(NS, "g");
    узлы.кодГр.setAttribute("class", "rv-опозн-код");
    var кт = d.createElementNS(NS, "text");
    кт.textContent = н.код;
    узлы.кодГр.appendChild(кт);
    узлы.код = кт;
    for (var s = 0; s < н.строки.length; s++) {
      var ст = d.createElementNS(NS, "text");
      ст.setAttribute("class", "rv-опозн-строка");
      ст.setAttribute("y", 14 * (s + 1));
      узлы.кодГр.appendChild(ст);
      узлы.строки.push(ст);
    }
    /* Волосяная черта под блоком: она у них есть на каждой подписи. */
    var черта = d.createElementNS(NS, "line");
    черта.setAttribute("class", "rv-опозн-черта");
    черта.setAttribute("x1", 0); черта.setAttribute("x2", 128);
    черта.setAttribute("y1", 14 * (н.строки.length + 1) - 4);
    черта.setAttribute("y2", 14 * (н.строки.length + 1) - 4);
    узлы.кодГр.appendChild(черта);
    слой.appendChild(узлы.кодГр);
  }

  /* Кадр разметки. Считает только числа и пишет атрибуты. */
  function кадр(имя, доля) {
    var W = g.RV_WORLD;
    if (!W || !W["готов"] || !W["готов"]()) return;
    var мир = W["мир"]();
    if (!мир || !мир.cam) return;
    var T = мир.T;
    if (!_v) _v = new T.Vector3();

    if (текущий !== имя) построить(имя);
    var н = НАБОРЫ[имя];
    if (!н || !узлы) return;

    /* Разметка приходит к середине акта и уходит к его концу: на самом
       въезде она мешала бы читать заголовок, а на выезде висела бы над
       уже уехавшим предметом. */
    var сила = Math.min(зажать((доля - 0.10) / 0.16, 0, 1), зажать((0.88 - доля) / 0.14, 0, 1));
    живДоля += (сила - живДоля) * 0.14;
    корень.style.opacity = живДоля.toFixed(3);
    if (живДоля < 0.01) { корень.style.visibility = "hidden"; return; }
    корень.style.visibility = "visible";

    var ш = g.innerWidth || 1, в = g.innerHeight || 1;
    корень.setAttribute("viewBox", "0 0 " + ш + " " + в);

    /* Точка = середина габаритной коробки предмета плюс доля её
       полуразмера. Коробка снята при построении набора. */
    var кор = коробки[имя];
    if (!кор) { построить(имя); кор = коробки[имя]; if (!кор || !узлы) return; }

    var эк = [], видн = [];
    for (var i = 0; i < н.точки.length; i++) {
      var д = н.точки[i].д;
      if (н.сфера) {
        /* Полусфера: направление нормируется, поэтому точка садится
           ровно НА поверхность, а не в угол воображаемой коробки. */
        var дл = Math.sqrt(д[0] * д[0] + д[1] * д[1] + д[2] * д[2]) || 1;
        _v.set(кор.ц[0] + кор.р[0] * д[0] / дл,
               кор.ц[1] + кор.р[1] * Math.abs(д[1]) / дл,
               кор.ц[2] + кор.р[2] * д[2] / дл);
      } else {
        _v.set(кор.ц[0] + кор.р[0] * д[0],
               кор.ц[1] + кор.р[1] * д[1],
               кор.ц[2] + кор.р[2] * д[2]);
      }
      _v.project(мир.cam);
      /* z вне отрезка отсечения означает точку за спиной камеры: такую
         рисовать нельзя, проекция даёт зеркальный отпечаток. */
      var ок = _v.z > -1 && _v.z < 1;
      var x = (_v.x * 0.5 + 0.5) * ш, y = (-_v.y * 0.5 + 0.5) * в;
      эк.push([x, y]); видн.push(ок && x > -60 && x < ш + 60 && y > -60 && y < в + 60);
      var гр = узлы.точки[i];
      гр.setAttribute("transform", "translate(" + x.toFixed(1) + "," + y.toFixed(1) + ")");
      гр.style.display = видн[i] ? "" : "none";
    }
    for (var c = 0; c < н.связи.length; c++) {
      var a = н.связи[c][0], b = н.связи[c][1];
      var л = узлы.связи[c];
      if (!видн[a] || !видн[b]) { л.style.display = "none"; continue; }
      л.style.display = "";
      л.setAttribute("x1", эк[a][0].toFixed(1)); л.setAttribute("y1", эк[a][1].toFixed(1));
      л.setAttribute("x2", эк[b][0].toFixed(1)); л.setAttribute("y2", эк[b][1].toFixed(1));
    }
    /* Блок подписи держится первой ВИДИМОЙ точки и отступает от неё. */
    var я = -1;
    for (var q = 0; q < видн.length; q++) if (видн[q]) { я = q; break; }
    if (я < 0) { узлы.кодГр.style.display = "none"; return; }
    узлы.кодГр.style.display = "";
    var сдx = зажать(эк[я][0] + 26, 12, ш - 150);
    var сдy = зажать(эк[я][1] - 34, 26, в - 80);
    узлы.кодГр.setAttribute("transform", "translate(" + сдx.toFixed(1) + "," + сдy.toFixed(1) + ")");
    for (var s2 = 0; s2 < узлы.строки.length; s2++) {
      узлы.строки[s2].textContent = показание(н.строки[s2], имя, доля);
    }
  }

  /* ── Подписка на плёнку ───────────────────────────────────────*/
  var повешено = false;
  function повесить() {
    if (повешено) return true;
    if (!g.RV_MOTION || !g.RV_MOTION["слушать"]) return false;
    повешено = true;
    создать();
    for (var имя in НАБОРЫ) {
      (function (и) {
        g.RV_MOTION["слушать"](и, function (д) {
          /* Ведёт разметку только тот акт, который сейчас идёт. */
          if (д <= 0.002 || д >= 0.998) {
            if (текущий === и) { корень.style.visibility = "hidden"; живДоля = 0; }
            return;
          }
          кадр(и, д);
        });
      })(имя);
    }
    return true;
  }

  function старт() {
    if (повесить()) return;
    var n = 0;
    var t = g.setInterval(function () {
      if (повесить() || ++n > 40) g.clearInterval(t);
    }, 300);
  }

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", старт);
  else старт();

  g.RV_ОПОЗН = { "наборы": function () { var с = []; for (var k in НАБОРЫ) с.push(k); return с; } };
})(window, document);
