/* ЛЕНТА ЛИСТАЕТСЯ ВНУТРИ КОНТЕЙНЕРА, А НЕ ДОКУМЕНТОМ.

   ЗАЧЕМ. Владелец с телефона, дважды одним и тем же словами: «начинаю
   листать вниз, у меня строка поиска в браузере уходит вверх, а снизу
   чёрная полоса появляется, типа полноэкранный режим врубается» и
   «можно сделать, чтобы строка поиска сверху никогда не уходила? как
   только я вниз начинаю листать, она уходит и размер сайта меняется».

   Я ответила, что страница не может запретить браузеру прятать адресную
   строку, и это решает сам Chrome. Ответ был неверный, владелец сразу
   назвал встречный пример: «на сайте igloo.inc такого нету нигде, я
   листаю также вниз и всё нормально».

   Он прав, и вот в чём дело. Chrome прячет панель не на любой
   прокрутке, а только когда листают КОРНЕВОЙ прокрутчик документа.
   Прокрутка внутри обычного элемента с `overflow-y: auto` панель не
   трогает вовсе: браузеру нечего сворачивать, документ стоит на месте.
   Это ровно то, что делает igloo.inc, и что теперь делаем мы.

   Отсюда весь размер сцены становится постоянным: контейнер прибит
   `position: fixed; inset: 0`, его высота равна видимой части окна и не
   меняется никогда, потому что панель никуда не уезжает. Уходит и
   чёрная полоса снизу, и скачок композиции на первом же движении
   пальца - две беды, которые до этого лечились подбором единиц `svh`,
   `dvh`, `lvh` и не вылечились ни одной из них.

   ЧТО ЭТО ЗА ФАЙЛ. Прокрутку читают десять модулей сайта: камера,
   рейка прогресса, меню, кнопки панели, слова. Если каждый пойдёт к
   контейнеру своей строкой, то однажды один из них останется на
   `window.scrollY` и будет тихо считать ноль. Поэтому дверь одна, и она
   здесь. Файл грузится ПЕРВЫМ и без `defer`: к нему обращаются с первой
   же строки ядра.

   Узел ищется лениво и каждый раз проверяется на связь с документом:
   на момент разбора этого файла плёнки в разметке ещё нет. */
(function (g, d) {
  "use strict";
  if (g.RV_СКРОЛЛ) return;

  var узел = null;

  function К() {
    if (узел && узел.isConnected) return узел;
    узел = d.querySelector(".rv-плёнка");
    return узел;
  }

  /* Запасной путь на случай, если плёнки в разметке нет вовсе: тогда
     сайт листается документом, как раньше. Молча отдавать нули нельзя -
     это остановило бы камеру. */
  function y() {
    var к = К();
    return к ? к.scrollTop : (g.scrollY || g.pageYOffset || 0);
  }

  function высота() {
    var к = К();
    if (к && к.clientHeight > 1) return к.clientHeight;
    return g.innerHeight || d.documentElement.clientHeight || 800;
  }

  function лента() {
    var к = К();
    if (к && к.scrollHeight > 1) return к.scrollHeight;
    return d.documentElement.scrollHeight || 0;
  }

  /* Верх элемента в системе координат ленты. Контейнер прибит к окну,
     значит его верхняя кромка совпадает с верхом окна, и прямоугольник
     от браузера складывается с положением ленты так же, как раньше
     складывался с `scrollY`. */
  function верх(эл) {
    if (!эл || !эл.getBoundingClientRect) return 0;
    return эл.getBoundingClientRect().top + y();
  }

  /* ══════════════════════════════════════════════════════════════
     СВОЙ СЧЁТЧИК ХОДА ВМЕСТО РОДНОЙ ПРОКРУТКИ

     Владелец: «если я сильно листнул вниз, не должно быть такого, что
     всё потом автоматически до конца сайта с пропуском всех анимаций
     ушло. Я сейчас быстро пролистал вниз один раз, и у меня всё
     пропустило: от дома сразу резко всё произошло и сразу экран
     последний с панелью управления. Пролетел мигом весь сайт».

     Причина была записана в нашем же коде за полгода до жалобы, в
     комментарии к доводчику покоя (rv-motion.js): «У igloo НЕТ родной
     прокрутки страницы: колесо идёт через свой счётчик, и цель
     физически не может убежать далеко. У нас прокрутка родная, палец
     двигает её мгновенно на сколько угодно».

     Дальше всё сходится само. Резкий свайп отдаёт ленту родной инерции
     браузера, та уносит её на двадцать экранов за полсекунды, камера с
     поводком и пределом шага догоняет, а доводчик покоя (он включается
     через 0.15 с тишины) переносит её в конец за четверть секунды. Весь
     фильм пролетает, и ни одной сцены человек не видит. Камера тут ни
     при чём, она честно едет туда, куда уехала лента.

     Значит лечить надо ленту, а не камеру. Родной прокрутки у плёнки
     больше нет (`overflow: hidden`, `touch-action: none` в стилях),
     ход ведёт этот счётчик:

       палец      ведёт ленту один к одному, как родная прокрутка;
       отпустил   короткий довыкат с ОГРАНИЧЕННОЙ начальной скоростью;
       колесо     шаг как есть, но не больше половины экрана за тик;
       клавиши    стрелки, страницы, пробел, начало и конец;
       переход    плавный ход к месту для меню и рейки.

     Считаем в числах: довыкат не длиннее ПРЕДЕЛ_СКОРОСТИ экранов в
     секунду с затуханием, то есть один жест двигает ленту примерно на
     экран с небольшим. Лента длиной в двадцать четыре экрана за один
     взмах больше не кончается.

     Сглаживание камеры при этом НЕ дублируется: счётчик ведёт саму
     ленту, а массу движения по-прежнему даёт rv-motion.js двумя своими
     подтяжками. Две инерции подряд дали бы вату.
     ══════════════════════════════════════════════════════════════ */
  var ЦЕЛЬ = null;          /* куда лента едет; null - ещё не считали */
  var СКОРОСТЬ = 0;         /* точек в секунду, знак это направление */
  var ХОД = null;           /* плавный переход: {от, до, начало, длина} */
  var кадрЖдёт = 0;
  var прошлоеВремя = 0;

  var ПРЕДЕЛ_СКОРОСТИ = 2.0;   /* экранов в секунду на отпускании пальца */
  var ЗАТУХАНИЕ = 3.4;         /* во столько раз скорость падает за секунду */
  var ПРЕДЕЛ_КОЛЕСА = 0.5;     /* экранов за один тик колеса */
  var ПОРОГ_ПОКОЯ = 12;        /* точек в секунду: ниже считаем, что встали */

  function часы() {
    return (g.performance && g.performance.now) ? g.performance.now() : Date.now();
  }

  function предел() {
    var у = К();
    if (!у) return 0;
    return Math.max(0, у.scrollHeight - у.clientHeight);
  }

  function зажатьY(в) {
    var п = предел();
    return в < 0 ? 0 : (в > п ? п : в);
  }

  function поставить(в) {
    var у = К();
    if (!у) return;
    ЦЕЛЬ = зажатьY(в);
    у.scrollTop = ЦЕЛЬ;
  }

  function разбудить() {
    if (кадрЖдёт) return;
    прошлоеВремя = часы();
    кадрЖдёт = g.requestAnimationFrame(тик);
  }

  function тик(t) {
    кадрЖдёт = 0;
    var dt = (t - прошлоеВремя) / 1000;
    прошлоеВремя = t;
    if (!(dt > 0)) dt = 1 / 60;
    if (dt > 0.1) dt = 0.1;   /* вкладка была спрятана - не прыгаем */

    if (ХОД) {
      var д = (t - ХОД.начало) / ХОД.длина;
      if (д >= 1) { поставить(ХОД.до); ХОД = null; }
      else {
        /* Плавный ход мягко тормозит у цели: резкая остановка читается
           как обрыв, а не как приезд. */
        var с = 1 - Math.pow(1 - д, 3);
        поставить(ХОД.от + (ХОД.до - ХОД.от) * с);
        разбудить();
      }
      return;
    }

    if (Math.abs(СКОРОСТЬ) > ПОРОГ_ПОКОЯ) {
      поставить((ЦЕЛЬ == null ? y() : ЦЕЛЬ) + СКОРОСТЬ * dt);
      СКОРОСТЬ /= Math.pow(ЗАТУХАНИЕ, dt);
      /* Доехали до кромки - гасим сразу, иначе счётчик будет молотить
         вхолостую, упёршись в ноль или в конец. */
      if (ЦЕЛЬ <= 0 || ЦЕЛЬ >= предел()) СКОРОСТЬ = 0;
      else разбудить();
    } else {
      СКОРОСТЬ = 0;
    }
  }

  /* ── ЗАМКИ ЛЕНТЫ УВАЖАЕМ ЗДЕСЬ, А НЕ ТОЛЬКО В СТИЛЯХ ───────────
     Пока лента листалась браузером, её запирал `overflow: hidden` на
     плёнке, и этого хватало. Свой счётчик такой замок не видит: он
     пишет `scrollTop` напрямую, то есть прокрутил бы ленту прямо через
     запрет. А запретов два, и оба настоящие: вступление (посадка на
     Луну, пять с половиной секунд) и разбор внутри глыбы, где мы стоим
     в предмете, а не на ленте. */
  function заперто() {
    var к = d.documentElement && d.documentElement.classList;
    return !!(к && (к.contains("рв-замок") || к.contains("рв-внутри")));
  }

  function двинуть(на) {
    ХОД = null;
    поставить((ЦЕЛЬ == null ? y() : ЦЕЛЬ) + на);
  }

  function к(цель, плавно) {
    var у = К();
    var т = Math.round(+цель || 0);
    if (!у) { g.scrollTo(0, т); return; }
    СКОРОСТЬ = 0;
    if (!плавно) { ХОД = null; поставить(т); return; }
    ХОД = { от: y(), до: зажатьY(т), начало: часы(), длина: 620 };
    разбудить();
  }

  /* ── ПАЛЕЦ ─────────────────────────────────────────────────────
     Во время движения лента идёт за пальцем один к одному: иначе жест
     перестаёт быть прокруткой и начинает ощущаться как перетаскивание
     чего-то вязкого. Скорость считаем по последним двум точкам, а не по
     всему жесту: человек тормозит перед отпусканием, и средняя скорость
     за жест отправила бы ленту дальше, чем он просил. */
  var палец = null;

  function касаниеНачал(е) {
    if (заперто()) { палец = null; return; }
    if (!е.touches || е.touches.length !== 1) { палец = null; return; }
    СКОРОСТЬ = 0; ХОД = null;
    if (ЦЕЛЬ == null) ЦЕЛЬ = y();
    палец = { y: е.touches[0].clientY, t: часы(), v: 0 };
  }

  function касаниеВёл(е) {
    if (!палец || !е.touches || е.touches.length !== 1) return;
    var сейчас = е.touches[0].clientY;
    var dy = палец.y - сейчас;
    var t = часы();
    var dt = (t - палец.t) / 1000;
    if (dt > 0.001) палец.v = dy / dt;
    палец.y = сейчас; палец.t = t;
    двинуть(dy);
  }

  function касаниеСнял() {
    if (!палец) return;
    var v = палец.v;
    var тихо = часы() - палец.t;
    палец = null;
    /* Палец постоял перед тем, как оторваться - это не бросок, а
       остановка на месте, и довыката быть не должно. Иначе лента
       трогалась бы сама после того, как человек её удержал. */
    if (тихо > 90) v = 0;
    var п = ПРЕДЕЛ_СКОРОСТИ * высота();
    СКОРОСТЬ = Math.max(-п, Math.min(п, v));
    if (Math.abs(СКОРОСТЬ) > ПОРОГ_ПОКОЯ) разбудить();
  }

  /* ── КОЛЕСО ────────────────────────────────────────────────────
     Строки и страницы приводим к точкам: мышь отдаёт три разных режима,
     и без пересчёта страничный режим двигал бы ленту на единицу. */
  function колесо(е) {
    if (заперто()) { try { е.preventDefault(); } catch (e0) {} return; }
    var d1 = е.deltaY || 0;
    if (е.deltaMode === 1) d1 *= 16;
    else if (е.deltaMode === 2) d1 *= высота();
    var п = ПРЕДЕЛ_КОЛЕСА * высота();
    СКОРОСТЬ = 0;
    двинуть(Math.max(-п, Math.min(п, d1)));
    try { е.preventDefault(); } catch (e) {}
  }

  function клавиша(е) {
    if (заперто()) return;
    var ц = е.target;
    if (ц && ц.closest && ц.closest("input,textarea,select,[contenteditable]")) return;
    var в = высота(), на = null;
    switch (е.key) {
      case "ArrowDown": на = в * 0.18; break;
      case "ArrowUp": на = -в * 0.18; break;
      case "PageDown": case " ": case "Spacebar": на = в * 0.85; break;
      case "PageUp": на = -в * 0.85; break;
      case "Home": к(0, true); try { е.preventDefault(); } catch (e1) {} return;
      case "End": к(предел(), true); try { е.preventDefault(); } catch (e2) {} return;
      default: return;
    }
    СКОРОСТЬ = 0;
    двинуть(на);
    try { е.preventDefault(); } catch (e3) {}
  }

  function завести() {
    var у = К();
    if (!у) return false;
    ЦЕЛЬ = у.scrollTop;
    у.addEventListener("touchstart", касаниеНачал, { passive: true });
    у.addEventListener("touchmove", касаниеВёл, { passive: true });
    у.addEventListener("touchend", касаниеСнял, { passive: true });
    у.addEventListener("touchcancel", касаниеСнял, { passive: true });
    у.addEventListener("wheel", колесо, { passive: false });
    d.addEventListener("keydown", клавиша, { passive: false });
    return true;
  }

  if (!завести()) {
    d.addEventListener("DOMContentLoaded", завести, { once: true });
  }

  /* Событие прокрутки у элемента не всплывает до окна, поэтому слушать
     надо именно контейнер. Подписка откладывается до появления узла:
     модули объявляются раньше разметки. */
  function слушать(фн, опц) {
    var о = опц || { passive: true };
    var у = К();
    if (у) { у.addEventListener("scroll", фн, о); return; }
    d.addEventListener("DOMContentLoaded", function () {
      var п = К();
      (п || g).addEventListener("scroll", фн, о);
    }, { once: true });
  }

  g.RV_СКРОЛЛ = {
    "узел": К,
    "y": y,
    "высота": высота,
    "лента": лента,
    "верх": верх,
    "к": к,
    "слушать": слушать
  };
})(window, document);
