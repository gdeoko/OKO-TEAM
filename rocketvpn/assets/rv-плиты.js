/* Rocket VPN. Плиты карточек как часть сцены.

   ЗАЧЕМ. Слой слов лежал поверх холста наклейкой: у мира есть свет,
   ход камеры и глубина, у карточек не было ничего из этого. Владелец
   назвал это прямо: «текст как обычное наложение поверх сайта». Здесь
   карточки получают три вещи, которые есть у любого предмета в кадре:
     · свет сцены: точка главного источника акта (планета, щит, ворота,
       кольцо) проецируется на экран и уходит в вёрстку переменными,
       по которым плиты подсвечиваются со стороны источника;
     · инерцию: боковой ход и крен камеры дают слою слов и карточкам
       разный сдвиг, и между ними появляется глубина;
     · на полной ступени под каждой карточкой в самом мире стоит
       стеклянная плита, в которой едет отражение неба и бликуют
       софтбоксы плёнки. Плита рисуется тем же холстом, тем же
       ореолом, той же инверсией днём, и потому принадлежит кадру.

   ПОЧЕМУ СВОЙ ЦИКЛ, А НЕ ПОДПИСКА НА АКТ. Свет и инерция нужны сразу
   двум актам на перегоне (один уходит, другой подъезжает), а подписка
   в rv-motion.js идёт по одному акту. Свой кадр раз в rAF с десятком
   умножений матриц стоит ничего, а порядок с кадром мира ему не важен:
   он читает камеру, которую мир уже поставил.

   ЦЕНА ПО СТУПЕНЯМ. 0: модуль не поднимается вовсе, вёрстка живёт
   значениями по умолчанию. 1: переменные света и инерции, это пять
   записей стиля на кадр. 2: плюс плиты в мире, один instanced-вызов
   до 24 плоскостей и замер до восьми прямоугольников на кадр. */
(function (g, d) {
  "use strict";

  var W = null, T = null;
  var ступень = 0;
  var тихо = false;
  try {
    тихо = !!(g.matchMedia && g.matchMedia("(prefers-reduced-motion: reduce)").matches);
  } catch (e0) {}

  var СЕЛЕКТОР_КАРТОЧЕК = ".rv-станции li, .rv-тех li, .rv-док, .rv-орбита, .rv-кн-cdn";
  var МАКС_ПЛИТ = 24;          /* плит в мире на все акты */
  var МАКС_НА_АКТ = 8;         /* замеров прямоугольников на акт за кадр */
  var ГЛУБИНА = 14;            /* плита стоит перед объективом на этом расстоянии */
  var ГЛУБИНА_ТЕНИ = 15.2;     /* тёмная подложка глубже: от неё и берётся глубина */

  /* Главный источник света каждого акта. Точка задана в координатах
     КОРНЯ акта, а корень акты уже ставят туда, где стоит предмет:
     рубка держит свой корень в (5.3, 0.9, 0), то есть на щите, и
     чертёжное смещение поверх этого удваивало сдвиг (свет уезжал за
     правую кромку кадра, замерено). Поэтому везде начало корня; у
     выхода планета ищется сферой, у прокола точка берётся по взгляду
     камеры, у плоского периметра источника в мире нет. Цвет: индиго
     везде, кроме двух мест, где акт носит свой цвет: янтарь периметра
     и бирюза ворот Rocket CDN. */
  var ИСТОЧНИКИ = {
    "оболочка": { точка: [0, 0, 0],       цвет: "138,156,255", огонь: 0x8A9CFF },
    "прокол":   { поВзгляду: 40,          цвет: "138,156,255", огонь: 0x8A9CFF },
    "выход":    { точка: [0, -7, 0], сфера: true, цвет: "138,156,255", огонь: 0x8A9CFF },
    "рубка":    { точка: [0, 0, 0],       цвет: "138,156,255", огонь: 0x6078D8 },
    "пуск":     { точка: [0, 0, 0],       цвет: "138,156,255", огонь: 0x8A9CFF },
    "стыковка": { точка: [0, 0, 0],       цвет: "48,168,216",  огонь: 0x30A8D8 },
    "периметр": { экран: [0.78, 0.35],    цвет: "255,154,74",  огонь: 0xFF6A3C }
  };

  function зажать(v, a, b) { return v < a ? a : (v > b ? b : v); }

  /* Подтягивание, не зависящее от частоты кадров: см. rv-act-exit.js. */
  function подтянуть(a, b, скорость, dt) {
    return a + (b - a) * (1 - Math.pow(1 - скорость, dt * 60));
  }

  /* ── Состояние ─────────────────────────────────────────────── */
  var акты = [];               /* { имя, узел, слой, вид, ист, точкаМира, карточки, есть } */
  var кадров = 0;
  var прошлое = 0;
  var прежняяКамера = null;
  var парX = 0, парY = 0, крен = 0;
  var парXбыл = "", парYбыл = "", кренБыл = "";
  var телефон = false;
  var день = false;

  /* Плиты в мире (ступень 2). */
  var плиты = null, тени = null, аВид = null, аОгонь = null, матПлит = null, матТени = null;
  var небо = null;
  var занято = 0;

  var в1 = null, в2 = null, в3 = null;

  function собратьАкты() {
    акты.length = 0;
    var узлы = d.querySelectorAll(".rv-акт[data-акт]");
    for (var i = 0; i < узлы.length; i++) {
      var имя = узлы[i].getAttribute("data-акт");
      акты.push({
        имя: имя,
        узел: узлы[i],
        слой: узлы[i].querySelector(".rv-слой"),
        вид: 0,
        ист: ИСТОЧНИКИ[имя] || null,
        точкаМира: null,
        корень: null,
        карточки: null,
        есть: false,
        свБыло: ""
      });
    }
  }

  /* Корень акта под гнездом. Гнездо держит корень акта и группу титров;
     корень узнаётся по числу потомков: у титра одна плоскость, у акта
     десятки узлов. Своего имени у корня нет, а просить акты объявлять
     его значит трогать шесть файлов ради одной точки. */
  function кореньАкта(имя) {
    if (!g.RV_WORLD || !g.RV_WORLD["гнездо"]) return null;
    var гн = null;
    try { гн = g.RV_WORLD["гнездо"](имя); } catch (e) { return null; }
    /* Пустое гнездо не корень: акт ещё не собран, и запомнить сейчас
       гнездо значит навсегда светить из точки станции вместо предмета.
       Поймано на рубке: свет уезжал за правую кромку кадра. */
    if (!гн || !гн.children.length) return null;
    /* Пока акт не собран, в гнезде может стоять только группа титров:
       у неё тоже один прямой ребёнок, и по числу детей её не отличить.
       Прогрев ядра знает, что уже собрано. */
    try {
      var пр = g.RV_WORLD["прогрев"] ? g.RV_WORLD["прогрев"]() : null;
      var сд = пр && пр["сделано"];
      if (сд) {
        var собран = false;
        /* Запись прогрева это пара [имя, мс]; имя лежит в нулевом поле. */
        for (var j = 0; j < сд.length; j++) {
          var з = сд[j] && сд[j].length !== undefined && typeof сд[j] !== "string" ? сд[j][0] : сд[j];
          if (з === "акт " + имя) { собран = true; break; }
        }
        if (!собран) return null;
      }
    } catch (eП) {}
    var лучший = null, макс = 0;
    for (var i = 0; i < гн.children.length; i++) {
      var n = 0;
      гн.children[i].traverse(function () { n++; });
      if (n > макс) { макс = n; лучший = гн.children[i]; }
    }
    return лучший;
  }

  /* Планета выхода. Её центр в координатах корня не равен чертёжному:
     акт панорамирует сцену и вкладывает её в свои группы. Надёжнее
     найти саму планету: это самая большая сфера под корнем. */
  function самаяБольшаяСфера(корень) {
    var лучший = null, макс = 0;
    корень.traverse(function (o) {
      var п = o.geometry && o.geometry.parameters;
      if (!п || typeof п.radius !== "number") return;
      var r = п.radius * Math.max(o.scale.x, 1e-6);
      if (r > макс) { макс = r; лучший = o; }
    });
    return лучший;
  }

  /* Мировая точка источника акта. Считается редко: корень акта на
     перегоне не движется, а гнездо при вызове переставляется заново
     (lookAt), и звать его каждый кадр незачем. */
  function обновитьТочку(a) {
    if (!a.ист) return;
    if (a.ист.поВзгляду) {
      if (!в1) в1 = new T.Vector3();
      W.cam.getWorldDirection(в1);
      a.точкаМира = (a.точкаМира || new T.Vector3()).copy(W.cam.position).addScaledVector(в1, a.ист.поВзгляду);
      return;
    }
    if (!a.ист.точка) return;
    if (!a.корень) a.корень = кореньАкта(a.имя);
    if (!a.корень) return;
    if (a.ист.сфера) {
      if (!a.сфера) a.сфера = самаяБольшаяСфера(a.корень);
      if (a.сфера) {
        a.точкаМира = a.сфера.getWorldPosition(a.точкаМира || new T.Vector3());
        return;
      }
    }
    a.точкаМира = (a.точкаМира || new T.Vector3()).fromArray(a.ист.точка);
    a.корень.localToWorld(a.точкаМира);
  }

  /* Видимость акта. Вёрстка считает --вид из --д, --подход и --уход, но
     прочитать готовое значение нельзя: вычисленный стиль отдаёт
     незарегистрированную переменную сырой строкой «min(clamp(...))», а
     не числом. Поэтому те же три числа берутся с инлайн-стиля секции
     (их пишет rv-motion.js) и складываются по той же формуле, что в
     rv.css. Меняется формула там - меняется и здесь. Чтение инлайн-стиля
     раскладки не трогает и идёт каждый кадр. */
  function зажать01(v) { return v < 0 ? 0 : (v > 1 ? 1 : v); }
  function прочитатьВид() {
    for (var i = 0; i < акты.length; i++) {
      var a = акты[i];
      var s = a.узел.style;
      var д = parseFloat(s.getPropertyValue("--д")) || 0;
      var подход = parseFloat(s.getPropertyValue("--подход")) || 0;
      var уходС = s.getPropertyValue("--уход");
      var уход = уходС === "" ? 1 : (parseFloat(уходС) || 0);
      var вход = Math.max(зажать01((д - 0.008) * 26), зажать01((подход - 0.28) * 2.6));
      if (a.имя === "видно") вход = 1;
      var выход = Math.max(зажать01((0.992 - д) * 26), зажать01((уход - 0.28) * 2.6));
      var v = Math.min(вход, выход);
      a.вид = v;
      if (v > 0.02 && !a.карточки) a.карточки = a.узел.querySelectorAll(СЕЛЕКТОР_КАРТОЧЕК);
    }
  }

  /* ── Плиты в мире ──────────────────────────────────────────── */

  /* Имена внутри шейдеров ЛАТИНИЦЕЙ: кириллица в GLSL не имя, и материал
     молча не собирается. Объяснения в комментариях рядом. */
  var ВЕРШИНЫ = [
    "attribute float aVid;",           /* видимость акта 0..1 */
    "attribute vec4 aOgon;",           /* rgb огня акта и его сила у этой плиты */
    "varying vec2 vUv;",
    "varying vec3 vPos;",              /* положение в осях камеры */
    "varying float vVid;",
    "varying vec4 vOgon;",
    "void main() {",
    "  vUv = uv; vVid = aVid; vOgon = aOgon;",
    "  vec4 p = modelViewMatrix * instanceMatrix * vec4(position, 1.0);",
    "  vPos = p.xyz;",
    "  gl_Position = projectionMatrix * p;",
    "}"
  ].join("\n");

  var ПЛИТА = [
    "uniform sampler2D nebo;",
    "uniform mat3 camRot;",            /* оси камеры в мире: отражение считается в мире */
    "uniform float neboRot;",          /* поворот сферы неба, она едет со временем */
    "uniform vec2 sdvig;",             /* дрейф отражения по положению камеры */
    "uniform float den;",              /* 1 днём: блики вполсилы */
    "uniform vec3 telo;",
    "uniform float teloA;",
    "varying vec2 vUv;",
    "varying vec3 vPos;",
    "varying float vVid;",
    "varying vec4 vOgon;",
    "void main() {",
    "  vec3 I = normalize(vPos);",
    /* Нормаль плиты смотрит в объектив; отражение взгляда от неё уходит
       в мир, и при повороте камеры небо в плите едет. Это и есть «свет
       сцены на плите»: плита показывает то, что у зрителя за спиной. */
    "  vec3 R = reflect(I, vec3(0.0, 0.0, 1.0));",
    "  vec3 Rw = camRot * R;",
    "  float c = cos(neboRot), s = sin(neboRot);",
    "  Rw = vec3(c * Rw.x - s * Rw.z, Rw.y, s * Rw.x + c * Rw.z);",
    "  vec2 st = vec2(atan(Rw.x, Rw.z) / 6.2831853 + 0.5, asin(clamp(Rw.y, -1.0, 1.0)) / 3.1415926 + 0.5);",
    /* Сдвиг по положению камеры. Небо стоит бесконечно далеко и от
       проезда камеры в отражении не движется, а стекло приборной
       панели отражает ближний мир, который движется. Замер двух точек
       дуги в 0.12 хода давал одинаковую плиту; дрейф даёт ей ехать. */
    "  st = vec2(fract(st.x + sdvig.x), clamp(st.y + sdvig.y, 0.0, 1.0));",
    "  vec3 otr = texture2D(nebo, st).rgb;",
    /* Два софтбокса плёнки: верхний правый сильнее, левый заполняющий.
       Показатель высокий, пятна тугие: блик на стекле узкий. */
    "  float b1 = pow(max(dot(R, normalize(vec3(0.45, 0.70, 0.55))), 0.0), 30.0);",
    "  float b2 = pow(max(dot(R, normalize(vec3(-0.60, 0.25, 0.75))), 0.0), 30.0);",
    "  float blik = (b1 * 0.5 + b2 * 0.3) * (1.0 - 0.5 * den);",
    /* Френель по кромке: стекло у края ловит больше света. */
    "  float kr = min(min(vUv.x, 1.0 - vUv.x), min(vUv.y, 1.0 - vUv.y));",
    "  float fr = 1.0 - smoothstep(0.0, 0.06, kr);",
    "  vec3 kromka = vec3(0.541, 0.612, 1.0) * 0.6;",
    /* Отсвет ближайшего огня акта: сила уже посчитана по экранному
       расстоянию до плиты, здесь ложится градиентом со стороны огня. */
    /* Отражение 0.16. Пробовали 0.35: тело плиты светлело с 12 до 32
       уровней, и подпись на ней теряла контраст с 6.5 до 4.2. */
    "  vec3 col = telo + otr * 0.16 + kromka * fr + vec3(blik) + vOgon.rgb * vOgon.a * (0.35 + 0.65 * vUv.x);",
    "  float a = teloA + fr * 0.30 + blik * 0.4;",
    "  gl_FragColor = vec4(col, clamp(a, 0.0, 1.0) * vVid);",
    "  #include <colorspace_fragment>",
    "}"
  ].join("\n");

  var ТЕНЬ = [
    "varying vec2 vUv;",
    "varying float vVid;",
    "varying vec4 vOgon;",
    "void main() {",
    "  float kr = min(min(vUv.x, 1.0 - vUv.x), min(vUv.y, 1.0 - vUv.y));",
    "  float mjag = smoothstep(0.0, 0.10, kr);",
    "  gl_FragColor = vec4(0.008, 0.012, 0.04, 0.35 * mjag * vVid);",
    "  #include <colorspace_fragment>",
    "}"
  ].join("\n");

  /* Небо берётся из сцены: своей ссылки ядро не отдаёт, а сфера неба в
     сцене одна и узнаётся по порядку рисования, она рисуется первой. */
  function найтиНебо() {
    var д = W.scene.children;
    for (var i = 0; i < д.length; i++) {
      if (д[i].renderOrder === -100 && д[i].material && д[i].material.map) return д[i];
    }
    return null;
  }

  function собратьПлиты() {
    небо = найтиНебо();
    var гео = new T.PlaneGeometry(1, 1);
    аВид = new T.InstancedBufferAttribute(new Float32Array(МАКС_ПЛИТ), 1);
    аОгонь = new T.InstancedBufferAttribute(new Float32Array(МАКС_ПЛИТ * 4), 4);
    аВид.setUsage(T.DynamicDrawUsage);
    аОгонь.setUsage(T.DynamicDrawUsage);
    гео.setAttribute("aVid", аВид);
    гео.setAttribute("aOgon", аОгонь);

    матПлит = new T.ShaderMaterial({
      uniforms: {
        nebo: { value: небо ? небо.material.map : null },
        camRot: { value: new T.Matrix3() },
        neboRot: { value: 0 },
        sdvig: { value: new T.Vector2() },
        den: { value: день ? 1 : 0 },
        /* Тело плиты как var(--rv-плита) сейчас: rgba(8,11,24,.62). В
           линейном пространстве, перевод в sRGB делает colorspace_fragment. */
        telo: { value: new T.Color(0x080B18) },
        teloA: { value: 0.62 }
      },
      vertexShader: ВЕРШИНЫ,
      fragmentShader: ПЛИТА,
      transparent: true,
      depthTest: false,
      depthWrite: false
    });
    матТени = new T.ShaderMaterial({
      vertexShader: ВЕРШИНЫ,
      fragmentShader: ТЕНЬ,
      transparent: true,
      depthTest: false,
      depthWrite: false
    });
    плиты = new T.InstancedMesh(гео, матПлит, МАКС_ПЛИТ);
    тени = new T.InstancedMesh(гео, матТени, МАКС_ПЛИТ);
    плиты.instanceMatrix.setUsage(T.DynamicDrawUsage);
    тени.instanceMatrix.setUsage(T.DynamicDrawUsage);
    /* Дети камеры рисуются всегда, отсечение по пирамиде им не нужно и
       вредно: коробка instanced-меша не знает о матрицах экземпляров. */
    плиты.frustumCulled = false; тени.frustumCulled = false;
    /* Тень глубже и рисуется раньше плиты. */
    тени.renderOrder = 59; плиты.renderOrder = 60;
    плиты.count = 0; тени.count = 0;
    W.cam.add(тени); W.cam.add(плиты);
  }

  var мат4 = null, кват = null, поз = null, масш = null;

  /* Одна плита из прямоугольника карточки. Ширина в мире считается от
     угла обзора: на расстоянии ГЛУБИНА полувысота кадра равна
     tan(fov/2) * ГЛУБИНА, и точка экрана переводится в единицы мира
     линейно. Камера аспект и угол меняет по актам, читаем каждый раз. */
  function поставитьПлиту(меш, k, r, вш, вы, полуВ, аспект, глубина, сдвX, сдвY) {
    var cx = (r.left + r.right) * 0.5 + сдвX, cy = (r.top + r.bottom) * 0.5 + сдвY;
    var nx = (cx / вш) * 2 - 1, ny = 1 - (cy / вы) * 2;
    var м = глубина / ГЛУБИНА;
    поз.set(nx * полуВ * аспект * м, ny * полуВ * м, -глубина);
    масш.set(r.width / вы * 2 * полуВ * м, r.height / вы * 2 * полуВ * м, 1);
    мат4.compose(поз, кват, масш);
    меш.setMatrixAt(k, мат4);
  }

  /* Днём плит в мире нет. Дневная карточка почти непрозрачна (.82
     белого), и плита под ней не видна, зато её кромка и блики после
     инверсии холста становятся ТЁМНЫМИ и обводят белую карточку серой
     рамкой (снимок выхода днём на полной ступени). Вёрстка решила то
     же: днём плита это карточка, стекла и свечений нет. Признак
     rv-плиты-есть снимается, иначе заливка карточки останется тонкой
     без тела под ней. */
  function погаситьПлиты() {
    for (var i = 0; i < акты.length; i++) {
      if (акты[i].есть) { акты[i].есть = false; акты[i].узел.classList.remove("rv-плиты-есть"); }
    }
    занято = 0;
    плиты.count = 0; тени.count = 0;
    плиты.visible = false; тени.visible = false;
  }

  function вестиПлиты(dt) {
    if (!плиты) return;
    if (день) { if (занято || плиты.visible) погаситьПлиты(); return; }
    if (!мат4) { мат4 = new T.Matrix4(); кват = new T.Quaternion(); поз = new T.Vector3(); масш = new T.Vector3(); }
    var вш = g.innerWidth, вы = g.innerHeight;
    var полуВ = Math.tan(W.cam.fov * Math.PI / 360) * ГЛУБИНА;
    var аспект = W.cam.aspect;
    var k = 0;
    /* Тень отстаёт от плиты на сглаженный ход слоя: обе висят на
       камере и сами по себе при повороте не расходятся, расхождение
       им даёт инерция, та же, что двигает слой слов. */
    var тX = 3 - парX * 0.6, тY = 3 - парY * 0.6;
    for (var i = 0; i < акты.length && k < МАКС_ПЛИТ; i++) {
      var a = акты[i];
      var было = a.есть;
      a.есть = false;
      if (a.вид <= 0.02 || !a.карточки || !a.карточки.length) {
        if (было) a.узел.classList.remove("rv-плиты-есть");
        continue;
      }
      var огонь = a.ист ? a.ист.огонь : 0x8A9CFF;
      var ог = ((огонь >> 16) & 255) / 255, ob = ((огонь >> 8) & 255) / 255, obb = (огонь & 255) / 255;
      var св = a.свЭкран;   /* экранная точка источника, если есть */
      var n = 0;
      for (var j = 0; j < a.карточки.length && n < МАКС_НА_АКТ && k < МАКС_ПЛИТ; j++) {
        var r = a.карточки[j].getBoundingClientRect();
        /* Скрытая фазой карточка (display:none) даёт нулевой прямоугольник:
           плита под ней обязана исчезнуть вместе с ней. */
        if (r.width < 2 || r.height < 2) continue;
        if (r.bottom < -40 || r.top > вы + 40) continue;
        поставитьПлиту(плиты, k, r, вш, вы, полуВ, аспект, ГЛУБИНА, 0, 0);
        поставитьПлиту(тени, k, r, вш, вы, полуВ, аспект, ГЛУБИНА_ТЕНИ, тX, тY);
        аВид.array[k] = зажать(a.вид, 0, 1);
        /* Сила отсвета падает с экранным расстоянием до огня: у плиты
           рядом с планетой кромка горит, у дальней еле тлеет. */
        var сила = 0;
        if (св) {
          var dx = ((r.left + r.right) * 0.5 - св[0]) / вш, dy = ((r.top + r.bottom) * 0.5 - св[1]) / вы;
          сила = зажать(1 - Math.sqrt(dx * dx + dy * dy) * 1.6, 0, 1) * св[2] * 0.22;
        }
        аОгонь.array[k * 4] = ог; аОгонь.array[k * 4 + 1] = ob; аОгонь.array[k * 4 + 2] = obb; аОгонь.array[k * 4 + 3] = сила;
        k++; n++;
      }
      a.есть = n > 0;
      if (a.есть !== было) a.узел.classList.toggle("rv-плиты-есть", a.есть);
    }
    занято = k;
    плиты.count = k; тени.count = k;
    плиты.visible = k > 0; тени.visible = k > 0;
    if (k > 0) {
      плиты.instanceMatrix.needsUpdate = true;
      тени.instanceMatrix.needsUpdate = true;
      аВид.needsUpdate = true; аОгонь.needsUpdate = true;
      матПлит.uniforms.camRot.value.setFromMatrix4(W.cam.matrixWorld);
      матПлит.uniforms.neboRot.value = небо ? -небо.rotation.y : 0;
      /* Сотая доля текстуры на единицу пути: дуга акта в десяток единиц
         сдвигает отражение на десятую часть неба, перегон крутит его
         целиком, но на перегоне плит не видно. */
      матПлит.uniforms.sdvig.value.set((W.cam.position.x + W.cam.position.z) * 0.01, W.cam.position.y * 0.004);
    }
  }

  /* ── Свет и инерция ────────────────────────────────────────── */
  function вестиСвет(dt) {
    var вш = g.innerWidth, вы = g.innerHeight;
    if (!в2) в2 = new T.Vector3();
    /* Два прохода: сначала все ЧТЕНИЯ раскладки (коробка колонки слов),
       потом все ЗАПИСИ css-переменных. Запись переменной на узле
       первого акта пачкает раскладку, и чтение коробки у второго акта
       заставляло браузер пересчитать её прямо в кадре, по разу на акт.
       Гасящую запись (сила 0) тоже откладываем: она такая же запись. */
    var записи = [];
    for (var i = 0; i < акты.length; i++) {
      var a = акты[i];
      if (a.вид <= 0.02 || !a.ист) {
        if (a.свБыло) { записи.push([a, null]); a.свБыло = ""; a.свЭкран = null; }
        continue;
      }
      var x, y, сила, знак;
      if (a.ист.экран) {
        /* Плоский акт: своего источника в мире нет, огонь стоит там, где
           его рисует холст акта, в правой половине кадра. */
        x = a.ист.экран[0] * вш; y = a.ист.экран[1] * вы; сила = 0.6;
      } else {
        if (!a.точкаМира || (кадров % 30) === 0) обновитьТочку(a);
        if (!a.точкаМира) continue;
        в2.copy(a.точкаМира);
        var глубина = в2.distanceTo(W.cam.position);
        в2.project(W.cam);
        /* Точка за спиной камеры проецируется в кадр зеркально: свет
           оттуда не приходит. */
        if (в2.z > 1) { сила = 0; x = вш * 0.75; y = вы * 0.4; }
        else {
          x = (в2.x + 1) * 0.5 * вш; y = (1 - в2.y) * 0.5 * вы;
          /* Вес «камера на станции этого акта»: на перегоне свет чужого
             акта не должен ложиться на слова текущего. */
          var наСт = 1;
          try { наСт = g.RV_WORLD["наСтанции"](a.имя, 0.8); } catch (eС) { наСт = 1; }
          if (!(наСт > 0)) наСт = 0;
          /* Глубина гасит свет только на перегоне, в сотнях единиц:
             планета выхода стоит в восьмидесяти по замыслу акта, и
             спад от ста двадцати держал её свет на самом полу. */
          сила = зажать(наСт, 0, 1) * зажать(1.15 - глубина / 400, 0.5, 1);
        }
      }
      x = зажать(x, -вш * 0.5, вш * 1.5); y = зажать(y, -вы * 0.5, вы * 1.5);
      /* Со стороны какой кромки свет: на ПК источник справа от колонки
         слов, на телефоне может оказаться и слева. */
      var колонка = a.слой ? a.слой.getBoundingClientRect() : null;
      знак = (колонка && x < (колонка.left + колонка.right) * 0.5) ? -1 : 1;
      a.свЭкран = [x, y, сила];
      var з = Math.round(x) + "|" + Math.round(y) + "|" + сила.toFixed(2) + "|" + знак;
      if (з === a.свБыло) continue;
      a.свБыло = з;
      записи.push([a, [Math.round(x), Math.round(y), сила.toFixed(2), знак]]);
    }
    for (i = 0; i < записи.length; i++) {
      var s = записи[i][0].узел.style, зн = записи[i][1];
      if (!зн) { s.setProperty("--св-сила", "0"); continue; }
      s.setProperty("--св-x", зн[0] + "px");
      s.setProperty("--св-y", зн[1] + "px");
      s.setProperty("--св-сила", зн[2]);
      s.setProperty("--св-цвет", записи[i][0].ист.цвет);
      s.setProperty("--св-знак", String(зн[3]));
    }
  }

  function вестиИнерцию(dt) {
    if (!в3) в3 = new T.Vector3();
    if (!прежняяКамера) { прежняяКамера = W.cam.position.clone(); return; }
    в3.copy(W.cam.position).sub(прежняяКамера);
    прежняяКамера.copy(W.cam.position);
    /* Скорость камеры в её осях: столбцы матрицы мира камеры это её
       правая и верхняя оси. Делим на dt, чтобы величина не зависела от
       частоты кадров: на 120 герцах шаг вдвое короче. */
    var m = W.cam.matrixWorld.elements;
    var бок = (в3.x * m[0] + в3.y * m[1] + в3.z * m[2]) / dt;
    var верт = (в3.x * m[4] + в3.y * m[5] + в3.z * m[6]) / dt;
    /* Крен: у камеры без крена правая ось лежит в горизонте, её высота
       и есть синус крена. */
    var кр = Math.asin(зажать(m[1], -1, 1));
    var предел = телефон ? 6 : 10;
    var цX = зажать(-бок * 1.2 + кр * 40, -предел, предел);
    var цY = зажать(-верт * 1.2, -предел * 0.8, предел * 0.8);
    /* Перегон в сотни единиц за секунду упирается в предел и стоит там:
       инерция читается на дугах внутри акта, а на перегоне слой всё
       равно невидим. */
    парX = подтянуть(парX, цX, 0.15, dt);
    парY = подтянуть(парY, цY, 0.15, dt);
    крен = подтянуть(крен, зажать(кр * -45, -3, 3), 0.15, dt);
    var сX = парX.toFixed(1) + "px", сY = парY.toFixed(1) + "px", сК = крен.toFixed(2);
    var корень = d.documentElement.style;
    if (сX !== парXбыл) { корень.setProperty("--пар-x", сX); парXбыл = сX; }
    if (сY !== парYбыл) { корень.setProperty("--пар-y", сY); парYбыл = сY; }
    if (сК !== кренБыл) { корень.setProperty("--кр", сК); кренБыл = сК; }
  }

  function кадр(ts) {
    g.requestAnimationFrame(кадр);
    if (!W || !W.готов || !W.cam) return;
    var dt = прошлое ? Math.min(0.05, Math.max(0.004, (ts - прошлое) / 1000)) : 0.016;
    прошлое = ts;
    кадров++;
    прочитатьВид();
    /* Сначала все чтения раскладки, потом записи: иначе каждая запись
       стиля заставляет браузер пересчитать раскладку перед следующим
       чтением. */
    вестиИнерцию(dt);
    вестиСвет(dt);
    if (ступень >= 2) вестиПлиты(dt);
  }

  function поТеме() {
    день = d.documentElement.getAttribute("data-тема") === "светлая";
    if (матПлит) матПлит.uniforms.den.value = день ? 1 : 0;
  }

  function поРазмеру() {
    телефон = Math.min(g.innerWidth, g.innerHeight) < 760;
    for (var i = 0; i < акты.length; i++) { акты[i].карточки = null; акты[i].свБыло = ""; }
  }

  var поднят = false;
  function поднять() {
    if (поднят) return;
    if (!g.RV_WORLD || !g.RV_WORLD["готов"] || !g.RV_WORLD["готов"]()) return;
    W = g.RV_WORLD["мир"]();
    T = W.T;
    if (!W || !T || !W.cam) return;
    ступень = g.RV_WORLD["ступень"] ? g.RV_WORLD["ступень"]() : 0;
    /* Ступень 0: ничего дорогого, вёрстка живёт своими значениями по
       умолчанию. Тихий режим: камера стоит, инерции и света нет. */
    if (ступень < 1 || тихо) { поднят = true; return; }
    поднят = true;
    собратьАкты();
    поРазмеру();
    поТеме();
    d.documentElement.classList.add("rv-плиты");
    if (ступень >= 2) {
      try { собратьПлиты(); } catch (e) { плиты = null; тени = null; }
    }
    g.addEventListener("resize", поРазмеру);
    g.addEventListener("rv-тема", поТеме);
    g.requestAnimationFrame(кадр);
  }

  /* Мир поднимается в свободный промежуток после DOMContentLoaded, и
     своего события «готов» не шлёт: ждём опросом, шаг в четверть
     секунды, пока не поднялся. */
  function ждать() {
    поднять();
    if (!поднят) g.setTimeout(ждать, 250);
  }

  g.RV_ПЛИТЫ = {
    "состояние": function () {
      var сп = [];
      for (var i = 0; i < акты.length; i++) if (акты[i].вид > 0.02) sп(акты[i]);
      function sп(a) { сп.push({ "акт": a.имя, "вид": Math.round(a.вид * 100) / 100, "плит": a.есть, "св": a.свЭкран ? a.свЭкран.map(function (v) { return Math.round(v * 100) / 100; }) : null }); }
      return { "ступень": ступень, "поднят": поднят, "плит": занято, "пар": [Math.round(парX * 10) / 10, Math.round(парY * 10) / 10, Math.round(крен * 100) / 100], "акты": сп };
    }
  };

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", ждать);
  else ждать();
})(window, document);
