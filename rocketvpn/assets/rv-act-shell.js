/* Rocket VPN. Акт 2 «Оболочка» - момент бренда.

   ЗАЧЕМ ЗДЕСЬ ЧЕСТНОЕ ПРЕЛОМЛЕНИЕ, А НЕ ПРОЗРАЧНЫЙ ШАР. Сценарий продаёт
   не слово «шифрование», а зрелище: досмотр работает и всё равно ничего
   не находит. Если оболочка будет просто полупрозрачной сферой, человек
   прочитает её как «пузырь», то есть как пустоту. Нужно обратное: за
   оболочкой среда должна ЛОМАТЬСЯ, тогда видно, что там плотное тело, а
   не дырка. Поэтому среда сначала рисуется в отдельную мишень, а корка
   оболочки берёт из неё выборку со смещением по своей нормали и с
   разбегом каналов. Разбег каналов тут не украшение: одна выборка даёт
   мутное пятно, три дают стекло.

   ПОЧЕМУ ЛУЧ ЛОМАЕТСЯ, А НЕ ГАСНЕТ. Гаснущий луч читается как «досмотр
   сломался», и это продаёт не тот товар. Луч обязан дойти, упереться и
   уйти в стороны: работает - и не находит. Поэтому в самом луче
   пробивается дыра ровно по ширине оболочки, а от точки касания в обе
   стороны уходят отражённые сегменты.

   ПОЧЕМУ СОСЕДНИЕ ПАКЕТЫ ВСПЫХИВАЮТ. Пустая подпись у своего пакета
   читается только на фоне непустых у чужих. Один пакет в кадре ничего
   не доказывает, поэтому рядом идут чужие, и их луч вскрывает.

   Ступень качества здесь меняет РАЗМЕР МИШЕНИ и густоту среды, но не
   отменяет ни оболочки, ни луча, ни преломления. Отказ в содержимом -
   прямой урок родственного проекта, там это читалось как «всё пропало».

   ПОЧЕМУ НА СТУПЕНЯХ 1-2 СТЕКЛО ФИЗИЧЕСКОЕ, А СВОЙ ШЕЙДЕР ОСТАЛСЯ ТОЛЬКО
   НИЩЕЙ. Самописная выборка из мишени со сдвигом по нормали давала три
   цветные копии решётки и три копии своего пакета: на кропе это читалось
   не стеклом, а сбоем канала. Физический материал слоя считает
   пропускание по толщине и показателю преломления, берёт стан света и
   карту окружения, и шар получает то, чего у выборки не было: блик
   ключа, отражение софтбоксов и радужную кромку. Снимок среды в свою
   мишень при этом не нужен: слой делает проход пропускания сам, и
   двойная отрисовка сцены на каждом кадре уходит. Среда и чужие пакеты
   ради этого объявлены непрозрачными: в проход пропускания слой берёт
   только их, прозрачное сквозь стекло не видно вовсе. Марка и ореолы
   наоборот остаются прозрачными, чтобы в проход не попасть: марка над
   шаром преломлялась нижней половиной и печаталась дважды. */
(function (g, d) {
  "use strict";

  /* Радиус оболочки в местных единицах. Камера ядра стоит на z=12 с углом
     52 градуса, на плоскости z=0 в кадр влезает около 11.7 по высоте,
     поэтому 2.1 - это заметное тело, но не заслонка на весь экран. */
  var РАДИУС = 2.1;

  var М = {};              /* всё нажитое актом */
  var W = null;
  var собрано = false;
  var шир = 0, выс = 0;

  function зажать(v, a, b) { return v < a ? a : (v > b ? b : v); }

  /* Плавная ступенька. Нужна на каждом шаге драматургии: линейные
     переходы в кадре выглядят механическими, человек видит счётчик,
     а не движение. */
  function мягко(край0, край1, v) {
    var t = зажать((v - край0) / (край1 - край0), 0, 1);
    return t * t * (3 - 2 * t);
  }

  /* Постоянный случай, как в актах 0 и 1: сцена должна быть узнаваемой
     при повторном заходе, одной и той же на каждую перезагрузку. */
  function случай(с) {
    var x = Math.sin(с * 12.9898) * 43758.5453;
    return x - Math.floor(x);
  }

  /* ── Шейдеры ──────────────────────────────────────────────────
     Внутри GLSL всё называется латиницей намеренно: имена в шейдере
     обязаны быть ASCII, иначе часть драйверов молча не соберёт программу
     и акт станет чёрным пятном. Объяснения остаются здесь, в JS. */

  var В_ОБОЛОЧКА = [
    "varying vec3 vN;",
    "varying vec3 vEye;",
    "varying vec3 vLoc;",
    "void main(){",
    "  vLoc = position;",
    "  vN = normalize(normalMatrix * normal);",
    "  vec4 mv = modelViewMatrix * vec4(position,1.0);",
    "  vEye = normalize(mv.xyz);",
    "  gl_Position = projectionMatrix * mv;",
    "}"
  ].join("\n");

  /* uRefr - сила увода выборки по нормали, то есть насколько сильно
     оболочка гнёт среду. uHitY - высота, на которой сейчас стоит луч:
     по ней зажигается место касания.

     ДВА МЕСТА, ГДЕ ЛЕГКО ПОЛУЧИТЬ ПЛОСКИЙ СИНИЙ БЛИН ВМЕСТО СТЕКЛА.
     Первое: у задней грани нормаль смотрит от зрителя, и френель на ней
     выходит единицей по всей площади - сфера заливается ровным цветом.
     Разворачиваем нормаль по gl_FrontFacing.
     Второе: касание луча нельзя жечь по всей окружности на его высоте.
     Спереди эта окружность проецируется в прямую через центр, и кадр
     читается как «луч прошёл насквозь» - ровно наоборот сценарию.
     Поэтому касание горит только у боков, где луч и соскальзывает. */
  var Ф_ОБОЛОЧКА = [
    "uniform sampler2D uBack;",
    "uniform vec2 uRes;",
    "uniform float uRefr;",
    "uniform float uLight;",
    "uniform float uSeamPhase;",
    "uniform float uSeamGlow;",
    "uniform float uHitY;",
    "uniform float uHit;",
    "uniform float uR;",
    "uniform float uTilt;",
    "uniform vec3 uIndigo;",
    "uniform vec3 uGlow;",
    "uniform vec3 uVoid;",
    "varying vec3 vN;",
    "varying vec3 vEye;",
    "varying vec3 vLoc;",
    "void main(){",
    "  vec3 n = gl_FrontFacing ? vN : -vN;",
    /* Корка наклонена, а луч идёт по горизонтали кадра: высоту касания
       сравниваем в координатах корня, иначе пятно уезжает по шару. */
    "  float rootY = vLoc.y * cos(uTilt) - vLoc.z * sin(uTilt);",
    "  vec2 uv = gl_FragCoord.xy / uRes;",
    "  vec2 off = n.xy * uRefr;",
    "  vec4 s = texture2D(uBack, uv + off);",
    "  float rr = texture2D(uBack, uv + off * 1.14).r;",
    "  float bb = texture2D(uBack, uv + off * 0.86).b;",
    "  vec3 back = mix(uVoid, vec3(rr, s.g, bb), clamp(s.a * 1.8, 0.0, 1.0));",
    "  float fres = pow(1.0 - max(dot(n, -vEye), 0.0), 3.0);",
    "  vec3 c = back * 1.35 + uIndigo * fres * 1.25;",
    "  float belt = 1.0 - smoothstep(0.015, 0.10, abs(vLoc.y));",
    "  float ang = atan(vLoc.z, vLoc.x) * 0.15915 + 0.5;",
    "  float run = pow(max(0.0, 1.0 - abs(fract(ang - uSeamPhase + 0.5) - 0.5) * 7.0), 2.0);",
    "  float edge = smoothstep(0.45, 0.95, abs(vLoc.x) / uR);",
    "  c += uGlow * belt * (0.22 + run * 1.5) * uSeamGlow * (0.4 + edge * 0.9);",
    "  float hit = (1.0 - smoothstep(0.0, 0.26, abs(rootY - uHitY))) * edge;",
    "  c += uGlow * hit * uHit * 1.4;",
    /* Основа и френель подняты по замеру света: на подъёме оболочки
       (доли 0.20-0.44) светом было занято 1,4-1,9 процента кадра при
       4-6 на её же второй половине. Оболочка в этот момент уже сомкнута
       вокруг человека, и не видеть её нельзя - это ровно тот кадр, за
       который сайт продаёт защиту. */
    "  float a = uLight * (0.26 + fres * 0.92 + belt * uSeamGlow * 0.5 + hit * uHit * 0.8);",
    "  gl_FragColor = vec4(c, clamp(a, 0.0, 1.0));",
    "}"
  ].join("\n");

  /* Луч досмотра. uHoleX и uHoleR вырезают в нём дыру: именно она
     показывает, что луч не прошёл сквозь оболочку. */
  var В_ПРОСТО = [
    "varying vec2 vUv;",
    "void main(){ vUv = uv; gl_Position = projectionMatrix * modelViewMatrix * vec4(position,1.0); }"
  ].join("\n");

  /* uSide отрезает половину полосы. Отражённый конец обязан начинаться в
     точке касания и уходить наружу; двусторонний сегмент выглядел бы как
     ещё один сквозной луч, то есть отменял бы весь смысл кадра. */
  var Ф_ЛУЧ = [
    "uniform float uWide;",
    "uniform float uHoleX;",
    "uniform float uHoleR;",
    "uniform float uBright;",
    "uniform float uSide;",
    "uniform vec2 uEnds;",
    "uniform vec3 uCol;",
    "varying vec2 vUv;",
    "void main(){",
    "  float across = 1.0 - smoothstep(0.0, 1.0, abs(vUv.y - 0.5) * 2.0);",
    "  across = pow(across, 2.5);",
    "  float core = pow(1.0 - abs(vUv.y - 0.5) * 2.0, 22.0);",
    "  float x = (vUv.x - 0.5) * uWide;",
    "  float hole = smoothstep(uHoleR * 0.72, uHoleR, abs(x - uHoleX));",
    /* Спад к концам отдельной парой: у сквозного луча концы за кадром,
       у отражённого - в кадре, и там гаснуть надо раньше, иначе конец
       читается обрубком. */
    "  float ends = 1.0 - smoothstep(uEnds.x, uEnds.y, abs(vUv.x - 0.5));",
    "  float side = 1.0;",
    "  if (uSide > 0.5) side = smoothstep(0.50, 0.56, vUv.x);",
    "  if (uSide < -0.5) side = smoothstep(0.50, 0.56, 1.0 - vUv.x);",
    "  float a = (across * 0.30 + core * 0.9) * uBright * hole * ends * side;",
    "  gl_FragColor = vec4(uCol * (0.6 + core), a);",
    "}"
  ].join("\n");

  /* Пакеты-соседи. Атрибут aOpen - насколько пакет сейчас вскрыт. */
  var В_ПАКЕТЫ = [
    "attribute float aOpen;",
    "varying float vOpen;",
    "uniform float uSize;",
    "void main(){",
    "  vOpen = aOpen;",
    "  vec4 mv = modelViewMatrix * vec4(position,1.0);",
    "  gl_PointSize = uSize * (1.0 + aOpen * 2.2) * (34.0 / max(0.4, -mv.z));",
    "  gl_Position = projectionMatrix * mv;",
    "}"
  ].join("\n");

  var Ф_ПАКЕТЫ = [
    "varying float vOpen;",
    "uniform vec3 uCalm;",
    "uniform vec3 uOpen;",
    "void main(){",
    "  float dd = length(gl_PointCoord - 0.5);",
    "  float a = 1.0 - smoothstep(0.14, 0.5, dd);",
    "  vec3 c = mix(uCalm, uOpen, vOpen);",
    "  gl_FragColor = vec4(c, a * (0.34 + vOpen * 0.66));",
    "}"
  ].join("\n");

  /* Ореол вокруг марки и вокруг своего пакета. Отдельный шейдер дешевле
     текстуры и не тянет за собой загрузку. Степень высокая намеренно:
     при пологом спаде у пятна видна граница круга, и оно читается не
     свечением, а наклеенным диском. */
  var Ф_ОРЕОЛ = [
    "uniform vec3 uCol;",
    "uniform float uBright;",
    "varying vec2 vUv;",
    "void main(){",
    "  float dd = length(vUv - 0.5) * 2.0;",
    "  float a = pow(max(0.0, 1.0 - dd), 4.5);",
    "  gl_FragColor = vec4(uCol, a * uBright);",
    "}"
  ].join("\n");

  /* Среда. Затухание считается в вершине: решётка должна быть облаком
     вокруг оболочки. Обоями на весь экран она спорит с подписью
     акта и отбирают у оболочки роль главного предмета в кадре. */
  var В_СРЕДА = [
    "varying float vFade;",
    "void main(){",
    "  float r = length(position.xy);",
    "  float dep = clamp((-position.z - 3.0) / 16.0, 0.0, 1.0);",
    /* Спад от шара ближе, чем был (3..8.6): среда теперь лежит на трёх
       глубинах с поворотом, и на дуге камеры далёкие слои уезжают
       сильнее ближних. Широкая решётка при этом заливала кадр обоями. */
    "  vFade = (1.0 - smoothstep(2.0, 6.4, r)) * (1.0 - dep * 0.6);",
    "  gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);",
    "}"
  ].join("\n");

  var Ф_СРЕДА = [
    "uniform vec3 uCol;",
    "uniform float uBright;",
    "varying float vFade;",
    "void main(){ gl_FragColor = vec4(uCol * vFade * uBright, 1.0); }"
  ].join("\n");

  /* Пыль в воздухе, по которой виден луч. Свет в пустоте не виден, его
     видно только на взвеси; без облака луч читался палкой, режущей
     кадр. Вспышка идёт по высоте луча, остывает за uTail единиц позади
     него (uPassed - с какой стороны уже прошёл), а в тени шара (за ним,
     в его ширину) вспышек нет: так тень от шара появляется без тени. */
  var В_ОБЛАКО = [
    "attribute float aPh;",
    "varying float vA;",
    "uniform float uBeamY;",
    "uniform float uR;",
    "uniform float uTail;",
    "uniform float uPassed;",
    "uniform float uOn;",
    "uniform float uSize;",
    "void main(){",
    "  float dy = position.y - uBeamY;",
    "  float flash = 1.0 - smoothstep(0.0, 0.3, abs(dy));",
    /* Остывание только с той стороны, где луч уже прошёл: без step
       непройденная сторона получала полный хвост, и пыль вспыхивала
       по всему кадру разом. */
    "  float back = dy * uPassed;",
    "  float after = step(0.0, back) * exp(-back / max(uTail, 0.05)) * 0.55;",
    "  float glow = max(flash, after) * uOn;",
    "  if (abs(position.x) < uR && position.z < 0.0) glow = 0.0;",
    "  vA = 0.05 + glow * (0.45 + 0.55 * aPh);",
    "  vec4 mv = modelViewMatrix * vec4(position, 1.0);",
    "  gl_PointSize = uSize * (1.6 + glow * 3.0) * (34.0 / max(0.4, -mv.z));",
    "  gl_Position = projectionMatrix * mv;",
    "}"
  ].join("\n");

  var Ф_ОБЛАКО = [
    "uniform vec3 uCol;",
    "varying float vA;",
    "void main(){",
    "  float dd = length(gl_PointCoord - 0.5);",
    "  float a = 1.0 - smoothstep(0.08, 0.5, dd);",
    "  gl_FragColor = vec4(uCol, a * vA);",
    "}"
  ].join("\n");

  /* ── Сборка ───────────────────────────────────────────────────*/
  function построить(мир) {
    if (собрано) return true;
    W = мир || W;
    if (!W || !W.T || !W.scene || !W.r) return false;
    var T = W.T;

    М.корень = new T.Group();
    М.корень.visible = false;
    /* Не в сцену, а в гнездо станции. Гнездо стоит в мировом адресе
       акта и развёрнуто лицом к камере, поэтому вся раскладка ниже
       («шар справа от текста, марка над ним») остаётся ровно той же,
       какой была при камере, стоявшей в нуле. Меняется только то, что
       к этому месту теперь ЛЕТЯТ. */
    var гн = g.RV_WORLD && g.RV_WORLD["гнездо"] ? g.RV_WORLD["гнездо"]("оболочка") : null;
    (гн || W.scene).add(М.корень);

    var цИндиго = new T.Color(0x3048A8);
    var цПерелив = new T.Color(0x6078D8);
    var цСвет = new T.Color(0x8A9CFF);
    var цПустота = new T.Color(0x05060C);

    /* ── Среда ──────────────────────────────────────────────────
       Три решётки на разной глубине. Одна решётка не даёт понять, что
       среда объёмная, а преломление на ней читается как рябь по стеклу.
       Три слоя расходятся при смещении выборки, и корка сразу читается
       как тело с толщиной. */
    var слоёв = W.ступень === 0 ? 2 : 3;
    var шаг = W.ступень === 0 ? 2.0 : 1.35;
    /* Слои повёрнуты и разнесены вглубь неравномерно: три одинаковые
       решётки друг за другом сливались в одну плотную, и дуга камеры
       не давала им разъехаться. С поворотом каждый слой на дуге едет
       своим ходом, и глубина среды видна без единого лишнего объекта. */
    var ПОВОРОТ = [0, 0.35, -0.5];
    var ГЛУБИНА = [-3, -9, -18];
    var точки = [];
    var сл, i, j;
    function отрезок(x1, y1, x2, y2, cз, sз, z) {
      /* Поворот слоя по оси взгляда кладётся на готовый отрезок: сетка и
         её случайные сдвиги едут вместе, одним поворотом. */
      точки.push(x1 * cз - y1 * sз, x1 * sз + y1 * cз, z,
                 x2 * cз - y2 * sз, x2 * sз + y2 * cз, z);
    }
    for (сл = 0; сл < слоёв; сл++) {
      var z = ГЛУБИНА[сл];
      var cs = Math.cos(ПОВОРОТ[сл]), sn = Math.sin(ПОВОРОТ[сл]);
      for (i = -7; i <= 7; i++) {
        for (j = -6; j <= 6; j++) {
          var x0 = i * шаг + (случай(сл * 31.7 + i * 3.1 + j * 7.7) - 0.5) * 0.5;
          var y0 = j * шаг + (случай(сл * 17.3 + i * 5.9 + j * 2.3) - 0.5) * 0.5;
          /* Горизонталь и вертикаль соседям: полный граф превратился бы
             в заливку, а нам нужно, чтобы сквозь среду было видно. */
          if (i < 7) отрезок(x0, y0, x0 + шаг, y0, cs, sn, z);
          if (j < 6) отрезок(x0, y0, x0, y0 + шаг, cs, sn, z);
        }
      }
    }
    var гСреда = new T.BufferGeometry();
    гСреда.setAttribute("position", new T.Float32BufferAttribute(точки, 3));
    М.среда = new T.LineSegments(гСреда, new T.ShaderMaterial({
      /* Ярче в полтора раза по замеру света: в первой половине акта
         светом занято 1,5-1,8 процента кадра при 4-6 во второй и 8-18 у
         соседних актов. Среда - единственное, что стоит в кадре, пока
         оболочка ещё сходится, и на этой яркости она читалась чертежом
         на чёрном. */
      uniforms: { uCol: { value: цПерелив }, uBright: { value: 0.54 } },
      vertexShader: В_СРЕДА, fragmentShader: Ф_СРЕДА,
      /* Непрозрачной среда объявлена ради стекла: в проход пропускания
         слой берёт только непрозрачное, и без этого шар преломлял бы
         пустоту. Сложение цветов при этом остаётся. */
      transparent: W.ступень === 0, depthWrite: false, blending: T.AdditiveBlending
    }));
    М.среда.renderOrder = 0;
    М.корень.add(М.среда);

    /* ── Соседние пакеты ────────────────────────────────────────*/
    var сколько = W.ступень === 0 ? 14 : 26;
    var поз = new Float32Array(сколько * 3);
    М.вскрыт = new Float32Array(сколько);
    М.пакетY = new Float32Array(сколько);
    for (i = 0; i < сколько; i++) {
      var px = (случай(i * 4.3) - 0.5) * 13;
      var py = (случай(i * 8.1) - 0.5) * 9;
      /* Своё место в центре занято оболочкой: чужие пакеты туда не лезут,
         иначе они окажутся внутри неё и запутают кадр. */
      if (Math.abs(px) < РАДИУС * 1.7 && Math.abs(py) < РАДИУС * 1.7) px += 4.2;
      поз[i * 3] = px;
      поз[i * 3 + 1] = py;
      поз[i * 3 + 2] = -1.5 - случай(i * 2.9) * 6;
      М.пакетY[i] = py;
    }
    var гПак = new T.BufferGeometry();
    гПак.setAttribute("position", new T.Float32BufferAttribute(поз, 3));
    М.аВскрыт = new T.Float32BufferAttribute(М.вскрыт, 1);
    гПак.setAttribute("aOpen", М.аВскрыт);
    М.мПакеты = new T.ShaderMaterial({
      uniforms: {
        uSize: { value: 5.0 },
        uCalm: { value: цПерелив },
        uOpen: { value: цСвет }
      },
      vertexShader: В_ПАКЕТЫ, fragmentShader: Ф_ПАКЕТЫ,
      /* Непрозрачные по той же причине, что среда: чужие пакеты за шаром
         обязаны в нём преломляться, а прозрачное в проход не попадает. */
      transparent: W.ступень === 0, depthWrite: false, blending: T.AdditiveBlending
    });
    М.пакеты = new T.Points(гПак, М.мПакеты);
    М.пакеты.renderOrder = 1;
    М.корень.add(М.пакеты);

    /* ── Свой пакет ─────────────────────────────────────────────
       Он остаётся видимым сквозь оболочку: смысл кадра в том, что
       внутри есть содержимое, просто снаружи его не прочитать. */
    М.свой = new T.Mesh(
      new T.SphereGeometry(0.24, W.ступень === 0 ? 12 : 20, W.ступень === 0 ? 8 : 14),
      new T.MeshBasicMaterial({ color: цСвет })
    );
    М.свой.renderOrder = 2;
    М.корень.add(М.свой);

    М.свойОреол = new T.Mesh(
      new T.PlaneGeometry(1.5, 1.5),
      new T.ShaderMaterial({
        uniforms: { uCol: { value: цСвет }, uBright: { value: 0.5 } },
        vertexShader: В_ПРОСТО, fragmentShader: Ф_ОРЕОЛ,
        /* Без проверки глубины: стекло на ступенях 1-2 пишет глубину, и
           ореол в центре шара иначе отсекался бы его передней стенкой. */
        transparent: true, depthWrite: false, depthTest: false, blending: T.AdditiveBlending
      })
    );
    М.свойОреол.renderOrder = 7;
    М.корень.add(М.свойОреол);

    /* ── Корка: группа с наклоном ───────────────────────────────
       Наклон по X, чтобы экватор читался эллипсом: шов, лежащий ровно
       в плоскости взгляда, проецируется в прямую, и кольца в нём не
       видно. В группе лежат обе половины, их швы и волна щелчка. */
    М.корка = new T.Group();
    М.корка.rotation.x = 0.35;
    М.корень.add(М.корка);

    var деление = W.ступень === 0 ? [20, 12] : (W.ступень === 1 ? [32, 20] : [48, 32]);

    /* Униформы шва и касания общие для обоих путей: кадр пишет в один
       набор, а какой шейдер его читает, решает ступень. */
    М.u = {
      uRes: { value: new T.Vector2(2, 2) },
      uRefr: { value: 0.0 },
      uLight: { value: 0.0 },
      uSeamPhase: { value: 0.0 },
      uSeamGlow: { value: 0.0 },
      uHitY: { value: 99.0 },
      uHit: { value: 0.0 },
      uR: { value: РАДИУС },
      uTilt: { value: 0.35 },
      uIndigo: { value: цИндиго },
      uGlow: { value: цСвет },
      uSeamCol: { value: new T.Color(0x8A9CFF) },
      uBeamCol: { value: new T.Color(0xC8D6FF) },
      uVoid: { value: цПустота }
    };

    if (W.ступень === 0) {
      /* ── Мишень для среды (только нищая ступень) ──────────────
         Здесь преломление остаётся самописным: физическое стекло со
         своим проходом пропускания слабой машине не по карману. */
      М.доляМишени = 0.5;
      М.мишень = new T.WebGLRenderTarget(2, 2, {
        minFilter: T.LinearFilter, magFilter: T.LinearFilter
      });
      М.u.uBack = { value: М.мишень.texture };
      М.мОболочка = new T.ShaderMaterial({
        uniforms: М.u,
        vertexShader: В_ОБОЛОЧКА, fragmentShader: Ф_ОБОЛОЧКА,
        transparent: true, depthWrite: false, side: T.DoubleSide
      });
    } else if (W.ступень === 1) {
      /* ── Дешёвое стекло средней ступени ───────────────────────
         Пропускание у three это отдельный проход всей сцены в текстуру
         на каждом кадре, а средняя ступень это все телефоны. Здесь
         стекло без пропускания: прозрачный физический материал с
         бликом среды, и Френель по кромке добавляется прямо в альфу
         (см. onBeforeCompile ниже). Среда за шаром просвечивает
         прозрачностью без увода, зато кадр стоит один проход. */
      М.мОболочка = new T.MeshPhysicalMaterial({
        color: 0x3048A8,
        metalness: 0.0,
        roughness: 0.16,
        transmission: 0.0,
        iridescence: 0.0,
        clearcoat: 0.0,
        envMapIntensity: 1.5,
        emissive: 0x000000,
        emissiveIntensity: 1.0,
        side: T.FrontSide,
        transparent: true,
        opacity: 0.30,
        depthWrite: false
      });
    } else {
      /* ── Физическое стекло (только полная ступень) ────────────
         Толщина и показатель преломления дают честный увод среды за
         шаром, затухание по цвету - тон индиго в толще, радужная плёнка
         даёт разбег каналов по кромке вместо трёх копий картинки. */
      М.мОболочка = new T.MeshPhysicalMaterial({
        color: 0xFFFFFF,
        metalness: 0.0,
        roughness: 0.10,
        transmission: 1.0,
        thickness: 1.4,
        ior: 1.45,
        attenuationColor: new T.Color(0x3048A8),
        attenuationDistance: 3.2,
        iridescence: 0.25,
        iridescenceIOR: 1.3,
        iridescenceThicknessRange: [120, 420],
        clearcoat: 1.0,
        clearcoatRoughness: 0.08,
        envMapIntensity: 1.5,
        emissive: 0x000000,
        emissiveIntensity: 1.0,
        side: T.FrontSide,
        transparent: false,
        depthWrite: true
      });
    }
    if (W.ступень > 0) {
      var uФиз = М.u;
      var дешёвое = W.ступень === 1;
      М.мОболочка.onBeforeCompile = function (ш) {
        ш.uniforms.uSeamCol = uФиз.uSeamCol;
        ш.uniforms.uSeamGlow = uФиз.uSeamGlow;
        ш.uniforms.uBeamCol = uФиз.uBeamCol;
        ш.uniforms.uHit = uФиз.uHit;
        ш.uniforms.uHitY = uФиз.uHitY;
        ш.uniforms.uTilt = uФиз.uTilt;
        ш.uniforms.uR = uФиз.uR;
        ш.vertexShader = "varying vec3 vLoc;\n" + ш.vertexShader.replace(
          "#include <begin_vertex>",
          "#include <begin_vertex>\n  vLoc = position;"
        );
        /* Пояс шва только у боков (edge): полоса по всей ширине резала бы
           шар пополам, а у боков она сливается с кольцом. Касание луча
           считается в координатах корня: половина наклонена, а луч идёт
           по горизонтали кадра. */
        ш.fragmentShader = [
          "varying vec3 vLoc;",
          "uniform vec3 uSeamCol;",
          "uniform float uSeamGlow;",
          "uniform vec3 uBeamCol;",
          "uniform float uHit;",
          "uniform float uHitY;",
          "uniform float uTilt;",
          "uniform float uR;"
        ].join("\n") + "\n" + ш.fragmentShader.replace(
          "#include <emissivemap_fragment>",
          "#include <emissivemap_fragment>\n" +
          "  float belt = 1.0 - smoothstep(0.06, 0.12, abs(vLoc.y));\n" +
          "  float edge = smoothstep(0.55, 0.95, abs(vLoc.x) / uR);\n" +
          "  float rootY = vLoc.y * cos(uTilt) - vLoc.z * sin(uTilt);\n" +
          "  float hit = (1.0 - smoothstep(0.0, 0.26, abs(rootY - uHitY))) * edge;\n" +
          "  totalEmissiveRadiance += uSeamCol * belt * edge * uSeamGlow + uBeamCol * hit * uHit;" +
          /* Средняя ступень: Френель в альфу. Без него прозрачный шар
             читается ровной синей плёнкой, с ним кромка плотнеет, как у
             стекла, и середина остаётся почти чистой. У нормали здесь
             уже учтена сторона грани, vViewPosition смотрит на камеру. */
          (дешёвое
            ? "\n  float fres = pow(1.0 - max(dot(normal, normalize(vViewPosition)), 0.0), 3.0);" +
              "\n  diffuseColor.a = clamp(diffuseColor.a + fres * 0.6 + (belt * edge * uSeamGlow + hit * uHit) * 0.5, 0.0, 1.0);"
            : "")
        );
      };
      М.мОболочка.customProgramCacheKey = function () { return "rv-shell-glass-" + W.ступень; };
    }

    М.верх = new T.Mesh(
      new T.SphereGeometry(РАДИУС, деление[0], деление[1], 0, 6.2832, 0, 1.5708),
      М.мОболочка
    );
    М.низ = new T.Mesh(
      new T.SphereGeometry(РАДИУС, деление[0], деление[1], 0, 6.2832, 1.5708, 1.5708),
      М.мОболочка
    );
    М.верх.renderOrder = 5;
    М.низ.renderOrder = 5;
    М.корка.add(М.верх);
    М.корка.add(М.низ);

    /* ── Шов железом ────────────────────────────────────────────
       Кольцо на срезе каждой половины. Пока половины разведены, колец
       два, и видно, что это две створки с окантовкой; при смыкании они
       сходятся в одно кольцо с канавкой. По кольцу бежит энергия через
       свечение материала. */
    function кольцо(радиус, труба, сег) {
      var гео = new T.TorusGeometry(радиус, труба, 12, сег);
      var мат = (g.RV_REAL && g.RV_REAL["корпус"])
        ? g.RV_REAL["корпус"](T, { цвет: 0x56628E, металл: 0.85, шерох: 0.3, свет: 0x8A9CFF, жар: 0 })
        : new T.MeshStandardMaterial({ color: 0x56628E, metalness: 0.85, roughness: 0.3, emissive: 0x8A9CFF, emissiveIntensity: 0 });
      if (!мат.жар) мат.жар = function (v) { мат.emissiveIntensity = Math.max(0, v) * 0.5; };
      var м = new T.Mesh(гео, мат);
      м.rotation.x = Math.PI / 2;
      return м;
    }
    var сег = W.ступень === 0 ? 48 : 96;
    М.шовВерх = кольцо(РАДИУС, 0.035, сег);
    М.шовНиз = кольцо(РАДИУС, 0.035, сег);
    /* Полтуба вверх и вниз от среза: сомкнутые кольца не воюют за одну
       глубину, а складываются в одно с канавкой посередине. */
    М.шовВерх.position.y = 0.02;
    М.шовНиз.position.y = -0.02;
    М.шовВерх.renderOrder = 5;
    М.шовНиз.renderOrder = 5;
    М.верх.add(М.шовВерх);
    М.низ.add(М.шовНиз);

    /* ── Ударная волна щелчка ───────────────────────────────────
       Кольцо, разбегающееся по экватору наружу: у щелчка появляется
       форма в придачу к вспышке шва. Функция доли, при отмотке
       схлопывается назад. */
    М.волна = new T.Mesh(
      new T.TorusGeometry(РАДИУС, 0.03, 8, 64),
      new T.MeshBasicMaterial({
        color: 0x8A9CFF, transparent: true, opacity: 0,
        depthWrite: false, depthTest: false, blending: T.AdditiveBlending
      })
    );
    М.волна.rotation.x = Math.PI / 2;
    М.волна.renderOrder = 7;
    М.волна.visible = false;
    М.корка.add(М.волна);

    /* ── Пыль под луч ───────────────────────────────────────────
       Только на ступенях 1-2: на нищей и так дорог каждый кадр, а луч
       там остаётся полосой. Внутрь шара точки не кладём: внутри должен
       быть один свой пакет и ничего больше. */
    if (W.ступень > 0) {
      var пыли = W.ступень === 2 ? 480 : 300;
      var пПоз = new Float32Array(пыли * 3);
      var пФаза = new Float32Array(пыли);
      var н = 0;
      for (i = 0; н < пыли && i < пыли * 4; i++) {
        var dx = (случай(i * 3.7 + 0.1) - 0.5) * 17;
        var dy = (случай(i * 5.3 + 0.2) - 0.5) * 12;
        var dz = -6 + случай(i * 7.1 + 0.3) * 8.5;
        if (Math.sqrt(dx * dx + dy * dy + dz * dz) < РАДИУС + 0.35) continue;
        пПоз[н * 3] = dx; пПоз[н * 3 + 1] = dy; пПоз[н * 3 + 2] = dz;
        пФаза[н] = случай(i * 9.7 + 0.4);
        н++;
      }
      var гПыль = new T.BufferGeometry();
      гПыль.setAttribute("position", new T.Float32BufferAttribute(пПоз, 3));
      гПыль.setAttribute("aPh", new T.Float32BufferAttribute(пФаза, 1));
      М.мОблако = new T.ShaderMaterial({
        uniforms: {
          uBeamY: { value: 99.0 }, uR: { value: РАДИУС }, uTail: { value: 0.5 },
          uPassed: { value: 1.0 }, uOn: { value: 0.0 }, uSize: { value: 1.0 },
          uCol: { value: new T.Color(0xC8D6FF) }
        },
        vertexShader: В_ОБЛАКО, fragmentShader: Ф_ОБЛАКО,
        transparent: true, depthWrite: false, depthTest: false, blending: T.AdditiveBlending
      });
      М.облако = new T.Points(гПыль, М.мОблако);
      М.облако.renderOrder = 3;
      М.корень.add(М.облако);
    }

    /* ── Марка ──────────────────────────────────────────────────
       Настоящая марка клиента из файла. Пока файл едет, на её
       месте горит ореол: пустого места в кадре не остаётся ни на кадр.
       Если файл не доедет вовсе - останется ореол, и акт не сломается. */
    if (W.ступень === 0) {
      М.мМарка = new T.MeshBasicMaterial({
        transparent: true, opacity: 0, depthWrite: false, color: 0xffffff
      });
    } else {
      /* Пластина на общем физическом корпусе: марка ловит ключевой свет
         и отражение софтбоксов, как всякий предмет в сцене. Своё
         свечение по картинке держит её читаемой в тени. Прозрачность
         оставлена намеренно: так марка не попадает в проход пропускания
         и не печатается второй раз в нижней половине шара. */
      М.мМарка = (g.RV_REAL && g.RV_REAL["корпус"])
        ? g.RV_REAL["корпус"](T, { цвет: 0xFFFFFF, металл: 0.9, шерох: 0.3, свет: 0xFFFFFF, жар: 0, лак: 0.35 })
        : new T.MeshPhysicalMaterial({ color: 0xFFFFFF, metalness: 0.9, roughness: 0.3, emissive: 0xFFFFFF, emissiveIntensity: 0 });
      М.мМарка.transparent = true;
      М.мМарка.opacity = 0;
      М.мМарка.alphaTest = 0.08;
      М.мМарка.depthWrite = false;
    }
    М.марка = new T.Mesh(new T.PlaneGeometry(1.9, 1.9), М.мМарка);
    М.марка.position.set(0, 3.55, -0.4);
    М.марка.renderOrder = 6;
    М.марка.visible = false;
    М.корень.add(М.марка);

    try {
      new T.TextureLoader().load("assets/rv-mark.webp", function (тек) {
        if (T.SRGBColorSpace) тек.colorSpace = T.SRGBColorSpace;
        М.мМарка.map = тек;
        /* Прозрачность берётся из альфы самой картинки, не из alphaMap:
           alphaMap читает зелёный канал, и синее «VPN» на марке
           уходило в ноль. */
        if (W.ступень > 0) М.мМарка.emissiveMap = тек;
        М.мМарка.needsUpdate = true;
        М.марка.visible = true;
      });
    } catch (e) {}

    М.ореолМарки = new T.Mesh(
      new T.PlaneGeometry(5.2, 5.2),
      new T.ShaderMaterial({
        uniforms: { uCol: { value: цПерелив }, uBright: { value: 0.0 } },
        vertexShader: В_ПРОСТО, fragmentShader: Ф_ОРЕОЛ,
        transparent: true, depthWrite: false, blending: T.AdditiveBlending
      })
    );
    М.ореолМарки.position.set(0, 3.55, -0.6);
    М.ореолМарки.renderOrder = 4;
    М.корень.add(М.ореолМарки);

    /* ── Луч досмотра и его отражённые концы ────────────────────
       Луч холодный. Янтарь на этом сайте живёт только в акте «Периметр»,
       и если растащить его дальше, тревога перестанет работать. */
    М.ширинаЛуча = 30;
    function лучМат(ярко) {
      return new T.ShaderMaterial({
        uniforms: {
          uWide: { value: М.ширинаЛуча },
          uHoleX: { value: 0.0 },
          uHoleR: { value: 0.0 },
          uBright: { value: ярко },
          uSide: { value: 0.0 },
          uEnds: { value: new T.Vector2(0.30, 0.5) },
          uCol: { value: new T.Color(0xC8D6FF) }
        },
        vertexShader: В_ПРОСТО, fragmentShader: Ф_ЛУЧ,
        transparent: true, depthWrite: false, depthTest: false,
        blending: T.AdditiveBlending
      });
    }

    М.мЛуч = лучМат(0);
    М.мЛуч.uniforms.uSide.value = -1;
    М.луч = new T.Mesh(new T.PlaneGeometry(М.ширинаЛуча, 1.5), М.мЛуч);
    М.луч.position.z = 0.6;
    М.луч.renderOrder = 8;
    М.корень.add(М.луч);

    /* Второй слой полосы: вдвое шире и в четыре раза тусклее. Один
       острый луч читался нарисованной линией, широкий ореол вокруг него
       даёт свет, рассеянный воздухом. Нищей ступени хватает одного. */
    if (W.ступень > 0) {
      М.мЛуч2 = лучМат(0);
      М.мЛуч2.uniforms.uSide.value = -1;
      М.луч2 = new T.Mesh(new T.PlaneGeometry(М.ширинаЛуча, 3.0), М.мЛуч2);
      М.луч2.position.z = 0.55;
      М.луч2.renderOrder = 8;
      М.корень.add(М.луч2);
    }

    М.отражённые = [];
    for (i = 0; i < 2; i++) {
      var мо = лучМат(0);
      мо.uniforms.uWide.value = 5.5;
      мо.uniforms.uEnds.value.set(0.2, 0.45);
      /* Отрезаем внутреннюю половину: сегмент начинается ровно в точке
         касания. Сегмент, торчащий в обе стороны, читался бы как второй
         сквозной луч. */
      мо.uniforms.uSide.value = i === 0 ? 1 : -1;
      var от = new T.Mesh(new T.PlaneGeometry(5.5, 1.0), мо);
      от.position.z = 0.7;
      от.renderOrder = 8;
      /* Уходят в стороны и вверх: соскользнувший луч не может уйти вниз,
         он отбит поверхностью, по которой пришёл. */
      от.rotation.z = i === 0 ? 0.42 : -0.42;
      М.отражённые.push(от);
      М.корень.add(от);
    }

    собрано = true;
    размерить(g.innerWidth, g.innerHeight);
    return true;
  }

  /* ── Размер ───────────────────────────────────────────────────
     Сцена уступает место тексту. На узком экране
     она уезжает вниз и уменьшается, на широком - вправо: подпись акта
     набрана слева и ограничена по ширине. */
  function размерить(w, h) {
    if (!собрано || !W) return;
    шир = w; выс = h;
    var узко = w < 760;
    if (узко) {
      /* На телефоне подпись акта занимает середину кадра, поэтому сцена
         уходит в нижнюю треть, а марка поднимается над текстом. Двигать
         её вбок бессмысленно: по ширине там места нет вовсе. */
      М.корень.scale.setScalar(0.56);
      М.корень.position.set(0, -3.2, 0);
      /* 12.6. На 10.4 марка садилась ровно на строку
         «03 ОБОЛОЧКА» и читалась частью подписи. */
      М.марка.position.set(0, 12.6, -0.4);
      М.ореолМарки.position.set(0, 12.6, -0.6);
    } else {
      М.корень.scale.setScalar(0.92);
      М.корень.position.set(w > 1180 ? 3.4 : 2.4, -0.3, 0);
      М.марка.position.set(0, 4.75, -0.4);
      М.ореолМарки.position.set(0, 4.75, -0.6);
    }

    var T = W.T;
    var р = W.r.getDrawingBufferSize(new T.Vector2());
    М.u.uRes.value.set(Math.max(2, р.x), Math.max(2, р.y));
    if (М.мишень) {
      М.мишень.setSize(
        Math.max(2, Math.round(р.x * М.доляМишени)),
        Math.max(2, Math.round(р.y * М.доляМишени))
      );
    }
    var пикс = W.r.getPixelRatio ? W.r.getPixelRatio() : 1;
    М.мПакеты.uniforms.uSize.value = 5.0 * пикс;
    if (М.мОблако) М.мОблако.uniforms.uSize.value = пикс;
  }

  /* Посадка с перелётом: створки садятся, как крышка на защёлке, с
     проскоком на несколько процентов и возвратом. Ровная ступенька
     читалась как две тарелки, съехавшиеся по рельсу. */
  function сПерелётом(t) {
    t = зажать(t, 0, 1);
    var c1 = 1.0, c3 = c1 + 1;
    var u = t - 1;
    return 1 + c3 * u * u * u + c1 * u * u;
  }

  /* ── Кадр ─────────────────────────────────────────────────────*/
  function кадр(доля, dt, часы) {
    if (!собрано && !построить(g.RV_WORLD ? g.RV_WORLD["мир"]() : null)) return;

    var T = W.T;
    var u = М.u;
    var физика = W.ступень > 0;

    /* 1. Марка зажигается первой. До этого кадра индиго на сайте нет
       вовсе, поэтому её появление и есть событие. */
    var маркаСвет = мягко(0.02, 0.22, доля);
    М.мМарка.opacity = маркаСвет * 0.95;
    if (физика && М.мМарка.жар) М.мМарка.жар(маркаСвет * 2.4);
    М.ореолМарки.material.uniforms.uBright.value =
      маркаСвет * (0.09 + 0.03 * Math.sin(часы * 1.7));

    /* 2. Пакет человека уходит к марке и встаёт в центр будущей оболочки.
       Стартует он от марки: по сценарию пакет уходит
       к ней и там одевается. */
    var подход = мягко(0.04, 0.30, доля);
    var стартY = М.марка.position.y * 0.55, стартZ = 2.6;
    М.свой.position.set(0, стартY * (1 - подход), стартZ * (1 - подход));
    М.свойОреол.position.copy(М.свой.position);
    М.свойОреол.material.uniforms.uBright.value = 0.14 + 0.04 * Math.sin(часы * 2.3);

    /* Ореол в сомкнутом шаре ярче: шарик прячется (ниже), и без этого
       центр читался пустым, а смысл кадра ровно в том, что внутри
       что-то есть. Сила прибавки считается после разъезда. */

    /* 3. Две половины сходятся. Разъезд считается назад от смыкания:
       к 0.46 половины стоят на месте, и дальше оболочка целая. */
    var разъезд = 1 - сПерелётом((доля - 0.24) / 0.22);
    var отход = РАДИУС * 1.35 * разъезд;
    М.верх.position.y = отход;
    М.низ.position.y = -отход;
    /* Половины подлетают ещё и по глубине: сходящиеся строго по прямой
       читаются как две тарелки, а с небольшим разворотом - как створки. */
    М.верх.rotation.z = разъезд * 0.26;
    М.низ.rotation.z = -разъезд * 0.26;
    var смыкание = зажать(1 - разъезд, 0, 1);

    /* Свой пакет при смыкании прячется: сквозь стекло он и так виден
       ореолом, а настоящий шарик поверх ореола давал в центре двойной
       пакет. Ореол остаётся: содержимое внутри есть. */
    М.свой.visible = смыкание < 0.9;
    if (!М.свой.visible) М.свойОреол.material.uniforms.uBright.value += 0.34;

    /* Сжатие корки на щелчке: 0.985 в момент удара, 1.02 отскок, 1.0 в
       покое. Без него кольцо волны бежит от неподвижного шара, и удара
       не читается. */
    var сж = 1.0;
    if (доля > 0.44 && доля <= 0.47) сж = 1.0 - 0.015 * мягко(0.44, 0.47, доля);
    else if (доля > 0.47 && доля <= 0.50) {
      var о = мягко(0.47, 0.50, доля);
      сж = о < 0.5 ? 0.985 + 0.035 * (о * 2) : 1.02 - 0.02 * ((о - 0.5) * 2);
    }
    М.корка.scale.setScalar(сж);

    /* Ударная волна щелчка: кольцо от экватора наружу, гаснет по ходу.
       Функция доли, не времени: при отмотке назад волна схлопывается. */
    var волна = зажать((доля - 0.44) / 0.05, 0, 1);
    М.волна.visible = волна > 0 && волна < 1;
    if (М.волна.visible) {
      М.волна.scale.setScalar(1 + 0.9 * волна);
      М.волна.material.opacity = 1 - волна;
    }

    /* Оболочка набирает свет раньше: было 0.06-0.30, стало 0.04-0.22.
       Замер света ловил начало акта тёмным (1,85 процента кадра при
       пороге 2), и причина была не в материале, а в том, что акт
       разгорался почти треть своего хода. Треть акта на разгорание -
       это не выдержка, это опоздание. */
    u.uLight.value = мягко(0.04, 0.22, доля);
    /* Преломление растёт по мере смыкания: у разведённых половин гнуть
       среду ещё нечем, у сомкнутой оболочки - есть чем, и именно этим
       она отличается от прозрачного пузыря. */
    u.uRefr.value = 0.042 * (1 - разъезд) + 0.008;

    /* 4. Щелчок: в момент смыкания по шву пробегает свет. Вспышка
       короткая и сильная, дальше шов светится тихо - он остаётся
       единственным следом того, что оболочка вообще есть. */
    var щелчок = мягко(0.44, 0.49, доля) * (1 - мягко(0.49, 0.66, доля));
    u.uSeamGlow.value = смыкание * (0.20 + щелчок * 1.9);
    М.фазаШва = (М.фазаШва || 0) + dt * (0.14 + щелчок * 2.6);
    u.uSeamPhase.value = М.фазаШва % 1;
    /* Энергия по железному кольцу: тихий ход всегда, на щелчке
       вспышка. Пока створки разведены, кольца горят слабее: свет по шву
       идёт с момента смыкания. */
    var жарШва = (0.4 + 0.6 * Math.sin(М.фазаШва * 6.2832)) * (0.35 + смыкание * 0.65) + щелчок * 2.2;
    М.шовВерх.material.жар(жарШва);
    М.шовНиз.material.жар(жарШва);

    /* 5. Досмотр. Два прохода за оставшуюся часть акта: один читается
       как случайность, два - как правило. Первый с 0.56: до этого
       ещё гаснет щелчок, и луч поверх него читался бы вторым событием. */
    var идёт = доля > 0.56;
    var цикл = идёт ? ((доля - 0.56) / 0.22) : 0;
    var номер = Math.floor(цикл);
    var внутри = цикл - номер;
    var yЛуча = 6.6 - внутри * 13.2;
    var лучЖив = идёт && номер < 2;

    М.луч.visible = лучЖив;
    М.мЛуч.uniforms.uBright.value = лучЖив ? 1.0 : 0.0;
    М.луч.position.y = yЛуча;
    if (М.луч2) {
      М.луч2.visible = лучЖив;
      М.мЛуч2.uniforms.uBright.value = лучЖив ? 0.25 : 0.0;
      М.луч2.position.y = yЛуча;
    }

    /* Пыль: вспышка по высоте луча и остывание позади него. Хвост
       считается от скорости луча в кадре: прокрутка задаёт её сама, и
       при быстрой отмотке хвост длиннее, при медленной короче. */
    if (М.мОблако) {
      var оу = М.мОблако.uniforms;
      var прежY = М.прежYЛуча == null ? yЛуча : М.прежYЛуча;
      var vy = dt > 0 ? (yЛуча - прежY) / dt : 0;
      М.прежYЛуча = yЛуча;
      if (Math.abs(vy) < 40) {
        М.скорЛуча = (М.скорЛуча || 0) + (vy - (М.скорЛуча || 0)) * 0.25;
      }
      оу.uOn.value = лучЖив ? 1.0 : 0.0;
      оу.uBeamY.value = лучЖив ? yЛуча : 99;
      оу.uPassed.value = (М.скорЛуча || 0) < 0 ? 1.0 : -1.0;
      оу.uTail.value = зажать(Math.abs(М.скорЛуча || 0) * 0.6, 0.25, 2.0);
    }

    /* Дыра в луче открывается только на подходе к оболочке. Если держать
       её всегда, луч выглядит бракованным ещё до встречи. */
    var близко = лучЖив ? зажать(1 - (Math.abs(yЛуча) - РАДИУС) / 1.4, 0, 1) : 0;
    var внутриТела = лучЖив && Math.abs(yЛуча) < РАДИУС;
    М.мЛуч.uniforms.uHoleR.value = (РАДИУС * 1.25) * близко;
    М.мЛуч.uniforms.uHoleX.value = 0;

    /* Отражённые концы живут ровно столько, сколько луч стоит на корке.
       Разводим их от точки касания: чем глубже луч зашёл, тем шире
       расходятся, - так видно, что он именно соскальзывает. */
    var скольжение = внутриТела ? Math.sqrt(Math.max(0, РАДИУС * РАДИУС - yЛуча * yЛуча)) : 0;
    var камМир = null;
    if (внутриТела && W.cam) {
      камМир = W.cam.getWorldPosition(new T.Vector3());
    }
    for (var i = 0; i < М.отражённые.length; i++) {
      var от = М.отражённые[i];
      var зн = i === 0 ? 1 : -1;
      от.visible = внутриТела;
      от.material.uniforms.uBright.value = внутриТела ? (0.6 + близко * 1.2) : 0;
      /* Начало сегмента - ровно точка касания на боку оболочки. Чем
         глубже луч зашёл, тем круче он уходит вверх: соскальзывание
         должно быть видно как изменение угла; мигание читается сбоем. */
      от.position.x = зн * скольжение;
      от.position.y = yЛуча;
      var угол = зн * (0.22 + (1 - Math.abs(yЛуча) / РАДИУС) * 0.55);
      if (камМир) {
        /* Плоскость конца смотрит в камеру каждый кадр: на дуге камеры
           плоская полоса, стоящая в плоскости сцены, сжималась в нить. */
        от.lookAt(камМир);
        от.rotateZ(угол);
      } else {
        от.rotation.set(0, 0, угол);
      }
    }

    u.uHitY.value = внутриТела ? yЛуча : 99;
    u.uHit.value = внутриТела ? (0.30 + близко * 0.45) : 0;

    /* 6. Чужие пакеты вскрываются под лучом и гаснут сами. Пустая подпись
       своего пакета читается только на фоне непустых у остальных. */
    var надо = false;
    for (i = 0; i < М.вскрыт.length; i++) {
      if (лучЖив && Math.abs(М.пакетY[i] - yЛуча) < 0.55) М.вскрыт[i] = 1;
      else if (М.вскрыт[i] > 0) { М.вскрыт[i] = Math.max(0, М.вскрыт[i] - dt * 1.1); }
      if (М.вскрыт[i] > 0) надо = true;
    }
    if (надо || М.былоВскрытие) { М.аВскрыт.needsUpdate = true; }
    М.былоВскрытие = надо;

    /* Среда живёт: без движения она читается как наклейка, и преломление
       на ней не видно вовсе. Дрейф медленный и без бокового проезда
       камеры - камера на этом сайте ходит только вглубь. */
    М.среда.position.x = Math.sin(часы * 0.09) * 0.7;
    М.среда.position.y = Math.cos(часы * 0.07) * 0.5;

    /* 7. Снимок среды для преломления. Убираем на время снимка не только
       оболочку (иначе она попадёт в собственную выборку и даст зеркальный
       коридор вместо стекла), но и весь досмотр: луч, попавший в фон,
       читается сквозь оболочку как прошедший насквозь, а это ровно то,
       чего в этом кадре быть не должно. */
    /* МАРКА В СНИМОК НЕ ПОПАДАЕТ. Она висит над оболочкой и попадала:
       нижняя полусфера честно преломляла её и рисовала ВТОРУЮ надпись
       чуть ниже настоящей, со сдвигом по цветам. Физика верная, а на
       экране это читается не преломлением, а сбоем отрисовки: человек
       видит логотип клиента, напечатанный дважды.

       Поймано на снимке акта, увеличенном до пикселей, и подтверждено
       отключением плёнки: без неё двойник остался, значит дело не в
       свечении, а в сцене.

       Оболочка обязана преломлять только МИР. Марка стоит перед
       ней и принадлежит зрителю. */
    /* На ступенях 1-2 снимка нет: проход пропускания делает слой сам,
       и всё прозрачное (марка, ореолы, луч, волна) в него не попадает
       по устройству. Список ниже живёт только для нищей ступени, и
       любой новый узел акта обязан быть в нём. */
    if (физика) return;
    var прячем = [М.корка, М.луч, М.марка, М.ореолМарки, М.свой, М.свойОреол];
    for (i = 0; i < М.отражённые.length; i++) прячем.push(М.отражённые[i]);
    var были = [];
    for (i = 0; i < прячем.length; i++) { были[i] = прячем[i].visible; прячем[i].visible = false; }
    var прежняя = W.r.getRenderTarget();
    W.r.setRenderTarget(М.мишень);
    W.r.render(W.scene, W.cam);
    W.r.setRenderTarget(прежняя);
    for (i = 0; i < прячем.length; i++) прячем[i].visible = были[i];
  }

  /* ── Договор с ядром ──────────────────────────────────────────*/
  var МОДУЛЬ = {
    "собрать": function (мир) { построить(мир); },
    "показать": function (да) {
      /* Если очередь прогрева не дошла до этого акта, а человек уже
         докрутил, собираем немедленно. Пустой кадр здесь дороже, чем
         рывок на одну сборку. */
      if (да && !собрано) построить(g.RV_WORLD ? g.RV_WORLD["мир"]() : null);
      if (собрано) М.корень.visible = !!да;
    },
    "кадр": кадр,
    "размер": function (w, h) { размерить(w, h); }
  };

  function встать() {
    if (!g.RV_WORLD) return;
    /* ПОЗА АКТА. Первая станция мира: она стоит в начале координат, и
       все остальные отсчитываются от неё вглубь по оси Z.

       Пролог длиной в восемьдесят единиц - это разгон, который человек
       проходит, пока читает два плоских акта («Тебя видно» и
       «Периметр»). Объёмного в кадре там нет, но камера уже идёт, и
       оболочка выплывает из глубины задолго до своего акта, вместо
       того чтобы возникнуть готовой в первом же кадре.

       Ход внутри акта короткий и вперёд: с восемнадцати единиц до
       десяти. Дальше подъезжать нельзя - марка висит над шаром, и на
       девяти единицах её ореол начинает резаться верхней кромкой. */
    g.RV_WORLD["поза"]("оболочка", {
      "на": [0, 0, 0],
      "от": [0, 0, 12],
      "подход": 6,
      "уход": -2,
      /* Поле сужается по ходу акта: наезд объективом на шар без
         подъезда камеры, марка над ним при этом в кадре остаётся. */
      "поле": [58, 52, 46],
      /* Дуга вбок: за акт камера проходит мимо оболочки справа налево
         на четыре с лишним единицы. Наезда вглубь тут мало (марка висит
         высоко и режется кромкой), а объём шару и параллакс трём слоям
         среды даёт именно смена ракурса. */
      "бок": [2.4, 0.4, -2.0],
      /* Крен: лёгкий завал в начале и обратный в конце, перед проколом.
         В проколе камера довернётся сильно, и поворот, начатый заранее,
         читается как ход; начатый с нуля он читался бы рывком. */
      "крен": [-0.02, 0, 0.04],
      "пролог": 80
    });
    g.RV_WORLD["акт"]("оболочка", МОДУЛЬ);
  }

  /* Ждём подъёма мира, одного наличия RV_WORLD мало: ядро объявляет себя
     сразу, а рисовальщик и сцена появляются позже, на готовой разметке.
     Сборка до этого момента ушла бы в пустоту. */
  if (g.RV_WORLD && g.RV_WORLD["готов"] && g.RV_WORLD["готов"]()) встать();
  else g.addEventListener("rv:мир", встать);
})(window, document);
