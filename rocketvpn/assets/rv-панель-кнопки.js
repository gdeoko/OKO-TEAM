/* Rocket VPN. Две клавиши панели и «Назад»: то, чем кончается фильм.

   ЗАЧЕМ ЭТОТ ФАЙЛ ЕСТЬ. Приёмка последнего кадра нашла обе клавиши
   мёртвыми. В разметке у них стояли признаки `data-к-игре` и
   `data-фин-назад`, а обработчика не было НИ ОДНОГО - ни в одном модуле
   сайта. Человек доезжал до панели, нажимал «Запустить игру» и попадал
   по якорю `#rvИгра` в скрытый блок, то есть никуда; «Назад» не делала
   вовсе ничего.

   Владелец про этот экран: «на Vpn только в конце вопросы и кнопки как
   на сайте cdn 1:1», и отдельно про сам список: «вопросы и 2 кнопки с
   кнопкой назад». Значит все три обязаны работать.

   ЧТО ДЕЛАЮТ КЛАВИШИ.

     Запустить VPN   обычная ссылка в бот, ей код не нужен.
     Запустить игру  открывает гнездо игры на панели и убирает вопросы.
                     Ворота ангара в сцене живут по этому же признаку
                     (rv-act-пуск.js смотрит на `hidden` гнезда), поэтому
                     игра появляется и в разметке, и в объёме разом.
     Назад           пока игра открыта - закрывает её и возвращает
                     вопросы. Когда игры нет - уводит человека в начало
                     ленты, к первому кадру фильма.

   ПОЧЕМУ «НАЗАД» НЕ ВЕДЁТ НА СОСЕДНИЙ САЙТ. Уход на Rocket CDN стоял
   тут раньше, и это было неверно по смыслу: «назад» это шаг назад по
   ЭТОМУ сайту, а не выход с него. Ссылка на соседей живёт в подвале и в
   меню шапки. */
(function (g, d) {
  "use strict";

  var ГНЕЗДО = "rvИграГнездо";

  function гнездо() { return d.getElementById(ГНЕЗДО); }

  function вопросы() {
    return d.querySelector(".рв-фин-впр");
  }

  /* Открыть или закрыть игру. Признак `hidden` тут не украшение: по нему
     же сцена решает, показывать ли ворота ангара, и второго источника
     правды заводить нельзя. */
  function игра(открыть) {
    if (открыть && (!g.RV_WORLD || !g.RV_WORLD["готов"]() || g.RV_WORLD["тихо"]())) return false;
    var гн = гнездо();
    if (!гн) return false;
    гн.hidden = !открыть;
    var в = вопросы();
    if (в) в.hidden = !!открыть;
    /* Кнопка «Пуск» внутри игры получает фокус сама: человек только что
       нажал клавишу и ждёт, что дальше нажимать. */
    if (открыть) {
      try {
        var пуск = d.getElementById("rvИграКн");
        if (пуск && пуск.focus) пуск.focus({ preventScroll: true });
      } catch (e) {}
    } else {
      var launch = d.querySelector("[data-к-игре]");
      if (launch && launch.focus) launch.focus({ preventScroll: true });
    }
    return true;
  }

  /* В начало ленты. Прокрутку ведёт плёнка, и дёргать её мгновенным
     переходом нельзя: сглаживание догоняло бы скачок несколько секунд,
     а человек всё это время смотрел бы на промотку. Просим браузер
     доехать плавно. */
  function вНачало() {
    try {
      g.scrollTo({ top: 0, behavior: g.matchMedia && g.matchMedia("(prefers-reduced-motion: reduce)").matches ? "instant" : "smooth" });
    } catch (e) {
      g.scrollTo(0, 0);
    }
  }

  d.addEventListener("click", function (со) {
    var цель = со.target;
    if (!цель || !цель.closest) return;

    var кИгре = цель.closest("[data-к-игре]");
    if (кИгре) {
      if (игра(true)) со.preventDefault();
      return;
    }

    var назад = цель.closest("[data-фин-назад]");
    if (назад) {
      со.preventDefault();
      var гн = гнездо();
      if (гн && !гн.hidden) { игра(false); return; }
      вНачало();
    }
  }, false);

  g.RV_ПАНЕЛЬ_КНОПКИ = {
    "игра": игра,
    "замер": function () {
      var гн = гнездо(), в = вопросы();
      return {
        "гнездоЕсть": !!гн,
        "играОткрыта": !!(гн && !гн.hidden),
        "вопросыВидны": !!(в && !в.hidden),
        "клавишИгры": d.querySelectorAll("[data-к-игре]").length,
        "клавишНазад": d.querySelectorAll("[data-фин-назад]").length
      };
    }
  };
})(window, document);
