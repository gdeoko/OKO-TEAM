/* Rocket VPN. Акт «Пуск»: три кольца запуска.

   ЗАЧЕМ ЗДЕСЬ ВООБЩЕ ОБЪЁМ. Акт «Пуск» отвечает на вопрос «что делать
   руками» и по смыслу мог бы обойтись текстом. Но сайт это ЛЕНТА: мир
   в нём идёт непрерывно, и акт без объёмного содержимого означает не
   «спокойный кадр», а ЧЁРНЫЙ ЭКРАН - ядро мира рисует сцену только
   пока в кадре есть хоть один живой акт. Два с половиной экрана черноты
   между рубкой и стыковкой рвут ленту пополам.

   ЧТО В КАДРЕ. Три кольца, стоящие в линию вглубь. Они загораются по
   очереди, ровно в том порядке и на тех же долях хода, на которых
   появляются три шага в разметке: открыл бот, поставил приложение,
   вставил ключ. Кольцо, через которое прошли, остаётся гореть - канал
   собирается на глазах и не разбирается обратно.

   Через кольца летит частица: она входит в первое, проходит второе и
   уходит в третье. Это тот самый пакет, который в первом акте вскрывал
   досмотр, и здесь он впервые проходит весь путь целиком.

   ПОЧЕМУ КОЛЬЦА, А НЕ ЩИТ И НЕ СТАНЦИЯ. Железо в этом акте было бы
   враньём: никакого железа человек не ставит, он ставит приложение.
   Кольцо это чистая геометрия хода, и она читается как «пройти
   насквозь» - та же мысль, что несёт весь сайт.
   ═══════════════════════════════════════════════════════════ */
(function (g, d) {
  "use strict";

  var W = null, T = null;
  var собрано = false;
  var М = {};
  var КОЛЕЦ = 3;

  function зажать(v, a, b) { return v < a ? a : (v > b ? b : v); }
  function плавно(t) { t = зажать(t, 0, 1); return t * t * (3 - 2 * t); }
  function отрезок(д, a, b) { return плавно((д - a) / (b - a)); }

  function построить(мир) {
    if (собрано) return true;
    W = мир || W;
    if (!W || !W.T || !W.scene) return false;
    T = W.T;

    var гн = g.RV_WORLD && g.RV_WORLD["гнездо"] ? g.RV_WORLD["гнездо"]("пуск") : null;
    if (!гн) return false;

    М.корень = new T.Group();
    М.корень.visible = false;
    гн.add(М.корень);

    var цИндиго = new T.Color(0x3048A8);
    var цСвет = new T.Color(0x8A9CFF);

    /* Кольца. Тор, а не окружность линией: линия в объёме не имеет
       толщины и на просвет пропадает, стоит камере встать с ней в одну
       плоскость. Тор виден всегда. */
    М.кольца = [];
    var граней = W.ступень === 0 ? 6 : (W.ступень === 1 ? 10 : 16);
    for (var i = 0; i < КОЛЕЦ; i++) {
      var г = new T.Group();
      г.position.z = -6 - i * 13;

      var мат = new T.MeshBasicMaterial({
        color: цСвет, transparent: true, opacity: 0.10,
        depthWrite: false, blending: T.AdditiveBlending
      });
      var тор = new T.Mesh(
        new T.TorusGeometry(4.3 - i * 0.2, 0.09, граней, W.ступень === 0 ? 28 : 64),
        мат
      );
      г.add(тор);

      /* Зубцы по кругу: восемь коротких штрихов снаружи кольца. Голое
         кольцо читается нарисованным кругом, зубцы делают его
         устройством. */
      var зМат = new T.MeshBasicMaterial({
        color: цИндиго, transparent: true, opacity: 0.10,
        depthWrite: false, blending: T.AdditiveBlending
      });
      for (var k = 0; k < 8; k++) {
        var у = (k / 8) * Math.PI * 2;
        var з = new T.Mesh(new T.BoxGeometry(0.10, 0.62, 0.10), зМат);
        var R = 4.3 - i * 0.2 + 0.5;
        з.position.set(Math.cos(у) * R, Math.sin(у) * R, 0);
        з.rotation.z = у;
        г.add(з);
      }

      /* Ореол кольца: плоское пятно за ним. Оно и даёт ощущение, что
         кольцо ГОРИТ, а не покрашено светлым. */
      var оМат = new T.SpriteMaterial({
        map: пятноТекстура(), color: цСвет, transparent: true,
        opacity: 0, blending: T.AdditiveBlending, depthWrite: false
      });
      var ореол = new T.Sprite(оМат);
      ореол.scale.set(19, 19, 1);
      ореол.position.z = -0.4;
      г.add(ореол);

      М.корень.add(г);
      М.кольца.push({ узел: г, тор: мат, зубцы: зМат, ореол: оМат });
    }

    /* Пакет: тот самый, которого вскрывали в первом акте. */
    М.пакет = new T.Mesh(
      new T.SphereGeometry(0.22, W.ступень === 0 ? 8 : 16, W.ступень === 0 ? 6 : 12),
      new T.MeshBasicMaterial({ color: 0xC8D6FF, transparent: true, opacity: 0 })
    );
    М.корень.add(М.пакет);

    М.след = new T.Sprite(new T.SpriteMaterial({
      map: пятноТекстура(), color: цСвет, transparent: true,
      opacity: 0, blending: T.AdditiveBlending, depthWrite: false
    }));
    М.след.scale.set(3.4, 3.4, 1);
    М.корень.add(М.след);

    собрано = true;
    return true;
  }

  /* Мягкое пятно. Одна текстура на весь акт: их тут десяток, и десять
     одинаковых картинок в памяти это десять лишних выгрузок в
     видеопамять на пустом месте. */
  var пятно = null;
  function пятноТекстура() {
    if (пятно) return пятно;
    var c = d.createElement("canvas");
    c.width = c.height = 128;
    var x = c.getContext("2d");
    var гр = x.createRadialGradient(64, 64, 0, 64, 64, 64);
    гр.addColorStop(0, "rgba(255,255,255,1)");
    гр.addColorStop(0.35, "rgba(255,255,255,.34)");
    гр.addColorStop(1, "rgba(255,255,255,0)");
    x.fillStyle = гр;
    x.fillRect(0, 0, 128, 128);
    пятно = new T.CanvasTexture(c);
    return пятно;
  }

  function кадр(доля, dt, часы) {
    if (!собрано && !построить(g.RV_WORLD ? g.RV_WORLD["мир"]() : null)) return;

    /* Появление и уход акта. Как у всех: сцена не имеет права возникать
       готовой и не имеет права оставаться после своего акта. */
    var явь = плавно(доля / 0.10) * (1 - плавно((доля - 0.92) / 0.08));

    /* Кольца зажигаются по очереди. Границы те же, на которых в
       разметке появляются шаги: разметка и мир обязаны говорить об
       одном и том же в один и тот же момент, иначе человек читает
       второй шаг, глядя на первое кольцо. */
    var окна = [[0.10, 0.28], [0.34, 0.52], [0.58, 0.76]];
    for (var i = 0; i < М.кольца.length; i++) {
      var к = М.кольца[i];
      var о = окна[i];
      var г = отрезок(доля, о[0], о[1]);
      /* Пройденное кольцо ОСТАЁТСЯ гореть. Канал собирается и не
         разбирается обратно - это и есть смысл акта.

         ОСНОВА ПОДНЯТА ВТРОЕ по замеру света: на десятой доле кадр был
         занят светом на 0,33 процента при пороге 2 - то есть начало
         акта человек встречал почти чёрным экраном. Причина в том, что
         незажжённое кольцо было почти невидимым, а зажигается первое
         только к трети акта. Кольцо это ЖЕЛЕЗО: оно стоит в космосе и
         до того, как через него пошёл канал, и видеть его надо сразу. */
      var пульс = 1 + 0.12 * Math.sin(часы * 2.4 + i * 1.7) * г;
      к.тор.opacity = (0.32 + 0.68 * г) * явь * пульс;
      к.зубцы.opacity = (0.24 + 0.55 * г) * явь;
      к.ореол.opacity = (0.05 + 0.32 * г) * явь * пульс;
      /* Медленный проворот. Каждое своё в свою сторону: одинаковый
         поворот трёх колец читается одной деталью, повторённой трижды. */
      к.узел.rotation.z = часы * (0.06 + i * 0.03) * (i % 2 ? -1 : 1);
    }

    /* Пакет идёт сквозь все три кольца за акт и уходит дальше. Ход
       чистая функция доли: вверх лента отматывает его назад. */
    var ход = отрезок(доля, 0.08, 0.86);
    var z = 6 - ход * 46;
    М.пакет.position.set(0, 0, z);
    М.след.position.set(0, 0, z);
    var виден = ход > 0.001 && ход < 0.999;
    М.пакет.material.opacity = виден ? явь : 0;
    М.след.material.opacity = виден ? 0.55 * явь : 0;

    М.корень.visible = явь > 0.01;
  }

  /* ── Раскладка по размеру окна ────────────────────────────────
     На мониторе кадр поделён надвое: слева слова, справа мир. Кольца,
     стоящие по оси взгляда, попадали ровно на границу - половина в
     колонке текста, половина в мире. Замер света поймал это числом: в
     той половине кадра, где живёт мир, светом было занято 0,8 процента
     при пороге 2, хотя на глаз кольца горели.

     Сдвигаем их в мир целиком. Камера при этом проходит не сквозь них,
     а вдоль - и это честнее для монитора: сквозной проход читается на
     узком экране, где кольца стоят по центру кадра. */
  var сдвиг = 0;
  function размерить(ш) {
    сдвиг = ш >= 1000 ? 6.4 : (ш >= 760 ? 3.2 : 0);
    if (собрано) М.корень.position.x = сдвиг;
  }

  var МОДУЛЬ = {
    "собрать": function (мир) { построить(мир); размерить(g.innerWidth || 1200); },
    "показать": function (да) {
      if (да && !собрано) построить(g.RV_WORLD ? g.RV_WORLD["мир"]() : null);
      if (собрано) { М.корень.visible = !!да; М.корень.position.x = сдвиг; }
    },
    "кадр": кадр,
    "размер": function (ш) { размерить(ш || g.innerWidth || 1200); }
  };

  function встать() {
    if (!g.RV_WORLD) return;
    /* ПОЗА АКТА. Стоит между рубкой и стыковкой - и теперь не только
       по порядку секций, но и ПО КООРДИНАТАМ.

       Раньше здесь стояло z минус триста пятьдесят два, при том что
       рубка стоит на минус девятистах, а стыковка на минус тысяче
       пятидесяти. Порядок в разметке был верный, а место в мире - нет,
       и камера шла так: вперёд на девятьсот, НАЗАД на пятьсот
       пятьдесят, снова вперёд на семьсот. Замер хода поймал это
       числом: разворот на сто шестьдесят шесть градусов за один шаг
       прокрутки и скачок скорости с полутора единиц до ста сорока
       пяти. Владелец увидел то же самое глазами: «идём в туннель, а
       потом резко поворачивает налево и идёт к другому месту».

       Заодно развёрнут взгляд. Прежняя пара ставила камеру ПОЗАДИ цели
       по оси Z, то есть смотрящей назад, против общего хода фильма.
       Теперь камера смотрит туда же, куда идёт весь сайт - вглубь.

       Камера идёт СКВОЗЬ кольца, а не мимо них: подход перед первым,
       уход за третьим. Это единственный акт, где человек проходит
       содержимое насквозь физически, и после «Прокола» это читается
       рифмой, а не повтором. */
    g.RV_WORLD["поза"]("пуск", {
      "на": [-58, 24, -975],
      "от": [-62, 26, -930],
      "подход": 12,
      "уход": -34,
      "поле": [48, 44, 40],
      "бок": [0, 0, 0],
      "крен": [0.04, 0, -0.04]
    });
    g.RV_WORLD["акт"]("пуск", МОДУЛЬ);
  }

  if (g.RV_WORLD && g.RV_WORLD["готов"] && g.RV_WORLD["готов"]()) встать();
  else g.addEventListener("rv:мир", встать);
})(window, document);
