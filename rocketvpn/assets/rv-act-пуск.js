/* Rocket VPN. Акт «Пуск»: три кольца запуска.

   ЗАЧЕМ ЗДЕСЬ ВООБЩЕ ОБЪЁМ. Акт «Пуск» отвечает на вопрос «что делать
   руками» и по смыслу мог бы обойтись текстом. Но сайт это ЛЕНТА: мир
   в нём идёт непрерывно, и акт без объёмного содержимого означает не
   «спокойный кадр», а ЧЁРНЫЙ ЭКРАН - ядро мира рисует сцену только
   пока в кадре есть хоть один живой акт. Два с половиной экрана черноты
   между рубкой и стыковкой рвут ленту пополам.

   ЧТО В КАДРЕ. Три кольца, стоящие в линию вглубь. Они загораются по
   очереди, ровно в том порядке и на тех же долях хода, на которых
   появляются три шага в разметке: открыл бот, поставил приложение,
   вставил ключ. Кольцо, через которое прошли, остаётся гореть - канал
   собирается на глазах и не разбирается обратно.

   Через кольца летит частица: она входит в первое, проходит второе и
   уходит в третье. Это тот самый пакет, который в первом акте вскрывал
   досмотр, и здесь он впервые проходит весь путь целиком.

   ПОЧЕМУ КОЛЬЦА, А НЕ ЩИТ И НЕ СТАНЦИЯ. Кольцо это чистая геометрия
   хода, и она читается как «пройти насквозь» - та же мысль, что несёт
   весь сайт. Щит или станция здесь спорили бы с соседними актами.

   ПОЧЕМУ КОЛЬЦА ИЗ ЖЕЛЕЗА, А НЕ СВЕТЯЩИЕСЯ ЛИНИИ. Первый заход рисовал
   их полупрозрачными складывающимися окружностями, и середина ленты
   (рубка -> стыковка) стояла почти чёрной: три тонких линии не держат
   кадр. Теперь кольцо это предмет: массивный тор на общем корпусе
   (RV_REAL.корпус, тот же материал, что у станции и корабля), с
   горящей внутренней губой, зубцами по ободу и бортовыми маячками.
   Зажигание стало событием с формой: по кольцу обегает заряд, зубцы
   подтягиваются с отдачей, губа вспыхивает выше единицы и ореол плёнки
   подхватывает её. Пакет тянет за собой шлейф света и хвост из точек,
   и кольца вздрагивают, когда он проходит сквозь них.

   ВСЁ ЧИСТАЯ ФУНКЦИЯ ДОЛИ. Лента отматывается назад, и заряд, хвост,
   зубцы обязаны разворачиваться вместе с ней, без своего состояния.
   ═══════════════════════════════════════════════════════════ */
(function (g, d) {
  "use strict";

  var W = null, T = null;
  var собрано = false;
  var М = {};
  var КОЛЕЦ = 3;
  var ЗУБЦОВ = 24;      /* на кольцо */
  var МАЯЧКОВ = 8;      /* на кольцо: чётные красные, нечётные зелёные */
  var ШЛЕЙФА = 32;      /* пластин света за пакетом (ступень 0: 12) */
  var ХВОСТА = 48;      /* точек хвоста за пакетом */

  /* Окна зажигания совпадают с шагами разметки (открыл бот, поставил
     приложение, вставил ключ). Двигать нельзя: разметка и мир обязаны
     говорить об одном и том же в один и тот же момент. */
  var ОКНА = [[0.10, 0.28], [0.34, 0.52], [0.58, 0.76]];

  function зажать(v, a, b) { return v < a ? a : (v > b ? b : v); }
  function плавно(t) { t = зажать(t, 0, 1); return t * t * (3 - 2 * t); }
  function отрезок(д, a, b) { return плавно((д - a) / (b - a)); }
  /* Отдача: проскок за цель и возврат. Так зубцы «схватывают» кольцо,
     а не подъезжают к нему как по рельсам. */
  function отдача(t) {
    t = зажать(t, 0, 1);
    var s = 1.70158, u = t - 1;
    return 1 + (s + 1) * u * u * u + s * u * u;
  }
  function радиус(i) { return 4.3 - i * 0.2; }

  /* Один служебный узел на все инстансы: собирать матрицу через него
     дешевле и понятнее, чем руками из синусов. */
  var ставень = null, цв = null, камЛок = null;

  function построить(мир) {
    if (собрано) return true;
    W = мир || W;
    if (!W || !W.T || !W.scene) return false;
    T = W.T;
    if (!g.RV_REAL || !g.RV_REAL["корпус"]) return false;

    var гн = g.RV_WORLD && g.RV_WORLD["гнездо"] ? g.RV_WORLD["гнездо"]("пуск") : null;
    if (!гн) return false;

    var ст = W.ступень;
    ставень = new T.Object3D();
    цв = new T.Color();
    камЛок = new T.Vector3();

    М.корень = new T.Group();
    /* РАКЕТА ИЗ ЧАСТИЦ. Владелец: «ракету делаем сами но по механике
       как у них сделаны частицы со свечением». Сборка в rv-частицы.js:
       точки снимаются с поверхности нашей ракеты по площади граней и
       живут завихрением вокруг своего дома. */
    if (g.RV_ЧАСТИЦЫ && g.RV_ЧАСТИЦЫ["собрать"]) {
      М.рой = g.RV_ЧАСТИЦЫ["собрать"](мир, М.корень, { размер: 13.0 });
      if (М.рой) {
        /* Ракета стоит НЕ на оси кольца. В центре она тонула в его
           свечении: замер показал рой ровно в середине кадра, там же,
           где ядро кольца. Сдвиг влево и вверх выводит её на тёмное
           поле, и силуэт из точек читается. */
        М.рой.position.set(-3.4, 1.6, 2.0);
        М.рой.scale.setScalar(3.6);
      }
    }
    /* ── Ворота мини-игры ───────────────────────────────────────
       Владелец: «за мини игру получаешь бесплатно 3 дня ВПН логично?».
       Створки встают перед ракетой, на её оси: игра про то же, про что
       весь сайт, - провести канал сквозь стену. Ставятся ПОСЛЕ роя,
       чтобы взять его настоящее место, а не повторять числа. */
    if (g.RV_ИГРА && g.RV_ИГРА["собрать"]) {
      М.ворота = g.RV_ИГРА["собрать"](мир, М.корень, {
        ось: М.рой ? М.рой.position.clone() : new T.Vector3(-3.4, 1.6, 2.0),
        z: -7.5, размах: 5.2, проём: 2.0
      });
    }
    М.корень.visible = false;
    гн.add(М.корень);

    var цСвет = new T.Color(0x8A9CFF);
    М.цСвет = цСвет;
    М.цКрасный = new T.Color(0xFF4A3C);
    М.цЗелёный = new T.Color(0x4AFF9A);

    /* Свой ключ и контровой в корне акта, как у щита в рубке. Стан
       мира поставлен под планету и станции, а гнездо пуска развёрнуто
       лицом к камере: без своего света лицевая сторона тора, которую
       и видит человек, оставалась тёмной плитой без блика. Источники
       живут в корне и гаснут вместе с ним. */
    var ключ = new T.DirectionalLight(0xEAEFFF, 3.4);
    ключ.position.set(-3.6, 5.2, 8.0);
    М.корень.add(ключ);
    М.корень.add(ключ.target);
    var кромка = new T.DirectionalLight(0x6E7EE0, 2.2);
    кромка.position.set(4.6, -3.2, -7.0);
    М.корень.add(кромка);
    М.корень.add(кромка.target);

    /* Зажжённое кольцо освещает соседей. Одна лампа на акт, она
       переезжает к последнему зажжённому кольцу. Только на полной
       ступени: точечный свет прибавляет работы каждому физическому
       материалу в кадре. Сила в канделах (three считает свет честно,
       с падением по квадрату расстояния): три единицы из плана на
       пяти единицах до тора дали бы ноль, поэтому число крупнее. */
    М.лампа = null;
    if (ст === 2) {
      М.лампа = new T.PointLight(0x8A9CFF, 0, 18, 2);
      М.корень.add(М.лампа);
    }

    var сегм = ст === 0 ? 40 : 112;
    var труб = ст === 0 ? 8 : 20;

    /* Зубцы и их наконечники: по одному инстанс-вызову на все три
       кольца. Семьдесят два отдельных меша это семьдесят два вызова
       рисования на пустом месте. Зубцы лежат прямо в корне, минуя узел
       кольца, поэтому поворот кольца и отклик на пакет входят в их
       матрицы руками каждый кадр. */
    var матЗуб = g.RV_REAL["корпус"](T, {
      цвет: 0x3F4A78, металл: 0.9, шерох: 0.3, свет: 0x121B45, жар: 0.15, лак: 0.35
    });
    М.зубцы = new T.InstancedMesh(new T.BoxGeometry(0.12, 0.7, 0.14), матЗуб, КОЛЕЦ * ЗУБЦОВ);
    М.зубцы.frustumCulled = false;
    М.корень.add(М.зубцы);

    /* Наконечники и маячки: самосветящиеся, цвет через instanceColor.
       Основа белая, чтобы цвет экземпляра ложился в кадр как есть:
       любая другая основа помножила бы его на себя. */
    М.наконечники = new T.InstancedMesh(
      new T.SphereGeometry(0.05, 6, 5),
      new T.MeshBasicMaterial({ color: 0xFFFFFF, toneMapped: false }),
      КОЛЕЦ * ЗУБЦОВ
    );
    М.наконечники.frustumCulled = false;
    М.корень.add(М.наконечники);

    /* Маячки: первый красный и зелёный на сайте. Держатся мелкими,
       чтобы палитра не спорила с индиго: они задают масштаб и жизнь,
       как бортовые огни, и кадр остаётся в индиго. */
    М.маячки = new T.InstancedMesh(
      new T.SphereGeometry(0.12, 8, 6),
      new T.MeshBasicMaterial({ color: 0xFFFFFF, toneMapped: false }),
      КОЛЕЦ * МАЯЧКОВ
    );
    М.маячки.frustumCulled = false;
    М.корень.add(М.маячки);

    var i, k;
    for (i = 0; i < КОЛЕЦ * ЗУБЦОВ; i++) М.наконечники.setColorAt(i, цСвет);
    for (i = 0; i < КОЛЕЦ * МАЯЧКОВ; i++) М.маячки.setColorAt(i, i % 2 ? М.цЗелёный : М.цКрасный);

    /* Кольца. Тор на корпусе. Окружность линией и прозрачный тор
       отпали: линия на просвет пропадает, прозрачный тор уходит в
       прозрачный проход и просвечивает сам сквозь себя. Корпус
       непрозрачен, стоит в честной глубине и ловит свет. */
    М.кольца = [];
    for (i = 0; i < КОЛЕЦ; i++) {
      var R = радиус(i);
      var узел = new T.Group();
      узел.position.z = -6 - i * 13;

      var матТор = g.RV_REAL["корпус"](T, {
        цвет: 0x3F4A78, металл: 0.9, шерох: 0.3, свет: 0x121B45, жар: 0.15, лак: 0.35
      });
      узел.add(new T.Mesh(new T.TorusGeometry(R, 0.26, труб, сегм), матТор));

      /* Внутренняя губа: тонкий тор по внутреннему краю тела. Сидит
         чуть глубже внутреннего края (R минус 0.30 при теле до R минус
         0.26), иначе она тонула бы внутри тела и не читалась.
         Самосветящаяся без прозрачности и с записью глубины: зажигание
         это цвет ВЫШЕ единицы при полной альфе, и ореол плёнки
         подхватывает его сам. */
      var матГуба = new T.MeshBasicMaterial({ color: 0x8A9CFF, toneMapped: false });
      узел.add(new T.Mesh(new T.TorusGeometry(R - 0.30, 0.06, 8, сегм), матГуба));

      /* Заряд: дуга, обегающая кольцо в окне зажигания. Сидит на
         радиусе тела и шире его трубки: светящаяся муфта, надетая на
         железо, читается как заряд, бегущий ПО кольцу. Первый заход
         клал дугу на губу, и на снимке её было не отличить от самой
         губы, которая к середине окна уже горит выше единицы. Только
         на средней и полной ступени: на нищей само зажигание губы уже
         событие. */
      var заряд = null;
      if (ст > 0) {
        var цЗаряд = цСвет.clone().multiplyScalar(2.2);
        заряд = new T.Mesh(
          new T.TorusGeometry(R, 0.36, 8, 64, 0.9),
          new T.MeshBasicMaterial({
            color: цЗаряд, transparent: true, opacity: 0,
            depthWrite: false, blending: T.AdditiveBlending, toneMapped: false
          })
        );
        заряд.visible = false;
        узел.add(заряд);
      }

      /* Ореол кольца: плоское пятно за ним. Оно и даёт ощущение, что
         кольцо ГОРИТ: без пятна оно выглядит покрашенным светлым. */
      var оМат = new T.SpriteMaterial({
        map: пятноТекстура(), color: цСвет, transparent: true,
        opacity: 0, blending: T.AdditiveBlending, depthWrite: false
      });
      var ореол = new T.Sprite(оМат);
      ореол.scale.set(19, 19, 1);
      ореол.position.z = -0.4;
      узел.add(ореол);

      М.корень.add(узел);
      М.кольца.push({ узел: узел, тор: матТор, губа: матГуба, заряд: заряд, ореол: оМат, R: R, z: узел.position.z });
    }

    /* Пакет: тот самый, которого вскрывали в первом акте. Теперь это
       предмет с материалом: гладкий шар, светящийся изнутри, с лаком
       на полной ступени. */
    М.пакет = new T.Mesh(
      new T.SphereGeometry(0.22, ст === 0 ? 8 : 16, ст === 0 ? 6 : 12),
      new T.MeshPhysicalMaterial({
        color: 0xC8D6FF, metalness: 0, roughness: 0.15,
        emissive: 0x8A9CFF, emissiveIntensity: 3.5,
        clearcoat: ст === 2 ? 1 : 0
      })
    );
    М.пакет.visible = false;
    М.корень.add(М.пакет);

    /* Шлейф: пластины света за пакетом, парами крест-накрест. Одна
       плоскость с оси камеры видна ребром (на телефоне камера идёт
       ровно по оси), две скрещённые читаются с любой стороны. Полоса
       геометрии повёрнута вдоль оси хода, положение и яркость каждой
       пары считаются от хода каждый кадр. */
    М.шлейфа = ст === 0 ? 12 : ШЛЕЙФА;
    var пластина = new T.PlaneGeometry(0.16, 1.2);
    пластина.rotateX(Math.PI / 2);
    М.шлейф = new T.InstancedMesh(
      пластина,
      new T.MeshBasicMaterial({
        color: 0xFFFFFF, transparent: true, depthWrite: false,
        blending: T.AdditiveBlending, side: T.DoubleSide, toneMapped: false
      }),
      М.шлейфа * 2
    );
    М.шлейф.frustumCulled = false;
    for (i = 0; i < М.шлейфа * 2; i++) М.шлейф.setColorAt(i, цСвет);
    М.корень.add(М.шлейф);

    /* Хвост из точек по пройденному пути. Положение каждой точки
       считается в шейдере от хода пакета: на процессоре ничего не
       пересчитывается, а при отмотке хвост разворачивается сам.
       Имена внутри шейдера латиницей: кириллица в GLSL ломает разбор. */
    М.хвост = null;
    if (ст > 0) {
      var гХ = new T.BufferGeometry();
      var поз = new Float32Array(ХВОСТА * 3);
      var лаг = new Float32Array(ХВОСТА);
      for (k = 0; k < ХВОСТА; k++) лаг[k] = k + 1;
      гХ.setAttribute("position", new T.BufferAttribute(поз, 3));
      гХ.setAttribute("aLag", new T.BufferAttribute(лаг, 1));
      var мХ = new T.ShaderMaterial({
        uniforms: {
          zP: { value: 6 }, yav: { value: 0 }, n: { value: ХВОСТА },
          zStart: { value: 6 }, hpx: { value: 800 }, col: { value: цСвет }
        },
        vertexShader: [
          "attribute float aLag;",
          "uniform float zP; uniform float yav; uniform float n; uniform float zStart; uniform float hpx;",
          "varying float vA;",
          "void main(){",
          "  float z = zP + aLag * 0.8;",
          "  float w = 1.0 - aLag / n;",
          /* Точка позади старта пакета не существует: хвост не может
             быть длиннее пройденного пути. */
          "  vA = w * w * yav * step(z, zStart);",
          "  vec4 mv = modelViewMatrix * vec4(0.0, 0.0, z, 1.0);",
          "  gl_PointSize = (0.06 + 0.22 * w) * hpx * 0.5 * projectionMatrix[1][1] / max(0.1, -mv.z);",
          "  gl_Position = projectionMatrix * mv;",
          "}"
        ].join("\n"),
        fragmentShader: [
          "uniform vec3 col; varying float vA;",
          "void main(){",
          "  vec2 p = gl_PointCoord - 0.5;",
          "  float a = smoothstep(1.0, 0.15, dot(p, p) * 4.0);",
          "  gl_FragColor = vec4(col * vA * a, 1.0);",
          "}"
        ].join("\n"),
        transparent: true, depthWrite: false, blending: T.AdditiveBlending
      });
      М.хвост = new T.Points(гХ, мХ);
      М.хвост.frustumCulled = false;
      М.корень.add(М.хвост);
    }

    собрано = true;
    return true;
  }

  /* Матрица одного экземпляра: положение на окружности радиуса r на
     глубине z, повёрнутая по касательной. Масштаб ноль прячет
     экземпляр: у инстансов нет своего visible. */
  function поставить(меш, n, у, r, z, виден) {
    ставень.position.set(Math.cos(у) * r, Math.sin(у) * r, z);
    ставень.rotation.set(0, 0, у);
    ставень.scale.setScalar(виден ? 1 : 0);
    ставень.updateMatrix();
    меш.setMatrixAt(n, ставень.matrix);
  }

  /* Мягкое пятно. Одна текстура на весь акт: их тут десяток, и десять
     одинаковых картинок в памяти это десять лишних выгрузок в
     видеопамять на пустом месте. */
  var пятно = null;
  function пятноТекстура() {
    if (пятно) return пятно;
    var c = d.createElement("canvas");
    c.width = c.height = 128;
    var x = c.getContext("2d");
    var гр = x.createRadialGradient(64, 64, 0, 64, 64, 64);
    гр.addColorStop(0, "rgba(255,255,255,1)");
    гр.addColorStop(0.35, "rgba(255,255,255,.34)");
    гр.addColorStop(1, "rgba(255,255,255,0)");
    x.fillStyle = гр;
    x.fillRect(0, 0, 128, 128);
    пятно = new T.CanvasTexture(c);
    return пятно;
  }

  function кадр(доля, dt, часы) {
    /* КОМНАТА И ЕЁ ФОН. Акт стоит на дне шахты, вокруг фигуры из частиц.
       Пол, дымка, цилиндр текста и сам градиент принадлежат не ему, а
       месту: гаснут они только когда последний акт ушёл из комнаты. Луны
       здесь нет вовсе - мы под грунтом. */
    if (g.RV_КОМНАТА && g.RV_КОМНАТА["собрать"]) {
      g.RV_КОМНАТА["собрать"](W, { x: 0, y: -30, z: 76 });
      g.RV_КОМНАТА["видно"](true, "пуск");
      g.RV_КОМНАТА["кадр"](1, dt, часы);
    }
    if (g.RV_ФОН) { g.RV_ФОН["собрать"](W); g.RV_ФОН["сила"](1); g.RV_ФОН["кадр"](часы); }
    try { if (g.RV_ЛУНА && g.RV_ЛУНА["подземка"]) g.RV_ЛУНА["подземка"](true); } catch (eЛ) {}

    /* Рой ракеты: время идёт всегда, разлёт растёт к концу акта -
       ракета уходит, рассыпаясь, и это тот же приём, которым у igloo
       рассыпается голова моаи. */
    if (g.RV_ЧАСТИЦЫ && М.рой) {
      g.RV_ЧАСТИЦЫ["кадр"](dt, часы);
      /* Разлёт по ходу акта отдан игре, когда она живёт: два хозяина у
         одного числа спорили бы, и рой на попадании всё равно уходил бы
         в рассыпание по прокрутке. За воротами акт распоряжается им сам. */
      if (!(g.RV_ИГРА && М.ворота && доля > 0.34 && доля < 0.94)) {
        g.RV_ЧАСТИЦЫ["разлёт"](Math.max(0, (доля - 0.62) / 0.38) * 0.9);
      }
    }
    if (g.RV_ИГРА && М.ворота) g.RV_ИГРА["кадр"](доля, dt, часы);
    if (!собрано && !построить(g.RV_WORLD ? g.RV_WORLD["мир"]() : null)) return;

    /* Появление и уход акта. Как у всех: сцена не имеет права возникать
       готовой и не имеет права оставаться после своего акта. */
    var явь = плавно(доля / 0.10) * (1 - плавно((доля - 0.92) / 0.08));

    var есть = явь > 0.01;
    М.корень.visible = есть;
    if (!есть) return;

    /* Пакет идёт сквозь все три кольца за акт и уходит дальше. Ход
       чистая функция доли: вверх лента отматывает его назад. Считается
       ДО колец: кольца откликаются на его проход. */
    var ход = отрезок(доля, 0.08, 0.86);
    var zП = 6 - ход * 46;
    var виден = ход > 0.001 && ход < 0.999;

    /* Камера в координатах акта. На телефоне сдвига нет и камера идёт
       ровно сквозь кольца: тор с трубкой 0.26 при ближней плоскости
       0.1 давал бы чёрный клин на пол-экрана. Кольцо, в котором сейчас
       стоит камера, гасится целиком. */
    камЛок.set(0, 0, 0);
    if (W.cam) { камЛок.copy(W.cam.position); М.корень.worldToLocal(камЛок); }

    var горит = -1, i, k, n;
    for (i = 0; i < М.кольца.length; i++) {
      var к = М.кольца[i];
      var о = ОКНА[i];
      var г = отрезок(доля, о[0], о[1]);
      if (г > 0.5) горит = i;

      /* Схватывание: сразу после окна губа на миг ярче стационара и
         возвращается. Без этого зажигание заканчивается ничем, а
         событию нужна точка. */
      var после = (доля - о[1]) / 0.03;
      var пере = (после > 0 && после < 1) ? 0.25 * Math.sin(после * Math.PI) : 0;

      /* Ореолы дышат в противофазе, только на зажжённом. Отклик: кольцо
         вздрагивает и вспыхивает, когда пакет проходит сквозь него. */
      var пульс = 1 + 0.12 * Math.sin(часы * 2.4 + i * 2.1) * г;
      var dz = (zП - к.z) / 2.5;
      var отклик = виден ? Math.exp(-dz * dz) : 0;
      var масштаб = 1 + 0.10 * отклик;

      /* Пройденное кольцо ОСТАЁТСЯ гореть. Канал собирается и не
         разбирается обратно - это и есть смысл акта. Незажжённое
         кольцо читается железом от света, а губа у него тлеет на 0.6:
         замер света на десятой доле требует, чтобы начало акта не
         встречало человека чёрным экраном. */
      к.губа.color.copy(М.цСвет).multiplyScalar((0.6 + 4.0 * г) * пульс * (1 + пере) + 0.8 * отклик);
      к.тор.жар(г * (1 + пере) + 0.3 * отклик);
      к.ореол.opacity = ((0.05 + 0.32 * г) * пульс + 0.2 * отклик) * явь;
      к.узел.scale.setScalar(масштаб);
      /* Медленный проворот. Каждое своё в свою сторону: одинаковый
         поворот трёх колец читается одной деталью, повторённой трижды. */
      var поворот = часы * (0.06 + i * 0.03) * (i % 2 ? -1 : 1);
      к.узел.rotation.z = поворот;

      var близко = Math.abs(камЛок.z - к.z) < 0.5;
      к.узел.visible = !близко;

      /* Заряд обегает губу два раза за окно: один оборот читается как
         дрожь точки, два уже как бег по кольцу. Яркость по параболе
         4г(1-г): на краях окна она ноль, и заряд не возникает и не
         пропадает рывком при любой скорости прокрутки. */
      if (к.заряд) {
        var вОкне = доля > о[0] && доля < о[1] && !близко;
        к.заряд.visible = вОкне;
        if (вОкне) {
          к.заряд.rotation.z = г * Math.PI * 4;
          к.заряд.material.opacity = 4 * г * (1 - г) * явь;
        }
      }

      /* Зубцы: с отдачей подтягиваются к кольцу при зажигании и чуть
         дрейфуют по своему синусу, чтобы три кольца не шли в ногу. */
      var дрейф = 0.02 * Math.sin(часы * 1.3 + i * 2.0);
      var rЗ = (к.R + 0.5 - 0.25 * отдача(г)) * масштаб;
      цв.copy(М.цСвет).multiplyScalar((0.2 + 2.5 * г) * явь);
      for (k = 0; k < ЗУБЦОВ; k++) {
        n = i * ЗУБЦОВ + k;
        var у = (k / ЗУБЦОВ) * Math.PI * 2 + поворот + дрейф;
        поставить(М.зубцы, n, у, rЗ, к.z, !близко);
        поставить(М.наконечники, n, у, rЗ + 0.35, к.z, !близко);
        М.наконечники.setColorAt(n, цв);
      }

      /* Маячки на внешнем ободе: мигают раз в кадр, красные и зелёные
         в своей фазе, как бортовые огни. */
      for (k = 0; k < МАЯЧКОВ; k++) {
        n = i * МАЯЧКОВ + k;
        var уМ = ((k + 0.5) / МАЯЧКОВ) * Math.PI * 2 + поворот;
        поставить(М.маячки, n, уМ, (к.R + 0.26) * масштаб, к.z, !близко);
        var фаза = (i * МАЯЧКОВ + k) * 0.37;
        var миг = (часы * 0.9 + фаза) % 1 < 0.5 ? 0.25 : 1;
        цв.copy(k % 2 ? М.цЗелёный : М.цКрасный).multiplyScalar(3 * миг * явь);
        М.маячки.setColorAt(n, цв);
      }
    }
    М.зубцы.instanceMatrix.needsUpdate = true;
    М.наконечники.instanceMatrix.needsUpdate = true;
    М.наконечники.instanceColor.needsUpdate = true;
    М.маячки.instanceMatrix.needsUpdate = true;
    М.маячки.instanceColor.needsUpdate = true;

    /* Лампа одна на все кольца и переезжает в центр последнего
       зажжённого: точечный свет дорожает каждому физическому материалу
       в кадре, а глаз всё равно смотрит туда, где только что зажглось.
       Сила помножена на явь: на перегоне лампа не должна подсвечивать
       соседний акт. */
    if (М.лампа) {
      if (горит >= 0) {
        М.лампа.position.z = М.кольца[горит].z;
        М.лампа.intensity = 60 * явь;
      } else М.лампа.intensity = 0;
    }

    /* Пакет и его шлейф: пластины уходят назад по пройденному пути,
       ярче к пакету и не длиннее того, что он прошёл. */
    М.пакет.position.set(0, 0, zП);
    М.пакет.visible = виден;
    var шаг = 0.9;
    for (k = 0; k < М.шлейфа; k++) {
      var zШ = zП + (k + 1) * шаг;
      var видна = виден && zШ <= 6;
      var w = 1 - k / М.шлейфа;
      ставень.position.set(0, 0, zШ);
      ставень.scale.setScalar(видна ? 1 : 0);
      ставень.rotation.set(0, 0, 0);
      ставень.updateMatrix();
      М.шлейф.setMatrixAt(k * 2, ставень.matrix);
      ставень.rotation.set(0, 0, Math.PI / 2);
      ставень.updateMatrix();
      М.шлейф.setMatrixAt(k * 2 + 1, ставень.matrix);
      цв.copy(М.цСвет).multiplyScalar(w * w * явь * 1.6);
      М.шлейф.setColorAt(k * 2, цв);
      М.шлейф.setColorAt(k * 2 + 1, цв);
    }
    М.шлейф.instanceMatrix.needsUpdate = true;
    М.шлейф.instanceColor.needsUpdate = true;

    if (М.хвост) {
      var u = М.хвост.material.uniforms;
      u.zP.value = zП;
      u.yav.value = виден ? явь : 0;
      u.hpx.value = (W.r && W.r.domElement && W.r.domElement.height) || 800;
      М.хвост.visible = виден;
    }
  }

  /* ── Раскладка по размеру окна ────────────────────────────────
     На мониторе кадр поделён надвое: слева слова, справа мир. Кольца,
     стоящие по оси взгляда, попадали ровно на границу - половина в
     колонке текста, половина в мире. Замер света поймал это числом: в
     той половине кадра, где живёт мир, светом было занято 0,8 процента
     при пороге 2, хотя на глаз кольца горели.

     Сдвигаем их в мир целиком. Камера при этом проходит не сквозь них,
     а вдоль - и это честнее для монитора: сквозной проход читается на
     узком экране, где кольца стоят по центру кадра. */
  var сдвиг = 0;
  function размерить(ш) {
    сдвиг = ш >= 1000 ? 6.4 : (ш >= 760 ? 3.2 : 0);
    if (собрано) М.корень.position.x = сдвиг;
  }

  var МОДУЛЬ = {
    "собрать": function (мир) { построить(мир); размерить(g.innerWidth || 1200); },
    "показать": function (да) {
      if (да && !собрано) построить(g.RV_WORLD ? g.RV_WORLD["мир"]() : null);
      if (собрано) { М.корень.visible = !!да; М.корень.position.x = сдвиг; }
    },
    "кадр": кадр,
    "размер": function (ш) { размерить(ш || g.innerWidth || 1200); }
  };

  function встать() {
    if (!g.RV_WORLD) return;
    /* ПОЗА АКТА. Стоит между рубкой и стыковкой - и теперь не только
       по порядку секций, но и ПО КООРДИНАТАМ.

       Раньше здесь стояло z минус триста пятьдесят два, при том что
       рубка стоит на минус девятистах, а стыковка на минус тысяче
       пятидесяти. Порядок в разметке был верный, а место в мире - нет,
       и камера шла так: вперёд на девятьсот, НАЗАД на пятьсот
       пятьдесят, снова вперёд на семьсот. Замер хода поймал это
       числом: разворот на сто шестьдесят шесть градусов за один шаг
       прокрутки и скачок скорости с полутора единиц до ста сорока
       пяти. Владелец увидел то же самое глазами: «идём в туннель, а
       потом резко поворачивает налево и идёт к другому месту».

       Заодно развёрнут взгляд. Прежняя пара ставила камеру ПОЗАДИ цели
       по оси Z, то есть смотрящей назад, против общего хода фильма.
       Теперь камера смотрит туда же, куда идёт весь сайт - вглубь.

       Камера идёт СКВОЗЬ кольца: подход перед первым,
       уход за третьим. Это единственный акт, где человек проходит
       содержимое насквозь физически, и после «Прокола» это читается
       рифмой, повтора глаз в этом не видит.

       СКВОЗНОЙ ПРОХОД СТАЛ ПРАВДОЙ, А НЕ ОБЕЩАНИЕМ. Стояла пара
       на [-58,24,-975] и от [-62,26,-930]: камера сидела в сорока пяти
       единицах от станции, а не в двенадцати, и уход минус тридцать
       четыре оставлял её в одиннадцати единицах ПЕРЕД станцией. Кольца
       стоят за станцией на 6, 19 и 32 единицы, то есть камера не
       доходила до ПЕРВОГО кольца семнадцать единиц, при том что
       комментарий рядом обещал проход сквозь все три. Теперь камера
       стоит в двенадцати единицах, как на прочих станциях, идёт с
       тридцати шести единиц перед станцией до пятидесяти трёх за ней и
       проходит все три кольца насквозь, выходя за последнее на
       двадцать одну единицу.

       Станция переехала вместе со всем миром на общую линию коридора:
       была в 82 единицах от стыковки и в 233 от рубки, теперь в 248 и
       200. Перегоны выровнены, перелом курса на станции 14 градусов
       вместо 48. */
    /* ── ПУСК ЭТО ВТОРАЯ ОСТАНОВКА ОБХОДА ────────────────────────
       Та же комната, та же фигура в середине, камера продвинулась по
       окружности ещё на восемьдесят пять градусов. Человек обходит
       фигуру и видит её с другой стороны - это и есть «по скроллу мы
       обходим вокруг». Отдельного места у пуска больше нет: он был за
       восемьсот единиц отсюда, и перелёт туда рвал сцену надвое.

       Прицел тот же самый, что у ангара: фигура остаётся в середине
       кадра всю дорогу, а меняется только то, с какой стороны на неё
       смотрят и какие слова стоят рядом. */
    g.RV_WORLD["поза"]("пуск", {
      "на": [0, -22.5, 76],
      "от": [25.11, -19.0, 69.27],
      "подход": 2,
      "уход": -3,
      "поле": [44, 44, 46],
      "бок": [-15, 0, 16],
      "крен": [0, 0, 0]
    });
    g.RV_WORLD["акт"]("пуск", МОДУЛЬ);
  }

  if (g.RV_WORLD && g.RV_WORLD["готов"] && g.RV_WORLD["готов"]()) встать();
  else g.addEventListener("rv:мир", встать);
})(window, document);
