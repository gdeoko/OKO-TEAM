/* ═══════════════════════════════════════════════════════════
   Rocket VPN · счётчик для общей панели

   Панель одна на два сайта, значит и счётчик один. Этот файл
   отправляет события сюда же, куда их шлёт Rocket CDN, только с
   пометкой site=vpn: `https://rocketcdn.ru/api.php?action=track`.

   ПОЧЕМУ НЕ СВОЙ СЕРВЕР У КАЖДОГО САЙТА. Два хранилища означают две
   правды: посчитать общую воронку по ним нельзя, а сравнить сайты
   между собой можно только на глаз. Хранилище одно, разрез по сайту
   лежит внутри.

   ЧТО СОБИРАЕМ И ЧЕГО НЕ СОБИРАЕМ. Собираем: заход, номер акта, до
   какого места дошёл человек, нажатия по кнопкам входа и ухода в
   космос, включение звука, ошибки в консоли. Не собираем ничего, чем
   человека можно узнать: ни адреса, ни отпечатка браузера, ни текста
   с экрана. Метка сессии живёт в памяти вкладки и умирает вместе с
   ней - это счётчик посещений, а не слежка.

   ПОЧЕМУ ПАЧКОЙ. Сайт это фильм на восемь актов, и человек проходит
   их за минуту. Слать запрос на каждый акт значит восемь запросов на
   посещение и восемь пересчётов файла статистики на сервере. Копим
   до пяти событий или до двух секунд, а на уходе досылаем остаток
   через sendBeacon: он уходит даже когда вкладку уже закрыли.
   ═══════════════════════════════════════════════════════════ */
(function (g, d) {
  "use strict";

  var АДРЕС = "https://rocketcdn.ru/api.php?action=track&site=vpn";

  /* Уважаем «не отслеживать». Счётчик посещений это не то, ради чего
     стоит спорить с настройкой браузера. */
  try {
    if (navigator.doNotTrack === "1" || g.doNotTrack === "1") return;
  } catch (e) {}

  /* Метка сессии живёт в памяти вкладки. Не в хранилище: там она
     пережила бы закрытие браузера и превратилась бы в постоянный
     идентификатор человека, а нам нужно только «сколько разных
     заходов за сутки». */
  var метка = "";
  try {
    метка = sessionStorage.getItem("rv-сессия") || "";
    if (!метка) {
      метка = "v" + Date.now().toString(36) + Math.random().toString(36).slice(2, 8);
      sessionStorage.setItem("rv-сессия", метка);
    }
  } catch (e2) {
    метка = "v" + Date.now().toString(36) + Math.random().toString(36).slice(2, 8);
  }

  var очередь = [];
  var таймер = 0;
  var ушли = false;

  function отправить(маяком) {
    if (!очередь.length) return;
    var тело = JSON.stringify({
      sid: метка,
      ref: d.referrer || "",
      events: очередь.splice(0, 25)
    });
    if (таймер) { clearTimeout(таймер); таймер = 0; }
    try {
      /* На уходе только маяк: обычный запрос браузер отменяет вместе
         с выгрузкой страницы, и последнее событие теряется каждый
         раз - то есть ровно то, по которому видно, где человек ушёл. */
      if (маяком && navigator.sendBeacon) {
        navigator.sendBeacon(АДРЕС, new Blob([тело], { type: "text/plain" }));
        return;
      }
      fetch(АДРЕС, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: тело,
        keepalive: true,
        credentials: "omit",
        mode: "cors"
      }).catch(function () {});
    } catch (e3) {}
  }

  function событие(тип, метки) {
    if (ушли) return;
    очередь.push({ t: String(тип).slice(0, 20), l: String(метки == null ? "" : метки).slice(0, 80) });
    if (очередь.length >= 5) { отправить(false); return; }
    if (!таймер) таймер = setTimeout(function () { отправить(false); }, 2000);
  }

  /* ── Заход ─────────────────────────────────────────────── */
  событие("view", location.pathname);

  /* ── Акты фильма ───────────────────────────────────────────
     Каждый акт отмечаем ОДИН раз за посещение. Человек ходит
     прокруткой туда и обратно, и без этого «периметр» насчитал бы
     себе десяток заходов на одном качании колеса. */
  var виденные = {};
  function акт(имя) {
    if (!имя || виденные[имя]) return;
    виденные[имя] = 1;
    событие("акт", имя);
  }

  /* Смотрим за самими актами разметки, а не за плёнкой.

     У плёнки есть подписка `слушать`, но она ПОИМЁННАЯ: подписаться
     разом на все акты ею нельзя, а перечислять имена здесь значит
     держать второй список тех же восьми актов и однажды с ним
     разойтись. Акты и так объявлены в разметке признаком `data-акт`.

     Порог в сорок процентов с каждой стороны, а не первый пиксель:
     акт высотой в несколько экранов «начинается» задолго до того, как
     человек его увидит, и по первому пикселю все восемь отметились бы
     в первую же секунду прокрутки. Отмечаем, когда акт занял середину
     экрана - то есть когда человек его действительно смотрит. */
  function завести() {
    var узлы = d.querySelectorAll("[data-акт]");
    if (!узлы.length) return false;
    if (!g.IntersectionObserver) {
      /* Старый браузер: отмечаем хотя бы первый акт, чтобы посещение
         не выглядело пустым. */
      акт(узлы[0].getAttribute("data-акт"));
      return true;
    }
    var н = new IntersectionObserver(function (записи) {
      for (var i = 0; i < записи.length; i++) {
        if (записи[i].isIntersecting) акт(записи[i].target.getAttribute("data-акт"));
      }
    }, { rootMargin: "-40% 0px -40% 0px", threshold: 0 });
    for (var i = 0; i < узлы.length; i++) н.observe(узлы[i]);
    return true;
  }
  if (!завести()) {
    var попыток = 0;
    var ждём = setInterval(function () {
      if (завести() || ++попыток > 40) clearInterval(ждём);
    }, 250);
  }

  /* ── Нажатия, которые что-то значат ────────────────────────
     Считаем только органы, ведущие наружу: вход в личный кабинет,
     уход в космос Rocket CDN, включение звука. Остальные нажатия к
     воронке отношения не имеют. */
  d.addEventListener("click", function (е) {
    var ц = е.target && е.target.closest ? е.target.closest("a[href], button") : null;
    if (!ц) return;
    if (ц.id === "rvКcdn" || /rocketcdn/.test(ц.getAttribute("href") || "")) { событие("вCDN", ""); return; }
    if (ц.classList.contains("rv-вход")) { событие("вход", ""); return; }
    if (ц.classList.contains("rv-звук")) { событие("звук", ц.getAttribute("aria-pressed") === "true" ? "выкл" : "вкл"); return; }
    var текст = (ц.textContent || "").trim().slice(0, 40);
    if (текст) событие("кнопка", текст);
  }, { passive: true });

  /* ── Ошибки ───────────────────────────────────────────────
     Ошибка на сайте, который смотрит заказчик, обязана доходить до
     панели сама. Иначе о ней узнают от него. */
  g.addEventListener("error", function (е) {
    var м = (е && е.message ? е.message : "ошибка") +
            (е && е.filename ? " @ " + String(е.filename).split("/").pop() + ":" + (е.lineno || 0) : "");
    событие("jserr", м);
    отправить(false);
  });
  g.addEventListener("unhandledrejection", function (е) {
    var п = е && е.reason;
    событие("jserr", "промис: " + String(п && п.message ? п.message : п).slice(0, 90));
  });

  /* ── Уход ──────────────────────────────────────────────────
     Ловим и pagehide, и переход вкладки в фон: на телефоне закрытие
     вкладки события pagehide не даёт вовсе, а visibilitychange
     приходит всегда. */
  function прощаемся() {
    if (ушли) return;
    ушли = true;
    отправить(true);
  }
  g.addEventListener("pagehide", прощаемся);
  d.addEventListener("visibilitychange", function () {
    if (d.visibilityState === "hidden") отправить(true);
  });

  g.RV_СЧЁТ = { "событие": событие, "метка": function () { return метка; } };

})(window, document);
