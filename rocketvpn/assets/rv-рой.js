/* Rocket VPN. Рой: знак из частиц и фоновая лента терминов.

   ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ЧАСТЬ АКТА «ВИДНО». Акт держит
   решётку сети: узлы, рёбра, пакеты, луч досмотра. Рой живёт по другому
   закону - он собирается и рассыпается по доле акта и отвечает на палец,
   - и держать два разных закона в одном модуле значит однажды сломать
   решётку правкой роя. Ядро мира отдаёт всё нужное наружу
   (RV_WORLD.мир/наКамеру/ступень), поэтому свой файл ничего не стоит.

   ПОЧЕМУ РОЙ ВИСИТ НА КАМЕРЕ. Знак обязан стоять в кадре ровно там, где
   его поставили, при любом положении камеры на прологе. Мировая точка
   этого не даёт: камера идёт от z=92 к z=18, и знак в мировых
   координатах ехал бы по кадру вместе с ней. На камере он стоит перед
   объективом, а «жизнь» ему даёт не камера, а доля акта.

   ПОЧЕМУ ЛЕНТА СЛОВ ИДЁТ МИМО МАТРИЦ. Термины должны течь по ЭКРАНУ, а
   не по сцене: это фон, у него нет места в мире. Вершинный шейдер пишет
   в gl_Position сразу, без камеры, и потому лента одинаково лежит на
   любом кадре и стоит один вызов отрисовки. Зациклённой она не кажется
   потому, что блоки гасит и проявляет шум по их собственной глубине, а
   не положение на экране.

   ЦЕНА. Оба предмета за ступенью качества: на нищей не собираются вовсе,
   на средней 1400 частиц и 18 блоков, на полной 3600 и 40. Один вызов
   отрисовки на каждый, ни одного своего requestAnimationFrame: униформы
   обновляются в onBeforeRender, то есть внутри кадра мира. */
(function (g, d) {
  "use strict";

  var W = null;
  var М = {};            /* всё собранное: рой, лента, их материалы */
  var собрано = false;
  var шаг = { кадр: -1 };  /* номер кадра мира: обновляемся один раз за кадр */

  /* Термины ленты. Взяты по делу: это то, чем сервис отличается, и
     человек читает их боковым зрением, пока смотрит на знак. */
  var СЛОВА = [
    "WireGuard", "Hysteria 2", "0 логов", "265 узлов",
    "AES-256", "без белых списков", "3 дня бесплатно"
  ];

  function зажать(v, a, b) { return v < a ? a : (v > b ? b : v); }

  /* Подтяжка величины к цели, не зависящая от частоты кадров. Эталонный
     приём даёт 0.05 на кадр при шестидесяти герцах; на 120-герцовом
     телефоне то же число догоняло бы цель вдвое быстрее, и отклик роя
     на палец вышел бы на двух телефонах разным. Пересчитываем на долю
     кадра ровно так же, как это делает плёнка. */
  function подтяжка(k, dt) {
    var раз = dt * 60;
    if (раз > 4) раз = 4;
    if (!(раз > 0.05)) раз = 0.05;
    return 1 - Math.pow(1 - k, раз);
  }

  /* ── Отклик на курсор и палец ──────────────────────────────────
     Держим ЦЕЛЬ отдельно от показанного: показанное идёт к цели через
     два последовательных сглаживания, и это даёт рою массу. Одно
     сглаживание трогается с места на полном ходу, два - разгоняются. */
  var цель = { x: 0, y: 0, сила: 0 };
  var п1 = { x: 0, y: 0 }, п2 = { x: 0, y: 0 };
  var с1 = 0, с2 = 0;
  var пальцем = false;   /* последнее указание пришло от касания */

  function указать(x, y, сила) {
    var ш = g.innerWidth || 1, в = g.innerHeight || 1;
    цель.x = (x / ш) * 2 - 1;
    цель.y = 1 - (y / в) * 2;
    цель.сила = сила;
  }

  function слушатьРуку() {
    g.addEventListener("pointermove", function (e) {
      пальцем = e.pointerType === "touch";
      /* Касание без нажатия браузер не присылает: на телефоне рой
         отвечает только пока палец на стекле. */
      указать(e.clientX, e.clientY, (пальцем && e.pressure === 0) ? 0 : 1);
    }, { passive: true });
    g.addEventListener("pointerdown", function (e) {
      пальцем = e.pointerType === "touch";
      указать(e.clientX, e.clientY, 1);
    }, { passive: true });
    var отпустить = function () { цель.сила = 0; };
    g.addEventListener("pointerup", отпустить, { passive: true });
    g.addEventListener("pointercancel", отпустить, { passive: true });
    /* Мышь ушла за край окна: держать под ней дыру в рое незачем. */
    d.addEventListener("mouseleave", отпустить);
  }

  /* ── Шейдеры роя. Внутри только латиница: кириллица ломает разбор
     GLSL, и материал молча не собирается. ───────────────────────── */

  /* Проявление с разбегом. x это место частицы в череде, m ширина её
     собственного окна внутри хода p. Одна функция на положение и на
     прозрачность: если считать их разными законами, частица приезжает
     на место раньше, чем зажглась, и знак собирается ступенькой. */
  var ПРОЯВЛЕНИЕ = [
    "float falloffsmooth(float x, float s, float e, float m, float p){",
    "  float d = mix(s, e - m, clamp(x, 0.0, 1.0));",
    "  return smoothstep(d, d + m, p);",
    "}"
  ].join("\n");

  var В_РОЙ = [
    "attribute vec3 aTarget;",
    "attribute vec3 aStart;",
    "attribute float aW;",
    "attribute float aSeed;",
    "uniform float uSbor;",
    "uniform float uRas;",
    "uniform float uSize;",
    "uniform float uH;",
    "uniform float uTime;",
    "uniform vec2 uPoint;",
    "uniform float uPush;",
    "uniform float uRad;",
    "varying float vA;",
    "varying float vSeed;",
    ПРОЯВЛЕНИЕ,
    "void main(){",
    /* Сборка идёт от одного конца череды, рассыпание от другого: иначе
       вход и выход читаются одним движением, прокрученным назад. */
    "  float k  = falloffsmooth(aW, 0.0, 1.0, 0.5, uSbor);",
    "  float kr = falloffsmooth(1.0 - aW, 0.0, 1.0, 0.5, uRas);",
    "  float a  = falloffsmooth(aW, 0.0, 1.0, 0.45, uSbor);",
    "  a *= 1.0 - falloffsmooth(1.0 - aW, 0.0, 1.0, 0.45, uRas);",
    /* Точка ухода зеркальна точке прихода: вторая случайная тройка на
       частицу стоила бы ещё сорок килобайт видеопамяти без разницы в
       кадре. */
    "  vec3 away = aStart * vec3(-1.0, -1.0, 1.0) * 1.2;",
    "  vec3 pos = mix(aStart, aTarget, k);",
    "  pos = mix(pos, away, kr);",
    /* Собранный знак не стоит мёртвым: у каждой частицы своя фаза, и
       вместе они дышат. Амплитуда меньше шага сетки пикселей марки,
       поэтому силуэт не плывёт. */
    "  float br = 0.4 + 0.6 * k;",
    "  pos.x += sin(uTime * 0.7 + aSeed * 6.283) * 0.008 * br;",
    "  pos.y += cos(uTime * 0.61 + aSeed * 4.712) * 0.008 * br;",
    "  pos.z += sin(uTime * 0.45 + aSeed * 9.42) * 0.03;",
    /* Расступиться под курсором. Считаем в плоскости знака: точка уже
       распроецирована в те же местные единицы на стороне разметки. */
    "  vec2 dv = pos.xy - uPoint;",
    "  float dist = length(dv) + 0.0001;",
    "  float f = 1.0 - smoothstep(0.0, uRad, dist);",
    "  f = f * f;",
    "  pos.xy += (dv / dist) * f * uPush * uRad * 0.55;",
    "  pos.z += f * uPush * 0.18;",
    "  vec4 mv = modelViewMatrix * vec4(pos, 1.0);",
    /* Честная перспектива: размер точки падает с расстоянием, а высота
       кадра в точках держит его одинаковым на телефоне и на мониторе. */
    "  gl_PointSize = clamp(uSize * (0.7 + 0.7 * k) / max(0.4, length(mv.xyz)) * (uH * 0.5), 1.0, 26.0);",
    "  vA = a * (0.45 + 0.55 * k);",
    "  vSeed = aSeed;",
    "  gl_Position = projectionMatrix * mv;",
    "}"
  ].join("\n");

  var Ф_РОЙ = [
    "uniform vec3 uCol;",
    "uniform vec3 uCol2;",
    "uniform float uGlob;",
    "uniform float uHard;",
    "varying float vA;",
    "varying float vSeed;",
    "void main(){",
    "  vec2 c = gl_PointCoord - 0.5;",
    "  float r = dot(c, c) * 4.0;",
    "  if (r > 1.0) discard;",
    /* Мягкое ядро вместо диска: диск на полутора точках экрана даёт
       квадратную крупу, спад её убирает. Крутизна спада своя на тему:
       ночью частица светится сложением, и мягкий край ей идёт, а днём
       она чернильная, и мягкий край на светлом холсте просто исчезает -
       остаётся серая пыль вместо знака. */
    "  float g = pow(1.0 - r, uHard);",
    "  float a = g * vA * uGlob;",
    "  if (a < 0.004) discard;",
    "  gl_FragColor = vec4(mix(uCol, uCol2, vSeed), a);",
    "}"
  ].join("\n");

  /* ── Шейдеры ленты. Матрицы не участвуют: gl_Position пишется в
     отсечённых координатах напрямую. ──────────────────────────── */
  var В_ЛЕНТА = [
    "attribute vec3 aCentr;",
    "attribute vec2 aUv;",
    "uniform float uAspect;",
    "uniform float uP;",
    "uniform float uTime;",
    "uniform sampler2D tNoise;",
    "varying vec2 vUv;",
    "varying float vAlpha;",
    "void main(){",
    /* position уже хранит смещение угла ОТ центра блока: вычитать
       центр в шейдере значит гонять его через вершину дважды. */
    "  vec3 loc = position;",
    "  vec3 cen = aCentr;",
    "  cen.x /= uAspect;",
    "  float depth = cen.z * 0.5 + 0.5;",
    "  loc.x /= uAspect;",
    "  loc *= 2.5;",
    "  loc *= mix(1.0, 2.0, depth);",
    /* Скорость по глубине: ближние блоки идут быстрее дальних, и это
       весь параллакс ленты. */
    "  cen.y = fract((cen.y * 0.5 + 0.5) + uP * 1.25 * depth) * 2.0 - 1.0;",
    "  cen *= 1.7;",
    "  vec3 p = loc + cen;",
    "  vUv = aUv;",
    "  vAlpha = smoothstep(0.1, 0.6, texture2D(tNoise, p.xz * 3.0 + uTime * 0.075 + cen.z * 10.0).r);",
    /* z обнуляем намеренно. Глубина блока живёт в шуме и в скорости, а
       в отсечённых координатах при w=1 всё за пределами -1..1 по z
       выбрасывается ДО проверки глубины: с настоящим p.z дальние блоки
       просто исчезали бы. */
    "  gl_Position = vec4(p.xy, 0.0, 1.0);",
    "}"
  ].join("\n");

  var Ф_ЛЕНТА = [
    "uniform sampler2D tAtlas;",
    "uniform vec3 uCol;",
    "uniform float uGlob;",
    "varying vec2 vUv;",
    "varying float vAlpha;",
    "void main(){",
    "  float m = texture2D(tAtlas, vUv).a;",
    "  float a = m * vAlpha * uGlob;",
    "  if (a < 0.004) discard;",
    "  gl_FragColor = vec4(uCol, a);",
    "}"
  ].join("\n");

  /* ── Силуэт знака из марки ─────────────────────────────────────
     Марка читается в канвас и проходится с шагом: каждый непрозрачный
     пиксель это место для частицы. Порог по альфе отсекает мягкий край
     сглаживания, иначе знак обрастает облаком полупрозрачной пыли и
     силуэт теряет кромку.

     Берём только РАКЕТУ, верхние две трети картинки. Ниже в марке
     набрано имя в четыре пикселя высотой на каждые полсотни; частицами
     оно превращается в мохнатую полоску, которая отнимает у ракеты
     половину роя и не читается ни одной буквой. Имя на первом экране и
     так стоит в шапке.

     Шаг единица, а не три-четыре: после обрезки ракета занимает пятую
     часть картинки, и на крупном шаге весь бюджет частиц не набирается.
     Прямоугольник знака переводится в квадрат наибольшей стороной,
     иначе узкая ракета растянулась бы поперёк. */
  function точкиМарки(картинка, шагПикселя, порог) {
    var С = 256;
    var c = d.createElement("canvas");
    c.width = С; c.height = С;
    var x = c.getContext("2d", { willReadFrequently: true });
    x.drawImage(картинка, 0, 0, С, С);
    var дан;
    try { дан = x.getImageData(0, 0, С, С).data; } catch (e) { return null; }
    var предел = Math.round(С * 0.66);
    var мнX = С, мкX = -1, мнY = С, мкY = -1, i, j, п;
    for (j = 0; j < предел; j++) {
      for (i = 0; i < С; i++) {
        if (дан[(j * С + i) * 4 + 3] < порог) continue;
        if (i < мнX) мнX = i;
        if (i > мкX) мкX = i;
        if (j < мнY) мнY = j;
        if (j > мкY) мкY = j;
      }
    }
    if (мкX < 0) return null;
    var цX = (мнX + мкX) * 0.5, цY = (мнY + мкY) * 0.5;
    var пол = Math.max(мкX - мнX, мкY - мнY) * 0.5 || 1;
    var точки = [];
    for (j = мнY; j <= мкY; j += шагПикселя) {
      for (i = мнX; i <= мкX; i += шагПикселя) {
        п = (j * С + i) * 4;
        if (дан[п + 3] < порог) continue;
        точки.push([(i - цX) / пол, -(j - цY) / пол]);
      }
    }
    return точки;
  }

  /* Шумовая картинка для ленты. Значимый шум по сетке 16x16, растянутый
     мягкой ступенькой: он крупный, и блок целиком попадает в светлое
     или в тёмное пятно, а не рябит буквами. */
  function шумТекстура(T) {
    var Р = 16, С = 128;
    var сетка = new Float32Array((Р + 1) * (Р + 1)), i;
    for (i = 0; i < сетка.length; i++) сетка[i] = Math.random();
    var c = d.createElement("canvas");
    c.width = С; c.height = С;
    var x = c.getContext("2d");
    var кар = x.createImageData(С, С);
    var м = function (t) { return t * t * (3 - 2 * t); };
    for (var y = 0; y < С; y++) {
      for (var xx = 0; xx < С; xx++) {
        var fx = xx / С * Р, fy = y / С * Р;
        var ix = Math.floor(fx), iy = Math.floor(fy);
        var tx = м(fx - ix), ty = м(fy - iy);
        var a = сетка[iy * (Р + 1) + ix], b = сетка[iy * (Р + 1) + ix + 1];
        var e = сетка[(iy + 1) * (Р + 1) + ix], f = сетка[(iy + 1) * (Р + 1) + ix + 1];
        var v = (a + (b - a) * tx) + ((e + (f - e) * tx) - (a + (b - a) * tx)) * ty;
        var п = (y * С + xx) * 4;
        var б = Math.round(зажать(v, 0, 1) * 255);
        кар.data[п] = кар.data[п + 1] = кар.data[п + 2] = б;
        кар.data[п + 3] = 255;
      }
    }
    x.putImageData(кар, 0, 0);
    var т = new T.CanvasTexture(c);
    т.wrapS = т.wrapT = T.RepeatWrapping;
    т.generateMipmaps = false;
    т.minFilter = T.LinearFilter;
    return т;
  }

  /* Атлас слов. Каждое слово своей строкой; наружу уходят доли атласа и
     собственная пропорция слова, чтобы блок не растягивал буквы. */
  function атласСлов(T) {
    var Ш = 1024, ВЫС = 96, В = ВЫС * СЛОВА.length;
    var c = d.createElement("canvas");
    c.width = Ш; c.height = В;
    var x = c.getContext("2d");
    x.clearRect(0, 0, Ш, В);
    x.textBaseline = "middle";
    x.textAlign = "left";
    var поля = [], i;
    for (i = 0; i < СЛОВА.length; i++) {
      x.font = "700 52px 'Golos Text', 'Unbounded', system-ui, sans-serif";
      var ш = Math.min(Ш - 16, Math.ceil(x.measureText(СЛОВА[i]).width));
      x.fillStyle = "#ffffff";
      x.fillText(СЛОВА[i], 8, i * ВЫС + ВЫС * 0.5);
      поля.push({
        u0: 0, u1: (ш + 16) / Ш,
        v0: 1 - (i * ВЫС + ВЫС) / В, v1: 1 - (i * ВЫС) / В,
        отн: (ш + 16) / ВЫС
      });
    }
    var т = new T.CanvasTexture(c);
    т.generateMipmaps = false;
    т.minFilter = T.LinearFilter;
    т.magFilter = T.LinearFilter;
    return { текстура: т, поля: поля };
  }

  /* ── Сборка ────────────────────────────────────────────────── */
  function собратьРой(T, точки, сколько) {
    /* Череда сборки: снизу вверх с разбросом. Чистый порядок пикселей
       давал бы построчную развёртку, чистая случайность - мигание без
       направления. Смесь читается волной, которая поднимает знак. */
    var сп = точки.slice();
    for (var i = сп.length - 1; i > 0; i--) {
      var j = (Math.random() * (i + 1)) | 0;
      var t = сп[i]; сп[i] = сп[j]; сп[j] = t;
    }
    if (сп.length > сколько) сп.length = сколько;
    var н = сп.length;
    сп.sort(function (a, b) {
      return (a[1] * 0.6 + a[2]) - (b[1] * 0.6 + b[2]);
    });

    var цельм = new Float32Array(н * 3);
    var старт = new Float32Array(н * 3);
    var вес = new Float32Array(н);
    var зерно = new Float32Array(н);
    for (i = 0; i < н; i++) {
      цельм[i * 3] = сп[i][0] * 0.92;
      цельм[i * 3 + 1] = сп[i][1] * 0.92;
      цельм[i * 3 + 2] = (Math.random() - 0.5) * 0.14;
      /* Стартовый шар вокруг знака. Радиус больше кадра: на подлёте
         частицы разбросаны за краями, и знак вырастает из ниоткуда. */
      var u = Math.random() * 2 - 1, ф = Math.random() * Math.PI * 2;
      var р = 3.2 * Math.pow(Math.random(), 0.45);
      var к = Math.sqrt(1 - u * u);
      старт[i * 3] = р * к * Math.cos(ф);
      старт[i * 3 + 1] = р * к * Math.sin(ф);
      старт[i * 3 + 2] = р * u * 0.45;
      вес[i] = н > 1 ? i / (н - 1) : 0;
      зерно[i] = Math.random();
    }

    var гео = new T.BufferGeometry();
    гео.setAttribute("position", new T.BufferAttribute(цельм.slice(), 3));
    гео.setAttribute("aTarget", new T.BufferAttribute(цельм, 3));
    гео.setAttribute("aStart", new T.BufferAttribute(старт, 3));
    гео.setAttribute("aW", new T.BufferAttribute(вес, 1));
    гео.setAttribute("aSeed", new T.BufferAttribute(зерно, 1));
    /* Шар охвата ставим руками по стартовому радиусу: считать его по
       position ядро посчитало бы по СОБРАННОМУ знаку, и разлетевшийся
       рой отсекался бы по краям кадра. */
    гео.boundingSphere = new T.Sphere(new T.Vector3(0, 0, 0), 4.2);

    var мат = new T.ShaderMaterial({
      uniforms: {
        uSbor: { value: 0 }, uRas: { value: 0 },
        /* Мировой размер точки. Двух точек экрана мало: на решётке сети,
           которая под знаком светится сама, такой рой читается пылью.
           Четыре с половиной дают зерно, из которого складывается
           силуэт, и не залепляют его в пятно. */
        uSize: { value: 0.44 }, uH: { value: 800 },
        uTime: { value: 0 }, uGlob: { value: 0 }, uHard: { value: 2.2 },
        uPoint: { value: new T.Vector2(0, 0) },
        uPush: { value: 0 }, uRad: { value: 0.4 },
        uCol: { value: new T.Color(0x8fa6ff) },
        uCol2: { value: new T.Color(0xdfe8ff) }
      },
      vertexShader: В_РОЙ,
      fragmentShader: Ф_РОЙ,
      transparent: true,
      depthWrite: false,
      blending: T.AdditiveBlending
    });

    var точ = new T.Points(гео, мат);
    точ.name = "рой знака";
    точ.frustumCulled = false;
    точ.renderOrder = -90;
    return точ;
  }

  function собратьЛенту(T, блоков) {
    var атлас = атласСлов(T);
    var поз = new Float32Array(блоков * 4 * 3);
    var цен = new Float32Array(блоков * 4 * 3);
    var уф = new Float32Array(блоков * 4 * 2);
    var инд = new Uint16Array(блоков * 6);
    /* Полувысота блока. Лента это ФОН: слова крупнее этого начинают
       спорить с заголовком акта, а он тут главный. */
    var пв = 0.0115;
    for (var b = 0; b < блоков; b++) {
      var п = атлас.поля[b % атлас.поля.length];
      var пш = пв * п.отн;
      var cx = (Math.random() * 2 - 1) * 1.05;
      var cy = Math.random() * 2 - 1;
      var cz = Math.random() * 2 - 1;
      var углы = [[-пш, -пв], [пш, -пв], [пш, пв], [-пш, пв]];
      var уфУглы = [[п.u0, п.v0], [п.u1, п.v0], [п.u1, п.v1], [п.u0, п.v1]];
      for (var k = 0; k < 4; k++) {
        var о = (b * 4 + k);
        поз[о * 3] = углы[k][0];
        поз[о * 3 + 1] = углы[k][1];
        поз[о * 3 + 2] = 0;
        цен[о * 3] = cx; цен[о * 3 + 1] = cy; цен[о * 3 + 2] = cz;
        уф[о * 2] = уфУглы[k][0];
        уф[о * 2 + 1] = уфУглы[k][1];
      }
      var в = b * 4;
      инд[b * 6] = в; инд[b * 6 + 1] = в + 1; инд[b * 6 + 2] = в + 2;
      инд[b * 6 + 3] = в; инд[b * 6 + 4] = в + 2; инд[b * 6 + 5] = в + 3;
    }

    var гео = new T.BufferGeometry();
    гео.setAttribute("position", new T.BufferAttribute(поз, 3));
    гео.setAttribute("aCentr", new T.BufferAttribute(цен, 3));
    гео.setAttribute("aUv", new T.BufferAttribute(уф, 2));
    гео.setIndex(new T.BufferAttribute(инд, 1));

    var мат = new T.ShaderMaterial({
      uniforms: {
        tAtlas: { value: атлас.текстура },
        tNoise: { value: шумТекстура(T) },
        uAspect: { value: 1.6 },
        uP: { value: 0 }, uTime: { value: 0 }, uGlob: { value: 0 },
        uCol: { value: new T.Color(0x7f92ff) }
      },
      vertexShader: В_ЛЕНТА,
      fragmentShader: Ф_ЛЕНТА,
      transparent: true,
      depthTest: false,
      depthWrite: false,
      blending: T.AdditiveBlending
    });

    var сет = new T.Mesh(гео, мат);
    сет.name = "лента слов";
    сет.frustumCulled = false;
    сет.matrixAutoUpdate = false;
    сет.renderOrder = -100;
    return сет;
  }

  /* ── Краска по теме ───────────────────────────────────────────
     Ночью рой и лента светятся сложением, днём это чернила: на светлом
     холсте сложение даёт белое на белом, то есть пустой кадр. */
  function краскаПоТеме() {
    if (!собрано) return;
    var T = W.T;
    var днём = d.documentElement.getAttribute("data-тема") === "светлая";
    var рм = М.рой.material.uniforms, лм = М.лента.material.uniforms;
    if (днём) {
      рм.uCol.value.setHex(0x111a44);
      рм.uCol2.value.setHex(0x33409a);
      рм.uHard.value = 1.0;
      лм.uCol.value.setHex(0x232b63);
      М.рой.material.blending = T.NormalBlending;
      М.лента.material.blending = T.NormalBlending;
    } else {
      рм.uCol.value.setHex(0x8fa6ff);
      рм.uCol2.value.setHex(0xdfe8ff);
      рм.uHard.value = 2.2;
      лм.uCol.value.setHex(0x7f92ff);
      М.рой.material.blending = T.AdditiveBlending;
      М.лента.material.blending = T.AdditiveBlending;
    }
    М.рой.material.needsUpdate = true;
    М.лента.material.needsUpdate = true;
    М.днём = днём;
  }

  /* ── Кадр ────────────────────────────────────────────────────
     Своего цикла нет намеренно: обновляемся внутри кадра мира, по
     первому из двух предметов, который дошёл до отрисовки. Номер кадра
     ядра держит расчёт от двойного счёта. */
  function обновить() {
    if (!собрано) return;
    var н = W.r && W.r.info ? W.r.info.render.frame : (шаг.кадр + 1);
    if (н === шаг.кадр) return;
    var dt = зажать((н > шаг.кадр ? (W.часы - шаг.время) : 0), 0.001, 0.2);
    шаг.кадр = н; шаг.время = W.часы;

    var доля = g.RV_MOTION ? g.RV_MOTION["доля"]("видно") : 0;
    /* Сбор идёт от ДВУХ величин, и это не запас, а необходимость.
       Первый экран человек видит ДО прокрутки, где доля акта ровно
       ноль: собирай знак только долей - и на первом кадре сайта висело
       бы пустое место, пока не крутанут. Поэтому знак собирается сам за
       две с небольшим секунды после подъёма мира, а прокрутка ведёт тот
       же сбор дальше и потом рассыпает его на уходе. */
    М.вход = Math.min(1, (М.вход || 0) + dt * 0.45);
    var сбор = Math.max(зажать(доля / 0.52, 0, 1), М.вход);
    var рас = зажать((доля - 0.66) / 0.34, 0, 1);
    /* Общая сила гаснет к концу акта: дальше по ленте идёт периметр, и
       знак поверх блокпоста был бы мусором в кадре. */
    var вес = 1 - зажать((доля - 0.62) / 0.33, 0, 1);
    /* Краска приходит быстрее сбора: иначе первые частицы летят
       невидимыми и знак возникает уже наполовину готовым. */
    вес *= Math.min(1, М.вход * 3);

    var рм = М.рой.material.uniforms, лм = М.лента.material.uniforms;
    var живо = вес > 0.002;
    М.рой.geometry.setDrawRange(0, живо ? М.частиц : 0);
    М.лента.geometry.setDrawRange(0, живо ? М.индексов : 0);
    if (!живо) return;

    /* Размер и место знака считаются от кадра, а не заданы числом.
       Причина простая: на ПК слева стоит заголовок, и знак обязан жить
       в правой половине кадра, а на телефоне заголовок занимает верх, и
       знаку остаётся низ. Постоянные числа дали бы либо знак под
       текстом, либо знак за краем экрана. */
    var cam = W.cam;
    var полув = М.отступ * Math.tan(cam.fov * 0.5 * Math.PI / 180);
    var полуш = полув * cam.aspect;
    var широкий = cam.aspect > 1.1;
    var масштаб = широкий
      ? Math.min(полуш * 0.36, полув * 0.62)
      : Math.min(полуш * 0.56, полув * 0.26);
    var смещX = широкий ? полуш * 0.44 : 0;
    var смещY = широкий ? полув * 0.10 : -полув * 0.40;
    М.узел.scale.setScalar(масштаб);
    М.узел.position.set(смещX, смещY, -М.отступ);

    /* Отклик руки: два сглаживания подряд по 0.05. На телефоне без
       касания возврат вдвое медленнее - палец убрали, а рой ещё
       помнит движение. */
    var k = подтяжка(0.05, dt);
    var кс = (пальцем && цель.сила === 0) ? подтяжка(0.025, dt) : k;
    п1.x += (цель.x - п1.x) * k; п1.y += (цель.y - п1.y) * k;
    п2.x += (п1.x - п2.x) * k;   п2.y += (п1.y - п2.y) * k;
    с1 += (цель.сила - с1) * кс;
    с2 += (с1 - с2) * кс;
    /* Точка экрана на плоскость знака. Плоскость стоит перед объективом
       на известном отступе, поэтому луч пускать незачем: доля экрана
       умножается на полукадр, а смещение и масштаб знака переводят её в
       местные единицы роя. */
    рм.uPoint.value.set((п2.x * полуш - смещX) / масштаб,
                        (п2.y * полув - смещY) / масштаб);
    рм.uPush.value = с2;

    var высК = 800;
    if (W.r && W.r.getDrawingBufferSize) {
      высК = W.r.getDrawingBufferSize(М.разм).y || 800;
    }
    рм.uSbor.value = сбор;
    рм.uRas.value = рас;
    рм.uTime.value = W.часы;
    рм.uH.value = высК;
    рм.uGlob.value = вес;

    лм.uAspect.value = cam.aspect;
    лм.uTime.value = W.часы;
    /* Ход ленты: время плюс доля акта. Без времени лента стояла бы на
       месте у человека, который не крутит; без доли она не отвечала бы
       на прокрутку, а весь сайт отвечает. */
    лм.uP.value = W.часы * 0.014 + доля * 0.55;
    лм.uGlob.value = вес * (М.днём ? 0.38 : 0.44);
  }

  /* ── Подъём ──────────────────────────────────────────────── */
  var поднимаем = false;
  function поднять() {
    /* Признак ставится ДО чтения марки, а не после сборки: картинка
       грузится асинхронно, и второе событие готовности мира завело бы
       вторую загрузку и второй рой поверх первого. */
    if (собрано || поднимаем || !g.RV_WORLD) return;
    var мир = g.RV_WORLD["мир"]();
    if (!мир || !мир.T || !мир.scene || !мир.cam) return;
    W = мир;
    var T = W.T;
    var ст = W.ступень;
    /* Нищая ступень и просьба убрать движение: не собираем вовсе. Это
       не украшение кадра, это лишние сорок тысяч вершин на телефоне,
       который и без них не тянет. */
    if (ст === 0) return;
    if (g.RV_WORLD["тихо"] && g.RV_WORLD["тихо"]()) return;

    var частиц = ст >= 2 ? 3600 : 1400;
    var блоков = ст >= 2 ? 40 : 18;
    поднимаем = true;

    var карт = new Image();
    карт.onload = function () {
      var точки = точкиМарки(карт, 1, 90);
      if (!точки || точки.length < 40) return;
      /* Третье число у точки это разброс череды: сортировка снизу вверх
         идёт по нему вместе с высотой. */
      for (var i = 0; i < точки.length; i++) точки[i][2] = Math.random() * 0.9;

      М.узел = new T.Group();
      М.узел.name = "рой Rocket VPN";
      М.рой = собратьРой(T, точки, частиц);
      М.частиц = М.рой.geometry.getAttribute("aW").count;
      М.узел.add(М.рой);
      /* Отступ от объектива. Сорок единиц дают кадр в три десятка
         единиц по высоте: стартовый шар радиуса 3.2 в местных единицах
         знака уходит далеко за края, и разлёт читается разлётом. */
      М.отступ = 40;
      if (!g.RV_WORLD["наКамеру"](М.узел, М.отступ)) return;

      М.лента = собратьЛенту(T, блоков);
      М.индексов = блоков * 6;
      W.scene.add(М.лента);

      /* Обновление вешаем на оба предмета: если один из них однажды не
         соберётся, второй всё равно останется живым. */
      М.рой.onBeforeRender = обновить;
      М.лента.onBeforeRender = обновить;
      М.разм = new T.Vector2();
      М.вход = 0;
      шаг.время = W.часы;

      собрано = true;
      краскаПоТеме();
      g.addEventListener("rv-тема", краскаПоТеме);
      слушатьРуку();
    };
    карт.onerror = function () {};
    карт.src = "assets/rv-mark.webp";
  }

  function встать() {
    /* Мир мог подняться раньше нас, а мог и позже: порядок отложенных
       скриптов между собой ничем не закреплён. Слушателя вешаем в обоих
       случаях - второй подъём отсекает признак «собрано». */
    g.addEventListener("rv:мир", poehali);
    if (g.RV_WORLD && g.RV_WORLD["готов"] && g.RV_WORLD["готов"]()) poehali();
  }
  /* Имя латиницей потому, что оно уходит слушателем события и должно
     совпадать по ссылке при снятии; кириллица тут ничего не даёт. */
  function poehali() { try { поднять(); } catch (e) {} }

  g.RV_РОЙ = {
    "живой": function () { return собрано; },
    "счёт": function () { return собрано ? { "частиц": М.частиц, "блоков": М.индексов / 6 } : null; }
  };

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", встать);
  else встать();
})(window, document);
