/* Rocket VPN. Вход ВНУТРЬ глыбы льда по клику.

   СЦЕНАРИЙ ВЛАДЕЛЬЦА ДОСЛОВНО: «если нажать на какую-то глыбу льда, у
   них внутрь этой глыбы уходит камера, с таким эффектом ускорения, и
   там внутри фон соответствующий, как будто мы внутри льдины, вот эта
   иконка, которая внутри льдины, с небольшой подсветкой, и текст, какое-
   то описание... и кнопка выхода как у них, прямо сделать один в один».

   КАК ЭТО У IGLOO. Разобрано по их снимкам, кадр за кадром:
     1. глыба в кадре, от неё выноски с подписями и «CLICK TO EXPLORE»;
     2. по клику лёд НАЛЕТАЕТ на объектив с разгоном, распадаясь по краям
        в цветную кашу (у них на этом кадре видна хроматическая
        аберрация и растр - лёд буквально рвётся на пикселы);
     3. кадр гаснет в тёмную толщу, и на ней проявляется страница: слева
        вверху марка, справа вверху «Close» в уголках рамки, ниже
        «////// Summary» и абзацы;
     4. буквы приходят тем же перебором чужих глифов, каким проявляется
        весь их текст;
     5. «Close» возвращает назад тем же ходом, проигранным обратно.

   ЧТО ЗДЕСЬ. Разбор клика лучом, разгон камеры внутрь, тёмная толща
   льда как подложка, знак с подсветкой сверху, описание набором сцены и
   кнопка выхода. Прокрутка на это время заперта: мы внутри предмета, а
   не на ленте.

   ПОЧЕМУ ОПИСАНИЕ РАЗМЕТКОЙ, А НЕ В КОДЕ. Тексты живут там же, где все
   остальные слова сайта - в `frame.html`, в том же `li`, что и подпись
   на выноске. Поисковик читает их, а человек видит объём.

   API:
     RV_ВНУТРЬ.поднять(мир)
     RV_ВНУТРЬ.цели(список)   - кому можно попадать лучом
     RV_ВНУТРЬ.открыта()      - идёт ли сейчас погружение
     RV_ВНУТРЬ.закрыть()
     RV_ВНУТРЬ.замер() */
(function (g, d) {
  "use strict";

  var W = null, T = null;
  var поднято = false;

  /* Цели луча: список { глыба, корень, текст, знак }. Ставит акт. */
  var ЦЕЛИ = [];

  /* Состояние погружения.
       фаза: 0 снаружи, 1 влёт, 2 внутри, 3 вылет
       t: секунды в текущей фазе */
  var С = { фаза: 0, t: 0, цель: null, откудаПоз: null, откудаКвт: null, поле: 50 };

  /* ВЛЁТ 0.85 СЕКУНДЫ, ВЫЛЕТ 0.55. У igloo влёт заметно длиннее вылета:
     внутрь нас затягивает, наружу выбрасывает. Разгон кубический - на
     старте камера почти стоит, у самой глыбы идёт быстрее всего, и
     именно это читается как «ускорение», о котором сказал владелец. */
  var ВЛЁТ = 0.85, ВЫЛЕТ = 0.55;

  function зажать(v, н, в) { return v < н ? н : (v > в ? в : v); }
  function куб(t) { return t * t * t; }
  function квадВыход(t) { return 1 - (1 - t) * (1 - t); }

  /* ── Разметка страницы внутри ─────────────────────────────────
     Подложка, марка, кнопка выхода и место под описание. Собирается
     один раз и живёт спрятанной: строить её по клику значит платить
     раскладкой ровно в тот кадр, где идёт разгон камеры. */
  var УЗЕЛ = null, ТЕКСТ = null, ЗАГ = null;
  function собратьРазметку() {
    if (УЗЕЛ) return УЗЕЛ;
    УЗЕЛ = d.createElement("div");
    УЗЕЛ.className = "rv-внутрь";
    УЗЕЛ.setAttribute("aria-hidden", "true");
    УЗЕЛ.innerHTML =
      '<div class="rv-внутрь-шапка">' +
        '<p class="rv-внутрь-марка">ROCKET<i>VPN</i></p>' +
        '<button type="button" class="rv-внутрь-выход" aria-label="Закрыть">' +
          '<span class="rv-внутрь-уголки"></span>Закрыть</button>' +
      '</div>' +
      '<div class="rv-внутрь-лист">' +
        '<p class="rv-внутрь-над">////// Что это даёт</p>' +
        '<h3 class="rv-внутрь-заг"></h3>' +
        '<p class="rv-внутрь-текст"></p>' +
        /* Действия внизу описания - их набор. У igloo под текстом стоит
           «/// Discover» и ряд ссылок; здесь то же место занимают два
           живых действия сервиса. */
        '<p class="rv-внутрь-над rv-внутрь-над2">/// Дальше</p>' +
        '<p class="rv-внутрь-кнопки">' +
          '<a class="rv-кн rv-кн-гл" href="https://t.me/RocketCompanyVPN_bot" target="_blank" rel="noopener">Забрать три дня без карты</a>' +
          '<a class="rv-кн" href="https://t.me/rocketvpnnews" target="_blank" rel="noopener">Канал новостей</a>' +
        '</p>' +
      '</div>';
    d.body.appendChild(УЗЕЛ);
    ЗАГ = УЗЕЛ.querySelector(".rv-внутрь-заг");
    ТЕКСТ = УЗЕЛ.querySelector(".rv-внутрь-текст");
    УЗЕЛ.querySelector(".rv-внутрь-выход").addEventListener("click", function (е) {
      е.preventDefault();
      закрыть();
    });
    /* Escape закрывает: это модальное окно, и человек ждёт от него
       обычного поведения модального окна. */
    d.addEventListener("keydown", function (е) {
      if (С.фаза === 2 && (е.key === "Escape" || е.key === "Esc")) закрыть();
    });
    return УЗЕЛ;
  }

  /* ── Луч ──────────────────────────────────────────────────────
     Попадание считается по ТЕЛУ ЛЬДА, а не по всей группе: в группе
     висят ещё выноска и подпись, и клик по надписи в двух метрах от
     предмета открывал бы его молча. */
  var _луч = null, _мышь = null;
  function подЛучом(x, y) {
    if (!W || !W.cam || !ЦЕЛИ.length) return null;
    if (!_луч) { _луч = new T.Raycaster(); _мышь = new T.Vector2(); }
    _мышь.set((x / (g.innerWidth || 1)) * 2 - 1, -(y / (g.innerHeight || 1)) * 2 + 1);
    _луч.setFromCamera(_мышь, W.cam);
    var тела = [];
    for (var i = 0; i < ЦЕЛИ.length; i++) {
      var ц = ЦЕЛИ[i];
      if (!ц.глыба || !ц.глыба["лёд"]) continue;
      var р = ц.глыба["корень"], виден = true;
      while (р) { if (!р.visible) { виден = false; break; } р = р.parent; }
      if (!виден) continue;
      ц.глыба["лёд"].userData["цель"] = ц;
      тела.push(ц.глыба["лёд"]);
    }
    if (!тела.length) return null;
    var пересек = _луч.intersectObjects(тела, false);
    if (!пересек.length) return null;
    return пересек[0].object.userData["цель"] || null;
  }

  /* ── Открыть ──────────────────────────────────────────────────*/
  function открыть(цель) {
    if (!цель || С.фаза !== 0 || !W || !W.cam) return false;
    собратьРазметку();
    С.цель = цель;
    С.фаза = 1;
    С.t = 0;
    С.откудаПоз = W.cam.position.clone();
    С.откудаКвт = W.cam.quaternion.clone();
    С.поле = W.cam.fov;
    ЗАГ.textContent = цель.подпись || "";
    ТЕКСТ.textContent = цель.текст || "";
    УЗЕЛ.classList.add("рв-влёт");
    try { d.documentElement.classList.add("рв-внутри"); } catch (e) {}
    if (g.RV_SOUND && g.RV_SOUND["разом"]) g.RV_SOUND["разом"]("pull", 0.2, 0.5, 0.92);
    try { g.dispatchEvent(new CustomEvent("rv:внутрь", { detail: { "что": "вход" } })); } catch (e2) {}
    return true;
  }

  function закрыть() {
    if (С.фаза !== 2) return false;
    С.фаза = 3;
    С.t = 0;
    УЗЕЛ.classList.remove("рв-видно");
    if (g.RV_SOUND && g.RV_SOUND["разом"]) g.RV_SOUND["разом"]("sweep", 0.2, 0.42, 1.1);
    return true;
  }

  /* ── Кадр ─────────────────────────────────────────────────────
     Мир ведёт камеру сам, поэтому здесь она ПЕРЕПИСЫВАЕТСЯ после него:
     погружение это временный захват, а не своя ветка движения. Так
     выход возвращает всё на место без единой правки в ядре. */
  var _цп = null, _цк = null, _вспом = null;
  function кадр(dt) {
    if (С.фаза === 0 || !W || !W.cam) return;
    if (!_цп) { _цп = new T.Vector3(); _цк = new T.Quaternion(); _вспом = new T.Vector3(); }
    С.t += Math.min(0.1, dt || 0.016);
    var г = С.цель && С.цель.глыба;
    if (!г) { С.фаза = 0; return; }
    г["корень"].updateMatrixWorld();
    г["корень"].getWorldPosition(_цп);

    if (С.фаза === 1 || С.фаза === 3) {
      var длина = С.фаза === 1 ? ВЛЁТ : ВЫЛЕТ;
      var доля = зажать(С.t / длина, 0, 1);
      /* Влёт с РАЗГОНОМ (кубическая кривая от нуля), вылет с
         торможением: внутрь затягивает, наружу выбрасывает и отпускает. */
      var х = С.фаза === 1 ? куб(доля) : 1 - квадВыход(доля);
      /* Камера идёт не в центр глыбы, а СКВОЗЬ него: последняя треть
         пути проходит внутри тела, и лёд успевает накрыть объектив
         целиком. Без этого в конце влёта в кадре остаётся край глыбы и
         кусок стены за ней. */
      _вспом.copy(_цп).sub(С.откудаПоз);
      var путь = _вспом.length() || 1;
      _вспом.normalize();
      W.cam.position.copy(С.откудаПоз).addScaledVector(_вспом, путь * 1.06 * х);
      /* Прицел ведём в глыбу, но поворот берём малой долей: резкий
         доворот на разгоне читается рывком руля, а не полётом. */
      _цк.copy(С.откудаКвт);
      W.cam.quaternion.copy(_цк);
      W.cam.lookAt(_цп);
      W.cam.quaternion.slerp(_цк, 1 - х * 0.85);
      /* Поле сужается на влёте: сужение угла на ходу читается разгоном,
         тот же приём, что в тоннеле. */
      W.cam.fov = С.поле * (1 - 0.28 * х);
      W.cam.updateProjectionMatrix();
      if (доля >= 1) {
        if (С.фаза === 1) {
          С.фаза = 2; С.t = 0;
          УЗЕЛ.classList.remove("рв-влёт");
          УЗЕЛ.classList.add("рв-видно");
          /* Слова приходят волной расшифровки - тем же перебором чужих
             глифов, каким живёт весь текст сайта. */
          if (g.RV_СЛОВО3D && g.RV_СЛОВО3D["волна"]) {
            g.RV_СЛОВО3D["волна"]((g.innerWidth || 1) * 0.5, (g.innerHeight || 1) * 0.42, false);
          }
        } else {
          if (г["иконка"]) г["иконка"].scale.setScalar((г["размер"] || 1) * 0.82);
          С.фаза = 0; С.t = 0; С.цель = null;
          УЗЕЛ.classList.remove("рв-влёт");
          try { d.documentElement.classList.remove("рв-внутри"); } catch (e) {}
          W.cam.fov = С.поле;
          W.cam.updateProjectionMatrix();
          try { g.dispatchEvent(new CustomEvent("rv:внутрь", { detail: { "что": "выход" } })); } catch (e3) {}
        }
      }
      return;
    }

    /* ── ВНУТРИ ГЛЫБЫ ────────────────────────────────────────────
       Владелец про их переход: «внутри как раз вот эта 3D иконка стоит
       где-то сверху и ниже текст идёт, описание».

       Камера не в самом центре тела, а в полутора его размерах перед
       ним: изнутри геометрии видна только изнанка граней, а нужен ЗНАК.
       Полуторный размер при суженном поле даёт лёд во весь кадр - мы
       внутри толщи, - и знак остаётся читаемым.

       Прицел опущен под знак, поэтому сам знак уходит в верхнюю треть
       кадра, а нижние две трети остаются описанию. Ровно та раскладка,
       что и во всех остальных сценах сайта. */
    var разм = г["размер"] || 1;
    _вспом.copy(_цп).sub(С.откудаПоз);
    if (_вспом.lengthSq() < 1e-6) _вспом.set(0, 0, 1);
    _вспом.normalize();
    W.cam.position.copy(_цп).addScaledVector(_вспом, -разм * 1.55);
    /* Лёгкое дыхание: полная неподвижность читается снимком, а не
       местом. */
    W.cam.position.y += Math.sin(С.t * 0.9) * разм * 0.02;
    W.cam.fov = С.поле * 0.72;
    W.cam.updateProjectionMatrix();
    _вспом.copy(_цп);
    _вспом.y -= разм * 0.62;
    W.cam.lookAt(_вспом);
    /* Знак крупнее и разворачивается медленно: он тут главный предмет. */
    if (г["иконка"]) {
      г["иконка"].scale.setScalar(разм * 1.15);
      г["иконка"].rotation.y += (dt || 0.016) * 0.42;
    }
  }

  /* ── Подъём ───────────────────────────────────────────────────*/
  function поднять(мир) {
    if (поднято || !мир || !мир.T) return;
    W = мир; T = мир.T;
    поднято = true;
    собратьРазметку();
    d.addEventListener("pointerdown", function (е) {
      if (С.фаза !== 0) return;
      /* По разметке (кнопки, ссылки, шапка) не ловим: там свои действия. */
      if (е.target && е.target.closest && е.target.closest("a,button,input,textarea,label")) return;
      var ц = подЛучом(е.clientX, е.clientY);
      if (ц) открыть(ц);
    }, { passive: true });
  }

  function самоподъём() {
    if (!g.RV_WORLD || !g.RV_WORLD["готов"] || !g.RV_WORLD["готов"]()) return false;
    поднять(g.RV_WORLD["мир"]());
    return true;
  }
  if (!самоподъём()) g.addEventListener("rv:мир", самоподъём);
  /* Кадр цепляем к общему такту мира: своего цикла заводить незачем, а
     переписывать камеру надо ПОСЛЕ того, как её поставил мир. */
  g.addEventListener("rv:кадр", function (е) {
    кадр(е && е.detail ? е.detail["dt"] : 0.016);
  });

  g.RV_ВНУТРЬ = {
    "поднять": поднять,
    "цели": function (сп) { ЦЕЛИ = сп || []; },
    "открыта": function () { return С.фаза !== 0; },
    "открыть": открыть,
    "закрыть": закрыть,
    "кадр": кадр,
    "замер": function () {
      return {
        "поднято": поднято, "целей": ЦЕЛИ.length,
        "фаза": С.фаза, "t": +С.t.toFixed(2),
        "подпись": С.цель ? (С.цель.подпись || "") : ""
      };
    }
  };
})(window, document);
