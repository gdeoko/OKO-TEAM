/* Rocket VPN. Свечение с нулевым порогом: проход igloo целиком.

   ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ. Владелец смотрит на тоннель и говорит, что
   он «не такой, как у igloo», и называет разницу стеклянными эффектами.
   Разбор их сборки объясняет это одной строкой: вся сцена входа идёт
   через свечение с НУЛЕВЫМ порогом.

     addBloom({ levels: 6, luminanceThreshold: 0, intensity: 1, radius: 0.85 })

   Нулевой порог означает, что в ореол отдаёт КАЖДАЯ точка кадра, и
   отдаёт долю, равную своей собственной яркости. Тёмный камень кольца
   отдаёт мало, выбитая кромка отдаёт всё. Отсюда у них берутся сразу
   три вещи, которых нет у нас: чёрного нет нигде (минимум по их кадрам
   тоннеля 51 из 255), свет растекается на сотни точек (у них 80% света
   ореола лежит внутри 105 точек, у нашей прежней пирамиды внутри 10), и
   яркая кромка выжигается в чистый белый (5.8-9.2% площади их кадра, у
   нас не было НИ ОДНОЙ точки выше 249).

   ЧТО ЗДЕСЬ СОБРАНО.
   · Пирамида по их числам: шесть уменьшений ядром на 13 отсчётов,
     пять увеличений шатром 3x3, смешивание каждого подъёма с опорой по
     radius 0.85. Ровно этот radius и даёт форму: на 1.0 ядро уходит
     (радиус половины света прыгает с 32 точек до 97, кадр становится
     ровной пеленой), на 0.7 пропадает середина ореола.
   · Складывание SCREEN, а не сложение. Сложение перед тональной кривой
     давало серую муть: кривая жала сумму так же, как жала бы саму сцену.
   · Признак стекла 0..1. При единице выключаются кривая, виньетка,
     зерно, расхождение каналов и контурная резкость, экспозиция встаёт
     в 1.0 и кадр режется по единице, как у них. При нуле кадр
     собирается ровно так, как его собирала плёнка в rv-real.js.

   ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ ПРАВКОЙ ПЛЁНКИ. Два конвейера в одном
   кадре подрались бы за мишени, поэтому конвейер остаётся ОДИН: пока
   этот проход жив, ядро зовёт его, а плёнку не зовёт вовсе. Мишень
   сцены при этом берётся У ПЛЁНКИ (поле `сцена`): она уже нужного
   размера, с буфером глубины, с мультисэмплом на полной ступени, и
   размер ей меняет ядро при повороте телефона. Своя мишень заводится
   только тогда, когда плёнки нет вовсе.

   СКОЛЬКО СТОИТ. Считано в полных кадрах отсчётов: спуск 13 отсчётов на
   точку по площадям 1/4 + 1/16 + ... = 4.33 кадра, подъём 10 отсчётов
   по тем же площадям без самой мелкой = 3.33 кадра, вместе 7.66. Прежняя
   пирамида плёнки стоила 3.48. Живой замер в конце файла в поле `мс`.

   ПАМЯТЬ. На столе 1440x900 при плотности 2.25 буфер 3240x2025, шесть
   уровней вниз и пять вверх занимают 35 МБ полуплавающего цвета. На
   телефоне 390x844 при плотности 2.0 это 7 МБ, на нищей ступени пирамида
   начинается с четверти кадра и занимает 0.8 МБ. Плотность около трёх у
   владельца попадает в среднюю строку.

   ИМЕНА ВНУТРИ GLSL ТОЛЬКО ЛАТИНИЦЕЙ. Кириллическая буква в шейдере не
   даёт ни исключения, ни строчки в консоли: программа просто не
   собирается, и весь кадр уходит в чёрное. Проверка tools/checks/глсл.mjs
   узнаёт шейдер по имени переменной вида Ф_ЧТО-ТО, поэтому массивы строк
   названы именно так. */
(function (g) {
  "use strict";

  var В_КВАД = [
    "varying vec2 vUv;",
    "void main(){ vUv = uv; gl_Position = vec4(position.xy, 0.0, 1.0); }"
  ].join("\n");

  /* ── СПУСК ────────────────────────────────────────────────────────
     Ядро igloo на тринадцать отсчётов: четыре внутренних по 0.125 на
     половине текселя, восемь внешних и центр по 0.0555555 на целом
     текселе. Веса дают ровно единицу (4*0.125 + 9*0.0555555 = 1.0).

     Это ядро стоит здесь не ради красоты. Простая билинейная выборка
     при уменьшении вдвое читает четыре точки из шестнадцати, и мелкая
     искра то попадает в отсчёт, то нет: на движении камеры ореол от неё
     мигает. Тринадцать отсчётов накрывают весь квадрат исходного
     уровня, и мигание пропадает.

     Предфильтр стоит ТОЛЬКО на первом спуске, из кадра. Формула их:
     точка отдаёт в ореол свой цвет, помноженный на свою же яркость,
     а не проходит целиком после порога. При пороге ноль это означает,
     что тёмная точка отдаёт мало и всё же отдаёт, и в кадре не остаётся
     ни одной мёртвой чёрной. Наш прежний смягчённый порог 0.62 давал
     ступеньку: ниже 0.38 линейного вклад ровно ноль. */
  var Ф_ВНИЗ = [
    "precision highp float;",
    "varying vec2 vUv;",
    "uniform sampler2D tD;",
    "uniform vec2 tx;",
    "uniform float thr;",
    "uniform float soft;",
    "uniform float hicap;",
    "uniform float pre;",
    "vec3 tap(vec2 uv){",
    /* Отсчёт за краем кадра даёт ноль, иначе кромка растекается сама в
       себя и по краю экрана появляется светлая рамка. */
    "  if (uv.x < 0.0 || uv.x > 1.0 || uv.y < 0.0 || uv.y > 1.0) return vec3(0.0);",
    "  vec3 c = texture2D(tD, uv).rgb;",
    "  if (pre > 0.5) {",
    "    float l = dot(c, vec3(0.2126, 0.7152, 0.0722));",
    "    l = smoothstep(thr, thr + soft, l) * l;",
    /* Потолок нужен против одной пересвеченной точки: без него вспышка
       прокола утаскивала в белое весь кадр. У igloo потолка нет, у нас
       кайма зажата тройкой, так что шесть это запас вдвое. */
    "    c = min(c, vec3(hicap)) * clamp(l, 0.0, 1.0);",
    "  }",
    "  return c;",
    "}",
    "void main(){",
    "  vec3 c = vec3(0.0);",
    "  c += tap(vUv + tx * vec2(-1.0,  1.0)) * 0.125;",
    "  c += tap(vUv + tx * vec2( 1.0,  1.0)) * 0.125;",
    "  c += tap(vUv + tx * vec2(-1.0, -1.0)) * 0.125;",
    "  c += tap(vUv + tx * vec2( 1.0, -1.0)) * 0.125;",
    "  c += tap(vUv + tx * vec2(-2.0,  2.0)) * 0.0555555;",
    "  c += tap(vUv + tx * vec2( 0.0,  2.0)) * 0.0555555;",
    "  c += tap(vUv + tx * vec2( 2.0,  2.0)) * 0.0555555;",
    "  c += tap(vUv + tx * vec2(-2.0,  0.0)) * 0.0555555;",
    "  c += tap(vUv + tx * vec2( 2.0,  0.0)) * 0.0555555;",
    "  c += tap(vUv + tx * vec2(-2.0, -2.0)) * 0.0555555;",
    "  c += tap(vUv + tx * vec2( 0.0, -2.0)) * 0.0555555;",
    "  c += tap(vUv + tx * vec2( 2.0, -2.0)) * 0.0555555;",
    "  c += tap(vUv) * 0.0555555;",
    "  gl_FragColor = vec4(c, 1.0);",
    "}"
  ].join("\n");

  /* ── ПОДЪЁМ ───────────────────────────────────────────────────────
     Шатёр 3x3 (0.0625 по углам, 0.125 по сторонам, 0.25 в центре, сумма
     единица) по МЕЛКОМУ уровню, потом смешивание с опорой того же
     размера, что и цель.

     Опора это уровень спуска, а размытое приходит с уровня ниже. Число
     rad решает, чего в кадре больше. Замер функции рассеяния точки на
     кадре 1440x900, радиус, внутри которого лежит доля света ореола:

       rad 0.50: R50=5   R80=12   R90=23   R99=125
       rad 0.70: R50=9   R80=44   R90=90   R99=192
       rad 0.85: R50=32  R80=105  R90=142  R99=219
       rad 1.00: R80=147 R90=174  R99=239, но R50 прыгает до 97

     На единице ядро уходит и остаётся молоко, на 0.7 пропадает середина
     ореола и свет читается наклейкой. 0.85 держим на всех ступенях
     качества: rad это ФОРМА света, и телефон с монитором обязаны
     показывать одну форму. Ступенями режется число уровней. */
  var Ф_ВВЕРХ = [
    "precision highp float;",
    "varying vec2 vUv;",
    "uniform sampler2D tD;",
    "uniform sampler2D tO;",
    "uniform vec2 tx;",
    "uniform float rad;",
    "void main(){",
    "  vec3 c = vec3(0.0);",
    "  c += texture2D(tD, vUv + tx * vec2(-1.0,  1.0)).rgb * 0.0625;",
    "  c += texture2D(tD, vUv + tx * vec2( 0.0,  1.0)).rgb * 0.125;",
    "  c += texture2D(tD, vUv + tx * vec2( 1.0,  1.0)).rgb * 0.0625;",
    "  c += texture2D(tD, vUv + tx * vec2(-1.0,  0.0)).rgb * 0.125;",
    "  c += texture2D(tD, vUv).rgb * 0.25;",
    "  c += texture2D(tD, vUv + tx * vec2( 1.0,  0.0)).rgb * 0.125;",
    "  c += texture2D(tD, vUv + tx * vec2(-1.0, -1.0)).rgb * 0.0625;",
    "  c += texture2D(tD, vUv + tx * vec2( 0.0, -1.0)).rgb * 0.125;",
    "  c += texture2D(tD, vUv + tx * vec2( 1.0, -1.0)).rgb * 0.0625;",
    "  vec3 o = texture2D(tO, vUv).rgb;",
    "  gl_FragColor = vec4(mix(o, c, rad), 1.0);",
    "}"
  ].join("\n");

  /* ── СБОРКА ───────────────────────────────────────────────────────
     Один проход на всё: сглаживание, расхождение каналов, резкость,
     размытие по скорости, свечение, экспозиция, кривая, пол, виньетка,
     перевод в sRGB, зерно. Три полных прохода по кадру вместо одного
     стоили бы дороже всего остального вместе взятого.

     Признак steklo ведёт кадр между двумя разными плёнками. При нуле
     это наша прежняя плёнка до последней цифры. При единице это igloo:
     у них между сценой и экраном стоят ровно три звена, и два из них не
     эффекты (рисование сцены, свечение, перевод в sRGB со сглаживанием).
     Ни кривой, ни экспозиции, ни виньетки, ни зерна, ни расхождения
     каналов, ни резкости у них нет НИГДЕ.

     Гасить их приходится по одной причине на каждое.
     · Кривая. Чтобы точка вышла белой, нашей кривой нужен линейный вход
       9.66, их плёнке хватает 1.0. Кайма трубы зажата тройкой, поэтому
       белого у нас не было и не могло быть ни при каком свечении.
     · Резкость 0.22. Она даёт крутизну кромки 152 единицы на точку при
       их 86. Стекло и контурная резкость это противоположные вещи.
     · Виньетка. У них углы ровные, минимум по кадру 73.8 и 84.5,
       провала к краям нет вовсе.
     · Зерно. На полуплавающей мишени полос не бывает, зерно там только
       грязнит. Дизеринг в одну двухсотпятидесятипятую остаётся всегда,
       он держит тёмные заливки от ступеней.
     · Расхождение каналов. Их ореол ХОЛОДНЕЕ ядра: самый светлый пояс
       #d3dae5..#feffff, синий выше красного на 18-23 при любой яркости.
       Тёплая подкраска дальнего уровня, которая была у нас, тянула ровно
       против этого и её здесь нет совсем. */
  var Ф_СБОРКА = [
    "precision highp float;",
    "varying vec2 vUv;",
    "uniform sampler2D tD;",
    "uniform sampler2D tB;",
    "uniform float glow;",
    "uniform float vig;",
    "uniform float grain;",
    "uniform float time;",
    "uniform float expo;",
    "uniform vec3 pol;",
    "uniform vec2 px;",
    "uniform float ca;",
    "uniform float sharp;",
    "uniform float aa;",
    "uniform float speed;",
    "uniform vec2 vpt;",
    "uniform float boost;",
    "uniform float steklo;",
    "float ign(vec2 p){ return fract(52.9829189 * fract(0.06711056 * p.x + 0.00583715 * p.y)); }",
    "float luma(vec3 c){ return dot(c, vec3(0.299, 0.587, 0.114)); }",
    /* Краевой поиск: яркость в кресте вокруг точки, направление
       наибольшего перепада, подмешивание соседа ПОПЕРЁК него. Ровные
       места не трогаются вовсе. У igloo на этом месте стоит SMAA, у нас
       пять отсчётов на точку и та же работа. */
    "vec3 sgladit(vec2 uv){",
    "  vec3 c = texture2D(tD, uv).rgb;",
    "  if (aa < 0.5) return c;",
    "  float lC = luma(c);",
    "  float lN = luma(texture2D(tD, uv + vec2(0.0, px.y)).rgb);",
    "  float lS = luma(texture2D(tD, uv - vec2(0.0, px.y)).rgb);",
    "  float lE = luma(texture2D(tD, uv + vec2(px.x, 0.0)).rgb);",
    "  float lW = luma(texture2D(tD, uv - vec2(px.x, 0.0)).rgb);",
    "  float mx = max(lC, max(max(lN, lS), max(lE, lW)));",
    "  float mn = min(lC, min(min(lN, lS), min(lE, lW)));",
    "  float kr = mx - mn;",
    "  if (kr < 0.045) return c;",
    "  vec2 d = normalize(vec2(abs(lE - lW) + 1e-5, abs(lN - lS) + 1e-5));",
    "  vec2 pop = vec2(-d.y, d.x) * px * 1.35;",
    "  vec3 a = texture2D(tD, uv + pop).rgb;",
    "  vec3 b = texture2D(tD, uv - pop).rgb;",
    "  float sila = clamp(kr * 3.4, 0.0, 1.0);",
    "  return mix(c, (a + b + c * 2.0) * 0.25, sila);",
    "}",
    "void main(){",
    "  float st = clamp(steklo, 0.0, 1.0);",
    "  vec2 ot = vUv - 0.5;",
    "  float r2 = dot(ot, ot);",
    "  float caK = (ca + 0.010 * speed + 0.02 * boost) * (1.0 - st);",
    "  vec2 sdv = ot * r2 * caK;",
    "  vec3 gg = sgladit(vUv);",
    "  vec3 c = vec3(",
    "    texture2D(tD, vUv + sdv).r,",
    "    gg.g,",
    "    texture2D(tD, vUv - sdv).b);",
    "  c = mix(c, gg, 0.15);",
    "  float shK = sharp * (1.0 - st);",
    "  if (shK > 0.001) {",
    "    vec3 mjk = (texture2D(tD, vUv + vec2(px.x, 0.0)).rgb",
    "              + texture2D(tD, vUv - vec2(px.x, 0.0)).rgb",
    "              + texture2D(tD, vUv + vec2(0.0, px.y)).rgb",
    "              + texture2D(tD, vUv - vec2(0.0, px.y)).rgb) * 0.25;",
    "    c += (c - mjk) * shK;",
    "  }",
    /* Размытие по скорости в стекле остаётся наполовину. У igloo его
       нет вовсе, но у нас в тоннеле камера идёт быстрее всего, и полный
       отказ от него сделал бы движение рваным. */
    "  if (speed > 0.02) {",
    "    vec2 dir = (vUv - vpt) * 0.006 * speed;",
    "    vec3 rz = texture2D(tD, vUv - dir).rgb",
    "            + texture2D(tD, vUv - dir * 2.0).rgb * 0.85",
    "            + texture2D(tD, vUv - dir * 3.0).rgb * 0.70",
    "            + texture2D(tD, vUv - dir * 4.0).rgb * 0.55",
    "            + texture2D(tD, vUv - dir * 5.0).rgb * 0.45",
    "            + texture2D(tD, vUv - dir * 6.0).rgb * 0.40;",
    "    c = mix(c, rz / 3.95, 0.7 * speed * (1.0 - 0.5 * st));",
    "  }",
    /* Складывание SCREEN, формула их: mix(x, x + y - min(x*y, 1), 1).
       Оно тем и отличается от сложения, что светлое место не может стать
       ещё светлее до бесконечности, а тёмное поднимается на всю величину
       ореола. Именно этим у них поднимается тёмный камень колец с 118
       до 158 и не остаётся ни одной чёрной точки. */
    "  vec3 h = texture2D(tB, vUv).rgb * glow;",
    "  c = c + h - min(c * h, vec3(1.0));",
    "  c *= mix(expo * (1.0 + 0.45 * boost), 1.0, st);",
    "  vec3 tone = (c * (2.51 * c + 0.03)) / (c * (2.43 * c + 0.59) + 0.14);",
    "  tone = pol + (vec3(1.0) - pol) * tone;",
    "  c = mix(tone, clamp(c, 0.0, 1.0), st);",
    "  float r = distance(vUv, vec2(0.5));",
    "  c *= 1.0 - vig * (1.0 - st) * (1.0 + 0.6 * speed) * smoothstep(0.35, 0.95, r);",
    "  c = clamp(c, 0.0, 1.0);",
    "  c = mix(12.92 * c, 1.055 * pow(c, vec3(1.0 / 2.4)) - 0.055, step(vec3(0.0031308), c));",
    "  float n = ign(gl_FragCoord.xy + vec2(fract(time * 0.37) * 97.0)) - 0.5;",
    "  c += n * grain * (1.0 - st) + n * (1.0 / 255.0);",
    "  gl_FragColor = vec4(c, 1.0);",
    "}"
  ].join("\n");

  /* ── Состояние ────────────────────────────────────────────────── */
  var О = null;          /* собранный проход, null пока мир не поднялся */
  var сломан = false;    /* сборка не удалась, ядро рисует по-старому */
  var ВКЛ = true;
  var СИЛА = 1.0;        /* intensity ореола, у igloo ровно 1 */
  var СТЕКЛО = 0.0;      /* 0 наша плёнка, 1 их плёнка */
  var АВТО = true;       /* стекло ведут акты через порог плёнки */
  var внутри = false;    /* защита от повторного входа */

  function мишень(T, w, h, тип) {
    return new T.WebGLRenderTarget(Math.max(2, w), Math.max(2, h), {
      minFilter: T.LinearFilter, magFilter: T.LinearFilter,
      format: T.RGBAFormat, type: тип, depthBuffer: false, stencilBuffer: false
    });
  }

  /* Сколько уровней и с какой доли кадра начинать.

     Ступень 2 повторяет igloo дословно: пирамида начинается с половины
     кадра (у них resolutionScale 0.5) и идёт шестью уровнями до 1/64,
     что на 1440x900 даёт самый мелкий уровень 23x14 точек. Радиус 80%
     света ореола выходит 105 точек, ровно как у них.

     Ступень 1 отдаёт один уровень: самый мелкий становится 1/32, радиус
     80% света падает до 58 точек. Ореол уже, но живой.

     Ступень 0 начинается не с половины, а с четверти кадра, и берёт
     четыре уровня. Самый мелкий выходит той же 1/32, то есть ширина
     ореола почти как на средней ступени, а памяти уходит вчетверо
     меньше: 0.8 МБ против 3.5. Плотность буфера на телефоне владельца
     около трёх, и цели во весь экран на такой плотности дороги. */
  function лестница(ступень) {
    if (ступень === 0) return { начало: 2, уровней: 4 };
    if (ступень === 1) return { начало: 1, уровней: 5 };
    return { начало: 1, уровней: 6 };
  }

  function размеры(О, w, h) {
    var лw = w, лh = h, i;
    for (i = 0; i < О.начало; i++) { лw = Math.max(2, лw >> 1); лh = Math.max(2, лh >> 1); }
    for (i = 0; i < О.вниз.length; i++) {
      О.вниз[i].w = Math.max(2, лw); О.вниз[i].h = Math.max(2, лh);
      О.вниз[i].ц.setSize(О.вниз[i].w, О.вниз[i].h);
      if (О.вверх[i]) { О.вверх[i].w = О.вниз[i].w; О.вверх[i].h = О.вниз[i].h; О.вверх[i].ц.setSize(О.вниз[i].w, О.вниз[i].h); }
      лw = Math.max(2, лw >> 1); лh = Math.max(2, лh >> 1);
    }
    О.мСборка.uniforms.px.value.set(1 / Math.max(2, w), 1 / Math.max(2, h));
    О.w = w; О.h = h;
  }

  function построить(О, T, уровней) {
    var i;
    for (i = 0; i < О.вниз.length; i++) {
      О.вниз[i].ц.dispose();
      if (О.вверх[i]) О.вверх[i].ц.dispose();
    }
    О.вниз = []; О.вверх = [];
    for (i = 0; i < уровней; i++) {
      О.вниз.push({ w: 2, h: 2, ц: мишень(T, 2, 2, О.тип) });
      /* Подъёмов на один меньше: самый мелкий уровень поднимать некуда,
         с него подъём и начинается. */
      О.вверх.push(i < уровней - 1 ? { w: 2, h: 2, ц: мишень(T, 2, 2, О.тип) } : null);
    }
    размеры(О, О.w, О.h);
  }

  /* ── Сборка прохода ───────────────────────────────────────────── */
  function собрать(W) {
    var T = W.T, р = W.r;
    if (!T || !р) return null;

    var второйWebGL = false, полуМожно = false;
    try {
      второйWebGL = !!р.capabilities.isWebGL2;
      полуМожно = второйWebGL || р.extensions.has("EXT_color_buffer_half_float");
    } catch (e) {}
    var тип = полуМожно ? (T.HalfFloatType || T.FloatType) : T.UnsignedByteType;

    var ступень = W.ступень || 0;
    var л = лестница(ступень);

    var Н = {
      T: T, р: р, тип: тип, ступень: ступень,
      начало: л.начало, вниз: [], вверх: [],
      своя: null, w: 2, h: 2,
      мс: 0, кадров: 0, проверен: false
    };

    /* Мишень сцены берётся у плёнки: она уже нужного размера, с буфером
       глубины (по нему пыль и плиты мягко гаснут у поверхностей) и с
       мультисэмплом на полной ступени. Ядро само меняет ей размер при
       повороте телефона, и второй такой же буфер во весь экран на
       плотности три обошёлся бы в лишние 26 МБ. */
    var плёнка = W["плёнка"];
    if (плёнка && плёнка["сцена"]) {
      Н.сцена = плёнка["сцена"];
    } else {
      Н.своя = new T.WebGLRenderTarget(2, 2, {
        minFilter: T.LinearFilter, magFilter: T.LinearFilter,
        format: T.RGBAFormat, type: тип, depthBuffer: true, stencilBuffer: false
      });
      Н.сцена = Н.своя;
    }

    Н.мВниз = new T.ShaderMaterial({
      uniforms: {
        tD: { value: null }, tx: { value: new T.Vector2(1, 1) },
        /* Порог ноль это и есть вся суть прохода. Смягчение 0.025 их же:
           при нулевом пороге оно всё равно ставится, потому что больше
           нуля. */
        thr: { value: 0.0 }, soft: { value: 0.025 },
        hicap: { value: полуМожно ? 6.0 : 1.0 },
        pre: { value: 0.0 }
      },
      vertexShader: В_КВАД, fragmentShader: Ф_ВНИЗ,
      depthTest: false, depthWrite: false
    });

    Н.мВверх = new T.ShaderMaterial({
      uniforms: {
        tD: { value: null }, tO: { value: null },
        tx: { value: new T.Vector2(1, 1) }, rad: { value: 0.85 }
      },
      vertexShader: В_КВАД, fragmentShader: Ф_ВВЕРХ,
      depthTest: false, depthWrite: false
    });

    Н.мСборка = new T.ShaderMaterial({
      uniforms: {
        tD: { value: null }, tB: { value: null },
        glow: { value: СИЛА },
        vig: { value: 0.26 },
        grain: { value: ступень === 0 ? 0.0 : 0.012 },
        expo: { value: 0.75 },
        pol: { value: new T.Vector3(0.010, 0.013, 0.0225) },
        time: { value: 0 },
        px: { value: new T.Vector2(0.5, 0.5) },
        ca: { value: ступень === 0 ? 0.0 : 0.0042 },
        sharp: { value: ступень === 0 ? 0.0 : 0.22 },
        aa: { value: ступень === 0 ? 0.0 : 1.0 },
        speed: { value: 0.0 },
        vpt: { value: new T.Vector2(0.5, 0.5) },
        boost: { value: 0.0 },
        steklo: { value: СТЕКЛО }
      },
      vertexShader: В_КВАД, fragmentShader: Ф_СБОРКА,
      depthTest: false, depthWrite: false
    });

    Н.кам = new T.OrthographicCamera(-1, 1, 1, -1, 0, 1);
    Н.квад = new T.Mesh(new T.PlaneGeometry(2, 2), Н.мВниз);
    Н.сценаКв = new T.Scene();
    Н.сценаКв.add(Н.квад);

    Н.w = Math.max(2, Н.сцена.width || 2);
    Н.h = Math.max(2, Н.сцена.height || 2);
    построить(Н, T, л.уровней);

    /* Мост к актам. Акты про этот файл не знают и знать им незачем: они
       уже ведут порог плёнки по ходу сцены. Тоннель опускает его с 0.62
       до 0.12 и ниже, станция поднимает обратно в 0.62. Это ровно те
       места, где нужно и где не нужно стекло, поэтому признак стекла
       считается из порога и никаких правок в актах не требует.

       Метод `стекло` дописывается на плёнку тем же движением: сосед,
       который будет вести стекло из акта явно, позовёт его и попадёт
       сюда. */
    if (плёнка) {
      var старПорог = плёнка["порог"];
      плёнка["порог"] = function (v) {
        try { if (старПорог) старПорог.call(плёнка, v); } catch (e1) {}
        if (АВТО) {
          var s = (0.62 - Number(v)) / 0.62;
          СТЕКЛО = s > 1 ? 1 : (s > 0 ? s : 0);
        }
      };
      плёнка["стекло"] = function (v) { наружу["стекло"](v); };
    }

    return Н;
  }

  function прогон(Н, мат, цель) {
    Н.квад.material = мат;
    Н.р.setRenderTarget(цель || null);
    Н.р.render(Н.сценаКв, Н.кам);
  }

  /* Проверка буфера кадра один раз после первого рисования. Мишень сцены
     приходит от плёнки, и на первом WebGL мультисэмпл с полуплавающим
     цветом даёт неполный буфер: кадр молча уходит в никуда. */
  function проверитьБуфер(Н) {
    Н.проверен = true;
    if (!(Н.сцена.samples > 0)) return;
    try {
      var к = Н.р.getContext();
      var св = Н.р.properties.get(Н.сцена);
      var буфер = св.__webglMultisampledFramebuffer || св.__webglFramebuffer;
      if (!буфер) return;
      Н.р.state.bindFramebuffer(к.FRAMEBUFFER, буфер);
      var ок = к.checkFramebufferStatus(к.FRAMEBUFFER) === к.FRAMEBUFFER_COMPLETE;
      Н.р.state.bindFramebuffer(к.FRAMEBUFFER, null);
      if (!ок) { Н.сцена.samples = 0; Н.сцена.dispose(); }
    } catch (e) {}
  }

  /* ── События кадра ────────────────────────────────────────────────
     Скорость и толчок живут здесь по той же причине, по которой они жили
     в плёнке: камера едет мягко сама по себе, а плёнке нужна своя
     постоянная времени, чтобы росчерки не обрывались на первом медленном
     кадре. */
  var прежниеЧасы = -1, норм = 0, толчок = 0;
  var прежнееМесто = null, точка = null, ходК = null;

  function скоростьКамеры(Н, камера, dt) {
    var T = Н.T;
    if (!прежнееМесто) {
      прежнееМесто = new T.Vector3(); точка = new T.Vector3(); ходК = new T.Vector3();
      прежнееМесто.copy(камера.position);
      return 0;
    }
    ходК.copy(камера.position).sub(прежнееМесто);
    прежнееМесто.copy(камера.position);
    var путь = ходК.length();
    if (путь < 1e-4 || dt <= 0) return 0;
    var v = Math.min(1, путь / dt / 150);
    ходК.multiplyScalar(200 / путь);
    точка.copy(камера.position).add(ходК).project(камера);
    if (!(точка.z < 1) || !isFinite(точка.x) || !isFinite(точка.y)) {
      точка.copy(камера.position).sub(ходК).project(камера);
    }
    if (isFinite(точка.x) && isFinite(точка.y)) {
      Н.мСборка.uniforms.vpt.value.set(
        Math.max(-0.3, Math.min(1.3, точка.x * 0.5 + 0.5)),
        Math.max(-0.3, Math.min(1.3, точка.y * 0.5 + 0.5)));
    }
    return v;
  }

  function рисовать(Н, сцена, камера, часы) {
    var прежний = Н.р.getRenderTarget();
    var т = часы || 0;
    var dtСырой = прежниеЧасы < 0 ? 0.016 : Math.max(0, т - прежниеЧасы);
    var dt = Math.min(0.1, dtСырой);
    прежниеЧасы = т;

    var цель = 0;
    if (Н.ступень > 0) {
      var с = null;
      try { if (g.RV_WORLD && g.RV_WORLD["скорость"]) с = g.RV_WORLD["скорость"](); } catch (eС) {}
      if (typeof с === "number") цель = Math.max(0, Math.min(1, с));
      else if (с && typeof с["доля"] === "number") цель = Math.max(0, Math.min(1, с["доля"]));
      else if (камера) цель = скоростьКамеры(Н, камера, dt);
    }
    норм += (цель - норм) * (1 - Math.exp(-dt / 0.12));
    толчок *= Math.exp(-Math.min(1, dtСырой) / 0.28);
    Н.мСборка.uniforms.speed.value = норм < 0.01 ? 0 : норм;
    Н.мСборка.uniforms.boost.value = толчок < 0.005 ? 0 : толчок;

    /* Размер мишени сцены ведёт ядро. Сверяем каждый кадр: сравнение двух
       чисел стоит ноль, а после поворота телефона несовпадение уровней
       уводит ореол на треть кадра вбок. */
    var w = Math.max(2, Н.сцена.width), h = Math.max(2, Н.сцена.height);
    if (Н.своя) {
      var бр = Н.р.getDrawingBufferSize(new Н.T.Vector2());
      w = Math.max(2, Math.floor(бр.x)); h = Math.max(2, Math.floor(бр.y));
      if (Н.своя.width !== w || Н.своя.height !== h) Н.своя.setSize(w, h);
    }
    if (Н.w !== w || Н.h !== h) размеры(Н, w, h);

    Н.р.setRenderTarget(Н.сцена);
    Н.р.clear();
    Н.р.render(сцена, камера);
    if (!Н.проверен) проверитьБуфер(Н);

    var т0 = 0;
    try { т0 = g.performance ? g.performance.now() : 0; } catch (eВ) {}

    /* Спуск. Каждый следующий уровень читает ПРЕДЫДУЩИЙ, уже собранный:
       в этом вся дешевизна пирамиды. Предфильтр только на первом. */
    var ист = Н.сцена.texture, истW = w, истH = h, k;
    for (k = 0; k < Н.вниз.length; k++) {
      Н.мВниз.uniforms.tD.value = ист;
      Н.мВниз.uniforms.tx.value.set(1 / истW, 1 / истH);
      Н.мВниз.uniforms.pre.value = (k === 0) ? 1.0 : 0.0;
      прогон(Н, Н.мВниз, Н.вниз[k].ц);
      ист = Н.вниз[k].ц.texture; истW = Н.вниз[k].w; истH = Н.вниз[k].h;
    }

    /* Подъём от самого мелкого вверх. Опора для уровня k это уровень
       спуска того же размера, и смешивание mix(опора, размытое, 0.85)
       на каждом шаге собирает и тугое ядро, и широкий нимб. */
    var итог = ист;
    for (k = Н.вниз.length - 2; k >= 0; k--) {
      Н.мВверх.uniforms.tD.value = ист;
      Н.мВверх.uniforms.tO.value = Н.вниз[k].ц.texture;
      Н.мВверх.uniforms.tx.value.set(1 / истW, 1 / истH);
      прогон(Н, Н.мВверх, Н.вверх[k].ц);
      ист = Н.вверх[k].ц.texture; истW = Н.вверх[k].w; истH = Н.вверх[k].h;
      итог = ист;
    }

    Н.мСборка.uniforms.tD.value = Н.сцена.texture;
    Н.мСборка.uniforms.tB.value = итог;
    Н.мСборка.uniforms.time.value = т;
    Н.мСборка.uniforms.glow.value = СИЛА;
    Н.мСборка.uniforms.steklo.value = СТЕКЛО;
    прогон(Н, Н.мСборка, null);

    try {
      if (g.performance && т0) {
        var мс = g.performance.now() - т0;
        Н.мс = Н.кадров ? (Н.мс * 0.92 + мс * 0.08) : мс;
        Н.кадров++;
      }
    } catch (eВ2) {}

    Н.р.setRenderTarget(прежний);
  }

  /* ── Наружу ───────────────────────────────────────────────────── */
  var наружу = {

    /* Ядро зовёт это ОДНОЙ строкой вместо рисования кадра. Возврат false
       означает «рисуй сам»: мир обязан появиться на экране даже тогда,
       когда этого прохода нет. Отказывать в содержимом нельзя ни по
       какой причине. */
    "кадр": function (W) {
      if (!ВКЛ || сломан || внутри || !W || !W.r || !W.scene || !W.cam) return false;
      внутри = true;
      try {
        if (!О) О = собрать(W);
        if (!О) { сломан = true; return false; }
        рисовать(О, W.scene, W.cam, W.часы);
        return true;
      } catch (e) {
        сломан = true;
        try { W.r.setRenderTarget(null); } catch (e2) {}
        return false;
      } finally {
        внутри = false;
      }
    },

    /* Сила ореола. У igloo ровно единица и по ходу сцены она не
       меняется вовсе: порог, intensity и radius ставятся один раз и
       дальше их не трогает ни лента времени, ни камера. Ход по актам это
       наша добавка, и она нужна: над землёй у нас космос, у них над
       землёй ничего. */
    "сила": function (v) {
      var с = Number(v);
      СИЛА = isFinite(с) ? Math.max(0, Math.min(4, с)) : 1.0;
      if (О) О.мСборка.uniforms.glow.value = СИЛА;
    },

    /* Признак стекла. Число 0..1 ставит его руками и снимает
       вычисление из порога, null возвращает вычисление обратно. */
    "стекло": function (v) {
      if (v === null || v === undefined) { АВТО = true; return; }
      var с = Number(v);
      if (!isFinite(с)) return;
      АВТО = false;
      СТЕКЛО = Math.max(0, Math.min(1, с));
      if (О) О.мСборка.uniforms.steklo.value = СТЕКЛО;
    },

    /* Порог свечения. Ноль это их число и наше рабочее. Держится
       наружу для замеров: с порогом 0.62 проход считает ровно то же,
       что считала прежняя плёнка, и разницу видно на одном кадре. */
    "порог": function (v) {
      var с = Number(v);
      if (!isFinite(с) || !О) return;
      О.мВниз.uniforms.thr.value = Math.max(0, с);
    },

    "вкл": function (да) { ВКЛ = !!да; },

    /* Число уровней пирамиды. Ступень качества ставит его при сборке,
       наружу оно нужно замеру: ширина ореола растёт почти вдвое на
       каждый уровень (радиус 80% света: 3 уровня 17 точек, 4 уровня 31,
       5 уровней 58, 6 уровней 105). */
    "уровни": function (n) {
      var к = Math.max(2, Math.min(8, Number(n) | 0));
      if (!О || к === О.вниз.length) return;
      построить(О, О.T, к);
    },

    "сведения": function () {
      if (!О) return { "жив": false, "сломан": сломан };
      var р = [], k;
      for (k = 0; k < О.вниз.length; k++) р.push(О.вниз[k].w + "x" + О.вниз[k].h);
      return {
        "жив": true, "сломан": сломан, "вкл": ВКЛ,
        "ступень": О.ступень, "уровней": О.вниз.length, "начало": О.начало,
        "кадр": О.w + "x" + О.h, "уровни": р,
        "сила": СИЛА, "стекло": СТЕКЛО, "авто": АВТО,
        "радиус": О.мВверх.uniforms.rad.value,
        "порог": О.мВниз.uniforms.thr.value,
        "мс": Math.round(О.мс * 1000) / 1000,
        "своя": !!О.своя
      };
    }
  };

  /* Толчок от событий мира: короткий всплеск экспозиции и расхождения
     каналов. Берётся максимум, а не сумма: два события подряд не должны
     заливать кадр белым. */
  function толкнуть(с) {
    var v = Number(с);
    if (!(v > 0)) v = 1;
    толчок = Math.max(толчок, Math.min(1, v));
  }
  function поСобытию(поУмолчанию) {
    return function (e) {
      var с = поУмолчанию;
      try { if (e && e.detail && typeof e.detail["сила"] === "number") с = e.detail["сила"]; } catch (x) {}
      толкнуть(с);
    };
  }
  try {
    g.addEventListener("rv:прокол", поСобытию(1));
    g.addEventListener("rv:станция", поСобытию(0.25));
    g.addEventListener("rv:стыковка", поСобытию(0.5));
  } catch (eЛ) {}

  g.RV_ОРЕОЛ = наружу;
})(window);
