<?php
/**
 * V.LIONOFF · воронка бота. Запускается кроном раз в 15 минут.
 *
 * Правило времени: наружу ничего не уходит ночью. Касания идут 10:00–21:00
 * по Москве, даже если срок подошёл раньше — письмо в час ночи человек читает
 * как спам робота.
 *
 *   каждые 15 минут: строка crontab лежит в tools/deploy.sh
 */
declare(strict_types=1);

require_once __DIR__ . '/../core/db.php';
require_once __DIR__ . '/../core/telegram.php';

date_default_timezone_set('Europe/Moscow');
$hour = (int) date('G');
if ($hour < 10 || $hour >= 21) {
  echo date('H:i') . " вне окна касаний, стоим\n";
  exit;
}

$ШАГИ = [
  // шаг => [через сколько после прошлого, текст, кнопка]
  1 => ['+2 hour',
        "Короткий ориентир по V.LIONOFF.\n\nПервый блок курса открыт бесплатно: "
        . "четыре урока о том, как снять ролик, который досматривают. "
        . "Пройдите один — на это уйдёт семь минут.",
        'Открыть первый урок'],
  2 => ['+1 day',
        "Самая частая ошибка новичка — снимать «красиво», а не «понятно».\n\n"
        . "Ролик держат первые три секунды: показали результат, назвали пользу, "
        . "дальше объяснили. В уроке «Первые три секунды» это разложено по шагам.",
        'Посмотреть урок'],
  3 => ['+2 day',
        "В приложении есть биржа: заказчики оставляют заявки на обзоры, рилс и съёмку. "
        . "Откликаться можно после трёх пройденных уроков — так заказчик видит, "
        . "что человек умеет, а не обещает.",
        'Посмотреть заявки'],
  4 => ['+3 day',
        "Что даёт тариф PRO: весь курс, сертификат, отклики на заявки и место в каталоге "
        . "исполнителей, где вас находят заказчики.\n\nЕсть промокод на первый месяц — "
        . "напишите в поддержку, если нужен.",
        'Тарифы'],
];

$now = date('Y-m-d H:i:s');
$leads = vc_all("SELECT * FROM leads WHERE stage NOT IN ('paid','lost') AND next_at IS NOT NULL
                 AND next_at <= ? ORDER BY next_at LIMIT 120", [$now]);
$отправлено = 0;
foreach ($leads as $lead) {
  $шаг = (int)$lead['step'] + 1;
  if (!isset($ШАГИ[$шаг])) {
    vc_update('leads', ['next_at' => null, 'stage' => 'warm'], 'id=?', [$lead['id']]);
    continue;
  }
  // Платящий или активный ученик дожимать себя не даёт: он уже внутри.
  $u = vc_one('SELECT * FROM users WHERE tg_id=?', [$lead['tg_id']]);
  if ($u && ($u['plan'] !== 'free' || (int)$u['notify'] === 0)) {
    vc_update('leads', ['stage' => $u['plan'] !== 'free' ? 'paid' : 'lost', 'next_at' => null],
              'id=?', [$lead['id']]);
    continue;
  }
  [$через, $текст, $кнопка] = $ШАГИ[$шаг];
  $res = vc_tg_send((int)$lead['tg_id'], $текст, vc_tg_app_button($кнопка));
  $дальше = isset($ШАГИ[$шаг + 1]) ? date('Y-m-d H:i:s', strtotime($ШАГИ[$шаг + 1][0])) : null;
  vc_update('leads', [
    'step' => $шаг,
    'stage' => $шаг >= 3 ? 'offer' : 'warm',
    'next_at' => $дальше,
    'updated_at' => $now,
    'note' => ($res && !empty($res['ok'])) ? '' : 'не доставлено',
  ], 'id=?', [$lead['id']]);
  if ($res && !empty($res['ok'])) { $отправлено++; }
  usleep(400000);
}
echo date('H:i') . " касаний отправлено: $отправлено из " . count($leads) . "\n";
