def отчёт(шоты: list, всего: int) -> None:
    длины = [ш["кадров"] / FPS for ш in шоты]
    ось = sum(1 for ш in шоты if ш["макет"] in ОСЬ and ш["слова"])
    со_словами = sum(1 for ш in шоты if ш["слова"])
    print("шотов: %d на %.1f мин" % (len(шоты), всего / FPS / 60))
    print("длина шота: средняя %.1f с, самый длинный %.1f с" % (sum(длины) / len(длины), max(длины)))
    print("текст на центральной оси: %d из %d (%.0f%%)" % (ось, со_словами, ось / со_словами * 100))
    for поле in ("макет", "текст_вид", "медиа", "графика", "вещь", "фон", "шрифт",
                 "камера", "вход", "вход_слов", "тон", "рез", "ключ_арт", "клип"):
        подряд = max_подряд(шоты, поле)
        разных = len({ш.get(поле) for ш in шоты if ш.get(поле) not in (None, "")})
        в25 = len({ш.get(поле) for ш in шоты[:25] if ш.get(поле) not in (None, "")})
        print("  %-10s разных %2d, подряд одинаковых %d, в первых 25 разных %d"
              % (поле, разных, подряд, в25))


def max_подряд(шоты: list, поле: str) -> int:
    лучший, текущий, прошлое = 1, 1, object()
    for ш in шоты:
        з = ш.get(поле)
        if з == прошлое and з not in (None, ""):
            текущий += 1
            лучший = max(лучший, текущий)
        else:
            текущий = 1
        прошлое = з
    return лучший


