class Выбор:
    """Признак без повторов: что было в окне, не берём; дальше самое редкое."""

    def __init__(self, окно: int, rnd, веса=None):
        self.окно = окно
        self.rnd = rnd
        self.веса = веса or {}
        self.последние = []
        self.счёт = {}

    def взять(self, варианты, кроме=()):
        варианты = [в for в in dict.fromkeys(варианты) if в is not None and в not in кроме]
        if not варианты:
            return None
        окно = self.последние[-self.окно:]
        годные = [в for в in варианты if в not in окно]
        if not годные:
            последний = self.последние[-1] if self.последние else None
            годные = [в for в in варианты if в != последний] or варианты
        ключ = lambda в: self.счёт.get(в, 0) / float(self.веса.get(в, 1.0))
        мин = min(ключ(в) for в in годные)
        лучшие = [в for в in годные if abs(ключ(в) - мин) < 1e-9]
        в = self.rnd.choice(лучшие)
        self.счёт[в] = self.счёт.get(в, 0) + 1
        self.последние.append(в)
        return в


def есть(файл: str) -> bool:
    п = os.path.join(КАДРЫ, файл)
    return os.path.exists(п) and os.path.getsize(п) > 10000


def p_текст(п: dict) -> str:
    return п.get("текст") or " · ".join(п.get("строки", [])[:2])


def годные_тексты(к: list, ключ: str, циф: str, арт: str, знаков: int, макет: str) -> list:
    """Какая подача влезает в эту фразу и в этот короб."""
    слов = len(к)
    высокий = макет in ВЫСОКИЙ_ТЕКСТ
    средний = макет in СРЕДНИЙ_ТЕКСТ
    нельзя = set()
    # Подачи в столбик (лесенка, диагональ, вертикаль, сетка) требуют роста:
    # в нижней полосе они вылезают за край листа.
    if not высокий:
        нельзя.update(["лесенка", "диагональ", "вертикаль", "сетка"])
    if слов > 6:
        нельзя.add("лесенка")
    if слов > 7 or max((len(w["слово"]) for w in к), default=0) > 11:
        нельзя.add("вертикаль")
    if слов < 2 or слов > 9:
        нельзя.add("сетка")
    if слов > 7:
        нельзя.add("диагональ")
    if not ключ or not (высокий or средний):
        нельзя.update(["лента", "акцент"])
    if слов > 9:
        нельзя.add("акцент")
    if not циф:
        нельзя.add("цифра")
    if знаков > 70:
        нельзя.update(["обводка", "вертикаль", "диагональ"])
    годные = [т for т in ТЕКСТ_ВИДЫ if т not in нельзя]
    return годные or ["обычный"]


def годные_медиа(макет: str, графики: list, вещей: int, арт: str, можно_клип: bool) -> list:
    если = []
    for м in МЕДИА_ВИДЫ:
        if м == "график" and not графики:
            continue
        if м == "клип" and not можно_клип:
            continue
        if м == "карточка" and not арт:
            continue
        if м in ("вещи", "карусель") and (макет not in ШИРОКОЕ_МЕДИА or вещей < 3):
            continue
        if м == "карусель" and макет not in ("низ", "верх", "полный"):
            continue
        # Объёмным построениям нужен высокий короб: в полосе они схлопываются
        # в плоский прямоугольник и перестают читаться объёмом.
        # Коридору и плитам нужен рост короба: в низкой полосе тоннель
        # обрезается, и кадр читается пустым.
        if м in ("орбита", "плиты", "коридор") and макет not in ВЫСОКОЕ_МЕДИА:
            continue
        если.append(м)
    return если


