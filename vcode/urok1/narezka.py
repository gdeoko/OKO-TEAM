"""Монтажный лист: урок режется на шоты по фразам озвучки.

Единица монтажа это фраза, а не сцена. Из таймкодов слов собираются куски по
2-4 секунды, каждому назначается свой тип кадра, и подряд одинаковых типов нет.

    python3 narezka.py
"""
import json
import os
import random as сл
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sborka2 import по_сценарию   # слова на экране свои, время из расшифровки

КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))
ПУБЛИКА = os.path.join(КОРЕНЬ, "remotion", "public")
FPS = 25
ПАУЗА_РЕЗА = 0.42      # разрыв между словами, по которому режем фразу
МАКС_СЕК = 3.6         # дольше на экране ничего не висит
МАКС_СЛОВ = 11
ХВОСТ = 0.35           # добор после последнего слова фразы

# Типы кадров. Под каждый вид сцены свой набор, чтобы приём шёл по смыслу.
ТИПЫ_ТЕКСТ = ["крупно", "акцент", "полоса", "раскол", "лесенка", "шторка", "угол"]
ТИПЫ_ПРЕДМЕТ = ["предмет_пролёт", "предмет_крупно", "предмет_сетка", "предмет_разбор"]
ТИПЫ_ГРАФИКА = ["график_общий", "график_деталь", "график_сбоку", "график_маска"]
# Предмет-компаньон для текстовых кадров: в кадре всегда есть вещь.
ВИЗУАЛ = ["предмет_крупно", "предмет_сетка", "предмет_пролёт", "предмет_разбор"]
СПУТНИКИ = ["u2_kamera.png", "u2_obyektiv.png", "u2_obyektiv_shirokiy.png", "u2_petlichka.png",
            "u2_rekorder.png", "u2_pushka.png", "u2_softboks.png", "u2_kolco.png",
            "u2_shtativ.png", "u2_stedikam.png", "u2_dron.png", "u2_karta.png"]


def фразы(слова: list) -> list:
    """Слова в фразы: по знакам препинания, паузам и длине."""
    куски, текущая = [], []
    for i, с in enumerate(слова):
        текущая.append(с)
        конец = с["слово"].rstrip().endswith((".", "!", "?", ":"))
        длинно = (с["конец"] - текущая[0]["старт"]) > МАКС_СЕК or len(текущая) >= МАКС_СЛОВ
        пауза = i + 1 < len(слова) and (слова[i + 1]["старт"] - с["конец"]) > ПАУЗА_РЕЗА
        запятая = с["слово"].rstrip().endswith(",") and len(текущая) >= 5
        if конец or длинно or пауза or запятая:
            куски.append(текущая)
            текущая = []
    if текущая:
        куски.append(текущая)
    # Слишком короткие хвосты приклеиваем к соседу.
    вышло = []
    for к in куски:
        длина = к[-1]["конец"] - к[0]["старт"]
        if вышло and (длина < 1.1 or len(к) < 3):
            вышло[-1] += к
        else:
            вышло.append(к)
    return вышло


def ключевое(слова: list) -> str:
    """Слово, которое выносим крупно: самое длинное значимое."""
    пусто = {"который", "которая", "которые", "поэтому", "потому", "просто", "этого",
             "когда", "чтобы", "очень", "будет", "может", "нужно", "здесь", "такое"}
    годные = [w["слово"].strip(" ,.:;!?»«()").lower() for w in слова]
    годные = [w for w in годные if len(w) > 4 and w not in пусто]
    return max(годные, key=len) if годные else ""


def цифра(слова: list) -> str:
    for w in слова:
        т = w["слово"].strip(" ,.:;!?")
        if any(с.isdigit() for с in т):
            return т
    return ""


def главное() -> int:
    сценарий = json.load(open(os.path.join(КОРЕНЬ, "scenario2.json"), encoding="utf-8"))
    голос = json.load(open(os.path.join(КОРЕНЬ, "golos2", "golos.json"), encoding="utf-8"))
    rnd = сл.Random(20261013)
    шоты = []
    кадр = 0
    прошлый_тип = ""
    for сц in сценарий["сцены"]:
        г = голос.get(сц["id"])
        if not г:
            continue
        начало_сцены = кадр
        # На экран идёт текст сценария, а не расшифровка: whisper слышит
        # «кроп -фактор» и «в концу занятия», и этот мусор попадал в кадр.
        куски = фразы(по_сценарию(сц["текст"], г["слова"]))
        графика = сц.get("графика")
        предметы = сц.get("предметы") or []
        if сц.get("слева"):
            предметы = [сц["слева"], сц["справа"]]
        for н, к in enumerate(куски):
            от_сек = к[0]["старт"]
            до_сек = к[-1]["конец"] + ХВОСТ
            длина = max(int(1.0 * FPS), int(round((до_сек - от_сек) * FPS)))
            # выбор типа: по смыслу сцены, без повтора подряд
            слов = len(к)
            знаков = sum(len(w["слово"]) for w in к) + слов
            набор = [т for т in ТИПЫ_ТЕКСТ
                     if not (т == "лесенка" and слов > 6)
                     and not (т == "акцент" and (not ключевое(к) or слов > 9))
                     and not (т == "полоса" and знаков > 70)
                     and not (т == "крупно" and знаков > 95)]
            if графика:
                набор += ТИПЫ_ГРАФИКА * 2
            if предметы:
                набор += ТИПЫ_ПРЕДМЕТ * 2
            if цифра(к):
                набор += ["цифра", "цифра"]
            if н == 0:
                тип = "титр"
            else:
                набор = [т for т in набор if т != прошлый_тип]
                тип = rnd.choice(набор)
            прошлый_тип = тип
            # Даже у текстового кадра есть предмет-компаньон: пустых кадров нет.
            предмет = None
            if предметы:
                п = предметы[(н // 2) % len(предметы)]
                предмет = {"файл": п.get("файл", ""), "имя": п.get("имя") or п.get("титул", ""),
                           "текст": p_текст(п)}
            спутник = СПУТНИКИ[(len(шоты) + н) % len(СПУТНИКИ)]
            шоты.append({
                "id": "%s-%02d" % (сц["id"], н),
                "сцена": сц["id"],
                "вид": сц["вид"],
                "тип": тип,
                "от": начало_сцены + int(round(от_сек * FPS)),
                "кадров": длина,
                "текст": " ".join(w["слово"] for w in к),
                "слова": [{"слово": w["слово"], "старт": round(w["старт"] - от_сек, 3),
                           "конец": round(w["конец"] - от_сек, 3)} for w in к],
                "ключ": ключевое(к),
                "цифра": цифра(к),
                "заголовок": сц.get("заголовок", ""),
                "надзаголовок": сц.get("надзаголовок", ""),
                "графика": графика or "",
                "предмет": предмет,
                "спутник": спутник,
                "слов": len(к), "знаков": знаков,
                "шапка": сц.get("шапка"), "таблица": сц.get("таблица"),
                "от_граф": сц.get("от"), "до_граф": сц.get("до"),
                "первый": н == 0,
            })
        # Длина сцены берётся из озвучки и паузы: монтажный лист второго
        # урока (montazh2.json) считает её так же, поэтому звук не разъедется.
        кадр = начало_сцены + int(round((г["длительность"] + float(сц.get("пауза") or 0.55)) * FPS))
    # Шот тянется ровно до следующего: ни чёрных щелей, ни наложений.
    # Если до следующей фразы остаётся много, ставим перебивку: кадр без
    # слов, на котором работает вещь или график. Дольше 4,6 секунды в этом
    # ролике не живёт ничего.
    ПРЕДЕЛ = int(4.6 * FPS)
    собрано = []
    for i, ш in enumerate(шоты):
        конец = шоты[i + 1]["от"] if i + 1 < len(шоты) else кадр
        длина = max(12, конец - ш["от"])
        if длина > ПРЕДЕЛ + 20:
            своя = max(ПРЕДЕЛ - 20, int((ш["слова"][-1]["конец"] + 0.5) * FPS))
            своя = min(своя, длина - 25)
            ш["кадров"] = своя
            собрано.append(ш)
            пере = dict(ш)
            пере["id"] = ш["id"] + "-p"
            пере["от"] = ш["от"] + своя
            пере["кадров"] = длина - своя
            пере["слова"] = []
            пере["текст"] = ""
            пере["тип"] = (ВИЗУАЛ[i % len(ВИЗУАЛ)] if not ш.get("графика")
                           else ["график_деталь", "график_маска", "график_сбоку"][i % 3])
            собрано.append(пере)
        else:
            ш["кадров"] = длина
            собрано.append(ш)
    шоты = собрано
    for i, ш in enumerate(шоты):
        ш["№"] = i
    всего = кадр
    json.dump({"шоты": шоты, "всего": всего, "блок": сценарий.get("блок", ""),
               "звук": "zvuk_urok.mp3"},
              open(os.path.join(ПУБЛИКА, "shoty.json"), "w", encoding="utf-8"),
              ensure_ascii=False)
    длины = [ш["кадров"] / FPS for ш in шоты]
    print("шотов: %d на %.1f мин" % (len(шоты), всего / FPS / 60))
    print("длина шота: средняя %.1f с, самый длинный %.1f с" % (sum(длины) / len(длины), max(длины)))
    типы = {}
    for ш in шоты:
        типы[ш["тип"]] = типы.get(ш["тип"], 0) + 1
    print("типы:", ", ".join("%s %d" % (к, в) for к, в in sorted(типы.items(), key=lambda x: -x[1])))
    return 0


def p_текст(п: dict) -> str:
    return п.get("текст") or " · ".join(п.get("строки", [])[:2])


if __name__ == "__main__":
    raise SystemExit(главное())
