# -*- coding: utf-8 -*-
"""Аудит контента по десяти пунктам инструкции контент-завода.

Считает то, что можно посчитать, и не притворяется, что умеет мерить вкус.
Оценка от 1 до 100 по каждому пункту, ниже 85 единица идёт в правку.

    python3 audit.py папка-проекта
"""
import re, sys, glob, os, collections

ПЛОЩАДКИ = r"(Instagram|Telegram|ВКонтакте|Дзен|vc\.ru|РБК)"
СТОП_ОБОРОТЫ = re.compile(r"важно отметить|таким образом|в рамках|комплексн\w+ подход|позволяет вам|данная|осуществля", re.I)
# сильным считается зачин с числом, вопросом, конфликтом, обещанием или узнаваемой болью
ЦЕПЛЯЛКИ = re.compile(r"\d|\?|^(Не|Без|Никто|Почему|Как|Что|Сколько|Кто)\b|"
  r"стоит|теряют|ошибк|поздно|пугает|развалит|кажется|выглядит|разница|дешевле|дороже|"
  r"половина|каждый второй|чаще всего|обычно|спорить|развод|проверя|забывают|молчат", re.I)
ДЕЙСТВИЕ = re.compile(r"напиши|пришли|посчитай|сохрани|проверь|отправь|скажи|покажем|подскажем|"
                      r"приходи|заходи|записыва|записаться|попробуй|займи|приезжай|оставь|"
                      r"подпис|перешли|спроси|возьми", re.I)


def единицы(папка):
    для_разбора = []
    for ф in sorted(glob.glob(os.path.join(папка, "NEDELYA_*.md"))) or sorted(glob.glob(os.path.join(папка, "*.md"))):
        s = open(ф, encoding="utf-8").read()
        for ч in re.split(r"\n(?=## )", s):
            z = ч.split("\n")[0]
            if not re.match(r"## " + ПЛОЩАДКИ, z): continue
            m = re.search(r"```\n(.*?)\n```", ч, re.S)
            для_разбора.append({"файл": os.path.basename(ф), "загол": z[3:], "блок": ч,
                                "текст": m.group(1) if m else "",
                                "слайды": re.findall(r"^\*\*(\d+)\.\*\* ([^\n]+)\n> ([^\n]+)", ч, re.M)})
    return для_разбора


def оценить(е, зачины):
    слайды_текст = " ".join(a + " " + b for _, a, b in е["слайды"])
    т = е["текст"] or слайды_текст
    # у серий смысл живёт в кадрах, поэтому в оценку идут и они
    полный = (е["текст"] + " " + слайды_текст).strip()
    первая = (е["слайды"][0][1] if е["слайды"] and not е["текст"] else т.split("\n")[0]) if т else ""
    tg = е["загол"].startswith("Telegram")
    сторис = "истори" in е["загол"]
    карусель = "карусел" in е["загол"]

    о = {}
    # 1. интерес: есть ли в первой строке цифра, вопрос или сильный зачин
    о["интерес"] = 95 if ЦЕПЛЯЛКИ.search(первая[:110]) else 70
    # 2. хук: длина первой строки и её самостоятельность
    статья = bool(re.match(r"(Дзен|vc\.ru|РБК)", е["загол"]))
    предел_хука = 220 if статья else 90
    о["хук"] = 95 if 20 <= len(первая) <= предел_хука else (80 if первая else 40)
    # 3. сценарий: развитие мысли, абзацы или слайды
    блоков = len(е["слайды"]) or len([x for x in т.split("\n\n") if x.strip()])
    о["сценарий"] = 95 if блоков >= 4 else (80 if блоков >= 2 else 60)
    # 4. удержание: нет монотонных длинных абзацев
    длинные = [p for p in т.split("\n\n") if len(p) > 420]
    о["удержание"] = 95 if not длинные else 100 - 12 * len(длинные)
    # 5. визуал: указан промпт и формат
    о["визуал"] = 95 if re.search(r"промпт `[^`]+`", е["блок"]) else 50
    # 6. бренд и правила: тире, противопоставления, иишные обороты, эмодзи
    штраф = (е["блок"].count("—") * 20 + len(re.findall(r", а не ", е["блок"])) * 15 +
             len(СТОП_ОБОРОТЫ.findall(е["блок"])) * 10 +
             len(re.findall(r"[\U0001F300-\U0001FAFF]", е["блок"])) * 20)
    о["бренд"] = max(20, 100 - штраф)
    # 7. шанс в рекомендации: широта темы плюс механика распространения
    широта = 0 if re.search(r"мы |наш|у нас", первая, re.I) else 1
    механика = 1 if re.search(r"как думаете|напишите|опрос|викторин|слайдер|сохраните|перешлите", е["блок"], re.I) else 0
    о["рекомендации"] = 70 + широта * 15 + механика * 15
    # 8. соответствие формату площадки
    if tg and len(т) > 1000: о["формат"] = 40
    elif сторис and not (3 <= len(е["слайды"]) <= 10): о["формат"] = 40
    elif карусель and not (5 <= len(е["слайды"]) <= 10): о["формат"] = 40
    else: о["формат"] = 100
    # 9. попадание в аудиторию: конкретика, цифры, предметность
    # конкретность: цифры плюс предметные детали ниши. В гуманитарных темах
    # цифр мало по природе, и мерить только их значит требовать их зря.
    цифры = len(re.findall(r"\d", полный))
    детали = len(re.findall(r"(?<=[а-яё] )[А-ЯЁ][а-яё]{2,}|«[^»]{2,40}»|\b[а-яё]+(?:ов|ка|ция|ность|тель|щик|ист)\b", полный))
    конкретика = цифры + детали
    о["аудитория"] = 95 if конкретика >= 12 else (85 if конкретика >= 6 else 70)
    # 10. целевое действие
    интерактив = re.search(r"опрос|викторин|квиз|слайдер|стикер", е["блок"], re.I)
    о["действие"] = 95 if (ДЕЙСТВИЕ.search(е["блок"]) or (сторис and интерактив)) else 65
    # штраф за повтор зачина
    if первая and зачины[первая[:40]] > 1:
        о["интерес"] = min(о["интерес"], 60)
    return о


def главное(папка):
    сп = единицы(папка)
    зачины = collections.Counter((е["текст"].split("\n")[0][:40]) for е in сп if е["текст"])
    беды = []
    сумма = collections.Counter(); счёт = 0
    for е in сп:
        о = оценить(е, зачины)
        средн = sum(о.values()) / len(о)
        счёт += 1
        for k, v in о.items(): сумма[k] += v
        слабые = {k: v for k, v in о.items() if v < 85}
        if слабые:
            беды.append((round(средн), е["файл"], е["загол"][:52], слабые))
    print(f"единиц: {счёт}")
    print("средние по пунктам:")
    for k in ["интерес","хук","сценарий","удержание","визуал","бренд","рекомендации","формат","аудитория","действие"]:
        print(f"  {k:14} {сумма[k]/счёт:5.1f}")
    print(f"\nобщая средняя: {sum(сумма.values())/(счёт*10):.1f}")
    print(f"единиц с замечаниями: {len(беды)}")
    for с, ф, з, сл in sorted(беды)[:40]:
        print(f"  {с:3} [{ф[:12]}] {з:52} {сл}")


if __name__ == "__main__":
    главное(sys.argv[1] if len(sys.argv) > 1 else ".")
